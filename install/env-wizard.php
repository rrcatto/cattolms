/** @return array<string,string> */
function readEnv(string $text): array
{
    $values = [];
    foreach (preg_split('/\R/', $text) ?: [] as $line) {
        if (preg_match('/^\s*(?:export\s+)?([A-Z][A-Z0-9_]*)=(.*)$/', $line, $match) !== 1) continue;
        $value = trim($match[2]);
        if ($value !== '' && ($value[0] === '"' || $value[0] === "'")) {
            $quote = $value[0];
            $end = strrpos($value, $quote);
            $value = $end > 0 ? substr($value, 1, $end - 1) : substr($value, 1);
            if ($quote === '"') $value = stripcslashes($value);
        } else {
            $value = trim((string) preg_replace('/\s+#.*$/', '', $value));
        }
        $values[$match[1]] = $value;
    }
    return $values;
}

function quoteEnv(string $value): string
{
    if ($value === '' || preg_match('/^[A-Za-z0-9_.:\/@%+,=-]+$/', $value) === 1) return $value;
    return '"' . str_replace(['\\', '"', '$'], ['\\\\', '\\"', '\\$'], $value) . '"';
}

function ask(string $prompt, string $default, bool $secret, bool $interactive): string
{
