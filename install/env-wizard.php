    echo $prompt . ($shown !== '' ? " [{$shown}]" : '') . ': ';
    if ($secret && $interactive) shell_exec('stty -echo');
    $line = fgets(STDIN);
    if ($secret && $interactive) { shell_exec('stty echo'); echo "\n"; }
    if ($line === false) return $default;
    $line = trim($line);
    return $line === '' ? $default : $line;
}

