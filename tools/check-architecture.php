declare(strict_types=1);

$root = realpath(dirname(__DIR__));
if ($root === false) {
    fwrite(STDERR, "Unable to resolve project root.\n");
    exit(1);
}

$errors = [];
$iterator = new RecursiveIteratorIterator(
    new RecursiveDirectoryIterator($root . '/src', FilesystemIterator::SKIP_DOTS)
);

foreach ($iterator as $file) {
    if (!$file->isFile() || $file->getExtension() !== 'php') {
        continue;
    }

    // Normalised to forward slashes before anything compares it. Every rule below tests the
    // relative path against a literal like 'src/Infrastructure/Persistence/', so on Windows an
    // un-normalised path matched nothing and the check reported the persistence classes and the
    // documented container exceptions as violations - a false failure that grew by one every time
    // a legitimate file was added to those directories.
    $path = strtr($file->getPathname(), '\\', '/');
    $relative = str_replace(strtr($root, '\\', '/') . '/', '', $path);
    $contents = (string) file_get_contents($path);
    $basename = $file->getBasename('.php');

    $isRepository = str_ends_with($basename, 'Repository');
    $isPersistence = str_starts_with($relative, 'src/Infrastructure/Persistence/');

    // Every Database method takes SQL, so naming any of them outside a repository puts a query
    // where the layering says there should not be one.
    $runsSql = static function (string $contents): bool {
        foreach (['executeStatement', 'fetchAllAssociative', 'fetchAssociative', 'fetchOne', 'fetchFirstColumn'] as $method) {
            if (str_contains($contents, '->' . $method . '(')) {
                return true;
            }
        }

        return false;
    };
    if ($runsSql($contents) && !$isRepository && !$isPersistence) {
        $errors[] = $relative . ': SQL execution is outside a Repository or persistence class.';
    }

    // Persistence is Doctrine DBAL behind the Database interface. F3's DB\SQL and its mappers were
    // removed in v0.7, and reintroducing either would put a second connection - and therefore a
    // second transaction - beside the one every repository shares.
    if (preg_match('~^use\\s+DB\\\\SQL;|\\\\?DB\\\\SQL::class|new\\s+\\\\?DB\\\\SQL\\s*\\(~m', $contents) === 1) {
        $errors[] = $relative . ": F3's DB\\SQL was removed; persistence goes through the Database interface.";
    }

    if (str_contains($relative, '/Http/Controller/') && $basename !== 'BaseController'
        && $basename !== 'BaseApiController'
        && !str_ends_with($basename, 'Controller')
    ) {
        $errors[] = $relative . ': controller classes must end with Controller.';
    }
    if (str_ends_with($relative, 'Service.php') && !str_ends_with($basename, 'Service')) {
        $errors[] = $relative . ': service classes must end with Service.';
    }
    if (str_ends_with($relative, 'Repository.php') && !str_ends_with($basename, 'Repository')) {
        $errors[] = $relative . ': repository classes must end with Repository.';
    }


    $containerAllowed = [
        'src/Application/ContainerFactory.php',
        'src/Application/CliBootstrap.php',
        'src/Plugin/PluginManager.php',
    ];
    if (!in_array($relative, $containerAllowed, true)
        && (str_contains($contents, 'Psr\\Container\\ContainerInterface')
            || str_contains($contents, 'DI\\Container'))
    ) {
        $errors[] = $relative . ': PSR-11/PHP-DI container access is restricted to the composition/integration layer.';
    }

    if (str_contains($contents, 'AppContext') || str_contains($contents, 'ServiceFactory')) {
        $errors[] = $relative . ': obsolete AppContext/ServiceFactory dependency construction remains.';
    }

    if ($relative === 'src/Application/App.php' && preg_match('/new\s+[A-Za-z0-9_]+Controller\s*\(/', $contents) === 1) {
        $errors[] = $relative . ': HTTP controllers must be resolved lazily through PSR-11, not constructed during bootstrap.';
    }

}

if ($errors !== []) {
    fwrite(STDERR, "Architecture check failed:\n- " . implode("\n- ", $errors) . "\n");
    exit(1);
}

fwrite(STDOUT, "Architecture check passed.\n");