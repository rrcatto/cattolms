declare(strict_types=1);

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Seed\SeedNamePools;

require dirname(__DIR__) . '/vendor/autoload.php';

$pools = CliBootstrap::boot()['container']->get(SeedNamePools::class);
$published = $pools->publish();

printf(
    "Seed name pools: %d published, %d already present.\n",
    count($published),
    count(SeedNamePools::POOLS) - count($published)
);
foreach ($pools->report() as $row) {
    printf("  %-20s %6d names  %-8s %s\n", $row['pool'], $row['count'], $row['source'], $row['path']);
}
