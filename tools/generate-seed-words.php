#!/usr/bin/env php
<?php

/*
Generated by: Claude Code CLI

Date time: 2026/09/10 08:30 SAST

Version: 0.7

Description:
Grows a seed name pool with pronounceable invented words.

The owner's instruction, 2026/09/10: the generated course and company names repeat far too visibly,
and any words will do to fix it - invented ones included.

They were never actually duplicated. Every name the factory issues is unique, because it remembers
every combination and redraws on a repeat. What they were was *repetitive*: forty-one level words
served two and a half thousand courses, so each one appeared about seventy-five times and every card
read as a variation of the same handful of templates. Uniqueness is a property of the whole string;
what a reader sees is the words in it.

The remedy is more words, and English has more words than this machine has offline. So they are
built rather than found: an onset, a nucleus and a coda per syllable, two or three syllables, which
produces things that read as English without being English. "Brindalcor" is not a word, and as a
course qualifier nobody can tell.

Deterministic from a seed, so running it twice produces the same list and the pool files stay
reviewable in a diff instead of churning on every run.

Usage:
  php tools/generate-seed-words.php <pool-name> <count> [--seed=N] [--dry-run]

Architectural boundary: CLI tool. It reads and writes files under resources/seeds and nothing else.

Changelog:
2026/09/10 08:30 SAST
- Created to grow the pools after generated names were reported as far too repetitive.
*/

declare(strict_types=1);

$pool = $argv[1] ?? '';
$count = (int) ($argv[2] ?? 0);
$seed = 20260910;
$dryRun = false;
foreach ($argv as $argument) {
    if (str_starts_with((string) $argument, '--seed=')) $seed = (int) substr((string) $argument, 7);
    if ($argument === '--dry-run') $dryRun = true;
}

if ($pool === '' || $count < 1) {
    fwrite(STDERR, "Usage: php tools/generate-seed-words.php <pool-name> <count> [--seed=N] [--dry-run]\n");
    exit(1);
}

$path = dirname(__DIR__) . '/resources/seeds/' . $pool . '.txt';
if (!is_file($path)) {
    fwrite(STDERR, 'No such pool: ' . $path . "\n");
    exit(1);
}

// Onsets and codas that actually begin and end English words. A random pile of consonants produces
// strings nobody can pronounce, and an unpronounceable course name is a worse result than a
// repetitive one.
$onsets = ['b','bl','br','c','ch','cl','cr','d','dr','f','fl','fr','g','gl','gr','h','j','k','kn','l','m','n','p','ph','pl','pr','qu','r','s','sc','sh','sk','sl','sm','sn','sp','st','str','sw','t','th','tr','tw','v','w','wh','y','z'];
$nuclei = ['a','e','i','o','u','ai','au','ay','ea','ee','ei','ie','oa','oe','oi','oo','ou','ow','oy','ua','ue'];
$codas  = ['','b','ch','ck','ct','d','ff','ft','g','gh','k','l','ld','lk','ll','lm','lt','m','mb','mp','n','nd','ng','nk','nt','p','ph','pt','r','rd','rk','rl','rm','rn','rt','s','sh','sk','sp','ss','st','t','th','x','z'];

$random = new Random\Randomizer(new Random\Engine\Mt19937($seed));
$pick = static fn(array $list): string => $list[$random->getInt(0, count($list) - 1)];

// Simple vowels most of the time. Stacking diphthongs across every syllable produced things like
// "Poumsoyffnak", which is a string rather than a word - the point is that it should read as if it
// could be English.
$simpleOnsets = ['b','c','d','f','g','k','l','m','n','p','r','s','t','v','z','th','sh','ch'];
$simpleNuclei = ['a','e','i','o','u'];

$syllable = static function (bool $first) use ($random, $pick, $onsets, $simpleOnsets, $nuclei, $simpleNuclei, $codas): string {
    // A cluster is allowed to open a word; inside one it reads as a collision of two words.
    $onset = $first ? $pick($onsets) : $pick($simpleOnsets);
    $nucleus = ($first && $random->getInt(1, 100) <= 35) ? $pick($nuclei) : $pick($simpleNuclei);
    // A closed syllable in the middle of a word stacks consonants against the next onset, so only
    // the last syllable is freely closed.
    $coda = $random->getInt(1, 100) <= 45 ? $pick($codas) : '';

    return $onset . $nucleus . $coda;
};

// Everything already in the pool, so a generated word never collides with a real one or with
// itself. Comments and blank lines are preserved by appending rather than rewriting.
$existing = [];
foreach (file($path, FILE_IGNORE_NEW_LINES) ?: [] as $line) {
    $trimmed = trim($line);
    if ($trimmed === '' || str_starts_with($trimmed, '#')) continue;
    $existing[mb_strtolower($trimmed)] = true;
}
$before = count($existing);

$made = [];
$attempts = 0;
while (count($made) < $count && $attempts < $count * 200) {
    $attempts++;
    $word = '';
    $syllables = $random->getInt(2, 3);
    for ($position = 0; $position < $syllables; $position++) {
        $word .= $syllable($position === 0);
    }
    // Doubled vowels across a syllable seam and four-consonant runs both read as noise.
    if (preg_match('/[aeiou]{3}|[bcdfghjklmnpqrstvwxz]{3}/i', $word) === 1) continue;
    if (mb_strlen($word) < 5 || mb_strlen($word) > 12) continue;

    $word = mb_strtoupper(mb_substr($word, 0, 1)) . mb_substr($word, 1);
    $key = mb_strtolower($word);
    if (isset($existing[$key])) continue;

    $existing[$key] = true;
    $made[] = $word;
}

if (count($made) < $count) {
    fwrite(STDERR, 'Only produced ' . count($made) . ' of ' . $count . " distinct words.\n");
    exit(1);
}

sort($made);
if ($dryRun) {
    fwrite(STDOUT, implode("\n", array_slice($made, 0, 30)) . "\n... (" . count($made) . " words)\n");
    exit(0);
}

$body = "\n# Invented words, generated 2026/09/10 by tools/generate-seed-words.php --seed=" . $seed . ".\n"
    . "# They exist so no single word dominates a page of generated names. Edit or delete freely:\n"
    . "# this file is the pool, and the pool is whatever it says.\n"
    . implode("\n", $made) . "\n";

// Checked, because file_put_contents warns and returns false rather than throwing. Reported on the
// strength of the words it produced rather than the bytes it wrote, this tool prints six successes
// and changes nothing - which is what it did the first time it was run.
if (file_put_contents($path, $body, FILE_APPEND) === false) {
    fwrite(STDERR, 'Unable to write ' . $path . ". Is resources/seeds writable by this user?\n");
    exit(1);
}
fwrite(STDOUT, $pool . ': ' . $before . ' -> ' . ($before + count($made)) . " entries\n");
