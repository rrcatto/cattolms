<?php

/*
Generated by: Claude Code CLI

Date time: 2026/09/08 19:52 SAST

Version: 0.7

Description:
Provides the Catto Learning command-line benchmark dataset utility used for development,
validation, diagnostics or release management. It fills the paginated tables with a large SEED
batch so pagination and its queries can be measured at the volume they are designed for.

Why this exists alongside the Seed Database.

`composer` and the Administration Seed Database generate a *realistic* graph: a volume of 100,000
is a budget of 100,000 rows spread across roughly thirty tables, so it yields about 1,300 people
and 2,500 enrolments. That is exactly right for exercising the interface, and useless for measuring
pagination - a list of 1,300 rows is fast however it is written, and a deep OFFSET on it costs
nothing. Even the 500,000 ceiling produces only 6,400 people.

This tool does the opposite. It writes a deliberately shallow, wide batch: one hundred thousand rows
in each of the tables the paginated lists actually read, and nothing underneath them. There are no
modules, no assessment questions and no progress, because none of those are on a list screen.

What it is not: it is not a second seed generator, and nothing but the benchmark harness should read
its rows. It writes ordinary SEED-universe data, registers the batch in `seed_data` exactly as the
generator does, and is therefore removed by the ordinary Seed Database cleanup in Administration or
by `--remove` here. The cross-universe triggers are left enabled throughout: data that had to have
the platform's own invariants switched off to be created is not data worth benchmarking against.

Rows are inserted with explicit identifiers taken from a reserved sequence range rather than being
read back, so every cross-reference is arithmetic and the whole batch is one `INSERT ... SELECT`
per table rather than a hundred thousand statements.

Usage:
  php tools/seed-benchmark-dataset.php [--people=100000] [--companies=100000] [--courses=20000]
                                       [--enrolments=100000] [--activity=100000] [--credits=100000]
                                       [--requests=100000]
  php tools/seed-benchmark-dataset.php --list
  php tools/seed-benchmark-dataset.php --remove=<seed token>

Changelog:
2026/09/08 19:52 SAST
- Writes through the Database interface rather than F3's DB\SQL.
2026/09/04 21:00 SAST
- Created for the v0.6 Pagination 2.0 benchmark.
*/

declare(strict_types=1);

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Infrastructure\Persistence\SeedRepository;
use CattoLearning\Support\Env;
use CattoLearning\Support\Uuid;

require dirname(__DIR__) . '/vendor/autoload.php';

$boot = CliBootstrap::boot();
$container = $boot['container'];
/** @var Database $db */
$db = $container->get(Database::class);
$seeds = $container->get(SeedRepository::class);

// This writes six-figure row counts and is a development instrument, not an operational one.
// A production database has no business holding a hundred thousand benchmark people.
if (Env::string('APP_ENV', 'production') !== 'development') {
    fwrite(STDERR, "Refusing to run: APP_ENV is not development.\n");
    exit(1);
}

/** @return array<string,string> */
$options = static function (array $argv): array {
    $parsed = [];
    foreach (array_slice($argv, 1) as $argument) {
        if (preg_match('/^--([a-z-]+)(?:=(.*))?$/', $argument, $match) === 1) {
            $parsed[$match[1]] = $match[2] ?? '1';
        }
    }

    return $parsed;
};
$args = $options($argv);

if (isset($args['list'])) {
    foreach ($seeds->sets() as $set) {
        printf(
            "%s  %-40s %9d rows  %s\n",
            (string) $set['seed_token'],
            substr((string) $set['description'], 0, 40),
            (int) $set['initial_record_count'],
            ($set['cleaned_at'] ?? null) === null ? 'present' : 'cleaned'
        );
    }
    exit(0);
}

if (isset($args['remove'])) {
    $token = trim($args['remove']);
    // Checked here rather than trusted, because the value is interpolated into a token comparison
    // against every seed-aware table. Uuid has no validator of its own; the shape is the check.
    if (preg_match('/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i', $token) !== 1) {
        fwrite(STDERR, "Not a seed token: " . $token . "\n");
        exit(1);
    }
    // deleteSet() returns the same cleanup summary the Administration screen shows, so it is
    // printed per table rather than reduced to one number that would hide a table it skipped.
    $summary = $seeds->deleteSet($token);
    $seeds->markCleaned($token, ['source' => 'seed-benchmark-dataset']);
    foreach ((array) ($summary['tables'] ?? []) as $table => $count) {
        printf("  %-22s %9d rows\n", (string) $table, (int) $count);
    }
    printf("Removed %d rows for %s.\n", (int) ($summary['records'] ?? 0), $token);
    exit(0);
}

$volume = static function (string $name, int $default) use ($args): int {
    $value = $args[$name] ?? null;

    return $value === null ? $default : max(0, (int) $value);
};

$people = $volume('people', 100000);
$companies = $volume('companies', 100000);
$courses = $volume('courses', 20000);
$enrolments = $volume('enrolments', 100000);
$activity = $volume('activity', 100000);
$credits = $volume('credits', 100000);
$requests = $volume('requests', 100000);

if ($people < 1 || $companies < 1 || $courses < 1) {
    fwrite(STDERR, "People, companies and courses must all be at least 1.\n");
    exit(1);
}

// One enrolment per user/course pair is all the schema permits. Each row takes the next person in
// turn, so the pairs are unique as long as no more rows are asked for than there are people.
foreach (['enrolments' => $enrolments, 'requests' => $requests] as $name => $count) {
    if ($count > $people) {
        fwrite(STDERR, sprintf("%s cannot exceed people (%d), or two rows would share a pair.\n", $name, $people));
        exit(1);
    }
}

$token = Uuid::v4();
$short = substr(str_replace('-', '', $token), 0, 8);

/**
 * Reserves a contiguous block of identifiers and returns the first of them.
 *
 * Taking the ids up front is what lets every table below be one statement: a course knows which
 * user owns it by arithmetic rather than by reading anything back.
 */
$reserve = static function (string $sequence, int $count) use ($db): int {
    $first = (int) ($db->fetchAllAssociative('SELECT nextval(:sequence) AS value', ['sequence' => $sequence])[0]['value'] ?? 0);
    if ($count > 1) {
        $db->fetchAllAssociative('SELECT setval(:sequence, :last)', ['sequence' => $sequence, 'last' => $first + $count - 1]);
    }

    return $first;
};

$studentRoleId = (int) ($seeds->roleIdsByKey()['STUDENT'] ?? 0);
if ($studentRoleId < 1) {
    fwrite(STDERR, "The STUDENT role is missing; run composer migrate first.\n");
    exit(1);
}

$started = microtime(true);
$counts = [];

$run = static function (string $table, string $sql, array $params, int $count) use ($db, &$counts): void {
    if ($count < 1) {
        return;
    }
    $at = microtime(true);
    $db->executeStatement($sql, $params);
    $counts[$table] = $count;
    printf("  %-22s %9d rows  %6.2fs\n", $table, $count, microtime(true) - $at);
};

printf("Writing benchmark batch %s\n", $token);

$companyBase = $reserve('companies_id_seq', $companies);
$run('companies', "
    INSERT INTO companies (id, public_id, name, domain, status, is_system, company_type, seed_token)
    SELECT :base + g - 1,
           gen_random_uuid(),
           'Benchmark Company ' || lpad(g::text, 7, '0'),
           'bench-' || :short || '-' || g || '.seed.test',
           'active', FALSE, 'client', :token::uuid
    FROM generate_series(1, :count) g
", ['base' => $companyBase, 'short' => $short, 'token' => $token, 'count' => $companies], $companies);

$userBase = $reserve('users_id_seq', $people);
$run('users', "
    INSERT INTO users (id, public_id, display_name, first_name, last_name, status, created_at, updated_at, seed_token)
    SELECT :base + g - 1,
           gen_random_uuid(),
           'Bench Person ' || lpad(g::text, 7, '0'),
           'Bench' || lpad(g::text, 7, '0'),
           'Person' || lpad((g % 997)::text, 3, '0'),
           'active',
           now() - (g || ' minutes')::interval,
           now() - (g || ' minutes')::interval,
           :token::uuid
    FROM generate_series(1, :count) g
", ['base' => $userBase, 'token' => $token, 'count' => $people], $people);

$run('user_emails', "
    INSERT INTO user_emails (user_id, email, is_primary, verified_at, seed_token)
    SELECT :base + g - 1, 'bench-' || :short || '-' || g || '@seed.test', TRUE, now(), :token::uuid
    FROM generate_series(1, :count) g
", ['base' => $userBase, 'short' => $short, 'token' => $token, 'count' => $people], $people);

$run('user_roles', "
    INSERT INTO user_roles (user_id, role_id, seed_token)
    SELECT :base + g - 1, :role, :token::uuid
    FROM generate_series(1, :count) g
", ['base' => $userBase, 'role' => $studentRoleId, 'token' => $token, 'count' => $people], $people);

// Membership is deliberately skewed. Every fifth person joins the first benchmark company, so one
// company holds a fifth of the batch and the company-scoped lists are as deep as the platform-wide
// ones. Spread evenly instead, every company would hold a page or less and the company screens
// would be measured on data that never exercises them.
$run('company_users', "
    INSERT INTO company_users (company_id, user_id, company_role, status, seed_token)
    SELECT CASE WHEN g % 5 = 0 THEN :company_base ELSE :company_base + (g % :companies) END,
           :user_base + g - 1,
           'member', 'active', :token::uuid
    FROM generate_series(1, :count) g
", [
    'company_base' => $companyBase, 'companies' => $companies, 'user_base' => $userBase,
    'token' => $token, 'count' => $people,
], $people);

$courseBase = $reserve('courses_id_seq', $courses);
$run('courses', "
    INSERT INTO courses (id, public_id, slug, title, summary, status, owner_user_id, owner_company_id,
                         created_by_user_id, updated_by_user_id, published_at, created_at, updated_at, seed_token)
    SELECT :base + g - 1,
           gen_random_uuid(),
           'bench-' || :short || '-course-' || g,
           'Benchmark Course ' || lpad((g % 4999)::text, 6, '0'),
           'A benchmark course.',
           CASE WHEN g % 3 = 0 THEN 'draft' ELSE 'published' END,
           :user_base + (g % :people),
           :company_base + (g % :companies),
           :user_base + (g % :people),
           :user_base + (g % :people),
           CASE WHEN g % 3 = 0 THEN NULL ELSE now() - (g || ' hours')::interval END,
           now() - (g || ' hours')::interval,
           now() - (g || ' hours')::interval,
           :token::uuid
    FROM generate_series(1, :count) g
", [
    'base' => $courseBase, 'short' => $short, 'user_base' => $userBase, 'people' => $people,
    'company_base' => $companyBase, 'companies' => $companies, 'token' => $token, 'count' => $courses,
], $courses);

// The title repeats every 4999 courses on purpose. Ordering by a title alone is not a total order,
// and a benchmark dataset in which every title is unique would never show it.
//
// Enrolments and requests are spread across the courses rather than piled onto one. The first
// attempt divided the row number by the number of people, which is zero for every row when the two
// counts are equal - so all hundred thousand enrolments landed on a single course, and the
// Administration course list was measured counting a hundred thousand learners for one row. That is
// a real cost for a genuinely enormous course and a meaningless one to report as the list's. Every
// tenth row still goes to the first course, so one popular course exists and the aggregate is
// exercised at a realistic ten thousand rather than at everything.

$run('course_enrolments', "
    INSERT INTO course_enrolments (public_id, user_id, course_id, status, access_period_seconds,
                                   assigned_at, started_at, completed_at, created_at, updated_at, seed_token)
    SELECT gen_random_uuid(),
           :user_base + ((g - 1) % :people),
           CASE WHEN g % 10 = 0 THEN :course_base ELSE :course_base + ((g - 1) % :courses) END,
           (ARRAY['assigned','active','completed'])[1 + (g % 3)],
           31536000,
           now() - (g || ' minutes')::interval,
           CASE WHEN g % 3 = 0 THEN NULL ELSE now() - (g || ' minutes')::interval END,
           CASE WHEN g % 3 = 2 THEN now() - (g || ' minutes')::interval ELSE NULL END,
           now() - (g || ' minutes')::interval,
           now() - (g || ' minutes')::interval,
           :token::uuid
    FROM generate_series(1, :count) g
", [
    'user_base' => $userBase, 'people' => $people, 'course_base' => $courseBase,
    'courses' => $courses, 'token' => $token, 'count' => $enrolments,
], $enrolments);

$run('course_requests', "
    INSERT INTO course_requests (public_id, user_id, company_id, course_id, access_period_seconds,
                                 status, requested_at, seed_token)
    SELECT gen_random_uuid(),
           :user_base + ((g - 1) % :people),
           CASE WHEN g % 5 = 0 THEN :company_base ELSE :company_base + (g % :companies) END,
           CASE WHEN g % 10 = 0 THEN :course_base ELSE :course_base + ((g - 1) % :courses) END,
           31536000,
           (ARRAY['pending','approved','rejected','fulfilled','cancelled'])[1 + (g % 5)],
           now() - (g || ' minutes')::interval,
           :token::uuid
    FROM generate_series(1, :count) g
", [
    'user_base' => $userBase, 'people' => $people, 'company_base' => $companyBase,
    'companies' => $companies, 'course_base' => $courseBase, 'courses' => $courses,
    'token' => $token, 'count' => $requests,
], $requests);

$run('course_credits', "
    INSERT INTO course_credits (public_id, company_id, course_id, access_period_seconds, quantity,
                                source_type, note, created_at, seed_token)
    SELECT gen_random_uuid(),
           CASE WHEN g % 5 = 0 THEN :company_base ELSE :company_base + (g % :companies) END,
           :course_base + (g % :courses),
           31536000, 1 + (g % 20), 'administrator', 'Benchmark credit.',
           now() - (g || ' minutes')::interval,
           :token::uuid
    FROM generate_series(1, :count) g
", [
    'company_base' => $companyBase, 'companies' => $companies, 'course_base' => $courseBase,
    'courses' => $courses, 'token' => $token, 'count' => $credits,
], $credits);

$run('audit_log', "
    INSERT INTO audit_log (event_key, user_id, metadata, created_at, seed_token)
    SELECT (ARRAY['auth.login','course.enrolment.created','company.person.updated','course.published'])[1 + (g % 4)],
           :user_base + (g % :people),
           jsonb_build_object('course_id', (:course_base + (g % :courses))::text, 'benchmark', TRUE),
           now() - (g || ' seconds')::interval,
           :token::uuid
    FROM generate_series(1, :count) g
", [
    'user_base' => $userBase, 'people' => $people, 'course_base' => $courseBase,
    'courses' => $courses, 'token' => $token, 'count' => $activity,
], $activity);

$elapsed = microtime(true) - $started;
$total = array_sum($counts);

$seedDataId = $seeds->recordSet(
    $token,
    'Pagination 2.0 benchmark dataset',
    $total,
    $total,
    $elapsed,
    null
);
$seeds->recordSetTables($seedDataId, $counts);

// Statistics are what the planner chooses an index from. Without this the tables look empty to it
// and the first benchmark run measures a plan built for the data that was there yesterday.
foreach (array_keys($counts) as $table) {
    $db->executeStatement('ANALYZE ' . $table);
}

printf("\nWrote %d rows in %.1fs. Seed token %s\n", $total, $elapsed, $token);
printf("Remove with: php tools/seed-benchmark-dataset.php --remove=%s\n", $token);
