#!/usr/bin/env php
<?php

/*
Generated by: Claude Code CLI

Date time: 2026/09/06 17:00 SAST

Version: 0.6

Description:
Provides the Catto Learning command-line seed generation utility used for development, validation,
diagnostics or release management. It generates a Seed Database set without going through the
Administration screen, which needs a signed-in administrator.

Why this exists.

`composer smoke:install` resets the database, and a reset destroys every seed set with it. That is
correct - it is what a reset is - but it leaves the operator with nothing to look at and no way to
rebuild it without signing in first. Rebuilding test data should be one command, not a login and a
form, so that resetting during development is cheap rather than something to be avoided.

It also creates the platform administrator if one does not exist, because a reset removes that too
and a set has to be generated by somebody.

Usage:
  php tools/seed-generate.php [volume] [description]

Changelog:
2026/09/06 17:00 SAST
- Created after a database reset during development destroyed the owner's test data with no
  one-step way to rebuild it.
*/

declare(strict_types=1);

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Auth\RoleCatalog;
use CattoLearning\Infrastructure\Persistence\RoleRepository;
use CattoLearning\Infrastructure\Persistence\UserRepository;
use CattoLearning\Seed\SeedDatabaseService;
use CattoLearning\Seed\SeedGenerationPlan;
use CattoLearning\Support\Env;

require dirname(__DIR__) . '/vendor/autoload.php';

if (Env::string('APP_ENV', 'production') !== 'development') {
    fwrite(STDERR, "Refusing to run: APP_ENV is not development.\n");
    exit(1);
}

$container = CliBootstrap::boot()['container'];
$users = $container->get(UserRepository::class);
$roles = $container->get(RoleRepository::class);

$email = Env::string('APP_ADMIN_EMAIL', 'admin@catto.test');
$administrator = $users->findByVerifiedEmail($email);
if ($administrator === null) {
    $administrator = $users->createWithPrimaryEmail($email);
    $roles->assign((int) $administrator['id'], RoleCatalog::ADMIN);
    $roles->assign((int) $administrator['id'], RoleCatalog::STUDENT);
    printf("Created the platform administrator %s.\n", $email);
}

$volume = SeedGenerationPlan::normaliseVolume($argv[1] ?? SeedGenerationPlan::DEFAULT_VOLUME);
$description = trim((string) ($argv[2] ?? 'Development test data'));
$plan = SeedGenerationPlan::forVolume($volume);

printf(
    "Generating %s rows: %s people, %s companies, %s courses, %s enrolments.\n",
    number_format($volume),
    number_format($plan->users),
    number_format($plan->companies),
    number_format($plan->courses),
    number_format($plan->enrolments)
);

$startedAt = microtime(true);
$result = $container->get(SeedDatabaseService::class)->generate($volume, $description, (int) $administrator['id']);


printf(
    "Wrote %s rows in %.1fs.\n",
    number_format((int) array_sum((array) ($result['tables'] ?? []))),
    microtime(true) - $startedAt
);
