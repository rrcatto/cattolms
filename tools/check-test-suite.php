<?php

/*
Generated by: Claude Code CLI

Date time: 2026/08/24 20:30 SAST

Version: 0.5.8.2

Description:
Proves the test suites can actually start, without starting them.

This exists because of a defect that reached the VPS. Two Seed integration classes each declared a
helper named `count()`, colliding with the final `PHPUnit\Framework\TestCase::count()`. PHP rejects
that when the class is *declared*, so `php -l` passed, the Unit and Architecture suites passed
because they never loaded those files, and the Integration suite plus `composer qa` died with a
fatal before one test ran.

The natural instinct is to guard this with a PHPUnit test. That does not work, and it is worth
recording why: PHPUnit builds every suite named in phpunit.xml before executing anything, even when
`--testsuite` narrows what will run. One unloadable class therefore kills the run during suite
construction, before any test - including a guard - can execute. A PHPUnit test cannot protect
against a class that stops PHPUnit from starting.

So this is a source scan rather than a test. It never loads a class, which is precisely why it
survives a file that cannot be loaded, and it runs inside `composer qa` alongside the other
tools/check-*.php gates.

Companion command, in the pre-handoff sequence in docs/OPERATIONS.md:

    php vendor/bin/phpunit --list-tests --testsuite Integration

Test files present and zero tests discovered is a failure, not an empty directory.

Changelog:
2026/08/24 20:30 SAST
- Resolve the Composer autoloader from the code root or its parent, and fail with a diagnostic rather than a fatal when neither exists.
2026/08/24 17:45 SAST
- Created after the final-method collision reached the VPS.
*/

declare(strict_types=1);

$root = dirname(__DIR__);

// The autoloader is looked for in the code root first, then its parent. A workarea checkout keeps
// vendor/ outside the code root, and a check that dies with a fatal on a legitimate layout is a
// poor gate - especially this one, whose whole purpose is to turn a fatal into a diagnostic.
$autoloader = null;
foreach ([$root . '/vendor/autoload.php', dirname($root) . '/vendor/autoload.php'] as $candidate) {
    if (is_file($candidate)) {
        $autoloader = $candidate;
        break;
    }
}
if ($autoloader === null) {
    fwrite(STDERR, "Test suite check failed: no Composer autoloader found in:\n"
        . "- " . $root . "/vendor\n"
        . "- " . dirname($root) . "/vendor\n"
        . "Run composer install first.\n");
    exit(1);
}
require $autoloader;

if (!class_exists(PHPUnit\Framework\TestCase::class)) {
    // Passing without PHPUnit would be a vacuous pass, which is worse than no check at all.
    fwrite(STDERR, "Test suite check failed: PHPUnit is not installed, so final-method collisions cannot be detected.\n");
    exit(1);
}

$errors = [];

/**
 * Method names PHPUnit marks final.
 *
 * Read from the framework rather than hard-coded, so a PHPUnit upgrade that finalises another
 * method is caught the first time this runs instead of the first time QA runs.
 *
 * @return list<string>
 */
$finalFrameworkMethods = static function (): array {
    $final = [];
    foreach ([PHPUnit\Framework\TestCase::class, PHPUnit\Framework\Assert::class] as $frameworkClass) {
        foreach ((new ReflectionClass($frameworkClass))->getMethods() as $method) {
            if ($method->isFinal() && !$method->isPrivate()) {
                $final[] = $method->getName();
            }
        }
    }

    return array_values(array_unique($final));
};

/** @return list<string> every PHP file under tests/ */
$testFiles = static function (string $root): array {
    $files = [];
    $directory = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . '/tests'));
    foreach ($directory as $file) {
        if ($file->isDir() || $file->getExtension() !== 'php') {
            continue;
        }
        $files[] = strtr($file->getPathname(), '\\', '/');
    }
    sort($files);

    return $files;
};

$final = $finalFrameworkMethods();
if ($final === []) {
    $errors[] = 'PHPUnit exposes no final methods, so this check would prove nothing. Verify the PHPUnit version.';
}

$files = $testFiles($root);
if ($files === []) {
    $errors[] = 'No test files were found at all.';
}

foreach ($files as $file) {
    $source = (string) file_get_contents($file);
    $relative = str_replace(strtr($root, '\\', '/') . '/', '', $file);

    // Only a class inheriting from TestCase can collide. The collaborators under tests/Support are
    // ordinary classes and may name a method whatever suits them - __construct being the obvious
    // one.
    if (preg_match('/\bextends\s+TestCase\b/', $source) !== 1) {
        continue;
    }

    preg_match_all('/(?:public|protected|private)\s+(?:static\s+)?function\s+(\w+)\s*\(/', $source, $matches);
    foreach (array_unique($matches[1]) as $method) {
        if (in_array($method, $final, true)) {
            $errors[] = $relative . ': declares ' . $method . '(), which PHPUnit marks final on TestCase. '
                . 'PHP cannot declare this class, so the whole suite fails to start.';
        }
    }
}

// A suite holding test files but no discoverable test method is the exact symptom the collision
// produced, and it reads like "nothing to run" rather than "nothing could be loaded".
foreach (['Unit', 'Architecture', 'Integration'] as $suite) {
    $suiteFiles = glob($root . '/tests/' . $suite . '/*Test.php') ?: [];
    if ($suiteFiles === []) {
        $errors[] = 'The ' . $suite . ' suite contains no test files.';
        continue;
    }

    $methods = 0;
    foreach ($suiteFiles as $file) {
        $source = (string) file_get_contents($file);
        $methods += preg_match_all('/public\s+function\s+test\w*\s*\(/', $source);
    }
    if ($methods === 0) {
        $errors[] = 'The ' . $suite . ' suite has ' . count($suiteFiles)
            . ' test file(s) but no discoverable test method.';
    }
}

if ($errors !== []) {
    fwrite(STDERR, "Test suite check failed:\n- " . implode("\n- ", $errors) . "\n");
    exit(1);
}

echo 'Test suite check passed: ' . count($files) . " test files declare no final PHPUnit method and every suite is populated.\n";
