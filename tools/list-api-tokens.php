declare(strict_types=1);

use CattoLearning\Application\CliBootstrap;

require dirname(__DIR__) . '/vendor/autoload.php';

$options = getopt('', ['email:']);
$email = trim((string) ($options['email'] ?? ''));
if ($email === '') {
    fwrite(STDERR, "Usage: php tools/list-api-tokens.php --email=user@example.com\n");
    exit(1);
}

$boot = CliBootstrap::boot();
$tokens = $boot['context']->apiTokens->listForVerifiedEmail($email);
if ($tokens === []) {
    fwrite(STDOUT, "No API tokens found.\n");
    exit(0);
}

foreach ($tokens as $token) {
    fwrite(STDOUT, sprintf(
        "%s\t%s\t%s\tcreated=%s\texpires=%s\trevoked=%s\n",
        (string) $token['public_id'],
        (string) $token['name'],
        implode(',', (array) $token['scopes']),
        (string) ($token['created_at'] ?? '-'),
        (string) ($token['expires_at'] ?? 'never'),
        (string) ($token['revoked_at'] ?? 'no')
    ));
}