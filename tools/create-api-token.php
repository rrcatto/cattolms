declare(strict_types=1);

use CattoLearning\Application\CliBootstrap;

require dirname(__DIR__) . '/vendor/autoload.php';

$options = getopt('', ['email:', 'name:', 'scopes:', 'ttl-days::']);
$email = trim((string) ($options['email'] ?? ''));
$name = trim((string) ($options['name'] ?? ''));
$scopes = array_values(array_filter(array_map(
    'trim',
    explode(',', (string) ($options['scopes'] ?? ''))
)));
$ttlDays = isset($options['ttl-days']) ? max(1, (int) $options['ttl-days']) : null;

if ($email === '' || $name === '' || $scopes === []) {
    fwrite(STDERR, "Usage: php tools/create-api-token.php --email=user@example.com --name=AI --scopes=profile:read,courses:read [--ttl-days=90]\n");
    exit(1);
}

$boot = CliBootstrap::boot();
$result = $boot['container']->get(\CattoLearning\Api\ApiTokenService::class)->createForVerifiedEmail(
    $email,
    $name,
    $scopes,
    $ttlDays === null ? null : $ttlDays * 86400
);

fwrite(STDOUT, "API token created. Store it securely; it will not be shown again.\n\n");
fwrite(STDOUT, $result['token'] . "\n");
fwrite(STDOUT, "\nToken ID: " . $result['public_id'] . "\n");
fwrite(STDOUT, "Scopes: " . implode(', ', $result['scopes']) . "\n");