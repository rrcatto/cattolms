$settingsIterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . '/src', FilesystemIterator::SKIP_DOTS));
foreach ($settingsIterator as $settingsFile) {
    if (!$settingsFile->isFile() || strtolower($settingsFile->getExtension()) !== 'php') {
        continue;
    }
    $path = $settingsFile->getPathname();
    $relative = relativePath($root, $path);
    if ($relative === 'src/Configuration/RuntimeSettings.php') {
        continue;
    }
    $source = (string) file_get_contents($path);
    if (str_contains($source, "Env::string('APP_NAME'")) {
        $errors[] = $relative . ': must resolve the platform name through RuntimeSettings rather than APP_NAME directly.';
    }
    foreach (['MAILER_DSN', 'MAIL_FROM_ADDRESS', 'MAIL_FROM_NAME', 'MAIL_REPLY_TO'] as $mailEnv) {
        if (str_contains($source, $mailEnv)) {
            $errors[] = $relative . ': must resolve ' . $mailEnv . ' through RuntimeSettings.';
        }
    }
}

