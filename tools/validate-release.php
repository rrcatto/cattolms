    if (!$phpFile->isFile() || strtolower($phpFile->getExtension()) !== 'php' || str_contains($phpFile->getPathname(), DIRECTORY_SEPARATOR . 'vendor' . DIRECTORY_SEPARATOR)) {
        continue;
    }
    $phpSource = (string) file_get_contents($phpFile->getPathname());
    foreach (['Generated by: ChatGPT', 'Version: 0.5.4', 'Description:', 'Changelog:'] as $headerToken) {
        if (!str_contains($phpSource, $headerToken)) {
            $errors[] = 'PHP metadata header missing ' . $headerToken . ' in ' . relativePath($root, $phpFile->getPathname());
            break;
        }
    }
    if (preg_match('/Date time:\s+\d{4}\/\d{2}\/\d{2}\s+\d{2}:\d{2}\s+SAST/', $phpSource) !== 1) {
        $errors[] = 'PHP metadata header must contain a YYYY/MM/DD HH:MM SAST timestamp in ' . relativePath($root, $phpFile->getPathname());
    }
}

