<?php

/*
Generated by: Claude Code CLI

Date time: 2026/09/10 06:20 SAST

Version: 0.7

Description:
Installs every theme the code root ships into the instance, and publishes its browser assets.

The themes under `themes/` in the code root are the ones this platform ships. They are versioned
with the code, reviewed with the code, and this is what puts them on an instance - so a fresh
install arrives with the interface the platform was designed against rather than with one theme and
an instruction to upload the rest by hand.

An already-installed theme is left exactly as it is. An installed theme is an immutable release, and
reinstalling one at the same version would produce two builds wearing one version number. Its assets
are republished regardless, because the public web root is a different tree and a deployment that
overlays one and not the other leaves the theme installed and its stylesheet missing.

`--force` replaces installed themes with the bundled copies at the same version. That is a
development convenience for a local rebuild, not an upgrade path: on an instance whose themes are
accepted releases it discards them.

Architectural boundary: CLI tool. It bootstraps the container and calls ThemeManager; every decision
about what may be written lives there.

Changelog:
2026/09/10 06:20 SAST
- Created when the four installed themes joined Factory Reset in the code root.
*/

declare(strict_types=1);

use CattoLearning\Application\CliBootstrap;
use CattoLearning\View\ThemeManager;

require dirname(__DIR__) . '/vendor/autoload.php';

$force = in_array('--force', $argv, true);

$container = CliBootstrap::boot()['container'];
/** @var ThemeManager $themes */
$themes = $container->get(ThemeManager::class);

$slugs = $themes->bundledThemeSlugs();
if ($slugs === []) {
    fwrite(STDERR, "No bundled themes were found in the code root.\n");
    exit(1);
}

$failed = 0;
foreach ($slugs as $slug) {
    try {
        $outcome = $themes->installBundledTheme($slug, $force);
        fwrite(STDOUT, sprintf("  %-24s %s\n", $slug, $outcome));
    } catch (\Throwable $e) {
        // One theme that will not install must not stop the others. A child whose parent failed is
        // the common case, and reporting all of them at once is more use than stopping at the first.
        $failed++;
        fwrite(STDERR, sprintf("  %-24s FAILED: %s\n", $slug, $e->getMessage()));
    }
}

// The registry is a rebuildable index of the filesystem, so it is rebuilt after the filesystem
// changes rather than maintained alongside it.
$themes->resyncRegistry();

fwrite(STDOUT, 'Bundled themes: ' . (count($slugs) - $failed) . ' of ' . count($slugs) . " in place.\n");

exit($failed === 0 ? 0 : 1);
