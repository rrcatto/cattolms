<?php

/*
Generated by: Claude Code CLI

Date time: 2026/09/10 06:20 SAST

Version: 0.7

Description:
Builds an installable package for every theme the code root ships, into extras/themes/.

The unpacked tree under `themes/` is the source of truth: it is what gets reviewed, diffed and
installed by `composer themes:install`. The zip is the artifact for the other route onto an
instance - Administration, Themes, Install a theme package - which is how a theme reaches a server
that is not running this checkout.

Building them rather than committing them by hand is the point. A zip assembled once and edited
never again drifts from the tree beside it, and the two then disagree about what a version contains.

Packages are named `<slug>-v<version>.zip` from the manifest, which is the shape `validate-release`
requires and the shape the installer expects.

Architectural boundary: CLI tool. It reads the code root and writes extras/themes; it touches no
instance state and no database.

Changelog:
2026/09/10 06:20 SAST
- Created when the four installed themes joined Factory Reset in the code root.
*/

declare(strict_types=1);

$root = dirname(__DIR__);
$themesRoot = $root . '/themes';
$outputRoot = $root . '/extras/themes';

if (!is_dir($outputRoot) && !mkdir($outputRoot, 0775, true) && !is_dir($outputRoot)) {
    fwrite(STDERR, "Unable to create extras/themes.\n");
    exit(1);
}

/** Every file in one tree, relative to it, sorted so the archive is reproducible. */
$files = static function (string $dir): array {
    $found = [];
    $walk = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS));
    foreach ($walk as $file) {
        if (!$file->isFile()) continue;
        $relative = str_replace('\\', '/', substr((string) $file->getPathname(), strlen($dir) + 1));
        // A dotfile is not part of a theme package, and .DS_Store has been shipped inside one before.
        if (str_starts_with(basename($relative), '.')) continue;
        $found[] = $relative;
    }
    sort($found);

    return $found;
};

$built = 0;
foreach (scandir($themesRoot) ?: [] as $entry) {
    if ($entry === '.' || $entry === '..' || str_starts_with($entry, '.')) continue;
    $source = $themesRoot . '/' . $entry;
    if (!is_dir($source) || !is_file($source . '/theme.json')) continue;

    $manifest = json_decode((string) file_get_contents($source . '/theme.json'), true);
    if (!is_array($manifest)) {
        fwrite(STDERR, '  ' . $entry . " has an unreadable theme.json.\n");
        exit(1);
    }
    $meta = (array) ($manifest['theme'] ?? []);
    $name = (string) ($meta['slug'] ?? '') . '-v' . (string) ($meta['version'] ?? '') . '.zip';
    $target = $outputRoot . '/' . $name;

    if (is_file($target) && !@unlink($target)) {
        fwrite(STDERR, 'Unable to replace ' . $name . ". Is extras/themes writable by this user?\n");
        exit(1);
    }
    $zip = new ZipArchive();
    if ($zip->open($target, ZipArchive::CREATE) !== true) {
        fwrite(STDERR, 'Unable to create ' . $name . ". Is extras/themes writable by this user?\n");
        exit(1);
    }
    foreach ($files($source) as $relative) {
        if (!$zip->addFile($source . '/' . $relative, $relative)) {
            fwrite(STDERR, 'Unable to add ' . $relative . ' to ' . $name . ".\n");
            exit(1);
        }
    }
    $count = $zip->numFiles;

    // close() is where a ZipArchive actually writes, and it is where it actually fails: it needs to
    // create a temporary file beside the target, so a directory this user cannot write produces a
    // warning here and a zero-byte or absent archive - after every addFile() has returned true.
    // Reported on the strength of those, the tool prints five successes and builds nothing.
    if (!$zip->close()) {
        fwrite(STDERR, 'Unable to write ' . $name . ". Is extras/themes writable by this user?\n");
        exit(1);
    }
    clearstatcache(true, $target);
    $bytes = is_file($target) ? (int) filesize($target) : 0;
    if ($bytes <= 0) {
        fwrite(STDERR, $name . " was reported as written but is empty.\n");
        exit(1);
    }

    fwrite(STDOUT, sprintf("  %-34s %2d files  %7d bytes\n", $name, $count, $bytes));
    $built++;
}

fwrite(STDOUT, 'Built ' . $built . " theme packages into extras/themes.\n");
