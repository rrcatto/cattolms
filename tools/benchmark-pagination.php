Provides the Catto Learning command-line pagination benchmark utility used for development,
validation, diagnostics or release management. It measures every paginated repository read at the
first page, a middle page and the last page, together with the exact count that heads it.

What it measures, and why those three positions.

OFFSET pagination is cheap at the front and pays for depth: the database still has to produce and
discard every row before the offset. Timing page one alone therefore proves nothing - it is fast
even when the query is wrong. The last page is where a list either holds up or does not, and the
middle page shows whether the cost grows smoothly or falls off a cliff. The count is timed
separately because it is a second query on every page view and, on a hundred thousand rows, can
easily cost more than the page it heads.

Each measurement is the median of several runs, so one unlucky checkpoint or autovacuum does not
become the reported number. The first run of each case is discarded as a warm-up, because the
first touch of a cold table measures the disk rather than the query.

Read the results as relative, not absolute: a development container shares a machine. What matters
is the shape - whether the last page costs roughly what the first does, and whether either grows
with the dataset.

Usage:
  php tools/benchmark-pagination.php [--page-size=25] [--runs=5] [--universe=all|real|seed]

