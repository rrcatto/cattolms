/** Median wall-clock milliseconds over the configured runs, discarding the warm-up. */
$measure = static function (callable $call) use ($runs): float {
    $samples = [];
    for ($run = 0; $run <= $runs; $run++) {
        $at = microtime(true);
        $call();
        $elapsed = (microtime(true) - $at) * 1000;
        if ($run > 0) {
            $samples[] = $elapsed;
        }
    }
    sort($samples);

    return $samples[intdiv(count($samples), 2)];
};

