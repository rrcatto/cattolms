    /** @return array<string,mixed> */
    public function register(int $userId, string $userPrimaryEmail, string $name, string $inputDomain): array
    {
        $name = trim($name);
        if ($name === '' || mb_strlen($name) > 160) {
            throw new InvalidArgumentException('Enter a company or organisation name.');
        }
        $domain = DomainName::normalize($inputDomain);
        if (PublicEmailDomains::contains($domain)) {
            throw new InvalidArgumentException('A public webmail domain cannot be used for a company account.');
        }
        if (EmailAddress::domain($userPrimaryEmail) !== $domain) {
            throw new InvalidArgumentException('Your primary email address must use the company domain exactly.');
        }
        if ($this->companies->domainExists($domain)) {
            throw new InvalidArgumentException('That company domain is already registered.');
        }
        if ($this->companies->findForUser($userId) !== null) {
            throw new InvalidArgumentException('This account already belongs to a company.');
        }
        $company = $this->transactions->run(function () use ($userId, $name, $domain): array {
            $company = $this->companies->create($userId, $name, $domain);
            $this->roles->assign($userId, 'company_admin');
            $this->audit->record($userId, 'company.created', [
