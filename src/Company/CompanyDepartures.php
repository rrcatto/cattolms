    /**
     * What Delete does to a member now: refused (with why), ask (busy with a course), waiting (asked, the 3 days not
     * over), deactivate (asked, no answer in time) or delete (nothing started).
     *
     * @return array{action:string,why:string,busy:list<string>,answer_by:?string}
     */
    public function assess(int $actorUserId, int $companyId, int $userId): array
    {
        $refused = static fn(string $why): array => ['action' => 'refused', 'why' => $why, 'busy' => [], 'answer_by' => null];
        if ($userId === $actorUserId) return $refused(self::OWN);
        $membership = $this->companies->membership($userId);
        if ($membership === null || $membership['company_id'] !== $companyId) return $refused('That person is not in this company.');
        if (in_array($membership['company_role'], CompanyRepository::ADMINISTRATOR_ROLES, true) && $this->companies->administratorCount($companyId) <= 1) return $refused(self::LAST_ADMIN);
        $learning = $this->departures->learning($userId);
        if ($learning['completed'] > 0) return $refused(sprintf(self::COMPLETED, $this->name($userId)));
        $waiting = $this->departures->waitingFor($userId);
        if ($waiting !== null) {
            $answerBy = self::when((string) $waiting['answer_by']);

            return $waiting['answer_due']
                ? ['action' => 'deactivate', 'why' => '', 'busy' => $learning['busy'], 'answer_by' => $answerBy]
                : ['action' => 'waiting', 'why' => sprintf(self::WAITING, $this->name($userId), $answerBy), 'busy' => $learning['busy'], 'answer_by' => $answerBy];
        }

        return ['action' => $learning['busy'] === [] ? 'delete' : 'ask', 'why' => '', 'busy' => $learning['busy'], 'answer_by' => null];
    }

    /** Delete, as assess() says. Returns what happened, in words for the page. */
    public function delete(int $actorUserId, int $companyId, int $userId): string
    {
        return $this->transactions->run(function () use ($actorUserId, $companyId, $userId): string {
            $assessment = $this->assess($actorUserId, $companyId, $userId);
            $name = $this->name($userId);
            switch ($assessment['action']) {
                case 'refused':
                case 'waiting':
                    throw new InvalidArgumentException($assessment['why']);
                case 'ask':
                    $answerBy = $this->ask($companyId, $userId, 'staff_deleted', $actorUserId);

                    return sprintf('%s is busy with a course, so we have emailed them to choose: keep their account as a private one, or delete it. If they have not chosen by %s, you can delete them.', $name, $answerBy);
                case 'deactivate':
                    $waiting = $this->departures->waitingFor($userId);
                    $this->deactivate($actorUserId, $companyId, $userId, 'no answer');
                    if ($waiting !== null) $this->departures->decide((int) $waiting['id'], 'deactivated');

                    return sprintf('%s did not answer in time. Their account is out of the company and deactivated, with everything kept, so the site\'s administrators can restore it at a private address.', $name);
                default:
                    $this->audit->record($actorUserId, 'company.person_deleted', ['company_id' => $companyId, 'user_id' => $userId, 'name' => $name]);
                    if ($this->users->deleteUnlessKept($userId)) return sprintf('%s was deleted. Credit for courses they never started went back to the company.', $name);
                    $this->deactivate($actorUserId, $companyId, $userId, 'records kept');

                    return sprintf('%s is named on records that are kept for good, such as orders, so their account was deactivated instead of deleted.', $name);
            }
        });
    }

    /**
     * A company deleted by its Company Administrator (owner, 2026-10-26: "If they want to delete their company, they can.
     * We just hide it and retain all the records"): hidden, and every staff member deactivated and given 3 days to keep
     * their account as a private one. Typing the company's name confirms it.
     *
     * @return int how many staff were asked
     */
    public function deleteCompany(int $actorUserId, int $companyId, string $typedName): int
    {
        return $this->transactions->run(function () use ($actorUserId, $companyId, $typedName): int {
            $company = $this->companies->findById($companyId) ?? throw new RuntimeException('The company does not exist.');
            if ((string) $company['status'] === 'deleted') throw new InvalidArgumentException('The company is deleted already.');
            if (mb_strtolower(trim($typedName)) !== mb_strtolower(trim((string) $company['name']))) throw new InvalidArgumentException('Type the company\'s name exactly to delete it.');
            $this->companies->markDeleted($companyId);
            $asked = $this->closeCompany($actorUserId, $companyId);
            $this->audit->record($actorUserId, 'company.deleted', ['company_id' => $companyId, 'staff_asked' => $asked]);

            return $asked;
        });
    }

    /**
     * The staff of a company being deleted: each is deactivated and asked to keep their account as a private one.
     *
     * @return int how many were asked
     */
    public function closeCompany(int $actorUserId, int $companyId): int
    {
        $asked = 0;
        foreach ($this->companies->activeMemberIds($companyId) as $userId) {
            $this->deactivate($actorUserId, $companyId, $userId, 'company deleted');
            $this->ask($companyId, $userId, 'company_deleted', $actorUserId);
            $asked++;
        }

        return $asked;
    }

    /**
     * Out of the company and unable to sign in, with everything kept: courses, progress, certificates, records.
     */
    public function deactivate(?int $actorUserId, int $companyId, int $userId, string $why): void
    {
        $this->companies->removeUser($companyId, $userId);
        $this->roles->replaceUserRoles($userId, $this->rolesWithoutCompany($userId));
        $this->users->setStatus($userId, 'deactivated');
        $this->sessions->revokeAllForUser($userId);
        $this->audit->record($actorUserId, 'company.person_deactivated', ['company_id' => $companyId, 'user_id' => $userId, 'why' => $why]);
    }

    /**
     * The record behind an emailed link, with the person's name, address and the courses they are busy with, or null.
     *
     * @return array<string,mixed>|null
     */
    public function forLink(string $rawToken): ?array
    {
        $departure = $this->departures->findByTokenHash(Token::hash($rawToken));
        if ($departure === null) return null;
        $departure['name'] = $this->name((int) $departure['user_id']);
        $departure['email'] = $this->primaryEmail((int) $departure['user_id']);
        $departure['busy'] = $this->departures->learning((int) $departure['user_id'])['busy'];
        $departure['open'] = $departure['status'] === 'waiting' && !$departure['answer_due'];
        $departure['answer_by_words'] = self::when((string) $departure['answer_by']);

        return $departure;
    }

    /** The person chose to delete their account (a deleted staff member only; a deleted company's staff keep theirs or wait). */
    public function chooseDelete(string $rawToken): void
    {
        $this->transactions->run(function () use ($rawToken): void {
            $departure = $this->open($rawToken);
            if ($departure['reason'] !== 'staff_deleted') throw new InvalidArgumentException(self::EXPIRED);
            $userId = (int) $departure['user_id'];
            $this->departures->decide((int) $departure['id'], 'deleted');
            $this->audit->record($userId, 'company.person_chose_deletion', ['company_id' => $departure['company_id'], 'user_id' => $userId]);
            if (!$this->users->deleteUnlessKept($userId)) $this->deactivate($userId, (int) $departure['company_id'], $userId, 'chose deletion, records kept');
        });
    }

    /**
     * The person chose to keep their account as a private one at this address: a link to confirm it is sent there.
     * Never an address at a company's domain (owner: "they cannot continue using their employer's domain name").
     */
    public function choosePrivate(string $rawToken, string $email): string
    {
        $email = EmailAddress::normalize($email);
        $departure = $this->open($rawToken);
        if (EmailAddress::domain($email) === strtolower((string) $departure['company_domain'])) {
            throw new InvalidArgumentException('Give a private address of your own, not one at ' . $departure['company_domain'] . '.');
        }
        $this->rule->assertNotAnotherCompanysAddress($email);
        if ($this->users->emailTaken($email)) throw new InvalidArgumentException('That email address already has an account.');
        $this->departures->setPrivateEmail((int) $departure['id'], $email);
        $raw = Token::generate();
        $seconds = max(1800, (int) (strtotime((string) $departure['answer_by']) - time()));
        $this->tokens->create(Token::hash($raw), $email, 'departure_private', (int) $departure['user_id'], ['departure_id' => (int) $departure['id']], $seconds, ClientFingerprint::ipHash());
        $url = self::url('/leaving/confirm?token=' . rawurlencode($raw));
        try {
            $this->mailer->sendAdministratorMessage($email, 'Confirm your private address', 'Confirm that this is your address, and your account at ' . $this->settings->platformName() . " becomes a private one at it, with all your courses and certificates:\n\n" . $url);
        } catch (\Throwable $e) {
            throw new RuntimeException('The email to ' . $email . ' could not be sent. Try again.', 0, $e);
        }

        return $email;
    }

    /** The private address confirmed from its inbox: the account is a private one at it, active, with everything it had. */
    public function confirmPrivate(string $rawToken): string
    {
        return $this->transactions->run(function () use ($rawToken): string {
            $row = $this->tokens->findUsableForUpdate(Token::hash($rawToken), 'departure_private') ?? throw new RuntimeException(self::EXPIRED);
            $context = json_decode((string) $row['context'], true);
            $departure = $this->departures->find((int) (is_array($context) ? ($context['departure_id'] ?? 0) : 0));
            if ($departure === null || $departure['status'] !== 'waiting') throw new RuntimeException(self::EXPIRED);
            $userId = (int) $departure['user_id'];
            $email = (string) $row['email'];
            $membership = $this->companies->membership($userId);
            if ($membership !== null) {
                $this->companies->removeUser($membership['company_id'], $userId);
                $this->roles->replaceUserRoles($userId, $this->rolesWithoutCompany($userId));
            }
            $this->users->replacePrimaryEmail($userId, $email);
            $this->users->removeSecondaryEmailsAt($userId, (string) $departure['company_domain']);
            $this->users->setStatus($userId, 'active');
            $this->departures->decide((int) $departure['id'], 'went_private');
            $this->tokens->markUsed((int) $row['id']);
            $this->audit->record($userId, 'company.person_went_private', ['company_id' => $departure['company_id'], 'user_id' => $userId]);

            return $email;
        });
    }

    /**
     * ADMIN restores a deactivated account at a new address (owner: "Admin can restore her account, change her email to
     * her private one and allow her to continue with the courses that her profile has access to"). An address at a
     * company's domain makes them that company's staff, as anywhere.
     */
    public function restore(int $actorUserId, int $userId, string $email): void
    {
        $email = EmailAddress::normalize($email);
        $this->transactions->run(function () use ($actorUserId, $userId, $email): void {
            $user = $this->users->findById($userId) ?? throw new RuntimeException('That account does not exist.');
            if (($user['status'] ?? '') !== 'deactivated') throw new InvalidArgumentException('Only a deactivated account is restored.');
            $previous = $this->primaryEmail($userId);
            $this->users->replacePrimaryEmail($userId, $email);
            if ($previous !== '' && EmailAddress::domain($previous) !== EmailAddress::domain($email)) $this->users->removeSecondaryEmailsAt($userId, EmailAddress::domain($previous));
            $this->rule->followAddress($userId, $email, $actorUserId);
            $this->users->setStatus($userId, 'active');
            $waiting = $this->departures->waitingFor($userId);
            if ($waiting !== null) $this->departures->decide((int) $waiting['id'], 'went_private');
            $this->audit->record($actorUserId, 'user.restored', ['user_id' => $userId]);
        });
    }

    /**
     * The waiting records of a company's people, by person, for its pages.
     *
     * @return array<int,array<string,mixed>>
     */
    public function waitingForCompany(int $companyId): array
    {
        $waiting = $this->departures->waitingForCompany($companyId);
        foreach ($waiting as $userId => $departure) $waiting[$userId]['answer_by_words'] = self::when((string) $departure['answer_by']);

        return $waiting;
    }

    /** Asks a person by email, with a link valid for 3 days; returns the answer-by time in words. */
    private function ask(int $companyId, int $userId, string $reason, ?int $actorUserId): string
    {
        $raw = Token::generate();
        $id = $this->departures->create($companyId, $userId, $reason, $actorUserId, Token::hash($raw), self::ANSWER_SECONDS);
        $departure = $this->departures->find($id) ?? throw new RuntimeException('The request could not be recorded.');
        $answerBy = self::when((string) $departure['answer_by']);
        $company = (string) $departure['company_name'];
        $site = $this->settings->platformName();
        $url = self::url('/leaving/' . rawurlencode($raw));
        $email = $this->primaryEmail($userId);
        if ($reason === 'company_deleted') {
            $subject = $company . ' has closed its account: keep yours by ' . $answerBy;
            $body = $company . ' has closed its company account at ' . $site . ', so your staff account is deactivated.' . "\n\n"
                . 'You can keep your account as a private one, with all your courses and certificates, by giving a private email address of your own (not one at ' . $departure['company_domain'] . ') by ' . $answerBy . ":\n\n" . $url . "\n\n"
                . 'If you do not, your account stays deactivated. The site\'s administrators can still restore it for you later.';
        } else {
            $busy = $this->departures->learning($userId)['busy'];
            $subject = 'Your account at ' . $site . ': please choose by ' . $answerBy;
            $body = $company . ' is removing your staff account at ' . $site . '. You are busy with ' . implode(', ', $busy) . '.' . "\n\n"
                . 'Please choose what happens by ' . $answerBy . ":\n\n"
                . 'Keep your account as a private one, at a private email address of your own. You keep all your courses and certificates.' . "\n\n"
                . 'Or delete your account. Your courses and progress go with it.' . "\n\n"
                . 'Choose here: ' . $url . "\n\n"
                . 'If you have not chosen by ' . $answerBy . ', ' . $company . ' may deactivate your account. It is kept, and the site\'s administrators can restore it for you later at a private address.';
        }
        try {
            $this->mailer->sendAdministratorMessage($email, $subject, $body);
        } catch (\Throwable $e) {
            throw new RuntimeException('The email to ' . $email . ' could not be sent, so nothing changed. Try again.', 0, $e);
        }
        $this->audit->record($actorUserId, 'company.departure_asked', ['company_id' => $companyId, 'user_id' => $userId, 'reason' => $reason]);

        return $answerBy;
    }

    /** @return list<string> a person's roles without the company's, keeping Student */
    private function rolesWithoutCompany(int $userId): array
    {
        return array_values(array_unique([...array_diff($this->roles->roles($userId), self::COMPANY_ROLES), RoleCatalog::STUDENT]));
    }

    /** @return array<string,mixed> */
    private function open(string $rawToken): array
    {
        $departure = $this->departures->findByTokenHash(Token::hash($rawToken));
        if ($departure === null || $departure['status'] !== 'waiting' || $departure['answer_due']) throw new InvalidArgumentException(self::EXPIRED);

        return $departure;
    }

    private function name(int $userId): string
    {
        $user = $this->users->findById($userId) ?? [];
        $name = trim((string) ($user['first_name'] ?? '') . ' ' . (string) ($user['last_name'] ?? ''));

        return $name !== '' ? $name : (trim((string) ($user['display_name'] ?? '')) ?: 'This person');
    }

    private function primaryEmail(int $userId): string
    {
        foreach ($this->users->emails($userId) as $row) {
            if (in_array($row['is_primary'] ?? false, [true, 1, '1', 't', 'true'], true)) return (string) $row['email'];
        }

        return '';
    }

    private static function when(string $timestamp): string
    {
        $time = strtotime($timestamp);

        return $time === false ? $timestamp : date('j F Y \a\t H:i', $time);
    }

    private static function url(string $path): string
    {
        return rtrim(Env::string('APP_URL'), '/') . $path;
    }
