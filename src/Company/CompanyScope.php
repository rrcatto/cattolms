declare(strict_types=1);

namespace CattoLearning\Company;

final class CompanyScope
{
    private function __construct()
    {
    }

    /** True only when both are the same real company: neither may be missing, 0 or negative. */
    public static function same(mixed $companyId, mixed $otherCompanyId): bool
    {
        $a = is_numeric($companyId) ? (int) $companyId : 0;
        $b = is_numeric($otherCompanyId) ? (int) $otherCompanyId : 0;
        return $a > 0 && $b > 0 && $a === $b;
    }
}
