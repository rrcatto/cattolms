/*
Generated by: Claude Code CLI

Date time: 2026/08/25 13:59 SAST

Version: 0.5.8.3

Description:
Decides which company the Company workspace is describing on this request.

Stage D. Before this existed the workspace had exactly two modes: a Company Administrator saw
their own company, and a platform administrator saw "All companies". There was no way to say
"administer company X", so any action taken from the platform-wide view had no company to act on
and silently fell back to the actor's own membership - which for a platform administrator is
either the System Company or nothing at all.

Two modes:

  own        the actor's own active company. Every ordinary Company Administrator, always
  selected   company X, chosen by a platform administrator, defaulting to the REAL System Company

The workspace always describes exactly one concrete company. The former "All companies" mode was
removed: it was the default, so a platform administrator arrived at a context that no mutation could
act on, and every write silently fell back to the actor's own membership. The platform-wide overview
still exists, in Administration, which is where a list of every company belongs.

**The company determines the universe, never the other way round.** `companies.seed_token` is the
single source of truth, exactly as it is for identities, so selecting a SEED company means
administering SEED. The earlier implementation resolved the two independently and then refused any
pair that disagreed - and since the Company workspace carries no universe parameter, the request
universe was always REAL, so a SEED company could not be selected and a stored SEED selection was
discarded on the very next read. Deriving one from the other removes the disagreement entirely
rather than refereeing it.

The genuine platform administrator stays a REAL identity throughout. Administering a SEED company
is a viewing and editing context, never a membership: nothing here joins the actor to the selected
company, and no provenance exception is created for one.

The selection is held server-side in the session and re-validated on every read. It is never taken
from a request parameter, because a parameter is an instruction from the client and this is an
authorisation boundary: `?company_id=` on a GET is exactly the tampering this design has to refuse.
Selecting is a POST with a CSRF token, and it is the only thing that writes the selection.

Architectural boundary: resolves and validates context. It holds no SQL of its own - CompanyRepository
owns that - and it performs no business writes at all. A read must not write business data, so
resolving a context must never create, join or modify a company.

Changelog:

2026/08/29 21:05 SAST

- Round A. The selected company now determines the universe instead of being refused when it
  disagreed with a separately resolved one, so a SEED company can be selected and stays selected.
- Removed the "All companies" mode: the workspace always resolves one concrete company, defaulting
  to the REAL System Company, so every mutation has a company to act on.
- Added contextCompanyId(), the single authority every Company write now asks for its company.

2026/08/25 13:59 SAST

- Created for the v0.5.8.3 Stage D Platform ADMIN selected-company context.
*/

declare(strict_types=1);

namespace CattoLearning\Company;

use CattoLearning\Auth\AuthService;
use CattoLearning\Auth\CurrentUser;
use CattoLearning\Infrastructure\Persistence\CompanyRepository;
use InvalidArgumentException;
use RuntimeException;

final class SelectedCompanyContext
{
    /**
     * Where the selection lives.
     *
     * The session, not a cookie and not a hidden field. The value is only ever an integer id, and
     * it is re-validated against permissions, company status and universe on every single read -
     * so a stale or tampered session cannot widen anything, it can only be discarded.
     */
    private const SESSION_KEY = 'company_context_id';

    /** The read scope that makes the selector available at all. Writes carry their own PLATFORM.*.MANAGE checks. */
    public const SELECTOR_PERMISSION = 'PLATFORM.DASHBOARD.VIEW';

    public function __construct(private readonly CompanyRepository $companies)
    {
    }

    /**
     * Whether this identity may choose which company it is administering.
     *
     * A generated identity never may, whatever roles it holds. Seed roles can carry the same
     * business permissions as their normal counterparts by design, so the permission alone is not
     * the test - `users.seed_token` is, exactly as it is for universe selection.
     */
    public function canSelect(CurrentUser $user): bool
    {
        return $user->hasPermission(self::SELECTOR_PERMISSION);
    }

    /**
     * Chooses the company to administer.
     *
     * Validates everything before writing anything to the session, so a refused selection leaves
     * the previous context exactly as it was rather than clearing it as a side effect.
     *
     * @return array<string,mixed> the company now being administered
     */
    public function select(CurrentUser $user, int $companyId): array
    {
        if (!$this->canSelect($user)) {
            throw new RuntimeException('Your account administers a single company and cannot select another.');
        }
        if ($companyId < 1) {
            throw new InvalidArgumentException('Choose a company to administer.');
        }

        $company = $this->companies->findById($companyId);
        if ($company === null) {
            throw new InvalidArgumentException('That company does not exist.');
        }
        if ((string) $company['status'] !== 'active') {
            throw new InvalidArgumentException(
                'That company is disabled and cannot be administered from the Company workspace. '
                . 'Re-enable it in Administration first.'
            );
        }

        // No universe test. The company row carries its own universe in seed_token, so choosing
        // the company is choosing the universe - there is no second opinion for it to disagree
        // with. Refusing a mismatch here is what made a SEED company unselectable, because the
        // Company workspace has no universe parameter and so always resolved to REAL.
        $_SESSION[self::SESSION_KEY] = (int) $company['id'];

        return $company;
    }

    /** Forgets the explicit selection, returning the context to the REAL System Company default. */
    public function clear(): void
    {
        unset($_SESSION[self::SESSION_KEY]);
    }

    /**
     * The effective context for this request.
     *
     * Fails closed in every direction. An identity that may not select is pinned to its own
     * company and the session is ignored entirely, so a Company Administrator who somehow acquired
     * a selection in their session gains nothing from it. A platform administrator whose stored
     * selection no longer validates - the company was disabled, deleted, or the universe scope
     * changed underneath it - drops back to the All-companies overview, which is a narrowing to a
     * read-only view they already had rather than a widening.
     *
     * @return array{mode:string,company:array<string,mixed>,company_id:int,platform_wide:bool}
     */
    public function resolve(CurrentUser $user): array
    {
        if (!$this->canSelect($user)) {
            $company = $this->companies->findForUser($user->id);
            if ($company === null) {
                // Two quite different situations used to share one message, and it blamed the
                // reader for both. A suspended company is not a fault in their account, and
                // nothing of theirs has been lost - so it says so, in the same words the sign-in
                // page uses. In practice an ordinary member of a suspended company no longer holds
                // a session at all; this is the boundary that catches anyone who reaches here
                // another way.
                throw new RuntimeException(
                    $this->companies->userCompanyIsSuspended($user->id)
                        ? AuthService::SUSPENDED_COMPANY_MESSAGE
                        : 'Your account is not attached to a company yet. Ask your company administrator to add you.'
                );
            }

            return [
                'mode' => 'own',
                'company' => $company,
                'company_id' => (int) $company['id'],
                'platform_wide' => false,
            ];
        }

        $selectedId = (int) ($_SESSION[self::SESSION_KEY] ?? 0);
        if ($selectedId > 0) {
            $company = $this->companies->findById($selectedId);

            // Re-validated on every read, not trusted because it was valid when it was chosen:
            // the company may since have been deleted or disabled. The universe is deliberately
            // not part of this test. It used to be, and because the Company workspace carries no
            // universe parameter the test resolved to REAL on every request - so a SEED selection
            // was silently discarded on the very next page load and the administrator was dropped
            // back to the default without explanation.
            if ($company !== null && (string) $company['status'] === 'active') {
                return $this->selectedContext($company);
            }

            // Discard rather than carry a selection that no longer holds. This is a read path, so
            // it must not write business data - clearing a session key is not business data.
            $this->clear();
        }

        // No explicit selection: the REAL System Company. Resolved through the repository rather
        // than hard-coded, because there is one System Company per universe (decision D1) and the
        // genuine platform administrator is a REAL identity administering the REAL platform until
        // they say otherwise.
        $system = $this->companies->systemCompany();
        if ($system === null) {
            throw new RuntimeException(
                'The REAL System Company is missing, so there is no default company to administer. '
                . 'This database predates the v0.5.8 baseline.'
            );
        }

        return $this->selectedContext($system);
    }

    /**
     * The context view for one concrete company.
     *
     * The universe is read from the company row and from nowhere else, which is the whole of the
     * coupling rule: there is exactly one place that answers "which universe is this workspace in",
     * and it answers by looking at the company.
     *
     * @param array<string,mixed> $company
     * @return array{mode:string,company:array<string,mixed>,company_id:int,platform_wide:bool}
     */
    private function selectedContext(array $company): array
    {
        return [
            'mode' => 'selected',
            'company' => $company,
            'company_id' => (int) $company['id'],
            'platform_wide' => false,
        ];
    }

    /**
     * The company id every Company workspace write must act on.
     *
     * One authority, asked by every mutation. Previously each write called
     * `CompanyRepository::findForUser($actorUserId)` for itself, which is the actor's *own*
     * membership - so a platform administrator's writes landed on their own company, or were
     * refused outright because they have none, while the workspace displayed somebody else's.
     * Selecting a company and then writing to a different one is the defect this method exists
     * to make impossible.
     */
    public function contextCompanyId(CurrentUser $user): int
    {
        return (int) $this->resolve($user)['company_id'];
    }

}
