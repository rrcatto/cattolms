declare(strict_types=1);

namespace CattoLearning\Auth;

use CattoLearning\Support\Env;
use CattoPHP\SouthAfrica\IdNumber;
use DateTimeImmutable;
use InvalidArgumentException;

final class SouthAfricanIdNumber
{
    public const ENTER = IdNumber::ENTER;
    public const INVALID = IdNumber::INVALID;

    private function __construct(private readonly IdNumber $number, public readonly string $digits, public readonly string $birthdate)
    {
    }

    /**
     * The number as a person types it (spaces allowed), checked as valid. Someone under 18 is refused (adults only).
     *
     * @throws InvalidArgumentException in plain words
     */
    public static function fromInput(mixed $value, DateTimeImmutable $today): self
    {
        $number = IdNumber::fromInput($value, $today);
        if (AdultAge::under18($number->birthdate, $today)) throw new InvalidArgumentException(AdultAge::REFUSED);

        return new self($number, $number->digits, $number->birthdate);
    }

    /** Whether the person is a South African citizen (0) rather than a permanent resident (1). */
    public function isCitizen(): bool
    {
        return $this->number->isCitizen();
    }

    /** The keyed fingerprint that finds another account with the same number. */
    public function fingerprint(): string
    {
        return $this->number->fingerprint(Env::string('APP_KEY'));
    }

    /** The number as pages show it: the date part, then stars. */
    public static function masked(string $digits): string
    {
        return IdNumber::masked($digits);
    }

    /**
     * A valid number for someone born on that day (Seed Database and the checks' people), with its checksum.
     *
     * @param int $sequence 0 to 9999: below 5000 is how a woman's number is written, 5000 and above a man's
     */
    public static function make(DateTimeImmutable $born, int $sequence, bool $citizen = true): string
    {
        return IdNumber::make($born, $sequence, $citizen);
    }
}
