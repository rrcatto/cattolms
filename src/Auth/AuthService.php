    public function verifySecondaryEmail(string $rawToken): void
    {
        $userId = $this->transactions->run(function () use ($rawToken): int {
            $row = $this->tokens->findUsableForUpdate(
                Token::hash($rawToken),
                'secondary_email'
            );
            if ($row === null || (int) ($row['user_id'] ?? 0) < 1) {
                throw new RuntimeException('The verification link is invalid or has expired.');
            }

            $userId = (int) $row['user_id'];
            $this->users->addVerifiedSecondaryEmail($userId, (string) $row['email']);
            $this->tokens->markUsed((int) $row['id']);

            return $userId;
        });

        $this->audit->record($userId, 'user.secondary_email_verified');
        $this->events->dispatch('user.secondary_email_verified', ['user_id' => $userId]);
    }

