    public function requestLogin(string $inputEmail, string $returnPath = '/account/library'): void
    {
        $email = EmailAddress::normalize($inputEmail);
        $known = $this->users->findByVerifiedEmail($email);
        $admin = strtolower(trim(Env::string('APP_ADMIN_EMAIL')));
        if ($known === null && ($admin === '' || strtolower($email) !== $admin)) {
            throw new UnknownLoginEmailException($email);
        }
        if (!$this->withinRateLimits($email)) {
            throw new RuntimeException('Too many sign-in requests. Please wait before trying again.');
        }

        $rawToken = Token::generate();
        $tokenHash = Token::hash($rawToken);
        $this->tokens->create(
            $tokenHash,
            $email,
            'login',
            null,
            ['return_path' => $this->safeReturnPath($returnPath)],
            Env::int('AUTH_MAGIC_LINK_TTL', 1800),
            ClientFingerprint::ipHash()
        );

        $url = rtrim(Env::string('APP_URL'), '/') . '/auth/consume?token=' . rawurlencode($rawToken);
        try {
            $this->mailer->sendMagicLink($email, $url, Env::int('AUTH_MAGIC_LINK_TTL', 1800));
        } catch (\Throwable $e) {
            $this->tokens->deleteByHash($tokenHash);
            throw new RuntimeException('The sign-in email could not be sent.', 0, $e);
        }
        $this->audit->record(null, 'auth.magic_link_requested', ['email_hash' => hash('sha256', $email)]);
    }

    public function consumeLogin(string $rawToken): string
    {
        if ($rawToken === '') {
            throw new RuntimeException('The sign-in link is invalid or has expired.');
        }

        $state = $this->transactions->run(function () use ($rawToken): array {
            $row = $this->tokens->findUsableForUpdate(Token::hash($rawToken), 'login');
            if ($row === null) {
                throw new RuntimeException('The sign-in link is invalid or has expired.');
            }

            $created = false;
            $email = (string) $row['email'];
            $user = $this->users->findByVerifiedEmail($email);
            if ($user === null) {
                if (strtolower($email) !== strtolower(trim(Env::string('APP_ADMIN_EMAIL')))) {
                    throw new RuntimeException('This email is not registered. Please complete registration first.');
                }
                $user = $this->users->createWithPrimaryEmail($email);
                $this->roles->assign((int) $user['id'], RoleCatalog::STUDENT);
                $this->audit->record((int) $user['id'], 'user.created');
                $created = true;
            }
            $this->roles->assign((int) $user['id'], RoleCatalog::STUDENT);

            $this->roles->bootstrapAdministrator(
                (int) $user['id'],
                $email,
                Env::string('APP_ADMIN_EMAIL')
            );

            // A suspended company's members may not obtain a session. Checked here, after the
            // identity is known and before the session is created, so the magic link is consumed
            // by nobody and no session exists to clean up. The token is left unused deliberately:
            // the sign-in did not happen, so burning the link would also cost them the retry once
            // the company is active again.
            if ($this->companySuspensionBlocks((int) $user['id'])) {
                throw new RuntimeException(self::SUSPENDED_COMPANY_MESSAGE);
            }

            $this->tokens->markUsed((int) $row['id']);
            $this->users->markLogin((int) $user['id']);

            $sessionToken = Token::generate();
            $sessionPublicId = $this->sessions->create(
                (int) $user['id'],
                Token::hash($sessionToken),
                Env::int('AUTH_SESSION_TTL', 86400),
                ClientFingerprint::ipHash(),
                ClientFingerprint::userAgent(),
                $email
            );
            $context = json_decode((string) ($row['context'] ?? '{}'), true);

            return [
                'user' => $user,
                'created' => $created,
                'session_token' => $sessionToken,
                'session_public_id' => $sessionPublicId,
                'return_path' => $this->safeReturnPath(
                    is_array($context)
                        ? (string) ($context['return_path'] ?? '/account/library')
                        : '/account/library'
                ),
            ];
        });

        /** @var array<string,mixed> $user */
        $user = $state['user'];
        $this->setSessionCookie((string) $state['session_token']);
        $this->audit->record(
            (int) $user['id'],
            'auth.login',
            ['session' => (string) $state['session_public_id']]
        );
        if ((bool) $state['created']) {
            $this->events->dispatch('user.registered', ['user_id' => (int) $user['id']]);
        }
        $this->events->dispatch('auth.logged_in', [
            'user_id' => (int) $user['id'],
            'session_id' => (string) $state['session_public_id'],
        ]);

        return (string) $state['return_path'];
    }


    public function currentUser(): ?CurrentUser
    {
        if ($this->currentUser !== null) {
            return $this->currentUser;
        }
        $rawToken = (string) ($_COOKIE[Env::string('AUTH_SESSION_COOKIE', 'catto_learning_session')] ?? '');
        if ($rawToken === '') {
            return null;
        }
        $session = $this->sessions->findActive(Token::hash($rawToken));
        if ($session === null) {
            $this->clearSessionCookie();
            return null;
        }

        $lastSeen = strtotime((string) $session['last_seen_at']) ?: 0;
        if ($lastSeen < time() - Env::int('AUTH_SESSION_TOUCH_INTERVAL', 300)) {
            $this->sessions->touch((int) $session['id'], Env::int('AUTH_SESSION_TTL', 86400));
            $this->setSessionCookie($rawToken);
        }

        $displayName = trim((string) ($session['display_name'] ?? ''));
        if ($displayName === '') {
            $displayName = trim((string) (($session['first_name'] ?? '') . ' ' . ($session['last_name'] ?? '')));
        }
        if ($displayName === '') {
            $displayName = (string) $session['primary_email'];
        }

        $userId = (int) $session['user_id'];
        $primaryEmail = (string) $session['primary_email'];
        $authenticatedEmail = (string) ($session['authenticated_email'] ?? $primaryEmail);
        try {
            $roles = $this->roles->roles($userId);
        } catch (\Throwable) {
            $roles = [];
        }
        // The configured administrator identity is a recovery boundary. Even
        // if the ADMIN row has been removed, that account still receives the
        // hard-coded ADMIN role and the repository will recreate the row when
        // bootstrap next runs successfully.
        $configuredAdmin = strtolower(trim(Env::string('APP_ADMIN_EMAIL')));
        if ($configuredAdmin !== '' && strtolower($authenticatedEmail) === $configuredAdmin && !in_array('ADMIN', $roles, true)) {
            $roles[] = 'ADMIN';
        }
        $roles = array_values(array_unique(array_map('strtoupper', $roles)));

        // The central suspension boundary. Every authenticated request resolves its identity here,
        // so this one test covers the whole application: there is no controller that can forget it,
        // and no company-status check anywhere else.
        //
        // The session is revoked as well as refused. Suspension is not a momentary condition to be
        // re-evaluated on each request while a valid session sits in the database looking usable -
        // and revoking here catches a session that outlived the sweep done at suspension time, for
        // instance one created moments before it.
        if (self::isTrue($session['company_suspended'] ?? false) && !in_array('ADMIN', $roles, true)) {
            $this->sessions->revokeByTokenHash(Token::hash($rawToken));
            $this->clearSessionCookie();

            return null;
        }

        $permissions = $this->acl->permissionsForUser($userId, $roles);

        $this->currentUser = new CurrentUser(
            $userId,
            (string) $session['user_public_id'],
            $primaryEmail,
            $displayName,
            $roles,
            $permissions,
            (string) $session['public_id'],
            $authenticatedEmail
        );
        return $this->currentUser;
    }

