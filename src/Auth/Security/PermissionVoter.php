declare(strict_types=1);

namespace CattoLearning\Auth\Security;

use CattoLearning\Api\Security\ApiUser;
use CattoLearning\Auth\PermissionCatalog;
use Symfony\Component\Security\Core\Authentication\Token\TokenInterface;
use Symfony\Component\Security\Core\Authorization\Voter\Voter;

/** @extends Voter<string,mixed> */
final class PermissionVoter extends Voter
{
    public function __construct(private readonly PermissionCatalog $catalog)
    {
    }

    protected function supports(string $attribute, mixed $subject): bool
    {
        return in_array($attribute, $this->catalog->keys(), true);
    }

    protected function voteOnAttribute(string $attribute, mixed $subject, TokenInterface $token): bool
    {
        $user = $token->getUser();

        return $user instanceof ApiUser && $user->identity->hasPermission($attribute);
    }
}
