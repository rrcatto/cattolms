Description:
Decides whether the authenticated identity holds a business permission.

Architectural boundary: authorization. It answers exactly one of the three orthogonal access
questions - what may this identity DO - and reads the answer from the permission list the identity
already carries. It never looks at the data universe and never at a resource relationship; those are
decided elsewhere, and a permission name that encoded either of them would be a design error rather
than a convenience.

There is one business catalogue, so this voter serves every interface. The API supplies an ApiUser
and the web will supply the session identity; both hold the same permission keys, resolved by the
same AclService, which is why a route may state the permission it needs without stating which
interface is asking.

An attribute the catalogue does not define is not recognised, so a mistyped permission is denied
rather than quietly granted by another voter.

