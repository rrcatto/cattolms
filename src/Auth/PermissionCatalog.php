    /**
     * ADMIN sees the complete catalogue. Every other role may receive business
     * capabilities only; SYSTEM.* remains platform-infrastructure authority.
     *
     * @return array<string,list<array{key:string,name:string,group:string,description:string}>>
     */
    public function groupedForRole(string $roleKey): array
    {
        if (strtoupper(trim($roleKey)) === RoleCatalog::ADMIN) {
            return $this->grouped();
        }
        return $this->group(array_values(array_filter(
            $this->all(),
            static fn(array $permission): bool => self::isAssignableToRole($roleKey, (string) $permission['key'])
        )));
    }

    /**
     * Enforces the small capability difference intentionally retained for seed
     * test roles without creating a second SEED.* permission catalogue.
     */
    public static function isAssignableToRole(string $roleKey, string $permissionKey): bool
    {
        $roleKey = strtoupper(trim($roleKey));
        $permissionKey = strtoupper(trim($permissionKey));
        if ($roleKey === RoleCatalog::ADMIN) {
            return true;
        }
        if (str_starts_with($permissionKey, 'SYSTEM.')) {
            return false;
        }
        return !RoleCatalog::isSeedRole($roleKey) || !in_array($permissionKey, self::SEED_ROLE_EXCLUDED, true);
    }

    /** @param list<array{key:string,name:string,group:string,description:string}> $permissions
     *  @return array<string,list<array{key:string,name:string,group:string,description:string}>> */
    private function group(array $permissions): array
    {
        $groups = [];
        foreach ($permissions as $permission) {
            $groups[$permission['group']][] = $permission;
        }
        return $groups;
    }

