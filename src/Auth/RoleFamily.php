namespace CattoLearning\Auth;

use RuntimeException;

/** Prevents normal and SEED_* role families from being mixed on one identity. */
final class RoleFamily
{
    public const NORMAL = 'NORMAL';
    public const SEED = 'SEED';
    public const ADMIN = 'ADMIN';

    public static function forRole(string $roleKey): string
    {
        $roleKey = strtoupper(trim($roleKey));
        if ($roleKey === RoleCatalog::ADMIN) {
            return self::ADMIN;
        }
        return RoleCatalog::isSeedRole($roleKey) ? self::SEED : self::NORMAL;
    }

    /**
     * Returns the compatible role family for a user. ADMIN may retain the
     * normal STUDENT baseline but may never be combined with SEED_* roles.
     *
     * @param list<string> $roles
     */
    public static function forRoleSet(array $roles): string
    {
        $roles = array_values(array_unique(array_map(static fn(string $role): string => strtoupper(trim($role)), $roles)));
        $hasAdmin = in_array(RoleCatalog::ADMIN, $roles, true);
        $hasSeed = array_any($roles, static fn(string $role): bool => RoleCatalog::isSeedRole($role));
        $hasNormal = array_any($roles, static fn(string $role): bool => $role !== RoleCatalog::ADMIN && !RoleCatalog::isSeedRole($role));

        if (($hasAdmin && $hasSeed) || ($hasSeed && $hasNormal)) {
            throw new RuntimeException('Normal and SEED role families cannot be assigned to the same user.');
        }

        return $hasAdmin ? self::ADMIN : ($hasSeed ? self::SEED : self::NORMAL);
    }

    /** @param list<string> $roles */
    public static function assertCompatible(array $roles): void
    {
        self::forRoleSet($roles);
    }
}
