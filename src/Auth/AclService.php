declare(strict_types=1);

namespace CattoLearning\Auth;

use CattoLearning\Infrastructure\Persistence\OptionRepository;
use CattoLearning\Infrastructure\Persistence\RoleRepository;

/**
 * Central ACL decision service.
 *
 * Controllers, services and navigation should ask this service (or the
 * permission list carried by CurrentUser) rather than hard-coding role names.
 */
final class AclService
{
    public function __construct(
        private readonly RoleRepository $roles,
        private readonly OptionRepository $options,
        private readonly PermissionCatalog $catalog
    ) {
    }

    /**
     * @param list<string> $roleKeys
     * @return list<string>
     */
    public function permissionsForUser(int $userId, array $roleKeys): array
    {
        if (in_array('ADMIN', $roleKeys, true)) {
            return $this->catalog->keys();
        }

        $revision = $this->revision();
        $cached = $_SESSION['acl_permissions'][$userId] ?? null;
        if (is_array($cached)
            && (string) ($cached['revision'] ?? '') === $revision
            && is_array($cached['permissions'] ?? null)
        ) {
            return array_values(array_filter(
                $cached['permissions'],
                static fn(mixed $key): bool => is_string($key) && $key !== ''
            ));
        }

        $permissions = $this->roles->permissionsForUser($userId);
        $_SESSION['acl_permissions'][$userId] = [
            'revision' => $revision,
            'permissions' => $permissions,
        ];
        return $permissions;
    }

    /** @param list<string> $permissions */
    public function has(array $permissions, string $permission): bool
    {
        return in_array($permission, $permissions, true);
    }

    /**
     * Invalidates all permission caches by advancing a shared revision token.
     * Existing browser sessions refresh their permission list on the next
     * request without requiring a logout.
     */
    public function invalidateAll(?int $actorUserId = null): void
    {
        $this->options->set('acl_revision', (string) (time() . '-' . random_int(1000, 9999)), $actorUserId);
        unset($_SESSION['acl_permissions']);
    }

    private function revision(): string
    {
        $revision = trim($this->options->get('acl_revision', '1'));
        return $revision !== '' ? $revision : '1';
    }
}
