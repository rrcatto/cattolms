declare(strict_types=1);

namespace CattoLearning\Auth;

use CattoPHP\Access\FoundationPermissions;
use CattoPHP\Access\Permission;
use CattoPHP\Access\PermissionProvider;

final class CattolmsPermissions implements PermissionProvider
{
    public function __construct(private readonly PermissionCatalog $catalog, private readonly FoundationPermissions $foundation)
    {
    }

    public function permissions(): iterable
    {
        $named = [];
        foreach ($this->foundation->permissions() as $permission) {
            $named[$permission->key] = true;
        }
        foreach ($this->catalog->all() as $permission) {
            if (!isset($named[$permission['key']])) {
                yield new Permission($permission['key'], $permission['group'], $permission['description']);
            }
        }
    }
}
