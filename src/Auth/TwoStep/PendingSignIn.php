declare(strict_types=1);

namespace CattoLearning\Auth\TwoStep;

use CattoPHP\Security\SecretCipher;
use Symfony\Component\Clock\ClockInterface;
use Throwable;

class PendingSignIn
{
    public const KEY = 'pending_sign_in';
    public const TTL = 600;
    public const TRIES = 5;
    public const PATH = '/login/two-step';
    public const SETUP_PATH = '/login/two-step/setup';

    public function __construct(private readonly SecretCipher $cipher, private readonly ClockInterface $clock)
    {
    }

    /** Starts one, in place of any before it. Where to send them next. */
    public function begin(int $userId, string $email, string $returnPath, ?string $follow, string $via, bool $setUp): string
    {
        if (session_status() === PHP_SESSION_ACTIVE) session_regenerate_id(true);
        $_SESSION[self::KEY] = ['user_id' => $userId, 'email' => $email, 'return_path' => $returnPath, 'follow' => $follow, 'via' => $via,
            'set_up' => $setUp, 'expires_at' => $this->now() + self::TTL, 'tries' => 0];

        return $setUp ? self::SETUP_PATH : self::PATH;
    }

    /** @return array{user_id:int,email:string,return_path:string,follow:?string,via:string,set_up:bool,expires_at:int,tries:int}|null the one waiting, unless it has run out */
    public function current(): ?array
    {
        $pending = $_SESSION[self::KEY] ?? null;
        if (!is_array($pending) || !isset($pending['user_id'], $pending['email'], $pending['expires_at'])) return null;
        if ((int) $pending['expires_at'] < $this->now()) {
            $this->clear();

            return null;
        }

        return ['user_id' => (int) $pending['user_id'], 'email' => (string) $pending['email'], 'return_path' => (string) ($pending['return_path'] ?? '/account/courses'),
            'follow' => is_string($pending['follow'] ?? null) ? $pending['follow'] : null, 'via' => (string) ($pending['via'] ?? 'email'),
            'set_up' => (bool) ($pending['set_up'] ?? false), 'expires_at' => (int) $pending['expires_at'], 'tries' => (int) ($pending['tries'] ?? 0)];
    }

    /** A wrong code: whether it may be tried again. The fifth ends the sign-in. */
    public function wrong(): bool
    {
        $tries = (int) ($_SESSION[self::KEY]['tries'] ?? 0) + 1;
        if ($tries >= self::TRIES) {
            $this->clear();

            return false;
        }
        $_SESSION[self::KEY]['tries'] = $tries;

        return true;
    }

    /** The key being set up, kept encrypted in this session until the first code proves the phone holds it. */
    public function setUpSecret(string $context, ?string $fresh = null): ?string
    {
        $slot = 'two_step_setup_' . $context;
        if ($fresh !== null) {
            $_SESSION[$slot] = $this->cipher->encrypt($fresh);

            return $fresh;
        }
        try {
            $secret = is_string($_SESSION[$slot] ?? null) ? $this->cipher->decrypt($_SESSION[$slot]) : '';
        } catch (Throwable) {
            $secret = '';
        }

        return $secret === '' ? null : $secret;
    }

    public function forgetSetUpSecret(string $context): void
    {
        unset($_SESSION['two_step_setup_' . $context]);
    }

    /**
     * The recovery codes just made, shown once: kept encrypted in this session until the person says they have kept them.
     *
     * @param list<string>|null $codes to keep, or null to read
     * @return list<string>
     */
    public function recoveryCodes(string $context, ?array $codes = null): array
    {
        $slot = 'two_step_codes_' . $context;
        if ($codes !== null) {
            $_SESSION[$slot] = $this->cipher->encrypt(implode(' ', $codes));

            return $codes;
        }
        try {
            $text = is_string($_SESSION[$slot] ?? null) ? $this->cipher->decrypt($_SESSION[$slot]) : '';
        } catch (Throwable) {
            $text = '';
        }

        return $text === '' ? [] : array_values(array_filter(explode(' ', $text)));
    }

    public function forgetRecoveryCodes(string $context): void
    {
        unset($_SESSION['two_step_codes_' . $context]);
    }

    public function clear(): void
    {
        unset($_SESSION[self::KEY], $_SESSION['two_step_setup_sign_in'], $_SESSION['two_step_codes_sign_in']);
    }

    private function now(): int
    {
        return $this->clock->now()->getTimestamp();
    }
}
