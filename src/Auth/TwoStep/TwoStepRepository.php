declare(strict_types=1);

namespace CattoLearning\Auth\TwoStep;

use CattoLearning\Infrastructure\Persistence\Database;

class TwoStepRepository
{
    public function __construct(private readonly Database $db)
    {
    }

    /** @return array{secret_encrypted:string,confirmed_at:string,last_used_step:int}|null */
    public function find(int $userId, bool $forUpdate = false): ?array
    {
        $row = $this->db->fetchAssociative('SELECT secret_encrypted, confirmed_at, last_used_step FROM user_two_step WHERE user_id = :user' . ($forUpdate ? ' FOR UPDATE' : ''), ['user' => $userId]);
        if ($row === false) return null;

        return ['secret_encrypted' => (string) $row['secret_encrypted'], 'confirmed_at' => (string) $row['confirmed_at'], 'last_used_step' => (int) $row['last_used_step']];
    }

    /**
     * Turns it on with a new key, and the recovery codes with it: anything kept before is replaced.
     *
     * @param list<string> $hashes
     */
    public function save(int $userId, string $secretEncrypted, int $step, array $hashes): void
    {
        $this->db->executeStatement('DELETE FROM user_two_step WHERE user_id = :user', ['user' => $userId]);
        $this->db->executeStatement('INSERT INTO user_two_step (user_id, secret_encrypted, last_used_step) VALUES (:user, :secret, :step)', ['user' => $userId, 'secret' => $secretEncrypted, 'step' => $step]);
        $this->replaceRecovery($userId, $hashes);
    }

    public function useStep(int $userId, int $step): void
    {
        $this->db->executeStatement('UPDATE user_two_step SET last_used_step = :step WHERE user_id = :user AND last_used_step < :step', ['user' => $userId, 'step' => $step]);
    }

    /** @param list<string> $hashes */
    public function replaceRecovery(int $userId, array $hashes): void
    {
        $this->db->executeStatement('DELETE FROM user_two_step_recovery WHERE user_id = :user', ['user' => $userId]);
        foreach ($hashes as $hash) {
            $this->db->executeStatement('INSERT INTO user_two_step_recovery (user_id, code_hash) VALUES (:user, :hash)', ['user' => $userId, 'hash' => $hash]);
        }
    }

    /** Uses a recovery code once: whether it was there and unused. */
    public function useRecovery(int $userId, string $hash): bool
    {
        return $this->db->executeStatement('UPDATE user_two_step_recovery SET used_at = NOW() WHERE user_id = :user AND code_hash = :hash AND used_at IS NULL', ['user' => $userId, 'hash' => $hash]) === 1;
    }

    public function recoveryLeft(int $userId): int
    {
        return (int) $this->db->fetchOne('SELECT COUNT(*) FROM user_two_step_recovery WHERE user_id = :user AND used_at IS NULL', ['user' => $userId]);
    }

    /** The account holding this verified email address, in any case, or null (auth:two-step-reset). */
    public function userWithEmail(string $email): ?int
    {
        $user = $this->db->fetchOne('SELECT user_id FROM user_emails WHERE LOWER(email) = LOWER(:email) AND verified_at IS NOT NULL LIMIT 1', ['email' => trim($email)]);

        return $user === false || $user === null ? null : (int) $user;
    }

    /** Turns it off: the key and every recovery code go. Whether there was anything. */
    public function delete(int $userId): bool
    {
        return $this->db->executeStatement('DELETE FROM user_two_step WHERE user_id = :user', ['user' => $userId]) > 0;
    }
}
