declare(strict_types=1);

namespace CattoLearning\Auth\Signup;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\SignInHistoryRepository;
use CattoLearning\Support\GeoIpLocator;
use InvalidArgumentException;

class SignInHistory
{
    public function __construct(
        private readonly SignInHistoryRepository $signIns,
        private readonly NetworkLookup $network,
        private readonly AuditRepository $audit
    ) {
    }

    /**
     * The recent sign-ins as the person's page shows them, newest first.
     *
     * @return list<array<string,mixed>>
     */
    public function recent(int $userId, int $limit = 10): array
    {
        $rows = $this->signIns->recent($userId, $limit + 1);
        $shown = [];
        foreach (array_slice($rows, 0, $limit) as $row) {
            $facts = $row['ip'] !== '' ? $this->network->facts($row['ip']) : null;
            $country = $row['country'] !== '' ? $row['country'] : ($facts->countryCode ?? '');
            $earlier = $country === '' ? [] : $this->signIns->countriesBefore($userId, $row['id']);
            $shown[] = $row + [
                'place' => $row['ip'] !== '' ? $this->network->place($row['ip']) : 'No IP address',
                'country_label' => $country === '' ? 'Unknown' : trim(GeoIpLocator::flagForCountryCode($country) . ' ' . SignupCountries::name($country)),
                'network' => $facts->networkName ?? '',
                // A first sign-in from another country than every earlier one (not the account's very first sign-in).
                'new_country' => $country !== '' && $earlier !== [] && !in_array($country, $earlier, true),
            ];
        }

        return $shown;
    }

    /**
     * The sign-ins from a new country, for Needs your attention.
     *
     * @return list<array<string,mixed>>
     */
    public function newCountries(): array
    {
        $found = [];
        foreach ($this->signIns->newCountries() as $row) {
            $row['country_name'] = SignupCountries::name($row['country']);
            $row['earlier'] = array_map([SignupCountries::class, 'name'], $this->signIns->countriesBefore($row['user_id'], $row['id']));
            $found[] = $row;
        }

        return $found;
    }

    /** The administrator has looked at a sign-in from a new country: it leaves Needs your attention. */
    public function markSeen(int $userId, int $loginId, int $actorUserId): void
    {
        if (!$this->signIns->belongsTo($loginId, $userId)) throw new InvalidArgumentException('That sign-in could not be found.');
        $this->audit->record($actorUserId, 'user.signin_country_seen', ['user_id' => $userId, 'login_id' => (string) $loginId]);
    }
}
