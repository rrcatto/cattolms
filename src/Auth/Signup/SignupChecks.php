declare(strict_types=1);

namespace CattoLearning\Auth\Signup;

use CattoLearning\Infrastructure\Persistence\SignupAttemptRepository;
use CattoLearning\Support\ClientFingerprint;
use CattoLearning\Support\Env;

class SignupChecks
{
    /** The hidden field people never see (named like the contact form's). */
    public const TRAP_FIELD = 'website';
    public const STAMP_FIELD = 'signup_opened';
    public const ZONE_FIELD = 'signup_time_zone';

    public function __construct(
        private readonly SignupAttemptRepository $attempts,
        private readonly NetworkLookup $network,
        private readonly SignupLists $lists,
        private readonly MailDomainCheck $mail,
        private readonly SignupCountries $countries,
    ) {
    }

    /** When the form was opened, signed so a browser cannot make it up. */
    public static function formStamp(?int $now = null): string
    {
        $now ??= time();

        return $now . '.' . substr(hash_hmac('sha256', 'signup:' . $now, Env::string('APP_KEY')), 0, 16);
    }

    /** The seconds the form was open, or null without a genuine stamp. */
    public static function secondsOpen(string $stamp, ?int $now = null): ?int
    {
        if (preg_match('/^(\d{9,11})\.([0-9a-f]{16})$/', trim($stamp), $match) !== 1) return null;
        if (!hash_equals(substr(hash_hmac('sha256', 'signup:' . $match[1], Env::string('APP_KEY')), 0, 16), $match[2])) return null;
        $seconds = ($now ?? time()) - (int) $match[1];

        return $seconds >= 0 && $seconds < 86400 ? $seconds : null;
    }

    /**
     * Judges a registration and records it: refused (a throwaway address, or $refusal given by another rule, such as
     * Who can sign in), caught by the hidden field, or with its link sent.
     *
     * @param array<string,mixed> $form what the form sent
     * @return array{id:int,risk:RiskAssessment}
     */
    public function check(array $form, string $email, ?string $refusal = null): array
    {
        $ip = ClientFingerprint::ipAddress();
        $network = $this->network->facts($ip);
        $domain = strtolower((string) substr((string) strrchr($email, '@'), 1));
        $facts = new SignupFacts(
            $email,
            trim((string) ($form['first_name'] ?? '')),
            trim((string) ($form['last_name'] ?? '')),
            ClientFingerprint::userAgent(),
            $network,
            self::secondsOpen((string) ($form[self::STAMP_FIELD] ?? '')),
            mb_substr(trim((string) ($form[self::ZONE_FIELD] ?? '')), 0, 64),
            trim((string) ($form[self::TRAP_FIELD] ?? '')) !== '',
            $domain !== '' && $this->lists->isDisposable($domain),
            $domain !== '' ? $this->mail->receivesMail($domain) : null,
            $this->attempts->recentFromAddress($ip)
        );
        $risk = SignupRisk::assess($facts, $this->countries->allowed(), $this->countries->blocked());
        $refusal ??= $risk->refusal;
        $id = $this->attempts->record([
            'email' => $email, 'first_name' => $facts->firstName, 'last_name' => $facts->lastName,
            'account_type' => (string) ($form['account_type'] ?? 'individual'), 'ip' => $ip, 'country' => $network->countryCode,
            'home_country' => \CattoLearning\Support\Countries::code($form['country'] ?? '') ?? '',
            'asn' => $network->asn, 'network' => $network->networkName, 'agent' => $facts->userAgent, 'zone' => $facts->browserTimeZone,
            'seconds' => $facts->formSeconds, 'score' => $risk->score, 'band' => $risk->band, 'signals' => $risk->signals,
            'hold_reasons' => $risk->holdReasons, 'outcome' => $risk->trapped ? 'trapped' : ($refusal !== null ? 'refused' : 'link_sent'), 'refusal' => $refusal,
        ]);

        return ['id' => $id, 'risk' => $risk];
    }

    /** The country of an address, for a sign-in's record ('' when it is private or unknown). */
    public function countryOf(string $ip): string
    {
        return $ip === '' ? '' : $this->network->facts($ip)->countryCode;
    }

    /** The registration was completed: the account exists, held for approval or not. */
    public function complete(int $attemptId, int $userId, bool $held): void
    {
        $this->attempts->complete($attemptId, $userId, $held);
    }
}
