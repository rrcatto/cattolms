declare(strict_types=1);

namespace CattoLearning\Auth\Signup;

use CattoLearning\Support\Env;
use CattoLearning\Support\GeoIpLocator;
use GeoIp2\Database\Reader;
use Throwable;

class NetworkLookup
{
    private ?Reader $asn = null;
    private bool $asnOpened = false;

    public function __construct(private readonly GeoIpLocator $geo, private readonly SignupLists $lists)
    {
    }

    public function facts(string $ip): NetworkFacts
    {
        $public = filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_NO_PRIV_RANGE | FILTER_FLAG_NO_RES_RANGE) !== false;
        if (!$public) return NetworkFacts::unknown($ip, $this->geo->isAvailable());
        [$asn, $network] = $this->network($ip);

        return new NetworkFacts($ip, true, $this->geo->countryCode($ip), $asn, $network,
            $this->lists->isTor($ip), $this->lists->isVpn($ip), $this->lists->isDatacenter($ip), $this->geo->isAvailable());
    }

    /** @return array{geo:bool,network:bool} whether the country and network databases are there */
    public function available(): array
    {
        return ['geo' => $this->geo->isAvailable(), 'network' => $this->asnReader() !== null];
    }

    /** "Johannesburg, Gauteng, South Africa" for a page, or why there is none. */
    public function place(string $ip): string
    {
        return $this->geo->locate($ip);
    }

    /** The GeoLite2 ASN database beside GEOIP_DATABASE, opened once, or null when it is not there. */
    private function asnReader(): ?Reader
    {
        if (!$this->asnOpened) {
            $this->asnOpened = true;
            $city = Env::string('GEOIP_DATABASE');
            $file = $city !== '' ? dirname($city) . '/GeoLite2-ASN.mmdb' : '';
            try {
                if ($file !== '' && is_readable($file)) $this->asn = new Reader($file);
            } catch (Throwable) {
                $this->asn = null;
            }
        }

        return $this->asn;
    }

    /** @return array{0:?int,1:string} the network's number and name, when the ASN database is there */
    private function network(string $ip): array
    {
        $reader = $this->asnReader();
        if ($reader === null) return [null, ''];
        try {
            $record = $reader->asn($ip);

            return [$record->autonomousSystemNumber, (string) $record->autonomousSystemOrganization];
        } catch (Throwable) {
            return [null, ''];
        }
    }
}
