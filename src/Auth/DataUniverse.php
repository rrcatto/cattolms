Version: 0.5.8

Description:
The REAL / SEED / ALL query-scope vocabulary for the Seed Database data-universe boundary.

Architectural boundary: this is a pure value object. It holds no SQL beyond a reusable
predicate fragment, no table knowledge, no route knowledge and no authorisation logic.

The distinction this type exists to keep visible:

  permissions      answer what an identity may DO
  the universe     answers which business ROWS that identity may see or touch

They are separate mechanisms and must never be merged. A `.VIEW` permission does not widen a
universe, and a universe does not grant a capability.

There are exactly two business-data universes:

  REAL = seed_token IS NULL
  SEED = seed_token IS NOT NULL

ALL is not a third universe. It is the deliberate "no restriction" scope available only to a
genuine immutable ADMIN who has explicitly asked to see across the boundary.

Changelog:
2026/08/23 04:19 SAST
- Added shortLabel() for the rendered All / Real / Seed selector.
- Created for the v0.5.8 Seed Database phase.
*/

declare(strict_types=1);

namespace CattoLearning\Auth;

enum DataUniverse: string
{
    /** Genuine business data. The only universe anonymous and ordinary identities ever see. */
    case Real = 'real';

    /** Generated test data belonging to some seed set. */
    case Seed = 'seed';

    /**
     * No universe restriction. Genuine ADMIN only, and only when explicitly selected.
     *
     * The value is 'all' rather than 'both' so the enum and the documented request vocabulary
     * (universe=all|real|seed) are the same string, and no translation layer can drift.
     */
    case All = 'all';

    /**
     * Resolves an untrusted request value, falling back to the caller's own universe.
     *
     * An unrecognised value is never an error: a malformed filter in a URL must not break an
     * administration screen, and it must never widen scope by accident.
     */
    public static function fromRequest(mixed $value, self $fallback): self
    {
        if (!is_string($value)) {
            return $fallback;
        }

        return self::tryFrom(strtolower(trim($value))) ?? $fallback;
    }

    /** The universe an identity belongs to, derived from its seed token rather than its roles. */
    public static function forIdentity(?string $seedToken): self
    {
        return $seedToken === null || trim($seedToken) === '' ? self::Real : self::Seed;
    }

    /**
     * SQL predicate restricting a table to this universe, or null when unrestricted.
     *
     * Returned as a fragment rather than applied here so repositories keep ownership of their
     * own SQL, which is where the architecture check requires it to live. Callers pass the
     * table alias so the fragment composes with joins.
     */
    public function predicate(string $alias = ''): ?string
    {
        $column = ($alias === '' ? '' : $alias . '.') . 'seed_token';

        return match ($this) {
            self::Real => $column . ' IS NULL',
            self::Seed => $column . ' IS NOT NULL',
            self::All => null,
        };
    }

    /**
     * The same predicate as a WHERE-ready clause, so callers building a condition list do not
     * each reimplement the "unrestricted means omit the condition" case.
     *
     * @return list<string>
     */
    public function conditions(string $alias = ''): array
    {
        $predicate = $this->predicate($alias);

        return $predicate === null ? [] : [$predicate];
    }

    /** True when this scope may read rows outside the REAL universe. */
    public function includesSeed(): bool
    {
        return $this !== self::Real;
    }

    /** True when this scope may read genuine business rows. */
    public function includesReal(): bool
    {
        return $this !== self::Seed;
    }

    /** Display label for the genuine-ADMIN All / REAL / SEED selector. */
    public function label(): string
    {
        return match ($this) {
            self::Real => 'Real data',
            self::Seed => 'Seed data',
            self::All => 'All data',
        };
    }

    /**
     * The one-word form used on the selector itself.
     *
     * Three buttons reading "All data / Real data / Seed data" repeat the noun the surrounding
     * label already supplies, and the repetition is what pushes the control onto a second line
     * on a narrow screen. The long form stays for anywhere the word appears on its own.
     */
    public function shortLabel(): string
    {
        return match ($this) {
            self::Real => 'Real',
            self::Seed => 'Seed',
            self::All => 'All',
        };
    }
}
