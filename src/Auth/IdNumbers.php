declare(strict_types=1);

namespace CattoLearning\Auth;

use CattoLearning\Configuration\SecretCipher;
use CattoLearning\Infrastructure\Persistence\UserRepository;
use DateTimeImmutable;
use InvalidArgumentException;

final class IdNumbers
{
    public const TAKEN = 'That ID number already has an account. Sign in instead.';

    public function __construct(private readonly UserRepository $users, private readonly SecretCipher $cipher)
    {
    }

    /**
     * A number as a person types it, checked as valid and not held by another account.
     *
     * @throws InvalidArgumentException in plain words
     */
    public function check(mixed $input, ?int $forUserId = null): SouthAfricanIdNumber
    {
        $number = SouthAfricanIdNumber::fromInput($input, new DateTimeImmutable());
        $holder = $this->users->idNumberHolder($number->fingerprint());
        if ($holder !== null && $holder !== $forUserId) throw new InvalidArgumentException(self::TAKEN);

        return $number;
    }

    /** The number sealed for keeping until the account exists (a registration link's context). */
    public function seal(SouthAfricanIdNumber $number): string
    {
        return $this->cipher->encrypt($number->digits);
    }

    /** A sealed number opened again and checked once more. */
    public function open(string $sealed): SouthAfricanIdNumber
    {
        return SouthAfricanIdNumber::fromInput($this->cipher->decrypt($sealed), new DateTimeImmutable());
    }

    /** Keeps the number with the account, with the date of birth it holds and the country they live in. */
    public function save(int $userId, SouthAfricanIdNumber $number, ?string $residenceCountry = null): void
    {
        $holder = $this->users->idNumberHolder($number->fingerprint());
        if ($holder !== null && $holder !== $userId) throw new InvalidArgumentException(self::TAKEN);
        $this->users->saveIdNumber($userId, $this->cipher->encrypt($number->digits), $number->fingerprint(), $number->birthdate, $residenceCountry);
    }

    /** @return array{masked:string,residence_country:string} a person's ID number as pages show it, and where they live */
    public function shown(int $userId): array
    {
        $kept = $this->users->idNumber($userId);
        $digits = '';
        try {
            $digits = $kept['id_number_encrypted'] !== '' ? $this->cipher->decrypt($kept['id_number_encrypted']) : '';
        } catch (\RuntimeException) {
            $digits = '';
        }

        return ['masked' => SouthAfricanIdNumber::masked($digits), 'residence_country' => $kept['residence_country']];
    }
}
