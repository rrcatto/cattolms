namespace CattoLearning\Auth;

use CattoLearning\Infrastructure\Persistence\UserRepository;
use CattoLearning\Support\Env;
use CattoPHP\Access\Roles;
use CattoPHP\SignIn\SignInAccount;
use CattoPHP\SignIn\SignInAccounts;

final class CattolmsAccounts implements SignInAccounts
{
    public function __construct(private readonly UserRepository $users, private readonly Roles $roles)
    {
    }

    public function forEmail(string $email): ?SignInAccount
    {
        $id = $this->users->activeIdForVerifiedEmail($email);

        return $id === null ? null : $this->forId((string) $id);
    }

    public function forId(string $id): ?SignInAccount
    {
        if (preg_match('/^[1-9][0-9]{0,17}$/', $id) !== 1) return null;
        $account = $this->users->activeAccount((int) $id);
        if ($account === null) return null;
        $configured = strtolower(trim(Env::string('APP_ADMIN_EMAIL')));

        return new SignInAccount((string) $account['id'], $account['email'], $account['name'],
            $this->roles->isAdministrator((string) $account['id']) || ($configured !== '' && strtolower($account['email']) === $configured));
    }
}
