declare(strict_types=1);

namespace CattoLearning\Inbox;

use CattoLearning\Commerce\Document\FinancialDocuments;
use CattoPHP\Inbox\InboxDocuments;
use DateTimeImmutable;

final class InboxDocumentAttachments implements InboxDocuments
{
    public function __construct(private readonly InboxRepository $inbox, private readonly FinancialDocuments $documents)
    {
    }

    public function of(string $account): array
    {
        if (!ctype_digit($account)) return [];
        $documents = [];
        foreach ($this->inbox->documentsOf((int) $account) as $row) {
            $kind = ['invoice' => 'Invoice', 'receipt' => 'Receipt', 'credit_note' => 'Credit note'][(string) $row['kind']] ?? 'Document';
            $documents[] = ['id' => (int) $row['id'], 'number' => (string) $row['number'], 'kind' => $kind, 'label' => $kind . ' ' . $row['number'] . ', ' . (new DateTimeImmutable((string) $row['issued_at']))->format('j M Y')];
        }
        return $documents;
    }

    public function attachment(int $id): ?array
    {
        $document = $this->inbox->document($id);
        return $document === null ? null : [$this->documents->pdf($document), (string) $document['number'] . '.pdf', 'application/pdf'];
    }
}
