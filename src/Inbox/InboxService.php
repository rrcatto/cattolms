            $rows[] = ['id' => (int) $row['id'], 'reference' => (string) $row['reference'], 'href' => \CattoLearning\Support\Address\RecordAddress::message((string) $row['reference'], $status === 'draft' ? '#reply' : '#item-' . $row['id']),
                'to' => (string) $row['sender_name'], 'to_email' => (string) $row['to_email'], 'subject' => (string) $row['subject'],
                'excerpt' => mb_strlen((string) $row['body_text']) > 140 ? rtrim(mb_substr((string) $row['body_text'], 0, 137)) . '...' : (string) $row['body_text'],
                'format' => $row['format'] === 'html' ? 'HTML' : 'Plain text', 'when' => self::when((string) ($row['sent_at'] ?? $row['updated_at'])), 'error' => (string) ($row['error'] ?? '')];
        }
        return ['rows' => $rows, 'total' => $this->inbox->repliesCount($status, $search)];
    }

    /** @return list<array{key:string,points:int,words:string}> */
    private static function signs(string $json): array
    {
        $signs = json_decode($json, true);
        if (!is_array($signs)) return [];
        $out = [];
        foreach ($signs as $sign) {
            if (is_array($sign) && isset($sign['key'], $sign['points'], $sign['words'])) $out[] = ['key' => (string) $sign['key'], 'points' => (int) $sign['points'], 'words' => (string) $sign['words']];
        }
        return $out;
    }

    /**
     * @param array<string,mixed> $item
     * @return array<string,mixed>
     */
    private static function item(array $item): array
    {
        $label = match ([(string) $item['kind'], (string) $item['status']]) {
            ['message', 'received'] => 'Message received',
            ['acknowledgement', 'sent'] => 'Acknowledgement sent',
            ['reply', 'draft'] => 'Your draft reply',
            ['reply', 'failed'] => 'Your reply, not sent',
            ['reply', 'sent'] => 'Your reply',
            ['answer', 'received'] => 'Answer received',
            default => 'Message',
        };
        $attachments = json_decode((string) ($item['attachments'] ?? '[]'), true);
        return [
            'id' => (int) $item['id'], 'public_id' => (string) $item['public_id'], 'kind' => (string) $item['kind'], 'status' => (string) $item['status'],
            'direction' => (string) $item['direction'], 'label' => $label, 'format' => (string) $item['format'],
            'subject' => (string) $item['subject'], 'from_name' => (string) $item['from_name'], 'from_email' => (string) $item['from_email'], 'to_email' => (string) $item['to_email'],
            'body_text' => (string) $item['body_text'],
            'body_html' => $item['body_html'] !== null && $item['kind'] === 'reply' ? InboxHtml::clean((string) $item['body_html']) : '',
            'attachments' => is_array($attachments) ? $attachments : [],
            'mark_answered' => (bool) $item['mark_answered'],
            'written_by' => (string) ($item['written_by_name'] ?? ''),
            'error' => (string) ($item['error'] ?? ''),
            'when' => self::when((string) ($item['sent_at'] ?? $item['received_at'] ?? $item['updated_at'])),
        ];
    }

    private static function when(string $at): string
    {
        return $at === '' ? '' : (new DateTimeImmutable($at))->format('j M Y H:i');
    }
