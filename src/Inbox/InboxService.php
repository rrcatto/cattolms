    /**
     * A conversation as its page shows it: the message with its details (ContactService::present), the spam check's signs,
     * how it was sent, and every item, oldest first.
     *
     * @return array<string,mixed>|null
     */
    public function conversation(int $id): ?array
    {
        $row = $this->messages->find($id);
        $inbox = $this->inbox->conversation($id);
        if ($row === null || $inbox === null) return null;
        $view = ContactService::present($row) + [
            'folder' => (string) $inbox['folder'],
            'spam_score' => $inbox['spam_score'] !== null ? (int) $inbox['spam_score'] : null,
            'spam_signs' => self::signs((string) $inbox['spam_signals']),
            'spam_verdict' => $inbox['spam_verdict'],
            'read' => $inbox['read_at'] !== null,
            'country' => (string) ($inbox['sender_country'] ?? ''),
            'seconds_on_page' => $inbox['seconds_on_page'] !== null ? (int) $inbox['seconds_on_page'] : null,
            'browser' => $inbox['sender_agent'] !== null ? VisitorAgent::read((string) $inbox['sender_agent'])->label : '',
            'earlier' => $this->inbox->earlierFrom((string) $row['sender_email'], $id),
            'items' => array_map(self::item(...), $this->inbox->items($id)),
        ];
        $view['spam_line'] = $this->settings->spamLine();
        $score = $view['spam_score'] ?? 0;
        $view['spam_judgement'] = match (true) {
            $view['folder'] === 'spam' || $view['spam_verdict'] === 'spam' => ['label' => 'Spam', 'tone' => 'danger'],
            $view['spam_verdict'] === 'ham' => ['label' => 'Marked genuine', 'tone' => 'success'],
            $score >= $view['spam_line'] => ['label' => 'Looks like spam', 'tone' => 'danger'],
            $score >= 25 => ['label' => 'Unsure', 'tone' => 'warning'],
            default => ['label' => 'Looks genuine', 'tone' => 'success'],
        };
        return $view;
    }

    /**
     * A folder's page of conversations, each as its row shows it.
     *
     * @param array{show?:string,reason?:string,search?:string} $filters
     * @return array{rows:list<array<string,mixed>>,total:int}
     */
    public function folder(string $folder, array $filters, int $limit, int $offset, string $sort = 'newest'): array
    {
        $rows = [];
        foreach ($this->inbox->conversations($folder, $filters, $limit, $offset, $sort) as $row) {
            $answered = $row['answered_at'] !== null;
            $new = $row['read_at'] === null || (bool) $row['unread_answer'];
            $rows[] = [
                'id' => (int) $row['id'], 'reference' => (string) $row['reference'],
                'href' => \CattoLearning\Support\Address\RecordAddress::message((string) $row['reference']),
                'sender' => $row['person_id'] !== null
                    ? ['name' => (string) $row['sender_name'], 'reference' => (string) $row['person_reference'], 'href' => \CattoLearning\Support\Address\PersonAddress::admin((string) $row['person_reference'])]
                    : ['name' => (string) $row['sender_name'], 'reference' => '', 'href' => ''],
                'email' => (string) $row['sender_email'],
                'reason' => \CattoLearning\Contact\ContactReason::label((string) $row['reason']),
                'excerpt' => mb_strlen((string) $row['message']) > 140 ? rtrim(mb_substr((string) $row['message'], 0, 137)) . '...' : (string) $row['message'],
                'items' => (int) $row['items'],
                'when' => self::when((string) $row['last_activity_at']),
                'trashed' => $row['trashed_at'] !== null ? self::when((string) $row['trashed_at']) : '',
                'new' => $new,
                'status' => $row['unread_answer'] ? ['label' => 'Answer received', 'tone' => 'info'] : ($answered ? ['label' => 'Answered', 'tone' => 'success'] : ($new ? ['label' => 'New', 'tone' => 'warning'] : ['label' => 'Not answered', 'tone' => 'neutral'])),
                'spam_score' => $row['spam_score'] !== null ? (int) $row['spam_score'] : null,
                'spam_signs' => self::signs((string) $row['spam_signals']),
                'from_folder' => (string) ($row['folder_before_trash'] ?? ''),
                'gone' => match ((string) $row['folder']) {
                    'trash' => $this->engine->goneFor((string) $row['trashed_at'], $this->settings->trashKeptFor()),
                    'spam' => $this->engine->goneFor((string) $row['last_activity_at'], $this->settings->spamKeptFor()),
                    default => '',
                },
            ];
        }
        return ['rows' => $rows, 'total' => $this->inbox->count($folder, $filters)];
    }

