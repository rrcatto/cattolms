declare(strict_types=1);

namespace CattoLearning\Inbox;

use CattoLearning\Infrastructure\Persistence\Database;
use CattoPHP\Inbox\InboxStore;

final class InboxRepository
{
    public const FOLDERS = InboxStore::FOLDERS;
    public const SORTS = ['newest' => 'm.last_activity_at DESC, m.id DESC', 'oldest' => 'm.last_activity_at ASC, m.id ASC'];

    /** A person by their account, the user id in text. */
    private const PERSON = "CASE WHEN %s ~ '^[0-9]+$' THEN CAST(%s AS BIGINT) END";

    private const LIST = "SELECT m.id, m.reference, m.reason, m.sender_name, m.sender_email, %USER% AS user_id, m.account_reference, m.message, m.created_at,
            m.answered_at, m.read_at, m.unread_answer, m.folder, m.folder_before_trash, m.trashed_at, m.spam_score, m.spam_signals::text AS spam_signals,
            m.spam_verdict, m.last_activity_at, m.sender_country, m.seconds_on_page, m.sender_agent, u.id AS person_id, u.account_reference AS person_reference,
            (SELECT COUNT(*)::int FROM cattophp_inbox_items i WHERE i.conversation_id = m.id AND i.status <> 'draft') AS items
        FROM cattophp_inbox_conversations m LEFT JOIN users u ON u.id = %USER%";

    public function __construct(private readonly Database $db)
    {
    }

    /**
     * @param array{show?:string,reason?:string,search?:string} $filters
     * @return list<array<string,mixed>>
     */
    public function conversations(string $folder, array $filters, int $limit, int $offset, string $sort = 'newest'): array
    {
        [$where, $params] = self::where($folder, $filters);

        return $this->db->fetchAllAssociative(self::list() . ' WHERE ' . $where . ' ORDER BY ' . (self::SORTS[$sort] ?? self::SORTS['newest']) . ' LIMIT ' . max(1, $limit) . ' OFFSET ' . max(0, $offset), $params);
    }

    /** @param array{show?:string,reason?:string,search?:string} $filters */
    public function count(string $folder, array $filters): int
    {
        [$where, $params] = self::where($folder, $filters);

        return (int) $this->db->fetchOne('SELECT COUNT(*) FROM cattophp_inbox_conversations m WHERE ' . $where, $params);
    }

    /** @return array<string,mixed>|null a conversation as the lists read it, with the sender's account */
    public function conversation(int $id): ?array
    {
        $row = $this->db->fetchAssociative(self::list() . ' WHERE m.id = :id', ['id' => $id]);

        return $row === false ? null : $row;
    }

    /**
     * A conversation's items, oldest first, with who wrote each reply.
     *
     * @return list<array<string,mixed>>
     */
    public function items(int $conversationId): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT i.*, i.attachments::text AS attachments, u.display_name AS written_by_name FROM cattophp_inbox_items i LEFT JOIN users u ON u.id = " . sprintf(self::PERSON, 'i.written_by', 'i.written_by') . "
              WHERE i.conversation_id = :id AND i.trashed_at IS NULL AND i.status <> 'draft' ORDER BY (i.status = 'draft'), COALESCE(i.sent_at, i.received_at, i.created_at), i.id",
            ['id' => $conversationId]
        );
    }

    /**
     * The sender's other conversations, newest first: their references and whether each was answered.
     *
     * @return list<array{reference:string,answered:bool,folder:string}>
     */
    public function earlierFrom(string $email, int $exceptId): array
    {
        return array_map(static fn(array $row): array => ['reference' => (string) $row['reference'], 'answered' => $row['answered_at'] !== null, 'folder' => (string) $row['folder']],
            $this->db->fetchAllAssociative('SELECT reference, answered_at, folder FROM cattophp_inbox_conversations WHERE lower(sender_email) = lower(:email) AND id <> :id ORDER BY created_at DESC LIMIT 10', ['email' => $email, 'id' => $exceptId]));
    }

    /**
     * The drafts in the Trash, newest first, each with its conversation.
     *
     * @return list<array<string,mixed>>
     */
    public function trashedDrafts(): array
    {
        return $this->db->fetchAllAssociative(
            'SELECT i.id, i.body_text, i.trashed_at, m.id AS conversation_id, m.reference, m.sender_name FROM cattophp_inbox_items i JOIN cattophp_inbox_conversations m ON m.id = i.conversation_id
              WHERE i.trashed_at IS NOT NULL ORDER BY i.trashed_at DESC, i.id DESC'
        );
    }

    /**
     * Replies sent, or drafts saved, newest first, each with its conversation.
     *
     * @return list<array<string,mixed>>
     */
    public function replies(string $status, string $search, int $limit, int $offset): array
    {
        [$where, $params] = self::replyWhere($status, $search);

        return $this->db->fetchAllAssociative(
            "SELECT i.id, i.public_id, i.subject, i.body_text, i.format, i.status, i.to_email, i.sent_at, i.updated_at, i.error, m.id AS conversation_id, m.reference, m.sender_name, "
                . sprintf(self::PERSON, 'm.account', 'm.account') . " AS user_id, m.folder
               FROM cattophp_inbox_items i JOIN cattophp_inbox_conversations m ON m.id = i.conversation_id WHERE {$where} ORDER BY COALESCE(i.sent_at, i.updated_at) DESC, i.id DESC LIMIT " . max(1, $limit) . ' OFFSET ' . max(0, $offset),
            $params
        );
    }

    public function repliesCount(string $status, string $search): int
    {
        [$where, $params] = self::replyWhere($status, $search);

        return (int) $this->db->fetchOne("SELECT COUNT(*) FROM cattophp_inbox_items i JOIN cattophp_inbox_conversations m ON m.id = i.conversation_id WHERE {$where}", $params);
    }

    /**
     * An invoice, receipt or credit note a reply attaches.
     *
     * @return array<string,mixed>|null
     */
    public function document(int $id): ?array
    {
        $document = $this->db->fetchAssociative('SELECT * FROM commerce_documents WHERE id = :id', ['id' => $id]);

        return $document === false ? null : $document;
    }

    /**
     * A person's own invoices, receipts and credit notes, newest first (at most 60): what a reply to them may attach.
     *
     * @return list<array<string,mixed>>
     */
    public function documentsOf(int $userId): array
    {
        return $this->db->fetchAllAssociative(
            'SELECT d.id, d.number, d.kind, d.issued_at FROM commerce_documents d JOIN commerce_orders o ON o.id = d.order_id WHERE o.purchaser_user_id = :user ORDER BY d.issued_at DESC, d.id DESC LIMIT 60',
            ['user' => $userId]
        );
    }

    private static function list(): string
    {
        return str_replace('%USER%', sprintf(self::PERSON, 'm.account', 'm.account'), self::LIST);
    }

    /**
     * @param array{show?:string,reason?:string,search?:string} $filters
     * @return array{0:string,1:array<string,mixed>}
     */
    private static function where(string $folder, array $filters): array
    {
        $where = ['m.folder = :folder'];
        $params = ['folder' => in_array($folder, self::FOLDERS, true) ? $folder : 'inbox'];
        match ($filters['show'] ?? 'all') {
            'new' => $where[] = '(m.read_at IS NULL OR m.unread_answer)',
            'unanswered' => $where[] = 'm.answered_at IS NULL',
            'answered' => $where[] = 'm.answered_at IS NOT NULL',
            default => null,
        };
        if (($filters['reason'] ?? '') !== '') { $where[] = 'm.reason = :reason'; $params['reason'] = $filters['reason']; }
        $search = trim((string) ($filters['search'] ?? ''));
        if ($search !== '') {
            $where[] = "(m.reference ILIKE :search OR m.sender_name ILIKE :search OR m.sender_email ILIKE :search OR m.message ILIKE :search OR m.account_reference ILIKE :search
                OR EXISTS (SELECT 1 FROM cattophp_inbox_items i WHERE i.conversation_id = m.id AND (i.body_text ILIKE :search OR i.subject ILIKE :search)))";
            $params['search'] = '%' . addcslashes($search, '%_\\') . '%';
        }

        return [implode(' AND ', $where), $params];
    }

    /** @return array{0:string,1:array<string,mixed>} */
    private static function replyWhere(string $status, string $search): array
    {
        $params = ['status' => $status];
        $where = "i.status = :status AND i.kind = 'reply' AND i.trashed_at IS NULL";
        if (trim($search) !== '') {
            $where .= ' AND (i.subject ILIKE :search OR i.body_text ILIKE :search OR m.sender_name ILIKE :search OR m.sender_email ILIKE :search OR m.reference ILIKE :search)';
            $params['search'] = '%' . addcslashes(trim($search), '%_\\') . '%';
        }

        return [$where, $params];
    }
