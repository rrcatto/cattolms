{
    /** A company with this many people or courses or fewer opens them as cards, else as a table (owner, 2026-10-26). */
    public const GRID_UP_TO = ListView::COMPANY_PEOPLE_GRID_UP_TO;

    public const ORDER_STATES = ['placed' => ['Placed', 'warning'], 'awaiting_payment' => ['Waiting for payment', 'warning'], 'manual_review' => ['Being checked', 'info'], 'paid' => ['Paid', 'success'], 'fulfilled' => ['Paid, credits ready', 'success'], 'cancelled' => ['Cancelled', 'neutral'], 'partially_refunded' => ['Part refunded', 'info'], 'refunded' => ['Refunded', 'neutral']];

    public function __construct(
        private readonly PlatformAdministrationService $administration,
        private readonly AdministrationRepository $records,
        private readonly CompanyOverviewRepository $overview,
        private readonly ProfilePictures $pictures,
        private readonly ?WalletService $wallets = null,
        private readonly ?BillingProfileService $billing = null,
