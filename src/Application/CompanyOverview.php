    }

    /**
     * @param array<string,mixed> $query
     * @param array<string,mixed> $cookies
     * @return array<string,mixed>|null
     */
    public function view(int $companyId, CurrentUser $reader, array $query, array $cookies): ?array
    {
        $base = $this->administration->adminCompanyView($companyId);
        if ($base === null) return null;
        $company = $base['admin_company'];
        $can = static fn(string $permission): bool => $reader->hasPermission($permission);
        $address = '/admin/companies/' . $companyId;

        $data = ['admin_company' => $company, 'company_badges' => $this->badges($company)];
        $data['company_admins'] = $this->overview->administrators($companyId);
        $data['company_people_section'] = $can('PLATFORM.PERSON.VIEW') ? $this->people($companyId, $address, (string) $company['domain'], $query, $cookies) : null;
        $owned = $this->overview->ownedCourseFigures($companyId);
        $data['company_courses_section'] = $owned['total'] > 0 ? $this->courses($companyId, $owned, $address, $query, $cookies) : null;
        $data['company_learning'] = $this->learning($companyId);
        $data['company_credits'] = $can('PLATFORM.CREDIT.VIEW') ? $this->credits($companyId) : null;
        $data['company_orders_section'] = $can('PLATFORM.ORDER.VIEW') ? $this->orders($companyId) : null;
        $data['company_wallet'] = $can('PLATFORM.WALLET.VIEW') ? $this->wallet($companyId) : null;
        $billing = $this->billing?->forCompany($companyId);
        $data['company_billing'] = $billing === null ? [] : $billing->documentLines();
        $data['company_activity'] = $can('PLATFORM.ACTIVITY.VIEW') ? $this->administration->activityEvents(['company_id' => $companyId], 6) : null;
        $data['company_attention'] = $this->attention($companyId, $reader);
        $data['company_figures'] = $this->figures($data, $owned, (int) $base['people_total']);
        $data['assignable_roles'] = $can('PLATFORM.PERSON.MANAGE') ? $this->administration->assignableRoles() : [];

        return $data;
    }

    /**
     * @param array<string,mixed> $company
     * @return list<array{label:string,tone:string}>
     */
    private function badges(array $company): array
    {
        $status = (string) $company['status'];
        $badges = [['label' => ['active' => 'Active', 'disabled' => 'Disabled', 'deleted' => 'Deleted by its administrator'][$status] ?? ucfirst($status), 'tone' => ['active' => 'success', 'disabled' => 'danger'][$status] ?? 'neutral']];
        if ((bool) $company['is_client'] || !(bool) $company['is_course_provider']) $badges[] = ['label' => 'Client', 'tone' => 'info'];
        if ((bool) $company['is_course_provider']) $badges[] = ['label' => 'Course provider', 'tone' => 'info'];
        if ((string) $company['domain'] !== '') $badges[] = ['label' => (string) $company['domain'], 'tone' => 'neutral'];
        if ((string) ($company['account_reference'] ?? '') !== '') $badges[] = ['label' => 'Account Reference: ' . AccountReference::format((string) $company['account_reference']), 'tone' => 'neutral'];
        if ((string) ($company['created_at'] ?? '') !== '') $badges[] = ['label' => 'Since ' . (new DateTimeImmutable((string) $company['created_at']))->format('j F Y'), 'tone' => 'neutral'];

        return $badges;
    }

    /**
     * @param array<string,mixed> $query
     * @param array<string,mixed> $cookies
     * @return array<string,mixed>
     */
    private function people(int $companyId, string $address, string $domain, array $query, array $cookies): array
    {
        $search = PlatformAdministrationService::searchTerm('company_people', $query);
        $total = $this->records->companyPeopleCount($companyId, $search);
        $all = $search === '' ? $total : $this->records->companyPeopleCount($companyId);
        $view = ListView::chosen('company_people', $query, $cookies, $all <= self::GRID_UP_TO ? ListView::GRID : ListView::LIST);
        ListView::rememberAsked('company_people', $query);
        $pagination = Pagination::create($query[PlatformAdministrationService::pageParam('company_people')] ?? null, $query[PlatformAdministrationService::sizeParam('company_people')] ?? null, $total, 25);
        $people = [];
        foreach ($this->records->companyPeople($companyId, $pagination->pageSize, $pagination->offset, $search) as $person) {
            $role = (string) ($person['company_role'] ?? '');
            $people[] = [
                'id' => (int) $person['id'],
                'name' => PersonName::full($person),
                'account_reference' => (string) ($person['account_reference'] ?? ''),
                'email' => (string) $person['email'],
                'role' => PlatformAdministrationService::companyRoleWords($role),
                'role_tone' => in_array($role, ['owner', 'administrator'], true) ? 'info' : 'neutral',
                'course_count' => (int) ($person['course_count'] ?? 0),
                'last_login_at' => $person['last_login_at'] !== null ? (new DateTimeImmutable((string) $person['last_login_at']))->setTimezone(new DateTimeZone(date_default_timezone_get()))->format('j M Y') : '',
                'status' => (string) ($person['status'] ?? 'active'),
            ];
        }
        $filters = array_filter([PlatformAdministrationService::searchParam('company_people') => $search], static fn(string $v): bool => $v !== '');

        return [
            'people' => $this->pictures->withPictures($people),
            'total' => $total,
            'all' => $all,
            'search' => $search,
            'domain' => $domain,
            'view' => $view,
            'view_switch' => ListView::switcher('company_people', $view, $address, $filters),
            // No pager over an empty list.
            'pagination' => $total > 0 ? PlatformAdministrationService::paginationPayload('company_people', $pagination, $address, 'People', $filters) : null,
        ];
    }

    /**
     * @param array{total:int,published:int,draft:int,retired:int,learners:int} $figures
     * @param array<string,mixed> $query
     * @param array<string,mixed> $cookies
     * @return array<string,mixed>
     */
    private function courses(int $companyId, array $figures, string $address, array $query, array $cookies): array
    {
        $view = ListView::chosen('company_courses', $query, $cookies, $figures['total'] <= self::GRID_UP_TO ? ListView::GRID : ListView::LIST);
        ListView::rememberAsked('company_courses', $query);
        $courses = [];
        foreach ($this->overview->ownedCourses($companyId, 48) as $course) {
            $price = null;
            if ($course['price_minor_units'] !== null) {
                $currency = (string) $course['currency_code'];
                $price = ['price_label' => Money::strictMinorUnits((int) $course['price_minor_units'], $currency)->format()] + WasPrice::labels((int) $course['price_minor_units'], $course['was_price_minor_units'], $currency);
            }
            $courses[] = $course + ['price' => $price];
        }

        return ['courses' => $courses, 'figures' => $figures, 'view' => $view, 'view_switch' => ListView::switcher('company_courses', $view, $address), 'more' => max(0, $figures['total'] - count($courses))];
    }

    /** @return list<array<string,mixed>> each course its staff are on: how many, where they are, and how they did */
    private function learning(int $companyId): array
    {
        return array_map(static fn(array $row): array => [
            'id' => (int) $row['id'],
            'title' => (string) $row['title'],
            'on' => (int) $row['enrolments'],
            'not_started' => max(0, (int) $row['enrolments'] - (int) $row['started']),
            'in_progress' => max(0, (int) $row['started'] - (int) $row['completed']),
            'completed' => (int) $row['completed'],
            'average' => (int) $row['completed'] > 0 ? rtrim(rtrim(number_format((float) $row['average_result'], 1, '.', ''), '0'), '.') . '%' : '',
        ], $this->records->companyCourseReport($companyId, 12, 0));
    }

    /** @return array<string,mixed> */
    private function credits(int $companyId): array
    {
        $rows = $this->records->companyCredits($companyId, 25, 0);
        $orders = $this->overview->creditOrders(array_map(static fn(array $r): int => (int) $r['id'], $rows));
        $credits = [];
        foreach ($rows as $row) {
            $held = max(0, (int) $row['quantity'] - (int) $row['refunded_quantity']);
            $used = (int) $row['assigned_count'] + (int) $row['consumed_count'];
            $order = $orders[(int) $row['id']] ?? null;
            $credits[] = [
                'id' => (int) $row['id'],
                'course_id' => (int) $row['course_id'],
                'course_title' => (string) $row['course_title'],
                'held' => $held,
                'used' => $used,
                'left' => (int) $row['available_count'],
                'length' => AccessPeriod::label((int) $row['access_period_seconds']),
                'order_id' => $order,
                'source' => $order !== null ? 'Bought, order CL-' . str_pad((string) $order, 8, '0', STR_PAD_LEFT) : 'Given by hand',
                'can_take_back' => $order === null && (int) $row['available_count'] > 0,
            ];
        }

        return ['credits' => $credits, 'places' => $this->overview->creditPlaces($companyId), 'total' => $this->records->companyCreditsCount($companyId)];
    }

    /** @return array<string,mixed> */
    private function orders(int $companyId): array
    {
        $rows = $this->records->companyOrders($companyId, 6, 0);
        $what = $this->overview->orderSummaries(array_map(static fn(array $r): int => (int) $r['id'], $rows));
        $orders = [];
        foreach ($rows as $row) {
            [$label, $tone] = self::ORDER_STATES[(string) $row['state']] ?? [ucfirst((string) $row['state']), 'neutral'];
            $orders[] = [
                'id' => (int) $row['id'],
                'number' => 'CL-' . str_pad((string) $row['id'], 8, '0', STR_PAD_LEFT),
                'placed' => (new DateTimeImmutable((string) $row['placed_at']))->setTimezone(new DateTimeZone(date_default_timezone_get()))->format('j M Y'),
                'what' => $what[(int) $row['id']] ?? '',
                'amount' => Money::ofMinorUnits((int) $row['total_minor'], (string) $row['currency'])->format(),
                'due' => (int) $row['due_minor'] > 0 ? Money::ofMinorUnits((int) $row['due_minor'], (string) $row['currency'])->format() : '',
                'state' => $label,
                'tone' => $tone,
                'buyer' => $row['purchaser_user_id'] !== null ? ['name' => (string) ($row['purchaser_name'] ?? ''), 'reference' => (string) ($row['purchaser_reference'] ?? ''), 'href' => '/admin/people/' . (int) $row['purchaser_user_id']] : null,
            ];
        }
        $money = $this->overview->orderMoney($companyId);
        $unpaid = $this->overview->unpaidOrders($companyId);
        $due = array_sum(array_map(static fn(array $o): int => (int) $o['due_minor'], $unpaid));

        return ['orders' => $orders, 'total' => $money['orders'],
            'paid' => Money::ofMinorUnits($money['paid_minor'], $money['currency'])->format(), 'paid_orders' => $money['paid_orders'],
            'due' => Money::ofMinorUnits($due, $money['currency'])->format(), 'due_minor' => $due, 'unpaid_orders' => count($unpaid)];
    }

    /** @return array<string,mixed>|null */
    private function wallet(int $companyId): ?array
    {
        if ($this->wallets === null) return null;
        $owner = WalletOwner::company($companyId);
        $statement = $this->wallets->statement($owner, 3, 0);

        return [
            'balance' => Money::ofMinorUnits($this->wallets->spendable($owner))->format(),
            'expiring' => $this->wallets->expiringSoon($owner)[0] ?? null,
            'movements' => array_map(static fn(array $row): array => ['label' => (string) $row['label'] . ((string) $row['order_label'] !== '' ? ', ' . $row['order_label'] : ''), 'in' => (string) $row['in_label'], 'out' => (string) $row['out_label'],
                'when' => (new DateTimeImmutable((string) ($row['occurred_at'] ?? $row['created_at'] ?? 'now')))->setTimezone(new DateTimeZone(date_default_timezone_get()))->format('j M Y')], $statement['rows']),
            'entries' => (int) $statement['total'],
            'href' => '/admin/wallets/company/' . $companyId,
        ];
    }

    /** @return list<array<string,mixed>> what waits for an administrator about this company, in the dashboard's shape */
    private function attention(int $companyId, CurrentUser $reader): array
    {
        $items = [];
        if ($reader->hasPermission('PLATFORM.REQUEST.MANAGE')) {
            foreach ($this->overview->pendingRequests($companyId) as $request) {
                $items[] = ['kind' => 'request', 'badge' => 'Course request', 'subject' => true,
                    'person' => ['name' => (string) $request['name'], 'reference' => (string) $request['account_reference'], 'href' => '/admin/people/' . (int) $request['user_id']],
                    'title' => 'asked for ' . $request['course_title'],
                    'summary' => 'On ' . (new DateTimeImmutable((string) $request['requested_at']))->format('j F Y') . '. Approve it to give them the course, or reject it.',
                    'href' => '/admin/course/requests?requests_status=pending#request-' . (int) $request['id'], 'action' => 'Approve or reject', 'icon' => 'action-approve'];
            }
        }
        if ($reader->hasPermission('PLATFORM.ORDER.VIEW')) {
            foreach ($this->overview->unpaidOrders($companyId) as $order) {
                if ((int) $order['due_minor'] < 1) continue;
                $due = $order['payment_due_at'] !== null ? ', due by ' . (new DateTimeImmutable((string) $order['payment_due_at']))->setTimezone(new DateTimeZone(date_default_timezone_get()))->format('j F Y') : '';
                $items[] = ['kind' => 'money', 'badge' => 'Order', 'subject' => false, 'person' => null,
                    'title' => 'Order CL-' . str_pad((string) $order['id'], 8, '0', STR_PAD_LEFT) . ' waits for payment',
                    'summary' => Money::ofMinorUnits((int) $order['due_minor'], (string) $order['currency'])->format() . ' to pay' . $due . '.',
                    'href' => '/admin/commerce/orders/' . (int) $order['id'], 'action' => 'Open the order', 'icon' => 'action-view'];
            }
        }

        return $items;
    }

    /**
     * The figures under the head, each opening its part of the page; one only when its part is shown.
     *
     * @param array<string,mixed> $data
     * @param array{total:int,published:int,draft:int,retired:int,learners:int} $owned
     * @return list<array<string,mixed>>
     */
    private function figures(array $data, array $owned, int $peopleTotal): array
    {
        $admins = count($data['company_admins']);
        $figures = [];
        if ($data['company_people_section'] !== null) $figures[] = ['value' => $peopleTotal, 'label' => $peopleTotal === 1 ? 'Person' : 'People', 'note' => $admins === 1 ? '1 Company Administrator' : $admins . ' Company Administrators', 'icon' => 'figure-people', 'href' => '#people'];
        if ($owned['total'] > 0) {
            $figures[] = ['value' => $owned['total'], 'label' => 'Courses it provides', 'note' => $owned['published'] . ' published, ' . $owned['draft'] . ' draft', 'icon' => 'figure-courses', 'href' => '#provided'];
            $figures[] = ['value' => $owned['learners'], 'label' => 'Learners on its courses', 'note' => 'Everyone on them, its staff or not', 'icon' => 'figure-enrolments', 'href' => '#provided'];
        }
        $results = $this->overview->staffResults((int) $data['admin_company']['id']);
        $figures[] = ['value' => $results['completed'], 'label' => 'Staff courses completed', 'note' => $results['average'] !== null ? 'Average result ' . (int) $results['average'] . '%' : 'None yet', 'icon' => 'figure-completion', 'href' => '#learning'];
        if ($data['company_credits'] !== null) {
            $places = $data['company_credits']['places'];
            $figures[] = ['value' => $places['left'], 'label' => 'Credit places left', 'note' => 'Of ' . $places['held'] . ' held', 'icon' => 'figure-credits', 'href' => '#credits'];
        }
        if ($data['company_wallet'] !== null) {
            $expiring = $data['company_wallet']['expiring'];
            $figures[] = ['value' => $data['company_wallet']['balance'], 'label' => 'Wallet credit', 'note' => $expiring !== null ? $expiring['amount_label'] . ' expires ' . $expiring['expires_label'] : 'Nothing expiring soon', 'icon' => 'figure-wallet-held', 'href' => '#wallet', 'size' => 'small'];
        }
        if ($data['company_orders_section'] !== null) {
            $orders = $data['company_orders_section'];
            $figures[] = ['value' => $orders['paid'], 'label' => 'Paid', 'note' => $orders['paid_orders'] === 1 ? 'Over 1 order' : 'Over ' . $orders['paid_orders'] . ' orders', 'icon' => 'figure-money-in', 'href' => '#orders', 'size' => 'small'];
            $figures[] = ['value' => $orders['due'], 'label' => 'Waiting for payment', 'note' => $orders['unpaid_orders'] === 1 ? '1 order' : $orders['unpaid_orders'] . ' orders', 'icon' => 'figure-awaiting', 'href' => '#orders', 'size' => 'small'];
        }

        return $figures;
    }
