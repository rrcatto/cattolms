declare(strict_types=1);

namespace CattoLearning\Application;

use CattoLearning\Bundle\BundleService;
use CattoLearning\Course\CourseService;
use CattoLearning\Course\LearningService;
use CattoLearning\Infrastructure\Persistence\FavouritesRepository;
use CattoLearning\Support\ListView;
use CattoPHP\Ui\Pagination;
use InvalidArgumentException;

final class AccountFavourites
{
    public const DATASET = 'favourites';

    /** The feature cards above the list: what each shows, and the words after its count. */
    public const KINDS = [
        'all' => ['label' => 'All favourites', 'note' => 'courses and bundles', 'one' => 'course or bundle'],
        'courses' => ['label' => 'Courses', 'note' => 'courses', 'one' => 'course'],
        'bundles' => ['label' => 'Bundles', 'note' => 'bundles', 'one' => 'bundle'],
    ];

    public function __construct(
        private readonly FavouritesRepository $favourites,
        private readonly CourseService $courses,
        private readonly BundleService $bundles,
        private readonly PlatformAdministrationService $administration,
    ) {}

    /**
     * Favourites for its page and for the Account workspace.
     *
     * @param array<string,mixed> $request kind (null: all), favourites_view, and the dataset's page, page size and search
     * @return array<string,mixed>
     */
    public function view(int $userId, array $request): array
    {
        $kind = $request['kind'] ?? 'all';
        if (!is_string($kind) || !isset(self::KINDS[$kind])) throw new InvalidArgumentException('There is no such list of favourites.');
        $view = (string) ($request[self::DATASET . '_view'] ?? ListView::GRID);
        $counts = $this->counts($userId, '');
        $kinds = [];
        foreach (self::KINDS as $key => $definition) {
            $count = $counts[$key];
            $kinds[] = ['value' => $key, 'label' => $definition['label'], 'note' => $count === 0 ? 'None yet' : $count . ' ' . ($count === 1 ? $definition['one'] : $definition['note'])];
        }
        $search = PlatformAdministrationService::searchTerm(self::DATASET, $request);
        $total = $search === '' ? $counts[$kind] : $this->counts($userId, $search)[$kind];
        $request[self::DATASET . '_view'] = $view;
        $pagination = $this->administration->paginationFor(self::DATASET, $request, $total);
        $filters = array_filter(['kind' => $kind === 'all' ? '' : $kind, PlatformAdministrationService::searchParam(self::DATASET) => $search]);

        return [
            'favourites_kind' => $kind,
            'favourites_kinds' => $kinds,
            'favourites_cards' => $this->cards($userId, $kind, $search, $pagination),
            'favourites_search' => $search,
            'favourites_searchable' => $counts[$kind] >= LearningService::LIBRARY_SEARCH_FROM || $search !== '',
            'favourites_view' => $view,
            'favourites_view_switch' => ListView::switcher(self::DATASET, $view, '/account/favourites', $filters),
            // Each card's star, which unstars it in place and comes back here without JavaScript.
            'can_favourite' => true,
            'favourite_return' => '/account/favourites',
        ] + $this->administration->paginationView(self::DATASET, $pagination, '/account/favourites', 'Favourites', $filters, PlatformAdministrationService::listSizes(self::DATASET, $request));
    }

    /**
     * How many favourites of each kind the person has, narrowed by a search of their titles.
     *
     * @return array{all:int,courses:int,bundles:int}
     */
    private function counts(int $userId, string $search): array
    {
        $counts = $this->favourites->counts($userId, $search);
        return ['all' => $counts['courses'] + $counts['bundles']] + $counts;
    }

    /**
     * One page of the chosen favourites as the catalogue's cards, newest star first, each starred, with its kind.
     *
     * @return list<array<string,mixed>>
     */
    private function cards(int $userId, string $kind, string $search, Pagination $pagination): array
    {
        $rows = $this->favourites->page($userId, $kind !== 'bundles', $kind !== 'courses', $search, $pagination->pageSize, $pagination->offset);
        $courseIds = $bundleIds = [];
        foreach ($rows as $row) {
            if ($row['kind'] === 'course') $courseIds[] = (int) $row['item_id'];
            else $bundleIds[] = (int) $row['item_id'];
        }
        $courseCards = [];
        foreach ($this->courses->cardsByIds($courseIds) as $card) $courseCards[(int) $card['id']] = $card + ['kind' => 'course', 'is_favourite' => true, 'href' => '/courses/' . $card['slug']];
        $bundleCards = [];
        foreach ($this->bundles->cardsByIds($bundleIds) as $card) $bundleCards[(int) $card['bundle_id']] = $card + ['kind' => 'bundle', 'is_favourite' => true];
        $cards = [];
        foreach ($rows as $row) {
            $card = $row['kind'] === 'course' ? ($courseCards[(int) $row['item_id']] ?? null) : ($bundleCards[(int) $row['item_id']] ?? null);
            if ($card !== null) $cards[] = $card;
        }
        return $cards;
    }
}
