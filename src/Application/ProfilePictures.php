(View\Artwork\DrawnAvatar): nobody is without a picture and no picture is stored for them. "Show me another" saves a
random seed, and "Back to my first one" forgets it.

Each picture has a version, a short fingerprint that changes with it, for the addresses that serve it with a week-long
private cache: a new upload or a new avatar is a new address.

