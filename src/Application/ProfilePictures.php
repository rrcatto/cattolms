declare(strict_types=1);

namespace CattoLearning\Application;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\UserProfileRepository;
use CattoLearning\View\Artwork\DrawnAvatar;
use RuntimeException;

final class ProfilePictures
{
    public function __construct(
        private readonly UserProfileRepository $profiles,
        private readonly AuditRepository $audit,
    ) {
    }

    /**
     * What a person's picture is and its version, without reading or drawing it.
     *
     * @return array{drawn:bool,chosen:bool,version:string}|null null for an account that does not exist
     */
    public function state(int $userId): ?array
    {
        $state = $this->profiles->pictureState($userId);
        if ($state === null) {
            return null;
        }

        return [
            'drawn' => !$state['uploaded'],
            'chosen' => $state['chosen'],
            'version' => self::versionOf($state),
        ];
    }

    /**
     * Each person row with the address of their picture ("picture_url": Administration's, or the Company workspace's
     * with its prefix and suffix), in one query for the page.
     *
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    public function withPictures(array $rows, string $prefix = '/admin/people/', string $suffix = '/profile-image'): array
    {
        $states = $this->profiles->pictureStates(array_map(static fn(array $row): int => (int) ($row['id'] ?? 0), $rows));
        foreach ($rows as $index => $row) {
            $state = $states[(int) ($row['id'] ?? 0)] ?? null;
            $rows[$index]['picture_url'] = $state === null ? '' : $prefix . (int) $row['id'] . $suffix . '?v=' . self::versionOf($state);
            $rows[$index]['picture_drawn'] = $state !== null && !$state['uploaded'];
        }

        return $rows;
    }

    /**
     * A picture's version from UserProfileRepository::pictureState().
     *
     * @param array{uploaded:bool,upload_version:string,seed:string,chosen:bool} $state
     */
    public static function versionOf(array $state): string
    {
        return $state['uploaded'] ? $state['upload_version'] : 'a' . DrawnAvatar::version('person', $state['seed']);
    }

    /**
     * The picture itself: the upload's bytes, or the drawn avatar as SVG.
     *
     * @return array{bytes:string,mime_type:string,drawn:bool,version:string}
     */
    public function picture(int $userId): array
    {
        $state = $this->profiles->pictureState($userId) ?? throw new RuntimeException('The user account does not exist.');
        if ($state['uploaded']) {
            $image = $this->profiles->image($userId);
            if ($image !== null) {
                return ['bytes' => $image['bytes'], 'mime_type' => $image['mime_type'], 'drawn' => false, 'version' => $state['upload_version']];
            }
        }

        return [
            'bytes' => DrawnAvatar::person($state['seed']),
            'mime_type' => 'image/svg+xml',
            'drawn' => true,
            'version' => self::versionOf(['uploaded' => false] + $state),
        ];
    }

    /** "Show me another": a new drawn avatar, kept until the next. */
    public function showAnother(int $userId): void
    {
        $this->profiles->setAvatarSeed($userId, DrawnAvatar::newSeed());
        $this->audit->record($userId, 'profile.avatar_changed', ['user_id' => $userId]);
    }

    /** "Back to my first one": the avatar drawn from the account itself. */
    public function firstAgain(int $userId): void
    {
        $this->profiles->setAvatarSeed($userId, null);
        $this->audit->record($userId, 'profile.avatar_changed', ['user_id' => $userId, 'first' => true]);
    }
}
