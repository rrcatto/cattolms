declare(strict_types=1);

namespace CattoLearning\Application;

use CattoLearning\Auth\TwoStep\TwoStep;
use CattoLearning\Auth\TwoStepPolicy;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoPHP\Telegram\TelegramAccounts;

class SignInSecurityAdministration
{
    public function __construct(
        private readonly TwoStepPolicy $policy,
        private readonly TwoStep $twoStep,
        private readonly TelegramAccounts $telegram,
        private readonly AuditRepository $audit,
    ) {
    }

    /** @return array{value:string,source:string,environment:string,choices:array<string,array{label:string,note:string}>,summary:string} Settings > Two-step sign-in */
    public function settingsView(): array
    {
        $value = $this->policy->value();

        return ['value' => $value, 'source' => $this->policy->source(), 'environment' => $this->policy->environmentValue(), 'choices' => TwoStepPolicy::CHOICES,
            'summary' => TwoStepPolicy::CHOICES[$value]['label'] . '.'];
    }

    public function savePolicy(string $value, int $actorUserId): void
    {
        $before = $this->policy->value();
        $this->policy->save($value);
        $this->audit->record($actorUserId, 'settings.two_step_saved', ['before' => $before, 'after' => $this->policy->value()]);
    }

    public function resetPolicy(int $actorUserId): void
    {
        $before = $this->policy->value();
        $this->policy->reset();
        $this->audit->record($actorUserId, 'platform.setting_reset', ['setting' => 'two_step', 'source' => '.env', 'before' => $before, 'after' => $this->policy->value()]);
    }

    /**
     * A person's Sign-in card: their Telegram account and their two-step.
     *
     * @return array{telegram:?array{username:?string,connected_on:string},two_step:array{on:bool,since:string,left:int}}
     */
    public function personView(int $userId): array
    {
        $telegram = $this->telegram->forAccount((string) $userId);

        return ['telegram' => $telegram === null ? null : ['username' => $telegram['username'], 'connected_on' => (new \DateTimeImmutable($telegram['connected_at']))->setTimezone(new \DateTimeZone(date_default_timezone_get()))->format('j F Y')],
            'two_step' => $this->twoStep->state($userId)];
    }

    /** Reset two-step (a person's page): never one's own. Whether there was anything to reset. */
    public function resetTwoStep(int $targetUserId, int $actorUserId): bool
    {
        return $this->twoStep->reset($targetUserId, $actorUserId);
    }
}
