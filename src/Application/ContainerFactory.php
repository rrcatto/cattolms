        $builder = new ContainerBuilder();
        $builder->useAutowiring(true);
        $builder->writeProxiesToFile(true, $proxyRoot);

        $builder->addDefinitions([
            'catto.code_root' => value($codeRoot),
            'catto.instance_root' => value($instanceRoot),
            'catto.public_root' => value($publicRoot),

            Base::class => $f3 !== null
