final class ContainerFactory
{
    public static function build(
        string $codeRoot,
        string $instanceRoot,
        string $publicRoot,
        ?Base $f3 = null
    ): ContainerInterface {
        $cacheRoot = rtrim($instanceRoot, '/') . '/storage/cache';
        $proxyRoot = $cacheRoot . '/di-proxies';
        if (!is_dir($proxyRoot) && !mkdir($proxyRoot, 0775, true) && !is_dir($proxyRoot)) {
            throw new RuntimeException('Unable to create the PHP-DI proxy cache directory: ' . $proxyRoot);
        }

        $builder = new ContainerBuilder();
        $builder->useAutowiring(true);
        $builder->writeProxiesToFile(true, $proxyRoot);

        $builder->addDefinitions([
            'catto.code_root' => value($codeRoot),
            'catto.instance_root' => value($instanceRoot),
            'catto.public_root' => value($publicRoot),

            Base::class => $f3 !== null
                ? value($f3)
                : factory(static fn(): Base => Base::instance()),

            SQL::class => factory(static fn(): SQL => ConnectionFactory::create()),

            // DBAL over the connection F3 already opened, not a second one.
            //
            // Repositories are converted from mappers and DB\SQL to DBAL a few at a time, so for the
            // whole of that phase both wrappers are in use - and fifty call sites run inside
            // TransactionManager::run(). A transaction belongs to a connection: a second session
            // would put a converted repository's writes outside the transaction an unconverted one
            // began, and a rollback would leave half the work committed with nothing failing.
            //
            // Temporary. When the last repository is converted, DB\SQL goes and DBAL opens its own
            // connection through DriverManager in the ordinary way.
            DbalConnection::class => factory(static fn(SQL $db): DbalConnection => new DbalConnection(
                [],
                new SharedPdoDriver($db->pdo()),
                new DbalConfiguration()
            )),

            GeoIpLocator::class => autowire()
                ->constructorParameter('databasePath', Env::string('GEOIP_DATABASE')),

            // Mail is a suitable selective lazy dependency: most requests do
            // not send mail, so RuntimeSettings/mail construction is deferred
            // until a MailerInterface method is actually called.
            // Mail addressed to a generated seed identity is redirected to the one real inbox
            // the operator controls. The decorator wraps the interface rather than the transport,
            // so every send path inherits it without knowing seed data exists.
            // Built from RuntimeSettings, not from Env directly, so that the domain shown in
            // Administration and the domain seed mail is actually delivered to are the same value.
            // Reading .env here would let an administrator save a domain that was displayed but
            // never used - a divergence with no symptom until someone waited for mail that had
            // gone somewhere else.
            SeedMailRouter::class => factory(static fn(RuntimeSettings $settings): SeedMailRouter
                => new SeedMailRouter($settings->seedSystemCompanyDomain())),
            MailerInterface::class => autowire(SeedAwareMailer::class)->lazy(),

            ThemeManager::class => autowire()
                ->constructorParameter('codeRoot', $codeRoot)
                ->constructorParameter('instanceRoot', $instanceRoot)
                ->constructorParameter('publicRoot', $publicRoot),

            CourseService::class => autowire()
                ->constructorParameter('storageRoot', $instanceRoot . '/storage'),

            CoursePortabilityService::class => autowire()
                ->constructorParameter('storageRoot', $instanceRoot . '/storage')
                ->constructorParameter('bundledImportRoot', $codeRoot . '/resources/course-imports'),

            // The seed name lists follow the same rule as bundled course imports and themes: a copy
            // ships in the release, the installer publishes it to the instance, and the instance
            // copy is the one that is read - so an operator's edits survive every upgrade.
            SeedNamePools::class => autowire()
                ->constructorParameter('instanceRoot', $instanceRoot . '/storage/seeds')
                ->constructorParameter('bundledRoot', $codeRoot . '/resources/seeds'),
        ]);

        /** @var Container $container */
        $container = $builder->build();
        return $container;
    }
