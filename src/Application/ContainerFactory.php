        $cacheRoot = rtrim($instanceRoot, '/') . '/storage/cache';
        $proxyRoot = $cacheRoot . '/di-proxies';
        if (!is_dir($proxyRoot) && !mkdir($proxyRoot, 0775, true) && !is_dir($proxyRoot)) {
            throw new RuntimeException('Unable to create the PHP-DI proxy cache directory: ' . $proxyRoot);
