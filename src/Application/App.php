    public static function run(string $codeRoot, string $instanceRoot, string $publicRoot): void
    {
        $codeRoot = self::normaliseDirectory($codeRoot, 'application code');
        $instanceRoot = self::normaliseDirectory($instanceRoot, 'instance');
        $publicRoot = self::normaliseDirectory($publicRoot, 'public web');

        $envFile = $instanceRoot . '/.env';
        if (!is_file($envFile)) {
            throw new RuntimeException('The instance .env file does not exist: ' . $envFile);
        }
        Dotenv::createImmutable($instanceRoot)->load();

        date_default_timezone_set(Env::string('APP_TIMEZONE', 'Africa/Johannesburg'));
        $appKey = Env::string('APP_KEY');
        if (strlen($appKey) < 32 || str_starts_with($appKey, 'replace-')) {
            throw new RuntimeException('APP_KEY must be set to a private random value of at least 32 characters.');
        }

        $cacheRoot = $instanceRoot . '/storage/cache';
        self::requireWritableDirectory($cacheRoot);
        $logRoot = $instanceRoot . '/storage/logs';
        self::requireWritableDirectory($logRoot);
        self::requireWritableDirectory($publicRoot . '/themes');
        self::requireWritableDirectory($instanceRoot . '/themes');
        self::requireWritableDirectory($instanceRoot . '/storage/course-media');
        self::requireWritableDirectory($instanceRoot . '/storage/imports');

        ini_set('log_errors', '1');
        ini_set('error_log', $logRoot . '/application.log');
        self::logRequest();

        self::startSession(new DbalDatabase(ConnectionFactory::create()));

        // Symfony owns every route, the container and the error page. Fat-Free is gone.
        self::handleWithSymfony($instanceRoot);
    }

    /**
     * Writes one lightweight line for every dynamic HTTP request.
     *
     * Only the URL path is logged: query strings are deliberately excluded so
     * magic-link tokens and other request parameters never enter application.log.
     */
    private static function logRequest(): void
    {
        $method = strtoupper(trim((string) ($_SERVER['REQUEST_METHOD'] ?? '')));
        if ($method === '') {
            return;
        }

        $requestUri = (string) ($_SERVER['REQUEST_URI'] ?? '/');
        $path = parse_url($requestUri, PHP_URL_PATH);
        if (!is_string($path) || $path === '') {
            $path = '/';
        }

        error_log(sprintf('HTTP %s %s', $method, $path));
    }

    /**
     * Hands the request to the Symfony kernel, which owns every route.
     *
     * There is no second router to fall through to and no ownership question left to ask: the
     * kernel handles the request, answers its own 404 when nothing matches, and terminates.
     * The dual-router arrangement this method carried during the migration is gone with
     * Fat-Free, and reintroducing one is a build failure - check-runtime-hazards.php greps this
     * bootstrap for the Fat-Free entry point and fails if it ever reappears.
     */
    private static function handleWithSymfony(string $instanceRoot): void
    {
        $kernel = new Kernel(
            Env::string('APP_ENV', 'production'),
            Env::bool('APP_DEBUG', false),
            $instanceRoot
        );
        $kernel->boot();

        $request = Request::createFromGlobals();
        $response = $kernel->handle($request);
        $response->send();
        $kernel->terminate($request, $response);
    }

    private static function startSession(Database $db): void
    {
        if (session_status() === PHP_SESSION_ACTIVE) {
            return;
        }
        session_name(Env::string('PHP_SESSION_COOKIE', 'catto_learning_web'));
        session_set_cookie_params([
            'lifetime' => 0,
            'path' => '/',
            'domain' => '',
            'secure' => Env::bool('PHP_SESSION_SECURE', true),
            'httponly' => true,
            'samesite' => 'Lax',
        ]);
        session_set_save_handler(
            new DatabaseSessionHandler($db, Env::int('PHP_SESSION_TTL', 86400)),
            true
        );
        session_start();
    }

    private static function normaliseDirectory(string $directory, string $label): string
    {
        $resolved = realpath($directory);
        if ($resolved === false || !is_dir($resolved)) {
            throw new RuntimeException('The ' . $label . ' directory does not exist: ' . $directory);
        }
        return rtrim($resolved, '/');
    }

    private static function requireWritableDirectory(string $directory): void
    {
        if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) {
            throw new RuntimeException('Unable to create required directory: ' . $directory);
        }
        if (!is_writable($directory)) {
            throw new RuntimeException('Required directory is not writable: ' . $directory);
        }
    }
