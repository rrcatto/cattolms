    /**
     * The filter chips above Course Requests, built here so every link carries the search term and
     * the universe the reader already had.
     *
     * @param array<string,mixed> $filters
     * @return list<array{key:string,label:string,href:string,active:bool}>
     */
    public static function requestStatusFilters(string $selected, string $base, array $filters): array
    {
        $carried = $filters;
        unset($carried['requests_status'], $carried['requests_page']);

        $chips = [['key' => '', 'label' => 'All', 'href' => '', 'active' => $selected === '']];
        foreach (self::REQUEST_STATUS_LABELS as $key => $meta) {
            $chips[] = ['key' => $key, 'label' => $meta['label'], 'href' => '', 'active' => $selected === $key];
        }

        foreach ($chips as &$chip) {
            $query = $carried + ($chip['key'] === '' ? [] : ['requests_status' => $chip['key']]);
            $chip['href'] = $query === [] ? $base : $base . '?' . http_build_query($query);
        }

        return $chips;
    }

