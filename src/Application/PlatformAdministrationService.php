    /** @param array<string,mixed> $input */
    public function updateCompany(int $companyId, array $input, int $actorUserId): void
    {
        $name = trim((string) ($input['name'] ?? ''));
        $domain = strtolower(trim((string) ($input['domain'] ?? '')));
        $type = (string) ($input['company_type'] ?? 'client');
        $company = $this->companies->findById($companyId);
        if ($company === null) {
            throw new RuntimeException('The company does not exist.');
        }
        if ($name === '' || $domain === '' || str_contains($domain, '@') || str_contains($domain, '/') || filter_var('admin@' . $domain, FILTER_VALIDATE_EMAIL) === false) {
            throw new InvalidArgumentException('Enter a company name and one valid registered email domain.');
        }
        if ($this->companies->domainExistsForOther($domain, $companyId)) {
            throw new InvalidArgumentException('That company email domain is already registered.');
        }
        $this->companies->updateManaged($companyId, $name, $domain, $type);
        if (in_array($company['is_system'] ?? false, [true,1,'1','t','true'], true)) {
            $this->options->set('system_company_name', $name, $actorUserId);
        }
        $this->audit->record($actorUserId, 'company.updated', ['company_id' => $companyId]);
    }

    /**
     * Activates or suspends a company.
     *
     * Suspension is a real suspension, not a listing flag. Disabling ends the company's ordinary
     * members' sessions in the same transaction as the status change, so it takes effect at once
     * rather than as each session happens to expire; `AuthService` then refuses both a new sign-in
     * and any surviving session. A platform administrator is exempt throughout, so suspending a
     * company can never lock the installation away from its owner.
     *
     * Re-enabling deliberately does nothing beyond the status. Sessions are not restored - they
     * cannot be - and nothing needs repairing: memberships, enrolments, progress and certificates
     * were never touched, so an eligible active member simply signs in again and resumes. A person
     * disabled in their own right stays disabled, because that was a separate decision about them.
     *
     * The System Company cannot be suspended; CompanyRepository refuses it, which is where the
     * invariant belongs rather than in a hidden UI button.
     */
    public function setCompanyStatus(int $companyId, string $status, int $actorUserId): void
    {
        $this->transactions->run(function () use ($companyId, $status, $actorUserId): void {
            $this->companies->setStatus($companyId, $status);

            $revoked = $status === 'active' ? 0 : $this->sessions->revokeCompanyMemberSessions($companyId);

            $this->audit->record($actorUserId, 'company.status_changed', [
                'company_id' => $companyId,
                'status' => $status,
                'sessions_revoked' => $revoked,
            ]);
        });
    }

    public function setPersonStatus(int $userId, string $status, int $actorUserId): void
