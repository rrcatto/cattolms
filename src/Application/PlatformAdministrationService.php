    /**
     * Builds the consolidated Company workspace as bounded previews with genuine totals.
     *
     * Every section here used to load its complete dataset — and in the platform-wide branch it
     * did so across every company, not one. Sections are now capped at PREVIEW_PAGE_SIZE rows,
     * and the counts are real SQL counts rather than count() over a capped array.
     *
     * @param array{mode:string,company:array<string,mixed>,company_id:int,platform_wide:bool} $context
     * @return array<string,mixed>
     */
    public function companyControlCentre(int $actorUserId, array $context): array
    {
        $companyId = (int) $context['company_id'];

        // Once a concrete company is in context, everything shown is that company's universe.
        // Only the All-companies overview uses the requested scope, because only it spans more
        // than one company.

        $data = [
            'company' => $context['company'],
            'company_platform_wide' => $context['platform_wide'],
            // The platform-wide workspace renders an "All companies" table. Bounded like every
            // other preview here; deep paging lives on /admin/companies, which the table links
            // to. Leaving this empty rendered a table of headings and no rows.
            'companies' => $context['platform_wide']
                ? $this->normaliseCompanies($this->administration->companies(self::PREVIEW_PAGE_SIZE, 0))
                : [$context['company']],
            'is_preview' => true,
        ] + $this->datasetDefaults();

        // Counts only. The rows for each section are fetched by the section's own route when the
        // reader opens it, so landing on this page costs one cheap count per dataset instead of a
        // page of rows and a count for every section at once - and each section then arrives fully
        // paginated and searchable rather than as a bounded preview that could not be paged.
        foreach (['people', 'requests', 'enrolments', 'credits'] as $dataset) {
            $data[$dataset] = [];
            $data[$dataset . '_count'] = $this->companyTotal($dataset, $companyId);
        }

        // The consolidated preview must use the same company rule as the standalone Courses
        // section. It previously used allCourses()/publishedCourses(), so the workspace and the
        // section it links to described two different populations.
        $data['courses'] = [];
        $data['training'] = [];
        $data['courses_count'] = $context['platform_wide']
            ? $this->courses->allCoursesCount()
            : $this->courses->companyCoursesCount($companyId, 'owned');
        $data['training_count'] = $context['platform_wide']
            ? 0
            : $this->courses->companyCoursesCount($companyId, 'training');

        return $data;
    }

    /**
