    /**
     * Removes a person's relationship with the context company.
     *
     * This is a membership operation and nothing more. It used to also set
     * `users.status = 'disabled'`, which conflated two unrelated decisions: "this person no longer
     * works here" and "this person may no longer sign in anywhere". Somebody moving between
     * companies was banned from the platform as a side effect, and there was no way to reverse it
     * from the Company workspace. Disabling an account is now its own action -
     * {@see setCompanyPersonStatus()} - and removal leaves the global identity alone.
     *
     * Company-sponsored enrolments are still ended, because those are the company's to grant and
     * the person is no longer a member. The learning history behind them is preserved; only access
     * is withdrawn.
     */
    public function removeCompanyPerson(int $actorUserId, int $companyId, int $targetUserId): void
    {
        $company = $this->contextCompany($companyId);
        $this->assertCompanyMember((int) $company['id'], $targetUserId);
        if ($actorUserId === $targetUserId) {
            throw new InvalidArgumentException('You cannot remove your own company-administrator account.');
        }
        $this->transactions->run(function () use ($company, $targetUserId, $actorUserId): void {
            $companyId = (int) $company['id'];
            foreach ($this->administration->activeCompanyUserEnrolmentIds($companyId, $targetUserId) as $enrolmentId) {
                $this->administration->removeEnrolmentAccess($enrolmentId, $actorUserId, 'Company membership removed');
            }
            $this->companies->removeUser($companyId, $targetUserId);
            $this->audit->record($actorUserId, 'company.person_removed', ['company_id' => $companyId, 'user_id' => $targetUserId]);
        });
    }

    /**
     * Enables or disables a company person's ability to sign in.
     *
     * `users.status` is the authoritative login gate, so this is the control that genuinely stops
     * someone using the platform. Nothing is deleted: membership, enrolments, progress, results and
     * certificates all remain exactly as they were, so enabling the account again returns the
     * learner to where they left off.
     *
     * Disabling also revokes every live session. Without that, `users.status` would only be
     * consulted at the next sign-in and an already-authenticated learner could carry on with a
     * course for the remaining lifetime of their session - which is not what "disabled" means to
     * anyone reading it.
     */
    public function setCompanyPersonStatus(int $actorUserId, int $companyId, int $targetUserId, string $status): void
    {
        if (!in_array($status, ['active', 'disabled'], true)) {
            throw new InvalidArgumentException('Choose either active or disabled.');
        }
        $company = $this->contextCompany($companyId);
        $this->assertCompanyMember((int) $company['id'], $targetUserId);
        if ($actorUserId === $targetUserId) {
            throw new InvalidArgumentException('You cannot disable your own account.');
        }

        // A company-level control must never reach a platform administrator or a system identity.
        // Company administration is scoped to the company; the platform is not the company's to
        // manage, and a lockout path from here would be a way to lose the installation.
        $targetRoles = $this->roles->roles($targetUserId);
        if (in_array(RoleCatalog::ADMIN, $targetRoles, true)) {
            throw new InvalidArgumentException('A Platform Administrator cannot be disabled from the Company workspace.');
        }

        $this->transactions->run(function () use ($actorUserId, $company, $targetUserId, $status): void {
            $this->users->setStatus($targetUserId, $status);
            $revoked = $status === 'disabled' ? $this->sessions->revokeAllForUser($targetUserId) : 0;
            $this->audit->record(
                $actorUserId,
                $status === 'disabled' ? 'company.person_disabled' : 'company.person_enabled',
                [
                    'company_id' => (int) $company['id'],
                    'user_id' => $targetUserId,
                    'status' => $status,
                    'sessions_revoked' => $revoked,
                ]
            );
        });
    }

    /**
     * Edits the fields a company legitimately owns for one of its people.
     *
     * Deliberately narrower than {@see updatePerson()}, which is the platform editor and can move
     * a person between companies, rewrite their email identity and grant platform roles. None of
     * that is the company's to decide, so this method reuses the same profile writer but exposes
     * only the profile fields, and refuses any target that is not a member of the context company.
