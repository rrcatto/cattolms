    /**
     * Extracts only the recognised Activity filter values from raw request state.
     *
     * Pagination keys travel in the same array, so they must be stripped before the filters
     * reach the repository: the count query and the row query have to see an identical filter
     * set, and a stray page number in that set would be silently ignored by one and not the
     * other if the repository ever started reading it.
     *
     * @param array<string,mixed> $request
     * @return array<string,mixed>
     */
    private function activityFilterValues(array $request): array
    {
        return [
            'from' => trim((string) ($request['from'] ?? '')),
            'to' => trim((string) ($request['to'] ?? '')),
            'family' => trim((string) ($request['family'] ?? '')),
            'actor_id' => max(0, (int) ($request['actor_id'] ?? 0)),
            'course_id' => max(0, (int) ($request['course_id'] ?? 0)),
            'company_id' => max(0, (int) ($request['company_id'] ?? 0)),
            'q' => trim((string) ($request['q'] ?? '')),
            'after_id' => max(0, (int) ($request['after_id'] ?? 0)),
        ];
    }

