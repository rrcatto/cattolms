                    'activity_filters' => $filters,
                    'activity_selected_actor' => $this->lookups->describe('people', $universe, (int) ($filters['actor_id'] ?? 0)),
                    'activity_selected_company' => $this->lookups->describe('companies', $universe, (int) ($filters['company_id'] ?? 0)),
