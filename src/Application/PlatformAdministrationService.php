    /**
     * The column headers for one sortable list.
     *
     * Each entry carries the URL that applies it, the direction that click would request, and
     * whether it is the column in force. Built here for the same reason paging URLs are: a header
     * that rebuilt its own URL would be free to drop the search term or the universe that its
     * neighbours keep.
     *
     * @param array<string,string> $columns  key => visible label, in table order, sortable or not
     * @param list<string>         $sortable  the keys this dataset can actually sort by
     * @param array<string,string> $natural   key => the direction that column reads best in first
     * @param array<string,mixed>  $filters
     * @return array<string,mixed>
     */
    public function sortView(string $dataset, SortOrder $sort, string $base, array $columns, array $sortable, array $filters = [], array $natural = []): array
    {
        return self::sortViewFor($dataset, $sort, $base, $columns, $sortable, $filters, $natural);
    }

    /**
     * The same model, built from nothing but its arguments.
     *
     * Static and dependency-free for the reason paginationPayload() is: the render tests must feed
     * the partial the model production actually produces, and the only way to guarantee that is for
     * both to call one function.
     *
     * @param array<string,string> $columns
     * @param list<string>         $sortable
     * @param array<string,mixed>  $filters
     * @param array<string,string> $natural
     * @return array<string,mixed>
     */
    public static function sortViewFor(string $dataset, SortOrder $sort, string $base, array $columns, array $sortable, array $filters = [], array $natural = []): array
    {
        $filters = array_filter(
            $filters,
            static fn(mixed $value): bool => $value !== '' && $value !== 0 && $value !== null
        );

        $headers = [];
        foreach ($columns as $key => $label) {
            // A column the dataset cannot sort by still belongs in this model. The header row is
            // then one declaration per table instead of a repeat that filters itself by key twice,
            // and a column can gain or lose sorting without its markup being rewritten.
            // A label may carry its share of the table's width, written as "Label|12" - twelve per
            // cent. Declared beside the label because the two are one decision: how much room a
            // column needs is a fact about what it holds. A column with no share stated takes an
            // equal slice of whatever is left.
            [$label, $width] = array_pad(explode('|', $label, 2), 2, '');

            if (!in_array($key, $sortable, true)) {
                $headers[] = ['key' => $key, 'label' => $label, 'width' => $width, 'sortable' => false, 'active' => false, 'direction' => '', 'href' => ''];
                continue;
            }

            $direction = $sort->nextDirectionFor($key, $natural[$key] ?? SortOrder::ASCENDING);
            $headers[] = [
                'key' => $key,
                'label' => $label,
                'width' => $width,
                'sortable' => true,
                'active' => $sort->isOn($key),
                'direction' => $sort->isOn($key) ? $sort->direction : '',
                // A sort always returns to page one. Staying on page 90 of a list that has just
                // been reordered lands the reader among rows that have nothing to do with what
                // they were looking at.
                'href' => $base . '?' . http_build_query($filters + [
                    $dataset . '_sort' => $key,
                    $dataset . '_dir' => $direction,
                    $dataset . '_page' => 1,
                ]),
            ];
        }

        return [
            $dataset . '_sort_headers' => $headers,
            $dataset . '_region' => $dataset . '-region',
            $dataset . '_results' => $dataset . '-results',
        ] + $sort->toPrefixedArray($dataset);
    }

    /** @param array<string,mixed> $request */
    public function paginationFor(string $dataset, array $request, int $total): Pagination
    {
        return Pagination::create(
            $request[$dataset . '_page'] ?? null,
            $request[$dataset . '_page_size'] ?? null,
            $total,
            self::DEFAULT_PAGE_SIZES[$dataset] ?? Pagination::DEFAULT_PAGE_SIZE
        );
    }

    /**
     * Builds the complete view payload for one paginated dataset.
     *
     * Returns both shapes deliberately:
     *   - `<dataset>_pagination`, the single array the shared pagination partial consumes;
     *   - `<dataset>_page`, `<dataset>_total`, ... flat scalars, which are the established
     *     view contract that tools/validate-ui-contracts.php asserts for Companies and that
     *     templates use for simple conditionals.
     *
     * `filters` are the non-pagination query values to re-emit on every paging link, so a
     * filtered list stays filtered when the reader moves to page 2. The search term, the data
     * universe and every list filter arrive here as ordinary filters, which is why one URL
     * builder preserves all of them without knowing what any of them mean.
     *
     * Pagination 2.0 composes every target URL here rather than in markup. The partial used to
     * concatenate a base, a pre-joined query string, a page parameter and a size parameter
     * inline, which meant each of the four controls re-derived the same URL and any new control
     * had to re-derive it again. One private builder now produces First, Previous, every
     * numbered page, Next and Last, so a link cannot lose a filter that its neighbour keeps.
     *
     * `region` and `results` are the htmx swap targets, derived from the dataset prefix by the
     * same convention the shared search control uses. They are supplied rather than assumed in
     * markup so a caller cannot pair a control with another dataset's table.
     *
     * @param array<string,mixed> $filters
     * @return array<string,mixed>
     */
    public function paginationView(string $dataset, Pagination $pagination, string $base, string $label, array $filters = []): array
    {
        return $pagination->toPrefixedArray($dataset)
            + [$dataset . '_pagination' => self::paginationPayload($dataset, $pagination, $base, $label, $filters)];
    }

    /**
     * The array the shared pagination partial consumes, built from nothing but its arguments.
     *
     * Static and dependency-free on purpose. The render smoke tests must feed the partial the
     * payload production actually produces, and the only way to guarantee that is for both to
     * call the same function. A hand-written copy in the test harness cannot drift visibly: it
     * keeps passing while a partial reads a key the service stopped supplying, which is exactly
     * the failure mode the render harness exists to catch.
     *
     * The two query-parameter names default to the dataset convention and are overridable for the
     * one surface that predates it: the public catalogue carries a single principal dataset and
     * has always paged on bare `page` / `page_size`, which are public URLs people have bookmarked.
     * Naming them here keeps that surface on this builder rather than letting it keep a payload of
     * its own, which is what it had.
     *
     * @param array<string,mixed> $filters
     * @return array<string,mixed>
     */
    public static function paginationPayload(
        string $dataset,
        Pagination $pagination,
        string $base,
        string $label,
        array $filters = [],
        ?string $pageParam = null,
        ?string $sizeParam = null
    ): array {
        $pageParam ??= $dataset . '_page';
        $sizeParam ??= $dataset . '_page_size';

        $filters = array_filter(
            $filters,
            static fn(mixed $value): bool => $value !== '' && $value !== 0 && $value !== null
        );

        $href = fn(int $page): string => self::pageHref($base, $filters, $pageParam, $sizeParam, $page, $pagination->pageSize);

        $pages = [];
        foreach ($pagination->window() as $item) {
            $pages[] = $item + ['href' => $item['is_gap'] ? '' : $href($item['page'])];
        }

        return $pagination->toArray() + [
            'prefix' => $dataset,
            'page_param' => $pageParam,
            'size_param' => $sizeParam,
            'base' => $base,
            'label' => $label,
            'page_sizes' => Pagination::PAGE_SIZES,
            'filters' => $filters,
            'query' => $filters === [] ? '' : http_build_query($filters) . '&',
            'region' => $dataset . '-region',
            'results' => $dataset . '-results',
            'pages' => $pages,
            'first_href' => $href($pagination->firstPage),
            'previous_href' => $href(max(1, $pagination->page - 1)),
            'next_href' => $href(min($pagination->totalPages, $pagination->page + 1)),
            'last_href' => $href($pagination->lastPage),
        ];
    }

    /**
     * One page's URL: the list's own route, its current filters, its page and its page size.
     *
     * The page size travels on every link because it is dataset state like any other. Leaving it
     * off meant a reader who chose 250 rows dropped back to the dataset default the moment they
     * moved off page 1, which reads as the setting not having been applied.
     *
     * @param array<string,mixed> $filters
     */
    private static function pageHref(string $base, array $filters, string $pageParam, string $sizeParam, int $page, int $pageSize): string
    {
        return $base . '?' . http_build_query($filters + [$pageParam => $page, $sizeParam => $pageSize]);
    }

    /**
     * Fetches one bounded preview page for a consolidated workspace section.
     *
     * One extra row is requested purely as a probe, so the workspace can offer "View all"
     * without paying for a COUNT on every section of every consolidated page load. The probe
     * row is discarded before the caller sees it.
     *
     * @param callable(int,int):list<array<string,mixed>> $rows
     * @return array{0:list<array<string,mixed>>,1:bool}
     */
    private function preview(callable $rows): array
    {
        $fetched = $rows(self::PREVIEW_PAGE_SIZE + 1, 0);
        $hasMore = count($fetched) > self::PREVIEW_PAGE_SIZE;
        if ($hasMore) array_pop($fetched);

        return [$fetched, $hasMore];
    }

    /**
     * Builds the consolidated Administration workspace as one bounded preview per section.
     *
     * The consolidated /admin deliberately shows a fixed, small slice of each section with a
     * "View all" link rather than deep paging every dataset at once, and exposes no page-size
     * selector. It also issues no COUNT per section: a single probe row is enough to decide
     * whether "View all" is warranted, and seven aggregate queries on a dashboard is exactly
     * the cost this release exists to remove.
     *
     * Every section's real values are collected first and datasetDefaults() is applied once at
     * the end. Applying the defaults per section instead let one section's default overwrite
     * another section's real value — `companies` reset `people_preview_has_more` to false — so
     * the workspace silently lost the "View all" affordance for all but the last section.
     *
     * @param list<string> $sections Section keys the actor may see, in display order.
     * @param array<string,array<string,bool>> $capabilities Sub-resource visibility, keyed by section.
     * @return array<string,mixed>
     */
    public function workspacePreview(array $sections, int $actorUserId, array $capabilities = []): array
    {
        $data = [];
        foreach ($sections as $section) {
            // Roles & ACL and Seed Database carry no business dataset of their own;
            // RoleAdministrationService and SeedDatabaseService supply them through the
            // controller's presentation step.
            if ($section === 'roles' || $section === 'seed') continue;
            $data += $this->sectionPreviewValues($section, $actorUserId, $capabilities[$section] ?? []);
        }

        return $data + ['is_preview' => true] + $this->datasetDefaults();
    }

    /**
     * The genuine data for one consolidated-workspace section, before defaults are applied.
     *
     * @param array<string,bool> $capabilities
     * @return array<string,mixed>
     */
    private function sectionPreviewValues(string $section, int $actorUserId, array $capabilities): array
    {
        $bounded = function (string $dataset, callable $rows, callable $normalise): array {
            [$fetched, $hasMore] = $this->preview($rows);

            return [
                $dataset => $normalise($fetched),
                $dataset . '_preview_has_more' => $hasMore,
            ];
        };

        return match ($section) {
            'dashboard', 'themes', 'settings', 'reports', 'company_report' => $this->sectionDataValues($section, $actorUserId, [], $capabilities),
            'people' => $bounded(
                'people',
                fn(int $l, int $o): array => $this->administration->people($l, $o),
                fn(array $rows): array => $this->normalisePeople($rows, $this->roles->all())
            ) + ['roles' => $this->normalAssignableRoles()],
            // Each half previews its own audience, so the consolidated workspace shows the same
            // rows the section it links to will show.
            'companies' => $bounded(
                'companies',
                fn(int $l, int $o): array => $this->administration->companies($l, $o, '', null, 'consumers'),
                fn(array $rows): array => $this->normaliseCompanies($rows)
            ) + ['system_company' => $this->systemCompanyContext($actorUserId)],
            'company_creators' => $bounded(
                'company_creators',
                fn(int $l, int $o): array => $this->administration->companies($l, $o, '', null, 'creators'),
                fn(array $rows): array => $this->normaliseCompanies($rows)
            ),
            'courses' => $bounded(
                'courses',
                fn(int $l, int $o): array => $this->adminCoursePage($actorUserId, !empty($capabilities['view_all_courses']), $l, $o),
                static fn(array $rows): array => $rows
            ),
            'credits' => $bounded(
                'credits',
                fn(int $l, int $o): array => $this->administration->creditLedger($l, $o),
                fn(array $rows): array => $this->normaliseCredits($rows)
            ),
            'requests' => empty($capabilities['view_requests'])
                ? ['requests' => [], 'requests_preview_has_more' => false]
                : $bounded('requests', fn(int $l, int $o): array => $this->administration->requests($l, $o), fn(array $r): array => $this->normaliseRequests($r)),
            'enrolments' => empty($capabilities['view_enrolments'])
                ? ['enrolments' => [], 'enrolments_preview_has_more' => false]
                : $bounded('enrolments', fn(int $l, int $o): array => $this->administration->enrolments($l, $o), fn(array $r): array => $this->normaliseEnrolments($r)),
            'activity' => (function (): array {
                $events = $this->normaliseActivity($this->administration->activity([], self::PREVIEW_PAGE_SIZE + 1, 0));
                $hasMore = count($events) > self::PREVIEW_PAGE_SIZE;
                if ($hasMore) array_pop($events);

                return [
                    'activity_events' => $events,
                    'activity_last_id' => (int) ($events[0]['id'] ?? 0),
                    'activity_families' => $this->administration->activityFamilies(),
                    'activity_filters' => $this->activityFilterValues([]),
                    'activity_preview_has_more' => $hasMore,
                ];
            })(),
            default => throw new InvalidArgumentException('Unknown Administration section: ' . $section),
        };
    }

    /**
     * One page of the Administration course list under the actor's course scope.
     *
     * `view_all_courses` is the platform-administration capability the caller's ACL layer
     * decides. Without it the list is restricted to the courses the actor owns, edits or
     * administers through their company; both Administration course surfaces previously
     * returned every course on the platform regardless of who was looking.
     *
     * @return list<array<string,mixed>>
     */
    private function adminCoursePage(int $actorUserId, bool $viewAll, int $limit, int $offset, string $search = '', ?SortOrder $sort = null): array
    {
        return $viewAll
            // Trimmed here because this list has no normaliser of its own: it returns repository
            // rows straight to the template, so it was the one table still printing a timestamp to
            // the microsecond - the widest column on the screen after the title.
            ? self::trimTimestamps($this->courses->allCourses($limit, $offset, $search, $sort))
            : self::trimTimestamps($this->courses->manageableCourses($actorUserId, $limit, $offset, $search, $sort));
    }

    /** Total rows behind adminCoursePage() under the same scope, counted with the identical membership rule. */
    private function adminCoursesTotal(int $actorUserId, bool $viewAll, string $search = ''): int
    {
        return $viewAll
            ? $this->courses->allCoursesCount($search)
            : $this->courses->manageableCoursesCount($actorUserId, $search);
    }

    /**
     * Loads only the business data needed by one standalone Administration
     * section. Section identity comes from AdministrationSectionRegistry; the
     * service does not know or care whether the caller renders tabs, accordions
     * or a dedicated page.
     *
     * @param array<string,mixed> $activityFilters
