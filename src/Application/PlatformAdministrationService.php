                $pagination = $this->paginationFor('credits', $activityFilters, $this->administration->creditLedgerCount($universe, $search));
                return [
                    'credits' => $this->normaliseCredits($this->administration->creditLedger($universe, $pagination->pageSize, $pagination->offset, $search)),
                    'credits_search' => $search,
                ] + $this->paginationView('credits', $pagination, '/admin/credits', 'Credits', self::withSearch($scope, 'credits', $search));
