    /**
     * The genuine data for one standalone Administration section, before defaults are applied.
     *
     * @param array<string,mixed> $activityFilters
     * @param array<string,bool> $capabilities
     * @return array<string,mixed>
     */
    private function sectionDataValues(string $section, int $actorUserId, array $activityFilters, array $capabilities): array
    {
        return match ($section) {
            'dashboard' => [
                'overview' => $this->administration->overview(),
                'recent_activity_events' => array_slice($this->normaliseActivity($this->administration->activity([], 8)), 0, 5),
            ],
            'courses' => (function () use ($actorUserId, $activityFilters, $capabilities): array {
                $viewAll = !empty($capabilities['view_all_courses']);
                $pagination = $this->paginationFor('courses', $activityFilters, $this->adminCoursesTotal($actorUserId, $viewAll));
                return ['courses' => $this->adminCoursePage($actorUserId, $viewAll, $pagination->pageSize, $pagination->offset)]
                    + $this->paginationView('courses', $pagination, '/admin/courses', 'Courses');
            })(),
            'people' => (function () use ($activityFilters): array {
                $allRoles = $this->roles->all();
                $pagination = $this->paginationFor('people', $activityFilters, $this->administration->peopleCount());
                return [
                    'people' => $this->normalisePeople($this->administration->people($pagination->pageSize, $pagination->offset), $allRoles),
                    'roles' => $this->normalAssignableRoles(),
                ] + $this->paginationView('people', $pagination, '/admin/people', 'People');
            })(),
            'companies' => (function () use ($actorUserId, $activityFilters): array {
                $pagination = $this->paginationFor('companies', $activityFilters, $this->administration->companyCount());
                return [
                    'system_company' => $this->systemCompanyContext($actorUserId),
                    'companies' => $this->normaliseCompanies($this->administration->companies($pagination->pageSize, $pagination->offset)),
                ] + $this->paginationView('companies', $pagination, '/admin/companies', 'Companies');
            })(),
            // Enrolments and Requests share this screen but hold entirely separate pagination
            // state, because the two datasets grow at very different rates.
            'enrolments' => (function () use ($activityFilters, $capabilities): array {
                $data = [];

                if (!empty($capabilities['view_requests'])) {
                    $pagination = $this->paginationFor('requests', $activityFilters, $this->administration->requestsCount());
                    $data['requests'] = $this->administration->requests($pagination->pageSize, $pagination->offset);
                    $data += $this->paginationView('requests', $pagination, '/admin/enrolments', 'Course requests');
                } else {
                    $data['requests'] = [];
                }

                if (!empty($capabilities['view_enrolments'])) {
                    $pagination = $this->paginationFor('enrolments', $activityFilters, $this->administration->enrolmentsCount());
                    $data['enrolments'] = $this->normaliseEnrolments($this->administration->enrolments($pagination->pageSize, $pagination->offset));
                    $data += $this->paginationView('enrolments', $pagination, '/admin/enrolments', 'Enrolments');
                } else {
                    $data['enrolments'] = [];
                }

                return $data;
            })(),
            // The credit-entry controls previously loaded every company, person and course to
            // populate three <select> elements. They are now htmx-driven lookups, so this
            // section loads only the ledger page it displays.
            'credits' => (function () use ($activityFilters): array {
                $pagination = $this->paginationFor('credits', $activityFilters, $this->administration->creditLedgerCount());
                return ['credits' => $this->normaliseCredits($this->administration->creditLedger($pagination->pageSize, $pagination->offset))]
                    + $this->paginationView('credits', $pagination, '/admin/credits', 'Credits');
            })(),
            // Activity previously reported no total at all, and populated its person, company
            // and course filters by loading those three tables in full. It now counts with the
            // identical filter set and resolves entities through bounded htmx lookups.
            'activity' => (function () use ($activityFilters): array {
                $filters = $this->activityFilterValues($activityFilters);
                $pagination = $this->paginationFor('activity', $activityFilters, $this->administration->activityCount($filters));
                $events = $this->normaliseActivity($this->administration->activity($filters, $pagination->pageSize, $pagination->offset));

                return [
                    'activity_events' => $events,
                    'activity_last_id' => (int) ($events[0]['id'] ?? 0),
                    'activity_families' => $this->administration->activityFamilies(),
                    'activity_filters' => $filters,
                    'activity_selected_actor' => $this->lookups->describe('people', (int) ($filters['actor_id'] ?? 0)),
                    'activity_selected_company' => $this->lookups->describe('companies', (int) ($filters['company_id'] ?? 0)),
                    'activity_selected_course' => $this->lookups->describe('courses', (int) ($filters['course_id'] ?? 0)),
                ] + $this->paginationView('activity', $pagination, '/admin/activity', 'Activity', $filters);
            })(),
            'reports' => [
                'report_summary' => $this->administration->reportSummary(),
                'course_report' => $this->normaliseCourseReport($this->administration->courseReport()),
                'company_report' => $this->normaliseCompanyReport($this->administration->companyReport()),
            ],
            'themes' => [],
            'settings' => (function () use ($actorUserId): array {
                $systemCompany = $this->systemCompanyContext($actorUserId);
                return [
                    'system_company' => $systemCompany,
                    'platform_name' => $this->settings->platformName(),
                    'platform_name_source' => $this->settings->platformNameSource(),
                    'mail_settings' => $this->settings->mailAdminView(),
                    'system_company_name' => $this->options->get('system_company_name', (string) $systemCompany['name']),
                    'system_company_domain' => (string) $systemCompany['domain'],
                ];
            })(),
            default => throw new InvalidArgumentException('Unknown Administration section: ' . $section),
        };
    }

    /** @return array<string,mixed> */
    private function systemCompanyContext(int $actorUserId): array
    {
        $systemCompany = $this->companies->ensureSystemCompany(
            $actorUserId,
            $this->options->get('system_company_name', 'System Company'),
            Env::string('APP_DOMAIN', 'local')
        );
        $this->companies->assignUnassignedUsersToSystemCompany((int) $systemCompany['id']);
        return $systemCompany;
    }

    /**
     * Resolves the company context a Company-workspace request operates in.
     *
     * A platform-wide actor (PLATFORM.DASHBOARD.VIEW) sees every company and is represented by
     * company id 0, which every scoped repository method treats as "no company restriction".
     * An ordinary Company Administrator is pinned to their own company, and that scope is
     * always applied in SQL rather than by filtering fetched rows.
     *
     * @return array{company:array<string,mixed>,company_id:int,platform_wide:bool}
     */
    private function companyContext(int $actorUserId, bool $platformWide): array
    {
        if ($platformWide) {
            return [
                'company' => ['id' => 0, 'name' => 'All companies', 'domain' => 'Platform-wide'],
                'company_id' => 0,
                'platform_wide' => true,
            ];
        }

        $company = $this->companies->findForUser($actorUserId);
        if ($company === null) {
            throw new RuntimeException('Your account is not attached to an active company.');
        }

        return ['company' => $company, 'company_id' => (int) $company['id'], 'platform_wide' => false];
    }

    /**
     * Counts one company dataset, honouring platform-wide scope.
     *
     * These are real SQL counts. The dashboard previously derived its totals with count() over
     * an already-capped array, so "People: 250" could mean "at least 250, we stopped looking" —
     * a wrong number rather than a truncated list.
     */
    private function companyTotal(string $dataset, int $companyId): int
    {
        return match ($dataset) {
            'people' => $companyId > 0 ? $this->administration->companyPeopleCount($companyId) : $this->administration->peopleCount(),
            'requests' => $companyId > 0 ? $this->administration->companyRequestsCount($companyId) : $this->administration->requestsCount(),
            'enrolments' => $companyId > 0 ? $this->administration->companyEnrolmentsCount($companyId) : $this->administration->enrolmentsCount(),
            'credits' => $companyId > 0 ? $this->administration->companyCreditsCount($companyId) : $this->administration->creditLedgerCount(),
            default => 0,
        };
    }

    /**
     * Fetches one page of a company dataset, honouring platform-wide scope.
     *
     * @return list<array<string,mixed>>
     */
    private function companyRows(string $dataset, int $companyId, int $limit, int $offset): array
    {
        return match ($dataset) {
            'people' => $companyId > 0
                ? $this->administration->companyPeople($companyId, $limit, $offset)
                : $this->administration->people($limit, $offset),
            'requests' => $companyId > 0
