    /**
     * @param list<array<string,mixed>> $roleOptions
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    private function normalisePeople(array $rows, array $roleOptions = []): array
    {
        $roleNames = [];
        foreach ($roleOptions as $role) {
            $roleNames[(string) ($role['role_key'] ?? '')] = (string) ($role['role_name'] ?? $role['role_key'] ?? '');
        }
        foreach ($rows as &$row) {
            $keys = array_values(array_filter(explode(',', (string) ($row['role_keys'] ?? ''))));
            $row['roles'] = array_map(static fn(string $key): string => $roleNames[$key] ?? ucwords(str_replace('_', ' ', $key)), $keys);
            // Platform-wide people queries do not join company_users, while the
            // Company People partial is shared with company-scoped queries. Keep
            // the row shape stable so F3 never compiles a missing array-key read.
            $row['company_role'] = (string) ($row['company_role'] ?? '');
            // Same reason: the Company People editor reads these, and the platform-wide people
            // query does not select them. Keep the row shape stable so F3 never compiles a
            // missing array-key read into an undefined variable.
            $row['certificate_name'] = (string) ($row['certificate_name'] ?? '');
            $row['mobile_number'] = (string) ($row['mobile_number'] ?? '');
            $row['middle_names'] = (string) ($row['middle_names'] ?? '');
            $row['roles_label'] = implode(', ', $row['roles']);
            $row['role_options'] = array_map(static function (array $role) use ($keys): array {
                $role['selected'] = in_array((string) ($role['role_key'] ?? ''), $keys, true);
                return $role;
            }, $roleOptions);
            $name = trim((string) ($row['first_name'] ?? '') . ' ' . (string) ($row['last_name'] ?? ''));
            $row['name'] = $name !== '' ? $name : ((string) ($row['display_name'] ?? '') ?: (string) $row['email']);
        }
        unset($row);
        return self::trimTimestamps($rows);
    }

    /**
     * One page of either half of Companies.
     *
     * Both halves list the same table through the same repository call and differ only in which
     * companies they ask for and which columns that makes worth showing. Writing them out twice
     * would be two copies of the search, sort, pagination and universe wiring that would then have
     * to be kept identical by hand.
     *
     * The columns are the whole point of the split. A consumer is described by its staff and their
     * enrolments; a creator by the courses it owns. Neither screen carries the other's figures, and
     * neither carries the Type column that the reader used to have to filter by mentally, because
     * which screen they are on already answers it.
     *
     * The search term is carried on the dataset-prefixed key, like every other piece of per-dataset
     * state, so it survives paging and page-size changes and cannot collide with the Activity
     * filter that also calls itself q. It is read by the caller rather than here so that each
     * section's search wiring is visible in the section itself.
     *
     * @param array<string,mixed> $request
     * @param array<string,string> $scope
     * @return array<string,mixed>
     */
    private function companyAudienceSection(string $dataset, string $audience, string $search, array $request, array $scope): array
    {
        $base = self::ADMIN_SECTION_ROUTES[$dataset];
        $sort = $this->sortFor($dataset, $request, array_keys(AdministrationRepository::COMPANY_SORTS), 'name');
        $pagination = $this->paginationFor($dataset, $request, $this->administration->companyCount($search, $audience));
        $searchFilter = self::withSearch($scope, $dataset, $search);
        $filters = $searchFilter + $sort->toPrefixedArray($dataset);

        $columns = $audience === 'creators'
            ? ['name' => 'Company|70', 'courses' => 'Owned courses|10', 'status' => 'Status|10', 'actions' => 'Actions|10']
            : ['name' => 'Company|66', 'people' => 'People|7', 'enrolments' => 'Enrolments|9', 'status' => 'Status|8', 'actions' => 'Actions|10'];

        return [
            $dataset . '_search' => $search,
            $dataset => $this->normaliseCompanies(
                $this->administration->companies($pagination->pageSize, $pagination->offset, $search, $sort, $audience)
            ),
        ]
            + $this->paginationView($dataset, $pagination, $base, self::UNIVERSE_COUNT_LABELS[$dataset], $filters)
            + $this->sortView($dataset, $sort, $base, $columns, array_keys(AdministrationRepository::COMPANY_SORTS), $searchFilter, [
                'people' => SortOrder::DESCENDING,
                'courses' => SortOrder::DESCENDING,
                'enrolments' => SortOrder::DESCENDING,
                'created' => SortOrder::DESCENDING,
            ]);
    }

    /**
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    private function normaliseCompanies(array $rows): array
    {
        foreach ($rows as &$row) {
            $isSystem = in_array($row['is_system'] ?? false, [true, 1, '1', 't', 'true'], true);
            $row['is_system'] = $isSystem;
            $row['company_type_label'] = $isSystem
                ? 'System company'
                : ((string) ($row['company_type'] ?? 'client') === 'course_provider' ? 'Course provider' : 'Client company');
            $row['status_label'] = ucfirst((string) ($row['status'] ?? ''));
        }
        unset($row);
        return self::trimTimestamps($rows);
    }

    /**
