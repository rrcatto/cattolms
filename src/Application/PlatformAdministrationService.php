    /**
     * Whether a section should build the named dataset on this request.
     *
     * Two Administration screens carry two independent tables - Enrolments sits under Requests, and
     * Reports holds a course report and a company report - and turning the page on one of them used
     * to run the queries for the other as well. Nothing on screen changes for the other table, so
