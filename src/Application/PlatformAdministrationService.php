    /**
     * Puts one staff member on one course, on behalf of their company.
     *
     * The owner's second workflow: an administrator assigns a course and tells the staff member
     * outside the LMS - ROADMAP section 2c. Approving a request is the other way in and ends at the
     * same place, which is why both consume entitlement through the same two rules:
     *
     *   owned      the company made the course, so training its own staff costs nothing and no
     *              credit is looked for or consumed;
     *   credited   the company holds a credit with a free seat, and the seat is taken.
     *
     * Anything else is refused. Until Commerce exists there is nothing to pay with, so an assignment
     * the company cannot cover has to fail loudly rather than record an enrolment nobody paid for.
     *
     * The whole thing is one transaction. Between finding a free seat and taking it, a second
     * administrator assigning the same course could take the same seat; the credit row is locked
     * FOR UPDATE by availableCredit(), and holding the enrolment in the same transaction is what
     * makes that lock mean anything.
     *
     * @return array{enrolment_id:int,entitlement:string}
     */
    public function assignCourseToStaff(int $companyId, int $courseId, int $userId, int $accessPeriodSeconds, int $actorUserId): array
    {
        $result = $this->transactions->run(function () use ($companyId, $courseId, $userId, $accessPeriodSeconds, $actorUserId): array {
            if (!$this->administration->isActiveCompanyMember($companyId, $userId)) {
                throw new RuntimeException('That person is not an active member of this company.');
            }

            $owned = $this->administration->companyOwnsCourse($companyId, $courseId);
            $credit = $owned ? null : $this->administration->availableCredit($companyId, $courseId, $accessPeriodSeconds);

            if (!$owned && $credit === null) {
                throw new RuntimeException(
                    'This company has no free seat for that course and access period. Buy a credit before assigning it.'
                );
            }

            $enrolmentId = $this->courses->grantCourse($userId, $courseId, $accessPeriodSeconds, $actorUserId);
            if ($credit !== null) {
                $this->administration->allocateCredit((int) $credit['id'], $userId, $enrolmentId, $actorUserId);
            }

            $this->audit->record($actorUserId, 'company.course.assigned', [
                'company_id' => $companyId,
                'course_id' => $courseId,
                'user_id' => $userId,
                'enrolment_id' => $enrolmentId,
                'entitlement' => $owned ? 'owned' : 'credit',
            ]);

            return ['enrolment_id' => $enrolmentId, 'entitlement' => $owned ? 'owned' : 'credit'];
        });

        // After the commit, never inside it: telling a learner they are on a course that a rolled
        // back transaction never enrolled them on is worse than telling them nothing.
        $learner = $this->administration->learnerNotice($userId, $courseId);
        if ($learner !== null) {
            $this->mailer->sendCourseEnrolmentNotice(
                (string) $learner['email'],
                (string) $learner['course_title'],
                (string) $learner['slug']
            );
        }

        return $result;
    }

