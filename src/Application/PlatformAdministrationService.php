                    $this->administration->companyCourseReport($companyId, $pagination->pageSize, $pagination->offset, $search, $sort)
                )
                : [];
            $data['company_performance_search'] = $search;
            $data['courses'] = [];
            $data['training'] = [];

            return $data
                + $this->paginationView('company_performance', $pagination, '/company/performance', 'Performance', $searchFilter + $sort->toPrefixedArray('company_performance'))
