    /**
     * @param array<string,mixed> $metadata
     * @return list<array{label:string,url:string}>
     */
    private function activityRelatedLinks(array $metadata): array
    {
        $links = [];
        if ((int) ($metadata['course_id'] ?? 0) > 0) {
            $links[] = ['label' => 'Course', 'url' => '/admin/courses/' . (int) $metadata['course_id']];
        }
        if ((int) ($metadata['user_id'] ?? 0) > 0) {
            $links[] = ['label' => 'Person', 'url' => '/admin/people/' . (int) $metadata['user_id']];
        }
        if ((int) ($metadata['company_id'] ?? 0) > 0) {
            $links[] = ['label' => 'Company administration', 'url' => '/admin/companies'];
        }
        if ((int) ($metadata['enrolment_id'] ?? 0) > 0 || (int) ($metadata['request_id'] ?? 0) > 0) {
            $links[] = ['label' => 'Enrolments & Requests', 'url' => '/admin/enrolments'];
        }
        return $links;
    }

    /** @param array<string,mixed> $metadata */
    private function activityResult(array $metadata): string
    {
        if (isset($metadata['percentage'])) {
            $percentage = rtrim(rtrim(number_format((float) $metadata['percentage'], 1, '.', ''), '0'), '.');
            return $percentage . '%' . (isset($metadata['status']) ? ' · ' . ucfirst((string) $metadata['status']) : '');
        }
        foreach (['status','decision','role','mode'] as $key) {
            if (isset($metadata[$key]) && is_scalar($metadata[$key])) {
                return ucfirst(str_replace('_', ' ', (string) $metadata[$key]));
            }
        }
        return '—';
    }

    /**
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    private function normaliseCourseReport(array $rows): array
    {
        foreach ($rows as &$row) {
            $enrolments = max(0, (int) ($row['enrolments'] ?? 0));
            $completed = max(0, (int) ($row['completed'] ?? 0));
            $row['completion_rate'] = $enrolments > 0 ? round($completed / $enrolments * 100, 1) : 0.0;
        }
        unset($row);
        return $rows;
    }

