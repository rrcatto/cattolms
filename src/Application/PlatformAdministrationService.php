    /**
     * Builds the consolidated Company workspace as bounded previews with genuine totals.
     *
     * Every section here used to load its complete dataset — and in the platform-wide branch it
     * did so across every company, not one. Sections are now capped at PREVIEW_PAGE_SIZE rows,
     * and the counts are real SQL counts rather than count() over a capped array.
     *
     * @return array<string,mixed>
     */
    public function companyControlCentre(int $actorUserId, bool $platformWide = false): array
    {
        $context = $this->companyContext($actorUserId, $platformWide);
        $companyId = $context['company_id'];

        $data = [
            'company' => $context['company'],
            'company_platform_wide' => $context['platform_wide'],
            // The platform-wide workspace renders an "All companies" table. Bounded like every
            // other preview here; deep paging lives on /admin/companies, which the table links
            // to. Leaving this empty rendered a table of headings and no rows.
            'companies' => $context['platform_wide']
                ? $this->normaliseCompanies($this->administration->companies(self::PREVIEW_PAGE_SIZE, 0))
                : [$context['company']],
            'is_preview' => true,
        ] + $this->datasetDefaults();

        foreach (['people', 'requests', 'enrolments', 'credits'] as $dataset) {
            [$rows, $hasMore] = $this->preview(
                fn(int $l, int $o): array => $this->companyRows($dataset, $companyId, $l, $o)
            );
            $data[$dataset] = $this->normaliseCompanyDataset($dataset, $rows);
            $data[$dataset . '_preview_has_more'] = $hasMore;
            $data[$dataset . '_count'] = $this->companyTotal($dataset, $companyId);
        }

        [$courses, $coursesMore] = $this->preview(fn(int $l, int $o): array => $context['platform_wide']
            ? $this->courses->allCourses($l, $o)
            : $this->courses->publishedCourses($l, $o));
        $data['courses'] = $courses;
        $data['courses_preview_has_more'] = $coursesMore;

        return $data;
    }

    /**
     * Loads only the dataset one standalone Company section renders.
     *
     * Every /company/* route previously called companyControlCentre() and therefore loaded
     * people, requests, enrolments, credits and the full course list even when the operator had
     * asked for a single section.
     *
     * @param array<string,mixed> $request
     * @return array<string,mixed>
     */
    public function companySectionData(string $section, int $actorUserId, bool $platformWide, array $request = []): array
    {
        $context = $this->companyContext($actorUserId, $platformWide);
        $companyId = $context['company_id'];

        $data = [
            'company' => $context['company'],
            'company_platform_wide' => $context['platform_wide'],
            'companies' => $context['platform_wide'] ? [] : [$context['company']],
            'is_preview' => false,
        ] + $this->datasetDefaults();

        if ($section === 'dashboard') {
            foreach (['people', 'requests', 'enrolments', 'credits'] as $dataset) {
                $data[$dataset] = [];
                $data[$dataset . '_count'] = $this->companyTotal($dataset, $companyId);
            }
            $data['courses'] = [];
            // Only the dashboard renders the platform-wide "All companies" table, so the query
            // stays inside this branch rather than running on every /company/* route.
            if ($context['platform_wide']) {
                $data['companies'] = $this->normaliseCompanies($this->administration->companies(self::PREVIEW_PAGE_SIZE, 0));
            }

            return $data;
        }

        if ($section === 'courses') {
            $pagination = $this->paginationFor('courses', $request, $context['platform_wide']
                ? $this->courses->allCoursesCount()
                : $this->courses->publishedCoursesCount());
            $data['courses'] = $context['platform_wide']
                ? $this->courses->allCourses($pagination->pageSize, $pagination->offset)
                : $this->courses->publishedCourses($pagination->pageSize, $pagination->offset);

            return $data + $this->paginationView('courses', $pagination, '/company/courses', 'Courses');
        }

        // 'learning' is the Company label for the enrolments dataset.
        $dataset = $section === 'learning' ? 'enrolments' : $section;
        if (!in_array($dataset, ['people', 'requests', 'enrolments', 'credits'], true)) {
            throw new InvalidArgumentException('Unknown Company section: ' . $section);
        }

        $total = $this->companyTotal($dataset, $companyId);
        $pagination = $this->paginationFor($dataset, $request, $total);
        $data[$dataset] = $this->normaliseCompanyDataset(
            $dataset,
            $this->companyRows($dataset, $companyId, $pagination->pageSize, $pagination->offset)
        );
        $data[$dataset . '_count'] = $total;
        $data['courses'] = [];

        return $data + $this->paginationView($dataset, $pagination, self::COMPANY_SECTION_ROUTES[$section] ?? '/company', ucfirst($section));
    }

