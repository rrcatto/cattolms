                + $this->datasetDefaults();
        }

        // Course performance for this company's own staff.
        //
        // The platform report answers "how is this course doing across the platform", which is not
        // a company administrator's question and is not theirs to see. Every figure here counts only
        // enrolments held by an active member of the company in context, and only courses at least
        // one of them is enrolled in appear at all.
