            // sensible 0 instead of a 500. The flat scalars mirror toPrefixedArray() exactly,
            // which is the established Companies view contract the validator asserts.
            $defaults += Pagination::create(1, $pageSize, 0, $pageSize)->toPrefixedArray($dataset);
            $defaults[$dataset . '_pagination'] = null;
            $defaults[$dataset . '_preview_has_more'] = false;
            // Sort state, defaulted for every dataset whether or not it sorts yet. A partial that
            // renders sortable headings in a section which supplied none would otherwise read an
            // undefined variable, which F3 turns into a 500 for the whole page rather than a blank.
            $defaults[$dataset . '_sort_headers'] = [];
            $defaults[$dataset . '_sort'] = '';
            $defaults[$dataset . '_dir'] = '';
            $defaults[$dataset . '_region'] = $dataset . '-region';
            $defaults[$dataset . '_results'] = $dataset . '-results';
            $defaults[$dataset . '_count'] = 0;
            $defaults[$dataset . '_search'] = '';
            // The rows themselves. A template reaching a dataset its controller never loaded must
            // render an empty list rather than return 500 on an undefined variable. Defaults are
            // unioned last everywhere, so a real page of rows always wins over this.
            $defaults[$dataset] = [];
        }

        // Course Requests narrows by status, and F3 turns an unset template variable into a 500
        // for the whole page rather than an empty value.
        $defaults['requests_status'] = '';
        $defaults['requests_status_filters'] = [];

        return $defaults;
    }

