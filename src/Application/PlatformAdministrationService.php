    public function requestCourse(int $userId, int $courseId, int $accessPeriodSeconds, string $note): int
    {
        $allowedPeriod = false;
        foreach ($this->courses->priceVariants($courseId, true) as $variant) {
            if ((int) ($variant['access_period_seconds'] ?? 0) === $accessPeriodSeconds) {
                $allowedPeriod = true;
                break;
            }
        }
        if (!$allowedPeriod) {
            throw new InvalidArgumentException('Choose one of the active access options configured for this course.');
        }
        $company = $this->companies->findForUser($userId);
        $id = $this->administration->createRequest(
            $userId,
            $company !== null ? (int) $company['id'] : null,
            $courseId,
            $accessPeriodSeconds,
            $note
        );
        $this->audit->record($userId, 'course_request.created', ['request_id' => $id, 'course_id' => $courseId]);
        return $id;
    }

    private function validateCompanyInput(string $name, string $domain): void
    {
        if ($name === '') {
            throw new InvalidArgumentException('Enter the company name.');
        }
        if ($domain === '' || str_contains($domain, '@') || str_contains($domain, '/') || filter_var('admin@' . $domain, FILTER_VALIDATE_EMAIL) === false) {
            throw new InvalidArgumentException('Enter one valid registered email domain, for example example.co.za.');
        }
        if ($this->companies->domainExists($domain)) {
            throw new InvalidArgumentException('That company email domain is already registered.');
        }
    }

    /**
     * @param list<array<string,mixed>> $roleOptions
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    private function normalisePeople(array $rows, array $roleOptions = []): array
    {
        $roleNames = [];
        foreach ($roleOptions as $role) {
            $roleNames[(string) ($role['role_key'] ?? '')] = (string) ($role['role_name'] ?? $role['role_key'] ?? '');
        }
        foreach ($rows as &$row) {
            $keys = array_values(array_filter(explode(',', (string) ($row['role_keys'] ?? ''))));
            $row['roles'] = array_map(static fn(string $key): string => $roleNames[$key] ?? ucwords(str_replace('_', ' ', $key)), $keys);
            // Platform-wide people queries do not join company_users, while the
            // Company People partial is shared with company-scoped queries. Keep
            // the row shape stable so F3 never compiles a missing array-key read.
            $row['company_role'] = (string) ($row['company_role'] ?? '');
            $row['roles_label'] = implode(', ', $row['roles']);
            $row['role_options'] = array_map(static function (array $role) use ($keys): array {
                $role['selected'] = in_array((string) ($role['role_key'] ?? ''), $keys, true);
                return $role;
            }, $roleOptions);
            $name = trim((string) ($row['first_name'] ?? '') . ' ' . (string) ($row['last_name'] ?? ''));
            $row['name'] = $name !== '' ? $name : ((string) ($row['display_name'] ?? '') ?: (string) $row['email']);
        }
        unset($row);
        return $rows;
    }

    /**
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    private function normaliseCompanies(array $rows): array
    {
        foreach ($rows as &$row) {
            $isSystem = in_array($row['is_system'] ?? false, [true, 1, '1', 't', 'true'], true);
            $row['is_system'] = $isSystem;
            $row['company_type_label'] = $isSystem
                ? 'System company'
                : ((string) ($row['company_type'] ?? 'client') === 'course_provider' ? 'Course provider' : 'Client company');
            $row['status_label'] = ucfirst((string) ($row['status'] ?? ''));
        }
        unset($row);
        return $rows;
    }

    /**
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    private function normaliseEnrolments(array $rows): array
    {
        foreach ($rows as &$row) {
            $total = max(0, (int) ($row['module_count'] ?? 0));
            $done = max(0, (int) ($row['modules_completed'] ?? 0));
            $row['progress_percentage'] = $total > 0 ? min(100, (int) round($done / $total * 100)) : 0;
        }
        unset($row);
        return $rows;
    }

    /**
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    private function normaliseCredits(array $rows): array
    {
        foreach ($rows as &$row) {
            $seconds = (int) ($row['access_period_seconds'] ?? 0);
            $row['access_period_label'] = $seconds % 31536000 === 0
                ? (int) ($seconds / 31536000) . ' year(s)'
                : (int) round($seconds / 86400) . ' days';
        }
        unset($row);
        return $rows;
    }

    /**
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    private function normaliseActivity(array $rows): array
    {
        foreach ($rows as &$row) {
            $metadata = $row['metadata'] ?? [];
            if (is_string($metadata)) {
                $decoded = json_decode($metadata, true);
                $metadata = is_array($decoded) ? $decoded : [];
            }
            if (!is_array($metadata)) {
                $metadata = [];
            }
            $row['metadata'] = $metadata;
            $row['metadata_text'] = json_encode($metadata, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT) ?: '{}';
            $key = (string) ($row['event_key'] ?? 'activity');
            $row['event_label'] = $this->activityLabel($key);
            $row['family_label'] = ucfirst(str_replace(['_','-'], ' ', (string) ($row['event_family'] ?? 'other')));
            $row['subject'] = (string) ($row['course_title'] ?? '') ?: ((string) ($row['subject_user_name'] ?? '') ?: ((string) ($row['company_name'] ?? '') ?: 'Platform'));
            $row['result'] = $this->activityResult($metadata);
            $row['source_label'] = str_starts_with($key, 'mcp.') ? 'MCP' : (str_starts_with($key, 'api.') ? 'API' : 'Web');
            $ipAddress = trim((string) ($row['ip_address'] ?? ''));
            $row['ip_address'] = $ipAddress;
            $row['geo_location'] = $ipAddress !== '' ? $this->geoIp->locate($ipAddress) : '—';
            $row['related_links'] = $this->activityRelatedLinks($metadata);
        }
        unset($row);
        return $rows;
    }

