    /**
     * Loads the company a Company workspace action is authorised to act on.
     *
     * Callers pass the id resolved by SelectedCompanyContext, never one taken from the request.
     * This method exists so that every mutation states the same thing in the same way, and so that
     * "no company" and "a company that has since been disabled" produce a sentence a reader can
     * act on rather than a null dereference further down.
     *
     * @return array<string,mixed>
     */
    private function contextCompany(int $companyId): array
    {
        if ($companyId < 1) {
            throw new RuntimeException('No company is selected, so there is nothing to act on.');
        }
        $company = $this->companies->findById($companyId);
        if ($company === null) {
            throw new RuntimeException('The company being administered no longer exists.');
        }

        return $company;
    }

