    public function addCredit(array $input, int $actorUserId): int
    {
        $companyId = max(0, (int) ($input['company_id'] ?? 0)) ?: null;
        $userId = max(0, (int) ($input['user_id'] ?? 0)) ?: null;
        if (($companyId === null) === ($userId === null)) {
            throw new InvalidArgumentException('Choose either a company or one person as the credit holder.');
        }
        $courseId = max(1, (int) ($input['course_id'] ?? 0));
        $period = max(86400, (int) ($input['access_period_seconds'] ?? 31536000));
        $quantity = max(1, min(10000, (int) ($input['quantity'] ?? 1)));
        $id = $this->administration->addCredit(
            $companyId,
            $userId,
            $courseId,
            $period,
            $quantity,
            trim((string) ($input['reason'] ?? 'administrator')) ?: 'administrator',
            (string) ($input['note'] ?? ''),
            $actorUserId
        );
        $this->audit->record($actorUserId, 'course_credit.added', [
            'credit_id' => $id,
            'company_id' => $companyId,
            'user_id' => $userId,
            'course_id' => $courseId,
            'quantity' => $quantity,
        ]);
        return $id;
    }

    public function decideRequest(int $requestId, bool $approve, string $note, int $actorUserId, ?int $allowedCompanyId = null): void
    {
        $request = $this->transactions->run(function () use ($requestId, $approve, $note, $actorUserId, $allowedCompanyId): array {
            $request = $this->administration->requestForUpdate($requestId);
            if ($request === null || (string) $request['status'] !== 'pending') {
                throw new RuntimeException('The course request is no longer pending.');
            }
            if ($allowedCompanyId !== null && (int) ($request['company_id'] ?? 0) !== $allowedCompanyId) {
                throw new RuntimeException('You may decide requests only for your own company.');
            }
            if (!$approve) {
                $this->administration->decideRequest($requestId, 'rejected', $note, $actorUserId);
                $this->audit->record($actorUserId, 'course_request.rejected', ['request_id' => $requestId]);
                return $request + ['decision' => 'rejected'];
            }

            $enrolmentId = null;
            if (!empty($request['company_id'])) {
                $credit = $this->administration->availableCredit(
                    (int) $request['company_id'],
                    (int) $request['course_id'],
                    (int) $request['access_period_seconds']
                );
                if ($credit !== null) {
                    $enrolmentId = $this->courses->grantCourse(
                        (int) $request['user_id'],
                        (int) $request['course_id'],
                        (int) $request['access_period_seconds'],
                        $actorUserId
                    );
                    $this->administration->allocateCredit((int) $credit['id'], (int) $request['user_id'], $enrolmentId, $actorUserId);
                    $this->administration->decideRequest($requestId, 'fulfilled', $note, $actorUserId, $enrolmentId);
                } else {
                    $this->administration->decideRequest($requestId, 'approved', $note, $actorUserId);
                }
            } else {
                $this->administration->decideRequest($requestId, 'approved', $note, $actorUserId);
            }
            $this->audit->record($actorUserId, 'course_request.approved', [
                'request_id' => $requestId,
                'enrolment_id' => $enrolmentId,
            ]);
            return $request + ['decision' => 'approved', 'enrolment_id' => $enrolmentId];
        });
        $this->mailer->sendCourseRequestDecision(
            (string) $request['email'],
            (string) $request['course_title'],
            $approve
        );
    }

    /** @param array<string,mixed> $input */
    public function saveSettings(array $input, int $actorUserId): void
    {
        $platformName = trim((string) ($input['platform_name'] ?? ''));
        $companyName = trim((string) ($input['system_company_name'] ?? ''));
        $companyDomain = strtolower(trim((string) ($input['system_company_domain'] ?? Env::string('APP_DOMAIN', 'local'))));
        if ($platformName !== '') {
            $this->options->set('platform_name', $platformName, $actorUserId);
        }
        if ($companyName !== '') {
            if ($companyDomain === '' || str_contains($companyDomain, '@') || str_contains($companyDomain, '/') || filter_var('admin@' . $companyDomain, FILTER_VALIDATE_EMAIL) === false) {
                throw new InvalidArgumentException('Enter one valid System Company domain, for example example.co.za.');
            }
            $this->options->set('system_company_name', $companyName, $actorUserId);
            $system = $this->companies->ensureSystemCompany($actorUserId, DataUniverse::Real, $companyName, Env::string('APP_DOMAIN', 'local'));
            // Saving Settings is a deliberate administrative act in the genuine universe, so the
            // administrator owning the System Company they just configured is correct here. It is
            // stated explicitly rather than happening inside a lookup.
            $this->companies->assignSystemCompanyOwner((int) $system['id'], $actorUserId);
            if ($this->companies->domainExistsForOther($companyDomain, (int) $system['id'])) {
                throw new InvalidArgumentException('That company email domain is already registered.');
            }
            $this->companies->updateManaged((int) $system['id'], $companyName, $companyDomain, 'system');
        }
        $this->audit->record($actorUserId, 'platform.settings_updated');
    }

