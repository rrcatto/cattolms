    /**
     * @param list<array<string,mixed>> $roleOptions
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    private function normalisePeople(array $rows, array $roleOptions = []): array
    {
        $roleNames = [];
        foreach ($roleOptions as $role) {
            $roleNames[(string) ($role['role_key'] ?? '')] = (string) ($role['role_name'] ?? $role['role_key'] ?? '');
        }
        foreach ($rows as &$row) {
            $keys = array_values(array_filter(explode(',', (string) ($row['role_keys'] ?? ''))));
            $row['roles'] = array_map(static fn(string $key): string => $roleNames[$key] ?? ucwords(str_replace('_', ' ', $key)), $keys);
            // Platform-wide people queries do not join company_users, while the
            // Company People partial is shared with company-scoped queries. Keep
            // the row shape stable so F3 never compiles a missing array-key read.
            $row['company_role'] = (string) ($row['company_role'] ?? '');
            // Same reason: the Company People editor reads these, and the platform-wide people
            // query does not select them. Keep the row shape stable so F3 never compiles a
            // missing array-key read into an undefined variable.
            $row['certificate_name'] = (string) ($row['certificate_name'] ?? '');
            $row['mobile_number'] = (string) ($row['mobile_number'] ?? '');
            $row['roles_label'] = implode(', ', $row['roles']);
            $row['role_options'] = array_map(static function (array $role) use ($keys): array {
                $role['selected'] = in_array((string) ($role['role_key'] ?? ''), $keys, true);
                return $role;
            }, $roleOptions);
            $name = trim((string) ($row['first_name'] ?? '') . ' ' . (string) ($row['last_name'] ?? ''));
            $row['name'] = $name !== '' ? $name : ((string) ($row['display_name'] ?? '') ?: (string) $row['email']);
        }
        unset($row);
        return $rows;
    }

    /**
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    private function normaliseCompanies(array $rows): array
    {
        foreach ($rows as &$row) {
            $isSystem = in_array($row['is_system'] ?? false, [true, 1, '1', 't', 'true'], true);
            $row['is_system'] = $isSystem;
            $row['company_type_label'] = $isSystem
                ? 'System company'
                : ((string) ($row['company_type'] ?? 'client') === 'course_provider' ? 'Course provider' : 'Client company');
            $row['status_label'] = ucfirst((string) ($row['status'] ?? ''));
            // Resolved here so no template has to reason about seed_token. A row's universe is a
            // fact about the row, and the Switch Company picker and the Administration list must
            // agree about it. Same rule as SelectedCompanyContext::universeOf(): the token is the
            // only source of truth, and a name or domain says nothing about which universe a
            // company is in.
            $isSeed = trim((string) ($row['seed_token'] ?? '')) !== '';
            $row['universe'] = $isSeed ? DataUniverse::Seed->value : DataUniverse::Real->value;
            $row['universe_label'] = $isSeed ? 'SEED' : 'REAL';
            $row['is_seed'] = $isSeed;
        }
        unset($row);
        return $rows;
    }

