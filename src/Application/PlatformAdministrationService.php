                    'system_company' => $this->systemCompanyContext($actorUserId, $universe),
                    'companies_search' => $search,
                    'companies' => $this->normaliseCompanies($this->administration->companies($universe, $pagination->pageSize, $pagination->offset, $search)),
                ] + $this->paginationView('companies', $pagination, '/admin/companies', 'Companies', $filters);
            })(),
            // Enrolments and Requests share this screen but hold entirely separate pagination
            // state, because the two datasets grow at very different rates.
            'enrolments' => (function () use ($activityFilters, $capabilities, $universe, $scope): array {
                $data = [];

                if (!empty($capabilities['view_requests'])) {
                    $search = self::searchTerm('requests', $activityFilters);
                    $pagination = $this->paginationFor('requests', $activityFilters, $this->administration->requestsCount($universe, $search));
                    $data['requests'] = $this->administration->requests($universe, $pagination->pageSize, $pagination->offset, $search);
                    $data['requests_search'] = $search;
                    $data += $this->paginationView('requests', $pagination, '/admin/enrolments', 'Course requests', self::withSearch($scope, 'requests', $search));
                } else {
                    $data['requests'] = [];
                }

                if (!empty($capabilities['view_enrolments'])) {
                    $search = self::searchTerm('enrolments', $activityFilters);
                    $pagination = $this->paginationFor('enrolments', $activityFilters, $this->administration->enrolmentsCount($universe, $search));
                    $data['enrolments'] = $this->normaliseEnrolments($this->administration->enrolments($universe, $pagination->pageSize, $pagination->offset, $search));
                    $data['enrolments_search'] = $search;
                    $data += $this->paginationView('enrolments', $pagination, '/admin/enrolments', 'Enrolments', self::withSearch($scope, 'enrolments', $search));
                } else {
                    $data['enrolments'] = [];
                }

                return $data;
            })(),
            // The credit-entry controls previously loaded every company, person and course to
            // populate three <select> elements. They are now htmx-driven lookups, so this
            // section loads only the ledger page it displays.
            'credits' => (function () use ($activityFilters, $universe, $scope): array {
