    }

    /** @return array<string,mixed> */
    public function personForAdministration(int $userId): array
    {
        $profile = $this->users->profile($userId) ?? throw new RuntimeException('The user account does not exist.');
        // The same whole name the person sees on their own profile, composed by the same helper, so
        // the two screens describing one person cannot call them different things.
        $profile['full_name'] = PersonName::full($profile);
        $emails = $this->users->emails($userId);
        $primary = '';
        $secondary = '';
        foreach ($emails as $email) {
            $isPrimary = in_array($email['is_primary'] ?? false, [true, 1, '1', 't', 'true'], true);
            if ($isPrimary) {
                $primary = (string) ($email['email'] ?? '');
            } elseif ($secondary === '') {
                $secondary = (string) ($email['email'] ?? '');
            }
        }
        $selectedRoles = $this->roles->roles($userId);
        $roleOptions = $this->roleOptionsForUser($selectedRoles);
        foreach ($roleOptions as &$role) {
            $role['selected'] = in_array((string) ($role['role_key'] ?? ''), $selectedRoles, true);
        }
        unset($role);
        return [
            'profile' => $profile,
            'primary_email' => $primary,
            'secondary_email' => $secondary,
            'company' => $this->companies->findForUser($userId),
            'roles' => $selectedRoles,
            'role_options' => $roleOptions,
            // The company reassignment control used to load every company into a <select>.
            // It is now an htmx lookup, so only the currently selected company is resolved.
            'selected_company' => $this->lookups->describe('companies', (int) ($profile['company_id'] ?? 0)),
        ];
    }

