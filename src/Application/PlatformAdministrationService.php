            if ((int) ($variant['access_period_seconds'] ?? 0) === $accessPeriodSeconds) {
                $allowedPeriod = true;
                break;
            }
        }
        if (!$allowedPeriod) {
            throw new InvalidArgumentException('Choose one of the active access options configured for this course.');
        }
        $company = $this->companies->findForUser($userId);
        $id = $this->administration->createRequest(
            $userId,
            $company !== null ? (int) $company['id'] : null,
            $courseId,
            $accessPeriodSeconds,
            $note
        );
        $this->audit->record($userId, 'course_request.created', ['request_id' => $id, 'course_id' => $courseId]);
        return $id;
    }

