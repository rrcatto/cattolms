    /**
     * The timestamp columns every list normaliser trims, and the fields they live in.
     *
     * PostgreSQL returns `2026-09-06 03:31:27.749417+02`. Twenty-nine characters, of which
     * microseconds and a time-zone offset are neither read nor useful in a list, and they are the
     * widest thing in several tables after the email address. Minutes is what a reader of a list
     * wants; the full value is still on the record itself.
     *
     * @var list<string>
     */
    private const TRIMMED_TIMESTAMPS = [
        'created_at', 'updated_at', 'last_login_at', 'assigned_at', 'started_at', 'completed_at',
        'expires_at', 'requested_at', 'decided_at', 'fulfilled_at', 'access_removed_at',
    ];

    /**
     * Shortens every timestamp on a row to the minute.
     *
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    private static function trimTimestamps(array $rows): array
    {
        foreach ($rows as &$row) {
            foreach (self::TRIMMED_TIMESTAMPS as $field) {
                $value = $row[$field] ?? null;
                if (is_string($value) && $value !== '' && preg_match('/^(\d{4}-\d{2}-\d{2} \d{2}:\d{2})/', $value, $match) === 1) {
                    $row[$field] = $match[1];
                }
            }
        }

        return $rows;
    }

