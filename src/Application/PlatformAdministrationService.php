    /**
     * The genuine data for one standalone Administration section, before defaults are applied.
     *
     * @param array<string,mixed> $activityFilters
     * @param array<string,bool> $capabilities
     * @return array<string,mixed>
     */
    private function sectionDataValues(
        string $section,
        int $actorUserId,
        DataUniverse $universe,
        array $activityFilters,
        array $capabilities,
