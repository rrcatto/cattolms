declare(strict_types=1);

namespace CattoLearning\Application;

use CattoLearning\Auth\CurrentUser;
use CattoLearning\Commerce\Application\TransactionAttention;
use CattoLearning\Contact\ContactReason;
use CattoLearning\Identity\IdentityVerificationService;
use CattoLearning\Infrastructure\Persistence\AdminAttentionRepository;
use CattoLearning\Infrastructure\Persistence\UserRepository;

final class AdminAttention
{
    /** What each money item's button does on its page. */
    private const MONEY_ACTIONS = [
        'underpaid' => 'See what is still due',
        'overpaid' => 'Check it and mark it dealt with',
        'cancelled_paid' => 'Check it and mark it dealt with',
        'refund_request' => 'Decide the refund',
        'refund_to_pay' => 'Record the payout',
        'unmatched' => 'Match it or pay it back',
    ];

    public function __construct(
        private readonly AdminAttentionRepository $records,
        private readonly UserRepository $users,
        private readonly TransactionAttention $money,
        private readonly IdentityVerificationService $identity
    ) {
    }

    /**
     * Every row the administrator can resolve. A row's person (owner, 2026-10-21: every person named is linked to their
     * account, with their account reference) is the subject of its title ("<person> reviewed …") or, for money, named
     * in front of its summary.
     *
     * @return list<array{kind:string,badge:string,person:?array{name:string,reference:string,href:string},subject:bool,title:string,summary:string,href:string,action:string,at:string}>
     */
    public function items(CurrentUser $admin): array
    {
        $items = [];
        if ($admin->hasPermission('PLATFORM.PERSON.MANAGE')) {
            foreach ($this->users->awaitingApproval() as $person) {
                $items[] = self::item('account', 'Account', self::person($person['id'], $person['name'] ?: $person['email'], $person['account_reference']), true, 'is waiting for approval',
                    'Registered ' . self::date($person['created_at']) . ' with ' . $person['email'] . '. Approve the account to let them sign in, or disable it to keep them out.',
                    '/admin/people/' . $person['id'], 'Approve or disable', $person['created_at']);
            }
        }
        if ($admin->hasPermission('COURSE.REVIEW.MANAGE')) {
            foreach ($this->records->pendingReviews() as $review) {
                $stars = (int) $review['rating'] . ((int) $review['rating'] === 1 ? ' star' : ' stars');
                $items[] = self::item('review', 'Review', self::person($review['person_id'], $review['person_name'], $review['person_reference']), true,
                    ((bool) $review['is_edit'] ? 'changed their review of ' : 'reviewed ') . $review['course_title'] . ': ' . $stars,
                    (bool) $review['is_edit'] ? 'The site still shows their earlier review. Approve the change to publish it, or reject it.' : 'Nothing shows on the site until you approve it. Approve it to publish it, or reject it.',
                    '/admin/course-reviews#review-' . $review['id'], 'Approve or reject', (string) $review['submitted_at']);
            }
        }
        if ($admin->hasPermission('PLATFORM.REQUEST.MANAGE')) {
            foreach ($this->records->pendingCourseRequests() as $request) {
                $company = trim((string) ($request['company_name'] ?? ''));
                $items[] = self::item('request', 'Course request', self::person($request['person_id'], $request['person_name'], $request['person_reference']), true,
                    'asked ' . ($company !== '' ? $company . ' ' : '') . 'for ' . $request['course_title'],
                    'Approve it to give them the course, or reject it. Either way they are emailed.',
                    '/admin/course/requests?requests_status=pending#request-' . $request['id'], 'Approve or reject', (string) $request['requested_at']);
            }
        }
        if ($admin->hasPermission('PLATFORM.PERSON.VIEW')) {
            foreach ($this->records->unansweredMessages() as $message) {
                // A sender without an account is named without a link.
                $sender = $message['person_id'] !== null ? self::person($message['person_id'], $message['sender_name'], $message['person_reference'])
                    : ['name' => self::name($message['sender_name']), 'reference' => '', 'href' => ''];
                $items[] = self::item('message', 'Message', $sender, true, 'sent message ' . $message['reference'] . ': ' . ContactReason::label((string) $message['reason']),
                    'Received ' . self::date((string) $message['created_at']) . '. Read it, reply by email, then mark it answered.',
                    '/admin/messages/' . $message['id'], 'Read and reply', (string) $message['created_at']);
            }
        }
        if ($admin->hasPermission('PLATFORM.PAYMENT.VIEW')) {
            foreach ($this->money->items(100) as $entry) {
                $items[] = self::item('money', 'Money', $entry['person'], false, (string) $entry['title'], (string) $entry['summary'], (string) $entry['href'],
                    self::MONEY_ACTIONS[$entry['kind']] ?? 'Open', (string) $entry['at']);
            }
        }
        if ($admin->hasPermission('PLATFORM.IDENTITY.VIEW')) {
            foreach ($this->identity->inReview() as $check) {
                $items[] = self::item('identity', 'Identity check', self::person($check['user_id'], $check['person_name'] ?? '', $check['person_reference'] ?? ''), true, 'is having their identity checked',
                    'Didit\'s reviewers are deciding it (session ' . $check['session_id'] . '). Open the person to see where it stands.',
                    '/admin/people/' . $check['user_id'] . '#identity', 'Open the person', (string) $check['started_at']);
            }
        }
        if ($admin->hasPermission('COURSE.MANAGEMENT.VIEW')) {
            foreach ($this->records->draftCourses() as $course) {
                $items[] = self::item('draft', 'Draft course', null, false, $course['title'] . ' is not published',
                    'Nobody can see or buy it. Publish it when it is ready, or delete it.',
                    '/admin/courses/' . $course['id'], 'Open the course', (string) $course['updated_at']);
            }
        }
        $order = array_flip(['account', 'review', 'request', 'message', 'money', 'identity', 'draft']);
        usort($items, static fn(array $a, array $b): int => [$order[$a['kind']], $a['at']] <=> [$order[$b['kind']], $b['at']]);
        return $items;
    }

    /**
     * @param ?array{name:string,reference:string,href:string} $person
     * @return array{kind:string,badge:string,person:?array{name:string,reference:string,href:string},subject:bool,title:string,summary:string,href:string,action:string,at:string}
     */
    private static function item(string $kind, string $badge, ?array $person, bool $subject, string $title, string $summary, string $href, string $action, string $at): array
    {
        return ['kind' => $kind, 'badge' => $badge, 'person' => $person, 'subject' => $subject && $person !== null, 'title' => $title, 'summary' => $summary, 'href' => $href, 'action' => $action, 'at' => $at];
    }

    /** @return array{name:string,reference:string,href:string} a person with an account, for data.person */
    private static function person(mixed $id, mixed $name, mixed $reference): array
    {
        return ['name' => self::name($name), 'reference' => (string) $reference, 'href' => '/admin/people/' . (int) $id];
    }

    private static function name(mixed $name): string
    {
        $name = trim((string) $name);
        return $name !== '' ? $name : 'Someone';
    }

    private static function date(string $at): string
    {
        $time = strtotime($at);
        return $time === false ? $at : date('j F Y', $time);
    }
}
