declare(strict_types=1);

namespace CattoLearning\Application;

use CattoLearning\Commerce\Document\FinancialDocumentDesignService;
use CattoLearning\Configuration\SiteLogo;
use CattoLearning\Course\Certificate\CertificateDesignService;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use InvalidArgumentException;

final class SiteLogoFollowers
{
    public function __construct(
        private readonly SiteLogo $logo,
        private readonly FinancialDocumentDesignService $documents,
        private readonly CertificateDesignService $certificates,
        private readonly AuditRepository $audit,
    ) {}

    /**
     * @return array{documents:list<string>,certificates:list<string>,kept:list<string>} what was given the new logo, and the
     *         certificate designs that kept the version they had because their words would no longer fit
     * @throws InvalidArgumentException in plain words when the file cannot be the logo
     */
    public function upload(string $bytes, int $actorId): array
    {
        $change = $this->logo->upload($bytes, $actorId);
        $this->audit->record($actorId, 'site_owner.logo_changed', $change);
        return $this->follow($actorId);
    }

    /** @return array{documents:list<string>,certificates:list<string>,kept:list<string>}|null null when there was no logo */
    public function remove(int $actorId): ?array
    {
        $removed = $this->logo->remove($actorId);
        if ($removed === null) return null;
        $this->audit->record($actorId, 'site_owner.logo_changed', ['from' => $removed, 'to' => null]);
        return $this->follow($actorId);
    }

    /** @return array{documents:list<string>,certificates:list<string>,kept:list<string>} */
    private function follow(int $actorId): array
    {
        $certificates = $this->certificates->followSiteLogo($actorId);
        return ['documents' => $this->documents->followSiteLogo($actorId), 'certificates' => $certificates['changed'], 'kept' => $certificates['kept']];
    }
}
