Uploading or removing the site logo at Settings > Site Owner (owner, 2026-11-09), and what follows it: the financial
document design and every certificate design that prints the site logo publish new versions with the new one
(FinancialDocumentDesignService::followSiteLogo, CertificateDesignService::followSiteLogo), so a document issued from
then on carries it and one already issued keeps the logo it was issued with. The PDFs drawn from templates and the
emails read the logo when they are made, so they need nothing. The change is in the Activity log
(site_owner.logo_changed, with the versions before and after).

