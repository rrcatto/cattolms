declare(strict_types=1);

namespace CattoLearning\Application;

use CattoLearning\Auth\AuthService;
use CattoLearning\Auth\CurrentUser;
use CattoLearning\Auth\TwoStep\PendingSignIn;
use CattoLearning\Auth\TwoStep\TwoStep;
use CattoLearning\OwnerMessages\TelegramConnections;
use CattoLearning\OwnerMessages\TelegramFailed;
use CattoLearning\OwnerMessages\TelegramInbox;
use InvalidArgumentException;

class AccountSecurity
{
    private const NOTE = 'account_security_note';
    /** Where the two-step key being set up and the codes just made are held in the session (PendingSignIn). */
    private const CONTEXT = 'account';

    public function __construct(
        private readonly AuthService $auth,
        private readonly TwoStep $twoStep,
        private readonly PendingSignIn $session,
        private readonly TelegramConnections $telegram,
        private readonly TelegramInbox $inbox,
    ) {
    }

    /**
     * What the page shows. $ask is the two-step action waiting for a current code ('off' or 'codes'), from the address.
     *
     * @return array{telegram:array<string,mixed>,two_step:array<string,mixed>}
     */
    public function view(CurrentUser $user, string $ask = ''): array
    {
        $telegram = $this->telegram->view($user->id);
        // While the page waits for Telegram, it reads what the bot was sent (at most once every 2 seconds) and notices.
        if ($telegram['state'] === 'waiting') {
            try {
                if ($this->inbox->read(true) > 0) $telegram = $this->telegram->view($user->id);
            } catch (TelegramFailed) {
            }
        }
        $required = $this->auth->twoStepRequired($user->id, $user->primaryEmail);
        $state = $this->twoStep->state($user->id);
        $codes = $this->session->recoveryCodes(self::CONTEXT);
        $secret = $this->session->setUpSecret(self::CONTEXT);
        $two = ['state' => $state['on'] ? 'on' : 'off', 'required' => $required, 'since' => $state['since'], 'left' => $state['left'], 'qr' => '', 'key' => '', 'codes' => [],
            'ask' => $state['on'] && in_array($ask, ['off', 'codes'], true) && !($ask === 'off' && $required) ? $ask : ''];
        if ($codes !== [] && $state['on']) {
            $two = ['state' => 'codes', 'codes' => $codes] + $two;
        } elseif ($secret !== null && !$state['on']) {
            $two = ['state' => 'scan'] + $this->twoStep->picture($secret, $user->primaryEmail) + $two;
        }

        return ['telegram' => ['note' => $this->note('telegram') ?? $telegram['note']] + $telegram, 'two_step' => ['note' => $this->note('two_step')] + $two];
    }

    public function connectTelegram(CurrentUser $user): void
    {
        $this->telegram->start($user->id, $user->primaryEmail);
    }

    public function cancelTelegram(CurrentUser $user): void
    {
        $this->telegram->cancel($user->id);
    }

    /** "I have pressed Start", for a page without JavaScript: read what the bot was sent now. */
    public function checkTelegram(CurrentUser $user): void
    {
        try {
            $this->inbox->read();
        } catch (TelegramFailed) {
        }
        if ($this->telegram->view($user->id)['state'] === 'waiting') $this->keep('telegram', 'info', 'Telegram has not told us yet. Press Start in the chat with the bot, then press I have pressed Start again.');
    }

    public function testTelegram(CurrentUser $user): void
    {
        $this->telegram->test($user->id)
            ? $this->keep('telegram', 'success', 'Sent. Check your phone.')
            : $this->keep('telegram', 'danger', 'Telegram did not take the message. Open the chat with the bot, press Start, and try again.');
    }

    public function disconnectTelegram(CurrentUser $user): void
    {
        $this->telegram->disconnect($user->id);
        $this->keep('telegram', 'success', 'Telegram is disconnected. Sign in by email from now on.');
    }

    public function startTwoStep(CurrentUser $user): void
    {
        if ($this->twoStep->isOn($user->id)) throw new InvalidArgumentException('Two-step sign-in is on already.');
        $this->session->setUpSecret(self::CONTEXT, $this->twoStep->newSecret());
    }

    public function confirmTwoStep(CurrentUser $user, string $code): void
    {
        $secret = $this->session->setUpSecret(self::CONTEXT) ?? throw new InvalidArgumentException('Press Set up two-step to start again.');
        $codes = $this->twoStep->turnOn($user->id, $secret, $code);
        if ($codes === null) {
            $this->keep('two_step', 'danger', TwoStep::WRONG);

            return;
        }
        $this->session->forgetSetUpSecret(self::CONTEXT);
        $this->session->recoveryCodes(self::CONTEXT, $codes);
    }

    public function cancelTwoStep(): void
    {
        $this->session->forgetSetUpSecret(self::CONTEXT);
    }

    /** "I have kept them": the codes are not shown again. */
    public function keptCodes(): void
    {
        $this->session->forgetRecoveryCodes(self::CONTEXT);
    }

    public function newRecoveryCodes(CurrentUser $user, string $code): void
    {
        try {
            $this->session->recoveryCodes(self::CONTEXT, $this->twoStep->newRecoveryCodes($user->id, $code));
        } catch (InvalidArgumentException $wrong) {
            $this->keep('two_step', 'danger', $wrong->getMessage());
            throw $wrong;
        }
    }

    public function turnOffTwoStep(CurrentUser $user, string $code): void
    {
        try {
            $this->twoStep->turnOff($user->id, $code, $this->auth->twoStepRequired($user->id, $user->primaryEmail));
        } catch (\RuntimeException $refused) {
            $this->keep('two_step', 'danger', $refused->getMessage());
            throw $refused;
        }
        $this->keep('two_step', 'success', 'Two-step sign-in is off.');
    }

    /** A card's note after an action, kept until the card is drawn. */
    public function keep(string $card, string $tone, string $words): void
    {
        $_SESSION[self::NOTE][$card] = ['tone' => $tone, 'words' => $words];
    }

    /** @return array{tone:string,words:string}|null */
    private function note(string $card): ?array
    {
        $note = $_SESSION[self::NOTE][$card] ?? null;
        unset($_SESSION[self::NOTE][$card]);

        return is_array($note) && isset($note['tone'], $note['words']) ? ['tone' => (string) $note['tone'], 'words' => (string) $note['words']] : null;
    }
}
