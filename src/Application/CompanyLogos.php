declare(strict_types=1);

namespace CattoLearning\Application;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\CompanyLogoRepository;
use CattoLearning\Support\CompanyLogo;
use CattoLearning\View\Artwork\DrawnAvatar;
use RuntimeException;

final class CompanyLogos
{
    public function __construct(
        private readonly CompanyLogoRepository $logos,
        private readonly AuditRepository $audit,
    ) {
    }

    /**
     * Whether the company has a logo, and its picture's version. Null for a company that does not exist.
     *
     * @return array{uploaded:bool,version:string}|null
     */
    public function state(int $companyId): ?array
    {
        $state = $this->logos->state($companyId);

        return $state === null ? null : ['uploaded' => $state['uploaded'], 'version' => self::versionOf($state)];
    }

    /**
     * Each company row with the address of its picture ("logo_url", Administration's) and whether it is an upload.
     *
     * @param list<array<string,mixed>> $rows
     * @return list<array<string,mixed>>
     */
    public function withPictures(array $rows): array
    {
        $states = $this->logos->states(array_map(static fn(array $row): int => (int) ($row['id'] ?? 0), $rows));
        foreach ($rows as $index => $row) {
            $state = $states[(int) ($row['id'] ?? 0)] ?? null;
            $rows[$index]['logo_url'] = $state === null ? '' : '/admin/companies/' . (int) $row['id'] . '/logo?v=' . self::versionOf($state);
            $rows[$index]['logo_uploaded'] = $state !== null && $state['uploaded'];
        }

        return $rows;
    }

    /** @param array{public_id:string,uploaded:bool,upload_version:string} $state */
    public static function versionOf(array $state): string
    {
        return $state['uploaded'] ? $state['upload_version'] : 's' . DrawnAvatar::version('company', $state['public_id']);
    }

    /**
     * The picture itself: the logo, or the drawn one as SVG.
     *
     * @return array{bytes:string,mime_type:string,drawn:bool}
     */
    public function picture(int $companyId): array
    {
        $state = $this->logos->state($companyId) ?? throw new RuntimeException('There is no such company.');
        $logo = $state['uploaded'] ? $this->logos->logo($companyId) : null;

        return $logo !== null
            ? ['bytes' => $logo['bytes'], 'mime_type' => $logo['mime_type'], 'drawn' => false]
            : ['bytes' => DrawnAvatar::company($state['public_id']), 'mime_type' => 'image/svg+xml', 'drawn' => true];
    }

    /** Stores an uploaded logo in place of the company's last one. */
    public function upload(int $companyId, string $bytes, int $actorUserId): void
    {
        if ($this->logos->state($companyId) === null) {
            throw new RuntimeException('There is no such company.');
        }
        $logo = CompanyLogo::fromUpload($bytes);
        $this->logos->store($companyId, $logo->bytes, $logo->mimeType, $logo->width, $logo->height, $actorUserId);
        $this->audit->record($actorUserId, 'company.logo_changed', ['company_id' => $companyId, 'type' => $logo->mimeType]);
    }

    public function remove(int $companyId, int $actorUserId): void
    {
        $this->logos->remove($companyId);
        $this->audit->record($actorUserId, 'company.logo_removed', ['company_id' => $companyId]);
    }
}
