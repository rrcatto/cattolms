declare(strict_types=1);

namespace CattoLearning\Analytics;

final class CampaignAttribution
{
    public const PARAMETERS = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_content', 'utm_term'];

    private function __construct()
    {
    }

    /**
     * The utm_ parameters from an address's query (or a stored campaign), cleaned; empty when none.
     *
     * @param array<array-key,mixed> $query
     * @return array<string,string>
     */
    public static function from(array $query): array
    {
        $campaign = [];
        foreach (self::PARAMETERS as $name) {
            $value = $query[$name] ?? null;
            if (!is_string($value) || !mb_check_encoding($value, 'UTF-8')) {
                continue;
            }
            $value = trim((string) preg_replace('/[\x00-\x1F\x7F]+/u', ' ', $value));
            if ($value !== '') {
                $campaign[$name] = mb_substr($value, 0, 64);
            }
        }
        return $campaign;
    }
}
