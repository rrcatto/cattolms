namespace CattoLearning\Document;

use CattoLearning\Infrastructure\Persistence\Database;

final class DocumentTemplateRepository
{
    private const VERSION_COLUMNS = 'v.id, v.template_id, v.version_number, v.state, v.html, v.css, v.page_size, v.page_orientation,
        v.margin_top_mm, v.margin_right_mm, v.margin_bottom_mm, v.margin_left_mm, v.change_note, v.based_on_version_id,
        v.created_at, v.updated_at, v.published_at, t.document_type, t.name AS template_name,
        COALESCE(NULLIF(trim(concat_ws(\' \', cu.first_name, cu.last_name)), \'\'), cu.display_name) AS created_by_name,
        COALESCE(NULLIF(trim(concat_ws(\' \', pu.first_name, pu.last_name)), \'\'), pu.display_name) AS published_by_name';
    private const VERSION_FROM = 'document_template_versions v JOIN document_templates t ON t.id = v.template_id
        LEFT JOIN users cu ON cu.id = v.created_by_user_id LEFT JOIN users pu ON pu.id = v.published_by_user_id';

    public function __construct(private readonly Database $db) {}

    /** @return array<string,mixed>|null */
    public function version(int $id): ?array
    {
        $row = $this->db->fetchAssociative('SELECT ' . self::VERSION_COLUMNS . ' FROM ' . self::VERSION_FROM . ' WHERE v.id = :id', ['id' => $id]);
        return $row === false ? null : $row;
    }

    /**
     * The published version documents of this type are generated from now.
     *
     * @return array<string,mixed>|null
     */
    public function currentVersion(DocumentType $type): ?array
    {
        $row = $this->db->fetchAssociative(
            'SELECT ' . self::VERSION_COLUMNS . ' FROM ' . self::VERSION_FROM . ' WHERE t.document_type = :type AND t.is_current AND v.id = t.published_version_id',
            ['type' => $type->value]
        );
        return $row === false ? null : $row;
    }
}
