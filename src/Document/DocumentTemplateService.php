<?php

/*
Generated by: Claude Code CLI

Date time: 2026/10/06 SAST

Version: 0.8.8.7

Description:
What an administrator does with document templates: create one, edit its draft, preview, publish,
start a draft from any earlier version, archive. Every change runs in one transaction under the
template's row lock and is audited by reference to the version, never with the HTML or CSS body.

- A template has at most one draft. Saving when there is none starts one from the published
  version, so editing after publication never touches the published version.
- Publishing validates the draft completely, fixes it for ever, and makes the template the current
  one for its document type.
- Re-using an earlier version starts a new draft from it; history is never rewritten.

Changelog:
2026/10/06 SAST
- Created for the shared document template engine (Phase I).
*/

declare(strict_types=1);

namespace CattoLearning\Document;

use CattoLearning\Auth\CurrentUser;
use CattoLearning\Document\Template\TemplateValidator;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use RuntimeException;

final class DocumentTemplateService
{
    public const NAME_LIMIT = 120;
    public const DESCRIPTION_LIMIT = 1000;
    public const NOTE_LIMIT = 500;

    public function __construct(
        private readonly DocumentTemplateRepository $templates,
        private readonly TemplateValidator $validator,
        private readonly DocumentTemplateRenderer $renderer,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
    ) {}

    /**
     * Creates a template of a type with a first draft taken from the type's source default.
     *
     * @param array<string,mixed> $input name, description, document_type
     */
    public function create(CurrentUser $actor, array $input): int
    {
        $type = DocumentType::tryFrom((string) ($input['document_type'] ?? '')) ?? throw new RuntimeException('Choose a document type.');
        [$name, $description] = self::details($input);
        return $this->transactions->run(function () use ($actor, $type, $name, $description): int {
            if ($this->templates->nameTaken($type, $name)) {
                throw new RuntimeException('There is already a ' . strtolower($type->label()) . ' template called "' . $name . '".');
            }
            $id = $this->templates->createTemplate($type, $name, $description, $actor->id);
            $default = DocumentTemplateDefaults::for($type);
            $versionId = $this->templates->createDraft($id, 1, $default['html'], $default['css'], $type->defaultSettings(), null, null, $actor->id);
            $this->audit->record($actor->id, 'document_template.created', ['template_id' => $id, 'document_type' => $type->value, 'name' => $name]);
            $this->audit->record($actor->id, 'document_template.version_created', ['template_id' => $id, 'version_id' => $versionId, 'version_number' => 1, 'source' => 'default']);
            return $id;
        });
    }

    /** @param array<string,mixed> $input name, description */
    public function updateDetails(CurrentUser $actor, int $templateId, array $input): void
    {
        [$name, $description] = self::details($input);
        $this->transactions->run(function () use ($actor, $templateId, $name, $description): void {
            $template = $this->lock($templateId);
            $type = DocumentType::from((string) $template['document_type']);
            if ($this->templates->nameTaken($type, $name, $templateId)) {
                throw new RuntimeException('There is already a ' . strtolower($type->label()) . ' template called "' . $name . '".');
            }
            $this->templates->updateDetails($templateId, $name, $description, $actor->id);
            $this->audit->record($actor->id, 'document_template.details_updated', ['template_id' => $templateId, 'name' => $name]);
        });
    }

    /**
     * Saves the draft, starting one from the published version when there is none. The content must
     * validate: an unknown placeholder or malformed block is reported and nothing is saved.
     *
     * @param array<string,mixed> $input html, css, page settings, change_note
     * @return int the draft's version id
     */
    public function saveDraft(CurrentUser $actor, int $templateId, array $input): int
    {
        [$html, $css, $settings, $note] = $this->content($templateId, $input);
        return $this->transactions->run(function () use ($actor, $templateId, $html, $css, $settings, $note): int {
            $template = $this->lock($templateId);
            $this->assertEditable($template);
            $draft = $this->templates->draft($templateId);
            if ($draft !== null) {
                $this->templates->updateDraft((int) $draft['id'], $html, $css, $settings, $note, $actor->id);
                $this->audit->record($actor->id, 'document_template.draft_edited', ['template_id' => $templateId, 'version_id' => (int) $draft['id'], 'version_number' => (int) $draft['version_number']]);
                return (int) $draft['id'];
            }
            $number = $this->templates->nextVersionNumber($templateId);
            $basedOn = $template['published_version_id'] === null ? null : (int) $template['published_version_id'];
            $versionId = $this->templates->createDraft($templateId, $number, $html, $css, $settings, $note, $basedOn, $actor->id);
            $this->audit->record($actor->id, 'document_template.version_created', ['template_id' => $templateId, 'version_id' => $versionId, 'version_number' => $number, 'based_on_version_id' => $basedOn]);
            return $versionId;
        });
    }

    /**
     * Saves the submitted draft and publishes it in one transaction: the published version is the
     * content that was on the screen.
     *
     * @param array<string,mixed> $input
     * @return array{version_id:int,version_number:int}
     */
    public function saveAndPublish(CurrentUser $actor, int $templateId, array $input): array
    {
        return $this->transactions->run(function () use ($actor, $templateId, $input): array {
            $this->saveDraft($actor, $templateId, $input);
            return $this->publish($actor, $templateId);
        });
    }

    /**
     * Publishes the saved draft after validating it completely.
     *
     * @return array{version_id:int,version_number:int}
     */
    public function publish(CurrentUser $actor, int $templateId): array
    {
        return $this->transactions->run(function () use ($actor, $templateId): array {
            $template = $this->lock($templateId);
            $this->assertEditable($template);
            $draft = $this->templates->draft($templateId) ?? throw new RuntimeException('There is no draft to publish. Save a draft first.');
            $type = DocumentType::from((string) $template['document_type']);
            $settings = PageSettings::fromInput($draft);
            // The same renderer documents use, with the type's sample data: a version that cannot
            // render a complete sample document is not published.
            $this->renderer->renderSource($type, (string) $draft['html'], (string) $draft['css'], $settings, DocumentSampleData::for($type));
            $this->templates->publish($templateId, (int) $draft['id'], $type, $actor->id);
            $this->audit->record($actor->id, 'document_template.published', [
                'template_id' => $templateId, 'document_type' => $type->value,
                'version_id' => (int) $draft['id'], 'version_number' => (int) $draft['version_number'],
            ]);
            return ['version_id' => (int) $draft['id'], 'version_number' => (int) $draft['version_number']];
        });
    }

    /**
     * Starts a new draft from any version of the template. History is never changed: an earlier
     * version is re-used by copying it into a new draft, which is published like any other.
     */
    public function draftFromVersion(CurrentUser $actor, int $templateId, int $versionId): int
    {
        return $this->transactions->run(function () use ($actor, $templateId, $versionId): int {
            $template = $this->lock($templateId);
            $this->assertEditable($template);
            $source = $this->templates->version($versionId);
            if ($source === null || (int) $source['template_id'] !== $templateId) {
                throw new RuntimeException('That version does not belong to this template.');
            }
            if ($this->templates->draft($templateId) !== null) {
                throw new RuntimeException('This template already has a draft. Publish or discard it before starting another.');
            }
            $number = $this->templates->nextVersionNumber($templateId);
            $note = 'Started from version ' . $source['version_number'] . '.';
            $id = $this->templates->createDraft($templateId, $number, (string) $source['html'], (string) $source['css'], PageSettings::fromInput($source), $note, $versionId, $actor->id);
            $this->audit->record($actor->id, 'document_template.draft_from_version', ['template_id' => $templateId, 'version_id' => $id, 'version_number' => $number, 'based_on_version_id' => $versionId]);
            return $id;
        });
    }

    public function discardDraft(CurrentUser $actor, int $templateId): void
    {
        $this->transactions->run(function () use ($actor, $templateId): void {
            $this->lock($templateId);
            $draft = $this->templates->draft($templateId) ?? throw new RuntimeException('There is no draft to discard.');
            $this->templates->deleteDraft((int) $draft['id']);
            $this->audit->record($actor->id, 'document_template.draft_discarded', ['template_id' => $templateId, 'version_number' => (int) $draft['version_number']]);
        });
    }

    public function setArchived(CurrentUser $actor, int $templateId, bool $archived): void
    {
        $this->transactions->run(function () use ($actor, $templateId, $archived): void {
            $template = $this->lock($templateId);
            if ($archived && (bool) $template['is_current']) {
                throw new RuntimeException('The current template of a document type cannot be archived. Publish another template of this type first.');
            }
            $this->templates->setStatus($templateId, $archived ? 'archived' : 'active', $actor->id);
            $this->audit->record($actor->id, $archived ? 'document_template.archived' : 'document_template.restored', ['template_id' => $templateId]);
        });
    }

    /**
     * Renders submitted, unsaved content with the type's sample data - the editor's Preview. It goes
     * through the renderer production documents use.
     *
     * @param array<string,mixed> $input
     */
    public function preview(int $templateId, array $input): RenderedDocument
    {
        [$html, $css, $settings] = $this->content($templateId, $input);
        $type = DocumentType::from((string) $this->find($templateId)['document_type']);
        return $this->renderer->renderSource($type, $html, $css, $settings, DocumentSampleData::for($type), $templateId);
    }

    /** A stored version rendered with its type's sample data. */
    public function previewVersion(int $versionId): RenderedDocument
    {
        $version = $this->templates->version($versionId) ?? throw new RuntimeException('That template version does not exist.');
        return $this->renderer->renderVersion($versionId, DocumentSampleData::for(DocumentType::from((string) $version['document_type'])));
    }

    /**
     * Validates and normalises submitted content without saving it.
     *
     * @param array<string,mixed> $input
     * @return array{0:string,1:string,2:PageSettings,3:?string}
     */
    private function content(int $templateId, array $input): array
    {
        $type = DocumentType::from((string) $this->find($templateId)['document_type']);
        $html = str_replace("\r\n", "\n", (string) ($input['html'] ?? ''));
        $css = str_replace("\r\n", "\n", (string) ($input['css'] ?? ''));
        $note = trim((string) ($input['change_note'] ?? ''));
        $errors = [];
        if (mb_strlen($note) > self::NOTE_LIMIT) {
            $errors[] = 'The change note can be at most ' . self::NOTE_LIMIT . ' characters.';
        }
        $settings = null;
        try {
            $settings = PageSettings::fromInput($input);
        } catch (TemplateValidationException $invalid) {
            $errors = [...$errors, ...$invalid->errors];
        }
        try {
            $this->validator->validate($type, $html, $css);
        } catch (TemplateValidationException $invalid) {
            $errors = [...$errors, ...$invalid->errors];
        }
        if ($errors !== [] || $settings === null) {
            throw new TemplateValidationException($errors);
        }
        return [$html, $css, $settings, $note === '' ? null : $note];
    }

    /** @return array<string,mixed> */
    private function find(int $templateId): array
    {
        return $this->templates->template($templateId) ?? throw new RuntimeException('That document template does not exist.');
    }

    /** @return array<string,mixed> */
    private function lock(int $templateId): array
    {
        return $this->templates->template($templateId, true) ?? throw new RuntimeException('That document template does not exist.');
    }

    /** @param array<string,mixed> $template */
    private function assertEditable(array $template): void
    {
        if ($template['status'] === 'archived') {
            throw new RuntimeException('This template is archived. Restore it before changing it.');
        }
    }

    /**
     * @param array<string,mixed> $input
     * @return array{0:string,1:?string}
     */
    private static function details(array $input): array
    {
        $name = trim((string) ($input['name'] ?? ''));
        $description = trim((string) ($input['description'] ?? ''));
        if ($name === '' || mb_strlen($name) > self::NAME_LIMIT) {
            throw new RuntimeException('Give the template a name of up to ' . self::NAME_LIMIT . ' characters.');
        }
        if (mb_strlen($description) > self::DESCRIPTION_LIMIT) {
            throw new RuntimeException('The description can be at most ' . self::DESCRIPTION_LIMIT . ' characters.');
        }
        return [$name, $description === '' ? null : $description];
    }
}
