<?php

/*
Generated by: Claude Code CLI

Date time: 2026/10/07 SAST

Version: 0.8.8.10

Description:
Stored document images: certificate backgrounds, logos and signatures. An image is kept once,
addressed by the SHA-256 of its bytes, and never changes, so a template version that names it
(asset:<sha256>) draws the same picture for ever and two designs using one picture share it. The
renderer embeds the bytes as a data: URI when it renders; nothing is fetched.

Bytes travel as base64 through decode()/encode() in SQL, as profile images do, so no binary value is
bound through PDO.

Changelog:
2026/10/07 SAST
- Created for certificate designs with uploaded backgrounds, logos and signatures.
*/

declare(strict_types=1);

namespace CattoLearning\Document;

use CattoLearning\Infrastructure\Persistence\Database;

final class DocumentAssetRepository
{
    public function __construct(private readonly Database $db) {}

    /**
     * Keeps an image and returns its address. An image already stored is not stored again.
     *
     * @return string the SHA-256 of the bytes
     */
    public function store(string $bytes, string $mimeType, int $width, int $height, ?int $actorId): string
    {
        $sha = hash('sha256', $bytes);
        $this->db->executeStatement(
            "INSERT INTO document_assets (sha256, mime_type, byte_size, width, height, data, created_by_user_id)
             VALUES (:sha, :mime, :size, :width, :height, decode(:data, 'base64'), :actor)
             ON CONFLICT (sha256) DO NOTHING",
            ['sha' => $sha, 'mime' => $mimeType, 'size' => strlen($bytes), 'width' => $width, 'height' => $height, 'data' => base64_encode($bytes), 'actor' => $actorId]
        );
        return $sha;
    }

    public function exists(string $sha): bool
    {
        return preg_match('/^[0-9a-f]{64}$/D', $sha) === 1
            && (bool) $this->db->fetchOne('SELECT EXISTS (SELECT 1 FROM document_assets WHERE sha256 = :sha)', ['sha' => $sha]);
    }

    /** @return array{sha256:string,mime_type:string,width:int,height:int,byte_size:int,bytes:string}|null */
    public function find(string $sha): ?array
    {
        if (preg_match('/^[0-9a-f]{64}$/D', $sha) !== 1) {
            return null;
        }
        $row = $this->db->fetchAssociative(
            "SELECT sha256, mime_type, width, height, byte_size, encode(data, 'base64') AS encoded FROM document_assets WHERE sha256 = :sha",
            ['sha' => $sha]
        );
        if ($row === false) {
            return null;
        }
        return [
            'sha256' => (string) $row['sha256'], 'mime_type' => (string) $row['mime_type'],
            'width' => (int) $row['width'], 'height' => (int) $row['height'], 'byte_size' => (int) $row['byte_size'],
            'bytes' => (string) base64_decode(str_replace(["\n", "\r"], '', (string) $row['encoded']), true),
        ];
    }

    /** The image as a data: URI, or null when it is not stored. */
    public function dataUri(string $sha): ?string
    {
        $asset = $this->find($sha);
        return $asset === null ? null : 'data:' . $asset['mime_type'] . ';base64,' . base64_encode($asset['bytes']);
    }
}
