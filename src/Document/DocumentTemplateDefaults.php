namespace CattoLearning\Document;

use RuntimeException;

final class DocumentTemplateDefaults
{
    /** @return array{name:string,description:string,html:string,css:string} */
    public static function for(DocumentType $type): array
    {
        $base = dirname(__DIR__, 2) . '/resources/documents/' . $type->value;
        $html = @file_get_contents($base . '.html');
        $css = @file_get_contents($base . '.css');
        if ($html === false || $css === false) {
            throw new RuntimeException('The default ' . strtolower($type->label()) . ' template is missing from resources/documents/.');
        }
        return [
            'name' => 'Standard ' . strtolower($type->label()),
            'description' => 'The default ' . strtolower($type->label()) . ' template supplied with CattoLMS.',
            'html' => $html,
            'css' => $css,
        ];
    }
}
