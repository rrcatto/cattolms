declare(strict_types=1);

namespace CattoLearning\Document;

use RuntimeException;

final class DocumentTemplateDefaults
{
    /** file key => [name, description], the first of each type being its default and current design */
    private const PRESETS = [
        'certificate' => [
            'certificate-classic' => ['Classic certificate', 'Formal serif typography in a double-ruled frame, centred, with signatures at the foot.'],
            'certificate-modern' => ['Modern certificate', 'A solid accent band, clean sans-serif type and a ruled footer row.'],
            'certificate-minimal' => ['Minimal certificate', 'Generous whitespace, two hairlines and the learner’s name in large type.'],
        ],
        'invoice' => ['invoice' => ['Standard invoice', 'The default invoice template supplied with CattoLMS.']],
        'receipt' => ['receipt' => ['Standard receipt', 'The default receipt template supplied with CattoLMS.']],
        'credit_note' => ['credit_note' => ['Standard credit note', 'The default credit note template supplied with CattoLMS.']],
    ];

    /**
     * The type's default design, which a new template's first draft starts from.
     *
     * @return array{key:string,name:string,description:string,html:string,css:string}
     */
    public static function for(DocumentType $type): array
    {
        return self::presets($type)[0];
    }

    /**
     * Every starter design of a type, default first.
     *
     * @return list<array{key:string,name:string,description:string,html:string,css:string}>
     */
    public static function presets(DocumentType $type): array
    {
        $presets = [];
        foreach (self::PRESETS[$type->value] as $key => [$name, $description]) {
            $base = dirname(__DIR__, 2) . '/resources/documents/' . $key;
            $html = @file_get_contents($base . '.html');
            $css = @file_get_contents($base . '.css');
            if ($html === false || $css === false) {
                throw new RuntimeException('The starter template "' . $key . '" is missing from resources/documents/.');
            }
            $presets[] = ['key' => $key, 'name' => $name, 'description' => $description, 'html' => $html, 'css' => $css];
        }
        return $presets;
    }
}
