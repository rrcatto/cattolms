/*
Generated by: Claude Code CLI

Date time: 2026/10/06 SAST

Version: 0.8.8.7

Description:
The one renderer for document templates. The administrator's preview, a stored version, the current
template of a type and the PDF all come from renderSource(), so what the preview shows is what a
document will be: there is no second rendering path to drift from it.

    renderCurrent('invoice', $data)   the published version documents of a type use now
    renderVersion($versionId, $data)  one exact version, published or draft, to reproduce a document
    renderSource(...)                 unsaved content, for previewing edits

$data is a flat dictionary keyed by registered placeholder name ('invoice.number' => 'INV-1'), with
each collection as a list of entries keyed by field ('items' => [['description' => ...], ...]). It is
validated against the registry first: an unregistered key, a missing required value or a value of
the wrong kind is an error, never a blank. A published version that no longer validates is an error
too - the renderer never falls back to another template for a legal or financial document.

Changelog:
2026/10/07 SAST
- Embeds stored pictures: an asset:<sha256> reference in an img src or a CSS url() becomes a data: URI read from document_assets, and a missing picture stops the render with a clear message.
2026/10/06 SAST
- Created for the shared document template engine (Phase I).
*/

declare(strict_types=1);

namespace CattoLearning\Document;

use CattoLearning\Document\Template\CollectionDefinition;
use CattoLearning\Document\Template\DocumentValueFormatter;
use CattoLearning\Document\Template\PlaceholderRegistry;
use CattoLearning\Document\Template\PlaceholderSet;
use CattoLearning\Document\Template\TemplateValidator;
use InvalidArgumentException;
use RuntimeException;

final class DocumentTemplateRenderer
{
    public function __construct(
        private readonly DocumentTemplateRepository $templates,
        private readonly PlaceholderRegistry $registry,
        private readonly TemplateValidator $validator,
        private readonly DocumentValueFormatter $formatter,
        private readonly ?DocumentAssetRepository $assets = null,
    ) {}

    /** @param array<string,mixed> $data */
    public function renderCurrent(DocumentType|string $type, array $data): RenderedDocument
    {
        $type = $type instanceof DocumentType ? $type : (DocumentType::tryFrom($type) ?? throw new InvalidArgumentException('Unknown document type "' . $type . '".'));
        $version = $this->templates->currentVersion($type)
            ?? throw new RuntimeException('No published ' . strtolower($type->label()) . ' template is current; publish one before generating ' . strtolower($type->label()) . 's.');
        return $this->renderRow($version, $data);
    }

    /** @param array<string,mixed> $data */
    public function renderVersion(int $versionId, array $data): RenderedDocument
    {
        $version = $this->templates->version($versionId) ?? throw new RuntimeException('Document template version ' . $versionId . ' does not exist.');
        return $this->renderRow($version, $data);
    }

    /**
     * @param array<string,mixed> $data
     * @throws TemplateValidationException when the template is not valid
     * @throws DocumentDataException when the data does not fit the document type's placeholders
     */
    public function renderSource(DocumentType $type, string $html, string $css, PageSettings $settings, array $data, ?int $templateId = null, ?int $versionId = null, ?int $versionNumber = null): RenderedDocument
    {
        $tree = $this->validator->validate($type, $html, $css);
        $set = $this->registry->forType($type);
        $this->checkData($set, $data);
        $body = $this->embedAssets($this->nodes($tree, $set, $data, null, []));
        $title = DocumentValueFormatter::escape($type->label());
        $document = '<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>' . $title . '</title>'
            . '<style>' . $settings->css() . '</style>'
            . ($css !== '' ? '<style>' . $this->embedAssets($css) . '</style>' : '')
            . '</head><body>' . $body . '</body></html>';
        return new RenderedDocument($type, $document, $body, $settings, $templateId, $versionId, $versionNumber);
    }

    /**
     * Replaces each stored image reference (asset:<sha256>) in an src attribute or a CSS url() with
     * the image itself. A reference to an image that is not stored is an error, never a blank.
     */
    private function embedAssets(string $source): string
    {
        if (!str_contains($source, 'asset:')) {
            return $source;
        }
        $embed = function (string $sha): string {
            $uri = $this->assets?->dataUri($sha);
            if ($uri === null) {
                throw new RuntimeException('The document image ' . $sha . ' is not stored.');
            }
            return $uri;
        };
        $source = (string) preg_replace_callback('/(\bsrc=")asset:([0-9a-f]{64})(")/', static fn(array $m): string => $m[1] . $embed($m[2]) . $m[3], $source);
        return (string) preg_replace_callback('/url\(\s*([\'"]?)asset:([0-9a-f]{64})\1\s*\)/', static fn(array $m): string => 'url("' . $embed($m[2]) . '")', $source);
    }

    /**
     * @param array<string,mixed> $row
     * @param array<string,mixed> $data
     */
    private function renderRow(array $row, array $data): RenderedDocument
    {
        $type = DocumentType::from((string) $row['document_type']);
        try {
            return $this->renderSource($type, (string) $row['html'], (string) $row['css'], PageSettings::fromInput($row), $data,
                (int) $row['template_id'], (int) $row['id'], (int) $row['version_number']);
        } catch (TemplateValidationException $invalid) {
            // A stored version is validated when it is saved and published; reaching here means it was
            // changed outside the application or the registry lost a name it uses. Never render a
            // different template instead.
            throw new RuntimeException('Document template version ' . $row['id'] . ' (' . $row['template_name'] . ' v' . $row['version_number'] . ') is not valid: ' . $invalid->getMessage(), 0, $invalid);
        }
    }

    /** @param array<string,mixed> $data */
    private function checkData(PlaceholderSet $set, array $data): void
    {
        $errors = [];
        foreach ($data as $key => $value) {
            $key = (string) $key;
            if (isset($set->collections[$key])) {
                if (!is_array($value) || !array_is_list($value)) {
                    $errors[] = $key . ' must be a list of entries.';
                    continue;
                }
                foreach ($value as $index => $entry) {
                    $errors = [...$errors, ...$this->checkEntry($set->collections[$key], $index, $entry)];
                }
            } elseif (isset($set->scalars[$key])) {
                $problem = $this->formatter->problem($set->scalars[$key], $value);
                if ($problem !== null) $errors[] = $problem;
            } else {
                $errors[] = $key . ' is not a registered placeholder for this document type.';
            }
        }
        foreach ($set->scalars as $name => $definition) {
            if ($definition->required && !$this->formatter->present($definition, $data[$name] ?? null) && !self::zeroMoney($definition, $data[$name] ?? null)) {
                $errors[] = $name . ' is required.';
            }
        }
        if ($errors !== []) {
            throw new DocumentDataException($errors);
        }
    }

    /** @return list<string> */
    private function checkEntry(CollectionDefinition $collection, int $index, mixed $entry): array
    {
        if (!is_array($entry)) {
            return [$collection->name . '[' . $index . '] must be an entry of fields.'];
        }
        $errors = [];
        foreach ($entry as $field => $value) {
            $definition = $collection->fields[(string) $field] ?? null;
            if ($definition === null) {
                $errors[] = $collection->name . '[' . $index . '].' . $field . ' is not a field of ' . $collection->name . '.';
                continue;
            }
            $problem = $this->formatter->problem($definition, $value);
            if ($problem !== null) $errors[] = $collection->name . '[' . $index . ']: ' . $problem;
        }
        foreach ($collection->fields as $field => $definition) {
            if ($definition->required && !array_key_exists($field, $entry)) {
                $errors[] = $collection->name . '[' . $index . '].' . $field . ' is required.';
            }
        }
        return $errors;
    }

    /** A required amount may be zero: a free order still has a total. */
    private static function zeroMoney(Template\PlaceholderDefinition $definition, mixed $value): bool
    {
        return $definition->kind === Template\PlaceholderKind::Money && is_array($value) && ($value['minor'] ?? null) === 0;
    }

    /**
     * @param list<array<string,mixed>> $nodes
     * @param array<string,mixed> $data
     * @param array<string,mixed> $entry the current repeating entry's fields
     */
    private function nodes(array $nodes, PlaceholderSet $set, array $data, ?CollectionDefinition $within, array $entry): string
    {
        $out = '';
        foreach ($nodes as $node) {
            switch ($node['type']) {
                case 'text':
                    $out .= (string) $node['text'];
                    break;
                case 'value':
                    [$definition, $value] = $this->resolve((string) $node['path'], $set, $data, $within, $entry);
                    $out .= $this->formatter->format($definition, $value);
                    break;
                case 'each':
                    $collection = $set->collections[(string) $node['name']];
                    foreach ((array) ($data[$collection->name] ?? []) as $item) {
                        $out .= $this->nodes((array) $node['children'], $set, $data, $collection, (array) $item);
                    }
                    break;
                case 'if':
                    $path = (string) $node['path'];
                    $present = $within === null && isset($set->collections[$path])
                        ? ((array) ($data[$path] ?? [])) !== []
                        : $this->formatter->present(...$this->resolve($path, $set, $data, $within, $entry));
                    $out .= $this->nodes($present ? (array) $node['children'] : (array) $node['else'], $set, $data, $within, $entry);
                    break;
            }
        }
        return $out;
    }

    /**
     * @param array<string,mixed> $data
     * @param array<string,mixed> $entry
     * @return array{0:Template\PlaceholderDefinition,1:mixed}
     */
    private function resolve(string $path, PlaceholderSet $set, array $data, ?CollectionDefinition $within, array $entry): array
    {
        $definition = $set->find($path, $within) ?? throw new RuntimeException('Unregistered placeholder ' . $path . '.');
        if ($within !== null && str_starts_with($path, $within->alias . '.')) {
            return [$definition, $entry[substr($path, strlen($within->alias) + 1)] ?? null];
        }
        return [$definition, $data[$path] ?? null];
    }
}
