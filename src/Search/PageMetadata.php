final class PageMetadata
{
    /** The longest description a head carries, as a landing page's. */
    public const DESCRIPTION_LIMIT = 300;
    /** The site's own picture, the home page's hero (img/hero-learning.svg) drawn at 1200 by 630 by rsvg-convert. */
    public const SITE_PICTURE = '/img/hero-learning-1200x630.png';
    /** What it shows, in the picture's own words (its desc). */
    private const SITE_PICTURE_ALT = 'Layered books, connected nodes and a terminal window on a dark blue background.';
    /** The site's mark, 512 by 512: the Organization's logo. */
    public const LOGO = '/img/favicon-512x512.png';

    public function __construct(
        private readonly SiteOwner $owner,
        private readonly RuntimeSettings $settings,
        private readonly SearchSettings $search,
        private readonly SharePictures $pictures,
        private readonly SearchRepository $records,
        private readonly CourseRepository $courses,
    ) {
    }

    /**
     * A course's page: the head of the course as its page shows it.
     *
     * @param array<string,mixed> $course CourseService::publicCourse, with its active prices
     * @param array<string,mixed> $page CoursePageView::view
     * @param array<string,mixed> $rating CourseRatingSummary::toArray, approved reviews only
     * @param list<string> $blocks the blocks the page shows (CoursePageLayout::rows)
     * @return array<string,mixed> page_meta
     */
    public function course(array $course, array $page, array $rating, array $blocks): array
    {
        $base = self::base();
        $description = self::describe((string) ($course['summary'] ?? ''), (string) ($course['subtitle'] ?? ''), (string) $course['title']);
        if ($base === null) return ['description' => $description];
        $url = $base . '/courses/' . rawurlencode((string) $course['slug']);
        $picture = $this->picture('course', (string) $course['slug'], (string) ($course['cover_svg'] ?? ''));
        $node = StructuredData::course([
            'id' => $url . '#course', 'url' => $url, 'name' => (string) $course['title'], 'description' => $description,
            'code' => (string) ($course['code'] ?? ''), 'language' => self::language(), 'provider' => $this->provider($course, $base),
            'image' => $picture, 'level' => in_array('glance', $blocks, true) ? trim((string) ($course['level'] ?? '')) : '',
            // The head of the page states the study time whenever there is one.
            'workload_minutes' => (string) ($page['total'] ?? '') !== '' ? (int) ($page['minutes'] ?? 0) : 0,
            // Course access is always shown, with every active price (CoursePageLayout).
            'offers' => self::offers((array) ($course['price_variants'] ?? []), $url),
            'rating' => self::rating($rating),
        ]);
        return $this->shared($url, (string) $course['title'], $description, $picture, self::alt((string) ($course['cover_svg'] ?? ''), (string) $course['title'])) + ['structured_data' => [StructuredData::encode($node)]];
    }

    /**
     * A landing page: its own head, and the same Course as its course's page, holding only what its sections show.
     *
     * @param array<string,mixed> $view LandingPageViewBuilder::build
     * @return array<string,mixed> page_meta
     */
    public function landing(array $view): array
    {
        $meta = (array) $view['meta'];
        $base = self::base();
        // A preview is not the page: it is not indexed and carries nothing more.
        if ($base === null || (bool) ($view['preview'] ?? false)) return $meta;
        $course = $this->courses->findBySlug((string) $view['course']['slug'], true);
        if ($course === null) return $meta;
        $url = $base . (string) $view['path'];
        $courseUrl = $base . '/courses/' . rawurlencode((string) $course['slug']);
        $title = (string) ($meta['title'] ?? $course['title']);
        $description = (string) ($meta['description'] ?? '');
        $picture = $this->picture('course', (string) $course['slug'], (string) ($course['cover_svg'] ?? ''));
        $shown = ['rating' => false, 'minutes' => 0, 'offers' => false];
        if (is_array($view['hero'] ?? null) && (int) ($view['hero']['rating']['count'] ?? 0) > 0) $shown['rating'] = true;
        foreach ((array) ($view['sections'] ?? []) as $section) {
            $type = (string) ($section['type'] ?? '');
            if ($type === 'reviews' && (int) ($section['rating']['count'] ?? 0) > 0) $shown['rating'] = true;
            if ($type === 'contents' && (string) ($section['total'] ?? '') !== '') $shown['minutes'] = (int) ($section['minutes'] ?? 0);
            if ($type === 'pricing' || $type === 'cta') $shown['offers'] = true;
        }
        $rating = $shown['rating'] ? (array) (($view['hero']['rating'] ?? null) ?: []) : [];
        if ($shown['rating'] && $rating === []) {
            foreach ((array) $view['sections'] as $section) { if (($section['type'] ?? '') === 'reviews') $rating = (array) $section['rating']; }
        }
        $node = StructuredData::course([
            'id' => $courseUrl . '#course', 'url' => $courseUrl, 'name' => (string) $course['title'],
            'description' => self::describe((string) ($course['summary'] ?? ''), (string) ($course['subtitle'] ?? ''), (string) $course['title']),
            'code' => (string) ($course['code'] ?? ''), 'language' => self::language(), 'provider' => $this->provider($course, $base),
            'image' => $picture, 'level' => is_array($view['hero'] ?? null) ? trim((string) ($course['level'] ?? '')) : '',
            'workload_minutes' => $shown['minutes'],
            'offers' => $shown['offers'] ? self::offers($this->courses->priceVariants((int) $course['id'], true), $courseUrl) : [],
            'rating' => self::rating($rating),
        ]);
        // A hero picture of the page's own (from the Resource Library) is what it is shared with; else the course's cover.
        $own = (string) ($meta['og']['image'] ?? '');
        $shared = $this->shared($url, $title, $description, $own !== '' ? '' : $picture, self::alt((string) ($course['cover_svg'] ?? ''), (string) $course['title']));
        if ($own !== '') {
            $shared['og']['image'] = $own;
            $shared['twitter_card'] = 'summary_large_image';
        }
        return $shared + $meta + ['structured_data' => [StructuredData::encode($node)]];
    }

    /**
     * A bundle's page: a Product with its Offer while it is on sale.
     *
     * @param array<string,mixed> $bundle BundleService::detail
     * @return array<string,mixed> page_meta
     */
    public function bundle(array $bundle): array
    {
        $base = self::base();
        $description = self::describe((string) ($bundle['short_description'] ?? ''), (string) ($bundle['description_html'] ?? ''), (string) $bundle['title']);
        if ($base === null) return ['description' => $description];
        $url = $base . '/bundles/' . rawurlencode((string) $bundle['slug']);
        $cover = (string) ($this->records->bundleCover((string) $bundle['slug']) ?? '');
        $picture = $this->picture('bundle', (string) $bundle['slug'], $cover);
        // The page offers it to buy only while it is on sale with a price (BundleRules::unavailableReason).
        $onSale = ($bundle['price_label'] ?? null) !== null && ($bundle['unavailable'] ?? null) === null && ($bundle['offer_id'] ?? null) !== null;
        $courses = [];
        foreach ((array) ($bundle['courses'] ?? []) as $course) {
            $slug = (string) ($course['slug'] ?? '');
            if ($slug !== '' && ($course['status'] ?? 'published') === 'published') $courses[] = ['name' => (string) $course['title'], 'url' => $base . '/courses/' . rawurlencode($slug)];
        }
        $node = StructuredData::bundle([
            'id' => $url . '#bundle', 'url' => $url, 'name' => (string) $bundle['title'], 'description' => $description, 'image' => $picture,
            'brand' => $this->siteOrganisation($base),
            'offer' => $onSale ? [
                'price' => Money::strictMinorUnits((int) $bundle['price_minor_units'], (string) $bundle['currency_code'])->toMajorUnits(),
                'currency' => (string) $bundle['currency_code'], 'url' => $url,
                'valid_from' => self::date($bundle['available_from'] ?? null), 'valid_until' => self::date($bundle['available_until'] ?? null),
            ] : null,
        ]);
        $list = StructuredData::courseList($url, 'Courses in ' . (string) $bundle['title'], array_column($courses, 'url'));
        return $this->shared($url, (string) $bundle['title'], $description, $picture, self::alt($cover, (string) $bundle['title']))
            + ['structured_data' => array_map(StructuredData::encode(...), array_values(array_filter([$node, $list])))];
    }

    /**
     * The home page: the business behind the site and the site itself, the site's picture, and the codes that prove to Google
     * and Bing that the site is the owner's.
     *
     * @return array<string,mixed> page_meta
     */
    public function home(string $description): array
    {
        $base = self::base();
        $verification = $this->search->verificationTags();
        if ($base === null) return ['description' => $description, 'verification' => $verification];
        $name = $this->settings->platformName();
        $owner = $this->owner->details();
        $organisation = StructuredData::organisation([
            'id' => $base . '/#organization', 'name' => $owner['trading_name'] !== '' ? $owner['trading_name'] : $name, 'legal_name' => $owner['legal_name'],
            'url' => $base . '/', 'logo' => $base . self::LOGO, 'email' => $owner['email'], 'telephone' => $owner['phone'],
            'address' => $this->owner->addressLine(), 'country' => self::country($this->owner->addressLine()), 'contact_url' => $base . '/contact',
            // The footer's social marks that are the site's own profiles, never a platform's home page.
            'same_as' => SocialPlatform::profiles([]), 'description' => '',
        ]);
        $website = StructuredData::website($base . '/#website', $name, $base . '/', self::language(), $base . '/#organization');
        $fingerprint = is_file(self::sitePicturePath()) ? md5_file(self::sitePicturePath()) : false;
        return $this->shared($base . '/', $name, $description, $fingerprint === false ? '' : $base . self::SITE_PICTURE . '?v=' . substr($fingerprint, 0, 12), self::SITE_PICTURE_ALT)
            + ['verification' => $verification, 'structured_data' => [StructuredData::encode($organisation), StructuredData::encode($website)]];
    }

    /**
     * A catalogue page (All courses or a category): the courses it shows, as the summary page of Google's Course list. A
     * search's results are not marked up.
     *
     * @param list<array<string,mixed>> $courses the page's course cards, in its order
     * @return array<string,mixed> page_meta, or nothing to add
     */
    public function catalogue(string $path, string $name, array $courses, bool $searched): array
    {
        $base = self::base();
        if ($base === null || $searched) return [];
        $list = StructuredData::courseList($base . $path, $name, array_map(static fn(array $course): string => $base . '/courses/' . rawurlencode((string) $course['slug']), $courses));
        return $list === null ? [] : ['structured_data' => [StructuredData::encode($list)]];
    }

    /**
     * The FAQ: its questions and answers, as the page shows them.
     *
     * @param list<array{question:string,answer:string}> $answered Help\Faq::answered
     * @return array<string,mixed> page_meta
     */
    public function faq(array $answered, string $description): array
    {
        $base = self::base();
        if ($base === null || $answered === []) return ['description' => $description];
        return ['description' => $description, 'canonical' => $base . '/faq', 'structured_data' => [StructuredData::encode(StructuredData::faq($base . '/faq', $answered))]];
    }

    /** APP_URL without its trailing slash, or null. */
    public static function base(): ?string
    {
        return StructuredData::base(Env::string('APP_URL'));
    }

    /**
     * The address of a share picture, with its version, when it has been drawn; empty otherwise.
     */
    private function picture(string $kind, string $slug, string $cover): string
    {
        $base = self::base();
        if ($base === null || !$this->pictures->has($cover)) return '';
        return $base . '/share/' . $kind . '/' . rawurlencode($slug) . '.png?v=' . SharePictures::version($cover);
    }

    /**
     * The canonical address and the Open Graph set, with X's large card when there is a picture.
     *
     * @return array<string,mixed>
     */
    private function shared(string $url, string $title, string $description, string $picture, string $alt): array
    {
        $og = ['type' => 'website', 'title' => $title, 'description' => $description, 'url' => $url];
        if ($picture !== '') $og += ['image' => $picture, 'image:type' => 'image/png', 'image:width' => (string) SharePictures::WIDTH, 'image:height' => (string) SharePictures::HEIGHT, 'image:alt' => $alt];
        return ['description' => $description, 'canonical' => $url, 'og' => $og, 'twitter_card' => $picture !== '' ? 'summary_large_image' : 'summary'];
    }

    /**
     * Who provides a course: the company that owns it, else the Site Owner (a course no company owns is the Site Owner's).
     *
     * @param array<string,mixed> $course
     * @return array{name:string,url:string,id:string}
     */
    private function provider(array $course, string $base): array
    {
        $company = $this->records->providerCompany(isset($course['owner_company_id']) ? (int) $course['owner_company_id'] : null);
        return $company !== null ? ['name' => $company, 'url' => '', 'id' => ''] : $this->siteOrganisation($base);
    }

    /** @return array{name:string,url:string,id:string} */
    private function siteOrganisation(string $base): array
    {
        $name = $this->owner->value('trading_name');
        return ['name' => $name !== '' ? $name : $this->settings->platformName(), 'url' => $base . '/', 'id' => $base . '/#organization'];
    }

    /**
     * Each active price as an Offer: the price in the currency's major units, and the access it buys.
     *
     * @param list<array<string,mixed>> $variants
     * @return list<array{name:string,price:string,currency:string,url:string}>
     */
    private static function offers(array $variants, string $url): array
    {
        $offers = [];
        foreach ($variants as $variant) {
            if (array_key_exists('is_active', $variant) && !(bool) $variant['is_active']) continue;
            $currency = (string) ($variant['currency_code'] ?? Money::platformCurrency());
            $offers[] = [
                'name' => AccessPeriod::label((int) ($variant['access_period_seconds'] ?? 0)) . ' of access',
                'price' => Money::strictMinorUnits((int) ($variant['price_minor_units'] ?? 0), $currency)->toMajorUnits(),
                'currency' => $currency, 'url' => $url,
            ];
        }
        return $offers;
    }

    /**
     * The rating as the page shows it, or null without an approved review.
     *
     * @param array<string,mixed> $rating
     * @return array{value:string,count:int}|null
     */
    private static function rating(array $rating): ?array
    {
        $count = (int) ($rating['count'] ?? 0);
        $value = (string) ($rating['average_label'] ?? '');
        return $count >= 1 && $value !== '' ? ['value' => $value, 'count' => $count] : null;
    }

    /** The first of the given words that says something, as one plain line of at most DESCRIPTION_LIMIT characters. */
    private static function describe(string ...$candidates): string
    {
        foreach ($candidates as $candidate) {
            $text = LandingCopy::excerpt($candidate, self::DESCRIPTION_LIMIT);
            if ($text !== '') return $text;
        }
        return '';
    }

    /** The cover's own words for what it shows (its aria-label), else the title. */
    private static function alt(string $cover, string $title): string
    {
        if (preg_match('/^<svg\b[^>]*\baria-label="([^"]{3,300})"/i', trim($cover), $label) === 1) return html_entity_decode($label[1], ENT_QUOTES | ENT_HTML5, 'UTF-8');
        return $title;
    }

    /** A sale's moment as the day it falls on, in the site's time. */
    private static function date(mixed $moment): string
    {
        if ($moment === null || trim((string) $moment) === '') return '';
        try {
            return (new \DateTimeImmutable((string) $moment))->setTimezone(new \DateTimeZone(date_default_timezone_get()))->format('Y-m-d');
        } catch (\Exception) {
            return '';
        }
    }

    private static function language(): string
    {
        return StructuredData::language(Env::string('APP_LOCALE'));
    }

    /** ZA when the Site Owner's address ends with South Africa; otherwise the country is not claimed. */
    private static function country(string $address): string
    {
        return preg_match('/\bsouth\s+africa\.?\s*$/i', $address) === 1 ? 'ZA' : '';
    }

    private static function sitePicturePath(): string
    {
        return dirname(__DIR__, 2) . '/public_html' . self::SITE_PICTURE;
    }
}
