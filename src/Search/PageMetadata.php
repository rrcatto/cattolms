    /**
     * The address of a share picture, with its version, when it has been drawn; empty otherwise.
     */
    private function picture(string $kind, string $slug, string $cover): string
    {
        $base = self::base();
        if ($base === null || !$this->pictures->has($cover)) return '';
        return $base . '/share/' . $kind . '/' . rawurlencode($slug) . '.png?v=' . SharePictures::version($cover);
    }

    /**
     * The canonical address and the Open Graph set, with X's large card when there is a picture.
     *
     * @return array<string,mixed>
     */
    private function shared(string $url, string $title, string $description, string $picture, string $alt, string $type = 'image/png'): array
    {
        $og = ['type' => 'website', 'title' => $title, 'description' => $description, 'url' => $url, 'locale' => str_replace('-', '_', self::language())];
        if ($picture !== '') $og += ['image' => $picture, 'image:type' => $type, 'image:width' => (string) SharePictures::WIDTH, 'image:height' => (string) SharePictures::HEIGHT, 'image:alt' => $alt];
        return ['description' => $description, 'canonical' => $url, 'og' => $og, 'twitter_card' => $picture !== '' ? 'summary_large_image' : 'summary'];
    }

    /**
     * Who provides a course: the company that owns it, else the Site Owner (a course no company owns is the Site Owner's).
     *
     * @param array<string,mixed> $course
     * @return array{name:string,url:string,id:string}
     */
    private function provider(array $course, string $base): array
    {
        $company = $this->records->providerCompany(isset($course['owner_company_id']) ? (int) $course['owner_company_id'] : null);
        return $company !== null ? ['name' => $company, 'url' => '', 'id' => ''] : $this->siteOrganisation($base);
    }

    /** @return array{name:string,url:string,id:string} */
    private function siteOrganisation(string $base): array
    {
        $name = $this->owner->value('trading_name');
        return ['name' => $name !== '' ? $name : $this->settings->platformName(), 'url' => $base . '/', 'id' => $base . '/#organization'];
    }

    /**
     * Each active price as an Offer: the price in the currency's major units, and the access it buys.
     *
     * @param list<array<string,mixed>> $variants
     * @return list<array{name:string,price:string,currency:string,url:string}>
     */
    private static function offers(array $variants, string $url): array
    {
        $offers = [];
        foreach ($variants as $variant) {
            if (array_key_exists('is_active', $variant) && !(bool) $variant['is_active']) continue;
            $currency = (string) ($variant['currency_code'] ?? Money::platformCurrency());
            $offers[] = [
                'name' => AccessPeriod::label((int) ($variant['access_period_seconds'] ?? 0)) . ' of access',
                'price' => Money::strictMinorUnits((int) ($variant['price_minor_units'] ?? 0), $currency)->toMajorUnits(),
                'currency' => $currency, 'url' => $url,
            ];
        }
        return $offers;
    }

    /**
     * The rating as the page shows it, or null without an approved review.
     *
     * @param array<string,mixed> $rating
     * @return array{value:string,count:int}|null
     */
    private static function rating(array $rating): ?array
    {
        $count = (int) ($rating['count'] ?? 0);
        $value = (string) ($rating['average_label'] ?? '');
        return $count >= 1 && $value !== '' ? ['value' => $value, 'count' => $count] : null;
    }

    /** The first of the given words that says something, as one plain line of at most DESCRIPTION_LIMIT characters. */
    private static function describe(string ...$candidates): string
    {
        foreach ($candidates as $candidate) {
            $text = LandingCopy::excerpt($candidate, self::DESCRIPTION_LIMIT);
            if ($text !== '') return $text;
        }
        return '';
    }

    /**
     * A list described by what it holds: "Property courses: Start an Airbnb in South Africa, Run a Guest House and 4 more."
     *
     * @param list<array<string,mixed>> $courses
     */
    private static function holding(string $name, array $courses): string
    {
        $titles = array_values(array_filter(array_map(static fn(array $course): string => trim((string) ($course['title'] ?? '')), $courses)));
        if ($titles === []) return '';
        $shown = array_slice($titles, 0, 3);
        $more = count($titles) - count($shown);
        $words = count($shown) === 1 ? $shown[0] : implode(', ', array_slice($shown, 0, -1)) . ($more > 0 ? ', ' : ' and ') . $shown[count($shown) - 1];
        return LandingCopy::excerpt($name . ': ' . $words . ($more > 0 ? ' and ' . $more . ' more.' : '.'), self::DESCRIPTION_LIMIT);
    }

    /** The cover's own words for what it shows (its aria-label), else the title. */
    private static function alt(string $cover, string $title): string
    {
        if (preg_match('/^<svg\b[^>]*\baria-label="([^"]{3,300})"/i', trim($cover), $label) === 1) return html_entity_decode($label[1], ENT_QUOTES | ENT_HTML5, 'UTF-8');
        return $title;
    }

    /** A sale's moment as the day it falls on, in the site's time. */
    private static function date(mixed $moment): string
    {
        if ($moment === null || trim((string) $moment) === '') return '';
        try {
            return (new \DateTimeImmutable((string) $moment))->setTimezone(new \DateTimeZone(date_default_timezone_get()))->format('Y-m-d');
        } catch (\Exception) {
            return '';
        }
    }

    private static function language(): string
    {
        return StructuredData::language(Env::string('APP_LOCALE'));
    }

    /** ZA when the Site Owner's address ends with South Africa; otherwise the country is not claimed. */
    private static function country(string $address): string
    {
        return preg_match('/\bsouth\s+africa\.?\s*$/i', $address) === 1 ? 'ZA' : '';
    }

    /**
     * The site's picture (Settings > Site Owner; the owner's hero, 2026-11-09) as shared: its 1200 by 630 copy, or '' when
     * none is uploaded, and then a page without a picture of its own is shared without one.
     */
    private function sitePictureUrl(string $base): string
    {
        return $this->sitePicture?->shareUrl($base) ?? '';
    }

    /** The site's picture in words, for those who cannot see it: the business's name. */
    private function sitePictureAlt(): string
    {
        $name = $this->owner->value('trading_name');
        return $name !== '' ? $name : $this->settings->platformName();
    }
