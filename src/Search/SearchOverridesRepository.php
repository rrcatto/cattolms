declare(strict_types=1);

namespace CattoLearning\Search;

use CattoLearning\Infrastructure\Persistence\Database;

final class SearchOverridesRepository
{
    public function __construct(private readonly Database $db) {}

    /** @return array{title:string,description:string,hidden:bool}|null */
    public function course(int $courseId): ?array
    {
        $row = $this->db->fetchAssociative('SELECT search_title, search_description, search_hidden FROM courses WHERE id = :id', ['id' => $courseId]);
        if ($row === false) return null;
        return ['title' => (string) $row['search_title'], 'description' => (string) $row['search_description'], 'hidden' => in_array($row['search_hidden'], [true, 't', 1, '1'], true)];
    }

    public function saveCourse(int $courseId, string $title, string $description, bool $hidden): void
    {
        $this->db->executeStatement(
            'UPDATE courses SET search_title = :title, search_description = :description, search_hidden = :hidden, updated_at = NOW() WHERE id = :id',
            ['title' => $title, 'description' => $description, 'hidden' => $hidden ? 't' : 'f', 'id' => $courseId]
        );
    }

    /** @return array{title:string,description:string}|null */
    public function category(int $categoryId): ?array
    {
        $row = $this->db->fetchAssociative('SELECT search_title, search_description FROM course_categories WHERE id = :id', ['id' => $categoryId]);
        return $row === false ? null : ['title' => (string) $row['search_title'], 'description' => (string) $row['search_description']];
    }

    public function saveCategory(int $categoryId, string $title, string $description): void
    {
        $this->db->executeStatement('UPDATE course_categories SET search_title = :title, search_description = :description, updated_at = NOW() WHERE id = :id',
            ['title' => $title, 'description' => $description, 'id' => $categoryId]);
    }
}
