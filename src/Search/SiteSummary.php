declare(strict_types=1);

namespace CattoLearning\Search;

use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Configuration\SiteOwner;
use CattoLearning\Legal\LegalDocuments;
use CattoLearning\Support\Money;
use CattoPHP\Search\LlmsTxtContent;

final class SiteSummary implements LlmsTxtContent
{
    /** What the site is, in the home page's own words. */
    public const SITE_WORDS = 'Structured modules, meaningful assessments and a course library that remembers your progress.';

    public function __construct(
        private readonly SiteOwner $owner,
        private readonly RuntimeSettings $settings,
        private readonly SearchRepository $records,
        private readonly LegalDocuments $legal,
    ) {
    }

    public function name(): string
    {
        return $this->settings->platformName();
    }

    /** The site, and the Site Owner when the business is not called what the site is. */
    public function summary(): string
    {
        $name = $this->name();
        $trading = $this->owner->value('trading_name');
        $by = $trading === '' || $trading === $name ? '' : ' of ' . $trading;
        return $name . ' is the online course site' . $by . '. Self-study courses, taken online at your own pace. ' . self::SITE_WORDS;
    }

    public function notes(): array
    {
        return ['Courses are in English and priced in ' . Money::platformCurrency() . '. A course starts as soon as it is paid for and stays open for the access period bought. Results come from the module assessments and the final assessment, half each. Each course page lists its modules, study time, level and prices.'];
    }

    public function sections(string $base): array
    {
        $courses = [];
        foreach ($this->records->publishedCourses() as $course) {
            $courses[] = ['name' => $course['title'], 'url' => $base . '/courses/' . rawurlencode($course['slug']), 'notes' => $course['summary'] !== '' ? $course['summary'] : $course['subtitle']];
        }
        $bundles = [];
        foreach ($this->records->publishedBundles() as $bundle) {
            $bundles[] = ['name' => $bundle['title'], 'url' => $base . '/bundles/' . rawurlencode($bundle['slug']), 'notes' => $bundle['short_description']];
        }
        $legal = [];
        foreach ($this->legal->all() as $document) {
            $legal[] = ['name' => (string) $document['title'], 'url' => $base . (string) $document['path'], 'notes' => (string) $document['intro']];
        }
        return [
            ['title' => 'Courses', 'entries' => $courses],
            ['title' => 'Course bundles', 'entries' => $bundles],
            ['title' => 'Help', 'entries' => [
                ['name' => 'Course catalogue', 'url' => $base . '/courses', 'notes' => 'Every published course, by category.'],
                ['name' => 'Help', 'url' => $base . '/help', 'notes' => 'How to find, buy and use courses.'],
                ['name' => 'Frequently asked questions', 'url' => $base . '/faq', 'notes' => 'Buying, paying, access, grading, certificates and refunds.'],
                ['name' => 'Contact', 'url' => $base . '/contact', 'notes' => 'Questions before buying, about an account, an order or a course.'],
            ]],
            ['title' => 'Legal', 'entries' => $legal],
        ];
    }
}
