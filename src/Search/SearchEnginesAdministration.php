declare(strict_types=1);

namespace CattoLearning\Search;

use CattoLearning\Configuration\SiteMode;
use CattoLearning\Infrastructure\Persistence\AuditRepository;

final class SearchEnginesAdministration
{
    public function __construct(
        private readonly SearchSettings $settings,
        private readonly SharePictures $pictures,
        private readonly SearchRepository $records,
        private readonly AuditRepository $audit,
        private readonly SiteMode $site,
        private readonly LlmsTxt $llms,
    ) {
    }

    /** @return array<string,mixed> what Settings shows */
    public function view(): array
    {
        $saved = $this->settings->saved();
        $published = $this->records->publishedCovers();
        $made = 0;
        $without = 0;
        foreach ($published as $item) {
            if (!SharePictures::usable($item['cover'])) { $without++; continue; }
            if ($this->pictures->has($item['cover'])) $made++;
        }
        $drawable = count($published) - $without;
        $base = PageMetadata::base();
        $counts = AiCrawlers::counts();
        return $saved + [
            'summary' => match ($saved['ai_crawlers']) {
                SearchSettings::BLOCK_ALL => 'No AI crawler may come in.',
                SearchSettings::SEARCH_ONLY => 'AI search and answer assistants may come in; training crawlers may not.',
                default => 'Every AI crawler may come in.',
            } . ' ' . ($made === $drawable ? 'Every share picture is made.' : ($drawable - $made) . ' share ' . ($drawable - $made === 1 ? 'picture is' : 'pictures are') . ' missing.'),
            'crawler_counts' => $counts,
            'crawler_total' => array_sum($counts),
            'crawlers_checked' => date('j F Y', (int) strtotime(AiCrawlers::CHECKED)),
            'pictures' => ['tool' => $this->pictures->available(), 'made' => $made, 'drawable' => $drawable, 'missing' => $drawable - $made, 'without_cover' => $without, 'published' => count($published)],
            'demo' => $this->site->isDemo(),
            'addresses' => [
                'robots' => $base === null ? '/robots.txt' : $base . '/robots.txt',
                'llms' => $this->llms->available() ? $base . '/llms.txt' : '',
                'sitemap' => !$this->site->isDemo() && $base !== null ? $base . '/sitemap.xml' : '',
                'site' => $base === null ? '' : $base . '/',
            ],
        ];
    }

    /** @param array<string,mixed> $input ai_crawlers, google, bing */
    public function save(array $input, int $actorUserId): void
    {
        $change = $this->settings->save($input, $actorUserId);
        if ($change['old'] !== $change['new']) $this->audit->record($actorUserId, 'platform.search_engines_changed', $change);
    }

    /**
     * Draws every share picture not yet drawn, for every course and bundle that has a cover.
     *
     * @return array{made:int,failed:int,tool:bool}
     */
    public function makeMissing(int $actorUserId): array
    {
        if (!$this->pictures->available()) return ['made' => 0, 'failed' => 0, 'tool' => false];
        $made = 0;
        $failed = 0;
        foreach ($this->records->covers() as $cover) {
            if ($this->pictures->has($cover)) continue;
            $this->pictures->make($cover) ? $made++ : $failed++;
        }
        $this->audit->record($actorUserId, 'platform.share_pictures_made', ['made' => $made, 'failed' => $failed]);
        return ['made' => $made, 'failed' => $failed, 'tool' => true];
    }
}
