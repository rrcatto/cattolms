declare(strict_types=1);

namespace CattoLearning\Search;

use CattoLearning\Infrastructure\Persistence\Database;

final class SearchRepository
{
    /** The catalogue's order (CourseRepository): numbered courses first, lowest first, then the rest newest first. */
    private const CATALOGUE_ORDER = 'c.catalogue_position ASC NULLS LAST, c.published_at DESC NULLS LAST, c.title, c.id';

    /** A bundle's cover: its own, else the cover of its first course. */
    private const BUNDLE_COVER = "COALESCE(NULLIF(trim(b.cover_svg), ''),
        (SELECT c.cover_svg FROM bundle_courses bc JOIN courses c ON c.id = bc.course_id
          WHERE bc.bundle_id = b.id AND trim(COALESCE(c.cover_svg, '')) <> '' ORDER BY bc.position, bc.course_id LIMIT 1), '')";

    public function __construct(private readonly Database $db)
    {
    }

    /**
     * The published courses, in the catalogue's order.
     *
     * @return list<array{slug:string,title:string,subtitle:string,summary:string}>
     */
    public function publishedCourses(): array
    {
        return array_map(static fn(array $row): array => ['slug' => (string) $row['slug'], 'title' => (string) $row['title'], 'subtitle' => (string) ($row['subtitle'] ?? ''), 'summary' => (string) ($row['summary'] ?? '')],
            $this->db->fetchAllAssociative("SELECT c.slug, c.title, c.subtitle, c.summary FROM courses c WHERE c.status = 'published' ORDER BY " . self::CATALOGUE_ORDER));
    }

    /**
     * The published bundles, newest first, as the bundles page lists them.
     *
     * @return list<array{slug:string,title:string,short_description:string}>
     */
    public function publishedBundles(): array
    {
        return array_map(static fn(array $row): array => ['slug' => (string) $row['slug'], 'title' => (string) $row['title'], 'short_description' => (string) ($row['short_description'] ?? '')],
            $this->db->fetchAllAssociative("SELECT b.slug, b.title, b.short_description FROM bundles b WHERE b.status = 'published' ORDER BY " . \CattoLearning\Bundle\BundleRepository::LISTED_ORDER));
    }

    /** The name of the company that provides a course, or null for a course the Site Owner provides. */
    public function providerCompany(?int $companyId): ?string
    {
        if ($companyId === null || $companyId < 1) return null;
        $name = $this->db->fetchOne('SELECT name FROM companies WHERE id = :id', ['id' => $companyId]);
        return is_string($name) && trim($name) !== '' ? trim($name) : null;
    }

    /** A published course's cover, by its address; null for a course that is not published. */
    public function courseCover(string $slug): ?string
    {
        $cover = $this->db->fetchOne("SELECT COALESCE(cover_svg, '') FROM courses WHERE slug = :slug AND status = 'published'", ['slug' => $slug]);
        return is_string($cover) ? $cover : null;
    }

    /** A published bundle's cover, its own or its first course's, by its address; null for a bundle that is not published. */
    public function bundleCover(string $slug): ?string
    {
        $cover = $this->db->fetchOne('SELECT ' . self::BUNDLE_COVER . " FROM bundles b WHERE b.slug = :slug AND b.status = 'published'", ['slug' => $slug]);
        return is_string($cover) ? $cover : null;
    }

    /**
     * Every cover a share picture is drawn from: each course's and each bundle's (its own, else its first course's), drafts
     * too, so a course has its picture before it is published. Each cover once.
     *
     * @return list<string>
     */
    public function covers(): array
    {
        $rows = $this->db->fetchFirstColumn(
            "SELECT DISTINCT cover FROM (
                SELECT COALESCE(c.cover_svg, '') AS cover FROM courses c WHERE c.status NOT IN ('retired', 'archived')
                UNION ALL
                SELECT " . self::BUNDLE_COVER . " AS cover FROM bundles b WHERE b.status <> 'retired'
             ) covers WHERE trim(cover) <> ''"
        );
        return array_map('strval', $rows);
    }

    /**
     * The covers of the published courses and bundles, each with what it belongs to, for Settings' count of what has a
     * share picture.
     *
     * @return list<array{kind:string,title:string,cover:string}>
     */
    public function publishedCovers(): array
    {
        return array_map(static fn(array $row): array => ['kind' => (string) $row['kind'], 'title' => (string) $row['title'], 'cover' => (string) $row['cover']],
            $this->db->fetchAllAssociative(
                "SELECT 'course' AS kind, c.title, COALESCE(c.cover_svg, '') AS cover FROM courses c WHERE c.status = 'published'
                 UNION ALL
                 SELECT 'bundle' AS kind, b.title, " . self::BUNDLE_COVER . " AS cover FROM bundles b WHERE b.status = 'published'"
            ));
    }
}
