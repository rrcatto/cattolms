    public const PUBLIC_PAGES = ['home', 'courses', 'course-tags', 'course-detail', 'landing-page', 'bundles', 'bundle-detail', 'help', 'faq', 'contact', 'terms', 'refunds', 'privacy', 'about', 'site-presentation'];

