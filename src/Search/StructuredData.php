                'priceCurrency' => $offer['currency'],
                'availability' => 'https://schema.org/InStock',
                'url' => $offer['url'],
            ], $course['offers']);
        }
        if ($course['rating'] !== null && $course['rating']['count'] >= 1) $node['aggregateRating'] = self::rating($course['rating']);
        return $node;
    }

    /**
     * A bundle: a Product with one Offer. Its page lists its courses as well, which itemList() marks up.
     *
     * Why a Product (decided 2026-11-06, from Google's documentation of that day): a bundle is one priced thing bought in
     * one order line, which is what a Product with an Offer says, and Google's product snippets read a Product's name and
     * Offer ("Product rich results only support pages that focus on a single product", which a bundle's page is). Google
     * retired the Course info rich result in 2025, and with it the only course markup that could price several courses
     * together (a Course with hasPart); schema.org's Course is still one course. The courses it holds are an ItemList of
     * their pages, the summary-page form of Google's one remaining course feature, Course list, so each course is named
     * by its own page and its own Course markup there. Google's merchant listings are for goods: Merchant Center's
     * policies leave out online classes, so a bundle may show as a product snippet at most; other search engines and AI
     * assistants read the Product as it is.
     *
     * @param array{id:string,url:string,name:string,description:string,image:string,brand:array{name:string,url:string,id:string},offer:?array{price:string,currency:string,url:string,valid_from:string,valid_until:string}} $bundle
     * @return array<string,mixed>
     */
    public static function bundle(array $bundle): array
    {
        $node = [
            '@context' => self::CONTEXT,
            '@type' => 'Product',
            '@id' => $bundle['id'],
            'name' => $bundle['name'],
            'description' => $bundle['description'],
            'url' => $bundle['url'],
        ];
        if ($bundle['image'] !== '') $node['image'] = $bundle['image'];
        $node['brand'] = self::organisationReference($bundle['brand']);
        if ($bundle['offer'] !== null) {
            $offer = [
                '@type' => 'Offer',
                'price' => $bundle['offer']['price'],
                'priceCurrency' => $bundle['offer']['currency'],
                'availability' => 'https://schema.org/InStock',
                'url' => $bundle['offer']['url'],
            ];
            if ($bundle['offer']['valid_from'] !== '') $offer['validFrom'] = $bundle['offer']['valid_from'];
            if ($bundle['offer']['valid_until'] !== '') $offer['priceValidUntil'] = $bundle['offer']['valid_until'];
            $node['offers'] = $offer;
        }
        return $node;
    }

    /**
     * A list of courses a page shows, each by its own page's address, in the page's order: the summary page of Google's
     * Course list (each course's page carries its Course). Google shows that carousel for three courses or more, so a
     * shorter list is not marked up; null then.
     *
     * @param list<string> $urls each course's page, absolute
     * @return array<string,mixed>|null
     */
    public static function courseList(string $url, string $name, array $urls): ?array
    {
        if (count($urls) < 3) return null;
        $items = [];
        foreach ($urls as $index => $item) $items[] = ['@type' => 'ListItem', 'position' => $index + 1, 'url' => $item];
        return ['@context' => self::CONTEXT, '@type' => 'ItemList', 'name' => $name, 'url' => $url, 'itemListElement' => $items];
    }

    /**
