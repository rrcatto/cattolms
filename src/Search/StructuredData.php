    /** APP_URL without its trailing slash, when it is a web address; null otherwise, and then nothing is marked up. */
    public static function base(string $appUrl): ?string
    {
        $base = rtrim(trim($appUrl), '/');
        return preg_match('#^https?://[^/\s]+#i', $base) === 1 ? $base : null;
    }

    /**
     * A course: the course page's, and a landing page's for the same course.
     *
     * Google (checked 2026-11-06) retired its Course info rich result in 2025 and now reads only a course's name,
     * description and provider, for Course list; the rest is schema.org's Course as other search engines and AI assistants
     * read it, and as the owner's brief asks: the code, the level, the language, the study time as courseWorkload in ISO
     * 8601 (as Course info asked) and each price as an Offer. A rating is marked up only as the page shows it (Google's
     * review snippets still take Course).
     *
     * @param array{id:string,url:string,name:string,description:string,code:string,language:string,provider:array{name:string,url:string,id:string},image:string,level:string,workload_minutes:int,offers:list<array{name:string,price:string,currency:string,url:string}>,rating:?array{value:string,count:int}} $course
     * @return array<string,mixed>
     */
    public static function course(array $course): array
    {
        $node = [
            '@context' => self::CONTEXT,
            '@type' => 'Course',
            '@id' => $course['id'],
            'name' => $course['name'],
            'description' => $course['description'],
            'url' => $course['url'],
        ];
        if ($course['code'] !== '') $node['courseCode'] = $course['code'];
