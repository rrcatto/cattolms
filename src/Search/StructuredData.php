        $node['provider'] = self::organisationReference($course['provider']);
        // Self-study, online, at the learner's own pace: the study time is the workload, the whole course's.
        $instance = ['@type' => 'CourseInstance', 'courseMode' => 'Online'];
        $workload = self::duration($course['workload_minutes']);
        if ($workload !== null) $instance['courseWorkload'] = $workload;
        $node['hasCourseInstance'] = [$instance];
        if ($course['offers'] !== []) {
