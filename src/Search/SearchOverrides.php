declare(strict_types=1);

namespace CattoLearning\Search;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\OptionRepository;
use InvalidArgumentException;

final class SearchOverrides
{
    public const TITLE_LIMIT = 120;
    public const DESCRIPTION_LIMIT = 320;
    /** About as much as a search result shows (Google cuts by width, not by count). */
    public const TITLE_SHOWN = 60;
    public const DESCRIPTION_SHOWN = 160;
    public const PAGES_OPTION = 'search_pages';

    public function __construct(
        private readonly SearchOverridesRepository $records,
        private readonly OptionRepository $options,
        private readonly AuditRepository $audit,
    ) {}

    /** @return array<string,array{title:string,description:string}> every public page's own words, empty where it has none */
    public function pages(): array
    {
        $decoded = json_decode($this->options->get(self::PAGES_OPTION, '{}'), true);
        $saved = is_array($decoded) ? $decoded : [];
        $pages = [];
        foreach (array_keys(PublicPages::PAGES) as $key) {
            $own = is_array($saved[$key] ?? null) ? $saved[$key] : [];
            $pages[$key] = ['title' => self::plain((string) ($own['title'] ?? '')), 'description' => self::plain((string) ($own['description'] ?? ''))];
        }
        return $pages;
    }

    /** @return array{title:string,description:string} */
    public function page(string $key): array
    {
        return $this->pages()[$key] ?? ['title' => '', 'description' => ''];
    }

    /**
     * Saves every public page's own words from the form (pages[key][title], pages[key][description]).
     *
     * @param array<string,mixed> $input
     * @return list<string> the names of the pages that changed
     */
    public function savePages(array $input, int $actorId): array
    {
        $before = $this->pages();
        $after = [];
        $changed = [];
        foreach (array_keys(PublicPages::PAGES) as $key) {
            $typed = is_array($input['pages'][$key] ?? null) ? $input['pages'][$key] : [];
            $after[$key] = self::checked($typed, PublicPages::label($key));
            if ($after[$key] !== $before[$key]) $changed[] = PublicPages::label($key);
        }
        if ($changed === []) return [];
        $kept = array_filter($after, static fn(array $own): bool => $own['title'] !== '' || $own['description'] !== '');
        if ($kept === []) $this->options->delete(self::PAGES_OPTION);
        else $this->options->set(self::PAGES_OPTION, (string) json_encode($kept, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES), $actorId);
        $this->audit->record($actorId, 'search.pages_updated', ['pages' => $changed]);
        return $changed;
    }

    /** @return array{title:string,description:string,hidden:bool} */
    public function course(int $courseId): array
    {
        return $this->records->course($courseId) ?? throw new InvalidArgumentException('The course does not exist.');
    }

    /** @param array<string,mixed> $input title, description, hidden */
    public function saveCourse(int $courseId, array $input, int $actorId): void
    {
        $before = $this->course($courseId);
        $checked = self::checked($input, 'The course');
        $after = ['title' => $checked['title'], 'description' => $checked['description'], 'hidden' => in_array($input['hidden'] ?? null, ['1', 'on', 'yes', true, 1], true)];
        if ($after === $before) return;
        $this->records->saveCourse($courseId, $after['title'], $after['description'], $after['hidden']);
        $this->audit->record($actorId, 'search.course_updated', ['course_id' => $courseId, 'from' => $before, 'to' => $after]);
    }

    /** @return array{title:string,description:string} */
    public function category(int $categoryId): array
    {
        return $this->records->category($categoryId) ?? throw new InvalidArgumentException('The category does not exist.');
    }

    /** @param array<string,mixed> $input title, description */
    public function saveCategory(int $categoryId, array $input, int $actorId): void
    {
        $before = $this->category($categoryId);
        $after = self::checked($input, 'The category');
        if ($after === $before) return;
        $this->records->saveCategory($categoryId, $after['title'], $after['description']);
        $this->audit->record($actorId, 'search.category_updated', ['category_id' => $categoryId, 'from' => $before, 'to' => $after]);
    }

    /**
     * What partials/admin/search-fields.html.twig draws: the fields' names and values, the previews and the limits.
     *
     * @param array{title:string,description:string} $own
     * @param array<string,string> $preview PageMetadata's coursePreview, categoryPreview or pagePreview
     * @return array<string,mixed>
     */
    public static function fields(string $id, string $titleName, string $descriptionName, array $own, array $preview, string $site, ?bool $hidden = null, string $hiddenName = 'hidden'): array
    {
        return ['id' => $id, 'title_name' => $titleName, 'description_name' => $descriptionName, 'title' => $own['title'], 'description' => $own['description'],
            'preview' => $preview, 'site' => $site, 'title_limit' => self::TITLE_LIMIT, 'description_limit' => self::DESCRIPTION_LIMIT,
            'title_shown' => self::TITLE_SHOWN, 'description_shown' => self::DESCRIPTION_SHOWN, 'hidden' => $hidden, 'hidden_name' => $hiddenName];
    }

    /** One line of plain text: tags removed, spaces run together. */
    public static function plain(string $text): string
    {
        return trim((string) preg_replace('/\s+/u', ' ', html_entity_decode(strip_tags($text), ENT_QUOTES | ENT_HTML5, 'UTF-8')));
    }

    /**
     * @param array<string,mixed> $input
     * @return array{title:string,description:string}
     * @throws InvalidArgumentException in plain words when one is too long
     */
    private static function checked(array $input, string $what): array
    {
        $title = self::plain((string) ($input['title'] ?? ''));
        $description = self::plain((string) ($input['description'] ?? ''));
        if (mb_strlen($title) > self::TITLE_LIMIT) throw new InvalidArgumentException($what . '\'s search title can be at most ' . self::TITLE_LIMIT . ' characters. Search results show about ' . self::TITLE_SHOWN . '.');
        if (mb_strlen($description) > self::DESCRIPTION_LIMIT) throw new InvalidArgumentException($what . '\'s search description can be at most ' . self::DESCRIPTION_LIMIT . ' characters. Search results show about ' . self::DESCRIPTION_SHOWN . '.');
        return ['title' => $title, 'description' => $description];
    }
}
