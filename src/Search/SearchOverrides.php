engines are asked to leave it out (search_hidden: a robots noindex, and out of the sitemap); a title and a description
for a category (course_categories.search_title, search_description); and a title and a description for each of the
public pages PublicPages lists (the option search_pages). Empty means the ones the site makes from the page.

Plain text only, one line, as a search result shows it: tags are removed and spaces run together. A title may be up to
TITLE_LIMIT characters and a description DESCRIPTION_LIMIT; a search result shows about TITLE_SHOWN and
DESCRIPTION_SHOWN, which the previews on each form mark, never refuse. Every change is in the Activity log.

