Date time: 2026/11/06 SAST

Version: 1.1.0

Description:
Share pictures (owner, 2026-11-06, "2A"): the picture Facebook, LinkedIn, X, WhatsApp and Google show when a course, a
bundle or a landing page is shared or listed. A course's cover is SVG, which none of them accepts, so each cover gets a
PNG copy at 1200 by 630, the size Open Graph and X's large card ask for.

How it is drawn: rsvg-convert, from librsvg (LGPL-2.1-or-later), run as its own process. The PHP image has GD and
nothing that draws SVG, and no PHP package draws these covers faithfully: they are gradients, paths, opacity and
clipping, which meyfa/php-svg, the one pure-PHP renderer, does not draw. rsvg-convert is one Debian package
(librsvg2-bin) in the development image and the Podman kit's image (deploy/podman/Containerfile), so every site the kit
builds has it; a server installed another way installs it with its package manager. Without it nothing is drawn, the
pages carry no og:image and Settings > Search engines and AI says what to install.

The cover's own canvas (course specification 6.1: 640 by 360, preserveAspectRatio "xMidYMid slice") is drawn into
1200 by 630 by giving the root svg that size and the same slice, so the picture is cropped a little top and bottom
exactly as a card crops it, never stretched. It is read from standard input, so it can load no file, and it may take
no longer than TIMEOUT seconds.

Made at save, never on a request (the owner's brief): when a cover is uploaded or a course is imported
(CourseService, CourseCatalogueSettings, a new course), when a bundle is saved, and for every missing one from Settings >
Search engines and AI. Each picture is a stored file named by the SHA-256 of the cover and the drawing's version
(storage/share-pictures/<hash>.png), so the same cover is drawn once, a changed cover is a new file and a new ?v=
version of its address, and a request only asks whether the file is there.

Changelog:
2026/11/06 SAST
- Created.
*/

declare(strict_types=1);

namespace CattoLearning\Search;

use DOMDocument;
use DOMElement;
use RuntimeException;

final class SharePictures
{
    public const WIDTH = 1200;
    public const HEIGHT = 630;
    /** Raised when the drawing changes, so every picture is drawn again. */
    private const DRAWING = 'share-1200x630-v1';
    private const TIMEOUT = 20;
    private const FOLDER = 'share-pictures';
    /** The largest cover drawn: a cover is a few kilobytes, and the course form takes nothing larger. */
    private const MOST_BYTES = 2000000;

    public function __construct(private readonly string $storageRoot, private readonly ?string $tool = null)
    {
    }

    /** The full path of rsvg-convert, or null when this server has none. */
    public function tool(): ?string
    {
        if ($this->tool !== null) return is_file($this->tool) && is_executable($this->tool) ? $this->tool : null;
        foreach (['/usr/bin/rsvg-convert', '/usr/local/bin/rsvg-convert', '/opt/homebrew/bin/rsvg-convert'] as $candidate) {
            if (is_file($candidate) && is_executable($candidate)) return $candidate;
        }
        return null;
    }

    public function available(): bool
    {
        return $this->tool() !== null;
    }

    /** The picture's version: the start of its file name, for the ?v= of its address. Null for no usable cover. */
    public static function version(string $svg): ?string
    {
        return self::usable($svg) ? substr(self::hash($svg), 0, 16) : null;
    }

    /** Whether the PNG of this cover has been drawn. */
    public function has(string $svg): bool
    {
        return self::usable($svg) && is_file($this->path($svg));
    }

    /** The stored PNG's bytes, or null when it has not been drawn. */
    public function bytes(string $svg): ?string
    {
        if (!$this->has($svg)) return null;
        $bytes = file_get_contents($this->path($svg));
        return $bytes === false || $bytes === '' ? null : $bytes;
    }

    /**
     * Draws the cover's PNG unless it is there already. Returns whether it is there now; false when there is no tool, the
     * cover is not SVG, or drawing failed (never thrown: saving a course never fails because of its share picture).
     */
    public function make(string $svg): bool
    {
        if (!self::usable($svg)) return false;
        if ($this->has($svg)) return true;
        $tool = $this->tool();
        if ($tool === null) return false;
        try {
            $png = $this->draw($tool, self::sized($svg));
        } catch (RuntimeException) {
            return false;
        }
        $folder = rtrim($this->storageRoot, '/') . '/' . self::FOLDER;
        if (!is_dir($folder) && !@mkdir($folder, 0775, true) && !is_dir($folder)) return false;
        $target = $this->path($svg);
        $partial = $target . '.' . bin2hex(random_bytes(4)) . '.part';
        if (@file_put_contents($partial, $png) !== strlen($png)) { @unlink($partial); return false; }
        return @rename($partial, $target);
    }

    /** Whether a cover is SVG markup this can draw. */
    public static function usable(string $svg): bool
    {
        $svg = trim($svg);
        return $svg !== '' && strlen($svg) <= self::MOST_BYTES && preg_match('/^<svg\b/i', $svg) === 1;
    }

    private function path(string $svg): string
    {
        return rtrim($this->storageRoot, '/') . '/' . self::FOLDER . '/' . self::hash($svg) . '.png';
    }

    private static function hash(string $svg): string
    {
        return hash('sha256', self::DRAWING . "\n" . trim($svg));
    }

    /**
     * The cover with its root at 1200 by 630 and its canvas sliced into it, as a card shows it. A cover without a viewBox
     * gets one from its own width and height, or the specification's 640 by 360.
     */
    public static function sized(string $svg): string
    {
        $document = new DOMDocument();
        $previous = libxml_use_internal_errors(true);
        // No network and no entity expansion: a cover can load nothing.
        $loaded = $document->loadXML(trim($svg), LIBXML_NONET);
        libxml_clear_errors();
        libxml_use_internal_errors($previous);
        $root = $loaded ? $document->documentElement : null;
        if (!$root instanceof DOMElement || strtolower($root->localName) !== 'svg') throw new RuntimeException('The cover is not SVG.');
        if (!$root->hasAttribute('viewBox')) {
            $width = (float) preg_replace('/[^0-9.]/', '', $root->getAttribute('width'));
            $height = (float) preg_replace('/[^0-9.]/', '', $root->getAttribute('height'));
            $root->setAttribute('viewBox', $width > 0 && $height > 0 ? '0 0 ' . $width . ' ' . $height : '0 0 640 360');
        }
        $root->setAttribute('width', (string) self::WIDTH);
        $root->setAttribute('height', (string) self::HEIGHT);
        $root->setAttribute('preserveAspectRatio', 'xMidYMid slice');
        $sized = $document->saveXML($root);
        if ($sized === false) throw new RuntimeException('The cover could not be read.');
        return $sized;
    }

    private function draw(string $tool, string $svg): string
    {
        $process = proc_open([$tool, '--format=png', '--background-color=white'], [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes);
        if (!is_resource($process)) throw new RuntimeException('rsvg-convert could not be started.');
        stream_set_blocking($pipes[1], false);
        stream_set_blocking($pipes[2], false);
        fwrite($pipes[0], $svg);
        fclose($pipes[0]);
        $png = '';
        $deadline = microtime(true) + self::TIMEOUT;
        while (true) {
            $png .= (string) stream_get_contents($pipes[1]);
            stream_get_contents($pipes[2]);
            $status = proc_get_status($process);
            if (!$status['running']) {
                $png .= (string) stream_get_contents($pipes[1]);
                break;
            }
            if (microtime(true) > $deadline) {
                proc_terminate($process);
                fclose($pipes[1]); fclose($pipes[2]); proc_close($process);
                throw new RuntimeException('rsvg-convert took too long.');
            }
            usleep(20000);
        }
        fclose($pipes[1]);
        fclose($pipes[2]);
        proc_close($process);
        $size = $png === '' ? false : @getimagesizefromstring($png);
        if ($size === false || $size[0] !== self::WIDTH || $size[1] !== self::HEIGHT || $size['mime'] !== 'image/png') throw new RuntimeException('rsvg-convert drew nothing usable.');
        return $png;
    }
}
