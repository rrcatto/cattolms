namespace CattoLearning\Search;

use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Configuration\SiteOwner;
use CattoLearning\Configuration\SitePicture;
use CattoPHP\Search\DefaultSharePicture;

final class SiteSharePicture implements DefaultSharePicture
{
    public function __construct(private readonly SitePicture $picture, private readonly SiteOwner $owner, private readonly RuntimeSettings $settings)
    {
    }

    public function url(string $base): ?string
    {
        return $this->picture->shareUrl($base);
    }

    public function alt(): string
    {
        $name = $this->owner->value('trading_name');
        return $name !== '' ? $name : $this->settings->platformName();
    }

    public function type(): string
    {
        return 'image/jpeg';
    }
}
