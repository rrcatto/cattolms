     * The ACL already withholds COURSE.IMPORT from every SEED role, so this is the second of two
     * independent gates rather than the only one. It is worth having because the permission
     * catalogue is administrator-editable and the universe rule is not.
     */
    private function refuseSeedImporter(int $userId): void
    {
    }

    /** @return array<string,mixed> */
    private function requireCourse(int $courseId): array
    {
        $course = $this->courses->findById($courseId);
        if ($course === null) {
            throw new InvalidArgumentException('The course does not exist.');
        }
        return $course;
    }

    /** @return array{0:string,1:array<string,mixed>} */
    private function staged(string $key): array
    {
        if (preg_match('/^[a-f0-9]{32}$/', $key) !== 1) {
            throw new InvalidArgumentException('Invalid import reference.');
        }
        $metaPath = $this->storageRoot . '/imports/' . $key . '.meta.json';
        if (!is_file($metaPath)) {
            throw new InvalidArgumentException('The staged import does not exist or has expired.');
        }
        $metadata = json_decode((string) file_get_contents($metaPath), true);
        if (!is_array($metadata)) {
            throw new InvalidArgumentException('The staged import metadata is invalid.');
        }
        $extension = (string) ($metadata['extension'] ?? 'html');
        $path = $this->storageRoot . '/imports/' . $key . '.' . $extension;
        if (!is_file($path)) {
            throw new InvalidArgumentException('The staged course file is missing.');
        }
        return [$path, $metadata];
    }

    /** @return array<string,mixed> */
    private function analysePath(string $path, string $name, string $extension): array
    {
        return $extension === 'json'
            ? $this->jsonImporter->analyseFile($path, $name)
            : $this->htmlImporter->analyseFile($path, $name);
    }

    private function requireDirectory(string $directory): void
    {
        if (!is_dir($directory) && !mkdir($directory, 0770, true) && !is_dir($directory)) {
            throw new RuntimeException('Unable to create storage directory: ' . $directory);
        }
        if (!is_writable($directory)) {
            throw new RuntimeException('Storage directory is not writable: ' . $directory);
        }
    }
