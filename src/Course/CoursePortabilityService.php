    /**
     * @param list<array<string,mixed>> $blocks
     * @return list<array<string,mixed>>
     */
    private function exportBlocks(array $blocks): array
    {
        return array_map(function (array $block): array {
            return [
                'type' => $block['block_type'] ?? $block['type'] ?? 'html',
                'title' => $block['title'] ?? null,
                'content_html' => $block['content_html'] ?? '',
                'settings' => is_array($block['settings'] ?? null) ? $block['settings'] : [],
                'blocks' => $this->exportBlocks((array) ($block['blocks'] ?? [])),
            ];
        }, $blocks);
    }

    /**
     * @param array<string,mixed> $course
     * @param array<string,string> $values
     */
    private function renderCertificateTemplate(array $course, array $values): string
    {
        $html = trim((string) ($course['certificate_template_html'] ?? ''));
        if ($html === '') {
            $html = '<section class="cl-certificate"><p>{{certificate_title}}</p><h1>{{student_name}}</h1><p>{{certificate_body}}</p><h2>{{course_title}}</h2><p>{{overall_percentage}}% · {{overall_grade}}</p><footer>{{certificate_number}}</footer></section>';
        }
        foreach ($values as $key => $value) {
            $html = str_replace('{{' . $key . '}}', htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'), $html);
        }
        $css = (string) ($course['certificate_template_css'] ?? '');
        return '<style>' . $css . '</style>' . $html;
    }

    /** @param list<string> $storageKeys */
    private function removeMediaFiles(array $storageKeys): void
    {
        $root = realpath($this->storageRoot . '/course-media');
        if ($root === false) {
            return;
        }
        foreach ($storageKeys as $storageKey) {
            $candidate = $this->storageRoot . '/course-media/' . ltrim($storageKey, '/');
            $directory = realpath(dirname($candidate));
            if ($directory === false || !str_starts_with($directory . '/', $root . '/')) {
                continue;
            }
            if (is_file($candidate)) {
                @unlink($candidate);
            }
        }
    }

    /** @return array<string,mixed> */
    /**
     * A course that exists and is REAL.
     *
     * Decision D5 makes portability a REAL-only capability, and the rule is about the course's
     * universe rather than the actor's permission: a genuine ADMIN holds COURSE.EXPORT and may
     * legitimately view SEED data, but exporting a SEED course would produce a package that
     * re-imports as REAL content and launders generated rows into the genuine universe.
     *
     * @return array<string,mixed>
     */
    private function requireRealCourse(int $courseId): array
    {
        $course = $this->requireCourse($courseId);
        if (($course['seed_token'] ?? null) !== null) {
            throw new InvalidArgumentException(
                'Course portability is available for genuine courses only. This course belongs to a generated seed set.'
            );
        }

        return $course;
    }

