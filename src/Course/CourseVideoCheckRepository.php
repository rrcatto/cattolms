declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Infrastructure\Persistence\Database;
use DateTimeImmutable;

final class CourseVideoCheckRepository
{
    public function __construct(private readonly Database $db)
    {
    }

    /**
     * Every YouTube item placed in a course, with its video's id.
     *
     * @return list<array{course_item_id:int,youtube_id:string}>
     */
    public function videos(): array
    {
        $rows = $this->db->fetchAllAssociative(
            "SELECT ci.id AS course_item_id, ci.type_config->>'youtube_id' AS youtube_id
               FROM course_items ci
              WHERE ci.item_type = 'youtube' AND COALESCE(ci.type_config->>'youtube_id', '') <> ''
                AND EXISTS (SELECT 1 FROM course_item_placements p WHERE p.course_item_id = ci.id)
              ORDER BY ci.id"
        );
        return array_map(static fn(array $row): array => ['course_item_id' => (int) $row['course_item_id'], 'youtube_id' => (string) $row['youtube_id']], $rows);
    }

    /** What the check found for one video: a video that stops playing keeps the time it first failed. */
    public function record(int $itemId, string $youtubeId, string $status, string $detail, DateTimeImmutable $at): void
    {
        $this->db->executeStatement(
            "INSERT INTO course_video_checks (course_item_id, youtube_id, status, detail, checked_at, failing_since)
             VALUES (:item, :video, :status, :detail, CAST(:at AS timestamptz), CASE WHEN :status = 'plays' THEN NULL ELSE CAST(:at AS timestamptz) END)
             ON CONFLICT (course_item_id) DO UPDATE SET youtube_id = EXCLUDED.youtube_id, status = EXCLUDED.status, detail = EXCLUDED.detail, checked_at = EXCLUDED.checked_at,
                 failing_since = CASE WHEN EXCLUDED.status = 'plays' THEN NULL
                                      WHEN course_video_checks.status <> 'plays' AND course_video_checks.youtube_id = EXCLUDED.youtube_id THEN course_video_checks.failing_since
                                      ELSE EXCLUDED.checked_at END",
            ['item' => $itemId, 'video' => $youtubeId, 'status' => $status, 'detail' => mb_substr($detail, 0, 300), 'at' => $at->format('Y-m-d H:i:sP')]
        );
    }

    /** Forgets the checks of videos no longer placed in any course, or whose id has changed since. */
    public function forgetOthers(): int
    {
        return $this->db->executeStatement(
            "DELETE FROM course_video_checks v
              WHERE NOT EXISTS (SELECT 1 FROM course_items ci WHERE ci.id = v.course_item_id AND ci.item_type = 'youtube' AND ci.type_config->>'youtube_id' = v.youtube_id
                                   AND EXISTS (SELECT 1 FROM course_item_placements p WHERE p.course_item_id = ci.id))"
        );
    }

    /**
     * The videos that do not play, each with a course it is in, for Needs your attention.
     *
     * @return list<array{course_item_id:int,title:string,course_id:int,course_title:string,status:string,detail:string,checked_at:string,failing_since:string}>
     */
    public function failing(): array
    {
        $rows = $this->db->fetchAllAssociative(
            "SELECT v.course_item_id, ci.title, c.id AS course_id, c.title AS course_title, v.status, v.detail, v.checked_at, v.failing_since
               FROM course_video_checks v
               JOIN course_items ci ON ci.id = v.course_item_id AND ci.type_config->>'youtube_id' = v.youtube_id
               JOIN LATERAL (SELECT p.course_id FROM course_item_placements p WHERE p.course_item_id = ci.id ORDER BY p.course_id LIMIT 1) placed ON TRUE
               JOIN courses c ON c.id = placed.course_id
              WHERE v.status <> 'plays'
              ORDER BY v.failing_since, v.course_item_id"
        );
        return array_map(static fn(array $row): array => ['course_item_id' => (int) $row['course_item_id'], 'title' => (string) $row['title'], 'course_id' => (int) $row['course_id'],
            'course_title' => (string) $row['course_title'], 'status' => (string) $row['status'], 'detail' => (string) $row['detail'],
            'checked_at' => (string) $row['checked_at'], 'failing_since' => (string) $row['failing_since']], $rows);
    }
}
