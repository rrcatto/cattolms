    /**
     * @param array<string,mixed> $uploadedFile
     * @return array<string,mixed>
     */
    public function importPresentationFromHtml(int $courseId, array $uploadedFile, int $userId): array
    {
        if ($this->courses->findById($courseId) === null) {
            throw new InvalidArgumentException('The course does not exist.');
        }
        $error = (int) ($uploadedFile['error'] ?? UPLOAD_ERR_NO_FILE);
        if ($error !== UPLOAD_ERR_OK) {
            throw new InvalidArgumentException('Select the original HTML course file.');
        }
        $size = (int) ($uploadedFile['size'] ?? 0);
        if ($size < 1 || $size > 10 * 1024 * 1024) {
            throw new InvalidArgumentException('The HTML course file must be smaller than 10 MB.');
        }
        $temporary = (string) ($uploadedFile['tmp_name'] ?? '');
        $original = basename((string) ($uploadedFile['name'] ?? 'course.html'));
        $extension = strtolower(pathinfo($original, PATHINFO_EXTENSION));
        if (!in_array($extension, ['html', 'htm'], true) || !is_file($temporary)) {
            throw new InvalidArgumentException('Upload an HTML course file.');
        }
        $html = file_get_contents($temporary);
        if (!is_string($html) || trim($html) === '') {
            throw new InvalidArgumentException('The uploaded HTML course file is empty.');
        }
        $css = $this->importer->presentationCss($html);
        if (trim($css) === '') {
            throw new InvalidArgumentException('No course presentation stylesheet was found in that HTML file.');
        }
        $this->courses->updatePresentationCss($courseId, $css, $userId);
        $this->courses->recordHistory(
            $courseId,
            $userId,
            'course.presentation_imported',
            'course',
            $courseId,
            'Course presentation refreshed from ' . $original . '.',
            ['source_filename' => $original, 'css_bytes' => strlen($css)]
        );
        $this->audit->record($userId, 'course.presentation_imported', [
            'course_id' => $courseId,
            'source_filename' => $original,
            'css_bytes' => strlen($css),
        ]);
        return ['source_filename' => $original, 'css_bytes' => strlen($css)];
    }

    /** Save an edited presentation stylesheet exactly as authored; an empty value removes it. */
    public function updatePresentationCss(int $courseId, string $css, int $userId): void
