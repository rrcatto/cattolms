    private static function scaled(array $rows): array
    {
        $largest = 0;
        foreach ($rows as $row) {
            $largest = max($largest, $row['total']);
        }

        $scaled = [];
        foreach ($rows as $row) {
            $scaled[] = $row + ['share' => $largest === 0 ? 0 : (int) round($row['total'] / $largest * 100)];
        }

        return $scaled;
    }

