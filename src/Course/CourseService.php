            $this->courses->replaceAssessmentQuestions($id, $questions);
            $this->courses->recordHistory($courseId, $userId, $event, 'assessment', $id, $summary, [
                'question_count' => count($questions),
                'assessment_key' => $assessmentData['assessment_key'],
            ]);
            return $id;
        });

