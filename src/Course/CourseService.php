    /**
     * @param array<string,mixed> $input
     * @return array<string,mixed>
     */
    private function validatePriceVariantInput(array $input): array
    {
        $value = max(1, (int) ($input['access_period_value'] ?? 0));
        $unit = trim((string) ($input['access_period_unit'] ?? 'months'));
        $multipliers = [
            'days' => 86400,
            'weeks' => 604800,
            'months' => 2592000,
            'years' => 31536000,
        ];
        if (!isset($multipliers[$unit])) {
            throw new InvalidArgumentException('Choose a valid access-period unit.');
        }
        if (($unit === 'days' && $value > 3650) || ($unit === 'weeks' && $value > 520) || ($unit === 'months' && $value > 120) || ($unit === 'years' && $value > 10)) {
            throw new InvalidArgumentException('The access period is unreasonably long.');
        }
        $priceText = trim(str_replace([',', ' '], '', (string) ($input['price'] ?? '')));
        if (preg_match('/^\d+(?:\.\d{1,2})?$/', $priceText) !== 1) {
            throw new InvalidArgumentException('Enter the price as an amount with no more than two decimal places.');
        }
        // Parsed by Money, so there is one conversion from a typed amount to cents on the platform.
        // The validation above is deliberately stricter than Money is: a price with three decimal
        // places is a typo on this form, and rounding it silently is not a kindness.
        $minorUnits = Money::ofMajorUnits($priceText)->minorUnits;
        $currency = strtoupper(trim((string) ($input['currency_code'] ?? 'ZAR')));
        if (preg_match('/^[A-Z]{3}$/', $currency) !== 1) {
            throw new InvalidArgumentException('Currency must be a three-letter ISO code such as ZAR.');
        }
        return [
            'access_period_seconds' => $value * $multipliers[$unit],
            'price_minor_units' => $minorUnits,
            'currency_code' => $currency,
            'label' => mb_substr(trim((string) ($input['label'] ?? '')), 0, 120),
            'is_active' => !empty($input['is_active']),
            'is_default' => false,
        ];
    }

    private function ensureDefaultPriceVariant(int $courseId, int $userId): void
    {
        $active = $this->courses->priceVariants($courseId, true);
        if ($active === []) {
            return;
        }
        foreach ($active as $variant) {
            if ((bool) ($variant['is_default'] ?? false)) {
                return;
            }
        }
        $this->courses->setDefaultPriceVariant($courseId, (int) $active[0]['id'], $userId);
    }

    private function assertPublishedPricingInvariant(int $courseId): void
    {
        $course = $this->courses->findById($courseId);
        if ($course === null || (string) ($course['status'] ?? '') !== 'published') {
            return;
        }
        $active = $this->courses->priceVariants($courseId, true);
        $defaults = array_filter($active, static fn(array $variant): bool => (bool) ($variant['is_default'] ?? false));
        if ($active === [] || count($defaults) !== 1) {
            throw new InvalidArgumentException('A published course must keep at least one active price option and exactly one active default price.');
        }
    }

    /**
     * @param list<array<string,mixed>> $variants
     * @return list<array<string,mixed>>
     */
    private function normalisePriceVariants(array $variants): array
    {
        foreach ($variants as &$variant) {
            $seconds = (int) ($variant['access_period_seconds'] ?? 0);
            $variant['access_period_label'] = $this->accessPeriodLabel($seconds);
            $variant['price_label'] = $this->formatPrice((int) ($variant['price_minor_units'] ?? 0), (string) ($variant['currency_code'] ?? 'ZAR'));
            [$value, $unit] = $this->accessPeriodInput($seconds);
            $variant['access_period_value'] = $value;
            $variant['access_period_unit'] = $unit;
            $variant['price_input'] = number_format(((int) ($variant['price_minor_units'] ?? 0)) / 100, 2, '.', '');
        }
        unset($variant);
        return $variants;
    }

    /** @return array{0:int,1:string} */
    private function accessPeriodInput(int $seconds): array
    {
        if ($seconds > 0 && $seconds % 31536000 === 0) {
            return [(int) ($seconds / 31536000), 'years'];
        }
        if ($seconds > 0 && $seconds % 2592000 === 0) {
            return [(int) ($seconds / 2592000), 'months'];
        }
        if ($seconds > 0 && $seconds % 604800 === 0) {
            return [(int) ($seconds / 604800), 'weeks'];
        }
        return [max(1, (int) round($seconds / 86400)), 'days'];
    }

    private function accessPeriodLabel(int $seconds): string
    {
        [$value, $unit] = $this->accessPeriodInput($seconds);
        $singular = rtrim($unit, 's');
        return $value . ' ' . ($value === 1 ? $singular : $unit);
    }

    /**
     * One price, formatted for this installation.
     *
     * Delegated to Money rather than assembled here. This used to test the code against 'ZAR' and
     * prefix an R, which is right for one country and wrong for the next: it puts the symbol on the
     * wrong side for several currencies and uses the wrong thousands separator for most of Europe.
     */
    private function formatPrice(int $minorUnits, string $currency): string
    {
        return Money::ofMinorUnits($minorUnits, $currency)->format();
    }

    /**
     * @param array<string,mixed> $input
     * @return array<string,mixed>
     */
    private function validateCategoryInput(array $input, ?int $existingCategoryId = null): array
    {
        $name = trim((string) ($input['name'] ?? $input['category_name'] ?? ''));
        if ($name === '' || mb_strlen($name) > 120) {
            throw new InvalidArgumentException('Enter a category name of no more than 120 characters.');
        }
        $slugInput = trim((string) ($input['slug'] ?? $input['category_slug'] ?? ''));
        $slug = $slugInput !== '' ? Slug::validate($slugInput) : Slug::from($name);
        $duplicate = $this->courses->categoryBySlug($slug);
        if ($duplicate !== null && (int) $duplicate['id'] !== (int) $existingCategoryId) {
            throw new InvalidArgumentException('Another course category already uses the slug "' . $slug . '".');
        }
        // Names are unique across the whole taxonomy, so the clash is caught here with a sentence
        // rather than reaching the reader as a constraint violation.
        $sameName = $this->courses->categoryByName($name);
        if ($sameName !== null && (int) $sameName['id'] !== (int) $existingCategoryId) {
            throw new InvalidArgumentException('Another course category is already called "' . $name . '".');
        }

        // A category may sit under one parent, and the depth cap is three. Rejected here with an
        // explanation; the database refuses it as well, but a constraint violation is not a
        // sentence anybody can act on.
        $parentId = max(0, (int) ($input['parent_id'] ?? 0));
        if ($parentId > 0) {
            if ($parentId === (int) $existingCategoryId) {
                throw new InvalidArgumentException('A course category cannot be filed under itself.');
            }
            $parent = $this->courses->categoryById($parentId);
            if ($parent === null) {
                throw new InvalidArgumentException('Choose a parent category that exists.');
            }
            if ((int) $parent['level'] >= 3) {
                throw new InvalidArgumentException(
                    'Course categories go three levels deep, so "' . (string) $parent['name'] . '" cannot hold sub-categories.'
                );
            }
            if ($existingCategoryId !== null && $this->categoryIsDescendantOf($parentId, $existingCategoryId)) {
                throw new InvalidArgumentException('A course category cannot be filed under one of its own sub-categories.');
            }
        }

        return [
            'name' => $name,
            'slug' => $slug,
            'parent_id' => $parentId,
            'description' => trim((string) ($input['description'] ?? $input['category_description'] ?? '')),
        ];
    }

    /** The parent of one category, or 0 when it is a top-level one. */
    private function parentOf(int $categoryId): int
    {
        $category = $this->courses->categoryById($categoryId);

        return (int) ($category['parent_id'] ?? 0);
    }

    /**
     * Whether one category sits anywhere beneath another.
     *
     * The depth trigger only compares a row against its immediate parent, so it cannot see a cycle
     * being created by re-parenting a category under its own grandchild. Three levels means the
     * walk is bounded by construction.
     */
    private function categoryIsDescendantOf(int $candidateId, int $ancestorId): bool
    {
        $walk = $candidateId;
        for ($depth = 0; $depth < 3 && $walk > 0; $depth++) {
            if ($walk === $ancestorId) {
                return true;
            }
            $walk = $this->parentOf($walk);
        }

        return false;
    }

    /**
     * @param array<string,mixed> $existing
     * @param array<string,mixed> $input
     * @return array<string,mixed>
     */
    private function validateCourseInput(array $input, array $existing = []): array
    {
        $title = trim((string) ($input['title'] ?? $existing['title'] ?? ''));
        if ($title === '' || mb_strlen($title) > 240) {
            throw new InvalidArgumentException('Enter a course title of no more than 240 characters.');
        }
        $slugInput = trim((string) ($input['slug'] ?? $existing['slug'] ?? ''));
        $slug = $slugInput !== '' ? Slug::validate($slugInput) : Slug::from($title);
        $moduleWeight = $this->fraction($input['module_weight'] ?? $existing['module_weight'] ?? 0.5);
        $finalWeight = $this->fraction($input['final_weight'] ?? $existing['final_weight'] ?? 0.5);
        if (abs(($moduleWeight + $finalWeight) - 1.0) > 0.0001) {
            throw new InvalidArgumentException('Module and final-assessment weights must total 1.0.');
        }
        $period = array_key_exists('access_days', $input)
            ? max(1, (int) $input['access_days']) * 86400
            : (int) ($input['default_access_period_seconds'] ?? $existing['default_access_period_seconds'] ?? 31536000);
        if ($period < 1) {
            throw new InvalidArgumentException('The default access period must be greater than zero.');
        }
        return [
            'category_id' => (int) ($input['category_id'] ?? $existing['category_id'] ?? 0),
            'slug' => $slug,
            'title' => $title,
            'subtitle' => trim((string) ($input['subtitle'] ?? $existing['subtitle'] ?? '')),
            'summary' => trim((string) ($input['summary'] ?? $existing['summary'] ?? '')),
            'description_html' => $this->courseHtml->preserve((string) ($input['description_html'] ?? $existing['description_html'] ?? '')),
            'level' => trim((string) ($input['level'] ?? $existing['level'] ?? '')),
            'estimated_minutes' => max(0, (int) ($input['estimated_minutes'] ?? $existing['estimated_minutes'] ?? 0)),
            'status' => (string) ($input['status'] ?? $existing['status'] ?? 'draft'),
            'default_access_period_seconds' => $period,
            'module_weight' => $moduleWeight,
            'final_weight' => $finalWeight,
            'certificate_enabled' => $this->boolValue($input['certificate_enabled'] ?? $existing['certificate_enabled'] ?? true),
            'certificate_title' => trim((string) ($input['certificate_title'] ?? $existing['certificate_title'] ?? 'Certificate of Completion')),
            'certificate_template' => trim((string) ($input['certificate_template'] ?? $existing['certificate_template'] ?? 'classic')) ?: 'classic',
            'certificate_body_text' => trim((string) ($input['certificate_body_text'] ?? $existing['certificate_body_text'] ?? 'has successfully completed')) ?: 'has successfully completed',
            'certificate_footer_text' => trim((string) ($input['certificate_footer_text'] ?? $existing['certificate_footer_text'] ?? '')),
            'certificate_signatory_name' => trim((string) ($input['certificate_signatory_name'] ?? $existing['certificate_signatory_name'] ?? '')),
            'certificate_signatory_title' => trim((string) ($input['certificate_signatory_title'] ?? $existing['certificate_signatory_title'] ?? '')),
            'course_style_key' => trim((string) ($input['course_style_key'] ?? $existing['course_style_key'] ?? 'standard')) ?: 'standard',
            'source_filename' => trim((string) ($input['source_filename'] ?? $existing['source_filename'] ?? '')),
        ];
    }

    /**
     * @param array<string,mixed> $input
     * @return array<string,mixed>
     */
    private function validateModuleInput(array $input): array
    {
        $title = trim((string) ($input['title'] ?? ''));
        if ($title === '') {
            throw new InvalidArgumentException('Enter a module title.');
        }
        $position = (int) ($input['position'] ?? 0);
        if ($position < 1) {
            throw new InvalidArgumentException('Module position must be one or greater.');
        }
        $moduleKey = trim((string) ($input['module_key'] ?? ''));
        if ($moduleKey === '') {
            $moduleKey = 'm' . $position;
        }
        if (preg_match('/^[a-zA-Z0-9_-]+$/', $moduleKey) !== 1) {
            throw new InvalidArgumentException('Module keys may contain letters, numbers, underscores and hyphens only.');
        }
        $isReview = $this->boolValue($input['is_review'] ?? false);
        $assessmentRequired = array_key_exists('assessment_required', $input)
            ? $this->boolValue($input['assessment_required'])
            : !$isReview;
        return [
            'module_key' => $moduleKey,
            'position' => $position,
            'title' => $title,
            'subtitle' => trim((string) ($input['subtitle'] ?? '')),
            'learning_outcomes_html' => $this->courseHtml->learningOutcomes((string) ($input['learning_outcomes_html'] ?? '')),
            'content_html' => $this->courseHtml->preserve((string) ($input['content_html'] ?? '')),
            'summary_html' => $this->courseHtml->preserve((string) ($input['summary_html'] ?? '')),
            'is_review' => $isReview,
            'assessment_required' => $assessmentRequired,
            'assessment' => is_array($input['assessment'] ?? null) ? $input['assessment'] : null,
        ];
    }

    /**
     * @param array<string,mixed> $input
     * @return list<array<string,mixed>>
     */
    private function parseQuestionEditorInput(array $input): array
    {
        $questionTexts = (array) ($input['question_html'] ?? []);
        $points = (array) ($input['question_points'] ?? []);
        $explanations = (array) ($input['question_explanation'] ?? []);
        $optionTexts = (array) ($input['option_html'] ?? []);
        $correctOptions = (array) ($input['correct_option'] ?? []);
        $difficulties = (array) ($input['question_difficulty'] ?? []);
        $practiceEligible = (array) ($input['practice_eligible'] ?? []);
        $gradedEligible = (array) ($input['graded_eligible'] ?? []);
        $incorrectPoints = (array) ($input['incorrect_points'] ?? []);
        $remediationKeys = (array) ($input['remediation_module_keys'] ?? []);
        $questions = [];
        foreach ($questionTexts as $index => $text) {
            $text = $this->courseHtml->preserve((string) $text);
            if ($text === '') {
                continue;
            }
            $rawOptions = is_array($optionTexts[$index] ?? null) ? $optionTexts[$index] : [];
            $correct = (int) ($correctOptions[$index] ?? -1);
            $options = [];
            foreach ($rawOptions as $optionIndex => $optionText) {
                $optionText = $this->courseHtml->preserve((string) $optionText);
                if ($optionText === '') {
                    continue;
                }
                $options[] = [
                    'option_html' => $optionText,
                    'is_correct' => (int) $optionIndex === $correct,
                ];
            }
            if (count($options) < 2 || count(array_filter($options, static fn(array $o): bool => $o['is_correct'])) !== 1) {
                throw new InvalidArgumentException('Every question requires at least two options and exactly one correct answer.');
            }
            $questions[] = [
                'question_html' => $text,
                'points' => max(1, (int) ($points[$index] ?? 1)),
                'explanation_html' => $this->courseHtml->preserve((string) ($explanations[$index] ?? '')),
                'difficulty' => in_array((string) ($difficulties[$index] ?? 'standard'), ['introductory','standard','advanced'], true) ? (string) $difficulties[$index] : 'standard',
                'practice_eligible' => array_key_exists((string) $index, $practiceEligible) || array_key_exists($index, $practiceEligible),
                'graded_eligible' => array_key_exists((string) $index, $gradedEligible) || array_key_exists($index, $gradedEligible),
                'incorrect_points' => min(0, (float) ($incorrectPoints[$index] ?? 0)),
                'remediation_module_keys' => array_values(array_filter(array_map(
                    static fn(mixed $value): string => trim((string) $value),
                    is_array($remediationKeys[$index] ?? null) ? $remediationKeys[$index] : []
                ), static fn(string $value): bool => $value !== '')),
                'options' => $options,
            ];
        }
        if ($questions === []) {
            throw new InvalidArgumentException('Add at least one assessment question.');
        }
        return $questions;
    }

    /**
     * @param array<string,mixed> $assessment
     * @param list<array<string,mixed>> $questions
     */
    private function validateAssessmentSelection(array $assessment, array $questions): void
    {
        $graded = array_values(array_filter($questions, static fn(array $question): bool => (bool) ($question['graded_eligible'] ?? false)));
        $gradedCount = (int) ($assessment['graded_question_count'] ?? 0);
        if ($gradedCount < 1 || $gradedCount > count($graded)) {
            throw new InvalidArgumentException('The graded question count must not exceed the number of graded-eligible questions.');
        }

        $quotas = (array) ($assessment['difficulty_selection'] ?? []);
        $quotaTotal = array_sum(array_map('intval', $quotas));
        if ($quotaTotal > 0 && $quotaTotal !== $gradedCount) {
            throw new InvalidArgumentException('Difficulty quotas must total the graded questions drawn.');
        }
        foreach (['introductory','standard','advanced'] as $tier) {
            $available = count(array_filter($graded, static fn(array $question): bool => (string) ($question['difficulty'] ?? 'standard') === $tier));
            if ((int) ($quotas[$tier] ?? 0) > $available) {
                throw new InvalidArgumentException('The ' . $tier . ' quota exceeds the available graded-eligible questions.');
            }
        }

        if (!(bool) ($assessment['practice_enabled'] ?? false)) {
            return;
        }
        $poolMode = (string) ($assessment['practice_pool_mode'] ?? 'both');
        $practice = array_values(array_filter($questions, static function (array $question) use ($poolMode): bool {
            return match ($poolMode) {
                'separate' => (bool) ($question['practice_eligible'] ?? false) && !(bool) ($question['graded_eligible'] ?? false),
                'graded' => (bool) ($question['graded_eligible'] ?? false),
                default => (bool) ($question['practice_eligible'] ?? false) || (bool) ($question['graded_eligible'] ?? false),
            };
        }));
        if ((int) ($assessment['practice_question_count'] ?? 0) > count($practice)) {
            throw new InvalidArgumentException('The practice question count exceeds the eligible practice pool.');
        }
    }

    private function fraction(mixed $value): float
    {
        $number = (float) $value;
        if ($number < 0 || $number > 1) {
            throw new InvalidArgumentException('Assessment weights must be between 0 and 1.');
        }
        return $number;
    }

    private function percentage(mixed $value): float
    {
        $number = (float) $value;
        if ($number < 0 || $number > 100) {
            throw new InvalidArgumentException('Percentages must be between 0 and 100.');
        }
        return $number;
    }

    private function boolValue(mixed $value): bool
    {
        return in_array($value, [true, 1, '1', 'true', 'on', 'yes'], true);
    }


    private function assertPublishable(int $courseId): void
    {
        $modules = $this->courses->modules($courseId);
        foreach ($modules as $module) {
            if (!(bool) ($module['assessment_required'] ?? true)) {
                continue;
            }
            $assessment = $this->courses->assessmentForModule((int) $module['id']);
            if ($assessment === null || $this->courses->questions((int) $assessment['id'], false) === []) {
                throw new InvalidArgumentException(
                    'Every module explicitly marked as requiring an assessment must have at least one assessment question before publication.'
                );
            }
        }

        $finalAssessment = $this->courses->finalAssessment($courseId);
        if ($finalAssessment !== null
            && (bool) ($finalAssessment['required'] ?? false)
            && $this->courses->questions((int) $finalAssessment['id'], false) === []) {
            throw new InvalidArgumentException('A final assessment marked as required must contain at least one question before publication.');
        }

        $activePrices = $this->courses->priceVariants($courseId, true);
        $defaults = array_filter($activePrices, static fn(array $variant): bool => (bool) ($variant['is_default'] ?? false));
        if ($activePrices === [] || count($defaults) !== 1) {
            throw new InvalidArgumentException('Define at least one active course price and exactly one default price before publication.');
        }
    }

