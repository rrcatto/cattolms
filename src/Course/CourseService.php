        $this->courses->updateTag($id, ['name' => $name, 'slug' => $slug]);
        $this->audit->record($actorUserId, 'course.tag.updated', [
            'tag_id' => $id, 'from' => (string) $tag['name'], 'to' => $name,
        ]);
    }

