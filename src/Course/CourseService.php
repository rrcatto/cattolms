    public function moveCategory(int $categoryId, string $direction, int $userId): void
    {
        if (!in_array($direction, ['up', 'down'], true)) {
            throw new InvalidArgumentException('Choose whether to move the category up or down.');
        }
        // Moving is within a branch: the ordering below is already tree order, and swapping two
        // rows that sit under different parents would move a category sideways rather than up.
        // The parent is resolved once, outside the filter - asking per row would be one query per
        // category to answer the same question.
        $parentId = $this->parentOf($categoryId);
        $categories = array_values(array_filter(
            $this->courses->categories(),
            static fn(array $row): bool => (int) ($row['parent_id'] ?? 0) === $parentId
        ));
        $index = null;
        foreach ($categories as $position => $category) {
            if ((int) $category['id'] === $categoryId) {
                $index = $position;
                break;
            }
        }
        if ($index === null) {
            throw new InvalidArgumentException('The course category does not exist.');
        }
        $otherIndex = $direction === 'up' ? $index - 1 : $index + 1;
        if (!isset($categories[$otherIndex])) {
            return;
        }
        $this->courses->swapCategoryPositions($categoryId, (int) $categories[$otherIndex]['id']);
        $this->audit->record($userId, 'course_category.reordered', ['category_id' => $categoryId, 'direction' => $direction]);
    }

    public function deleteCategory(int $categoryId, ?int $replacementCategoryId, int $userId): void
    {
        $category = $this->category($categoryId);
        $courseCount = (int) ($category['course_count'] ?? 0);
        if ($replacementCategoryId === $categoryId) {
            throw new InvalidArgumentException('Choose a different replacement category.');
        }
        // A branch is never deleted wholesale. The database refuses it too - the parent reference
        // is ON DELETE RESTRICT - but a foreign key violation is not a sentence anybody can act on,
        // and removing three levels of taxonomy plus every course filed under them is not something
        // one button should be able to do.
        $childCount = $this->courses->categoryChildCount($categoryId);
        if ($childCount > 0) {
            throw new InvalidArgumentException(
                'This category has ' . $childCount . ' sub-categor' . ($childCount === 1 ? 'y' : 'ies')
                . ' beneath it. Move or delete those first.'
            );
        }
        if ($courseCount > 0 && ($replacementCategoryId === null || $replacementCategoryId < 1)) {
            throw new InvalidArgumentException('This category is still used by courses. Choose a replacement category or deactivate it instead.');
        }
        $this->transactions->run(function () use ($categoryId, $replacementCategoryId): void {
            if ($replacementCategoryId !== null && $replacementCategoryId > 0) {
                $replacement = $this->courses->categoryById($replacementCategoryId);
                if ($replacement === null) {
                    throw new InvalidArgumentException('The replacement category does not exist.');
                }
                $this->courses->reassignCategoryCourses($categoryId, $replacementCategoryId);
            }
            $this->courses->deleteCategory($categoryId);
        });
        $this->audit->record($userId, 'course_category.deleted', [
            'category_id' => $categoryId,
            'name' => (string) $category['name'],
            'replacement_category_id' => $replacementCategoryId,
            'reassigned_course_count' => $courseCount,
        ]);
    }

    /** @return array<string,mixed>|null */
    public function publicCourse(string $slug): ?array
    {
        $course = $this->courses->findBySlug(Slug::validate($slug), true);
        if ($course === null) {
            return null;
        }
        $course['modules'] = $this->courses->modules((int) $course['id']);
        $course['grade_bands'] = $this->courses->gradeBands((int) $course['id']);
        $course['module_count'] = count($course['modules']);
        $course['question_count'] = array_sum(array_map(
            static fn(array $module): int => (int) ($module['question_count'] ?? 0),
            $course['modules']
        ));
        foreach ($this->courses->diagnosticAssessments((int) $course['id']) as $diagnostic) {
            $course['question_count'] += count($this->courses->questions((int) $diagnostic['id'], false));
        }
        $final = $this->courses->finalAssessment((int) $course['id']);
        if ($final !== null) {
            $course['question_count'] += count($this->courses->questions((int) $final['id'], false));
        }
        $course['price_variants'] = $this->normalisePriceVariants($this->courses->priceVariants((int) $course['id'], true));
        return $course;
    }

