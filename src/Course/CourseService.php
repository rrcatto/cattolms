    public function movePriceVariant(int $courseId, int $variantId, string $direction, int $userId): void
    {
        if (!in_array($direction, ['up', 'down'], true)) {
            throw new InvalidArgumentException('Invalid pricing reorder direction.');
        }
        $variants = $this->courses->priceVariants($courseId);
        $index = null;
        foreach ($variants as $position => $variant) {
            if ((int) $variant['id'] === $variantId) {
                $index = $position;
                break;
            }
        }
        if ($index === null) {
            throw new InvalidArgumentException('The course price variant does not exist.');
        }
        $otherIndex = $direction === 'up' ? $index - 1 : $index + 1;
        if (!isset($variants[$otherIndex])) {
            return;
        }
        $this->courses->swapPriceVariantPositions($courseId, $variantId, (int) $variants[$otherIndex]['id']);
        $this->courses->recordHistory($courseId, $userId, 'pricing.reordered', 'price_variant', $variantId, 'Course price variants reordered.');
        $this->audit->record($userId, 'course.pricing_reordered', ['course_id' => $courseId, 'price_variant_id' => $variantId]);
    }

