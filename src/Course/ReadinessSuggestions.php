declare(strict_types=1);

namespace CattoLearning\Course;

final class ReadinessSuggestions
{
    /** The parts of a module a learner studies, by CourseItemService::part(). */
    public const STUDY_PARTS = ['presentation', 'video', 'lesson', 'summary', 'flashcards', 'review'];

    /**
     * The suggestions for the questions not answered correctly, in course order.
     *
     * @param list<array<string,mixed>> $structure the course's whole outline, as CourseItemService::availability() gives it
     * @param list<list<string>> $wrong each question not answered correctly, by the references it holds
     * @param array<int,true>|null $open the parts the reader can open, by row id (the public preview's), or null for every one
     * @return list<array{heading:string,module:int|null,link:array<string,mixed>|null,questions:int,parts:list<array{label:string,title:string,row:array<string,mixed>,locked:bool,opens_in:string}>,elsewhere:bool}>
     */
    public static function resolve(array $structure, array $wrong, ?array $open = null): array
    {
        $modules = []; $items = []; $parents = [];
        foreach ($structure as $row) {
            $id = (int) $row['id'];
            $parents[$id] = $row['parent_node_id'] === null ? null : (int) $row['parent_node_id'];
            if (($row['node_type'] ?? '') === 'section' && ($row['section_number'] ?? null) !== null) { $modules[(int) $row['section_number']] ??= $id; }
            if (($row['node_type'] ?? '') === 'item' && (string) ($row['item_key'] ?? '') !== '') { $items[(string) $row['item_key']] ??= $id; }
        }

        $questions = [];
        foreach ($wrong as $references) {
            $targets = [];
            foreach ($references as $reference) {
                $reference = trim((string) $reference);
                $module = preg_match('/^m(\d{1,3})$/i', $reference, $number) === 1 ? ($modules[(int) $number[1]] ?? null) : null;
                $target = $module ?? $items[$reference] ?? null;
                if ($target !== null) { $targets[$target] = true; }
            }
            foreach (array_keys($targets) as $target) { $questions[$target] = ($questions[$target] ?? 0) + 1; }
        }
        if ($questions === []) { return []; }

        $opens = static fn(array $row): bool => $open === null || isset($open[(int) $row['id']]);
        $inside = static function (int $id, int $section) use ($parents): bool {
            for ($up = $parents[$id] ?? null; $up !== null; $up = $parents[$up] ?? null) { if ($up === $section) { return true; } }
            return false;
        };

        $suggestions = [];
        foreach ($structure as $row) {
            $id = (int) $row['id'];
            if (!isset($questions[$id])) { continue; }
            if (($row['node_type'] ?? '') === 'section') {
                $parts = [];
                foreach ($structure as $part) {
                    if (($part['node_type'] ?? '') !== 'item' || !$inside((int) $part['id'], $id) || !$opens($part)) { continue; }
                    $kind = (string) ($part['part'] ?? CourseItemService::part($part));
                    if (!in_array($kind, self::STUDY_PARTS, true) || (($part['type_config']['kind'] ?? '') === 'trailer')) { continue; }
                    $parts[] = self::part($part, $kind);
                }
                $link = CourseNavigation::isStop($row) && $opens($row) ? $row : null;
                $suggestions[] = ['heading' => 'Module ' . (int) $row['section_number'] . ': ' . (string) $row['section_title'], 'module' => (int) $row['section_number'], 'link' => $link, 'questions' => $questions[$id], 'parts' => $parts, 'elsewhere' => $link === null && $parts === []];
                continue;
            }
            $kind = (string) ($row['part'] ?? CourseItemService::part($row));
            $part = self::part($row, $kind);
            $link = $opens($row) ? $row : null;
            $suggestions[] = ['heading' => $part['label'] . ': ' . $part['title'], 'module' => null, 'link' => $link, 'questions' => $questions[$id], 'parts' => [], 'elsewhere' => $link === null];
        }
        return $suggestions;
    }

    /**
     * @param array<string,mixed> $row
     * @return array{label:string,title:string,row:array<string,mixed>,locked:bool,opens_in:string}
     */
    private static function part(array $row, string $kind): array
    {
        $title = trim((string) (($row['display_title_override'] ?? '') ?: ($row['item_title'] ?? '')));
        $label = CourseItemService::PART_LABELS[$kind] ?? (CourseItemService::TYPE_LABELS[(string) ($row['item_type'] ?? '')] ?? 'Part');
        return ['label' => $label, 'title' => $title !== '' ? $title : $label, 'row' => $row, 'locked' => (bool) ($row['is_locked'] ?? false), 'opens_in' => (string) ($row['remaining_delay_label'] ?? '')];
    }
}
