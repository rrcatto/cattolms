answer"), kept as the question's references (assessment_questions.remediation_item_keys) as the importer has kept them
since v0.5.4. m2 is Module 2 as the course numbers its modules, from 1 or from 0 (courses.first_module_number), the way a
course file names them (mod-m2) and the way the reader shows them. The suggestion is the module, in course order, with
the parts a learner studies in it (its presentation, video, lesson, summary, flash cards and review study aid, never its
practical work or its assessment) and how many of the questions point to it. Each part opens where the reader is: the
learner's reader, or the public preview, where only what the preview shows opens and a module it leaves out is named as
part of the full course. A reference that names no module but a Course Item placed in the course (one an administrator
typed in the question editor) suggests that part.

