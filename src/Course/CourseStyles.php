    /** At-rules whose block holds style rules, which are guarded in turn. */
    private const GROUPS = ['media', 'supports', 'container', 'layer', 'document', '-moz-document'];

    /** @var array<string,string> stylesheets already guarded in this request, by their hash */
    private static array $done = [];

    public static function forReader(string $css): string
    {
        if (trim($css) === '') return $css;
        $key = md5($css);
        return self::$done[$key] ??= self::rules($css);
    }

    /** A run of rules: each style rule's selectors guarded, each grouping at-rule's rules in turn, the rest as written. */
    private static function rules(string $css): string
    {
        $out = '';
        $length = strlen($css);
        $i = 0;
        while ($i < $length) {
            // Whitespace and comments between rules are kept as they are.
            if (ctype_space($css[$i])) { $out .= $css[$i++]; continue; }
            if (substr($css, $i, 2) === '/*') {
                $end = strpos($css, '*/', $i + 2);
                $end = $end === false ? $length : $end + 2;
                $out .= substr($css, $i, $end - $i);
                $i = $end;
                continue;
            }
            $open = self::find($css, $i, ['{', ';', '}']);
            if ($open === null) { $out .= substr($css, $i); break; }
            $char = $css[$open];
            if ($char !== '{') {
                // A statement (@import, @charset) or a stray closing brace: kept as written.
                $out .= substr($css, $i, $open - $i + 1);
                $i = $open + 1;
                continue;
            }
            $prelude = substr($css, $i, $open - $i);
            $close = self::matching($css, $open);
            $body = substr($css, $open + 1, $close - $open - 1);
            $head = trim($prelude);
            if (str_starts_with($head, '@')) {
                $name = strtolower((string) preg_replace('/^@([a-z-]+).*$/is', '$1', $head));
                $out .= $prelude . '{' . (in_array($name, self::GROUPS, true) ? self::rules($body) : $body) . '}';
            } else {
                $out .= self::selectors($prelude) . '{' . $body . '}';
            }
            $i = $close + 1;
        }
        return $out;
    }

    /** A selector list with each selector guarded, its spacing kept. */
    private static function selectors(string $prelude): string
    {
        $leading = (string) preg_replace('/^(\s*).*$/s', '$1', $prelude);
        $parts = [];
        foreach (self::split(trim($prelude)) as $selector) {
            $selector = trim($selector);
            if ($selector !== '') $parts[] = self::guard($selector);
        }
        return $leading . implode(', ', $parts) . ' ';
    }

    /** One selector with the guard on its subject, before a pseudo-element if it ends with one. */
    public static function guard(string $selector): string
    {
        if (str_contains($selector, self::GUARD)) return $selector;
        $at = self::pseudoElement($selector);
        return $at === null ? $selector . self::GUARD : substr($selector, 0, $at) . self::GUARD . substr($selector, $at);
    }

    /** Where a selector's trailing pseudo-element starts (::before, or the old :before, :after, :first-line, :first-letter). */
    private static function pseudoElement(string $selector): ?int
    {
        $depth = 0;
        $quote = null;
        $found = null;
        $length = strlen($selector);
        for ($i = 0; $i < $length; $i++) {
            $char = $selector[$i];
            if ($quote !== null) { if ($char === '\\') { $i++; } elseif ($char === $quote) { $quote = null; } continue; }
            if ($char === '"' || $char === "'") { $quote = $char; continue; }
            if ($char === '(' || $char === '[') { $depth++; continue; }
            if ($char === ')' || $char === ']') { $depth = max(0, $depth - 1); continue; }
            if ($depth > 0 || $char !== ':') continue;
            if (($selector[$i + 1] ?? '') === ':') { $found ??= $i; $i++; continue; }
            if (preg_match('/\G:(before|after|first-line|first-letter)\b/i', $selector, $match, 0, $i) === 1) { $found ??= $i; }
        }
        return $found;
    }

    /**
     * The selectors of a list, split at the commas outside brackets and strings.
     *
     * @return list<string>
     */
    private static function split(string $list): array
    {
        $parts = [];
        $current = '';
        $depth = 0;
        $quote = null;
        $length = strlen($list);
        for ($i = 0; $i < $length; $i++) {
            $char = $list[$i];
            if ($quote !== null) {
                $current .= $char;
                if ($char === '\\' && $i + 1 < $length) { $current .= $list[++$i]; } elseif ($char === $quote) { $quote = null; }
                continue;
            }
            if ($char === '"' || $char === "'") { $quote = $char; $current .= $char; continue; }
            if ($char === '(' || $char === '[') { $depth++; }
            if ($char === ')' || $char === ']') { $depth = max(0, $depth - 1); }
            if ($char === ',' && $depth === 0) { $parts[] = $current; $current = ''; continue; }
            $current .= $char;
        }
        $parts[] = $current;
        return $parts;
    }

    /**
     * The first of the given characters at or after $from, outside strings and comments.
     *
     * @param list<string> $chars
     */
    private static function find(string $css, int $from, array $chars): ?int
    {
        $length = strlen($css);
        $quote = null;
        for ($i = $from; $i < $length; $i++) {
            $char = $css[$i];
            if ($quote !== null) { if ($char === '\\') { $i++; } elseif ($char === $quote) { $quote = null; } continue; }
            if ($char === '"' || $char === "'") { $quote = $char; continue; }
            if ($char === '/' && ($css[$i + 1] ?? '') === '*') { $end = strpos($css, '*/', $i + 2); if ($end === false) return null; $i = $end + 1; continue; }
            if (in_array($char, $chars, true)) return $i;
        }
        return null;
    }

    /** The brace closing the one at $open, or the end of the stylesheet. */
    private static function matching(string $css, int $open): int
    {
        $depth = 0;
        $length = strlen($css);
        $quote = null;
        for ($i = $open; $i < $length; $i++) {
            $char = $css[$i];
            if ($quote !== null) { if ($char === '\\') { $i++; } elseif ($char === $quote) { $quote = null; } continue; }
            if ($char === '"' || $char === "'") { $quote = $char; continue; }
            if ($char === '/' && ($css[$i + 1] ?? '') === '*') { $end = strpos($css, '*/', $i + 2); if ($end === false) return $length; $i = $end + 1; continue; }
            if ($char === '{') { $depth++; }
            if ($char === '}' && --$depth === 0) return $i;
        }
        return $length;
    }
