    }

    /** @param list<float> $values */
    private function aggregate(array $values, string $policy): float
    {
        if ($values === []) {
            return 0.0;
        }
        return match ($policy) {
            'latest' => (float) $values[array_key_last($values)],
            'average' => array_sum($values) / count($values),
            default => max($values),
        };
    }

    /**
     * @param list<array<string,mixed>> $bands
