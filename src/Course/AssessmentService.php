    private function startAttempt(int $userId, array $overview, string $mode): array
    {
        if (!in_array($mode, ['practice','graded','diagnostic'], true)) {
            throw new InvalidArgumentException('Select a valid assessment mode.');
        }
        $assessment = (array) $overview['assessment'];
        $enrolment = (array) $overview['enrolment'];
        $isDiagnostic = (string) ($assessment['assessment_type'] ?? '') === 'diagnostic';
        if ($isDiagnostic && $mode !== 'diagnostic') {
            throw new InvalidArgumentException('Course diagnostics must be started in diagnostic mode.');
        }
        if (!$isDiagnostic && $mode === 'diagnostic') {
            throw new InvalidArgumentException('Diagnostic mode is only available for course diagnostics.');
        }
        if ($mode === 'practice' && !(bool) ($assessment['practice_enabled'] ?? true)) {
            throw new InvalidArgumentException('Practice assessment is not enabled for this assessment.');
        }
        $active = $this->assessments->activeSession((int) $enrolment['id'], (int) $assessment['id'], $mode);
        if ($active !== null) {
            return $active;
        }
        if (in_array($mode, ['graded', 'diagnostic'], true)) {
            $maximum = $assessment['maximum_attempts'] === null || $assessment['maximum_attempts'] === ''
                ? null
                : (int) $assessment['maximum_attempts'];
            $used = $this->assessments->completedAttemptCount((int) $enrolment['id'], (int) $assessment['id'], $mode);
            if ($maximum !== null && $used >= $maximum) {
                throw new InvalidArgumentException($mode === 'diagnostic' ? 'No diagnostic attempts remain.' : 'No graded assessment attempts remain.');
            }
        }
        $questions = $this->selectQuestions($assessment, $mode);
        if ($questions === []) {
            throw new InvalidArgumentException('No eligible questions are available for this assessment.');
        }
        $session = $this->transactions->run(fn(): array => $this->assessments->createSession(
            (int) $enrolment['id'],
            $assessment,
            $mode,
            $questions
        ));
        $this->audit->record($userId, 'assessment.started', [
            'assessment_id' => (int) $assessment['id'],
            'session_id' => (int) $session['id'],
            'mode' => $mode,
            'preview' => (bool) $enrolment['is_preview'],
        ]);
        return $session;
    }

    /**
     * @param array<string,mixed> $assessment
     * @return list<array<string,mixed>>
     */
    private function selectQuestions(array $assessment, string $mode): array
    {
        $all = $this->courses->questions((int) $assessment['id'], true);
        $poolMode = (string) ($assessment['practice_pool_mode'] ?? 'both');
        $eligible = array_values(array_filter($all, static function (array $question) use ($mode, $poolMode): bool {
            if ($mode === 'graded') {
                return (bool) ($question['graded_eligible'] ?? true);
            }
            return match ($poolMode) {
                'separate' => (bool) ($question['practice_eligible'] ?? true) && !(bool) ($question['graded_eligible'] ?? true),
                'graded' => (bool) ($question['graded_eligible'] ?? true),
                default => (bool) ($question['practice_eligible'] ?? true) || (bool) ($question['graded_eligible'] ?? true),
            };
        }));
        if ($mode === 'graded') {
            $difficulty = $assessment['difficulty_selection'] ?? [];
            if (is_string($difficulty)) {
                $decoded = json_decode($difficulty, true);
                $difficulty = is_array($decoded) ? $decoded : [];
            }
            if (is_array($difficulty) && array_sum(array_map('intval', $difficulty)) > 0) {
                $selected = [];
                foreach (['introductory','standard','advanced'] as $tier) {
                    $tierPool = array_values(array_filter($eligible, static fn(array $q): bool => (string) ($q['difficulty'] ?? 'standard') === $tier));
                    shuffle($tierPool);
                    $wanted = max(0, (int) ($difficulty[$tier] ?? 0));
                    if ($wanted > count($tierPool)) {
                        throw new InvalidArgumentException('The ' . $tier . ' question pool does not contain enough questions for the configured quota.');
                    }
                    $selected = array_merge($selected, array_slice($tierPool, 0, $wanted));
                }
                $eligible = $selected;
            }
        }
        if ((bool) ($assessment['randomise_questions'] ?? true)) {
            shuffle($eligible);
        }
        $count = in_array($mode, ['practice','diagnostic'], true)
            ? (int) ($assessment['practice_question_count'] ?? min(5, count($eligible)))
            : (int) ($assessment['graded_question_count'] ?? count($eligible));
        return array_slice($eligible, 0, max(1, min($count, count($eligible))));
    }

    /**
     * @param array<string,mixed> $session
