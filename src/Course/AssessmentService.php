     */
    private function band(float $percentage, array $bands): array
    {
        foreach ($bands as $band) {
            if ($percentage + 0.0001 >= (float) $band['minimum_percentage']) {
                return $band;
            }
        }
        return ['grade_code' => 'Fail', 'grade_label' => 'Fail', 'minimum_percentage' => 0, 'is_passing' => false];
    }

    /** @param array<string,mixed> $session */
    private function remainingSeconds(array $session): int
    {
        $deadline = strtotime((string) $session['deadline_at']);
        return max(0, ($deadline === false ? time() : $deadline) - time());
    }

    /** @param array<string,mixed> $session */
    private function elapsedSeconds(array $session): int
    {
        $started = strtotime((string) ($session['started_at'] ?? ''));
        $completed = strtotime((string) ($session['completed_at'] ?? ''));
        if ($started === false) {
            return 0;
        }
        if ($completed === false) {
            $completed = time();
        }
        return max(0, $completed - $started);
    }

    private function durationLabel(int $seconds): string
    {
        $seconds = max(1, $seconds);
        $hours = intdiv($seconds, 3600);
        $minutes = intdiv($seconds % 3600, 60);
        $parts = [];
        if ($hours > 0) {
            $parts[] = $hours . ' hour' . ($hours === 1 ? '' : 's');
        }
        if ($minutes > 0) {
            $parts[] = $minutes . ' minute' . ($minutes === 1 ? '' : 's');
        }
        if ($parts === []) {
            $parts[] = $seconds . ' seconds';
        }
        return implode(' ', $parts);
    }

    private function timerLabel(int $seconds): string
    {
        $hours = intdiv($seconds, 3600);
        $minutes = intdiv($seconds % 3600, 60);
        $remaining = $seconds % 60;
        return $hours > 0
            ? sprintf('%d:%02d:%02d', $hours, $minutes, $remaining)
            : sprintf('%d:%02d', $minutes, $remaining);
    }
