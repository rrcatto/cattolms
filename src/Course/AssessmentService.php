    private function finalise(array $session, bool $timedOut, bool $manual = false): array
    {
        if ((string) $session['status'] !== 'in_progress') {
            return $this->result((int) $session['user_id'], (string) $session['public_id']);
        }
        $result = $this->transactions->run(function () use ($session, $timedOut, $manual): array {
            if ($timedOut) {
                $this->assessments->markExpiredQuestions((int) $session['id']);
            } elseif ($manual) {
                $this->assessments->markRemainingUnanswered((int) $session['id']);
            }
            $calculated = $this->assessments->calculateSession((int) $session['id']);
            $course = $this->courses->findById((int) $session['course_id']);
            if ($course === null) {
                throw new RuntimeException('The course no longer exists.');
            }
            if ((string) ($session['assessment_type'] ?? '') === 'diagnostic') {
                $diagnosticPassed = (float) $calculated['percentage'] + 0.0001 >= (float) ($session['pass_mark'] ?? 50);
                $band = [
                    'grade_code' => $diagnosticPassed ? 'Ready' : 'Review',
                    'grade_label' => $diagnosticPassed ? 'Ready' : 'Review recommended',
                    'is_passing' => $diagnosticPassed,
                ];
            } else {
                $band = $this->band((float) $calculated['percentage'], $this->courses->gradeBands((int) $course['id']));
            }
            $status = $timedOut ? 'timed_out' : 'submitted';
            $this->assessments->completeSession((int) $session['id'], $status, $calculated, (string) $band['grade_code'], (bool) $band['is_passing']);
            if ((string) ($session['assessment_type'] ?? '') === 'diagnostic'
                && (bool) $band['is_passing']
                && (string) ($session['diagnostic_pass_action'] ?? 'guidance_only') === 'complete_course') {
                $beforeCompletion = $this->courses->enrolmentByIdForUser((int) $session['enrolment_id'], (int) $session['user_id']);
                $this->courses->completeEnrolmentFromDiagnostic((int) $session['enrolment_id']);
                if ((string) ($beforeCompletion['status'] ?? '') !== 'completed') {
                    $this->audit->record((int) $session['user_id'], 'course.completed', [
                        'course_id' => (int) $session['course_id'],
                        'enrolment_id' => (int) $session['enrolment_id'],
                        'completion_method' => 'diagnostic',
                        'percentage' => (float) $calculated['percentage'],
                        'status' => 'completed',
                    ]);
                }
            }
            return $calculated + [
                'grade_code' => $band['grade_code'],
                'grade_label' => $band['grade_label'],
                'passed' => $band['is_passing'],
                'status' => $status,
            ];
        });

        $session = $this->requireSession((int) $session['user_id'], (string) $session['public_id']);
        if ((string) $session['attempt_mode'] === 'graded' && empty($session['legacy_attempt_id'])) {
            $responses = [];
            foreach ($this->assessments->sessionResponses((int) $session['id']) as $response) {
                if ($response['selected_option_id'] === null || $response['selected_option_id'] === '') {
                    continue;
                }
                $responses[] = [
                    'question_id' => (int) $response['question_id'],
                    'selected_option_id' => (int) $response['selected_option_id'],
                    'is_correct' => (bool) $response['is_correct'],
                    'points_awarded' => (float) $response['points_awarded'],
                ];
            }
            $attemptId = $this->courses->saveAttempt(
                (int) $session['enrolment_id'],
                (int) $session['assessment_id'],
                max(0.0, (float) $result['earned_points']),
                max(1.0, (float) $result['maximum_points']),
                (float) $result['percentage'],
                (string) $result['grade_code'],
                (bool) $result['passed'],
                $responses
            );
            $this->assessments->attachLegacyAttempt((int) $session['id'], $attemptId);
            $this->applyScorePolicy($session);
        }
        $this->audit->record((int) $session['user_id'], 'assessment.completed', [
            'assessment_id' => (int) $session['assessment_id'],
            'session_id' => (int) $session['id'],
