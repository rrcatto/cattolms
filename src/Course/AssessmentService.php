    /** @return array<string,mixed> */
    private function requireSession(int $userId, string $publicId): array
    {
        if (preg_match('/^[0-9a-f-]{36}$/i', $publicId) !== 1) {
            throw new InvalidArgumentException('Invalid assessment session.');
        }
        $session = $this->assessments->sessionByPublicId($publicId);
        if ($session === null || (int) $session['user_id'] !== $userId) {
