            'percentage' => $result['percentage'],
            'status' => $result['status'],
            'preview' => (bool) $session['is_preview'],
        ]);
        return $this->result((int) $session['user_id'], (string) $session['public_id']);
    }

    /** @param array<string,mixed> $session */
    private function applyScorePolicy(array $session): void
    {
        $percentages = $this->assessments->completedPercentages((int) $session['enrolment_id'], (int) $session['assessment_id']);
        $value = $this->aggregate($percentages, (string) $session['score_policy']);
        $band = $this->band($value, $this->courses->gradeBands((int) $session['course_id']));
        if ((string) $session['assessment_type'] === 'module' && $session['module_id'] !== null) {
            $this->courses->setModuleResult((int) $session['enrolment_id'], (int) $session['module_id'], $value, (string) $band['grade_code']);
            return;
        }
        if ((string) $session['assessment_type'] === 'final') {
            $this->completeCourseIfPossible($session, $value);
        }
    }

    /** @param array<string,mixed> $session */
    private function completeCourseIfPossible(array $session, float $finalPercentage): void
    {
        $course = $this->courses->findById((int) $session['course_id']);
        if ($course === null) {
            return;
        }
        $moduleValues = [];
        foreach ($this->courses->modules((int) $course['id']) as $module) {
            if (!(bool) ($module['assessment_required'] ?? true)) {
                continue;
            }
            $assessment = $this->courses->assessmentForModule((int) $module['id']);
            if ($assessment === null) {
                continue;
            }
            $scores = $this->assessments->completedPercentages((int) $session['enrolment_id'], (int) $assessment['id']);
            if ($scores === []) {
                return;
            }
            $moduleValues[] = $this->aggregate($scores, (string) ($assessment['score_policy'] ?? 'highest'));
        }
        if ($moduleValues === []) {
            return;
        }
        $modulePercentage = array_sum($moduleValues) / count($moduleValues);
        $overall = round(
            $modulePercentage * (float) $course['module_weight']
            + $finalPercentage * (float) $course['final_weight'],
            2
        );
        $band = $this->band($overall, $this->courses->gradeBands((int) $course['id']));
        $beforeCompletion = $this->courses->enrolmentByIdForUser((int) $session['enrolment_id'], (int) $session['user_id']);
        $this->courses->saveCourseResult(
            (int) $session['enrolment_id'],
            $modulePercentage,
            $finalPercentage,
            $overall,
            (string) $band['grade_code'],
            (bool) $band['is_passing']
        );
        if ((string) ($beforeCompletion['status'] ?? '') !== 'completed') {
            $this->audit->record((int) $session['user_id'], 'course.completed', [
                'course_id' => (int) $course['id'],
                'enrolment_id' => (int) $session['enrolment_id'],
                'completion_method' => 'final_assessment',
                'percentage' => $overall,
                'grade_code' => (string) $band['grade_code'],
                'passed' => (bool) $band['is_passing'],
                'status' => 'completed',
            ]);
        }
        if ((bool) $course['certificate_enabled'] && (bool) $band['is_passing']) {
            $user = $this->courses->findUserById((int) $session['user_id']);
            $name = trim((string) ($user['certificate_name'] ?? $user['display_name'] ?? $user['email'] ?? 'Learner'));
            $certificateBefore = $this->courses->certificateForEnrolment((int) $session['enrolment_id']);
            $this->courses->createCertificate(
                (int) $session['enrolment_id'],
                $name,
                trim((string) ($course['certificate_title'] ?? '')) ?: 'Certificate of Completion',
                (string) $course['title'],
                (string) $band['grade_code'],
                $overall,
                (string) ($course['certificate_template'] ?? 'custom'),
                (string) ($course['certificate_body_text'] ?? 'has successfully completed'),
                (string) ($course['certificate_footer_text'] ?? ''),
                (string) ($course['certificate_signatory_name'] ?? ''),
                (string) ($course['certificate_signatory_title'] ?? ''),
                (string) ($course['certificate_template_html'] ?? ''),
                (string) ($course['certificate_template_css'] ?? '')
            );
            if ($certificateBefore === null) {
                $this->audit->record((int) $session['user_id'], 'certificate.issued', [
                    'course_id' => (int) $course['id'],
                    'enrolment_id' => (int) $session['enrolment_id'],
                    'percentage' => $overall,
                    'grade_code' => (string) $band['grade_code'],
                    'status' => 'issued',
                ]);
            }
        }
    }

    /** @return array{0:array<string,mixed>,1:array<string,mixed>} */
    private function courseAndEnrolment(int $userId, string $slug, bool $preview): array
    {
