        ['grade_code' => 'B', 'grade_label' => 'Second Class (B)', 'minimum_percentage' => 60, 'is_passing' => true],
        ['grade_code' => 'C', 'grade_label' => 'Third (C)', 'minimum_percentage' => 50, 'is_passing' => true],
        ['grade_code' => 'Fail', 'grade_label' => 'Fail', 'minimum_percentage' => 0, 'is_passing' => false],
    ];

    /**
     * Read the grading scale from the file: the shown scale list first, the grading script otherwise.
     * @return array{bands:list<array<string,mixed>>,source:string,function_agrees:?bool}
     */
    private function gradeScale(DOMXPath $xpath, string $html): array
    {
        $listed = [];
        foreach ($xpath->query('//ul[contains(concat(" ", normalize-space(@class), " "), " scale-list ")][1]/li') as $item) {
            if (!$item instanceof DOMElement) { continue; }
            $label = ''; $minimum = null;
            foreach ($item->childNodes as $child) {
                $text = trim((string) preg_replace('/\s+/u', ' ', (string) $child->textContent));
                if ($text === '') { continue; }
                if ($minimum === null && preg_match('/^(\d+(?:\.\d+)?)\s*[-–—]\s*\d+(?:\.\d+)?\s*%$/u', $text, $range) === 1) { $minimum = (float) $range[1]; }
                elseif ($label === '') { $label = $text; }
            }
            if ($label !== '' && $minimum !== null) { $listed[] = ['label' => $label, 'minimum' => $minimum]; }
        }
        $scripted = $this->scriptedGradeScale($html);
        $codes = [];
        foreach ($scripted as $band) { if ($band['code'] !== null) { $codes[mb_strtolower($band['label'])] = $band['code']; } }
        $chosen = $listed !== [] ? $listed : $scripted;
        $source = $listed !== [] ? 'list' : ($scripted !== [] ? 'function' : 'default');
        if ($chosen === [] || !in_array(0.0, array_map(static fn(array $band): float => (float) $band['minimum'], $chosen), true)) {
            return ['bands' => self::DEFAULT_GRADE_BANDS, 'source' => 'default', 'function_agrees' => null];
        }
        $bands = [];
        foreach ($chosen as $band) {
            $label = mb_substr((string) $band['label'], 0, 120);
            $code = $codes[mb_strtolower($label)] ?? (preg_match('/\(([^()]{1,24})\)\s*$/u', $label, $match) === 1 ? $match[1] : mb_substr($label, 0, 24));
            $bands[] = ['grade_code' => $code, 'grade_label' => $label, 'minimum_percentage' => (float) $band['minimum'], 'is_passing' => preg_match('/\bfail/iu', $label) !== 1];
        }
        usort($bands, static fn(array $a, array $b): int => $b['minimum_percentage'] <=> $a['minimum_percentage']);
        $agrees = null;
        if ($listed !== [] && $scripted !== []) {
            $shape = static fn(array $rows): array => array_map(static fn(array $row): string => mb_strtolower((string) $row['label']) . '@' . (float) $row['minimum'], $rows);
            $left = $shape($listed); $right = $shape($scripted); sort($left); sort($right);
            $agrees = $left === $right;
        }
        return ['bands' => $bands, 'source' => $source, 'function_agrees' => $agrees];
    }

    /**
     * The grading function of a standalone course, e.g. bandFor(pct) or gradeBand(p):
     * a run of "if (x >= N) return <label>" followed by a final return for 0%.
     * @return list<array{label:string,code:?string,minimum:float}>
     */
    private function scriptedGradeScale(string $html): array
    {
        if (preg_match('/function\s+(?:bandFor|gradeBand)\s*\([^)]*\)\s*\{/u', $html, $start, PREG_OFFSET_CAPTURE) !== 1) { return []; }
        $body = substr($html, $start[0][1] + strlen($start[0][0]), 1500);
        $returned = '(?:\{\s*label\s*:\s*[\'"]([^\'"]+)[\'"](?:\s*,\s*code\s*:\s*[\'"]([^\'"]+)[\'"])?|\[\s*[\'"]([^\'"]+)[\'"])';
        $bands = []; $end = 0;
        preg_match_all('/>=\s*(\d+(?:\.\d+)?)\s*\)\s*return\s*' . $returned . '/u', $body, $conditions, PREG_SET_ORDER | PREG_OFFSET_CAPTURE);
        foreach ($conditions as $condition) {
            $label = ($condition[2][0] ?? '') !== '' ? $condition[2][0] : (string) ($condition[4][0] ?? '');
            $bands[] = ['label' => $label, 'code' => ($condition[3][0] ?? '') !== '' ? $condition[3][0] : null, 'minimum' => (float) $condition[1][0]];
            $end = $condition[0][1] + strlen($condition[0][0]);
        }
        // The first return after the last condition is the band for everything below it.
        if ($bands !== [] && preg_match('/\breturn\s*' . $returned . '/u', substr($body, $end), $last) === 1) {
            $bands[] = ['label' => $last[1] !== '' ? $last[1] : $last[3], 'code' => $last[2] !== '' ? $last[2] : null, 'minimum' => 0.0];
        }
        return $bands;
    }

    /** The words of the file's course description panel, without its <summary>, or null when it has none. */
    private function courseDescription(DOMXPath $xpath): ?string
    {
        $panel = $xpath->query('//details[contains(concat(" ", normalize-space(@class), " "), " course-description ")][1]')->item(0);
        if (!$panel instanceof DOMElement) { return null; }
        $html = '';
        foreach ($panel->childNodes as $child) {
            if ($child instanceof DOMElement && strtolower($child->tagName) === 'summary') { continue; }
            $html .= $child instanceof DOMElement ? CourseHtml::html($child) : htmlspecialchars((string) $child->textContent, ENT_NOQUOTES | ENT_SUBSTITUTE, 'UTF-8');
        }
        $html = trim($html);
        return $html === '' ? null : $this->courseHtml->preserve($html);
    }

    /** How long the final assessment allows, in minutes in the file's head (specification 6.4), or two hours. */
    private function finalTimeLimit(DOMXPath $xpath): int
    {
        $nodes = $xpath->query('//meta[@name="cattolms:final-time-limit"]/@content');
        $minutes = $nodes->length > 0 ? (int) $nodes->item(0)?->nodeValue : 0;
        return $minutes >= 1 && $minutes <= 1440 ? $minutes * 60 : 7200;
    }

    /**
     * The parts the file names (specification 6.6): <meta name="cattolms:part-names" content="module-1=module-3 …">, the
     * name a part's place gives it and the part's own name. Anything that is not a pair of part names is left out.
     *
     * @return array<string,string>
     */
    private function partNames(DOMXPath $xpath): array
    {
        $nodes = $xpath->query('//meta[@name="cattolms:part-names"]/@content');
        $names = [];
        foreach (preg_split('/\s+/', trim($nodes->length > 0 ? (string) $nodes->item(0)?->nodeValue : '')) ?: [] as $pair) {
            if (preg_match('#^(' . CoursePartAddress::REQUIREMENT . ')=(' . CoursePartAddress::REQUIREMENT . ')$#', $pair, $part) === 1) { $names[$part[1]] = $part[2]; }
        }
        return $names;
    }

    /**
     * The whole course's study time in minutes, or null: the page adds up its parts. A full course states it in hours
     * (cattolms:study-hours, specification 6.5), a short course in minutes (cattolms:study-minutes, section 15.1).
     */
    private function studyMinutes(DOMXPath $xpath, bool $short = false): ?int
    {
        if ($short) {
            $minutes = self::metaNumber($xpath, 'cattolms:study-minutes');
            return $minutes >= 1 && $minutes <= 10000 ? $minutes : null;
        }
        $hours = self::metaNumber($xpath, 'cattolms:study-hours');
        return $hours >= 1 && $hours <= 10000 ? $hours * 60 : null;
    }

    /** A head meta's content as a whole number, or 0 when it is missing. */
    private static function metaNumber(DOMXPath $xpath, string $name): int
    {
        $nodes = $xpath->query('//meta[@name="' . $name . '"]/@content');
        return $nodes->length > 0 ? (int) trim((string) $nodes->item(0)?->nodeValue) : 0;
    }

    /** Whether the head carries this meta at all. */
    private static function hasMeta(DOMXPath $xpath, string $name): bool
    {
        $nodes = $xpath->query('//meta[@name="' . $name . '"]');
        return $nodes->length > 0;
    }

    /**
     * The course's type from its head (Course Specification 4.13, section 15.1): 'short' for a short course; a file without
     * the line, or with "full", is a full course.
     *
     * @param list<string> $warnings
     */
    private function courseType(DOMXPath $xpath, array &$warnings): string
    {
        $nodes = $xpath->query('//meta[@name="cattolms:course-type"]/@content');
        $type = $nodes->length > 0 ? strtolower(trim((string) $nodes->item(0)?->nodeValue)) : 'full';
        if (in_array($type, ['full', 'short'], true)) return $type;
        $warnings[] = 'The course type "' . mb_substr($type, 0, 20) . '" is neither short nor full, so it was imported as a full course (specification, section 15.1).';
        return 'full';
    }

    /**
     * What a short course's file has that a short course does not (Course Specification 4.13, section 15.7), each a warning:
     * a second module, a module 0, a readiness check, QUIZ keys other than m1, study-hours beside study-minutes, a final time
     * limit, minutes outside 60 to 120 and a missing course preview. The review and the grading wording are checked where
     * they are read; practical work with one block and not the other, as for every module, by partDrift.
     *
     * @param list<array<string,mixed>> $modules
     * @param array<mixed> $quiz
     * @param array<mixed> $presentations
     * @return list<string>
     */
    private function shortCourseDrift(DOMXPath $xpath, array $modules, array $quiz, array $presentations): array
    {
        $warnings = [];
        $keys = array_map(static fn(array $module): string => (string) $module['module_key'], array_values(array_filter($modules, static fn(array $module): bool => !$module['is_review'])));
        if (count($keys) > 1) $warnings[] = 'A short course has one module, mod-m1. This file has ' . count($keys) . ': ' . implode(', ', array_map(static fn(string $key): string => 'mod-' . $key, $keys)) . ' (specification, section 15.2).';
        if (in_array('m0', $keys, true)) $warnings[] = 'A short course has no module 0 (specification, section 15.2).';
        if ($keys !== [] && $keys[0] !== 'm1' && $keys[0] !== 'm0') $warnings[] = 'A short course\'s module is mod-m1, key m1. This file\'s is mod-' . $keys[0] . ' (specification, section 15.2).';
        $readinessKeys = array_values(array_intersect(array_map('strval', array_keys($quiz)), ['diag', 'diagnostic', 'prereq', 'prerequisite', 'readiness']));
        $readinessPanel = $xpath->query('//*[@id="diagnostic" or contains(concat(" ", normalize-space(@class), " "), " diag ")]');
        if ($readinessKeys !== [] || $readinessPanel->length > 0) $warnings[] = 'A short course has no readiness check, so it was left out (specification, section 15.2).';
        $others = array_values(array_diff(array_map('strval', array_keys($quiz)), ['m1'], $readinessKeys));
        if ($others !== []) $warnings[] = 'A short course\'s QUIZ holds m1 only (specification, section 15.5). It also has ' . implode(', ', array_map(static fn(string $key): string => 'QUIZ.' . $key, $others)) . (in_array('final', $others, true) ? ': a short course has no final assessment, so its module\'s assessment makes the whole mark and the rest was left out.' : ', which was left out.');
        if (self::hasMeta($xpath, 'cattolms:study-hours')) $warnings[] = 'A short course states its time in cattolms:study-minutes and never also has cattolms:study-hours (specification, section 15.1). The minutes were used.';
        if (self::hasMeta($xpath, 'cattolms:final-time-limit')) $warnings[] = 'A short course has no final assessment, so it has no cattolms:final-time-limit (specification, section 15.2).';
        $minutes = self::metaNumber($xpath, 'cattolms:study-minutes');
        if (!self::hasMeta($xpath, 'cattolms:study-minutes')) $warnings[] = 'A short course states how long it takes in cattolms:study-minutes, 60 to 120 (specification, section 15.1).';
        elseif ($minutes < 60 || $minutes > 120) $warnings[] = 'cattolms:study-minutes says ' . $minutes . ' minutes. A short course takes 60 to 120 (specification, section 15.1).';
        if (!is_array($presentations['trailer'] ?? null)) $warnings[] = 'A short course must have a course preview, PRESENTATIONS.trailer, with 5 to 8 slides ending on a call to action (specification, section 15.4).';
        return $warnings;
    }

    /**
     * The section of files the course names (specification 6.3): a file holds no PDF or spreadsheet, only their names.
     *
     * @return array{title:string,introduction_html:string,files:list<array{filename:string,title:string,description:string}>}|null
     */
    private function courseFiles(DOMXPath $xpath): ?array
    {
        $panel = $xpath->query('//details[contains(concat(" ", normalize-space(@class), " "), " course-files ")][1]')->item(0);
        if (!$panel instanceof DOMElement) { return null; }
        $title = '';
        $introduction = '';
        $files = [];
        foreach ($panel->childNodes as $child) {
            if (!$child instanceof DOMElement) { continue; }
            $tag = strtolower($child->tagName);
            if ($tag === 'summary') { $title = trim((string) $child->textContent); continue; }
            if ($tag === 'p') { $introduction .= CourseHtml::html($child); continue; }
            if ($tag !== 'ul' && $tag !== 'ol') { continue; }
            foreach ($child->getElementsByTagName('li') as $row) {
                $link = $row->getElementsByTagName('a')->item(0);
                if (!$link instanceof DOMElement) { continue; }
                $name = trim((string) $link->textContent);
                $files[] = [
                    'filename' => basename(rawurldecode($link->getAttribute('href'))), 'title' => $name,
                    'description' => trim((string) preg_replace('/\s+/u', ' ', str_replace($name, '', (string) $row->textContent))),
                ];
            }
        }
        return $files === [] ? null : ['title' => $title !== '' ? $title : 'Course files', 'introduction_html' => $this->courseHtml->preserve($introduction), 'files' => $files];
    }

    /** A section the importer takes in its own right: a module, the review, the final assessment or the readiness check. */
    private static function importedElsewhere(DOMElement $node): bool
    {
        $class = ' ' . (string) preg_replace('/\s+/', ' ', (string) $node->getAttribute('class')) . ' ';
        foreach (['module', 'review', 'final', 'diag', 'course-preview', 'course-description', 'course-files'] as $name) { if (str_contains($class, ' ' . $name . ' ')) return true; }
        $id = (string) $node->getAttribute('id');
        return in_array($id, ['diagnostic', 'final', 'mod-review'], true) || str_starts_with($id, 'mod-');
    }

    /**
     * Parts of a standalone course that only worked with its own script, removed on the owner's
     * instruction (2026/09/25): the static scale list (replaced by the [grading-scale] placeholder),
     * the reset-progress button and sentences saying progress is kept in the browser.
     * @return array{0:string,1:array{placeholder_inserted:bool,reset_button_removed:bool,storage_sentences_removed:int}}
     */
    private function withoutStandaloneParts(string $html, bool $replaceScale): array
    {
        $placeholders = 0; $buttons = 0; $sentences = 0;
        if ($replaceScale) {
            $html = (string) preg_replace('/<ul\b[^>]*class="[^"]*\bscale-list\b[^"]*"[^>]*>.*?<\/ul>/su', GradeScale::PLACEHOLDER, $html, 1, $placeholders);
        }
        $html = (string) preg_replace('/\s*<button\b[^>]*\bid="resetBtn"[^>]*>.*?<\/button>/su', '', $html, -1, $buttons);
        $html = (string) preg_replace('/\s*(?:Your )?[Pp]rogress is (?:saved|stored)(?: only)? in (?:this|your) browser\b[^.<]*\./u', '', $html, -1, $sentences);
        return [$html, ['placeholder_inserted' => $placeholders > 0, 'reset_button_removed' => $buttons > 0, 'storage_sentences_removed' => $sentences]];
    }

    private function booleanDataAttribute(DOMElement $element, string $attribute, bool $default): bool
    {
        if (!$element->hasAttribute($attribute)) {
            return $default;
        }
        $value = strtolower(trim((string) $element->getAttribute($attribute)));
        if ($value === '') {
            return true;
        }
        return !in_array($value, ['0', 'false', 'no', 'off'], true);
    }

    /** @param array<string,mixed> $reviewData */
    private function buildReviewHtml(array $reviewData): string
    {
        $html = '<div class="review-grid">';
        foreach ($reviewData as $moduleKey => $entry) {
            if (!is_array($entry)) {
                continue;
            }
            $title = trim((string) ($entry['t'] ?? $moduleKey));
            $points = is_array($entry['pts'] ?? null) ? $entry['pts'] : [];
            if ($points === []) {
                continue;
            }
            $html .= '<div class="review-card">';
            $html .= '<h3>' . htmlspecialchars($title, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8') . '</h3><ul>';
            foreach ($points as $point) {
                $html .= '<li>' . $this->courseHtml->preserve((string) $point) . '</li>';
            }
            $html .= '</ul></div>';
        }
        $html .= '</div>';
        return $this->courseHtml->preserve($html);
    }

    /** @return list<array<string,mixed>> */
    private function convertQuestions(mixed $rawQuestions, bool $diagnostic = false): array
    {
        if (!is_array($rawQuestions)) {
            return [];
        }
        $questions = [];
        foreach ($rawQuestions as $raw) {
            if (!is_array($raw) || !isset($raw['q'], $raw['o'], $raw['a'])) {
                continue;
            }
            $options = [];
            $answer = (int) $raw['a'];
            foreach ((array) $raw['o'] as $index => $text) {
                $options[] = [
                    'option_html' => $this->courseHtml->preserve((string) $text),
                    'is_correct' => (int) $index === $answer,
                ];
            }
            if ($options === [] || $answer < 0 || $answer >= count($options)) {
                continue;
            }
            $points = max(1, (int) ($raw['p'] ?? 1));
            $questions[] = [
                'question_html' => $this->courseHtml->preserve((string) $raw['q']),
                'points' => $points,
                'difficulty' => match (true) {
                    $points >= 3 => 'advanced',
                    $points === 2 => 'standard',
                    default => 'introductory',
                },
                'practice_eligible' => true,
                'graded_eligible' => !$diagnostic,
                'remediation_item_keys' => $this->remediationKeys($raw['u'] ?? []),
                'incorrect_points' => 0,
                'explanation_html' => $this->courseHtml->preserve((string) ($raw['e'] ?? '')),
                'options' => $options,
            ];
        }
        return $questions;
    }

    /**
     * @param list<array<string,mixed>> $questions
     * @return array<string,mixed>
     */
    private function diagnosticAssessment(
        string $key,
        array $questions,
        string $html,
        DOMXPath $xpath,
        int $position
    ): array {
        $normalisedKey = strtolower($key);
        $title = $this->diagnosticTitle($xpath, $normalisedKey);
        $passMark = $this->diagnosticPassMark($html, $normalisedKey, count($questions));
        $isPrerequisite = in_array($normalisedKey, ['prereq', 'prerequisite', 'readiness'], true);
        $passAction = $this->diagnosticPassAction($html, $normalisedKey);
        $instructions = $isPrerequisite
            ? '<p>This optional readiness check covers knowledge the course assumes. It does not affect your course grade or progress.</p>'
            : '<p>This optional diagnostic identifies whether you already have the skills covered by this course and which modules deserve revision. It does not affect your course grade or progress.</p>';
        $passHtml = $isPrerequisite
            ? '<p><strong>You are ready to begin.</strong> Your result meets the suggested readiness threshold. Review any incorrect answers before continuing if useful.</p>'
            : ($passAction === 'complete_course'
                ? '<p><strong>Diagnostic passed.</strong> This course is designed to be skipped when you meet the diagnostic threshold, so your enrolment has been recorded as completed. Any weaker areas are still listed below for optional review.</p>'
                : '<p><strong>Your diagnostic result meets the suggested threshold.</strong> You may continue according to the guidance for this course; any weaker areas are listed below.</p>');
        $failHtml = $isPrerequisite
            ? '<p><strong>Some assumed knowledge needs revision.</strong> Review the explanations for incorrect answers before continuing. This result does not prevent you from starting the course.</p>'
            : '<p><strong>Some areas would benefit from revision.</strong> The modules linked to incorrect answers are listed below. This result does not affect your grade.</p>';

        return [
            'assessment_type' => 'diagnostic',
            'assessment_key' => $normalisedKey,
            'position' => $position,
            'title' => $title,
            'instructions_html' => $instructions,
            'pass_mark' => $passMark,
            'required' => false,
            'result_pass_html' => $passHtml,
            'result_fail_html' => $failHtml,
            'is_visible' => true,
            'practice_enabled' => true,
            'practice_pool_mode' => 'both',
            'practice_question_count' => count($questions),
            'graded_question_count' => count($questions),
            'maximum_attempts' => null,
            'time_limit_seconds' => 3600,
            'score_policy' => 'latest',
            'randomise_questions' => false,
            'randomise_options' => false,
            'negative_marking' => false,
            'difficulty_selection' => [],
            'questions' => $questions,
        ];
    }

    private function diagnosticTitle(DOMXPath $xpath, string $key): string
    {
        $node = $xpath->query('//*[@data-quiz="' . $key . '"][1]')->item(0);
        if ($node instanceof DOMNode) {
            $section = $xpath->query('ancestor::*[contains(concat(" ", normalize-space(@class), " "), " diag ")][1]', $node)->item(0);
            if ($section instanceof DOMNode) {
                $title = $this->relativeText($xpath, $section, './/*[contains(concat(" ", normalize-space(@class), " "), " m-name ")][1]');
                if ($title !== '') {
                    return $title;
                }
            }
            $heading = $xpath->query('preceding::h4[1]', $node)->item(0);
            if ($heading instanceof DOMNode) {
                $title = trim(preg_replace('/\s+/u', ' ', $heading->textContent) ?? $heading->textContent);
                $title = preg_replace('/^\d+\.\s*/', '', $title) ?? $title;
                if ($title !== '') {
                    return $title;
                }
            }
        }
        return in_array($key, ['prereq', 'prerequisite', 'readiness'], true)
            ? 'Course readiness check'
            : 'Course diagnostic assessment';
    }

    private function diagnosticPassAction(string $html, string $key): string
    {
        if (($key === 'diag' || $key === 'diagnostic')
            && preg_match('/skip\s+(?:this\s+)?course[^.]{0,160}recorded\s+pass|recorded\s+pass[^.]{0,160}skip\s+(?:this\s+)?course/is', $html) === 1) {
            return 'complete_course';
        }
        return 'guidance_only';
    }

    private function diagnosticPassMark(string $html, string $key, int $questionCount): float
    {
        if ($key === 'diag' || $key === 'diagnostic') {
            if (preg_match('/\bDIAG_PASS\s*=\s*(\d+(?:\.\d+)?)/i', $html, $match) === 1) {
                return max(0.0, min(100.0, (float) $match[1]));
            }
        }
        if (in_array($key, ['prereq', 'prerequisite', 'readiness'], true)
            && preg_match('/\bcorrect\s*>=\s*(\d+)/i', $html, $match) === 1
            && $questionCount > 0) {
            return round(((int) $match[1]) / $questionCount * 100, 2);
        }
        return 50.0;
    }

    /** @return list<string> */
    private function remediationKeys(mixed $raw): array
    {
        if (!is_array($raw)) {
            return [];
        }
        $keys = [];
        foreach ($raw as $value) {
            // Remediation must use explicit module keys (for example "m3").
            // Numeric references are deliberately ignored because inferring a
            // prefix (historically "u") creates silent dead mappings when a
            // course uses a different module-key convention.
            if (is_int($value) || ctype_digit((string) $value)) {
                continue;
            }
            $key = trim((string) $value);
            if ($key !== '') {
                $keys[] = $key;
            }
        }
        return array_values(array_unique($keys));
    }

    private function hasNumericRemediationReferences(mixed $rawQuestions): bool
    {
        if (!is_array($rawQuestions)) {
            return false;
        }
        foreach ($rawQuestions as $question) {
            if (!is_array($question) || !is_array($question['u'] ?? null)) {
                continue;
            }
            foreach ($question['u'] as $value) {
                if (is_int($value) || ctype_digit((string) $value)) {
                    return true;
                }
            }
        }
        return false;
    }

    /**
     * Extract and isolate the visual presentation rules from a legacy course.
     * Ordinary selectors retain the course wrapper scope as a presentation contract.
     * Owner-authored CSS and external stylesheet imports are trusted, not filtered.
     */
    public function presentationCss(string $html): string
    {
        $styleBlocks = [];
        // The rules a course file adds for its frame are the file's, not the course's.
        if (preg_match_all('~<style\\b(?![^>]*\\bdata-course-file\\b)[^>]*>(.*?)</style\\s*>~is', $html, $matches) !== false) {
            foreach ($matches[1] as $block) {
                $block = trim((string) $block);
                if ($block !== '') {
                    $styleBlocks[] = $block;
                }
            }
        }

        $imports = [];
        if (preg_match_all('~<link\\b[^>]*rel=["\\\']?stylesheet["\\\']?[^>]*>~is', $html, $links) !== false) {
            foreach ($links[0] as $tag) {
                if (preg_match('~\\bhref\\s*=\\s*(["\\\'])(.*?)\\1~is', (string) $tag, $hrefMatch) !== 1) {
                    continue;
                }
                $href = html_entity_decode(trim((string) $hrefMatch[2]), ENT_QUOTES | ENT_HTML5, 'UTF-8');
                $imports[] = '@import url("' . str_replace(['\\\\', '"'], ['\\\\\\\\', '\\"'], $href) . '");';
            }
        }

        $css = trim(implode("\n\n", $styleBlocks));
        if ($css === '') {
            return implode("\n", array_values(array_unique($imports)));
        }

        // Keep author-provided imports before scoped rules; treating an @import and the
        // following selector as one prelude would leave that selector unscoped.
        $css = preg_replace_callback(
            '~@import\s+(?:url\(\s*(?:"[^"]*"|\x27[^\x27]*\x27|[^)]*)\s*\)|"[^"]*"|\x27[^\x27]*\x27)[^;]*;~i',
            static function (array $match) use (&$imports): string {
                $imports[] = $match[0];
                return '';
            },
            $css
        ) ?? $css;
        $css = preg_replace('~/\\*.*?\\*/~s', '', $css) ?? $css;
        $scoped = trim($this->scopePresentationCss($css));
        $prefix = implode("\n", array_values(array_unique($imports)));
        $result = trim(($prefix !== '' ? $prefix . "\n" : '') . $scoped);
        return str_ireplace('</style', '<\/style', $result);
    }

    private function scopePresentationCss(string $css): string
    {
        return $this->scopeCssRange($css, '.cl-course-presentation');
    }

    private function scopeCssRange(string $css, string $scope): string
    {
        $length = strlen($css);
        $index = 0;
        $out = '';
        while ($index < $length) {
            $open = $this->nextCssBrace($css, $index);
            if ($open === null) {
                $out .= substr($css, $index);
                break;
            }

            $prelude = substr($css, $index, $open - $index);
            $close = $this->matchingCssBrace($css, $open);
            if ($close === null) {
                // Keep malformed trailing CSS inert rather than guessing where
                // its declarations finish.
                break;
            }
            $body = substr($css, $open + 1, $close - $open - 1);
            $trimmedPrelude = trim($prelude);

            if ($trimmedPrelude !== '' && str_starts_with($trimmedPrelude, '@')) {
                $name = strtolower((string) strtok(substr($trimmedPrelude, 1), " \t\r\n("));
                if (in_array($name, ['media', 'supports', 'container', 'layer'], true)) {
                    $out .= $prelude . '{' . $this->scopeCssRange($body, $scope) . '}';
                } else {
                    // @font-face / @keyframes / similar definition blocks do
                    // not contain selectors that should be course-prefixed.
                    $out .= $prelude . '{' . $body . '}';
                }
            } else {
                $leading = substr($prelude, 0, strlen($prelude) - strlen(ltrim($prelude)));
                $out .= $leading . $this->scopeSelectorList(trim($prelude), $scope) . '{' . $body . '}';
            }
            $index = $close + 1;
        }
        return $out;
    }

    private function nextCssBrace(string $css, int $offset): ?int
    {
        $length = strlen($css);
        $quote = null;
        $comment = false;
        for ($i = $offset; $i < $length; $i++) {
            $char = $css[$i];
            $next = $i + 1 < $length ? $css[$i + 1] : '';
            if ($comment) {
                if ($char === '*' && $next === '/') {
                    $comment = false;
                    $i++;
                }
                continue;
            }
            if ($quote !== null) {
                if ($char === '\\') {
                    $i++;
                } elseif ($char === $quote) {
                    $quote = null;
                }
                continue;
            }
            if ($char === '/' && $next === '*') {
                $comment = true;
                $i++;
                continue;
            }
            if ($char === '"' || $char === "'") {
                $quote = $char;
                continue;
            }
            if ($char === '{') {
                return $i;
            }
        }
        return null;
    }

    private function matchingCssBrace(string $css, int $open): ?int
    {
        $length = strlen($css);
        $depth = 1;
        $quote = null;
        $comment = false;
        for ($i = $open + 1; $i < $length; $i++) {
            $char = $css[$i];
            $next = $i + 1 < $length ? $css[$i + 1] : '';
            if ($comment) {
                if ($char === '*' && $next === '/') {
                    $comment = false;
                    $i++;
                }
                continue;
            }
            if ($quote !== null) {
                if ($char === '\\') {
                    $i++;
                } elseif ($char === $quote) {
                    $quote = null;
                }
                continue;
            }
            if ($char === '/' && $next === '*') {
                $comment = true;
                $i++;
                continue;
            }
            if ($char === '"' || $char === "'") {
                $quote = $char;
                continue;
            }
            if ($char === '{') {
                $depth++;
            } elseif ($char === '}') {
                $depth--;
                if ($depth === 0) {
                    return $i;
                }
            }
        }
        return null;
    }

    private function scopeSelectorList(string $selectors, string $scope): string
    {
        if ($selectors === '') {
            return '';
        }
        $parts = [];
        $current = '';
        $paren = 0;
        $bracket = 0;
        $quote = null;
        $length = strlen($selectors);
        for ($i = 0; $i < $length; $i++) {
            $char = $selectors[$i];
            if ($quote !== null) {
                $current .= $char;
                if ($char === '\\' && $i + 1 < $length) {
                    $current .= $selectors[++$i];
                } elseif ($char === $quote) {
                    $quote = null;
                }
                continue;
            }
            if ($char === '"' || $char === "'") {
                $quote = $char;
                $current .= $char;
                continue;
            }
            if ($char === '(') { $paren++; }
            if ($char === ')' && $paren > 0) { $paren--; }
            if ($char === '[') { $bracket++; }
            if ($char === ']' && $bracket > 0) { $bracket--; }
            if ($char === ',' && $paren === 0 && $bracket === 0) {
                $parts[] = $current;
                $current = '';
                continue;
            }
            $current .= $char;
        }
        $parts[] = $current;

        $scoped = [];
        foreach ($parts as $part) {
            $selector = trim($part);
            if ($selector === '') {
                continue;
            }
            if ($selector === '*') {
                $scoped[] = $scope;
                $scoped[] = $scope . ' *';
                continue;
            }
            if ($selector === ':root' || $selector === 'html' || $selector === 'body' || $selector === 'html body') {
                $scoped[] = $scope;
                continue;
            }
            if (preg_match('/^(?:html\\s+)?body(?=$|[\\s.#:\\[])/i', $selector) === 1) {
                $remainder = (string) preg_replace('/^(?:html\\s+)?body/i', '', $selector, 1);
                // The imported body element is not copied into the LMS reader. Preserve
                // body-qualified rules by applying them to the Core content boundary.
                $scoped[] = $remainder === '' || !str_starts_with($remainder, ' ')
                    ? $scope
                    : $scope . $remainder;
                continue;
            }
            if (preg_match('/^html(?=$|[\\s.#:\\[])/i', $selector) === 1) {
                $scoped[] = preg_replace('/^html/i', $scope, $selector, 1) ?? ($scope . ' ' . $selector);
                continue;
            }
            if (str_starts_with($selector, $scope)) {
                $scoped[] = $selector;
                continue;
            }
            $scoped[] = $scope . ' ' . $selector;
        }
        return implode(', ', array_values(array_unique($scoped)));
    }

    /**
     * Return a DOM-parsing copy of the source with raw-text script/style bodies
     * blanked out. Newline characters and tag boundaries are retained so libxml
     * warning line numbers still correspond to the uploaded source file.
     */
    private function htmlForDomParsing(string $html): string
    {
        $prepared = preg_replace_callback(
            '~(<(?:script|style)\b[^>]*>)(.*?)(</(?:script|style)\s*>)~is',
            static function (array $match): string {
                $body = (string) $match[2];
                $blanked = preg_replace('/[^\r\n]/', ' ', $body);
                return (string) $match[1]
                    . (is_string($blanked) ? $blanked : '')
                    . (string) $match[3];
            },
            $html
        );

        return is_string($prepared) ? $prepared : $html;
    }

    /**
     * @param list<\LibXMLError> $errors
     * @return array<string,mixed>
     */
    private function parserDiagnostics(array $errors): array
    {
        $compatibility = 0;
        $structural = 0;
        $messages = [];
        foreach ($errors as $error) {
            $message = trim((string) ($error->message ?? ''));
            if ($message === '') {
                continue;
            }
            if (preg_match('/^Tag [a-z0-9:_-]+ invalid$/i', $message) === 1) {
                $compatibility++;
                continue;
            }
            $structural++;
            $summary = preg_replace('/\s+/u', ' ', $message) ?? $message;
            if (!isset($messages[$summary])) {
                $messages[$summary] = [
                    'message' => $summary,
                    'count' => 0,
                    'first_line' => (int) ($error->line ?? 0),
                ];
            }
            $messages[$summary]['count']++;
        }
        usort($messages, static fn(array $a, array $b): int => $b['count'] <=> $a['count']);
        return [
            'compatibility_notice_count' => $compatibility,
            'structural_warning_count' => $structural,
            'messages' => $messages,
        ];
    }

    /** The code the file gives its course, tidied, or empty when it gives none (a review shows a suggestion). */
