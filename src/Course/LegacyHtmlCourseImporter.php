    private function extractJsonAssignment(string $source, string $variable): mixed
    {
        $needle = 'const ' . $variable;
        $start = strpos($source, $needle);
        if ($start === false) {
            return null;
        }
        $equals = strpos($source, '=', $start + strlen($needle));
        if ($equals === false) {
            return null;
        }
        $literalStart = $this->firstLiteralStart($source, $equals + 1);
        if ($literalStart === null) {
            return null;
        }

        [$literal, $endOffset] = $this->extractBalancedLiteral($source, $literalStart);
        $decoded = $this->decodeJavascriptDataLiteral($literal, $variable);
        if (!is_array($decoded)) {
            return $decoded;
        }

        // Some legacy courses initialise only part of the bank in `const QUIZ`
        // and append later units with assignments such as `QUIZ.u2=[...]`.
        // Merge those data-only assignments so the complete course imports.
        $pattern = '/\\b' . preg_quote($variable, '/') . '\\.([A-Za-z_$][A-Za-z0-9_$]*)\\s*=\\s*/';
        if (preg_match_all($pattern, $source, $matches, PREG_OFFSET_CAPTURE, $endOffset) !== false) {
            foreach ($matches[0] ?? [] as $matchIndex => $match) {
                $memberName = (string) (($matches[1][$matchIndex][0] ?? ''));
                $assignmentEnd = (int) $match[1] + strlen((string) $match[0]);
                $memberStart = $this->firstLiteralStart($source, $assignmentEnd);
                if ($memberName === '' || $memberStart === null) {
                    continue;
                }
                try {
                    [$memberLiteral] = $this->extractBalancedLiteral($source, $memberStart);
                    $decoded[$memberName] = $this->decodeJavascriptDataLiteral($memberLiteral, $variable . '.' . $memberName);
                } catch (InvalidArgumentException) {
                    // Ignore unrelated dynamic assignments. Supported question-bank
                    // members must be plain array/object data literals.
                }
            }
        }
        return $decoded;
    }

    private function firstLiteralStart(string $source, int $offset): ?int
    {
        $length = strlen($source);
        for ($index = max(0, $offset); $index < $length; $index++) {
            if (ctype_space($source[$index])) {
                continue;
            }
            return ($source[$index] === '{' || $source[$index] === '[') ? $index : null;
        }
        return null;
    }

    /** @return array{0:string,1:int} */
    private function extractBalancedLiteral(string $source, int $start): array
    {
        $opening = $source[$start] ?? '';
        if ($opening !== '{' && $opening !== '[') {
            throw new InvalidArgumentException('JavaScript data literal must begin with { or [.');
        }

        $stack = [$opening];
        $quote = null;
        $escaped = false;
        $length = strlen($source);
        $index = $start + 1;
        while ($index < $length) {
            $char = $source[$index];
            if ($quote !== null) {
                if ($escaped) {
                    $escaped = false;
                } elseif ($char === '\\') {
                    $escaped = true;
                } elseif ($char === $quote) {
                    $quote = null;
                }
                $index++;
                continue;
            }
            if ($char === '"' || $char === "'") {
                $quote = $char;
                $index++;
                continue;
            }
            if ($char === '/' && $index + 1 < $length && $source[$index + 1] === '*') {
                $endComment = strpos($source, '*/', $index + 2);
                if ($endComment === false) {
                    throw new InvalidArgumentException('Unterminated JavaScript block comment.');
                }
                $index = $endComment + 2;
                continue;
            }
            if ($char === '/' && $index + 1 < $length && $source[$index + 1] === '/') {
                $newline = strpos($source, "\n", $index + 2);
                $index = $newline === false ? $length : $newline + 1;
                continue;
            }
            if ($char === '{' || $char === '[') {
                $stack[] = $char;
            } elseif ($char === '}' || $char === ']') {
                $expected = $char === '}' ? '{' : '[';
                $actual = array_pop($stack);
                if ($actual !== $expected) {
                    throw new InvalidArgumentException('Mismatched brackets in JavaScript data literal.');
                }
                if ($stack === []) {
                    return [substr($source, $start, $index - $start + 1), $index + 1];
                }
            }
            $index++;
        }
        throw new InvalidArgumentException('Unterminated JavaScript data literal.');
    }

    private function decodeJavascriptDataLiteral(string $literal, string $label): mixed
    {
        try {
            return json_decode($literal, true, 512, JSON_THROW_ON_ERROR);
        } catch (\JsonException) {
            try {
                return json_decode($this->normaliseJavascriptObjectLiteral($literal), true, 512, JSON_THROW_ON_ERROR);
            } catch (\JsonException $exception) {
                throw new InvalidArgumentException(
                    'The ' . $label . ' question bank is not valid JSON or a supported JavaScript object literal.',
                    0,
                    $exception
                );
            }
        }
    }

    /**
     * Convert the restricted JavaScript object-literal syntax used by legacy
     * self-contained courses into strict JSON. This intentionally supports
     * data-only literals: comments, unquoted identifier keys, single-quoted
     * strings and trailing commas. It never executes JavaScript.
     */
    private function normaliseJavascriptObjectLiteral(string $literal): string
    {
        $out = '';
        $length = strlen($literal);
        $index = 0;

        while ($index < $length) {
            $char = $literal[$index];

            if ($char === '/' && $index + 1 < $length && $literal[$index + 1] === '*') {
                $end = strpos($literal, '*/', $index + 2);
                if ($end === false) {
                    throw new InvalidArgumentException('Unterminated block comment in JavaScript object literal.');
                }
                $index = $end + 2;
                continue;
            }
            if ($char === '/' && $index + 1 < $length && $literal[$index + 1] === '/') {
                $newline = strpos($literal, "\n", $index + 2);
                $index = $newline === false ? $length : $newline + 1;
                $out .= "\n";
                continue;
            }

            if ($char === '"' || $char === "'") {
                [$jsonString, $index] = $this->readJavascriptString($literal, $index);
                $out .= $jsonString;
                continue;
            }

            if (preg_match('/[A-Za-z_$]/', $char) === 1) {
                $start = $index;
                $index++;
                while ($index < $length && preg_match('/[A-Za-z0-9_$]/', $literal[$index]) === 1) {
                    $index++;
                }
                $identifier = substr($literal, $start, $index - $start);
                $lookahead = $index;
                while ($lookahead < $length && ctype_space($literal[$lookahead])) {
                    $lookahead++;
                }
                if ($lookahead < $length && $literal[$lookahead] === ':') {
                    $out .= json_encode($identifier, JSON_THROW_ON_ERROR);
                } else {
                    $out .= $identifier;
                }
                continue;
            }

            $out .= $char;
            $index++;
        }

        // JSON does not permit trailing commas. Only data literals are
        // supported here, so commas immediately before ] or } are safe to drop.
        $out = preg_replace('/,\s*([}\]])/', '$1', $out) ?? $out;
        return $out;
    }

    /** @return array{0:string,1:int} */
    private function readJavascriptString(string $source, int $start): array
    {
        $quote = $source[$start];
        $length = strlen($source);
        $value = '';
        $index = $start + 1;

        while ($index < $length) {
            $char = $source[$index];
            if ($char === $quote) {
                return [json_encode($value, JSON_THROW_ON_ERROR | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES), $index + 1];
            }
            if ($char !== '\\') {
                $value .= $char;
                $index++;
                continue;
            }

            if ($index + 1 >= $length) {
                throw new InvalidArgumentException('Unterminated escape sequence in JavaScript string.');
            }
            $escape = $source[$index + 1];
            $value .= match ($escape) {
                'n' => "\n",
                'r' => "\r",
                't' => "\t",
                'b' => "\b",
                'f' => "\f",
                'v' => "\v",
                '0' => "\0",
                '\\' => '\\',
                '"' => '"',
                "'" => "'",
                '/' => '/',
                default => '\\' . $escape,
            };
            $index += 2;
        }

        throw new InvalidArgumentException('Unterminated JavaScript string in object literal.');
    }
