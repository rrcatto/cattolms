    private function diagnosticTitle(DOMXPath $xpath, string $key): string
    {
        $node = $xpath->query('//*[@data-quiz="' . $key . '"][1]')->item(0);
        if ($node instanceof DOMNode) {
            $section = $xpath->query('ancestor::*[contains(concat(" ", normalize-space(@class), " "), " diag ")][1]', $node)->item(0);
            if ($section instanceof DOMNode) {
                $title = $this->relativeText($xpath, $section, './/*[contains(concat(" ", normalize-space(@class), " "), " m-name ")][1]');
                if ($title !== '') {
                    return $title;
                }
            }
            $heading = $xpath->query('preceding::h4[1]', $node)->item(0);
            if ($heading instanceof DOMNode) {
                $title = trim(preg_replace('/\s+/u', ' ', $heading->textContent) ?? $heading->textContent);
                $title = preg_replace('/^\d+\.\s*/', '', $title) ?? $title;
                if ($title !== '') {
                    return $title;
                }
            }
        }
        return in_array($key, ['prereq', 'prerequisite', 'readiness'], true)
            ? 'Course readiness check'
            : 'Course diagnostic assessment';
    }

    private function diagnosticPassAction(string $html, string $key): string
    {
        if (($key === 'diag' || $key === 'diagnostic')
            && preg_match('/skip\s+(?:this\s+)?course[^.]{0,160}recorded\s+pass|recorded\s+pass[^.]{0,160}skip\s+(?:this\s+)?course/is', $html) === 1) {
            return 'complete_course';
        }
        return 'guidance_only';
    }

    private function diagnosticPassMark(string $html, string $key, int $questionCount): float
    {
        if ($key === 'diag' || $key === 'diagnostic') {
            if (preg_match('/\bDIAG_PASS\s*=\s*(\d+(?:\.\d+)?)/i', $html, $match) === 1) {
                return max(0.0, min(100.0, (float) $match[1]));
            }
        }
        if (in_array($key, ['prereq', 'prerequisite', 'readiness'], true)
            && preg_match('/\bcorrect\s*>=\s*(\d+)/i', $html, $match) === 1
            && $questionCount > 0) {
            return round(((int) $match[1]) / $questionCount * 100, 2);
        }
        return 50.0;
    }

    /** @return list<string> */
    private function remediationKeys(mixed $raw): array
    {
        if (!is_array($raw)) {
            return [];
        }
        $keys = [];
        foreach ($raw as $value) {
            // Remediation must use explicit module keys (for example "m3").
            // Numeric references are deliberately ignored because inferring a
            // prefix (historically "u") creates silent dead mappings when a
            // course uses a different module-key convention.
            if (is_int($value) || ctype_digit((string) $value)) {
                continue;
            }
            $key = trim((string) $value);
            if ($key !== '') {
                $keys[] = $key;
            }
        }
        return array_values(array_unique($keys));
    }

    private function hasNumericRemediationReferences(mixed $rawQuestions): bool
    {
        if (!is_array($rawQuestions)) {
            return false;
        }
        foreach ($rawQuestions as $question) {
            if (!is_array($question) || !is_array($question['u'] ?? null)) {
                continue;
            }
            foreach ($question['u'] as $value) {
                if (is_int($value) || ctype_digit((string) $value)) {
                    return true;
                }
            }
        }
        return false;
    }

    /**
     * Extract and isolate the visual presentation rules from a legacy course.
     * The returned stylesheet is safe to render on an LMS course page because
     * ordinary selectors are scoped under .cl-course-presentation instead of
     * being allowed to restyle the LMS shell. Google Fonts stylesheets are the
     * only external stylesheets carried across; they provide font-face data but
     * do not contain the source course's layout rules.
     */
    public function presentationCss(string $html): string
    {
        $styleBlocks = [];
        if (preg_match_all('~<style\\b[^>]*>(.*?)</style\\s*>~is', $html, $matches) !== false) {
            foreach ($matches[1] as $block) {
                $block = trim((string) $block);
                if ($block !== '') {
                    $styleBlocks[] = $block;
                }
            }
        }

        $imports = [];
        if (preg_match_all('~<link\\b[^>]*rel=["\\\']?stylesheet["\\\']?[^>]*>~is', $html, $links) !== false) {
            foreach ($links[0] as $tag) {
                if (preg_match('~\\bhref\\s*=\\s*(["\\\'])(.*?)\\1~is', (string) $tag, $hrefMatch) !== 1) {
                    continue;
                }
                $href = html_entity_decode(trim((string) $hrefMatch[2]), ENT_QUOTES | ENT_HTML5, 'UTF-8');
                $parts = parse_url($href);
                if (($parts['scheme'] ?? '') !== 'https' || strtolower((string) ($parts['host'] ?? '')) !== 'fonts.googleapis.com') {
                    continue;
                }
                $imports[] = '@import url("' . str_replace(['\\\\', '"'], ['\\\\\\\\', '\\"'], $href) . '");';
            }
        }

        $css = trim(implode("\n\n", $styleBlocks));
        if ($css === '') {
            return implode("\n", array_values(array_unique($imports)));
        }

        // Source-authored @import rules are deliberately removed. External
        // CSS could otherwise escape course isolation. Approved Google Fonts
        // links are reintroduced from <link rel="stylesheet"> above.
        $css = preg_replace('~@import\\s+[^;]+;~i', '', $css) ?? $css;
        $css = preg_replace('~/\\*.*?\\*/~s', '', $css) ?? $css;
        $scoped = trim($this->scopePresentationCss($css));
        $prefix = implode("\n", array_values(array_unique($imports)));
        $result = trim(($prefix !== '' ? $prefix . "\n" : '') . $scoped);
        return str_ireplace('</style', '<\/style', $result);
    }

    private function scopePresentationCss(string $css): string
    {
        return $this->scopeCssRange($css, '.cl-course-presentation');
    }

    private function scopeCssRange(string $css, string $scope): string
    {
        $length = strlen($css);
        $index = 0;
        $out = '';
        while ($index < $length) {
            $open = $this->nextCssBrace($css, $index);
            if ($open === null) {
                $out .= substr($css, $index);
                break;
            }

            $prelude = substr($css, $index, $open - $index);
            $close = $this->matchingCssBrace($css, $open);
            if ($close === null) {
                // Keep malformed trailing CSS inert rather than guessing where
                // its declarations finish.
                break;
            }
            $body = substr($css, $open + 1, $close - $open - 1);
            $trimmedPrelude = trim($prelude);

            if ($trimmedPrelude !== '' && str_starts_with($trimmedPrelude, '@')) {
                $name = strtolower((string) strtok(substr($trimmedPrelude, 1), " \t\r\n("));
                if (in_array($name, ['media', 'supports', 'container', 'layer'], true)) {
                    $out .= $prelude . '{' . $this->scopeCssRange($body, $scope) . '}';
                } else {
                    // @font-face / @keyframes / similar definition blocks do
                    // not contain selectors that should be course-prefixed.
                    $out .= $prelude . '{' . $body . '}';
                }
            } else {
                $leading = substr($prelude, 0, strlen($prelude) - strlen(ltrim($prelude)));
                $out .= $leading . $this->scopeSelectorList(trim($prelude), $scope) . '{' . $body . '}';
            }
            $index = $close + 1;
        }
        return $out;
    }

    private function nextCssBrace(string $css, int $offset): ?int
    {
        $length = strlen($css);
        $quote = null;
        $comment = false;
        for ($i = $offset; $i < $length; $i++) {
            $char = $css[$i];
            $next = $i + 1 < $length ? $css[$i + 1] : '';
            if ($comment) {
                if ($char === '*' && $next === '/') {
                    $comment = false;
                    $i++;
                }
                continue;
            }
            if ($quote !== null) {
                if ($char === '\\') {
                    $i++;
                } elseif ($char === $quote) {
                    $quote = null;
                }
                continue;
            }
            if ($char === '/' && $next === '*') {
                $comment = true;
                $i++;
                continue;
            }
            if ($char === '"' || $char === "'") {
                $quote = $char;
                continue;
            }
            if ($char === '{') {
                return $i;
            }
        }
        return null;
    }

    private function matchingCssBrace(string $css, int $open): ?int
    {
        $length = strlen($css);
        $depth = 1;
        $quote = null;
        $comment = false;
        for ($i = $open + 1; $i < $length; $i++) {
            $char = $css[$i];
            $next = $i + 1 < $length ? $css[$i + 1] : '';
            if ($comment) {
                if ($char === '*' && $next === '/') {
                    $comment = false;
                    $i++;
                }
                continue;
            }
            if ($quote !== null) {
                if ($char === '\\') {
                    $i++;
                } elseif ($char === $quote) {
                    $quote = null;
                }
                continue;
            }
            if ($char === '/' && $next === '*') {
                $comment = true;
                $i++;
                continue;
            }
            if ($char === '"' || $char === "'") {
                $quote = $char;
                continue;
            }
            if ($char === '{') {
                $depth++;
            } elseif ($char === '}') {
                $depth--;
                if ($depth === 0) {
                    return $i;
                }
            }
        }
        return null;
    }

    private function scopeSelectorList(string $selectors, string $scope): string
    {
        if ($selectors === '') {
            return '';
        }
        $parts = [];
        $current = '';
        $paren = 0;
        $bracket = 0;
        $quote = null;
        $length = strlen($selectors);
        for ($i = 0; $i < $length; $i++) {
            $char = $selectors[$i];
            if ($quote !== null) {
                $current .= $char;
                if ($char === '\\' && $i + 1 < $length) {
                    $current .= $selectors[++$i];
                } elseif ($char === $quote) {
                    $quote = null;
                }
                continue;
            }
            if ($char === '"' || $char === "'") {
                $quote = $char;
                $current .= $char;
                continue;
            }
            if ($char === '(') { $paren++; }
            if ($char === ')' && $paren > 0) { $paren--; }
            if ($char === '[') { $bracket++; }
            if ($char === ']' && $bracket > 0) { $bracket--; }
            if ($char === ',' && $paren === 0 && $bracket === 0) {
                $parts[] = $current;
                $current = '';
                continue;
            }
            $current .= $char;
        }
        $parts[] = $current;

        $scoped = [];
        foreach ($parts as $part) {
            $selector = trim($part);
            if ($selector === '') {
                continue;
            }
            if ($selector === '*') {
                $scoped[] = $scope;
                $scoped[] = $scope . ' *';
                continue;
            }
            if ($selector === ':root' || $selector === 'html' || $selector === 'body' || $selector === 'html body') {
                $scoped[] = $scope;
                continue;
            }
            if (preg_match('/^(?:html\\s+)?body(?=$|[\\s.#:\\[])/i', $selector) === 1) {
                $scoped[] = preg_replace('/^(?:html\\s+)?body/i', $scope, $selector, 1) ?? ($scope . ' ' . $selector);
                continue;
            }
            if (preg_match('/^html(?=$|[\\s.#:\\[])/i', $selector) === 1) {
                $scoped[] = preg_replace('/^html/i', $scope, $selector, 1) ?? ($scope . ' ' . $selector);
                continue;
            }
            if (str_starts_with($selector, $scope)) {
                $scoped[] = $selector;
                continue;
            }
            $scoped[] = $scope . ' ' . $selector;
        }
        return implode(', ', array_values(array_unique($scoped)));
    }

    /**
     * Return a DOM-parsing copy of the source with raw-text script/style bodies
     * blanked out. Newline characters and tag boundaries are retained so libxml
     * warning line numbers still correspond to the uploaded source file.
     */
    private function htmlForDomParsing(string $html): string
    {
        $prepared = preg_replace_callback(
            '~(<(?:script|style)\b[^>]*>)(.*?)(</(?:script|style)\s*>)~is',
            static function (array $match): string {
                $body = (string) $match[2];
                $blanked = preg_replace('/[^\r\n]/', ' ', $body);
                return (string) $match[1]
                    . (is_string($blanked) ? $blanked : '')
                    . (string) $match[3];
            },
            $html
        );

        return is_string($prepared) ? $prepared : $html;
    }

    /**
     * @param list<\LibXMLError> $errors
     * @return array<string,mixed>
     */
    private function parserDiagnostics(array $errors): array
    {
        $compatibility = 0;
        $structural = 0;
        $messages = [];
        foreach ($errors as $error) {
            $message = trim((string) ($error->message ?? ''));
            if ($message === '') {
                continue;
            }
            if (preg_match('/^Tag [a-z0-9:_-]+ invalid$/i', $message) === 1) {
                $compatibility++;
                continue;
            }
            $structural++;
            $summary = preg_replace('/\s+/u', ' ', $message) ?? $message;
            if (!isset($messages[$summary])) {
                $messages[$summary] = [
                    'message' => $summary,
                    'count' => 0,
                    'first_line' => (int) ($error->line ?? 0),
                ];
            }
            $messages[$summary]['count']++;
        }
        usort($messages, static fn(array $a, array $b): int => $b['count'] <=> $a['count']);
        return [
            'compatibility_notice_count' => $compatibility,
            'structural_warning_count' => $structural,
            'messages' => $messages,
        ];
    }

    private function detectLevel(DOMXPath $xpath): string
    {
        $masthead = $xpath->query('//*[contains(concat(" ", normalize-space(@class), " "), " masthead ")][1]')->item(0);
        if (!$masthead instanceof DOMElement) {
            return '';
        }

        // New courses must state their level explicitly on the masthead. Do not
        // infer level from arbitrary teaching content: a course may legitimately
        // mention beginner/intermediate/advanced material without being that level.
        $explicit = trim(preg_replace('/\s+/u', ' ', $masthead->getAttribute('data-level')) ?? $masthead->getAttribute('data-level'));
        if ($explicit !== '') {
            $known = [
                'beginner' => 'Beginner',
                'intermediate' => 'Intermediate',
                'advanced' => 'Advanced',
            ];
            $key = mb_strtolower($explicit);
            return $known[$key] ?? $explicit;
        }

        // Compatibility fallback for older authored courses: inspect only the
        // masthead eyebrow, never the full document body.
        $eyebrow = $this->relativeText(
            $xpath,
            $masthead,
            './/*[contains(concat(" ", normalize-space(@class), " "), " eyebrow ")][1]'
        );
        foreach (['beginner' => 'Beginner', 'intermediate' => 'Intermediate', 'advanced' => 'Advanced'] as $needle => $label) {
            if (preg_match('/\b' . preg_quote($needle, '/') . '\b/ui', $eyebrow) === 1) {
                return $label;
            }
        }

        return '';
    }

    private function firstText(DOMXPath $xpath, string $query): string
    {
        $node = $xpath->query($query)->item(0);
        return $node instanceof DOMNode ? trim(preg_replace('/\s+/u', ' ', $node->textContent) ?? $node->textContent) : '';
    }

    private function relativeText(DOMXPath $xpath, DOMNode $context, string $query): string
    {
        $node = $xpath->query($query, $context)->item(0);
        return $node instanceof DOMNode ? trim(preg_replace('/\s+/u', ' ', $node->textContent) ?? $node->textContent) : '';
    }

    private function relativeElement(DOMXPath $xpath, DOMNode $context, string $query): ?DOMElement
    {
        $node = $xpath->query($query, $context)->item(0);
        return $node instanceof DOMElement ? $node : null;
    }

    private function innerHtml(DOMElement $element): string
    {
        $html = '';
        foreach ($element->childNodes as $child) {
            $html .= $element->ownerDocument?->saveHTML($child) ?? '';
        }
        return $html;
    }

    private function extractJsonAssignment(string $source, string $variable): mixed
    {
        $needle = 'const ' . $variable;
        $start = strpos($source, $needle);
        if ($start === false) {
            return null;
        }
        $equals = strpos($source, '=', $start + strlen($needle));
        if ($equals === false) {
            return null;
        }
        $literalStart = $this->firstLiteralStart($source, $equals + 1);
        if ($literalStart === null) {
            return null;
        }

        [$literal, $endOffset] = $this->extractBalancedLiteral($source, $literalStart);
        $decoded = $this->decodeJavascriptDataLiteral($literal, $variable);
        if (!is_array($decoded)) {
            return $decoded;
        }

        // Some legacy courses initialise only part of the bank in `const QUIZ`
        // and append later units with assignments such as `QUIZ.u2=[...]`.
        // Merge those data-only assignments so the complete course imports.
        $pattern = '/\\b' . preg_quote($variable, '/') . '\\.([A-Za-z_$][A-Za-z0-9_$]*)\\s*=\\s*/';
        if (preg_match_all($pattern, $source, $matches, PREG_OFFSET_CAPTURE, $endOffset) !== false) {
            foreach ($matches[0] ?? [] as $matchIndex => $match) {
                $memberName = (string) (($matches[1][$matchIndex][0] ?? ''));
                $assignmentEnd = (int) $match[1] + strlen((string) $match[0]);
                $memberStart = $this->firstLiteralStart($source, $assignmentEnd);
                if ($memberName === '' || $memberStart === null) {
                    continue;
                }
                try {
                    [$memberLiteral] = $this->extractBalancedLiteral($source, $memberStart);
                    $decoded[$memberName] = $this->decodeJavascriptDataLiteral($memberLiteral, $variable . '.' . $memberName);
                } catch (InvalidArgumentException) {
                    // Ignore unrelated dynamic assignments. Supported question-bank
                    // members must be plain array/object data literals.
                }
            }
        }
        return $decoded;
    }

    private function firstLiteralStart(string $source, int $offset): ?int
    {
        $length = strlen($source);
        for ($index = max(0, $offset); $index < $length; $index++) {
            if (ctype_space($source[$index])) {
                continue;
            }
            return ($source[$index] === '{' || $source[$index] === '[') ? $index : null;
        }
        return null;
    }

    /** @return array{0:string,1:int} */
    private function extractBalancedLiteral(string $source, int $start): array
    {
        $opening = $source[$start] ?? '';
        if ($opening !== '{' && $opening !== '[') {
            throw new InvalidArgumentException('JavaScript data literal must begin with { or [.');
        }

        $stack = [$opening];
        $quote = null;
        $escaped = false;
        $length = strlen($source);
        $index = $start + 1;
        while ($index < $length) {
            $char = $source[$index];
            if ($quote !== null) {
                if ($escaped) {
                    $escaped = false;
                } elseif ($char === '\\') {
                    $escaped = true;
                } elseif ($char === $quote) {
                    $quote = null;
                }
                $index++;
                continue;
            }
            if ($char === '"' || $char === "'") {
                $quote = $char;
                $index++;
                continue;
            }
            if ($char === '/' && $index + 1 < $length && $source[$index + 1] === '*') {
                $endComment = strpos($source, '*/', $index + 2);
                if ($endComment === false) {
                    throw new InvalidArgumentException('Unterminated JavaScript block comment.');
                }
                $index = $endComment + 2;
                continue;
            }
            if ($char === '/' && $index + 1 < $length && $source[$index + 1] === '/') {
                $newline = strpos($source, "\n", $index + 2);
                $index = $newline === false ? $length : $newline + 1;
                continue;
            }
            if ($char === '{' || $char === '[') {
                $stack[] = $char;
            } elseif ($char === '}' || $char === ']') {
                $expected = $char === '}' ? '{' : '[';
                $actual = array_pop($stack);
                if ($actual !== $expected) {
                    throw new InvalidArgumentException('Mismatched brackets in JavaScript data literal.');
                }
                if ($stack === []) {
                    return [substr($source, $start, $index - $start + 1), $index + 1];
                }
            }
            $index++;
        }
        throw new InvalidArgumentException('Unterminated JavaScript data literal.');
    }

    private function decodeJavascriptDataLiteral(string $literal, string $label): mixed
    {
        try {
            return json_decode($literal, true, 512, JSON_THROW_ON_ERROR);
        } catch (\JsonException) {
            try {
                return json_decode($this->normaliseJavascriptObjectLiteral($literal), true, 512, JSON_THROW_ON_ERROR);
            } catch (\JsonException $exception) {
                throw new InvalidArgumentException(
                    'The ' . $label . ' question bank is not valid JSON or a supported JavaScript object literal.',
                    0,
                    $exception
                );
            }
        }
    }

    /**
     * Convert the restricted JavaScript object-literal syntax used by legacy
     * self-contained courses into strict JSON. This intentionally supports
     * data-only literals: comments, unquoted identifier keys, single-quoted
     * strings and trailing commas. It never executes JavaScript.
     */
    private function normaliseJavascriptObjectLiteral(string $literal): string
    {
        $out = '';
        $length = strlen($literal);
        $index = 0;

        while ($index < $length) {
            $char = $literal[$index];

            if ($char === '/' && $index + 1 < $length && $literal[$index + 1] === '*') {
                $end = strpos($literal, '*/', $index + 2);
                if ($end === false) {
                    throw new InvalidArgumentException('Unterminated block comment in JavaScript object literal.');
                }
                $index = $end + 2;
                continue;
            }
            if ($char === '/' && $index + 1 < $length && $literal[$index + 1] === '/') {
                $newline = strpos($literal, "\n", $index + 2);
                $index = $newline === false ? $length : $newline + 1;
                $out .= "\n";
                continue;
            }

            if ($char === '"' || $char === "'") {
                [$jsonString, $index] = $this->readJavascriptString($literal, $index);
                $out .= $jsonString;
                continue;
            }

            if (preg_match('/[A-Za-z_$]/', $char) === 1) {
                $start = $index;
                $index++;
                while ($index < $length && preg_match('/[A-Za-z0-9_$]/', $literal[$index]) === 1) {
                    $index++;
                }
                $identifier = substr($literal, $start, $index - $start);
                $lookahead = $index;
                while ($lookahead < $length && ctype_space($literal[$lookahead])) {
                    $lookahead++;
                }
                if ($lookahead < $length && $literal[$lookahead] === ':') {
                    $out .= json_encode($identifier, JSON_THROW_ON_ERROR);
                } else {
                    $out .= $identifier;
                }
                continue;
            }

            $out .= $char;
            $index++;
        }

        // JSON does not permit trailing commas. Only data literals are
        // supported here, so commas immediately before ] or } are safe to drop.
        $out = preg_replace('/,\s*([}\]])/', '$1', $out) ?? $out;
        return $out;
    }

    /** @return array{0:string,1:int} */
    private function readJavascriptString(string $source, int $start): array
    {
        $quote = $source[$start];
        $length = strlen($source);
        $value = '';
        $index = $start + 1;

        while ($index < $length) {
            $char = $source[$index];
            if ($char === $quote) {
                return [json_encode($value, JSON_THROW_ON_ERROR | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES), $index + 1];
            }
            if ($char !== '\\') {
                $value .= $char;
                $index++;
                continue;
            }

            if ($index + 1 >= $length) {
                throw new InvalidArgumentException('Unterminated escape sequence in JavaScript string.');
            }
            $escape = $source[$index + 1];
            $value .= match ($escape) {
                'n' => "\n",
                'r' => "\r",
                't' => "\t",
                'b' => "\b",
                'f' => "\f",
                'v' => "\v",
                '0' => "\0",
                '\\' => '\\',
                '"' => '"',
                "'" => "'",
                '/' => '/',
                default => '\\' . $escape,
            };
            $index += 2;
        }

        throw new InvalidArgumentException('Unterminated JavaScript string in object literal.');
    }
