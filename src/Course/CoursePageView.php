declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Course\Catwalk\DeckRenderer;
use CattoLearning\Course\Catwalk\Narrations;
use CattoLearning\Course\Catwalk\SlideDeck;
use CattoLearning\View\Artwork\IconLibrary;

final class CoursePageView
{
    /** Each part's picture in the strip of a module's parts (Lucide, resources/icons). */
    private const PART_ICONS = ['presentation' => 'presentation', 'video' => 'video', 'lesson' => 'book-open', 'summary' => 'file-text', 'flashcards' => 'layers', 'practical' => 'pencil-line', 'review' => 'list-checks', 'assessment' => 'circle-help'];

    private const NUMBER_WORDS = ['', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten'];

    public function __construct(
        private readonly DeckRenderer $decks,
        private readonly Narrations $narrations,
        private readonly IconLibrary $icons
    ) {
    }

    /**
     * @param array<string,mixed> $course A public course with its structure (CourseService::publicCourse).
     * @param bool $withTrailer Whether to draw the trailer (a landing page's contents need none).
     * @return array{modules:list<array{number:int,title:string,time:string,preview:bool}>,parts:list<array{part:string,label:string,icon:string}>,paragraph:string,after:string,total:string,figures:list<array{n:string,label:string}>,free:string,trailer:array<string,mixed>|null}
     */
    public function view(array $course, bool $withTrailer = true): array
    {
        $rows = (array) ($course['structure'] ?? []);
        $modules = [];
        $moduleOf = [];
        foreach ($rows as $row) {
            if ((string) $row['node_type'] === 'section' && !empty($row['numbered']) && ($row['section_number'] ?? null) !== null) {
                $moduleOf[(int) $row['id']] = count($modules);
                $modules[] = ['number' => (int) $row['section_number'], 'title' => (string) $row['section_title'], 'minutes' => 0, 'preview' => !empty($row['public_preview']), 'parts' => []];
            }
        }
        $presentations = 0; $videos = 0; $cards = 0; $tasks = 0; $moduleQuestions = 0; $finalQuestions = 0; $narrated = false; $courseMinutes = 0;
        $trailer = null;
        foreach ($rows as $row) {
            if ((string) $row['node_type'] !== 'item') { continue; }
            $part = CourseItemService::part($row);
            $config = is_array($row['type_config'] ?? null) ? $row['type_config'] : [];
            $parent = $row['parent_node_id'] === null ? null : (int) $row['parent_node_id'];
            $in = $parent !== null && isset($moduleOf[$parent]) ? $moduleOf[$parent] : null;
            if ($part === 'presentation' && ($config['kind'] ?? '') === 'trailer') {
                if ($trailer === null && !empty($row['public_preview'])) { $trailer = $row; }
                continue;
            }
            $courseMinutes += CourseItemService::itemMinutes($row) ?? 0;
            if ($in !== null) {
                $modules[$in]['minutes'] += CourseItemService::itemMinutes($row) ?? 0;
                $modules[$in]['parts'][$part] = true;
            }
            match ($part) {
                'presentation' => $in !== null ? $presentations++ : null,
                'video' => $videos++,
                'flashcards' => $cards += count((array) ($config['cards'] ?? [])),
                'practical' => $tasks += substr_count((string) ($row['content_source'] ?? ''), '<section class="task"'),
                'assessment' => $in !== null ? $moduleQuestions += (int) ($row['question_count'] ?? 0) : null,
                'final' => $finalQuestions += (int) ($row['question_count'] ?? 0),
                default => null,
            };
            if ($part === 'presentation' && $in !== null && !$narrated) { $narrated = $this->narrations->forItem((int) $row['course_item_id']) !== []; }
        }

        $count = count($modules);
        $total = array_sum(array_column($modules, 'minutes'));
        $common = [];
        $some = [];
        foreach (array_keys(CourseItemService::PART_LABELS) as $part) {
            $with = count(array_filter($modules, static fn(array $module): bool => isset($module['parts'][$part])));
            if ($with === 0 || in_array($part, ['final', 'diagnostic'], true)) { continue; }
            if ($with === $count) { $common[] = $part; } else { $some[$part] = $with; }
        }
        $free = '';
        foreach ($modules as $module) { if ($module['preview']) { $free = 'Module ' . $module['number']; break; } }

        $figures = array_values(array_filter([
            $presentations > 0 ? ['n' => (string) $presentations, 'label' => $presentations === $count && in_array('presentation', $common, true) ? 'presentations, one opening each module' : 'presentations'] : null,
            $videos > 0 ? ['n' => (string) $videos, 'label' => $videos === 1 ? 'video' : 'videos'] : null,
            $cards > 0 ? ['n' => number_format($cards, 0, '.', ','), 'label' => 'flash cards'] : null,
            $tasks > 0 ? ['n' => (string) $tasks, 'label' => 'practical tasks with model answers'] : null,
            $moduleQuestions > 0 ? ['n' => number_format($moduleQuestions, 0, '.', ','), 'label' => 'questions in the module assessments'] : null,
            $finalQuestions > 0 ? ['n' => number_format($finalQuestions, 0, '.', ','), 'label' => 'questions in the final assessment'] : null,
        ]));

        return [
            'modules' => array_map(static fn(array $module): array => ['number' => $module['number'], 'title' => $module['title'], 'time' => self::time($module['minutes']), 'preview' => $module['preview']], $modules),
            'parts' => array_map(fn(string $part): array => ['part' => $part, 'label' => $part === 'assessment' ? 'Self assessment' : CourseItemService::PART_LABELS[$part], 'icon' => (string) $this->icons->svg(self::PART_ICONS[$part] ?? 'circle')], array_values(array_intersect(array_keys(CourseItemService::PART_LABELS), array_merge($common, array_keys($some))))),
            'paragraph' => $count > 0 ? self::paragraph($common, $some, $count, $narrated, (int) round($total / $count)) : '',
            'after' => $this->after($rows, $moduleOf, $moduleQuestions > 0, $finalQuestions > 0),
            // The whole course's study time, the review and the final with it; the trailer is for visitors.
            'total' => $courseMinutes > 0 ? self::roughly($courseMinutes) : '',
            'figures' => $figures,
            'free' => $free,
            'trailer' => $trailer === null || !$withTrailer ? null : $this->trailer($trailer, $course),
        ];
    }

    /**
     * How a module is made, in one paragraph: the parts every module has, in their order, then those only some have,
     * then its usual length.
     *
     * @param list<string> $common
     * @param array<string,int> $some
     */
    public static function paragraph(array $common, array $some, int $modules, bool $narrated, int $minutes): string
    {
        $has = static fn(string $part): bool => in_array($part, $common, true);
        $sentences = [];
        if ($has('presentation')) {
            $sentences[] = 'Every module opens with a presentation, a short ' . ($narrated ? 'narrated ' : '') . 'slide show you can play on any screen' . ($has('video') ? ', followed by a video.' : '.');
        } elseif ($has('video')) {
            $sentences[] = 'Every module opens with a video.';
        }
        if ($has('lesson')) {
            $aids = array_values(array_filter([$has('summary') ? 'a summary' : '', $has('flashcards') ? 'flash cards' : '']));
            $sentences[] = ($sentences === [] ? 'Every module has a lesson' : 'Then comes the lesson') . ($aids === [] ? '.' : ', with ' . implode(' and ', $aids) . ' to fix what matters.');
        }
        $closing = array_values(array_filter([
            $has('practical') ? 'practical work with model answers lets you apply it' : '',
            $has('review') ? 'a review study aid gathers the points to remember' : '',
            $has('assessment') ? 'each module ends with a self assessment' : '',
        ]));
        if ($closing !== []) { $sentences[] = ucfirst(self::series($closing)) . '.'; }
        $words = ['presentation' => 'a presentation', 'video' => 'a video', 'summary' => 'a summary', 'flashcards' => 'flash cards', 'practical' => 'practical work', 'review' => 'a review study aid', 'assessment' => 'a self assessment'];
        $most = []; $several = [];
        foreach ($some as $part => $with) {
            if (!isset($words[$part])) { continue; }
            if ($with * 2 > $modules) { $most[] = $words[$part]; } else { $several[] = $words[$part]; }
        }
        if ($most !== []) { $sentences[] = 'Most modules also have ' . self::series($most) . '.'; }
        if ($several !== []) { $sentences[] = 'Some modules also have ' . self::series($several) . '.'; }
        if ($minutes > 0) { $sentences[] = 'A module takes ' . self::roughly($minutes) . '.'; }
        return implode(' ', $sentences);
    }

    /** A length in plain words, rounded: "about 25 minutes", "about an hour and a half", "about 47 hours". */
    public static function roughly(int $minutes): string
    {
        if ($minutes < 55) { return 'about ' . max(5, (int) (round($minutes / 5) * 5)) . ' minutes'; }
        if ($minutes >= 600) { return 'about ' . (int) round($minutes / 60) . ' hours'; }
        $halves = (int) round($minutes / 30);
        $hours = intdiv($halves, 2);
        $half = $halves % 2 === 1;
        if ($hours === 1) { return $half ? 'about an hour and a half' : 'about an hour'; }
        $number = self::NUMBER_WORDS[$hours] ?? (string) $hours;
        return 'about ' . $number . ($half ? ' and a half' : '') . ' hours';
    }

    /** A module's study time as the outline words it ("2 hours 43 minutes"). */
    private static function time(int $minutes): string
    {
        return $minutes > 0 ? CourseItemService::duration($minutes) : '';
    }

    /** @param list<string> $items */
    private static function series(array $items): string
    {
        return count($items) <= 1 ? (string) ($items[0] ?? '') : implode(', ', array_slice($items, 0, -1)) . ' and ' . end($items);
    }

    /**
     * What follows the modules: a course review before a final assessment, and how the result is worked out.
     *
     * @param list<array<string,mixed>> $rows
     * @param array<int,int> $moduleOf
     */
    private function after(array $rows, array $moduleOf, bool $moduleAssessments, bool $final): string
    {
        $review = false;
        foreach ($rows as $row) {
            if ((string) $row['node_type'] !== 'item' || ($row['parent_node_id'] !== null && isset($moduleOf[(int) $row['parent_node_id']]))) { continue; }
            if (CourseItemService::part($row) === 'review') { $review = true; }
        }
        $sentences = [];
        if ($review && $final) { $sentences[] = 'After the modules, a course review with its own study aid prepares you for the final assessment.'; }
        elseif ($final) { $sentences[] = 'After the modules comes the final assessment.'; }
        if ($moduleAssessments && $final) { $sentences[] = 'Your result is half the module assessments and half the final.'; }
        return implode(' ', $sentences);
    }

    /**
     * The trailer as CatWalk plays it in the window: its Get this course button takes the reader to Course access on
     * this page, its preview button to the free preview.
     *
     * @param array<string,mixed> $row
     * @param array<string,mixed> $course
     * @return array<string,mixed>
     */
    private function trailer(array $row, array $course): array
    {
        $config = is_array($row['type_config'] ?? null) ? $row['type_config'] : [];
        $narrations = [];
        foreach ($this->narrations->forItem((int) $row['course_item_id']) as $slide => $publicId) { $narrations[$slide] = '/narrations/' . rawurlencode($publicId); }
        $slug = rawurlencode((string) $course['slug']);
        $slides = count((array) ($config['slides'] ?? []));
        return [
            'html' => $this->decks->render($config, (string) $row['item_key'], SlideDeck::barText((string) ($row['description_html'] ?? ''), (string) $row['item_title']), ['enrol' => '#course-access', 'continue' => '#course-access', 'preview' => '/courses/' . $slug . '/preview'], $narrations),
            'slides' => $slides,
            'time' => self::roughly(CourseItemService::itemMinutes($row) ?? 0),
            'narrated' => $narrations !== [],
            // Without JavaScript the button opens the trailer in the free preview.
            'href' => '/courses/' . $slug . '/preview/' . (int) $row['id'] . '/content',
        ];
    }
}
