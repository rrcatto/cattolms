    /**
     * Every course, in catalogue order, for the export form: its code, title, category and status.
     *
     * @return list<array{id:int,code:string,title:string,status:string,category:string}>
     */
    public function exportChoices(): array
    {
        $paths = $this->settings->categoryPaths();
        return array_map(static fn(array $row): array => ['id' => $row['id'], 'code' => $row['code'], 'title' => $row['title'], 'status' => $row['status'],
            'category' => $row['category_id'] === null ? '' : ($paths[$row['category_id']] ?? '')], $this->repository->catalogueExportRows());
    }

    /**
     * Writes a catalogue package to a new temporary file and answers its path; the caller sends and removes it. It holds
     * the chosen courses (null: every course) and only their categories, each with those above it, and their tags; a
     * related course that was not chosen is left out (owner, 2026-10-23: "Unselected courses and categories and tags
     * which do not apply to the select courses must not be included in the export").
     *
     * @param list<int>|null $courseIds
     */
    public function export(int $userId, ?array $courseIds = null): string
    {
        $chosen = $this->chosen($courseIds);
        if ($chosen === []) throw new InvalidArgumentException('Tick the courses to put in the catalogue package.');
        $path = tempnam(sys_get_temp_dir(), 'catalogue');
        if ($path === false) throw new RuntimeException('The catalogue package could not be made.');
        $zip = new ZipArchive();
        if ($zip->open($path, ZipArchive::OVERWRITE) !== true) throw new RuntimeException('The catalogue package could not be made.');
        $codes = [];
        $files = [];
        $packages = [];
        foreach ($chosen as $courseId) $packages[$courseId] = $this->portability->exportCourse($courseId);
        $chosenCodes = array_map(static fn(array $package): string => (string) $package['course']['code'], $packages);
        foreach ($packages as $courseId => $package) {
            $code = (string) $package['course']['code'];
            $package['catalogue']['related'] = array_values(array_intersect((array) $package['catalogue']['related'], $chosenCodes));
            $zip->addFromString(self::COURSES . $code . '.json', self::json($package));
            $codes[] = $code;
            foreach ((array) $package['resources'] as $resource) {
                $publicId = (string) ($resource['public_id'] ?? '');
                if ($publicId === '' || isset($files[$publicId])) continue;
                $source = $this->resources->path(['filename' => (string) $resource['filename']]);
                if (is_file($source)) $zip->addFile($source, $files[$publicId] = self::RESOURCES . $publicId . '/' . basename((string) $resource['filename']));
            }
            foreach ((array) $package['course_items'] as $item) {
                foreach ((array) ($item['narrations'] ?? []) as $clip) {
                    $source = $this->narrations?->path((string) $clip['public_id'], (string) $clip['content_type']);
                    if ($source !== null && is_file($source)) $zip->addFile($source, self::NARRATIONS . basename($source));
                }
            }
        }
        [$categories, $tags] = $this->taxonomyOf($chosen);
        $zip->addFromString(self::CATALOGUE, self::json($this->file->export($categories, $tags) + ['courses' => $codes]));
        if (!$zip->close()) throw new RuntimeException('The catalogue package could not be written.');
        $this->audit->record($userId, 'catalogue.exported', ['courses' => count($codes), 'categories' => count($categories), 'tags' => count($tags), 'files' => count($files),
            'every_course' => $courseIds === null]);
        return $path;
    }

    /**
     * The categories and tags of the chosen courses, as a catalogue file; with no course chosen, every category and tag
     * (owner, 2026-10-23: the categories and tags file follows the selection).
     *
     * @param list<int>|null $courseIds
     */
    public function exportCategoriesAndTags(int $userId, ?array $courseIds = null): string
    {
        $chosen = $courseIds === null || $courseIds === [] ? [] : $this->chosen($courseIds);
        if ($chosen === []) {
            $this->audit->record($userId, 'catalogue.exported', ['courses' => 0, 'categories_and_tags_only' => true]);
            return self::json($this->file->export());
        }
        [$categories, $tags] = $this->taxonomyOf($chosen);
        $this->audit->record($userId, 'catalogue.exported', ['courses' => 0, 'categories_and_tags_only' => true, 'of_courses' => count($chosen), 'categories' => count($categories), 'tags' => count($tags)]);
        return self::json($this->file->export($categories, $tags));
    }

    /**
     * The chosen courses that are on the site, in catalogue order; null chooses every course.
     *
     * @param list<int>|null $courseIds
     * @return list<int>
     */
    private function chosen(?array $courseIds): array
    {
        $order = $this->repository->catalogueOrderIds();
        if ($courseIds === null) return $order;
        $wanted = array_fill_keys(array_map('intval', $courseIds), true);
        return array_values(array_filter($order, static fn(int $id): bool => isset($wanted[$id])));
    }

    /**
     * The categories the courses are in and the tags they carry.
     *
     * @param list<int> $courseIds
     * @return array{0:list<int>,1:list<int>}
     */
    private function taxonomyOf(array $courseIds): array
    {
        $categories = [];
        $tags = [];
        foreach ($courseIds as $courseId) {
            $course = $this->repository->findById($courseId);
            if ($course !== null && $course['category_id'] !== null) $categories[(int) $course['category_id']] = true;
            foreach ($this->repository->courseTagIds($courseId) as $tagId) $tags[(int) $tagId] = true;
        }
        return [array_keys($categories), array_keys($tags)];
    }

    /**
     * Keeps an uploaded package (or catalogue.json) for its review and answers the key the review names it by. A file
     * that is not one is refused here, before anything is kept.
     *
     * @param array<string,mixed> $upload one entry of $_FILES
     */
    public function stage(array $upload, int $userId): string
    {
        $error = (int) ($upload['error'] ?? UPLOAD_ERR_NO_FILE);
        if ($error === UPLOAD_ERR_INI_SIZE || $error === UPLOAD_ERR_FORM_SIZE) throw new InvalidArgumentException('The file is larger than ' . intdiv(self::MAXIMUM_UPLOAD_BYTES, 1024 * 1024) . ' MB, the most this site accepts.');
        if ($error !== UPLOAD_ERR_OK) throw new InvalidArgumentException('Choose the catalogue package (.zip) or catalogue file (.json) to import.');
        $temporary = (string) ($upload['tmp_name'] ?? '');
        if (!is_uploaded_file($temporary) && !is_file($temporary)) throw new InvalidArgumentException('The uploaded file is unavailable.');
        return $this->keep($temporary, basename((string) ($upload['name'] ?? 'catalogue.zip')), $userId, true);
    }

    /** Keeps a package from a path (the console's catalogue:import), copying it. */
    public function stageFile(string $path, string $name, int $userId): string
    {
        if (!is_file($path) || !is_readable($path)) throw new InvalidArgumentException('There is no file at ' . $path . '.');
        return $this->keep($path, $name, $userId, false);
    }

    /**
     * What importing the staged package would do, changing nothing.
     *
     * @return array<string,mixed>
     */
    public function plan(string $key): array
    {
        [$path, $meta] = $this->staged($key);
        $package = $this->read($path, (string) $meta['extension']);
        $inPackage = array_fill_keys(array_keys($package['files']), true);
        $plan = [
            'key' => $key,
            'filename' => (string) $meta['original_filename'],
            'kind' => (string) $meta['extension'],
            'catalogue' => $this->file->plan($package['catalogue']),
            'files_new' => count(array_filter(array_keys($inPackage), fn(string $id): bool => $this->items->resourceByPublicId($id) === null)),
            'courses' => [],
            'counts' => ['new' => 0, 'update' => 0, 'unchanged' => 0, 'skip' => 0],
        ];
        $codes = [];
        $slugs = [];
        foreach ($package['courses'] as $entry) {
            $row = $this->planCourse($entry['name'], $entry['data'], $inPackage, $codes, $slugs);
            $plan['courses'][] = $row;
            $plan['counts'][$row['action']]++;
        }
        return $plan;
    }

    /**
     * Imports the staged package as its review chose, and answers what was done.
     *
     * @param array{courses?:list<string>|null,replace?:list<string>,prices?:bool,publish?:bool} $choices
     *        courses: the codes to import or update (null for every one); replace: the courses already here whose
     *        content is replaced; prices: the package's prices for new courses; publish: new courses published as they were
     * @return array<string,mixed>
     */
    public function apply(string $key, array $choices, int $userId): array
    {
        $plan = $this->plan($key);
        [$path, $meta] = $this->staged($key);
        $package = $this->read($path, (string) $meta['extension']);
        $chosen = $choices['courses'] ?? null;
        $replace = array_map([CourseCode::class, 'normalise'], (array) ($choices['replace'] ?? []));
        $prices = (bool) ($choices['prices'] ?? true);
        $publish = (bool) ($choices['publish'] ?? true);
        $report = ['filename' => $plan['filename'], 'catalogue' => $this->file->import($package['catalogue'], $userId), 'files_installed' => 0,
            'courses' => [], 'counts' => ['imported' => 0, 'updated' => 0, 'replaced' => 0, 'unchanged' => 0, 'left_out' => 0, 'skipped' => 0, 'failed' => 0]];
        $report['files_installed'] = $this->installFiles($path, $package['files'], $package['courses'], $userId);

        $data = [];
        foreach ($package['courses'] as $entry) $data[$entry['name']] = $entry['data'];
        $done = [];
        foreach ($plan['courses'] as $row) {
            $outcome = ['code' => $row['code'], 'title' => $row['title'], 'course_id' => $row['course_id'], 'outcome' => '', 'details' => []];
            if ($row['action'] === 'skip') {
                $report['courses'][] = array_replace($outcome, ['outcome' => 'skipped', 'details' => [$row['reason']]]);
                $report['counts']['skipped']++;
                continue;
            }
            if ($chosen !== null && !in_array($row['code'], array_map([CourseCode::class, 'normalise'], $chosen), true)) {
                $report['courses'][] = array_replace($outcome, ['outcome' => 'left out']);
                $report['counts']['left_out']++;
                continue;
            }
            $block = is_array($data[$row['file']]['catalogue'] ?? null) ? $data[$row['file']]['catalogue'] : [];
            try {
                if ($row['action'] === 'new') {
                    $analysis = $this->portability->analysePackage($data[$row['file']], $row['file']);
                    $categoryId = $this->settings->categoryIdByPath((string) ($block['category'] ?? ''));
                    $courseId = $this->portability->importChecked($analysis, $categoryId ?? 0, $userId, null, $row['code']);
                    $details = array_merge([$categoryId === null ? 'Uncategorised' : 'Category: ' . $block['category']],
                        $this->settings->apply($courseId, array_diff_key($block, ['category' => true]), $userId, $prices));
                    $narrated = $this->installNarrations($path, $package['narrations'], $data[$row['file']], $userId);
                    if ($narrated > 0) $details[] = 'Narration: ' . $narrated . ' slides';
                    $outcome = array_replace($outcome, ['course_id' => $courseId, 'outcome' => 'imported', 'details' => $details]);
                    $report['counts']['imported']++;
                    $done[$courseId] = ['block' => $block, 'new' => true];
                } else {
                    $courseId = (int) $row['course_id'];
                    $details = [];
                    if (in_array($row['code'], $replace, true)) {
                        if ($row['started']) throw new InvalidArgumentException('Learners have started this course, so its content is not replaced.');
                        $current = $this->repository->findById($courseId) ?? throw new InvalidArgumentException('The course is no longer on the site.');
                        $analysis = $this->portability->analysePackage($data[$row['file']], $row['file']);
                        $this->portability->importChecked($analysis, (int) ($current['category_id'] ?? 0), $userId, $courseId, $row['code']);
                        $details[] = 'Content replaced with the package\'s';
                        $narrated = $this->installNarrations($path, $package['narrations'], $data[$row['file']], $userId);
                        if ($narrated > 0) $details[] = 'Narration: ' . $narrated . ' slides';
                    }
                    $details = array_merge($details, $this->settings->apply($courseId, $block, $userId, false));
                    $kind = in_array($row['code'], $replace, true) ? 'replaced' : ($details === [] ? 'unchanged' : 'updated');
                    $outcome = array_replace($outcome, ['outcome' => $kind === 'replaced' ? 'content replaced' : $kind, 'details' => $details]);
                    $report['counts'][$kind]++;
                    $done[$courseId] = ['block' => $block, 'new' => false];
                }
            } catch (Throwable $failed) {
                $outcome = array_replace($outcome, ['outcome' => 'failed', 'details' => [$failed->getMessage()]]);
                $report['counts']['failed']++;
            }
            $report['courses'][] = $outcome;
        }
        // The related courses once every course is in; then the new courses published as they were where they came from.
        $byId = [];
        foreach ($report['courses'] as $index => $outcome) if ($outcome['course_id'] !== null) $byId[(int) $outcome['course_id']] = $index;
        foreach ($done as $courseId => $course) {
            $added = $this->settings->relate($courseId, $course['block']);
            if ($added > 0) $report['courses'][$byId[$courseId]]['details'][] = 'Related courses: ' . $added . ' added';
            if ($course['new'] && $publish && (string) ($course['block']['status'] ?? '') === 'published') {
                try {
                    // Its warnings were accepted where it was published; an error (no price, say) still keeps it a draft.
                    $this->courses->changeStatus($courseId, 'published', $userId, true);
                    $report['courses'][$byId[$courseId]]['details'][] = 'Published';
                } catch (InvalidArgumentException|RuntimeException $refused) {
                    $report['courses'][$byId[$courseId]]['details'][] = 'Left as a draft: ' . $refused->getMessage();
                }
            }
        }
        $this->audit->record($userId, 'catalogue.imported', ['filename' => $plan['filename'], 'catalogue' => $report['catalogue'], 'files_installed' => $report['files_installed'], 'counts' => $report['counts']]);
        $this->discard($key);
        return $report;
    }

    /** Forgets a staged package (the review's Cancel). */
    public function discard(string $key): void
    {
        [$path] = $this->staged($key);
        @unlink($path);
        @unlink($this->directory() . '/catalogue-' . $key . '.meta.json');
    }

    /**
     * One course of the package: new, already here (with what would change), or left out and why.
     *
     * @param array<string,mixed> $data
     * @param array<string,true> $inPackage the files the package carries, by public id
     * @param array<string,true> $codes the codes seen so far in the package
     * @param array<string,true> $slugs the slugs seen so far in the package
     * @return array<string,mixed>
     */
    private function planCourse(string $name, array $data, array $inPackage, array &$codes, array &$slugs): array
    {
        $course = is_array($data['course'] ?? null) ? $data['course'] : [];
        $block = is_array($data['catalogue'] ?? null) ? $data['catalogue'] : [];
        $row = ['file' => $name, 'code' => CourseCode::normalise((string) ($course['code'] ?? '')), 'title' => trim((string) ($course['title'] ?? '')) ?: $name,
            'slug' => (string) ($course['slug'] ?? ''), 'action' => 'skip', 'reason' => '', 'changes' => [], 'course_id' => null, 'started' => false,
            'category' => (string) ($block['category'] ?? ''), 'status' => (string) ($block['status'] ?? 'draft')];
        try {
            $analysis = $this->portability->analysePackage($data, $name);
        } catch (Throwable $unreadable) {
            return ['reason' => 'It cannot be read: ' . $unreadable->getMessage()] + $row;
        }
        $row['slug'] = (string) ($analysis['course']['slug'] ?? $row['slug']);
        if (!CourseCode::isValid($row['code'])) {
            return ['reason' => 'It has no course code' . ($row['code'] === '' ? '' : ' it can use ("' . $row['code'] . '")') . ', and a catalogue import knows a course only by its code. Export it again from a site that gives it one.'] + $row;
        }
        if (isset($codes[$row['code']])) return ['reason' => 'Another course in this package has the code ' . $row['code'] . '.'] + $row;
        $codes[$row['code']] = true;

        $existing = $this->repository->findByCode($row['code']);
        if ($existing !== null) {
            $row['course_id'] = (int) $existing['id'];
            $row['started'] = $this->portability->hasStartedLearners((int) $existing['id']);
            $row['changes'] = $this->settings->changes($existing, $block, false);
            $row['action'] = $row['changes'] === [] ? 'unchanged' : 'update';
            $row['site_title'] = (string) $existing['title'];
            return $row;
        }
        if (isset($slugs[$row['slug']])) return ['reason' => 'Another course in this package has the address /courses/' . $row['slug'] . '.'] + $row;
        $slugs[$row['slug']] = true;
        $advice = ' To update that course from this package, give it the code ' . $row['code'] . ' on its Details tab and import again.';
        $holder = $this->repository->findBySlug($row['slug']);
        if ($holder !== null) {
            return ['reason' => 'The address /courses/' . $row['slug'] . ' is another course\'s here: “' . $holder['title'] . '” (' . $holder['code'] . ').' . $advice] + $row;
        }
        $conflicts = $this->conflicts($analysis, $inPackage);
        if ($conflicts !== []) {
            $holderId = $this->portability->courseHoldingConflicts(['key_conflicts' => $conflicts]);
            $holder = $holderId === null ? null : $this->repository->findById($holderId);
            return ['reason' => $holder !== null
                ? 'Its content is already on the site as “' . $holder['title'] . '” (' . $holder['code'] . ').' . $advice
                : implode(' ', $conflicts)] + $row;
        }
        $row['action'] = 'new';
        $row['changes'] = [$row['category'] !== '' ? 'Category: ' . $row['category'] . ($this->settings->categoryIdByPath($row['category']) === null && !$this->categoryInPackage($row['category']) ? ' (not in the package: uncategorised)' : '') : 'Uncategorised'];
        return $row;
    }

    /** Whether the package's own categories include this path (the package read last). */
    private function categoryInPackage(string $path): bool
    {
        return in_array($path, $this->packageCategoryPaths, true);
    }

    /**
     * The analysis's conflicts, less those about files the package itself brings.
     *
     * @param array<string,mixed> $analysis
     * @param array<string,true> $inPackage
     * @return list<string>
     */
    private function conflicts(array $analysis, array $inPackage): array
    {
        $brought = [];
        foreach ((array) ($analysis['course_items'] ?? []) as $item) {
            $resource = trim((string) ($item['resource_public_id'] ?? ''));
            if ($resource !== '' && isset($inPackage[$resource])) $brought[] = 'Course Item ' . (string) ($item['item_key'] ?? '') . ' needs an installed Resource.';
        }
        return array_values(array_filter((array) ($analysis['key_conflicts'] ?? []), static function (string $conflict) use ($inPackage, $brought): bool {
            if (in_array($conflict, $brought, true)) return false;
            foreach (array_keys($inPackage) as $publicId) if (str_contains($conflict, (string) $publicId)) return false;
            return true;
        }));
    }

    /**
     * A course's Presentations get the narration the package holds for them, each clip under its slide; a slide that
     * already has one here keeps it.
     *
     * @param array<string,string> $narrations entry name by the clip's public id
     * @param array<string,mixed> $course the course's package
     */
    private function installNarrations(string $path, array $narrations, array $course, int $userId): int
    {
        if ($narrations === [] || $this->narrations === null) return 0;
        $zip = new ZipArchive();
        if ($zip->open($path, ZipArchive::RDONLY) !== true) return 0;
        $installed = 0;
        try {
            foreach ((array) ($course['course_items'] ?? []) as $item) {
                if (!is_array($item) || ($item['item_type'] ?? '') !== 'slide_deck' || empty($item['narrations'])) continue;
                $target = $this->items->itemByKey((string) $item['item_key']);
                if ($target === null) continue;
                $have = $this->narrations->forItem((int) $target['id']);
                foreach ((array) $item['narrations'] as $clip) {
                    $entry = $narrations[(string) ($clip['public_id'] ?? '')] ?? null;
                    $slide = (string) ($clip['slide_id'] ?? '');
                    if ($entry === null || $slide === '' || isset($have[$slide])) continue;
                    $bytes = $zip->getFromName($entry);
                    if ($bytes === false) continue;
                    $temporary = (string) tempnam(sys_get_temp_dir(), 'narration');
                    try {
                        file_put_contents($temporary, $bytes);
                        $this->narrations->save((int) $target['id'], $slide, $temporary, isset($clip['duration_seconds']) ? (float) $clip['duration_seconds'] : null, $userId);
                        $installed++;
                    } catch (InvalidArgumentException) {
                        // A clip whose slide is not in the deck any more is left out.
                    } finally {
                        @unlink($temporary);
                    }
                }
            }
        } finally {
            $zip->close();
        }
        return $installed;
    }

    /**
     * Installs the package's files that are not on the site yet, for the courses that use them.
     *
     * @param array<string,string> $files entry name by public id
     * @param list<array{name:string,data:array<string,mixed>}> $courses
     */
    private function installFiles(string $path, array $files, array $courses, int $userId): int
    {
        if ($files === []) return 0;
        $described = [];
        foreach ($courses as $entry) foreach ((array) ($entry['data']['resources'] ?? []) as $resource) {
            if (is_array($resource) && isset($resource['public_id'])) $described[(string) $resource['public_id']] = $resource;
        }
        $zip = new ZipArchive();
        if ($zip->open($path, ZipArchive::RDONLY) !== true) throw new InvalidArgumentException('The catalogue package cannot be opened.');
        $installed = 0;
        foreach ($files as $publicId => $entryName) {
            if ($this->items->resourceByPublicId((string) $publicId) !== null) continue;
            $bytes = $zip->getFromName($entryName);
            if ($bytes === false) continue;
            $about = $described[$publicId] ?? [];
            $this->resources->install((string) $publicId, basename($entryName), $bytes, [
                'title' => (string) ($about['title'] ?? basename($entryName)), 'description' => (string) ($about['description'] ?? ''),
                'resource_type' => (string) ($about['resource_type'] ?? ''), 'original_filename' => (string) ($about['original_filename'] ?? basename($entryName)),
            ], $userId);
            $installed++;
        }
        $zip->close();
        return $installed;
    }

    /**
     * The package's catalogue file, its courses' packages in catalogue order and its files.
     *
     * @return array{catalogue:array<string,mixed>,courses:list<array{name:string,data:array<string,mixed>}>,files:array<string,string>,narrations:array<string,string>}
     */
    private function read(string $path, string $extension): array
    {
        if ($extension === 'json') {
            $catalogue = self::decode((string) file_get_contents($path), 'The catalogue file');
            CatalogueFile::check($catalogue);
            $this->packageCategoryPaths = self::paths((array) ($catalogue['categories'] ?? []));
            return ['catalogue' => $catalogue, 'courses' => [], 'files' => [], 'narrations' => []];
        }
        $zip = new ZipArchive();
        if ($zip->open($path, ZipArchive::RDONLY) !== true) throw new InvalidArgumentException('The file is not a zip: choose a catalogue package made by Export catalogue.');
        try {
            if ($zip->numFiles > self::MAXIMUM_ENTRIES) throw new InvalidArgumentException('The package holds more than ' . self::MAXIMUM_ENTRIES . ' files.');
            $unpacked = 0;
            $courses = [];
            $files = [];
            $narrations = [];
            for ($index = 0; $index < $zip->numFiles; $index++) {
                $stat = $zip->statIndex($index);
                if ($stat === false) continue;
                $name = (string) $stat['name'];
                $unpacked += (int) $stat['size'];
                if ($unpacked > self::MAXIMUM_UNPACKED_BYTES) throw new InvalidArgumentException('The package unpacks to more than ' . intdiv(self::MAXIMUM_UNPACKED_BYTES, 1024 * 1024) . ' MB.');
                if (str_ends_with($name, '/')) continue;
                if ($name === self::CATALOGUE) continue;
                if (preg_match('#^courses/([A-Za-z0-9][A-Za-z0-9._-]{0,120})\.json$#', $name) === 1) { $courses[] = $name; continue; }
                if (preg_match('#^resources/([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})/([A-Za-z0-9][A-Za-z0-9._ -]{0,499})$#', $name, $match) === 1) { $files[$match[1]] = $name; continue; }
                if (preg_match('#^narrations/([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\.(webm|ogg|m4a|mp3|wav)$#', $name, $match) === 1) { $narrations[$match[1]] = $name; continue; }
                throw new InvalidArgumentException('The package holds a file a catalogue package does not: ' . $name . '.');
            }
            $text = $zip->getFromName(self::CATALOGUE);
            if ($text === false) throw new InvalidArgumentException('The package has no catalogue.json: choose a catalogue package made by Export catalogue.');
            $catalogue = self::decode($text, 'catalogue.json');
            CatalogueFile::check($catalogue);
            $this->packageCategoryPaths = self::paths((array) ($catalogue['categories'] ?? []));
            // In the catalogue's order, then any course it does not list.
            $order = array_flip(array_map(static fn(mixed $code): string => self::COURSES . CourseCode::normalise((string) $code) . '.json', (array) ($catalogue['courses'] ?? [])));
            usort($courses, static fn(string $a, string $b): int => [$order[$a] ?? PHP_INT_MAX, $a] <=> [$order[$b] ?? PHP_INT_MAX, $b]);
            $packages = [];
            foreach ($courses as $name) {
                $packages[] = ['name' => $name, 'data' => self::decode((string) $zip->getFromName($name), $name)];
            }
            return ['catalogue' => $catalogue, 'courses' => $packages, 'files' => $files, 'narrations' => $narrations];
        } finally {
            $zip->close();
        }
    }

    /**
     * @param list<array<string,mixed>> $nodes
     * @return list<string>
     */
    private static function paths(array $nodes, string $path = ''): array
    {
        $paths = [];
        foreach ($nodes as $node) {
            $here = ($path === '' ? '' : $path . CourseCatalogueSettings::SEPARATOR) . trim((string) ($node['name'] ?? ''));
            $paths[] = $here;
            array_push($paths, ...self::paths((array) ($node['children'] ?? []), $here));
        }
        return $paths;
    }

    private function keep(string $source, string $name, int $userId, bool $uploaded): string
    {
        $extension = strtolower(pathinfo($name, PATHINFO_EXTENSION));
        if (!in_array($extension, ['zip', 'json'], true)) throw new InvalidArgumentException('Choose a catalogue package (.zip) or a catalogue file (.json).');
        if ((int) filesize($source) > self::MAXIMUM_UPLOAD_BYTES) throw new InvalidArgumentException('The file is larger than ' . intdiv(self::MAXIMUM_UPLOAD_BYTES, 1024 * 1024) . ' MB.');
        $key = bin2hex(random_bytes(16));
        $path = $this->directory() . '/catalogue-' . $key . '.' . $extension;
        $moved = $uploaded ? (move_uploaded_file($source, $path) || rename($source, $path)) : copy($source, $path);
        if (!$moved) throw new RuntimeException('The file could not be kept for its review.');
        chmod($path, 0640);
        file_put_contents($this->directory() . '/catalogue-' . $key . '.meta.json', json_encode([
            'original_filename' => $name, 'extension' => $extension, 'uploaded_by_user_id' => $userId, 'staged_at' => date(DATE_ATOM),
        ], JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES), LOCK_EX);
        try {
            $this->read($path, $extension);
        } catch (Throwable $refused) {
            $this->discard($key);
            throw $refused instanceof InvalidArgumentException ? $refused : new InvalidArgumentException($refused->getMessage(), 0, $refused);
        }
        return $key;
    }

    /** @return array{0:string,1:array<string,mixed>} */
    private function staged(string $key): array
    {
        if (preg_match('/^[a-f0-9]{32}$/', $key) !== 1) throw new InvalidArgumentException('Invalid import reference.');
        $metaPath = $this->directory() . '/catalogue-' . $key . '.meta.json';
        $meta = is_file($metaPath) ? json_decode((string) file_get_contents($metaPath), true) : null;
        if (!is_array($meta) || !in_array($meta['extension'] ?? '', ['zip', 'json'], true)) throw new InvalidArgumentException('That import has been finished or cancelled. Upload the file again.');
        $path = $this->directory() . '/catalogue-' . $key . '.' . $meta['extension'];
        if (!is_file($path)) throw new InvalidArgumentException('That import has been finished or cancelled. Upload the file again.');
        return [$path, $meta];
    }

    private function directory(): string
    {
        $directory = $this->storageRoot . '/imports';
        if (!is_dir($directory) && !mkdir($directory, 0770, true) && !is_dir($directory)) throw new RuntimeException('Unable to create the import directory.');
        return $directory;
    }

    /** @return array<string,mixed> */
    private static function decode(string $json, string $what): array
    {
        try {
            $data = json_decode($json, true, 512, JSON_THROW_ON_ERROR);
        } catch (\JsonException $invalid) {
            throw new InvalidArgumentException($what . ' is not valid JSON: ' . $invalid->getMessage(), 0, $invalid);
        }
        if (!is_array($data)) throw new InvalidArgumentException($what . ' must hold an object.');
        return $data;
    }

    private static function json(mixed $data): string
    {
        return json_encode($data, JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . "\n";
    }
