Automatic position ranges (owner, 2026-11-01: "yes, build automatic ranges"): Settings > Course positions lists course
code prefixes, each with the number its range starts at, such as GDN from 1000. A course that arrives with no position
(added in Administration, imported, or new from a catalogue package) takes the next free number in its code's range,
in steps of 100: the range runs from its start up to the next range's start, and the next number is 100 after the
highest position anything has in it, or the start itself when nothing does. When the range is full the course takes
the midpoint before the next range, and when even that is taken it keeps no position, as before. A course that has a
position, typed, dragged or brought by a file, is never moved.

Bands (owner, 2026-11-12, bands 10,000 apart): renumber() puts every course back in its prefix's band, 100 apart in its
present order (Support\PositionBands), from Administration > Courses or Settings > Course positions. The bands' rows,
saving and words are Support\PositionRanges, shared with Settings > Bundle positions.

