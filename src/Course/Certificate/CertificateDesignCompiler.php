<?php

/*
Generated by: Claude Code CLI

Date time: 2026/10/07 SAST

Version: 0.8.8.10

Description:
Turns a certificate design into the template HTML and CSS the document template engine renders, so
a design is drawn by the same renderer and PDF engine as every other document and its saved version
is as immutable as any template version.

The sheet is the background picture across all of A4 landscape (asset:<sha256>, embedded by the
renderer) with one absolutely positioned box of words on top. The box is a fixed-height table in
millimetres - head, a middle centred vertically in the space left, and a foot with the signature
and small print - because Dompdf lays tables out reliably and does not do flexbox. Its id,
cd-layout, is what the fit check measures: a box that is too full grows taller than the look allows.

Pure: no database. An installed look's background is addressed by the SHA-256 of its file, which
the installation stores in document_assets (and CertificateDesignService stores again on save).

Changelog:
2026/10/07 SAST
- Created for certificate designs.
*/

declare(strict_types=1);

namespace CattoLearning\Course\Certificate;

use CattoLearning\Document\DocumentType;
use CattoLearning\Document\PageSettings;

final class CertificateDesignCompiler
{
    public const LAYOUT_ID = 'cd-layout';
    private const SIGNATURE_WIDTH = 72;

    /** @return array{html:string,css:string,settings:PageSettings,box_height_mm:int} */
    public function compile(CertificateDesign $design): array
    {
        $look = $design->lookDefinition();
        [$left, $top, $width, $height] = $look->box;
        $background = $design->isCustom() ? $design->background?->sha : self::lookBackgroundSha($look);
        [$head, $main] = CertificateWording::toTemplateParts($design->wording);
        $smallPrint = CertificateWording::toTemplate($design->smallPrint);
        $logo = $design->logo === null ? '' : '<p class="cd-logo-line">' . self::image('cd-logo', $design->logo, 13, 60) . '</p>';

        $rows = '';
        $hasHead = $head !== '' || $logo !== '';
        // A logo sits above the title, so the head grows by its height and the middle gives it up.
        $headHeight = $look->headHeight + ($logo !== '' ? 15 : 0);
        if ($hasHead) {
            $rows .= '<tr><td class="cd-head">' . $logo . $head . '</td></tr>';
        }
        $rows .= '<tr><td class="cd-main">' . $main . '</td></tr>';
        $band = '';
        $foot = $this->foot($look, $width, $this->signature($design), $look->smallPrint === 'band' ? '' : $smallPrint);
        if ($look->smallPrint === 'band' && $smallPrint !== '') {
            $band = '<div class="cd-band"><table class="cd-band-row"><tr><td>' . $smallPrint . '</td></tr></table></div>';
        }
        $rows .= '<tr><td class="cd-foot">' . $foot . '</td></tr>';

        $html = ($background !== null ? '<img class="cd-bg" src="asset:' . $background . '" alt="">' : '')
            . '<div class="cd-box"><table class="cd-layout" id="' . self::LAYOUT_ID . '">' . $rows . '</table></div>' . $band;
        $css = 'body{margin:0}'
            . '.cd-bg{position:absolute;left:0;top:0;width:297mm;height:210mm}'
            . sprintf('.cd-box{position:absolute;left:%dmm;top:%dmm;width:%dmm;height:%dmm}', $left, $top, $width, $height)
            . sprintf('.cd-layout{width:%dmm;height:%dmm;border-collapse:collapse}', $width, $height)
            . '.cd-layout td{padding:0}'
            . sprintf('.cd-head{vertical-align:top;height:%dmm}', $headHeight)
            // Dompdf does not share a table's spare height among its rows, so the middle row is given
            // what is left after the head and foot; the foot then sits on the box's bottom edge.
            . sprintf('.cd-main{vertical-align:middle;height:%dmm}', $height - ($hasHead ? $headHeight : 0) - $look->footHeight)
            . sprintf('.cd-foot{vertical-align:bottom;height:%dmm}', $look->footHeight)
            . '.cd-foot-row{width:100%;border-collapse:collapse}.cd-foot-row td{vertical-align:bottom;padding:0}'
            . 'p{margin:0 0 1.4mm}'
            . '.align-left{text-align:left}.align-center{text-align:center}.align-right{text-align:right}'
            . '.cd-logo-line{margin:0 0 2mm}'
            . '.cd-sign-image{display:block;margin:0 auto 1mm}'
            . '.cd-sign-line{border-top:0.3mm solid #333333;padding-top:1.4mm;text-align:center}'
            . '.cd-sign-position{text-align:center}'
            . '.cd-band{position:absolute}.cd-band-row{width:100%;height:10mm;border-collapse:collapse}.cd-band-row td{vertical-align:middle;padding:0}'
            . $look->css;
        return ['html' => $html, 'css' => $css, 'settings' => DocumentType::Certificate->defaultSettings(), 'box_height_mm' => $height];
    }

    /** The SHA-256 an installed look's background is stored under. */
    public static function lookBackgroundSha(CertificateLook $look): string
    {
        return (string) hash_file('sha256', $look->backgroundPath());
    }

    private function signature(CertificateDesign $design): string
    {
        if ($design->signature === null && trim($design->signatureName) === '' && trim($design->signaturePosition) === '') {
            return '';
        }
        $html = '<div class="cd-sign">';
        if ($design->signature !== null) {
            $html .= self::image('cd-sign-image', $design->signature, 14, 64);
        }
        $html .= '<div class="cd-sign-line">' . (trim($design->signatureName) === '' ? '&nbsp;' : self::text($design->signatureName)) . '</div>';
        if (trim($design->signaturePosition) !== '') {
            $html .= '<div class="cd-sign-position">' . self::text($design->signaturePosition) . '</div>';
        }
        return $html . '</div>';
    }

    /** The foot row: the signature in its 72 mm column and the small print beside it. */
    private function foot(CertificateLook $look, int $width, string $signature, string $smallPrint): string
    {
        $rest = $width - self::SIGNATURE_WIDTH;
        $small = static fn(int $cellWidth, string $align): string => sprintf('<td class="cd-small" style="width:%dmm;text-align:%s">%s</td>', $cellWidth, $align, $smallPrint);
        $sign = sprintf('<td class="cd-sign-cell" style="width:%dmm">%s</td>', self::SIGNATURE_WIDTH, $signature);
        $cells = match ($look->signature) {
            'left' => $sign . $small($rest, $look->smallPrint === 'center' ? 'center' : 'right'),
            'right' => $small($rest, $look->smallPrint === 'center' ? 'center' : 'left') . $sign,
            default => sprintf('<td class="cd-small" style="width:%dmm;text-align:left">%s</td>', intdiv($rest, 2), $look->smallPrint === 'left' ? $smallPrint : '')
                . $sign
                . sprintf('<td class="cd-small" style="width:%dmm;text-align:right">%s</td>', $rest - intdiv($rest, 2), $look->smallPrint === 'right' ? $smallPrint : ''),
        };
        return '<table class="cd-foot-row"><tr>' . $cells . '</tr></table>';
    }

    /** A stored picture at a fixed height, narrower if it would be wider than allowed. */
    private static function image(string $class, CertificateImage $image, int $heightMm, int $maxWidthMm): string
    {
        $height = (float) $heightMm;
        $width = $height * $image->width / $image->height;
        if ($width > $maxWidthMm) {
            [$width, $height] = [(float) $maxWidthMm, $maxWidthMm * $image->height / $image->width];
        }
        return sprintf('<img class="%s" src="asset:%s" alt="" style="width:%.1fmm;height:%.1fmm">', $class, $image->sha, $width, $height);
    }

    private static function text(string $text): string
    {
        return str_replace(['{', '}'], ['&#123;', '&#125;'], htmlspecialchars($text, ENT_QUOTES | ENT_HTML5));
    }
}
