Description:
Turns real CattoLMS completion data into the certificate placeholders the document template engine
renders (PlaceholderRegistry, certificate type). One assembly step serves issuing, the course's
certificate preview and the Seed Database, so a certificate's values come from one place:

- certificate.* : the number and public verification address minted for it, the course's title,
  body and footer wording, and the issue time;
- learner.name : the learner's certificate name, else their display name, else their email;
- course.*     : the course title, the provider (the course's owner company, else the System
  Company, else the platform name) and the completion time;
- result.*     : the course result's overall percentage and grade, when the course has one;
- signatory.*  : the course's signatory name and title;
- business.*   : DocumentBusinessData.

The values are stored with the certificate exactly as built (CertificateIssuer), so a certificate
keeps the names, titles and dates it was issued with.

Changelog:
2026/10/07 SAST
- Created for certificates on the document template engine (Phase J).
