namespace CattoLearning\Course\Certificate;

use CattoLearning\Course\CourseRepository;
use CattoLearning\Document\DocumentBusinessData;
use CattoLearning\Support\Env;
use DateTimeImmutable;
use RuntimeException;

final class CertificateDocumentDataBuilder
{
    public function __construct(
        private readonly CertificateRepository $certificates,
        private readonly CourseRepository $courses,
        private readonly DocumentBusinessData $business,
    ) {}

    /**
     * The certificate values for an enrolment at the moment of issue.
     *
     * @return array<string,mixed>
     */
    public function forIssue(int $enrolmentId, string $certificateNumber, string $publicId, DateTimeImmutable $issuedAt, string $verifiedName): array
    {
        $row = $this->certificates->issueContext($enrolmentId);
        if ($row === null) {
            throw new RuntimeException('Enrolment ' . $enrolmentId . ' does not exist; no certificate can be issued.');
        }
        $completed = trim((string) ($row['completed_at'] ?? ''));
        return self::assemble(
            $this->business->values(),
            $row,
            $verifiedName,
            $this->courses->certificateProviderName((int) $row['course_id']),
            $certificateNumber,
            self::verificationUrl($publicId),
            $issuedAt->format(DATE_ATOM),
            $completed !== '' ? (new DateTimeImmutable($completed))->format(DATE_ATOM) : $issuedAt->format(DATE_ATOM),
        );
    }

    /**
     * A course's certificate as it would be issued to a sample learner today, for the course's
     * certificate page. Nothing is issued or stored.
     *
     * @param array<string,mixed> $course
     * @return array<string,mixed>
     */
    public function forPreview(array $course, string $learnerName): array
    {
        $now = (new DateTimeImmutable())->format(DATE_ATOM);
        return self::assemble(
            $this->business->values(),
            $course,
            $learnerName,
            $this->courses->certificateProviderName((int) $course['id']),
            'CL-PREVIEW-000001',
            self::verificationUrl('sample'),
            $now,
            $now,
        );
    }

    /**
     * The certificate placeholders from their parts. Optional values that are absent stay null, so a
     * template's {{#if}} leaves them out.
     *
     * @param array<string,mixed> $business business.* values
     * @param array<string,mixed> $course the course's title and certificate_accreditation
     * @return array<string,mixed>
     */
    public static function assemble(array $business, array $course, string $learnerName, string $provider, string $certificateNumber, ?string $verificationUrl, string $issuedAt, string $completedAt): array
    {
        $optional = static fn(mixed $value): ?string => ($value = trim((string) $value)) === '' ? null : $value;
        return $business + [
            'certificate.number' => $certificateNumber,
            'certificate.issue_date' => $issuedAt,
            'certificate.verification_url' => $verificationUrl,
            'learner.name' => $learnerName,
            'course.title' => (string) $course['title'],
            'course.provider' => $optional($provider),
            'course.completion_date' => $completedAt,
            'course.accreditation' => $optional($course['certificate_accreditation'] ?? null),
        ];
    }

    /** The public page that verifies a certificate, when the installation knows its own address. */
    public static function verificationUrl(string $publicId): ?string
    {
        $base = rtrim(Env::string('APP_URL'), '/');
        return preg_match('#^https?://#i', $base) === 1 ? $base . '/certificates/' . $publicId : null;
    }
}
