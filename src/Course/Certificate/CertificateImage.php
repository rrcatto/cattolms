Description:
A picture on a certificate design - its background, logo or signature - as stored in
document_assets: the SHA-256 of its bytes and its size in pixels. fromBytes() checks an uploaded
file and prepares it: PNG or JPEG only, read by GD, a background in A4 landscape proportions and
scaled to 2480 x 1754 (about 212 dpi, which prints sharply and keeps a render well inside PHP's
memory), a logo or signature scaled down to fit its box. Nothing is cropped. A background prints
opaque, so any transparency in it is flattened onto white: Dompdf separates a PNG's alpha channel
pixel by pixel, which made every certificate on a transparent full-page background take seconds to
draw. A logo or signature keeps its transparency, so it sits cleanly on the background.

Changelog:
2026/10/07 SAST
- Created for certificate designs (uploaded Canva backgrounds, logos and signatures).
- A background is stored without an alpha channel.
