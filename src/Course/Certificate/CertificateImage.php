declare(strict_types=1);

namespace CattoLearning\Course\Certificate;

use InvalidArgumentException;

final class CertificateImage
{
    public const BACKGROUND = 'background';
    public const LOGO = 'logo';
    public const SIGNATURE = 'signature';
    public const MAX_UPLOAD_BYTES = 12 * 1024 * 1024;
    /** The stored size of a background: A4 landscape at about 212 dpi. */
    public const BACKGROUND_SIZE = [2480, 1754];
    /** The largest stored logo and signature, in pixels. */
    private const BOXES = [self::LOGO => [1200, 600], self::SIGNATURE => [1200, 400]];
    private const LABELS = [self::BACKGROUND => 'background', self::LOGO => 'logo', self::SIGNATURE => 'signature'];

    public function __construct(
        public readonly string $sha,
        public readonly int $width,
        public readonly int $height,
    ) {
        if (preg_match('/^[0-9a-f]{64}$/D', $sha) !== 1 || $width < 1 || $height < 1) {
            throw new InvalidArgumentException('A certificate picture needs its stored address and size.');
        }
    }

    /** @param array<string,mixed>|null $row as stored in a design */
    public static function fromArray(?array $row): ?self
    {
        if ($row === null || !isset($row['sha'], $row['width'], $row['height'])) {
            return null;
        }
        return new self((string) $row['sha'], (int) $row['width'], (int) $row['height']);
    }

    /** @return array{sha:string,width:int,height:int} */
    public function toArray(): array
    {
        return ['sha' => $this->sha, 'width' => $this->width, 'height' => $this->height];
    }

    /**
     * An uploaded file checked and prepared for storing.
     *
     * @return array{bytes:string,mime:string,width:int,height:int}
     * @throws InvalidArgumentException with a message for the person who uploaded it
     */
    public static function prepare(string $bytes, string $kind): array
    {
        $label = self::LABELS[$kind] ?? throw new InvalidArgumentException('Unknown certificate picture.');
        if ($bytes === '' || strlen($bytes) > self::MAX_UPLOAD_BYTES) {
            throw new InvalidArgumentException('The ' . $label . ' must be a PNG or JPEG file of at most 12 MB.');
        }
        $info = @getimagesizefromstring($bytes);
        $mime = is_array($info) ? $info['mime'] : '';
        if (!in_array($mime, ['image/png', 'image/jpeg'], true)) {
            throw new InvalidArgumentException('The ' . $label . ' must be a PNG or JPEG picture. From Canva, choose Download → PNG.');
        }
        [$width, $height] = [(int) $info[0], (int) $info[1]];
        if ($kind === self::BACKGROUND) {
            $ratio = $width / max(1, $height);
            if (abs($ratio - 297 / 210) > 0.05) {
                throw new InvalidArgumentException('The background must be A4 landscape (297 × 210 mm, for example 3508 × 2480 px). This picture is ' . $width . ' × ' . $height . ' px.');
            }
            if ($width < 1240) {
                throw new InvalidArgumentException('The background is too small to print sharply: it needs to be at least 1240 px wide. From Canva, choose the largest size.');
            }
            [$targetWidth, $targetHeight] = self::BACKGROUND_SIZE;
        } else {
            [$boxWidth, $boxHeight] = self::BOXES[$kind];
            $scale = min(1.0, $boxWidth / $width, $boxHeight / $height);
            [$targetWidth, $targetHeight] = [max(1, (int) round($width * $scale)), max(1, (int) round($height * $scale))];
        }
        $opaque = $kind === self::BACKGROUND;
        if ($targetWidth === $width && $targetHeight === $height && !($opaque && self::hasTransparency($bytes, $mime))) {
            return ['bytes' => $bytes, 'mime' => $mime, 'width' => $width, 'height' => $height];
        }
        return ['bytes' => self::resample($bytes, $mime, $targetWidth, $targetHeight, !$opaque), 'mime' => $mime, 'width' => $targetWidth, 'height' => $targetHeight];
    }

    /** Whether a PNG has an alpha channel or a transparent colour (a tRNS chunk before its image data). */
    private static function hasTransparency(string $bytes, string $mime): bool
    {
        if ($mime !== 'image/png') {
            return false;
        }
        $data = strpos($bytes, 'IDAT');
        $transparent = strpos($bytes, 'tRNS');
        return in_array(ord($bytes[25] ?? "\0"), [4, 6], true) || ($transparent !== false && ($data === false || $transparent < $data));
    }

    private static function resample(string $bytes, string $mime, int $width, int $height, bool $keepTransparency): string
    {
        $source = @imagecreatefromstring($bytes);
        if ($source === false) {
            throw new InvalidArgumentException('The picture could not be read. Save it again as PNG or JPEG.');
        }
        $target = imagecreatetruecolor($width, $height);
        if ($mime === 'image/png' && $keepTransparency) {
            imagealphablending($target, false);
            imagesavealpha($target, true);
            imagefill($target, 0, 0, (int) imagecolorallocatealpha($target, 0, 0, 0, 127));
        } else {
            imagefill($target, 0, 0, (int) imagecolorallocate($target, 255, 255, 255));
        }
        imagecopyresampled($target, $source, 0, 0, 0, 0, $width, $height, imagesx($source), imagesy($source));
        ob_start();
        $mime === 'image/png' ? imagepng($target, null, 6) : imagejpeg($target, null, 90);
        return (string) ob_get_clean();
    }
}
