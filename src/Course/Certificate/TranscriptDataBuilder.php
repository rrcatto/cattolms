declare(strict_types=1);

namespace CattoLearning\Course\Certificate;

use CattoLearning\Course\AssessmentRepository;
use CattoLearning\Course\CourseItemRepository;
use CattoLearning\Course\CourseRepository;
use CattoLearning\Course\ScorePolicy;
use CattoLearning\Document\DocumentBusinessData;
use CattoLearning\Support\Env;
use DateTimeImmutable;
use RuntimeException;

final class TranscriptDataBuilder
{
    public function __construct(
        private readonly CertificateRepository $certificates,
        private readonly CourseRepository $courses,
        private readonly CourseItemRepository $items,
        private readonly AssessmentRepository $assessments,
        private readonly DocumentBusinessData $business,
    ) {}

    /** @return array<string,mixed> */
    public function forIssue(int $enrolmentId, string $transcriptNumber, string $publicId, string $certificateNumber, DateTimeImmutable $issuedAt, string $verifiedName): array
    {
        $row = $this->certificates->issueContext($enrolmentId) ?? throw new RuntimeException('Enrolment ' . $enrolmentId . ' does not exist; no transcript can be issued.');
        $completed = trim((string) ($row['completed_at'] ?? ''));
        $assessments = $this->marks($enrolmentId, (int) $row['course_id']);
        $hasModules = array_filter($assessments, static fn(array $a): bool => $a['kind'] === 'Module assessment') !== [];
        $optional = static fn(mixed $value): ?string => ($value = trim((string) $value)) === '' ? null : $value;
        return $this->business->values() + [
            'transcript.number' => $transcriptNumber,
            'transcript.certificate_number' => $certificateNumber,
            'transcript.issue_date' => $issuedAt->format(DATE_ATOM),
            'transcript.verification_url' => self::verificationUrl($publicId),
            'learner.name' => $verifiedName,
            'course.title' => (string) $row['title'],
            'course.provider' => $optional($this->courses->certificateProviderName((int) $row['course_id'])),
            'course.completion_date' => $completed !== '' ? (new DateTimeImmutable($completed))->format(DATE_ATOM) : $issuedAt->format(DATE_ATOM),
            'course.accreditation' => $optional($row['certificate_accreditation'] ?? null),
            'result.module_average' => $hasModules ? self::percent($row['module_percentage'] ?? 0) : null,
            'result.final' => self::percent($row['final_percentage'] ?? 0),
            'result.overall' => self::percent($row['overall_percentage'] ?? 0),
            'result.grade' => $optional($row['grade_code'] ?? null),
            'assessments' => $assessments,
        ];
    }

    /**
     * Every graded assessment of the course with the mark that counts, in course order.
     *
     * @return list<array{title:string,kind:string,mark:string}>
     */
    public function marks(int $enrolmentId, int $courseId): array
    {
        $order = [];
        foreach ($this->items->structure($courseId) as $position => $node) {
            $order[(int) $node['id']] = $position;
        }
        $contexts = $this->items->assessmentContexts($courseId, $enrolmentId);
        usort($contexts, static fn(array $a, array $b): int => [($order[(int) $a['node_id']] ?? PHP_INT_MAX), $a['assessment_role'] === 'final' ? 1 : 0, (int) $a['course_item_id']]
            <=> [($order[(int) $b['node_id']] ?? PHP_INT_MAX), $b['assessment_role'] === 'final' ? 1 : 0, (int) $b['course_item_id']]);
        $marks = [];
        foreach ($contexts as $context) {
            $scores = $this->assessments->completedPercentages($enrolmentId, (int) $context['course_item_id'], (int) $context['node_id']);
            if ($scores === []) continue;
            $marks[] = [
                'title' => mb_substr((string) ($context['item_title'] ?? $context['item_key']), 0, 240),
                'kind' => $context['assessment_role'] === 'final' ? 'Final assessment' : 'Module assessment',
                'mark' => self::percent(ScorePolicy::aggregate($scores, (string) $context['score_policy'])),
            ];
        }
        return $marks;
    }

    /** The public page that verifies a transcript, when the installation knows its own address. */
    public static function verificationUrl(string $publicId): ?string
    {
        $base = rtrim(Env::string('APP_URL'), '/');
        return preg_match('#^https?://#i', $base) === 1 ? $base . '/transcripts/' . $publicId : null;
    }

    private static function percent(mixed $value): string
    {
        return number_format(max(0.0, min(100.0, (float) $value)), 2, '.', '');
    }
}
