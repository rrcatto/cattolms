/*
Generated by: Claude Code CLI

Date time: 2026/10/07 SAST

Version: 0.8.8.10

Description:
A certificate design's words - the wording and the small print - between the editor and the
document template engine.

The editor (CKEditor with the certificate profile, public_html/js/ck-certificate.js) writes
paragraphs, each optionally in one of the text styles below and aligned left, centre or right,
holding text, bold, italic, line breaks and fields. A field is
<span class="cl-field" data-field="learner.name">Learner name</span>: the author sees a label and
never the template language. Without JavaScript the same field can be typed as [Learner name].

normalize() reads whatever was posted into that one stored form, keeping only those constructs: an
unknown element is unwrapped to its text and an unknown style is dropped, so pasted formatting never
reaches a certificate. toTemplate() turns the stored form into template HTML for the engine: a field
becomes {{ placeholder }}, a paragraph holding an optional field is wrapped in {{#if}} so a line
whose field is empty is left out, and every literal brace is written as an entity so nothing typed
can become template syntax.

Changelog:
2026/10/07 SAST
- Created for certificate designs.
*/

declare(strict_types=1);

namespace CattoLearning\Course\Certificate;

use Dom\Element;
use Dom\HTMLDocument;
use Dom\Node;

final class CertificateWording
{
    /** placeholder => [label, optional]. A paragraph holding an optional field is left out when it is empty. */
    public const FIELDS = [
        'learner.name' => ['Learner name', false],
        'course.title' => ['Course title', false],
        'course.completion_date' => ['Completion date', false],
        'certificate.issue_date' => ['Date issued', false],
        'result.percentage' => ['Result', true],
        'result.grade' => ['Grade', true],
        'course.accreditation' => ['Accreditation line', true],
        'course.provider' => ['Course provider', true],
        'certificate.number' => ['Certificate number', false],
        'certificate.verification_url' => ['Verification address', true],
    ];
    /** class => label, in the order the editor offers them; a paragraph without one is normal text. */
    public const STYLES = ['cert-title' => 'Certificate title', 'cert-name' => 'Learner name', 'cert-course' => 'Course title', 'cert-caps' => 'Small capitals', 'cert-small' => 'Small text'];
    public const ALIGNMENTS = ['align-left', 'align-center', 'align-right'];
    private const LIMIT = 20000;
    private const PARAGRAPHS = 40;

    /** A field as the editor stores it. */
    public static function chip(string $path): string
    {
        return '<span class="cl-field" data-field="' . $path . '">' . self::FIELDS[$path][0] . '</span>';
    }

    /** @return list<array{path:string,label:string,optional:bool}> for the editor's Insert field menu */
    public static function fields(): array
    {
        $fields = [];
        foreach (self::FIELDS as $path => [$label, $optional]) {
            $fields[] = ['path' => $path, 'label' => $label, 'optional' => $optional];
        }
        return $fields;
    }

    /**
     * The posted words in their stored form, and what is wrong with them.
     *
     * @return array{html:string,errors:list<string>}
     */
    public static function normalize(string $posted, string $label): array
    {
        $posted = trim($posted);
        if ($posted !== '' && !str_contains($posted, '<')) {
            // Typed without the editor: each line is a paragraph.
            $posted = implode('', array_map(static fn(string $line): string => '<p>' . htmlspecialchars($line, ENT_QUOTES | ENT_HTML5) . '</p>', preg_split('/\R/', $posted) ?: []));
        }
        $document = HTMLDocument::createFromString('<!DOCTYPE html><html><body>' . $posted . '</body></html>', LIBXML_NOERROR);
        $paragraphs = [];
        foreach ($document->body->childNodes as $node) {
            foreach (self::blocks($node) as $paragraph) {
                $paragraphs[] = $paragraph;
            }
        }
        while ($paragraphs !== [] && self::isBlank(end($paragraphs))) {
            array_pop($paragraphs);
        }
        $html = implode('', $paragraphs);
        $errors = [];
        if (count($paragraphs) > self::PARAGRAPHS) {
            $errors[] = 'The ' . $label . ' can have at most ' . self::PARAGRAPHS . ' lines.';
        }
        if (mb_strlen($html) > self::LIMIT) {
            $errors[] = 'The ' . $label . ' is too long.';
        }
        return ['html' => $html, 'errors' => $errors];
    }

    /**
     * The fields a stored text uses.
     *
     * @return list<string>
     */
    public static function fieldsUsed(string $stored): array
    {
        preg_match_all('/data-field="([a-z_.]+)"/', $stored, $found);
        return array_values(array_unique(array_intersect($found[1], array_keys(self::FIELDS))));
    }

    /** Template HTML for the engine, one string. */
    public static function toTemplate(string $stored): string
    {
        return implode('', array_column(self::templateParagraphs($stored), 'html'));
    }

    /**
     * The wording split where the certificate title ends: the head is every paragraph up to and
     * including the first one in the Certificate title style, the rest is the middle. Without a
     * title, everything is the middle.
     *
     * @return array{0:string,1:string} head and middle template HTML
     */
    public static function toTemplateParts(string $stored): array
    {
        $paragraphs = self::templateParagraphs($stored);
        foreach ($paragraphs as $index => $paragraph) {
            if ($paragraph['title']) {
                return [implode('', array_column(array_slice($paragraphs, 0, $index + 1), 'html')), implode('', array_column(array_slice($paragraphs, $index + 1), 'html'))];
            }
        }
        return ['', implode('', array_column($paragraphs, 'html'))];
    }

    /** @return list<array{html:string,title:bool}> */
    private static function templateParagraphs(string $stored): array
    {
        if (trim($stored) === '') {
            return [];
        }
        $document = HTMLDocument::createFromString('<!DOCTYPE html><html><body>' . $stored . '</body></html>', LIBXML_NOERROR);
        $out = [];
        foreach ($document->body->childNodes as $node) {
            if (!$node instanceof Element || strtolower($node->localName) !== 'p') {
                continue;
            }
            $classes = self::classes($node);
            $optional = [];
            $content = self::templateInline($node, $optional);
            $html = '<p' . ($classes === [] ? '' : ' class="' . implode(' ', $classes) . '"') . '>' . ($content === '' ? '&nbsp;' : $content) . '</p>';
            foreach (array_reverse(array_values(array_unique($optional))) as $path) {
                $html = '{{#if ' . $path . '}}' . $html . '{{/if}}';
            }
            $out[] = ['html' => $html, 'title' => in_array('cert-title', $classes, true)];
        }
        return $out;
    }

    /** @param list<string> $optional the optional fields met, collected */
    private static function templateInline(Node $parent, array &$optional): string
    {
        $out = '';
        foreach ($parent->childNodes as $node) {
            if ($node instanceof Element) {
                $tag = strtolower($node->localName);
                if ($tag === 'span' && isset(self::FIELDS[(string) $node->getAttribute('data-field')])) {
                    $path = (string) $node->getAttribute('data-field');
                    if (self::FIELDS[$path][1]) {
                        $optional[] = $path;
                    }
                    $out .= '{{ ' . $path . ' }}';
                } elseif ($tag === 'br') {
                    $out .= '<br>';
                } elseif (in_array($tag, ['strong', 'em'], true)) {
                    $out .= '<' . $tag . '>' . self::templateInline($node, $optional) . '</' . $tag . '>';
                } else {
                    $out .= self::templateInline($node, $optional);
                }
            } elseif ($node->nodeType === XML_TEXT_NODE) {
                $out .= str_replace(['{', '}'], ['&#123;', '&#125;'], htmlspecialchars((string) $node->textContent, ENT_QUOTES | ENT_HTML5));
            }
        }
        return $out;
    }

    /** @return list<string> stored paragraphs */
    private static function blocks(Node $node): array
    {
        if ($node instanceof Element) {
            $tag = strtolower($node->localName);
            if (in_array($tag, ['ul', 'ol', 'div', 'section', 'blockquote', 'table', 'tbody', 'thead', 'tr'], true)) {
                $out = [];
                foreach ($node->childNodes as $child) {
                    $out = [...$out, ...self::blocks($child)];
                }
                return $out;
            }
            if ($tag === 'br') {
                return [];
            }
            if (in_array($tag, ['p', 'li', 'td', 'th', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6'], true)) {
                $classes = $tag === 'p' ? self::classes($node) : ($tag === 'h1' ? ['cert-title'] : []);
                $content = self::inline($node);
                return ['<p' . ($classes === [] ? '' : ' class="' . implode(' ', $classes) . '"') . '>' . ($content === '' ? '&nbsp;' : $content) . '</p>'];
            }
            $content = self::inline($node);
            return $content === '' ? [] : ['<p>' . $content . '</p>'];
        }
        if ($node->nodeType === XML_TEXT_NODE && trim((string) $node->textContent) !== '') {
            return ['<p>' . self::text((string) $node->textContent) . '</p>'];
        }
        return [];
    }

    private static function inline(Node $parent): string
    {
        $out = '';
        foreach ($parent->childNodes as $node) {
            if ($node instanceof Element) {
                $tag = strtolower($node->localName);
                $field = (string) $node->getAttribute('data-field');
                if ($tag === 'span' && isset(self::FIELDS[$field])) {
                    $out .= self::chip($field);
                } elseif ($tag === 'br') {
                    $out .= '<br>';
                } elseif (in_array($tag, ['strong', 'b'], true)) {
                    $inner = self::inline($node);
                    $out .= $inner === '' ? '' : '<strong>' . $inner . '</strong>';
                } elseif (in_array($tag, ['em', 'i'], true)) {
                    $inner = self::inline($node);
                    $out .= $inner === '' ? '' : '<em>' . $inner . '</em>';
                } elseif (!in_array($tag, ['script', 'style', 'template'], true)) {
                    $out .= self::inline($node);
                }
            } elseif ($node->nodeType === XML_TEXT_NODE) {
                $out .= self::text((string) $node->textContent);
            }
        }
        return trim(str_replace("\u{00A0}", ' ', $out)) === '' && !str_contains($out, 'cl-field') ? '' : $out;
    }

    /** Text with [Label] read as the field of that label. */
    private static function text(string $text): string
    {
        $labels = [];
        foreach (self::FIELDS as $path => [$label]) {
            $labels[strtolower($label)] = $path;
        }
        $parts = preg_split('/(\[[^\[\]]{2,40}\])/', $text, -1, PREG_SPLIT_DELIM_CAPTURE) ?: [];
        $out = '';
        foreach ($parts as $part) {
            $path = str_starts_with($part, '[') ? ($labels[strtolower(trim($part, '[] '))] ?? null) : null;
            $out .= $path !== null ? self::chip($path) : htmlspecialchars($part, ENT_QUOTES | ENT_HTML5);
        }
        return $out;
    }

    /** @return list<string> the paragraph's style and alignment classes, at most one of each */
    private static function classes(Element $element): array
    {
        $tokens = preg_split('/\s+/', trim((string) $element->getAttribute('class'))) ?: [];
        $style = array_values(array_intersect($tokens, array_keys(self::STYLES)));
        $align = array_values(array_intersect($tokens, self::ALIGNMENTS));
        return [...array_slice($style, 0, 1), ...array_slice($align, 0, 1)];
    }

    private static function isBlank(string $paragraph): bool
    {
        return preg_match('#^<p[^>]*>&nbsp;</p>$#', $paragraph) === 1;
    }
}
