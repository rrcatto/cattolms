What a certificate design is, as the author made it: its look (an installed look, or an uploaded
background with the placement, typeface and colour chosen for it), an optional logo, the wording,
the signatory and signature picture, and the small print. Each saved design version keeps this in
document_template_versions.design beside the template HTML and CSS compiled from it
(CertificateDesignCompiler), so the editor always reopens what the author saw.

The wording and small print are in CertificateWording's stored form.

Changelog:
