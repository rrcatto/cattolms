declare(strict_types=1);

namespace CattoLearning\Course\Certificate;

use InvalidArgumentException;

final class CertificateDesign
{
    public const NAME_LIMIT = 120;
    public const SIGNATURE_NAME_LIMIT = 120;
    public const SIGNATURE_POSITION_LIMIT = 160;
    public const DEFAULT_COLOUR = '#1F3A5F';

    public function __construct(
        public readonly string $look,
        public readonly ?CertificateImage $background,
        public readonly string $placement,
        public readonly string $typeface,
        public readonly string $colour,
        public readonly ?CertificateImage $logo,
        public readonly string $wording,
        public readonly string $signatureName,
        public readonly string $signaturePosition,
        public readonly ?CertificateImage $signature,
        public readonly string $smallPrint,
    ) {}

    /** A new design on an installed look, as it is installed. */
    public static function starter(string $look, string $signatureName = '', string $signaturePosition = ''): self
    {
        return new self($look, null, 'centre', 'serif', self::DEFAULT_COLOUR, null,
            CertificateLooks::defaultWording($look), $signatureName, $signaturePosition, null, CertificateLooks::defaultSmallPrint());
    }

    /** @param array<string,mixed> $stored */
    public static function fromArray(array $stored): self
    {
        return new self(
            (string) ($stored['look'] ?? 'classic'),
            CertificateImage::fromArray(is_array($stored['background'] ?? null) ? $stored['background'] : null),
            (string) ($stored['placement'] ?? 'centre'),
            (string) ($stored['typeface'] ?? 'serif'),
            (string) ($stored['colour'] ?? self::DEFAULT_COLOUR),
            CertificateImage::fromArray(is_array($stored['logo'] ?? null) ? $stored['logo'] : null),
            (string) ($stored['wording'] ?? ''),
            (string) ($stored['signature_name'] ?? ''),
            (string) ($stored['signature_position'] ?? ''),
            CertificateImage::fromArray(is_array($stored['signature'] ?? null) ? $stored['signature'] : null),
            (string) ($stored['small_print'] ?? ''),
        );
    }

    /** @return array<string,mixed> */
    public function toArray(): array
    {
        return [
            'look' => $this->look,
            'background' => $this->background?->toArray(),
            'placement' => $this->placement,
            'typeface' => $this->typeface,
            'colour' => $this->colour,
            'logo' => $this->logo?->toArray(),
            'wording' => $this->wording,
            'signature_name' => $this->signatureName,
            'signature_position' => $this->signaturePosition,
            'signature' => $this->signature?->toArray(),
            'small_print' => $this->smallPrint,
        ];
    }

    public function isCustom(): bool
    {
        return $this->look === CertificateLooks::CUSTOM;
    }

    /**
     * The look the compiler lays the design out with. Only a #RRGGBB colour ever reaches the CSS, even
     * for a preview of a form that has not been checked yet.
     */
    public function lookDefinition(): CertificateLook
    {
        $colour = preg_match('/^#[0-9A-Fa-f]{6}$/D', $this->colour) === 1 ? $this->colour : self::DEFAULT_COLOUR;
        return $this->isCustom()
            ? CertificateLooks::custom($this->placement, $this->typeface, $colour)
            : CertificateLooks::get($this->look);
    }

    /**
     * Everything that stops this design from being saved, in the words its author needs.
     *
     * @return list<string>
     */
    public function problems(): array
    {
        $errors = [];
        if (!$this->isCustom() && !isset(CertificateLooks::installed()[$this->look])) {
            $errors[] = 'Choose one of the looks, or upload your own background.';
        }
        if ($this->isCustom() && $this->background === null) {
            $errors[] = 'Upload your background, or choose one of the looks.';
        }
        if (!isset(CertificateLooks::PLACEMENTS[$this->placement])) {
            $errors[] = 'Choose where the words go.';
        }
        if (!isset(CertificateLooks::TYPEFACES[$this->typeface])) {
            $errors[] = 'Choose a typeface.';
        }
        if (preg_match('/^#[0-9A-Fa-f]{6}$/D', $this->colour) !== 1) {
            $errors[] = 'Choose the title and name colour.';
        }
        if (!in_array('learner.name', CertificateWording::fieldsUsed($this->wording), true)) {
            $errors[] = 'The wording must include the Learner name field: use Insert field.';
        }
        if (mb_strlen($this->signatureName) > self::SIGNATURE_NAME_LIMIT) {
            $errors[] = 'The signatory’s name can be at most ' . self::SIGNATURE_NAME_LIMIT . ' characters.';
        }
        if (mb_strlen($this->signaturePosition) > self::SIGNATURE_POSITION_LIMIT) {
            $errors[] = 'The signatory’s position can be at most ' . self::SIGNATURE_POSITION_LIMIT . ' characters.';
        }
        return $errors;
    }

    /** @throws InvalidArgumentException when the design cannot be saved */
    public function assertValid(): void
    {
        $errors = $this->problems();
        if ($errors !== []) {
            throw new InvalidArgumentException(implode(' ', $errors));
        }
    }
}
