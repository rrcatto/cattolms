declare(strict_types=1);

namespace CattoLearning\Course\Certificate;

use CattoLearning\Document\DocumentTemplateRenderer;
use CattoLearning\Document\DocumentType;
use CattoLearning\Identity\IdentityVerificationRepository;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use DateTimeImmutable;
use Symfony\Component\Clock\ClockInterface;
use RuntimeException;
use Throwable;

final class CertificateIssuer
{
    public function __construct(
        private readonly CertificateRepository $certificates,
        private readonly CertificateDocumentDataBuilder $data,
        private readonly TranscriptDataBuilder $transcripts,
        private readonly CertificateDesignRepository $designs,
        private readonly DocumentTemplateRenderer $renderer,
        private readonly IdentityVerificationRepository $identities,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
        private readonly ClockInterface $clock,
    ) {}

    /** @return array<string,mixed> the issued certificate */
    public function issue(int $enrolmentId, ?int $actorUserId = null): array
    {
        return $this->transactions->run(function () use ($enrolmentId, $actorUserId): array {
            $context = $this->certificates->issueContext($enrolmentId) ?? throw new RuntimeException('The enrolment does not exist.');
            $verification = $this->identities->approved((int) $context['user_id'])
                ?? throw new RuntimeException('A certificate is issued only to a verified account.');
            $existing = $this->certificates->identityForEnrolment($enrolmentId);
            if ($existing !== null && $existing['revoked_at'] !== null) {
                return $this->certificates->forEnrolment($enrolmentId) ?? throw new RuntimeException('The certificate could not be read.');
            }
            $publicId = $existing['public_id'] ?? CertificateAddress::generate();
            $number = $existing['certificate_number'] ?? $this->newNumber();
            $issuedAt = DateTimeImmutable::createFromInterface($this->clock->now());
            $name = (string) $verification['verified_name'];
            $data = $this->data->forIssue($enrolmentId, $number, $publicId, $issuedAt, $name);
            try {
                $version = $this->designs->versionForEnrolment($enrolmentId) ?? throw new RuntimeException('the course has no certificate design.');
                $reference = $this->renderer->renderVersion($version['version_id'], $data)->reference();
            } catch (Throwable $failed) {
                throw new RuntimeException('The certificate could not be issued: ' . $failed->getMessage(), 0, $failed);
            }
            // The completion date the certificate states is the one it stores.
            $certificate = $this->certificates->store($enrolmentId, $publicId, $number, $data, $reference, $issuedAt, (string) $data['course.completion_date'], (int) $verification['id']);
            $transcript = $this->issueTranscript((int) $certificate['id'], $enrolmentId, $number, $issuedAt, $name);
            $this->audit->record($actorUserId, $existing === null ? 'certificate.issued' : 'certificate.reissued', [
                'certificate_id' => (int) $certificate['id'], 'enrolment_id' => $enrolmentId, 'user_id' => (int) $context['user_id'],
                'course_id' => (int) $context['course_id'], 'certificate_number' => $number, 'transcript_number' => $transcript['transcript_number'],
                'template_id' => $reference['template_id'], 'template_version_id' => $reference['template_version_id'],
                'template_version_number' => $reference['template_version_number'],
            ]);
            return $this->certificates->forEnrolment($enrolmentId) ?? $certificate;
        });
    }

    /** @return array<string,mixed> */
    private function issueTranscript(int $certificateId, int $enrolmentId, string $certificateNumber, DateTimeImmutable $issuedAt, string $name): array
    {
        $existing = $this->certificates->transcriptIdentity($certificateId);
        $publicId = $existing['public_id'] ?? CertificateAddress::generate();
        $number = $existing['transcript_number'] ?? 'TR-' . substr($certificateNumber, 3);
        $data = $this->transcripts->forIssue($enrolmentId, $number, $publicId, $certificateNumber, $issuedAt, $name);
        try {
            $reference = $this->renderer->renderCurrent(DocumentType::Transcript, $data)->reference();
        } catch (Throwable $failed) {
            throw new RuntimeException('The transcript could not be issued: ' . $failed->getMessage(), 0, $failed);
        }
        return $this->certificates->storeTranscript($certificateId, $publicId, $number, $data, $reference, $issuedAt);
    }

    /**
     * CL-<UTC year>-<twelve hex digits>, minted once per certificate. The digits are random and nothing
     * to do with the certificate's address, so a printed number never gives the address away
     * (owner, 2026-10-19).
     */
    public static function number(string $serial, \DateTimeInterface $at): string
    {
        $year = DateTimeImmutable::createFromInterface($at)->setTimezone(new \DateTimeZone('UTC'))->format('Y');
        return 'CL-' . $year . '-' . strtoupper(substr($serial, 0, 12));
    }

    /** A certificate number no other certificate has. */
    private function newNumber(): string
    {
        for ($try = 0; $try < 5; $try++) {
            $number = self::number(bin2hex(random_bytes(6)), $this->clock->now());
            if (!$this->certificates->numberTaken($number)) return $number;
        }
        throw new RuntimeException('No unused certificate number could be found.');
    }
}
