declare(strict_types=1);

namespace CattoLearning\Course\Certificate;

use CattoLearning\Document\DocumentTemplateRenderer;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\Uuid;
use DateTimeImmutable;
use Symfony\Component\Clock\ClockInterface;
use RuntimeException;
use Throwable;

final class CertificateIssuer
{
    public function __construct(
        private readonly CertificateRepository $certificates,
        private readonly CertificateDocumentDataBuilder $data,
        private readonly CertificateDesignRepository $designs,
        private readonly DocumentTemplateRenderer $renderer,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
        private readonly ClockInterface $clock,
    ) {}

    /** @return array<string,mixed> the issued certificate */
    public function issue(int $enrolmentId, ?int $actorUserId = null): array
    {
        return $this->transactions->run(function () use ($enrolmentId, $actorUserId): array {
            $existing = $this->certificates->identityForEnrolment($enrolmentId);
            $publicId = $existing['public_id'] ?? Uuid::v4();
            $number = $existing['certificate_number'] ?? self::number($publicId, $this->clock->now());
            $issuedAt = DateTimeImmutable::createFromInterface($this->clock->now());
            $data = $this->data->forIssue($enrolmentId, $number, $publicId, $issuedAt);
            try {
                $version = $this->designs->versionForEnrolment($enrolmentId) ?? throw new RuntimeException('the course has no certificate design.');
                $reference = $this->renderer->renderVersion($version['version_id'], $data)->reference();
            } catch (Throwable $failed) {
                throw new RuntimeException('The certificate could not be issued: ' . $failed->getMessage(), 0, $failed);
            }
            $certificate = $this->certificates->store($enrolmentId, $publicId, $number, $data, $reference, $issuedAt);
            $this->audit->record($actorUserId, $existing === null ? 'certificate.issued' : 'certificate.reissued', [
                'certificate_id' => (int) $certificate['id'], 'enrolment_id' => $enrolmentId, 'certificate_number' => $number,
                'template_id' => $reference['template_id'], 'template_version_id' => $reference['template_version_id'],
                'template_version_number' => $reference['template_version_number'],
            ]);
            return $certificate;
        });
    }

    /** CL-<UTC year>-<the first twelve hex digits of the public id>, minted once per certificate: the existing rule. */
    public static function number(string $publicId, \DateTimeInterface $at): string
    {
        $year = DateTimeImmutable::createFromInterface($at)->setTimezone(new \DateTimeZone('UTC'))->format('Y');
        return 'CL-' . $year . '-' . strtoupper(substr(str_replace('-', '', $publicId), 0, 12));
    }
}
