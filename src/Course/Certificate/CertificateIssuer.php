Issues a certificate through the document template engine. At issue it takes the latest version of
the course's certificate design, builds the real certificate data, renders it with that exact
version - which validates both - and stores the data and the version reference with the
certificate. There is no other certificate renderer and no fallback: if the design cannot be drawn,
issuing fails with the reason.

A later passing final reissues the certificate: it keeps the number and public id a learner may
already have shared, and records the data and the template version of the new issue.

