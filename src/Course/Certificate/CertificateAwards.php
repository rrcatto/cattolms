When a learner gets a certificate (owner, 2026-10-19). A certificate proves that the learner took the
course, never that they passed: it is earned when the learner has completed every graded assessment of
a course that gives one, pass or fail, outside a preview. It is issued, with its transcript, only to a
verified account. A learner who earned it but is not verified sees "You have completed every assessment.
Verify your identity to receive your certificate and transcript." with a Verify button; once verified,
every certificate waiting is issued with its original completion date (issueWaiting).

ADMIN revokes a certificate, and with it its transcript, with a written reason; a revoked certificate
and its transcript say so publicly and have no PDF. Every issue and revocation is in the Activity log.

