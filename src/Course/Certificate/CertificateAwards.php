declare(strict_types=1);

namespace CattoLearning\Course\Certificate;

use CattoLearning\Course\CourseItemRepository;
use CattoLearning\Identity\IdentityVerificationRepository;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use InvalidArgumentException;
use Throwable;

final class CertificateAwards
{
    /** What a learner who earned a certificate but is not verified is told. */
    public const VERIFY_TO_RECEIVE = 'You have completed every assessment. Verify your identity to receive your certificate and transcript.';

    public function __construct(
        private readonly CertificateRepository $certificates,
        private readonly CertificateIssuer $issuer,
        private readonly CourseItemRepository $items,
        private readonly IdentityVerificationRepository $identities,
        private readonly AuditRepository $audit,
    ) {}

    /** Whether an enrolment has earned its certificate: completed, every graded assessment done, pass or fail. */
    public function earned(int $enrolmentId): bool
    {
        if (!$this->certificates->isEarned($enrolmentId)) return false;
        $context = $this->certificates->issueContext($enrolmentId);
        if ($context === null) return false;
        foreach ($this->items->assessmentContexts((int) $context['course_id'], $enrolmentId) as $assessment) {
            if (!$assessment['submitted']) return false;
        }
        return true;
    }

    /**
     * After a graded attempt: issues (or reissues) the certificate and transcript when the enrolment has
     * earned them and the learner is verified. A learner who is not verified is told to verify instead.
     */
    public function afterGradedAttempt(int $enrolmentId, int $userId): void
    {
        if (!$this->earned($enrolmentId) || $this->identities->approved($userId) === null) return;
        $this->issuer->issue($enrolmentId);
    }

    /**
     * Issues every certificate a newly verified learner earned while waiting, each with its original
     * completion date. One that cannot be drawn does not stop the others; it is recorded and can be
     * issued again by the next graded attempt or verification.
     *
     * @return int how many were issued
     */
    public function issueWaiting(int $userId): int
    {
        if ($this->identities->approved($userId) === null) return 0;
        $issued = 0;
        foreach ($this->certificates->earnedWithoutCertificate($userId) as $enrolmentId) {
            if (!$this->earned($enrolmentId)) continue;
            try {
                $this->issuer->issue($enrolmentId);
                $issued++;
            } catch (Throwable $failed) {
                $this->audit->record(null, 'certificate.issue_failed', ['enrolment_id' => $enrolmentId, 'user_id' => $userId, 'reason' => mb_substr($failed->getMessage(), 0, 300)]);
            }
        }
        return $issued;
    }

    /**
     * What the learner's course page says about the certificate: issued (with the certificate),
     * waiting for verification, or nothing yet.
     *
     * @return array{state:string,certificate:?array<string,mixed>,message:?string}
     */
    public function forLearner(int $enrolmentId, int $userId): array
    {
        $certificate = $this->certificates->forEnrolment($enrolmentId);
        if ($certificate !== null) return ['state' => 'issued', 'certificate' => $certificate, 'message' => null];
        if ($this->earned($enrolmentId) && $this->identities->approved($userId) === null) {
            return ['state' => 'waiting', 'certificate' => null, 'message' => self::VERIFY_TO_RECEIVE];
        }
        return ['state' => 'none', 'certificate' => null, 'message' => null];
    }

    /** ADMIN revokes a certificate and its transcript, with a written reason. */
    public function revoke(int $certificateId, int $actorId, string $reason): void
    {
        $reason = trim($reason);
        if ($reason === '' || mb_strlen($reason) > 500) throw new InvalidArgumentException('Write why the certificate is revoked, in at most 500 characters.');
        $certificate = $this->certificates->find($certificateId) ?? throw new InvalidArgumentException('That certificate does not exist.');
        if ($certificate['revoked_at'] !== null) throw new InvalidArgumentException('That certificate is already revoked.');
        if ($this->certificates->revoke($certificateId, $actorId, $reason)) {
            $this->audit->record($actorId, 'certificate.revoked', ['certificate_id' => $certificateId, 'user_id' => (int) $certificate['user_id'],
                'course_id' => (int) $certificate['course_id'], 'certificate_number' => (string) $certificate['certificate_number'], 'reason' => $reason]);
        }
    }
}
