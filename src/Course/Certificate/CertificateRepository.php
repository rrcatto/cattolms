    /** @return array{0:string,1:array<string,mixed>} */
    private static function issuedFilter(string $search, string $state): array
    {
        $conditions = []; $bindings = [];
        if ($state === 'valid') $conditions[] = 'cert.revoked_at IS NULL';
        if ($state === 'revoked') $conditions[] = 'cert.revoked_at IS NOT NULL';
        $search = trim($search);
        if ($search !== '') {
            $conditions[] = '(cert.certificate_number ILIKE :search OR tr.transcript_number ILIKE :search OR cert.learner_name ILIKE :search OR cert.course_title ILIKE :search)';
            $bindings['search'] = '%' . addcslashes(mb_substr($search, 0, 120), '%_\\') . '%';
        }
        return [$conditions === [] ? '' : ' WHERE ' . implode(' AND ', $conditions), $bindings];
    }

    /** @return array<string,mixed>|null */
    private function one(string $where, int|string $key): ?array
    {
        $row = $this->db->fetchAssociative(
            'SELECT cert.*, c.slug AS course_slug, c.id AS course_id, t.name AS template_name, ce.user_id,
                    tr.id AS transcript_id, tr.public_id AS transcript_public_id, tr.is_public AS transcript_is_public, tr.transcript_number,
                    COALESCE(NULLIF(trim(concat_ws(\' \', rb.first_name, rb.last_name)), \'\'), rb.display_name) AS revoked_by_name, rb.account_reference AS revoked_by_reference,
                    lu.account_reference AS learner_reference
               FROM certificates cert
               JOIN course_enrolments ce ON ce.id = cert.enrolment_id
               JOIN users lu ON lu.id = ce.user_id
               JOIN courses c ON c.id = ce.course_id
               JOIN document_templates t ON t.id = cert.template_id
               LEFT JOIN transcripts tr ON tr.certificate_id = cert.id
               LEFT JOIN users rb ON rb.id = cert.revoked_by_user_id
              WHERE ' . $where,
            ['key' => $key]
        );
        if ($row === false) {
            return null;
        }
        $row['document_data'] = json_decode((string) $row['document_data'], true, 512, JSON_THROW_ON_ERROR);
        return $row;
    }

