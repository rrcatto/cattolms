/*
Generated by: Claude Code CLI

Date time: 2026/10/07 SAST

Version: 0.8.8.10

Description:
The rules for certificate designs: reading the one design form (with its uploaded background, logo
and signature), saving, previewing, duplicating, deleting and choosing the default for new courses.

A design is checked before it is saved: it must be complete (CertificateDesign::problems()), its
compiled template must pass the engine's validator, and its words must fit the look's box on one A4
page with the sample learner - measured in the real PDF, not guessed. A preview draws whatever the
form holds through the same renderer and PDF engine, so it is exactly what saving would produce.

Every change is audited (certificate.design_*); none changes a certificate already issued, which
names the version it was drawn with.

Changelog:
2026/10/07 SAST
- A design thumbnail is absent rather than an HTTP 500 when the server has no GD extension.
- Created for certificate designs.
*/

declare(strict_types=1);

namespace CattoLearning\Course\Certificate;

use CattoLearning\Document\DocumentAssetRepository;
use CattoLearning\Document\DocumentPdfRenderer;
use CattoLearning\Document\DocumentSampleData;
use CattoLearning\Document\DocumentTemplateRenderer;
use CattoLearning\Document\DocumentType;
use CattoLearning\Document\RenderedDocument;
use CattoLearning\Document\TemplateValidationException;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\ImageProcessing;
use InvalidArgumentException;
use RuntimeException;

final class CertificateDesignService
{
    private const PICTURES = [CertificateImage::BACKGROUND => 'background', CertificateImage::LOGO => 'logo', CertificateImage::SIGNATURE => 'signature_image'];
    private readonly \Closure $isUploadedFile;

    /** @param (\Closure(string):bool)|null $isUploadedFile tests replace PHP's upload check, which is always false on the CLI */
    public function __construct(
        private readonly CertificateDesignRepository $designs,
        private readonly CertificateDesignCompiler $compiler,
        private readonly DocumentAssetRepository $assets,
        private readonly DocumentTemplateRenderer $renderer,
        private readonly DocumentPdfRenderer $pdf,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
        ?\Closure $isUploadedFile = null,
    ) {
        $this->isUploadedFile = $isUploadedFile ?? static fn(string $path): bool => is_uploaded_file($path);
    }

    /** @return list<array<string,mixed>> */
    public function designs(): array
    {
        return $this->designs->list();
    }

    /** @return array<string,mixed> */
    public function design(int $id): array
    {
        return $this->designs->find($id) ?? throw new InvalidArgumentException('That certificate design does not exist.');
    }

    /**
     * The design form read into a design, storing any picture uploaded with it. Problems are
     * collected rather than thrown, so the form can be shown again with everything the author typed.
     *
     * @param array<string,mixed> $post
     * @param array<string,mixed> $files
     * @return array{name:string,design:CertificateDesign,errors:list<string>}
     */
    public function fromForm(array $post, array $files, ?int $actorId): array
    {
        $errors = [];
        $pictures = [];
        foreach (self::PICTURES as $kind => $field) {
            $pictures[$kind] = null;
            try {
                $pictures[$kind] = $this->upload($files[$field] ?? null, $kind, $actorId);
            } catch (InvalidArgumentException $refused) {
                $errors[] = $refused->getMessage();
            }
            if ($pictures[$kind] === null && !isset($post['remove_' . $field])) {
                $pictures[$kind] = $this->stored((string) ($post[$field . '_asset'] ?? ''));
            }
        }
        $look = (string) ($post['look'] ?? 'classic');
        if ($pictures[CertificateImage::BACKGROUND] !== null && $this->uploaded($files['background'] ?? null)) {
            // Uploading a background means using it.
            $look = CertificateLooks::CUSTOM;
        }
        $wording = CertificateWording::normalize((string) ($post['wording'] ?? ''), 'wording');
        $smallPrint = CertificateWording::normalize((string) ($post['small_print'] ?? ''), 'small print');
        $design = new CertificateDesign(
            $look,
            $look === CertificateLooks::CUSTOM ? $pictures[CertificateImage::BACKGROUND] : null,
            (string) ($post['placement'] ?? 'centre'),
            (string) ($post['typeface'] ?? 'serif'),
            strtoupper((string) ($post['colour'] ?? CertificateDesign::DEFAULT_COLOUR)),
            $pictures[CertificateImage::LOGO],
            $wording['html'],
            trim((string) ($post['signature_name'] ?? '')),
            trim((string) ($post['signature_position'] ?? '')),
            $pictures[CertificateImage::SIGNATURE],
            $smallPrint['html'],
        );
        return ['name' => trim((string) ($post['name'] ?? '')), 'design' => $design, 'errors' => [...$errors, ...$wording['errors'], ...$smallPrint['errors']]];
    }

    /**
     * Saves the form as a new design or a new version of one.
     *
     * @param array<string,mixed> $post
     * @param array<string,mixed> $files
     * @return array{id:int,errors:list<string>,name:string,design:CertificateDesign} errors empty when saved
     */
    public function save(?int $id, array $post, array $files, int $actorId): array
    {
        $form = $this->fromForm($post, $files, $actorId);
        $errors = $form['errors'];
        $name = $form['name'];
        if ($name === '') {
            $errors[] = 'Give the design a name.';
        } elseif (mb_strlen($name) > CertificateDesign::NAME_LIMIT) {
            $errors[] = 'The name can be at most ' . CertificateDesign::NAME_LIMIT . ' characters.';
        } elseif ($this->designs->nameTaken($name, $id)) {
            $errors[] = 'Another design is already called “' . $name . '”.';
        }
        $errors = [...$errors, ...$form['design']->problems()];
        if ($errors === []) {
            $errors = $this->check($form['design'])['errors'];
        }
        if ($errors !== []) {
            return ['id' => $id ?? 0, 'errors' => array_values(array_unique($errors)), 'name' => $name, 'design' => $form['design']];
        }
        $compiled = $this->compile($form['design']);
        $saved = $this->transactions->run(function () use ($id, $name, $form, $compiled, $actorId): int {
            if ($id === null) {
                $id = $this->designs->create($name, '', $form['design']->toArray(), $compiled['html'], $compiled['css'], $compiled['settings'], $actorId);
                $this->audit->record($actorId, 'certificate.design_created', ['design_id' => $id, 'name' => $name]);
                return $id;
            }
            if ($this->designs->find($id, true) === null) {
                throw new InvalidArgumentException('That certificate design does not exist.');
            }
            $this->designs->save($id, $name, $form['design']->toArray(), $compiled['html'], $compiled['css'], $compiled['settings'], $actorId);
            $this->audit->record($actorId, 'certificate.design_updated', ['design_id' => $id, 'name' => $name]);
            return $id;
        });
        return ['id' => $saved, 'errors' => [], 'name' => $name, 'design' => $form['design']];
    }

    /**
     * The design drawn as the sample certificate, and what is wrong with it: anything that stops it
     * rendering, and words that do not fit on the page.
     *
     * @param array<string,mixed>|null $data the certificate's values; the sample learner when null
     * @return array{pdf:?string,errors:list<string>}
     */
    public function check(CertificateDesign $design, ?array $data = null): array
    {
        try {
            $compiled = $this->compile($design);
            $document = $this->renderer->renderSource(DocumentType::Certificate, $compiled['html'], $compiled['css'], $compiled['settings'], $data ?? self::sample());
        } catch (TemplateValidationException $invalid) {
            return ['pdf' => null, 'errors' => $invalid->errors];
        } catch (RuntimeException | InvalidArgumentException $failed) {
            return ['pdf' => null, 'errors' => [$failed->getMessage()]];
        }
        $out = $this->pdf->renderWithLayout($document, [CertificateDesignCompiler::LAYOUT_ID]);
        $height = $out['boxes'][CertificateDesignCompiler::LAYOUT_ID]['h'] ?? 0.0;
        $errors = $height > $compiled['box_height_mm'] * 72 / 25.4 + 1.0
            ? ['The words do not fit on one A4 page. Shorten the wording or the small print, or use smaller text styles.']
            : [];
        return ['pdf' => $out['pdf'], 'errors' => $errors];
    }

    /** A saved design as the sample certificate. */
    public function previewPdf(int $id): string
    {
        return $this->check($this->design($id)['design'])['pdf'] ?? throw new RuntimeException('The design could not be drawn.');
    }

    /** @return list<array{id:int,title:string}> the courses that use a design */
    public function coursesUsing(int $id): array
    {
        return $this->designs->courses($id);
    }

    public function duplicate(int $id, int $actorId): int
    {
        $source = $this->design($id);
        $name = 'Copy of ' . $source['name'];
        for ($n = 2; $this->designs->nameTaken($name); $n++) {
            $name = 'Copy ' . $n . ' of ' . $source['name'];
        }
        $name = mb_substr($name, 0, CertificateDesign::NAME_LIMIT);
        $compiled = $this->compile($source['design']);
        return $this->transactions->run(function () use ($source, $name, $compiled, $actorId): int {
            $copy = $this->designs->create($name, '', $source['design']->toArray(), $compiled['html'], $compiled['css'], $compiled['settings'], $actorId);
            $this->audit->record($actorId, 'certificate.design_created', ['design_id' => $copy, 'name' => $name, 'copied_from' => $source['id']]);
            return $copy;
        });
    }

    /** Deletes a design; its courses, and the default if it was the default, move to the replacement. */
    public function delete(int $id, int $replacementId, int $actorId): void
    {
        if ($id === $replacementId) {
            throw new InvalidArgumentException('Choose another design for its courses.');
        }
        $this->transactions->run(function () use ($id, $replacementId, $actorId): void {
            $design = $this->designs->find($id, true) ?? throw new InvalidArgumentException('That certificate design does not exist.');
            $replacement = $this->designs->find($replacementId, true) ?? throw new InvalidArgumentException('Choose another design for its courses.');
            $this->designs->delete($id, $replacementId, $actorId);
            $this->audit->record($actorId, 'certificate.design_deleted', ['design_id' => $id, 'name' => $design['name'], 'courses_moved_to' => $replacement['id'], 'course_count' => $design['course_count']]);
        });
    }

    public function setDefault(int $id, int $actorId): void
    {
        $this->transactions->run(function () use ($id, $actorId): void {
            $design = $this->designs->find($id, true) ?? throw new InvalidArgumentException('Choose one of the certificate designs.');
            $this->designs->setDefault($id);
            $this->audit->record($actorId, 'certificate.design_default_changed', ['design_id' => $id, 'name' => $design['name']]);
        });
    }

    /**
     * A small PNG of a stored picture, for the design pickers.
     *
     * @return array{bytes:string,mime:string}|null
     */
    public function thumbnail(string $sha, int $width = 480): ?array
    {
        $asset = $this->assets->find($sha);
        if ($asset === null || !ImageProcessing::available()) {
            return null;
        }
        $source = @imagecreatefromstring($asset['bytes']);
        if ($source === false) {
            return null;
        }
        $height = max(1, (int) round($width * imagesy($source) / max(1, imagesx($source))));
        $target = imagecreatetruecolor($width, $height);
        imagefill($target, 0, 0, (int) imagecolorallocate($target, 255, 255, 255));
        imagecopyresampled($target, $source, 0, 0, 0, 0, $width, $height, imagesx($source), imagesy($source));
        ob_start();
        imagepng($target, null, 6);
        return ['bytes' => (string) ob_get_clean(), 'mime' => 'image/png'];
    }

    /**
     * The design's template, with an installed look's background stored as a document image so the
     * renderer can embed it.
     *
     * @return array{html:string,css:string,settings:\CattoLearning\Document\PageSettings,box_height_mm:int}
     */
    private function compile(CertificateDesign $design): array
    {
        if (!$design->isCustom()) {
            $look = CertificateLooks::get($design->look);
            if (!$this->assets->exists(CertificateDesignCompiler::lookBackgroundSha($look))) {
                $bytes = (string) file_get_contents($look->backgroundPath());
                [$width, $height] = getimagesizefromstring($bytes) ?: [1, 1];
                $this->assets->store($bytes, 'image/png', (int) $width, (int) $height, null);
            }
        }
        return $this->compiler->compile($design);
    }

    /** @return array<string,mixed> the sample certificate's values */
    public static function sample(): array
    {
        return DocumentSampleData::for(DocumentType::Certificate);
    }

    /** A rendered sample for callers that need the HTML too. */
    public function render(CertificateDesign $design): RenderedDocument
    {
        $compiled = $this->compile($design);
        return $this->renderer->renderSource(DocumentType::Certificate, $compiled['html'], $compiled['css'], $compiled['settings'], self::sample());
    }

    private function upload(mixed $file, string $kind, ?int $actorId): ?CertificateImage
    {
        if (!$this->uploaded($file)) {
            if (is_array($file) && (int) ($file['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_NO_FILE) {
                throw new InvalidArgumentException('The ' . ($kind === CertificateImage::SIGNATURE ? 'signature picture' : $kind) . ' could not be uploaded. Try again with a file of at most 12 MB.');
            }
            return null;
        }
        /** @var array<string,mixed> $file */
        $prepared = CertificateImage::prepare((string) file_get_contents((string) $file['tmp_name']), $kind);
        $sha = $this->assets->store($prepared['bytes'], $prepared['mime'], $prepared['width'], $prepared['height'], $actorId);
        return new CertificateImage($sha, $prepared['width'], $prepared['height']);
    }

    private function uploaded(mixed $file): bool
    {
        return is_array($file) && (int) ($file['error'] ?? UPLOAD_ERR_NO_FILE) === UPLOAD_ERR_OK && ($this->isUploadedFile)((string) ($file['tmp_name'] ?? ''));
    }

    private function stored(string $sha): ?CertificateImage
    {
        $asset = $this->assets->find($sha);
        return $asset === null ? null : new CertificateImage($asset['sha256'], $asset['width'], $asset['height']);
    }
}
