/*
Generated by: Claude Code CLI

Date time: 2026/10/19 SAST

Version: 0.9.6

Description:
Who can see a certificate and its transcript (owner, 2026-10-19). The learner decides, for each one
separately and at any time: private means only the learner sees it; public means anyone who has its
address sees it. The site never links to it, lists it or says where to find it, so a public one is
seen only by the people the learner gives the address to. A new certificate and transcript start
private. The learner can also give either one a new address, a new random 32-digit hex code, at any
time: the old address stops working at once.

Each change is the learner's own and is recorded in the Activity log without the address.

Changelog:
2026/10/19 SAST
- Created.
*/

declare(strict_types=1);

namespace CattoLearning\Course\Certificate;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use InvalidArgumentException;

final class CertificateSharing
{
    /** The two documents a learner decides about. */
    public const DOCUMENTS = ['certificate', 'transcript'];

    public function __construct(
        private readonly CertificateRepository $certificates,
        private readonly AuditRepository $audit,
        private readonly TransactionManager $transactions,
    ) {}

    /**
     * Whether a viewer may see a certificate or transcript: anyone when it is public, otherwise only the
     * learner it belongs to.
     *
     * @param array<string,mixed> $row a certificate or transcript row (with user_id and is_public)
     */
    public static function canSee(array $row, ?int $viewerId): bool
    {
        return (bool) $row['is_public'] || ($viewerId !== null && $viewerId === (int) $row['user_id']);
    }

    /**
     * Whether the viewer is the learner the certificate or transcript belongs to.
     *
     * @param array<string,mixed> $row
     */
    public static function isOwner(array $row, ?int $viewerId): bool
    {
        return $viewerId !== null && $viewerId === (int) $row['user_id'];
    }

    /**
     * The learner's certificates for My Certificates, each with its transcript, whether each is public
     * and its full address.
     *
     * @return list<array<string,mixed>>
     */
    public function forLearner(int $userId): array
    {
        return array_map(static function (array $row): array {
            $row['is_public'] = (bool) $row['is_public'];
            $row['transcript_is_public'] = (bool) ($row['transcript_is_public'] ?? false);
            $row['certificate_url'] = self::address('certificate', (string) $row['public_id']);
            $row['transcript_url'] = $row['transcript_public_id'] === null ? null : self::address('transcript', (string) $row['transcript_public_id']);
            return $row;
        }, $this->certificates->forLearner($userId));
    }

    /** The learner makes their certificate or its transcript public or private. */
    public function setPublic(int $userId, int $certificateId, string $document, bool $public): void
    {
        $this->transactions->run(function () use ($userId, $certificateId, $document, $public): void {
            $certificate = $this->own($userId, $certificateId, $document);
            if ($this->certificates->setPublic($certificateId, $document, $public)) {
                $this->audit->record($userId, $document . '.made_' . ($public ? 'public' : 'private'), [
                    'certificate_id' => $certificateId, 'user_id' => $userId, 'course_id' => (int) $certificate['course_id'],
                    'certificate_number' => (string) $certificate['certificate_number'],
                ]);
            }
        });
    }

    /**
     * The learner gives their certificate or its transcript a new address. The old one stops working at
     * once and the PDF shows the new one.
     *
     * @return string the new address
     */
    public function newAddress(int $userId, int $certificateId, string $document): string
    {
        return $this->transactions->run(function () use ($userId, $certificateId, $document): string {
            $certificate = $this->own($userId, $certificateId, $document);
            $code = CertificateAddress::generate();
            $url = $document === 'transcript' ? TranscriptDataBuilder::verificationUrl($code) : CertificateDocumentDataBuilder::verificationUrl($code);
            $this->certificates->changeAddress($certificateId, $document, $code, $url);
            $this->audit->record($userId, $document . '.address_changed', [
                'certificate_id' => $certificateId, 'user_id' => $userId, 'course_id' => (int) $certificate['course_id'],
                'certificate_number' => (string) $certificate['certificate_number'],
            ]);
            return self::address($document, $code);
        });
    }

    /** A certificate's or transcript's address: in full when the site knows its own address. */
    public static function address(string $document, string $code): string
    {
        return ($document === 'transcript' ? TranscriptDataBuilder::verificationUrl($code) : CertificateDocumentDataBuilder::verificationUrl($code))
            ?? '/' . $document . 's/' . $code;
    }

    /** @return array<string,mixed> the learner's own certificate, with a transcript when that is the document */
    private function own(int $userId, int $certificateId, string $document): array
    {
        if (!in_array($document, self::DOCUMENTS, true)) throw new InvalidArgumentException('Choose the certificate or the transcript.');
        $certificate = $this->certificates->find($certificateId);
        if ($certificate === null || (int) $certificate['user_id'] !== $userId) throw new InvalidArgumentException('That certificate is not one of yours.');
        if ($document === 'transcript' && $certificate['transcript_id'] === null) throw new InvalidArgumentException('That certificate has no transcript.');
        return $certificate;
    }
}
