        if ((bool) $this->db->fetchOne('SELECT is_current FROM document_templates WHERE id = :id', ['id' => $id])) {
            $this->setDefault($replacementId);
        }
        $this->db->executeStatement(
            "UPDATE document_templates SET status = 'archived', is_current = FALSE, name = left(name, 80) || ' (deleted ' || id || ')',
                    updated_at = NOW(), updated_by_user_id = :actor WHERE id = :id",
            ['id' => $id, 'actor' => $actorId]
        );
    }

