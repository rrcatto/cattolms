        $this->publish($id, $number, $name, $design, $html, $css, $settings, $actorId);
    }

    public function setDefault(int $id): void
    {
        $this->db->executeStatement("UPDATE document_templates SET is_current = FALSE WHERE document_type = 'certificate' AND is_current AND id <> :id", ['id' => $id]);
