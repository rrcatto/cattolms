               JOIN document_template_versions v ON v.id = t.published_version_id
              WHERE c.id = :id',
            ['id' => $courseId]
        );
        return $row === false ? null : ['template_id' => (int) $row['template_id'], 'version_id' => (int) $row['version_id'], 'version_number' => (int) $row['version_number']];
    }

    /**
     * The version an enrolment's certificate is issued with now: its course's design's latest.
     *
     * @return array{template_id:int,version_id:int,version_number:int}|null
     */
    public function versionForEnrolment(int $enrolmentId): ?array
