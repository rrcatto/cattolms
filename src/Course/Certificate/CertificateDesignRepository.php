            ['template' => $id, 'number' => $number, 'html' => $html, 'css' => $css, 'actor' => $actorId,
                'design' => json_encode($design, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE)] + $settings->toArray()
        );
        $this->db->executeStatement(
            'UPDATE document_templates SET name = :name, published_version_id = :version, updated_at = NOW(), updated_by_user_id = :actor WHERE id = :id',
            ['id' => $id, 'name' => $name, 'version' => $versionId, 'actor' => $actorId]
        );
    }

