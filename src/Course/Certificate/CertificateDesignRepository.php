Description:
Certificate designs in the database. A design is a certificate document template; every save is a
new published version holding the design (document_template_versions.design) and the HTML and CSS
compiled from it, so an issued certificate keeps the version it was drawn with. None of this
versioning is shown: a design has a name, the courses that use it and when it was last edited.

The default design (is_current) is the one a new course starts with. Deleting a design moves its
courses to another one and takes it out of every list; its versions stay, because issued
