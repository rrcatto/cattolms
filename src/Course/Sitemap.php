declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Configuration\SiteMode;
use CattoLearning\Legal\LegalDocuments;
use CattoLearning\Search\PublicPages;
use CattoLearning\Search\AiCrawlers;
use CattoLearning\Search\SearchSettings;
use CattoLearning\Support\Env;
use DateTimeImmutable;
use Symfony\Contracts\Cache\CacheInterface;
use Symfony\Contracts\Cache\ItemInterface;

final class Sitemap
{
    /** The most addresses one sitemap may list (sitemaps.org). */
    public const LIMIT = 50000;
    private const CACHE_SECONDS = 3600;

    /** The paths crawlers are asked to leave alone: private, single-use or machine pages. */
    private const DISALLOW = [
        '# Single-use sign-in links: a crawler that follows one uses it up.' => ['/auth/'],
        '# Signing in carries nothing to index.' => ['/login', '/login/', '/logout'],
        '# Signed-in workspaces.' => ['/admin/', '/account/', '/company/', '/learn/', '/mailing/'],
        '# Each email\'s own links and a person\'s own pages, by a token: nobody else\'s to read.' => ['/m/', '/leaving/', '/join/'],
        '# Machine interfaces, not documents.' => ['/api/', '/theme/', '/webhooks/'],
        '# Certificates and transcripts name a learner, and course media is served by opaque id.' => ['/certificates/', '/transcripts/', '/course-media/'],
    ];

    public function __construct(
        private readonly SitemapRepository $entries,
        private readonly SiteMode $site,
        private readonly CacheInterface $cache,
        private readonly int $limit = self::LIMIT,
        private readonly ?SearchSettings $search = null,
        private readonly ?LegalDocuments $legal = null,
    ) {}

    /** The public pages the sitemap starts with: those that list courses, the guides and the legal pages. */
    public const PAGES = ['home', 'courses', 'course-tags', 'bundles', 'help', 'faq', 'contact', 'about', 'terms', 'refunds', 'privacy'];

    /** Whether this site has a sitemap: a live site that knows its own address. */
    public function available(): bool
    {
        return !$this->site->isDemo() && self::base() !== null;
    }

    /** The number of sitemap files: 1 is /sitemap.xml itself, more makes it an index. */
    public function pages(): int
    {
        return max(1, (int) ceil((count(self::PAGES) + $this->entries->count()) / $this->limit));
    }

    /** /sitemap.xml: the sitemap itself, or the index of its pages when there are too many addresses. */
    public function document(): ?string
    {
        if (!$this->available()) return null;
        return $this->cache->get('sitemap.document.' . $this->limit, function (ItemInterface $item): string {
            $item->expiresAfter(self::CACHE_SECONDS);
            $pages = $this->pages();
            return $pages === 1 ? $this->urlset(0) : $this->index($pages);
        });
    }

    /** /sitemap-{page}.xml, when /sitemap.xml is an index; null for a page that does not exist. */
    public function page(int $page): ?string
    {
        if (!$this->available() || $page < 1) return null;
        $pages = $this->pages();
        if ($pages === 1 || $page > $pages) return null;
        return $this->cache->get('sitemap.page.' . $this->limit . '.' . $page, function (ItemInterface $item) use ($page): string {
            $item->expiresAfter(self::CACHE_SECONDS);
            return $this->urlset(($page - 1) * $this->limit);
        });
    }

    /**
     * robots.txt: the crawl rules, a group for each AI crawler as Settings > Search engines and AI chooses (AiCrawlers), and
     * on a live site the full address of its sitemap and of its summary for AI assistants (/llms.txt).
     */
    public function robots(): string
    {
        $lines = ['# The crawl rules for this site. They ask crawlers to stay out of private and single-use', '# pages; they are not access control.', '', 'User-agent: *'];
        $lines = [...$lines, ...self::privatePaths(), 'Allow: /'];
        $choice = $this->search?->aiCrawlers() ?? SearchSettings::ALLOW_ALL;
        $lines[] = '';
        $lines[] = '# AI crawlers, as Settings > Search engines and AI says: ' . match ($choice) {
            SearchSettings::BLOCK_ALL => 'none of them may come in.',
            SearchSettings::SEARCH_ONLY => 'AI search and answer assistants may come in, crawlers that only collect training data may not.',
            default => 'every one of them may come in.',
        };
        $lines[] = '# A crawler named here follows only its own group, so each one that may come in repeats the private paths.';
        $lines[] = '# The list as of ' . AiCrawlers::CHECKED . ', from each company\'s own documentation.';
        foreach (AiCrawlers::all() as $token => $crawler) {
            $lines[] = '';
            $lines[] = '# ' . $crawler['company'] . ': ' . $crawler['purpose'] . '.';
            $lines[] = 'User-agent: ' . $token;
            $lines = AiCrawlers::allowed($crawler['kind'], $choice) ? [...$lines, ...self::privatePaths(false), 'Allow: /'] : [...$lines, 'Disallow: /'];
        }
        if ($this->available()) {
            $lines[] = '';
            $lines[] = 'Sitemap: ' . self::base() . '/sitemap.xml';
            $lines[] = '# A summary of this site for AI assistants, in the llms.txt format (llmstxt.org): ' . self::base() . '/llms.txt';
        }
        return implode("\n", $lines) . "\n";
    }

    /**
     * The private paths, each group with its reason as a comment, or the paths alone.
     *
     * @return list<string>
     */
    private static function privatePaths(bool $comments = true): array
    {
        $lines = [];
        foreach (self::DISALLOW as $comment => $paths) {
            if ($comments) $lines[] = $comment;
            foreach ($paths as $path) $lines[] = 'Disallow: ' . $path;
        }
        return $lines;
    }

    private function urlset(int $offset): string
    {
        $base = (string) self::base();
        $xml = '<?xml version="1.0" encoding="UTF-8"?>' . "\n" . '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' . "\n";
        // The public pages first, then the courses, landing pages, categories, tags and bundles.
        $pages = $this->publicPages();
        $first = array_slice($pages, $offset, $this->limit);
        $rest = $this->limit - count($first);
        $entries = $rest > 0 ? [...$first, ...$this->entries->entries($rest, max(0, $offset - count($pages)))] : $first;
        foreach ($entries as $entry) {
            $changed = $entry['changed_at'] === null ? '' : '<lastmod>' . (new DateTimeImmutable($entry['changed_at']))->format(DATE_ATOM) . '</lastmod>';
            $xml .= '<url><loc>' . self::escape($base . $entry['path']) . '</loc>' . $changed . '</url>' . "\n";
        }
        return $xml . '</urlset>' . "\n";
    }

    /**
     * The public pages, each with when what it shows last changed: a list of courses when a course or bundle did, a legal
     * page on its own date; null where no date is known.
     *
     * @return list<array{path:string,changed_at:?string}>
     */
    private function publicPages(): array
    {
        $latest = $this->entries->latest();
        $pages = [];
        foreach (self::PAGES as $key) {
            $changed = match ($key) {
                'home', 'courses', 'course-tags', 'bundles' => $latest,
                'terms', 'refunds', 'privacy' => $this->legal?->document($key)['updated'] ?? null,
                default => null,
            };
            $pages[] = ['path' => PublicPages::path($key), 'changed_at' => $changed];
        }
        return $pages;
    }

    private function index(int $pages): string
    {
        $base = (string) self::base();
        $xml = '<?xml version="1.0" encoding="UTF-8"?>' . "\n" . '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' . "\n";
        for ($page = 1; $page <= $pages; $page++) {
            $xml .= '<sitemap><loc>' . self::escape($base . '/sitemap-' . $page . '.xml') . '</loc></sitemap>' . "\n";
        }
        return $xml . '</sitemapindex>' . "\n";
    }

    /** APP_URL without its trailing slash, when it is a web address. */
    private static function base(): ?string
    {
        $base = rtrim(trim(Env::string('APP_URL')), '/');
        return preg_match('#^https?://[^/\s]+#i', $base) === 1 ? $base : null;
    }

    private static function escape(string $value): string
    {
        return htmlspecialchars($value, ENT_XML1 | ENT_QUOTES, 'UTF-8');
    }
}
