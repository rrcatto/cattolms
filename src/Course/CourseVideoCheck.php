declare(strict_types=1);

namespace CattoLearning\Course;

use Symfony\Component\Clock\ClockInterface;
use Symfony\Contracts\HttpClient\HttpClientInterface;
use Throwable;

final class CourseVideoCheck
{
    /** What each finding means, in the words Needs your attention uses. */
    public const FINDINGS = [
        'blocked' => 'YouTube does not let it play here: it is private, or its owner has turned off playing it on other sites.',
        'removed' => 'YouTube says the video is not there any more: it was removed, or the id is wrong.',
        'invalid' => 'YouTube does not recognise the video\'s id.',
    ];

    public function __construct(
        private readonly CourseVideoCheckRepository $records,
        private readonly ClockInterface $clock,
        private readonly ?HttpClientInterface $http = null,
    ) {
    }

    /** Checks every course video and says what it found, for the scheduled job's record. */
    public function run(): string
    {
        if ($this->http === null) { return 'Not available here.'; }
        $videos = $this->records->videos();
        $found = ['plays' => 0, 'blocked' => 0, 'removed' => 0, 'invalid' => 0, 'unknown' => 0];
        foreach ($videos as $video) {
            [$status, $detail] = $this->ask($video['youtube_id']);
            $found[$status]++;
            if ($status !== 'unknown') { $this->records->record($video['course_item_id'], $video['youtube_id'], $status, $detail, $this->clock->now()); }
        }
        $this->records->forgetOthers();
        if ($videos !== [] && $found['unknown'] === count($videos)) { throw new \RuntimeException('YouTube could not be reached for any of the ' . count($videos) . ' course videos.'); }
        $failing = $found['blocked'] + $found['removed'] + $found['invalid'];
        return sprintf('Checked %d course video%s: %d play%s, %d do%s not%s.', count($videos), count($videos) === 1 ? '' : 's', $found['plays'], $found['plays'] === 1 ? 's' : '',
            $failing, $failing === 1 ? 'es' : '', $found['unknown'] > 0 ? ', and ' . $found['unknown'] . ' could not be checked this time' : '');
    }

    /** @return array{0:'plays'|'blocked'|'removed'|'invalid'|'unknown',1:string} */
    private function ask(string $youtubeId): array
    {
        if (preg_match('/^[A-Za-z0-9_-]{11}$/', $youtubeId) !== 1) { return ['invalid', self::FINDINGS['invalid']]; }
        $watch = 'https://www.youtube.com/watch?v=' . $youtubeId;
        try {
            $response = $this->http?->request('GET', 'https://www.youtube.com/oembed', ['query' => ['url' => $watch, 'format' => 'json'], 'timeout' => 15,
                'headers' => ['User-Agent' => 'CattoLMS course video check']]);
            $code = $response?->getStatusCode() ?? 0;
        } catch (Throwable) {
            return ['unknown', ''];
        }
        return match (true) {
            $code === 200 => ['plays', ''],
            $code === 401, $code === 403 => ['blocked', self::FINDINGS['blocked']],
            $code === 404 => ['removed', self::FINDINGS['removed']],
            $code === 400 => ['invalid', self::FINDINGS['invalid']],
            default => ['unknown', ''],
        };
    }
}
