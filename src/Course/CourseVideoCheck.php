Whether every course video still plays (owner, 2026-10-28, decision 8A: the videos are other people's YouTube videos,
which can disappear). Once a day the video_check scheduled job asks YouTube's public oEmbed address about each video
placed in a course: the address answers with the video's details when it can be played on another site, and refuses
when the video was removed, is private or may not be played elsewhere. A video that does not play is on the
dashboard's Needs your attention until it plays again, is replaced or is taken out of the course. Nothing about a
learner is sent: only the video's id. An answer that is neither (YouTube not reached, a server error) changes nothing.

