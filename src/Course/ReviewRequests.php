The one email asking a learner for a review (owner, 2026-10-28, decision 8A): three days after a learner completes a
course, if they have not reviewed it, they are emailed once with a link to rate it. It is a service email about a
course they took, sent at once like the other course emails, never to an address on Addresses never emailed, and never
twice for one enrolment. A course completed more than 30 days ago is not asked about, so a site's first run does not
email everyone who ever finished a course. The review_requests scheduled job runs it every hour.

