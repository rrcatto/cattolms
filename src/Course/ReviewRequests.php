declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Infrastructure\Mail\MailerInterface;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\Env;
use Symfony\Component\Clock\ClockInterface;

final class ReviewRequests
{
    /** How long after completing a course the learner is asked: three days. */
    public const ASK_AFTER = 3 * 86400;

    /** Completions older than this are never asked about: 30 days. */
    public const ASK_UNTIL = 30 * 86400;

    public function __construct(
        private readonly CourseReviewRepository $reviews,
        private readonly TransactionManager $transactions,
        private readonly MailerInterface $mailer,
        private readonly ClockInterface $clock,
    ) {
    }

    /** Emails every learner due to be asked, at most $limit of them; returns how many were emailed. */
    public function send(int $limit = 100): int
    {
        $base = rtrim(Env::string('APP_URL', ''), '/');
        $sent = 0;
        for ($i = 0; $i < $limit; $i++) {
            $done = $this->transactions->run(function () use ($base): bool {
                $now = $this->clock->now();
                $due = $this->reviews->dueReviewRequests(1, $now, self::ASK_AFTER, self::ASK_UNTIL)[0] ?? null;
                if ($due === null) { return false; }
                // Marked first, in the same transaction: a failed send rolls both back and is tried again next hour.
                $this->reviews->markReviewRequested($due['enrolment_id'], $now);
                $this->mailer->sendReviewRequest($due['email'], $due['first_name'], $due['course_title'], $base . '/learn/' . rawurlencode($due['course_slug']) . '/review');
                return true;
            });
            if (!$done) { break; }
            $sent++;
        }
        return $sent;
    }
}
