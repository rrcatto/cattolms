                    COUNT(DISTINCT cm.id)::int AS module_count,
                    COUNT(DISTINCT mp.module_id) FILTER (WHERE mp.first_opened_at IS NOT NULL)::int AS opened_module_count,
                    COUNT(DISTINCT mp.module_id) FILTER (WHERE mp.best_percentage IS NOT NULL)::int AS assessed_module_count,
                    cr.overall_percentage, cr.grade_code AS overall_grade_code,
                    cert.public_id AS certificate_public_id
             FROM course_enrolments ce
             JOIN courses c ON c.id = ce.course_id
             LEFT JOIN course_categories cc ON cc.id = c.category_id
             LEFT JOIN course_modules cm ON cm.course_id = c.id AND cm.assessment_required = TRUE
             LEFT JOIN module_progress mp ON mp.enrolment_id = ce.id AND mp.module_id = cm.id
             LEFT JOIN course_results cr ON cr.enrolment_id = ce.id
             LEFT JOIN certificates cert ON cert.enrolment_id = ce.id AND cert.revoked_at IS NULL
             WHERE ce.user_id = :user_id AND ce.is_preview = FALSE AND ce.status IN ('assigned','active','completed')
             GROUP BY ce.id, c.id, cc.name, cr.overall_percentage, cr.grade_code, cert.public_id
             ORDER BY ce.assigned_at DESC",
            [':user_id' => $userId]
        );
        return $this->normaliseRows($rows);
    }

    public function grantCourse(
        int $userId,
        int $courseId,
        int $accessPeriodSeconds,
        int $assignedByUserId
    ): int {
        if ($this->enrolment($userId, $courseId) !== null) {
            throw new RuntimeException('That user already has this course in their library.');
        }

        $enrolmentM = new CourseEnrolmentsM($this->db);
        $enrolmentM->public_id = Uuid::v4();
        $enrolmentM->user_id = $userId;
        $enrolmentM->course_id = $courseId;
        $enrolmentM->source_type = 'administrator';
        $enrolmentM->source_reference = null;
        $enrolmentM->status = 'assigned';
        $enrolmentM->access_period_seconds = $accessPeriodSeconds;
        $enrolmentM->assigned_at = gmdate('Y-m-d H:i:sP');
        $enrolmentM->assigned_by_user_id = $assignedByUserId;
        $enrolmentM->created_at = gmdate('Y-m-d H:i:sP');
        $enrolmentM->updated_at = gmdate('Y-m-d H:i:sP');
