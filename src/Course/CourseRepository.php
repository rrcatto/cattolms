    private const TAG_ORDER = 't.name, t.id';

    /**
     * @return array{0:string,1:array<string,mixed>}
     */
    private static function andTagSearch(string $search): array
    {
        $term = trim($search);

        return $term === ''
            ? ['', []]
            : [' AND t.name::text ILIKE :tag_search', ['tag_search' => '%' . addcslashes($term, '%_\\') . '%']];
    }

    /**
     * One page of the tag administration list.
     *
     * Universe-free, and so is its count, because both describe the same population: the tags that
     * exist. A tag is a shared label like a category, and a label belongs to no universe.
     *
     * What *is* scoped is how many courses carry each tag, and that is deliberately a separate read
     * - see courseCountsForTags(). Folding it in here would make this method take a DataUniverse
     * that its count query does not, which is exactly the shape the pairing rule exists to catch;
     * and the rule is right, because the two would then look like a scoped list with an unscoped
     * total.
     *
     * @return list<array<string,mixed>>
     */
    public function tags(string $search, int $limit, int $offset): array
    {
        [$match, $bindings] = self::andTagSearch($search);

        $keys = 'SELECT t.id FROM tags t WHERE TRUE' . $match;
        $detail = 'SELECT t.id, t.name, t.slug, t.created_at
                   FROM page JOIN tags t ON t.id = page.id';

        return $this->normaliseRows($this->db->fetchAllAssociative(
            PageQuery::deferred($keys, $detail, self::TAG_ORDER, $limit, $offset),
            $bindings
        ));
    }

    /**
     * How many courses carry each of these tags, in the reader's universe.
     *
     * The label is shared; what is counted under it is not. An operator reading REAL must not be
     * told a tag is on forty courses when every one of them is generated.
     *
     * @param list<int> $tagIds
     * @return array<int,int>
     */
    public function courseCountsForTags(array $tagIds): array
