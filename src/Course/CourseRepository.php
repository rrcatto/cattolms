    /** @return array<string,float|int> */
    public function resultPercentages(int $enrolmentId, int $courseId): array
    {
        $moduleRows = $this->db->exec(
            "SELECT COALESCE(SUM(best.earned_points),0)::int AS earned,
                    COALESCE(SUM(best.maximum_points),0)::int AS maximum
             FROM course_assessments ca
             JOIN course_modules cm ON cm.id = ca.module_id
             JOIN LATERAL (
                 SELECT aa.earned_points, aa.maximum_points
                 FROM assessment_attempts aa
                 WHERE aa.assessment_id = ca.id AND aa.enrolment_id = :enrolment_id
                 ORDER BY aa.percentage DESC, aa.submitted_at DESC LIMIT 1
             ) best ON TRUE
             WHERE ca.course_id = :course_id AND ca.assessment_type = 'module' AND cm.assessment_required = TRUE",
            [':enrolment_id' => $enrolmentId, ':course_id' => $courseId]
        );
        $finalRows = $this->db->exec(
            "SELECT aa.percentage
             FROM assessment_attempts aa
             JOIN course_assessments ca ON ca.id = aa.assessment_id
             WHERE aa.enrolment_id = :enrolment_id AND ca.course_id = :course_id AND ca.assessment_type = 'final'
             ORDER BY aa.percentage DESC, aa.submitted_at DESC LIMIT 1",
            [':enrolment_id' => $enrolmentId, ':course_id' => $courseId]
        );
        $earned = (int) ($moduleRows[0]['earned'] ?? 0);
        $maximum = (int) ($moduleRows[0]['maximum'] ?? 0);
        return [
            'module_percentage' => $maximum > 0 ? ($earned / $maximum * 100) : 0.0,
            'final_percentage' => isset($finalRows[0]['percentage']) ? (float) $finalRows[0]['percentage'] : 0.0,
        ];
    }

    public function saveCourseResult(
        int $enrolmentId,
        float $modulePercentage,
        float $finalPercentage,
        float $overallPercentage,
        string $gradeCode,
        bool $passed
    ): void {
        $now = gmdate('Y-m-d H:i:sP');

        $this->db->exec(
            'INSERT INTO course_results
             (enrolment_id,module_percentage,final_percentage,overall_percentage,grade_code,passed,calculated_at,seed_token)
             VALUES (:enrolment_id,:module_percentage,:final_percentage,:overall_percentage,:grade_code,:passed,:calculated_at,:seed_token::uuid)
             ON CONFLICT (enrolment_id) DO UPDATE SET
               module_percentage=EXCLUDED.module_percentage,final_percentage=EXCLUDED.final_percentage,
               overall_percentage=EXCLUDED.overall_percentage,grade_code=EXCLUDED.grade_code,
               passed=EXCLUDED.passed,calculated_at=EXCLUDED.calculated_at',
            [
                ':enrolment_id' => $enrolmentId, ':module_percentage' => $modulePercentage,
                ':final_percentage' => $finalPercentage, ':overall_percentage' => $overallPercentage,
                ':grade_code' => $gradeCode, ':passed' => $passed, ':calculated_at' => $now,
                ':seed_token' => $this->provenance->fromEnrolment($enrolmentId),
            ]
        );

        $enrolmentM = new CourseEnrolmentsM($this->db);
        $enrolmentM->load(['id = ?', $enrolmentId]);
        if (!$enrolmentM->dry()) {
            $enrolmentM->status = 'completed';
            if ($enrolmentM->completed_at === null || $enrolmentM->completed_at === '') {
                $enrolmentM->completed_at = $now;
            }
            $enrolmentM->updated_at = $now;
            $enrolmentM->save();
        }
    }

