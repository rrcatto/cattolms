    /** @param list<array<string,mixed>> $responses */
    public function saveAttempt(
        int $enrolmentId,
        int $assessmentId,
        float $earned,
        float $maximum,
        float $percentage,
        string $gradeCode,
        bool $passed,
        array $responses
    ): int {
        // The row lock serialises concurrent submissions for this enrolment. MAX()+1
        // is then safe inside the surrounding service transaction.
        $this->db->exec(
            'SELECT id FROM course_enrolments WHERE id = :id FOR UPDATE',
            [':id' => $enrolmentId]
        );
        $attemptRows = $this->db->exec(
            'SELECT COALESCE(MAX(attempt_number), 0) + 1 AS next_number
             FROM assessment_attempts
             WHERE enrolment_id = :enrolment_id AND assessment_id = :assessment_id',
            [
                ':enrolment_id' => $enrolmentId,
                ':assessment_id' => $assessmentId,
            ]
        );
        $attemptNumber = (int) ($attemptRows[0]['next_number'] ?? 1);

        $attemptM = new AssessmentAttemptsM($this->db);
        $attemptM->public_id = Uuid::v4();
        $attemptM->seed_token = $this->provenance->fromEnrolment($enrolmentId);
        $attemptM->enrolment_id = $enrolmentId;
        $attemptM->assessment_id = $assessmentId;
        $attemptM->attempt_number = $attemptNumber;
        $attemptM->earned_points = $earned;
        $attemptM->maximum_points = $maximum;
        $attemptM->percentage = $percentage;
        $attemptM->grade_code = $gradeCode;
        $attemptM->passed = $passed;
        $attemptM->submitted_at = gmdate('Y-m-d H:i:sP');
        $attemptM->save();

        $attemptId = (int) $attemptM->id;
        if ($attemptId < 1) {
            throw new RuntimeException('Unable to save assessment attempt.');
        }

        foreach ($responses as $response) {
            $this->db->exec(
                'INSERT INTO assessment_responses
                 (attempt_id,question_id,selected_option_id,is_correct,points_awarded,seed_token)
                 VALUES (:attempt_id,:question_id,:selected_option_id,:is_correct,:points_awarded,:seed_token::uuid)
                 ON CONFLICT (attempt_id,question_id) DO UPDATE
                 SET selected_option_id=EXCLUDED.selected_option_id,is_correct=EXCLUDED.is_correct,points_awarded=EXCLUDED.points_awarded',
                [
                    ':seed_token' => $this->provenance->fromAttempt($attemptId),
                    ':attempt_id' => $attemptId,
                    ':question_id' => (int) $response['question_id'],
                    ':selected_option_id' => $response['selected_option_id'],
                    ':is_correct' => (bool) $response['is_correct'],
                    ':points_awarded' => $response['points_awarded'],
                ]
            );
        }

        return $attemptId;
    }

