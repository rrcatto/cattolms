    /** @return list<array<string,mixed>> */
    /**
     * Every enrolment a learner holds, unbounded.
     *
     * The Account dashboard summarises the whole set, so it reads this. The Course Library
     * displays it a page at a time and reads {@see libraryPage()} and {@see libraryCount()},
     * which apply the identical membership rule.
     *
     * @return list<array<string,mixed>>
     */
    public function library(int $userId): array
    {
        return $this->libraryPage($userId, self::LIBRARY_STATUSES, 0, 0, '');
    }

    /**
     * One page of a learner's enrolments, optionally narrowed to a status group.
     *
     * A limit of zero means the whole set: the unbounded read above and the paged read below are
     * the same query, so a status group cannot be counted by one rule and listed by another.
     *
     * @param list<string> $statuses
     * @return list<array<string,mixed>>
     */
    public function libraryPage(int $userId, array $statuses, int $limit, int $offset, string $search = ''): array
    {
        [$where, $bindings] = self::libraryFilter($userId, $statuses, $search);

        $detail = "SELECT ce.*, c.slug, c.title, c.subtitle, c.summary, c.level, c.status AS course_status,
                    cc.name AS category_name,
                    COUNT(DISTINCT cm.id)::int AS module_count,
                    COUNT(DISTINCT mp.module_id) FILTER (WHERE mp.first_opened_at IS NOT NULL)::int AS opened_module_count,
                    COUNT(DISTINCT mp.module_id) FILTER (WHERE mp.best_percentage IS NOT NULL)::int AS assessed_module_count,
                    cr.overall_percentage, cr.grade_code AS overall_grade_code,
                    cert.public_id AS certificate_public_id
             FROM %s
             LEFT JOIN course_categories cc ON cc.id = c.category_id
             LEFT JOIN course_modules cm ON cm.course_id = c.id AND cm.assessment_required = TRUE
             LEFT JOIN module_progress mp ON mp.enrolment_id = ce.id AND mp.module_id = cm.id
             LEFT JOIN course_results cr ON cr.enrolment_id = ce.id
             LEFT JOIN certificates cert ON cert.enrolment_id = ce.id AND cert.revoked_at IS NULL
             %s
             GROUP BY ce.id, c.id, cc.name, cr.overall_percentage, cr.grade_code, cert.public_id";

        // A limit of zero means the learner's whole library, which the API, the MCP surface and the
        // administrator's view of a learner all ask for. There is nothing to defer then: every
        // enrolment is on the page.
        $sql = $limit > 0
            ? PageQuery::deferred(
                'SELECT ce.id FROM course_enrolments ce JOIN courses c ON c.id = ce.course_id ' . $where,
                sprintf($detail, 'page JOIN course_enrolments ce ON ce.id = page.id JOIN courses c ON c.id = ce.course_id', ''),
                self::LIBRARY_ORDER,
                $limit,
                $offset
            )
            : sprintf($detail, 'course_enrolments ce JOIN courses c ON c.id = ce.course_id', $where)
                . "\nORDER BY " . self::LIBRARY_ORDER;

        return $this->normaliseRows($this->db->fetchAllAssociative($sql, $bindings));
    }

    /**
     * Total enrolments behind {@see libraryPage()} under the identical membership rule.
     *
     * @param list<string> $statuses
     */
    public function libraryCount(int $userId, array $statuses = self::LIBRARY_STATUSES, string $search = ''): int
    {
        [$where, $bindings] = self::libraryFilter($userId, $statuses, $search);
        $rows = $this->db->fetchAllAssociative(
            'SELECT COUNT(*)::int AS total FROM course_enrolments ce
             JOIN courses c ON c.id = ce.course_id ' . $where,
            $bindings
        );

        return (int) ($rows[0]['total'] ?? 0);
    }

    /**
     * The single membership rule behind every Course Library read.
     *
     * @param list<string> $statuses
     * @return array{0:string,1:array<string,mixed>}
     */
    private static function libraryFilter(int $userId, array $statuses, string $search): array
    {
        $allowed = array_values(array_intersect(self::LIBRARY_STATUSES, $statuses));
        if ($allowed === []) {
            $allowed = self::LIBRARY_STATUSES;
        }

        $bindings = ['user_id' => $userId];
        $names = [];
        foreach ($allowed as $index => $status) {
            $names[] = ':library_status_' . $index;
            $bindings['library_status_' . $index] = $status;
        }

        $where = 'WHERE ce.user_id = :user_id AND ce.is_preview = FALSE'
            . ' AND ce.status IN (' . implode(',', $names) . ')';

        [$match, $searchBindings] = self::andTitleSearch($search);

        return [$where . $match, $bindings + $searchBindings];
    }

    public function grantCourse(
        int $userId,
        int $courseId,
        int $accessPeriodSeconds,
        int $assignedByUserId
    ): int {
        if ($this->enrolment($userId, $courseId) !== null) {
            throw new RuntimeException('That user already has this course in their library.');
        }

        $now = gmdate('Y-m-d H:i:sP');
        $rows = $this->db->fetchAllAssociative(
            "INSERT INTO course_enrolments
                 (public_id,user_id,course_id,source_type,source_reference,status,
                  access_period_seconds,assigned_at,assigned_by_user_id,created_at,updated_at)
             VALUES (:public_id,:user_id,:course_id,'administrator',NULL,'assigned',
                     :access_period_seconds,:assigned_at,:assigned_by,:created_at,:updated_at)
             RETURNING id",
            [
                'public_id' => Uuid::v4(),
                // The learner and the course must be in the same universe. forPair() refuses a
                // mismatch by name rather than leaving the trigger to report a column.
                'user_id' => $userId,
                'course_id' => $courseId,
                'access_period_seconds' => $accessPeriodSeconds,
                'assigned_at' => $now,
                'assigned_by' => $assignedByUserId,
                'created_at' => $now,
                'updated_at' => $now,
            ]
        );

        $id = (int) ($rows[0]['id'] ?? 0);
        if ($id < 1) {
            throw new RuntimeException('Unable to grant course access.');
        }

        return $id;
    }

