    public function swapCategoryPositions(int $firstId, int $secondId): void
    {
        $first = $this->categoryById($firstId);
        $second = $this->categoryById($secondId);
        if ($first === null || $second === null) {
            throw new RuntimeException('The course categories could not be reordered.');
        }
        $temporaryRows = $this->db->exec('SELECT COALESCE(MAX(position),0)+10 AS position FROM course_categories');
        $temporary = (int) ($temporaryRows[0]['position'] ?? 10);
        $this->db->exec('UPDATE course_categories SET position=:position,updated_at=NOW() WHERE id=:id', [':position' => $temporary, ':id' => $firstId]);
        $this->db->exec('UPDATE course_categories SET position=:position,updated_at=NOW() WHERE id=:id', [':position' => (int) $first['position'], ':id' => $secondId]);
        $this->db->exec('UPDATE course_categories SET position=:position,updated_at=NOW() WHERE id=:id', [':position' => (int) $second['position'], ':id' => $firstId]);
    }

