    /** @param list<int> $userIds */
    public function replaceCourseEditors(int $courseId, array $userIds, int $actorUserId): void
    {
        $userIds = array_values(array_unique(array_filter(array_map('intval', $userIds), static fn(int $id): bool => $id > 0)));
        if ($userIds === []) {
            $this->db->executeStatement('DELETE FROM course_editors WHERE course_id=:course_id', ['course_id' => $courseId]);
            return;
        }
        $placeholders = [];
        $params = ['course_id' => $courseId];
        foreach ($userIds as $index => $userId) {
            $key = ':u' . $index;
            $placeholders[] = $key;
            $params[$key] = $userId;
        }
        $this->db->executeStatement(
            'DELETE FROM course_editors WHERE course_id=:course_id AND user_id NOT IN (' . implode(',', $placeholders) . ')',
            $params
        );
        foreach ($userIds as $userId) {
            $this->db->executeStatement(
                'INSERT INTO course_editors (course_id,user_id,assigned_by_user_id,created_at)
                 VALUES (:course_id,:user_id,:actor_user_id,NOW())
                 ON CONFLICT (course_id,user_id) DO UPDATE SET assigned_by_user_id=EXCLUDED.assigned_by_user_id',
                [
                    'course_id' => $courseId,
                    'user_id' => $userId,
                    'actor_user_id' => $actorUserId,
                    // Editor and course must share a universe; the assigning actor need not.
                ]
            );
        }
    }

    public function setCourseOwnership(int $courseId, int $ownerCompanyId, int $ownerUserId, int $actorUserId): void
    {
        if ($ownerCompanyId < 1 || $ownerUserId < 1) {
