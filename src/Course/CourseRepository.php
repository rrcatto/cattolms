    /**
     * One page of a company's courses, in one of its two senses.
     *
     * `owned` is the provider view: courses this company made and offers. `training` is the
     * entitlement view: courses it has bought access to for its staff. See ROADMAP section 3d - the
     * screen that showed both at once could not answer either question.
     *
     * @return list<array<string,mixed>>
     */
    public function companyCourses(int $companyId, string $relationship, int $limit, int $offset, string $search = '', ?SortOrder $sort = null): array
    {
        $order = self::orderFor($sort, self::COMPANY_COURSE_SORTS, self::COMPANY_COURSE_ORDER, 'c.id');
        [$match, $bindings] = self::andTitleSearch($search);

        $keys = "SELECT c.id FROM courses c WHERE " . self::companyCourseWhere($relationship)
            . '' . $match;

        $detail = "SELECT c.id, c.public_id, c.slug, c.title, c.subtitle, c.summary, c.level, c.status,
                    c.estimated_minutes, c.default_access_period_seconds, c.certificate_enabled,
                    c.course_style_key, c.category_id, cc.name AS category_name, cc.slug AS category_slug,
                    c.owner_company_id, oc.name AS owner_company_name,
                    (c.owner_company_id = :company_id) AS is_company_owned,
                    EXISTS (
                        SELECT 1 FROM course_credits cr
                        WHERE cr.course_id = c.id AND cr.company_id = :company_id
                    ) AS has_company_credits,
                    -- The entitlement figures a Training Courses row exists to show. Scalar
                    -- sub-selects rather than joined aggregates: credits, allocations and
                    -- enrolments are three independent one-to-many relationships on the same
                    -- course, so joining them multiplies before anything is counted.
                    (SELECT COALESCE(SUM(cr.quantity),0)::int FROM course_credits cr
                      WHERE cr.course_id = c.id AND cr.company_id = :company_id) AS credits_bought,
                    (SELECT COUNT(*)::int FROM course_credit_allocations cca
                        JOIN course_credits cr ON cr.id = cca.credit_id
                       WHERE cr.course_id = c.id AND cr.company_id = :company_id
                         AND cca.status IN ('assigned','consumed')) AS credits_used,
                    (SELECT COUNT(*)::int FROM course_enrolments ce
                        JOIN company_users cu ON cu.user_id = ce.user_id
                                             AND cu.company_id = :company_id AND cu.status = 'active'
                       WHERE ce.course_id = c.id AND ce.is_preview = FALSE) AS staff_enrolled,
                    (SELECT COUNT(*)::int FROM course_enrolments ce
                        JOIN company_users cu ON cu.user_id = ce.user_id
                                             AND cu.company_id = :company_id AND cu.status = 'active'
                       WHERE ce.course_id = c.id AND ce.is_preview = FALSE
                         AND ce.status = 'completed') AS staff_completed,
                    cover.public_id AS cover_media_public_id,
                    COUNT(DISTINCT cm.id)::int AS module_count
             FROM page
             JOIN courses c ON c.id = page.id
             LEFT JOIN course_categories cc ON cc.id = c.category_id
             LEFT JOIN companies oc ON oc.id = c.owner_company_id
             LEFT JOIN LATERAL (
                 SELECT public_id FROM course_media
                 WHERE course_id = c.id AND media_role = 'cover'
                 ORDER BY created_at DESC LIMIT 1
             ) cover ON TRUE
             LEFT JOIN course_modules cm ON cm.course_id = c.id
             GROUP BY c.id, cc.name, cc.slug, oc.name, cover.public_id";

        return $this->normaliseRows($this->db->fetchAllAssociative(
            PageQuery::deferred($keys, $detail, $order, $limit, $offset),
            ['company_id' => $companyId] + $bindings
        ));
    }

