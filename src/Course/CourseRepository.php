    public function startEnrolment(int $enrolmentId, int $userId): void
    {
        $enrolmentM = new CourseEnrolmentsM($this->db);
        $enrolmentM->load([
            "id = ? AND user_id = ? AND status = 'assigned'",
            $enrolmentId,
            $userId,
        ]);
        if ($enrolmentM->dry()) {
            return;
        }

        $startedAt = new \DateTimeImmutable('now', new \DateTimeZone('UTC'));
        $expiresAt = $startedAt->modify(
            '+' . (int) $enrolmentM->access_period_seconds . ' seconds'
        );

        $enrolmentM->status = 'active';
        $enrolmentM->started_at = $startedAt->format('Y-m-d H:i:sP');
        $enrolmentM->expires_at = $this->databaseBoolean($enrolmentM->is_preview)
            ? null
            : $expiresAt->format('Y-m-d H:i:sP');
        $enrolmentM->updated_at = $startedAt->format('Y-m-d H:i:sP');
        $enrolmentM->save();

        if (!$this->databaseBoolean($enrolmentM->is_preview)) {
            $this->db->exec(
                "UPDATE course_credit_allocations
                 SET status='consumed', consumed_at=COALESCE(consumed_at,NOW()), returned_at=NULL
                 WHERE enrolment_id=:enrolment_id AND status='assigned'",
                [':enrolment_id' => $enrolmentId]
            );
        }
    }

