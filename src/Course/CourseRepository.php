    /**
     * How many courses each option in a facet would return, given everything else the reader has
     * chosen.
     *
     * The subtlety that makes or breaks a faceted UI: a facet's own counts are taken with **that
     * facet relaxed**. Apply the tag facet to its own counts and selecting one tag drives every
     * other tag to zero, because no course carries a tag it does not carry - the rail turns into a
     * single live option and a dead end. Counting with the tag facet dropped, but the category and
     * the keyword still applied, gives the figure the reader actually wants: how many more courses
     * this option would add.
     *
     * Both callers below pass a filter that has already had its own facet removed. That is stated at
     * the call site rather than done here, because a repository silently rewriting the filter it was
     * given is worse than a caller saying what it means.
     *
     * @param list<int> $tagIds
     * @return array<int,int>
     */
    public function tagFacetCounts(array $tagIds, CatalogueFilter $filter): array
    {
        if ($tagIds === []) {
            return [];
        }

        [$narrow, $bindings] = self::andCatalogueFilter($filter);
        $ids = implode(',', array_map('intval', $tagIds));

        $counts = [];
        foreach ($this->db->fetchAllAssociative(
            "SELECT ct.tag_id, COUNT(*)::int AS total
               FROM course_tags ct JOIN courses c ON c.id = ct.course_id
              WHERE ct.tag_id IN ({$ids}) AND c.status = 'published'"
                . '' . $narrow . '
              GROUP BY ct.tag_id',
            $bindings
        ) as $row) {
            $counts[(int) $row['tag_id']] = (int) $row['total'];
        }

        return $counts;
    }

    /**
     * The same idea for the category facet: how many courses each branch holds, given the tags and
     * the keyword but not the category the reader is already inside.
     *
     * @param list<int> $categoryIds
     * @return array<int,int>
     */
    public function categoryFacetCounts(array $categoryIds, CatalogueFilter $filter): array
    {
        $counts = [];
        foreach ($categoryIds as $categoryId) {
            // One statement per branch rather than one grouped statement, because the branch
            // predicate is a per-category subquery rather than a column to group by. The list is a
            // page of sibling categories, never the whole taxonomy.
            [$narrow, $bindings] = self::andCatalogueFilter($filter->withCategory((int) $categoryId));
            $rows = $this->db->fetchAllAssociative(
                "SELECT COUNT(*)::int AS total FROM courses c WHERE c.status = 'published'"
                    . '' . $narrow,
                $bindings
            );
            $counts[(int) $categoryId] = (int) ($rows[0]['total'] ?? 0);
        }

        return $counts;
    }

    /**
     * How the published catalogue is spread across the top level of the taxonomy.
     *
     * Top level only, and by whole branch, because that is the question a distribution answers:
     * which parts of the catalogue are full and which are empty. A row per category at every level
     * would be the taxonomy screen again, which is directly above it.
     *
     * The uncategorised row is the point of the chart as much as the branches are. A course with no
     * category is invisible to every browse path there is, and nothing else on the platform says how
     * many of them exist.
     *
     * @return list<array{label:string,slug:string,total:int}>
     */
    public function categoryDistribution(): array
    {
        $scope = '';
        $rows = $this->normaliseRows($this->db->fetchAllAssociative(
            "SELECT cc.name AS label, cc.slug,
                    (SELECT COUNT(*)::int FROM courses c
                      WHERE c.status = 'published' AND " . self::inBranchOf('c', 'cc.id') . $scope . ") AS total
             FROM course_categories cc
             WHERE cc.parent_id IS NULL
             ORDER BY total DESC, cc.name"
        ));

        $distribution = [];
        foreach ($rows as $row) {
            $distribution[] = ['label' => (string) $row['label'], 'slug' => (string) $row['slug'], 'total' => (int) $row['total']];
        }

        $orphans = $this->db->fetchAllAssociative(
            "SELECT COUNT(*)::int AS total FROM courses c
              WHERE c.status = 'published' AND c.category_id IS NULL" . $scope
        );
        $distribution[] = ['label' => 'Uncategorised', 'slug' => '', 'total' => (int) ($orphans[0]['total'] ?? 0)];

        return $distribution;
    }

