    public function startEnrolment(int $enrolmentId, int $userId): void
    {
        $enrolment = $this->db->fetchAssociative(
            "SELECT access_period_seconds, is_preview FROM course_enrolments
              WHERE id = :id AND user_id = :user_id AND status = 'assigned'",
            ['id' => $enrolmentId, 'user_id' => $userId]
        );
        if ($enrolment === false) {
            return;
        }

        $isPreview = $this->databaseBoolean($enrolment['is_preview']);
        $startedAt = new \DateTimeImmutable('now', new \DateTimeZone('UTC'));
        $expiresAt = $startedAt->modify(
            '+' . (int) $enrolment['access_period_seconds'] . ' seconds'
        );

        $this->db->executeStatement(
            "UPDATE course_enrolments
                SET status='active',started_at=:started_at,expires_at=:expires_at,updated_at=:started_at
              WHERE id=:id",
            [
                'started_at' => $startedAt->format('Y-m-d H:i:sP'),
                'expires_at' => $isPreview ? null : $expiresAt->format('Y-m-d H:i:sP'),
                'id' => $enrolmentId,
            ]
        );

        if (!$isPreview) {
            $this->db->executeStatement(
                "UPDATE course_credit_allocations
                 SET status='consumed', consumed_at=COALESCE(consumed_at,NOW()), returned_at=NULL
                 WHERE enrolment_id=:enrolment_id AND status='assigned'",
                ['enrolment_id' => $enrolmentId]
            );
        }
    }

