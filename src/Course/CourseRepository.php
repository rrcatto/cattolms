    /**
     * The ORDER BY a list should use: the reader's chosen column, or the dataset's default.
     *
     * @param array<string,string> $sorts
     */
    private static function orderFor(?SortOrder $sort, array $sorts, string $default, string $tiebreaker): string
    {
        // The tiebreaker is appended rather than replaced, so an ordering the reader chose is still
        // total and paging through it still shows every row exactly once. NULLS LAST in both
        // directions: "no value" is not a value that sorts, so a course never updated belongs at the
        // end whether the reader asked for oldest or newest first.
        return $sort === null
            ? $default
            : $sorts[$sort->key] . ' ' . $sort->sql() . ' NULLS LAST, ' . $tiebreaker;
    }

