    /** @return array<string,mixed> */
    public function createCertificate(
        int $enrolmentId,
        string $learnerName,
        string $certificateTitle,
        string $courseTitle,
        string $gradeCode,
        float $overallPercentage,
        string $template,
        string $bodyText,
        string $footerText,
        string $signatoryName,
        string $signatoryTitle,
        string $templateHtml = '',
        string $templateCss = ''
    ): array {
        $certificateM = new CertificatesM($this->db);
        $certificateM->load(['enrolment_id = ?', $enrolmentId]);

        if ($certificateM->dry()) {
            $publicId = Uuid::v4();
            $certificateM->public_id = $publicId;
            $certificateM->seed_token = $this->provenance->fromEnrolment($enrolmentId);
            $certificateM->enrolment_id = $enrolmentId;
            $certificateM->certificate_number = 'CL-' . gmdate('Y') . '-'
                . strtoupper(substr(str_replace('-', '', $publicId), 0, 12));
        }

        $certificateNumber = (string) $certificateM->certificate_number;
        $issuedAt = gmdate('Y-m-d H:i:sP');
        $context = $this->certificateContext($enrolmentId);
        $completionTimestamp = trim((string) ($context['completed_at'] ?? ''));
        try {
            $completionDateValue = $completionTimestamp !== ''
                ? new \DateTimeImmutable($completionTimestamp)
                : new \DateTimeImmutable('now');
            $completionDate = $completionDateValue
                ->setTimezone(new \DateTimeZone(Env::string('APP_TIMEZONE', 'UTC')))
                ->format('j F Y');
        } catch (\Throwable) {
            $completionDate = gmdate('j F Y');
        }
        $providerName = trim((string) ($context['provider_name'] ?? '')) ?: $this->settings->platformName();
        $verificationBase = rtrim(Env::string('APP_URL'), '/');
        $verificationUrl = ($verificationBase !== '' ? $verificationBase : '') . '/certificates/' . (string) $certificateM->public_id;
        if (trim($templateHtml) === '') {
            $templateHtml = '<section class="cl-certificate"><p>{{certificate_title}}</p><h1>{{student_name}}</h1><p>{{certificate_body}}</p><h2>{{course_title}}</h2><p>{{overall_percentage}}% · {{overall_grade}}</p><footer>{{signatory_name}}<br>{{signatory_title}}<br>{{certificate_footer}}<br>{{certificate_number}}</footer></section>';
        }
        $values = [
            'student_name' => $learnerName,
            'course_title' => $courseTitle,
            'course_provider' => $providerName,
            'completion_date' => $completionDate,
            'overall_percentage' => number_format($overallPercentage, 2, '.', ''),
            'overall_grade' => $gradeCode,
            'certificate_number' => $certificateNumber,
            'certificate_verification_url' => $verificationUrl,
            'signatory_name' => $signatoryName,
            'signatory_title' => $signatoryTitle,
            'certificate_title' => $certificateTitle,
            'certificate_body' => $bodyText,
            'certificate_footer' => $footerText,
        ];
        $rendered = $templateHtml;
        foreach ($values as $key => $value) {
            $rendered = str_replace('{{' . $key . '}}', htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'), $rendered);
        }

        $certificateM->learner_name = $learnerName;
        $certificateM->certificate_title = $certificateTitle;
        $certificateM->course_title = $courseTitle;
        $certificateM->grade_code = $gradeCode;
        $certificateM->overall_percentage = $overallPercentage;
        $certificateM->certificate_template = $template;
        $certificateM->certificate_body_text = $bodyText;
        $certificateM->certificate_footer_text = $footerText !== '' ? $footerText : null;
        $certificateM->certificate_signatory_name = $signatoryName !== '' ? $signatoryName : null;
        $certificateM->certificate_signatory_title = $signatoryTitle !== '' ? $signatoryTitle : null;
        $certificateM->issued_at = $issuedAt;
        $certificateM->template_html_snapshot = $templateHtml;
        $certificateM->template_css_snapshot = $templateCss;
        $certificateM->rendered_html = '<style>' . $templateCss . '</style>' . $rendered;
        $certificateM->revoked_at = null;
        $certificateM->revocation_reason = null;
        $certificateM->save();

        return $this->certificateForEnrolment($enrolmentId)
            ?? throw new RuntimeException('Unable to create certificate.');
    }


