    private static function andTitleSearch(string $search): array
    {
        $term = trim($search);
        if ($term === '') {
            return ['', []];
        }

        return [
            ' AND c.title::text ILIKE :search_term',
            [':search_term' => '%' . addcslashes($term, '%_\\') . '%'],
        ];
    }

    private const COMPANY_COURSES_WHERE = '(c.owner_company_id = :company_id
