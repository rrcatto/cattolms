    public function swapPriceVariantPositions(int $courseId, int $firstId, int $secondId): void
    {
        $first = $this->priceVariant($courseId, $firstId);
        $second = $this->priceVariant($courseId, $secondId);
        if ($first === null || $second === null) {
            throw new RuntimeException('The price variant could not be reordered.');
        }
        $temporaryRows = $this->db->exec(
            'SELECT COALESCE(MAX(position),0)+1 AS position FROM course_price_variants WHERE course_id=:course_id',
            [':course_id' => $courseId]
