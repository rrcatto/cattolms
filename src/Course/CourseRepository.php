        $enrolmentM->updated_at = $startedAt->format('Y-m-d H:i:sP');
        $enrolmentM->save();

        if (!$this->databaseBoolean($enrolmentM->is_preview)) {
            $this->db->exec(
                "UPDATE course_credit_allocations
                 SET status='consumed', consumed_at=COALESCE(consumed_at,NOW()), returned_at=NULL
                 WHERE enrolment_id=:enrolment_id AND status='assigned'",
