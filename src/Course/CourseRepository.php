    /**
     * The ancestor chain of a category, root first, for a breadcrumb.
     *
     * Recursive in form and bounded in fact: the level CHECK constraint caps the tree at three, so
     * this walks at most three rows. Written as a recursion anyway rather than as two hard-coded
     * self-joins, because the join count would silently become wrong if the cap ever moved, while
     * this would simply follow it.
     *
     * @return list<array<string,mixed>>
     */
    public function categoryAncestry(int $categoryId): array
    {
        return $this->normaliseRows($this->db->fetchAllAssociative(
            "WITH RECURSIVE chain AS (
                 SELECT id, parent_id, name, slug, level FROM course_categories WHERE id = :id
                 UNION ALL
                 SELECT p.id, p.parent_id, p.name, p.slug, p.level
                   FROM course_categories p JOIN chain ch ON p.id = ch.parent_id
             )
             SELECT id, name, slug, level FROM chain ORDER BY level",
            ['id' => $categoryId]
        ));
    }

