    /** @param array<string,mixed> $data */
    public function updateCategory(int $categoryId, array $data): void
    {
        if ($this->categoryById($categoryId) === null) {
            throw new RuntimeException('The course category does not exist.');
        }

        $set = 'name=:name,slug=:slug,description=:description,updated_at=:updated_at';
        $params = [
            'name' => (string) $data['name'],
            'slug' => (string) $data['slug'],
            'description' => (string) $data['description'],
            'updated_at' => date('Y-m-d H:i:sP'),
            'id' => $categoryId,
        ];
        if (array_key_exists('parent_id', $data)) {
            $parentId = (int) $data['parent_id'];
            $set .= ',parent_id=:parent_id,level=:level';
            $params['parent_id'] = $parentId > 0 ? $parentId : null;
            $params['level'] = $this->categoryLevelFor($parentId);
        }

        $this->db->executeStatement('UPDATE course_categories SET ' . $set . ' WHERE id=:id', $params);
    }

    /**
     * The level a category sits at, given its parent.
     *
     * One below the parent, or the top level when there is none. The database enforces the same
     * rule with a trigger; this is what makes the application agree with it rather than discover it
     * through an exception.
     */
    private function categoryLevelFor(int $parentId): int
    {
        if ($parentId < 1) {
            return 1;
        }

        $rows = $this->db->fetchAllAssociative('SELECT level FROM course_categories WHERE id = :id', ['id' => $parentId]);
        $parentLevel = (int) ($rows[0]['level'] ?? 0);
        if ($parentLevel < 1) {
            throw new RuntimeException('The parent course category does not exist.');
        }
        if ($parentLevel >= 3) {
            throw new RuntimeException('Course categories are limited to three levels, so this one cannot hold children.');
        }

        return $parentLevel + 1;
    }

