    /**
     * One SQL fragment and its bindings for everything the reader has narrowed the catalogue to.
     *
     * Built once and handed to both the count and the rows, which is the point. They are separate
     * statements describing what has to be one population, and the way that guarantee is lost is a
     * facet reaching one call site and not the other. Neither can apply half of this.
     *
     * The tag match is an EXISTS rather than a join: a course carries several tags, and joining
     * course_tags would multiply the row before the count ever saw it.
     *
     * @return array{0:string,1:array<string,mixed>}
     */
    private static function andCatalogueFilter(CatalogueFilter $filter): array
    {
        $sql = '';
        $bindings = [];

        if ($filter->categoryId !== null) {
            $sql .= ' AND ' . self::inBranchOf('c', ':category');
            $bindings['category'] = $filter->categoryId;
        }
        if ($filter->tagIds !== []) {
            // EXISTS rather than a join, and one EXISTS for the whole list rather than one each: a
            // course carries several tags, so joining course_tags would return it once per tag it
            // matched and the count would exceed the number of courses. Any of the tags qualifies -
            // see CatalogueFilter::toggleTag() for why a tag facet is a disjunction.
            //
            // The ids are cast integers resolved from slugs by this repository, never request text.
            $ids = implode(',', array_map('intval', $filter->tagIds));
            $sql .= " AND EXISTS (SELECT 1 FROM course_tags ct WHERE ct.course_id = c.id AND ct.tag_id IN ({$ids}))";
        }
        if ($filter->search !== '') {
            // Title, subtitle and summary, which is what a reader means by searching a catalogue.
            $sql .= " AND (c.title::text ILIKE :catalogue_search
                        OR COALESCE(c.subtitle,'')::text ILIKE :catalogue_search
                        OR COALESCE(c.summary,'')::text ILIKE :catalogue_search)";
            $bindings['catalogue_search'] = '%' . addcslashes($filter->search, '%_\\') . '%';
        }

        return [$sql, $bindings];
    }

    /**
     * Courses filed anywhere in one category's branch: the category itself, its children and its
     * grandchildren.
     *
     * Browsing a level includes everything below it - browsing Technology returns courses in
     * Technology, in Linux and in Linux Administration - and the three-level cap is what lets that
     * be two nested lookups instead of a recursive walk.
     *
     * Stated once and shared by the taxonomy counts, the browse count and the browse rows, because
     * a faceted count that disagrees with its own list is indistinguishable from missing data. Both
     * halves of a paginated browse have to mean the same thing by construction, not by two authors
     * happening to write the same SQL twice.
     *
     * Neither argument is ever request text: the root is a bound parameter name or a column, and the
     * alias is a literal in this file. A category slug from a URL is resolved to a row first.
     */
    private static function inBranchOf(string $courseAlias, string $root): string
    {
        return "{$courseAlias}.category_id IN (
                    SELECT d.id FROM course_categories d
                     WHERE d.id = {$root}
                        OR d.parent_id = {$root}
                        OR d.parent_id IN (SELECT s.id FROM course_categories s WHERE s.parent_id = {$root}))";
    }

    /** @return list<array<string,mixed>> */
    /**
     * The whole taxonomy, in tree order, with the number of courses filed under each.
     *
     * The universe matters here even though a category does not have one. A category is a shared
     * label, but the courses counted under it are business records, and a category page reporting a
     * thousand courses when three of them are genuine is a universe leak in a new costume. So the
     * count takes an explicit DataUniverse exactly as every other repository read does, and the
     * label itself takes none.
     *
     * `course_count` is the courses filed directly at this level. `descendant_course_count` is that
     * plus everything below it, which is what browsing a level actually shows: browsing Technology
     * returns courses in Technology, in Linux and in Linux Administration. The depth cap is what
     * lets that be a plain two-level join instead of a recursive walk.
     *
     * @return list<array<string,mixed>>
     */
    public function categories(bool $activeOnly = false): array
    {
        // A category exists or it does not. It carried an active flag that nobody asked for and
        // that no screen could explain, so the parameter is now inert and every caller sees the
        // whole taxonomy.
        $active = '';
        $scope = '';
        $descendantScope = '';

        return $this->normaliseRows($this->db->fetchAllAssociative(
            "SELECT cc.*,
                    parent.name AS parent_name,
                    grandparent.name AS grandparent_name,
                    (SELECT COUNT(*)::int FROM courses c
                      WHERE c.category_id = cc.id) AS course_count,
                    (SELECT COUNT(*)::int FROM courses dc
                      WHERE " . self::inBranchOf('dc', 'cc.id') . "{$descendantScope}) AS descendant_course_count,
                    (SELECT COUNT(*)::int FROM course_categories ch WHERE ch.parent_id = cc.id) AS child_count
             FROM course_categories cc
             LEFT JOIN course_categories parent ON parent.id = cc.parent_id
             LEFT JOIN course_categories grandparent ON grandparent.id = parent.parent_id
             {$active}
             -- Tree order: by the root branch, then by the sub-category within it, then by the
             -- sub-sub-category within that. A parent sorts immediately before its own children
             -- because the not-applicable levels sort as -1, which is below every real position.
             -- Sorting by level first instead would list all the sub-categories and only then all
             -- the sub-sub-categories, which reads as a flat list of three groups rather than as a
             -- tree.
             ORDER BY COALESCE(grandparent.position, parent.position, cc.position),
                      COALESCE(grandparent.name, parent.name, cc.name),
                      CASE cc.level WHEN 1 THEN -1 WHEN 2 THEN cc.position ELSE parent.position END,
                      CASE cc.level WHEN 1 THEN '' WHEN 2 THEN cc.name ELSE parent.name END,
                      CASE cc.level WHEN 3 THEN cc.position ELSE -1 END,
                      cc.name"
        ));
    }

    /**
     * One page of the courses filed directly in one category, for the catalogue's category browser.
     *
     * Directly, not the branch. Each category in the browser is its own accordion and its
     * sub-categories are accordions inside it, so counting a child's courses here would show every
     * course twice - once under the child and once under its parent.
     *
     * The cover comes back with the row because the browser draws a card per course. It is the one
     * list projection that selects cover_svg, which is why the column can sit on the table without
     * costing every other list anything.
     *
     * @return list<array<string,mixed>>
     */
    public function categoryCourses(int $categoryId, int $limit, int $offset): array
    {
        $keys = "SELECT c.id FROM courses c
                  WHERE c.status = 'published' AND c.category_id = :category_id"
            . '';

        $detail = "SELECT c.id, c.public_id, c.slug, c.title, c.subtitle, c.summary, c.level,
                          c.estimated_minutes, c.default_access_period_seconds, c.certificate_enabled,
                          c.cover_svg, c.category_id,
                          cat.name AS category_name, cat.slug AS category_slug,
                          cover.public_id AS cover_media_public_id,
                          (SELECT COUNT(*)::int FROM course_modules cm WHERE cm.course_id = c.id) AS module_count,
                          (SELECT cpv.price_minor_units FROM course_price_variants cpv
                            WHERE cpv.course_id=c.id AND cpv.is_active=TRUE AND cpv.is_default=TRUE LIMIT 1) AS default_price_minor_units,
                          (SELECT cpv.currency_code FROM course_price_variants cpv
                            WHERE cpv.course_id=c.id AND cpv.is_active=TRUE AND cpv.is_default=TRUE LIMIT 1) AS default_currency_code
                   FROM page
                   JOIN courses c ON c.id = page.id
                   LEFT JOIN course_categories cat ON cat.id = c.category_id
                   LEFT JOIN LATERAL (
                       SELECT public_id FROM course_media
                       WHERE course_id = c.id AND media_role = 'cover'
                       ORDER BY created_at DESC LIMIT 1
