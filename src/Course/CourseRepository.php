    /**
     * Adds or removes one company favourite, and says which it did.
     *
     * A single toggle rather than separate add and remove endpoints: the control on screen is one
     * button whose meaning depends on the current state, and two endpoints would let the page and
     * the database disagree about which one it is.
     */
    public function toggleCompanyFavourite(int $companyId, int $courseId, int $actorUserId): bool
    {
        $existing = $this->db->fetchAllAssociative(
            'SELECT 1 FROM company_favourites WHERE company_id = :company_id AND course_id = :course_id',
            ['company_id' => $companyId, 'course_id' => $courseId]
        );

        if ($existing !== []) {
            $this->db->executeStatement(
                'DELETE FROM company_favourites WHERE company_id = :company_id AND course_id = :course_id',
                ['company_id' => $companyId, 'course_id' => $courseId]
            );

            return false;
        }

        $this->db->executeStatement(
            'INSERT INTO company_favourites (company_id, course_id, added_by_user_id)
             VALUES (:company_id, :course_id, :actor)
             ON CONFLICT DO NOTHING',
            ['company_id' => $companyId, 'course_id' => $courseId, 'actor' => $actorUserId]
        );

        return true;
    }

