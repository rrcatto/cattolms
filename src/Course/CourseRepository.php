    public function allCourses(DataUniverse $universe, int $limit, int $offset, string $search = ''): array
    {
        [$where, $bindings] = self::whereScopeAndSearch($universe, 'c', $search);

        return $this->normaliseRows($this->db->exec(
            "SELECT c.id, c.public_id, c.slug, c.title, c.subtitle, c.summary, c.status, c.level,
                    c.updated_at, c.published_at, c.revision_number, c.owner_user_id, c.owner_company_id,
