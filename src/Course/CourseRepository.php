        return $this->databaseBoolean($rows[0]['allowed'] ?? false);
    }

    /** @return list<array<string,mixed>> */
    public function manageableCourses(int $userId): array
    {
        return $this->normaliseRows($this->db->exec(
            "SELECT c.id, c.public_id, c.slug, c.title, c.subtitle, c.summary, c.status, c.level,
                    c.updated_at, c.published_at, c.revision_number,
                    cc.name AS category_name,
                    oc.name AS owner_company_name,
                    COALESCE(NULLIF(trim(concat_ws(' ',ou.first_name,ou.last_name)),''),ou.display_name,oue.email) AS owner_person_name,
                    (SELECT COUNT(*)::int FROM course_modules cm WHERE cm.course_id=c.id) AS module_count,
                    (SELECT COUNT(*)::int FROM assessment_questions aq JOIN course_assessments ca ON ca.id=aq.assessment_id WHERE ca.course_id=c.id) AS question_count,
                    (SELECT COUNT(*)::int FROM course_editors ced2 WHERE ced2.course_id=c.id) AS editor_count,
                    (SELECT COUNT(DISTINCT ce.user_id)::int FROM course_enrolments ce WHERE ce.course_id=c.id AND ce.status IN ('assigned','active','completed') AND ce.is_preview=FALSE) AS learner_count,
                    (SELECT COUNT(DISTINCT ce.user_id)::int FROM course_enrolments ce WHERE ce.course_id=c.id AND ce.started_at IS NOT NULL AND ce.is_preview=FALSE) AS started_count
             FROM courses c
             LEFT JOIN course_categories cc ON cc.id=c.category_id
             LEFT JOIN companies oc ON oc.id=c.owner_company_id
             LEFT JOIN users ou ON ou.id=c.owner_user_id
             LEFT JOIN user_emails oue ON oue.user_id=ou.id AND oue.is_primary=TRUE
             WHERE c.owner_user_id=:user_id
                OR EXISTS (SELECT 1 FROM course_editors ced WHERE ced.course_id=c.id AND ced.user_id=:user_id)
                OR EXISTS (
                    SELECT 1 FROM company_users cu
                    WHERE cu.company_id=c.owner_company_id
                      AND cu.user_id=:user_id
                      AND cu.status='active'
                      AND cu.company_role IN ('owner','administrator','course_owner')
                )
             ORDER BY c.updated_at DESC,c.title",
            [':user_id' => $userId]
        ));
    }

    /** @return list<array<string,mixed>> */
    public function courseEditors(int $courseId): array
    {
        return $this->db->exec(
            'SELECT u.id,u.public_id,u.first_name,u.last_name,u.display_name,ue.email,co.name AS company_name
             FROM course_editors ce
             JOIN users u ON u.id=ce.user_id
             JOIN user_emails ue ON ue.user_id=u.id AND ue.is_primary=TRUE
             LEFT JOIN company_users cu ON cu.user_id=u.id AND cu.status=\'active\'
             LEFT JOIN companies co ON co.id=cu.company_id
             WHERE ce.course_id=:course_id
             ORDER BY COALESCE(NULLIF(trim(concat_ws(\' \',u.first_name,u.last_name)),\'\'),u.display_name,ue.email)',
            [':course_id' => $courseId]
        );
    }

    /** @param list<int> $userIds */
    public function replaceCourseEditors(int $courseId, array $userIds, int $actorUserId): void
    {
        $userIds = array_values(array_unique(array_filter(array_map('intval', $userIds), static fn(int $id): bool => $id > 0)));
        if ($userIds === []) {
            $this->db->exec('DELETE FROM course_editors WHERE course_id=:course_id', [':course_id' => $courseId]);
            return;
        }
        $placeholders = [];
        $params = [':course_id' => $courseId];
        foreach ($userIds as $index => $userId) {
            $key = ':u' . $index;
            $placeholders[] = $key;
            $params[$key] = $userId;
        }
        $this->db->exec(
            'DELETE FROM course_editors WHERE course_id=:course_id AND user_id NOT IN (' . implode(',', $placeholders) . ')',
            $params
        );
        foreach ($userIds as $userId) {
            $this->db->exec(
                'INSERT INTO course_editors (course_id,user_id,assigned_by_user_id,created_at)
                 VALUES (:course_id,:user_id,:actor_user_id,NOW())
                 ON CONFLICT (course_id,user_id) DO UPDATE SET assigned_by_user_id=EXCLUDED.assigned_by_user_id',
                [':course_id' => $courseId, ':user_id' => $userId, ':actor_user_id' => $actorUserId]
            );
        }
    }

    public function setCourseOwnership(int $courseId, int $ownerCompanyId, int $ownerUserId, int $actorUserId): void
    {
        if ($ownerCompanyId < 1 || $ownerUserId < 1) {
            throw new RuntimeException('Every course requires both an owning company and an owning person.');
        }
        $course = new CoursesM($this->db);
        $course->load(['id = ?', $courseId]);
        if ($course->dry()) {
            throw new RuntimeException('The course does not exist.');
        }
        $course->owner_company_id = $ownerCompanyId;
        $course->owner_user_id = $ownerUserId;
        $course->updated_by_user_id = $actorUserId;
        $course->updated_at = gmdate('Y-m-d H:i:sP');
        $course->save();
    }


    /** @return list<string> */
    private function jsonArray(mixed $value): array
    {
        if (is_array($value)) {
            return array_values(array_map('strval', $value));
        }
        if (!is_string($value) || trim($value) === '') {
            return [];
        }
        $decoded = json_decode($value, true);
        return is_array($decoded) ? array_values(array_map('strval', $decoded)) : [];
    }

    private function databaseBoolean(mixed $value): bool
    {
        return in_array($value, [true, 1, '1', 't', 'true'], true);
    }

    private function normaliseRows(array $rows): array
    {
        return array_map(fn(array $row): array => $this->normaliseRow($row), $rows);
    }

    /** @param array<string,mixed> $row @return array<string,mixed> */
    private function normaliseRow(array $row): array
    {
        $booleanKeys = [
            'certificate_enabled', 'is_review', 'assessment_required', 'required', 'is_correct', 'is_passing',
            'passed', 'is_public', 'practice_enabled', 'randomise_questions', 'randomise_options',
            'negative_marking', 'practice_eligible', 'graded_eligible', 'is_preview', 'is_visible', 'is_active', 'is_default',
        ];
        foreach ($booleanKeys as $key) {
            if (array_key_exists($key, $row)) {
                $row[$key] = $this->databaseBoolean($row[$key]);
            }
        }
        return $row;
    }
