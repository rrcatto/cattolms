    /**
     * Resolves tag slugs from a URL to ids, dropping anything unknown or retired.
     *
     * Dropping rather than failing, for the same reason an unknown category slug widens instead of
     * erroring: a stale or hand-edited link should show a reader courses.
     *
     * @param list<string> $slugs
     * @return list<array<string,mixed>>
     */
    public function activeTagsBySlug(array $slugs): array
    {
        if ($slugs === []) {
            return [];
        }

        $placeholders = [];
        $bindings = [];
        foreach ($slugs as $index => $slug) {
            $placeholders[] = ':s' . $index;
            $bindings['s' . $index] = $slug;
        }

        return $this->normaliseRows($this->db->fetchAllAssociative(
            'SELECT id, name, slug FROM tags WHERE slug IN (' . implode(',', $placeholders) . ')
             ORDER BY name',
            $bindings
        ));
    }

    /**
     * The tags carried by a page of courses, keyed by course.
     *
     * One statement for the whole page rather than one per card. A tag chip is worth showing on a
     * catalogue card, and it is not worth twenty-five queries.
     *
     * @param list<int> $courseIds
     * @return array<int,list<array<string,mixed>>>
     */
    public function tagsForCourses(array $courseIds): array
    {
        if ($courseIds === []) {
            return [];
        }

        // The ids are cast integers taken from rows this repository has just read, never request
        // text, so they are inlined rather than bound: the count varies with the page size and a
        // bound list would mean building placeholder names per call.
        $ids = implode(',', array_map('intval', $courseIds));

        $grouped = [];
        foreach ($this->db->fetchAllAssociative(
            "SELECT ct.course_id, t.id, t.name, t.slug
               FROM course_tags ct JOIN tags t ON t.id = ct.tag_id
              WHERE ct.course_id IN ({$ids})
              ORDER BY t.name"
        ) as $row) {
            $grouped[(int) $row['course_id']][] = [
                'id' => (int) $row['id'],
                'name' => (string) $row['name'],
                'slug' => (string) $row['slug'],
            ];
        }

        return $grouped;
    }

    /**
     * The active tags, most used first, for a tag cloud or a browse rail.
     *
     * @return list<array<string,mixed>>
     */
    public function popularTags(int $limit): array
    {
        $scope = '';

        return $this->normaliseRows($this->db->fetchAllAssociative(
