    /** @return list<array<string,mixed>> */
    public function questions(int $assessmentId, bool $includeCorrect = false): array
    {
        $questionM = new AssessmentQuestionsM($this->db);
        $questionRows = $questionM->find(
            ['assessment_id = ?', $assessmentId],
            ['order' => 'position']
        ) ?: [];

        $questions = [];
        foreach ($questionRows as $questionRow) {
            $optionM = new AssessmentOptionsM($this->db);
            $optionRows = $optionM->find(
                ['question_id = ?', (int) $questionRow->id],
                ['order' => 'position']
            ) ?: [];

            $options = [];
            foreach ($optionRows as $optionRow) {
