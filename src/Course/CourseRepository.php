    /**
     * Membership rule for "courses this person may manage": owned, edited, or owned by a company
     * they administer. Shared verbatim by the row query and the count, so the two can never
     * describe different populations and the "Showing X-Y of Z" line cannot lie.
     */
    private const MANAGEABLE_COURSES_WHERE = "c.owner_user_id=:user_id
                OR EXISTS (SELECT 1 FROM course_editors ced WHERE ced.course_id=c.id AND ced.user_id=:user_id)
                OR EXISTS (
                    SELECT 1 FROM company_users cu
                    WHERE cu.company_id=c.owner_company_id
                      AND cu.user_id=:user_id
                      AND cu.status='active'
                      AND cu.company_role IN ('owner','administrator','course_owner')
                )";

    /**
     * One page of the courses a non-platform administrator may manage.
     *
     * Carries the same correlated sub-selects per row as allCourses(), so bounding it matters
     * just as much: unbounded, it ran them once for every course the person could reach, on
     * every visit to /admin/courses.
     *
     * @return list<array<string,mixed>>
     */
    public function manageableCourses(int $userId, int $limit, int $offset, string $search = '', ?SortOrder $sort = null): array
    {
        $order = self::orderFor($sort, self::ADMIN_COURSE_SORTS, self::ADMIN_COURSE_ORDER, 'c.id');
        [$match, $bindings] = self::andTitleSearch($search);

        $keys = "SELECT c.id FROM courses c WHERE (" . self::MANAGEABLE_COURSES_WHERE . ")"
            . '' . $match;

        return $this->normaliseRows($this->db->fetchAllAssociative(
            PageQuery::deferred($keys, self::courseAdministrationDetail(), $order, $limit, $offset),
            ['user_id' => $userId] + $bindings
        ));
    }

    /** Total courses this person may manage; every join in the row query is a LEFT join, so membership is the WHERE clause alone. */
    public function manageableCoursesCount(int $userId, string $search = ''): int
    {
        $rows = $this->db->fetchAllAssociative(
            "SELECT COUNT(*)::int AS total FROM courses c WHERE (" . self::MANAGEABLE_COURSES_WHERE . ")" . '' . self::andTitleSearch($search)[0],
            ['user_id' => $userId] + self::andTitleSearch($search)[1]
        );

        return (int) ($rows[0]['total'] ?? 0);
    }

