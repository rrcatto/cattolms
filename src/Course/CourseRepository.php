    /** @return list<array<string,mixed>> */
    /**
     * Every enrolment a learner holds, unbounded.
     *
     * The Account dashboard summarises the whole set, so it reads this. The Course Library
     * displays it a page at a time and reads {@see libraryPage()} and {@see libraryCount()},
     * which apply the identical membership rule.
     *
     * @return list<array<string,mixed>>
     */
    public function library(int $userId, DataUniverse $universe): array
    {
        return $this->libraryPage($userId, $universe, self::LIBRARY_STATUSES, 0, 0, '');
    }

    /**
     * One page of a learner's enrolments, optionally narrowed to a status group.
     *
     * A limit of zero means the whole set: the unbounded read above and the paged read below are
     * the same query, so a status group cannot be counted by one rule and listed by another.
     *
     * @param list<string> $statuses
     * @return list<array<string,mixed>>
     */
    public function libraryPage(int $userId, DataUniverse $universe, array $statuses, int $limit, int $offset, string $search = ''): array
    {
        [$where, $bindings] = self::libraryFilter($userId, $universe, $statuses, $search);

        $rows = $this->db->exec(
            "SELECT ce.*, c.slug, c.title, c.subtitle, c.summary, c.level, c.status AS course_status,
                    cc.name AS category_name,
                    COUNT(DISTINCT cm.id)::int AS module_count,
                    COUNT(DISTINCT mp.module_id) FILTER (WHERE mp.first_opened_at IS NOT NULL)::int AS opened_module_count,
                    COUNT(DISTINCT mp.module_id) FILTER (WHERE mp.best_percentage IS NOT NULL)::int AS assessed_module_count,
                    cr.overall_percentage, cr.grade_code AS overall_grade_code,
                    cert.public_id AS certificate_public_id
             FROM course_enrolments ce
             JOIN courses c ON c.id = ce.course_id
             LEFT JOIN course_categories cc ON cc.id = c.category_id
             LEFT JOIN course_modules cm ON cm.course_id = c.id AND cm.assessment_required = TRUE
             LEFT JOIN module_progress mp ON mp.enrolment_id = ce.id AND mp.module_id = cm.id
             LEFT JOIN course_results cr ON cr.enrolment_id = ce.id
             LEFT JOIN certificates cert ON cert.enrolment_id = ce.id AND cert.revoked_at IS NULL
             " . $where . "
             GROUP BY ce.id, c.id, cc.name, cr.overall_percentage, cr.grade_code, cert.public_id
             ORDER BY ce.assigned_at DESC"
            . ($limit > 0 ? $this->limitOffset($limit, $offset) : ''),
            $bindings
        );
        return $this->normaliseRows($rows);
    }

    /**
     * Total enrolments behind {@see libraryPage()} under the identical membership rule.
     *
     * @param list<string> $statuses
     */
    public function libraryCount(int $userId, DataUniverse $universe, array $statuses = self::LIBRARY_STATUSES, string $search = ''): int
    {
        [$where, $bindings] = self::libraryFilter($userId, $universe, $statuses, $search);
        $rows = $this->db->exec(
            'SELECT COUNT(*)::int AS total FROM course_enrolments ce
             JOIN courses c ON c.id = ce.course_id ' . $where,
            $bindings
        );

        return (int) ($rows[0]['total'] ?? 0);
    }

    /**
     * The single membership rule behind every Course Library read.
     *
     * @param list<string> $statuses
     * @return array{0:string,1:array<string,mixed>}
     */
    private static function libraryFilter(int $userId, DataUniverse $universe, array $statuses, string $search): array
    {
        $allowed = array_values(array_intersect(self::LIBRARY_STATUSES, $statuses));
        if ($allowed === []) {
            $allowed = self::LIBRARY_STATUSES;
        }

        $bindings = [':user_id' => $userId];
        $names = [];
        foreach ($allowed as $index => $status) {
            $placeholder = ':library_status_' . $index;
            $names[] = $placeholder;
            $bindings[$placeholder] = $status;
        }

        $where = 'WHERE ce.user_id = :user_id AND ce.is_preview = FALSE'
            . ' AND ce.status IN (' . implode(',', $names) . ')';

        $scope = $universe->predicate('ce');
        if ($scope !== null) {
            $where .= ' AND ' . $scope;
        }

        [$match, $searchBindings] = self::andTitleSearch($search);

        return [$where . $match, $bindings + $searchBindings];
    }

