declare(strict_types=1);

namespace CattoLearning\Course;

final class ScorePolicy
{
    /** @param list<float> $values the attempts' percentages, oldest first */
    public static function aggregate(array $values, string $policy): float
    {
        if ($values === []) {
            return 0.0;
        }
        return match ($policy) {
            'average' => array_sum($values) / count($values),
            'latest' => $values[array_key_last($values)],
            default => max($values),
        };
    }
}
