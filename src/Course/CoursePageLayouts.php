declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\OptionRepository;

final class CoursePageLayouts
{
    private const OPTION = 'course_page.layout';

    public function __construct(
        private readonly OptionRepository $options,
        private readonly CourseRepository $courses,
        private readonly AuditRepository $audit
    ) {
    }

    /** @return list<array{id:string,width:string,shown:bool}> The layout of every course without one of its own. */
    public function siteDefault(): array
    {
        $json = $this->options->get(self::OPTION);
        return $json === '' ? CoursePageLayout::template('course') : CoursePageLayout::normalise(json_decode($json, true));
    }

    /** @return array{own:bool,layout:list<array{id:string,width:string,shown:bool}>} The layout a course's page uses. */
    public function forCourse(int $courseId): array
    {
        $own = $this->courses->pageLayout($courseId);
        return ['own' => $own !== null, 'layout' => $own ?? $this->siteDefault()];
    }

    /** @param list<array{id:string,width:string,shown:bool}> $layout */
    public function saveSiteDefault(array $layout, int $userId): void
    {
        $layout = CoursePageLayout::normalise($layout);
        $this->options->set(self::OPTION, json_encode($layout, JSON_THROW_ON_ERROR), $userId);
        $this->audit->record($userId, 'course_page.default_layout_saved', ['layout' => $layout]);
    }

    /**
     * A course's own layout, or the site's default again when null.
     *
     * @param list<array{id:string,width:string,shown:bool}>|null $layout
     */
    public function saveForCourse(int $courseId, ?array $layout, int $userId): void
    {
        $layout = $layout === null ? null : CoursePageLayout::normalise($layout);
        $this->courses->setPageLayout($courseId, $layout);
        $this->courses->recordHistory($courseId, $userId, 'course.page_layout_saved', 'course', $courseId,
            $layout === null ? 'The course page uses the default layout.' : 'The course page has a custom layout.', ['layout' => $layout]);
    }

    /**
     * The layout a builder's form asks for, and what it asked: save, a template ("template:buy"), a move ("move:about:up",
     * the arrows without JavaScript), a block hidden or shown ("hide:reviews", "show:reviews") or reset. Without JavaScript every button sends the whole form, so each acts on what
     * the form holds and saves it; with JavaScript the page changes in place and only Save layout and Reset are sent.
     *
     * @param array<string,mixed> $input
     * @return array{0:list<array{id:string,width:string,shown:bool}>,1:string}
     */
    public static function fromForm(array $input): array
    {
        $layout = CoursePageLayout::fromInput($input);
        $action = (string) ($input['action'] ?? 'save');
        if (str_starts_with($action, 'template:')) {
            return [CoursePageLayout::template(substr($action, 9)), 'template'];
        }
        if (preg_match('/^move:([a-z]+):(up|down)$/', $action, $match) === 1) {
            return [CoursePageLayout::move($layout, $match[1], $match[2]), 'move'];
        }
        if (preg_match('/^(hide|show):([a-z]+)$/', $action, $match) === 1) {
            $shown = $match[1] === 'show';
            return [CoursePageLayout::normalise(array_map(static fn(array $block): array => $block['id'] === $match[2] ? ['shown' => $shown] + $block : $block, $layout)), $match[1]];
        }
        return [$layout, $action === 'reset' ? 'reset' : 'save'];
    }

    /**
     * What the builder shows: the layout, which template it matches, the templates drawn small, and the blocks in
     * order with their names, notes and whether they may be hidden.
     *
     * @param list<array{id:string,width:string,shown:bool}> $layout
     * @return array<string,mixed>
     */
    public static function builder(array $layout): array
    {
        $blocks = array_map(static fn(array $block): array => $block + [
            'name' => CoursePageLayout::BLOCKS[$block['id']]['name'],
            'note' => CoursePageLayout::BLOCKS[$block['id']]['note'],
            'required' => in_array($block['id'], CoursePageLayout::ALWAYS_SHOWN, true),
        ], $layout);
        $templates = [];
        foreach (CoursePageLayout::TEMPLATE_NAMES as $key => $name) {
            $templates[] = [
                'key' => $key, 'name' => $name, 'note' => CoursePageLayout::TEMPLATE_NOTES[$key],
                'current' => CoursePageLayout::isTemplate($layout, $key),
                'cells' => array_map(static fn(array $block): array => ['id' => $block['id'], 'width' => $block['width'], 'name' => CoursePageLayout::BLOCKS[$block['id']]['name']], CoursePageLayout::template($key)),
            ];
        }
        return [
            'blocks' => $blocks,
            'order' => implode(',', array_column($layout, 'id')),
            'templates' => $templates,
            // The templates as data for the builder's script, which applies one without a page load.
            'templates_json' => json_encode(array_map(static fn(string $key): array => CoursePageLayout::template($key), array_combine(array_keys(CoursePageLayout::TEMPLATES), array_keys(CoursePageLayout::TEMPLATES))), JSON_THROW_ON_ERROR),
        ];
    }
}
