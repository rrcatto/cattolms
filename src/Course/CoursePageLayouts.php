namespace CattoLearning\Course;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use InvalidArgumentException;

final class CoursePageLayouts
{
    public const NAME_MAX = 80;

    public const PURPOSE_MAX = 160;

    /** What a course's page uses, as the course's Page layout tab offers them. */
    public const CHOICES = ['default', 'layout', 'custom'];

    public function __construct(
        private readonly CoursePageLayoutRepository $layouts,
        private readonly CourseRepository $courses,
        private readonly CourseItemService $items,
        private readonly CourseReviewRepository $reviews,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit
    ) {
    }

    /**
     * Every layout, the default first, each with how many courses use it (the default's count takes in the courses on
     * the default layout).
     *
     * @return list<array{id:int,name:string,purpose:string,blocks:list<array{id:string,width:string,shown:bool}>,is_default:bool,updated_at:string,courses:int}>
     */
    public function all(): array
    {
        $onDefault = count(array_filter($this->layouts->courses(), static fn(array $course): bool => $course['choice'] === 'default'));
        return array_map(static fn(array $layout): array => $layout['is_default'] ? ['courses' => $layout['courses'] + $onDefault] + $layout : $layout, $this->layouts->all());
    }

    /** @return array{id:int,name:string,purpose:string,blocks:list<array{id:string,width:string,shown:bool}>,is_default:bool,updated_at:string,courses:int} */
    public function layout(int $id): array
    {
        foreach ($this->all() as $layout) {
            if ($layout['id'] === $id) return $layout;
        }
        throw new InvalidArgumentException('There is no such layout.');
    }

    /**
     * The default layout. A site always has one (the baseline makes Default, and the default is never deleted); were it
     * missing, the starting arrangement stands in.
     *
     * @return array{id:int,name:string,blocks:list<array{id:string,width:string,shown:bool}>}
     */
    public function defaultLayout(): array
    {
        $layout = $this->layouts->findDefault();
        return $layout === null ? ['id' => 0, 'name' => 'Default', 'blocks' => CoursePageLayout::starting()] : $layout;
    }

    /** @param list<array{id:string,width:string,shown:bool}> $blocks */
    public function create(string $name, string $purpose, array $blocks, int $userId): int
    {
        return $this->transactions->run(function () use ($name, $purpose, $blocks, $userId): int {
            $this->layouts->lockAll();
            $name = $this->freeName($name, null);
            $id = $this->layouts->insert($name, self::purpose($purpose), CoursePageLayout::normalise($blocks), $userId);
            $this->audit->record($userId, 'course_page_layout.created', ['layout_id' => $id, 'name' => $name]);
            return $id;
        });
    }

    /** @param list<array{id:string,width:string,shown:bool}> $blocks */
    public function update(int $id, string $name, string $purpose, array $blocks, int $userId): void
    {
        $this->transactions->run(function () use ($id, $name, $purpose, $blocks, $userId): void {
            $this->layouts->lockAll();
            $before = $this->layouts->find($id) ?? throw new InvalidArgumentException('There is no such layout.');
            $name = $this->freeName($name, $id);
            $blocks = CoursePageLayout::normalise($blocks);
            $this->layouts->update($id, $name, self::purpose($purpose), $blocks, $userId);
            $this->audit->record($userId, 'course_page_layout.saved', ['layout_id' => $id, 'name' => $name, 'renamed_from' => $before['name'] === $name ? null : $before['name'], 'blocks' => $blocks]);
        });
    }

    /** A copy named "Copy of …" (made unique), to change without touching the original. */
    public function copy(int $id, int $userId): int
    {
        return $this->transactions->run(function () use ($id, $userId): int {
            $this->layouts->lockAll();
            $from = $this->layouts->find($id) ?? throw new InvalidArgumentException('There is no such layout.');
            $base = mb_substr('Copy of ' . $from['name'], 0, self::NAME_MAX - 3);
            $name = $base;
            for ($n = 2; $this->layouts->findByName($name) !== null; $n++) { $name = $base . ' ' . $n; }
            $copy = $this->layouts->insert($name, $from['purpose'], $from['blocks'], $userId);
            $this->audit->record($userId, 'course_page_layout.created', ['layout_id' => $copy, 'name' => $name, 'copied_from' => $id]);
            return $copy;
        });
    }

    /** Makes this layout the default: every course on the default layout follows it from now on. */
    public function makeDefault(int $id, int $userId): void
    {
        $this->transactions->run(function () use ($id, $userId): void {
            $this->layouts->lockAll();
            $layout = $this->layouts->find($id) ?? throw new InvalidArgumentException('There is no such layout.');
            if ($layout['is_default']) return;
            $this->layouts->makeDefault($id, $userId);
            $this->audit->record($userId, 'course_page_layout.made_default', ['layout_id' => $id, 'name' => $layout['name']]);
        });
    }

    /** Deletes a layout no course uses that is not the default; says why otherwise. */
    public function delete(int $id, int $userId): string
    {
        return $this->transactions->run(function () use ($id, $userId): string {
            $this->layouts->lockAll();
            $layout = $this->layouts->find($id) ?? throw new InvalidArgumentException('There is no such layout.');
            if ($layout['is_default']) throw new InvalidArgumentException('"' . $layout['name'] . '" is the default layout, so it cannot be deleted. Make another layout the default first.');
            if ($layout['courses'] > 0) {
                throw new InvalidArgumentException('"' . $layout['name'] . '" is used by ' . $layout['courses'] . ' ' . ($layout['courses'] === 1 ? 'course' : 'courses') . ', so it cannot be deleted. Give ' . ($layout['courses'] === 1 ? 'it' : 'them') . ' another layout first.');
            }
            $this->layouts->delete($id);
            $this->audit->record($userId, 'course_page_layout.deleted', ['layout_id' => $id, 'name' => $layout['name'], 'blocks' => $layout['blocks']]);
            return $layout['name'];
        });
    }

    /**
     * What a course's page uses: the choice, the layout (the default or one chosen by name; none for its custom
     * layout), the blocks the page is drawn with, and its custom layout, kept while another is chosen.
     *
     * @return array{choice:string,layout:array{id:int,name:string,blocks:list<array{id:string,width:string,shown:bool}>}|null,blocks:list<array{id:string,width:string,shown:bool}>,custom:list<array{id:string,width:string,shown:bool}>|null}
     */
    public function forCourse(int $courseId): array
    {
        $choice = $this->layouts->choiceOf($courseId) ?? throw new InvalidArgumentException('The course does not exist.');
        if ($choice['choice'] === 'custom' && $choice['custom'] !== null) {
            return ['choice' => 'custom', 'layout' => null, 'blocks' => $choice['custom'], 'custom' => $choice['custom']];
        }
        $layout = $choice['choice'] === 'layout' && $choice['layout_id'] !== null ? $this->layouts->find($choice['layout_id']) : null;
        $layout ??= $this->defaultLayout();
        return ['choice' => $choice['choice'] === 'layout' ? 'layout' : 'default', 'layout' => $layout, 'blocks' => $layout['blocks'], 'custom' => $choice['custom']];
    }

    /**
     * Sets what a course's page uses. Custom layout takes the blocks given, else the custom layout it has, else a
     * copy of what it used until now; choosing another keeps the custom layout to come back to.
     *
     * @param list<array{id:string,width:string,shown:bool}>|null $custom
     */
    public function choose(int $courseId, string $choice, ?int $layoutId, ?array $custom, int $userId): string
    {
        if (!in_array($choice, self::CHOICES, true)) throw new InvalidArgumentException('Choose the default layout, one of your layouts or a custom layout.');
        return $this->transactions->run(function () use ($courseId, $choice, $layoutId, $custom, $userId): string {
            $current = $this->forCourse($courseId);
            $layout = null;
            if ($choice === 'layout') {
                $layout = $layoutId === null ? null : $this->layouts->find($layoutId);
                if ($layout === null) throw new InvalidArgumentException('Choose which of your layouts this course uses.');
            }
            if ($choice === 'custom') {
                $custom = CoursePageLayout::normalise($custom ?? $current['custom'] ?? $current['blocks']);
            }
            $this->layouts->choose($courseId, $choice, $layout['id'] ?? null, $choice === 'custom' ? $custom : null);
            $words = match ($choice) {
                'default' => 'The course page uses the default layout (' . $this->defaultLayout()['name'] . ').',
                'layout' => 'The course page uses the layout ' . $layout['name'] . '.',
                default => $current['choice'] === 'custom' ? 'The custom layout of the course page was saved.' : 'The course page uses its custom layout.',
            };
            $this->courses->recordHistory($courseId, $userId, 'course.page_layout_saved', 'course', $courseId, $words,
                ['choice' => $choice, 'layout_id' => $layout['id'] ?? null, 'layout' => $choice === 'custom' ? $custom : null]);
            return $words;
        });
    }

    /**
     * Gives the courses ticked the default layout ($layoutId 0) or one of the layouts. A course with a custom layout
     * keeps it, to choose again on its Page layout tab.
     *
     * @param list<int> $courseIds
     * @return int how many courses changed
     */
    public function apply(array $courseIds, int $layoutId, int $userId): int
    {
        $courseIds = array_values(array_unique(array_filter($courseIds, static fn(int $id): bool => $id > 0)));
        if ($courseIds === []) throw new InvalidArgumentException('Tick the courses to give the layout to.');
        if ($layoutId > 0 && $this->layouts->find($layoutId) === null) throw new InvalidArgumentException('There is no such layout.');
        return $this->transactions->run(function () use ($courseIds, $layoutId, $userId): int {
            $changed = 0;
            foreach ($courseIds as $courseId) {
                $current = $this->layouts->choiceOf($courseId);
                if ($current === null) continue;
                $choice = $layoutId > 0 ? 'layout' : 'default';
                if ($current['choice'] === $choice && ($choice === 'default' || $current['layout_id'] === $layoutId)) continue;
                $this->choose($courseId, $choice, $layoutId > 0 ? $layoutId : null, null, $userId);
                $changed++;
            }
            return $changed;
        });
    }

    /**
     * Makes a course's custom layout one of the layouts, under a name, and the course uses it from then on (its custom
     * layout is kept).
     *
     * @param list<array{id:string,width:string,shown:bool}> $blocks
     */
    public function saveAsLayout(int $courseId, string $name, array $blocks, int $userId): int
    {
        return $this->transactions->run(function () use ($courseId, $name, $blocks, $userId): int {
            $id = $this->create($name, '', $blocks, $userId);
            $this->layouts->choose($courseId, 'custom', null, CoursePageLayout::normalise($blocks));
            $this->choose($courseId, 'layout', $id, null, $userId);
            return $id;
        });
    }

    /**
     * What a course's page needs to know of its blocks, as its page counts them: its modules and figures, its approved
     * reviews, whether it has a free preview and its published related courses. A reader who owns the course is not
     * counted here: these are the page as a visitor sees it.
     *
     * @return array{modules:int,figures:int,reviews:int,preview:bool,related:int}
     */
    public function facts(int $courseId): array
    {
        return $this->factsFor([$courseId])[$courseId];
    }

    /**
     * @param list<int> $courseIds
     * @return array<int,array{modules:int,figures:int,reviews:int,preview:bool,related:int}>
     */
    public function factsFor(array $courseIds): array
    {
        $ratings = $this->reviews->ratingSummaries($courseIds);
        $facts = [];
        foreach ($courseIds as $courseId) {
            $facts[$courseId] = CoursePageView::facts($this->items->availability($courseId, null, false)) + [
                'reviews' => isset($ratings[$courseId]) ? $ratings[$courseId]->count : 0,
                'related' => count($this->courses->publishedCoursesByIds($this->courses->relatedCourseIds($courseId))),
            ];
        }
        return $facts;
    }

    /**
     * Every course with the layout its page uses and the blocks it leaves out, for the layouts' page.
     *
     * @return list<array{id:int,code:string,title:string,slug:string,status:string,choice:string,layout_id:?int,layout_name:string,left_out:list<array{id:string,name:string,reason:string}>,present:list<string>}>
     */
    public function courses(): array
    {
        $courses = $this->layouts->courses();
        $layouts = array_column($this->layouts->all(), null, 'id');
        $default = $this->defaultLayout();
        $facts = $this->factsFor(array_column($courses, 'id'));
        $rows = [];
        foreach ($courses as $course) {
            $custom = $course['choice'] === 'custom' ? $this->layouts->choiceOf($course['id'])['custom'] ?? null : null;
            $layout = $course['choice'] === 'layout' && isset($layouts[$course['layout_id']]) ? $layouts[$course['layout_id']] : $default;
            $blocks = $custom ?? $layout['blocks'];
            $rows[] = $course + [
                'layout_name' => $custom !== null ? 'Custom' : $layout['name'],
                'left_out' => CoursePageLayout::leftOut($blocks, $facts[$course['id']]),
                'present' => CoursePageLayout::present($facts[$course['id']]),
            ];
        }
        return $rows;
    }

    /**
     * The layout a builder's form asks for, and what it asked: save, a move ("move:about:up", the arrows without
     * JavaScript), a block hidden or shown ("hide:reviews", "show:reviews"), or a layout copied in ("start" with the
     * layout chosen in start_from, Start again from on a course's custom layout, given back as "start:3"). Without JavaScript every button sends the whole form, so each acts on
     * what the form holds; with JavaScript the page changes in place and only saving is sent.
     *
     * @param array<string,mixed> $input
     * @return array{0:list<array{id:string,width:string,shown:bool}>,1:string}
     */
    public static function fromForm(array $input): array
    {
        $layout = CoursePageLayout::fromInput($input);
        $action = (string) ($input['action'] ?? 'save');
        if (preg_match('/^move:([a-z]+):(up|down)$/', $action, $match) === 1) {
            return [CoursePageLayout::move($layout, $match[1], $match[2]), 'move'];
        }
        if (preg_match('/^(hide|show):([a-z]+)$/', $action, $match) === 1) {
            $shown = $match[1] === 'show';
            return [CoursePageLayout::normalise(array_map(static fn(array $block): array => $block['id'] === $match[2] ? ['shown' => $shown] + $block : $block, $layout)), $match[1]];
        }
        if ($action === 'start') {
            return [$layout, 'start:' . (int) ($input['start_from'] ?? 0)];
        }
        return [$layout, 'save'];
    }

    /**
     * What the builder shows: the blocks in order with their names, notes and whether they may be hidden.
     *
     * @param list<array{id:string,width:string,shown:bool}> $layout
     * @return array{blocks:list<array<string,mixed>>,order:string}
     */
    public static function builder(array $layout): array
    {
        return [
            'blocks' => array_map(static fn(array $block): array => $block + [
                'name' => CoursePageLayout::BLOCKS[$block['id']]['name'],
                'note' => CoursePageLayout::BLOCKS[$block['id']]['note'],
                'required' => in_array($block['id'], CoursePageLayout::ALWAYS_SHOWN, true),
            ], $layout),
            'order' => implode(',', array_column($layout, 'id')),
        ];
    }

    /**
     * A layout drawn small: its shown blocks in order, each with its name and width.
     *
     * @param list<array{id:string,width:string,shown:bool}> $layout
     * @return list<array{id:string,width:string,name:string}>
     */
    public static function cells(array $layout): array
    {
        return array_values(array_map(static fn(array $block): array => ['id' => $block['id'], 'width' => $block['width'], 'name' => CoursePageLayout::BLOCKS[$block['id']]['name']],
            array_filter($layout, static fn(array $block): bool => $block['shown'])));
    }

    /**
     * The sketch of a course's page under a layout (the layouts' pages and a course's Page layout tab): every block in the layout's order, each drawn or not (hidden in
     * the layout, or left out for this course with why).
     *
     * @param list<array{id:string,width:string,shown:bool}> $blocks
     * @param list<string> $present
     * @return array{cells:list<array{id:string,width:string,name:string,drawn:bool}>,left_out:list<array{id:string,name:string,reason:string}>}
     */
    public static function sketch(array $blocks, array $present): array
    {
        $cells = array_map(static fn(array $block): array => ['id' => $block['id'], 'width' => $block['width'], 'name' => CoursePageLayout::BLOCKS[$block['id']]['name'],
            'reason' => CoursePageLayout::LEFT_OUT[$block['id']] ?? '', 'drawn' => $block['shown'] && in_array($block['id'], $present, true)], $blocks);
        $leftOut = array_values(array_map(static fn(array $cell): array => ['id' => $cell['id'], 'name' => $cell['name'], 'reason' => $cell['reason']],
            array_filter($cells, static fn(array $cell): bool => !$cell['drawn'] && in_array($cell['id'], array_column(array_filter($blocks, static fn(array $block): bool => $block['shown']), 'id'), true))));
        return ['cells' => $cells, 'left_out' => $leftOut];
    }

    /** A name a layout may have: one line, at most 80 letters, no other layout's. */
    private function freeName(string $name, ?int $id): string
    {
        $name = trim((string) preg_replace('/\s+/u', ' ', $name));
        if ($name === '') throw new InvalidArgumentException('Give the layout a name.');
        if (mb_strlen($name) > self::NAME_MAX) throw new InvalidArgumentException('A layout\'s name is at most ' . self::NAME_MAX . ' letters long.');
        $other = $this->layouts->findByName($name);
        if ($other !== null && $other['id'] !== $id) throw new InvalidArgumentException('Another layout is called "' . $other['name'] . '". Give this one a name of its own.');
        return $name;
    }

    /** What a layout is for: one line, at most 160 letters. */
    private static function purpose(string $purpose): string
    {
        $purpose = trim((string) preg_replace('/\s+/u', ' ', $purpose));
        if (mb_strlen($purpose) > self::PURPOSE_MAX) throw new InvalidArgumentException('What a layout is for is at most ' . self::PURPOSE_MAX . ' letters long.');
        return $purpose;
    }
}
