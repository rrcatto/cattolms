    /** @return array<string,mixed> */
    public function courseHome(int $userId, string $slug, bool $preview = false): array
    {
        $course = $this->courses->findBySlug(Slug::validate($slug));
        if ($course === null) {
            throw new InvalidArgumentException('The course does not exist.');
        }
        $enrolment = $this->courses->enrolment($userId, (int) $course['id'], $preview);
        if ($enrolment === null) {
            throw new InvalidArgumentException($preview ? 'Start a course preview first.' : 'This course is not in your library.');
        }
        if (!($this->commerceAccess?->assertAccess((int)$enrolment['id']) ?? false)) {
            $this->assertNotExpired($enrolment);
        }
        $course['grade_bands'] = GradeScale::ranges($this->courses->gradeBands((int) $course['id']));
        $course['introduction_html'] = GradeScale::resolve((string) ($course['introduction_html'] ?? ''), $course['grade_bands']);
        $course['enrolment'] = $enrolment;
        $course['structure'] = $this->courseItems->availability((int) $course['id'], empty($enrolment['started_at']) ? null : (string) $enrolment['started_at'], false);
        $course['progress'] = $this->courseItemRecords->assessmentProgress((int) $enrolment['id'], (int) $course['id']);
        $course['is_preview'] = $preview;
        $course['remaining_access_label'] = empty($enrolment['expires_at']) ? '' : CourseItemService::duration((int) ceil(max(0, (strtotime((string) $enrolment['expires_at']) ?: time()) - time()) / 60));
        $certificate = $this->certificates->forEnrolment((int) $enrolment['id']);
        $course['certificate'] = $certificate !== null && $certificate['revoked_at'] === null ? $certificate : null;
        return $course;
    }

    public function start(int $userId, string $slug, bool $preview = false): void
    {
        $course = $this->courses->findBySlug(Slug::validate($slug));
        if ($course === null) {
            throw new InvalidArgumentException('The course does not exist.');
        }
        $enrolment = $this->courses->enrolment($userId, (int) $course['id'], $preview);
        if ($enrolment === null) {
            throw new InvalidArgumentException('This course is not in your library.');
        }
        if (!$preview) { $this->assertNotExpired($enrolment); }
        if ($this->commerceAccess?->start((int)$enrolment['id'])) return;
        if ((string) $enrolment['status'] === 'assigned') {
            $this->courses->startEnrolment((int) $enrolment['id'], $userId);
            $this->audit->record($userId, 'course.started', [
                'course_id' => (int) $course['id'],
                'enrolment_id' => (int) $enrolment['id'],
            ]);
        }
    }

    /**
     * The file behind a Downloadable File, for one learner at one course placement. The placement
     * must belong to the course, the learner's enrolment must be started, current and not removed,
     * and the placement must be unlocked. The item is the placement's own, or a Downloadable File the
     * placement's HTML lesson embeds with [course-item:key].
     *
     * @return array{path:string,filename:string,mime_type:string}
     * @throws InvalidArgumentException when this learner may not download it here
     * @throws ResourceUnavailable when the Resource or its stored file is missing
     */
    public function download(int $userId, string $slug, int $nodeId, string $itemKey, bool $preview = false): array
    {
        $course = $this->courseHome($userId, $slug, $preview);
        $enrolment = (array) $course['enrolment'];
        if (empty($enrolment['started_at'])) {
            throw new InvalidArgumentException('Start the course before downloading its files.');
        }
        if (!$preview && (!in_array((string) ($enrolment['status'] ?? ''), ['active', 'completed'], true) || !empty($enrolment['access_removed_at']))) {
            throw new InvalidArgumentException('Your access to this course has ended.');
        }
        $node = null;
        foreach ((array) $course['structure'] as $row) {
            if ((int) $row['id'] === $nodeId && ($row['node_type'] ?? '') === 'item') { $node = $row; break; }
        }
        if ($node === null) {
            throw new InvalidArgumentException('That download is not part of this course.');
        }
        if (!empty($node['is_locked']) && !$preview) {
            throw new InvalidArgumentException('This file is not available yet.');
        }
        if ((string) $node['item_key'] === $itemKey) {
            $item = $this->courseItemRecords->item((int) $node['course_item_id']);
        } elseif (($node['item_type'] ?? '') === 'html_lesson' && $this->courseItemRecords->itemReferencesKey((int) $node['course_item_id'], $itemKey)) {
            $item = $this->courseItemRecords->itemByKey($itemKey);
        } else {
            throw new InvalidArgumentException('That download is not part of this course.');
        }
        if ($item === null || ($item['item_type'] ?? '') !== 'downloadable_file') {
            throw new InvalidArgumentException('That download is not part of this course.');
        }
        $resource = $this->courseItemRecords->resource((int) ($item['resource_id'] ?? 0));
        if ($resource === null) {
            throw new ResourceUnavailable('The file for this download is missing.');
        }
        $path = $this->resources->path($resource);
        if (!is_file($path) || !is_readable($path)) {
            throw new ResourceUnavailable('The file for this download is missing.');
        }
        return [
            'path' => $path,
            'filename' => (string) ($resource['original_filename'] ?: $resource['filename']),
            'mime_type' => (string) ($resource['mime_type'] ?: 'application/octet-stream'),
        ];
    }

    /** @return array<string,mixed> */
    public function item(int $userId, string $slug, int $nodeId, bool $preview = false): array
    {
        $course = $this->courseHome($userId, $slug, $preview);
        $enrolment = (array) $course['enrolment'];
        if (empty($enrolment['started_at'])) {
            throw new InvalidArgumentException('Click Start course before opening Course Content.');
        }
        $node = null;
        foreach (CourseNavigation::sequence((array) $course['structure']) as $row) {
            if ((int) $row['id'] === $nodeId) { $node = $row; }
        }
        if ($node === null) { throw new InvalidArgumentException('The Course Item placement does not exist.'); }
        if (!empty($node['is_locked']) && !$preview) { throw new InvalidArgumentException('This Course Item is not available yet.'); }
        if (($node['assessment_role'] ?? '') === 'final' && !$preview && !$this->courseItemRecords->precedingGradedAssessmentsSubmitted((int) $enrolment['id'], (int) $course['id'], $nodeId)) { throw new InvalidArgumentException('Submit every preceding graded assessment before opening the final assessment.'); }
        $around = CourseNavigation::neighbours((array) $course['structure'], $nodeId);
        $node['previous_node'] = $around['previous'];
        $node['next_node'] = $around['next'];
        $node['rendered_html'] = $node['node_type'] === 'section' ? (string) $node['section_introduction_html'] : $this->courseItemRenderer->render($node, (string) $course['slug'], $nodeId, false);
        $node['rendered_html'] = GradeScale::resolve($node['rendered_html'], (array) $course['grade_bands']);
        if ($preview) { $node['rendered_html'] = preg_replace('/(href="\/learn\/[^"?]+)(")/', '$1?preview=1$2', $node['rendered_html']) ?? $node['rendered_html']; }
        $course['item'] = $node;
        $course['current_node_id'] = $nodeId;
        return $course;
    }

    /** @param array<string,mixed> $enrolment */
    private function assertNotExpired(array $enrolment): void
    {
        if ($this->expired($enrolment)) {
            $this->courses->markEnrolmentExpired((int) $enrolment['id']);
            throw new InvalidArgumentException('Your access period for this course has expired.');
        }
    }

    /** @param array<string,mixed> $enrolment */
    private function expired(array $enrolment): bool
    {
        $expires = trim((string) ($enrolment['expires_at'] ?? ''));
        return $expires !== '' && (strtotime($expires) ?: PHP_INT_MAX) < time();
    }

    private function durationLabel(int $seconds): string
    {
        $days = max(1, (int) round($seconds / 86400));
        if ($days % 365 === 0) {
            $years = (int) ($days / 365);
            return $years . ' year' . ($years === 1 ? '' : 's');
        }
        if ($days % 30 === 0) {
            $months = (int) ($days / 30);
            return $months . ' month' . ($months === 1 ? '' : 's');
        }
        return $days . ' days';
    }
