declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Infrastructure\Persistence\RoleRepository;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputArgument;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Output\OutputInterface;

#[AsCommand(name: 'course:arrange-modules', description: 'Arrange courses of the older shape into numbered module sections.')]
final class CourseArrangeCommand extends Command
{
    public function __construct(private readonly CourseRestructurer $restructurer, private readonly CourseRepository $courses, private readonly RoleRepository $roles)
    {
        parent::__construct();
    }

    protected function configure(): void
    {
        $this->addArgument('codes', InputArgument::IS_ARRAY, 'The courses\' codes; none means every course that needs it.');
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $actor = $this->roles->firstUserWithRole('ADMIN');
        if ($actor === null) {
            $output->writeln('<error>Sign ADMIN in once first: the courses are arranged as ADMIN.</error>');
            return Command::FAILURE;
        }
        $codes = array_map('strtoupper', (array) $input->getArgument('codes'));
        $failed = 0;
        foreach ($this->courses->codes() as $id => $code) {
            if ($codes !== [] && !in_array($code, $codes, true)) { continue; }
            if (!$this->restructurer->needsArranging($id)) { $output->writeln($code . ': already arranged, left as it is.'); continue; }
            try {
                $report = $this->restructurer->arrange($id, $actor);
                $output->writeln(sprintf('%s: %d modules%s, %d videos, %d practical work items, %d summaries, %d outcome lists moved into their sections.', $code, $report['modules'], $report['review'] ? ' and a review' : '', $report['videos'], $report['practicals'], $report['summaries'], $report['outcomes']));
            } catch (\InvalidArgumentException|\RuntimeException $exception) {
                $failed++;
                $output->writeln('<error>' . $code . ': ' . $exception->getMessage() . '</error>');
            }
        }
        return $failed === 0 ? Command::SUCCESS : Command::FAILURE;
    }
}
