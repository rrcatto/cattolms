declare(strict_types=1);

namespace CattoLearning\Course\Parts;

use InvalidArgumentException;

final class FlashCards
{
    public const MOST = 60;

    private function __construct()
    {
    }

    /**
     * @param mixed $cards The cards, as a list of {front, back, hint}.
     * @return list<array{front:string,back:string,hint?:string}>
     */
    public static function normalise(mixed $cards): array
    {
        $shaped = [];
        foreach (is_array($cards) ? $cards : [] as $card) {
            if (!is_array($card)) { continue; }
            $front = trim(str_replace("\r", '', (string) ($card['front'] ?? '')));
            $back = trim(str_replace("\r", '', (string) ($card['back'] ?? '')));
            $hint = trim(str_replace("\r", '', (string) ($card['hint'] ?? '')));
            if ($front === '' && $back === '' && $hint === '') { continue; }
            $entry = ['front' => $front, 'back' => $back];
            if ($hint !== '') { $entry['hint'] = $hint; }
            $shaped[] = $entry;
        }
        return $shaped;
    }

    /**
     * @return list<array{front:string,back:string,hint?:string}>
     */
    public static function validate(mixed $cards): array
    {
        $cards = self::normalise($cards);
        if ($cards === []) { throw new InvalidArgumentException('Add at least one flash card.'); }
        if (count($cards) > self::MOST) { throw new InvalidArgumentException('A set may have at most ' . self::MOST . ' flash cards.'); }
        foreach ($cards as $index => $card) {
            $where = 'Card ' . ($index + 1);
            if ($card['front'] === '') { throw new InvalidArgumentException($where . ' needs a front: the question.'); }
            if ($card['back'] === '') { throw new InvalidArgumentException($where . ' needs a back: the answer.'); }
            if (mb_strlen($card['front']) > 200) { throw new InvalidArgumentException($where . ': the front may be at most 200 characters.'); }
            if (mb_strlen($card['back']) > 400) { throw new InvalidArgumentException($where . ': the back may be at most 400 characters.'); }
            if (mb_strlen($card['hint'] ?? '') > 150) { throw new InvalidArgumentException($where . ': the hint may be at most 150 characters.'); }
            foreach ($card as $text) {
                if (str_contains($text, '<') || str_contains($text, '>')) { throw new InvalidArgumentException($where . ' is plain text, without < or >.'); }
            }
            if (isset($card['hint']) && mb_strtolower($card['hint']) === mb_strtolower($card['back'])) { throw new InvalidArgumentException($where . ': the hint gives the answer away.'); }
        }
        return $cards;
    }

    /**
     * @param list<array<string,string>> $cards
     * @return list<string>
     */
    public static function warnings(array $cards): array
    {
        return count($cards) >= 10 && count($cards) <= 20 ? [] : ['A module usually has 10 to 20 flash cards. This set has ' . count($cards) . '.'];
    }

    /**
     * About 45 seconds a card.
     *
     * @param list<array<string,string>> $cards
     */
    public static function estimatedMinutes(array $cards): int
    {
        return max(1, (int) ceil(count($cards) * 0.75));
    }

    /**
     * The cards as a list a learner can work through without JavaScript: each front, its answer behind
     * "Show the answer". The script turns the list into one card at a time.
     *
     * @param list<array<string,string>> $cards
     */
    public static function render(array $cards, string $key): string
    {
        $html = '<div class="cl-flashcards" data-cl-flashcards="' . self::e($key) . '"><ol class="cl-flashcards-list">';
        foreach ($cards as $card) {
            $html .= '<li class="cl-flashcard"><p class="cl-flashcard-front">' . self::e($card['front']) . '</p>'
                . (isset($card['hint']) ? '<p class="cl-flashcard-hint"><span>Hint:</span> ' . self::e($card['hint']) . '</p>' : '')
                . '<details class="cl-flashcard-back"><summary>Show the answer</summary><p>' . self::e($card['back']) . '</p></details></li>';
        }
        return $html . '</ol></div>';
    }

    private static function e(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
}
