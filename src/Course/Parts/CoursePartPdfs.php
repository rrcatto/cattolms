declare(strict_types=1);

namespace CattoLearning\Course\Parts;

use CattoLearning\Document\DocumentPdfRenderer;
use RuntimeException;

final class CoursePartPdfs
{
    /** The parts a learner can download as a PDF. */
    public const PRINTABLE = ['lesson', 'summary', 'review', 'flashcards', 'practical'];

    public function __construct(private readonly DocumentPdfRenderer $pdfs, private readonly string $storageRoot)
    {
    }

    /** @param array<string,mixed> $node a structure row */
    public static function printable(array $node): bool
    {
        return (string) ($node['node_type'] ?? '') === 'item' && in_array((string) ($node['part'] ?? ''), self::PRINTABLE, true);
    }

    /**
     * What the part prints: its body for the PDF's page.
     *
     * @param array<string,mixed> $node
     */
    public static function body(array $node, string $rendered): string
    {
        return self::drawingsAsPictures(self::content($node, $rendered));
    }

    /** @param array<string,mixed> $node */
    private static function content(array $node, string $rendered): string
    {
        $config = is_array($node['type_config'] ?? null) ? $node['type_config'] : [];
        return match ((string) ($node['part'] ?? '')) {
            'flashcards' => self::cards(FlashCards::normalise($config['cards'] ?? [])),
            'practical' => '<div class="pdf-practical">' . (string) ($node['content_source'] ?? '') . '</div><h2 class="pdf-answers">Model answers</h2><p class="pdf-answers-note">Try the tasks before you read these.</p>' . (string) ($config['answer_html'] ?? ''),
            default => $rendered,
        };
    }

    /**
     * The PDF engine draws an SVG given as a picture but not one written into the page, whose words it would print as
     * a paragraph. So every drawing in the part becomes a picture of itself, kept within the page's width.
     */
    public static function drawingsAsPictures(string $html): string
    {
        return (string) preg_replace_callback('#<svg\b[^>]*>.*?</svg>#si', static function (array $match): string {
            $svg = $match[0];
            if (!preg_match('#^<svg\b[^>]*\bxmlns=#i', $svg)) { $svg = (string) preg_replace('#^<svg\b#i', '<svg xmlns="http://www.w3.org/2000/svg"', $svg, 1); }
            $label = preg_match('#\baria-label="([^"]*)"#i', $svg, $labelled) === 1 ? $labelled[1] : '';
            return '<img class="pdf-drawing" src="data:image/svg+xml;base64,' . base64_encode($svg) . '" alt="' . $label . '">';
        }, $html);
    }

    /** @param list<array<string,string>> $cards */
    private static function cards(array $cards): string
    {
        $rows = '';
        foreach ($cards as $index => $card) {
            $rows .= '<tr><td class="pdf-card-number">' . ($index + 1) . '</td><td><strong>' . self::e($card['front']) . '</strong>' . (isset($card['hint']) ? '<br><span class="pdf-card-hint">Hint: ' . self::e($card['hint']) . '</span>' : '') . '</td><td>' . self::e($card['back']) . '</td></tr>';
        }
        return '<p>Cover the right-hand column, answer each question in your head, then check.</p><table class="pdf-cards"><thead><tr><th></th><th>Question</th><th>Answer</th></tr></thead><tbody>' . $rows . '</tbody></table>';
    }

    /**
     * The PDF's file, made now or kept from before: the same page is never drawn twice.
     *
     * @param string $html the whole page, for the PDF engine
     */
    public function file(string $html): string
    {
        $directory = $this->storageRoot . '/course-pdfs';
        if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) { throw new RuntimeException('The PDF folder could not be made.'); }
        $path = $directory . '/' . hash('sha256', $html) . '.pdf';
        if (is_file($path) && filesize($path) > 0) { return $path; }
        $previous = (string) ini_get('memory_limit');
        // A long lesson needs room for the PDF engine to lay out every page.
        if ($previous !== '-1' && (int) $previous < 512) { ini_set('memory_limit', '512M'); }
        try {
            $pdf = $this->pdfs->renderPage($html);
        } finally {
            ini_set('memory_limit', $previous);
        }
        $temporary = $path . '.' . bin2hex(random_bytes(4));
        file_put_contents($temporary, $pdf);
        rename($temporary, $path);
        return $path;
    }

    /**
     * What the PDF's page shows about where the part sits, for partials/course-part-pdf.
     *
     * @param array<string,mixed> $course with its structure
     * @param array<string,mixed> $node
     * @return array{course:string,module:string,part:string,title:string,date:string}
     */
    public static function heading(array $course, array $node): array
    {
        $module = '';
        $number = $node['module_of'] ?? null;
        foreach ((array) ($course['structure'] ?? []) as $row) {
            if ($number !== null && ($row['section_number'] ?? null) === $number) { $module = 'Module ' . $number . ': ' . (string) $row['section_title']; break; }
            if ($number === null && (int) $row['id'] === (int) ($node['parent_node_id'] ?? 0) && (string) $row['node_type'] === 'section') { $module = (string) $row['section_title']; break; }
        }
        $part = \CattoLearning\Course\CourseItemService::PART_LABELS[(string) ($node['part'] ?? '')] ?? (string) ($node['part'] ?? '');
        return [
            'course' => (string) $course['title'],
            'module' => $module,
            'part' => $part === 'Review' || (string) ($node['part'] ?? '') === 'review' ? 'Review' : $part,
            'title' => (string) (($node['display_title_override'] ?? '') ?: $node['item_title'] ?? ''),
            'date' => date('j F Y'),
        ];
    }

    /** A name for the saved file, such as "Module-3-Evidence-Lesson.pdf". */
    public static function filename(string ...$parts): string
    {
        $name = trim((string) preg_replace('/[^A-Za-z0-9]+/', '-', implode(' ', array_filter($parts, static fn(string $part): bool => $part !== ''))), '-');
        return ($name === '' ? 'Course' : mb_substr($name, 0, 120)) . '.pdf';
    }

    private static function e(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
}
