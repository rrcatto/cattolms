    public static function parse(string $html): HTMLDocument
    {
        $previous = libxml_use_internal_errors(true);
        try {
            // In the HTML namespace: without it a script's or a stylesheet's text is escaped when written out, which breaks both.
            return HTMLDocument::createFromString($html, 0, 'UTF-8');
        } finally {
            libxml_clear_errors();
            libxml_use_internal_errors($previous);
        }
    }

    /** Text with its markup, entities, case and spacing taken out, to compare two copies of the same words. */
    public static function words(string $html): string
    {
        $html = (string) preg_replace('/<(svg|style|script)\b.*?<\/\1>/si', ' ', $html);
        $text = html_entity_decode(strip_tags($html), ENT_QUOTES | ENT_HTML5, 'UTF-8');
        return mb_strtolower(trim((string) preg_replace('/[\s\x{00A0}]+/u', ' ', $text)));
    }

    /** Every panel of the original build as a <details>, its button as the <summary>, each keeping its classes. */
    public static function panelsToDetails(HTMLDocument $document): void
    {
        foreach ($document->querySelectorAll('.acc-item') as $item) {
            if (strtolower($item->tagName) === 'details') { continue; }
            $details = $document->createElement('details');
            foreach ($item->attributes as $attribute) { $details->setAttribute($attribute->name, $attribute->value); }
            $details->classList->remove('open');
            while ($item->firstChild !== null) {
                $child = $item->firstChild;
                if ($child instanceof Element && strtolower($child->tagName) === 'button' && $child->classList->contains('acc-trigger')) {
                    $summary = $document->createElement('summary');
                    foreach ($child->attributes as $attribute) {
                        if (!in_array($attribute->name, ['type', 'aria-expanded', 'aria-controls'], true)) { $summary->setAttribute($attribute->name, $attribute->value); }
                    }
                    while ($child->firstChild !== null) { $summary->appendChild($child->firstChild); }
                    $child->remove();
                    $details->appendChild($summary);
                    continue;
                }
                $details->appendChild($child);
            }
            $item->replaceWith($details);
        }
    }

    /** A stylesheet's `.open` rules as `[open]`, the state a <details> carries. Only in selectors, never in a rule's body. */
    public static function openRules(string $css): string
    {
        return (string) preg_replace('/\.open\b(?=[^{}]*\{)/', '[open]', $css);
    }

    /**
     * A script's named constant cut out, a placeholder in its place.
     *
     * @return array{0:string,1:string|null} the code, and the constant's value as written
     */
    private static function cutConstant(string $code, string $name): array
    {
        if (preg_match('/\b(const|let|var)\s+' . $name . '\s*=\s*/', $code, $match, PREG_OFFSET_CAPTURE) !== 1) { return [$code, null]; }
        $start = $match[0][1] + strlen($match[0][0]);
        $end = self::valueEnd($code, $start);
        if ($end === null) { return [$code, null]; }
        $value = substr($code, $start, $end - $start);
        $after = $end;
        while ($after < strlen($code) && ctype_space($code[$after])) { $after++; }
        if (($code[$after] ?? '') === ';') { $end = $after + 1; }
        return [substr($code, 0, $match[0][1]) . '/*cl:' . $name . ':' . $match[1][0] . '*/' . substr($code, $end), $value];
    }

    /** Where a JSON-like value that opens at $start ends, past any strings holding brackets. */
    private static function valueEnd(string $code, int $start): ?int
    {
        $depth = 0;
        $quote = '';
        for ($i = $start, $length = strlen($code); $i < $length; $i++) {
            $char = $code[$i];
            if ($quote !== '') {
                if ($char === '\\') { $i++; } elseif ($char === $quote) { $quote = ''; }
                continue;
            }
            if ($char === '"' || $char === "'" || $char === '`') { $quote = $char; continue; }
            if ($char === '{' || $char === '[') { $depth++; continue; }
            if ($char === '}' || $char === ']') {
                $depth--;
                if ($depth === 0) { return $i + 1; }
            }
        }
        return null;
    }

    /**
     * Fields a question has in the file that the site does not hold, such as a domain chip, kept by the question's words.
     *
     * @param array<int|string,mixed> $quiz
     * @return array<string,array<string,mixed>>
     */
    private static function questionExtras(array $quiz): array
    {
        $extras = [];
        foreach ($quiz as $questions) {
            foreach ((array) $questions as $question) {
                if (!is_array($question) || !isset($question['q'])) { continue; }
                $extra = array_diff_key($question, array_flip(['q', 'o', 'a', 'e', 'p', 'u']));
                if ($extra !== []) { $extras[md5(self::words((string) $question['q']))] = $extra; }
            }
        }
        return $extras;
    }

    /** What stands between the masthead and the modules, cut out, a placeholder in its place. */
    private static function cutIntroduction(HTMLDocument $document): void
    {
        $masthead = $document->querySelector('.masthead');
        $modules = $document->querySelector('.modules');
        if (!$masthead instanceof Element || !$modules instanceof Element || $masthead->parentNode !== $modules->parentNode) { return; }
        $marked = false;
        for ($node = $masthead->nextSibling; $node !== null && $node !== $modules; $node = $next) {
            $next = $node->nextSibling;
            if ($node instanceof Element && self::importedElsewhere($node)) { continue; }
            if (!$node instanceof Element && trim((string) $node->textContent) === '') { continue; }
            if (!$node instanceof Element && !$node instanceof \Dom\Text) { continue; }
            if (!$marked) {
                $node->parentNode?->insertBefore($document->createComment('cl:introduction'), $node);
                $marked = true;
            }
            $node->remove();
        }
        if (!$marked) { $modules->parentNode?->insertBefore($document->createComment('cl:introduction'), $modules); }
    }

    private static function importedElsewhere(Element $node): bool
    {
        foreach (['module', 'review', 'final', 'diag'] as $name) { if ($node->classList->contains($name)) { return true; } }
        $id = (string) $node->getAttribute('id');
        return in_array($id, ['diagnostic', 'final', 'mod-review'], true) || str_starts_with($id, 'mod-');
    }

    /** A module without the content the site holds: its lesson and video go, and its panels stay, their words and icons kept. */
    /** A node and the blank line before it, so that a file captured again comes out the same. */
    private static function removeWithItsSpace(Element $node): void
    {
        $space = $node->previousSibling;
        if ($space instanceof \Dom\Text && trim((string) $space->textContent) === '') { $space->remove(); }
        $node->remove();
    }

    /** A block the site holds as a part of the module, wherever in the module the original put it. */
    private static function isPart(Element $node): bool
    {
        if (!$node->classList->contains('block')) { return false; }
        foreach (self::BLOCK_KINDS as $kind) {
            if ($node->classList->contains($kind)) { return true; }
        }
        return false;
    }

    private static function emptyModule(Element $module): void
    {
        $body = $module->querySelector('.module-body');
        if (!$body instanceof Element) { return; }
        foreach (iterator_to_array($body->childNodes) as $child) {
            if ($child instanceof Element && ($child->classList->contains('subs') || $child->classList->contains('blocks') || $child->classList->contains('outcomes') || self::isPart($child))) { continue; }
            $child->parentNode?->removeChild($child);
        }
        foreach ($body->querySelectorAll('.s-summary .sub-inner') as $inner) { $inner->innerHTML = ''; }
        // A block among the panels (`.subs`), such as some courses' answer key, is the frame's. In `.blocks`, only the kinds
        // the site holds as parts are: any other stays in the lesson, which is where the site keeps it.
        foreach ($body->querySelectorAll('.blocks > .block, .module-body > .block') as $block) {
            if (!self::isPart($block)) { $block->remove(); continue; }
            $inner = $block->querySelector('.block-inner');
            if ($inner instanceof Element) { $inner->innerHTML = ''; }
        }
        foreach ($body->querySelectorAll('.blocks') as $blocks) {
            if ($blocks->querySelector('.block') === null) { $blocks->remove(); }
        }
    }
