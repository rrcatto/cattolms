            'status' => 'answered',
            'is_correct' => $correct,
            'points_awarded' => $points,
            'correct_option_html' => (string) ($correctOption['option_html'] ?? ''),
            'explanation_html' => (string) ($row['explanation_html'] ?? ''),
        ];
    }

