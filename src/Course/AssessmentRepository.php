    /** @return array<string,mixed> */
    public function calculateSession(int $sessionId): array
    {
        $rows = $this->db->exec(
            "SELECT COALESCE(SUM(points_awarded),0)::numeric AS earned,
                    COALESCE(SUM(q.points),0)::numeric AS maximum,
                    COUNT(*) FILTER (WHERE sq.response_status='answered')::int AS answered,
                    COUNT(*) FILTER (WHERE sq.response_status='answered' AND sq.is_correct=TRUE)::int AS correct,
                    COUNT(*) FILTER (WHERE sq.response_status='answered' AND sq.is_correct=FALSE)::int AS incorrect,
                    COUNT(*) FILTER (WHERE sq.response_status='skipped')::int AS skipped,
                    COUNT(*) FILTER (WHERE sq.response_status='timed_out')::int AS timed_out,
                    COUNT(*) FILTER (WHERE sq.response_status='unanswered')::int AS unanswered
             FROM assessment_session_questions sq
             JOIN assessment_questions q ON q.id=sq.question_id
             WHERE sq.session_id=:session_id",
            [':session_id' => $sessionId]
        );
        $row = $rows[0] ?? [];
        $earned = max(0.0, (float) ($row['earned'] ?? 0));
        $maximum = max(1.0, (float) ($row['maximum'] ?? 0));
        return [
            'earned_points' => $earned,
            'maximum_points' => $maximum,
            'percentage' => round($earned / $maximum * 100, 2),
            'answered' => (int) ($row['answered'] ?? 0),
            'correct' => (int) ($row['correct'] ?? 0),
            'incorrect' => (int) ($row['incorrect'] ?? 0),
            'skipped' => (int) ($row['skipped'] ?? 0),
            'timed_out' => (int) ($row['timed_out'] ?? 0),
            'unanswered' => (int) ($row['unanswered'] ?? 0),
        ];
    }

