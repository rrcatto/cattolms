declare(strict_types=1);

namespace CattoLearning\Course;

use DateTimeImmutable;
use DateTimeZone;

final class CourseTiming
{
    private const BOUGHT = ['paid_order', 'bundle'];

    private function __construct()
    {
    }

    /**
     * The timing lines for one enrolment: started_at (the learner pressed Start course), access_started_at
     * (when its access began, by payment or by the learner), expires_at, status and source_type.
     *
     * @param array<string,mixed> $enrolment
     * @return array{state:string,lines:list<string>}
     */
    public static function of(array $enrolment, DateTimeImmutable $now): array
    {
        $zone = new DateTimeZone(date_default_timezone_get());
        $now = $now->setTimezone($zone);
        $status = (string) ($enrolment['status'] ?? '');
        $expires = self::at($enrolment['expires_at'] ?? null, $zone);
        $started = self::at($enrolment['access_started_at'] ?? null, $zone) ?? self::at($enrolment['started_at'] ?? null, $zone);
        $bought = in_array((string) ($enrolment['source_type'] ?? ''), self::BOUGHT, true);

        if ($status === 'expired' || ($expires !== null && $expires <= $now && $status !== 'completed')) {
            return ['state' => 'expired', 'lines' => ['Access ended ' . ($expires !== null ? self::date($expires) : 'earlier') . '.']];
        }
        if ($started === null) {
            return ['state' => 'not_started', 'lines' => [$bought
                ? 'Starts as soon as your payment is confirmed.'
                : 'Assigned to you. Your access period starts when you press Start course.']];
        }
        $lines = [];
        $since = self::days($started, $now);
        $lines[] = ($bought ? 'Started on payment, ' : 'Started ') . self::dateTime($started) . ', ' . self::ago($since) . '.';
        if ($expires !== null) {
            $left = self::days($now, $expires);
            $lines[] = 'Access ends ' . self::date($expires) . ', ' . ($left === 0 ? 'today' : 'in ' . $left . ' day' . ($left === 1 ? '' : 's')) . '.';
        }
        if ($status === 'completed') $lines[] = 'Completed.';

        return ['state' => $status === 'completed' ? 'completed' : 'started', 'lines' => $lines];
    }

    private static function at(mixed $value, DateTimeZone $zone): ?DateTimeImmutable
    {
        return is_string($value) && $value !== '' ? (new DateTimeImmutable($value))->setTimezone($zone) : null;
    }

    /** Whole calendar days from $from to $to (0 on the same day). */
    private static function days(DateTimeImmutable $from, DateTimeImmutable $to): int
    {
        return max(0, (int) $from->setTime(0, 0)->diff($to->setTime(0, 0))->format('%r%a'));
    }

    private static function ago(int $days): string
    {
        return $days === 0 ? 'today' : $days . ' day' . ($days === 1 ? '' : 's') . ' ago';
    }

    private static function date(DateTimeImmutable $at): string
    {
        return $at->format('j F Y');
    }

    private static function dateTime(DateTimeImmutable $at): string
    {
        return $at->format('j F Y H:i');
    }
}
