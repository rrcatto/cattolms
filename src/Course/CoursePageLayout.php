    /**
     * A layout made whole: every block once in the order given, each width half or full, Course access shown, an
     * unknown block dropped and a missing one put where the default template has it.
     *
     * @param mixed $layout
     * @return list<array{id:string,width:string,shown:bool}>
     */
    public static function normalise(mixed $layout): array
    {
        $result = [];
        foreach (is_array($layout) ? $layout : [] as $block) {
            $id = is_array($block) ? (string) ($block['id'] ?? '') : '';
            if (!isset(self::BLOCKS[$id]) || isset($result[$id])) { continue; }
            $width = (string) ($block['width'] ?? '');
            $result[$id] = ['id' => $id, 'width' => in_array($width, self::WIDTHS, true) ? $width : 'full', 'shown' => in_array($id, self::ALWAYS_SHOWN, true) || !empty($block['shown'])];
        }
        $default = self::starting();
        foreach ($default as $index => $block) {
            if (isset($result[$block['id']])) { continue; }
            // A block the layout lacks goes after the block that comes before it in the default.
            $ids = array_keys($result);
            $after = $index > 0 ? array_search($default[$index - 1]['id'], $ids, true) : false;
            $position = $after === false ? ($index === 0 ? 0 : count($ids)) : $after + 1;
            $result = array_slice($result, 0, $position, true) + [$block['id'] => $block] + array_slice($result, $position, null, true);
        }
        return array_values($result);
    }

    /**
     * A layout from the builder's form: the order of the blocks, each one's width and the blocks ticked as shown.
     *
     * @param array<string,mixed> $input
     * @return list<array{id:string,width:string,shown:bool}>
     */
    public static function fromInput(array $input): array
    {
        $order = array_values(array_filter(array_map('trim', explode(',', (string) ($input['order'] ?? '')))));
        $widths = is_array($input['width'] ?? null) ? $input['width'] : [];
        $shown = is_array($input['shown'] ?? null) ? $input['shown'] : [];
