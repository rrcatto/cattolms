            'reviews' => $facts['reviews'] > 0, 'access' => true, 'start' => $facts['preview'] && empty($facts['owned']),
            'related' => $facts['related'] > 0,
        ]));
    }

    /**
     * The blocks a layout shows that this course's page leaves out, each with its name and why, in the layout's order.
     *
     * @param list<array{id:string,width:string,shown:bool}> $layout
     * @param array{modules:int,figures:int,reviews:int,preview:bool,related:int,owned?:bool} $facts
     * @return list<array{id:string,name:string,reason:string}>
     */
    public static function leftOut(array $layout, array $facts): array
    {
        $present = self::present($facts);
        $out = [];
        foreach ($layout as $block) {
            if (!$block['shown'] || in_array($block['id'], $present, true)) { continue; }
            $out[] = ['id' => $block['id'], 'name' => self::BLOCKS[$block['id']]['name'], 'reason' => self::LEFT_OUT[$block['id']] ?? 'nothing to show'];
        }
        return $out;
    }
