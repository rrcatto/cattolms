    }

    /**
     * One block moved a place up or down among the shown blocks (the builder's arrows without JavaScript).
     *
     * @param list<array{id:string,width:string,shown:bool}> $layout
     * @return list<array{id:string,width:string,shown:bool}>
     */
    public static function move(array $layout, string $id, string $direction): array
    {
        $at = array_search($id, array_column($layout, 'id'), true);
        if ($at === false) { return $layout; }
        $step = $direction === 'up' ? -1 : 1;
        for ($to = $at + $step; $to >= 0 && $to < count($layout); $to += $step) {
            if ($layout[$to]['shown']) {
                $block = array_splice($layout, $at, 1);
                array_splice($layout, $to, 0, $block);
                break;
            }
        }
        return $layout;
    }

    /**
     * The shown blocks that have something to show, in rows: a full block alone, two half blocks side by side, a half
     * block with no half beside it alone in half a row.
     *
     * @param list<array{id:string,width:string,shown:bool}> $layout
