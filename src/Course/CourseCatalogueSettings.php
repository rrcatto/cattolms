Description:
A course's place in the catalogue, carried in its course package (owner, 2026-10-23: a course's catalogue settings go
inside each course's JSON, so a course exported from its page and imported on another site comes with its cover and
tags). The "catalogue" block of a catto-learning-course 2.1 package holds:

  {"category": "Design › Gardens", "tags": ["Planting"], "cover": "<svg …>", "position": 100,
   "related": ["GDN-102"], "status": "published",
   "prices": [{"period": 6, "unit": "months", "price": "950.00", "was_price": "1250.00", "currency": "ZAR",
               "label": "Six months", "active": true, "default": true}]}

The category is the path of names joined by " › "; related courses are named by their codes. export() reads it from
the site; changes() says, in words, what apply() would change on a course; apply() makes those changes through
CourseService and the course repository, as ADMIN does on the course's pages:

  the category only when the course has none (a category chosen on the site is kept);
  its tags, made exactly the block's (a tag the site lacks is made, with the icon that fits its name);
  its cover and its catalogue position;
  its prices only for a course the import has just created, and only when asked (owner, 2026-10-23: "use the file's
  prices for new courses only"), never for a course already on the site.

relate() adds the block's related courses that are on the site; a relation is both courses', so it only adds. The
status is the package's business: a catalogue import publishes new courses that were published where they came from.

Changelog:
2026/10/23 SAST
- Created with the catalogue package.
*/

declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Support\AccessPeriod;
use CattoLearning\Support\Money;
use CattoLearning\Support\Slug;
use CattoLearning\View\Artwork\UploadedSvg;
use InvalidArgumentException;

final class CourseCatalogueSettings
{
    public const SEPARATOR = ' › ';

    public function __construct(
        private readonly CourseService $courses,
        private readonly CourseRepository $repository,
    ) {}

    /**
     * The catalogue block of a course's package: what the site holds of its place in the catalogue.
     *
     * @return array<string,mixed>
     */
    public function export(int $courseId): array
    {
        $course = $this->repository->findById($courseId) ?? throw new InvalidArgumentException('The course does not exist.');
        $paths = $this->categoryPaths();
        $related = [];
        foreach ($this->repository->relatedCourseIds($courseId) as $otherId) {
            $code = (string) ($this->repository->findById($otherId)['code'] ?? '');
            if ($code !== '') $related[] = $code;
        }
        $prices = [];
        foreach ($this->repository->priceVariants($courseId) as $variant) {
            [$period, $unit] = AccessPeriod::decompose((int) $variant['access_period_seconds']);
            $currency = (string) $variant['currency_code'];
            $prices[] = [
                'period' => $period,
                'unit' => $unit,
                'price' => Money::strictMinorUnits((int) $variant['price_minor_units'], $currency)->toMajorUnits(),
                'was_price' => $variant['was_price_minor_units'] === null ? null : Money::strictMinorUnits((int) $variant['was_price_minor_units'], $currency)->toMajorUnits(),
                'currency' => $currency,
                'label' => (string) ($variant['label'] ?? ''),
                'active' => (bool) $variant['is_active'],
                'default' => (bool) $variant['is_default'],
            ];
        }
        return [
            'category' => $course['category_id'] === null ? '' : ($paths[(int) $course['category_id']] ?? ''),
            'tags' => $this->tagNames($courseId),
            'cover' => (string) ($course['cover_svg'] ?? ''),
            'position' => $course['catalogue_position'] === null ? null : (int) $course['catalogue_position'],
            'related' => $related,
            'status' => (string) $course['status'],
            'prices' => $prices,
        ];
    }

    /**
     * Every category's path of names, by id: "Design › Gardens".
     *
     * @return array<int,string>
     */
    public function categoryPaths(): array
    {
        $paths = [];
        foreach ($this->repository->catalogueCategories() as $row) {
            $parent = $row['parent_id'] === null ? null : (int) $row['parent_id'];
            $paths[(int) $row['id']] = ($parent !== null && isset($paths[$parent]) ? $paths[$parent] . self::SEPARATOR : '') . (string) $row['name'];
        }
        return $paths;
    }

    /** The category at this path of names, or null when the site has none there. */
    public function categoryIdByPath(string $path): ?int
    {
        $path = trim($path);
        if ($path === '') return null;
        $found = array_search($path, $this->categoryPaths(), true);
        return $found === false ? null : (int) $found;
    }

    /**
     * What apply() would change on this course, each in a few words for the import review; empty when nothing would.
     *
     * @param array<string,mixed> $course a course row
     * @param array<string,mixed> $block
     * @return list<string>
     */
    public function changes(array $course, array $block, bool $prices): array
    {
        $changes = [];
        $courseId = (int) $course['id'];
        $category = (string) ($block['category'] ?? '');
        if ($category !== '' && $course['category_id'] === null) {
            $changes[] = $this->categoryIdByPath($category) === null ? 'Category: ' . $category . ' (made by this import)' : 'Category: ' . $category;
        }
        $tags = self::names($block['tags'] ?? []);
        if (array_key_exists('tags', $block) && $tags !== $this->tagNames($courseId)) {
            $changes[] = 'Tags: ' . ($tags === [] ? 'none' : implode(', ', $tags));
        }
        $cover = self::cover($block['cover'] ?? '', (string) $course['slug']);
        if ($cover !== null && $cover !== (string) ($course['cover_svg'] ?? '')) $changes[] = 'Cover picture';
        if (array_key_exists('position', $block)) {
            $position = CourseService::cataloguePosition($block['position']);
            $current = $course['catalogue_position'] === null ? null : (int) $course['catalogue_position'];
            if ($position !== $current) $changes[] = 'Position in the catalogue: ' . ($position ?? 'none');
        }
        $missing = array_diff($this->relatedIds($block), $this->repository->relatedCourseIds($courseId));
        if ($missing !== []) $changes[] = 'Related courses: ' . count($missing) . ' added';
        if ($prices && $this->repository->priceVariants($courseId) === [] && (array) ($block['prices'] ?? []) !== []) {
            $changes[] = 'Prices: ' . implode(', ', array_map(static fn(array $price): string => self::priceWords($price), self::prices($block)));
        }
        return $changes;
    }

    /**
     * Puts the block's settings on the course (the related courses are relate()'s), saying what changed.
     *
     * @param array<string,mixed> $block
     * @return list<string>
     */
    public function apply(int $courseId, array $block, int $actor, bool $prices): array
    {
        $course = $this->repository->findById($courseId) ?? throw new InvalidArgumentException('The course does not exist.');
        $done = [];
        $category = $this->categoryIdByPath((string) ($block['category'] ?? ''));
        if ($category !== null && $this->repository->categoriseIfUncategorised($courseId, $category)) $done[] = 'Category: ' . $block['category'];
        if (array_key_exists('tags', $block)) {
            $tags = self::names($block['tags']);
            if ($tags !== $this->tagNames($courseId)) {
                foreach ($tags as $name) {
                    if ($this->repository->tagBySlug(Slug::from($name)) === null) $this->courses->createTag(['name' => $name], $actor);
                }
                $this->courses->setCourseTagsByName($courseId, $tags, $actor);
                $done[] = 'Tags: ' . ($tags === [] ? 'none' : implode(', ', $tags));
            }
        }
        $cover = self::cover($block['cover'] ?? '', (string) $course['slug']);
        if ($cover !== null && $cover !== (string) ($course['cover_svg'] ?? '')) {
            $this->courses->setCourseCover($courseId, $cover, $actor);
            $done[] = 'Cover picture';
        }
        if (array_key_exists('position', $block)) {
            $position = CourseService::cataloguePosition($block['position']);
            $current = $course['catalogue_position'] === null ? null : (int) $course['catalogue_position'];
            if ($position !== $current) {
                $this->repository->setCataloguePosition($courseId, $position);
                $done[] = 'Position in the catalogue: ' . ($position ?? 'none');
            }
        }
        if ($prices && $this->repository->priceVariants($courseId) === []) {
            foreach (self::prices($block) as $price) {
                $this->courses->createPriceVariant($courseId, [
                    'access_period_value' => (string) $price['period'], 'access_period_unit' => $price['unit'],
                    'price' => $price['price'], 'was_price' => (string) ($price['was_price'] ?? ''), 'currency_code' => $price['currency'],
                    'label' => $price['label'], 'is_active' => $price['active'] ? '1' : '', 'is_default' => $price['default'] ? '1' : '',
                ], $actor);
                $done[] = 'Price: ' . self::priceWords($price);
            }
        }
        return $done;
    }

    /**
     * Adds the block's related courses that are on the site; a relation is both courses', so it never takes one away.
     *
     * @param array<string,mixed> $block
     * @return int how many were added
     */
    public function relate(int $courseId, array $block): int
    {
        $current = $this->repository->relatedCourseIds($courseId);
        $added = array_values(array_diff($this->relatedIds($block), $current, [$courseId]));
        if ($added === []) return 0;
        $slugs = array_map(fn(int $id): string => (string) ($this->repository->findById($id)['slug'] ?? ''), array_merge($current, $added));
        $this->courses->setRelatedCoursesBySlug($courseId, $slugs);
        return count($added);
    }

    /**
     * The tag names a course carries, in order.
     *
     * @return list<string>
     */
    public function tagNames(int $courseId): array
    {
        $carried = $this->repository->courseTagIds($courseId);
        $names = [];
        foreach ($this->repository->tagOptions() as $tag) {
            if (in_array((int) $tag['id'], $carried, true)) $names[] = (string) $tag['name'];
        }
        sort($names, SORT_NATURAL | SORT_FLAG_CASE);
        return $names;
    }

    /**
     * @param array<string,mixed> $block
     * @return list<int>
     */
    private function relatedIds(array $block): array
    {
        $ids = [];
        foreach ((array) ($block['related'] ?? []) as $code) {
            if (!is_string($code) || !CourseCode::isValid($code)) continue;
            $other = $this->repository->findByCode($code);
            if ($other !== null) $ids[] = (int) $other['id'];
        }
        return array_values(array_unique($ids));
    }

    /** @return list<string> */
    private static function names(mixed $names): array
    {
        $list = array_values(array_unique(array_filter(array_map(static fn(mixed $name): string => trim((string) $name), (array) $names), static fn(string $name): bool => $name !== '')));
        sort($list, SORT_NATURAL | SORT_FLAG_CASE);
        return $list;
    }

    private static function cover(mixed $svg, string $slug): ?string
    {
        return is_string($svg) && trim($svg) !== '' ? UploadedSvg::validate($svg, UploadedSvg::COVER_BYTES, 'cover of "' . $slug . '"') : null;
    }

    /**
     * The block's prices, each checked for its shape (the price form checks the amounts).
     *
     * @param array<string,mixed> $block
     * @return list<array{period:int,unit:string,price:string,was_price:?string,currency:string,label:string,active:bool,default:bool}>
     */
    private static function prices(array $block): array
    {
        $prices = [];
        foreach ((array) ($block['prices'] ?? []) as $price) {
            if (!is_array($price)) continue;
            $unit = (string) ($price['unit'] ?? 'months');
            if (!in_array($unit, ['days', 'weeks', 'months', 'years'], true)) throw new InvalidArgumentException('A price\'s period is in days, weeks, months or years, not "' . $unit . '".');
            $was = $price['was_price'] ?? null;
            $prices[] = [
                'period' => max(1, (int) ($price['period'] ?? 12)),
                'unit' => $unit,
                'price' => (string) ($price['price'] ?? ''),
                'was_price' => $was === null || $was === '' ? null : (string) $was,
                'currency' => strtoupper((string) ($price['currency'] ?? 'ZAR')),
                'label' => (string) ($price['label'] ?? ''),
                'active' => (bool) ($price['active'] ?? true),
                'default' => (bool) ($price['default'] ?? false),
            ];
        }
        return $prices;
    }

    /**
     * "R 1 200,00 (was R 1 800,00) for 1 year".
     *
     * @param array{period:int,unit:string,price:string,was_price:?string,currency:string} $price
     */
    private static function priceWords(array $price): string
    {
        $money = static function (string $amount) use ($price): string {
            try {
                return Money::ofMajorUnits($amount, $price['currency'])->format();
            } catch (\Throwable) {
                return $price['currency'] . ' ' . $amount;
            }
        };
        $seconds = AccessPeriod::fromInput($price['period'], $price['unit']);
        return $money($price['price']) . ($price['was_price'] !== null ? ' (was ' . $money($price['was_price']) . ')' : '') . ' for ' . AccessPeriod::label($seconds);
    }
}
