What a reader has narrowed the course catalogue to: a category branch, a tag, a keyword, or any
combination of them.

Architectural boundary: a pure value object. It holds no SQL and no HTTP knowledge. The repository
turns it into one predicate; the controller builds it from the request.

Why it exists rather than three more parameters.

The count and the rows are two separate statements that must describe the same population - a
faceted count that disagrees with its own list is indistinguishable from missing data - and the way
that guarantee gets lost is a filter being added to one call site and not the other. One object
passed to both cannot be half-applied. It is also the shape faceted search needs: another facet is a
property here, not a fourth positional argument on four methods.

