declare(strict_types=1);

namespace CattoLearning\Course;

final class CatalogueFilter
{
    /** @var list<int> */
    public readonly array $tagIds;

    /**
     * @param list<int> $tagIds Any of these tags, not all of them - see the note on OR below.
     */
    public function __construct(
        /** A category branch: the category itself, its children and its grandchildren. */
        public readonly ?int $categoryId = null,
        array $tagIds = [],
        public readonly string $search = ''
    ) {
        // De-duplicated and re-indexed so two routes to the same tag cannot widen the IN list, and
        // sorted so two filters naming the same tags compare equal.
        $unique = array_values(array_unique(array_map('intval', $tagIds)));
        sort($unique);
        $this->tagIds = $unique;
    }

    /** The whole published catalogue, narrowed by nothing. */
    public static function none(): self
    {
        return new self();
    }

    /** One tag, which is what a /courses/tag/<slug> page is. */
    public static function forTag(int $tagId): self
    {
        return new self(null, [$tagId]);
    }

    public function isFiltered(): bool
    {
        return $this->categoryId !== null || $this->tagIds !== [] || $this->search !== '';
    }

    public function hasTag(int $tagId): bool
    {
        return in_array($tagId, $this->tagIds, true);
    }

    /**
     * The same filter with this tag added, or removed if it was already there.
     *
     * Selecting several tags means *any* of them, not all. Two reasons, and they point the same
     * way: intersecting tags collapses to nothing almost immediately, because a course carries
     * three tags out of a hundred; and a facet whose options can only ever narrow gives the reader
     * no way back except starting again. OR within a facet, AND across facets, is the convention
     * for exactly that reason.
     */
    public function toggleTag(int $tagId): self
    {
        $tags = $this->hasTag($tagId)
            ? array_values(array_filter($this->tagIds, static fn(int $id): bool => $id !== $tagId))
            : [...$this->tagIds, $tagId];

        return new self($this->categoryId, $tags, $this->search);
    }

    /** The same filter with one facet relaxed, which is how that facet's own counts are taken. */
    public function withoutTags(): self
    {
        return new self($this->categoryId, [], $this->search);
    }

    public function withoutCategory(): self
    {
        return new self(null, $this->tagIds, $this->search);
    }

    public function withCategory(?int $categoryId): self
    {
        return new self($categoryId, $this->tagIds, $this->search);
    }

    public function withSearch(string $search): self
    {
        return new self($this->categoryId, $this->tagIds, trim($search));
    }
}
