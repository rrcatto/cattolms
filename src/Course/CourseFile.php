    /**
     * A section's introduction as the import made it, back into the module's subtitle and outcomes: "<p>subtitle</p>"
     * and "<p>In this module you will learn to:</p><ol class="cl-section-outcomes">...</ol>". Anything else is named.
     *
     * @param list<string> $leftOut
     * @return array{0:string,1:list<string>}
     */
    private static function heading(string $introduction, string $title, array &$leftOut): array
    {
        $html = trim($introduction);
        $outcomes = [];
        if (preg_match('#<p>In this module you will learn to:</p>\s*<ol class="cl-section-outcomes">(.*?)</ol>\s*$#s', $html, $match) === 1) {
            preg_match_all('#<li>(.*?)</li>#s', $match[1], $items);
            $outcomes = array_map('trim', $items[1]);
            $html = trim(substr($html, 0, -strlen($match[0])));
        }
        $subtitle = '';
        if (preg_match('#^<p>(.*?)</p>$#s', $html, $paragraph) === 1 && !str_contains($paragraph[1], '<p')) {
            $subtitle = trim($paragraph[1]);
        } elseif ($html !== '') {
            $leftOut[] = $title . ': its introduction is more than a subtitle and outcomes; only its text is kept, as the subtitle.';
            $subtitle = htmlspecialchars(trim((string) preg_replace('/\s+/u', ' ', html_entity_decode(strip_tags($html), ENT_QUOTES | ENT_HTML5, 'UTF-8'))), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
        }
        return [$subtitle, $outcomes];
    }

    /**
     * The introduction with its grading scale written out where the site shows the course's own bands.
     *
     * @param list<array<string,mixed>> $bands
     * @param list<string> $leftOut
     */
    private static function withScale(string $introduction, array $bands, array &$leftOut): string
    {
        usort($bands, static fn(array $a, array $b): int => (float) $b['minimum_percentage'] <=> (float) $a['minimum_percentage']);
        $top = 100.0;
        $list = '<ul class="scale-list">';
        foreach ($bands as $band) {
            $low = (float) $band['minimum_percentage'];
            $label = (string) $band['grade_label'];
            $code = (string) ($band['grade_code'] ?? '');
            if ($code !== '' && $code !== $label && !str_ends_with($label, '(' . $code . ')')) { $label .= ' (' . $code . ')'; }
            $list .= '<li><span>' . self::e($label) . '</span><b>' . self::number($low) . '-' . self::number($top) . '%</b></li>';
            $top = $low - 1;
        }
        $list .= '</ul>';
        // The introduction as it is stored (everything the file had before its modules), the scale written where the site
        // shows it: a list never inside a paragraph, so a placeholder alone in one takes the paragraph's place.
        if (str_contains($introduction, GradeScale::PLACEHOLDER)) {
            $introduction = (string) preg_replace('#<p>\s*' . preg_quote(GradeScale::PLACEHOLDER, '#') . '\s*</p>#', $list, $introduction, 1);
            return trim(str_replace(GradeScale::PLACEHOLDER, $list, $introduction));
        }
        $standard = [['First Class (A)', 75.0], ['Second Class (B+)', 70.0], ['Second Class (B)', 60.0], ['Third (C)', 50.0], ['Fail', 0.0]];
        if (array_map(static fn(array $band): array => [(string) $band['grade_label'], (float) $band['minimum_percentage']], $bands) === $standard) {
            $leftOut[] = 'The introduction shows no grading scale, so an import uses the standard five bands, which are this course\'s.';
            return trim($introduction);
        }
        $leftOut[] = 'The introduction showed no grading scale, so the course\'s own scale is written at its end.';
        return trim($introduction) . "\n" . $list;
    }

    /**
     * A review study aid's points drawn from REVIEW back into REVIEW, and what is left as the review's own text.
     *
     * @return array{0:string,1:array<string,array{t:string,pts:list<string>}>}
     */
    private static function reviewPoints(string $html): array
    {
        $previous = libxml_use_internal_errors(true);
        try {
            $document = \Dom\HTMLDocument::createFromString('<!doctype html><html><body><div id="cl-review-root">' . $html . '</div></body></html>', \Dom\HTML_NO_DEFAULT_NS, 'UTF-8');
        } finally {
            libxml_clear_errors();
            libxml_use_internal_errors($previous);
        }
        $root = $document->getElementById('cl-review-root');
        $grid = $root?->lastElementChild;
        // Only the box the import made from REVIEW, the last thing in the review: a grid of cards each an <h3> and a
        // list. A course's own cards, under any class, stay in its text.
        if ($root === null || $grid === null || strtolower($grid->tagName) !== 'div' || $grid->getAttribute('class') !== 'review-grid') { return [$html, []]; }
        $points = [];
        foreach ($grid->children as $index => $card) {
            $heading = $card->firstElementChild;
            $list = $heading?->nextElementSibling;
            if ($card->getAttribute('class') !== 'review-card' || $heading === null || strtolower($heading->tagName) !== 'h3' || $list === null || strtolower($list->tagName) !== 'ul') { return [$html, []]; }
            $items = [];
            foreach ($list->children as $item) { $items[] = trim(CourseHtml::innerHtml($item)); }
            $points['m' . ($index + 1)] = ['t' => trim((string) $heading->textContent), 'pts' => $items];
        }
        $grid->remove();
        return [trim(CourseHtml::innerHtml($root)), $points];
    }

    /**
     * A review study aid's opening line, which the import made from its panel's line, and the rest.
     *
     * @return array{0:string,1:string}
     */
    private static function leadIn(string $html): array
    {
        if (preg_match('#^\s*<p class="lead-in">(.*?)</p>\s*#s', $html, $match) === 1) {
            return [html_entity_decode(strip_tags($match[1]), ENT_QUOTES | ENT_HTML5, 'UTF-8'), substr($html, strlen($match[0]))];
        }
        return ['The points to fix in memory', $html];
    }

    /**
     * An assessment's questions as QUIZ holds them.
     *
     * @param array<string,mixed> $item
     * @return list<array<string,mixed>>
     */
    private static function questions(array $item, bool $diagnostic): array
    {
        $questions = (array) ($item['questions'] ?? []);
        usort($questions, static fn(array $a, array $b): int => (int) $a['position'] <=> (int) $b['position']);
        $out = [];
        foreach ($questions as $question) {
            $options = (array) $question['options'];
            usort($options, static fn(array $a, array $b): int => (int) $a['position'] <=> (int) $b['position']);
            $right = 0;
            foreach ($options as $index => $option) { if (!empty($option['is_correct'])) { $right = $index; break; } }
            $entry = ['q' => (string) $question['question_html'], 'o' => array_map(static fn(array $option): string => (string) $option['option_html'], $options), 'a' => $right, 'p' => (int) round((float) $question['points'])];
            if (trim((string) ($question['explanation_html'] ?? '')) !== '') { $entry['e'] = (string) $question['explanation_html']; }
            $remediation = array_values(array_filter((array) ($question['remediation_item_keys'] ?? []), static fn($key): bool => is_string($key) && preg_match('/^m\d+$/', $key) === 1));
            if ($diagnostic && $remediation !== []) { $entry['u'] = $remediation; }
            $out[] = $entry;
        }
        return $out;
    }

    /**
     * A presentation as PRESENTATIONS holds it.
     *
     * @param array<string,mixed> $item
     * @return array<string,mixed>
     */
    private static function deck(array $item): array
    {
        $deck = ['title' => (string) $item['title']];
        if ((int) ($item['estimated_minutes'] ?? 0) > 0) { $deck['minutes'] = (int) $item['estimated_minutes']; }
        if (($item['type_config']['theme'] ?? 'light') !== 'light') { $deck['theme'] = (string) $item['type_config']['theme']; }
        $deck['slides'] = array_values((array) ($item['type_config']['slides'] ?? []));
        return $deck;
    }

    /**
     * The course's stylesheet as its author wrote it: the frame's rules first, so the course's own win, then the
     * course's rules with CattoLMS's confinement taken off (the course box back to body, its prefix removed). Rules the
     * frame added on an earlier export are not written twice.
     */
    private function stylesheet(string $css): string
    {
        $frame = trim($this->file('resources/course-file/frame.css'));
        $own = trim((string) preg_replace(['/' . preg_quote(self::SCOPE, '/') . '\s+/', '/' . preg_quote(self::SCOPE, '/') . '(?=\s*[{,])/'], ['', 'body'], $css));
        $known = array_flip(array_map([self::class, 'rule'], self::rules($frame)));
        $kept = [];
        foreach (self::rules($own) as $rule) {
            if (!isset($known[self::rule($rule)])) { $kept[] = $rule; }
        }
        return $frame . "\n" . implode("\n", $kept);
    }

    /**
     * A stylesheet's top-level rules and at-rule blocks, each whole.
     *
     * @return list<string>
     */
    private static function rules(string $css): array
    {
        $rules = [];
        $depth = 0;
        $start = 0;
        $length = strlen($css);
        for ($i = 0; $i < $length; $i++) {
            $char = $css[$i];
            if ($char === ';' && $depth === 0) { $rules[] = trim(substr($css, $start, $i - $start + 1)); $start = $i + 1; }
            elseif ($char === '{') { $depth++; }
            elseif ($char === '}') { $depth--; if ($depth === 0) { $rules[] = trim(substr($css, $start, $i - $start + 1)); $start = $i + 1; } }
        }
        $rest = trim(substr($css, $start));
        if ($rest !== '') { $rules[] = $rest; }
        return array_values(array_filter($rules, static fn(string $rule): bool => $rule !== ''));
    }

    /** A rule without the spacing an import may change, to compare two copies of it. */
    private static function rule(string $rule): string
    {
        return (string) preg_replace(['/\s+/', '/\s*([{};:,>])\s*/'], [' ', '$1'], trim($rule));
    }

    /** @param list<string> $panels */
    private static function subs(array $panels): string
    {
        return "        <div class=\"subs\">\n" . implode('', $panels) . "        </div>\n\n";
    }

    private static function panel(string $kind, string $name, string $line, string $inner): string
    {
        return '          <details class="sub ' . $kind . '">' . "\n"
            . '            <summary><span class="sub-label">' . $name . '<small>' . self::e($line) . '</small></span><span class="chev">&#8250;</span></summary>' . "\n"
            . '            <div class="sub-inner">' . $inner . "</div>\n          </details>\n";
    }

    private function block(string $kind, string $name, string $line, string $inner): string
    {
        return '          <details class="block ' . $kind . '">' . "\n"
            . '            <summary><span class="sub-label">' . $name . '<small>' . self::e($line) . '</small></span>' . ($this->ownBlockArrow ? '' : '<span class="chev">&#8250;</span>') . "</summary>\n"
            . '            <div class="block-inner">' . "\n" . trim($inner) . "\n            </div>\n          </details>\n";
    }

    /** Strict JSON, readable, and safe inside a script element. */
    private static function json(mixed $value): string
    {
        return str_replace('</', '<\/', (string) json_encode($value, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR));
    }

    private static function number(float $value): string
    {
        return rtrim(rtrim(number_format($value, 2, '.', ''), '0'), '.');
    }

    private function file(string $path): string
    {
        $content = @file_get_contents($this->root . '/' . $path);
        if ($content === false) { throw new RuntimeException('The course file\'s ' . basename($path) . ' is missing.'); }
        return $content;
    }

    private static function e(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
