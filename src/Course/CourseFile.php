                $mark('outcomes', '<div class="outcomes"><span class="eyebrow">Learning outcomes</span><ol>' . implode('', array_map(static fn(string $outcome): string => '<li>' . $outcome . '</li>', $outcomes)) . '</ol></div>', $anchor);
            }
        } else {
