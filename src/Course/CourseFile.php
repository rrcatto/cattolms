    /**
     * The section of files, named and not held (specification 6.3; owner, 2026-11-05: "it's not about stuffing them all
     * into html files"): importing the file places each one the Resource Library has.
     *
     * @param array<string,mixed> $section
     * @param list<array<string,mixed>> $rows
     * @param array<string,array<string,mixed>> $items
     * @param array<int|string,mixed> $resources
     */
    private static function filesPanel(array $section, array $rows, array $items, array $resources): string
    {
        $names = array_column(array_filter($resources, 'is_array'), 'original_filename', 'public_id');
        $list = '';
        foreach ($rows as $row) {
            $item = $items[(string) ($row['item_key'] ?? '')] ?? [];
            $name = (string) ($names[(string) ($item['resource_public_id'] ?? '')] ?? '');
            if ($name === '') { continue; }
            $words = trim(html_entity_decode(strip_tags((string) ($item['description_html'] ?? '')), ENT_QUOTES | ENT_HTML5, 'UTF-8'));
            $list .= '<li><a href="' . self::e($name) . '">' . self::e((string) ($item['title'] ?? '')) . '</a>' . ($words === '' ? '' : ' ' . self::e($words)) . "</li>\n";
        }
        return '<details class="course-files"><summary>' . self::e((string) ($section['title'] ?? '')) . '</summary>' . "\n" . trim((string) ($section['introduction_html'] ?? '')) . "\n<ul>\n" . $list . "</ul>\n</details>\n\n";
    }

    private static function keepOrReplace(?\Dom\Element $node, string $words): void
    {
        if ($node instanceof \Dom\Element && $words !== '' && CourseFileFrame::words($node->innerHTML) !== CourseFileFrame::words($words)) { $node->textContent = $words; }
    }

    /**
     * The site's introduction, its scale written as the original wrote it while the grades are the same, and the reset
     * button the file's progress needs.
     *
     * @param list<array<string,mixed>> $bands
     * @param array<string,mixed> $frame
     * @param list<string> $leftOut
     */
    private static function framedIntroduction(string $introduction, array $bands, array $frame, array &$leftOut): string
    {
        $html = self::withScale($introduction, $bands, $leftOut);
        $scale = (string) ($frame['scale'] ?? '');
        if ($scale !== '' && self::scaleFloors($scale) === self::bandFloors($bands)) {
            $html = (string) preg_replace_callback('#<ul class="scale-list">.*?</ul>#s', static fn(): string => $scale, $html, 1);
        }
        $reset = (string) ($frame['reset'] ?? '');
        if ($reset !== '' && !str_contains($html, 'id="resetBtn"')) {
            $replaced = preg_replace('#(<ul\b[^>]*\bscale-list\b.*?</ul>)#s', '$1' . str_replace(['\\', '$'], ['\\\\', '\\$'], $reset), $html, 1, $count);
            $html = $count > 0 ? (string) $replaced : self::intoScaleBox($html, $reset);
        }
        return self::panelsInFragment($html);
    }

    /** The reset button in the box a grading scale would have, or at the end of the introduction. */
    private static function intoScaleBox(string $html, string $reset): string
    {
        $document = CourseFileFrame::parse('<!doctype html><html><body><div id="cl-fragment">' . $html . '</div></body></html>');
        $box = $document->querySelector('.info.scale');
        $root = $document->getElementById('cl-fragment');
        if (!$box instanceof \Dom\Element || $root === null) { return $html . $reset; }
        $box->appendChild($document->createComment('cl:reset'));
        return str_replace('<!--cl:reset-->', $reset, trim($root->innerHTML));
    }

    /**
     * The lowest mark of each grade in a written scale.
     *
     * @return list<int>
     */
    private static function scaleFloors(string $scale): array
    {
        preg_match_all('#<li\b[^>]*>(.*?)</li>#s', $scale, $items);
        return array_map(static fn(string $item): int => preg_match('/(\d+)\s*(?:-|\x{2013}|\x{2014}|to)\s*\d+/u', strip_tags($item), $range) === 1 ? (int) $range[1] : -1, $items[1]);
    }

    /**
     * The lowest mark of each of the site's grades, highest first.
     *
     * @param list<array<string,mixed>> $bands
     * @return list<int>
     */
    private static function bandFloors(array $bands): array
    {
        $floors = array_map(static fn(array $band): int => (int) round((float) $band['minimum_percentage']), $bands);
        rsort($floors);
        return $floors;
    }

    /** Any panel still in the original's button form inside authored content, as a <details>. */
    private static function panelsInFragment(string $html): string
    {
        if (!str_contains($html, 'acc-trigger')) { return $html; }
        $document = CourseFileFrame::parse('<!doctype html><html><body><div id="cl-fragment">' . $html . '</div></body></html>');
        CourseFileFrame::panelsToDetails($document);
        $root = $document->getElementById('cl-fragment');
        return $root === null ? $html : trim($root->innerHTML);
    }

    /**
     * A module's rows sorted into its parts.
     *
     * @param list<array<string,mixed>> $rows
     * @param array<string,array<string,mixed>> $items
     * @param list<string> $leftOut
     * @return array<string,list<array<string,mixed>>>
     */
    private static function moduleParts(array $rows, array $items, string $title, array &$leftOut): array
    {
        $parts = ['presentation' => [], 'video' => [], 'lesson' => [], 'summary' => [], 'flashcards' => [], 'practical' => [], 'review' => [], 'assessment' => []];
        foreach ($rows as $row) {
            if ($row['node_type'] !== 'item') { $leftOut[] = $title . ': a section inside the module.'; continue; }
            $item = $items[(string) $row['item_key']] ?? null;
            if ($item === null) continue;
            $kind = CourseItemService::part(['node_type' => 'item', 'assessment_role' => $row['assessment_role'] ?? null] + $item);
            if (!array_key_exists($kind, $parts)) { $leftOut[] = $title . ': the ' . str_replace('_', ' ', $kind) . ' "' . $item['title'] . '".'; continue; }
            $parts[$kind][] = $item + ['assessment_role' => $row['assessment_role'] ?? null];
        }
        foreach (['presentation', 'video', 'summary', 'flashcards', 'practical', 'review', 'assessment'] as $kind) {
            if (count($parts[$kind]) > 1) { $leftOut[] = $title . ': ' . (count($parts[$kind]) - 1) . ' more ' . $kind . ' part(s) than a module has room for.'; }
        }
        foreach ($parts['presentation'] as $deck) {
            if (!empty($deck['narrations'])) { $leftOut[] = $title . ': the recorded narration of its presentation.'; }
        }
        return $parts;
    }

    /** @param array<string,mixed> $video */
    private static function videoHtml(array $video, bool $framed): string
    {
        $id = self::e((string) ($video['type_config']['youtube_id'] ?? ''));
        $frame = '<iframe src="https://www.youtube-nocookie.com/embed/' . $id . '" title="' . self::e((string) $video['title']) . '" allowfullscreen></iframe>';
        // YouTube does not play an embedded video in a file opened from the computer, so the caption ends as the
        // original course files' did, with the video's own address (the import leaves that sentence out again).
        $caption = '<p class="video-cap">' . (trim((string) ($video['type_config']['caption'] ?? '')) !== '' ? self::e(trim((string) $video['type_config']['caption'])) . ' ' : '')
            . '<a href="https://www.youtube.com/watch?v=' . $id . '" rel="noopener">Open it on YouTube</a> if the player does not load.</p>';
        if ($framed) { return '<div class="video"><div class="video-frame">' . $frame . '</div>' . $caption . '</div>'; }
        return '        <div class="video">' . "\n" . '          ' . $frame . "\n" . '          ' . $caption . "\n" . "        </div>\n\n";
    }

    /**
     * A part's flash cards as FLASHCARDS holds them.
