    /**
     * The frame's modules made the course's: any the course no longer has removed, and any it has gained added, each made
     * from the frame's first module and numbered as it is numbered.
     *
     * @param list<string> $wanted
     * @return list<string> the modules the frame had
     */
    private static function matchModules(\Dom\HTMLDocument $document, array $wanted): array
    {
        $shells = iterator_to_array($document->querySelectorAll('.module'));
        $had = array_map(static fn(\Dom\Element $shell): string => substr((string) $shell->getAttribute('id'), 4), array_values($shells));
        $first = $shells[0] ?? null;
        if (!$first instanceof \Dom\Element || $wanted === [] || $had === $wanted) { return $had; }
        $model = $first->cloneNode(true);
        $holder = $first->parentNode;
        $step = 0;
        if (preg_match('/^mod-m(\d+)$/', (string) $first->getAttribute('id'), $own) === 1 && preg_match('/\d+/', (string) $first->querySelector('.eyebrow')?->textContent, $shown) === 1) {
            $step = (int) $shown[0] - (int) $own[1];
        }
        foreach ($shells as $shell) {
            if (!in_array(substr((string) $shell->getAttribute('id'), 4), $wanted, true)) { $shell->remove(); }
        }
        $previous = null;
        foreach ($wanted as $key) {
            $node = $document->querySelector('.module[id="mod-' . $key . '"]');
            if ($node === null && $model instanceof \Dom\Element && $holder !== null) {
                $node = $model->cloneNode(true);
                if (!$node instanceof \Dom\Element) { continue; }
                $node->setAttribute('id', 'mod-' . $key);
                $number = (int) substr($key, 1);
                // What in the model named its module now names this one.
                foreach ($node->querySelectorAll('[data-quiz], [data-key], [data-deck], [data-cards]') as $part) {
                    foreach (['data-quiz', 'data-key', 'data-deck', 'data-cards'] as $name) {
                        if ($part->hasAttribute($name)) { $part->setAttribute($name, $key); }
                    }
                }
                foreach (['.num' => $number, '.eyebrow' => $number + $step] as $selector => $value) {
                    $place = $node->querySelector($selector);
                    if ($place instanceof \Dom\Element) {
                        $place->textContent = (string) preg_replace_callback('/\d+/', static fn(array $digits): string => str_pad((string) $value, strlen($digits[0]), '0', STR_PAD_LEFT), (string) $place->textContent, 1);
                    }
                }
                if ($previous !== null) { $previous->after($node); } else { $holder->insertBefore($node, $holder->firstChild); }
            }
            $previous = $node;
        }
        $change = count($wanted) - count($had);
        foreach ($document->querySelectorAll('.meta') as $facts) {
            $facts->innerHTML = (string) preg_replace_callback('/(?<![\d.,])\d+(?=(?:\s|<[^>]+>)*(?:monthly\s+)?modules?\b)/i', static fn(array $number): string => (string) ((int) $number[0] + $change), $facts->innerHTML);
        }
        return $had;
    }

    /**
     * What a course's own script holds about its modules made the course's: the lists of their ids and their short names,
     * with those added and removed, and a course's own table of them, whose titles are the site's. A list that leaves out a
     * module that sets the course up still does.
     *
     * @param list<string> $added
     * @param list<string> $removed
     * @param list<string> $titles
     */
    private static function matchScripts(\Dom\HTMLDocument $document, array $added, array $removed, array $titles): void
    {
        foreach ($document->querySelectorAll('script') as $script) {
            $code = (string) $script->textContent;
            if ($added !== [] || $removed !== []) {
                $code = (string) preg_replace_callback('/\b([A-Z_]*IDS\s*=\s*\[)([^\]]*)(\])/', static function (array $list) use ($added, $removed): string {
                    preg_match_all('/([\'"])([^\'"]+)\1/', $list[2], $entries, PREG_SET_ORDER);
                    $modules = array_filter($entries, static fn(array $entry): bool => preg_match('/^m\d+$/', $entry[2]) === 1);
                    if ($modules === []) { return $list[0]; }
                    $last = array_key_last($modules);
                    $kept = [];
                    foreach ($entries as $index => $entry) {
                        if (!in_array($entry[2], $removed, true)) { $kept[] = $entry[1] . $entry[2] . $entry[1]; }
                        if ($index === $last) {
                            foreach ($added as $key) { $kept[] = $entry[1] . $key . $entry[1]; }
                        }
                    }
                    return $list[1] . implode(', ', $kept) . $list[3];
                }, $code);
                $code = (string) preg_replace_callback('/\b(MODULE_NAMES\s*=\s*\{)/', static fn(array $names): string => $names[1] . implode('', array_map(static fn(string $key): string => $key . ': "Module ' . substr($key, 1) . '", ', $added)), $code);
            }
            // Written on an earlier export of this file, when it is imported again.
            $earlier = strpos($code, '.forEach(function (title, index) {');
            if ($earlier !== false) {
                $from = (int) strrpos(substr($code, 0, $earlier), "\n[") + 1;
                $to = strpos($code, "\n", (int) strpos($code, 'MODULES.length = ', $earlier));
                if ($to !== false) { $code = substr($code, 0, $from) . substr($code, $to + 1); }
            }
            $table = strpos($code, 'const MODULES = [');
            $end = $table === false ? false : strpos($code, "];\n", $table);
            if ($end !== false) {
                $code = substr($code, 0, $end + 3) . self::json($titles) . '.forEach(function (title, index) { if (MODULES[index]) { MODULES[index].title = title; } else { MODULES[index] = {title: title, concepts: []}; } });' . "\n" . 'MODULES.length = ' . count($titles) . ";\n" . substr($code, $end + 3);
                $code = (string) preg_replace('/(\blet\s+\w+\s*=\s*1\s*;\s*\w+\s*<=\s*)\d+(\s*;)/', '${1}' . count($titles) . '${2}', $code);
            }
            $script->textContent = $code;
        }
    }

