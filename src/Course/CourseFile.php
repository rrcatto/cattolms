            $kept = $outcomesNode instanceof \Dom\Element;
            if ($kept) {
                $words = CourseFileFrame::words($outcomesNode->innerHTML);
                foreach ($outcomes as $outcome) { if (!str_contains($words, CourseFileFrame::words($outcome))) { $kept = false; break; } }
            }
            if (!$kept) {
