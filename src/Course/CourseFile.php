            }
            if ($this->frameWritesKeys && $body->querySelector('.s-answers') === null) {
                self::subsOf($document, $body, $anchor)->appendChild(self::modelPanel($document, $model, 's-answers', 'Answer key', 'The answers and why, for after the assessment', 'answers', '<ol class="key-list" data-key="' . $key . '"></ol>', $key, $fill));
            }
        } else {
            foreach (['.s-assess', '.s-answers'] as $panel) { $body->querySelector($panel)?->remove(); }
        }
        self::answerKeyName($body->querySelector('.s-answers'));
        foreach ($body->querySelectorAll('.subs, .blocks') as $box) {
            if ($box->firstElementChild === null) { $box->remove(); }
        }
        unset($data['QUIZ']['']);
    }

