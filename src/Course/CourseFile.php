            . '        <span class="m-titles"><span class="eyebrow">Revision</span><span class="m-name">' . self::e((string) $section['title']) . '</span>' . ($subtitle !== '' ? '<small>' . $subtitle . '</small>' : '') . "</span>\n"
            . '        <span class="chev">&#8250;</span>' . "\n" . "      </summary>\n"
            . (isset($data['PRESENTATIONS']['review']) ? self::subs([self::panel('s-present', 'Presentation', (string) $data['PRESENTATIONS']['review']['title'], '<div class="presentation" data-deck="review"></div>')]) : '')
            . '      <div class="review-inner">' . "\n" . trim($inner) . "\n" . '        <div id="reviewCards"></div>' . "\n" . "      </div>\n"
            . ($assessed ? self::subs([
                self::panel('s-assess', 'Self Assessment', count($data['QUIZ']['review']) . ' questions, ' . array_sum(array_column($data['QUIZ']['review'], 'p')) . ' points', '<div class="quiz" data-quiz="review"></div>'),
                self::panel('s-answers', 'Answer key', 'The answers and why, for after the assessment', '<ol class="key-list" data-key="review"></ol>'),
