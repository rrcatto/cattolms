        return array_values(array_map(static fn(array $card): array => array_filter(['front' => (string) ($card['front'] ?? ''), 'back' => (string) ($card['back'] ?? ''), 'hint' => (string) ($card['hint'] ?? '')], static fn(string $value): bool => $value !== ''), (array) ($item['type_config']['cards'] ?? [])));
    }

    /**
     * One module and its parts, each part in its panel, in the specification's order.
     *
     * @param array<string,mixed> $section
     * @param list<array<string,mixed>> $rows
     * @param array<string,array<string,mixed>> $items
     * @param array<string,array<string,mixed>> $data
     * @param list<string> $leftOut
     */
    private function module(array $section, array $rows, array $items, string $key, int $number, array &$data, array &$leftOut): string
    {
        $title = (string) $section['title'];
        [$subtitle, $outcomes] = self::heading((string) ($section['introduction_html'] ?? ''), $title, $leftOut);
        $parts = self::moduleParts($rows, $items, $title, $leftOut);
        $first = static fn(string $kind): ?array => $parts[$kind][0] ?? null;
        $pad = str_pad((string) $number, 2, '0', STR_PAD_LEFT);
        $assessment = $first('assessment');
        $required = $assessment !== null && ($assessment['assessment_role'] ?? '') === 'graded';

        $body = '';
        if (($deck = $first('presentation')) !== null) {
            $data['PRESENTATIONS'][$key] = self::deck($deck);
            $body .= self::subs([self::panel('s-present', 'Presentation', (string) $deck['title'], '<div class="presentation" data-deck="' . $key . '"></div>')]);
        }
        if (($video = $first('video')) !== null) {
            $body .= self::videoHtml($video, false);
        }
        if ($outcomes !== []) {
            $body .= '        <div class="outcomes">' . "\n" . '          <span class="eyebrow">Learning outcomes</span>' . "\n          <ol>\n"
                . implode('', array_map(static fn(string $outcome): string => '            <li>' . $outcome . "</li>\n", $outcomes)) . "          </ol>\n        </div>\n\n";
        }
        foreach ($parts['lesson'] as $lesson) { $body .= trim((string) $lesson['content_source']) . "\n\n"; }
        $after = [];
        if (($summary = $first('summary')) !== null) { $after[] = self::panel('s-summary', 'Summary', 'The module in brief', "\n" . trim((string) $summary['content_source']) . "\n            "); }
        if (($cards = $first('flashcards')) !== null) {
            $data['FLASHCARDS'][$key] = self::cards($cards);
            $after[] = self::panel('s-cards', 'Flash cards', 'Test your recall, one card at a time', '<div class="flashcards" data-cards="' . $key . '"></div>');
        }
        if ($after !== []) { $body .= self::subs($after); }
        $blocks = [];
        if (($practical = $first('practical')) !== null) {
            $tasks = substr_count((string) $practical['content_source'], '<section class="task"');
            $blocks[] = $this->block('practical', 'Practical work', $tasks === 1 ? 'One task' : $tasks . ' tasks', (string) $practical['content_source']);
            $blocks[] = $this->block('answers', 'Model answers', 'Check your own work once you have done the tasks', (string) ($practical['type_config']['answer_html'] ?? ''));
        }
        if (($aid = $first('review')) !== null) {
            [$line, $content] = self::leadIn((string) $aid['content_source']);
            $blocks[] = $this->block('review-aid', 'Review Study Aid', $line, $content);
        }
        if ($blocks !== []) { $body .= "        <div class=\"blocks\">\n" . implode('', $blocks) . "        </div>\n\n"; }
        if ($assessment !== null) {
            $data['QUIZ'][$key] = self::questions($assessment, false);
            $count = count($data['QUIZ'][$key]);
            $points = array_sum(array_column($data['QUIZ'][$key], 'p'));
            $body .= self::subs([
                self::panel('s-assess', 'Self Assessment', $count . ' questions, ' . $points . ' points', '<div class="quiz" data-quiz="' . $key . '"></div>'),
                self::panel('s-answers', 'Answer key', 'The answers and why, for after the assessment', '<ol class="key-list" data-key="' . $key . '"></ol>'),
            ]);
        }

        return '    <section class="module" id="mod-' . $key . '" data-assessment-required="' . ($required ? 'true' : 'false') . '">' . "\n"
            . '      <details class="panel">' . "\n" . '        <summary class="panel-head">' . "\n"
            . '          <span class="node"><span class="num">' . $pad . '</span><span class="check">&#10003;</span></span>' . "\n"
            . '          <span class="m-titles"><span class="eyebrow">' . ($this->short ? 'Short course' : 'Module ' . $pad) . '</span><span class="m-name">' . self::e($title) . '</span>' . ($subtitle !== '' ? '<small>' . $subtitle . '</small>' : '') . "</span>\n"
            . '          <span class="m-grade" data-grade></span>' . "\n" . '          <span class="chev">&#8250;</span>' . "\n" . "        </summary>\n"
            . '        <div class="module-body">' . "\n\n" . $body . "        </div>\n      </details>\n    </section>\n";
    }

    /**
