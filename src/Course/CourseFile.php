    /** Whether the course's own stylesheet draws the arrow on its blocks' headings, as the original files' did. */
    private bool $ownBlockArrow = false;

    public function __construct(private readonly CoursePortabilityService $portability)
    {
        $this->root = dirname(__DIR__, 2);
    }

    /**
     * The file's name: the course's code and address, as "GDN-101-growing-vegetables.html".
     *
     * @param array<string,mixed> $package
     */
    public static function filename(array $package): string
    {
        $course = (array) ($package['course'] ?? []);
        $name = trim((string) preg_replace('/[^A-Za-z0-9._-]+/', '-', (string) ($course['code'] ?? '') . '-' . (string) ($course['slug'] ?? '')), '-.');
        return ($name === '' ? 'course' : $name) . '.html';
    }

    /**
     * A course on the site as its file, and what the file could not hold.
     *
     * @return array{html:string,left_out:list<string>,filename:string}
     */
    public function fromCourse(int $courseId): array
    {
        $package = $this->portability->exportCourse($courseId);
        return $this->render($package) + ['filename' => self::filename($package)];
    }

    /**
     * @param array<string,mixed> $package a course package in the 2.1 shape the site exports
     * @return array{html:string,left_out:list<string>}
     */
    public function render(array $package): array
    {
        $course = (array) ($package['course'] ?? []);
        $items = [];
        foreach ((array) ($package['course_items'] ?? []) as $item) { $items[(string) $item['item_key']] = $item; }
        $children = [];
        foreach ((array) ($package['structure'] ?? []) as $row) { $children[(string) ($row['parent_node_key'] ?? '')][] = $row; }
        foreach ($children as &$rows) { usort($rows, static fn(array $a, array $b): int => (int) $a['position'] <=> (int) $b['position']); }
        unset($rows);

        $leftOut = [];
        $this->ownBlockArrow = preg_match('/\.block\s*>\s*summary::?(?:before|after)\s*\{[^}]*content/', (string) ($course['presentation_css'] ?? '')) === 1;
        $data = ['QUIZ' => [], 'PRESENTATIONS' => [], 'FLASHCARDS' => [], 'REVIEW' => []];
        $diagnostic = $review = $final = '';
        $diagPass = null;
        $modules = [];
        $number = (int) ($course['first_module_number'] ?? 1);
        foreach ($children[''] ?? [] as $row) {
            if ($row['node_type'] === 'section' && !empty($row['numbered'])) {
                $modules[] = $this->module($row, $children[(string) $row['node_key']] ?? [], $items, 'm' . $number, $number, $data, $leftOut);
                $number++;
                continue;
            }
            if ($row['node_type'] === 'section') {
                if ($review !== '') { $leftOut[] = 'The section "' . $row['title'] . '": a file has room for one review.'; continue; }
                $review = $this->review($row, $children[(string) $row['node_key']] ?? [], $items, $data, $leftOut);
                continue;
            }
            $item = $items[(string) $row['item_key']] ?? null;
            if ($item === null) continue;
            $kind = CourseItemService::part(['node_type' => 'item', 'assessment_role' => $row['assessment_role'] ?? null] + $item);
            if ($item['item_type'] === 'slide_deck' && (($item['type_config']['kind'] ?? '') === 'trailer')) {
                $leftOut[] = 'The trailer, "' . $item['title'] . '": a course file has no place for it.';
            } elseif ($item['item_type'] === 'diagnostic') {
                $data['QUIZ']['diag'] = self::questions($item, true);
                $diagPass = (int) round((float) ($item['pass_mark'] ?? 50));
                $diagnostic = $this->diagnostic($item);
            } elseif ($kind === 'final') {
                $data['QUIZ']['final'] = self::questions($item, false);
                $final = $this->finalAssessment($item);
            } else {
                $leftOut[] = 'The ' . str_replace('_', ' ', (string) $item['item_type']) . ' "' . $item['title'] . '" outside the modules.';
            }
        }

        $html = '<!doctype html>' . "\n" . '<html lang="en-ZA">' . "\n" . '<head>' . "\n" . '<meta charset="utf-8">' . "\n"
            . '<meta name="viewport" content="width=device-width, initial-scale=1">' . "\n"
            . '<meta name="cattolms:course-code" content="' . self::e((string) ($course['code'] ?? '')) . '">' . "\n"
            . '<title>' . self::e((string) ($course['title'] ?? '')) . '</title>' . "\n"
            . "<style>\n" . $this->stylesheet((string) ($course['presentation_css'] ?? '')) . "\n</style>\n</head>\n<body>\n<div class=\"wrap\">\n"
            . $this->masthead($course, (string) (($package['catalogue']['cover'] ?? null) ?: ''))
            . self::withScale((string) ($course['introduction_html'] ?? ''), (array) ($package['grade_bands'] ?? []), $leftOut) . "\n\n"
            . $diagnostic
            . '  <div class="modules">' . "\n" . implode("\n", $modules) . "  </div>\n\n"
            . $review . $final
            . "</div>\n\n<script>\n";
        foreach ($data as $name => $value) {
            $html .= 'const ' . $name . ' = ' . self::json($value === [] ? new \stdClass() : $value) . ";\n";
        }
        if ($diagPass !== null && $diagPass !== 50) { $html .= 'const DIAG_PASS = ' . $diagPass . ";\n"; }
        $html .= "</script>\n\n<script>\n" . $this->file('resources/course-file/course.js') . "</script>\n</body>\n</html>\n";
        return ['html' => $html, 'left_out' => $leftOut];
    }

    /**
     * One module and its parts, each part in its panel, in the specification's order.
     *
     * @param array<string,mixed> $section
     * @param list<array<string,mixed>> $rows
     * @param array<string,array<string,mixed>> $items
     * @param array<string,array<string,mixed>> $data
     * @param list<string> $leftOut
     */
    private function module(array $section, array $rows, array $items, string $key, int $number, array &$data, array &$leftOut): string
    {
        $title = (string) $section['title'];
        [$subtitle, $outcomes] = self::heading((string) ($section['introduction_html'] ?? ''), $title, $leftOut);
        $parts = ['presentation' => [], 'video' => [], 'lesson' => [], 'summary' => [], 'flashcards' => [], 'practical' => [], 'review' => [], 'assessment' => []];
        foreach ($rows as $row) {
            if ($row['node_type'] !== 'item') { $leftOut[] = $title . ': a section inside the module.'; continue; }
            $item = $items[(string) $row['item_key']] ?? null;
            if ($item === null) continue;
            $kind = CourseItemService::part(['node_type' => 'item', 'assessment_role' => $row['assessment_role'] ?? null] + $item);
            if (!array_key_exists($kind, $parts)) { $leftOut[] = $title . ': the ' . str_replace('_', ' ', $kind) . ' "' . $item['title'] . '".'; continue; }
            $parts[$kind][] = $item + ['assessment_role' => $row['assessment_role'] ?? null];
        }
        foreach (['presentation', 'video', 'summary', 'flashcards', 'practical', 'review', 'assessment'] as $kind) {
            if (count($parts[$kind]) > 1) { $leftOut[] = $title . ': ' . (count($parts[$kind]) - 1) . ' more ' . $kind . ' part(s) than a module has room for.'; }
        }
        $first = static fn(string $kind): ?array => $parts[$kind][0] ?? null;
        $pad = str_pad((string) $number, 2, '0', STR_PAD_LEFT);
        $assessment = $first('assessment');
        $required = $assessment !== null && ($assessment['assessment_role'] ?? '') === 'graded';

        $body = '';
        if (($deck = $first('presentation')) !== null) {
            $data['PRESENTATIONS'][$key] = self::deck($deck);
            $body .= self::subs([self::panel('s-present', 'Presentation', (string) $deck['title'], '<div class="presentation" data-deck="' . $key . '"></div>')]);
        }
        if (($video = $first('video')) !== null) {
            $body .= '        <div class="video">' . "\n"
                . '          <iframe src="https://www.youtube-nocookie.com/embed/' . self::e((string) ($video['type_config']['youtube_id'] ?? '')) . '" title="' . self::e((string) $video['title']) . '" allowfullscreen></iframe>' . "\n"
                // YouTube does not play an embedded video in a file opened from the computer, so the caption ends as the
                // original course files' did, with the video's own address (the import leaves that sentence out again).
                . '          <p class="video-cap">' . (trim((string) ($video['type_config']['caption'] ?? '')) !== '' ? self::e(trim((string) $video['type_config']['caption'])) . ' ' : '')
                . '<a href="https://www.youtube.com/watch?v=' . self::e((string) ($video['type_config']['youtube_id'] ?? '')) . '" rel="noopener">Open it on YouTube</a> if the player does not load.</p>' . "\n"
                . "        </div>\n\n";
        }
        if ($outcomes !== []) {
            $body .= '        <div class="outcomes">' . "\n" . '          <span class="eyebrow">Learning outcomes</span>' . "\n          <ol>\n"
                . implode('', array_map(static fn(string $outcome): string => '            <li>' . $outcome . "</li>\n", $outcomes)) . "          </ol>\n        </div>\n\n";
        }
        foreach ($parts['lesson'] as $lesson) { $body .= trim((string) $lesson['content_source']) . "\n\n"; }
        $after = [];
        if (($summary = $first('summary')) !== null) { $after[] = self::panel('s-summary', 'Summary', 'The module in brief', "\n" . trim((string) $summary['content_source']) . "\n            "); }
        if (($cards = $first('flashcards')) !== null) {
            $data['FLASHCARDS'][$key] = array_values(array_map(static fn(array $card): array => array_filter(['front' => (string) ($card['front'] ?? ''), 'back' => (string) ($card['back'] ?? ''), 'hint' => (string) ($card['hint'] ?? '')], static fn(string $value): bool => $value !== ''), (array) ($cards['type_config']['cards'] ?? [])));
            $after[] = self::panel('s-cards', 'Flash cards', 'Test your recall, one card at a time', '<div class="flashcards" data-cards="' . $key . '"></div>');
        }
        if ($after !== []) { $body .= self::subs($after); }
        $blocks = [];
        if (($practical = $first('practical')) !== null) {
            $tasks = substr_count((string) $practical['content_source'], '<section class="task"');
            $blocks[] = $this->block('practical', 'Practical work', $tasks === 1 ? 'One task' : $tasks . ' tasks', (string) $practical['content_source']);
            $blocks[] = $this->block('answers', 'Model answers', 'Check your own work once you have done the tasks', (string) ($practical['type_config']['answer_html'] ?? ''));
        }
        if (($aid = $first('review')) !== null) {
            [$line, $content] = self::leadIn((string) $aid['content_source']);
            $blocks[] = $this->block('review-aid', 'Review Study Aid', $line, $content);
        }
        if ($blocks !== []) { $body .= "        <div class=\"blocks\">\n" . implode('', $blocks) . "        </div>\n\n"; }
        if ($assessment !== null) {
            $data['QUIZ'][$key] = self::questions($assessment, false);
            $count = count($data['QUIZ'][$key]);
            $points = array_sum(array_column($data['QUIZ'][$key], 'p'));
            $body .= self::subs([
                self::panel('s-assess', 'Self Assessment', $count . ' questions, ' . $points . ' points', '<div class="quiz" data-quiz="' . $key . '"></div>'),
                self::panel('s-answers', 'Answer key', 'The answers and why, for after the assessment', '<ol class="key-list" data-key="' . $key . '"></ol>'),
            ]);
        }

        return '    <section class="module" id="mod-' . $key . '" data-assessment-required="' . ($required ? 'true' : 'false') . '">' . "\n"
            . '      <details class="panel">' . "\n" . '        <summary class="panel-head">' . "\n"
            . '          <span class="node"><span class="num">' . $pad . '</span><span class="check">&#10003;</span></span>' . "\n"
            . '          <span class="m-titles"><span class="eyebrow">Module ' . $pad . '</span><span class="m-name">' . self::e($title) . '</span>' . ($subtitle !== '' ? '<small>' . $subtitle . '</small>' : '') . "</span>\n"
            . '          <span class="m-grade" data-grade></span>' . "\n" . '          <span class="chev">&#8250;</span>' . "\n" . "        </summary>\n"
            . '        <div class="module-body">' . "\n\n" . $body . "        </div>\n      </details>\n    </section>\n";
    }

    /**
     * The review, after the modules: its study aid, its points as REVIEW, its presentation and its assessment.
     *
     * @param array<string,mixed> $section
     * @param list<array<string,mixed>> $rows
     * @param array<string,array<string,mixed>> $items
     * @param array<string,array<string,mixed>> $data
     * @param list<string> $leftOut
     */
    private function review(array $section, array $rows, array $items, array &$data, array &$leftOut): string
    {
        $inner = '';
        $required = false;
        foreach ($rows as $row) {
            $item = $items[(string) ($row['item_key'] ?? '')] ?? null;
            if ($item === null) continue;
            $kind = CourseItemService::part(['node_type' => 'item', 'assessment_role' => $row['assessment_role'] ?? null] + $item);
            if ($item['item_type'] === 'slide_deck') {
                $data['PRESENTATIONS']['review'] = self::deck($item);
            } elseif ($kind === 'review' || $item['item_type'] === 'html_lesson') {
                [$inner, $points] = self::reviewPoints((string) $item['content_source']);
                $data['REVIEW'] = $points;
            } elseif (in_array($kind, ['assessment', 'final'], true)) {
                $data['QUIZ']['review'] = self::questions($item, false);
                $required = ($row['assessment_role'] ?? '') === 'graded';
            } else {
                $leftOut[] = 'The review\'s ' . str_replace('_', ' ', (string) $item['item_type']) . ' "' . $item['title'] . '".';
            }
        }
        [$subtitle, $outcomes] = self::heading((string) ($section['introduction_html'] ?? ''), (string) $section['title'], $leftOut);
        if ($outcomes !== []) {
            $inner = '<div class="outcomes">' . "\n" . '          <span class="eyebrow">Learning outcomes</span>' . "\n          <ol>\n"
                . implode('', array_map(static fn(string $outcome): string => '            <li>' . $outcome . "</li>\n", $outcomes)) . "          </ol>\n        </div>\n" . $inner;
        }
        $assessed = isset($data['QUIZ']['review']) && !str_contains($inner, 'data-quiz="review"');
        return '  <section class="review" id="mod-review" data-assessment-required="' . ($required ? 'true' : 'false') . '">' . "\n"
            . '    <details class="panel">' . "\n" . '      <summary class="panel-head">' . "\n"
            . '        <span class="node"><span class="num">R</span></span>' . "\n"
            . '        <span class="m-titles"><span class="eyebrow">Revision</span><span class="m-name">' . self::e((string) $section['title']) . '</span>' . ($subtitle !== '' ? '<small>' . $subtitle . '</small>' : '') . "</span>\n"
            . '        <span class="chev">&#8250;</span>' . "\n" . "      </summary>\n"
            . (isset($data['PRESENTATIONS']['review']) ? self::subs([self::panel('s-present', 'Presentation', (string) $data['PRESENTATIONS']['review']['title'], '<div class="presentation" data-deck="review"></div>')]) : '')
            . '      <div class="review-inner">' . "\n" . trim($inner) . "\n" . '        <div id="reviewCards"></div>' . "\n" . "      </div>\n"
            . ($assessed ? self::subs([
                self::panel('s-assess', 'Self Assessment', count($data['QUIZ']['review']) . ' questions, ' . array_sum(array_column($data['QUIZ']['review'], 'p')) . ' points', '<div class="quiz" data-quiz="review"></div>'),
                self::panel('s-answers', 'Answer key', 'The answers and why, for after the assessment', '<ol class="key-list" data-key="review"></ol>'),
            ]) : '')
            . "    </details>\n  </section>\n\n";
    }

