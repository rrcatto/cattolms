     */
    private function review(array $section, array $rows, array $items, array &$data, array &$leftOut): string
    {
        $inner = '';
        $required = false;
        foreach ($rows as $row) {
            $item = $items[(string) ($row['item_key'] ?? '')] ?? null;
            if ($item === null) continue;
            $kind = CourseItemService::part(['node_type' => 'item', 'assessment_role' => $row['assessment_role'] ?? null] + $item);
