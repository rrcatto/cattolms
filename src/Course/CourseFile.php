    /**
     * The course in its original file's frame.
     *
     * @param array<string,mixed> $package
     * @param array<string,mixed> $frame
     * @param array<string,list<array<string,mixed>>> $children
     * @param array<string,array<string,mixed>> $items
     * @param list<string> $leftOut
     */
    private function framed(array $package, array $frame, array $children, array $items, array &$leftOut): string
    {
        $course = (array) ($package['course'] ?? []);
        $document = CourseFileFrame::parse((string) $frame['template']);
        $this->frameWritesKeys = preg_match('/key-list|data-key/', (string) $frame['template']) === 1;
        $number = (int) ($course['first_module_number'] ?? 1);
        $sections = array_values(array_filter($children[''] ?? [], static fn(array $row): bool => $row['node_type'] === 'section' && !empty($row['numbered'])));
        $wanted = [];
        foreach ($sections as $index => $section) { $wanted[] = 'm' . ($number + $index); }
        $had = self::matchModules($document, $wanted);
        self::matchScripts($document, array_values(array_diff($wanted, $had)), array_values(array_diff($had, $wanted)), array_map(static fn(array $section): string => (string) $section['title'], $sections));

        $data = ['QUIZ' => [], 'PRESENTATIONS' => [], 'FLASHCARDS' => [], 'REVIEW' => []];
        $fill = [];
        $summary = $document->querySelector('.sub.s-summary') ?? $document->querySelector('.sub');
        $copy = $summary instanceof \Dom\Element ? $summary->cloneNode(true) : null;
        $model = $copy instanceof \Dom\Element ? $copy : null;
        $preview = null;
        $filesPanel = '';
        $finalLimit = self::STANDARD_FINAL_LIMIT;
        foreach ($children[''] ?? [] as $row) {
            if ($row['node_type'] === 'section' && !empty($row['numbered'])) {
                $key = 'm' . $number;
                $this->framedModule($document, $document->querySelector('.module[id="mod-' . $key . '"]'), $row, $children[(string) $row['node_key']] ?? [], $items, $key, $model, $data, $fill, $leftOut);
                $number++;
            } elseif ($row['node_type'] === 'section' && $filesPanel === '' && self::onlyFiles($children[(string) $row['node_key']] ?? [], $items)) {
                $filesPanel = self::filesPanel($row, $children[(string) $row['node_key']] ?? [], $items, (array) ($package['resources'] ?? []));
            } elseif ($row['node_type'] === 'section') {
                $this->framedReview($document, $row, $children[(string) $row['node_key']] ?? [], $items, $frame, $model, $data, $fill, $leftOut);
            } else {
                $item = $items[(string) $row['item_key']] ?? null;
                if ($item === null) { continue; }
                $kind = CourseItemService::part(['node_type' => 'item', 'assessment_role' => $row['assessment_role'] ?? null] + $item);
                if ($item['item_type'] === 'slide_deck' && (($item['type_config']['kind'] ?? '') === 'trailer')) {
                    $data['PRESENTATIONS']['trailer'] = self::deck($item);
                    $preview = $item;
                } elseif ($item['item_type'] === 'diagnostic') {
                    $data['QUIZ']['diag'] = self::questions($item, true);
                    self::title($document->querySelector('.diag'), (string) $item['title']);
                } elseif ($kind === 'final') {
                    $data['QUIZ']['final'] = self::questions($item, false);
                    $finalLimit = (int) ($item['time_limit_seconds'] ?? self::STANDARD_FINAL_LIMIT);
                    self::title($document->querySelector('.final'), (string) $item['title']);
                    self::counted($document->querySelector('.final .m-titles small'), $data['QUIZ']['final']);
                } else {
                    $leftOut[] = 'The ' . str_replace('_', ' ', (string) $item['item_type']) . ' "' . $item['title'] . '" outside the modules.';
                }
            }
        }

        if ($preview !== null) {
            $box = $document->createElement('div');
            $box->classList->add('subs');
            $box->classList->add('course-preview');
            $box->appendChild(self::modelPanel($document, $model, 's-present', (string) $preview['title'], self::oneLine($preview), 'present', '<div class="presentation" data-deck="trailer"></div>', 'trailer', $fill));
            $before = $document->querySelector('.diag') ?? $document->querySelector('.modules');
            $before?->parentNode?->insertBefore($box, $before);
        }

        // The head and masthead: the site's words, in the original's markup while the words are the same.
        $code = $document->querySelector('meta[name="' . CourseCode::META_NAME . '"]');
        if (!$code instanceof \Dom\Element) {
            $code = $document->createElement('meta');
            $code->setAttribute('name', CourseCode::META_NAME);
            $document->querySelector('head')?->appendChild($code);
        }
        $code->setAttribute('content', (string) ($course['code'] ?? ''));
        $masthead = $document->querySelector('.masthead');
        if ($masthead instanceof \Dom\Element) {
            $masthead->setAttribute('data-level', (string) ($course['level'] ?? ''));
            self::keepOrReplace($masthead->querySelector('h1'), (string) ($course['title'] ?? ''));
            self::keepOrReplace($masthead->querySelector('.course-subtitle'), (string) ($course['subtitle'] ?? ''));
            self::keepOrReplace($masthead->querySelector('.course-summary'), (string) ($course['summary'] ?? ''));
            $cover = trim((string) (($package['catalogue']['cover'] ?? null) ?: ''));
            if ($cover !== '') {
                $masthead->insertBefore($document->createComment('cl:cover'), $masthead->firstChild);
                $fill['<!--cl:cover-->'] = '<div class="course-cover">' . $cover . '</div>';
            }
        }
        // The course's styling is its CSS tab (owner, 2026-11-03). The panels the original never had take its Summary panel's
        // rules, so they look like their neighbours.
        $css = CourseFileFrame::openRules(self::ownRules((string) ($course['presentation_css'] ?? '')));
        $neighbours = self::summaryRules($css);
        $fill['<!--cl:stylesheet-->'] = '<style data-course-file>' . "\n" . trim($this->file('resources/course-file/original.css')) . "\n</style>\n<style>\n" . $css . "\n</style>"
            . ($neighbours === '' ? '' : "\n" . '<style data-course-file>' . "\n" . $neighbours . '</style>');
        $document->querySelector('body')?->appendChild($document->createComment('cl:parts'));

        $stated = (int) ($course['estimated_minutes'] ?? 0);
        $short = ($course['course_type'] ?? 'full') === 'short';
        $document->querySelector('meta[name="' . self::COURSE_TYPE_META . '"]')?->remove();
        $metas = $short
            ? [self::FINAL_LIMIT_META => 0, self::STUDY_HOURS_META => 0, self::STUDY_MINUTES_META => $stated, self::COURSE_TYPE_META => 'short']
            : [self::FINAL_LIMIT_META => $finalLimit === self::STANDARD_FINAL_LIMIT ? 0 : $finalLimit / 60, self::STUDY_HOURS_META => $stated / 60, self::STUDY_MINUTES_META => 0];
        foreach ($metas as $name => $value) {
            $document->querySelector('meta[name="' . $name . '"]')?->remove();
            $content = is_string($value) ? $value : ($value > 0 ? (string) (int) round($value) : '');
            if ($content === '' || !$document->head instanceof \Dom\Element) { continue; }
            $meta = $document->createElement('meta');
            $meta->setAttribute('name', $name);
            $meta->setAttribute('content', $content);
            $document->head->prepend($meta);
        }
        $document->querySelector('meta[name="' . self::PART_NAMES_META . '"]')?->remove();
        if (self::partNames($package) !== '' && $document->head instanceof \Dom\Element) {
            $meta = $document->createElement('meta');
            $meta->setAttribute('name', self::PART_NAMES_META);
            $meta->setAttribute('content', self::partNames($package));
            $document->head->prepend($meta);
        }
        $fill['<!--cl:introduction-->'] = self::descriptionPanel($course) . $filesPanel . self::framedIntroduction((string) ($course['introduction_html'] ?? ''), (array) ($package['grade_bands'] ?? []), $frame, $leftOut);
        $parts = '';
        foreach (['PRESENTATIONS', 'FLASHCARDS'] as $name) {
            if ($data[$name] !== []) { $parts .= 'const ' . $name . ' = ' . self::json($data[$name]) . ";\n"; }
        }
        $fill['<!--cl:parts-->'] = $parts === '' ? '' : '<script data-course-parts>' . "\n" . $parts . $this->file('resources/course-file/parts.js') . "</script>\n";
        $extras = (array) ($frame['extras'] ?? []);
        foreach ($data['QUIZ'] as &$questions) {
            foreach ($questions as &$question) {
                $question += (array) ($extras[md5(CourseFileFrame::words((string) $question['q']))] ?? []);
            }
            unset($question);
        }
        unset($questions);
        $html = (string) $document->saveHtml();
        foreach (['QUIZ', 'REVIEW'] as $name) {
            $value = $data[$name] === [] ? new \stdClass() : $data[$name];
            $html = (string) preg_replace_callback('#/\*cl:' . $name . ':(const|let|var)\*/#', static fn(array $match): string => $match[1] . ' ' . $name . ' = ' . self::json($value) . ';', $html);
        }
        return "<!doctype html>\n" . strtr((string) preg_replace('/^<!doctype[^>]*>\s*/i', '', $html), $fill);
    }

    /**
     * A module poured into its panel in the frame: the site's words, video, lesson and parts, the frame's panels around them.
     *
     * @param array<string,mixed> $section
     * @param list<array<string,mixed>> $rows
     * @param array<string,array<string,mixed>> $items
     * @param array<string,array<string,mixed>> $data
     * @param array<string,string> $fill
     * @param list<string> $leftOut
     */
    private function framedModule(\Dom\HTMLDocument $document, ?\Dom\Element $node, array $section, array $rows, array $items, string $key, ?\Dom\Element $model, array &$data, array &$fill, array &$leftOut): void
    {
        $body = $node?->querySelector('.module-body');
        if ($node === null || !$body instanceof \Dom\Element) { return; }
        $title = (string) $section['title'];
        [$subtitle, $outcomes] = self::heading((string) ($section['introduction_html'] ?? ''), $title, $leftOut);
        $parts = self::moduleParts($rows, $items, $title, $leftOut);
        $first = static fn(string $kind): ?array => $parts[$kind][0] ?? null;

        self::title($node, $title);
        $small = $node->querySelector('.m-titles small');
        if ($small instanceof \Dom\Element && $subtitle !== '' && CourseFileFrame::words($small->innerHTML) !== CourseFileFrame::words($subtitle)) { $small->innerHTML = $subtitle; }
        if ($small instanceof \Dom\Element && $subtitle === '') { $small->remove(); }

        $assessment = $first('assessment');
        $node->setAttribute('data-assessment-required', $assessment !== null && ($assessment['assessment_role'] ?? '') === 'graded' ? 'true' : 'false');

        $anchor = null;
        foreach ($body->childNodes as $child) {
            if ($child instanceof \Dom\Element && ($child->classList->contains('blocks') || $child->classList->contains('block') || $child->classList->contains('subs'))) { $anchor = $child; break; }
        }
