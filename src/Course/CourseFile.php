        } elseif ($summaryPanel instanceof \Dom\Element) {
            $summaryPanel->remove();
            $summaryPanel = null;
        } elseif ($summary !== null) {
            $summaryPanel = self::modelPanel($document, $model, 's-summary', 'Summary', 'The module in brief', 'summary', trim((string) $summary['content_source']), $key, $fill);
            self::subsOf($document, $body, $anchor)->appendChild($summaryPanel);
        }
        $cards = $first('flashcards');
