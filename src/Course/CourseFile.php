            $inner = '<div class="outcomes">' . "\n" . '          <span class="eyebrow">Learning outcomes</span>' . "\n          <ol>\n"
                . implode('', array_map(static fn(string $outcome): string => '            <li>' . $outcome . "</li>\n", $outcomes)) . "          </ol>\n        </div>\n" . $inner;
        }
        $assessed = isset($data['QUIZ']['review']) && !str_contains($inner, 'data-quiz="review"');
