/*
Generated by: Claude Code CLI

Date time: 2026/10/07 SAST

Version: 0.8.8.11

Description:
Where course categories sit: the one place the category tree's structure is decided. Dragging on
/admin/courses/categories, the keyboard and the ⋯ menu moves, the Move into page and creating a
category all come here, so every route obeys the same rules:

- three levels at most: a main category may hold subcategories, a subcategory may hold
  sub-subcategories, a sub-subcategory holds nothing; a move counts the depth of the whole subtree
  that travels (new parent's level plus the subtree's height), never just the moved category;
- a category never goes inside itself or one of its own descendants;
- siblings keep an explicit order, stored as positions 1..n within each parent.

Each change is one transaction. The taxonomy is locked against other writers, the change is applied
to the tree as it is now (Support\TreeArrangement), the whole result is checked, and only the rows
whose parent, level or position changed are written. A refused move writes nothing and says why. A
browser that saw a different tree from the stored one is refused rather than guessed at. Moving a
category never touches which courses are filed in it.

Changelog:
2026/10/07 SAST
- Created for the draggable category tree.
*/

declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\TreeArrangement;
use CattoLearning\Support\TreeMoveRefused;
use InvalidArgumentException;

final class CategoryHierarchyService
{
    public const MAX_LEVEL = 3;
    public const DIRECTIONS = TreeArrangement::DIRECTIONS;

    private const MESSAGES = [
        TreeMoveRefused::MISSING_ROW => 'That category no longer exists. Reload the page.',
        TreeMoveRefused::NOTHING_CHOSEN => 'Choose a category to move.',
        TreeMoveRefused::MISSING_DESTINATION => 'The category you chose to move it into no longer exists. Reload the page and try again.',
        TreeMoveRefused::CYCLE => 'A category cannot be moved into itself or one of its own subcategories.',
        TreeMoveRefused::TOO_DEEP => 'Course categories go three levels deep. Moving it there would put it, or its subcategories, below the third level.',
        TreeMoveRefused::BAD_POSITION => 'Choose a valid position.',
        TreeMoveRefused::BAD_DIRECTION => 'Choose a valid move.',
        TreeMoveRefused::ALREADY_OUTER => 'This category is already a main category.',
        TreeMoveRefused::STALE => 'The categories changed while you were moving this one. Reload the page and try again.',
    ];

    private readonly TreeArrangement $tree;

    public function __construct(
        private readonly CourseRepository $categories,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
    ) {
        $this->tree = new TreeArrangement(self::MAX_LEVEL);
    }

    /**
     * Puts a category, with its whole subtree, under $parentId (null for a main category) at $index
     * among that parent's other children (null for last). $fromParentId, when given, is the parent
     * the browser showed it under: if the stored tree says otherwise the move is refused.
     */
    public function move(int $categoryId, ?int $parentId, ?int $index, int $userId, ?int $fromParentId = null, bool $checkFrom = false): void
    {
        $this->rearrange($categoryId, $userId, function (array $rows) use ($categoryId, $parentId, $index, $fromParentId, $checkFrom): array {
            if ($checkFrom && self::parentIn($rows, $categoryId) !== $fromParentId) {
                throw new TreeMoveRefused(TreeMoveRefused::STALE);
            }
            return $this->tree->place($rows, [$categoryId], $parentId, $index);
        });
    }

    /** Top, up, down or bottom among its siblings, or out to just after its parent. */
    public function step(int $categoryId, string $direction, int $userId): void
    {
        $this->rearrange($categoryId, $userId, fn(array $rows): array => $this->tree->move($rows, [$categoryId], $direction));
    }

    /**
     * The places a category can be moved into: null for "a main category", then every category
     * that is neither it nor inside it and leaves room for its deepest subcategory.
     *
     * @return list<int|null>
     */
    public function destinations(int $categoryId): array
    {
        return $this->worded(fn(): array => $this->tree->destinations(self::rows($this->categories->categoryTree()), [$categoryId]));
    }

    /**
     * The level and position a new category gets under $parentId (null for a main category): the
     * next level down, last among its siblings. Call inside the transaction that inserts it, after
     * lock(), so two new categories cannot take the same place.
     *
     * @return array{level:int,position:int}
     */
    public function placeForNew(?int $parentId): array
    {
        if ($parentId === null) {
            return ['level' => 1, 'position' => $this->categories->nextCategoryPosition(0)];
        }
        $parent = $this->categories->categoryById($parentId);
        if ($parent === null) {
            throw new InvalidArgumentException('The category to add it under no longer exists. Reload the page and try again.');
        }
        if ((int) $parent['level'] >= self::MAX_LEVEL) {
            throw new InvalidArgumentException('Course categories go three levels deep, so “' . (string) $parent['name'] . '” cannot hold subcategories.');
        }
        return ['level' => (int) $parent['level'] + 1, 'position' => $this->categories->nextCategoryPosition($parentId)];
    }

    /** Holds the taxonomy against other writers until the caller's transaction ends. */
    public function lock(): void
    {
        $this->categories->lockCategories();
    }

    /** Renumbers a parent's children 1..n after one of them was deleted. */
    public function closeGap(?int $parentId): void
    {
        $this->categories->compactCategorySiblings($parentId);
    }

    /**
     * Each category's height - 1 for a category with no subcategories, up to 3 - which tells the
     * tree whether a drop would push the subtree too deep.
     *
     * @param list<array<string,mixed>> $categories rows with id and parent_id, in tree order
     * @return array<int,int>
     */
    public function heights(array $categories): array
    {
        return $this->tree->heights(self::rows($categories));
    }

    /**
     * One validated write: lock, apply the change to the current tree, check the whole result and
     * persist only what moved.
     *
     * @param callable(list<array{id:int,parent:int|null}>):list<array{id:int,parent:int|null}> $change
     */
    private function rearrange(int $categoryId, int $userId, callable $change): void
    {
        $this->worded(function () use ($categoryId, $userId, $change): array {
            return $this->transactions->run(function () use ($categoryId, $userId, $change): array {
                $this->categories->lockCategories();
                $stored = $this->categories->categoryTree();
                $before = self::rows($stored);
                $after = $change($before);
                $this->tree->assertComplete(array_column($before, 'id'), $after);
                $current = [];
                foreach ($stored as $row) {
                    $current[(int) $row['id']] = [$row['parent_id'] === null ? null : (int) $row['parent_id'], (int) $row['level'], (int) $row['position']];
                }
                $changed = array_values(array_filter(
                    $this->tree->levelled($after),
                    static fn(array $row): bool => $current[$row['id']] !== [$row['parent'], $row['depth'], $row['position']]
                ));
                if ($changed === []) {
                    return [];
                }
                $from = $current[$categoryId] ?? [null, 0, 0];
                $this->categories->saveCategoryArrangement($changed);
                $to = array_values(array_filter($this->tree->levelled($after), static fn(array $row): bool => $row['id'] === $categoryId))[0];
                $this->audit->record($userId, 'course_category.moved', [
                    'category_id' => $categoryId,
                    'from_parent_id' => $from[0],
                    'from_position' => $from[2],
                    'to_parent_id' => $to['parent'],
                    'to_position' => $to['position'],
                    'level' => $to['depth'],
                ]);
                return [];
            });
        });
    }

    /**
     * @param list<array{id:int,parent:int|null}> $rows
     */
    private static function parentIn(array $rows, int $categoryId): ?int
    {
        foreach ($rows as $row) {
            if ($row['id'] === $categoryId) {
                return $row['parent'];
            }
        }
        throw new TreeMoveRefused(TreeMoveRefused::MISSING_ROW);
    }

    /**
     * @param list<array<string,mixed>> $categories
     * @return list<array{id:int,parent:int|null}>
     */
    private static function rows(array $categories): array
    {
        return array_map(static fn(array $row): array => ['id' => (int) $row['id'], 'parent' => $row['parent_id'] === null ? null : (int) $row['parent_id']], $categories);
    }

    /**
     * @template T
     * @param callable():T $operation
     * @return T
     */
    private function worded(callable $operation): mixed
    {
        try {
            return $operation();
        } catch (TreeMoveRefused $refused) {
            throw new InvalidArgumentException(self::MESSAGES[$refused->reason] ?? 'The category could not be moved.', 0, $refused);
        }
    }
}
