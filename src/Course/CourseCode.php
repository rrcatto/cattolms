declare(strict_types=1);

namespace CattoLearning\Course;

use InvalidArgumentException;

final class CourseCode
{
    /** The meta tag in a course HTML file's head that carries its code. */
    public const META_NAME = 'cattolms:course-code';
    public const MAXIMUM = 20;
    public const RULE = 'A course code is capital letters and digits, in parts joined by hyphens, such as GDN-101 (2 to 20 characters).';
    private const PATTERN = '/^[A-Z0-9]+(?:-[A-Z0-9]+)*$/';
    // Words left out of a suggested code: "An Introduction to Garden Design" suggests IGD-101.
    private const MINOR_WORDS = ['a', 'an', 'and', 'for', 'in', 'of', 'on', 'or', 'the', 'to', 'with', 'your'];

    /** What a person typed, tidied: "gdn 101" is GDN-101. Empty stays empty. */
    public static function normalise(string $input): string
    {
        $code = strtoupper(trim($input));
        $code = (string) preg_replace('/[\s_]+/', '-', $code);
        return trim((string) preg_replace('/-{2,}/', '-', $code), '-');
    }

    /** The tidied code, or why it cannot be one. */
    public static function validate(string $input): string
    {
        $code = self::normalise($input);
        if (strlen($code) < 2 || strlen($code) > self::MAXIMUM || preg_match(self::PATTERN, $code) !== 1) {
            throw new InvalidArgumentException(self::RULE . ($code === '' ? '' : ' "' . $code . '" is not one.'));
        }
        return $code;
    }

    public static function isValid(string $input): bool
    {
        $code = self::normalise($input);
        return strlen($code) >= 2 && strlen($code) <= self::MAXIMUM && preg_match(self::PATTERN, $code) === 1;
    }

    /**
     * A code to offer for a course with this title: the initials of its main words, up to four, and the first free
     * number from 101. $taken says whether a code is already used.
     *
     * @param callable(string):bool $taken
     */
    public static function suggest(string $title, callable $taken): string
    {
        $initials = '';
        foreach (preg_split('/[^\p{L}\p{N}]+/u', $title) ?: [] as $word) {
            if ($word === '' || in_array(mb_strtolower($word), self::MINOR_WORDS, true)) continue;
            $letter = strtoupper((string) iconv('UTF-8', 'ASCII//TRANSLIT//IGNORE', mb_substr($word, 0, 1)));
            if (preg_match('/^[A-Z0-9]$/', $letter) === 1) $initials .= $letter;
            if (strlen($initials) === 4) break;
        }
        $prefix = strlen($initials) >= 2 ? $initials : 'C' . $initials;
        for ($number = 101; $number < 1000; $number++) {
            if (!$taken($prefix . '-' . $number)) return $prefix . '-' . $number;
        }
        return self::generated();
    }

    /** A code for a course nobody gave one: C- and eight random characters, as the database's own default. */
    public static function generated(): string
    {
        return 'C-' . strtoupper(bin2hex(random_bytes(4)));
    }
}
