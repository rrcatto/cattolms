Description:
A course's code (owner, 2026-10-23: "Surely we need to introduce a course code instead so that small changes to the
title don't throw things off?"). The code is chosen by the course's author, such as GDN-101, and stays the same on
every site: a course package, a catalogue import and a course HTML file's <meta name="cattolms:course-code"> all name
the course by it, never by its title or slug.

A code is capital letters and digits in parts joined by hyphens, 2 to 20 characters. What a person types is tidied
first (lower case raised, spaces and underscores made hyphens), so "gdn 101" is GDN-101. A course made without one
gets a suggestion from its title's initials, or a random C- code where nobody chose (generated()).

