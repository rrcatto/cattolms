declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\AccessPeriod;
use CattoLearning\Support\Money;
use CattoLearning\Support\WasPrice;
use InvalidArgumentException;

final class CourseQuickEdit
{
    /** The units an access period is typed in, as on the Pricing tab. */
    public const UNITS = ['days', 'weeks', 'months', 'years'];

    public function __construct(
        private readonly CourseService $courses,
        private readonly CourseRepository $repository,
        private readonly TransactionManager $transactions
    ) {
    }

    /**
     * Whether a row may change the course's price: it has none yet, or its only price option is its default.
     *
     * @param array<string,mixed> $row CourseRepository::adminCourse()
     */
    public static function priceEditable(array $row): bool
    {
        $count = (int) ($row['price_option_count'] ?? 0);
        return $count === 0 || ($count === 1 && ($row['default_price_id'] ?? null) !== null);
    }

    /**
     * A row's fields: the code, the title, the category picker and, when the price may be changed here, the price as
     * typed, the was price and the access period as a number and a unit (12 months for a new price).
     *
     * @param array<string,mixed> $row CourseRepository::adminCourse()
     * @return array<string,mixed>
     */
    public function form(array $row, bool $mayPrice): array
    {
        $minor = $row['default_price_minor_units'] ?? null;
        [$value, $unit] = $minor === null ? [12, 'months'] : AccessPeriod::decompose((int) $row['default_price_access_period_seconds']);
        return [
            'code' => (string) $row['code'],
            'title' => (string) $row['title'],
            'position' => ($row['catalogue_position'] ?? null) === null ? '' : (string) (int) $row['catalogue_position'],
            'category' => $this->courses->courseCategoryPicker(($row['category_id'] ?? null) === null ? null : (int) $row['category_id']),
            'price' => [
                // Changing prices needs COURSE.PRICING.MANAGE; a course with other price options is priced on its tab.
                'shown' => $mayPrice,
                'editable' => $mayPrice && self::priceEditable($row),
                'now' => $minor === null ? '' : number_format((int) $minor / 100, 2, '.', ''),
                'was' => WasPrice::input($row['default_was_price_minor_units'] ?? null),
                'period_value' => $value,
                'period_unit' => in_array($unit, self::UNITS, true) ? $unit : 'days',
                'units' => self::UNITS,
            ],
        ];
    }

    /**
     * Saves a row: the code, title and category, and the default price when the row may change it and its price field
     * was sent. A blank price leaves a course without a price as it is.
     *
     * @param array<string,mixed> $input
     */
    public function save(int $courseId, array $input, int $userId, bool $mayPrice): void
    {
        $this->transactions->run(function () use ($courseId, $input, $userId, $mayPrice): void {
            $course = $this->repository->findById($courseId) ?? throw new InvalidArgumentException('The course does not exist.');
            $code = trim((string) ($input['code'] ?? ''));
            if ($code === '') throw new InvalidArgumentException('Give the course a code, such as GDN-101.');
            $title = trim((string) ($input['title'] ?? ''));
            $category = max(0, (int) ($input['category_id'] ?? 0));
            $changes = ['code' => $code, 'title' => $title, 'category_id' => $category];
            // The position, when the row sent one: a whole number from 1, or empty for none.
            $current = ($course['catalogue_position'] ?? null) === null ? null : (int) $course['catalogue_position'];
            if (array_key_exists('catalogue_position', $input) && CourseService::cataloguePosition($input['catalogue_position']) !== $current) {
                $changes['catalogue_position'] = $input['catalogue_position'];
            }
            if ($code !== (string) $course['code'] || $title !== (string) $course['title'] || $category !== (int) ($course['category_id'] ?? 0) || isset($changes['catalogue_position'])) {
                $this->courses->updateCourse($courseId, $changes, $userId);
            }
            if ($mayPrice && array_key_exists('price', $input)) {
                $this->savePrice($courseId, $input, $userId);
            }
        });
    }

    /** @param array<string,mixed> $input */
    private function savePrice(int $courseId, array $input, int $userId): void
    {
        $variants = $this->repository->priceVariants($courseId);
        $now = trim((string) ($input['price'] ?? ''));
        $period = ['access_period_value' => (string) ($input['access_period_value'] ?? ''), 'access_period_unit' => (string) ($input['access_period_unit'] ?? 'months')];
        if ($variants === []) {
            if ($now === '' && trim((string) ($input['was_price'] ?? '')) === '') return;
            $this->courses->createPriceVariant($courseId, ['price' => $now, 'was_price' => (string) ($input['was_price'] ?? ''), 'currency_code' => Money::platformCurrency(),
                'label' => '', 'is_active' => '1', 'is_default' => '1'] + $period, $userId);
            return;
        }
        if (count($variants) > 1 || empty($variants[0]['is_default'])) {
            throw new InvalidArgumentException('This course has other price options: change its prices on its Pricing tab.');
        }
        $existing = $variants[0];
        $wanted = ['price' => $now, 'was_price' => (string) ($input['was_price'] ?? ''), 'currency_code' => (string) $existing['currency_code'],
            'label' => (string) ($existing['label'] ?? ''), 'is_active' => !empty($existing['is_active']) ? '1' : ''] + $period;
        // Saved only when something about it changed, so the course's history names only real changes.
        $same = $now !== '' && preg_match('/^\d+(?:\.\d{1,2})?$/', str_replace([',', ' '], '', $now)) === 1
            && Money::ofMajorUnits(str_replace([',', ' '], '', $now))->minorUnits === (int) $existing['price_minor_units']
            && WasPrice::input($existing['was_price_minor_units'] ?? null) === WasPrice::input(WasPrice::fromInput($wanted['was_price'], (int) $existing['price_minor_units']))
            && AccessPeriod::fromInput($period['access_period_value'], $period['access_period_unit']) === (int) $existing['access_period_seconds'];
        if (!$same) $this->courses->updatePriceVariant($courseId, (int) $existing['id'], $wanted, $userId);
    }
}
