    public function clean(string $html): string
    {
        $html = trim($html);
        if ($html === '') {
            return '';
        }

        if (!class_exists(DOMDocument::class)) {
            throw new RuntimeException('The PHP DOM extension is required to sanitise course HTML.');
        }

        $document = new DOMDocument('1.0', 'UTF-8');
        $previous = libxml_use_internal_errors(true);
        $loaded = $document->loadHTML(
            '<?xml encoding="UTF-8"><!doctype html><html><body><div id="cl-sanitizer-root">' . $html . '</div></body></html>',
            LIBXML_HTML_NOIMPLIED | LIBXML_HTML_NODEFDTD | LIBXML_NOERROR | LIBXML_NOWARNING
        );
        libxml_clear_errors();
        libxml_use_internal_errors($previous);
        if (!$loaded) {
            throw new RuntimeException('The course HTML could not be parsed.');
        }

        $xpath = new DOMXPath($document);
        $root = $xpath->query('//*[@id="cl-sanitizer-root"]')->item(0);
        if (!$root instanceof DOMElement) {
            throw new RuntimeException('The course HTML could not be sanitised.');
        }

        $nodes = [];
        foreach ($root->getElementsByTagName('*') as $node) {
            $nodes[] = $node;
        }

        foreach (array_reverse($nodes) as $element) {
            $tag = strtolower($element->tagName);
            if (!isset(self::ALLOWED_TAGS[$tag])) {
                $this->unwrap($element);
                continue;
            }
            $this->cleanAttributes($element, $tag);
        }

        return trim($this->innerHtml($root));
    }

    private function cleanAttributes(DOMElement $element, string $tag): void
    {
        $allowed = self::GLOBAL_ATTRIBUTES;
        if ($tag === 'a') {
            $allowed += ['href' => true, 'target' => true, 'rel' => true];
        } elseif ($tag === 'img') {
            $allowed += ['src' => true, 'alt' => true, 'width' => true, 'height' => true, 'loading' => true];
        } elseif (in_array($tag, ['td', 'th'], true)) {
            $allowed += ['colspan' => true, 'rowspan' => true, 'scope' => true];
        } elseif ($tag === 'col') {
            $allowed += ['span' => true];
        } elseif ($tag === 'ol') {
            $allowed += ['start' => true, 'reversed' => true, 'type' => true];
        } elseif ($tag === 'details') {
            $allowed += ['open' => true];
        } elseif ($tag === 'input') {
            $allowed += ['type' => true, 'checked' => true, 'disabled' => true];
        } elseif ($tag === 'oembed') {
            $allowed += ['url' => true];
        }

        $remove = [];
        foreach ($element->attributes as $attribute) {
            $name = strtolower($attribute->name);
            $isDataAttribute = preg_match('/^data-[a-z0-9_-]+$/', $name) === 1;
            $isAriaAttribute = preg_match('/^aria-[a-z0-9_-]+$/', $name) === 1;
            if (
                str_starts_with($name, 'on')
                || (!isset($allowed[$name]) && !$isDataAttribute && !$isAriaAttribute)
            ) {
                $remove[] = $attribute->name;
                continue;
            }
            if (($name === 'href' || $name === 'src') && !$this->safeUrl($attribute->value, $tag === 'img')) {
                $remove[] = $attribute->name;
                continue;
            }
            if ($name === 'url' && !$this->safeUrl($attribute->value, false)) {
                $remove[] = $attribute->name;
                continue;
            }
            if ($name === 'style') {
                $safeStyle = $this->safeStyle($attribute->value);
                if ($safeStyle === '') {
                    $remove[] = $attribute->name;
                } else {
                    $element->setAttribute('style', $safeStyle);
                }
            }
        }
        foreach ($remove as $name) {
            $element->removeAttribute($name);
        }

        if ($tag === 'a' && strtolower($element->getAttribute('target')) === '_blank') {
            $element->setAttribute('rel', 'noopener noreferrer');
        }
        if ($tag === 'img' && !$element->hasAttribute('loading')) {
            $element->setAttribute('loading', 'lazy');
        }
        if ($tag === 'input') {
            if (strtolower($element->getAttribute('type')) !== 'checkbox') {
                $element->setAttribute('type', 'checkbox');
            }
            $element->setAttribute('disabled', 'disabled');
        }
    }

    private function safeStyle(string $style): string
    {
        if (
            str_contains($style, '\\')
            || preg_match('/(?:url\s*\(|expression\s*\(|javascript\s*:|@import)/i', $style) === 1
        ) {
            return '';
        }

        $safe = [];
        foreach (explode(';', $style) as $declaration) {
            if (!str_contains($declaration, ':')) {
                continue;
            }
            [$property, $value] = array_map('trim', explode(':', $declaration, 2));
            $property = strtolower($property);
            if (!isset(self::ALLOWED_STYLE_PROPERTIES[$property]) || $value === '') {
                continue;
            }
            if (preg_match('/^[a-zA-Z0-9#(),.%\-\s\"\']+$/u', $value) !== 1) {
                continue;
            }
            $safe[] = $property . ': ' . $value;
        }

        return implode('; ', $safe);
    }

    private function safeUrl(string $url, bool $image): bool
    {
        $url = trim(html_entity_decode($url, ENT_QUOTES | ENT_HTML5, 'UTF-8'));
        if ($url === '' || str_starts_with($url, '/') || str_starts_with($url, '#')) {
            return true;
        }
        if ($image && str_starts_with($url, 'data:image/')) {
            return false;
        }
        $scheme = strtolower((string) parse_url($url, PHP_URL_SCHEME));
        return in_array($scheme, $image ? ['https'] : ['http', 'https', 'mailto'], true);
    }

    private function unwrap(DOMElement $element): void
    {
        $parent = $element->parentNode;
        if (!$parent instanceof DOMNode) {
            return;
        }
        while ($element->firstChild !== null) {
            $parent->insertBefore($element->firstChild, $element);
        }
        $parent->removeChild($element);
    }

    private function innerHtml(DOMElement $element): string
    {
        $html = '';
        foreach ($element->childNodes as $child) {
            $html .= $element->ownerDocument?->saveHTML($child) ?? '';
        }
        return $html;
    }
