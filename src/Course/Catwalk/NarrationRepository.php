     * Removes the clips of slides that are no longer in the deck.
     *
     * @param list<string> $slideIds
     * @return list<string> their public ids
     */
    public function deleteMissingSlides(int $itemId, array $slideIds): array
    {
        $rows = $this->rowsForItem($itemId);
        $gone = [];
        foreach ($rows as $row) {
            if (!in_array((string) $row['slide_id'], $slideIds, true)) {
                $this->delete((int) $row['id']);
                $gone[] = (string) $row['public_id'];
            }
        }
        return $gone;
    }

