        return (int) $this->db->fetchOne(
            "SELECT COUNT(*) FROM course_landing_sections s JOIN course_landing_pages lp ON lp.id=s.landing_page_id JOIN courses c ON c.id=lp.course_id JOIN course_items ci ON ci.item_key=s.data->>'presentation'
             WHERE ci.id=:item AND s.section_type='presentation' AND s.enabled AND lp.status='published' AND c.status='published'",
            ['item' => $itemId]
        ) > 0;
    }
