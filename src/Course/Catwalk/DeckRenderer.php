<?php

/*
Generated by: Claude Code CLI

Date time: 2026/10/28 SAST

Version: 1.0.0

Description:
Draws a Presentation's slides (SlideDeck) as the markup CatWalk plays: one div.cw-deck of section.cw-slide elements,
following the engine's markup contract (DEVDOCS "Catwalk Presentation Engine - Specification", sections 5 and 6). The
words are escaped plain text, so a deck reads as one page without JavaScript and prints whole. The host's addresses
(continue, enrol, preview) go in data-cw-host-links and each slide's narration in data-cw-audio, so the engine needs
no inline script. Pictures are the deck's own: an SVG drawing inline, a PNG or JPEG as an image.

Changelog:
2026/10/28 SAST
- Created.
*/

declare(strict_types=1);

namespace CattoLearning\Course\Catwalk;

final class DeckRenderer
{
    /**
     * @param array<string,mixed> $deck The deck as stored (kind, theme, slides).
     * @param array{continue?:string,enrol?:string,preview?:string} $links Where the action buttons lead.
     * @param array<string,string> $narrations Each narrated slide's audio address, by slide id.
     */
    public function render(array $deck, string $key, string $title, array $links = [], array $narrations = [], string $language = 'en-ZA'): string
    {
        $deck = SlideDeck::normalise($deck);
        $hostLinks = array_filter($links, static fn(string $link): bool => $link !== '');
        $html = '<div class="cw-deck" tabindex="0" data-cw-key="' . self::e($key) . '" data-cw-kind="' . self::e($deck['kind']) . '" data-cw-title="' . self::e($title)
            . '" data-cw-version="1" data-cw-theme="' . self::e($deck['theme']) . '" lang="' . self::e($language) . '"'
            . ($hostLinks === [] ? '' : ' data-cw-host-links="' . self::e((string) json_encode($hostLinks, JSON_UNESCAPED_SLASHES)) . '"') . '>';
        foreach ($deck['slides'] as $slide) {
            $html .= $this->slide($slide, $narrations[(string) $slide['id']] ?? null, $links);
        }
        return $html . '</div>';
    }

    /**
     * One slide as a picture (owner, 2026-10-30: "I have to be able to see what each layout design looks like"): the
     * slide as the player shows it, drawn 800 pixels wide and shrunk by the page's CSS (`.cl-slide-thumb--small`,
     * `--medium`, `--large`), every point shown. The engine never plays it (data-cw-manual) and nothing in it can be
     * reached (inert).
     *
     * @param array<string,mixed> $slide
     */
    public function thumbnail(array $slide, string $theme, string $size = 'small'): string
    {
        $slide = SlideDeck::normaliseSlide($slide);
        $markup = $this->slide($slide, null, ['continue' => '#', 'enrol' => '#', 'preview' => '#']);
        $markup = preg_replace('/^<section class="cw-slide"/', '<section class="cw-slide cw-current"', $markup, 1) ?? $markup;
        // A picture is often inside a link of its own, and a link cannot hold another: the slide's buttons are drawn as text.
        $markup = preg_replace(['/<a class="cw-action"[^>]*>/', '#</a>#'], ['<span class="cw-action">', '</span>'], $markup) ?? $markup;
        $size = in_array($size, ['small', 'medium', 'large'], true) ? $size : 'small';
        return '<div class="cl-slide-thumb cl-slide-thumb--' . $size . '"><div class="cw-deck cw-ready" data-cw-manual data-cw-theme="' . self::e($theme === 'dark' ? 'dark' : 'light')
            . '" inert aria-hidden="true"><div class="cw-viewport">' . $markup . '</div></div></div>';
    }

    /**
     * @param array<string,mixed> $slide
     * @param array<string,string> $links
     */
    private function slide(array $slide, ?string $audio, array $links): string
    {
        $layout = (string) $slide['layout'];
        $attributes = ' data-cw-layout="' . self::e($layout) . '" data-cw-title="' . self::e((string) ($slide['title'] ?? '')) . '" data-cw-slide-id="' . self::e((string) $slide['id']) . '"';
        if (!empty($slide['chapter'])) { $attributes .= ' data-cw-chapter="' . self::e((string) $slide['chapter']) . '"'; }
        if (!empty($slide['tone'])) { $attributes .= ' data-cw-tone="' . self::e((string) $slide['tone']) . '"'; }
        if ($audio !== null) { $attributes .= ' data-cw-audio="' . self::e($audio) . '"'; }
        $body = match ($layout) {
            'title' => self::optional('p', 'cw-kicker', $slide['kicker'] ?? null) . '<h2>' . self::e((string) ($slide['heading'] ?? '')) . '</h2>' . self::optional('p', 'cw-sub', $slide['sub'] ?? null),
            'statement' => '<p class="cw-big">' . self::e((string) ($slide['text'] ?? '')) . '</p>' . self::optional('p', 'cw-source', $slide['source'] ?? null),
            'points' => '<h2>' . self::e((string) ($slide['heading'] ?? '')) . '</h2>' . self::list((array) ($slide['points'] ?? []), !empty($slide['ordered']) ? 'ol' : 'ul', '', (bool) ($slide['build'] ?? true)),
            'compare' => '<h2>' . self::e((string) ($slide['heading'] ?? '')) . '</h2><div class="cw-cols">' . implode('', array_map(static fn(array $column): string => '<div class="cw-col"><h3>' . self::e((string) $column['heading']) . '</h3>' . (isset($column['points']) ? self::list($column['points'], 'ul', '', false) : '<p>' . self::e((string) ($column['text'] ?? '')) . '</p>') . '</div>', (array) ($slide['columns'] ?? []))) . '</div>',
            'picture' => self::optional('h2', '', $slide['heading'] ?? null) . '<figure class="cw-figure">' . $this->picture((string) ($slide['picture'] ?? ''), (string) ($slide['alt'] ?? '')) . self::optional('figcaption', '', $slide['caption'] ?? null) . '</figure>',
            'number' => '<p class="cw-big">' . self::e((string) ($slide['figure'] ?? '')) . '</p><p class="cw-label">' . self::e((string) ($slide['label'] ?? '')) . '</p>' . self::optional('p', 'cw-source', $slide['source'] ?? null),
            'timeline' => '<h2>' . self::e((string) ($slide['heading'] ?? '')) . '</h2><ol class="cw-timeline">' . implode('', array_map(static fn(array $event): string => '<li class="cw-step"><b class="cw-when">' . self::e($event['when']) . '</b> ' . self::e($event['what']) . '</li>', (array) ($slide['events'] ?? []))) . '</ol>',
            'steps' => '<h2>' . self::e((string) ($slide['heading'] ?? '')) . '</h2>' . self::list((array) ($slide['steps'] ?? []), 'ol', 'cw-steps', true),
            'case' => '<h2>' . self::e((string) ($slide['heading'] ?? '')) . '</h2><div class="cw-facts"><p>' . self::e((string) ($slide['facts'] ?? '')) . '</p></div><p class="cw-question">' . self::e((string) ($slide['question'] ?? '')) . '</p><div class="cw-outcome cw-step"><p>' . self::e((string) ($slide['outcome'] ?? '')) . '</p></div>',
            'check' => '<h2>' . self::e((string) ($slide['question'] ?? '')) . '</h2><ol class="cw-options" data-cw-answer="' . (int) ($slide['answer'] ?? 0) . '">' . implode('', array_map(static fn(string $option): string => '<li>' . self::e($option) . '</li>', (array) ($slide['options'] ?? []))) . '</ol><details class="cw-explain"><summary>Show the answer</summary><p>' . self::e((string) ($slide['explanation'] ?? '')) . '</p></details>',
            'next' => '<h2>' . self::e((string) ($slide['heading'] ?? '')) . '</h2><p>' . self::e((string) ($slide['text'] ?? '')) . '</p><a class="cw-action" data-cw-action="continue" href="' . self::e($links['continue'] ?? '#') . '">' . self::e((string) (($slide['action_label'] ?? '') ?: 'Continue')) . '</a>',
            'cta' => '<h2>' . self::e((string) ($slide['heading'] ?? '')) . '</h2><p>' . self::e((string) ($slide['text'] ?? '')) . '</p><p class="cw-actions">' . implode('', array_map(static fn(string $action): string => '<a class="cw-action" data-cw-action="' . self::e($action) . '" href="' . self::e($links[$action] ?? '#') . '">' . self::e(SlideLayouts::ACTIONS[$action] ?? $action) . '</a>', (array) ($slide['actions'] ?? []))) . '</p>',
            default => '',
        };
        $notes = trim((string) ($slide['narration'] ?? ''));
        return '<section class="cw-slide"' . $attributes . '>' . $body . ($notes === '' ? '' : '<aside class="cw-notes">' . self::e($notes) . '</aside>') . '</section>';
    }

    private function picture(string $picture, string $alt): string
    {
        if (str_starts_with($picture, 'data:image/')) {
            return '<img src="' . self::e($picture) . '" alt="' . self::e($alt) . '" loading="lazy">';
        }
        // An SVG drawing is the author's own (trusted course content): kept as drawn, labelled for screen readers.
        $svg = preg_replace('/^\s*<\?xml[^>]*>\s*/', '', $picture) ?? $picture;
        return '<div class="cw-svg" role="img" aria-label="' . self::e($alt) . '">' . $svg . '</div>';
    }

    /** @param list<string> $items */
    private static function list(array $items, string $tag, string $class, bool $build): string
    {
        $html = '<' . $tag . ($class === '' ? '' : ' class="' . $class . '"') . '>';
        foreach ($items as $item) { $html .= '<li' . ($build ? ' class="cw-step"' : '') . '>' . self::e((string) $item) . '</li>'; }
        return $html . '</' . $tag . '>';
    }

    private static function optional(string $tag, string $class, mixed $text): string
    {
        $text = trim((string) (is_scalar($text) ? $text : ''));
        return $text === '' ? '' : '<' . $tag . ($class === '' ? '' : ' class="' . $class . '"') . '>' . self::e($text) . '</' . $tag . '>';
    }

    private static function e(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
}
