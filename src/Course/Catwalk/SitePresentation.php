declare(strict_types=1);

namespace CattoLearning\Course\Catwalk;

use CattoLearning\Course\CourseItemRepository;

final class SitePresentation
{
    public function __construct(
        private readonly CourseItemRepository $items,
        private readonly DeckRenderer $decks,
        private readonly Narrations $narrations
    ) {
    }

    public function ready(): bool
    {
        return $this->items->sitePresentation() !== null;
    }

    /** @return array{title:string,lead:string,html:string}|null */
    public function page(bool $signedIn): ?array
    {
        $item = $this->items->sitePresentation();
        if ($item === null) { return null; }
        $deck = (array) $item['type_config'];
        if ($signedIn) {
            foreach ((array) ($deck['slides'] ?? []) as $index => $slide) {
                if (($slide['layout'] ?? '') !== 'cta') { continue; }
                $actions = array_values(array_diff((array) ($slide['actions'] ?? []), ['register']));
                $deck['slides'][$index]['actions'] = $actions === [] ? ['courses'] : $actions;
            }
        }
        $narrations = [];
        foreach ($this->narrations->forItem((int) $item['id']) as $slide => $publicId) { $narrations[$slide] = '/narrations/' . rawurlencode($publicId); }
        $lead = SlideDeck::barText((string) ($item['description_html'] ?? ''), '');
        return [
            'title' => (string) $item['title'],
            'lead' => $lead,
            'html' => $this->decks->render($deck, (string) $item['item_key'], (string) $item['title'], [], $narrations),
        ];
    }
}
