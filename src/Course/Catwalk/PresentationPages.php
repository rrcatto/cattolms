namespace CattoLearning\Course\Catwalk;

use CattoLearning\Course\CourseItemService;
use CattoLearning\Support\ListView;
use CattoLearning\View\Artwork\IconLibrary;

final class PresentationPages
{
    /** A slide's backgrounds, as the slide page offers them: plain, the shaded colour, or the accent colour. */
    private const TONES = ['' => 'Plain', 'alt' => 'Shaded', 'accent' => 'Accent colour'];

    /** What a presentation is for, as feature cards: the icon of each. */
    private const KIND_ICONS = ['intro' => 'door-open', 'review' => 'rotate-ccw', 'overview' => 'map', 'trailer' => 'clapperboard'];
    private const KIND_NOTES = [
        'intro' => 'Opens a module, ending with Up next.',
        'review' => 'Goes over the whole course.',
        'overview' => 'What a part of the course covers.',
        'trailer' => 'For the landing page, ending with a call to action.',
    ];

    public function __construct(
        private readonly CourseItemService $items,
        private readonly Narrations $narrations,
        private readonly DeckRenderer $decks,
        private readonly IconLibrary $icons
    ) {
    }

    /**
     * Everything the presentation's page draws. The way back is where editing began (Course Content or the Course
     * Item Library), else the Course Content of the first course it is placed in.
     *
     * @param array<string,mixed> $item
     * @return array<string,mixed>
     */
    public function page(array $item, string $view, ?string $returnTo = null, string $error = ''): array
    {
        $overview = $this->overview($item, $view);
        $first = $overview['placements'][0] ?? null;
        $crumb = match (true) {
            $returnTo === '/admin/course-items' => ['href' => $returnTo, 'label' => 'Course Item Library'],
            $returnTo !== null => ['href' => $returnTo, 'label' => 'Course Content'],
            $first !== null => ['href' => '/admin/courses/' . $first['course_id'] . '/content', 'label' => 'Course Content: ' . $first['course_title']],
            default => ['href' => '/admin/course-items', 'label' => 'Course Item Library'],
        };
        return ['title' => 'Edit Course Item: Presentation', 'item' => $item, 'presentation' => $overview, 'crumb' => $crumb, 'list_error' => $error, 'load_catwalk' => true,
            'view_switch' => ListView::switcher('slides', $view, '/admin/course-items/' . (int) $item['id'])];
    }

    /**
     * The presentation's page.
     *
     * @param array<string,mixed> $item
     * @return array<string,mixed>
     */
    public function overview(array $item, string $view): array
    {
        $deck = PresentationEditor::deckOf($item);
        $id = (int) $item['id'];
        $clips = $this->narrations->forItem($id);
        $count = count($deck['slides']);
        $slides = [];
        foreach ($deck['slides'] as $index => $slide) {
            $slides[] = [
                'id' => (string) $slide['id'],
                'number' => $index + 1,
                'title' => (string) ($slide['title'] ?? ''),
                'layout_label' => SlideLayouts::LAYOUTS[(string) $slide['layout']]['label'] ?? 'Slide',
                'thumb' => $this->decks->thumbnail($slide, $deck['theme'], $view === 'grid' ? 'medium' : 'small'),
                'recorded' => isset($clips[(string) $slide['id']]),
                'scripted' => trim((string) ($slide['narration'] ?? '')) !== '',
                'is_first' => $index === 0,
                'is_last' => $index === $count - 1,
            ];
        }
        $recorded = count(array_filter($slides, static fn(array $slide): bool => $slide['recorded']));
        $checks = array_map(static fn(string $warning): array => ['ok' => false, 'text' => $warning], SlideDeck::warnings($deck));
        if ($checks === []) {
            $kind = SlideLayouts::KINDS[$deck['kind']] ?? null;
            $checks[] = ['ok' => true, 'text' => $count . ' slides' . ($kind === null ? '.' : ', which suits a ' . strtolower($kind['label']) . ' (' . $kind['slides'][0] . ' to ' . $kind['slides'][1] . ').')];
        }
        $checks[] = $recorded === $count
            ? ['ok' => true, 'text' => 'Every slide has a recording.']
            : ['ok' => false, 'text' => ($count - $recorded) . ' of ' . $count . ' slides have no recording yet. Narration is optional.'];
        $urls = [];
        foreach ($clips as $slideId => $publicId) { $urls[$slideId] = '/narrations/' . rawurlencode($publicId); }
        return [
            'deck' => $deck,
            'slides' => $slides,
            'order' => implode(',', array_column($slides, 'id')),
            'recorded' => $recorded,
            'kind_label' => SlideLayouts::KINDS[$deck['kind']]['label'] ?? 'Presentation',
            'theme_label' => SlideLayouts::THEMES[$deck['theme']] ?? 'Light',
            'checks' => $checks,
            'placements' => $this->placements($item),
            'preview_html' => $this->decks->render($deck, (string) $item['item_key'], SlideDeck::barText((string) ($item['description_html'] ?? ''), (string) $item['title']), ['continue' => '#', 'enrol' => '#', 'preview' => '#'], $urls),
        ];
    }

    /**
     * One slide's page: the row of slides to choose from (the one being edited drawn as it now stands), and the slide.
     *
     * @param array<string,mixed> $item
     * @param array<string,mixed> $slide The slide as stored, or as the form left it.
     * @param int|null $after For a new slide, the number of the slide it goes after.
     * @return array<string,mixed>
     */
    public function slidePage(array $item, array $slide, ?int $after = null): array
    {
        $deck = PresentationEditor::deckOf($item);
        $clips = $this->narrations->forItem((int) $item['id']);
        $strip = [];
        foreach ($deck['slides'] as $index => $stored) {
            $current = $after === null && (string) $stored['id'] === (string) ($slide['id'] ?? '');
            $strip[] = ['id' => (string) $stored['id'], 'number' => $index + 1, 'title' => (string) (($current ? $slide['title'] ?? '' : $stored['title'] ?? '') ?: 'Untitled'), 'current' => $current,
                'thumb' => $this->decks->thumbnail($current ? $slide : $stored, $deck['theme'], 'small')];
        }
        if ($after !== null) {
            array_splice($strip, $after, 0, [['id' => '', 'number' => $after + 1, 'title' => 'New slide', 'current' => true, 'thumb' => $this->decks->thumbnail($slide, $deck['theme'], 'small')]]);
            foreach ($strip as $index => $entry) { $strip[$index]['number'] = $index + 1; }
        }
        $layout = (string) ($slide['layout'] ?? 'points');
        $position = 0;
        foreach ($strip as $entry) { if ($entry['current']) { $position = $entry['number']; } }
        return [
            'deck' => $deck,
            'slide' => $slide,
            'strip' => $strip,
            'position' => $position,
            'slide_count' => count($strip),
            'slide_layout' => SlideLayouts::LAYOUTS[$layout] + ['name' => $layout],
            'layout_thumb' => $this->decks->thumbnail($slide, $deck['theme'], 'small'),
            // The background, chosen by the slide drawn in each (owner, 2026-10-30: see what each looks like).
            'tones' => array_map(fn(string $tone, string $label): array => ['value' => $tone, 'label' => $label, 'drawing' => $this->decks->thumbnail(array_diff_key($slide, ['tone' => true]) + ($tone === '' ? [] : ['tone' => $tone]), $deck['theme'], 'small')],
                array_keys(self::TONES), array_values(self::TONES)),
            'clip' => $clips[(string) ($slide['id'] ?? '')] ?? null,
            'slide_actions' => SlideLayouts::ACTIONS,
        ];
    }

    /**
     * One slide drawn as a deck of its own, for the Preview window: what the form now holds, saved or not.
     *
     * @param array<string,mixed> $item
     * @param array<string,mixed> $slide
     */
    public function slidePreview(array $item, array $slide): string
    {
        $deck = PresentationEditor::deckOf($item);
        $clip = $this->narrations->forItem((int) $item['id'])[(string) ($slide['id'] ?? '')] ?? null;
        return $this->decks->render(['kind' => $deck['kind'], 'theme' => $deck['theme'], 'slides' => [$slide]], 'slide-preview', SlideDeck::barText((string) ($item['description_html'] ?? ''), (string) $item['title']),
            ['continue' => '#', 'enrol' => '#', 'preview' => '#'], $clip === null ? [] : [(string) $slide['id'] => '/narrations/' . rawurlencode($clip)]);
    }

    /**
     * The layout window's choices, in groups, each layout drawn as a sample slide in the presentation's look. A call to
     * action belongs only in a trailer, so other presentations are not offered one.
     *
     * @param array{kind:string,theme:string} $deck
     * @return list<array{legend:string,items:list<array{value:string,label:string,drawing:string,note:string}>}>
     */
    public function layoutChoices(array $deck): array
    {
        $groups = [];
        foreach (SlideLayouts::GROUPS as $legend => $names) {
            $items = [];
            foreach ($names as $name) {
                if ($name === 'cta' && $deck['kind'] !== 'trailer') { continue; }
                $items[] = ['value' => $name, 'label' => SlideLayouts::LAYOUTS[$name]['label'], 'drawing' => $this->decks->thumbnail(['layout' => $name] + SlideLayouts::SAMPLES[$name], $deck['theme'], 'medium'), 'note' => SlideLayouts::LAYOUTS[$name]['use']];
            }
            if ($items !== []) { $groups[] = ['legend' => $legend, 'items' => $items]; }
        }
        return $groups;
    }

    /**
     * The details page's choices: what the presentation is for, as feature cards, and its look, drawn as its first slide.
     *
     * @param array{kind:string,theme:string,slides:list<array<string,mixed>>} $deck
     * @return array{kinds:list<array{value:string,label:string,icon:string,note:string}>,looks:list<array{value:string,label:string,drawing:string,note:string}>}
     */
    public function detailChoices(array $deck): array
    {
        $kinds = [];
        foreach (SlideLayouts::KINDS as $kind => $about) {
            $kinds[] = ['value' => $kind, 'label' => $about['label'], 'icon' => (string) $this->icons->svg(self::KIND_ICONS[$kind]), 'note' => self::KIND_NOTES[$kind] . ' ' . $about['slides'][0] . ' to ' . $about['slides'][1] . ' slides.'];
        }
        $first = $deck['slides'][0] ?? (['layout' => 'title'] + SlideLayouts::SAMPLES['title']);
        $looks = [];
        foreach (SlideLayouts::THEMES as $theme => $label) {
            $looks[] = ['value' => $theme, 'label' => $label, 'drawing' => $this->decks->thumbnail($first, $theme, 'medium'), 'note' => $theme === 'dark' ? 'Suits a trailer.' : 'Suits a lesson.'];
        }
        return ['kinds' => $kinds, 'looks' => $looks];
    }

    /**
     * Where the presentation is placed: each course, and the module it opens there.
     *
     * @param array<string,mixed> $item
     * @return list<array{course_id:int,course_title:string,module:string}>
     */
    private function placements(array $item): array
    {
        $placements = [];
        foreach ((array) ($item['course_usage'] ?? []) as $course) {
            $module = '';
            $rows = $this->items->availability((int) $course['id'], null, false);
            $sections = [];
            foreach ($rows as $row) { if ($row['node_type'] === 'section') { $sections[(int) $row['id']] = (string) $row['section_title']; } }
            foreach ($rows as $row) {
                if ((int) ($row['course_item_id'] ?? 0) !== (int) $item['id']) { continue; }
                $parent = (int) ($row['parent_node_id'] ?? 0);
                $module = $row['module_of'] !== null && isset($sections[$parent]) ? 'Module ' . $row['module_of'] . ': ' . $sections[$parent] : ($sections[$parent] ?? '');
                break;
            }
            $placements[] = ['course_id' => (int) $course['id'], 'course_title' => (string) $course['title'], 'module' => $module];
        }
        return $placements;
    }
}
