Version: 1.0.0

Description:
A Presentation's narration (owner, 2026-10-28: "I'd like to be able to narrate the slides, so please allow for recording
audio if it's possible"): a clip per slide, recorded in the browser by the Presentation's editor (MediaRecorder) or
uploaded as a file, kept in storage/course-narrations/ under its public id and filed by the slide's stable id. A new
clip replaces the slide's old one; a slide removed from the deck takes its clip with it. Who may hear a clip is decided
as for the Presentation itself: anyone where it is public (a public preview placement, a published landing page),
otherwise the course's authors and learners whose course has the placement unlocked.

