declare(strict_types=1);

namespace CattoLearning\Course\Catwalk;

use CattoLearning\Course\CourseItemService;
use CattoLearning\Course\CourseRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\Uuid;
use InvalidArgumentException;
use RuntimeException;

final class Narrations
{
    public const MOST_BYTES = 20 * 1024 * 1024;

    /** The audio a browser records or a person uploads, by what the file really is, and the extension it is kept under. */
    private const TYPES = [
        'audio/webm' => 'webm', 'video/webm' => 'webm',
        'audio/ogg' => 'ogg', 'application/ogg' => 'ogg', 'video/ogg' => 'ogg',
        'audio/mp4' => 'm4a', 'video/mp4' => 'm4a', 'audio/x-m4a' => 'm4a',
        'audio/mpeg' => 'mp3', 'audio/mp3' => 'mp3',
        'audio/wav' => 'wav', 'audio/x-wav' => 'wav', 'audio/wave' => 'wav',
    ];

    public function __construct(
        private readonly NarrationRepository $narrations,
        private readonly CourseRepository $courses,
        private readonly CourseItemService $items,
        private readonly TransactionManager $transactions,
        private readonly string $storageRoot
    ) {
    }

    /**
     * Keeps a slide's clip, replacing any it had. $path is the uploaded or recorded file; it is copied, never moved.
     *
     * @return array<string,mixed> The stored clip.
     */
    public function save(int $itemId, string $slideId, string $path, ?float $duration, int $userId): array
    {
        $item = $this->items->item($itemId);
        if ((string) $item['item_type'] !== 'slide_deck') { throw new InvalidArgumentException('Only a Presentation has narration.'); }
        $slideIds = array_map(static fn(array $slide): string => (string) ($slide['id'] ?? ''), (array) ($item['type_config']['slides'] ?? []));
        if (!in_array($slideId, $slideIds, true)) { throw new InvalidArgumentException('Save the presentation first: this slide is not in it yet.'); }
        if (!is_file($path) || filesize($path) === 0) { throw new InvalidArgumentException('The recording is empty. Record it again.'); }
        $bytes = (int) filesize($path);
        if ($bytes > self::MOST_BYTES) { throw new InvalidArgumentException('A slide\'s narration may be at most 20 MB.'); }
        $sniffed = (string) (new \finfo(FILEINFO_MIME_TYPE))->file($path);
        $extension = self::TYPES[$sniffed] ?? null;
        if ($extension === null) { throw new InvalidArgumentException('That file is not audio a browser can play: use WebM, Ogg, MP4 (M4A), MP3 or WAV.'); }
        $type = ['webm' => 'audio/webm', 'ogg' => 'audio/ogg', 'm4a' => 'audio/mp4', 'mp3' => 'audio/mpeg', 'wav' => 'audio/wav'][$extension];
        $publicId = Uuid::v4();
        $directory = $this->directory();
        $target = $directory . '/' . $publicId . '.' . $extension;
        if (!copy($path, $target)) { throw new RuntimeException('The narration could not be kept.'); }
        $old = null;
        try {
            $this->transactions->run(function () use ($itemId, $slideId, $publicId, $type, $bytes, $target, $duration, $userId, &$old): void {
                $old = $this->narrations->forSlide($itemId, $slideId);
                if ($old !== null) { $this->narrations->delete((int) $old['id']); }
                $this->narrations->insert($publicId, $itemId, $slideId, $type, $bytes, (string) hash_file('sha256', $target), $duration !== null && $duration >= 0 ? round($duration, 2) : null, $userId);
            });
        } catch (\Throwable $exception) {
            @unlink($target);
            throw $exception;
        }
        if ($old !== null) { $this->removeFile((string) $old['public_id']); }
        return ['public_id' => $publicId, 'slide_id' => $slideId, 'content_type' => $type, 'byte_size' => $bytes];
    }

    public function remove(int $itemId, string $slideId): void
    {
        $old = $this->narrations->forSlide($itemId, $slideId);
        if ($old === null) { return; }
        $this->narrations->delete((int) $old['id']);
        $this->removeFile((string) $old['public_id']);
    }

    /** After a Presentation is saved: the clips of slides it no longer has go too. */
    public function keepOnly(int $itemId): void
    {
        $item = $this->items->item($itemId);
        $slideIds = array_map(static fn(array $slide): string => (string) ($slide['id'] ?? ''), (array) ($item['type_config']['slides'] ?? []));
        foreach ($this->narrations->deleteMissingSlides($itemId, $slideIds) as $publicId) { $this->removeFile($publicId); }
    }

    /** @return array<string,string> Each narrated slide's clip, public id by slide id. */
    public function forItem(int $itemId): array
    {
        return $this->narrations->forItem($itemId);
    }

    /** @return list<array<string,mixed>> */
    public function rowsForItem(int $itemId): array
    {
        return $this->narrations->rowsForItem($itemId);
    }

    /**
     * A clip and its file, when this person may hear it.
     *
     * @return array{path:string,content_type:string,public_id:string}|null
     */
    public function playable(string $publicId, ?int $userId, bool $administrator): ?array
    {
        $clip = $this->narrations->byPublicId($publicId);
        if ($clip === null) { return null; }
        $path = $this->path($publicId, (string) $clip['content_type']);
        if (!is_file($path) || !$this->mayHear((int) $clip['course_item_id'], $userId, $administrator)) { return null; }
        return ['path' => $path, 'content_type' => (string) $clip['content_type'], 'public_id' => $publicId];
    }

    /** The file a clip is kept in. */
    public function path(string $publicId, string $contentType): string
    {
        $extension = self::TYPES[$contentType] ?? 'webm';
        return $this->storageRoot . '/course-narrations/' . $publicId . '.' . $extension;
    }

    private function mayHear(int $itemId, ?int $userId, bool $administrator): bool
    {
        if ($administrator || $this->narrations->onPublishedLandingPage($itemId)) { return true; }
        foreach ($this->narrations->contexts($itemId) as $context) {
            if ((bool) $context['public_preview'] && (string) $context['status'] === 'published') { return true; }
            if ($userId === null) { continue; }
            $courseId = (int) $context['course_id'];
            if ($this->courses->userCanManageCourse($courseId, $userId)) { return true; }
            $enrolment = $this->courses->enrolment($userId, $courseId);
            if ($enrolment === null || !in_array($enrolment['status'], ['active', 'completed'], true) || empty($enrolment['started_at']) || !empty($enrolment['access_removed_at'])) { continue; }
            if (!empty($enrolment['expires_at']) && strtotime((string) $enrolment['expires_at']) <= time()) { continue; }
            foreach ($this->items->availability($courseId, (string) $enrolment['started_at'], false) as $node) {
                if ((int) $node['id'] === (int) $context['node_id'] && !$node['is_locked']) { return true; }
            }
        }
        return false;
    }

    private function directory(): string
    {
        $directory = $this->storageRoot . '/course-narrations';
        if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) { throw new RuntimeException('The narration folder could not be made.'); }
        return $directory;
    }

    /**
     * The recordings' files of a Presentation that was deleted (its rows went with it): the public ids read before.
     *
     * @param list<string> $publicIds
     */
    public function removeFiles(array $publicIds): void
    {
        foreach ($publicIds as $publicId) { if (preg_match('/^[0-9a-f-]{36}$/', $publicId) === 1) { $this->removeFile($publicId); } }
    }

    private function removeFile(string $publicId): void
    {
        foreach (array_unique(self::TYPES) as $extension) {
            $file = $this->storageRoot . '/course-narrations/' . $publicId . '.' . $extension;
            if (is_file($file)) { @unlink($file); }
        }
    }
}
