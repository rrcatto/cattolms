declare(strict_types=1);

namespace CattoLearning\Course\Catwalk;

use InvalidArgumentException;

final class SlideDeck
{
    /** A picture is an SVG drawing or a PNG or JPEG kept in the deck, so the deck travels whole. */
    public const PICTURE_LIMIT_BYTES = 1500000;

    /** A Presentation's description: one line in the player's top bar (owner, 2026-10-30, decision A). */
    public const DESCRIPTION_LIMIT = 100;

    /**
     * A Presentation's description as stored: plain text on one line, at most DESCRIPTION_LIMIT characters.
     */
    public static function description(string $text): string
    {
        $plain = trim((string) preg_replace('/\s+/u', ' ', html_entity_decode(strip_tags($text), ENT_QUOTES | ENT_HTML5, 'UTF-8')));
        $length = mb_strlen($plain);
        if ($length > self::DESCRIPTION_LIMIT) {
            throw new InvalidArgumentException('A presentation\'s description is one line of up to ' . self::DESCRIPTION_LIMIT . ' characters. This one has ' . $length . '.');
        }
        return $plain;
    }

    /**
     * What the player's top bar shows under the page's heading: the description, so the title is not printed twice,
     * or the title while there is no description.
     */
    public static function barText(string $description, string $title): string
    {
        $plain = trim((string) preg_replace('/\s+/u', ' ', html_entity_decode(strip_tags($description), ENT_QUOTES | ENT_HTML5, 'UTF-8')));
        return $plain !== '' ? $plain : $title;
    }

    private function __construct()
    {
    }

    public static function newSlideId(): string
    {
        return bin2hex(random_bytes(6));
    }

    /**
     * The deck as stored, from what an editor posted or a package held, shaped but not judged: unknown fields are
     * dropped, lines are split, and every slide keeps or gets its id.
     *
     * @param array<string,mixed> $deck
     * @return array{kind:string,theme:string,slides:list<array<string,mixed>>}
     */
    public static function normalise(array $deck): array
    {
        $kind = (string) ($deck['kind'] ?? 'intro');
        $theme = (string) ($deck['theme'] ?? ($kind === 'trailer' ? 'dark' : 'light'));
        $slides = [];
        foreach (array_values(is_array($deck['slides'] ?? null) ? $deck['slides'] : []) as $raw) {
            if (is_array($raw)) { $slides[] = self::normaliseSlide($raw); }
        }
        return ['kind' => $kind, 'theme' => $theme, 'slides' => $slides];
    }

    /**
     * @param array<string,mixed> $raw
     * @return array<string,mixed>
     */
    public static function normaliseSlide(array $raw): array
    {
        $layout = (string) ($raw['layout'] ?? 'points');
        $id = strtolower(trim((string) ($raw['id'] ?? '')));
        $slide = ['id' => preg_match('/^[a-z0-9]{6,32}$/', $id) === 1 ? $id : self::newSlideId(), 'layout' => $layout];
        foreach (SlideLayouts::COMMON as $field) {
            $value = trim((string) ($raw[$field] ?? ''));
            if ($value !== '') { $slide[$field] = $value; }
        }
        foreach (SlideLayouts::LAYOUTS[$layout]['fields'] ?? [] as $name => $field) {
            $value = self::field($field, $raw[$name] ?? null);
            if ($value !== null) { $slide[$name] = $value; }
        }
        return $slide;
    }

    /**
     * @param array<string,mixed> $field
     */
    private static function field(array $field, mixed $value): mixed
    {
        return match ($field['kind']) {
            'text', 'long' => ($text = trim(str_replace("\r", '', (string) (is_scalar($value) ? $value : '')))) === '' ? null : $text,
            'lines' => ($lines = self::lines($value)) === [] ? null : $lines,
            'events' => ($events = self::events($value)) === [] ? null : $events,
            'columns' => self::columns($value),
            'answer' => is_numeric($value) ? (int) $value : null,
            'flag' => $value === null ? (bool) ($field['default'] ?? false) : filter_var($value, FILTER_VALIDATE_BOOLEAN),
            'actions' => array_values(array_unique(array_filter(array_map('strval', is_array($value) ? $value : []), static fn(string $action): bool => isset(SlideLayouts::ACTIONS[$action])))),
            'picture' => ($picture = trim((string) (is_string($value) ? $value : ''))) === '' ? null : $picture,
            default => null,
        };
    }

    /** @return list<string> */
    private static function lines(mixed $value): array
    {
        $items = is_array($value) ? $value : (preg_split('/\R/', (string) (is_scalar($value) ? $value : '')) ?: []);
        return array_values(array_filter(array_map(static fn(mixed $line): string => trim((string) (is_scalar($line) ? $line : '')), $items), static fn(string $line): bool => $line !== ''));
    }

    /** @return list<array{when:string,what:string}> */
    private static function events(mixed $value): array
    {
        $events = [];
        if (is_array($value)) {
            foreach ($value as $event) {
                if (is_array($event)) { $events[] = ['when' => trim((string) ($event['when'] ?? '')), 'what' => trim((string) ($event['what'] ?? ''))]; }
            }
        } else {
            foreach (self::lines($value) as $line) {
                [$when, $what] = array_pad(explode('|', $line, 2), 2, '');
                $events[] = ['when' => trim($when), 'what' => trim($what)];
            }
        }
        return array_values(array_filter($events, static fn(array $event): bool => $event['when'] !== '' || $event['what'] !== ''));
    }

    /** @return list<array<string,mixed>> */
    private static function columns(mixed $value): array
    {
        $columns = [];
        foreach (array_slice(array_values(is_array($value) ? $value : []), 0, 2) as $column) {
            if (!is_array($column)) { continue; }
            $entry = ['heading' => trim((string) ($column['heading'] ?? ''))];
            $points = self::lines($column['points'] ?? []);
            $text = trim((string) ($column['text'] ?? ''));
            if ($points !== []) { $entry['points'] = $points; } elseif ($text !== '') { $entry['text'] = $text; }
            $columns[] = $entry;
        }
        return $columns;
    }

    /**
     * The deck, normalised, or the first thing CatWalk cannot play, naming its slide.
     *
     * @param array<string,mixed> $deck
     * @return array{kind:string,theme:string,slides:list<array<string,mixed>>}
     */
    public static function validate(array $deck): array
    {
        $deck = self::normalise($deck);
        if (!isset(SlideLayouts::KINDS[$deck['kind']])) { throw new InvalidArgumentException('Choose what the presentation is for: a module opening, a review, an overview or a trailer.'); }
        if (!isset(SlideLayouts::THEMES[$deck['theme']])) { throw new InvalidArgumentException('Choose a light or a dark presentation.'); }
        $count = count($deck['slides']);
        if ($count === 0) { throw new InvalidArgumentException('A presentation needs at least one slide.'); }
        if ($count > SlideLayouts::MAX_SLIDES) { throw new InvalidArgumentException('A presentation may have at most ' . SlideLayouts::MAX_SLIDES . ' slides. This one has ' . $count . '.'); }
        $ids = [];
        foreach ($deck['slides'] as $index => $slide) {
            $where = 'Slide ' . ($index + 1);
            $layout = (string) $slide['layout'];
            if (!isset(SlideLayouts::LAYOUTS[$layout])) { throw new InvalidArgumentException($where . ': "' . $layout . '" is not one of the layouts.'); }
            $where .= ' (' . SlideLayouts::LAYOUTS[$layout]['label'] . ')';
            if (isset($ids[$slide['id']])) { throw new InvalidArgumentException($where . ' has the same id as slide ' . $ids[$slide['id']] . '.'); }
            $ids[$slide['id']] = $index + 1;
            $title = (string) ($slide['title'] ?? '');
            if ($title === '') { throw new InvalidArgumentException($where . ' needs a short title, used in the contents list.'); }
            if (mb_strlen($title) > 40) { throw new InvalidArgumentException($where . ': the title may be at most 40 characters.'); }
            if (isset($slide['tone']) && !in_array($slide['tone'], SlideLayouts::TONES, true)) { throw new InvalidArgumentException($where . ': the background is base, alt or accent.'); }
            foreach (['title', 'chapter', 'narration'] as $field) { self::plain($where, $field, (string) ($slide[$field] ?? '')); }
            if (mb_strlen((string) ($slide['narration'] ?? '')) > 2000) { throw new InvalidArgumentException($where . ': the narration may be at most 2,000 characters.'); }
            foreach (SlideLayouts::LAYOUTS[$layout]['fields'] as $name => $field) { self::checkField($where, $name, $field, $slide[$name] ?? null); }
            if ($layout === 'check' && (!is_int($slide['answer'] ?? null) || $slide['answer'] < 0 || $slide['answer'] >= count($slide['options'] ?? []))) {
                throw new InvalidArgumentException($where . ': choose which option is right.');
            }
            if ($layout === 'cta' && ($slide['actions'] ?? []) === []) { throw new InvalidArgumentException($where . ': choose at least one button.'); }
            $last = $index === $count - 1;
            if ($layout === 'cta' && $deck['kind'] !== 'trailer') { throw new InvalidArgumentException($where . ': a call to action belongs only in a trailer.'); }
            if (in_array($layout, ['next', 'cta'], true) && !$last) { throw new InvalidArgumentException($where . ': an Up next or call to action slide comes last.'); }
        }
        if ($deck['kind'] === 'trailer' && $deck['slides'][$count - 1]['layout'] !== 'cta') { throw new InvalidArgumentException('A trailer ends with a call to action slide.'); }
        return $deck;
    }

    /**
     * @param array<string,mixed> $field
     */
    private static function checkField(string $where, string $name, array $field, mixed $value): void
    {
        $label = strtolower((string) $field['label']);
        $required = (bool) ($field['required'] ?? false);
        switch ($field['kind']) {
            case 'text':
            case 'long':
                $text = (string) ($value ?? '');
                if ($required && $text === '') { throw new InvalidArgumentException($where . ' needs ' . self::article($label) . '.'); }
                if (isset($field['max']) && mb_strlen($text) > $field['max']) { throw new InvalidArgumentException($where . ': the ' . $label . ' may be at most ' . $field['max'] . ' characters.'); }
                self::plain($where, $label, $text);
                return;
            case 'lines':
                $lines = is_array($value) ? $value : [];
                if ($required && count($lines) < (int) ($field['min'] ?? 1)) { throw new InvalidArgumentException($where . ' needs at least ' . ($field['min'] ?? 1) . ' ' . self::plural($name) . '.'); }
                if (isset($field['most']) && count($lines) > $field['most']) { throw new InvalidArgumentException($where . ' may have at most ' . $field['most'] . ' ' . self::plural($name) . '.'); }
                foreach ($lines as $line) {
                    if (isset($field['max']) && mb_strlen((string) $line) > $field['max']) { throw new InvalidArgumentException($where . ': each line may be at most ' . $field['max'] . ' characters.'); }
                    self::plain($where, $label, (string) $line);
                }
                if ($name === 'options' && count(array_unique(array_map('mb_strtolower', $lines))) !== count($lines)) { throw new InvalidArgumentException($where . ': two options are the same.'); }
                return;
            case 'events':
                $events = is_array($value) ? $value : [];
                if (count($events) < (int) $field['min']) { throw new InvalidArgumentException($where . ' needs at least ' . $field['min'] . ' events, one per line: when | what.'); }
                if (count($events) > $field['most']) { throw new InvalidArgumentException($where . ' may have at most ' . $field['most'] . ' events.'); }
                foreach ($events as $event) {
                    if ($event['when'] === '' || $event['what'] === '') { throw new InvalidArgumentException($where . ': every event needs when and what, written when | what.'); }
                    if (mb_strlen($event['when']) > 40 || mb_strlen($event['what']) > 200) { throw new InvalidArgumentException($where . ': an event\'s when may be 40 characters and its what 200.'); }
                    self::plain($where, 'events', $event['when'] . $event['what']);
                }
                return;
            case 'columns':
                $columns = is_array($value) ? $value : [];
                if (count($columns) !== 2) { throw new InvalidArgumentException($where . ' needs exactly two columns.'); }
                foreach ($columns as $number => $column) {
                    $which = $number === 0 ? 'the first column' : 'the second column';
                    if ($column['heading'] === '') { throw new InvalidArgumentException($where . ': ' . $which . ' needs a heading.'); }
                    if (!isset($column['points']) && !isset($column['text'])) { throw new InvalidArgumentException($where . ': ' . $which . ' needs points or a line of text.'); }
                    if (count($column['points'] ?? []) > 4) { throw new InvalidArgumentException($where . ': ' . $which . ' may have at most 4 points.'); }
                    self::plain($where, 'columns', $column['heading'] . implode('', $column['points'] ?? []) . ($column['text'] ?? ''));
                }
                return;
            case 'picture':
                $picture = (string) ($value ?? '');
                if ($required && $picture === '') { throw new InvalidArgumentException($where . ' needs a picture.'); }
                if (strlen($picture) > self::PICTURE_LIMIT_BYTES) { throw new InvalidArgumentException($where . ': the picture is larger than 1.5 MB.'); }
                if (!self::isPicture($picture)) { throw new InvalidArgumentException($where . ': the picture must be an SVG drawing, a PNG or a JPEG.'); }
                return;
            default:
                return;
        }
    }

    /** An SVG drawing, or a PNG or JPEG as a data address. */
    public static function isPicture(string $picture): bool
    {
        return preg_match('/^\s*(<\?xml[^>]*>\s*)?<svg[\s>]/i', $picture) === 1 || preg_match('#^data:image/(png|jpeg);base64,[A-Za-z0-9+/=\s]+$#', $picture) === 1;
    }

    private static function plain(string $where, string $label, string $text): void
    {
        if (str_contains($text, '<') || str_contains($text, '>')) { throw new InvalidArgumentException($where . ': the ' . $label . ' is plain text, without < or >.'); }
    }

    private static function article(string $label): string
    {
        return (preg_match('/^(the|what|why|a |an )/', $label) === 1 ? '' : (preg_match('/^[aeiou]/', $label) === 1 ? 'an ' : 'a ')) . $label;
    }

    private static function plural(string $name): string
    {
        return $name === 'points' ? 'points' : ($name === 'steps' ? 'steps' : 'options');
    }

    /**
     * The specification's guidance a deck misses: never a reason to refuse it.
     *
     * @param array{kind:string,theme:string,slides:list<array<string,mixed>>} $deck
     * @return list<string>
     */
    public static function warnings(array $deck): array
    {
        $warnings = [];
        $slides = $deck['slides'];
        $kind = SlideLayouts::KINDS[$deck['kind']] ?? null;
        if ($kind !== null && (count($slides) < $kind['slides'][0] || count($slides) > $kind['slides'][1])) {
            $warnings[] = 'A ' . strtolower($kind['label']) . ' usually has ' . $kind['slides'][0] . ' to ' . $kind['slides'][1] . ' slides. This one has ' . count($slides) . '.';
        }
        $layouts = array_column($slides, 'layout');
        if ($deck['kind'] === 'intro') {
            if (!in_array('check', $layouts, true)) { $warnings[] = 'A module opening has at least one quick question.'; }
            if ($layouts !== [] && end($layouts) !== 'next') { $warnings[] = 'A module opening ends with an Up next slide that says what to watch or look for.'; }
        }
        $run = 0;
        foreach ($slides as $index => $slide) {
            $where = 'Slide ' . ($index + 1);
            $run = $slide['layout'] === 'points' ? $run + 1 : 0;
            if ($run === 3) { $warnings[] = $where . ' is the third Points slide in a row: mix in a number, statement, picture or case.'; }
            $cap = $slide['layout'] === 'case' ? 90 : 35;
            $words = self::visibleWords($slide);
            if ($words > $cap) { $warnings[] = $where . ' shows ' . $words . ' words: up to ' . $cap . ' is right.'; }
            foreach (SlideLayouts::LAYOUTS[$slide['layout']]['fields'] ?? [] as $name => $field) {
                if (!isset($field['words'])) { continue; }
                foreach ((array) ($slide[$name] ?? []) as $text) {
                    if (is_string($text) && self::words($text) > $field['words']) { $warnings[] = $where . ': "' . mb_strimwidth($text, 0, 40, '...') . '" is longer than ' . $field['words'] . ' words.'; break; }
                }
            }
        }
        return $warnings;
    }

    /** @param array<string,mixed> $slide */
    public static function visibleWords(array $slide): int
    {
        $visible = [];
        foreach (['kicker', 'heading', 'sub', 'text', 'source', 'figure', 'label', 'facts', 'question', 'caption'] as $field) { $visible[] = (string) ($slide[$field] ?? ''); }
        foreach (['points', 'steps', 'options'] as $field) { foreach ((array) ($slide[$field] ?? []) as $line) { $visible[] = (string) $line; } }
        foreach ((array) ($slide['events'] ?? []) as $event) { $visible[] = $event['when'] . ' ' . $event['what']; }
        foreach ((array) ($slide['columns'] ?? []) as $column) { $visible[] = $column['heading'] . ' ' . implode(' ', $column['points'] ?? []) . ' ' . ($column['text'] ?? ''); }
        return array_sum(array_map(self::words(...), $visible));
    }

    private static function words(string $text): int
    {
        return count(preg_split('/\s+/', trim($text), -1, PREG_SPLIT_NO_EMPTY) ?: []);
    }

    /**
     * A presentation's running time when nobody gave one: about 25 seconds a slide.
     *
     * @param array{slides:list<array<string,mixed>>} $deck
     */
    public static function estimatedMinutes(array $deck): int
    {
        return max(1, (int) ceil(count($deck['slides']) * 25 / 60));
    }
}
