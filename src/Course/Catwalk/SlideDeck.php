Description:
A Presentation's slides as data (owner, 2026-10-28, decision 7A): what a slide_deck Course Item keeps in its type_config
(kind, theme and the slides) and the rules a deck must keep to be saved. Every slide is a layout from SlideLayouts with
plain text in that layout's fields only, and a stable id that its narration is filed under, so adding, moving or
removing slides never mixes up their recordings. normalise() shapes what an editor or a package sent without judging
it, validate() refuses what CatWalk cannot play, naming the slide, and warnings() gives the specification's guidance
(counts and word limits), which never blocks a save.

