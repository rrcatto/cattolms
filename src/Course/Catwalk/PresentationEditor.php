Date time: 2026/10/30 SAST

Version: 1.0.0

Description:
A Presentation changed one part at a time (owner, 2026-10-30, the approved mockup: "Each component needs to be edited
and saved separately"): one slide saved on its own, a slide added after another, copied or deleted (its recording
with it), the slides put in a new order by dragging or by the ⋯ menu, a slide's narration script saved on its own, and
the presentation's details. Each change locks the item's row, reads the stored deck, changes that one part and saves
the whole deck only when SlideDeck::validate accepts it; a refused change writes nothing. A drag sends the order the
page showed, and a different stored order is refused rather than guessed at.

