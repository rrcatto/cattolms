declare(strict_types=1);

namespace CattoLearning\Course\Catwalk;

use CattoLearning\Course\CourseItemRepository;
use CattoLearning\Course\CourseItemService;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\TreeArrangement;
use CattoLearning\Support\TreeMoveRefused;
use InvalidArgumentException;

final class PresentationEditor
{
    public const STALE = 'The slides were changed elsewhere since this page was loaded. The saved order is shown.';

    public function __construct(
        private readonly CourseItemService $items,
        private readonly CourseItemRepository $records,
        private readonly Narrations $narrations,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit
    ) {
    }

    /**
     * The Presentation's deck as stored.
     *
     * @param array<string,mixed> $item
     * @return array{kind:string,theme:string,slides:list<array<string,mixed>>}
     */
    public static function deckOf(array $item): array
    {
        if ((string) ($item['item_type'] ?? '') !== 'slide_deck') { throw new InvalidArgumentException('That Course Item is not a presentation.'); }
        return SlideDeck::normalise(is_array($item['type_config'] ?? null) ? $item['type_config'] : []);
    }

    /**
     * A slide as its form posts it, in the layout it names, keeping its id and its narration script (saved apart).
     *
     * @param array<string,mixed> $input The slide's fields (slide[...]).
     * @param array<string,mixed>|null $before The stored slide, for its id and script.
     * @return array<string,mixed>
     */
    public static function slideFrom(array $input, ?array $before): array
    {
        $raw = $input;
        $raw['id'] = (string) ($before['id'] ?? SlideDeck::newSlideId());
        if ($before !== null && !array_key_exists('narration', $input)) { $raw['narration'] = (string) ($before['narration'] ?? ''); }
        if (!isset(SlideLayouts::LAYOUTS[(string) ($raw['layout'] ?? '')])) { $raw['layout'] = (string) ($before['layout'] ?? 'points'); }
        return SlideDeck::normaliseSlide($raw);
    }

    /**
     * A slide in another layout, unsaved: what both layouts share stays, the rest is left out (owner, 2026-10-30, the
     * mockup's layout window). A list of points becomes a list of steps and back.
     *
     * @param array<string,mixed> $slide
     * @return array<string,mixed>
     */
    public static function inLayout(array $slide, string $layout): array
    {
        if (!isset(SlideLayouts::LAYOUTS[$layout])) { throw new InvalidArgumentException('Choose one of the layouts.'); }
        $from = (string) ($slide['layout'] ?? 'points');
        if ($from === 'points' && $layout === 'steps' && isset($slide['points'])) { $slide['steps'] = $slide['points']; }
        if ($from === 'steps' && $layout === 'points' && isset($slide['steps'])) { $slide['points'] = $slide['steps']; }
        $slide['layout'] = $layout;
        return SlideDeck::normaliseSlide($slide);
    }

    /**
     * What changing a slide's layout keeps and leaves out, in the words the layout window shows.
     *
     * @param array<string,mixed> $slide
     * @return array{kept:list<string>,dropped:list<string>}
     */
    public static function layoutChange(array $slide, string $layout): array
    {
        $from = (string) ($slide['layout'] ?? 'points');
        $before = SlideLayouts::LAYOUTS[$from]['fields'] ?? [];
        $after = SlideLayouts::LAYOUTS[$layout]['fields'] ?? [];
        $kept = []; $dropped = [];
        foreach ($before as $name => $field) {
            if (!array_key_exists($name, $slide)) { continue; }
            if (isset($after[$name]) || ($name === 'points' && $layout === 'steps') || ($name === 'steps' && $layout === 'points')) { $kept[] = (string) $field['label']; }
            else { $dropped[] = (string) $field['label']; }
        }
        return ['kept' => $kept, 'dropped' => $dropped];
    }

    /** @param array<string,mixed> $input */
    public function saveSlide(int $itemId, string $slideId, array $input, int $userId): void
    {
        $this->change($itemId, $userId, 'presentation.slide_saved', function (array $deck) use ($slideId, $input): array {
            $at = self::indexOf($deck, $slideId);
            $deck['slides'][$at] = self::slideFrom($input, $deck['slides'][$at]);
            return [$deck, ['slide_id' => $slideId]];
        });
    }

    /**
     * A new slide, placed after the slide numbered $after (0 puts it first).
     *
     * @param array<string,mixed> $input
     */
    public function addSlide(int $itemId, int $after, array $input, int $userId): string
    {
        $made = '';
        $this->change($itemId, $userId, 'presentation.slide_added', function (array $deck) use ($after, $input, &$made): array {
            if ($after < 0 || $after > count($deck['slides'])) { throw new InvalidArgumentException('Choose where the new slide goes.'); }
            $slide = self::slideFrom($input, null);
            $made = (string) $slide['id'];
            array_splice($deck['slides'], $after, 0, [$slide]);
            return [$deck, ['slide_id' => $made, 'position' => $after + 1]];
        });
        return $made;
    }

    /** A copy of a slide straight after it, under a new id and without its recording. */
    public function duplicate(int $itemId, string $slideId, int $userId): string
    {
        $made = '';
        $this->change($itemId, $userId, 'presentation.slide_copied', function (array $deck) use ($slideId, &$made): array {
            $at = self::indexOf($deck, $slideId);
            $copy = $deck['slides'][$at];
            $copy['id'] = SlideDeck::newSlideId();
            $copy['title'] = mb_substr(mb_substr((string) ($copy['title'] ?? 'Slide'), 0, 33) . ' (copy)', 0, 40);
            $made = (string) $copy['id'];
            array_splice($deck['slides'], $at + 1, 0, [$copy]);
            return [$deck, ['slide_id' => $made, 'copied_from' => $slideId]];
        });
        return $made;
    }

    /** A slide deleted, with its recording. A presentation keeps at least one slide. */
    public function delete(int $itemId, string $slideId, int $userId): void
    {
        $this->change($itemId, $userId, 'presentation.slide_deleted', function (array $deck) use ($slideId): array {
            $at = self::indexOf($deck, $slideId);
            if (count($deck['slides']) < 2) { throw new InvalidArgumentException('A presentation keeps at least one slide.'); }
            array_splice($deck['slides'], $at, 1);
            return [$deck, ['slide_id' => $slideId]];
        });
        $this->narrations->remove($itemId, $slideId);
    }

    /** The ⋯ menu and the keyboard: top, up, down or bottom. */
    public function step(int $itemId, string $slideId, string $direction, int $userId): void
    {
        if (!in_array($direction, ['top', 'up', 'down', 'bottom'], true)) { throw new InvalidArgumentException('Choose a valid move.'); }
        $this->reorder($itemId, $slideId, null, $userId, static fn(TreeArrangement $tree, array $rows, int $moving): array => $tree->move($rows, [$moving], $direction));
    }

    /**
     * A drag: the slide goes to $index among the others. $shown is the order the page showed.
     *
     * @param list<string>|null $shown
     */
    public function arrange(int $itemId, string $slideId, int $index, ?array $shown, int $userId): void
    {
        $this->reorder($itemId, $slideId, $shown, $userId, static fn(TreeArrangement $tree, array $rows, int $moving): array => $tree->place($rows, [$moving], null, $index));
    }

    /** A slide's narration script, which learners can read as its transcript, saved on its own. */
    public function saveScript(int $itemId, string $slideId, string $script, int $userId): void
    {
        $this->change($itemId, $userId, 'presentation.script_saved', function (array $deck) use ($slideId, $script): array {
            $at = self::indexOf($deck, $slideId);
            $text = trim(str_replace("\r", '', $script));
            if ($text === '') { unset($deck['slides'][$at]['narration']); } else { $deck['slides'][$at]['narration'] = $text; }
            return [$deck, ['slide_id' => $slideId]];
        });
    }

    /**
     * The presentation's details: its name, title, description, key, time to study, what it is for and its look. The
     * slides are not changed.
     *
     * @param array<string,mixed> $input
     */
    public function saveDetails(int $itemId, array $input, int $userId): void
    {
        $item = $this->items->item($itemId);
        $deck = self::deckOf($item);
        $deck['kind'] = (string) ($input['deck_kind'] ?? $deck['kind']);
        $deck['theme'] = (string) ($input['deck_theme'] ?? $deck['theme']);
        $fields = array_intersect_key($input, array_flip(['name', 'title', 'description_html', 'item_key', 'estimated_minutes']));
        $this->items->update($itemId, ['type_config' => $deck] + $fields + $item, $userId);
    }

    /**
     * @param list<string>|null $shown
     * @param callable(TreeArrangement,list<array{id:int,parent:null}>,int):list<array<string,mixed>> $move
     */
    private function reorder(int $itemId, string $slideId, ?array $shown, int $userId, callable $move): void
    {
        $this->change($itemId, $userId, 'presentation.slides_reordered', function (array $deck) use ($slideId, $shown, $move): array {
            $ids = array_map(static fn(array $slide): string => (string) $slide['id'], $deck['slides']);
            if ($shown !== null && $shown !== $ids) { throw new InvalidArgumentException(self::STALE); }
            $from = self::indexOf($deck, $slideId);
            // TreeArrangement orders whole numbers: each slide is its place in the stored order, counted from 1.
            $rows = array_map(static fn(int $n): array => ['id' => $n, 'parent' => null], range(1, count($ids)));
            try {
                $moved = array_map(static fn(array $row): int => (int) $row['id'], $move(new TreeArrangement(1), $rows, $from + 1));
            } catch (TreeMoveRefused $refused) {
                throw new InvalidArgumentException($refused->reason === TreeMoveRefused::BAD_POSITION ? 'That is not a place among the slides.' : 'That move is not possible.');
            }
            $deck['slides'] = array_map(static fn(int $n): array => $deck['slides'][$n - 1], $moved);
            $to = (int) array_search($from + 1, $moved, true);
            return [$deck, ['slide_id' => $slideId, 'from' => $from + 1, 'to' => $to + 1]];
        });
    }

    /**
     * Locks the item, changes its stored deck and saves it once it validates.
     *
     * @param callable(array{kind:string,theme:string,slides:list<array<string,mixed>>}):array{0:array<string,mixed>,1:array<string,mixed>} $change
     */
    private function change(int $itemId, int $userId, string $event, callable $change): void
    {
        $this->transactions->run(function () use ($itemId, $userId, $event, $change): void {
            $this->records->lockItem($itemId);
            $deck = self::deckOf($this->items->item($itemId));
            [$changed, $details] = $change($deck);
            $this->records->saveDeck($itemId, SlideDeck::validate($changed), $userId);
            $this->audit->record($userId, $event, ['course_item_id' => $itemId] + $details);
        });
    }

    /** @param array{slides:list<array<string,mixed>>} $deck */
    public static function indexOf(array $deck, string $slideId): int
    {
        foreach ($deck['slides'] as $index => $slide) {
            if ((string) $slide['id'] === $slideId) { return $index; }
        }
        throw new InvalidArgumentException('That slide is no longer in the presentation.');
    }
}
