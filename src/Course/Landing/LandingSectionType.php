declare(strict_types=1);

namespace CattoLearning\Course\Landing;

use InvalidArgumentException;

enum LandingSectionType: string
{
    case Hero = 'hero';
    case Audience = 'audience';
    case Outcomes = 'outcomes';
    case Contents = 'contents';
    case Benefits = 'benefits';
    case Instructor = 'instructor';
    case Reviews = 'reviews';
    case Pricing = 'pricing';
    case Faq = 'faq';
    case Cta = 'cta';

    /** Where the hero's second button may lead: a part of the page, or the course's free preview. */
    public const SECONDARY_TARGETS = [
        'none' => 'No second button',
        'contents' => 'Course contents',
        'reviews' => 'Reviews',
        'pricing' => 'Pricing',
        'faq' => 'Questions',
        'preview' => 'The course’s free preview',
    ];

    /** The hero picture: none, the course's cover artwork, or a picture from the Resource Library. */
    public const IMAGE_SOURCES = ['none', 'cover', 'resource'];

    public const REVIEW_LIMIT_MAX = 12;

    public static function fromName(string $name): self
    {
        return self::tryFrom($name) ?? throw new InvalidArgumentException('Choose a kind of section.');
    }

    /**
     * The sections a new landing page starts with, in order. The instructor section is offered but
     * not added: the platform knows a course's provider, not a person who teaches it.
     *
     * @return list<self>
     */
    public static function starting(): array
    {
        return [self::Hero, self::Audience, self::Outcomes, self::Contents, self::Benefits, self::Reviews, self::Pricing, self::Faq, self::Cta];
    }

    public function label(): string
    {
        return match ($this) {
            self::Hero => 'Hero',
            self::Audience => 'Who this course is for',
            self::Outcomes => 'Learning outcomes',
            self::Contents => 'Course contents',
            self::Benefits => 'Benefits',
            self::Instructor => 'Instructor',
            self::Reviews => 'Reviews',
            self::Pricing => 'Pricing',
            self::Faq => 'FAQ',
            self::Cta => 'Call to action',
        };
    }

    /** What the section shows, for the Add section list. */
    public function description(): string
    {
        return match ($this) {
            self::Hero => 'The top of the page: a headline, a short pitch, a picture and the buy button.',
            self::Audience => 'A short list of the people the course is meant for.',
            self::Outcomes => 'What a learner will be able to do after the course.',
            self::Contents => 'The course’s outline, read from the course itself.',
            self::Benefits => 'Cards, each a benefit with a short explanation.',
            self::Instructor => 'Who provides the course and its accreditation, with your introduction.',
            self::Reviews => 'The course’s rating and its latest approved reviews.',
            self::Pricing => 'The course’s current prices and access periods, with the buy button.',
            self::Faq => 'Questions and answers that open one at a time.',
            self::Cta => 'A closing heading and sentence with the buy button.',
        };
    }

    /** Whether a page may hold only one of these. */
    public function once(): bool
    {
        return !in_array($this, [self::Benefits, self::Faq, self::Cta], true);
    }

    /** The heading shown when the author leaves it empty. The hero's is the course title. */
    public function defaultHeading(): string
    {
        return match ($this) {
            self::Hero => '',
            self::Audience => 'Who this course is for',
            self::Outcomes => 'What you will learn',
            self::Contents => 'What the course covers',
            self::Benefits => 'Why take this course',
            self::Instructor => 'Who provides this course',
            self::Reviews => 'What learners say',
            self::Pricing => 'Price and access',
            self::Faq => 'Questions and answers',
            self::Cta => 'Ready to start?',
        };
    }

    /**
     * A new section's settings: every field present, with no copy written for the author.
     *
     * @return array<string,mixed>
     */
    public function defaults(): array
    {
        return match ($this) {
            self::Hero => ['headline' => '', 'text' => '', 'image' => 'cover', 'image_resource_id' => null, 'secondary' => 'contents', 'secondary_label' => ''],
            self::Audience, self::Outcomes => ['heading' => '', 'text' => '', 'items' => []],
            self::Contents => ['heading' => '', 'text' => '', 'show_items' => true, 'show_descriptions' => false],
            self::Benefits => ['heading' => '', 'text' => '', 'items' => []],
            self::Instructor, self::Pricing, self::Cta => ['heading' => '', 'text' => ''],
            self::Reviews => ['heading' => '', 'text' => '', 'limit' => 3, 'when_empty' => 'hide'],
            self::Faq => ['heading' => '', 'text' => '', 'items' => []],
        };
    }

    /**
     * The section's settings as they will be stored, from a posted form or from stored data being
     * checked again. Anything outside the type's schema is ignored; anything malformed is refused
     * with a message naming the field. A hero's chosen picture is checked against the Resource
     * Library by LandingPageService, which can see it.
     *
     * @param array<string,mixed> $input
     * @return array<string,mixed>
     */
    public function normalise(array $input): array
    {
        $heading = fn(): string => LandingCopy::line($input['heading'] ?? '', 120, 'The heading');
        $text = fn(int $max = 1000): string => LandingCopy::prose($input['text'] ?? '', $max, 'The introduction');
        return match ($this) {
            self::Hero => self::hero($input),
            self::Audience => ['heading' => $heading(), 'text' => $text(), 'items' => LandingCopy::lines($input['items'] ?? [], 12, 200, 'The list')],
            self::Outcomes => ['heading' => $heading(), 'text' => $text(), 'items' => LandingCopy::lines($input['items'] ?? [], 20, 200, 'The list')],
            self::Contents => [
                'heading' => $heading(),
                'text' => $text(),
                'show_items' => self::flag($input['show_items'] ?? false),
                'show_descriptions' => self::flag($input['show_descriptions'] ?? false),
            ],
            self::Benefits => [
                'heading' => $heading(),
                'text' => $text(),
                'items' => LandingCopy::rows($input['items'] ?? [], ['title' => ['Title', 80, false], 'text' => ['Explanation', 400, true]], 12, 'Benefit'),
            ],
            self::Instructor => ['heading' => $heading(), 'text' => $text(1500)],
            self::Reviews => [
                'heading' => $heading(),
                'text' => $text(),
                'limit' => self::limit($input['limit'] ?? 3),
                'when_empty' => in_array($input['when_empty'] ?? 'hide', ['hide', 'show'], true) ? (string) ($input['when_empty'] ?? 'hide') : throw new InvalidArgumentException('Choose what the section does when there are no reviews.'),
            ],
            self::Pricing, self::Cta => ['heading' => $heading(), 'text' => $text(600)],
            self::Faq => [
                'heading' => $heading(),
                'text' => $text(),
                'items' => LandingCopy::rows($input['items'] ?? [], ['question' => ['Question', 200, false], 'answer' => ['Answer', 2000, true]], 20, 'Question'),
            ],
        };
    }

    /**
     * What stops a section being published while it is shown: a list that is still empty. A hidden
     * section is never checked, so an unfinished one can wait.
     *
     * @param array<string,mixed> $data normalised settings
     * @return list<string>
     */
    public function missing(array $data): array
    {
        $empty = ($data['items'] ?? []) === [];
        return match ($this) {
            self::Audience => $empty ? ['Who this course is for has no statements yet.'] : [],
            self::Outcomes => $empty ? ['Learning outcomes has no outcomes yet.'] : [],
            self::Benefits => $empty ? ['Benefits has no benefits yet.'] : [],
            self::Faq => $empty ? ['FAQ has no questions yet.'] : [],
            self::Hero => ($data['image'] ?? '') === 'resource' && empty($data['image_resource_id']) ? ['The hero has no picture chosen.'] : [],
            default => [],
        };
    }

    /**
     * The editor list's one line about the section.
     *
     * @param array<string,mixed> $data normalised settings
     */
    public function summary(array $data): string
    {
        $count = count((array) ($data['items'] ?? []));
        $heading = trim((string) ($data['heading'] ?? ''));
        $named = $heading !== '' ? '“' . $heading . '”' : '';
        $plural = static fn(int $n, string $one, string $many): string => $n . ' ' . ($n === 1 ? $one : $many);
        return match ($this) {
            self::Hero => trim((string) ($data['headline'] ?? '')) !== '' ? '“' . (string) $data['headline'] . '”' : 'The course title as the headline',
            self::Audience => $plural($count, 'statement', 'statements'),
            self::Outcomes => $plural($count, 'outcome', 'outcomes'),
            self::Benefits => trim($named . ' · ' . $plural($count, 'benefit', 'benefits'), ' ·'),
            self::Faq => trim($named . ' · ' . $plural($count, 'question', 'questions'), ' ·'),
            self::Contents => ((bool) ($data['show_items'] ?? false) ? 'Sections and items' : 'Sections only') . ((bool) ($data['show_descriptions'] ?? false) ? ', with descriptions' : '') . ', from the course',
            self::Instructor => 'The course’s provider and accreditation',
            self::Reviews => 'Up to ' . $plural((int) ($data['limit'] ?? 3), 'approved review', 'approved reviews'),
            self::Pricing => 'The course’s current prices',
            self::Cta => $named !== '' ? $named : 'The buy button',
        };
    }

    /**
     * @param array<string,mixed> $input
     * @return array<string,mixed>
     */
    private static function hero(array $input): array
    {
        $image = (string) ($input['image'] ?? 'cover');
        if (!in_array($image, self::IMAGE_SOURCES, true)) {
            throw new InvalidArgumentException('Choose the hero picture.');
        }
        $resource = $input['image_resource_id'] ?? null;
        $resourceId = is_int($resource) || (is_string($resource) && ctype_digit($resource)) ? (int) $resource : null;
        $secondary = (string) ($input['secondary'] ?? 'none');
        if (!array_key_exists($secondary, self::SECONDARY_TARGETS)) {
            throw new InvalidArgumentException('Choose where the second button leads.');
        }
        return [
            'headline' => LandingCopy::line($input['headline'] ?? '', 120, 'The headline'),
            'text' => LandingCopy::prose($input['text'] ?? '', 600, 'The supporting text'),
            'image' => $image,
            'image_resource_id' => $image === 'resource' && $resourceId !== null && $resourceId > 0 ? $resourceId : null,
            'secondary' => $secondary,
            'secondary_label' => LandingCopy::line($input['secondary_label'] ?? '', 40, 'The second button’s label'),
        ];
    }

    private static function flag(mixed $value): bool
    {
        return $value === true || $value === 1 || $value === '1' || $value === 'on';
    }

    private static function limit(mixed $value): int
    {
        $limit = is_int($value) || (is_string($value) && ctype_digit($value)) ? (int) $value : 0;
        if ($limit < 1 || $limit > self::REVIEW_LIMIT_MAX) {
            throw new InvalidArgumentException(sprintf('Show between 1 and %d reviews.', self::REVIEW_LIMIT_MAX));
        }
        return $limit;
    }
