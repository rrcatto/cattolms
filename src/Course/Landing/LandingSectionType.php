second button of the hero can only point at another part of the page or the course's own free
preview, and every purchase button is the platform's own.

The hero is the top of the page and is always first. Hero, the audience, the outcomes, the course
contents, the provider, the reviews and the pricing appear at most once (a second copy would repeat
the same live data, or say the same thing twice); benefits, questions and calls to action may repeat.

