/*
Generated by: Claude Code CLI

Date time: 2026/10/09 SAST

Version: 0.9.0

Description:
The two first-party events a landing page produces. landing_page_view: a view of a published page
by a visitor (signed in or not), never ADMIN's preview, the editor or a page that is not public.
landing_page_cta_clicked: one of the page's purchase buttons was pressed and the cart accepted it,
or a company request was sent; it records which button and which price, never more. Both carry the
browser session's analytics visitor and the campaign the visitor arrived from, if any. A view or
a click is never a purchase: checkout_started and course_purchased remain the record of a sale.

Changelog:
2026/10/09 SAST
- Created for course marketing landing pages (Phase L).
*/

declare(strict_types=1);

namespace CattoLearning\Course\Landing;

use CattoLearning\Analytics\AnalyticsEventRecorder;
use CattoLearning\Analytics\AnalyticsEventType;
use CattoLearning\Analytics\AnalyticsSource;

final class LandingPageAnalytics
{
    public const ACTIONS = ['add', 'buy_now', 'request'];

    public function __construct(
        private readonly AnalyticsEventRecorder $events,
        private readonly LandingPageRepository $pages,
    ) {
    }

    /**
     * A view of a published page.
     *
     * @param array<string,mixed> $page
     * @param array<string,string> $campaign
     */
    public function viewed(array $page, ?int $userId, string $visitorId, array $campaign): void
    {
        $this->events->recordSafely(
            AnalyticsEventType::LandingPageView,
            AnalyticsSource::LandingPage,
            ['course_id' => (int) $page['course_id'], 'user_id' => $userId, 'visitor_id' => $visitorId],
            ['landing_page_id' => (int) $page['id']] + $campaign
        );
    }

    /**
     * The published landing page a purchase form says it came from, if it is one and sells this
     * course; otherwise null, and the purchase is an ordinary one.
     *
     * @return array<string,mixed>|null
     */
    public function source(int $landingPageId, int $courseId): ?array
    {
        if ($landingPageId < 1) {
            return null;
        }
        $page = $this->pages->byId($landingPageId);
        if ($page === null || (int) $page['course_id'] !== $courseId || $page['status'] !== 'published' || $page['course_status'] !== 'published') {
            return null;
        }
        return $page;
    }

    /**
     * A purchase button on the page was pressed and accepted.
     *
     * @param array<string,mixed> $page
     * @param array<string,string> $campaign
     */
    public function clicked(array $page, string $action, int $variantId, ?int $userId, string $visitorId, array $campaign): void
    {
        if (!in_array($action, self::ACTIONS, true)) {
            return;
        }
        $this->events->recordSafely(
            AnalyticsEventType::LandingPageCtaClicked,
            AnalyticsSource::LandingPage,
            ['course_id' => (int) $page['course_id'], 'user_id' => $userId, 'visitor_id' => $visitorId],
            ['landing_page_id' => (int) $page['id'], 'action' => $action, 'variant_id' => $variantId] + $campaign
        );
    }
}
