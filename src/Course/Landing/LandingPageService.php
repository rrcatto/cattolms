    /**
     * @param callable(TreeArrangement, list<array{id:int,parent:null}>):list<array{id:int,parent:int|null}> $change
     * @param list<int>|null $shown
     */
    private function reorder(int $courseId, int $sectionId, int $userId, ?array $shown, callable $change): void
    {
        $this->transactions->run(function () use ($courseId, $sectionId, $userId, $shown, $change): void {
            $page = $this->locked($courseId);
            $section = $this->section($page, $sectionId);
            if ($section['section_type'] === 'hero') {
                throw new InvalidArgumentException('The hero is always at the top of the page.');
            }
            $ids = array_values(array_map(static fn(array $s): int => $s['id'], array_filter($this->pages->sections((int) $page['id']), static fn(array $s): bool => $s['section_type'] !== 'hero')));
            if ($shown !== null && $shown !== $ids) {
                throw new InvalidArgumentException('The sections were changed elsewhere since this page was loaded. The saved order is shown.');
            }
            $tree = new TreeArrangement(1);
            $rows = array_map(static fn(int $id): array => ['id' => $id, 'parent' => null], $ids);
            try {
                $moved = array_map(static fn(array $row): int => (int) $row['id'], $change($tree, $rows));
                $tree->assertComplete($ids, array_map(static fn(int $id): array => ['id' => $id, 'parent' => null], $moved));
            } catch (TreeMoveRefused $refused) {
                throw new InvalidArgumentException(match ($refused->reason) {
                    TreeMoveRefused::BAD_POSITION => 'That is not a place on the page.',
                    TreeMoveRefused::STALE => 'The sections were changed elsewhere since this page was loaded. The saved order is shown.',
                    default => 'That move is not possible.',
                });
            }
            if ($moved === $ids) {
                return;
            }
            $this->pages->saveOrder((int) $page['id'], $moved);
            $this->pages->touch((int) $page['id'], $userId);
            $from = (int) array_search($sectionId, $ids, true) + 1;
            $to = (int) array_search($sectionId, $moved, true) + 1;
            $label = LandingSectionType::from((string) $section['section_type'])->label();
            $this->record($courseId, $userId, 'landing_page.sections_reordered', $sectionId, 'Landing page section moved: ' . $label . ' from ' . $from . ' to ' . $to . '.', ['landing_page_id' => (int) $page['id'], 'section_id' => $sectionId, 'from_position' => $from, 'to_position' => $to]);
        });
    }

    /**
     * Each section with its type, its stored settings checked again (filled with the type's
     * defaults for fields added since it was saved) and, if they no longer pass, why.
     *
     * @param array<string,mixed> $page
     * @return array<string,mixed>
     */
    private function withSections(array $page): array
    {
        $page['sections'] = [];
        foreach ($this->pages->sections((int) $page['id']) as $section) {
            $type = LandingSectionType::tryFrom((string) $section['section_type']);
            if ($type === null) {
                continue;
            }
            $section['type'] = $type;
            $section['invalid'] = '';
            try {
                $section['data'] = $type->normalise($section['data'] + $type->defaults());
            } catch (InvalidArgumentException $problem) {
                $section['data'] = $type->defaults();
                $section['invalid'] = $problem->getMessage();
            }
            $page['sections'][] = $section;
        }
        return $page;
    }

    /** @return array<string,mixed> the course's page, locked */
    private function locked(int $courseId): array
    {
        $page = $this->pages->forCourse($courseId) ?? throw new InvalidArgumentException('This course has no landing page yet.');
        $this->pages->lock((int) $page['id']);
        return $this->pages->forCourse($courseId) ?? throw new InvalidArgumentException('This course has no landing page yet.');
    }

    /**
     * @param array<string,mixed> $page
     * @return array<string,mixed>
     */
    private function section(array $page, int $sectionId): array
    {
        return $this->pages->sectionOf((int) $page['id'], $sectionId) ?? throw new InvalidArgumentException('That section is not on this page.');
    }

    private function freeSlug(string $base): string
    {
        $base = substr(Slug::validate($base), 0, 110);
        $slug = $base;
        for ($n = 2; $this->pages->slugTaken($slug); $n++) {
            $slug = rtrim($base, '-') . '-' . $n;
        }
        return $slug;
    }

    /** @param array<string,mixed> $upload */
    private function uploadPicture(array $upload, string $title, int $userId): int
    {
        $tmp = (string) ($upload['tmp_name'] ?? '');
        $mime = is_file($tmp) ? ((new \finfo(FILEINFO_MIME_TYPE))->file($tmp) ?: '') : '';
        if (!str_starts_with($mime, 'image/')) {
            throw new InvalidArgumentException('The uploaded file is not a picture.');
        }
        $title = trim($title) !== '' ? trim($title) : pathinfo((string) ($upload['name'] ?? 'Picture'), PATHINFO_FILENAME);
        try {
            return $this->resources->upload($upload, ['title' => $title, 'resource_type' => 'image_graphic', 'original_filename' => (string) ($upload['name'] ?? '')], $userId);
        } catch (RuntimeException $failed) {
            throw new InvalidArgumentException($failed->getMessage());
        }
    }

    /** @param array<string,mixed> $metadata identifiers and field names, never copy */
    private function record(int $courseId, int $userId, string $event, int $entityId, string $summary, array $metadata): void
    {
        $this->courses->recordHistory($courseId, $userId, $event, 'landing_page', $entityId, $summary, $metadata);
        $this->audit->record($userId, $event, ['course_id' => $courseId] + $metadata);
    }
}
