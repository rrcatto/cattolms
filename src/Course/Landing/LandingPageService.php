use InvalidArgumentException;
use RuntimeException;

final class LandingPageService
{
    public function __construct(
        private readonly LandingPageRepository $pages,
        private readonly CourseRepository $courses,
        private readonly ResourceLibraryService $resources,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
    ) {
    }

    /**
     * The course's page with its sections, each with its type, or null when it has none.
     *
     * @return array<string,mixed>|null
     */
    public function page(int $courseId): ?array
    {
        $page = $this->pages->forCourse($courseId);
        return $page === null ? null : $this->withSections($page);
    }

    /**
     * A published page of a published course, by its address, or null.
     *
     * @return array<string,mixed>|null
     */
    public function published(string $slug): ?array
    {
        try {
            $slug = Slug::validate($slug);
        } catch (InvalidArgumentException) {
            return null;
        }
        $page = $this->pages->bySlug($slug);
        if ($page === null || $page['status'] !== 'published' || $page['course_status'] !== 'published') {
            return null;
        }
        return $this->withSections($page);
    }

    /**
     * A page by its address whatever its status, with its sections, or null.
     *
     * @return array<string,mixed>|null
     */
    public function atAddress(string $slug): ?array
    {
        try {
            $page = $this->pages->bySlug(Slug::validate($slug));
        } catch (InvalidArgumentException) {
            return null;
        }
        return $page === null ? null : $this->withSections($page);
    }

    /** Creates the course's page as a draft with the starting sections. */
    public function create(int $courseId, int $userId): int
    {
        return $this->transactions->run(function () use ($courseId, $userId): int {
            $course = $this->courses->findById($courseId) ?? throw new InvalidArgumentException('The course does not exist.');
            if ($this->pages->forCourse($courseId) !== null) {
                throw new InvalidArgumentException('This course already has a landing page.');
            }
            $slug = $this->freeSlug((string) $course['slug']);
            $pageId = $this->pages->create($courseId, $slug, $userId);
            $position = 0;
            foreach (LandingSectionType::starting() as $type) {
                $this->pages->insertSection($pageId, $type->value, $type === LandingSectionType::Hero ? 0 : ++$position, $type->defaults());
            }
            $this->record($courseId, $userId, 'landing_page.created', $pageId, 'Landing page created at /landing/' . $slug . '.', ['landing_page_id' => $pageId, 'slug' => $slug]);
            return $pageId;
        });
    }

    /**
     * The page's address, title and description.
     *
     * @param array<string,mixed> $input
     */
    public function updateSettings(int $courseId, array $input, int $userId): void
    {
        $this->transactions->run(function () use ($courseId, $input, $userId): void {
            $page = $this->locked($courseId);
            $slug = trim((string) ($input['slug'] ?? ''));
            if ($slug === '') {
                throw new InvalidArgumentException('The page needs an address.');
            }
            $slug = Slug::validate($slug);
            if (strlen($slug) > 120) {
                throw new InvalidArgumentException('The address is longer than 120 characters.');
            }
            if ($this->pages->slugTaken($slug, (int) $page['id'])) {
                throw new InvalidArgumentException('Another landing page already uses /landing/' . $slug . '.');
            }
            $title = LandingCopy::line($input['meta_title'] ?? '', 120, 'The page title');
            $description = LandingCopy::line($input['meta_description'] ?? '', 300, 'The page description');
            $changed = array_keys(array_filter([
                'slug' => $slug !== $page['slug'],
                'meta_title' => $title !== (string) ($page['meta_title'] ?? ''),
                'meta_description' => $description !== (string) ($page['meta_description'] ?? ''),
            ]));
            if ($changed === []) {
                return;
            }
            $this->pages->updateSettings((int) $page['id'], $slug, $title !== '' ? $title : null, $description !== '' ? $description : null, $userId);
            $metadata = ['landing_page_id' => (int) $page['id'], 'changed' => $changed];
            if (in_array('slug', $changed, true)) {
                $metadata += ['from_slug' => (string) $page['slug'], 'to_slug' => $slug];
            }
            $this->record($courseId, $userId, 'landing_page.settings_updated', (int) $page['id'], 'Landing page settings updated: ' . implode(', ', $changed) . '.', $metadata);
        });
    }

    /** Adds a section of the given kind at the end of the page (a hero goes first). */
    public function addSection(int $courseId, string $typeName, int $userId): int
    {
        $type = LandingSectionType::fromName($typeName);
        return $this->transactions->run(function () use ($courseId, $type, $userId): int {
            $page = $this->locked($courseId);
            $sections = $this->pages->sections((int) $page['id']);
            if ($type->once()) {
                foreach ($sections as $section) {
                    if ($section['section_type'] === $type->value) {
                        throw new InvalidArgumentException('The page already has a ' . mb_strtolower($type->label()) . ' section; a page has only one.');
                    }
                }
            }
            $position = $type === LandingSectionType::Hero ? 0 : count(array_filter($sections, static fn(array $s): bool => $s['section_type'] !== 'hero')) + 1;
            $sectionId = $this->pages->insertSection((int) $page['id'], $type->value, $position, $type->defaults());
            $this->pages->touch((int) $page['id'], $userId);
            $this->record($courseId, $userId, 'landing_page.section_added', $sectionId, 'Landing page section added: ' . $type->label() . '.', ['landing_page_id' => (int) $page['id'], 'section_id' => $sectionId, 'section_type' => $type->value]);
            return $sectionId;
        });
    }

    /**
     * Saves a section's copy and settings. A hero may also take a new picture, uploaded into the
     * Resource Library and chosen.
     *
     * @param array<string,mixed> $input
     * @param array<string,mixed>|null $upload a posted file for the hero's picture
     */
    public function updateSection(int $courseId, int $sectionId, array $input, int $userId, ?array $upload = null, bool $mayUpload = false): void
    {
        $this->transactions->run(function () use ($courseId, $sectionId, $input, $userId, $upload, $mayUpload): void {
            $page = $this->locked($courseId);
            $section = $this->section($page, $sectionId);
            $type = LandingSectionType::from((string) $section['section_type']);
            if ($type === LandingSectionType::Hero && $upload !== null && (int) ($upload['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_NO_FILE) {
                if (!$mayUpload) {
                    throw new InvalidArgumentException('You may not add files to the Resource Library.');
                }
                $input['image'] = 'resource';
                $input['image_resource_id'] = $this->uploadPicture($upload, (string) ($input['upload_title'] ?? ''), $userId);
            }
            $data = $type->normalise($input);
            if ($type === LandingSectionType::Hero && $data['image'] === 'resource') {
                if ($data['image_resource_id'] === null) {
                    throw new InvalidArgumentException('Choose the picture from the Resource Library, or upload one.');
                }
                if ($this->pages->picture((int) $data['image_resource_id']) === null) {
                    throw new InvalidArgumentException('That picture is not in the Resource Library.');
                }
            }
            try {
                $before = $type->normalise($section['data'] + $type->defaults());
            } catch (InvalidArgumentException) {
                $before = [];
            }
            $changed = array_keys(array_filter($data, static fn(mixed $value, string $key): bool => ($before[$key] ?? null) !== $value, ARRAY_FILTER_USE_BOTH));
            if ($changed === []) {
                return;
            }
            $this->pages->updateSection($sectionId, $data);
            $this->pages->touch((int) $page['id'], $userId);
            $this->record($courseId, $userId, 'landing_page.section_updated', $sectionId, 'Landing page section edited: ' . $type->label() . '.', ['landing_page_id' => (int) $page['id'], 'section_id' => $sectionId, 'section_type' => $type->value, 'changed' => $changed]);
        });
    }

    public function setSectionEnabled(int $courseId, int $sectionId, bool $enabled, int $userId): void
    {
        $this->transactions->run(function () use ($courseId, $sectionId, $enabled, $userId): void {
            $page = $this->locked($courseId);
            $section = $this->section($page, $sectionId);
            if ($section['enabled'] === $enabled) {
                return;
            }
            $this->pages->setEnabled($sectionId, $enabled);
            $this->pages->touch((int) $page['id'], $userId);
            $label = LandingSectionType::from((string) $section['section_type'])->label();
            $this->record($courseId, $userId, $enabled ? 'landing_page.section_shown' : 'landing_page.section_hidden', $sectionId, 'Landing page section ' . ($enabled ? 'shown' : 'hidden') . ': ' . $label . '.', ['landing_page_id' => (int) $page['id'], 'section_id' => $sectionId, 'section_type' => (string) $section['section_type']]);
        });
    }

    public function removeSection(int $courseId, int $sectionId, int $userId): void
    {
        $this->transactions->run(function () use ($courseId, $sectionId, $userId): void {
            $page = $this->locked($courseId);
            $section = $this->section($page, $sectionId);
            $this->pages->deleteSection($sectionId);
            $rest = array_values(array_filter($this->pages->sections((int) $page['id']), static fn(array $s): bool => $s['section_type'] !== 'hero'));
            $this->pages->saveOrder((int) $page['id'], array_map(static fn(array $s): int => $s['id'], $rest));
            $this->pages->touch((int) $page['id'], $userId);
            $label = LandingSectionType::from((string) $section['section_type'])->label();
            $this->record($courseId, $userId, 'landing_page.section_removed', $sectionId, 'Landing page section removed: ' . $label . '.', ['landing_page_id' => (int) $page['id'], 'section_id' => $sectionId, 'section_type' => (string) $section['section_type']]);
        });
    }

    /**
     * Drag and drop: the section goes to $index among the other sections after the hero (0 is the
     * first). $shown, when given, is the order the page showed; a different stored order refuses.
     *
     * @param list<int>|null $shown
     */
    public function arrange(int $courseId, int $sectionId, int $index, ?array $shown, int $userId): void
    {
        $this->reorder($courseId, $sectionId, $userId, $shown, static fn(TreeArrangement $tree, array $rows): array => $tree->place($rows, [$sectionId], null, $index));
    }

    /** The ⋯ menu and the keyboard: top, up, down or bottom. */
    public function step(int $courseId, int $sectionId, string $direction, int $userId): void
    {
        if (!in_array($direction, ['top', 'up', 'down', 'bottom'], true)) {
            throw new InvalidArgumentException('Choose a valid move.');
        }
        $this->reorder($courseId, $sectionId, $userId, null, static fn(TreeArrangement $tree, array $rows): array => $tree->move($rows, [$sectionId], $direction));
    }

    /**
     * What stops the page being published, in the words the editor shows. Empty when it can be.
     *
     * @param array<string,mixed> $page a page with its sections
     * @return list<string>
     */
    public function problems(array $page): array
    {
        $problems = [];
        if ((string) ($page['course_status'] ?? '') !== 'published') {
            $problems[] = 'The course is not published, so its landing page cannot be either.';
        }
        try {
            Slug::validate((string) $page['slug']);
        } catch (InvalidArgumentException) {
            $problems[] = 'The page address is not valid.';
        }
        $shown = 0;
        foreach ($page['sections'] as $section) {
            if (!$section['enabled']) {
                continue;
            }
            $shown++;
            if ($section['invalid'] !== '') {
                $problems[] = $section['type']->label() . ': ' . $section['invalid'];
                continue;
            }
            foreach ($section['type']->missing($section['data']) as $missing) {
                $problems[] = $missing;
            }
            if ($section['type'] === LandingSectionType::Hero && $section['data']['image'] === 'resource' && $section['data']['image_resource_id'] !== null && $this->pages->picture((int) $section['data']['image_resource_id']) === null) {
                $problems[] = 'The hero’s picture is no longer in the Resource Library.';
            }
        }
        if ($shown === 0) {
            $problems[] = 'Every section is hidden, so the page would be empty.';
        }
        return $problems;
    }

    public function publish(int $courseId, int $userId): void
    {
        $this->transactions->run(function () use ($courseId, $userId): void {
            $page = $this->withSections($this->locked($courseId));
            $problems = $this->problems($page);
            if ($problems !== []) {
                throw new InvalidArgumentException('The page was not published. ' . implode(' ', $problems));
            }
            if ($page['status'] === 'published') {
                return;
            }
            $this->pages->publish((int) $page['id'], $userId);
            $this->record($courseId, $userId, 'landing_page.published', (int) $page['id'], 'Landing page published at /landing/' . $page['slug'] . '.', ['landing_page_id' => (int) $page['id'], 'slug' => (string) $page['slug']]);
        });
    }

    public function unpublish(int $courseId, int $userId): void
    {
        $this->transactions->run(function () use ($courseId, $userId): void {
            $page = $this->locked($courseId);
            if ($page['status'] !== 'published') {
                return;
            }
            $this->pages->unpublish((int) $page['id'], $userId);
            $this->record($courseId, $userId, 'landing_page.unpublished', (int) $page['id'], 'Landing page unpublished.', ['landing_page_id' => (int) $page['id'], 'slug' => (string) $page['slug']]);
        });
    }

    /** Deletes a page that has never been public, with its sections. The course, its reviews, files and events stay. */
    public function delete(int $courseId, int $userId): void
    {
        $this->transactions->run(function () use ($courseId, $userId): void {
            $page = $this->locked($courseId);
            if ($page['first_published_at'] !== null) {
                throw new InvalidArgumentException('This page has been public, so it is unpublished rather than deleted.');
            }
            $this->pages->delete((int) $page['id']);
            $this->record($courseId, $userId, 'landing_page.deleted', (int) $page['id'], 'Landing page deleted.', ['landing_page_id' => (int) $page['id'], 'slug' => (string) $page['slug']]);
        });
    }

