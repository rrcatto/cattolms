/*
Generated by: Claude Code CLI

Date time: 2026/10/09 SAST

Version: 0.9.0

Description:
The rules of a course's landing page. One page per course, created as a draft with the starting
sections and no copy written for the author; its address is /landing/{slug}, a slug of its own that
is unique among landing pages (only the page itself lives under /landing/, so no other route can
collide with it). A page is public only while it is published and its course is published.

Sections are a flat list after the hero, which is always first. Every change takes the page's row
lock in one transaction: adding a section (a kind a page holds once is refused when it is already
there), saving its copy (checked against its type's schema), showing or hiding it, removing it and
moving it. A move names the section and where it goes - an index among the others, or a step
(top, up, down, bottom) - and the stored order is changed and written 1..n by the shared tree rules
(TreeArrangement with one level); when the browser says what order it showed, a different stored
order refuses the move rather than guessing.

Publishing checks the slug, that the course is published and that every shown section is complete
(a shown list with nothing in it is not). Unpublishing keeps everything. A page that has never been
published can be deleted; once it has been public it is unpublished instead.

Every change is audited with identifiers and the names of the fields that changed, never the copy,
and written to the course's history.

Changelog:
2026/10/09 SAST
- Created for course marketing landing pages (Phase L).
*/

