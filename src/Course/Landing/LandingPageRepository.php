     * The course outline for the public: every section and item in course order with its depth,
     * title, kind and free-preview flag, and nothing of what is inside it. An item's description is
     * read only when asked for.
     *
     * @return list<array<string,mixed>>
     */
    public function outline(int $courseId, bool $withDescriptions): array
    {
        // An item's own description only: a section's introduction is part of the course.
        $descriptions = $withDescriptions
            ? 'CASE WHEN t.node_type = \'item\' THEN COALESCE(NULLIF(p.display_description_override, \'\'), ci.description_html, \'\') ELSE \'\' END'
            : '\'\'';
        return $this->db->fetchAllAssociative(
            "WITH RECURSIVE tree AS (
                SELECT n.id, n.parent_node_id, n.node_type, 1 AS depth, ARRAY[n.position, n.id::int] AS order_path
                FROM course_structure_nodes n WHERE n.course_id = :course AND n.parent_node_id IS NULL
                UNION ALL
                SELECT n.id, n.parent_node_id, n.node_type, t.depth + 1, t.order_path || ARRAY[n.position, n.id::int]
                FROM course_structure_nodes n JOIN tree t ON t.id = n.parent_node_id
             )
             SELECT t.id, t.parent_node_id, t.node_type, t.depth,
                    CASE WHEN t.node_type = 'section' THEN s.title ELSE COALESCE(NULLIF(p.display_title_override, ''), ci.title) END AS title,
                    ci.item_type, COALESCE(p.public_preview, s.public_preview, FALSE) AS public_preview,
                    {$descriptions} AS description_html
             FROM tree t
             LEFT JOIN course_sections s ON s.node_id = t.id
             LEFT JOIN course_item_placements p ON p.node_id = t.id
             LEFT JOIN course_items ci ON ci.id = p.course_item_id
             ORDER BY t.order_path",
            ['course' => $courseId]
        );
    }

