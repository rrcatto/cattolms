<?php

/*
Generated by: Claude Code CLI

Date time: 2026/10/09 SAST

Version: 0.9.0

Description:
Turns a landing page and its sections into what the page template draws, for the public page and
for ADMIN's preview alike, so the preview is the page. The templates only lay this out: they never
query anything.

The section copy comes from the page; everything the course knows comes live from where it is kept,
read once and only for the sections shown: the course and its provider, its active prices and what
this visitor can do about them (CoursePurchaseOptions, the same rules as the course page and
checkout), its rating and its latest approved reviews (CourseReviewService, as many as the section
shows), and its outline (titles and kinds only, LandingPageRepository::outline). A section that has
nothing to show is left out: a reviews section set to hide while there are no approved reviews, a
contents section of an empty course.

In a preview the visitor is treated as someone who does not have the course, the purchase buttons
are drawn but do nothing, the page says it is a preview and asks not to be indexed, and it claims
no canonical address.

Changelog:
2026/10/09 SAST
- Created for course marketing landing pages (Phase L).
*/

declare(strict_types=1);

namespace CattoLearning\Course\Landing;

use CattoLearning\Auth\CurrentUser;
use CattoLearning\Commerce\Application\CoursePurchaseOptions;
use CattoLearning\Course\CourseItemService;
use CattoLearning\Course\CourseReviewService;
use CattoLearning\Support\Env;
use InvalidArgumentException;

final class LandingPageViewBuilder
{
    /** What the hero's second button says when its author gives it no label. */
    private const SECONDARY_LABELS = [
        'contents' => 'See what’s inside',
        'reviews' => 'Read the reviews',
        'pricing' => 'See the price',
        'faq' => 'Questions and answers',
        'preview' => 'Try the free preview',
    ];

    public function __construct(
        private readonly LandingPageRepository $pages,
        private readonly CourseReviewService $reviews,
        private readonly CoursePurchaseOptions $purchases,
    ) {
    }

    /**
     * @param array<string,mixed> $page a page with its sections (LandingPageService)
     * @return array<string,mixed>
     */
    public function build(array $page, ?CurrentUser $viewer, bool $preview): array
    {
        $course = $this->pages->course((int) $page['course_id']) ?? throw new InvalidArgumentException('The course does not exist.');
        $path = '/landing/' . (string) $page['slug'];
        $shown = array_values(array_filter($page['sections'], static fn(array $section): bool => $section['enabled'] && $section['invalid'] === ''));
        $types = array_map(static fn(array $section): LandingSectionType => $section['type'], $shown);
        $has = static fn(LandingSectionType ...$wanted): bool => array_intersect(array_map(static fn(LandingSectionType $t): string => $t->value, $wanted), array_map(static fn(LandingSectionType $t): string => $t->value, $types)) !== [];

        $purchase = $has(LandingSectionType::Hero, LandingSectionType::Pricing, LandingSectionType::Cta)
            ? $this->purchases->for($course, $preview ? null : $viewer, $path)
            : null;
        $rating = $has(LandingSectionType::Hero, LandingSectionType::Reviews, LandingSectionType::Pricing)
            ? $this->reviews->ratingSummary((int) $course['id'])->toArray()
            : null;
        $contents = null;
        foreach ($shown as $section) {
            if ($section['type'] === LandingSectionType::Contents) {
                $contents = $section['data'];
            }
        }
        $outline = $contents !== null ? $this->pages->outline((int) $course['id'], (bool) $contents['show_descriptions']) : null;

        $anchors = [];
        $sections = [];
        $hero = null;
        foreach ($shown as $section) {
            $type = $section['type'];
            $anchor = isset($anchors[$type->value]) ? $type->value . '-' . $section['id'] : $type->value;
            $anchors[$type->value] ??= $anchor;
            $resolved = $this->section($type, $section['data'], $course, $outline, $rating, $purchase) + [
                'id' => $section['id'],
                'type' => $type->value,
                'anchor' => $anchor,
            ];
            if ($resolved['omit'] ?? false) {
                unset($anchors[$type->value]);
                continue;
            }
            if ($type === LandingSectionType::Hero) {
                $hero = $resolved;
                continue;
            }
            $sections[] = $resolved;
        }
        if ($hero !== null) {
            $hero['secondary'] = $this->secondary($hero['secondary_target'], $hero['secondary_label'], $anchors, $course);
            $hero['picture'] = $this->heroPicture($hero['image'], $hero['image_resource_id'], $path, $course);
        }

        $title = trim((string) ($page['meta_title'] ?? '')) ?: (($hero['headline'] ?? '') !== '' ? (string) $hero['headline'] : (string) $course['title']);
        $description = trim((string) ($page['meta_description'] ?? '')) ?: LandingCopy::excerpt((string) ($course['summary'] ?: $course['subtitle']), 300);
        $base = rtrim(Env::string('APP_URL'), '/');
        $picture = $hero['picture']['src'] ?? '';

        return [
            'preview' => $preview,
            'path' => $path,
            'course' => [
                'id' => (int) $course['id'],
                'slug' => (string) $course['slug'],
                'title' => (string) $course['title'],
                'subtitle' => (string) ($course['subtitle'] ?? ''),
                'level' => (string) ($course['level'] ?? ''),
                'category_name' => (string) ($course['category_name'] ?? ''),
                'cover_svg' => (string) ($course['cover_svg'] ?? ''),
                'published' => $course['status'] === 'published',
            ],
            'landing_page_id' => (int) $page['id'],
            'hero' => $hero,
            'sections' => $sections,
            'purchase' => $purchase,
            'meta' => [
                'title' => $title,
                'description' => $description,
                // A preview is not the page: it claims no address and asks not to be indexed.
                'canonical' => $preview ? '' : $base . $path,
                'robots' => $preview ? 'noindex, nofollow' : '',
                'og' => $preview ? [] : array_filter([
                    'type' => 'website',
                    'title' => $title,
                    'description' => $description,
                    'url' => $base . $path,
                    'image' => $picture !== '' && ($hero['picture']['kind'] ?? '') === 'resource' ? $base . $picture : '',
                ]),
            ],
        ];
    }

    /**
     * @param array<string,mixed> $data
     * @param array<string,mixed> $course
     * @param list<array<string,mixed>>|null $outline
     * @param array<string,mixed>|null $rating
     * @param array<string,mixed>|null $purchase
     * @return array<string,mixed>
     */
    private function section(LandingSectionType $type, array $data, array $course, ?array $outline, ?array $rating, ?array $purchase): array
    {
        $heading = trim((string) ($data['heading'] ?? '')) ?: $type->defaultHeading();
        $paragraphs = LandingCopy::paragraphs((string) ($data['text'] ?? ''));
        $common = ['heading' => $heading, 'paragraphs' => $paragraphs];
        return match ($type) {
            LandingSectionType::Hero => [
                'headline' => trim((string) $data['headline']) ?: (string) $course['title'],
                'paragraphs' => LandingCopy::paragraphs(trim((string) $data['text']) !== '' ? (string) $data['text'] : (string) ($course['subtitle'] ?: $course['summary'])),
                'image' => (string) $data['image'],
                'image_resource_id' => $data['image_resource_id'],
                'secondary_target' => (string) $data['secondary'],
                'secondary_label' => (string) $data['secondary_label'],
                'rating' => $rating,
                'purchase' => $purchase,
            ],
            LandingSectionType::Audience, LandingSectionType::Outcomes => $common + ['items' => $data['items']],
            LandingSectionType::Benefits => $common + ['items' => array_map(static fn(array $item): array => ['title' => $item['title'], 'paragraphs' => LandingCopy::paragraphs($item['text'])], $data['items'])],
            LandingSectionType::Faq => $common + ['items' => array_map(static fn(array $item): array => ['question' => $item['question'], 'paragraphs' => LandingCopy::paragraphs($item['answer'])], $data['items'])],
            LandingSectionType::Contents => $this->contents($common, $data, $outline ?? []),
            LandingSectionType::Instructor => $common + [
                'provider' => (string) ($course['provider_name'] ?? ''),
                'accreditation' => (string) ($course['certificate_accreditation'] ?? ''),
                'certificate' => (bool) $course['certificate_enabled'],
            ],
            LandingSectionType::Reviews => $this->reviewsSection($common, $data, $course, $rating ?? ['count' => 0]),
            LandingSectionType::Pricing => $common + ['rating' => $rating, 'purchase' => $purchase],
            LandingSectionType::Cta => $common + ['purchase' => $purchase],
        };
    }

    /**
     * @param array<string,mixed> $common
     * @param array<string,mixed> $data
     * @param list<array<string,mixed>> $outline
     * @return array<string,mixed>
     */
    private function contents(array $common, array $data, array $outline): array
    {
        $nodes = [];
        $sections = 0;
        $items = 0;
        foreach ($outline as $row) {
            $isSection = $row['node_type'] === 'section';
            $isSection ? $sections++ : $items++;
            if (!$isSection && !(bool) $data['show_items']) {
                continue;
            }
            $nodes[] = [
                'depth' => (int) $row['depth'],
                'title' => (string) $row['title'],
                'is_section' => $isSection,
                'kind' => $isSection ? '' : (CourseItemService::TYPE_LABELS[(string) $row['item_type']] ?? ''),
                'free_preview' => !$isSection && (bool) $row['public_preview'],
                'description' => (bool) $data['show_descriptions'] ? LandingCopy::excerpt((string) $row['description_html'], 240) : '',
            ];
        }
        if ($nodes === []) {
            return ['omit' => true];
        }
        return $common + ['nodes' => $nodes, 'section_count' => $sections, 'item_count' => $items];
    }

    /**
     * @param array<string,mixed> $common
     * @param array<string,mixed> $data
     * @param array<string,mixed> $course
     * @param array<string,mixed> $rating
     * @return array<string,mixed>
     */
    private function reviewsSection(array $common, array $data, array $course, array $rating): array
    {
        if ((int) $rating['count'] === 0 && $data['when_empty'] === 'hide') {
            return ['omit' => true];
        }
        return $common + [
            'rating' => $rating,
            'reviews' => (int) $rating['count'] > 0 ? $this->reviews->publishedReviews((int) $course['id'], (int) $data['limit'], 0) : [],
            // Every review is on the course's own page, which only a published course has.
            'all_href' => $course['status'] === 'published' && (int) $rating['count'] > (int) $data['limit'] ? '/courses/' . rawurlencode((string) $course['slug']) . '#reviews' : '',
        ];
    }

    /**
     * The hero's second button: a part of this page that is shown, or the course's free preview
     * when it has one; otherwise none.
     *
     * @param array<string,string> $anchors
     * @param array<string,mixed> $course
     * @return array{label:string,href:string}|null
     */
    private function secondary(string $target, string $label, array $anchors, array $course): ?array
    {
        if ($target === 'none') {
            return null;
        }
        if ($target === 'preview') {
            if ($course['status'] !== 'published' || !$this->pages->hasPublicPreview((int) $course['id'])) {
                return null;
            }
            $href = '/courses/' . rawurlencode((string) $course['slug']) . '/preview';
        } elseif (isset($anchors[$target])) {
            $href = '#' . $anchors[$target];
        } else {
            return null;
        }
        return ['label' => $label !== '' ? $label : self::SECONDARY_LABELS[$target], 'href' => $href];
    }

    /**
     * @param array<string,mixed> $course
     * @return array{kind:string,src:string,alt:string}|null
     */
    private function heroPicture(string $image, mixed $resourceId, string $path, array $course): ?array
    {
        if ($image === 'resource' && is_int($resourceId)) {
            $picture = $this->pages->picture($resourceId);
            return $picture === null ? null : ['kind' => 'resource', 'src' => $path . '/picture/' . $picture['public_id'], 'alt' => ''];
        }
        if ($image === 'cover' && trim((string) ($course['cover_svg'] ?? '')) !== '') {
            return ['kind' => 'cover', 'src' => '', 'alt' => ''];
        }
        return null;
    }
}
