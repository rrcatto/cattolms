/*
Generated by: Claude Code CLI

Date time: 2026/10/09 SAST

Version: 0.9.0

Description:
The text rules for landing page copy. Landing page copy is plain text: a line (a headline, a
heading, a button label) or prose (paragraphs separated by an empty line), never HTML, so nothing
an author types can become markup, a script or a style. Control characters are dropped, invalid
UTF-8 and over-long text are refused with the field's name, and prose is split into paragraphs for
the page, which escapes every one of them.

Changelog:
2026/10/09 SAST
- Created for course marketing landing pages (Phase L).
*/

declare(strict_types=1);

namespace CattoLearning\Course\Landing;

use InvalidArgumentException;

final class LandingCopy
{
    private function __construct()
    {
    }

    /** One line of text: whitespace collapsed, at most $max characters. */
    public static function line(mixed $value, int $max, string $label): string
    {
        $text = self::text($value, $label);
        $text = trim((string) preg_replace('/\s+/u', ' ', $text));
        if (mb_strlen($text) > $max) {
            throw new InvalidArgumentException(sprintf('%s is longer than %d characters.', $label, $max));
        }
        return $text;
    }

    /** Paragraphs: line breaks kept, runs of empty lines reduced to one, at most $max characters. */
    public static function prose(mixed $value, int $max, string $label): string
    {
        $text = str_replace(["\r\n", "\r"], "\n", self::text($value, $label));
        $lines = array_map(static fn(string $line): string => trim((string) preg_replace('/[^\S\n]+/u', ' ', $line)), explode("\n", $text));
        $text = trim((string) preg_replace("/\n{3,}/", "\n\n", implode("\n", $lines)));
        if (mb_strlen($text) > $max) {
            throw new InvalidArgumentException(sprintf('%s is longer than %d characters.', $label, $max));
        }
        return $text;
    }

    /**
     * A list of short statements: one per line of a text box, or already a list. Empty lines are
     * dropped.
     *
     * @return list<string>
     */
    public static function lines(mixed $value, int $maxItems, int $maxLength, string $label): array
    {
        $values = is_array($value) ? array_values($value) : explode("\n", str_replace(["\r\n", "\r"], "\n", self::text($value, $label)));
        $items = [];
        foreach ($values as $number => $item) {
            $line = self::line($item, $maxLength, sprintf('%s line %d', $label, $number + 1));
            if ($line !== '') {
                $items[] = $line;
            }
        }
        if (count($items) > $maxItems) {
            throw new InvalidArgumentException(sprintf('%s has %d lines; at most %d fit on the page.', $label, count($items), $maxItems));
        }
        return $items;
    }

    /**
     * Rows of two fields, such as a question and its answer. A row left empty is dropped; a row
     * with only one of its fields is refused, because half a row on the page is a mistake.
     *
     * @param array<string,array{0:string,1:int,2:bool}> $fields name => [label, max length, prose]
     * @return list<array<string,string>>
     */
    public static function rows(mixed $value, array $fields, int $maxItems, string $label): array
    {
        $rows = [];
        foreach (is_array($value) ? array_values($value) : [] as $number => $row) {
            $row = is_array($row) ? $row : [];
            $clean = [];
            foreach ($fields as $name => [$fieldLabel, $max, $prose]) {
                $name = (string) $name;
                $title = sprintf('%s %d: %s', $label, $number + 1, $fieldLabel);
                $clean[$name] = $prose ? self::prose($row[$name] ?? '', $max, $title) : self::line($row[$name] ?? '', $max, $title);
            }
            $filled = array_filter($clean, static fn(string $field): bool => $field !== '');
            if ($filled === []) {
                continue;
            }
            if (count($filled) !== count($clean)) {
                $empty = array_keys(array_diff_key($clean, $filled));
                throw new InvalidArgumentException(sprintf('%s %d needs its %s as well.', $label, count($rows) + 1, mb_strtolower($fields[$empty[0]][0])));
            }
            $rows[] = $clean;
        }
        if (count($rows) > $maxItems) {
            throw new InvalidArgumentException(sprintf('%s has %d entries; at most %d fit on the page.', $label, count($rows), $maxItems));
        }
        return $rows;
    }

    /**
     * Prose as paragraphs for the page: each paragraph a list of its lines.
     *
     * @return list<list<string>>
     */
    public static function paragraphs(string $prose): array
    {
        $paragraphs = [];
        foreach (preg_split("/\n{2,}/", trim($prose)) ?: [] as $paragraph) {
            if (trim($paragraph) !== '') {
                $paragraphs[] = explode("\n", trim($paragraph));
            }
        }
        return $paragraphs;
    }

    /** Course HTML (a description or an introduction) as one line of plain text, cut at a word. */
    public static function excerpt(string $html, int $max): string
    {
        $text = html_entity_decode(strip_tags((string) preg_replace('/<(br|\/p|\/div|\/li|\/h[1-6])\b[^>]*>/i', ' ', $html)), ENT_QUOTES | ENT_HTML5, 'UTF-8');
        $text = trim((string) preg_replace('/\s+/u', ' ', $text));
        if (mb_strlen($text) <= $max) {
            return $text;
        }
        $cut = mb_substr($text, 0, $max);
        $space = mb_strrpos($cut, ' ');
        return rtrim($space !== false && $space > $max / 2 ? mb_substr($cut, 0, $space) : $cut, " ,.;:-") . '…';
    }

    private static function text(mixed $value, string $label): string
    {
        if ($value === null) {
            return '';
        }
        if (!is_string($value) && !is_int($value)) {
            throw new InvalidArgumentException(sprintf('%s must be text.', $label));
        }
        $text = (string) $value;
        if (!mb_check_encoding($text, 'UTF-8')) {
            throw new InvalidArgumentException(sprintf('%s contains characters that could not be read.', $label));
        }
        // Control characters other than line breaks and tabs never belong in page copy.
        return (string) preg_replace('/[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]/u', '', $text);
    }
}
