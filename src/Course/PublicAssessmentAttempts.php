declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Support\Uuid;
use InvalidArgumentException;

final class PublicAssessmentAttempts
{
    public function __construct(private readonly CourseRepository $courses, private readonly CourseItemRepository $itemRecords, private readonly AssessmentService $assessments)
    {
    }

    /**
     * The start page's facts, as AssessmentService::overview() gives them to a learner. Nothing is counted against the
     * visitor, so every attempt may start.
     *
     * @param array<string,mixed> $course
     * @return array<string,mixed>
     */
    public function overview(array $course, int $nodeId, string $key): array
    {
        $assessment = $this->assessment($course, $nodeId, $key);
        $maximum = !empty($assessment['practice']) || $assessment['maximum_attempts'] === null || $assessment['maximum_attempts'] === '' ? null : (int) $assessment['maximum_attempts'];
        return ['assessment' => $assessment, 'attempts_used' => 0, 'attempts_remaining' => $maximum, 'attempts_limited' => $maximum !== null, 'can_start_graded' => true, 'is_preview' => false, 'is_diagnostic' => $assessment['assessment_type'] === 'diagnostic', 'time_limit_label' => AssessmentService::durationLabel((int) ($assessment['time_limit_seconds'] ?? 1800))];
    }

    /**
     * A new attempt, the learner's mode rules applied (AssessmentService::startAttempt).
     *
     * @param array<string,mixed> $course
     * @param list<array<string,mixed>> $earlier the visitor's earlier attempts, for the attempt's number
     * @return array<string,mixed>
     */
    public function start(array $course, int $nodeId, string $key, string $mode, array $earlier = []): array
    {
        $assessment = $this->assessment($course, $nodeId, $key);
        if (!in_array($mode, ['practice', 'graded', 'diagnostic'], true)) { throw new InvalidArgumentException('Select a valid assessment mode.'); }
        $diagnostic = $assessment['assessment_type'] === 'diagnostic';
        if (!$diagnostic && (bool) ($assessment['practice'] ?? false)) { $mode = 'practice'; }
        if (($diagnostic && $mode !== 'diagnostic') || (!$diagnostic && $mode === 'diagnostic')) { throw new InvalidArgumentException('Select the assessment mode that matches this Course Item.'); }
        if ($mode === 'practice' && !(bool) ($assessment['practice_enabled'] ?? false) && !(bool) ($assessment['practice'] ?? false)) { throw new InvalidArgumentException('Practice is not enabled for this assessment.'); }
        $questions = $this->assessments->drawQuestions($assessment, $mode);
        if ($questions === []) { throw new InvalidArgumentException('No eligible questions are available for this assessment.'); }
        $number = 1;
        foreach ($earlier as $attempt) {
            if ((int) ($attempt['node_id'] ?? 0) === $nodeId && ($attempt['attempt_mode'] ?? '') === $mode) { $number++; }
        }
        $now = time();
        $asked = [];
        foreach ($questions as $index => $question) {
            $order = array_map(static fn(array $option): int => (int) $option['id'], (array) $question['options']);
            if ((bool) ($assessment['randomise_options'] ?? true)) { shuffle($order); }
            $asked[] = ['question_id' => (int) $question['id'], 'sequence' => $index + 1, 'answer_order' => $order, 'response_status' => 'pending', 'selected_option_id' => null, 'is_correct' => null, 'points_awarded' => 0.0, 'presented_at' => null, 'submitted_at' => null, 'response_seconds' => null];
        }
        return [
            'public_id' => Uuid::v4(), 'course_id' => (int) $course['id'], 'slug' => (string) $course['slug'], 'node_id' => $nodeId, 'assessment_id' => (int) $assessment['id'],
            'assessment_key' => (string) $assessment['item_key'], 'assessment_title' => (string) $assessment['title'], 'assessment_type' => (string) $assessment['assessment_type'], 'assessment_role' => (string) $assessment['assessment_role'],
            'pass_mark' => (float) ($assessment['pass_mark'] ?? 50), 'negative_marking' => (bool) ($assessment['negative_marking'] ?? false),
            'result_pass_html' => (string) ($assessment['result_pass_html'] ?? ''), 'result_fail_html' => (string) ($assessment['result_fail_html'] ?? ''),
            'attempt_mode' => $mode, 'practice_only' => (bool) ($assessment['practice'] ?? false), 'attempt_number' => $number, 'status' => 'in_progress',
            'started_at' => $now, 'deadline_at' => $now + (int) ($assessment['time_limit_seconds'] ?? 1800), 'completed_at' => null,
            'questions' => $asked, 'percentage' => null, 'earned_points' => 0.0, 'maximum_points' => 0.0, 'grade_code' => null, 'passed' => null,
        ];
    }

    /**
     * Whether a finished attempt ticks its part, by the learner's rule (CourseItemRepository::partsProgressJoin): a
     * graded attempt, a readiness check, or practice on an assessment that is practice only.
     *
     * @param array<string,mixed> $attempt
     */
    public static function ticksItsPart(array $attempt): bool
    {
        return in_array($attempt['status'] ?? '', ['submitted', 'timed_out'], true) && (($attempt['attempt_mode'] ?? '') !== 'practice' || (bool) ($attempt['practice_only'] ?? false));
    }

    /**
     * The question to answer now, as AssessmentService::session() gives it; a finished or timed-out attempt comes back
     * finished, for the caller to show its result.
     *
     * @param array<string,mixed> $attempt
     * @return array<string,mixed>
     */
    public function session(array $attempt): array
    {
        if ($attempt['status'] !== 'in_progress') { return $attempt; }
        if ($this->remainingSeconds($attempt) <= 0) { return $this->finalise($attempt, true); }
        $index = $this->nextIndex($attempt);
        if ($index === null) { return $this->finalise($attempt, false); }
        $row = &$attempt['questions'][$index];
        if ($row['response_status'] === 'skipped') { $row['presented_at'] = time(); $row['submitted_at'] = null; } else { $row['presented_at'] ??= time(); }
        unset($row);
        return $attempt;
    }

    /**
     * The page's view of an attempt in progress: the question with its answers in the attempt's order, the counts and
     * the time left.
     *
     * @param array<string,mixed> $attempt
     * @return array<string,mixed>
     */
    public function view(array $attempt): array
    {
        $index = $this->nextIndex($attempt);
        if ($index === null) { throw new InvalidArgumentException('This attempt has no question left.'); }
        $row = $attempt['questions'][$index];
        $question = $this->questions((int) $attempt['assessment_id'])[(int) $row['question_id']] ?? null;
        if ($question === null) { throw new InvalidArgumentException('The assessment has changed since this attempt started. Start again.'); }
        $options = [];
        foreach ((array) $question['options'] as $option) { $options[(int) $option['id']] = ['id' => (int) $option['id'], 'option_html' => (string) $option['option_html']]; }
        $view = $attempt;
        $view['question'] = ['question_id' => (int) $row['question_id'], 'sequence' => (int) $row['sequence'], 'question_html' => (string) $question['question_html'], 'points' => $question['points'], 'options' => array_values(array_filter(array_map(static fn(int $id): ?array => $options[$id] ?? null, (array) $row['answer_order'])))];
        $view['counts'] = self::counts($attempt);
        $view['remaining_seconds'] = $this->remainingSeconds($attempt);
        $view['timer_label'] = AssessmentService::timerLabel($view['remaining_seconds']);
        return $view;
    }

    /**
     * An answer or a skip on the current question (AssessmentRepository::recordResponse); practice gives its feedback.
     *
     * @param array<string,mixed> $attempt
     * @return array{attempt:array<string,mixed>,feedback:array<string,mixed>|null}
     */
    public function respond(array $attempt, int $questionId, ?int $optionId, bool $skip): array
    {
        if ($attempt['status'] !== 'in_progress') { return ['attempt' => $attempt, 'feedback' => null]; }
        if ($this->remainingSeconds($attempt) <= 0) { return ['attempt' => $this->finalise($attempt, true), 'feedback' => null]; }
        $index = $this->nextIndex($attempt);
        if ($index === null || (int) $attempt['questions'][$index]['question_id'] !== $questionId) { throw new InvalidArgumentException('This is not the current assessment question.'); }
        $row = &$attempt['questions'][$index];
        $now = time();
        $row['response_seconds'] = max(0, $now - (int) ($row['presented_at'] ?? $now));
        $row['submitted_at'] = $now;
        $feedback = null;
        if ($skip) {
            $row['response_status'] = 'skipped'; $row['selected_option_id'] = null; $row['is_correct'] = null; $row['points_awarded'] = 0.0;
        } else {
            $question = $this->questions((int) $attempt['assessment_id'])[$questionId] ?? null;
            $selected = null; $correctOption = null;
            foreach ((array) ($question['options'] ?? []) as $option) {
                if ((int) $option['id'] === $optionId) { $selected = $option; }
                if ((bool) $option['is_correct']) { $correctOption = $option; }
            }
            if ($selected === null) { throw new InvalidArgumentException('Select a valid answer or choose Skip.'); }
            $correct = (bool) $selected['is_correct'];
            $row['response_status'] = 'answered'; $row['selected_option_id'] = $optionId; $row['is_correct'] = $correct;
            $row['points_awarded'] = $correct ? (float) $question['points'] : ($attempt['negative_marking'] ? (float) $question['incorrect_points'] : 0.0);
            if ($attempt['attempt_mode'] === 'practice') { $feedback = ['status' => 'answered', 'is_correct' => $correct, 'points_awarded' => $row['points_awarded'], 'correct_option_html' => (string) ($correctOption['option_html'] ?? ''), 'explanation_html' => (string) ($question['explanation_html'] ?? '')]; }
        }
        unset($row);
        if ($this->nextIndex($attempt) === null) { return ['attempt' => $this->finalise($attempt, false), 'feedback' => $feedback]; }
        return ['attempt' => $this->session($attempt), 'feedback' => $feedback];
    }

    /**
     * A visitor's course result after the final, by the learner's rule (AssessmentService::completeCourse): from their own
     * finished graded attempts on this course, kept in their session.
     *
     * @param array<string,mixed> $attempt
     * @param list<array<string,mixed>> $attempts
     * @return array<string,mixed>|null
     */
    public function courseResult(array $attempt, array $attempts): ?array
    {
        if ($attempt['attempt_mode'] !== 'graded' || $attempt['status'] === 'in_progress') { return null; }
        // The final closes a course; a short course, which has none, is closed by its one assessment (specification 4.13, 15.5).
        $closing = $this->itemRecords->closingAssessment((int) $attempt['course_id']);
        if ($closing === null || (int) $closing['node_id'] !== (int) $attempt['node_id']) { return null; }
        $short = $closing['assessment_role'] !== 'final';
        $graded = []; $final = null;
        foreach ($this->itemRecords->assessmentContexts((int) $attempt['course_id']) as $context) {
            $scores = [];
            foreach ($attempts as $other) {
                if ((int) $other['course_id'] === (int) $attempt['course_id'] && (int) $other['node_id'] === (int) $context['node_id'] && $other['attempt_mode'] === 'graded' && $other['status'] !== 'in_progress') { $scores[] = (float) $other['percentage']; }
            }
            if ($scores === []) { continue; }
            $value = ScorePolicy::aggregate($scores, (string) $context['score_policy']);
            if ($context['assessment_role'] === 'final') { $final = $value; } else { $graded[] = $value; }
        }
        if ($final === null && (!$short || $graded === [])) { return null; }
        ['module' => $module, 'overall' => $overall] = AssessmentService::courseFigures($graded, $short ? null : $final);
        $band = AssessmentService::gradeBand($overall, $this->courses->gradeBands((int) $attempt['course_id']));
        return ['module_percentage' => round($module, 2), 'final_percentage' => $short ? $overall : $final, 'overall_percentage' => $overall, 'grade_code' => (string) $band['grade_code']];
    }

    /**
     * Finish now: every question not yet answered scores zero.
     *
     * @param array<string,mixed> $attempt
     * @return array<string,mixed>
     */
    public function finish(array $attempt): array
    {
        if ($attempt['status'] !== 'in_progress') { return $attempt; }
        return $this->finalise($attempt, $this->remainingSeconds($attempt) <= 0, true);
    }

    /**
     * The result page's view (AssessmentService::result): the score, the counts, the question report and, for a
     * readiness check, its message and the modules to study again, opening only what the public preview shows.
     *
     * @param array<string,mixed> $attempt
     * @param list<array<string,mixed>> $structure the public preview's outline
     * @return array<string,mixed>
     */
    public function result(array $attempt, array $structure): array
    {
        if ($attempt['status'] === 'in_progress') { throw new InvalidArgumentException('Finish the assessment first.'); }
        $questions = $this->questions((int) $attempt['assessment_id']);
        $rows = $attempt['questions'];
        usort($rows, static fn(array $a, array $b): int => (int) $a['sequence'] <=> (int) $b['sequence']);
        $responses = []; $references = [];
        foreach ($rows as $row) {
            $question = $questions[(int) $row['question_id']] ?? null;
            if ($question === null) { continue; }
            $selected = ''; $correct = '';
            foreach ((array) $question['options'] as $option) {
                if ((int) $option['id'] === (int) ($row['selected_option_id'] ?? 0)) { $selected = (string) $option['option_html']; }
                if ((bool) $option['is_correct']) { $correct = (string) $option['option_html']; }
            }
            $responses[] = ['question_id' => (int) $row['question_id'], 'question_html' => (string) $question['question_html'], 'explanation_html' => (string) ($question['explanation_html'] ?? ''), 'points' => $question['points'], 'response_status' => $row['response_status'], 'is_correct' => $row['is_correct'], 'points_awarded' => $row['points_awarded'], 'selected_option_html' => $selected, 'correct_option_html' => $correct, 'response_seconds' => $row['response_seconds'], 'has_response_seconds' => $row['response_seconds'] !== null && $row['response_status'] !== 'unanswered', 'response_time' => AssessmentService::timeTaken((int) $row['response_seconds'])];
            $references[] = ['is_correct' => $row['is_correct'], 'remediation_item_keys' => (array) ($question['remediation_item_keys'] ?? [])];
        }
        $view = $attempt;
        $view['responses'] = $responses;
        $view['counts'] = self::counts($attempt);
        $view['elapsed_seconds'] = max(0, (int) ($attempt['completed_at'] ?? time()) - (int) $attempt['started_at']);
        $view['elapsed_label'] = AssessmentService::timeTaken($view['elapsed_seconds']);
        $view['structure_node_id'] = (int) $attempt['node_id'];
        $view['is_diagnostic'] = $attempt['assessment_type'] === 'diagnostic';
        if ($view['is_diagnostic']) {
            $passed = (float) $attempt['percentage'] + .0001 >= (float) $attempt['pass_mark'];
            $view['diagnostic_passed'] = $passed;
            $view['diagnostic_message_html'] = $passed ? (string) $attempt['result_pass_html'] : (string) $attempt['result_fail_html'];
            // The learner's modules to study again (AssessmentService::studySuggestions): only what the public preview
            // shows opens, and a module it leaves out is named as part of the full course.
            $open = [];
            foreach (CourseNavigation::sequence($structure) as $node) { $open[(int) $node['id']] = true; }
            $view['study_suggestions'] = $this->assessments->studySuggestions((int) $attempt['course_id'], $references, null, $open);
        }
        return $view;
    }

    /**
     * The assessment a public part holds, as AssessmentService::overview() describes it.
     *
     * @param array<string,mixed> $course
     * @return array<string,mixed>
     */
    private function assessment(array $course, int $nodeId, string $key): array
    {
        $context = $this->itemRecords->placement((int) $course['id'], $nodeId);
        if ($context === null || !$context['public_preview']) { throw new InvalidArgumentException('This Course Item is not public.'); }
        $assessment = null;
        foreach ($this->itemRecords->reachableItems((int) $context['course_item_id']) as $item) {
            if ($item['item_key'] === $key && in_array($item['item_type'], ['assessment', 'diagnostic'], true)) { $assessment = $item; break; }
        }
        if ($assessment === null) { throw new InvalidArgumentException('This assessment is not part of the public Course Item.'); }
        $assessment['question_pool_count'] = count($this->itemRecords->questions((int) $assessment['id'], false));
        $assessment['id'] = (int) $assessment['id']; $assessment['structure_node_id'] = $nodeId; $assessment['assessment_type'] = (string) $assessment['item_type']; $assessment['assessment_key'] = (string) $assessment['item_key'];
        $assessment['assessment_role'] = (($context['course_item_id'] ?? null) == $assessment['id']) ? (string) ($context['assessment_role'] ?? 'content') : 'content';
        return $assessment;
    }

    /**
     * Scores the attempt and closes it (AssessmentService::finalise without anything saved): questions not yet answered
     * score zero, and the result takes the course's grade band, or Ready and Review for a readiness check.
     *
     * @param array<string,mixed> $attempt
     * @return array<string,mixed>
     */
    private function finalise(array $attempt, bool $timedOut, bool $manual = false): array
    {
        if ($attempt['status'] !== 'in_progress') { return $attempt; }
        $points = [];
        foreach ($this->questions((int) $attempt['assessment_id']) as $id => $question) { $points[$id] = (float) $question['points']; }
        $earned = 0.0; $maximum = 0.0;
        foreach ($attempt['questions'] as &$row) {
            if (($timedOut || $manual) && $row['response_status'] === 'pending') { $row['response_status'] = 'unanswered'; $row['points_awarded'] = 0.0; }
            $earned += (float) $row['points_awarded'];
            $maximum += $points[(int) $row['question_id']] ?? 0.0;
        }
        unset($row);
        $earned = max(0.0, $earned); $maximum = max(1.0, $maximum);
        $percentage = round($earned / $maximum * 100, 2);
        if ($attempt['assessment_type'] === 'diagnostic') {
            $passing = $percentage >= (float) $attempt['pass_mark'];
            $band = ['grade_code' => $passing ? 'Ready' : 'Review', 'is_passing' => $passing];
        } else {
            $band = AssessmentService::gradeBand($percentage, $this->courses->gradeBands((int) $attempt['course_id']));
        }
        $attempt['status'] = $timedOut ? 'timed_out' : 'submitted';
        $attempt['earned_points'] = $earned; $attempt['maximum_points'] = $maximum; $attempt['percentage'] = $percentage;
        $attempt['grade_code'] = (string) $band['grade_code']; $attempt['passed'] = (bool) $band['is_passing']; $attempt['completed_at'] = time();
        return $attempt;
    }

    /**
     * The question asked now (AssessmentRepository::nextQuestion): the first not yet answered in the attempt's order,
     * then the skipped ones in the order they were skipped, the one being shown again first. A skipped question keeps
     * its number.
     *
     * @param array<string,mixed> $attempt
     */
    private function nextIndex(array $attempt): ?int
    {
        $best = null;
        foreach ($attempt['questions'] as $index => $row) {
            if ($row['response_status'] === 'pending' && ($best === null || (int) $row['sequence'] < (int) $attempt['questions'][$best]['sequence'])) { $best = $index; }
        }
        if ($best !== null) { return $best; }
        $key = static fn(array $row): array => [$row['submitted_at'] === null ? 0 : 1, (int) ($row['submitted_at'] ?? 0), (int) $row['sequence']];
        foreach ($attempt['questions'] as $index => $row) {
            if ($row['response_status'] === 'skipped' && ($best === null || $key($row) < $key($attempt['questions'][$best]))) { $best = $index; }
        }
        return $best;
    }

    /**
     * @param array<string,mixed> $attempt
     * @return array<string,int>
     */
    private static function counts(array $attempt): array
    {
        $counts = ['total' => 0, 'answered' => 0, 'correct' => 0, 'incorrect' => 0, 'skipped' => 0, 'pending' => 0, 'timed_out' => 0, 'unanswered' => 0];
        foreach ($attempt['questions'] as $row) {
            $counts['total']++;
            $status = (string) $row['response_status'];
            if (isset($counts[$status])) { $counts[$status]++; }
            if ($status === 'answered') { $counts[$row['is_correct'] === true ? 'correct' : 'incorrect']++; }
        }
        return $counts;
    }

    /** @param array<string,mixed> $attempt */
    private function remainingSeconds(array $attempt): int { return max(0, (int) $attempt['deadline_at'] - time()); }

    /** @return array<int,array<string,mixed>> the assessment's questions with their answers, by id */
    private function questions(int $assessmentId): array
    {
        $byId = [];
        foreach ($this->itemRecords->questions($assessmentId, true) as $question) { $byId[(int) $question['id']] = $question; }
        return $byId;
    }
}
