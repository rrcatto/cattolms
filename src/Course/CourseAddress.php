Description:
The one way a course's address is made outside its public pages (owner, 2026-11-06: "You must not use internal db id
fields in any urls across the entire site ... All courses must be referred to by their course code in urls"). A course
is named by its code everywhere but the pages visitors see, which keep its name ("keep the course names for public
pages": /courses/{slug}, its public preview, its landing page and its share picture): Administration's pages for it
(/admin/courses/GDN-101/content), its popularity report, the Company workspace's star, Follow, its anchor on a list
(#course-GDN-101) and the API.

Every template makes these through the Twig functions course_admin_url(), course_anchor() and course_url(), and every
PHP file through this class, so a source scan (tests/Architecture/RowIdAddressScanTest) can require it: a course address
built by hand from a number is refused. A controller turns the code into the course's row id once (CourseService::
courseIdForCode); the services keep working on ids, which never leave the server in an address.

A code is capital letters and digits joined by hyphens, with at least one letter (CourseCode), so it never looks like a
row id, and the fixed words beside it in Administration (new, import, catalogue, categories, tags, page-layouts) are
lower case, so REQUIREMENT cannot match one of them.

Changelog:
2026/11/06 SAST
- Created for stage 1 of the work to keep row ids out of addresses.
*/

declare(strict_types=1);

namespace CattoLearning\Course;

use InvalidArgumentException;

final class CourseAddress
{
    /** A course code in a route: capital letters and digits joined by hyphens, holding a letter. */
    public const REQUIREMENT = '(?=[A-Z0-9-]*[A-Z])[A-Z0-9]+(?:-[A-Z0-9]+)*';

    /**
     * The course's code: a code itself, or a course's row from any query that names its code (`code`, or `course_code`
     * where the row is something else's, such as an enrolment).
     *
     * @param array<string,mixed>|string $course
     */
    public static function code(array|string $course): string
    {
        $code = is_string($course) ? $course : (string) ($course['course_code'] ?? $course['code'] ?? '');
        if (!CourseCode::isValid($code) || CourseCode::normalise($code) !== $code) {
            throw new InvalidArgumentException('A course address needs the course\'s code' . ($code === '' ? '.' : ', and "' . $code . '" is not one.'));
        }
        return $code;
    }

    /**
     * The course in Administration, with what follows it: /admin/courses/GDN-101, /admin/courses/GDN-101/content,
     * /admin/courses/GDN-101?tab=pricing.
     *
     * @param array<string,mixed>|string $course
     */
    public static function admin(array|string $course, string $rest = ''): string
    {
        return '/admin/courses/' . rawurlencode(self::code($course)) . $rest;
    }

    /**
     * The course's row or card on a list, as an anchor's name: course-GDN-101 (Administration > Courses, a company's
     * favourites).
     *
     * @param array<string,mixed>|string $course
     */
    public static function anchor(array|string $course): string
    {
        return 'course-' . self::code($course);
    }

    /**
     * The course's other addresses that are not public pages, by place: popularity (Administration > Reports >
     * Popularity), favourite (the Company workspace's star), follow (Follow, carried through signing in) and api.
     *
     * @param array<string,mixed>|string $course
     */
    public static function to(string $place, array|string $course): string
    {
        $code = rawurlencode(self::code($course));
        return match ($place) {
            'popularity' => '/admin/reports/popularity/' . $code,
            'favourite' => '/company/favourites/' . $code . '/toggle',
            'follow' => '/follow/course/' . $code,
            'api' => '/api/v1/admin/courses/' . $code,
            default => throw new InvalidArgumentException('There is no course address called "' . $place . '".'),
        };
    }
}
