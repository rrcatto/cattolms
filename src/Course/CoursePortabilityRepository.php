    public function itemKeyIsExclusiveToCourse(string $key, int $courseId): bool
    {
        $item = $this->db->fetchAssociative('SELECT id FROM course_items WHERE item_key=:key', ['key' => $key]);
        if ($item === false) {
            return true;
