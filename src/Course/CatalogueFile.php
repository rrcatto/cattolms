declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Infrastructure\Persistence\RoleRepository;
use CattoLearning\Support\Slug;
use CattoLearning\View\Artwork\UploadedSvg;
use InvalidArgumentException;

final class CatalogueFile
{
    public const FORMAT = 'cattolms-catalogue';
    public const VERSION = 2;
    public const SEPARATOR = CourseCatalogueSettings::SEPARATOR;

    public function __construct(
        private readonly CourseService $courses,
        private readonly CourseRepository $repository,
        private readonly RoleRepository $roles,
    ) {}

    /** The catalogue file published with the code: the starter categories and tags. */
    public static function bundledPath(): string
    {
        return dirname(__DIR__, 2) . '/resources/catalogue/catalogue.json';
    }

    /**
     * What the database holds, in the catalogue file's shape: every category and tag, or (owner, 2026-10-23: "only
     * their categories and tags") only these categories, each with the categories above it, and only these tags.
     *
     * @param list<int>|null $categoryIds
     * @param list<int>|null $tagIds
     * @return array<string,mixed>
     */
    public function export(?array $categoryIds = null, ?array $tagIds = null): array
    {
        $nodes = [];
        $roots = [];
        foreach ($this->repository->catalogueCategories() as $row) {
            $id = (int) $row['id'];
            $parent = $row['parent_id'] === null ? null : (int) $row['parent_id'];
            $nodes[$id] = ['name' => (string) $row['name'], 'slug' => (string) $row['slug'], 'description' => (string) ($row['description'] ?? ''),
                'icon' => (string) ($row['icon_svg'] ?? ''), 'children' => [], 'parent' => $parent];
        }
        if ($categoryIds !== null) {
            // A category's own place needs the categories above it; nothing else is kept.
            $kept = [];
            foreach ($categoryIds as $id) {
                for ($at = (int) $id; isset($nodes[$at]) && !isset($kept[$at]); $at = (int) ($nodes[$at]['parent'] ?? 0)) $kept[$at] = true;
            }
            $nodes = array_intersect_key($nodes, $kept);
        }
        foreach ($nodes as $id => $node) {
            if ($node['parent'] === null || !isset($nodes[$node['parent']])) $roots[] = $id;
            else $nodes[$node['parent']]['children'][] = $id;
        }
        $tree = static function (array $ids) use (&$tree, $nodes): array {
            return array_map(static function (int $id) use ($tree, $nodes): array {
                $node = $nodes[$id];
                unset($node['parent']);
                $node['children'] = $tree($node['children']);
                if ($node['children'] === []) unset($node['children']);
                return $node;
            }, $ids);
        };
        $tags = array_map(static fn(array $tag): array => ['name' => (string) $tag['name'], 'slug' => (string) $tag['slug'], 'icon' => (string) ($tag['icon_svg'] ?? '')],
            array_values(array_filter($this->repository->tagOptions(), static fn(array $tag): bool => $tagIds === null || in_array((int) $tag['id'], $tagIds, true))));
        return ['format' => self::FORMAT, 'version' => self::VERSION, 'categories' => $tree($roots), 'tags' => $tags];
    }

    /** Refuses anything but a catalogue file of this version. */
    public static function check(mixed $catalogue): void
    {
        if (!is_array($catalogue) || ($catalogue['format'] ?? null) !== self::FORMAT || (int) ($catalogue['version'] ?? 0) !== self::VERSION) {
            throw new InvalidArgumentException('This is not a CattoLMS catalogue file (format "' . self::FORMAT . '", version ' . self::VERSION . ').');
        }
    }

    /**
     * What import() would do: the categories and tags it would make, and how many are on the site already.
     *
     * @param array<string,mixed> $catalogue
     * @return array{categories_new:list<string>,categories_kept:int,tags_new:list<string>,tags_kept:int}
     */
    public function plan(array $catalogue): array
    {
        self::check($catalogue);
        $plan = ['categories_new' => [], 'categories_kept' => 0, 'tags_new' => [], 'tags_kept' => 0];
        $walk = function (array $nodes, string $path) use (&$walk, &$plan): void {
            foreach ($nodes as $node) {
                $name = trim((string) ($node['name'] ?? ''));
                $slug = trim((string) ($node['slug'] ?? '')) ?: Slug::from($name);
                $here = $path === '' ? $name : $path . self::SEPARATOR . $name;
                if ($this->repository->categoryBySlug($slug) === null) $plan['categories_new'][] = $here;
                else $plan['categories_kept']++;
                $walk((array) ($node['children'] ?? []), $here);
            }
        };
        $walk((array) ($catalogue['categories'] ?? []), '');
        foreach ((array) ($catalogue['tags'] ?? []) as $tag) {
            $name = trim((string) ($tag['name'] ?? ''));
            if ($name === '') continue;
            if ($this->repository->tagBySlug(Slug::from($name)) === null) $plan['tags_new'][] = $name;
            else $plan['tags_kept']++;
        }
        return $plan;
    }

    /**
     * Puts the file's categories and tags on the site, as ADMIN (who must have signed in once).
     *
     * @param array<string,mixed> $catalogue
     * @return array{categories_created:int,categories_kept:int,tags_created:int,tags_kept:int}
     */
    public function import(array $catalogue, ?int $actor = null): array
    {
        self::check($catalogue);
        $actor ??= $this->roles->firstUserWithRole('ADMIN') ?? throw new InvalidArgumentException('Sign ADMIN in once before importing the catalogue: the import is made as ADMIN.');
        $report = ['categories_created' => 0, 'categories_kept' => 0, 'tags_created' => 0, 'tags_kept' => 0];
        $this->importCategories((array) ($catalogue['categories'] ?? []), null, $actor, $report);
        foreach ((array) ($catalogue['tags'] ?? []) as $tag) {
            $name = trim((string) ($tag['name'] ?? ''));
            if ($name === '') continue;
            $icon = self::icon($tag['icon'] ?? '', 'icon of the tag "' . $name . '"', UploadedSvg::ICON_BYTES);
            $existing = $this->repository->tagBySlug(Slug::from($name));
            if ($existing === null) {
                $this->courses->createTag(['name' => $name], $actor, $icon);
                $report['tags_created']++;
            } else {
                if ($icon !== null && $icon !== (string) ($existing['icon_svg'] ?? '')) $this->repository->setTagIcon((int) $existing['id'], $icon);
                $report['tags_kept']++;
            }
        }
        return $report;
    }

    /**
     * @param list<array<string,mixed>> $nodes
     * @param array<string,mixed> $report
     */
    private function importCategories(array $nodes, ?int $parentId, int $actor, array &$report): void
    {
        foreach ($nodes as $node) {
            $name = trim((string) ($node['name'] ?? ''));
            $slug = trim((string) ($node['slug'] ?? '')) ?: Slug::from($name);
            $icon = self::icon($node['icon'] ?? '', 'icon of the category "' . $name . '"', UploadedSvg::ICON_BYTES);
            $existing = $this->repository->categoryBySlug($slug);
            if ($existing === null) {
                $id = (int) $this->courses->createCategory(['name' => $name, 'slug' => $slug, 'description' => (string) ($node['description'] ?? '')], $actor, $parentId, $icon)['id'];
                $report['categories_created']++;
            } else {
                $id = (int) $existing['id'];
                if ($icon !== null && $icon !== (string) ($existing['icon_svg'] ?? '')) $this->repository->setCategoryIcon($id, $icon);
                $report['categories_kept']++;
            }
            $this->importCategories((array) ($node['children'] ?? []), $id, $actor, $report);
        }
    }

    private static function icon(mixed $svg, string $what, int $limit): ?string
    {
        return is_string($svg) && trim($svg) !== '' ? UploadedSvg::validate($svg, $limit, $what) : null;
    }
}
