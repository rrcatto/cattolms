   "courses": [{"file", "slug", "title", "category", "position", "related": [slugs], "tags": [names], "cover", "price", "was_price", "access_period"}]}
"category" is the path of names joined by " › ". "position" is the course's place in the catalogue, or null.
"related" names the courses related to it by slug; a relation is both courses', so each pair may be given once.
