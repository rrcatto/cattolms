tree, the tags, every icon and cover picture, and for each course the file it was imported from, its
category, its tags, its cover and its default price and was price.

export() writes what the database holds. import() puts it back: each category (parents first) and tag
is created through CourseService as ADMIN would at Course categories and Course Tags, or given the file's
