declare(strict_types=1);

namespace CattoLearning\Course;

use CattoLearning\Infrastructure\Persistence\RoleRepository;
use CattoLearning\Support\AccessPeriod;
use CattoLearning\Support\Money;
use CattoLearning\Support\Slug;
use CattoLearning\View\Artwork\UploadedSvg;
use InvalidArgumentException;

final class CatalogueFile
{
    public const FORMAT = 'cattolms-catalogue';
    public const VERSION = 1;
    public const SEPARATOR = ' › ';

    public function __construct(
        private readonly CourseService $courses,
        private readonly CourseRepository $repository,
        private readonly RoleRepository $roles,
    ) {}

    /** The catalogue file published with the code: the starter categories and tags, and the owner's courses' details. */
    public static function bundledPath(): string
    {
        return dirname(__DIR__, 2) . '/resources/catalogue/catalogue.json';
    }

    /**
     * What the database holds, in the catalogue file's shape.
     *
     * @return array<string,mixed>
     */
    public function export(): array
    {
        $nodes = [];
        $roots = [];
        $paths = [];
        foreach ($this->repository->catalogueCategories() as $row) {
            $id = (int) $row['id'];
            $parent = $row['parent_id'] === null ? null : (int) $row['parent_id'];
            $paths[$id] = ($parent !== null && isset($paths[$parent]) ? $paths[$parent] . self::SEPARATOR : '') . (string) $row['name'];
            $nodes[$id] = ['name' => (string) $row['name'], 'slug' => (string) $row['slug'], 'description' => (string) ($row['description'] ?? ''),
                'icon' => (string) ($row['icon_svg'] ?? ''), 'children' => [], 'parent' => $parent];
        }
        foreach ($nodes as $id => $node) {
            if ($node['parent'] === null || !isset($nodes[$node['parent']])) $roots[] = $id;
            else $nodes[$node['parent']]['children'][] = $id;
        }
        $tree = static function (array $ids) use (&$tree, $nodes): array {
            return array_map(static function (int $id) use ($tree, $nodes): array {
                $node = $nodes[$id];
                unset($node['parent']);
                $node['children'] = $tree($node['children']);
                if ($node['children'] === []) unset($node['children']);
                return $node;
            }, $ids);
        };
        $tags = array_map(static fn(array $tag): array => ['name' => (string) $tag['name'], 'slug' => (string) $tag['slug'], 'icon' => (string) ($tag['icon_svg'] ?? '')],
            $this->repository->tagOptions());
        $courses = [];
        foreach ($this->repository->catalogueCourses() as $course) {
            $price = $course['price_minor_units'] === null ? null : (int) $course['price_minor_units'];
            $courses[] = [
                'file' => (string) ($course['source_filename'] ?? ''),
                'slug' => (string) $course['slug'],
                'title' => (string) $course['title'],
                'category' => $course['category_id'] === null ? '' : ($paths[(int) $course['category_id']] ?? ''),
                'position' => $course['catalogue_position'] === null ? null : (int) $course['catalogue_position'],
                'related' => $course['related_slugs'] === '' ? [] : explode('|', (string) $course['related_slugs']),
                'tags' => $course['tag_names'] === '' ? [] : explode('|', (string) $course['tag_names']),
                'cover' => (string) ($course['cover_svg'] ?? ''),
                'price' => $price === null ? null : Money::strictMinorUnits($price, 'ZAR')->toMajorUnits(),
                'was_price' => $course['was_price_minor_units'] === null ? null : Money::strictMinorUnits((int) $course['was_price_minor_units'], 'ZAR')->toMajorUnits(),
                'access_period' => $course['access_period_seconds'] === null ? null : AccessPeriod::label((int) $course['access_period_seconds']),
            ];
        }
        return ['format' => self::FORMAT, 'version' => self::VERSION, 'categories' => $tree($roots), 'tags' => $tags, 'courses' => $courses];
    }

    /**
     * Puts the file's categories and tags on the site, and on each course already there its tags, its cover
     * and, when it has no category, its category. Prices are never taken from the file. Run as the site's
     * ADMIN account, which must exist.
     *
     * The file is published with the code (resources/catalogue/catalogue.json, owner 2026-10-20: "I might
     * want to adjust the files containing categories and tags - be sure to publish these files"): a new
     * installation loads its categories and tags. A site's own catalogue file, kept privately, also lists its
     * courses: a site that imports the same courses gets their categories, tags and covers from it.
     *
     * @param array<string,mixed> $catalogue
     * @return array{categories_created:int,categories_kept:int,tags_created:int,tags_kept:int,courses_updated:int,courses_missing:list<string>}
     */
    public function import(array $catalogue): array
    {
        if (($catalogue['format'] ?? null) !== self::FORMAT || (int) ($catalogue['version'] ?? 0) !== self::VERSION) {
            throw new InvalidArgumentException('This is not a CattoLMS catalogue file (format "' . self::FORMAT . '", version ' . self::VERSION . ').');
        }
        $actor = $this->roles->firstUserWithRole('ADMIN') ?? throw new InvalidArgumentException('Sign ADMIN in once before importing the catalogue: the import is made as ADMIN.');
        $report = ['categories_created' => 0, 'categories_kept' => 0, 'tags_created' => 0, 'tags_kept' => 0, 'courses_updated' => 0, 'courses_missing' => []];
        $this->importCategories((array) ($catalogue['categories'] ?? []), null, $actor, $report);
        foreach ((array) ($catalogue['tags'] ?? []) as $tag) {
            $name = trim((string) ($tag['name'] ?? ''));
            $icon = self::icon($tag['icon'] ?? '', 'icon of the tag "' . $name . '"', UploadedSvg::ICON_BYTES);
            $existing = $this->repository->tagBySlug(Slug::from($name));
            if ($existing === null) {
                $this->courses->createTag(['name' => $name], $actor, $icon);
                $report['tags_created']++;
            } else {
                if ($icon !== null) $this->repository->setTagIcon((int) $existing['id'], $icon);
                $report['tags_kept']++;
            }
        }
        // A course's category in the file, by its path of names, for the courses already on the site.
        $categoryByPath = [];
        $pathById = [];
        foreach ($this->repository->catalogueCategories() as $row) {
            $parent = $row['parent_id'] === null ? null : (int) $row['parent_id'];
            $path = ($parent !== null && isset($pathById[$parent]) ? $pathById[$parent] . self::SEPARATOR : '') . (string) $row['name'];
            $pathById[(int) $row['id']] = $path;
            $categoryByPath[$path] = (int) $row['id'];
        }
        foreach ((array) ($catalogue['courses'] ?? []) as $entry) {
            $slug = (string) ($entry['slug'] ?? '');
            $course = $slug === '' ? null : $this->repository->findBySlug($slug);
            if ($course === null) {
                $report['courses_missing'][] = $slug !== '' ? $slug : (string) ($entry['file'] ?? '?');
                continue;
            }
            // Its category only when it has none: a category chosen on the site is kept (owner, 2026-10-20: the
            // file gives courses their categories, tags and covers, never their prices).
            $category = $categoryByPath[(string) ($entry['category'] ?? '')] ?? null;
            if ($category !== null) $this->repository->categoriseIfUncategorised((int) $course['id'], $category);
            $this->courses->setCourseTagsByName((int) $course['id'], array_map('strval', (array) ($entry['tags'] ?? [])), $actor);
            $cover = self::icon($entry['cover'] ?? '', 'cover of "' . $slug . '"', UploadedSvg::COVER_BYTES);
            if ($cover !== null) $this->courses->setCourseCover((int) $course['id'], $cover, $actor);
            // Its place in the catalogue, when the file gives one (owner, 2026-10-20).
            if (array_key_exists('position', $entry)) $this->repository->setCataloguePosition((int) $course['id'], CourseService::cataloguePosition($entry['position']));
            $report['courses_updated']++;
        }
        // The related courses last, once every course of the file has been seen (owner, 2026-10-20). A relation is both
        // courses', so a course's list adds to what the other courses' lists gave it, never takes away.
        foreach ((array) ($catalogue['courses'] ?? []) as $entry) {
            if (!array_key_exists('related', $entry)) continue;
            $course = $this->repository->findBySlug((string) ($entry['slug'] ?? ''));
            if ($course === null) continue;
            $current = array_map(fn(int $id): string => (string) ($this->repository->findById($id)['slug'] ?? ''), $this->repository->relatedCourseIds((int) $course['id']));
            $this->courses->setRelatedCoursesBySlug((int) $course['id'], array_values(array_unique(array_merge($current, array_map('strval', (array) $entry['related'])))));
        }
        return $report;
    }

    /**
     * @param list<array<string,mixed>> $nodes
     * @param array<string,mixed> $report
     */
    private function importCategories(array $nodes, ?int $parentId, int $actor, array &$report): void
    {
        foreach ($nodes as $node) {
            $name = trim((string) ($node['name'] ?? ''));
            $slug = trim((string) ($node['slug'] ?? '')) ?: Slug::from($name);
            $icon = self::icon($node['icon'] ?? '', 'icon of the category "' . $name . '"', UploadedSvg::ICON_BYTES);
            $existing = $this->repository->categoryBySlug($slug);
            if ($existing === null) {
                $id = (int) $this->courses->createCategory(['name' => $name, 'slug' => $slug, 'description' => (string) ($node['description'] ?? '')], $actor, $parentId, $icon)['id'];
                $report['categories_created']++;
            } else {
                $id = (int) $existing['id'];
                if ($icon !== null) $this->repository->setCategoryIcon($id, $icon);
                $report['categories_kept']++;
            }
            $this->importCategories((array) ($node['children'] ?? []), $id, $actor, $report);
        }
    }

    private static function icon(mixed $svg, string $what, int $limit): ?string
    {
        return is_string($svg) && trim($svg) !== '' ? UploadedSvg::validate($svg, $limit, $what) : null;
    }
}
