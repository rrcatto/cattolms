{
    private const MAXIMUM_ENTRIES = 3000;
    private const MAXIMUM_UNPACKED_BYTES = 200 * 1024 * 1024;
    private const MODULE_FILES = ['module.json', 'lesson.html', 'summary.html', 'practical.html', 'practical-answer.html'];

    /** @var array<string,string> every file, by its path inside the package */
    private array $files = [];
    /** @var list<string> */
    private array $errors = [];
    /** @var list<string> */
    private array $warnings = [];

    private function __construct(private readonly JsonSchema $schema)
    {
    }

    /** Whether a zip holds a course package 3.0 (a course.json at its top or in its one folder). */
    public static function isPackage(string $path): bool
    {
        $zip = new ZipArchive();
        if ($zip->open($path, ZipArchive::RDONLY) !== true) { return false; }
        try {
            for ($index = 0; $index < min($zip->numFiles, self::MAXIMUM_ENTRIES); $index++) {
                $name = (string) $zip->getNameIndex($index);
                if (preg_match('#^([^/]+/)?course\.json$#', $name) === 1) { return true; }
            }
            return false;
        } finally {
            $zip->close();
        }
    }

    /**
     * The package as the course package every import reads, with the specification's guidance as warnings; refused,
     * with every error, when it cannot be imported.
     *
     * @return array{package:array<string,mixed>,warnings:list<string>}
     */
    public static function read(string $zipPath): array
    {
        $reader = new self(JsonSchema::bundled());
        $reader->unpack($zipPath);
        $package = $reader->convert();
        if ($reader->errors !== []) {
            throw new InvalidArgumentException('The course package cannot be imported. Fix these and try again: ' . implode(' · ', array_slice($reader->errors, 0, 40)) . (count($reader->errors) > 40 ? ' · and ' . (count($reader->errors) - 40) . ' more.' : ''));
        }
        return ['package' => $package, 'warnings' => $reader->warnings];
    }

    private function unpack(string $path): void
    {
        $zip = new ZipArchive();
        if ($zip->open($path, ZipArchive::RDONLY) !== true) { throw new InvalidArgumentException('The file is not a zip: choose a course package 3.0.'); }
        try {
            if ($zip->numFiles > self::MAXIMUM_ENTRIES) { throw new InvalidArgumentException('The package holds more than ' . self::MAXIMUM_ENTRIES . ' files.'); }
            $names = [];
            $unpacked = 0;
            for ($index = 0; $index < $zip->numFiles; $index++) {
                $stat = $zip->statIndex($index);
                if ($stat === false) { continue; }
                $name = (string) $stat['name'];
                if (str_starts_with($name, '__MACOSX/') || str_contains($name, '/.') || str_starts_with($name, '.') || str_ends_with($name, '/')) { continue; }
                if (str_starts_with($name, '/') || in_array('..', explode('/', $name), true)) { throw new InvalidArgumentException('The package holds a path outside it: ' . $name . '.'); }
                $unpacked += (int) $stat['size'];
                if ($unpacked > self::MAXIMUM_UNPACKED_BYTES) { throw new InvalidArgumentException('The package unpacks to more than 200 MB.'); }
                $names[$index] = $name;
            }
            // The package may sit in one folder named after its course code, or at the zip's top.
            $tops = array_unique(array_map(static fn(string $name): string => str_contains($name, '/') ? explode('/', $name, 2)[0] . '/' : '', $names));
            $prefix = count($tops) === 1 && $tops[0] !== '' && !in_array('course.json', $names, true) ? $tops[0] : '';
            foreach ($names as $index => $name) {
                $relative = $prefix !== '' && str_starts_with($name, $prefix) ? substr($name, strlen($prefix)) : $name;
                $this->files[$relative] = (string) $zip->getFromIndex($index);
            }
        } finally {
            $zip->close();
        }
        if (!isset($this->files['course.json'])) { throw new InvalidArgumentException('The zip has no course.json: choose a course package 3.0 made to the course specification.'); }
    }

    /** @return array<string,mixed>|null */
    private function json(string $file, string $definition): ?array
    {
        if (!isset($this->files[$file])) { $this->errors[] = $file . ' is missing'; return null; }
        $data = json_decode($this->files[$file], true);
        if (!is_array($data)) { $this->errors[] = $file . ' is not valid JSON: ' . json_last_error_msg(); return null; }
        foreach ($this->schema->problems($data, $definition, $file) as $problem) { $this->errors[] = $problem; }
        return $data;
    }

    private function html(string $file, ?string $moduleFolder = null): string
    {
        $html = $this->files[$file] ?? '';
        if (preg_match('/<(script|style)\b/i', $html) === 1) { $this->errors[] = $file . ' holds a script or a style: lessons are plain HTML'; }
        if (preg_match('/<h1\b/i', $html) === 1) { $this->errors[] = $file . ' holds an h1: start at h2'; }
        if (preg_match('/^\s*<!doctype|<(html|body|head)\b/i', $html) === 1) { $this->errors[] = $file . ' is a fragment: no doctype, html, head or body'; }
        // A picture in the module's pictures folder is kept in the lesson itself, so the lesson travels whole.
        return (string) preg_replace_callback('/(<img\b[^>]*\bsrc=")(pictures\/[a-z0-9][a-z0-9._-]*)(")/i', function (array $match) use ($file, $moduleFolder): string {
            $picture = $moduleFolder === null ? null : $this->picture($moduleFolder . '/' . $match[2]);
            if ($picture === null) { $this->errors[] = $file . ': ' . $match[2] . ' is not in the module\'s pictures folder'; return $match[0]; }
            return $match[1] . (str_starts_with($picture, 'data:') ? $picture : 'data:image/svg+xml;base64,' . base64_encode($picture)) . $match[3];
        }, $html);
    }

    /** A picture as a slide keeps it: an SVG drawing's text, or a PNG or JPEG as a data address. */
    private function picture(string $file): ?string
    {
        $bytes = $this->files[$file] ?? null;
        if ($bytes === null) { return null; }
        if (str_ends_with(strtolower($file), '.svg')) { return SlideDeck::isPicture($bytes) ? $bytes : null; }
        $type = str_ends_with(strtolower($file), '.png') ? 'image/png' : 'image/jpeg';
        return 'data:' . $type . ';base64,' . base64_encode($bytes);
    }

    /** @return array<string,mixed> */
    private function convert(): array
    {
        $course = $this->json('course.json', 'courseFile') ?? [];
        $info = (array) ($course['course'] ?? []);
        $code = (string) ($info['code'] ?? 'COURSE');
        $prefix = strtolower($code);
        $modules = array_values(array_filter((array) ($course['modules'] ?? []), 'is_string'));
        $expected = array_map(static fn(int $n): string => 'm' . $n, range(1, max(1, count($modules))));
        if ($modules !== [] && $modules !== $expected) { $this->errors[] = 'course.json: modules must be ' . implode(', ', $expected) . ' in order'; }
        foreach (array_keys($this->files) as $file) {
            if (preg_match('#^modules/([^/]+)/#', $file, $match) === 1 && $match[1] !== 'review' && !in_array($match[1], $modules, true)) { $this->errors[] = 'modules/' . $match[1] . ' is not listed in course.json\'s modules'; break; }
        }
        if (!isset($this->files['introduction.html'])) { $this->errors[] = 'introduction.html is missing'; }
        $items = [];
        $structure = [];
        $nodes = 0;
        $node = static function (array $fields) use (&$structure, &$nodes): string {
            $key = 'n' . (++$nodes);
            $structure[] = ['node_key' => $key] + $fields + ['relative_delay_minutes' => 0, 'public_preview' => false];
            return $key;
        };
        $position = 0;
        if (isset($this->files['trailer.json'])) {
            $trailer = $this->json('trailer.json', 'deck');
            if ($trailer !== null) {
                $items[] = $this->deckItem($prefix . '-trailer', $trailer, 'trailer.json', null);
                $node(['parent_node_key' => null, 'position' => ++$position, 'node_type' => 'item', 'item_key' => $prefix . '-trailer', 'public_preview' => true, 'assessment_role' => 'content']);
            }
        }
        if (isset($this->files['diagnostic.json'])) {
            $diagnostic = $this->json('diagnostic.json', 'diagnosticFile');
            if ($diagnostic !== null) {
                $items[] = $this->assessmentItem($prefix . '-diagnostic', 'diagnostic', 'Diagnostic', $diagnostic, 'diagnostic.json', $prefix, $modules);
                $node(['parent_node_key' => null, 'position' => ++$position, 'node_type' => 'item', 'item_key' => $prefix . '-diagnostic', 'assessment_role' => 'content']);
            }
        }
        // A long course's parts hold its modules; without them the modules sit at the top.
        $parts = array_values(array_filter((array) ($course['parts'] ?? []), 'is_array'));
        if ($parts !== [] && array_merge(...array_map(static fn(array $part): array => (array) $part['modules'], $parts)) !== $modules) { $this->errors[] = 'course.json: parts must hold every module exactly once, in the order of modules'; }
        $partOf = [];
        foreach ($parts as $part) {
            $key = $node(['parent_node_key' => null, 'position' => ++$position, 'node_type' => 'section', 'title' => (string) $part['title'], 'introduction_html' => '', 'show_outline' => true, 'numbered' => false]);
            foreach ((array) $part['modules'] as $module) { $partOf[(string) $module] = $key; }
        }
        $inPart = [];
        $finalModules = $modules;
        if (isset($this->files['modules/review/module.json'])) { $finalModules[] = 'review'; }
        foreach ($finalModules as $module) {
            $parent = $partOf[$module] ?? null;
            $at = $parent === null ? ++$position : ($inPart[$parent] = ($inPart[$parent] ?? 0) + 1);
            $this->module($module, $prefix, $modules, $items, $node, $parent, $at);
        }
        if (!isset($this->files['final.json'])) { $this->errors[] = 'final.json is missing: every course ends with a final assessment'; }
        else {
            $final = $this->json('final.json', 'finalFile');
            if ($final !== null) {
                if (count((array) ($final['questions'] ?? [])) < 10) { $this->errors[] = 'final.json: questions: never fewer than 10'; }
                $items[] = $this->assessmentItem($prefix . '-final', 'assessment', 'Final assessment', $final, 'final.json', $prefix, $modules);
                $node(['parent_node_key' => null, 'position' => ++$position, 'node_type' => 'item', 'item_key' => $prefix . '-final', 'assessment_role' => 'final']);
            }
        }
        $catalogue = (array) ($course['catalogue'] ?? []);
        if (isset($this->files['cover.svg'])) {
            if (preg_match('/<script\b|\son[a-z]+\s*=/i', $this->files['cover.svg']) === 1) { $this->errors[] = 'cover.svg must not hold scripts'; }
            else { $catalogue['cover'] = $this->files['cover.svg']; }
        }
        $bands = [];
        foreach (array_values((array) ($course['grade_bands'] ?? [])) as $index => $band) {
            $bands[] = ['position' => $index + 1, 'grade_code' => (string) $band['code'], 'grade_label' => (string) $band['label'], 'minimum_percentage' => (float) $band['from'], 'is_passing' => (bool) $band['passing']];
        }
        $starts = array_column($bands, 'minimum_percentage');
        if ($bands !== [] && ($starts !== array_values(array_unique($starts)) || $starts !== self::descending($starts) || end($starts) != 0.0)) { $this->errors[] = 'course.json: grade_bands must start at different percentages, highest first, the lowest from 0'; }
        $certificate = (array) ($info['certificate'] ?? []);
        return [
            'format' => 'catto-learning-course',
            'schema_version' => '2.1',
            'course' => [
                'code' => $code,
                'slug' => Slug::from((string) ($info['title'] ?? $code)),
                'title' => (string) ($info['title'] ?? ''),
                'subtitle' => (string) ($info['subtitle'] ?? ''),
                'summary' => (string) ($info['summary'] ?? ''),
                'description_html' => '<p>' . htmlspecialchars((string) ($info['summary'] ?? ''), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8') . '</p>',
                'level' => (string) ($info['level'] ?? ''),
                'introduction_html' => $this->html('introduction.html'),
                'show_outline_on_intro' => true,
                'certificate_enabled' => (bool) ($certificate['enabled'] ?? true),
                'certificate_accreditation' => (string) ($certificate['accreditation'] ?? ''),
                'presentation_css' => (string) ($this->files['styles.css'] ?? ''),
                'content_checked' => (string) ($info['content_checked'] ?? ''),
            ],
            'catalogue' => $catalogue === [] ? null : $catalogue,
            'resources' => [],
            'course_items' => $items,
            'structure' => $structure,
            'grade_bands' => $bands,
        ];
    }

    /**
     * One module's section and its parts, in the specification's order.
     *
     * @param list<string> $modules
     * @param list<array<string,mixed>> $items
     * @param callable(array<string,mixed>):string $node
     */
    private function module(string $module, string $prefix, array $modules, array &$items, callable $node, ?string $parent, int $position): void
    {
        $folder = 'modules/' . $module;
        $data = $this->json($folder . '/module.json', 'moduleFile');
        if ($data === null) { return; }
        foreach (array_keys($this->files) as $file) {
            if (str_starts_with($file, $folder . '/') && !in_array(substr($file, strlen($folder) + 1), self::MODULE_FILES, true) && !str_starts_with(substr($file, strlen($folder) + 1), 'pictures/')) {
                $this->warnings[] = $file . ' is not a file a module holds: it was left out';
            }
        }
        $review = $module === 'review';
        if (($data['key'] ?? '') !== $module) { $this->errors[] = $folder . '/module.json: key must be "' . $module . '", the folder\'s name'; }
        if ($review !== (($data['kind'] ?? 'module') === 'review')) { $this->errors[] = $folder . '/module.json: the review module is the folder review with kind "review", and only that one'; }
        $title = (string) ($data['title'] ?? '');
        if (preg_match('/^(module|week|part)\s*[0-9]/i', $title) === 1) { $this->errors[] = $folder . '/module.json: title must not hold the module\'s number: the site numbers modules itself'; }
        foreach ($review ? [] : ['summary', 'flashcards', 'practical', 'assessment'] as $part) {
            if (!isset($data[$part])) { $this->errors[] = $folder . '/module.json needs "' . $part . '"'; }
        }
        $introduction = implode('', array_map(static fn(string $paragraph): string => '<p>' . htmlspecialchars($paragraph, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8') . '</p>', array_values(array_filter((array) ($data['introduction'] ?? []), 'is_string'))));
        $outcomes = array_values(array_filter((array) ($data['outcomes'] ?? []), 'is_string'));
        if ($outcomes !== []) {
            $introduction .= '<p>In this module you will learn to:</p><ol class="cl-section-outcomes">' . implode('', array_map(static fn(string $outcome): string => '<li>' . htmlspecialchars($outcome, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8') . '</li>', $outcomes)) . '</ol>';
        }
        $section = $node(['parent_node_key' => $parent, 'position' => $position, 'node_type' => 'section', 'title' => $review && $title === '' ? 'Review' : $title, 'introduction_html' => $introduction, 'show_outline' => true, 'numbered' => !$review]);
        $base = $prefix . '-' . $module;
        $at = 0;
        $place = static function (string $key, string $role = 'content') use ($node, $section, &$at): void {
            $node(['parent_node_key' => $section, 'position' => ++$at, 'node_type' => 'item', 'item_key' => $key, 'assessment_role' => $role]);
        };
        if (isset($data['presentation'])) {
            $items[] = $this->deckItem($base . '-presentation', (array) $data['presentation'], $folder . '/module.json: presentation', $folder);
            $place($base . '-presentation');
        }
        if (isset($data['video'])) {
            $video = (array) $data['video'];
            if (str_contains((string) ($video['youtube_id'] ?? ''), 'EXAMPLE')) { $this->warnings[] = $folder . ': the video is the example\'s placeholder'; }
            $items[] = ['item_key' => $base . '-video', 'item_type' => 'youtube', 'title' => (string) ($video['title'] ?? 'Video'), 'description_html' => '', 'content_source' => '',
                'type_config' => array_filter(['youtube_id' => (string) ($video['youtube_id'] ?? ''), 'caption' => (string) ($video['watch_for'] ?? ''), 'start_seconds' => isset($video['start_seconds']) ? (int) $video['start_seconds'] : null, 'channel' => (string) ($video['channel'] ?? ''), 'checked' => (string) ($video['checked'] ?? '')], static fn(mixed $value): bool => $value !== null && $value !== ''),
                'estimated_minutes' => isset($video['minutes']) ? (int) $video['minutes'] : null, 'questions' => []];
            $place($base . '-video');
        }
        if (!isset($this->files[$folder . '/lesson.html'])) { $this->errors[] = $folder . '/lesson.html is missing'; }
        $items[] = ['item_key' => $base . '-lesson', 'item_type' => 'html_lesson', 'title' => (string) (($data['lesson']['title'] ?? '') ?: $title), 'description_html' => '', 'content_source' => $this->html($folder . '/lesson.html', $folder), 'type_config' => [], 'estimated_minutes' => isset($data['lesson']['minutes']) ? (int) $data['lesson']['minutes'] : null, 'questions' => []];
        $place($base . '-lesson');
        if (isset($data['summary']) || isset($this->files[$folder . '/summary.html'])) {
            if (!isset($this->files[$folder . '/summary.html'])) { $this->errors[] = $folder . '/summary.html is missing'; }
            $items[] = ['item_key' => $base . '-summary', 'item_type' => 'html_lesson', 'title' => 'Summary', 'description_html' => '', 'content_source' => $this->html($folder . '/summary.html', $folder), 'type_config' => ['presentation_role' => 'summary'], 'estimated_minutes' => isset($data['summary']['minutes']) ? (int) $data['summary']['minutes'] : null, 'questions' => []];
            $place($base . '-summary');
        }
        if (isset($data['flashcards'])) {
            try {
                $cards = FlashCards::validate((array) ($data['flashcards']['cards'] ?? []));
                $items[] = ['item_key' => $base . '-flashcards', 'item_type' => 'flashcards', 'title' => 'Flash cards', 'description_html' => '', 'content_source' => '', 'type_config' => ['cards' => $cards], 'estimated_minutes' => null, 'questions' => []];
                $place($base . '-flashcards');
                if (!$review && (count($cards) < 10 || count($cards) > 20)) { $this->warnings[] = $folder . ': ' . count($cards) . ' flash cards, where 10 to 20 are right'; }
            } catch (InvalidArgumentException $refused) {
                $this->errors[] = $folder . '/module.json: flashcards: ' . $refused->getMessage();
            }
        }
        if (isset($data['practical']) || isset($this->files[$folder . '/practical.html'])) {
            $tasks = $this->html($folder . '/practical.html', $folder);
            $answers = $this->html($folder . '/practical-answer.html', $folder);
            if (!isset($this->files[$folder . '/practical.html'])) { $this->errors[] = $folder . '/practical.html is missing'; }
            if (!isset($this->files[$folder . '/practical-answer.html'])) { $this->errors[] = $folder . '/practical-answer.html is missing'; }
            if (self::headings($tasks, 'task') !== self::headings($answers, 'answer')) { $this->errors[] = $folder . '/practical-answer.html must hold one section class="answer" per task, in the same order, each h3 exactly like its task\'s'; }
            $items[] = ['item_key' => $base . '-practical', 'item_type' => 'practical', 'title' => (string) (($data['practical']['title'] ?? '') ?: 'Practical work'), 'description_html' => '', 'content_source' => $tasks, 'type_config' => ['answer_html' => $answers], 'estimated_minutes' => isset($data['practical']['minutes']) ? (int) $data['practical']['minutes'] : null, 'questions' => []];
            $place($base . '-practical');
        }
        if (isset($data['assessment'])) {
            $items[] = $this->assessmentItem($base . '-assessment', 'assessment', ($review ? 'Review' : $title) . ' assessment', (array) $data['assessment'], $folder . '/module.json: assessment', $prefix, $modules);
            $place($base . '-assessment', 'graded');
        }
    }

    /**
     * A Presentation as an item, its slides checked as CatWalk checks them and its pictures kept in it.
     *
     * @param array<string,mixed> $deck
     * @return array<string,mixed>
     */
    private function deckItem(string $key, array $deck, string $where, ?string $folder): array
    {
        $slides = [];
        foreach ((array) ($deck['slides'] ?? []) as $slide) {
            if (is_array($slide) && ($slide['layout'] ?? '') === 'picture') {
                $picture = $folder === null ? null : $this->picture($folder . '/pictures/' . (string) ($slide['picture'] ?? ''));
                if ($picture === null) { $this->errors[] = $where . ': the picture ' . ($slide['picture'] ?? '') . ' is not in the module\'s pictures folder'; }
                $slide['picture'] = $picture ?? '';
            }
            $slides[] = $slide;
        }
        $config = ['kind' => (string) ($deck['kind'] ?? 'intro'), 'theme' => (string) ($deck['theme'] ?? (($deck['kind'] ?? '') === 'trailer' ? 'dark' : 'light')), 'slides' => $slides];
        try {
            $config = SlideDeck::validate($config);
            foreach (SlideDeck::warnings($config) as $warning) { $this->warnings[] = $where . ': ' . $warning; }
        } catch (InvalidArgumentException $refused) {
            $this->errors[] = $where . ': ' . $refused->getMessage();
        }
        return ['item_key' => $key, 'item_type' => 'slide_deck', 'title' => (string) ($deck['title'] ?? 'Presentation'), 'description_html' => '', 'content_source' => '', 'type_config' => $config, 'estimated_minutes' => isset($deck['minutes']) ? (int) $deck['minutes'] : null, 'questions' => []];
    }

    /**
     * An assessment or diagnostic as an item: its questions in the shape every import reads.
     *
     * @param array<string,mixed> $data
     * @param list<string> $modules
     * @return array<string,mixed>
     */
    private function assessmentItem(string $key, string $type, string $title, array $data, string $where, string $prefix, array $modules): array
    {
        $questions = [];
        foreach (array_values((array) ($data['questions'] ?? [])) as $index => $question) {
            if (!is_array($question)) { continue; }
            $options = array_values((array) ($question['o'] ?? []));
            $answer = $question['a'] ?? null;
            if (!is_int($answer) || $answer >= count($options)) { $this->errors[] = $where . '[' . $index . '].a points at an option that is not there (counting from 0)'; }
            $remediation = [];
            foreach ((array) ($question['u'] ?? []) as $module) {
                if (!in_array($module, $modules, true)) { $this->errors[] = $where . '[' . $index . '].u: "' . $module . '" is not one of the course\'s modules'; continue; }
                $remediation[] = $prefix . '-' . $module . '-lesson';
            }
            if (isset($question['m']) && !in_array($question['m'], [...$modules, 'review'], true)) { $this->errors[] = $where . '[' . $index . '].m: "' . $question['m'] . '" is not one of the course\'s modules'; }
            $points = max(1, (int) ($question['p'] ?? 1));
            $questions[] = [
                'position' => $index + 1,
                'question_html' => htmlspecialchars((string) ($question['q'] ?? ''), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'),
                'points' => $points,
                'difficulty' => $points <= 1 ? 'introductory' : ($points === 2 ? 'standard' : 'advanced'),
                'practice_eligible' => true,
                'graded_eligible' => $type !== 'diagnostic',
                'incorrect_points' => 0,
                'remediation_item_keys' => $remediation,
                'explanation_html' => htmlspecialchars((string) ($question['e'] ?? ''), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'),
                'options' => array_map(static fn(int $i, mixed $option): array => ['position' => $i + 1, 'option_html' => htmlspecialchars((string) $option, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'), 'is_correct' => $i === $answer], array_keys($options), $options),
            ];
        }
        $count = count($questions);
        $asked = $type === 'diagnostic' ? $count : min($count, max(1, (int) ($data['ask'] ?? $count)));
        return [
            'item_key' => $key, 'item_type' => $type, 'title' => $title, 'description_html' => '', 'content_source' => '', 'type_config' => [],
            'instructions_html' => '<p>Answer every question, then submit the assessment.</p>', 'result_pass_html' => '', 'result_fail_html' => '',
            'pass_mark' => (float) ($data['pass_mark'] ?? 50), 'practice' => false, 'practice_enabled' => $type === 'assessment', 'practice_pool_mode' => 'both',
            'practice_question_count' => max(1, min(5, $count)), 'graded_question_count' => max(1, $asked), 'maximum_attempts' => null,
            'time_limit_seconds' => max(1800, $asked * 90), 'score_policy' => 'highest', 'randomise_questions' => true, 'randomise_options' => true, 'negative_marking' => false,
            'estimated_minutes' => null, 'questions' => $questions,
        ];
    }

    /** @return list<string> Each task's or answer's h3, in order. */
    private static function headings(string $html, string $kind): array
    {
        preg_match_all('#<section[^>]*class="[^"]*\b' . $kind . '\b[^"]*"[^>]*>\s*<h3[^>]*>(.*?)</h3>#si', $html, $matches);
        return array_map(static fn(string $heading): string => trim((string) preg_replace('/\s+/', ' ', html_entity_decode(strip_tags($heading), ENT_QUOTES | ENT_HTML5, 'UTF-8'))), $matches[1]);
    }

    /**
     * @param list<float> $values
     * @return list<float>
     */
    private static function descending(array $values): array
    {
        rsort($values);
        return $values;
    }
