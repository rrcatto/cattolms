declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;

use Doctrine\DBAL\Driver\Connection as DriverConnection;
use Doctrine\DBAL\Driver\Middleware\AbstractDriverMiddleware;
use SensitiveParameter;

final class SessionTimeZoneDriver extends AbstractDriverMiddleware
{
    /**
     * The timezone name is interpolated rather than bound because SET TIME ZONE is a utility
     * statement and takes no parameters. It comes from APP_TIMEZONE and is validated against PHP's
     * own timezone list by {@see SessionTimeZoneMiddleware} before it reaches here.
     */
    public function __construct(
        \Doctrine\DBAL\Driver $driver,
        private readonly string $timeZone
    ) {
        parent::__construct($driver);
    }

    /**
     * {@inheritDoc}
     */
    public function connect(
        #[SensitiveParameter]
        array $params,
    ): DriverConnection {
        $connection = parent::connect($params);
        $connection->exec("SET TIME ZONE '" . $this->timeZone . "'");

        return $connection;
    }
}
