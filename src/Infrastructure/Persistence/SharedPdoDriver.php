Description:
A Doctrine DBAL driver that hands back a PDO connection the platform already opened.

Architectural boundary: connection plumbing only. It opens nothing, closes nothing and knows no SQL.

Why this exists, and it is the thing that makes the persistence migration safe to do gradually.

The repositories are converted from F3 mappers and `DB\SQL` to DBAL one at a time, so for the whole
of that phase some repositories speak DBAL and the rest speak `DB\SQL`. Fifty call sites run inside
`TransactionManager::run()`, and a transaction is a property of a *connection*: if DBAL opened its
own, a converted repository writing inside a transaction an unconverted one began would be writing
outside it, and a rollback would leave half the work committed. Nothing would fail loudly. The rows
would simply be wrong.

Sharing one PDO removes the question. `BEGIN` issued through either wrapper is the same transaction,
because it is the same session, so a converted and an unconverted repository can appear in the same
`run()` closure and behave exactly as they did before.

DBAL 4 has no supported way to pass an existing PDO to `DriverManager`, which is why this is a
driver rather than a connection parameter. `Doctrine\DBAL\Driver\PDO\Connection` is public API and
takes a `PDO`, so the driver is the only piece missing.

This class is temporary. When the last repository is converted, `DB\SQL` goes, the driver goes with
it, and DBAL opens its own connection through `DriverManager` in the ordinary way.

Changelog:
2026/09/08 SAST
- Created for the v0.7 persistence migration.
*/

declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;

use Doctrine\DBAL\Driver;
use Doctrine\DBAL\Driver\API\ExceptionConverter;
use Doctrine\DBAL\Driver\API\PostgreSQL\ExceptionConverter as PostgreSQLExceptionConverter;
use Doctrine\DBAL\Driver\Connection as DriverConnection;
use Doctrine\DBAL\Driver\PDO\Connection as PdoConnection;
use Doctrine\DBAL\Platforms\AbstractPlatform;
use Doctrine\DBAL\Platforms\PostgreSQLPlatform;
use Doctrine\DBAL\ServerVersionProvider;
use PDO;

final class SharedPdoDriver implements Driver
{
    public function __construct(private readonly PDO $pdo)
    {
    }

    /**
     * Returns the connection the platform already holds.
     *
     * The parameters are ignored on purpose: the connection is already open, and honouring a second
     * set of credentials here would quietly produce a second session, which is the one thing this
     * class exists to prevent.
     *
     * @param array<string,mixed> $params
     */
    public function connect(array $params): DriverConnection
    {
        return new PdoConnection($this->pdo);
    }

    public function getDatabasePlatform(ServerVersionProvider $versionProvider): AbstractPlatform
    {
        return new PostgreSQLPlatform();
    }

    public function getExceptionConverter(): ExceptionConverter
    {
        return new PostgreSQLExceptionConverter();
    }
}
