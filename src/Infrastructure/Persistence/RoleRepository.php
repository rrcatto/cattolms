    /** @param list<string> $permissionKeys */
    public function replaceRolePermissions(int $roleId, array $permissionKeys): void
    {
        $role = $this->findById($roleId);
        if ($role === null) {
            throw new RuntimeException('The role does not exist.');
        }
        $roleKey = (string) $role['role_key'];
        if ($roleKey === RoleCatalog::ADMIN) {
            throw new RuntimeException('ADMIN permissions are immutable.');
        }
        foreach ($permissionKeys as $key) {
            if (!PermissionCatalog::isAssignableToRole($roleKey, $key)) {
                throw new RuntimeException('That permission is not assignable to the selected role family: ' . $key);
            }
        }

        $this->db->beginTransaction();
        try {
            $this->db->executeStatement('DELETE FROM role_permissions WHERE role_id=:role_id', ['role_id' => $roleId]);
            foreach ($permissionKeys as $key) {
                $this->db->executeStatement(
                    'INSERT INTO role_permissions (role_id,permission_id)
                     SELECT :role_id,p.id FROM permissions p WHERE p.permission_key=:permission_key
                     ON CONFLICT (role_id,permission_id) DO NOTHING',
                    ['role_id' => $roleId, 'permission_key' => $key]
                );
            }
            $this->db->commit();
        } catch (Throwable $e) {
            $this->db->rollBack();
            throw $e;
        }
    }

    /** @param list<string> $roles */
    public function replaceUserRoles(int $userId, array $roles): void
    {
        $allowed = array_map(static fn(array $row): string => (string) $row['role_key'], $this->all());
        $roles = array_values(array_unique(array_filter(
            array_map(static fn(string $role): string => strtoupper(trim($role)), $roles),
            static fn(string $role): bool => in_array($role, $allowed, true)
        )));
        if ($roles === []) {
            throw new RuntimeException('Every user must retain at least one role.');
        }
        RoleFamily::assertCompatible($roles);
        $family = RoleFamily::forRoleSet($roles);
        $baseline = $family === RoleFamily::SEED ? RoleCatalog::SEED_STUDENT : RoleCatalog::STUDENT;
        if (!in_array($baseline, $roles, true)) {
            $roles[] = $baseline;
        }
        RoleFamily::assertCompatible($roles);

        $current = $this->roles($userId);
        foreach ($current as $role) {
            if (!in_array($role, $roles, true)) {
                if (in_array($role, [RoleCatalog::STUDENT, RoleCatalog::SEED_STUDENT], true)) {
                    continue;
                }
                $this->revoke($userId, $role);
            }
        }
        foreach ($roles as $role) {
            $this->assign($userId, $role);
        }

        $opposite = $family === RoleFamily::SEED ? RoleCatalog::STUDENT : RoleCatalog::SEED_STUDENT;
        if (in_array($opposite, $this->roles($userId), true)) {
            $row = $this->roleByKey($opposite);
            if ($row !== null) {
                $this->db->executeStatement(
                    'DELETE FROM user_roles WHERE user_id=:user_id AND role_id=:role_id',
                    ['user_id' => $userId, 'role_id' => (int) $row['id']]
                );
            }
        }
    }

    /** @return array<string,mixed>|null */
    private function roleByKey(string $role): ?array
    {
        $rows = $this->db->fetchAllAssociative(
            'SELECT id,role_key,role_name,role_description FROM roles WHERE role_key=:role LIMIT 1',
            ['role' => $role]
        );
        return $rows[0] ?? null;
    }

    private function insertUserRole(int $userId, int $roleId): void
    {
        $this->db->executeStatement(
            'INSERT INTO user_roles (user_id,role_id,created_at,seed_token)
             VALUES (:user_id,:role_id,NOW(),:seed_token::uuid) ON CONFLICT (user_id,role_id) DO NOTHING',
            ['user_id' => $userId, 'role_id' => $roleId, 'seed_token' => $this->provenance->fromUser($userId)]
        );
    }
