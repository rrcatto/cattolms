declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;

final class CompanyLogoRepository
{
    public function __construct(private readonly Database $db)
    {
    }

    /**
     * What a company's picture is, without reading the logo's bytes. Null for a company that does not exist.
     *
     * @return array{public_id:string,uploaded:bool,upload_version:string}|null
     */
    public function state(int $companyId): ?array
    {
        $row = $this->db->fetchAssociative(
            "SELECT c.public_id::text AS public_id, l.byte_size, to_char(l.updated_at, 'YYYY-MM-DD HH24:MI:SS.US') AS updated_at
             FROM companies c LEFT JOIN company_logos l ON l.company_id = c.id WHERE c.id = :id",
            ['id' => $companyId]
        );
        if ($row === false) {
            return null;
        }
        $uploaded = $row['byte_size'] !== null;

        return [
            'public_id' => (string) $row['public_id'],
            'uploaded' => $uploaded,
            'upload_version' => $uploaded ? substr(sha1((string) $row['updated_at'] . (string) $row['byte_size']), 0, 12) : '',
        ];
    }

    /**
     * state() for many companies at once, keyed by company id (one query for a page of them).
     *
     * @param list<int> $companyIds
     * @return array<int, array{public_id:string,uploaded:bool,upload_version:string}>
     */
    public function states(array $companyIds): array
    {
        $companyIds = array_values(array_unique(array_filter(array_map('intval', $companyIds), static fn(int $id): bool => $id > 0)));
        if ($companyIds === []) {
            return [];
        }
        $states = [];
        $rows = $this->db->fetchAllAssociative(
            "SELECT c.id, c.public_id::text AS public_id, l.byte_size, to_char(l.updated_at, 'YYYY-MM-DD HH24:MI:SS.US') AS updated_at
             FROM companies c LEFT JOIN company_logos l ON l.company_id = c.id WHERE c.id = ANY(CAST(:ids AS BIGINT[]))",
            ['ids' => '{' . implode(',', $companyIds) . '}']
        );
        foreach ($rows as $row) {
            $uploaded = $row['byte_size'] !== null;
            $states[(int) $row['id']] = [
                'public_id' => (string) $row['public_id'],
                'uploaded' => $uploaded,
                'upload_version' => $uploaded ? substr(sha1((string) $row['updated_at'] . (string) $row['byte_size']), 0, 12) : '',
            ];
        }

        return $states;
    }

    /** @return array{bytes:string,mime_type:string}|null */
    public function logo(int $companyId): ?array
    {
        $row = $this->db->fetchAssociative(
            "SELECT mime_type, encode(data, 'base64') AS encoded FROM company_logos WHERE company_id = :id",
            ['id' => $companyId]
        );
        if ($row === false) {
            return null;
        }

        return [
            'bytes' => (string) base64_decode((string) preg_replace('/\s+/', '', (string) $row['encoded']), true),
            'mime_type' => (string) $row['mime_type'],
        ];
    }

    /** Replaces the company's logo: one row per company. */
    public function store(int $companyId, string $bytes, string $mimeType, ?int $width, ?int $height, int $actorUserId): void
    {
        $this->db->executeStatement(
            "INSERT INTO company_logos (company_id, mime_type, byte_size, width, height, data, updated_at, updated_by_user_id)
             VALUES (:id, :mime, :size, :width, :height, decode(:data, 'base64'), NOW(), :actor)
             ON CONFLICT (company_id) DO UPDATE SET mime_type = EXCLUDED.mime_type, byte_size = EXCLUDED.byte_size,
                 width = EXCLUDED.width, height = EXCLUDED.height, data = EXCLUDED.data, updated_at = NOW(),
                 updated_by_user_id = EXCLUDED.updated_by_user_id",
            ['id' => $companyId, 'mime' => $mimeType, 'size' => strlen($bytes), 'width' => $width, 'height' => $height,
                'data' => base64_encode($bytes), 'actor' => $actorUserId]
        );
    }

    public function remove(int $companyId): void
    {
        $this->db->executeStatement('DELETE FROM company_logos WHERE company_id = :id', ['id' => $companyId]);
    }
}
