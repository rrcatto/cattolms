declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;

final class FavouritesRepository
{
    public function __construct(private readonly Database $db) {}

    /**
     * How many courses and bundles the person starred, narrowed by a search of their titles and summaries.
     *
     * @return array{courses:int,bundles:int}
     */
    public function counts(int $userId, string $search): array
    {
        [$courseMatch, $bundleMatch, $params] = self::search($search);
        $row = $this->db->fetchAssociative(
            "SELECT (SELECT COUNT(*) FROM course_favourites cf JOIN courses c ON c.id = cf.course_id WHERE cf.user_id = :user AND c.status = 'published'" . $courseMatch . ") AS courses,
                    (SELECT COUNT(*) FROM bundle_favourites bf JOIN bundles b ON b.id = bf.bundle_id WHERE bf.user_id = :user AND b.status <> 'draft'" . $bundleMatch . ') AS bundles',
            ['user' => $userId] + $params
        ) ?: ['courses' => 0, 'bundles' => 0];
        return ['courses' => (int) $row['courses'], 'bundles' => (int) $row['bundles']];
    }

    /**
     * One page of the person's favourites, newest star first: each its kind (course or bundle) and id. The kind and the id
     * make the order total, so no two favourites swap between pages.
     *
     * @return list<array{kind:string,item_id:int}>
     */
    public function page(int $userId, bool $courses, bool $bundles, string $search, int $limit, int $offset): array
    {
        [$courseMatch, $bundleMatch, $params] = self::search($search);
        $parts = [];
        if ($courses) $parts[] = "SELECT 'course' AS kind, cf.course_id AS item_id, cf.created_at FROM course_favourites cf JOIN courses c ON c.id = cf.course_id WHERE cf.user_id = :user AND c.status = 'published'" . $courseMatch;
        if ($bundles) $parts[] = "SELECT 'bundle' AS kind, bf.bundle_id AS item_id, bf.created_at FROM bundle_favourites bf JOIN bundles b ON b.id = bf.bundle_id WHERE bf.user_id = :user AND b.status <> 'draft'" . $bundleMatch;
        if ($parts === []) return [];
        return array_map(static fn(array $row): array => ['kind' => (string) $row['kind'], 'item_id' => (int) $row['item_id']], $this->db->fetchAllAssociative(
            'SELECT kind, item_id FROM (' . implode(' UNION ALL ', $parts) . ') f ORDER BY created_at DESC, kind, item_id DESC LIMIT :limit OFFSET :offset',
            ['user' => $userId, 'limit' => $limit, 'offset' => $offset] + $params
        ));
    }

    /**
     * The search's predicates on a course's title and summary and a bundle's title and short description.
     *
     * @return array{0:string,1:string,2:array<string,string>}
     */
    private static function search(string $search): array
    {
        $term = trim($search);
        if ($term === '') return ['', '', []];
        return [' AND (c.title ILIKE :term OR c.summary ILIKE :term)', ' AND (b.title ILIKE :term OR b.short_description ILIKE :term)', ['term' => '%' . addcslashes($term, '%_\\') . '%']];
    }
}
