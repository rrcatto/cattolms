            return;
        }
        $rows = $this->db->fetchAllAssociative(
            'SELECT id,user_id,is_primary FROM user_emails WHERE lower(email)=lower(:email) LIMIT 1',
            ['email' => $email]
        );
        if (isset($rows[0])) {
            if ((int) $rows[0]['user_id'] !== $userId) {
                throw new RuntimeException('That secondary email address belongs to another account.');
            }
            if ($this->databaseBoolean($rows[0]['is_primary'])) {
                return;
            }
        }
        $this->db->executeStatement(
            'INSERT INTO user_emails (user_id,email,is_primary,verified_at,created_at)
             VALUES (:user_id,:email,FALSE,NOW(),NOW())
             ON CONFLICT (email) DO UPDATE SET verified_at=NOW()',
            ['user_id' => $userId, 'email' => $email]
        );
    }

