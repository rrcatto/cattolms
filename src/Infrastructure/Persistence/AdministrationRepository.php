              WHERE company_id = :company_id AND user_id = :user_id AND status = 'active' LIMIT 1",
            ['company_id' => $companyId, 'user_id' => $userId]
        );

        return $rows !== [];
    }

    /**
     * The address and course a newly enrolled learner should be told about.
     *
     * Read after the enrolment commits rather than carried out of the transaction, so the notice can
     * only ever describe something that actually happened.
     *
     * @return array<string,mixed>|null
