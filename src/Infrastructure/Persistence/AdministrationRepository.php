    /** Total Administration Course Requests rows, using the same membership joins as {@see requests()}. */
    /**
     * One status, or every status.
     *
     * A whitelist rather than a bound value, for the same reason an ORDER BY column is: this is
     * compared against a CHECK-constrained column and a value outside that set can only ever match
     * nothing, so an unknown one widens to everything instead of returning a silently empty screen.
     *
     * @return array{0:string,1:array<string,mixed>}
     */
    private static function andRequestStatus(string $status): array
    {
        $allowed = ['pending', 'approved', 'fulfilled', 'rejected', 'cancelled'];

        return in_array($status, $allowed, true)
            ? [' AND cr.status = :request_status', ['request_status' => $status]]
            : ['', []];
    }

