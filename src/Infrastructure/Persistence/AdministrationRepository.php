            'SELECT ue.email, c.title AS course_title, c.slug
               FROM users u
               JOIN user_emails ue ON ue.user_id = u.id AND ue.is_primary = TRUE
               CROSS JOIN courses c
              WHERE u.id = :user_id AND c.id = :course_id
              LIMIT 1',
            ['user_id' => $userId, 'course_id' => $courseId]
        );

        return $rows[0] ?? null;
    }

    /**
     * Whether a company owns a course, and may therefore train its own staff on it for nothing.
     *
     * Ownership *is* the entitlement. A company that made a course has already paid for it by making
     * it, so approving one of its own staff onto it must not look for a credit, must not consume one
     * if a stray credit happens to exist, and must not leave the request in the limbo state that
     * "approved but no credit found" produces.
     *
     * See ROADMAP section 2c, owner decision of 2026/09/07.
     */
    public function companyOwnsCourse(int $companyId, int $courseId): bool
    {
        if ($companyId <= 0 || $courseId <= 0) {
            return false;
        }

        $rows = $this->db->fetchAllAssociative(
            'SELECT 1 AS owns FROM courses WHERE id = :course_id AND owner_company_id = :company_id LIMIT 1',
            ['course_id' => $courseId, 'company_id' => $companyId]
        );

        return $rows !== [];
    }

    /** @return array<string,mixed>|null */
    public function availableCredit(int $companyId, int $courseId, int $accessPeriodSeconds): ?array
    {
        // A correlated count keeps the candidate row lock legal in PostgreSQL.
        // GROUP BY queries cannot be combined safely with FOR UPDATE.
        $rows = $this->db->fetchAllAssociative(
            'SELECT cc.*,
                    (SELECT COUNT(*) FROM course_credit_allocations cca
                     WHERE cca.credit_id=cc.id AND cca.status IN (\'assigned\',\'consumed\'))::int AS used_count
             FROM course_credits cc
             WHERE cc.company_id=:company_id
               AND cc.course_id=:course_id
               AND cc.access_period_seconds=:period
               AND cc.quantity > (
                    SELECT COUNT(*) FROM course_credit_allocations cca
                    WHERE cca.credit_id=cc.id AND cca.status IN (\'assigned\',\'consumed\')
               )
             ORDER BY cc.created_at, cc.id
             FOR UPDATE OF cc SKIP LOCKED
             LIMIT 1',
            ['company_id' => $companyId, 'course_id' => $courseId, 'period' => $accessPeriodSeconds]
        );
        return $rows[0] ?? null;
    }

