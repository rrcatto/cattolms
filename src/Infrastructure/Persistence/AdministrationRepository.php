    /**
     * Which companies a Companies screen is about.
     *
     * Two audiences rather than one list with a type column. A **creator** owns courses and offers
     * them; a **consumer** has staff being trained. They are asked different questions - a creator
     * screen wants owned courses, a consumer screen wants people and enrolments - and a single list
     * showing both columns to both audiences leaves most of every row empty.
     *
     * Split on the relationship rather than on a `company_type` field, so a company that both sells
     * and buys appears on both screens, which is what it actually is. A type field would force it to
     * be one or the other.
     */
    private static function companyAudienceWhere(string $existingWhere, string $audience): string
    {
        $predicate = self::companyAudiencePredicate($audience);
        if ($predicate === '') {
            return $existingWhere;
        }

        // The search filter opens the WHERE only when it has something to say, and in the ALL
        // universe with no search term it has nothing: appending an AND-fragment to an empty string
        // is a syntax error, not a narrower query.
        return $existingWhere === ''
            ? ' WHERE ' . $predicate
            : $existingWhere . ' AND ' . $predicate;
    }

    /** The predicate itself, without the joining keyword. */
    private static function companyAudiencePredicate(string $audience): string
    {
        return match ($audience) {
            'creators' => 'EXISTS (SELECT 1 FROM courses oc WHERE oc.owner_company_id = c.id)',
            // The last clause is what keeps every company reachable. A company with no staff, no
            // credits and no courses is on neither side of the split by any positive test, so it
            // would be administered from nowhere - and a company is created empty, which makes that
            // the state every new one starts in. Owning no courses is therefore enough to be a
            // consumer, and Consumers is where staff are added.
            'consumers' => "(EXISTS (SELECT 1 FROM company_users acu
                                 WHERE acu.company_id = c.id AND acu.status = 'active')
                              OR EXISTS (SELECT 1 FROM course_credits acc WHERE acc.company_id = c.id)
                              OR NOT EXISTS (SELECT 1 FROM courses noc WHERE noc.owner_company_id = c.id))",
            default => '',
        };
    }

    /**
     * One page of the Administration Companies list. This was the project's reference
     * pagination implementation and keeps its established behaviour and view-variable names;
     * only the shared limit/offset handling and the unique ordering tiebreaker changed.
     *
     * @return list<array<string,mixed>>
     */
    public function companies(int $limit, int $offset, string $search = '', ?SortOrder $sort = null, string $audience = ''): array
    {
        $order = self::orderFor($sort, self::COMPANY_SORTS, self::COMPANY_ORDER, 'c.id');
        $keys = 'SELECT c.id FROM companies c';

        // The three figures are scalar sub-selects rather than joined aggregates, and that is not a
        // style preference.
        //
        // This query used to join `company_users`, `courses` and a second `company_users` to the
        // same company and then de-duplicate with COUNT(DISTINCT). Those are three independent
        // one-to-many relationships, so the join produces their cartesian product: a company with
        // twenty thousand people and a hundred courses builds four hundred million intermediate
        // rows to arrive at three integers. On the development database, where the largest company
        // held a few dozen people, it was invisible; the v0.6 benchmark, whose largest company
        // holds twenty thousand, could not complete the first page of this list in ten minutes.
        //
        // Each sub-select counts one relationship on its own, so the cost is the sum of the three
        // rather than their product, and no DISTINCT is needed to undo a fan-out that never
        // happens. The membership rules are unchanged, which is why the counts are identical.
        $detail = <<<'SQL'
SELECT c.*,
       (SELECT COUNT(*)::int FROM company_users cu
         WHERE cu.company_id=c.id AND cu.status='active') AS people_count,
       (SELECT COUNT(*)::int FROM courses co
         WHERE co.owner_company_id=c.id) AS owned_course_count,
       (SELECT COUNT(*)::int FROM course_enrolments ce
          JOIN company_users lcu ON lcu.user_id=ce.user_id AND lcu.company_id=c.id AND lcu.status='active'
         WHERE ce.is_preview=FALSE AND ce.status IN ('assigned','active','completed')) AS enrolment_count
FROM page
JOIN companies c ON c.id=page.id
SQL;
        [$where, $bindings] = self::searchFilter('c', $search, self::COMPANY_SEARCH);
        $where = self::companyAudienceWhere($where, $audience);

        return $this->db->fetchAllAssociative(
            PageQuery::deferred($keys . $where, $detail, $order, $limit, $offset),
            $bindings
        );
    }

    public function companyCount(string $search = '', string $audience = ''): int
    {
        // The identical audience predicate the rows use.
        [$where, $bindings] = self::searchFilter('c', $search, self::COMPANY_SEARCH);
