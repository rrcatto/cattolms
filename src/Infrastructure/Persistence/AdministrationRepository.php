    private const COMPANY_LEARNER_COURSE = "EXISTS (SELECT 1 FROM course_enrolments rce
                                                     JOIN company_users rcu ON rcu.user_id=rce.user_id
                                                      AND rcu.company_id=:report_company_id
                                                      AND rcu.status='active'
                                                    WHERE rce.course_id=c.id AND rce.is_preview=FALSE)";

    /**
     * The company report's sortable columns.
     *
     * The same keys as COURSE_REPORT_SORTS so one template and one view model serve both screens,
     * with every expression narrowed to the company's own members.
     *
     * @return array<string,string>
     */
    public static function companyCourseReportSorts(): array
    {
        $member = "AND EXISTS (SELECT 1 FROM company_users rcu
                                WHERE rcu.user_id=se.user_id
