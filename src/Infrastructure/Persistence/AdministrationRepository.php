            . $where,
            $bindings
        );

        return (int) ($rows[0]['total'] ?? 0);
    }

    /**
     * One page of the Administration credit ledger. This query was previously unbounded and
     * could render the entire `course_credits` table.
     *
     * @return list<array<string,mixed>>
     */
    public function creditLedger(int $limit, int $offset, string $search = '', ?SortOrder $sort = null): array
    {
        $order = self::orderFor($sort, self::CREDIT_SORTS, self::CREDIT_ORDER, 'cc.id DESC');
        [$where, $bindings] = self::searchFilter('cc', $search, self::CREDIT_SEARCH);

        // The holder joins are in the key query because the search matches on them; the allocation
        // join is not, because it fans a credit out into one row per allocation and contributes
        // nothing to which credits are on the page.
        $keys = 'SELECT cc.id
             FROM course_credits cc
             JOIN courses c ON c.id=cc.course_id
             LEFT JOIN companies co ON co.id=cc.company_id
             LEFT JOIN users u ON u.id=cc.user_id
             LEFT JOIN user_emails ue ON ue.user_id=u.id AND ue.is_primary=TRUE' . $where;

        $detail = 'SELECT cc.id, cc.public_id, cc.company_id, cc.user_id, cc.course_id, cc.access_period_seconds,
                    cc.quantity, cc.source_type, cc.note, cc.created_at,
                    c.title AS course_title,
                    COALESCE(co.name, NULLIF(trim(concat_ws(\' \',u.first_name,u.last_name)),\'\'),u.display_name,ue.email) AS holder_name,
                    COUNT(cca.id) FILTER (WHERE cca.status=\'assigned\')::int AS assigned_count,
                    COUNT(cca.id) FILTER (WHERE cca.status=\'consumed\')::int AS consumed_count,
                    GREATEST(cc.quantity - COUNT(cca.id) FILTER (WHERE cca.status IN (\'assigned\',\'consumed\')),0)::int AS available_count
             FROM page
             JOIN course_credits cc ON cc.id=page.id
             JOIN courses c ON c.id=cc.course_id
             LEFT JOIN companies co ON co.id=cc.company_id
             LEFT JOIN users u ON u.id=cc.user_id
             LEFT JOIN user_emails ue ON ue.user_id=u.id AND ue.is_primary=TRUE
             LEFT JOIN course_credit_allocations cca ON cca.credit_id=cc.id
             GROUP BY cc.id,c.title,co.name,u.first_name,u.last_name,u.display_name,ue.email';

        return $this->db->fetchAllAssociative(
            PageQuery::deferred($keys, $detail, $order, $limit, $offset),
            $bindings
        );
    }

