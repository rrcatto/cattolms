            'started' => "(SELECT COUNT(*) FROM course_enrolments se WHERE se.course_id=c.id AND se.is_preview=FALSE AND se.started_at IS NOT NULL {$member})",
            'completed' => "(SELECT COUNT(*) FROM course_enrolments se WHERE se.course_id=c.id AND se.is_preview=FALSE AND se.status='completed' {$member})",
