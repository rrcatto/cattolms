        // The three joins are membership joins, not decoration - the primary-email join is INNER -
        // so the key query carries all of them, exactly as the count does. What it does not carry
        // is the two correlated sub-selects, which are the expensive half and now run once per
        // displayed row instead of once per enrolment in the platform.
        $keys = 'SELECT ce.id
             FROM course_enrolments ce
             JOIN courses c ON c.id=ce.course_id
             JOIN users u ON u.id=ce.user_id
