SELECT u.id
FROM users u
JOIN user_emails ue ON ue.user_id = u.id AND ue.is_primary = TRUE
SQL;

        $detail = <<<'SQL'
SELECT
    u.id,
    u.public_id,
    u.first_name,
    u.middle_names,
    u.last_name,
    u.display_name,
    u.status,
    u.created_at,
    u.last_login_at,
    ue.email,
    c.id AS company_id,
    c.name AS company_name,
