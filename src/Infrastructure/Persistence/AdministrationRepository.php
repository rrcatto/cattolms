     *
     * @param array<string,mixed> $filters
     * @return array{where: list<string>, params: array<string,mixed>, needs_actor: bool}
     */
    private function activityConditions(array $filters): array
    {
        $where = [];
        $params = [];
        $from = trim((string) ($filters['from'] ?? ''));
        $to = trim((string) ($filters['to'] ?? ''));
        $family = trim((string) ($filters['family'] ?? ''));
        $actorId = max(0, (int) ($filters['actor_id'] ?? 0));
        $courseId = max(0, (int) ($filters['course_id'] ?? 0));
        $companyId = max(0, (int) ($filters['company_id'] ?? 0));
        $query = trim((string) ($filters['q'] ?? ''));
        $eventId = max(0, (int) ($filters['event_id'] ?? 0));
        $afterId = max(0, (int) ($filters['after_id'] ?? 0));

        if ($eventId > 0) {
            $where[] = 'al.id=:event_id';
            $params['event_id'] = $eventId;
        }
        if ($afterId > 0) {
            $where[] = 'al.id>:after_id';
            $params['after_id'] = $afterId;
        }
        if (preg_match('/^\d{4}-\d{2}-\d{2}$/', $from) === 1) {
            $where[] = 'al.created_at >= CAST(:from AS date)';
            $params['from'] = $from;
        }
        if (preg_match('/^\d{4}-\d{2}-\d{2}$/', $to) === 1) {
            $where[] = "al.created_at < CAST(:to AS date) + INTERVAL '1 day'";
            $params['to'] = $to;
        }
        if ($family !== '' && preg_match('/^[a-z][a-z0-9_-]*$/', $family) === 1) {
            $where[] = "split_part(al.event_key,'.',1)=:family";
            $params['family'] = $family;
        }
        if ($actorId > 0) {
            $where[] = 'al.user_id=:actor_id';
            $params['actor_id'] = $actorId;
        }
        if ($courseId > 0) {
            $courseText = (string) $courseId;
            $params['course_direct'] = $courseText;
            $params['course_enrolment'] = $courseText;
            $params['course_assessment'] = $courseText;
            $params['course_request'] = $courseText;
            $where[] = "(
                al.metadata->>'course_id'=:course_direct
                OR EXISTS (SELECT 1 FROM course_enrolments ace WHERE ace.id::text=al.metadata->>'enrolment_id' AND ace.course_id::text=:course_enrolment)
                OR EXISTS (SELECT 1 FROM course_assessments aca WHERE aca.id::text=al.metadata->>'assessment_id' AND aca.course_id::text=:course_assessment)
                OR EXISTS (SELECT 1 FROM course_requests acr WHERE acr.id::text=al.metadata->>'request_id' AND acr.course_id::text=:course_request)
            )";
        }
        if ($companyId > 0) {
            $companyText = (string) $companyId;
            $params['company_direct'] = $companyText;
            $params['company_request'] = $companyText;
            $params['company_enrolment'] = $companyText;
            $params['company_actor'] = $companyText;
            $where[] = "(
                al.metadata->>'company_id'=:company_direct
                OR EXISTS (SELECT 1 FROM course_requests arq WHERE arq.id::text=al.metadata->>'request_id' AND arq.company_id::text=:company_request)
                OR EXISTS (
                    SELECT 1 FROM course_enrolments aen
                    JOIN company_users acu ON acu.user_id=aen.user_id AND acu.status='active'
                    WHERE aen.id::text=al.metadata->>'enrolment_id' AND acu.company_id::text=:company_enrolment
                )
                OR EXISTS (SELECT 1 FROM company_users acu2 WHERE acu2.user_id=al.user_id AND acu2.status='active' AND acu2.company_id::text=:company_actor)
            )";
        }
        if ($query !== '') {
            $like = '%' . $query . '%';
            $params['query_event'] = $like;
            $params['query_actor'] = $like;
            $params['query_metadata'] = $like;
            $where[] = "(al.event_key ILIKE :query_event OR COALESCE(NULLIF(trim(concat_ws(' ',u.first_name,u.last_name)),''),u.display_name,ue.email,'System') ILIKE :query_actor OR al.metadata::text ILIKE :query_metadata)";
        }


        // The actor joins are only ever referenced by the free-text condition above. Saying so here
        // lets the key query and the count leave them out when nothing needs them, which on a
        // hundred thousand audit entries is the difference between a two-second list and a
        // sixty-millisecond one: `user_emails` has no unique constraint on `user_id` alone, so
        // PostgreSQL cannot prove the LEFT JOIN adds no rows and has to perform it.
        return ['where' => $where, 'params' => $params, 'needs_actor' => $query !== ''];
    }

    /** The actor joins the Activity free-text search matches on. */
    private const ACTIVITY_ACTOR_JOINS = "\nLEFT JOIN users u ON u.id=al.user_id"
        . "\nLEFT JOIN user_emails ue ON ue.user_id=u.id AND ue.is_primary=TRUE";

    /**
     * One page of the Activity log for the given filters.
     *
     * @param array<string,mixed> $filters
     * @return list<array<string,mixed>>
     */
    public function activity(array $filters = [], int $limit = 250, int $offset = 0, ?SortOrder $sort = null): array
    {
        $order = self::orderFor($sort, self::ACTIVITY_SORTS, self::ACTIVITY_ORDER, 'al.id DESC');
        ['where' => $where, 'params' => $params, 'needs_actor' => $needsActor] = $this->activityConditions($filters);
        
        // Deferred join. Every row of this list carries four COALESCE chains of correlated
        // sub-selects - up to fourteen lookups per row - to name the course, the company and the
        // subject a generic audit entry refers to. Evaluated across the whole filtered log in
        // order to display twenty-five entries, that is the single most expensive read on the
        // platform; evaluated for twenty-five ids it is nothing.
        $keys = 'SELECT al.id' . "\nFROM audit_log al" . ($needsActor ? self::ACTIVITY_ACTOR_JOINS : '');

        $detail = <<<'SQL'
SELECT al.id, al.event_key, al.metadata, al.created_at, al.user_id AS actor_user_id,
       COALESCE(host(al.ip_address), '') AS ip_address,
       COALESCE(NULLIF(trim(concat_ws(' ',u.first_name,u.last_name)),''),u.display_name,ue.email,'System') AS actor_name,
       COALESCE(
           (SELECT c.title FROM courses c WHERE c.id::text=al.metadata->>'course_id' LIMIT 1),
           (SELECT c.title FROM course_enrolments ce JOIN courses c ON c.id=ce.course_id WHERE ce.id::text=al.metadata->>'enrolment_id' LIMIT 1),
           (SELECT c.title FROM course_assessments ca JOIN courses c ON c.id=ca.course_id WHERE ca.id::text=al.metadata->>'assessment_id' LIMIT 1),
           (SELECT c.title FROM course_requests cr JOIN courses c ON c.id=cr.course_id WHERE cr.id::text=al.metadata->>'request_id' LIMIT 1)
       ) AS course_title,
       COALESCE(
           (SELECT co.name FROM companies co WHERE co.id::text=al.metadata->>'company_id' LIMIT 1),
           (SELECT co.name FROM course_requests cr JOIN companies co ON co.id=cr.company_id WHERE cr.id::text=al.metadata->>'request_id' LIMIT 1),
           (SELECT co.name FROM course_enrolments ce JOIN company_users cu ON cu.user_id=ce.user_id AND cu.status='active' JOIN companies co ON co.id=cu.company_id WHERE ce.id::text=al.metadata->>'enrolment_id' LIMIT 1),
           (SELECT co.name FROM company_users cu JOIN companies co ON co.id=cu.company_id WHERE cu.user_id=al.user_id AND cu.status='active' LIMIT 1)
       ) AS company_name,
       COALESCE(
           (SELECT COALESCE(NULLIF(trim(concat_ws(' ',tu.first_name,tu.last_name)),''),tu.display_name,te.email) FROM users tu LEFT JOIN user_emails te ON te.user_id=tu.id AND te.is_primary=TRUE WHERE tu.id::text=al.metadata->>'user_id' LIMIT 1),
           (SELECT COALESCE(NULLIF(trim(concat_ws(' ',eu.first_name,eu.last_name)),''),eu.display_name,ee.email) FROM course_enrolments ce JOIN users eu ON eu.id=ce.user_id LEFT JOIN user_emails ee ON ee.user_id=eu.id AND ee.is_primary=TRUE WHERE ce.id::text=al.metadata->>'enrolment_id' LIMIT 1)
       ) AS subject_user_name,
       split_part(al.event_key,'.',1) AS event_family
FROM page
JOIN audit_log al ON al.id=page.id
LEFT JOIN users u ON u.id=al.user_id
LEFT JOIN user_emails ue ON ue.user_id=u.id AND ue.is_primary=TRUE
SQL;

        if ($where !== []) {
            $keys .= ' WHERE ' . implode(' AND ', $where);
        }

        return $this->db->fetchAllAssociative(
            PageQuery::deferred($keys, $detail, $order, $limit, $offset),
            $params
        );
    }

    /**
     * Total Activity rows for the same filters as {@see activity()}.
     *
     * The two `LEFT JOIN`s are carried only when the free-text search condition is present, because
     * that condition is the only thing that references `u.first_name`, `u.last_name`,
     * `u.display_name` and `ue.email`. Dropping them unconditionally would make the count fail
     * whenever a term is set; carrying them unconditionally made every unsearched count pay for a
     * join it never read. The page query answers the same question the same way, so the two cannot
     * describe different populations.
     *
     * @param array<string,mixed> $filters
     */
    public function activityCount(array $filters = []): int
    {
        ['where' => $where, 'params' => $params, 'needs_actor' => $needsActor] = $this->activityConditions($filters);
        
        $sql = 'SELECT COUNT(*)::int AS total FROM audit_log al'
            . ($needsActor ? self::ACTIVITY_ACTOR_JOINS : '');
        if ($where !== []) $sql .= ' WHERE ' . implode(' AND ', $where);

        $rows = $this->db->fetchAllAssociative($sql, $params);

        return (int) ($rows[0]['total'] ?? 0);
    }

    /** @return list<string> */
    public function activityFamilies(): array
    {
        $rows = $this->db->fetchAllAssociative(
            "SELECT DISTINCT split_part(event_key,'.',1) AS family FROM audit_log WHERE event_key<>''"
            . '' . ' ORDER BY family'
        );
        return array_values(array_filter(array_map(static fn(array $row): string => (string) ($row['family'] ?? ''), $rows)));
    }

    /** @return array<string,int|float> */
    public function reportSummary(): array
    {
        // Report scalars are scoped exactly like the tables they summarise. An unscoped average
        // is worse than an unscoped list: it silently blends generated results into a genuine
        // performance figure with nothing on screen to suggest it happened.
        $enrolmentScope = '';
        $rows = $this->db->fetchAllAssociative(<<<SQL
SELECT
  (SELECT COUNT(*) FROM course_enrolments WHERE is_preview=FALSE)::int AS enrolments,
  (SELECT COUNT(*) FROM course_enrolments WHERE is_preview=FALSE AND status='assigned')::int AS assigned,
  (SELECT COUNT(*) FROM course_enrolments WHERE is_preview=FALSE AND status='active')::int AS active,
  (SELECT COUNT(*) FROM course_enrolments WHERE is_preview=FALSE AND status='completed')::int AS completed,
  (SELECT COUNT(*) FROM course_enrolments WHERE is_preview=FALSE AND status='cancelled')::int AS cancelled,
  (SELECT COUNT(*) FROM assessment_sessions s JOIN course_enrolments e ON e.id=s.enrolment_id WHERE e.is_preview=FALSE AND s.status='submitted' AND s.attempt_mode='graded'{$enrolmentScope})::int AS graded_assessments,
  COALESCE((SELECT ROUND(AVG(s.percentage),1) FROM assessment_sessions s JOIN course_enrolments e ON e.id=s.enrolment_id WHERE e.is_preview=FALSE AND s.status='submitted' AND s.attempt_mode='graded'{$enrolmentScope}),0)::float AS assessment_average,
  COALESCE((SELECT ROUND(100.0*AVG(CASE WHEN s.passed THEN 1 ELSE 0 END),1) FROM assessment_sessions s JOIN course_enrolments e ON e.id=s.enrolment_id WHERE e.is_preview=FALSE AND s.status='submitted' AND s.attempt_mode='graded'{$enrolmentScope}),0)::float AS assessment_pass_rate,
  (SELECT COUNT(*) FROM certificates WHERE revoked_at IS NULL)::int AS certificates
SQL);
        return $rows[0] ?? [];
    }

    /** @return list<array<string,mixed>> */
    public function courseReport(int $limit = 0, int $offset = 0, string $search = '', ?SortOrder $sort = null): array
    {
        $order = self::orderFor($sort, self::COURSE_REPORT_SORTS, self::COURSE_REPORT_ORDER, 'c.id');
        [$courseScope, $bindings] = self::searchFilter('c', $search, self::COURSE_REPORT_SEARCH);

        $detail = <<<'SQL'
SELECT c.id,c.title,c.status,
       COUNT(DISTINCT ce.id) FILTER (WHERE ce.is_preview=FALSE)::int AS enrolments,
       COUNT(DISTINCT ce.id) FILTER (WHERE ce.is_preview=FALSE AND ce.started_at IS NOT NULL)::int AS started,
       COUNT(DISTINCT ce.id) FILTER (WHERE ce.is_preview=FALSE AND ce.status='completed')::int AS completed,
       COALESCE(ROUND(AVG(cr.overall_percentage) FILTER (WHERE ce.is_preview=FALSE),1),0)::float AS average_result
FROM %s
LEFT JOIN course_enrolments ce ON ce.course_id=c.id
LEFT JOIN course_results cr ON cr.enrolment_id=ce.id
%s
GROUP BY c.id
SQL;

        // A limit of zero means the whole report, which no screen asks for but the signature still
        // allows. There is nothing to defer in that case: every course is on the page.
        if ($limit <= 0) {
            return $this->db->fetchAllAssociative(
                sprintf($detail, 'courses c', $courseScope) . "\nORDER BY " . $order,
                $bindings
            );
        }

        return $this->db->fetchAllAssociative(
            PageQuery::deferred(
                'SELECT c.id FROM courses c' . $courseScope,
                sprintf($detail, 'page JOIN courses c ON c.id=page.id', ''),
                $order,
                $limit,
                $offset
            ),
            $bindings
        );
    }

    /**
     * The company's own course performance: how its staff are doing, course by course.
     *
     * The same report as {@see courseReport()} asked of one company. Every figure counts only
     * enrolments held by an active member of that company, and only courses at least one of them is
     * enrolled in appear at all - a company administrator asking how training is going is asking
     * about their own people, and a platform-wide figure on that screen would be somebody else's
     * answer to a question they did not ask.
     *
     * The membership predicate is repeated in the aggregate join and in every sort expression on
     * purpose. Sorting by a platform-wide count while displaying a company one would order the rows
     * by numbers that are not on the screen.
     *
     * @return list<array<string,mixed>>
     */
    public function companyCourseReport(int $companyId, int $limit, int $offset, string $search = '', ?SortOrder $sort = null): array
    {
        $order = self::orderFor($sort, self::companyCourseReportSorts(), self::COURSE_REPORT_ORDER, 'c.id');
        [$courseScope, $bindings] = self::searchFilter('c', $search, self::COURSE_REPORT_SEARCH);
        $bindings['report_company_id'] = $companyId;
        $where = $courseScope === ''
            ? ' WHERE ' . self::COMPANY_LEARNER_COURSE
            : $courseScope . ' AND ' . self::COMPANY_LEARNER_COURSE;

        $member = self::COMPANY_LEARNER_ENROLMENT;
        $detail = <<<SQL
SELECT c.id,c.title,c.status,
       COUNT(DISTINCT ce.id)::int AS enrolments,
       COUNT(DISTINCT ce.id) FILTER (WHERE ce.started_at IS NOT NULL)::int AS started,
       COUNT(DISTINCT ce.id) FILTER (WHERE ce.status='completed')::int AS completed,
       COALESCE(ROUND(AVG(cr.overall_percentage),1),0)::float AS average_result
FROM page
JOIN courses c ON c.id=page.id
LEFT JOIN course_enrolments ce ON ce.course_id=c.id AND ce.is_preview=FALSE AND {$member}
LEFT JOIN course_results cr ON cr.enrolment_id=ce.id
GROUP BY c.id
SQL;

        return $this->db->fetchAllAssociative(
            PageQuery::deferred('SELECT c.id FROM courses c' . $where, $detail, $order, $limit, $offset),
            $bindings
        );
    }

