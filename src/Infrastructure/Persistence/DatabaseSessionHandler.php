        $rows = $this->db->exec(
            'SELECT data FROM web_sessions WHERE id=:id AND last_activity>=:cutoff LIMIT 1',
            [':id' => $id, ':cutoff' => gmdate('Y-m-d H:i:sP', time() - $this->ttl)]
