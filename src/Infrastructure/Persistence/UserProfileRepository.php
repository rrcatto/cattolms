Persistence for the two things a profile carries besides its own fields: an image and social links.

Architectural boundary: persistence. Every line of SQL for `user_profile_images` and
`user_social_links` is here, and it returns arrays and scalars - never an object, never a resource.

Image bytes travel as base64 and are converted at the database, `decode(:data,'base64')` on the way
in and `encode(image_data,'base64')` on the way out. Binding a bytea directly would mean handing raw
binary through a parameter that infers its PDO type from the PHP value, and a string of arbitrary
bytes is not reliably a string as far as that inference is concerned. Base64 makes the parameter
unambiguously text and leaves the column genuinely binary, which is the property that matters.

