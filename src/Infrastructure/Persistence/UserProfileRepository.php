declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;

final class UserProfileRepository
{
    public function __construct(private readonly Database $db)
    {
    }

    /**
     * One person's stored image, or null.
     *
     * @return array{mime_type:string,byte_size:int,width:int,height:int,bytes:string,updated_at:string}|null
     */
    public function image(int $userId): ?array
    {
        $row = $this->db->fetchAssociative(
            "SELECT mime_type, byte_size, width, height, encode(image_data,'base64') AS encoded,
                    to_char(updated_at, 'YYYY-MM-DD HH24:MI') AS updated_at
             FROM user_profile_images WHERE user_id = :user_id",
            ['user_id' => $userId]
        );
        if ($row === false) {
            return null;
        }

        return [
            'mime_type' => (string) $row['mime_type'],
            'byte_size' => (int) $row['byte_size'],
            'width' => (int) $row['width'],
            'height' => (int) $row['height'],
            // PostgreSQL wraps base64 output at 76 characters, which base64_decode tolerates but
            // nothing else should have to.
            'bytes' => (string) base64_decode((string) preg_replace('/\s+/', '', (string) $row['encoded']), true),
            'updated_at' => (string) $row['updated_at'],
        ];
    }

    /** True when this person has an image, without reading its bytes. */
    public function hasImage(int $userId): bool
    {
        return (bool) $this->db->fetchOne(
            'SELECT EXISTS(SELECT 1 FROM user_profile_images WHERE user_id = :user_id)',
            ['user_id' => $userId]
        );
    }

    /** Replace this person's image. One row per person, so this is an upsert and never accumulates. */
    public function storeImage(int $userId, string $bytes, string $mimeType, int $width, int $height): void
    {
        $this->db->executeStatement(
            "INSERT INTO user_profile_images (user_id, mime_type, byte_size, width, height, image_data, updated_at)
             VALUES (:user_id, :mime_type, :byte_size, :width, :height, decode(:image_data,'base64'), now())
             ON CONFLICT (user_id) DO UPDATE SET
                 mime_type = EXCLUDED.mime_type,
                 byte_size = EXCLUDED.byte_size,
                 width = EXCLUDED.width,
                 height = EXCLUDED.height,
                 image_data = EXCLUDED.image_data,
                 updated_at = now()",
            [
                'user_id' => $userId,
                'mime_type' => $mimeType,
                'byte_size' => strlen($bytes),
                'width' => $width,
                'height' => $height,
                'image_data' => base64_encode($bytes),
            ]
        );
    }

    public function removeImage(int $userId): void
    {
        $this->db->executeStatement('DELETE FROM user_profile_images WHERE user_id = :user_id', ['user_id' => $userId]);
    }

    /**
     * This person's social links, keyed by platform.
     *
     * @return array<string,string>
     */
    public function socialLinks(int $userId): array
    {
        $links = [];
        foreach ($this->db->fetchAllAssociative(
            'SELECT platform, url FROM user_social_links WHERE user_id = :user_id ORDER BY platform',
            ['user_id' => $userId]
        ) as $row) {
            $links[(string) $row['platform']] = (string) $row['url'];
        }

        return $links;
    }

    /** Store one platform's address. */
    public function storeSocialLink(int $userId, string $platform, string $url): void
    {
        $this->db->executeStatement(
            'INSERT INTO user_social_links (user_id, platform, url)
             VALUES (:user_id, :platform, :url)
             ON CONFLICT (user_id, platform) DO UPDATE SET url = EXCLUDED.url, updated_at = now()',
            ['user_id' => $userId, 'platform' => $platform, 'url' => $url]
        );
    }

    /** Remove one platform's address. */
    public function removeSocialLink(int $userId, string $platform): void
    {
        $this->db->executeStatement(
            'DELETE FROM user_social_links WHERE user_id = :user_id AND platform = :platform',
            ['user_id' => $userId, 'platform' => $platform]
        );
    }
}
