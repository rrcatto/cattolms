declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;

use CattoLearning\Support\Env;
use DateTimeZone;
use Doctrine\DBAL\Driver;
use Doctrine\DBAL\Driver\Middleware;
use InvalidArgumentException;

final class SessionTimeZoneMiddleware implements Middleware
{
    private readonly string $timeZone;

    public function __construct(?string $timeZone = null)
    {
        $timeZone ??= Env::string('APP_TIMEZONE', 'Africa/Johannesburg');
        if (!in_array($timeZone, DateTimeZone::listIdentifiers(), true)) {
            throw new InvalidArgumentException('APP_TIMEZONE is not a known timezone: ' . $timeZone);
        }

        $this->timeZone = $timeZone;
    }

    public function wrap(Driver $driver): Driver
    {
        return new SessionTimeZoneDriver($driver, $this->timeZone);
    }
}
