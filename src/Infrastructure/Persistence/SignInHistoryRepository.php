A person's sign-ins, from the activity log's auth.login rows (owner, 2026-10-26: "none of these signins show me their IP
address or any GeoIP info. It would help if I knew which country the person was logging in from"): the recent ones with
their IP address and country, and every sign-in of the last week from a country the account had never signed in from
