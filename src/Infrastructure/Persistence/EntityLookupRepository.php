declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;


final class EntityLookupRepository
{
    /** Never return more than this many rows, regardless of how broad the search term is. */
    public const MAX_RESULTS = 20;

    /** Shorter terms match too much to be useful and would scan the whole table for nothing. */
    public const MIN_QUERY_LENGTH = 2;

    /** Longer terms are pointless and are a cheap way to push work onto PostgreSQL. */
    public const MAX_QUERY_LENGTH = 120;

    /** The only entity types that may be searched. Anything else is rejected by the caller. */
    public const TYPES = ['people', 'companies', 'courses', 'assignable_courses'];

    public function __construct(private readonly Database $db)
    {
    }

    public static function isSupportedType(string $type): bool
    {
        return in_array($type, self::TYPES, true);
    }

    /**
     * Searches one entity type.
     *
     * `$companyId` scopes people and courses to a single company for company-scoped operators;
     * a platform-wide actor passes 0. The scope is applied in SQL, never by filtering rows
     * after they have been fetched.
     *
     * @return list<array{id:int,label:string,detail:string}>
     */
    public function search(string $type, string $query, int $companyId = 0): array
    {
        $query = trim($query);
        if (!self::isSupportedType($type) || mb_strlen($query) < self::MIN_QUERY_LENGTH) return [];

        // Escape the LIKE metacharacters so a term of "%" cannot turn into "match everything".
        $term = '%' . str_replace(['\\', '%', '_'], ['\\\\', '\\%', '\\_'], mb_substr($query, 0, self::MAX_QUERY_LENGTH)) . '%';

        return match ($type) {
            'people' => $this->searchPeople($term, $companyId),
            'companies' => $this->searchCompanies($term),
            'courses' => $this->searchCourses($term, $companyId),
            'assignable_courses' => $this->searchAssignableCourses($term, $companyId),
            default => [],
        };
    }

    /**
     * Resolves one already-selected entity so a filter or form can redisplay its label after a
     * page reload without searching again. Returns null when the id is absent or out of scope.
     *
     * @return array{id:int,label:string,detail:string}|null
     */
    public function describe(string $type, int $id, int $companyId = 0): ?array
    {
        if (!self::isSupportedType($type) || $id <= 0) return null;

        // Applied in SQL rather than by discarding a fetched row: a direct id lookup that
        // fetches first and filters afterwards still confirms the row exists, which is enough
        // to probe for the presence of data in the other universe.
        $scope = '';
        $companyScope = '';

        $rows = match ($type) {
            'people' => $this->db->fetchAllAssociative(
                'SELECT u.id,
                        COALESCE(NULLIF(trim(concat_ws(\' \',u.first_name,u.last_name)),\'\'),u.display_name,ue.email) AS label,
                        ue.email AS detail
                 FROM users u
                 JOIN user_emails ue ON ue.user_id=u.id AND ue.is_primary=TRUE
                 LEFT JOIN company_users cu ON cu.user_id=u.id AND cu.status=\'active\'
                 WHERE u.id=:id AND (:company_id=0 OR cu.company_id=:company_id)' . $scope . '
                 LIMIT 1',
                ['id' => $id, 'company_id' => $companyId]
            ),
            'companies' => $this->db->fetchAllAssociative(
                'SELECT c.id, c.name AS label, c.domain AS detail FROM companies c WHERE c.id=:id' . $companyScope . ' LIMIT 1',
                ['id' => $id]
            ),
            'courses' => $this->db->fetchAllAssociative(
                'SELECT c.id, c.title AS label, c.slug AS detail
                 FROM courses c
                 WHERE c.id=:id AND (:company_id=0 OR c.owner_company_id=:company_id)' . $companyScope . '
                 LIMIT 1',
                ['id' => $id, 'company_id' => $companyId]
            ),
            default => [],
        };

        return isset($rows[0]) ? $this->row($rows[0]) : null;
    }

    /** @return list<array{id:int,label:string,detail:string}> */
    private function searchPeople(string $term, int $companyId): array
    {
        return $this->rows($this->db->fetchAllAssociative(
            'SELECT DISTINCT u.id,
                    COALESCE(NULLIF(trim(concat_ws(\' \',u.first_name,u.last_name)),\'\'),u.display_name,ue.email) AS label,
                    ue.email AS detail
             FROM users u
             JOIN user_emails ue ON ue.user_id=u.id AND ue.is_primary=TRUE
             LEFT JOIN company_users cu ON cu.user_id=u.id AND cu.status=\'active\'
             WHERE (:company_id=0 OR cu.company_id=:company_id)
               AND (
                   COALESCE(NULLIF(trim(concat_ws(\' \',u.first_name,u.last_name)),\'\'),u.display_name,\'\') ILIKE :term
                   OR ue.email ILIKE :term
               )' . '' . '
             ORDER BY label, u.id
             LIMIT ' . self::MAX_RESULTS,
            ['term' => $term, 'company_id' => $companyId]
        ));
    }

    /** @return list<array{id:int,label:string,detail:string}> */
    private function searchCompanies(string $term): array
    {
        return $this->rows($this->db->fetchAllAssociative(
            'SELECT c.id, c.name AS label, c.domain AS detail
             FROM companies c
             WHERE (c.name ILIKE :term OR c.domain ILIKE :term)' . '' . '
             ORDER BY c.is_system DESC, c.name, c.id
             LIMIT ' . self::MAX_RESULTS,
            ['term' => $term]
        ));
    }

    /** @return list<array{id:int,label:string,detail:string}> */
    private function searchCourses(string $term, int $companyId): array
    {
        return $this->rows($this->db->fetchAllAssociative(
            'SELECT c.id, c.title AS label, c.slug AS detail
             FROM courses c
             WHERE (:company_id=0 OR c.owner_company_id=:company_id)
               AND (c.title ILIKE :term OR c.slug ILIKE :term)' . '' . '
             ORDER BY c.title, c.id
             LIMIT ' . self::MAX_RESULTS,
            ['term' => $term, 'company_id' => $companyId]
        ));
    }

    /**
     * The courses a company may put a staff member on right now.
     *
     * Two things qualify and they qualify for different reasons. A course the company **owns** costs
     * nothing to train its own staff on - ownership is the entitlement. A course it does not own
     * qualifies only while it holds a credit with a **free seat**: a credit that is fully allocated
     * buys nothing more, and offering it would produce an assignment that fails at the last step.
     *
     * A company with no company id selected gets nothing rather than everything. This lookup answers
     * "what may *this* company assign", and with no company that question has no answer - returning
     * the platform catalogue would be the Stage D defect in a new place.
     *
     * @return list<array<string,mixed>>
     */
    private function searchAssignableCourses(string $term, int $companyId): array
    {
        if ($companyId <= 0) {
            return [];
        }

        return $this->rows($this->db->fetchAllAssociative(
            "SELECT c.id, c.title AS label,
                    CASE WHEN c.owner_company_id = :company_id THEN 'Owned - free for staff'
                         ELSE 'Seats available' END AS detail
             FROM courses c
             WHERE (c.title ILIKE :term OR c.slug ILIKE :term)
               AND (
                    c.owner_company_id = :company_id
                    OR EXISTS (
                        SELECT 1 FROM course_credits cr
                         WHERE cr.course_id = c.id AND cr.company_id = :company_id
                           AND cr.quantity - cr.refunded_quantity > (
                                SELECT COUNT(*) FROM course_credit_allocations cca
                                 WHERE cca.credit_id = cr.id AND cca.status IN ('assigned','consumed')
                           )
                    )
               )" . '' . "
             ORDER BY c.title, c.id
             LIMIT " . self::MAX_RESULTS,
            ['term' => $term, 'company_id' => $companyId]
        ));
    }


    /**
     * @param list<array<string,mixed>> $rows
     * @return list<array{id:int,label:string,detail:string}>
     */
    private function rows(array $rows): array
    {
        return array_map(fn(array $row): array => $this->row($row), $rows);
    }

    /**
     * @param array<string,mixed> $row
     * @return array{id:int,label:string,detail:string}
     */
    private function row(array $row): array
    {
        return [
            'id' => (int) ($row['id'] ?? 0),
            'label' => (string) ($row['label'] ?? ''),
            'detail' => (string) ($row['detail'] ?? ''),
        ];
    }
}
