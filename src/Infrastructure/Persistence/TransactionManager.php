declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;

use DB\SQL;
use Throwable;

final class TransactionManager
{
    public function __construct(private readonly SQL $db)
    {
    }

    /**
     * Runs an operation inside a transaction, joining an outer one if it already exists.
     *
     * PDO has no nested transactions: calling beginTransaction() while one is active throws. That
     * made it unsafe for a repository to protect its own multi-statement write, because the same
     * method might be called directly or from inside a service transaction, and only one of those
     * worked. The effect was that repositories left their writes unprotected instead.
     *
     * Joining is the right semantic rather than a workaround. The inner block wants "these
     * statements succeed or none of them do", and an outer transaction already guarantees that -
     * more strongly, in fact, because a later failure rolls this work back too. What the inner
     * block must not do is commit early and release work the outer caller may still abandon,
     * which is exactly what a naive nested commit would do.
     *
     * @param callable():T $operation
     * @return T
     * @template T
     */
    public function run(callable $operation): mixed
    {
        if ($this->db->trans()) {
            // Already inside a transaction: participate in it and let the owner decide the
            // outcome. Committing here would release work the outer caller might still roll back.
            return $operation();
        }

        $this->db->begin();
        try {
            $result = $operation();
            $this->db->commit();
            return $result;
        } catch (Throwable $exception) {
            $this->db->rollback();
            throw $exception;
        }
    }
}