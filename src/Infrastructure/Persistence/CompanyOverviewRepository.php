declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;

class CompanyOverviewRepository
{
    public function __construct(private readonly Database $db)
    {
    }

    /**
     * The courses a company provides, in catalogue order, with the lowest current price and how many learners are on each.
     *
     * @return list<array<string,mixed>>
     */
    public function ownedCourses(int $companyId, int $limit): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT c.id, c.title, c.slug, COALESCE(c.code, '') AS code, c.status, c.cover_svg, c.updated_at, COALESCE(cat.name, '') AS category_name,
                    p.price_minor_units, p.was_price_minor_units, p.currency_code,
                    (SELECT COUNT(*) FROM course_enrolments e WHERE e.course_id = c.id AND e.is_preview = FALSE AND e.status IN ('assigned', 'active', 'completed'))::int AS learner_count
             FROM courses c
             LEFT JOIN course_categories cat ON cat.id = c.category_id
             LEFT JOIN LATERAL (SELECT v.price_minor_units, v.was_price_minor_units, v.currency_code FROM course_price_variants v
                                WHERE v.course_id = c.id AND v.is_active ORDER BY v.is_default DESC, v.price_minor_units, v.position LIMIT 1) p ON TRUE
             WHERE c.owner_company_id = :c
             ORDER BY c.catalogue_position NULLS LAST, lower(c.title), c.id LIMIT :limit",
            ['c' => $companyId, 'limit' => $limit]
        );
    }

    /** @return array{total:int,published:int,draft:int,retired:int,learners:int} */
    public function ownedCourseFigures(int $companyId): array
    {
        $row = $this->db->fetchAssociative(
            "SELECT COUNT(*)::int AS total,
                    COUNT(*) FILTER (WHERE c.status = 'published')::int AS published,
                    COUNT(*) FILTER (WHERE c.status = 'draft')::int AS draft,
                    COUNT(*) FILTER (WHERE c.status IN ('retired', 'archived'))::int AS retired,
                    (SELECT COUNT(*) FROM course_enrolments e JOIN courses oc ON oc.id = e.course_id WHERE oc.owner_company_id = :c AND e.is_preview = FALSE AND e.status IN ('assigned', 'active', 'completed'))::int AS learners
             FROM courses c WHERE c.owner_company_id = :c",
            ['c' => $companyId]
        );

        return array_map('intval', $row === false ? ['total' => 0, 'published' => 0, 'draft' => 0, 'retired' => 0, 'learners' => 0] : $row);
    }

    /** @return array{completed:int,average:?float} the courses its staff completed, and their average result */
    public function staffResults(int $companyId): array
    {
        $row = $this->db->fetchAssociative(
            "SELECT COUNT(DISTINCT e.id) FILTER (WHERE e.status = 'completed')::int AS completed, ROUND(AVG(r.overall_percentage) FILTER (WHERE e.status = 'completed'), 0) AS average
             FROM course_enrolments e JOIN company_users cu ON cu.user_id = e.user_id AND cu.company_id = :c AND cu.status = 'active'
             LEFT JOIN course_results r ON r.enrolment_id = e.id
             WHERE e.is_preview = FALSE",
            ['c' => $companyId]
        );

        return ['completed' => (int) ($row['completed'] ?? 0), 'average' => isset($row['average']) ? (float) $row['average'] : null];
    }

    /** @return list<array<string,mixed>> course requests from its staff waiting for a decision, oldest first */
    public function pendingRequests(int $companyId): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT cr.id, cr.requested_at, c.title AS course_title, u.id AS user_id, u.account_reference,
                    COALESCE(NULLIF(trim(concat_ws(' ', u.first_name, u.last_name)), ''), u.display_name, ue.email) AS name
             FROM course_requests cr JOIN courses c ON c.id = cr.course_id JOIN users u ON u.id = cr.user_id
             JOIN user_emails ue ON ue.user_id = u.id AND ue.is_primary
             WHERE cr.company_id = :c AND cr.status = 'pending' ORDER BY cr.requested_at, cr.id",
            ['c' => $companyId]
        );
    }

    /** @return list<array<string,mixed>> its orders still to be paid, with what is due */
    public function unpaidOrders(int $companyId): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT o.id, o.total_minor, o.currency, o.placed_at, o.payment_due_at,
                    GREATEST(o.total_minor - COALESCE((SELECT SUM(p.amount_minor) FROM commerce_payments p WHERE p.order_id = o.id AND p.state IN ('paid', 'partially_refunded', 'refunded')), 0), 0) AS due_minor
             FROM commerce_orders o WHERE o.company_id = :c AND o.state IN ('placed', 'awaiting_payment') ORDER BY o.payment_due_at NULLS LAST, o.id",
            ['c' => $companyId]
        );
    }

    /** @return array{paid_minor:int,paid_orders:int,orders:int,currency:string} the money of its orders */
    public function orderMoney(int $companyId): array
    {
        $row = $this->db->fetchAssociative(
            "SELECT COUNT(*)::int AS orders,
                    COUNT(*) FILTER (WHERE o.state IN ('paid', 'fulfilled', 'partially_refunded', 'refunded'))::int AS paid_orders,
                    COALESCE((SELECT SUM(p.amount_minor) FROM commerce_payments p JOIN commerce_orders po ON po.id = p.order_id WHERE po.company_id = :c AND p.state IN ('paid', 'partially_refunded', 'refunded')), 0)::bigint AS paid_minor,
                    COALESCE(MAX(o.currency), 'ZAR') AS currency
             FROM commerce_orders o WHERE o.company_id = :c",
            ['c' => $companyId]
        );

        return ['paid_minor' => (int) ($row['paid_minor'] ?? 0), 'paid_orders' => (int) ($row['paid_orders'] ?? 0), 'orders' => (int) ($row['orders'] ?? 0), 'currency' => (string) ($row['currency'] ?? 'ZAR')];
    }

    /**
     * What each order bought, in a few words: "8 places on Payroll Basics", "and 2 more".
     *
     * @param list<int> $orderIds
     * @return array<int,string>
     */
    public function orderSummaries(array $orderIds): array
    {
        if ($orderIds === []) return [];
        $out = [];
        foreach ($this->db->fetchAllAssociative(
            "SELECT i.order_id, i.quantity, COALESCE(c.title, i.snapshot->>'title', 'a course') AS title, COUNT(*) OVER (PARTITION BY i.order_id) AS lines,
                    ROW_NUMBER() OVER (PARTITION BY i.order_id ORDER BY i.id) AS position
             FROM commerce_order_items i LEFT JOIN courses c ON c.id = i.course_id WHERE i.order_id = ANY(CAST(:ids AS BIGINT[]))",
            ['ids' => '{' . implode(',', array_map('intval', $orderIds)) . '}']
        ) as $row) {
            if ((int) $row['position'] !== 1) continue;
            $quantity = (int) $row['quantity'];
            $more = (int) $row['lines'] - 1;
            $out[(int) $row['order_id']] = ($quantity === 1 ? '1 place' : $quantity . ' places') . ' on ' . $row['title'] . ($more > 0 ? ' and ' . $more . ' more' : '');
        }

        return $out;
    }

    /** @return list<array{user_id:int,name:string,account_reference:string}> its Company Administrators, by name */
    public function administrators(int $companyId): array
    {
        return array_map(static fn(array $r): array => ['user_id' => (int) $r['user_id'], 'name' => (string) $r['name'], 'account_reference' => (string) $r['account_reference']], $this->db->fetchAllAssociative(
            "SELECT u.id AS user_id, u.account_reference, COALESCE(NULLIF(trim(concat_ws(' ', u.first_name, u.last_name)), ''), u.display_name, ue.email) AS name
             FROM company_users cu JOIN users u ON u.id = cu.user_id JOIN user_emails ue ON ue.user_id = u.id AND ue.is_primary
             WHERE cu.company_id = :c AND cu.status = 'active' AND cu.company_role IN ('owner', 'administrator')
             ORDER BY u.sort_name NULLS LAST, u.id",
            ['c' => $companyId]
        ));
    }

    /**
     * The order each bought credit came from.
     *
     * @param list<int> $creditIds
     * @return array<int,int> credit id => order id
     */
    public function creditOrders(array $creditIds): array
    {
        if ($creditIds === []) return [];
        $out = [];
        foreach ($this->db->fetchAllAssociative(
            'SELECT cc.id, i.order_id FROM course_credits cc JOIN commerce_order_items i ON i.id = cc.commerce_order_item_id WHERE cc.id = ANY(CAST(:ids AS BIGINT[]))',
            ['ids' => '{' . implode(',', array_map('intval', $creditIds)) . '}']
        ) as $row) $out[(int) $row['id']] = (int) $row['order_id'];

        return $out;
    }

    /** @return array{held:int,left:int} credit places it holds (after refunds) and those not yet assigned or used */
    public function creditPlaces(int $companyId): array
    {
        $row = $this->db->fetchAssociative(
            "SELECT COALESCE(SUM(cc.quantity - cc.refunded_quantity), 0)::int AS held,
                    COALESCE(SUM(GREATEST(cc.quantity - cc.refunded_quantity - (SELECT COUNT(*) FROM course_credit_allocations a WHERE a.credit_id = cc.id AND a.status IN ('assigned', 'consumed')), 0)), 0)::int AS left_over
             FROM course_credits cc WHERE cc.company_id = :c",
            ['c' => $companyId]
        );

        return ['held' => (int) ($row['held'] ?? 0), 'left' => (int) ($row['left_over'] ?? 0)];
    }
}
