/*
Generated by: Claude Code CLI

Date time: 2026/08/23 04:19 SAST

Version: 0.5.8

Description:
Resolves the seed provenance an ordinary application write must carry.

A generated seed set is only useful if a SEED identity can then use the LMS normally. Every
business row created during a SEED workflow has to carry the correct `seed_token` before it
reaches the database integrity boundary, or the cross-universe trigger rejects it and the seed
identity cannot do anything.

The token is always taken from the **authoritative parent resource**, never from the actor:

    module              <- its course
    enrolment           <- its learner and course
    attempt             <- its enrolment
    response            <- its attempt
    membership          <- its company and user

That distinction matters most for a genuine ADMIN operating on SEED data. The ADMIN is a REAL
identity, so using the actor's own token would write a REAL row into a SEED aggregate and the
trigger would reject it. The actor may still appear in an allowlisted attribution column
(decision D4); it just never decides which universe the row belongs to.

Architectural boundary: persistence. It reads one indexed column and returns a token. It holds no
business rules and writes nothing.

Changelog:
2026/08/23 04:19 SAST
- Created to finish seed provenance on ordinary writes.
*/

declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;

use CattoLearning\Seed\SeedTableCatalog;
use DB\SQL;
use RuntimeException;

final class SeedProvenance
{
    /**
     * Cached per request.
     *
     * A learner working through a course triggers several provenance lookups against the same
     * enrolment and course, and the answer cannot change inside one request: a row never moves
     * between universes.
     *
     * @var array<string,string|null>
     */
    private array $cache = [];

    public function __construct(private readonly SQL $db)
    {
    }

    /**
     * The token carried by one existing row, or null when it is REAL.
     *
     * The table must be seed-aware; asking about a table with no `seed_token` column is a
     * programming error rather than a null answer, because the caller has misidentified which
     * row is authoritative.
     */
    public function tokenFor(string $table, ?int $id): ?string
    {
        if ($id === null || $id < 1) {
            return null;
        }
        if (!SeedTableCatalog::isSeedAware($table)) {
            throw new RuntimeException($table . ' carries no seed provenance and cannot be an authority for it.');
        }

        $key = $table . ':' . $id;
        if (array_key_exists($key, $this->cache)) {
            return $this->cache[$key];
        }

        $rows = $this->db->exec(
            'SELECT seed_token::text AS token FROM ' . $table . ' WHERE id = :id LIMIT 1',
            [':id' => $id]
        );

        $token = isset($rows[0]['token']) ? trim((string) $rows[0]['token']) : '';

        return $this->cache[$key] = ($token === '' ? null : $token);
    }

    public function fromUser(?int $userId): ?string
    {
        return $this->tokenFor('users', $userId);
    }

    public function fromCompany(?int $companyId): ?string
    {
        return $this->tokenFor('companies', $companyId);
    }

    public function fromCourse(?int $courseId): ?string
    {
        return $this->tokenFor('courses', $courseId);
    }

    public function fromModule(?int $moduleId): ?string
    {
        return $this->tokenFor('course_modules', $moduleId);
    }

    public function fromAssessment(?int $assessmentId): ?string
    {
        return $this->tokenFor('course_assessments', $assessmentId);
    }

    public function fromQuestion(?int $questionId): ?string
    {
        return $this->tokenFor('assessment_questions', $questionId);
    }

    public function fromEnrolment(?int $enrolmentId): ?string
    {
        return $this->tokenFor('course_enrolments', $enrolmentId);
    }

    public function fromAttempt(?int $attemptId): ?string
    {
        return $this->tokenFor('assessment_attempts', $attemptId);
    }

    public function fromSession(?int $sessionId): ?string
    {
        return $this->tokenFor('assessment_sessions', $sessionId);
    }

    public function fromCredit(?int $creditId): ?string
    {
        return $this->tokenFor('course_credits', $creditId);
    }

    /**
     * The token for a row that joins two resources, rejecting a cross-universe pairing early.
     *
     * The database would refuse it anyway, but a `RuntimeException` naming both sides is far more
     * use to whoever is reading the log than a trigger message naming a column. Used where a row
     * genuinely belongs to two parents at once, such as an enrolment or a company membership.
     */
    public function forPair(string $leftTable, ?int $leftId, string $rightTable, ?int $rightId): ?string
    {
        $left = $this->tokenFor($leftTable, $leftId);
        $right = $this->tokenFor($rightTable, $rightId);

        if (($left === null) !== ($right === null)) {
            throw new RuntimeException(sprintf(
                'Refusing to relate %s #%d to %s #%d: one is real data and the other is seed data.',
                $leftTable,
                (int) $leftId,
                $rightTable,
                (int) $rightId
            ));
        }

        // Both SEED but from different sets is legitimate: tokens are provenance, not tenancy.
        // The new row is attributed to the left-hand parent, which is the subject of the relation.
        return $left ?? $right;
    }

    /** Forgets cached answers. Only needed when a test mutates tokens inside one request. */
    public function forget(): void
    {
        $this->cache = [];
    }
}
