declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;

final class CompanyDepartureRepository
{
    private const COLUMNS = 'd.id, d.company_id, d.user_id, d.reason, d.requested_by_user_id, d.asked_at, d.answer_by, d.status,
        d.private_email, d.decided_at, d.answer_by <= NOW() AS answer_due, c.name AS company_name, c.domain AS company_domain';

    public function __construct(private readonly Database $db)
    {
    }

    public function create(int $companyId, int $userId, string $reason, ?int $requestedBy, string $tokenHash, int $answerSeconds): int
    {
        return (int) $this->db->fetchOne(
            "INSERT INTO company_departures (company_id, user_id, reason, requested_by_user_id, token_hash, answer_by)
             VALUES (:c, :u, :reason, :by, :hash, NOW() + make_interval(secs => :seconds)) RETURNING id",
            ['c' => $companyId, 'u' => $userId, 'reason' => $reason, 'by' => $requestedBy, 'hash' => $tokenHash, 'seconds' => $answerSeconds]
        );
    }

    /** @return array<string,mixed>|null */
    public function waitingFor(int $userId): ?array
    {
        return $this->one("d.user_id = :key AND d.status = 'waiting'", $userId);
    }

    /** @return array<string,mixed>|null */
    public function find(int $id): ?array
    {
        return $this->one('d.id = :key', $id);
    }

    /** @return array<string,mixed>|null */
    public function findByTokenHash(string $hash): ?array
    {
        return $this->one('d.token_hash = :key', $hash);
    }

    /**
     * The waiting records of a company's people, by person.
     *
     * @return array<int,array<string,mixed>>
     */
    public function waitingForCompany(int $companyId): array
    {
        $rows = $this->db->fetchAllAssociative('SELECT ' . self::COLUMNS . " FROM company_departures d JOIN companies c ON c.id = d.company_id
            WHERE d.company_id = :c AND d.status = 'waiting'", ['c' => $companyId]);
        $byPerson = [];
        foreach ($rows as $row) $byPerson[(int) $row['user_id']] = self::shape($row);

        return $byPerson;
    }

    public function setPrivateEmail(int $id, string $email): void
    {
        $this->db->executeStatement('UPDATE company_departures SET private_email = :e WHERE id = :id', ['id' => $id, 'e' => $email]);
    }

    public function decide(int $id, string $status): void
    {
        $this->db->executeStatement("UPDATE company_departures SET status = :s, decided_at = NOW() WHERE id = :id AND status = 'waiting'", ['id' => $id, 's' => $status]);
    }

    /**
     * What a person's learning says about deleting them: how many courses they completed, and the courses they are busy
     * with (started, not completed, access still open).
     *
     * @return array{completed:int,busy:list<string>}
     */
    public function learning(int $userId): array
    {
        $completed = (int) $this->db->fetchOne(
            "SELECT COUNT(*) FROM course_enrolments WHERE user_id = :u AND is_preview = FALSE AND (status = 'completed' OR completed_at IS NOT NULL)",
            ['u' => $userId]
        );
        $busy = $this->db->fetchFirstColumn(
            "SELECT c.title FROM course_enrolments ce JOIN courses c ON c.id = ce.course_id
             WHERE ce.user_id = :u AND ce.is_preview = FALSE AND ce.status = 'active' AND ce.started_at IS NOT NULL AND ce.completed_at IS NULL
               AND (ce.expires_at IS NULL OR ce.expires_at > NOW())
             ORDER BY c.title",
            ['u' => $userId]
        );

        return ['completed' => $completed, 'busy' => array_map('strval', $busy)];
    }

    /** @return array<string,mixed>|null */
    private function one(string $where, int|string $key): ?array
    {
        $rows = $this->db->fetchAllAssociative('SELECT ' . self::COLUMNS . ' FROM company_departures d JOIN companies c ON c.id = d.company_id WHERE ' . $where . ' LIMIT 1', ['key' => $key]);

        return isset($rows[0]) ? self::shape($rows[0]) : null;
    }

    /**
     * @param array<string,mixed> $row
     * @return array<string,mixed>
     */
    private static function shape(array $row): array
    {
        $row['id'] = (int) $row['id'];
        $row['company_id'] = (int) $row['company_id'];
        $row['user_id'] = (int) $row['user_id'];
        $row['answer_due'] = in_array($row['answer_due'], [true, 1, '1', 't', 'true'], true);

        return $row;
    }
}
