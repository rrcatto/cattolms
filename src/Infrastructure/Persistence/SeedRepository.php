    /**
     * Attaches generated courses to existing tags.
     *
     * A tag is a shared label, so the association hangs off the course and goes with it through
     * the ON DELETE CASCADE from `courses`. Its own method rather than a case inside insertMany()
     * so the ON CONFLICT stays visible.
     *
     * @param list<array{0:int,1:int}> $pairs course id, tag id
     */
    public function attachCourseTags(array $pairs): void
    {
        foreach (array_chunk($pairs, self::INSERT_BATCH) as $chunk) {
            $placeholders = [];
            $params = [];
            foreach ($chunk as $index => $pair) {
                $placeholders[] = '(:c' . $index . ',:t' . $index . ')';
                $params['c' . $index] = (int) $pair[0];
                $params['t' . $index] = (int) $pair[1];
            }

            $this->db->executeStatement(
                'INSERT INTO course_tags (course_id, tag_id) VALUES ' . implode(',', $placeholders)
                    . ' ON CONFLICT DO NOTHING',
                $params
            );
        }
    }

    /**
     * Inserts many rows in batches, optionally returning the generated ids in insertion order.
     *
     * PostgreSQL returns RETURNING rows in the order the VALUES were supplied, which is what
     * lets the generator build a parent's id list and then reference it while building children
     * without a second round trip per row.
     *
     * @param list<string> $columns
     * @param list<list<mixed>> $rows
     * @return list<int> generated ids, or an empty list when $returnIds is false
     */
    public function insertMany(string $table, array $columns, array $rows, bool $returnIds = false): array
    {
        if ($rows === []) {
            return [];
        }

        $ids = [];
        foreach (array_chunk($rows, self::INSERT_BATCH) as $chunk) {
            $placeholders = [];
            $params = [];
            foreach ($chunk as $rowIndex => $row) {
                $slots = [];
                foreach ($columns as $columnIndex => $column) {
                    // The name and the placeholder are no longer the same string: DBAL binds by
                    // bare name and the colon belongs only in the SQL.
                    $name = 'v' . $rowIndex . '_' . $columnIndex;
                    $slot = ':' . $name;
                    $cast = self::COLUMN_CASTS[$column] ?? null;
                    $slots[] = $cast === null ? $slot : $slot . '::' . $cast;
                    $params[$name] = $row[$columnIndex] ?? null;
                }
                $placeholders[] = '(' . implode(',', $slots) . ')';
            }

            $sql = 'INSERT INTO ' . $table . ' (' . implode(',', $columns) . ') VALUES '
                . implode(',', $placeholders)
                . ($returnIds ? ' RETURNING id' : '');

            // The statement carries RETURNING only when ids were asked for, so which DBAL call
            // is correct depends on a runtime flag rather than on the SQL as written.
            $result = $returnIds
                ? $this->db->fetchAllAssociative($sql, $params)
                : $this->db->executeStatement($sql, $params);
            if ($returnIds && is_array($result)) {
                foreach ($result as $returned) {
                    $ids[] = (int) ($returned['id'] ?? 0);
                }
            }
        }

        return $ids;
    }

    /**
     * Role ids by role key, so the generator can attach SEED_* roles without a lookup per user.
     *
     * @return array<string,int>
