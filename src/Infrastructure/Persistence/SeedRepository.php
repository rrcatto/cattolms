    }

    /**
     * Every category with the branch it sits in, so a generated course can be named after it.
     *
     * A generated course used to take its title from one word list and its category from another,
     * with nothing connecting them: "Abattoir Hygiene: Awareness" could be filed under Cloud
     * Infrastructure, and the tags on it were picked by arithmetic on the row index. The catalogue
     * was therefore full of courses whose category and tags said nothing true about them.
     *
     * Returning the ancestry with each row is what lets the generator do the whole job from one
     * query: the course is named after the category, and it is tagged with the branch it belongs to.
     *
     * @return list<array{id:int,name:string,level:int,root:string,branch:string}>
     */
    public function categoryTaxonomy(): array
    {
        $rows = $this->db->exec(
            "SELECT c.id, c.name, c.level,
                    COALESCE(r.name, p.name, c.name) AS root,
                    COALESCE(p.name, c.name) AS branch
               FROM course_categories c
               LEFT JOIN course_categories p ON p.id = c.parent_id
               LEFT JOIN course_categories r ON r.id = p.parent_id
              ORDER BY c.level, c.position, c.name"
        );

        return array_map(static fn(array $row): array => [
            'id' => (int) $row['id'],
            'name' => (string) $row['name'],
            'level' => (int) $row['level'],
            'root' => (string) $row['root'],
            'branch' => (string) $row['branch'],
        ], $rows);
    }

    /**
     * Resolves tag names to ids, creating any that do not exist yet.
     *
     * Tags are universe-free labels, so a generated course shares them with the genuine catalogue
     * and none of them carries a seed token. That is also why they are not removed when a seed set
     * is cleaned up: the label outlives the set, exactly as a category does.
     *
     * @param list<string> $names
     * @return array<string,int> Keyed by name.
     */
    public function ensureTags(array $names): array
    {
        $names = array_values(array_unique(array_filter(array_map(trim(...), $names), static fn(string $n): bool => $n !== '')));
        if ($names === []) {
            return [];
        }

        $placeholders = [];
        $params = [];
        foreach ($names as $index => $name) {
            $placeholders[] = '(:n' . $index . ',:s' . $index . ')';
            $params[':n' . $index] = mb_substr($name, 0, 80);
            $params[':s' . $index] = mb_substr(Slug::from($name), 0, 80);
        }

        // ON CONFLICT on the slug, because that is the unique column; the name is not unique in the
        // schema and two labels that slug identically are the same label.
        $this->db->exec(
            'INSERT INTO tags (name, slug) VALUES ' . implode(',', $placeholders) . ' ON CONFLICT (slug) DO NOTHING',
            $params
        );

        $lookup = [];
        foreach ($this->db->exec(
            'SELECT id, name FROM tags WHERE slug IN (' . implode(',', array_map(static fn(int $i): string => ':s' . $i, array_keys($names))) . ')',
            array_filter($params, static fn(string $key): bool => str_starts_with($key, ':s'), ARRAY_FILTER_USE_KEY)
        ) as $row) {
            $lookup[(string) $row['name']] = (int) $row['id'];
        }

        return $lookup;
    }

    /**
     * Attaches tags to courses.
     *
     * Written here rather than through insertMany() because `course_tags` is deliberately not a
     * seed-aware table - it carries no token, and insertMany() refuses any table outside the frozen
     * catalogue. The rows still disappear with their courses, through the cascade.
     *
     * @param list<array{0:int,1:int}> $pairs
     */
    public function insertCourseTags(array $pairs): void
    {
        foreach (array_chunk($pairs, 500) as $chunk) {
            $placeholders = [];
            $params = [];
            foreach ($chunk as $index => [$courseId, $tagId]) {
                $placeholders[] = '(:c' . $index . ', :t' . $index . ')';
                $params[':c' . $index] = $courseId;
                $params[':t' . $index] = $tagId;
            }
            $this->db->exec(
                'INSERT INTO course_tags (course_id, tag_id) VALUES ' . implode(',', $placeholders)
                . ' ON CONFLICT DO NOTHING',
                $params
            );
        }
    }

    /**
     * Every person name already in the database, so a new set cannot reissue one.
     *
     * Both universes are read, not just the generated one. A generated person sharing a name with
     * a real member of staff is exactly as confusing as two generated people sharing one, and the
     * name space is large enough that excluding real names costs nothing.
     *
     * @return list<string>
     */
    public function existingDisplayNames(): array
    {
        return $this->column('SELECT display_name FROM users WHERE display_name IS NOT NULL');
    }

    /** @return list<string> */
    public function existingCompanyNames(): array
    {
        return $this->column('SELECT name FROM companies');
    }

    /** @return list<string> */
    public function existingCourseTitles(): array
    {
        return $this->column('SELECT title FROM courses');
    }

    /**
     * One text column of a query as a flat list.
     *
     * @return list<string>
     */
    private function column(string $sql): array
    {
        $values = [];
        foreach ($this->db->exec($sql) as $row) {
            $value = trim((string) (array_values($row)[0] ?? ''));
            if ($value !== '') {
                $values[] = $value;
            }
        }

        return $values;
    }

    public function totalSeedRows(): int
    {
        $branches = [];
        foreach (SeedTableCatalog::seedAwareTables() as $table) {
            $branches[] = 'SELECT COUNT(*)::int AS total FROM ' . $table . ' WHERE seed_token IS NOT NULL';
        }

        $rows = $this->db->exec('SELECT SUM(total)::int AS grand_total FROM (' . implode(' UNION ALL ', $branches) . ') counts');

        return (int) ($rows[0]['grand_total'] ?? 0);
    }
