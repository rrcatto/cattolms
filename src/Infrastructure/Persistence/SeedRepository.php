    /** @return array<int,array{correct:list<int>,wrong:list<int>}> each question of an assessment, its right and wrong answers */
    public function answers(int $assessmentItemId): array
    {
        $out = [];
        foreach ($this->db->fetchAllAssociative(
            'SELECT o.question_id, o.id, o.is_correct FROM assessment_options o JOIN assessment_questions q ON q.id = o.question_id WHERE q.course_item_id = :i ORDER BY o.question_id, o.position, o.id',
            ['i' => $assessmentItemId]
        ) as $row) {
            $out[(int) $row['question_id']] ??= ['correct' => [], 'wrong' => []];
            $out[(int) $row['question_id']][in_array($row['is_correct'], [true, 1, '1', 't', 'true'], true) ? 'correct' : 'wrong'][] = (int) $row['id'];
        }

        return $out;
    }

