    /**
     * Removes one seed set and every SEED row that cannot survive it.
     *
     * Deleted in `cleanupOrder()` - children before parents - with target rows and cross-set
     * collateral in one plan. Ordering by table dependency rather than by set membership is what
     * prevents the foreign-key violation: no parent is deleted before its children, whichever set
     * they belong to. SeedSchemaContractTest proves the order satisfies every collateral edge.
     *
     * @return array{tables:array<string,int>,collateral:array<string,int>,target:int,records:int}
     */
    public function deleteSet(string $token): array
    {
        if ($token === SeedTableCatalog::INFRASTRUCTURE_TOKEN) {
            throw new RuntimeException('The shared SEED infrastructure cannot be cleaned up as if it were a seed set.');
        }

        $this->buildCleanupPlan($token);
        $summary = $this->summariseCleanupPlan();

        foreach (SeedTableCatalog::cleanupOrder() as $table) {
            $this->db->exec(
                'DELETE FROM ' . $table . ' t
                 USING seed_cleanup_plan p
                 WHERE p.table_name = :table::text
                   AND p.row_key = ' . self::rowKeyExpression($table, 't'),
                [':table' => $table]
            );
        }

        $this->discardCleanupPlan();

        return $summary;
    }

    /**
     * The plan's counts, read before deletion so the figures describe what was planned.
     *
     * @return array{tables:array<string,int>,collateral:array<string,int>,target:int,records:int}
     */
    private function summariseCleanupPlan(): array
    {
        $tables = [];
        foreach ($this->db->exec(
            'SELECT table_name, COUNT(*)::int AS total FROM seed_cleanup_plan GROUP BY table_name'
        ) as $row) {
            $tables[(string) $row['table_name']] = (int) $row['total'];
        }

        $collateral = [];
        foreach ($this->db->exec(
            'SELECT owner_token::text AS other_token, COUNT(*)::int AS total
             FROM seed_cleanup_plan WHERE is_target = FALSE GROUP BY owner_token'
        ) as $row) {
            $collateral[(string) $row['other_token']] = (int) $row['total'];
        }

        $target = (int) ($this->db->exec(
            'SELECT COUNT(*)::int AS total FROM seed_cleanup_plan WHERE is_target = TRUE'
        )[0]['total'] ?? 0);

        return [
            'tables' => $tables,
            'collateral' => $collateral,
            'target' => $target,
            'records' => array_sum($tables),
        ];
    }

    /**
     * Rows left pointing at a parent that no longer exists.
     *
     * A safety net rather than part of the plan: the plan is transitively closed, so against a
     * consistent database this finds nothing. It exists so a row orphaned by some earlier incident
     * does not survive a cleanup meant to tidy up.
     *
     * Catalogue-driven, so a new reference is covered without editing this method.
     *
     * @return array<string,int>
     */
    public function deleteOrphanedSeedRows(): array
    {
        $removed = [];

        foreach (SeedTableCatalog::cleanupOrder() as $table) {
            $conditions = [];
            foreach (SeedTableCatalog::collateralReferences() as $reference) {
                if ($reference['child'] !== $table) {
                    continue;
                }
                $conditions[] = '(c.' . $reference['column'] . ' IS NOT NULL AND NOT EXISTS ('
                    . 'SELECT 1 FROM ' . $reference['parent'] . ' p WHERE p.id = c.' . $reference['column'] . '))';
            }
            if ($conditions === []) {
                continue;
            }

            $rows = $this->db->exec(
                'DELETE FROM ' . $table . ' c
                 WHERE c.seed_token IS NOT NULL AND (' . implode(' OR ', $conditions) . ')
                 RETURNING 1 AS deleted'
            );
            $count = is_array($rows) ? count($rows) : 0;
            if ($count > 0) {
                $removed[$table] = $count;
            }
        }

        return $removed;
    }

    /**
     * Invalidates outstanding passwordless login tokens for the identities being removed.
     *
     * `auth_login_tokens` is deliberately not seed-aware (decision D3), so it cannot be deleted
     * by token. It is cleared by identity instead, and it must happen before those users
     * disappear: a token outliving its user would otherwise be a live login link naming an
     * address nobody owns any more.
     *
     * Two matches rather than one. A token raised for an identity that already exists carries
     * `user_id`, but a token raised before the account was resolved carries only the address, so
     * matching the set's verified addresses as well closes that case. Both sides are anchored on
     * rows belonging to this set, so no REAL identity's token can be caught by either: addresses
     * are unique across `user_emails`, and this deletes nothing that a set identity does not own.
     *
     * Short-lived token semantics are untouched. This is an early expiry of the set's own tokens,
     * not a change to how any token is issued, consumed or pruned.
     */
    public function invalidateLoginTokensForSet(string $token): int
    {
        $rows = $this->db->exec(
            'DELETE FROM auth_login_tokens t
             WHERE EXISTS (
                     SELECT 1 FROM users u
                     WHERE u.id = t.user_id AND u.seed_token = :token::uuid
                 )
                OR EXISTS (
                     SELECT 1 FROM user_emails ue
                     JOIN users u ON u.id = ue.user_id
                     WHERE ue.email = t.email AND u.seed_token = :token::uuid
                 )
             RETURNING 1 AS deleted',
            [':token' => $token]
        );

        return is_array($rows) ? count($rows) : 0;
    }

    /** @param array<string,mixed> $metadata */
    public function markCleaned(string $token, array $metadata): void
    {
        $this->db->exec(
            'UPDATE seed_data SET cleaned_at = NOW(), cleanup_metadata = :metadata::jsonb WHERE seed_token = :token::uuid',
            [':token' => $token, ':metadata' => json_encode($metadata, JSON_THROW_ON_ERROR)]
        );
    }

    /** Total SEED rows across every seed-aware table, for the section summary. */
    /**
     * What one seed set wrote per table, beside what is left of it.
     *
     * Both figures already exist and neither was reachable: `seed_data_tables` records what
     * generation wrote, and currentCounts() derives what physically remains. Showing them together
     * is what makes the pair meaningful - a table whose current count has fallen below its initial
     * one has had rows removed by something other than cleanup, which is worth seeing rather than
     * discovering later.
     *
     * @return list<array{table:string,initial:int,current:int,removed:int}>
     */
    public function setTableBreakdown(string $token): array
    {
        $set = $this->findSet($token);
        if ($set === null) {
            return [];
        }

        $initial = [];
        foreach ($this->db->exec(
            'SELECT t.table_name, t.initial_record_count FROM seed_data_tables t
             JOIN seed_data d ON d.id = t.seed_data_id
             WHERE d.seed_token = :token::uuid',
            [':token' => $token]
        ) as $row) {
            $initial[(string) $row['table_name']] = (int) $row['initial_record_count'];
        }

        $current = $this->currentCounts($token);

        $breakdown = [];
        foreach (SeedTableCatalog::seedAwareTables() as $table) {
            $wrote = $initial[$table] ?? 0;
            $remains = $current[$table] ?? 0;
            if ($wrote === 0 && $remains === 0) {
                continue;
            }
            $breakdown[] = [
                'table' => $table,
                'initial' => $wrote,
                'current' => $remains,
                'removed' => max(0, $wrote - $remains),
            ];
        }

        return $breakdown;
    }

    /**
     * The active course categories, at every level of the hierarchy.
     *
     * Universe-free, so there is no scope to apply: a category belongs to the catalogue rather
     * than to one universe, and a generated course is filed under the same one a genuine course
     * would be.
     *
     * @return list<int>
