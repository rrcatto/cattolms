    /** @return array<string,mixed>|null */
    public function findSet(string $token): ?array
    {
        // A token arrives from a route parameter, and seed_token is a UUID column, so an unparseable
        // value fails in PostgreSQL rather than simply matching nothing.
        if (!Uuid::isValid($token)) {
            return null;
        }

        $rows = $this->db->exec(
            'SELECT * FROM seed_data WHERE seed_token = :token::uuid LIMIT 1',
            [':token' => $token]
        );

        return $rows[0] ?? null;
    }

    /**
     * Current row counts for one seed set, derived from the physical rows (decision D2).
     *
     * One UNION ALL rather than 31 round trips. Every branch hits that table's partial
     * seed_token index, so the whole thing is index-only work no matter how large the REAL
     * universe has grown.
     *
     * @return array<string,int>
     */
    public function currentCounts(string $token): array
    {
        $branches = [];
        foreach (SeedTableCatalog::seedAwareTables() as $table) {
            $branches[] = "SELECT '" . $table . "' AS table_name, COUNT(*)::int AS total"
                . ' FROM ' . $table . ' WHERE seed_token = :token::uuid';
        }

        $counts = [];
        foreach ($this->db->exec(implode(' UNION ALL ', $branches), [':token' => $token]) as $row) {
            $counts[(string) $row['table_name']] = (int) $row['total'];
        }

        return $counts;
    }




    /**
     * Builds the complete set of rows a cleanup would remove, without removing anything.
     *
     * One plan answers two questions that used to be answered separately and inconsistently: the
     * preview counts it, the deletion deletes exactly it.
     *
     * **Row identity.** Rows are named by a JSONB key built from each table's declared primary
     * key, not by an `id` column. Eight of the thirty-one seed-aware tables have a composite or
     * non-surrogate key - `company_users(company_id, user_id)`, `course_results(enrolment_id)` and
     * six others - and an earlier version of this method assumed `t.id` everywhere, which failed
     * on PostgreSQL with `column t.id does not exist`.
     *
     * **Closure.** Seeded with every row carrying the target token, then extended: any SEED row in
     * any set whose parent is already planned is itself planned, repeated until a pass adds
     * nothing. Transitivity is required, not theoretical - a certificate references an enrolment
     * which references a course, and `certificates.enrolment_id` is ON DELETE RESTRICT, so a plan
     * that stopped at one edge would fail when it tried to delete the enrolment.
     *
     * **REAL rows.** Every insert requires `seed_token IS NOT NULL`, so a genuine row has no path
     * into the plan and therefore none into the deletion.
     *
     * A temporary table rather than a PHP array: a seed set may hold hundreds of thousands of
     * rows, and the closure is naturally a join. It is session-local, holds no business data, and
     * is dropped before control returns to the caller.
     *
     * Designed behaviour; proven by the Integration suite against PostgreSQL, not by this comment.
     */
    private function buildCleanupPlan(string $token): void
    {
        $this->db->exec('DROP TABLE IF EXISTS seed_cleanup_plan');
        $this->db->exec(
            'CREATE TEMPORARY TABLE seed_cleanup_plan (
                 table_name  TEXT    NOT NULL,
                 row_key     JSONB   NOT NULL,
                 owner_token UUID    NOT NULL,
                 is_target   BOOLEAN NOT NULL,
                 PRIMARY KEY (table_name, row_key)
             )'
        );

        foreach (SeedTableCatalog::seedAwareTables() as $table) {
            $this->db->exec(
                'INSERT INTO seed_cleanup_plan (table_name, row_key, owner_token, is_target)
                 SELECT :table::text, ' . self::rowKeyExpression($table, 't') . ', t.seed_token, TRUE
                 FROM ' . $table . ' t
                 WHERE t.seed_token = :token::uuid
                 ON CONFLICT (table_name, row_key) DO NOTHING',
                [':table' => $table, ':token' => $token]
            );
        }

        // Every foreign key in the catalogue targets its parent's single `id` column, which
        // SeedSchemaContractTest asserts. That is what lets the join below compare the parent's
        // planned key against one child column.
        do {
            $added = 0;
            foreach (SeedTableCatalog::collateralReferences() as $reference) {
                $rows = $this->db->exec(
                    'INSERT INTO seed_cleanup_plan (table_name, row_key, owner_token, is_target)
                     SELECT :child::text, ' . self::rowKeyExpression($reference['child'], 'c') . ', c.seed_token, FALSE
                     FROM ' . $reference['child'] . ' c
                     JOIN seed_cleanup_plan p
                       ON p.table_name = :parent::text
                      AND p.row_key = jsonb_build_object(\'id\', c.' . $reference['column'] . ')
                     WHERE c.seed_token IS NOT NULL
                       AND c.' . $reference['column'] . ' IS NOT NULL
                     ON CONFLICT (table_name, row_key) DO NOTHING
                     RETURNING 1 AS planned',
                    [':child' => $reference['child'], ':parent' => $reference['parent']]
                );
                $added += is_array($rows) ? count($rows) : 0;
            }
        } while ($added > 0);

        // A temporary table is never reached by autovacuum, so the planner has no statistics for it
        // at all and falls back to a fixed guess. Every DELETE below joins against this table, and a
        // plan chosen from a guess about a table holding a million rows is not the plan those
        // deletes need. One ANALYZE costs milliseconds and is the difference between a nested loop
        // and a hash join.
        $this->db->exec('ANALYZE seed_cleanup_plan');
    }

    /**
     * The JSONB key naming one row of a table, built from its declared primary key.
     *
     * Deliberately not a concatenated string: a delimiter scheme would need a collision-safety
     * argument, and `jsonb_build_object` gives typed, comparable keys with none required.
     */
    private static function rowKeyExpression(string $table, string $alias): string
    {
        $parts = [];
        foreach (SeedTableCatalog::rowIdentity($table) as $column) {
            $parts[] = "'" . $column . "', " . $alias . '.' . $column;
        }

        return 'jsonb_build_object(' . implode(', ', $parts) . ')';
    }

    private function discardCleanupPlan(): void
    {
        $this->db->exec('DROP TABLE IF EXISTS seed_cleanup_plan');
    }

    /**
     * Rows belonging to other seed sets that cannot survive this one's removal.
     *
     * Seed tokens are provenance, not tenancy: a learner generated in set B may legitimately be
     * enrolled on a course generated in set A. Cleaning A therefore reaches into other sets, and
     * the operator must see that before confirming.
     *
     * @return array<string,int> other set token => rows that will be removed with this one
     */
    public function collateralImpact(string $token): array
    {
        $this->buildCleanupPlan($token);
        $impact = $this->summariseCleanupPlan()['collateral'];
        $this->discardCleanupPlan();

        return $impact;
    }

    /**
     * Everything the plan will remove, for the preview.
