{
    /**
     * Rows per INSERT statement.
     *
     * Large enough that a 500,000-row set is a few thousand statements rather than half a
     * million, small enough that one statement's parameter list stays well inside the
     * PostgreSQL protocol's 65,535 bound-parameter limit even for the widest table here.
     */
    private const INSERT_BATCH = 250;

    /** Columns needing an explicit cast, because a bound parameter arrives as text. */
    private const COLUMN_CASTS = [
        'public_id' => 'uuid',
        'seed_token' => 'uuid',
        'ip_address' => 'inet',
    ];

    public function __construct(private readonly SQL $db)
    {
    }

    /**
     * Inserts many rows in batches, optionally returning the generated ids in insertion order.
     *
     * PostgreSQL returns RETURNING rows in the order the VALUES were supplied, which is what
     * lets the generator build a parent's id list and then reference it while building children
     * without a second round trip per row.
     *
     * @param list<string> $columns
     * @param list<list<mixed>> $rows
     * @return list<int> generated ids, or an empty list when $returnIds is false
     */
    public function insertMany(string $table, array $columns, array $rows, bool $returnIds = false): array
    {
        if (!SeedTableCatalog::isSeedAware($table)) {
            throw new RuntimeException('Refusing to seed a table outside the frozen catalogue: ' . $table);
        }
        if ($rows === []) {
            return [];
        }

        $ids = [];
        foreach (array_chunk($rows, self::INSERT_BATCH) as $chunk) {
            $placeholders = [];
            $params = [];
            foreach ($chunk as $rowIndex => $row) {
                $slots = [];
                foreach ($columns as $columnIndex => $column) {
                    $key = ':v' . $rowIndex . '_' . $columnIndex;
                    $cast = self::COLUMN_CASTS[$column] ?? null;
                    $slots[] = $cast === null ? $key : $key . '::' . $cast;
                    $params[$key] = $row[$columnIndex] ?? null;
                }
                $placeholders[] = '(' . implode(',', $slots) . ')';
            }

            $sql = 'INSERT INTO ' . $table . ' (' . implode(',', $columns) . ') VALUES '
                . implode(',', $placeholders)
                . ($returnIds ? ' RETURNING id' : '');

            $result = $this->db->exec($sql, $params);
            if ($returnIds && is_array($result)) {
                foreach ($result as $returned) {
                    $ids[] = (int) ($returned['id'] ?? 0);
                }
            }
        }

        return $ids;
    }

    /**
     * Role ids by role key, so the generator can attach SEED_* roles without a lookup per user.
     *
     * @return array<string,int>
     */
    public function roleIdsByKey(): array
    {
        $map = [];
        foreach ($this->db->exec('SELECT id, role_key FROM roles') as $row) {
            $map[(string) $row['role_key']] = (int) $row['id'];
        }

        return $map;
    }

    /** The shared SEED System Company created by the baseline (decision D1). */
    public function seedSystemCompanyId(): int
    {
        $rows = $this->db->exec(
            'SELECT id FROM companies WHERE is_system = TRUE AND seed_token = :token LIMIT 1',
            [':token' => SeedTableCatalog::INFRASTRUCTURE_TOKEN]
        );

        $id = (int) ($rows[0]['id'] ?? 0);
        if ($id < 1) {
            throw new RuntimeException(
                'The shared SEED System Company is missing. The database predates the v0.5.8 baseline.'
            );
        }

        return $id;
    }

    /** Records the completed set. Only historical figures are stored (decision D2). */
    public function recordSet(
        string $token,
        string $description,
        int $requestedVolume,
        int $initialRecordCount,
        float $generationSeconds,
        ?int $actorUserId
    ): int {
        $rows = $this->db->exec(
            'INSERT INTO seed_data (seed_token, description, requested_volume, initial_record_count, generation_seconds, created_by_user_id)
             VALUES (:token::uuid, :description, :volume, :records, :seconds, :actor)
             RETURNING id',
            [
                ':token' => $token,
                ':description' => $description,
                ':volume' => $requestedVolume,
                ':records' => $initialRecordCount,
                ':seconds' => round($generationSeconds, 3),
                ':actor' => $actorUserId,
            ]
        );

        return (int) ($rows[0]['id'] ?? 0);
    }

    /** @param array<string,int> $counts */
    public function recordSetTables(int $seedDataId, array $counts): void
    {
        $rows = [];
        foreach ($counts as $table => $count) {
            if ($count > 0) {
                $rows[] = [$seedDataId, $table, $count];
            }
        }
        if ($rows === []) {
            return;
        }

        $placeholders = [];
        $params = [];
        foreach ($rows as $index => $row) {
            $placeholders[] = '(:s' . $index . ', :t' . $index . ', :c' . $index . ')';
            $params[':s' . $index] = $row[0];
            $params[':t' . $index] = $row[1];
            $params[':c' . $index] = $row[2];
        }

        $this->db->exec(
            'INSERT INTO seed_data_tables (seed_data_id, table_name, initial_record_count) VALUES '
            . implode(',', $placeholders),
            $params
        );
    }

    /**
     * Every recorded seed set, newest first, with its historical figures.
     *
     * Current counts are deliberately not joined here: they are derived per set on demand, and
     * doing that inside a list query would mean one COUNT per seed-aware table per row.
     *
     * @return list<array<string,mixed>>
     */
    public function sets(): array
    {
        return $this->db->exec(
            "SELECT s.id, s.seed_token, s.description, s.requested_volume, s.initial_record_count,
                    s.generation_seconds, s.created_at, s.cleaned_at, s.cleanup_metadata,
                    COALESCE(NULLIF(trim(concat_ws(' ', u.first_name, u.last_name)), ''), u.display_name, ue.email, 'System') AS created_by_name
             FROM seed_data s
             LEFT JOIN users u ON u.id = s.created_by_user_id
             LEFT JOIN user_emails ue ON ue.user_id = u.id AND ue.is_primary = TRUE
             ORDER BY s.created_at DESC, s.id DESC"
        );
    }

    /** @return array<string,mixed>|null */
    public function findSet(string $token): ?array
    {
        $rows = $this->db->exec(
            'SELECT * FROM seed_data WHERE seed_token = :token::uuid LIMIT 1',
            [':token' => $token]
        );

        return $rows[0] ?? null;
    }

    /**
     * Current row counts for one seed set, derived from the physical rows (decision D2).
     *
     * One UNION ALL rather than 31 round trips. Every branch hits that table's partial
     * seed_token index, so the whole thing is index-only work no matter how large the REAL
     * universe has grown.
     *
     * @return array<string,int>
     */
    public function currentCounts(string $token): array
    {
        $branches = [];
        foreach (SeedTableCatalog::seedAwareTables() as $table) {
            $branches[] = "SELECT '" . $table . "' AS table_name, COUNT(*)::int AS total"
                . ' FROM ' . $table . ' WHERE seed_token = :token::uuid';
        }

        $counts = [];
        foreach ($this->db->exec(implode(' UNION ALL ', $branches), [':token' => $token]) as $row) {
            $counts[(string) $row['table_name']] = (int) $row['total'];
        }

        return $counts;
    }




    /**
     * Builds the complete set of rows a cleanup would remove, without removing anything.
     *
     * One plan answers two questions that used to be answered separately and inconsistently: the
     * preview counts it, the deletion deletes exactly it.
     *
     * **Row identity.** Rows are named by a JSONB key built from each table's declared primary
     * key, not by an `id` column. Eight of the thirty-one seed-aware tables have a composite or
     * non-surrogate key - `company_users(company_id, user_id)`, `course_results(enrolment_id)` and
     * six others - and an earlier version of this method assumed `t.id` everywhere, which failed
     * on PostgreSQL with `column t.id does not exist`.
     *
     * **Closure.** Seeded with every row carrying the target token, then extended: any SEED row in
     * any set whose parent is already planned is itself planned, repeated until a pass adds
     * nothing. Transitivity is required, not theoretical - a certificate references an enrolment
     * which references a course, and `certificates.enrolment_id` is ON DELETE RESTRICT, so a plan
     * that stopped at one edge would fail when it tried to delete the enrolment.
     *
     * **REAL rows.** Every insert requires `seed_token IS NOT NULL`, so a genuine row has no path
     * into the plan and therefore none into the deletion.
     *
     * A temporary table rather than a PHP array: a seed set may hold hundreds of thousands of
     * rows, and the closure is naturally a join. It is session-local, holds no business data, and
     * is dropped before control returns to the caller.
     *
     * Designed behaviour; proven by the Integration suite against PostgreSQL, not by this comment.
     */
    private function buildCleanupPlan(string $token): void
    {
        $this->db->exec('DROP TABLE IF EXISTS seed_cleanup_plan');
        $this->db->exec(
            'CREATE TEMPORARY TABLE seed_cleanup_plan (
                 table_name  TEXT    NOT NULL,
                 row_key     JSONB   NOT NULL,
                 owner_token UUID    NOT NULL,
                 is_target   BOOLEAN NOT NULL,
                 PRIMARY KEY (table_name, row_key)
             )'
        );

        foreach (SeedTableCatalog::seedAwareTables() as $table) {
            $this->db->exec(
                'INSERT INTO seed_cleanup_plan (table_name, row_key, owner_token, is_target)
                 SELECT :table::text, ' . self::rowKeyExpression($table, 't') . ', t.seed_token, TRUE
                 FROM ' . $table . ' t
                 WHERE t.seed_token = :token::uuid
                 ON CONFLICT (table_name, row_key) DO NOTHING',
                [':table' => $table, ':token' => $token]
            );
        }

        // Every foreign key in the catalogue targets its parent's single `id` column, which
        // SeedSchemaContractTest asserts. That is what lets the join below compare the parent's
        // planned key against one child column.
        do {
            $added = 0;
            foreach (SeedTableCatalog::collateralReferences() as $reference) {
                $rows = $this->db->exec(
                    'INSERT INTO seed_cleanup_plan (table_name, row_key, owner_token, is_target)
                     SELECT :child::text, ' . self::rowKeyExpression($reference['child'], 'c') . ', c.seed_token, FALSE
                     FROM ' . $reference['child'] . ' c
                     JOIN seed_cleanup_plan p
                       ON p.table_name = :parent::text
                      AND p.row_key = jsonb_build_object(\'id\', c.' . $reference['column'] . ')
                     WHERE c.seed_token IS NOT NULL
                       AND c.' . $reference['column'] . ' IS NOT NULL
                     ON CONFLICT (table_name, row_key) DO NOTHING
                     RETURNING 1 AS planned',
                    [':child' => $reference['child'], ':parent' => $reference['parent']]
                );
                $added += is_array($rows) ? count($rows) : 0;
            }
        } while ($added > 0);
    }

    /**
     * The JSONB key naming one row of a table, built from its declared primary key.
     *
     * Deliberately not a concatenated string: a delimiter scheme would need a collision-safety
     * argument, and `jsonb_build_object` gives typed, comparable keys with none required.
     */
    private static function rowKeyExpression(string $table, string $alias): string
    {
        $parts = [];
        foreach (SeedTableCatalog::rowIdentity($table) as $column) {
            $parts[] = "'" . $column . "', " . $alias . '.' . $column;
        }

        return 'jsonb_build_object(' . implode(', ', $parts) . ')';
    }

    private function discardCleanupPlan(): void
    {
        $this->db->exec('DROP TABLE IF EXISTS seed_cleanup_plan');
    }

    /**
     * Rows belonging to other seed sets that cannot survive this one's removal.
     *
     * Seed tokens are provenance, not tenancy: a learner generated in set B may legitimately be
     * enrolled on a course generated in set A. Cleaning A therefore reaches into other sets, and
     * the operator must see that before confirming.
     *
     * @return array<string,int> other set token => rows that will be removed with this one
     */
    public function collateralImpact(string $token): array
    {
        $this->buildCleanupPlan($token);
        $impact = $this->summariseCleanupPlan()['collateral'];
        $this->discardCleanupPlan();

        return $impact;
    }

    /**
     * Everything the plan will remove, for the preview.
     *
     * @return array{tables:array<string,int>,collateral:array<string,int>,target:int,records:int}
     */
    public function cleanupPlanSummary(string $token): array
    {
        $this->buildCleanupPlan($token);
        $summary = $this->summariseCleanupPlan();
        $this->discardCleanupPlan();

        return $summary;
    }

    /**
     * Removes one seed set and every SEED row that cannot survive it.
     *
     * Deleted in `cleanupOrder()` - children before parents - with target rows and cross-set
     * collateral in one plan. Ordering by table dependency rather than by set membership is what
     * prevents the foreign-key violation: no parent is deleted before its children, whichever set
     * they belong to. SeedSchemaContractTest proves the order satisfies every collateral edge.
     *
     * @return array{tables:array<string,int>,collateral:array<string,int>,target:int,records:int}
     */
    public function deleteSet(string $token): array
    {
        if ($token === SeedTableCatalog::INFRASTRUCTURE_TOKEN) {
            throw new RuntimeException('The shared SEED infrastructure cannot be cleaned up as if it were a seed set.');
        }

        $this->buildCleanupPlan($token);
        $summary = $this->summariseCleanupPlan();

        foreach (SeedTableCatalog::cleanupOrder() as $table) {
            $this->db->exec(
                'DELETE FROM ' . $table . ' t
                 USING seed_cleanup_plan p
                 WHERE p.table_name = :table::text
                   AND p.row_key = ' . self::rowKeyExpression($table, 't'),
                [':table' => $table]
            );
        }

        $this->discardCleanupPlan();

        return $summary;
    }

    /**
     * The plan's counts, read before deletion so the figures describe what was planned.
     *
     * @return array{tables:array<string,int>,collateral:array<string,int>,target:int,records:int}
     */
    private function summariseCleanupPlan(): array
    {
        $tables = [];
        foreach ($this->db->exec(
            'SELECT table_name, COUNT(*)::int AS total FROM seed_cleanup_plan GROUP BY table_name'
        ) as $row) {
            $tables[(string) $row['table_name']] = (int) $row['total'];
        }

        $collateral = [];
        foreach ($this->db->exec(
            'SELECT owner_token::text AS other_token, COUNT(*)::int AS total
             FROM seed_cleanup_plan WHERE is_target = FALSE GROUP BY owner_token'
        ) as $row) {
            $collateral[(string) $row['other_token']] = (int) $row['total'];
        }

        $target = (int) ($this->db->exec(
            'SELECT COUNT(*)::int AS total FROM seed_cleanup_plan WHERE is_target = TRUE'
        )[0]['total'] ?? 0);

        return [
            'tables' => $tables,
            'collateral' => $collateral,
            'target' => $target,
            'records' => array_sum($tables),
        ];
    }

    /**
     * Rows left pointing at a parent that no longer exists.
     *
     * A safety net rather than part of the plan: the plan is transitively closed, so against a
     * consistent database this finds nothing. It exists so a row orphaned by some earlier incident
     * does not survive a cleanup meant to tidy up.
     *
     * Catalogue-driven, so a new reference is covered without editing this method.
     *
     * @return array<string,int>
     */
    public function deleteOrphanedSeedRows(): array
    {
        $removed = [];

        foreach (SeedTableCatalog::cleanupOrder() as $table) {
            $conditions = [];
            foreach (SeedTableCatalog::collateralReferences() as $reference) {
                if ($reference['child'] !== $table) {
                    continue;
                }
                $conditions[] = '(c.' . $reference['column'] . ' IS NOT NULL AND NOT EXISTS ('
                    . 'SELECT 1 FROM ' . $reference['parent'] . ' p WHERE p.id = c.' . $reference['column'] . '))';
            }
            if ($conditions === []) {
                continue;
            }

            $rows = $this->db->exec(
                'DELETE FROM ' . $table . ' c
                 WHERE c.seed_token IS NOT NULL AND (' . implode(' OR ', $conditions) . ')
                 RETURNING 1 AS deleted'
            );
            $count = is_array($rows) ? count($rows) : 0;
            if ($count > 0) {
                $removed[$table] = $count;
            }
        }

        return $removed;
    }

    /**
     * Invalidates outstanding passwordless login tokens for the identities being removed.
     *
     * `auth_login_tokens` is deliberately not seed-aware (decision D3), so it cannot be deleted
     * by token. It is cleared by identity instead, and it must happen before those users
     * disappear: a token outliving its user would otherwise be a live login link naming an
     * address nobody owns any more.
     *
     * Two matches rather than one. A token raised for an identity that already exists carries
     * `user_id`, but a token raised before the account was resolved carries only the address, so
     * matching the set's verified addresses as well closes that case. Both sides are anchored on
     * rows belonging to this set, so no REAL identity's token can be caught by either: addresses
     * are unique across `user_emails`, and this deletes nothing that a set identity does not own.
     *
     * Short-lived token semantics are untouched. This is an early expiry of the set's own tokens,
     * not a change to how any token is issued, consumed or pruned.
     */
    public function invalidateLoginTokensForSet(string $token): int
    {
        $rows = $this->db->exec(
            'DELETE FROM auth_login_tokens t
             WHERE EXISTS (
                     SELECT 1 FROM users u
                     WHERE u.id = t.user_id AND u.seed_token = :token::uuid
                 )
                OR EXISTS (
                     SELECT 1 FROM user_emails ue
                     JOIN users u ON u.id = ue.user_id
                     WHERE ue.email = t.email AND u.seed_token = :token::uuid
                 )
             RETURNING 1 AS deleted',
            [':token' => $token]
        );

        return is_array($rows) ? count($rows) : 0;
    }

    /** @param array<string,mixed> $metadata */
    public function markCleaned(string $token, array $metadata): void
    {
        $this->db->exec(
            'UPDATE seed_data SET cleaned_at = NOW(), cleanup_metadata = :metadata::jsonb WHERE seed_token = :token::uuid',
            [':token' => $token, ':metadata' => json_encode($metadata, JSON_THROW_ON_ERROR)]
        );
    }

    /** Total SEED rows across every seed-aware table, for the section summary. */
    public function totalSeedRows(): int
    {
        $branches = [];
        foreach (SeedTableCatalog::seedAwareTables() as $table) {
            $branches[] = 'SELECT COUNT(*)::int AS total FROM ' . $table . ' WHERE seed_token IS NOT NULL';
        }

        $rows = $this->db->exec('SELECT SUM(total)::int AS grand_total FROM (' . implode(' UNION ALL ', $branches) . ') counts');

        return (int) ($rows[0]['grand_total'] ?? 0);
    }
