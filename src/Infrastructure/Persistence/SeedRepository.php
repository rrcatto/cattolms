Architectural boundary: persistence only. This class decides nothing about what seed data should
look like - that is SeedGenerator - and nothing about who may generate it, which is the
controller's ACL check. It owns the SQL, which is where the architecture check requires SQL to
live.

Decision D2 shapes the counting here: historical counts are stored once at generation, and the
current count is always derived from the physical rows through the indexed seed_token column.
There are deliberately no counter triggers and no stored remaining_record_count, because a
stored figure can drift from the rows it claims to describe and a derived one cannot.

