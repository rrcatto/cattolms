{
    /** Rows per INSERT. At generation volumes this is the difference between seconds and minutes. */
    private const INSERT_BATCH = 250;

    /** Columns PostgreSQL will not infer from a bound string, so the placeholder states the type. */
    private const COLUMN_CASTS = [
        'public_id' => 'uuid',
        'ip_address' => 'inet',
    ];

    public function __construct(
        private readonly Database $db,
        private readonly ArtworkGenerator $artwork
    ) {
    }

    /**
     * Attaches generated courses to existing tags.
     *
     * A tag is a shared label, so the association hangs off the course and goes with it through
     * the ON DELETE CASCADE from `courses`. Its own method rather than a case inside insertMany()
     * so the ON CONFLICT stays visible.
     *
     * @param list<array{0:int,1:int}> $pairs course id, tag id
     */
    public function attachCourseTags(array $pairs): void
    {
        foreach (array_chunk($pairs, self::INSERT_BATCH) as $chunk) {
            $placeholders = [];
            $params = [];
            foreach ($chunk as $index => $pair) {
                $placeholders[] = '(:c' . $index . ',:t' . $index . ')';
                $params['c' . $index] = (int) $pair[0];
                $params['t' . $index] = (int) $pair[1];
            }

            $this->db->executeStatement(
                'INSERT INTO course_tags (course_id, tag_id) VALUES ' . implode(',', $placeholders)
                    . ' ON CONFLICT DO NOTHING',
                $params
            );
        }
    }

    /**
     * Inserts many rows in batches, optionally returning the generated ids in insertion order.
     *
     * PostgreSQL returns RETURNING rows in the order the VALUES were supplied, which is what
     * lets the generator build a parent's id list and then reference it while building children
     * without a second round trip per row.
     *
     * @param list<string> $columns
     * @param list<list<mixed>> $rows
     * @return list<int> generated ids, or an empty list when $returnIds is false
     */
    public function insertMany(string $table, array $columns, array $rows, bool $returnIds = false): array
    {
        if ($rows === []) {
            return [];
        }

        // A row wider than the column list is a bug, not a row with spare parts.
        //
        // The loop below walks the columns and indexes into the row, so a value past the last
        // column is silently dropped - and a value in front of it silently lands in the wrong
        // column. That is exactly what happened to generated course artwork: a leftover token sat
        // second-from-last in the row, took the `cover_svg` column, and pushed the artwork off the
        // end. Every catalogue card rendered a sixteen-character hex string instead of a cover, and
        // nothing failed anywhere.
        $width = count($columns);
        foreach ($rows as $index => $row) {
            if (count($row) !== $width) {
                throw new \RuntimeException(
                    'Seed insert into ' . $table . ' has ' . $width . ' columns but row ' . $index
                    . ' has ' . count($row) . ' values. A row must state exactly one value per column.'
                );
            }
        }

        $ids = [];
        foreach (array_chunk($rows, self::INSERT_BATCH) as $chunk) {
            $placeholders = [];
            $params = [];
            foreach ($chunk as $rowIndex => $row) {
                $slots = [];
                foreach ($columns as $columnIndex => $column) {
                    // The name and the placeholder are no longer the same string: DBAL binds by
                    // bare name and the colon belongs only in the SQL.
                    $name = 'v' . $rowIndex . '_' . $columnIndex;
                    $slot = ':' . $name;
                    $cast = self::COLUMN_CASTS[$column] ?? null;
                    $slots[] = $cast === null ? $slot : $slot . '::' . $cast;
                    $params[$name] = $row[$columnIndex] ?? null;
                }
                $placeholders[] = '(' . implode(',', $slots) . ')';
            }

            $sql = 'INSERT INTO ' . $table . ' (' . implode(',', $columns) . ') VALUES '
                . implode(',', $placeholders)
                . ($returnIds ? ' RETURNING id' : '');

            // The statement carries RETURNING only when ids were asked for, so which DBAL call
            // is correct depends on a runtime flag rather than on the SQL as written.
            $result = $returnIds
                ? $this->db->fetchAllAssociative($sql, $params)
                : $this->db->executeStatement($sql, $params);
            if ($returnIds && is_array($result)) {
                foreach ($result as $returned) {
                    $ids[] = (int) ($returned['id'] ?? 0);
                }
            }
        }

        return $ids;
    }

    /**
     * Role ids by role key, so the generator can attach SEED_* roles without a lookup per user.
     *
     * @return array<string,int>
     */
    public function roleIdsByKey(): array
    {
        $map = [];
        foreach ($this->db->fetchAllAssociative('SELECT id, role_key FROM roles') as $row) {
            $map[(string) $row['role_key']] = (int) $row['id'];
        }

        return $map;
    }

    /**
     * Every category with the branch it sits in, so a generated course can be named after it.
     *
     * A generated course used to take its title from one word list and its category from another,
     * with nothing connecting them: "Abattoir Hygiene: Awareness" could be filed under Cloud
     * Infrastructure, and the tags on it were picked by arithmetic on the row index. The catalogue
     * was therefore full of courses whose category and tags said nothing true about them.
     *
     * Returning the ancestry with each row is what lets the generator do the whole job from one
     * query: the course is named after the category, and it is tagged with the branch it belongs to.
     *
     * @return list<array{id:int,name:string,level:int,root:string,branch:string}>
     */
    public function categoryTaxonomy(): array
    {
        $rows = $this->db->fetchAllAssociative(
            "SELECT c.id, c.name, c.level,
                    COALESCE(r.name, p.name, c.name) AS root,
                    COALESCE(p.name, c.name) AS branch
               FROM course_categories c
               LEFT JOIN course_categories p ON p.id = c.parent_id
               LEFT JOIN course_categories r ON r.id = p.parent_id
              ORDER BY c.level, c.position, c.name"
        );

        return array_map(static fn(array $row): array => [
            'id' => (int) $row['id'],
            'name' => (string) $row['name'],
            'level' => (int) $row['level'],
            'root' => (string) $row['root'],
            'branch' => (string) $row['branch'],
        ], $rows);
    }

    /**
     * Resolves tag names to ids, creating any that do not exist yet.
     *
     * Tags are universe-free labels, so a generated course shares them with the genuine catalogue
     * and none of them carries a seed token. That is also why they are not removed when a seed set
     * is cleaned up: the label outlives the set, exactly as a category does.
     *
     * @param list<string> $names
     * @return array<string,int> Keyed by name.
     */
    public function ensureTags(array $names): array
    {
        $names = array_values(array_unique(array_filter(array_map(trim(...), $names), static fn(string $n): bool => $n !== '')));
        if ($names === []) {
            return [];
        }

        $placeholders = [];
        $params = [];
        foreach ($names as $index => $name) {
            $placeholders[] = '(:n' . $index . ',:s' . $index . ',:i' . $index . ')';
            $label = mb_substr($name, 0, 80);
            $slug = mb_substr(Slug::from($name), 0, 80);
            $params['n' . $index] = $label;
            $params['s' . $index] = $slug;
            // A tag created here is a tag like any other and gets its icon in the same statement,
            // for the same reason the administration form does: a chip with no icon beside chips
            // that have one reads as a rendering failure rather than as a tag.
            $params['i' . $index] = $this->artwork->tagIcon($slug, $label);
        }

        // ON CONFLICT on the slug, because that is the unique column; the name is not unique in the
        // schema and two labels that slug identically are the same label.
        $this->db->executeStatement(
            'INSERT INTO tags (name, slug, icon_svg) VALUES ' . implode(',', $placeholders) . ' ON CONFLICT (slug) DO NOTHING',
            $params
        );

        $lookup = [];
        foreach ($this->db->fetchAllAssociative(
            'SELECT id, name FROM tags WHERE slug IN (' . implode(',', array_map(static fn(int $i): string => ':s' . $i, array_keys($names))) . ')',
            array_filter($params, static fn(string $key): bool => str_starts_with($key, 's'), ARRAY_FILTER_USE_KEY)
        ) as $row) {
            $lookup[(string) $row['name']] = (int) $row['id'];
        }

        return $lookup;
    }

