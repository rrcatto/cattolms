declare(strict_types=1);

namespace CattoLearning\Infrastructure\Persistence;

use CattoLearning\Support\SortOrder;
use CattoPHP\Signup\SignupAttempts;

final class SignupAttemptRepository
{
    /** The list's sorts: key => column. */
    public const SORTS = ['created' => 'a.created_at', 'risk' => 'a.score', 'email' => 'a.email', 'country' => 'a.country_code', 'outcome' => 'a.outcome'];

    /** An attempt with its account type, and the account it became by its user id, name and reference. */
    private const SELECT = 'SELECT ' . SignupAttempts::COLUMNS . ", COALESCE(a.details->>'account_type', 'individual') AS account_type, u.id AS user_id,
            u.status AS user_status, COALESCE(NULLIF(trim(concat_ws(' ', u.first_name, u.last_name)), ''), u.display_name) AS user_name, u.account_reference AS user_reference
        FROM cattophp_signup_attempts a LEFT JOIN users u ON u.id = CASE WHEN a.account ~ '^[0-9]+$' THEN CAST(a.account AS BIGINT) END";

    public function __construct(private readonly Database $db, private readonly SignupAttempts $records)
    {
    }

    /** @return array<string,mixed>|null */
    public function find(int $id): ?array
    {
        $row = $this->db->fetchAssociative(self::SELECT . ' WHERE a.id = :id', ['id' => $id]);

        return $row === false ? null : self::decode($row);
    }

    /** @return array<string,mixed>|null the attempt an account was registered by */
    public function forUser(int $userId): ?array
    {
        $row = $this->db->fetchAssociative(self::SELECT . ' WHERE a.account = :user ORDER BY a.completed_at DESC NULLS LAST, a.id DESC LIMIT 1', ['user' => (string) $userId]);

        return $row === false ? null : self::decode($row);
    }

    /**
     * Each account's band, score and country, for a page of people.
     *
     * @param list<int> $userIds
     * @return array<int,array{id:int,band:string,score:int,country_code:string}>
     */
    public function forUsers(array $userIds): array
    {
        $found = [];
        foreach ($this->records->forAccounts(array_values(array_map('strval', array_filter(array_map('intval', $userIds), static fn(int $id): bool => $id > 0)))) as $account => $attempt) {
            $found[(int) $account] = $attempt;
        }

        return $found;
    }

    /**
     * A page of attempts, newest first unless sorted otherwise.
     *
     * @return list<array<string,mixed>>
     */
    public function page(string $search, string $band, string $outcome, SortOrder $sort, int $limit, int $offset): array
    {
        [$where, $params] = self::filters($search, $band, $outcome);
        $column = self::SORTS[$sort->key] ?? 'a.created_at';
        $direction = $sort->direction === SortOrder::ASCENDING ? 'ASC' : 'DESC';

        return array_map([self::class, 'decode'], $this->db->fetchAllAssociative(
            self::SELECT . $where . " ORDER BY {$column} {$direction} NULLS LAST, a.id DESC LIMIT :limit OFFSET :offset",
            $params + ['limit' => $limit, 'offset' => $offset]
        ));
    }

    public function count(string $search, string $band, string $outcome): int
    {
        [$where, $params] = self::filters($search, $band, $outcome);

        return (int) $this->db->fetchOne('SELECT COUNT(*) FROM cattophp_signup_attempts a' . $where, $params);
    }

    /** @return array<string,int> attempts in the last 30 days by band, and in all */
    public function lastMonth(): array
    {
        return $this->records->lastMonth();
    }

    /** @return array{0:string,1:array<string,mixed>} */
    private static function filters(string $search, string $band, string $outcome): array
    {
        $where = [];
        $params = [];
        $search = trim($search);
        if ($search !== '') {
            $where[] = "(a.email ILIKE :search OR concat_ws(' ', a.first_name, a.last_name) ILIKE :search OR host(a.ip_address) LIKE :prefix OR a.network_name ILIKE :search OR a.country_code = upper(:exact))";
            $params += ['search' => '%' . addcslashes($search, '%_\\') . '%', 'prefix' => addcslashes($search, '%_\\') . '%', 'exact' => $search];
        }
        if (in_array($band, ['low', 'medium', 'high'], true)) { $where[] = 'a.band = :band'; $params['band'] = $band; }
        if (in_array($outcome, SignupAttempts::OUTCOMES, true)) { $where[] = 'a.outcome = :outcome'; $params['outcome'] = $outcome; }

        return [$where === [] ? '' : ' WHERE ' . implode(' AND ', $where), $params];
    }

    /**
     * @param array<string,mixed> $row
     * @return array<string,mixed>
     */
    private static function decode(array $row): array
    {
        $row = SignupAttempts::decode($row);
        // The person is their user id here; 'account' is the page's own (SignupAttemptsController::row).
        unset($row['account']);
        $row['user_id'] = $row['user_id'] === null ? null : (int) $row['user_id'];

        return $row;
    }
}
