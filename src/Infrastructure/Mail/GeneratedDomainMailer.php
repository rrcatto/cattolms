Rewrites the delivery address of mail sent to a generated seed identity, then delegates to the
real mailer.

This decorator exists so the rewrite happens in exactly one place. Every outgoing message in the
platform goes through MailerInterface, so wrapping the interface catches magic links, secondary
email verification, staff notices and course-request decisions without any of those call sites
knowing that seed data exists.

