    /** @param array<string,string> $attachments file name => PDF, beside the one $attachment */
    private function send(
        string $to,
        string $subject,
        string $html,
        string $text,
        ?string $replyToEmail = null,
        string $replyToName = '',
        ?string $attachment = null,
        string $attachmentName = '',
        array $attachments = []
    ): void
    {
        if (filter_var($to, FILTER_VALIDATE_EMAIL) === false) {
            throw new RuntimeException('Cannot send email to an invalid address.');
        }

        // Every email from a demo site says so (SiteMode, owner 2026-10-18), in its subject and first line.
        if ($this->site?->isDemo() ?? false) {
            $subject = SiteMode::EMAIL_PREFIX . $subject;
            $html = '<p><strong>' . $this->escape(SiteMode::EMAIL_NOTICE) . '</strong></p>' . $html;
            $text = SiteMode::EMAIL_NOTICE . "\n\n" . $text;
        }
        $configuration = $this->settings->mailConfiguration();
        $mailer = new Mailer(Transport::fromDsn($configuration['dsn']));
        $from = new Address($configuration['from_address'], $configuration['from_name']);

        $message = (new Email())
            ->from($from)
            ->to($to)
            ->subject($subject)
            ->html($html)
            ->text($text);

        if ($replyToEmail !== null && filter_var($replyToEmail, FILTER_VALIDATE_EMAIL) !== false) {
            $message->replyTo(new Address($replyToEmail, $replyToName));
        } elseif ($configuration['reply_to'] !== '') {
            $message->replyTo($configuration['reply_to']);
        }
        if ($attachment !== null) $message->attach($attachment, $attachmentName, 'application/pdf');
        foreach ($attachments as $name => $bytes) $message->attach($bytes, (string) $name, 'application/pdf');
        $mailer->send($message);
    }

    private function escape(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
