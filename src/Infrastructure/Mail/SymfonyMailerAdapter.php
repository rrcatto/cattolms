    public function sendMagicLink(string $email, string $url, int $ttlSeconds): void
    {
        $minutes = max(1, (int) ceil($ttlSeconds / 60));
        $appName = $this->settings->platformName();
        $this->send(
            $email,
            'Your secure sign-in link',
