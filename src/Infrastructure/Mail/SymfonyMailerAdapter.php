    {
        $dashboardUrl = rtrim(Env::string('APP_URL'), '/') . '/company/requests';
        $this->send(
            $email,
            'Staff course request: ' . $courseTitle,
            '<p>' . $this->escape($staffLabel) . ' requested the course <strong>'
