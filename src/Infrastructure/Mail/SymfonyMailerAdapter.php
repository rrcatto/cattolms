            "The mail transport for {$appName} is working."
        );
    }

    private function send(string $to, string $subject, string $html, string $text): void
    {
        if (filter_var($to, FILTER_VALIDATE_EMAIL) === false) {
            throw new RuntimeException('Cannot send email to an invalid address.');
        }

        $configuration = $this->settings->mailConfiguration();
        $mailer = new Mailer(Transport::fromDsn($configuration['dsn']));
        $from = new Address($configuration['from_address'], $configuration['from_name']);

        $message = (new Email())
            ->from($from)
            ->to($to)
            ->subject($subject)
            ->html($html)
            ->text($text);

        if ($configuration['reply_to'] !== '') {
            $message->replyTo($configuration['reply_to']);
        }
        $mailer->send($message);
    }

    private function escape(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
}
