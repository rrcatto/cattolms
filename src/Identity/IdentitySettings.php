declare(strict_types=1);

namespace CattoLearning\Identity;

use CattoLearning\Support\Env;

final class IdentitySettings
{
    /** The .env keys verification needs. */
    public const KEYS = ['DIDIT_API_KEY', 'DIDIT_WORKFLOW_ID', 'DIDIT_WEBHOOK_SECRET'];

    /** Where the learner goes when the hosted page is done; Didit adds the session id and status. */
    public const RETURN_PATH = '/account/verification/return';

    /** Where Didit sends its webhooks: entered in the Didit console. */
    public const WEBHOOK_PATH = '/webhooks/didit';

    /** Whether the keys verification needs are all in .env. */
    public function available(): bool
    {
        return $this->missingKeys() === [];
    }

    /** @return list<string> the .env keys still missing */
    public function missingKeys(): array
    {
        // .env.example's placeholders start with replace-with-: a copied example is not a configured site.
        return array_values(array_filter(self::KEYS, static fn(string $key): bool => trim(Env::string($key)) === '' || str_starts_with(trim(Env::string($key)), 'replace-with-')));
    }

    public function apiKey(): string
    {
        return trim(Env::string('DIDIT_API_KEY'));
    }

    public function workflowId(): string
    {
        return trim(Env::string('DIDIT_WORKFLOW_ID'));
    }

    public function webhookSecret(): string
    {
        return trim(Env::string('DIDIT_WEBHOOK_SECRET'));
    }

    /** The site's own address, without a trailing slash. */
    public static function siteUrl(): string
    {
        return rtrim(trim(Env::string('APP_URL')), '/');
    }

    /** The address to enter in the Didit console as the webhook destination. */
    public static function webhookUrl(): string
    {
        return self::siteUrl() . self::WEBHOOK_PATH;
    }

    public static function returnUrl(): string
    {
        return self::siteUrl() . self::RETURN_PATH;
    }
}
