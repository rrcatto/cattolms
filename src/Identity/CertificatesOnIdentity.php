declare(strict_types=1);

namespace CattoLearning\Identity;

use CattoLearning\Course\Certificate\CertificateAwards;
use CattoPHP\Identity\IdentityApproved;

final class CertificatesOnIdentity implements IdentityApproved
{
    public function __construct(private readonly CertificateAwards $certificates)
    {
    }

    public function approved(string $account): void
    {
        if (ctype_digit($account)) {
            $this->certificates->issueWaiting((int) $account);
        }
    }
}
