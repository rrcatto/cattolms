declare(strict_types=1);

namespace CattoLearning\Identity;

use CattoLearning\Auth\CurrentUser;
use CattoLearning\Course\Certificate\CertificateAwards;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use DateTimeImmutable;
use InvalidArgumentException;
use JsonException;
use RuntimeException;
use Symfony\Component\Clock\ClockInterface;
use Throwable;

final class IdentityVerificationService
{
    /** Declined checks a learner may make before ADMIN must allow another try. */
    public const TRIES = 3;

    /** Didit's console, where ADMIN opens a check by its session id. */
    public const CONSOLE = 'https://business.didit.me';

    public function __construct(
        private readonly IdentityVerificationRepository $records,
        private readonly DiditClient $didit,
        private readonly IdentitySettings $settings,
        private readonly CertificateAwards $certificates,
        private readonly AuditRepository $audit,
        private readonly TransactionManager $transactions,
        private readonly ClockInterface $clock,
    ) {}

    public function isVerified(int $userId): bool
    {
        return $this->records->approved($userId) !== null;
    }

    /**
     * Where a person stands, for their verification page, a course page and ADMIN.
     *
     * @return array<string,mixed>
     */
    public function state(int $userId): array
    {
        $approved = $this->records->approved($userId);
        $latest = $this->records->latest($userId);
        $declined = $this->records->declinedTries($userId);
        $status = $approved !== null ? 'verified' : (string) ($latest['status'] ?? 'none');
        $minor = $approved !== null && \CattoLearning\Auth\AdultAge::under18($approved['date_of_birth'] ?? null, $this->now());
        return [
            'status' => $status,
            'verified' => $approved !== null,
            'verification' => $approved,
            'latest' => $latest,
            'tries_used' => $declined,
            'tries_left' => max(0, self::TRIES - $declined),
            'blocked' => $approved === null && $declined >= self::TRIES,
            'in_review' => $approved === null && ($latest['status'] ?? '') === IdentityDecision::IN_REVIEW,
            'available' => $this->settings->available(),
            'minor' => $minor,
            'status_words' => self::words($status),
        ];
    }

    /**
     * Starts a check on Didit's page and returns its address. Refused when the account is verified,
     * a check is being reviewed, three checks were declined or verification is not available.
     */
    public function start(CurrentUser $user): string
    {
        $state = $this->state($user->id);
        if ($state['verified']) throw new RuntimeException('Your identity is already verified.');
        if (!$state['available']) throw new RuntimeException('Identity verification is not available at the moment. Please try again later.');
        if ($state['in_review']) throw new RuntimeException('Your identity check is being reviewed. We will let you know the result.');
        if ($state['blocked']) throw new RuntimeException('Your identity check was declined ' . self::TRIES . ' times. Please contact us so we can allow another try.');
        $session = $this->didit->createSession($this->records->accountReference($user->id), IdentitySettings::returnUrl());
        $this->transactions->run(function () use ($user, $session): void {
            $row = $this->records->create($user->id, $session['session_id']);
            $this->audit->record($user->id, 'identity.verification_started', ['user_id' => $user->id, 'verification_id' => (int) $row['id'], 'session_id' => $session['session_id']]);
        });
        return $session['url'];
    }

    /**
     * The learner came back from Didit's page: the decision is read from Didit, so the check finishes
     * even where the webhook cannot reach the site.
     *
     * @return array<string,mixed> the learner's state afterwards
     */
    public function returned(CurrentUser $user, string $sessionId): array
    {
        $row = $this->records->bySession($sessionId);
        if ($row === null || (int) $row['user_id'] !== $user->id) throw new InvalidArgumentException('That identity check could not be found.');
        try {
            $report = $this->didit->decision($sessionId);
            $this->apply($sessionId, (string) ($report['status'] ?? ''), $report);
        } catch (RuntimeException $unreachable) {
            // The webhook still brings the result; the learner sees the check as it stands.
        }
        return $this->state($user->id);
    }

    /**
     * Didit's webhook. Refused unless signed with the webhook secret within the last 5 minutes. Each
     * event is handled once; anything but a verification session's status change is ignored.
     *
     * @param array<string,string> $headers lower-case header name => value
     */
    public function webhook(string $rawBody, array $headers): void
    {
        if (!DiditSignature::verify($rawBody, $headers['x-signature-v2'] ?? '', $headers['x-signature'] ?? '', $headers['x-timestamp'] ?? '', $this->settings->webhookSecret(), $this->now()->getTimestamp())) {
            throw new InvalidDiditWebhook('The webhook signature is not valid.');
        }
        try {
            $event = json_decode($rawBody, true, 512, JSON_THROW_ON_ERROR);
        } catch (JsonException) {
            throw new InvalidDiditWebhook('The webhook is not JSON.');
        }
        if (!is_array($event) || ($event['webhook_type'] ?? '') !== 'status.updated' || ($event['session_kind'] ?? '') === 'business') return;
        $sessionId = (string) ($event['session_id'] ?? '');
        if ($sessionId === '' || $this->records->bySession($sessionId) === null) return;
        $eventId = (string) ($event['event_id'] ?? '');
        if (preg_match('/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i', $eventId) === 1 && !$this->records->rememberEvent($eventId)) return;
        $this->apply($sessionId, (string) ($event['status'] ?? ''), is_array($event['decision'] ?? null) ? $event['decision'] : []);
    }

    /**
     * Records Didit's status for a check. A decided check is changed only by a later decision (a
     * reviewer's), a revoked one never. An approval issues every certificate the learner earned.
     *
     * @param array<string,mixed> $report the decision report
     */
    public function apply(string $sessionId, string $diditStatus, array $report): void
    {
        $decision = IdentityDecision::from($diditStatus, $report);
        $approvedNow = $this->transactions->run(function () use ($sessionId, $decision): ?int {
            $row = $this->records->bySession($sessionId, true);
            if ($row === null || $row['status'] === IdentityDecision::REVOKED || $row['status'] === $decision->status) return null;
            if ($decision->status === IdentityDecision::STARTED && $row['status'] !== IdentityDecision::STARTED) return null;
            $userId = (int) $row['user_id'];
            if ($decision->status === IdentityDecision::APPROVED) {
                $other = $this->records->approved($userId);
                // One verification at a time; a check approved without a name waits for a reviewer.
                if (($other !== null && (int) $other['id'] !== (int) $row['id']) || $decision->name === null) return null;
            }
            $this->records->decide((int) $row['id'], $decision);
            $this->audit->record(null, 'identity.verification_' . $decision->status, ['user_id' => $userId, 'verification_id' => (int) $row['id'], 'session_id' => $sessionId]
                + ($decision->status === IdentityDecision::APPROVED ? ['document_type' => $decision->documentType, 'issuing_country' => $decision->issuingCountry] : [])
                + ($decision->status === IdentityDecision::DECLINED ? ['reason' => $decision->declineReason] : []));
            return $decision->status === IdentityDecision::APPROVED ? $userId : null;
        });
        // Adults only (owner, 2026-10-20): a document showing the learner under 18 issues nothing.
        if ($approvedNow !== null && !$this->state($approvedNow)['minor']) {
            try {
                $this->certificates->issueWaiting($approvedNow);
            } catch (Throwable) {
                // Each certificate that cannot be drawn is recorded by CertificateAwards; the check stays approved.
            }
        }
    }

    /** ADMIN revokes an approved verification with a written reason. The account must verify again. */
    public function revoke(int $verificationId, int $actorId, string $reason): void
    {
        $reason = trim($reason);
        if ($reason === '' || mb_strlen($reason) > 500) throw new InvalidArgumentException('Write why the verification is revoked, in at most 500 characters.');
        $this->transactions->run(function () use ($verificationId, $actorId, $reason): void {
            $row = $this->records->find($verificationId, true) ?? throw new InvalidArgumentException('That identity check does not exist.');
            if ($row['status'] !== IdentityDecision::APPROVED) throw new InvalidArgumentException('Only an approved verification can be revoked.');
            $this->records->revoke($verificationId, $actorId, $reason);
            $this->audit->record($actorId, 'identity.verification_revoked', ['user_id' => (int) $row['user_id'], 'verification_id' => $verificationId, 'reason' => $reason]);
        });
    }

    /** ADMIN allows another try after three declined checks. */
    public function allowAnotherTry(int $userId, int $actorId): void
    {
        $this->transactions->run(function () use ($userId, $actorId): void {
            $this->records->allowAnotherTry($userId);
            $this->audit->record($actorId, 'identity.retry_allowed', ['user_id' => $userId]);
        });
    }

    /** @return list<array<string,mixed>> the checks Didit is reviewing, for the dashboard */
    public function inReview(): array
    {
        return $this->records->inReview();
    }

    /** @return list<array<string,mixed>> a person's checks, newest first, for ADMIN */
    public function history(int $userId): array
    {
        return array_map(static fn(array $row): array => $row + ['status_words' => self::words((string) $row['status'])], $this->records->history($userId));
    }

    /** A status in words. */
    public static function words(string $status): string
    {
        return match ($status) {
            'verified', IdentityDecision::APPROVED => 'Verified',
            IdentityDecision::STARTED => 'Started, not finished',
            IdentityDecision::IN_REVIEW => 'Being reviewed',
            IdentityDecision::DECLINED => 'Declined',
            IdentityDecision::ABANDONED => 'Left unfinished',
            IdentityDecision::EXPIRED => 'Expired',
            IdentityDecision::REVOKED => 'Revoked',
            default => 'Not verified',
        };
    }

    private function now(): DateTimeImmutable
    {
        return DateTimeImmutable::createFromInterface($this->clock->now());
    }
}
