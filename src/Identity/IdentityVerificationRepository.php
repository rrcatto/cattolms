declare(strict_types=1);

namespace CattoLearning\Identity;

use CattoLearning\Infrastructure\Persistence\Database;
use CattoPHP\Identity\IdentityAccounts;

final class IdentityVerificationRepository implements IdentityAccounts
{
    /** A person by their account, the user id in text. */
    private const PERSON = "CASE WHEN %s ~ '^[0-9]+$' THEN CAST(%s AS BIGINT) END";

    public function __construct(private readonly Database $db)
    {
    }

    /** The account reference Didit is given as vendor_data, so a check is easy to find in its console. */
    public function reference(string $account): string
    {
        return ctype_digit($account) ? $this->accountReference((int) $account) : $account;
    }

    public function accountReference(int $userId): string
    {
        return (string) $this->db->fetchOne('SELECT account_reference FROM users WHERE id = :user', ['user' => $userId]);
    }

    /** @return list<array<string,mixed>> every check the person made, newest first, with who revoked any */
    public function history(int $userId): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT iv.*, " . sprintf(self::PERSON, 'iv.account', 'iv.account') . " AS user_id, rb.id AS revoked_by_user_id,
                    COALESCE(NULLIF(trim(concat_ws(' ', rb.first_name, rb.last_name)), ''), rb.display_name) AS revoked_by_name, rb.account_reference AS revoked_by_reference
               FROM cattophp_identity_verifications iv
               LEFT JOIN users rb ON rb.id = " . sprintf(self::PERSON, 'iv.revoked_by', 'iv.revoked_by') . "
              WHERE iv.account = :user ORDER BY iv.started_at DESC, iv.id DESC LIMIT 50",
            ['user' => (string) $userId]
        );
    }

    /** @return list<array<string,mixed>> every check Didit is reviewing, oldest first, with whose they are */
    public function inReview(): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT iv.id, u.id AS user_id, iv.session_id, iv.started_at, iv.decided_at,
                    COALESCE(NULLIF(btrim(COALESCE(u.first_name,'') || ' ' || COALESCE(u.last_name,'')), ''), u.display_name, ue.email) AS person_name, ue.email, u.account_reference AS person_reference
               FROM cattophp_identity_verifications iv
               JOIN users u ON u.id = " . sprintf(self::PERSON, 'iv.account', 'iv.account') . "
               LEFT JOIN user_emails ue ON ue.user_id = u.id AND ue.is_primary = TRUE
              WHERE iv.status = 'in_review'
              ORDER BY iv.started_at, iv.id"
        );
    }
}
