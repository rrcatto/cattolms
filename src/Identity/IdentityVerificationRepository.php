declare(strict_types=1);

namespace CattoLearning\Identity;

use CattoLearning\Infrastructure\Persistence\Database;

final class IdentityVerificationRepository
{
    public function __construct(private readonly Database $db) {}

    /** @return array<string,mixed> the new check */
    public function create(int $userId, string $sessionId): array
    {
        $row = $this->db->fetchAssociative(
            "INSERT INTO identity_verifications (user_id, session_id, status) VALUES (:user, :session, 'started')
             ON CONFLICT (session_id) DO UPDATE SET updated_at = NOW() RETURNING *",
            ['user' => $userId, 'session' => $sessionId]
        );
        return (array) $row;
    }

    /** @return array<string,mixed>|null */
    public function bySession(string $sessionId, bool $lock = false): ?array
    {
        $row = $this->db->fetchAssociative('SELECT * FROM identity_verifications WHERE session_id = :session' . ($lock ? ' FOR UPDATE' : ''), ['session' => $sessionId]);
        return $row === false ? null : $row;
    }

    /** @return array<string,mixed>|null */
    public function find(int $id, bool $lock = false): ?array
    {
        $row = $this->db->fetchAssociative('SELECT * FROM identity_verifications WHERE id = :id' . ($lock ? ' FOR UPDATE' : ''), ['id' => $id]);
        return $row === false ? null : $row;
    }

    /** @return array<string,mixed>|null the person's approved check, which is what makes them verified */
    public function approved(int $userId): ?array
    {
        $row = $this->db->fetchAssociative("SELECT * FROM identity_verifications WHERE user_id = :user AND status = 'approved' LIMIT 1", ['user' => $userId]);
        return $row === false ? null : $row;
    }

    /** @return array<string,mixed>|null the person's most recent check */
    public function latest(int $userId): ?array
    {
        $row = $this->db->fetchAssociative('SELECT * FROM identity_verifications WHERE user_id = :user ORDER BY started_at DESC, id DESC LIMIT 1', ['user' => $userId]);
        return $row === false ? null : $row;
    }

    /** @return list<array<string,mixed>> every check the person made, newest first */
    public function history(int $userId): array
    {
        return $this->db->fetchAllAssociative(
            'SELECT iv.*, COALESCE(NULLIF(trim(concat_ws(\' \', rb.first_name, rb.last_name)), \'\'), rb.display_name) AS revoked_by_name, rb.account_reference AS revoked_by_reference FROM identity_verifications iv
               LEFT JOIN users rb ON rb.id = iv.revoked_by_user_id
              WHERE iv.user_id = :user ORDER BY iv.started_at DESC, iv.id DESC LIMIT 50',
            ['user' => $userId]
        );
    }

    /** Declined checks that count towards the three tries: those since ADMIN last allowed another try. */
    public function declinedTries(int $userId): int
    {
        return (int) $this->db->fetchOne(
            "SELECT COUNT(*) FROM identity_verifications iv JOIN users u ON u.id = iv.user_id
              WHERE iv.user_id = :user AND iv.status = 'declined'
                AND iv.started_at > COALESCE(u.identity_attempts_reset_at, '-infinity'::timestamptz)",
            ['user' => $userId]
        );
    }

    /**
     * Records a decision on a check. An approved check keeps the identity it verified; any other keeps
     * none. A revoked check is never changed.
     */
    public function decide(int $id, IdentityDecision $decision): void
    {
        $approved = $decision->status === IdentityDecision::APPROVED;
        $this->db->executeStatement(
            "UPDATE identity_verifications SET status = :status, verified_name = :name, document_type = :type, document_number = :number,
                    issuing_country = :country, date_of_birth = CAST(:birth AS DATE), decline_reason = :reason,
                    decided_at = CASE WHEN :final THEN COALESCE(decided_at, NOW()) ELSE decided_at END, updated_at = NOW()
              WHERE id = :id AND status <> 'revoked'",
            ['id' => $id, 'status' => $decision->status, 'name' => $approved ? $decision->name : null, 'type' => $approved ? $decision->documentType : null,
                'number' => $approved ? $decision->documentNumber : null, 'country' => $approved ? $decision->issuingCountry : null,
                'birth' => $approved ? $decision->dateOfBirth : null, 'reason' => $decision->declineReason,
                'final' => in_array($decision->status, [...IdentityDecision::FINAL, IdentityDecision::IN_REVIEW], true)]
        );
    }

    public function revoke(int $id, int $actorId, string $reason): void
    {
        $this->db->executeStatement(
            "UPDATE identity_verifications SET status = 'revoked', revoked_at = NOW(), revoked_by_user_id = :actor, revocation_reason = :reason, updated_at = NOW()
              WHERE id = :id AND status = 'approved'",
            ['id' => $id, 'actor' => $actorId, 'reason' => $reason]
        );
    }

    /** ADMIN allows another try: the declined checks so far stop counting. */
    public function allowAnotherTry(int $userId): void
    {
        $this->db->executeStatement('UPDATE users SET identity_attempts_reset_at = NOW(), updated_at = NOW() WHERE id = :user', ['user' => $userId]);
    }

    /** Records a webhook event; false when it was already handled. */
    public function rememberEvent(string $eventId): bool
    {
        return $this->db->executeStatement(
            'INSERT INTO identity_webhook_events (event_id) VALUES (CAST(:event AS UUID)) ON CONFLICT (event_id) DO NOTHING',
            ['event' => $eventId]
        ) === 1;
    }

    /** @return list<array<string,mixed>> the checks Didit is reviewing, oldest first, with whose they are */
    public function inReview(int $limit = 50): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT iv.id, iv.user_id, iv.session_id, iv.started_at, iv.decided_at,
                    COALESCE(NULLIF(btrim(COALESCE(u.first_name,'') || ' ' || COALESCE(u.last_name,'')), ''), u.display_name, ue.email) AS person_name, ue.email, u.account_reference AS person_reference
               FROM identity_verifications iv
               JOIN users u ON u.id = iv.user_id
               LEFT JOIN user_emails ue ON ue.user_id = u.id AND ue.is_primary = TRUE
              WHERE iv.status = 'in_review'
              ORDER BY iv.started_at, iv.id LIMIT :limit",
            ['limit' => $limit]
        );
    }

    /** The account reference Didit is given as vendor_data, so a check is easy to find in its console. */
    public function accountReference(int $userId): string
    {
        return (string) $this->db->fetchOne('SELECT account_reference FROM users WHERE id = :user', ['user' => $userId]);
    }

}
