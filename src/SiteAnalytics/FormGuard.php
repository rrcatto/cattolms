/*
Generated by: Claude Code CLI

Date time: 2026/11/04 SAST

Description:
The checks on the public forms (owner, 2026-11-04): whether a form sent to Sign in or Contact is a bot's, from the hidden
field people never see, a missing or years-old browser or a script, or comes from an email address on the refused list.
The controller then shows the usual answer, sends and creates nothing, and the Site Log shows it under Forms refused, so
the bot learns nothing (owner: "I don't want to give them any information"). Register keeps its own sign-up check and
only asks about the refused list and the signals. An address on Never lock out, or a private one, is the owner's own: its
forms are never refused, so the owner's own tools and a local test site keep working.

Changelog:
2026/11/04 SAST
- Created.
*/

declare(strict_types=1);

namespace CattoLearning\SiteAnalytics;

use CattoLearning\Support\ClientFingerprint;
use CattoLearning\Support\Env;
use Symfony\Component\HttpFoundation\RequestStack;

class FormGuard
{
    public const ATTRIBUTE = '_site_log_form';
    public const TRAP_FIELD = 'website';

    public const SIGN_IN = 'sign_in';
    public const REGISTER = 'register';
    public const CONTACT = 'contact';

    /** Each form's name and each signal's reason, as Forms refused says them. */
    public const FORMS = [self::SIGN_IN => 'Sign in', self::REGISTER => 'Register', self::CONTACT => 'Contact'];
    public const SIGNALS = [
        'trap' => 'The hidden field was filled in',
        'no_browser' => 'No browser named',
        'outdated' => 'A browser years out of date',
        'script' => 'A script, not a browser',
        'email_list' => 'An email address or domain you refuse',
    ];

    public function __construct(
        private readonly RequestStack $requests,
        private readonly RefusedEmailRepository $refusedEmails,
        private readonly SiteProtectionSettings $settings,
    ) {
    }

    /**
     * Whether this form is refused. What was found stays on the request for the Site Log.
     *
     * @param array<string,mixed> $form what the form sent
     */
    public function refuses(string $name, array $form, string $email): bool
    {
        $email = strtolower(trim($email));
        $signal = $this->signal($form);
        $listed = $email !== '' && $this->refusedEmails->refuses($email);
        if ($listed) $signal = 'email_list';
        $address = ClientFingerprint::ipAddress();
        // No address is no web visitor; a private one is a local test site, or a proxy not passing the address on.
        $own = $address === '' || RequestFacts::isPrivate($address) || $this->settings->isNeverLockedOut($address);
        // Register has its own check (Auth\Signup\SignupRisk): only the refused list refuses it here.
        $refused = !$own && $signal !== null && ($name !== self::REGISTER || $listed);
        $this->note($name, $own ? null : $signal, $refused, $email);

        return $refused;
    }

    /** @param array<string,mixed> $form */
    private function signal(array $form): ?string
    {
        if (trim((string) ($form[self::TRAP_FIELD] ?? '')) !== '') return 'trap';

        return match (VisitorAgent::read((string) ($this->requests->getCurrentRequest()?->headers->get('User-Agent', '') ?? ''))->kind) {
            VisitorAgent::NONE => 'no_browser',
            VisitorAgent::OUTDATED => 'outdated',
            VisitorAgent::SCRIPT, VisitorAgent::CRAWLER, VisitorAgent::SEARCH => 'script',
            default => null,
        };
    }

    private function note(string $name, ?string $signal, bool $refused, string $email): void
    {
        $this->requests->getCurrentRequest()?->attributes->set(self::ATTRIBUTE, [
            'form' => $name, 'signal' => $signal, 'refused' => $refused, 'email' => $email !== '' ? mb_substr($email, 0, 254) : null,
            // To count how many different addresses one visitor tries, without keeping the addresses of real people.
            'email_hash' => $email !== '' ? hash_hmac('sha256', $email, Env::string('APP_KEY')) : null,
        ]);
    }
}
