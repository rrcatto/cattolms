namespace CattoLearning\SiteAnalytics;

use CattoLearning\Auth\AuthService;
use CattoPHP\Protection\VisitorAccounts;

final class ProtectionVisitors implements VisitorAccounts
{
    public const ADMINISTRATOR = 'PLATFORM.SITEANALYTICS.VIEW';

    public function __construct(private readonly AuthService $auth)
    {
    }

    public function current(): ?array
    {
        $user = $this->auth->currentUser();

        return $user === null ? null : ['id' => (string) $user->id, 'administrator' => $user->hasPermission(self::ADMINISTRATOR)];
    }
}
