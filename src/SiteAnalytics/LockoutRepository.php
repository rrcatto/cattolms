declare(strict_types=1);

namespace CattoLearning\SiteAnalytics;

use CattoLearning\Infrastructure\Persistence\Database;
use DateTimeImmutable;

class LockoutRepository
{
    /** A lockout that keeps someone out now. */
    public const IN_FORCE = '(l.lifted_at IS NULL AND (l.until_at IS NULL OR l.until_at > NOW()))';

    /** The kinds of lockout: the feature cards, and what each holds. */
    public const KINDS = [
        'force' => ['label' => 'In force now', 'where' => self::IN_FORCE],
        'auto' => ['label' => 'In force, automatic', 'where' => self::IN_FORCE . ' AND l.automatic'],
        'you' => ['label' => 'In force, by you', 'where' => self::IN_FORCE . ' AND NOT l.automatic'],
        'ended' => ['label' => 'Ended or lifted', 'where' => 'NOT ' . self::IN_FORCE],
    ];

    private const COLUMNS = "l.*, abbrev(CAST(l.network AS inet)) AS network_text, " . self::IN_FORCE . " AS in_force, cu.display_name AS created_by_name, lu.display_name AS lifted_by_name";
    private const FROM = 'site_lockouts l LEFT JOIN users cu ON cu.id = l.created_by_user_id LEFT JOIN users lu ON lu.id = l.lifted_by_user_id';

    public function __construct(private readonly Database $db)
    {
    }

    /**
     * @param array{kind:string,network:?string,asn:?int,label:string,which:string,why:string,rule_key:?string,automatic:bool,created_by_user_id:?int,until:?DateTimeImmutable,firewall:string} $lockout
     */
    public function add(array $lockout): int
    {
        return (int) $this->db->fetchOne(
            'INSERT INTO site_lockouts (kind, network, asn, label, which, why, rule_key, automatic, created_by_user_id, until_at, firewall)
             VALUES (:kind, CAST(:network AS cidr), :asn, :label, :which, :why, :rule_key, :automatic, :created_by_user_id, :until, :firewall) RETURNING id',
            ['kind' => $lockout['kind'], 'network' => $lockout['network'], 'asn' => $lockout['asn'], 'label' => $lockout['label'], 'which' => $lockout['which'], 'why' => mb_substr($lockout['why'], 0, 500), 'rule_key' => $lockout['rule_key'], 'automatic' => $lockout['automatic'],
                'created_by_user_id' => $lockout['created_by_user_id'], 'until' => $lockout['until']?->format(DATE_ATOM), 'firewall' => $lockout['firewall']]
        );
    }

    /** @return array<string,mixed>|null */
    public function find(int $id): ?array
    {
        $row = $this->db->fetchAssociative('SELECT ' . self::COLUMNS . ' FROM ' . self::FROM . ' WHERE l.id = :id', ['id' => $id]);

        return is_array($row) ? $row : null;
    }

    public function lift(int $id, ?int $actorUserId, ?string $firewall = null): bool
    {
        return $this->db->executeStatement(
            'UPDATE site_lockouts l SET lifted_at = NOW(), lifted_by_user_id = :actor, firewall = COALESCE(:firewall, firewall) WHERE l.id = :id AND ' . self::IN_FORCE,
            ['id' => $id, 'actor' => $actorUserId, 'firewall' => $firewall]
        ) > 0;
    }

    /** @return array<string,int> how many each kind holds */
    public function counts(): array
    {
        $columns = [];
        foreach (self::KINDS as $key => $kind) {
            $columns[] = 'COUNT(*) FILTER (WHERE ' . $kind['where'] . ') AS ' . $key;
        }
        $row = $this->db->fetchAssociative('SELECT ' . implode(', ', $columns) . ' FROM site_lockouts l');

        return array_map('intval', is_array($row) ? $row : array_fill_keys(array_keys(self::KINDS), 0));
    }

    /** @return list<array<string,mixed>> */
    public function page(string $kind, int $limit, int $offset): array
    {
        $where = self::KINDS[$kind]['where'] ?? self::IN_FORCE;

        return $this->db->fetchAllAssociative('SELECT ' . self::COLUMNS . ' FROM ' . self::FROM . ' WHERE ' . $where . ' ORDER BY l.started_at DESC, l.id DESC LIMIT :limit OFFSET :offset', ['limit' => $limit, 'offset' => $offset]);
    }

    /** @return list<array<string,mixed>> every lockout that covered an address, newest first */
    public function forSubject(string $subject): array
    {
        return $this->db->fetchAllAssociative('SELECT ' . self::COLUMNS . ' FROM ' . self::FROM . ' WHERE l.network >>= CAST(:subject AS inet) ORDER BY l.started_at DESC', ['subject' => $subject]);
    }

    /**
     * The lockout keeping an address out now, the longest kind first, or a network owner's.
     *
     * @return array<string,mixed>|null
     */
    public function inForceFor(string $subject, ?int $asn): ?array
    {
        $row = $this->db->fetchAssociative(
            'SELECT ' . self::COLUMNS . ' FROM ' . self::FROM . ' WHERE ' . self::IN_FORCE . ' AND (l.network >>= CAST(:subject AS inet) OR l.asn = :asn)
             ORDER BY CASE l.which WHEN \'lockout\' THEN 0 ELSE 1 END, l.until_at DESC NULLS FIRST LIMIT 1',
            ['subject' => $subject, 'asn' => $asn]
        );

        return is_array($row) ? $row : null;
    }

    /** Ends what is in force on exactly this target, so a new lockout replaces it. */
    public function liftSameTarget(?string $network, ?int $asn, ?int $actorUserId): int
    {
        return $this->db->executeStatement(
            'UPDATE site_lockouts l SET lifted_at = NOW(), lifted_by_user_id = :actor WHERE ' . self::IN_FORCE . ' AND (l.network = CAST(:network AS cidr) OR l.asn = :asn)',
            ['actor' => $actorUserId, 'network' => $network, 'asn' => $asn]
        );
    }

    /** Ends what the site itself put on an address. */
    public function liftAutomatic(string $subject, int $actorUserId): int
    {
        return $this->db->executeStatement(
            'UPDATE site_lockouts l SET lifted_at = NOW(), lifted_by_user_id = :actor WHERE ' . self::IN_FORCE . ' AND l.automatic AND l.network = CAST(:subject AS cidr)',
            ['actor' => $actorUserId, 'subject' => $subject]
        );
    }

    /** @return list<array{started_at:string,until_at:?string,which:string}> an address's automatic time-outs since a moment */
    public function automaticTimeoutsSince(string $subject, DateTimeImmutable $since): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT started_at, until_at, which FROM site_lockouts WHERE automatic AND which = 'timeout' AND network = CAST(:subject AS cidr) AND started_at >= :since ORDER BY started_at DESC",
            ['subject' => $subject, 'since' => $since->format(DATE_ATOM)]
        );
    }

    /** @return list<array<string,mixed>> lockouts at the firewall whose time has run out and which it still holds */
    public function firewallDue(): array
    {
        return $this->db->fetchAllAssociative("SELECT l.id, abbrev(CAST(l.network AS inet)) AS network_text FROM site_lockouts l WHERE l.firewall = 'banned' AND NOT " . self::IN_FORCE);
    }

    public function firewallReleased(int $id): void
    {
        $this->db->executeStatement("UPDATE site_lockouts SET firewall = 'released' WHERE id = :id", ['id' => $id]);
    }

    public function deleteEndedBefore(DateTimeImmutable $before): int
    {
        return $this->db->executeStatement(
            'DELETE FROM site_lockouts l WHERE NOT ' . self::IN_FORCE . " AND l.firewall <> 'banned' AND COALESCE(l.lifted_at, l.until_at) < :before",
            ['before' => $before->format(DATE_ATOM)]
        );
    }
}
