    /** Whether an address or range lies on the Never lock out list. */
    public function isNeverLockedOut(string $address): bool
    {
        foreach ((array) $this->values()['never_lock_out'] as $entry) {
            if (self::contains((string) $entry, $address)) return true;
        }

        return false;
    }

    /** Whether a range holds an address, or an address is that address. */
    public static function contains(string $range, string $address): bool
    {
        [$network, $bits] = array_pad(explode('/', trim($range), 2), 2, null);
        $packedNetwork = @inet_pton((string) $network);
        $packedAddress = @inet_pton((string) strtok($address, '/'));
        if ($packedNetwork === false || $packedAddress === false || strlen($packedNetwork) !== strlen($packedAddress)) return false;
        $bits = $bits === null ? strlen($packedNetwork) * 8 : (int) $bits;
        $whole = intdiv($bits, 8);
        if (substr($packedNetwork, 0, $whole) !== substr($packedAddress, 0, $whole)) return false;
        $rest = $bits % 8;
        if ($rest === 0) return true;
        $mask = (0xFF << (8 - $rest)) & 0xFF;

        return (ord($packedNetwork[$whole]) & $mask) === (ord($packedAddress[$whole]) & $mask);
    }

    /** @return array{on:bool,count:int,within:string,then:string,length:string} */
    private static function ruleFrom(string $line, string $start): array
    {
        $parts = array_map('trim', explode(',', $line !== '' ? $line : $start));
        $starting = array_map('trim', explode(',', $start));
        if (count($parts) !== 5 || !ctype_digit($parts[1]) || !Duration::isValid($parts[2]) || !Duration::isValid($parts[4])) $parts = $starting;

        return ['on' => $parts[0] !== 'off', 'count' => max(1, (int) $parts[1]), 'within' => $parts[2], 'then' => $parts[3] === 'timeout' ? 'timeout' : 'flag', 'length' => $parts[4]];
    }

    private static function lengthOr(string $text, string $default): string
    {
        $text = trim($text);

        return $text !== '' && Duration::isValid($text) ? $text : $default;
    }

    private static function length(string $text, string $name): string
    {
        $text = trim($text);
        if ($text === '' || !Duration::isValid($text)) throw new InvalidArgumentException($name . ': ' . Duration::HOW);

        return $text;
    }

    /** @return list<string> */
    private static function addressLines(string $text): array
    {
        return array_values(array_filter(array_map('trim', preg_split('/[\s,]+/', $text) ?: []), static fn(string $line): bool => $line !== '' && self::isAddressOrRange($line)));
    }

    /** @return list<string> */
    private static function checkedAddresses(string $text): array
    {
        $lines = array_values(array_filter(array_map('trim', preg_split('/[\s,]+/', $text) ?: []), static fn(string $line): bool => $line !== ''));
        foreach ($lines as $line) {
            if (!self::isAddressOrRange($line)) throw new InvalidArgumentException('Never lock out: ' . $line . ' is not an address or a range.');
        }

        return array_values(array_unique($lines));
    }

    public static function isAddressOrRange(string $text): bool
    {
        [$address, $bits] = array_pad(explode('/', $text, 2), 2, null);
        if (filter_var($address, FILTER_VALIDATE_IP) === false) return false;
        if ($bits === null) return true;
        $most = str_contains((string) $address, ':') ? 128 : 32;

        return ctype_digit($bits) && (int) $bits >= 1 && (int) $bits <= $most;
    }
