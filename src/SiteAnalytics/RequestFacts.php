declare(strict_types=1);

namespace CattoLearning\SiteAnalytics;

final class RequestFacts
{
    public const MASK = '••••';

    /** The address parts that hold a secret: the unsubscribe and other email links, join links, a leaving link, a private certificate. */
    private const SECRET_PATHS = '#^(/(?:m/[a-z]|join|leaving|certificates|transcripts)/)[^/.]+#';

    /** The page asked for: no query string, no secrets. */
    public static function maskedPath(string $requestUri): string
    {
        $path = parse_url($requestUri, PHP_URL_PATH);
        if (!is_string($path) || $path === '') $path = '/';
        $path = (string) preg_replace(self::SECRET_PATHS, '$1' . self::MASK, $path);
        // Anything else that looks like a key, wherever it comes up: 32 or more hexadecimal or URL-safe characters together,
        // holding a digit. Words joined by hyphens are not a key but a record's name (2026-11-07: a Course Item's slug, a
        // part name such as module-12-practical-work-and-model-answers), and are kept: lower case, a hyphen between words,
        // and a letter after f, which no hexadecimal id or UUID holds.
        $path = (string) preg_replace_callback('#(?<=/)(?=[A-Za-z0-9_-]*[0-9])[A-Za-z0-9_-]{32,}#', static fn(array $key): string => self::isName($key[0]) ? $key[0] : self::MASK, $path);

        return mb_substr($path, 0, 500);
    }

    /** Lowercase words joined by hyphens, holding a letter no hexadecimal key holds: a record's name, never a secret. */
    private static function isName(string $segment): bool
    {
        return preg_match('/^[a-z0-9]+(?:-[a-z0-9]+)+$/', $segment) === 1 && preg_match('/[g-z]/', $segment) === 1;
    }

    /** The address the rules count and a lockout holds: the address, or an IPv6 address's /64. */
    public static function subject(string $address): string
    {
        $packed = @inet_pton($address);
        if ($packed === false) return $address;
        if (strlen($packed) === 4) return (string) inet_ntop($packed);

        return inet_ntop(substr($packed, 0, 8) . str_repeat("\0", 8)) . '/64';
    }

    /** A private or loopback address: a local test site, or a proxy not passing the visitor's address on. Never timed out, or everyone would be. */
    public static function isPrivate(string $address): bool
    {
        $address = (string) strtok($address, '/');
        if (filter_var($address, FILTER_VALIDATE_IP) === false) return false;
        if ($address === '::1' || str_starts_with($address, '127.')) return true;

        return filter_var($address, FILTER_VALIDATE_IP, FILTER_FLAG_NO_PRIV_RANGE) === false;
    }

    /**
     * Where a visitor came from.
     *
     * @return array{0:string,1:string} the name of the site they came from, and which kind that is
     */
    public static function cameFrom(string $referrer, string $thisHost): array
    {
        $host = strtolower((string) parse_url($referrer, PHP_URL_HOST));
        if ($host === '') return ['', 'direct'];
        if ($host === strtolower($thisHost)) return ['', 'inside'];
        $host = (string) preg_replace('/^www\./', '', $host);
        $kind = match (true) {
            preg_match('/(^|\.)(google|bing|duckduckgo|yahoo|yandex|baidu|ecosia|brave)\./', $host) === 1 => 'search',
            preg_match('/(^|\.)(facebook|fb|instagram|twitter|t|x|linkedin|whatsapp|youtube|tiktok|reddit|pinterest)\.(com|co|me|net)$/', $host) === 1 => 'social',
            preg_match('/(^|\.)(mail|outlook|webmail)\./', $host) === 1 => 'email',
            default => 'site',
        };

        return [mb_substr($host, 0, 200), $kind];
    }
}
