Description:
Locking out by hand and lifting (owner, 2026-11-04). What can be locked out: one address (an IPv6 machine counts as its
whole /64), a range, or everything from a network owner. The address in use now, and anything on Never lock out, cannot
be locked out, so nobody locks themselves out by mistake. A lockout may also ban at the server's firewall, for an address
or range only: a firewall knows nothing of network owners.

Changelog:
