declare(strict_types=1);

namespace CattoLearning\SiteAnalytics;

use CattoLearning\Auth\Signup\NetworkLookup;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Support\ClientFingerprint;
use CattoLearning\Support\Duration;
use DateTimeImmutable;
use InvalidArgumentException;

class LockoutService
{
    /** The lengths a lockout by hand is offered: the value, and how the page says it. */
    public const LENGTHS = ['1h' => '1 hour', '1d' => '1 day', '1w' => '1 week', '30d' => '1 month', 'good' => 'For good'];

    public function __construct(
        private readonly LockoutRepository $lockouts,
        private readonly FlagRepository $flags,
        private readonly SiteProtectionSettings $settings,
        private readonly ServerLink $server,
        private readonly NetworkLookup $network,
        private readonly AuditRepository $audit,
    ) {
    }

    /**
     * Reads what the Add a lockout form was given: an address, a range such as 198.51.100.0/24, or a network owner's number such as AS64500.
     *
     * @return array{kind:string,network:?string,asn:?int,label:string}
     */
    public function target(string $text, string $ownerName = ''): array
    {
        $text = trim($text);
        if (preg_match('/^AS(\d{1,10})$/i', $text, $match) === 1) {
            return ['kind' => 'owner', 'network' => null, 'asn' => (int) $match[1], 'label' => $ownerName !== '' ? $ownerName : 'AS' . $match[1]];
        }
        if (filter_var($text, FILTER_VALIDATE_IP) !== false) {
            $subject = RequestFacts::subject($text);
            return ['kind' => 'address', 'network' => $subject, 'asn' => null, 'label' => $subject];
        }
        if (SiteProtectionSettings::isAddressOrRange($text) && str_contains($text, '/')) {
            [$address, $bits] = explode('/', $text, 2);
            $v6 = str_contains($address, ':');
            if ((int) $bits < ($v6 ? 24 : 8)) throw new InvalidArgumentException('That range is too wide. The widest allowed is /8, or /24 for IPv6.');
            $packed = (string) inet_pton($address);
            $whole = intdiv((int) $bits, 8);
            $rest = (int) $bits % 8;
            $network = substr($packed, 0, $whole);
            if ($rest > 0) $network .= chr(ord($packed[$whole]) & ((0xFF << (8 - $rest)) & 0xFF));
            $network = str_pad($network, strlen($packed), "\0");
            $range = inet_ntop($network) . '/' . $bits;
            if ($v6 ? (int) $bits === 128 : (int) $bits === 32) return ['kind' => 'address', 'network' => $range, 'asn' => null, 'label' => (string) inet_ntop($network)];

            return ['kind' => 'range', 'network' => $range, 'asn' => null, 'label' => $range];
        }

        throw new InvalidArgumentException('Give an address, a range such as 198.51.100.0/24, or a network owner\'s number such as AS64500.');
    }

    /**
     * Locks out, ending whatever was in force on exactly the same thing.
     *
     * @param array{kind:string,network:?string,asn:?int,label:string} $target
     */
    public function lockOut(array $target, string $length, string $why, bool $firewall, int $actorUserId): int
    {
        $why = trim($why);
        if ($why === '') throw new InvalidArgumentException('Say why it is being locked out.');
        if (!isset(self::LENGTHS[$length])) throw new InvalidArgumentException('Choose how long it is locked out for.');
        $this->assertAllowed($target);
        $until = $length === 'good' ? null : Duration::parse($length)->after(new DateTimeImmutable());
        $firewall = $firewall && $target['kind'] !== 'owner' && $this->settings->values()['firewall_link'] === true;
        $this->lockouts->liftSameTarget($target['network'], $target['asn'], $actorUserId);
        if ($firewall) $this->server->ban((string) $target['network']);
        $id = $this->lockouts->add($target + ['which' => 'lockout', 'why' => $why, 'rule_key' => null, 'automatic' => false, 'created_by_user_id' => $actorUserId, 'until' => $until, 'firewall' => $firewall ? 'banned' : 'no']);
        if ($target['kind'] === 'address') $this->flags->raise((string) $target['network'], 'high', 'by_hand', 'Locked out by hand: ' . $why, 60);
        $this->audit->record($actorUserId, 'site.locked_out', ['what' => $target['label'], 'kind' => $target['kind'], 'length' => $length, 'firewall' => $firewall]);

        return $id;
    }

    public function lift(int $id, int $actorUserId): void
    {
        $lockout = $this->lockouts->find($id);
        if ($lockout === null) throw new InvalidArgumentException('That lockout could not be found.');
        $atFirewall = $lockout['firewall'] === 'banned';
        if (!$this->lockouts->lift($id, $actorUserId, $atFirewall ? 'released' : null)) throw new InvalidArgumentException('That lockout has already ended.');
        if ($atFirewall) $this->server->release((string) $lockout['network_text']);
        $this->audit->record($actorUserId, 'site.lockout_lifted', ['what' => (string) $lockout['label']]);
    }

    /** @param array{kind:string,network:?string,asn:?int,label:string} $target */
    private function assertAllowed(array $target): void
    {
        $own = ClientFingerprint::ipAddress();
        if ($target['kind'] === 'owner') {
            if ($own !== '' && $this->network->facts($own)->asn === $target['asn']) throw new InvalidArgumentException('You are using an address of this network owner now, so you cannot lock it out.');

            return;
        }
        $network = (string) $target['network'];
        if ($own !== '' && SiteProtectionSettings::contains($network, $own)) throw new InvalidArgumentException('You are using this address now, so you cannot lock it out.');
        foreach ((array) $this->settings->values()['never_lock_out'] as $entry) {
            if (SiteProtectionSettings::contains($network, (string) strtok((string) $entry, '/')) || SiteProtectionSettings::contains((string) $entry, (string) strtok($network, '/'))) {
                throw new InvalidArgumentException($target['label'] . ' is on your Never lock out list, so it cannot be locked out.');
            }
        }
    }
}
