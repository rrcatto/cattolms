    /**
     * @param array<string,mixed> $filters
     * @return array{0:string,1:array<string,mixed>}
     */
    private function where(array $filters): array
    {
        $where = ['TRUE'];
        $params = [];
        if (($filters['from'] ?? null) instanceof DateTimeImmutable) { $where[] = 'r.at >= :from'; $params['from'] = $filters['from']->format(DATE_ATOM); }
        if (($filters['to'] ?? null) instanceof DateTimeImmutable) { $where[] = 'r.at < :to'; $params['to'] = $filters['to']->format(DATE_ATOM); }
        if (($filters['country'] ?? '') !== '') { $where[] = 'r.country_code = :country'; $params['country'] = $filters['country']; }
        if (!empty($filters['leave_out_administrators'])) $where[] = 'NOT r.by_administrator';
        if (($filters['subject'] ?? '') !== '') { $where[] = 'r.subject = CAST(:subject AS inet)'; $params['subject'] = $filters['subject']; }
        if (($filters['q'] ?? '') !== '') {
            $where[] = "(host(r.address) ILIKE :q OR r.path ILIKE :q OR r.agent_label ILIKE :q OR r.user_agent ILIKE :q OR r.network_name ILIKE :q OR r.account_id IN (SELECT CAST(id AS text) FROM users WHERE display_name ILIKE :q OR account_reference ILIKE :q))";
            $params['q'] = '%' . addcslashes((string) $filters['q'], '%_\\') . '%';
        }

        return [implode(' AND ', $where), $params];
    }

    /** @return array{0:string,1:array<string,mixed>} */
    private function inPeriod(SitePeriod $period, bool $leaveOutAdministrators): array
    {
        return ['at >= :from AND at < :to' . ($leaveOutAdministrators ? ' AND NOT by_administrator' : ''), ['from' => $period->from->format(DATE_ATOM), 'to' => $period->to->format(DATE_ATOM)]];
    }
