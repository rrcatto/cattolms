    /**
     * The people who put on or lifted lockouts, by their account ids, for the Lockouts page.
     *
     * @param list<string|null> $accountIds
     * @return array<string,string> each name by account id
     */
    public function namesOf(array $accountIds): array
    {
        $ids = array_values(array_unique(array_filter($accountIds, static fn(?string $id): bool => $id !== null && ctype_digit($id))));
        if ($ids === []) return [];
        $names = [];
        // Only digits reach the array, so it is written out as PostgreSQL reads one.
        foreach ($this->db->fetchAllAssociative('SELECT CAST(id AS text) AS id, display_name FROM users WHERE CAST(id AS text) = ANY(CAST(:ids AS text[]))', ['ids' => '{' . implode(',', $ids) . '}']) as $row) {
            $names[(string) $row['id']] = (string) $row['display_name'];
        }

        return $names;
    }

