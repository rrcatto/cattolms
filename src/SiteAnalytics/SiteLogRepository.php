    /** @return list<array{id:int,name:string,reference:string,last_used:string}> the people who used an address, a range or a network owner's addresses */
    public function peopleOn(?string $network, ?int $asn, int $days, int $limit = 20): array
    {
        $on = $network !== null ? 'r.subject <<= CAST(:target AS cidr)' : 'r.network_asn = :target';
        $rows = $this->db->fetchAllAssociative(
            "SELECT u.id, u.display_name AS name, u.account_reference AS reference, MAX(r.at) AS last_used FROM cattophp_site_requests r JOIN users u ON CAST(u.id AS text) = r.account_id
             WHERE $on AND r.at > NOW() - make_interval(days => :days) GROUP BY u.id, u.display_name, u.account_reference ORDER BY last_used DESC LIMIT :limit",
            ['target' => $network ?? $asn, 'days' => $days, 'limit' => $limit]
        );

        return array_map(static fn(array $row): array => ['id' => (int) $row['id'], 'name' => (string) $row['name'], 'reference' => (string) $row['reference'], 'last_used' => (string) $row['last_used']], $rows);
