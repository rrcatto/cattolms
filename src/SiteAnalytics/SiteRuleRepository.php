namespace CattoLearning\SiteAnalytics;

use CattoLearning\Infrastructure\Persistence\Database;

class SiteRuleRepository
{
    /** What each rule counts, among requests not refused. */
    private const CONDITIONS = [
        'missing' => 'r.status = 404',
        'flood' => 'TRUE',
        'links' => "r.form = 'sign_in'",
        'register' => "r.form = 'register'",
        'tokens' => "r.method = 'POST' AND r.status = 400",
        'trap' => "r.form_signal = 'trap'",
        'script' => "r.form_signal = 'script'",
        'old' => "r.form_signal IN ('outdated','no_browser')",
    ];

    public function __construct(private readonly Database $db)
    {
    }

    /**
     * The addresses over a rule's limit. Requests from before a lockout of the address ended are not counted again.
     *
     * @return list<array{subject:string,n:int}>
     */
    public function offenders(string $rule, int $withinSeconds, int $count): array
    {
        $measure = $rule === 'links' ? 'COUNT(DISTINCT r.form_email_hash)' : 'COUNT(*)';
        $rows = $this->db->fetchAllAssociative(
            "SELECT abbrev(r.subject) AS subject, $measure AS n FROM site_requests r
             WHERE r.at > NOW() - make_interval(secs => :within) AND NOT r.refused AND " . self::CONDITIONS[$rule] . "
               AND NOT EXISTS (SELECT 1 FROM site_lockouts l WHERE l.network >>= r.subject AND r.at < COALESCE(l.lifted_at, l.until_at, 'infinity'))
             GROUP BY r.subject HAVING $measure >= :count",
            ['within' => $withinSeconds, 'count' => $count]
        );

        return array_map(static fn(array $row): array => ['subject' => (string) $row['subject'], 'n' => (int) $row['n']], $rows);
    }

    public function usedByAnAdministrator(string $subject, int $days): bool
    {
        return (bool) $this->db->fetchOne('SELECT EXISTS (SELECT 1 FROM site_requests WHERE subject = CAST(:subject AS inet) AND by_administrator AND at > NOW() - make_interval(days => :days))', ['subject' => $subject, 'days' => $days]);
    }

    public function usedBySomeoneSignedIn(string $subject, int $days): bool
    {
        return (bool) $this->db->fetchOne('SELECT EXISTS (SELECT 1 FROM site_requests WHERE subject = CAST(:subject AS inet) AND user_id IS NOT NULL AND at > NOW() - make_interval(days => :days))', ['subject' => $subject, 'days' => $days]);
    }

    public function isProvedSearchEngine(string $subject): bool
    {
        return (bool) $this->db->fetchOne("SELECT EXISTS (SELECT 1 FROM site_requests WHERE subject = CAST(:subject AS inet) AND agent_kind = 'search' AND agent_proved)", ['subject' => $subject]);
    }

    /** @return list<array<string,mixed>> addresses calling themselves search engines, not yet asked about */
    public function searchEnginesToProve(int $limit): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT host(address) AS address, MAX(agent_label) AS engine FROM site_requests WHERE agent_kind = 'search' AND agent_proved IS NULL AND at > NOW() - INTERVAL '1 day' GROUP BY address ORDER BY MAX(at) DESC LIMIT :limit",
            ['limit' => $limit]
        );
    }

    /** The answer given for this address in the past week, or null. */
    public function earlierProof(string $address): ?bool
    {
        $known = $this->db->fetchOne("SELECT agent_proved FROM site_requests WHERE address = CAST(:address AS inet) AND agent_proved IS NOT NULL AND at > NOW() - INTERVAL '7 days' ORDER BY at DESC LIMIT 1", ['address' => $address]);

        return $known === false || $known === null ? null : ($known === true || $known === 't');
    }

    public function proved(string $address, bool $proved): void
    {
        $this->db->executeStatement('UPDATE site_requests SET agent_proved = :proved WHERE address = CAST(:address AS inet) AND agent_proved IS NULL', ['proved' => $proved, 'address' => $address]);
    }
}
