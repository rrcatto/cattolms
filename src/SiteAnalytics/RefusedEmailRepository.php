declare(strict_types=1);

namespace CattoLearning\SiteAnalytics;

use CattoLearning\Infrastructure\Persistence\Database;
use InvalidArgumentException;

class RefusedEmailRepository
{
    public function __construct(private readonly Database $db)
    {
    }

    /** @return list<array<string,mixed>> */
    public function all(): array
    {
        return $this->db->fetchAllAssociative('SELECT id, value, why, refused, created_at FROM site_refused_emails ORDER BY created_at DESC, id DESC');
    }

    /** Whether this email address, or its domain, is on the list. Counted when it is. */
    public function refuses(string $email): bool
    {
        $email = strtolower(trim($email));
        $domain = (string) substr((string) strrchr($email, '@'), 1);

        return $this->db->executeStatement('UPDATE site_refused_emails SET refused = refused + 1 WHERE value IN (:email, :domain)', ['email' => $email, 'domain' => $domain !== '' ? $domain : $email]) > 0;
    }

    public function add(string $value, string $why, ?int $actorUserId): string
    {
        $value = strtolower(trim($value));
        $isEmail = filter_var($value, FILTER_VALIDATE_EMAIL) !== false;
        $isDomain = preg_match('/^(?=.{3,253}$)([a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$/', $value) === 1;
        if (!$isEmail && !$isDomain) throw new InvalidArgumentException('Give an email address, such as someone@example.com, or a domain, such as example.com.');
        $this->db->executeStatement(
            'INSERT INTO site_refused_emails (value, why, created_by_user_id) VALUES (:value, :why, :actor) ON CONFLICT (value) DO UPDATE SET why = EXCLUDED.why',
            ['value' => $value, 'why' => mb_substr(trim($why), 0, 500), 'actor' => $actorUserId]
        );

        return $value;
    }

    public function remove(int $id): ?string
    {
        $value = $this->db->fetchOne('DELETE FROM site_refused_emails WHERE id = :id RETURNING value', ['id' => $id]);

        return $value === false || $value === null ? null : (string) $value;
    }
}
