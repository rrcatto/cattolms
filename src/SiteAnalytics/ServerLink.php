/*
Generated by: Claude Code CLI

Date time: 2026/11/04 SAST

Description:
What the site and the server's firewall tell each other (owner, 2026-11-04, decisions 1B and 2B). The site never needs
root: it appends what it wants banned or released to storage/server-firewall/requests.log, and reads what the server
refuses from storage/server-firewall/view.json. Something on the server, run by the server's owner, reads the one and
writes the other (docs/OPERATIONS.md, "The server's firewall"). On a server without it there is no view, the Settings
page says so, and the tick on a lockout is not offered.

Changelog:
2026/11/04 SAST
- Created.
*/

declare(strict_types=1);

namespace CattoLearning\SiteAnalytics;

use Throwable;

class ServerLink
{
    /** How old the view may be before the pages say it is out of date. */
    public const STALE_AFTER = 600;

    public function __construct(private readonly string $storageRoot)
    {
    }

    public function ban(string $network): void
    {
        $this->request('ban', $network);
    }

    public function release(string $network): void
    {
        $this->request('lift', $network);
    }

    /**
     * What the server last said.
     *
     * @return array{available:bool,stale:bool,written_at:string,bans:list<array{address:string,why:string,since:string}>,probes:list<array{at:string,address:string,path:string}>,probes_today:int}
     */
    public function view(): array
    {
        $none = ['available' => false, 'stale' => false, 'written_at' => '', 'bans' => [], 'probes' => [], 'probes_today' => 0];
        $file = $this->folder() . '/view.json';
        if (!is_readable($file)) return $none;
        try {
            $view = json_decode((string) file_get_contents($file), true, 8, JSON_THROW_ON_ERROR);
        } catch (Throwable) {
            return $none;
        }
        if (!is_array($view)) return $none;
        $written = strtotime((string) ($view['written_at'] ?? '')) ?: (int) filemtime($file);

        return [
            'available' => true,
            'stale' => time() - $written > self::STALE_AFTER,
            'written_at' => gmdate(DATE_ATOM, $written),
            'bans' => array_values(array_map(static fn(array $ban): array => ['address' => (string) ($ban['address'] ?? ''), 'why' => (string) ($ban['why'] ?? ''), 'since' => (string) ($ban['since'] ?? '')], array_filter((array) ($view['bans'] ?? []), 'is_array'))),
            'probes' => array_values(array_map(static fn(array $probe): array => ['at' => (string) ($probe['at'] ?? ''), 'address' => (string) ($probe['address'] ?? ''), 'path' => RequestFacts::maskedPath((string) ($probe['path'] ?? '/'))], array_filter((array) ($view['probes'] ?? []), 'is_array'))),
            'probes_today' => (int) ($view['probes_today'] ?? 0),
        ];
    }

    /** Whether the server's firewall holds this address, by this site's lockout or any other rule. */
    public function isBanned(string $subject): bool
    {
        foreach ($this->view()['bans'] as $ban) {
            if (SiteProtectionSettings::contains($ban['address'], (string) strtok($subject, '/'))) return true;
        }

        return false;
    }

    public function folder(): string
    {
        return $this->storageRoot . '/server-firewall';
    }

    private function request(string $what, string $network): void
    {
        $folder = $this->folder();
        if (!is_dir($folder) && !@mkdir($folder, 0775, true) && !is_dir($folder)) throw new \RuntimeException('The folder for the server\'s firewall could not be made.');
        $line = json_encode(['at' => gmdate(DATE_ATOM), 'do' => $what, 'network' => $network], JSON_THROW_ON_ERROR) . "\n";
        if (@file_put_contents($folder . '/requests.log', $line, FILE_APPEND | LOCK_EX) === false) throw new \RuntimeException('The request to the server\'s firewall could not be written.');
    }
}
