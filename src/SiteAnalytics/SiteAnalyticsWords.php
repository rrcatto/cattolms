namespace CattoLearning\SiteAnalytics;

use CattoLearning\Auth\Signup\SignupCountries;
use DateTimeImmutable;

final class SiteAnalyticsWords
{
    public const NETWORKS = ['home' => 'Home or mobile', 'hosting' => 'Hosting', 'vpn' => 'VPN', 'tor' => 'Tor exit', 'private' => 'Local network', '' => 'Unknown'];

    public static function when(string $at, bool $seconds = false): string
    {
        $time = strtotime($at);
        if ($time === false) return $at;
        $moment = (new DateTimeImmutable('@' . $time))->setTimezone(new \DateTimeZone(date_default_timezone_get()));
        $today = new DateTimeImmutable('today', new \DateTimeZone(date_default_timezone_get()));
        $clock = $moment->format($seconds ? 'H:i:s' : 'H:i');
        if ($moment >= $today->modify('+2 days')) return $moment->format($moment->format('Y') === $today->format('Y') ? 'j F H:i' : 'j F Y H:i');
        if ($moment >= $today->modify('+1 day')) return 'Tomorrow ' . $clock;
        if ($moment >= $today) return 'Today ' . $clock;
        if ($moment >= $today->modify('-1 day')) return 'Yesterday ' . $clock;

        return $moment->format($moment->format('Y') === $today->format('Y') ? 'j F H:i' : 'j F Y H:i');
    }

    /** "4 minutes ago", or when, if it was long ago. */
    public static function ago(?string $at): string
    {
        if ($at === null || $at === '') return 'Not seen';
        $seconds = time() - (int) strtotime($at);
        if ($seconds < 60) return 'Just now';
        if ($seconds < 3600) return intdiv($seconds, 60) . (intdiv($seconds, 60) === 1 ? ' minute ago' : ' minutes ago');
        if ($seconds < 21600) return intdiv($seconds, 3600) . (intdiv($seconds, 3600) === 1 ? ' hour ago' : ' hours ago');

        return self::when($at);
    }

    public static function until(?string $until): string
    {
        return $until === null || $until === '' ? 'For good' : self::when($until);
    }

    public static function country(?string $code): string
    {
        return $code === null || $code === '' ? 'Unknown' : SignupCountries::name($code);
    }

    /** @return array{label:string,tone:string} what the site answered */
    public static function answer(int $status, bool $refused, bool $formRefused, string $method): array
    {
        if ($refused) return ['label' => '403 Refused', 'tone' => 'danger'];
        if ($formRefused) return ['label' => $status . ' Form refused', 'tone' => 'danger'];
        if ($status === 400 && $method === 'POST') return ['label' => '400 Form refused', 'tone' => 'danger'];

        return match (true) {
            $status === 404 => ['label' => '404 Not found', 'tone' => 'warning'],
            $status >= 500 => ['label' => $status . ' Fault', 'tone' => 'danger'],
            $status >= 400 => ['label' => $status . ' Refused', 'tone' => 'warning'],
            $status >= 300 => ['label' => $status . ' Sent on', 'tone' => 'success'],
            default => ['label' => $status . ' Shown', 'tone' => 'success'],
        };
    }

    /**
     * A row of the Site Log as the pages show it.
     *
     * @param array<string,mixed> $row
     * @return array<string,mixed>
     */
    public static function row(array $row): array
    {
        $signedIn = $row['user_id'] !== null;
        $fine = $row['flag_fine'] ?? null;
        $flagged = ($row['flag_level'] ?? null) !== null && $fine !== true && $fine !== 't';
        $proved = ($row['agent_proved'] ?? null) === true || ($row['agent_proved'] ?? null) === 't';
        $named = in_array($row['agent_kind'], [VisitorAgent::SEARCH, VisitorAgent::CRAWLER], true);
        $answer = self::answer((int) $row['status'], self::truthy($row['refused']), self::truthy($row['form_refused']), (string) $row['method']);

        return [
            'id' => (int) $row['id'],
            'when' => self::when((string) $row['at'], true),
            'signed_in' => $signedIn,
            'who' => $signedIn ? (string) $row['user_name'] : ($named ? (string) $row['agent_label'] : (string) $row['address']),
            'who_href' => $signedIn ? '/admin/people/' . (int) $row['user_id'] : self::addressHref((string) $row['subject']),
            'address' => (string) $row['address'],
            'show_address' => $signedIn || $named,
            'address_href' => self::addressHref((string) $row['subject']),
            'flag' => $flagged ? ['label' => ucfirst((string) $row['flag_level']), 'tone' => $row['flag_level'] === 'high' ? 'danger' : 'warning'] : null,
            'from' => self::country($row['country_code'] ?? null),
            'network' => $row['agent_kind'] === VisitorAgent::SEARCH ? 'Search engine' : (self::NETWORKS[(string) $row['network_kind']] ?? 'Unknown'),
            'network_name' => (string) $row['network_name'],
            'page' => (string) $row['path'],
            'method' => (string) $row['method'],
            'answer' => $answer,
            'browser' => (string) $row['agent_label'] . ($proved ? ', proved' : ''),
            'lockable' => !$signedIn && !self::truthy($row['refused']) && !$proved && !RequestFacts::isPrivate((string) $row['address']),
        ];
    }

    public static function addressHref(string $subject): string
    {
        // An IPv6 machine is always its /64, so the address needs no mark of it.
        return '/admin/site-analytics/address/' . strtok($subject, '/');
    }

    /**
     * What someone is doing, from the page they asked for last.
     *
     * @param array<string,string> $courses each course's title by its address
     */
    public static function doing(string $path, bool $refused, array $courses): string
    {
        if ($refused) return 'Refused: locked out';
        if ($path === '/') return 'On the home page';
        if (preg_match('#^/learn/([^/]+)#', $path, $match) === 1) return 'Reading ' . ($courses[$match[1]] ?? $match[1]);
        if (preg_match('#^/landing/([^/]+)#', $path, $match) === 1) return 'Looking at ' . ($courses[$match[1]] ?? $match[1]);
        if (preg_match('#^/courses/category#', $path) === 1 || $path === '/courses') return 'Looking at the catalogue';
        if (preg_match('#^/courses/([^/]+)#', $path, $match) === 1) return 'Looking at ' . ($courses[$match[1]] ?? $match[1]);
        foreach (['/checkout' => 'At checkout', '/cart' => 'At the cart', '/register' => 'Registering', '/login' => 'Signing in', '/auth/' => 'Signing in', '/account' => 'In their account', '/company' => 'In the company pages', '/admin' => 'In Administration', '/mailing' => 'In Mailing', '/contact' => 'On the contact page', '/help' => 'Reading the help', '/faq' => 'Reading the FAQ'] as $start => $words) {
            if (str_starts_with($path, $start)) return $words;
        }

        return 'Asking for ' . $path;
    }

    /**
     * A page's name in the most-viewed list.
     *
     * @param array<string,string> $courses
     */
    public static function pageName(string $path, array $courses): string
    {
        if ($path === '/') return 'Home';
        if ($path === '/courses') return 'Catalogue';
        if (preg_match('#^/(?:courses|landing|learn)/([^/]+)#', $path, $match) === 1 && isset($courses[$match[1]])) return $courses[$match[1]];

        return ['/register' => 'Register', '/login' => 'Sign in', '/contact' => 'Contact', '/help' => 'Help', '/faq' => 'FAQ', '/terms' => 'Terms', '/privacy' => 'Privacy Policy', '/refunds' => 'Refund Policy', '/presentation' => 'Presentation', '/cart' => 'Cart', '/checkout' => 'Checkout'][$path] ?? $path;
    }

    public static function truthy(mixed $value): bool
    {
        return $value === true || $value === 't' || $value === 1 || $value === '1';
    }
}
