declare(strict_types=1);

namespace CattoLearning\SiteAnalytics;

use CattoLearning\Auth\AuthService;
use CattoLearning\Auth\Signup\NetworkLookup;
use CattoLearning\Support\ClientFingerprint;
use Symfony\Component\DependencyInjection\Attribute\Autowire;
use Symfony\Component\EventDispatcher\Attribute\AsEventListener;
use Symfony\Component\HttpKernel\Event\TerminateEvent;
use Symfony\Component\HttpKernel\KernelEvents;
use Throwable;

#[AsEventListener(event: KernelEvents::TERMINATE)]
final class RequestRecorder
{
    /** On a request, set by a page that refreshes itself: that refresh is not a visit. */
    public const LIVE_REFRESH = 'site_analytics.live_refresh';

    public function __construct(
        private readonly SiteLogRepository $log,
        private readonly AuthService $auth,
        private readonly NetworkLookup $network,
        #[Autowire('%kernel.environment%')] private readonly string $environment,
    ) {
    }

    public function __invoke(TerminateEvent $event): void
    {
        $address = ClientFingerprint::ipAddress();
        // The tests' kernel asks for pages with no visitor behind them, and every run must leave the records as it found them.
        if ($address === '' || $this->environment === 'test') return;
        try {
            $request = $event->getRequest();
            if ($request->attributes->get(self::LIVE_REFRESH) === true) return;
            $response = $event->getResponse();
            $user = $this->auth->currentUser();
            $agent = (string) $request->headers->get('User-Agent', '');
            $reading = VisitorAgent::read($agent);
            $facts = $this->network->facts($address);
            [$cameFrom, $source] = RequestFacts::cameFrom((string) $request->headers->get('Referer', ''), $request->getHost());
            $form = $request->attributes->get(FormGuard::ATTRIBUTE);
            $form = is_array($form) ? $form : [];
            $networkKind = RequestFacts::isPrivate($address) ? 'private' : ($facts->tor ? 'tor' : ($facts->vpn ? 'vpn' : ($facts->datacenter ? 'hosting' : ($facts->public ? 'home' : ''))));
            // A page changed in place (UX rule 8.6a) is a page like any other. htmx names its target as main#cl-main.
            $inPlace = str_ends_with((string) $request->headers->get('HX-Target', ''), 'cl-main');
            $page = $request->isMethod('GET') && $response->getStatusCode() < 400 && (!$request->headers->has('HX-Request') || $inPlace)
                && str_starts_with((string) $response->headers->get('Content-Type', 'text/html'), 'text/html');
            $this->log->record([
                'address' => $address, 'subject' => RequestFacts::subject($address), 'user_id' => $user?->id,
                'by_administrator' => $user !== null && $user->hasPermission('PLATFORM.SITEANALYTICS.VIEW'),
                'visitor' => $user !== null ? 'signed_in' : ($reading->isAutomated() ? 'automated' : 'person'),
                'agent_kind' => $reading->kind, 'agent_label' => $reading->label, 'device' => $reading->device, 'user_agent' => mb_substr($agent, 0, 500),
                'country_code' => $facts->countryCode !== '' ? $facts->countryCode : null, 'network_kind' => $networkKind, 'network_asn' => $facts->asn, 'network_name' => mb_substr($facts->networkName, 0, 200),
                'method' => mb_substr($request->getMethod(), 0, 10), 'path' => RequestFacts::maskedPath($request->getRequestUri()), 'status' => $response->getStatusCode(), 'is_page' => $page,
                'came_from' => $cameFrom, 'source' => $source,
                'form' => $form['form'] ?? null, 'form_signal' => $form['signal'] ?? null, 'form_refused' => (bool) ($form['refused'] ?? false),
                'form_email' => ($form['refused'] ?? false) ? ($form['email'] ?? null) : null, 'form_email_hash' => $form['email_hash'] ?? null,
            ]);
        } catch (Throwable $fault) {
            error_log('A request could not be written to the Site Log: ' . $fault->getMessage());
        }
    }
}
