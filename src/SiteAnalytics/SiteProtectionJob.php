<?php

/*
Generated by: Claude Code CLI

Date time: 2026/11/04 SAST

Description:
Applies the rules once a minute (owner, 2026-11-04, decision 3A): counts what each address did from the Site Log, flags it
and times it out as Settings > Site protection says, doubling each new time-out and locking out one that keeps coming back.
An address on Never lock out, an administrator's, a private one and a search engine that proves who it is are never timed
out. One a signed-in person used lately is flagged for the owner instead, because mobile networks share addresses among
many people. It also releases at the firewall what has run out, and asks whether search engines are what they say.

Changelog:
2026/11/04 SAST
- Created.
*/

declare(strict_types=1);

namespace CattoLearning\SiteAnalytics;

use CattoLearning\Support\Duration;
use DateTimeImmutable;

class SiteProtectionJob
{
    /** How long administrators' and signed-in people's addresses are spared after they were used. */
    public const SPARED_DAYS = 30;

    /** How many addresses are asked about in one run: a name lookup can take seconds. */
    private const PROOFS_A_RUN = 10;

    public function __construct(
        private readonly SiteRuleRepository $requests,
        private readonly SiteProtectionSettings $settings,
        private readonly FlagRepository $flags,
        private readonly LockoutRepository $lockouts,
        private readonly ServerLink $server,
    ) {
    }

    public function run(): string
    {
        $proved = $this->proveSearchEngines();
        $settings = $this->settings->values();
        $done = ['flagged' => 0, 'timed' => 0, 'locked' => 0];
        foreach (SiteProtectionSettings::RULES as $key => $rule) {
            $set = $settings['rules'][$key] ?? null;
            if (!is_array($set) || empty($set['on'])) continue;
            foreach ($this->requests->offenders($key, Duration::parse((string) $set['within'])->lengthInSeconds(), (int) $set['count']) as $offender) {
                $this->act($key, $rule, $set, $settings, $offender, $done);
            }
        }
        $released = 0;
        foreach ($this->lockouts->firewallDue() as $due) {
            $this->server->release((string) $due['network_text']);
            $this->lockouts->firewallReleased((int) $due['id']);
            $released++;
        }

        return sprintf('%d flagged, %d timed out, %d locked out, %d released at the firewall, %d search engines checked.', $done['flagged'], $done['timed'], $done['locked'], $released, $proved);
    }

    /**
     * @param array{name:string,counted:bool,level:string,env:string,start:string} $rule
     * @param array<string,mixed> $set
     * @param array<string,mixed> $settings
     * @param array{subject:string,n:int} $offender
     * @param array{flagged:int,timed:int,locked:int} $done
     */
    private function act(string $key, array $rule, array $set, array $settings, array $offender, array &$done): void
    {
        $subject = $offender['subject'];
        if ($this->settings->isNeverLockedOut($subject) || RequestFacts::isPrivate($subject)) return;
        if (!empty($settings['spare_administrators']) && $this->requests->usedByAnAdministrator($subject, self::SPARED_DAYS)) return;
        if (!empty($settings['spare_search_engines']) && $this->requests->isProvedSearchEngine($subject)) return;
        if ($this->flags->isFine($subject, SiteProtectionSettings::FINE_DAYS)) return;
        $fine = $this->flags->findBySubject($subject);
        if ($fine !== null && ($fine['fine'] === true || $fine['fine'] === 't')) $this->flags->reopen($subject);

        $within = Duration::parse((string) $set['within'])->lengthInSeconds();
        $words = self::words($key, $offender['n'], (string) $set['within']);
        $timeOut = $set['then'] === 'timeout';
        if ($timeOut && !empty($settings['spare_people']) && $this->requests->usedBySomeoneSignedIn($subject, self::SPARED_DAYS)) {
            $timeOut = false;
            $words .= ' Signed-in people have used this address, so it was only flagged, not timed out.';
        }
        $flagged = $this->flags->raise($subject, $rule['level'], $key, $words, max($within, 60));
        if (!$timeOut) {
            if ($flagged) $done['flagged']++;

            return;
        }
        $this->timeOut($key, $set, $settings, $subject, $words, $done);
    }

    /**
     * @param array<string,mixed> $set
     * @param array<string,mixed> $settings
     * @param array{flagged:int,timed:int,locked:int} $done
     */
    private function timeOut(string $key, array $set, array $settings, string $subject, string $words, array &$done): void
    {
        $now = new DateTimeImmutable();
        $earlier = $this->lockouts->automaticTimeoutsSince($subject, Duration::parse((string) $settings['lockout_within'])->before($now));
        $base = ['kind' => 'address', 'network' => $subject, 'asn' => null, 'label' => $subject, 'rule_key' => $key, 'automatic' => true, 'created_by_user_id' => null, 'firewall' => 'no'];
        if (count($earlier) + 1 >= (int) $settings['lockout_count']) {
            $this->lockouts->add($base + ['which' => 'lockout', 'why' => 'Timed out ' . (count($earlier) + 1) . ' times within ' . Duration::parse((string) $settings['lockout_within'])->words() . '.', 'until' => Duration::parse((string) $settings['lockout_length'])->after($now)]);
            $done['locked']++;

            return;
        }
        $seconds = Duration::parse((string) $set['length'])->lengthInSeconds();
        $again = $earlier !== [];
        if ($again && !empty($settings['doubles'])) {
            $last = $earlier[0];
            $seconds = max($seconds, 2 * ((int) strtotime((string) $last['until_at']) - (int) strtotime((string) $last['started_at'])));
            $seconds = min($seconds, max(Duration::parse((string) $settings['longest'])->lengthInSeconds(), Duration::parse((string) $set['length'])->lengthInSeconds()));
        }
        $this->lockouts->add($base + ['which' => 'timeout', 'why' => $words . ($again ? ' It came back after a time-out.' : ''), 'until' => $now->modify('+' . $seconds . ' seconds')]);
        $done['timed']++;
    }

    /** Why a rule fired, in words. */
    public static function words(string $key, int $count, string $within): string
    {
        $in = Duration::parse($within)->words();

        return match ($key) {
            'missing' => 'Asked for ' . $count . ' pages that do not exist in ' . $in . '.',
            'flood' => $count . ' requests in ' . $in . '.',
            'links' => 'Asked for sign-in links for ' . $count . ' different email addresses in ' . $in . '.',
            'register' => 'Tried to register ' . $count . ' times in ' . $in . '.',
            'tokens' => 'Sent ' . $count . ' forms with a false or expired form token in ' . $in . '.',
            'trap' => 'Filled in a hidden field that people never see.',
            'script' => 'Sent a form from a script, not a browser.',
            default => 'Sent a form from a browser years out of date, or from no browser at all.',
        };
    }

    /**
     * Whether addresses calling themselves search engines are: the host name their address gives must belong to the
     * engine and lead back to the same address. An earlier answer for an address is used again for a week.
     */
    private function proveSearchEngines(): int
    {
        $asked = 0;
        foreach ($this->requests->searchEnginesToProve(self::PROOFS_A_RUN) as $row) {
            $address = (string) $row['address'];
            $this->requests->proved($address, $this->requests->earlierProof($address) ?? self::proves($address, (string) $row['engine']));
            $asked++;
        }

        return $asked;
    }

    private static function proves(string $address, string $engine): bool
    {
        $suffixes = VisitorAgent::SEARCH_ENGINES[$engine] ?? [];
        $host = @gethostbyaddr($address);
        if (!is_string($host) || $host === $address) return false;
        $host = strtolower(rtrim($host, '.'));
        $belongs = false;
        foreach ($suffixes as $suffix) {
            if (str_ends_with($host, '.' . $suffix)) $belongs = true;
        }
        if (!$belongs) return false;
        $back = @dns_get_record($host, str_contains($address, ':') ? DNS_AAAA : DNS_A);
        foreach (is_array($back) ? $back : [] as $record) {
            if (($record['ip'] ?? $record['ipv6'] ?? '') !== '' && inet_pton((string) ($record['ip'] ?? $record['ipv6'])) === inet_pton($address)) return true;
        }

        return false;
    }
}
