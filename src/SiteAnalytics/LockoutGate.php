/*
Generated by: Claude Code CLI

Date time: 2026/11/04 SAST

Description:
The lockout check (owner, 2026-11-04): every request, before a session is started or the application is loaded. A
locked-out address gets a bare "This site is not available." and nothing else, no reason and no theme (owner: "I don't
want to give them any information"). The webhooks of payment and service providers are never refused, because each
carries its own signature. A refused request adds to its lockout's counter, and only the first of a day go into the Site
Log, so a flood cannot fill the disk.

It runs before the container is built, so it takes the database it is handed and looks nothing up unless it must: the
network owner's number only when a network owner is locked out, the Never lock out list only when something matches.

Changelog:
2026/11/04 SAST
- Created.
*/

declare(strict_types=1);

namespace CattoLearning\SiteAnalytics;

use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Infrastructure\Persistence\OptionRepository;
use CattoLearning\Support\ClientFingerprint;
use CattoLearning\Support\Env;
use CattoLearning\Support\GeoIpLocator;
use GeoIp2\Database\Reader;
use Throwable;

final class LockoutGate
{
    /** How many refused requests of one lockout the Site Log keeps in a day. The counter goes on counting. */
    public const LOGGED_A_DAY = 100;

    public const PAGE = "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"robots\" content=\"noindex\"><title>Not available</title></head><body><p>This site is not available.</p></body></html>\n";

    private readonly LockoutGateRepository $records;

    public function __construct(private readonly Database $db)
    {
        $this->records = new LockoutGateRepository($db);
    }

    /**
     * Whether this request is refused, counted when it is. A fault here never stops the site: it answers as if nothing
     * were locked out.
     */
    public function refuses(string $address, string $path, string $method = 'GET', string $agent = ''): bool
    {
        if ($address === '' || str_starts_with($path, '/webhooks/')) return false;
        try {
            $lockout = $this->matching($address);
            if ($lockout === null) return false;
            if ((new SiteProtectionSettings(new OptionRepository($this->db)))->isNeverLockedOut($address)) return false;
            $this->count((int) $lockout, $address, $path, $method, $agent);

            return true;
        } catch (Throwable $fault) {
            error_log('The lockout check failed: ' . $fault->getMessage());

            return false;
        }
    }

    /** Answers a refused request and ends it, before any session or theme. */
    public static function refuse(): never
    {
        http_response_code(403);
        header('Content-Type: text/html; charset=utf-8');
        header('Cache-Control: no-store');
        header('X-Robots-Tag: noindex');
        echo self::PAGE;
        exit;
    }

    private function matching(string $address): ?int
    {
        $rows = $this->records->inForceFor($address);
        if ($rows === []) return null;
        if ($rows[0]['asn'] === null) return (int) $rows[0]['id'];
        $number = self::networkNumber($address);
        foreach ($rows as $row) {
            if ($number !== null && (int) $row['asn'] === $number) return (int) $row['id'];
        }

        return null;
    }

    private function count(int $lockout, string $address, string $path, string $method, string $agent): void
    {
        if ($this->records->count($lockout) > self::LOGGED_A_DAY) return;
        // What the log knows of this address from its last request, or its country and network from the databases.
        $subject = RequestFacts::subject($address);
        $last = $this->records->lastKnown($subject);
        $reading = VisitorAgent::read($agent);
        $this->records->record(['address' => $address, 'subject' => $subject, 'visitor' => $reading->isAutomated() ? 'automated' : 'person', 'kind' => $reading->kind, 'label' => $reading->label, 'device' => $reading->device, 'agent' => mb_substr($agent, 0, 500),
            'country' => $last !== null ? ($last['country_code'] ?: null) : ((new GeoIpLocator())->countryCode($address) ?: null), 'network_kind' => $last !== null ? (string) $last['network_kind'] : '',
            'asn' => $last !== null ? $last['network_asn'] : self::networkNumber($address), 'network' => $last !== null ? (string) $last['network_name'] : '',
            'method' => mb_substr($method, 0, 10), 'path' => RequestFacts::maskedPath($path)]);
    }

    /** The number of the network an address belongs to, from the ASN database beside GEOIP_DATABASE. */
    private static function networkNumber(string $address): ?int
    {
        $city = Env::string('GEOIP_DATABASE');
        $file = $city !== '' ? dirname($city) . '/GeoLite2-ASN.mmdb' : '';
        if ($file === '' || !is_readable($file)) return null;
        try {
            return (new Reader($file))->asn($address)->autonomousSystemNumber;
        } catch (Throwable) {
            return null;
        }
    }

    /** The visitor's address and page, as the web server gave them. */
    public static function checkCurrentRequest(Database $db): void
    {
        $address = ClientFingerprint::ipAddress();
        $path = (string) (parse_url((string) ($_SERVER['REQUEST_URI'] ?? '/'), PHP_URL_PATH) ?: '/');
        if ((new self($db))->refuses($address, $path, (string) ($_SERVER['REQUEST_METHOD'] ?? 'GET'), (string) ($_SERVER['HTTP_USER_AGENT'] ?? ''))) self::refuse();
    }
}
