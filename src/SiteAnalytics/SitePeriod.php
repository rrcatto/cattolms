declare(strict_types=1);

namespace CattoLearning\SiteAnalytics;

use DateTimeImmutable;

final class SitePeriod
{
    public const CHOICES = ['hour' => 'Past hour', 'today' => 'Today', 'week' => 'Past week', 'month' => 'Past month', 'quarter' => 'Past 3 months', 'dates' => 'Dates'];

    private function __construct(
        public readonly string $key,
        public readonly string $label,
        public readonly DateTimeImmutable $from,
        public readonly DateTimeImmutable $to,
        public readonly string $fromDay,
        public readonly string $toDay,
    ) {
    }

    public static function of(string $key, string $from, string $to, DateTimeImmutable $now, string $default = 'week'): self
    {
        if (!isset(self::CHOICES[$key])) $key = $default;
        $fromDay = self::day($from);
        $toDay = self::day($to);
        if ($key === 'dates' && $fromDay !== '' && $toDay !== '' && $fromDay <= $toDay) {
            return new self('dates', $fromDay . ' to ' . $toDay, new DateTimeImmutable($fromDay . ' 00:00:00'), (new DateTimeImmutable($toDay . ' 00:00:00'))->modify('+1 day'), $fromDay, $toDay);
        }
        if ($key === 'dates') $key = $default;
        $start = match ($key) {
            'hour' => $now->modify('-1 hour'),
            'today' => $now->setTime(0, 0),
            'week' => $now->modify('-7 days'),
            'month' => $now->modify('-30 days'),
            default => $now->modify('-90 days'),
        };

        return new self($key, self::CHOICES[$key], $start, $now, '', '');
    }

    /** The same length of time just before this period, with how to say it. */
    public function before(): self
    {
        $length = $this->to->getTimestamp() - $this->from->getTimestamp();

        return new self($this->key, 'the period before', $this->from->modify('-' . $length . ' seconds'), $this->from, '', '');
    }

    /** The length of one column of a chart of this period: an hour, a day or a week. */
    public function unit(): string
    {
        $days = ($this->to->getTimestamp() - $this->from->getTimestamp()) / 86400;

        return $days <= 1.01 ? 'hour' : ($days <= 45 ? 'day' : 'week');
    }

    /** @return array<string,string> */
    public function query(): array
    {
        return $this->key === 'dates' ? ['period' => 'dates', 'from' => $this->fromDay, 'to' => $this->toDay] : ['period' => $this->key];
    }

    /** @return array{key:string,label:string,fromDay:string,toDay:string} what a page shows of the period */
    public function view(): array
    {
        return ['key' => $this->key, 'label' => $this->label, 'fromDay' => $this->fromDay, 'toDay' => $this->toDay];
    }

    private static function day(string $text): string
    {
        $text = trim($text);
        $parsed = DateTimeImmutable::createFromFormat('!Y-m-d', $text);

        return $parsed !== false && $parsed->format('Y-m-d') === $text ? $text : '';
    }
}
