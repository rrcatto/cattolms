declare(strict_types=1);

namespace CattoLearning\SiteAnalytics;

use CattoLearning\Infrastructure\Persistence\Database;

final class LockoutGateRepository
{
    public function __construct(private readonly Database $db)
    {
    }

    /** @return list<array<string,mixed>> what is in force on this address, and every network owner locked out */
    public function inForceFor(string $address): array
    {
        return $this->db->fetchAllAssociative(
            'SELECT id, asn FROM site_lockouts
             WHERE lifted_at IS NULL AND (until_at IS NULL OR until_at > NOW()) AND (asn IS NOT NULL OR network >>= CAST(:address AS inet))
             ORDER BY asn NULLS FIRST, started_at',
            ['address' => $address]
        );
    }

    /** Adds to a lockout's counter, and says how many it has refused today. */
    public function count(int $lockout): int
    {
        return (int) $this->db->fetchOne(
            'UPDATE site_lockouts SET refused = refused + 1, last_refused_at = NOW(),
                logged_on_day = CASE WHEN logged_day = CURRENT_DATE THEN logged_on_day + 1 ELSE 1 END, logged_day = CURRENT_DATE
             WHERE id = :id RETURNING logged_on_day',
            ['id' => $lockout]
        );
    }

    /** @return array<string,mixed>|null the country and network the log last had for this address */
    public function lastKnown(string $subject): ?array
    {
        $row = $this->db->fetchAssociative(
            'SELECT country_code, network_kind, network_asn, network_name FROM site_requests WHERE subject = CAST(:subject AS inet) ORDER BY at DESC LIMIT 1',
            ['subject' => $subject]
        );

        return is_array($row) ? $row : null;
    }

    /** @param array<string,mixed> $row */
    public function record(array $row): void
    {
        $this->db->executeStatement(
            'INSERT INTO site_requests (address, subject, visitor, agent_kind, agent_label, device, user_agent, country_code, network_kind, network_asn, network_name, method, path, status, refused)
             VALUES (CAST(:address AS inet), CAST(:subject AS inet), :visitor, :kind, :label, :device, :agent, :country, :network_kind, :asn, :network, :method, :path, 403, TRUE)',
            $row
        );
    }
}
