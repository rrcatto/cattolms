    public function save(array $input, ?int $actorUserId = null): array
    {
        if ($this->options === null || $this->cipher === null) throw new InvalidArgumentException('Settings cannot be saved here.');
        $changed = [];
        foreach (self::FIELDS as $field => [, $label, $secret]) {
            if (!array_key_exists($field, $input)) continue;
            $value = trim((string) $input[$field]);
            if ($secret && $value === '') continue;
            self::check($field, $value);
            if (!$secret && $value === $this->value($field) && $this->source($field) === 'database') continue;
            $this->options->set(self::OPTION . $field, $secret ? $this->cipher->encrypt($value) : $value, $actorUserId);
            $changed[] = $label;
        }

        return $changed;
    }

