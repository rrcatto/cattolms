    public function digestSummary(): array
    {
        $rules = $this->rules();
        $from = (string) $rules['send_from'];
        $until = (string) $rules['send_until'];
        $all = $from === $until;
        $day = (int) $rules['digest_month_day'];
        $ordinal = $day . (in_array($day % 100, [11, 12, 13], true) ? 'th' : ([1 => 'st', 2 => 'nd', 3 => 'rd'][$day % 10] ?? 'th'));

        return ['around_the_clock' => $all, 'hours' => $all ? 'around the clock' : 'between ' . $from . ' and ' . $until,
            'daily' => 'every day at ' . ($all ? '00:00' : $from), 'weekly' => 'every ' . self::DAYS[(int) $rules['digest_weekday']] . ' at ' . ($all ? '00:00' : $from),
            'monthly' => 'on the ' . $ordinal . ' of each month at ' . ($all ? '00:00' : $from)];
    }

