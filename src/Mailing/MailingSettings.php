    /**
     * Whether a moment falls within the sending hours: from the start up to the end, local time; the same start and end
     * mean around the clock, and an end before the start runs through midnight (20:00 to 06:00).
     */
    public function withinSendingHours(\DateTimeInterface $at): bool
    {
        $rules = $this->rules();
        $from = (string) $rules['send_from'];
        $until = (string) $rules['send_until'];
        if ($from === $until) return true;
        $now = \DateTimeImmutable::createFromInterface($at)->setTimezone(new \DateTimeZone(date_default_timezone_get()))->format('H:i');

        return $from < $until ? $now >= $from && $now < $until : $now >= $from || $now < $until;
    }

