        return (int) $this->db->fetchOne("SELECT COUNT(*) FROM mailing_suppressions WHERE (:search = '' OR email ILIKE :like)", ['search' => $search, 'like' => '%' . addcslashes($search, '%_\\') . '%']);
    }

    public function saveAsset(string $sha256, string $mediaType, string $bytes, int $width, int $height, ?int $userId): void
    {
        $this->db->executeStatement(
            'INSERT INTO mailing_assets (sha256, media_type, bytes, width, height, created_by_user_id, created_at) VALUES (:s, :m, decode(:b, \'base64\'), :w, :h, :u, NOW()) ON CONFLICT (sha256) DO NOTHING',
            ['s' => $sha256, 'm' => $mediaType, 'b' => base64_encode($bytes), 'w' => $width, 'h' => $height, 'u' => $userId]
        );
    }

    /** @return array{media_type:string,bytes:string,width:int,height:int}|null */
    public function asset(string $sha256): ?array
    {
        if (preg_match('/^[0-9a-f]{64}$/', $sha256) !== 1) return null;
        $row = $this->db->fetchAssociative("SELECT media_type, encode(bytes, 'base64') AS bytes, width, height FROM mailing_assets WHERE sha256 = :s", ['s' => $sha256]);

        return $row === false ? null : ['media_type' => (string) $row['media_type'], 'bytes' => (string) base64_decode((string) $row['bytes'], true), 'width' => (int) $row['width'], 'height' => (int) $row['height']];
    }

    /**
     * What a course block shows: title, address, summary and the lowest current price with its was price.
     *
     * @param list<int> $courseIds
     * @return array<int,array<string,mixed>>
     */
    public function courseCards(array $courseIds): array
    {
        if ($courseIds === []) return [];
        $cards = [];
        foreach ($this->db->fetchAllAssociative(
            "SELECT c.id, c.title, c.slug, c.summary, c.subtitle, c.status, p.price_minor_units, p.was_price_minor_units, p.currency_code, p.access_period_seconds
             FROM courses c LEFT JOIN LATERAL (
                 SELECT v.price_minor_units, v.was_price_minor_units, v.currency_code, v.access_period_seconds FROM course_price_variants v
                 WHERE v.course_id = c.id AND v.is_active ORDER BY v.is_default DESC, v.price_minor_units, v.position LIMIT 1) p ON TRUE
             WHERE c.id = ANY(CAST(:ids AS BIGINT[]))",
            ['ids' => '{' . implode(',', array_map('intval', $courseIds)) . '}']
        ) as $row) $cards[(int) $row['id']] = $row;

        return $cards;
    }

    /** @return list<array{id:int,title:string,code:string,slug:string}> published courses for a course block's choice */
