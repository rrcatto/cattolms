        ));
    }

    /**
     * People who follow something, were first sent news before $cutoff, and have opened or clicked nothing since then,
     * and were not asked whether they still want it since then either: the sleeping addresses.
     *
     * @return list<array{user_id:int,email:string,first_name:string}>
     */
    public function sleepingCandidates(string $cutoff, int $limit): array
    {
        return array_map(static fn(array $r): array => ['user_id' => (int) $r['user_id'], 'email' => (string) $r['email'], 'first_name' => (string) $r['first_name']], $this->db->fetchAllAssociative(
            "SELECT u.id AS user_id, e.email, COALESCE(u.first_name, '') AS first_name
             FROM users u JOIN user_emails e ON e.user_id = u.id AND e.is_primary
             WHERE u.status = 'active'
               AND EXISTS (SELECT 1 FROM mailing_subscriptions s WHERE s.user_id = u.id AND s.status = 'subscribed')
               AND NOT EXISTS (SELECT 1 FROM mailing_suppressions x WHERE x.email = LOWER(e.email))
               AND (SELECT MIN(d.handed_at) FROM mailing_deliveries d WHERE d.user_id = u.id) < :cutoff
               AND NOT EXISTS (SELECT 1 FROM mailing_deliveries d WHERE d.user_id = u.id AND (d.last_opened_at >= :cutoff OR d.first_clicked_at >= :cutoff OR d.first_opened_at >= :cutoff))
               AND NOT EXISTS (SELECT 1 FROM mailing_deliveries d JOIN mailing_campaigns c ON c.id = d.campaign_id WHERE d.user_id = u.id AND c.kind = 'sleeping' AND d.created_at >= :cutoff)
             ORDER BY u.id LIMIT :limit",
            ['cutoff' => $cutoff, 'limit' => $limit]
        ));
    }

    /** @return list<array<string,mixed>> sleeping-address copies handed before $cutoff with no answer and not yet settled */
    public function sleepingUnanswered(string $cutoff): array
    {
        return array_map(static fn(array $row): array => self::decodeDelivery($row), $this->db->fetchAllAssociative(
            "SELECT d.* FROM mailing_deliveries d JOIN mailing_campaigns c ON c.id = d.campaign_id
             WHERE c.kind = 'sleeping' AND d.handed_at < :cutoff AND d.user_id IS NOT NULL
               AND d.content->>'kept' IS NULL AND d.content->>'stopped' IS NULL",
            ['cutoff' => $cutoff]
        ));
    }

