    /**
     * The sendings handed to catto-mail, newest first: one per message or digest and list, with what became of its copies.
     *
     * @return list<array<string,mixed>>
     */
    public function cattomailJobs(int $limit): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT d.transport_job_id AS job_id, c.id AS campaign_id, c.name AS campaign, c.kind, MIN(d.handed_at) AS handed_at, MAX(d.checked_at) AS checked_at, COUNT(*) AS copies,
                    COUNT(*) FILTER (WHERE d.status = 'handed') AS on_the_way, COUNT(*) FILTER (WHERE d.status = 'delivered') AS delivered,
                    COUNT(*) FILTER (WHERE d.status IN ('bounced', 'soft_bounced', 'complained', 'failed', 'suppressed')) AS problems
             FROM mailing_deliveries d JOIN mailing_campaigns c ON c.id = d.campaign_id
             WHERE d.transport = 'cattomail' AND d.transport_job_id IS NOT NULL GROUP BY d.transport_job_id, c.id, c.name, c.kind ORDER BY MIN(d.handed_at) DESC LIMIT :limit",
            ['limit' => $limit]
        );
    }

    /** @return list<array<string,mixed>> the events catto-mail reported, newest first */
    public function transportEvents(string $type, int $limit): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT id, event_id, event_type, received_at, processed_at, outcome, payload->'data'->'message'->>'external_recipient_reference' AS token, payload->'data'->>'id' AS job_id
             FROM mailing_transport_events WHERE (:type = '' OR event_type = :type) ORDER BY received_at DESC, id DESC LIMIT :limit",
            ['type' => $type, 'limit' => $limit]
        );
    }

    /** An event taken again on the next run. */
    public function retryTransportEvent(int $id): bool
    {
        return $this->db->executeStatement('UPDATE mailing_transport_events SET processed_at = NULL, outcome = NULL WHERE id = :id', ['id' => $id]) > 0;
    }

    public function transportEventProcessed(int $id, string $outcome): void
