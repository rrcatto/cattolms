            'INSERT INTO mailing_links (campaign_id, url) VALUES (:c, :u) ON CONFLICT (campaign_id, url) DO UPDATE SET url = EXCLUDED.url RETURNING id',
            ['c' => $campaignId, 'u' => $url]
        );
    }

    public function linkUrl(int $campaignId, int $linkId): ?string
    {
        $url = $this->db->fetchOne('SELECT url FROM mailing_links WHERE id = :id AND campaign_id = :c', ['id' => $linkId, 'c' => $campaignId]);

