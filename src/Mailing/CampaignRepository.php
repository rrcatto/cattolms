    /**
     * @param array<string,mixed> $row
     * @return array<string,mixed>
     */
    private static function decode(array $row): array
    {
        foreach (['blocks', 'list_ids', 'exclude_list_ids'] as $json) if (isset($row[$json]) && is_string($row[$json])) $row[$json] = json_decode($row[$json], true) ?? [];
        foreach (['list_ids', 'exclude_list_ids'] as $ids) if (isset($row[$ids])) $row[$ids] = array_values(array_map('intval', (array) $row[$ids]));
        if (isset($row['blocks'])) $row['blocks'] = EmailBlocks::normalise($row['blocks']);
        foreach (['id', 'total', 'queued', 'sent', 'delivered', 'bounced', 'hard_bounced', 'complained', 'not_sent', 'opened', 'clicked', 'unsubscribed', 'via_cattomail'] as $int) if (isset($row[$int])) $row[$int] = (int) $row[$int];

        return $row;
    }

    /**
     * @param array<string,mixed> $row
     * @return array<string,mixed>
     */
    private static function decodeDelivery(array $row): array
    {
        foreach (['reasons', 'content'] as $json) if (isset($row[$json]) && is_string($row[$json])) $row[$json] = json_decode($row[$json], true) ?? [];
        foreach (['id', 'campaign_id', 'user_id', 'list_id', 'attempts', 'open_count', 'click_count'] as $int) if (isset($row[$int])) $row[$int] = (int) $row[$int];

        return $row;
    }
