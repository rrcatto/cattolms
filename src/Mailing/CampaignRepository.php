    /**
     * The addresses that contain what has been typed (owner, 2026-10-28: "show me all the emails that match as I type"):
     * every account's addresses, and addresses already never emailed that no account holds, those starting with it first.
     *
     * @return list<array{email:string,name:string,user_id:int,never_emailed:bool}>
     */
    public function matchingAddresses(string $typed, int $limit): array
    {
        $typed = mb_strtolower(trim($typed));
        if (mb_strlen($typed) < 2) return [];
        $like = addcslashes($typed, '%_\\');

        return array_map(static fn(array $r): array => ['email' => (string) $r['email'], 'name' => (string) $r['name'], 'user_id' => (int) $r['user_id'], 'never_emailed' => in_array($r['never_emailed'], [true, 't', 1, '1'], true)],
            $this->db->fetchAllAssociative(
                "SELECT email, name, user_id, never_emailed FROM (
                     SELECT LOWER(e.email) AS email, COALESCE(NULLIF(trim(concat_ws(' ', u.first_name, u.last_name)), ''), u.display_name, '') AS name, u.id AS user_id,
                            EXISTS (SELECT 1 FROM cattophp_mailing_suppressions x WHERE x.email = LOWER(e.email)) AS never_emailed
                     FROM user_emails e JOIN users u ON u.id = e.user_id WHERE LOWER(e.email) LIKE :contains
                     UNION
                     SELECT x.email, '' AS name, 0 AS user_id, TRUE AS never_emailed FROM cattophp_mailing_suppressions x
                     WHERE x.email LIKE :contains AND NOT EXISTS (SELECT 1 FROM user_emails e WHERE LOWER(e.email) = x.email)
                 ) found ORDER BY (email LIKE :starts) DESC, email LIMIT :limit",
                ['contains' => '%' . $like . '%', 'starts' => $like . '%', 'limit' => $limit]
            ));
    }

