            "SELECT id, title, slug, COALESCE(code, '') AS code FROM courses WHERE status = 'published' ORDER BY catalogue_position NULLS LAST, lower(title)"
        ));
    }

    /**
     * People who follow something, were first sent news before $cutoff, and have opened or clicked nothing since then,
     * and were not asked whether they still want it since then either: the sleeping addresses.
     *
     * @return list<array{user_id:int,email:string,first_name:string}>
     */
    public function sleepingCandidates(string $cutoff, int $limit): array
    {
        return array_map(static fn(array $r): array => ['user_id' => (int) $r['user_id'], 'email' => (string) $r['email'], 'first_name' => (string) $r['first_name']], $this->db->fetchAllAssociative(
            "SELECT u.id AS user_id, e.email, COALESCE(u.first_name, '') AS first_name
             FROM users u JOIN user_emails e ON e.user_id = u.id AND e.is_primary
             WHERE u.status = 'active'
               AND EXISTS (SELECT 1 FROM cattophp_mailing_subscriptions s WHERE s.account = CAST(u.id AS TEXT) AND s.status = 'subscribed')
               AND NOT EXISTS (SELECT 1 FROM cattophp_mailing_suppressions x WHERE x.email = LOWER(e.email))
               AND (SELECT MIN(d.handed_at) FROM cattophp_mailing_copies d WHERE d.account = CAST(u.id AS TEXT)) < :cutoff
               AND NOT EXISTS (SELECT 1 FROM cattophp_mailing_copies d WHERE d.account = CAST(u.id AS TEXT) AND (d.last_opened_at >= :cutoff OR d.first_clicked_at >= :cutoff OR d.first_opened_at >= :cutoff))
               AND NOT EXISTS (SELECT 1 FROM cattophp_mailing_copies d JOIN cattophp_mailing_campaigns c ON c.id = d.campaign_id WHERE d.account = CAST(u.id AS TEXT) AND c.kind = 'sleeping' AND d.created_at >= :cutoff)
             ORDER BY u.id LIMIT :limit",
            ['cutoff' => $cutoff, 'limit' => $limit]
        ));
    }

    /** @return list<array<string,mixed>> sleeping-address copies handed before $cutoff with no answer and not yet settled */
    public function sleepingUnanswered(string $cutoff): array
    {
        return array_map(static fn(array $row): array => self::delivery(Copies::decode($row)), $this->db->fetchAllAssociative(
            "SELECT d.* FROM cattophp_mailing_copies d JOIN cattophp_mailing_campaigns c ON c.id = d.campaign_id
             WHERE c.kind = 'sleeping' AND d.handed_at < :cutoff AND d.account IS NOT NULL
               AND d.content->>'kept' IS NULL AND d.content->>'stopped' IS NULL",
            ['cutoff' => $cutoff]
        ));
    }

    /** @param array<string,mixed> $content */
    public function setDeliveryContent(int $id, array $content): void
    {
        $this->copies->setContent($id, $content);
    }

    /** The daily clean-up: copies made before $before go, their clicks with them; campaigns and suppressions stay. */
    public function deleteBefore(\DateTimeImmutable $before): int
    {
        return $this->copies->deleteBefore($before);
    }

    /**
     * The sendings handed to catto-mail, newest first: one per message or digest and list, with what became of its copies.
     *
     * @return list<array<string,mixed>>
     */
    public function cattomailJobs(int $limit): array
    {
        return $this->copies->cattomailJobs($limit);
    }

    /**
     * Each campaign's template, by its id.
     *
     * @param list<int> $ids
     * @return array<int,?int>
     */
    private function templates(array $ids): array
    {
        if ($ids === []) return [];
        $out = [];
        foreach ($this->db->fetchAllAssociative('SELECT campaign_id, template_id FROM mailing_campaign_settings WHERE campaign_id = ANY(CAST(:ids AS BIGINT[]))', ['ids' => '{' . implode(',', $ids) . '}']) as $row) {
            $out[(int) $row['campaign_id']] = $row['template_id'] === null ? null : (int) $row['template_id'];
        }

        return $out;
    }

    /**
     * A campaign as cattolms's services read it: its blocks, its template, and who made and approved it as user ids.
     *
     * @param array<string,mixed> $row
     * @param array<int,?int> $templates
     * @return array<string,mixed>
     */
    private function campaign(array $row, array $templates): array
    {
        $row['blocks'] = EmailBlocks::normalise((array) ($row['content'] ?? []));
        unset($row['content']);
        $row['template_id'] = $templates[(int) $row['id']] ?? null;
        $row['created_by_user_id'] = isset($row['created_by']) && ctype_digit((string) $row['created_by']) ? (int) $row['created_by'] : null;
        $row['approved_by_user_id'] = isset($row['approved_by']) && ctype_digit((string) $row['approved_by']) ? (int) $row['approved_by'] : null;

        return $row;
    }

    /**
     * A copy as cattolms's services read it: its person as their user id.
     *
     * @param array<string,mixed> $row
     * @return array<string,mixed>
     */
    private static function delivery(array $row): array
    {
        $row['user_id'] = isset($row['account']) && ctype_digit((string) $row['account']) ? (int) $row['account'] : null;

        return $row;
    }
