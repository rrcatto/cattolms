<?php

/*
Generated by: Claude Code CLI

Date time: 2026/10/28 SAST

Version: 1.0.0

Description:
Records course changes as held updates (owner, 2026-10-28, decision 1A: "The site records course changes, and you keep,
reword or delete each one"), each kind switched on or off in Sending settings (MailingSettings::RECORDED). It reads the
activity log from where it last stopped, so no course action needs to know about mailing, and it never goes back over the
history from before it first ran:

- a course published for the first time ("New course: <title>");
- lessons or sections added to a published course, merged while held ("3 new lessons or sections in <title>");
- a published course's lowest price going down ("<title>: now R2,400, was R3,000"), compared with the lowest price it last
  saw (mailing_course_prices), merged while held;
- a promotion limited to chosen courses coming into force, once for each course it covers;
- a course's landing page published;
- a course retired.

Nothing is sent: each update waits on the Digest page until ADMIN releases it.

Changelog:
2026/10/28 SAST
- Created.
*/

declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Infrastructure\Persistence\OptionRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\AccessPeriod;
use CattoLearning\Support\Env;
use CattoLearning\Support\Money;
use DateTimeImmutable;
use Symfony\Component\Clock\ClockInterface;

final class UpdateRecorder
{
    private const MARK = 'mailing.updates_audit_mark';
    private const PROMOTIONS = 'mailing.updates_promotions_seen';
    private const BATCH = 500;

    public function __construct(
        private readonly UpdateRepository $updates,
        private readonly MailingSettings $settings,
        private readonly OptionRepository $options,
        private readonly TransactionManager $transactions,
        private readonly ClockInterface $clock,
    ) {
    }

    /** @return int how many updates were made or added to */
    public function run(): int
    {
        return (int) $this->transactions->run(function (): int {
            $mark = $this->options->find(self::MARK);
            if ($mark === null) {
                // The first run starts from now: the history before mailing existed is not news.
                $this->options->set(self::MARK, (string) $this->updates->lastActivityId());
                $this->options->set(self::PROMOTIONS, (string) json_encode(array_values(array_unique(array_column($this->updates->promotionsInForce($this->now()), 'promotion_id')))));

                return 0;
            }
            $rules = $this->settings->rules();
            $changed = 0;
            $last = (int) $mark;
            foreach ($this->updates->activitySince($last, self::BATCH) as $row) {
                $last = $row['id'];
                $changed += $this->record($row['event_key'], $row['metadata'], $rules);
            }
            $this->options->set(self::MARK, (string) $last);
            $changed += $this->promotions($rules);

            return $changed;
        });
    }

    /**
     * @param array<string,mixed> $metadata
     * @param array<string,mixed> $rules
     */
    private function record(string $event, array $metadata, array $rules): int
    {
        $courseId = (int) ($metadata['course_id'] ?? 0);
        if ($courseId <= 0) return 0;
        $course = $this->updates->course($courseId);
        if ($course === null) return 0;

        return match ($event) {
            'course.status_changed' => match ((string) ($metadata['status'] ?? '')) {
                'published' => (bool) $rules['record_first_published'] && !$this->updates->everRecorded($courseId, 'first_published') ? $this->firstPublished($courseId, $course) : 0,
                'retired' => (bool) $rules['record_retired'] ? $this->add($courseId, 'retired', $course['title'] . ' is no longer offered', 'People who have it keep their access until it ends.', $this->courseUrl($course)) : 0,
                default => 0,
            },
            'course_item.placed', 'course_section.created' => (bool) $rules['record_content_added'] && $course['status'] === 'published' ? $this->contentAdded($courseId, $course) : 0,
            'course.pricing_created', 'course.pricing_updated', 'course.pricing_deleted', 'course.pricing_default_changed' => (bool) $rules['record_price_lowered'] ? $this->priceChanged($courseId, $course) : 0,
            'landing_page.published' => (bool) $rules['record_landing_published'] && $course['status'] === 'published'
                ? $this->add($courseId, 'landing_published', 'Find out more about ' . $course['title'], 'Its new page shows what it covers and who it is for.', $this->siteUrl() . '/landing/' . (string) ($metadata['slug'] ?? $course['slug'])) : 0,
            default => 0,
        };
    }

    /** @param array{title:string,slug:string,status:string} $course */
    private function firstPublished(int $courseId, array $course): int
    {
        $price = $this->updates->lowestPrice($courseId);
        if ($price !== null) $this->updates->seePrice($courseId, $price['price']);

        return $this->add($courseId, 'first_published', 'New course: ' . $course['title'], $price !== null ? 'From ' . self::money($price['price'], $price['currency']) . ' for ' . AccessPeriod::label($price['period']) . '.' : '', $this->courseUrl($course));
    }

    /** @param array{title:string,slug:string,status:string} $course */
    private function contentAdded(int $courseId, array $course): int
    {
        $held = $this->updates->heldRecorded($courseId, 'content_added');
        $count = $held === null ? 1 : (int) $held['change_count'] + 1;
        $headline = ($count === 1 ? 'A new lesson or section' : $count . ' new lessons or sections') . ' in ' . $course['title'];
        if ($held !== null) {
            $this->updates->update((int) $held['id'], ['change_count' => $count, 'headline' => $headline], null);

            return 1;
        }
        $this->updates->create('recorded', 'content_added', $courseId, null, $headline, 'Open the course to see what is new.', $this->courseUrl($course), null);

        return 1;
    }

    /** @param array{title:string,slug:string,status:string} $course */
    private function priceChanged(int $courseId, array $course): int
    {
        $price = $this->updates->lowestPrice($courseId);
        if ($price === null) return 0;
        $before = $this->updates->lastPrice($courseId);
        $this->updates->seePrice($courseId, $price['price']);
        if ($before === null || $price['price'] >= $before) return 0;
        $was = $price['was'] !== null && $price['was'] > $price['price'] ? $price['was'] : $before;
        $headline = $course['title'] . ': now ' . self::money($price['price'], $price['currency']) . ', was ' . self::money($was, $price['currency']);
        $held = $this->updates->heldRecorded($courseId, 'price_lowered');
        if ($held !== null) {
            $this->updates->update((int) $held['id'], ['headline' => $headline, 'change_count' => (int) $held['change_count'] + 1], null);

            return 1;
        }
        $this->updates->create('recorded', 'price_lowered', $courseId, null, $headline, 'For ' . AccessPeriod::label($price['period']) . '.', $this->courseUrl($course), null);

        return 1;
    }

    /** @param array<string,mixed> $rules */
    private function promotions(array $rules): int
    {
        $seen = array_map('intval', (array) json_decode((string) ($this->options->find(self::PROMOTIONS) ?? '[]'), true));
        $made = 0;
        $now = $this->now();
        foreach ($this->updates->promotionsInForce($now) as $row) {
            if (in_array($row['promotion_id'], $seen, true)) continue;
            $course = $this->updates->course($row['course_id']);
            if ($course !== null && (bool) $rules['record_promotion']) {
                $ends = $row['ends_at'] !== null ? ' until ' . (new DateTimeImmutable($row['ends_at']))->setTimezone(new \DateTimeZone(date_default_timezone_get()))->format('j F') : '';
                $made += $this->add($row['course_id'], 'promotion', $row['name'] . ': ' . $course['title'], 'On now' . $ends . '.', $this->courseUrl($course));
            }
            $seen[] = $row['promotion_id'];
        }
        // A promotion is announced once, for every course it covers, the first time it is seen in force.
        $this->options->set(self::PROMOTIONS, (string) json_encode(array_values(array_unique($seen))));

        return $made;
    }

    private function add(int $courseId, string $event, string $headline, string $body, string $link): int
    {
        $this->updates->create('recorded', $event, $courseId, null, $headline, $body, $link, null);

        return 1;
    }

    /** @param array{title:string,slug:string,status:string} $course */
    private function courseUrl(array $course): string
    {
        return $this->siteUrl() . '/courses/' . $course['slug'];
    }

    private function siteUrl(): string
    {
        return rtrim(Env::string('APP_URL'), '/');
    }

    private static function money(int $minor, string $currency): string
    {
        return Money::strictMinorUnits($minor, $currency)->format();
    }

    private function now(): string
    {
        return DateTimeImmutable::createFromInterface($this->clock->now())->format(DATE_ATOM);
    }
}
