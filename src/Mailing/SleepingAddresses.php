Description:
Sleeping addresses (mailing, step 2; owner, 2026-10-26, part of "best sending practices"): an address that has opened or
clicked nothing for the Settings' time (a year to start with) is asked once whether it still wants the news, with one
button. Someone who presses it keeps everything they follow; someone who does not answer within the Settings' time (30
days to start with) stops getting news, everything they follow stopped with the reason kept. Mail that is never read
tells the inbox providers that the sender is not wanted, and an abandoned address can become a spam trap, so asking
first and then stopping keeps the sending address clean.

The question is a campaign of its own (kind "sleeping"), made and sent by itself once a day.

Changelog:
2026/10/26 SAST
- Created.
