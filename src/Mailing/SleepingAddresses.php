declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Support\Duration;
use DateTimeImmutable;
use DateTimeZone;
use Symfony\Component\Clock\ClockInterface;

class SleepingAddresses
{
    public function __construct(
        private readonly CampaignRepository $campaigns,
        private readonly MailingSettings $settings,
        private readonly MailingConsents $consents,
        private readonly AuditRepository $audit,
        private readonly ClockInterface $clock,
        private readonly ?AutomaticEmails $automatic = null,
    ) {
    }

    /** @return array{asked:int,stopped:int} */
    public function run(): array
    {
        $rules = $this->settings->rules();
        $now = DateTimeImmutable::createFromInterface($this->clock->now());
        $asked = 0;
        $cutoff = Duration::parse((string) $rules['sleeping_after'])->before($now);
        // Switched off on Automatic emails, nobody is asked; those asked before still have their answer counted.
        $people = ($this->automatic?->word('sleeping_on') ?? true) ? $this->campaigns->sleepingCandidates(self::stamp($cutoff), 1000) : [];
        if ($people !== []) {
            $id = $this->campaigns->create('sleeping', 'Do you still want our news? (' . $now->setTimezone(new DateTimeZone(date_default_timezone_get()))->format('j M Y') . ')', null, [
                'subject' => (string) ($this->automatic?->word('sleeping_subject') ?? AutomaticEmails::WORDS['sleeping_subject']),
                'preheader' => 'One click keeps it coming.',
                'blocks' => [
                    ['id' => 'b' . bin2hex(random_bytes(5)), 'type' => 'heading', 'text' => 'Do you still want our news?'],
                    ['id' => 'b' . bin2hex(random_bytes(5)), 'type' => 'text', 'text' => str_replace('{wait}', Duration::parse((string) $rules['sleeping_answer_within'])->words(), (string) ($this->automatic?->word('sleeping_intro') ?? AutomaticEmails::WORDS['sleeping_intro']))],
                ],
                'status' => 'scheduled',
            ]);
            $asked = $this->campaigns->addDeliveries($id, array_map(static fn(array $p): array => $p + ['list_id' => 0, 'reasons' => ['News and Updates']], $people));
        }
        $stopped = 0;
        foreach ($this->campaigns->sleepingUnanswered(self::stamp(Duration::parse((string) $rules['sleeping_answer_within'])->before($now))) as $delivery) {
            $this->consents->unsubscribeAll((int) $delivery['user_id'], 'sleeping');
            $this->campaigns->setDeliveryContent((int) $delivery['id'], (array) $delivery['content'] + ['stopped' => self::stamp($now)]);
            $stopped++;
        }

        return ['asked' => $asked, 'stopped' => $stopped];
    }

    /**
     * They pressed "Yes, keep sending me news".
     *
     * @param array<string,mixed> $delivery
     */
    public function keep(array $delivery): void
    {
        $content = (array) $delivery['content'];
        if (isset($content['kept']) || isset($content['stopped'])) return;
        $this->campaigns->setDeliveryContent((int) $delivery['id'], $content + ['kept' => self::stamp(DateTimeImmutable::createFromInterface($this->clock->now()))]);
        $this->audit->record($delivery['user_id'] !== null ? (int) $delivery['user_id'] : null, 'mailing.kept', ['delivery_id' => (int) $delivery['id']]);
    }

    private static function stamp(DateTimeImmutable $at): string
    {
        return $at->setTimezone(new DateTimeZone('UTC'))->format('Y-m-d H:i:sP');
    }
}
