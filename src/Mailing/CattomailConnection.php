catto-mail"; the approved page 9; decision 8A: news goes through catto-mail once connected), as catto-mail's integration
guide (section 15, API draft 11) describes it, in four steps:

1. catto-mail's address, from CATTOMAIL_API_BASE_URL and overridden here (https only);
2. Connect: an authorisation-code flow with PKCE (S256). The administrator's browser goes to catto-mail's connect page
   with this site's name, the address it comes back to, its webhook address and the domain news comes from; they approve
   it there, and back here the one-time code is exchanged for the API key, the webhook's signing secret and the sending
   domains, given once. The key and secret are kept encrypted in Settings (overriding .env), and news goes through
   catto-mail from then on. Connecting again replaces the connection;
3. the sending domain ready: catto-mail sends only from a verified domain with an active DKIM key; until it can, news
   waits (nothing is sent unsigned), and the mailing job asks catto-mail again every five minutes;
4. a test to the administrator, a real email through catto-mail.

It also checks the connection (a job that cannot exist answers 404 to a key catto-mail accepts), disconnects (catto-mail
revokes the key and removes the webhook) or only forgets the connection here, and remembers until when catto-mail's
quota is used up, so that nothing is asked before it resets.

