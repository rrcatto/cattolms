declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Support\Env;
use InvalidArgumentException;
use Symfony\Component\Mailer\Transport;
use Symfony\Component\Mime\Address;
use Symfony\Component\Mime\Email;

final class MailingForwards
{
    public const PER_COPY = 5;
    public const PER_DAY = 10;

    public function __construct(
        private readonly CampaignRepository $campaigns,
        private readonly EmailRenderer $renderer,
        private readonly RuntimeSettings $runtime,
        private readonly ForwardRepository $forwards,
        private readonly AuditRepository $audit,
    ) {
    }

    /** @return array{delivery:array<string,mixed>,campaign:array<string,mixed>}|null a copy that was sent, by its token, with its campaign */
    public function copy(string $token): ?array
    {
        $delivery = $this->campaigns->deliveryByToken($token);
        if ($delivery === null || $delivery['handed_at'] === null || $delivery['user_id'] === null) return null;
        $campaign = $this->campaigns->find((int) $delivery['campaign_id']);

        return $campaign === null ? null : ['delivery' => $delivery, 'campaign' => $campaign];
    }

    /**
     * @param array{delivery:array<string,mixed>,campaign:array<string,mixed>} $copy
     * @return array{subject:string,html:string,text:string,unsubscribe_url:string} the web copy: the person's copy, nothing tracked
     */
    public function webCopy(array $copy): array
    {
        return $this->renderer->render($copy['campaign'], $this->person($copy['delivery']), false);
    }

    /**
     * Forwards a copy to a friend. Returns the friend's address.
     *
     * @param array{delivery:array<string,mixed>,campaign:array<string,mixed>} $copy
     */
    public function forward(array $copy, string $email, string $name, string $note): string
    {
        $delivery = $copy['delivery'];
        $userId = (int) $delivery['user_id'];
        $email = mb_strtolower(trim($email));
        if (filter_var($email, FILTER_VALIDATE_EMAIL) === false) throw new InvalidArgumentException('Write your friend\'s email address in full, such as thandi@example.com.');
        $name = trim((string) preg_replace('/\s+/', ' ', $name));
        if (mb_strlen($name) > 120) throw new InvalidArgumentException('Keep your friend\'s name under 120 characters.');
        $note = trim(str_replace("\r\n", "\n", $note));
        if (mb_strlen($note) > 500) throw new InvalidArgumentException('Keep your note under 500 characters.');
        if ($email === mb_strtolower((string) $delivery['email'])) throw new InvalidArgumentException('That is your own address. Write your friend\'s.');
        if ($this->campaigns->isSuppressed($email)) throw new InvalidArgumentException('We do not email that address.');
        if ($this->forwards->forwardedTo((int) $delivery['id'], $email)) {
            throw new InvalidArgumentException('You already forwarded this email to ' . $email . '.');
        }
        if ($this->forwards->countForCopy((int) $delivery['id']) >= self::PER_COPY) {
            throw new InvalidArgumentException('This email has been forwarded to ' . self::PER_COPY . ' friends already, the most it can be.');
        }
        if ($this->forwards->countForPersonToday($userId) >= self::PER_DAY) {
            throw new InvalidArgumentException('You have forwarded ' . self::PER_DAY . ' emails today, the most in a day. Try again tomorrow.');
        }
        $token = bin2hex(random_bytes(16));
        $site = rtrim(Env::string('APP_URL'), '/');
        $from = $this->campaigns->firstName($userId);
        $friend = $this->renderer->render($copy['campaign'], ['first_name' => $name !== '' ? explode(' ', $name)[0] : '', 'reasons' => [], 'list_name' => '', 'content' => (array) $delivery['content'],
            'forward' => ['from' => $from !== '' ? $from : 'A friend', 'note' => $note, 'never_url' => $this->renderer->linkBase() . '/m/n/' . $token, 'register_url' => $site . '/register']], false);
        $mail = $this->runtime->mailConfiguration();
        $message = (new Email())->from(new Address((string) $mail['from_address'], (string) $mail['from_name']))->to($name !== '' ? new Address($email, $name) : $email)
            ->subject($friend['subject'])->html($friend['html'])->text($friend['text']);
        Transport::fromDsn((string) $mail['dsn'])->send($message);
        $this->forwards->create((int) $delivery['id'], $userId, $email, $name, $note, $token);
        $this->audit->record($userId, 'mailing.forwarded', ['delivery_id' => (int) $delivery['id'], 'campaign_id' => (int) $delivery['campaign_id']]);

        return $email;
    }

    /** @return array{to_email:string}|null a forward by the friend's "Never email me" token */
    public function forwardByToken(string $token): ?array
    {
        if (preg_match('/^[0-9a-f]{32}$/', $token) !== 1) return null;
        $email = $this->forwards->emailByToken($token);

        return $email === null ? null : ['to_email' => $email];
    }

    /** The friend's "Never email me": their address goes on Addresses never emailed. */
    public function neverEmail(string $token): string
    {
        $forward = $this->forwardByToken($token) ?? throw new InvalidArgumentException('This link is not known.');
        $this->campaigns->suppress($forward['to_email'], 'manual', 'Asked never to be emailed, from an email a friend forwarded.', null, null);

        return $forward['to_email'];
    }

    /** How many times a campaign's copies were forwarded. */
    public function countFor(int $campaignId): int
    {
        return $this->forwards->countForCampaign($campaignId);
    }

    /**
     * @param array<string,mixed> $delivery
     * @return array<string,mixed>
     */
    private function person(array $delivery): array
    {
        $reasons = array_values(array_map('strval', (array) ($delivery['reasons'] ?? [])));

        return ['token' => (string) $delivery['token'], 'first_name' => $this->campaigns->firstName((int) $delivery['user_id']), 'reasons' => $reasons,
            'list_name' => $reasons[0] ?? 'News and Updates', 'content' => (array) ($delivery['content'] ?? [])];
    }
}
