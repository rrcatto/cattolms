declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\OptionRepository;
use InvalidArgumentException;

final class AutomaticEmails
{
    private const OPTION = 'mailing.automatic';

    public const WORDS = [
        'updates_intro' => "Hello [First name],\n\nHere is what is new in what you follow.",
        'digest_intro' => "Hello [First name],\n\nHere is what is new in what you follow since your last digest.",
        'sleeping_on' => true,
        'sleeping_subject' => 'Do you still want our news, [First name]?',
        'sleeping_intro' => "Hello [First name],\n\nWe have not seen you open our news for a while, so we are checking before we send more. If you still want it, press the button below. If you do nothing, we will stop sending you news in {wait}, and you can always start again under Account, My Subscriptions.",
    ];

    public function __construct(
        private readonly OptionRepository $options,
        private readonly CampaignRepository $campaigns,
        private readonly AuditRepository $audit,
        private readonly ?MailingTemplates $templates = null,
    ) {
    }

    /** @return array<string,mixed> the words and switches, what is saved over the starting ones */
    public function words(): array
    {
        $saved = json_decode((string) ($this->options->find(self::OPTION) ?? '{}'), true);

        return array_replace(self::WORDS, is_array($saved) ? array_intersect_key($saved, self::WORDS) : []);
    }

    public function word(string $key): mixed
    {
        return $this->words()[$key] ?? self::WORDS[$key] ?? null;
    }

    /** @param array<string,mixed> $input one email's words: updates, digest or sleeping */
    public function save(string $email, array $input, int $userId): void
    {
        $words = $this->words();
        $text = static function (mixed $value, string $label, int $most): string {
            $text = trim(str_replace("\r\n", "\n", (string) $value));
            if ($text === '') throw new InvalidArgumentException('Write ' . $label . '.');
            if (mb_strlen($text) > $most) throw new InvalidArgumentException('Keep ' . $label . ' under ' . number_format($most) . ' characters.');

            return $text;
        };
        switch ($email) {
            case 'updates': $words['updates_intro'] = $text($input['intro'] ?? '', 'the opening words', 4000); break;
            case 'digest': $words['digest_intro'] = $text($input['intro'] ?? '', 'the opening words', 4000); break;
            case 'sleeping':
                $words['sleeping_on'] = ($input['on'] ?? '') === '1';
                $words['sleeping_subject'] = $text($input['subject'] ?? '', 'the subject', 200);
                $words['sleeping_intro'] = $text($input['intro'] ?? '', 'the words', 4000);
                break;
            default: throw new InvalidArgumentException('There is no such automatic email.');
        }
        $this->options->set(self::OPTION, (string) json_encode($words, JSON_THROW_ON_ERROR), $userId);
        $this->audit->record($userId, 'mailing.automatic_saved', ['email' => $email]);
    }

    public function reset(string $email, int $userId): void
    {
        $words = $this->words();
        $keys = ['updates' => ['updates_intro'], 'digest' => ['digest_intro'], 'sleeping' => ['sleeping_on', 'sleeping_subject', 'sleeping_intro']][$email] ?? throw new InvalidArgumentException('There is no such automatic email.');
        foreach ($keys as $key) $words[$key] = self::WORDS[$key];
        $this->options->set(self::OPTION, (string) json_encode($words, JSON_THROW_ON_ERROR), $userId);
    }

    /**
     * Every automatic email, for the page: what it is, what sends it, its template, when one last went, and whether it is on.
     *
     * @param array<string,mixed> $digestDays when each digest goes, in words
     * @return list<array<string,mixed>>
     */
    public function rows(array $digestDays, string $sleepingAfter): array
    {
        $last = $this->campaigns->lastHandedByKind(['updates', 'digest', 'sleeping']);
        $digestTemplate = (string) ($this->templates?->defaultFor('digest')['name'] ?? '');
        $messageTemplate = (string) ($this->templates?->defaultFor('messages')['name'] ?? '');
        $rows = [
            ['key' => 'updates', 'name' => 'Updates as they happen', 'when' => 'Updates are released, to the people who chose them as they happen', 'template' => $digestTemplate, 'last' => $last['updates'] ?? null, 'on' => true, 'href' => '#updates'],
            ['key' => 'digest', 'name' => 'The digests', 'when' => 'Daily ' . ($digestDays['daily'] ?? '') . ', weekly ' . ($digestDays['weekly'] ?? '') . ', monthly ' . ($digestDays['monthly'] ?? '') . ', to each person with updates waiting', 'template' => $digestTemplate, 'last' => $last['digest'] ?? null, 'on' => true, 'href' => '#digest'],
            ['key' => 'sleeping', 'name' => 'Do you still want our news?', 'when' => 'An address has opened and clicked nothing for ' . $sleepingAfter, 'template' => $messageTemplate, 'last' => $last['sleeping'] ?? null, 'on' => (bool) $this->word('sleeping_on'), 'href' => '#sleeping'],
        ];
        foreach ($this->campaigns->welcomeEmails() as $row) {
            $rows[] = ['key' => 'welcome', 'name' => (string) ($row['subject'] ?: 'Welcome to ' . $row['list_name']), 'when' => 'Someone joins ' . $row['list_name'], 'template' => (string) ($row['template'] ?: $messageTemplate),
                'last' => $row['last'], 'on' => (string) $row['status'] === 'sending', 'href' => '/mailing/messages/' . (int) $row['campaign_id'], 'list_href' => '/mailing/lists/' . (int) $row['list_id'] . '#welcome'];
        }

        return $rows;
    }
}
