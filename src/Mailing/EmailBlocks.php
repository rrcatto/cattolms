    /**
     * Checks a whole list of blocks as stored: every block known, each id once.
     *
     * @param mixed $blocks
     * @return list<array<string,mixed>>
     */
    public static function normalise(mixed $blocks): array
    {
        $out = [];
        $seen = [];
        foreach (is_array($blocks) ? $blocks : [] as $block) {
            if (!is_array($block) || !isset(self::TYPES[(string) ($block['type'] ?? '')])) continue;
            $id = (string) ($block['id'] ?? '');
            if (preg_match('/^b[0-9a-f]{10}$/', $id) !== 1 || isset($seen[$id])) continue;
            $seen[$id] = true;
            $out[] = array_replace(self::make((string) $block['type']), $block);
        }

        return $out;
    }

    /**
     * What a block shows in the editor's list: "Heading: Our new courses".
     *
     * @param array<string,mixed> $block
     */
    public static function summary(array $block): string
    {
        $label = self::TYPES[(string) $block['type']][0] ?? 'Block';
        $what = match ((string) $block['type']) {
            'heading', 'text' => html_entity_decode(strip_tags(str_replace(['</p>', '<br>', '</li>'], ' ', (string) $block['text'])), ENT_QUOTES | ENT_HTML5, 'UTF-8'),
            'image' => (string) ($block['alt'] !== '' ? $block['alt'] : ($block['asset'] === '' ? 'no picture yet' : 'a picture')),
            'button' => (string) $block['label'],
            'html' => trim(strip_tags((string) $block['html'])),
            default => '',
        };
        $what = trim((string) preg_replace('/\s+/', ' ', $what));

        return $what === '' ? $label : $label . ': ' . (mb_strlen($what) > 80 ? mb_substr($what, 0, 79) . '…' : $what);
    }

    /**
     * A text block's words as the editor writes them, keeping only what an email can show: paragraphs, line breaks, bold,
     * italics, links (web and email addresses) and lists. Anything else is taken away and its words kept.
     */
    public static function richText(string $html): string
    {
        $allowed = ['p', 'br', 'strong', 'b', 'em', 'i', 'a', 'ul', 'ol', 'li'];
        $document = new \DOMDocument();
        @$document->loadHTML('<?xml encoding="utf-8"?><div id="rich">' . $html . '</div>', LIBXML_NONET | LIBXML_NOERROR | LIBXML_NOWARNING);
        $root = $document->getElementById('rich');
        if ($root === null) return '';
        $clean = static function (\DOMNode $node) use (&$clean, $allowed): void {
            foreach (iterator_to_array($node->childNodes) as $child) {
                if ($child instanceof \DOMComment) { $node->removeChild($child); continue; }
                if (!$child instanceof \DOMElement) continue;
                $clean($child);
                $tag = strtolower($child->tagName);
                if (!in_array($tag, $allowed, true)) {
                    if (in_array($tag, ['script', 'style'], true)) { $node->removeChild($child); continue; }
                    while ($child->firstChild !== null) $node->insertBefore($child->firstChild, $child);
                    $node->removeChild($child);
                    continue;
                }
                $href = $tag === 'a' ? trim($child->getAttribute('href')) : '';
                foreach (iterator_to_array($child->attributes) as $attribute) $child->removeAttribute($attribute->nodeName);
                if ($tag === 'a') {
                    if (preg_match('#^(https?://|mailto:)[^\s"<>]+$#i', $href) === 1) $child->setAttribute('href', $href);
                    else { while ($child->firstChild !== null) $node->insertBefore($child->firstChild, $child); $node->removeChild($child); }
                }
            }
        };
        $clean($root);
        $out = '';
        foreach ($root->childNodes as $child) $out .= $document->saveHTML($child);

        return trim($out);
    }

    private static function text(mixed $value, int $max, string $label, bool $required, bool $oneLine = false): string
    {
        $text = str_replace("\r\n", "\n", trim((string) $value));
        if ($required && $text === '') throw new InvalidArgumentException($label . ' is empty.');
        if (mb_strlen($text) > $max) throw new InvalidArgumentException($label . ' is longer than ' . $max . ' characters.');

        return $oneLine ? (string) preg_replace('/\s+/', ' ', $text) : $text;
    }

    private static function url(mixed $value, bool $required): string
    {
        $url = trim((string) $value);
        if ($url === '' && !$required) return '';
        if (preg_match('#^(https?://[^\s"<>]+|mailto:[^\s"<>]+)$#i', $url) !== 1) throw new InvalidArgumentException('Enter the web address in full, such as https://example.test/courses.');

        return $url;
    }
