declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Infrastructure\Mail\GeneratedDomainRouter;
use Symfony\Component\Mailer\Exception\TransportExceptionInterface;
use Symfony\Component\Mailer\Transport;
use Symfony\Component\Mime\Address;
use Symfony\Component\Mime\Email;
use Throwable;

class SmtpMailingTransport implements MailingTransport
{
    public function __construct(
        private readonly MailingSettings $settings,
        private readonly RuntimeSettings $runtime,
        private readonly GeneratedDomainRouter $router,
    ) {
    }

    public function name(): string
    {
        return 'smtp';
    }

    public function send(array $campaign, array $copies, array $sender): array
    {
        $dsn = $this->settings->value('dsn') !== '' ? $this->settings->value('dsn') : $this->runtime->mailConfiguration()['dsn'];
        try {
            $transport = Transport::fromDsn($dsn);
        } catch (Throwable $broken) {
            throw new MailingTransportRefused('The mail server setting cannot be used: ' . $broken->getMessage());
        }
        $host = (string) (parse_url($copies[0]['unsubscribe_url'] ?? '', PHP_URL_HOST) ?: 'localhost');
        $handed = [];
        $failed = [];
        foreach ($copies as $copy) {
            $email = (new Email())
                ->from(new Address($sender['email'], $sender['name']))
                ->replyTo(new Address((string) (($sender['reply_to'] ?? '') !== '' ? $sender['reply_to'] : $sender['email'])))
                ->to($this->router->deliveryAddress($copy['to']))
                ->subject($copy['subject'])
                ->html($copy['html'])
                ->text($copy['text']);
            $headers = $email->getHeaders();
            $headers->addTextHeader('List-Unsubscribe', '<' . $copy['unsubscribe_url'] . '>');
            $headers->addTextHeader('List-Unsubscribe-Post', 'List-Unsubscribe=One-Click');
            $headers->addTextHeader('List-Id', '"' . str_replace('"', '', $copy['list_name']) . '" <list-' . $copy['list_id'] . '.' . $host . '>');
            $headers->addTextHeader('Feedback-ID', (int) $campaign['id'] . ':' . (string) $campaign['kind'] . ':cattolms');
            try {
                $sent = $transport->send($email);
                $handed[$copy['delivery_id']] = ['job_id' => null, 'message_id' => $sent?->getMessageId()];
            } catch (TransportExceptionInterface $problem) {
                // Nothing was handed yet: the server itself is not there, so everything waits for the next run.
                if ($handed === [] && $failed === []) throw new MailingTransportUnavailable('The mail server did not answer: ' . $problem->getMessage());
                $failed[$copy['delivery_id']] = 'The mail server refused it: ' . $problem->getMessage();
            }
        }

        return ['handed' => $handed, 'failed' => $failed];
    }
}
