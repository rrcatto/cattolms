declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Support\Env;

class MailingSettingsView
{
    public function __construct(private readonly MailingSettings $settings, private readonly RuntimeSettings $runtime, private readonly CampaignRepository $campaigns)
    {
    }

    /** @return array<string,mixed> */
    public function view(): array
    {
        $fields = [];
        foreach (MailingSettings::FIELDS as $key => [$env, $label, $secret]) {
            // catto-mail's address, key and webhook secret come from connecting it, on Mailing › catto-mail (page 9).
            if (str_starts_with($key, 'cattomail_')) continue;
            $value = $this->settings->value($key);
            $fields[$key] = ['label' => $label, 'env' => $env, 'secret' => $secret, 'value' => $secret ? '' : $value, 'set' => $value !== '', 'source' => $this->settings->source($key)];
        }
        $site = rtrim(Env::string('APP_URL'), '/');
        $mail = $this->runtime->mailConfiguration();
        $logo = $this->settings->logo();
        $asset = $logo !== '' ? $this->campaigns->asset($logo) : null;

        return [
            'fields' => $fields,
            'transports' => MailingSettings::TRANSPORTS,
            'transport' => $this->settings->transport(),
            'sender' => $this->settings->fromName((string) $mail['from_name']) . ' <' . $this->settings->fromAddress((string) $mail['from_address']) . '>',
            'link_base' => $this->settings->linkBase($site),
            'webhook_url' => $site . '/webhooks/cattomail',
            'rules' => $this->settings->rules(),
            'rules_source' => $this->settings->rulesSource(),
            'days' => MailingSettings::DAYS,
            'recorded' => MailingSettings::RECORDED,
            'digest_days' => $this->settings->digestSummary(),
            'duration_how' => \CattoLearning\Support\Duration::HOW,
            'logo' => $asset === null ? '' : '/m/i/' . $logo . EmailRenderer::extension($asset['media_type']),
            'source' => array_filter(array_map(fn(string $key): bool => $this->settings->source($key) === 'database', array_keys(MailingSettings::FIELDS))) !== [] ? 'database' : 'environment',
        ];
    }
}
