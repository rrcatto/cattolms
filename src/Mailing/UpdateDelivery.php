Description:
Releases held updates and delivers them as each person chose (owner, 2026-10-28, round two 1A and 2A: "ADMIN approves
updates, not each email"; "They should also be able to choose to receive updates as they occur, or each list collated
into its own digest, or one big digest containing all their subscriptions, sent out according to a frequency they
choose: daily, weekly or monthly"). Each minute, from the mailing job:

1. every held update whose release time has come is released, unless nobody follows what it is about then: that one is
   closed and says so (decision 4B: "If nobody follows it, it does not go out in the digest");
2. people who chose updates as they occur get one email with every released update they have not had (a single update's
   headline is its subject);
3. when a digest's day and time come (the start of the sending hours on the day: every day, the weekly day, the monthly
   day), everyone at that frequency gets their digest of the updates released since their last one, all together or one
   email for each list, as they chose. People who have not chosen get one digest a week.

Nobody gets an update twice (mailing_update_deliveries), nor one released before they began following what brought it.
The emails go through the sender, so the sending hours and the sending discipline apply.

