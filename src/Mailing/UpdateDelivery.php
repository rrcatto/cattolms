declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\OptionRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use DateTimeImmutable;
use DateTimeZone;
use Symfony\Component\Clock\ClockInterface;

final class UpdateDelivery
{
    public const DELIVERIES = [
        'instant' => 'As they happen',
        'per_list' => 'A digest for each thing I follow',
        'combined' => 'One digest with everything',
    ];
    public const FREQUENCIES = ['daily' => 'Daily', 'weekly' => 'Weekly', 'monthly' => 'Monthly'];

    /** An update older than this is no longer news to anyone who has not had it. */
    private const WINDOW = '-62 days';
    private const MADE = 'mailing.digest_made.';

    public function __construct(
        private readonly UpdateRepository $updates,
        private readonly CampaignRepository $campaigns,
        private readonly MailingSettings $settings,
        private readonly OptionRepository $options,
        private readonly RuntimeSettings $runtime,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
        private readonly ClockInterface $clock,
        private readonly ?AutomaticEmails $automatic = null,
    ) {
    }

    /** @return array{released:int,closed:int,instant:int,digests:int} */
    public function run(): array
    {
        [$released, $closed] = $this->release();

        return ['released' => $released, 'closed' => $closed, 'instant' => $this->instant(), 'digests' => $this->digests()];
    }

    /** @return array{0:int,1:int} updates released, and those closed because nobody followed them */
    public function release(): array
    {
        return $this->transactions->run(function (): array {
            $due = $this->updates->dueForRelease($this->stamp($this->now()));
            if ($due === []) return [0, 0];
            $counts = $this->updates->reachCounts($due);
            $released = 0;
            $closed = 0;
            foreach ($due as $id) {
                if (($counts[$id] ?? 0) === 0) {
                    $this->updates->update($id, ['status' => 'closed', 'status_note' => 'Nobody followed what it is about when it was due, so it went to nobody.'], null);
                    $closed++;
                    continue;
                }
                $this->updates->update($id, ['status' => 'released', 'released_at' => $this->stamp($this->now()), 'status_note' => null], null);
                $released++;
            }
            $this->audit->record(null, 'mailing.updates_released', ['released' => $released, 'closed' => $closed]);

            return [$released, $closed];
        });
    }

    /** Emails the people who chose updates as they occur. Returns how many emails it made. */
    public function instant(): int
    {
        return (int) $this->transactions->run(function (): int {
            $released = $this->updates->releasedSince($this->stamp($this->now()->modify(self::WINDOW)));
            if ($released === []) return 0;
            $rows = $this->updates->reach(array_keys($released));
            $instant = array_flip($this->updates->instantPeople(array_values(array_unique(array_column($rows, 'user_id')))));
            $people = $this->gather(array_filter($rows, static fn(array $r): bool => isset($instant[$r['user_id']])), $released, null);
            if ($people === []) return 0;
            $id = $this->campaigns->create('updates', 'Updates as they happen, ' . $this->local()->format('j M Y H:i'), null, [
                'subject' => 'News from ' . $this->runtime->platformName(),
                'preheader' => 'What is new in what you follow.',
                'blocks' => [['type' => 'text', 'text' => $this->words('updates_intro')] + EmailBlocks::make('text')],
                'status' => 'scheduled',
            ]);
            $this->deliver($id, array_map(fn(array $p): array => $this->copy($p, count($p['updates']) === 1 ? $this->headline($p['updates'][0]) : count($p['updates']) . ' new things in what you follow'), $people));

            return count($people);
        });
    }

    /** Makes the digests whose day and time have come. Returns how many emails they hold. */
    public function digests(): int
    {
        $made = 0;
        $local = $this->local();
        if (!$this->digestTimeReached($local)) return 0;
        foreach (array_keys(self::FREQUENCIES) as $frequency) {
            if (!$this->dueToday($frequency, $local)) continue;
            $made += (int) $this->transactions->run(function () use ($frequency, $local): int {
                if ($this->options->find(self::MADE . $frequency) === $local->format('Y-m-d')) return 0;
                $this->options->set(self::MADE . $frequency, $local->format('Y-m-d'));

                return $this->makeDigest($frequency, $local);
            });
        }

        return $made;
    }

    /**
     * When each digest next goes, in words, for the pages: "Friday 30 October at 07:00".
     *
     * @return array<string,string>
     */
    public function nextDigests(): array
    {
        $out = [];
        $local = $this->local();
        $start = $local->setTime(...$this->digestClock());
        foreach (array_keys(self::FREQUENCIES) as $frequency) {
            $made = $this->options->find(self::MADE . $frequency);
            for ($i = 0; $i < 62 && !isset($out[$frequency]); $i++) {
                $day = $start->modify('+' . $i . ' days');
                if (!$this->dueToday($frequency, $day) || $made === $day->format('Y-m-d')) continue;
                $out[$frequency] = $day <= $local ? 'within the next minute' : $day->format('l j F') . ' at ' . $day->format('H:i');
            }
        }

        return $out;
    }

    private function makeDigest(string $frequency, DateTimeImmutable $local): int
    {
        $released = $this->updates->releasedSince($this->stamp($this->now()->modify(self::WINDOW)));
        if ($released === []) return 0;
        $rows = $this->updates->reach(array_keys($released));
        $people = $this->updates->digestPeople($frequency, array_values(array_unique(array_column($rows, 'user_id'))));
        if ($people === []) return 0;
        $label = strtolower(self::FREQUENCIES[$frequency]);
        $combined = $this->gather(array_filter($rows, static fn(array $r): bool => ($people[$r['user_id']]['delivery'] ?? '') === 'combined'), $released, $people);
        $perList = $this->gather(array_filter($rows, static fn(array $r): bool => ($people[$r['user_id']]['delivery'] ?? '') === 'per_list'), $released, $people, true);
        $emails = 0;
        $date = $local->format('j M Y');
        if ($combined !== []) {
            $id = $this->campaigns->create('digest', 'Your ' . $label . ' digest, ' . $date, null, [
                'subject' => 'Your ' . $label . ' digest from ' . $this->runtime->platformName(),
                'preheader' => 'What is new in what you follow.',
                'blocks' => [['type' => 'heading', 'text' => 'Your ' . $label . ' digest'] + EmailBlocks::make('heading'),
                    ['type' => 'text', 'text' => $this->words('digest_intro')] + EmailBlocks::make('text')],
                'status' => 'scheduled',
            ]);
            $this->deliver($id, array_map(fn(array $p): array => $this->copy($p, 'Your ' . $label . ' digest: ' . $this->headline($p['updates'][0]) . (count($p['updates']) > 1 ? ' and ' . (count($p['updates']) - 1) . ' more' : '')), $combined));
            $emails += count($combined);
        }
        // One email for each list: a campaign for each list, in the list's own sender and template when it has them (9A).
        $byList = [];
        foreach ($perList as $copy) $byList[$copy['list_id']][] = $copy;
        foreach ($byList as $listId => $copies) {
            $listName = $copies[0]['list_names'][0];
            $id = $this->campaigns->create('digest', $listName . ', ' . $label . ' digest, ' . $date, null, [
                'subject' => $listName . ': your ' . $label . ' digest', 'preheader' => 'What is new in ' . $listName . '.', 'list_ids' => [$listId],
                'blocks' => [['type' => 'heading', 'text' => $listName] + EmailBlocks::make('heading'),
                    ['type' => 'text', 'text' => $this->words('digest_intro')] + EmailBlocks::make('text')],
                'status' => 'scheduled',
            ]);
            $this->campaigns->update($id, $this->campaigns->listSender($listId));
            $this->deliver($id, array_map(fn(array $p): array => $this->copy($p, $listName . ': ' . $this->headline($p['updates'][0]) . (count($p['updates']) > 1 ? ' and ' . (count($p['updates']) - 1) . ' more' : '')), $copies));
            $emails += count($copies);
        }
        $now = $this->stamp($this->now());
        foreach (array_unique([...array_column($combined, 'user_id'), ...array_column($perList, 'user_id')]) as $userId) $this->updates->digestSent((int) $userId, $now);
        if ($emails > 0) $this->audit->record(null, 'mailing.digest_made', ['frequency' => $frequency, 'emails' => $emails]);

        return $emails;
    }

    /**
     * The reach rows grouped into copies: for each person (or each person and list), the updates they have not had,
     * released after they began following what brings each and, for a digest, after their last digest.
     *
     * @param array<array{update_id:int,user_id:int,email:string,first_name:string,list_id:int,list_name:string,list_kind:string,followed_at:string}> $rows
     * @param array<int,string> $released
     * @param array<int,array{delivery:string,last_digest_at:?string}>|null $people
     * @return list<array{user_id:int,email:string,first_name:string,list_id:int,updates:list<int>,why:array<int,string>,lists:list<int>,list_names:list<string>}>
     */
    private function gather(array $rows, array $released, ?array $people, bool $perList = false): array
    {
        $delivered = $this->updates->delivered(array_keys($released));
        $copies = [];
        $home = [];
        foreach ($rows as $row) {
            $update = $row['update_id'];
            $userId = $row['user_id'];
            $at = $released[$update] ?? null;
            if ($at === null || isset($delivered[$update][$userId])) continue;
            if (strtotime($row['followed_at']) > strtotime($at)) continue;
            $last = $people[$userId]['last_digest_at'] ?? null;
            if ($last !== null && strtotime($at) <= strtotime($last)) continue;
            // Each update reaches a person once: with a digest for each list, in the digest of the first list that brings
            // it (its course, then its categories, its tags, then the list it was posted to); the others are named in why.
            $list = $home[$userId][$update] ??= $row['list_id'];
            $key = $perList ? $userId . ':' . $list : (string) $userId;
            $copies[$key] ??= ['user_id' => $userId, 'email' => $row['email'], 'first_name' => $row['first_name'], 'list_id' => $list, 'updates' => [], 'why' => [], 'lists' => [], 'list_names' => []];
            if (!in_array($update, $copies[$key]['updates'], true)) $copies[$key]['updates'][] = $update;
            $copies[$key]['why'][$update][] = $row['list_name'];
            if ((!$perList || $row['list_id'] === $list) && !in_array($row['list_id'], $copies[$key]['lists'], true)) {
                $copies[$key]['lists'][] = $row['list_id'];
                $copies[$key]['list_names'][] = $row['list_name'];
            }
        }
        foreach ($copies as &$copy) {
            foreach ($copy['why'] as $update => $names) $copy['why'][$update] = 'Because you follow ' . self::andList(array_values(array_unique($names)));
        }
        unset($copy);

        return array_values($copies);
    }

    /**
     * @param array{user_id:int,email:string,first_name:string,list_id:int,updates:list<int>,why:array<int,string>,lists:list<int>,list_names:list<string>} $person
     * @return array{user_id:int,email:string,first_name:string,list_id:int,updates:list<int>,reasons:list<string>,content:array<string,mixed>}
     */
    private function copy(array $person, string $subject): array
    {
        return ['user_id' => $person['user_id'], 'email' => $person['email'], 'first_name' => $person['first_name'], 'list_id' => $person['list_id'], 'updates' => $person['updates'],
            'reasons' => $person['list_names'],
            'content' => ['updates' => $person['updates'], 'why' => $person['why'], 'lists' => $person['lists'], 'list_names' => $person['list_names'], 'subject' => mb_substr($subject, 0, 200)]];
    }

    /** @param list<array{user_id:int,email:string,first_name:string,list_id:int,updates:list<int>,reasons:list<string>,content:array<string,mixed>}> $copies */
    private function deliver(int $campaignId, array $copies): void
    {
        $this->campaigns->addDeliveries($campaignId, $copies);
        $ids = $this->campaigns->deliveryIds($campaignId);
        foreach ($copies as $copy) $this->updates->markDelivered($copy['updates'], $copy['user_id'], $ids[$copy['user_id']] ?? null);
    }

    /** The opening words ADMIN wrote on Automatic emails, or the starting ones. */
    private function words(string $key): string
    {
        return (string) ($this->automatic?->word($key) ?? AutomaticEmails::WORDS[$key]);
    }

    private function headline(int $updateId): string
    {
        return (string) ($this->updates->cards([$updateId])[$updateId]['headline'] ?? 'What is new in what you follow');
    }

    private function dueToday(string $frequency, DateTimeImmutable $local): bool
    {
        $rules = $this->settings->rules();

        return match ($frequency) {
            'daily' => true,
            'weekly' => (int) $local->format('N') === (int) $rules['digest_weekday'],
            'monthly' => (int) $local->format('j') === (int) $rules['digest_month_day'],
            default => false,
        };
    }

    /** The digests go at the start of the sending hours, or at midnight when email goes around the clock. */
    private function digestTimeReached(DateTimeImmutable $local): bool
    {
        [$hour, $minute] = $this->digestClock();

        return (int) $local->format('G') * 60 + (int) $local->format('i') >= $hour * 60 + $minute;
    }

    /** @return array{0:int,1:int} */
    private function digestClock(): array
    {
        $rules = $this->settings->rules();
        $from = (string) $rules['send_from'] === (string) $rules['send_until'] ? '00:00' : (string) $rules['send_from'];

        return [(int) substr($from, 0, 2), (int) substr($from, 3, 2)];
    }

    /** @param list<string> $names */
    private static function andList(array $names): string
    {
        $last = array_pop($names);

        return $names === [] ? (string) $last : implode(', ', $names) . ' and ' . $last;
    }

    private function now(): DateTimeImmutable
    {
        return DateTimeImmutable::createFromInterface($this->clock->now());
    }

    private function local(): DateTimeImmutable
    {
        return $this->now()->setTimezone(new DateTimeZone(date_default_timezone_get()));
    }

    private function stamp(DateTimeImmutable $at): string
    {
        return $at->setTimezone(new DateTimeZone('UTC'))->format('Y-m-d H:i:sP');
    }
}
