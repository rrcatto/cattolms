declare(strict_types=1);

namespace CattoLearning\Mailing;

use DateTimeImmutable;
use Symfony\Component\Clock\ClockInterface;

final class MailingOverview
{
    public const KINDS = ['news' => '', 'category' => 'category', 'course' => 'course', 'tag' => 'tag'];

    public function __construct(
        private readonly OverviewRepository $overview,
        private readonly CampaignRepository $campaigns,
        private readonly MailingRepository $lists,
        private readonly UpdateRepository $updates,
        private readonly UpdateDelivery $delivery,
        private readonly MailingSettings $settings,
        private readonly ClockInterface $clock,
        private readonly ?CattomailConnection $cattomail = null,
    ) {
    }

    /** @return array<string,mixed> everything the Overview shows */
    public function view(): array
    {
        $now = DateTimeImmutable::createFromInterface($this->clock->now());
        $since = $now->modify('-30 days')->format(DATE_ATOM);
        $names = [];
        $kinds = [];
        foreach ($this->lists->lists() as $list) {
            $names[$list['id']] = $list['name'] !== '' ? $list['name'] : 'A removed ' . (self::KINDS[$list['kind']] ?: 'list');
            $kinds[$list['id']] = $list['kind'];
        }
        $to = static fn(array $ids): string => $ids === [] ? 'Everyone with something waiting' : implode(', ', array_map(static fn(int $id): string => $names[$id] ?? 'a removed list', $ids));

        $held = $this->updates->held();
        $counts = $this->updates->reachCounts(array_map(static fn(array $u): int => (int) $u['id'], $held));
        $nobody = count(array_filter($counts, static fn(int $n): bool => $n === 0));
        $waitingNow = count($held);

        $attention = [];
        // Sending through catto-mail before its four steps are done (page 9): news waits until they are.
        if ($this->cattomail !== null && $this->settings->transport() === 'cattomail' && ($steps = $this->cattomail->steps())['done'] < 4) {
            $attention[] = ['badge' => 'catto-mail', 'title' => 'Sending is not set up yet: ' . $steps['done'] . ' of 4 steps done',
                'summary' => $steps['domain'] ? 'Send yourself a test through catto-mail to finish.' : 'News waits until catto-mail is connected and can send from the domain.', 'action' => 'Set it up', 'href' => '/mailing/cattomail#setup', 'icon' => 'action-open'];
        }
        foreach ($this->campaigns->waiting() as $campaign) {
            $kind = CampaignService::KIND_LABELS[(string) $campaign['kind']] ?? 'Message';
            $paused = (string) $campaign['status'] === 'paused';
            $attention[] = ['badge' => $kind, 'title' => (string) $campaign['name'],
                'summary' => $paused ? 'It paused itself: ' . ((string) ($campaign['status_note'] ?? '') ?: 'look at its figures before you resume it.') : 'It waits for your approval.',
                'action' => $paused ? 'Look into it' : 'Approve or cancel it', 'href' => '/mailing/messages/' . (int) $campaign['id'] . '#send', 'icon' => 'action-open'];
        }
        foreach ($this->overview->scheduled() as $message) {
            $attention[] = ['badge' => 'Message', 'title' => $message['name'],
                'summary' => 'Scheduled for ' . (new DateTimeImmutable($message['send_at']))->setTimezone($now->getTimezone())->format('l j F \a\t H:i') . ', to ' . $to($message['list_ids']) . '.',
                'action' => 'Open the message', 'href' => '/mailing/messages/' . $message['id'], 'icon' => 'action-open'];
        }
        if ($waitingNow - $nobody > 0) {
            $count = $waitingNow - $nobody;
            $attention[] = ['badge' => 'Digest', 'title' => $count === 1 ? '1 update is held until you release it' : $count . ' updates are held until you release them',
                'summary' => 'Nothing goes to anyone until you release it, now or at a time you choose.', 'action' => 'Release them', 'href' => '/mailing/digest#release', 'icon' => 'action-send'];
        }
        if ($nobody > 0) {
            $attention[] = ['badge' => 'Digest', 'title' => $nobody === 1 ? '1 update is held and nobody follows what it is about' : $nobody . ' updates are held and nobody follows what they are about',
                'summary' => 'Post them to News and Updates, or delete them.', 'action' => 'See them', 'href' => '/mailing/digest#nobody', 'icon' => 'action-view-list'];
        }

        $subscribers = $this->overview->subscribers($since);
        $byKind = $this->overview->listsByKind();
        $listCount = array_sum($byKind);
        $recent = $this->overview->recentlySent(5);
        $last = null;
        foreach ($recent as $row) if ($row['sent'] > 0) { $last = $row; break; }
        $bounces = $this->overview->bouncesSince($since);
        $limit = (float) $this->settings->rule('pause_bounce_percent');
        $percent = static fn(int $part, int $whole): string => $whole === 0 ? '' : rtrim(rtrim(number_format(100 * $part / $whole, 1, '.', ''), '0'), '.') . '%';
        $kindWords = [];
        foreach (['news' => ['news', 'news'], 'category' => ['category', 'categories'], 'course' => ['course', 'courses'], 'tag' => ['tag', 'tags']] as $kind => [$one, $many]) {
            if ($byKind[$kind] > 0) $kindWords[] = $byKind[$kind] . ' ' . ($byKind[$kind] === 1 ? $one : $many);
        }

        return [
            'attention' => $attention,
            'figures' => [
                ['label' => 'Subscribers', 'value' => number_format($subscribers['total']), 'note' => $subscribers['joined'] . ' joined in the past 30 days', 'href' => '/mailing/lists', 'icon' => 'figure-people'],
                ['label' => 'Lists', 'value' => (string) $listCount, 'note' => $kindWords === [] ? 'None with anyone on it yet' : implode(', ', $kindWords), 'href' => '/mailing/lists', 'icon' => 'figure-chart'],
                ['label' => 'Updates held', 'value' => (string) $waitingNow, 'note' => 'Until you release them', 'href' => '/mailing/digest#held', 'icon' => 'figure-awaiting'],
                ['label' => 'Last sent, opened', 'value' => $last === null ? 'None' : $percent($last['opened'], $last['sent']), 'note' => $last === null ? 'Nothing sent yet' : $last['name'], 'href' => $last === null ? '/mailing/messages' : '/mailing/messages/' . $last['id'], 'icon' => 'figure-completion'],
                ['label' => 'Bounces, 30 days', 'value' => $bounces['sent'] === 0 ? 'None' : $percent($bounces['bounced'], $bounces['sent']), 'note' => 'A sending pauses itself at ' . rtrim(rtrim(number_format($limit, 1, '.', ''), '0'), '.') . '%', 'href' => '/mailing/settings', 'icon' => 'figure-risk-medium'],
                ['label' => 'Never emailed', 'value' => (string) $this->campaigns->suppressionCount(''), 'note' => 'Hard bounces, complaints and addresses you added', 'href' => '/mailing/never-emailed', 'icon' => 'figure-cancelled'],
            ],
            'recent' => array_map(static fn(array $row): array => $row + ['to' => in_array($row['kind'], ['digest', 'updates'], true) && $row['list_ids'] === [] ? 'Everyone with an update for them' : $to($row['list_ids']),
                'kind_label' => CampaignService::KIND_LABELS[$row['kind']] ?? 'Message', 'opened_label' => $percent($row['opened'], $row['sent']), 'clicked_label' => $percent($row['clicked'], $row['sent'])], $recent),
            'digest' => ['hours' => $this->settings->digestSummary()['hours'], 'next' => $this->delivery->nextDigests(), 'held' => $waitingNow],
            'growing' => array_map(static fn(array $row): array => $row + ['name' => $names[$row['list_id']] ?? 'A removed list', 'kind' => self::KINDS[$kinds[$row['list_id']] ?? 'news']], $this->overview->growing($since, 5)),
        ];
    }
}
