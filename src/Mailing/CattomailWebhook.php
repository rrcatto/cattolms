declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Infrastructure\Persistence\TransactionManager;

class CattomailWebhook
{
    public function __construct(
        private readonly CampaignRepository $campaigns,
        private readonly MailingOutcomes $outcomes,
        private readonly TransactionManager $transactions,
    ) {
    }

    /** Keeps an event, once. False when it was already kept. */
    public function receive(string $eventId, string $type, string $body): bool
    {
        return $this->campaigns->recordTransportEvent($eventId, $type, $body);
    }

    /** Works through the events not yet processed. Returns how many were processed. */
    public function process(int $limit = 100): int
    {
        return (int) $this->transactions->run(function () use ($limit): int {
            $done = 0;
            foreach ($this->campaigns->unprocessedTransportEvents($limit) as $event) {
                $this->campaigns->transportEventProcessed((int) $event['id'], $this->apply((string) $event['event_type'], json_decode((string) $event['payload'], true) ?: []));
                $done++;
            }

            return $done;
        });
    }

    /** @param array<string,mixed> $event */
    private function apply(string $type, array $event): string
    {
        $data = (array) ($event['data'] ?? []);
        if (in_array($type, ['message.hard_bounced', 'message.complained'], true)) {
            $message = (array) ($data['message'] ?? []);
            $delivery = $this->campaigns->deliveryByToken((string) ($message['external_recipient_reference'] ?? ''));
            if ($delivery === null) return 'No copy here has that reference.';
            $detail = trim((string) (($data['event']['detail'] ?? null) ?? ($data['event']['reason'] ?? null) ?? ($data['event']['diagnostic'] ?? '')));
            $status = $type === 'message.hard_bounced' ? 'bounced' : 'complained';
            $this->outcomes->record($delivery, $status, $detail !== '' ? mb_substr($detail, 0, 400) : '', (string) ($message['id'] ?? ''));

            return 'Recorded: ' . ($status === 'bounced' ? 'a hard bounce' : 'a spam complaint') . '.';
        }
        if (in_array($type, ['send.completed', 'send.failed'], true)) {
            $job = (string) ($data['id'] ?? '');
            if ($job !== '') $this->campaigns->jobNeedsReading($job);

            return 'Its copies are read back on the next run.';
        }

        return 'Kept; nothing to do.';
    }
}
