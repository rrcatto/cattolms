        $forward = $person['forward'] ?? null;
        // A forwarded copy carries none of its sender's links.
        $token = $forward === null ? (string) ($person['token'] ?? '') : '';
        $track = $live && $token !== '';
        $base = $this->linkBase();
        $site = $this->siteUrl();
        $first = trim((string) ($person['first_name'] ?? ''));
        $name = $first !== '' ? $first : 'there';
        $blocks = EmailBlocks::normalise($campaign['blocks'] ?? []);
        $courseIds = array_values(array_unique(array_filter(array_map(static fn(array $b): int => $b['type'] === 'course' ? (int) $b['course_id'] : 0, $blocks))));
        $cards = $this->campaigns->courseCards($courseIds);
        $items = in_array((string) ($campaign['kind'] ?? ''), ['digest', 'updates'], true) ? $this->items((array) ($person['content'] ?? [])) : [];

        $html = '';
        $text = [];
        foreach ($blocks as $block) {
            [$blockHtml, $blockText] = $this->block($block, $name, $s, $cards);
            $html .= $blockHtml;
            if ($blockText !== '') $text[] = $blockText;
        }
        foreach ($items as $item) {
            [$itemHtml, $itemText] = $this->update($item, $s);
            $html .= $itemHtml;
            $text[] = $itemText;
        }
        if ($forward !== null) {
            $from = trim((string) ($forward['from'] ?? '')) ?: 'Someone';
            $note = trim((string) ($forward['note'] ?? ''));
            $intro = '<p style="margin:0 0 16px;padding:12px 14px;background:#f6f2ec;border-radius:' . max(0, $s['radius']) . 'px;">' . self::e($from . ' thought you would like this email from ' . $this->runtime->platformName() . '.')
                . ($note !== '' ? '<br><em>' . nl2br(self::e($note), false) . '</em>' : '') . '</p>';
            $html = $intro . $html . $this->button('Create your account', (string) $forward['register_url'], $s);
            array_unshift($text, $from . ' thought you would like this email from ' . $this->runtime->platformName() . '.' . ($note !== '' ? "\n" . $note : ''));
            $text[] = 'Create your account: ' . (string) $forward['register_url'];
        }
        if ((string) ($campaign['kind'] ?? '') === 'sleeping') {
            $keep = $token !== '' ? $base . '/m/k/' . $token : $site . '/account/subscriptions';
            $html .= $this->button('Yes, keep sending me news', $keep, $s);
            $text[] = 'Yes, keep sending me news: ' . $keep;
        }

        if ($track && (bool) $rules['track_clicks']) {
            $campaignId = (int) $campaign['id'];
            $html = (string) preg_replace_callback('/\bhref=(["\'])(https?:\/\/[^"\'\s>]+)\1/i', function (array $m) use ($campaignId, $token, $base): string {
                $url = html_entity_decode($m[2], ENT_QUOTES | ENT_HTML5, 'UTF-8');
                if (str_starts_with($url, $base . '/m/')) return $m[0];

                return 'href="' . self::e($base . '/m/c/' . $token . '/' . $this->campaigns->linkId($campaignId, $url)) . '"';
            }, $html);
        }

        $unsubscribe = $token !== '' ? $base . '/m/u/' . $token : $site . '/account/subscriptions';
