     */
    public function render(array $campaign, array $person, bool $live, ?array $template = null): array
    {
        $template ??= $this->templates?->forCampaign($campaign) ?? ['mode' => 'design', 'design' => TemplateDesign::DEFAULTS, 'html' => '', 'text_mode' => 'made', 'text_part' => ''];
        $s = self::style(TemplateDesign::read((array) ($template['design'] ?? [])));
