    public static function extension(string $mediaType): string
    {
        return match ($mediaType) { 'image/jpeg' => '.jpg', 'image/gif' => '.gif', default => '.png' };
    }

    /**
     * What a design draws with: its colours, the two font stacks, the sizes, the spacing and the corners.
     *
     * @param array<string,mixed> $design
     * @return array<string,mixed>
     */
    private static function style(array $design): array
    {
        $heading = TemplateDesign::font((string) $design['heading_font']);
        $body = TemplateDesign::font((string) $design['body_font']);
        $pad = $design['spacing'] === 'compact' ? 16 : 24;

        return $design['colours'] + [
            'design' => $design, 'heading_font' => $heading[1], 'body_font' => $body[1],
            'families' => array_values(array_unique(array_filter([$heading[2], $body[2]]))),
            'size' => (int) $design['text_size'], 'width' => (int) $design['width'], 'pad' => $pad,
            'radius' => $design['corners'] === 'rounded' ? 8 : 0,
            'button_radius' => match ((string) $design['button_shape']) { 'square' => 0, 'pill' => 999, default => 4 },
        ];
    }

    /**
