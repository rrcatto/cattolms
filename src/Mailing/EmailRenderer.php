        $webUrl = $token !== '' ? $base . '/m/v/' . $token : '';
        $forwardUrl = $token !== '' ? $base . '/m/f/' . $token : '';
        $reasons = array_values(array_filter(array_map('strval', (array) ($person['reasons'] ?? []))));
        $listName = trim((string) ($person['list_name'] ?? ($reasons[0] ?? 'News and Updates')));
        $listNames = array_values(array_filter(array_map('strval', (array) ($person['content']['list_names'] ?? []))));
        if (count($listNames) > 1) $listName = self::andList($listNames);
        $because = $forward !== null
            ? 'You get this email because ' . (trim((string) ($forward['from'] ?? '')) ?: 'someone') . ' forwarded it to you. You are not on any of our lists, and we will not email you again unless you ask.'
            : $this->because($reasons, (string) ($campaign['kind'] ?? ''));
        $ownerName = $this->owner?->value('trading_name') ?: $this->runtime->platformName();
