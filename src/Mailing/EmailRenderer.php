    public function sample(array $template, string $sample, string $firstName): array
    {
        $courses = array_slice($this->campaigns->publishedCourses(), 0, 2);
        $first = $courses[0]['id'] ?? 0;
        if ($sample === 'digest') {
            $site = $this->siteUrl();
            $items = [];
            foreach ($courses as $i => $course) {
                $items[] = ['headline' => $i === 0 ? 'New course: ' . (string) $course['title'] : 'A new lesson or section in ' . (string) $course['title'],
                    'body' => $i === 0 ? 'Published this week.' : 'Open the course to see what is new.', 'link' => $site . '/courses/' . (string) $course['slug'],
                    'button' => 'View the course', 'why' => 'Because you follow Bookkeeping'];
            }
            if ($items === []) $items[] = ['headline' => 'Our new courses are on their way', 'body' => 'This is where each update you release appears.', 'link' => $site . '/courses', 'button' => 'Find out more', 'why' => 'Because you follow News and Updates'];

            return $this->render(['id' => 0, 'kind' => 'digest', 'subject' => 'Your weekly digest from ' . $this->runtime->platformName(), 'preheader' => 'What is new in what you follow.',
                'blocks' => [['type' => 'heading', 'text' => 'Your weekly digest'] + EmailBlocks::make('heading'), ['type' => 'text', 'text' => "Hello [First name],\n\nHere is what is new in what you follow since your last digest."] + EmailBlocks::make('text')]],
                ['first_name' => $firstName, 'reasons' => ['Bookkeeping'], 'list_name' => 'Bookkeeping', 'content' => ['items' => $items]], false, $template);
        }

        return $this->render(['id' => 0, 'kind' => 'message', 'subject' => 'Our news, [First name]', 'preheader' => 'What is new on the site this month.', 'blocks' => array_values(array_filter([
            ['type' => 'heading', 'text' => 'Our news this month'] + EmailBlocks::make('heading'),
            ['type' => 'text', 'text' => "Hello [First name],\n\nThis is how your emails look in this template. The words, pictures and courses are the ones each message gives it."] + EmailBlocks::make('text'),
            $first > 0 ? ['type' => 'course', 'course_id' => $first] + EmailBlocks::make('course') : null,
            ['type' => 'button', 'label' => 'See every course', 'href' => $this->siteUrl() . '/courses'] + EmailBlocks::make('button'),
        ]))], ['first_name' => $firstName, 'reasons' => ['News and Updates'], 'list_name' => 'News and Updates'], false, $template);
    }

    /**
     * A copy's updates as they are drawn: those a sample gives, or the updates its content names, with why each came.
     *
     * @param array<string,mixed> $content
     * @return list<array{headline:string,body:string,link:string,button:string,why:string}>
     */
    private function items(array $content): array
    {
        if (isset($content['items']) && is_array($content['items'])) {
            return array_values(array_map(static fn(array $i): array => ['headline' => (string) ($i['headline'] ?? ''), 'body' => (string) ($i['body'] ?? ''), 'link' => (string) ($i['link'] ?? ''),
                'button' => (string) ($i['button'] ?? 'Find out more'), 'why' => (string) ($i['why'] ?? '')], array_filter($content['items'], 'is_array')));
        }
        $ids = array_values(array_map('intval', (array) ($content['updates'] ?? [])));
        $cards = $this->updates?->cards($ids) ?? [];
        $why = (array) ($content['why'] ?? []);
        $items = [];
        foreach ($ids as $id) if (isset($cards[$id])) $items[] = $cards[$id] + ['why' => (string) ($why[$id] ?? $why[(string) $id] ?? '')];

        return $items;
    }

