    /** @param array<string,string> $values */
    private function htmlFrame(string $html, array $values, bool $demo, string $pixel): string
    {
        $page = strtr($html, $values);
        // A demo site says so in every email (owner, 2026-10-18), whether or not the template has a place for it.
        if ($demo && !str_contains($html, '{demo_notice}')) {
            $notice = '<div style="padding:12px 16px;background:#fff4d6;font-family:Arial,Helvetica,sans-serif;font-size:13px;line-height:1.5;color:#2b2420;"><strong>' . $values['{demo_notice}'] . '</strong></div>';
            $page = preg_match('/<body\b[^>]*>/i', $page) === 1 ? (string) preg_replace('/(<body\b[^>]*>)/i', '$1' . $notice, $page, 1) : $notice . $page;
        }
        if ($pixel !== '') $page = stripos($page, '</body>') !== false ? (string) preg_replace('#</body>#i', $pixel . '</body>', $page, 1) : $page . $pixel;

        return $page;
    }

    /**
     * @param array<string,mixed> $block
     * @param array<string,mixed> $s
     * @param array<int,array<string,mixed>> $cards
     * @return array{0:string,1:string}
     */
    private function block(array $block, string $name, array $s, array $cards): array
    {
        $fill = static fn(string $text): string => str_replace(EmailBlocks::PLACEHOLDER, $name, $text);

        return match ((string) $block['type']) {
            'heading' => ['<h2 style="margin:0 0 16px;font-family:' . $s['heading_font'] . ';font-size:' . ($s['size'] + 8) . 'px;line-height:1.25;color:' . $s['headings'] . ';">' . self::e($fill((string) $block['text'])) . '</h2>', mb_strtoupper($fill((string) $block['text']))],
            'text' => str_contains((string) $block['text'], '<')
                ? [$this->rich($fill((string) $block['text']), $s), self::plain($fill((string) $block['text']))]
                : [$this->paragraphs($fill((string) $block['text']), $s), $fill((string) $block['text'])],
            'image' => $this->image($block, $s),
            'button' => [(string) $block['href'] === '' ? '' : $this->button($fill((string) $block['label']), (string) $block['href'], $s), (string) $block['href'] === '' ? '' : $fill((string) $block['label']) . ': ' . (string) $block['href']],
            'course' => isset($cards[(int) $block['course_id']]) ? $this->course($cards[(int) $block['course_id']], $s, '') : ['', ''],
            'divider' => ['<hr style="border:0;border-top:1px solid ' . self::LINE . ';margin:24px 0;">', '----'],
            'html' => [(string) $block['html'], self::plain((string) $block['html'])],
            default => ['', ''],
        };
    }

    /**
     * A text block written in the editor, its few allowed tags given the template's look inline, as email apps need.
     *
     * @param array<string,mixed> $s
     */
    private function rich(string $html, array $s): string
    {
        $html = EmailBlocks::richText($html);

        return strtr((string) preg_replace('#<a href=#', '<a style="color:' . $s['links'] . ';" href=', $html), [
            '<p>' => '<p style="margin:0 0 16px;">',
            '<ul>' => '<ul style="margin:0 0 16px;padding-left:24px;">',
            '<ol>' => '<ol style="margin:0 0 16px;padding-left:24px;">',
            '<li>' => '<li style="margin:0 0 6px;">',
        ]);
    }

    /** @param array<string,mixed> $s */
    private function paragraphs(string $text, array $s): string
    {
        $out = '';
        foreach (preg_split('/\n\s*\n/', trim($text)) ?: [] as $paragraph) {
            $escaped = nl2br(self::e(trim($paragraph)), false);
            $linked = (string) preg_replace_callback('#https?://[^\s<]+[^\s<.,;:!?)\]]#i', static fn(array $m): string => '<a href="' . $m[0] . '" style="color:' . $s['links'] . ';">' . $m[0] . '</a>', $escaped);
            $out .= '<p style="margin:0 0 16px;">' . $linked . '</p>';
        }

        return $out;
    }

    /**
     * @param array<string,mixed> $block
     * @param array<string,mixed> $s
     * @return array{0:string,1:string}
     */
    private function image(array $block, array $s): array
    {
        $asset = (string) $block['asset'] !== '' ? $this->campaigns->asset((string) $block['asset']) : null;
        if ($asset === null) return ['', ''];
        $width = min($s['width'] - 2 * $s['pad'], $asset['width']);
        $img = '<img src="' . self::e($this->linkBase() . '/m/i/' . $block['asset'] . self::extension($asset['media_type'])) . '" width="' . $width . '" alt="' . self::e((string) $block['alt']) . '" style="display:block;border:0;width:100%;max-width:' . $width . 'px;height:auto;">';
        $href = (string) $block['href'];

        return ['<p style="margin:0 0 16px;">' . ($href !== '' ? '<a href="' . self::e($href) . '">' . $img . '</a>' : $img) . '</p>', trim((string) $block['alt'] . ($href !== '' ? ': ' . $href : ''))];
    }

    /** @param array<string,mixed> $s */
    private function button(string $label, string $href, array $s): string
    {
        return '<table role="presentation" cellpadding="0" cellspacing="0" border="0" style="margin:0 0 16px;"><tr><td style="background:' . $s['button'] . ';border-radius:' . $s['button_radius'] . 'px;">'
            . '<a href="' . self::e($href) . '" style="display:inline-block;padding:12px 22px;font-family:' . $s['body_font'] . ';font-size:16px;font-weight:bold;line-height:1.2;color:' . $s['button_text'] . ';text-decoration:none;border-radius:' . $s['button_radius'] . 'px;">' . self::e($label) . '</a></td></tr></table>';
    }

    /**
     * @param array<string,mixed> $card
     * @param array<string,mixed> $s
     * @return array{0:string,1:string}
     */
    private function course(array $card, array $s, string $why): array
    {
        $url = $this->siteUrl() . '/courses/' . (string) $card['slug'];
        $summary = trim((string) ($card['summary'] !== '' ? $card['summary'] : ($card['subtitle'] ?? '')));
        $price = '';
        $priceText = '';
        if ($card['price_minor_units'] !== null) {
            $currency = (string) $card['currency_code'];
            $amount = Money::strictMinorUnits((int) $card['price_minor_units'], $currency)->format();
            $was = WasPrice::labels((int) $card['price_minor_units'], $card['was_price_minor_units'], $currency)['was_label'];
            $period = AccessPeriod::label((int) $card['access_period_seconds']);
            $price = '<p style="margin:8px 0 0;font-weight:bold;">' . self::e($amount) . ($was !== null ? ' <s style="font-weight:normal;color:' . self::MUTED . ';">' . self::e($was) . '</s>' : '') . ' <span style="font-weight:normal;color:' . self::MUTED . ';">for ' . self::e($period) . '</span></p>';
            $priceText = $amount . ($was !== null ? ' (was ' . $was . ')' : '') . ' for ' . $period;
        }

        return ['<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="margin:0 0 16px;border:1px solid ' . self::LINE . ';' . ($s['radius'] > 0 ? 'border-radius:' . $s['radius'] . 'px;' : '') . '"><tr><td style="padding:16px;font-family:' . $s['body_font'] . ';font-size:' . ($s['size'] - 1) . 'px;line-height:1.5;color:' . $s['text'] . ';">'
            . ($why !== '' ? '<p style="margin:0 0 6px;font-size:12px;color:' . self::MUTED . ';">' . self::e($why) . '</p>' : '')
            . '<a href="' . self::e($url) . '" style="font-family:' . $s['heading_font'] . ';font-size:18px;font-weight:bold;line-height:1.3;color:' . $s['links'] . ';text-decoration:none;">' . self::e((string) $card['title']) . '</a>'
            . ($summary !== '' ? '<p style="margin:8px 0 0;">' . self::e(mb_strlen($summary) > 280 ? mb_substr($summary, 0, 279) . '…' : $summary) . '</p>' : '')
            . $price
            . '<p style="margin:12px 0 0;"><a href="' . self::e($url) . '" style="color:' . $s['links'] . ';font-weight:bold;">View the course</a></p>'
            . '</td></tr></table>',
            trim(($why !== '' ? $why . "\n" : '') . (string) $card['title'] . "\n" . ($summary !== '' ? $summary . "\n" : '') . ($priceText !== '' ? $priceText . "\n" : '') . $url)];
    }

    /**
     * One update: why it came, its headline linked, its words and its button's link.
     *
     * @param array{headline:string,body:string,link:string,button:string,why:string} $item
     * @param array<string,mixed> $s
     * @return array{0:string,1:string}
     */
    private function update(array $item, array $s): array
    {
        $link = $item['link'];
        $headline = $link !== '' ? '<a href="' . self::e($link) . '" style="font-family:' . $s['heading_font'] . ';font-size:18px;font-weight:bold;line-height:1.3;color:' . $s['links'] . ';text-decoration:none;">' . self::e($item['headline']) . '</a>'
            : '<span style="font-family:' . $s['heading_font'] . ';font-size:18px;font-weight:bold;line-height:1.3;color:' . $s['headings'] . ';">' . self::e($item['headline']) . '</span>';

        return ['<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="margin:0 0 16px;border:1px solid ' . self::LINE . ';' . ($s['radius'] > 0 ? 'border-radius:' . $s['radius'] . 'px;' : '') . '"><tr><td style="padding:16px;font-family:' . $s['body_font'] . ';font-size:' . ($s['size'] - 1) . 'px;line-height:1.5;color:' . $s['text'] . ';">'
            . ($item['why'] !== '' ? '<p style="margin:0 0 6px;font-size:12px;color:' . self::MUTED . ';">' . self::e($item['why']) . '</p>' : '')
            . $headline
            . ($item['body'] !== '' ? '<p style="margin:8px 0 0;">' . nl2br(self::e($item['body'])) . '</p>' : '')
            . ($link !== '' ? '<p style="margin:12px 0 0;"><a href="' . self::e($link) . '" style="color:' . $s['links'] . ';font-weight:bold;">' . self::e($item['button']) . '</a></p>' : '')
            . '</td></tr></table>',
            trim(($item['why'] !== '' ? $item['why'] . "\n" : '') . $item['headline'] . "\n" . ($item['body'] !== '' ? $item['body'] . "\n" : '') . $link)];
    }

    /** @param list<string> $names */
    private static function andList(array $names): string
    {
        $last = array_pop($names);

        return $names === [] ? (string) $last : implode(', ', $names) . ' and ' . $last;
    }

    /** @param list<string> $reasons */
    private function because(array $reasons, string $kind): string
    {
        if ($kind === 'sleeping' || $reasons === [] || $reasons === ['News and Updates']) return 'You get this email because you asked for News and Updates.';
        $names = array_values(array_filter($reasons, static fn(string $r): bool => $r !== 'News and Updates'));
        $last = array_pop($names);

        return 'You get this email because you follow ' . ($names === [] ? $last : implode(', ', $names) . ' and ' . $last) . (in_array('News and Updates', $reasons, true) ? ' and asked for News and Updates' : '') . '.';
    }

    private function siteUrl(): string
    {
        return rtrim(Env::string('APP_URL'), '/');
    }

    private static function plain(string $html): string
    {
        $html = (string) preg_replace_callback('#<a\s[^>]*href=(["\'])([^"\']+)\1[^>]*>(.*?)</a>#is', static fn(array $m): string => trim(strip_tags($m[3])) . ' (' . $m[2] . ')', $html);
        $html = (string) preg_replace('#<(br|/p|/div|/h[1-6]|/li|/tr)\b[^>]*>#i', "\n", $html);
        $text = html_entity_decode(strip_tags($html), ENT_QUOTES | ENT_HTML5, 'UTF-8');

        return trim((string) preg_replace("/\n{3,}/", "\n\n", (string) preg_replace('/[ \t]+/', ' ', $text)));
    }

    private static function e(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE | ENT_HTML5, 'UTF-8');
    }
