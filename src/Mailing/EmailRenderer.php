            . ($demo ? '<tr><td style="padding:12px ' . $pad . 'px;background:#fff4d6;font-family:' . $s['body_font'] . ';font-size:13px;line-height:1.5;color:#2b2420;"><strong>' . self::e(SiteMode::EMAIL_NOTICE) . '</strong></td></tr>' : '')
