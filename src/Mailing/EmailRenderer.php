    /**
     * One person's copy.
     *
     * @param array<string,mixed> $campaign
     * @param array{token?:?string,first_name?:string,reasons?:list<string>,list_name?:string,list_kind?:string,content?:array<string,mixed>,forward?:array<string,string>} $person
