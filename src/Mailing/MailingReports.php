    /**
     * @param array<string,mixed> $query
     * @return array{key:string,label:string,from:string,to:string,from_at:string,to_before:string,days:int,unit:string}
     */
    public function period(array $query): array
    {
        $key = isset(MoneyRecords::PERIODS[(string) ($query['period'] ?? '')]) ? (string) $query['period'] : 'month';
        $zone = new DateTimeZone(date_default_timezone_get());
        $today = DateTimeImmutable::createFromInterface($this->clock->now())->setTimezone($zone)->setTime(0, 0);
        $first = $this->reports->firstHanded();
        [$from, $to] = match ($key) {
            'today' => [$today, $today],
            'week' => [$today->modify('-6 days'), $today],
            'ytd' => [$today->modify('first day of january this year'), $today],
            'all' => [is_string($first) ? min($today, (new DateTimeImmutable($first))->setTimezone($zone)->setTime(0, 0)) : $today, $today],
            'custom' => [self::date($query['from'] ?? '', $zone) ?? $today->modify('-1 month'), self::date($query['to'] ?? '', $zone) ?? $today],
            default => [$today->modify('-' . self::MONTHS[$key] . ' months')->modify('+1 day'), $today],
        };
        if ($to < $from) [$from, $to] = [$to, $from];
        $days = (int) $from->diff($to)->days + 1;
        $utc = new DateTimeZone('UTC');

        return ['key' => $key, 'label' => $key === 'custom' ? $from->format('j M Y') . ' to ' . $to->format('j M Y') : MoneyRecords::PERIODS[$key],
            'from' => $from->format('Y-m-d'), 'to' => $to->format('Y-m-d'), 'days' => $days,
            'from_at' => $from->setTimezone($utc)->format('Y-m-d H:i:sP'), 'to_before' => $to->modify('+1 day')->setTimezone($utc)->format('Y-m-d H:i:sP'),
            'unit' => $days === 1 ? 'hour' : ($days <= 31 ? 'day' : ($days <= 186 ? 'week' : 'month'))];
    }

    /**
     * The emails sent in each slice of the period, as the column chart draws them.
     *
     * @param array{from_at:string,to_before:string,unit:string,from:string,to:string} $period
     * @return array{top:string,columns:list<array{label:string,labelled:bool,share:int,title:string,href:string}>,unit:string}
     */
    private function columns(array $period): array
    {
        $zone = date_default_timezone_get();
        $unit = $period['unit'];
        $rows = [];
        foreach ($this->reports->slices($unit, $zone, $period['from_at'], $period['to_before']) as $row) $rows[(new DateTimeImmutable((string) $row['slice']))->format('Y-m-d H')] = (int) $row['sent'];
        $tz = new DateTimeZone($zone);
        $cursor = new DateTimeImmutable($period['from'], $tz);
        $end = (new DateTimeImmutable($period['to'], $tz))->modify('+1 day');
        $cursor = match ($unit) { 'week' => $cursor->modify('monday this week'), 'month' => $cursor->modify('first day of this month'), default => $cursor };
        $step = ['hour' => '+1 hour', 'day' => '+1 day', 'week' => '+1 week', 'month' => '+1 month'][$unit];
        $format = ['hour' => 'H:00', 'day' => 'j M', 'week' => 'j M', 'month' => 'M Y'][$unit];
        $slices = [];
        while ($cursor < $end && count($slices) < 400) {
            $slices[] = [$cursor, $rows[$cursor->format('Y-m-d H')] ?? 0];
            $cursor = $cursor->modify($step);
        }
        $top = max(1, ...array_map(static fn(array $s): int => $s[1], $slices ?: [[null, 0]]));
        $every = max(1, (int) ceil(count($slices) / 6));
        $columns = [];
        foreach ($slices as $i => [$at, $sent]) {
            $columns[] = ['label' => $at->format($format), 'labelled' => $i % $every === 0, 'share' => (int) round(100 * $sent / $top),
                'title' => ($unit === 'week' ? 'Week of ' : '') . $at->format($unit === 'hour' ? 'H:00' : 'j F Y') . ': ' . number_format($sent) . ' sent', 'href' => ''];
        }

        return ['top' => number_format($top), 'columns' => $columns, 'unit' => $unit];
    }

    private static function date(mixed $value, DateTimeZone $zone): ?DateTimeImmutable
    {
        $text = trim((string) $value);
        $date = DateTimeImmutable::createFromFormat('!Y-m-d', $text, $zone);

        return $date !== false && $date->format('Y-m-d') === $text ? $date : null;
    }

    private static function rate(int $part, int $whole): string
    {
        return $whole === 0 ? '' : rtrim(rtrim(number_format(100 * $part / $whole, 1, '.', ''), '0'), '.') . '%';
    }
