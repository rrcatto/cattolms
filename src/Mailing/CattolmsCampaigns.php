declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Support\Env;
use CattoPHP\Mailing\CampaignProject;
use CattoPHP\Mailing\DrawnCopy;
use CattoPHP\Mailing\SenderIdentity;
use CattoPHP\Mailing\SendingRules;

class CattolmsCampaigns implements CampaignProject
{
    /** @var array<int,array<string,mixed>> the campaign being sent, as cattolms reads it, for its copies' drawing */
    private array $current = [];

    public function __construct(
        private readonly CampaignRepository $campaigns,
        private readonly EmailRenderer $renderer,
        private readonly MailingSettings $settings,
        private readonly RuntimeSettings $runtime,
    ) {
    }

    public function audience(array $campaign): ?array
    {
        if ($campaign['kind'] !== 'message') return null;

        return array_map(static fn(array $person): array => ['account' => (string) $person['user_id'], 'email' => $person['email'], 'list_id' => $person['list_id'] > 0 ? $person['list_id'] : null,
            'reasons' => $person['reasons']], $this->campaigns->audience(array_values(array_map('intval', (array) $campaign['list_ids'])), array_values(array_map('intval', (array) ($campaign['exclude_list_ids'] ?? [])))));
    }

    public function sender(array $campaign): SenderIdentity
    {
        $campaign = $this->prepared($campaign, true);
        $mail = $this->runtime->mailConfiguration();

        return new SenderIdentity($this->settings->fromAddress((string) $mail['from_address']),
            trim((string) ($campaign['from_name'] ?? '')) !== '' ? (string) $campaign['from_name'] : $this->settings->fromName((string) $mail['from_name']),
            trim((string) ($campaign['reply_to'] ?? '')));
    }

    public function draw(array $campaign, array $copy): DrawnCopy
    {
        $campaign = $this->prepared($campaign, false);
        $reasons = array_values(array_map('strval', (array) ($copy['reasons'] ?? [])));
        $account = (string) ($copy['account'] ?? '');
        $drawn = $this->renderer->render($campaign, ['token' => (string) $copy['token'], 'first_name' => ctype_digit($account) ? $this->campaigns->firstName((int) $account) : '', 'reasons' => $reasons,
            'list_name' => $reasons[0] ?? 'News and Updates', 'content' => (array) ($copy['content'] ?? [])], true);

        return new DrawnCopy((string) $drawn['subject'], (string) $drawn['html'], (string) $drawn['text'], (string) $drawn['unsubscribe_url'], $reasons[0] ?? 'News and Updates');
    }

    public function drawForFriend(array $campaign, array $copy, string $friendName, string $note, string $token): DrawnCopy
    {
        $campaign = $this->prepared($campaign, true);
        $account = (string) ($copy['account'] ?? '');
        $from = ctype_digit($account) ? $this->campaigns->firstName((int) $account) : '';
        $drawn = $this->renderer->render($campaign, ['first_name' => $friendName !== '' ? explode(' ', $friendName)[0] : '', 'reasons' => [], 'list_name' => '', 'content' => (array) ($copy['content'] ?? []),
            'forward' => ['from' => $from !== '' ? $from : 'A friend', 'note' => $note, 'never_url' => $this->renderer->linkBase() . '/m/n/' . $token, 'register_url' => rtrim(Env::string('APP_URL'), '/') . '/register']], false);

        return new DrawnCopy((string) $drawn['subject'], (string) $drawn['html'], (string) $drawn['text'], '', '');
    }

    /**
     * A copy's web copy: the person's copy as it was sent (in the template it was sent in), its links their own, nothing
     * recorded (decision 12A).
     *
     * @param array<string,mixed> $campaign
     * @param array<string,mixed> $copy
     * @return array{subject:string,html:string,text:string,unsubscribe_url:string}
     */
    public function webCopy(array $campaign, array $copy): array
    {
        $campaign = $this->prepared($campaign, true);
        $reasons = array_values(array_map('strval', (array) ($copy['reasons'] ?? [])));
        $account = (string) ($copy['account'] ?? '');

        return $this->renderer->render($campaign, ['token' => (string) $copy['token'], 'first_name' => ctype_digit($account) ? $this->campaigns->firstName((int) $account) : '', 'reasons' => $reasons,
            'list_name' => $reasons[0] ?? 'News and Updates', 'content' => (array) ($copy['content'] ?? [])], false);
    }

    public function waitsForMore(array $campaign): bool
    {
        return $campaign['kind'] === 'welcome';
    }

    public function rules(): SendingRules
    {
        $rules = $this->settings->rules();

        return new SendingRules((int) $rules['hourly_limit'], (int) $rules['first_day_limit'], (float) $rules['pause_bounce_percent'], (float) $rules['pause_complaint_percent'],
            (int) $rules['judge_after'], (string) $rules['send_from'], (string) $rules['send_until'], (bool) $rules['track_opens'], (bool) $rules['track_clicks']);
    }

    /**
     * The campaign as cattolms reads it (its blocks and template), with its list's sender, reply-to and template where it
     * is written to one list alone and has none of its own. Read afresh when a batch starts (the sender is asked first),
     * then kept for that batch's copies.
     *
     * @param array<string,mixed> $campaign
     * @return array<string,mixed>
     */
    private function prepared(array $campaign, bool $fresh): array
    {
        $id = (int) $campaign['id'];
        if ($fresh || !isset($this->current[$id])) {
            $read = $this->campaigns->find($id) ?? $campaign;
            if (in_array($read['kind'], ['message', 'welcome'], true) && count((array) $read['list_ids']) === 1) {
                foreach ($this->campaigns->listSender((int) ((array) $read['list_ids'])[0]) as $field => $value) {
                    if (in_array($read[$field] ?? null, [null, '', 0], true)) $read[$field] = $value;
                }
            }
            $this->current = [$id => $read];
        }

        return $this->current[$id];
    }
}
