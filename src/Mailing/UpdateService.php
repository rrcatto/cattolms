declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use DateTimeImmutable;
use DateTimeZone;
use InvalidArgumentException;
use Symfony\Component\Clock\ClockInterface;

final class UpdateService
{
    /** How each recorded update came about, in words. */
    public const SOURCES = [
        'first_published' => 'Recorded when the course was published for the first time',
        'content_added' => 'Recorded when lessons or sections were added',
        'price_lowered' => 'Recorded when its price went down',
        'promotion' => 'Recorded when a promotion that covers it began',
        'landing_published' => 'Recorded when its landing page was published',
        'retired' => 'Recorded when the course was retired',
    ];

    public function __construct(
        private readonly UpdateRepository $updates,
        private readonly UpdateDelivery $delivery,
        private readonly UpdateRecorder $recorder,
        private readonly MailingRepository $lists,
        private readonly MailingSettings $settings,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
        private readonly ClockInterface $clock,
    ) {
    }

    /** @return array<string,mixed> everything the Digest page shows */
    public function view(): array
    {
        // Changes made a moment ago show at once, not a minute later.
        $this->recorder->run();
        $held = $this->updates->held();
        $counts = $this->updates->reachCounts(array_map(static fn(array $u): int => (int) $u['id'], $held));
        $zone = new DateTimeZone(date_default_timezone_get());
        $rows = [];
        foreach ($held as $update) {
            $id = (int) $update['id'];
            $rows[] = $update + [
                'reach' => $counts[$id] ?? 0,
                'source' => $update['origin'] === 'written' ? 'Written for ' . (string) $update['list_name'] : (self::SOURCES[(string) $update['event']] ?? 'Recorded'),
                'when' => (new DateTimeImmutable((string) $update['created_at']))->setTimezone($zone)->format('j M Y, H:i'),
                'merged' => (int) $update['change_count'] > 1 ? (int) $update['change_count'] . ' changes' : '',
                'release_label' => $update['release_at'] !== null ? 'Goes ' . (new DateTimeImmutable((string) $update['release_at']))->setTimezone($zone)->format('l j F \a\t H:i') : '',
                'posted' => $update['origin'] === 'recorded' && $update['list_id'] !== null ? 'Posted to ' . (string) $update['list_name'] . ' as well' : '',
            ];
        }
        $reached = array_values(array_filter($rows, static fn(array $u): bool => $u['reach'] > 0));
        $nobody = array_values(array_filter($rows, static fn(array $u): bool => $u['reach'] === 0));

        return [
            'held' => $reached,
            'nobody' => $nobody,
            'history' => array_map(static fn(array $u): array => $u + ['when' => (new DateTimeImmutable((string) ($u['released_at'] ?? $u['updated_at'])))->setTimezone($zone)->format('j M Y, H:i')], $this->updates->history(20)),
            'reach_total' => $this->reachTotal(array_map(static fn(array $u): int => (int) $u['id'], $reached)),
            'next' => $this->delivery->nextDigests(),
            'hours' => $this->settings->digestSummary(),
            'choices' => $this->preferenceCounts(),
            'for' => $this->forChoices(),
            'now_date' => (new DateTimeImmutable('now', $zone))->format('Y-m-d'),
        ];
    }

    /** @param array<string,mixed> $input for, headline, body, link_url */
    public function write(array $input, int $userId): int
    {
        return (int) $this->transactions->run(function () use ($input, $userId): int {
            [$listId, $name] = $this->listFor((string) ($input['for'] ?? ''));
            [$headline, $body, $link] = $this->words($input);
            $id = $this->updates->create('written', 'written', null, $listId, $headline, $body, $link, $userId);
            $this->audit->record($userId, 'mailing.update_written', ['update_id' => $id, 'list' => $name]);

            return $id;
        });
    }

    /** @param array<string,mixed> $input headline, body, link_url */
    public function reword(int $id, array $input, int $userId): void
    {
        $this->transactions->run(function () use ($id, $input, $userId): void {
            $this->held($id);
            [$headline, $body, $link] = $this->words($input);
            $this->updates->update($id, ['headline' => $headline, 'body' => $body, 'link_url' => $link], $userId);
            $this->audit->record($userId, 'mailing.update_reworded', ['update_id' => $id]);
        });
    }

    public function delete(int $id, int $userId): void
    {
        $this->transactions->run(function () use ($id, $userId): void {
            $this->held($id);
            $this->updates->update($id, ['status' => 'deleted', 'status_note' => 'Deleted before it was released.'], $userId);
            $this->audit->record($userId, 'mailing.update_deleted', ['update_id' => $id]);
        });
    }

    /** An update nobody follows goes to News and Updates' followers too (decision 4B). */
    public function postToNews(int $id, int $userId): void
    {
        $this->transactions->run(function () use ($id, $userId): void {
            $this->held($id);
            $this->updates->update($id, ['list_id' => $this->lists->listId('news', null, true)], $userId);
            $this->audit->record($userId, 'mailing.update_posted_to_news', ['update_id' => $id]);
        });
    }

    public function holdAgain(int $id, int $userId): void
    {
        $this->transactions->run(function () use ($id, $userId): void {
            $this->held($id);
            $this->updates->update($id, ['release_at' => null], $userId);
        });
    }

    /**
     * Releases the ticked updates now, or sets them to go at a date and time (round two 1A). Returns how many and when.
     *
     * @param list<int> $ids
     * @return array{count:int,now:bool,at:string,instant:int}
     */
    public function release(array $ids, string $when, string $date, string $time, int $userId): array
    {
        $ids = array_values(array_unique(array_filter(array_map('intval', $ids), static fn(int $id): bool => $id > 0)));
        if ($ids === []) throw new InvalidArgumentException('Tick the updates to release.');
        $zone = new DateTimeZone(date_default_timezone_get());
        $now = DateTimeImmutable::createFromInterface($this->clock->now());
        if ($when === 'later') {
            $at = DateTimeImmutable::createFromFormat('!Y-m-d H:i', trim($date) . ' ' . trim($time), $zone);
            if ($at === false || $at->format('Y-m-d H:i') !== trim($date) . ' ' . trim($time)) throw new InvalidArgumentException('Choose the day and the time it goes, such as 2026-10-30 and 09:00.');
            if ($at <= $now) throw new InvalidArgumentException('Choose a time from now on, or release them now.');
        } else {
            $at = $now;
        }
        $stamp = $at->setTimezone(new DateTimeZone('UTC'))->format('Y-m-d H:i:sP');
        $this->transactions->run(function () use ($ids, $stamp, $userId): void {
            foreach ($ids as $id) {
                $this->held($id);
                $this->updates->update($id, ['release_at' => $stamp], $userId);
            }
            $this->audit->record($userId, 'mailing.updates_set_to_release', ['update_ids' => $ids, 'at' => $stamp]);
        });
        $instant = 0;
        if ($when !== 'later') {
            $this->delivery->release();
            $instant = $this->delivery->instant();
        }

        return ['count' => count($ids), 'now' => $when !== 'later', 'at' => $at->setTimezone($zone)->format('l j F \a\t H:i'), 'instant' => $instant];
    }

    /** @return array<string,mixed> */
    private function held(int $id): array
    {
        $update = $this->updates->find($id, true);
        if ($update === null || $update['status'] !== 'held') throw new InvalidArgumentException('That update is no longer held, so it cannot be changed.');

        return $update;
    }

    /**
     * @param array<string,mixed> $input
     * @return array{0:string,1:string,2:string}
     */
    private function words(array $input): array
    {
        $headline = trim((string) preg_replace('/\s+/', ' ', (string) ($input['headline'] ?? '')));
        if ($headline === '') throw new InvalidArgumentException('Write the headline.');
        if (mb_strlen($headline) > 200) throw new InvalidArgumentException('Keep the headline under 200 characters.');
        $body = trim(str_replace("\r\n", "\n", (string) ($input['body'] ?? '')));
        if (mb_strlen($body) > 2000) throw new InvalidArgumentException('Keep the words under 2,000 characters.');
        $link = trim((string) ($input['link_url'] ?? ''));
        if ($link !== '' && (mb_strlen($link) > 500 || filter_var($link, FILTER_VALIDATE_URL) === false || preg_match('#^https?://#i', $link) !== 1)) {
            throw new InvalidArgumentException('Write the link as a full web address, starting with https://.');
        }

        return [$headline, $body, $link];
    }

    /** @return array{0:int,1:string} the list an update is written for, made when nobody has followed it yet */
    private function listFor(string $choice): array
    {
        if ($choice === 'news') return [$this->lists->listId('news', null, true), 'News and Updates'];
        if (preg_match('/^(own|category|course|tag):([1-9][0-9]{0,17})$/', $choice, $m) !== 1) throw new InvalidArgumentException('Choose who the update is for.');
        $id = (int) $m[2];
        if ($m[1] === 'own') {
            $list = $this->lists->ownList($id);
            if ($list === null || $list['closed_at'] !== null) throw new InvalidArgumentException('Choose who the update is for.');

            return [(int) $list['id'], (string) $list['name']];
        }
        $name = $this->lists->subjectName($m[1], $id);
        if ($name === null) throw new InvalidArgumentException('Choose who the update is for.');

        return [(int) $this->lists->listId($m[1], $id, true), $name];
    }

    /** @return list<array{group:string,options:list<array{value:string,label:string}>}> who an update can be written for */
    private function forChoices(): array
    {
        $own = $this->lists->ownLists(true);
        $groups = [['group' => 'Everyone who asked for news', 'options' => [['value' => 'news', 'label' => 'News and Updates']]]];
        if ($own !== []) $groups[] = ['group' => 'Your lists', 'options' => array_map(static fn(array $r): array => ['value' => 'own:' . $r['id'], 'label' => (string) $r['name']], $own)];
        foreach (['course' => 'Followers of a course', 'category' => 'Followers of a category', 'tag' => 'Followers of a tag'] as $kind => $label) {
            $rows = $this->updates->subjects($kind);
            if ($rows !== []) $groups[] = ['group' => $label, 'options' => array_map(static fn(array $r): array => ['value' => $kind . ':' . $r['id'], 'label' => (string) $r['name']], $rows)];
        }

        return $groups;
    }

    /** @param list<int> $ids */
    private function reachTotal(array $ids): int
    {
        return count(array_unique(array_column($this->updates->reach($ids), 'user_id')));
    }

    /** @return array<string,int> how the people who follow anything chose to hear: as they happen, daily, weekly or monthly */
    private function preferenceCounts(): array
    {
        return $this->updates->preferenceCounts();
    }
}
