    public function duplicate(int $id, int $userId): int
    {
        $template = $this->get($id);
        $copy = $this->templates->create(self::name('Copy of ' . $template['name']), $template['mode'], $template['design'], $template['html'], $template['text_mode'], $template['text_part'], false, false, $userId);
        $this->audit->record($userId, 'mailing.template_copied', ['template_id' => $copy, 'from' => $id]);

        return $copy;
    }

    /** Deletes a template that is the default for nothing; messages that chose it then use the default for messages. */
    public function delete(int $id, int $userId): void
    {
        $template = $this->get($id);
        if ($template['default_for_messages']) throw new InvalidArgumentException('It is the default for messages. Make another template the default for messages first.');
        if ($template['default_for_digest']) throw new InvalidArgumentException('It is the default for the digest. Make another template the default for the digest first.');
        $this->templates->delete($id);
        $this->audit->record($userId, 'mailing.template_deleted', ['template_id' => $id, 'name' => $template['name']]);
    }

    /** Makes "Standard" when there is no template yet, from what Sending settings held before templates existed. */
    public function ensureStandard(): void
    {
        if ($this->templates->count() > 0) return;
        $design = TemplateDesign::DEFAULTS;
        $accent = (string) $this->settings->rule('accent_colour');
        if (preg_match('/^#[0-9a-f]{6}$/', strtolower($accent)) === 1) {
            foreach (['header', 'links', 'button'] as $key) $design['colours'][$key] = strtolower($accent);
        }
        $design['logo'] = $this->settings->logo();
        $this->transactions->run(function () use ($design): void {
            if ($this->templates->count() === 0) $this->templates->create('Standard', 'design', $design, '', 'made', '', true, true, null);
        });
    }

    private static function name(string $name): string
    {
        $name = trim($name);
        if ($name === '') throw new InvalidArgumentException('Give the template a name you will recognise, such as "Newsletter".');
        if (mb_strlen($name) > 120) throw new InvalidArgumentException('Keep the name under 120 characters.');

        return $name;
    }

    private static function assertHtml(string $html): void
    {
        if (trim($html) === '') throw new InvalidArgumentException('Write the template\'s HTML, with {content} where the message goes.');
        if (mb_strlen($html) > self::HTML_LIMIT) throw new InvalidArgumentException('Keep the HTML under 200,000 characters.');
        $missing = array_values(array_filter(self::REQUIRED, static fn(string $placeholder): bool => !str_contains($html, $placeholder)));
        if ($missing !== []) throw new InvalidArgumentException('The HTML must hold ' . implode(', ', $missing) . ': every news email carries the message, its unsubscribe link and your business\'s name and address.');
        if (preg_match('/<script\b/i', $html) === 1) throw new InvalidArgumentException('Take out the script: email apps do not run scripts, and some treat an email that has one as spam.');
    }

    private static function assertText(string $text): void
    {
        if (!str_contains($text, '{content}') || !str_contains($text, '{unsubscribe_link}')) {
            throw new InvalidArgumentException('Your own plain-text copy must hold {content} and {unsubscribe_link}.');
        }
        if (mb_strlen($text) > 20000) throw new InvalidArgumentException('Keep the plain-text copy under 20,000 characters.');
    }
