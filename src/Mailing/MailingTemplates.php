        return $this->templates->find($id) ?? throw new InvalidArgumentException('That template could not be found.');
    }

    /**
     * The template an email is drawn in: the one its message chose, else the default for its kind.
     *
     * @param array<string,mixed> $campaign
     * @return array<string,mixed>
     */
    public function forCampaign(array $campaign): array
    {
        $chosen = (int) ($campaign['template_id'] ?? 0);
        $template = $chosen > 0 ? $this->templates->find($chosen) : null;

        // Updates, whether in a digest or as they occur, are drawn in the template for digests.
        return $template ?? $this->defaultFor(in_array((string) ($campaign['kind'] ?? 'message'), ['digest', 'updates'], true) ? 'digest' : 'messages');
    }

    /** @return array<string,mixed> */
    public function defaultFor(string $kind): array
    {
        $this->ensureStandard();

        return $this->templates->defaultFor($kind) ?? $this->templates->defaultFor($kind === 'digest' ? 'messages' : 'digest') ?? $this->templates->all()[0];
    }

    /**
     * Gives a template a sample's look: its colours, fonts, sizes and shapes. Its logo, header picture, footer words and
     * social links stay as they are.
     */
    public function applySample(int $id, string $sample, int $userId): void
    {
        $look = TemplateDesign::sample($sample) ?? throw new InvalidArgumentException('Choose one of the sample designs.');
        $this->transactions->run(function () use ($id, $look, $sample, $userId): void {
            $template = $this->get($id);
            $design = $look;
            foreach (['logo', 'header_picture', 'footer_words', 'social', 'logo_size'] as $kept) $design[$kept] = $template['design'][$kept] ?? TemplateDesign::DEFAULTS[$kept];
            $this->templates->update($id, (string) $template['name'], 'design', $design, (string) $template['html'], (string) $template['text_mode'], (string) $template['text_part'], $userId);
            $this->audit->record($userId, 'mailing.template_sample_applied', ['template_id' => $id, 'sample' => $sample]);
        });
    }

    /**
     * A new designed template: a sample design's look (owner, 2026-10-28), keeping the default's logo, or a copy of the
     * default for messages. Without a name, a sample's own name.
     */
    public function create(string $name, int $userId, string $sample = ''): int
    {
        $from = $this->defaultFor('messages');
        $design = TemplateDesign::sample($sample);
        if ($design !== null) {
            $design['logo'] = (string) ($from['design']['logo'] ?? '');
            if (trim($name) === '') $name = TemplateDesign::SAMPLES[$sample]['name'];
        }
        $name = self::name($name);
        $id = $this->templates->create($name, 'design', $design ?? $from['design'], '', 'made', '', false, false, $userId);
        $this->audit->record($userId, 'mailing.template_made', ['template_id' => $id, 'sample' => $design !== null ? $sample : '']);

        return $id;
    }

    /**
     * Saves a template from its form: the name, how it is made, the design or the HTML, and the plain-text copy.
     *
     * @param array<string,mixed> $input
     */
    public function save(int $id, array $input, int $userId): void
    {
        $this->transactions->run(function () use ($id, $input, $userId): void {
            $template = $this->templates->find($id, true) ?? throw new InvalidArgumentException('That template could not be found.');
            $mode = (string) ($input['mode'] ?? $template['mode']);
            if (!in_array($mode, ['design', 'html'], true)) throw new InvalidArgumentException('Choose how the template is made.');
            $design = $mode === 'design' ? TemplateDesign::checked(is_array($input['design'] ?? null) ? $input['design'] : [], $template['design']) : $template['design'];
            $html = str_replace("\r\n", "\n", (string) ($input['html'] ?? $template['html']));
            if ($mode === 'html') self::assertHtml($html);
            $textMode = (string) ($input['text_mode'] ?? $template['text_mode']);
            if (!in_array($textMode, ['made', 'own'], true)) throw new InvalidArgumentException('Choose how the plain-text copy is made.');
            $text = str_replace("\r\n", "\n", (string) ($input['text_part'] ?? $template['text_part']));
            if ($textMode === 'own') self::assertText($text);
            $this->templates->update($id, self::name((string) ($input['name'] ?? $template['name'])), $mode, $design, $html, $textMode, $text, $userId);
            $this->audit->record($userId, 'mailing.template_saved', ['template_id' => $id, 'mode' => $mode]);
        });
    }

    /** Makes it the default for messages or for the digest. */
    public function makeDefault(int $id, string $kind, int $userId): void
    {
        if (!in_array($kind, ['messages', 'digest'], true)) throw new InvalidArgumentException('Choose what it is the default for.');
        $this->get($id);
        $this->transactions->run(fn() => $this->templates->makeDefault($id, $kind, $userId));
        $this->audit->record($userId, 'mailing.template_default', ['template_id' => $id, 'for' => $kind]);
    }

