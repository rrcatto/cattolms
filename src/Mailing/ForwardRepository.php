declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Infrastructure\Persistence\Database;

final class ForwardRepository
{
    public function __construct(private readonly Database $db)
    {
    }

    public function forwardedTo(int $deliveryId, string $email): bool
    {
        return $this->db->fetchOne('SELECT 1 FROM mailing_forwards WHERE delivery_id = :d AND to_email = :e', ['d' => $deliveryId, 'e' => $email]) !== false;
    }

    public function countForCopy(int $deliveryId): int
    {
        return (int) $this->db->fetchOne('SELECT COUNT(*) FROM mailing_forwards WHERE delivery_id = :d', ['d' => $deliveryId]);
    }

    /** How many a person forwarded in the past day. */
    public function countForPersonToday(int $userId): int
    {
        return (int) $this->db->fetchOne("SELECT COUNT(*) FROM mailing_forwards WHERE user_id = :u AND created_at > NOW() - INTERVAL '1 day'", ['u' => $userId]);
    }

    public function create(int $deliveryId, int $userId, string $email, string $name, string $note, string $token): void
    {
        $this->db->executeStatement('INSERT INTO mailing_forwards (delivery_id, user_id, to_email, to_name, note, token) VALUES (:d, :u, :e, :n, :note, :t)',
            ['d' => $deliveryId, 'u' => $userId, 'e' => $email, 'n' => $name, 'note' => $note, 't' => $token]);
    }

    /** The friend's address a "Never email me" token names, or null. */
    public function emailByToken(string $token): ?string
    {
        $email = $this->db->fetchOne('SELECT to_email FROM mailing_forwards WHERE token = :t', ['t' => $token]);

        return is_string($email) ? $email : null;
    }

    public function countForCampaign(int $campaignId): int
    {
        return (int) $this->db->fetchOne('SELECT COUNT(*) FROM mailing_forwards f JOIN mailing_deliveries d ON d.id = f.delivery_id WHERE d.campaign_id = :c', ['c' => $campaignId]);
    }
}
