declare(strict_types=1);

namespace CattoLearning\Mailing;

use InvalidArgumentException;

class MailingAssets
{
    public const MAX_BYTES = 5 * 1024 * 1024;
    public const WIDTH = 1200;

    public function __construct(private readonly CampaignRepository $campaigns)
    {
    }

    /** Stores a picture and returns its name (SHA-256). */
    public function store(string $bytes, ?int $userId): string
    {
        if ($bytes === '') throw new InvalidArgumentException('No picture was received. Choose a PNG, JPEG or GIF file and try again.');
        if (strlen($bytes) > self::MAX_BYTES) throw new InvalidArgumentException('The picture is larger than 5 MB. Choose a smaller one.');
        $info = @getimagesizefromstring($bytes);
        $type = is_array($info) ? $info['mime'] : '';
        if (!in_array($type, ['image/png', 'image/jpeg', 'image/gif'], true)) throw new InvalidArgumentException('Email apps show only PNG, JPEG and GIF pictures. Choose one of those.');
        [$width, $height] = [(int) $info[0], (int) $info[1]];
        if ($width < 1 || $height < 1) throw new InvalidArgumentException('The picture could not be read.');
        if ($width > self::WIDTH && $type !== 'image/gif' && function_exists('imagecreatefromstring')) {
            $source = @imagecreatefromstring($bytes);
            if ($source !== false) {
                $newHeight = (int) max(1, round($height * self::WIDTH / $width));
                $scaled = imagecreatetruecolor(self::WIDTH, $newHeight);
                if ($type === 'image/png') {
                    imagealphablending($scaled, false);
                    imagesavealpha($scaled, true);
                }
                imagecopyresampled($scaled, $source, 0, 0, 0, 0, self::WIDTH, $newHeight, $width, $height);
                ob_start();
                $type === 'image/png' ? imagepng($scaled, null, 9) : imagejpeg($scaled, null, 85);
                $bytes = (string) ob_get_clean();
                [$width, $height] = [self::WIDTH, $newHeight];
            }
        }
        $sha = hash('sha256', $bytes);
        $this->campaigns->saveAsset($sha, $type, $bytes, $width, $height, $userId);

        return $sha;
    }
}
