declare(strict_types=1);

namespace CattoLearning\Mailing;

final class CattomailSignature
{
    public const TOLERANCE = 300;

    /** @param list<string> $secrets */
    public static function valid(string $header, string $body, array $secrets, int $now): bool
    {
        $time = null;
        $signatures = [];
        foreach (explode(',', $header) as $part) {
            [$key, $value] = array_pad(explode('=', trim($part), 2), 2, '');
            if ($key === 't' && preg_match('/^\d+$/', $value) === 1) $time = (int) $value;
            if ($key === 'v1' && preg_match('/^[0-9a-f]{64}$/', $value) === 1) $signatures[] = $value;
        }
        if ($time === null || $signatures === [] || abs($now - $time) > self::TOLERANCE) return false;
        foreach (array_filter($secrets, static fn(string $s): bool => $s !== '') as $secret) {
            $expected = hash_hmac('sha256', $time . '.' . $body, $secret);
            foreach ($signatures as $signature) if (hash_equals($expected, $signature)) return true;
        }

        return false;
    }
}
