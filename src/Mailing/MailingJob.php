declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Infrastructure\Persistence\OptionRepository;
use DateTimeImmutable;
use DateTimeZone;
use Symfony\Component\Clock\ClockInterface;

class MailingJob
{
    private const SLEEPING_LAST = 'mailing.sleeping_last_day';

    public function __construct(
        private readonly CattomailWebhook $webhook,
        private readonly UpdateRecorder $recorder,
        private readonly UpdateDelivery $delivery,
        private readonly MailingSender $sender,
        private readonly SleepingAddresses $sleeping,
        private readonly OptionRepository $options,
        private readonly ClockInterface $clock,
        private readonly ?CattomailConnection $cattomail = null,
    ) {
    }

    public function run(): string
    {
        $events = $this->webhook->process();
        // While catto-mail cannot send from the domain yet, ask it again every five minutes (page 9, step 3).
        $asked = $this->cattomail?->recheckIfWaiting() ?? false;
        $recorded = $this->recorder->run();
        $updates = $this->delivery->run();
        $sent = $this->sender->run();
        $words = [$sent['handed'] . ' email' . ($sent['handed'] === 1 ? '' : 's') . ' sent'];
        if ($sent['started'] > 0) $words[] = $sent['started'] . ' campaign' . ($sent['started'] === 1 ? '' : 's') . ' started';
        if ($sent['paused'] > 0) $words[] = $sent['paused'] . ' paused by itself';
        if ($sent['resolved'] > 0) $words[] = $sent['resolved'] . ' outcome' . ($sent['resolved'] === 1 ? '' : 's') . ' read back';
        if ($events > 0) $words[] = $events . ' catto-mail event' . ($events === 1 ? '' : 's') . ' processed';
        if ($asked) $words[] = 'catto-mail asked whether the sending domain is ready';
        if ($recorded > 0) $words[] = $recorded . ' course change' . ($recorded === 1 ? '' : 's') . ' recorded as held updates';
        if ($updates['released'] > 0) $words[] = $updates['released'] . ' update' . ($updates['released'] === 1 ? '' : 's') . ' released';
        if ($updates['closed'] > 0) $words[] = $updates['closed'] . ' update' . ($updates['closed'] === 1 ? '' : 's') . ' closed because nobody followed ' . ($updates['closed'] === 1 ? 'it' : 'them');
        if ($updates['instant'] > 0) $words[] = $updates['instant'] . ' update email' . ($updates['instant'] === 1 ? '' : 's') . ' made';
        if ($updates['digests'] > 0) $words[] = $updates['digests'] . ' digest' . ($updates['digests'] === 1 ? '' : 's') . ' made';
        $local = DateTimeImmutable::createFromInterface($this->clock->now())->setTimezone(new DateTimeZone(date_default_timezone_get()));
        if ((int) $local->format('G') >= 3 && $this->options->find(self::SLEEPING_LAST) !== $local->format('Y-m-d')) {
            $this->options->set(self::SLEEPING_LAST, $local->format('Y-m-d'));
            $asked = $this->sleeping->run();
            $words[] = $asked['asked'] . ' sleeping address' . ($asked['asked'] === 1 ? '' : 'es') . ' asked and ' . $asked['stopped'] . ' stopped';
        }

        return ucfirst(implode(', ', $words)) . '.' . ($sent['notes'] !== [] ? ' ' . implode(' ', $sent['notes']) : '');
    }
}
