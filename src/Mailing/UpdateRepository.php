    public function subjects(string $kind): array
    {
        $sql = match ($kind) {
            'course' => "SELECT id, title AS name FROM courses WHERE status = 'published' ORDER BY lower(title)",
            'category' => 'SELECT id, name FROM course_categories ORDER BY lower(name)',
            default => 'SELECT id, name FROM tags ORDER BY lower(name)',
        };

        return array_map(static fn(array $r): array => ['id' => (int) $r['id'], 'name' => (string) $r['name']], $this->db->fetchAllAssociative($sql));
    }

    /** @return array<string,int> how the people who follow anything chose to hear: as they happen, daily, weekly or monthly */
    public function preferenceCounts(): array
    {
        $counts = ['instant' => 0, 'daily' => 0, 'weekly' => 0, 'monthly' => 0];
        foreach ($this->db->fetchAllAssociative(
            "SELECT CASE WHEN p.delivery = 'instant' THEN 'instant' ELSE COALESCE(p.frequency, 'weekly') END AS choice, COUNT(*) AS people
             FROM (SELECT DISTINCT s.user_id FROM mailing_subscriptions s JOIN users u ON u.id = s.user_id AND u.status = 'active' WHERE s.status = 'subscribed') f
             LEFT JOIN mailing_preferences p ON p.user_id = f.user_id GROUP BY 1"
        ) as $row) $counts[(string) $row['choice']] = (int) $row['people'];

        return $counts;
    }

