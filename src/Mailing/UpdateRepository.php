    public function create(string $origin, string $event, ?int $courseId, ?int $listId, string $headline, string $body, string $link, ?int $userId): int
    {
        return (int) $this->db->fetchOne(
            'INSERT INTO mailing_updates (origin, event, course_id, list_id, headline, body, link_url, created_by_user_id, updated_by_user_id)
             VALUES (:origin, :event, :course, :list, :headline, :body, :link, :user, :user) RETURNING id',
            ['origin' => $origin, 'event' => $event, 'course' => $courseId, 'list' => $listId, 'headline' => mb_substr($headline, 0, 200), 'body' => mb_substr($body, 0, 2000),
