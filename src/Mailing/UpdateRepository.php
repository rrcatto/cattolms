    }

    /** @param array<string,mixed> $fields headline, body, link_url, list_id, change_count, status, release_at, released_at, status_note */
    public function update(int $id, array $fields, ?int $userId): void
    {
        $sets = [];
        $params = ['id' => $id, 'user' => $userId];
        foreach ($fields as $column => $value) {
            if (!in_array($column, ['headline', 'body', 'link_url', 'list_id', 'change_count', 'status', 'release_at', 'released_at', 'status_note'], true)) continue;
            $sets[] = $column . ' = :' . $column;
            $params[$column] = $value;
        }
        if ($sets === []) return;
        $this->db->executeStatement('UPDATE mailing_updates SET ' . implode(', ', $sets) . ', updated_by_user_id = COALESCE(:user, updated_by_user_id), updated_at = NOW() WHERE id = :id', $params);
    }

    /** @return list<int> held updates whose release time has come */
    public function dueForRelease(string $now): array
    {
        return array_map('intval', $this->db->fetchFirstColumn("SELECT id FROM mailing_updates WHERE status = 'held' AND release_at IS NOT NULL AND release_at <= :now ORDER BY release_at, id FOR UPDATE SKIP LOCKED", ['now' => $now]));
    }

    /**
     * Everyone an update reaches now, one row per person and list that brings them, with the time they last changed that
     * follow (a follow begun after an update was released does not bring it to them).
     *
     * @param list<int> $updateIds
     * @return list<array{update_id:int,user_id:int,email:string,first_name:string,list_id:int,list_name:string,list_kind:string,followed_at:string}>
     */
    public function reach(array $updateIds): array
    {
        if ($updateIds === []) return [];
        $rows = $this->db->fetchAllAssociative(
            "WITH RECURSIVE picked AS (
                 SELECT id, course_id, list_id FROM mailing_updates WHERE id = ANY(CAST(:ids AS BIGINT[]))
             ), chain AS (
                 SELECT p.id AS update_id, cat.id AS category_id, cat.parent_id FROM picked p JOIN courses c ON c.id = p.course_id JOIN course_categories cat ON cat.id = c.category_id
                 UNION ALL
                 SELECT chain.update_id, parent.id, parent.parent_id FROM chain JOIN course_categories parent ON parent.id = chain.parent_id
             ), lists AS (
                 SELECT p.id AS update_id, l.id AS list_id, 0 AS sort FROM picked p JOIN mailing_lists l ON l.kind = 'course' AND l.subject_id = p.course_id
                 UNION SELECT chain.update_id, l.id, 1 FROM chain JOIN mailing_lists l ON l.kind = 'category' AND l.subject_id = chain.category_id
                 UNION SELECT p.id, l.id, 2 FROM picked p JOIN course_tags ct ON ct.course_id = p.course_id JOIN mailing_lists l ON l.kind = 'tag' AND l.subject_id = ct.tag_id
                 UNION SELECT p.id, p.list_id, 3 FROM picked p WHERE p.list_id IS NOT NULL
             )
             SELECT lists.update_id, s.user_id, e.email, COALESCE(u.first_name, '') AS first_name, l.id AS list_id, l.kind AS list_kind, s.changed_at AS followed_at,
                    CASE l.kind WHEN 'news' THEN 'News and Updates' WHEN 'own' THEN l.name ELSE COALESCE(cat.name, co.title, t.name, '') END AS list_name
             FROM lists
             JOIN mailing_lists l ON l.id = lists.list_id AND l.closed_at IS NULL
             JOIN mailing_subscriptions s ON s.list_id = l.id AND s.status = 'subscribed'
             JOIN users u ON u.id = s.user_id AND u.status = 'active'
             JOIN user_emails e ON e.user_id = u.id AND e.is_primary
             LEFT JOIN course_categories cat ON l.kind = 'category' AND cat.id = l.subject_id
             LEFT JOIN courses co ON l.kind = 'course' AND co.id = l.subject_id
             LEFT JOIN tags t ON l.kind = 'tag' AND t.id = l.subject_id
             WHERE NOT EXISTS (SELECT 1 FROM mailing_suppressions x WHERE x.email = LOWER(e.email))
             ORDER BY s.user_id, lists.update_id, lists.sort, l.id",
            ['ids' => '{' . implode(',', array_map('intval', $updateIds)) . '}']
        );

        return array_map(static fn(array $r): array => ['update_id' => (int) $r['update_id'], 'user_id' => (int) $r['user_id'], 'email' => (string) $r['email'],
            'first_name' => (string) $r['first_name'], 'list_id' => (int) $r['list_id'], 'list_name' => (string) $r['list_name'], 'list_kind' => (string) $r['list_kind'],
            'followed_at' => (string) $r['followed_at']], $rows);
    }

    /**
     * @param list<int> $updateIds
     * @return array<int,int> how many people each update reaches now
     */
    public function reachCounts(array $updateIds): array
    {
        $counts = array_fill_keys($updateIds, 0);
        $seen = [];
        foreach ($this->reach($updateIds) as $row) {
            if (isset($seen[$row['update_id']][$row['user_id']])) continue;
            $seen[$row['update_id']][$row['user_id']] = true;
            $counts[$row['update_id']]++;
        }

        return $counts;
    }

    /** @return array<int,string> released updates (id => when) released after a moment, oldest first */
    public function releasedSince(string $since): array
    {
        $out = [];
        foreach ($this->db->fetchAllAssociative("SELECT id, released_at FROM mailing_updates WHERE status = 'released' AND released_at > :since ORDER BY released_at, id", ['since' => $since]) as $row) {
            $out[(int) $row['id']] = (string) $row['released_at'];
        }

        return $out;
    }

