    /**
     * People who chose a digest (or have not chosen, so get one weekly) at a frequency, with when their last digest went.
     *
     * @param list<int> $userIds
     * @return array<int,array{delivery:string,last_digest_at:?string}>
     */
    public function digestPeople(string $frequency, array $userIds): array
    {
        if ($userIds === []) return [];
        $chosen = [];
        foreach ($this->db->fetchAllAssociative('SELECT user_id, delivery, frequency, last_digest_at FROM mailing_preferences WHERE user_id = ANY(CAST(:ids AS BIGINT[]))',
            ['ids' => '{' . implode(',', array_map('intval', $userIds)) . '}']) as $row) $chosen[(int) $row['user_id']] = $row;
        $out = [];
        foreach ($userIds as $userId) {
            $row = $chosen[$userId] ?? ['delivery' => 'combined', 'frequency' => 'weekly', 'last_digest_at' => null];
            if ((string) $row['delivery'] === 'instant' || (string) $row['frequency'] !== $frequency) continue;
            $out[$userId] = ['delivery' => (string) $row['delivery'], 'last_digest_at' => $row['last_digest_at'] === null ? null : (string) $row['last_digest_at']];
        }

        return $out;
    }

