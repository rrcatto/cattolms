        return array_map(static fn(array $r): array => ['promotion_id' => (int) $r['promotion_id'], 'course_id' => (int) $r['course_id'], 'name' => (string) $r['name'],
            'ends_at' => $r['ends_at'] === null ? null : (string) $r['ends_at']], $this->db->fetchAllAssociative(
            "SELECT p.id AS promotion_id, pc.course_id, p.name, p.ends_at FROM promotions p JOIN promotion_courses pc ON pc.promotion_id = p.id
             JOIN courses c ON c.id = pc.course_id AND c.status = 'published'
             WHERE p.active AND p.course_scope = 'selected' AND (p.starts_at IS NULL OR p.starts_at <= :now) AND (p.ends_at IS NULL OR p.ends_at > :now)
