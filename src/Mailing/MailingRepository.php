    /** The list for a subject, made when it is first needed. */
    public function listId(string $kind, ?int $subjectId, bool $create): ?int
    {
        if ($kind === 'own') return null;
        $id = $this->db->fetchOne('SELECT id FROM mailing_lists WHERE kind = :k AND COALESCE(subject_id, 0) = :s', ['k' => $kind, 's' => $subjectId ?? 0]);
        if ($id !== false) return (int) $id;
        if (!$create) return null;

        return (int) $this->db->fetchOne(
            "INSERT INTO mailing_lists (kind, subject_id) VALUES (:k, :s) ON CONFLICT (kind, COALESCE(subject_id, 0)) WHERE kind <> 'own' DO UPDATE SET kind = EXCLUDED.kind RETURNING id",
            ['k' => $kind, 's' => $subjectId]
        );
    }

    /**
     * The lists ADMIN made (decision 7A), with how many are on each: all of them, or only those people may join now.
     *
     * @return list<array<string,mixed>>
     */
    public function ownLists(bool $openOnly = false): array
    {
        return array_map(static fn(array $row): array => self::own($row), $this->db->fetchAllAssociative(
            "SELECT l.*, (SELECT COUNT(*) FROM mailing_subscriptions s WHERE s.list_id = l.id AND s.status = 'subscribed') AS followers
             FROM mailing_lists l WHERE l.kind = 'own'" . ($openOnly ? ' AND l.closed_at IS NULL' : '') . ' ORDER BY l.closed_at IS NOT NULL, lower(l.name)'
        ));
    }

    /** @return array<string,mixed>|null */
    public function ownList(int $id): ?array
    {
        $row = $this->db->fetchAssociative("SELECT l.*, (SELECT COUNT(*) FROM mailing_subscriptions s WHERE s.list_id = l.id AND s.status = 'subscribed') AS followers
            FROM mailing_lists l WHERE l.id = :id AND l.kind = 'own'", ['id' => $id]);

        return $row === false ? null : self::own($row);
    }

    /** @return array<string,mixed>|null an open list by its join link's token */
    public function ownListByToken(string $token): ?array
    {
        if (preg_match('/^[0-9a-f]{32}$/', $token) !== 1) return null;
        $row = $this->db->fetchAssociative("SELECT l.*, 0 AS followers FROM mailing_lists l WHERE l.join_token = :t AND l.kind = 'own' AND l.closed_at IS NULL", ['t' => $token]);

        return $row === false ? null : self::own($row);
    }

    /** @param array<string,mixed> $fields name, description, shown */
    public function createOwn(array $fields, int $userId): int
    {
        return (int) $this->db->fetchOne(
            "INSERT INTO mailing_lists (kind, name, description, shown, join_token, created_by_user_id) VALUES ('own', :name, :description, :shown, :token, :user) RETURNING id",
            ['name' => $fields['name'], 'description' => $fields['description'], 'shown' => (bool) $fields['shown'] ? 'true' : 'false', 'token' => bin2hex(random_bytes(16)), 'user' => $userId]
        );
    }

    /** @param array<string,mixed> $fields name, description, shown, from_name, reply_to, template_id, welcome_campaign_id, closed_at, join_token */
    public function updateList(int $id, array $fields): void
    {
        $sets = [];
        $params = ['id' => $id];
        foreach ($fields as $column => $value) {
            if (!in_array($column, ['name', 'description', 'shown', 'from_name', 'reply_to', 'template_id', 'welcome_campaign_id', 'closed_at', 'join_token'], true)) continue;
            $sets[] = $column . ' = :' . $column;
            $params[$column] = is_bool($value) ? ($value ? 'true' : 'false') : $value;
        }
        if ($sets === []) return;
        $this->db->executeStatement('UPDATE mailing_lists SET ' . implode(', ', $sets) . ' WHERE id = :id', $params);
    }

    /** @return array<string,mixed>|null any list's own settings: its sender, template and welcome email (decision 9A) */
    public function listSettings(int $id): ?array
    {
        $row = $this->db->fetchAssociative('SELECT id, kind, name, from_name, reply_to, template_id, welcome_campaign_id FROM mailing_lists WHERE id = :id', ['id' => $id]);

        return $row === false ? null : $row;
    }

    /**
     * @param array<string,mixed> $row
     * @return array<string,mixed>
     */
    private static function own(array $row): array
    {
        return ['id' => (int) $row['id'], 'kind' => 'own', 'subject_id' => 0, 'name' => (string) $row['name'], 'description' => (string) ($row['description'] ?? ''),
            'shown' => in_array($row['shown'], [true, 't', 'true', 1, '1'], true), 'join_token' => (string) $row['join_token'], 'from_name' => (string) ($row['from_name'] ?? ''),
            'reply_to' => (string) ($row['reply_to'] ?? ''), 'template_id' => $row['template_id'] === null ? 0 : (int) $row['template_id'],
            'welcome_campaign_id' => $row['welcome_campaign_id'] === null ? 0 : (int) $row['welcome_campaign_id'], 'closed_at' => $row['closed_at'],
            'followers' => (int) $row['followers'], 'created_at' => (string) $row['created_at'], 'slug' => ''];
    }

    /** The name of a category, a published course or a tag that can be followed, or null when there is none. */
    public function subjectName(string $kind, int $id): ?string
    {
        $name = match ($kind) {
            'category' => $this->db->fetchOne('SELECT name FROM course_categories WHERE id = :id', ['id' => $id]),
            'course' => $this->db->fetchOne("SELECT title FROM courses WHERE id = :id AND status = 'published'", ['id' => $id]),
            'tag' => $this->db->fetchOne('SELECT name FROM tags WHERE id = :id', ['id' => $id]),
            default => false,
        };

        return is_string($name) && $name !== '' ? $name : null;
    }

    /** The person's answer for a list changes, and the change goes into the history; false when it was the answer already. */
    public function answer(int $listId, int $userId, string $status, string $source): bool
    {
        $current = $this->db->fetchOne('SELECT status FROM mailing_subscriptions WHERE list_id = :l AND user_id = :u FOR UPDATE', ['l' => $listId, 'u' => $userId]);
        if ($current === $status) return false;
        $this->db->executeStatement(
            'INSERT INTO mailing_subscriptions (list_id, user_id, status, source, changed_at) VALUES (:l, :u, :s, :src, NOW())
             ON CONFLICT (list_id, user_id) DO UPDATE SET status = EXCLUDED.status, source = EXCLUDED.source, changed_at = NOW()',
            ['l' => $listId, 'u' => $userId, 's' => $status, 'src' => $source]
        );
        $this->db->executeStatement('INSERT INTO mailing_subscription_events (list_id, user_id, status, source) VALUES (:l, :u, :s, :src)', ['l' => $listId, 'u' => $userId, 's' => $status, 'src' => $source]);

        return true;
    }

    public function isSubscribed(int $userId, string $kind, ?int $subjectId): bool
    {
        return $this->db->fetchOne(
            "SELECT 1 FROM mailing_subscriptions s JOIN mailing_lists l ON l.id = s.list_id
             WHERE s.user_id = :u AND s.status = 'subscribed' AND l.kind = :k AND COALESCE(l.subject_id, 0) = :sub",
            ['u' => $userId, 'k' => $kind, 'sub' => $subjectId ?? 0]
        ) !== false;
    }

    /**
     * What a person follows, with each subject's name and address.
     *
     * @return list<array{kind:string,subject_id:int,name:string,slug:string,since:string}>
     */
    public function follows(int $userId): array
    {
        return array_map(static fn(array $row): array => ['kind' => (string) $row['kind'], 'subject_id' => (int) $row['subject_id'], 'name' => (string) $row['name'], 'slug' => (string) $row['slug'], 'since' => (string) $row['changed_at']], $this->db->fetchAllAssociative(
            "SELECT l.kind, l.subject_id, s.changed_at,
                    COALESCE(cat.name, c.title, t.name, '') AS name, COALESCE(cat.slug, c.slug, t.slug, '') AS slug
             FROM mailing_subscriptions s JOIN mailing_lists l ON l.id = s.list_id
             LEFT JOIN course_categories cat ON l.kind = 'category' AND cat.id = l.subject_id
             LEFT JOIN courses c ON l.kind = 'course' AND c.id = l.subject_id
             LEFT JOIN tags t ON l.kind = 'tag' AND t.id = l.subject_id
             WHERE s.user_id = :u AND s.status = 'subscribed' AND l.kind NOT IN ('news', 'own')
             ORDER BY l.kind, lower(COALESCE(cat.name, c.title, t.name, ''))",
            ['u' => $userId]
        ));
    }

    /**
     * Every list with its subject's name and how many follow it, News and Updates first.
     *
     * @return list<array{id:int,kind:string,subject_id:int,name:string,slug:string,followers:int,created_at:string}>
     */
    public function lists(): array
    {
        return array_map(static fn(array $row): array => ['id' => (int) $row['id'], 'kind' => (string) $row['kind'], 'subject_id' => (int) $row['subject_id'], 'name' => (string) $row['name'], 'slug' => (string) $row['slug'], 'followers' => (int) $row['followers'], 'created_at' => (string) $row['created_at']], $this->db->fetchAllAssociative(
            "SELECT l.id, l.kind, COALESCE(l.subject_id, 0) AS subject_id, l.created_at,
                    CASE l.kind WHEN 'news' THEN 'News and Updates' WHEN 'own' THEN l.name ELSE COALESCE(cat.name, c.title, t.name, '') END AS name,
                    COALESCE(cat.slug, c.slug, t.slug, '') AS slug,
                    (SELECT COUNT(*) FROM mailing_subscriptions s WHERE s.list_id = l.id AND s.status = 'subscribed') AS followers
             FROM mailing_lists l
             LEFT JOIN course_categories cat ON l.kind = 'category' AND cat.id = l.subject_id
             LEFT JOIN courses c ON l.kind = 'course' AND c.id = l.subject_id
             LEFT JOIN tags t ON l.kind = 'tag' AND t.id = l.subject_id
             ORDER BY CASE l.kind WHEN 'news' THEN 0 WHEN 'own' THEN 1 WHEN 'category' THEN 2 WHEN 'course' THEN 3 ELSE 4 END, lower(COALESCE(l.name, cat.name, c.title, t.name, ''))"
        ));
    }

    /** @return array{id:int,kind:string,subject_id:int,name:string,slug:string,followers:int,created_at:string}|null */
    public function list(int $listId): ?array
    {
        foreach ($this->lists() as $list) if ($list['id'] === $listId) return $list;

        return null;
    }

    /**
     * The people who follow a list, newest first, with when and where they said yes.
     *
     * @return list<array<string,mixed>>
     */
    public function followers(int $listId, int $limit, int $offset): array
    {
        return $this->db->fetchAllAssociative(
            "SELECT s.user_id, s.source, s.changed_at, u.account_reference, e.email,
                    COALESCE(NULLIF(trim(concat_ws(' ', u.first_name, u.last_name)), ''), u.display_name, e.email) AS name
             FROM mailing_subscriptions s JOIN users u ON u.id = s.user_id JOIN user_emails e ON e.user_id = u.id AND e.is_primary
             WHERE s.list_id = :l AND s.status = 'subscribed'
             ORDER BY s.changed_at DESC, s.user_id DESC LIMIT :limit OFFSET :offset",
            ['l' => $listId, 'limit' => $limit, 'offset' => $offset]
        );
    }

    /** @return list<int> the lists a person follows now */
    public function subscribedListIds(int $userId): array
    {
        return array_map('intval', $this->db->fetchFirstColumn("SELECT list_id FROM mailing_subscriptions WHERE user_id = :u AND status = 'subscribed' ORDER BY list_id", ['u' => $userId]));
    }

    /** @return array{list_id:int,followers:int} who follows a category, course or tag, for its page in Administration */
    public function followersOf(string $kind, int $subjectId): array
    {
        $listId = $this->listId($kind, $subjectId, false);

        return ['list_id' => $listId ?? 0, 'followers' => $listId === null ? 0 : $this->followerCount($listId)];
    }

    public function followerCount(int $listId): int
    {
        return (int) $this->db->fetchOne("SELECT COUNT(*) FROM mailing_subscriptions WHERE list_id = :l AND status = 'subscribed'", ['l' => $listId]);
    }

    /**
     * Of these subjects of a kind, the ones a person follows.
     *
     * @param list<int> $subjectIds
     * @return list<int>
     */
    public function followedAmong(int $userId, string $kind, array $subjectIds): array
    {
        if ($subjectIds === []) return [];

        return array_map('intval', $this->db->fetchFirstColumn(
            "SELECT l.subject_id FROM mailing_subscriptions s JOIN mailing_lists l ON l.id = s.list_id
             WHERE s.user_id = :u AND s.status = 'subscribed' AND l.kind = :k AND l.subject_id = ANY(CAST(:ids AS BIGINT[]))",
            ['u' => $userId, 'k' => $kind, 'ids' => '{' . implode(',', array_map('intval', $subjectIds)) . '}']
        ));
    }
