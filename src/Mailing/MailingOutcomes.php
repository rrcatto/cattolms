declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Infrastructure\Persistence\AuditRepository;

class MailingOutcomes
{
    /** How far along each status is: a copy never moves back. */
    private const RANK = ['queued' => 0, 'handed' => 1, 'deferred' => 2, 'delivered' => 3, 'soft_bounced' => 4, 'failed' => 4, 'suppressed' => 4, 'skipped' => 4, 'bounced' => 5, 'complained' => 6];

    public function __construct(
        private readonly CampaignRepository $campaigns,
        private readonly MailingConsents $consents,
        private readonly AuditRepository $audit,
    ) {
    }

    /**
     * Records what became of a copy. Returns false when it says nothing new.
     *
     * @param array<string,mixed> $delivery
     */
    public function record(array $delivery, string $status, string $detail = '', ?string $messageId = null): bool
    {
        if (!isset(self::RANK[$status])) return false;
        $current = (string) $delivery['status'];
        $fields = [];
        if ($messageId !== null && $messageId !== '' && (string) ($delivery['transport_message_id'] ?? '') === '') $fields['transport_message_id'] = $messageId;
        $forward = self::RANK[$status] > (self::RANK[$current] ?? 0);
        if ($forward) {
            $fields['status'] = $status;
            if ($detail !== '') $fields['status_detail'] = $detail;
            if (in_array($status, CampaignRepository::RESOLVED, true)) $fields['resolved_at'] = gmdate('Y-m-d H:i:sP');
        }
        if ($fields !== []) $this->campaigns->updateDelivery((int) $delivery['id'], $fields);
        if (!$forward) return false;

        $email = (string) $delivery['email'];
        $userId = $delivery['user_id'] !== null ? (int) $delivery['user_id'] : null;
        if ($status === 'bounced') {
            $this->campaigns->suppress($email, 'hard_bounce', $detail !== '' ? $detail : 'The receiving server said the address does not exist.', (int) $delivery['id'], null);
            $this->audit->record($userId, 'mailing.hard_bounce', ['delivery_id' => (int) $delivery['id'], 'campaign_id' => (int) $delivery['campaign_id']]);
        }
        if ($status === 'complained') {
            $this->campaigns->suppress($email, 'complaint', $detail !== '' ? $detail : 'Marked an email as spam.', (int) $delivery['id'], null);
            if ($userId !== null) $this->consents->unsubscribeAll($userId, 'complaint');
            $this->campaigns->updateDelivery((int) $delivery['id'], ['unsubscribed_at' => gmdate('Y-m-d H:i:sP')]);
            $this->audit->record($userId, 'mailing.complaint', ['delivery_id' => (int) $delivery['id'], 'campaign_id' => (int) $delivery['campaign_id']]);
        }

        return true;
    }

    /**
     * The unsubscribe link of a copy, or the email app's one-click button: stops the copy's list, or every list.
     *
     * @param array<string,mixed> $delivery
     */
    public function unsubscribe(array $delivery, bool $everything, string $source): int
    {
        $userId = $delivery['user_id'] !== null ? (int) $delivery['user_id'] : 0;
        if ($userId < 1) return 0;
        // A digest or an update brought by several lists unsubscribes from every one of them.
        $lists = array_values(array_filter(array_map('intval', (array) ($delivery['content']['lists'] ?? []))));
        if ($lists === [] && $delivery['list_id'] !== null) $lists = [(int) $delivery['list_id']];
        $stopped = 0;
        if ($everything || $lists === []) $stopped = $this->consents->unsubscribeAll($userId, $source);
        else foreach ($lists as $listId) $stopped += $this->consents->unsubscribeList($userId, $listId, $source) ? 1 : 0;
        if ($delivery['unsubscribed_at'] === null) $this->campaigns->updateDelivery((int) $delivery['id'], ['unsubscribed_at' => gmdate('Y-m-d H:i:sP')]);

        return $stopped;
    }
}
