    /** @param list<int> $listIds */
    public function create(int $userId, string $name, array $listIds = []): int
    {
        $name = trim($name) !== '' ? mb_substr(trim($name), 0, 160) : 'New email ' . $this->localNow()->format('j M Y');
        $id = $this->campaigns->create('message', $name, $userId, [
            'list_ids' => $this->checkedLists($listIds),
            'blocks' => [
                ['type' => 'heading', 'text' => 'News from ' . $this->runtime->platformName()] + EmailBlocks::make('heading'),
                ['type' => 'text', 'text' => "Hello [First name],\n\n"] + EmailBlocks::make('text'),
            ],
        ]);
        $this->audit->record($userId, 'mailing.campaign_created', ['campaign_id' => $id]);

        return $id;
    }

    /** @return array<string,mixed> */
    public function get(int $id): array
    {
        return $this->campaigns->find($id) ?? throw new InvalidArgumentException('That message could not be found.');
    }

    /** @param array<string,mixed> $input name, subject, preheader, list_ids */
    public function saveDetails(int $id, array $input, int $userId): void
    {
        $this->editing($id, function (array $campaign) use ($input): array {
            $subject = trim((string) ($input['subject'] ?? ''));
            if (mb_strlen($subject) > 200) throw new InvalidArgumentException('The subject is longer than 200 characters.');
            $preheader = trim((string) ($input['preheader'] ?? ''));
            if (mb_strlen($preheader) > 200) throw new InvalidArgumentException('The preview line is longer than 200 characters.');
            $name = trim((string) ($input['name'] ?? ''));
            if ($name === '') throw new InvalidArgumentException('Give the message a name you will recognise, such as "November news". Readers never see it.');
            $fields = ['name' => mb_substr($name, 0, 160), 'subject' => $subject, 'preheader' => $preheader];
            // The lists change only when the form showed them (lists_shown): no box ticked then means none.
            if ($campaign['kind'] === 'message' && $campaign['status'] === 'draft' && ($input['lists_shown'] ?? '') === '1') {
                $fields['list_ids'] = $this->checkedLists(array_map('intval', (array) ($input['list_ids'] ?? [])));
                $fields['exclude_list_ids'] = array_values(array_diff($this->checkedLists(array_map('intval', (array) ($input['exclude_list_ids'] ?? []))), $fields['list_ids']));
            }
            // Its template, sender, most to send and own plain-text copy (owner, 2026-10-28: decisions 5B and 9A, ctnlist's maximum).
            if (($input['more_shown'] ?? '') === '1') {
                $template = (int) ($input['template_id'] ?? 0);
                if ($template > 0 && $this->templates !== null) {
                    try {
                        $this->templates->get($template);
                    } catch (InvalidArgumentException) {
                        throw new InvalidArgumentException('Choose the template from the list.');
                    }
                }
                $fromName = trim((string) ($input['from_name'] ?? ''));
                if (mb_strlen($fromName) > 120) throw new InvalidArgumentException('Keep the sender\'s name under 120 characters.');
                $replyTo = strtolower(trim((string) ($input['reply_to'] ?? '')));
                if ($replyTo !== '' && filter_var($replyTo, FILTER_VALIDATE_EMAIL) === false) throw new InvalidArgumentException('Write the reply-to address in full, such as help@example.com, or leave it empty.');
                $most = trim((string) ($input['max_recipients'] ?? ''));
                if ($most !== '' && preg_match('/^[1-9][0-9]{0,8}$/', $most) !== 1) throw new InvalidArgumentException('Write the most people to send it to as a whole number, or leave it empty for everyone.');
                $plain = trim(str_replace("\r\n", "\n", (string) ($input['plain_text'] ?? '')));
                if (mb_strlen($plain) > 20000) throw new InvalidArgumentException('Keep the plain-text copy under 20,000 characters.');
                $fields += ['template_id' => $template > 0 ? $template : null, 'from_name' => $fromName !== '' ? $fromName : null, 'reply_to' => $replyTo !== '' ? $replyTo : null,
                    'max_recipients' => $most !== '' ? (int) $most : null, 'plain_text' => ($input['plain_mode'] ?? 'made') === 'own' && $plain !== '' ? $plain : null];
            }

            return $fields;
        }, $userId, 'mailing.campaign_details_saved');
    }

    public function addBlock(int $id, string $type, string $after, int $userId): string
    {
        $block = EmailBlocks::make($type);
        $this->editing($id, function (array $campaign) use ($block, $after): array {
            $blocks = $campaign['blocks'];
            $at = count($blocks);
            foreach ($blocks as $index => $existing) if ($existing['id'] === $after) $at = $index + 1;
            array_splice($blocks, $at, 0, [$block]);

            return ['blocks' => $blocks];
        }, $userId, 'mailing.block_added');

        return (string) $block['id'];
    }

    /** @param array<string,mixed> $input */
    public function updateBlock(int $id, string $blockId, array $input, int $userId, ?string $pictureBytes = null): void
    {
        $this->editing($id, function (array $campaign) use ($blockId, $input, $userId, $pictureBytes): array {
            $blocks = $campaign['blocks'];
            $index = $this->blockIndex($blocks, $blockId);
            $block = EmailBlocks::update($blocks[$index], $input);
            if ($block['type'] === 'image' && $pictureBytes !== null && $pictureBytes !== '') $block['asset'] = $this->assets->store($pictureBytes, $userId);
            if ($block['type'] === 'image' && (string) $block['asset'] === '') throw new InvalidArgumentException('Choose the picture to show.');
            $blocks[$index] = $block;

            return ['blocks' => $blocks];
        }, $userId, 'mailing.block_saved');
    }

    public function moveBlock(int $id, string $blockId, string $direction, int $userId): void
    {
        $this->editing($id, function (array $campaign) use ($blockId, $direction): array {
            $blocks = $campaign['blocks'];
            $index = $this->blockIndex($blocks, $blockId);
            $to = match ($direction) { 'up' => $index - 1, 'down' => $index + 1, 'top' => 0, 'bottom' => count($blocks) - 1, default => throw new InvalidArgumentException('Choose where to move it.') };
            if ($to < 0 || $to >= count($blocks) || $to === $index) return [];
            $moving = array_splice($blocks, $index, 1);
            array_splice($blocks, $to, 0, $moving);

            return ['blocks' => $blocks];
        }, $userId, 'mailing.block_moved');
    }

    public function removeBlock(int $id, string $blockId, int $userId): void
    {
        $this->editing($id, function (array $campaign) use ($blockId): array {
            $blocks = $campaign['blocks'];
            array_splice($blocks, $this->blockIndex($blocks, $blockId), 1);

            return ['blocks' => $blocks];
        }, $userId, 'mailing.block_removed');
    }

    /**
     * The copy a reader sees: for a preview or a test, with the writer's first name and the campaign's first list.
     *
     * @return array{subject:string,html:string,text:string,unsubscribe_url:string}
     */
    public function preview(int $id, string $firstName): array
    {
        $campaign = $this->get($id);
        $names = $this->listNames($campaign['list_ids']);
        // A digest's or an update email's preview is its first copy: each person's holds what reached them.
        $sample = in_array($campaign['kind'], ['digest', 'updates'], true) ? $this->campaigns->firstContent($id) : [];

        return $this->renderer->render($campaign, ['first_name' => $firstName, 'reasons' => $names === [] ? ['News and Updates'] : $names, 'list_name' => $names[0] ?? 'News and Updates', 'content' => $sample], false);
    }

    /** Sends the writer a test copy to their own address, through the site's own mail. */
    public function sendTest(int $id, int $userId, string $email, string $firstName): void
    {
        $copy = $this->preview($id, $firstName);
        if (filter_var($email, FILTER_VALIDATE_EMAIL) === false) throw new InvalidArgumentException('Your account has no address to send the test to.');
        if (trim((string) $this->get($id)['subject']) === '') throw new InvalidArgumentException('Write the subject first.');
        $mail = $this->runtime->mailConfiguration();
        $message = (new Email())->from(new Address((string) $mail['from_address'], (string) $mail['from_name']))->to($email)->subject('[Proof] ' . $copy['subject'])->html($copy['html'])->text($copy['text']);
        Transport::fromDsn((string) $mail['dsn'])->send($message);
        $this->audit->record($userId, 'mailing.test_sent', ['campaign_id' => $id]);
    }

    /** Schedules a draft: now when $sendAt is empty, else at that time in the site's time zone. */
    public function schedule(int $id, string $sendAt, int $userId): void
    {
        $this->transactions->run(function () use ($id, $sendAt, $userId): void {
            $campaign = $this->campaigns->find($id, true) ?? throw new InvalidArgumentException('That message could not be found.');
            if ($campaign['status'] !== 'draft') throw new InvalidArgumentException('Only a draft can be sent. This one is ' . strtolower(self::STATUS_LABELS[$campaign['status']]) . '.');
            $this->assertReady($campaign);
            $at = null;
            if (trim($sendAt) !== '') {
                $when = DateTimeImmutable::createFromFormat('Y-m-d\TH:i', trim($sendAt), new DateTimeZone(date_default_timezone_get()));
                if ($when === false) throw new InvalidArgumentException('Enter the date and time to send it, such as 2026-11-02 09:00.');
                if ($when < $this->localNow()) throw new InvalidArgumentException('That time has passed. Choose a later one, or send it now.');
                $at = $when->setTimezone(new DateTimeZone('UTC'))->format('Y-m-d H:i:sP');
            }
            $this->campaigns->update($id, ['status' => 'scheduled', 'send_at' => $at, 'approved_by_user_id' => $userId, 'approved_at' => $this->stamp(), 'status_note' => null]);
            $this->audit->record($userId, 'mailing.campaign_scheduled', ['campaign_id' => $id, 'send_at' => $at]);
        });
    }

    /** Takes back a scheduled campaign that has not started: it is a draft again. */
    public function unschedule(int $id, int $userId): void
    {
        $this->change($id, ['scheduled'], ['status' => 'draft', 'send_at' => null, 'approved_by_user_id' => null, 'approved_at' => null], $userId, 'mailing.campaign_unscheduled', 'Only a scheduled campaign that has not started can be taken back.');
    }

    public function approve(int $id, int $userId): void
    {
        $this->transactions->run(function () use ($id, $userId): void {
            $campaign = $this->campaigns->find($id, true) ?? throw new InvalidArgumentException('That message could not be found.');
            if ($campaign['status'] !== 'awaiting_approval') throw new InvalidArgumentException('It is not waiting for approval.');
            if (trim((string) $campaign['subject']) === '') throw new InvalidArgumentException('Write the subject first.');
            $this->campaigns->update($id, ['status' => 'scheduled', 'send_at' => null, 'approved_by_user_id' => $userId, 'approved_at' => $this->stamp(), 'status_note' => null]);
            $this->audit->record($userId, 'mailing.campaign_approved', ['campaign_id' => $id]);
        });
    }

    public function pause(int $id, int $userId, string $name): void
    {
        $this->change($id, ['sending', 'scheduled'], ['status' => 'paused', 'status_note' => 'Paused by ' . $name . '.'], $userId, 'mailing.campaign_paused', 'Only a campaign that is sending or scheduled can be paused.');
    }

    public function resume(int $id, int $userId): void
    {
        $this->transactions->run(function () use ($id, $userId): void {
            $campaign = $this->campaigns->find($id, true) ?? throw new InvalidArgumentException('That message could not be found.');
            if ($campaign['status'] !== 'paused') throw new InvalidArgumentException('Only a paused message can be resumed.');
            $byItself = str_starts_with((string) $campaign['status_note'], 'Paused by itself');
            $started = $campaign['started_at'] !== null;
            $this->campaigns->update($id, ['status' => $started ? 'sending' : 'scheduled', 'status_note' => null] + ($byItself ? ['checks_overridden' => true] : []));
            $this->audit->record($userId, 'mailing.campaign_resumed', ['campaign_id' => $id, 'overrode_checks' => $byItself]);
        });
    }

    public function cancel(int $id, int $userId): void
    {
        $this->transactions->run(function () use ($id, $userId): void {
            $campaign = $this->campaigns->find($id, true) ?? throw new InvalidArgumentException('That message could not be found.');
            if (!in_array($campaign['status'], ['draft', 'awaiting_approval', 'scheduled', 'sending', 'paused'], true)) throw new InvalidArgumentException('It has already ' . ($campaign['status'] === 'sent' ? 'been sent' : 'been cancelled') . '.');
            foreach ($this->campaigns->nextQueued($id, 100000) as $delivery) $this->campaigns->updateDelivery((int) $delivery['id'], ['status' => 'skipped', 'status_detail' => 'The campaign was cancelled.', 'resolved_at' => $this->stamp()]);
            $this->campaigns->update($id, ['status' => 'cancelled', 'finished_at' => $this->stamp()]);
            $this->audit->record($userId, 'mailing.campaign_cancelled', ['campaign_id' => $id]);
        });
    }

    public function duplicate(int $id, int $userId): int
    {
        $campaign = $this->get($id);
        // Each block gets a new id, so the copy's blocks are its own.
        $blocks = array_map(static fn(array $block): array => ['id' => EmailBlocks::make((string) $block['type'])['id']] + $block, $campaign['blocks']);
        $copy = $this->campaigns->create('message', mb_substr('Copy of ' . $campaign['name'], 0, 160), $userId, ['subject' => $campaign['subject'], 'preheader' => $campaign['preheader'], 'blocks' => $blocks, 'list_ids' => $campaign['kind'] === 'message' ? $campaign['list_ids'] : []]);
        $this->audit->record($userId, 'mailing.campaign_created', ['campaign_id' => $copy, 'copied_from' => $id]);

        return $copy;
    }

    public function delete(int $id, int $userId): void
    {
        $campaign = $this->get($id);
        if (!in_array($campaign['status'], ['draft', 'cancelled'], true) || $this->campaigns->deliveryCount($id, '') > 0) throw new InvalidArgumentException('Only a draft, or a cancelled campaign that sent nothing, can be deleted. A sent campaign stays as a record of what was sent.');
        $this->campaigns->delete($id);
        $this->audit->record($userId, 'mailing.campaign_deleted', ['campaign_id' => $id, 'name' => $campaign['name']]);
    }

    /** @param array<string,mixed> $campaign */
    public function assertReady(array $campaign): void
    {
        if (trim((string) $campaign['subject']) === '') throw new InvalidArgumentException('Write the subject first.');
        if ($campaign['blocks'] === []) throw new InvalidArgumentException('Add something to the email first.');
        if ($campaign['kind'] === 'message') {
            if ($campaign['list_ids'] === []) throw new InvalidArgumentException('Choose the lists it goes to.');
            if ($this->campaigns->audienceCount($campaign['list_ids']) === 0) throw new InvalidArgumentException('Nobody follows the lists you chose yet, so there is nobody to send it to.');
        }
        foreach ($campaign['blocks'] as $block) {
            if ($block['type'] === 'button' && (string) $block['href'] === '') throw new InvalidArgumentException('The button "' . $block['label'] . '" has no web address yet.');
            if ($block['type'] === 'image' && (string) $block['asset'] === '') throw new InvalidArgumentException('A picture block has no picture yet. Choose one or remove the block.');
            if ($block['type'] === 'course' && (int) $block['course_id'] < 1) throw new InvalidArgumentException('A course block has no course yet. Choose one or remove the block.');
            if (in_array($block['type'], ['text', 'html'], true) && trim((string) ($block['text'] ?? $block['html'] ?? '')) === '') throw new InvalidArgumentException('A ' . strtolower(EmailBlocks::TYPES[$block['type']][0]) . ' block is empty. Write in it or remove it.');
        }
    }

    /**
     * @param list<int> $listIds
     * @return list<string>
     */
    public function listNames(array $listIds): array
    {
        $byId = [];
        foreach ($this->lists->lists() as $list) $byId[$list['id']] = $list['name'];

        return array_values(array_filter(array_map(static fn(int $id): string => (string) ($byId[$id] ?? ''), $listIds)));
    }

    /**
     * Runs a change to a campaign that may still be edited: a draft, one waiting for approval, or a paused one, and a
     * list's welcome email at any time (each copy is drawn when it is sent).
     *
     * @param callable(array<string,mixed>):array<string,mixed> $change
     */
    private function editing(int $id, callable $change, int $userId, string $event): void
    {
        $this->transactions->run(function () use ($id, $change, $userId, $event): void {
            $campaign = $this->campaigns->find($id, true) ?? throw new InvalidArgumentException('That message could not be found.');
            if ($campaign['kind'] !== 'welcome' && !in_array($campaign['status'], ['draft', 'awaiting_approval', 'paused'], true)) throw new InvalidArgumentException('It is ' . strtolower(self::STATUS_LABELS[$campaign['status']]) . ', so it can no longer be changed. Pause it first, or make a copy.');
            $fields = $change($campaign);
            if ($fields === []) return;
            $this->campaigns->update($id, $fields);
            $this->audit->record($userId, $event, ['campaign_id' => $id]);
        });
    }

    /**
     * @param list<string> $from
     * @param array<string,mixed> $fields
     */
    private function change(int $id, array $from, array $fields, int $userId, string $event, string $refusal): void
    {
        $this->transactions->run(function () use ($id, $from, $fields, $userId, $event, $refusal): void {
            $campaign = $this->campaigns->find($id, true) ?? throw new InvalidArgumentException('That message could not be found.');
            if (!in_array($campaign['status'], $from, true)) throw new InvalidArgumentException($refusal);
            $this->campaigns->update($id, $fields);
            $this->audit->record($userId, $event, ['campaign_id' => $id]);
        });
    }

    /** @param list<array<string,mixed>> $blocks */
    private function blockIndex(array $blocks, string $blockId): int
    {
        foreach ($blocks as $index => $block) if ($block['id'] === $blockId) return $index;

        throw new InvalidArgumentException('That block is no longer in the email. The page has been refreshed.');
    }

    /**
     * @param list<int> $listIds
     * @return list<int>
     */
    private function checkedLists(array $listIds): array
    {
        $known = array_column($this->lists->lists(), 'id');
        $listIds = array_values(array_unique(array_filter(array_map('intval', $listIds), static fn(int $id): bool => $id > 0)));
        foreach ($listIds as $id) if (!in_array($id, $known, true)) throw new InvalidArgumentException('One of the lists chosen no longer exists.');

        return $listIds;
    }

    private function localNow(): DateTimeImmutable
    {
        return DateTimeImmutable::createFromInterface($this->clock->now())->setTimezone(new DateTimeZone(date_default_timezone_get()));
    }

    private function stamp(): string
    {
        return DateTimeImmutable::createFromInterface($this->clock->now())->setTimezone(new DateTimeZone('UTC'))->format('Y-m-d H:i:sP');
    }
}
