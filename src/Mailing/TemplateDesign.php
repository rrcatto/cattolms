    public static function checked(array $input, array $current): array
    {
        $design = self::read($current);
        foreach (self::COLOURS as $key => $label) {
            $colour = strtolower(trim((string) ($input['colours'][$key] ?? $design['colours'][$key])));
            if (preg_match('/^#[0-9a-f]{6}$/', $colour) !== 1) throw new InvalidArgumentException($label . ': write the colour as # and six hex digits, such as #9a3f12.');
            $design['colours'][$key] = $colour;
        }
        $choose = static function (string $key, array $choices, string $label) use ($input, &$design): void {
            $value = (string) ($input[$key] ?? $design[$key]);
            if (!isset($choices[$value])) throw new InvalidArgumentException('Choose ' . $label . ' from the list.');
            $design[$key] = $value;
        };
        $choose('logo_size', self::LOGO_SIZES, 'the logo\'s size');
        $choose('align', self::ALIGNMENTS, 'where the logo sits');
        $choose('heading_font', self::FONTS, 'the headings\' font');
        $choose('body_font', self::FONTS, 'the text\'s font');
        $choose('corners', self::CORNERS, 'the corners');
        $choose('spacing', self::SPACINGS, 'the spacing');
        $choose('button_shape', self::BUTTON_SHAPES, 'the buttons\' shape');
        foreach (['text_size' => [self::TEXT_SIZES, 'the text size'], 'width' => [self::WIDTHS, 'the width']] as $key => [$choices, $label]) {
            $value = (int) ($input[$key] ?? $design[$key]);
            if (!in_array($value, $choices, true)) throw new InvalidArgumentException('Choose ' . $label . ' from the list.');
            $design[$key] = $value;
        }
        $words = trim(str_replace("\r\n", "\n", (string) ($input['footer_words'] ?? $design['footer_words'])));
        if (mb_strlen($words) > 1000) throw new InvalidArgumentException('Keep the footer\'s words under 1,000 characters.');
        $design['footer_words'] = $words;
        $design['social'] = [];
        foreach (self::SOCIAL as $key => $label) {
            $address = trim((string) ($input['social'][$key] ?? ''));
            if ($address === '') continue;
            if (!self::isHttps($address)) throw new InvalidArgumentException($label . ': write your profile\'s full address, starting with https://.');
            $design['social'][$key] = $address;
        }

        return $design;
    }

