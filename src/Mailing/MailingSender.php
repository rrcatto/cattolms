Sends news, once a minute from the scheduler (mailing, step 2; owner, 2026-10-26: "I will be employing best sending
practices and ensuring I don't run foul of spam problems"). Each run:

1. starts every campaign that is due: everyone following its lists then, with an active account and an address that is
   not suppressed, gets a copy (a digest's copies are made when it is planned);
2. sends what the discipline allows, and only within the sending hours Sending settings choose (owner, 2026-10-28,
   round two 6A: everything the mailing system sends; account and order emails are the site's own and always go at
   once): no more than the hourly limit in any hour, and on the first days of sending from
   this site the first day's number doubling each day, so the sending address and domain build their standing
   gently. A copy whose person has stopped following its list, or whose address was suppressed, since the campaign
   started is skipped. A transport that cannot be reached leaves the copies queued for the next run; one that refuses
   the campaign pauses it with the reason;
3. pauses a campaign by itself when its hard bounces or spam complaints pass the Settings' limits once enough copies
   have gone to judge, unless ADMIN resumed it after such a pause;
4. reads back from cattomail what became of the copies handed to it.

