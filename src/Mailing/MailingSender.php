declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use DateTimeImmutable;
use DateTimeZone;
use Symfony\Component\Clock\ClockInterface;
use Throwable;

class MailingSender
{
    /** The most copies one run hands on, so a run stays within its minute. */
    public const PER_RUN = 200;

    public function __construct(
        private readonly CampaignRepository $campaigns,
        private readonly EmailRenderer $renderer,
        private readonly MailingTransports $transports,
        private readonly MailingSettings $settings,
        private readonly MailingOutcomes $outcomes,
        private readonly MailingConsents $consents,
        private readonly RuntimeSettings $runtime,
        private readonly TransactionManager $transactions,
        private readonly ClockInterface $clock,
    ) {
    }

    /** @return array{started:int,handed:int,paused:int,resolved:int,notes:list<string>} */
    public function run(): array
    {
        $done = ['started' => 0, 'handed' => 0, 'paused' => 0, 'resolved' => 0, 'notes' => []];
        foreach ($this->campaigns->dueToStart($this->stamp($this->now())) as $id) $done['started'] += $this->start($id) ? 1 : 0;
        $budget = $this->allowance();
        foreach ($this->campaigns->sending() as $id) {
            if ($budget < 1) break;
            [$handed, $note] = $this->sendSome($id, $budget);
            $budget -= $handed;
            $done['handed'] += $handed;
            if ($note !== '') $done['notes'][] = $note;
        }
        foreach ($this->campaigns->sending() as $id) $done['paused'] += $this->checkRates($id) ? 1 : 0;
        $done['resolved'] = $this->reconcile();

        return $done;
    }

    /** How many copies may be handed on now: none outside the sending hours, the hourly limit, and the gentle start on the first days. */
    public function allowance(): int
    {
        $rules = $this->settings->rules();
        $now = $this->now();
        if (!$this->settings->withinSendingHours($now)) return 0;
        $allowed = (int) $rules['hourly_limit'] - $this->campaigns->handedSince($this->stamp($now->modify('-1 hour')));
        $first = (int) $rules['first_day_limit'];
        if ($first > 0) {
            $zone = new DateTimeZone(date_default_timezone_get());
            $today = $now->setTimezone($zone)->setTime(0, 0);
            $firstAt = $this->campaigns->firstHandedAt();
            $day = $firstAt === null ? 0 : max(0, (int) (new DateTimeImmutable($firstAt))->setTimezone($zone)->setTime(0, 0)->diff($today)->days);
            $cap = $day >= 20 ? PHP_INT_MAX : $first * (2 ** $day);
            if ($cap < (int) $rules['hourly_limit'] * 24) $allowed = min($allowed, $cap - $this->campaigns->handedSince($this->stamp($today)));
        }

        return max(0, min($allowed, self::PER_RUN));
    }

    private function start(int $campaignId): bool
    {
        return (bool) $this->transactions->run(function () use ($campaignId): bool {
            $campaign = $this->campaigns->find($campaignId, true);
            if ($campaign === null || $campaign['status'] !== 'scheduled') return false;
            // Everyone on its lists but the people on the lists it leaves out, up to the most it sends to (owner, 2026-10-28).
            if ($campaign['kind'] === 'message') {
                $people = $this->campaigns->audience($campaign['list_ids'], (array) ($campaign['exclude_list_ids'] ?? []));
                if ((int) ($campaign['max_recipients'] ?? 0) > 0) $people = array_slice($people, 0, (int) $campaign['max_recipients']);
                $this->campaigns->addDeliveries($campaignId, $people);
            }
            $now = $this->stamp($this->now());
            if ($this->campaigns->queuedCount($campaignId) === 0) {
                $this->campaigns->update($campaignId, ['status' => 'sent', 'started_at' => $now, 'finished_at' => $now, 'status_note' => 'Nobody followed its lists when it was due, so nothing was sent.']);

                return true;
            }
            $this->campaigns->update($campaignId, ['status' => 'sending', 'started_at' => $now, 'status_note' => null]);

            return true;
        });
    }

    /** @return array{0:int,1:string} copies handed on, and a note when the transport could not take them */
    private function sendSome(int $campaignId, int $budget): array
    {
        try {
            return $this->transactions->run(function () use ($campaignId, $budget): array {
                $campaign = $this->campaigns->find($campaignId, true);
                if ($campaign === null || $campaign['status'] !== 'sending') return [0, ''];
                $mail = $this->runtime->mailConfiguration();
                // Written to one list alone, it takes that list's sender, reply-to and template where it has none of its own (9A).
                if (in_array($campaign['kind'], ['message', 'welcome'], true) && count((array) $campaign['list_ids']) === 1) {
                    foreach ($this->campaigns->listSender((int) $campaign['list_ids'][0]) as $field => $value) {
                        if (in_array($campaign[$field] ?? null, [null, '', 0], true)) $campaign[$field] = $value;
                    }
                }
                // The message's own sender name and reply-to, else Sending settings' (decision 9A).
                $sender = ['email' => $this->settings->fromAddress((string) $mail['from_address']),
                    'name' => trim((string) ($campaign['from_name'] ?? '')) !== '' ? (string) $campaign['from_name'] : $this->settings->fromName((string) $mail['from_name']),
                    'reply_to' => trim((string) ($campaign['reply_to'] ?? ''))];
                $copies = [];
                foreach ($this->campaigns->nextQueued($campaignId, $budget) as $delivery) {
                    $why = $this->stillWanted($campaign, $delivery);
                    if ($why !== '') {
                        $this->campaigns->updateDelivery((int) $delivery['id'], ['status' => $why === 'suppressed' ? 'suppressed' : 'skipped', 'status_detail' => $why === 'suppressed' ? 'The address may not be emailed news.' : $why, 'resolved_at' => $this->stamp($this->now())]);
                        continue;
                    }
                    $reasons = array_values(array_map('strval', (array) $delivery['reasons']));
                    $copy = $this->renderer->render($campaign, ['token' => (string) $delivery['token'], 'first_name' => (string) $delivery['first_name'], 'reasons' => $reasons, 'list_name' => $reasons[0] ?? 'News and Updates', 'content' => (array) $delivery['content']], true);
                    $copies[] = ['delivery_id' => (int) $delivery['id'], 'token' => (string) $delivery['token'], 'to' => (string) $delivery['email'], 'list_id' => (int) ($delivery['list_id'] ?? 0), 'list_name' => $reasons[0] ?? 'News and Updates'] + $copy;
                }
                $handed = 0;
                if ($copies !== []) {
                    $transport = $this->transports->current();
                    try {
                        $result = $transport->send($campaign, array_map(static fn(array $c): array => ['delivery_id' => $c['delivery_id'], 'token' => $c['token'], 'to' => $c['to'], 'subject' => $c['subject'], 'html' => $c['html'], 'text' => $c['text'], 'unsubscribe_url' => $c['unsubscribe_url'], 'list_id' => $c['list_id'], 'list_name' => $c['list_name']], $copies), $sender);
                    } catch (MailingTransportRefused $refused) {
                        $this->campaigns->update($campaignId, ['status' => 'paused', 'status_note' => 'Paused: ' . $refused->getMessage() . ' Nothing more was sent. Fix it, then resume.']);

                        return [0, 'Message ' . $campaignId . ' paused: ' . $refused->getMessage()];
                    }
                    $now = $this->stamp($this->now());
                    foreach ($result['handed'] as $deliveryId => $handedTo) {
                        $this->campaigns->updateDelivery($deliveryId, ['status' => 'handed', 'handed_at' => $now, 'transport' => $transport->name(), 'transport_job_id' => $handedTo['job_id'], 'transport_message_id' => $handedTo['message_id'], 'attempts' => 1]);
                        $handed++;
                    }
                    foreach ($result['failed'] as $deliveryId => $detail) $this->campaigns->updateDelivery($deliveryId, ['status' => 'failed', 'status_detail' => $detail, 'attempts' => 1, 'resolved_at' => $now]);
                }
                // A welcome email waits, sending, for the next person to join its list.
                if ($campaign['kind'] !== 'welcome' && $this->campaigns->queuedCount($campaignId) === 0) $this->campaigns->update($campaignId, ['status' => 'sent', 'finished_at' => $this->stamp($this->now())]);

                return [$handed, ''];
            });
        } catch (MailingTransportUnavailable $busy) {
            // The copies stay queued: the next run tries again.
            return [0, 'Message ' . $campaignId . ' waits: ' . $busy->getMessage()];
        }
    }

    /**
     * Why a queued copy should not go after all, or '' when it should.
     *
     * @param array<string,mixed> $campaign
     * @param array<string,mixed> $delivery
     */
    private function stillWanted(array $campaign, array $delivery): string
    {
        if ($this->campaigns->isSuppressed((string) $delivery['email'])) return 'suppressed';
        if ($delivery['user_id'] === null) return 'The account was deleted before it was sent.';
        if ($campaign['kind'] === 'sleeping') return '';
        $lists = array_values(array_filter(array_map('intval', (array) ($delivery['content']['lists'] ?? []))));
        if ($lists === [] && $delivery['list_id'] !== null) $lists = [(int) $delivery['list_id']];
        if ($lists === []) return '';
        foreach ($lists as $listId) if ($this->consents->isSubscribedToList((int) $delivery['user_id'], $listId)) return '';
        if (count($lists) > 1) return 'They unsubscribed from everything that brought it before it was sent.';

        return 'They unsubscribed from it before it was sent.';
    }

    /** Pauses a sending campaign whose hard bounces or complaints pass the limits. */
    private function checkRates(int $campaignId): bool
    {
        $campaign = $this->campaigns->find($campaignId);
        if ($campaign === null || $campaign['status'] !== 'sending' || (bool) $campaign['checks_overridden']) return false;
        $rules = $this->settings->rules();
        $figures = $this->campaigns->figures($campaignId);
        $sent = (int) ($figures['sent'] ?? 0);
        if ($sent < (int) $rules['judge_after'] || $sent < 1) return false;
        $bounces = 100 * (int) $figures['hard_bounced'] / $sent;
        $complaints = 100 * (int) $figures['complained'] / $sent;
        $why = '';
        if ($bounces > (float) $rules['pause_bounce_percent']) $why = $figures['hard_bounced'] . ' of the ' . $sent . ' emails sent bounced (' . self::percent($bounces) . '), above the limit of ' . self::percent((float) $rules['pause_bounce_percent']) . '.';
        elseif ($complaints > (float) $rules['pause_complaint_percent']) $why = $figures['complained'] . ' of the ' . $sent . ' emails sent were marked as spam (' . self::percent($complaints) . '), above the limit of ' . self::percent((float) $rules['pause_complaint_percent']) . '.';
        if ($why === '') return false;
        $this->campaigns->update($campaignId, ['status' => 'paused', 'status_note' => 'Paused by itself: ' . $why . ' Look at who bounced or complained before you resume or cancel it.']);

        return true;
    }

    /** Reads back from cattomail what became of the copies it was given, a few jobs each run. */
    private function reconcile(): int
    {
        $resolved = 0;
        foreach ($this->campaigns->openJobs('cattomail', $this->stamp($this->now()->modify('-15 minutes')), 10) as $job) {
            $jobId = (string) $job['transport_job_id'];
            try {
                $outcomes = $this->transports->cattomail()->outcomes($jobId);
            } catch (Throwable) {
                continue;
            }
            foreach ($outcomes as $outcome) {
                if ($outcome['token'] === '') continue;
                $delivery = $this->campaigns->deliveryByToken($outcome['token']);
                if ($delivery === null) continue;
                if ($outcome['status'] === null) {
                    if ($outcome['message_id'] !== '' && (string) ($delivery['transport_message_id'] ?? '') === '') $this->campaigns->updateDelivery((int) $delivery['id'], ['transport_message_id' => $outcome['message_id']]);
                    continue;
                }
                $resolved += $this->outcomes->record($delivery, $outcome['status'], '', $outcome['message_id']) ? 1 : 0;
            }
            $this->campaigns->jobChecked($jobId);
        }

        return $resolved;
    }

    private static function percent(float $value): string
    {
        return rtrim(rtrim(number_format($value, 2, '.', ''), '0'), '.') . '%';
    }

    private function now(): DateTimeImmutable
    {
        return DateTimeImmutable::createFromInterface($this->clock->now());
    }

    private function stamp(DateTimeImmutable $at): string
    {
        return $at->setTimezone(new DateTimeZone('UTC'))->format('Y-m-d H:i:sP');
    }
}
