declare(strict_types=1);

namespace CattoLearning\Mailing;

class CattomailTransport implements MailingTransport
{
    /** cattomail's message statuses, as a copy's status here; those not listed are still on their way ("handed"). */
    public const STATUSES = [
        'remote_accepted' => 'delivered',
        'deferred' => 'deferred',
        'soft_bounced' => 'soft_bounced',
        'hard_bounced' => 'bounced',
        'complained' => 'complained',
        'failed' => 'failed',
        'suppressed' => 'suppressed',
    ];

    public function __construct(private readonly CattomailClient $client, private readonly ?CattomailConnection $connection = null)
    {
    }

    public function name(): string
    {
        return 'cattomail';
    }

    public function send(array $campaign, array $copies, array $sender): array
    {
        // News waits, unsent, while catto-mail cannot send from the domain or its quota is used up (owner, 2026-10-28,
        // page 9): nothing goes unsigned, and nothing is asked before the quota resets.
        if ($this->connection !== null) {
            $until = $this->connection->quotaUntil();
            if ($until !== null) throw new MailingTransportUnavailable('catto-mail\'s quota is used up until ' . $until->format('j F \a\t H:i') . '.');
            if ($this->connection->connected() && !$this->connection->ready()) {
                throw new MailingTransportUnavailable('catto-mail cannot send from ' . $this->connection->sendingDomain() . ' yet: finish its DNS steps on Mailing, catto-mail.');
            }
        }
        try {
            return $this->sendNow($campaign, $copies, $sender);
        } catch (CattomailQuotaExceeded $quota) {
            $this->connection?->quotaUsedUntil($quota->resetsAt, $quota->getMessage());

            throw new MailingTransportUnavailable('catto-mail\'s quota is used up' . ($quota->resetsAt !== null ? ' until ' . $quota->resetsAt->setTimezone(new \DateTimeZone(date_default_timezone_get()))->format('j F \a\t H:i') : '') . '.');
        }
    }

    /**
     * @param array<string,mixed> $campaign
     * @param list<array{delivery_id:int,token:string,to:string,subject:string,html:string,text:string,unsubscribe_url:string,list_id:int,list_name:string}> $copies
     * @param array{email:string,name:string,reply_to?:string} $sender
     * @return array{handed:array<int,array{job_id:?string,message_id:?string}>,failed:array<int,string>}
     */
    private function sendNow(array $campaign, array $copies, array $sender): array
    {
        $handed = [];
        $byList = [];
        foreach ($copies as $copy) $byList[$copy['list_id']][] = $copy;
        foreach ($byList as $listId => $group) {
            $host = (string) (parse_url($group[0]['unsubscribe_url'], PHP_URL_HOST) ?: 'localhost');
            $reference = 'cattolms-c' . (int) $campaign['id'] . '-l' . $listId . '-' . substr(hash('sha256', implode(',', array_column($group, 'delivery_id'))), 0, 24);
            $job = $this->client->createJob([
                'external_reference' => $reference,
                'message_class' => 'subscription',
                'sender_identity' => ['email' => $sender['email'], 'name' => $sender['name']],
                'tracking' => ['opens' => false, 'clicks' => false],
                'list_id' => mb_substr(str_replace(['<', '>', '"'], '', $group[0]['list_name']), 0, 150) . ' <list-' . $listId . '.' . $host . '>',
            ] + (($sender['reply_to'] ?? '') !== '' ? ['reply_to' => ['email' => (string) $sender['reply_to']]] : []), $reference . '-job');
            $jobId = (string) ($job['id'] ?? '');
            if ($jobId === '') throw new MailingTransportRefused('catto-mail made no send job.');
            foreach (array_chunk($group, CattomailClient::BATCH) as $index => $chunk) {
                $this->client->addRecipients($jobId, array_map(static fn(array $copy): array => [
                    'external_recipient_reference' => $copy['token'],
                    'email_address' => $copy['to'],
                    'subject' => $copy['subject'],
                    'html_body' => $copy['html'],
                    'text_body' => $copy['text'],
                    'unsubscribe_url' => $copy['unsubscribe_url'],
                ], $chunk), $reference . '-r' . $index);
            }
            $this->client->submit($jobId);
            foreach ($group as $copy) $handed[$copy['delivery_id']] = ['job_id' => $jobId, 'message_id' => null];
        }

        return ['handed' => $handed, 'failed' => []];
    }

    /**
     * What became of each copy in a job: its token, cattomail's message id and its status here (null while it is
     * still on its way).
     *
     * @return list<array{token:string,message_id:string,status:?string}>
     */
    public function outcomes(string $jobId): array
    {
        $out = [];
        $cursor = null;
        do {
            $page = $this->client->messages($jobId, $cursor);
            foreach ($page['data'] as $message) {
                $out[] = ['token' => (string) ($message['external_recipient_reference'] ?? ''), 'message_id' => (string) ($message['id'] ?? ''), 'status' => self::STATUSES[(string) ($message['current_status'] ?? '')] ?? null];
            }
            $cursor = $page['next_cursor'];
        } while ($cursor !== null);

        return $out;
    }
}
