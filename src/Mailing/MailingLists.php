declare(strict_types=1);

namespace CattoLearning\Mailing;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use DateTimeImmutable;
use InvalidArgumentException;

final class MailingLists
{
    public function __construct(
        private readonly MailingRepository $lists,
        private readonly CampaignRepository $campaigns,
        private readonly MailingTemplates $templates,
        private readonly MailingConsents $consents,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
    ) {
    }

    /** @param array<string,mixed> $input name, description, shown */
    public function create(array $input, int $userId): int
    {
        [$name, $description] = $this->words($input);

        return (int) $this->transactions->run(function () use ($name, $description, $input, $userId): int {
            $id = $this->lists->createOwn(['name' => $name, 'description' => $description, 'shown' => ($input['shown'] ?? '') === '1'], $userId);
            $this->audit->record($userId, 'mailing.list_created', ['list_id' => $id, 'name' => $name]);

            return $id;
        });
    }

    /**
     * A list of ADMIN's own: its name, its words and whether My Subscriptions shows it.
     *
     * @param array<string,mixed> $input name, description, shown
     */
    public function saveWords(int $id, array $input, int $userId): void
    {
        $this->own($id);
        [$name, $description] = $this->words($input);
        $this->lists->updateList($id, ['name' => $name, 'description' => $description, 'shown' => ($input['shown'] ?? '') === '1']);
        $this->audit->record($userId, 'mailing.list_updated', ['list_id' => $id]);
    }

    /**
     * Any list: the sender's name, the reply-to address and the template used when it is written to alone (9A).
     *
     * @param array<string,mixed> $input from_name, reply_to, template_id
     */
    public function saveSender(int $id, array $input, int $userId): void
    {
        if ($this->lists->listSettings($id) === null) throw new InvalidArgumentException('There is no such list.');
        $from = trim((string) ($input['from_name'] ?? ''));
        if (mb_strlen($from) > 120) throw new InvalidArgumentException('Keep the sender\'s name under 120 characters.');
        $reply = mb_strtolower(trim((string) ($input['reply_to'] ?? '')));
        if ($reply !== '' && filter_var($reply, FILTER_VALIDATE_EMAIL) === false) throw new InvalidArgumentException('Write the reply-to address in full, such as help@example.test.');
        $template = (int) ($input['template_id'] ?? 0);
        if ($template > 0) $this->templates->get($template);
        $this->lists->updateList($id, ['from_name' => $from !== '' ? $from : null, 'reply_to' => $reply !== '' ? $reply : null, 'template_id' => $template > 0 ? $template : null]);
        $this->audit->record($userId, 'mailing.list_sender_saved', ['list_id' => $id]);
    }

    /**
     * Switches a list's welcome email on (made the first time, to be written in the message editor) or off. Returns the
     * welcome email's campaign.
     */
    public function welcome(int $id, bool $on, int $userId, string $listName): int
    {
        return (int) $this->transactions->run(function () use ($id, $on, $userId, $listName): int {
            $list = $this->lists->listSettings($id);
            if ($list === null) throw new InvalidArgumentException('There is no such list.');
            $campaignId = (int) ($list['welcome_campaign_id'] ?? 0);
            if ($campaignId === 0 || $this->campaigns->find($campaignId) === null) {
                if (!$on) return 0;
                $campaignId = $this->campaigns->create('welcome', 'Welcome to ' . $listName, $userId, [
                    'subject' => 'Welcome to ' . $listName, 'preheader' => 'Thank you for joining.', 'list_ids' => [$id], 'status' => 'draft',
                    'blocks' => [['type' => 'heading', 'text' => 'Welcome to ' . $listName] + EmailBlocks::make('heading'),
                        ['type' => 'text', 'text' => "Hello [First name],\n\nThank you for joining " . $listName . '. This is what you can look forward to.'] + EmailBlocks::make('text')],
                ]);
                $this->lists->updateList($id, ['welcome_campaign_id' => $campaignId]);
            }
            // A welcome email that is on waits, sending, for each person who joins; off, it is a draft and sends nothing.
            $this->campaigns->update($campaignId, ['status' => $on ? 'sending' : 'draft', 'started_at' => $on ? gmdate('Y-m-d H:i:sP') : null, 'status_note' => null]);
            $this->audit->record($userId, $on ? 'mailing.welcome_on' : 'mailing.welcome_off', ['list_id' => $id, 'campaign_id' => $campaignId]);

            return $campaignId;
        });
    }

    public function newJoinLink(int $id, int $userId): void
    {
        $this->own($id);
        $this->lists->updateList($id, ['join_token' => bin2hex(random_bytes(16))]);
        $this->audit->record($userId, 'mailing.list_join_link_replaced', ['list_id' => $id]);
    }

    public function close(int $id, bool $closed, int $userId): void
    {
        $this->own($id);
        $this->lists->updateList($id, ['closed_at' => $closed ? (new DateTimeImmutable())->format(DATE_ATOM) : null]);
        $this->audit->record($userId, $closed ? 'mailing.list_closed' : 'mailing.list_opened', ['list_id' => $id]);
    }

    /** Takes one person off one list; every other list they are on stays. */
    public function takeOff(int $listId, int $personId, int $userId): void
    {
        if (!$this->consents->unsubscribeList($personId, $listId, 'admin')) throw new InvalidArgumentException('They are not on this list.');
        $this->audit->record($userId, 'mailing.taken_off_list', ['list_id' => $listId, 'user_id' => $personId]);
    }

    /** @return array<string,mixed> */
    private function own(int $id): array
    {
        $list = $this->lists->ownList($id);
        if ($list === null) throw new InvalidArgumentException('Only a list you made can be changed like that.');

        return $list;
    }

    /**
     * @param array<string,mixed> $input
     * @return array{0:string,1:string}
     */
    private function words(array $input): array
    {
        $name = trim((string) preg_replace('/\s+/', ' ', (string) ($input['name'] ?? '')));
        if ($name === '') throw new InvalidArgumentException('Give the list a name, such as "Early access to new courses".');
        if (mb_strlen($name) > 120) throw new InvalidArgumentException('Keep the name under 120 characters.');
        $description = trim((string) ($input['description'] ?? ''));
        if (mb_strlen($description) > 500) throw new InvalidArgumentException('Keep what it is for under 500 characters.');

        return [$name, $description];
    }
}
