declare(strict_types=1);

namespace CattoLearning\Configuration;

use CattoLearning\Support\Env;
use CattoPHP\Activity\Actor;
use CattoPHP\Settings\Settings;
use InvalidArgumentException;
use RuntimeException;

final class RuntimeSettings
{
    private const MAIL_DSN = 'MAILER_DSN';
    private const MAIL_FROM_ADDRESS = 'MAIL_FROM_ADDRESS';
    private const MAIL_FROM_NAME = 'MAIL_FROM_NAME';
    private const MAIL_REPLY_TO = 'MAIL_REPLY_TO';
    private const PLATFORM_NAME = 'APP_NAME';

    public function __construct(
        private readonly Settings $settings,
        private readonly ?SiteMode $site = null,
        private readonly ?SiteOwner $owner = null
    ) {
    }

    /**
     * The domain this installation answers on.
     *
     * Mail to any domain the platform invents is redirected here, so an operator receives it in
     * one real inbox instead of it bouncing off a name that was never meant to resolve.
     */
    public function platformDomain(): string
    {
        return self::normaliseDomain(Env::string('APP_DOMAIN', 'local'));
    }

    /**
     * The Site Owner's bank account for EFT payments (SiteOwner: .env, overridden at Administration >
     * Settings > Site Owner). Configured only when all four details are set.
     *
     * @return array{bank_name:string,account_name:string,account_number:string,branch_code:string,configured:bool}
     */
    public function bankDetails(): array
    {
        return $this->owner?->bankDetails() ?? ['bank_name' => '', 'account_name' => '', 'account_number' => '', 'branch_code' => '', 'configured' => false];
    }

    /**
     * The bank account customers are told to pay into: on a demo site fake details, each labelled as
     * fake (SiteMode::FAKE_BANK_DETAILS), so nobody pays real money for a simulated order; on a live
     * site the Site Owner's.
     *
     * @return array{bank_name:string,account_name:string,account_number:string,branch_code:string,configured:bool,fake:bool}
     */
    public function payableBankDetails(): array
    {
        if ($this->site?->isDemo() ?? true) return SiteMode::FAKE_BANK_DETAILS + ['configured' => true, 'fake' => true];
        return $this->bankDetails() + ['fake' => false];
    }

    public function platformName(): string
    {
        return $this->settings->get(self::PLATFORM_NAME);
    }

    /**
     * The address people are told to write to: the reply-to address mail goes out with, or the sender
     * when there is none. Read without the mail transport, so a document never depends on it.
     */
    public function contactEmail(): string
    {
        foreach ([$this->settings->get(self::MAIL_REPLY_TO), $this->settings->get(self::MAIL_FROM_ADDRESS)] as $address) {
            $address = trim($address);
            if ($address !== '' && filter_var($address, FILTER_VALIDATE_EMAIL) !== false) {
                return $address;
            }
        }
        return '';
    }

    public function platformNameSource(): string
    {
        return $this->settings->isOverridden(self::PLATFORM_NAME) ? 'database' : 'environment';
    }

    public function resetPlatformName(): void
    {
        $this->settings->reset(self::PLATFORM_NAME);
    }

    /** Saves the platform name; the name .env gives is no override, so a later .env change still shows. */
    public function savePlatformName(string $name, int $actorUserId): void
    {
        $this->settings->set(self::PLATFORM_NAME, $name, self::actor($actorUserId));
    }








    /**
     * One spelling of a domain.
     *
     * Lower-cased, trimmed, and with any leading dot removed, so that `.Example.COM ` and
     * `example.com` cannot become two different companies through a unique index that sees them as
     * distinct strings.
     */
    public static function normaliseDomain(string $domain): string
    {
        return ltrim(strtolower(trim($domain)), '.');
    }

    /** @return array{dsn:string,from_address:string,from_name:string,reply_to:string} */
    public function mailConfiguration(): array
    {
        $dsn = $this->effectiveMailerDsn();
        $this->parseMailerDsn($dsn); // structural validation

        $fromAddress = $this->settings->get(self::MAIL_FROM_ADDRESS);
        if (filter_var($fromAddress, FILTER_VALIDATE_EMAIL) === false) {
            throw new RuntimeException('The effective mail sender address is invalid.');
        }

        $fromName = $this->settings->get(self::MAIL_FROM_NAME);
        $replyTo = $this->settings->get(self::MAIL_REPLY_TO);
        if ($replyTo !== '' && filter_var($replyTo, FILTER_VALIDATE_EMAIL) === false) {
            throw new RuntimeException('The effective mail reply-to address is invalid.');
        }

        return [
            'dsn' => $dsn,
            'from_address' => $fromAddress,
            'from_name' => $fromName !== '' ? $fromName : $this->platformName(),
            'reply_to' => $replyTo,
        ];
    }

    /** @return array<string,mixed> */
    public function mailAdminView(): array
    {
        try {
            $parsed = $this->parseMailerDsn($this->effectiveMailerDsn());
            $error = '';
        } catch (RuntimeException $exception) {
            $parsed = [
                'scheme' => 'smtp', 'host' => '', 'port' => 587,
                'username' => '', 'password' => '', 'query' => '',
            ];
            $error = $exception->getMessage();
        }

        $fromAddress = $this->settings->get(self::MAIL_FROM_ADDRESS);
        $fromName = $this->settings->get(self::MAIL_FROM_NAME);
        if ($fromName === '') $fromName = $this->platformName();
        $replyTo = $this->settings->get(self::MAIL_REPLY_TO);

        return [
            'smtp_scheme' => $parsed['scheme'],
            'smtp_host' => $parsed['host'],
            'smtp_port' => $parsed['port'],
            'smtp_username' => $parsed['username'],
            'smtp_query' => $parsed['query'],
            'smtp_password_configured' => $parsed['password'] !== '',
            'mail_from_address' => $fromAddress,
            'mail_from_name' => $fromName,
            'mail_reply_to' => $replyTo,
            'mail_connection_source' => $this->settings->isOverridden(self::MAIL_DSN) ? 'database' : 'environment',
            'mail_sender_source' => $this->hasAnySenderOverride() ? 'database' : 'environment',
            'mail_override_active' => $this->hasMailOverride(),
            'mail_configuration_error' => $error,
        ];
    }

    /** @return array{password:string,source:string} */
    public function mailPasswordForAdmin(): array
    {
        $parsed = $this->parseMailerDsn($this->effectiveMailerDsn());
        return [
            'password' => $parsed['password'],
            'source' => $this->settings->isOverridden(self::MAIL_DSN) ? 'database' : 'environment',
        ];
    }

    /** @param array<string,mixed> $input */
    public function saveMailOverride(array $input, int $actorUserId): void
    {
        $scheme = strtolower(trim((string) ($input['smtp_scheme'] ?? 'smtp')));
        if (!in_array($scheme, ['smtp', 'smtps'], true)) {
            throw new InvalidArgumentException('Choose SMTP / STARTTLS or SMTP over TLS.');
        }

        $host = trim((string) ($input['smtp_host'] ?? ''));
        if ($host === '' || preg_match('/\s/', $host) === 1 || str_contains($host, '/')) {
            throw new InvalidArgumentException('Enter a valid SMTP server hostname.');
        }

        $port = (int) ($input['smtp_port'] ?? 0);
        if ($port < 1 || $port > 65535) {
            throw new InvalidArgumentException('Enter a valid SMTP port between 1 and 65535.');
        }

        $username = trim((string) ($input['smtp_username'] ?? ''));
        $newPassword = (string) ($input['smtp_password'] ?? '');
        $query = ltrim(trim((string) ($input['smtp_query'] ?? '')), '?');
        if ($query !== '' && preg_match('/[\s#]/', $query) === 1) {
            throw new InvalidArgumentException('The advanced SMTP DSN options may not contain whitespace or #.');
        }

        $currentPassword = '';
        try {
            $currentPassword = $this->parseMailerDsn($this->effectiveMailerDsn())['password'];
        } catch (RuntimeException) {
            // An administrator may replace a broken environment DSN from the UI.
        }
        $password = $newPassword !== '' ? $newPassword : $currentPassword;
        if ($username === '') {
            $password = '';
        }

        $fromAddress = trim((string) ($input['mail_from_address'] ?? ''));
        if (filter_var($fromAddress, FILTER_VALIDATE_EMAIL) === false) {
            throw new InvalidArgumentException('Enter a valid From email address.');
        }
        $fromName = trim((string) ($input['mail_from_name'] ?? ''));
        $replyTo = trim((string) ($input['mail_reply_to'] ?? ''));
        if ($replyTo !== '' && filter_var($replyTo, FILTER_VALIDATE_EMAIL) === false) {
            throw new InvalidArgumentException('Enter a valid Reply-to email address or leave it blank.');
        }

        $dsn = $this->buildMailerDsn($scheme, $host, $port, $username, $password, $query);
        $this->parseMailerDsn($dsn);

        // Saved together, the connection a secret CattoPHP encrypts; a value .env already gives is no override.
        $this->settings->save('mail', [self::MAIL_DSN => $dsn, self::MAIL_FROM_ADDRESS => $fromAddress, self::MAIL_FROM_NAME => $fromName, self::MAIL_REPLY_TO => $replyTo], self::actor($actorUserId));
    }

    public function resetMailOverride(): void
    {
        $this->settings->resetGroup('mail');
    }

    public function hasMailOverride(): bool
    {
        return $this->settings->isOverridden(self::MAIL_DSN) || $this->hasAnySenderOverride();
    }

    private function hasAnySenderOverride(): bool
    {
        return $this->settings->isOverridden(self::MAIL_FROM_ADDRESS)
            || $this->settings->isOverridden(self::MAIL_FROM_NAME)
            || $this->settings->isOverridden(self::MAIL_REPLY_TO);
    }

    /** Who saved it, for CattoPHP's log. */
    private static function actor(int $userId): ?Actor
    {
        return $userId > 0 ? new Actor((string) $userId, (string) $userId) : null;
    }

    private function effectiveMailerDsn(): string
    {
        $dsn = $this->settings->get(self::MAIL_DSN);
        if (
            $dsn === ''
            || preg_match('/^(null|test):\/\//i', $dsn) === 1
            || str_contains(strtolower($dsn), 'smtp.example.com')
            || str_contains(strtolower($dsn), 'smtp.example.test')
        ) {
            throw new RuntimeException('Configure a working SMTP server in Settings or MAILER_DSN in .env.');
        }
        return $dsn;
    }

    /** @return array{scheme:string,host:string,port:int,username:string,password:string,query:string} */
    private function parseMailerDsn(string $dsn): array
    {
        $parts = parse_url($dsn);
        if (!is_array($parts)) {
            throw new RuntimeException('The effective MAILER_DSN is invalid.');
        }
        $scheme = strtolower((string) ($parts['scheme'] ?? ''));
        if (!in_array($scheme, ['smtp', 'smtps'], true)) {
            throw new RuntimeException('The mail transport must use smtp:// or smtps://.');
        }
        $host = trim((string) ($parts['host'] ?? ''));
        if ($host === '') {
            throw new RuntimeException('The SMTP server hostname is missing.');
        }
        // parse_url() rejects ports outside the valid 1..65535 range.
        $port = (int) ($parts['port'] ?? ($scheme === 'smtps' ? 465 : 25));
        return [
            'scheme' => $scheme,
            'host' => $host,
            'port' => $port,
            'username' => rawurldecode((string) ($parts['user'] ?? '')),
            'password' => rawurldecode((string) ($parts['pass'] ?? '')),
            'query' => (string) ($parts['query'] ?? ''),
        ];
    }

    private function buildMailerDsn(
        string $scheme,
        string $host,
        int $port,
        string $username,
        string $password,
        string $query
    ): string {
        $dsnHost = str_contains($host, ':') && !str_starts_with($host, '[') ? '[' . $host . ']' : $host;
        $credentials = '';
        if ($username !== '') {
            $credentials = rawurlencode($username);
            if ($password !== '') {
                $credentials .= ':' . rawurlencode($password);
            }
            $credentials .= '@';
        }
        return $scheme . '://' . $credentials . $dsnHost . ':' . $port . ($query !== '' ? '?' . $query : '');
    }
}
