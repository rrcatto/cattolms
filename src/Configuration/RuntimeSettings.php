    {
        $scheme = strtolower(trim((string) ($input['smtp_scheme'] ?? 'smtp')));
        if (!in_array($scheme, ['smtp', 'smtps'], true)) {
            throw new InvalidArgumentException('Choose SMTP / STARTTLS or SMTP over TLS.');
        }

        $host = trim((string) ($input['smtp_host'] ?? ''));
        if ($host === '' || preg_match('/\s/', $host) === 1 || str_contains($host, '/')) {
            throw new InvalidArgumentException('Enter a valid SMTP server hostname.');
        }

        $port = (int) ($input['smtp_port'] ?? 0);
        if ($port < 1 || $port > 65535) {
            throw new InvalidArgumentException('Enter a valid SMTP port between 1 and 65535.');
        }

        $username = trim((string) ($input['smtp_username'] ?? ''));
        $newPassword = (string) ($input['smtp_password'] ?? '');
        $query = ltrim(trim((string) ($input['smtp_query'] ?? '')), '?');
        if ($query !== '' && preg_match('/[\s#]/', $query) === 1) {
            throw new InvalidArgumentException('The advanced SMTP DSN options may not contain whitespace or #.');
        }

        $currentPassword = '';
        try {
            $currentPassword = $this->parseMailerDsn($this->effectiveMailerDsn())['password'];
        } catch (RuntimeException) {
            // An administrator may replace a broken environment DSN from the UI.
        }
        $password = $newPassword !== '' ? $newPassword : $currentPassword;
        if ($username === '') {
            $password = '';
        }

        $fromAddress = trim((string) ($input['mail_from_address'] ?? ''));
        if (filter_var($fromAddress, FILTER_VALIDATE_EMAIL) === false) {
            throw new InvalidArgumentException('Enter a valid From email address.');
        }
        $fromName = trim((string) ($input['mail_from_name'] ?? ''));
        $replyTo = trim((string) ($input['mail_reply_to'] ?? ''));
        if ($replyTo !== '' && filter_var($replyTo, FILTER_VALIDATE_EMAIL) === false) {
            throw new InvalidArgumentException('Enter a valid Reply-to email address or leave it blank.');
        }

