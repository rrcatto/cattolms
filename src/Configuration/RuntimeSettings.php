    /** @return array{scheme:string,host:string,port:int,username:string,password:string,query:string} */
    private function parseMailerDsn(string $dsn): array
    {
        $parts = parse_url($dsn);
        if (!is_array($parts)) {
            throw new RuntimeException('The effective MAILER_DSN is invalid.');
        }
        $scheme = strtolower((string) ($parts['scheme'] ?? ''));
        if (!in_array($scheme, ['smtp', 'smtps'], true)) {
            throw new RuntimeException('The mail transport must use smtp:// or smtps://.');
        }
        $host = trim((string) ($parts['host'] ?? ''));
        if ($host === '') {
            throw new RuntimeException('The SMTP server hostname is missing.');
        }
        // parse_url() rejects ports outside the valid 1..65535 range.
        $port = (int) ($parts['port'] ?? ($scheme === 'smtps' ? 465 : 25));
        return [
            'scheme' => $scheme,
            'host' => $host,
            'port' => $port,
            'username' => rawurldecode((string) ($parts['user'] ?? '')),
            'password' => rawurldecode((string) ($parts['pass'] ?? '')),
            'query' => (string) ($parts['query'] ?? ''),
        ];
    }

    private function buildMailerDsn(
        string $scheme,
        string $host,
        int $port,
        string $username,
        string $password,
        string $query
    ): string {
        $dsnHost = str_contains($host, ':') && !str_starts_with($host, '[') ? '[' . $host . ']' : $host;
        $credentials = '';
        if ($username !== '') {
            $credentials = rawurlencode($username);
            if ($password !== '') {
                $credentials .= ':' . rawurlencode($password);
            }
            $credentials .= '@';
        }
        return $scheme . '://' . $credentials . $dsnHost . ':' . $port . ($query !== '' ? '?' . $query : '');
    }
