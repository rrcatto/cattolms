    private function effectiveMailerDsn(): string
    {
        $encrypted = $this->options->find(self::MAIL_DSN);
        $dsn = $encrypted !== null ? $this->cipher->decrypt($encrypted) : Env::string('MAILER_DSN');
        if (
            $dsn === ''
