declare(strict_types=1);

namespace CattoLearning\Configuration;

use CattoLearning\Infrastructure\Persistence\OptionRepository;
use DateTimeImmutable;
use DateTimeZone;
use InvalidArgumentException;
use JsonException;

final class SiteNotification
{
    private const OPTION = 'site_notification';

    /** Each kind of message and the notice tone it is drawn in. */
    public const KINDS = ['promotion' => 'success', 'information' => 'info', 'warning' => 'warning'];
    public const COUNTDOWN_WORDS = 'Time left:';
    public const LIMITS = ['heading' => 60, 'message' => 300, 'countdown_words' => 60];
    /** Largest first, as the count shows them. */
    private const UNITS = ['week' => 604800, 'day' => 86400, 'hour' => 3600, 'minute' => 60, 'second' => 1];

    public function __construct(private readonly OptionRepository $options)
    {
    }

    /**
     * What ADMIN saved, whether or not it is showing.
     *
     * @return array{show:bool,on_course_pages:bool,kind:string,heading:string,message:string,countdown_words:string,ends_at:?int}
     */
    public function saved(): array
    {
        $saved = [];
        try {
            $saved = json_decode((string) $this->options->find(self::OPTION), true, 8, JSON_THROW_ON_ERROR);
        } catch (JsonException) {
        }
        if (!is_array($saved)) $saved = [];
        $kind = (string) ($saved['kind'] ?? '');
        return [
            'show' => (bool) ($saved['show'] ?? false),
            'on_course_pages' => (bool) ($saved['on_course_pages'] ?? false),
            'kind' => isset(self::KINDS[$kind]) ? $kind : 'promotion',
            'heading' => (string) ($saved['heading'] ?? ''),
            'message' => (string) ($saved['message'] ?? ''),
            'countdown_words' => (string) ($saved['countdown_words'] ?? ''),
            'ends_at' => is_int($saved['ends_at'] ?? null) ? $saved['ends_at'] : null,
        ];
    }

    /**
     * What every page shows now, or null: switched off, or its countdown has reached zero.
     *
     * @return array{kind:string,tone:string,on_course_pages:bool,heading:string,message:string,countdown:?array{words:string,ends_at:int,now:int,until:string,units:list<array{name:string,count:int,shown:bool}>}}|null
     */
    public function forPage(?int $now = null): ?array
    {
        $now ??= time();
        $saved = $this->saved();
        if (!$saved['show'] || $saved['message'] === '') return null;
        $endsAt = $saved['ends_at'];
        if ($endsAt !== null && $endsAt <= $now) return null;
        return [
            'kind' => $saved['kind'], 'tone' => self::KINDS[$saved['kind']], 'on_course_pages' => $saved['on_course_pages'], 'heading' => $saved['heading'], 'message' => $saved['message'],
            'countdown' => $endsAt === null ? null : [
                'words' => $saved['countdown_words'] === '' ? self::COUNTDOWN_WORDS : $saved['countdown_words'],
                'ends_at' => $endsAt, 'now' => $now, 'units' => self::timeLeft($endsAt - $now),
                'until' => (new DateTimeImmutable('@' . $endsAt))->setTimezone(self::zone())->format('j F Y \a\t H:i T'),
            ],
        ];
    }

    /**
     * Settings' form: what is saved, and whether it is showing.
     *
     * @return array<string,mixed>
     */
    public function settingsView(?int $now = null): array
    {
        $now ??= time();
        $saved = $this->saved();
        $endsAt = $saved['ends_at'];
        return $saved + [
            'ends_at_local' => $endsAt === null ? '' : (new DateTimeImmutable('@' . $endsAt))->setTimezone(self::zone())->format('Y-m-d\TH:i'),
            'showing' => $this->forPage($now) !== null,
            'ended' => $saved['show'] && $endsAt !== null && $endsAt <= $now,
            'exists' => $this->options->find(self::OPTION) !== null,
            'limits' => self::LIMITS, 'standard_words' => self::COUNTDOWN_WORDS, 'zone' => date_default_timezone_get(),
        ];
    }

    /** @param array<string,mixed> $input show, on_course_pages, kind, heading, message, countdown_words, ends_at (typed in the site's time) */
    public function save(array $input, int $actorUserId, ?int $now = null): void
    {
        $now ??= time();
        $kind = (string) ($input['kind'] ?? '');
        if (!isset(self::KINDS[$kind])) throw new InvalidArgumentException('Choose the kind of message.');
        $names = ['heading' => 'The heading', 'message' => 'The message', 'countdown_words' => 'The words before the countdown'];
        $text = [];
        foreach ($names as $field => $name) {
            $text[$field] = trim((string) preg_replace('/\s+/u', ' ', (string) ($input[$field] ?? '')));
            if (mb_strlen($text[$field]) > self::LIMITS[$field]) throw new InvalidArgumentException($name . ' can be at most ' . self::LIMITS[$field] . ' characters.');
        }
        $show = (bool) ($input['show'] ?? false);
        if ($show && $text['message'] === '') throw new InvalidArgumentException('Write the message, or untick Show this notification.');
        $endsAt = self::moment((string) ($input['ends_at'] ?? ''));
        if ($show && $endsAt !== null && $endsAt <= $now) throw new InvalidArgumentException('That date and time has already passed. Choose a later one, or leave it empty for no countdown.');
        $this->options->set(self::OPTION, json_encode(['show' => $show, 'on_course_pages' => (bool) ($input['on_course_pages'] ?? false), 'kind' => $kind] + $text + ['ends_at' => $endsAt], JSON_THROW_ON_ERROR), $actorUserId);
    }

    public function remove(): void
    {
        $this->options->delete(self::OPTION);
    }

    /**
     * The time left in its five units: from the largest that is not zero down to the seconds, which always show.
     *
     * @return list<array{name:string,count:int,shown:bool}>
     */
    public static function timeLeft(int $seconds): array
    {
        $left = max(0, $seconds);
        $units = [];
        $shown = false;
        foreach (self::UNITS as $name => $length) {
            $count = intdiv($left, $length);
            $left -= $count * $length;
            $shown = $shown || $count > 0 || $name === 'second';
            $units[] = ['name' => $name, 'count' => $count, 'shown' => $shown];
        }
        return $units;
    }

    private static function moment(string $typed): ?int
    {
        $typed = trim($typed);
        if ($typed === '') return null;
        $at = DateTimeImmutable::createFromFormat('!Y-m-d\TH:i', substr($typed, 0, 16), self::zone());
        if ($at === false || $at->format('Y-m-d\TH:i') !== substr($typed, 0, 16)) throw new InvalidArgumentException('Choose the date and time the countdown runs to, or leave it empty for no countdown.');
        return $at->getTimestamp();
    }

    private static function zone(): DateTimeZone
    {
        return new DateTimeZone(date_default_timezone_get());
    }
}
