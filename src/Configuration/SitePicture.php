A PNG, JPEG or WebP of at least 600 by 315 pixels. Two copies are kept with the documents' pictures (document_assets):
the picture itself, at most 2400 pixels wide, and its share copy, 1200 by 630 as Facebook, LinkedIn and X ask, cut from
its middle like a cover, never stretched; both JPEG on a dark ground, which shows on every site that shares it. The
option site_owner.picture names them and the pictures before it, which stay served, so a link shared already keeps its
