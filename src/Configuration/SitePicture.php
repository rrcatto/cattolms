declare(strict_types=1);

namespace CattoLearning\Configuration;

use CattoLearning\Document\DocumentAssetRepository;
use CattoLearning\Infrastructure\Persistence\OptionRepository;
use CattoLearning\Support\ImageProcessing;
use InvalidArgumentException;

final class SitePicture
{
    public const OPTION = 'site_owner.picture';
    public const PATH = '/site-picture/';
    public const SHARE_WIDTH = 1200;
    public const SHARE_HEIGHT = 630;
    private const FULL_WIDTH = 2400;
    private const MOST_BYTES = 12 * 1024 * 1024;
    private const KEPT = 20;

    public function __construct(
        private readonly OptionRepository $options,
        private readonly DocumentAssetRepository $assets,
    ) {}

    /** The share copy's full address on the given site address, or null without a picture. */
    public function shareUrl(string $base): ?string
    {
        $version = $this->version();
        return $version === null ? null : rtrim($base, '/') . self::PATH . $version . '.jpg';
    }

    /** The picture's version: the first 16 characters of its share copy's SHA-256. */
    public function version(): ?string
    {
        $share = (string) ($this->stored()['share'] ?? '');
        return preg_match('/^[0-9a-f]{64}$/D', $share) === 1 ? substr($share, 0, 16) : null;
    }

    /**
     * The share copy, or the picture itself ($full), of this picture or one before it, by version. Null for anything else.
     *
     * @return array{bytes:string,mime:string}|null
     */
    public function picture(string $version, bool $full = false): ?array
    {
        if (preg_match('/^[0-9a-f]{16}$/D', $version) !== 1) return null;
        $stored = $this->stored();
        $all = [['share' => (string) ($stored['share'] ?? ''), 'full' => (string) ($stored['full'] ?? '')], ...array_filter((array) ($stored['before'] ?? []), 'is_array')];
        foreach ($all as $pair) {
            if (!str_starts_with((string) ($pair['share'] ?? ''), $version)) continue;
            $asset = $this->assets->find((string) ($full ? ($pair['full'] ?? '') : $pair['share']));
            return $asset === null ? null : ['bytes' => $asset['bytes'], 'mime' => $asset['mime_type']];
        }
        return null;
    }

    /**
     * Keeps an uploaded picture as the site's picture.
     *
     * @return array{from:?string,to:string} the versions before and after, for the Activity log
     * @throws InvalidArgumentException in plain words when the file cannot be the picture
     */
    public function upload(string $bytes, ?int $actorId): array
    {
        if (!ImageProcessing::available()) throw new InvalidArgumentException(ImageProcessing::UNAVAILABLE);
        if ($bytes === '' || strlen($bytes) > self::MOST_BYTES) throw new InvalidArgumentException('The site picture must be a PNG, JPEG or WebP file of at most 12 MB.');
        $info = @getimagesizefromstring($bytes);
        if (!is_array($info) || !in_array($info['mime'], ['image/png', 'image/jpeg', 'image/webp'], true)) throw new InvalidArgumentException('The site picture must be a PNG, JPEG or WebP file of at most 12 MB.');
        [$width, $height] = [(int) $info[0], (int) $info[1]];
        if ($width < 600 || $height < 315) throw new InvalidArgumentException('The site picture is too small to share: it needs to be at least 600 by 315 pixels, and 1200 by 630 or larger is best. This one is ' . $width . ' by ' . $height . '.');
        $source = @imagecreatefromstring($bytes);
        if ($source === false) throw new InvalidArgumentException('The picture could not be read. Save it again as PNG or JPEG.');
        $scale = min(1.0, self::FULL_WIDTH / $width);
        $full = $this->jpeg($source, 0, 0, $width, $height, max(1, (int) round($width * $scale)), max(1, (int) round($height * $scale)));
        // The share copy: the middle of the picture in 1200 by 630's shape, as a cover is cut.
        $ratio = self::SHARE_WIDTH / self::SHARE_HEIGHT;
        [$cropWidth, $cropHeight] = $width / $height > $ratio ? [(int) round($height * $ratio), $height] : [$width, (int) round($width / $ratio)];
        $share = $this->jpeg($source, intdiv($width - $cropWidth, 2), intdiv($height - $cropHeight, 2), $cropWidth, $cropHeight, self::SHARE_WIDTH, self::SHARE_HEIGHT);
        $before = $this->version();
        $kept = [
            'share' => $this->assets->store($share[0], 'image/jpeg', self::SHARE_WIDTH, self::SHARE_HEIGHT, $actorId),
            'full' => $this->assets->store($full[0], 'image/jpeg', $full[1], $full[2], $actorId),
        ];
        $this->save($kept, $actorId);
        return ['from' => $before, 'to' => substr($kept['share'], 0, 16)];
    }

    /** @return ?string the version removed, null when there was none */
    public function remove(?int $actorId): ?string
    {
        $before = $this->version();
        if ($before === null) return null;
        $this->save(null, $actorId);
        return $before;
    }

    /**
     * Part of the picture drawn at a size, on a dark ground, as JPEG.
     *
     * @return array{0:string,1:int,2:int} the bytes, width and height
     */
    private function jpeg(\GdImage $source, int $x, int $y, int $width, int $height, int $toWidth, int $toHeight): array
    {
        $target = imagecreatetruecolor($toWidth, $toHeight);
        imagefill($target, 0, 0, (int) imagecolorallocate($target, 18, 15, 12));
        imagecopyresampled($target, $source, 0, 0, $x, $y, $toWidth, $toHeight, $width, $height);
        ob_start();
        imagejpeg($target, null, 86);
        return [(string) ob_get_clean(), $toWidth, $toHeight];
    }

    /** @param array{share:string,full:string}|null $picture */
    private function save(?array $picture, ?int $actorId): void
    {
        $stored = $this->stored();
        $before = array_values(array_filter((array) ($stored['before'] ?? []), 'is_array'));
        if (preg_match('/^[0-9a-f]{64}$/D', (string) ($stored['share'] ?? '')) === 1 && ($stored['share'] ?? '') !== ($picture['share'] ?? '')) {
            array_unshift($before, ['share' => (string) $stored['share'], 'full' => (string) ($stored['full'] ?? '')]);
        }
        $this->options->set(self::OPTION, (string) json_encode(($picture ?? []) + ['before' => array_slice($before, 0, self::KEPT)], JSON_UNESCAPED_SLASHES), $actorId);
    }

    /** @return array<string,mixed> */
    private function stored(): array
    {
        $decoded = json_decode($this->options->get(self::OPTION, '{}'), true);
        return is_array($decoded) ? $decoded : [];
    }
}
