declare(strict_types=1);

namespace CattoLearning\Configuration;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\OptionRepository;
use InvalidArgumentException;

final class SettingsOrder
{
    public const OPTION = 'settings.section_order';
    /** Every section of Settings, in the order the page starts with. */
    public const STANDARD = [
        'site-mode', 'site-notification', 'identity', 'site-owner', 'owner-messages', 'sign-in', 'two-step', 'signup-checks',
        'search-engines', 'smtp', 'payment-methods', 'identity-verification', 'commerce-fees', 'commerce-references',
        'commerce-wallet', 'commerce-orders', 'configuration', 'course-positions', 'maintenance',
    ];
    /** Each section's name, for its handle and menu. */
    public const TITLES = [
        'site-mode' => 'Site mode', 'site-notification' => 'Site notification', 'identity' => 'Platform identity', 'site-owner' => 'Site Owner',
        'owner-messages' => 'Messages to you', 'sign-in' => 'Who can sign in', 'two-step' => 'Two-step sign-in', 'signup-checks' => 'Sign-up checks',
        'search-engines' => 'Search engines and AI', 'smtp' => 'SMTP / outgoing email', 'payment-methods' => 'Payment methods',
        'identity-verification' => 'Identity verification', 'commerce-fees' => 'Commerce: fees', 'commerce-references' => 'Commerce: account references',
        'commerce-wallet' => 'Commerce: wallet credit', 'commerce-orders' => 'Commerce: orders and refunds', 'configuration' => 'Configuration model',
        'course-positions' => 'Course positions', 'maintenance' => 'Maintenance',
    ];
    public const DIRECTIONS = ['top', 'up', 'down', 'bottom'];

    public function __construct(private readonly OptionRepository $options, private readonly AuditRepository $audit)
    {
    }

    /** @return list<string> every section, in the order the page draws them */
    public function order(): array
    {
        $saved = $this->saved();
        if ($saved === []) return self::STANDARD;
        $order = array_values(array_intersect($saved, self::STANDARD));
        foreach (self::STANDARD as $at => $key) {
            if (in_array($key, $order, true)) continue;
            // A section the saved order does not name goes after the one before it in the standard order.
            $before = $at === 0 ? null : self::STANDARD[$at - 1];
            $place = $before === null ? 0 : (int) array_search($before, $order, true) + 1;
            array_splice($order, $place, 0, [$key]);
        }
        return $order;
    }

    /** Whether an order of the owner's own is saved. */
    public function arranged(): bool
    {
        return $this->saved() !== [] && $this->order() !== self::STANDARD;
    }

    /**
     * A section moved before another, or to the end when $before is '' (a drag, or the keyboard on its handle).
     *
     * @param list<string> $shown the order the page showed
     * @return list<string> the order now
     * @throws InvalidArgumentException when a section is unknown or the order changed since
     */
    public function place(string $key, string $before, array $shown, int $actorId): array
    {
        $order = $this->order();
        self::known($key);
        if ($before !== '') self::known($before);
        if ($before === $key) throw new InvalidArgumentException('A section cannot go before itself.');
        if ($shown !== $order) throw new InvalidArgumentException('The order changed since this page was opened. The saved order is shown.');
        $others = array_values(array_diff($order, [$key]));
        $index = $before === '' ? count($others) : (int) array_search($before, $others, true);
        array_splice($others, $index, 0, [$key]);
        return $this->save($others, $order, $actorId);
    }

    /**
     * A section moved by its menu: to the top, up one, down one or to the bottom.
     *
     * @return list<string> the order now
     */
    public function move(string $key, string $direction, int $actorId): array
    {
        self::known($key);
        if (!in_array($direction, self::DIRECTIONS, true)) throw new InvalidArgumentException('Choose where the section goes.');
        $order = $this->order();
        $at = (int) array_search($key, $order, true);
        $others = array_values(array_diff($order, [$key]));
        $index = match ($direction) { 'top' => 0, 'up' => max(0, $at - 1), 'down' => min(count($others), $at + 1), 'bottom' => count($others) };
        array_splice($others, $index, 0, [$key]);
        return $this->save($others, $order, $actorId);
    }

    /** Back to the order the page starts with. */
    public function reset(int $actorId): void
    {
        if ($this->saved() === []) return;
        $before = $this->order();
        $this->options->delete(self::OPTION);
        $this->audit->record($actorId, 'settings.order_changed', ['from' => $before, 'to' => self::STANDARD, 'reset' => true]);
    }

    /**
     * @param list<string> $order
     * @param list<string> $before
     * @return list<string>
     */
    private function save(array $order, array $before, int $actorId): array
    {
        if ($order === $before) return $order;
        $this->options->set(self::OPTION, (string) json_encode($order), $actorId);
        $this->audit->record($actorId, 'settings.order_changed', ['from' => $before, 'to' => $order]);
        return $order;
    }

    /** @return list<string> */
    private function saved(): array
    {
        $decoded = json_decode($this->options->get(self::OPTION, '[]'), true);
        return is_array($decoded) ? array_values(array_filter($decoded, 'is_string')) : [];
    }

    private static function known(string $key): void
    {
        if (!in_array($key, self::STANDARD, true)) throw new InvalidArgumentException('That section is not one of Settings.');
    }
}
