namespace CattoLearning\Configuration;

use CattoLearning\Support\Env;

final class RunMode
{
    public const DEVELOPMENT = 'development';
    public const PRODUCTION = 'production';

    /** development, unless APP_ENV says production. */
    public static function environment(): string
    {
        return strtolower(Env::string('APP_ENV')) === self::PRODUCTION ? self::PRODUCTION : self::DEVELOPMENT;
    }

    /** Debugging follows the environment: on in development, off in production. */
    public static function debug(): bool
    {
        return self::environment() === self::DEVELOPMENT;
