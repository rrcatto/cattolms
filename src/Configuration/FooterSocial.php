declare(strict_types=1);

namespace CattoLearning\Configuration;

use CattoLearning\Infrastructure\Persistence\OptionRepository;
use CattoLearning\Support\SocialPlatform;
use JsonException;

final class FooterSocial
{
    private const OPTION = 'footer_social';

    public function __construct(private readonly OptionRepository $options)
    {
    }

    /** @return array<string,string> the site's own profile address on each platform that has one, in the footer's order */
    public function saved(): array
    {
        try {
            $saved = json_decode((string) ($this->options->find(self::OPTION) ?? '[]'), true, 4, JSON_THROW_ON_ERROR);
        } catch (JsonException) {
            return [];
        }
        $profiles = [];
        foreach (SocialPlatform::FOOTER as $key) {
            $address = is_array($saved) && is_string($saved[$key] ?? null) ? trim($saved[$key]) : '';
            if ($address !== '') $profiles[$key] = $address;
        }

        return $profiles;
    }

    /** @return list<array{key:string,label:string,href:string}> the footer's marks */
    public function marks(): array
    {
        return SocialPlatform::footerMarks($this->saved());
    }

    /** @return array{rows:list<array{key:string,label:string,placeholder:string,url:string}>,count:int} the Settings section */
    public function settingsView(): array
    {
        $saved = $this->saved();
        $rows = array_values(array_filter(SocialPlatform::form($saved), static fn (array $row): bool => in_array($row['key'], SocialPlatform::FOOTER, true)));
        usort($rows, static fn (array $a, array $b): int => array_search($a['key'], SocialPlatform::FOOTER, true) <=> array_search($b['key'], SocialPlatform::FOOTER, true));

        return ['rows' => $rows, 'count' => count($saved)];
    }

    /**
     * Keeps the typed addresses, an empty field taking that profile away; nothing is kept if one is not an address on its
     * platform's own site (\RuntimeException in plain words, naming the platform).
     *
     * @param array<array-key,mixed> $input platform => the address typed
     */
    public function save(array $input, int $actorUserId): void
    {
        $profiles = [];
        foreach (SocialPlatform::FOOTER as $key) {
            $address = SocialPlatform::normalise($key, is_string($input[$key] ?? null) ? $input[$key] : '');
            if ($address !== null) $profiles[$key] = $address;
        }
        if ($profiles === []) {
            $this->options->delete(self::OPTION);

            return;
        }
        $this->options->set(self::OPTION, json_encode($profiles, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES), $actorUserId);
    }
}
