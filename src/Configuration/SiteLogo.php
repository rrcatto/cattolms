declare(strict_types=1);

namespace CattoLearning\Configuration;

use CattoLearning\Course\Certificate\CertificateImage;
use CattoLearning\Document\DocumentAssetRepository;
use CattoLearning\Infrastructure\Persistence\OptionRepository;
use CattoLearning\Support\SvgRaster;
use InvalidArgumentException;
use RuntimeException;

final class SiteLogo
{
    public const OPTION = 'site_owner.logo';
    /** What a design prints at the top (FinancialDocumentDesign, CertificateDesign, Mailing\TemplateDesign). */
    public const CHOICES = ['site' => 'The site logo', 'own' => 'A logo of its own', 'none' => 'No logo'];
    /** The address the logo is served at, followed by its version and .png or .jpg. */
    public const PATH = '/site-logo/';
    private const SVG_MOST_BYTES = 2000000;
    private const SVG_SECONDS = 20;
    /** How many logos before this one are still served, for emails already sent. */
    private const KEPT = 20;

    /** @var array{address:string,width:int,height:int}|false|null the top bar's logo, read once a page; false for none */
    private array|false|null $address = null;
    /** The height of the top bar's copy, in pixels: twice the bar's 44, for sharp screens. */
    public const SMALL_HEIGHT = 88;

    public function __construct(
        private readonly OptionRepository $options,
        private readonly DocumentAssetRepository $assets,
        private readonly ?string $tool = null,
    ) {}

    /**
     * The logo's address on this site, such as /site-logo/0123456789abcdef.png, from the saved option alone (no picture
     * is read), for the top bar of every page. Null without a logo.
     */
    public function address(): ?string
    {
        return $this->bar()['address'] ?? null;
    }

    /**
     * The top bar's logo: the address of its small copy (SMALL_HEIGHT pixels tall, so a page never loads the full logo to
     * show it 44 pixels high; the SEO brief's fast pages, 2026-11-09) and its width at the bar's 44 pixels, so the page keeps
     * its room before it loads. Null without a logo.
     *
     * @return array{address:string,width:int,height:int}|null
     */
    public function bar(): ?array
    {
        if ($this->address === null) {
            $stored = $this->stored();
            $sha = (string) ($stored['sha'] ?? '');
            $width = (int) ($stored['width'] ?? 0);
            $height = (int) ($stored['height'] ?? 0);
            $this->address = preg_match('/^[0-9a-f]{64}$/D', $sha) !== 1 ? false : [
                'address' => self::PATH . substr($sha, 0, 16) . '-small' . (($stored['mime'] ?? '') === 'image/jpeg' ? '.jpg' : '.png'),
                'width' => $height > 0 ? max(1, (int) round(44 * $width / $height)) : 44, 'height' => 44,
            ];
        }
        return $this->address === false ? null : $this->address;
    }

    /**
     * The small copy of the logo, or of one before it, by version: SMALL_HEIGHT pixels tall at most, its shape and
     * transparency kept, made when asked (the browser keeps it). Null for anything else.
     *
     * @return array{bytes:string,mime:string}|null
     */
    public function smallPicture(string $version): ?array
    {
        $picture = $this->picture($version);
        if ($picture === null) return null;
        $source = @imagecreatefromstring($picture['bytes']);
        if ($source === false) return $picture;
        [$width, $height] = [imagesx($source), imagesy($source)];
        if ($height <= self::SMALL_HEIGHT) return $picture;
        $small = imagecreatetruecolor(max(1, (int) round($width * self::SMALL_HEIGHT / $height)), self::SMALL_HEIGHT);
        imagealphablending($small, false);
        imagesavealpha($small, true);
        imagefill($small, 0, 0, (int) imagecolorallocatealpha($small, 0, 0, 0, 127));
        imagecopyresampled($small, $source, 0, 0, 0, 0, imagesx($small), self::SMALL_HEIGHT, $width, $height);
        ob_start();
        $picture['mime'] === 'image/jpeg' ? imagejpeg($small, null, 86) : imagepng($small, null, 9);
        return ['bytes' => (string) ob_get_clean(), 'mime' => $picture['mime']];
    }

    /** The logo, or null when none is uploaded (or its picture is gone). */
    public function image(): ?CertificateImage
    {
        $stored = $this->stored();
        $sha = (string) ($stored['sha'] ?? '');
        if (preg_match('/^[0-9a-f]{64}$/D', $sha) !== 1) return null;
        $image = CertificateImage::fromArray($stored);
        return $image !== null && $this->assets->exists($sha) ? $image : null;
    }

    /** The logo's version: the first 16 characters of its SHA-256, which name it in its address. */
    public function version(): ?string
    {
        $image = $this->image();
        return $image === null ? null : substr($image->sha, 0, 16);
    }

    /** The logo's full address on the given site address, or null without a logo. */
    public function url(string $base): ?string
    {
        $image = $this->image();
        if ($image === null) return null;
        return rtrim($base, '/') . self::PATH . substr($image->sha, 0, 16) . ($this->mime() === 'image/jpeg' ? '.jpg' : '.png');
    }

    /**
     * The logo for the top of a PDF drawn from a template: its picture as a data: address and its printed size in
     * millimetres, as large as fits the box given without changing its shape. Null without a logo.
     *
     * @return array{src:string,width_mm:float,height_mm:float}|null
     */
    public function forPdf(float $mostWidthMm, float $mostHeightMm): ?array
    {
        $image = $this->image();
        if ($image === null) return null;
        $src = $this->assets->dataUri($image->sha);
        if ($src === null) return null;
        $scale = min($mostWidthMm / max(1, $image->width), $mostHeightMm / max(1, $image->height));
        return ['src' => $src, 'width_mm' => floor($image->width * $scale * 10) / 10, 'height_mm' => floor($image->height * $scale * 10) / 10];
    }

    /**
     * The picture for its address: the logo or one of the logos before it, by version. Null for anything else.
     *
     * @return array{bytes:string,mime:string}|null
     */
    public function picture(string $version): ?array
    {
        if (preg_match('/^[0-9a-f]{16}$/D', $version) !== 1) return null;
        $stored = $this->stored();
        foreach ([(string) ($stored['sha'] ?? ''), ...array_map('strval', (array) ($stored['before'] ?? []))] as $sha) {
            if (preg_match('/^[0-9a-f]{64}$/D', $sha) !== 1 || !str_starts_with($sha, $version)) continue;
            $asset = $this->assets->find($sha);
            return $asset === null ? null : ['bytes' => $asset['bytes'], 'mime' => $asset['mime_type']];
        }
        return null;
    }

    /**
     * Keeps an uploaded logo as the site logo.
     *
     * @return array{from:?string,to:string} the versions before and after, for the Activity log
     * @throws InvalidArgumentException in plain words when the file cannot be the logo
     */
    public function upload(string $bytes, ?int $actorId): array
    {
        if ($bytes === '') throw new InvalidArgumentException('Choose the logo file to upload.');
        if (self::isSvg($bytes)) $bytes = $this->drawn($bytes);
        try {
            $prepared = CertificateImage::prepare($bytes, CertificateImage::LOGO);
        } catch (InvalidArgumentException $refused) {
            // The certificate's words name only PNG and JPEG; the site logo may be SVG too.
            throw str_contains($refused->getMessage(), 'PNG or JPEG') ? new InvalidArgumentException('The logo must be a PNG, JPEG or SVG file of at most 12 MB.') : $refused;
        }
        $sha = $this->assets->store($prepared['bytes'], $prepared['mime'], $prepared['width'], $prepared['height'], $actorId);
        $before = $this->image();
        $this->save(['sha' => $sha, 'width' => $prepared['width'], 'height' => $prepared['height'], 'mime' => $prepared['mime']], $actorId);
        return ['from' => $before === null ? null : substr($before->sha, 0, 16), 'to' => substr($sha, 0, 16)];
    }

    /** @return ?string the version removed, null when there was none */
    public function remove(?int $actorId): ?string
    {
        $before = $this->image();
        if ($before === null) return null;
        $this->save(null, $actorId);
        return substr($before->sha, 0, 16);
    }

    /** Whether rsvg-convert is here to draw an SVG logo. */
    public function drawsSvg(): bool
    {
        return SvgRaster::tool($this->tool) !== null;
    }

    private function mime(): string
    {
        $saved = (string) ($this->stored()['mime'] ?? '');
        if ($saved !== '') return $saved;
        $image = $this->image();
        $asset = $image === null ? null : $this->assets->find($image->sha);
        return $asset === null ? 'image/png' : $asset['mime_type'];
    }

    /** @param array{sha:string,width:int,height:int,mime:string}|null $logo */
    private function save(?array $logo, ?int $actorId): void
    {
        $stored = $this->stored();
        $before = array_values(array_filter(array_map('strval', (array) ($stored['before'] ?? [])), static fn(string $sha): bool => preg_match('/^[0-9a-f]{64}$/D', $sha) === 1));
        $previous = (string) ($stored['sha'] ?? '');
        if ($previous !== '' && $previous !== ($logo['sha'] ?? '')) array_unshift($before, $previous);
        $before = array_slice(array_values(array_unique(array_diff($before, [$logo['sha'] ?? '']))), 0, self::KEPT);
        $this->options->set(self::OPTION, (string) json_encode(($logo ?? []) + ['before' => $before], JSON_UNESCAPED_SLASHES), $actorId);
        $this->address = null;
    }

    /** @return array<string,mixed> */
    private function stored(): array
    {
        $decoded = json_decode($this->options->get(self::OPTION, '{}'), true);
        return is_array($decoded) ? $decoded : [];
    }

    private static function isSvg(string $bytes): bool
    {
        $start = ltrim(substr($bytes, 0, 2048));
        return preg_match('/^(<\?xml[^>]*>\s*)?(<!--.*?-->\s*)*(<!DOCTYPE[^>]*>\s*)?<svg\b/is', $start) === 1;
    }

    /** An SVG logo drawn as PNG, as large as fits 1200 by 600 pixels, on a transparent ground. */
    private function drawn(string $svg): string
    {
        if (strlen($svg) > self::SVG_MOST_BYTES) throw new InvalidArgumentException('An SVG logo can be at most 2 MB.');
        $tool = SvgRaster::tool($this->tool) ?? throw new InvalidArgumentException('This server cannot draw SVG: upload the logo as a PNG file, or install librsvg2-bin.');
        try {
            return SvgRaster::png($tool, $svg, ['--width=1200', '--height=600', '--keep-aspect-ratio'], self::SVG_SECONDS);
        } catch (RuntimeException) {
            throw new InvalidArgumentException('The SVG logo could not be drawn. Save it again from the program that made it, or upload it as a PNG file.');
        }
    }
}
