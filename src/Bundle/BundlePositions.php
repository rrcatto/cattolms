declare(strict_types=1);

namespace CattoLearning\Bundle;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\OptionRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\PositionBands;
use CattoLearning\Support\PositionRanges;
use InvalidArgumentException;

final class BundlePositions
{
    /** The app_options key: the bands as JSON, {"FIN": 10000, ...}. */
    public const OPTION = 'bundle.position_ranges';

    private readonly PositionRanges $bands;

    public function __construct(OptionRepository $options, private readonly BundleRepository $bundles, private readonly TransactionManager $transactions, private readonly AuditRepository $audit)
    {
        $this->bands = new PositionRanges($options, self::OPTION, 'bundle');
    }

    /** @return array<string,int> prefix => start, lowest start first */
    public function ranges(): array
    {
        return $this->bands->ranges();
    }

    /**
     * @param array<int,mixed> $prefixes
     * @param array<int,mixed> $starts
     * @return array<string,int> what was saved
     */
    public function save(array $prefixes, array $starts, int $actor): array
    {
        return $this->bands->save($prefixes, $starts, $actor);
    }

    /** @return array{rows:list<array{prefix:string,start:string,band:string}>,summary:string} */
    public function view(): array
    {
        return $this->bands->view();
    }

    /** A bundle's position as typed: empty for none, else a whole number from 1. */
    public static function typed(mixed $value): ?int
    {
        try {
            return PositionBands::typed($value, 'Enter the bundle\'s position as a whole number from 1, such as 10100, or leave it empty.');
        } catch (InvalidArgumentException $wrong) {
            // As every other refusal of a bundle form, so the form comes back with what was typed.
            throw new \RuntimeException($wrong->getMessage(), 0, $wrong);
        }
    }

    /**
     * Gives a bundle without a position the next free number in its code's band; one with a position, or whose prefix has
     * no band, is left as it is. Answers the number given.
     */
    public function fill(int $id): ?int
    {
        $bundle = $this->bundles->find($id);
        if ($bundle === null || $bundle['catalogue_position'] !== null) return null;
        $position = PositionBands::next($this->ranges(), (string) $bundle['code'], $this->bundles->positions());
        if ($position !== null) $this->bundles->setPosition($id, $position, false);
        return $position;
    }

    /**
     * Puts a bundle after another, or first when $afterId is null: from a drag.
     *
     * @return array<int,int> each bundle whose number changed, with its new number
     */
    public function arrange(int $id, ?int $afterId, int $actor): array
    {
        if ($afterId === $id) throw new InvalidArgumentException('A bundle cannot go after itself.');
        $changed = $this->transactions->run(function () use ($id, $afterId): array {
            $order = $this->bundles->orderForUpdate();
            $ids = array_column($order, 'id');
            $positions = array_column($order, 'position', 'id');
            if (!in_array($id, $ids, true)) throw new InvalidArgumentException('That bundle does not exist.');
            $ids = array_values(array_filter($ids, static fn(int $other): bool => $other !== $id));
            $index = 0;
            if ($afterId !== null) {
                $found = array_search($afterId, $ids, true);
                if ($found === false) throw new InvalidArgumentException('The bundle to put it after does not exist.');
                $index = $found + 1;
            }
            array_splice($ids, $index, 0, [$id]);
            $changes = [];
            foreach (PositionBands::place(array_map(static fn(int $other): ?int => $positions[$other], $ids), $index) as $at => $number) {
                if (($positions[$ids[$at]] ?? null) === $number) continue;
                $changes[$ids[$at]] = $number;
                $this->bundles->setPosition($ids[$at], $number);
            }
            return $changes;
        });
        $this->audit->record($actor, 'bundle.arranged', ['bundle_id' => $id, 'after_bundle_id' => $afterId, 'positions' => $changed]);
        return $changed;
    }

    /**
     * The ⋯ menu's moves, without JavaScript: up, down or to the top.
     *
     * @return array<int,int> each bundle whose number changed, with its new number
     */
    public function move(int $id, string $direction, int $actor): array
    {
        $ids = array_column($this->transactions->run(fn(): array => $this->bundles->orderForUpdate()), 'id');
        $index = array_search($id, $ids, true);
        if ($index === false) throw new InvalidArgumentException('That bundle does not exist.');
        if ($direction === 'up' && $index === 0) throw new InvalidArgumentException('That bundle is already first.');
        $after = match ($direction) {
            'up' => $index >= 2 ? $ids[$index - 2] : null,
            'down' => $ids[$index + 1] ?? throw new InvalidArgumentException('That bundle is already last.'),
            'top' => null,
            default => throw new InvalidArgumentException('Choose up, down or to the top.'),
        };
        return $this->arrange($id, $after, $actor);
    }

    /**
     * Renumber (owner, 2026-11-12): every bundle back in its prefix's band, from the band's start, 100 apart in the order
     * it is listed in now. A bundle whose prefix has no band keeps its number. Dates of change are left alone.
     *
     * @return array{changed:int,unbanded:list<string>,crowded:list<string>} how many moved, the codes with no band, the
     *         prefixes whose band is too narrow for them all
     */
    public function renumber(int $actor): array
    {
        $result = $this->transactions->run(function (): array {
            $rows = $this->bundles->orderForUpdate();
            $plan = PositionBands::renumber($this->ranges(), array_map(static fn(array $row): array => ['key' => $row['id'], 'code' => $row['code'], 'position' => $row['position']], $rows));
            foreach ($plan['changes'] as $id => $position) $this->bundles->setPosition((int) $id, $position, false);
            $codes = array_column($rows, 'code', 'id');
            return ['changed' => count($plan['changes']), 'unbanded' => array_map(static fn(int|string $id): string => (string) $codes[$id], $plan['unbanded']), 'crowded' => $plan['crowded']];
        });
        $this->audit->record($actor, 'bundle.renumbered', $result);
        return $result;
    }
}
