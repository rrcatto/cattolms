type as the fallback for a long list, numbered 100 apart from the start of a band for each code prefix, and "a renumber
bundle position numbers button which will redo the numbering"; bands 10,000 apart). The same rules as the catalogue's
courses (Course\CataloguePositions, Support\PositionBands):

- Settings > Bundle positions: each bundle code prefix and where its band starts (Support\PositionRanges).
- fill(): a bundle arriving without a position (made here, or new from a catalogue package) takes the next free number in
  its prefix's band; one with a position is never moved.
- arrange() and move(): a drag puts a bundle after another, the ⋯ menu up, down or to the top; halfway between its new
  neighbours, or its crowded neighbours spread between the nearest numbers with room.
- renumber(): every bundle back in its prefix's band, 100 apart in its present order; one whose prefix has no band keeps
  its number.

