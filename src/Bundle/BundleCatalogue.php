    /** What a package's bundle may say about itself, at most. */
    private const LIMITS = ['title' => 240, 'short_description' => 320, 'description_html' => 100000, 'cover_svg' => 200000];

    public function __construct(
        private readonly BundleRepository $bundles,
        private readonly CourseRepository $courses,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
        private readonly ClockInterface $clock,
    ) {}

    /**
     * The bundles whose courses are all among these course codes, as a package's `bundles` list.
     *
     * @param list<string> $courseCodes the codes of the courses being exported
     * @return list<array<string,mixed>>
     */
    public function export(array $courseCodes): array
    {
        $exported = array_fill_keys($courseCodes, true);
        $entries = [];
        foreach ($this->bundles->allWithCourseCodes() as $bundle) {
            $codes = $bundle['course_codes'];
            if ($codes === [] || array_diff($codes, array_keys($exported)) !== []) continue;
            $entries[] = [
                'code' => (string) $bundle['code'], 'slug' => (string) $bundle['slug'], 'title' => (string) $bundle['title'],
                'short_description' => (string) $bundle['short_description'], 'description_html' => (string) $bundle['description_html'], 'cover_svg' => (string) $bundle['cover_svg'],
                'courses' => array_values($codes),
                'price_minor_units' => $bundle['offer_id'] === null ? null : (int) $bundle['price_minor_units'],
                'was_price_minor_units' => $bundle['was_price_minor_units'] === null ? null : (int) $bundle['was_price_minor_units'],
                'currency' => $bundle['offer_id'] === null ? null : (string) $bundle['currency_code'],
                'access_period_seconds' => $bundle['offer_id'] === null ? null : (int) $bundle['access_period_seconds'],
                'on_sale' => $bundle['offer_id'] === null ? null : (bool) $bundle['offer_active'],
                'status' => (string) $bundle['status'],
                'available_from' => self::moment($bundle['available_from']), 'available_until' => self::moment($bundle['available_until']),
            ];
        }
        return $entries;
    }

    /**
     * What importing these bundles would do, changing nothing.
     *
     * @param list<mixed> $entries the package's `bundles`
     * @param array<string,true> $packageCourses the codes of the courses the package brings (those not left out)
     * @return list<array<string,mixed>> each: code, title, action (new, update, unchanged, skip), reason, changes (words),
     *         differences (for a bundle here: each kind, words and any problem), bundle_id, status
     */
    public function plan(array $entries, array $packageCourses): array
    {
        $rows = [];
        $codes = [];
        $slugs = [];
        foreach ($entries as $index => $entry) {
            $entry = is_array($entry) ? $entry : [];
            $code = CourseCode::normalise((string) ($entry['code'] ?? ''));
            $row = ['code' => $code, 'title' => trim((string) ($entry['title'] ?? '')) ?: 'Bundle ' . ($index + 1), 'action' => 'skip', 'reason' => '', 'changes' => [], 'differences' => [], 'bundle_id' => null,
                'status' => (string) ($entry['status'] ?? 'draft'), 'courses' => array_values(array_map(static fn(mixed $c): string => CourseCode::normalise((string) $c), (array) ($entry['courses'] ?? [])))];
            $why = $this->refusal($entry, $code, $packageCourses, $codes);
            if ($why !== null) {
                $rows[] = ['reason' => $why] + $row;
                continue;
            }
            $codes[$code] = true;
            $existing = $this->bundles->findByCode($code);
            if ($existing !== null) {
                $row['bundle_id'] = (int) $existing['id'];
                $row['site_title'] = (string) $existing['title'];
                $row['differences'] = array_map(static fn(array $d): array => $d + ['choosable' => $d['problem'] === null], $this->differences($existing, $entry));
                $row['changes'] = array_column($row['differences'], 'words');
                $row['action'] = $row['changes'] === [] ? 'unchanged' : 'update';
                $rows[] = $row;
                continue;
            }
            $slug = (string) ($entry['slug'] ?? '');
            $holder = $this->bundles->findBySlug($slug);
            if ($holder !== null || isset($slugs[$slug])) {
                $rows[] = ['reason' => $holder !== null ? 'The address /bundles/' . $slug . ' is another bundle\'s here: “' . $holder['title'] . '” (' . $holder['code'] . '). To update that bundle from this package, give it the code ' . $code . ' and import again.'
                    : 'Another bundle in this package has the address /bundles/' . $slug . '.'] + $row;
                continue;
            }
            $slugs[$slug] = true;
            $row['action'] = 'new';
            $row['changes'] = ['Courses: ' . implode(', ', $row['courses']),
                ($entry['price_minor_units'] ?? null) === null ? 'No price' : 'Price: ' . Money::strictMinorUnits((int) $entry['price_minor_units'], (string) ($entry['currency'] ?? Money::platformCurrency()))->format() . ', ' . AccessPeriod::label((int) $entry['access_period_seconds']) . ' of access'];
            if (($entry['available_from'] ?? null) !== null) $row['changes'][] = 'On sale from ' . BundleRules::saleDate((string) $entry['available_from'], true);
            $rows[] = $row;
        }
        return $rows;
    }

    /**
     * Imports the chosen bundles (null: every one the plan does not leave out), once the package's courses are in.
     *
     * @param list<mixed> $entries the package's `bundles`
     * @param list<array<string,mixed>> $plan plan() for the same entries
     * @param list<string>|null $chosen the codes ticked on the review
     * @param array<string,list<string>> $keep by bundle code, the differences whose site version is kept
     * @return array{bundles:list<array<string,mixed>>,counts:array<string,int>}
     */
    public function apply(array $entries, array $plan, ?array $chosen, int $userId, array $keep = []): array
    {
        $byCode = [];
        foreach ($entries as $entry) if (is_array($entry)) $byCode[CourseCode::normalise((string) ($entry['code'] ?? ''))] ??= $entry;
        $chosen = $chosen === null ? null : array_map([CourseCode::class, 'normalise'], $chosen);
        $report = ['bundles' => [], 'counts' => ['imported' => 0, 'updated' => 0, 'unchanged' => 0, 'left_out' => 0, 'skipped' => 0, 'failed' => 0]];
        foreach ($plan as $row) {
            $outcome = ['code' => $row['code'], 'title' => $row['title'], 'bundle_id' => $row['bundle_id'], 'outcome' => '', 'details' => []];
            if ($row['action'] === 'skip') {
                $report['bundles'][] = array_replace($outcome, ['outcome' => 'skipped', 'details' => [$row['reason']]]);
                $report['counts']['skipped']++;
                continue;
            }
            // A bundle with no difference has no tick to untick: it is unchanged, never "left out".
            if ($row['action'] === 'unchanged') {
                $report['bundles'][] = array_replace($outcome, ['outcome' => 'unchanged']);
                $report['counts']['unchanged']++;
                continue;
            }
            if ($chosen !== null && !in_array($row['code'], $chosen, true)) {
                $report['bundles'][] = array_replace($outcome, ['outcome' => 'left out']);
                $report['counts']['left_out']++;
                continue;
            }
            $entry = $byCode[$row['code']] ?? [];
            try {
                $outcome = $row['action'] === 'new'
                    ? array_replace($outcome, $this->create($entry, $row['code'], $userId), ['outcome' => 'imported'])
                    : array_replace($outcome, ['details' => $this->update((int) $row['bundle_id'], $entry, $userId, array_map('strval', (array) ($keep[$row['code']] ?? []))), 'outcome' => 'updated']);
                if ($outcome['outcome'] === 'updated' && $outcome['details'] === []) $outcome['outcome'] = 'unchanged';
                $report['counts'][$outcome['outcome']]++;
            } catch (Throwable $failed) {
                $outcome = array_replace($outcome, ['outcome' => 'failed', 'details' => [$failed->getMessage()]]);
                $report['counts']['failed']++;
            }
            $report['bundles'][] = $outcome;
        }
        return $report;
    }

    /**
     * A new bundle from the package: its words, courses, price and sale dates, and its status where it may have it.
     *
     * @param array<string,mixed> $entry
     * @return array{bundle_id:int,details:list<string>}
     */
    private function create(array $entry, string $code, int $userId): array
    {
        return $this->transactions->run(function () use ($entry, $code, $userId): array {
            $now = $this->clock->now()->format(DATE_ATOM);
            $courseIds = $this->courseIds((array) ($entry['courses'] ?? []));
            $id = $this->bundles->create(['code' => $code] + self::words($entry) + ['slug' => (string) $entry['slug'],
                'available_from' => self::moment($entry['available_from'] ?? null), 'available_until' => self::moment($entry['available_until'] ?? null)], $userId, $now);
            $this->bundles->replaceCourses($id, array_column($courseIds, 'id'));
            $details = ['Courses: ' . count($courseIds)];
            if (($entry['price_minor_units'] ?? null) !== null) {
                $this->bundles->saveOffer($id, (int) $entry['price_minor_units'], (string) ($entry['currency'] ?? Money::platformCurrency()), (int) $entry['access_period_seconds'],
                    (bool) ($entry['on_sale'] ?? true), $userId, $now, ($entry['was_price_minor_units'] ?? null) === null ? null : (int) $entry['was_price_minor_units']);
                $details[] = 'Price: ' . Money::strictMinorUnits((int) $entry['price_minor_units'], (string) ($entry['currency'] ?? Money::platformCurrency()))->format();
            }
            // Its status as it was where it came from: published only while every course is published here and it has a price.
            $status = (string) ($entry['status'] ?? 'draft');
            if ($status === 'published') {
                $unpublished = array_values(array_filter($courseIds, static fn(array $course): bool => $course['status'] !== 'published'));
                if ($unpublished !== []) {
                    $details[] = 'Left as a draft: ' . implode(', ', array_column($unpublished, 'code')) . (count($unpublished) === 1 ? ' is' : ' are') . ' not published here';
                } elseif (($entry['price_minor_units'] ?? null) === null) {
                    $details[] = 'Left as a draft: it has no price';
                } else {
                    $this->bundles->setStatus($id, 'published', $userId, $now);
                    $details[] = 'Published';
                }
            } elseif ($status === 'retired') {
                $this->bundles->setStatus($id, 'retired', $userId, $now);
                $details[] = 'Retired';
            }
            $this->audit->record($userId, 'bundle.created', ['bundle_id' => $id, 'code' => $code, 'slug' => (string) $entry['slug'], 'title' => self::words($entry)['title'], 'source' => 'catalogue']);
            return ['bundle_id' => $id, 'details' => $details];
        });
    }

    /**
     * A bundle already here takes the file's version of every difference but those kept as this site's (owner,
     * 2026-11-06): its words, courses, address and sale dates, then its price, then its status, which a published
     * bundle has only while every course is published here and it has a price on sale. Nothing replaced is kept.
     *
     * @param array<string,mixed> $entry
     * @param list<string> $keep the kinds kept as this site's
     * @return list<string> what was done
     */
    private function update(int $id, array $entry, int $userId, array $keep = []): array
    {
        return $this->transactions->run(function () use ($id, $entry, $userId, $keep): array {
            $bundle = $this->bundles->find($id, true) ?? throw new \RuntimeException('The bundle is no longer on the site.');
            $take = array_values(array_diff(array_column(array_filter($this->differences($bundle, $entry), static fn(array $d): bool => $d['problem'] === null), 'kind'), $keep));
            if ($take === []) return [];
            $now = $this->clock->now()->format(DATE_ATOM);
            $done = [];
            $words = self::words($entry);
            $fields = ['code' => (string) $bundle['code'], 'slug' => (string) $bundle['slug'], 'title' => (string) $bundle['title'], 'short_description' => (string) $bundle['short_description'],
                'description_html' => (string) $bundle['description_html'], 'cover_svg' => (string) $bundle['cover_svg'],
                'available_from' => self::moment($bundle['available_from']), 'available_until' => self::moment($bundle['available_until'])];
            foreach (['title' => 'title', 'short_description' => 'short_description', 'description' => 'description_html', 'cover' => 'cover_svg'] as $kind => $field) {
                if (in_array($kind, $take, true)) { $fields[$field] = $words[$field]; $done[] = self::LABELS[$kind]; }
            }
            if (in_array('address', $take, true)) { $fields['slug'] = (string) $entry['slug']; $done[] = 'Address: /bundles/' . $entry['slug']; }
            if (in_array('sale_dates', $take, true)) {
                $fields['available_from'] = self::moment($entry['available_from'] ?? null);
                $fields['available_until'] = self::moment($entry['available_until'] ?? null);
                $done[] = 'On sale: ' . self::saleWords($fields['available_from'], $fields['available_until']);
            }
            $this->bundles->update($id, $fields, $userId, $now);
            if (in_array('courses', $take, true)) {
                $courseIds = $this->courseIds((array) ($entry['courses'] ?? []));
                $this->bundles->replaceCourses($id, array_column($courseIds, 'id'));
                $done[] = 'Courses: ' . implode(', ', array_column($courseIds, 'code'));
            }
            if (in_array('price', $take, true)) {
                if (($entry['price_minor_units'] ?? null) === null) {
                    // A bundle that was sold keeps its offer for its orders: the file's "no price" takes it off sale.
                    if ($bundle['offer_id'] !== null) $this->bundles->saveOffer($id, (int) $bundle['price_minor_units'], (string) $bundle['currency_code'], (int) $bundle['access_period_seconds'], false, $userId, $now,
                        $bundle['was_price_minor_units'] === null ? null : (int) $bundle['was_price_minor_units']);
                    $done[] = 'Price: none';
                } else {
                    $this->bundles->saveOffer($id, (int) $entry['price_minor_units'], (string) ($entry['currency'] ?? Money::platformCurrency()), (int) $entry['access_period_seconds'],
                        (bool) ($entry['on_sale'] ?? true), $userId, $now, ($entry['was_price_minor_units'] ?? null) === null ? null : (int) $entry['was_price_minor_units']);
                    $done[] = 'Price: ' . self::priceWords(self::filePrice($entry));
                }
            }
            if (in_array('status', $take, true)) {
                $status = (string) ($entry['status'] ?? 'draft');
                $after = $this->bundles->find($id) ?? $bundle;
                $courses = array_map(fn(array $c): array => ['code' => (string) ($this->courses->findById((int) $c['course_id'])['code'] ?? ''), 'status' => (string) ($this->courses->findById((int) $c['course_id'])['status'] ?? '')], $this->bundles->courses($id));
                $unpublished = array_values(array_filter($courses, static fn(array $c): bool => $c['status'] !== 'published'));
                if ($status === 'published' && count($courses) < BundleRules::MINIMUM_COURSES) {
                    $done[] = 'Left ' . $bundle['status'] . ': a published bundle needs at least two courses';
                } elseif ($status === 'published' && $unpublished !== []) {
                    $done[] = 'Left ' . $bundle['status'] . ': ' . implode(', ', array_column($unpublished, 'code')) . (count($unpublished) === 1 ? ' is' : ' are') . ' not published here';
                } elseif ($status === 'published' && ($after['offer_id'] === null || !(bool) $after['offer_active'])) {
                    $done[] = 'Left ' . $bundle['status'] . ': it has no price on sale';
                } else {
                    $this->bundles->setStatus($id, $status, $userId, $now);
                    $done[] = 'Status: ' . $status;
                }
            }
            $this->audit->record($userId, 'bundle.updated', ['bundle_id' => $id, 'changed' => $done, 'source' => 'catalogue']);
            return $done;
        });
    }

    /** What each difference is called where it is listed. */
    private const LABELS = ['title' => 'Title', 'short_description' => 'Short description', 'description' => 'Description', 'cover' => 'Cover picture'];

    /**
     * Everything the file would change in a bundle here, each by its kind, in words saying this site's and then the
     * file's, with a problem when the file's cannot be taken (its address another bundle's).
     *
     * @param array<string,mixed> $bundle
     * @param array<string,mixed> $entry
     * @return list<array{kind:string,words:string,problem:?string}>
     */
    private function differences(array $bundle, array $entry): array
    {
        $found = [];
        $words = self::words($entry);
        if ((string) $bundle['title'] !== $words['title']) $found[] = ['kind' => 'title', 'words' => 'Title: ' . $bundle['title'] . ' → ' . $words['title'], 'problem' => null];
        foreach (['short_description' => 'short_description', 'description' => 'description_html', 'cover' => 'cover_svg'] as $kind => $field) {
            if ((string) $bundle[$field] !== $words[$field]) $found[] = ['kind' => $kind, 'words' => self::LABELS[$kind] . ': the file\'s is different', 'problem' => null];
        }
        $here = array_map(fn(array $c): string => (string) ($this->courses->findById((int) $c['course_id'])['code'] ?? ''), $this->bundles->courses((int) $bundle['id']));
        $file = array_values(array_map(static fn(mixed $c): string => CourseCode::normalise((string) $c), (array) ($entry['courses'] ?? [])));
        if ($here !== $file) {
            $adds = array_values(array_diff($file, $here));
            $removes = array_values(array_diff($here, $file));
            $found[] = ['kind' => 'courses', 'words' => 'Courses: ' . ($adds === [] && $removes === [] ? 'the same courses in the file\'s order, ' . implode(', ', $file)
                : implode(', ', array_filter([$adds === [] ? '' : 'adds ' . implode(', ', $adds), $removes === [] ? '' : 'removes ' . implode(', ', $removes)]))), 'problem' => null];
        }
        $sitePrice = $bundle['offer_id'] === null ? null : ['price' => (int) $bundle['price_minor_units'], 'was' => $bundle['was_price_minor_units'] === null ? null : (int) $bundle['was_price_minor_units'],
            'currency' => (string) $bundle['currency_code'], 'seconds' => (int) $bundle['access_period_seconds'], 'on_sale' => (bool) $bundle['offer_active']];
        $filePrice = self::filePrice($entry);
        $silent = $filePrice === null && $sitePrice !== null && !$sitePrice['on_sale'];
        if ($sitePrice !== $filePrice && !$silent) $found[] = ['kind' => 'price', 'words' => 'Price: ' . self::priceWords($sitePrice) . ' → ' . self::priceWords($filePrice), 'problem' => null];
        $status = (string) ($entry['status'] ?? 'draft');
        if ($status !== (string) $bundle['status']) $found[] = ['kind' => 'status', 'words' => 'Status: ' . $bundle['status'] . ' → ' . $status, 'problem' => null];
        $from = self::moment($entry['available_from'] ?? null);
        $until = self::moment($entry['available_until'] ?? null);
        if ([$from, $until] !== [self::moment($bundle['available_from']), self::moment($bundle['available_until'])]) {
            $found[] = ['kind' => 'sale_dates', 'words' => 'On sale: ' . self::saleWords(self::moment($bundle['available_from']), self::moment($bundle['available_until'])) . ' → ' . self::saleWords($from, $until), 'problem' => null];
        }
        $slug = (string) ($entry['slug'] ?? '');
        if ($slug !== (string) $bundle['slug']) {
            $found[] = ['kind' => 'address', 'words' => 'Address: /bundles/' . $bundle['slug'] . ' → /bundles/' . $slug,
                'problem' => $this->bundles->slugTaken($slug, (int) $bundle['id']) ? 'Another bundle here has the address /bundles/' . $slug . '.' : null];
        }
        return $found;
    }

    /**
     * The file's price as the site's is compared, or null when it has none.
     *
     * @param array<string,mixed> $entry
     * @return array{price:int,was:?int,currency:string,seconds:int,on_sale:bool}|null
     */
    private static function filePrice(array $entry): ?array
    {
        if (($entry['price_minor_units'] ?? null) === null) return null;
        return ['price' => (int) $entry['price_minor_units'], 'was' => ($entry['was_price_minor_units'] ?? null) === null ? null : (int) $entry['was_price_minor_units'],
            'currency' => (string) ($entry['currency'] ?? Money::platformCurrency()), 'seconds' => (int) $entry['access_period_seconds'], 'on_sale' => (bool) ($entry['on_sale'] ?? true)];
    }

    /** @param array{price:int,was:?int,currency:string,seconds:int,on_sale:bool}|null $price */
    private static function priceWords(?array $price): string
    {
        if ($price === null) return 'no price';
        $money = static fn(int $minor): string => Money::strictMinorUnits($minor, $price['currency'])->format();
        return $money($price['price']) . ($price['was'] !== null ? ' (was ' . $money($price['was']) . ')' : '') . ' for ' . AccessPeriod::label($price['seconds']) . ($price['on_sale'] ? '' : ', not on sale');
    }

    private static function saleWords(?string $from, ?string $until): string
    {
        if ($from === null && $until === null) return 'with no dates';
        return trim(($from === null ? '' : 'from ' . BundleRules::saleDate($from, true)) . ($until === null ? '' : ' until ' . BundleRules::saleDate($until, true)));
    }

    /**
     * Why a package's bundle is left out, or null.
     *
     * @param array<string,mixed> $entry
     * @param array<string,true> $packageCourses
     * @param array<string,true> $seen the codes of the bundles before it
     */
    private function refusal(array $entry, string $code, array $packageCourses, array $seen): ?string
    {
        if (!CourseCode::isValid($code)) return 'It has no bundle code it can use' . ($code === '' ? '' : ' ("' . $code . '")') . ', and an import knows a bundle only by its code.';
        if (isset($seen[$code])) return 'Another bundle in this package has the code ' . $code . '.';
        $course = $this->courses->findByCode($code);
        if ($course !== null || isset($packageCourses[$code])) return 'The code ' . $code . ' is a course\'s' . ($course !== null ? ' here: “' . $course['title'] . '”' : ' in this package') . '. A code names one course or one bundle.';
        foreach (self::LIMITS as $field => $limit) {
            if (!is_string($entry[$field] ?? '') || mb_strlen((string) ($entry[$field] ?? '')) > $limit) return 'Its ' . str_replace(['_html', '_'], ['', ' '], $field) . ' is not one this site can hold.';
        }
        if (trim((string) ($entry['title'] ?? '')) === '') return 'It has no title.';
        if (preg_match('/^[a-z0-9]+(-[a-z0-9]+)*$/D', (string) ($entry['slug'] ?? '')) !== 1 || strlen((string) $entry['slug']) > 180) return 'Its web address is not one this site can use.';
        $cover = trim((string) ($entry['cover_svg'] ?? ''));
        if ($cover !== '' && !str_starts_with($cover, '<svg')) return 'Its cover is not SVG.';
        if (!in_array((string) ($entry['status'] ?? 'draft'), BundleRules::STATUSES, true)) return 'Its status is not draft, published or retired.';
        $courses = (array) ($entry['courses'] ?? []);
        if (count($courses) < BundleRules::MINIMUM_COURSES) return 'It has fewer than two courses.';
        foreach ($courses as $courseCode) {
            $courseCode = CourseCode::normalise((string) $courseCode);
            if (!isset($packageCourses[$courseCode]) && $this->courses->findByCode($courseCode) === null) return 'Its course ' . $courseCode . ' is neither in this package nor on this site.';
        }
        if (count(array_unique(array_map(static fn(mixed $c): string => CourseCode::normalise((string) $c), $courses))) !== count($courses)) return 'It names a course twice.';
        if (($entry['price_minor_units'] ?? null) !== null) {
            $price = $entry['price_minor_units'];
            $was = $entry['was_price_minor_units'] ?? null;
            $period = $entry['access_period_seconds'] ?? null;
            if (!is_int($price) || $price < 1 || !is_int($period) || $period < 1 || ($was !== null && (!is_int($was) || $was <= $price))) return 'Its price is not one this site can take.';
            if (preg_match('/^[A-Z]{3}$/', (string) ($entry['currency'] ?? Money::platformCurrency())) !== 1) return 'Its currency is not one this site can take.';
        }
        try {
            $from = ($entry['available_from'] ?? null) === null ? null : new DateTimeImmutable((string) $entry['available_from']);
            $until = ($entry['available_until'] ?? null) === null ? null : new DateTimeImmutable((string) $entry['available_until']);
        } catch (Throwable) {
            return 'Its sale dates cannot be read.';
        }
        if ($from !== null && $until !== null && $until <= $from) return 'Its sale ends before it starts.';
        return null;
    }

    /**
     * These course codes' courses on the site, in order.
     *
     * @param list<mixed> $codes
     * @return list<array{id:int,code:string,status:string}>
     */
    private function courseIds(array $codes): array
    {
        $found = [];
        foreach ($codes as $code) {
            $code = CourseCode::normalise((string) $code);
            $course = $this->courses->findByCode($code) ?? throw new \RuntimeException('Its course ' . $code . ' is not on this site: it was left out of the import or could not be imported.');
            $found[] = ['id' => (int) $course['id'], 'code' => $code, 'status' => (string) $course['status']];
        }
        return $found;
    }

    /**
     * @param array<string,mixed> $entry
     * @return array{title:string,short_description:string,description_html:string,cover_svg:string}
     */
    private static function words(array $entry): array
    {
        return ['title' => trim((string) ($entry['title'] ?? '')), 'short_description' => trim((string) ($entry['short_description'] ?? '')),
            'description_html' => trim((string) ($entry['description_html'] ?? '')), 'cover_svg' => trim((string) ($entry['cover_svg'] ?? ''))];
    }

    private static function moment(mixed $value): ?string
    {
        return $value === null || $value === '' ? null : (new DateTimeImmutable((string) $value))->format(DATE_ATOM);
    }
