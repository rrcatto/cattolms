declare(strict_types=1);

namespace CattoLearning\Http\Symfony\Listener;

use CattoLearning\Seed\SeedDatabaseService;
use CattoLearning\Seed\SeedQueue;
use Closure;
use Symfony\Component\DependencyInjection\Attribute\AutowireServiceClosure;
use Symfony\Component\EventDispatcher\Attribute\AsEventListener;
use Symfony\Component\HttpKernel\KernelEvents;

#[AsEventListener(event: KernelEvents::TERMINATE)]
final class SeedRunListener
{
    /** @param Closure():SeedDatabaseService $seeds */
    public function __construct(
        private readonly SeedQueue $queue,
        #[AutowireServiceClosure(SeedDatabaseService::class)] private readonly Closure $seeds
    ) {
    }

    public function __invoke(): void
    {
        $run = $this->queue->take();
        if ($run !== null) ($this->seeds)()->runQueued($run);
    }
}
