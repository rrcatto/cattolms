Renders the platform's own error page for a web request that failed.

Architectural boundary: HTTP. It chooses a status and a message and hands both to the theme; it
resolves nothing and logs only what it did not expect.

Replaces Fat-Free's ONERROR handler, which did the same job and went with the router. Without it a
failed request falls back to Symfony's default page, which is unstyled, carries no navigation and
looks like a different site.

Two rules it keeps from the handler it replaces:

  a 5xx never shows its message to the reader unless debug is on, because the message is as likely
  to be a database error as anything a reader could act on - the detail goes to the log instead;

  the API surface is left alone. It answers with a problem document of its own and a themed HTML
  page would be an unparseable response to a JSON client.

It says what happened in plain words (owner, 2026-10-23: "should it not fail more gracefully?"): the kind of error
(not found, not allowed, something broken, or a request the site could not take) chooses the page's title and what
the reader can do next, and the router's own messages ("No route found for ...") and an expired form's token are
put in words a reader understands. The status code stays in small print, for reporting a fault.

