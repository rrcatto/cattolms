declare(strict_types=1);

namespace CattoLearning\Http\Symfony\Listener;

use CattoLearning\Company\NoCompanyChosen;
use Symfony\Component\EventDispatcher\EventSubscriberInterface;
use Symfony\Component\HttpFoundation\RedirectResponse;
use Symfony\Component\HttpKernel\Event\ExceptionEvent;
use Symfony\Component\HttpKernel\KernelEvents;

final class NoCompanyChosenListener implements EventSubscriberInterface
{
    /** @return array<string,array{0:string,1:int}> */
    public static function getSubscribedEvents(): array
    {
        return [KernelEvents::EXCEPTION => ['onException', 16]];
    }

    public function onException(ExceptionEvent $event): void
    {
        $exception = $event->getThrowable();
        if (!$exception instanceof NoCompanyChosen) {
            return;
        }
        $_SESSION['flash'][] = ['type' => 'info', 'message' => $exception->getMessage()];
        $event->setResponse(new RedirectResponse('/company/picker'));
    }
}
