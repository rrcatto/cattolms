namespace CattoLearning\Http\Symfony\Listener;

use CattoLearning\Auth\AuthService;
use Symfony\Component\EventDispatcher\EventSubscriberInterface;
use Symfony\Component\HttpFoundation\RedirectResponse;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Event\RequestEvent;
use Symfony\Component\HttpKernel\KernelEvents;

final class AccountStepListener implements EventSubscriberInterface
{
    /** Where each step is done. */
    private const PAGES = ['id_number' => '/account/id-number', 'adults_only' => '/account/adults-only'];

    /** Addresses a pending step never holds up. */
    private const OPEN = ['/account/id-number', '/account/adults-only', '/logout', '/auth/', '/login', '/register', '/terms', '/refunds', '/privacy', '/help', '/faq', '/contact',
        '/api/', '/webhooks/', '/m/', '/theme/', '/assets/', '/css/', '/js/', '/img/', '/robots.txt', '/sitemap', '/certificates/', '/transcripts/', '/favicon', '/_'];

    public function __construct(private readonly AuthService $auth) {}

    /** @return array<string,array{0:string,1:int}> */
    public static function getSubscribedEvents(): array
    {
        // After the router (32), so the request is known to be one this site answers.
        return [KernelEvents::REQUEST => ['onRequest', 16]];
    }

    public function onRequest(RequestEvent $event): void
    {
        if (!$event->isMainRequest()) return;
        $request = $event->getRequest();
        $path = $request->getPathInfo();
        foreach (self::OPEN as $open) {
            if ($path === rtrim($open, '/') || str_starts_with($path, $open)) return;
        }
        $user = $this->auth->currentUser();
        if ($user === null || !isset(self::PAGES[$user->accountStep])) return;
        $target = self::PAGES[$user->accountStep] . '?return=' . rawurlencode($request->getRequestUri());
        if ($request->headers->has('HX-Request')) {
            // htmx swaps a response into the page; it is told to load the step's page instead.
            $event->setResponse(new Response('', 200, ['HX-Redirect' => $target]));
            return;
        }
        $event->setResponse(new RedirectResponse($target, 303));
    }
}
