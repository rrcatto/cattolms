declare(strict_types=1);

namespace CattoLearning\Http\Symfony;

use CattoLearning\Api\ApiScope;
use CattoLearning\Api\AuthorizationException;
use CattoLearning\Api\Security\ApiUser;
use CattoLearning\Course\CatalogueFilter;
use CattoLearning\Course\CourseService;
use CattoLearning\Support\Pagination;
use Symfony\Component\HttpFoundation\JsonResponse;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;
use Symfony\Component\Routing\Attribute\Route;
use Symfony\Component\Security\Http\Attribute\CurrentUser;
use Symfony\Component\Security\Http\Attribute\IsGranted;

final class ApiCourseController
{
    public function __construct(private readonly CourseService $courses)
    {
    }

    #[Route('/api/v1/courses', name: 'api_courses_index', methods: ['GET'])]
    #[IsGranted(ApiScope::COURSES_READ)]
    #[IsGranted('CATALOGUE.VIEW')]
    public function index(Request $request): JsonResponse
    {
        $pagination = Pagination::create(
            $request->query->get('page'),
            $request->query->get('page_size'),
            $this->courses->catalogueCount(CatalogueFilter::none())
        );

        return ApiResponse::page(
            $this->courses->catalogue(
                CatalogueFilter::none(),
                $pagination->pageSize,
                $pagination->offset
            ),
            $pagination->toArray()
        );
    }

    #[Route('/api/v1/courses/{slug}', name: 'api_courses_show', methods: ['GET'])]
    #[IsGranted(ApiScope::COURSES_READ)]
    #[IsGranted('CATALOGUE.VIEW')]
    public function show(string $slug): JsonResponse
    {
        $course = $this->courses->publicCourse($slug);
        if ($course === null) {
            throw new NotFoundHttpException('The course could not be found.');
        }

        return ApiResponse::data($course);
    }

    #[Route('/api/v1/admin/courses', name: 'api_courses_create', methods: ['POST'])]
    #[IsGranted(ApiScope::COURSES_WRITE)]
    #[IsGranted('COURSE.CREATE')]
    public function create(Request $request, #[CurrentUser] ApiUser $user): JsonResponse
    {
        $body = ApiRequest::jsonBody($request);
        if (!array_key_exists('certificate_enabled', $body)) {
            $body['certificate_enabled'] = true;
        }

        $courseId = $this->courses->createBlank($body, $user->identity->userId);

        return ApiResponse::data($this->courses->adminCourse($courseId), 201);
    }

    #[Route('/api/v1/admin/courses/{id}', name: 'api_courses_update', methods: ['PUT'], requirements: ['id' => '\d+'])]
    #[IsGranted(ApiScope::COURSES_WRITE)]
    #[IsGranted('COURSE.EDIT')]
    public function update(int $id, Request $request, #[CurrentUser] ApiUser $user): JsonResponse
    {
        $this->requireManagement($id, $user);
        $this->courses->updateCourse($id, ApiRequest::jsonBody($request), $user->identity->userId);

        return ApiResponse::data($this->courses->adminCourse($id));
    }

    #[Route('/api/v1/admin/courses/{id}/status', name: 'api_courses_status', methods: ['POST'], requirements: ['id' => '\d+'])]
    #[IsGranted(ApiScope::COURSES_PUBLISH)]
    #[IsGranted('COURSE.PUBLISH')]
    public function status(int $id, Request $request, #[CurrentUser] ApiUser $user): JsonResponse
    {
        $this->requireManagement($id, $user);
        $body = ApiRequest::jsonBody($request);
        $this->courses->changeStatus($id, (string) ($body['status'] ?? ''), $user->identity->userId);

        return ApiResponse::data($this->courses->adminCourse($id));
    }

    /**
     * The resource-relationship question, which no permission may answer.
     *
     * A platform administrator manages every course by definition; everyone else must own or edit
     * this one.
     */
    private function requireManagement(int $courseId, ApiUser $user): void
    {
        if ($user->identity->hasPermission('PLATFORM.DASHBOARD.VIEW')) {
            return;
        }
        if (!$this->courses->userCanManageCourse($courseId, $user->identity->userId)) {
            throw new AuthorizationException('The authenticated account cannot manage this course.');
        }
    }
}
