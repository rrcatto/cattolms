declare(strict_types=1);

namespace CattoLearning\Http\Symfony;

use InvalidArgumentException;
use JsonException;
use Symfony\Component\HttpFoundation\Request;

final class ApiRequest
{
    /** @return array<string,mixed> */
    public static function jsonBody(Request $request): array
    {
        $raw = (string) $request->getContent();
        if (trim($raw) === '') {
            return [];
        }

        try {
            $data = json_decode($raw, true, 512, JSON_THROW_ON_ERROR);
        } catch (JsonException $exception) {
            throw new InvalidArgumentException('The request body is not valid JSON.', 0, $exception);
        }

        if (!is_array($data)) {
            throw new InvalidArgumentException('The JSON request body must be an object.');
        }

        return $data;
    }
}
