     * Kept values as they were stored, or null for anything else.
     *
     * @return array{action:string,values:array<string,mixed>}|null
     */
    public static function valid(mixed $kept): ?array
    {
        if (!is_array($kept) || !is_string($kept['action'] ?? null) || !is_array($kept['values'] ?? null)) return null;
        $values = [];
        foreach ($kept['values'] as $name => $value) if (is_string($name)) $values[$name] = $value;
        return ['action' => $kept['action'], 'values' => $values];
    }

    /** A form's action as it is compared: its path, without a query or a place on the page. */
    private static function path(string $action): string
    {
        $path = (string) parse_url($action, PHP_URL_PATH);
        return $path === '' ? '/' : $path;
    }

