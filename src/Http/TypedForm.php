        if (is_scalar($value)) return mb_substr((string) $value, 0, self::LONGEST);
        if (!is_array($value) || $depth >= 2) return null;
        $kept = [];
        foreach (array_slice($value, 0, self::MOST, true) as $key => $item) {
            $item = self::value($item, $depth + 1);
            if ($item !== null) $kept[$key] = $item;
        }
        return $kept;
    }
