declare(strict_types=1);

namespace CattoLearning\Http;

use CattoLearning\Auth\AuthService;
use CattoLearning\Auth\CurrentUser;
use CattoLearning\View\ThemeRenderer;
use CattoPHP\Http\ErrorPage;
use CattoPHP\Http\ErrorPageDrawer;
use Symfony\Component\HttpFoundation\Request;
use Throwable;

final class ThemedErrorPage implements ErrorPageDrawer
{
    public function __construct(private readonly ThemeRenderer $view, private readonly AuthService $auth)
    {
    }

    public function draw(ErrorPage $page, Request $request): string
    {
        return $this->view->render('error', ViewIdentity::of($this->auth, $this->reader(), [
            'title' => $page->title,
            'status' => $page->status,
            'kind' => $page->kind,
            'message' => $page->message,
            'reference' => $page->reference,
            'retry_url' => $page->retryUrl,
        ]), $page->status);
    }

    /** Who is reading, or nobody when that cannot be told (the error may be the database's own). */
    private function reader(): ?CurrentUser
    {
        try {
            return $this->auth->currentUser();
        } catch (Throwable) {
            return null;
        }
    }
}
