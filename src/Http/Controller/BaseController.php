declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Auth\CurrentUser;
use CattoLearning\Http\HttpRedirect;
use CattoLearning\Http\ViewIdentity;
use CattoLearning\Support\Csrf;
use CattoLearning\View\ThemeRenderer;
use RuntimeException;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Exception\AccessDeniedHttpException;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;

abstract class BaseController
{
    public function __construct(
        protected readonly AuthService $auth,
        protected readonly ThemeRenderer $view,
        protected readonly RequestStack $requests
    ) {
    }

    /** The current request, which every helper below reads rather than touching a superglobal. */
    protected function request(): Request
    {
        return $this->requests->getCurrentRequest() ?? Request::createFromGlobals();
    }

    /**
     * One route parameter.
     *
     * Replaces Fat-Free's PARAMS hive. Returns a string always, because every caller either
     * validates it or casts it, and a null here would only move the check outward.
     */
    protected function param(string $name, string $default = ''): string
    {
        return (string) ($this->request()->attributes->get($name) ?? $default);
    }

    /** One posted field. */
    protected function posted(string $name, string $default = ''): string
    {
        return (string) ($this->request()->request->get($name) ?? $default);
    }

    protected function currentUser(): ?CurrentUser
    {
        return $this->auth->currentUser();
    }

    protected function requireUser(): CurrentUser
    {
        $user = $this->currentUser();
        if ($user === null) {
            $this->flash('warning', 'Sign in to continue.');
            $this->redirect('/login?return=' . rawurlencode($this->request()->getRequestUri()));
        }
        return $user;
    }

    protected function requirePermission(string $permission): CurrentUser
    {
        $user = $this->requireUser();
        if (!$user->hasPermission($permission)) {
            throw new AccessDeniedHttpException('You do not have permission to access this function.');
        }
        return $user;
    }

    protected function requireCourseAuthor(): CurrentUser
    {
        return $this->requirePermission('COURSE.EDIT');
    }

    /**
     * A form sent without its token, or with an expired one, is a request the site could not take (400), never a fault
     * on the site's side (2026-10-24: it answered 500, "Something went wrong on our side").
     */
    protected function requireCsrf(): void
    {
        try {
            Csrf::requireValid(is_string($_POST['csrf'] ?? null) ? $_POST['csrf'] : null);
        } catch (RuntimeException $invalid) {
            throw new \Symfony\Component\HttpKernel\Exception\BadRequestHttpException($invalid->getMessage(), $invalid);
        }
    }

    /**
     * Renders one platform-owned partial as a bare HTML fragment, with no theme chrome.
     *
     * Used for htmx responses, where the browser swaps the result into an existing page and a
     * full document would nest a second <html> inside the current one. Fragments are core-owned
     * functional markup: a theme styles them through the ordinary platform classes but never
     * supplies or replaces them.
     *
     * @param array<string,mixed> $data
     */
    protected function renderFragment(string $template, array $data = [], int $status = 200): Response
    {
        // The same identity and capability flags the page render supplies. A fragment includes the
        // same partials, and those partials hide controls on the same can_* flags.
        $data = $this->viewIdentity($data);

        header('Content-Type: text/html; charset=utf-8');
        // A lookup response reflects one operator's resource scope, so it must never be reused
        // for another request by a shared cache.
        header('Cache-Control: no-store');

        return new Response($this->view->renderFragment($template, $data), $status);
    }

    /**
     * True when the current request came from htmx rather than an ordinary navigation.
     *
     * htmx sends `HX-Request: true`. Callers use this only to decide whether to return a
     * fragment or a full page; behaviour and authorisation never depend on it, so a client
     * that omits or forges the header simply gets the full page.
     */
    protected function isHtmxRequest(): bool
    {
        return strtolower((string) ($_SERVER['HTTP_HX_REQUEST'] ?? '')) === 'true';
    }

    /**
     * The dataset an htmx request is swapping, or null when it is not swapping one.
     *
     * htmx sends the id of the element it will replace in `HX-Target`, and every paginated list on
     * the platform targets `<dataset>-region` by the convention the shared search and pagination
     * controls share. So the header names the dataset directly, and nothing has to be inferred from
     * which query parameters happen to be present - a reader who has both a search term and a page
     * number in the URL is indistinguishable that way, and guessing wrong means loading the wrong
     * list.
     *
     * Untrusted, like any header, so it is matched against a strict pattern and used only to decide
     * how much work to do. A forged or absent value costs the reader a full page, never data they
     * may not see: the universe, the permissions and the scope are resolved exactly as they are for
     * an ordinary navigation.
     */
    protected function htmxDataset(): ?string
    {
        if (!$this->isHtmxRequest()) {
            return null;
        }

        $target = (string) ($_SERVER['HTTP_HX_TARGET'] ?? '');

        return preg_match('/^([a-z][a-z_]*)-region$/', $target, $match) === 1 ? $match[1] : null;
    }


    /**
     * The identity and capability values every platform template may read.
     *
     * Shared by the page render and the fragment render, and that is the point. A fragment is a
     * piece of a page: it includes the same partials, and those partials guard controls on the same
     * can_* flags. The fragment path used to supply four scalars - csrf, app_name, app_url and
     * current_uri - so every htmx swap of an Administration list died on "Undefined variable
     * $can_manage_people", returned a 500, and htmx swapped the error page into the results region.
     * Paging and searching by keyboard worked, because those are ordinary GET requests; only the
     * swap was broken, which is why it survived every route smoke test.
     *
     * @param array<string,mixed> $data
     * @return array<string,mixed>
     */
    protected function viewIdentity(array $data): array
    {
        return ViewIdentity::of($this->auth, $this->currentUser(), $data);
    }

    /** @param array<string,mixed> $data */
    protected function render(string $page, array $data = [], int $status = 200): Response
    {
        $data = $this->viewIdentity($data);
        // Navigation state belongs to a page, not to a fragment swapped into one.
        $data['active_nav'] = $data['active_nav'] ?? $this->activeNavigation();
        $data['page_title'] = $data['page_title'] ?? ($data['title'] ?? '');
        $data['page_kicker'] = $data['page_kicker'] ?? '';
        $data['flash_messages'] = $this->consumeFlash();

        return new Response($this->view->render($page, $data, $status), $status);
    }

    /**
     * Stops the controller and sends the reader somewhere else.
     *
     * Thrown rather than returned so a guard can redirect from the middle of a method without
     * every caller forwarding a response it did not ask for. See HttpRedirect for why.
     */
    /**
     * The analytics visitor: a random UUID kept in this browser session, so anonymous course views
     * can be counted per visitor without a fingerprint, a long-lived tracking cookie, the session
     * token itself or an IP address. It ends with the browser session.
     */
    protected function analyticsVisitor(): string
    {
        $visitor = $_SESSION['analytics_visitor'] ?? null;
        if (!is_string($visitor) || !\CattoLearning\Support\Uuid::isValid($visitor)) {
            $visitor = \CattoLearning\Support\Uuid::v4();
            $_SESSION['analytics_visitor'] = $visitor;
        }
        return $visitor;
    }

    /**
     * The campaign this browser session arrived from: the utm_ parameters of the last landing page
     * address that carried them, remembered with the analytics visitor and ending with it. With
     * $capture, this request's address replaces it when it carries any.
     *
     * @return array<string,string>
     */
    protected function analyticsCampaign(bool $capture = false): array
    {
        if ($capture) {
            $fresh = \CattoLearning\Analytics\CampaignAttribution::from($this->request()->query->all());
            if ($fresh !== []) {
                $_SESSION['analytics_campaign'] = $fresh;
            }
        }
        $stored = $_SESSION['analytics_campaign'] ?? [];
        return \CattoLearning\Analytics\CampaignAttribution::from(is_array($stored) ? $stored : []);
    }

    protected function redirect(string $path): never
    {
        throw new HttpRedirect($path);
    }

    /** The response for a resource that is not there. */
    protected function notFound(string $message): NotFoundHttpException
    {
        return new NotFoundHttpException($message);
    }

    protected function flash(string $type, string $message): void
    {
        $_SESSION['flash'][] = ['type' => $type, 'message' => $message];
    }

    /** @return list<array{type:string,message:string}> */
    private function consumeFlash(): array
    {
        $messages = is_array($_SESSION['flash'] ?? null) ? $_SESSION['flash'] : [];
        unset($_SESSION['flash']);
        return array_values(array_filter($messages, static fn(mixed $m): bool =>
            is_array($m) && isset($m['type'], $m['message'])
        ));
    }

    /**
     * Runs a write and turns a domain failure into a message on the page it came from.
     *
     * A redirect is not a failure: HttpRedirect extends Exception rather than RuntimeException
     * precisely so a successful write's own redirect passes straight through this.
     */
    protected function handle(callable $callback, string $fallbackPath): Response
    {
        try {
            $result = $callback();
        } catch (RuntimeException|\InvalidArgumentException $e) {
            $this->flash('danger', $e->getMessage());
            $this->redirect($fallbackPath);
        } catch (\Doctrine\DBAL\Exception\UniqueConstraintViolationException) {
            // The database's own refusals in words, never an error page (2026-10-26 audit: a taken course address, an
            // address already on an account): a service that knows the reason says it first.
            $this->flash('danger', 'That was not saved: something in it is already used by another record. Change it and try again.');
            $this->redirect($fallbackPath);
        } catch (\Doctrine\DBAL\Exception\ForeignKeyConstraintViolationException) {
            $this->flash('danger', 'That was not done: other records still depend on it.');
            $this->redirect($fallbackPath);
        } catch (\Doctrine\DBAL\Exception\DriverException $refused) {
            // A company always keeps its Company Administrator (owner, 2026-10-27; the database checks it when a change
            // ends): whatever path tried to take the last one away is told why, never shown an error page.
            if ($refused->getSQLState() !== '23514' || !str_contains($refused->getMessage(), 'Company Administrator')) throw $refused;
            $this->flash('danger', 'That was not done: a company always has a Company Administrator. Make someone else at the company its administrator first.');
            $this->redirect($fallbackPath);
        }

        // A callback that produced a response is showing the reader something; one that produced
        // nothing has performed a write, and the reader goes back where they came from.
        return $result instanceof Response ? $result : $this->redirect($fallbackPath);
    }
    private function activeNavigation(): string
    {
        $path = parse_url((string) ($_SERVER['REQUEST_URI'] ?? '/'), PHP_URL_PATH) ?: '/';
        return match (true) {
            str_starts_with($path, '/admin') => 'admin',
            str_starts_with($path, '/help') => 'help',
            str_starts_with($path, '/contact') => 'contact',
            str_starts_with($path, '/company') => 'company',
            str_starts_with($path, '/account') => 'account',
            str_starts_with($path, '/learn') => 'learning',
            str_starts_with($path, '/courses') => 'catalogue',
            default => 'home',
        };
    }

}
