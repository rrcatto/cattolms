declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use Base;
use CattoLearning\Auth\AuthService;
use CattoLearning\Auth\CurrentUser;
use CattoLearning\Support\Csrf;
use CattoLearning\View\ThemeRenderer;
use RuntimeException;

abstract class BaseController
{
    public function __construct(
        protected readonly Base $f3,
        protected readonly AuthService $auth,
        protected readonly ThemeRenderer $view
    ) {
    }

    protected function currentUser(): ?CurrentUser
    {
        return $this->auth->currentUser();
    }

    protected function requireUser(): CurrentUser
    {
        $user = $this->currentUser();
        if ($user === null) {
            $this->flash('warning', 'Sign in to continue.');
            $this->redirect('/login?return=' . rawurlencode((string) ($_SERVER['REQUEST_URI'] ?? '/account/library')));
        }
        return $user;
    }

    protected function requirePermission(string $permission): CurrentUser
    {
        $user = $this->requireUser();
        if (!$user->hasPermission($permission)) {
            $this->f3->error(403, 'You do not have permission to access this function.');
        }
        return $user;
    }

    protected function requireCourseAuthor(): CurrentUser
    {
        return $this->requirePermission('COURSES.EDIT');
    }

    protected function requireCsrf(): void
    {
        Csrf::requireValid(is_string($_POST['csrf'] ?? null) ? $_POST['csrf'] : null);
    }

    /** @param array<string,mixed> $data */
    protected function render(string $page, array $data = [], int $status = 200): void
    {
        $currentUser = $this->currentUser();

        // Never place CurrentUser or another application object in the F3 hive.
        // F3 recursively escapes hive values before rendering and attempts to
        // write escaped values back to public properties. CurrentUser is a
        // readonly value object, so passing it to a template causes a fatal
        // "Cannot modify readonly property" error.
        $data['is_authenticated'] = $currentUser !== null;
        $data['is_platform_admin'] = $currentUser?->hasRole('ADMIN') ?? false;
        $data['is_company_admin'] = $currentUser?->hasRole('COMPANY_ADMIN') ?? false;
        $data['is_course_owner'] = $currentUser?->hasRole('COURSE_OWNER') ?? false;
        $data['is_course_editor'] = $currentUser?->hasRole('COURSE_EDITOR') ?? false;
        $data['user_email'] = $currentUser === null ? '' : $currentUser->primaryEmail;
        $data['user_name'] = $currentUser === null ? '' : $currentUser->displayName;
        $data['permissions'] = $currentUser === null ? [] : $currentUser->permissions;
        // Stable presentation capabilities let platform-owned templates hide
        // controls using ACL decisions rather than hard-coded role names.
        $capabilities = [
            'can_access_admin' => 'ADMIN.DASHBOARD.VIEW',
            'can_view_admin_dashboard' => 'ADMIN.DASHBOARD.VIEW',
            'can_manage_people' => 'ADMIN.PEOPLE.MANAGE',
            'can_manage_companies' => 'ADMIN.COMPANIES.MANAGE',
            'can_manage_enrolments' => 'ADMIN.ENROLMENTS.MANAGE',
            'can_manage_credits' => 'ADMIN.CREDITS.MANAGE',
            'can_manage_themes' => 'ADMIN.THEMES.MANAGE',
            'can_manage_settings' => 'ADMIN.SETTINGS.MANAGE',
            'can_manage_roles' => 'ADMIN.ROLES.MANAGE',
            'can_create_courses' => 'COURSES.CREATE',
            'can_delete_courses' => 'COURSES.DELETE',
            'can_publish_courses' => 'COURSES.PUBLISH',
            'can_manage_categories' => 'COURSES.CATEGORIES.MANAGE',
            'can_manage_course_ownership' => 'COURSES.OWNERSHIP.MANAGE',
            'can_manage_course_pricing' => 'COURSES.PRICING.MANAGE',
            'can_manage_course_media' => 'COURSES.MEDIA.MANAGE',
            'can_manage_assessments' => 'COURSES.ASSESSMENTS.MANAGE',
            'can_manage_certificates' => 'COURSES.CERTIFICATES.MANAGE',
            'can_preview_courses' => 'COURSES.PREVIEW',
        ];
        foreach ($capabilities as $flag => $permission) {
            $data[$flag] = $currentUser?->hasPermission($permission) ?? false;
        }
        $data['active_nav'] = $data['active_nav'] ?? $this->activeNavigation();
        $data['page_title'] = $data['page_title'] ?? ($data['title'] ?? '');
        $data['page_kicker'] = $data['page_kicker'] ?? '';
        $data['flash_messages'] = $this->consumeFlash();

        echo $this->view->render($page, $data, $status);
    }

    protected function redirect(string $path): never
    {
        header('Location: ' . $path, true, 303);
        exit;
    }

    protected function flash(string $type, string $message): void
    {
        $_SESSION['flash'][] = ['type' => $type, 'message' => $message];
    }

    /** @return list<array{type:string,message:string}> */
    private function consumeFlash(): array
    {
        $messages = is_array($_SESSION['flash'] ?? null) ? $_SESSION['flash'] : [];
        unset($_SESSION['flash']);
        return array_values(array_filter($messages, static fn(mixed $m): bool =>
            is_array($m) && isset($m['type'], $m['message'])
        ));
    }

    protected function handle(callable $callback, string $fallbackPath): void
    {
        try {
            $callback();
        } catch (RuntimeException|\InvalidArgumentException $e) {
            $this->flash('danger', $e->getMessage());
            $this->redirect($fallbackPath);
        }
    }
    private function activeNavigation(): string
    {
        $path = parse_url((string) ($_SERVER['REQUEST_URI'] ?? '/'), PHP_URL_PATH) ?: '/';
        return match (true) {
            str_starts_with($path, '/admin') => 'admin',
            str_starts_with($path, '/help') => 'help',
            str_starts_with($path, '/contact') => 'contact',
            str_starts_with($path, '/company') => 'company',
            str_starts_with($path, '/account') => 'account',
            str_starts_with($path, '/account/library'), str_starts_with($path, '/learn') => 'learning',
            str_starts_with($path, '/courses') => 'catalogue',
            default => 'home',
        };
    }

