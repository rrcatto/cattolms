declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Http\PictureResponse;
use CattoLearning\Search\SearchRepository;
use CattoPHP\Search\LlmsTxt;
use CattoPHP\Search\RobotsTxt;
use CattoPHP\Search\SharePictures;
use CattoPHP\Search\Sitemap;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;
use Symfony\Component\Routing\Attribute\Route;

final class SearchEngineController extends BaseController
{
    public function __construct(AuthService $auth, ThemeRenderer $view, RequestStack $requests, private readonly Sitemap $sitemap,
        private readonly RobotsTxt $robots, private readonly LlmsTxt $llms, private readonly SharePictures $pictures, private readonly SearchRepository $records)
    {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/sitemap.xml', name: 'sitemap', methods: ['GET'])]
    public function sitemap(): Response
    {
        return self::xml($this->sitemap->document());
    }

    #[Route('/sitemap-{page}.xml', name: 'sitemap_page', requirements: ['page' => '[1-9]\d{0,5}'], methods: ['GET'])]
    public function sitemapPage(): Response
    {
        return self::xml($this->sitemap->page((int) $this->param('page')));
    }

    #[Route('/robots.txt', name: 'robots', methods: ['GET'])]
    public function robots(): Response
    {
        return new Response($this->robots->document(), 200, ['Content-Type' => 'text/plain; charset=UTF-8', 'Cache-Control' => 'public, max-age=3600']);
    }

    /** A summary of the site for AI assistants (llmstxt.org), on a live site only. */
    #[Route('/llms.txt', name: 'llms_txt', methods: ['GET'])]
    public function llms(): Response
    {
        $document = $this->llms->document() ?? throw new NotFoundHttpException('This site has no llms.txt.');
        return new Response($document, 200, ['Content-Type' => 'text/plain; charset=UTF-8', 'Cache-Control' => 'public, max-age=3600']);
    }

    /** A published course's share picture, its cover at 1200 by 630 (CattoPHP\Search\SharePictures). */
    #[Route('/share/course/{slug}.png', name: 'share_course_picture', requirements: ['slug' => '[a-zA-Z0-9_-]+'], methods: ['GET'])]
    public function coursePicture(): Response
    {
        return $this->picture($this->records->courseCover((string) $this->param('slug')));
    }

    /**
     * A published course's cover as a picture, small on a bundle's card beside its other courses' (owner, 2026-11-07, the
     * approved bundles mockup). Its address carries the cover's version, so it may be kept for good.
     */
    #[Route('/courses/{slug}/cover.svg', name: 'course_cover_picture', requirements: ['slug' => '[a-zA-Z0-9_-]+'], methods: ['GET'])]
    public function courseCover(): Response
    {
        $cover = $this->records->courseCover((string) $this->param('slug'));
        if ($cover === null || !str_starts_with(ltrim($cover), '<svg')) throw new NotFoundHttpException('There is no such picture.');
        return PictureResponse::of($cover, 'image/svg+xml', true);
    }

    /** A published bundle's share picture: its own cover, else its first course's. */
    #[Route('/share/bundle/{slug}.png', name: 'share_bundle_picture', requirements: ['slug' => '[a-z0-9]+(?:-[a-z0-9]+)*'], methods: ['GET'])]
    public function bundlePicture(): Response
    {
        return $this->picture($this->records->bundleCover((string) $this->param('slug')));
    }

    private function picture(?string $cover): Response
    {
        $bytes = $cover === null ? null : $this->pictures->bytes($cover);
        if ($bytes === null) throw new NotFoundHttpException('There is no such picture.');
        return PictureResponse::of($bytes, 'image/png', true);
    }

    private static function xml(?string $document): Response
    {
        if ($document === null) throw new NotFoundHttpException('This site has no sitemap.');
        return new Response($document, 200, ['Content-Type' => 'application/xml; charset=UTF-8', 'Cache-Control' => 'public, max-age=3600']);
    }
}
