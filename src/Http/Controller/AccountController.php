declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Application\AccountSectionRegistry;
use Symfony\Component\HttpFoundation\RequestStack;
use CattoLearning\Application\PlatformAdministrationService;
use CattoLearning\Auth\AuthService;
use CattoLearning\Auth\CurrentUser;
use CattoLearning\Company\CompanyService;
use CattoLearning\Course\LearningService;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class AccountController extends BaseController
{
    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly LearningService $learning,
        private readonly PlatformAdministrationService $platformAdministration,
        private readonly CompanyService $companies,
        private readonly AccountSectionRegistry $sections
    ) {
        parent::__construct($auth, $view, $requests);
    }

    /** Renders every Account section in one presentation-neutral workspace. */
    #[Route('/account', name: 'account_index', methods: ['GET'])]
    public function index(): Response
    {
        $user = $this->requirePermission('ACCOUNT.VIEW');
        $sections = $this->allowedSections($user);
        $data = $this->workspaceData($user, $sections);
        $data['account_sections'] = $sections;
        $data['account_layout'] = 'workspace';
        return $this->render('account-control-centre', $data + [
            'title' => 'Account',
            'page_kicker' => 'Dashboard, profile, learning, sessions and activity',
            'active_nav' => 'account',
        ]);
    }


    #[Route('/account/dashboard', name: 'account_dashboard', methods: ['GET'])]
    public function dashboard(): Response
    {
        $user = $this->requirePermission('ACCOUNT.VIEW');
        return $this->renderAccountSection('dashboard', $this->dashboardData($user->id));
    }


    #[Route('/account/library', name: 'account_learning', methods: ['GET'])]
    public function learning(): Response
    {
        $user = $this->requirePermission('LEARNING.LIBRARY.VIEW');
        return $this->renderAccountSection('learning', $this->learningData($user->id, $this->libraryRequest()));
    }

    #[Route('/account/profile', name: 'account_profile', methods: ['GET'])]
    public function profile(): Response
    {
        $user = $this->requirePermission('ACCOUNT.PROFILE.VIEW');
        return $this->renderAccountSection('profile', $this->profileData($user->id));
    }


    #[Route('/account/profile', name: 'account_update_profile', methods: ['POST'])]
    public function updateProfile(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('ACCOUNT.PROFILE.EDIT');
        return $this->handle(function () use ($user): void {
            $this->auth->updateProfile($user->id, $_POST);
            $this->flash('success', 'Your profile was updated.');
            $this->redirect('/account/profile');
        }, '/account/profile');
    }


    #[Route('/account/sessions', name: 'account_sessions', methods: ['GET'])]
    public function sessions(): Response
    {
        $user = $this->requirePermission('ACCOUNT.SESSION.VIEW');
        return $this->renderAccountSection('sessions', [
            'sessions' => $this->auth->activeSessions($user->id),
        ]);
    }


    #[Route('/account/activity', name: 'account_activity', methods: ['GET'])]
    public function activity(): Response
    {
        $user = $this->requirePermission('ACCOUNT.ACTIVITY.VIEW');
        return $this->renderAccountSection('activity', [
            'account_activity' => $this->platformAdministration->activityEvents(['actor_id' => $user->id], 100),
        ]);
    }

    #[Route('/account/sessions/revoke', name: 'account_revoke_session', methods: ['POST'])]
    public function revokeSession(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('ACCOUNT.SESSION.MANAGE');
        $publicId = trim((string) ($_POST['session_id'] ?? ''));
        $isCurrent = $publicId !== '' && $publicId === $user->sessionPublicId;
        if ($publicId !== '') $this->auth->revokeSession($user->id, $publicId);
        $this->flash('success', 'The session was revoked.');
        $this->redirect($isCurrent ? '/' : '/account/sessions');
    }


    #[Route('/account/email/secondary', name: 'account_request_secondary_email', methods: ['POST'])]
    public function requestSecondaryEmail(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('ACCOUNT.EMAIL.MANAGE');
        return $this->handle(function () use ($user): void {
            $this->auth->requestSecondaryEmail($user->id, (string) ($_POST['email'] ?? ''));
            $this->flash('success', 'A verification link has been sent to the secondary email address.');
            $this->redirect('/account/profile#emails');
        }, '/account/profile#emails');
    }


    #[Route('/account/email/verify', name: 'account_verify_secondary_email', methods: ['GET'])]
    public function verifySecondaryEmail(): Response
    {
        $token = (string) ($_GET['token'] ?? '');
        return $this->handle(function () use ($token): void {
            $this->auth->verifySecondaryEmail($token);
            $this->flash('success', 'The secondary email address has been verified.');
            $this->redirect('/account/profile#emails');
        }, '/login');
    }


    #[Route('/account/email/remove', name: 'account_remove_secondary_email', methods: ['POST'])]
    public function removeSecondaryEmail(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('ACCOUNT.EMAIL.MANAGE');
        $this->auth->removeSecondaryEmail($user->id, (int) ($_POST['email_id'] ?? 0));
        $this->flash('success', 'The secondary email address was removed.');
        $this->redirect('/account/profile#emails');
    }

    /** @return array<string,mixed> */
    private function dashboardData(int $userId): array
    {
        $courses = $this->learning->library($userId);
        $current = array_values(array_filter($courses, static fn(array $course): bool => in_array((string) ($course['status'] ?? ''), ['assigned','active'], true)));
        $completed = array_values(array_filter($courses, static fn(array $course): bool => (string) ($course['status'] ?? '') === 'completed'));
        $progressValues = array_map(static fn(array $course): int => (int) ($course['progress_percentage'] ?? 0), $current);
        return [
            'account_courses' => $courses,
            'account_stats' => [
                'current_courses' => count($current),
                'completed_courses' => count($completed),
                'certificates' => count(array_filter($courses, static fn(array $course): bool => !empty($course['certificate_public_id']))),
                'average_progress' => $progressValues !== [] ? (int) round(array_sum($progressValues) / count($progressValues)) : 0,
            ],
        ];
    }

    /**
     * The Course Library section of the consolidated Account workspace.
     *
     * Delegates to the same builder the standalone page uses, so the two cannot describe the same
     * four lists differently.
     *
     * @param array<string,mixed> $request
     * @return array<string,mixed>
     */
    private function learningData(int $userId, array $request): array
    {
        return $this->learning->courseLibraryView(
            $userId,
            $request,
            fn(string $dataset, array $req, int $total) => $this->platformAdministration->paginationFor($dataset, $req, $total),
            fn(string $dataset, $pagination, string $label, string $search) => $this->platformAdministration->paginationView(
                $dataset,
                $pagination,
                '/account/library',
                $label,
                $search === '' ? [] : [PlatformAdministrationService::searchParam($dataset) => $search]
            )
        );
    }

    /**
     * Page, page size and search term for each Course Library dataset.
     *
     * @return array<string,mixed>
     */
    private function libraryRequest(): array
    {
        $request = [];
        foreach (array_keys(LearningService::LIBRARY_DATASETS) as $dataset) {
            $request[$dataset . '_page'] = $_GET[$dataset . '_page'] ?? null;
            $request[$dataset . '_page_size'] = $_GET[$dataset . '_page_size'] ?? null;
            $param = PlatformAdministrationService::searchParam($dataset);
            $request[$param] = $_GET[$param] ?? null;
        }

        return $request;
    }

    /**
     * Builds only data for Account sections the current ACL permits. This keeps
     * hidden section data out of the Theme API rather than merely hiding links.
     *
     * @param list<array<string,mixed>> $sections
     * @return array<string,mixed>
     */
    private function workspaceData(CurrentUser $user, array $sections): array
    {
        // The shared search control reads the data scope, and an absent key is an undefined
        // variable rather than an empty one - which F3 turns into a 500 for the whole page. It is
        // emitted only for an identity that may choose a scope; for everyone else it stays empty,
        // because naming a scope would tell an ordinary reader that a second population exists.
        $data = [];
        foreach ($sections as $section) {
            $data = array_replace($data, match ((string) $section['key']) {
                'dashboard' => $this->dashboardData($user->id),
                'profile' => $this->profileData($user->id),
                'learning' => $this->learningData($user->id, $this->libraryRequest()),
                'sessions' => ['sessions' => $this->auth->activeSessions($user->id)],
                'activity' => ['account_activity' => $this->platformAdministration->activityEvents(['actor_id' => $user->id], 100)],
                default => [],
            });
        }
        return $data;
    }

    /** @return list<array<string,mixed>> */
    private function allowedSections(CurrentUser $user): array
    {
        $permissions = [
            'dashboard' => 'ACCOUNT.VIEW',
            'profile' => 'ACCOUNT.PROFILE.VIEW',
            'learning' => 'LEARNING.LIBRARY.VIEW',
            'sessions' => 'ACCOUNT.SESSION.VIEW',
            'activity' => 'ACCOUNT.ACTIVITY.VIEW',
        ];
        return array_values(array_filter(
            $this->sections->all(),
            static fn(array $section): bool => $user->hasPermission($permissions[(string) $section['key']] ?? 'ACCOUNT.VIEW')
        ));
    }

    /** @return array<string,mixed> */
    private function profileData(int $userId): array
    {
        $user = $this->requireUser();
        return [
            'profile' => $this->auth->profile($userId),
            'emails' => $this->auth->emails($userId),
            'company' => $this->companies->forUser($userId),
            'user_roles' => $user->roles,
        ];
    }

    /** @param array<string,mixed> $data */
    private function renderAccountSection(string $key, array $data): Response
    {
        $user = $this->requireUser();
        // See workspaceData(): every Account section renders through here, so the scope key is
        // supplied once rather than remembered by each caller.

        $definition = $this->sections->get($key);
        $data['account_section'] = $definition;
        $data['account_layout'] = 'section';
        return $this->render('account-section', $data + [
            'title' => $definition['label'] . ' · Account',
            'page_title' => $definition['label'],
            'page_kicker' => 'Account',
            'active_nav' => 'account',
        ]);
    }
