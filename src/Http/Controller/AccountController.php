declare(strict_types=1);

namespace CattoLearning\Http\Controller;

final class AccountController extends BaseController
{
    public function profile(): void
    {
        $user = $this->requireUser();
        $library = $this->app->learning->library($user->id);
        $favourites = $this->app->platformAdministration->favourites($user->id);
        $requests = $this->app->platformAdministration->userRequests($user->id);
        $sessions = $this->app->auth->activeSessions($user->id);
        $this->render('profile', [
            'title' => 'Profile',
            'page_kicker' => 'Personal details and account settings',
            'profile' => $this->app->auth->profile($user->id),
            'emails' => $this->app->auth->emails($user->id),
            'company' => $this->app->companies->forUser($user->id),
            'user_roles' => $user->roles,
            'library_courses' => $library,
            'favourites' => $favourites,
            'requests' => $requests,
            'sessions' => $sessions,
            'library_count' => count($library),
            'favourites_count' => count($favourites),
            'requests_count' => count($requests),
            'sessions_count' => count($sessions),
        ]);
    }

    public function updateProfile(): void
    {
        $this->requireCsrf();
        $user = $this->requireUser();
        $this->handle(function () use ($user): void {
            $this->app->auth->updateProfile($user->id, $_POST);
            $this->flash('success', 'Your profile was updated.');
            $this->redirect('/account/profile');
        }, '/account/profile');
    }

    public function sessions(): void
    {
        $user = $this->requireUser();
        $this->render('sessions', [
            'title' => 'Active sessions',
            'page_kicker' => 'Account security',
            'sessions' => $this->app->auth->activeSessions($user->id),
        ]);
    }

    public function revokeSession(): void
    {
        $this->requireCsrf();
        $user = $this->requireUser();
        $publicId = trim((string) ($_POST['session_id'] ?? ''));
        $isCurrent = $publicId !== '' && $publicId === $user->sessionPublicId;
        if ($publicId !== '') {
            $this->app->auth->revokeSession($user->id, $publicId);
        }
        $this->flash('success', 'The session was revoked.');
        $this->redirect($isCurrent ? '/' : '/account/profile#sessions');
    }

    public function requestSecondaryEmail(): void
    {
        $this->requireCsrf();
        $user = $this->requireUser();
        $this->handle(function () use ($user): void {
            $this->app->auth->requestSecondaryEmail($user->id, (string) ($_POST['email'] ?? ''));
            $this->flash('success', 'A verification link has been sent to the secondary email address.');
            $this->redirect('/account/profile#emails');
        }, '/account/profile#emails');
    }

    public function verifySecondaryEmail(): void
    {
        $token = (string) ($_GET['token'] ?? '');
        $this->handle(function () use ($token): void {
            $this->app->auth->verifySecondaryEmail($token);
            $this->flash('success', 'The secondary email address has been verified.');
            $this->redirect('/account/profile#emails');
        }, '/login');
    }

    public function removeSecondaryEmail(): void
    {
        $this->requireCsrf();
        $user = $this->requireUser();
        $this->app->auth->removeSecondaryEmail($user->id, (int) ($_POST['email_id'] ?? 0));
        $this->flash('success', 'The secondary email address was removed.');
        $this->redirect('/account/profile#emails');
    }
}