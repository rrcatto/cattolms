declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Application\AccountSecurity;
use CattoLearning\Auth\AuthService;
use CattoLearning\Auth\CurrentUser;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class AccountSecurityController extends BaseController
{
    private const PAGE = '/account/security';

    public function __construct(AuthService $auth, ThemeRenderer $view, RequestStack $requests, private readonly AccountSecurity $security)
    {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/account/security/telegram/connect', name: 'account_security_telegram_connect', methods: ['POST'])]
    public function connectTelegram(): Response
    {
        return $this->act('telegram', fn(CurrentUser $user) => $this->security->connectTelegram($user));
    }

    #[Route('/account/security/telegram/cancel', name: 'account_security_telegram_cancel', methods: ['POST'])]
    public function cancelTelegram(): Response
    {
        return $this->act('telegram', fn(CurrentUser $user) => $this->security->cancelTelegram($user));
    }

    /** "I have pressed Start": the page without JavaScript asks now. */
    #[Route('/account/security/telegram/check', name: 'account_security_telegram_check', methods: ['POST'])]
    public function checkTelegram(): Response
    {
        return $this->act('telegram', fn(CurrentUser $user) => $this->security->checkTelegram($user));
    }

    #[Route('/account/security/telegram/test', name: 'account_security_telegram_test', methods: ['POST'])]
    public function testTelegram(): Response
    {
        return $this->act('telegram', fn(CurrentUser $user) => $this->security->testTelegram($user));
    }

    #[Route('/account/security/telegram/disconnect', name: 'account_security_telegram_disconnect', methods: ['POST'])]
    public function disconnectTelegram(): Response
    {
        return $this->act('telegram', fn(CurrentUser $user) => $this->security->disconnectTelegram($user));
    }

    #[Route('/account/security/two-step/start', name: 'account_security_two_step_start', methods: ['POST'])]
    public function startTwoStep(): Response
    {
        return $this->act('two_step', fn(CurrentUser $user) => $this->security->startTwoStep($user));
    }

    #[Route('/account/security/two-step/confirm', name: 'account_security_two_step_confirm', methods: ['POST'])]
    public function confirmTwoStep(): Response
    {
        return $this->act('two_step', fn(CurrentUser $user) => $this->security->confirmTwoStep($user, (string) ($_POST['code'] ?? '')));
    }

    #[Route('/account/security/two-step/cancel', name: 'account_security_two_step_cancel', methods: ['POST'])]
    public function cancelTwoStep(): Response
    {
        return $this->act('two_step', fn() => $this->security->cancelTwoStep());
    }

    #[Route('/account/security/two-step/kept', name: 'account_security_two_step_kept', methods: ['POST'])]
    public function keptCodes(): Response
    {
        return $this->act('two_step', fn() => $this->security->keptCodes());
    }

    /** New recovery codes, after a current code. */
    #[Route('/account/security/two-step/codes', name: 'account_security_two_step_codes', methods: ['POST'])]
    public function newCodes(): Response
    {
        return $this->act('two_step', fn(CurrentUser $user) => $this->security->newRecoveryCodes($user, (string) ($_POST['code'] ?? '')), 'codes');
    }

    /** Turn two-step off, after a current code, unless the site asks this person to use it. */
    #[Route('/account/security/two-step/off', name: 'account_security_two_step_off', methods: ['POST'])]
    public function turnOff(): Response
    {
        return $this->act('two_step', fn(CurrentUser $user) => $this->security->turnOffTwoStep($user, (string) ($_POST['code'] ?? '')), 'off');
    }

    /**
     * Does what was asked and goes back to the page, at the card. A refusal is said on the card; when it came from a step that
     * asks for a code, the page shows that step again.
     */
    private function act(string $card, callable $action, string $askAgain = ''): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('ACCOUNT.SESSION.MANAGE');
        $back = self::PAGE . '#' . ($card === 'telegram' ? 'security-telegram' : 'security-two-step');
        try {
            $action($user);
        } catch (\InvalidArgumentException|\RuntimeException $refused) {
            $this->security->keep($card, 'danger', $refused->getMessage());
            if ($askAgain !== '') $back = self::PAGE . '?two_step=' . $askAgain . '#security-two-step';
        }
        $this->redirect($back);
    }
}
