declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Course\CoursePageLayout;
use CattoLearning\Course\CoursePageLayouts;
use CattoLearning\View\ThemeRenderer;
use InvalidArgumentException;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class AdminPageLayoutController extends BaseController
{
    private const PAGE = '/admin/courses/page-layouts';

    /** The feature cards over the courses' table: every course, or only those on one kind of layout. */
    private const SHOW = ['all' => 'All courses', 'default' => 'Default layout', 'layout' => 'Your other layouts', 'custom' => 'Custom layouts'];

    public function __construct(AuthService $auth, ThemeRenderer $view, RequestStack $requests, private readonly CoursePageLayouts $layouts)
    {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/admin/courses/page-layouts', name: 'admin_page_layouts', methods: ['GET'])]
    public function index(): Response
    {
        $user = $this->requirePermission('COURSE.MANAGEMENT.VIEW');
        $layouts = $this->layouts->all();
        $courses = $this->layouts->courses();
        $kind = static fn(array $course): string => $course['choice'];
        $show = (string) ($_GET['show'] ?? 'all');
        if (!isset(self::SHOW[$show])) $show = 'all';
        $counts = ['all' => count($courses)];
        foreach (['default', 'layout', 'custom'] as $key) $counts[$key] = count(array_filter($courses, static fn(array $course): bool => $kind($course) === $key));
        return $this->render('admin-course-page-layouts', [
            'title' => 'Course Page Layouts',
            'active_nav' => 'admin',
            'layouts' => array_map(static fn(array $layout): array => $layout + [
                'cells' => CoursePageLayouts::cells($layout['blocks']),
                'hidden' => array_values(array_map(static fn(array $block): string => CoursePageLayout::BLOCKS[$block['id']]['name'], array_filter($layout['blocks'], static fn(array $block): bool => !$block['shown']))),
            ], $layouts),
            'courses' => array_values(array_filter(array_map(static fn(array $course): array => $course + ['kind' => $kind($course)], $courses), static fn(array $course): bool => $show === 'all' || $course['kind'] === $show)),
            'show' => $show,
            'show_choices' => self::SHOW,
            'show_counts' => $counts,
            'can_manage' => $user->hasPermission('SYSTEM.SETTING.MANAGE'),
        ]);
    }

    #[Route('/admin/courses/page-layouts/new', name: 'admin_page_layout_new', methods: ['GET'])]
    public function newLayout(): Response
    {
        $this->requirePermission('SYSTEM.SETTING.MANAGE');
        // A new layout starts as the default layout, to change from there.
        $default = $this->layouts->defaultLayout();
        return $this->layoutPage(['id' => 0, 'name' => '', 'purpose' => '', 'blocks' => $default['blocks'], 'is_default' => false, 'courses' => 0, 'updated_at' => ''], true);
    }

    #[Route('/admin/courses/page-layouts/new', name: 'admin_page_layout_create', methods: ['POST'])]
    public function create(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            [$blocks] = CoursePageLayouts::fromForm($_POST);
            $id = $this->layouts->create((string) ($_POST['name'] ?? ''), (string) ($_POST['purpose'] ?? ''), $blocks, $user->id);
            $this->flash('success', 'The layout was made. Give it to courses on Course Page Layouts or on a course\'s Page layout tab.');
            $this->redirect(self::PAGE . '/' . $id);
        }, self::PAGE . '/new');
    }

    #[Route('/admin/courses/page-layouts/{id}', name: 'admin_page_layout', requirements: ['id' => '\\d+'], methods: ['GET'])]
    public function edit(): Response
    {
        $user = $this->requirePermission('COURSE.MANAGEMENT.VIEW');
        try {
            $layout = $this->layouts->layout($this->layoutId());
        } catch (InvalidArgumentException) {
            throw $this->notFound('There is no such layout.');
        }
        return $this->layoutPage($layout, $user->hasPermission('SYSTEM.SETTING.MANAGE'));
    }

    /** Saves the layout's name, what it is for and its blocks; without JavaScript, a move or a block hidden or shown too. */
    #[Route('/admin/courses/page-layouts/{id}', name: 'admin_page_layout_save', requirements: ['id' => '\\d+'], methods: ['POST'])]
    public function save(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        $id = $this->layoutId();
        // The course the sketch was drawn for, by its code (owner, 2026-11-06: no row id in an address).
        $back = self::PAGE . '/' . $id . (is_string($_POST['course'] ?? null) && $_POST['course'] !== '' ? '?course=' . rawurlencode($_POST['course']) : '');
        return $this->handle(function () use ($id, $user, $back): void {
            [$blocks, $action] = CoursePageLayouts::fromForm($_POST);
            $this->layouts->update($id, (string) ($_POST['name'] ?? ''), (string) ($_POST['purpose'] ?? ''), $blocks, $user->id);
            $courses = $this->layouts->layout($id)['courses'];
            $this->flash('success', $action === 'save'
                ? 'The layout was saved. ' . ($courses === 1 ? 'The 1 course that uses it shows it now.' : 'The ' . $courses . ' courses that use it show it now.')
                : 'The layout was saved as it is now.');
            $this->redirect($back . '#page-layout-form');
        }, $back);
    }

    #[Route('/admin/courses/page-layouts/{id}/copy', name: 'admin_page_layout_copy', requirements: ['id' => '\\d+'], methods: ['POST'])]
    public function copy(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            $copy = $this->layouts->copy($this->layoutId(), $user->id);
            $this->flash('success', 'The copy was made. Rename it and change it here: no course uses it yet.');
            $this->redirect(self::PAGE . '/' . $copy);
        }, self::PAGE);
    }

    #[Route('/admin/courses/page-layouts/{id}/default', name: 'admin_page_layout_default', requirements: ['id' => '\\d+'], methods: ['POST'])]
    public function makeDefault(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            $this->layouts->makeDefault($this->layoutId(), $user->id);
            $this->flash('success', '"' . $this->layouts->defaultLayout()['name'] . '" is the default layout now. Every course on the default layout shows it.');
            $this->redirect(self::PAGE);
        }, self::PAGE);
    }

    #[Route('/admin/courses/page-layouts/{id}/delete', name: 'admin_page_layout_delete', requirements: ['id' => '\\d+'], methods: ['POST'])]
    public function delete(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            $name = $this->layouts->delete($this->layoutId(), $user->id);
            $this->flash('success', 'The layout "' . $name . '" was deleted.');
            $this->redirect(self::PAGE);
        }, self::PAGE);
    }

    /** Gives the ticked courses the layout chosen beside Apply; a course with a custom layout keeps it to come back to. */
    #[Route('/admin/courses/page-layouts/apply', name: 'admin_page_layouts_apply', methods: ['POST'])]
    public function apply(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        $back = self::PAGE . (isset($_POST['show']) && isset(self::SHOW[(string) $_POST['show']]) && $_POST['show'] !== 'all' ? '?show=' . $_POST['show'] : '') . '#courses-layouts';
        return $this->handle(function () use ($user, $back): void {
            $courseIds = array_map('intval', (array) ($_POST['courses'] ?? []));
            $layoutId = (int) ($_POST['layout'] ?? 0);
            $changed = $this->layouts->apply($courseIds, $layoutId, $user->id);
            $name = $layoutId > 0 ? $this->layouts->layout($layoutId)['name'] : 'the default layout';
            $this->flash('success', $changed === 0 ? 'The ticked courses use ' . $name . ' already.' : ($changed === 1 ? '1 course uses ' : $changed . ' courses use ') . $name . ' now.');
            $this->redirect($back);
        }, $back);
    }

    /**
     * A layout's page: its name and purpose, the builder for its blocks, and the sketch for a course chosen with
     * ?course= (a course using the layout first, else the first course), with what that course leaves out.
     *
     * @param array{id:int,name:string,purpose:string,blocks:list<array{id:string,width:string,shown:bool}>,is_default:bool,courses:int,updated_at:string} $layout
     */
    private function layoutPage(array $layout, bool $canManage): Response
    {
        $courses = $this->layouts->courses();
        $default = $this->layouts->defaultLayout();
        $using = array_values(array_filter($courses, static fn(array $course): bool => $layout['id'] > 0
            && (($course['choice'] === 'layout' && $course['layout_id'] === $layout['id']) || ($course['choice'] === 'default' && $layout['is_default']))));
        // The course to sketch, named by its code in the address (owner, 2026-11-06).
        $chosen = (int) (array_column($courses, 'id', 'code')[is_string($_GET['course'] ?? null) ? $_GET['course'] : ''] ?? 0);
        $ids = array_column($courses, 'id');
        if (!in_array($chosen, $ids, true)) $chosen = (int) ($using[0]['id'] ?? $ids[0] ?? 0);
        $sketchCourses = array_map(static fn(array $course): array => ['id' => $course['id'], 'code' => $course['code'], 'label' => $course['code'] . ' · ' . $course['title'],
            'present' => $course['present'], 'selected' => $course['id'] === $chosen], $courses);
        $present = $chosen > 0 ? (array_column($courses, 'present', 'id')[$chosen] ?? array_keys(CoursePageLayout::BLOCKS)) : array_keys(CoursePageLayout::BLOCKS);
        return $this->render('admin-course-page-layout', [
            'title' => $layout['id'] > 0 ? $layout['name'] : 'New layout',
            'active_nav' => 'admin',
            'pl_layout' => $layout + ['default_name' => $default['name']],
            'builder' => CoursePageLayouts::builder($layout['blocks']),
            'sketch' => CoursePageLayouts::sketch($layout['blocks'], $present),
            'sketch_courses' => $sketchCourses,
            'sketch_present' => implode(',', $present),
            'using' => $using,
            'can_manage' => $canManage,
            'name_max' => CoursePageLayouts::NAME_MAX,
            'purpose_max' => CoursePageLayouts::PURPOSE_MAX,
        ]);
    }

    private function layoutId(): int
    {
        $id = (int) $this->param('id');
        if ($id < 1) throw new InvalidArgumentException('There is no such layout.');
        return $id;
    }
}
