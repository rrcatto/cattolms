        // platform administrator. Without this flag the section lists every course on the
        // platform to a course editor who administers only their own.
        if ($key === 'courses') {
            return ['view_all_courses' => $user->hasPermission('PLATFORM.DASHBOARD.VIEW')];
        }
        // Two sections since v0.6, and each needs its own flag. Missing this, the requests section
        // built with an empty capability set and rendered an empty screen with no error anywhere.
        return match ($key) {
            'requests' => ['view_requests' => $user->hasPermission('PLATFORM.REQUEST.VIEW')],
            'enrolments' => ['view_enrolments' => $user->hasPermission('PLATFORM.ENROLMENT.VIEW')],
            default => [],
        };
    }

    /**
     * Collects the request state one Administration section needs.
     *
     * Pagination parameters are dataset-prefixed (people_page, credits_page_size, ...) so the
     * consolidated workspace can carry several independent lists without them sharing a page
     * number. Raw values are passed through untouched: normalisation is Pagination's job, and
     * doing it in two places is how the two copies drift apart.
     *
     * @return array<string,mixed>
     */
    private function sectionRequest(string $key): array
    {
        $request = [];
        foreach (self::PAGINATED_DATASETS as $dataset) {
            $request[$dataset . '_page'] = $_GET[$dataset . '_page'] ?? null;
            $request[$dataset . '_page_size'] = $_GET[$dataset . '_page_size'] ?? null;
            // Sort state is dataset state like page and page size, and it is collected for every
            // dataset rather than for the ones that currently sort. A list that gains sorting and
            // is forgotten here would show working headers whose clicks did nothing - which is
            // exactly how the Companies search shipped inert.
            $request[$dataset . '_sort'] = $_GET[$dataset . '_sort'] ?? null;
            $request[$dataset . '_dir'] = $_GET[$dataset . '_dir'] ?? null;
        }

        // Course Requests narrows by status as well, so an operator can find the approvals that are
        // waiting on payment and have therefore put nobody on a course.
        $request['requests_status'] = $_GET['requests_status'] ?? null;

        // A list shown as a table or a grid of cards, as its reader chose (owner, 2026-10-26): the address's choice is
        // remembered, and the remembered one used when the address names none.
        foreach (array_keys(\CattoLearning\Support\ListView::DEFAULTS) as $list) {
            if ($list === 'catalogue') continue;
            $request[$list . '_view'] = \CattoLearning\Support\ListView::chosen($list, $_GET, $_COOKIE);
            if ($list === $key) \CattoLearning\Support\ListView::rememberAsked($list, $_GET);
        }

        // Search terms are collected from the declaration, not from a list written out here. The
        // Companies search shipped doing nothing because this method gathered page and page size
        // and nothing else: the form, the URL, the service, the predicate and the count were all
        // correct, and the term was dropped one layer above the query. Reading the declaration
        // means the next dataset to gain a search cannot be forgotten in the same way.
        foreach (array_keys(PlatformAdministrationService::SEARCHABLE_DATASETS) as $dataset) {
            $param = PlatformAdministrationService::searchParam($dataset);
            $request[$param] = $_GET[$param] ?? null;
        }

        return $key === 'activity' ? $request + $this->activityFilters() : $request;
    }

    /**
     * Activity filter values only. Pagination travels separately so that the row query and the
     * count query are guaranteed to receive an identical filter set.
     *
     * @return array<string,mixed>
     */
    private function activityFilters(): array
    {
        return [
            'from' => trim((string) ($_GET['from'] ?? '')),
            'to' => trim((string) ($_GET['to'] ?? '')),
            'family' => trim((string) ($_GET['family'] ?? '')),
            'actor_id' => max(0, (int) ($_GET['actor_id'] ?? 0)),
            'course_id' => max(0, (int) ($_GET['course_id'] ?? 0)),
            'company_id' => max(0, (int) ($_GET['company_id'] ?? 0)),
            'q' => trim((string) ($_GET['q'] ?? '')),
        ];
    }

