    /**
     * Renders one Administration section through the same section definition
     * and business-data source used by the consolidated workspace.
     */
    private function renderAdministrationSection(string $key): void
    {
        $user = $this->requireUser();
        if (!$this->canAccessAdministrationSection($user, $key)) {
            $this->f3->error(403, 'You do not have permission to access this Administration section.');
            return;
        }
        $definition = $this->adminSections->get($key);
        $filters = $this->sectionRequest($key);
        $capabilities = $this->sectionCapabilities($user, $key);
        $crossUniverse = $this->canSelectUniverse($user);

        // A paging or search request replaces one table and nothing else, so it builds one table
        // and nothing else. The header, the navigation, the summary strip, the universe counts and
        // any second table on the screen are all still on the reader's screen, unchanged, and
        // rebuilding them only to throw them away was the largest part of what a page turn cost.
        $swapping = $this->htmxDataset();
        $data = in_array($key, ['roles', 'seed'], true)
            ? []
            : $this->platformAdministration->sectionData(
                $key,
                $user->id,
                $this->universe($user),
                $filters,
                $capabilities,
                $crossUniverse,
                $swapping
            );
        // Merged in front so the selector and its counts win over the empty view defaults that
        // sectionData() supplies for sections which have neither.
        $data = $this->platformAdministration->universeView(
            $key,
            $user->id,
            $this->universe($user),
            $crossUniverse,
            $filters,
            $capabilities,
            null,
            $swapping === null
        ) + $data;
        $data = $this->withAdministrationPresentation($data, false, $definition);
        // The Companies table offers a Manage action that hands the row to the Company workspace.
        // Whether to render it is the same question SelectedCompanyContext answers, asked through
        // the context itself so the button appears exactly where the selection would be honoured.
        $data['can_select_company'] = $this->companyContext->canSelect($user);

        // Which tab each group strip shows as current. Set before the swap branch, not after it: a
        // section body includes its group strip, so a fragment that omitted these would render the
        // strip with no tab marked and, in F3, on an undefined variable.
        $data['course_group'] = match ($key) { 'courses' => 'courses', 'enrolments' => 'enrolments', 'requests' => 'requests', default => '' };
        $data['company_group'] = match ($key) { 'companies' => 'consumers', 'company_creators' => 'creators', default => '' };

        // Nothing but the section body is sent back for a swap. htmx still selects the results
        // element out of it, so the markup contract is unchanged and a client that forges or omits
        // the header simply receives the whole page, as it always did.
        if ($swapping !== null) {
            // preg_replace, not rtrim. rtrim takes a set of characters rather than a suffix, so
            // rtrim('...form.html', '.html') strips the trailing "m" of "form" as well and asks for
            // a template that does not exist. The registry template always ends in .html.
            $this->renderFragment((string) preg_replace('/\.html$/', '', $definition['template']), $data);

            return;
        }

        $this->render('admin-section', $data + [
            'title' => $definition['label'] . ' · Administration',
            'page_title' => $definition['label'],
            'page_kicker' => $this->sectionKicker($user, $key),
            'load_ckeditor' => false,
        ]);
    }

    /**
     * The eyebrow above a section heading.
     *
     * Almost always "Platform administration", because that is what the reader is doing. Courses
     * is the exception: COURSE.MANAGEMENT.VIEW opens it for a course editor or owner who
     * administers only their own courses and is not a platform administrator at all, so telling
     * them they are doing platform administration is simply untrue. The distinction predates this
     * route moving onto the shared renderer and is kept deliberately rather than lost in the move.
     */
    private function sectionKicker(CurrentUser $user, string $key): string
    {
        if ($key === 'courses' && !$user->hasPermission('PLATFORM.DASHBOARD.VIEW')) {
            return 'Course authoring';
        }

        return 'Platform administration';
    }

    /**
     * Adds view-layer Administration dependencies without moving theme or
     * maintenance concerns into the application business service.
     *
     * @param array<string,mixed> $data
     * @param array{key:string,label:string,icon:string,route:string,template:string,description:string}|null $singleSection
     * @param list<array{key:string,label:string,icon:string,route:string,template:string,description:string}>|null $workspaceSections
     * @return array<string,mixed>
     */
    private function withAdministrationPresentation(array $data, bool $workspace, ?array $singleSection = null, ?array $workspaceSections = null): array
    {
        $sectionKeys = $workspace
            ? array_column($workspaceSections ?? $this->adminSections->all(), 'key')
            : [(string) ($singleSection['key'] ?? '')];
        if (in_array('themes', $sectionKeys, true)) {
            $data['themes'] = $this->themes->themes();
            $data['active_theme_name'] = $this->themes->activeTheme();
            $data['theme_registry_out_of_sync'] = $this->themes->registryOutOfSync();
        }
        if (in_array('settings', $sectionKeys, true)) {
            $data['maintenance'] = $this->maintenance->pending();
        }
        if (in_array('roles', $sectionKeys, true)) {
            $data['roles_acl'] = $this->roleAdministration->roles();
            $data['permission_total'] = $this->roleAdministration->permissionTotal();
        }
        if (in_array('seed', $sectionKeys, true)) {
            $data['seed_sets'] = $this->seeds->sets();
            $data['seed_total_records'] = $this->seeds->totalSeedRecords();
            $data['seed_volume'] = $this->seeds->volumeBounds();
            $data['seed_cleanup_preview'] = null;
        }

        if ($workspace) {
            $data['admin_sections'] = $workspaceSections ?? $this->adminSections->all();
            $data['admin_layout'] = 'workspace';
        } elseif ($singleSection !== null) {
            $data['admin_section'] = $singleSection;
            $data['admin_layout'] = 'section';
        }
        return $data;
    }

    private function administrationPermission(CurrentUser $user, string $key): string
    {
        return match ($key) {
            'dashboard' => 'PLATFORM.DASHBOARD.VIEW',
            'courses' => 'COURSE.MANAGEMENT.VIEW',
            'people' => 'PLATFORM.PERSON.VIEW',
            'companies' => 'PLATFORM.COMPANY.VIEW',
            'company_creators' => 'PLATFORM.COMPANY.VIEW',
            'enrolments' => 'PLATFORM.ENROLMENT.VIEW',
            // Both were falling through to the default, so Course Requests was gated on the
            // dashboard permission and Company Enrolments on it too. Each section is one
            // permission since the combined screens were split.
            'requests' => 'PLATFORM.REQUEST.VIEW',
            'company_report' => 'PLATFORM.REPORT.VIEW',
            'credits' => 'PLATFORM.CREDIT.VIEW',
            'activity' => 'PLATFORM.ACTIVITY.VIEW',
            'reports' => 'PLATFORM.REPORT.VIEW',
            'themes' => 'SYSTEM.THEME.VIEW',
            'settings' => 'SYSTEM.SETTING.VIEW',
            'roles' => 'SYSTEM.ROLE.VIEW',
            'seed' => 'SYSTEM.SEED.VIEW',
            default => 'PLATFORM.DASHBOARD.VIEW',
        };
    }

    private function canAccessAdministrationSection(CurrentUser $user, string $key): bool
    {
        return $user->hasPermission($this->administrationPermission($user, $key));
    }

    /** @return array<string,bool> */
    private function sectionCapabilities(CurrentUser $user, string $key): array
    {
        // COURSE.MANAGEMENT.VIEW opens the Courses section; it does not make the actor a
        // platform administrator. Without this flag the section lists every course on the
        // platform to a course editor who administers only their own.
        if ($key === 'courses') {
            return ['view_all_courses' => $user->hasPermission('PLATFORM.DASHBOARD.VIEW')];
        }
        // Two sections since v0.6, and each needs its own flag. Missing this, the requests section
        // built with an empty capability set and rendered an empty screen with no error anywhere.
        return match ($key) {
            'requests' => ['view_requests' => $user->hasPermission('PLATFORM.REQUEST.VIEW')],
            'enrolments' => ['view_enrolments' => $user->hasPermission('PLATFORM.ENROLMENT.VIEW')],
            default => [],
        };
    }

    /**
     * Collects the request state one Administration section needs.
     *
     * Pagination parameters are dataset-prefixed (people_page, credits_page_size, ...) so the
     * consolidated workspace can carry several independent lists without them sharing a page
     * number. Raw values are passed through untouched: normalisation is Pagination's job, and
     * doing it in two places is how the two copies drift apart.
     *
     * @return array<string,mixed>
     */
    private function sectionRequest(string $key): array
    {
        $request = [];
        foreach (self::PAGINATED_DATASETS as $dataset) {
            $request[$dataset . '_page'] = $_GET[$dataset . '_page'] ?? null;
            $request[$dataset . '_page_size'] = $_GET[$dataset . '_page_size'] ?? null;
            // Sort state is dataset state like page and page size, and it is collected for every
            // dataset rather than for the ones that currently sort. A list that gains sorting and
            // is forgotten here would show working headers whose clicks did nothing - which is
            // exactly how the Companies search shipped inert.
            $request[$dataset . '_sort'] = $_GET[$dataset . '_sort'] ?? null;
            $request[$dataset . '_dir'] = $_GET[$dataset . '_dir'] ?? null;
        }

        // Course Requests narrows by status as well, so an operator can find the approvals that are
        // waiting on payment and have therefore put nobody on a course.
        $request['requests_status'] = $_GET['requests_status'] ?? null;

        // Search terms are collected from the declaration, not from a list written out here. The
        // Companies search shipped doing nothing because this method gathered page and page size
        // and nothing else: the form, the URL, the service, the predicate and the count were all
        // correct, and the term was dropped one layer above the query. Reading the declaration
        // means the next dataset to gain a search cannot be forgotten in the same way.
        foreach (array_keys(PlatformAdministrationService::SEARCHABLE_DATASETS) as $dataset) {
            $param = PlatformAdministrationService::searchParam($dataset);
            $request[$param] = $_GET[$param] ?? null;
        }

        return $key === 'activity' ? $request + $this->activityFilters() : $request;
    }

    /**
     * Activity filter values only. Pagination travels separately so that the row query and the
     * count query are guaranteed to receive an identical filter set.
     *
     * @return array<string,mixed>
     */
    private function activityFilters(): array
    {
        return [
            'from' => trim((string) ($_GET['from'] ?? '')),
            'to' => trim((string) ($_GET['to'] ?? '')),
            'family' => trim((string) ($_GET['family'] ?? '')),
            'actor_id' => max(0, (int) ($_GET['actor_id'] ?? 0)),
            'course_id' => max(0, (int) ($_GET['course_id'] ?? 0)),
            'company_id' => max(0, (int) ($_GET['company_id'] ?? 0)),
            'q' => trim((string) ($_GET['q'] ?? '')),
        ];
    }


