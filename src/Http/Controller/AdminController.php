    /**
     * Renders the complete Administration workspace. All top-level sections
     * are loaded together and exposed through the presentation-neutral
     * @admin.sections Theme API; no tab/query parameter selects a section.
     */
    #[Route('/admin', name: 'admin_index', methods: ['GET'])]
    public function index(): Response
    {
        $user = $this->requireUser();
        $sections = array_values(array_filter(
            $this->adminSections->all(),
            fn(array $section): bool => $this->canAccessAdministrationSection($user, (string) $section['key'])
        ));
        if ($sections === []) {
            throw new AccessDeniedHttpException('You do not have permission to access Administration.');
        }
        // The consolidated workspace loads a bounded preview of each section rather than a full
        // paginated page. Before v0.5.7.6 this ran every section's complete dataset in one
        // request, so /admin was the single most expensive page in the platform.
        //
        // The whole section list goes in one call: merging per-section payloads here let a
        // later section's view defaults overwrite an earlier section's real values, which is
        // how every "View all" link vanished from the workspace.
        $keys = array_map(static fn(array $section): string => (string) $section['key'], $sections);
        $capabilities = [];
        foreach ($keys as $key) $capabilities[$key] = $this->sectionCapabilities($user, $key);

        $data = $this->platformAdministration->workspacePreview($keys, $user->id, $capabilities)
            // The Seed Database section is a form rather than a dataset, so the section loader has
            // nothing to give it: its bounds, and where the last run stands.
            + ['seed_bounds' => $this->seedDatabase->bounds(), 'seed_run' => $this->seedDatabase->status(), 'seed_unavailable' => $this->seedDatabase->unavailable()];
        return $this->render('admin-control-centre', $this->withAdministrationPresentation($data, true, null, $sections) + [
            'title' => 'Administration',
            'page_kicker' => 'Complete permitted platform administration workspace',
            'load_ckeditor' => false,
        ]);
    }

