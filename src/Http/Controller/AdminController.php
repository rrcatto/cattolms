    /**
     * Renders one Administration section through the same section definition
     * and business-data source used by the consolidated workspace.
     */
    private function renderAdministrationSection(string $key): Response
    {
        $user = $this->requireUser();
        if (!$this->canAccessAdministrationSection($user, $key)) {
            throw new AccessDeniedHttpException('You do not have permission to access this Administration section.');
        }
        $definition = $this->adminSections->get($key);
        $filters = $this->sectionRequest($key);
        $capabilities = $this->sectionCapabilities($user, $key);

        // A paging or search request replaces one table and nothing else, so it builds one table
        // and nothing else. The header, the navigation, the summary strip and any second table on
        // the screen are all still on the reader's screen, unchanged, and rebuilding them only to
        // throw them away was the largest part of what a page turn cost.
        $swapping = $this->htmxDataset();
        $data = $key === 'roles'
            ? []
            : $this->platformAdministration->sectionData(
                $key,
                $user->id,
                $filters,
                $capabilities,
                $swapping
            );
        // Each person's picture, uploaded or drawn (owner, 2026-10-26), for their card.
        if ($key === 'people' && isset($data['people']) && is_array($data['people']) && array_is_list($data['people'])) {
            $data['people'] = $this->pictures->withPictures($data['people']);
            // Each one's sign-up check, its risk at a glance (owner, 2026-10-26); none for an account made here.
            $checks = $this->signupAttempts->forUsers(array_map(static fn(array $row): int => (int) ($row['id'] ?? 0), $data['people']));
            foreach ($data['people'] as $index => $row) {
                $check = $checks[(int) ($row['id'] ?? 0)] ?? null;
                $data['people'][$index]['risk'] = $check === null ? null : ['label' => \CattoLearning\Auth\Signup\RiskAssessment::label($check['band']) . ' ' . $check['score'],
                    'tone' => \CattoLearning\Auth\Signup\RiskAssessment::tone($check['band']), 'href' => '/admin/people/signup-attempts/' . $check['id']];
            }
        }
        // Each company's logo, or its drawn picture (owner, 2026-10-26), for its row and its Edit window.
        foreach (['companies', 'company_creators'] as $companyRows) {
            if ($key === $companyRows && isset($data[$companyRows]) && is_array($data[$companyRows]) && array_is_list($data[$companyRows])) {
                $data[$companyRows] = $this->logos->withPictures($data[$companyRows]);
            }
        }
        $data = $this->withAdministrationPresentation($data, false, $definition);

        // Nothing but the section body is sent back for a swap. htmx still selects the results
        // element out of it, so the markup contract is unchanged and a client that forges or omits
        // the header simply receives the whole page, as it always did.
        if ($swapping !== null) {
            // preg_replace, not rtrim. rtrim takes a set of characters rather than a suffix, so
            // rtrim('...form.html', '.html') strips the trailing "m" of "form" as well and asks for
            // a template that does not exist. The registry template always ends in .html.
            return $this->renderFragment((string) preg_replace('/\.html\.twig$/', '', $definition['template']), $data);
        }

        return $this->render('admin-section', $data + [
            'title' => $definition['label'] . ' · Administration',
            'page_title' => $definition['label'],
            'page_kicker' => $this->sectionKicker($user, $key),
            'load_ckeditor' => false,
        ]);
    }

    /**
     * The eyebrow above a section heading.
     *
     * Almost always "Platform administration", because that is what the reader is doing. Courses
     * is the exception: COURSE.MANAGEMENT.VIEW opens it for a course editor or owner who
     * administers only their own courses and is not a platform administrator at all, so telling
     * them they are doing platform administration is simply untrue. The distinction predates this
     * route moving onto the shared renderer and is kept deliberately rather than lost in the move.
     */
    private function sectionKicker(CurrentUser $user, string $key): string
