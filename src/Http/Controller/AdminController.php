    public function mailPassword(): void
    {
        $this->requireCsrf();
        $this->requireRole('platform_admin');
        $payload = $this->app->platformAdministration->mailPasswordForAdmin();
        header('Content-Type: application/json; charset=utf-8');
        header('Cache-Control: no-store, no-cache, must-revalidate, private');
        header('Pragma: no-cache');
        echo json_encode($payload, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        exit;
    }

    public function saveMailSettings(): void
    {
        $this->requireCsrf();
        $user = $this->requireRole('platform_admin');
