    /**
     * Renders one Administration section through the same section definition
     * and business-data source used by the consolidated workspace.
     */
    private function renderAdministrationSection(string $key): void
    {
        $user = $this->requireUser();
        if (!$this->canAccessAdministrationSection($user, $key)) {
            $this->f3->error(403, 'You do not have permission to access this Administration section.');
            return;
        }
        $definition = $this->adminSections->get($key);
        $filters = $key === 'activity' ? $this->activityFilters() : ($key === 'companies' ? $this->companyFilters() : []);
        $data = $key === 'roles' ? [] : $this->platformAdministration->sectionData($key, $user->id, $filters, $this->sectionCapabilities($user, $key));
        $data = $this->withAdministrationPresentation($data, false, $definition);

        $this->render('admin-section', $data + [
            'title' => $definition['label'] . ' · Administration',
            'page_title' => $definition['label'],
            'page_kicker' => 'Platform administration',
            'load_ckeditor' => false,
        ]);
    }

    /**
     * Adds view-layer Administration dependencies without moving theme or
     * maintenance concerns into the application business service.
     *
     * @param array<string,mixed> $data
     * @param array{key:string,label:string,icon:string,route:string,template:string,description:string}|null $singleSection
     * @param list<array{key:string,label:string,icon:string,route:string,template:string,description:string}>|null $workspaceSections
     * @return array<string,mixed>
     */
    private function withAdministrationPresentation(array $data, bool $workspace, ?array $singleSection = null, ?array $workspaceSections = null): array
    {
        $sectionKeys = $workspace
            ? array_column($workspaceSections ?? $this->adminSections->all(), 'key')
            : [(string) ($singleSection['key'] ?? '')];
        if (in_array('themes', $sectionKeys, true)) {
            $data['themes'] = $this->themes->themes();
            $data['active_theme_name'] = $this->themes->activeTheme();
            $data['theme_registry_out_of_sync'] = $this->themes->registryOutOfSync();
        }
        if (in_array('settings', $sectionKeys, true)) {
            $data['maintenance'] = $this->maintenance->pending();
        }
        if (in_array('roles', $sectionKeys, true)) {
            $data['roles_acl'] = $this->roleAdministration->roles();
            $data['permission_total'] = $this->roleAdministration->permissionTotal();
        }

        if ($workspace) {
            $data['admin_sections'] = $workspaceSections ?? $this->adminSections->all();
            $data['admin_layout'] = 'workspace';
        } elseif ($singleSection !== null) {
            $data['admin_section'] = $singleSection;
            $data['admin_layout'] = 'section';
        }
        return $data;
    }

    private function administrationPermission(CurrentUser $user, string $key): string
    {
        return match ($key) {
            'dashboard' => 'PLATFORM.DASHBOARD.VIEW',
            'courses' => 'COURSE.MANAGEMENT.VIEW',
            'people' => 'PLATFORM.PERSON.VIEW',
            'companies' => 'PLATFORM.COMPANY.VIEW',
            'enrolments' => 'PLATFORM.ENROLMENT.VIEW',
