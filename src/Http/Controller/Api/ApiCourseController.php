declare(strict_types=1);

namespace CattoLearning\Http\Controller\Api;

use CattoLearning\Course\CatalogueFilter;
use CattoLearning\Course\CourseService;

use CattoLearning\Api\AuthorizationService;

use CattoLearning\Api\ApiAuthService;

use Base;

use CattoLearning\Auth\DataUniverse;
use CattoLearning\Api\ApiScope;
use CattoLearning\Api\AuthorizationException;
use CattoLearning\Support\Pagination;

final class ApiCourseController extends BaseApiController
{
    public function __construct(
        Base $f3,
        ApiAuthService $apiAuth,
        AuthorizationService $authorization,
        private readonly CourseService $courses
    ) {
        parent::__construct($f3, $apiAuth, $authorization);
    }

    /**
     * Lists the published catalogue, one page at a time.
     *
     * The underlying query is now bounded, so the response carries explicit pagination meta:
     * a client must be able to tell that more courses exist rather than silently receiving a
     * truncated list.
     */
    public function index(): void
    {
        $this->execute(function (): void {
            $this->identity(ApiScope::COURSES_READ, 'CATALOGUE.VIEW');
            $pagination = Pagination::create($_GET['page'] ?? null, $_GET['page_size'] ?? null, $this->courses->catalogueCount(DataUniverse::Real, CatalogueFilter::none()));
            $this->respond([
                'data' => $this->courses->catalogue(DataUniverse::Real, CatalogueFilter::none(), $pagination->pageSize, $pagination->offset),
                'meta' => $pagination->toArray(),
            ]);
        });
    }

    public function show(): void
    {
        $this->execute(function (): void {
            $this->identity(ApiScope::COURSES_READ, 'CATALOGUE.VIEW');
            $slug = (string) $this->f3->get('PARAMS.slug');
            $course = $this->courses->publicCourse($slug, DataUniverse::Real);
            if ($course === null) {
                $this->notFound('The course could not be found.');
                return;
            }

            $this->respond(['data' => $course]);
        });
    }

    public function create(): void
    {
        $this->execute(function (): void {
            $identity = $this->identity(ApiScope::COURSES_WRITE, 'COURSE.CREATE');
            $body = $this->jsonBody();
            if (!array_key_exists('certificate_enabled', $body)) {
                $body['certificate_enabled'] = true;
            }
            // REAL-only: decision D3 forbids issuing an API token to a seed identity, so no
            // request on this surface can belong to the SEED universe.
            $courseId = $this->courses->createBlank(
                $body,
                $identity->userId,
                DataUniverse::Real
            );
            $this->respond([
                'data' => $this->courses->adminCourse($courseId),
            ], 201);
        });
    }

    public function update(): void
    {
        $this->execute(function (): void {
            $identity = $this->identity(ApiScope::COURSES_WRITE, 'COURSE.EDIT');
            $courseId = (int) $this->f3->get('PARAMS.id');
            if (!$identity->hasPermission('PLATFORM.DASHBOARD.VIEW')
                && !$this->courses->userCanManageCourse($courseId, $identity->userId)) {
                throw new AuthorizationException('The authenticated account cannot manage this course.');
            }
            $this->courses->updateCourse(
                $courseId,
                $this->jsonBody(),
                $identity->userId
            );
            $this->respond([
                'data' => $this->courses->adminCourse($courseId),
            ]);
        });
    }

    public function status(): void
    {
        $this->execute(function (): void {
            $identity = $this->identity(ApiScope::COURSES_PUBLISH, 'COURSE.PUBLISH');
            $courseId = (int) $this->f3->get('PARAMS.id');
            if (!$identity->hasPermission('PLATFORM.DASHBOARD.VIEW')
                && !$this->courses->userCanManageCourse($courseId, $identity->userId)) {
                throw new AuthorizationException('The authenticated account cannot manage this course.');
            }
            $body = $this->jsonBody();
            $this->courses->changeStatus(
                $courseId,
                (string) ($body['status'] ?? ''),
                $identity->userId
            );
            $this->respond([
                'data' => $this->courses->adminCourse($courseId),
            ]);
        });
    }
}