declare(strict_types=1);

namespace CattoLearning\Http\Controller\Api;

use Base;
use CattoLearning\Api\ApiAuthService;
use CattoLearning\Api\ApiIdentity;
use CattoLearning\Api\AuthenticationException;
use CattoLearning\Api\AuthorizationException;
use CattoLearning\Api\AuthorizationService;
use InvalidArgumentException;
use JsonException;
use RuntimeException;
use Throwable;

abstract class BaseApiController
{
    public function __construct(
        protected readonly Base $f3,
        protected readonly ApiAuthService $apiAuth,
        protected readonly AuthorizationService $authorization
    ) {
    }

    protected function identity(string $scope, string $permission): ApiIdentity
    {
        $identity = $this->apiAuth->authenticateBearer($this->authorizationHeader());
        $this->authorization->requireBusinessAccess($identity, $scope, $permission);

        return $identity;
    }

    /** @return array<string,mixed> */
    protected function jsonBody(): array
    {
        $raw = (string) file_get_contents('php://input');
        if (trim($raw) === '') {
            return [];
        }

        try {
            $data = json_decode($raw, true, 512, JSON_THROW_ON_ERROR);
        } catch (JsonException $exception) {
            throw new InvalidArgumentException('The request body is not valid JSON.', 0, $exception);
        }

        if (!is_array($data)) {
            throw new InvalidArgumentException('The JSON request body must be an object.');
        }

        return $data;
    }

    /** @param array<string,mixed>|list<mixed> $data */
    protected function respond(array $data, int $status = 200): void
    {
        http_response_code($status);
        header('Content-Type: application/json; charset=utf-8');
        header('Cache-Control: no-store');
        echo json_encode($data, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
    }

    protected function execute(callable $callback): void
    {
        try {
            $callback();
        } catch (AuthenticationException $exception) {
            header('WWW-Authenticate: Bearer');
            $this->problem(401, 'unauthenticated', $exception->getMessage());
        } catch (AuthorizationException $exception) {
            $this->problem(403, 'forbidden', $exception->getMessage());
        } catch (InvalidArgumentException $exception) {
            $this->problem(422, 'invalid_request', $exception->getMessage());
        } catch (RuntimeException $exception) {
            $this->problem(409, 'request_failed', $exception->getMessage());
        } catch (Throwable $exception) {
            error_log($exception->__toString());
            $this->problem(500, 'server_error', 'An unexpected error occurred.');
        }
    }

    protected function notFound(string $message): void
    {
        $this->problem(404, 'not_found', $message);
    }

    private function problem(int $status, string $code, string $message): void
    {
        $this->respond([
            'error' => [
                'status' => $status,
                'code' => $code,
                'message' => $message,
            ],
        ], $status);
    }

    private function authorizationHeader(): string
    {
        return trim((string) (
            $_SERVER['HTTP_AUTHORIZATION']
            ?? $_SERVER['REDIRECT_HTTP_AUTHORIZATION']
            ?? $this->f3->get('HEADERS.Authorization')
            ?? ''
        ));
    }
