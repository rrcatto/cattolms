namespace CattoLearning\Http\Controller\Api;

use CattoLearning\Course\LearningService;

use CattoLearning\Api\AuthorizationService;

use CattoLearning\Api\ApiAuthService;

use Base;

use CattoLearning\Api\ApiScope;

final class ApiLearningController extends BaseApiController
{
    public function __construct(
        Base $f3,
        ApiAuthService $apiAuth,
        AuthorizationService $authorization,
        private readonly LearningService $learning
    ) {
        parent::__construct($f3, $apiAuth, $authorization);
    }

    public function library(): void
    {
        $this->execute(function (): void {
            $identity = $this->identity(ApiScope::LIBRARY_READ, 'LEARNING.LIBRARY.VIEW');
            $this->respond([
                'data' => $this->learning->library($identity->userId),
            ]);
        });
    }

    public function start(): void
    {
        $this->execute(function (): void {
            $identity = $this->identity(ApiScope::LEARNING_START, 'LEARNING.COURSE.START');
            $slug = (string) $this->f3->get('PARAMS.slug');
            $this->learning->start($identity->userId, $slug);
            $this->respond([
                'data' => $this->learning->courseHome(
                    $identity->userId,
                    $slug
                ),
            ]);
        });
    }
