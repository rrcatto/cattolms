    /** Take back, pause, resume, cancel, approve, duplicate and delete. */
    #[Route('/mailing/messages/{id}/{action}', name: 'mailing_manage_campaign_action', requirements: ['id' => '\d+', 'action' => 'unschedule|pause|resume|cancel|approve|duplicate|delete'], methods: ['POST'])]
    public function action(): Response
    {
        $action = (string) $this->param('action');
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');
        $id = (int) $this->param('id');

        return $this->handle(function () use ($action, $id, $user): void {
            switch ($action) {
                case 'duplicate':
                    $copy = $this->service->duplicate($id, $user->id);
                    $this->flash('success', 'A copy was made as a draft.');
                    $this->redirect(self::BASE . '/' . $copy);
                case 'delete':
                    $this->service->delete($id, $user->id);
                    $this->flash('success', 'The message was deleted.');
                    $this->redirect(self::BASE);
                case 'unschedule': $this->service->unschedule($id, $user->id); $done = 'It is a draft again.'; break;
                case 'pause': $this->service->pause($id, $user->id, $this->firstName($user->id) ?: 'an administrator'); $done = 'It is paused. Nothing more goes until you resume it.'; break;
                case 'resume': $this->service->resume($id, $user->id); $done = 'It goes on.'; break;
                case 'cancel': $this->service->cancel($id, $user->id); $done = 'It is cancelled. Nothing more will be sent.'; break;
                default: $this->service->approve($id, $user->id); $done = 'It is approved and goes out within a minute.';
            }
            $this->flash('success', $done);
            $this->redirect(self::BASE . '/' . $id . '#send');
        }, self::BASE . '/' . $id . '#send');
    }

