    /**
     * The Switch Company results region.
     *
     * Returns the same fragment the modal renders inline, so htmx swaps like for like. The
     * canonical state stays in the query string: without JavaScript the same URL renders the same
     * page of results as an ordinary GET.
     */
    public function picker(): void
    {
        $user = $this->requirePermission(SelectedCompanyContext::SELECTOR_PERMISSION);
        if (!$this->companyContext->canSelect($user)) {
            $this->f3->error(403, 'Your account administers a single company.');
            return;
        }

        // ALL by default, and never the request universe. The picker's job is to show every
        // company this administrator may take on; the company they choose then decides which
        // universe the workspace operates in. Resolving it from the request meant the modal, which
        // sends no universe, always resolved REAL - so a SEED company could not be found at all.
        $data = $this->platformAdministration->companyPicker($_GET)
            + ['company_context_id' => $this->contextCompanyId($user)];

        if ($this->isHtmxRequest()) {
            $this->renderFragment('partials/company-picker-results', $data);
            return;
        }

        $this->render('company-picker', $data + [
            'title' => 'Switch company', 'page_title' => 'Switch company', 'active_nav' => 'company',
        ]);
    }


    /**
     * The company every Company workspace write acts on.
     *
     * A Company Administrator resolves to their own company; a genuine platform administrator
     * resolves to the one they selected. Asking SelectedCompanyContext rather than
     * `CompanyRepository::findForUser($actorUserId)` is the whole correction: the old call read
     * the *actor's* membership, so a platform administrator's writes went to their own company
     * while the workspace displayed another - or were refused because they belong to none.
     */
    private function contextCompanyId(CurrentUser $user): int
    {
        return $this->companyContext->contextCompanyId($user);
    }

    /**
     * Renders one standalone Company section.
     *
     * Each section now loads only its own paginated dataset. Previously every /company/* route
     * called the consolidated loader, so opening Company People also fetched requests,
     * enrolments, credits and the entire course list.
     */
    private function standalone(string $key, string $permission): void
    {
        $user = $this->requirePermission($permission);
        $definition = $this->sections->get($key);
        // The selector view comes FIRST. companySectionData() ends by applying datasetDefaults(),
        // which seeds can_select_company => false, and PHP's + keeps the left operand - so putting
        // the defaults on the left discarded the real answer and the Administering-company banner
        // and its Switch Company modal vanished from every standalone page.
        $data = $this->companySelectorView($user)
            + $this->platformAdministration->companySectionData(
                $key,
                $user->id,
                $this->companyContext->resolve($user),
                $this->sectionRequest()
            );
        $data['company_section'] = $definition;
        $data['company_layout'] = 'section';
        $this->render('company-section', $data + [
            'title' => $definition['label'] . ' · Company', 'page_title' => $definition['label'], 'page_kicker' => 'Company', 'active_nav' => 'company',
        ]);
    }

    /**
     * Collects dataset-prefixed pagination state for the Company standalone routes.
     *
     * @return array<string,mixed>
     */
    private function sectionRequest(): array
    {
        $request = [];
        foreach (['people', 'requests', 'enrolments', 'credits', 'courses', 'training', 'company_favourites', 'company_performance'] as $dataset) {
            $request[$dataset . '_page'] = $_GET[$dataset . '_page'] ?? null;
            $request[$dataset . '_page_size'] = $_GET[$dataset . '_page_size'] ?? null;
            // Sort state is dataset state like page and page size, collected for every dataset
            // rather than the ones that currently sort: a list that gains sorting and is forgotten
            // here would show working headers whose clicks did nothing.
            $request[$dataset . '_sort'] = $_GET[$dataset . '_sort'] ?? null;
            $request[$dataset . '_dir'] = $_GET[$dataset . '_dir'] ?? null;
        }

        // Search terms come from the shared declaration for the same reason they do in
        // Administration: a hardcoded list here is where the next dataset's search gets forgotten.
        foreach (array_keys(PlatformAdministrationService::SEARCHABLE_DATASETS) as $dataset) {
            $param = PlatformAdministrationService::searchParam($dataset);
            $request[$param] = $_GET[$param] ?? null;
        }

        return $request;
    }

    /** @return array<string,mixed> */
    private function workspaceData(CurrentUser $user): array
    {
        // Same ordering rule as standalone(): real values first, shared defaults last.
        return $this->companySelectorView($user)
            + $this->platformAdministration->companyControlCentre(
                $user->id,
                $this->companyContext->resolve($user)
            );
    }

    /**
     * The view contract for the "Administering company" control.
     *
     * Built here rather than in the template so that whether the control is offered and whether a
     * selection would actually be honoured are decided by the same code. A control shown to
     * somebody whose selection is ignored is worse than no control.
     *
     * @return array<string,mixed>
     */
    private function companySelectorView(CurrentUser $user): array
    {
        $canSelect = $this->companyContext->canSelect($user);
        $context = $this->companyContext->resolve($user);

        return [
            'can_select_company' => $canSelect,
            'company_context_mode' => (string) $context['mode'],
            'company_context_name' => (string) ($context['company']['name'] ?? ''),
            'company_context_domain' => (string) ($context['company']['domain'] ?? ''),
            'company_context_id' => (int) $context['company_id'],
            // The switcher renders its first page of companies server-side so it works with no
            // JavaScript at all; htmx only replaces the same region on search and paging.
            'company_switcher' => $canSelect
                ? $this->platformAdministration->companyPicker([])
                : null,
        ];
    }

    /**
     * Chooses which company a platform administrator is administering.
     *
     * A POST with a CSRF token, never a GET parameter. The selection is an authorisation
     * boundary, and `?company_id=` on a read would be exactly the widening this design exists to
     * refuse - as well as a read that writes, which this project has already been bitten by once.
     */
    public function selectCompany(): void
    {
        $this->requireCsrf();
        $user = $this->requirePermission('COMPANY.DASHBOARD.VIEW');
        $this->handle(function () use ($user): void {
            $companyId = (int) ($_POST['company_id'] ?? 0);
            if ($companyId === 0) {
                // Back to the default rather than to a synthetic "all companies" context, which
                // no mutation could ever act on.
                $this->companyContext->clear();
                $this->flash('success', 'Returned to the default company.');
                $this->redirect('/company');
            }

            $company = $this->companyContext->select($user, $companyId);
            $this->platformAdministration->recordCompanyContextSelected($user->id, (int) $company['id']);
            $this->flash('success', 'Now administering ' . (string) $company['name'] . '.');
            $this->redirect('/company');
        }, '/company');
    }

    /** @return list<array<string,mixed>> */
    private function allowedSections(\CattoLearning\Auth\CurrentUser $user): array
    {
        $map = [
            'dashboard'=>'COMPANY.DASHBOARD.VIEW','people'=>'COMPANY.PERSON.VIEW','requests'=>'COMPANY.REQUEST.VIEW',
            'enrolments'=>'COMPANY.ENROLMENT.VIEW','credits'=>'COMPANY.CREDIT.VIEW','courses'=>'COMPANY.COURSE.VIEW',
        ];
        return array_values(array_filter(
            $this->sections->all(),
            static fn(array $section): bool => $user->hasPermission($map[(string) $section['key']] ?? 'COMPANY.DASHBOARD.VIEW')
        ));
    }

