declare(strict_types=1);

namespace CattoLearning\Http\Controller;

final class CompanyController extends BaseController
{
    public function registerForm(): void
    {
        $user = $this->requireUser();
        if ($this->app->companies->forUser($user->id) !== null) {
            $this->redirect('/company');
        }
        $this->render('company-register', [
            'title' => 'Register a company account',
            'user_email' => $user->primaryEmail,
        ]);
    }

    public function register(): void
    {
        $this->requireCsrf();
        $user = $this->requireUser();
        $this->handle(function () use ($user): void {
            $this->app->companies->register(
                $user->id,
                $user->primaryEmail,
                (string) ($_POST['name'] ?? ''),
                (string) ($_POST['domain'] ?? '')
            );
            $this->flash('success', 'The company account has been created.');
            $this->redirect('/company');
        }, '/company/register');
    }

    public function dashboard(): void
    {
        $user = $this->requireRole('company_admin');
        $company = $this->app->companies->forUser($user->id);
        if ($company === null) {
            $this->f3->error(403, 'Your account is not attached to an active company.');
            return;
        }
        $tab = (string) ($_GET['tab'] ?? 'overview');
        if (!in_array($tab, ['overview','people','requests','learning','credits'], true)) {
            $tab = 'overview';
        }
        $this->render('company-control-centre', $this->app->platformAdministration->companyControlCentre($user->id) + [
            'title' => 'Company administration',
            'page_kicker' => 'People, course requests, learning access and credits',
            'active_nav' => 'company',
            'company_tab' => $tab,
        ]);
    }

    public function createPerson(): void
    {
        $this->requireCsrf();
        $user = $this->requireRole('company_admin');
        $this->handle(function () use ($user): void {
            $this->app->platformAdministration->createCompanyPerson($user->id, $_POST);
            $this->flash('success', 'The staff account was created.');
            $this->redirect('/company?tab=people');
        }, '/company?tab=people');
    }

    public function removePerson(): void
    {
        $this->requireCsrf();
        $user = $this->requireRole('company_admin');
        $target = max(1, (int) $this->f3->get('PARAMS.id'));
        $this->handle(function () use ($user, $target): void {
            $this->app->platformAdministration->removeCompanyPerson($user->id, $target);
            $this->flash('success', 'The person was removed from the company and their account was disabled.');
            $this->redirect('/company?tab=people');
        }, '/company?tab=people');
    }

    public function decideRequest(): void
    {
        $this->requireCsrf();
        $user = $this->requireRole('company_admin');
        $company = $this->app->companies->forUser($user->id);
        if ($company === null) {
            $this->f3->error(403, 'Your account is not attached to an active company.');
            return;
        }
        $requestId = max(1, (int) $this->f3->get('PARAMS.id'));
        $approve = (string) ($_POST['decision'] ?? '') === 'approve';
        $this->handle(function () use ($user, $company, $requestId, $approve): void {
            $this->app->platformAdministration->decideRequest(
                $requestId,
                $approve,
                (string) ($_POST['note'] ?? ''),
                $user->id,
                (int) $company['id']
            );
            $this->flash('success', $approve ? 'The course request was approved.' : 'The course request was rejected.');
            $this->redirect('/company?tab=requests');
        }, '/company?tab=requests');
    }

    public function removeEnrolment(): void
    {
        $this->requireCsrf();
        $user = $this->requireRole('company_admin');
        $enrolmentId = max(1, (int) $this->f3->get('PARAMS.id'));
        $this->handle(function () use ($user, $enrolmentId): void {
            $this->app->platformAdministration->removeCompanyEnrolment(
                $user->id,
                $enrolmentId,
                (string) ($_POST['reason'] ?? 'Removed by company administrator')
            );
            $this->flash('success', 'Course access was removed. The consumed credit was not returned.');
            $this->redirect('/company?tab=learning');
        }, '/company?tab=learning');
    }

    public function restoreEnrolment(): void
    {
        $this->requireCsrf();
        $user = $this->requireRole('company_admin');
        $enrolmentId = max(1, (int) $this->f3->get('PARAMS.id'));
        $this->handle(function () use ($user, $enrolmentId): void {
            $this->app->platformAdministration->restoreCompanyEnrolment($user->id, $enrolmentId);
            $this->flash('success', 'Course access was restored.');
            $this->redirect('/company?tab=learning');
        }, '/company?tab=learning');
    }
