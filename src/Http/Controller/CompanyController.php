declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use Base;
use CattoLearning\Application\CompanySectionRegistry;
use CattoLearning\Application\PlatformAdministrationService;
use CattoLearning\Auth\AuthService;
use CattoLearning\Company\CompanyService;
use CattoLearning\View\ThemeRenderer;
use RuntimeException;

final class CompanyController extends BaseController
{
    public function __construct(
        Base $f3,
        AuthService $auth,
        ThemeRenderer $view,
        private readonly CompanyService $companies,
        private readonly PlatformAdministrationService $platformAdministration,
        private readonly CompanySectionRegistry $sections
    ) {
        parent::__construct($f3, $auth, $view);
    }

    public function registerForm(): void
    {
        $user = $this->requireUser();
        if ($this->companies->forUser($user->id) !== null) $this->redirect('/company');
        $this->render('company-register', ['title' => 'Register a company account', 'user_email' => $user->primaryEmail]);
    }

    public function register(): void
    {
        $this->requireCsrf();
        $user = $this->requireUser();
        $this->handle(function () use ($user): void {
            $this->companies->register($user->id, $user->primaryEmail, (string) ($_POST['name'] ?? ''), (string) ($_POST['domain'] ?? ''));
            $this->flash('success', 'The company account has been created.');
            $this->redirect('/company');
        }, '/company/register');
    }

    /** Renders every Company section as one presentation-neutral workspace. */
    public function index(): void
    {
        $user = $this->requirePermission('COMPANY.DASHBOARD.VIEW');
        $data = $this->workspaceData($user->id, $user->hasRole('ADMIN'));
        $data['company_sections'] = $this->allowedSections($user->permissions);
        $data['company_layout'] = 'workspace';
        $this->render('company-control-centre', $data + [
            'title' => 'Company', 'page_kicker' => 'People, requests, learning, credits and courses', 'active_nav' => 'company',
        ]);
    }

    public function dashboard(): void { $this->standalone('dashboard', 'COMPANY.DASHBOARD.VIEW'); }
    public function people(): void { $this->standalone('people', 'COMPANY.PEOPLE.VIEW'); }
    public function requests(): void { $this->standalone('requests', 'COMPANY.REQUESTS.VIEW'); }
    public function learning(): void { $this->standalone('learning', 'COMPANY.LEARNING.VIEW'); }
    public function credits(): void { $this->standalone('credits', 'COMPANY.CREDITS.VIEW'); }
    public function courses(): void { $this->standalone('courses', 'COMPANY.COURSES.VIEW'); }

    public function createPerson(): void
    {
        $this->requireCsrf();
        $user = $this->requirePermission('COMPANY.PEOPLE.MANAGE');
        $this->handle(function () use ($user): void {
            if ($user->hasRole('ADMIN') && $this->companies->forUser($user->id) === null) {
                throw new RuntimeException('Use Administration → People when creating a person outside a specific company context.');
            }
            $this->platformAdministration->createCompanyPerson($user->id, $_POST);
            $this->flash('success', 'The staff account was created.');
            $this->redirect('/company/people');
        }, '/company/people');
    }

    public function removePerson(): void
    {
        $this->requireCsrf();
        $user = $this->requirePermission('COMPANY.PEOPLE.MANAGE');
        $target = max(1, (int) $this->f3->get('PARAMS.id'));
        $this->handle(function () use ($user, $target): void {
            $this->platformAdministration->removeCompanyPerson($user->id, $target);
            $this->flash('success', 'The person was removed from the company and their account was disabled.');
            $this->redirect('/company/people');
        }, '/company/people');
    }

    public function decideRequest(): void
    {
        $this->requireCsrf();
        $user = $this->requirePermission('COMPANY.REQUESTS.MANAGE');
        $company = $this->companies->forUser($user->id);
        if ($company === null && !$user->hasRole('ADMIN')) {
            $this->f3->error(403, 'Your account is not attached to an active company.');
            return;
        }
        $requestId = max(1, (int) $this->f3->get('PARAMS.id'));
        $approve = (string) ($_POST['decision'] ?? '') === 'approve';
        $this->handle(function () use ($user, $company, $requestId, $approve): void {
            $this->platformAdministration->decideRequest($requestId, $approve, (string) ($_POST['note'] ?? ''), $user->id, $user->hasRole('ADMIN') ? null : (int) $company['id']);
            $this->flash('success', $approve ? 'The course request was approved.' : 'The course request was rejected.');
            $this->redirect('/company/requests');
        }, '/company/requests');
    }

    public function removeEnrolment(): void
    {
        $this->requireCsrf();
        $user = $this->requirePermission('COMPANY.LEARNING.MANAGE');
        $id = max(1, (int) $this->f3->get('PARAMS.id'));
        $this->handle(function () use ($user, $id): void {
            if ($user->hasRole('ADMIN')) $this->platformAdministration->removeEnrolment($id, $user->id, (string) ($_POST['reason'] ?? 'Removed by administrator'));
            else $this->platformAdministration->removeCompanyEnrolment($user->id, $id, (string) ($_POST['reason'] ?? 'Removed by company administrator'));
            $this->flash('success', 'Course access was removed.');
            $this->redirect('/company/learning');
        }, '/company/learning');
    }

    public function restoreEnrolment(): void
    {
        $this->requireCsrf();
        $user = $this->requirePermission('COMPANY.LEARNING.MANAGE');
        $id = max(1, (int) $this->f3->get('PARAMS.id'));
        $this->handle(function () use ($user, $id): void {
            if ($user->hasRole('ADMIN')) $this->platformAdministration->restoreEnrolment($id, $user->id);
            else $this->platformAdministration->restoreCompanyEnrolment($user->id, $id);
            $this->flash('success', 'Course access was restored.');
            $this->redirect('/company/learning');
        }, '/company/learning');
    }

    private function standalone(string $key, string $permission): void
    {
        $user = $this->requirePermission($permission);
        $definition = $this->sections->get($key);
        $data = $this->workspaceData($user->id, $user->hasRole('ADMIN'));
        $data['company_section'] = $definition;
        $data['company_layout'] = 'section';
        $this->render('company-section', $data + [
            'title' => $definition['label'] . ' · Company', 'page_title' => $definition['label'], 'page_kicker' => 'Company', 'active_nav' => 'company',
        ]);
    }

    /** @return array<string,mixed> */
    private function workspaceData(int $userId, bool $platformWide): array
    {
        return $this->platformAdministration->companyControlCentre($userId, $platformWide);
    }

    /**
     * @param list<string> $permissions
     * @return list<array<string,mixed>>
     */
    private function allowedSections(array $permissions): array
    {
        $map = [
            'dashboard'=>'COMPANY.DASHBOARD.VIEW','people'=>'COMPANY.PEOPLE.VIEW','requests'=>'COMPANY.REQUESTS.VIEW',
            'learning'=>'COMPANY.LEARNING.VIEW','credits'=>'COMPANY.CREDITS.VIEW','courses'=>'COMPANY.COURSES.VIEW',
        ];
        return array_values(array_filter($this->sections->all(), fn(array $s): bool => in_array('ADMIN', $this->requireUser()->roles, true) || in_array($map[$s['key']], $permissions, true)));
    }
}
