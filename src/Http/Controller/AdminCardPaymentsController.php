declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Commerce\Settings\CardPaymentSettings;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;
use Throwable;

final class AdminCardPaymentsController extends BaseController
{
    public const PAGE = '/admin/settings?section=card-payments#settings-card-payments';

    public function __construct(AuthService $auth, ThemeRenderer $view, RequestStack $requests, private readonly CardPaymentSettings $cards)
    {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/admin/settings/card-payments', name: 'admin_save_card_payments', methods: ['POST'])]
    public function save(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');

        return $this->answer(function () use ($user): array {
            $problem = $this->cards->save(['client_id' => $this->posted('client_id'), 'client_secret' => $this->posted('client_secret'), 'webhook_secret' => $this->posted('webhook_secret')], $user->id);

            return $problem === null
                ? ['success', 'Saved. Stitch accepts the client ID and secret.']
                : ['warning', 'Saved, but Stitch did not accept them: ' . $problem];
        });
    }

    #[Route('/admin/settings/card-payments/check', name: 'admin_check_card_payments', methods: ['POST'])]
    public function check(): Response
    {
        $this->requireCsrf();
        $this->requirePermission('SYSTEM.SETTING.MANAGE');

        return $this->answer(function (): array {
            $problem = $this->cards->check();

            return $problem === null ? ['success', 'Stitch accepts the client ID and secret.'] : ['danger', 'Stitch did not accept them: ' . $problem];
        });
    }

    #[Route('/admin/settings/card-payments/return-address', name: 'admin_card_payments_return_address', methods: ['POST'])]
    public function returnAddress(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');

        return $this->answer(function () use ($user): array {
            $this->cards->registerReturnAddress($user->id);

            return ['success', 'Stitch now sends buyers back to this site after they pay.'];
        });
    }

    #[Route('/admin/settings/card-payments/webhook', name: 'admin_card_payments_webhook', methods: ['POST'])]
    public function webhook(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');

        return $this->answer(function () use ($user): array {
            $this->cards->registerWebhook($user->id);

            return ['success', 'Stitch now tells this site the moment a payment is made, and its signing secret is saved here.'];
        });
    }

    #[Route('/admin/settings/card-payments/reset', name: 'admin_reset_card_payments', methods: ['POST'])]
    public function reset(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');

        return $this->answer(function () use ($user): array {
            $this->cards->reset($user->id);

            return ['success', 'The keys saved here were removed: card payments use what .env says.'];
        });
    }

    /** @param callable():array{0:string,1:string} $action */
    private function answer(callable $action): Response
    {
        try {
            [$tone, $words] = $action();
        } catch (Throwable $refused) {
            [$tone, $words] = ['danger', $refused->getMessage()];
        }
        $_SESSION['card_payments_note'] = ['tone' => $tone, 'words' => $words];
        $this->redirect(self::PAGE);
    }
}
