    #[Route('/m/u/{token}', name: 'mailing_unsubscribe', requirements: ['token' => '[0-9a-f]{32}'], methods: ['GET', 'POST'])]
    public function stop(): Response
    {
        $delivery = $this->campaigns->deliveryByToken((string) $this->param('token'));
        $request = $this->request();
        if ($request->isMethod('POST')) {
            // The email app's one-click button (RFC 8058): the list stops at once and nothing is shown.
            if ($request->request->get('List-Unsubscribe') === 'One-Click') {
                if ($delivery !== null) $this->outcomes->unsubscribe($delivery, false, 'one_click');

                return new Response('', 200, ['Content-Type' => 'text/plain; charset=utf-8']);
            }
            if ($delivery === null) throw $this->notFound('This unsubscribe link is not known. What you get is under Account, My Subscriptions.');
            $everything = $request->request->get('what') === 'all';
            $this->outcomes->unsubscribe($delivery, $everything, 'unsubscribe_link');

            return $this->render('mailing-unsubscribe', ['title' => 'Unsubscribed', 'stopped' => true, 'everything' => $everything, 'list_name' => self::listName($delivery), 'token' => (string) $delivery['token']]);
        }
        if ($delivery === null) throw $this->notFound('This unsubscribe link is not known. What you get is under Account, My Subscriptions.');
        // Already stopped (the email app's button, or this page before): it says so rather than asking again.
        if ($delivery['unsubscribed_at'] !== null && ($delivery['list_id'] === null || $delivery['user_id'] === null || !$this->consents->isSubscribedToList((int) $delivery['user_id'], (int) $delivery['list_id']))) {
            return $this->render('mailing-unsubscribe', ['title' => 'Unsubscribed', 'stopped' => true, 'everything' => $delivery['list_id'] === null, 'list_name' => self::listName($delivery), 'token' => (string) $delivery['token']]);
        }

        return $this->render('mailing-unsubscribe', ['title' => 'Unsubscribe', 'stopped' => false, 'everything' => false, 'list_name' => self::listName($delivery), 'token' => (string) $delivery['token']]);
    }

    #[Route('/m/k/{token}', name: 'mailing_keep', requirements: ['token' => '[0-9a-f]{32}'], methods: ['GET', 'POST'])]
    public function keep(): Response
    {
        $delivery = $this->campaigns->deliveryByToken((string) $this->param('token'));
        if ($delivery === null || $delivery['campaign_kind'] !== 'sleeping') throw $this->notFound('This link is not known. What you get is under Account, My Subscriptions.');
        $kept = false;
        if ($this->request()->isMethod('POST')) {
            $this->sleeping->keep($delivery);
            $kept = true;
        }

        return $this->render('mailing-keep', ['title' => $kept ? 'News kept' : 'Keep the news coming', 'kept' => $kept, 'token' => (string) $delivery['token']]);
    }

    #[Route('/m/o/{token}.gif', name: 'mailing_open', requirements: ['token' => '[0-9a-f]{32}'], methods: ['GET'])]
    public function open(): Response
    {
        $delivery = $this->campaigns->deliveryByToken((string) $this->param('token'));
        if ($delivery !== null && (bool) $this->settings->rule('track_opens')) $this->campaigns->recordOpen((int) $delivery['id']);

        return new Response((string) base64_decode(self::PIXEL, true), 200, ['Content-Type' => 'image/gif', 'Cache-Control' => 'no-store, max-age=0']);
    }

    #[Route('/m/c/{token}/{link}', name: 'mailing_click', requirements: ['token' => '[0-9a-f]{32}', 'link' => '\d+'], methods: ['GET'])]
    public function click(): Response
    {
        $delivery = $this->campaigns->deliveryByToken((string) $this->param('token'));
        $url = $delivery === null ? null : $this->campaigns->linkUrl((int) $delivery['campaign_id'], (int) $this->param('link'));
        if ($delivery === null || $url === null) throw $this->notFound('This link is not known.');
        if ((bool) $this->settings->rule('track_clicks')) $this->campaigns->recordClick((int) $delivery['id'], (int) $this->param('link'));

        return new RedirectResponse($url, 302, ['Cache-Control' => 'no-store']);
    }

    #[Route('/m/i/{asset}.{extension}', name: 'mailing_picture', requirements: ['asset' => '[0-9a-f]{64}', 'extension' => 'png|jpg|gif'], methods: ['GET'])]
    public function picture(): Response
    {
        $asset = $this->campaigns->asset((string) $this->param('asset'));
        if ($asset === null) throw $this->notFound('That picture is not known.');

        return new Response($asset['bytes'], 200, ['Content-Type' => $asset['media_type'], 'Cache-Control' => 'public, max-age=31536000, immutable']);
    }

    /** The email's web copy: the person's copy as it was sent, its links their own, nothing recorded (12A). */
    #[Route('/m/v/{token}', name: 'mailing_web_copy', requirements: ['token' => '[0-9a-f]{32}'], methods: ['GET'])]
    public function webCopy(): Response
    {
        $copy = $this->forwards->copy((string) $this->param('token'));
        if ($copy === null) throw $this->notFound('This email is not known, or has not been sent yet.');
        $page = $this->forwards->webCopy($copy);

        return new Response($page['html'], 200, ['Content-Type' => 'text/html; charset=utf-8', 'Cache-Control' => 'no-store', 'X-Robots-Tag' => 'noindex, nofollow',
            'Content-Security-Policy' => "default-src 'none'; img-src * data:; style-src 'unsafe-inline' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; frame-ancestors 'self'"]);
    }

    /** Forward to a friend (11A): the form, and sending it. */
    #[Route('/m/f/{token}', name: 'mailing_forward', requirements: ['token' => '[0-9a-f]{32}'], methods: ['GET', 'POST'])]
    public function forward(): Response
    {
        $token = (string) $this->param('token');
        $copy = $this->forwards->copy($token);
        if ($copy === null) throw $this->notFound('This email is not known, or has not been sent yet.');
        $subject = trim((string) (($copy['delivery']['content']['subject'] ?? '') ?: $copy['campaign']['subject']));
        $sent = '';
        $error = '';
        $values = ['email' => '', 'name' => '', 'note' => ''];
        // Like every /m/ address, the copy's unguessable token is what allows it: there is no sign-in to tie a form token to.
        if ($this->request()->isMethod('POST')) {
            $values = ['email' => (string) ($_POST['email'] ?? ''), 'name' => (string) ($_POST['name'] ?? ''), 'note' => (string) ($_POST['note'] ?? '')];
            try {
                $sent = $this->forwards->forward($copy, $values['email'], $values['name'], $values['note']);
                $values = ['email' => '', 'name' => '', 'note' => ''];
            } catch (\InvalidArgumentException $refused) {
                $error = $refused->getMessage();
            }
        }

        return $this->render('mailing-forward', ['title' => 'Forward to a friend', 'subject' => $subject, 'token' => $token, 'sent' => $sent, 'error' => $error, 'values' => $values,
            'per_copy' => \CattoLearning\Mailing\MailingForwards::PER_COPY]);
    }

    /** A forwarded copy's "Never email me", for the friend: the page asks, the button does it. */
    #[Route('/m/n/{token}', name: 'mailing_never', requirements: ['token' => '[0-9a-f]{32}'], methods: ['GET', 'POST'])]
    public function never(): Response
    {
        $token = (string) $this->param('token');
        $forward = $this->forwards->forwardByToken($token);
        if ($forward === null) throw $this->notFound('This link is not known.');
        $done = false;
        if ($this->request()->isMethod('POST')) {
            $this->forwards->neverEmail($token);
            $done = true;
        }

        return $this->render('mailing-never', ['title' => $done ? 'We will never email you' : 'Never email me', 'token' => $token, 'email' => $forward['to_email'], 'done' => $done]);
    }

    /** @param array<string,mixed> $delivery */
    private static function listName(array $delivery): string
    {
        // The lists that brought a digest or an update, named together: "Finance, Excel and Bookkeeping".
        $names = array_values(array_filter(array_map('strval', (array) ($delivery['content']['list_names'] ?? []))));
        if (count($names) > 1) {
            $last = array_pop($names);

            return implode(', ', $names) . ' and ' . $last;
        }
        $name = trim((string) ($delivery['list_name'] ?? ''));

        return $name !== '' ? $name : 'News and Updates';
    }
