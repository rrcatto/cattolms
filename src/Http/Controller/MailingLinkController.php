- /m/i/{sha256}.{png|jpg|gif}: a picture an email shows.
- /m/v/{token}: the email's web copy, "View it in your browser" (owner, 2026-10-28, decision 12A).
- /m/f/{token}: Forward to a friend (decision 11A): the friend's address, name and a note; sending is the button.
- /m/n/{token}: a forwarded copy's "Never email me", for the friend: opening it shows a button.

