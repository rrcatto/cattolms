declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Search\SearchEnginesAdministration;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class AdminSearchEnginesController extends BaseController
{
    private const SECTION = '/admin/settings?section=search-engines#settings-search-engines';

    public function __construct(AuthService $auth, ThemeRenderer $view, RequestStack $requests, private readonly SearchEnginesAdministration $searchEngines)
    {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/admin/settings/search-engines', name: 'admin_save_search_engines', methods: ['POST'])]
    public function save(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            $this->searchEngines->save(['ai_crawlers' => (string) ($_POST['ai_crawlers'] ?? ''), 'google' => (string) ($_POST['google'] ?? ''), 'bing' => (string) ($_POST['bing'] ?? '')], $user->id);
            $this->flash('success', 'Search engines and AI are saved. robots.txt and the home page follow at once.');
            $this->redirect(self::SECTION);
        }, self::SECTION);
    }

    #[Route('/admin/settings/search-engines/share-pictures', name: 'admin_make_share_pictures', methods: ['POST'])]
    public function makeSharePictures(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            $done = $this->searchEngines->makeMissing($user->id);
            if (!$done['tool']) {
                $this->flash('danger', 'No share picture was made: this server cannot draw pictures yet. Install rsvg-convert, as this section says, then try again.');
            } elseif ($done['failed'] > 0) {
                $this->flash('warning', ($done['made'] === 1 ? '1 share picture was made' : $done['made'] . ' share pictures were made') . ', and ' . ($done['failed'] === 1 ? '1 cover could not be drawn' : $done['failed'] . ' covers could not be drawn') . '. Upload a fresh SVG cover for it and its picture is made as it saves.');
            } else {
                $this->flash('success', $done['made'] === 0 ? 'Every share picture was made already.' : ($done['made'] === 1 ? '1 share picture was made.' : $done['made'] . ' share pictures were made.'));
            }
            $this->redirect(self::SECTION);
        }, self::SECTION);
    }
}
