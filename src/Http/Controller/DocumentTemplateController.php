    /**
     * @param array<string,string> $input
     * @param list<string> $errors
     */
    private function keep(int $id, array $input, array $errors): Response
    {
        $_SESSION[self::SESSION][(string) $id] = ['input' => $input, 'errors' => $errors];
        $this->flash('danger', 'Nothing was saved: the template has ' . (count($errors) === 1 ? 'a problem' : count($errors) . ' problems') . ', listed above the editor.');
        $this->redirect(self::BASE . '/' . $id . '#template-errors');
    }

    /**
     * @param array<string,mixed> $post
     * @return array<string,string>
     */
    private static function input(array $post): array
    {
        $input = [];
        foreach (self::FIELDS as $field) {
            $input[$field] = is_scalar($post[$field] ?? null) ? (string) $post[$field] : '';
        }
        return $input;
    }

    /** @return array{0:array<string,mixed>,1:array<string,mixed>} */
    private function versionOf(int $templateId, int $versionId): array
    {
        $template = $this->templates->template($templateId) ?? throw $this->notFound('That document template does not exist.');
        $version = $this->templates->version($versionId);
        if ($version === null || (int) $version['template_id'] !== $templateId) {
            throw $this->notFound('That version does not belong to this template.');
        }
        return [$template, $version];
    }

    /**
     * @param array<string,string> $options
     * @param array<string,string> $carried
     * @return list<array{label:string,href:string,active:bool}>
     */
    private static function chips(array $options, string $param, string $selected, array $carried): array
    {
        $chips = [];
        foreach ($options as $value => $label) {
            $query = $carried + ($value === '' ? [] : [$param => $value]);
            $chips[] = ['label' => $label, 'href' => self::BASE . ($query === [] ? '' : '?' . http_build_query($query)), 'active' => $selected === $value];
        }
        return $chips;
    }
