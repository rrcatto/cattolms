    /** The editor's one form: save the draft, preview it, or save and publish it. */
    #[Route('/admin/documents/templates/{id}', name: 'admin_document_template_update', requirements: ['id' => '\d+'], methods: ['POST'])]
    public function update(): Response
    {
        $this->requireCsrf();
        $actor = $this->requirePermission('DOCUMENT.TEMPLATE.MANAGE');
        $id = (int) $this->param('id');
        $input = self::input($_POST);
        $intent = (string) ($_POST['intent'] ?? 'save');

        if ($intent === 'preview') {
            // Rendered, not saved: the page is answered directly with the submitted content kept.
            try {
                return $this->editor($id, $input, [], $this->documents->preview($id, $input));
            } catch (TemplateValidationException $invalid) {
                return $this->editor($id, $input, $invalid->errors, null);
            } catch (RuntimeException $failed) {
                return $this->editor($id, $input, [$failed->getMessage()], null);
            }
        }
        try {
            if ($intent === 'publish') {
                $published = $this->documents->saveAndPublish($actor, $id, $input);
                $this->flash('success', 'Version ' . $published['version_number'] . ' is published and is now the current template. Documents generated from now on use it; documents already generated keep the version they were made with.');
            } else {
                $this->documents->saveDraft($actor, $id, $input);
                $this->flash('success', 'The draft was saved. The preview below shows the saved draft.');
            }
        } catch (TemplateValidationException $invalid) {
            return $this->keep($id, $input, $invalid->errors);
        } catch (RuntimeException $failed) {
            return $this->keep($id, $input, [$failed->getMessage()]);
        }
        $this->redirect(self::BASE . '/' . $id . '#template-preview');
    }

