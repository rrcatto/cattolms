    /**
     * @param array<string,string>|null $input submitted content to show instead of the stored content
     * @param list<string> $errors
     */
    private function editor(int $id, ?array $input, array $errors, ?RenderedDocument $preview): Response
    {
        $actor = $this->currentUser();
        $template = $this->templates->template($id) ?? throw $this->notFound('That document template does not exist.');
        $type = DocumentType::from((string) $template['document_type']);
        $draft = $this->templates->draft($id);
        $published = $template['published_version_id'] === null ? null : $this->templates->version((int) $template['published_version_id']);
        $source = $draft ?? $published;
        $form = $input ?? ($source === null ? [] : array_intersect_key($source, array_flip(self::FIELDS)));
        $form += ['html' => '', 'css' => '', 'change_note' => ''] + $type->defaultSettings()->toArray();
        if ($input === null && $draft === null) {
            // Editing the published version starts a new draft: its note is the new draft's own.
            $form['change_note'] = '';
        }
        $previewError = null;
        if ($preview === null && $input === null && $source !== null) {
            try {
                $preview = $this->documents->previewVersion((int) $source['id']);
            } catch (RuntimeException $failed) {
                $previewError = $failed->getMessage();
            }
        }
        $versions = [];
        foreach ($this->templates->versions($id) as $version) {
            $versions[] = $version + ['is_published_version' => (int) $version['id'] === (int) ($template['published_version_id'] ?? 0)];
        }
        $set = $this->registry->forType($type);
        $placeholders = [];
        foreach ($set->scalars as $definition) {
            $placeholders[] = ['token' => '{{ ' . $definition->name . ' }}', 'name' => $definition->name, 'kind' => $definition->kind->label(), 'required' => $definition->required, 'description' => $definition->description];
        }
        $collections = [];
        foreach ($set->collections as $collection) {
            $fields = [];
            foreach ($collection->fields as $definition) {
                $fields[] = ['token' => '{{ ' . $definition->name . ' }}', 'name' => $definition->name, 'kind' => $definition->kind->label(), 'required' => $definition->required, 'description' => $definition->description];
            }
            $collections[] = ['name' => $collection->name, 'description' => $collection->description, 'open' => '{{#each ' . $collection->name . '}}', 'close' => '{{/each}}', 'fields' => $fields];
        }
        return $this->render('admin-document-template', [
            'title' => (string) $template['name'],
            'template' => $template + ['type_label' => $type->label()],
            'form' => $form,
            'errors' => $errors,
            'editing_draft' => $draft !== null,
            'draft' => $draft,
            'published' => $published,
            'preview' => $preview === null ? null : self::preview($preview),
            'preview_unsaved' => $preview !== null && $input !== null,
            'preview_error' => $previewError,
            'versions' => $versions,
            'placeholders' => $placeholders,
            'collections' => $collections,
            'sizes' => array_combine(array_keys(PageSettings::SIZES), array_keys(PageSettings::SIZES)),
            'orientations' => PageSettings::ORIENTATIONS,
            'max_margin' => PageSettings::MAX_MARGIN_MM,
            'can_manage' => $actor !== null && $actor->hasPermission('DOCUMENT.TEMPLATE.MANAGE') && $template['status'] === 'active',
            'can_archive' => $actor !== null && $actor->hasPermission('DOCUMENT.TEMPLATE.MANAGE'),
        ]);
    }

    /** @return array{html:string,width:int,height:int,label:string,version_number:?int} */
    private static function preview(RenderedDocument $document): array
    {
        return [
            'html' => $document->html,
            'width' => $document->settings->widthPx(),
