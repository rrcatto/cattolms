    #[Route('/account/verification', name: 'identity_verification', methods: ['GET'])]
    public function show(): Response
    {
        $user = $this->requirePermission('ACCOUNT.PROFILE.VIEW');
        // Start sends the learner on to Didit's page, an address Didit gives only then.
        $this->policy->allow('form-action', 'https:');
        return $this->render('identity-verification', [
            'title' => 'Identity verification',
            'active_nav' => 'account',
            'identity' => $this->identity->state($user->id),
            'tries' => IdentityVerificationService::TRIES,
            'return_path' => $this->safeReturn((string) $this->request()->query->get('return', '')),
        ]);
    }

    #[Route('/account/verification/start', name: 'identity_verification_start', methods: ['POST'])]
    public function start(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('ACCOUNT.PROFILE.VIEW');
        $return = $this->safeReturn($this->posted('return_path'));
        return $this->handle(function () use ($user, $return): Response {
            $url = $this->identity->start($user);
            $_SESSION['identity_return'] = $return;
            return new RedirectResponse($url, 303);
        }, '/account/verification' . ($return !== '' ? '?return=' . rawurlencode($return) : ''));
    }

    #[Route('/account/verification/return', name: 'identity_verification_return', methods: ['GET'])]
    public function returned(): Response
    {
        $user = $this->requirePermission('ACCOUNT.PROFILE.VIEW');
        $return = $this->safeReturn((string) ($_SESSION['identity_return'] ?? ''));
        $sessionId = (string) $this->request()->query->get('verificationSessionId', '');
        return $this->handle(function () use ($user, $sessionId, $return): void {
            $state = $this->identity->returned($user, $sessionId);
            if ($state['verified']) {
                $this->flash('success', 'Your identity is verified. Thank you.');
            } elseif ($state['in_review']) {
                $this->flash('info', 'Your identity check is being reviewed. We will let you know the result.');
            } elseif (($state['latest']['status'] ?? '') === 'declined') {
                $this->flash('warning', 'Your identity check was declined. ' . (string) ($state['latest']['decline_reason'] ?? ''));
            } else {
                $this->flash('info', 'Your identity check is not finished yet. You can carry on with it from this page.');
            }
            unset($_SESSION['identity_return']);
            $this->redirect($state['verified'] && $return !== '' ? $return : '/account/verification' . ($return !== '' ? '?return=' . rawurlencode($return) : ''));
        }, '/account/verification');
    }

    /** Didit's webhook: answered at once, 401 when it is not signed by Didit. */
    #[Route('/webhooks/didit', name: 'identity_didit_webhook', methods: ['POST'])]
    public function webhook(): Response
    {
        $request = $this->request();
        $headers = [];
        // The -Previous signatures come for 24 hours after the secret is rotated in Didit (2026-11-06): they were checked
        // but never passed on here until 2026-11-12.
        foreach (['x-signature-v2', 'x-signature', 'x-timestamp', 'x-signature-v2-previous', 'x-signature-previous'] as $name) {
            $headers[$name] = (string) $request->headers->get($name, '');
        }
        try {
            $this->identity->webhook((string) $request->getContent(), $headers);
        } catch (InvalidDiditWebhook $refused) {
            return new JsonResponse(['error' => $refused->getMessage()], 401);
        } catch (Throwable) {
            // Didit retries on a 5xx; a failure here is worth one more delivery.
            return new JsonResponse(['error' => 'The webhook could not be handled.'], 500);
        }
        return new JsonResponse(['ok' => true]);
    }

    #[Route('/admin/people/{reference}/identity/{verification}/revoke', name: 'admin_identity_revoke', requirements: ['reference' => PersonAddress::REQUIREMENT, 'verification' => '\d+'], methods: ['POST'])]
    public function revoke(): Response
    {
        $this->requireCsrf();
        $actor = $this->requirePermission('PLATFORM.IDENTITY.MANAGE');
        // The person by their account reference (owner, 2026-11-06); the check keeps its number, which permissions protect.
        $this->personIdFromAddress($this->keys);
        $person = PersonAddress::admin($this->param('reference'), '#identity');
        return $this->handle(function () use ($actor, $person): void {
            $this->identity->revoke((int) $this->param('verification'), $actor->id, $this->posted('reason'));
            $this->flash('success', 'The verification was revoked. The person must verify again before a purchase or a certificate.');
            $this->redirect($person);
        }, $person);
    }

    #[Route('/admin/people/{reference}/identity/allow-retry', name: 'admin_identity_allow_retry', requirements: ['reference' => PersonAddress::REQUIREMENT], methods: ['POST'])]
    public function allowRetry(): Response
    {
        $this->requireCsrf();
        $actor = $this->requirePermission('PLATFORM.IDENTITY.MANAGE');
        $userId = $this->personIdFromAddress($this->keys);
        $person = PersonAddress::admin($this->param('reference'), '#identity');
        return $this->handle(function () use ($actor, $userId, $person): void {
            $this->identity->allowAnotherTry($userId, $actor->id);
            $this->flash('success', 'The person may try again: ' . IdentityVerificationService::TRIES . ' more checks.');
            $this->redirect($person);
        }, $person);
    }

    /** A local path to come back to, or nothing. */
    private function safeReturn(string $path): string
    {
        return str_starts_with($path, '/') && !str_starts_with($path, '//') && strlen($path) <= 300 ? $path : '';
    }
}
