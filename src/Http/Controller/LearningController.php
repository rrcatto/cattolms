    #[Route('/account/courses/enrolments/{id}/remove', name: 'learning_remove_own_access', requirements: ['id' => '\\d+'], methods: ['POST'])]
    public function removeOwnAccess(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.ENROLMENT.MANAGE');
        $enrolmentId = max(1, (int) $this->param('id'));
        $enrolment = $this->learning->enrolmentForUser($enrolmentId, $user->id);
        if ($enrolment === null) {
            throw new NotFoundHttpException('The course enrolment was not found.');
        }
        $this->platformAdministration->removeEnrolment($enrolmentId, $user->id, 'Removed from the platform administrator’s own test library.');
        $this->flash('success', 'The course was removed from your library. The consumed credit was not returned.');
        $this->redirect('/account/courses');
    }


    #[Route('/learn/{slug}', name: 'learning_course', requirements: ['slug' => '[a-zA-Z0-9_-]+'], methods: ['GET'])]
    public function course(): Response
    {
        $user = $this->requirePermission('LEARNING.COURSE.VIEW');
        $slug = (string) $this->param('slug');
        $preview = $this->previewMode();
        return $this->handle(function () use ($user, $slug, $preview): Response {
            $course = $this->learning->courseHome($user->id, $slug, $preview);
            // An ADMIN preview is authoring, not reading: it is never a course view.
            if (!$preview) { $this->analytics->courseViewed((int) $course['id'], AnalyticsSource::LearnerReader, $user->id, $this->analyticsVisitor(), 'course_home'); }
            return $this->render('learn-course', [
                'title' => (string) $course['title'],
                'course' => $course,
                'is_preview' => $preview,
                'preview_query' => $preview ? '?preview=1' : '',
                'course_content_mode' => true,
            ]);
        }, '/account/courses');
    }


    #[Route('/learn/{slug}/start', name: 'learning_start', requirements: ['slug' => '[a-zA-Z0-9_-]+'], methods: ['POST'])]
    public function start(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('LEARNING.COURSE.START');
        $slug = (string) $this->param('slug');
        $preview = $this->previewMode();
        return $this->handle(function () use ($user, $slug, $preview): void {
            // Starting begins the access period and ends any refund (owner, 2026-10-17): the learner ticks that first.
            if (!$preview && $this->posted('confirm_start') !== 'yes') throw new \RuntimeException('Tick the box to confirm that starting begins your access period and that a started course can no longer be refunded.');
            $this->learning->start($user->id, $slug, $preview);
            $this->flash('success', 'The course has started. Your access period begins now.');
            $this->redirect('/learn/' . rawurlencode($slug) . ($preview ? '?preview=1' : ''));
        }, '/learn/' . rawurlencode($slug));
    }


    #[Route('/learn/{slug}/item/{node_id}/content', name: 'learning_course_content', requirements: ['slug' => '[a-zA-Z0-9_-]+', 'node_id' => '\\d+'], methods: ['GET'])]
    public function item(): Response
    {
        $user = $this->requirePermission('LEARNING.COURSE.VIEW');
        $slug = (string) $this->param('slug');
        $nodeId = (int) $this->param('node_id');
        $preview = $this->previewMode();
        return $this->handle(function () use ($user, $slug, $nodeId, $preview): Response {
            $course = $this->learning->item($user->id, $slug, $nodeId, $preview);
            if (in_array((string) ($course['item']['item_type'] ?? ''), ['assessment', 'diagnostic'], true)) {
                throw $this->notFound('Assessments open from their direct assessment route.');
            }
            if (!$preview) {
                $itemId = (int) ($course['item']['course_item_id'] ?? 0);
                $this->analytics->courseViewed((int) $course['id'], AnalyticsSource::LearnerReader, $user->id, $this->analyticsVisitor(), 'item', $nodeId, $itemId > 0 ? $itemId : null);
            }
            return $this->render('learn-item', [
                'title' => (string) ($course['item']['display_title_override'] ?: $course['item']['item_title']),
                'course' => $course,
                'item' => $course['item'],
                'course_content_mode' => true,
                'is_preview' => $preview,
                'preview_query' => $preview ? '?preview=1' : '',
            ]);
        }, '/learn/' . rawurlencode($slug));
    }

