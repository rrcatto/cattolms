namespace CattoLearning\Http\Controller;

final class LearningController extends BaseController
{
    public function library(): void
    {
        $user = $this->requireUser();
        $courses = $this->app->learning->library($user->id);
        $this->render('library', [
            'title' => 'My Learning',
            'page_kicker' => 'Current, completed and requested courses',
            'courses' => $courses,
            'current_courses' => array_values(array_filter($courses, static fn(array $course): bool => in_array((string) ($course['status'] ?? ''), ['assigned','active'], true))),
            'completed_courses' => array_values(array_filter($courses, static fn(array $course): bool => (string) ($course['status'] ?? '') === 'completed')),
            'favourites' => $this->app->platformAdministration->favourites($user->id),
            'requests' => $this->app->platformAdministration->userRequests($user->id),
            'active_learning_tab' => trim((string) ($_GET['tab'] ?? 'current')),
        ]);
    }

    public function removeOwnAccess(): void
    {
        $this->requireCsrf();
        $user = $this->requireRole('platform_admin');
        $enrolmentId = max(1, (int) $this->f3->get('PARAMS.id'));
        $enrolment = $this->app->courseRepository->enrolmentByIdForUser($enrolmentId, $user->id);
        if ($enrolment === null) {
            $this->f3->error(404, 'The course enrolment was not found.');
            return;
        }
        $this->app->platformAdministration->removeEnrolment($enrolmentId, $user->id, 'Removed from the platform administrator’s own test library.');
        $this->flash('success', 'The course was removed from your library. The consumed credit was not returned.');
        $this->redirect('/account/library');
    }

    public function course(): void
    {
        $user = $this->requireUser();
        $slug = (string) $this->f3->get('PARAMS.slug');
        $preview = $this->previewMode();
        $this->handle(function () use ($user, $slug, $preview): void {
            $course = $this->app->learning->courseHome($user->id, $slug, $preview);
            $this->render('learn-course', [
                'title' => (string) $course['title'],
                'course' => $course,
                'is_preview' => $preview,
                'preview_query' => $preview ? '?preview=1' : '',
                'course_content_mode' => true,
            ]);
        }, '/account/library');
    }

    public function start(): void
    {
        $this->requireCsrf();
        $user = $this->requireUser();
        $slug = (string) $this->f3->get('PARAMS.slug');
        $preview = $this->previewMode();
        $this->handle(function () use ($user, $slug, $preview): void {
            $this->app->learning->start($user->id, $slug, $preview);
            $this->flash('success', 'The course has started. Your access period begins now.');
            $this->redirect('/learn/' . rawurlencode($slug) . ($preview ? '?preview=1' : ''));
        }, '/learn/' . rawurlencode($slug));
    }

    public function module(): void
    {
        $user = $this->requireUser();
        $slug = (string) $this->f3->get('PARAMS.slug');
        $position = (int) $this->f3->get('PARAMS.position');
        $preview = $this->previewMode();
        $this->handle(function () use ($user, $slug, $position, $preview): void {
            $course = $this->app->learning->module($user->id, $slug, $position, $preview);
            $this->render('learn-module', [
                'title' => (string) $course['module']['title'],
                'course' => $course,
                'module' => $course['module'],
                'course_content_mode' => true,
                'is_preview' => $preview,
                'preview_query' => $preview ? '?preview=1' : '',
            ]);
        }, '/learn/' . rawurlencode($slug));
    }

    private function previewMode(): bool
    {
        $preview = (string) ($_GET['preview'] ?? '') === '1';
        if ($preview) {
            $this->requireCourseAuthor();
        }
        return $preview;
    }
