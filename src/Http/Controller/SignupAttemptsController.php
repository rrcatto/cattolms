    #[Route('/admin/people/signup-attempts', name: 'admin_signup_attempts', methods: ['GET'])]
    public function index(): Response
    {
        $this->requirePermission('PLATFORM.PERSON.VIEW');
        $query = $this->request()->query;
        $band = (string) $query->get('band', '');
        if (!in_array($band, ['low', 'medium', 'high'], true)) $band = '';
        $outcome = (string) $query->get('outcome', '');
        if (!isset(self::OUTCOMES[$outcome])) $outcome = '';
        $search = mb_substr(trim((string) $query->get('q', '')), 0, 120);
        $sort = SortOrder::create($query->get('attempts_sort'), $query->get('attempts_dir'), array_keys(SignupAttemptRepository::SORTS), 'created', SortOrder::DESCENDING);
        $pagination = Pagination::create($query->get('attempts_page'), $query->get('attempts_page_size'), $this->attempts->count($search, $band, $outcome), 25);
        $filters = ['band' => $band, 'outcome' => $outcome, 'q' => $search];
        $sorted = $filters + $sort->toPrefixedArray('attempts');

        return $this->render('admin-signup-attempts', [
            'title' => 'Sign-up Attempts',
            'active_nav' => 'admin',
            'rows' => array_map([self::class, 'row'], $this->attempts->page($search, $band, $outcome, $sort, $pagination->pageSize, $pagination->offset)),
            'filters' => $filters,
            'filtered' => $band !== '' || $outcome !== '' || $search !== '',
            'outcomes' => self::OUTCOMES,
            'month' => $this->attempts->lastMonth(),
            'sort_headers' => self::headers($sort, $filters),
            'attempts_pagination' => PlatformAdministrationService::paginationPayload('attempts', $pagination, self::BASE, 'attempts', $sorted),
        ]);
    }

    #[Route('/admin/people/signup-attempts/{id}', name: 'admin_signup_attempt', requirements: ['id' => '[0-9]+'], methods: ['GET'])]
    public function show(): Response
    {
        $this->requirePermission('PLATFORM.PERSON.VIEW');
        $attempt = $this->attempts->find((int) $this->request()->attributes->get('id'));
        if ($attempt === null) throw $this->notFound('That sign-up attempt could not be found.');
        $row = self::row($attempt);
        $row['place'] = $attempt['ip_address'] !== '' ? $this->network->place((string) $attempt['ip_address']) : 'No IP address';
        $row['hold_words'] = array_map([SignupRisk::class, 'holdWords'], (array) $attempt['hold_reasons']);

        return $this->render('admin-signup-attempt', [
            'title' => 'Sign-up attempt by ' . $attempt['email'],
            'active_nav' => 'admin',
            'attempt' => $row,
        ]);
    }

    /**
     * An attempt as the pages show it.
     *
     * @param array<string,mixed> $attempt
     * @return array<string,mixed>
     */
    public static function row(array $attempt): array
    {
        $country = (string) $attempt['country_code'];
        $outcome = (string) $attempt['outcome'];
        $held = $attempt['held'] ?? null;

        return $attempt + [
            'href' => self::BASE . '/' . (int) $attempt['id'],
            'name' => trim($attempt['first_name'] . ' ' . $attempt['last_name']),
            'country' => $country === '' ? 'Unknown' : trim(GeoIpLocator::flagForCountryCode($country) . ' ' . SignupCountries::name($country)),
            // The country they say they live in (owner, 2026-10-27), which may differ from where they were.
            'home_country' => (string) ($attempt['home_country'] ?? '') === '' ? 'Not asked' : \CattoLearning\Support\Countries::name((string) $attempt['home_country']),
            'risk_label' => RiskAssessment::label((string) $attempt['band']),
            'risk_tone' => RiskAssessment::tone((string) $attempt['band']),
            'outcome_label' => $outcome === 'completed' ? (($held === true || $held === 't') ? 'Registered, held' : 'Registered') : (self::OUTCOMES[$outcome] ?? $outcome),
            'account' => $attempt['user_id'] !== null ? ['name' => (string) ($attempt['user_name'] ?: $attempt['email']), 'href' => '/admin/people/' . (int) $attempt['user_id']] : null,
        ];
    }

    /**
     * The list's column headings, sortable where the list sorts.
     *
     * @param array<string,string> $filters
     * @return list<array<string,mixed>>
     */
    private static function headers(SortOrder $sort, array $filters): array
    {
        $columns = [['created', 'When', 12], ['email', 'Email address', 22], ['', 'Name', 13], ['country', 'Country', 13], ['', 'Network', 13], ['risk', 'Risk', 10], ['outcome', 'Outcome', 11], ['', '', 6]];
        $headers = [];
        foreach ($columns as [$key, $label, $width]) {
            if ($key === '') { $headers[] = ['sortable' => false, 'label' => $label, 'width' => $width]; continue; }
            $direction = $sort->nextDirectionFor($key, in_array($key, ['created', 'risk'], true) ? SortOrder::DESCENDING : SortOrder::ASCENDING);
            $headers[] = ['sortable' => true, 'key' => $key, 'label' => $label, 'width' => $width, 'active' => $sort->isOn($key), 'direction' => $sort->direction,
                'href' => self::BASE . '?' . http_build_query(array_filter($filters + ['attempts_sort' => $key, 'attempts_dir' => $direction], static fn(string $value): bool => $value !== ''))];
        }

        return $headers;
    }
