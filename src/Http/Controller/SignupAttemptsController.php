final class SignupAttemptsController extends BaseController
{
    private const BASE = '/admin/people/signup-attempts';

    /** What became of an attempt, in words. */
    public const OUTCOMES = ['link_sent' => 'Link sent, not confirmed', 'refused' => 'Refused', 'trapped' => 'Caught by the hidden field', 'completed' => 'Registered'];

    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly SignupAttemptRepository $attempts,
        private readonly NetworkLookup $network
    ) {
        parent::__construct($auth, $view, $requests);
