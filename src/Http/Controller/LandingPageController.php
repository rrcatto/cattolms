declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Course\CourseService;
use CattoLearning\Course\Landing\LandingPageAnalytics;
use CattoLearning\Course\Landing\LandingPageService;
use CattoLearning\Course\Landing\LandingPageViewBuilder;
use CattoLearning\Course\Landing\LandingSectionType;
use CattoLearning\Course\ResourceLibraryService;
use CattoLearning\View\ThemeRenderer;
use InvalidArgumentException;
use Symfony\Component\HttpFoundation\BinaryFileResponse;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpFoundation\ResponseHeaderBag;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;
use Symfony\Component\Routing\Attribute\Route;

final class LandingPageController extends BaseController
{
    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly LandingPageService $landing,
        private readonly LandingPageViewBuilder $views,
        private readonly LandingPageAnalytics $analytics,
        private readonly ResourceLibraryService $resources,
        private readonly CourseService $courses,
    ) {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/landing/{slug}', name: 'landing_page', requirements: ['slug' => '[a-z0-9]+(?:-[a-z0-9]+)*'], methods: ['GET'])]
    public function show(): Response
    {
        $page = $this->landing->published((string) $this->param('slug')) ?? throw new NotFoundHttpException('The page could not be found.');
        $user = $this->currentUser();
        $view = $this->views->build($page, $user, false);
        $this->analytics->viewed($page, $user?->id, $this->analyticsVisitor(), $this->analyticsCampaign(true));
        return $this->render('landing-page', ['title' => $view['meta']['title'], 'active_nav' => 'catalogue', 'landing' => $view, 'page_meta' => $view['meta']]);
    }

    #[Route('/landing/{slug}/picture/{public_id}', name: 'landing_page_picture', requirements: ['slug' => '[a-z0-9]+(?:-[a-z0-9]+)*', 'public_id' => '[0-9a-fA-F-]{36}'], methods: ['GET'])]
    public function picture(): Response
    {
        $page = $this->landing->atAddress((string) $this->param('slug')) ?? throw new NotFoundHttpException('The picture could not be found.');
        $public = $page['status'] === 'published' && $page['course_status'] === 'published';
        $user = $this->currentUser();
        $manager = $user !== null && ($user->hasPermission('PLATFORM.DASHBOARD.VIEW') || ($user->hasPermission('COURSE.EDIT') && $this->courses->userCanManageCourse((int) $page['course_id'], $user->id)));
        if (!$public && !$manager) {
            throw new NotFoundHttpException('The picture could not be found.');
        }
        $resourceId = null;
        foreach ($page['sections'] as $section) {
            if ($section['type'] === LandingSectionType::Hero && $section['data']['image'] === 'resource') {
                $resourceId = $section['data']['image_resource_id'];
            }
        }
        $picture = is_int($resourceId) ? $this->landing->picture($resourceId) : null;
        if ($picture === null || strcasecmp($picture['public_id'], (string) $this->param('public_id')) !== 0) {
            throw new NotFoundHttpException('The picture could not be found.');
        }
        try {
            $file = $this->resources->resourceByPublicId($picture['public_id']);
        } catch (InvalidArgumentException) {
            throw new NotFoundHttpException('The picture could not be found.');
        }
        $response = new BinaryFileResponse((string) $file['path']);
        $response->headers->set('Content-Type', $picture['mime_type']);
        $response->headers->set('X-Content-Type-Options', 'nosniff');
        $response->headers->set('Content-Security-Policy', "default-src 'none'; style-src 'unsafe-inline'; sandbox");
        $response->setContentDisposition(ResponseHeaderBag::DISPOSITION_INLINE, $picture['original_filename']);
        if ($public) {
            $response->setPublic();
            $response->setMaxAge(3600);
        } else {
            $response->setPrivate();
            $response->headers->addCacheControlDirective('no-store');
        }
        return $response;
    }
}
