<?php

/*
Generated by: Claude Code CLI

Date time: 2026/10/07 SAST

Version: 0.8.8.9

Description:
A course's certificate settings: whether the course issues a certificate, its wording and its
signatory - the certificate data that belongs to the course. The design is the current certificate
document template, managed at System → Document Templates; the page links there and never stores
HTML or CSS on the course. Its preview and sample PDF are this course's certificate rendered by the
shared document renderer with the current design and a sample learner, the same path issuing uses.

Changelog:
2026/10/07 SAST
- Created for certificates on the document template engine (Phase J), replacing the course's own
  certificate HTML/CSS editor and its separate preview renderer.
*/

declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Course\Certificate\CertificateDocumentDataBuilder;
use CattoLearning\Course\CourseService;
use CattoLearning\Document\DocumentPdfRenderer;
use CattoLearning\Document\DocumentTemplateRenderer;
use CattoLearning\Document\DocumentTemplateRepository;
use CattoLearning\Document\DocumentType;
use CattoLearning\Document\RenderedDocument;
use CattoLearning\View\ThemeRenderer;
use RuntimeException;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Exception\AccessDeniedHttpException;
use Symfony\Component\Routing\Attribute\Route;

final class CourseCertificateController extends BaseController
{
    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly CourseService $courses,
        private readonly CertificateDocumentDataBuilder $data,
        private readonly DocumentTemplateRenderer $renderer,
        private readonly DocumentTemplateRepository $templates,
        private readonly DocumentPdfRenderer $pdf,
    ) {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/admin/courses/{id}/certificate', name: 'admin_course_certificate', requirements: ['id' => '\d+'], methods: ['GET'])]
    public function show(): Response
    {
        $user = $this->requirePermission('COURSE.CERTIFICATE.MANAGE');
        $course = $this->managedCourse((int) $this->param('id'));
        $current = $this->templates->currentVersion(DocumentType::Certificate);
        $preview = null;
        $error = null;
        try {
            $preview = $this->preview($course, $user->id);
        } catch (RuntimeException $failed) {
            $error = $failed->getMessage();
        }
        return $this->render('admin-course-certificate', [
            'title' => 'Certificate · ' . (string) $course['title'],
            'course' => $course,
            'current_template' => $current,
            'preview' => $preview === null ? null : ['html' => $preview->html, 'width' => $preview->settings->widthPx(), 'height' => $preview->settings->heightPx(), 'label' => $preview->settings->label()],
            'preview_error' => $error,
            'can_view_templates' => $user->hasPermission('DOCUMENT.TEMPLATE.VIEW'),
        ]);
    }

    #[Route('/admin/courses/{id}/certificate', name: 'admin_course_update_certificate', requirements: ['id' => '\d+'], methods: ['POST'])]
    public function update(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('COURSE.CERTIFICATE.MANAGE');
        $courseId = (int) $this->param('id');
        $this->managedCourse($courseId);
        return $this->handle(function () use ($user, $courseId): void {
            $this->courses->updateCertificateSettings($courseId, $_POST, $user->id);
            $this->flash('success', 'The certificate settings were saved. The preview below uses them.');
            $this->redirect('/admin/courses/' . $courseId . '/certificate#certificate-preview');
        }, '/admin/courses/' . $courseId . '/certificate');
    }

    /** This course's certificate in the current design, as the PDF engine draws it. */
    #[Route('/admin/courses/{id}/certificate/sample.pdf', name: 'admin_course_certificate_sample', requirements: ['id' => '\d+'], methods: ['GET'])]
    public function sample(): Response
    {
        $user = $this->requirePermission('COURSE.CERTIFICATE.MANAGE');
        $course = $this->managedCourse((int) $this->param('id'));
        return new Response($this->pdf->render($this->preview($course, $user->id)), 200, [
            'Content-Type' => 'application/pdf',
            'Content-Disposition' => 'inline; filename="certificate-sample.pdf"',
            'X-Content-Type-Options' => 'nosniff',
            'Cache-Control' => 'private, no-store',
        ]);
    }

    /** @param array<string,mixed> $course */
    private function preview(array $course, int $userId): RenderedDocument
    {
        $profile = $this->auth->profile($userId);
        $sample = CertificateDocumentDataBuilder::learnerName((array) $profile + ['display_name' => 'Sample Learner']);
        return $this->renderer->renderCurrent(DocumentType::Certificate, $this->data->forPreview($course, $sample));
    }

    /** @return array<string,mixed> */
    private function managedCourse(int $courseId): array
    {
        $user = $this->requireUser();
        $course = $this->courses->adminCourse($courseId);
        if (!$user->hasPermission('PLATFORM.DASHBOARD.VIEW') && !$this->courses->userCanManageCourse($courseId, $user->id)) {
            throw new AccessDeniedHttpException('You do not have permission to manage this course.');
        }
        return $course;
    }
}
