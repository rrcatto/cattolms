declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Course\Certificate\CertificateDesignRepository;
use CattoLearning\Course\Certificate\CertificateDesignService;
use CattoLearning\Course\Certificate\CertificateDocumentDataBuilder;
use CattoLearning\Course\CourseService;
use CattoLearning\Document\DocumentPdfRenderer;
use CattoLearning\Document\DocumentTemplateRenderer;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Exception\AccessDeniedHttpException;
use Symfony\Component\Routing\Attribute\Route;

final class CourseCertificateController extends BaseController
{
    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly CourseService $courses,
        private readonly CertificateDesignService $designs,
        private readonly CertificateDesignRepository $designRecords,
        private readonly CertificateDocumentDataBuilder $data,
        private readonly DocumentTemplateRenderer $renderer,
        private readonly DocumentPdfRenderer $pdf,
    ) {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/admin/courses/{id}/certificate', name: 'admin_course_certificate', requirements: ['id' => '\d+'], methods: ['GET'])]
    public function show(): Response
    {
        $user = $this->requirePermission('COURSE.CERTIFICATE.MANAGE');
        $course = $this->managedCourse((int) $this->param('id'));
        $items = [];
        foreach ($this->designs->designs() as $design) {
            $row = CertificateDesignController::listRow($design);
            $items[] = ['value' => $row['id'], 'label' => $row['name'], 'image' => $row['image'], 'note' => $row['is_default'] ? 'Default for new courses' : ''];
        }
        return $this->render('admin-course-certificate', [
            'title' => 'Certificate · ' . (string) $course['title'],
            'course' => $course,
            'design_items' => $items,
            'selected_design' => (int) $course['certificate_design_id'],
            'can_manage_designs' => $user->hasPermission('CERTIFICATE.DESIGN.MANAGE'),
            'can_view_designs' => $user->hasPermission('CERTIFICATE.DESIGN.VIEW'),
        ]);
    }

    #[Route('/admin/courses/{id}/certificate', name: 'admin_course_update_certificate', requirements: ['id' => '\d+'], methods: ['POST'])]
    public function update(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('COURSE.CERTIFICATE.MANAGE');
        $courseId = (int) $this->param('id');
        $this->managedCourse($courseId);
        return $this->handle(function () use ($user, $courseId): void {
            $this->courses->updateCertificateSettings($courseId, $_POST, $user->id);
            $this->flash('success', 'The certificate settings were saved.');
            $this->redirect('/admin/courses/' . $courseId . '/certificate');
        }, '/admin/courses/' . $courseId . '/certificate');
    }

    /** The saved settings drawn for a sample learner. */
    #[Route('/admin/courses/{id}/certificate/preview.pdf', name: 'admin_course_certificate_preview', requirements: ['id' => '\d+'], methods: ['GET'])]
    public function preview(): Response
    {
        $user = $this->requirePermission('COURSE.CERTIFICATE.MANAGE');
        $course = $this->managedCourse((int) $this->param('id'));
        return $this->draw($course, (int) $course['certificate_design_id'], (string) ($course['certificate_accreditation'] ?? ''), $user->id);
    }

    /** The form as it stands - the chosen design and accreditation line - before it is saved. */
    #[Route('/admin/courses/{id}/certificate/preview.pdf', name: 'admin_course_certificate_preview_form', requirements: ['id' => '\d+'], methods: ['POST'])]
    public function previewForm(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('COURSE.CERTIFICATE.MANAGE');
        $course = $this->managedCourse((int) $this->param('id'));
        return $this->draw($course, (int) $this->posted('certificate_design_id'), mb_substr(trim($this->posted('certificate_accreditation')), 0, 240), $user->id);
    }

    /** @param array<string,mixed> $course */
    private function draw(array $course, int $designId, string $accreditation, int $userId): Response
    {
        $design = $this->designRecords->find($designId) ?? $this->designRecords->find((int) $course['certificate_design_id']);
        if ($design === null) {
            throw $this->notFound('That certificate design does not exist.');
        }
        $profile = $this->auth->profile($userId);
        $learner = CertificateDocumentDataBuilder::learnerName((array) $profile + ['display_name' => 'Sample Learner']);
        $data = $this->data->forPreview(['certificate_accreditation' => $accreditation] + $course, $learner);
        $document = $this->renderer->renderVersion((int) $design['published_version_id'], $data);
        return new Response($this->pdf->render($document), 200, [
            'Content-Type' => 'application/pdf',
            'Content-Disposition' => 'inline; filename="certificate-preview.pdf"',
            'X-Content-Type-Options' => 'nosniff',
            'Cache-Control' => 'private, no-store',
        ]);
    }

    /** @return array<string,mixed> */
    private function managedCourse(int $courseId): array
    {
        $user = $this->requireUser();
        $course = $this->courses->adminCourse($courseId);
        if (!$user->hasPermission('PLATFORM.DASHBOARD.VIEW') && !$this->courses->userCanManageCourse($courseId, $user->id)) {
            throw new AccessDeniedHttpException('You do not have permission to manage this course.');
        }
        return $course;
    }
}
