    /** The editor's PNG, or null when it did not run. */
    private static function edited(string $field): ?string
    {
        $prefix = 'data:image/png;base64,';
        if (!str_starts_with($field, $prefix)) return null;
        if (strlen($field) > 16 * 1024 * 1024) throw new \InvalidArgumentException('The edited logo was too large. Make it smaller in the editor and try again.');
        $bytes = base64_decode(substr($field, strlen($prefix)), true);
        return $bytes === false || $bytes === '' ? null : $bytes;
    }

    /** @param array{documents:list<string>,certificates:list<string>,kept:list<string>} $followed */
    private static function followed(array $followed, bool $removed = false): string
    {
        $parts = [];
        if ($followed['documents'] !== []) $parts[] = 'invoices, receipts and credit notes';
        if ($followed['certificates'] !== []) $parts[] = count($followed['certificates']) === 1 ? 'the certificate design ' . $followed['certificates'][0] : count($followed['certificates']) . ' certificate designs';
        $made = $parts === [] ? '' : 'New versions of ' . implode(' and ', $parts) . ($removed ? ' print no logo' : ' print it') . ' from now on, and documents already issued keep the logo they had. ';
        return $made . ($removed ? 'The other PDFs and the email templates that chose the site logo show none until another is uploaded.' : 'Every other PDF the site makes, and every email template that chooses the site logo, shows it.');
    }

    /** @param list<string> $kept */
    private static function kept(array $kept): string
    {
        if (count($kept) === 1) {
            return 'The certificate design ' . $kept[0] . ' kept the look it had: with the new logo its words would not fit on the page. Open it under Courses, Certificate Designs, and shorten the words or choose No logo.';
        }
        return 'The certificate designs ' . implode(', ', $kept) . ' kept the look they had: with the new logo their words would not fit on the page. Open each under Courses, Certificate Designs, and shorten the words or choose No logo.';
    }
