    #[Route('/admin/settings/site-owner/logo', name: 'admin_site_logo_upload', methods: ['POST'])]
    public function upload(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            // What the editor made of it (turned, sized and placed, as a profile picture is), else the file as it came; the
            // site checks and prepares either alike, so a hand-posted field is only a differently shaped upload.
            $bytes = self::edited((string) ($_POST['edited_image'] ?? ''));
            if ($bytes === null) {
                $file = $_FILES['logo'] ?? null;
                if (!is_array($file) || (int) ($file['error'] ?? UPLOAD_ERR_NO_FILE) === UPLOAD_ERR_NO_FILE) {
                    throw new \InvalidArgumentException('Choose the logo file to upload.');
                }
                if ((int) ($file['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_OK || !is_uploaded_file((string) ($file['tmp_name'] ?? ''))) {
                    throw new \InvalidArgumentException('The logo could not be uploaded. Try again with a file of at most 12 MB.');
                }
                $bytes = (string) file_get_contents((string) $file['tmp_name']);
            }
            $followed = $this->followers->upload($bytes, $user->id);
            $this->flash('success', 'The site logo was saved. ' . self::followed($followed));
            if ($followed['kept'] !== []) $this->flash('warning', self::kept($followed['kept']));
            $this->redirect(self::SECTION);
        }, self::SECTION);
    }

    #[Route('/admin/settings/site-owner/logo/remove', name: 'admin_site_logo_remove', methods: ['POST'])]
    public function remove(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            $followed = $this->followers->remove($user->id);
            $this->flash('success', $followed === null ? 'There was no site logo to remove.' : 'The site logo was removed. ' . self::followed($followed, true));
            if ($followed !== null && $followed['kept'] !== []) $this->flash('warning', self::kept($followed['kept']));
            $this->redirect(self::SECTION);
        }, self::SECTION);
    }

    /** The site's picture (owner, 2026-11-09: the hero), what a page without a picture of its own is shared with. */
    #[Route('/admin/settings/site-owner/picture', name: 'admin_site_picture_upload', methods: ['POST'])]
    public function uploadPicture(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            $file = $_FILES['picture'] ?? null;
            if (!is_array($file) || (int) ($file['error'] ?? UPLOAD_ERR_NO_FILE) === UPLOAD_ERR_NO_FILE) throw new \InvalidArgumentException('Choose the picture to upload.');
            if ((int) ($file['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_OK || !is_uploaded_file((string) ($file['tmp_name'] ?? ''))) {
                throw new \InvalidArgumentException('The picture could not be uploaded. Try again with a file of at most 12 MB.');
            }
            $change = $this->picture->upload((string) file_get_contents((string) $file['tmp_name']), $user->id);
            $this->audit->record($user->id, 'site_owner.picture_changed', $change);
            $this->flash('success', 'The site picture was saved. A page without a picture of its own is shared with it from now on.');
            $this->redirect(self::SECTION);
        }, self::SECTION);
    }

    #[Route('/admin/settings/site-owner/picture/remove', name: 'admin_site_picture_remove', methods: ['POST'])]
    public function removePicture(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            $removed = $this->picture->remove($user->id);
            if ($removed !== null) $this->audit->record($user->id, 'site_owner.picture_changed', ['from' => $removed, 'to' => null]);
            $this->flash('success', $removed === null ? 'There was no site picture to remove.' : 'The site picture was removed. A page without a picture of its own is shared without one until another is uploaded.');
            $this->redirect(self::SECTION);
        }, self::SECTION);
    }

    /** The site's picture as shared (1200 by 630), or the picture itself, of this picture or one before it. */
    #[Route('/site-picture/{version}.jpg', name: 'site_picture', requirements: ['version' => '[0-9a-f]{16}'], methods: ['GET'])]
