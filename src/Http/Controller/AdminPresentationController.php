    /**
     * Runs one move. The list's script asks with HX-Request and gets the saved list back, or the stored one and a 422
     * with the reason; a plain form post goes back to the slide in the list.
     *
     * @param array<string,mixed> $item
     */
    private function moved(CurrentUser $user, array $item, string $slideId, callable $move): Response
    {
        $home = self::home($item);
        if (!$this->isHtmxRequest()) {
            return $this->handle(function () use ($move, $home, $slideId): void {
                $move();
                $this->flash('success', 'The slide was moved.');
                $this->redirect($home . '#slide-' . $slideId);
            }, $home . '#presentation-slides');
        }
        $error = '';
        try {
            $move();
        } catch (InvalidArgumentException|RuntimeException $refused) {
            $error = $refused->getMessage();
        }
        $fresh = $this->items->item((int) $item['id']);
        return $this->renderFragment('partials/admin/presentation-slides', $this->pages->page($fresh, ListView::chosen('slides', $_GET, $_COOKIE), null, $error), $error === '' ? 200 : 422);
    }

    /**
     * @param array<string,mixed> $posted
     * @return array<string,mixed>
     */
    private function withPicture(array $posted): array
    {
        $file = $_FILES['slide_picture'] ?? null;
        if (!is_array($file) || (int) ($file['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_OK || !is_string($file['tmp_name'] ?? null) || !is_uploaded_file($file['tmp_name'])) { return $posted; }
        $size = (int) filesize($file['tmp_name']);
        if ($size < 1 || $size > SlideDeck::PICTURE_LIMIT_BYTES) { throw new InvalidArgumentException('A picture may be at most 1.5 MB.'); }
        $type = (string) (new \finfo(FILEINFO_MIME_TYPE))->file($file['tmp_name']);
        $bytes = (string) file_get_contents($file['tmp_name']);
        $picture = match (true) {
            in_array($type, ['image/svg+xml', 'image/svg', 'text/xml', 'text/plain', 'application/xml'], true) && SlideDeck::isPicture($bytes) => $bytes,
            in_array($type, ['image/png', 'image/jpeg'], true) => 'data:' . $type . ';base64,' . base64_encode($bytes),
            default => throw new InvalidArgumentException('A picture is an SVG drawing, or a PNG or JPEG photo or chart.'),
        };
        return ['picture' => $picture] + $posted;
    }

    /**
     * Where a new slide goes: after the slide numbered so, or before an Up next or call to action that ends the slides.
     *
     * @param array{slides:list<array<string,mixed>>} $deck
     */
    private function afterOf(array $deck, mixed $asked): int
    {
        $count = count($deck['slides']);
        if (is_string($asked) && ctype_digit($asked) && (int) $asked <= $count) { return (int) $asked; }
        $last = $deck['slides'][$count - 1]['layout'] ?? '';
        return in_array($last, ['next', 'cta'], true) ? $count - 1 : $count;
    }

    /** @param array{slides:list<array<string,mixed>>} $deck */
    private function slideIndex(array $deck): int
    {
        try {
            return PresentationEditor::indexOf($deck, $this->param('slide_id'));
        } catch (InvalidArgumentException) {
            throw new NotFoundHttpException('That slide is no longer in the presentation.');
        }
    }

    /** @return array<string,mixed> A Presentation the reader may edit. */
    private function viewing(): array
    {
        $user = $this->requirePermission('COURSE.EDIT');
        $id = (int) $this->param('item_id');
        try {
            $item = $this->items->item($id);
        } catch (InvalidArgumentException|RuntimeException) {
            throw new NotFoundHttpException('That presentation does not exist.');
        }
        if ((string) $item['item_type'] !== 'slide_deck') { throw new NotFoundHttpException('That Course Item is not a presentation.'); }
        if ($user->hasPermission('PLATFORM.DASHBOARD.VIEW') || (int) $item['created_by_user_id'] === $user->id) { return $item; }
        foreach ((array) $item['course_usage'] as $course) { if ($this->courses->userCanManageCourse((int) $course['id'], $user->id)) { return $item; } }
        throw new AccessDeniedHttpException('You do not have permission to edit this presentation.');
    }

    /** @return array{0:CurrentUser,1:array<string,mixed>} */
    private function changing(): array
    {
        $this->requireCsrf();
        $item = $this->viewing();
        return [$this->requirePermission('COURSE.EDIT'), $item];
    }

    /** @param array<string,mixed> $item */
    private static function home(array $item): string
    {
        return '/admin/course-items/' . (int) $item['id'];
    }
