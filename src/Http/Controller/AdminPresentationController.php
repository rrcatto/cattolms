    }

    /** A slide's narration script, saved on its own, an audio file uploaded without JavaScript, or its recording removed. */
    #[Route('/admin/course-items/{item_id}/slides/{slide_id}/narration', name: 'admin_presentation_slide_narration', requirements: self::SLIDE, methods: ['POST'])]
    public function narration(): Response
    {
        [$user, $item] = $this->changing();
        $slideId = $this->param('slide_id');
        $page = self::home($item) . '/slides/' . $slideId;
        $message = '';
        try {
            if (isset($_POST['narration_remove'])) {
                $this->narrations->remove((int) $item['id'], $slideId);
                $message = 'The recording was removed.';
            } else {
                $this->editor->saveScript((int) $item['id'], $slideId, (string) ($_POST['narration'] ?? ''), $user->id);
                $message = 'The script was saved.';
                $file = $_FILES['narration_upload'] ?? null;
                if (is_array($file) && (int) ($file['error'] ?? UPLOAD_ERR_NO_FILE) === UPLOAD_ERR_OK && is_uploaded_file((string) $file['tmp_name'])) {
                    $this->narrations->save((int) $item['id'], $slideId, (string) $file['tmp_name'], null, $user->id);
                    $message = 'The script and the audio file were saved.';
                }
            }
        } catch (InvalidArgumentException|RuntimeException $refused) {
            if ($this->isHtmxRequest()) { return $this->renderFragment('partials/admin/slide-script-status', ['status' => $refused->getMessage(), 'refused' => true], 422); }
            $this->flash('danger', $refused->getMessage());
            $this->redirect($page . '#narration');
        }
        if ($this->isHtmxRequest()) { return $this->renderFragment('partials/admin/slide-script-status', ['status' => $message, 'refused' => false]); }
        $this->flash('success', $message);
        $this->redirect($page . '#narration');
    }

