    /**
     * @param array<string,mixed> $item
     * @param array<string,mixed>|null $stored The slide as saved, or null for a new one.
     */
    private function slideAction(CurrentUser $user, array $item, ?array $stored, ?int $after): Response
    {
        $action = (string) ($_POST['slide_action'] ?? 'save');
        $posted = is_array($_POST['slide'] ?? null) ? $_POST['slide'] : null;
        $draft = $posted === null ? ($stored ?? SlideDeck::normaliseSlide(['layout' => 'points'])) : PresentationEditor::slideFrom($posted, $stored);
        try {
            if ($posted !== null) { $draft = PresentationEditor::slideFrom($this->withPicture($posted), $stored); }
        } catch (InvalidArgumentException $refused) {
            return $this->slidePage($item, $draft, $after, 422, ['tone' => 'danger', 'text' => $refused->getMessage()], true);
        }
        if ($action === 'layout') {
            $layout = (string) ($_POST['slide_layout'] ?? '');
            try {
                $draft = PresentationEditor::inLayout($draft, $layout);
            } catch (InvalidArgumentException $refused) {
                return $this->slidePage($item, $draft, $after, 422, ['tone' => 'danger', 'text' => $refused->getMessage()], true);
            }
            return $this->slidePage($item, $draft, $after, 200, ['tone' => 'info', 'text' => 'The slide is in the ' . SlideLayouts::LAYOUTS[$layout]['label'] . ' layout now. Press Save slide to keep it, or Close to leave it as it was.'], true);
        }
        if ($action === 'preview') {
            $preview = $this->pages->slidePreview($item, $draft);
            if ($this->isHtmxRequest()) { return $this->renderFragment('partials/admin/slide-preview', ['preview_html' => $preview, 'unsaved' => true]); }
            return $this->slidePage($item, $draft, $after, 200, null, $posted !== null, $preview);
        }
        try {
            if ($stored === null) {
                $id = $this->editor->addSlide((int) $item['id'], (int) $after, $draft, $user->id);
            } else {
                $this->editor->saveSlide((int) $item['id'], (string) $stored['id'], $draft, $user->id);
                $id = (string) $stored['id'];
            }
        } catch (InvalidArgumentException|RuntimeException $refused) {
            return $this->slidePage($item, $draft, $after, 422, ['tone' => 'danger', 'text' => $refused->getMessage()], true);
        }
        $this->flash('success', $stored === null ? 'The new slide was saved.' : 'The slide was saved.');
        $this->redirect(self::home($item) . '/slides/' . $id);
    }

    /**
     * @param array<string,mixed> $item
     * @param array<string,mixed> $slide
     * @param array{tone:string,text:string}|null $notice
