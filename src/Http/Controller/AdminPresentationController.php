    /** A drag, or a move from the keyboard: the slide goes to index among the others, the order shown sent with it. */
    #[Route('/admin/course-items/{item_id}/slides/{slide_id}/arrange', name: 'admin_presentation_slide_arrange', requirements: self::SLIDE, methods: ['POST'])]
    public function arrange(): Response
    {
        [$user, $item] = $this->changing();
        $slideId = $this->param('slide_id');
        $index = trim($this->posted('index'));
        $order = $_POST['order'] ?? null;
        return $this->moved($user, $item, $slideId, function () use ($item, $slideId, $index, $order, $user): void {
            if (!ctype_digit($index) || ($order !== null && (!is_array($order) || array_filter($order, static fn(mixed $id): bool => !is_string($id) || preg_match('/^[a-z0-9]{6,32}$/', $id) !== 1) !== []))) {
                throw new InvalidArgumentException('Choose a valid place among the slides.');
            }
            $this->editor->arrange((int) $item['id'], $slideId, (int) $index, $order === null ? null : array_values(array_map('strval', $order)), $user->id);
        });
    }

    #[Route('/admin/course-items/{item_id}/slides/{slide_id}/copy', name: 'admin_presentation_slide_copy', requirements: self::SLIDE, methods: ['POST'])]
