    private function slidePage(array $item, array $slide, ?int $after, int $status = 200, ?array $notice = null, bool $unsaved = false, string $preview = ''): Response
    {
        $data = $this->pages->slidePage($item, $slide, $after);
        return $this->render('admin-presentation-slide', $data + [
