    private function folder(string $folder): Response
    {
        $user = $this->requirePermission('PLATFORM.INBOX.VIEW');
        $query = $this->request()->query;
        $show = (string) $query->get('show', 'all');
        if (!in_array($show, ['all', 'new', 'unanswered', 'answered'], true)) $show = 'all';
        $reason = (string) $query->get('reason', '');
        if (!ContactReason::valid($reason)) $reason = '';
        $search = mb_substr(trim((string) $query->get('q', '')), 0, 120);
        $filters = $folder === 'inbox' ? ['show' => $show, 'reason' => $reason, 'search' => $search] : ['search' => $search];
        $total = $this->inbox->folder($folder, $filters, 1, 0)['total'];
        $pagination = Pagination::create($query->get('messages_page'), $query->get('messages_page_size'), $total, 25);
        $page = $this->inbox->folder($folder, $filters, $pagination->pageSize, $pagination->offset);
        $counts = $this->inbox->counts();
        return $this->render('inbox-folder', [
            'title' => self::FOLDERS[$folder]['title'],
            'active_nav' => 'inbox',
            'folder' => $folder,
            'path' => self::FOLDERS[$folder]['path'],
            'rows' => $page['rows'],
            'drafts' => $folder === 'trash' ? $this->inbox->trashedDrafts() : [],
            'total' => $total,
            'counts' => $counts,
            'keeping' => $this->inbox->keeping(),
            'trained' => $this->inbox->trained(),
            'filters' => ['show' => $show, 'reason' => $reason, 'q' => $search],
            'filtered' => $search !== '' || $reason !== '' || $show !== 'all',
            'reasons' => ContactReason::LABELS,
            'can_manage' => $user->hasPermission('PLATFORM.INBOX.MANAGE'),
            'messages_pagination' => Pager::payload($pagination, 'messages', self::FOLDERS[$folder]['path'], 'messages', array_filter(['show' => $show !== 'all' ? $show : '', 'reason' => $reason, 'q' => $search])),
        ]);
    }

