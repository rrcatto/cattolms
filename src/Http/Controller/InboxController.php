    {
        return preg_match('#^/inbox(/(spam|trash|sent|drafts))?(\?[^\s"<>]*)?$#', $path) === 1 ? $path : '/inbox';
    }

    /**
     * @param array<mixed> $values
     * @return list<int>
     */
    private static function ids(array $values): array
    {
        return array_values(array_unique(array_filter(array_map('intval', $values), static fn(int $id): bool => $id > 0)));
    }

    private static function count(int $count, string $what): string
    {
        return ($count === 1 ? '1 message' : $count . ' messages') . ' ' . $what . '.';
    }
