    #[Route('/inbox/{reference}/reply', name: 'inbox_reply', requirements: ['reference' => RecordAddress::MESSAGE], methods: ['POST'])]
    public function reply(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.INBOX.MANAGE');
        $id = $this->conversationId();
        $page = RecordAddress::message($this->param('reference'));
        $files = array_values(array_filter($this->request()->files->all('attachments'), static fn(mixed $file): bool => $file instanceof UploadedFile));
        $send = $this->posted('send') === 'send';
        return $this->handle(function () use ($id, $user, $page, $files, $send): void {
            $result = $this->replies->save($id, $this->request()->request->all(), $files, (string) $user->id, $send);
            if ($result['error'] !== '') {
                $this->flash('danger', $result['error']);
                $this->redirect($page . '#reply');
            }
            $this->flash('success', $result['sent'] ? 'Your reply is sent. It is in the conversation and in Sent.' : 'Your draft is saved. It is in Drafts until you send it.');
            $this->redirect($page . ($result['sent'] ? '#item-' . $result['item_id'] : '#reply'));
        }, $page . '#reply', true);
    }

