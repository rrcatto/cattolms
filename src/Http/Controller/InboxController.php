    #[Route('/inbox/settings', name: 'inbox_settings_save', methods: ['POST'])]
    public function saveSettings(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.INBOX.MANAGE');
        $action = $this->posted('action', 'save');
        return $this->handle(function () use ($user, $action): void {
            if ($action === 'reset') {
                $this->settings->resetAll($this->actor($user));
                $this->flash('success', 'The Inbox settings are back to the standard ones.');
            } elseif ($action === 'disconnect') {
                $this->settings->forgetMailbox($this->actor($user));
                $this->mailboxJob->forget();
                $this->flash('success', 'The mailbox is disconnected: nothing is fetched until one is set again.');
            } elseif ($action === 'check') {
                // What is typed is saved first, so the check reads it.
                try {
                    $this->settings->saveAll($this->request()->request->all(), $this->actor($user));
                } catch (SettingsRefused $refused) {
                    throw new \InvalidArgumentException($refused->getMessage());
                }
                try {
                    $this->flash('success', $this->mailbox->check($this->settings->mailbox()) . ' Answers arriving from now on come into their conversations.');
                } catch (\RuntimeException $failed) {
                    $this->flash('danger', $failed->getMessage() . ' The settings are saved; correct them and check again.');
                }
            } elseif ($action === 'forget') {
                $this->inbox->forget($user->id);
                $this->flash('success', 'The word filter has forgotten what it learnt. Only the fixed signs count until you mark messages again.');
            } else {
                try {
                    $this->settings->saveAll($this->request()->request->all(), $this->actor($user));
                } catch (SettingsRefused $refused) {
                    throw new \InvalidArgumentException($refused->getMessage());
                }
                $this->flash('success', 'The Inbox settings are saved.');
            }
            $this->redirect('/inbox/settings');
        }, '/inbox/settings', true);
    }

