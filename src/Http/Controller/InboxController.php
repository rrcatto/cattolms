    #[Route('/inbox/act', name: 'inbox_act', methods: ['POST'])]
    public function act(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.INBOX.MANAGE');
        $back = $this->back((string) $this->posted('back', '/inbox'));
        $ids = self::ids($this->request()->request->all('ids'));
        $drafts = self::ids($this->request()->request->all('drafts'));
        $action = $this->posted('action');
        return $this->handle(function () use ($action, $ids, $drafts, $user, $back): void {
            if (!in_array($action, ['empty_trash', 'empty_spam', 'forget'], true) && $ids === [] && $drafts === []) throw new \InvalidArgumentException('Tick the messages first.');
            $message = match ($action) {
                'answered' => self::count(array_sum(array_map(function (int $id) use ($user): int { $this->inbox->markAnswered($id, $user->id); return 1; }, $ids)), 'marked answered'),
                'spam' => self::count($this->inbox->markSpam($ids, $user->id), 'moved to Spam'),
                'not_spam' => self::count($this->inbox->notSpam($ids, $user->id), 'moved back to the Inbox'),
                'trash' => self::count($this->inbox->trash($ids, $user->id) + $this->inbox->trashDrafts($drafts, $user->id), 'moved to the Trash'),
                'restore' => self::count($this->inbox->restore($ids, $user->id) + $this->inbox->restoreDrafts($drafts, $user->id), 'restored'),
                'delete' => self::count($this->inbox->deleteForever($ids, $user->id) + $this->inbox->deleteDraftsForever($drafts, $user->id), 'deleted for good'),
                'block' => self::count(array_sum(array_map(function (int $id) use ($user): int { $this->inbox->blockSender($id, 'email', $user->id); return 1; }, $ids)), 'blocked: their senders\' later messages go straight to Spam'),
                'empty_trash' => self::count($this->inbox->emptyFolder('trash', $user->id), 'deleted for good: the Trash is empty'),
                'empty_spam' => self::count($this->inbox->emptyFolder('spam', $user->id), 'deleted for good: Spam is empty'),
                default => throw new \InvalidArgumentException('That is not something the Inbox can do.'),
            };
            $this->flash('success', $message);
            $this->redirect($back);
        }, $back);
    }

