namespace CattoLearning\Http\Controller;

use CattoLearning\View\ThemeManager;

use CattoLearning\View\ThemeRenderer;

use CattoLearning\Auth\AuthService;

use Base;

/**
 * Serves presentation-only runtime theme metadata required by platform-owned
 * browser behaviour without exposing theme filesystem internals.
 */
final class ThemeController extends BaseController
{
    public function __construct(
        Base $f3,
        AuthService $auth,
        ThemeRenderer $view,
        private readonly ThemeManager $themes
    ) {
        parent::__construct($f3, $auth, $view);
    }

    public function palette(): void
    {
        $key = $this->themes->activeTheme();
        $preview = trim((string) ($_GET['theme_preview'] ?? ''));
        $user = $this->currentUser();
        if ($preview !== '' && $user !== null && $user->hasPermission('ADMIN.THEMES.VIEW')) {
            try {
                $this->themes->theme($preview);
                $key = $preview;
            } catch (\RuntimeException) {
                // Invalid preview identifiers never affect the live theme.
            }
        }

        header('Content-Type: application/json; charset=UTF-8');
        header('Cache-Control: private, no-store');
        echo json_encode($this->themes->paletteConfiguration($key), JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
        exit;
    }
}
