    /**
     * Why an address was flagged, and what else about it points that way.
     *
     * @param array<string,mixed>|null $flag
     * @param array<string,mixed>|null $latest
     * @return list<string>
     */
    private static function whyList(?array $flag, ?array $latest): array
    {
        $why = $flag === null ? [] : array_map(static fn(array $entry): string => $entry['words'], FlagRepository::why($flag));
        if ($flag === null) return [];
        if (($latest['network_kind'] ?? '') === 'hosting') $why[] = 'It is on a hosting network, where people do not normally browse from.';
        if (($latest['network_kind'] ?? '') === 'vpn') $why[] = 'It is on a VPN provider\'s network.';
        if (($latest['network_kind'] ?? '') === 'tor') $why[] = 'It is a Tor exit, used to hide where someone is.';
        if (($latest['agent_kind'] ?? '') === 'script') $why[] = 'Its browser says it is a script, ' . substr((string) $latest['agent_label'], 8) . '.';

        return array_values(array_unique($why));
    }

    /**
     * @param array<string,mixed>|null $flag
     * @param list<array<string,mixed>> $lockouts
     * @return list<array{when:string,what:string}>
     */
    private static function history(?array $flag, array $lockouts, ?string $firstSeen): array
    {
        $events = [];
        foreach ($flag === null ? [] : FlagRepository::why($flag) as $entry) {
            $events[] = [(int) strtotime($entry['at']), 'Flagged: ' . $entry['words']];
        }
        if ($flag !== null && Words::truthy($flag['fine']) && $flag['decided_at'] !== null) $events[] = [(int) strtotime((string) $flag['decided_at']), 'You marked it not a problem.'];
        foreach ($lockouts as $lockout) {
            $started = (int) strtotime((string) $lockout['started_at']);
            $until = $lockout['until_at'] !== null ? (int) strtotime((string) $lockout['until_at']) : 0;
            $length = $until > 0 ? Duration::ofSeconds(max(60, $until - $started))->words() : '';
            $name = $lockout['which'] === 'timeout' ? 'Timed out' : 'Locked out';
            $events[] = [$started, $name . ($length !== '' ? ' for ' . $length : ' for good') . (Words::truthy($lockout['automatic']) ? ' automatically' : ' by ' . ((string) ($lockout['created_by_name'] ?? '') ?: 'hand')) . ': ' . $lockout['why']];
            if ($lockout['lifted_at'] !== null) $events[] = [(int) strtotime((string) $lockout['lifted_at']), 'Lifted' . ((string) ($lockout['lifted_by_name'] ?? '') !== '' ? ' by ' . $lockout['lifted_by_name'] : '') . '.'];
        }
        if ($firstSeen !== null) $events[] = [(int) strtotime($firstSeen), 'First seen.'];
        usort($events, static fn(array $a, array $b): int => $b[0] <=> $a[0]);

        return array_map(static fn(array $event): array => ['when' => Words::when(gmdate(DATE_ATOM, $event[0])), 'what' => $event[1]], array_slice($events, 0, 30));
    }

    /** An address as the pages hold it: the address, or an IPv6 address's /64, or nothing when it is not one. */
    private static function subjectFrom(string $text): string
    {
        $text = trim($text);
        $address = (string) strtok($text, '/');
        if (filter_var($address, FILTER_VALIDATE_IP) === false) return '';

        return RequestFacts::subject($address);
    }

    private static function compared(int $now, int $before): string
    {
        if ($before === 0) return $now === 0 ? 'None in the period before' : 'None in the period before';
        if ($now === $before) return 'The same as the period before';
        $change = abs($now - $before);
        $share = (int) round($change * 100 / $before);

        return ($share >= 1 ? $share . '%' : (string) $change) . ($now > $before ? ' more' : ' fewer') . ' than the period before';
    }

    /**
     * Each slice of the period, the empty ones too, as two stacked columns.
     *
     * @param array<string,array{people:int,automated:int}> $slices
     * @return array{top:int,columns:list<array<string,mixed>>}
     */
    private static function chart(SitePeriod $period, array $slices): array
    {
        $unit = $period->unit();
        $zone = new \DateTimeZone(date_default_timezone_get());
        $from = $period->from->setTimezone($zone);
        $cursor = match ($unit) {
            'hour' => $from->setTime((int) $from->format('H'), 0),
            'day' => $from->setTime(0, 0),
            default => $from->modify('monday this week')->setTime(0, 0),
        };
        $step = ['hour' => '+1 hour', 'day' => '+1 day', 'week' => '+7 days'][$unit];
        $format = $unit === 'hour' ? 'H:i' : 'j M';
        $rows = [];
        while ($cursor < $period->to) {
            $values = $slices[$cursor->format('Y-m-d H:i')] ?? ['people' => 0, 'automated' => 0];
            $rows[] = ['label' => $cursor->format($format), 'title' => ($unit === 'week' ? 'Week of ' : '') . $cursor->format($format) . ': ' . $values['people'] . ' people, ' . $values['automated'] . ' automated'] + $values;
            $cursor = $cursor->modify($step);
        }
        $top = 0;
        foreach ($rows as $row) $top = max($top, $row['people'] + $row['automated']);
        $every = max(1, (int) ceil(count($rows) / 7));
        foreach ($rows as $index => $row) {
            $rows[$index]['people_share'] = $top > 0 ? round($row['people'] * 100 / $top, 1) : 0;
            $rows[$index]['automated_share'] = $top > 0 ? round($row['automated'] * 100 / $top, 1) : 0;
            $rows[$index]['labelled'] = $index % $every === 0;
        }

        return ['top' => $top, 'columns' => $rows];
    }

    /**
     * @param list<array{code:string,visitors:int,flagged:int}> $rows
     * @return list<array<string,mixed>>
     */
    private static function countries(array $rows, string $periodQuery): array
    {
        $top = $rows[0]['visitors'] ?? 0;
        $shown = [];
        foreach (array_slice($rows, 0, 5) as $row) {
            $shown[] = ['name' => Words::country($row['code']), 'visitors' => number_format($row['visitors']), 'flagged' => number_format($row['flagged']), 'share' => $top > 0 ? (int) round($row['visitors'] * 100 / $top) : 0,
                'href' => $row['code'] !== '' ? self::BASE . '/log?country=' . $row['code'] . '&' . $periodQuery : ''];
        }
        $rest = array_slice($rows, 5);
        if ($rest !== []) {
            $visitors = array_sum(array_column($rest, 'visitors'));
            $shown[] = ['name' => count($rest) . ' other ' . (count($rest) === 1 ? 'country' : 'countries'), 'visitors' => number_format($visitors), 'flagged' => number_format(array_sum(array_column($rest, 'flagged'))), 'share' => $top > 0 ? min(100, (int) round($visitors * 100 / $top)) : 0, 'href' => ''];
        }

        return $shown;
    }

    /**
     * @param list<array{source:string,came_from:string,visitors:int}> $rows
     * @return list<array<string,mixed>>
     */
    private static function sources(array $rows): array
    {
        $names = ['search' => 'Search engines', 'direct' => 'Typed in or a bookmark', 'email' => 'An email', 'site' => 'Other sites'];
        $merged = [];
        foreach ($rows as $row) {
            $name = $row['source'] === 'social' ? ucfirst((string) preg_replace('/\.[a-z.]+$/', '', $row['came_from'])) : ($names[$row['source']] ?? 'Other sites');
            $merged[$name] = ($merged[$name] ?? 0) + $row['visitors'];
        }
        arsort($merged);
        $top = $merged === [] ? 0 : (int) max($merged);
        $shown = [];
        foreach ($merged as $name => $visitors) {
            $shown[] = ['name' => $name, 'visitors' => number_format($visitors), 'share' => $top > 0 ? (int) round($visitors * 100 / $top) : 0];
        }

        return $shown;
    }

    /** @param array<string,int> $devices */
    private static function devices(array $devices): string
    {
        $total = array_sum($devices);
        if ($total === 0) return '';
        $names = ['phone' => 'Phones', 'computer' => 'computers', 'tablet' => 'tablets'];
        $parts = [];
        foreach ($names as $key => $name) {
            if (($devices[$key] ?? 0) > 0) $parts[] = $name . ' ' . (int) round($devices[$key] * 100 / $total) . '%';
        }

        return ucfirst(implode(', ', $parts)) . '.';
    }

    private static function howMany(string $range): string
    {
        [$network, $bits] = explode('/', $range, 2);
        if (str_contains($network, ':')) return 'an IPv6 network';
        $count = 2 ** (32 - (int) $bits);

        return number_format($count) . ($count === 1 ? ' address' : ' addresses');
    }

    /** Only back to one of these pages. */
    private static function back(string $return): string
    {
        return str_starts_with($return, self::BASE . '/') && !str_contains($return, '//') ? $return : self::BASE . '/lockouts';
    }
