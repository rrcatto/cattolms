declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Company\CompanyDepartures;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class CompanyDepartureController extends BaseController
{
    private const TOKEN = '[A-Za-z0-9_-]{20,}';

    public function __construct(AuthService $auth, ThemeRenderer $view, RequestStack $requests, private readonly CompanyDepartures $departures)
    {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/leaving/confirm', name: 'company_departure_confirm', methods: ['GET'])]
    public function confirm(): Response
    {
        $token = (string) ($_GET['token'] ?? '');

        return $this->handle(function () use ($token): Response {
            $email = $this->departures->confirmPrivate($token);

            return $this->render('company-leaving-done', ['title' => 'Your account is private', 'private_email' => $email]);
        }, '/login');
    }

    #[Route('/leaving/{token}', name: 'company_departure', requirements: ['token' => self::TOKEN], methods: ['GET'], priority: -1)]
    public function show(): Response
    {
        $departure = $this->departures->forLink((string) $this->param('token'));
        if ($departure === null) throw $this->notFound(CompanyDepartures::EXPIRED);

        return $this->render('company-leaving', ['title' => 'Your account at ' . $departure['company_name'], 'departure' => $departure, 'token' => (string) $this->param('token'),
            'sent_to' => (string) ($_GET['sent'] ?? '') !== '' ? (string) $departure['private_email'] : '']);
    }

    #[Route('/leaving/{token}/private', name: 'company_departure_private', requirements: ['token' => self::TOKEN], methods: ['POST'])]
    public function keepPrivate(): Response
    {
        $this->requireCsrf();
        $token = (string) $this->param('token');

        return $this->handle(function () use ($token): void {
            $this->departures->choosePrivate($token, (string) ($_POST['email'] ?? ''));
            $this->redirect('/leaving/' . $token . '?sent=1');
        }, '/leaving/' . $token);
    }

    #[Route('/leaving/{token}/delete', name: 'company_departure_delete', requirements: ['token' => self::TOKEN], methods: ['POST'])]
    public function deleteAccount(): Response
    {
        $this->requireCsrf();
        $token = (string) $this->param('token');

        return $this->handle(function () use ($token): Response {
            if (($_POST['understood'] ?? '') !== '1') throw new \InvalidArgumentException('Tick the box to say you understand your courses and progress go too.');
            $this->departures->chooseDelete($token);

            return $this->render('company-leaving-done', ['title' => 'Your account is deleted', 'private_email' => '']);
        }, '/leaving/' . $token);
    }
}
