        return $this->render('admin-course-categories', [
            'title' => 'Course categories',
            'course_group' => 'categories',
            'category_tree' => $tree,
            'category_statistics' => CourseService::categoryStatistics($categories),
            'open_ids' => self::openIn($tree),
            'tree_error' => '',
            'create_parent' => null,
            'create_values' => [],
        ]);
    }

