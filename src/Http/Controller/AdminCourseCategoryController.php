    #[Route('/admin/courses/categories/inline', name: 'admin_course_category_inline_create', methods: ['POST'])]
    public function inlineCreate(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('COURSE.CATEGORY.MANAGE');

        // The one JSON answer outside /api/v1: the category picker creates a category without
        // leaving the form it is sitting in, so the caller is this platform's own JavaScript.
        try {
            $category = $this->courses->createCategory($_POST, $user->id);

            return new JsonResponse([
                'category' => [
                    'id' => (int) $category['id'],
                    'name' => (string) $category['name'],
                    'slug' => (string) $category['slug'],
                ],
            ], Response::HTTP_CREATED);
        } catch (InvalidArgumentException|RuntimeException $e) {
            return new JsonResponse(['error' => $e->getMessage()], Response::HTTP_UNPROCESSABLE_ENTITY);
        }
    }

    /**
     * Creates a category; a refusal shows the form again with what was typed and the reason.
     *
     * @param array<string,mixed>|null $parent
     */
    private function created(?array $parent, int $userId): Response
    {
        try {
            $category = $this->courses->createCategory($_POST, $userId, $parent === null ? null : (int) $parent['id']);
        } catch (InvalidArgumentException|RuntimeException $refused) {
            return $this->createForm($parent, $_POST, [$refused->getMessage()], 422);
        }
        $this->flash('success', 'The course category “' . (string) $category['name'] . '” was created.');
        $this->redirect(self::revealing((int) $category['id']));
    }

    /**
     * @param array<string,mixed>|null $parent
     * @param array<string,mixed> $values
     * @param list<string> $errors
     */
    private function createForm(?array $parent, array $values, array $errors, int $status): Response
    {
        if ($parent !== null) {
            $parent['path'] = $this->courses->categoryTrail((int) $parent['id']);
        }
        $data = [
            'title' => $parent === null ? 'Add category' : 'Add subcategory to ' . (string) $parent['name'],
            'course_group' => 'categories',
            'in_modal' => $this->isHtmxRequest(),
            'create_parent' => $parent,
            'create_values' => $values,
            'create_errors' => $errors,
        ];
        // The tree's modal asks with htmx for the form alone; a plain request gets it on its own page.
        return $this->isHtmxRequest()
            ? $this->renderFragment('partials/admin/category-create-form', $data, $status)
            : $this->render('admin-course-category-new', $data, $status);
    }

    /**
     * Runs one move. The tree's script asks with HX-Request and gets the saved tree and counts back,
     * or the authoritative ones and a 422 with the reason; a plain form post redirects.
     */
    private function moved(int $categoryId, callable $move): Response
    {
        if (!$this->isHtmxRequest()) {
            return $this->handle(function () use ($move, $categoryId): void {
                $move();
                $this->flash('success', 'The category was moved.');
                $this->redirect(self::revealing($categoryId));
            }, self::revealing($categoryId));
        }
        $error = '';
        try {
            $move();
        } catch (InvalidArgumentException|RuntimeException $refused) {
            $error = $refused->getMessage();
        }
        $categories = $this->courses->categories();
        return $this->renderFragment('partials/admin/category-tree-response', [
            'category_tree' => $this->courses->categoryManagementTree($categories),
            'category_statistics' => CourseService::categoryStatistics($categories),
            'tree_error' => $error,
        ], $error === '' ? 200 : 422);
    }

    /** @return array<string,mixed> the category in the address, which must be able to hold subcategories */
    private function parent(): array
    {
        $parent = $this->courses->category($this->categoryId());
        if ((int) $parent['level'] >= 3) {
            throw $this->notFound('Course categories go three levels deep, so “' . (string) $parent['name'] . '” cannot hold subcategories.');
        }
        return $parent;
    }

    private function categoryId(): int
    {
        $categoryId = (int) $this->param('id');
        if ($categoryId < 1) {
            throw new InvalidArgumentException('The course category does not exist.');
        }
        return $categoryId;
    }

    /** The tree with this category's branch open and the page scrolled to it. */
    private static function revealing(int $categoryId): string
    {
        return self::INDEX . '?reveal=' . $categoryId . '#category-' . $categoryId;
    }

    /**
     * @param array<mixed> $values
     * @return list<int>
     */
    private static function ids(array $values): array
    {
        return array_values(array_unique(array_filter(array_map('intval', $values), static fn(int $id): bool => $id > 0)));
    }

    /**
     * The categories whose branches the page shows open, for the GET form behind the disclosure
     * buttons, so opening one branch without JavaScript keeps the others open.
     *
     * @param list<array<string,mixed>> $nodes
     * @return list<int>
     */
    private static function openIn(array $nodes): array
    {
        $open = [];
        foreach ($nodes as $node) {
            if ($node['open']) {
                $open[] = (int) $node['id'];
            }
            $open = [...$open, ...self::openIn($node['children'])];
        }
        return $open;
    }
