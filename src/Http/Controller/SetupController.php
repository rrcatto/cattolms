declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Setup\SetupChecklist;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class SetupController extends BaseController
{
    public function __construct(AuthService $auth, ThemeRenderer $view, RequestStack $requests, private readonly SetupChecklist $setup)
    {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/admin/setup', name: 'admin_setup', methods: ['GET'])]
    public function index(): Response
    {
        $user = $this->requirePermission('SYSTEM.SETTING.VIEW');
        return $this->render('admin-setup', [
            'title' => 'Setup',
            'active_nav' => 'admin',
            'steps' => $this->setup->steps(),
            'progress' => $this->setup->progress(),
            'can_manage' => $user->hasPermission('SYSTEM.SETTING.MANAGE'),
        ]);
    }

    #[Route('/admin/setup/{step}/mark', name: 'admin_setup_mark', requirements: ['step' => '[a-z-]+'], methods: ['POST'])]
    public function mark(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        $step = (string) $this->request()->attributes->get('step');
        $done = $this->posted('done') === 'yes';
        return $this->handle(function () use ($step, $done, $user): void {
            $this->setup->mark($step, $done, $user->id);
            $this->flash('success', $done ? 'Marked done.' : 'Marked not done.');
            $this->redirect('/admin/setup#setup-' . $step);
        }, '/admin/setup#setup-' . $step);
    }

    /** Loads the starter categories and tags from the catalogue file published with the code. */
    #[Route('/admin/setup/catalogue', name: 'admin_setup_catalogue', methods: ['POST'])]
    public function catalogue(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            $report = $this->setup->loadCatalogue($user->id);
            $this->flash('success', sprintf('Categories: %d added, %d already there. Tags: %d added, %d already there.',
                $report['categories_created'], $report['categories_kept'], $report['tags_created'], $report['tags_kept']));
            $this->redirect('/admin/setup#setup-catalogue');
        }, '/admin/setup#setup-catalogue');
    }
}
