final class CourseController extends BaseController
{
    public function __construct(
        Base $f3,
        AuthService $auth,
        ThemeRenderer $view,
        private readonly CourseService $courses,
        private readonly PlatformAdministrationService $platformAdministration,
        private readonly LearningService $learning
    ) {
        parent::__construct($f3, $auth, $view);
    }

    /**
     * Renders one page of the public course catalogue.
     *
     * This is the only paginated surface that uses bare `page` / `page_size` query parameters,
     * because it has a single principal dataset; Administration and Company routes carry
     * several lists at once and therefore use dataset-prefixed parameters.
     */
    /** The dataset name every catalogue request key is composed from. */
    private const DATASET = 'catalogue';

    public function catalogue(): void
    {
        $user = $this->currentUser();

        // The category comes from the path rather than a query parameter, because a category page is
        // a destination people link to and search engines index, not a filter state. An unknown or
        // deactivated slug browses the whole catalogue instead of erroring: a stale link should show
        // a reader courses, not a 404.
        $slug = trim((string) $this->f3->get('PARAMS.slug'));
        $category = $this->courses->browsableCategory($slug, $this->universe());

        // Tags arrive two ways and mean the same thing. A single tag has its own path because a tag
        // page is a destination people link to; several arrive in one query parameter, because a
        // combination someone assembled by clicking is a filter state rather than a destination.
        // Unknown or retired slugs are dropped from either, so a stale link still shows courses.
        $selectedTags = $this->courses->activeTagsBySlug($this->requestedTagSlugs());

        $filter = new CatalogueFilter(
            $category === null ? null : (int) $category['id'],
            array_map(static fn(array $tag): int => (int) $tag['id'], $selectedTags),
            trim((string) ($_GET[PlatformAdministrationService::searchParam(self::DATASET)] ?? ''))
        );
        $browse = $this->courses->browseContext($category, $filter, $this->universe(), 24, $selectedTags);
        $tag = count($selectedTags) === 1 ? $selectedTags[0] : null;

        // The path is the base only while it still describes the whole filter. Add a second tag and
        // the page is a combination rather than that tag's page, so it moves to the query string and
        // the canonical single-tag URL is left meaning exactly one tag.
        $base = '/courses';
        if ($category !== null) {
            $base = '/courses/category/' . (string) $category['slug'];
        } elseif ($tag !== null) {
            $base = '/courses/tag/' . (string) $tag['slug'];
        }

        $tagFilters = $category !== null || count($selectedTags) !== 1
            ? [self::TAGS_PARAM => implode(',', array_column($selectedTags, 'slug'))]
            : [];

        // Facet links are composed against the category base, never the tag path. A toggle from
        // /courses/tag/databases must be able to *remove* databases, and it cannot while the tag is
        // baked into the path - "clear tags" would link to the tag's own page and the tag would come
        // straight back. The tag path stays a canonical entry point; touching a facet moves the
        // reader to the query form, which is the only form that can express a combination anyway.
        $facetBase = $category === null ? '/courses' : '/courses/category/' . (string) $category['slug'];

        $pagination = Pagination::create($_GET['page'] ?? null, $_GET['page_size'] ?? null, $this->courses->catalogueCount($this->universe(), $filter));
        $courses = $this->courses->catalogue($this->universe(), $filter, $pagination->pageSize, $pagination->offset);
        $favouriteIds = [];
        $requestStatus = [];
        if ($user !== null) {
            foreach ($this->platformAdministration->favourites($user->id, $this->universe()) as $item) {
                $favouriteIds[(int) $item['id']] = true;
            }
            foreach ($this->platformAdministration->userRequests($user->id, $this->universe()) as $request) {
                $requestStatus[(int) $request['course_id']] = (string) $request['status'];
            }
        }
        foreach ($courses as &$course) {
            $course['is_favourite'] = isset($favouriteIds[(int) $course['id']]);
            $course['request_status'] = $requestStatus[(int) $course['id']] ?? '';
        }
        unset($course);
        $this->render('courses', [
            'title' => $this->catalogueTitle($category, $tag),
            'page_kicker' => 'Discover what to learn next',
            'courses' => $courses,
            'browse_category' => $category ?? [],
            'browse_tag' => $tag ?? [],
            'browse_trail' => $browse['trail'],
            'browse_children' => $browse['children'],
            'browse_tags' => $this->tagRail($browse['tags'], $selectedTags, $filter, $facetBase),
            'browse_selected_tags' => $selectedTags,
            'browse_clear_href' => $this->facetHref($facetBase, $filter->withoutTags()),
            'catalogue_search' => $filter->search,
            // Built by the one shared payload builder, not by hand. This screen used to assemble
            // its own array, so every control added to the shared pagination control rendered
            // everywhere except here - which is how a surface quietly ends up with a different
            // pagination from the rest of the platform. Only the two query-parameter names are
            // this route's own, because they are public URLs.
            'catalogue_pagination' => PlatformAdministrationService::paginationPayload(
                'catalogue',
                $pagination,
                $base,
                'Catalogue',
                [PlatformAdministrationService::searchParam(self::DATASET) => $filter->search] + $tagFilters,
                'page',
                'page_size'
            ),
        ] + $pagination->toArray());
    }

    /**
     * Every tag in the catalogue, sized by how much of it each one holds.
     *
     * A rail of twenty-four tags is a way to narrow what is already on screen; this is a way to find
     * out what the catalogue is about. They answer different questions, which is why both exist.
     *
     * A tag holding nothing is still listed, greyed rather than hidden. An operator reading this
     * page is being told what the vocabulary is, and a term nobody has used is exactly the thing
     * worth seeing.
     */
    public function tagIndex(): void
    {
        $tags = $this->courses->tagIndex($this->universe());

        $largest = 0;
        foreach ($tags as $tag) {
            $largest = max($largest, (int) $tag['course_count']);
        }
        foreach ($tags as &$tag) {
            // Five steps rather than a continuous scale. A cloud sized by raw proportion is
            // unreadable the moment one tag runs away with the catalogue, and a reader cannot tell
            // 14pt from 15pt anyway.
            $count = (int) $tag['course_count'];
            $tag['weight'] = $largest === 0 || $count === 0 ? 0 : (int) ceil($count / $largest * 5);
        }
        unset($tag);

        $this->render('course-tags', [
            'title' => 'Browse by tag',
            'page_kicker' => 'Every label in the catalogue',
            'tag_index' => $tags,
        ]);
    }

    /** The query parameter several tags travel on. */
    private const TAGS_PARAM = 'tags';

    /**
     * Every tag slug the request names, from the path and the query parameter together.
     *
     * @return list<string>
     */
    private function requestedTagSlugs(): array
    {
        $slugs = [trim((string) $this->f3->get('PARAMS.tag'))];
        foreach (explode(',', (string) ($_GET[self::TAGS_PARAM] ?? '')) as $slug) {
            $slugs[] = trim($slug);
        }

        return array_values(array_unique(array_filter($slugs, static fn(string $slug): bool => $slug !== '')));
    }

    /**
     * The URL a facet option points at: this page, with that option turned on or off.
     *
     * Composed here rather than in markup for the reason every pagination URL is - a link that
     * re-derives the page's own state is a link that will one day derive it differently.
     */
    private function facetHref(string $base, CatalogueFilter $filter, string $tagSlugs = ''): string
    {
        $query = array_filter([
            self::TAGS_PARAM => $tagSlugs,
            PlatformAdministrationService::searchParam(self::DATASET) => $filter->search,
        ], static fn(string $value): bool => $value !== '');

        return $query === [] ? $base : $base . '?' . http_build_query($query);
    }

    /**
     * The tag rail: every offered tag with its count, whether it is on, and the URL that toggles it.
     *
     * @param list<array<string,mixed>> $tags     the tags the rail offers
     * @param list<array<string,mixed>> $selected  the tags currently chosen, offered or not
     * @return list<array<string,mixed>>
     */
    private function tagRail(array $tags, array $selected, CatalogueFilter $filter, string $base): array
    {
        // Keyed from the offered tags *and* the chosen ones. A reader can arrive on a tag the rail
        // does not offer - a link, or a tag that has since fallen out of the popular set - and if
        // its slug were unknown here, every toggle would quietly drop it from the URL and widen the
        // filter the reader did not touch.
        $slugById = [];
        foreach ([...$tags, ...$selected] as $tag) {
            $slugById[(int) $tag['id']] = (string) $tag['slug'];
        }

        $rail = [];
        foreach ($tags as $tag) {
            $toggled = $filter->toggleTag((int) $tag['id']);
            $slugs = array_filter(
                array_map(static fn(int $id): string => $slugById[$id] ?? '', $toggled->tagIds),
                static fn(string $slug): bool => $slug !== ''
            );

            $rail[] = $tag + ['href' => $this->facetHref($base, $toggled, implode(',', $slugs))];
        }

        return $rail;
    }

    /**
     * @param array<string,mixed>|null $category
     * @param array<string,mixed>|null $tag
     */
    private function catalogueTitle(?array $category, ?array $tag): string
    {
        if ($category !== null) {
            return (string) $category['name'] . ' courses';
        }

        return $tag === null ? 'Course catalogue' : 'Courses tagged ' . (string) $tag['name'];
    }

    public function toggleFavourite(): void
    {
        $this->requireCsrf();
        $user = $this->requirePermission('CATALOGUE.COURSE.FAVOURITE');
        $courseId = max(1, (int) ($_POST['course_id'] ?? 0));
        $added = $this->platformAdministration->toggleFavourite($user->id, $courseId);
        $this->flash('success', $added ? 'The course was added to your favourites.' : 'The course was removed from your favourites.');
        $return = (string) ($_POST['return'] ?? '/courses');
        $this->redirect(str_starts_with($return, '/') ? $return : '/courses');
    }

    public function requestCourse(): void
    {
        $this->requireCsrf();
        $user = $this->requirePermission('CATALOGUE.COURSE.REQUEST');
        $courseId = max(1, (int) ($_POST['course_id'] ?? 0));
        $period = max(86400, (int) ($_POST['access_period_seconds'] ?? 31536000));
        $this->handle(function () use ($user, $courseId, $period): void {
            $this->platformAdministration->requestCourse($user->id, $courseId, $period, (string) ($_POST['note'] ?? ''));
            $this->flash('success', 'Your course request was sent to your company administrator.');
            $this->redirect('/account/library?tab=requests');
        }, '/courses');
    }

    public function detail(): void
    {
        $slug = (string) $this->f3->get('PARAMS.slug');
        try {
            $course = $this->courses->publicCourse($slug, $this->universe());
        } catch (InvalidArgumentException) {
            $course = null;
        }
        if ($course === null) {
            $this->f3->error(404, 'The course could not be found.');
        }
        $user = $this->currentUser();
        $enrolment = $user !== null
            ? $this->courses->enrolmentForUser($user->id, (int) $course['id'])
            : null;
        $this->render('course-detail', [
            'title' => (string) $course['title'],
            'course' => $course,
            'has_access' => $enrolment !== null,
            'enrolment_status' => is_array($enrolment) ? (string) $enrolment['status'] : '',
            'course_content_mode' => true,
        ]);
    }

    public function media(): void
    {
        $publicId = (string) $this->f3->get('PARAMS.public_id');
        $media = $this->courses->media($publicId);
        if ($media === null) {
            $this->f3->error(404, 'The course media file could not be found.');
        }

        $allowed = (bool) $media['is_public'] && (string) $media['course_status'] === 'published';
        $user = $this->currentUser();
        if (!$allowed && $user !== null) {
            $allowed = $this->courses->userCanAccessMedia($user->id, $media, $user->hasPermission('PLATFORM.DASHBOARD.VIEW'));
        }
        if (!$allowed) {
            $this->f3->error(403, 'You do not have access to this course media.');
        }

        $filename = str_replace(["\r", "\n", '"'], '', (string) $media['original_filename']);
        header('Content-Type: ' . (string) $media['mime_type']);
        header('Content-Length: ' . (string) filesize((string) $media['path']));
        header('Cache-Control: private, max-age=3600');
        header('Content-Disposition: ' . ((string) $media['media_role'] === 'download' ? 'attachment' : 'inline') . '; filename="' . $filename . '"');
        readfile((string) $media['path']);
        exit;
    }

    public function certificate(): void
    {
        $publicId = (string) $this->f3->get('PARAMS.public_id');
        $certificate = $this->learning->certificate($publicId);
        if ($certificate === null) {
            $this->f3->error(404, 'The certificate could not be found.');
        }
        $this->render('certificate', [
            'title' => 'Certificate verification',
            'certificate' => $certificate,
        ]);
    }
