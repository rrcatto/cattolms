    /**
     * Every tag slug the request names, from the path and the query parameter together.
     *
     * @return list<string>
     */
    private function requestedTagSlugs(): array
    {
        $slugs = [trim((string) $this->param('tag'))];
        foreach (explode(',', (string) ($_GET[self::TAGS_PARAM] ?? '')) as $slug) {
            $slugs[] = trim($slug);
        }

        return array_values(array_unique(array_filter($slugs, static fn(string $slug): bool => $slug !== '')));
    }

    /**
     * The URL a facet option points at: this page, with that option turned on or off.
     *
     * Composed here rather than in markup for the reason every pagination URL is - a link that
     * re-derives the page's own state is a link that will one day derive it differently.
     */
    private function facetHref(string $base, CatalogueFilter $filter, string $tagSlugs = ''): string
    {
        $query = array_filter([
            self::TAGS_PARAM => $tagSlugs,
            PlatformAdministrationService::searchParam(self::DATASET) => $filter->search,
        ], static fn(string $value): bool => $value !== '');

        return $query === [] ? $base : $base . '?' . http_build_query($query);
    }

    /**
     * The tag rail: every offered tag with its count, whether it is on, and the URL that toggles it.
     *
     * @param list<array<string,mixed>> $tags     the tags the rail offers
     * @param list<array<string,mixed>> $selected  the tags currently chosen, offered or not
     * @return list<array<string,mixed>>
     */
    private function tagRail(array $tags, array $selected, CatalogueFilter $filter, string $base): array
    {
        // Keyed from the offered tags *and* the chosen ones. A reader can arrive on a tag the rail
        // does not offer - a link, or a tag that has since fallen out of the popular set - and if
        // its slug were unknown here, every toggle would quietly drop it from the URL and widen the
        // filter the reader did not touch.
        $slugById = [];
        foreach ([...$tags, ...$selected] as $tag) {
            $slugById[(int) $tag['id']] = (string) $tag['slug'];
        }

        $rail = [];
        foreach ($tags as $tag) {
            $toggled = $filter->toggleTag((int) $tag['id']);
            $slugs = array_filter(
                array_map(static fn(int $id): string => $slugById[$id] ?? '', $toggled->tagIds),
                static fn(string $slug): bool => $slug !== ''
            );

            $rail[] = $tag + ['href' => $this->facetHref($base, $toggled, implode(',', $slugs))];
        }

        return $rail;
    }

