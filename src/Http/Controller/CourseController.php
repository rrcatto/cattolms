    /**
     * The catalogue's category accordions: every branch that holds a course, nested.
     *
     * They page on their own dataset's parameters, because the catalogue's own
     * grid is already paging on page and page_size on the same screen, and one page number cannot
     * mean two lists at once.
     *
     * @return list<array<string,mixed>>
     */
    /**
     * @param array<string,mixed> $preserved
     * @return list<array<string,mixed>>
     */
    private function categoryTree(string $base, array $preserved): array
    {
        $tree = $this->courses->categoryBrowser();
        $openSlug = trim((string) ($_GET['open'] ?? ''));

        $decorate = function (array $node) use (&$decorate, $openSlug, $base, $preserved): array {
            // Only the category named by `open` is rendered with its courses. Every other accordion
            // carries the address of its own contents and fetches them when it is opened, which is
            // what keeps this page a few tens of kilobytes: the seed catalogue's whole taxonomy
            // rendered eagerly came to three megabytes of inline cover artwork, most of it for
            // categories the reader never opened.
            $node['is_open'] = $openSlug !== '' && $openSlug === (string) $node['slug'];
            if ($node['is_open']) {
                $node += $this->categoryCourses((string) $node['slug'], (int) $node['id'], $base, $preserved);
            }
            $node['children'] = array_map($decorate, (array) $node['children']);

            // Every ancestor of the opened category is opened with it. A link to a category three
            // levels down otherwise arrived with its own accordion open inside two closed ones, so
            // the reader saw no change at all and the link looked broken.
            $node['has_open_descendant'] = false;
            foreach ($node['children'] as $child) {
                if ($child['is_open'] === true || $child['has_open_descendant'] === true) {
                    $node['has_open_descendant'] = true;
                    break;
                }
            }

            return $node;
        };

        return array_map($decorate, $tree);
    }


