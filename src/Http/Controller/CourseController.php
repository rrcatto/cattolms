    /**
     * A tag list sized for a cloud.
     *
     * One implementation, because the catalogue and the dedicated tag page draw the same control
     * and a second weighting would let the same tag be a different size on two screens.
     *
     * @param list<array<string,mixed>> $tags
     * @return list<array<string,mixed>>
     */
    private function weightedTags(array $tags): array
    {
        $largest = 0;
        foreach ($tags as $tag) {
            $largest = max($largest, (int) $tag['course_count']);
        }
        foreach ($tags as &$tag) {
            // Five steps rather than a continuous scale. A cloud sized by raw proportion is
            // unreadable the moment one tag runs away with the catalogue, and a reader cannot tell
            // 14pt from 15pt anyway.
            $count = (int) $tag['course_count'];
            $tag['weight'] = $largest === 0 || $count === 0 ? 0 : (int) ceil($count / $largest * 5);
        }
        unset($tag);

        return $tags;
    }

