declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Mailing\AutomaticEmails;
use CattoLearning\Mailing\MailingReports;
use CattoLearning\Mailing\MailingSettings;
use CattoLearning\Support\Duration;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class MailingSetupController extends BaseController
{
    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly AutomaticEmails $automatic,
        private readonly MailingReports $reports,
        private readonly MailingSettings $settings,
    ) {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/mailing/automatic', name: 'mailing_manage_automatic', methods: ['GET'])]
    public function automatic(): Response
    {
        $user = $this->requirePermission('PLATFORM.MAILING.VIEW');
        $rules = $this->settings->rules();

        return $this->render('mailing-automatic', [
            'title' => 'Automatic emails · Mailing',
            'active_nav' => 'mailing',
            'rows' => $this->automatic->rows($this->settings->digestSummary(), Duration::parse((string) $rules['sleeping_after'])->words()),
            'words' => $this->automatic->words(),
            'wait' => Duration::parse((string) $rules['sleeping_answer_within'])->words(),
            'placeholder' => \CattoLearning\Mailing\EmailBlocks::PLACEHOLDER,
            'can_manage' => $user->hasPermission('PLATFORM.MAILING.MANAGE'),
        ]);
    }

    #[Route('/mailing/automatic/{email}', name: 'mailing_manage_automatic_save', requirements: ['email' => 'updates|digest|sleeping'], methods: ['POST'])]
    public function saveAutomatic(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');
        $email = $this->param('email');

        return $this->handle(function () use ($user, $email): void {
            if (($_POST['reset'] ?? '') === '1') {
                $this->automatic->reset($email, $user->id);
                $this->flash('success', 'Its starting words are back.');
            } else {
                $this->automatic->save($email, $_POST, $user->id);
                $this->flash('success', 'Saved. The next ones sent use these words.');
            }
            $this->redirect('/mailing/automatic#' . $email);
        }, '/mailing/automatic#' . $email);
    }

    #[Route('/mailing/reports', name: 'mailing_manage_reports', methods: ['GET'])]
    public function reports(): Response
    {
        $this->requirePermission('PLATFORM.MAILING.VIEW');

        return $this->render('mailing-reports', ['title' => 'Reports · Mailing', 'active_nav' => 'mailing', 'report' => $this->reports->view($_GET)]);
    }
}
