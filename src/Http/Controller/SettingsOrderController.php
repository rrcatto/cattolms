Version: 1.1.3

Description:
Arranging the sections of Administration > Settings (owner, 2026-11-09; Configuration\SettingsOrder), for whoever may
change settings (SYSTEM.SETTING.MANAGE). A drag or a keyboard move from the page's script posts to /arrange with the
section it now goes before and the order the page showed, and is answered with the saved order (or the stored one and
why, when it was refused), which the script puts the sections in (settings_order_controller.js). A section's menu posts
to /move with top, up, down or bottom and comes back to the page at that section, which works without JavaScript; Reset
goes back to the standard order.

Changelog:
2026/11/09 SAST
