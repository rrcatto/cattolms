declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Configuration\SettingsOrder;
use CattoLearning\View\ThemeRenderer;
use InvalidArgumentException;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class SettingsOrderController extends BaseController
{
    private const KEY = '[a-z]+(?:-[a-z]+)*';

    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly SettingsOrder $order,
    ) {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/admin/settings/order/{key}/arrange', name: 'admin_settings_order_arrange', requirements: ['key' => self::KEY], methods: ['POST'])]
    public function arrange(string $key): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        $shown = array_values(array_map('strval', (array) ($_POST['order'] ?? [])));
        try {
            $order = $this->order->place($key, (string) ($_POST['before'] ?? ''), $shown, $user->id);
            return self::answer($order, '', 200);
        } catch (InvalidArgumentException $refused) {
            return self::answer($this->order->order(), $refused->getMessage(), 409);
        }
    }

    #[Route('/admin/settings/order/{key}/move', name: 'admin_settings_order_move', requirements: ['key' => self::KEY], methods: ['POST'])]
    public function move(string $key): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($key, $user): void {
            $this->order->move($key, (string) ($_POST['direction'] ?? ''), $user->id);
            $this->redirect('/admin/settings#settings-order-' . $key);
        }, '/admin/settings');
    }

    #[Route('/admin/settings/order/reset', name: 'admin_settings_order_reset', methods: ['POST'])]
    public function reset(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        return $this->handle(function () use ($user): void {
            $this->order->reset($user->id);
            $this->flash('success', 'The sections of Settings are back in their standard order.');
            $this->redirect('/admin/settings');
        }, '/admin/settings');
    }

    /**
     * The order, as the list the page's script reads: its id, the order and any refusal.
     *
     * @param list<string> $order
     */
    private static function answer(array $order, string $error, int $status): Response
    {
        $html = '<ol id="settings-sections" data-order="' . htmlspecialchars(implode(',', $order), ENT_QUOTES) . '" data-error="' . htmlspecialchars($error, ENT_QUOTES) . '"></ol>';
        return new Response($html, $status, ['Content-Type' => 'text/html; charset=utf-8', 'Cache-Control' => 'no-store']);
    }
}
