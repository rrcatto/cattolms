Date time: 2026/10/07 SAST

Version: 0.8.8.10

Description:
Administration → Courses → Certificate Designs: the list of designs (picture, name, the courses
that use it, when it was last edited), the default for new courses, and one form per design - its
look, logo, wording, signatory and small print - beside a preview that is the PDF the certificate
will be. A new design opens the same form. Save keeps a version a certificate can always be drawn
again from; nothing about versions is shown. Delete moves the design's courses to another design.

The editor can be opened from a course's certificate page; it then returns there (return_to, only a
course certificate page is accepted).

Changelog:
