use InvalidArgumentException;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class MailingTemplateController extends BaseController
{
    private const BASE = '/mailing/templates';

    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly MailingTemplates $templates,
        private readonly EmailRenderer $renderer,
        private readonly TemplateProof $proofs,
        private readonly CampaignRepository $campaigns,
    ) {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/mailing/templates', name: 'mailing_templates', methods: ['GET'])]
    public function index(): Response
    {
        $user = $this->requirePermission('PLATFORM.MAILING.VIEW');

        return $this->render('mailing-templates', ['title' => 'Templates · Mailing', 'active_nav' => 'mailing', 'templates' => $this->templates->all(),
            'samples' => self::samples(true), 'can_manage' => $user->hasPermission('PLATFORM.MAILING.MANAGE')]);
    }

    /**
     * The sample designs as pictures to choose from (owner, 2026-10-28), with a copy of the default for messages first
     * when a new template is being made. Each picture is drawn at its own address (sample()).
     *
     * @return list<array{value:string,label:string,image:string,note:string}>
     */
    private static function samples(bool $withDefault): array
    {
        $out = [];
        if ($withDefault) $out[] = ['value' => '', 'label' => 'A copy of the default for messages', 'image' => self::BASE . '/samples/default.svg', 'note' => 'The look your messages have now.'];
        foreach (TemplateDesign::SAMPLES as $key => $sample) {
            $out[] = ['value' => $key, 'label' => $sample['name'], 'image' => self::BASE . '/samples/' . $key . '.svg', 'note' => $sample['note']];
        }

        return $out;
    }

    /** A sample design drawn small, or the default for messages ("default"). */
    #[Route('/mailing/templates/samples/{key}.svg', name: 'mailing_template_sample_picture', requirements: ['key' => '[a-z]+'], methods: ['GET'])]
    public function samplePicture(): Response
    {
        $this->requirePermission('PLATFORM.MAILING.VIEW');
        $key = $this->param('key');
        $design = $key === 'default' ? (array) $this->templates->defaultFor('messages')['design'] : TemplateDesign::sample($key);
        if ($design === null) throw $this->notFound('There is no such sample design.');

        return new Response(TemplateDesign::thumbnail($design, $key === 'default' ? 'The default for messages' : TemplateDesign::SAMPLES[$key]['name']), 200,
            ['Content-Type' => 'image/svg+xml; charset=utf-8', 'Cache-Control' => 'private, max-age=300', 'Content-Security-Policy' => "default-src 'none'; style-src 'unsafe-inline'"]);
    }

    #[Route('/mailing/templates', name: 'mailing_template_create', methods: ['POST'])]
    public function create(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');

        return $this->handle(function () use ($user): void {
            $sample = (string) ($_POST['sample'] ?? '');
            $id = $this->templates->create((string) ($_POST['name'] ?? ''), $user->id, $sample);
            $this->flash('success', isset(TemplateDesign::SAMPLES[$sample]) ? 'The template was made from the ' . TemplateDesign::SAMPLES[$sample]['name'] . ' sample. Change anything below.' : 'The template was made from the default for messages. Change it below.');
            $this->redirect(self::BASE . '/' . $id);
        }, self::BASE . '#new');
    }

    #[Route('/mailing/templates/{id}', name: 'mailing_template', requirements: ['id' => '\d+'], methods: ['GET'])]
    public function show(): Response
    {
        $user = $this->requirePermission('PLATFORM.MAILING.VIEW');
        $template = $this->found();
        $sample = ($_GET['sample'] ?? '') === 'digest' ? 'digest' : 'message';

        return $this->render('mailing-template', ['title' => $template['name'] . ' · Templates', 'active_nav' => 'mailing', 'template' => $template,
            'sample' => $sample, 'phone' => ($_GET['width'] ?? '') === 'phone', 'can_manage' => $user->hasPermission('PLATFORM.MAILING.MANAGE'), 'samples' => self::samples(false),
            'fonts' => array_map(static fn(array $font): string => $font[0], TemplateDesign::FONTS), 'colours' => TemplateDesign::COLOURS,
            'logo_sizes' => TemplateDesign::LOGO_SIZES, 'alignments' => TemplateDesign::ALIGNMENTS, 'text_sizes' => TemplateDesign::TEXT_SIZES, 'widths' => TemplateDesign::WIDTHS,
            'corners' => TemplateDesign::CORNERS, 'spacings' => TemplateDesign::SPACINGS, 'button_shapes' => TemplateDesign::BUTTON_SHAPES, 'social' => TemplateDesign::SOCIAL,
            'placeholders' => MailingTemplates::PLACEHOLDERS, 'proof_to' => $this->primaryEmail($user->id),
            'logo_url' => $this->pictureUrl((string) $template['design']['logo']), 'header_picture_url' => $this->pictureUrl((string) $template['design']['header_picture'])]);
    }

    #[Route('/mailing/templates/{id}', name: 'mailing_template_save', requirements: ['id' => '\d+'], methods: ['POST'])]
    public function save(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');
        $id = (int) $this->param('id');

        return $this->handle(function () use ($id, $user): void {
            $this->templates->save($id, $_POST, $user->id);
            $this->flash('success', 'The template was saved. Messages and digests drawn in it look like this from now on.');
            $this->redirect(self::BASE . '/' . $id);
        }, self::BASE . '/' . $id);
    }

    /** The saved template drawn with a sample, or the form's unsaved values when it posts them ("Update the preview"). */
    #[Route('/mailing/templates/{id}/preview', name: 'mailing_template_preview', requirements: ['id' => '\d+'], methods: ['GET', 'POST'])]
    public function preview(): Response
    {
        $user = $this->requirePermission('PLATFORM.MAILING.VIEW');
        $template = $this->found();
        $sample = (($_POST['sample'] ?? $_GET['sample'] ?? '') === 'digest') ? 'digest' : 'message';
        if ($this->request()->isMethod('POST')) {
            $this->requireCsrf();
            $template = $this->unsaved($template);
        }
        $copy = $this->renderer->sample($template, $sample, $this->firstName($user->id));

        // Sandboxed, as a message's preview is: an HTML template's own markup never runs with Mailing's rights.
        return new Response($copy['html'], 200, ['Content-Type' => 'text/html; charset=utf-8', 'X-Frame-Options' => 'SAMEORIGIN', 'Cache-Control' => 'no-store',
            'Content-Security-Policy' => "default-src 'none'; img-src * data:; style-src 'unsafe-inline' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; sandbox allow-popups allow-popups-to-escape-sandbox"]);
    }

    #[Route('/mailing/templates/{id}/picture', name: 'mailing_template_picture', requirements: ['id' => '\d+'], methods: ['POST'])]
    public function picture(): Response
    {
        return $this->act(function (int $id, int $userId): string {
            $slot = (string) ($_POST['slot'] ?? '');
            if (($_POST['remove'] ?? '') === '1') {
                $this->templates->removePicture($id, $slot, $userId);

                return $slot === 'logo' ? 'The logo was taken off. The site\'s name stands in its place.' : 'The header picture was taken off.';
            }
            $upload = $this->request()->files->get('picture');
            if ($upload === null || !$upload->isValid()) throw new InvalidArgumentException('No picture was received. Choose a PNG, JPEG or GIF file and try again.');
            $this->templates->setPicture($id, $slot, (string) file_get_contents((string) $upload->getPathname()), $userId);

            return $slot === 'logo' ? 'The logo was saved.' : 'The header picture was saved.';
        }, '#pictures');
    }

    #[Route('/mailing/templates/{id}/proof', name: 'mailing_template_proof', requirements: ['id' => '\d+'], methods: ['POST'])]
    public function proof(): Response
    {
        return $this->act(function (int $id, int $userId): string {
            $email = (string) ($_POST['email'] ?? '');
            $this->proofs->send($this->templates->get($id), (string) ($_POST['sample'] ?? 'message'), $email, $this->firstName($userId), $userId);

            return 'A proof was sent to ' . trim($email) . '. Its links go straight to their pages and nothing is recorded.';
        }, '#proof');
    }

    #[Route('/mailing/templates/{id}/{action}', name: 'mailing_template_action', requirements: ['id' => '\d+', 'action' => 'copy|default|delete|sample'], methods: ['POST'])]
    public function action(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');
        $id = (int) $this->param('id');
        $action = (string) $this->param('action');

        return $this->handle(function () use ($id, $action, $user): void {
            if ($action === 'copy') {
                $copy = $this->templates->duplicate($id, $user->id);
                $this->flash('success', 'A copy was made. Change it below.');
                $this->redirect(self::BASE . '/' . $copy);
            }
            if ($action === 'sample') {
                $this->templates->applySample($id, (string) ($_POST['sample'] ?? ''), $user->id);
                $this->flash('success', 'It has the sample\'s look now. Its logo, header picture, footer words and social links stayed as they were.');
                $this->redirect(self::BASE . '/' . $id . '#design');
            }
            if ($action === 'default') {
                $for = (string) ($_POST['for'] ?? '');
                $this->templates->makeDefault($id, $for, $user->id);
                $this->flash('success', $for === 'digest' ? 'It is now the default for the digest.' : 'It is now the default for messages.');
                $this->redirect(self::BASE);
            }
            $this->templates->delete($id, $user->id);
            $this->flash('success', 'The template was deleted. Messages that chose it now use the default for messages.');
            $this->redirect(self::BASE);
        }, self::BASE);
    }

    /** @return array<string,mixed> */
    private function found(): array
    {
        try {
            return $this->templates->get((int) $this->param('id'));
        } catch (InvalidArgumentException) {
            throw $this->notFound('That template could not be found.');
        }
    }

    /**
     * The template as the form would save it, for the preview; a value the form could not have sent leaves what was saved.
     *
     * @param array<string,mixed> $template
     * @return array<string,mixed>
     */
    private function unsaved(array $template): array
    {
        $mode = in_array($_POST['mode'] ?? '', ['design', 'html'], true) ? (string) $_POST['mode'] : $template['mode'];
        $posted = is_array($_POST['design'] ?? null) ? $_POST['design'] : [];
        // A colour still being typed keeps its saved value in the preview, so the rest of the unsaved design still shows.
        foreach ((array) ($posted['colours'] ?? []) as $key => $colour) {
            if (preg_match('/^#[0-9a-f]{6}$/i', trim((string) $colour)) !== 1) $posted['colours'][$key] = (string) ($template['design']['colours'][$key] ?? '');
        }
        try {
            $design = TemplateDesign::checked($posted, $template['design']);
        } catch (InvalidArgumentException) {
            $design = $template['design'];
        }
        $html = str_replace("\r\n", "\n", (string) ($_POST['html'] ?? $template['html']));

        return ['mode' => $mode, 'design' => $design, 'html' => $mode === 'html' && preg_match('/<script\b/i', $html) !== 1 ? $html : $template['html'],
            'text_mode' => $template['text_mode'], 'text_part' => $template['text_part']] + $template;
    }

    /** @param callable(int,int):string $change */
    private function act(callable $change, string $anchor): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');
        $id = (int) $this->param('id');

        return $this->handle(function () use ($change, $id, $user, $anchor): void {
            $this->flash('success', $change($id, $user->id));
            $this->redirect(self::BASE . '/' . $id . $anchor);
        }, self::BASE . '/' . $id . $anchor);
    }

    private function pictureUrl(string $sha): string
    {
        return $sha === '' ? '' : $this->renderer->linkBase() . '/m/i/' . $sha . '.png';
    }

    private function firstName(int $userId): string
    {
        return $this->campaigns->firstName($userId);
    }

    private function primaryEmail(int $userId): string
    {
        $user = $this->currentUser();

        return $user === null ? '' : $user->primaryEmail;
    }
}
