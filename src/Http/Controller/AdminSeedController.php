ADMIN-only SYSTEM.* namespace:

  SYSTEM.SEED.VIEW      see the section and its history
  SYSTEM.SEED.MANAGE    generate and clean up

SEED_ADMIN is a platform-style administrator *inside* seed business data and receives no SYSTEM.*
authority at all, so it can never reach this screen. That is enforced by the permission check
