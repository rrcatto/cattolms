declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Application\AdministrationSectionRegistry;
use CattoLearning\Auth\AuthService;
use CattoLearning\Seed\SeedDatabaseService;
use CattoLearning\View\ThemeRenderer;
use Base;

final class AdminSeedController extends BaseController
{
    public function __construct(
        Base $f3,
        AuthService $auth,
        ThemeRenderer $view,
        private readonly SeedDatabaseService $seeds,
        private readonly AdministrationSectionRegistry $adminSections
    ) {
        parent::__construct($f3, $auth, $view);
    }

    /** The standalone Seed Database section. */
    public function index(): void
    {
        $this->requirePermission('SYSTEM.SEED.VIEW');

        $this->render('admin-section', $this->sectionData() + [
            'title' => 'Seed Database · Administration',
            'page_title' => 'Seed Database',
            'page_kicker' => 'Platform administration',
            'admin_section' => $this->adminSections->get('seed'),
            'admin_layout' => 'section',
        ]);
    }

    /**
     * Generates one seed set.
     *
     * Generation can take a while at volume, so the time limit is lifted for this request only.
     * It is a deliberate, ADMIN-only maintenance action on a disposable database, not something
     * an ordinary request path can reach.
     */
    public function generate(): void
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SEED.MANAGE');

        $this->handle(function () use ($user): void {
            set_time_limit(0);
            $result = $this->seeds->generate(
                $_POST['volume'] ?? null,
                (string) ($_POST['description'] ?? ''),
                $user->id
            );

            $this->flash('success', sprintf(
                'Generated %s seed records in %.1f seconds. Set token %s.',
                number_format($result['records']),
                $result['seconds'],
                $result['token']
            ));
            $this->redirect('/admin/seed');
        }, '/admin/seed');
    }

    /**
     * Shows what a cleanup would remove before it happens.
     *
     * Seed tokens are provenance rather than tenancy, so removing one set can take SEED rows
     * belonging to other sets with it. The operator sees that collateral before confirming.
     */
    public function cleanupPreview(): void
    {
        $this->requirePermission('SYSTEM.SEED.MANAGE');
        $token = (string) $this->f3->get('PARAMS.token');

        $this->handle(function () use ($token): void {
            $preview = $this->seeds->cleanupPreview($token);

            $this->render('admin-section', $this->sectionData() + [
                'title' => 'Confirm seed cleanup · Administration',
                'page_title' => 'Seed Database',
                'page_kicker' => 'Platform administration',
                'admin_section' => $this->adminSections->get('seed'),
                'admin_layout' => 'section',
                'seed_cleanup_preview' => $preview,
            ]);
        }, '/admin/seed');
    }

    public function cleanup(): void
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SEED.MANAGE');
        $token = (string) $this->f3->get('PARAMS.token');

        $this->handle(function () use ($token, $user): void {
            set_time_limit(0);
            $result = $this->seeds->cleanup($token, $user->id);

            $this->flash('success', sprintf(
                'Removed %s seed records.%s',
                number_format($result['records']),
                $result['collateral'] === []
                    ? ''
                    : ' ' . count($result['collateral']) . ' other seed set(s) were affected.'
            ));
            $this->redirect('/admin/seed');
        }, '/admin/seed');
    }

    /**
     * View data for the section, shared by the listing and the cleanup confirmation.
     *
     * @return array<string,mixed>
     */
    private function sectionData(): array
    {
        return [
            'seed_sets' => $this->seeds->sets(),
            'seed_total_records' => $this->seeds->totalSeedRecords(),
            'seed_volume' => $this->seeds->volumeBounds(),
            'seed_cleanup_preview' => null,
        ];
    }
}
