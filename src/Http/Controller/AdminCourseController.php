            $this->flash('success', 'The course was saved.');
            $this->redirect(rtrim($list, '?&') . '#' . CourseAddress::anchor($this->courseCode($courseId)));
        }
        return $this->courseRowFragment($user, $courseId, false, $view, !empty($_POST['arrange']), $list, saved: true);
