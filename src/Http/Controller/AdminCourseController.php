            $replaceable = array_values(array_filter(
                $this->app->courses->adminCourses(),
                fn(array $course): bool => !$this->app->portability->hasStartedLearners((int) $course['id'])
                    && ($user->hasRole('platform_admin') || (int) ($course['owner_user_id'] ?? 0) === $user->id)
            ));
            $this->render('admin-course-import-preview', [
                'title' => 'Review course import',
                'analysis' => $analysis,
                'categories' => $this->app->courses->categories(true),
                'replaceable_courses' => $replaceable,
            ]);
        }, '/admin/courses/import');
    }

    public function commitImport(): void
    {
        $this->requireCsrf();
        $user = $this->requireCourseAuthor();
        $key = trim((string) ($_POST['import_key'] ?? ''));
        $categoryId = (int) ($_POST['category_id'] ?? 0);
        $replaceCourseId = (int) ($_POST['replace_course_id'] ?? 0);
        $this->handle(function () use ($user, $key, $categoryId, $replaceCourseId): void {
            if ($replaceCourseId > 0) {
                $this->requireManagedCourse($replaceCourseId);
            }
            $courseId = $this->app->portability->commitImport($key, $categoryId, $user->id, $replaceCourseId > 0 ? $replaceCourseId : null);
            $this->flash('success', 'The course was imported into PostgreSQL as a draft.');
            $this->redirect('/admin/courses/' . $courseId);
        }, '/admin/courses/import/preview?key=' . rawurlencode($key));
    }

    public function grantSelf(): void
    {
        $this->requireCsrf();
        $user = $this->requireCourseAuthor();
        $courseId = $this->courseId();
        $this->requireManagedCourse($courseId);
        $this->handle(function () use ($user, $courseId): void {
            $course = $this->app->courses->adminCourse($courseId);
            $this->app->courses->grantForTesting($courseId, $user->id, $user->id);
