    /** @return array<string,mixed> */
    private function requireManagedCourse(int $courseId): array
    {
        $user = $this->requireCourseAuthor();
        $course = $this->app->courses->adminCourse($courseId);
        if (!$user->hasRole('platform_admin') && !$this->app->courses->userCanManageCourse($courseId, $user->id)) {
            $this->f3->error(403, 'You do not have permission to manage this course.');
        }
        return $course;
    }

