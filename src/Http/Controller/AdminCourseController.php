    #[Route('/admin/courses/import/preview', name: 'admin_course_preview_import', methods: ['GET'])]
    public function previewImport(): Response
    {
        $this->requirePermission('COURSE.IMPORT');
        $key = trim((string) ($_GET['key'] ?? ''));
        return $this->handle(function () use ($key): Response {
            $analysis = $this->portability->reanalyseImport($key);
            foreach ($analysis['modules'] ?? [] as &$module) {
                $blocks = (array) ($module['content_blocks'] ?? $module['blocks'] ?? []);
                $module['block_count'] = count($blocks);
                $module['question_count'] = isset($module['assessment']) && is_array($module['assessment'])
                    ? count((array) ($module['assessment']['questions'] ?? []))
                    : 0;
            }
            unset($module);
            $analysis['display_module_count'] = (int) ($analysis['statistics']['module_count'] ?? count((array) ($analysis['modules'] ?? [])));

            $moduleAssessmentCount = 0;
            $moduleQuestionCount = 0;
            foreach ((array) ($analysis['modules'] ?? []) as $module) {
                if (!is_array($module) || !is_array($module['assessment'] ?? null)) {
                    continue;
                }
                $moduleAssessmentCount++;
                $moduleQuestionCount += count((array) ($module['assessment']['questions'] ?? []));
            }

            $diagnostics = (array) ($analysis['diagnostic_assessments'] ?? []);
            $diagnosticQuestionCount = 0;
            foreach ($diagnostics as $diagnostic) {
                if (is_array($diagnostic)) {
                    $diagnosticQuestionCount += count((array) ($diagnostic['questions'] ?? []));
                }
            }

            $finalAssessment = is_array($analysis['final_assessment'] ?? null)
                ? $analysis['final_assessment']
                : null;
            $finalQuestionCount = $finalAssessment === null
                ? 0
                : count((array) ($finalAssessment['questions'] ?? []));

            $analysis['display_module_assessment_count'] = $moduleAssessmentCount;
            $analysis['display_module_question_count'] = $moduleQuestionCount;
            $analysis['display_diagnostic_count'] = count($diagnostics);
            $analysis['display_diagnostic_question_count'] = $diagnosticQuestionCount;
            $analysis['display_final_assessment_count'] = $finalAssessment === null ? 0 : 1;
            $analysis['display_final_question_count'] = $finalQuestionCount;
            $analysis['display_question_count'] = (int) ($analysis['statistics']['question_count'] ?? ($moduleQuestionCount + $diagnosticQuestionCount + $finalQuestionCount));
            $analysis['display_format'] = strtoupper((string) ($analysis['format'] ?? 'HTML'));
            $analysis['display_presentation_css_bytes'] = strlen((string) ($analysis['course']['presentation_css'] ?? ''));
            $parser = is_array($analysis['parser_diagnostics'] ?? null) ? $analysis['parser_diagnostics'] : [];
            $analysis['parser_compatibility_count'] = (int) ($parser['compatibility_notice_count'] ?? 0);
            $analysis['parser_structural_count'] = (int) ($parser['structural_warning_count'] ?? 0);
            $analysis['parser_messages'] = (array) ($parser['messages'] ?? []);
            $user = $this->requireUser();
            // The replaceable-course picker filters in PHP on hasStartedLearners() and
            // ownership, so it cannot be paginated without moving both rules into SQL. It is
            // bounded here at the largest approved page size rather than left unbounded; the
            // import screen is outside the v0.5.7.6 pagination scope and this surface is
            // recorded as a follow-up candidate for the entity-lookup pattern.
            $replaceable = array_values(array_filter(
                $this->courses->adminCourses(null, true, max(Pagination::PAGE_SIZES), 0),
                fn(array $course): bool => $user->hasPermission('PLATFORM.DASHBOARD.VIEW') || (int) ($course['owner_user_id'] ?? 0) === $user->id
            ));
            return $this->render('admin-course-import-preview', [
                'title' => 'Review course import',
                'analysis' => $analysis,
                'categories' => $this->courses->categories(true),
                'replaceable_courses' => $replaceable,
            ]);
        }, '/admin/courses/import');
    }


