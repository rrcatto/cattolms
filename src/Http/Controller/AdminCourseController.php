        return $this->courseIdFromAddress($this->courses);
    }

    private function priceVariantId(): int
    {
        $id = (int) $this->param('price_variant_id');
        if ($id < 1) {
            throw new InvalidArgumentException('Invalid price variant identifier.');
        }
        return $id;
    }

