    #[Route('/admin/courses/{id}/export', name: 'admin_course_export', requirements: ['id' => '\\d+'], methods: ['GET'])]
    public function export(): Response
    {
        $this->requirePermission('COURSE.EXPORT');
        $courseId = $this->courseId();
        $course = $this->requireManagedCourse($courseId);
        // Serialise before any header is sent. Decision D5 makes the service refuse a seed course,
        // and a refusal after the download headers were emitted would arrive as an error page
        // wearing a JSON content type and an attachment filename.
        try {
            $payload = $this->portability->exportCourseJson($courseId);
        } catch (InvalidArgumentException $exception) {
            $this->flash('error', $exception->getMessage());
            // redirect() terminates the request, so there is nothing after this.
            $this->redirect('/admin/courses/' . $courseId);
        }
        $filename = (string) $course['slug'] . '.course.json';
        header('Content-Type: application/json; charset=UTF-8');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        echo $payload;
        exit;
    }


