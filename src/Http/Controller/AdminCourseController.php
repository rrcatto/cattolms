            $this->redirect('/learn/' . rawurlencode((string) $course['slug']));
        }, '/admin/courses/' . $courseId);
    }

    public function grant(): void
    {
        $this->requireCsrf();
        $user = $this->requireRole('platform_admin');
        $courseId = $this->courseId();
        $this->handle(function () use ($user, $courseId): void {
            $this->app->courses->grantByEmail(
                $courseId,
                (string) ($_POST['email'] ?? ''),
                max(1, (int) ($_POST['access_days'] ?? 365)),
                $user->id
