declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Commerce\Domain\RefundRule;
use CattoLearning\Commerce\Policy\CommercePolicy;
use CattoLearning\Legal\LegalDocuments;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class LegalController extends BaseController
{
    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly LegalDocuments $legal,
        private readonly CommercePolicy $policy
    ) {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/terms', name: 'legal_terms', methods: ['GET'])]
    public function terms(): Response
    {
        return $this->document(LegalDocuments::TERMS);
    }

    #[Route('/refunds', name: 'legal_refunds', methods: ['GET'])]
    public function refunds(): Response
    {
        return $this->document(LegalDocuments::REFUNDS);
    }

    #[Route('/privacy', name: 'legal_privacy', methods: ['GET'])]
    public function privacy(): Response
    {
        return $this->document(LegalDocuments::PRIVACY);
    }

    private function document(string $key): Response
    {
        $document = $this->legal->document($key);

        return $this->render($key, [
            'title' => $document['title'],
            'legal' => $document,
            'legal_documents' => $this->legal->all(),
            'supplier' => $this->legal->supplier(),
            'refund_window_days' => RefundRule::WINDOW_DAYS,
            'activation_deadline_days' => $this->policy->activationDeadlineDays,
            'payment_due_days' => $this->policy->paymentDueDays,
        ]);
    }
}
