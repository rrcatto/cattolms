declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Auth\CurrentUser;
use CattoLearning\Course\CataloguePackage;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Exception\AccessDeniedHttpException;
use Symfony\Component\Routing\Attribute\Route;

final class AdminCatalogueController extends BaseController
{
    private const PAGE = '/admin/courses/catalogue';
    // The last import's report, shown once on the result page.
    private const REPORT = 'catalogue_import_report';

    public function __construct(AuthService $auth, ThemeRenderer $view, RequestStack $requests, private readonly CataloguePackage $package)
    {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/admin/courses/catalogue', name: 'admin_course_catalogue', methods: ['GET'])]
    public function index(): Response
    {
        $user = $this->requireAny();
        // The courses to export are ticked (owner, 2026-10-23: "first select the courses I wish to export"): none at
        // first. Without JavaScript, Tick every course, Tick the published courses and Clear the ticks submit the form
        // here with tick=all, published or none; with it they tick in place.
        $tick = (string) ($_GET['tick'] ?? '');
        $choices = $user->hasPermission('COURSE.EXPORT') ? $this->package->exportChoices() : [];
        foreach ($choices as &$choice) $choice['ticked'] = $tick === 'all' || ($tick === 'published' && $choice['status'] === 'published');
        unset($choice);
        return $this->render('admin-course-catalogue', [
            'title' => 'Import & Export Catalogue',
            'active_nav' => 'admin',
            'export_choices' => $choices,
            'can_export' => $user->hasPermission('COURSE.EXPORT'),
            'can_import' => self::mayImport($user),
            'upload_limit_mb' => intdiv(min(CataloguePackage::MAXIMUM_UPLOAD_BYTES, self::iniBytes((string) ini_get('upload_max_filesize')), self::iniBytes((string) ini_get('post_max_size'))), 1024 * 1024),
        ]);
    }

    /**
     * The ticked courses' catalogue package, or (what=categories) their categories and tags as a catalogue file, every
     * category and tag when no course is ticked.
     */
    #[Route('/admin/courses/catalogue/export', name: 'admin_course_catalogue_export', methods: ['GET'])]
    public function export(): Response
    {
        $user = $this->requirePermission('COURSE.EXPORT');
        $courseIds = array_values(array_unique(array_filter(array_map('intval', (array) ($_GET['courses'] ?? [])), static fn(int $id): bool => $id > 0)));
        if (($_GET['what'] ?? '') === 'categories') {
            $json = $this->package->exportCategoriesAndTags($user->id, $courseIds);
            header('Content-Type: application/json; charset=UTF-8');
            header('Content-Disposition: attachment; filename="catalogue.json"');
            echo $json;
            exit;
        }
        // Made before any header is sent, so a refusal is a page with its message, not a broken download.
        $path = '';
        try {
            $path = $this->package->export($user->id, $courseIds);
        } catch (\RuntimeException|\InvalidArgumentException $failed) {
            $this->flash('danger', $failed->getMessage());
            $this->redirect(self::PAGE . '#export-courses');
        }
        header('Content-Type: application/zip');
        header('Content-Disposition: attachment; filename="catalogue-' . date('Y-m-d') . '.zip"');
        header('Content-Length: ' . (string) filesize($path));
        readfile($path);
        @unlink($path);
        exit;
    }

    #[Route('/admin/courses/catalogue/import', name: 'admin_course_catalogue_stage', methods: ['POST'])]
    public function stage(): Response
    {
        $this->requireCsrf();
        $user = $this->requireImporter();
        return $this->handle(function () use ($user): void {
            $key = $this->package->stage((array) ($_FILES['catalogue'] ?? []), $user->id);
            $this->redirect(self::PAGE . '/review?key=' . $key);
        }, self::PAGE);
    }

    #[Route('/admin/courses/catalogue/review', name: 'admin_course_catalogue_review', methods: ['GET'])]
    public function review(): Response
    {
        $user = $this->requireImporter();
        $key = trim((string) ($_GET['key'] ?? ''));
        return $this->handle(fn(): Response => $this->render('admin-course-catalogue-review', [
            'title' => 'Review catalogue import',
            'active_nav' => 'admin',
            'plan' => $this->package->plan($key),
            'can_price' => $user->hasPermission('COURSE.PRICING.MANAGE'),
            'can_publish' => $user->hasPermission('COURSE.PUBLISH'),
        ]), self::PAGE);
    }

    #[Route('/admin/courses/catalogue/review', name: 'admin_course_catalogue_apply', methods: ['POST'])]
    public function apply(): Response
    {
        $this->requireCsrf();
        $user = $this->requireImporter();
        $key = $this->posted('key');
        return $this->handle(function () use ($user, $key): void {
            $report = $this->package->apply($key, [
                'courses' => array_values(array_map('strval', (array) ($_POST['courses'] ?? []))),
                'replace' => array_values(array_map('strval', (array) ($_POST['replace'] ?? []))),
                'prices' => $user->hasPermission('COURSE.PRICING.MANAGE') && $this->posted('prices') === '1',
                'publish' => $user->hasPermission('COURSE.PUBLISH') && $this->posted('publish') === '1',
            ], $user->id);
            $_SESSION[self::REPORT] = $report;
            $this->redirect(self::PAGE . '/result');
        }, self::PAGE . '/review?key=' . rawurlencode($key));
    }

    #[Route('/admin/courses/catalogue/cancel', name: 'admin_course_catalogue_cancel', methods: ['POST'])]
    public function cancel(): Response
    {
        $this->requireCsrf();
        $this->requireImporter();
        $key = $this->posted('key');
        return $this->handle(function () use ($key): void {
            $this->package->discard($key);
            $this->flash('info', 'The import was cancelled. Nothing was changed.');
            $this->redirect(self::PAGE);
        }, self::PAGE);
    }

    #[Route('/admin/courses/catalogue/result', name: 'admin_course_catalogue_result', methods: ['GET'])]
    public function result(): Response
    {
        $this->requireImporter();
        $report = $_SESSION[self::REPORT] ?? null;
        if (!is_array($report)) $this->redirect(self::PAGE);
        return $this->render('admin-course-catalogue-result', [
            'title' => 'Catalogue imported',
            'active_nav' => 'admin',
            'report' => $report,
        ]);
    }

    private function requireAny(): CurrentUser
    {
        $user = $this->requireUser();
        if (!$user->hasPermission('COURSE.EXPORT') && !self::mayImport($user)) {
            throw new AccessDeniedHttpException('You do not have permission to access this function.');
        }
        return $user;
    }

    private function requireImporter(): CurrentUser
    {
        $user = $this->requireUser();
        if (!self::mayImport($user)) {
            throw new AccessDeniedHttpException('Importing a catalogue makes categories and tags: it needs course import, category and tag management.');
        }
        return $user;
    }

    private static function mayImport(CurrentUser $user): bool
    {
        return $user->hasPermission('COURSE.IMPORT') && $user->hasPermission('COURSE.CATEGORY.MANAGE') && $user->hasPermission('COURSE.TAG.MANAGE');
    }

    /** "64M" in bytes. */
    private static function iniBytes(string $value): int
    {
        $value = trim($value);
        $number = (int) $value;
        return match (strtoupper(substr($value, -1))) {
            'G' => $number * 1024 * 1024 * 1024,
            'M' => $number * 1024 * 1024,
            'K' => $number * 1024,
            default => $number > 0 ? $number : PHP_INT_MAX,
        };
    }
}
