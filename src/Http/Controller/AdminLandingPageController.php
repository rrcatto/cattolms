            $this->landing->arrange((int) $course['id'], $sectionId, (int) $index, $shown, $user->id);
        });
    }

    /**
     * Runs one move. The list's script asks with HX-Request and gets the saved list back, or the
     * stored one and a 422 with the reason; a plain form post redirects.
     *
     * @param array<string,mixed> $course
     */
    private function moved(CurrentUser $user, array $course, int $sectionId, callable $move): Response
    {
        if (!$this->isHtmxRequest()) {
            return $this->handle(function () use ($move, $course, $sectionId): void {
                $move();
                $this->flash('success', 'The section was moved.');
                $this->redirect(self::home($course) . '#landing-section-' . $sectionId);
            }, self::home($course) . '#landing-sections');
        }
        $error = '';
        try {
            $move();
        } catch (InvalidArgumentException|RuntimeException $refused) {
            $error = $refused->getMessage();
        }
        return $this->renderFragment('partials/admin/landing-section-list', ['list_error' => $error] + $this->overview($user, $course), $error === '' ? 200 : 422);
    }

    /**
     * @param array<string,mixed> $course
     * @param array<string,mixed> $extra
     * @return array<string,mixed>
     */
    private function overview(CurrentUser $user, array $course, array $extra = []): array
    {
        $page = $this->landing->page((int) $course['id']);
        $data = [
            'title' => 'Landing page · ' . (string) $course['title'],
            'course' => ['id' => (int) $course['id'], 'title' => (string) $course['title'], 'slug' => (string) $course['slug'], 'status' => (string) $course['status']],
            'landing_page' => null,
            'can_publish' => $user->hasPermission('COURSE.PUBLISH'),
            'settings_error' => '',
            'list_error' => '',
            'csrf' => \CattoLearning\Support\Csrf::token(),
        ];
        if ($page === null) {
            return $extra + $data;
        }
        $rows = [];
        $others = array_values(array_filter($page['sections'], static fn(array $s): bool => $s['type'] !== LandingSectionType::Hero));
        $present = [];
        foreach ($page['sections'] as $section) {
            $present[$section['type']->value] = true;
            $index = array_search($section, $others, true);
            $rows[] = [
                'id' => (int) $section['id'],
                'type' => $section['type']->value,
                'label' => $section['type']->label(),
                'summary' => $section['invalid'] !== '' ? 'Its saved copy no longer passes: ' . $section['invalid'] : $section['type']->summary($section['data']),
                'enabled' => $section['enabled'],
                'needs_content' => $section['invalid'] !== '' || $section['type']->missing($section['data']) !== [],
                'is_hero' => $section['type'] === LandingSectionType::Hero,
                'is_first' => $index === 0,
                'is_last' => $index === count($others) - 1,
            ];
        }
        $options = [];
        foreach (LandingSectionType::cases() as $type) {
            $options[] = ['value' => $type->value, 'label' => $type->label(), 'description' => $type->description(), 'taken' => $type->once() && isset($present[$type->value])];
        }
        $values = $extra['settings_values'] ?? ['slug' => $page['slug'], 'meta_title' => $page['meta_title'] ?? '', 'meta_description' => $page['meta_description'] ?? ''];
        unset($extra['settings_values']);
        return $extra + [
            'landing_page' => [
                'id' => (int) $page['id'],
                'slug' => (string) $page['slug'],
                'status' => (string) $page['status'],
                'published_at' => $page['published_at'],
                'was_published' => $page['first_published_at'] !== null,
                'path' => '/landing/' . $page['slug'],
                'url' => rtrim(\CattoLearning\Support\Env::string('APP_URL'), '/') . '/landing/' . $page['slug'],
                'problems' => $this->landing->problems($page),
                'rows' => array_values(array_filter($rows, static fn(array $row): bool => !$row['is_hero'])),
                'hero' => array_values(array_filter($rows, static fn(array $row): bool => $row['is_hero']))[0] ?? null,
                'order' => array_map(static fn(array $s): int => (int) $s['id'], $others),
                'add_options' => $options,
            ],
            'settings_values' => ['slug' => (string) ($values['slug'] ?? ''), 'meta_title' => (string) ($values['meta_title'] ?? ''), 'meta_description' => (string) ($values['meta_description'] ?? '')],
        ] + $data;
    }

    /**
     * @param array<string,mixed> $course
     * @param array<string,mixed> $page
     * @param array<string,mixed> $section
     * @param array<string,mixed> $values
     * @return array<string,mixed>
     */
    private function sectionForm(CurrentUser $user, array $course, array $page, array $section, array $values, string $error = ''): array
    {
        $type = $section['type'];
        $data = [
            'title' => $type->label() . ' · Landing page · ' . (string) $course['title'],
            'course' => ['id' => (int) $course['id'], 'title' => (string) $course['title'], 'subtitle' => (string) ($course['subtitle'] ?? ''), 'summary' => (string) ($course['summary'] ?? '')],
            'section' => ['id' => (int) $section['id'], 'type' => $type->value, 'label' => $type->label(), 'description' => $type->description(), 'enabled' => $section['enabled'], 'default_heading' => $type->defaultHeading()],
            'values' => $values,
            'error' => $error,
            'landing_home' => self::home($course),
        ];
        if ($type === LandingSectionType::Hero) {
            $data['pictures'] = $this->landing->pictures();
            $data['can_upload'] = $user->hasPermission('COURSE.MEDIA.MANAGE');
            $data['secondary_targets'] = LandingSectionType::SECONDARY_TARGETS;
        }
        if ($type === LandingSectionType::Instructor) {
            $data['provider'] = (string) ($course['owner_company_name'] ?? '');
            $data['accreditation'] = (string) ($course['certificate_accreditation'] ?? '');
        }
        if ($type === LandingSectionType::Reviews) {
            $data['review_limit_max'] = LandingSectionType::REVIEW_LIMIT_MAX;
        }
        return $data;
    }

    /**
     * What the section's form shows: its stored settings, or what was just posted. A list is one
     * text box with a line each; rows get a few empty ones to add more.
     *
     * @param array<string,mixed> $values
     * @return array<string,mixed>
     */
    private static function formValues(LandingSectionType $type, array $values, bool $posted = false): array
    {
        $values += $type->defaults();
        if (in_array($type, [LandingSectionType::Audience, LandingSectionType::Outcomes], true) && is_array($values['items'])) {
            $values['items'] = implode("\n", array_map('strval', $values['items']));
        }
        if (in_array($type, [LandingSectionType::Benefits, LandingSectionType::Faq], true)) {
            $keys = $type === LandingSectionType::Faq ? ['question', 'answer'] : ['title', 'text'];
            $rows = [];
            foreach (is_array($values['items']) ? $values['items'] : [] as $row) {
                $row = is_array($row) ? $row : [];
                $clean = [$keys[0] => (string) ($row[$keys[0]] ?? ''), $keys[1] => (string) ($row[$keys[1]] ?? '')];
                if (!$posted || $clean[$keys[0]] !== '' || $clean[$keys[1]] !== '') {
                    $rows[] = $clean;
                }
            }
            for ($i = 0; $i < self::SPARE_ROWS; $i++) {
                $rows[] = [$keys[0] => '', $keys[1] => ''];
            }
            $values['items'] = $rows;
        }
        if ($type === LandingSectionType::Contents && $posted) {
            $values['show_items'] = in_array($values['show_items'], ['1', 'on', true], true);
            $values['show_descriptions'] = in_array($values['show_descriptions'], ['1', 'on', true], true);
        }
        return $values;
    }

    /**
     * @param array<string,mixed> $course
     * @return array{0:array<string,mixed>,1:array<string,mixed>}
     */
    private function pageSection(array $course): array
    {
        $page = $this->landing->page((int) $course['id']) ?? throw new NotFoundHttpException('This course has no landing page yet.');
        foreach ($page['sections'] as $section) {
            if ((int) $section['id'] === (int) $this->param('section')) {
                return [$page, $section];
            }
        }
        throw new NotFoundHttpException('That section is not on this page.');
    }

    /** @return array<string,mixed> the course in the address, which the person must be able to manage */
    private function managedCourse(CurrentUser $user): array
    {
        try {
            $course = $this->courses->adminCourse((int) $this->param('id'));
        } catch (InvalidArgumentException) {
            throw new NotFoundHttpException('The course does not exist.');
        }
        if (!$user->hasPermission('PLATFORM.DASHBOARD.VIEW') && !$this->courses->userCanManageCourse((int) $course['id'], $user->id)) {
            throw new AccessDeniedHttpException('You do not have permission to manage this course.');
        }
        return $course;
    }

    /** @param array<string,mixed> $course */
    private static function home(array $course): string
    {
        return '/admin/courses/' . (int) $course['id'] . '/landing';
    }
