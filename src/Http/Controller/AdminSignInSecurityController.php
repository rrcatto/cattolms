declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Support\Address\PersonAddress;
use CattoLearning\Application\SignInSecurityAdministration;
use CattoLearning\Auth\AuthService;
use CattoLearning\Auth\TwoStepPolicy;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class AdminSignInSecurityController extends BaseController
{
    private const SETTINGS = '/admin/settings?section=two-step#settings-two-step';

    public function __construct(AuthService $auth, ThemeRenderer $view, RequestStack $requests, private readonly SignInSecurityAdministration $security, private readonly \CattoLearning\Infrastructure\Persistence\AddressKeyRepository $keys)
    {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/admin/settings/two-step', name: 'admin_save_two_step', methods: ['POST'])]
    public function savePolicy(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');

        return $this->handle(function () use ($user): void {
            $this->security->savePolicy((string) ($_POST['two_step'] ?? ''), $user->id);
            $this->flash('success', 'Saved. ' . TwoStepPolicy::CHOICES[$this->security->settingsView()['value']]['label'] . '.');
            $this->redirect(self::SETTINGS);
        }, self::SETTINGS);
    }

    /** Removes what Settings saved: AUTH_TWO_STEP in .env decides again. */
    #[Route('/admin/settings/two-step/reset', name: 'admin_reset_two_step', methods: ['POST'])]
    public function resetPolicy(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('SYSTEM.SETTING.MANAGE');
        $this->security->resetPolicy($user->id);
        $this->flash('success', 'Two-step sign-in now follows AUTH_TWO_STEP in .env: ' . lcfirst(TwoStepPolicy::CHOICES[$this->security->settingsView()['value']]['label']) . '.');
        $this->redirect(self::SETTINGS);
    }

    /** For someone who has lost their phone and their recovery codes: they set it up again. Never one's own. */
    #[Route('/admin/people/{reference}/two-step/reset', name: 'admin_person_two_step_reset', requirements: ['reference' => PersonAddress::REQUIREMENT], methods: ['POST'])]
    public function resetPerson(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.PERSON.MANAGE');
        $target = $this->personIdFromAddress($this->keys);
        $back = PersonAddress::admin($this->param('reference'), '#sign-in');

        return $this->handle(function () use ($user, $target, $back): void {
            $this->flash('success', $this->security->resetTwoStep($target, $user->id) ? 'Two-step sign-in is off for them now. They can set it up again.' : 'Two-step sign-in was already off for them.');
            $this->redirect($back);
        }, $back);
    }
}
