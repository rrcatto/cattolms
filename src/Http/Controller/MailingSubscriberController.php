    }

    #[Route('/mailing/subscribers/{id}/{action}', name: 'mailing_manage_subscriber_change', requirements: ['id' => '\d+', 'action' => 'take-off|stop'], methods: ['POST'])]
    public function change(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');
        $id = (int) $this->param('id');
        $action = $this->param('action');
        // From the list's Actions menu, back to the list as it was.
        $return = (string) ($_POST['return'] ?? '');
        $back = preg_match('#^/mailing/subscribers(\?[A-Za-z0-9_=&%.+-]*)?$#', $return) === 1 ? $return : self::BASE . '/' . $id . ($action === 'stop' ? '#stop' : '#lists');

        return $this->handle(function () use ($user, $id, $action, $back): void {
            $person = $this->subscribers->person($id);
            if ($person === null) throw $this->notFound('That person could not be found.');
            if ($action === 'take-off') {
                $this->lists->takeOff((int) ($_POST['list_id'] ?? 0), $id, $user->id);
                $this->flash('success', 'They are off that list. Every other list they are on stays as it is.');
                $this->redirect($back);
            }
            // Stop all email: off every list, and the address never emailed news again.
            $stopped = $this->consents->unsubscribeAll($id, 'admin');
            $email = mb_strtolower((string) $person['email']);
            if (!$this->campaigns->suppress($email, 'manual', 'Stopped by an administrator on their subscriber page.', null, $user->id) && $stopped === 0) {
                throw new InvalidArgumentException('Nothing is sent to them already.');
            }
            $this->audit->record($user->id, 'mailing.stopped_all', ['user_id' => $id]);
            $this->flash('success', 'They are off every list, and ' . $email . ' will never be emailed news.');
            $this->redirect($back);
        }, $back);
    }
