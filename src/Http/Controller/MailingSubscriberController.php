    #[Route('/mailing/subscribers/{id}', name: 'mailing_manage_subscriber', requirements: ['id' => '\d+'], methods: ['GET'])]
    public function subscriber(): Response
    {
        $user = $this->requirePermission('PLATFORM.MAILING.VIEW');
        $person = $this->subscribers->person((int) $this->param('id'));
        if ($person === null) throw $this->notFound('That person could not be found.');
        $id = (int) $person['user_id'];

        return $this->render('mailing-subscriber', [
            'title' => (string) $person['name'] . ' · Subscribers',
            'active_nav' => 'mailing',
            'person' => $person,
            'lists' => $this->subscribers->lists($id),
            'sent' => $this->subscribers->sent($id, 50),
            'history' => $this->subscribers->history($id, 50),
            'sources' => MailingConsents::SOURCES,
            'deliveries' => UpdateDelivery::DELIVERIES,
            'frequencies' => UpdateDelivery::FREQUENCIES,
            'can_manage' => $user->hasPermission('PLATFORM.MAILING.MANAGE'),
