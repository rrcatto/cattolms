declare(strict_types=1);

namespace CattoLearning\Http\Controller;

use CattoLearning\Auth\AuthService;
use CattoLearning\Mailing\CampaignRepository;
use CattoLearning\Mailing\EmailBlocks;
use CattoLearning\Mailing\EmailRenderer;
use CattoLearning\Mailing\MailingTemplates;
use CattoLearning\Mailing\UpdateDelivery;
use CattoLearning\Mailing\UpdateRepository;
use CattoLearning\Mailing\UpdateService;
use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class MailingDigestController extends BaseController
{
    private const BASE = '/mailing/digest';

    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly UpdateService $service,
        private readonly UpdateRepository $updates,
        private readonly EmailRenderer $renderer,
        private readonly MailingTemplates $templates,
        private readonly CampaignRepository $campaigns,
        private readonly RuntimeSettings $runtime,
    ) {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/mailing/digest', name: 'mailing_manage_digest', methods: ['GET'])]
    public function index(): Response
    {
        $user = $this->requirePermission('PLATFORM.MAILING.VIEW');

        return $this->render('mailing-digest', [
            'title' => 'Digest · Mailing',
            'active_nav' => 'mailing',
            'digest' => $this->service->view(),
            'frequencies' => UpdateDelivery::FREQUENCIES,
            'editing' => (int) ($_GET['edit'] ?? 0),
            'can_manage' => $user->hasPermission('PLATFORM.MAILING.MANAGE'),
        ]);
    }

    /** What the digest looks like with the updates held now, drawn in the template for digests. */
    #[Route('/mailing/digest/preview', name: 'mailing_manage_digest_preview', methods: ['GET'])]
    public function preview(): Response
    {
        $user = $this->requirePermission('PLATFORM.MAILING.VIEW');
        $held = array_map(static fn(array $u): int => (int) $u['id'], $this->updates->held());
        $why = [];
        foreach ($this->updates->reach($held) as $row) $why[$row['update_id']] ??= 'Because you follow ' . $row['list_name'];
        $cards = $this->updates->cards($held);
        $items = [];
        foreach ($held as $id) if (isset($cards[$id], $why[$id])) $items[] = $cards[$id] + ['why' => $why[$id]];
        if ($items === []) $items[] = ['headline' => 'Nothing is held for anyone yet', 'body' => 'Each update you release appears here, under why it reached the reader.', 'link' => '', 'button' => '', 'why' => ''];
        $copy = $this->renderer->render(['id' => 0, 'kind' => 'digest', 'subject' => 'Your weekly digest from ' . $this->runtime->platformName(), 'preheader' => 'What is new in what you follow.',
            'blocks' => [['type' => 'heading', 'text' => 'Your weekly digest'] + EmailBlocks::make('heading'), ['type' => 'text', 'text' => "Hello [First name],\n\nHere is what is new in what you follow since your last digest."] + EmailBlocks::make('text')]],
            ['first_name' => $this->campaigns->firstName($user->id), 'reasons' => ['What you follow'], 'list_name' => 'What you follow', 'content' => ['items' => $items]], false, $this->templates->defaultFor('digest'));

        return new Response($copy['html'], 200, ['Content-Type' => 'text/html; charset=utf-8', 'X-Frame-Options' => 'SAMEORIGIN', 'Cache-Control' => 'no-store',
            'Content-Security-Policy' => "default-src 'none'; img-src * data:; style-src 'unsafe-inline' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; sandbox allow-popups allow-popups-to-escape-sandbox"]);
    }

    #[Route('/mailing/digest/updates', name: 'mailing_manage_update_write', methods: ['POST'])]
    public function write(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');

        return $this->handle(function () use ($user): void {
            $id = $this->service->write($_POST, $user->id);
            $this->flash('success', 'The update is held with the others. Nothing is sent until you release it.');
            $this->redirect(self::BASE . '#update-' . $id);
        }, self::BASE . '#write');
    }

    #[Route('/mailing/digest/release', name: 'mailing_manage_updates_release', methods: ['POST'])]
    public function release(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');

        return $this->handle(function () use ($user): void {
            $done = $this->service->release((array) ($_POST['updates'] ?? []), (string) ($_POST['when'] ?? 'now'), (string) ($_POST['date'] ?? ''), (string) ($_POST['time'] ?? ''), $user->id);
            $what = $done['count'] === 1 ? '1 update' : $done['count'] . ' updates';
            $this->flash('success', $done['now']
                ? 'Released ' . $what . '. ' . ($done['instant'] > 0 ? ($done['instant'] === 1 ? '1 person who chose' : $done['instant'] . ' people who chose') . ' updates as they happen get an email now, within the sending hours. ' : '') . 'Everyone else gets them in their next digest.'
                : ucfirst($what) . ' will be released on ' . $done['at'] . '.');
            $this->redirect(self::BASE . ($done['now'] ? '#released' : '#held'));
        }, self::BASE . '#release');
    }

    #[Route('/mailing/digest/updates/{id}/{action}', name: 'mailing_manage_update_change', requirements: ['id' => '\d+', 'action' => 'reword|delete|news|hold'], methods: ['POST'])]
    public function change(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');
        $id = (int) $this->param('id');
        $action = $this->param('action');

        return $this->handle(function () use ($id, $action, $user): void {
            switch ($action) {
                case 'reword': $this->service->reword($id, $_POST, $user->id); $done = 'The update\'s words are saved.'; break;
                case 'delete': $this->service->delete($id, $user->id); $done = 'The update is deleted. Nobody will get it.'; break;
                case 'news': $this->service->postToNews($id, $user->id); $done = 'It goes to everyone who asked for News and Updates too.'; break;
                default: $this->service->holdAgain($id, $user->id); $done = 'It is held again until you release it.';
            }
            $this->flash('success', $done);
            $this->redirect(self::BASE . ($action === 'delete' ? '#held' : '#update-' . $id));
        }, self::BASE . '?edit=' . ($action === 'reword' ? $id : 0) . '#update-' . $id);
    }
}
