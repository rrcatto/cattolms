    /** A change to one list: its words, sender, welcome email, join link, closing, or taking one person off it. */
    #[Route('/mailing/lists/{id}/{action}', name: 'mailing_manage_list_change', requirements: ['id' => '\\d+', 'action' => 'words|sender|welcome|link|close|open|take-off'], methods: ['POST'])]
    public function changeList(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');
        $id = (int) $this->param('id');
        $action = $this->param('action');
        $anchor = ['words' => '#words', 'sender' => '#sender', 'welcome' => '#welcome', 'link' => '#join', 'close' => '#close', 'open' => '#close', 'take-off' => '#followers'][$action];

        return $this->handle(function () use ($user, $id, $action, $anchor): void {
            $list = $this->lists->list($id);
            if ($list === null) throw $this->notFound('That list could not be found.');
            switch ($action) {
                case 'words': $this->listService->saveWords($id, $_POST, $user->id); $done = 'The list is saved.'; break;
                case 'sender': $this->listService->saveSender($id, $_POST, $user->id); $done = 'Its sender and template are saved.'; break;
                case 'welcome':
                    $on = ($_POST['on'] ?? '') === '1';
                    $campaign = $this->listService->welcome($id, $on, $user->id, $list['name']);
                    if ($on && ($_POST['write'] ?? '') === '1') {
                        $this->flash('success', 'The welcome email is on. Write its words here; each person who joins gets it once.');
                        $this->redirect('/mailing/messages/' . $campaign . '#content');
                    }
                    $done = $on ? 'The welcome email is on: each person who joins gets it once.' : 'The welcome email is off.';
                    break;
                case 'link': $this->listService->newJoinLink($id, $user->id); $done = 'It has a new join link. The old one no longer works.'; break;
                case 'close': $this->listService->close($id, true, $user->id); $done = 'The list is closed: nothing more is sent to it and nobody can join.'; break;
                case 'open': $this->listService->close($id, false, $user->id); $done = 'The list is open again.'; break;
                default: $this->listService->takeOff($id, (int) ($_POST['user_id'] ?? 0), $user->id); $done = 'They are off this list. Every other list they are on stays as it is.';
            }
            $this->flash('success', $done);
            $this->redirect('/mailing/lists/' . $id . $anchor);
        }, '/mailing/lists/' . $id . $anchor);
    }

