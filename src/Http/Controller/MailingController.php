    /** Follow or Unfollow a category, course or tag, from its page or from My Subscriptions. */
    #[Route('/account/follow', name: 'account_follow', methods: ['POST'])]
    public function follow(): Response
    {
        $this->requireCsrf();
        $user = $this->requireUser();
        $back = self::back((string) ($_POST['return'] ?? '/account/subscriptions'));
        return $this->handle(function () use ($user, $back): void {
            $kind = (string) ($_POST['kind'] ?? '');
            $subject = (int) ($_POST['subject_id'] ?? 0);
            $source = in_array((string) ($_POST['source'] ?? ''), ['follow_button', 'preferences'], true) ? (string) $_POST['source'] : 'follow_button';
            if (($_POST['follow'] ?? '') === '1') {
                // The first follow says how the person would like their updates (round two 4C).
                if (isset($_POST['delivery'])) $this->mailing->chooseHow($user->id, (string) $_POST['delivery'], (string) ($_POST['frequency'] ?? 'weekly'));
