    /** Step 3's card, asked again: what catto-mail says of the sending domain now (the page asks every 30 seconds). */
    #[Route('/mailing/cattomail/domain', name: 'mailing_manage_cattomail_domain', methods: ['GET'])]
    public function domain(): Response
    {
        $this->requirePermission('PLATFORM.MAILING.VIEW');
        if ($this->connection->connected()) $this->connection->checkDomains();

