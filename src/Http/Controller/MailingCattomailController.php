    #[Route('/mailing/cattomail/connect', name: 'mailing_manage_cattomail_connect', methods: ['POST'])]
    public function connect(): Response
    {
        $this->requireCsrf();
        $this->requirePermission('PLATFORM.MAILING.MANAGE');
        try {
            $start = $this->connection->begin();
        } catch (InvalidArgumentException $refused) {
            $this->flash('error', $refused->getMessage());
            $this->redirect(self::BASE . '#address');
        }
        $_SESSION[self::SESSION] = ['state' => $start['state'], 'verifier' => $start['verifier'], 'redirect_uri' => $start['redirect_uri'], 'at' => time()];

        return new RedirectResponse($start['url'], 303);
    }

    /** catto-mail sends the administrator back here with the one-time code, or with why it was not approved. */
    #[Route('/mailing/cattomail/callback', name: 'mailing_manage_cattomail_callback', methods: ['GET'])]
    public function callback(): Response
    {
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');
        $kept = (array) ($_SESSION[self::SESSION] ?? []);
        unset($_SESSION[self::SESSION]);
        $state = (string) ($_GET['state'] ?? '');
        if ($kept === [] || !hash_equals((string) ($kept['state'] ?? ''), $state) || time() - (int) ($kept['at'] ?? 0) > 1800) {
            $this->flash('error', 'That answer from catto-mail does not belong to a Connect pressed here in the past half hour, so nothing was changed. Press Connect again.');
            $this->redirect(self::BASE . '#connect');
        }
        if (isset($_GET['error'])) {
            $words = trim((string) ($_GET['error_description'] ?? ''));
            $this->flash('info', (string) $_GET['error'] === 'access_denied' ? 'The connection was not approved at catto-mail. Nothing was changed.' : 'catto-mail did not connect it' . ($words !== '' ? ': ' . mb_substr($words, 0, 300) : '.'));
            $this->redirect(self::BASE . '#connect');
        }

        return $this->handle(function () use ($kept, $user): void {
            $this->connection->finish((string) ($_GET['code'] ?? ''), (string) $kept['verifier'], (string) $kept['redirect_uri'], $user->id, $this->campaigns->firstName($user->id) ?: 'an administrator');
            $this->flash('success', 'This site is connected to catto-mail. News goes through it once the sending domain is ready.');
            $this->redirect(self::BASE . '#domain');
        }, self::BASE . '#connect');
    }

    #[Route('/mailing/cattomail/{action}', name: 'mailing_manage_cattomail_change', requirements: ['action' => 'address|domains|check|test|disconnect|forget'], methods: ['POST'])]
    public function change(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.MAILING.MANAGE');
        $action = $this->param('action');
        $anchor = ['address' => '#address', 'domains' => '#domain', 'check' => '#connection', 'test' => '#test', 'disconnect' => '#connection', 'forget' => '#connection'][$action];

        return $this->handle(function () use ($user, $action, $anchor): void {
            switch ($action) {
                case 'address': $this->connection->saveAddress((string) ($_POST['address'] ?? ''), $user->id); $done = 'catto-mail\'s address is kept.'; break;
                case 'domains': $this->connection->checkDomains(); $done = $this->connection->ready() ? 'catto-mail can send from ' . $this->connection->sendingDomain() . '.' : 'catto-mail cannot send from ' . $this->connection->sendingDomain() . ' yet.'; break;
                case 'check': $done = $this->connection->check() ? 'catto-mail can be reached and takes the key.' : 'The check found a problem: ' . (string) $this->connection->state()['last_problem']; break;
                case 'test': $this->connection->test((string) ($_POST['email'] ?? ''), $user->id); $done = 'The test is on its way through catto-mail.'; break;
                case 'disconnect': $this->connection->disconnect($user->id); $done = 'The connection is ended at catto-mail and forgotten here. News waits until you connect again or choose a mail server in Sending settings.'; break;
                default: $this->connection->forget($user->id); $done = 'The connection is forgotten here. It still stands at catto-mail until it is ended there.';
            }
            $this->flash('success', $done);
            $this->redirect(self::BASE . $anchor);
        }, self::BASE . $anchor);
    }

    /** A sending asked about again, or a report taken again, on the next run. */
    #[Route('/mailing/cattomail/{what}/{id}/again', name: 'mailing_manage_cattomail_again', requirements: ['what' => 'jobs|events', 'id' => '[A-Za-z0-9-]{1,100}'], methods: ['POST'])]
    public function again(): Response
    {
        $this->requireCsrf();
        $this->requirePermission('PLATFORM.MAILING.MANAGE');
        if ($this->param('what') === 'jobs') {
