declare(strict_types=1);

namespace CattoLearning\Http\Controller;

final class AuthController extends BaseController
{
    public function loginForm(): void
    {
        if ($this->currentUser() !== null) {
            $this->redirect('/account/library');
        }
        $this->render('login', [
            'title' => 'Sign in',
            'return_path' => $this->safeReturnPath((string) ($_GET['return'] ?? '/account/library')),
        ]);
    }

    public function requestLink(): void
    {
        $this->requireCsrf();
        $email = (string) ($_POST['email'] ?? '');
        $returnPath = $this->safeReturnPath((string) ($_POST['return_path'] ?? '/account/library'));
        try {
            $this->auth->requestLogin($email, $returnPath);
            $this->redirect('/login/sent');
        } catch (\InvalidArgumentException|\RuntimeException $e) {
            error_log('Magic-link request failed: ' . $e->getMessage());
            $this->flash('danger', $e->getMessage());
            $this->redirect('/login');
        } catch (\Throwable $e) {
            error_log('Magic-link request failed: ' . $e->getMessage());
            $this->flash('danger', 'The sign-in email could not be sent. Please try again or contact support.');
            $this->redirect('/login');
        }
    }


    public function sent(): void
    {
        $this->render('login-sent', ['title' => 'Check your email']);
    }

    public function consumeHead(): void
    {
        // Link scanners may probe the URL with HEAD. Never consume a token on HEAD.
        http_response_code(204);
        header('Cache-Control: no-store');
    }

    public function consume(): void
    {
        $token = (string) ($_GET['token'] ?? '');
        $this->handle(function () use ($token): void {
            $returnPath = $this->auth->consumeLogin($token);
            session_regenerate_id(true);
            $this->flash('success', 'You are signed in.');
            $this->redirect($returnPath);
        }, '/login');
    }

    public function logout(): void
    {
        $this->requireCsrf();
        $this->auth->logout();
        session_regenerate_id(true);
        $this->flash('success', 'You have been signed out.');
        $this->redirect('/');
    }

    private function safeReturnPath(string $path): string
    {
        return str_starts_with($path, '/') && !str_starts_with($path, '//') ? $path : '/account/library';
    }
}