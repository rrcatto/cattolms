    /** @return array{done:int,total:int,next:?array<string,mixed>} */
    public function progress(): array
    {
        $steps = $this->steps();
        $next = null;
        foreach ($steps as $step) if (!$step['done']) { $next = $step; break; }
        return ['done' => count(array_filter($steps, static fn(array $step): bool => $step['done'])), 'total' => count($steps), 'next' => $next];
    }

    /** ADMIN marks a step done, or not done again. */
    public function mark(string $key, bool $done, int $actorId): void
    {
        if (!in_array($key, self::MANUAL, true)) throw new InvalidArgumentException('That step is done by what the site holds, not by marking it.');
        if ($done) $this->options->set('setup.done.' . $key, gmdate('Y-m-d H:i:sP'), $actorId);
        else $this->options->delete('setup.done.' . $key);
        $this->audit->record($actorId, 'setup.step_marked', ['step' => $key, 'done' => $done]);
    }

    /**
     * Loads the catalogue file published with the code: its categories and tags.
     *
     * @return array<string,mixed> what the import did
     */
    public function loadCatalogue(int $actorId): array
    {
        $json = is_file(CatalogueFile::bundledPath()) ? (string) file_get_contents(CatalogueFile::bundledPath()) : '';
        if ($json === '') throw new InvalidArgumentException('The catalogue file resources/catalogue/catalogue.json is missing from the code.');
        try {
            $report = $this->catalogue->import(json_decode($json, true, 64, JSON_THROW_ON_ERROR), $actorId);
        } catch (JsonException) {
            throw new InvalidArgumentException('The catalogue file is not valid JSON.');
        }
        $this->audit->record($actorId, 'setup.catalogue_loaded', ['categories_created' => $report['categories_created'], 'tags_created' => $report['tags_created']]);
        return $report;
    }
