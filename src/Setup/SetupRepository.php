declare(strict_types=1);

namespace CattoLearning\Setup;

use CattoLearning\Infrastructure\Persistence\Database;

final class SetupRepository
{
    public function __construct(private readonly Database $db) {}

    /** @return array{categories:int,tags:int,courses:int,published:int,uncategorised:int,unpriced:int} */
    public function counts(): array
    {
        $row = $this->db->fetchAssociative(
            "SELECT (SELECT COUNT(*) FROM course_categories) AS categories,
                    (SELECT COUNT(*) FROM tags) AS tags,
                    (SELECT COUNT(*) FROM courses) AS courses,
                    (SELECT COUNT(*) FROM courses WHERE status = 'published') AS published,
                    (SELECT COUNT(*) FROM courses WHERE category_id IS NULL) AS uncategorised,
                    (SELECT COUNT(*) FROM courses c WHERE c.status = 'published' AND NOT EXISTS (
                        SELECT 1 FROM course_price_variants v WHERE v.course_id = c.id AND v.is_active = TRUE)) AS unpriced"
        );
        $row = $row === false ? [] : $row;
        return ['categories' => (int) ($row['categories'] ?? 0), 'tags' => (int) ($row['tags'] ?? 0), 'courses' => (int) ($row['courses'] ?? 0),
            'published' => (int) ($row['published'] ?? 0), 'uncategorised' => (int) ($row['uncategorised'] ?? 0), 'unpriced' => (int) ($row['unpriced'] ?? 0)];
    }

    /** @return array<string,string> step key => when ADMIN marked it done */
    public function marked(): array
    {
        $marked = [];
        foreach ($this->db->fetchAllAssociative("SELECT option_key, option_value FROM app_options WHERE option_key LIKE 'setup.done.%'") as $row) {
            $marked[substr((string) $row['option_key'], strlen('setup.done.'))] = (string) $row['option_value'];
        }
        return $marked;
    }
}
