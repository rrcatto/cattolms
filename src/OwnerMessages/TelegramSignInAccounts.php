declare(strict_types=1);

namespace CattoLearning\OwnerMessages;

use CattoLearning\Support\EmailAddress;
use CattoPHP\Telegram\TelegramAccounts;
use Throwable;

final class TelegramSignInAccounts
{
    public function __construct(private readonly TelegramAccounts $accounts, private readonly TelegramRepository $records)
    {
    }

    /** @return array{user_id:int,chat_id:string,username:?string,connected_at:string}|null */
    public function forSignIn(string $typed): ?array
    {
        $typed = trim($typed);
        if ($typed === '') return null;
        if (str_contains(ltrim($typed, '@'), '@')) {
            try {
                $email = EmailAddress::normalize($typed);
            } catch (Throwable) {
                return null;
            }
            $user = $this->records->userByVerifiedEmail($email);
            $account = $user === null ? null : $this->accounts->forAccount((string) $user);
        } else {
            $account = $this->accounts->forUsername($typed);
        }
        if ($account === null || !ctype_digit($account['account'])) return null;

        return ['user_id' => (int) $account['account'], 'chat_id' => $account['chat_id'], 'username' => $account['username'], 'connected_at' => $account['connected_at']];
    }
}
