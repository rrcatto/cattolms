declare(strict_types=1);

namespace CattoLearning\OwnerMessages;

use DateTimeImmutable;
use DateTimeZone;
use InvalidArgumentException;
use RuntimeException;

class OwnerMessageSetup
{
    /** How @BotFather writes a key: the bot's number, a colon and its secret. */
    private const KEY_SHAPE = '/^\d{3,20}:[A-Za-z0-9_-]{20,100}$/';
    /** How Telegram allows a username to be written. */
    private const USERNAME_SHAPE = '/^[A-Za-z0-9_]{5,32}$/';

    public function __construct(
        private readonly OwnerMessageSettings $settings,
        private readonly OwnerMessageRepository $messages,
        private readonly OwnerMessages $owner,
        private readonly TelegramClient $telegram
    ) {
    }

    /**
     * Settings' section (owner, 2026-11-05: connected or not, and which account to which). Its state is `connected`,
     * `failing` (connected, and Telegram is refusing messages), `waiting` (a key and a username, and Telegram has not
     * seen that account yet) or `none`.
     *
     * @return array<string,mixed>
     */
    public function view(): array
    {
        $saved = $this->settings->saved();
        $status = $this->messages->status();
        $connected = $this->settings->connected();
        $state = $connected ? ($status['last_error'] !== null && $status['last_error'] !== '' ? 'failing' : 'connected') : ($saved['key'] !== '' && $saved['username'] !== '' ? 'waiting' : 'none');
        $link = '@' . $saved['bot_name'] . ' to @' . $saved['username'];

        return ['state' => $state, 'has_key' => $saved['key'] !== '', 'connected' => $connected, 'disconnected' => $saved['disconnected'], 'bot_name' => $saved['bot_name'], 'username' => $saved['username'],
            'title' => match ($state) { 'connected' => 'Connected: ' . $link, 'failing' => 'Not getting through: ' . $link, default => 'Not connected' },
            'title_tone' => match ($state) { 'connected' => 'success', 'failing' => 'danger', default => 'neutral' },
            'on_register' => $saved['on_register'], 'on_sale' => $saved['on_sale'], 'waiting' => $status['waiting'], 'last_error' => $status['last_error']];
    }

    /**
     * Connect to Telegram: a new key Telegram accepts and the username are kept, then that account's chat is looked for.
     * Whether it is found is the answer, because the account only shows once it has written to the bot.
     *
     * @param array{key:string,username:string} $input
     * @return array{connected:bool,key_changed:bool}
     */
    public function connect(array $input, int $actor): array
    {
        $key = trim($input['key']);
        $username = ltrim(trim($input['username']), '@');
        if ($key === '' && $this->settings->key() === '') throw new InvalidArgumentException('Paste the bot key.');
        // A key Telegram accepts is kept whatever is wrong with the username, so it need not be pasted again.
        $changed = false;
        if ($key !== '') {
            if (preg_match(self::KEY_SHAPE, $key) !== 1) throw new InvalidArgumentException('That is not a bot key. @BotFather gives one like 123456789:AAFbcd. Paste all of it.');
            $this->settings->setKey($key, $this->telegram->botName($this->settings->address(), $key), $actor);
            $changed = true;
        }
        if ($username === '') throw new InvalidArgumentException('Type your Telegram username.');
        if (preg_match(self::USERNAME_SHAPE, $username) !== 1) throw new InvalidArgumentException('That is not a Telegram username. It has 5 to 32 letters, numbers and underscores.');
        // The two usernames are easily confused (owner, 2026-11-05: "the one I registered for the bot or my personal one?"), and a bot cannot message itself. A new key is kept, so it need not be pasted again.
        if (strcasecmp($username, $this->settings->saved()['bot_name']) === 0) throw new InvalidArgumentException('That is the bot. Type your own username.');
        $this->settings->setUsername($username, $actor);
        $chat = $this->telegram->chatOf($this->settings->address(), $this->settings->key(), $username);
        if ($chat === null) return ['connected' => false, 'key_changed' => $changed];
        $this->settings->setChat($chat, $actor);

        return ['connected' => true, 'key_changed' => $changed];
    }

    public function saveChoices(bool $onRegister, bool $onSale, int $actor): void
    {
        $this->settings->setChoices($onRegister, $onSale, $actor);
    }

    /** Goes at once, not by the queue, so what Telegram says is shown on the page. */
    public function sendTest(): void
    {
        if (!$this->settings->connected()) throw new InvalidArgumentException('Connect to Telegram first.');
        $body = $this->owner->worded('Test message: your messages from this site will arrive here');
        $reference = 'test:' . bin2hex(random_bytes(8));
        try {
            $this->telegram->send($this->settings->address(), $this->settings->key(), $this->settings->saved()['chat_id'], $body);
        } catch (TelegramFailed $failed) {
            $this->messages->logTest($reference, $body, $failed->getMessage());
            throw $failed;
        }
        $this->messages->logTest($reference, $body, null);
    }

    public function disconnect(int $actor): void
    {
        $this->settings->forget($actor);
    }
}
