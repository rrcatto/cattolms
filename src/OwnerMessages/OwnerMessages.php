declare(strict_types=1);

namespace CattoLearning\OwnerMessages;

use CattoLearning\Commerce\Application\MoneyRecords;
use CattoLearning\Commerce\Infrastructure\CommerceRepository;
use CattoLearning\Infrastructure\Mail\GeneratedDomainRouter;
use CattoLearning\Support\Countries;
use CattoLearning\Support\Env;
use CattoPHP\Telegram\TelegramBot;
use CattoPHP\Telegram\TelegramLog;
use CattoPHP\Telegram\TelegramWords;

class OwnerMessages
{
    /** The domains reserved for testing and examples (RFC 2606, RFC 6761), which only the checks use. */
    private const RESERVED_SUFFIXES = ['.test', '.example', '.localhost'];
    private const RESERVED_DOMAINS = ['example.com', 'example.net', 'example.org'];

    /** The owner's choices of what sends a message, as Settings > Connect to Telegram bot ticks them. */
    public const CHOICES = ['on_register', 'on_order', 'on_sale'];

    public function __construct(
        private readonly TelegramBot $settings,
        private readonly TelegramLog $messages,
        private readonly TelegramWords $words,
        private readonly TelegramRepository $records,
    ) {
    }

    /** A person finished registering through the site: their account exists, whether it is held or not. */
    public function registered(int $userId, string $email, string $name, ?string $country): void
    {
        $this->messages->guarded(function () use ($userId, $email, $name, $country): void {
            if (self::invented($email) || !$this->settings->choice('on_register') || !$this->settings->connected()) return;
            $where = $country !== null && $country !== '' ? ', ' . Countries::name($country) : '';
            $this->messages->record('registration:' . $userId, 'registration', $this->worded('New registration: ' . ($name !== '' ? $name : 'no name given') . $where));
        });
    }

    /** A message came through the contact form and is in the Inbox (owner, 2026-11-11), when Inbox settings ask for it. */
    public function contactMessage(string $reference, string $reason, string $name, string $email): void
    {
        $this->messages->guarded(function () use ($reference, $reason, $name, $email): void {
            if (self::invented($email) || !$this->settings->connected()) return;
            $this->messages->record('message:' . $reference, 'message', $this->worded('New message ' . $reference . ': ' . $reason . ' from ' . ($name !== '' ? $name : 'no name given')));
        });
    }

    /**
     * An order is paid in full.
     *
     * @param array<string,mixed> $order
     * @param list<array<string,mixed>> $items
     */
    public function orderPaid(array $order, array $items): void
    {
        $this->messages->guarded(function () use ($order, $items): void {
            if (!$this->settings->choice('on_sale') || !$this->settings->connected()) return;
            $buyer = $this->records->primaryEmail((int) ($order['purchaser_user_id'] ?? 0));
            if ($buyer === null || self::invented($buyer)) return;
            $id = (int) $order['id'];
            $words = 'Sale: Order ' . MoneyRecords::orderNumber($id) . ', ' . self::bought($items) . ', ' . self::amount((int) $order['total_minor'], (string) $order['currency'])
                . ', ' . self::how($this->records->paidGateways($id), (int) $order['total_minor']);
            $this->messages->record('order:' . $id, 'sale', $this->worded($words));
        });
    }

    /**
     * An order is placed, before it is paid (owner, 2026-11-06: "I would also like to receive a notification when an order is
     * placed"), once, whichever checkout placed it.
     *
     * @param array<string,mixed> $order
     * @param list<array<string,mixed>> $items
     */
    public function orderPlaced(array $order, array $items, string $method): void
    {
        $this->messages->guarded(function () use ($order, $items, $method): void {
            if (!$this->settings->choice('on_order') || !$this->settings->connected()) return;
            $buyer = $this->records->primaryEmail((int) ($order['purchaser_user_id'] ?? 0));
            if ($buyer === null || self::invented($buyer)) return;
            $id = (int) $order['id'];
            $words = 'New order: Order ' . MoneyRecords::orderNumber($id) . ', ' . self::bought($items) . ', ' . self::amount((int) $order['total_minor'], (string) $order['currency'])
                . ', ' . self::toPay($method, (int) $order['total_minor']);
            $this->messages->record('placed:' . $id, 'order', $this->worded($words));
        });
    }

    /** Whether an address is one nobody real has: invented by Seed Database, or reserved for testing. */
    public static function invented(string $email): bool
    {
        if (GeneratedDomainRouter::isGeneratedAddress($email)) return true;
        $domain = strtolower(trim((string) substr((string) strrchr($email, '@'), 1)));
        foreach (self::RESERVED_SUFFIXES as $suffix) {
            if (str_ends_with($domain, $suffix)) return true;
        }
        foreach (self::RESERVED_DOMAINS as $reserved) {
            if ($domain === $reserved || str_ends_with($domain, '.' . $reserved)) return true;
        }

        return false;
    }

    /** R2,500, or R2,500.50 when there are cents. */
    public static function amount(int $minor, string $currency): string
    {
        $whole = $minor % 100 === 0;
        $number = number_format($minor / 100, $whole ? 0 : 2, '.', ',');

        return $currency === 'ZAR' ? 'R' . $number : $currency . ' ' . $number;
    }

    /** @param list<array<string,mixed>> $items */
    private static function bought(array $items): string
    {
        $names = [];
        foreach ($items as $item) {
            $snapshot = CommerceRepository::decode((string) ($item['snapshot'] ?? '{}'));
            $title = (string) ($snapshot['bundle_title'] ?? $snapshot['course_title'] ?? 'a course');
            $names[] = in_array($item['product_type'] ?? '', ['company_credit', 'bundle_credit'], true) ? $title . ' (' . (int) $item['quantity'] . ((int) $item['quantity'] === 1 ? ' credit)' : ' credits)') : $title;
        }

        return $names === [] ? 'nothing listed' : implode(', ', $names);
    }

    /** @param list<string> $gateways */
    private static function how(array $gateways, int $total): string
    {
        if ($gateways === []) return $total === 0 ? 'covered by a promotion' : 'paid';
        $words = array_values(array_unique(array_map(static fn(string $gateway): string => match ($gateway) { 'manual_bank' => 'EFT', 'wallet' => 'wallet credit', default => 'card' }, $gateways)));

        return 'paid by ' . implode(' and ', $words);
    }

    /** How an order just placed is to be paid, by the method chosen at checkout. */
    private static function toPay(string $method, int $total): string
    {
        if ($total === 0) return 'covered by a promotion';

        return match ($method) { 'eft' => 'to be paid by EFT', 'wallet' => 'paid from wallet credit', 'dummy' => 'by simulated card', default => 'by card' };
    }

    /** A demo site says so, as its emails do, and every message ends with the site it came from. */
    public function worded(string $words): string
    {
        return $this->words->worded($words);
    }

    /** What a message to a person begins with: [DEMO] on a demo site, as its emails do. */
    public function demo(): string
    {
        return $this->words->demo();
    }

    /** The site's name in a message: its domain, or its address's host. */
    public static function domain(): string
    {
        $domain = trim(Env::string('APP_DOMAIN'));
        if ($domain === '') $domain = (string) parse_url(Env::string('APP_URL'), PHP_URL_HOST);

        return $domain !== '' ? $domain : 'this site';
    }
}
