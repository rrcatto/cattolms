declare(strict_types=1);

namespace CattoLearning\OwnerMessages;

use CattoLearning\Configuration\SecretCipher;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\LoginTokenRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\ClientFingerprint;
use CattoLearning\Support\Token;
use InvalidArgumentException;
use Symfony\Component\Clock\ClockInterface;
use Throwable;

class TelegramConnections
{
    public const PURPOSE = 'telegram_connect';
    public const TTL = 600;
    private const SESSION = 'telegram_connect';

    /** What the page says when a connection did not happen. */
    public const TAKEN = 'That Telegram account is already connected to another account here. Disconnect it there first, or use another Telegram account.';
    public const OTHER = 'Your account is already connected to another Telegram account. Disconnect it first.';
    public const EXPIRED = 'The link ran out before Telegram was started. Press Connect Telegram to try again.';
    public const NOT_OFFERED = 'Signing in with Telegram is not offered on this site.';

    public function __construct(
        private readonly LoginTokenRepository $tokens,
        private readonly TelegramAccountRepository $accounts,
        private readonly OwnerMessageSettings $settings,
        private readonly TelegramMessenger $messenger,
        private readonly OwnerMessages $owner,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
        private readonly SecretCipher $cipher,
        private readonly ClockInterface $clock,
    ) {
    }

    /** Starts connecting: the button to the bot shows until Telegram is started or 10 minutes pass. */
    public function start(int $userId, string $email): void
    {
        if (!$this->settings->signInOffered() || $this->settings->botName() === '') throw new InvalidArgumentException(self::NOT_OFFERED);
        if ($this->accounts->forUser($userId) !== null) throw new InvalidArgumentException('Your Telegram account is connected already.');
        $raw = Token::generate();
        $this->transactions->run(function () use ($userId, $email, $raw): void {
            $this->tokens->deleteOpenFor($userId, self::PURPOSE);
            $this->tokens->create(Token::hash($raw), $email, self::PURPOSE, $userId, [], self::TTL, ClientFingerprint::ipHash());
        });
        $_SESSION[self::SESSION] = ['user_id' => $userId, 'token' => $this->cipher->encrypt($raw), 'expires_at' => $this->now() + self::TTL];
    }

    /** Stops connecting: the link no longer works. */
    public function cancel(int $userId): void
    {
        $this->tokens->deleteOpenFor($userId, self::PURPOSE);
        unset($_SESSION[self::SESSION]);
    }

    /**
     * Where a person's Telegram stands, for their Sign-in and security page: 'on' (connected), 'waiting' (the button to the
     * bot, until it is started) or 'off', with a note when a connection just failed.
     *
     * @return array{offered:bool,state:string,username:?string,connected_on:string,bot_name:string,link:string,note:?array{tone:string,words:string}}
     */
    public function view(int $userId): array
    {
        $offered = $this->settings->signInOffered();
        $bot = $this->settings->botName();
        $base = ['offered' => $offered, 'state' => 'off', 'username' => null, 'connected_on' => '', 'bot_name' => $bot, 'link' => '', 'note' => null];
        $connected = $this->accounts->forUser($userId);
        if ($connected !== null) {
            unset($_SESSION[self::SESSION]);

            return ['state' => 'on', 'username' => $connected['username'], 'connected_on' => self::day($connected['connected_at'])] + $base;
        }
        $asked = $_SESSION[self::SESSION] ?? null;
        if (!is_array($asked) || (int) ($asked['user_id'] ?? 0) !== $userId) return $base;
        try {
            $raw = $this->cipher->decrypt((string) ($asked['token'] ?? ''));
        } catch (Throwable) {
            $raw = '';
        }
        $row = $raw === '' ? null : $this->tokens->findByHash(Token::hash($raw), self::PURPOSE);
        $context = $row === null ? [] : (json_decode((string) ($row['context'] ?? '{}'), true) ?: []);
        if ($row === null || $row['used_at'] !== null || (int) ($asked['expires_at'] ?? 0) < $this->now() || !$offered) {
            unset($_SESSION[self::SESSION]);
            $words = match ((string) ($context['refused'] ?? '')) { 'taken' => self::TAKEN, 'other' => self::OTHER, default => $offered && $row !== null && $row['used_at'] === null ? self::EXPIRED : null };

            return ['note' => $words === null ? null : ['tone' => 'danger', 'words' => $words]] + $base;
        }

        return ['state' => 'waiting', 'link' => 'https://t.me/' . rawurlencode($bot) . '?start=' . rawurlencode($raw)] + $base;
    }

    /** The bot was sent /start with a token (TelegramInbox): the chat is connected to the token's account, or refused. */
    public function started(string $chatId, ?string $username, string $raw): void
    {
        $outcome = $this->transactions->run(function () use ($chatId, $username, $raw): array {
            $row = $this->tokens->findUsableForUpdate(Token::hash($raw), self::PURPOSE);
            if ($row === null || (int) ($row['user_id'] ?? 0) < 1) return ['expired', null];
            $userId = (int) $row['user_id'];
            $context = json_decode((string) ($row['context'] ?? '{}'), true) ?: [];
            $taken = $this->accounts->forChat($chatId, true);
            $own = $this->accounts->forUser($userId);
            $refused = $taken !== null && $taken['user_id'] !== $userId ? 'taken' : ($own !== null && $own['chat_id'] !== $chatId ? 'other' : null);
            $this->tokens->markUsed((int) $row['id']);
            if ($refused !== null) {
                $this->tokens->updateContext((int) $row['id'], ['refused' => $refused] + $context);
                $this->audit->record($userId, 'telegram.connect_refused', ['user_id' => $userId, 'why' => $refused]);

                return [$refused, $userId];
            }
            $this->accounts->connect($userId, $chatId, $username);
            $this->audit->record($userId, 'telegram.connected', ['user_id' => $userId, 'username' => TelegramAccountRepository::username($username)]);

            return ['connected', $userId];
        });
        [$what, $userId] = $outcome;
        $domain = OwnerMessages::domain();
        $words = match ($what) {
            'connected' => 'Your Telegram account is now connected to ' . $domain,
            'taken' => 'This Telegram account is already connected to another account on ' . $domain . '. Disconnect it there first.',
            'other' => 'Your account on ' . $domain . ' is already connected to another Telegram account. Disconnect that one first.',
            default => 'That link has run out or was used already. Go back to ' . $domain . ' and press Connect Telegram again.',
        };
        // The log names whose chat it is now: the person just connected, whoever holds it already, or nobody.
        $this->messenger->send('connected', $chatId, $this->accounts->forChat($chatId)['user_id'] ?? null, $username, $this->owner->demo() . $words, '', [$raw],
            ($what === 'connected' ? 'connected' : 'reply') . ':' . bin2hex(random_bytes(8)));
    }

    /** Someone pressed Start on the bot without a token: one line saying what the bot is for. */
    public function greeted(string $chatId, ?string $username): void
    {
        $connected = $this->accounts->forChat($chatId);
        $domain = OwnerMessages::domain();
        $this->messenger->send('connected', $chatId, $connected['user_id'] ?? null, $username,
            $this->owner->demo() . 'This bot sends sign-in messages for ' . $domain . '. To use it, sign in there, open Sign-in and security in your account and press Connect Telegram.');
    }

    /** A test to the person's own chat, from their page. Whether it went. */
    public function test(int $userId): bool
    {
        $connected = $this->accounts->forUser($userId) ?? throw new InvalidArgumentException('Connect Telegram first.');

        return $this->messenger->send('test', $connected['chat_id'], $userId, $connected['username'], $this->owner->demo() . 'Test message from ' . OwnerMessages::domain());
    }

    public function disconnect(int $userId): void
    {
        $this->cancel($userId);
        if ($this->accounts->disconnect($userId)) $this->audit->record($userId, 'telegram.disconnected', ['user_id' => $userId]);
    }

    private function now(): int
    {
        return $this->clock->now()->getTimestamp();
    }

    private static function day(string $at): string
    {
        try {
            return (new \DateTimeImmutable($at))->setTimezone(new \DateTimeZone(date_default_timezone_get()))->format('j F Y');
        } catch (Throwable) {
            return '';
        }
    }
}
