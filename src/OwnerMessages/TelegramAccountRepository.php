declare(strict_types=1);

namespace CattoLearning\OwnerMessages;

use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Support\EmailAddress;
use Throwable;

class TelegramAccountRepository
{
    /** How Telegram writes a username, without its @. */
    public const USERNAME = '/^[A-Za-z0-9_]{4,32}$/';

    public function __construct(private readonly Database $db)
    {
    }

    /** @return array{user_id:int,chat_id:string,username:?string,connected_at:string}|null */
    public function forUser(int $userId): ?array
    {
        return self::shaped($this->db->fetchAssociative('SELECT user_id, chat_id, username, connected_at FROM telegram_accounts WHERE user_id = :user', ['user' => $userId]));
    }

    /** @return array{user_id:int,chat_id:string,username:?string,connected_at:string}|null */
    public function forChat(string $chatId, bool $forUpdate = false): ?array
    {
        return self::shaped($this->db->fetchAssociative('SELECT user_id, chat_id, username, connected_at FROM telegram_accounts WHERE chat_id = :chat' . ($forUpdate ? ' FOR UPDATE' : ''), ['chat' => $chatId]));
    }

    /**
     * The connected account a sign-in form names, by its Telegram username (with or without its @, in any case) or by any
     * verified email address of the account, or null. Whether the account may sign in is the caller's question.
     *
     * @return array{user_id:int,chat_id:string,username:?string,connected_at:string}|null
     */
    public function forSignIn(string $typed): ?array
    {
        $typed = trim($typed);
        if ($typed === '') return null;
        if (str_contains(ltrim($typed, '@'), '@')) {
            try {
                $email = EmailAddress::normalize($typed);
            } catch (Throwable) {
                return null;
            }

            return self::shaped($this->db->fetchAssociative(
                'SELECT t.user_id, t.chat_id, t.username, t.connected_at FROM telegram_accounts t
                 WHERE EXISTS (SELECT 1 FROM user_emails e WHERE e.user_id = t.user_id AND LOWER(e.email) = LOWER(:email) AND e.verified_at IS NOT NULL)',
                ['email' => $email]
            ));
        }
        $username = ltrim($typed, '@');
        if (preg_match(self::USERNAME, $username) !== 1) return null;

        return self::shaped($this->db->fetchAssociative('SELECT user_id, chat_id, username, connected_at FROM telegram_accounts WHERE LOWER(username) = LOWER(:username)', ['username' => $username]));
    }

    /** Connects a person's Telegram account. The caller has made sure neither is connected to anyone else. */
    public function connect(int $userId, string $chatId, ?string $username): void
    {
        $username = self::username($username);
        if ($username !== null) $this->db->executeStatement('UPDATE telegram_accounts SET username = NULL, updated_at = NOW() WHERE LOWER(username) = LOWER(:username) AND chat_id <> :chat', ['username' => $username, 'chat' => $chatId]);
        $this->db->executeStatement(
            'INSERT INTO telegram_accounts (user_id, chat_id, username) VALUES (:user, :chat, :username)
             ON CONFLICT (user_id) DO UPDATE SET chat_id = EXCLUDED.chat_id, username = EXCLUDED.username, connected_at = NOW(), updated_at = NOW()',
            ['user' => $userId, 'chat' => $chatId, 'username' => $username]
        );
    }

    /** What the bot just heard a chat called: its username now, or none. Whether anything changed. */
    public function heard(string $chatId, ?string $username): bool
    {
        $username = self::username($username);
        $row = $this->forChat($chatId);
        if ($row === null || $row['username'] === $username) return false;
        if ($username !== null) $this->db->executeStatement('UPDATE telegram_accounts SET username = NULL, updated_at = NOW() WHERE LOWER(username) = LOWER(:username) AND chat_id <> :chat', ['username' => $username, 'chat' => $chatId]);
        $this->db->executeStatement('UPDATE telegram_accounts SET username = :username, updated_at = NOW() WHERE chat_id = :chat', ['username' => $username, 'chat' => $chatId]);

        return true;
    }

    /** Forgets a person's Telegram account. Whether there was one. */
    public function disconnect(int $userId): bool
    {
        return $this->db->executeStatement('DELETE FROM telegram_accounts WHERE user_id = :user', ['user' => $userId]) > 0;
    }

    /** A username as it is kept: without its @, or null when there is none or it is not one. */
    public static function username(?string $username): ?string
    {
        $username = ltrim(trim((string) $username), '@');

        return preg_match(self::USERNAME, $username) === 1 ? $username : null;
    }

    /**
     * @param array<string,mixed>|false $row
     * @return array{user_id:int,chat_id:string,username:?string,connected_at:string}|null
     */
    private static function shaped(array|false $row): ?array
    {
        if ($row === false) return null;

        return ['user_id' => (int) $row['user_id'], 'chat_id' => (string) $row['chat_id'], 'username' => is_string($row['username'] ?? null) ? $row['username'] : null, 'connected_at' => (string) $row['connected_at']];
    }
}
