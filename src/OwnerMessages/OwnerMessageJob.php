declare(strict_types=1);

namespace CattoLearning\OwnerMessages;

use DateTimeImmutable;
use Symfony\Component\Clock\ClockInterface;

class OwnerMessageJob
{
    public const BATCH = 30;

    public function __construct(
        private readonly OwnerMessageRepository $messages,
        private readonly OwnerMessageSettings $settings,
        private readonly TelegramClient $telegram,
        private readonly ClockInterface $clock,
        private readonly ?TelegramInbox $inbox = null
    ) {
    }

    public function run(): string
    {
        $dropped = $this->messages->deleteWaitingBefore(DateTimeImmutable::createFromInterface($this->clock->now())->modify('-7 days'));
        $droppedWords = $dropped === 0 ? '' : ' Dropped ' . $dropped . ' older than 7 days.';
        // What people sent the bot, while they can sign in with Telegram: Start pressed to connect, and new usernames.
        try {
            $read = $this->inbox?->read() ?? 0;
            if ($read > 0) $droppedWords .= ' Read ' . $read . ' sent to the bot.';
        } catch (TelegramFailed $failed) {
            $droppedWords .= ' What people sent the bot could not be read: ' . $failed->getMessage();
        }
        if (!$this->settings->connected()) return 'Not connected to Telegram.' . $droppedWords;
        $key = $this->settings->key();
        $chat = $this->settings->saved()['chat_id'];
        $username = $this->settings->saved()['username'];
        $address = $this->settings->address();
        $sent = 0;
        foreach ($this->messages->waiting(self::BATCH) as $message) {
            try {
                $this->telegram->send($address, $key, $chat, (string) $message['body']);
            } catch (TelegramFailed $failed) {
                $this->messages->markFailed((int) $message['id'], $failed->getMessage(), $username);

                return 'Sent ' . $sent . ', and the next could not go: ' . $failed->getMessage() . $droppedWords;
            }
            $this->messages->markSent((int) $message['id'], $username);
            $sent++;
        }

        return ($sent === 0 ? 'Nothing was waiting.' : 'Sent ' . $sent . ' message' . ($sent === 1 ? '' : 's') . '.') . $droppedWords;
    }
}
