Every minute: sends the waiting messages to the owner's Telegram, oldest first, and stops at the first failure, because
the rest would fail too. A message that fails stays and is tried next minute, with what went wrong beside it for Settings
to show. One still unsent after 7 days is dropped, because by then it tells nobody anything.

