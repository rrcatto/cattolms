declare(strict_types=1);

namespace CattoLearning\Maintenance;

use CattoLearning\Infrastructure\Persistence\Database;
use DateTimeImmutable;

final class ScheduledJobRepository
{
    private const TIME = 'Y-m-d H:i:sP';

    public function __construct(private readonly Database $db) {}

    public function started(ScheduledJob $job, DateTimeImmutable $at): void
    {
        $this->db->executeStatement(
            'INSERT INTO scheduled_jobs (job_key, last_started_at, run_count) VALUES (:job, :at, 1)
             ON CONFLICT (job_key) DO UPDATE SET last_started_at = EXCLUDED.last_started_at, run_count = scheduled_jobs.run_count + 1',
            ['job' => $job->value, 'at' => $at->format(self::TIME)]
        );
    }

    public function succeeded(ScheduledJob $job, DateTimeImmutable $at, string $summary): void
    {
        $this->db->executeStatement(
            'UPDATE scheduled_jobs SET last_finished_at = :at, last_succeeded_at = :at, last_summary = :summary WHERE job_key = :job',
            ['job' => $job->value, 'at' => $at->format(self::TIME), 'summary' => mb_substr($summary, 0, 1000)]
        );
    }

    public function failed(ScheduledJob $job, DateTimeImmutable $at, string $error): void
    {
        $this->db->executeStatement(
            'UPDATE scheduled_jobs SET last_finished_at = :at, last_failed_at = :at, last_error = :error WHERE job_key = :job',
            ['job' => $job->value, 'at' => $at->format(self::TIME), 'error' => mb_substr($error, 0, 1000)]
        );
    }

    /** @return array<string,array<string,mixed>> job key => its row, for the jobs that have run */
    public function all(): array
    {
        $rows = [];
        foreach ($this->db->fetchAllAssociative('SELECT * FROM scheduled_jobs ORDER BY job_key') as $row) {
            $rows[(string) $row['job_key']] = $row;
        }
        return $rows;
    }
}
