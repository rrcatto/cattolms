declare(strict_types=1);

namespace CattoLearning\Maintenance;

use DateTimeImmutable;
use Symfony\Component\Clock\ClockInterface;

final class ScheduledJobStatus
{
    public function __construct(private readonly ScheduledJobRepository $runs, private readonly ClockInterface $clock) {}

    /** @return list<array<string,mixed>> each job, in schedule order, with its last run in words */
    public function jobs(): array
    {
        $records = $this->runs->all();
        $jobs = [];
        foreach (ScheduledJob::cases() as $job) {
            $record = $records[$job->value] ?? [];
            $succeeded = self::time($record['last_succeeded_at'] ?? null);
            $failed = self::time($record['last_failed_at'] ?? null);
            $lastFailed = $failed !== null && ($succeeded === null || $failed > $succeeded);
            $jobs[] = [
                'key' => $job->value,
                'label' => $job->label(),
                'description' => $job->description(),
                'last_run' => $this->words(self::time($record['last_started_at'] ?? null)) ?? 'Never',
                'last_success' => $this->words($succeeded) ?? 'Never',
                'last_failure' => $lastFailed ? $this->words($failed) : null,
                'error' => $lastFailed ? (string) ($record['last_error'] ?? '') : '',
                'summary' => (string) ($record['last_summary'] ?? ''),
                'overdue' => $this->overdue($job, $succeeded),
            ];
        }
        return $jobs;
    }

    /** The dashboard's warning when the commerce job has stopped, or null while it runs. */
    public function commerceWarning(): ?string
    {
        $record = $this->runs->all()[ScheduledJob::Commerce->value] ?? [];
        $succeeded = self::time($record['last_succeeded_at'] ?? null);
        if (!$this->overdue(ScheduledJob::Commerce, $succeeded)) return null;
        if ($succeeded === null) {
            return 'Order emails are not being sent: the scheduled job that sends them has never run on this site.';
        }
        return 'Order emails have not been sent since ' . $this->words($succeeded) . '. The scheduled job that sends them has stopped.';
    }

    private function overdue(ScheduledJob $job, ?DateTimeImmutable $succeeded): bool
    {
        return $succeeded === null || $this->now()->getTimestamp() - $succeeded->getTimestamp() > $job->overdueAfter();
    }

    /** 10:42 today, else 18 October 2026 at 10:42. */
    private function words(?DateTimeImmutable $at): ?string
    {
        if ($at === null) return null;
        $local = $at->setTimezone($this->now()->getTimezone());
        return $local->format('Y-m-d') === $this->now()->format('Y-m-d') ? $local->format('H:i') : $local->format('j F Y \a\t H:i');
    }

    private function now(): DateTimeImmutable
    {
        return DateTimeImmutable::createFromInterface($this->clock->now());
    }

    private static function time(mixed $value): ?DateTimeImmutable
    {
        return is_string($value) && $value !== '' ? new DateTimeImmutable($value) : null;
    }
}
