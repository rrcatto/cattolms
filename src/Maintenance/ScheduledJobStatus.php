declare(strict_types=1);

namespace CattoLearning\Maintenance;

use CattoPHP\Scheduler\TaskStatus;

final class ScheduledJobStatus
{
    public const COMMERCE = 'commerce';

    public function __construct(private readonly TaskStatus $status) {}

    /** @return list<array{key:string,label:string,description:string,last_run:string,last_success:string,last_failure:?string,error:string,summary:string,overdue:bool,run_count:int}> each job, in schedule order, with its last run in words */
    public function jobs(): array
    {
        return $this->status->tasks();
    }

    /** The dashboard's warning when the commerce job has stopped, or null while it runs. */
    public function commerceWarning(): ?string
    {
        if (!$this->status->isOverdue(self::COMMERCE)) return null;
        $succeeded = $this->status->lastSucceeded(self::COMMERCE);
        if ($succeeded === null) {
            return 'Order emails are not being sent: the scheduled job that sends them has never run on this site.';
        }
        return 'Order emails have not been sent since ' . $this->status->words($succeeded) . '. The scheduled job that sends them has stopped.';
    }
}
