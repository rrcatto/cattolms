The one scheduler (owner, 2026-10-19). Each time it runs it starts every job that is due (ScheduledJob:
the commerce job every minute, the popularity calculation every hour, the clean-ups every day) and
records each run: when it started and finished, and what it did or why it failed. One job failing
never stops the others. schedule:run calls it once, or once a minute with --watch; an installation
runs it from cron every minute or under a supervisor (docs/OPERATIONS.md, "Scheduled work").

The status of each job, and whether the commerce job has stopped, is read by Settings > Maintenance
