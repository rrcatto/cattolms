The application log, archived every night (owner, 2026-10-27: "I think you should truncate the application log - I'm
just reading now that it is 4.5GB long. Can you have a scheduler run at least once a day around midnight, that archives
the log and truncates it? ... I don't want to burn space on keeping unnecessary logs.").

The log is storage/logs/application.log, where PHP writes every request and error (App::boot). Just after midnight the
scheduler's log_archive job moves it into storage/logs/archive, compresses it there as application-<the day it
holds>.log.gz and leaves an empty log in its place, with the same permissions. Nothing written is lost: PHP opens the
log for every line it writes, so a line written while the old log is being compressed starts the new one. Archives
older than the keep period are deleted (LOG_ARCHIVES_KEPT_FOR in .env, a length of time such as 2w, overridden at
Administration > Settings > Maintenance with a Reset, as every setting is). Every other log in storage/logs is archived
the same way under its own name: install.sh's cron line appends the scheduler's output to schedule.log, which would
otherwise grow for good.

Changelog:
2026/10/27 SAST
