declare(strict_types=1);

namespace CattoLearning\Maintenance;

use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;

#[AsCommand(name: 'schedule:run', description: 'Run the scheduled jobs that are due (orders and emails every minute, popularity every hour, clean-up every day).')]
final class ScheduleRunCommand extends Command
{
    public function __construct(private readonly Scheduler $scheduler)
    {
        parent::__construct();
    }

    protected function configure(): void
    {
        $this->addOption('watch', null, InputOption::VALUE_NONE, 'Run once a minute until stopped.');
        $this->addOption('job', null, InputOption::VALUE_REQUIRED, 'Run one job now, due or not: commerce, popularity, cleanup, signup_lists or mailing.');
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $only = null;
        if ($input->getOption('job') !== null) {
            $job = ScheduledJob::tryFrom((string) $input->getOption('job'));
            if ($job === null) {
                $output->writeln('<error>Choose a job: commerce, popularity or cleanup.</error>');
                return Command::INVALID;
            }
            $only = [$job];
        }
        $watch = (bool) $input->getOption('watch');
        do {
            $failed = false;
            foreach ($this->scheduler->run($only) as $key => $result) {
                $failed = $failed || !$result['ok'];
                $output->writeln(($result['ok'] ? '' : '<error>') . $key . ': ' . htmlspecialchars($result['summary']) . ($result['ok'] ? '' : '</error>'));
            }
            if (!$watch) return $failed ? Command::FAILURE : Command::SUCCESS;
            sleep(60);
        } while (true);
    }
}
