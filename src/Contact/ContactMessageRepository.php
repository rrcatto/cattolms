declare(strict_types=1);

namespace CattoLearning\Contact;

use CattoLearning\Infrastructure\Persistence\Database;
use DateTimeImmutable;
use JsonException;

final class ContactMessageRepository
{
    /** What the list shows, with the sender's account and the order's number and course's title. */
    private const LIST_SELECT = "SELECT m.id, m.reference, m.reason, m.sender_name, m.sender_email, m.user_id, m.account_reference,
            m.order_id, m.order_number, m.course_id, c.title AS course_title, c.slug AS course_slug, m.details, m.message,
            m.created_at, m.emailed_at, m.acknowledged_at, m.answered_at, m.answered_by_user_id,
            COALESCE(NULLIF(trim(concat_ws(' ', answerer.first_name, answerer.last_name)), ''), answerer.display_name) AS answered_by_name,
            answerer.account_reference AS answered_by_reference, sender.account_reference AS sender_reference
        FROM contact_messages m
        LEFT JOIN courses c ON c.id = m.course_id
        LEFT JOIN users sender ON sender.id = m.user_id
        LEFT JOIN users answerer ON answerer.id = m.answered_by_user_id";

    public function __construct(private readonly Database $db) {}

    /**
     * Keeps a message and gives it its reference, MSG- and its number.
     *
     * @param array{reason:string,sender_name:string,sender_email:string,user_id:?int,account_reference:?string,order_id:?int,order_number:?string,course_id:?int,details:array<string,string>,message:string} $message
     * @return array{id:int,reference:string}
     * @throws JsonException
     */
    public function create(array $message): array
    {
        $row = $this->db->fetchAssociative(
            "WITH next AS (SELECT nextval(pg_get_serial_sequence('contact_messages', 'id')) AS id)
             INSERT INTO contact_messages (id, reference, reason, sender_name, sender_email, user_id, account_reference, order_id, order_number, course_id, details, message)
             SELECT next.id, 'MSG-' || lpad(next.id::text, 6, '0'), :reason, :sender_name, :sender_email, :user_id, :account_reference, :order_id, :order_number, :course_id, CAST(:details AS JSONB), :message
               FROM next
             RETURNING id, reference",
            ['reason' => $message['reason'], 'sender_name' => $message['sender_name'], 'sender_email' => $message['sender_email'],
                'user_id' => $message['user_id'], 'account_reference' => $message['account_reference'], 'order_id' => $message['order_id'],
                'order_number' => $message['order_number'], 'course_id' => $message['course_id'],
                'details' => json_encode((object) $message['details'], JSON_THROW_ON_ERROR | JSON_UNESCAPED_UNICODE), 'message' => $message['message']]
        );
        if ($row === false) throw new \RuntimeException('The message could not be kept.');
        return ['id' => (int) $row['id'], 'reference' => (string) $row['reference']];
    }

    public function markEmailed(int $id): void
    {
        $this->db->executeStatement('UPDATE contact_messages SET emailed_at = NOW() WHERE id = :id AND emailed_at IS NULL', ['id' => $id]);
    }

    public function markAcknowledged(int $id): void
    {
        $this->db->executeStatement('UPDATE contact_messages SET acknowledged_at = NOW() WHERE id = :id AND acknowledged_at IS NULL', ['id' => $id]);
    }

    /** Marks a message answered once. False when it already was. */
    public function markAnswered(int $id, int $actorId): bool
    {
        return $this->db->executeStatement(
            'UPDATE contact_messages SET answered_at = NOW(), answered_by_user_id = :actor WHERE id = :id AND answered_at IS NULL',
            ['id' => $id, 'actor' => $actorId]
        ) === 1;
    }

    /** @return array<string,mixed>|null */
    public function find(int $id): ?array
    {
        $row = $this->db->fetchAssociative(self::LIST_SELECT . ' WHERE m.id = :id', ['id' => $id]);
        return $row === false ? null : $row;
    }

    /**
     * One page of messages, newest first.
     *
     * @param 'new'|'answered'|'all' $status
     * @return list<array<string,mixed>>
     */
    public function page(string $status, string $reason, string $search, int $limit, int $offset): array
    {
        [$where, $params] = $this->filters($status, $reason, $search);
        return $this->db->fetchAllAssociative(self::LIST_SELECT . $where . ' ORDER BY m.created_at DESC, m.id DESC LIMIT :limit OFFSET :offset',
            $params + ['limit' => $limit, 'offset' => $offset]);
    }

    /** @param 'new'|'answered'|'all' $status */
    public function count(string $status, string $reason, string $search): int
    {
        [$where, $params] = $this->filters($status, $reason, $search);
        return (int) $this->db->fetchOne('SELECT COUNT(*) FROM contact_messages m' . $where, $params);
    }

    /** Messages not answered yet, for the menu. */
    public function unansweredCount(): int
    {
        return (int) $this->db->fetchOne('SELECT COUNT(*) FROM contact_messages WHERE answered_at IS NULL');
    }

    /** The daily clean-up: deletes messages sent before the moment given. */
    public function deleteBefore(DateTimeImmutable $before): int
    {
        return $this->db->executeStatement('DELETE FROM contact_messages WHERE created_at < :before', ['before' => $before->format('Y-m-d H:i:sP')]);
    }

    /**
     * The published courses a message may be about, by title.
     *
     * @return list<array{id:int,slug:string,title:string}>
     */
    public function publishedCourses(): array
    {
        return array_map(static fn(array $row): array => ['id' => (int) $row['id'], 'slug' => (string) $row['slug'], 'title' => (string) $row['title']],
            $this->db->fetchAllAssociative("SELECT id, slug, title FROM courses WHERE status = 'published' ORDER BY lower(title), id"));
    }

    /**
     * A signed-in sender's own orders, newest first, for choosing the one a message is about.
     *
     * @return list<array<string,mixed>>
     */
    public function ordersOf(int $userId): array
    {
        return $this->db->fetchAllAssociative(
            'SELECT id, state, total_minor, currency, placed_at FROM commerce_orders WHERE purchaser_user_id = :user ORDER BY id DESC LIMIT 100',
            ['user' => $userId]
        );
    }

    /** @return array{0:string,1:array<string,mixed>} */
    private function filters(string $status, string $reason, string $search): array
    {
        $where = [];
        $params = [];
        if ($status === 'new') $where[] = 'm.answered_at IS NULL';
        if ($status === 'answered') $where[] = 'm.answered_at IS NOT NULL';
        if (ContactReason::valid($reason)) {
            $where[] = 'm.reason = :reason';
            $params['reason'] = $reason;
        }
        $search = trim($search);
        if ($search !== '') {
            $where[] = '(m.reference ILIKE :search OR m.sender_name ILIKE :search OR m.sender_email ILIKE :search OR m.account_reference ILIKE :search OR m.order_number ILIKE :search)';
            $params['search'] = '%' . addcslashes($search, '%_\\') . '%';
        }
        return [$where === [] ? '' : ' WHERE ' . implode(' AND ', $where), $params];
    }
}
