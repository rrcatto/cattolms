    /** What a message is about in cattolms's terms: its order (or the number typed) and its course. */
    public function saveSubject(int $messageId, ?int $orderId, ?string $orderNumber, ?int $courseId): void
    {
        if ($orderId === null && $orderNumber === null && $courseId === null) return;
        $this->db->executeStatement(
            'INSERT INTO contact_message_subjects (message_id, order_id, order_number, course_id) VALUES (:id, :order_id, :order_number, :course_id)
             ON CONFLICT (message_id) DO UPDATE SET order_id = EXCLUDED.order_id, order_number = EXCLUDED.order_number, course_id = EXCLUDED.course_id',
            ['id' => $messageId, 'order_id' => $orderId, 'order_number' => $orderNumber, 'course_id' => $courseId]
        );
    }

    /** @return array<string,mixed>|null */
    public function find(int $id): ?array
    {
        $row = $this->db->fetchAssociative(str_replace(['%SENDER%', '%ANSWERER%'], [sprintf(self::PERSON, 'm.account', 'm.account'), sprintf(self::PERSON, 'm.answered_by', 'm.answered_by')], self::LIST_SELECT) . ' WHERE m.id = :id', ['id' => $id]);
