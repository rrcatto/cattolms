namespace CattoLearning\Contact;

use CattoLearning\Infrastructure\Persistence\Database;

final class ContactMessageRepository
{
    /** A person by their account, the user id in text. */
    private const PERSON = "CASE WHEN %s ~ '^[0-9]+$' THEN CAST(%s AS BIGINT) END";

    /** What a message's page shows, with the sender's account, the order's number and the course's title. */
    private const LIST_SELECT = "SELECT m.id, m.reference, m.reason, m.sender_name, m.sender_email, %SENDER% AS user_id, m.account_reference,
            s.order_id, s.order_number, s.course_id, c.title AS course_title, c.code AS course_code, c.slug AS course_slug, m.details, m.message,
            m.created_at, m.emailed_at, m.acknowledged_at, m.answered_at, %ANSWERER% AS answered_by_user_id,
            COALESCE(NULLIF(trim(concat_ws(' ', answerer.first_name, answerer.last_name)), ''), answerer.display_name) AS answered_by_name,
            answerer.account_reference AS answered_by_reference, sender.account_reference AS sender_reference
        FROM cattophp_inbox_conversations m
        LEFT JOIN contact_message_subjects s ON s.message_id = m.id
