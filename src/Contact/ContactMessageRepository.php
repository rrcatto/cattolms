        return array_map(static fn(array $row): array => ['id' => (int) $row['id'], 'slug' => (string) $row['slug'], 'title' => (string) $row['title']],
            $this->db->fetchAllAssociative("SELECT id, slug, title FROM courses WHERE status = 'published' ORDER BY lower(title), id"));
    }

    /**
     * A signed-in sender's own orders, newest first, for choosing the one a message is about.
     *
     * @return list<array<string,mixed>>
     */
    public function ordersOf(int $userId): array
    {
        return $this->db->fetchAllAssociative(
            'SELECT id, state, total_minor, currency, placed_at FROM commerce_orders WHERE purchaser_user_id = :user ORDER BY id DESC LIMIT 100',
            ['user' => $userId]
        );
    }

