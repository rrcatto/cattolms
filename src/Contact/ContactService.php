/*
Generated by: Claude Code CLI

Date time: 2026/10/20 SAST

Version: 0.9.6

Description:
The contact form (owner, 2026-10-20): one form whose fields follow the reason chosen.

- Everyone gives a reason, their name, their email address and a message.
- A signed-in sender's name, email and account reference come from their account, and the account
  reference is taken from the account, never from the form. They choose the order a message is
  about from their own orders.
- A sender who is not signed in may type an account reference, checked by its check character, and an
  order number, checked for its shape only. Neither is looked up for them, so the form never says
  whether an account or an order exists.
- Each reason's own fields are read only for that reason (ContactReason).
- The message is kept (contact_messages) and given its reference, then emailed to the site (reply-to the
  sender) and acknowledged to the sender. A failed email loses nothing: Administration lists every
  message and shows whether each was emailed. The acknowledgement holds only fixed words and the
  reference, never what the sender typed, so the form cannot be used to send someone else words.
- Pages link to a reason with what they know filled in: /contact?reason=order&order=CL-00000012,
  /contact?reason=course&course=a-slug.
- ADMIN lists, opens and marks messages answered (PLATFORM.PERSON.VIEW / MANAGE).

Changelog:
2026/10/20 SAST
- Created, in place of the name, email, subject and message form that only emailed.
*/

declare(strict_types=1);

namespace CattoLearning\Contact;

use CattoLearning\Auth\CurrentUser;
use CattoLearning\Infrastructure\Mail\MailerInterface;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Infrastructure\Persistence\UserRepository;
use CattoLearning\Support\AccountReference;
use CattoLearning\Support\Env;
use CattoLearning\Support\Money;
use DateTimeImmutable;
use InvalidArgumentException;
use Throwable;

final class ContactService
{
    /** The form's fields, kept as typed when a message is refused for a mistake. */
    public const FIELDS = ['reason', 'name', 'email', 'account_reference', 'buying_course_id', 'course_id', 'for_company', 'company_name', 'learners', 'account_topic',
        'order_topic', 'order_id', 'order_number', 'eft_paid_on', 'eft_amount', 'eft_reference', 'where', 'message'];

    /** How an order number looks: CL- and eight digits. */
    private const ORDER_NUMBER = '/^CL-?(\d{8})$/i';

    public function __construct(
        private readonly ContactMessageRepository $messages,
        private readonly UserRepository $users,
        private readonly MailerInterface $mailer,
        private readonly AuditRepository $audit,
        private readonly TransactionManager $transactions,
    ) {}

    /** An order's number as people see it. */
    public static function orderNumber(int $orderId): string
    {
        return 'CL-' . str_pad((string) $orderId, 8, '0', STR_PAD_LEFT);
    }

    /**
     * What the form shows: the reasons and their fields' choices, filled in from the account of a signed-in
     * sender and from the address (reason, course, order).
     *
     * @param array<string,mixed> $query
     * @param array<string,string> $draft a refused message, as it was typed
     * @return array<string,mixed>
     */
    public function form(?CurrentUser $user, array $query, array $draft = []): array
    {
        $reason = (string) ($draft['reason'] ?? $query['reason'] ?? '');
        $courses = $this->messages->publishedCourses();
        $courseSlug = (string) ($query['course'] ?? '');
        $courseId = '';
        foreach ($courses as $course) if ($course['slug'] === $courseSlug) $courseId = (string) $course['id'];
        $orderNumber = strtoupper(trim((string) ($draft['order_number'] ?? $query['order'] ?? '')));
        $chosenOrder = (string) ($draft['order_id'] ?? '');
        $orders = [];
        $account = null;
        if ($user !== null) {
            $profile = $this->users->profile($user->id) ?? [];
            $account = ['name' => $user->displayName, 'email' => $user->primaryEmail, 'reference' => AccountReference::format((string) ($profile['account_reference'] ?? ''))];
            foreach ($this->messages->ordersOf($user->id) as $order) {
                $number = self::orderNumber((int) $order['id']);
                $orders[] = ['value' => (string) $order['id'], 'number' => $number, 'selected' => $chosenOrder !== '' ? $chosenOrder === (string) $order['id'] : $number === $orderNumber,
                    'label' => $number . ', ' . (new DateTimeImmutable((string) $order['placed_at']))->format('j M Y') . ', ' . Money::strictMinorUnits((int) $order['total_minor'], (string) $order['currency'])->format()];
            }
        }
        return [
            'reasons' => array_map(static fn(string $key, string $label): array => ['value' => $key, 'label' => $label, 'note' => ContactReason::NOTES[$key], 'selected' => $key === $reason], array_keys(ContactReason::LABELS), ContactReason::LABELS),
            'reason' => ContactReason::valid($reason) ? $reason : '',
            'account_topics' => array_map(static fn(string $key, string $label): array => ['value' => $key, 'label' => $label, 'note' => ContactReason::ACCOUNT_TOPIC_NOTES[$key]], array_keys(ContactReason::ACCOUNT_TOPICS), ContactReason::ACCOUNT_TOPICS),
            'order_topics' => array_map(static fn(string $key, string $label): array => ['value' => $key, 'label' => $label, 'note' => ContactReason::ORDER_TOPIC_NOTES[$key]], array_keys(ContactReason::ORDER_TOPICS), ContactReason::ORDER_TOPICS),
            'courses' => $courses,
            'course_id' => $courseId,
            'orders' => $orders,
            'order_number' => $user === null && (isset($draft['order_number']) || preg_match(self::ORDER_NUMBER, $orderNumber) === 1) ? $orderNumber : '',
            'account' => $account,
            'draft' => array_fill_keys(self::FIELDS, '') + array_map('strval', $draft),
        ];
    }

    /**
     * Checks and keeps a message, then emails it to the site and acknowledges it to the sender.
     *
     * @param array<string,mixed> $input the posted form
     * @return string the message's reference
     */
    public function submit(?CurrentUser $user, array $input): string
    {
        $text = static fn(string $name, int $max): string => mb_substr(trim(is_string($input[$name] ?? null) ? $input[$name] : ''), 0, $max + 1);
        $reason = $text('reason', 20);
        if (!ContactReason::valid($reason)) throw new InvalidArgumentException('Choose what your message is about.');
        $name = $text('name', 120);
        if ($name === '' || mb_strlen($name) > 120) throw new InvalidArgumentException('Enter your name, in at most 120 characters.');
        $email = $text('email', 254);
        if (filter_var($email, FILTER_VALIDATE_EMAIL) === false || mb_strlen($email) > 254) throw new InvalidArgumentException('Enter a valid email address.');
        $message = $text('message', 5000);
        if ($message === '' || mb_strlen($message) > 5000) throw new InvalidArgumentException('Enter your message, in at most 5,000 characters.');

        // The account reference: a signed-in sender's from their account, anyone else's as typed, checked.
        $accountReference = null;
        if ($user !== null) {
            $stored = (string) (($this->users->profile($user->id) ?? [])['account_reference'] ?? '');
            $accountReference = $stored !== '' ? AccountReference::format($stored) : null;
        } elseif ($text('account_reference', 40) !== '') {
            $accountReference = AccountReference::format(AccountReference::parse($text('account_reference', 40)));
        }

        $courses = [];
        foreach ($this->messages->publishedCourses() as $course) $courses[(string) $course['id']] = $course;
        $courseId = null;
        $orderId = null;
        $orderNumber = null;
        $details = [];
        if ($reason === ContactReason::BEFORE_BUYING || $reason === ContactReason::COURSE) {
            // Each reason has its own course list, so a form shown without JavaScript sends both.
            $chosen = $text($reason === ContactReason::BEFORE_BUYING ? 'buying_course_id' : 'course_id', 20);
            if ($chosen !== '') {
                if (!isset($courses[$chosen])) throw new InvalidArgumentException('Choose a course from the list.');
                $courseId = (int) $chosen;
            }
        }
        if ($reason === ContactReason::BEFORE_BUYING && ($input['for_company'] ?? '') === 'yes') {
            $company = $text('company_name', 160);
            if ($company === '' || mb_strlen($company) > 160) throw new InvalidArgumentException('Enter your company\'s name, in at most 160 characters.');
            $details['company_name'] = $company;
            $learners = $text('learners', 10);
            if ($learners !== '') {
                if (preg_match('/^\d{1,6}$/', $learners) !== 1 || (int) $learners < 1) throw new InvalidArgumentException('Enter how many people need the course as a whole number.');
                $details['learners'] = (string) (int) $learners;
            }
        }
        if ($reason === ContactReason::ACCOUNT) {
            $topic = $text('account_topic', 20);
            if (!isset(ContactReason::ACCOUNT_TOPICS[$topic])) throw new InvalidArgumentException('Choose what your account question is about.');
            $details['topic'] = $topic;
        }
        if ($reason === ContactReason::ORDER) {
            $topic = $text('order_topic', 20);
            if (!isset(ContactReason::ORDER_TOPICS[$topic])) throw new InvalidArgumentException('Choose what your order question is about.');
            $details['topic'] = $topic;
            if ($user !== null) {
                $chosen = $text('order_id', 20);
                if ($chosen !== '') {
                    $own = array_map(static fn(array $order): string => (string) $order['id'], $this->messages->ordersOf($user->id));
                    if (!in_array($chosen, $own, true)) throw new InvalidArgumentException('Choose one of your orders from the list.');
                    $orderId = (int) $chosen;
                    $orderNumber = self::orderNumber($orderId);
                }
            } elseif ($text('order_number', 20) !== '') {
                if (preg_match(self::ORDER_NUMBER, $text('order_number', 20), $digits) !== 1) throw new InvalidArgumentException('An order number looks like CL-00000012.');
                $orderNumber = 'CL-' . $digits[1];
            }
            // The EFT payment, as the bank statement shows it: what ADMIN needs to match the money.
            $paidOn = $text('eft_paid_on', 10);
            if ($paidOn !== '') {
                if (preg_match('/^(\d{4})-(\d{2})-(\d{2})$/', $paidOn, $date) !== 1 || !checkdate((int) $date[2], (int) $date[3], (int) $date[1]) || $paidOn > (new DateTimeImmutable())->format('Y-m-d')) {
                    throw new InvalidArgumentException('Enter the day you paid as a real date, not in the future.');
                }
                $details['eft_paid_on'] = $paidOn;
            }
            $amount = $text('eft_amount', 30);
            if ($amount !== '') {
                if (preg_match('/^R?\s*\d{1,3}([ ,]?\d{3})*([.,]\d{1,2})?$/i', $amount) !== 1) throw new InvalidArgumentException('Enter the amount you paid, for example R1 200.00.');
                $details['eft_amount'] = $amount;
            }
            $paidWith = $text('eft_reference', 80);
            if ($paidWith !== '') $details['eft_reference'] = mb_substr($paidWith, 0, 80);
        }
        if ($reason === ContactReason::COURSE) {
            $where = $text('where', 200);
            if ($where !== '') $details['where'] = mb_substr($where, 0, 200);
        }

        $kept = $this->transactions->run(fn(): array => $this->messages->create([
            'reason' => $reason, 'sender_name' => $name, 'sender_email' => $email, 'user_id' => $user?->id,
            'account_reference' => $accountReference, 'order_id' => $orderId, 'order_number' => $orderNumber,
            'course_id' => $courseId, 'details' => $details, 'message' => $message,
        ]));

        $mail = ['reference' => $kept['reference'], 'reason' => ContactReason::label($reason), 'name' => $name, 'email' => $email,
            'account_reference' => $accountReference ?? '', 'signed_in' => $user !== null, 'order_number' => $orderNumber ?? '',
            'course' => $courseId !== null ? (string) $courses[(string) $courseId]['title'] : '', 'details' => $this->detailLines($reason, $details),
            'message' => $message, 'admin_url' => rtrim(Env::string('APP_URL'), '/') . '/admin/messages/' . $kept['id']];
        try {
            $this->mailer->sendContactMessage($mail);
            $this->messages->markEmailed($kept['id']);
        } catch (Throwable $failed) {
            error_log('Contact message ' . $kept['reference'] . ' could not be emailed: ' . $failed->getMessage());
        }
        try {
            $this->mailer->sendContactAcknowledgement($email, $kept['reference'], ContactReason::label($reason));
            $this->messages->markAcknowledged($kept['id']);
        } catch (Throwable $failed) {
            error_log('Contact message ' . $kept['reference'] . ' could not be acknowledged: ' . $failed->getMessage());
        }
        return $kept['reference'];
    }

    /**
     * Administration's list: a page of messages with what each row shows.
     *
     * @param 'new'|'answered'|'all' $status
     * @return list<array<string,mixed>>
     */
    public function page(string $status, string $reason, string $search, int $limit, int $offset): array
    {
        return array_map(fn(array $row): array => $this->view($row), $this->messages->page($status, $reason, $search, $limit, $offset));
    }

    /** @param 'new'|'answered'|'all' $status */
    public function count(string $status, string $reason, string $search): int
    {
        return $this->messages->count($status, $reason, $search);
    }

    public function unansweredCount(): int
    {
        return $this->messages->unansweredCount();
    }

    /** @return array<string,mixed>|null one message, as its page shows it */
    public function find(int $id): ?array
    {
        $row = $this->messages->find($id);
        return $row === null ? null : $this->view($row);
    }

    public function markAnswered(int $id, int $actorId): void
    {
        $this->transactions->run(function () use ($id, $actorId): void {
            if ($this->messages->find($id) === null) throw new InvalidArgumentException('That message does not exist.');
            if ($this->messages->markAnswered($id, $actorId)) $this->audit->record($actorId, 'contact.message_answered', ['message_id' => $id]);
        });
    }

    /**
     * @param array<string,mixed> $row
     * @return array<string,mixed>
     */
    private function view(array $row): array
    {
        $details = is_string($row['details'] ?? null) ? (json_decode($row['details'], true) ?: []) : [];
        $row['details'] = is_array($details) ? array_map('strval', $details) : [];
        $row['reason_label'] = ContactReason::label((string) $row['reason']);
        $row['detail_lines'] = $this->detailLines((string) $row['reason'], $row['details']);
        $row['received'] = (new DateTimeImmutable((string) $row['created_at']))->format('j M Y H:i');
        $row['answered'] = $row['answered_at'] !== null;
        $row['status_label'] = $row['answered'] ? 'Answered' : 'New';
        $row['status_tone'] = $row['answered'] ? 'success' : 'warning';
        $row['href'] = '/admin/messages/' . (int) $row['id'];
        $row['excerpt'] = mb_strlen((string) $row['message']) > 120 ? rtrim(mb_substr((string) $row['message'], 0, 117)) . '...' : (string) $row['message'];
        // The sender and whoever answered, as data.person's props (owner, 2026-10-21: every person named is linked to their
        // account, with their account reference). A sender without an account is their name alone.
        $row['sender'] = $row['user_id'] !== null
            ? ['name' => (string) $row['sender_name'], 'reference' => (string) ($row['sender_reference'] ?? ''), 'href' => '/admin/people/' . (int) $row['user_id']]
            : ['name' => (string) $row['sender_name'], 'reference' => '', 'href' => ''];
        $row['answered_by'] = $row['answered_by_user_id'] !== null
            ? ['name' => (string) ($row['answered_by_name'] ?? '') ?: 'User ' . (int) $row['answered_by_user_id'], 'reference' => (string) ($row['answered_by_reference'] ?? ''), 'href' => '/admin/people/' . (int) $row['answered_by_user_id']]
            : null;
        return $row;
    }

    /**
     * The reason's own answers in words, in the order the form asks them.
     *
     * @param array<string,string> $details
     * @return list<array{label:string,value:string}>
     */
    private function detailLines(string $reason, array $details): array
    {
        $lines = [];
        if (isset($details['topic'])) $lines[] = ['label' => 'About', 'value' => ContactReason::topicLabel($reason, $details['topic'])];
        foreach (['company_name' => 'Company', 'learners' => 'People who need the course', 'eft_paid_on' => 'EFT paid on', 'eft_amount' => 'EFT amount',
            'eft_reference' => 'EFT reference used', 'where' => 'Where in the course'] as $key => $label) {
            if (($details[$key] ?? '') !== '') $lines[] = ['label' => $label, 'value' => $details[$key]];
        }
        return $lines;
    }
}
