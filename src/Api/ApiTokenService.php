namespace CattoLearning\Api;

use CattoLearning\Infrastructure\Persistence\ApiTokenRepository;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\UserRepository;
use CattoLearning\Support\EmailAddress;
use CattoLearning\Support\Token;
use InvalidArgumentException;

final class ApiTokenService
