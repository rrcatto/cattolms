    /**
     * @param list<string> $scopes
     * @return array{token:string,public_id:string,expires_in:?int,scopes:list<string>}
     */
    public function createForVerifiedEmail(
        string $email,
        string $name,
        array $scopes,
        ?int $ttlSeconds = null
    ): array {
        $email = EmailAddress::normalize($email);
        $name = trim($name);
        if ($name === '' || mb_strlen($name) > 120) {
            throw new InvalidArgumentException('Enter a token name of no more than 120 characters.');
        }

        $scopes = array_values(array_unique(array_map('trim', $scopes)));
        foreach ($scopes as $scope) {
            if (!ApiScope::isValid($scope)) {
                throw new InvalidArgumentException('Unknown API scope: ' . $scope);
            }
        }
        if ($scopes === []) {
            throw new InvalidArgumentException('At least one API scope is required.');
        }
        if ($ttlSeconds !== null && $ttlSeconds < 60) {
            throw new InvalidArgumentException('Token lifetime must be at least 60 seconds.');
        }

        $user = $this->users->findByVerifiedEmail($email);
        if ($user === null) {
            throw new InvalidArgumentException('No active verified user exists for that email address.');
        }

        $rawToken = 'clpat_' . Token::generate();
        $publicId = $this->tokens->create(
            (int) $user['id'],
            $name,
            Token::hash($rawToken),
            $scopes,
            (int) $user['id'],
            $ttlSeconds
        );
        $this->audit->record((int) $user['id'], 'api.token_created', [
            'token_id' => $publicId,
            'name' => $name,
            'scopes' => $scopes,
        ]);

        return [
            'token' => $rawToken,
            'public_id' => $publicId,
            'expires_in' => $ttlSeconds,
            'scopes' => $scopes,
        ];
    }

