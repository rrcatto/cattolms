namespace CattoLearning\Api;

use CattoLearning\Infrastructure\Persistence\Database;
use CattoPHP\Api\ApiAccounts;

final class ApiAccountRepository implements ApiAccounts
{
    public function __construct(private readonly Database $db)
    {
    }

    /** @return array<string,mixed>|null */
    public function find(string $accountId): ?array
    {
        if (!ctype_digit($accountId)) return null;
        $row = $this->db->fetchAssociative(
            "SELECT u.public_id, ue.email FROM users u
               JOIN user_emails ue ON ue.user_id = u.id AND ue.is_primary = TRUE AND ue.verified_at IS NOT NULL
              WHERE u.id = :id AND u.status = 'active' LIMIT 1",
            ['id' => (int) $accountId]
        );
        return $row === false ? null : ['name' => (string) $row['email'], 'email' => (string) $row['email'], 'public_id' => (string) $row['public_id']];
    }
}
