namespace CattoLearning\Api;


final class AuthorizationService
{
    public function requireScope(ApiIdentity $identity, string $scope): void
    {
        if (!$identity->hasScope($scope)) {
            throw new AuthorizationException('The API token does not grant the required scope.');
        }
    }

    public function requireRole(ApiIdentity $identity, string $role): void
    {
        if (!$identity->hasRole($role)) {
            throw new AuthorizationException('The authenticated account does not have the required role.');
        }
    }

    public function requirePlatformAdministrator(ApiIdentity $identity, string $scope): void
    {
        $this->requireScope($identity, $scope);
        $this->requireRole($identity, 'platform_admin');
    }
}