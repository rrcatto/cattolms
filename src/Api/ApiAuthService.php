declare(strict_types=1);

namespace CattoLearning\Api;

use CattoLearning\Infrastructure\Persistence\ApiTokenRepository;
use CattoLearning\Infrastructure\Persistence\RoleRepository;
use CattoLearning\Support\Token;

final class ApiAuthService
{
    public function __construct(
        private readonly ApiTokenRepository $tokens,
        private readonly RoleRepository $roles
    ) {
    }

    public function authenticateBearer(?string $authorizationHeader): ApiIdentity
    {
        $header = trim((string) $authorizationHeader);
        if (!preg_match('/^Bearer\s+(.+)$/i', $header, $matches)) {
            throw new AuthenticationException('A Bearer API token is required.');
        }

        return $this->authenticateToken(trim($matches[1]));
    }

    public function authenticateToken(string $rawToken): ApiIdentity
    {
        if ($rawToken === '') {
            throw new AuthenticationException('The API token is missing.');
        }

        $row = $this->tokens->findActiveByHash(Token::hash($rawToken));
        if ($row === null) {
            throw new AuthenticationException('The API token is invalid, expired or revoked.');
        }

        $scopes = json_decode((string) ($row['scopes'] ?? '[]'), true);
        $scopes = is_array($scopes)
            ? array_values(array_filter($scopes, 'is_string'))
            : [];

        $this->tokens->touch((int) $row['id']);

        return new ApiIdentity(
            (int) $row['user_id'],
            (string) $row['user_public_id'],
            (string) $row['primary_email'],
            $this->roles->roles((int) $row['user_id']),
            $this->roles->permissionsForUser((int) $row['user_id']),
            $scopes,
            (string) $row['public_id']
        );
    }
}