use Symfony\Component\HttpFoundation\JsonResponse;

final class ApiProblem
{
    public static function response(int $status, string $code, string $message): JsonResponse
    {
        $response = new JsonResponse([
            'error' => [
                'status' => $status,
                'code' => $code,
                'message' => $message,
            ],
        ], $status, [], false);
