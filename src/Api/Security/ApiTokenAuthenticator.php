declare(strict_types=1);

namespace CattoLearning\Api\Security;

use CattoLearning\Api\ApiAuthService;
use CattoLearning\Api\AuthenticationException as PlatformAuthenticationException;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Security\Core\Authentication\Token\TokenInterface;
use Symfony\Component\Security\Core\Exception\AuthenticationException;
use Symfony\Component\Security\Core\Exception\CustomUserMessageAuthenticationException;
use Symfony\Component\Security\Http\Authenticator\AbstractAuthenticator;
use Symfony\Component\Security\Http\Authenticator\Passport\Badge\UserBadge;
use Symfony\Component\Security\Http\Authenticator\Passport\Passport;
use Symfony\Component\Security\Http\Authenticator\Passport\SelfValidatingPassport;
use Symfony\Component\Security\Http\EntryPoint\AuthenticationEntryPointInterface;

final class ApiTokenAuthenticator extends AbstractAuthenticator implements AuthenticationEntryPointInterface
{
    public function __construct(private readonly ApiAuthService $apiAuth)
    {
    }

    /**
     * Every request the firewall covers is a candidate.
     *
     * Returning false for a request without an Authorization header would let it through as
     * anonymous, and the route's authorization attributes would then be the only thing standing
     * between an unauthenticated caller and the data. Refusing here means the token is required by
     * the firewall rather than by remembering to annotate a controller.
     */
    public function supports(Request $request): ?bool
    {
        return true;
    }

    public function authenticate(Request $request): Passport
    {
        $header = (string) $request->headers->get('Authorization', '');

        try {
            $identity = $this->apiAuth->authenticateBearer($header);
        } catch (PlatformAuthenticationException $exception) {
            // The platform's message is the one clients have always been shown - which token
            // problem it was, in its own words - so it is carried through rather than replaced.
            throw new CustomUserMessageAuthenticationException($exception->getMessage(), [], 0, $exception);
        }

        return new SelfValidatingPassport(
            new UserBadge($identity->userPublicId, static fn(): ApiUser => new ApiUser($identity))
        );
    }

    public function onAuthenticationSuccess(Request $request, TokenInterface $token, string $firewallName): ?Response
    {
        return null;
    }

    /**
     * Only a message this platform wrote is shown to the caller.
     *
     * Symfony's own authentication exceptions carry internal wording that says more about the
     * framework than about the request, so anything that is not one of ours is reported as the
     * plain token refusal the API has always returned.
     */
    public function onAuthenticationFailure(Request $request, AuthenticationException $exception): Response
    {
        return $this->refuse($exception instanceof CustomUserMessageAuthenticationException
            ? $exception->getMessage()
            : 'The API token is invalid, expired or revoked.');
    }

    public function start(Request $request, ?AuthenticationException $authException = null): Response
    {
        return $this->refuse($authException?->getMessage() ?? 'A Bearer API token is required.');
    }

    private function refuse(string $message): Response
    {
        $response = ApiProblem::response(401, 'unauthenticated', $message);
        $response->headers->set('WWW-Authenticate', 'Bearer');

        return $response;
    }
}
