declare(strict_types=1);

namespace CattoLearning\Api\Security;

use CattoLearning\Api\AuthorizationException;
use InvalidArgumentException;
use RuntimeException;
use Symfony\Component\EventDispatcher\EventSubscriberInterface;
use Symfony\Component\HttpKernel\Event\ExceptionEvent;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;
use Symfony\Component\HttpKernel\KernelEvents;
use Symfony\Component\Security\Core\Exception\AccessDeniedException;
use Throwable;

final class ApiExceptionListener implements EventSubscriberInterface
{
    /** @return array<string,array{0:string,1:int}> */
    public static function getSubscribedEvents(): array
    {
        // Ahead of Symfony's own ErrorListener, which would otherwise render the HTML error page.
        return [KernelEvents::EXCEPTION => ['onException', 32]];
    }

    public function onException(ExceptionEvent $event): void
    {
        if (!str_starts_with($event->getRequest()->getPathInfo(), '/api/')) {
            return;
        }

        $event->setResponse($this->responseFor($event->getThrowable()));
    }

    private function responseFor(Throwable $exception): \Symfony\Component\HttpFoundation\JsonResponse
    {
        return match (true) {
            $exception instanceof AccessDeniedException,
            $exception instanceof AuthorizationException
                => ApiProblem::response(403, 'forbidden', $this->forbiddenMessage($exception)),
            $exception instanceof NotFoundHttpException
                => ApiProblem::response(404, 'not_found', $exception->getMessage() ?: 'The requested resource does not exist.'),
            $exception instanceof InvalidArgumentException
                => ApiProblem::response(422, 'invalid_request', $exception->getMessage()),
            $exception instanceof RuntimeException
                => ApiProblem::response(409, 'request_failed', $exception->getMessage()),
            default => $this->serverError($exception),
        };
    }

    /**
     * Symfony's AccessDeniedException says "Access Denied.", which tells a client nothing about
     * which of the two checks refused it. The platform's own wording is used where there is one.
     */
    private function forbiddenMessage(Throwable $exception): string
    {
        return $exception instanceof AuthorizationException
            ? $exception->getMessage()
            : 'The authenticated account does not have the required permission.';
    }

    private function serverError(Throwable $exception): \Symfony\Component\HttpFoundation\JsonResponse
    {
        error_log($exception->__toString());

        return ApiProblem::response(500, 'server_error', 'An unexpected error occurred.');
    }
}
