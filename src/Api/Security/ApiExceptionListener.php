Turns an exception raised under /api/ into the API's error document.

Architectural boundary: HTTP edge. It maps exception classes to status codes and formats; it makes
no authorization decision and runs no business rule.

The mapping is the one BaseApiController::execute() has applied since the interface existed, kept
exactly: a refused permission is 403 forbidden, a bad argument is 422 invalid_request, a rule the
platform will not break is 409 request_failed, and anything else is logged and reported as 500
server_error without its message. Clients parse these codes, so the port had to preserve them
rather than adopt Symfony's defaults.

It is a listener rather than a base-class method because it also covers what a base class cannot:
an exception thrown by the framework between routing and the controller.

