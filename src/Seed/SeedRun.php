    /** @param array{first:string,last:string,name:string} $person */
    private function buy(int $userId, array $person): void
    {
        $actor = $this->actor($userId);
        $offers = $this->seeds->bundleOffersOnSale();
        $bundle = $offers !== [] && $this->chance(0.1)
            && $this->attempt('a bundle', fn() => $this->orders->changeBundle($actor, $offers[random_int(0, count($offers) - 1)])) !== null;
        if (!$bundle) foreach ($this->pickCourses($this->chance(0.25) ? 2 : 1) as $course) $this->orders->changeCart($actor, $course['variant_id']);
        $cart = $this->orders->cart($actor);
        $this->checkout->begin($actor, $cart);
        [$city, $postal, $region] = self::CITIES[random_int(0, count(self::CITIES) - 1)];
        $this->checkout->saveProfile($actor, ['first_name' => $person['first'], 'last_name' => $person['last'], 'mobile_number' => $this->mobile(), 'billing_name' => $person['name'],
            'address_line_1' => random_int(1, 240) . ' ' . self::STREETS[random_int(0, count(self::STREETS) - 1)], 'city' => $city, 'postal_code' => $postal,
            'region' => $region, 'country_code' => 'ZA']);
        $method = $this->method();
        $this->checkout->selectMethod($actor, $method, $method === 'dummy' ? 'demo_success' : '', false, false);
        $cart = $this->orders->cart($actor);
        $order = $this->checkout->place($actor, (int) $cart['id'], (string) $cart['quote'], true, true);
        unset($_SESSION['checkout']);
        if ($order === null) return;
        $this->count('private orders');
        // Keep me informed, as some tick it at the checkout.
        if ($this->chance(0.25)) $this->mailing->subscribe($userId, 'news', null, 'checkout');
        if ($this->chance(0.3)) foreach ($this->seeds->orderLines($order) as $line) if ($line['course_id'] > 0) $this->mailing->subscribe($userId, 'course', $line['course_id'], 'checkout');
        if ($method === 'eft' && !$this->payByEft($order, $userId)) return;
        $this->paidOrders[] = ['user' => $userId, 'order' => $order];
        foreach ($this->seeds->enrolments($userId) as $enrolment) {
            $this->learners[] = ['user' => $userId, 'course' => $enrolment['course_id'], 'slug' => $enrolment['slug'], 'skill' => $this->skill(), 'started' => true, 'private' => true];
        }
    }

    /**
     * ADMIN records the EFT from the bank statement at Record EFT Payment, the payer's reference their account
     * reference, as the payment instructions ask; one in six is still waiting for the money.
     */
    private function payByEft(int $order, int $payerId): bool
    {
        if ($this->chance(1 / 6)) {
            $this->count('orders waiting for an EFT');

            return false;
        }
        $payer = $this->seeds->person($payerId);
        $reference = AccountReference::format((string) ($payer['account_reference'] ?? ''));
        $bank = 'FNB ' . random_int(100000000, 999999999);
        // The deposit shows on this morning's statement, an hour or two after the order.
        $received = (new DateTimeImmutable())->modify('-' . random_int(5, 90) . ' minutes')->format(DATE_ATOM);
        $paid = $this->attempt('recording an EFT', fn() => $this->bank->recordAgainstOrder($this->admin, $order, Uuid::v4(), $this->commerce->dueAmount($order),
            $received, $reference, $bank, 'Seen on the business account statement.'));
        if ($paid !== null) $this->count('EFT payments recorded');

        return $paid !== null;
    }

    /**
     * A learner works through a course: starts it, then answers its graded assessments in order, one question at a time,
     * choosing the right answer as often as their skill allows. Some stop part of the way and some finish.
