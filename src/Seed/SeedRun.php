     * @param array{user:int,course:int,slug:string,skill:float,started:bool,private:bool} $learner
     */
    private function study(array $learner): void
    {
        if (!$learner['started']) return;
        $this->learning->start($learner['user'], $learner['slug']);
        $this->count('courses started');
        $graded = array_values(array_filter($this->items->availability($learner['course'], (new DateTimeImmutable())->format(DATE_ATOM), false),
            static fn(array $node): bool => (string) ($node['item_type'] ?? '') === 'assessment' && in_array((string) ($node['assessment_role'] ?? ''), ['graded', 'final'], true)));
        if ($graded === []) return;
        $roll = random_int(1, 100);
        $done = $roll <= 20 ? 0 : ($roll <= 60 ? random_int(1, max(1, count($graded) - 1)) : count($graded));
        foreach (array_slice($graded, 0, $done) as $node) {
            if ($this->attempt('an assessment', fn() => $this->answer($learner, $node)) === null) return;
            $this->count('assessments submitted');
        }
        if ($done === count($graded)) $this->count('courses finished');
    }

    /**
     * @param array{user:int,course:int,slug:string,skill:float,started:bool,private:bool} $learner
     * @param array<string,mixed> $node
     */
    private function answer(array $learner, array $node): bool
    {
        $session = $this->assessments->startAttempt($learner['user'], $learner['slug'], (int) $node['id'], (string) $node['item_key'], 'graded');
        $publicId = (string) $session['public_id'];
        $answers = $this->seeds->answers((int) $node['course_item_id']);
        $state = $this->assessments->session($learner['user'], $publicId);
        for ($i = 0; $i < 500 && isset($state['question']['question_id']); $i++) {
            $question = (int) $state['question']['question_id'];
            $choices = $answers[$question] ?? ['correct' => [], 'wrong' => []];
            $right = $choices['correct'] !== [] && (mt_rand() / mt_getrandmax()) < $learner['skill'];
            $pool = $right || $choices['wrong'] === [] ? $choices['correct'] : $choices['wrong'];
            $option = $pool === [] ? null : $pool[random_int(0, count($pool) - 1)];
            $state = $this->assessments->respond($learner['user'], $publicId, $question, $option, $option === null);
        }
        if (($state['status'] ?? '') === 'in_progress') $this->assessments->finish($learner['user'], $publicId);

        return true;
    }

    /** Some learners who have done part of a course review it; ADMIN approves most, rejects one now and then, and leaves a few. */
    private function reviewCourses(): void
    {
        $seen = [];
        foreach ($this->learners as $learner) {
            $key = $learner['user'] . ':' . $learner['course'];
            if (isset($seen[$key]) || !$learner['started'] || !$this->chance(0.45) || !$this->reviews->canReview($learner['user'], $learner['course'])) continue;
            $seen[$key] = true;
            $roll = random_int(1, 100);
            $rating = $roll <= 45 ? 5 : ($roll <= 78 ? 4 : ($roll <= 92 ? 3 : ($roll <= 98 ? 2 : 1)));
            $words = self::REVIEWS[$rating];
            if ($this->attempt('a review', fn() => $this->reviews->submit($learner['user'], $learner['course'], $rating, $words[random_int(0, count($words) - 1)])) === null) continue;
            $this->count('reviews');
            $review = $this->reviewRecords->forLearner($learner['course'], $learner['user']);
            if ($review === null) continue;
            $decide = random_int(1, 100);
            if ($decide <= 80) {
                $this->attempt('approving a review', fn() => $this->reviews->approve((int) $review['id'], $this->admin->id, $review['revision'], null));
                $this->count('reviews approved');
            } elseif ($decide <= 90) {
                $this->attempt('rejecting a review', fn() => $this->reviews->reject((int) $review['id'], $this->admin->id, $review['revision'], 'It describes a different course.', false));
                $this->count('reviews rejected');
            } else {
                $this->count('reviews waiting for moderation');
            }
        }
    }

    /**
     * Three learners ask for a refund: ADMIN approves one as goodwill (the course started on payment, so the Refund
     * Policy needs the written override), refuses one by the Refund Policy, and has not yet decided the third.
     */
    private function refundRequests(): void
    {
        shuffle($this->paidOrders);
        foreach (array_slice($this->paidOrders, 0, 3) as $i => $paid) {
            $line = $this->seeds->orderLines($paid['order'])[0] ?? null;
            if ($line === null) continue;
            $actor = $this->actor($paid['user']);
            $reasons = ['I was transferred to another branch and no longer need this course.', 'I bought the wrong course by mistake.', 'I do not have time to take the course this year.'];
            $request = $this->attempt('a refund request', fn() => $this->refunds->requestForOwnOrder($actor, $paid['order'], $line['id'], $i === 0 ? 'wallet' : 'money_back', $reasons[$i]));
            if ($request === null) continue;
            $this->count('refund requests');
            if ($i === 0) {
                $this->attempt('approving a refund', fn() => $this->refunds->approve($this->admin, (int) $request, 'goodwill', 'Refunded to the learner\'s wallet as goodwill.', 'The course started on payment; refunded as goodwill because the learner had not opened it.'));
                $this->count('refunds approved');
            } elseif ($i === 1) {
                $this->attempt('refusing a refund', fn() => $this->refunds->refuse($this->admin, (int) $request, 'The course started on payment, and the Refund Policy does not refund a course once it has started.'));
            }
        }
    }

    /** A few messages through the contact form, from visitors and from learners signed in. */
    private function contactMessages(): void
    {
        $messages = self::CONTACT;
        shuffle($messages);
        foreach (array_slice($messages, 0, random_int(3, 5)) as [$reason, $message, $extra]) {
            // A learner writes in signed in; a visitor gives their name and address.
            $learner = $this->learners !== [] && $this->chance(0.5) ? $this->learners[random_int(0, count($this->learners) - 1)]['user'] : null;
            $who = $learner !== null ? $this->seeds->person($learner) : null;
            if ($who !== null) {
                $name = trim($who['first_name'] . ' ' . $who['last_name']);
                $email = $who['email'];
            } else {
                $visitor = $this->names->person();
                $name = $visitor['name'];
                $email = SeedNames::address($visitor, SeedNames::privateDomain());
            }
            $input = ['reason' => $reason, 'name' => $name, 'email' => $email, 'message' => $message] + $extra;
            if (array_key_exists('for_company', $extra)) $input['company_name'] = $this->names->company()['name'];
            if ($this->attempt('a contact message', fn() => $this->contact->submit($learner !== null ? $this->actor($learner) : null, $input)) !== null) $this->count('contact messages');
        }
    }

    /** Someone as the site knows them when they are signed in: their roles and what those allow. */
    private function actor(int $userId): CurrentUser
    {
        $person = $this->seeds->person($userId) ?? throw new \RuntimeException('There is no account ' . $userId . '.');
        $roles = $this->roles->roles($userId);

        return new CurrentUser($userId, $person['public_id'], $person['email'], $person['display_name'] !== '' ? $person['display_name'] : $person['email'],
            $roles, $this->acl->permissionsForUser($userId, $roles), Uuid::v4(), $person['email']);
    }

    /**
     * Does one step; a step the app refuses is noted with its reason and the run goes on.
     *
     * @template T
     * @param callable():T $step
     * @return T|null
     */
    private function attempt(string $what, callable $step): mixed
    {
        try {
            return $step();
        } catch (Throwable $refused) {
            unset($_SESSION['checkout'], $_SESSION['company_credit_basket']);
            $this->refused[] = ucfirst($what) . ': ' . $refused->getMessage();

            return null;
        }
    }

    private function step(string $words): void
    {
        $this->breathe();
        ($this->progress)($words, $this->figures());
    }

    /**
     * In development a web request's logger keeps every record (each SQL statement) in memory for the profiler; a run
     * makes tens of thousands, so they are let go as it goes.
     */
    private function breathe(): void
    {
        if ($this->logger instanceof DebugLoggerInterface) $this->logger->clear();
    }

    /** @return array<string,int> what is made so far, in the page's order */
    private function figures(): array
    {
        $ordered = [];
        foreach (self::FIGURES as $what) if (isset($this->made[$what])) $ordered[$what] = $this->made[$what];

        return $ordered + $this->made;
    }

    private function count(string $what): void
    {
        $this->made[$what] = ($this->made[$what] ?? 0) + 1;
    }

    /** @return list<array{id:int,slug:string,title:string,variant_id:int,period:int,price:int}> */
    private function pickCourses(int $count): array
    {
        $courses = $this->courses;
        shuffle($courses);

        return array_slice($courses, 0, max(1, $count));
    }

    /** @return array{id:int,slug:string,title:string,variant_id:int,period:int,price:int}|null */
    private function course(int $id): ?array
    {
        foreach ($this->courses as $course) if ($course['id'] === $id) return $course;

        return null;
    }

    /** The simulated card for most, EFT for about a third, as the site offers them. */
    private function method(): string
    {
        if (count($this->methods) === 1) return $this->methods[0];

        return $this->chance(0.35) ? 'eft' : 'dummy';
    }

    private function skill(): float
    {
        return random_int(45, 95) / 100;
    }

    private function chance(float $p): bool
    {
        return mt_rand() / mt_getrandmax() < $p;
    }

    private function mobile(): string
    {
        $prefixes = ['060', '061', '062', '063', '064', '065', '066', '071', '072', '073', '074', '076', '078', '079', '081', '082', '083', '084'];

        return $prefixes[random_int(0, count($prefixes) - 1)] . ' ' . random_int(100, 999) . ' ' . random_int(1000, 9999);
    }
