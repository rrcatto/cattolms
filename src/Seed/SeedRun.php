    private function privateLearners(int $count): void
    {
        $registering = $this->signIn->restricted() ? 0 : (int) round($count * 0.75);
        $waiting = $this->auth->demoHoldsRegistrations() ? min(2, intdiv($registering, 5)) : 0;
        for ($i = 0; $i < $count; $i++) {
            $this->step('Making private learner ' . ($i + 1) . ' of ' . $count);
            $person = $this->names->person();
            $email = SeedNames::address($person, SeedNames::privateDomain());
            if ($this->seeds->emailTaken($email)) continue;
            $id = null;
            if ($i < $registering) {
                // One never clicks the link in their email; a couple are left for ADMIN to approve.
                if ($i === 0 && $registering >= 8) {
                    $this->attempt('a registration', fn() => $this->requestRegistration($person, $email, []));
                    $this->count('registrations never finished');
                    continue;
                }
                $id = $this->register($person, $email, [], $i > $waiting);
                if ($id !== null && $i <= $waiting && $this->auth->demoHoldsRegistrations()) {
                    $this->count('accounts waiting for approval');
                    continue;
                }
            } else {
                $id = $this->attempt('adding a person', fn() => $this->administration->createPerson(['first_name' => $person['first'], 'last_name' => $person['last'],
                    'email' => $email, 'role' => RoleCatalog::STUDENT], $this->admin->id));
                if ($id !== null) $this->count('people added by ADMIN');
            }
            if ($id === null) continue;
            $this->count('private learners');
            if ($this->courses !== [] && $this->methods !== [] && $this->chance(0.85)) $this->attempt('a purchase', fn() => $this->buy((int) $id, $person));
        }
    }

    /**
     * Registers someone through the Register workflow and follows the link in their (held) email, as they would; on a
     * demo site the account then waits for ADMIN, who approves it when $approve.
     *
     * @param array{first:string,last:string,name:string} $person
     * @param array<string,string> $extra
     */
    private function register(array $person, string $email, array $extra, bool $approve): ?int
    {
        $sent = $this->attempt('a registration', fn() => $this->requestRegistration($person, $email, $extra));
        if ($sent === null) return null;
        $link = $this->mail->heldRegistrationLink($email);
        parse_str((string) parse_url((string) $link, PHP_URL_QUERY), $query);
        $token = is_string($query['token'] ?? null) ? $query['token'] : '';
        if ($token === '' || $this->attempt('finishing a registration', fn() => $this->auth->consumeRegistration($token)) === null) return null;
        $id = $this->seeds->userIdByEmail($email);
        if ($id === null) return null;
        $this->count('registrations');
        if ($approve && $this->auth->demoHoldsRegistrations()) $this->attempt('approving an account', fn() => $this->auth->approveAccount($id, $this->admin->id));

        return $id;
    }

