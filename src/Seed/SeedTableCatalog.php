    {
        $constraints = [];
        foreach (self::SAME_UNIVERSE_REFERENCES as $table => $columns) {
            foreach ($columns as $column => $references) {
                $constraints[] = ['table' => $table, 'column' => $column, 'references' => $references];
            }
        }

        return $constraints;
    }
