    /**
     * Every foreign key between seed-aware tables, flattened.
     *
     * @return list<array{child:string,column:string,parent:string,on_delete:string}>
     */
    public static function interSeedReferences(): array
    {
        $references = [];
        foreach (self::INTER_SEED_REFERENCES as $child => $columns) {
            foreach ($columns as $column => $reference) {
                $references[] = [
                    'child' => $child,
                    'column' => $column,
                    'parent' => $reference['parent'],
                    'on_delete' => $reference['on_delete'],
                ];
            }
        }

        return $references;
    }

    /**
     * The references a cleanup plan must follow: every one the child cannot survive.
     *
     * Everything except SET NULL, where the database nulls the column and the row lives on.
     *
     * @return list<array{child:string,column:string,parent:string,on_delete:string}>
     */
    public static function collateralReferences(): array
    {
        return array_values(array_filter(
            self::interSeedReferences(),
            static fn(array $reference): bool => $reference['on_delete'] !== 'SET NULL'
        ));
    }

    /**
