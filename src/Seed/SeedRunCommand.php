namespace CattoLearning\Seed;

use CattoLearning\Infrastructure\Persistence\RoleRepository;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;

#[AsCommand(name: 'seed:run', description: 'Fill a demo site with companies, staff and private learners made through the app\'s workflows.')]
final class SeedRunCommand extends Command
{
    public function __construct(private readonly SeedDatabaseService $seeds, private readonly RoleRepository $roles)
    {
        parent::__construct();
    }

    protected function configure(): void
    {
        $this->addOption('companies', null, InputOption::VALUE_REQUIRED, 'How many companies to make.', (string) SeedDatabaseService::COMPANIES['default']);
        $this->addOption('learners', null, InputOption::VALUE_REQUIRED, 'How many private learners to make.', (string) SeedDatabaseService::LEARNERS['default']);
        $this->addOption('description', null, InputOption::VALUE_REQUIRED, 'What the data is for, for the activity log.', 'Made with seed:run');
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $actor = $this->roles->firstUserWithRole('ADMIN');
        if ($actor === null) {
            $output->writeln('<error>Sign ADMIN in once first: the run is made as ADMIN.</error>');
            return Command::FAILURE;
        }
        try {
            $run = $this->seeds->prepare($input->getOption('companies'), $input->getOption('learners'), (string) $input->getOption('description'), $actor);
        } catch (\InvalidArgumentException $refused) {
            $output->writeln('<error>' . $refused->getMessage() . '</error>');
            return Command::FAILURE;
        }
        $run = $this->seeds->run($run);
        foreach ((array) ($run['made'] ?? []) as $what => $count) $output->writeln(sprintf('%5d %s', $count, $what));
        foreach ((array) ($run['refused'] ?? []) as $refusal) $output->writeln('Not done: ' . $refusal);
        if (($run['state'] ?? '') !== 'done') {
            $output->writeln('<error>The run stopped: ' . ($run['error'] ?? 'unknown') . '</error>');
            return Command::FAILURE;
        }
        $output->writeln(sprintf('Finished in %.0f seconds.', (float) $run['seconds']));

        return Command::SUCCESS;
    }
}
