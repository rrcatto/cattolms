Version: 0.6

Description:
Loads the word lists the Seed Database builds generated names from.

Architectural boundary: filesystem only. This class reads text files and hands back arrays of
words. It draws nothing, combines nothing and knows nothing about people, companies or courses;
{@see SeedNameFactory} does all of that.

Where the files live, and why in two places.

The lists ship inside the release under `resources/seeds/`, and the installer publishes them to the
instance at `storage/seeds/`. The instance copy is the one that is read. That is the same
arrangement themes use, and it exists because both things have to be true at once: a fresh
deployment must be able to generate seed data without anyone hand-creating ten files first, and the
operator must be able to add names of their own without an upgrade quietly overwriting them.

A file the operator has not edited simply does not exist in the instance directory yet, and the
bundled copy answers for it. So an upgrade that adds two hundred surnames reaches an instance that
never touched surnames, and leaves alone one that did.

One word per line. Blank lines and lines beginning with a hash are ignored, so an operator can
group and annotate their own additions. Duplicates are removed on load rather than being an error,
because a hand-edited file gaining the same name twice is an ordinary slip and not worth refusing
to seed over.

Changelog:
2026/09/05 11:00 SAST
- Created for the v0.6 seed name pools.
*/

declare(strict_types=1);

namespace CattoLearning\Seed;

use RuntimeException;

final class SeedNamePools
{
    /**
     * Every pool, and the smallest size at which it is still worth drawing from.
     *
     * The minimums are deliberately low. They are a guard against an operator emptying a file or
     * saving a truncated one, not a quality standard: the shipped lists are far larger, and the
     * combination counts that matter are asserted by SeedNamePoolContractTest rather than here.
     *
     * @var array<string,int>
     */
    public const POOLS = [
        'first-names' => 100,
        'middle-names' => 100,
        'surnames' => 100,
        'company-places' => 50,
        'company-qualities' => 50,
        'company-sectors' => 10,
        'course-subjects' => 25,
        'course-topics' => 50,
        'course-levels' => 5,
        'course-categories' => 5,
    ];

    /** @var array<string,list<string>> */
    private array $loaded = [];

    public function __construct(
        private readonly string $instanceRoot,
        private readonly string $bundledRoot
    ) {
    }

    /**
     * One pool, as a list of words, in the order the file holds them.
     *
     * @return list<string>
     */
    public function pool(string $name): array
    {
        if (isset($this->loaded[$name])) {
            return $this->loaded[$name];
        }

        if (!array_key_exists($name, self::POOLS)) {
            // The name reaches a filesystem path, so it is checked against the declared set rather
            // than sanitised. There is no legitimate caller with a name that is not in the list.
            throw new RuntimeException('Unknown seed name pool: ' . $name);
        }

        $path = $this->pathFor($name);
        if ($path === null) {
            throw new RuntimeException(
                'The seed name pool "' . $name . '" is missing. Expected ' . $this->instanceRoot . '/' . $name
                . '.txt or the bundled copy at ' . $this->bundledRoot . '/' . $name . '.txt. '
                . 'Run composer seeds:publish to install the bundled lists.'
            );
        }

        $words = [];
        foreach (preg_split('/\R/', (string) file_get_contents($path)) ?: [] as $line) {
            $word = trim($line);
            if ($word === '' || str_starts_with($word, '#')) {
                continue;
            }
            $words[$word] = true;
        }

        $unique = array_keys($words);
        $minimum = self::POOLS[$name];
        if (count($unique) < $minimum) {
            throw new RuntimeException(
                'The seed name pool "' . $name . '" holds ' . count($unique) . ' names; at least '
                . $minimum . ' are needed. Check ' . $path . '.'
            );
        }

        return $this->loaded[$name] = $unique;
    }

    /**
     * Where each pool is actually being read from, and how many names it holds.
     *
     * Shown in Administration so an operator can see at a glance whether their edits are the ones
     * in use, and how many distinct names each list can contribute.
     *
     * @return list<array{pool:string,source:string,path:string,count:int,minimum:int}>
     */
    public function report(): array
    {
        $report = [];
        foreach (array_keys(self::POOLS) as $name) {
            $instance = $this->instanceRoot . '/' . $name . '.txt';
            $path = $this->pathFor($name);
            $report[] = [
                'pool' => $name,
                'source' => $path === null ? 'missing' : ($path === $instance ? 'instance' : 'bundled'),
                'path' => $path ?? $instance,
                'count' => $path === null ? 0 : count($this->pool($name)),
                'minimum' => self::POOLS[$name],
            ];
        }

        return $report;
    }

    /**
     * Copies any bundled list the instance does not already have into the instance directory.
     *
     * Never overwrites. An operator's edited file is theirs, and an upgrade that replaced it would
     * discard exactly the work this arrangement exists to protect.
     *
     * @return list<string> the pools that were published
     */
    public function publish(): array
    {
        if (!is_dir($this->instanceRoot) && !@mkdir($this->instanceRoot, 0775, true) && !is_dir($this->instanceRoot)) {
            throw new RuntimeException('Unable to create the seed names directory at ' . $this->instanceRoot . '.');
        }

        $published = [];
        foreach (array_keys(self::POOLS) as $name) {
            $target = $this->instanceRoot . '/' . $name . '.txt';
            $source = $this->bundledRoot . '/' . $name . '.txt';
            if (is_file($target) || !is_file($source)) {
                continue;
            }
            if (!@copy($source, $target)) {
                throw new RuntimeException('Unable to publish the seed name pool ' . $name . ' to ' . $target . '.');
            }
            $published[] = $name;
        }

        return $published;
    }

    /** The instance copy when it exists, otherwise the bundled one, otherwise null. */
    private function pathFor(string $name): ?string
    {
        foreach ([$this->instanceRoot, $this->bundledRoot] as $root) {
            $path = $root . '/' . $name . '.txt';
            if (is_file($path) && filesize($path) > 0) {
                return $path;
            }
        }

        return null;
    }
}
