Description:
Decides where mail addressed to a generated seed identity is actually delivered.

Seed companies each need their own domain, because `companies.domain` is globally unique, but
nobody is going to register a hundred domains to make test data work. So a generated company gets
a synthetic domain, the address is stored and displayed with that domain, and only the delivery
envelope is rewritten to the one real inbox the operator controls.

  stored and displayed   thabo-nkosi.7.01a029f4@highveld-mining-0-01a029f4.seed.invalid
  actually delivered to  thabo-nkosi.7.01a029f4@<SEED_SYSTEM_COMPANY_DOMAIN>

Two properties make this safe rather than merely convenient:

  1. Generated domains end in `.seed.invalid`. `.invalid` is reserved by RFC 2606 and can never
     be registered or resolved, so if the rewrite ever fails to fire the message bounces instead
     of reaching a stranger. A subdomain of a real domain would not have that property.
  2. The local part is globally unique on its own, not merely unique within its domain. The
     rewrite collapses every generated domain onto one real domain, so two addresses that differ
     only by domain would become the same inbox and two seed identities would share a mailbox.

Architectural boundary: pure address arithmetic. No SQL, no mail transport, no configuration
lookup - the delivery domain is supplied by the caller so this stays testable and so there is one
obvious place where the value comes from.

Changelog:
2026/08/23 04:19 SAST
- Created for the v0.5.8 Seed Database phase.
*/

declare(strict_types=1);

namespace CattoLearning\Seed;

final class SeedMailRouter
{
    /**
     * Suffix every generated company domain ends with.
     *
     * `.invalid` is reserved by RFC 2606 specifically so it can never resolve. That makes an
     * un-rewritten seed address undeliverable by construction rather than by convention.
     */
    public const GENERATED_DOMAIN_SUFFIX = '.seed.invalid';

    public function __construct(private readonly string $deliveryDomain)
    {
    }

    /** True when this address belongs to a generated seed identity. */
    public static function isSeedAddress(string $email): bool
    {
        $email = strtolower(trim($email));

        return $email !== '' && str_ends_with($email, self::GENERATED_DOMAIN_SUFFIX);
    }

    /**
     * The domain for one generated company.
     *
     * The set suffix and the company index both appear so the domain is unique across companies
     * within a set and across sets, which `companies.domain` requires globally.
     */
    public static function generatedDomain(string $companySlug, int $index, string $setSuffix): string
    {
        return $companySlug . '-' . $index . '-' . $setSuffix . self::GENERATED_DOMAIN_SUFFIX;
    }

    /**
     * The local part for one generated identity.
     *
     * Unique on its own, because the rewrite below discards the domain. The person's name is
     * kept so the address is still recognisable in an inbox.
     */
    public static function generatedLocalPart(string $nameSlug, int $index, string $setSuffix): string
    {
        return strtolower($nameSlug) . '.' . $index . '.' . $setSuffix;
    }

    /**
     * The address mail should actually be sent to.
     *
     * A real address is returned untouched. That is the important half: this must never rewrite
     * anything that is not recognisably generated, or genuine mail would be diverted.
     */
    public function deliveryAddress(string $email): string
    {
        if (!self::isSeedAddress($email) || $this->deliveryDomain === '') {
            return $email;
        }

        $at = strrpos($email, '@');
        if ($at === false || $at === 0) {
            return $email;
        }

        return substr($email, 0, $at) . '@' . $this->deliveryDomain;
    }

    /** True when a delivery domain is configured; without one, seed mail is not rewritten. */
    public function isConfigured(): bool
    {
        return $this->deliveryDomain !== '';
    }

    public function deliveryDomain(): string
    {
        return $this->deliveryDomain;
    }
}
