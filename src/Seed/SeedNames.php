declare(strict_types=1);

namespace CattoLearning\Seed;

use CattoLearning\Infrastructure\Mail\GeneratedDomainRouter;
use CattoLearning\Infrastructure\Persistence\SeedRepository;
use CattoLearning\Support\Slug;
use RuntimeException;

final class SeedNames
{
    /** The invented domains private learners' addresses use, as people use a few big providers. */
    private const PRIVATE_DOMAINS = ['webmail', 'homemail', 'inbox', 'mymail'];

    /** @var array<string,true> names given in this run */
    private array $given = [];

    public function __construct(
        private readonly SeedNamePools $pools,
        private readonly SeedRepository $seeds
    ) {
    }

    /**
     * A person nobody on the site shares a name with.
     *
     * @return array{first:string,last:string,name:string}
     */
    public function person(): array
    {
        $first = $this->pools->pool('first-names');
        $last = $this->pools->pool('surnames');
        for ($try = 0; $try < 200; $try++) {
            $given = $first[random_int(0, count($first) - 1)];
            $family = $last[random_int(0, count($last) - 1)];
            $key = 'person:' . mb_strtolower($given . ' ' . $family);
            if (isset($this->given[$key])) continue;
            if ($this->seeds->personNameTaken($given, $family)) continue;
            $this->given[$key] = true;

            return ['first' => $given, 'last' => $family, 'name' => $given . ' ' . $family];
        }

        throw new RuntimeException('Every name tried is already in use. Add names to the first names or surnames list.');
    }

    /**
     * A company no company on the site shares a name or a domain with.
     *
     * @return array{name:string,domain:string}
     */
    public function company(): array
    {
        $words = $this->pools->pool('company-words');
        $trades = $this->pools->pool('company-trades');
        for ($try = 0; $try < 200; $try++) {
            $name = $words[random_int(0, count($words) - 1)] . ' ' . $trades[random_int(0, count($trades) - 1)];
            $domain = GeneratedDomainRouter::generatedDomain(str_replace('-', '', Slug::from($name)));
            if (isset($this->given['company:' . mb_strtolower($name)])) continue;
            if ($this->seeds->companyTaken($name, $domain)) continue;
            $this->given['company:' . mb_strtolower($name)] = true;

            return ['name' => $name, 'domain' => $domain];
        }

        throw new RuntimeException('Every company name tried is already in use. Add words to the company lists.');
    }

    /**
     * first.last at a domain, as people write their address.
     *
     * @param array{first:string,last:string} $person
     */
    public static function address(array $person, string $domain): string
    {
        $local = static fn(string $part): string => (string) preg_replace('/[^a-z]/', '', strtolower(iconv('UTF-8', 'ASCII//TRANSLIT', $part) ?: $part));

        return $local($person['first']) . '.' . $local($person['last']) . '@' . $domain;
    }

    /** An invented private address domain (never delivered to), as a private learner's provider. */
    public static function privateDomain(): string
    {
        return GeneratedDomainRouter::generatedDomain(self::PRIVATE_DOMAINS[random_int(0, count(self::PRIVATE_DOMAINS) - 1)]);
    }
}
