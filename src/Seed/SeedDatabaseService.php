declare(strict_types=1);

namespace CattoLearning\Seed;

use CattoLearning\Configuration\SiteMode;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\SeedRepository;
use Closure;
use InvalidArgumentException;
use Symfony\Component\DependencyInjection\Attribute\AutowireServiceClosure;
use Throwable;

final class SeedDatabaseService
{
    /** @var array{minimum:int,maximum:int,default:int} */
    public const COMPANIES = ['minimum' => 0, 'maximum' => 40, 'default' => 8];

    /** @var array{minimum:int,maximum:int,default:int} */
    public const LEARNERS = ['minimum' => 0, 'maximum' => 300, 'default' => 30];

    /** A run that has said nothing for this long has stopped (its process ended), and another may start. */
    private const STALLED_AFTER = 1800;

    /** @param Closure():SeedRun $runner the run's services, loaded only when a run starts */
    public function __construct(
        private readonly SeedRepository $seeds,
        #[AutowireServiceClosure(SeedRun::class)] private readonly Closure $runner,
        private readonly AuditRepository $audit,
        private readonly SiteMode $siteMode,
        private readonly SeedQueue $queue
    ) {
    }

    /** @return array{companies:array{minimum:int,maximum:int,default:int},learners:array{minimum:int,maximum:int,default:int}} */
    public function bounds(): array
    {
        return ['companies' => self::COMPANIES, 'learners' => self::LEARNERS];
    }

    /** @return array<string,mixed>|null where the last run stands, with 'busy' while it is waiting or running */
    public function status(): ?array
    {
        $run = $this->seeds->run();
        if ($run === null) return null;
        $said = strtotime((string) ($run['updated_at'] ?? '')) ?: 0;
        $run['busy'] = in_array($run['state'] ?? '', ['waiting', 'running'], true) && time() - $said < self::STALLED_AFTER;
        if (in_array($run['state'] ?? '', ['waiting', 'running'], true) && !$run['busy']) $run['state'] = 'stopped';

        return $run;
    }

    /** Why seeding cannot run here, in words, or null when it can. */
    public function unavailable(): ?string
    {
        if (!$this->siteMode->isDemo()) return 'Seed Database runs only on a demo site: a live site never gets made-up people, orders and payments.';
        if ($this->seeds->coursesOnSale() === []) return 'Seed Database needs courses on sale. Import your catalogue at Courses > Import & Export Catalogue first.';

        return null;
    }

    /**
     * Checks a request and queues the run; it starts once the page has answered (SeedRunListener).
     */
    public function request(mixed $companies, mixed $learners, string $description, int $actorUserId): void
    {
        $this->queue->queue($this->prepare($companies, $learners, $description, $actorUserId));
    }

    /**
     * Checks a request and records it as waiting.
     *
     * @return array<string,mixed> the run, for run()
     */
    public function prepare(mixed $companies, mixed $learners, string $description, int $actorUserId): array
    {
        $reason = $this->unavailable();
        if ($reason !== null) throw new InvalidArgumentException($reason);
        if (($this->status()['busy'] ?? false) === true) throw new InvalidArgumentException('A run is already under way. Wait for it to finish.');
        $companies = self::number($companies, self::COMPANIES, 'companies');
        $learners = self::number($learners, self::LEARNERS, 'private learners');
        if ($companies + $learners === 0) throw new InvalidArgumentException('Ask for at least one company or one private learner.');
        $run = ['state' => 'waiting', 'companies' => $companies, 'learners' => $learners, 'description' => mb_substr(trim($description), 0, 500),
            'requested_by' => $actorUserId, 'requested_at' => date(DATE_ATOM), 'updated_at' => date(DATE_ATOM), 'step' => 'Waiting to start', 'made' => []];
        $this->seeds->saveRun($run, $actorUserId);

        return $run;
    }

    /**
     * Runs a queued request, after the browser has its answer.
     *
     * @param array<string,mixed> $run
     */
    public function runQueued(array $run): void
    {
        ignore_user_abort(true);
        set_time_limit(0);
        // The page's own allowance is for a page, not for minutes of work.
        if (self::bytes((string) ini_get('memory_limit')) < 512 * 1024 * 1024) ini_set('memory_limit', '512M');
        $this->run($run);
    }

    /**
     * Runs one request, recording each step.
     *
     * @param array<string,mixed> $run
     * @return array<string,mixed> the run as it ended
     */
    public function run(array $run): array
    {
        $actor = (int) $run['requested_by'];
        $started = microtime(true);
        $run = ['state' => 'running', 'started_at' => date(DATE_ATOM)] + $run;
        $save = function (string $step, array $made) use (&$run, $actor): void {
            $run = ['step' => $step, 'made' => $made, 'updated_at' => date(DATE_ATOM)] + $run;
            $this->seeds->saveRun($run, $actor);
        };
        $save('Starting', []);
        try {
            $result = ($this->runner)()->run($actor, (int) $run['companies'], (int) $run['learners'], $save);
            $run = ['state' => 'done', 'step' => 'Finished', 'made' => $result['made'], 'refused' => $result['refused']] + $run;
        } catch (Throwable $failed) {
            $run = ['state' => 'failed', 'error' => $failed->getMessage()] + $run;
        }
        $run = ['finished_at' => date(DATE_ATOM), 'updated_at' => date(DATE_ATOM), 'seconds' => round(microtime(true) - $started, 1)] + $run;
        $this->seeds->saveRun($run, $actor);
        $this->audit->record($actor, 'data.generated', ['description' => $run['description'], 'companies' => $run['companies'], 'learners' => $run['learners'],
            'state' => $run['state'], 'made' => $run['made'], 'seconds' => $run['seconds']]);

        return $run;
    }

    private static function bytes(string $limit): int
    {
        if ($limit === '-1') return PHP_INT_MAX;
        $number = (int) $limit;

        return match (strtolower(substr(trim($limit), -1))) { 'g' => $number * 1024 ** 3, 'm' => $number * 1024 ** 2, 'k' => $number * 1024, default => $number };
    }

    /** @param array{minimum:int,maximum:int,default:int} $bounds */
    private static function number(mixed $value, array $bounds, string $what): int
    {
        $text = trim(is_scalar($value) ? (string) $value : '');
        if (preg_match('/^\d{1,4}$/', $text) !== 1 || (int) $text < $bounds['minimum'] || (int) $text > $bounds['maximum']) {
            throw new InvalidArgumentException('Enter how many ' . $what . ' to make, from ' . $bounds['minimum'] . ' to ' . $bounds['maximum'] . '.');
        }

        return (int) $text;
    }
}
