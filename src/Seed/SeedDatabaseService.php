declare(strict_types=1);

namespace CattoLearning\Seed;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;

final class SeedDatabaseService
{
    public function __construct(
        private readonly TransactionManager $transactions,
        private readonly SeedGenerator $generator,
        private readonly AuditRepository $audit
    ) {
    }

    /**
     * Generates one set of data inside a single transaction.
     *
     * @return array{records:int,seconds:float,tables:array<string,int>}
     */
    public function generate(mixed $requestedVolume, string $description, int $actorUserId): array
    {
        $plan = SeedGenerationPlan::forVolume($requestedVolume);
        $description = mb_substr(trim($description), 0, 500);

        // The run key seeds the generator's randomness and disambiguates the technical identifiers
        // it mints - slugs, domains, email local parts - so two runs cannot collide on a column the
        // database requires to be unique. It is not stored on any row.
        $runKey = bin2hex(random_bytes(8));

        $startedAt = microtime(true);
        /** @var array<string,int> $tables */
        $tables = $this->transactions->run(fn(): array => $this->generator->generate($plan, $runKey));
        $seconds = microtime(true) - $startedAt;
        $records = array_sum($tables);

        $this->audit->record($actorUserId, 'data.generated', [
            'description' => $description,
            'requested_volume' => $plan->requestedVolume,
            'records' => $records,
            'seconds' => round($seconds, 3),
        ]);

        return ['records' => $records, 'seconds' => $seconds, 'tables' => $tables];
    }

    /**
     * The volumes a request may ask for.
     *
     * @return array{minimum:int,maximum:int,default:int}
     */
    public function volumeBounds(): array
    {
        return SeedGenerationPlan::bounds();
    }
}
