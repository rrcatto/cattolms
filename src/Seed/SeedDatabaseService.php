declare(strict_types=1);

namespace CattoLearning\Seed;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\SeedRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\Uuid;
use InvalidArgumentException;
use RuntimeException;

final class SeedDatabaseService
{
    public function __construct(
        private readonly TransactionManager $transactions,
        private readonly SeedRepository $seeds,
        private readonly SeedGenerator $generator,
        private readonly AuditRepository $audit
    ) {
    }

    /**
     * Generates one seed set inside a single transaction.
     *
     * Any failure rolls the whole set back, so a partial graph never survives. Generation sends
     * no email of any kind: a set of a thousand learners must not produce a thousand messages,
     * and a generated address is not a real inbox.
     *
     * @return array{token:string,records:int,seconds:float,tables:array<string,int>}
     */
    public function generate(mixed $requestedVolume, string $description, int $actorUserId): array
    {
        $plan = SeedGenerationPlan::forVolume($requestedVolume);
        $token = Uuid::v7();
        $description = trim($description);
        if (mb_strlen($description) > 500) {
            $description = mb_substr($description, 0, 500);
        }

        $startedAt = microtime(true);

        /** @var array<string,int> $tables */
        $tables = $this->transactions->run(function () use ($plan, $token): array {
            return $this->generator->generate($plan, $token);
        });

        $seconds = microtime(true) - $startedAt;
        $records = array_sum($tables);

        // Metadata is written outside the generation transaction on purpose: if generation rolls
        // back there is no set, and a seed_data row describing a set that does not exist would be
        // worse than no row at all.
        $seedDataId = $this->seeds->recordSet(
            $token,
            $description,
            $plan->requestedVolume,
            $records,
            $seconds,
            $actorUserId
        );
        $this->seeds->recordSetTables($seedDataId, $tables);

        $this->audit->record($actorUserId, 'seed.set_generated', [
            'seed_token' => $token,
            'requested_volume' => $plan->requestedVolume,
            'records' => $records,
            'seconds' => round($seconds, 3),
        ]);

        return ['token' => $token, 'records' => $records, 'seconds' => $seconds, 'tables' => $tables];
    }

    /**
     * Every seed set with both its historical and its current record count.
     *
     * The current figure is derived per set, which is one indexed count per seed-aware table.
     * That is acceptable here because /admin/seed is an occasional maintenance screen, not a hot
     * path - the same reasoning decision D2 gives for rejecting counter triggers.
     *
     * @return list<array<string,mixed>>
     */
    public function sets(): array
    {
        $sets = [];
        foreach ($this->seeds->sets() as $row) {
            $token = (string) $row['seed_token'];
            $current = $row['cleaned_at'] === null ? $this->seeds->currentCounts($token) : [];

            $sets[] = $row + [
                'current_record_count' => array_sum($current),
                'current_table_counts' => $current,
                'is_cleaned' => $row['cleaned_at'] !== null,
            ];
        }

        return $sets;
    }

    /** Total SEED rows across the whole platform, for the section summary. */
    public function totalSeedRecords(): int
    {
        return $this->seeds->totalSeedRows();
    }

    /**
     * What removing this set would delete, shown before the operator confirms.
     *
     * The figures come from the same plan the deletion executes, so what the operator is shown
     * is what actually happens.
     *
     * @return array{token:string,records:int,tables:array<string,int>,collateral:array<string,int>}
     */
    public function cleanupPreview(string $token): array
    {
        $set = $this->requireSet($token);

        // Built from the cleanup plan rather than from currentCounts(), because those answer two
        // different questions. currentCounts() is "how big is this set", which is the right figure
        // for the set list; the preview must instead answer "what will this operation remove",
        // and that includes rows in other seed sets which cannot survive it. Using the same plan
        // the deletion uses is what makes the preview a promise rather than an estimate.
        $plan = $this->seeds->cleanupPlanSummary($token);

        return [
            'token' => (string) $set['seed_token'],
            'records' => $plan['records'],
            'tables' => array_filter($plan['tables'], static fn(int $count): bool => $count > 0),
            'collateral' => $plan['collateral'],
        ];
    }

    /**
     * Removes one seed set and any SEED rows left dangling by it.
     *
     * REAL rows are never eligible for collateral deletion; the queries behind this only ever
     * consider rows that already carry a token.
     *
     * @return array{records:int,tables:array<string,int>,collateral:array<string,int>}
     */
    public function cleanup(string $token, int $actorUserId): array
    {
        $set = $this->requireSet($token);
        if ($set['cleaned_at'] !== null) {
            throw new InvalidArgumentException('That seed set has already been cleaned up.');
        }

        // Everything destructive *and* everything that records it, in one transaction. The
        // previous version committed the deletion and then wrote markCleaned() and the audit row
        // outside it, so a failure in either left the rows gone while seed_data still reported the
        // set as live - a database that disagrees with itself and no way to tell which half is
        // right.
        /** @var array{tables:array<string,int>,collateral:array<string,int>,target:int,records:int} $result */
        $result = $this->transactions->run(function () use ($token, $actorUserId): array {
            // Login tokens are not seed-aware (decision D3), so they are invalidated by identity
            // before those identities disappear.
            $this->seeds->invalidateLoginTokensForSet($token);

            // deleteSet() plans first, then deletes in dependency order - children before parents,
            // whichever seed set each row belongs to.
            $result = $this->seeds->deleteSet($token);

            // A safety net, not part of the plan. The plan is transitively closed, so against a
            // consistent database this finds nothing.
            foreach ($this->seeds->deleteOrphanedSeedRows() as $table => $count) {
                $result['tables'][$table] = ($result['tables'][$table] ?? 0) + $count;
                $result['records'] += $count;
            }

            $metadata = [
                'tables' => $result['tables'],
                'collateral' => $result['collateral'],
                'records' => $result['records'],
            ];

            // Inside the transaction: if either of these fails, the deletion is rolled back with
            // them. SeedRepository and AuditRepository share the same DB\SQL, and
            // TransactionManager::run() joins an open transaction rather than opening a second.
            $this->seeds->markCleaned($token, $metadata);
            $this->audit->record($actorUserId, 'seed.set_cleaned', [
                'seed_token' => $token,
                'records' => $result['records'],
                'collateral_sets' => count($result['collateral']),
            ]);

            return $result;
        });

        return ['records' => $result['records'], 'tables' => $result['tables'], 'collateral' => $result['collateral']];
    }

    /** @return array<string,mixed> */
    private function requireSet(string $token): array
    {
        if (preg_match('/^[0-9a-fA-F-]{36}$/', $token) !== 1) {
            throw new InvalidArgumentException('That is not a valid seed set token.');
        }
        if ($token === SeedTableCatalog::INFRASTRUCTURE_TOKEN) {
            throw new RuntimeException('The shared SEED infrastructure is not a seed set.');
        }

        $set = $this->seeds->findSet($token);
        if ($set === null) {
            throw new InvalidArgumentException('That seed set does not exist.');
        }

        return $set;
    }

    /**
     * The volume bounds and default, so the form does not restate them.
     *
     * @return array{minimum:int,maximum:int,default:int}
     */
    public function volumeBounds(): array
    {
        return [
            'minimum' => SeedGenerationPlan::MINIMUM_VOLUME,
            'maximum' => SeedGenerationPlan::MAXIMUM_VOLUME,
            'default' => SeedGenerationPlan::DEFAULT_VOLUME,
        ];
    }
}
