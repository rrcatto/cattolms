    /**
     * Generates the full graph for one set.
     *
     * The caller supplies the transaction: everything below either commits together or is rolled
     * back together, which is what makes a failed generation leave no partial set behind.
     *
     * @return array<string,int> rows written per table
     */
    public function generate(SeedGenerationPlan $plan, string $token): array
    {
        $this->counts = [];
        $this->randomState = abs(crc32($token)) ?: 1;

        $roleIds = $this->repository->roleIdsByKey();
        foreach (self::SEED_ROLE_MIX as $roleKey) {
            if (!isset($roleIds[$roleKey])) {
                throw new RuntimeException('The seed role ' . $roleKey . ' is missing from the roles table.');
            }
        }

        $suffix = $this->setUniqueKey($token);

        $companies = $this->generateCompanies($plan, $token, $suffix);
        $people = $this->generatePeople($plan, $token, $suffix, $companies, $roleIds);
        $categories = $this->generateCategories($plan, $token, $suffix);
        $courses = $this->generateCourses($plan, $token, $suffix, $categories, $companies, $people);
        $this->generateEnrolmentActivity($plan, $token, $suffix, $courses, $people);
        $this->generateCommercialRecords($plan, $token, $courses, $companies, $people);
        $this->generateAuditTrail($token, $courses, $people);

        return $this->counts;
    }

    /**
     * The per-set uniqueness key: the namespace every globally unique generated value is built on.
     *
     * Derived by hashing the whole token rather than by slicing it. A UUIDv7 opens with a 48-bit
     * millisecond timestamp, so the first eight hex characters of one are the top 32 bits of that
     * counter - they change once every 2^16 ms, roughly once a minute. Two sets generated inside
     * the same minute therefore shared a key and produced identical category and course slugs,
     * which `course_categories_slug_key` correctly refused. Hashing spreads the value across the
     * whole token, including its random half, so the interval between two sets stops mattering.
     *
     * Deterministic on purpose: the same token rebuilds the same graph, which is what makes a
     * defect found at volume reproducible. The token is lowercased first so two spellings of one
     * UUID cannot describe two different graphs.
     *
     * Sixteen hex characters is 64 bits. Two sets would collide with probability near n^2/2^65 -
     * negligible at any plausible number of seed sets - and a collision could only ever surface as
     * a refused INSERT on a UNIQUE constraint, loudly, never as two sets quietly sharing rows. The
     * full 64-character digest would also fit every column this feeds; it is shortened only to
     * keep generated slugs and domains readable to someone reading the database directly.
     *
     * Every globally unique value the generator writes is built from this key: `companies.domain`,
     * `user_emails.email`, `course_categories.slug`, `courses.slug` and
     * `certificates.certificate_number`. That list is the whole of it: every other unique
     * constraint on a table this class writes is either a random `public_id`, or composite and
     * scoped to a parent row the generator creates itself, so two sets cannot reach each other
     * through one. Anything globally unique added later must be built from this key.
     */
    private function setUniqueKey(string $token): string
    {
        return substr(hash('sha256', strtolower($token)), 0, 16);
    }

    /**
     * Deterministic pseudo-random integer in [0, $bound).
     *
     * A linear congruential step rather than mt_rand, so the graph depends only on the seed set
     * token and not on process state. Reproducibility matters when a defect only appears at
     * volume: the same token rebuilds the same data.
     */
    private function next(int $bound): int
    {
        $this->randomState = ($this->randomState * 1103515245 + 12345) & 0x7fffffff;

        return $bound < 1 ? 0 : $this->randomState % $bound;
    }

    /** @param list<string> $values */
    private function pick(array $values): string
    {
        return $values[$this->next(count($values))];
    }

    /**
     * @param list<string> $columns
     * @param list<list<mixed>> $rows
     * @return list<int>
     */
    private function write(string $table, array $columns, array $rows, bool $returnIds = false): array
    {
        if ($rows === []) {
            return [];
        }
        $this->counts[$table] = ($this->counts[$table] ?? 0) + count($rows);

        return $this->repository->insertMany($table, $columns, $rows, $returnIds);
    }

    /** @return list<array{id:int,domain:string,name:string}> */
    private function generateCompanies(SeedGenerationPlan $plan, string $token, string $suffix): array
    {
        $rows = [];
        $meta = [];
        for ($i = 0; $i < $plan->companies; $i++) {
            $name = $this->pick(self::COMPANY_PREFIXES) . ' ' . $this->pick(self::COMPANY_SUFFIXES);
            // Domains are globally unique across both universes, so every generated one carries
            // the company index and the set suffix. The .seed.invalid suffix is reserved by
            // RFC 2606 and can never resolve, so an address here is undeliverable unless the
            // seed mail router rewrites it to the operator's real inbox.
            $domain = SeedMailRouter::generatedDomain(Slug::from($name), $i, $suffix);
            $meta[] = ['name' => $name, 'domain' => $domain];
            $rows[] = [Uuid::v4(), $name, $domain, 'active', false, 'client', $token];
        }

        $ids = $this->write(
            'companies',
            ['public_id', 'name', 'domain', 'status', 'is_system', 'company_type', 'seed_token'],
            $rows,
            true
        );

        $companies = [];
        foreach ($ids as $index => $id) {
            $companies[] = ['id' => $id, 'domain' => $meta[$index]['domain'], 'name' => $meta[$index]['name']];
        }

        return $companies;
    }

    /**
     * @param list<array{id:int,domain:string,name:string}> $companies
     * @param array<string,int> $roleIds
     * @return array{all:list<int>,students:list<int>,owners:list<int>,editors:list<int>,admins:list<int>}
     */
    private function generatePeople(SeedGenerationPlan $plan, string $token, string $suffix, array $companies, array $roleIds): array
    {
        $userRows = [];
        $identities = [];
        for ($i = 0; $i < $plan->users; $i++) {
            $first = $this->pick(self::FIRST_NAMES);
            $last = $this->pick(self::LAST_NAMES);
            $roleKey = self::SEED_ROLE_MIX[$i % count(self::SEED_ROLE_MIX)];
            $company = $companies[$i % count($companies)];

            $identities[] = ['first' => $first, 'last' => $last, 'role' => $roleKey, 'company' => $company];
            $userRows[] = [
                Uuid::v4(),
                trim($first . ' ' . $last),
                $first,
                $last,
                'active',
                $token,
            ];
        }

        $userIds = $this->write(
            'users',
            ['public_id', 'display_name', 'first_name', 'last_name', 'status', 'seed_token'],
            $userRows,
            true
        );

        $emailRows = [];
        $roleRows = [];
        $membershipRows = [];
        $buckets = ['all' => [], 'students' => [], 'owners' => [], 'editors' => [], 'admins' => []];

        foreach ($userIds as $index => $userId) {
            $identity = $identities[$index];
            // The local part must be unique on its own, not merely within its domain: the mail
            // router discards the generated domain, so two identities differing only by company
            // would otherwise collapse onto one real inbox.
            $local = SeedMailRouter::generatedLocalPart(
                Slug::from($identity['first'] . '-' . $identity['last']),
                $index,
                $suffix
            );
            $emailRows[] = [$userId, $local . '@' . $identity['company']['domain'], true, $token];
            $roleRows[] = [$userId, $roleIds[$identity['role']], $token];
            $membershipRows[] = [
                $identity['company']['id'],
                $userId,
                $this->companyRoleFor($identity['role']),
                'active',
                $token,
            ];

            $buckets['all'][] = $userId;
            $buckets[match ($identity['role']) {
                RoleCatalog::SEED_COURSE_OWNER => 'owners',
                RoleCatalog::SEED_COURSE_EDITOR => 'editors',
                RoleCatalog::SEED_COMPANY_ADMIN => 'admins',
                default => 'students',
            }][] = $userId;
        }

        $this->write('user_emails', ['user_id', 'email', 'is_primary', 'seed_token'], $emailRows);
        $this->write('user_roles', ['user_id', 'role_id', 'seed_token'], $roleRows);
        $this->write('company_users', ['company_id', 'user_id', 'company_role', 'status', 'seed_token'], $membershipRows);

        if ($buckets['owners'] === []) {
            $buckets['owners'] = array_slice($buckets['all'], 0, 1);
        }
        if ($buckets['students'] === []) {
            $buckets['students'] = $buckets['all'];
        }

        return $buckets;
    }

