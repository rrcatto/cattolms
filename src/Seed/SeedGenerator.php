final class SeedGenerator
{
    /**
     * How many rows of one kind are held in PHP memory at a time.
     *
     * The generator's cost used to be linear in the size of the whole set, because each phase built
     * every row for its table before writing any of them - and a set of 500,000 rows needed roughly
     * 120 MB against a 128 MB limit, so the largest sets could not finish at all. Building a chunk,
     * writing it, resolving its ids and discarding it holds the row arrays at a fixed size instead,
     * and only the generated ids survive a phase: those are packed integer lists costing about
     * eight bytes each, which is what the children genuinely need to reference their parents.
     *
     * The value trades round trips against memory. SeedRepository::insertMany batches at 250, so a
     * chunk of 2,000 is eight statements and never a per-row round trip.
     */
    private const GENERATION_CHUNK = 2000;

    /** Seed roles a generated identity may hold. Never a normal role, never ADMIN. */
    private const SEED_ROLE_MIX = [
        RoleCatalog::STUDENT,
        RoleCatalog::STUDENT,
        RoleCatalog::STUDENT,
        RoleCatalog::STUDENT,
        RoleCatalog::STUDENT,
        RoleCatalog::STUDENT,
        RoleCatalog::COMPANY_ADMIN,
        RoleCatalog::COURSE_EDITOR,
        RoleCatalog::COURSE_OWNER,
    ];

    private const GRADE_BANDS = [
        ['DIST', 'Distinction', 80.0, true],
        ['MERIT', 'Merit', 70.0, true],
        ['PASS', 'Pass', 50.0, true],
        ['FAIL', 'Not yet competent', 0.0, false],
    ];

    /**
     * Names for this set, drawn from the operator-editable pools in storage/seeds.
     *
     * Built per generation because it carries the set's own random seed and the record of every
     * name it has issued. Null outside a generation.
     */
    private ?SeedNameFactory $names = null;

    /**
     * Numeric randomness for the set: prices, marks, which answer is the correct one.
     *
     * A seeded Mt19937 through Random\Randomizer, so a token rebuilds the same graph and nothing
     * else in the process can shift the sequence. It replaces a hand-written linear congruential
     * generator whose result was taken modulo the bound - and the low bits of that generator have a
     * period of two, so `next(40)` could only ever return twenty of its forty values, and
     * `next(4)` two of its four. Every generated course had its correct answer in one of two
     * positions.
     */
    private ?Randomizer $random = null;

    /** @var array<string,int> */
    private array $counts = [];

    public function __construct(
        private readonly SeedNamePools $pools,
        private readonly ArtworkGenerator $artwork,
        private readonly SeedRepository $repository
    ) {
    }

    /**
     * Generates the full graph for one set.
     *
     * The caller supplies the transaction: everything below either commits together or is rolled
     * back together, which is what makes a failed generation leave no partial set behind.
     *
     * @return array<string,int> rows written per table
     */
    public function generate(SeedGenerationPlan $plan, string $token): array
    {
        $this->counts = [];

        // Seeded from this set's own token, so one token always rebuilds the same graph, and primed
        // with the names the database already holds, so a second set never repeats a person, a
        // company or a course title from the first.
        $this->random = new Randomizer(new Mt19937(abs(crc32($token)) ?: 1));
        $this->names = new SeedNameFactory($this->pools, $token);
        $this->names->reserve(
            $this->repository->existingDisplayNames(),
            $this->repository->existingCompanyNames(),
            $this->repository->existingCourseTitles()
        );

        $roleIds = $this->repository->roleIdsByKey();
        foreach (self::SEED_ROLE_MIX as $roleKey) {
            if (!isset($roleIds[$roleKey])) {
                throw new RuntimeException('The seed role ' . $roleKey . ' is missing from the roles table.');
            }
        }

        $suffix = $this->setUniqueKey($token);

        try {
            return $this->build($plan, $token, $suffix, $roleIds);
        } finally {
            // The name factory holds a hash of every name in the database, which is the largest
            // thing this class builds and is of no use once the set is written. names() already
            // says these exist only during a generation; this is what makes that true, rather
            // than leaving the set alive on the generator for as long as the container holds it.
            $this->names = null;
            $this->random = null;
        }
    }

    /**
     * The generation itself, so generate() can release the per-run state in a finally.
     *
     * @param array<string,int> $roleIds
     * @return array<string,int> rows written per table
     */
    private function build(SeedGenerationPlan $plan, string $token, string $suffix, array $roleIds): array
    {
        $companies = $this->generateCompanies($plan, $token);
        $people = $this->generatePeople($plan, $token, $companies, $roleIds);
        $categories = $this->assignableCategories();
        $courses = $this->generateCourses($plan, $token, $suffix, $categories, $companies, $people);
        $this->generateEnrolmentActivity($plan, $token, $suffix, $courses, $people);
        $this->generateCommercialRecords($plan, $token, $courses, $companies, $people);
        $this->generateAuditTrail($plan, $token, $courses, $people);

        return $this->counts;
    }

    /**
     * The per-set uniqueness key: the namespace every globally unique generated value is built on.
     *
     * Derived by hashing the whole token rather than by slicing it. A UUIDv7 opens with a 48-bit
     * millisecond timestamp, so the first eight hex characters of one are the top 32 bits of that
     * counter - they change once every 2^16 ms, roughly once a minute. Two sets generated inside
     * the same minute therefore shared a key and produced identical category and course slugs,
     * which `course_categories_slug_key` correctly refused. Hashing spreads the value across the
     * whole token, including its random half, so the interval between two sets stops mattering.
     *
     * Deterministic on purpose: the same token rebuilds the same graph, which is what makes a
     * defect found at volume reproducible. The token is lowercased first so two spellings of one
     * UUID cannot describe two different graphs.
     *
     * Sixteen hex characters is 64 bits. Two sets would collide with probability near n^2/2^65 -
     * negligible at any plausible number of seed sets - and a collision could only ever surface as
     * a refused INSERT on a UNIQUE constraint, loudly, never as two sets quietly sharing rows. The
     * full 64-character digest would also fit every column this feeds; it is shortened only to
     * keep generated slugs and domains readable to someone reading the database directly.
     *
     * Every globally unique value the generator writes is built from this key: `companies.domain`,
     * `user_emails.email`, `course_categories.slug`, `courses.slug` and
     * `certificates.certificate_number`. That list is the whole of it: every other unique
     * constraint on a table this class writes is either a random `public_id`, or composite and
     * scoped to a parent row the generator creates itself, so two sets cannot reach each other
     * through one. Anything globally unique added later must be built from this key.
     */
    private function setUniqueKey(string $token): string
    {
        return substr(hash('sha256', strtolower($token)), 0, 16);
    }


    /**
     * The name factory for the generation in progress.
     *
     * Generation is the only time names are drawn, so the factory exists only then; asking for one
     * outside a generation is a programming error rather than something to build a fresh one for,
     * because a fresh one would not know what the set had already issued.
     */
    private function names(): SeedNameFactory
    {
        return $this->names ?? throw new RuntimeException('Seed names are only available during a generation.');
    }

    /** A number from 0 to one below the bound, from this set's own seeded sequence. */
    private function next(int $bound): int
    {
        if ($bound < 1) {
            return 0;
        }
        $random = $this->random ?? throw new RuntimeException('Seed randomness is only available during a generation.');

        return $random->getInt(0, $bound - 1);
    }

    /**
     * @param list<string> $columns
     * @param list<list<mixed>> $rows
     * @return list<int>
     */
    private function write(string $table, array $columns, array $rows, bool $returnIds = false): array
    {
        if ($rows === []) {
            return [];
        }
        $this->counts[$table] = ($this->counts[$table] ?? 0) + count($rows);

        return $this->repository->insertMany($table, $columns, $rows, $returnIds);
    }

    /** @return list<array{id:int,domain:string,name:string}> */
    private function generateCompanies(SeedGenerationPlan $plan, string $token): array
    {
        $rows = [];
        $meta = [];
        for ($i = 0; $i < $plan->companies; $i++) {
            $name = $this->names()->company();
            // The domain is the company's name. `companies.domain` is unique platform-wide and
            // the name already carries that uniqueness, so nothing is appended to it. The
            // .invalid suffix is reserved by RFC 2606 and can never resolve, so an address here
            // is undeliverable unless the mail router rewrites it to the operator's inbox.
            $domain = GeneratedDomainRouter::generatedDomain(Slug::from($name));
            $meta[] = ['name' => $name, 'domain' => $domain];
            $rows[] = [Uuid::v4(), $name, $domain, 'active', false];
        }

        $ids = $this->write(
            'companies',
            ['public_id', 'name', 'domain', 'status', 'is_system'],
            $rows,
            true
        );

        $companies = [];
        foreach ($ids as $index => $id) {
            $companies[] = ['id' => $id, 'domain' => $meta[$index]['domain'], 'name' => $meta[$index]['name']];
        }

        return $companies;
    }

    /**
     * @param list<array{id:int,domain:string,name:string}> $companies
     * @param array<string,int> $roleIds
     * @return array{all:list<int>,students:list<int>,owners:list<int>,editors:list<int>,admins:list<int>}
     */
    private function generatePeople(SeedGenerationPlan $plan, string $token, array $companies, array $roleIds): array
    {
        $buckets = ['all' => [], 'students' => [], 'owners' => [], 'editors' => [], 'admins' => []];
        $roleMixCount = count(self::SEED_ROLE_MIX);
        $companyCount = count($companies);

        // One chunk at a time. Every row array below is discarded before the next chunk is built,
        // so what survives the loop is the id lists in $buckets and nothing else.
        for ($offset = 0; $offset < $plan->users; $offset += self::GENERATION_CHUNK) {
            $size = min(self::GENERATION_CHUNK, $plan->users - $offset);

            $userRows = [];
            // A packed list, not a map: the keys were the same four strings 37,500 times over, and
            // the company was held as a nested copy of the whole company row rather than the two
            // fields the loop below reads.
            $identities = [];

            for ($j = 0; $j < $size; $j++) {
                $i = $offset + $j;
                $person = $this->names()->person();
                $roleKey = self::SEED_ROLE_MIX[$i % $roleMixCount];
                // Deliberately lopsided. Spread evenly, a set of 7,500 people across 938 companies
                // gives every company eight staff, and a company screen is never tested against
                // anything bigger than a page. Every fifth person joins the first company instead,
                // so one company holds a fifth of the set and the rest keep a realistic long tail.
                $company = $i % 5 === 0
                    ? $companies[0]
                    : $companies[$i % $companyCount];

                // The global index travels with the row: it settles the email local part, and a
                // chunk-local index would repeat it every chunk.
                $identities[] = [$person['first'], $person['last'], $roleKey, $company['id'], $company['domain'], $i];
                $userRows[] = [
                    Uuid::v4(),
                    $person['display'],
                    $person['first'],
                    $person['middle'],
                    $person['last'],
                    'active',
                ];
            }

            $userIds = $this->write(
                'users',
                ['public_id', 'display_name', 'first_name', 'middle_names', 'last_name', 'status'],
                $userRows,
                true
            );
            unset($userRows);

            $emailRows = [];
            $roleRows = [];
            $membershipRows = [];

            foreach ($userIds as $index => $userId) {
                [$first, $last, $roleKey, $companyId, $companyDomain, $globalIndex] = $identities[$index];
                // Name plus row index. The name factory guarantees the whole display name is
                // unique, middle names included, so `first last` on its own is not - the index
                // settles it.
                $local = GeneratedDomainRouter::generatedLocalPart(
                    Slug::from($first . '-' . $last),
                    $globalIndex
                );
                $emailRows[] = [$userId, $local . '@' . $companyDomain, true];
                $roleRows[] = [$userId, $roleIds[$roleKey]];
                $membershipRows[] = [
                    $companyId,
                    $userId,
                    $this->companyRoleFor($roleKey),
                    'active',
                ];

                $buckets['all'][] = $userId;
                $buckets[match ($roleKey) {
                    RoleCatalog::COURSE_OWNER => 'owners',
                    RoleCatalog::COURSE_EDITOR => 'editors',
                    RoleCatalog::COMPANY_ADMIN => 'admins',
                    default => 'students',
                }][] = $userId;
            }
            unset($identities, $userIds);

            $this->write('user_emails', ['user_id', 'email', 'is_primary'], $emailRows);
            $this->write('user_roles', ['user_id', 'role_id'], $roleRows);
            $this->write('company_users', ['company_id', 'user_id', 'company_role', 'status'], $membershipRows);
            unset($emailRows, $roleRows, $membershipRows);
        }

        if ($buckets['owners'] === []) {
            $buckets['owners'] = array_slice($buckets['all'], 0, 1);
        }
        if ($buckets['students'] === []) {
            $buckets['students'] = $buckets['all'];
        }

        return $buckets;
    }

    private function companyRoleFor(string $seedRole): string
    {
        return match ($seedRole) {
            RoleCatalog::COMPANY_ADMIN => 'administrator',
            RoleCatalog::COURSE_OWNER => 'course_owner',
            default => 'student',
        };
    }

    /**
     * The categories generated courses are filed under.
     *
     * A seed set no longer creates categories. They are universe-free labels shared with the
     * genuine catalogue, so a generated course goes into the same "Mining Safety" a real one does -
     * which is the point: seed data that sat in its own cloned taxonomy could never exercise the
     * real one, and browsing a category would never show the volume that was generated to test it.
     *
     * An installation with no categories at all yields an empty list, and the courses below are
     * filed under none. That is a legitimate state - the schema allows a course without a category
     * - rather than a reason to start inventing taxonomy.
     *
     * Each row carries its ancestry, because the course is named after its category and tagged with
     * the branch it belongs to. See SeedRepository::categoryTaxonomy().
     *
     * @return list<array{id:int,name:string,level:int,root:string,branch:string}>
     */
    private function assignableCategories(): array
    {
        return $this->repository->categoryTaxonomy();
    }

    /**
     * @param list<array{id:int,name:string,level:int,root:string,branch:string}> $categories
     * @param list<array{id:int,domain:string,name:string}> $companies
     * @param array{all:list<int>,students:list<int>,owners:list<int>,editors:list<int>,admins:list<int>} $people
     * @return list<array{id:int,modules:list<int>,assessments:list<int>,questions:array<int,list<int>>,options:array<int,list<int>>,title:string}>
     */
    private function generateCourses(
        SeedGenerationPlan $plan,
        string $token,
        string $suffix,
        array $categories,
        array $companies,
        array $people
    ): array {
        $titles = [];
        // The category each course belongs to, kept so the tags can be drawn from the same place
        // the title was. Before this the two were unrelated: a course called "Abattoir Hygiene"
        // could be filed under Cloud Infrastructure and tagged by arithmetic on its row number.
        $courseCategories = [];
        $courseIds = [];
        $categoryCount = count($categories);
        $ownerCount = count($people['owners']);
        $companyCount = count($companies);

        // Chunked because a course row is the widest the generator writes: twenty-one columns, one
        // of which is the generated SVG cover. Artwork is produced here rather than backfilled
        // afterwards, for the same reason a real course gets its cover in the statement that
        // creates it - a course without one is a grey rectangle, and a catalogue of them is
        // indistinguishable from a broken image - but only a chunk of them need exist at once.
        for ($offset = 0; $offset < $plan->courses; $offset += self::GENERATION_CHUNK) {
            $size = min(self::GENERATION_CHUNK, $plan->courses - $offset);
            $courseRows = [];

            for ($j = 0; $j < $size; $j++) {
                $i = $offset + $j;
                $category = $categories === [] ? null : $categories[$i % $categoryCount];
                $courseCategories[] = $category;
                $title = $category === null
                    ? $this->names()->courseTitle()
                    : $this->names()->courseTitleFor((string) $category['name']);
                $owner = $people['owners'][$i % $ownerCount];
                $company = $companies[$i % $companyCount];
                // Two thirds published so the catalogue has volume, the rest draft so the
                // Administration status filters have something to separate.
                $status = $i % 3 === 2 ? 'draft' : 'published';

                $titles[] = $title;
                $publicId = Uuid::v4();
                $courseRows[] = [
                    $publicId,
                    $category === null ? null : $category['id'],
                    Slug::from($title) . '-' . $i . '-' . $suffix,
                    $title,
                    'Generated seed course for volume testing.',
                    'standard',
                    60,
                    $status,
                    31536000,
                    0.6,
                    0.4,
                    true,
                    'classic',
                    $owner,
                    $company['id'],
                    1,
                    'approved',
                    $owner,
                    $owner,
                    $status === 'published' ? gmdate('Y-m-d H:i:sP') : null,
                    $this->artwork->courseCover($publicId, $title),
                ];
            }

            foreach ($this->write(
                'courses',
                [
                    'public_id', 'category_id', 'slug', 'title', 'summary', 'level', 'estimated_minutes',
                    'status', 'default_access_period_seconds', 'module_weight', 'final_weight',
                    'certificate_enabled', 'certificate_template', 'owner_user_id', 'owner_company_id',
                    'revision_number', 'publication_approval_status', 'created_by_user_id',
                    'updated_by_user_id', 'published_at', 'cover_svg',
                ],
                $courseRows,
                true
            ) as $courseId) {
                $courseIds[] = $courseId;
            }
            unset($courseRows);
        }

        // Grade bands, a price and an editor are cheap and belong to every course: they are what a
        // catalogue row displays. Modules, assessments, questions and answer options are the
        // expensive part - about 120 rows a course - and go to the planned minority.
        //
        // A catalogue where most entries are listings and a minority are built out is also closer
        // to a real one than a catalogue where every course is complete. The rich courses are taken
        // from the front of the list rather than sampled, so the same request always builds out the
        // same courses and a set is reproducible.
        $this->generateGradeBands($courseIds, $token);
        $this->generatePriceVariants($courseIds, $token, $people);
        $this->generateEditors($courseIds, $token, $people);

        $this->tagCourses($courseIds, $courseCategories);

        $richCourseIds = array_slice($courseIds, 0, $plan->richCourses);
        $modulesByCourse = $this->generateModules($richCourseIds, $token);
        $assessments = $this->generateAssessments($richCourseIds, $modulesByCourse, $token);
        $questionBank = $this->generateQuestions($assessments['ids'], $token);

        $courses = [];
        foreach ($courseIds as $index => $courseId) {
            $courses[] = [
                'id' => $courseId,
                'title' => $titles[$index],
                'modules' => $modulesByCourse[$courseId] ?? [],
                'assessments' => $assessments['byCourse'][$courseId] ?? [],
                'questions' => $questionBank['questions'],
                'options' => $questionBank['options'],
            ];
        }

        return $courses;
    }

    /** @param list<int> $courseIds */
    private function generateGradeBands(array $courseIds, string $token): void
    {
        $rows = [];
        foreach ($courseIds as $courseId) {
            foreach (self::GRADE_BANDS as $position => $band) {
                $rows[] = [$courseId, $position + 1, $band[0], $band[1], $band[2], $band[3]];
            }
        }

        $this->write(
            'course_grade_bands',
            ['course_id', 'position', 'grade_code', 'grade_label', 'minimum_percentage', 'is_passing'],
            $rows
        );
    }

    /**
     * @param list<int> $courseIds
     * @param array{all:list<int>,students:list<int>,owners:list<int>,editors:list<int>,admins:list<int>} $people
     */
    private function generatePriceVariants(array $courseIds, string $token, array $people): void
    {
        $rows = [];
        foreach ($courseIds as $index => $courseId) {
            $owner = $people['owners'][$index % count($people['owners'])];
            $rows[] = [
                Uuid::v4(), $courseId, 31536000, (($this->next(40) + 5) * 10000),
                'ZAR', '12 months', 1, true, true, $owner, $owner,
            ];
        }

        $this->write(
            'course_price_variants',
            [
                'public_id', 'course_id', 'access_period_seconds', 'price_minor_units', 'currency_code',
                'label', 'position', 'is_active', 'is_default', 'created_by_user_id', 'updated_by_user_id',
            ],
            $rows
        );
    }

    /**
     * @param list<int> $courseIds
     * @param array{all:list<int>,students:list<int>,owners:list<int>,editors:list<int>,admins:list<int>} $people
     */
    private function generateEditors(array $courseIds, string $token, array $people): void
    {
        $editors = $people['editors'] !== [] ? $people['editors'] : $people['owners'];
        $rows = [];
        foreach ($courseIds as $index => $courseId) {
            $rows[] = [$courseId, $editors[$index % count($editors)]];
        }

        $this->write('course_editors', ['course_id', 'user_id'], $rows);
    }

    /**
     * Attaches tags to every generated course.
     *
     * Tags carry no seed token, exactly as categories no longer do: a tag classifies a course
     * rather than describing anybody, and it is shared with the genuine catalogue. So this writes
     * into `course_tags` only, and the tags themselves are whatever the installation already has.
     *
     * The association rows do carry the token - they hang off a generated course and must go when
     * it does - which is why `course_tags` is deliberately absent from the seed-aware catalogue and
     * relies on the ON DELETE CASCADE from `courses` instead. Removing a seed set removes its
     * courses, and the associations go with them; the tags stay, because they were never the set's.
     *
     * @param list<int> $courseIds
     * @param list<array{id:int,name:string,level:int,root:string,branch:string}|null> $courseCategories
     *        The category each course was filed under, in the same order.
     */
    private function tagCourses(array $courseIds, array $courseCategories): void
    {
        if ($courseIds === []) {
            return;
        }

        // A tag now says something true about the course wearing it.
        //
        // Three of the four come from the course's own place in the taxonomy - the discipline, the
        // area within it, and the subject itself - so a course filed under Health and Safety ›
        // Occupational Health › Hearing Conservation is tagged with exactly those. The fourth says
        // what kind of course it is. Together that is what somebody would actually search a
        // catalogue by.
        //
        // The old version picked tags by arithmetic on the row index against whatever tags happened
        // to exist, so every course got three unrelated words and the tag pages listed courses with
        // nothing in common.
        $delivery = ['Online', 'Classroom', 'Blended', 'Self Study'];
        $purpose = ['Induction', 'Refresher', 'Certification', 'Assessment', 'Practical'];

        $namesByCourse = [];
        $wanted = [];
        foreach ($courseIds as $index => $courseId) {
            $category = $courseCategories[$index] ?? null;
            $names = $category === null
                ? []
                : array_values(array_unique([
                    (string) $category['root'],
                    (string) $category['branch'],
                    (string) $category['name'],
                ]));
            $names[] = $delivery[$index % count($delivery)];
            $names[] = $purpose[($index * 3) % count($purpose)];

            $namesByCourse[$courseId] = $names;
            foreach ($names as $name) {
                $wanted[$name] = true;
            }
        }

        // One round trip for the whole set. Tags are universe-free labels shared with the genuine
        // catalogue, so any that do not exist yet are created here and are not the set's to remove.
        $ids = $this->repository->ensureTags(array_keys($wanted));

        $rows = [];
        $seen = [];
        foreach ($namesByCourse as $courseId => $names) {
            foreach ($names as $name) {
                $tagId = $ids[$name] ?? null;
                if ($tagId === null) {
                    continue;
                }
                $pair = $courseId . ':' . $tagId;
                if (isset($seen[$pair])) {
                    continue;
                }
                $seen[$pair] = true;
                $rows[] = [$courseId, $tagId];
            }
        }

        // The one insert that does not go through write(), and it has its own repository method so
        // that stays visible. write() adds its rows to the reported counts, and those counts are the
        // set's manifest: every table in the manifest must be removable by token, and `course_tags`
        // carries none, because a tag association is not seed-provenanced data. The rows still go
        // when the set does, through the cascade from `courses`, which owns them.
        $this->repository->attachCourseTags($rows);
    }

    /**
     * @param list<int> $courseIds
     * @return array<int,list<int>> module ids per course
     */
    private function generateModules(array $courseIds, string $token): array
    {
        $rows = [];
        $order = [];
        foreach ($courseIds as $courseId) {
            for ($position = 1; $position <= SeedGenerationPlan::MODULES_PER_COURSE; $position++) {
                $order[] = $courseId;
                $rows[] = [
                    Uuid::v4(), $courseId, 'module-' . $position, $position,
                    'Module ' . $position, 'Generated module content for volume testing.',
                ];
            }
        }

        $ids = $this->write(
            'course_modules',
            ['public_id', 'course_id', 'module_key', 'position', 'title', 'content_html'],
            $rows,
            true
        );

        $byCourse = [];
        $blockRows = [];
        foreach ($ids as $index => $moduleId) {
            $byCourse[$order[$index]][] = $moduleId;
            for ($position = 1; $position <= SeedGenerationPlan::BLOCKS_PER_MODULE; $position++) {
                $blockRows[] = [
                    Uuid::v4(), $moduleId, $position, 'html',
                    'Section ' . $position, '<p>Generated seed content.</p>',
                ];
            }
        }

        $this->write(
            'course_content_blocks',
            ['public_id', 'module_id', 'position', 'block_type', 'title', 'content_html'],
            $blockRows
        );

        return $byCourse;
    }

    /**
     * One assessment per module plus one final per course.
     *
     * The schema permits exactly one assessment per module and exactly one final per course, so
     * the shape here is fixed rather than randomised.
     *
     * @param list<int> $courseIds
     * @param array<int,list<int>> $modulesByCourse
     * @return array{ids:list<int>,byCourse:array<int,list<int>>}
     */
    private function generateAssessments(array $courseIds, array $modulesByCourse, string $token): array
    {
        $rows = [];
        $order = [];
        foreach ($courseIds as $courseId) {
            foreach ($modulesByCourse[$courseId] ?? [] as $position => $moduleId) {
                $order[] = $courseId;
                $rows[] = [
                    Uuid::v4(), $courseId, $moduleId, 'module', 'Module ' . ($position + 1) . ' assessment',
                    $position + 1, 50.0, true, 5, 1800, 'highest',
                ];
            }
            $order[] = $courseId;
            $rows[] = [
                Uuid::v4(), $courseId, null, 'final', 'Final assessment',
                99, 60.0, true, 5, 3600, 'highest',
            ];
        }

        $ids = $this->write(
            'course_assessments',
            [
                'public_id', 'course_id', 'module_id', 'assessment_type', 'title', 'position',
                'pass_mark', 'required', 'practice_question_count', 'time_limit_seconds', 'score_policy',
            ],
            $rows,
            true
        );

        $byCourse = [];
        foreach ($ids as $index => $assessmentId) {
            $byCourse[$order[$index]][] = $assessmentId;
        }

        return ['ids' => $ids, 'byCourse' => $byCourse];
    }

    /**
     * @param list<int> $assessmentIds
     * @return array{questions:array<int,list<int>>,options:array<int,list<int>>}
     */
    private function generateQuestions(array $assessmentIds, string $token): array
    {
        $byAssessment = [];
        $optionsByQuestion = [];

        $perQuestion = SeedGenerationPlan::OPTIONS_PER_QUESTION;
        $perAssessment = SeedGenerationPlan::QUESTIONS_PER_ASSESSMENT;

        // Chunked by assessment so a whole set's questions and their four-times-larger option
        // bank are never all in memory at once. The two parallel arrays this used to carry - one
        // naming each question's assessment, one naming each option's question - are gone: the
        // shape is fixed at a constant per parent, so the parent of row n is arithmetic on n, and
        // a 60,000-entry index does not need to be built to record what division already knows.
        $chunk = max(1, intdiv(self::GENERATION_CHUNK, $perAssessment));

        foreach (array_chunk($assessmentIds, $chunk) as $assessmentChunk) {
            $rows = [];
            foreach ($assessmentChunk as $assessmentId) {
                for ($position = 1; $position <= $perAssessment; $position++) {
                    $rows[] = [
                        Uuid::v4(), $assessmentId, $position,
                        '<p>Generated question ' . $position . ' for volume testing.</p>',
                        1, 'standard',
                    ];
                }
            }

            $ids = $this->write(
                'assessment_questions',
                ['public_id', 'assessment_id', 'position', 'question_html', 'points', 'difficulty'],
                $rows,
                true
            );
            unset($rows);

            $optionRows = [];
            foreach ($ids as $index => $questionId) {
                $byAssessment[$assessmentChunk[intdiv($index, $perAssessment)]][] = $questionId;
                // Exactly one correct option per question: the schema enforces it with a partial
                // unique index, and a question with none would be unanswerable.
                $correct = $this->next($perQuestion) + 1;
                for ($position = 1; $position <= $perQuestion; $position++) {
                    $optionRows[] = [
                        Uuid::v4(), $questionId, $position,
                        '<p>Option ' . $position . '</p>', $position === $correct,
                    ];
                }
            }

            // The ids are captured because assessment_responses.selected_option_id is NOT NULL: a
            // response cannot be recorded without naming a real option.
            $optionIds = $this->write(
                'assessment_options',
                ['public_id', 'question_id', 'position', 'option_html', 'is_correct'],
                $optionRows,
                true
            );
            unset($optionRows);

            foreach ($optionIds as $index => $optionId) {
                $optionsByQuestion[$ids[intdiv($index, $perQuestion)]][] = $optionId;
            }
            unset($ids, $optionIds);
        }

        return ['questions' => $byAssessment, 'options' => $optionsByQuestion];
    }

    /**
     * Enrolments and everything that hangs off them: progress, attempts, responses, sessions,
     * results and certificates.
     *
     * @param list<array{id:int,modules:list<int>,assessments:list<int>,questions:array<int,list<int>>,options:array<int,list<int>>,title:string}> $courses
     * @param array{all:list<int>,students:list<int>,owners:list<int>,editors:list<int>,admins:list<int>} $people
     */
    private function generateEnrolmentActivity(
        SeedGenerationPlan $plan,
        string $token,
        string $suffix,
        array $courses,
        array $people
    ): void {
        if ($courses === [] || $people['students'] === []) {
            return;
        }

        $learners = $people['students'];
        $now = gmdate('Y-m-d H:i:sP');

        $seenPairs = [];
        // How many enrolments have been given a full history so far. The plan caps it.
        $worked = 0;
        // Certificate numbers run across the whole set, so the counter cannot live inside a chunk:
        // reset per chunk it would issue SEED-<key>-000000 once per chunk instead of once.
        $certificateSequence = 0;
        $learnerCount = count($learners);
        $courseCount = count($courses);

        // This phase writes eleven tables and used to build every row of all of them before
        // issuing a single statement, which is why it was the largest of the six. A chunk of
        // enrolments now carries its own progress, attempts, responses, sessions, results and
        // certificates through to the database and is then discarded.
        //
        // One consequence worth stating: the random sequence is consumed in a different order than
        // it was when every enrolment's attempts were built before any enrolment's responses. A
        // token still rebuilds its own graph exactly - that is what reproducibility means here -
        // but a token does not rebuild the graph the previous arrangement produced for it.
        for ($offset = 0; $offset < $plan->enrolments; $offset += self::GENERATION_CHUNK) {
            $size = min(self::GENERATION_CHUNK, $plan->enrolments - $offset);

            $enrolmentRows = [];
            $context = [];

            for ($j = 0; $j < $size; $j++) {
                $i = $offset + $j;
                $learner = $learners[$i % $learnerCount];
                $course = $courses[($i * 7 + intdiv($i, $learnerCount)) % $courseCount];

                // One active enrolment per learner and course: the schema enforces it with a
                // partial unique index. The plan never asks for more enrolments than there are
                // people and each pass takes the next person in turn, so a repeat should be
                // impossible - but the guard stays, because a skipped row here is a silent
                // under-delivery rather than an error, which is precisely how the old shortfall
                // stayed invisible.
                $pair = $learner . ':' . $course['id'];
                if (isset($seenPairs[$pair])) {
                    continue;
                }
                $seenPairs[$pair] = true;

                $stage = $i % 3;
                $status = match ($stage) {
                    0 => 'assigned',
                    1 => 'active',
                    default => 'completed',
                };

                $context[] = [$course, $status];
                $enrolmentRows[] = [
                    Uuid::v4(), $learner, $course['id'], 'seed', $status, 31536000,
                    $stage > 0 ? $now : null,
                    $stage === 2 ? $now : null,
                ];
            }

            if ($enrolmentRows === []) {
                continue;
            }

            $enrolmentIds = $this->write(
                'course_enrolments',
                ['public_id', 'user_id', 'course_id', 'source_type', 'status', 'access_period_seconds', 'started_at', 'completed_at'],
                $enrolmentRows,
                true
            );
            unset($enrolmentRows);

            $progressRows = [];
            $attemptRows = [];
            $attemptContext = [];
            $sessionRows = [];
            $sessionContext = [];
            $resultRows = [];
            $certificateRows = [];

            foreach ($enrolmentIds as $index => $enrolmentId) {
                [$course, $entryStatus] = $context[$index];
                $complete = $entryStatus === 'completed';

                // Only the planned share of enrolments is worked through, and the projection counts
                // the same figure. The two used to disagree in both directions: the projection
                // assumed every enrolment produced attempts, sessions and answers while the
                // generator skipped every one that had not been started, so those four tables
                // under-delivered by exactly a third; and progress was written for every enrolment
                // whose course happened to have modules, which the projection had no way to
                // predict, so that one over-delivered.
                //
                // Progress belongs inside this gate rather than above it. Module progress means
                // somebody opened the modules, and an enrolment with no assessment activity at all
                // did not.
                if ($worked >= $plan->workedEnrolments || $course['assessments'] === []) {
                    continue;
                }
                $worked++;

                foreach ($course['modules'] as $moduleId) {
                    $progressRows[] = [
                        $enrolmentId, $moduleId, $now, $now,
                        $complete ? $now : null,
                        $complete ? 75.0 : null,
                        $complete ? 'MERIT' : null,
                    ];
                }

                $assessmentId = $course['assessments'][0];
                $questions = $course['questions'][$assessmentId] ?? [];
                $maximum = max(1, count($questions));

                for ($attempt = 1; $attempt <= SeedGenerationPlan::ATTEMPTS_PER_ENROLMENT; $attempt++) {
                    $earned = $this->next($maximum + 1);
                    $percentage = round($earned / $maximum * 100, 2);
                    $attemptContext[] = [$questions, $earned, $course['options']];
                    $attemptRows[] = [
                        Uuid::v4(), $enrolmentId, $assessmentId, $attempt,
                        $earned, $maximum, $percentage,
                        $this->gradeFor($percentage), $percentage >= 50.0, $now,
                    ];
                }

                $sessionContext[] = $questions;
                $sessionRows[] = [
                    Uuid::v4(), $enrolmentId, $assessmentId, 'graded', 1, 'submitted',
                    $maximum, $maximum, $now, gmdate('Y-m-d H:i:sP', time() + 3600), $now,
                ];

                if ($complete) {
                    $overall = round(60 + $this->next(40), 2);
                    $resultRows[] = [$enrolmentId, $overall, $overall, $overall, $this->gradeFor($overall), $overall >= 50.0];

                    $certificateRows[] = [
                        Uuid::v4(), $enrolmentId,
                        'SEED-' . strtoupper($suffix) . '-' . str_pad((string) $certificateSequence, 6, '0', STR_PAD_LEFT),
                        'Seed Learner', $course['title'], $this->gradeFor($overall), $overall, $now,
                    ];
                    $certificateSequence++;
                }
            }
            unset($context, $enrolmentIds);

            $this->write(
                'module_progress',
                ['enrolment_id', 'module_id', 'first_opened_at', 'last_viewed_at', 'completed_at', 'best_percentage', 'best_grade_code'],
                $progressRows
            );
            unset($progressRows);

            $attemptIds = $this->write(
                'assessment_attempts',
                ['public_id', 'enrolment_id', 'assessment_id', 'attempt_number', 'earned_points', 'maximum_points', 'percentage', 'grade_code', 'passed', 'submitted_at'],
                $attemptRows,
                true
            );
            unset($attemptRows);

            $responseRows = [];
            foreach ($attemptIds as $index => $attemptId) {
                [$entryQuestions, $entryEarned, $entryOptions] = $attemptContext[$index];
                foreach ($entryQuestions as $position => $questionId) {
                    $options = $entryOptions[$questionId] ?? [];
                    if ($options === []) {
                        continue;
                    }
                    $responseRows[] = [
                        $attemptId,
                        $questionId,
                        $options[$this->next(count($options))],
                        $position < $entryEarned,
                    ];
                }
            }
            unset($attemptContext, $attemptIds);
            $this->write('assessment_responses', ['attempt_id', 'question_id', 'selected_option_id', 'is_correct'], $responseRows);
            unset($responseRows);

            $sessionIds = $this->write(
                'assessment_sessions',
                ['public_id', 'enrolment_id', 'assessment_id', 'attempt_mode', 'attempt_number', 'status', 'selected_question_count', 'current_sequence', 'started_at', 'deadline_at', 'completed_at'],
                $sessionRows,
                true
            );
            unset($sessionRows);

            $sessionQuestionRows = [];
            foreach ($sessionIds as $index => $sessionId) {
                foreach ($sessionContext[$index] as $position => $questionId) {
                    $sessionQuestionRows[] = [$sessionId, $questionId, $position + 1, 'answered', $now];
                }
            }
            unset($sessionContext, $sessionIds);
            $this->write(
                'assessment_session_questions',
                ['session_id', 'question_id', 'sequence', 'response_status', 'submitted_at'],
                $sessionQuestionRows
            );
            unset($sessionQuestionRows);

            $this->write(
                'course_results',
                ['enrolment_id', 'module_percentage', 'final_percentage', 'overall_percentage', 'grade_code', 'passed'],
                $resultRows
            );
            unset($resultRows);

            $this->write(
                'certificates',
                ['public_id', 'enrolment_id', 'certificate_number', 'learner_name', 'course_title', 'grade_code', 'overall_percentage', 'issued_at'],
                $certificateRows
            );
            unset($certificateRows);
        }
    }

    private function gradeFor(float $percentage): string
    {
        foreach (self::GRADE_BANDS as $band) {
            if ($percentage >= $band[2]) {
                return $band[0];
            }
        }

        return 'FAIL';
    }

    /**
     * Favourites, course requests, company credits and their allocations.
     *
     * @param list<array{id:int,modules:list<int>,assessments:list<int>,questions:array<int,list<int>>,options:array<int,list<int>>,title:string}> $courses
     * @param list<array{id:int,domain:string,name:string}> $companies
     * @param array{all:list<int>,students:list<int>,owners:list<int>,editors:list<int>,admins:list<int>} $people
     */
    private function generateCommercialRecords(
        SeedGenerationPlan $plan,
        string $token,
        array $courses,
        array $companies,
        array $people
    ): void {
        if ($courses === [] || $people['students'] === []) {
            return;
        }
        $learners = $people['students'];

        $favouriteRows = [];
        $seen = [];
        for ($i = 0; $i < $plan->favourites; $i++) {
            $learner = $learners[$i % count($learners)];
            $course = $courses[($i * 3) % count($courses)];
            $pair = $learner . ':' . $course['id'];
            if (isset($seen[$pair])) {
                continue;
            }
            $seen[$pair] = true;
            $favouriteRows[] = [$learner, $course['id']];
        }
        $this->write('course_favourites', ['user_id', 'course_id'], $favouriteRows);

        $requestRows = [];
        for ($i = 0; $i < $plan->requests; $i++) {
            $learner = $learners[$i % count($learners)];
            $course = $courses[($i * 5) % count($courses)];
            $requestRows[] = [
                Uuid::v4(), $learner, $companies[$i % count($companies)]['id'], $course['id'],
                31536000, $i % 2 === 0 ? 'pending' : 'approved',
            ];
        }
        $this->write(
            'course_requests',
            ['public_id', 'user_id', 'company_id', 'course_id', 'access_period_seconds', 'status'],
            $requestRows
        );

        // course_credits requires exactly one holder: a company or a person, never both.
        $creditRows = [];
        for ($i = 0; $i < $plan->credits; $i++) {
            $creditRows[] = [
                Uuid::v4(), $companies[$i % count($companies)]['id'], null,
                $courses[($i * 2) % count($courses)]['id'], 31536000,
                $this->next(8) + 2, 'seed',
            ];
        }
        $creditIds = $this->write(
            'course_credits',
            ['public_id', 'company_id', 'user_id', 'course_id', 'access_period_seconds', 'quantity', 'source_type'],
            $creditRows,
            true
        );

        $allocationRows = [];
        foreach ($creditIds as $index => $creditId) {
            $allocationRows[] = [$creditId, $learners[$index % count($learners)], null, 'assigned'];
        }
        $this->write(
            'course_credit_allocations',
            ['credit_id', 'user_id', 'enrolment_id', 'status'],
            $allocationRows
        );
    }

    /**
     * Course edit history and audit activity, so the Activity screen has volume to page through.
     *
     * @param list<array{id:int,modules:list<int>,assessments:list<int>,questions:array<int,list<int>>,options:array<int,list<int>>,title:string}> $courses
     * @param array{all:list<int>,students:list<int>,owners:list<int>,editors:list<int>,admins:list<int>} $people
     */
    private function generateAuditTrail(SeedGenerationPlan $plan, string $token, array $courses, array $people): void
    {
        $historyRows = [];
        foreach ($courses as $course) {
            $historyRows[] = [
                $course['id'],
                $people['owners'][0] ?? null,
                'course.created',
                'course',
                'Generated seed course created.',
            ];
        }
        $this->write(
            'course_edit_history',
            ['course_id', 'user_id', 'event_key', 'entity_type', 'summary'],
            $historyRows
        );

        // The audit trail is the balancing figure: every other quantity is a ratio that rounds on
        // its own, and an audit row costs exactly one row and references only rows that already
        // exist. Writing precisely what the plan projected is what makes a request for 100,000
        // deliver 100,000 rather than something several percent short of it.
        $events = ['seed.person_created', 'seed.course_published', 'auth.login', 'course.enrolment.created'];
        $actors = $people['all'] !== [] ? $people['all'] : [null];
        $auditRows = [];
        for ($i = 0; $i < $plan->auditEntries; $i++) {
            $auditRows[] = [$actors[$i % count($actors)], $events[$i % count($events)]];
        }
        $this->write('audit_log', ['user_id', 'event_key'], $auditRows);
    }
