/*
Generated by: Claude Code CLI

Date time: 2026/09/05 11:00 SAST

Version: 0.6

Description:
Draws the generated names a seed set uses: people, companies and course titles.

Architectural boundary: pure name construction. It reads word lists through {@see SeedNamePools},
combines them, and guarantees every name it returns is one it has not returned before. It writes
nothing and knows nothing about the database beyond the names it is primed with.

Uniqueness is a guarantee, not a probability.

Each name is three words drawn from three lists, so the space is the product of the three pool
sizes - around 1.5 billion person names, 165 million company names and 19 million course titles on
the shipped lists. At those sizes a random draw almost never repeats, but "almost never" is not the
requirement: the requirement is proper names that are unique across the seed database, with nothing
appended to force it. So every combination drawn is remembered and a repeat is redrawn. Fifteen
thousand people cost about a hundred redraws in total, and the result is exact rather than likely.

Priming carries that across sets. Given the names already in the database, a second seed set will
not repeat a person from the first - again without a discriminator, because the space is four
orders of magnitude larger than anything that will be drawn from it.

Randomness comes from a seeded Mt19937 through Random\Randomizer: reproducible for a given seed
token, so a set can be regenerated identically, and isolated, so nothing else in the process can
shift the sequence. It replaces a hand-written linear congruential generator whose low bits were
taken modulo the pool size - a combination that could only ever reach half of an even-sized list.
Against the previous 34 first names and 28 surnames it produced 17 and 14 of them respectively, and
237 distinct full names across 1,282 people where 700 were expected.

Changelog:
2026/09/05 11:00 SAST
- Created for the v0.6 seed name pools.
*/

declare(strict_types=1);

namespace CattoLearning\Seed;

use Random\Engine\Mt19937;
use Random\Randomizer;
use RuntimeException;

final class SeedNameFactory
{
    /**
     * How many times a draw may repeat before the pools are declared exhausted.
     *
     * A generous ceiling on an event that should not happen. With the shipped lists the chance of
     * even two consecutive collisions is negligible; hitting this many in a row means the pools
     * have been edited down to something far smaller than the set being generated, and saying so
     * is more useful than looping until the request times out.
     */
    private const MAX_ATTEMPTS = 200;

    private readonly Randomizer $random;

    /** @var array<int,true> Person names already issued or already in the database, by hash. */
    private array $usedPeople = [];

    /** @var array<int,true> */
    private array $usedCompanies = [];

    /** @var array<int,true> */
    private array $usedCourses = [];

    public function __construct(
        private readonly SeedNamePools $pools,
        string $seed
    ) {
        // Seeded from the set's own token, so regenerating a set with the same token reproduces it
        // exactly, and two sets generated in the same second do not share a sequence.
        $this->random = new Randomizer(new Mt19937(abs(crc32($seed)) ?: 1));
    }

    /**
     * Treats the given names as already taken.
     *
     * The caller passes what the database already holds, so a second seed set cannot repeat a
     * person, company or course title from the first.
     *
     * @param iterable<string> $people
     * @param iterable<string> $companies
     * @param iterable<string> $courses
     */
    public function reserve(iterable $people, iterable $companies, iterable $courses): void
    {
        foreach ($people as $name) $this->usedPeople[self::key($name)] = true;
        foreach ($companies as $name) $this->usedCompanies[self::key($name)] = true;
        foreach ($courses as $name) $this->usedCourses[self::key($name)] = true;
    }

    /**
     * One person, with a middle name only some of the time.
     *
     * Most people are known by two names, so most generated people have none. `middle_names` holds
     * everything between the first name and the surname, whether that is one name or several, and
     * is an empty string when there is nothing between them.
     *
     * Uniqueness is over the full name as displayed. Two people may share a first name and a
     * surname if one of them has a middle name and the other does not, exactly as in life.
     *
     * @return array{first:string,middle:string,last:string,display:string}
     */
    public function person(): array
    {
        $first = $this->pool('first-names');
        $last = $this->pool('surnames');
        $middle = $this->pool('middle-names');

        for ($attempt = 0; $attempt < self::MAX_ATTEMPTS; $attempt++) {
            $firstName = $first[$this->random->getInt(0, count($first) - 1)];
            $lastName = $last[$this->random->getInt(0, count($last) - 1)];

            // Roughly two in five carry a middle name and one in twelve carry two, which is about
            // what a real population looks like and keeps the second column worth rendering.
            $roll = $this->random->getInt(1, 12);
            $middleNames = [];
            if ($roll <= 5) {
                $middleNames[] = $middle[$this->random->getInt(0, count($middle) - 1)];
            }
            if ($roll === 1) {
                $middleNames[] = $middle[$this->random->getInt(0, count($middle) - 1)];
            }
            $middleNames = array_values(array_unique($middleNames));

            $display = trim($firstName . ' ' . implode(' ', $middleNames) . ' ' . $lastName);
            $display = (string) preg_replace('/\s+/', ' ', $display);

            if (!isset($this->usedPeople[self::key($display)])) {
                $this->usedPeople[self::key($display)] = true;

                return [
                    'first' => $firstName,
                    'middle' => implode(' ', $middleNames),
                    'last' => $lastName,
                    'display' => $display,
                ];
            }
        }

        throw self::exhausted('people', count($first) * count($middle) * count($last));
    }

    /** One company name: a place, what sort of firm it is, and the trade it is in. */
    public function company(): string
    {
        $places = $this->pool('company-places');
        $qualities = $this->pool('company-qualities');
        $sectors = $this->pool('company-sectors');

        for ($attempt = 0; $attempt < self::MAX_ATTEMPTS; $attempt++) {
            $name = $places[$this->random->getInt(0, count($places) - 1)]
                . ' ' . $qualities[$this->random->getInt(0, count($qualities) - 1)]
                . ' ' . $sectors[$this->random->getInt(0, count($sectors) - 1)];

            if (!isset($this->usedCompanies[self::key($name)])) {
                $this->usedCompanies[self::key($name)] = true;

                return $name;
            }
        }

        throw self::exhausted('companies', count($places) * count($qualities) * count($sectors));
    }

    /**
     * One course title: the subject matter, how deep the course goes, and sometimes the field.
     *
     * The domain prefix is applied to about two courses in five rather than to all of them, and
     * that is a deliberate retreat from the original design. A topic is already a complete and
     * sensible course name - "Fire Marshal Duties", "Confined Space Entry" - so crossing every
     * topic with every field produced titles like "Game Ranching Telephone Technique", which is
     * precisely the kind of nonsense generated data is not allowed to contain. Most titles are
     * therefore the topic itself, and the prefix appears often enough to give the catalogue
     * variety without making incoherence the norm.
     *
     * The remaining odd pairing is possible and accepted: a blind cross-product of two independent
     * lists cannot be made semantically coherent without tagging every word, which is a far larger
     * design than a set of editable text files.
     */
    /**
     * A course title named after the category it is filed under.
     *
     * The title and the category used to come from two unrelated word lists, so the catalogue was
     * full of courses whose category said nothing about them - and a category page listed a set of
     * courses with no subject in common, which is the opposite of what a taxonomy is for.
     *
     * The level varies so one category yields many distinct courses, and a subject prefix is added
     * once the levels for that category are used up. Nothing is appended to make a title unique:
     * the combination space is the category count times the level count, and beyond that the prefix
     * widens it again.
     */
    public function courseTitleFor(string $categoryName): string
    {
        $levels = $this->pool('course-levels');
        $subjects = $this->pool('course-subjects');
        $topics = $this->pool('course-topics');

        for ($attempt = 0; $attempt < self::MAX_ATTEMPTS; $attempt++) {
            // The category leads, because a course filed under Health and Safety should say so, and
            // there are only ever a few dozen categories. The variety therefore has to come from
            // what follows the colon, and it has to come from more than one word: a quarter of a
            // million courses across forty-five categories is five thousand titles per category,
            // and one word per title would spend the pool and read as a list of near-identical
            // names long before that. Two words is fifty million per category.
            $tail = $levels[$this->random->getInt(0, count($levels) - 1)];
            if ($this->random->getInt(1, 5) > 2) {
                $tail .= ' ' . $topics[$this->random->getInt(0, count($topics) - 1)];
            }
            // A leading subject appears on a minority, so the column is not one shape repeated.
            $prefix = $this->random->getInt(1, 5) === 1
                ? $subjects[$this->random->getInt(0, count($subjects) - 1)] . ' '
                : '';
            $title = $prefix . $categoryName . ': ' . $tail;

            if (!isset($this->usedCourses[self::key($title)])) {
                $this->usedCourses[self::key($title)] = true;

                return $title;
            }
        }

        throw self::exhausted('course titles', count($levels) * count($topics) * count($subjects));
    }

    public function courseTitle(): string
    {
        $subjects = $this->pool('course-subjects');
        $topics = $this->pool('course-topics');
        $levels = $this->pool('course-levels');

        for ($attempt = 0; $attempt < self::MAX_ATTEMPTS; $attempt++) {
            $prefix = $this->random->getInt(1, 5) <= 2
                ? $subjects[$this->random->getInt(0, count($subjects) - 1)] . ' '
                : '';
            $title = $prefix
                . $topics[$this->random->getInt(0, count($topics) - 1)]
                . ': ' . $levels[$this->random->getInt(0, count($levels) - 1)];

            if (!isset($this->usedCourses[self::key($title)])) {
                $this->usedCourses[self::key($title)] = true;

                return $title;
            }
        }

        throw self::exhausted('course titles', count($subjects) * count($topics) * count($levels));
    }

    /**
     * Category names, drawn without replacement so a set never lists the same one twice.
     *
     * @return list<string>
     */
    public function categories(int $count): array
    {
        $categories = $this->pool('course-categories');
        $shuffled = $this->random->shuffleArray($categories);

        return array_slice($shuffled, 0, max(1, min($count, count($shuffled))));
    }

    /**
     * How many distinct names each kind can produce from the current pools.
     *
     * @return array{people:int,companies:int,courses:int}
     */
    public function capacity(): array
    {
        return [
            'people' => count($this->pool('first-names')) * count($this->pool('middle-names')) * count($this->pool('surnames')),
            'companies' => count($this->pool('company-places')) * count($this->pool('company-qualities')) * count($this->pool('company-sectors')),
            'courses' => count($this->pool('course-subjects')) * count($this->pool('course-topics')) * count($this->pool('course-levels')),
        ];
    }

    /** @return list<string> */
    private function pool(string $name): array
    {
        return $this->pools->pool($name);
    }

    /** Case and spacing are not what makes two names different, so neither decides uniqueness. */
    /**
     * The set key for a name: a 64-bit hash of it, not the name itself.
     *
     * These sets are primed with every name already in the database, so their size follows the
     * installation's accumulated history rather than the size of the set being generated - a small
     * request pays for every row ever generated before it. Holding the normalised names as string
     * keys cost 26 MB at 141,067 people; the same names as integer keys cost 12 MB, because an
     * integer key is a bucket and a string key is a bucket plus an interned string.
     *
     * Nothing ever reads a name back out - only membership is ever asked - so the original is not
     * needed. A collision would cost one unnecessary redraw and can never produce a duplicate: the
     * database's own UNIQUE constraints remain the authority on that, and this set is only how the
     * factory avoids proposing a name it would then have to retry.
     */
    private static function key(string $name): int
    {
        $normalised = mb_strtolower((string) preg_replace('/\s+/', ' ', trim($name)));

        return (int) unpack('q', substr(hash('xxh128', $normalised, true), 0, 8))[1];
    }

    private static function exhausted(string $kind, int $capacity): RuntimeException
    {
        return new RuntimeException(
            'Ran out of distinct ' . $kind . ' after ' . self::MAX_ATTEMPTS . ' attempts. The name '
            . 'pools can produce ' . number_format($capacity) . ' combinations; add more names in '
            . 'storage/seeds/ or generate a smaller set.'
        );
    }
}
