declare(strict_types=1);

namespace CattoLearning;

use Symfony\Bundle\FrameworkBundle\Kernel\MicroKernelTrait;
use Symfony\Component\DependencyInjection\ContainerBuilder;
use Symfony\Component\HttpKernel\Kernel as BaseKernel;

final class Kernel extends BaseKernel
{
    use MicroKernelTrait;

    /**
     * @param string $instanceRoot The writable instance tree: .env, storage, themes, public_html.
     */
    public function __construct(
        string $environment,
        bool $debug,
        private readonly string $instanceRoot
    ) {
        parent::__construct($environment, $debug);
    }

    /** The release directory, which is what `code/current` resolves to. */
    public function getProjectDir(): string
    {
        return dirname(__DIR__);
    }

    /** This release's own cache: storage/cache/symfony/<release>/<environment>. */
    public function getCacheDir(): string
    {
        return $this->instanceRoot . '/storage/cache/symfony/' . self::releaseCacheKey($this->getProjectDir()) . '/' . $this->environment;
    }

    /**
     * The release's part of the cache folder: the code's folder name (0.9.10, or a checkout's name), in letters, digits,
     * dots, hyphens and underscores, then 8 hex digits of its full path, so two folders of one name in different places
     * never meet. The installers delete "<version>-*" before they build a release and prune the folders of releases
     * they delete.
     */
    public static function releaseCacheKey(string $projectDir): string
    {
        $name = trim((string) preg_replace('/[^A-Za-z0-9._-]+/', '-', basename($projectDir)), '-');
        return ($name !== '' ? $name : 'release') . '-' . substr(hash('sha256', $projectDir), 0, 8);
    }

    public function getBuildDir(): string
    {
        return $this->getCacheDir();
    }

    public function getLogDir(): string
    {
        return $this->instanceRoot . '/storage/logs';
    }

    /** The instance root, exposed so services can be given it without reading the environment. */
    public function getInstanceRoot(): string
    {
        return $this->instanceRoot;
    }

    /**
     * The three roots, as container parameters.
     *
     * Several services take one of them as a constructor string - where a course's media is
     * written, where the bundled imports are read from - and the value is a property of the
     * deployment rather than of the service. Setting them here means config/services.yaml can bind
     * them by name once, instead of every definition repeating a path.
     *
     * They are baked into the compiled container. That is correct: the cache lives under the
     * instance root, so a container compiled for one instance is never read by another.
     */
    protected function build(ContainerBuilder $container): void
    {
        $container->setParameter('catto.code_root', $this->getProjectDir());
        $container->setParameter('catto.instance_root', $this->instanceRoot);
        $container->setParameter('catto.public_root', $this->instanceRoot . '/public_html');
    }
}
