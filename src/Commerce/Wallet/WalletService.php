/*
Generated by: Claude Code CLI

Date time: 2026/10/17 SAST

Version: 0.9.4

Description:
Wallets and the money ledger (owner, 2026-10-17). Wallets replace Account Funds: a person's or company's
Rand credit, spent on courses and company credits and never paid out as cash. Every movement is one
ledger row; credit lives in lots, each with the expiry fixed when it was issued (the wallet credit
expiry setting, 3 years by default), and is spent oldest first. Only a lot older than the limit
expires, and the expiry is recorded in the ledger. No interest accrues.

Credit comes from refunds paid to the wallet, the part of an EFT above its order, a payment for an
order that was cancelled before it was paid in full, and ADMIN corrections. A wallet payment held for
an unpaid order goes back to the lots it came from when the order is cancelled, and a refund of a
wallet-paid order goes back the same way: both keep the credit's original expiry, so buying and
refunding never renews credit.

Every method expects the caller's transaction and takes the wallet's row lock first, so two spends
can never take the same credit.

Changelog:
2026/10/17 SAST
- Created with the money ledger and wallets.
*/

declare(strict_types=1);

namespace CattoLearning\Commerce\Wallet;

use CattoLearning\Commerce\Settings\CommerceSettings;
use CattoLearning\Support\Money;
use DateTimeImmutable;
use InvalidArgumentException;
use RuntimeException;
use Symfony\Component\Clock\ClockInterface;

final class WalletService
{
    public function __construct(
        private readonly WalletRepository $wallets,
        private readonly CommerceSettings $settings,
        private readonly ClockInterface $clock
    ) {
    }

    /** What the owner's wallet holds now. */
    public function balance(WalletOwner $owner, string $currency = 'ZAR'): int
    {
        $id = $this->wallets->walletId($owner, $currency);

        return $id === null ? 0 : $this->wallets->balance($id);
    }

    /** What the owner can spend now: credit not yet expired. */
    public function spendable(WalletOwner $owner, string $currency = 'ZAR'): int
    {
        $id = $this->wallets->walletId($owner, $currency);
        if ($id === null) return 0;

        return array_sum(array_column($this->wallets->openLots($id, $this->clock->now()->format(DATE_ATOM)), 'remaining'));
    }

    /**
     * A ledger row that is not a wallet movement: a payment received, a processor fee, a refund owed
     * or paid, a deduction. $refs carries order_id, order_item_id, payment_id, refund_id,
     * document_number, external_reference, actor_user_id and memo as they apply.
     *
     * @param array<string,mixed> $refs
     */
    public function record(string $kind, ?WalletOwner $owner, int $amount, string $currency, string $method, array $refs = [], ?string $occurredAt = null): ?int
    {
        if ($amount <= 0) return null;
        [$wallet, $cash] = LedgerKind::effects($kind);
        if ($wallet !== 0) throw new InvalidArgumentException('Use credit() or a spend for a wallet movement.');

        return $this->wallets->insertEntry($refs + ['kind' => $kind, 'occurred_at' => $occurredAt ?? $this->now(), 'owner' => $owner, 'amount_minor' => $amount,
            'currency' => $currency, 'wallet_effect' => 0, 'cash_effect' => $cash, 'method' => $method]);
    }

    /**
     * New credit for the owner: one ledger row and one lot, expiring after the wallet credit expiry
     * setting in force now.
     *
     * @param array<string,mixed> $refs
     */
    public function credit(WalletOwner $owner, string $kind, int $amount, string $currency, string $method, array $refs = []): int
    {
        if ($amount <= 0) throw new InvalidArgumentException('Wallet credit must be more than nothing.');
        [$walletEffect] = LedgerKind::effects($kind);
        if ($walletEffect !== 1 && $kind !== 'correction') throw new InvalidArgumentException('That ledger kind does not credit a wallet.');
        $walletId = $this->wallets->lockWallet($owner, $currency);
        $now = $this->clock->now();
        $entry = $this->wallets->insertEntry($refs + ['kind' => $kind, 'occurred_at' => $now->format(DATE_ATOM), 'owner' => $owner, 'amount_minor' => $amount,
            'currency' => $currency, 'wallet_effect' => 1, 'cash_effect' => 0, 'method' => $method]);
        $this->wallets->insertLot($walletId, $entry, $amount, $now->format(DATE_ATOM), $this->settings->walletExpiry()->after($now)->format(DATE_ATOM));

        return $entry;
    }

    /**
     * Pays part or all of an order from the wallet: the credit is taken now, oldest unexpired lots
     * first, and the payment is held until the order is paid or cancelled.
     */
    public function payForOrder(WalletOwner $owner, int $orderId, int $amount, string $currency, ?string $paymentId = null): int
    {
        if ($amount <= 0) throw new InvalidArgumentException('A wallet payment must be more than nothing.');

        return $this->spend($owner, 'wallet_payment', $amount, $currency, ['order_id' => $orderId, 'payment_id' => $paymentId], 'Your wallet does not hold enough credit for this payment.');
    }

    /**
     * Returns what the order's wallet payment still holds to the lots it came from (kind
     * wallet_payment_released for an unpaid order that was cancelled, refund_to_wallet for a refund),
     * keeping each credit's original expiry. Returns the amount given back, at most $limit.
     *
     * @param array<string,mixed> $refs
     */
    public function returnOrderPayment(WalletOwner $owner, int $orderId, string $currency, string $kind, ?int $limit = null, array $refs = []): int
    {
        if (!in_array($kind, ['wallet_payment_released', 'refund_to_wallet'], true)) throw new InvalidArgumentException('That ledger kind does not return a wallet payment.');
        $this->wallets->lockWallet($owner, $currency);
        $given = $this->wallets->givenToOrder($orderId);
        $available = array_sum(array_column($given, 'given'));
        $amount = $limit === null ? $available : min($limit, $available);
        if ($amount <= 0) return 0;
        $now = $this->now();
        $entry = $this->wallets->insertEntry($refs + ['kind' => $kind, 'occurred_at' => $now, 'owner' => $owner, 'order_id' => $orderId, 'amount_minor' => $amount,
            'currency' => $currency, 'wallet_effect' => 1, 'cash_effect' => 0, 'method' => 'wallet']);
        $left = $amount;
        foreach ($given as $lot) {
            if ($left <= 0) break;
            $back = min($left, $lot['given']);
            $this->wallets->insertAllocation($lot['lot_id'], $entry, -$back, $now);
            $left -= $back;
        }

        return $amount;
    }

    /** True once a payment's receipt has been recorded in the ledger. */
    public function hasPaymentEntry(string $paymentId): bool
    {
        return $this->wallets->hasEntry('payment_received', $paymentId);
    }

    /** The processor fee recorded on a payment, or 0. */
    public function processorFee(string $paymentId): int
    {
        return $this->wallets->processorFeeForPayment($paymentId);
    }

    /** What the order's wallet payment still holds (taken, less what has gone back). */
    public function heldForOrder(int $orderId): int
    {
        return $this->wallets->walletPaidForOrder($orderId);
    }

    /**
     * Writes off the value left in credits whose expiry has passed, each as its own credit_expired
     * row. Returns how many credits expired.
     */
    public function expireDue(int $limit = 200): int
    {
        $now = $this->now();
        $count = 0;
        foreach ($this->wallets->expiredLots($now, $limit) as $lot) {
            $owner = $lot['owner_company_id'] !== null ? WalletOwner::company($lot['owner_company_id']) : WalletOwner::person((int) $lot['owner_user_id']);
            $this->wallets->lockWallet($owner, $lot['currency']);
            $remaining = array_values(array_filter($this->wallets->openLots($lot['wallet_id']), static fn(array $open): bool => $open['id'] === $lot['id']))[0]['remaining'] ?? 0;
            if ($remaining <= 0) continue;
            $entry = $this->wallets->insertEntry(['kind' => 'credit_expired', 'occurred_at' => $now, 'owner' => $owner, 'amount_minor' => $remaining, 'currency' => $lot['currency'],
                'wallet_effect' => -1, 'cash_effect' => 0, 'method' => 'none', 'memo' => 'Credit issued and not used by ' . (new DateTimeImmutable($lot['expires_at']))->format('j F Y')]);
            $this->wallets->insertAllocation($lot['id'], $entry, $remaining, $now);
            $count++;
        }

        return $count;
    }

    /**
     * Wallets whose credit expires within the reminder period and that have not been reminded about
     * it, for the reminder email. Mark each credit with markReminded() once the email is sent.
     *
     * @return list<array{wallet_id:int,owner_user_id:?int,owner_company_id:?int,currency:string,lots:list<array{id:int,remaining:int,expires_at:string}>}>
     */
    public function remindersDue(int $limit = 20): array
    {
        $now = $this->clock->now();

        return $this->wallets->reminderDue($now->format(DATE_ATOM), $this->settings->walletReminder()->after($now)->format(DATE_ATOM), $limit);
    }

    /**
     * Who is told about a wallet: the person, or the company's active administrators.
     *
     * @return list<array{email:string,name:string}>
     */
    public function recipients(WalletOwner $owner): array
    {
        return $this->wallets->recipients($owner);
    }

    public function markReminded(int $lotId): void
    {
        $this->wallets->markReminded($lotId, $this->now());
    }

    /**
     * An ADMIN correction with a written reason: more credit as a new lot, or less taken from the
     * oldest credit. Never an edit of an earlier row.
     */
    public function correct(WalletOwner $owner, int $deltaMinor, string $currency, string $reason, int $actorId, ?int $correctsEntryId = null): int
    {
        $reason = trim($reason);
        if (mb_strlen($reason) < 5 || mb_strlen($reason) > 2000) throw new InvalidArgumentException('Write why the wallet is corrected, in 5 to 2,000 characters.');
        if ($deltaMinor === 0) throw new InvalidArgumentException('Enter the amount to add or take away.');
        $refs = ['memo' => $reason, 'actor_user_id' => $actorId, 'corrects_entry_id' => $correctsEntryId];
        if ($deltaMinor > 0) return $this->credit($owner, 'correction', $deltaMinor, $currency, 'none', $refs);

        return $this->spend($owner, 'correction', -$deltaMinor, $currency, $refs, 'The wallet holds less than that.');
    }

    /**
     * Owner's statement page: rows newest first with the balance after each, money as labels.
     *
     * @return array{rows:list<array<string,mixed>>,total:int}
     */
    public function statement(WalletOwner $owner, int $limit, int $offset, ?string $from = null, ?string $to = null, string $currency = 'ZAR'): array
    {
        $rows = [];
        foreach ($this->wallets->statement($owner, $currency, $limit, $offset, $from, $to) as $row) {
            $amount = (int) $row['amount_minor'];
            $row['label'] = LedgerKind::label((string) $row['kind']);
            $row['in_label'] = (int) $row['wallet_effect'] > 0 ? Money::strictMinorUnits($amount, (string) $row['currency'])->format() : '';
            $row['out_label'] = (int) $row['wallet_effect'] < 0 ? Money::strictMinorUnits($amount, (string) $row['currency'])->format() : '';
            $row['balance_label'] = Money::ofMinorUnits(max(0, (int) $row['balance_after']), (string) $row['currency'])->format();
            $row['order_label'] = $row['order_id'] === null ? '' : 'CL-' . sprintf('%08d', (int) $row['order_id']);
            $rows[] = $row;
        }

        return ['rows' => $rows, 'total' => $this->wallets->statementCount($owner, $currency, $from, $to)];
    }

    /**
     * Credit that expires within the reminder period, soonest first, for the wallet page.
     *
     * @return list<array{amount_label:string,expires_label:string}>
     */
    public function expiringSoon(WalletOwner $owner, string $currency = 'ZAR'): array
    {
        $id = $this->wallets->walletId($owner, $currency);
        if ($id === null) return [];
        $now = $this->clock->now();
        $until = $this->settings->walletReminder()->after($now);
        $soon = [];
        foreach ($this->wallets->openLots($id, $now->format(DATE_ATOM)) as $lot) {
            $expires = new DateTimeImmutable($lot['expires_at']);
            if ($expires > $until) continue;
            $soon[] = ['amount_label' => Money::strictMinorUnits($lot['remaining'], $currency)->format(), 'expires_label' => $expires->setTimezone($now->getTimezone())->format('j F Y')];
        }

        return $soon;
    }

    /** @param array<string,mixed> $refs */
    private function spend(WalletOwner $owner, string $kind, int $amount, string $currency, array $refs, string $shortMessage): int
    {
        $walletId = $this->wallets->lockWallet($owner, $currency);
        $now = $this->now();
        $lots = $this->wallets->openLots($walletId, $now);
        if (array_sum(array_column($lots, 'remaining')) < $amount) throw new RuntimeException($shortMessage);
        $entry = $this->wallets->insertEntry($refs + ['kind' => $kind, 'occurred_at' => $now, 'owner' => $owner, 'amount_minor' => $amount, 'currency' => $currency,
            'wallet_effect' => -1, 'cash_effect' => 0, 'method' => $kind === 'correction' ? 'none' : 'wallet']);
        $left = $amount;
        foreach ($lots as $lot) {
            if ($left <= 0) break;
            $take = min($left, $lot['remaining']);
            $this->wallets->insertAllocation($lot['id'], $entry, $take, $now);
            $left -= $take;
        }

        return $entry;
    }

    private function now(): string
    {
        return $this->clock->now()->format(DATE_ATOM);
    }
}
