    public function reminderDue(string $now, string $until, int $limit): array
    {
        $rows = $this->db->fetchAllAssociative(
            'SELECT l.id, l.wallet_id, l.amount_minor - COALESCE(SUM(a.amount_minor), 0) AS remaining, l.expires_at, w.owner_user_id, w.owner_company_id, w.currency
               FROM commerce_wallet_lots l JOIN commerce_wallets w ON w.id = l.wallet_id LEFT JOIN commerce_wallet_allocations a ON a.lot_id = l.id
              WHERE l.expires_at > :now AND l.expires_at <= :until AND NOT EXISTS (SELECT 1 FROM commerce_wallet_reminders r WHERE r.lot_id = l.id)
              GROUP BY l.id, w.id HAVING l.amount_minor - COALESCE(SUM(a.amount_minor), 0) > 0
              ORDER BY l.wallet_id, l.expires_at, l.id',
            ['now' => $now, 'until' => $until]
        );
        $wallets = [];
        foreach ($rows as $row) {
            $id = (int) $row['wallet_id'];
            $wallets[$id] ??= ['wallet_id' => $id, 'owner_user_id' => $row['owner_user_id'] === null ? null : (int) $row['owner_user_id'], 'owner_company_id' => $row['owner_company_id'] === null ? null : (int) $row['owner_company_id'], 'currency' => (string) $row['currency'], 'lots' => []];
