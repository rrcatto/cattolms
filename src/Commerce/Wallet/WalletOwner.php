namespace CattoLearning\Commerce\Wallet;

use InvalidArgumentException;

final class WalletOwner
{
    private function __construct(public readonly ?int $userId, public readonly ?int $companyId)
    {
    }

    public static function person(int $userId): self
    {
        if ($userId < 1) throw new InvalidArgumentException('A wallet belongs to a person or a company.');

        return new self($userId, null);
    }

    public static function company(int $companyId): self
    {
        if ($companyId < 1) throw new InvalidArgumentException('A wallet belongs to a person or a company.');

        return new self(null, $companyId);
    }

    /**
     * The purchaser's wallet for an order: the company's for a company order, else the person's.
     *
     * @param array<string,mixed> $order a commerce_orders row
     */
    public static function forOrder(array $order): self
    {
        return $order['company_id'] !== null ? self::company((int) $order['company_id']) : self::person((int) $order['purchaser_user_id']);
    }

    public function isCompany(): bool
    {
        return $this->companyId !== null;
    }

    /** "person:12" or "company:3", for keys and references. */
    public function key(): string
    {
        return $this->companyId !== null ? 'company:' . $this->companyId : 'person:' . $this->userId;
    }
}
