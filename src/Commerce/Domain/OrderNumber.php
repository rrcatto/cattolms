namespace CattoLearning\Commerce\Domain;

final class OrderNumber
{
    /** An order number in a route: CL- and at least eight digits. */
    public const REQUIREMENT = 'CL-[0-9]{8,18}';

    private function __construct()
    {
    }

    public static function format(int $orderId): string
    {
        return 'CL-' . str_pad((string) $orderId, 8, '0', STR_PAD_LEFT);
    }

    /** The order a number names, only when it is written exactly as the site writes it. */
    public static function id(string $number): ?int
    {
        if (preg_match('/^CL-([0-9]{8,18})$/', $number, $part) !== 1) return null;
        $id = (int) ltrim($part[1], '0');
        return $id > 0 && self::format($id) === $number ? $id : null;
    }
}
