declare(strict_types=1);

namespace CattoLearning\Commerce\Domain;

use CattoLearning\Support\Duration;
use DateTimeImmutable;

final class RefundRule
{
    private function __construct()
    {
    }

    /** The first moment at which the rule no longer gives a refund. */
    public static function windowEndsAt(DateTimeImmutable $purchasedAt, Duration $window): DateTimeImmutable
    {
        return $window->after($purchasedAt->setTimezone(new \DateTimeZone(date_default_timezone_get())));
    }

    /**
     * Why the rule refuses a refund of one order line now; empty when the rule allows it.
     *
     * @param list<array{title:string,started_at:string}> $started the line's courses whose access has started (a company credit line passes none)
     * @return list<string>
     */
    public static function refusals(DateTimeImmutable $purchasedAt, DateTimeImmutable $now, Duration $window, array $started, bool $bundle = false, bool $company = false): array
    {
        $refusals = [];
        foreach ($started as $course) {
            $on = self::date(new DateTimeImmutable($course['started_at']));
            $refusals[] = $bundle
                ? $course['title'] . ', a course in this bundle, started on ' . $on . '. A started course is not refunded.'
                : 'The course started on ' . $on . '. A started course is not refunded.';
        }
        if ($now >= self::windowEndsAt($purchasedAt, $window)) {
            $refusals[] = 'The refund period of ' . $window->words() . ' from ' . ($company ? 'the credit purchase' : 'the purchase') . ' on ' . self::date($purchasedAt) . ' has ended.';
        }

        return $refusals;
    }

    private static function date(DateTimeImmutable $at): string
    {
        return $at->setTimezone(new \DateTimeZone(date_default_timezone_get()))->format('j F Y');
    }
}
