Description:
The Refund Policy's rule, as the refund action enforces it and the Refund Policy page states it.

A refund is given only while both are true: the learner has not started the course, and fewer than
seven days have passed since the purchase. The purchase is the moment the order's payment was
confirmed. Starting any course of a bundle ends the refund for the whole bundle. Company credits
are refundable for seven days from their purchase; which credits (unused ones only) is decided by
the credit lot accounting, not here.

This class only says why the rule refuses. ADMIN may approve a refused refund with a written
override reason, which RefundAdministrationService records with the refund.

Changelog:
2026/10/13 SAST
- Created for the Refund Policy rule.
