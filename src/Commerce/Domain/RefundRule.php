declare(strict_types=1);

namespace CattoLearning\Commerce\Domain;

use DateTimeImmutable;

final class RefundRule
{
    /** A refund is given while fewer than this many days have passed since the purchase. */
    public const WINDOW_DAYS = 7;

    private function __construct()
    {
    }

    /** The first moment at which the rule no longer gives a refund. */
    public static function windowEndsAt(DateTimeImmutable $purchasedAt): DateTimeImmutable
    {
        return $purchasedAt->modify('+' . self::WINDOW_DAYS . ' days');
    }

    /**
     * Why the rule refuses a refund of one order line now; empty when the rule allows it.
     *
     * @param list<array{title:string,started_at:string}> $started the line's courses the learner has started (a company credit line passes none)
     * @return list<string>
     */
    public static function refusals(DateTimeImmutable $purchasedAt, DateTimeImmutable $now, array $started, bool $bundle = false, bool $company = false): array
    {
        $refusals = [];
        foreach ($started as $course) {
            $on = self::date(new DateTimeImmutable($course['started_at']));
            $refusals[] = $bundle
                ? 'The learner started ' . $course['title'] . ', a course in this bundle, on ' . $on . '.'
                : 'The learner started the course on ' . $on . '.';
        }
        if ($now >= self::windowEndsAt($purchasedAt)) {
            $refusals[] = self::WINDOW_DAYS . ' days have passed since ' . ($company ? 'the credits were bought' : 'the purchase') . ' on ' . self::date($purchasedAt) . '.';
        }

        return $refusals;
    }

    private static function date(DateTimeImmutable $at): string
    {
        return $at->setTimezone(new \DateTimeZone(date_default_timezone_get()))->format('j F Y');
    }
}
