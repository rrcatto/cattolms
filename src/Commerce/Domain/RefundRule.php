Description:
The Refund Policy's rule, as the refund action enforces it and the Refund Policy page states it.

Once a course has started, no refund of any kind is given: no money back and no wallet credit (owner,
2026-10-17). Every course starts the moment its payment is confirmed, so a course bought by a person has
always started once it is paid; its content has been supplied and cannot be returned. Starting any course
of a bundle ends the refund for the whole bundle. A course that has not started is refundable only
within the refund window (the commerce setting, 7 days by default) from the moment the payment was
confirmed. Company credits are refundable within the refund window of their purchase, as wallet credit;
which credits (unused ones only) is decided by the credit lot accounting, not here.

This class only says why the rule refuses. ADMIN may approve a refused refund with a written override
reason, which RefundAdministrationService records with the refund; the Refund Policy does not mention
it. The statutory rights of a buyer of a faulty course are not affected by the rule.

Changelog:
2026/10/17 SAST
- A started course is never refunded, and every course starts on payment; the window is the refund
  window setting (a Duration), no longer a constant.
2026/10/13 SAST
- Created for the Refund Policy rule.
