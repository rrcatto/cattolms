/*
Generated by: Claude Code CLI

Date time: 2026/10/08 SAST

Version: 0.8.9

Description:
The rules for the financial document design (Commerce → Financial Documents): reading its one form
(with an uploaded logo), previewing any of its documents for a sample order, and saving it.

A design is checked before it is saved: it must be complete (FinancialDocumentDesign::problems()),
and every document it draws - the invoice, receipt and credit note of every sample order - must pass
the engine's validator and render with the values FinancialDocumentDataBuilder makes. A preview draws
whatever the form holds through the same builder, renderer and PDF engine as an issued document, so
it is exactly what saving would produce.

Saving publishes a new version of each template the design changes, in one transaction; documents
issued from then on are drawn in it, and documents already issued keep the version they name. The
save is audited (commerce.document_design_updated) with the versions it made.

Changelog:
2026/10/08 SAST
- Created for financial documents on the document template engine (Phase K).
*/

declare(strict_types=1);

namespace CattoLearning\Commerce\Document;

use CattoLearning\Course\Certificate\CertificateImage;
use CattoLearning\Document\DocumentAssetRepository;
use CattoLearning\Document\DocumentBusinessData;
use CattoLearning\Document\DocumentDataException;
use CattoLearning\Document\DocumentPdfRenderer;
use CattoLearning\Document\DocumentTemplateRenderer;
use CattoLearning\Document\DocumentType;
use CattoLearning\Document\RenderedDocument;
use CattoLearning\Document\TemplateValidationException;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\ImageProcessing;
use InvalidArgumentException;

final class FinancialDocumentDesignService
{
    private readonly \Closure $isUploadedFile;

    /** @param (\Closure(string):bool)|null $isUploadedFile tests replace PHP's upload check, which is always false on the CLI */
    public function __construct(
        private readonly FinancialDocumentDesignRepository $templates,
        private readonly FinancialDocumentDesignCompiler $compiler,
        private readonly FinancialDocumentDataBuilder $builder,
        private readonly DocumentBusinessData $business,
        private readonly DocumentAssetRepository $assets,
        private readonly DocumentTemplateRenderer $renderer,
        private readonly DocumentPdfRenderer $pdf,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
        ?\Closure $isUploadedFile = null,
    ) {
        $this->isUploadedFile = $isUploadedFile ?? static fn(string $path): bool => is_uploaded_file($path);
    }

    /**
     * The design the current templates were compiled from. A save publishes only the templates it
     * changes, so each document's note is read from its own current version; the logo, typeface and
     * colour change all three together, so any of them holds those.
     */
    public function design(): FinancialDocumentDesign
    {
        $current = $this->templates->current();
        $notes = [];
        foreach (FinancialDocumentDesign::types() as $type) {
            $note = $current[$type->value]['design']['notes'][$type->value] ?? null;
            if (is_string($note)) {
                $notes[$type->value] = $note;
            }
        }
        return FinancialDocumentDesign::fromArray(['notes' => $notes] + (array) ($current[DocumentType::Invoice->value]['design'] ?? []));
    }

    /**
     * When the design was last saved and by whom, and the version each document is drawn in now.
     *
     * @return array{updated_at:string,updated_by:?string,versions:array<string,int>}
     */
    public function summary(): array
    {
        $current = $this->templates->current();
        $latest = null;
        foreach ($current as $row) {
            if ($latest === null || strcmp((string) $row['updated_at'], (string) $latest['updated_at']) > 0) {
                $latest = $row;
            }
        }
        return [
            'updated_at' => (string) $latest['updated_at'],
            'updated_by' => $latest['updated_by_name'] === null ? null : (string) $latest['updated_by_name'],
            'versions' => array_map(static fn(array $row): int => (int) $row['version_number'], $current),
        ];
    }

    /**
     * The design the form holds, with a newly uploaded logo stored.
     *
     * @param array<string,mixed> $post
     * @param array<string,mixed> $files
     * @return array{design:FinancialDocumentDesign,errors:list<string>}
     */
    public function fromForm(array $post, array $files, ?int $actorId): array
    {
        $errors = [];
        $logo = null;
        try {
            $logo = $this->upload($files['logo'] ?? null, $actorId);
        } catch (InvalidArgumentException $refused) {
            $errors[] = $refused->getMessage();
        }
        if ($logo === null && !isset($post['remove_logo'])) {
            $logo = $this->stored((string) ($post['logo_asset'] ?? ''));
        }
        $notes = [];
        foreach (FinancialDocumentDesign::types() as $type) {
            $notes[$type->value] = trim(str_replace(["\r\n", "\r"], "\n", (string) ($post['note_' . $type->value] ?? '')));
        }
        $design = new FinancialDocumentDesign($logo, (string) ($post['typeface'] ?? 'dejavu'), strtoupper(trim((string) ($post['colour'] ?? FinancialDocumentDesign::STANDARD_COLOUR))), $notes);
        return ['design' => $design, 'errors' => $errors];
    }

    /**
     * Everything that stops the design being saved: its own problems, then anything a document it
     * draws for a sample order would fail on.
     *
     * @return list<string>
     */
    public function check(FinancialDocumentDesign $design): array
    {
        $problems = $design->problems();
        if ($problems !== []) {
            return $problems;
        }
        $errors = [];
        foreach (array_keys(FinancialDocumentSamples::SAMPLES) as $sample) {
            foreach (FinancialDocumentSamples::documents($sample) as $type) {
                try {
                    $this->draw($design, $type, $sample);
                } catch (TemplateValidationException | DocumentDataException $invalid) {
                    $errors[] = 'The ' . strtolower($type->label()) . ' cannot be drawn: ' . $invalid->getMessage();
                }
            }
        }
        return array_values(array_unique($errors));
    }

    /**
     * Saves the form: a new version of each template it changes.
     *
     * @param array<string,mixed> $post
     * @param array<string,mixed> $files
     * @return array{errors:list<string>,design:FinancialDocumentDesign,changed:list<string>}
     */
    public function save(array $post, array $files, int $actorId): array
    {
        $form = $this->fromForm($post, $files, $actorId);
        $errors = [...$form['errors'], ...$this->check($form['design'])];
        if ($errors !== []) {
            return ['errors' => array_values(array_unique($errors)), 'design' => $form['design'], 'changed' => []];
        }
        $changed = $this->transactions->run(function () use ($form, $actorId): array {
            $current = $this->templates->current(true);
            $versions = [];
            foreach (FinancialDocumentDesign::types() as $type) {
                $row = $current[$type->value];
                $compiled = $this->compiler->compile($form['design'], $type);
                // The HTML and CSS hold everything the design sets, so unchanged ones draw the same document.
                if ($compiled['html'] === (string) $row['html'] && $compiled['css'] === (string) $row['css']) {
                    continue;
                }
                $versions[$type->value] = $this->templates->publish((int) $row['id'], $type, $form['design']->toArray(), $compiled['html'], $compiled['css'], $compiled['settings'], $actorId);
            }
            if ($versions !== []) {
                $this->audit->record($actorId, 'commerce.document_design_updated', ['versions' => $versions]);
            }
            return array_keys($versions);
        });
        return ['errors' => [], 'design' => $form['design'], 'changed' => $changed];
    }

    /** A document of the design for a sample order, as a PDF. */
    public function previewPdf(FinancialDocumentDesign $design, DocumentType $type, string $sample): string
    {
        return $this->pdf->render($this->draw($design, $type, $sample));
    }

    /** @return array{bytes:string,mime:string}|null a small picture of a stored logo for the form */
    public function thumbnail(string $sha, int $width = 320): ?array
    {
        $asset = $this->assets->find($sha);
        if ($asset === null || !ImageProcessing::available()) {
            return null;
        }
        $source = @imagecreatefromstring($asset['bytes']);
        if ($source === false) {
            return null;
        }
        $height = max(1, (int) round($width * imagesy($source) / max(1, imagesx($source))));
        $target = imagecreatetruecolor($width, $height);
        imagefill($target, 0, 0, (int) imagecolorallocate($target, 255, 255, 255));
        imagecopyresampled($target, $source, 0, 0, 0, 0, $width, $height, imagesx($source), imagesy($source));
        ob_start();
        imagepng($target, null, 6);
        return ['bytes' => (string) ob_get_clean(), 'mime' => 'image/png'];
    }

    /**
     * The sample's document drawn in the design, with this platform's business and bank details.
     *
     * @throws InvalidArgumentException when the sample has no such document
     * @throws TemplateValidationException when the compiled template is not valid
     * @throws DocumentDataException when the values do not fit the document's placeholders
     */
    private function draw(FinancialDocumentDesign $design, DocumentType $type, string $sample): RenderedDocument
    {
        $compiled = $this->compiler->compile($design, $type);
        $example = FinancialDocumentSamples::for($sample, $type);
        $data = FinancialDocumentDataBuilder::assemble($type, $example['order'], $example['snapshot'], $example['number'], $example['issued_at'],
            $example['context'], $this->business->values(), $this->builder->bank());
        return $this->renderer->renderSource($type, $compiled['html'], $compiled['css'], $compiled['settings'], $data);
    }

    private function upload(mixed $file, ?int $actorId): ?CertificateImage
    {
        if (!is_array($file) || (int) ($file['error'] ?? UPLOAD_ERR_NO_FILE) === UPLOAD_ERR_NO_FILE) {
            return null;
        }
        if ((int) ($file['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_OK || !($this->isUploadedFile)((string) ($file['tmp_name'] ?? ''))) {
            throw new InvalidArgumentException('The logo could not be uploaded. Try again with a file of at most 12 MB.');
        }
        $prepared = CertificateImage::prepare((string) file_get_contents((string) $file['tmp_name']), CertificateImage::LOGO);
        $sha = $this->assets->store($prepared['bytes'], $prepared['mime'], $prepared['width'], $prepared['height'], $actorId);
        return new CertificateImage($sha, $prepared['width'], $prepared['height']);
    }

    private function stored(string $sha): ?CertificateImage
    {
        if (preg_match('/^[0-9a-f]{64}$/D', $sha) !== 1) {
            return null;
        }
        $asset = $this->assets->find($sha);
        return $asset === null ? null : new CertificateImage($asset['sha256'], $asset['width'], $asset['height']);
    }
}
