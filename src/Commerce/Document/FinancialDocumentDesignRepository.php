declare(strict_types=1);

namespace CattoLearning\Commerce\Document;

use CattoLearning\Document\DocumentType;
use CattoLearning\Document\PageSettings;
use CattoLearning\Infrastructure\Persistence\Database;
use RuntimeException;

final class FinancialDocumentDesignRepository
{
    public function __construct(private readonly Database $db) {}

    /**
     * The current template of each financial document, with its latest version.
     *
     * @return array<string,array<string,mixed>> document type value => row
     */
    public function current(bool $lock = false): array
    {
        $rows = $this->db->fetchAllAssociative(
            "SELECT t.id, t.document_type, t.name, t.updated_at, t.published_version_id, v.version_number, v.html, v.css, v.design,
                    COALESCE(NULLIF(trim(concat_ws(' ', u.first_name, u.last_name)), ''), u.display_name) AS updated_by_name
               FROM document_templates t
               JOIN document_template_versions v ON v.id = t.published_version_id
               LEFT JOIN users u ON u.id = t.updated_by_user_id
              WHERE t.is_current AND t.document_type IN ('invoice', 'receipt', 'credit_note')
              ORDER BY t.id" . ($lock ? ' FOR UPDATE OF t' : '')
        );
        $current = [];
        foreach ($rows as $row) {
            $design = is_string($row['design'] ?? null) ? json_decode($row['design'], true) : null;
            $row['design'] = is_array($design) ? $design : null;
            $current[(string) $row['document_type']] = $row;
        }
        foreach (FinancialDocumentDesign::types() as $type) {
            if (!isset($current[$type->value])) {
                throw new RuntimeException('No current ' . strtolower($type->label()) . ' template is installed.');
            }
        }
        return $current;
    }

    /**
     * A new published version of a financial template, which documents issued from now on are drawn in.
     *
     * @param array<string,mixed> $design
     * @return int the new version's number
     */
    public function publish(int $templateId, DocumentType $type, array $design, string $html, string $css, PageSettings $settings, int $actorId): int
    {
        $number = (int) $this->db->fetchOne('SELECT COALESCE(MAX(version_number), 0) + 1 FROM document_template_versions WHERE template_id = :id', ['id' => $templateId]);
        $versionId = (int) $this->db->fetchOne(
            "INSERT INTO document_template_versions (template_id, version_number, state, html, css, design, page_size, page_orientation,
                    margin_top_mm, margin_right_mm, margin_bottom_mm, margin_left_mm, change_note, created_by_user_id, updated_by_user_id, published_at, published_by_user_id)
             VALUES (:template, :number, 'published', :html, :css, CAST(:design AS JSONB), :page_size, :page_orientation,
                    :margin_top_mm, :margin_right_mm, :margin_bottom_mm, :margin_left_mm, 'Financial document design saved.', :actor, :actor, NOW(), :actor) RETURNING id",
            ['template' => $templateId, 'number' => $number, 'html' => $html, 'css' => $css, 'actor' => $actorId,
                'design' => json_encode($design, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE)] + $settings->toArray()
        );
        $updated = $this->db->executeStatement(
            "UPDATE document_templates SET published_version_id = :version, updated_at = NOW(), updated_by_user_id = :actor
              WHERE id = :id AND document_type = :type AND is_current",
            ['id' => $templateId, 'type' => $type->value, 'version' => $versionId, 'actor' => $actorId]
        );
        if ($updated !== 1) {
            throw new RuntimeException('The ' . strtolower($type->label()) . ' template is not the current one.');
        }
        return $number;
    }
}
