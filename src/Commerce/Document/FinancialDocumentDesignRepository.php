The invoice, receipt and credit note templates in the database, as the financial document design
sees them: the current template of each kind and its latest published version, which holds the
design it was compiled from (document_template_versions.design). Saving the design publishes a new
version of a template whose HTML or CSS it changes; earlier versions stay, because issued documents
name them. None of this versioning is shown on the design page.

