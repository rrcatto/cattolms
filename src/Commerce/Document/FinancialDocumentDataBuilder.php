/*
Generated by: Claude Code CLI

Date time: 2026/10/08 SAST

Version: 0.8.9

Description:
Builds the values an invoice, a receipt or a credit note prints - the document engine's registered
placeholders for its type - from the commerce record it is issued from. It runs once, when the
document is issued, and the result is stored with the document (commerce_documents.document_data),
so the document is drawn from it ever after.

Everything about the sale comes from the immutable snapshots, never from current data:
- the customer: the order's billing snapshot (Phase F), its purchaser and, for a company order, the
  company it was placed for;
- the lines: each course, bundle (with the courses it included when it was sold, Phase H) or
  company credit line as placed, with its price, its share of the promotion and what was paid;
- the promotion: its code and label as frozen into the order (Phase G);
- a receipt's payment: the amount the payment actually received, how and with what reference, and
  when (an EFT's bank date when ADMIN recorded one);
- a credit note's refund: the refunded line as it was paid, the amount credited, the basis and the
  reason, and the invoice it credits.
The business details (business.*) and, on an invoice with something to pay, the EFT bank details
(bank.*) are the platform's settings at the moment of issue, copied in with the rest.

Optional values that do not apply are absent, so a template's {{#if}} leaves their rows out: an order
without a promotion prints no promotion and no discount. A zero total is a real amount.

assemble() is the pure part, given the business and bank details; the samples on the design page
are built by it too, so a preview is drawn exactly as an issued document is.

Changelog:
2026/10/08 SAST
- Created for financial documents on the document template engine (Phase K).
*/

declare(strict_types=1);

namespace CattoLearning\Commerce\Document;

use CattoLearning\Commerce\Domain\BillingDetails;
use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Document\DocumentBusinessData;
use CattoLearning\Document\DocumentType;
use CattoLearning\Support\Money;
use DateTimeImmutable;
use DateTimeZone;
use InvalidArgumentException;

final class FinancialDocumentDataBuilder
{
    public const BASES = ['statutory' => 'Statutory right', 'service_failure' => 'Service failure', 'goodwill' => 'Goodwill', 'voluntary' => 'Voluntary'];
    private const PAYMENT_METHODS = ['dummy' => 'Card (simulated)', 'manual_bank' => 'EFT / bank transfer'];

    public function __construct(
        private readonly DocumentBusinessData $business,
        private readonly RuntimeSettings $settings,
    ) {}

    /**
     * The values of a document being issued now, with the business and bank details as they are now.
     *
     * @param array<string,mixed> $order the commerce_orders row (id, placed_at, payment_due_at)
     * @param array<string,mixed> $snapshot the commerce record the document is issued from
     * @param array<string,mixed> $context a receipt's payment, a credit note's invoice number
     * @return array<string,mixed>
     */
    public function forIssue(DocumentType $type, array $order, array $snapshot, string $number, string $issuedAt, array $context = []): array
    {
        return self::assemble($type, $order, $snapshot, $number, $issuedAt, $context, $this->business->values(), $this->bank());
    }

    /**
     * The EFT details from Settings, when all of them have been entered.
     *
     * @return array<string,string>
     */
    public function bank(): array
    {
        $bank = $this->settings->bankDetails();
        if (!$bank['configured']) {
            return [];
        }
        return ['bank.name' => (string) $bank['bank_name'], 'bank.account_name' => (string) $bank['account_name'],
            'bank.account_number' => (string) $bank['account_number'], 'bank.branch_code' => (string) $bank['branch_code']];
    }

    /**
     * @param array<string,mixed> $order
     * @param array<string,mixed> $snapshot
     * @param array<string,mixed> $context payment: {amount_minor, currency, gateway, reference, received_at}; invoice_number
     * @param array<string,mixed> $business the business.* values
     * @param array<string,string> $bank the bank.* values, or none
     * @return array<string,mixed>
     */
    public static function assemble(DocumentType $type, array $order, array $snapshot, string $number, string $issuedAt, array $context, array $business, array $bank): array
    {
        $currency = (string) ($snapshot['currency'] ?? '');
        $money = static fn(int $minor): array => ['minor' => $minor, 'currency' => $currency];
        $optionalMoney = static fn(int $minor): ?array => $minor > 0 ? $money($minor) : null;
        $promotion = is_array($snapshot['promotion'] ?? null) ? $snapshot['promotion'] : null;
        $data = $business + self::customer($snapshot) + [
            'order.number' => self::orderNumber((int) $order['id']),
            'order.date' => self::date((string) $order['placed_at']),
        ];
        switch ($type) {
            case DocumentType::Invoice:
                $total = (int) $snapshot['total_minor'];
                $discount = (int) ($snapshot['discount_minor'] ?? 0);
                $data += [
                    'invoice.number' => $number,
                    'invoice.date' => self::date($issuedAt),
                    'invoice.due_date' => $total > 0 ? self::date((string) $order['payment_due_at']) : null,
                    'invoice.subtotal' => $money((int) ($snapshot['subtotal_minor'] ?? self::linesTotal($snapshot))),
                    'invoice.discount' => $optionalMoney($discount),
                    'invoice.total' => $money($total),
                    'invoice.currency' => $currency,
                ] + self::promotion($promotion) + ($total > 0 ? $bank : []);
                $data['items'] = self::lines($snapshot, $money);
                return $data;
            case DocumentType::Receipt:
                $payment = (array) ($context['payment'] ?? []);
                if (!isset($payment['amount_minor'])) {
                    throw new InvalidArgumentException('A receipt needs the payment it records.');
                }
                $discount = (int) ($snapshot['discount_minor'] ?? 0);
                $data += [
                    'receipt.number' => $number,
                    'receipt.date' => self::date((string) ($payment['received_at'] ?? $issuedAt)),
                    'receipt.subtotal' => $discount > 0 ? $money((int) ($snapshot['subtotal_minor'] ?? self::linesTotal($snapshot))) : null,
                    'receipt.discount' => $optionalMoney($discount),
                    'receipt.amount' => ['minor' => (int) $payment['amount_minor'], 'currency' => (string) ($payment['currency'] ?? $currency)],
                    'receipt.currency' => (string) ($payment['currency'] ?? $currency),
                    'receipt.payment_method' => self::PAYMENT_METHODS[(string) ($payment['gateway'] ?? '')] ?? null,
                    'receipt.payment_reference' => self::text($payment['reference'] ?? null),
                ] + self::promotion($promotion);
                $data['items'] = self::lines($snapshot, $money);
                return $data;
            case DocumentType::CreditNote:
                $data += [
                    'credit_note.number' => $number,
                    'credit_note.date' => self::date($issuedAt),
                    'credit_note.amount' => $money((int) $snapshot['total_minor']),
                    'credit_note.currency' => $currency,
                    'credit_note.basis' => self::BASES[(string) ($snapshot['refund_basis'] ?? '')] ?? (string) ($snapshot['refund_basis'] ?? ''),
                    'credit_note.reason' => self::text($snapshot['refund_reason'] ?? null),
                    'credit_note.invoice_number' => self::text($context['invoice_number'] ?? null),
                ];
                $data['items'] = self::creditedLines($snapshot, $money);
                return $data;
            default:
                throw new InvalidArgumentException('A ' . strtolower($type->label()) . ' is not a financial document.');
        }
    }

    public static function orderNumber(int $orderId): string
    {
        return 'CL-' . str_pad((string) $orderId, 8, '0', STR_PAD_LEFT);
    }

    /**
     * @param array<string,mixed> $snapshot
     * @return array<string,mixed>
     */
    private static function customer(array $snapshot): array
    {
        $billing = BillingDetails::fromSnapshot((array) ($snapshot['billing'] ?? []));
        return [
            'customer.billing_name' => $billing->name,
            'customer.organisation' => $billing->organisationName,
            'customer.tax_number' => $billing->taxRegistrationNumber,
            'customer.billing_address' => $billing->addressLines(),
            'customer.company_name' => self::text($snapshot['company_name'] ?? null),
            'customer.purchaser_name' => self::text($snapshot['purchaser_name'] ?? null),
            'customer.email' => self::text($snapshot['purchaser_email'] ?? null),
        ];
    }

    /**
     * @param array<string,mixed>|null $promotion the promotion as frozen into the order
     * @return array<string,?string>
     */
    private static function promotion(?array $promotion): array
    {
        return $promotion === null ? [] : ['promotion.code' => self::text($promotion['code'] ?? null), 'promotion.label' => self::text($promotion['label'] ?? null)];
    }

    /**
     * The order's lines as placed.
     *
     * @param array<string,mixed> $snapshot
     * @param \Closure(int):array{minor:int,currency:string} $money
     * @return list<array<string,mixed>>
     */
    private static function lines(array $snapshot, \Closure $money): array
    {
        $lines = [];
        foreach ((array) ($snapshot['items'] ?? []) as $item) {
            $item = (array) $item;
            $price = (int) $item['line_total_minor'];
            $discount = (int) ($item['discount_minor'] ?? 0);
            $quantity = max(1, (int) ($item['quantity'] ?? 1));
            [$description, $detail] = self::describe($item);
            if (self::isCompanyCredit($item, $snapshot)) {
                $detail = self::credits($quantity, intdiv($price, $quantity), (string) $snapshot['currency']);
            }
            $lines[] = [
                'description' => $description,
                'detail' => $detail,
                'quantity' => $quantity,
                'access_period' => self::period((int) $item['access_period_seconds']),
                'price' => $money($price),
                'discount' => $discount > 0 ? $money($discount) : null,
                'paid' => $money((int) ($item['paid_minor'] ?? $price - $discount)),
            ];
        }
        return $lines;
    }

    /**
     * A credit note's line: the refunded order line as it was paid, and what this refund credits.
     * A company credit line is credited by the unit, so it shows the refunded units at the price
     * each was bought for.
     *
     * @param array<string,mixed> $snapshot
     * @param \Closure(int):array{minor:int,currency:string} $money
     * @return list<array<string,mixed>>
     */
    private static function creditedLines(array $snapshot, \Closure $money): array
    {
        $paidLine = (array) ($snapshot['refund_line'] ?? []);
        $lines = [];
        foreach ((array) ($snapshot['items'] ?? []) as $item) {
            $item = (array) $item;
            $credited = (int) $item['line_total_minor'];
            $quantity = max(1, (int) ($item['quantity'] ?? 1));
            [$description, $detail] = self::describe($item);
            if (self::isCompanyCredit($item, $snapshot)) {
                $bought = max(1, (int) ($paidLine['quantity'] ?? $quantity));
                $unit = intdiv((int) ($paidLine['price_minor'] ?? $credited), $bought);
                $price = $unit * $quantity;
                [$discount, $paid] = [0, $price];
                $detail = $quantity . ' of ' . $bought . ' ' . ($bought === 1 ? 'credit' : 'credits') . ' refunded, at ' . Money::strictMinorUnits($unit, (string) $snapshot['currency'])->format() . ' each';
            } else {
                $price = (int) ($paidLine['price_minor'] ?? $credited);
                $discount = (int) ($paidLine['discount_minor'] ?? 0);
                $paid = (int) ($paidLine['paid_minor'] ?? $price - $discount);
                if ($discount > 0 && self::text($paidLine['promotion_code'] ?? null) !== null) {
                    $detail = implode(' · ', array_filter([$detail, 'Discount from promotion ' . $paidLine['promotion_code']]));
                }
            }
            $lines[] = [
                'description' => $description,
                'detail' => $detail,
                'quantity' => $quantity,
                'access_period' => self::period((int) $item['access_period_seconds']),
                'price' => $money($price),
                'discount' => $discount > 0 ? $money($discount) : null,
                'paid' => $money($paid),
                'credited' => $money($credited),
            ];
        }
        return $lines;
    }

    /**
     * What a line is called: the course, or the bundle with the courses it included when it was sold.
     *
     * @param array<string,mixed> $item
     * @return array{0:string,1:?string}
     */
    private static function describe(array $item): array
    {
        if (($item['fulfilment_type'] ?? '') === 'bundle') {
            $courses = array_map(static fn(mixed $course): string => (string) ((array) $course)['title'], (array) ($item['courses'] ?? []));
            return ['Bundle: ' . $item['bundle_title'], $courses === [] ? null : 'Includes: ' . implode(', ', $courses)];
        }
        return [(string) $item['course_title'], null];
    }

    /**
     * @param array<string,mixed> $item
     * @param array<string,mixed> $snapshot
     */
    private static function isCompanyCredit(array $item, array $snapshot): bool
    {
        return isset($snapshot['company_id']) && ($item['fulfilment_type'] ?? 'company_credit') === 'company_credit';
    }

    private static function credits(int $quantity, int $unitMinor, string $currency): string
    {
        return $quantity . ' company ' . ($quantity === 1 ? 'credit' : 'credits') . ' at ' . Money::strictMinorUnits($unitMinor, $currency)->format() . ' each';
    }

    /** @param array<string,mixed> $snapshot */
    private static function linesTotal(array $snapshot): int
    {
        return array_sum(array_map(static fn(mixed $item): int => (int) ((array) $item)['line_total_minor'], (array) ($snapshot['items'] ?? [])));
    }

    private static function period(int $seconds): string
    {
        $days = (int) round($seconds / 86400);
        return $days === 1 ? '1 day' : $days . ' days';
    }

    /** A moment as the date it fell on here. */
    private static function date(string $moment): string
    {
        return (new DateTimeImmutable($moment))->setTimezone(new DateTimeZone(date_default_timezone_get()))->format('Y-m-d');
    }

    private static function text(mixed $value): ?string
    {
        return is_string($value) && trim($value) !== '' ? $value : null;
    }
}
