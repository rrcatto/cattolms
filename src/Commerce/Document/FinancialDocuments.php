/*
Generated by: Claude Code CLI

Date time: 2026/10/08 SAST

Version: 0.8.9

Description:
The one way invoices, receipts and credit notes are issued and drawn.

issue() runs inside the transaction that places an order, confirms a payment or approves a refund,
at the moment it always has: an invoice when an order is placed, a receipt when a payment is
confirmed, a credit note when a refund is approved. It takes the document's number, builds every
value the document prints from the commerce record (FinancialDocumentDataBuilder), draws it with the
current template of its kind - which checks the values against the placeholder registry - and stores
the values with the exact template version that drew them. A source (order:, payment:, refund:)
issues one document however often it is replayed.

render() and pdf() draw an issued document again from its stored values and its own template
version only, through the same DocumentTemplateRenderer and DocumentPdfRenderer as every preview, so
a later design, billing profile, course, bundle or promotion never changes it. The PDF is made the
first time it is asked for - to view, to download or to attach to an email - and kept
(commerce_document_files), so every later copy is the same file.

Changelog:
2026/10/08 SAST
- Created for financial documents on the document template engine (Phase K), replacing
  InvoicePdfRenderer's hard-coded HTML.
*/

declare(strict_types=1);

namespace CattoLearning\Commerce\Document;

use CattoLearning\Commerce\Infrastructure\CommerceRepository;
use CattoLearning\Document\DocumentPdfRenderer;
use CattoLearning\Document\DocumentTemplateRenderer;
use CattoLearning\Document\DocumentType;
use CattoLearning\Document\RenderedDocument;
use RuntimeException;

final class FinancialDocuments
{
    public function __construct(
        private readonly CommerceRepository $records,
        private readonly FinancialDocumentDataBuilder $builder,
        private readonly DocumentTemplateRenderer $renderer,
        private readonly DocumentPdfRenderer $pdf,
    ) {}

    /**
     * The invoice of an order just placed.
     *
     * @param array<string,mixed> $snapshot the order as placed
     */
    public function issueInvoice(int $orderId, array $snapshot, string $issuedAt, ?int $actorId = null): void
    {
        $this->issue($orderId, DocumentType::Invoice, 'order:' . $orderId, $snapshot, $issuedAt, [], $actorId);
    }

    /**
     * The receipt of a confirmed payment, for the amount the payment received.
     *
     * @param array<string,mixed> $orderSnapshot
     * @param array<string,mixed> $payment the commerce_payments row, now paid
     */
    public function issueReceipt(int $orderId, array $orderSnapshot, array $payment, string $gateway, ?string $reference, string $issuedAt): void
    {
        $evidence = $this->records->manualEvidence((string) $payment['id']);
        $snapshot = $orderSnapshot + ['payment_id' => (string) $payment['id'], 'gateway' => $gateway, 'provider_reference' => $reference];
        $this->issue($orderId, DocumentType::Receipt, 'payment:' . $payment['id'], $snapshot, $issuedAt, ['payment' => [
            'amount_minor' => (int) $payment['amount_minor'],
            'currency' => (string) $payment['currency'],
            'gateway' => $gateway,
            'reference' => $reference,
            // An EFT was received on the day the bank says, which ADMIN recorded; a card payment when it was confirmed.
            'received_at' => $evidence === null ? $issuedAt : (string) $evidence['received_at'],
        ]]);
    }

    /**
     * The credit note of one approved refund: this refund alone, never the order's refunds so far.
     *
     * @param array<string,mixed> $snapshot the refund as CreditNote data: the refunded line, amount, basis and reason
     */
    public function issueCreditNote(int $orderId, int $refundId, array $snapshot, string $issuedAt, int $actorId): void
    {
        $invoice = null;
        foreach ($this->records->documents($orderId) as $document) {
            if ($document['kind'] === 'invoice') {
                $invoice = (string) $document['number'];
            }
        }
        $this->issue($orderId, DocumentType::CreditNote, 'refund:' . $refundId, $snapshot, $issuedAt, ['invoice_number' => $invoice], $actorId);
    }

    /** @param array<string,mixed> $document an issued commerce_documents row */
    public function render(array $document): RenderedDocument
    {
        return $this->renderer->renderVersion((int) $document['template_version_id'], self::data($document));
    }

    /** @param array<string,mixed> $document an issued commerce_documents row */
    public function pdf(array $document): string
    {
        $id = (int) $document['id'];
        return $this->records->pdf($id) ?? $this->records->savePdf($id, $this->pdf->render($this->render($document)));
    }

    /**
     * @param array<string,mixed> $snapshot
     * @param array<string,mixed> $context
     */
    private function issue(int $orderId, DocumentType $type, string $sourceKey, array $snapshot, string $issuedAt, array $context, ?int $actorId = null): void
    {
        if ($this->records->documentForSource($sourceKey) !== null) {
            return;
        }
        $order = $this->records->order($orderId);
        $number = $this->records->nextDocumentNumber($type->value);
        $data = $this->builder->forIssue($type, $order, $snapshot, $number, $issuedAt, $context);
        // Drawing it now checks every value against the registry and names the version that drew it.
        $reference = $this->renderer->renderCurrent($type, $data)->reference();
        if ($reference['template_version_id'] === null) {
            throw new RuntimeException('The ' . strtolower($type->label()) . ' template has no published version.');
        }
        $id = $this->records->insertDocument($orderId, $type->value, $number, $sourceKey, $snapshot, $data, $reference, $issuedAt);
        $this->records->audit($orderId, $actorId, 'document.issued', ['document_id' => $id, 'kind' => $type->value, 'number' => $number,
            'template_id' => $reference['template_id'], 'template_version_id' => $reference['template_version_id'], 'template_version_number' => $reference['template_version_number']], $issuedAt);
    }

    /**
     * @param array<string,mixed> $document
     * @return array<string,mixed>
     */
    private static function data(array $document): array
    {
        $data = $document['document_data'] ?? null;
        return is_array($data) ? $data : CommerceRepository::decode((string) $data);
    }
}
