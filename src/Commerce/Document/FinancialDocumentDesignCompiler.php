/*
Generated by: Claude Code CLI

Date time: 2026/10/08 SAST

Version: 0.8.9

Description:
Turns the financial document design into the template HTML and CSS of an invoice, a receipt or a
credit note, so all three are drawn by the document engine's one renderer and PDF engine and every
saved version is as immutable as any template version.

The documents' structure is in resources/documents: invoice.html, receipt.html and credit_note.html,
written in the engine's controlled language, and financial.css, shared by all three. Each has slots
the design fills, and nothing else: [[logo]] and [[note]] in the HTML, [[font]] and [[accent]] in the
CSS. A slot never reaches the engine; the result is validated like any template.

Pure: no database. The logo is addressed by the SHA-256 it is stored under in document_assets, which
the renderer embeds.

Changelog:
2026/10/08 SAST
- Created for financial documents on the document template engine (Phase K).
*/

declare(strict_types=1);

namespace CattoLearning\Commerce\Document;

use CattoLearning\Document\DocumentType;
use CattoLearning\Document\PageSettings;
use InvalidArgumentException;
use RuntimeException;

final class FinancialDocumentDesignCompiler
{
    /** The logo's largest printed size, in millimetres. */
    private const LOGO_HEIGHT = 16.0;
    private const LOGO_WIDTH = 60.0;

    /** @return array{html:string,css:string,settings:PageSettings} */
    public function compile(FinancialDocumentDesign $design, DocumentType $type): array
    {
        if (!in_array($type, FinancialDocumentDesign::types(), true)) {
            throw new InvalidArgumentException('A ' . strtolower($type->label()) . ' is not a financial document.');
        }
        $html = self::fill(self::source($type->value . '.html'), [
            '[[logo]]' => $design->logo === null ? '' : self::logo($design),
            '[[note]]' => self::note($design->note($type)),
        ]);
        $css = self::fill(self::source('financial.css'), [
            '[[font]]' => $design->fontStack(),
            '[[accent]]' => $design->colour,
        ]);
        return ['html' => $html, 'css' => $css, 'settings' => $type->defaultSettings()];
    }

    private static function logo(FinancialDocumentDesign $design): string
    {
        $logo = $design->logo ?? throw new InvalidArgumentException('The design has no logo.');
        $height = self::LOGO_HEIGHT;
        $width = $height * $logo->width / $logo->height;
        if ($width > self::LOGO_WIDTH) {
            [$width, $height] = [self::LOGO_WIDTH, self::LOGO_WIDTH * $logo->height / $logo->width];
        }
        return sprintf('<p class="logo"><img src="asset:%s" alt="" style="width:%.1fmm;height:%.1fmm"></p>', $logo->sha, floor($width * 10) / 10, floor($height * 10) / 10);
    }

    /** The note as typed: plain text, its line breaks kept; nothing in it is markup or a placeholder. */
    private static function note(string $note): string
    {
        $note = trim(str_replace(["\r\n", "\r"], "\n", $note));
        if ($note === '') {
            return '';
        }
        $text = str_replace(['{', '}'], ['&#123;', '&#125;'], htmlspecialchars($note, ENT_QUOTES | ENT_HTML5));
        return '<p class="note">' . str_replace("\n", '<br>', $text) . '</p>';
    }

    /** @param array<string,string> $slots */
    private static function fill(string $source, array $slots): string
    {
        foreach ($slots as $slot => $value) {
            if (!str_contains($source, $slot)) {
                throw new RuntimeException('The financial document source has no ' . $slot . ' slot.');
            }
            $source = str_replace($slot, $value, $source);
        }
        return $source;
    }

    private static function source(string $file): string
    {
        $source = @file_get_contents(dirname(__DIR__, 3) . '/resources/documents/' . $file);
        if ($source === false) {
            throw new RuntimeException('The financial document source resources/documents/' . $file . ' is missing.');
        }
        return $source;
    }
}
