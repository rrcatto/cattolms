        $row = $this->db->fetchAssociative('SELECT o.company_id, o.purchaser_user_id, u.display_name, u.account_reference AS user_reference, c.name AS company_name, c.account_reference AS company_reference
            FROM commerce_orders o JOIN users u ON u.id = o.purchaser_user_id LEFT JOIN companies c ON c.id = o.company_id WHERE o.id = :id', ['id' => $orderId]);
        if ($row === false) return null;

        return $row['company_id'] !== null
            ? ['kind' => 'company', 'id' => (int) $row['company_id'], 'name' => (string) $row['company_name'], 'reference' => (string) $row['company_reference']]
            : ['kind' => 'person', 'id' => (int) $row['purchaser_user_id'], 'name' => (string) $row['display_name'], 'reference' => (string) $row['user_reference']];
    }

    /**
     * An account's orders paid by EFT that can still take a payment: those waiting for it, then those
     * cancelled for not being paid in time, newest first within each.
     *
     * @return list<array<string,mixed>>
     */
    public function eftOrders(string $kind, int $accountId): array
    {
        $owner = $kind === 'company' ? 'o.company_id = :id' : 'o.company_id IS NULL AND o.purchaser_user_id = :id';

        return $this->db->fetchAllAssociative("SELECT o.id, o.state, o.total_minor, o.currency, o.placed_at, o.payment_due_at,
                (SELECT COALESCE(SUM(p.amount_minor), 0) FROM commerce_payments p WHERE p.order_id = o.id AND p.state IN ('paid','partially_refunded','refunded')) AS paid_minor,
                (SELECT string_agg(COALESCE(i.snapshot->>'bundle_title', i.snapshot->>'course_title', ''), ', ' ORDER BY i.id) FROM commerce_order_items i WHERE i.order_id = o.id) AS bought
            FROM commerce_orders o JOIN commerce_order_preferences pref ON pref.order_id = o.id
            WHERE {$owner} AND pref.payment_method = 'eft' AND o.state IN ('awaiting_payment','cancelled')
            ORDER BY o.state = 'awaiting_payment' DESC, o.placed_at DESC LIMIT 50", ['id' => $accountId]);
    }

    /**
     * One order paid by EFT that can still take a payment, as eftOrders() lists it.
     *
     * @return array<string,mixed>|null
     */
    public function eftOrder(int $orderId): ?array
    {
        $account = $this->accountForOrder($orderId);
        if ($account === null) return null;
        foreach ($this->eftOrders($account['kind'], $account['id']) as $order) {
            if ((int) $order['id'] === $orderId) return $order;
        }

        return null;
    }

