    }

    /** @return array<string,mixed>|null */
    public function unmatched(int $id, bool $lock = false): ?array
    {
        if ($lock) $this->db->fetchOne('SELECT id FROM commerce_unmatched_payments WHERE id = :id FOR UPDATE', ['id' => $id]);

        return $this->db->fetchAssociative('SELECT ' . self::UNMATCHED_COLUMNS . ' ' . self::UNMATCHED_FROM . ' WHERE u.id = :id', ['id' => $id]) ?: null;
    }

    /**
     * Unmatched deposits: the open ones, oldest first, or every one, newest first.
     *
     * @return list<array<string,mixed>>
     */
    public function unmatchedList(bool $openOnly, int $limit = 200): array
    {
        $where = $openOnly ? "WHERE u.state = 'open' ORDER BY u.received_at, u.id" : 'ORDER BY u.received_at DESC, u.id DESC';

        return $this->db->fetchAllAssociative('SELECT ' . self::UNMATCHED_COLUMNS . ' ' . self::UNMATCHED_FROM . ' ' . $where . ' LIMIT ' . max(1, $limit));
    }

