declare(strict_types=1);

namespace CattoLearning\Commerce\Infrastructure\Payment;

use CattoLearning\Commerce\Domain\OrderNumber;
use CattoLearning\Commerce\Domain\PaymentResult;
use CattoLearning\Configuration\SiteMode;
use CattoLearning\Support\Money;
use CattoPHP\Installation\Installation;
use CattoPHP\Payments\PaymentGateways;
use DateTimeImmutable;
use Omnipay\Common\Exception\InvalidRequestException;
use Omnipay\Common\Message\NotificationInterface;
use Omnipay\StitchExpress\Gateway;
use RuntimeException;
use Throwable;

final class StitchPaymentGateway
{
    /** The gateway's name in payment records, the ledger and receipts. */
    public const ID = 'stitch';

    /** Its name in CattoPHP's payments configuration. */
    public const GATEWAY = 'stitch';

    /** Where Stitch sends the customer back, and where it sends payment.paid. */
    public const RETURN_PATH = '/checkout/stitch/return';
    public const WEBHOOK_PATH = '/webhooks/stitch';

    /** Stitch's test client IDs start with this. */
    public const TEST_PREFIX = 'test-';

    public function __construct(
        private readonly PaymentGateways $gateways,
        private readonly SiteMode $site,
        private readonly Installation $installation,
    ) {
    }

    /** Why card payments cannot be taken now, in words for Settings, or null when they can. */
    public function problem(): ?string
    {
        $missing = $this->gateways->missing(self::GATEWAY);
        if ($missing !== []) {
            $labels = array_map(static fn (string $name): string => match ($name) { 'STITCH_CLIENT_ID' => 'client ID', 'STITCH_CLIENT_SECRET' => 'client secret', default => $name }, $missing);

            return 'Enter Stitch\'s ' . implode(' and ', $labels) . ' at Settings > Card payments (Stitch) first.';
        }
        if (!$this->site->isDemo() && $this->kind() === 'test') {
            return 'This live site has Stitch\'s test client ID (it starts with test-): a live site takes real payments only, with the live ID and secret.';
        }

        return null;
    }

    /** test for Stitch's test credentials, live for any other, '' without a client ID. */
    public function kind(): string
    {
        $id = (string) ($this->gateways->parameters(self::GATEWAY)['clientId'] ?? '');

        return $id === '' ? '' : (str_starts_with($id, self::TEST_PREFIX) ? 'test' : 'live');
    }

    /** Whether payment.paid deliveries can be checked: the webhook's signing secret is set. */
    public function hasWebhookSecret(): bool
    {
        return ($this->gateways->parameters(self::GATEWAY)['webhookSecret'] ?? '') !== '';
    }

    public function returnAddress(): string
    {
        return $this->installation->addressOf(self::RETURN_PATH);
    }

    public function webhookAddress(): string
    {
        return $this->installation->addressOf(self::WEBHOOK_PATH);
    }

    /**
     * A payment link for a card payment: the order number as Stitch's reference (it comes back on the return), the buyer
     * as the payer, card only, working until $expiresAt; the customer returns to the site's return address.
     *
     * @return array{reference:string,url:string,expires_at:?string}
     */
    public function start(int $orderId, Money $amount, string $payerName, string $payerEmail, DateTimeImmutable $expiresAt): array
    {
        $response = $this->gateway()->purchase([
            'amount' => $amount->toMajorUnits(),
            'currency' => $amount->currency,
            'transactionId' => OrderNumber::format($orderId),
            'payerName' => self::payerName($payerName, $payerEmail),
            'payerEmailAddress' => $payerEmail,
            'returnUrl' => $this->returnAddress(),
            'expiresAt' => $expiresAt,
            'allowedPaymentMethods' => ['CARD'],
        ])->send();
        $reference = $response->getTransactionReference();
        $url = $response->getRedirectUrl();
        if (!$response->isRedirect() || $reference === null || $url === null) {
            throw new RuntimeException('Stitch did not make a payment link: ' . ($response->getMessage() ?? 'no reason given') . '.');
        }

        return ['reference' => $reference, 'url' => $url, 'expires_at' => $response->getExpiresAt()];
    }

    /**
     * Where a card payment stands, as Stitch says, by its payment link: paid (with Stitch's payment id as the provider's
     * reference and the amount Stitch received), failed (the link was cancelled or expired) or pending. Null when Stitch
     * could not be asked; it is asked again later.
     *
     * @param array<string,mixed> $attempt the payment record
     */
    public function check(array $attempt): ?PaymentResult
    {
        $link = (string) ($attempt['checkout_reference'] ?? '');
        if ($link === '') {
            return null;
        }
        try {
            $response = $this->gateway()->fetchTransaction(['transactionReference' => $link])->send();
        } catch (Throwable) {
            return null;
        }
        if (!$response->answered()) {
            return null;
        }
        $currency = (string) $attempt['currency'];
        $amount = Money::strictMinorUnits($response->getAmountInteger() ?? (int) $attempt['amount_minor'], $currency);
        if ($response->isSuccessful()) {
            return new PaymentResult((string) $attempt['id'], 'paid', $amount, $response->getPaymentId(), null, 'Paid through Stitch.');
        }
        if ($response->isCancelled() || $response->isExpired()) {
            return new PaymentResult((string) $attempt['id'], 'failed', $amount, null, null, $response->isExpired() ? 'The payment link expired before it was paid.' : 'The payment link was cancelled.');
        }

        return new PaymentResult((string) $attempt['id'], 'pending', $amount, null, null, 'Waiting for the payment.');
    }

    /**
     * A payment.paid webhook, once its signature is checked: the payment link it paid, Stitch's payment id, the amount in
     * cents and the delivery's id (the same for each retry). Null for anything that is not a paid payment link.
     *
     * @return array{link:string,payment:string,amount:int,delivery:string}|null
     * @throws InvalidRequestException when the delivery is not genuine
     */
    public function notification(): ?array
    {
        $notification = $this->gateway()->acceptNotification();
        if ($notification->getTransactionStatus() !== NotificationInterface::STATUS_COMPLETED || $notification->getType() !== 'LINK') {
            return null;
        }
        $link = $notification->getTransactionReference();
        $payment = $notification->getPaymentId();
        $amount = $notification->getAmountInteger();
        if ($link === null || $payment === null || $amount === null) {
            return null;
        }

        return ['link' => $link, 'payment' => $payment, 'amount' => $amount, 'delivery' => $notification->getMessageId()];
    }

    /**
     * Refunds part or all of a Stitch payment to the card it came from (owner, 2026-11-11): processed (with Stitch's refund
     * id) or failed (with Stitch's words). Thrown when Stitch could not be asked: it may or may not have refunded, which
     * refundsOf() tells before anyone tries again.
     *
     * @return array{state:string,id:?string,message:string}
     */
    public function refund(string $paymentId, Money $amount): array
    {
        $response = $this->gateway()->refund(['paymentId' => $paymentId, 'amount' => $amount->toMajorUnits(), 'currency' => $amount->currency, 'reason' => 'REQUESTED_BY_USER'])->send();
        if ($response->isSuccessful()) {
            return ['state' => 'processed', 'id' => $response->getTransactionReference(), 'message' => 'Refunded through Stitch.'];
        }

        return ['state' => 'failed', 'id' => $response->getTransactionReference(), 'message' => $response->getMessage() ?? ($response->getStatus() === 'FAILED' ? 'Stitch did not process the refund.' : 'Stitch did not refund it.')];
    }

    /**
     * Every refund Stitch has made of a payment: its id, amount in cents, status (PROCESSED or FAILED) and when.
     *
     * @return list<array{id:string,amount:int,status:string,created:string}>
     */
    public function refundsOf(string $paymentId): array
    {
        $response = $this->gateway()->fetchPaymentRefunds(['paymentId' => $paymentId])->send();
        if (!$response->answered()) {
            throw new RuntimeException('Stitch did not list the payment\'s refunds: ' . ($response->getMessage() ?? 'no reason given') . '.');
        }
        $refunds = [];
        foreach ($response instanceof \Omnipay\StitchExpress\Message\ListResponse ? $response->getItems() : [] as $item) {
            $refunds[] = ['id' => (string) ($item['id'] ?? ''), 'amount' => (int) ($item['amount'] ?? 0), 'status' => (string) ($item['status'] ?? ''), 'created' => (string) ($item['createdAt'] ?? '')];
        }

        return $refunds;
    }

    /**
     * The account as Stitch's dashboard shows it: its balance in cents, and its bank account (holder, bank, account number),
     * or null for one Stitch has not verified yet (it answers 404 until then).
     *
     * @return array{balance:?int,bank:?array{name:string,bank:string,number:string}}
     */
    public function account(): array
    {
        $gateway = $this->gateway();
        $balance = $gateway->fetchBalance()->send();
        $bank = $gateway->fetchBankDetails()->send();
        if (!$balance->answered()) {
            throw new RuntimeException('Stitch did not give the balance: ' . ($balance->getMessage() ?? 'no reason given') . '.');
        }

        return [
            'balance' => $balance->getBalance(),
            'bank' => $bank->answered() && $bank->getAccountNumber() !== null
                ? ['name' => (string) $bank->getAccountName(), 'bank' => (string) $bank->getBankId(), 'number' => (string) $bank->getAccountNumber()]
                : null,
        ];
    }

    /**
     * One page of the account's payment links, payments, refunds or fees since $from, newest first, as Stitch gives them,
     * with the cursor of the next page.
     *
     * @return array{items:list<array<string,mixed>>,next:?string}
     */
    public function page(string $list, DateTimeImmutable $from, string $cursor = '', int $limit = 50): array
    {
        $gateway = $this->gateway();
        $options = ['startTime' => $from, 'limit' => $limit] + ($cursor !== '' ? ['cursor' => $cursor] : []);
        $response = match ($list) {
            'links' => $gateway->listPaymentLinks($options)->send(),
            'payments' => $gateway->listPayments($options)->send(),
            'refunds' => $gateway->listRefunds($options)->send(),
            'fees' => $gateway->listFees($options)->send(),
            default => throw new RuntimeException('Stitch has no such list.'),
        };
        if (!$response->answered()) {
            throw new RuntimeException('Stitch did not give the list: ' . ($response->getMessage() ?? 'no reason given') . '.');
        }

        return ['items' => $response->getItems(), 'next' => $response->hasMore() ? $response->getNextCursor() : null];
    }

    /** Whether Stitch accepts the client ID and secret: null when it does, else what it said. */
    public function connectionProblem(): ?string
    {
        try {
            $response = $this->gateway()->redirectUrls()->send();
        } catch (Throwable $failed) {
            return $failed->getMessage();
        }

        return $response->answered() ? null : ($response->getMessage() ?? 'Stitch did not answer.');
    }

    /** @return list<string> the return addresses Stitch accepts for this account */
    public function returnAddresses(): array
    {
        return $this->gateway()->redirectUrls()->send()->getRedirectUrls();
    }

    /** Registers the site's return address with Stitch, unless it is there already. */
    public function registerReturnAddress(): void
    {
        if (in_array($this->returnAddress(), $this->returnAddresses(), true)) {
            return;
        }
        $response = $this->gateway()->registerRedirectUrl(['redirectUrl' => $this->returnAddress()])->send();
        if (!$response->answered()) {
            throw new RuntimeException('Stitch did not register ' . $this->returnAddress() . ': ' . ($response->getMessage() ?? 'no reason given') . '.');
        }
    }

    /** Registers the site's webhook address with Stitch and gives its signing secret, which Stitch shows only now. */
    public function registerWebhook(): string
    {
        $response = $this->gateway()->registerWebhook(['url' => $this->webhookAddress()])->send();
        if ($response->isAlreadyRegistered()) {
            throw new RuntimeException('Stitch already has ' . $this->webhookAddress() . ' as a webhook. Its signing secret is shown only once: delete the webhook in Stitch\'s dashboard (Webhooks) and register it here again, or paste its secret below.');
        }
        $secret = $response->getSecret();
        if (!$response->answered() || $secret === null) {
            throw new RuntimeException('Stitch did not register the webhook: ' . ($response->getMessage() ?? 'no reason given') . '.');
        }

        return $secret;
    }

    private function gateway(): Gateway
    {
        $gateway = $this->gateways->gateway(self::GATEWAY);
        if (!$gateway instanceof Gateway) {
            throw new RuntimeException('Card payments are configured with another gateway than Stitch.');
        }

        return $gateway;
    }

    /** The payer as Stitch takes them: 3 to 40 characters, else the email address's name, else the word Customer. */
    private static function payerName(string $name, string $email): string
    {
        $name = trim((string) preg_replace('/\s+/', ' ', $name));
        if (mb_strlen($name) < 3) {
            $name = trim(explode('@', $email)[0]);
        }
        if (mb_strlen($name) < 3) {
            $name = 'Customer';
        }

        return mb_substr($name, 0, 40);
    }
}
