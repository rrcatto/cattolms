        $ids = array_values(array_unique(array_filter(array_map('intval', $enrolmentIds), static fn(int $id): bool => $id > 0)));
        if ($ids === []) return [];
        $titles = [];
        foreach ($this->db->fetchAllAssociative('SELECT e.id, c.title FROM course_enrolments e JOIN courses c ON c.id = e.course_id WHERE e.id IN (' . implode(',', $ids) . ')') as $row) {
            $titles[(int) $row['id']] = (string) $row['title'];
        }
        return $titles;
    }

    /**
     * The ledger between two instants, by kind and method: what each dashboard money figure adds up.
     *
     * @return list<array{kind:string,method:string,entries:int,total:int}>
     */
    public function ledgerByKind(string $fromAt, string $toBefore): array
    {
        return array_map(static fn(array $r): array => ['kind' => (string) $r['kind'], 'method' => (string) $r['method'], 'entries' => (int) $r['entries'], 'total' => (int) $r['total']],
            $this->db->fetchAllAssociative('SELECT kind, method, COUNT(*) AS entries, COALESCE(SUM(amount_minor), 0) AS total FROM commerce_ledger_entries
                WHERE occurred_at >= CAST(:from_at AS TIMESTAMPTZ) AND occurred_at < CAST(:to_before AS TIMESTAMPTZ) GROUP BY kind, method', ['from_at' => $fromAt, 'to_before' => $toBefore]));
    }

    /**
     * Money in and out of the business per day, week or month, in the platform's time zone.
     *
     * @return list<array{bucket:string,money_in:int,money_out:int}>
     */
    public function moneySeries(string $fromAt, string $toBefore, string $unit, string $timezone): array
    {
        $unit = in_array($unit, ['day', 'week', 'month'], true) ? $unit : 'day';
        return array_map(static fn(array $r): array => ['bucket' => (string) $r['bucket'], 'money_in' => (int) $r['money_in'], 'money_out' => (int) $r['money_out']],
            $this->db->fetchAllAssociative("SELECT to_char(date_trunc('" . $unit . "', occurred_at AT TIME ZONE :tz), 'YYYY-MM-DD') AS bucket,
                    COALESCE(SUM(CASE WHEN cash_effect = 1 THEN amount_minor END), 0) AS money_in,
                    COALESCE(SUM(CASE WHEN cash_effect = -1 THEN amount_minor END), 0) AS money_out
                FROM commerce_ledger_entries WHERE occurred_at >= CAST(:from_at AS TIMESTAMPTZ) AND occurred_at < CAST(:to_before AS TIMESTAMPTZ)
                GROUP BY 1 ORDER BY 1", ['tz' => $timezone, 'from_at' => $fromAt, 'to_before' => $toBefore]));
    }

    /** @return list<array{state:string,orders:int,total:int}> orders placed between two instants, by state */
    public function ordersByState(string $fromAt, string $toBefore): array
    {
        return array_map(static fn(array $r): array => ['state' => (string) $r['state'], 'orders' => (int) $r['orders'], 'total' => (int) $r['total']],
            $this->db->fetchAllAssociative('SELECT state, COUNT(*) AS orders, COALESCE(SUM(total_minor), 0) AS total FROM commerce_orders
                WHERE placed_at >= CAST(:from_at AS TIMESTAMPTZ) AND placed_at < CAST(:to_before AS TIMESTAMPTZ) GROUP BY state', ['from_at' => $fromAt, 'to_before' => $toBefore]));
    }

    /** All wallet credit not yet spent or expired, now: every credit lot less what has been taken from it. */
    public function walletCreditOutstanding(): int
    {
        return (int) $this->db->fetchOne('SELECT (SELECT COALESCE(SUM(amount_minor), 0) FROM commerce_wallet_lots) - (SELECT COALESCE(SUM(amount_minor), 0) FROM commerce_wallet_allocations)');
    }
