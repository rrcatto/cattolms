declare(strict_types=1);

namespace CattoLearning\Commerce\Infrastructure;

use CattoLearning\Infrastructure\Persistence\Database;

final class MoneyReportRepository
{
    public function __construct(private readonly Database $db)
    {
    }

    /**
     * What the orders placed between two instants, in the given states, sold: one row for each course, bundle and course's
     * credits, with how many, their prices before promotions, the promotions on them and what they were paid, the most
     * paid first. A line's title is its order's own record of it, the latest when it changed.
     *
     * @param list<string> $states
     * @return list<array{product_type:string,product_id:int,title:string,sold:int,before_minor:int,promotions_minor:int,paid_minor:int}>
     */
    public function sales(string $fromAt, string $toBefore, array $states): array
    {
        [$in, $params] = self::states($states);
        $rows = $this->db->fetchAllAssociative(
            "SELECT i.product_type, COALESCE(i.bundle_id, i.course_id) AS product_id,
                    (array_agg(COALESCE(i.snapshot->>'bundle_title', i.snapshot->>'course_title', '') ORDER BY o.placed_at DESC, i.id DESC))[1] AS title,
                    SUM(i.quantity) AS sold, SUM(i.amount_minor) AS before_minor, SUM(i.discount_minor) AS promotions_minor, SUM(i.amount_minor - i.discount_minor) AS paid_minor
               FROM commerce_order_items i JOIN commerce_orders o ON o.id = i.order_id
              WHERE o.placed_at >= CAST(:from_at AS TIMESTAMPTZ) AND o.placed_at < CAST(:to_before AS TIMESTAMPTZ) AND o.state IN (" . $in . ')
              GROUP BY i.product_type, COALESCE(i.bundle_id, i.course_id)
              ORDER BY SUM(i.amount_minor - i.discount_minor) DESC, 3',
            ['from_at' => $fromAt, 'to_before' => $toBefore] + $params
        );

        return array_map(static fn(array $row): array => ['product_type' => (string) $row['product_type'], 'product_id' => (int) $row['product_id'], 'title' => (string) $row['title'],
            'sold' => (int) $row['sold'], 'before_minor' => (int) $row['before_minor'], 'promotions_minor' => (int) $row['promotions_minor'], 'paid_minor' => (int) $row['paid_minor']], $rows);
    }

    /**
     * How many of the orders placed between two instants, in the given states, a promotion was given on.
     *
     * @param list<string> $states
     */
    public function promotedOrders(string $fromAt, string $toBefore, array $states): int
    {
        [$in, $params] = self::states($states);

        return (int) $this->db->fetchOne(
            'SELECT COUNT(*) FROM commerce_orders o WHERE o.placed_at >= CAST(:from_at AS TIMESTAMPTZ) AND o.placed_at < CAST(:to_before AS TIMESTAMPTZ)
                AND o.discount_minor > 0 AND o.state IN (' . $in . ')',
            ['from_at' => $fromAt, 'to_before' => $toBefore] + $params
        );
    }

    /** The first day of the first month the site has a money record, an order or an account in, in its time zone; null before any. */
    public function firstMonth(string $timezone): ?string
    {
        $month = $this->db->fetchOne(
            "SELECT to_char(date_trunc('month', MIN(at) AT TIME ZONE :tz), 'YYYY-MM-DD') FROM (
                SELECT MIN(occurred_at) AS at FROM commerce_ledger_entries
                UNION ALL SELECT MIN(placed_at) FROM commerce_orders
                UNION ALL SELECT MIN(created_at) FROM users) firsts",
            ['tz' => $timezone]
        );

        return is_string($month) && $month !== '' ? $month : null;
    }

    /** @return array<string,mixed>|null what became of a month's report, its month the first day ('2026-10-01') */
    public function send(string $month): ?array
    {
        return $this->db->fetchAssociative('SELECT * FROM money_report_sends WHERE month = CAST(:month AS DATE)', ['month' => $month]) ?: null;
    }

    /**
     * Claims a month's report before anything goes, once: what each tick said at that moment (waiting, off, not_connected).
     * A month already claimed keeps what it was given.
     */
    public function claim(string $month, string $email, string $telegram): void
    {
        $this->db->executeStatement(
            'INSERT INTO money_report_sends (month, email, telegram) VALUES (CAST(:month AS DATE), :email, :telegram) ON CONFLICT (month) DO NOTHING',
            ['month' => $month, 'email' => $email, 'telegram' => $telegram]
        );
    }

    /**
     * A month's report, locked until the transaction ends, so two schedulers never both send it.
     *
     * @return array<string,mixed>|null
     */
    public function lock(string $month): ?array
    {
        return $this->db->fetchAssociative('SELECT * FROM money_report_sends WHERE month = CAST(:month AS DATE) FOR UPDATE', ['month' => $month]) ?: null;
    }

    public function emailed(string $month, string $to): void
    {
        $this->db->executeStatement("UPDATE money_report_sends SET email = 'sent', emailed_to = :to, emailed_at = NOW(), tries = tries + 1, last_error = NULL, updated_at = NOW() WHERE month = CAST(:month AS DATE)",
            ['month' => $month, 'to' => $to]);
    }

    /** The email could not go: tried again next time, or, with $givenUp, never. */
    public function emailFailed(string $month, string $error, bool $givenUp): void
    {
        $this->db->executeStatement('UPDATE money_report_sends SET email = CASE WHEN :given_up THEN \'failed\' ELSE email END, tries = tries + 1, last_error = :error, updated_at = NOW() WHERE month = CAST(:month AS DATE)',
            ['month' => $month, 'error' => mb_substr($error, 0, 500), 'given_up' => $givenUp]);
    }

    public function telegramSent(string $month): void
    {
        $this->db->executeStatement("UPDATE money_report_sends SET telegram = 'sent', telegram_at = NOW(), updated_at = NOW() WHERE month = CAST(:month AS DATE)", ['month' => $month]);
    }

    /**
     * @param list<string> $states
     * @return array{0:string,1:array<string,string>}
     */
    private static function states(array $states): array
    {
        $names = [];
        $params = [];
        foreach ($states as $index => $state) {
            $names[] = ':state_' . $index;
            $params['state_' . $index] = $state;
        }

        return [$names === [] ? 'NULL' : implode(', ', $names), $params];
    }
}
