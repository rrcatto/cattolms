declare(strict_types=1);

namespace CattoLearning\Commerce\Settings;

use CattoLearning\Commerce\Infrastructure\Payment\StitchPaymentGateway;
use CattoLearning\Configuration\SiteMode;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoPHP\Activity\Actor;
use CattoPHP\Settings\Settings;
use CattoPHP\Settings\SettingsRefused;
use RuntimeException;

final class CardPaymentSettings
{
    /** CattoPHP's group of settings for the Stitch gateway. */
    public const GROUP = 'payment_stitch';

    public const CLIENT_ID = 'STITCH_CLIENT_ID';
    public const CLIENT_SECRET = 'STITCH_CLIENT_SECRET';
    public const WEBHOOK_SECRET = 'STITCH_WEBHOOK_SECRET';

    public function __construct(
        private readonly Settings $settings,
        private readonly StitchPaymentGateway $stitch,
        private readonly SiteMode $site,
        private readonly AuditRepository $audit,
    ) {
    }

    /**
     * What the section shows: the state in a few words with its tone, the client ID (never a secret), whether each secret is
     * set and where each value comes from, the two addresses to give Stitch, and whether this is a demo or a live site.
     *
     * @return array<string,mixed>
     */
    public function view(): array
    {
        $kind = $this->stitch->kind();
        $problem = $this->stitch->problem();
        $demo = $this->site->isDemo();
        // The accordion's title says the state in the tones it has: success, danger or neutral.
        [$state, $tone] = match (true) {
            $kind === '' || $this->settings->get(self::CLIENT_SECRET) === '' => ['Not set up', 'neutral'],
            $problem !== null => ['Not available: a test client ID on a live site', 'danger'],
            $kind === 'live' && $demo => ['Live keys on a demo site', 'danger'],
            $kind === 'test' => ['Test mode', 'neutral'],
            default => ['Live', 'success'],
        };

        return [
            'state' => $state,
            'tone' => $tone,
            'kind' => $kind,
            'problem' => $problem,
            'demo_site' => $demo,
            'client_id' => $this->settings->get(self::CLIENT_ID),
            'has_secret' => $this->settings->get(self::CLIENT_SECRET) !== '',
            'has_webhook_secret' => $this->stitch->hasWebhookSecret(),
            'sources' => [
                'client_id' => $this->source(self::CLIENT_ID),
                'client_secret' => $this->source(self::CLIENT_SECRET),
                'webhook_secret' => $this->source(self::WEBHOOK_SECRET),
            ],
            'overridden' => $this->settings->isOverridden(self::CLIENT_ID) || $this->settings->isOverridden(self::CLIENT_SECRET) || $this->settings->isOverridden(self::WEBHOOK_SECRET),
            'return_address' => $this->stitch->returnAddress(),
            'webhook_address' => $this->stitch->webhookAddress(),
            'ready' => $kind !== '' && $this->settings->get(self::CLIENT_SECRET) !== '',
        ];
    }

    /**
     * Saves what was typed: the client ID as typed, each secret only when one was typed (blank keeps it). Then asks Stitch
     * whether it accepts them; returns null when it does, else what Stitch said (the keys are kept either way).
     *
     * @param array{client_id?:string,client_secret?:string,webhook_secret?:string} $typed
     */
    public function save(array $typed, int $actorId): ?string
    {
        $clientId = trim((string) ($typed['client_id'] ?? ''));
        if ($clientId !== '' && preg_match('/^[A-Za-z0-9._-]{4,200}$/', $clientId) !== 1) {
            throw new RuntimeException('The client ID is the one Stitch shows under Settings, Developers: letters, digits and hyphens, such as test-958fd377-....');
        }
        $secret = trim((string) ($typed['client_secret'] ?? ''));
        $webhook = trim((string) ($typed['webhook_secret'] ?? ''));
        if ($webhook !== '' && !str_starts_with($webhook, 'whsec_')) {
            throw new RuntimeException('The webhook\'s signing secret starts with whsec_, as Stitch gives it when the webhook is registered.');
        }
        try {
            $this->settings->save(self::GROUP, [
                self::CLIENT_ID => $clientId,
                self::CLIENT_SECRET => $secret === '' ? null : $secret,
                self::WEBHOOK_SECRET => $webhook === '' ? null : $webhook,
            ], self::actor($actorId));
        } catch (SettingsRefused $refused) {
            throw new RuntimeException(implode(' ', $refused->errors()));
        }

        return $this->stitch->kind() === '' || $this->settings->get(self::CLIENT_SECRET) === '' ? null : $this->stitch->connectionProblem();
    }

    /** Whether Stitch accepts the keys now: null when it does, else what it said. */
    public function check(): ?string
    {
        if (!$this->view()['ready']) {
            throw new RuntimeException('Enter the client ID and secret first.');
        }

        return $this->stitch->connectionProblem();
    }

    /** Registers the site's return address with Stitch (once; again changes nothing). */
    public function registerReturnAddress(int $actorId): void
    {
        $this->requireReady();
        $this->stitch->registerReturnAddress();
        $this->audit->record($actorId, 'settings.stitch_return_address_registered', ['address' => $this->stitch->returnAddress()]);
    }

    /** Registers the site's webhook with Stitch and keeps the signing secret Stitch gives, which it shows only now. */
    public function registerWebhook(int $actorId): void
    {
        $this->requireReady();
        $secret = $this->stitch->registerWebhook();
        $this->settings->set(self::WEBHOOK_SECRET, $secret, self::actor($actorId));
        $this->audit->record($actorId, 'settings.stitch_webhook_registered', ['address' => $this->stitch->webhookAddress()]);
    }

    /** The three back to what .env says. */
    public function reset(int $actorId): void
    {
        $this->settings->resetGroup(self::GROUP, self::actor($actorId));
    }

    private function requireReady(): void
    {
        $problem = $this->stitch->problem();
        if ($problem !== null) {
            throw new RuntimeException($problem);
        }
    }

    /** saved (here), env (from .env) or none. */
    private function source(string $name): string
    {
        if ($this->settings->isOverridden($name)) {
            return 'saved';
        }

        return $this->settings->get($name) !== '' ? 'env' : 'none';
    }

    private static function actor(int $userId): ?Actor
    {
        return $userId > 0 ? new Actor((string) $userId, (string) $userId) : null;
    }
}
