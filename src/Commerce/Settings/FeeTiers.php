    /** @param list<array{from:int,fee:int}> $tiers */
    public static function of(array $tiers): self
    {
        if ($tiers === [] || count($tiers) > 20) throw new InvalidArgumentException('Give between one and twenty fee tiers.');
        usort($tiers, static fn(array $a, array $b): int => $a['from'] <=> $b['from']);
        if ($tiers[0]['from'] !== 0) throw new InvalidArgumentException('The first fee tier starts at R0.');
        $previous = -1;
        foreach ($tiers as $tier) {
            if ($tier['from'] === $previous) throw new InvalidArgumentException('Two fee tiers start at the same amount.');
            if ($tier['fee'] < 0 || $tier['fee'] > 1000000) throw new InvalidArgumentException('A fee is a Rand amount from R0 to R10,000.');
            $previous = $tier['from'];
        }

        return new self($tiers);
    }

    public static function fromText(string $text): self
    {
        $tiers = [];
        foreach (array_filter(array_map('trim', explode(',', $text)), static fn(string $part): bool => $part !== '') as $part) {
            if (preg_match('/^(\d{1,10}):(\d{1,7})$/', $part, $match) !== 1) {
                throw new InvalidArgumentException('Fee tiers are written as amount:fee pairs in cents, such as 0:2000,1000000:10000.');
            }
            $tiers[] = ['from' => (int) $match[1], 'fee' => (int) $match[2]];
        }

        return self::of($tiers);
    }

    public function toText(): string
    {
        return implode(',', array_map(static fn(array $tier): string => $tier['from'] . ':' . $tier['fee'], $this->tiers));
    }

    /** The tiers in words, as the Refund Policy states them: "R 20,00 on a refund under R 10 000,00 and R 100,00 on R 10 000,00 or more". */
    public function words(string $currency = 'ZAR'): string
    {
        $money = static fn(int $minor): string => \CattoLearning\Support\Money::ofMinorUnits($minor, $currency)->format();
        if (count($this->tiers) === 1) return $this->tiers[0]['fee'] === 0 ? 'none at present' : $money($this->tiers[0]['fee']);
        $parts = [];
        foreach ($this->tiers as $index => $tier) {
            $next = $this->tiers[$index + 1]['from'] ?? null;
            $parts[] = $money($tier['fee']) . ($next !== null ? ' on a refund under ' . $money($next) : ' on ' . $money($tier['from']) . ' or more');
        }
        $last = array_pop($parts);

        return implode(', ', $parts) . ' and ' . $last;
    }

    public function feeFor(int $amountMinor): int
    {
        $fee = $this->tiers[0]['fee'];
        foreach ($this->tiers as $tier) {
            if ($amountMinor >= $tier['from']) $fee = $tier['fee'];
        }

        return $fee;
    }
}
