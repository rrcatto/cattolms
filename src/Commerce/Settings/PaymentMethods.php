/*
Generated by: Claude Code CLI

Date time: 2026/10/19 SAST

Version: 0.9.6

Description:
The payment methods a site offers (owner, 2026-10-19): Administration > Settings > Payment methods has
one tick box per method, EFT and card (Stitch) for now, so more can be added later. A method can be
ticked only when it is configured: card needs its keys in .env (STITCH_CLIENT_ID, STITCH_CLIENT_SECRET)
and the Stitch connection, which is not built yet, so it cannot be ticked. The simulated card exists
only on a demo site and is never offered on a live site, whatever is saved. Checkout offers only the
ticked methods that work; the wallet is not one of them, it is always available to spend. Every change
goes to the Activity log (settings.payment_methods_changed) with the old and new methods.

No payment method may ever collect card details on this site: card payment is always on the
provider's own page. Checkout and receipts name the method and its provider (label(), receiptLabel()).

Changelog:
2026/10/19 SAST
- Created.
*/

declare(strict_types=1);

namespace CattoLearning\Commerce\Settings;

use CattoLearning\Configuration\SiteMode;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\OptionRepository;
use CattoLearning\Support\Env;
use InvalidArgumentException;

final class PaymentMethods
{
    public const EFT = 'eft';
    public const CARD = 'card';
    /** The simulated card of a demo site; its order and payment records call it dummy. */
    public const SIMULATED = 'dummy';

    /** The app_options key: the ticked methods, comma separated. */
    public const OPTION = 'payment_methods';

    /** What a site offers before anyone saves the setting: EFT, and the simulated card on a demo site. */
    private const DEFAULT = [self::EFT, self::SIMULATED];

    /** The .env keys card payments need. */
    public const CARD_KEYS = ['STITCH_CLIENT_ID', 'STITCH_CLIENT_SECRET'];

    public function __construct(
        private readonly SiteMode $site,
        private readonly ?OptionRepository $options = null,
        private readonly ?AuditRepository $audit = null,
    ) {}

    /** @return list<string> every method, in the order Settings and checkout show them */
    public function methods(): array
    {
        return $this->site->isDemo() ? [self::EFT, self::CARD, self::SIMULATED] : [self::EFT, self::CARD];
    }

    /** @return list<string> the saved ticks, or the defaults */
    public function ticked(): array
    {
        $saved = $this->options?->find(self::OPTION);
        $ticked = $saved === null ? self::DEFAULT : array_values(array_filter(array_map('trim', explode(',', $saved))));
        return array_values(array_intersect([self::EFT, self::CARD, self::SIMULATED], $ticked));
    }

    /** Why a method cannot be offered now, or null when it can. */
    public function problem(string $method): ?string
    {
        return match ($method) {
            self::EFT => null,
            self::CARD => $this->cardProblem(),
            self::SIMULATED => $this->site->isDemo() ? null : 'The simulated card exists only on a demo site.',
            default => 'There is no such payment method.',
        };
    }

    /** @return list<string> the methods checkout offers: ticked and working */
    public function offered(): array
    {
        return array_values(array_filter($this->methods(), fn(string $method): bool => in_array($method, $this->ticked(), true) && $this->problem($method) === null));
    }

    public function isOffered(string $method): bool
    {
        return in_array($method, $this->offered(), true);
    }

    /** @return list<array{key:string,label:string,provider:string,ticked:bool,problem:?string}> for Settings > Payment methods */
    public function settingsView(): array
    {
        return array_map(fn(string $method): array => ['key' => $method, 'label' => self::label($method), 'provider' => self::provider($method),
            'ticked' => in_array($method, $this->ticked(), true) && $this->problem($method) === null, 'problem' => $this->problem($method)], $this->methods());
    }

    /** @return list<array{key:string,label:string}> what checkout's payment method field lists */
    public function checkoutOptions(): array
    {
        return array_map(static fn(string $method): array => ['key' => $method, 'label' => self::label($method)], $this->offered());
    }

    /**
     * Saves the ticked methods. A method that cannot be offered cannot be ticked, and at least one must
     * be ticked, or nobody could pay for anything the wallet does not cover. The change is logged.
     *
     * @param list<string> $ticked
     */
    public function save(array $ticked, int $actorId): void
    {
        if ($this->options === null) throw new InvalidArgumentException('The payment methods cannot be changed here.');
        $ticked = array_values(array_unique(array_map('strval', $ticked)));
        foreach ($ticked as $method) {
            if (!in_array($method, $this->methods(), true)) throw new InvalidArgumentException('There is no such payment method.');
            $problem = $this->problem($method);
            if ($problem !== null) throw new InvalidArgumentException(self::label($method) . ' cannot be ticked: ' . $problem);
        }
        if ($ticked === []) throw new InvalidArgumentException('Tick at least one payment method. The wallet only pays what it holds.');
        // A live site keeps a saved simulated-card tick out of its list; it is never offered there anyway.
        $before = $this->offered();
        $kept = array_values(array_intersect([self::EFT, self::CARD, self::SIMULATED], $ticked));
        $this->options->set(self::OPTION, implode(',', $kept), $actorId);
        $after = $this->offered();
        if ($before !== $after) {
            $this->audit?->record($actorId, 'settings.payment_methods_changed', ['before' => $before, 'after' => $after]);
        }
    }

    /** The method as checkout names it, with its provider. */
    public static function label(string $method): string
    {
        return match ($method) {
            self::EFT => 'EFT: bank transfer to our bank account',
            self::CARD => 'Card: paid on Stitch\'s secure page',
            self::SIMULATED => 'Simulated card (demo site, no money is charged)',
            'wallet' => 'Wallet credit',
            default => $method,
        };
    }

    /** Who carries the payment. */
    public static function provider(string $method): string
    {
        return match ($method) {
            self::EFT => 'Your bank, to the Site Owner\'s bank account',
            self::CARD => 'Stitch',
            self::SIMULATED => 'Nobody: a simulation on a demo site',
            default => '',
        };
    }

    /** How a receipt names a payment, from the gateway that took it. */
    public static function receiptLabel(string $gateway): ?string
    {
        return match ($gateway) {
            'manual_bank' => 'EFT (direct bank transfer)',
            'stitch' => 'Card, through Stitch',
            'dummy' => 'Simulated card (demo site, no money was charged)',
            'wallet' => 'Wallet credit',
            default => null,
        };
    }

    private function cardProblem(): ?string
    {
        $missing = array_values(array_filter(self::CARD_KEYS, static fn(string $key): bool => trim(Env::string($key)) === ''));
        if ($missing !== []) return 'Add ' . implode(' and ', $missing) . ' to .env first.';
        if (!$this->cardConnected()) return 'Card payments through Stitch are not connected yet.';
        return null;
    }

    /** Whether card payments through Stitch are built. Until they are, card cannot be ticked. */
    private function cardConnected(): bool
    {
        return class_exists('CattoLearning\\Commerce\\Infrastructure\\Payment\\StitchPaymentGateway');
    }
}
