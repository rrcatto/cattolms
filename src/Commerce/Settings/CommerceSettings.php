    public const SECTIONS = ['fees', 'references', 'wallet', 'orders'];

    public function __construct(private readonly OptionRepository $options)
    {
    }

    /** The app_options key of a setting's database override. */
    public static function optionKey(string $key): string
    {
        return 'commerce.' . $key;
    }

    /** The text in force: the database override, else the .env default, else the built-in default. */
    public function text(string $key): string
    {
        self::definition($key);
        $override = $this->options->find(self::optionKey($key));
        if ($override !== null && self::check($key, $override) === null) return $override;

        return $this->environmentText($key);
    }

    /** Where the value in force comes from: database, environment or default. */
    public function source(string $key): string
    {
        $override = $this->options->find(self::optionKey($key));
        if ($override !== null && self::check($key, $override) === null) return 'database';
        [, $env] = self::definition($key);
        $environment = trim(Env::string($env, ''));

        return $environment !== '' && self::check($key, $environment) === null ? 'environment' : 'default';
    }

    /** The .env default, or the built-in default when .env has none or an invalid one. */
    public function environmentText(string $key): string
    {
        [, $env, $default] = self::definition($key);
        $environment = trim(Env::string($env, ''));

        return $environment !== '' && self::check($key, $environment) === null ? $environment : $default;
    }

    public function stitchFee(): ProcessorFee { return ProcessorFee::fromText($this->text('stitch_fee')); }
    public function stitchRefundFee(): ProcessorFee { return ProcessorFee::fromText($this->text('stitch_refund_fee')); }
    public function eftRefundFee(): FeeTiers { return FeeTiers::fromText($this->text('eft_refund_fee')); }
    public function accountPrefix(): string { return $this->text('account_prefix'); }
    public function walletExpiry(): Duration { return Duration::parse($this->text('wallet_expiry')); }
    public function walletReminder(): Duration { return Duration::parse($this->text('wallet_reminder')); }
    public function refundWindow(): Duration { return Duration::parse($this->text('refund_window')); }
    public function paymentDue(): Duration { return Duration::parse($this->text('payment_due')); }
    public function paymentLinkLifetime(): Duration { return Duration::parse($this->text('payment_link_lifetime')); }

    /**
     * Checks every value of one section and saves the ones that changed. Nothing is saved when any
     * value is wrong. The wallet reminder must be shorter than the credit expiry.
     *
     * @param array<string,string> $values key => text as entered
     */
    public function saveSection(string $section, array $values, int $actorId): void
    {
        if (!in_array($section, self::SECTIONS, true)) throw new InvalidArgumentException('Unknown commerce settings section.');
        $checked = [];
        foreach (self::SETTINGS as $key => [$owner]) {
            if ($owner !== $section) continue;
            $text = trim((string) ($values[$key] ?? ''));
            $problem = self::check($key, $text);
            if ($problem !== null) throw new InvalidArgumentException(self::label($key) . ': ' . $problem);
            $checked[$key] = $text;
        }
        if ($section === 'wallet') {
            $from = new DateTimeImmutable();
            if (!Duration::parse($checked['wallet_reminder'])->isShorterThan(Duration::parse($checked['wallet_expiry']), $from)) {
                throw new InvalidArgumentException('Expiry reminder: make it shorter than the credit expiry.');
            }
        }
        foreach ($checked as $key => $text) {
            if ($text === $this->text($key) && $this->source($key) !== 'database') continue;
            $this->options->set(self::optionKey($key), $text, $actorId);
        }
    }

    /** Removes a setting's database override, so the .env default applies again. */
    public function reset(string $key): void
    {
        self::definition($key);
        $this->options->delete(self::optionKey($key));
    }

    /** Why a value cannot be used, or null when it can. */
    public static function check(string $key, string $text): ?string
    {
        [, , , $type] = self::definition($key);
        try {
            match ($type) {
                'processor_fee' => ProcessorFee::fromText($text),
                'fee_tiers' => FeeTiers::fromText($text),
                'duration' => Duration::parse($text),
                'prefix' => AccountReference::validPrefix($text) ? null : throw new InvalidArgumentException('Use 1 to 3 capital letters, such as CL.'),
                default => throw new InvalidArgumentException('Unknown kind of commerce setting.'),
            };
        } catch (InvalidArgumentException $exception) {
            return $exception->getMessage();
        }

        return null;
    }

    public static function label(string $key): string
    {
        return match ($key) {
            'stitch_fee' => 'Stitch transaction fee',
            'stitch_refund_fee' => 'Stitch refund fee',
            'eft_refund_fee' => 'EFT refund fee',
            'account_prefix' => 'Account reference prefix',
            'wallet_expiry' => 'Wallet credit expiry',
            'wallet_reminder' => 'Expiry reminder',
            'refund_window' => 'Refund window',
            'payment_due' => 'Unpaid order cancellation',
            'payment_link_lifetime' => 'Payment link lifetime',
            default => $key,
        };
    }

    /** @return array{0:string,1:string,2:string,3:string} */
    private static function definition(string $key): array
    {
        return self::SETTINGS[$key] ?? throw new InvalidArgumentException('Unknown commerce setting: ' . $key);
    }
}
