declare(strict_types=1);

namespace CattoLearning\Commerce\Settings;

use InvalidArgumentException;

final class ProcessorFee
{
    private function __construct(public readonly string $percent, public readonly int $fixedMinor)
    {
    }

    public static function of(string $percent, int $fixedMinor): self
    {
        $percent = trim($percent);
        if (preg_match('/^\d{1,2}(?:\.\d{1,2})?$/', $percent) !== 1 || (float) $percent > 50) {
            throw new InvalidArgumentException('Enter the percentage as a number from 0 to 50 with up to two decimals, such as 2.9.');
        }
        if ($fixedMinor < 0 || $fixedMinor > 100000) throw new InvalidArgumentException('Enter the fixed part as a Rand amount from R0 to R1,000.');

        return new self($percent, $fixedMinor);
    }

    /** "2.9%+150" (fixed part in cents), the form stored in app_options and .env. */
    public static function fromText(string $text): self
    {
        if (preg_match('/^\s*(\d{1,2}(?:\.\d{1,2})?)%\s*\+\s*(\d{1,6})\s*$/', $text, $part) !== 1) {
            throw new InvalidArgumentException('A fee is written as a percentage and a fixed amount in cents, such as 2.9%+150.');
        }

        return self::of($part[1], (int) $part[2]);
    }

    public function toText(): string
    {
        return $this->percent . '%+' . $this->fixedMinor;
    }

    /** The fee in words, as the Refund Policy states it: "2.9% of the amount plus R 1,50". */
    public function words(string $currency = 'ZAR'): string
    {
        $percent = (float) $this->percent > 0 ? $this->percent . '% of the amount' : '';
        $fixed = $this->fixedMinor > 0 ? \CattoLearning\Support\Money::ofMinorUnits($this->fixedMinor, $currency)->format() : '';
        if ($percent === '' && $fixed === '') return 'none at present';

        return $percent !== '' && $fixed !== '' ? $percent . ' plus ' . $fixed : $percent . $fixed;
    }

    /** The fee on an amount, in minor units, rounded half up; zero on nothing. */
    public function on(int $amountMinor): int
    {
        if ($amountMinor <= 0) return 0;
        $hundredths = (int) round((float) $this->percent * 100);

        return intdiv($amountMinor * $hundredths + 5000, 10000) + $this->fixedMinor;
    }
}
