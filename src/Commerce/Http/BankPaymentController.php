declare(strict_types=1);

namespace CattoLearning\Commerce\Http;

use CattoLearning\Auth\AuthService;
use CattoLearning\Commerce\Application\BankPayments;
use CattoLearning\Http\Controller\BaseController;
use CattoLearning\Support\Uuid;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class BankPaymentController extends BaseController
{
    /** The statement details the Record EFT Payment form carries from finding to recording. */
    private const STATEMENT = ['reference', 'amount', 'received_on', 'received_time', 'bank_reference', 'reason'];

    public function __construct(AuthService $auth, ThemeRenderer $view, RequestStack $requests, private readonly BankPayments $bank)
    {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/admin/commerce/eft', name: 'admin_record_eft', methods: ['GET'])]
    public function record(): Response
    {
        $this->requirePermission('PLATFORM.PAYMENT.MANAGE');
        $statement = [];
        foreach (self::STATEMENT as $field) $statement[$field] = trim((string) $this->request()->query->get($field, ''));
        $today = (new \DateTimeImmutable('now', new \DateTimeZone(date_default_timezone_get())))->format('Y-m-d');
        if (preg_match('/^\d{4}-\d{2}-\d{2}$/', $statement['received_on']) !== 1) $statement['received_on'] = $today;

        return $this->render('admin-eft-payment', ['title' => 'Record EFT Payment', 'active_nav' => 'admin', 'statement' => $statement, 'today' => $today,
            'match' => $statement['reference'] === '' ? null : $this->bank->find($statement['reference']), 'request_key' => Uuid::v4()]);
    }

    #[Route('/admin/commerce/eft/order', name: 'admin_record_eft_order', methods: ['POST'])]
    public function recordAgainstOrder(): Response
    {
        $this->requireCsrf();
        $actor = $this->requirePermission('PLATFORM.PAYMENT.MANAGE');
        $back = $this->statementHref();
        $orderId = (int) $this->posted('order_id');

        return $this->handle(function () use ($actor, $orderId): void {
            $this->bank->recordAgainstOrder($actor, $orderId, $this->posted('request_key'), EftForm::amount($this->posted('amount')),
                EftForm::receivedAt($this->posted('received_on'), $this->posted('received_time')), $this->posted('reference'), $this->posted('bank_reference'), $this->posted('reason'));
            $this->flash('success', 'The EFT payment is recorded against this order.');
            $this->redirect('/admin/commerce/orders/' . $orderId);
        }, $back);
    }

    #[Route('/admin/commerce/eft/unmatched', name: 'admin_record_eft_unmatched', methods: ['POST'])]
    public function recordUnmatched(): Response
    {
        $this->requireCsrf();
        $actor = $this->requirePermission('PLATFORM.PAYMENT.MANAGE');

        return $this->handle(function () use ($actor): void {
            $id = $this->bank->recordUnmatched($actor, $this->posted('request_key'), EftForm::amount($this->posted('amount')),
                EftForm::receivedAt($this->posted('received_on'), $this->posted('received_time')), $this->posted('reference'), $this->posted('bank_reference'), $this->posted('reason'));
            $this->flash('success', 'The deposit is on the unmatched money list.');
            $this->redirect('/admin/commerce/unmatched/' . $id);
        }, $this->statementHref());
    }

    #[Route('/admin/commerce/unmatched', name: 'admin_unmatched_money', methods: ['GET'])]
    public function unmatchedList(): Response
    {
        $this->requirePermission('PLATFORM.PAYMENT.VIEW');
        $all = $this->request()->query->get('show') === 'all';

        return $this->render('admin-unmatched-money', ['title' => 'Unmatched Money', 'active_nav' => 'admin', 'show_all' => $all, 'items' => $this->bank->unmatchedList(!$all)]);
    }

    #[Route('/admin/commerce/unmatched/{id}', name: 'admin_unmatched_item', requirements: ['id' => '[0-9]+'], methods: ['GET'])]
    public function unmatched(): Response
    {
        $actor = $this->requirePermission('PLATFORM.PAYMENT.VIEW');
        $item = $this->bank->unmatched((int) $this->param('id')) ?? throw $this->notFound('That deposit is not on the list.');
        $reference = trim((string) $this->request()->query->get('reference', ''));
        $canManage = $actor->hasPermission('PLATFORM.PAYMENT.MANAGE') && $actor->hasPermission('PLATFORM.PAYMENT.RECONCILE');

        return $this->render('admin-unmatched-item', ['title' => 'Unmatched deposit ' . $item['id'], 'active_nav' => 'admin', 'item' => $item, 'can_manage' => $canManage,
            'reference' => $reference, 'match' => $item['state'] === 'open' && $canManage && $reference !== '' ? $this->bank->find($reference) : null,
            'today' => (new \DateTimeImmutable('now', new \DateTimeZone(date_default_timezone_get())))->format('Y-m-d')]);
    }

    #[Route('/admin/commerce/unmatched/{id}/match', name: 'admin_unmatched_match', requirements: ['id' => '[0-9]+'], methods: ['POST'])]
    public function match(): Response
    {
        $this->requireCsrf();
        $actor = $this->requirePermission('PLATFORM.PAYMENT.MANAGE');
        $id = (int) $this->param('id');
        $orderId = (int) $this->posted('order_id');

        return $this->handle(function () use ($actor, $id, $orderId): void {
            $this->bank->match($actor, $id, $orderId);
            $this->flash('success', 'The deposit is matched: it is recorded as this order’s EFT payment.');
            $this->redirect('/admin/commerce/orders/' . $orderId);
        }, '/admin/commerce/unmatched/' . $id);
    }

    #[Route('/admin/commerce/unmatched/{id}/returned', name: 'admin_unmatched_returned', requirements: ['id' => '[0-9]+'], methods: ['POST'])]
    public function returned(): Response
    {
        $this->requireCsrf();
        $actor = $this->requirePermission('PLATFORM.PAYMENT.MANAGE');
        $id = (int) $this->param('id');

        return $this->handle(function () use ($actor, $id): void {
            $this->bank->returned($actor, $id, $this->posted('returned_on'), $this->posted('return_reference'), $this->posted('note'));
            $this->flash('success', 'Recorded as paid back to the sender. It is no longer on the list.');
            $this->redirect('/admin/commerce/unmatched/' . $id);
        }, '/admin/commerce/unmatched/' . $id);
    }

    /** Record EFT Payment again with what was posted, so a refused form keeps what ADMIN typed. */
    private function statementHref(): string
    {
        $query = [];
        foreach (self::STATEMENT as $field) $query[$field] = $this->posted($field);

        return '/admin/commerce/eft?' . http_build_query($query);
    }
}
