declare(strict_types=1);

namespace CattoLearning\Commerce\Http;

use CattoLearning\Auth\AuthService;
use CattoLearning\Commerce\Application\PaymentService;
use CattoLearning\Commerce\Infrastructure\Payment\StitchPaymentGateway;
use CattoLearning\Support\Address\OrderAddress;
use CattoLearning\Http\Controller\BaseController;
use CattoLearning\View\ThemeRenderer;
use Omnipay\Common\Exception\InvalidRequestException;
use Symfony\Component\HttpFoundation\JsonResponse;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;
use Throwable;

final class StitchController extends BaseController
{
    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly PaymentService $payments,
        private readonly StitchPaymentGateway $stitch,
        private readonly \CattoLearning\Commerce\Application\StitchDashboard $dashboard,
    ) {
        parent::__construct($auth, $view, $requests);
    }

    #[Route(StitchPaymentGateway::RETURN_PATH, name: 'commerce_stitch_return', methods: ['GET'])]
    public function returned(): Response
    {
        $reference = (string) $this->request()->query->get('reference', '');
        try {
            $found = $this->payments->cardReturn($reference);
        } catch (Throwable) {
            $found = null;
        }
        if ($found === null) {
            $this->flash('warning', 'Stitch sent you back without an order we know. Your orders are listed here; a payment Stitch confirms shows on its order.');
            $this->redirect('/account/orders');
        }
        match ($found['state']) {
            'paid' => $this->flash('success', 'Thank you: Stitch confirmed your card payment. Your receipt is on your order and in your email.'),
            // Stitch's docs do not say whether a buyer who cancels on its page is sent back here, so the words fit both.
            'pending' => $this->flash('info', 'Stitch has not confirmed a card payment yet. If you paid, it shows here as soon as Stitch confirms it; if you did not finish paying, you can pay from this page.'),
            default => $this->flash('warning', 'The card payment was not completed. You can try again, or choose EFT.'),
        };
        $this->redirect(OrderAddress::buyer($found['order']));
    }

    /**
     * Administration > Credits & Orders > Stitch (owner, 2026-11-11): the Stitch account as Stitch's records give it, and which of
     * them are this site's. The list and the period change the page in place, the address following.
     */
    #[Route('/admin/commerce/stitch', name: 'admin_commerce_stitch', methods: ['GET'])]
    public function dashboard(): Response
    {
        $this->requirePermission('PLATFORM.PAYMENT.VIEW');
        $query = $this->request()->query;

        return $this->render('admin-stitch', ['title' => 'Stitch', 'active_nav' => 'admin',
            'stitch' => $this->dashboard->view((string) $query->get('list', 'links'), (string) $query->get('period', '30d'), (string) $query->get('cursor', ''))]);
    }

    #[Route(StitchPaymentGateway::WEBHOOK_PATH, name: 'commerce_stitch_webhook', methods: ['POST'])]
    public function webhook(): Response
    {
        try {
            $paid = $this->stitch->notification();
            if ($paid === null) {
                return new JsonResponse(['ok' => true, 'recorded' => false]);
            }

            return new JsonResponse(['ok' => true, 'recorded' => $this->payments->cardPaid($paid)]);
        } catch (InvalidRequestException $refused) {
            return new JsonResponse(['error' => $refused->getMessage()], 400);
        } catch (Throwable) {
            // Stitch retries anything but a 2xx for about a day: a failure here is worth another delivery.
            return new JsonResponse(['error' => 'The payment could not be recorded.'], 500);
        }
    }
}
