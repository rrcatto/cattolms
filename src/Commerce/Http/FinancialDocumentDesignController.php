declare(strict_types=1);

namespace CattoLearning\Commerce\Http;

use CattoLearning\Auth\AuthService;
use CattoLearning\Commerce\Document\FinancialDocumentDesign;
use CattoLearning\Commerce\Document\FinancialDocumentDesignService;
use CattoLearning\Commerce\Document\FinancialDocumentSamples;
use CattoLearning\Document\DocumentType;
use CattoLearning\Http\Controller\BaseController;
use CattoLearning\View\ThemeRenderer;
use InvalidArgumentException;
use Symfony\Component\HttpFoundation\RequestStack;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Routing\Attribute\Route;

final class FinancialDocumentDesignController extends BaseController
{
    private const BASE = '/admin/commerce/documents';

    public function __construct(
        AuthService $auth,
        ThemeRenderer $view,
        RequestStack $requests,
        private readonly FinancialDocumentDesignService $designs,
    ) {
        parent::__construct($auth, $view, $requests);
    }

    #[Route('/admin/commerce/documents', name: 'admin_financial_documents', methods: ['GET'])]
    public function edit(): Response
    {
        $this->requirePermission('PLATFORM.DOCUMENT.VIEW');
        [$type, $sample] = $this->choice($this->request()->query->all());
        return $this->editor($this->designs->design(), [], $type, $sample);
    }

    #[Route('/admin/commerce/documents', name: 'admin_financial_documents_save', methods: ['POST'])]
    public function save(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.DOCUMENT.MANAGE');
        [$type, $sample] = $this->choice($_POST);
        $saved = $this->designs->save($_POST, $_FILES, $user->id);
        if ($saved['errors'] !== []) {
            return $this->editor($saved['design'], $saved['errors'], $type, $sample, 422);
        }
        $this->flash('success', $saved['changed'] === []
            ? 'Nothing in the design changed.'
            : 'The design was saved. Invoices, receipts and credit notes issued from now on use it; documents already issued keep the design they were issued with.');
        $this->redirect(self::BASE . '?document=' . $type->value . '&sample=' . $sample);
    }

    /** The posted form drawn as the chosen document for the chosen sample order, without saving anything. */
    #[Route('/admin/commerce/documents/preview.pdf', name: 'admin_financial_documents_preview', methods: ['POST'])]
    public function preview(): Response
    {
        $this->requireCsrf();
        $user = $this->requirePermission('PLATFORM.DOCUMENT.MANAGE');
        [$type, $sample] = $this->choice($_POST);
        $form = $this->designs->fromForm($_POST, $_FILES, $user->id);
        $errors = [...$form['errors'], ...$form['design']->problems()];
        if ($errors !== []) {
            return $this->problems($errors);
        }
        return $this->pdf($form['design'], $type, $sample);
    }

    /** The saved design drawn as a document for a sample order. */
    #[Route('/admin/commerce/documents/{document}/preview.pdf', name: 'admin_financial_documents_saved_preview', requirements: ['document' => 'invoice|receipt|credit_note'], methods: ['GET'])]
    public function savedPreview(): Response
    {
        $this->requirePermission('PLATFORM.DOCUMENT.VIEW');
        [$type, $sample] = $this->choice(['document' => $this->param('document'), 'sample' => $this->request()->query->get('sample', 'learner')]);
        return $this->pdf($this->designs->design(), $type, $sample);
    }

    /** A small picture of the stored logo, for the form. */
    #[Route('/admin/commerce/documents/pictures/{sha}.png', name: 'admin_financial_documents_picture', requirements: ['sha' => '[0-9a-f]{64}'], methods: ['GET'])]
    public function picture(): Response
    {
        $this->requirePermission('PLATFORM.DOCUMENT.VIEW');
        $thumbnail = $this->designs->thumbnail((string) $this->param('sha'));
        if ($thumbnail === null) {
            throw $this->notFound('That picture does not exist.');
        }
        return new Response($thumbnail['bytes'], 200, ['Content-Type' => $thumbnail['mime'], 'Cache-Control' => 'private, max-age=31536000, immutable', 'X-Content-Type-Options' => 'nosniff']);
    }

    /** @param list<string> $errors */
    private function editor(FinancialDocumentDesign $design, array $errors, DocumentType $type, string $sample, int $status = 200): Response
    {
        $user = $this->requireUser();
        $summary = $this->designs->summary();
        $documents = [];
        foreach (FinancialDocumentDesign::types() as $choice) {
            $documents[] = ['value' => $choice->value, 'label' => $choice->label()];
        }
        $samples = [];
        foreach (FinancialDocumentSamples::SAMPLES as $key => $label) {
            $samples[] = ['value' => $key, 'label' => $label, 'documents' => array_map(static fn(DocumentType $type): string => $type->value, FinancialDocumentSamples::documents($key))];
        }
        $typefaces = [];
        foreach (FinancialDocumentDesign::TYPEFACES as $key => [$label]) {
            $typefaces[$key] = $label;
        }
        $notes = [];
        foreach (FinancialDocumentDesign::types() as $choice) {
            $notes[] = ['type' => $choice->value, 'label' => $choice->label() . ' note', 'value' => $design->note($choice)];
        }
        return $this->render('admin-financial-documents', [
            'title' => 'Financial documents',
            'design' => $design->toArray(),
            'documents' => $documents,
            'document' => $type->value,
            'samples' => $samples,
            'sample' => $sample,
            'typefaces' => $typefaces,
            'notes' => $notes,
            'note_limit' => FinancialDocumentDesign::NOTE_LIMIT,
            'logo' => $design->logo === null ? null : self::BASE . '/pictures/' . $design->logo->sha . '.png',
            'errors' => $errors,
            'preview_src' => $errors === [] ? self::BASE . '/' . $type->value . '/preview.pdf?sample=' . $sample : '',
            'saved' => $summary,
            'can_manage' => $user->hasPermission('PLATFORM.DOCUMENT.MANAGE'),
        ], $status);
    }

    /**
     * Which document and sample order to show; a free order has only its invoice.
     *
     * @param array<string,mixed> $input
     * @return array{0:DocumentType,1:string}
     */
    private function choice(array $input): array
    {
        $type = DocumentType::tryFrom((string) ($input['document'] ?? 'invoice'));
        $type = $type !== null && in_array($type, FinancialDocumentDesign::types(), true) ? $type : DocumentType::Invoice;
        $sample = (string) ($input['sample'] ?? 'learner');
        $sample = isset(FinancialDocumentSamples::SAMPLES[$sample]) ? $sample : 'learner';
        if (!in_array($type, FinancialDocumentSamples::documents($sample), true)) {
            $type = DocumentType::Invoice;
        }
        return [$type, $sample];
    }

    private function pdf(FinancialDocumentDesign $design, DocumentType $type, string $sample): Response
    {
        try {
            $bytes = $this->designs->previewPdf($design, $type, $sample);
        } catch (InvalidArgumentException $refused) {
            return $this->problems([$refused->getMessage()]);
        }
        return new Response($bytes, 200, [
            'Content-Type' => 'application/pdf',
            'Content-Disposition' => 'inline; filename="' . $type->value . '-preview.pdf"',
            'X-Content-Type-Options' => 'nosniff',
            'Cache-Control' => 'private, no-store',
        ]);
    }

    /**
     * A plain page in the preview frame listing what stops the document being drawn.
     *
     * @param list<string> $errors
     */
    private function problems(array $errors): Response
    {
        $items = implode('', array_map(static fn(string $error): string => '<li>' . htmlspecialchars($error, ENT_QUOTES) . '</li>', $errors));
        return new Response('<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>Preview</title>'
            . '<style>body{font:16px/1.5 system-ui,sans-serif;margin:1.5rem;color:#1c2430}h1{font-size:1.1rem}</style></head><body>'
            . '<h1>The preview cannot be drawn yet</h1><ul>' . $items . '</ul></body></html>', 422, ['Content-Type' => 'text/html; charset=UTF-8', 'Cache-Control' => 'no-store']);
    }
}
