Date time: 2026/10/08 SAST

Version: 0.8.9

Description:
Administration → Commerce → Financial Documents: one form for the design of invoices, receipts and
credit notes - a logo, a typeface, an accent colour and each document's closing note - under a
preview that is the PDF the chosen document will be, for a made-up sample order. Save keeps a new
version of each document's template, which documents issued from then on are drawn in; documents
already issued keep theirs. Nothing about templates, HTML or versions is shown here.

Changelog:
2026/10/08 SAST
- Created for financial documents on the document template engine (Phase K), in the manner of the
  certificate designs (owner's choice, 2026/10/08: a design form, not a template editor).
