namespace CattoLearning\Commerce\Http;

use RuntimeException;

final class EftForm
{
    /** 123.45 as 12345 cents. */
    public static function amount(string $value): int
    {
        $value = trim($value);
        if (!preg_match('/^\d+(?:\.\d{1,2})?$/', $value) || strlen($value) > 16) throw new RuntimeException('Enter an amount in rands and cents, such as 123.45.');
        [$whole, $fraction] = array_pad(explode('.', $value, 2), 2, '');

        return ((int) $whole) * 100 + (int) str_pad($fraction, 2, '0');
    }

    /**
     * The moment money arrived, from a calendar date and an optional time. With no time: a minute ago
     * when the day is today, otherwise midday.
     */
    public static function receivedAt(string $date, string $time): string
    {
        if (preg_match('/^\d{4}-\d{2}-\d{2}$/', $date) !== 1) throw new RuntimeException('Choose the date the money reached the bank.');
        $now = new \DateTimeImmutable('now', new \DateTimeZone(date_default_timezone_get()));
        $time = trim($time) !== '' ? trim($time) : ($date === $now->format('Y-m-d') ? $now->modify('-1 minute')->format('H:i') : '12:00');
        if (preg_match('/^\d{2}:\d{2}$/', $time) !== 1) throw new RuntimeException('Enter the time as hours and minutes, such as 14:30, or leave it empty.');
        try {
            return (new \DateTimeImmutable($date . ' ' . $time, new \DateTimeZone(date_default_timezone_get())))->format('Y-m-d\TH:iP');
        } catch (\Exception) {
            throw new RuntimeException('Choose the date the money reached the bank.');
        }
    }
