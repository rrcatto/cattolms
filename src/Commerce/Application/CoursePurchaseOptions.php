declare(strict_types=1);

namespace CattoLearning\Commerce\Application;

use CattoLearning\Auth\CurrentUser;
use CattoLearning\Commerce\Infrastructure\CommerceRepository;
use CattoLearning\Course\CourseService;

final class CoursePurchaseOptions
{
    public function __construct(
        private readonly CourseService $courses,
        private readonly CommerceRepository $records,
    ) {
    }

    /**
     * @param array<string,mixed> $course at least id, slug and status
     * @param list<array<string,mixed>>|null $variants the course's active prices when already loaded
     * @param string $returnTo the page to come back to after signing in
     * @return array<string,mixed>
     */
    public function for(array $course, ?CurrentUser $viewer, string $returnTo, ?array $variants = null): array
    {
        $courseId = (int) $course['id'];
        $slug = (string) $course['slug'];
        $options = [
            'state' => 'unavailable',
            'course_id' => $courseId,
            'course_slug' => $slug,
            'continue' => null,
            'variants' => [],
            'default_variant' => null,
            'can_request' => false,
            'sign_in_href' => $viewer === null ? '/login?return=' . rawurlencode($returnTo) : '',
            'orders_href' => '/account/orders',
        ];
        if ($viewer !== null) {
            $enrolment = $this->courses->enrolmentForUser($viewer->id, $courseId);
            if ($enrolment !== null) {
                $status = (string) ($enrolment['status'] ?? '');
                $label = $status === 'completed' ? 'Open course' : (empty($enrolment['started_at']) ? 'Start course' : 'Continue course');
                return ['state' => 'owned', 'continue' => ['label' => $label, 'href' => '/learn/' . $slug]] + $options;
            }
            if ($this->records->hasPayableCourse($viewer->id, $courseId)) {
                return ['state' => 'ordered'] + $options;
            }
        }
        if ((string) ($course['status'] ?? '') !== 'published') {
            return $options;
        }
        $variants ??= $this->courses->activePriceVariants($courseId);
        if ($variants === []) {
            return $options;
        }
        $default = null;
        foreach ($variants as $variant) {
            if ((bool) ($variant['is_default'] ?? false)) {
                $default = $variant;
                break;
            }
        }
        return [
            'state' => 'available',
            'variants' => $variants,
            'default_variant' => $default ?? $variants[0],
            'can_request' => $viewer !== null && $viewer->hasPermission('CATALOGUE.COURSE.REQUEST'),
        ] + $options;
    }
}
