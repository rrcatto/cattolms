            ['Orders cancelled at their deadline', 'orders_cancelled', false], ['Orders refunded', 'orders_refunded', false], ['New accounts', 'new_accounts', false]] as [$label, $key, $money]) {
            $cells = [new StringCell($label), $money ? $rand($m[$key]) : $count($m[$key]), $money ? $rand($b[$key]) : $count($b[$key]), $change($m[$key], $b[$key])];
            if ($year !== null && $y !== null) $cells = [...$cells, $money ? $rand($y[$key]) : $count($y[$key]), $change($m[$key], $y[$key])];
            $writer->addRow(new Row($cells));
        }
        $writer->addRow(new Row([new StringCell('Promotions given'), $rand($promotions)]));
        $writer->addRow(new Row([new StringCell('Wallet credit used to pay'), $rand((int) $report['wallet_paid']['minor'])]));
        $writer->addRow(new Row([]));
        $writer->addRow(new Row([new StringCell($report['no_sales'] ? 'No sales in ' . $report['month']['label'] . '.' : 'Counted from the site\'s money records. VAT is not charged on this site.')]));
        if ($report['no_sales']) $writer->addRow(new Row([new StringCell('Counted from the site\'s money records. VAT is not charged on this site.')]));

        // Money in: every payment received in the month, as the Money Ledger lists them.
        $sheet = $writer->addNewSheetAndMakeItCurrent();
        $sheet->setName('Money in');
        $sheet->setColumnWidth(18, 1);
        $sheet->setColumnWidth(14, 2, 5, 6);
        $sheet->setColumnWidth(26, 3, 4);
        $writer->addRow($headings('Date', 'Order', 'Account reference', 'Account', 'Method', 'Amount'));
        foreach ($report['payment_lines'] as $line) {
            $writer->addRow(new Row([$when($line['at'], $stamp), $text($line['order']), $text($line['reference']), $text($line['account']), $text($line['method']), $rand($line['minor'])]));
        }

        // Sales: each course and bundle bought, with how many, before promotions, the promotions and what was paid.
        $sheet = $writer->addNewSheetAndMakeItCurrent();
