    /**
     * The Excel file's bytes.
     *
     * @param array<string,mixed> $report
     */
    public function excel(array $report): string
    {
        $path = tempnam(sys_get_temp_dir(), 'money-report-');
        if ($path === false) throw new RuntimeException('The Excel file could not be started.');
        try {
            $by = $this->owner->value('trading_name');
            $writer = new Writer(new Options(properties: new Properties(title: 'Money report, ' . $report['month']['label'], application: $by, creator: $by, lastModifiedBy: $by)));
            $writer->openToFile($path);
            $this->write($writer, $report);
            $writer->close();
            $bytes = file_get_contents($path);
            if ($bytes === false || $bytes === '') throw new RuntimeException('The Excel file could not be made.');

            return $bytes;
        } finally {
            @unlink($path);
        }
    }

    /** @param array<string,mixed> $report */
    private function write(Writer $writer, array $report): void
    {
        $bold = (new Style())->withFontBold(true);
        $heading = (new Style())->withFontBold(true)->withBackgroundColor('F2F2F2');
        $amount = (new Style())->withFormat(self::AMOUNT_FORMAT);
        $whole = (new Style())->withFormat('#,##0');
        $share = (new Style())->withFormat('0%');
        $date = (new Style())->withFormat('yyyy-mm-dd');
        $stamp = (new Style())->withFormat('yyyy-mm-dd hh:mm');
        $text = static fn(string $value, ?Style $style = null): Cell => $value === '' ? new EmptyCell(null, $style) : new StringCell($value, $style);
        // Whole cents become rand and cents only here, in the cell: 1234550 cents is 12345.5.
        $rand = static fn(int $minor, ?Style $style = null): Cell => Cell::fromValue($minor / 100, $style ?? $amount);
        $count = static fn(int $value): Cell => Cell::fromValue($value, $whole);
        // An instant is kept as an ISO date and time in the site's time zone, and the cell shows that local date and time.
        $when = static fn(string $at, Style $style): Cell => Cell::fromValue(new DateTimeImmutable($style === $date ? substr($at, 0, 10) : $at), $style);
        $headings = static fn(string ...$labels): Row => new Row(array_map(static fn(string $label): Cell => new StringCell($label, $heading), $labels));

        $m = $report['measures'];
        $b = $report['measures_before'];
        $y = $report['measures_year'];
        $year = $report['year'];
        $change = static fn(int $now, int $was): Cell => $was === 0 ? new EmptyCell(null, $share) : Cell::fromValue(($now - $was) / $was, $share);

        // Summary: the figures, this month beside the month before and, once there is a year of records, the same month last year.
        $sheet = $writer->getCurrentSheet();
        $sheet->setName('Summary');
        $sheet->setColumnWidth(34, 1);
        $sheet->setColumnWidth(18, 2, 3, 4, 5, 6);
        $writer->addRow(new Row([new StringCell('Money report, ' . $report['month']['label'], $bold)]));
        $writer->addRow(new Row([new StringCell(trim($this->owner->value('trading_name') . ', made ' . $report['made'], ', '))]));
        if ($this->site->isDemo()) $writer->addRow(new Row([new StringCell($this->site->heading() . ': ' . $this->site->notice())]));
        $writer->addRow(new Row([]));
        $columns = ['Figure', $report['month']['label'], $report['before']['label'], 'Change'];
        if ($year !== null) $columns = [...$columns, $year['label'], 'Change'];
        $writer->addRow($headings(...$columns));
        $promotions = (int) $report['sold']['promotions_minor'];
        foreach ([['Money in', 'money_in', true], ['Refunds and payouts', 'refunds', true], ['Card fees', 'card_fees', true], ['What is left', 'left', true],
