        $sheet->setColumnWidth(16, 2, 3, 4, 5, 6);
        $writer->addRow($headings('What was bought', 'Kind', 'Sold', 'Before promotions', 'Promotions', 'Paid'));
        foreach ($report['sales'] as $line) {
            $writer->addRow(new Row([$text($line['title']), $text($line['kind']), $count($line['sold']), $rand($line['before_minor']), $rand($line['promotions_minor']), $rand($line['paid_minor'])]));
        }

        // Orders: every order placed in the month and where it stands now.
        $sheet = $writer->addNewSheetAndMakeItCurrent();
        $sheet->setName('Orders');
        $sheet->setColumnWidth(18, 1);
        $sheet->setColumnWidth(14, 2, 5, 6);
