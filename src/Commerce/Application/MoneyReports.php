declare(strict_types=1);

namespace CattoLearning\Commerce\Application;

use CattoLearning\Commerce\Infrastructure\MoneyReportRepository;
use CattoLearning\Infrastructure\Persistence\AdministrationRepository;
use CattoPHP\Foundation\AccountReference;
use CattoLearning\Support\Address\OrderAddress;
use CattoLearning\Support\Money;
use DateTimeImmutable;
use DateTimeZone;
use Symfony\Component\Clock\ClockInterface;

final class MoneyReports
{
    /** The months a report is offered for, at most: ten years. */
    private const MONTHS_OFFERED = 120;

    public function __construct(
        private readonly MoneyRecords $money,
        private readonly AdministrationRepository $administration,
        private readonly MoneyReportRepository $reports,
        private readonly ClockInterface $clock,
    ) {
    }

    private static function zone(): DateTimeZone
    {
        return new DateTimeZone(date_default_timezone_get());
    }

    /** The first day of this month, in the site's time zone. */
    private function thisMonth(): DateTimeImmutable
    {
        return DateTimeImmutable::createFromInterface($this->clock->now())->setTimezone(self::zone())->modify('first day of this month')->setTime(0, 0);
    }

    /** The first day of the first month the site has records of, never later than last month. */
    private function firstMonth(): DateTimeImmutable
    {
        $last = $this->thisMonth()->modify('-1 month');
        $first = $this->reports->firstMonth(self::zone()->getName());
        $first = $first === null ? $last : new DateTimeImmutable($first . ' 00:00:00', self::zone());

        return max(min($first, $last), $this->thisMonth()->modify('-' . (self::MONTHS_OFFERED - 1) . ' months'));
    }

    /**
     * The months a report can be made for, newest first: this month so far, then every month back to the first the site has
     * records of.
     *
     * @return list<array{key:string,label:string}>
     */
    public function months(): array
    {
        $months = [];
        $first = $this->firstMonth();
        for ($at = $this->thisMonth(); $at >= $first; $at = $at->modify('-1 month')) {
            $months[] = ['key' => $at->format('Y-m'), 'label' => $at->format('F Y') . ($at == $this->thisMonth() ? ', so far' : '')];
        }

        return $months;
    }

    /** Last month, the one a report is usually wanted for. */
    public function lastMonth(): string
    {
        return $this->thisMonth()->modify('-1 month')->format('Y-m');
    }

    /** Whether a report can be made for a month ('2026-10'): one of months(). */
    public function offers(string $key): bool
    {
        return in_array($key, array_column($this->months(), 'key'), true);
    }

    /**
     * A month's days and the instants they bound, for the SQL and for the lists' addresses.
     *
     * @return array{key:string,label:string,name:string,from:string,to:string,from_at:string,to_before:string,so_far:bool}
     */
    private function span(DateTimeImmutable $first): array
    {
        $first = $first->modify('first day of this month')->setTime(0, 0);

        return ['key' => $first->format('Y-m'), 'label' => $first->format('F Y'), 'name' => $first->format('F'),
            'from' => $first->format('Y-m-d'), 'to' => $first->modify('last day of this month')->format('Y-m-d'),
            'from_at' => $first->format(DATE_ATOM), 'to_before' => $first->modify('first day of next month')->format(DATE_ATOM),
            'so_far' => $first == $this->thisMonth()];
    }

    private static function money(int $minor): string
    {
        return ($minor < 0 ? '−' : '') . Money::ofMinorUnits(abs($minor), Money::platformCurrency())->format();
    }

    /** A whole percentage of a part of a whole, rounded half away from nought, in whole numbers only. */
    private static function percent(int $part, int $whole): int
    {
        if ($whole === 0) return 0;
        $sign = ($part < 0) !== ($whole < 0) ? -1 : 1;

        return $sign * intdiv(200 * abs($part) + abs($whole), 2 * abs($whole));
    }

    /**
     * What one month's figures add up, each by the code of the list it opens.
     *
     * @param array{from:string,to:string,from_at:string,to_before:string} $span
     * @return array<string,int>
     */
    private function measures(array $span): array
    {
        $q = ['from' => $span['from'], 'to' => $span['to']];
        $in = $this->money->ledgerTotalsFor($q + ['money' => 'in']);
        $refunds = $this->money->ledgerTotalsFor($q + ['kind' => 'refund_paid']);
        $fees = $this->money->ledgerTotalsFor($q + ['kind' => 'card_fees']);
        $all = $this->money->ledgerTotalsFor($q);
        $card = $this->money->ledgerTotalsFor($q + ['kind' => 'payment_received', 'method' => 'stitch']);

        return [
            'money_in' => $in['money_in'], 'payments' => $in['entries'],
            'refunds' => $refunds['money_out'], 'refunds_count' => $refunds['entries'],
            'card_fees' => $fees['money_out'], 'card_money' => $card['money_in'],
            'left' => $all['money_in'] - $all['money_out'],
            'orders_placed' => $this->money->orderCountFor($q),
            'orders_paid' => $this->money->orderCountFor($q + ['state' => 'paid_in_full']),
            'orders_to_pay' => $this->money->orderCountFor($q + ['state' => 'to_pay']),
            'orders_cancelled' => $this->money->orderCountFor($q + ['state' => 'cancelled']),
            'orders_refunded' => $this->money->orderCountFor($q + ['state' => 'refunded_any']),
            'new_accounts' => $this->administration->peopleCount('', $span['from_at'], $span['to_before']),
        ];
    }

    /**
     * The address of a list for a month: the Money Ledger, Orders & Payments or People, with that month's dates filled in.
     *
     * @param array{from:string,to:string} $span
     * @param array<string,string> $extra
     */
    private static function href(string $path, array $span, array $extra = []): string
    {
        $dates = $path === '/admin/people' ? ['people_from' => $span['from'], 'people_to' => $span['to']] : ['from' => $span['from'], 'to' => $span['to']];

        return $path . '?' . http_build_query($dates + $extra);
    }

    /**
     * A figure set against another month: "+18% on September (R 41 200,00)".
     *
     * @param array{label:string,name:string} $then
     */
    private static function against(int $now, int $was, array $then, bool $sameYear, bool $money): string
    {
        $name = $sameYear ? $then['name'] : $then['label'];
        if ($was === 0) return $now === 0 ? 'None in ' . $name . ' either' : 'None in ' . $name;
        $change = self::percent($now - $was, $was);
        $words = $change === 0 ? 'The same as ' . $name : ($change > 0 ? '+' : '−') . abs($change) . '% on ' . $name;

        return $words . ' (' . ($money ? self::money($was) : number_format($was)) . ')';
    }

    /**
     * One month's report, the same for the page, the PDF, the Excel file, the email and the Telegram line.
     *
     * @return array<string,mixed>
     */
    public function report(string $key): array
    {
        $month = $this->span(new DateTimeImmutable($key . '-01 00:00:00', self::zone()));
        $first = new DateTimeImmutable($month['from'] . ' 00:00:00', self::zone());
        $before = $this->span($first->modify('-1 month'));
        // The same month last year, once the site has a year of records.
        $yearAgo = $first->modify('-1 year');
        $year = $this->firstMonth() <= $yearAgo ? $this->span($yearAgo) : null;
        $now = $this->measures($month);
        $then = $this->measures($before);
        $lastYear = $year === null ? null : $this->measures($year);
        $q = ['from' => $month['from'], 'to' => $month['to']];

        $sameYear = substr($before['from'], 0, 4) === substr($month['from'], 0, 4);
        $compare = static function (string $measure, bool $money) use ($now, $then, $lastYear, $before, $year, $sameYear): array {
            $notes = [self::against($now[$measure], $then[$measure], $before, $sameYear, $money)];
            if ($year !== null && $lastYear !== null) $notes[] = self::against($now[$measure], $lastYear[$measure], $year, false, $money);

            return $notes;
        };
        $note = static fn(string $context, array $changes): string => implode(' · ', array_values(array_filter([$context, ...$changes], static fn(string $part): bool => $part !== '')));
        $plural = static fn(int $count, string $one, string $many): string => number_format($count) . ' ' . ($count === 1 ? $one : $many);
        $cardShare = $now['card_money'] > 0 ? self::percent($now['card_fees'], $now['card_money']) . '% of ' . self::money($now['card_money']) . ' by card' : 'No card payments';

        $figures = [
            ['key' => 'money_in', 'label' => 'Money in', 'minor' => $now['money_in'], 'context' => $plural($now['payments'], 'payment', 'payments'),
                'changes' => $compare('money_in', true), 'href' => self::href('/admin/commerce/ledger', $month, ['money' => 'in']), 'icon' => 'figure-money-in'],
            ['key' => 'refunds', 'label' => 'Refunds and payouts', 'minor' => $now['refunds'], 'context' => $now['refunds_count'] === 0 ? 'Nothing paid back' : $plural($now['refunds_count'], 'refund', 'refunds') . ' paid back',
                'changes' => $compare('refunds', true), 'href' => self::href('/admin/commerce/ledger', $month, ['kind' => 'refund_paid']), 'icon' => 'figure-refunds'],
            ['key' => 'card_fees', 'label' => 'Card fees', 'minor' => $now['card_fees'], 'context' => $cardShare,
                'changes' => $compare('card_fees', true), 'href' => self::href('/admin/commerce/ledger', $month, ['kind' => 'card_fees']), 'icon' => 'figure-fees'],
            ['key' => 'left', 'label' => 'What is left', 'minor' => $now['left'], 'context' => 'Money in less refunds, payouts and card fees',
                'changes' => $compare('left', true), 'href' => self::href('/admin/commerce/ledger', $month), 'icon' => 'figure-net'],
            ['key' => 'orders_paid', 'label' => 'Orders paid', 'count' => $now['orders_paid'], 'context' => 'of ' . number_format($now['orders_placed']) . ' placed, ' . number_format($now['orders_cancelled']) . ' cancelled unpaid',
                'changes' => $compare('orders_paid', false), 'href' => self::href('/admin/commerce/orders', $month, ['state' => 'paid_in_full']), 'icon' => 'figure-fulfilled'],
            ['key' => 'new_accounts', 'label' => 'New accounts', 'count' => $now['new_accounts'], 'context' => '',
                'changes' => $compare('new_accounts', false), 'href' => self::href('/admin/people', $month), 'icon' => 'figure-people'],
        ];
        foreach ($figures as $index => $figure) {
            $money = isset($figure['minor']);
            $figures[$index] += ['value' => $money ? self::money((int) $figure['minor']) : number_format((int) $figure['count']), 'note' => $note($figure['context'], $figure['changes']), 'size' => $money ? 'small' : 'normal'];
        }

        // Money in by method, each opening the Money Ledger's payments by that method; wallet credit beside it, not in it.
        $methods = [];
        foreach (MoneyRecords::METHODS as $method => $label) {
            $totals = $this->money->ledgerTotalsFor($q + ['kind' => 'payment_received', 'method' => $method]);
            if ($totals['entries'] === 0) continue;
            $methods[] = ['method' => $method, 'label' => $label, 'payments' => $totals['entries'], 'minor' => $totals['money_in'], 'amount' => self::money($totals['money_in']),
                'href' => self::href('/admin/commerce/ledger', $month, ['kind' => 'payment_received', 'method' => $method])];
        }
        usort($methods, static fn(array $a, array $b): int => [$b['minor'], $a['label']] <=> [$a['minor'], $b['label']]);
        $walletPaid = $this->money->ledgerTotalsFor($q + ['kind' => 'wallet_payment']);

        $orders = [];
        foreach ([['placed', 'Placed', [], 'orders_placed'], ['paid_in_full', 'Paid in full', ['state' => 'paid_in_full'], 'orders_paid'], ['to_pay', 'Still to be paid', ['state' => 'to_pay'], 'orders_to_pay'],
            ['cancelled', 'Cancelled at their deadline', ['state' => 'cancelled'], 'orders_cancelled'], ['refunded', 'Refunded, in full or in part', ['state' => 'refunded_any'], 'orders_refunded']] as [$k, $label, $filter, $measure]) {
            $orders[] = ['key' => $k, 'label' => $label, 'count' => $now[$measure], 'href' => self::href('/admin/commerce/orders', $month, $filter)];
        }

        $paidStates = MoneyRecords::ORDER_STATE_GROUPS['paid_in_full']['states'];
        $sales = [];
        foreach ($this->reports->sales($month['from_at'], $month['to_before'], $paidStates) as $row) {
            $kind = match ($row['product_type']) { 'bundle' => 'Bundle', 'company_credit' => 'Course credits', 'bundle_credit' => 'Bundle credits', default => 'Course' };
            $sales[] = $row + ['kind' => $kind, 'name' => $row['title'] . ($kind === 'Course' ? '' : ' (' . strtolower($kind) . ')'),
                'before' => self::money($row['before_minor']), 'promotions' => $row['promotions_minor'] === 0 ? '' : self::money($row['promotions_minor']), 'paid' => self::money($row['paid_minor'])];
        }
        $sold = ['sold' => array_sum(array_column($sales, 'sold')), 'before_minor' => array_sum(array_column($sales, 'before_minor')),
            'promotions_minor' => array_sum(array_column($sales, 'promotions_minor')), 'paid_minor' => array_sum(array_column($sales, 'paid_minor'))];
        $sold += ['before' => self::money($sold['before_minor']), 'promotions' => self::money($sold['promotions_minor']), 'paid' => self::money($sold['paid_minor']),
            'promoted_orders' => $this->reports->promotedOrders($month['from_at'], $month['to_before'], $paidStates)];

        // Refunds and payouts: money paid back, then refunds given as wallet credit, which is no money out.
        $refunds = [];
        foreach ([...$this->money->ledgerEntriesFor($q + ['kind' => 'refund_paid']), ...$this->money->ledgerEntriesFor($q + ['kind' => 'refund_to_wallet'])] as $line) {
            $back = $line['kind'] === 'refund_paid';
            $refunds[] = ['at' => self::local((string) $line['occurred_at']), 'id' => (int) $line['id'], 'date' => self::day((string) $line['occurred_at']),
                'order' => $line['order_id'] === null ? '' : MoneyRecords::orderNumber((int) $line['order_id']), 'order_href' => $line['order_id'] === null ? '' : OrderAddress::admin((int) $line['order_id']),
                'how' => $back ? ((string) $line['method'] === 'stitch' ? 'Money back to the card' : 'Money back to a bank account') : 'As wallet credit, no money out',
                'money_back' => $back, 'minor' => (int) $line['amount_minor'], 'amount' => self::money((int) $line['amount_minor']), 'href' => '/admin/commerce/ledger/' . (int) $line['id']];
        }
        usort($refunds, static fn(array $a, array $b): int => [$a['at'], $a['id']] <=> [$b['at'], $b['id']]);
        $refundTotals = ['money_back_minor' => $now['refunds'], 'money_back' => self::money($now['refunds']),
            'wallet_minor' => array_sum(array_map(static fn(array $r): int => $r['money_back'] ? 0 : $r['minor'], $refunds))];
        $refundTotals['wallet'] = self::money($refundTotals['wallet_minor']);

        // Wallet credit in the month: what was used, given and expired, each counted as the Money Ledger counts its kind.
        $wallet = [];
        foreach ([['Credit used to pay', ['kind' => 'wallet_payment'], 'wallet_out'], ['Credit given back by refunds', ['kind' => 'refund_to_wallet'], 'wallet_in'],
            ['Overpayments credited', ['kind' => 'overpayment_to_wallet'], 'wallet_in'], ['Payments for cancelled orders credited', ['kind' => 'unfulfilled_payment_to_wallet'], 'wallet_in'],
            ['Credit returned from unpaid orders', ['kind' => 'wallet_payment_released'], 'wallet_in'], ['Credit expired', ['kind' => 'credit_expired'], 'wallet_out'],
            ['Corrections that added credit', ['kind' => 'correction', 'wallet' => 'in'], 'wallet_in'], ['Corrections that took credit', ['kind' => 'correction', 'wallet' => 'out'], 'wallet_out']] as [$label, $filter, $sum]) {
            $totals = $this->money->ledgerTotalsFor($q + $filter);
            $wallet[] = ['label' => $label, 'count' => $totals['entries'], 'minor' => $totals[$sum], 'amount' => self::money($totals[$sum])];
        }

        // Every payment in the month and every order placed in it, one row each, for the Excel file.
        $payments = array_map(static fn(array $line): array => ['at' => self::local((string) $line['occurred_at']), 'order' => $line['order_id'] === null ? '' : MoneyRecords::orderNumber((int) $line['order_id']),
            'reference' => (string) $line['account_reference'] === '' ? '' : AccountReference::format((string) $line['account_reference']), 'account' => (string) $line['account_name'],
            'method' => MoneyRecords::METHODS[(string) $line['method']] ?? (string) $line['method'], 'minor' => (int) $line['amount_minor']], $this->money->ledgerEntriesFor($q + ['money' => 'in']));
        $placed = array_map(static fn(array $row): array => ['at' => self::local((string) $row['placed_at']), 'order' => MoneyRecords::orderNumber((int) $row['id']),
            'buyer' => (string) ($row['company_name'] ?? '') !== '' ? (string) $row['company_name'] : (string) $row['purchaser_name'],
            'reference' => (string) ($row['account_reference'] ?? '') === '' ? '' : AccountReference::format((string) $row['account_reference']),
            'total_minor' => (int) $row['total_minor'], 'paid_minor' => (int) $row['paid_minor'], 'state' => $row['status']['label'] . ($row['status']['note'] !== '' ? ': ' . $row['status']['note'] : '')],
            $this->money->orderEntriesFor($q));

        return [
            'month' => $month, 'before' => $before, 'year' => $year, 'measures' => $now, 'measures_before' => $then, 'measures_year' => $lastYear,
            'figures' => $figures, 'by_method' => $methods, 'money_in' => self::money($now['money_in']), 'payments' => $now['payments'],
            'wallet_paid' => ['payments' => $walletPaid['entries'], 'minor' => $walletPaid['wallet_out'], 'amount' => self::money($walletPaid['wallet_out']), 'href' => self::href('/admin/commerce/ledger', $month, ['kind' => 'wallet_payment'])],
            'orders' => $orders, 'sales' => $sales, 'sold' => $sold, 'no_sales' => $sales === [],
            'refunds' => $refunds, 'refund_totals' => $refundTotals, 'wallet' => $wallet, 'payment_lines' => $payments, 'order_lines' => $placed,
            'card_fees' => self::money($now['card_fees']), 'left' => self::money($now['left']),
            'made_at' => DateTimeImmutable::createFromInterface($this->clock->now())->setTimezone(self::zone())->format(DATE_ATOM),
            'made' => DateTimeImmutable::createFromInterface($this->clock->now())->setTimezone(self::zone())->format('j F Y, H:i'),
        ];
    }

    /** An instant in the site's time zone, as an ISO date and time: what a report holds instead of an object. */
    private static function local(string $at): string
    {
        return (new DateTimeImmutable($at))->setTimezone(self::zone())->format(DATE_ATOM);
    }

    private static function day(string $at): string
    {
        return (new DateTimeImmutable($at))->setTimezone(self::zone())->format('j M Y');
    }

    /**
     * The one line the 1st sends by Telegram (owner, 2026-11-06): money in, what is left and the orders paid.
     *
     * @param array<string,mixed> $report
     */
    public static function summaryLine(array $report): string
    {
        $m = $report['measures'];
        $amount = static fn(int $minor): string => ($minor < 0 ? '-' : '') . \CattoLearning\OwnerMessages\OwnerMessages::amount(abs($minor), Money::platformCurrency());

        return 'Money report, ' . $report['month']['label'] . ': ' . ($report['no_sales'] ? 'no sales. ' : '') . 'Money in ' . $amount((int) $m['money_in'])
            . ', what is left ' . $amount((int) $m['left']) . ', ' . number_format((int) $m['orders_paid']) . ((int) $m['orders_paid'] === 1 ? ' order' : ' orders') . ' paid';
    }
}
