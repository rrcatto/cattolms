Money Reports (owner, 2026-11-06, the approved mockup REPORTS/money-reports-mockup/): each month's money in one report, on
the page at Administration > Credits & Orders > Money Reports, as a PDF and as an Excel file, and on the 1st by email and
Telegram (MoneyReportJob). One report for a month, built here, is what all of them show, so the page, the PDF and the Excel
file carry the same numbers.

Each figure is counted as the list it opens counts it, by the same code: money in, refunds and payouts, card fees and what
is left by the Money Ledger's totals for the month (MoneyRecords::ledgerTotalsFor), the orders by Orders & Payments' count
(orderCountFor) and the new accounts by People's (AdministrationRepository::peopleCount). Money is integer cents
throughout. Each figure is set against the month before and, once the site has a year of records, against the same month
last year.

What was sold is the lines of the orders placed in the month and paid in full, refunded later or not (MoneyRecords::
ORDER_STATE_GROUPS paid_in_full): how many, their prices before promotions, the promotions and what was paid, which adds up
to those orders' totals. Wallet credit used to pay is not money in: it came in before, or was given back by a refund.

