    /**
     * The Money Ledger's lines that its filters match, oldest first, with their totals and the filters in words.
     *
     * @param array<string,mixed> $query the Money Ledger page's own address
     * @return array<string,mixed>
     */
    public function ledger(array $query, string $format): array
    {
        $limit = self::limit($format);
        $filters = $this->money->ledgerFiltersShown($query);
        $rows = $this->money->ledgerEntriesFor($query, $limit + 1);
        if (count($rows) > $limit) {
            throw new RuntimeException($format === 'pdf'
                ? 'A PDF of the Money Ledger holds at most ' . number_format(self::PDF_LINES) . ' lines, and more than that match. Choose a shorter period, or download the Excel file.'
                : 'An Excel file of the Money Ledger holds at most ' . number_format(self::EXCEL_LINES) . ' lines, and more than that match. Choose a shorter period.');
        }
        $totals = $this->money->ledgerTotalsFor($query);
        $lines = [];
        foreach ($rows as $row) {
            $amount = (int) $row['amount_minor'];
            $lines[] = [
                'id' => (int) $row['id'],
                'at' => $this->local((string) $row['occurred_at']),
                'what' => MoneyRecords::ledgerSentence($row),
                'kind' => LedgerKind::label((string) $row['kind']),
                'reference' => (string) $row['account_reference'] === '' ? '' : AccountReference::format((string) $row['account_reference']),
                'account' => (string) $row['account_name'],
                'account_type' => $row['account_type'] === 'company' ? 'Company' : 'Person',
                'order' => $row['order_id'] === null ? '' : OrderNumber::format((int) $row['order_id']),
                'document' => (string) ($row['document_number'] ?? ''),
                'method' => MoneyRecords::METHODS[(string) ($row['method'] ?? '')] ?? (string) ($row['method'] ?? ''),
                'money_in' => (int) $row['cash_effect'] === 1 ? $amount : 0,
                'money_out' => (int) $row['cash_effect'] === -1 ? $amount : 0,
                'wallet' => (int) $row['wallet_effect'] * $amount,
                'bank_reference' => (string) ($row['external_reference'] ?? ''),
                'note' => (string) ($row['memo'] ?? ''),
            ];
        }
        foreach ($lines as &$line) {
            $line['money_in_label'] = $line['money_in'] > 0 ? self::rand($line['money_in']) : '';
            $line['money_out_label'] = $line['money_out'] > 0 ? self::rand($line['money_out']) : '';
            $line['wallet_label'] = $line['wallet'] === 0 ? '' : ($line['wallet'] > 0 ? '+' : '−') . self::rand(abs($line['wallet']));
            $line['when'] = $line['at']->format('j M Y H:i');
        }
        unset($line);
        $net = $totals['money_in'] - $totals['money_out'];

        return [
            'title' => 'Money Ledger',
            'period' => self::period((string) $filters['from'], (string) $filters['to'], 'Every line'),
            'filters' => self::ledgerFilterWords($filters),
            'lines' => $lines,
            'totals' => $totals + ['net' => $net, 'money_in_label' => self::rand($totals['money_in']), 'money_out_label' => self::rand($totals['money_out']),
                'net_label' => ($net < 0 ? '−' : '') . self::rand(abs($net)), 'wallet_in_label' => self::rand($totals['wallet_in']), 'wallet_out_label' => self::rand($totals['wallet_out'])],
            'made' => $this->clock->now()->setTimezone(self::zone()),
            'made_label' => $this->clock->now()->setTimezone(self::zone())->format('j F Y H:i'),
            'file' => 'money-ledger' . self::nameSuffix((string) $filters['from'], (string) $filters['to'], $this->today()),
        ];
    }

    /**
     * A wallet's statement for the dates its form gives (either may be empty), oldest first.
     *
     * @param array<string,mixed> $query the statement form's from and to
     * @return array<string,mixed>
     */
    public function statement(WalletOwner $owner, string $ownerName, string $reference, array $query, string $format, string $currency = 'ZAR'): array
    {
        $limit = self::limit($format);
        $from = self::date($query['from'] ?? '');
        $to = self::date($query['to'] ?? '');
        if ($from !== '' && $to !== '' && $to < $from) throw new RuntimeException('The statement\'s last day comes before its first. Choose the dates again.');
        [$fromAt, $toBefore] = self::bounds($from, $to);
        $rows = $this->wallets->statementOldestFirst($owner, $currency, $fromAt, $toBefore, $limit + 1);
        if (count($rows) > $limit) {
            throw new RuntimeException('A statement ' . ($format === 'pdf' ? 'PDF' : 'Excel file') . ' holds at most ' . number_format($limit) . ' movements, and more than that fall in these dates. Choose a shorter period.');
        }
        $opening = $this->wallets->balanceBefore($owner, $currency, $fromAt);
        $lines = [];
        $added = 0;
        $used = 0;
        foreach ($rows as $row) {
            $amount = (int) $row['amount_minor'];
            $in = (int) $row['wallet_effect'] > 0 ? $amount : 0;
            $out = (int) $row['wallet_effect'] < 0 ? $amount : 0;
            $added += $in;
            $used += $out;
            $at = $this->local((string) $row['occurred_at']);
            $lines[] = [
                'id' => (int) $row['id'], 'at' => $at, 'when' => $at->format('j M Y H:i'),
                'what' => LedgerKind::label((string) $row['kind']),
                'order' => $row['order_id'] === null ? '' : OrderNumber::format((int) $row['order_id']),
                'document' => (string) ($row['document_number'] ?? ''),
                'note' => (string) ($row['memo'] ?? ''),
                'added' => $in, 'used' => $out, 'balance' => (int) $row['balance_after'],
                'added_label' => $in > 0 ? self::rand($in) : '', 'used_label' => $out > 0 ? self::rand($out) : '', 'balance_label' => self::rand((int) $row['balance_after']),
            ];
        }
        $closing = $lines === [] ? $opening : $lines[count($lines) - 1]['balance'];
        $today = $this->today();

        return [
            'title' => 'Wallet statement',
            'owner_name' => $ownerName,
            'reference' => AccountReference::format($reference),
            'is_company' => $owner->isCompany(),
            'period' => self::period($from, $to, 'Every movement to ' . (new DateTimeImmutable($today))->format('j F Y')),
            'lines' => $lines,
            'opening' => $opening, 'added' => $added, 'used' => $used, 'closing' => $closing,
            'opening_label' => self::rand($opening), 'added_label' => self::rand($added), 'used_label' => self::rand($used), 'closing_label' => self::rand($closing),
            'opening_words' => $from === '' ? 'Before the first movement' : 'Before ' . (new DateTimeImmutable($from))->format('j F Y'),
            'closing_words' => $to === '' ? 'Now' : 'At the end of ' . (new DateTimeImmutable($to))->format('j F Y'),
            'made' => $this->clock->now()->setTimezone(self::zone()),
            'made_label' => $this->clock->now()->setTimezone(self::zone())->format('j F Y H:i'),
            'file' => 'wallet-statement-' . strtolower((string) preg_replace('/[^A-Za-z0-9]+/', '', $reference)) . self::nameSuffix($from, $to, $today),
        ];
    }

