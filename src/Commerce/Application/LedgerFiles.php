    /**
     * Draws the PDF once to count its pages and again saying "Page 1 of 3", as Money Reports do.
     *
     * @param array<string,mixed> $data
     */
    private function twicePdf(string $template, array $data, string $orientation): string
    {
        // A page is given words and numbers only (ThemeRenderer refuses objects): each date as its text.
        $doc = self::plain($data);
        $logo = $this->logo?->forPdf(45, 14);
        $html = fn(int $pages): string => $this->view->renderFragment($template, ['doc' => $doc, 'trading_name' => $this->owner->value('trading_name'), 'page_total' => $pages, 'pdf_logo' => $logo,
            'doc_demo' => $this->site->isDemo(), 'doc_demo_heading' => $this->site->isDemo() ? $this->site->heading() : '', 'doc_demo_notice' => $this->site->isDemo() ? $this->site->notice() : '']);

        return $this->pdfs->renderPage($html(MoneyReportFiles::pageCount($this->pdfs->renderPage($html(0), 'A4', $orientation))), 'A4', $orientation);
    }

    /**
     * The data with every date as its ISO text, for a page.
     *
     * @param array<mixed> $data
     * @return array<mixed>
     */
    private static function plain(array $data): array
    {
        foreach ($data as $key => $value) {
            if ($value instanceof \DateTimeInterface) $data[$key] = $value->format(DATE_ATOM);
            elseif (is_array($value)) $data[$key] = self::plain($value);
        }

        return $data;
    }

    /** @param callable(Writer,array<string,mixed>):void $write */
    private function excel(string $title, callable $write): string
    {
        $path = tempnam(sys_get_temp_dir(), 'ledger-');
        if ($path === false) throw new RuntimeException('The Excel file could not be started.');
        try {
            $by = $this->owner->value('trading_name');
            $writer = new Writer(new Options(properties: new Properties(title: $title, application: $by, creator: $by, lastModifiedBy: $by)));
            $writer->openToFile($path);
            $write($writer, self::cells());
            $writer->close();
            $bytes = file_get_contents($path);
            if ($bytes === false || $bytes === '') throw new RuntimeException('The Excel file could not be made.');

            return $bytes;
        } finally {
            @unlink($path);
        }
    }

    /**
     * The cell makers both files use: every word a text cell (never read as a formula), amounts numbers in rand and cents
     * made from whole cents only here, dates real dates and times.
     *
     * @return array<string,callable>
     */
    private static function cells(): array
    {
        $heading = (new Style())->withFontBold(true)->withBackgroundColor('F2F2F2');
        $bold = (new Style())->withFontBold(true);
        $amount = (new Style())->withFormat(MoneyReportFiles::AMOUNT_FORMAT);
        $whole = (new Style())->withFormat('0');
        $stamp = (new Style())->withFormat('yyyy-mm-dd hh:mm');
        $text = static fn(string $value): Cell => $value === '' ? new EmptyCell(null) : new StringCell($value, null);

        return [
            'text' => $text,
            'bold' => static fn(string $value): Cell => new StringCell($value, $bold),
            'rand' => static fn(int $minor): Cell => Cell::fromValue($minor / 100, $amount),
            'randOrEmpty' => static fn(int $minor): Cell => $minor === 0 ? new EmptyCell(null) : Cell::fromValue($minor / 100, $amount),
            'count' => static fn(int $value): Cell => Cell::fromValue($value, $whole),
            // The local date and time the page shows, kept as a date and time without its zone.
            'when' => static fn(DateTimeImmutable $at): Cell => Cell::fromValue(new DateTimeImmutable($at->format('Y-m-d H:i:s')), $stamp),
            'row' => static fn(array $cells): Row => new Row($cells),
            'headings' => static fn(string ...$labels): Row => new Row(array_map(static fn(string $label): Cell => new StringCell($label, $heading), $labels)),
        ];
    }

    private static function limit(string $format): int
    {
        if (!isset(self::FORMATS[$format])) throw new RuntimeException('Choose a PDF or an Excel file.');
        return $format === 'pdf' ? self::PDF_LINES : self::EXCEL_LINES;
    }

    /**
     * The Money Ledger's filters in words, for the top of the files: what the lines were chosen by, apart from the dates.
     *
     * @param array<string,mixed> $f
     * @return list<string>
     */
    private static function ledgerFilterWords(array $f): array
    {
        $kinds = array_map(static fn(array $k): string => $k[2], LedgerKind::KINDS) + array_map(static fn(array $g): string => $g['label'], MoneyRecords::LEDGER_KIND_GROUPS);
        $words = [];
        if (($f['kind'] ?? '') !== '') $words[] = 'What happened: ' . ($kinds[$f['kind']] ?? $f['kind']);
        if (($f['method'] ?? '') !== '') $words[] = 'How it was paid: ' . (MoneyRecords::METHODS[$f['method']] ?? $f['method']);
        if (($f['money'] ?? '') !== '') $words[] = ['in' => 'Money in only', 'out' => 'Money out only', 'none' => 'Neither money in nor money out'][$f['money']] ?? '';
        if (($f['wallet'] ?? '') !== '') $words[] = ['in' => 'Wallet credit added only', 'out' => 'Wallet credit used or expired only'][$f['wallet']] ?? '';
        if (($f['account'] ?? '') !== '') $words[] = ['person' => 'People only', 'company' => 'Companies only'][$f['account']] ?? '';
        if (($f['order'] ?? '') !== '') $words[] = 'Order ' . $f['order'];
        if (($f['q'] ?? '') !== '') $words[] = 'Search: "' . $f['q'] . '"';

        return array_values(array_filter($words, static fn(string $w): bool => $w !== ''));
    }

    /** A YYYY-MM-DD date that exists, else nothing. */
    private static function date(mixed $value): string
    {
        return is_string($value) && preg_match('/^\d{4}-\d{2}-\d{2}$/', $value) === 1 && checkdate((int) substr($value, 5, 2), (int) substr($value, 8, 2), (int) substr($value, 0, 4)) ? $value : '';
    }

    /**
     * The period's first moment and the moment after its last day, in the site's time zone; null for no bound.
     *
     * @return array{0:?string,1:?string}
     */
    private static function bounds(string $from, string $to): array
    {
        return [$from === '' ? null : (new DateTimeImmutable($from . ' 00:00:00', self::zone()))->format(DATE_ATOM),
            $to === '' ? null : (new DateTimeImmutable($to . ' 00:00:00', self::zone()))->modify('+1 day')->format(DATE_ATOM)];
    }

    private static function period(string $from, string $to, string $neither): string
    {
        $day = static fn(string $date): string => (new DateTimeImmutable($date))->format('j F Y');
        return match (true) {
            $from !== '' && $to !== '' => $day($from) . ' to ' . $day($to),
            $from !== '' => 'From ' . $day($from),
            $to !== '' => 'Up to ' . $day($to),
            default => $neither,
        };
    }

    private static function nameSuffix(string $from, string $to, string $today): string
    {
        return match (true) {
            $from !== '' && $to !== '' => '-' . $from . '-to-' . $to,
            $from !== '' => '-' . $from . '-to-' . $today,
            $to !== '' => '-to-' . $to,
            default => '-to-' . $today,
        };
    }

    private function today(): string
    {
        return $this->clock->now()->setTimezone(self::zone())->format('Y-m-d');
    }

    private function local(string $at): DateTimeImmutable
    {
        return (new DateTimeImmutable($at))->setTimezone(self::zone());
    }

    private static function zone(): DateTimeZone
    {
        return new DateTimeZone(date_default_timezone_get());
    }

    private static function rand(int $minor): string
    {
        return Money::ofMinorUnits($minor)->format();
    }
