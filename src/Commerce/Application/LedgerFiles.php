    /** @param array<string,mixed> $ledger */
    public function ledgerExcel(array $ledger): string
    {
        return $this->excel('Money Ledger, ' . $ledger['period'], function (Writer $writer, array $s) use ($ledger): void {
            $writer->getCurrentSheet()->setName('Summary');
            $writer->addRow($s['row']([$s['bold']('Money Ledger')]));
            $writer->addRow($s['row']([$s['text']('Period'), $s['text']($ledger['period'])]));
            foreach ($ledger['filters'] as $words) $writer->addRow($s['row']([$s['text']('Showing only'), $s['text']($words)]));
            $writer->addRow($s['row']([$s['text']('Lines'), $s['count'](count($ledger['lines']))]));
            foreach (['money_in' => 'Money in', 'money_out' => 'Money out', 'net' => 'Net money', 'wallet_in' => 'Wallet credit added', 'wallet_out' => 'Wallet credit used or expired'] as $key => $label) {
                $writer->addRow($s['row']([$s['text']($label), $s['rand']((int) $ledger['totals'][$key])]));
            }
            $writer->addRow($s['row']([$s['text']('Made'), $s['when']($ledger['made'])]));
            if ($this->site->isDemo()) $writer->addRow($s['row']([$s['text']($this->site->heading()), $s['text']($this->site->notice())]));

            $writer->addNewSheetAndMakeItCurrent()->setName('Lines');
            $writer->addRow($s['headings']('Line', 'When', 'Account reference', 'Account', 'Person or company', 'What happened', 'Kind', 'Order', 'Document', 'How it was paid',
                'Money in', 'Money out', 'Wallet credit', 'Bank reference', 'Note'));
            foreach ($ledger['lines'] as $line) {
                $writer->addRow($s['row']([$s['count']($line['id']), $s['when']($line['at']), $s['text']($line['reference']), $s['text']($line['account']), $s['text']($line['account_type']),
                    $s['text']($line['what']), $s['text']($line['kind']), $s['text']($line['order']), $s['text']($line['document']), $s['text']($line['method']),
                    $s['randOrEmpty']($line['money_in']), $s['randOrEmpty']($line['money_out']), $s['randOrEmpty']($line['wallet']), $s['text']($line['bank_reference']), $s['text']($line['note'])]));
            }
        });
    }

