    /**
     * A payload as label: value lines, nested values as JSON.
     *
     * @return list<array{label:string,value:string}>
     */
    public static function payloadLines(string $json): array
    {
        $payload = json_decode($json, true);
        if (!is_array($payload)) return [];
        $lines = [];
        foreach ($payload as $key => $value) {
            $lines[] = ['label' => ucfirst(str_replace('_', ' ', (string) $key)), 'value' => is_scalar($value) || $value === null ? (is_bool($value) ? ($value ? 'yes' : 'no') : (string) ($value ?? '—')) : (string) json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE)];
        }
        return $lines;
    }

