declare(strict_types=1);

namespace CattoLearning\Commerce\Application;

use CattoLearning\Infrastructure\Persistence\OptionRepository;
use JsonException;

final class MoneyReportSettings
{
    public const OPTION = 'money_reports';

    public function __construct(private readonly OptionRepository $options)
    {
    }

    /** @return array{email:bool,telegram:bool} */
    public function saved(): array
    {
        $saved = [];
        try {
            $saved = json_decode((string) ($this->options->find(self::OPTION) ?? '{}'), true, 4, JSON_THROW_ON_ERROR);
        } catch (JsonException) {
        }
        if (!is_array($saved)) $saved = [];

        return ['email' => (bool) ($saved['email'] ?? true), 'telegram' => (bool) ($saved['telegram'] ?? true)];
    }

    public function save(bool $email, bool $telegram, int $actorUserId): void
    {
        $this->options->set(self::OPTION, json_encode(['email' => $email, 'telegram' => $telegram], JSON_THROW_ON_ERROR), $actorUserId);
    }
}
