declare(strict_types=1);

namespace CattoLearning\Commerce\Application;

use CattoLearning\Bundle\BundleRules;
use CattoLearning\Commerce\Infrastructure\BundleCreditRepository;
use CattoLearning\Commerce\Infrastructure\CommerceRepository;
use CattoLearning\Course\CourseRepository;
use CattoLearning\Infrastructure\Mail\MailerInterface;
use CattoLearning\Infrastructure\Persistence\AdministrationRepository;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\AccessPeriod;
use CattoLearning\Support\Money;
use CattoLearning\Support\WasPrice;
use RuntimeException;
use Symfony\Component\Clock\ClockInterface;

final class BundleCredits
{
    /** The rule, said wherever a company buys or gives a bundle credit. */
    public const RULE = 'Each bundle credit is for one person. That person gets every course in the bundle, and a bundle is never split between people.';

    /** What the Company Administrator ticks before placing an order with bundle credits in it. */
    public const ACCEPT = 'I understand that each bundle credit is for one person: that person gets every course in the bundle, and a bundle can never be split between people.';

    public function __construct(
        private readonly BundleCreditRepository $credits,
        private readonly CommerceRepository $records,
        private readonly CourseRepository $courses,
        private readonly AdministrationRepository $administration,
        private readonly TransactionManager $transactions,
        private readonly AuditRepository $audit,
        private readonly ClockInterface $clock,
        private readonly ?MailerInterface $mailer = null,
        private readonly ?AccessService $access = null,
    ) {}

    /**
     * The courses of a bundle credit that a person already has (owner, 2026-11-11: "if a staff member already has one or more
     * of the courses, show them which ones they already have").
     *
     * @return list<array{course_id:int,title:string,enrolment_id:int}>
     */
    public function heldCourses(int $companyId, int $creditId, int $userId): array
    {
        $credit = $this->credits->credit($creditId);
        if ($credit === null || (int) $credit['company_id'] !== $companyId) return [];
        $held = [];
        foreach ((array) $credit['courses'] as $course) {
            $enrolment = $this->records->openEnrolment($userId, (int) $course['course_id']);
            if ($enrolment !== null) $held[] = ['course_id' => (int) $course['course_id'], 'title' => (string) $course['title'], 'enrolment_id' => $enrolment];
        }
        return $held;
    }

    public function personName(int $userId): string
    {
        return $this->credits->personName($userId);
    }

    /**
     * The bundle offers a company may buy now, each with its courses, its price as each credit costs it and its access period.
     *
     * @return list<array<string,mixed>>
     */
    public function offers(): array
    {
        $now = $this->clock->now();
        $offers = [];
        foreach ($this->credits->offers() as $offer) {
            $courses = $this->credits->courses((int) $offer['bundle_id']);
            if (BundleRules::unavailableReason($offer, $courses, $now) !== null || (string) $offer['currency_code'] !== 'ZAR') continue;
            $offers[] = $this->presented($offer, $courses);
        }
        return $offers;
    }

    /**
     * One offer a company may buy, with its courses, or why it cannot.
     *
     * @return array<string,mixed>
     */
    public function requireOffer(int $offerId): array
    {
        $offer = $this->credits->offer($offerId) ?? throw new RuntimeException('This bundle is not available.');
        $courses = $this->credits->courses((int) $offer['bundle_id']);
        $reason = BundleRules::unavailableReason($offer, $courses, $this->clock->now());
        if ($reason !== null) throw new RuntimeException($reason);
        if ((string) $offer['currency_code'] !== 'ZAR') throw new RuntimeException('This bundle is not available for purchase at the moment.');
        return $this->presented($offer, $courses);
    }

    /**
     * A company's bundle credits, newest first, with how many each holds and has left to give.
     *
     * @return list<array<string,mixed>>
     */
    public function forCompany(int $companyId): array
    {
        return array_map(static fn(array $credit): array => $credit + [
            'access_label' => AccessPeriod::label((int) $credit['access_period_seconds']),
            'course_titles' => array_map(static fn(array $course): string => (string) $course['title'], (array) $credit['courses']),
        ], $this->credits->forCompany($companyId));
    }

    /**
     * Gives one bundle credit to one person: every course of the bundle as it was sold, with its access period, or nothing.
     *
     * @return array{allocation_id:int,enrolment_ids:list<int>}
     */
    public function assign(int $companyId, int $creditId, int $userId, int $actorUserId, bool $extendHeld = false): array
    {
        $result = $this->transactions->run(function () use ($companyId, $creditId, $userId, $actorUserId, $extendHeld): array {
            $credit = $this->credits->credit($creditId, true);
            if ($credit === null || (int) $credit['company_id'] !== $companyId) throw new RuntimeException('The bundle credit does not exist.');
            if (!$this->administration->isActiveCompanyMember($companyId, $userId)) throw new RuntimeException('That person is not an active member of this company.');
            if ($credit['left'] < 1) throw new RuntimeException('Every ' . $credit['bundle_title'] . ' bundle credit has been given. ' . self::RULE);
            // A course they already have: the Company Administrator is shown which, and may give the bundle anyway, which
            // extends that course by the bundle's access period (owner, 2026-11-11).
            $held = [];
            foreach ($this->heldCourses($companyId, $creditId, $userId) as $course) $held[$course['course_id']] = $course;
            if ($held !== [] && !$extendHeld) {
                throw new RuntimeException('This person already has ' . self::titles(array_values($held)) . '. Give the bundle anyway to extend their access to ' . (count($held) === 1 ? 'it' : 'them') . ' by the bundle\'s access period.');
            }
            $now = $this->clock->now()->format(DATE_ATOM);
            $allocationId = $this->credits->allocate($creditId, $userId, $actorUserId, $now);
            $enrolments = [];
            $underWay = false;
            $period = (int) $credit['access_period_seconds'];
            foreach ((array) $credit['courses'] as $course) {
                $courseId = (int) $course['course_id'];
                if (isset($held[$courseId])) {
                    // The person's own access becomes a source of its own first, so the two stay independent.
                    $enrolmentId = $held[$courseId]['enrolment_id'];
                    $this->records->recordOriginSource($enrolmentId, $now);
                    $term = $this->credits->enrolmentTerm($enrolmentId) ?? throw new RuntimeException('The enrolment is unavailable.');
                    $snapshot = ['bundle_credit_id' => $creditId, 'bundle_id' => (int) $credit['bundle_id'], 'bundle_title' => (string) $credit['bundle_title'], 'company_id' => $companyId, 'extends' => true];
                    if ($term['expires_at'] !== null) {
                        $underWay = true;
                        $from = max(new \DateTimeImmutable($term['expires_at']), $this->clock->now());
                        $source = $this->credits->addExtensionSource($credit['commerce_order_item_id'] === null ? null : (int) $credit['commerce_order_item_id'], $enrolmentId, $period, $from->format(DATE_ATOM), $snapshot, $now);
                    } else {
                        $source = $this->credits->addExtensionSource($credit['commerce_order_item_id'] === null ? null : (int) $credit['commerce_order_item_id'], $enrolmentId, $term['access_period_seconds'] + $period, null, $snapshot, $now);
                    }
                    $this->credits->linkEnrolment($allocationId, $courseId, $enrolmentId, true, $source);
                    $this->access?->reconcile($enrolmentId);
                } else {
                    $enrolmentId = $this->courses->grantCourse($userId, $courseId, $period, $actorUserId);
                    $this->credits->linkEnrolment($allocationId, $courseId, $enrolmentId);
                }
                $enrolments[] = $enrolmentId;
            }
            // A course it extended that is already under way puts the credit to use at once.
            if ($underWay) $this->credits->consumeAllocation($allocationId, $now);
            $this->audit->record($actorUserId, 'company.bundle.assigned', ['company_id' => $companyId, 'bundle_credit_id' => $creditId, 'bundle_id' => (int) $credit['bundle_id'], 'user_id' => $userId, 'allocation_id' => $allocationId, 'enrolment_ids' => $enrolments, 'extended_course_ids' => array_keys($held)]);
            return ['allocation_id' => $allocationId, 'enrolment_ids' => $enrolments, 'courses' => array_values(array_filter((array) $credit['courses'], static fn(array $course): bool => !isset($held[(int) $course['course_id']])))];
        });
        // After the commit: the person is told about each course, as for a course credit.
        foreach ($result['courses'] as $course) {
            $learner = $this->administration->learnerNotice($userId, (int) $course['course_id']);
            if ($learner !== null) $this->mailer?->sendCourseEnrolmentNotice((string) $learner['email'], (string) $learner['course_title'], (string) $learner['slug']);
        }
        return ['allocation_id' => $result['allocation_id'], 'enrolment_ids' => $result['enrolment_ids']];
    }

    /** @param list<array{title:string}> $courses "A", "A and B", "A, B and C". */
    private static function titles(array $courses): string
    {
        $names = array_map(static fn(array $course): string => (string) $course['title'], $courses);
        $last = array_pop($names);
        return $names === [] ? (string) $last : implode(', ', $names) . ' and ' . $last;
    }

    /**
     * @param array<string,mixed> $offer
     * @param list<array<string,mixed>> $courses
     * @return array<string,mixed>
     */
    private function presented(array $offer, array $courses): array
    {
        $price = Money::strictMinorUnits((int) $offer['price_minor_units'], (string) $offer['currency_code']);
        return $offer + [
            'courses' => $courses,
            'course_titles' => array_map(static fn(array $course): string => (string) $course['title'], $courses),
            'price_label' => $price->format(),
            'access_label' => AccessPeriod::label((int) $offer['access_period_seconds']),
        ] + WasPrice::labels($price->minorUnits, $offer['was_price_minor_units'] ?? null, $price->currency);
    }
}
