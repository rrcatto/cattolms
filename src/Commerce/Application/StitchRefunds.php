Description:
Money-back refunds sent to the card through Stitch (owner, 2026-11-11: "build the Stitch refunds next"). A refund approved as
money back on an order paid through Stitch is sent to the card it came from, for what the Refund Policy gives back (the
refund's net amount, after Stitch's fees), and its payout is recorded at once with Stitch's refund id as its reference, as
RefundAdministrationService::recordPayout records one paid by hand. Stitch takes no request key, so before sending, Stitch's
own refunds of the payment are read: a processed refund of exactly that amount that no refund of this site holds is the one
sent before (a reply that never came) and is recorded instead of sending again. A refund Stitch refuses stays to pay, with
Stitch's words in the order's trail, and can be sent again or paid another way and recorded.

