declare(strict_types=1);

namespace CattoLearning\Commerce\Application;

use CattoLearning\Auth\CurrentUser;
use CattoLearning\Commerce\Infrastructure\CommerceRepository;
use CattoLearning\Commerce\Infrastructure\Payment\StitchPaymentGateway;
use CattoLearning\Support\Money;
use RuntimeException;
use Symfony\Component\Clock\ClockInterface;
use Throwable;

final class StitchRefunds
{
    /** Stitch refunds R1.00 at least. */
    public const SMALLEST_MINOR = 100;

    public function __construct(
        private readonly CommerceRepository $records,
        private readonly RefundAdministrationService $refunds,
        private readonly ClockInterface $clock,
        private readonly ?StitchPaymentGateway $stitch = null,
    ) {
    }

    /**
     * Whether a refund can go to the card through Stitch: money back, still to pay, at least R1.00, on an order paid through
     * Stitch, with card payments set up.
     *
     * @param array<string,mixed> $refund a refund record
     */
    public function canSend(array $refund): bool
    {
        return $this->stitch !== null && $this->stitch->problem() === null
            && $refund['destination'] === 'money_back' && (int) $refund['net_minor'] >= self::SMALLEST_MINOR
            && ($refund['paid_at'] ?? $refund['payout_paid_at'] ?? null) === null
            && $this->stitchPayment((int) $refund['order_id']) !== null;
    }

    /**
     * Sends a money-back refund to the card and records its payout. Returns whether it is paid now, with what to tell ADMIN.
     *
     * @return array{done:bool,words:string}
     */
    public function send(CurrentUser $actor, int $refundId): array
    {
        OrderService::requireCapability($actor, 'PLATFORM.REFUND.MANAGE');
        $refund = $this->records->refund($refundId) ?? throw new RuntimeException('Refund not found.');
        if ($refund['destination'] !== 'money_back' || (int) $refund['net_minor'] <= 0) throw new RuntimeException('This refund went to the wallet: there is nothing to send to a card.');
        if ($refund['paid_at'] !== null) return ['done' => true, 'words' => 'This refund is already paid, reference ' . $refund['payout_reference'] . '.'];
        $amount = Money::strictMinorUnits((int) $refund['net_minor'], (string) $refund['currency']);
        if ((int) $refund['net_minor'] < self::SMALLEST_MINOR) throw new RuntimeException('Stitch refunds R1.00 at least: pay ' . $amount->format() . ' another way and record it.');
        $stitch = $this->stitch ?? throw new RuntimeException('Card payments through Stitch are not set up.');
        if (($problem = $stitch->problem()) !== null) throw new RuntimeException($problem);
        $payment = $this->stitchPayment((int) $refund['order_id']) ?? throw new RuntimeException('This order was not paid through Stitch, so there is no card to refund: pay it another way and record it.');
        $paymentId = (string) $payment['provider_reference'];
        $orderId = (int) $refund['order_id'];
        $now = $this->clock->now();

        // A refund sent before whose reply never came is recorded, never sent twice.
        try {
            $known = array_filter(array_map(static fn (array $row): string => (string) ($row['payout_reference'] ?? ''), $this->records->refunds($orderId)));
            foreach ($stitch->refundsOf($paymentId) as $earlier) {
                if ($earlier['status'] === 'PROCESSED' && $earlier['amount'] === (int) $refund['net_minor'] && $earlier['id'] !== '' && !in_array($earlier['id'], $known, true)) {
                    $this->refunds->recordPayout($actor, $refundId, $now->format('Y-m-d'), $earlier['id']);
                    $this->records->audit($orderId, $actor->id, 'refund.sent_to_card', ['refund_id' => $refundId, 'stitch_refund' => $earlier['id'], 'amount_minor' => (int) $refund['net_minor'], 'found' => true], $now->format(DATE_ATOM));

                    return ['done' => true, 'words' => 'Stitch had already refunded ' . $amount->format() . ' to the card (Stitch refund ' . $earlier['id'] . '). It is now recorded as paid.'];
                }
            }
            $sent = $stitch->refund($paymentId, $amount);
        } catch (Throwable $unreachable) {
            $this->records->audit($orderId, $actor->id, 'refund.stitch_failed', ['refund_id' => $refundId, 'message' => $unreachable->getMessage()], $now->format(DATE_ATOM));

            return ['done' => false, 'words' => 'Stitch could not be reached: ' . $unreachable->getMessage() . ' Send it again later: the site first asks Stitch whether it went through.'];
        }
        if ($sent['state'] !== 'processed' || $sent['id'] === null) {
            $this->records->audit($orderId, $actor->id, 'refund.stitch_failed', ['refund_id' => $refundId, 'message' => $sent['message'], 'stitch_refund' => $sent['id']], $now->format(DATE_ATOM));

            return ['done' => false, 'words' => 'Stitch did not refund ' . $amount->format() . ': ' . $sent['message'] . ' Send it again, or pay it another way and record it.'];
        }
        $this->refunds->recordPayout($actor, $refundId, $now->format('Y-m-d'), $sent['id']);
        $this->records->audit($orderId, $actor->id, 'refund.sent_to_card', ['refund_id' => $refundId, 'stitch_refund' => $sent['id'], 'amount_minor' => (int) $refund['net_minor']], $now->format(DATE_ATOM));

        return ['done' => true, 'words' => 'Refunded ' . $amount->format() . ' to the card through Stitch (Stitch refund ' . $sent['id'] . '). It is recorded as paid.'];
    }

    /**
     * The order's payment that came through Stitch, with Stitch's payment id: what a refund to the card is made against.
     *
     * @return array<string,mixed>|null
     */
    private function stitchPayment(int $orderId): ?array
    {
        foreach (array_reverse($this->records->payments($orderId)) as $payment) {
            if ($payment['gateway'] === StitchPaymentGateway::ID && in_array($payment['state'], ['paid', 'partially_refunded', 'refunded'], true) && (string) ($payment['provider_reference'] ?? '') !== '') {
                return $payment;
            }
        }

        return null;
    }
}
