/*
Generated by: Claude Code CLI

Date time: 2026/10/19 SAST

Version: 0.9.5

Description:
Record EFT Payment and Unmatched Money (owner, 2026-10-18: "I don't want to go hunting for orders";
2026-10-19: money that matches no unpaid order "goes on an unmatched money list for me to sort out").

ADMIN starts from the bank statement: the reference the payer wrote, the amount, the day it arrived,
the bank's own reference for the deposit and where it was seen. find() reads the payer's reference as an
account reference (CL-20261018-13147-3, with or without hyphens or spaces, among other words) or an order
number (CL-00000183), and lists that account's orders paid by EFT that can still take a payment. ADMIN
records the deposit against one of them (PaymentAdministrationService::confirmBank, the same as on the
order's page), or puts it on the unmatched money list.

An unmatched deposit is not in the money ledger: it enters it only when ADMIN matches it to an order,
as that order's EFT payment on the day it arrived, in the same transaction that marks it matched. Money
paid back to the sender never enters the ledger; ADMIN records the day and the bank's reference of the
return. Either way the deposit leaves the list, and nothing about it changes afterwards. Every step is in
the Commerce Trail, and each open deposit is under Transactions that need attention.

Changelog:
2026/10/19 SAST
- Created.
*/

declare(strict_types=1);

namespace CattoLearning\Commerce\Application;

use CattoLearning\Auth\CurrentUser;
use CattoLearning\Commerce\Infrastructure\BankPaymentRepository;
use CattoLearning\Commerce\Infrastructure\CommerceRepository;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Support\AccountReference;
use CattoLearning\Support\Money;
use CattoLearning\Support\Uuid;
use DateTimeImmutable;
use InvalidArgumentException;
use RuntimeException;
use Symfony\Component\Clock\ClockInterface;

final class BankPayments
{
    public function __construct(
        private readonly BankPaymentRepository $bank,
        private readonly CommerceRepository $records,
        private readonly PaymentAdministrationService $payments,
        private readonly TransactionManager $transactions,
        private readonly ClockInterface $clock
    ) {}

    /**
     * Who a bank statement's reference names, and their orders that can take an EFT payment.
     *
     * @return array{typed:string,found:bool,message:string,account:?array{kind:string,id:int,name:string,reference:string,label:string},orders:list<array<string,mixed>>}
     */
    public function find(string $typed): array
    {
        $typed = trim($typed);
        $result = ['typed' => $typed, 'found' => false, 'message' => '', 'account' => null, 'orders' => []];
        if ($typed === '') return $result;

        [$stored, $mistyped] = self::accountReferenceIn($typed);
        $account = $stored !== null ? $this->bank->accountByReference($stored) : null;
        $orderId = $account === null ? self::orderNumberIn($typed) : null;
        if ($account === null && $orderId !== null) $account = $this->bank->accountForOrder($orderId);
        if ($account === null) {
            $result['message'] = match (true) {
                $stored !== null => 'No account has the reference ' . AccountReference::format($stored) . '.',
                $mistyped => 'That looks like an account reference with a mistake in it, so it names no account. Check it against the statement.',
                $orderId !== null => 'There is no order ' . MoneyRecords::orderNumber($orderId) . '.',
                default => 'There is no account reference or order number in "' . $typed . '".',
            };

            return $result;
        }

        $orders = $this->bank->eftOrders($account['kind'], $account['id']);
        if ($orderId !== null) $orders = array_values(array_filter($orders, static fn(array $o): bool => (int) $o['id'] === $orderId));
        $result['found'] = true;
        $result['account'] = $account + ['label' => AccountReference::format($account['reference']) . ' · ' . $account['name'],
            // A person's account is the person, linked to their account with their reference and email (owner, 2026-10-21).
            'person' => $account['kind'] === 'person' ? MoneyRecords::person($account['id'], $account['name'], $account['reference'], $account['email']) : null];
        $result['orders'] = array_map(self::orderRow(...), $orders);
        if ($result['orders'] === []) {
            $result['message'] = $orderId !== null
                ? 'Order ' . MoneyRecords::orderNumber($orderId) . ' is not waiting for an EFT payment.'
                : $account['name'] . ' has no order waiting for an EFT payment.';
        }

        return $result;
    }

    /**
     * Records a deposit against one of the orders find() offered, as that order's EFT payment.
     *
     * @return string the payment's id
     */
    public function recordAgainstOrder(CurrentUser $actor, int $orderId, string $requestKey, int $amountMinor, string $receivedAt, string $payerReference, string $bankReference, string $seenWhere): string
    {
        $this->bank->eftOrder($orderId) ?? throw new RuntimeException('That order cannot take an EFT payment.');

        return $this->payments->confirmBank($actor, $orderId, $requestKey, $amountMinor, $receivedAt, trim($bankReference), self::evidence($seenWhere, $payerReference));
    }

    /** Puts a deposit that pays no order on the unmatched money list. @return int its id */
    public function recordUnmatched(CurrentUser $actor, string $requestKey, int $amountMinor, string $receivedAt, string $payerReference, string $bankReference, string $seenWhere): int
    {
        self::requireManage($actor);
        if (!Uuid::isValid($requestKey)) throw new RuntimeException('Invalid confirmation identifier.');
        [$payerReference, $bankReference, $seenWhere] = [trim($payerReference), trim($bankReference), trim($seenWhere)];
        if ($amountMinor <= 0 || mb_strlen($bankReference) < 3 || mb_strlen($bankReference) > 200 || mb_strlen($seenWhere) < 5 || mb_strlen($seenWhere) > 2000) {
            throw new RuntimeException('Enter the amount received, the bank’s reference for it and where you saw it.');
        }
        if ($payerReference === '' || mb_strlen($payerReference) > 200) throw new RuntimeException('Enter the reference the payer used, as the statement shows it.');
        $received = $this->received($receivedAt);

        return $this->transactions->run(function () use ($actor, $requestKey, $amountMinor, $received, $payerReference, $bankReference, $seenWhere): int {
            $existing = $this->bank->unmatchedByPublicId($requestKey);
            if ($existing !== null) return (int) $existing['id'];
            if ($this->records->bankReferenceRecorded($bankReference)) throw new RuntimeException('A deposit with the bank reference ' . $bankReference . ' is already recorded.');
            $now = $this->clock->now()->format(DATE_ATOM);
            $id = $this->bank->createUnmatched($requestKey, $amountMinor, 'ZAR', $received->format(DATE_ATOM), $payerReference, $bankReference, $seenWhere, $actor->id, $now);
            $this->records->audit(null, $actor->id, 'unmatched.recorded', ['unmatched_id' => $id, 'amount_minor' => $amountMinor, 'currency' => 'ZAR',
                'received_at' => $received->format(DATE_ATOM), 'payer_reference' => $payerReference, 'bank_reference' => $bankReference], $now);

            return $id;
        });
    }

    /** Matches an unmatched deposit to an order: it becomes that order's EFT payment on the day it arrived. */
    public function match(CurrentUser $actor, int $id, int $orderId): string
    {
        self::requireManage($actor);

        return $this->transactions->run(function () use ($actor, $id, $orderId): string {
            $item = $this->bank->unmatched($id, true) ?? throw new RuntimeException('That deposit is not on the list.');
            if ($item['state'] !== 'open') throw new RuntimeException('This deposit has already been sorted out.');
            $this->bank->eftOrder($orderId) ?? throw new RuntimeException('That order cannot take an EFT payment.');
            // The deposit's own id is the request key, so the payment is made once whatever happens.
            $paymentId = $this->payments->confirmBank($actor, $orderId, (string) $item['public_id'], (int) $item['amount_minor'],
                (new DateTimeImmutable((string) $item['received_at']))->format(DATE_ATOM), (string) $item['bank_reference'],
                self::evidence('Unmatched money ' . $id . ': ' . $item['seen_where'], (string) $item['payer_reference']));
            $now = $this->clock->now()->format(DATE_ATOM);
            $this->bank->markMatched($id, $orderId, $paymentId, $actor->id, $now);
            $this->records->audit($orderId, $actor->id, 'unmatched.matched', ['unmatched_id' => $id, 'payment_id' => $paymentId, 'amount_minor' => (int) $item['amount_minor'],
                'currency' => (string) $item['currency'], 'bank_reference' => (string) $item['bank_reference']], $now);

            return $paymentId;
        });
    }

    /** Records that an unmatched deposit was paid back to whoever sent it. */
    public function returned(CurrentUser $actor, int $id, string $returnedOn, string $reference, string $note): void
    {
        self::requireManage($actor);
        [$reference, $note] = [trim($reference), trim($note)];
        if (mb_strlen($reference) < 3 || mb_strlen($reference) > 200) throw new RuntimeException('Enter the bank’s reference for the money you paid back.');
        if (mb_strlen($note) > 2000) throw new RuntimeException('Keep the note to 2,000 characters.');
        if (preg_match('/^\d{4}-\d{2}-\d{2}$/', $returnedOn) !== 1) throw new RuntimeException('Choose the date you paid it back.');
        // Today means now; an earlier day is taken at midday, like the day money arrived.
        $now = $this->clock->now();
        $returned = $this->received($returnedOn === $now->format('Y-m-d') ? $now->format(DATE_ATOM) : $returnedOn . 'T12:00:00' . $now->format('P'), 'The date you paid it back cannot be in the future.');
        $this->transactions->run(function () use ($actor, $id, $returned, $reference, $note): void {
            $item = $this->bank->unmatched($id, true) ?? throw new RuntimeException('That deposit is not on the list.');
            if ($item['state'] !== 'open') throw new RuntimeException('This deposit has already been sorted out.');
            if ($returned < new DateTimeImmutable((string) $item['received_at'])) $returned = new DateTimeImmutable((string) $item['received_at']);
            $now = $this->clock->now()->format(DATE_ATOM);
            $this->bank->markReturned($id, $returned->format(DATE_ATOM), $reference, $note, $actor->id, $now);
            $this->records->audit(null, $actor->id, 'unmatched.returned', ['unmatched_id' => $id, 'amount_minor' => (int) $item['amount_minor'], 'currency' => (string) $item['currency'],
                'return_reference' => $reference], $now);
        });
    }

    /**
     * One deposit on the list, in words.
     *
     * @return array<string,mixed>|null
     */
    public function unmatched(int $id): ?array
    {
        $row = $this->bank->unmatched($id);

        return $row === null ? null : self::unmatchedRow($row);
    }

    /** @return list<array<string,mixed>> the open deposits oldest first, or every deposit newest first */
    public function unmatchedList(bool $openOnly): array
    {
        return array_map(self::unmatchedRow(...), $this->bank->unmatchedList($openOnly));
    }

    /**
     * An account reference in what the payer wrote, stored form, or whether one is there but mistyped.
     * The reference may be written with or without hyphens or spaces and among other words, so every
     * run of up to five neighbouring words is tried, joined.
     *
     * @return array{0:?string,1:bool}
     */
    public static function accountReferenceIn(string $typed): array
    {
        $words = array_values(array_filter(preg_split('/[\s,;:\/]+/', strtoupper($typed)) ?: [], static fn(string $w): bool => $w !== ''));
        $mistyped = false;
        foreach ($words as $start => $_) {
            // Longest first: "CL 20261027 30492 Z" read three words at a time could make another, valid-looking
            // reference (CL-20261027-3049-2) before reaching the whole one (2026-10-27).
            for ($length = min(5, count($words) - $start); $length >= 1; $length--) {
                $candidate = implode('', array_slice($words, $start, $length));
                try {
                    return [AccountReference::parse($candidate), false];
                } catch (InvalidArgumentException $error) {
                    if (str_contains($error->getMessage(), 'mistake')) $mistyped = true;
                }
            }
        }

        return [null, $mistyped];
    }

    /** An order number such as CL-00000183 (or CL00000183) in what the payer wrote. */
    public static function orderNumberIn(string $typed): ?int
    {
        foreach (preg_split('/[\s,;:\/]+/', strtoupper($typed)) ?: [] as $word) {
            if (preg_match('/^CL-?(\d{8})$/', $word, $match) === 1 && (int) $match[1] > 0) return (int) $match[1];
        }

        return null;
    }

    /**
     * @param array<string,mixed> $order
     * @return array<string,mixed>
     */
    private static function orderRow(array $order): array
    {
        $due = max(0, (int) $order['total_minor'] - (int) $order['paid_minor']);
        $currency = (string) $order['currency'];

        return [
            'id' => (int) $order['id'], 'number' => MoneyRecords::orderNumber((int) $order['id']), 'href' => '/admin/commerce/orders/' . (int) $order['id'],
            'bought' => (string) $order['bought'], 'state' => (string) $order['state'],
            'total_label' => Money::ofMinorUnits((int) $order['total_minor'], $currency)->format(),
            'due_minor' => $due, 'due_label' => Money::ofMinorUnits($due, $currency)->format(),
            'placed' => (new DateTimeImmutable((string) $order['placed_at']))->format('j M Y'),
            'note' => $order['state'] === 'cancelled'
                ? 'Cancelled because it was not paid by ' . (new DateTimeImmutable((string) $order['payment_due_at']))->format('j M Y') . '. Money recorded against it goes to the customer’s wallet.'
                : Money::ofMinorUnits($due, $currency)->format() . ' still due by ' . (new DateTimeImmutable((string) $order['payment_due_at']))->format('j M Y') . '.',
        ];
    }

    /**
     * @param array<string,mixed> $row
     * @return array<string,mixed>
     */
    private static function unmatchedRow(array $row): array
    {
        $amount = Money::ofMinorUnits((int) $row['amount_minor'], (string) $row['currency'])->format();
        $received = (new DateTimeImmutable((string) $row['received_at']))->format('j M Y');
        $resolver = ['person' => MoneyRecords::person((int) ($row['resolved_by_user_id'] ?? 0), (string) ($row['resolved_by_name'] ?? ''), (string) ($row['resolved_by_reference'] ?? ''), (string) ($row['resolved_by_email'] ?? ''))];
        $outcome = match ((string) $row['state']) {
            'matched' => [['text' => 'Matched to order ' . MoneyRecords::orderNumber((int) $row['order_id']) . ' by '], $resolver,
                ['text' => ' on ' . (new DateTimeImmutable((string) $row['resolved_at']))->format('j M Y') . ': it is that order’s EFT payment, received on ' . $received . '.']],
            'returned' => [['text' => 'Paid back to the sender on ' . (new DateTimeImmutable((string) $row['returned_at']))->format('j M Y') . ', bank reference ' . $row['return_reference'] . ', recorded by '], $resolver,
                ['text' => '.' . (trim((string) $row['resolution_note']) !== '' ? ' ' . trim((string) $row['resolution_note']) : '')]],
            default => [],
        };

        return [
            'id' => (int) $row['id'], 'href' => '/admin/commerce/unmatched/' . (int) $row['id'], 'state' => (string) $row['state'],
            'amount_minor' => (int) $row['amount_minor'], 'amount_label' => $amount, 'received' => $received,
            'received_on' => (new DateTimeImmutable((string) $row['received_at']))->format('Y-m-d'),
            'payer_reference' => (string) $row['payer_reference'], 'bank_reference' => (string) $row['bank_reference'], 'seen_where' => (string) $row['seen_where'],
            'recorded' => (new DateTimeImmutable((string) $row['recorded_at']))->format('j M Y \a\t H:i'), 'recorded_by' => (string) $row['recorded_by_name'],
            'recorded_by_person' => MoneyRecords::person((int) $row['recorded_by_user_id'], (string) $row['recorded_by_name'], (string) ($row['recorded_by_reference'] ?? ''), (string) ($row['recorded_by_email'] ?? '')),
            'sentence' => $amount . ' arrived on ' . $received . ' with the reference "' . $row['payer_reference'] . '", and no unpaid order could be matched to it.',
            'status_label' => match ((string) $row['state']) { 'matched' => 'Matched', 'returned' => 'Paid back', default => 'To sort out' },
            'status_tone' => $row['state'] === 'open' ? 'warning' : 'neutral',
            'outcome' => implode('', array_map(static fn(array $part): string => $part['text'] ?? $part['person']['name'], $outcome)),
            // The same sentence with whoever resolved it as a person (owner, 2026-10-21).
            'outcome_parts' => $outcome,
            'order_href' => $row['order_id'] === null ? '' : '/admin/commerce/orders/' . (int) $row['order_id'],
            'order_label' => $row['order_id'] === null ? '' : MoneyRecords::orderNumber((int) $row['order_id']),
        ];
    }

    /** What the evidence of an EFT payment says: where ADMIN saw it, and the payer's own reference. */
    private static function evidence(string $seenWhere, string $payerReference): string
    {
        $seenWhere = trim($seenWhere);
        $payerReference = trim($payerReference);

        return mb_substr($payerReference === '' ? $seenWhere : $seenWhere . ' The payer’s reference: ' . $payerReference . '.', 0, 2000);
    }

    private function received(string $at, string $future = 'The day the money arrived cannot be in the future.'): DateTimeImmutable
    {
        try {
            $received = new DateTimeImmutable($at);
        } catch (\Exception) {
            throw new RuntimeException('Choose the date the money reached the bank.');
        }
        if ($received > $this->clock->now()) throw new RuntimeException($future);

        return $received;
    }

    private static function requireManage(CurrentUser $actor): void
    {
        OrderService::requireCapability($actor, 'PLATFORM.PAYMENT.MANAGE');
        OrderService::requireCapability($actor, 'PLATFORM.PAYMENT.RECONCILE');
    }
}
