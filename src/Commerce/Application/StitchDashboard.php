declare(strict_types=1);

namespace CattoLearning\Commerce\Application;

use CattoLearning\Commerce\Domain\OrderNumber;
use CattoLearning\Commerce\Infrastructure\CommerceRepository;
use CattoLearning\Commerce\Infrastructure\Payment\StitchPaymentGateway;
use CattoLearning\Support\Address\OrderAddress;
use CattoLearning\Support\Money;
use CattoPHP\Installation\Installation;
use DateTimeImmutable;
use Symfony\Component\Clock\ClockInterface;
use Throwable;

final class StitchDashboard
{
    public const LISTS = ['links' => 'Payment links', 'payments' => 'Payments', 'refunds' => 'Refunds', 'fees' => 'Fees'];
    public const PERIODS = ['7d' => 'Past 7 days', '30d' => 'Past 30 days', '90d' => 'Past 90 days', '1y' => 'Past year'];
    private const SINCE = ['7d' => '-7 days', '30d' => '-30 days', '90d' => '-90 days', '1y' => '-1 year'];
    public const PAGE = 50;

    public function __construct(
        private readonly CommerceRepository $records,
        private readonly Installation $installation,
        private readonly ClockInterface $clock,
        private readonly ?StitchPaymentGateway $stitch = null,
    ) {
    }

    /**
     * The page: the account, and one page of the chosen list for the period.
     *
     * @return array<string,mixed>
     */
    public function view(string $list, string $period, string $cursor): array
    {
        $list = isset(self::LISTS[$list]) ? $list : 'links';
        $period = isset(self::PERIODS[$period]) ? $period : '30d';
        $cursor = preg_match('/^[A-Za-z0-9_=\-]{1,500}$/', $cursor) === 1 ? $cursor : '';
        $view = ['list' => $list, 'period' => $period, 'cursor' => $cursor, 'lists' => self::LISTS, 'periods' => self::PERIODS, 'problem' => null, 'account' => null, 'rows' => [], 'next' => null, 'error' => null];
        if ($this->stitch === null) {
            return ['problem' => 'Card payments through Stitch are not set up in this installation.'] + $view;
        }
        $problem = $this->stitch->problem();
        $kind = $this->stitch->kind();
        $view['account'] = ['kind' => $kind, 'return_address' => $this->stitch->returnAddress(), 'webhook_secret' => $this->stitch->hasWebhookSecret()];
        if ($kind === '' || ($problem !== null && str_starts_with($problem, 'Enter '))) {
            return ['problem' => $problem] + $view;
        }
        try {
            $account = $this->stitch->account();
            $addresses = $this->stitch->returnAddresses();
        } catch (Throwable $failed) {
            return ['error' => 'Stitch did not answer: ' . $failed->getMessage()] + $view;
        }
        $view['account'] += [
            'balance' => $account['balance'] === null ? '' : Money::strictMinorUnits($account['balance'], 'ZAR')->format(),
            'bank' => $account['bank'] === null ? null : ['name' => $account['bank']['name'], 'bank' => strtoupper($account['bank']['bank']), 'ending' => substr($account['bank']['number'], -4)],
            'addresses' => $addresses,
            'return_registered' => in_array($this->stitch->returnAddress(), $addresses, true),
        ];
        $view['problem'] = $problem;
        try {
            $page = $this->stitch->page($list, $this->clock->now()->modify(self::SINCE[$period]), $cursor, self::PAGE);
        } catch (Throwable $failed) {
            return ['error' => 'Stitch did not give the ' . strtolower(self::LISTS[$list]) . ': ' . $failed->getMessage()] + $view;
        }
        $view['rows'] = $this->rows($list, $page['items']);
        $view['next'] = $page['next'];

        return $view;
    }

    /**
     * Each record as the page shows it, with what this site holds of it.
     *
     * @param list<array<string,mixed>> $items
     * @return list<array<string,mixed>>
     */
    private function rows(string $list, array $items): array
    {
        $ids = static fn (string $key): array => array_values(array_unique(array_filter(array_map(static fn (array $item): string => is_string($item[$key] ?? null) ? $item[$key] : '', $items))));
        $matches = $this->records->stitchMatches(
            StitchPaymentGateway::ID,
            $list === 'links' ? $ids('id') : [],
            match ($list) { 'payments' => $ids('id'), 'refunds', 'fees' => $ids('paymentId'), default => [] },
            $list === 'refunds' ? $ids('id') : [],
        );
        $rows = [];
        foreach ($items as $item) {
            $id = self::text($item['id'] ?? '');
            $paymentId = self::text($item['paymentId'] ?? '');
            $match = match ($list) {
                'links' => isset($matches['links'][$id]) ? $this->order($matches['links'][$id]['order_id'], 'card payment ' . self::state($matches['links'][$id]['state'])) : null,
                'payments' => isset($matches['payments'][$id]) ? $this->order($matches['payments'][$id]['order_id'], 'card payment ' . self::state($matches['payments'][$id]['state'])) : null,
                'refunds' => isset($matches['refunds'][$id]) ? $this->order($matches['refunds'][$id]['order_id'], 'refund recorded as paid') : (isset($matches['payments'][$paymentId]) ? $this->order($matches['payments'][$paymentId]['order_id'], 'refund not recorded here') : null),
                default => isset($matches['payments'][$paymentId]) ? $this->order($matches['payments'][$paymentId]['order_id'], 'fee on its card payment') : null,
            };
            $fee = is_array($item['fee'] ?? null) ? $item['fee'] : null;
            $card = is_array($item['cardDetail'] ?? null) ? $item['cardDetail'] : null;
            $rows[] = [
                'id' => $id,
                'when' => $this->when(self::text($item[$list === 'payments' ? 'paidAt' : 'createdAt'] ?? '')),
                'paid' => $this->when(self::text($item['paidAt'] ?? '')),
                'expires' => $this->when(self::text($item['expireAt'] ?? '')),
                'reference' => self::text($item['merchantReference'] ?? ''),
                'payer' => self::text($item['payerName'] ?? ''),
                'amount' => Money::strictMinorUnits((int) ($item['amount'] ?? 0), 'ZAR')->format(),
                'status' => self::text($item['status'] ?? $item['type'] ?? ''),
                'tone' => match (self::text($item['status'] ?? '')) { 'PAID', 'SETTLED', 'PROCESSED' => 'success', 'EXPIRED', 'CANCELLED', 'FAILED' => 'danger', default => 'neutral' },
                'type' => self::text($item['type'] ?? ''),
                'payment' => $paymentId,
                'fee' => $fee !== null && is_numeric($fee['amount'] ?? null) ? Money::strictMinorUnits((int) $fee['amount'], 'ZAR')->format() : '',
                'card' => $card !== null && is_string($card['last4'] ?? null) ? '•••• ' . $card['last4'] : '',
                'match' => $match,
            ];
        }

        return $rows;
    }

    /** @return array{label:string,href:string,note:string} */
    private function order(int $orderId, string $note): array
    {
        return ['label' => OrderNumber::format($orderId), 'href' => OrderAddress::admin($orderId), 'note' => $note];
    }

    private static function state(string $state): string
    {
        return match ($state) { 'pending' => 'waiting', 'partially_refunded' => 'partly refunded', default => $state };
    }

    private function when(string $iso): string
    {
        if ($iso === '') {
            return '';
        }
        try {
            return $this->installation->localTime(new DateTimeImmutable($iso))->format('j M Y H:i');
        } catch (Throwable) {
            return $iso;
        }
    }

    private static function text(mixed $value): string
    {
        return is_string($value) ? $value : (is_int($value) || is_float($value) ? (string) $value : '');
    }
}
