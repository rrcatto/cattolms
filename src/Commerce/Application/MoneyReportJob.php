declare(strict_types=1);

namespace CattoLearning\Commerce\Application;

use CattoLearning\Commerce\Infrastructure\MoneyReportRepository;
use CattoLearning\Configuration\SiteOwner;
use CattoLearning\Infrastructure\Mail\MailerInterface;
use CattoLearning\Infrastructure\Persistence\TransactionManager;
use CattoLearning\Mailing\MailingSettings;
use CattoLearning\OwnerMessages\OwnerMessageRepository;
use CattoLearning\OwnerMessages\OwnerMessages;
use CattoLearning\OwnerMessages\OwnerMessageSettings;
use CattoLearning\Support\Env;
use DateTimeImmutable;
use DateTimeZone;
use Symfony\Component\Clock\ClockInterface;
use Throwable;

final class MoneyReportJob
{
    /** How long an email that could not go is tried again, from the 1st. */
    private const TRY_FOR_DAYS = 7;

    public function __construct(
        private readonly MoneyReports $reports,
        private readonly MoneyReportFiles $files,
        private readonly MoneyReportSettings $settings,
        private readonly MoneyReportRepository $sends,
        private readonly MailerInterface $mailer,
        private readonly SiteOwner $owner,
        private readonly MailingSettings $mailing,
        private readonly OwnerMessages $ownerMessages,
        private readonly OwnerMessageRepository $messages,
        private readonly OwnerMessageSettings $telegram,
        private readonly TransactionManager $transactions,
        private readonly ClockInterface $clock,
    ) {
    }

    private function now(): DateTimeImmutable
    {
        return DateTimeImmutable::createFromInterface($this->clock->now())->setTimezone(new DateTimeZone(date_default_timezone_get()));
    }

    /** The start of the sending hours, "07:00", or midnight when they are around the clock. */
    public function startsAt(): string
    {
        $rules = $this->mailing->rules();

        return (string) $rules['send_from'] === (string) $rules['send_until'] ? '00:00' : (string) $rules['send_from'];
    }

    /** When this month's 1st reaches the start of the sending hours. */
    private function markOf(DateTimeImmutable $month): DateTimeImmutable
    {
        [$hour, $minute] = array_map('intval', explode(':', $this->startsAt()));

        return $month->modify('first day of this month')->setTime($hour, $minute);
    }

    public function run(): string
    {
        $now = $this->now();
        $thisMonth = $now->modify('first day of this month')->setTime(0, 0);
        $month = $thisMonth->modify('-1 month');
        $key = $month->format('Y-m');
        $label = $month->format('F Y');
        $mark = $this->markOf($thisMonth);
        $known = $this->sends->send($month->format('Y-m-d'));
        if ($known !== null && $known['email'] !== 'waiting' && $known['telegram'] !== 'waiting') return $label . '\'s report is done: ' . self::outcome($known) . '.';
        if ($now < $mark) return 'Not yet: ' . $label . '\'s report goes on ' . $mark->format('j F Y \a\t H:i') . '.';
        // A month is claimed on the 1st only: a site that was down all that day sends nothing late, as no reader expects it.
        if ($known === null && $now->format('j') !== '1') return 'Nothing is due: ' . $thisMonth->format('F Y') . '\'s report goes on ' . $this->markOf($thisMonth->modify('first day of next month'))->format('j F Y \a\t H:i') . '.';
        if (!$this->mailing->withinSendingHours($now)) return 'Waiting for the sending hours to send ' . $label . '\'s report.';

        return $this->transactions->run(function () use ($month, $key, $label, $now, $mark): string {
            $ticks = $this->settings->saved();
            $this->sends->claim($month->format('Y-m-d'), $ticks['email'] ? 'waiting' : 'off', !$ticks['telegram'] ? 'off' : ($this->telegram->connected() ? 'waiting' : 'not_connected'));
            $send = $this->sends->lock($month->format('Y-m-d')) ?? throw new \RuntimeException('The month\'s report could not be claimed.');
            if ($send['email'] !== 'waiting' && $send['telegram'] !== 'waiting') return $label . '\'s report is done: ' . self::outcome($send) . '.';
            $report = $this->reports->report($key);
            $done = [];
            if ($send['email'] === 'waiting') {
                $to = trim($this->owner->value('email'));
                try {
                    if (filter_var($to, FILTER_VALIDATE_EMAIL) === false) throw new \RuntimeException('There is no administrator address to send it to: set APP_ADMIN_EMAIL, or the Site Owner\'s email address in Settings.');
                    $this->email($to, $report);
                    $this->sends->emailed($month->format('Y-m-d'), $to);
                    $done[] = 'emailed to ' . $to;
                } catch (Throwable $failed) {
                    $givenUp = $now >= $mark->modify('+' . self::TRY_FOR_DAYS . ' days');
                    $this->sends->emailFailed($month->format('Y-m-d'), $failed->getMessage(), $givenUp);
                    $done[] = ($givenUp ? 'not emailed, and no longer tried: ' : 'not emailed yet, tried again next minute: ') . $failed->getMessage();
                }
            }
            if ($send['telegram'] === 'waiting') {
                $this->messages->record('money_report:' . $key, 'money_report', $this->ownerMessages->worded(MoneyReports::summaryLine($report)));
                $this->sends->telegramSent($month->format('Y-m-d'));
                $done[] = 'its line kept for Telegram';
            }

            return $label . '\'s report ' . implode(', and ', $done) . '.';
        });
    }

    /**
     * The email and its two files.
     *
     * @param array<string,mixed> $report
     */
    private function email(string $to, array $report): void
    {
        $lines = [];
        foreach ($report['figures'] as $figure) {
            $lines[] = ['label' => (string) $figure['label'], 'value' => (string) $figure['value'], 'note' => (string) $figure['note']];
        }
        $this->mailer->sendMoneyReport($to, [
            'month' => (string) $report['month']['label'],
            'lines' => $lines,
            'no_sales' => $report['no_sales'] ? 'No sales in ' . $report['month']['label'] . '.' : '',
            'url' => rtrim(Env::string('APP_URL'), '/') . '/admin/commerce/reports?month=' . $report['month']['key'],
        ], [
            MoneyReportFiles::name($report, 'pdf') => $this->files->pdf($report),
            MoneyReportFiles::name($report, 'xlsx') => $this->files->excel($report),
        ]);
    }

    /** @param array<string,mixed> $send */
    private static function outcome(array $send): string
    {
        $email = match ((string) $send['email']) {
            'sent' => 'emailed to ' . $send['emailed_to'],
            'off' => 'not emailed, Email the report was off',
            'failed' => 'not emailed: ' . (string) $send['last_error'],
            default => 'not emailed yet',
        };
        $telegram = match ((string) $send['telegram']) {
            'sent' => 'its line kept for Telegram',
            'off' => 'no Telegram line, the summary was off',
            'not_connected' => 'no Telegram line, Telegram was not connected',
            default => 'its Telegram line not kept yet',
        };

        return $email . ', ' . $telegram;
    }

    /**
     * What the page says under the ticks: what became of the month shown, and when the next report goes.
     *
     * @return array{email:bool,telegram:bool,connected:bool,address:string,starts:string,sent:string,next:string}
     */
    public function status(string $monthKey): array
    {
        $ticks = $this->settings->saved();
        $now = $this->now();
        $next = $this->markOf($now->modify('first day of this month')->setTime(0, 0));
        if ($next <= $now) $next = $this->markOf($now->modify('first day of next month')->setTime(0, 0));
        $nextMonth = $next->modify('-1 month')->format('F Y');
        $label = (new DateTimeImmutable($monthKey . '-01'))->format('F Y');
        $send = $this->sends->send($monthKey . '-01');
        $at = static fn(mixed $when): string => is_string($when) ? (new DateTimeImmutable($when))->setTimezone(new DateTimeZone(date_default_timezone_get()))->format('j F Y \a\t H:i') : '';
        $sent = match (true) {
            $send === null => '',
            $send['email'] === 'sent' => $label . '\'s report was emailed to ' . $send['emailed_to'] . ' on ' . $at($send['emailed_at']) . ($send['telegram'] === 'sent' ? ', and its line sent by Telegram.' : '.'),
            $send['email'] === 'failed' => $label . '\'s report could not be emailed: ' . $send['last_error'],
            $send['email'] === 'waiting' => $label . '\'s report is waiting to be emailed' . ((string) ($send['last_error'] ?? '') !== '' ? ': ' . $send['last_error'] : '.'),
            $send['telegram'] === 'sent' => $label . '\'s line was sent by Telegram on ' . $at($send['telegram_at']) . '.',
            default => $label . '\'s report was not sent: both ticks were off.',
        };
        $going = $ticks['email'] || ($ticks['telegram'] && $this->telegram->connected());

        return ['email' => $ticks['email'], 'telegram' => $ticks['telegram'], 'connected' => $this->telegram->connected(), 'address' => trim($this->owner->value('email')),
            'starts' => $this->startsAt(), 'sent' => $sent,
            'next' => $going ? $nextMonth . '\'s report goes on ' . $next->format('j F Y \a\t H:i') . '.' : 'Nothing goes on the 1st while both are off.'];
    }
}
