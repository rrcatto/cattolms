Money Reports on the 1st (owner, 2026-11-06, the approved mockup): from the start of the mailing sending hours on the 1st of
each month, last month's report is emailed to the administrator address (APP_ADMIN_EMAIL, as the Site Owner's email is
found) with its PDF and Excel file attached, while Email the report is ticked; and its one line (money in, what is left,
orders paid) goes by the owner's Telegram, while Telegram summary is ticked and Telegram is connected, through the owner's
messages, so the Telegram log records it. A month with no sales still goes, saying so. A month is claimed on the 1st
only, so a scheduler started later in the month never sends last month's report as a surprise; the page always has it.

Each month goes once. It is claimed (money_report_sends) before anything is sent, with what each tick said at that moment,
and locked while it is sent, so a restart or a second scheduler never sends it twice, and a tick turned on later never
sends a month whose moment has passed. An email that could not go is tried again each minute within the sending hours,
and no more after a week. The scheduler's money_report job runs this every minute.

