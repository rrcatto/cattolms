declare(strict_types=1);

namespace CattoLearning\Mcp;

use CattoLearning\Course\CatalogueFilter;
use CattoPHP\Api\ApiIdentity;
use CattoLearning\Api\ApiScope;
use CattoPHP\Api\ApiAccess;
use CattoLearning\Course\CourseService;
use CattoLearning\Course\LearningService;
use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoPHP\Ui\Pagination;
use InvalidArgumentException;

final class LmsMcpTools
{
    public function __construct(
        private readonly ApiIdentity $identity,
        private readonly ApiAccess $authorization,
        private readonly CourseService $courses,
        private readonly LearningService $learning,
        private readonly AuditRepository $audit
    ) {
    }

    /** @return array<string,mixed> */
    public function status(): array
    {
        return [
            'application' => 'Catto Learning',
            'application_version' => \CattoLearning\Support\AppVersion::current(),
            'mcp_transport' => 'stdio',
            'identity' => \CattoLearning\Api\ApiPerson::toArray($this->identity),
        ];
    }

    /**
     * Lists the published catalogue one bounded page at a time.
     *
     * The page size is capped by the shared Pagination contract, so a tool call cannot ask the
     * server to materialise the entire catalogue in one response.
     *
     * @return array<string,mixed>
     */
    public function listCourses(int $page = 1, int $pageSize = 25): array
    {
        $this->authorization->requireBusinessAccess($this->identity, ApiScope::COURSES_READ, 'CATALOGUE.VIEW');

        $pagination = Pagination::create($page, $pageSize, $this->courses->catalogueCount(CatalogueFilter::none()));

        return [
            'courses' => $this->courses->catalogue(CatalogueFilter::none(), $pagination->pageSize, $pagination->offset),
            'meta' => $pagination->toArray(),
        ];
    }

    /** @return array<string,mixed> */
    public function getCourse(string $slug): array
    {
        $this->authorization->requireBusinessAccess($this->identity, ApiScope::COURSES_READ, 'CATALOGUE.VIEW');
        $course = $this->courses->publicCourse($slug);
        if ($course === null) {
            throw new InvalidArgumentException('The course could not be found.');
        }

        return $course;
    }

    /** @return list<array<string,mixed>> */
    public function listMyLibrary(): array
    {
        $this->authorization->requireBusinessAccess($this->identity, ApiScope::LIBRARY_READ, 'LEARNING.LIBRARY.VIEW');

        return $this->learning->library(\CattoLearning\Api\ApiPerson::userId($this->identity));
    }

    /** @return array<string,mixed> */
    public function startCourse(string $slug): array
    {
        $this->authorization->requireBusinessAccess($this->identity, ApiScope::LEARNING_START, 'LEARNING.COURSE.START');
        $this->learning->start(\CattoLearning\Api\ApiPerson::userId($this->identity), $slug);
        $this->audit->record(\CattoLearning\Api\ApiPerson::userId($this->identity), 'mcp.course_started', [
            'tool' => 'start_course',
            'token_id' => $this->identity->tokenPublicId,
            'course_slug' => $slug,
        ]);

        return $this->learning->courseHome(\CattoLearning\Api\ApiPerson::userId($this->identity), $slug);
    }

    /** @return array<string,mixed> */
    public function createCourse(
        string $title,
        string $slug = '',
        string $summary = '',
        string $descriptionHtml = '',
        int $accessPeriodDays = 365
    ): array {
        $this->authorization->requireBusinessAccess(
            $this->identity,
            ApiScope::COURSES_WRITE,
            'COURSE.CREATE'
        );
        $courseId = $this->courses->createBlank([
            'title' => $title,
            'slug' => $slug,
            'summary' => $summary,
            'description_html' => $descriptionHtml,
            'access_days' => max(1, $accessPeriodDays),
            'certificate_enabled' => true,
        ], \CattoLearning\Api\ApiPerson::userId($this->identity));
        $this->audit->record(\CattoLearning\Api\ApiPerson::userId($this->identity), 'mcp.course_created', [
            'tool' => 'create_course',
            'token_id' => $this->identity->tokenPublicId,
            'course_id' => $courseId,
        ]);

        return $this->courses->adminCourse($courseId);
    }

    /**
     * The course is named by its code, such as GDN-101 (owner, 2026-11-06: a course is its code, never its row id).
     *
     * @return array<string,mixed>
     */
    public function setCourseStatus(string $courseCode, string $status): array
    {
        $this->authorization->requireBusinessAccess(
            $this->identity,
            ApiScope::COURSES_PUBLISH,
            'COURSE.PUBLISH'
        );
        $courseId = $this->courses->courseIdForCode(\CattoLearning\Course\CourseCode::normalise($courseCode))
            ?? throw new \InvalidArgumentException('No course has the code ' . $courseCode . '.');
        $this->courses->changeStatus(
            $courseId,
            $status,
            \CattoLearning\Api\ApiPerson::userId($this->identity)
        );
        $this->audit->record(\CattoLearning\Api\ApiPerson::userId($this->identity), 'mcp.course_status_changed', [
            'tool' => 'set_course_status',
            'token_id' => $this->identity->tokenPublicId,
            'course_id' => $courseId,
            'status' => $status,
        ]);

        return $this->courses->adminCourse($courseId);
    }
}
