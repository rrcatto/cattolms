declare(strict_types=1);

namespace CattoLearning\Plugin;

use Psr\Container\ContainerInterface;
use RuntimeException;

final class PluginManager
{
    /** @var list<PluginInterface> */
    private array $plugins = [];

    /** @param list<class-string<PluginInterface>> $pluginClasses */
    public function __construct(
        private readonly ContainerInterface $container,
        private readonly array $pluginClasses
    ) {
    }

    public function boot(PluginContext $context): void
    {
        $keys = [];
        foreach ($this->pluginClasses as $class) {
            if (!class_exists($class)) {
                throw new RuntimeException('Plugin class does not exist: ' . $class);
            }
            $plugin = $this->container->get($class);
            if (!$plugin instanceof PluginInterface) {
                throw new RuntimeException('Plugin must implement PluginInterface: ' . $class);
            }
            if (isset($keys[$plugin->key()])) {
                throw new RuntimeException('Duplicate plugin key: ' . $plugin->key());
            }
            $keys[$plugin->key()] = true;
            $plugin->boot($context);
            $this->plugins[] = $plugin;
        }
    }

    /** @return list<array{key:string,version:string}> */
    public function inventory(): array
    {
        return array_map(
            static fn(PluginInterface $plugin): array => ['key' => $plugin->key(), 'version' => $plugin->version()],
            $this->plugins
        );
    }
