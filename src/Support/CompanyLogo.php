declare(strict_types=1);

namespace CattoLearning\Support;

use CattoLearning\View\Artwork\UploadedSvg;
use InvalidArgumentException;
use RuntimeException;

final class CompanyLogo
{
    /** The largest side of a stored raster logo, in pixels. */
    public const BOX = 512;
    /** Largest upload accepted, in bytes. */
    public const MAX_UPLOAD_BYTES = 8 * 1024 * 1024;
    private const MAX_SOURCE_PIXELS = 8000 * 8000;
    private const RASTER = [IMAGETYPE_PNG, IMAGETYPE_JPEG, IMAGETYPE_WEBP];

    private function __construct(
        public readonly string $bytes,
        public readonly string $mimeType,
        public readonly ?int $width,
        public readonly ?int $height,
    ) {
    }

    public static function fromUpload(string $bytes): self
    {
        if ($bytes === '') {
            throw new RuntimeException('No logo was received. Please choose a file and try again.');
        }
        if (strlen($bytes) > self::MAX_UPLOAD_BYTES) {
            throw new RuntimeException('That logo is larger than 8 MB. Please choose a smaller file.');
        }
        if (preg_match('/^\s*(?:\xEF\xBB\xBF)?\s*(?:<\?xml[^>]*>\s*)?(?:<!--.*?-->\s*)*(?:<!DOCTYPE[^>]*>\s*)?<svg[\s>]/is', $bytes) === 1) {
            try {
                $svg = UploadedSvg::validate($bytes, UploadedSvg::LOGO_BYTES, 'logo');
            } catch (InvalidArgumentException $refused) {
                throw new RuntimeException($refused->getMessage(), 0, $refused);
            }

            return new self($svg, 'image/svg+xml', null, null);
        }
        if (!ImageProcessing::available()) {
            throw new RuntimeException(ImageProcessing::UNAVAILABLE);
        }
        $info = @getimagesizefromstring($bytes);
        if ($info === false || !in_array($info[2], self::RASTER, true)) {
            throw new RuntimeException('That file is not an SVG, PNG, JPEG or WebP image.');
        }
        [$width, $height] = [(int) $info[0], (int) $info[1]];
        if ($width < 1 || $height < 1 || $width * $height > self::MAX_SOURCE_PIXELS) {
            throw new RuntimeException('That logo has too many pixels to process. Please choose a smaller one.');
        }
        $source = @imagecreatefromstring($bytes);
        if ($source === false) {
            throw new RuntimeException('That logo could not be read. It may be damaged.');
        }
        // Fitted inside the box, never cropped and never enlarged.
        $scale = min(1.0, self::BOX / max($width, $height));
        $fitWidth = max(1, (int) round($width * $scale));
        $fitHeight = max(1, (int) round($height * $scale));
        $fitted = imagecreatetruecolor($fitWidth, $fitHeight);
        if ($fitted === false) {
            throw new RuntimeException('That logo could not be read. It may be damaged.');
        }
        imagealphablending($fitted, false);
        imagesavealpha($fitted, true);
        imagefill($fitted, 0, 0, (int) imagecolorallocatealpha($fitted, 0, 0, 0, 127));
        imagecopyresampled($fitted, $source, 0, 0, 0, 0, $fitWidth, $fitHeight, $width, $height);
        ob_start();
        imagepng($fitted, null, 9);
        $png = (string) ob_get_clean();

        return new self($png, 'image/png', $fitWidth, $fitHeight);
    }
}
