<?php

/*
Generated by: Claude Code CLI

Date time: 2026/11/12 SAST

Version: 1.2.0

Description:
Position numbers in bands, for the catalogue's courses and for bundles (owner, 2026-11-12: "number them from 100 with
increments of 100", a band for each code prefix, "the renumber position number function needs to keep all the numbers
within their band"; bands 10,000 apart, owner: "I will go with your suggestion of using 10 000"). Pure: it works out
numbers and changes nothing.

A band belongs to a code prefix (the code before its first hyphen) and runs from its start up to the next band's start;
the last runs on without end. Settings saves only the starts, so bands can never overlap or leave a hole.

- next(): the number something arriving without one takes, 100 after the highest in its band.
- place(): the numbers a move needs, where a drag or the ⋯ menu put something: halfway between its new neighbours, or,
  with no whole number between them, it and the crowded run below it spread evenly up to the next number with room, so a
  move never renumbers the whole list and never carries a number out of its band.
- renumber(): every banded thing back in its band from the band's start, 100 apart in its present order (closer together
  when a band holds more than its width allows), and what has no band left as it is.

Changelog:
2026/11/12 SAST
- Created, from Course\CataloguePositions::next() and the course list's drag (CourseService::arrangeInCatalogue).
*/

declare(strict_types=1);

namespace CattoLearning\Support;

final class PositionBands
{
    /** How far apart things are numbered (owner, 2026-11-01 and 2026-11-12: "increments of 100"). */
    public const STEP = 100;
    /** A spread made by a move leaves at least this much between neighbours, so the next moves still find room. */
    private const ROOMY = 10;

    /** The highest number a position may have. */
    public const HIGHEST = 2000000000;

    /**
     * A position as typed: empty for none, else a whole number from 1; $refusal says what to type instead.
     *
     * @throws \InvalidArgumentException
     */
    public static function typed(mixed $value, string $refusal): ?int
    {
        $text = trim((string) (is_scalar($value) ? $value : ''));
        if ($text === '') return null;
        if (preg_match('/^[0-9]{1,10}$/', $text) !== 1 || (int) $text < 1 || (int) $text > self::HIGHEST) throw new \InvalidArgumentException($refusal);
        return (int) $text;
    }

    /** A code's prefix: the code before its first hyphen, in capitals; a code without a hyphen is its own prefix. */
    public static function prefixOf(string $code): string
    {
        return strtoupper(explode('-', trim($code), 2)[0]);
    }

    /**
     * The band of a prefix: its start and the next band's start (null for the last, which runs on without end).
     *
     * @param array<string,int> $ranges prefix => start
     * @return array{0:int,1:?int}|null
     */
    public static function band(array $ranges, string $prefix): ?array
    {
        if (!isset($ranges[$prefix])) return null;
        $start = $ranges[$prefix];
        $end = null;
        foreach ($ranges as $other) {
            if ($other > $start && ($end === null || $other < $end)) $end = $other;
        }
        return [$start, $end];
    }

    /**
     * How a band reads in Settings: "10000 to 19999, room for 100", or "from 80000, without end" for the last.
     *
     * @param array<string,int> $ranges
     */
    public static function words(array $ranges, string $prefix): string
    {
        $band = self::band($ranges, $prefix);
        if ($band === null) return '';
        [$start, $end] = $band;
        if ($end === null) return 'from ' . $start . ', without end';
        $room = intdiv($end - $start, self::STEP);
        return $start . ' to ' . ($end - 1) . ', room for ' . $room;
    }

    /**
     * The number something with this code takes when it arrives without one: the next free number in its prefix's band,
     * 100 after the highest there (the start itself when nothing is), halfway to the next band when the band is full, or
     * null when its prefix has no band or no whole number is left.
     *
     * @param array<string,int> $ranges
     * @param list<int> $positions every number in use now
     */
    public static function next(array $ranges, string $code, array $positions): ?int
    {
        $band = self::band($ranges, self::prefixOf($code));
        if ($band === null) return null;
        [$start, $end] = $band;
        $inside = array_filter($positions, static fn(int $position): bool => $position >= $start && ($end === null || $position < $end));
        if ($inside === []) return $start;
        $highest = max($inside);
        $next = $highest + self::STEP;
        if ($end === null || $next < $end) return $next;
        // Full: halfway to the next band while there is a whole number between them.
        return $end - $highest >= 2 ? intdiv($highest + $end, 2) : null;
    }

    /**
     * The numbers a move needs. $numbers is the whole list in its new order, the moved thing at $index (its own number is
     * not read); everything without a number comes last. Answers each index whose number must change: the moved one
     * halfway between its neighbours, or 100 after the one above it at the end; with no whole number between them, it and
     * the crowded run below it spread evenly up to the next number with room; dropped among things without a number, it
     * and those above it numbered on from the last number, 100 apart.
     *
     * @param list<?int> $numbers
     * @return array<int,int> index => its new number
     */
    public static function place(array $numbers, int $index): array
    {
        $count = count($numbers);
        $at = static fn(int $i): ?int => $i >= 0 && $i < $count && $i !== $index ? $numbers[$i] : null;
        // Among the unnumbered tail: number it and the unnumbered ones above it on from the last number.
        if ($index > 0 && $at($index - 1) === null) {
            $last = $index - 1;
            while ($last >= 0 && $at($last) === null) $last--;
            $from = $last >= 0 ? (int) $at($last) : 0;
            $changes = [];
            for ($i = $last + 1, $n = 1; $i <= $index; $i++, $n++) $changes[$i] = $from + $n * self::STEP;
            return $changes;
        }
        $low = $index > 0 ? (int) $at($index - 1) : 0;
        $high = $at($index + 1);
        if ($high === null) return [$index => $low + self::STEP];
        if ($high - $low >= 2) return [$index => intdiv($low + $high, 2)];
        // Crowded: widen the run below it, one neighbour at a time, until it fits roomily before the next number (at worst the
        // next band's first), so the numbers above stay and nothing leaves its band.
        $left = $index - 1;
        $right = $index + 1;
        $low = $left >= 0 ? (int) $at($left) : 0;
        while (true) {
            $high = $at($right);
            $inside = $right - $left - 1;
            if ($high === null) {
                $changes = [];
                for ($i = $left + 1, $n = 1; $i < $right; $i++, $n++) $changes[$i] = $low + $n * self::STEP;
                return self::changed($numbers, $changes, $index);
            }
            $gap = intdiv($high - $low, $inside + 1);
            if ($gap >= self::ROOMY) {
                $changes = [];
                for ($i = $left + 1, $n = 1; $i < $right; $i++, $n++) $changes[$i] = $low + $n * $gap;
                return self::changed($numbers, $changes, $index);
            }
            $right++;
        }
    }

    /**
     * Every banded thing back in its band, in its present order: from the band's start, 100 apart, or as far apart as the
     * band allows when it holds more than its width at 100. What has no band keeps its number; a band too narrow for a
     * whole number each is left as it is and named.
     *
     * @template K of int|string
     * @param array<string,int> $ranges
     * @param list<array{key:K,code:string,position:?int}> $items in their present order, unnumbered last
     * @return array{changes:array<K,int>,unbanded:list<K>,crowded:list<string>}
     */
    public static function renumber(array $ranges, array $items): array
    {
        $groups = [];
        $unbanded = [];
        foreach ($items as $item) {
            $prefix = self::prefixOf($item['code']);
            if (isset($ranges[$prefix])) $groups[$prefix][] = $item; else $unbanded[] = $item['key'];
        }
        $changes = [];
        $crowded = [];
        foreach ($groups as $prefix => $members) {
            [$start, $end] = self::band($ranges, $prefix) ?? [0, null];
            $step = self::STEP;
            if ($end !== null && count($members) * self::STEP > $end - $start) $step = intdiv($end - $start, count($members));
            if ($step < 1) { $crowded[] = $prefix; continue; }
            foreach ($members as $n => $item) {
                $number = $start + $n * $step;
                if ($item['position'] !== $number) $changes[$item['key']] = $number;
            }
        }
        return ['changes' => $changes, 'unbanded' => $unbanded, 'crowded' => $crowded];
    }

    /**
     * Words for a Renumber's outcome, as its page says them.
     *
     * @param array{changed:int,unbanded:list<string>,crowded:list<string>} $result
     */
    public static function outcome(array $result, string $things): string
    {
        $words = $result['changed'] === 0 ? 'Every ' . $things . ' was already numbered in its band.' : $result['changed'] . ' ' . $things . ($result['changed'] === 1 ? ' was' : 's were') . ' renumbered in their bands.';
        if ($result['unbanded'] !== []) $words .= ' No band for ' . implode(', ', $result['unbanded']) . ', so ' . (count($result['unbanded']) === 1 ? 'it keeps its number' : 'they keep their numbers') . ': give their prefix a band in Settings to number them too.';
        if ($result['crowded'] !== []) $words .= ' The band of ' . implode(', ', $result['crowded']) . ' is too narrow for a number each, so it was left as it was: move the next band\'s start further up.';
        return $words;
    }

    /**
     * Only the numbers that change, the moved one always.
     *
     * @param list<?int> $numbers
     * @param array<int,int> $changes
     * @return array<int,int>
     */
    private static function changed(array $numbers, array $changes, int $index): array
    {
        return array_filter($changes, static fn(int $number, int $i): bool => $i === $index || $numbers[$i] !== $number, ARRAY_FILTER_USE_BOTH);
    }
}
