declare(strict_types=1);

namespace CattoLearning\Support;

use InvalidArgumentException;

final class WasPrice
{
    /**
     * The was price as typed on a pricing form, in minor units: null when the field is empty.
     *
     * @throws InvalidArgumentException when it is not an amount or not higher than the price
     */
    public static function fromInput(mixed $input, int $priceMinor): ?int
    {
        $text = trim(str_replace([',', ' '], '', is_scalar($input) ? (string) $input : ''));
        if ($text === '') return null;
        if (preg_match('/^\d+(?:\.\d{1,2})?$/', $text) !== 1) {
            throw new InvalidArgumentException('Enter the was price as an amount with no more than two decimal places, or leave it empty.');
        }
        $minor = Money::ofMajorUnits($text)->minorUnits;
        if ($minor <= $priceMinor) {
            throw new InvalidArgumentException('The was price must be higher than the price, or left empty.');
        }
        return $minor;
    }

    /**
     * What a page shows of a price and its was price: the was price and the saving ("R600.00 (25%)"),
     * both null when there is no was price higher than the price.
     *
     * @return array{was_label:?string,saving_label:?string,saving_percent:?int}
     */
    public static function labels(int $priceMinor, mixed $wasMinor, string $currency): array
    {
        $was = $wasMinor === null || $wasMinor === '' ? null : (int) $wasMinor;
        if ($was === null || $was <= $priceMinor || $was < 1) {
            return ['was_label' => null, 'saving_label' => null, 'saving_percent' => null];
        }
        $saving = $was - $priceMinor;
        $percent = intdiv($saving * 100, $was);
        return [
            'was_label' => Money::strictMinorUnits($was, $currency)->format(),
            'saving_label' => Money::strictMinorUnits($saving, $currency)->format() . ($percent > 0 ? ' (' . $percent . '%)' : ''),
            'saving_percent' => $percent,
        ];
    }

    /** The amount a pricing form shows for a stored was price: "2400.00", or empty. */
    public static function input(mixed $wasMinor): string
    {
        return $wasMinor === null || $wasMinor === '' ? '' : number_format(((int) $wasMinor) / 100, 2, '.', '');
    }
}
