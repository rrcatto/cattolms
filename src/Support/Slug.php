namespace CattoLearning\Support;

use InvalidArgumentException;

final class Slug
{
    public static function from(string $value): string
    {
        $value = trim(mb_strtolower($value));
        if ($value === '') {
            throw new InvalidArgumentException('A slug or title is required.');
        }

        $transliterated = iconv('UTF-8', 'ASCII//TRANSLIT//IGNORE', $value);
        if (is_string($transliterated) && $transliterated !== '') {
            $value = $transliterated;
        }

        $value = preg_replace('/[^a-z0-9]+/', '-', $value) ?? '';
        $value = trim($value, '-');
        if ($value === '' || strlen($value) > 180) {
            throw new InvalidArgumentException('The generated slug is invalid.');
        }
        return $value;
    }

    public static function validate(string $value): string
    {
        $value = trim(mb_strtolower($value));
        if (preg_match('/^[a-z0-9]+(?:-[a-z0-9]+)*$/', $value) !== 1 || strlen($value) > 180) {
            throw new InvalidArgumentException('Use lowercase letters, numbers and hyphens for the slug.');
        }
        return $value;
    }
}