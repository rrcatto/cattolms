declare(strict_types=1);

namespace CattoLearning\Support;

final class HalfRows
{
    /**
     * @template T of array<string,mixed>
     * @param list<T> $blocks In page order, only those drawn, each with its width ('half', otherwise full).
     * @return list<list<T>>
     */
    public static function rows(array $blocks): array
    {
        $rows = [];
        $open = null;
        foreach ($blocks as $block) {
            $half = ($block['width'] ?? 'full') === 'half';
            if ($half && $open !== null) {
                $rows[$open][] = $block;
                $open = null;
                continue;
            }
            $rows[] = [$block];
            $open = $half ? count($rows) - 1 : null;
        }
        return $rows;
    }
}
