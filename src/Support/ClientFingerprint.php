declare(strict_types=1);

namespace CattoLearning\Support;

final class ClientFingerprint
{
    /**
     * Returns the validated client IP address reported by the web server.
     *
     * This intentionally does not trust forwarded headers; reverse-proxy IP
     * handling belongs in server configuration rather than request metadata.
     */
    public static function ipAddress(): string
    {
        $ip = trim((string) ($_SERVER['REMOTE_ADDR'] ?? ''));
        return filter_var($ip, FILTER_VALIDATE_IP) !== false ? $ip : '';
    }

    public static function ipHash(): string
    {
        $ip = self::ipAddress();
        return hash_hmac('sha256', $ip !== '' ? $ip : 'unknown', Env::string('APP_KEY'));
    }

    public static function userAgent(): string
    {
        return mb_substr(trim((string) ($_SERVER['HTTP_USER_AGENT'] ?? 'Unknown browser')), 0, 500);
    }
}