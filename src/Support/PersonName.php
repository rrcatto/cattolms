Description:
Composes a person's name from the parts a user record stores.

Architectural boundary: a pure value helper. It holds no SQL, no F3 knowledge and no route
knowledge; it takes the row and returns a string.

It exists because a name was assembled in the markup of every screen that showed one, and each
screen assembled a different name. The account profile header printed the first and last name only,
so someone whose middle names are part of how they are addressed - and who had just typed them into
the form directly below that heading - was shown a name that was not theirs.

Composed rather than concatenated: an empty middle names field left a double space in the heading,
and an identity with no name parts at all left an empty heading rather than falling back to
something the reader can recognise.

Changelog:
2026/09/07 18:40 SAST
- Created so the profile header shows every part of a person's name.
*/

declare(strict_types=1);

namespace CattoLearning\Support;

final class PersonName
{
    /**
     * Every part of the person's name, in order, with the missing parts left out.
     *
     * @param array<string,mixed> $row A user row.
     */
    public static function full(array $row): string
    {
        $parts = [];
        foreach (['first_name', 'middle_names', 'last_name'] as $field) {
            $part = trim((string) ($row[$field] ?? ''));
            if ($part !== '') {
                $parts[] = $part;
            }
        }

        if ($parts !== []) {
            return implode(' ', $parts);
        }

        // A record with no name parts still has to be addressable on screen. The display name is
        // what the person chose to be called; the primary email is the last thing that is certainly
        // present, because an identity cannot exist without one.
        $fallback = trim((string) ($row['display_name'] ?? ''));
        if ($fallback !== '') {
            return $fallback;
        }

        // The address, under either of the two names a user row carries it by. A profile row joins
        // it as primary_email; a listing row calls it email. Checking only one of them is why a
        // person with no name at all rendered an empty heading.
        foreach (['primary_email', 'email'] as $key) {
            $address = trim((string) ($row[$key] ?? ''));
            if ($address !== '') {
                return $address;
            }
        }

        return '';
    }
}
