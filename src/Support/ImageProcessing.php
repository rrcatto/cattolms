declare(strict_types=1);

namespace CattoLearning\Support;

/** Support check: reports whether GD is loaded and logs its absence; it processes nothing itself. */
final class ImageProcessing
{
    /** Shown to the person whose upload could not be processed. */
    public const UNAVAILABLE = 'Pictures cannot be processed on this server: its PHP has no GD extension. The site administrator needs to install it.';

    /** True when GD is loaded; otherwise logs what to install and returns false. */
    public static function available(): bool
    {
        if (extension_loaded('gd')) {
            return true;
        }
        error_log('CattoLMS: the PHP GD extension is not loaded, so pictures cannot be processed. Install it for the PHP that serves the site (for example php8.5-gd) and restart PHP-FPM.');
        return false;
    }
}
