Version: 0.8.8.13

Description:
Whether this server can process pictures. Profile images and certificate pictures are decoded and
resized with PHP's GD extension. composer.json requires it, so `composer install` refuses a server
without it, but an installation made before that requirement, or a PHP upgrade that left the
extension behind, still runs: without this check an upload ends in "Call to undefined function
imagecreatefromstring()" and an HTTP 500. With it, the person uploading reads what is wrong and the
log says what to install.

Changelog:
2026/10/07 SAST
- Created after a VPS without GD answered a profile image upload with HTTP 500.
