declare(strict_types=1);

namespace CattoLearning\Support;

use InvalidArgumentException;

final class DomainName
{
    public static function normalize(string $domain): string
    {
        $domain = strtolower(trim($domain));
        $domain = rtrim($domain, '.');
        if (str_contains($domain, '://') || str_contains($domain, '/') || str_contains($domain, '@')) {
            throw new InvalidArgumentException('Enter a domain name only, without a URL, path or email address.');
        }
        if (strlen($domain) > 253 || preg_match('/^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/', $domain) !== 1) {
            throw new InvalidArgumentException('Enter a valid registered domain name.');
        }
        return $domain;
    }
}