declare(strict_types=1);

namespace CattoLearning\Support\Address;

use InvalidArgumentException;

final class PersonAddress
{
    /** An account reference as the site stores it: the prefix, the date, the number and the check character. */
    public const REQUIREMENT = '[A-Z]{1,3}[0-9]{12,26}[0-9A-Z]';

    private function __construct()
    {
    }

    /**
     * The person's account reference: a reference itself, or a row's account_reference.
     *
     * @param array<string,mixed>|string $person
     */
    public static function key(array|string $person): string
    {
        return AddressKey::read($person, ['account_reference'], self::REQUIREMENT, 'a person');
    }

    /**
     * The person in Administration: /admin/people/CL2026011510423Z, with what follows it (/status, #identity).
     *
     * @param array<string,mixed>|string $person
     */
    public static function admin(array|string $person, string $rest = ''): string
    {
        return '/admin/people/' . self::key($person) . $rest;
    }

    /**
     * The person in the Company workspace: /company/people/CL2026011510423Z.
     *
     * @param array<string,mixed>|string $person
     */
    public static function company(array|string $person, string $rest = ''): string
    {
        return '/company/people/' . self::key($person) . $rest;
    }

    /**
     * The person's other addresses by place: subscriber (Mailing > Subscribers) and wallet (Administration > Wallets).
     *
     * @param array<string,mixed>|string $person
     */
    public static function to(string $place, array|string $person): string
    {
        return match ($place) {
            'subscriber' => '/mailing/subscribers/' . self::key($person),
            'wallet' => '/admin/wallets/person/' . self::key($person),
            default => throw new InvalidArgumentException('There is no person address called "' . $place . '".'),
        };
    }
}
