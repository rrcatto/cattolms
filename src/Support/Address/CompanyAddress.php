declare(strict_types=1);

namespace CattoLearning\Support\Address;

use InvalidArgumentException;

final class CompanyAddress
{
    /** A company's account reference, shaped as a person's. */
    public const REQUIREMENT = PersonAddress::REQUIREMENT;

    private function __construct()
    {
    }

    /**
     * The company's account reference: a reference itself, or a row's account_reference (company_reference where the
     * row is something else's).
     *
     * @param array<string,mixed>|string $company
     */
    public static function key(array|string $company): string
    {
        return AddressKey::read($company, ['company_reference', 'account_reference'], self::REQUIREMENT, 'a company');
    }

    /**
     * The company in Administration: /admin/companies/CL2026011510418T, with what follows it.
     *
     * @param array<string,mixed>|string $company
     */
    public static function admin(array|string $company, string $rest = ''): string
    {
        return '/admin/companies/' . self::key($company) . $rest;
    }

    /**
     * The company's other addresses by place: wallet (Administration > Wallets).
     *
     * @param array<string,mixed>|string $company
     */
    public static function to(string $place, array|string $company): string
    {
        return match ($place) {
            'wallet' => '/admin/wallets/company/' . self::key($company),
            default => throw new InvalidArgumentException('There is no company address called "' . $place . '".'),
        };
    }
}
