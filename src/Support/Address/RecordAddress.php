declare(strict_types=1);

namespace CattoLearning\Support\Address;

use InvalidArgumentException;

final class RecordAddress
{
    /** A certificate's number: two letters, the year it was issued and twelve hexadecimal digits. */
    public const CERTIFICATE = '[A-Z]{2}-[0-9]{4}-[0-9A-F]{12}';

    /** A contact message's reference. */
    public const MESSAGE = 'MSG-[0-9]{6,18}';

    private function __construct()
    {
    }

    /**
     * An issued certificate in Administration ('admin') or on its learner's account ('account').
     *
     * @param array<string,mixed>|string $certificate
     */
    public static function certificate(string $who, array|string $certificate, string $rest = ''): string
    {
        $number = self::certificateNumber($certificate);
        return match ($who) {
            'admin' => '/admin/certificates/' . $number . $rest,
            'account' => '/account/certificates/' . $number . $rest,
            default => throw new InvalidArgumentException('A certificate is Administration\'s or the learner\'s, not "' . $who . '".'),
        };
    }

    /** @param array<string,mixed>|string $certificate */
    public static function certificateAnchor(array|string $certificate): string
    {
        return 'certificate-' . self::certificateNumber($certificate);
    }

    /** @param array<string,mixed>|string $certificate */
    public static function certificateNumber(array|string $certificate): string
    {
        return AddressKey::read($certificate, ['certificate_number'], self::CERTIFICATE, 'a certificate');
    }

    /**
     * A conversation in the Inbox: /inbox/MSG-000043 (owner, 2026-11-11: the Inbox replaced Contact Messages).
     *
     * @param array<string,mixed>|string $message
     */
    public static function message(array|string $message, string $rest = ''): string
    {
        return '/inbox/' . AddressKey::read($message, ['message_reference', 'reference'], self::MESSAGE, 'a contact message') . $rest;
    }
}
