    public const BUNDLE = CourseAddress::REQUIREMENT;

    /** A promotion's code: capitals, digits, hyphens and underscores, holding a letter. */
    public const PROMOTION = '(?=[A-Z0-9_-]*[A-Z])[A-Z0-9][A-Z0-9_-]{2,39}';

    /** A slug holding a letter. */
    public const SLUG = '(?=[a-z0-9-]*[a-z])[a-z0-9]+(?:-[a-z0-9]+)*';

    /** The fixed words beside a category's slug in Administration's addresses. */
    public const CATEGORY_WORDS = ['new', 'inline', 'field'];

    /** A category's slug: a slug, never one of the fixed words. */
    public const CATEGORY = '(?!(?:new|inline|field)(?![a-z0-9-]))' . self::SLUG;

    /** A tag's slug. */
    public const TAG = self::SLUG;

    private function __construct()
    {
    }

    /** @param array<string,mixed>|string $bundle */
    public static function bundle(array|string $bundle, string $rest = ''): string
    {
        return '/admin/bundles/' . AddressKey::read($bundle, ['bundle_code', 'code'], self::BUNDLE, 'a bundle') . $rest;
    }

    /** @param array<string,mixed>|string $bundle */
    public static function bundleAnchor(array|string $bundle): string
    {
        return 'bundle-' . AddressKey::read($bundle, ['bundle_code', 'code'], self::BUNDLE, 'a bundle');
    }

    /** @param array<string,mixed>|string $promotion */
    public static function promotion(array|string $promotion, string $rest = ''): string
    {
        return '/admin/promotions/' . rawurlencode(AddressKey::read($promotion, ['promotion_code', 'code'], self::PROMOTION, 'a promotion')) . $rest;
    }

    /** @param array<string,mixed>|string $category */
    public static function category(array|string $category, string $rest = ''): string
    {
        return '/admin/courses/categories/' . self::categoryKey($category) . $rest;
    }

    /** @param array<string,mixed>|string $category */
    public static function categoryAnchor(array|string $category): string
    {
        return 'category-' . self::categoryKey($category);
    }

    /** @param array<string,mixed>|string $tag */
    public static function tag(array|string $tag, string $rest = ''): string
    {
        return '/admin/courses/tags/' . self::tagKey($tag) . $rest;
    }

    /**
     * Follow for a category or a tag, carried through signing in as category:{slug} or tag:{slug}.
     *
     * @param array<string,mixed>|string $record
     */
    public static function follow(string $kind, array|string $record): string
    {
        return match ($kind) {
            'category' => '/follow/category/' . self::categoryKey($record),
            'tag' => '/follow/tag/' . self::tagKey($record),
            default => throw new InvalidArgumentException('Only a category or a tag is followed here, not "' . $kind . '".'),
        };
    }

    /** @param array<string,mixed>|string $category */
    public static function categoryKey(array|string $category): string
    {
        return AddressKey::read($category, ['category_slug', 'slug'], self::CATEGORY, 'a category');
    }

    /** @param array<string,mixed>|string $tag */
    public static function tagKey(array|string $tag): string
    {
        return AddressKey::read($tag, ['tag_slug', 'slug'], self::TAG, 'a tag');
    }
}
