The one way the catalogue's other records are given addresses in Administration (owner, 2026-11-06: "a recogniseable
code is better ... if they have one ... they should use that too"), never by row id:

- a bundle by its code: /admin/bundles/BDL-GARDEN, anchored #bundle-BDL-GARDEN;
- a promotion by its code: /admin/promotions/SUMMER25;
- a category by its slug: /admin/courses/categories/garden-design, anchored #category-garden-design, followed at
  /follow/category/garden-design;
- a tag by its slug: /admin/courses/tags/raised-beds, followed at /follow/tag/raised-beds.

Every key holds a letter, so none looks like a row id, and a category's slug is never one of the fixed words beside it
(new, inline, field). A controller turns the key into the row id once (AddressKeyRepository).

