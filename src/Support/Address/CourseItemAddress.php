declare(strict_types=1);

namespace CattoLearning\Support\Address;

final class CourseItemAddress
{
    /** A Course Item's slug: lowercase words joined by hyphens, holding a letter, never "new". */
    public const REQUIREMENT = '(?!new(?![a-z0-9-]))(?=[a-z0-9-]*[a-z])[a-z0-9]+(?:-[a-z0-9]+)*';

    private function __construct()
    {
    }

    /**
     * The slug of a name, as the database's course_item_slug() makes it: apostrophes dropped, every run of anything but
     * an ASCII letter or digit one hyphen, lower case, no hyphen at either end.
     */
    public static function slug(string $name): string
    {
        $name = str_replace(["'", '’', '‘'], '', $name);
        return trim((string) preg_replace('/[^a-z0-9]+/', '-', strtolower($name)), '-');
    }

    /** Whether a name can name an address: its slug holds a letter and is not a fixed word. */
    public static function addressable(string $name): bool
    {
        return AddressKey::fits(self::slug($name), self::REQUIREMENT);
    }

    /**
     * The item in Administration: /admin/course-items/gdn-101-module-1-presentation, with what follows it.
     *
     * @param array<string,mixed>|string $item A row holding its name (name, item_name or course_item_name), or the name.
     */
    public static function admin(array|string $item, string $rest = ''): string
    {
        $name = is_string($item) ? $item : (string) ($item['name'] ?? $item['item_name'] ?? $item['course_item_name'] ?? '');
        return '/admin/course-items/' . AddressKey::read(self::slug($name), ['name'], self::REQUIREMENT, 'a Course Item') . $rest;
    }
}
