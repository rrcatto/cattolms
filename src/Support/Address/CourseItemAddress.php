The one way a Course Item's address is made (owner, 2026-11-06: "a recogniseable code is better"): by a slug of its name,
which administrators already know it by and which is unique: "GDN-101 Module 1 Presentation" is
/admin/course-items/gdn-101-module-1-presentation, and a Presentation's slides, details and narration sit beneath it. The
name stays unique as a slug too: the database keeps a unique index on course_item_slug(name), the same rule as slug()
here, so "GDN-101 Lesson" and "GDN 101 Lesson" can never both be names, and a lookup by the slug is exact and indexed
(AddressKeyRepository::courseItem). A name whose slug holds no letter, or is new (the word beside it in
