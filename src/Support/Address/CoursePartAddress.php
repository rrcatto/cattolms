Date time: 2026/11/07 SAST

Version: 1.1.0

Description:
The one way a course's part is named in an address (owner, 2026-11-06: no row id in any address; the part name approved
the same day, "yes, do it that way"): every section and item placed in a course has a short readable part name, unique
within its course (course_structure_nodes.part_name), made from the part's place when it is placed and kept when it
moves, so a learner's bookmark keeps working:

- the learner's reader: /learn/growing-vegetables/module-1-presentation, its PDF (/pdf), a file in it
  (/download/{file key}), its assessment (/assessment/{key}, /start) and Mark complete (/complete);
- the public preview: /courses/growing-vegetables/preview/module-1-presentation and the same beneath it;
- Course Content's forms for one part: /admin/courses/GDN-101/content/module-1-presentation/move.

A part name is lowercase words joined by hyphens, holds a letter, and is never one of the fixed words beside it in those
addresses (RESERVED), so it never looks like a row id and never stands for another page. make() is the rule that makes
one, and the database refuses one that breaks it (course_structure_nodes_part_name_check).

Changelog:
2026/11/07 SAST
- Created for stage 2 of the work to keep row ids out of addresses.
*/

declare(strict_types=1);

namespace CattoLearning\Support\Address;

use CattoLearning\Course\CourseAddress;

final class CoursePartAddress
{
    /** The fixed words beside a part name: the reader's (start, review, assessment), and Course Content's. */
    public const RESERVED = ['start', 'review', 'assessment', 'item', 'preview', 'content', 'arrange', 'arrange-modules', 'insert', 'move-into', 'move-selection', 'placements', 'sections', 'tree', 'new'];

    /** A part name in a route. */
    public const REQUIREMENT = '(?!(?:start|review|assessment|item|preview|content|arrange|arrange-modules|insert|move-into|move-selection|placements|sections|tree|new)(?![a-z0-9-]))(?=[a-z0-9-]*[a-z])[a-z0-9]+(?:-[a-z0-9]+)*';

    /** The longest part name. */
    public const MAXIMUM = 80;

    private function __construct()
    {
    }

    /** @param array<string,mixed>|string $part */
    public static function name(array|string $part): string
    {
        return AddressKey::read($part, ['part_name'], self::REQUIREMENT, 'a course\'s part');
    }

    /**
     * The part in the learner's reader: /learn/{course slug}/{part name}, with what follows it.
     *
     * @param array<string,mixed>|string $course The course's slug, or its row.
     * @param array<string,mixed>|string $part
     */
    public static function reader(array|string $course, array|string $part, string $rest = ''): string
    {
        return '/learn/' . rawurlencode(self::slug($course)) . '/' . self::name($part) . $rest;
    }

    /**
     * The part in the public preview: /courses/{course slug}/preview/{part name}, with what follows it.
     *
     * @param array<string,mixed>|string $course
     * @param array<string,mixed>|string $part
     */
    public static function preview(array|string $course, array|string $part, string $rest = ''): string
    {
        return '/courses/' . rawurlencode(self::slug($course)) . '/preview/' . self::name($part) . $rest;
    }

    /**
     * A stop in the reader ('reader') or the public preview ('preview'): an assessment's own page
     * (/learn/{slug}/{part}/assessment/{key}), anything else the part's page, then $query (?preview=1 or nothing).
     *
     * @param array<string,mixed>|string $course
     * @param array<string,mixed> $row A row of the course's structure.
     */
    public static function stop(string $where, array|string $course, array $row, string $query = ''): string
    {
        $assessment = (string) ($row['node_type'] ?? '') === 'item' && in_array((string) ($row['item_type'] ?? ''), ['assessment', 'diagnostic'], true);
        $rest = $assessment ? '/assessment/' . rawurlencode((string) ($row['item_key'] ?? '')) : '';
        return ($where === 'preview' ? self::preview($course, $row, $rest) : self::reader($course, $row, $rest)) . $query;
    }

    /**
     * Course Content's address for one part: /admin/courses/{code}/content/{part name}/{what}.
     *
     * @param array<string,mixed>|string $course The course's code, or its row.
     * @param array<string,mixed>|string $part
     */
    public static function content(array|string $course, array|string $part, string $rest = ''): string
    {
        return CourseAddress::admin($course, '/content/' . self::name($part) . $rest);
    }

    /**
     * A part name made from words (a place's name, a section's title), free in its course: lowercase words, at most
     * MAXIMUM characters, holding a letter (part-2024 for a section called 2024), never a fixed word (review-section,
     * assessment-part), then -2, -3 and so on while $taken says the name is used.
     *
     * @param callable(string):bool $taken
     */
    public static function make(string $words, bool $section, callable $taken): string
    {
        $base = CourseItemAddress::slug($words);
        if (strlen($base) > self::MAXIMUM - 8) {
            $base = substr($base, 0, self::MAXIMUM - 8);
            $cut = strrpos($base, '-');
            $base = rtrim($cut !== false && $cut > 20 ? substr($base, 0, $cut) : $base, '-');
        }
        if ($base === '') $base = $section ? 'section' : 'part';
        if (preg_match('/[a-z]/', $base) !== 1) $base = 'part-' . $base;
        if (in_array($base, self::RESERVED, true)) $base .= $section ? '-section' : '-part';
        $name = $base;
        for ($n = 2; $taken($name); $n++) $name = $base . '-' . $n;
        return $name;
    }

    /** A name for a part until its place names it: part- and eight random hexadecimal digits. */
    public static function provisional(): string
    {
        return 'part-' . bin2hex(random_bytes(4));
    }

    /** @param array<string,mixed>|string $course */
    private static function slug(array|string $course): string
    {
        $slug = is_string($course) ? $course : (string) ($course['slug'] ?? $course['course_slug'] ?? '');
        return AddressKey::read($slug, ['slug'], '[a-zA-Z0-9_-]+', 'a course\'s reader');
    }
}
