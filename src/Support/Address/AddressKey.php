declare(strict_types=1);

namespace CattoLearning\Support\Address;

use InvalidArgumentException;

final class AddressKey
{
    private function __construct()
    {
    }

    /**
     * The key: the string itself, or the first of $keys a row holds, held to $requirement.
     *
     * @param array<string,mixed>|string $record
     * @param list<string> $keys
     */
    public static function read(array|string $record, array $keys, string $requirement, string $what): string
    {
        $key = '';
        if (is_string($record)) {
            $key = $record;
        } else {
            foreach ($keys as $name) {
                if (isset($record[$name]) && is_scalar($record[$name]) && (string) $record[$name] !== '') { $key = (string) $record[$name]; break; }
            }
        }
        if (preg_match('#^(?:' . $requirement . ')$#', $key) !== 1) {
            throw new InvalidArgumentException('An address for ' . $what . ' needs its ' . implode(' or ', $keys) . ($key === '' ? '.' : ', and "' . $key . '" is not one.'));
        }
        return $key;
    }

    /** Whether a key has the shape its route holds it to. */
    public static function fits(string $key, string $requirement): bool
    {
        return preg_match('#^(?:' . $requirement . ')$#', $key) === 1;
    }
}
