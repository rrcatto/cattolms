namespace CattoLearning\Support;

final class PublicEmailDomains
{
    /** @return list<string> */
    public static function all(): array
    {
        $builtIn = require dirname(__DIR__, 2) . '/config/public-email-domains.php';
        $extra = array_filter(array_map('trim', explode(',', Env::string('COMPANY_PUBLIC_EMAIL_DOMAINS_EXTRA'))));
        return array_values(array_unique(array_map('strtolower', array_merge($builtIn, $extra))));
    }

    public static function contains(string $domain): bool
    {
        return in_array(strtolower($domain), self::all(), true);
    }
