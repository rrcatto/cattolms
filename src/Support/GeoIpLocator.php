declare(strict_types=1);

namespace CattoLearning\Support;

use Geocoder\Formatter\StringFormatter;
use Geocoder\Provider\GeoIP2\GeoIP2;
use Geocoder\Provider\GeoIP2\GeoIP2Adapter;
use Geocoder\Query\GeocodeQuery;
use GeoIp2\Database\Reader;
use Throwable;

/**
 * Provides best-effort IP geolocation for administrative audit displays.
 *
 * Missing databases, private addresses and lookup failures never break the
 * Activity Centre; callers receive a short display label instead.
 */
final class GeoIpLocator
{
    private ?GeoIP2 $geocoder = null;

    public function __construct(string $databasePath = '')
    {
        if ($databasePath === '' || !is_file($databasePath) || !is_readable($databasePath)) {
            return;
        }

        try {
            $reader = new Reader($databasePath, ['en']);
            $this->geocoder = new GeoIP2(new GeoIP2Adapter($reader));
        } catch (Throwable) {
            $this->geocoder = null;
        }
    }

    public function isAvailable(): bool
    {
        return $this->geocoder !== null;
    }

    /**
     * Converts a two-letter ISO 3166-1 country code to its Unicode flag glyph.
     *
     * The application already requires ext-mbstring, so regional-indicator
     * code points can be generated without shipping an additional icon pack.
     */
    public static function flagForCountryCode(string $countryCode): string
    {
        $countryCode = strtoupper(trim($countryCode));
        if (preg_match('/^[A-Z]{2}$/', $countryCode) !== 1) {
            return '';
        }

        $base = 0x1F1E6;
        return mb_chr($base + ord($countryCode[0]) - 65, 'UTF-8')
            . mb_chr($base + ord($countryCode[1]) - 65, 'UTF-8');
    }

    public function locate(string $ipAddress): string
    {
        if (filter_var($ipAddress, FILTER_VALIDATE_IP) === false) {
            return 'Invalid IP';
        }

        $publicAddress = filter_var(
            $ipAddress,
            FILTER_VALIDATE_IP,
            FILTER_FLAG_NO_PRIV_RANGE | FILTER_FLAG_NO_RES_RANGE
        );
        if ($publicAddress === false) {
            return 'Local/private';
        }

        if ($this->geocoder === null) {
            return 'GeoIP unavailable';
        }

        try {
            $address = $this->geocoder
                ->geocodeQuery(GeocodeQuery::create($ipAddress))
                ->first();
            $formatter = new StringFormatter();

            $locality = trim($formatter->format($address, '%L'));
            $adminLevel = trim($formatter->format($address, '%A1'));
            $country = trim($formatter->format($address, '%C'));
            $countryCode = strtoupper(trim($formatter->format($address, '%c')));
            $flag = self::flagForCountryCode($countryCode);

            $countryLabel = trim(($flag !== '' ? $flag . ' ' : '') . $country);
            $parts = array_values(array_unique(array_filter(
                [$locality, $adminLevel, $countryLabel],
                static fn(string $part): bool => $part !== ''
            )));

            return $parts !== [] ? implode(', ', $parts) : 'Location unavailable';
        } catch (Throwable) {
            return 'Location unavailable';
        }
    }
}