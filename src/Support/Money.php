Description:
An amount of money: an integer number of minor units and an ISO 4217 currency code.

Architectural boundary: a pure value object. It holds no SQL, no HTTP knowledge and no persistence.
The database stores the two fields it wraps - `price_minor_units` and `currency_code` - and this is
what the rest of the platform passes around instead of two loose values that can drift apart.

Three decisions are baked in, and each is here rather than at a call site on purpose.

**Minor units, never a float.** A payment processor takes cents, and a price held as a float is a
rounding error waiting for a total. Everything above this class works in whole cents; the only
division by 100 in the platform should be inside this file.

**Formatting comes from intl, not from a symbol table.** Given a currency code and a locale, PHP
knows where the symbol goes, which character separates thousands and which separates decimals -
`R 1 234,56`, `£1,234.56`, `1.234,56 €`. A hand-kept symbol gets the first of those right and the
next two wrong, and gets them wrong silently. See ROADMAP section 2d.

**Prices are exclusive of VAT.** That is the number the owner sets and the number stored. VAT is
added for display and stored per order line when the platform is registered for it; this class
carries no tax and must not grow any, because a price that sometimes includes tax is a price nobody
can reason about.

Changelog:
2026/09/07 22:00 SAST
- Created with the currency and locale decisions of 2026/09/07.
*/

declare(strict_types=1);

namespace CattoLearning\Support;

use NumberFormatter;
use InvalidArgumentException;
use OverflowException;

final class Money
{
    private function __construct(
        public readonly int $minorUnits,
        public readonly string $currency
    ) {
    }

    /** An amount already expressed in cents, which is how it is stored and how it is charged. */
    public static function ofMinorUnits(int $minorUnits, ?string $currency = null): self
    {
        return new self(max(0, $minorUnits), self::normaliseCurrency($currency));
    }

    /**
     * An amount a person typed, such as `1234.56`.
     *
     * A string is parsed as digits rather than converted to a float, and that is not fastidiousness:
     * `9.995` cannot be held exactly in binary, so it arrives as very slightly *less* than 9.995 and
     * rounds down to 999 cents rather than up to 1000. A price typed by a person must become the
     * cents they meant, and the only way to guarantee that is never to make it a float at all.
     *
     * A float argument is still accepted, and still rounded rather than truncated - truncation loses
     * a cent on every price ending in a half, and nobody notices until a day's takings are
     * reconciled against a processor that did not lose it.
     */
    public static function ofMajorUnits(float|string $amount, ?string $currency = null): self
    {
        if (is_string($amount) && preg_match('/^\s*(-?)(\d+)(?:[.,](\d*))?\s*$/', $amount, $parts) === 1) {
            $fraction = str_pad(substr($parts[3] ?? '', 0, 3), 3, '0');
            $thousandths = (int) $parts[2] * 1000 + (int) $fraction;
            $minorUnits = intdiv($thousandths + 5, 10);

            return new self($parts[1] === '-' ? 0 : $minorUnits, self::normaliseCurrency($currency));
        }

        return new self((int) round(((float) $amount) * 100), self::normaliseCurrency($currency));
    }

    public static function zero(?string $currency = null): self
    {
        return new self(0, self::normaliseCurrency($currency));
    }

    /** Strict financial boundary; legacy form factories retain their historical normalization. */
    public static function strictMinorUnits(int $amount, string $currency): self
    {
        if ($amount < 0 || preg_match('/^[A-Z]{3}$/', $currency) !== 1) {
            throw new InvalidArgumentException('Invalid monetary amount or currency.');
        }
        return new self($amount, $currency);
    }

    public function isFree(): bool
    {
        return $this->minorUnits === 0;
    }

    public function plus(self $other): self
    {
        if ($this->currency !== $other->currency) {
            throw new InvalidArgumentException('Cannot combine different currencies.');
        }
        if ($other->minorUnits > PHP_INT_MAX - $this->minorUnits) {
            throw new OverflowException('Monetary total is too large.');
        }
        return new self($this->minorUnits + $other->minorUnits, $this->currency);
    }

    public function times(int $quantity): self
    {
        if ($quantity > 0 && $this->minorUnits > intdiv(PHP_INT_MAX, $quantity)) {
            throw new OverflowException('Monetary total is too large.');
        }
        return new self($this->minorUnits * max(0, $quantity), $this->currency);
    }

    /** The amount as a plain decimal string, for a form field or an export. */
    public function toMajorUnits(): string
    {
        return intdiv($this->minorUnits, 100) . '.' . str_pad((string) ($this->minorUnits % 100), 2, '0', STR_PAD_LEFT);
    }

    /**
     * The amount as a reader of this installation should see it.
     *
     * Falls back to a plain code-and-amount when intl is unavailable, because a missing extension
     * must degrade to something legible rather than to a fatal error on a price.
     */
    public function format(?string $locale = null): string
    {
        $locale ??= Env::string('APP_LOCALE') ?: 'en_ZA';

        if (!class_exists(NumberFormatter::class)) {
            return $this->currency . ' ' . number_format($this->minorUnits / 100, 2, '.', ',');
        }

        $formatted = (new NumberFormatter($locale, NumberFormatter::CURRENCY))
            ->formatCurrency($this->minorUnits / 100, $this->currency);

        return $formatted === false ? $this->currency . ' ' . $this->toMajorUnits() : $formatted;
    }

    /** The platform's own currency, from the instance configuration. */
    public static function platformCurrency(): string
    {
        return self::normaliseCurrency(null);
    }

    private static function normaliseCurrency(?string $currency): string
    {
        $code = strtoupper(trim((string) ($currency ?? Env::string('APP_CURRENCY'))));

        // A code that is not three letters is not a currency, and defaulting is better than
        // formatting an amount against nonsense: the installation's own currency is the only
        // sensible fallback, and ZAR is the only sensible fallback for that.
        return preg_match('/^[A-Z]{3}$/', $code) === 1 ? $code : 'ZAR';
    }
}
