declare(strict_types=1);

namespace CattoLearning\Support;

final class Uuid
{
    /**
     * Time-ordered UUIDv7, used as the Seed Database set token.
     *
     * RFC 9562 layout: 48 bits of Unix milliseconds, 4 version bits, 12 random bits, 2 variant
     * bits, 62 random bits. The leading timestamp makes tokens sort by generation time, which
     * keeps the btree index on every seed_token column dense rather than scattering inserts the
     * way a v4 token would across 31 tables in one bulk transaction.
     */
    public static function v7(): string
    {
        $milliseconds = (int) (microtime(true) * 1000);

        $bytes = random_bytes(16);
        // 48-bit big-endian timestamp in the first six bytes.
        for ($i = 5; $i >= 0; $i--) {
            $bytes[$i] = chr($milliseconds & 0xff);
            $milliseconds >>= 8;
        }
        $bytes[6] = chr((ord($bytes[6]) & 0x0f) | 0x70);
        $bytes[8] = chr((ord($bytes[8]) & 0x3f) | 0x80);

        return self::format(bin2hex($bytes));
    }

    private static function format(string $hex): string
    {
        return sprintf('%s-%s-%s-%s-%s',
            substr($hex, 0, 8),
            substr($hex, 8, 4),
            substr($hex, 12, 4),
            substr($hex, 16, 4),
            substr($hex, 20, 12)
        );
    }

    /**
     * Whether a string is a UUID at all.
     *
     * A token reaches the application from a route parameter, so it can be anything. PostgreSQL
     * casts a UUID column comparison rather than comparing text, and a malformed value makes that
     * cast fail with an SQLSTATE the reader then sees. Checking the shape first turns a hand-typed
     * URL into "no such record", which is what it actually is.
     */
    public static function isValid(string $candidate): bool
    {
        // Anchored with \z rather than $, because $ also matches immediately before a trailing
        // newline, which would let "<uuid>\n" through to the cast this check exists to avoid.
        return preg_match('/\A[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\z/i', $candidate) === 1;
    }

    public static function v4(): string
    {
        $bytes = random_bytes(16);
        $bytes[6] = chr((ord($bytes[6]) & 0x0f) | 0x40);
        $bytes[8] = chr((ord($bytes[8]) & 0x3f) | 0x80);
        return self::format(bin2hex($bytes));
    }
}