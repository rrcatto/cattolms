<?php

/*
Generated by: Claude Code CLI

Date time: 2026/09/10 02:25 SAST

Version: 0.7

Description:
One uploaded profile image, validated and resized to the size the platform stores.

Architectural boundary: support value object. It takes bytes and returns bytes. It reads nothing,
writes nothing, and knows neither the database nor the request - which is what makes the whole of
the "is this actually an image, and how large is it" question testable without either.

Three things have to be true of an upload before it is worth resizing, and all three are checked
before any decoder touches it:

- it is small enough that decoding it cannot exhaust memory. A decoded bitmap costs four bytes a
  pixel whatever the file compressed to, so the byte cap is not the real defence - the pixel cap is,
  and both are applied before imagecreatefromstring is called;
- it is one of the three formats we store. The type comes from reading the bytes, never from the
  browser's Content-Type or the filename, both of which the client chooses;
- it decodes at all. A file that says PNG in its header and is not one fails here rather than
  somewhere further in.

The output is always PNG. One format out means one decoder path on the way back, the alpha channel
survives, and the stored bytes cannot be a JPEG that some later resize quietly recompresses again.

Changelog:
2026/09/10 07:10 SAST
- Applies the EXIF orientation. A photograph taken upright on a phone is stored as a landscape bitmap with a tag saying which way to turn it, and the decoder ignores that tag - so every such picture arrived lying on its side.

2026/09/10 02:25 SAST
- Created for the Profile submenu's personal particulars page.
*/

declare(strict_types=1);

namespace CattoLearning\Support;

use RuntimeException;

final class ProfileImage
{
    /** The stored square, in pixels. Large enough for a retina avatar and nothing beyond that. */
    public const SIZE = 256;

    /** Largest upload accepted, in bytes. */
    public const MAX_UPLOAD_BYTES = 8 * 1024 * 1024;

    /**
     * Largest edited-image field accepted, as posted - so base64, not the image.
     *
     * A PNG of the stored size is a few hundred kilobytes at worst. This is generous rather than
     * tight because the field is not the defence: fromUpload() is.
     */
    public const MAX_EDITED_FIELD_BYTES = 4 * 1024 * 1024;

    /**
     * Largest source image accepted, in pixels.
     *
     * A decoded bitmap is four bytes a pixel regardless of how small the file compressed to, so a
     * 20,000 x 20,000 PNG that downloads in 60KB would want 1.6GB to decode. The dimensions are
     * read from the header and refused before any decoder is handed the bytes.
     */
    public const MAX_SOURCE_PIXELS = 8000 * 8000;

    /** @var array<int,string> */
    private const SUPPORTED = [
        IMAGETYPE_PNG => 'image/png',
        IMAGETYPE_JPEG => 'image/jpeg',
        IMAGETYPE_WEBP => 'image/webp',
    ];

    private function __construct(
        public readonly string $bytes,
        public readonly string $mimeType,
        public readonly int $width,
        public readonly int $height
    ) {
    }

    /**
     * Validate and resize one upload.
     *
     * @throws RuntimeException with a message written for the person who uploaded the file.
     */
    public static function fromUpload(string $bytes): self
    {
        if ($bytes === '') {
            throw new RuntimeException('No image was received. Please choose a file and try again.');
        }
        if (strlen($bytes) > self::MAX_UPLOAD_BYTES) {
            throw new RuntimeException('That image is larger than 8 MB. Please choose a smaller file.');
        }

        // The type comes from the bytes. The browser sends a Content-Type and a filename and the
        // client chooses both, so neither is evidence of anything.
        $info = @getimagesizefromstring($bytes);
        if ($info === false || !isset(self::SUPPORTED[$info[2]])) {
            throw new RuntimeException('That file is not a PNG, JPEG or WebP image.');
        }

        [$sourceWidth, $sourceHeight] = [(int) $info[0], (int) $info[1]];
        if ($sourceWidth < 1 || $sourceHeight < 1 || $sourceWidth * $sourceHeight > self::MAX_SOURCE_PIXELS) {
            throw new RuntimeException('That image has too many pixels to process. Please choose a smaller one.');
        }

        $source = @imagecreatefromstring($bytes);
        if ($source === false) {
            throw new RuntimeException('That image could not be read. It may be damaged.');
        }

        // Turned the way the camera says it was held, before anything is measured or cropped.
        $source = self::uprighted($source, $bytes, $info[2]);

        // Re-read rather than reuse: a quarter turn swaps them, and cropping a portrait to the
        // dimensions of the landscape bitmap it was stored as crops the wrong axis.
        [$sourceWidth, $sourceHeight] = [imagesx($source), imagesy($source)];

        // Nothing frees the image explicitly. A GdImage has been an ordinary object collected by
        // refcount since PHP 8.0, and 8.5 deprecates the call that used to free it.
        return new self(self::render(self::square($source, $sourceWidth, $sourceHeight)), 'image/png', self::SIZE, self::SIZE);
    }

    /**
     * The bytes of an image the browser edited and posted back as a data URL, or null if none was.
     *
     * Only a PNG data URL is accepted, because that is the one thing the editor produces. Anything
     * else is "no edit" rather than an error: the original file is still in the request, so the
     * ordinary path takes over and the reader gets a centred square instead of a failure.
     *
     * The cap is on the encoded field, and is checked before decoding. Decoding first to find out
     * how large something is, is how a size limit becomes the thing it was meant to prevent.
     *
     * Nothing here trusts the result. It returns bytes, and those bytes go through fromUpload()
     * exactly as an uploaded file does - so a hand-posted field is only ever a differently shaped
     * upload, subject to the same type check, the same pixel cap and the same re-encode.
     *
     * @throws RuntimeException when the field is a PNG data URL but too large to accept.
     */
    public static function decodeEditedImage(string $field): ?string
    {
        $prefix = 'data:image/png;base64,';
        if ($field === '' || !str_starts_with($field, $prefix)) {
            return null;
        }
        if (strlen($field) > self::MAX_EDITED_FIELD_BYTES) {
            throw new RuntimeException('The edited image was too large. Please choose a smaller picture.');
        }

        $decoded = base64_decode(substr($field, strlen($prefix)), true);
        if ($decoded === false || $decoded === '') {
            return null;
        }

        return $decoded;
    }

    /**
     * The image the right way up.
     *
     * A camera does not rotate its sensor. It stores the bitmap the sensor produced - almost always
     * landscape - and records how the camera was held in the EXIF `Orientation` tag, leaving the
     * viewer to turn it. `imagecreatefromstring()` is not a viewer: it decodes the stored bitmap and
     * ignores the tag, so a photograph taken upright arrives on its side. That is not a corner case,
     * it is what every phone photograph does, and it is why two upright pictures imported lying
     * down.
     *
     * The eight values are the EXIF ones, and all eight are handled rather than only the three
     * common rotations: a mirrored value left unhandled is a portrait that comes out backwards,
     * which is harder to notice and worse.
     *
     * Note the sign. `imagerotate()` turns anticlockwise for a positive angle, and the EXIF values
     * describe the clockwise turn a viewer must apply, so the two are opposite.
     *
     * @param \GdImage $image
     * @return \GdImage
     */
    private static function uprighted(\GdImage $image, string $bytes, int $type): \GdImage
    {
        // Only JPEG carries orientation in practice. A PNG has no EXIF at all, and exif_read_data
        // emits a warning rather than returning false when handed one.
        if ($type !== IMAGETYPE_JPEG || !function_exists('exif_read_data')) {
            return $image;
        }

        $stream = fopen('php://memory', 'r+b');
        if ($stream === false) {
            return $image;
        }
        fwrite($stream, $bytes);
        rewind($stream);
        $exif = @exif_read_data($stream);
        fclose($stream);

        $orientation = is_array($exif) ? (int) ($exif['Orientation'] ?? 0) : 0;

        // Transparency is irrelevant for a JPEG, but the rotated canvas is filled with the colour
        // given here, and leaving it black would band the edges of a non-right-angle rotation.
        $white = (int) imagecolorallocate($image, 255, 255, 255);

        return match ($orientation) {
            2 => self::mirrored($image),
            3 => imagerotate($image, 180, $white) ?: $image,
            4 => imagerotate(self::mirrored($image), 180, $white) ?: $image,
            // 5 is mirror-then-270-clockwise and 7 is mirror-then-90-clockwise. Written the other
            // way round they still produce a plausible-looking portrait, which is why both are
            // covered by a test rather than reasoned about once.
            5 => imagerotate(self::mirrored($image), 90, $white) ?: $image,
            6 => imagerotate($image, -90, $white) ?: $image,
            7 => imagerotate(self::mirrored($image), -90, $white) ?: $image,
            8 => imagerotate($image, 90, $white) ?: $image,
            default => $image,
        };
    }

    /**
     * @param \GdImage $image
     * @return \GdImage
     */
    private static function mirrored(\GdImage $image): \GdImage
    {
        imageflip($image, IMG_FLIP_HORIZONTAL);

        return $image;
    }

    /**
     * The centred square crop, scaled to the stored size.
     *
     * Cropping to a square before scaling rather than squashing to one: a profile image is shown in
     * a round or square frame everywhere it appears, and a portrait squashed to a square is a worse
     * answer than a portrait with its edges trimmed.
     *
     * @param \GdImage $source
     * @return \GdImage
     */
    private static function square(\GdImage $source, int $width, int $height): \GdImage
    {
        $side = min($width, $height);
        $canvas = imagecreatetruecolor(self::SIZE, self::SIZE);

        // PNG out means alpha survives, and it only survives if the canvas is told to keep it
        // before anything is drawn on to it.
        imagealphablending($canvas, false);
        imagesavealpha($canvas, true);
        imagefill($canvas, 0, 0, imagecolorallocatealpha($canvas, 0, 0, 0, 127));

        imagecopyresampled(
            $canvas,
            $source,
            0,
            0,
            intdiv($width - $side, 2),
            intdiv($height - $side, 2),
            self::SIZE,
            self::SIZE,
            $side,
            $side
        );

        return $canvas;
    }

    /** @param \GdImage $image */
    private static function render(\GdImage $image): string
    {
        ob_start();
        $written = imagepng($image, null, 6);
        $bytes = (string) ob_get_clean();

        if ($written === false || $bytes === '') {
            throw new RuntimeException('The resized image could not be produced.');
        }

        return $bytes;
    }
}
