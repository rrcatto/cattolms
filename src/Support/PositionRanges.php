declare(strict_types=1);

namespace CattoLearning\Support;

use CattoLearning\Infrastructure\Persistence\OptionRepository;
use InvalidArgumentException;

final class PositionRanges
{
    /** Empty rows the Settings form offers for adding bands. */
    private const BLANK_ROWS = 3;

    /**
     * @param string $key where the bands are saved, as JSON {"GDN": 10000, ...}
     * @param string $things what is numbered, for the words: "course" or "bundle"
     */
    public function __construct(private readonly OptionRepository $options, private readonly string $key, private readonly string $things)
    {
    }

    /** @return array<string,int> prefix => start, lowest start first */
    public function ranges(): array
    {
        $saved = json_decode((string) $this->options->find($this->key), true);
        $ranges = [];
        foreach (is_array($saved) ? $saved : [] as $prefix => $start) {
            if (is_string($prefix) && is_int($start)) $ranges[$prefix] = $start;
        }
        asort($ranges);
        return $ranges;
    }

    /**
     * Saves the bands from the form's rows: a row with no prefix is left out; each prefix is capital letters and digits,
     * used once; each start a whole number from 1, used once.
     *
     * @param array<int,mixed> $prefixes
     * @param array<int,mixed> $starts
     * @return array<string,int> what was saved
     */
    public function save(array $prefixes, array $starts, int $actor): array
    {
        $ranges = [];
        foreach ($prefixes as $index => $raw) {
            $prefix = strtoupper(trim((string) (is_scalar($raw) ? $raw : '')));
            $startText = trim((string) (is_scalar($starts[$index] ?? null) ? $starts[$index] : ''));
            if ($prefix === '' && $startText === '') continue;
            if (preg_match('/^[A-Z0-9]{1,20}$/', $prefix) !== 1) throw new InvalidArgumentException('A prefix is the start of a ' . $this->things . ' code, before its first hyphen: capital letters and digits, such as GDN.');
            if (isset($ranges[$prefix])) throw new InvalidArgumentException($prefix . ' is listed twice. Give each prefix one band.');
            $start = PositionBands::typed($startText, 'Enter where ' . $prefix . '\'s band starts as a whole number from 1, such as 10000.') ?? throw new InvalidArgumentException('Give ' . $prefix . ' the number its band starts at, such as 10000.');
            if (in_array($start, $ranges, true)) throw new InvalidArgumentException('Two bands start at ' . $start . '. Give each its own starting number.');
            $ranges[$prefix] = $start;
        }
        asort($ranges);
        if ($ranges === []) {
            $this->options->delete($this->key);
        } else {
            $this->options->set($this->key, (string) json_encode($ranges), $actor);
        }
        return $ranges;
    }

    /**
     * The Settings section: each saved band with its range and room, then empty rows for more, and a line saying what is set.
     *
     * @return array{rows:list<array{prefix:string,start:string,band:string}>,summary:string}
     */
    public function view(): array
    {
        $ranges = $this->ranges();
        $rows = [];
        foreach ($ranges as $prefix => $start) $rows[] = ['prefix' => $prefix, 'start' => (string) $start, 'band' => PositionBands::words($ranges, $prefix)];
        for ($i = 0; $i < self::BLANK_ROWS; $i++) $rows[] = ['prefix' => '', 'start' => '', 'band' => ''];
        $summary = $ranges === [] ? 'No bands: a new ' . $this->things . ' goes to the end of the list until it is given a position.'
            : implode(', ', array_map(static fn(string $prefix, int $start): string => $prefix . ' from ' . $start, array_keys($ranges), $ranges)) . '.';
        return ['rows' => $rows, 'summary' => $summary];
    }
}
