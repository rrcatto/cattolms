declare(strict_types=1);

namespace CattoLearning\Support;

use DateTimeImmutable;
use InvalidArgumentException;

final class Duration
{
    private const PATTERN = '/^(?:(\d{1,3})y)?(?:(\d{1,4})w)?(?:(\d{1,5})d)?(?:(\d{1,6})h)?$/i';

    private function __construct(
        public readonly string $text,
        public readonly int $years,
        public readonly int $weeks,
        public readonly int $days,
        public readonly int $hours
    ) {
    }

    /** Reads a duration as entered, or explains how to write one. */
    public static function parse(string $text): self
    {
        $trimmed = trim($text);
        if ($trimmed === '' || preg_match(self::PATTERN, $trimmed, $match) !== 1 || $match[0] === '') {
            throw new InvalidArgumentException('Write a duration with y, w, d and h in that order, such as 3y, 4w2d or 1h.');
        }
        $parts = [];
        foreach ([1, 2, 3, 4] as $index) {
            $value = $match[$index] ?? '';
            if ($value === '') { $parts[] = 0; continue; }
            if ((int) $value < 1) throw new InvalidArgumentException('Each part of a duration is a whole number from 1 up, such as 3y or 4w2d.');
            $parts[] = (int) $value;
        }
        if (array_sum($parts) === 0) throw new InvalidArgumentException('Write a duration with y, w, d and h in that order, such as 3y, 4w2d or 1h.');

        return new self($trimmed, $parts[0], $parts[1], $parts[2], $parts[3]);
    }

    public static function isValid(string $text): bool
    {
        try { self::parse($text); return true; } catch (InvalidArgumentException) { return false; }
    }

    /** "3 years", "4 weeks 2 days", "1 hour". */
    public function words(): string
    {
        $words = [];
        foreach (['year' => $this->years, 'week' => $this->weeks, 'day' => $this->days, 'hour' => $this->hours] as $unit => $count) {
            if ($count > 0) $words[] = $count . ' ' . $unit . ($count === 1 ? '' : 's');
        }

        return implode(' ', $words);
    }

    /** The moment this long after $at, in $at's own time zone. */
    public function after(DateTimeImmutable $at): DateTimeImmutable
    {
        $result = $at;
        if ($this->years > 0) {
            $target = (int) $result->format('Y') + $this->years;
            $day = min((int) $result->format('j'), (int) (new DateTimeImmutable(sprintf('%04d-%02d-01', $target, (int) $result->format('n')), $result->getTimezone()))->format('t'));
            $result = $result->setDate($target, (int) $result->format('n'), $day);
        }
        $days = $this->weeks * 7 + $this->days;
        if ($days > 0) $result = $result->modify('+' . $days . ' days');
        if ($this->hours > 0) $result = $result->modify('+' . $this->hours . ' hours');

        return $result;
    }

    /** The moment this long before $at (for a reminder some time before an expiry). */
    public function before(DateTimeImmutable $at): DateTimeImmutable
    {
        $result = $at;
        if ($this->hours > 0) $result = $result->modify('-' . $this->hours . ' hours');
        $days = $this->weeks * 7 + $this->days;
        if ($days > 0) $result = $result->modify('-' . $days . ' days');
        if ($this->years > 0) {
            $target = (int) $result->format('Y') - $this->years;
            $day = min((int) $result->format('j'), (int) (new DateTimeImmutable(sprintf('%04d-%02d-01', $target, (int) $result->format('n')), $result->getTimezone()))->format('t'));
            $result = $result->setDate($target, (int) $result->format('n'), $day);
        }

        return $result;
    }

    /** True when this is shorter than $other, measured from the same moment. */
    public function isShorterThan(self $other, DateTimeImmutable $from): bool
    {
        return $this->after($from) < $other->after($from);
    }
}
