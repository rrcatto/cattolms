        'tiktok'    => ['label' => 'TikTok',    'hosts' => ['tiktok.com'],    'placeholder' => 'https://www.tiktok.com/@yourname'],
        'whatsapp'  => ['label' => 'WhatsApp',  'hosts' => ['wa.me', 'whatsapp.com'], 'placeholder' => 'https://wa.me/27820000000'],
