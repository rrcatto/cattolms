    /** @return list<string> */
    public static function keys(): array
    {
        return array_keys(self::CATALOGUE);
    }

    public static function isKnown(string $platform): bool
    {
        return isset(self::CATALOGUE[$platform]);
    }

    public static function label(string $platform): string
    {
        return self::CATALOGUE[$platform]['label'] ?? $platform;
    }

    /**
     * The catalogue as a view model, with each platform's current value filled in.
     *
     * @param array<string,string> $values
     * @return list<array{key:string,label:string,placeholder:string,url:string}>
     */
    public static function form(array $values): array
    {
        $rows = [];
        foreach (self::CATALOGUE as $key => $meta) {
            $rows[] = [
                'key' => $key,
                'label' => $meta['label'],
                'placeholder' => $meta['placeholder'],
                'url' => (string) ($values[$key] ?? ''),
            ];
        }

        return $rows;
    }

    /**
     * The address to store for one platform, or null to store nothing.
     *
     * An empty value means "remove this link" and is not an error. Anything else must be an https
     * URL on one of the platform's own hosts.
     *
     * @throws \RuntimeException when the value is neither empty nor a valid address for the platform.
     */
    public static function normalise(string $platform, string $url): ?string
    {
        $url = trim($url);
        if ($url === '') {
            return null;
        }
        if (!isset(self::CATALOGUE[$platform])) {
            throw new \RuntimeException('Unknown social platform: ' . $platform);
        }

        $label = self::CATALOGUE[$platform]['label'];
        if (strlen($url) > 500) {
            throw new \RuntimeException('The ' . $label . ' address is too long.');
        }

        $parts = parse_url($url);
        if ($parts === false || !isset($parts['host'])) {
            throw new \RuntimeException('The ' . $label . ' address is not a web address. Paste the whole link, starting with https://');
        }
        if (strtolower((string) ($parts['scheme'] ?? '')) !== 'https') {
            throw new \RuntimeException('The ' . $label . ' address must start with https://');
        }

        // Host, or a subdomain of it. Compared against the trailing dot so "notlinkedin.com" cannot
        // pass as "linkedin.com".
        $host = strtolower((string) $parts['host']);
        foreach (self::CATALOGUE[$platform]['hosts'] as $allowed) {
            if ($host === $allowed || str_ends_with($host, '.' . $allowed)) {
                return $url;
            }
        }

        throw new \RuntimeException(
            'That does not look like a ' . $label . ' address. It should be on '
            . implode(' or ', self::CATALOGUE[$platform]['hosts']) . '.'
        );
    }
}
