declare(strict_types=1);

namespace CattoLearning\View\Artwork;

final class ArtworkGenerator
{
    /**
     * A stream of numbers from a seed.
     *
     * SHA-256 of the seed, read two bytes at a time. It is a hash rather than a seeded PRNG because
     * PHP's generators have changed their sequence between versions before, and artwork that
     * silently redraws itself on an upgrade is worse than artwork nobody likes.
     *
     * @return list<int>
     */
    private static function stream(string $seed): array
    {
        $bytes = hash('sha256', $seed, true);
        $out = [];
        for ($i = 0; $i < strlen($bytes); $i += 2) {
            $out[] = (ord($bytes[$i]) << 8) | ord($bytes[$i + 1]);
        }

        return $out;
    }

    /** The first one or two letters of a name, for the monogram. */
    private static function monogram(string $name): string
    {
        $words = preg_split('/\s+/u', trim($name)) ?: [];
        $letters = '';
        foreach ($words as $word) {
            $first = preg_replace('/[^\p{L}\p{N}]/u', '', $word) ?? '';
            if ($first === '') {
                continue;
            }
            $letters .= mb_strtoupper(mb_substr($first, 0, 1));
            if (mb_strlen($letters) === 2) {
                break;
            }
        }

        return $letters === '' ? '·' : $letters;
    }

    private static function escape(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_XML1, 'UTF-8');
    }

    /**
     * A course cover: 16:9, a two-stop wash, three drifting arcs and the monogram.
     *
     * Arcs rather than the polygons and circles every identicon generator draws, because a course
     * cover sits at card width and reads as a picture rather than as an avatar. Their geometry is
     * the only part that varies beyond colour, which is what stops twelve palettes from producing
     * twelve visibly repeated images.
     */
    public function courseCover(string $seed, string $title): string
    {
        $n = self::stream($seed);
        $p = ArtworkPalette::forNumber($n[0]);
        $mono = self::escape(self::monogram($title));
        $g = 'g' . substr(hash('crc32b', $seed), 0, 6);

        $arcs = '';
        for ($i = 0; $i < 3; $i++) {
            $cx = 40 + ($n[1 + $i] % 560);
            $cy = 30 + ($n[4 + $i] % 300);
            $r = 90 + ($n[7 + $i] % 190);
            $opacity = ['0.30', '0.22', '0.16'][$i];
            $fill = $i === 2 ? $p['accent'] : $p['tint'];
            $arcs .= sprintf('<circle cx="%d" cy="%d" r="%d" fill="%s" opacity="%s"/>', $cx, $cy, $r, $fill, $opacity);
        }

        return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 360" role="img" aria-label="'
            . $mono . '" preserveAspectRatio="xMidYMid slice">'
            . '<defs><linearGradient id="' . $g . '" x1="0" y1="0" x2="1" y2="1">'
            . '<stop offset="0" stop-color="' . $p['base'] . '"/>'
            . '<stop offset="1" stop-color="' . $p['tint'] . '"/></linearGradient></defs>'
            . '<rect width="640" height="360" fill="url(#' . $g . ')"/>'
            . '<g clip-path="inset(0)">' . $arcs . '</g>'
            . '<text x="44" y="300" font-family="Georgia,serif" font-size="128" font-weight="700"'
            . ' fill="' . $p['ink'] . '" opacity="0.92">' . $mono . '</text>'
            . '<rect x="0" y="348" width="640" height="12" fill="' . $p['accent'] . '"/>'
            . '</svg>';
    }

    /**
     * A category icon: a rounded tile carrying the monogram, sized for a title bar.
     *
     * Square and flat on purpose. It sits beside a heading at 40px, where a picture becomes noise;
     * what it has to do is make one category distinguishable from the next at a glance down a list.
     */
    public function categoryIcon(string $seed, string $name): string
    {
        $n = self::stream($seed);
        $p = ArtworkPalette::forNumber($n[0]);
        $mono = self::escape(self::monogram($name));
        $bars = '';
        for ($i = 0; $i < 3; $i++) {
            $w = 10 + ($n[2 + $i] % 22);
            $bars .= sprintf('<rect x="%d" y="%d" width="%d" height="4" rx="2" fill="%s" opacity="0.55"/>',
                8, 46 + $i * 7, $w, $p['accent']);
        }

        return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="'
            . $mono . '">'
            . '<rect width="64" height="64" rx="14" fill="' . $p['base'] . '"/>'
            . '<circle cx="50" cy="16" r="18" fill="' . $p['tint'] . '" opacity="0.75"/>'
            . $bars
            . '<text x="8" y="38" font-family="Georgia,serif" font-size="30" font-weight="700"'
            . ' fill="' . $p['ink'] . '">' . $mono . '</text>'
            . '</svg>';
    }

    /**
     * A tag icon: one letter in a circle, at the size a chip can carry.
     *
     * Smaller and simpler than a category's, because a tag chip is about 18px of artwork and
     * anything with more than one shape in it turns to mud at that size.
     */
    public function tagIcon(string $seed, string $name): string
    {
        $n = self::stream($seed);
        $p = ArtworkPalette::forNumber($n[0]);
        $mono = self::escape(mb_substr(self::monogram($name), 0, 1));

        return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" role="img" aria-label="'
            . $mono . '">'
            . '<circle cx="16" cy="16" r="16" fill="' . $p['base'] . '"/>'
            . '<circle cx="16" cy="16" r="11" fill="none" stroke="' . $p['accent'] . '" stroke-width="2" opacity="0.7"/>'
            . '<text x="16" y="21" text-anchor="middle" font-family="Georgia,serif" font-size="14"'
            . ' font-weight="700" fill="' . $p['ink'] . '">' . $mono . '</text>'
            . '</svg>';
    }
}
