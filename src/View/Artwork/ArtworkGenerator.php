Version: 0.7

Description:
Generates the cover and icon artwork a course, a category and a tag are given when they are created.

Architectural boundary: presentation. It takes a name and a seed and returns SVG markup. It reads
nothing, writes nothing and knows no schema.

Why generated rather than uploaded. Every course needs a cover before anyone has drawn one, and the
alternative to generating one is a catalogue of identical grey rectangles - which is worse than a
placeholder, because it tells the reader the courses are the same. A course keeps its generated
cover until a real image replaces it.

Deterministic, from a seed. The seed is the row's public id, so the same course produces the same
artwork on every machine, in every export, and after any re-render. Nothing here calls rand().

The output is deliberately small. A cover is about 700 bytes and an icon about 300, because 250,000
courses each carrying a kilobyte is a quarter of a gigabyte inside the table every list query reads
past. It is stored, not recomputed, because the alternative is generating artwork for 25 rows on
every catalogue page render.

Changelog:
2026/09/09 05:00 SAST
- Created with generated course, category and tag artwork.
