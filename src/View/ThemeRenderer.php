    /**
     * Renders platform-owned Administration section fragments once, then makes
     * the resulting HTML available both to the stock platform workspace and to
     * theme page-family wrappers through @admin.sections. A theme may rearrange
     * these complete fragments but may not replace their business controls.
     *
     * @param array<string,mixed> $data
     * @return array<string,mixed>
     */
    private function materialiseAdministrationSections(array $data): array
    {
        $render = function (array $section, bool $standalone) use ($data): array {
            $template = (string) ($section['template'] ?? '');
            if (preg_match('#^partials/admin/[a-z0-9-]+\.html\.twig$#', $template) !== 1) {
                throw new RuntimeException('Invalid Administration section template.');
            }
            // The section's actions go in the page head when the section is the page, and in its
            // card's head when it is one of several on the "All sections" page.
            $section['actions'] = $this->sectionActions($this->adminSections->actions((string) ($section['key'] ?? '')), $data);
            $section['content'] = $this->fragment($template, array_merge($data, ['section_actions' => $section['actions'], 'section_standalone' => $standalone]));
            // Sections carry their sprite symbol for the same reason navigation items do: a theme
            // listing workspace sections must be able to draw an icon without knowing the key set
            // or shipping artwork of its own.
            $section['icon_id'] = self::navigationIconId((string) ($section['icon'] ?? ''));
            return $section;
        };

        if (isset($data['admin_sections']) && is_array($data['admin_sections'])) {
            $sections = [];
            foreach ($data['admin_sections'] as $section) {
                if (is_array($section)) $sections[] = $render($section, false);
            }
            $data['admin_sections'] = $sections;
        }
        if (isset($data['admin_section']) && is_array($data['admin_section'])) {
            $data['admin_section'] = $render($data['admin_section'], true);
        }
        return $data;
    }

    /**
     * The section actions this reader may use: those whose permission flag the page carries.
     *
     * @param list<array{label:string,href:string,modal:string,variant:string,icon:string,when:string}> $actions
     * @param array<string,mixed> $data
     * @return list<array{label:string,href:string,modal:string,variant:string,icon:string,when:string}>
     */
    private function sectionActions(array $actions, array $data): array
    {
        return array_values(array_filter($actions, static fn(array $action): bool => $action['when'] === '' || (bool) ($data[$action['when']] ?? false)));
    }

    /**
     * Materialises platform-owned Account or Company section fragments for
     * consolidated workspaces and standalone section routes.
     *
     * @param array<string,mixed> $data
     * @return array<string,mixed>
     */
    private function materialiseGenericSections(array $data, string $family): array
    {
        if (!in_array($family, ['account','company'], true)) throw new RuntimeException('Invalid section family.');
        $prefix = 'partials/' . $family . '/';
        $registry = $family === 'account' ? $this->accountSections : $this->companySections;
        $render = function (array $section, bool $standalone) use ($prefix, $family, $data, $registry): array {
            $template = (string) ($section['template'] ?? '');
            if (!str_starts_with($template, $prefix) || preg_match('#^partials/[a-z]+/[a-z0-9-]+\.html\.twig$#', $template) !== 1) {
                throw new RuntimeException('Invalid ' . ucfirst($family) . ' section template.');
            }
            $section['actions'] = $this->sectionActions($registry->actions((string) ($section['key'] ?? '')), $data);
            $section['content'] = $this->fragment($template, array_merge($data, ['section_actions' => $section['actions'], 'section_standalone' => $standalone]));
            // Sections carry their sprite symbol for the same reason navigation items do: a theme
            // listing workspace sections must be able to draw an icon without knowing the key set
            // or shipping artwork of its own.
            $section['icon_id'] = self::navigationIconId((string) ($section['icon'] ?? ''));
            return $section;
        };
        $plural = $family . '_sections';
        $singular = $family . '_section';
        if (isset($data[$plural]) && is_array($data[$plural])) {
            $sections = [];
            foreach ($data[$plural] as $section) if (is_array($section)) $sections[] = $render($section, false);
            $data[$plural] = $sections;
        }
        if (isset($data[$singular]) && is_array($data[$singular])) {
            // The Company workspace opens a section by fetching its page with htmx and keeping only the
            // section's body, so that request draws the section as one of several: its actions in its
            // own card, where the workspace shows them.
            $data[$singular] = $render($data[$singular], ($_SERVER['HTTP_HX_REQUEST'] ?? '') !== 'true');
        }
        return $data;
    }

    /**
     * The page-family objects a theme may read: `course`, `admin`, `account`, and the rest.
     *
     * Every key is present on every page, empty where it does not apply, so a theme template can
     * name one without guarding for its existence. That is the whole reason they are built here
     * rather than left to whichever controller happened to supply them.
     *
     * @param array<string,mixed> $data
     * @return array<string,mixed>
     */
    private function pageFamilyObjects(string $family, array $data): array
    {
        $objects = [];
        foreach (['home','catalogue','course','auth','account','library','module','assessment','certificate','commerce','company','admin','error'] as $key) $objects[$key] = [];
        if (isset($data['course']) && is_array($data['course'])) $objects['course'] = $data['course'];
        if (isset($data['module']) && is_array($data['module'])) $objects['module'] = $data['module'];
        if (isset($data['assessment']) && is_array($data['assessment'])) $objects['assessment'] = $data['assessment'];
        if (isset($data['certificate']) && is_array($data['certificate'])) $objects['certificate'] = $data['certificate'];
        if ($family === 'catalogue') $objects['catalogue'] = ['courses'=>(array)($data['courses']??[]),'categories'=>(array)($data['categories']??[])];
        if ($family === 'library') $objects['library'] = ['courses'=>(array)($data['courses']??$data['library']??[])];
        if ($family === 'home') $objects['home'] = ['courses'=>(array)($data['courses']??[])];
        if ($family === 'admin') {
            $admin = $data;
            $admin['sections'] = isset($data['admin_sections']) && is_array($data['admin_sections'])
                ? $data['admin_sections']
                : [];
            $admin['section'] = isset($data['admin_section']) && is_array($data['admin_section'])
                ? $data['admin_section']
                : [];
            $objects['admin'] = $admin;
        }
        if ($family === 'company' || isset($data['company_sections']) || isset($data['company_section'])) {
            $company = $data;
            $company['sections'] = isset($data['company_sections']) && is_array($data['company_sections']) ? $data['company_sections'] : [];
            $company['section'] = isset($data['company_section']) && is_array($data['company_section']) ? $data['company_section'] : [];
            $objects['company'] = $company;
        }
        if ($family === 'account' || $family === 'library' || isset($data['account_sections']) || isset($data['account_section'])) {
            $account = $data;
            $account['sections'] = isset($data['account_sections']) && is_array($data['account_sections']) ? $data['account_sections'] : [];
            $account['section'] = isset($data['account_section']) && is_array($data['account_section']) ? $data['account_section'] : [];
            $objects['account'] = $account;
        }
        if ($family === 'auth') $objects['auth'] = $data;
        if ($family === 'error') $objects['error'] = $data;

        return $objects;
    }

    /**
     * Renders one platform partial, named as a section registry names it.
     *
     * @param array<string,mixed> $data
     */
    private function fragment(string $template, array $data): string
    {
        return $this->twig->render(
            '@' . ThemeTemplates::PLATFORM_NAMESPACE . '/' . $template,
            array_merge($this->platformScalars(), $data)
        );
    }

    /**
     * The platform values any template may read, whether it is a whole page or one section of one.
     *
     * A section fragment is a piece of a page and must not silently have fewer facilities than the
     * page it sits in. Without this, a section containing a form died on an undefined csrf token -
     * which under Fat-Free was a blank hidden field and a form that failed its own check, and under
     * Twig is an error, which is the better of the two failures but still the wrong page.
     *
     * @return array<string,mixed>
     */
    private function platformScalars(): array
    {
        return [
            'csrf' => Csrf::token(),
            'app_name' => $this->settings->platformName(),
            'app_url' => rtrim(Env::string('APP_URL'), '/'),
            'current_uri' => (string) ($_SERVER['REQUEST_URI'] ?? '/'),
        ] + $this->siteModeScalars();
    }

    /**
     * Whether this is a demo site (SiteMode, owner 2026-10-18) and what a demo site says: every page
     * draws site_demo_notice (partials/flash-messages.html.twig), a checkout and an order
     * site_simulation, and the payment method offers the simulated card only on a demo site.
     *
     * @return array{site_demo:bool,site_demo_notice:string,site_simulation:string}
     */
    private function siteModeScalars(): array
    {
        return ['site_demo' => $this->site?->isDemo() ?? false, 'site_demo_notice' => \CattoLearning\Configuration\SiteMode::NOTICE,
            'site_simulation' => \CattoLearning\Configuration\SiteMode::SIMULATION];
    }

    /** @param array<string,mixed> $data */
    private function assertTemplateData(array $data): void
    {
        foreach ($data as $key => $value) {
            if (preg_match('/^[a-zA-Z_][a-zA-Z0-9_]*$/', $key) !== 1) throw new RuntimeException('Invalid template variable name: ' . $key);
            $this->assertTemplateValue($value, $key);
        }
    }

    private function assertTemplateValue(mixed $value, string $path): void
    {
        if ($value === null || is_scalar($value)) return;
        if (is_array($value)) {
            foreach ($value as $key => $child) $this->assertTemplateValue($child, $path . '[' . (string) $key . ']');
            return;
        }
        throw new RuntimeException('Template data contains an object at ' . $path . '.');
    }
