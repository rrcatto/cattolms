    /**
     * Builds a small, route-aware breadcrumb trail for theme presentation.
     * Every ancestor is linked; the current location is always the final,
     * unlinked item.
     *
     * @param array<string,mixed> $data
     * @return list<array{label:string,href:string,current:bool}>
     */
    private function breadcrumbs(array $data): array
    {
        $path = parse_url((string) ($_SERVER['REQUEST_URI'] ?? '/'), PHP_URL_PATH) ?: '/';
        $title = trim((string) ($data['page_title'] ?? $data['title'] ?? ''));
        $active = (string) ($data['active_nav'] ?? '');
        if ($path === '/') {
            return [['label' => 'Home', 'href' => '', 'current' => true]];
        }

        $crumbs = [['label' => 'Home', 'href' => '/', 'current' => false]];
        $appendCurrent = static function (array &$items, string $label): void {
            if ($label === '') return;
            $items[] = ['label' => $label, 'href' => '', 'current' => true];
        };
        $appendLink = static function (array &$items, string $label, string $href): void {
            $items[] = ['label' => $label, 'href' => $href, 'current' => false];
        };

        if ($active === 'admin') {
            if ($path === '/admin') {
                $appendCurrent($crumbs, 'Administration');
                return $crumbs;
            }

            $appendLink($crumbs, 'Administration', '/admin');
            $segments = array_values(array_filter(explode('/', trim($path, '/'))));
            $sectionKey = (string) ($segments[1] ?? '');
            try {
                $section = $this->adminSections->get($sectionKey);
            } catch (\InvalidArgumentException) {
                $section = ['label' => 'Administration', 'route' => '/admin'];
            }
            $sectionLabel = (string) $section['label'];

            if (count($segments) <= 2) {
                $appendCurrent($crumbs, $sectionLabel);
                return $crumbs;
            }

            $appendLink($crumbs, $sectionLabel, (string) $section['route']);
            $appendCurrent($crumbs, $title !== '' ? $title : $sectionLabel);
            return $crumbs;
        }

        if ($active === 'learning') {
            $appendLink($crumbs, 'My Course Library', '/account/library');
            if (str_starts_with($path, '/learn/')) {
                $course = is_array($data['course'] ?? null) ? $data['course'] : [];
                $courseTitle = trim((string) ($course['title'] ?? 'Course'));
                $slug = trim((string) ($course['slug'] ?? ''));
                $module = is_array($data['module'] ?? null) ? $data['module'] : [];
                $moduleTitle = trim((string) ($module['title'] ?? ''));
                if ($moduleTitle !== '' && $slug !== '') {
                    $appendLink($crumbs, $courseTitle, '/learn/' . rawurlencode($slug));
                    $appendCurrent($crumbs, $moduleTitle);
                } else {
                    $appendCurrent($crumbs, $courseTitle !== '' ? $courseTitle : ($title !== '' ? $title : 'Course'));
                }
            } else {
                // /account/library itself
                array_pop($crumbs);
                $appendCurrent($crumbs, 'My Course Library');
            }
            return $crumbs;
        }

        if ($active === 'catalogue') {
            if ($path === '/courses') {
                $appendCurrent($crumbs, 'Catalogue');
            } else {
                $appendLink($crumbs, 'Catalogue', '/courses');
                $appendCurrent($crumbs, $title !== '' ? $title : 'Course');
            }
            return $crumbs;
        }

        if ($active === 'account') {
            if ($path === '/account') {
                $appendCurrent($crumbs, 'Account');
                return $crumbs;
            }
            $appendLink($crumbs, 'Account', '/account');
            $segments = array_values(array_filter(explode('/', trim($path, '/'))));
            $sectionKey = (string) ($segments[1] ?? 'dashboard');
            if ($sectionKey === 'library') $sectionKey = 'learning';
            try { $section = $this->accountSections->get($sectionKey); }
            catch (\InvalidArgumentException) { $section = ['label' => $title !== '' ? $title : 'Account']; }
            $appendCurrent($crumbs, (string) $section['label']);
            return $crumbs;
        }

        if ($active === 'company') {
            if ($path === '/company') {
                $appendCurrent($crumbs, 'Company');
                return $crumbs;
            }
            $appendLink($crumbs, 'Company', '/company');
            $segments = array_values(array_filter(explode('/', trim($path, '/'))));
            $sectionKey = (string) ($segments[1] ?? 'dashboard');
            try { $section = $this->companySections->get($sectionKey); }
            catch (\InvalidArgumentException) { $section = ['label' => $title !== '' ? $title : 'Company']; }
            $appendCurrent($crumbs, (string) $section['label']);
            return $crumbs;
        }

        $appendCurrent($crumbs, match ($active) {
            'help' => 'Help',
            'contact' => 'Contact',
            default => $title !== '' ? $title : 'Page',
        });
        return $crumbs;
    }

    /**
     * @param array<string,mixed> $data
     * @return list<string>
     */
    private function roles(array $data): array
    {
        $provided = array_values(array_unique(array_filter(array_map(
            static fn(mixed $role): string => strtoupper(trim((string) $role)),
            (array) ($data['role_keys'] ?? [])
        ))));
        if ($provided !== []) return $provided;

        // Compatibility fallback for rendering isolated template fixtures that
        // predate explicit role_keys. Runtime controllers always supply roles.
        $roles = [];
        if ((bool) ($data['is_platform_admin'] ?? false)) $roles[] = 'ADMIN';
        if ((bool) ($data['is_company_admin'] ?? false)) $roles[] = 'COMPANY_ADMIN';
        if ((bool) ($data['is_course_editor'] ?? false)) $roles[] = 'COURSE_EDITOR';
        if ((bool) ($data['is_course_owner'] ?? false)) $roles[] = 'COURSE_OWNER';
        if ((bool) ($data['is_authenticated'] ?? false) && $roles === []) $roles[] = 'STUDENT';
        return array_values(array_unique($roles));
    }

    /**
     * Returns a cache-busted platform-owned browser asset URL for the current
     * LMS release. Theme assets are immutable/versioned separately.
     */
    private function platformAsset(string $path): string
    {
        return $this->themes->platformAssetUrl($path, self::PLATFORM_ASSET_VERSION);
    }

    private function pageFamily(string $page): string
    {
        if (str_starts_with($page, 'admin-')) return 'admin';
        if (str_starts_with($page, 'assessment-')) return 'assessment';
        return match ($page) {
            'home' => 'home', 'courses' => 'catalogue', 'course-detail' => 'course-detail',
            'login','login-sent','company-register' => 'auth', 'profile','sessions','account-control-centre','account-section','account-dashboard','account-activity' => 'account',
            'library' => 'library', 'learn-course','learn-module' => 'course-player',
            'certificate' => 'certificate', 'company-control-centre','company-section' => 'company', 'error' => 'error',
            default => 'content',
        };
    }

    /**
     * Renders platform-owned Administration section fragments once, then makes
     * the resulting HTML available both to the stock platform workspace and to
     * theme page-family wrappers through @admin.sections. A theme may rearrange
     * these complete fragments but may not replace their business controls.
     *
     * @param array<string,mixed> $data
     * @return array<string,mixed>
     */
    private function materialiseAdministrationSections(array $data): array
    {
        $this->f3->set('UI', rtrim($this->themes->platformViewsRoot(), '/') . '/');
        $render = function (array $section): array {
            $template = (string) ($section['template'] ?? '');
            if (preg_match('#^partials/admin/[a-z0-9-]+\.html$#', $template) !== 1) {
                throw new RuntimeException('Invalid Administration section template.');
            }
            $section['content'] = Template::instance()->render($template);
            // Sections carry their sprite symbol for the same reason navigation items do: a theme
            // listing workspace sections must be able to draw an icon without knowing the key set
            // or shipping artwork of its own.
            $section['icon_id'] = self::navigationIconId((string) ($section['icon'] ?? ''));
            return $section;
        };

        if (isset($data['admin_sections']) && is_array($data['admin_sections'])) {
            $sections = [];
            foreach ($data['admin_sections'] as $section) {
                if (is_array($section)) $sections[] = $render($section);
            }
            $data['admin_sections'] = $sections;
            $this->f3->set('admin_sections', $sections);
        }
        if (isset($data['admin_section']) && is_array($data['admin_section'])) {
            $data['admin_section'] = $render($data['admin_section']);
            $this->f3->set('admin_section', $data['admin_section']);
        }
        return $data;
    }

    /**
     * Materialises platform-owned Account or Company section fragments for
     * consolidated workspaces and standalone section routes.
     *
     * @param array<string,mixed> $data
     * @return array<string,mixed>
     */
    private function materialiseGenericSections(array $data, string $family): array
    {
        if (!in_array($family, ['account','company'], true)) throw new RuntimeException('Invalid section family.');
        $this->f3->set('UI', rtrim($this->themes->platformViewsRoot(), '/') . '/');
        $prefix = 'partials/' . $family . '/';
        $render = function (array $section) use ($prefix, $family): array {
            $template = (string) ($section['template'] ?? '');
            if (!str_starts_with($template, $prefix) || preg_match('#^partials/[a-z]+/[a-z0-9-]+\.html$#', $template) !== 1) {
                throw new RuntimeException('Invalid ' . ucfirst($family) . ' section template.');
            }
            $section['content'] = Template::instance()->render($template);
            // Sections carry their sprite symbol for the same reason navigation items do: a theme
            // listing workspace sections must be able to draw an icon without knowing the key set
            // or shipping artwork of its own.
            $section['icon_id'] = self::navigationIconId((string) ($section['icon'] ?? ''));
            return $section;
        };
        $plural = $family . '_sections';
        $singular = $family . '_section';
        if (isset($data[$plural]) && is_array($data[$plural])) {
            $sections = [];
            foreach ($data[$plural] as $section) if (is_array($section)) $sections[] = $render($section);
            $data[$plural] = $sections;
            $this->f3->set($plural, $sections);
        }
        if (isset($data[$singular]) && is_array($data[$singular])) {
            $data[$singular] = $render($data[$singular]);
            $this->f3->set($singular, $data[$singular]);
        }
        return $data;
    }

    /** @param array<string,mixed> $data */
    private function setPageFamilyObjects(string $family, array $data): void
    {
        foreach (['home','catalogue','course','auth','account','library','module','assessment','certificate','commerce','company','admin','error'] as $key) $this->f3->set($key, []);
        if (isset($data['course']) && is_array($data['course'])) $this->f3->set('course', $data['course']);
        if (isset($data['module']) && is_array($data['module'])) $this->f3->set('module', $data['module']);
        if (isset($data['assessment']) && is_array($data['assessment'])) $this->f3->set('assessment', $data['assessment']);
        if (isset($data['certificate']) && is_array($data['certificate'])) $this->f3->set('certificate', $data['certificate']);
        if ($family === 'catalogue') $this->f3->set('catalogue', ['courses'=>(array)($data['courses']??[]),'categories'=>(array)($data['categories']??[])]);
        if ($family === 'library') $this->f3->set('library', ['courses'=>(array)($data['courses']??$data['library']??[])]);
        if ($family === 'home') $this->f3->set('home', ['courses'=>(array)($data['courses']??[])]);
        if ($family === 'admin') {
            $admin = $data;
            $admin['sections'] = isset($data['admin_sections']) && is_array($data['admin_sections'])
                ? $data['admin_sections']
                : [];
            $admin['section'] = isset($data['admin_section']) && is_array($data['admin_section'])
                ? $data['admin_section']
                : [];
            $this->f3->set('admin', $admin);
        }
        if ($family === 'company' || isset($data['company_sections']) || isset($data['company_section'])) {
            $company = $data;
            $company['sections'] = isset($data['company_sections']) && is_array($data['company_sections']) ? $data['company_sections'] : [];
            $company['section'] = isset($data['company_section']) && is_array($data['company_section']) ? $data['company_section'] : [];
            $this->f3->set('company', $company);
        }
        if ($family === 'account' || $family === 'library' || isset($data['account_sections']) || isset($data['account_section'])) {
            $account = $data;
            $account['sections'] = isset($data['account_sections']) && is_array($data['account_sections']) ? $data['account_sections'] : [];
            $account['section'] = isset($data['account_section']) && is_array($data['account_section']) ? $data['account_section'] : [];
            $this->f3->set('account', $account);
        }
        if ($family === 'auth') $this->f3->set('auth', $data);
        if ($family === 'error') $this->f3->set('error', $data);
    }

    /** @param array<string,mixed> $data */
    private function assertTemplateData(array $data): void
    {
        foreach ($data as $key => $value) {
            if (preg_match('/^[a-zA-Z_][a-zA-Z0-9_]*$/', $key) !== 1) throw new RuntimeException('Invalid template variable name: ' . $key);
            $this->assertTemplateValue($value, $key);
        }
    }

    private function assertTemplateValue(mixed $value, string $path): void
    {
        if ($value === null || is_scalar($value)) return;
        if (is_array($value)) {
            foreach ($value as $key => $child) $this->assertTemplateValue($child, $path . '[' . (string) $key . ']');
            return;
        }
        throw new RuntimeException('Template data contains an object at ' . $path . '.');
    }
