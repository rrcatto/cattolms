    /**
     * Renders one platform-owned template as a bare fragment, without the theme base layout.
     *
     * htmx swaps the result into a live document, so no theme `base.html`, navigation or page
     * family wrapper may be applied. The fragment is functional core markup styled by the
     * theme's ordinary platform classes.
     *
     * @param array<string,mixed> $data
     */
    public function renderFragment(string $template, array $data = []): string
    {
        if (preg_match('/^[a-zA-Z0-9_\/-]+$/', $template) !== 1) {
            throw new RuntimeException('Invalid fragment template.');
        }
        $this->assertTemplateData($data);

        // The platform scalars a fragment may legitimately need, set BEFORE the caller's data so a
        // caller can still override one deliberately.
        //
        // A fragment is a piece of a page and must not silently have fewer facilities than the
        // page. Without this, a fragment containing a form died mid-output on "Undefined variable
        // $csrf" - the response was a truncated document, htmx swapped it into the results region,
        // and because the swap replaced the element that carried the target id, the control was
        // dead until a full page load. One missing token disabled the whole surface.
        foreach ([
            'csrf' => Csrf::token(),
            'app_name' => $this->settings->platformName(),
            'app_url' => rtrim(Env::string('APP_URL'), '/'),
            'current_uri' => (string) ($_SERVER['REQUEST_URI'] ?? '/'),
        ] as $key => $value) {
            $this->f3->set($key, $value);
        }

        foreach ($data as $key => $value) $this->f3->set($key, $value);

        $this->f3->set('UI', rtrim($this->themes->platformViewsRoot(), '/') . '/');

        return self::stripHtmlComments(Template::instance()->render($template . '.html'));
    }

    /**
     * Removes every HTML comment from rendered output, leaving script, style, pre and textarea
     * content untouched.
     *
     * Every template carries a file metadata header, and several carry explanatory notes about
     * why a control is built the way it is. Those are written for the next developer, not for the
     * public, and an HTML comment is served verbatim: without this they are readable in view
     * source on every page. Stripping happens here, at the one point where a response is
     * finished, so a template author never has to think about it and no theme can opt out.
     *
     * The alternation consumes script, style, pre and textarea blocks whole and returns them
     * unchanged. Imported course HTML reaches the page through a raw template token, so it can
     * legitimately contain a script whose string holds a comment delimiter; a plain
     * comment-stripping pattern would cut such a script in half. Whitespace-significant elements
     * are skipped for the same reason: their content is not ours to rewrite.
     *
     * This is deliberately not a minifier. It removes comments and nothing else, so a rendering
     * difference can never be blamed on it.
     */
    private static function stripHtmlComments(string $html): string
    {
        $stripped = preg_replace_callback(
            '#(<(script|style|pre|textarea)\b[^>]*>.*?</\2\s*>)|<!--.*?-->#is',
            static fn(array $match): string => $match[1] ?? '',
            $html
        );

        // A catastrophic backtrack or a bad UTF-8 sequence returns null. Serving the page with
        // its comments intact is a cosmetic failure; serving nothing is an outage.
        return $stripped ?? $html;
    }

    /** @param array<string,mixed> $data */
    public function render(string $page, array $data = [], int $status = 200): string
    {
        if (preg_match('/^[a-zA-Z0-9_\/-]+$/', $page) !== 1) {
            throw new RuntimeException('Invalid page template.');
        }
        $this->assertTemplateData($data);

        $themeKey = $this->themes->activeTheme();
        $previewTheme = trim((string) ($_GET['theme_preview'] ?? ''));
        $previewActive = false;
        if ($previewTheme !== '' && $this->can($data, 'SYSTEM.THEME.VIEW')) {
            try {
                $this->themes->theme($previewTheme);
                $themeKey = $previewTheme;
                $previewActive = $previewTheme !== $this->themes->activeTheme();
            } catch (RuntimeException) {
                // Invalid preview requests do not change the selected live theme.
            }
        }

        foreach ([
            'title' => '', 'page_title' => '', 'page_kicker' => '', 'active_nav' => '', 'body_class' => '',
            'is_authenticated' => false, 'is_platform_admin' => false, 'is_company_admin' => false,
            'is_course_editor' => false, 'is_course_owner' => false, 'user_email' => '', 'user_name' => '',
            'load_ckeditor' => false, 'load_question_editor' => false, 'load_assessment_timer' => false,
            'course_content_mode' => false, 'flash_messages' => [], 'permissions' => [],
        ] as $key => $value) {
            $this->f3->set($key, $value);
        }
        foreach ($data as $key => $value) $this->f3->set($key, $value);

        $appName = $this->settings->platformName();
        $appUrl = rtrim(Env::string('APP_URL'), '/');
        $family = $this->pageFamily($page);
        $themeInfo = $this->themes->theme($themeKey);
        $assetUrl = $this->themes->themeAssetUrl($themeKey);
        $csrf = Csrf::token();

        $this->f3->set('app_name', $appName);
        $this->f3->set('app_url', $appUrl);
        $this->f3->set('theme_name', (string) $themeInfo['name']);
        $this->f3->set('theme_asset_url', $assetUrl);
        $this->f3->set('theme_preview_active', $previewActive);
        $this->f3->set('csrf', $csrf);
        $this->f3->set('current_uri', (string) ($_SERVER['REQUEST_URI'] ?? '/'));

        $navigation = $this->navigation($data, $csrf);
        $platformStyles = [$this->platformAsset('/css/bootstrap.min.css'), $this->platformAsset('/css/catto-platform.css')];
        if ((bool) ($data['load_ckeditor'] ?? false)) $platformStyles[] = $this->platformAsset('/css/ckeditor5.css');
        // htmx is a platform-owned progressive enhancement: every surface that uses it renders
        // and works server-side first, so the page degrades to plain navigation if the script
        // is absent. Supplied with the other vendor browser assets under the public root.
        $platformScripts = [
            $this->platformAsset('/js/bootstrap.bundle.min.js'),
            $this->platformAsset('/js/htmx.min.js'),
            $this->platformAsset('/js/platform-overrides.js'),
        ];
        if ((bool) ($data['load_ckeditor'] ?? false)) {
            $platformScripts[] = $this->platformAsset('/js/ckeditor5.umd.js');
            $platformScripts[] = $this->platformAsset('/js/ck-main.js');
        }
        if ((bool) ($data['load_question_editor'] ?? false)) $platformScripts[] = $this->platformAsset('/js/question-editor.js');
        if ((bool) ($data['load_assessment_timer'] ?? false)) $platformScripts[] = $this->platformAsset('/js/assessment-timer.js');

        $this->f3->set('app', ['name' => $appName, 'base_url' => $appUrl !== '' ? $appUrl : '/']);
        $this->f3->set('platform', [
            'styles' => $platformStyles,
            'scripts' => $platformScripts,
            // One sprite for every theme. Fingerprinted like every other platform asset so a
            // changed icon reaches a browser that already cached the old one.
            'icon_sprite' => $this->platformAsset('/img/nav-icons.svg'),
        ]);
        $this->f3->set('theme', [
            'name' => (string) $themeInfo['name'],
            'version' => (string) $themeInfo['version'],
            'slug' => (string) $themeInfo['slug'],
            'key' => $themeKey,
            'asset_url' => $assetUrl,
            'styles' => $this->themes->themeStyles($themeKey),
            'scripts' => $this->themes->themeScripts($themeKey),
            'external_styles' => $this->themes->externalStyles($themeKey),
            'external_scripts' => $this->themes->externalScripts($themeKey),
            'is_child' => (bool) $themeInfo['is_child'],
            'parent_name' => (string) $themeInfo['parent_name'],
            'parent_version' => (string) $themeInfo['parent_version'],
        ]);
        $this->f3->set('page', [
            'type' => $family,
            'title' => (string) ($data['page_title'] ?? $data['title'] ?? ''),
            'subtitle' => (string) ($data['page_kicker'] ?? ''),
            'body_class' => (string) ($data['body_class'] ?? ''),
        ]);
        $this->f3->set('user', [
            'logged_in' => (bool) ($data['is_authenticated'] ?? false),
            'name' => trim((string) ($data['user_name'] ?? '')) !== '' ? (string) $data['user_name'] : (string) ($data['user_email'] ?? ''),
            'roles' => $this->roles($data),
        ]);
        $this->f3->set('navigation', $navigation);
        $this->f3->set('footer_navigation', $this->footerNavigation($data));
        $this->f3->set('breadcrumbs', $this->breadcrumbs($data));
        $this->f3->set('flash', array_values((array) ($data['flash_messages'] ?? [])));
        $this->f3->set('sidebar', '');
        if ($family === 'admin') {
            $data = $this->materialiseAdministrationSections($data);
        }
        if (isset($data['account_sections']) || isset($data['account_section'])) {
            $data = $this->materialiseGenericSections($data, 'account');
        }
        if (isset($data['company_sections']) || isset($data['company_section'])) {
            $data = $this->materialiseGenericSections($data, 'company');
        }
        $this->setPageFamilyObjects($family, $data);

        // Functional LMS page markup is platform-owned and independent of every theme.
        $this->f3->set('UI', rtrim($this->themes->platformViewsRoot(), '/') . '/');
        $platformContent = Template::instance()->render('pages/' . $page . '.html');
        $content = $platformContent;

        // Optional page-family wrappers are presentation only and resolve child -> direct parent.
        if ($this->themes->hasPageOverride($themeKey, $family)) {
            $this->f3->set('content', $platformContent);
            $this->f3->set('UI', $this->themes->themeUiPath($themeKey));
            $content = Template::instance()->render('pages/' . $family . '.html');
        }

        $this->f3->set('content', $content);
        $this->f3->set('UI', $this->themes->themeUiPath($themeKey));
        if (!headers_sent() && $this->f3->get('ERROR') === null) {
            http_response_code($status);
        }
        return self::stripHtmlComments(Template::instance()->render('base.html'));
    }

    /**
     * @param array<string,mixed> $data
     * @return list<array<string,mixed>>
     */
    private function navigation(array $data, string $csrf): array
    {
        $active = (string) ($data['active_nav'] ?? '');
        // Both helpers take the SEMANTIC icon key, never artwork. Core resolves it to two things:
        // the text glyph a theme may still use, and icon_id, the symbol every theme references in
        // the platform sprite. Passing a glyph here is what made icons a per-theme responsibility.
        $item = fn(string $key, string $label, string $href, string $icon, bool $isActive, string $method = 'GET', string $token = '', array $children = []): array => [
            'key'=>$key,'label'=>$label,'href'=>$href,
            'icon'=>$this->navigationIcon($icon),'icon_id'=>self::navigationIconId($icon),
            'active'=>$isActive,'method'=>$method,'csrf'=>$token,'children'=>$children,
        ];
        $child = fn(string $key,string $label,string $href,string $icon): array => [
            'key'=>$key,'label'=>$label,'href'=>$href,
            'icon'=>$this->navigationIcon($icon),'icon_id'=>self::navigationIconId($icon),
            'method'=>'GET',
        ];

        $items = [
            $item('home','Home','/','home',$active==='home'),
            $item('catalogue','Catalogue','/courses','catalogue',$active==='catalogue'),
            $item('help','Help','/help','help',$active==='help'),
            $item('contact','Contact','/contact','contact',$active==='contact'),
        ];

        if ($this->can($data, 'COMPANY.DASHBOARD.VIEW')) {
            $companyChildren = [$child('company-all','All company sections','/company','▤')];
            $companyPermissionBySection = [
                'dashboard' => 'COMPANY.DASHBOARD.VIEW',
                'people' => 'COMPANY.PERSON.VIEW',
                'requests' => 'COMPANY.REQUEST.VIEW',
                'enrolments' => 'COMPANY.ENROLMENT.VIEW',
                'credits' => 'COMPANY.CREDIT.VIEW',
                'courses' => 'COMPANY.COURSE.VIEW',
            ];
            foreach ($this->companySections->all() as $section) {
                $suffix = $companyPermissionBySection[$section['key']] ?? 'COMPANY.DASHBOARD.VIEW';
                if (!$this->can($data, $suffix)) continue;
                $companyChildren[] = $child('company-'.$section['key'],$section['label'],$section['route'],$section['icon']);
            }
            $items[] = $item('company','Company','/company','▤',$active==='company',children:$companyChildren);
        }

        $adminChildren = [];
        $adminPermissionBySection = [
            'dashboard' => ['business', 'PLATFORM.DASHBOARD.VIEW'],
            'courses' => ['business', 'COURSE.MANAGEMENT.VIEW'],
            'people' => ['business', 'PLATFORM.PERSON.VIEW'],
            'companies' => ['business', 'PLATFORM.COMPANY.VIEW'],
            'enrolments' => ['business-any', ['PLATFORM.ENROLMENT.VIEW', 'PLATFORM.REQUEST.VIEW']],
            'credits' => ['business', 'PLATFORM.CREDIT.VIEW'],
            'activity' => ['business', 'PLATFORM.ACTIVITY.VIEW'],
            'reports' => ['business', 'PLATFORM.REPORT.VIEW'],
            'themes' => ['system', 'SYSTEM.THEME.VIEW'],
            'roles' => ['system', 'SYSTEM.ROLE.VIEW'],
            'settings' => ['system', 'SYSTEM.SETTING.VIEW'],
        ];
        foreach ($this->adminSections->all() as $section) {
            [$kind, $permission] = $adminPermissionBySection[$section['key']] ?? ['business', 'PLATFORM.DASHBOARD.VIEW'];
            $allowed = match ($kind) {
                'system' => $this->can($data, (string) $permission),
                'business-any' => array_any((array) $permission, fn(string $suffix): bool => $this->can($data, $suffix)),
                default => $this->can($data, (string) $permission),
            };
            if (!$allowed) continue;
            $adminChildren[] = $child('admin-'.$section['key'],$section['label'],$section['route'],$section['icon']);
        }
        if ($adminChildren !== []) {
            array_unshift($adminChildren, $child('admin-all','All administration','/admin','all'));
            $items[] = $item('administration','Administration','/admin','administration',$active==='admin',children:$adminChildren);
        }

        if ((bool) ($data['is_authenticated'] ?? false)) {
            $accountPermissionBySection = [
                'dashboard' => 'ACCOUNT.VIEW',
                'profile' => 'ACCOUNT.PROFILE.VIEW',
                'learning' => 'LEARNING.LIBRARY.VIEW',
                'sessions' => 'ACCOUNT.SESSION.VIEW',
                'activity' => 'ACCOUNT.ACTIVITY.VIEW',
            ];
            $accountChildren = [$child('account-all','Account dashboard','/account','dashboard')];
            foreach ($this->accountSections->all() as $section) {
                if (!$this->can($data, $accountPermissionBySection[$section['key']] ?? 'ACCOUNT.VIEW')) continue;
                $accountChildren[] = $child('account-'.$section['key'],$section['label'],$section['route'],$section['icon']);
            }
            $items[] = $item('account','Account','/account','account',$active==='account',children:$accountChildren);
            $items[] = $item('signout','Sign out','/logout','signout',false,'POST',$csrf);
        } else {
            $items[] = $item('signin','Register / Sign in','/login','signin',$active==='login');
        }
        return $items;
    }

    /**
     * @param array<string,mixed> $data
     * @return list<array{key:string,label:string,href:string}>
     */
    private function footerNavigation(array $data): array
    {
        $items = [
            ['key'=>'home','label'=>'Home','href'=>'/'],
            ['key'=>'catalogue','label'=>'Catalogue','href'=>'/courses'],
            ['key'=>'help','label'=>'Help','href'=>'/help'],
            ['key'=>'contact','label'=>'Contact','href'=>'/contact'],
            ['key'=>'privacy','label'=>'Privacy','href'=>'/privacy'],
        ];
        if ((bool) ($data['is_authenticated'] ?? false)) $items[] = ['key'=>'account','label'=>'Account','href'=>'/account'];
        if ($this->can($data,'COMPANY.DASHBOARD.VIEW')) $items[] = ['key'=>'company','label'=>'Company','href'=>'/company'];
        if ($this->hasAdministrationAccess($data)) $items[] = ['key'=>'admin','label'=>'Administration','href'=>'/admin'];
        return $items;
    }

    /** @param array<string,mixed> $data */
    private function can(array $data, string $permission): bool
    {
        if (in_array('ADMIN', $this->roles($data), true)) return true;
        return in_array(strtoupper($permission), array_map('strtoupper', (array) ($data['permissions'] ?? [])), true);
    }

    /** @param array<string,mixed> $data */
    private function hasAdministrationAccess(array $data): bool
    {
        foreach ([
            'PLATFORM.DASHBOARD.VIEW','COURSE.MANAGEMENT.VIEW','PLATFORM.PERSON.VIEW','PLATFORM.COMPANY.VIEW',
            'PLATFORM.ENROLMENT.VIEW','PLATFORM.REQUEST.VIEW','PLATFORM.CREDIT.VIEW','PLATFORM.ACTIVITY.VIEW','PLATFORM.REPORT.VIEW',
        ] as $permission) {
            if ($this->can($data, $permission)) return true;
        }
        foreach (['SYSTEM.THEME.VIEW','SYSTEM.ROLE.VIEW','SYSTEM.SETTING.VIEW'] as $permission) {
            if ($this->can($data, $permission)) return true;
        }
        return false;
    }

    /**
     * Maps Administration section icon identities to the existing compact
     * navigation glyphs without duplicating section routes or labels. Themes
     * remain free to replace these presentation glyphs with their own icons.
     */
    /**
     * Every semantic navigation icon key core can emit, and the sprite symbol it resolves to.
     *
     * Declared rather than derived, so the set is a fact a test can enumerate: NavigationIconContractTest
     * fails if a key here has no symbol in public_html/img/nav-icons.svg. That is what stops a new
     * or renamed menu item rendering as a blank space, which is what happened every time a
     * navigation key changed and each theme had to be edited to catch up.
     *
     * @var list<string>
     */
    public const NAVIGATION_ICON_KEYS = [
        'home', 'catalogue', 'help', 'contact', 'privacy', 'signin', 'signout',
        'account', 'company', 'administration', 'all',
        'dashboard', 'people', 'companies', 'courses', 'enrolments', 'credits',
        'requests', 'activity', 'reports', 'themes', 'settings', 'roles', 'seed',
        'sessions', 'learning', 'profile',
    ];

    /** The symbol an unknown key resolves to, so a menu item is never iconless. */
    public const NAVIGATION_ICON_FALLBACK = 'nav-fallback';

    /**
     * The sprite symbol id for one semantic icon key.
     *
     * Core owns this mapping so every theme shows the same icon for the same menu item. A theme
     * that wants its own artwork ships a symbol with the same id; it never has to know the key set.
     */
    public static function navigationIconId(string $icon): string
    {
        return in_array($icon, self::NAVIGATION_ICON_KEYS, true)
            ? 'nav-' . $icon
            : self::NAVIGATION_ICON_FALLBACK;
    }

