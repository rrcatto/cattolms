    /**
     * Returns the active theme's optional auto-managed palette contract.
     *
     * A theme opts in by declaring one or more five-colour palettes. Every
     * palette is normalised from darkest to lightest by WCAG relative luminance.
     * One palette is applied automatically without a switcher; two or more make
     * the core palette switcher available. Themes without palettes retain
     * complete control of their own colours.
     *
     * @return array<string,mixed>
     */
    public function paletteConfiguration(string $key): array
    {
        $theme = $this->theme($key);
        $declared = $theme['manifest']['palettes'] ?? null;
        if (!is_array($declared) || count($declared) < 1) {
            return [
                'enabled' => false,
                'switcher_visible' => false,
                'palette_count' => 0,
                'theme_key' => (string) $theme['key'],
                'palettes' => [],
            ];
        }

        $palettes = [];
        foreach ($declared as $index => $palette) {
            if (!is_array($palette)) continue;
            $colours = array_values(array_map(static fn(mixed $colour): string => strtoupper((string) $colour), (array) ($palette['colors'] ?? [])));
            usort($colours, fn(string $a, string $b): int => $this->relativeLuminance($a) <=> $this->relativeLuminance($b));
            $palettes[] = [
                'id' => 'palette-' . ($index + 1),
                'name' => trim((string) ($palette['name'] ?? 'Palette ' . ($index + 1))),
                'colors' => $colours,
                'foregrounds' => array_map(fn(string $colour): string => $this->contrastForeground($colour), $colours),
            ];
        }

        $paletteCount = count($palettes);
        return [
            'enabled' => $paletteCount >= 1,
            'switcher_visible' => $paletteCount >= 2,
            'palette_count' => $paletteCount,
            'theme_key' => (string) $theme['key'],
            'theme_name' => (string) $theme['name'],
            'theme_version' => (string) $theme['version'],
            'palettes' => $palettes,
        ];
    }

    public function hasPageOverride(string $key, string $family): bool
    {
