    /** @return list<array<string,mixed>> */
    private function discoverInstalledThemes(): array
    {
        $itemsByKey = [];
        $root = $this->themesRoot();
        if (is_dir($root)) {
            foreach (scandir($root) ?: [] as $entry) {
                if ($entry === '.' || $entry === '..' || str_starts_with($entry, '.')) continue;
                $container = $root . '/' . $entry;
                if (!is_dir($container)) continue;

                // Current installs place theme.json directly in the versioned
                // directory. Older releases could leave one enclosing package
                // directory behind; accept that legacy layout as well so a
                // filesystem-authoritative resync can recover it.
                $candidates = [$container];
                foreach (scandir($container) ?: [] as $child) {
                    if ($child === '.' || $child === '..' || str_starts_with($child, '.')) continue;
                    $nested = $container . '/' . $child;
                    if (is_dir($nested) && is_file($nested . '/theme.json')) $candidates[] = $nested;
                }

                foreach ($candidates as $dir) {
                    if (!is_file($dir . '/theme.json')) continue;
                    try {
                        $manifest = $this->validator->validateInstalledDirectory($dir);
                    } catch (\Throwable) {
                        continue;
                    }
                    $meta = (array) $manifest['theme'];
                    $key = $this->installKey((string) $meta['slug'], (string) $meta['version']);
                    $item = $this->themeRecord($key, $dir, $manifest);
                    $item['filesystem_key'] = $entry;
                    // Prefer the canonical direct directory if both a legacy
                    // layout and canonical layout describe the same release.
                    if (!isset($itemsByKey[$key]) || basename($dir) === $key) {
                        $itemsByKey[$key] = $item;
                    }
                }
            }
        }

        // Factory Reset for the current LMS release is a bundled recovery
        // boundary. Always prefer the bundled copy for its exact version so a
        // stale persistent duplicate cannot shadow repaired core presentation
        // files. Older Factory Reset versions remain separately discoverable.
        $defaultKey = $this->defaultThemeKey();
        $dir = $this->bundledFactoryResetRoot();
        $manifest = $this->validator->validateInstalledDirectory($dir);
        $item = $this->themeRecord($defaultKey, $dir, $manifest);
        $item['filesystem_key'] = 'factory-reset-v1.0.1';
        $itemsByKey[$defaultKey] = $item;
        return array_values($itemsByKey);
    }

    /**
     * @param array<string,mixed> $manifest
     * @return array<string,mixed>
     */
    private function themeRecord(string $key, string $root, array $manifest): array
    {
        $meta = (array) $manifest['theme'];
        $parent = is_array($manifest['parent'] ?? null) ? $manifest['parent'] : null;
        return [
            'key' => $key,
            'slug' => (string) $meta['slug'],
            'name' => (string) $meta['name'],
            'version' => (string) $meta['version'],
            'author' => (string) $meta['author'],
            'description' => (string) $meta['description'],
            'manifest' => $manifest,
            'manifest_sha256' => hash_file('sha256', $root . '/theme.json') ?: '',
            'root' => $root,
            'storage' => 'filesystem',
            'parent_name' => $parent !== null ? (string) $parent['name'] : '',
            'parent_version' => $parent !== null ? (string) $parent['version'] : '',
            'is_child' => $parent !== null,
        ];
    }

    private function themeRootForKey(string $key): string
    {
        $key = $this->normaliseKey($key);
        foreach ($this->discoverInstalledThemes() as $theme) {
            if ((string) $theme['key'] === $key || (string) ($theme['filesystem_key'] ?? '') === $key) {
                return (string) $theme['root'];
            }
        }
        if ($key === $this->defaultThemeKey()) return $this->bundledFactoryResetRoot();
        throw new RuntimeException('The theme is not installed: ' . $key . '.');
    }

    private function bundledFactoryResetRoot(): string
    {
        return rtrim($this->codeRoot, '/') . '/themes/factory-reset';
    }

    /** @return array<string,mixed> */
    private function bundledFactoryResetManifest(): array
    {
        $path = $this->bundledFactoryResetRoot() . '/theme.json';
        $manifest = json_decode((string) file_get_contents($path), true, 512, JSON_THROW_ON_ERROR);
        if (!is_array($manifest)) throw new RuntimeException('Bundled Factory Reset theme.json is invalid.');
        return $manifest;
    }

    private function themesRoot(): string
    {
        return rtrim($this->instanceRoot, '/') . '/themes';
    }

    private function publicThemeRoot(string $key): string
    {
        return rtrim($this->publicRoot, '/') . '/themes/' . $key;
    }

    private function installKey(string $slug, string $version): string
    {
        $safeVersion = preg_replace('/[^0-9A-Za-z._-]+/', '-', $version) ?? $version;
        return $slug . '-v' . $safeVersion;
    }

    private function normaliseKey(string $key): string
    {
        $key = trim($key);
        if ($key === '' || $key === 'default' || $key === self::FACTORY_RESET_SLUG) return $this->defaultThemeKey();
        if (preg_match('/^[a-z0-9][a-z0-9._-]*$/', $key) !== 1) {
            throw new RuntimeException('Invalid installed theme identifier.');
        }
        return $key;
    }

