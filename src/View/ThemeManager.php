    /** @param array<string,mixed> $manifest */
    private function assertInstallableManifest(array $manifest): void
    {
        $meta = (array) $manifest['theme'];
        $name = (string) $meta['name'];
        $version = (string) $meta['version'];
        if ($this->findByNameVersion($name, $version) !== null) {
            throw new RuntimeException('Theme ' . $name . ' ' . $version . ' is already installed. Uninstall that exact release before reinstalling it.');
        }
        $key = $this->installKey((string) $meta['slug'], $version);
        if (file_exists($this->themesRoot() . '/' . $key)) {
            throw new RuntimeException('The theme installation key already exists: ' . $key . '.');
        }

        $parent = is_array($manifest['parent'] ?? null) ? $manifest['parent'] : null;
        if ($parent === null) return;
        $installedParent = $this->findByNameVersion((string) $parent['name'], (string) $parent['version']);
        if ($installedParent === null) {
            throw new RuntimeException('Install the exact parent theme ' . (string) $parent['name'] . ' ' . (string) $parent['version'] . ' before installing this child theme.');
        }
        if (is_array($installedParent['manifest']['parent'] ?? null)) {
            throw new RuntimeException('Child themes cannot inherit from another child theme.');
        }
    }

    /** @return list<array<string,mixed>> */
    private function themeLayers(string $key): array
    {
        $theme = $this->theme($key);
        if (!(bool) $theme['is_child']) return [$theme];
        $parent = $this->theme((string) $theme['parent_key']);
        return [$parent, $theme];
    }

    /**
     * @param array<string,mixed> $layer
     */
    private function versionedThemeAssetUrl(array $layer, string $path): string
    {
        $relative = ltrim($path, '/');
        // Fingerprint the browser-visible copy rather than the immutable source
        // directory. This guarantees a same-version defect repair invalidates
        // the actual file that the web server is serving.
        $file = rtrim($this->publicRoot, '/') . '/themes/' . (string) $layer['key'] . '/' . $relative;
        return $this->themeAssetUrl((string) $layer['key']) . '/' . $relative
            . '?v=' . $this->assetFingerprint($file, (string) ($layer['manifest_sha256'] ?? ''));
    }

    /**
     * @param array<string,mixed> $theme
     */
    private function versionedPublishedThemeAssetUrl(array $theme, string $path): string
    {
        $relative = ltrim($path, '/');
        $file = rtrim($this->publicRoot, '/') . '/themes/' . (string) $theme['key'] . '/' . $relative;
        return $this->themeAssetUrl((string) $theme['key']) . '/' . $relative
            . '?v=' . $this->assetFingerprint($file, (string) ($theme['manifest_sha256'] ?? ''));
    }

    private function assetFingerprint(string $file, string $fallback): string
    {
        if (is_file($file)) {
            $hash = hash_file('sha256', $file);
            if ($hash !== false) {
                return substr($hash, 0, 16);
            }
        }
        return substr(hash('sha256', $fallback), 0, 16);
    }

    /** @return list<string> */
    private function externalResources(string $key, string $family): array
    {
        $urls = [];
        foreach ($this->themeLayers($key) as $layer) {
            foreach ((array) ($layer['manifest']['external'][$family] ?? []) as $url) $urls[] = (string) $url;
        }
        return array_values(array_unique($urls));
    }

    /** @return array<string,mixed>|null */
    private function findByNameVersion(string $name, string $version): ?array
    {
        foreach ($this->discoverInstalledThemes() as $theme) {
            if (strcasecmp((string) $theme['name'], $name) === 0 && (string) $theme['version'] === $version) return $theme;
