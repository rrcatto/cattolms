declare(strict_types=1);

namespace CattoLearning\View\Twig;

use Twig\Loader\FilesystemLoader;

final class ThemeTemplates
{
    public const THEME_NAMESPACE = 'theme';
    public const PLATFORM_NAMESPACE = 'platform';

    public function __construct(private readonly FilesystemLoader $loader)
    {
    }

    /**
     * Points `@theme` at a theme's roots, most specific first.
     *
     * setPaths() replaces rather than appends, which matters: a preview request must not leave the
     * previous theme searchable behind the new one.
     *
     * @param list<string> $roots From ThemeManager::themeTemplateRoots(): child release, then parent.
     */
    public function use(array $roots): void
    {
        $this->loader->setPaths($roots, self::THEME_NAMESPACE);
    }

    /**
     * The layout a page of this family extends.
     *
     * A theme may ship an optional per-family wrapper - an administration shell, a course-player
     * frame - and where it does, that wrapper extends the theme's base itself. Where it does not,
     * the page extends the base directly. Resolving it here means a platform page template never
     * has to know which themes have wrappers, which is the whole point of the wrapper being
     * optional.
     */
    public function layoutFor(string $family): string
    {
        $wrapper = '@' . self::THEME_NAMESPACE . '/pages/' . $family . '.html.twig';

        return $this->loader->exists($wrapper)
            ? $wrapper
            : '@' . self::THEME_NAMESPACE . '/base.html.twig';
    }

    public function pageTemplate(string $page): string
    {
        return '@' . self::PLATFORM_NAMESPACE . '/pages/' . $page . '.html.twig';
    }

    public function hasPage(string $page): bool
    {
        return $this->loader->exists($this->pageTemplate($page));
    }
}
