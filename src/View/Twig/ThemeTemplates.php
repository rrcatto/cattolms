Description:
Points Twig's `@theme` namespace at the theme a request renders in.

Architectural boundary: view plumbing. It resolves paths and template names; it renders nothing and
knows no page data.

Two namespaces, and the split between them is the platform's oldest view rule. `@platform` is the
functional page bodies, which are core-owned and may never move into a theme. `@theme` is the
chrome, and it is a *list* of roots - a child release first, then its parent - so a child that ships
only a footer inherits every other template by falling through. Twig's filesystem loader tries the
paths of a namespace in order, which is exactly that rule, so nothing here implements inheritance;
the order itself comes from ThemeManager, which is where theme layering is already decided.

The namespace is reset per request rather than fixed at boot because an administrator may preview a
theme. Twig's compiled-template cache is keyed on the resolved file path, so two themes that both
define base.html.twig cannot collide in it.

Changelog:
2026/09/09 01:20 SAST
- Created for the Twig theme layer.
