declare(strict_types=1);

namespace CattoLearning\View\Twig;

use CattoLearning\View\ThemeManager;
use CattoLearning\View\ThemeRenderer;
use Symfony\Component\HttpFoundation\Response;
use Twig\Environment;

final class TwigPageRenderer
{
    public function __construct(
        private readonly Environment $twig,
        private readonly ThemeTemplates $templates,
        private readonly ThemeManager $themes,
        private readonly ThemeRenderer $model
    ) {
    }

    /** @param array<string,mixed> $data */
    public function render(string $page, array $data = [], int $status = 200): Response
    {
        return new Response($this->html($page, $data), $status, [
            'Content-Type' => 'text/html; charset=utf-8',
        ]);
    }

    /** @param array<string,mixed> $data */
    public function html(string $page, array $data = []): string
    {
        [$themeKey, $previewActive] = $this->model->resolveTheme($data);
        $this->templates->use($this->themes->themeTemplateRoots($themeKey));

        $context = $this->model->viewModel($page, $data, $themeKey, $previewActive);
        $context['layout'] = $this->templates->layoutFor((string) $context['page']['type']);

        return $this->twig->render($this->templates->pageTemplate($page), $context);
    }
}
