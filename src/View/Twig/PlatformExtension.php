namespace CattoLearning\View\Twig;

use Twig\Extension\AbstractExtension;
use Twig\TwigFilter;

final class PlatformExtension extends AbstractExtension
{
    /** @return list<TwigFilter> */
    public function getFilters(): array
    {
        return [
            new TwigFilter('ucfirst', self::ucfirst(...)),
            new TwigFilter('urlencode', self::urlencode(...)),
        ];
    }

    /** Upper-cases the first character and leaves the rest of the string exactly as written. */
    public static function ucfirst(?string $value): string
    {
        return ucfirst((string) $value);
    }

    /** Percent-encodes a value for a query string, where a space is a plus sign. */
    public static function urlencode(?string $value): string
    {
        return urlencode((string) $value);
    }
}
