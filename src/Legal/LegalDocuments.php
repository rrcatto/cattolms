/*
Generated by: Claude Code CLI

Date time: 2026/10/13 SAST

Version: 0.9.1

Description:
The site's three public legal documents - Terms and Conditions, Refund Policy and Privacy Policy -
and the supplier they name. Core owns them: the text of each is a version-controlled template in
resources/views/pages/, and its version and last-updated date are here, where the pages print them
and where an order reads the versions its purchaser accepted.

Changing a document's text means raising its version and date here in the same change. An order's
immutable snapshot records the Terms version as terms_version and the Refund Policy version inside
consent, so the version is the only link between an order and the words that were accepted.

The supplier's email address and website are read from the instance configuration each time they
are asked for (APP_ADMIN_EMAIL, APP_DOMAIN); they are never written here.

Changelog:
2026/10/13 SAST
- Created for the public legal pages.
*/

declare(strict_types=1);

namespace CattoLearning\Legal;

use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Support\Env;
use DateTimeImmutable;
use InvalidArgumentException;

final class LegalDocuments
{
    public const TERMS = 'terms';
    public const REFUNDS = 'refunds';
    public const PRIVACY = 'privacy';

    /**
     * Each document's page template is its key. label is the footer wording.
     *
     * @var array<string,array{title:string,label:string,path:string,version:string,updated:string}>
     */
    private const DOCUMENTS = [
        self::TERMS => ['title' => 'Terms and Conditions', 'label' => 'Terms', 'path' => '/terms', 'version' => '1.0', 'updated' => '2026-10-13'],
        self::REFUNDS => ['title' => 'Refund Policy', 'label' => 'Refunds', 'path' => '/refunds', 'version' => '1.0', 'updated' => '2026-10-13'],
        self::PRIVACY => ['title' => 'Privacy Policy', 'label' => 'Privacy', 'path' => '/privacy', 'version' => '1.0', 'updated' => '2026-10-13'],
    ];

    /** The seller: a natural person trading in his own name, not a registered company. */
    private const SUPPLIER = [
        'legal_name' => 'Richard Catto',
        'legal_status' => 'Sole proprietor, trading in his own name. Not a registered company.',
        'trading_name' => 'Catto Learning',
        'physical_address' => 'Ujala Towers, 258 Main Road, Kirstenhof, 7945, South Africa',
        'phone' => '+27 81 495 1212',
        'information_officer' => 'Richard Catto',
    ];

    public function __construct(private readonly RuntimeSettings $settings)
    {
    }

    /** The version of a document as an order records it. */
    public static function version(string $key): string
    {
        return self::definition($key)['version'];
    }

    /**
     * One document as its page shows it.
     *
     * @return array{key:string,title:string,label:string,path:string,version:string,updated:string,updated_label:string}
     */
    public function document(string $key): array
    {
        $definition = self::definition($key);

        return ['key' => $key] + $definition + ['updated_label' => (new DateTimeImmutable($definition['updated']))->format('j F Y')];
    }

    /**
     * The three documents in the order the footer and each page list them.
     *
     * @return array<string,array{key:string,title:string,label:string,path:string,version:string,updated:string,updated_label:string}>
     */
    public function all(): array
    {
        $documents = [];
        foreach (array_keys(self::DOCUMENTS) as $key) {
            $documents[$key] = $this->document($key);
        }

        return $documents;
    }

    /**
     * The footer's entries for the documents, for ThemeRenderer's Core-owned footer list.
     *
     * @return list<array{key:string,label:string,href:string}>
     */
    public static function footerItems(): array
    {
        $items = [];
        foreach (self::DOCUMENTS as $key => $definition) {
            $items[] = ['key' => $key, 'label' => $definition['label'], 'href' => $definition['path']];
        }

        return $items;
    }

    /**
     * The supplier's details. The email address is the ADMIN address and the website is the site's
     * domain, both from the instance configuration as it is now.
     *
     * @return array{legal_name:string,legal_status:string,trading_name:string,physical_address:string,phone:string,phone_href:string,information_officer:string,email:string,website:string,website_url:string}
     */
    public function supplier(): array
    {
        $domain = $this->settings->platformDomain();

        return self::SUPPLIER + [
            'phone_href' => 'tel:' . str_replace(' ', '', self::SUPPLIER['phone']),
            'email' => strtolower(trim(Env::string('APP_ADMIN_EMAIL'))),
            'website' => $domain,
            'website_url' => 'https://' . $domain . '/',
        ];
    }

    /** @return array{title:string,label:string,path:string,version:string,updated:string} */
    private static function definition(string $key): array
    {
        return self::DOCUMENTS[$key] ?? throw new InvalidArgumentException('Unknown legal document: ' . $key);
    }
}
