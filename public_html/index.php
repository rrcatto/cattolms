/**
 * The entry lines of a .env file, as Dotenv's Lines::process() finds them.
 *
 * @return list<string>
 */
function catto_dotenv_entries(string $contents): array
{
    $stops = static function (string $line, bool $started): bool {
        if ($line === '"') {
            return true;
        }
        $count = preg_match_all('/(?=([^\\\\]"))/', str_replace('\\\\', '', $line));
        return $started ? $count > 1 : $count >= 1;
    };
    $entries = [];
    $multiline = false;
    $buffer = [];
    foreach (preg_split("/(\r\n|\n|\r)/", $contents) ?: [] as $line) {
        $starts = false;
        if (!$multiline) {
            $equals = strpos($line, '="');
            $hash = strpos($line, '#');
            $starts = $equals !== false && !($hash !== false && $hash < $equals) && !$stops($line, true);
        }
        if ($starts) {
            $multiline = true;
        }
        if ($multiline) {
            $buffer[] = $line;
            if ($stops($line, $starts)) {
                $multiline = false;
                $line = implode("\n", $buffer);
                $buffer = [];
            }
        }
        if (!$multiline) {
            $trimmed = trim($line, " \n\r\t\0\x0B");
            if ($trimmed !== '' && $trimmed[0] !== '#') {
                $entries[] = $line;
            }
        }
    }
    return $entries;
}

/**
 * One value, by Dotenv's EntryParser rules.
 *
 * @return array{0:?string,1:string}
 */
function catto_dotenv_value(string $value): array
{
    if ($value === '') {
        return ['', 'APP_CODEBASE_PATH is empty'];
    }
    if (preg_match('~\A(?|([^\s\\\\\'"#$]{1,1000})|\'([^\']*)\'|"([^"\\\\$]*)")\z~', $value, $literal) === 1) {
        return [$literal[1], ''];
    }
    // initial, unquoted, single, double, escape, whitespace, comment
    $state = 'initial';
    $out = '';
    $variables = [];
    $length = strlen($value);
    for ($i = 0; $i < $length; $i++) {
        $c = $value[$i];
        switch ($state) {
            case 'initial':
            case 'unquoted':
                if ($c === "'" && $state === 'initial') {
                    $state = 'single';
                } elseif ($c === '"' && $state === 'initial') {
                    $state = 'double';
                } elseif ($c === '#') {
                    $state = 'comment';
                } elseif ($state === 'unquoted' && ctype_space($c)) {
                    $state = 'whitespace';
                } else {
                    if ($c === '$') {
                        $variables[] = strlen($out);
                    }
                    $out .= $c;
                    $state = 'unquoted';
                }
                break;
            case 'single':
                if ($c === "'") {
                    $state = 'whitespace';
                } else {
                    $out .= $c;
                }
                break;
            case 'double':
                if ($c === '"') {
                    $state = 'whitespace';
                } elseif ($c === '\\') {
                    $state = 'escape';
                } else {
                    if ($c === '$') {
                        $variables[] = strlen($out);
                    }
                    $out .= $c;
                }
                break;
            case 'escape':
                $escapes = ['"' => '"', '\\' => '\\', '$' => '$', 'f' => "\f", 'n' => "\n", 'r' => "\r", 't' => "\t", 'v' => "\v"];
                if (!isset($escapes[$c])) {
                    return [null, 'APP_CODEBASE_PATH has an escape sequence Dotenv rejects'];
                }
                $out .= $escapes[$c];
                $state = 'double';
                break;
            case 'whitespace':
                if ($c === '#') {
                    $state = 'comment';
                } elseif (!ctype_space($c)) {
                    return [null, 'APP_CODEBASE_PATH has unexpected whitespace in its value, which Dotenv rejects'];
                }
                break;
            case 'comment':
                break 2;
        }
    }
    if (in_array($state, ['single', 'double', 'escape'], true)) {
        return [null, 'APP_CODEBASE_PATH is missing a closing quote'];
    }
    foreach ($variables as $position) {
        if (preg_match('/\A\$\{[a-zA-Z0-9_.]+\}/', substr($out, $position)) === 1) {
            return [null, 'APP_CODEBASE_PATH refers to another variable (${...}); give the path itself'];
        }
    }
    return [$out, $out === '' ? 'APP_CODEBASE_PATH is empty' : ''];
}

