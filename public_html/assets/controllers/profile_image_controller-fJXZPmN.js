/*
Generated by: Claude Code CLI
Date time: 2026/09/10 07:10 SAST
Version: 0.7
Description:
  Orient, size and position a profile image, and see the result, before it is stored.

  The server remains the authority. Without this controller the form posts the file and the server
  applies the EXIF orientation and takes a centred square - which is a correct answer, just not a
  chosen one. With it, the reader chooses: quarter-turn rotation, a zoom, and a drag to say which
  part of the picture the square holds. What is submitted is a PNG of exactly the stored size, and
  the server validates and re-encodes it like any other upload rather than trusting it.

  Orientation is read from the file by the browser. createImageBitmap with imageOrientation
  'from-image' applies the EXIF rotation for us; the <img> fallback is for browsers that do not
  offer it, where the same rotation is applied by the decoder before the element reports a size.

  The picture is drawn from its own centre outwards, so rotating never moves the subject off the
  crop - a rotation about the corner would swing it out of frame and the reader would have to drag
  it back every time.

Changelog:
  2026/09/10 07:10 SAST
  - Created so a profile image can be oriented, sized and previewed before it is stored.
*/
import { Controller } from '@hotwired/stimulus';

export default class extends Controller {
    static targets = ['file', 'editor', 'stage', 'preview', 'data', 'zoom', 'placeholder'];

    static values = {
        // The square the server stores. The stage is drawn larger for the sake of the person using
        // it, and the submitted canvas is rendered at exactly this size.
        size: { type: Number, default: 256 },
    };

    connect() {
        this.reset();
        // The editor is hidden until there is something to edit. Without JavaScript it is never
        // shown at all, and the plain file input beside it is the whole control.
        this.editorTarget.hidden = true;
        this.element.classList.add('is-enhanced');
        this.onPointerMove = this.onPointerMove.bind(this);
        this.onPointerUp = this.onPointerUp.bind(this);
    }

    disconnect() {
        window.removeEventListener('pointermove', this.onPointerMove);
        window.removeEventListener('pointerup', this.onPointerUp);
        // A form left carrying an edit from a controller that is no longer running would post a
        // result nobody can see. The file input still holds the file, so the server's own centred
        // crop takes over - which is the same page without JavaScript.
        this.dataTarget.value = '';
    }

    reset() {
        this.bitmap = null;
        this.rotation = 0;
        this.scale = 1;
        this.offsetX = 0;
        this.offsetY = 0;
        this.dragging = false;
    }

    /** A file was chosen. Decode it, fit it to the frame, and show the editor. */
    async choose() {
        const file = this.fileTarget.files && this.fileTarget.files[0];
        if (!file) {
            this.editorTarget.hidden = true;
            this.dataTarget.value = '';
            return;
        }

        this.reset();
        try {
            this.bitmap = await this.decode(file);
        } catch {
            // Nothing is reported here. The file goes to the server as it always did, and the
            // server says what is wrong with it in the one place those messages belong.
            this.editorTarget.hidden = true;
            this.dataTarget.value = '';
            return;
        }

        this.zoomTarget.value = '1';
        this.scale = 1;
        this.editorTarget.hidden = false;
        if (this.hasPlaceholderTarget) {
            this.placeholderTarget.hidden = true;
        }
        this.draw();
    }

    /** Quarter turn anticlockwise. */
    rotateLeft() {
        this.rotation = (this.rotation + 270) % 360;
        this.draw();
    }

    /** Quarter turn clockwise. */
    rotateRight() {
        this.rotation = (this.rotation + 90) % 360;
        this.draw();
    }

    zoom() {
        this.scale = Math.max(1, Math.min(4, Number(this.zoomTarget.value) || 1));
        this.clampOffset();
        this.draw();
    }

    recentre() {
        this.rotation = 0;
        this.scale = 1;
        this.offsetX = 0;
        this.offsetY = 0;
        this.zoomTarget.value = '1';
        this.draw();
    }

    onPointerDown(event) {
        if (!this.bitmap) return;
        this.dragging = true;
        this.dragFrom = { x: event.clientX, y: event.clientY, offsetX: this.offsetX, offsetY: this.offsetY };
        // Listened for on the window, not the canvas: a drag that leaves the canvas should keep
        // working until the button is released, which is what every other drag on the platform does.
        window.addEventListener('pointermove', this.onPointerMove);
        window.addEventListener('pointerup', this.onPointerUp);
        event.preventDefault();
    }

    onPointerMove(event) {
        if (!this.dragging) return;
        const stage = this.stageTarget.width;
        const ratio = stage / this.stageTarget.getBoundingClientRect().width;
        this.offsetX = this.dragFrom.offsetX + (event.clientX - this.dragFrom.x) * ratio;
        this.offsetY = this.dragFrom.offsetY + (event.clientY - this.dragFrom.y) * ratio;
        this.clampOffset();
        this.draw();
    }

    onPointerUp() {
        this.dragging = false;
        window.removeEventListener('pointermove', this.onPointerMove);
        window.removeEventListener('pointerup', this.onPointerUp);
    }

    /** Keep the frame inside the picture, so a corner can never be dragged into empty space. */
    clampOffset() {
        if (!this.bitmap) return;
        const stage = this.stageTarget.width;
        const [width, height] = this.drawnSize(stage);
        const slackX = Math.max(0, (width - stage) / 2);
        const slackY = Math.max(0, (height - stage) / 2);
        this.offsetX = Math.max(-slackX, Math.min(slackX, this.offsetX));
        this.offsetY = Math.max(-slackY, Math.min(slackY, this.offsetY));
    }

    /**
     * How large the picture is drawn to cover a square frame at the current zoom.
     *
     * Cover, not contain: the frame is always full. A picture fitted inside it would leave bars,
     * and a profile image with bars baked into it is a worse result than one that is cropped.
     */
    drawnSize(frame) {
        const turned = this.rotation === 90 || this.rotation === 270;
        const sourceWidth = turned ? this.bitmap.height : this.bitmap.width;
        const sourceHeight = turned ? this.bitmap.width : this.bitmap.height;
        const cover = Math.max(frame / sourceWidth, frame / sourceHeight) * this.scale;

        return [sourceWidth * cover, sourceHeight * cover];
    }

    /** Paint the stage and the preview from the same routine, so they cannot disagree. */
    draw() {
        if (!this.bitmap) return;
        this.paint(this.stageTarget);
        this.paint(this.previewTarget);
    }

    paint(canvas) {
        const frame = canvas.width;
        const context = canvas.getContext('2d');
        context.clearRect(0, 0, frame, frame);
        context.save();

        const ratio = frame / this.stageTarget.width;
        context.translate(frame / 2 + this.offsetX * ratio, frame / 2 + this.offsetY * ratio);
        context.rotate((this.rotation * Math.PI) / 180);

        const [width, height] = this.drawnSize(this.stageTarget.width);
        // Measured unrotated and drawn inside the rotated space, so the axes are the picture's own.
        const turned = this.rotation === 90 || this.rotation === 270;
        const drawWidth = (turned ? height : width) * ratio;
        const drawHeight = (turned ? width : height) * ratio;
        context.imageSmoothingQuality = 'high';
        context.drawImage(this.bitmap, -drawWidth / 2, -drawHeight / 2, drawWidth, drawHeight);
        context.restore();
    }

    /**
     * Render what the reader chose, at the size the server stores, into the hidden field.
     *
     * Bound to the form's submit rather than to a button, so it runs whichever control submits.
     */
    capture() {
        if (!this.bitmap) {
            this.dataTarget.value = '';
            return;
        }
        const canvas = document.createElement('canvas');
        canvas.width = this.sizeValue;
        canvas.height = this.sizeValue;
        this.paint(canvas);
        this.dataTarget.value = canvas.toDataURL('image/png');
    }

    /** The picture, already turned the way its EXIF says it should be. */
    async decode(file) {
        if (typeof createImageBitmap === 'function') {
            try {
                return await createImageBitmap(file, { imageOrientation: 'from-image' });
            } catch {
                // Older implementations reject the options argument rather than ignoring it.
            }
        }

        return await new Promise((resolve, reject) => {
            const url = URL.createObjectURL(file);
            const image = new Image();
            image.onload = () => {
                URL.revokeObjectURL(url);
                resolve(image);
            };
            image.onerror = () => {
                URL.revokeObjectURL(url);
                reject(new Error('The image could not be decoded.'));
            };
            image.src = url;
        });
    }
}
