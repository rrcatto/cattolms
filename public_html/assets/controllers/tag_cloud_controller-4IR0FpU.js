/*
Generated by: Claude Code CLI
Date time: 2026/09/10 00:15 SAST
Version: 0.7
Description:
  Animates the tag cloud on /courses/tags, over markup that already works without it.

  The server renders the tags as an ordinary list of links. This reads that list, hands the words to
  TagCloud.js and hides the original - so a reader with JavaScript off, or with this controller
  broken, still gets a usable page of links rather than an empty box. That is the platform rule for
  every surface and the trial does not get an exemption from it.

  Clicking a word navigates to the same href the plain link carries. The mapping is by index rather
  than by text, because TagCloud renders the string it was given and two tags may share a name.
Changelog:
  2026/09/10 00:15 SAST
  - Created for the Symfony UX trial.
*/
import { Controller } from '@hotwired/stimulus';
import TagCloud from 'TagCloud';

export default class extends Controller {
    static targets = ['source', 'canvas'];

    static values = {
        radius: { type: Number, default: 260 },
        // The sphere animates this many words at most. Every tag stays in the list beneath it;
        // what is bounded is the animation, because 378 words on one sphere overlap into a ball
        // nobody can read or click.
        limit: { type: Number, default: 80 },
    };

    connect() {
        // Nothing to animate, or the library did not load: leave the server's markup alone.
        const links = this.linkElements();
        if (links.length === 0 || typeof TagCloud !== 'function') {
            return;
        }

        const shown = links.slice(0, this.limitValue);
        this.hrefs = shown.map((link) => link.getAttribute('href'));
        const words = shown.map((link) => link.dataset.tagLabel || link.textContent.trim());

        // The radius is capped to the container so the sphere never overflows the page on a narrow
        // screen, which is the one way this control can make a page worse than the list it replaces.
        const available = Math.max(160, Math.min(this.radiusValue, this.canvasTarget.clientWidth / 2 - 20));

        this.cloud = TagCloud([this.canvasTarget], words, {
            radius: available,
            maxSpeed: 'normal',
            initSpeed: 'normal',
            keep: true,
            useContainerInlineStyles: false,
        });

        this.canvasTarget.addEventListener('click', this.onClick);
        // The list is kept when it holds more than the sphere shows, so nothing becomes
        // unreachable just because it did not fit on the ball.
        this.sourceTarget.hidden = links.length <= shown.length;
        this.element.classList.add('is-animated');
    }

    disconnect() {
        this.canvasTarget.removeEventListener('click', this.onClick);
        if (this.cloud && typeof this.cloud.destroy === 'function') {
            this.cloud.destroy();
        }
        // Put the list back. A controller that disconnects and leaves the page with neither its
        // enhancement nor its fallback has made the page worse than not running at all.
        this.sourceTarget.hidden = false;
        this.element.classList.remove('is-animated');
    }

    onClick = (event) => {
        const item = event.target.closest('.tagcloud--item');
        if (!item) {
            return;
        }
        const index = Array.from(this.canvasTarget.querySelectorAll('.tagcloud--item')).indexOf(item);
        const href = this.hrefs[index];
        if (href) {
            window.location.assign(href);
        }
    };

    linkElements() {
        return this.hasSourceTarget ? Array.from(this.sourceTarget.querySelectorAll('a[href]')) : [];
    }
}
