        RAISE EXCEPTION 'SEED roles cannot be combined with normal roles or ADMIN';
    ELSIF LEFT(v_new_role,5) <> 'SEED_' AND v_has_seed THEN
        RAISE EXCEPTION 'Normal roles or ADMIN cannot be combined with SEED roles';
