Adds trigram indexes for the live dataset search.

This is an ADDITIVE migration. It creates indexes and nothing else: no table is created, altered or
dropped, no data is touched, and no existing migration is rebased. It can be applied to a populated
database without a reset, and `down()` removes only what `up()` added.

Why trigram indexes rather than ordinary ones.

The search matches with `ILIKE '%term%'`. A B-tree index is ordered by prefix, so it can serve
`name LIKE 'acme%'` but is useless the moment a wildcard leads. Every existing index on these
columns - `courses_status_title_idx` among them - is a B-tree and cannot help. Without this
migration each keystroke-pause costs two sequential scans, one for the page of rows and one for the
count, on every searched table. At a few hundred rows nobody notices; at the 25,000 and 100,000-row
volumes this platform is meant to reach, on every list, for every operator typing, it is the
difference between a search that feels instant and one that does not finish.

`pg_trgm` splits each value into overlapping three-character sequences and indexes those, which
turns `%cme%` into an index lookup. GIN indexes cost write time and disk; every table indexed here
is read far more often than it is written, so that is the right trade.

The extension is created if absent. Richard confirmed on 2026/08/30 that `pg_trgm` is installed on
the target database, so this is a safety net for a fresh environment rather than the expected path -
`CREATE EXTENSION` needs privileges the application role may not hold, and if it fails the message
says exactly what a superuser has to run once.

Indexes are created without CONCURRENTLY because Phinx wraps a migration in a transaction and
PostgreSQL forbids the concurrent form inside one. On a populated table this takes a brief write
lock; run it during a quiet moment rather than under load.

