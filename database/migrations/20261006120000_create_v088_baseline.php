-- Tags are the other half of discovery and are universe-free for the same reason categories are.
-- Categories are for browsing and are hierarchical; tags are for searching, are flat, and a
-- course may carry many. That distinction is the whole reason both exist, so a tag must never
-- acquire a parent.
--
-- The slug is the canonical key and is what uniqueness is enforced on, so "Fire Safety",
-- "fire safety" and "Fire  Safety" cannot become three tags. Synonym and merge handling is
-- deliberately not modelled yet.
-- A tag is a name and nothing else. It had a description column that no screen could justify
-- asking for and that took a third of the tag table's width to display an em dash.
CREATE TABLE tags (
    id BIGSERIAL PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    slug VARCHAR(80) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    icon_svg TEXT NOT NULL DEFAULT ''
);
COMMENT ON COLUMN tags.icon_svg IS 'Generated chip icon.';
CREATE INDEX tags_name_idx ON tags(name);

