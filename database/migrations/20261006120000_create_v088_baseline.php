-- Course categories are a browsing taxonomy of at most three levels, and they carry no
-- A category is a label rather than a business record.
CREATE TABLE course_categories (
    id BIGSERIAL PRIMARY KEY,
    -- RESTRICT rather than CASCADE. Deleting a parent silently taking three levels of taxonomy
    -- and orphaning every course under it is not a delete anyone means to perform; the
    -- administrator must empty the branch first.
    parent_id BIGINT NULL REFERENCES course_categories(id) ON DELETE RESTRICT,
    -- The depth cap is the whole design. Unbounded nesting makes the descendant query unbounded
    -- and the breadcrumb dishonest, which is exactly what the three-level rule exists to prevent.
    level SMALLINT NOT NULL DEFAULT 1 CHECK (level BETWEEN 1 AND 3),
    name VARCHAR(120) NOT NULL UNIQUE,
    slug VARCHAR(120) NOT NULL UNIQUE,
    description TEXT NULL,
    -- The category's place among its siblings, 1..n within one parent: the order ADMIN arranged,
    -- never derived from names, ids or insertion time.
    position INTEGER NOT NULL CHECK (position > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    icon_svg TEXT NOT NULL DEFAULT '',
    -- A top level category has no parent; anything deeper must have one. Checked here because it
    -- needs no other row to decide it.
    CONSTRAINT course_categories_root_has_no_parent
        CHECK ((level = 1 AND parent_id IS NULL) OR (level > 1 AND parent_id IS NOT NULL)),
    -- Two siblings never share a place. NULLS NOT DISTINCT makes the top level one sibling group.
    -- Deferrable so a move can renumber a whole group inside its transaction; it is checked at
    -- once otherwise, so a stray insert is refused where it happens.
    CONSTRAINT course_categories_sibling_position
        UNIQUE NULLS NOT DISTINCT (parent_id, position) DEFERRABLE INITIALLY IMMEDIATE
);
COMMENT ON COLUMN course_categories.icon_svg IS 'The category''s icon: uploaded by ADMIN, or generated until one is.';
CREATE INDEX course_categories_position_idx ON course_categories(position, name);

-- A child sits exactly one level below its parent. This cannot be a CHECK constraint because it
-- reads another row, so it is a trigger - the same mechanism the cross-universe guards use, and
-- for the same reason: an invariant the application can regress is one the database should hold.
CREATE OR REPLACE FUNCTION enforce_category_depth() RETURNS TRIGGER AS $category_depth$
DECLARE
    parent_level SMALLINT;
BEGIN
    IF NEW.parent_id IS NULL THEN
        RETURN NEW;
    END IF;

    IF NEW.parent_id = NEW.id THEN
        RAISE EXCEPTION 'A course category cannot be its own parent.';
    END IF;

    SELECT level INTO parent_level FROM course_categories WHERE id = NEW.parent_id;
    IF parent_level IS NULL THEN
        RAISE EXCEPTION 'Parent course category % does not exist.', NEW.parent_id;
    END IF;

    IF NEW.level <> parent_level + 1 THEN
        RAISE EXCEPTION 'A course category at level % cannot sit under a parent at level %.',
            NEW.level, parent_level;
    END IF;

    RETURN NEW;
END;
$category_depth$ LANGUAGE plpgsql;

CREATE TRIGGER course_categories_depth
    BEFORE INSERT OR UPDATE ON course_categories
    FOR EACH ROW EXECUTE FUNCTION enforce_category_depth();

