CREATE SEQUENCE account_reference_numbers AS BIGINT START 1;
CREATE FUNCTION account_reference_check(body TEXT) RETURNS TEXT LANGUAGE plpgsql IMMUTABLE AS $fn$
DECLARE
    alphabet CONSTANT TEXT := '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ';
    product INTEGER := 36;
    total INTEGER;
    idx INTEGER;
BEGIN
    FOR idx IN 1..length(body) LOOP
        total := (product + strpos(alphabet, substr(body, idx, 1)) - 1) % 36;
        IF total = 0 THEN total := 36; END IF;
        product := (total * 2) % 37;
    END LOOP;
    RETURN substr(alphabet, ((37 - product) % 36) + 1, 1);
END;
$fn$;
CREATE FUNCTION next_account_reference(fallback_prefix TEXT) RETURNS TEXT LANGUAGE plpgsql AS $fn$
DECLARE
    chosen TEXT;
    today DATE := CURRENT_DATE;
    counter BIGINT;
    digits TEXT;
    body TEXT;
BEGIN
    SELECT option_value INTO chosen FROM app_options WHERE option_key = 'commerce.account_prefix';
    IF chosen IS NULL OR chosen !~ '^[A-Z]{1,3}$' THEN chosen := fallback_prefix; END IF;
    IF chosen IS NULL OR chosen !~ '^[A-Z]{1,3}$' THEN chosen := 'CL'; END IF;
    counter := nextval('account_reference_numbers');
    digits := counter::TEXT;
    -- lpad() would cut a longer number down to 4 digits.
    IF length(digits) < 4 THEN digits := lpad(digits, 4, '0'); END IF;
    body := chosen || to_char(today, 'YYYYMMDD') || digits;
    RETURN body || account_reference_check(body);
END;
$fn$;

CREATE TABLE users (
    id BIGSERIAL PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    account_reference VARCHAR(32) NOT NULL UNIQUE DEFAULT next_account_reference(NULL),
    display_name VARCHAR(160) NULL,
    first_name VARCHAR(120) NULL,
    -- Every name between the first name and the surname, however many there are. One column
    -- rather than middle_name and middle_name_2, because people do not have a fixed number of
    -- names and a schema that assumes two has already decided that five is impossible.
    middle_names VARCHAR(160) NOT NULL DEFAULT '',
    last_name VARCHAR(120) NULL,
    -- What People is ordered by, maintained by PostgreSQL. It replaced
    -- COALESCE(NULLIF(trim(concat_ws(' ',first_name,last_name)),''),display_name,ue.email), which
    -- no index could serve: concat_ws() is only STABLE so it cannot be indexed at all, and the
    -- email fallback lives on another table. NULL when a person has no name of any kind, so the
    -- nameless sort last rather than first. Middle names are deliberately excluded - a reader
    -- looking for Anna van Wyk expects to find her next to the other van Wyks.
    sort_name TEXT GENERATED ALWAYS AS (
        COALESCE(
            NULLIF(btrim(COALESCE(first_name,'') || ' ' || COALESCE(last_name,'')),''),
            NULLIF(btrim(COALESCE(display_name,'')),'')
        )
    ) STORED,
    -- The South African ID number (owner, 2026-10-27: "only people with a valid South African ID can register"):
    -- given at registration, or at the next sign-in of an account someone else made, checked by SouthAfricanIdNumber,
    -- kept encrypted (SecretCipher), with a keyed fingerprint so no two accounts hold the same number. NULL until given.
    id_number_encrypted TEXT NULL,
    id_number_hash CHAR(64) NULL UNIQUE CHECK (id_number_hash ~ '^[0-9a-f]{64}$'),
    -- The country the person says they live in, chosen at registration (it may differ from where they are).
    residence_country CHAR(2) NULL CHECK (residence_country ~ '^[A-Z]{2}$'),
    -- The date of birth (owner, 2026-10-20: adults only; 2026-10-27: taken from the ID number), 18 or older (AdultAge).
    -- NULL until the ID number is given.
    birthdate DATE NULL,
    gender VARCHAR(40) NULL,
    mobile_number VARCHAR(60) NULL,
    -- Declined identity checks before this moment no longer count towards the three tries: set when
    -- ADMIN allows another try.
    identity_attempts_reset_at TIMESTAMPTZ NULL,
    -- The drawn avatar shown when a person has uploaded no picture (owner, 2026-10-26: DiceBear's Lorelei, Sunset
    -- Fade preset) is drawn from public_id; "Show me another" saves a random seed here instead. NULL: the first one.
    avatar_seed CHAR(16) NULL CHECK (avatar_seed ~ '^[0-9a-f]{16}$'),
    status VARCHAR(24) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login_at TIMESTAMPTZ NULL
);

