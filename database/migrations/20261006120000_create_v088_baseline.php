-- A lot can never give more than it holds, nor take back more than it gave.
CREATE FUNCTION commerce_wallet_allocation_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE used BIGINT; held BIGINT;
BEGIN
    SELECT amount_minor INTO held FROM commerce_wallet_lots WHERE id = NEW.lot_id FOR UPDATE;
    SELECT COALESCE(SUM(amount_minor), 0) + NEW.amount_minor INTO used FROM commerce_wallet_allocations WHERE lot_id = NEW.lot_id;
    IF used < 0 OR used > held THEN RAISE EXCEPTION 'A wallet credit cannot give more than it holds'; END IF;
    RETURN NEW;
END;
$fn$;
CREATE TRIGGER commerce_wallet_allocation_bounds BEFORE INSERT ON commerce_wallet_allocations FOR EACH ROW EXECUTE FUNCTION commerce_wallet_allocation_guard();
