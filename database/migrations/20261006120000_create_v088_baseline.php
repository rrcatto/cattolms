CREATE FUNCTION course_structure_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE
    parent_course BIGINT;
    parent_depth INTEGER;
BEGIN
    IF NEW.parent_node_id IS NULL THEN
        RETURN NEW;
    END IF;
    WITH RECURSIVE ancestry AS (
        SELECT id, course_id, parent_node_id, 1 AS depth FROM course_structure_nodes WHERE id = NEW.parent_node_id
        UNION ALL
        SELECT n.id, n.course_id, n.parent_node_id, a.depth + 1
        FROM course_structure_nodes n JOIN ancestry a ON n.id = a.parent_node_id
    )
    SELECT MAX(course_id), MAX(depth) INTO parent_course, parent_depth FROM ancestry;
    IF parent_course IS NULL OR parent_course <> NEW.course_id THEN
        RAISE EXCEPTION 'Course structure parent must belong to the same course';
    END IF;
    IF parent_depth >= 3 THEN
        RAISE EXCEPTION 'Course structure may nest to a maximum of three levels';
    END IF;
    RETURN NEW;
END;
$fn$;
CREATE TRIGGER course_structure_guard_trigger BEFORE INSERT OR UPDATE OF course_id,parent_node_id,node_type ON course_structure_nodes FOR EACH ROW EXECUTE FUNCTION course_structure_guard();

CREATE FUNCTION course_structure_detail_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE
    actual_course BIGINT;
    actual_type VARCHAR(16);
    item_type VARCHAR(32);
BEGIN
    SELECT course_id, node_type INTO actual_course, actual_type FROM course_structure_nodes WHERE id = NEW.node_id;
    IF TG_TABLE_NAME = 'course_sections' THEN
        IF actual_type <> 'section' THEN
            RAISE EXCEPTION 'A course section must use a section structure node';
        END IF;
        RETURN NEW;
    END IF;
    IF actual_type <> 'item' OR actual_course <> NEW.course_id THEN
        RAISE EXCEPTION 'A Course Item placement must use an item node in the same course';
    END IF;
    SELECT ci.item_type INTO item_type FROM course_items ci WHERE ci.id = NEW.course_item_id;
    IF NEW.assessment_role IN ('graded','final') AND item_type <> 'assessment' THEN
        RAISE EXCEPTION 'Only Assessment Course Items may use graded or final placement roles';
    END IF;
    RETURN NEW;
END;
