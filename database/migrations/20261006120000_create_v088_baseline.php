CREATE FUNCTION commerce_refund_request_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
    IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'Refund requests cannot be deleted'; END IF;
    IF OLD.status <> 'requested' THEN RAISE EXCEPTION 'A decided refund request cannot change'; END IF;
    IF (to_jsonb(NEW) - 'status' - 'decided_by_user_id' - 'decided_at' - 'decision_note')
        IS DISTINCT FROM (to_jsonb(OLD) - 'status' - 'decided_by_user_id' - 'decided_at' - 'decision_note') THEN
        RAISE EXCEPTION 'A refund request records only its decision';
    END IF;
    RETURN NEW;
END;
$fn$;
