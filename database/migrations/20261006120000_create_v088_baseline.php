-- Purchased credit lots. A lot that came from a paid company order line keeps that line's terms
-- for ever; refunds reduce only its unused units, and refunded units cannot be allocated.
CREATE FUNCTION commerce_protect_purchased_credit_lot() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
    IF OLD.commerce_order_item_id IS NOT NULL AND (
        TG_OP='DELETE' OR NEW.company_id IS DISTINCT FROM OLD.company_id
        OR NEW.course_id IS DISTINCT FROM OLD.course_id
        OR NEW.access_period_seconds IS DISTINCT FROM OLD.access_period_seconds
        OR NEW.quantity IS DISTINCT FROM OLD.quantity
        OR NEW.commerce_order_item_id IS DISTINCT FROM OLD.commerce_order_item_id
        OR NEW.source_type IS DISTINCT FROM OLD.source_type
    ) THEN
        RAISE EXCEPTION 'Purchased credit lot terms cannot be changed';
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$fn$;
CREATE TRIGGER commerce_purchased_credit_lot_immutable BEFORE UPDATE OR DELETE ON course_credits FOR EACH ROW EXECUTE FUNCTION commerce_protect_purchased_credit_lot();

CREATE FUNCTION commerce_validate_purchased_credit() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE purchased RECORD;
BEGIN
    IF NEW.source_type <> 'purchase' THEN RETURN NEW; END IF;
    SELECT i.product_type,i.company_id,i.course_id,i.access_period_seconds,i.quantity,o.state
      INTO purchased FROM commerce_order_items i JOIN commerce_orders o ON o.id=i.order_id
     WHERE i.id=NEW.commerce_order_item_id;
    IF NOT FOUND OR purchased.product_type <> 'company_credit' OR purchased.state NOT IN ('paid','fulfilled')
        OR purchased.company_id IS DISTINCT FROM NEW.company_id
        OR purchased.course_id IS DISTINCT FROM NEW.course_id
        OR purchased.access_period_seconds IS DISTINCT FROM NEW.access_period_seconds
        OR purchased.quantity IS DISTINCT FROM NEW.quantity THEN
        RAISE EXCEPTION 'A purchased credit requires a matching fully paid company order item';
    END IF;
    RETURN NEW;
END;
$fn$;
CREATE TRIGGER commerce_purchased_credit_settlement_guard BEFORE INSERT ON course_credits
FOR EACH ROW EXECUTE FUNCTION commerce_validate_purchased_credit();

CREATE FUNCTION commerce_guard_credit_refund_projection() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW.refunded_quantity IS DISTINCT FROM OLD.refunded_quantity THEN
        IF OLD.commerce_order_item_id IS NULL THEN RAISE EXCEPTION 'Only purchased credit lots can be refunded'; END IF;
        IF NEW.refunded_quantity < OLD.refunded_quantity THEN RAISE EXCEPTION 'Credit refunds cannot be reversed by editing a lot'; END IF;
        IF NEW.refunded_quantity + (SELECT COUNT(*) FROM course_credit_allocations a WHERE a.credit_id=OLD.id AND a.status IN ('assigned','consumed')) > OLD.quantity THEN
            RAISE EXCEPTION 'Allocated credit units cannot be refunded';
        END IF;
    END IF;
    RETURN NEW;
END;
$fn$;
CREATE TRIGGER commerce_credit_refund_projection_guard BEFORE UPDATE ON course_credits FOR EACH ROW EXECUTE FUNCTION commerce_guard_credit_refund_projection();

CREATE FUNCTION commerce_guard_refunded_credit_allocation() RETURNS trigger LANGUAGE plpgsql AS $fn$
DECLARE lot RECORD;
DECLARE used_units BIGINT;
BEGIN
    IF NEW.status NOT IN ('assigned','consumed') THEN RETURN NEW; END IF;
    SELECT quantity,refunded_quantity INTO lot FROM course_credits WHERE id=NEW.credit_id FOR UPDATE;
    SELECT COUNT(*) INTO used_units FROM course_credit_allocations
     WHERE credit_id=NEW.credit_id AND status IN ('assigned','consumed')
       AND (TG_OP='INSERT' OR id<>NEW.id);
    IF used_units >= lot.quantity-lot.refunded_quantity THEN
        RAISE EXCEPTION 'No unrefunded credit units remain for allocation';
    END IF;
    RETURN NEW;
END;
$fn$;
CREATE TRIGGER commerce_refunded_credit_allocation_guard BEFORE INSERT OR UPDATE OF credit_id,status ON course_credit_allocations
FOR EACH ROW EXECUTE FUNCTION commerce_guard_refunded_credit_allocation();

