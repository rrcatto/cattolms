-- An order is placed either from an individual's cart or as a company credit purchase, never
-- both. total_minor is the subtotal less discount_minor; only a promotion can bring it to zero,
-- and promotions apply to individual orders only.
CREATE TABLE commerce_orders (
    id BIGSERIAL PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    purchaser_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    cart_id BIGINT NULL UNIQUE REFERENCES commerce_carts(id) ON DELETE RESTRICT,
    state TEXT NOT NULL CHECK (state IN ('placed','awaiting_payment','manual_review','paid','fulfilled','cancelled','partially_refunded','refunded')),
    total_minor BIGINT NOT NULL,
    currency CHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    snapshot JSONB NOT NULL,
    placed_at TIMESTAMPTZ NOT NULL,
    payment_due_at TIMESTAMPTZ NOT NULL,
    company_id BIGINT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    request_id BIGINT NULL REFERENCES course_requests(id) ON DELETE RESTRICT,
    company_purchase_key UUID NULL UNIQUE,
    promotion_id BIGINT NULL REFERENCES promotions(id) ON DELETE RESTRICT,
    discount_minor BIGINT NOT NULL DEFAULT 0 CHECK (discount_minor >= 0),
    CHECK (payment_due_at > placed_at),
    CONSTRAINT commerce_order_purchase_channel CHECK (
        (cart_id IS NOT NULL AND company_id IS NULL AND request_id IS NULL AND company_purchase_key IS NULL)
        OR (cart_id IS NULL AND company_id IS NOT NULL AND company_purchase_key IS NOT NULL)
    ),
    CONSTRAINT commerce_orders_promotion_discount CHECK ((promotion_id IS NULL) = (discount_minor = 0)),
    CONSTRAINT commerce_orders_promotion_channel CHECK (promotion_id IS NULL OR cart_id IS NOT NULL),
    CONSTRAINT commerce_orders_total_minor_check CHECK (total_minor > 0 OR (total_minor = 0 AND promotion_id IS NOT NULL))
);
CREATE INDEX commerce_order_purchaser ON commerce_orders(purchaser_user_id,id DESC);
CREATE INDEX commerce_order_due ON commerce_orders(payment_due_at) WHERE state='awaiting_payment';
CREATE INDEX commerce_orders_company_idx ON commerce_orders(company_id,id DESC) WHERE company_id IS NOT NULL;
CREATE INDEX commerce_orders_request_idx ON commerce_orders(request_id,state) WHERE request_id IS NOT NULL;
CREATE UNIQUE INDEX commerce_one_active_company_order_per_request ON commerce_orders(request_id)
WHERE request_id IS NOT NULL AND state IN ('placed','awaiting_payment','manual_review','paid','fulfilled');
CREATE INDEX commerce_orders_promotion_idx ON commerce_orders (promotion_id, purchaser_user_id) WHERE promotion_id IS NOT NULL;

-- An order line is one of three products: individual access to a course (one learner), company
-- credits for a course variant (a quantity), or a bundle (one learner). amount_minor is the
-- line's price; discount_minor is its share of the order's promotion, and what the line was paid
-- is amount_minor - discount_minor, which bounds its refunds.
CREATE TABLE commerce_order_items (
    id BIGSERIAL PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES commerce_orders(id) ON DELETE RESTRICT,
    variant_id BIGINT NULL REFERENCES course_price_variants(id) ON DELETE RESTRICT,
    course_id BIGINT NULL REFERENCES courses(id) ON DELETE RESTRICT,
    beneficiary_user_id BIGINT NULL REFERENCES users(id) ON DELETE RESTRICT,
    amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
    access_period_seconds INTEGER NOT NULL CHECK (access_period_seconds > 0),
    snapshot JSONB NOT NULL,
    company_id BIGINT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    product_type TEXT NOT NULL DEFAULT 'individual_access' CHECK (product_type IN ('individual_access','company_credit','bundle')),
    discount_minor BIGINT NOT NULL DEFAULT 0,
    bundle_id BIGINT NULL REFERENCES bundles(id) ON DELETE RESTRICT,
    bundle_offer_id BIGINT NULL REFERENCES bundle_offers(id) ON DELETE RESTRICT,
    CONSTRAINT commerce_order_item_beneficiary CHECK (
        (product_type = 'individual_access' AND beneficiary_user_id IS NOT NULL AND company_id IS NULL AND quantity = 1
            AND variant_id IS NOT NULL AND course_id IS NOT NULL AND bundle_id IS NULL AND bundle_offer_id IS NULL)
        OR (product_type = 'company_credit' AND beneficiary_user_id IS NULL AND company_id IS NOT NULL
            AND variant_id IS NOT NULL AND course_id IS NOT NULL AND bundle_id IS NULL AND bundle_offer_id IS NULL)
        OR (product_type = 'bundle' AND beneficiary_user_id IS NOT NULL AND company_id IS NULL AND quantity = 1
            AND variant_id IS NULL AND course_id IS NULL AND bundle_id IS NOT NULL AND bundle_offer_id IS NOT NULL)),
    CONSTRAINT commerce_order_items_discount CHECK (discount_minor >= 0 AND discount_minor <= amount_minor)
);
CREATE UNIQUE INDEX commerce_order_individual_course_idx ON commerce_order_items(order_id,course_id) WHERE product_type='individual_access';
CREATE UNIQUE INDEX commerce_order_company_variant_idx ON commerce_order_items(order_id,variant_id) WHERE product_type='company_credit';
CREATE UNIQUE INDEX commerce_order_bundle_idx ON commerce_order_items (order_id, bundle_id) WHERE product_type = 'bundle';
CREATE INDEX commerce_order_items_company_idx ON commerce_order_items(company_id,order_id) WHERE company_id IS NOT NULL;
CREATE INDEX commerce_order_items_bundle_idx ON commerce_order_items (bundle_id, order_id) WHERE bundle_id IS NOT NULL;

