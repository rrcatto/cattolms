    public function testControllersDoNotSwitchPermissionsByDataUniverseOrOrdinaryBusinessRole(): void
    {
        $base = (string) file_get_contents(dirname(__DIR__, 2) . '/src/Http/Controller/BaseController.php');
        self::assertStringNotContainsString('function requireRole(', $base);
        self::assertStringNotContainsString('requireBusinessPermission(', $base);
        self::assertStringNotContainsString('businessPermission(', $base);

        $root = dirname(__DIR__, 2) . '/src/Http/Controller';
        $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if (!$file->isFile() || $file->getExtension() !== 'php') {
                continue;
            }
            $source = (string) file_get_contents($file->getPathname());
            self::assertStringNotContainsString("hasRole('ADMIN')", $source, $file->getPathname() . ' must not determine business resource scope from the ADMIN role name.');
            self::assertStringNotContainsString('requireBusinessPermission(', $source, $file->getPathname());
            self::assertStringNotContainsString("'REAL.", $source, $file->getPathname());
            self::assertStringNotContainsString("'SEED.", $source, $file->getPathname());
            foreach ([
                'hasRole(RoleCatalog::COMPANY_ADMIN',
                'hasRole(RoleCatalog::SEED_COMPANY_ADMIN',
                'hasRole(RoleCatalog::COURSE_OWNER',
                'hasRole(RoleCatalog::SEED_COURSE_OWNER',
                'hasRole(RoleCatalog::COURSE_EDITOR',
                'hasRole(RoleCatalog::SEED_COURSE_EDITOR',
            ] as $needle) {
                if ($file->getFilename() !== 'BaseController.php') {
                    self::assertStringNotContainsString($needle, $source, $file->getPathname() . ' must not determine business resource scope from role names.');
                }
            }
        }
    }

    private function methodSource(string $class, string $method): string
    {
        $reflection = new ReflectionMethod($class, $method);
        $lines = file((string) $reflection->getFileName());
