    public function testLiveControllersDoNotUseHardCodedRequireRoleGuards(): void
    {
        $base = (string) file_get_contents(dirname(__DIR__, 2) . '/src/Http/Controller/BaseController.php');
        self::assertStringNotContainsString('function requireRole(', $base, 'The obsolete role-guard helper must not remain after ACL migration.');

        $root = dirname(__DIR__, 2) . '/src/Http/Controller';
        $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if (!$file->isFile() || $file->getExtension() !== 'php' || $file->getFilename() === 'BaseController.php') continue;
            $source = (string) file_get_contents($file->getPathname());
            self::assertStringNotContainsString('requireRole(', $source, $file->getPathname() . ' must use ACL permission guards.');
        }
    }

    private function methodSource(string $class, string $method): string
    {
        $reflection = new ReflectionMethod($class, $method);
        $lines = file((string) $reflection->getFileName());
        self::assertIsArray($lines);
        return implode('', array_slice($lines, $reflection->getStartLine() - 1, $reflection->getEndLine() - $reflection->getStartLine() + 1));
    }
