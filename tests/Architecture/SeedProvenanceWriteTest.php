/*
Generated by: Claude Code CLI

Date time: 2026/08/23 04:19 SAST

Version: 0.5.8

Description:
Enforces that ordinary application writes carry seed provenance.

A generated seed set is only useful if a SEED identity can then use the LMS normally, and that
requires every business row created during a SEED workflow to carry the right `seed_token` before
it reaches the cross-universe trigger. Miss one writer and that workflow simply fails for seed
identities - usually with a trigger error naming a column rather than the feature that broke.

What this test can and cannot do: it proves every INSERT *names* the column and every writing
repository *can* resolve provenance. It cannot prove the runtime value is right, because that
needs a database. SeedProvenanceIntegrationTest does that half.

Changelog:
2026/08/23 04:19 SAST
- Tightened the write heuristic: constructing a mapper to count rows is not a write, so provenance is only required where the class also persists.
- Created to finish seed provenance on ordinary writes.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Architecture;

use CattoLearning\Seed\SeedTableCatalog;
use PHPUnit\Framework\TestCase;

final class SeedProvenanceWriteTest extends TestCase
{
    private static function root(): string
    {
        return dirname(__DIR__, 2);
    }

    /** @return list<string> every PHP file under src/, excluding the Seed module itself */
    private static function applicationSources(): array
    {
        $files = [];
        $directory = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator(self::root() . '/src'));
        foreach ($directory as $file) {
            if ($file->isDir() || $file->getExtension() !== 'php') {
                continue;
            }
            $path = strtr($file->getPathname(), '\\', '/');
            // The generator and its repository set the token explicitly on every row and are
            // covered by their own contract tests.
            if (str_contains($path, '/src/Seed/') || str_contains($path, 'SeedRepository.php')) {
                continue;
            }
            $files[] = $path;
        }
        sort($files);

        return $files;
    }

    /**
     * Every literal INSERT into a seed-aware table names `seed_token`.
     *
     * This is the precise half of the rule: an INSERT that does not list the column writes NULL,
     * which silently makes a SEED workflow's row REAL and then fails at the trigger one step
     * later, somewhere less obvious.
     */
    public function testEveryInsertIntoASeedAwareTableSetsTheToken(): void
    {
        $offenders = [];

        foreach (self::applicationSources() as $file) {
            $source = (string) file_get_contents($file);

            foreach (SeedTableCatalog::seedAwareTables() as $table) {
                $pattern = '/INSERT INTO\s+' . $table . '\s*\((.*?)\)/is';
                if (preg_match_all($pattern, $source, $matches) === 0) {
                    continue;
                }
                foreach ($matches[1] as $columns) {
                    if (!str_contains($columns, 'seed_token')) {
                        $offenders[] = basename($file) . ' -> INSERT INTO ' . $table;
                    }
                }
            }
        }

        self::assertSame(
            [],
            array_values(array_unique($offenders)),
            "These inserts would write a NULL token into a seed-aware table:\n  "
            . implode("\n  ", array_unique($offenders))
        );
    }

    /**
     * Every repository that writes a seed-aware table can resolve provenance.
     *
     * Mapper-based writes assign the column as a property rather than naming it in SQL, so they
     * cannot be checked as precisely as the inserts above. What is checkable, and what actually
     * prevents the mistake, is that such a class holds a SeedProvenance and uses it: a class with
     * no way to resolve a token cannot have set one.
     */
    public function testEveryRepositoryWritingSeedAwareTablesResolvesProvenance(): void
    {
        $mappers = self::seedAwareMapperClasses();
        $offenders = [];

        foreach (self::applicationSources() as $file) {
            $source = (string) file_get_contents($file);

            // Constructing a mapper is not itself a write: MaintenanceRepository builds one to
            // count expired rows and never saves. Only a class that also persists can be missing
            // provenance, so ->save() is what makes this a write.
            $persists = str_contains($source, '->save()');

            $writes = false;
            foreach ($mappers as $class) {
                if ($persists && str_contains($source, 'new ' . $class . '(')) {
                    $writes = true;
                    break;
                }
            }
            foreach (SeedTableCatalog::seedAwareTables() as $table) {
                if (preg_match('/INSERT INTO\s+' . $table . '\s*\(/i', $source) === 1) {
                    $writes = true;
                    break;
                }
            }

            if ($writes && !str_contains($source, 'SeedProvenance') && !str_contains($source, 'seed_token')) {
                $offenders[] = basename($file);
            }
        }

        self::assertSame(
            [],
            array_values(array_unique($offenders)),
            "These classes write a seed-aware table but cannot resolve provenance:\n  "
            . implode("\n  ", array_unique($offenders))
        );
    }

    /**
     * Provenance is never taken from the acting identity.
     *
     * A genuine ADMIN is a REAL identity. Using the actor's own token when it operates on SEED
     * data would write a REAL row into a SEED aggregate, and the trigger would reject it. The
     * token always comes from the resource, which is why no repository reads CurrentUser at all.
     */
    public function testProvenanceIsNeverTakenFromTheActor(): void
    {
        $offenders = [];

        foreach (self::applicationSources() as $file) {
            if (!str_contains($file, '/Persistence/') && !str_contains($file, 'Repository.php')) {
                continue;
            }
            $source = (string) file_get_contents($file);
            if (preg_match('/seed_token\s*=\s*\$\w*[Uu]ser->seedToken/', $source) === 1) {
                $offenders[] = basename($file);
            }
        }

        self::assertSame([], $offenders, 'A repository must derive provenance from the resource, not the actor.');
    }

    /** The pair helper exists and is used where a row genuinely has two parents. */
    public function testTwoParentRowsUseThePairHelper(): void
    {
        $checked = [
            'src/Course/CourseRepository.php' => "forPair('users'",
            'src/Infrastructure/Persistence/CompanyRepository.php' => "forPair('companies'",
            'src/Infrastructure/Persistence/AdministrationRepository.php' => "forPair(",
            'src/Course/CoursePortabilityRepository.php' => "forPair('users'",
        ];

        foreach ($checked as $relative => $needle) {
            self::assertStringContainsString(
                $needle,
                (string) file_get_contents(self::root() . '/' . $relative),
                $relative . ' joins two resources and must refuse a cross-universe pairing by name.'
            );
        }
    }

    /** @return list<string> mapper class names whose table is seed-aware */
    private static function seedAwareMapperClasses(): array
    {
        $classes = [];
        foreach (glob(self::root() . '/src/Infrastructure/Persistence/M/*.php') ?: [] as $file) {
            $source = (string) file_get_contents($file);
            if (preg_match("/return '(\w+)';/", $source, $match) !== 1) {
                continue;
            }
            if (SeedTableCatalog::isSeedAware($match[1])) {
                $classes[] = basename($file, '.php');
            }
        }

        return $classes;
    }
}
