    /**
     * The row ids routes open to someone signed out carry.
     *
     * @return array<string,string>
     */
    public function publicRowIds(): array
    {
        return array_filter($this->rowIds(), static function (string $key): bool {
            $path = explode(' ', $key)[1];
            foreach (self::SIGNED_IN as $prefix) if (str_starts_with($path, $prefix)) return false;
            return true;
        }, ARRAY_FILTER_USE_KEY);
    }

    /**
     * Every row id a route carries, as "METHODS path parameter" => where it is declared.
     *
     * @return array<string,string>
     */
    public function rowIds(): array
    {
        $found = [];
        foreach ($this->routes() as [$method, $route]) {
            $path = (string) $route->path;
            $methods = $route->methods === [] ? 'ANY' : implode(',', $route->methods);
            preg_match_all('/\{([a-zA-Z_][a-zA-Z0-9_]*)\}/', $path, $parameters);
            foreach ($parameters[1] as $name) {
                $key = $methods . ' ' . $path . ' ' . $name;
                if (array_key_exists($key, self::NOT_ROW_IDS) || array_key_exists($name, self::NOT_ROW_IDS)) continue;
                $requirement = (string) ($route->requirements[$name] ?? '');
                if (in_array($name, self::ID_NAMES, true) || str_ends_with($name, '_id') || self::onlyDigits($requirement)) {
                    $found[$key] = $method->getDeclaringClass()->getShortName() . '::' . $method->getName();
                }
            }
        }
        ksort($found);
        return $found;
    }

    /** Whether a route requirement accepts digits and nothing else: \d+, [0-9]+, [1-9][0-9]*, \d{1,9}. */
    private static function onlyDigits(string $requirement): bool
    {
        if ($requirement === '') return false;
        $left = (string) preg_replace(['/\\\\d/', '/\[(?:[0-9]-[0-9])+\]/', '/\{\d+(?:,\d*)?\}/', '/[+*?()|]/', '/[0-9]/'], '', $requirement);
        return $left === '';
    }

    /** @return list<array{0:ReflectionMethod,1:Route}> */
    private function routes(): array
    {
        $routes = [];
        $root = dirname(__DIR__, 2) . '/src/';
        foreach (['Http/Controller' => 'CattoLearning\\Http\\Controller\\', 'Http/Symfony' => 'CattoLearning\\Http\\Symfony\\', 'Commerce/Http' => 'CattoLearning\\Commerce\\Http\\'] as $folder => $namespace) {
            foreach (glob($root . $folder . '/*.php') ?: [] as $file) {
                $class = $namespace . basename($file, '.php');
                if (!class_exists($class)) continue;
                foreach ((new ReflectionClass($class))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
                    foreach ($method->getAttributes(Route::class) as $attribute) {
                        $routes[] = [$method, $attribute->newInstance()];
                    }
                }
            }
        }
        return $routes;
    }
