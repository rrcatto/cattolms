    /** No route carries a course's row id, anywhere: a course is its code. */
    public function testNoRouteCarriesACourseRowId(): void
    {
        $course = [];
        foreach (array_keys($this->rowIds()) as $key) {
            [, $path, $name] = explode(' ', $key);
            if (in_array($name, ['course', 'course_id'], true)
                || ($name === 'id' && preg_match('#^/(admin/courses|admin/reports/popularity|company/favourites|api/v1/admin/courses)/\{id\}#', $path) === 1)) {
                $course[] = $key;
            }
        }
        self::assertSame([], $course, "These routes name a course by its row id (owner, 2026-11-06: \"All courses must be referred to by their course code in urls\"):\n" . implode("\n", $course));
    }

    /** Every route that names a course names it by its code, held to CourseAddress::REQUIREMENT. */
    public function testEveryCourseRouteNamesTheCourseByItsCode(): void
    {
        $checked = 0;
        foreach ($this->routes() as [$method, $route]) {
            $path = (string) $route->path;
            $parameter = match (true) {
                preg_match('#^/(admin/courses|api/v1/admin/courses|admin/reports/popularity|company/favourites)/\{([a-z_]+)\}#', $path, $first) === 1 => $first[2],
                preg_match('#^/admin/bundles/\{[^}]+\}/courses/\{([a-z_]+)\}#', $path, $second) === 1 => $second[1],
                default => null,
            };
            if ($parameter === null) continue;
            $where = $method->getDeclaringClass()->getShortName() . '::' . $method->getName() . ' (' . $path . ')';
            self::assertContains($parameter, ['code', 'course_code'], $where . ' names its course by something other than its code.');
            self::assertSame(CourseAddress::REQUIREMENT, (string) ($route->requirements[$parameter] ?? ''), $where . ' does not hold its course code to CourseAddress::REQUIREMENT.');
            $checked++;
        }
        self::assertGreaterThanOrEqual(64, $checked, 'Fewer course routes were found than the course pages have.');
    }

    /** Every record with a code is named by it, held to its requirement (stage 2, 2026-11-07). */
    public function testEveryRecordWithACodeIsNamedByIt(): void
    {
        $checked = [];
        foreach ($this->routes() as [$method, $route]) {
            $path = (string) $route->path;
            foreach (self::RECORDS as $pattern => [$parameter, $requirement, $record]) {
                if (preg_match($pattern, $path, $found) !== 1) continue;
                $where = $method->getDeclaringClass()->getShortName() . '::' . $method->getName() . ' (' . $path . ')';
                self::assertSame($parameter, $found[1], $where . ' names ' . $record . ' by something other than {' . $parameter . '}.');
                self::assertSame($requirement, (string) ($route->requirements[$parameter] ?? ''), $where . ' does not hold ' . $record . ' to its requirement.');
                $checked[$record] = ($checked[$record] ?? 0) + 1;
            }
        }
        self::assertCount(count(array_unique(array_column(self::RECORDS, 2))), $checked, 'A record in RECORDS has no route left: ' . implode(', ', array_diff(array_unique(array_column(self::RECORDS, 2)), array_keys($checked))));
    }

    /** Every number left in a route is a record that keeps it, listed with why (owner, 2026-11-06). */
