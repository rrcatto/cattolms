declare(strict_types=1);

namespace CattoLearning\Tests\Architecture;

use CattoLearning\Auth\DataUniverse;
use CattoLearning\Course\CourseRepository;
use CattoLearning\Infrastructure\Persistence\AdministrationRepository;
use CattoLearning\Infrastructure\Persistence\EntityLookupRepository;
use PHPUnit\Framework\TestCase;
use ReflectionClass;
use ReflectionMethod;

final class DataUniverseScopeTest extends TestCase
{
    /** Repositories whose reads are business data and therefore universe-bound. */
    private const GUARDED_REPOSITORIES = [
        AdministrationRepository::class,
        CourseRepository::class,
        EntityLookupRepository::class,
    ];

    /**
     * Public read methods that legitimately need no universe, with the reason.
     *
     * Every entry is a deliberate exemption, not an oversight. Adding one is a decision about
     * the universe boundary and should be argued for in review.
     *
     * @var array<string,string>
     */
    private const EXEMPT = [
        'isSupportedType' => 'Pure input validation; touches no data.',
        'categories' => 'Course categories are looked up by the caller that already scoped the course.',
        'categoryById' => 'Resolved by id from an already-scoped course context.',
        'activityFamilies' => 'Takes a universe; listed here only because its name reads like a lookup.',
        'priceVariantCount' => 'Keyed by a course id the caller has already resolved inside one universe; '
            . 'course_price_variants rows are same-universe guarded by the database, so this cannot span both.',
    ];

    /**
     * A method is universe-bound when it reads business rows or counts them.
     *
     * Matching on name rather than body keeps the rule cheap and predictable: a new
     * `somethingCount()` is caught the moment it is written, before it has any callers.
     */
    private static function readsBusinessData(ReflectionMethod $method): bool
    {
        $name = $method->getName();

        if (array_key_exists($name, self::EXEMPT)) {
            return false;
        }
        if (str_ends_with($name, 'Count')) {
            return true;
        }

        return in_array($name, [
            'people', 'companies', 'enrolments', 'requests', 'creditLedger', 'activity',
            'companyPeople', 'companyRequests', 'companyEnrolments', 'companyCredits',
            'overview', 'reportSummary', 'courseReport', 'companyReport',
            'publishedCourses', 'allCourses', 'manageableCourses', 'featuredPublishedCourses',
            'findBySlug', 'search', 'describe',
        ], true);
    }

    private static function hasUniverseParameter(ReflectionMethod $method): bool
    {
        foreach ($method->getParameters() as $parameter) {
            $type = $parameter->getType();
            if ($type instanceof \ReflectionNamedType && $type->getName() === DataUniverse::class) {
                return true;
            }
        }

        return false;
    }

    /** Every guarded read must take a universe. */
    public function testEveryBusinessReadRequiresAUniverse(): void
    {
        $unscoped = [];

        foreach (self::GUARDED_REPOSITORIES as $class) {
            foreach ((new ReflectionClass($class))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
                if ($method->getDeclaringClass()->getName() !== $class || $method->isConstructor()) {
                    continue;
                }
                if (self::readsBusinessData($method) && !self::hasUniverseParameter($method)) {
                    $unscoped[] = $method->getDeclaringClass()->getShortName() . '::' . $method->getName() . '()';
                }
            }
        }

        self::assertSame(
            [],
            $unscoped,
            "These reads return business rows or counts without a data universe:\n  "
            . implode("\n  ", $unscoped)
        );
    }

    /**
     * Rows and their counts must agree.
     *
     * A paginated list is two queries describing one population. v0.5.7.6 made them agree on
     * the membership rule; v0.5.8 adds the universe as a second rule they must also share, and
     * a count that takes no universe while its row query does is exactly the drift that makes
     * "Showing X-Y of Z" lie.
     */
    public function testEveryCountIsScopedWhereverItsRowQueryIs(): void
    {
        $mismatched = [];

        foreach (self::GUARDED_REPOSITORIES as $class) {
            $reflection = new ReflectionClass($class);
            foreach ($reflection->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
                if ($method->getDeclaringClass()->getName() !== $class || !str_ends_with($method->getName(), 'Count')) {
                    continue;
                }
                $rowMethod = substr($method->getName(), 0, -5);
                if ($rowMethod === '' || !$reflection->hasMethod($rowMethod)) {
                    continue;
                }
                $rows = $reflection->getMethod($rowMethod);
                if (self::hasUniverseParameter($rows) !== self::hasUniverseParameter($method)) {
                    $mismatched[] = $reflection->getShortName() . '::' . $rowMethod . '() / ' . $method->getName() . '()';
                }
            }
        }

        self::assertSame([], $mismatched, 'A count and its row query must be scoped identically.');
    }

    /** The universe must never be optional: a default would silently pick a side. */
    public function testUniverseParametersAreNeverOptional(): void
    {
        $optional = [];

        foreach (self::GUARDED_REPOSITORIES as $class) {
            foreach ((new ReflectionClass($class))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
                if ($method->getDeclaringClass()->getName() !== $class) {
                    continue;
                }
                foreach ($method->getParameters() as $parameter) {
                    $type = $parameter->getType();
                    if ($type instanceof \ReflectionNamedType
                        && $type->getName() === DataUniverse::class
                        && $parameter->isDefaultValueAvailable()) {
                        $optional[] = $method->getDeclaringClass()->getShortName() . '::' . $method->getName() . '()';
                    }
                }
            }
        }

        self::assertSame([], $optional, 'A defaulted universe hides the decision at the call site.');
    }

    /**
     * The universe filter is read in exactly one place.
     *
     * DataUniverse::fromRequest() is only a parser - it will happily return All for the string
     * "all", which is correct. The rule about who may *use* All lives in
     * CurrentUser::resolveUniverse(), and BaseController::universe() is the only thing that
     * feeds it a request value. A controller reading the query string itself would bypass that
     * decision entirely, so the structural rule is asserted here rather than the parsing.
     */
    public function testTheUniverseFilterIsReadInExactlyOnePlace(): void
    {
        $controllers = glob(dirname(__DIR__, 2) . '/src/Http/Controller/*.php') ?: [];
        $offenders = [];
        foreach ($controllers as $file) {
            if (basename($file) === 'BaseController.php') {
                continue;
            }
            if (str_contains((string) file_get_contents($file), "\$_GET['universe']")) {
                $offenders[] = basename($file);
            }
        }

        self::assertSame([], $offenders, 'Resolve the universe through BaseController::universe(), not from $_GET directly.');
    }
}
