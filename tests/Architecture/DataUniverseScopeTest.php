Description:
Enforces that no repository method returning business rows or a count can be called without
saying which data universe it means.

The Seed Database plan's Phase 3 gate is "no repository method that returns business rows or a
count may be reachable without a universe scope", and it explicitly requires an architecture
test rather than a review checklist. The reason is the v0.5.7.6 audit: that release added
eighteen count methods and a lookup repository, and the specification's hand-written audit list
predated all of them. A list rots. A test does not.

A mis-scoped count is worse than a mis-scoped list. A list that shows generated rows looks
wrong; a count that includes them looks like a number.

