                foreach (self::ADDRESS_CLASSES as $place) if (str_starts_with($relative, $place)) return false;
                return true;
            }, ARRAY_FILTER_USE_KEY),
            2 => $this->files(['assets', 'public_html/js'], 'js'),
        ];
        foreach (self::RECORDS_BY_HAND as $record => $shapes) {
            foreach ($sources as $kind => $files) {
                foreach ($files as $relative => $source) {
                    if (preg_match_all($shapes[$kind], $source, $matches) > 0) $found[] = $relative . ': ' . implode(', ', array_unique($matches[0])) . ' (' . $record . ')';
                }
            }
        }
        self::assertSame([], $found, "An address was built by hand for a record that has a code (owner, 2026-11-06). Use its helper:\n" . implode("\n", $found));
    }

    public function testNoOtherAddressIsBuiltFromARowIdUnnoticed(): void
    {
        $counts = $this->builtFromIds();
        $more = $fewer = [];
        foreach ($counts as $relative => $count) {
            $allowed = self::BUILT_FROM_IDS[$relative][0] ?? 0;
            if ($count > $allowed) $more[] = $relative . ': ' . $count . ' (allowed ' . $allowed . ')';
        }
        foreach (self::BUILT_FROM_IDS as $relative => [$allowed, $why]) {
            if (($counts[$relative] ?? 0) < $allowed) $fewer[] = $relative . ': ' . ($counts[$relative] ?? 0) . ' (lower its number from ' . $allowed . ')';
            self::assertStringStartsWith('Keep their numbers: ', $why, $relative . ' says why its addresses keep their numbers.');
        }
        self::assertSame([], $more, "More addresses are built from a row id than agreed. Name the record by a code, a slug or a random public id, or, behind a sign-in only, agree the number in BUILT_FROM_IDS:\n" . implode("\n", $more));
        self::assertSame([], $fewer, "BUILT_FROM_IDS only shrinks: lower these numbers:\n" . implode("\n", $fewer));
    }

    /**
     * Every file that builds an address from a row id, with how many.
     *
     * @return array<string,int>
     */
    public function builtFromIds(): array
    {
        $counts = [];
        foreach ($this->files(['resources/views', 'themes'], 'twig') as $relative => $source) {
            $count = preg_match_all(self::TEMPLATE_FROM_ID, $source);
            if ($count > 0) $counts[$relative] = $count;
        }
        foreach ($this->files(['src'], 'php') as $relative => $source) {
            $count = preg_match_all(self::PHP_FROM_ID, $source);
            if ($count > 0) $counts[$relative] = $count;
        }
        ksort($counts);
        return $counts;
    }

    /**
     * @param list<string> $folders
     * @return array<string,string> relative path => source
     */
    private function files(array $folders, string $extension): array
    {
        $root = dirname(__DIR__, 2) . '/';
        $files = [];
        foreach ($folders as $folder) {
            if (!is_dir($root . $folder)) continue;
            $walk = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . $folder, FilesystemIterator::SKIP_DOTS));
            foreach ($walk as $file) {
                if (!$file->isFile() || $file->getExtension() !== $extension) continue;
                $relative = substr($file->getPathname(), strlen($root));
                // Bundled libraries are not ours to scan.
                if (preg_match('~(^|/)(vendor|ckeditor5|htmx|catwalk)[^/]*(\.min)?\.js$~', $relative) === 1 || str_contains($relative, '.min.js')) continue;
                $files[$relative] = (string) file_get_contents($file->getPathname());
            }
        }
        ksort($files);
        return $files;
    }
