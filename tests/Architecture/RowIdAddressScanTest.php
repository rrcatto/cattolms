    public function testACourseAddressIsMadeOnlyByTheHelpers(): void
    {
        $found = [];
        foreach ($this->files(['resources/views', 'themes'], 'twig') as $relative => $source) {
            foreach (self::TEMPLATE_COURSE as $needle => $shape) {
                if (str_contains($source, $needle)) $found[] = $relative . ': ' . $shape . ' (use course_admin_url(), course_anchor() or course_url())';
            }
        }
        foreach ($this->files(['src'], 'php') as $relative => $source) {
            if ($relative === 'src/Course/CourseAddress.php') continue;
            if (preg_match_all(self::PHP_COURSE, $source, $matches) > 0) $found[] = $relative . ': ' . implode(', ', array_unique($matches[0])) . ' (use CourseAddress)';
        }
        foreach ($this->files(['assets', 'public_html/js'], 'js') as $relative => $source) {
            if (preg_match(self::SCRIPT_COURSE, $source) === 1) $found[] = $relative . ': a course address built from a number (read the address the page gives, data-*-url)';
        }
        self::assertSame([], $found, "A course's address was built by hand (owner, 2026-11-06: a course is its code in every address):\n" . implode("\n", $found));
    }

