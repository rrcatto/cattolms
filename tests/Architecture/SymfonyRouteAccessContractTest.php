Description:
Every ported API route states both access questions, and every attribute it states them with is real.

Architectural boundary: architecture test. It reads the source's own declarations rather than
exercising a request, because the thing being protected is the declaration.

Why the second half exists at all. A PHP attribute whose class cannot be autoloaded is not an
error - reflection reports it by name, and any listener looking for the real class simply does not
find it. #[IsGranted] was first written here against a namespace that does not exist in Symfony 7,
so the route authorised nobody and everybody: the firewall authenticated the token, no authorization
ran, and the endpoint answered 200 to a token that held neither the scope nor the permission. The
response looked exactly like a correct one. Instantiating every attribute is what turns that class
of mistake back into a failure.

The first half is the platform's rule that an API call requires its transport scope and the same
business permission the equivalent web operation requires. Stating only one of them is the same bug
in slower motion.

Changelog:

2026/09/08 22:15 SAST
- Created after #[IsGranted] was imported from a namespace that no longer exists, which silently
  disabled authorization on the first ported authenticated route.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Architecture;

use CattoLearning\Api\ApiScope;
use CattoLearning\Auth\PermissionCatalog;
use PHPUnit\Framework\TestCase;
use ReflectionClass;
use ReflectionMethod;
use Symfony\Component\Routing\Attribute\Route;
use Symfony\Component\Security\Http\Attribute\IsGranted;

final class SymfonyRouteAccessContractTest extends TestCase
{
    /**
     * Routes that are deliberately open, with the reason they are.
     *
     * A route earns a place here by being something a client must be able to read before it has a
     * token at all. Anything else belongs behind the firewall.
     */
    private const PUBLIC_ROUTES = [
        '/api/v1' => 'The status document tells a client that authentication is by Bearer token.',
    ];

    public function testEveryApiRouteStatesAScopeAndAPermission(): void
    {
        $catalog = (new PermissionCatalog())->keys();
        $checked = 0;

        foreach ($this->routes() as [$method, $route, $attributes]) {
            $path = (string) $route->path;
            $where = $method->getDeclaringClass()->getShortName() . '::' . $method->getName() . ' (' . $path . ')';

            if (!str_starts_with($path, '/api/')) {
                continue;
            }
            if (array_key_exists($path, self::PUBLIC_ROUTES)) {
                self::assertSame([], $attributes, $where . ' is listed as public but states access requirements.');
                continue;
            }

            $stated = array_map(static fn(IsGranted $granted): string => (string) $granted->attribute, $attributes);
            $scopes = array_values(array_filter($stated, ApiScope::isValid(...)));
            $permissions = array_values(array_filter(
                $stated,
                static fn(string $key): bool => in_array($key, $catalog, true)
            ));

            self::assertNotSame([], $scopes, $where . ' states no API scope.');
            self::assertNotSame([], $permissions, $where . ' states no business permission.');
            self::assertSame(
                count($stated),
                count($scopes) + count($permissions),
                $where . ' states something that is neither an API scope nor a permission key.'
            );
            $checked++;
        }

        self::assertGreaterThan(0, $checked, 'No authenticated API routes were found to check.');
    }

    /**
     * Every attribute on every ported route can be instantiated.
     *
     * newInstance() is the assertion: an attribute naming a class that does not exist throws here
     * and is inert everywhere else.
     */
    public function testEveryRouteAttributeNamesAClassThatExists(): void
    {
        $instantiated = 0;

        foreach ($this->controllerMethods() as $method) {
            foreach ($method->getAttributes() as $attribute) {
                $attribute->newInstance();
                $instantiated++;
            }
        }

        self::assertGreaterThan(0, $instantiated);
    }

    /** @return list<array{0:ReflectionMethod,1:Route,2:list<IsGranted>}> */
    private function routes(): array
    {
        $routes = [];
        foreach ($this->controllerMethods() as $method) {
            foreach ($method->getAttributes(Route::class) as $attribute) {
                $routes[] = [
                    $method,
                    $attribute->newInstance(),
                    array_map(
                        static fn(\ReflectionAttribute $granted): IsGranted => $granted->newInstance(),
                        $method->getAttributes(IsGranted::class)
                    ),
                ];
            }
        }

        return $routes;
    }

    /** @return list<ReflectionMethod> */
    private function controllerMethods(): array
    {
        $methods = [];
        foreach (glob(__DIR__ . '/../../src/Http/Symfony/*.php') ?: [] as $file) {
            $class = 'CattoLearning\\Http\\Symfony\\' . basename($file, '.php');
            if (!class_exists($class)) {
                continue;
            }
            foreach ((new ReflectionClass($class))->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
                if ($method->getAttributes(Route::class) !== []) {
                    $methods[] = $method;
                }
            }
        }

        return $methods;
    }
}
