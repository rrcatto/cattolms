final class FooterSocialIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testTheSitesOwnProfilesAreSavedCheckedLoggedAndShownInTheFooter(): void
    {
        $container = IntegrationContainer::get();
        $service = $container->get(PlatformAdministrationService::class);
        $profiles = $container->get(FooterSocial::class);
        $owner = (new DevelopmentFixture($this->db))->createUser('Footer social owner');
        $before = $profiles->saved();

        try {
            $service->saveFooterSocial(['facebook' => 'https://www.facebook.com/example-site', 'linkedin' => 'https://www.example.org/not-linkedin'], $owner);
            self::fail('An address on another site was kept as a LinkedIn profile.');
        } catch (RuntimeException $refused) {
            self::assertStringContainsString('LinkedIn', $refused->getMessage());
            self::assertSame($before, $profiles->saved(), 'nothing is kept when one is wrong');
        }

        $service->saveFooterSocial(['youtube' => 'https://www.youtube.com/@example-site', 'telegram' => 'https://t.me/example_site', 'facebook' => 'https://www.facebook.com/example-site', 'x' => '  '], $owner);
        self::assertSame(['facebook' => 'https://www.facebook.com/example-site', 'telegram' => 'https://t.me/example_site', 'youtube' => 'https://www.youtube.com/@example-site'], $profiles->saved());
        $logged = $this->db->fetchAssociative("SELECT actor_id, details FROM cattophp_activity WHERE action = 'platform.footer_social_changed' ORDER BY id DESC LIMIT 1");
        self::assertIsArray($logged);
        self::assertSame((string) $owner, (string) $logged['actor_id']);
        self::assertEquals(['old' => $before, 'new' => $profiles->saved()], json_decode((string) $logged['details'], true), 'what it was and what it became');

        $renderer = $container->get(ThemeRenderer::class);
        [$theme, $preview] = $renderer->resolveTheme([]);
        $marks = $renderer->viewModel('help', [], $theme, $preview)['footer_social'];
        self::assertSame(['https://www.facebook.com/example-site', 'https://t.me/example_site', 'https://www.youtube.com/@example-site'], array_column($marks, 'href'), "the footer shows the site's own, and no platform's home page beside them");
        $home = $container->get(PageMetadata::class)->home('A description.');
        $named = str_replace('\/', '/', implode(' ', array_map('strval', (array) ($home['structured_data'] ?? []))));
        self::assertStringContainsString('"https://www.youtube.com/@example-site"', $named, "the home page names it as the organisation's own");
        // The Settings page's own variables, as SiteOwnerSettingsIntegrationTest passes them.
        $runtime = $container->get(\CattoLearning\Configuration\RuntimeSettings::class);
        $section = $renderer->renderFragment('partials/admin/settings', [
            'platform_name' => 'Test LMS', 'platform_name_source' => 'environment', 'mail_settings' => $runtime->mailAdminView(),
            'site_mode' => ['mode' => 'demo', 'source' => 'environment', 'environment' => 'demo', 'heading' => 'Demo mode', 'notice' => 'Notice', 'email_notice' => 'Email', 'simulation' => 'Simulation', 'own_words' => false, 'limits' => ['heading' => 60, 'notice' => 300, 'email_notice' => 400, 'simulation' => 300]],
            'site_owner' => $service->siteOwnerView(),
            'site_notification' => $container->get(\CattoLearning\Configuration\SiteNotification::class)->settingsView(),
            'commerce_fields' => \CattoLearning\Commerce\Http\CommerceSettingsController::fieldsView($container->get(\CattoLearning\Commerce\Settings\CommerceSettings::class)),
            'social_profiles' => $profiles->settingsView(),
            'can_manage_settings' => true, 'settings_open_section' => 'footer-social', 'csrf' => 'test',
            'maintenance' => ['login_tokens' => 0, 'auth_sessions' => 0, 'web_sessions' => 0],
        ]);
        self::assertStringContainsString('id="settings-footer-social"', $section);
        self::assertStringContainsString('value="https://www.youtube.com/@example-site"', $section);

        $service->saveFooterSocial([], $owner);
        self::assertSame([], $profiles->saved());
        self::assertSame(['https://www.facebook.com/', 'https://www.whatsapp.com/', 'https://telegram.org/', 'https://x.com/', 'https://www.linkedin.com/', 'https://www.instagram.com/', 'https://www.youtube.com/'], array_column($profiles->marks(), 'href'));
    }

    public function testACoursePageAndABundlePageOfferToShareThemselves(): void
    {
        $pages = $this->db->fetchAllAssociative("SELECT '/courses/' || slug AS path FROM courses WHERE status = 'published' AND slug IS NOT NULL ORDER BY id LIMIT 1");
        $pages = array_merge($pages, $this->db->fetchAllAssociative("SELECT '/bundles/' || b.slug AS path FROM bundles b WHERE b.status = 'published' ORDER BY b.id LIMIT 1"));
        if ($pages === []) self::markTestSkipped('No published course or bundle to share.');
        foreach (array_column($pages, 'path') as $path) {
            $html = (string) (new Kernel('test', true, (string) CliBootstrap::boot()['instance_root']))->handle(Request::create((string) $path))->getContent();
            self::assertSame(1, preg_match('/<link rel="canonical" href="([^"]+)"/', $html, $canonical), $path);
            self::assertStringContainsString('data-share-url="' . $canonical[1] . '"', $html, $path . ': shares its canonical address');
            self::assertStringContainsString('https://www.facebook.com/sharer/sharer.php?u=' . rawurlencode(html_entity_decode($canonical[1])), $html, $path);
            self::assertStringContainsString('https://wa.me/?text=', $html, $path);
            self::assertStringContainsString('https://t.me/share/url?url=' . rawurlencode(html_entity_decode($canonical[1])), $html, $path . ': Telegram, after WhatsApp');
            self::assertLessThan(strpos($html, 'https://t.me/share/url'), strpos($html, 'https://wa.me/?text='), $path);
            self::assertMatchesRegularExpression('/Share this (course|bundle)/', $html, $path);
        }
    }
