displayed somebody else's, and creating a person was refused outright because a platform
administrator belongs to no company. The workspace was a read-only viewer that looked like an
editor.

These tests are the ones the earlier suite should have had. The previous Stage D tests asserted
that cross-company access was *refused*, which passed while the feature did not work at all: a
refusal and an inability to reach the surface are indistinguishable from the outside. Each test
below therefore asserts where a write actually landed, by reading the row back.

The matrix, per write family:

  platform administrator with company X selected  -> the row is written to X
  platform administrator's own membership         -> never used as a fallback
  company administrator of X                      -> writes X
  company administrator naming Y in the request   -> refused
  a target belonging to another company           -> refused

Disable is asserted for what it actually has to do: stop the login, end the live sessions, and
