    private SQL $db;
    private SeedIntegrationFixture $fixture;
    private SelectedCompanyContext $context;
    private PlatformAdministrationService $administration;
    private AuthSessionRepository $sessions;

    private int $adminUserId = 0;
    private int $companyAdminUserId = 0;
    private int $personInA = 0;
    private int $personInB = 0;

    /** @var array{a:int,b:int} */
    private array $real = ['a' => 0, 'b' => 0];

    private string $suffix = '';

    protected function setUp(): void
    {
        $this->container = IntegrationContainer::get();
        $this->db = IntegrationContainer::db();
        $this->fixture = new SeedIntegrationFixture($this->db);

        /** @var SelectedCompanyContext $context */
        $context = $this->container->get(SelectedCompanyContext::class);
        $this->context = $context;
        /** @var PlatformAdministrationService $administration */
        $administration = $this->container->get(PlatformAdministrationService::class);
        $this->administration = $administration;
        /** @var AuthSessionRepository $sessions */
        $sessions = $this->container->get(AuthSessionRepository::class);
        $this->sessions = $sessions;

        $_SESSION = [];
        $this->suffix = $this->fixture->suffix();

        $this->adminUserId = $this->fixture->createUser('Platform administrator', 'admin-' . $this->suffix . '@admin-' . $this->suffix . '.test');

        $this->real['a'] = $this->fixture->createCompany($this->adminUserId, 'Alpha ' . $this->suffix, 'alpha-' . $this->suffix . '.test');
        $this->real['b'] = $this->fixture->createCompany($this->adminUserId, 'Beta ' . $this->suffix, 'beta-' . $this->suffix . '.test');

        $this->personInA = $this->fixture->createUser('Alpha person', 'alpha-person-' . $this->suffix . '@alpha-' . $this->suffix . '.test');
        $this->fixture->addCompanyMember($this->real['a'], $this->personInA);

        $this->personInB = $this->fixture->createUser('Beta person', 'beta-person-' . $this->suffix . '@beta-' . $this->suffix . '.test');
        $this->fixture->addCompanyMember($this->real['b'], $this->personInB);

        // The platform administrator is deliberately a member of company B. If a write ever falls
        // back to the actor's own membership, it lands here - and the assertions catch it.
        $this->fixture->addCompanyMember($this->real['b'], $this->adminUserId, null, 'administrator');

        $this->companyAdminUserId = $this->fixture->createUser('Company administrator', 'coadmin-' . $this->suffix . '@alpha-' . $this->suffix . '.test');
        $this->fixture->addCompanyMember($this->real['a'], $this->companyAdminUserId, null, 'administrator');
    }

    protected function tearDown(): void
    {
        $_SESSION = [];
        $this->fixture->cleanup();
    }

    /** @param list<string> $permissions */
    private function identity(int $userId, array $permissions): CurrentUser
    {
        return new CurrentUser($userId, Uuid::v4(), 'identity-' . $userId . '@example.test', 'Identity ' . $userId, [], $permissions, Uuid::v4(), null);
    }

    private function platformAdmin(): CurrentUser
    {
        return $this->identity($this->adminUserId, [
            SelectedCompanyContext::SELECTOR_PERMISSION,
            'COMPANY.DASHBOARD.VIEW',
            'COMPANY.PERSON.MANAGE',
            'PLATFORM.PERSON.MANAGE',
        ]);
    }

    private function companyAdmin(): CurrentUser
    {
        return $this->identity($this->companyAdminUserId, ['COMPANY.DASHBOARD.VIEW', 'COMPANY.PERSON.MANAGE']);
    }

    private function companyOf(int $userId): int
    {
        return (int) $this->fixture->scalar(
            "SELECT COALESCE(MAX(company_id), 0)::int AS value FROM company_users WHERE user_id = :id AND status = 'active'",
            [':id' => $userId]
        );
    }

    private function userStatus(int $userId): string
    {
        return (string) $this->fixture->scalar('SELECT status AS value FROM users WHERE id = :id', [':id' => $userId]);
    }

    private function liveSessions(int $userId): int
    {
        return (int) $this->fixture->scalar(
            'SELECT COUNT(*)::int AS value FROM auth_sessions WHERE user_id = :id AND revoked_at IS NULL',
            [':id' => $userId]
        );
    }

    // --- create person -----------------------------------------------------------------------------

    /**
     * A platform administrator creates into the selected company, not their own.
     *
     * The actor is a member of company B throughout. Before this change the create was refused
     * outright for a platform administrator; the failure mode being guarded now is the subtler
     * one, where it succeeds against the wrong company.
     */
    public function testPlatformAdminCreatesPersonIntoTheSelectedCompany(): void
    {
        $user = $this->platformAdmin();
        $this->context->select($user, $this->real['a'], DataUniverse::Real);

        $created = $this->administration->createCompanyPerson($user->id, $this->context->contextCompanyId($user, DataUniverse::Real), [
            'first_name' => 'New',
            'last_name' => 'Starter',
            'email' => 'new-starter-' . $this->suffix . '@alpha-' . $this->suffix . '.test',
            'role' => 'STUDENT',
        ], DataUniverse::Real);
        $this->fixture->rememberUser($created);

        self::assertSame($this->real['a'], $this->companyOf($created), 'The person must join the selected company.');
        self::assertNotSame($this->real['b'], $this->companyOf($created), "The actor's own company must never be used as a fallback.");
    }

    /** Switching the selection switches where the next write lands. */
    public function testSwitchingSelectionSwitchesWhereWritesLand(): void
    {
        $user = $this->platformAdmin();

        $this->context->select($user, $this->real['b'], DataUniverse::Real);
        $intoB = $this->administration->createCompanyPerson($user->id, $this->context->contextCompanyId($user, DataUniverse::Real), [
            'first_name' => 'Into', 'last_name' => 'Beta',
            'email' => 'into-beta-' . $this->suffix . '@beta-' . $this->suffix . '.test', 'role' => 'STUDENT',
        ], DataUniverse::Real);
        $this->fixture->rememberUser($intoB);

        self::assertSame($this->real['b'], $this->companyOf($intoB));
    }

    // --- edit person -------------------------------------------------------------------------------

    /** Editing writes the profile fields and refuses a target outside the context company. */
    public function testEditingIsScopedToTheContextCompany(): void
    {
        $user = $this->platformAdmin();
        $this->context->select($user, $this->real['a'], DataUniverse::Real);
        $companyId = $this->context->contextCompanyId($user, DataUniverse::Real);

        $this->administration->updateCompanyPerson($user->id, $companyId, $this->personInA, [
            'first_name' => 'Edited',
            'certificate_name' => 'Edited On Certificate',
        ]);

        self::assertSame('Edited', (string) $this->fixture->scalar('SELECT first_name AS value FROM users WHERE id = :id', [':id' => $this->personInA]));

        // A person in company B is not reachable while company A is selected.
        $this->expectExceptionMessageMatches('/not an active member/i');
        $this->administration->updateCompanyPerson($user->id, $companyId, $this->personInB, ['first_name' => 'Nope']);
    }

    /** A company administrator cannot reach another company's person by naming its id. */
    public function testCompanyAdminCannotEditAnotherCompanysPerson(): void
    {
        $user = $this->companyAdmin();
        $ownCompany = $this->context->contextCompanyId($user, DataUniverse::Real);

        self::assertSame($this->real['a'], $ownCompany, 'A company administrator resolves to their own company.');

        // Even handed company B's id directly, the target does not belong to it in a way that
        // helps: the person is in B, so naming B would reach them - which is why the id must come
        // from the context and never from the request. This asserts the context is what decides.
        $this->expectExceptionMessageMatches('/not an active member/i');
        $this->administration->updateCompanyPerson($user->id, $ownCompany, $this->personInB, ['first_name' => 'Nope']);
    }

    // --- disable and enable ------------------------------------------------------------------------

    /**
     * Disabling stops the login, ends live sessions, and deletes nothing.
     *
     * All three halves matter. users.status alone is only read at sign-in, so without the session
     * revocation a disabled learner carries on with a course until their session expires.
     */
    public function testDisablingStopsLoginEndsSessionsAndKeepsEverything(): void
    {
        $user = $this->platformAdmin();
        $this->context->select($user, $this->real['a'], DataUniverse::Real);
        $companyId = $this->context->contextCompanyId($user, DataUniverse::Real);

        $this->sessions->create($this->personInA, hash('sha256', 'token-' . $this->suffix), 3600, 'ip', 'agent');
        self::assertSame(1, $this->liveSessions($this->personInA), 'The fixture must start with a live session.');

        $membershipBefore = $this->companyOf($this->personInA);

        $this->administration->setCompanyPersonStatus($user->id, $companyId, $this->personInA, 'disabled');

        self::assertSame('disabled', $this->userStatus($this->personInA), 'The login gate must be closed.');
        self::assertSame(0, $this->liveSessions($this->personInA), 'Live sessions must be revoked, not left to expire.');
        self::assertSame($membershipBefore, $this->companyOf($this->personInA), 'Membership must be untouched.');
    }

    /** Enabling reverses it and the learner resumes where they left off. */
    public function testEnablingRestoresTheAccount(): void
    {
        $user = $this->platformAdmin();
        $this->context->select($user, $this->real['a'], DataUniverse::Real);
        $companyId = $this->context->contextCompanyId($user, DataUniverse::Real);

        $this->administration->setCompanyPersonStatus($user->id, $companyId, $this->personInA, 'disabled');
        $this->administration->setCompanyPersonStatus($user->id, $companyId, $this->personInA, 'active');

        self::assertSame('active', $this->userStatus($this->personInA));
        self::assertSame($this->real['a'], $this->companyOf($this->personInA), 'Nothing about the membership changed.');
    }

    /** Disabling refuses a target outside the context company. */
    public function testDisablingRefusesAnotherCompanysPerson(): void
    {
        $user = $this->platformAdmin();
        $this->context->select($user, $this->real['a'], DataUniverse::Real);

        $this->expectExceptionMessageMatches('/not an active member/i');
        $this->administration->setCompanyPersonStatus(
            $user->id,
            $this->context->contextCompanyId($user, DataUniverse::Real),
            $this->personInB,
            'disabled'
        );
    }

    // --- remove ------------------------------------------------------------------------------------

    /**
     * Removal ends the membership and leaves the identity alone.
     *
     * The old behaviour set users.status to disabled as a side effect, so somebody moving between
     * companies was banned from the platform with no way to reverse it from this workspace.
     */
    public function testRemovalEndsMembershipWithoutDisablingTheAccount(): void
    {
        $user = $this->platformAdmin();
        $this->context->select($user, $this->real['a'], DataUniverse::Real);

        $this->administration->removeCompanyPerson(
            $user->id,
            $this->context->contextCompanyId($user, DataUniverse::Real),
            $this->personInA
        );

        self::assertSame(0, $this->companyOf($this->personInA), 'The membership must end.');
        self::assertSame('active', $this->userStatus($this->personInA), 'Removal is not an account ban.');
    }

    /** Removal refuses a target outside the context company. */
    public function testRemovalRefusesAnotherCompanysPerson(): void
    {
        $user = $this->platformAdmin();
        $this->context->select($user, $this->real['a'], DataUniverse::Real);

        $this->expectExceptionMessageMatches('/not an active member/i');
        $this->administration->removeCompanyPerson(
            $user->id,
            $this->context->contextCompanyId($user, DataUniverse::Real),
            $this->personInB
        );
    }

    // --- company search ----------------------------------------------------------------------------

    /**
     * Search finds a company that is not on the current page.
     *
     * The defining test for the whole search change: with a page size of one, the match is on a
     * later page, so a current-page DOM filter could never find it.
     */
    public function testSearchFindsACompanyThatIsNotOnTheCurrentPage(): void
    {
        $repository = IntegrationContainer::get()->get(\CattoLearning\Infrastructure\Persistence\AdministrationRepository::class);

        $firstPage = $repository->companies(DataUniverse::Real, 1, 0);
        $names = array_column($firstPage, 'name');
        self::assertNotContains('Beta ' . $this->suffix, $names, 'The fixture must place the match off the first page.');

        $found = $repository->companies(DataUniverse::Real, 25, 0, 'Beta ' . $this->suffix);
        self::assertNotSame([], $found, 'Search must reach the whole dataset, not the rendered page.');
        self::assertContains('Beta ' . $this->suffix, array_column($found, 'name'));
    }

    /** The count describes the same filtered population as the rows. */
    public function testSearchCountAndRowsDescribeTheSamePopulation(): void
    {
        $repository = IntegrationContainer::get()->get(\CattoLearning\Infrastructure\Persistence\AdministrationRepository::class);

        $term = 'Beta ' . $this->suffix;
        $rows = $repository->companies(DataUniverse::Real, 100, 0, $term);
        $count = $repository->companyCount(DataUniverse::Real, $term);

        self::assertSame(count($rows), $count, 'A count that disagrees with its rows is the defect this guards.');
    }

    /** Domain search works as well as name search, and clearing restores the full population. */
    public function testSearchMatchesDomainAndClearingRestoresEverything(): void
    {
        $repository = IntegrationContainer::get()->get(\CattoLearning\Infrastructure\Persistence\AdministrationRepository::class);

        $byDomain = $repository->companies(DataUniverse::Real, 25, 0, 'beta-' . $this->suffix . '.test');
        self::assertContains('Beta ' . $this->suffix, array_column($byDomain, 'name'));

        $all = $repository->companyCount(DataUniverse::Real, '');
        self::assertGreaterThanOrEqual(2, $all, 'An empty term must return the whole selected universe.');
        self::assertGreaterThan($repository->companyCount(DataUniverse::Real, $this->suffix . '-no-such-company'), $all);
    }

    /** Search honours the universe predicate rather than replacing it. */
    public function testSearchStaysInsideItsUniverse(): void
    {
        $repository = IntegrationContainer::get()->get(\CattoLearning\Infrastructure\Persistence\AdministrationRepository::class);

        $seedMatches = $repository->companies(DataUniverse::Seed, 25, 0, 'Alpha ' . $this->suffix);

        self::assertSame([], $seedMatches, 'A REAL company must not surface in a SEED search.');
    }
