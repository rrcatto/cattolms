declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Infrastructure\Persistence\DatabaseSessionHandler;
use CattoLearning\Tests\Support\IntegrationContainer;
use PHPUnit\Framework\TestCase;

final class DatabaseSessionHandlerIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testARequestThatChangedNothingLeavesWhatAnotherSaved(): void
    {
        $handler = new DatabaseSessionHandler($this->db, 3600);
        $id = 'test' . bin2hex(random_bytes(14));
        $before = 'checkout|a:0:{}';
        $handler->write($id, $before);
        // The palette request reads the session, the form request saves its message, the palette request ends.
        $paletteRead = $handler->read($id);
        $handler->write($id, $before . 'flash|a:1:{i:0;s:13:"Promo applied";}');
        self::assertTrue($handler->updateTimestamp($id, $paletteRead));
        self::assertSame($before . 'flash|a:1:{i:0;s:13:"Promo applied";}', $handler->read($id), 'The form\'s message is still there.');
        self::assertInstanceOf(\SessionUpdateTimestampHandlerInterface::class, $handler, 'PHP asks the handler only to mark an unchanged session active.');
        self::assertTrue($handler->validateId($id));
        self::assertFalse($handler->validateId('test' . bin2hex(random_bytes(14))), 'An id with no session row is not valid.');
        $handler->destroy($id);
    }
}
