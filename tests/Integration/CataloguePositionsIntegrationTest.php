declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Course\CataloguePositions;
use CattoLearning\Course\CoursePortabilityService;
use CattoLearning\Course\CourseRepository;
use CattoLearning\Course\CourseService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\DevelopmentFixture;
use CattoLearning\Tests\Support\SpecificationExample;
use PHPUnit\Framework\TestCase;
use Psr\Container\ContainerInterface;

final class CataloguePositionsIntegrationTest extends TestCase
{
    private ContainerInterface $container;
    private Database $db;
    private CataloguePositions $positions;
    private CourseService $courses;
    private CourseRepository $repository;
    private int $admin;

    protected function setUp(): void
    {
        $this->container = CliBootstrap::boot()['container'];
        $this->db = $this->container->get(Database::class);
        $this->positions = $this->container->get(CataloguePositions::class);
        $this->courses = $this->container->get(CourseService::class);
        $this->repository = $this->container->get(CourseRepository::class);
        $this->db->beginTransaction();
        $fixture = new DevelopmentFixture($this->db);
        $this->admin = $fixture->person('ADMIN')['id'];
        // Ranges far above any position a site uses, so the site's own courses never sit in them.
        foreach (['ZQA', 'ZQB', 'GDN'] as $prefix) {
            if ((int) $this->db->fetchOne("SELECT count(*) FROM courses WHERE split_part(code, '-', 1) = :p", ['p' => $prefix]) > 0) self::markTestSkipped('Courses coded ' . $prefix . ' are on this site.');
        }
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) { $this->db->rollBack(); }
    }

    public function testSettingsRefuseWhatCannotBeARange(): void
    {
        foreach ([[['ZQ-A'], ['900000']], [['ZQA', 'zqa'], ['900000', '910000']], [['ZQA'], ['']], [['ZQA', 'ZQB'], ['900000', '900000']], [['ZQA'], ['0']]] as [$prefixes, $starts]) {
            try {
                $this->positions->save($prefixes, $starts, $this->admin);
                self::fail('Saved ' . json_encode([$prefixes, $starts]));
            } catch (\InvalidArgumentException) {
            }
        }
        self::assertSame(['ZQA' => 900000, 'ZQB' => 910000], $this->positions->save(['zqb', '', ' zqa '], ['910000', '', '900000'], $this->admin), 'Saved in order, a blank row left out, prefixes in capitals.');
        self::assertSame(['ZQA' => 900000, 'ZQB' => 910000], $this->positions->ranges());
        self::assertSame('ZQA from 900000, ZQB from 910000.', $this->positions->view()['summary']);
        self::assertSame([], $this->positions->save([''], [''], $this->admin));
        self::assertSame([], $this->positions->ranges(), 'Emptied, there are no ranges.');
    }

    public function testANewCourseTakesTheNextNumberInItsRange(): void
    {
        $this->positions->save(['ZQA', 'ZQB'], ['900000', '910000'], $this->admin);
        $first = $this->courses->createBlank(['title' => 'Range Check Course One', 'code' => 'ZQA-101'], $this->admin);
        $second = $this->courses->createBlank(['title' => 'Range Check Course Two', 'code' => 'ZQA-102'], $this->admin);
        $other = $this->courses->createBlank(['title' => 'Range Check Course Three', 'code' => 'ZQB-101'], $this->admin);
        $none = $this->courses->createBlank(['title' => 'Range Check Course Four', 'code' => 'ZQC-101'], $this->admin);
        $position = fn(int $id): ?int => ($this->repository->findById($id)['catalogue_position'] ?? null) === null ? null : (int) $this->repository->findById($id)['catalogue_position'];
        self::assertSame([900000, 900100, 910000, null], [$position($first), $position($second), $position($other), $position($none)]);

        // A course with a position keeps it.
        $this->repository->setCataloguePosition($second, 905000);
        self::assertNull($this->positions->fill($second, $this->admin));
        self::assertSame(905000, $position($second));
        self::assertSame(905100, $this->positions->fill($this->courses->createBlank(['title' => 'Range Check Course Five', 'code' => 'ZQA-103'], $this->admin), $this->admin) ?? $position((int) $this->db->fetchOne("SELECT id FROM courses WHERE code = 'ZQA-103'")));
    }

    public function testAnImportedCourseTakesItsRangesNumber(): void
    {
        $this->positions->save(['GDN'], ['920000'], $this->admin);
        $file = SpecificationExample::file();
        $portability = $this->container->get(CoursePortabilityService::class);
        $analysis = $portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => 'example.html', 'tmp_name' => $file], $this->admin);
        $courseId = $portability->commitImport((string) $analysis['import_key'], 0, $this->admin);
        self::assertSame(920000, (int) $this->repository->findById($courseId)['catalogue_position']);
    }
}
