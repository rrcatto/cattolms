declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Course\CoursePortabilityService;
use CattoLearning\Infrastructure\Persistence\AuthSessionRepository;
use CattoLearning\Kernel;
use CattoLearning\Support\Env;
use CattoLearning\Support\Token;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Tests\Support\IntegrationDataFixture;
use CattoLearning\Tests\Support\SpecificationExample;
use PHPUnit\Framework\TestCase;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\Response;

final class CourseImportReviewIntegrationTest extends TestCase
{
    private IntegrationDataFixture $fixture;
    private int $admin;
    /** @var list<string> */
    private array $keys = [];
    /** @var array<string,mixed> */
    private array $cookies = [];

    protected function setUp(): void
    {
        $db = IntegrationContainer::db();
        $this->fixture = new IntegrationDataFixture($db);
        $suffix = $this->fixture->suffix();
        $this->admin = $this->fixture->createUser('Import reviewer ' . $suffix, 'import-reviewer-' . $suffix . '@seed.test');
        $this->fixture->grantRole($this->admin, 'ADMIN');
        $this->cookies = $_COOKIE;
    }

    protected function tearDown(): void
    {
        $_COOKIE = $this->cookies;
        foreach ($this->keys as $key) {
            foreach (glob(CliBootstrap::boot()['instance_root'] . '/storage/imports/' . $key . '.*') ?: [] as $staged) { unlink($staged); }
        }
        $this->fixture->cleanup();
    }

    public function testTheSpecificationsExampleIsReviewed(): void
    {
        $file = SpecificationExample::file();
        $html = (string) $this->review($this->stage($file, 'example.html'))->getContent();
        self::assertStringContainsString('Growing Vegetables in Small Spaces', $html);
        self::assertMatchesRegularExpression('/>\s*HTML\s*<.*?Format/s', $html, 'The format is named plainly.');
        self::assertMatchesRegularExpression('/>\s*1\s*<.*?Module assessments.*?3 questions/s', $html, 'The module assessment is counted.');
        self::assertStringContainsString('Final assessment detected', $html);
        foreach (['m1-presentation', 'm1-flashcards', 'm1-assessment'] as $key) {
            self::assertStringContainsString($key, $html, 'Among its Course Items: ' . $key);
        }
        self::assertStringNotContainsString('Import warnings', $html, 'Nothing to warn about.');
        self::assertStringNotContainsString('Download as one HTML file', $html, 'The file is one already.');
        self::assertStringNotContainsString('/admin/courses/import/standalone', $html);
    }

    public function testACourseJsonIsReviewedWithItsAssessmentsCounted(): void
    {
        $json = (string) tempnam(sys_get_temp_dir(), 'course');
        file_put_contents($json, (string) json_encode([
            'format' => 'catto-learning-course', 'schema_version' => '2.1',
            'course' => ['code' => 'RVW-' . strtoupper(substr(bin2hex(random_bytes(3)), 0, 5)), 'slug' => 'review-check-' . bin2hex(random_bytes(3)), 'title' => 'Review Check Course', 'subtitle' => '', 'summary' => 'A course to review.', 'description_html' => '', 'level' => 'Beginner', 'introduction_html' => '<p>Welcome.</p>'],
            'resources' => [],
            'course_items' => [
                ['item_key' => 'review-check-' . bin2hex(random_bytes(3)), 'item_type' => 'assessment', 'title' => 'Check assessment', 'description_html' => '', 'content_source' => '', 'type_config' => [], 'questions' => [
                    ['question_html' => 'Which is a vegetable?', 'points' => 1, 'explanation_html' => '', 'options' => [['position' => 1, 'option_html' => 'Carrot', 'is_correct' => true], ['position' => 2, 'option_html' => 'Stone', 'is_correct' => false]]],
                ]],
            ],
            'structure' => [],
            'grade_bands' => [],
        ]));
        $data = (array) json_decode((string) file_get_contents($json), true);
        $data['structure'] = [['node_key' => 'n1', 'parent_node_key' => null, 'position' => 1, 'node_type' => 'item', 'item_key' => $data['course_items'][0]['item_key'], 'assessment_role' => 'final', 'public_preview' => false, 'relative_delay_minutes' => 0]];
        file_put_contents($json, (string) json_encode($data));
        $review = $this->review($this->stage($json, 'course.json'));
        self::assertSame(200, $review->getStatusCode(), 'The review of a course JSON opens.');
        $html = (string) $review->getContent();
        self::assertMatchesRegularExpression('/>\s*JSON 2\.1\s*<.*?Format/s', $html);
        self::assertStringContainsString('Final assessment detected', $html);
        self::assertStringNotContainsString('Legacy source components', $html, 'A course of Course Items has no legacy components to list.');
    }

    private function stage(string $file, string $name): string
    {
        $analysis = IntegrationContainer::get()->get(CoursePortabilityService::class)->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => $name, 'tmp_name' => $file], $this->admin);
        return $this->keys[] = (string) $analysis['import_key'];
    }

    private function review(string $key): Response
    {
        $token = Token::generate();
        IntegrationContainer::get()->get(AuthSessionRepository::class)->create($this->admin, Token::hash($token), 3600, 'qa', 'PHPUnit');
        $_COOKIE[Env::string('AUTH_SESSION_COOKIE', 'catto_learning_session')] = $token;
        $url = '/admin/courses/import/preview?key=' . $key;
        $kernel = new Kernel('test', true, CliBootstrap::boot()['instance_root']);
        $_GET = Request::create($url)->query->all();
        try {
            $response = $kernel->handle(Request::create($url));
            self::assertSame(200, $response->getStatusCode(), 'The review opens.');
            return $response;
        } finally {
            $kernel->shutdown();
            $_GET = [];
        }
    }
}
