    public function testTheSpecificationsExampleImportsWithEveryPart(): void
    {
        $file = SpecificationExample::file();
        $analysis = $this->portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => 'example.html', 'tmp_name' => $file], $this->admin);
        self::assertSame([], array_values((array) $analysis['warnings']), 'The review finds nothing to warn about.');
        $courseId = $this->portability->commitImport((string) $analysis['import_key'], 0, $this->admin);

        $container = $this->container;
        $course = $container->get(CourseRepository::class)->findById($courseId);
        self::assertSame(['GDN-101', 'Growing Vegetables in Small Spaces', 'Food from a balcony, a stoep or a small yard', 'Beginner'], [$course['code'], $course['title'], $course['subtitle'], $course['level']]);
        self::assertStringStartsWith('<svg', (string) $course['cover_svg'], 'The masthead\'s drawing is the cover.');
        self::assertStringContainsString('[grading-scale]', (string) $course['introduction_html'], 'The grading scale is shown from the course\'s bands.');
        self::assertSame([75.0, 70.0, 60.0, 50.0, 0.0], array_map(static fn(array $band): float => (float) $band['minimum_percentage'], $container->get(CourseRepository::class)->gradeBands($courseId)));

        $rows = $container->get(CourseItemService::class)->availability($courseId, null, false);
        $shape = array_map(static fn(array $row): string => str_repeat('  ', (int) $row['depth'] - 1) . ($row['node_type'] === 'section' ? 'Module ' . $row['section_number'] . ': ' . $row['section_title'] : (string) $row['part']), $rows);
        self::assertSame(['Module 1: Soil, compost and containers', '  presentation', '  video', '  lesson', '  summary', '  flashcards', '  practical', '  assessment', 'final'], $shape);
        $part = [];
        foreach ($rows as $row) { if ($row['node_type'] === 'item') { $part[(string) $row['part']] = $row; } }

        self::assertStringContainsString('Getting the ground right before you plant', (string) $rows[0]['section_introduction_html'], 'The subtitle opens the module.');
        self::assertSame(3, substr_count((string) $rows[0]['section_introduction_html'], '<li>'), 'The outcomes follow it.');
        self::assertCount(5, $part['presentation']['type_config']['slides']);
        self::assertSame('EXAMPLE0001', $part['video']['type_config']['youtube_id']);
        self::assertSame('How to make compost at home', $part['video']['item_title']);
        self::assertCount(4, $part['flashcards']['type_config']['cards']);
        self::assertStringContainsString('Task 2: Choose a container', (string) $part['practical']['content_source']);
        self::assertStringContainsString('<section class="answer">', (string) $part['practical']['type_config']['answer_html']);
        self::assertStringContainsString('Never fill a pot with garden soil', (string) $part['summary']['content_source'] . (string) $part['lesson']['content_source']);
        self::assertSame(3, (int) $part['assessment']['question_count']);
        self::assertSame('graded', $part['assessment']['assessment_role']);
        self::assertSame(2, (int) $part['final']['question_count']);

        // Only the lesson is left in the lesson: none of the file's frame or the other parts.
        $lesson = (string) $part['lesson']['content_source'];
        self::assertStringStartsWith('<h2>1. Why soil comes first</h2>', trim($lesson));
        foreach (['class="subs"', 'class="video"', 'iframe', 'class="outcomes"', 'class="practical"', 'class="answers"', 'class="blocks"', 'panel-head', 'class="sub ', 'data-quiz', 'data-deck', 'data-cards', 'data-key', 'Summary', 'Self Assessment'] as $frame) {
            self::assertStringNotContainsString($frame, $lesson, 'The lesson holds no ' . $frame . '.');
        }

        // Every rule of the stylesheet is confined to the course content.
        $css = (string) $course['presentation_css'];
        self::assertStringStartsWith('.cl-course-presentation{--ink:', $css, ':root reaches the course box.');
        preg_match_all('/(?:^|\})\s*([^{}@]+)\{/', $css, $rules);
        foreach ($rules[1] as $selectors) {
            foreach (explode(',', $selectors) as $selector) {
                self::assertStringStartsWith('.cl-course-presentation', trim($selector), 'Confined: ' . trim($selector));
            }
        }
    }

    public function testPracticalWorkUnderAnotherNameIsLiftedOnceItsNameIsPutRight(): void
    {
        $html = str_replace('<details class="block practical">', '<details class="block workshop">', SpecificationExample::html());
        $html = str_replace('<p class="time"><strong>Time:</strong> 30 minutes.</p>', '<p class="time"><strong>Time:</strong> 30 minutes.</p>', $html);
        $file = (string) tempnam(sys_get_temp_dir(), 'drift');
        file_put_contents($file, $html);
        $analysis = $this->portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => 'drifted.html', 'tmp_name' => $file], $this->admin);
        self::assertNotSame([], (array) $analysis['warnings'], 'The review names the drift.');
        $courseId = $this->portability->commitImport((string) $analysis['import_key'], 0, $this->admin);
        $items = $this->container->get(CourseItemService::class);
        $parts = static fn(): array => array_values(array_map(static fn(array $row): string => (string) $row['part'], array_filter($items->availability($courseId, null, false), static fn(array $row): bool => $row['node_type'] === 'item' && $row['parent_node_id'] !== null)));
        self::assertNotContains('practical', $parts(), 'Under another name it stays in the lesson.');

        // The name put right in the lesson, as the course fixes of 2026-11-01 do, with a "Verifiable" line in a task.
        $lesson = array_values(array_filter($items->availability($courseId, null, false), static fn(array $row): bool => ($row['part'] ?? '') === 'lesson'))[0];
        $item = $items->item((int) $lesson['course_item_id']);
        $content = str_replace('<details class="block workshop">', '<details class="block practical">', (string) $item['content_source']);
        $content = str_replace('<section class="task">', '<ol class="ex-list"><li><b class="ex-t">Check the drainage</b><p>Pour water into the pot.</p><div class="ex-out"><b>Verifiable outcome</b>Water runs out of the holes within a minute.</div></li></ol><section class="task">', $content);
        $items->update((int) $lesson['course_item_id'], ['content_source' => $content] + $item, $this->admin);
        $restructurer = $this->container->get(\CattoLearning\Course\CourseRestructurer::class);
        self::assertSame('practicals', $restructurer->arrangement($courseId));
        $report = $restructurer->arrange($courseId, $this->admin);
        self::assertSame(1, $report['practicals']);
        self::assertSame(['presentation', 'video', 'lesson', 'summary', 'flashcards', 'practical', 'assessment'], $parts());
        $practical = array_values(array_filter($items->availability($courseId, null, false), static fn(array $row): bool => ($row['part'] ?? '') === 'practical'))[0];
        self::assertStringContainsString('<p class="check"><strong>How to check:</strong> Water runs out', (string) $practical['content_source']);
        self::assertStringContainsString('<section class="answer">', (string) $practical['type_config']['answer_html']);
        $after = $items->item((int) $lesson['course_item_id']);
        self::assertStringNotContainsString('class="block practical"', (string) $after['content_source'], 'The lesson keeps everything else.');
        self::assertNull($restructurer->arrangement($courseId));
    }

    public function testAReadinessCheckBeforeTheModulesIsTheDiagnosticAndNotPartOfTheIntroduction(): void
    {
        $check = '<section class="diag" id="diagnostic"><details class="panel">'
            . '<summary class="panel-head"><span class="node"><span class="num">D</span></span>'
            . '<span class="m-titles"><span class="eyebrow">Diagnostic</span><span class="m-name">Readiness Check</span><small>Two questions</small></span><span class="chev">&#8250;</span></summary>'
            . '<div class="diag-inner"><p>This check is not scored.</p><div class="quiz" data-quiz="diag"></div></div></details></section>';
        $html = str_replace('  <div class="modules">', $check . "\n  <div class=\"modules\">", SpecificationExample::html(), $placed);
        self::assertSame(1, $placed);
        $html = str_replace('const QUIZ = {', 'const QUIZ = {"diag": [{"q": "Which particle is the largest?", "o": ["Clay", "Sand"], "a": 1, "p": 1, "u": ["m1"]}, {"q": "Does a pot need holes?", "o": ["Yes", "No"], "a": 0, "p": 1}],', $html);
        $file = (string) tempnam(sys_get_temp_dir(), 'diag');
        file_put_contents($file, $html);
        $analysis = $this->portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => 'readiness.html', 'tmp_name' => $file], $this->admin);
        self::assertSame([], array_values((array) $analysis['warnings']));
        $courseId = $this->portability->commitImport((string) $analysis['import_key'], 0, $this->admin);
        $introduction = (string) $this->container->get(CourseRepository::class)->findById($courseId)['introduction_html'];
        foreach (['Readiness Check', 'diag-inner', 'panel-head', 'data-quiz'] as $frame) {
            self::assertStringNotContainsString($frame, $introduction, 'The readiness check is not part of the introduction: ' . $frame);
        }
        self::assertStringContainsString('How this course works', $introduction);
        $diagnostic = array_values(array_filter($this->container->get(CourseItemService::class)->availability($courseId, null, false), static fn(array $row): bool => ($row['item_type'] ?? '') === 'diagnostic'));
        self::assertCount(1, $diagnostic, 'The readiness check is the course\'s diagnostic.');
        self::assertSame('Readiness Check', (string) $diagnostic[0]['item_title']);
    }

