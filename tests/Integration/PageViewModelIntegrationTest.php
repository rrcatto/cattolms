declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\View\ThemeManager;
use CattoLearning\View\ThemeRenderer;
use PHPUnit\Framework\TestCase;

final class PageViewModelIntegrationTest extends TestCase
{
    /**
     * @param array<string,mixed> $data
     * @return array<string,mixed>
     */
    private function model(string $page, array $data = []): array
    {
        $container = CliBootstrap::boot()['container'];
        /** @var ThemeRenderer $renderer */
        $renderer = $container->get(ThemeRenderer::class);
        /** @var ThemeManager $themes */
        $themes = $container->get(ThemeManager::class);

        return $renderer->viewModel($page, $data, $themes->activeTheme(), false);
    }

    public function testTheModelCarriesEverythingAThemeMayRead(): void
    {
        $model = $this->model('privacy');

        foreach (['app', 'platform', 'theme', 'page', 'user', 'navigation', 'footer_navigation',
                  'breadcrumbs', 'flash', 'sidebar', 'csrf', 'app_name', 'app_url', 'current_uri'] as $key) {
            self::assertArrayHasKey($key, $model, 'The view model must carry ' . $key . '.');
        }

        self::assertSame('content', $model['page']['type']);
        self::assertNotSame('', (string) $model['app_name']);
        self::assertNotSame('', (string) $model['theme']['name']);
        self::assertNotSame('', (string) $model['platform']['icon_sprite']);
        self::assertIsList($model['platform']['styles']);
        self::assertIsList($model['theme']['styles']);
    }

    /** Present and empty, so a theme can name one without guarding for it. */
    public function testEveryPageFamilyObjectIsAlwaysPresent(): void
    {
        $model = $this->model('privacy');

        foreach (['home','catalogue','course','auth','account','library','module','assessment',
                  'certificate','commerce','company','admin','error'] as $family) {
            self::assertArrayHasKey($family, $model);
            self::assertSame([], $model[$family], $family . ' must be empty on an unrelated page.');
        }
    }

    /** The family comes from the page name, and it is what selects the theme's optional wrapper. */
    public function testThePageFamilyIsDerivedFromThePageName(): void
    {
        self::assertSame('admin', $this->model('admin-control-centre')['page']['type']);
        self::assertSame('catalogue', $this->model('courses')['page']['type']);
        self::assertSame('auth', $this->model('login')['page']['type']);
        self::assertSame('content', $this->model('privacy')['page']['type']);
    }

    /** A signed-out reader gets the signed-out menu, and no administration entry appears in it. */
    public function testNavigationReflectsTheIdentityItWasBuiltFor(): void
    {
        $anonymous = $this->model('privacy');
        self::assertNotSame([], $anonymous['navigation']);
        foreach ($anonymous['navigation'] as $item) {
            self::assertNotSame('administration', $item['key'] ?? null, 'A signed-out menu must not offer Administration.');
        }

        $administrator = $this->model('privacy', [
            'is_authenticated' => true,
            'is_platform_admin' => true,
            'permissions' => ['PLATFORM.DASHBOARD.VIEW'],
        ]);
        $keys = array_map(static fn(array $item): string => (string) ($item['key'] ?? ''), $administrator['navigation']);
        self::assertContains('administration', $keys);
    }
}
