        $db = $container->get(Database::class);
        $portability = $container->get(CoursePortabilityService::class);
        $items = $container->get(CourseItemRepository::class);
        $fixture = new DevelopmentFixture($db);
        $suffix = $fixture->suffix();
        $temporary = (string) tempnam(sys_get_temp_dir(), 'arranged-course-');
        $key = null;
        try {
            $owner = $fixture->createUser('Arranged import ' . $suffix);
            $company = $fixture->createCompany($owner, 'Arranged author ' . $suffix, $suffix . '.example.test');
            $course = $fixture->createCourse($owner, $company, 'arranged-' . $suffix, 'Arranged course');
