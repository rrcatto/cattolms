    public function testThemeLifecycleCoversInspectActivateSwitchParentChildDeleteAndBrokenRejection(): void
    {
        $bootstrap = CliBootstrap::boot();
        $container = $bootstrap['container'];
        /** @var Database $db */
        $db = $container->get(Database::class);
        /** @var ThemeManager $liveThemes */
        $liveThemes = $container->get(ThemeManager::class);
        /** @var OptionRepository $options */
        $options = $container->get(OptionRepository::class);
        $fixture = new DevelopmentFixture($db);
        $suffix = $fixture->suffix();
        $actorId = $fixture->createUser('QA theme lifecycle actor ' . $suffix);
        $instanceRoot = sys_get_temp_dir() . '/catto-theme-e2e-instance-' . $suffix;
        $publicRoot = sys_get_temp_dir() . '/catto-theme-e2e-public-' . $suffix;
        $parentZip = sys_get_temp_dir() . '/catto-parent-' . $suffix . '.zip';
        $childZip = sys_get_temp_dir() . '/catto-child-' . $suffix . '.zip';
        $brokenZip = sys_get_temp_dir() . '/catto-broken-' . $suffix . '.zip';
        $parentName = 'QA Parent ' . $suffix;
        $parentSlug = 'qa-parent-' . $suffix;
        $childName = 'QA Child ' . $suffix;
        $childSlug = 'qa-child-' . $suffix;
        $originalActive = $liveThemes->activeTheme();

        try {
            mkdir($instanceRoot, 0775, true);
            mkdir($publicRoot, 0775, true);
            $manager = new ThemeManager(
                dirname(__DIR__, 2),
                $instanceRoot,
                $publicRoot,
                $options,
                $container->get(AuditRepository::class),
                $container->get(ThemeRegistryRepository::class)
            );

            $this->writeThemeZip($parentZip, $parentName, $parentSlug, '1.0.0', 'body{background:#111}');
            $parentInspection = $manager->stageImport($parentZip);
            self::assertSame('install', $parentInspection['install_action']);
            self::assertFalse((bool) $parentInspection['summary']['child']);
            $parentKey = $manager->importStaged((string) $parentInspection['token'], $actorId);
            $manager->activate($parentKey, $actorId);
            self::assertSame($parentKey, $manager->activeTheme());
            self::assertFileExists($publicRoot . '/themes/' . $parentKey . '/css/theme.css');

            $this->writeThemeZip(
                $childZip,
                $childName,
                $childSlug,
                '1.0.0',
                '.gn-child{border:1px solid gold}',
                ['name'=>$parentName,'version'=>'1.0.0'],
                false
            );
            $childInspection = $manager->stageImport($childZip);
            self::assertTrue((bool) $childInspection['summary']['child']);
            self::assertSame($parentName, $childInspection['summary']['parent_name']);
            $childKey = $manager->importStaged((string) $childInspection['token'], $actorId);
            $manager->activate($childKey, $actorId);
            self::assertSame($childKey, $manager->activeTheme());

            $registry = $container->get(ThemeRegistryRepository::class)->byInstallKey();
            self::assertArrayHasKey($parentKey, $registry);
            self::assertArrayHasKey($childKey, $registry);
            self::assertSame((int) $registry[$parentKey]['id'], (int) $registry[$childKey]['parent_theme_id']);

            $manager->activate($parentKey, $actorId);
            $manager->delete($childKey, $actorId);
            self::assertDirectoryDoesNotExist($instanceRoot . '/themes/' . $childKey);
            self::assertDirectoryDoesNotExist($publicRoot . '/themes/' . $childKey);

            $options->set('active_theme', $originalActive, $actorId);
            $manager->delete($parentKey, $actorId);
            self::assertDirectoryDoesNotExist($instanceRoot . '/themes/' . $parentKey);

            $this->writeBrokenThemeZip($brokenZip, 'QA Broken ' . $suffix, 'qa-broken-' . $suffix);
            try {
                $manager->stageImport($brokenZip);
                self::fail('A theme missing @platform.scripts must be rejected during inspection.');
            } catch (\RuntimeException $e) {
                self::assertStringContainsString('platform.scripts', $e->getMessage());
            }
        } finally {
            $options->set('active_theme', $originalActive, $actorId);
            $liveThemes->resyncRegistry();
            $fixture->cleanup();
            foreach ([$parentZip,$childZip,$brokenZip] as $path) @unlink($path);
            $this->removeDirectory($instanceRoot);
            $this->removeDirectory($publicRoot);
        }
    }

    /** @param array{name:string,version:string}|null $parent */
    private function writeThemeZip(string $path, string $name, string $slug, string $version, string $css, ?array $parent = null, bool $withBase = true): void
    {
        $manifest = [
            'format' => 'catto-learning-theme',
            'schema_version' => '4.0',
            'template_api' => '2.0',
            'theme' => [
                'name' => $name,
                'slug' => $slug,
                'version' => $version,
                'author' => 'QA',
                'description' => 'Same-version repair lifecycle test.',
                'created_at' => '2026-08-17T00:02:00+02:00',
            ],
            'parent' => $parent,
            'styles' => [],
            'scripts' => [],
            'external' => ['styles' => [], 'scripts' => []],
        ];

        $zip = new ZipArchive();
        self::assertTrue($zip->open($path, ZipArchive::CREATE | ZipArchive::OVERWRITE) === true);
        $zip->addFromString('theme.json', json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR));
        if ($withBase) {
            $zip->addFromString('base.html.twig', '<!doctype html><html><head>{% for style in platform.styles %}<link rel="stylesheet" href="{{ style }}">{% endfor %}</head><body>{% block page_content %}{% block page_body %}{% endblock %}{% endblock %}{% for script in platform.scripts %}<script src="{{ script }}"></script>{% endfor %}</body></html>');
        }
        $zip->addFromString('public/css/theme.css', $css);
        $zip->close();
    }


