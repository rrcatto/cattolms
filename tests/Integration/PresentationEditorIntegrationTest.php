declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Course\Catwalk\PresentationEditor;
use CattoLearning\Course\CourseItemService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\DevelopmentFixture;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class PresentationEditorIntegrationTest extends TestCase
{
    private Database $db;
    private CourseItemService $items;
    private PresentationEditor $editor;
    private int $owner;
    private int $deck;

    protected function setUp(): void
    {
        $container = CliBootstrap::boot()['container'];
        $this->db = $container->get(Database::class);
        $this->items = $container->get(CourseItemService::class);
        $this->editor = $container->get(PresentationEditor::class);
        $this->db->beginTransaction();
        $fixture = new DevelopmentFixture($this->db);
        $suffix = $fixture->suffix();
        $this->owner = $fixture->createUser('Presentation editor ' . $suffix);
        $company = $fixture->createCompany($this->owner, 'Presentation editor ' . $suffix, $suffix . '.example.test');
        $course = $fixture->createCourse($this->owner, $company, 'presentation-editor-' . $suffix, 'Presentation editor ' . $suffix);
        $this->deck = $this->items->createAttached($course, ['item_key' => 'editor-deck-' . $suffix, 'item_type' => 'slide_deck', 'title' => 'What you will learn', 'deck_kind' => 'intro', 'deck_theme' => 'light', 'slides' => [
            ['layout' => 'title', 'title' => 'Welcome', 'heading' => 'Good food starts below the surface', 'narration' => 'Welcome to the garden.'],
            ['layout' => 'points', 'title' => 'What you will learn', 'heading' => 'After this module you can', 'points' => "Test your soil\nMake compost"],
            ['layout' => 'check', 'title' => 'Quick question', 'question' => 'Which is a brown?', 'options' => "Peels\nDry leaves", 'answer' => '1', 'explanation' => 'Dry leaves are rich in carbon.'],
            ['layout' => 'next', 'title' => 'Up next', 'heading' => 'Now watch the video', 'text' => 'Watch for the balance of greens and browns.'],
        ]], $this->owner);
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) { $this->db->rollBack(); }
    }

    /** @return list<array<string,mixed>> */
    private function slides(): array
    {
        return PresentationEditor::deckOf($this->items->item($this->deck))['slides'];
    }

    /** @return list<string> */
    private function titles(): array
    {
        return array_map(static fn(array $slide): string => (string) $slide['title'], $this->slides());
    }

    public function testOneSlideIsSavedOnItsOwnAndARefusedSlideWritesNothing(): void
    {
        [$welcome, $points] = $this->slides();
        $this->editor->saveSlide($this->deck, (string) $welcome['id'], ['layout' => 'title', 'title' => 'Hello', 'heading' => 'Soil first'], $this->owner);
        $after = $this->slides();
        self::assertSame(['Hello', 'Soil first', 'Welcome to the garden.'], [$after[0]['title'], $after[0]['heading'], $after[0]['narration'] ?? null], 'The slide changes; its script stays.');
        self::assertSame($points, $after[1], 'The other slides are as they were.');
        self::assertSame((string) $welcome['id'], (string) $after[0]['id']);

        try {
            $this->editor->saveSlide($this->deck, (string) $points['id'], ['layout' => 'points', 'title' => 'Points', 'heading' => 'Only one point', 'points' => 'Just this'], $this->owner);
            self::fail('A slide that is not valid is refused.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString('Slide 2', $refused->getMessage());
        }
        self::assertSame($points, $this->slides()[1], 'Nothing was written.');
    }

    public function testSlidesAreAddedCopiedDeletedAndMoved(): void
    {
        $made = $this->editor->addSlide($this->deck, 1, ['layout' => 'statement', 'title' => 'The big idea', 'text' => 'Feed the soil.'], $this->owner);
        self::assertSame(['Welcome', 'The big idea', 'What you will learn', 'Quick question', 'Up next'], $this->titles());
        $copy = $this->editor->duplicate($this->deck, $made, $this->owner);
        self::assertSame('The big idea (copy)', $this->titles()[2]);
        self::assertNotSame($made, $copy);
        $this->editor->delete($this->deck, $copy, $this->owner);
        self::assertCount(5, $this->slides());

        $this->editor->step($this->deck, $made, 'down', $this->owner);
        self::assertSame(['Welcome', 'What you will learn', 'The big idea', 'Quick question', 'Up next'], $this->titles(), 'Move down.');
        $shown = array_map(static fn(array $slide): string => (string) $slide['id'], $this->slides());
        $this->editor->arrange($this->deck, $made, 0, $shown, $this->owner);
        self::assertSame('The big idea', $this->titles()[0], 'Dragged to the top.');
        try {
            $this->editor->arrange($this->deck, $made, 2, $shown, $this->owner);
            self::fail('An order changed since the page loaded is refused.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame(PresentationEditor::STALE, $refused->getMessage());
        }
        try {
            $last = (string) $this->slides()[4]['id'];
            $this->editor->step($this->deck, $last, 'up', $this->owner);
            self::fail('Up next stays the last slide.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString('comes last', $refused->getMessage());
        }
    }

    public function testANewPresentationAsksOnlyItsPurposeAndLookAndStartsWithATitleSlide(): void
    {
        $suffix = (string) $this->db->fetchOne('SELECT substr(md5(random()::text), 1, 8)');
        $opening = $this->items->create(['item_key' => 'editor-new-' . $suffix, 'item_type' => 'slide_deck', 'title' => 'Soil and compost', 'deck_kind' => 'intro', 'deck_theme' => 'light'], $this->owner);
        $deck = PresentationEditor::deckOf($this->items->item($opening));
        self::assertSame([['title', 'Soil and compost']], array_map(static fn(array $slide): array => [$slide['layout'], $slide['heading']], $deck['slides']), 'A title slide showing its title.');
        $trailer = $this->items->create(['item_key' => 'editor-trailer-' . $suffix, 'item_type' => 'slide_deck', 'title' => 'Grow your own food', 'deck_kind' => 'trailer', 'deck_theme' => 'dark'], $this->owner);
        $deck = PresentationEditor::deckOf($this->items->item($trailer));
        self::assertSame(['trailer', 'dark', ['title', 'cta']], [$deck['kind'], $deck['theme'], array_column($deck['slides'], 'layout')], 'A trailer also ends with a call to action.');
    }

    public function testAPresentationKeepsOneSlideAndTheScriptAndDetailsAreSavedApart(): void
    {
        $slides = $this->slides();
        $this->editor->saveScript($this->deck, (string) $slides[1]['id'], "  Two things  \r\nto learn. ", $this->owner);
        self::assertSame("Two things  \nto learn.", $this->slides()[1]['narration']);
        $this->editor->saveScript($this->deck, (string) $slides[1]['id'], '', $this->owner);
        self::assertArrayNotHasKey('narration', $this->slides()[1], 'An empty script is no script.');

        $this->editor->saveDetails($this->deck, ['title' => 'Before you plant', 'description_html' => 'Module 1: Soil and compost', 'deck_kind' => 'overview', 'deck_theme' => 'dark', 'name' => ''], $this->owner);
        $item = $this->items->item($this->deck);
        self::assertSame(['Before you plant', 'Module 1: Soil and compost', 'overview', 'dark'], [$item['title'], $item['description_html'], $item['type_config']['kind'], $item['type_config']['theme']]);
        self::assertSame($slides[0], $this->slides()[0], 'The slides are not changed.');

        foreach (array_slice($slides, 1) as $slide) { $this->editor->delete($this->deck, (string) $slide['id'], $this->owner); }
        try {
            $this->editor->delete($this->deck, (string) $slides[0]['id'], $this->owner);
            self::fail('The last slide cannot be deleted.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString('at least one slide', $refused->getMessage());
        }
    }
}
