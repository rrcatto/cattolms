    /**
     * Runs one deliberately invalid statement and returns PostgreSQL's message, or null if it
     * was accepted.
     *
     * Wrapped in a savepoint-free transaction that is always rolled back: the statement must not
     * survive whether it succeeded or failed, and a success here is a failure of the test.
     */
    /** @param array<string,mixed> $bindings */
    private function rejectionFor(string $sql, array $bindings): ?string
    {
        $this->db->begin();
        try {
            $this->db->exec($sql, $bindings);
            $this->db->rollback();

            return null;
        } catch (Throwable $exception) {
            $this->db->rollback();

            return $exception->getMessage();
        }
    }

