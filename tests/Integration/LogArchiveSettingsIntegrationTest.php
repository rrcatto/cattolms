declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Maintenance\LogArchive;
use CattoLearning\Support\Duration;
use CattoLearning\Tests\Support\IntegrationContainer;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class LogArchiveSettingsIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testSettingsOverrideHowLongArchivesAreKeptAndResetReturnsToEnv(): void
    {
        $archive = IntegrationContainer::get()->get(LogArchive::class);
        $archive->resetKeep();
        self::assertSame('environment', $archive->source());
        self::assertSame($archive->environmentKeep(), $archive->keep());

        self::assertSame('1w', $archive->saveKeep(' 1w '));
        self::assertSame(['database', '1w'], [$archive->source(), $archive->keep()]);
        foreach (['12h' => 'Keep the log archives for at least a day (1d).', 'a month' => Duration::HOW] as $typed => $refusal) {
            try {
                $archive->saveKeep($typed);
                self::fail('Accepted: ' . $typed);
            } catch (InvalidArgumentException $refused) {
                self::assertSame($refusal, $refused->getMessage());
            }
        }
        self::assertSame('1w', $archive->keep(), 'A refused period changes nothing.');

        $archive->resetKeep();
        self::assertSame(['environment', $archive->environmentKeep()], [$archive->source(), $archive->keep()]);
        self::assertStringEndsWith('/storage/logs/application.log', $archive->status()['log']);
        self::assertStringEndsWith('/storage/logs/archive', $archive->status()['folder']);
    }
}
