declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Auth\CurrentUser;
use CattoLearning\Auth\PermissionCatalog;
use CattoLearning\Http\Controller\AdminController;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Support\Uuid;
use CattoLearning\Tests\Support\DevelopmentFixture;
use CattoLearning\Tests\Support\InProcessPage;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoPHP\Foundation\Duration;
use CattoPHP\Scheduler\LogArchive;
use CattoPHP\Settings\Settings;
use PHPUnit\Framework\TestCase;

final class LogArchiveSettingsIntegrationTest extends TestCase
{
    private Database $db;

    private CurrentUser $admin;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
        $fixture = new DevelopmentFixture($this->db);
        $id = $fixture->createUser('Log archive administrator', 'log-archive-' . $fixture->suffix() . '@example.test');
        $this->admin = new CurrentUser($id, Uuid::v4(), 'log-archive@example.test', 'Log archive administrator', ['ADMIN'], (new PermissionCatalog())->keys(), Uuid::v4());
        $_SESSION['csrf'] = str_repeat('l', 64);
    }

    protected function tearDown(): void
    {
        IntegrationContainer::get()->get(Settings::class)->refresh();
        if ($this->db->isTransactionActive()) $this->db->rollBack();
        unset($_SESSION['csrf'], $_SESSION['flash']);
    }

    public function testSettingsOverrideHowLongArchivesAreKeptAndResetReturnsToEnv(): void
    {
        $container = IntegrationContainer::get();
        $archive = $container->get(LogArchive::class);
        $settings = $container->get(Settings::class);
        $environment = $settings->envValue(LogArchive::KEEP);
        $environment = Duration::isValid($environment) ? $environment : LogArchive::DEFAULT_KEEP;
        $settings->reset(LogArchive::KEEP);
        self::assertFalse($settings->isOverridden(LogArchive::KEEP));
        self::assertSame($environment, $archive->keep()->text);

        self::assertSame('Log archives are now kept for 1 week.', $this->post('saveLogArchives', ' 1w '));
        self::assertTrue($settings->isOverridden(LogArchive::KEEP));
        self::assertSame('1w', $archive->keep()->text);
        foreach (['12h' => 'Keep the log archives for at least a day (1d).', 'a month' => Duration::HOW] as $typed => $refusal) {
            self::assertSame($refusal, $this->post('saveLogArchives', $typed), 'Refused in the words Settings > Maintenance always used.');
        }
        self::assertSame('1w', $archive->keep()->text, 'A refused period changes nothing.');

        self::assertSame('Log archives are kept as LOG_ARCHIVES_KEPT_FOR in .env says: ' . Duration::parse($environment)->words() . '.', $this->post('resetLogArchives'));
        self::assertFalse($settings->isOverridden(LogArchive::KEEP));
        self::assertSame($environment, $archive->keep()->text);
        self::assertStringEndsWith('/storage/logs/application.log', $archive->status()['log']);
        self::assertStringEndsWith('/storage/logs/archive', $archive->status()['folder']);
    }

    /** Sends Settings > Maintenance's form to one of its routes and answers with the message the page then shows. */
    private function post(string $method, ?string $keep = null): string
    {
        unset($_SESSION['flash']);
        InProcessPage::run($this->admin, AdminController::class, $method, [], ['csrf' => $_SESSION['csrf']] + ($keep === null ? [] : ['keep' => $keep]));
        $flash = (array) ($_SESSION['flash'] ?? []);
        return (string) (end($flash)['message'] ?? '');
    }
}
