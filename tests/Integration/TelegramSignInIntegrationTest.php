        $this->db->executeStatement("UPDATE users SET status = 'deactivated' WHERE id = :id", ['id' => $friend['id']]);
        $this->assertRefused(fn() => $auth->consumeTelegramCode($row, $code), 'This email is not registered. Please complete registration first.', 'Deactivated meanwhile.');
        self::assertSame(0, $this->sessions($friend['id']));

