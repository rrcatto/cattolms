        self::assertNull($auth->requestTelegramLogin('listed_friend'));
        $this->messenger->deliverHeld();
        self::assertSame([], $this->telegram->sent, 'None of them was sent anything.');

        // A message already sent when the account stops: the code stops as the link would.
