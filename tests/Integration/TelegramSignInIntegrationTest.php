    /** @return array{id:int,email:string} someone with an account, connected to Telegram when a username or chat is given */
    private function person(string $name, ?string $username = null, ?string $chat = null): array
    {
        $email = strtolower(str_replace(' ', '.', $name)) . '-' . $this->fixture->suffix() . '@inbox.test';
        $id = $this->fixture->createUser($name, $email);
        [$first, $last] = explode(' ', $name, 2);
        $this->db->executeStatement('UPDATE users SET first_name = :first, last_name = :last WHERE id = :id', ['first' => $first, 'last' => $last, 'id' => $id]);
        if ($username !== null || $chat !== null) $this->accounts->connect($id, $chat ?? (string) random_int(100000, 999999), $username);

        return ['id' => $id, 'email' => $email];
    }

