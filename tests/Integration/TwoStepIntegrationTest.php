    public function testTheFirstCodeTurnsItOnAndACodeUsedOnceNeverWorksAgain(): void
    {
        $who = $this->person('Thandi Mokoena')['id'];
        $secret = OneTimeCode::newSecret();
        self::assertNull($this->twoStep->turnOn($who, $secret, '000000' === $this->code($secret) ? '111111' : '000000'), 'A wrong first code keeps nothing.');
        self::assertFalse($this->twoStep->isOn($who));
        $codes = $this->twoStep->turnOn($who, $secret, $this->code($secret));
        self::assertCount(8, $codes ?? []);
        self::assertTrue($this->twoStep->isOn($who));
        self::assertNull($this->twoStep->confirm($who, $this->code($secret)), 'The code that turned it on is used.');
        $this->clock->sleep(30);
        $code = $this->code($secret);
        self::assertSame('app', $this->twoStep->confirm($who, $code));
        self::assertNull($this->twoStep->confirm($who, $code), 'Replaying a code fails.');
        $stored = (string) $this->db->fetchOne('SELECT secret_encrypted FROM user_two_step WHERE user_id = :user', ['user' => $who]);
        self::assertStringNotContainsString($secret, $stored, 'The key is kept encrypted.');
        self::assertSame(['on' => true, 'left' => 8], array_intersect_key($this->twoStep->state($who), ['on' => 1, 'left' => 1]));
    }

    public function testARecoveryCodeWorksOnceAndNewOnesReplaceThem(): void
    {
        $who = $this->person('Thandi Mokoena')['id'];
        [$secret, $codes] = $this->turnOn($who);
        self::assertSame('recovery', $this->twoStep->confirm($who, strtolower(str_replace('-', ' ', $codes[0]))), 'Small letters and a space instead of the hyphen.');
        self::assertNull($this->twoStep->confirm($who, $codes[0]), 'Once only.');
        self::assertSame(7, $this->twoStep->state($who)['left']);
        $hashes = implode(' ', $this->db->fetchFirstColumn('SELECT code_hash FROM user_two_step_recovery WHERE user_id = :user', ['user' => $who]));
        foreach ($codes as $code) self::assertStringNotContainsString(str_replace('-', '', $code), str_replace('-', '', $hashes), 'Only hashes are kept.');
        try {
            $this->twoStep->newRecoveryCodes($who, '123');
            self::fail('New codes without a current code.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame(TwoStep::WRONG, $refused->getMessage());
        }
        $this->clock->sleep(30);
        $fresh = $this->twoStep->newRecoveryCodes($who, $this->code($secret));
        self::assertCount(8, $fresh);
        self::assertNull($this->twoStep->confirm($who, $codes[1]), 'The old ones stop working.');
        self::assertSame('recovery', $this->twoStep->confirm($who, $fresh[0]));
    }

    public function testNoSessionBeforeTheSecondStepByEmail(): void
    {
        $person = $this->person('Thandi Mokoena');
        [$secret] = $this->turnOn($person['id']);
        $auth = $this->auth();
        $auth->requestLogin($person['email'], '/account/certificates');
        self::assertSame(PendingSignIn::PATH, $auth->consumeLogin($this->linkToken()));
        self::assertSame(0, $this->sessions($person['id']), 'No session yet.');
        self::assertSame(0, $this->logins($person['id']), 'And no sign-in counted.');
        self::assertNull($auth->currentUser());
        $this->assertRefused(fn() => $auth->passTwoStep('000000' === $this->code($secret) ? '111111' : '000000'), TwoStep::WRONG);
        self::assertSame(0, $this->sessions($person['id']));
        self::assertSame('/account/certificates', $auth->passTwoStep($this->code($secret)));
        self::assertSame(1, $this->sessions($person['id']));
        self::assertNull($auth->pendingSignIn(), 'The waiting sign-in is gone.');
        $login = $this->db->fetchAssociative("SELECT metadata->>'via' AS via, metadata->>'two_step' AS two_step FROM audit_log WHERE event_key = 'auth.login' AND user_id = :user", ['user' => $person['id']]);
        self::assertSame(['via' => 'email', 'two_step' => 'app'], $login);
    }

    public function testNoSessionBeforeTheSecondStepByTelegramAndARecoveryCodeDoes(): void
    {
        $person = $this->person('Thandi Mokoena');
        [, $codes] = $this->turnOn($person['id']);
        $telegram = new TelegramStandIn();
        $container = IntegrationContainer::get();
        $settings = $container->get(OwnerMessageSettings::class);
        $settings->forget();
        $settings->setKey(TelegramStandIn::KEY, TelegramStandIn::BOT, $this->admin);
        $settings->setSignIn(true, $this->admin);
        $messenger = new TelegramMessenger($settings, $container->get(OwnerMessageRepository::class), new TelegramClient($telegram->client()));
        $container->get(TelegramAccountRepository::class)->connect($person['id'], '5559001', 'thandi_m');
        $auth = $this->auth($messenger);
        $row = (int) $auth->requestTelegramLogin('thandi_m');
        $messenger->deliverHeld();
        preg_match('/Your code is\n(\d{6})\n/', $telegram->textsTo('5559001')[0] ?? '', $code);
        self::assertSame(PendingSignIn::PATH, $auth->consumeTelegramCode($row, $code[1] ?? ''));
        self::assertSame(0, $this->sessions($person['id']));
        self::assertSame('/account/courses', $auth->passTwoStep($codes[3]), 'A recovery code does the same job.');
        self::assertSame(1, $this->sessions($person['id']));
        self::assertSame('recovery', $this->db->fetchOne("SELECT metadata->>'two_step' FROM audit_log WHERE event_key = 'auth.login' AND user_id = :user", ['user' => $person['id']]));
    }

    public function testFiveWrongCodesOrTenMinutesEndTheSignIn(): void
    {
        $person = $this->person('Thandi Mokoena');
        [$secret] = $this->turnOn($person['id']);
        $auth = $this->auth();
        $auth->requestLogin($person['email']);
        $auth->consumeLogin($this->linkToken());
        for ($try = 1; $try <= 4; $try++) $this->assertRefused(fn() => $auth->passTwoStep('ABCD-2345'), TwoStep::WRONG);
        $this->assertRefused(fn() => $auth->passTwoStep('ABCD-2345'), AuthService::PENDING_ENDED);
        $this->assertRefused(fn() => $auth->passTwoStep($this->code($secret)), AuthService::PENDING_GONE);
        self::assertSame(0, $this->sessions($person['id']), 'They start again.');

        $this->clock->sleep(60);
        $auth->requestLogin($person['email']);
        $auth->consumeLogin($this->linkToken());
        $this->clock->sleep(PendingSignIn::TTL + 1);
        $this->assertRefused(fn() => $auth->passTwoStep($this->code($secret)), AuthService::PENDING_GONE);
        self::assertSame(0, $this->sessions($person['id']));
    }

    public function testAdministratorsMustSetItUpBeforeTheyGetInAndLearnersMayChoose(): void
    {
        $this->policy->save(TwoStepPolicy::ADMINS);
        $learner = $this->person('Sipho Dlamini');
        $auth = $this->auth();
        $auth->requestLogin($learner['email']);
        self::assertSame('/account/courses', $auth->consumeLogin($this->linkToken()), 'A learner may choose: straight in.');
        $_SESSION = [];
        $adminEmail = (string) $this->db->fetchOne('SELECT email FROM user_emails WHERE user_id = :user', ['user' => $this->admin]);
        $auth->requestLogin($adminEmail);
        self::assertSame(PendingSignIn::SETUP_PATH, $auth->consumeLogin($this->linkToken()), 'An administrator sets it up first.');
        self::assertSame(0, $this->sessions($this->admin));
        $this->assertRefused(fn() => $auth->passTwoStep('123456'), AuthService::PENDING_GONE);
        $setUp = $auth->twoStepSetUpAtSignIn();
        self::assertStringStartsWith('<svg ', $setUp['qr']);
        $secret = str_replace(' ', '', $setUp['key']);
        self::assertSame($setUp['key'], $auth->twoStepSetUpAtSignIn()['key'], 'The same key until it is confirmed.');
        $this->assertRefused(fn() => $auth->finishTwoStepAtSignIn(), AuthService::PENDING_GONE);
        self::assertFalse($auth->confirmTwoStepAtSignIn('000000' === $this->code($secret) ? '111111' : '000000'));
        self::assertTrue($auth->confirmTwoStepAtSignIn($this->code($secret)));
        self::assertCount(8, $auth->twoStepSetUpAtSignIn()['codes'], 'The recovery codes, shown until they are kept.');
        self::assertSame(0, $this->sessions($this->admin), 'Still no session.');
        self::assertSame('/account/courses', $auth->finishTwoStepAtSignIn());
        self::assertSame(1, $this->sessions($this->admin));
        self::assertTrue($this->twoStep->isOn($this->admin));
        self::assertSame([], (new PendingSignIn(IntegrationContainer::get()->get(SecretCipher::class), $this->clock))->recoveryCodes('sign_in'), 'Forgotten once kept.');
    }

