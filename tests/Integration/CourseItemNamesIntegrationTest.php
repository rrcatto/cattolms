declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Course\CourseItemRenderer;
use CattoLearning\Course\CourseItemRepository;
use CattoLearning\Course\CourseItemService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\DevelopmentFixture;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class CourseItemNamesIntegrationTest extends TestCase
{
    private Database $db;
    private CourseItemService $items;
    private string $suffix;
    private string $code;
    private int $owner;
    private int $course;
    private \Psr\Container\ContainerInterface $container;

    protected function setUp(): void
    {
        $this->container = CliBootstrap::boot()['container'];
        $this->db = $this->container->get(Database::class);
        $this->items = $this->container->get(CourseItemService::class);
        $this->db->beginTransaction();
        $fixture = new DevelopmentFixture($this->db);
        $this->suffix = $fixture->suffix();
        $this->owner = $fixture->createUser('Item names author ' . $this->suffix);
        $company = $fixture->createCompany($this->owner, 'Item names ' . $this->suffix, $this->suffix . '.example.test');
        $this->course = $fixture->createCourse($this->owner, $company, 'item-names-' . $this->suffix, 'Item names ' . $this->suffix);
        $this->code = 'NMS-' . strtoupper(substr(preg_replace('/[^a-z0-9]/i', '', $this->suffix) ?? '', 0, 6));
        $this->db->executeStatement('UPDATE courses SET code = :code WHERE id = :id', ['code' => $this->code, 'id' => $this->course]);
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) { $this->db->rollBack(); }
    }

    /** @return array<string,mixed> */
    private function deck(string $key, string $title = 'What you will learn'): array
    {
        return ['item_key' => $key, 'item_type' => 'slide_deck', 'title' => $title, 'deck_kind' => 'intro', 'deck_theme' => 'light', 'slides' => [
            ['layout' => 'title', 'title' => 'Welcome', 'heading' => 'Good food starts below the surface'],
            ['layout' => 'next', 'title' => 'Up next', 'heading' => 'Now watch the video', 'text' => 'Watch for the balance of greens and browns.'],
        ]];
    }

    private function itemName(int $id): string
    {
        return (string) $this->items->item($id)['name'];
    }

    public function testAnItemLeftUnnamedIsNamedAfterItsPlaceAndNoNameIsUsedTwice(): void
    {
        $module = $this->items->addSection($this->course, ['title' => 'Soil and compost', 'numbered' => '1'], $this->owner);
        $in = ['parent_node_id' => (string) $module];
        $first = $this->items->createAttached($this->course, $in + $this->deck('names-deck-' . $this->suffix), $this->owner);
        self::assertSame($this->code . ' Module 1 Presentation', $this->itemName($first));
        $second = $this->items->createAttached($this->course, $in + $this->deck('names-deck-two-' . $this->suffix), $this->owner);
        self::assertSame($this->code . ' Module 1 Presentation 2', $this->itemName($second), 'The same place twice: the second is numbered.');

        try {
            $this->items->createAttached($this->course, $in + ['name' => strtolower($this->code . ' module 1 presentation')] + $this->deck('names-taken-' . $this->suffix), $this->owner);
            self::fail('A name another item has, in any case, is refused.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString('is already named', $refused->getMessage());
        }

        $video = $this->items->createAttached($this->course, $in + ['name' => 'Compost explained ' . $this->suffix, 'item_key' => 'names-video-' . $this->suffix, 'item_type' => 'youtube', 'title' => 'Compost explained', 'youtube_id' => 'abcdefghijk'], $this->owner);
        self::assertSame('Compost explained ' . $this->suffix, $this->itemName($video), 'A typed name is kept.');
        $this->items->update($video, ['name' => ''] + $this->items->item($video), $this->owner);
        self::assertSame($this->code . ' Module 1 Video', $this->itemName($video), 'Emptied, it is named after its place.');

        $found = $this->container->get(CourseItemRepository::class)->items($this->code . ' Module 1 V');
        self::assertSame([$video], array_map(static fn(array $row): int => (int) $row['id'], $found), 'The Library finds an item by its name.');

        $copy = $this->items->saveAs($first, ['item_key' => 'names-copy-' . $this->suffix, 'title' => 'Soil opening ' . $this->suffix, 'name' => $this->itemName($first)], $this->owner);
        self::assertSame('Soil opening ' . $this->suffix, $this->itemName($copy), 'A copy placed nowhere is named after its new title.');

        $outside = $this->items->createAttached($this->course, $this->deck('names-outside-' . $this->suffix, 'Course preview'), $this->owner);
        self::assertSame($this->code . ' Course preview', $this->itemName($outside), 'Outside the modules, the course code and the title.');
    }

    public function testAPresentationsDescriptionIsOneLineInItsPlayersTopBar(): void
    {
        $deck = $this->items->createAttached($this->course, ['description_html' => "<p>The  soil &amp; what\nfeeds it</p>"] + $this->deck('names-described-' . $this->suffix), $this->owner);
        self::assertSame('The soil & what feeds it', $this->items->item($deck)['description_html'], 'Plain text on one line.');
        try {
            $this->items->update($deck, ['description_html' => str_repeat('a', 101)] + $this->items->item($deck), $this->owner);
            self::fail('A description over 100 characters is refused.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString('up to 100 characters', $refused->getMessage());
        }

        $render = function (int $id): string {
            $row = array_values(array_filter($this->items->availability($this->course, null, false), static fn(array $row): bool => (int) ($row['course_item_id'] ?? 0) === $id))[0];
            return $this->container->get(CourseItemRenderer::class)->render($row, 'item-names-' . $this->suffix, (int) $row['id']);
        };
        $html = $render($deck);
        self::assertStringContainsString('data-cw-title="The soil &amp; what feeds it"', $html, 'The top bar shows the description, not the title again.');
        self::assertStringNotContainsString('cl-course-item-description', $html, 'Nor is it printed above the player.');

        $plain = $this->items->createAttached($this->course, $this->deck('names-plain-' . $this->suffix, 'Before you start'), $this->owner);
        self::assertStringContainsString('data-cw-title="Before you start"', $render($plain), 'Without a description the bar shows the title.');
    }
}
