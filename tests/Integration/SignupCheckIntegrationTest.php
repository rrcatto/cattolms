    /**
     * Registers someone the whole way: the form, then the link in the email.
     *
     * @return array{status:string,next:string,attempt:array<string,mixed>,mail:array<string,mixed>}
     */
    private function register(string $mode, NetworkFacts $network, string $name, ?string $email = null, ?SignInRestriction $restriction = null): array
    {
        $email ??= $name . '-' . $this->fixture->suffix() . '@example.test';
        $this->emails[] = $email;
        $mailer = new FakeMailer();
        $auth = $this->auth($mode, $mailer, $network, $restriction);
        $auth->requestRegistration($this->form($email));
        $mail = $mailer->messages[0] ?? [];
        parse_str((string) parse_url((string) ($mail['url'] ?? ''), PHP_URL_QUERY), $query);
        $next = $auth->consumeRegistration((string) ($query['token'] ?? ''));
        $userId = (int) $this->db->fetchOne('SELECT user_id FROM user_emails WHERE email = :email', ['email' => $email]);
        $this->fixture->rememberUser($userId);
        $this->fixture->rememberEmail($email);
        $attempt = $this->container->get(SignupAttemptRepository::class)->forUser($userId) ?? [];

        return ['status' => (string) $this->db->fetchOne('SELECT status FROM users WHERE id = :id', ['id' => $userId]), 'next' => $next, 'attempt' => $attempt, 'mail' => $mail];
    }

