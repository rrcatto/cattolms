declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Tests\Support\RouteTable;
use PHPUnit\Framework\TestCase;

final class ContainerResolutionTest extends TestCase
{
    public function testEveryRoutedControllerResolvesFromTheContainer(): void
    {
        $container = IntegrationContainer::get();

        $classes = array_values(array_unique(array_map(
            static fn(array $route): string => $route['class'],
            RouteTable::all()
        )));
        self::assertGreaterThan(15, count($classes), 'Almost no controllers were found; the scan is wrong.');

        foreach ($classes as $class) {
            self::assertTrue($container->has($class), $class . ' is routed but is not a service.');
            self::assertInstanceOf($class, $container->get($class), $class . ' could not be constructed.');
        }
    }
}
