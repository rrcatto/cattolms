Description:
Every controller the router can reach resolves from the container.

A controller that is not a service, or that asks for something the container cannot build, is a 500
with no route name in it - the least informative failure the platform produces, and one that only
appears when somebody visits the page. Resolving every one of them here turns that into a build
failure with the class named.

It reads the controllers from the route attributes rather than from a list, so a controller added
tomorrow is covered without this file being touched. A list would have to be remembered, and the
one nobody remembered is exactly the one that would break.

The previous version of this test verified that Fat-Free resolved controllers lazily through its
native PSR-11 support - that registering a route did not construct its controller, and that
dispatching asked the container exactly once. Symfony's container does that by construction, and
Fat-Free is gone, so what is left worth asserting is that every controller can be built at all.

