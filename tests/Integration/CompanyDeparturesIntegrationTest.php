final class CompanyDeparturesIntegrationTest extends TestCase
{
    private Database $db;
    private FakeMailer $mailer;
    private CompanyDepartures $departures;
    private IntegrationDataFixture $fixture;
    private int $company = 0;
    private int $administrator = 0;
    private string $domain = '';

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
        $container = IntegrationContainer::get();
        $this->mailer = new FakeMailer();
        $this->departures = new CompanyDepartures(
            $container->get(TransactionManager::class), $container->get(CompanyDepartureRepository::class), $container->get(CompanyRepository::class),
            $container->get(UserRepository::class), $container->get(RoleRepository::class), $container->get(AuthSessionRepository::class),
            $container->get(LoginTokenRepository::class), $container->get(AuditRepository::class), $this->mailer,
            $container->get(RuntimeSettings::class), $container->get(CompanyService::class)
        );
        $this->fixture = new IntegrationDataFixture($this->db);
        $this->domain = 'departures-' . $this->fixture->suffix() . '.test';
        $this->administrator = $this->fixture->createUser('Departures Admin', 'admin@' . $this->domain);
        $this->company = $this->fixture->createCompany($this->administrator, 'Departures Company', $this->domain, $this->administrator);
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testSomeoneWhoStartedNothingIsDeleted(): void
    {
        $staff = $this->staff('idle');
        $this->enrol($staff, 'assigned');

        self::assertSame('delete', $this->departures->assess($this->administrator, $this->company, $staff)['action']);
        self::assertStringContainsString('was deleted', $this->departures->delete($this->administrator, $this->company, $staff));
        self::assertFalse($this->db->fetchOne('SELECT 1 FROM users WHERE id = :u', ['u' => $staff]), 'Gone, with the course they never started.');
    }

    public function testSomeoneWhoCompletedACourseIsNeverDeleted(): void
    {
        $staff = $this->staff('done');
        $this->enrol($staff, 'completed');

        $assessment = $this->departures->assess($this->administrator, $this->company, $staff);
        self::assertSame('refused', $assessment['action']);
        $this->expectExceptionMessage('has completed a course');
        $this->departures->delete($this->administrator, $this->company, $staff);
    }

    public function testSomeoneBusyIsAskedFirstThenDeactivatedWithEverythingKeptAndRestored(): void
    {
        $staff = $this->staff('busy');
        $enrolment = $this->enrol($staff, 'active');

        self::assertStringContainsString('we have emailed them', $this->departures->delete($this->administrator, $this->company, $staff));
        $asked = $this->mailer->messages[array_key_last($this->mailer->messages)];
        self::assertSame('busy@' . $this->domain, $asked['email']);
        self::assertStringContainsString('/leaving/', (string) $asked['body']);
        self::assertSame('waiting', $this->departures->assess($this->administrator, $this->company, $staff)['action'], 'Not before the 3 days are over.');

        $this->db->executeStatement("UPDATE company_departures SET answer_by = NOW() - INTERVAL '1 minute' WHERE user_id = :u", ['u' => $staff]);
        self::assertStringContainsString('deactivated', $this->departures->delete($this->administrator, $this->company, $staff));
        self::assertSame('deactivated', $this->db->fetchOne('SELECT status FROM users WHERE id = :u', ['u' => $staff]));
        self::assertSame('inactive', $this->db->fetchOne('SELECT status FROM company_users WHERE user_id = :u', ['u' => $staff]), 'Out of the company.');
        self::assertSame('active', $this->db->fetchOne('SELECT status FROM course_enrolments WHERE id = :e', ['e' => $enrolment]), 'Everything kept.');

        $this->departures->restore($this->administrator, $staff, 'busy-private-' . $this->fixture->suffix() . '@example.test');
        self::assertSame('active', $this->db->fetchOne('SELECT status FROM users WHERE id = :u', ['u' => $staff]));
        self::assertSame('busy-private-' . $this->fixture->suffix() . '@example.test', $this->db->fetchOne('SELECT email FROM user_emails WHERE user_id = :u AND is_primary', ['u' => $staff]));
        self::assertSame('active', $this->db->fetchOne('SELECT status FROM course_enrolments WHERE id = :e', ['e' => $enrolment]), 'They continue their course.');
    }

    public function testKeepingTheAccountAsAPrivateOneKeepsEveryCourse(): void
    {
        $staff = $this->staff('leaver');
        $enrolment = $this->enrol($staff, 'active');
        $this->departures->delete($this->administrator, $this->company, $staff);
        $link = $this->token((string) $this->mailer->messages[array_key_last($this->mailer->messages)]['body'], '#/leaving/([A-Za-z0-9_-]+)#');

        try {
            $this->departures->choosePrivate($link, 'leaver2@' . $this->domain);
            self::fail('Never an address at the employer\'s domain.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString($this->domain, $refused->getMessage());
        }
        $private = 'leaver-' . $this->fixture->suffix() . '@example.test';
        $this->departures->choosePrivate($link, $private);
        $confirm = $this->mailer->messages[array_key_last($this->mailer->messages)];
        self::assertSame($private, $confirm['email'], 'The private address is confirmed from its own inbox.');
        self::assertSame($private, $this->departures->confirmPrivate($this->token((string) $confirm['body'], '#token=([A-Za-z0-9_-]+)#')));

        self::assertSame($private, $this->db->fetchOne('SELECT email FROM user_emails WHERE user_id = :u AND is_primary', ['u' => $staff]));
        self::assertSame(0, (int) $this->db->fetchOne("SELECT COUNT(*) FROM user_emails WHERE user_id = :u AND email LIKE :d", ['u' => $staff, 'd' => '%@' . $this->domain]), 'No address at the employer\'s domain.');
        self::assertSame('inactive', $this->db->fetchOne('SELECT status FROM company_users WHERE user_id = :u', ['u' => $staff]));
        self::assertSame('active', $this->db->fetchOne('SELECT status FROM users WHERE id = :u', ['u' => $staff]));
        self::assertSame('active', $this->db->fetchOne('SELECT status FROM course_enrolments WHERE id = :e', ['e' => $enrolment]), 'She keeps her course.');
    }

    public function testADeletedCompanyIsHiddenAndItsStaffAreAskedToGoPrivate(): void
    {
        $staff = $this->staff('closing');
        try {
            $this->departures->deleteCompany($this->administrator, $this->company, 'Not its name');
            self::fail('Typing the name confirms it.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString('name', $refused->getMessage());
        }
        $before = count($this->mailer->messages);
        self::assertSame(2, $this->departures->deleteCompany($this->administrator, $this->company, 'departures company'));
        self::assertSame(['deleted'], [$this->db->fetchOne('SELECT status FROM companies WHERE id = :c', ['c' => $this->company])]);
        self::assertNotFalse($this->db->fetchOne('SELECT deleted_at FROM companies WHERE id = :c', ['c' => $this->company]), 'Kept, with when.');
        foreach ([$this->administrator, $staff] as $who) self::assertSame('deactivated', $this->db->fetchOne('SELECT status FROM users WHERE id = :u', ['u' => $who]));
        self::assertCount($before + 2, $this->mailer->messages, 'Each staff member, its administrator too, is emailed.');

        // They can only keep their account as a private one, never delete it from the link.
        $link = $this->token((string) $this->mailer->messages[array_key_last($this->mailer->messages)]['body'], '#/leaving/([A-Za-z0-9_-]+)#');
        try {
            $this->departures->chooseDelete($link);
            self::fail('A deleted company\'s staff keep their account or wait.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame(CompanyDepartures::EXPIRED, $refused->getMessage());
        }
        $private = 'closing-' . $this->fixture->suffix() . '@example.test';
        $this->departures->choosePrivate($link, $private);
        $this->departures->confirmPrivate($this->token((string) $this->mailer->messages[array_key_last($this->mailer->messages)]['body'], '#token=([A-Za-z0-9_-]+)#'));
        self::assertSame('active', $this->db->fetchOne("SELECT u.status FROM users u JOIN user_emails e ON e.user_id = u.id AND e.is_primary WHERE e.email = :e", ['e' => $private]), 'Back, as a private account.');
    }

    public function testNobodyDeletesTheirOwnAccountAndTheCompanyKeepsOneAdministrator(): void
    {
        self::assertSame(CompanyDepartures::OWN, $this->departures->assess($this->administrator, $this->company, $this->administrator)['why']);
        $second = $this->staff('second');
        self::assertSame(CompanyDepartures::LAST_ADMIN, $this->departures->assess($second, $this->company, $this->administrator)['why'], 'The founder is the only Company Administrator.');
    }

    private function staff(string $name): int
    {
        $id = $this->fixture->createUser(ucfirst($name), $name . '@' . $this->domain);
        $this->fixture->addCompanyMember($this->company, $id);

        return $id;
    }

    private function enrol(int $userId, string $status): int
    {
        $course = $this->fixture->createCourse($this->administrator, $this->company, 'departures-' . $status . '-' . $userId, 'Departures ' . $status);

        return (int) $this->db->fetchOne(
            "INSERT INTO course_enrolments (public_id, user_id, course_id, status, access_period_seconds, started_at, completed_at, expires_at)
             VALUES (:p, :u, :c, :s, 31536000, CASE WHEN :s = 'assigned' THEN NULL ELSE NOW() END, CASE WHEN :s = 'completed' THEN NOW() ELSE NULL END, NOW() + INTERVAL '1 year') RETURNING id",
            ['p' => Uuid::v4(), 'u' => $userId, 'c' => $course, 's' => $status]
        );
    }

    private function token(string $body, string $pattern): string
    {
        self::assertSame(1, preg_match($pattern, $body, $match), 'The email holds the link.');

        return rawurldecode($match[1]);
    }
