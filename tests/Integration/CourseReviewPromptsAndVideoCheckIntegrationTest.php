    public function testALearnerIsEmailedOnceThreeDaysAfterCompletingACourseUnlessTheyReviewedIt(): void
    {
        $container = IntegrationContainer::get();
        $db = IntegrationContainer::db();
        $db->beginTransaction();
        try {
            $fixture = new DevelopmentFixture($db);
            $provider = $fixture->company();
            $course = $fixture->course($provider['founder']['id'], $provider['id'], 'published');
            $now = new \DateTimeImmutable('2026-11-20 10:00:00+02:00');
            $finished = static function (string $ago) use ($fixture, $db, $course, $provider, $now): array {
                $learner = $fixture->person('STUDENT');
                $enrolment = $fixture->createEnrolment($learner['id'], $course['id'], $provider['founder']['id'], 31536000, false, 'completed');
                $db->executeStatement('UPDATE course_enrolments SET started_at = CAST(:at AS timestamptz) - INTERVAL \'10 days\', completed_at = CAST(:at AS timestamptz) WHERE id = :id',
                    ['at' => $now->modify('-' . $ago)->format(DATE_ATOM), 'id' => $enrolment]);
                return $learner + ['enrolment' => $enrolment];
            };
            $due = $finished('4 days');
            $recent = $finished('1 day');
            $long = $finished('40 days');
            $reviewed = $finished('5 days');
            $container->get(CourseReviewService::class)->submit($reviewed['id'], $course['id'], 5, '');
            $suppressed = $finished('6 days');
            $db->executeStatement("INSERT INTO mailing_suppressions (email, reason) VALUES (:e, 'hard_bounce')", ['e' => strtolower($suppressed['email'])]);

            $mailer = new FakeMailer();
            $requests = new ReviewRequests($container->get(CourseReviewRepository::class), $container->get(TransactionManager::class), $mailer, new MockClock($now));
            $requests->send(1000);
            $ours = array_values(array_filter($mailer->messages, static fn(array $m): bool => in_array($m['email'], [$due['email'], $recent['email'], $long['email'], $reviewed['email'], $suppressed['email']], true)));
            self::assertSame([['type' => 'review_request', 'email' => $due['email'], 'firstName' => $due['first'], 'courseTitle' => $course['title'],
                'reviewUrl' => rtrim(Env::string('APP_URL', ''), '/') . '/learn/' . $course['slug'] . '/review']], $ours,
                'Only the learner who finished three to thirty days ago, has not reviewed it and may be emailed is asked.');
            self::assertNotNull($db->fetchOne('SELECT review_requested_at FROM course_enrolments WHERE id = :id', ['id' => $due['enrolment']]));

            $again = new FakeMailer();
            (new ReviewRequests($container->get(CourseReviewRepository::class), $container->get(TransactionManager::class), $again, new MockClock($now->modify('+3 days'))))->send(1000);
            self::assertSame([$recent['email']], array_values(array_map(static fn(array $m): string => $m['email'],
                array_filter($again->messages, static fn(array $m): bool => in_array($m['email'], [$due['email'], $recent['email']], true)))), 'Nobody is asked twice; the recent one is asked on their own day.');
        } finally {
            if ($db->isTransactionActive()) { $db->rollBack(); }
        }
    }

    public function testEveryCourseVideoIsCheckedAndOneThatNoLongerPlaysNeedsAttentionUntilItPlays(): void
    {
        $container = IntegrationContainer::get();
        $db = IntegrationContainer::db();
        $db->beginTransaction();
        try {
            $fixture = new DevelopmentFixture($db);
            $admin = $fixture->person('ADMIN');
            $provider = $fixture->company();
            $course = $fixture->course($provider['founder']['id'], $provider['id']);
            $items = $container->get(CourseItemService::class);
            $suffix = $fixture->suffix();
            $video = static fn(string $id, string $title): int => $items->createAndPlace($course['id'], ['item_key' => 'video-' . $suffix . '-' . strtolower($id), 'item_type' => 'youtube', 'title' => $title, 'youtube_id' => $id], $admin['id'])['item'];
            $playing = $video('aaaaaaaaaaa', 'Soil explained');
            $gone = $video('bbbbbbbbbbb', 'Compost in a month');
            $private = $video('ccccccccccc', 'Containers on a balcony');
            $answers = ['aaaaaaaaaaa' => 200, 'bbbbbbbbbbb' => 404, 'ccccccccccc' => 401];
            $asked = [];
            $youtube = new MockHttpClient(static function (string $method, string $url) use (&$answers, &$asked): MockResponse {
                parse_str((string) parse_url($url, PHP_URL_QUERY), $query);
                $id = substr((string) ($query['url'] ?? ''), -11);
                $asked[] = $id;
                return new MockResponse('{}', ['http_code' => $answers[$id] ?? 200]);
            });
            $records = $container->get(CourseVideoCheckRepository::class);
            $clock = new MockClock('2026-11-02 03:00:00+02:00');
            $summary = (new CourseVideoCheck($records, $clock, $youtube))->run();
            self::assertStringContainsString('2 do not', $summary);
            self::assertContains('aaaaaaaaaaa', $asked, 'YouTube is asked about the video by its id alone.');
            $status = static fn(int $item): string => (string) $db->fetchOne('SELECT status FROM course_video_checks WHERE course_item_id = :i', ['i' => $item]);
            self::assertSame(['plays', 'removed', 'blocked'], [$status($playing), $status($gone), $status($private)]);

            $actor = new CurrentUser($admin['id'], Uuid::v4(), $admin['email'], $admin['name'], ['ADMIN'], (new PermissionCatalog())->keys(), Uuid::v4());
            $videos = array_values(array_filter($container->get(AdminAttention::class)->items($actor), static fn(array $row): bool => $row['kind'] === 'video'
                && str_ends_with($row['title'], ' in ' . $course['title'] . ' no longer plays')));
            self::assertSame(['Compost in a month in ' . $course['title'] . ' no longer plays', 'Containers on a balcony in ' . $course['title'] . ' no longer plays'], array_column($videos, 'title'));
            self::assertSame('/admin/course-items/' . $gone, $videos[0]['href']);
            self::assertStringStartsWith(CourseVideoCheck::FINDINGS['removed'] . ' Found on 2 November 2026.', $videos[0]['summary']);

            // YouTube cannot be reached for one video: what was found before stands. The private one plays again.
            $answers['bbbbbbbbbbb'] = 503;
            $answers['ccccccccccc'] = 200;
            $clock->modify('+1 day');
            (new CourseVideoCheck($records, $clock, $youtube))->run();
            self::assertSame(['plays', 'removed', 'plays'], [$status($playing), $status($gone), $status($private)]);
            self::assertSame('2026-11-02', substr((string) $db->fetchOne('SELECT failing_since FROM course_video_checks WHERE course_item_id = :i', ['i' => $gone]), 0, 10), 'It keeps the day it was first found.');
        } finally {
            if ($db->isTransactionActive()) { $db->rollBack(); }
        }
    }

