    public function testTheCoursePageUsesTheDefaultALayoutByNameOrItsCustomLayout(): void
    {
        $buy = $this->layouts->create('Buy first ' . $this->suffix, 'Course access first.', self::arranged([['access', 'full'], ['about', 'half'], ['glance', 'half'], ['modules', 'full']]), $this->admin);
        $first = $this->layouts->create('Course first ' . $this->suffix, '', CoursePageLayout::starting(), $this->admin);

        // On the default layout, the course follows whichever layout is the default.
        $this->layouts->makeDefault($first, $this->admin);
        self::assertSame('default', $this->layouts->forCourse($this->course)['choice']);
        // A course without modules, figures, reviews, preview or related courses shows four blocks.
        self::assertSame(['about', 'modules', 'glance', 'access'], $this->blocks());
        $this->layouts->makeDefault($buy, $this->admin);
        self::assertSame(['access', 'about', 'glance', 'modules'], $this->blocks(), 'Another default changes every course on the default layout.');
        self::assertTrue($this->shareRow('About this course', 'At a glance'), 'Two half blocks side by side share a row.');

        // One of the layouts by name: it stays whichever layout is the default.
        $this->layouts->choose($this->course, 'layout', $first, null, $this->admin);
        self::assertSame(['about', 'modules', 'glance', 'access'], $this->blocks());

        // A custom layout, for this course only; Course access is never hidden.
        $custom = CoursePageLayout::starting();
        $custom[0]['shown'] = false; // About this course
        $custom[6]['shown'] = false; // Course access
        $this->layouts->choose($this->course, 'custom', null, $custom, $this->admin);
        self::assertSame(['modules', 'glance', 'access'], $this->blocks());
        $uses = $this->layouts->forCourse($this->course);
        self::assertSame(['custom', true], [$uses['choice'], $uses['blocks'][6]['shown']]);

        // Back on the default layout, the custom layout is kept, to choose again.
        $this->layouts->choose($this->course, 'default', null, null, $this->admin);
        self::assertSame(['access', 'about', 'glance', 'modules'], $this->blocks());
        self::assertFalse($this->layouts->forCourse($this->course)['custom'][0]['shown'] ?? true, 'The custom layout is kept.');
        $this->layouts->choose($this->course, 'custom', null, null, $this->admin);
        self::assertSame(['modules', 'glance', 'access'], $this->blocks(), 'Choosing Custom layout again brings it back.');
        self::assertSame(4, (int) $this->db->fetchOne("SELECT COUNT(*) FROM course_edit_history WHERE course_id=:c AND event_key='course.page_layout_saved'", ['c' => $this->course]));
    }

    public function testLayoutsAreNamedCopiedAndDeletedOnlyWhenNothingUsesThem(): void
    {
        $id = $this->layouts->create('  Sales   ' . $this->suffix . ' ', 'For courses people know they want.', CoursePageLayout::starting(), $this->admin);
        self::assertSame('Sales ' . $this->suffix, $this->layouts->layout($id)['name'], 'A name is one line, spaces tidied.');
        foreach (['', 'sales ' . $this->suffix, str_repeat('x', 81)] as $name) {
            try {
                $this->layouts->create($name, '', CoursePageLayout::starting(), $this->admin);
                self::fail('"' . $name . '" is not a name a layout may have.');
            } catch (\InvalidArgumentException) {
            }
        }
        $copy = $this->layouts->copy($id, $this->admin);
        self::assertSame('Copy of Sales ' . $this->suffix, $this->layouts->layout($copy)['name']);
        self::assertSame('Copy of Sales ' . $this->suffix . ' 2', $this->layouts->layout($this->layouts->copy($id, $this->admin))['name']);
        $this->layouts->update($copy, 'Reviews first ' . $this->suffix, '', CoursePageLayout::starting(), $this->admin);
        self::assertSame('Reviews first ' . $this->suffix, $this->layouts->layout($copy)['name']);

        // Used by a course: not deleted, and the reason says how many.
        $this->layouts->choose($this->course, 'layout', $id, null, $this->admin);
        self::assertSame(1, $this->layouts->layout($id)['courses']);
        $this->refused(fn() => $this->layouts->delete($id, $this->admin), 'is used by 1 course');
        // The default: never deleted.
        $this->layouts->makeDefault($copy, $this->admin);
        $this->refused(fn() => $this->layouts->delete($copy, $this->admin), 'is the default layout');
        self::assertSame(1, (int) $this->db->fetchOne('SELECT COUNT(*) FROM course_page_layouts WHERE is_default'), 'One default.');
        // Free again: deleted.
        $this->layouts->apply([$this->course], 0, $this->admin);
        self::assertSame('default', $this->layouts->forCourse($this->course)['choice']);
        self::assertSame('Sales ' . $this->suffix, $this->layouts->delete($id, $this->admin));
        self::assertNull(IntegrationContainer::get()->get(CoursePageLayoutRepository::class)->find($id));
    }

    public function testThePagesSaveWithoutJavaScript(): void
    {
        $this->signIn($this->admin);
        $list = $this->html('/admin/courses/page-layouts');
        self::assertStringContainsString('Courses and their layouts', $list);
        self::assertStringContainsString('/admin/courses/' . $this->code . '?tab=page-layout', $list, 'Every course is listed with a link to its Page layout tab.');
        self::assertStringContainsString('Ready to start (no free preview)', $this->html('/admin/courses/page-layouts?show=default'), 'What a course leaves out, and why.');
        self::assertStringNotContainsString('id="settings-course-pages"', $this->html('/admin/settings'), 'Settings no longer holds course pages.');

        // A new layout, then a block hidden without JavaScript (the button sends the whole form and saves).
        $order = 'about,how,modules,glance,get,reviews,access,start,related';
        $shown = array_fill_keys(['about', 'how', 'modules', 'glance', 'get', 'reviews', 'start', 'related'], '1');
        $this->post('/admin/courses/page-layouts/new', ['name' => 'Plain ' . $this->suffix, 'purpose' => '', 'order' => $order, 'shown' => $shown, 'action' => 'save']);
        $id = (int) (IntegrationContainer::get()->get(CoursePageLayoutRepository::class)->findByName('Plain ' . $this->suffix)['id'] ?? 0);
        self::assertGreaterThan(0, $id);
        $page = $this->html('/admin/courses/page-layouts/' . $id . '?course=' . $this->course);
        self::assertSame(9, substr_count($page, 'class="cl-page-builder-tile"'));
        self::assertStringContainsString('Left out on this course', $page);
        $this->post('/admin/courses/page-layouts/' . $id, ['name' => 'Plain ' . $this->suffix, 'purpose' => 'Plain', 'order' => $order, 'shown' => $shown, 'action' => 'hide:glance']);
        self::assertFalse($this->layouts->layout($id)['blocks'][3]['shown']);

        // Apply to the ticked courses.
        $this->post('/admin/courses/page-layouts/apply', ['courses' => [(string) $this->course], 'layout' => (string) $id]);
        self::assertSame(['layout', $id], [$this->layouts->forCourse($this->course)['choice'], $this->layouts->forCourse($this->course)['layout']['id'] ?? 0]);

        // The course's tab: the three choices, the custom layout's builder, Start again from and Save as a layout.
        $tab = $this->html('/admin/courses/' . $this->code . '?tab=page-layout');
        foreach (['Choose the layout', 'One of your layouts', 'Custom layout', 'Plain ' . $this->suffix, 'Start again from'] as $words) self::assertStringContainsString($words, $tab);
        $tabUrl = '/admin/courses/' . $this->code . '/page-layout';
        $this->post($tabUrl, ['source' => 'default', 'layout_id' => (string) $id, 'order' => $order, 'shown' => $shown, 'action' => 'save']);
        self::assertSame('default', $this->layouts->forCourse($this->course)['choice']);
        $this->post($tabUrl, ['source' => 'custom', 'order' => $order, 'shown' => $shown, 'action' => 'move:how:up']);
        self::assertSame(['custom', 'how'], [$this->layouts->forCourse($this->course)['choice'], $this->layouts->forCourse($this->course)['blocks'][0]['id']], 'A move without JavaScript saves the custom layout.');
        $this->post($tabUrl, ['source' => 'custom', 'order' => $order, 'shown' => $shown, 'action' => 'start', 'start_from' => (string) $id]);
        self::assertSame($this->layouts->layout($id)['blocks'], $this->layouts->forCourse($this->course)['blocks'], 'Start again from copies a layout in.');
        $this->post($tabUrl, ['source' => 'custom', 'order' => $order, 'shown' => $shown, 'action' => 'save_as', 'layout_name' => 'Saved ' . $this->suffix]);
        $uses = $this->layouts->forCourse($this->course);
        self::assertSame(['layout', 'Saved ' . $this->suffix], [$uses['choice'], $uses['layout']['name'] ?? '']);
        self::assertNotNull($uses['custom'], 'Its custom layout is kept.');
    }

    public function testTheCatalogueBlockCarriesWhatTheCourseUses(): void
    {
        $settings = IntegrationContainer::get()->get(CourseCatalogueSettings::class);
        $course = IntegrationContainer::get()->get(CourseRepository::class)->findById($this->course);
        self::assertNull($settings->export($this->course)['page_layout'], 'A course on the default layout carries null.');

        $own = CoursePageLayout::starting();
        $own[0]['shown'] = false;
        self::assertSame(['Page layout: custom'], $settings->changes($course, ['page_layout' => $own], false));
        self::assertSame(['Page layout: custom'], $settings->apply($this->course, ['page_layout' => $own], $this->admin, false));
        self::assertSame($own, $settings->export($this->course)['page_layout']);
        self::assertSame([], $settings->apply($this->course, ['page_layout' => $own], $this->admin, false), 'The same package again changes nothing.');
        self::assertSame([], $settings->apply($this->course, [], $this->admin, false), 'An older package without one leaves it as it is.');

        // One of the layouts, by name: made where the site has none, used as it is where it has one.
        $named = ['name' => 'Imported ' . $this->suffix, 'purpose' => 'From another site', 'blocks' => self::arranged([['reviews', 'full'], ['about', 'full']])];
        self::assertSame(['Page layout: Imported ' . $this->suffix . ' (made by this import)'], $settings->changes($course, ['page_layout' => $named], false));
        $settings->apply($this->course, ['page_layout' => $named], $this->admin, false);
        $uses = $this->layouts->forCourse($this->course);
        self::assertSame(['layout', 'reviews'], [$uses['choice'], $uses['blocks'][0]['id']]);
        self::assertSame(['name' => $named['name'], 'purpose' => 'From another site', 'blocks' => $uses['blocks']], $settings->export($this->course)['page_layout']);
        self::assertSame([], $settings->apply($this->course, ['page_layout' => ['blocks' => CoursePageLayout::starting()] + $named], $this->admin, false), 'A layout already here keeps its arrangement.');
        self::assertSame('reviews', $this->layouts->forCourse($this->course)['blocks'][0]['id']);

        self::assertSame(['Page layout: default'], $settings->apply($this->course, ['page_layout' => null], $this->admin, false));
        self::assertSame('default', $this->layouts->forCourse($this->course)['choice']);
    }

    /**
     * Blocks in the order given, each shown; the rest made whole after them.
     *
     * @param list<array{0:string,1:string}> $blocks
     * @return list<array{id:string,width:string,shown:bool}>
     */
    private static function arranged(array $blocks): array
    {
        return CoursePageLayout::normalise(array_map(static fn(array $block): array => ['id' => $block[0], 'width' => $block[1], 'shown' => true], $blocks));
    }

    private function refused(callable $change, string $because): void
    {
        try {
            $change();
            self::fail('Refused: ' . $because);
        } catch (\InvalidArgumentException $refused) {
            self::assertStringContainsString($because, $refused->getMessage());
        }
    }

    /** @return list<string> The course page's blocks in order, by their headings. */
    private function blocks(): array
    {
        preg_match_all('#<h2[^>]*>(.*?)</h2>#s', $this->coursePage(), $matches);
        $blocks = [];
        foreach ($matches[1] as $heading) {
            $text = trim(html_entity_decode(strip_tags($heading)));
            if (isset(self::HEADINGS[$text])) $blocks[] = self::HEADINGS[$text];
        }
        return $blocks;
    }

    private function shareRow(string $first, string $second): bool
    {
        foreach (explode('<section class="cl-page-section">', $this->coursePage()) as $section) {
            if (str_contains($section, '>' . $first . '</h2>')) return str_contains($section, '>' . $second . '</h2>');
        }
        return false;
    }

    private function coursePage(): string
    {
        $_COOKIE = $this->cookies;
        return $this->html('/courses/' . $this->slug);
    }

    private function signIn(int $user): void
    {
        $token = Token::generate();
        IntegrationContainer::get()->get(AuthSessionRepository::class)->create($user, Token::hash($token), 3600, 'qa', 'PHPUnit');
        $_COOKIE = $this->cookies;
        $_COOKIE[Env::string('AUTH_SESSION_COOKIE', 'catto_learning_session')] = $token;
    }

    /** @param array<string,mixed> $fields */
    private function post(string $url, array $fields): void
    {
        $_POST = ['csrf' => $_SESSION['csrf']] + $fields;
        $kernel = new Kernel('test', true, CliBootstrap::boot()['instance_root']);
        try {
            $kernel->handle(Request::create($url, 'POST', $_POST));
        } finally {
            $kernel->shutdown();
            $_POST = [];
        }
    }

    private function send(string $url): Response
    {
        $kernel = new Kernel('test', true, CliBootstrap::boot()['instance_root']);
        $_GET = Request::create($url)->query->all();
        try {
            return $kernel->handle(Request::create($url, 'GET'));
        } finally {
            $kernel->shutdown();
            $_GET = [];
        }
    }

    private function html(string $url): string
    {
        $response = $this->send($url);
        self::assertSame(200, $response->getStatusCode(), $url . ' must render: ' . substr(strip_tags((string) $response->getContent()), 0, 400));
        return (string) $response->getContent();
    }
