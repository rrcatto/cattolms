    public function testTheCoursePageFollowsTheSiteDefaultUntilItHasALayoutOfItsOwn(): void
    {
        // Course first: a course without modules, figures, reviews, preview or related courses shows four blocks.
        self::assertSame(['about', 'modules', 'glance', 'access'], $this->blocks());
        self::assertFalse($this->layouts->forCourse($this->course)['own']);

        $this->layouts->saveSiteDefault(CoursePageLayout::template('buy'), $this->admin);
        self::assertSame(['access', 'about', 'glance', 'modules'], $this->blocks(), 'A new default changes every course on it.');
        self::assertTrue($this->shareRow('About this course', 'At a glance'), 'Two half blocks side by side share a row.');

        $own = CoursePageLayout::template('reviews');
        $own[1]['shown'] = false; // About this course
        $own[6]['shown'] = false; // Course access, which is never hidden
        $this->layouts->saveForCourse($this->course, $own, $this->admin);
        self::assertSame(['modules', 'glance', 'access'], $this->blocks());
        self::assertTrue($this->layouts->forCourse($this->course)['own']);
        self::assertTrue(IntegrationContainer::get()->get(CourseRepository::class)->pageLayout($this->course)[6]['shown']);
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM course_edit_history WHERE course_id=:c AND event_key='course.page_layout_saved'", ['c' => $this->course]));

        $this->layouts->saveForCourse($this->course, null, $this->admin);
        self::assertSame(['access', 'about', 'glance', 'modules'], $this->blocks(), 'Back on the site\'s default.');
    }

    public function testThePageLayoutTabAndSettingsSaveWithoutJavaScript(): void
    {
        $this->signIn($this->admin);
        $html = $this->html('/admin/courses/' . $this->course . '?tab=page-layout');
        self::assertStringContainsString('id="page-layout-form"', $html);
        self::assertStringContainsString('Which layout this course uses', $html);
        self::assertSame(9, substr_count($html, 'class="cl-page-builder-tile"'));
        self::assertSame(1, substr_count($html, 'data-required'), 'Course access is the one block always shown.');

        $form = ['source' => 'default', 'order' => 'about,how,modules,glance,get,reviews,access,start,related'];
        $this->post('/admin/courses/' . $this->course . '/page-layout', $form + ['action' => 'template:buy']);
        self::assertSame(CoursePageLayout::template('buy'), $this->layouts->forCourse($this->course)['layout'], 'A template is saved as the course\'s own layout.');
        $this->post('/admin/courses/' . $this->course . '/page-layout', $form + ['action' => 'save']);
        self::assertFalse($this->layouts->forCourse($this->course)['own'], 'Saved on the default, the course follows it.');
        $this->post('/admin/courses/' . $this->course . '/page-layout', ['source' => 'own', 'action' => 'hide:glance'] + $form + ['shown' => array_fill_keys(['about', 'how', 'modules', 'glance', 'get', 'reviews', 'start', 'related'], '1')]);
        self::assertFalse($this->layouts->forCourse($this->course)['layout'][3]['shown']);
        $this->post('/admin/courses/' . $this->course . '/page-layout', $form + ['action' => 'reset']);
        self::assertFalse($this->layouts->forCourse($this->course)['own']);

        self::assertStringContainsString('id="settings-course-pages"', $this->html('/admin/settings?section=course-pages'));
        $this->post('/admin/settings/course-pages', $form + ['action' => 'template:reviews']);
        self::assertSame(CoursePageLayout::template('reviews'), $this->layouts->siteDefault());
        $this->post('/admin/settings/course-pages', $form + ['action' => 'reset']);
        self::assertSame(CoursePageLayout::template('course'), $this->layouts->siteDefault());
    }

    public function testTheCatalogueBlockCarriesTheLayout(): void
    {
        $settings = IntegrationContainer::get()->get(CourseCatalogueSettings::class);
        $course = IntegrationContainer::get()->get(CourseRepository::class)->findById($this->course);
        self::assertNull($settings->export($this->course)['page_layout'], 'A course on the default carries null.');

        $own = CoursePageLayout::template('buy');
        self::assertSame(['Page layout: its own'], $settings->changes($course, ['page_layout' => $own], false));
        self::assertSame(['Page layout: its own'], $settings->apply($this->course, ['page_layout' => $own], $this->admin, false));
        self::assertSame($own, $settings->export($this->course)['page_layout']);
        self::assertSame([], $settings->apply($this->course, ['page_layout' => $own], $this->admin, false), 'The same package again changes nothing.');
        self::assertSame([], $settings->apply($this->course, [], $this->admin, false), 'An older package without one leaves it as it is.');
        self::assertSame(['Page layout: the site\'s default'], $settings->apply($this->course, ['page_layout' => null], $this->admin, false));
        self::assertFalse($this->layouts->forCourse($this->course)['own']);
    }

    /** @return list<string> The course page's blocks in order, by their headings. */
    private function blocks(): array
    {
        preg_match_all('#<h2[^>]*>(.*?)</h2>#s', $this->coursePage(), $matches);
        $blocks = [];
        foreach ($matches[1] as $heading) {
            $text = trim(html_entity_decode(strip_tags($heading)));
            if (isset(self::HEADINGS[$text])) $blocks[] = self::HEADINGS[$text];
        }
        return $blocks;
    }

    private function shareRow(string $first, string $second): bool
    {
        foreach (explode('<section class="cl-page-section">', $this->coursePage()) as $section) {
            if (str_contains($section, '>' . $first . '</h2>')) return str_contains($section, '>' . $second . '</h2>');
        }
        return false;
    }

    private function coursePage(): string
    {
        $_COOKIE = $this->cookies;
        return $this->html('/courses/' . $this->slug);
    }

    private function signIn(int $user): void
    {
        $token = Token::generate();
        IntegrationContainer::get()->get(AuthSessionRepository::class)->create($user, Token::hash($token), 3600, 'qa', 'PHPUnit');
        $_COOKIE = $this->cookies;
        $_COOKIE[Env::string('AUTH_SESSION_COOKIE', 'catto_learning_session')] = $token;
    }

    /** @param array<string,mixed> $fields */
    private function post(string $url, array $fields): void
    {
        $_POST = ['csrf' => $_SESSION['csrf']] + $fields;
        $kernel = new Kernel('test', true, CliBootstrap::boot()['instance_root']);
        try {
            $kernel->handle(Request::create($url, 'POST', $_POST));
        } finally {
            $kernel->shutdown();
            $_POST = [];
        }
    }

    private function send(string $url): Response
    {
        $kernel = new Kernel('test', true, CliBootstrap::boot()['instance_root']);
        $_GET = Request::create($url)->query->all();
        try {
            return $kernel->handle(Request::create($url, 'GET'));
        } finally {
            $kernel->shutdown();
            $_GET = [];
        }
    }

    private function html(string $url): string
    {
        $response = $this->send($url);
        self::assertSame(200, $response->getStatusCode(), $url . ' must render: ' . substr(strip_tags((string) $response->getContent()), 0, 400));
        return (string) $response->getContent();
    }
