    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->fixture = new IntegrationDataFixture($this->db);
        $this->layouts = IntegrationContainer::get()->get(CoursePageLayouts::class);
        $this->options = IntegrationContainer::get()->get(OptionRepository::class);
        $this->defaultBefore = $this->options->find('course_page.layout');
        $this->options->delete('course_page.layout');
        $suffix = $this->fixture->suffix();
        $this->slug = 'page-layout-' . $suffix;
        $this->admin = $this->fixture->createUser('Layout admin ' . $suffix, 'layout-admin-' . $suffix . '@seed.test');
        $this->fixture->grantRole($this->admin, 'ADMIN');
        $company = $this->fixture->createCompany($this->admin, 'Page layout ' . $suffix, 'page-layout-' . $suffix . '.seed.test');
        $this->course = $this->fixture->createCourse($this->admin, $company, $this->slug, 'Page layout ' . $suffix);
        $this->cookies = $_COOKIE;
        $_SESSION['csrf'] = str_repeat('c', 64);
    }

    protected function tearDown(): void
    {
        $_COOKIE = $this->cookies;
        $this->defaultBefore === null ? $this->options->delete('course_page.layout') : $this->options->set('course_page.layout', $this->defaultBefore);
        $this->db->executeStatement('DELETE FROM analytics_events WHERE course_id=:id', ['id' => $this->course]);
        $this->fixture->cleanup();
