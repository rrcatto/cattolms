    public function testAMoneyBackRefundGoesToTheCardAndItsPayoutIsRecorded(): void
    {
        $refundId = $this->paidCardOrderWithRefund();
        $refund = $this->records->refund($refundId);
        self::assertNotNull($refund);
        self::assertTrue($this->stitchRefunds->canSend($refund));
        $net = (int) $refund['net_minor'];

        $this->answers = [[200, ['success' => true, 'data' => ['refund' => []]]], [200, ['success' => true, 'data' => ['refund' => self::refundOf('rf-1111', $net)]]]];
        $sent = $this->stitchRefunds->send($this->approver(), $refundId);
        self::assertTrue($sent['done'], $sent['words']);
        self::assertSame('https://express.stitch.money/api/v1/payment/pay_paid/refund', $this->sent[0]['url'], 'Stitch\'s refunds of the payment are read first.');
        self::assertSame('POST', $this->sent[1]['method']);
        self::assertSame(['amount' => $net, 'reason' => 'REQUESTED_BY_USER'], json_decode($this->sent[1]['body'], true));
        $refund = $this->records->refund($refundId);
        self::assertNotNull($refund);
        self::assertSame('rf-1111', $refund['payout_reference']);
        self::assertNotNull($refund['paid_at']);
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM commerce_ledger_entries WHERE refund_id=:r AND kind='refund_paid' AND method='stitch'", ['r' => $refundId]));
        self::assertFalse($this->stitchRefunds->canSend($refund), 'Paid: nothing more to send.');
        self::assertTrue($this->stitchRefunds->send($this->approver(), $refundId)['done']);
        self::assertCount(2, $this->sent, 'Sending a paid refund again asks Stitch nothing.');
    }

