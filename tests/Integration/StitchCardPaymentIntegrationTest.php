    public function testAnExpiredLinkFailsThePaymentAndTheBuyerCanPayAgain(): void
    {
        $order = $this->place();
        $this->answers = [self::link('pl_old', 'PENDING')];
        $this->payments->startCard($this->actor, $order, Uuid::v4());

        // A minute later the job asks; the link has expired.
        $this->clock->modify('+2 minutes');
        $this->answers = [self::link('pl_old', 'EXPIRED')];
        self::assertSame(1, $this->payments->checkWaitingCards());
        self::assertSame('failed', $this->latestPayment($order)['state']);
        self::assertSame('awaiting_payment', $this->records->order($order)['state']);

        $this->answers = [self::link('pl_new', 'PENDING')];
        self::assertStringContainsString('/pay/pl_new', $this->payments->startCard($this->actor, $order, Uuid::v4()));
        self::assertSame(0, $this->payments->checkWaitingCards(), 'A link not a minute old is left to the buyer.');
    }

