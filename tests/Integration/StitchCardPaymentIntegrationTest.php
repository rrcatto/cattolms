    public function testACardOrderIsSentToItsStitchLinkAndPaidWhenTheBuyerReturns(): void
    {
        WalletFixture::settings($this->db)->saveSection('fees', ['stitch_fee' => '3%+0', 'stitch_refund_fee' => '0%+0', 'eft_refund_fee' => '0:2000'], $this->actor->id);
        $order = $this->place();
        $key = Uuid::v4();
        $this->answers = [self::link('pl_first', 'PENDING')];
        $url = $this->payments->startCard($this->actor, $order, $key);
        self::assertSame('https://express.stitch.money/pay/pl_first?redirect_url=' . rawurlencode('https://learning.example.com/checkout/stitch/return'), $url);

        $attempt = $this->latestPayment($order);
        self::assertSame(['stitch', 'pending', 'pl_first', 120000], [$attempt['gateway'], $attempt['state'], $attempt['checkout_reference'], (int) $attempt['amount_minor']]);
        self::assertSame('card', $this->records->paymentMethod($order));
        $sent = json_decode($this->sent[0]['body'], true);
        self::assertSame(OrderNumber::format($order), $sent['merchantReference']);
        self::assertSame('2026-11-11T09:00:00.000Z', $sent['expiresAt'], 'The payment link lifetime, an hour.');
        self::assertSame(['CARD'], $sent['allowedPaymentMethods']);

        self::assertSame($url, $this->payments->startCard($this->actor, $order, $key), 'The same request: the same link.');
        self::assertCount(1, $this->sent, 'Stitch was not asked twice.');
        self::assertSame($url, $this->payments->cardCheckout($order));

        $this->answers = [self::link('pl_first', 'PAID', 'pay_9kL1')];
        self::assertSame(['order' => $order, 'state' => 'paid'], $this->payments->cardReturn(OrderNumber::format($order)));
        self::assertSame('fulfilled', $this->records->order($order)['state']);
        self::assertSame('pay_9kL1', $this->latestPayment($order)['provider_reference']);
        self::assertNull($this->payments->cardCheckout($order));
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM commerce_documents WHERE order_id=:o AND kind='receipt'", ['o' => $order]), 'Its receipt.');
        self::assertSame([['payment_received', 120000], ['processor_fee', 3600]], array_map(static fn (array $row): array => [$row['kind'], (int) $row['amount_minor']], $this->db->fetchAllAssociative("SELECT kind, amount_minor FROM commerce_ledger_entries WHERE order_id=:o AND kind IN ('payment_received','processor_fee') ORDER BY id", ['o' => $order])), 'The payment and Stitch\'s 3% fee in the ledger.');

        self::assertSame(['order' => $order, 'state' => 'paid'], $this->payments->cardReturn(OrderNumber::format($order)), 'A second return asks Stitch nothing more.');
        self::assertCount(2, $this->sent);
        self::assertNull($this->payments->cardReturn('CL-nothing'));
    }

