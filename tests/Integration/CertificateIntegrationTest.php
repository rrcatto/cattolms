    public function testAnIssuedCertificateNeverChangesWhenTheLearnerCourseOrTemplateChange(): void
    {
        [$courseId, $firstEnrolment, $learnerId] = $this->completedEnrolment('Original Learner', 'Original Course Title');
        $first = $this->issuer->issue($firstEnrolment, $this->adminId);
        $issuedWithFirst = $this->certificates->countForVersion((int) $first['template_version_id']);
        $before = $this->documents->render($first);
        $pdfPages = self::pages($this->documents->pdf($first));
        self::assertSame(1, $pdfPages);

        // Everything a certificate is drawn from changes afterwards.
        $this->db->executeStatement("UPDATE users SET certificate_name = 'Renamed Learner', display_name = 'Renamed Learner' WHERE id = :id", ['id' => $learnerId]);
        $this->db->executeStatement("UPDATE courses SET title = 'Renamed Course Title', certificate_title = 'Renamed Award' WHERE id = :id", ['id' => $courseId]);
        $templateId = (int) $first['template_id'];
        $documents = IntegrationContainer::get()->get(DocumentTemplateService::class);
        $settings = array_map('strval', DocumentType::Certificate->defaultSettings()->toArray());
        $documents->saveAndPublish($this->admin, $templateId, ['html' => '<p>Edition-2 {{ learner.name }} · {{ course.title }} · {{ certificate.number }}</p>', 'css' => 'p{margin:0}', 'change_note' => 'Second edition'] + $settings);

        $stored = $this->certificates->byPublicId((string) $first['public_id']);
        $after = $this->documents->render($stored);
        self::assertSame($before->body, $after->body, 'An issued certificate renders exactly as it was issued.');
        self::assertSame($before->html, $after->html);
        self::assertStringContainsString('Original Learner', $after->body);
        self::assertStringContainsString('Original Course Title', $after->body);
        self::assertStringNotContainsString('Edition-2', $after->body);
        self::assertSame('Original Learner', (string) $stored['learner_name']);

        // A new issue uses the newly published version and the current names.
        [, $secondEnrolment] = $this->completedEnrolment('Second Learner', 'Second Course');
        $second = $this->issuer->issue($secondEnrolment, $this->adminId);
        self::assertSame((int) $first['template_version_number'] + 1, (int) $second['template_version_number']);
        self::assertStringContainsString('Edition-2 Second Learner · Second Course', $this->documents->render($second)->body);
        self::assertSame($issuedWithFirst, $this->certificates->countForVersion((int) $first['template_version_id']), 'Issuing with a new version leaves the old count alone.');
        self::assertSame(1, $this->certificates->countForVersion((int) $second['template_version_id']));

        // A reissue keeps the identity a learner may have shared and records the issue it is now.
        $reissued = $this->issuer->issue($firstEnrolment, $this->adminId);
        self::assertSame((string) $first['public_id'], (string) $reissued['public_id']);
        self::assertSame((string) $first['certificate_number'], (string) $reissued['certificate_number']);
        self::assertSame((int) $second['template_version_id'], (int) $reissued['template_version_id']);
        self::assertStringContainsString('Edition-2 Renamed Learner · Renamed Course Title', $this->documents->render($reissued)->body);
    }

