        @unlink($file);
        self::assertSame([], $saved['errors']);
        $design = $this->designs->find($saved['id'])['design'];
        self::assertSame(CertificateLooks::CUSTOM, $design->look, 'Uploading a background means using it.');
        self::assertSame([2480, 1754], [$design->background?->width, $design->background?->height], 'Scaled to the stored size.');
        self::assertSame(['right', 'sans', '#7A2E3A'], [$design->placement, $design->typeface, $design->colour]);
        self::assertSame(1, (int) $this->db->fetchOne('SELECT COUNT(*) FROM document_assets WHERE sha256 = :sha', ['sha' => $design->background?->sha]));
        self::assertSame(1, self::pages($service->previewPdf($saved['id'])));
        $thumbnail = InProcessPage::run($this->admin, CertificateDesignController::class, 'picture', ['sha' => (string) $design->background?->sha]);
        self::assertSame(200, $thumbnail['status']);
        self::assertStringStartsWith("\x89PNG", $thumbnail['body']);
    }

