        self::assertSame(200, $page['status']);
        foreach (['Verified Learner', 'Verified Course', (string) $certificate['certificate_number'], 'sandbox=""', '/certificate.pdf', 'Download PDF'] as $text) {
            self::assertStringContainsString($text, $page['body']);
        }
        self::assertStringNotContainsString('versions/' . $certificate['template_version_id'], $page['body'], 'Only template viewers see the template line.');
        $adminPage = InProcessPage::run($this->admin, CertificateController::class, 'show', $id);
        self::assertStringContainsString('/admin/documents/templates/' . $certificate['template_id'] . '/versions/' . $certificate['template_version_id'], $adminPage['body']);

        $pdf = InProcessPage::run(null, CertificateController::class, 'pdf', $id);
        self::assertSame(200, $pdf['status']);
        self::assertStringStartsWith('%PDF-', $pdf['body']);
        self::assertSame(1, self::pages($pdf['body']));

        $version = InProcessPage::run($this->admin, DocumentTemplateController::class, 'version', ['id' => (int) $certificate['template_id'], 'version' => (int) $certificate['template_version_id']]);
        self::assertStringContainsString('Certificates issued with it', $version['body']);

        $this->db->executeStatement("UPDATE certificates SET revoked_at = NOW(), revocation_reason = 'Issued in error.' WHERE id = :id", ['id' => (int) $certificate['id']]);
        $revoked = InProcessPage::run(null, CertificateController::class, 'show', $id);
        self::assertStringContainsString('This certificate was revoked', $revoked['body']);
        self::assertStringContainsString('Issued in error.', $revoked['body']);
        self::assertStringNotContainsString('Download PDF', $revoked['body']);
        self::assertStringNotContainsString('sandbox=""', $revoked['body']);
        try {
            InProcessPage::run(null, CertificateController::class, 'pdf', $id);
            self::fail('A revoked certificate has no PDF.');
        } catch (NotFoundHttpException) {
            self::addToAssertionCount(1);
        }
        $this->expectException(NotFoundHttpException::class);
        InProcessPage::run(null, CertificateController::class, 'show', ['public_id' => Uuid::v4()]);
    }

