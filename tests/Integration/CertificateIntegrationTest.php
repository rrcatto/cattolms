    public function testAnIssuedCertificateNeverChangesWhenTheLearnerCourseOrDesignChange(): void
    {
        [$courseId, $firstEnrolment, $learnerId] = $this->completedEnrolment('Original Learner', 'Original Course Title');
        $first = $this->issuer->issue($firstEnrolment, $this->adminId);
        $before = $this->documents->render($first);
        self::assertSame(1, self::pages($this->documents->pdf($first)));

        // Everything a certificate is drawn from changes afterwards: the learner's names, the course, the
        // design's wording, and which design the course uses.
        $this->db->executeStatement("UPDATE users SET display_name = 'Renamed Learner', first_name = 'Renamed' WHERE id = :id", ['id' => $learnerId]);
        $this->db->executeStatement("UPDATE courses SET title = 'Renamed Course Title', certificate_accreditation = 'New line' WHERE id = :id", ['id' => $courseId]);
        $classic = $this->designs->find((int) $first['template_id']);
        self::assertNotNull($classic);
        $saved = $this->service->save($classic['id'], $this->form('Classic', '<p class="cert-title">Edition two</p><p>' . CertificateWording::chip('learner.name') . ' · ' . CertificateWording::chip('course.title') . '</p>'), [], $this->adminId);
        self::assertSame([], $saved['errors']);

        $stored = $this->certificates->byPublicId((string) $first['public_id']);
        self::assertNotNull($stored);
        $after = $this->documents->render($stored);
        self::assertSame($before->html, $after->html, 'An issued certificate draws exactly as it was issued.');
        self::assertStringContainsString('Original Learner', $after->body);
        self::assertStringNotContainsString('Edition two', $after->body);

        // A new issue uses the design as it is now.
        [, $secondEnrolment] = $this->completedEnrolment('Second Learner', 'Second Course');
        $second = $this->issuer->issue($secondEnrolment, $this->adminId);
        self::assertNotSame((int) $first['template_version_id'], (int) $second['template_version_id']);
        self::assertStringContainsString('Second Learner · Second Course', $this->documents->render($second)->body);
        self::assertStringContainsString('Edition two', $this->documents->render($second)->body);

        // Moving the course to another design changes nothing already issued either.
        $minimal = $this->designNamed('Minimal');
        $this->db->executeStatement('UPDATE courses SET certificate_design_id = :design WHERE id = :id', ['design' => $minimal['id'], 'id' => $courseId]);
        $again = $this->certificates->byPublicId((string) $first['public_id']);
        self::assertNotNull($again);
        self::assertSame($before->html, $this->documents->render($again)->html);

        // A reissue keeps the identity a learner may have shared, is drawn with the course's design now
        // and keeps the verified name, whatever the profile says.
        $reissued = $this->issuer->issue($firstEnrolment, $this->adminId);
        self::assertSame((string) $first['public_id'], (string) $reissued['public_id']);
        self::assertSame((string) $first['certificate_number'], (string) $reissued['certificate_number']);
        self::assertSame($minimal['id'], (int) $reissued['template_id']);
        self::assertStringContainsString('Original Learner', $this->documents->render($reissued)->body);
        self::assertStringNotContainsString('Renamed Learner', $this->documents->render($reissued)->body);
    }

