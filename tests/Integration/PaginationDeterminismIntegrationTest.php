Description:
Proves that paging through a list actually shows every row, exactly once, in a stable order.

This is the contract OFFSET pagination rests on and the one nothing was checking. A list query
whose ORDER BY is not a total order is not wrong on any single page - every page it returns is a
correct page of the dataset - but the *sequence* of pages is not a partition of it. PostgreSQL is
free to break a tie either way and is under no obligation to break it the same way twice, so a row
sitting on a page boundary can appear on page four and again on page five, while its neighbour
appears on neither. Nothing errors, the counts add up, and the reader simply never sees a person
who is definitely there.

Every fixture below is built to tie deliberately: people who share a name, courses that share a
title, requests raised in the same instant with the same status, enrolments assigned together. The
assertion is the strong one - reading the dataset in small pages must produce precisely the same
sequence as reading it in one, and the union of those pages must be the population the count query
reports. A weaker "no duplicates" check would pass on a query that silently skips a row.

What this test does NOT establish, and it matters: it cannot prove an ordering is total. Given a
tie PostgreSQL is *permitted* to return either order and, on one plan over a small fixture, it
reliably picks the same one. Removing the tiebreaker from Administration People and from Course
Requests was tried against these very assertions and they still passed - the queries were free to
lose rows and simply did not. `PaginationOrderingContractTest` is what covers that, by asserting
the ordering expressions themselves end in a unique column. This test covers what that one cannot:
that the counts and the pages describe one population, and that the deferred join returns its key
query's rows in its key query's order.

