    /**
     * The deferred join must return exactly the rows its key query selected, in that order.
     *
     * The key query and the detail query are two separate SELECTs sharing one ORDER BY expression.
     * If the detail query's joins were ever allowed to decide the order instead, every page would
     * hold the right rows in the wrong sequence - which looks like rows jumping around rather than
     * like an ordering defect, and is why it is asserted directly.
     */
    public function testDeferredJoinPreservesTheOrderOfItsKeyQuery(): void
    {
        $universe = DataUniverse::Seed;
        $rows = $this->administration->companyPeople($universe, $this->companyId, self::ROWS + 1, 0, '');

        $ids = array_map(static fn(array $row): int => (int) $row['id'], $rows);
        $expected = $ids;
        sort($expected);

        // Every fixture person shares a display name, so `sort_name` cannot separate them and the
        // id tiebreaker is the whole of the order. Ascending ids are therefore the only correct
        // answer, and any other sequence means the detail join reordered the page.
        self::assertSame($expected, $ids, 'The detail query must not reorder the page its key query selected.');
    }
