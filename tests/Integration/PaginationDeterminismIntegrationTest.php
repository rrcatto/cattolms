    /**
     * Reads a list page by page and asserts the sequence matches one unpaged read of the same rows.
     *
     * @param callable(int,int):list<array<string,mixed>> $page
     */
    private function assertPagesPartitionTheDataset(string $label, callable $page, int $total, string $idColumn = 'id'): void
    {
        self::assertGreaterThanOrEqual(
            self::ROWS,
            $total,
            $label . ': the fixture must actually be in the dataset, or this test asserts nothing.'
        );

        $whole = array_map(
            static fn(array $row): string => (string) $row[$idColumn],
            $page(max(self::ROWS, $total), 0)
        );

        $paged = [];
        for ($offset = 0; $offset < $total; $offset += self::PAGE_SIZE) {
            foreach ($page(self::PAGE_SIZE, $offset) as $row) {
                $paged[] = (string) $row[$idColumn];
            }
        }

        self::assertSame(
            count($paged),
            count(array_unique($paged)),
            $label . ': paging returned the same row twice, so its ordering is not a total order.'
        );
        self::assertSame(
            $total,
            count($paged),
            $label . ': paging returned a different number of rows than the count query promised.'
        );
        self::assertSame(
            array_slice($whole, 0, $total),
            $paged,
            $label . ': the sequence of pages differs from one unpaged read, so rows move between pages.'
        );
    }

