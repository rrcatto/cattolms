declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Course\CourseRepository;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\DevelopmentFixture;
use PHPUnit\Framework\TestCase;

final class CourseAuthoringWriteIntegrationTest extends TestCase
{
    public function testTheAuthoringGraphIsWrittenAndReadBack(): void
    {
        $container = CliBootstrap::boot()['container'];
        /** @var Database $sql */
        $sql = $container->get(Database::class);
        /** @var Database $db */
        $db = $container->get(Database::class);
        /** @var CourseRepository $repository */
        $repository = $container->get(CourseRepository::class);

        $fixture = new DevelopmentFixture($sql);
        $suffix = $fixture->suffix();
        $courseId = 0;
        $categoryId = 0;

        try {
            $ownerId = $fixture->createUser('QA author ' . $suffix);
            $companyId = $fixture->createCompany($ownerId, 'QA Author ' . $suffix, 'qa-author-' . $suffix . '.example.test');

            $categoryId = $repository->createCategory([
                'parent_id' => 0,
                'name' => 'QA Category ' . $suffix,
                'slug' => 'qa-category-' . $suffix,
                'description' => 'Temporary.',
                'position' => $repository->nextCategoryPosition(0),
            ]);
            self::assertGreaterThan(0, $categoryId);

            $repository->updateCategory($categoryId, [
                'name' => 'QA Category Renamed ' . $suffix,
                'slug' => 'qa-category-renamed-' . $suffix,
                'description' => 'Renamed.',
            ]);
            $category = $repository->categoryById($categoryId);
            self::assertNotNull($category);
            self::assertSame('QA Category Renamed ' . $suffix, (string) $category['name']);

            $courseId = $repository->createCourse([
                'category_id' => $categoryId,
                'slug' => 'qa-authoring-' . $suffix,
                'title' => 'QA Authoring Course',
                'subtitle' => '',
                'summary' => 'Summary.',
                'description_html' => '<p>Body.</p>',
                'level' => '',
                'estimated_minutes' => 60,
                'status' => 'draft',
                'default_access_period_seconds' => 2592000,
                'module_weight' => 0.6,
                'final_weight' => 0.4,
                'certificate_enabled' => true,
                'certificate_title' => '',
                'course_style_key' => '',
                'owner_company_id' => $companyId,
                'owner_user_id' => $ownerId,
            ], $ownerId);
            self::assertGreaterThan(0, $courseId);

            $repository->updateCourse($courseId, [
                'category_id' => $categoryId,
                'slug' => 'qa-authoring-' . $suffix,
                'title' => 'QA Authoring Course Renamed',
                'subtitle' => '',
                'summary' => 'Revised summary.',
                'description_html' => '<p>Revised body.</p>',
                'level' => '',
                'estimated_minutes' => 90,
                'default_access_period_seconds' => 2592000,
                'module_weight' => 0.5,
                'final_weight' => 0.5,
                'certificate_enabled' => false,
                'certificate_title' => '',
                'course_style_key' => '',
                'presentation_css' => '.from-update{}',
            ], $ownerId);
            $course = $repository->findById($courseId);
            self::assertNotNull($course);
            self::assertSame('QA Authoring Course Renamed', (string) $course['title']);
            self::assertSame(90, (int) $course['estimated_minutes']);
            self::assertSame('.from-update{}', (string) $course['presentation_css']);

            $repository->updatePresentationCss($courseId, '.from-css-editor{}', $ownerId);
            self::assertSame('.from-css-editor{}', (string) $repository->findById($courseId)['presentation_css']);

            $repository->updateCertificateSettings($courseId, [
                'certificate_enabled' => true,
                'certificate_title' => 'QA Certificate',
                'certificate_template' => 'classic',
                'certificate_body_text' => 'has successfully completed',
                'certificate_footer_text' => '',
                'certificate_signatory_name' => '',
                'certificate_signatory_title' => '',
            ], $ownerId);
            $certificated = $repository->findById($courseId);
            self::assertSame('QA Certificate', (string) $certificated['certificate_title']);
            self::assertNull($certificated['certificate_footer_text']);

            // Publishing stamps the date once. Unpublishing and republishing must not restamp it,
            // or a course's publication date would move every time its status was toggled.
            $repository->setStatus($courseId, 'published', $ownerId);
            $publishedAt = (string) $repository->findById($courseId)['published_at'];
            self::assertNotSame('', $publishedAt);
            $repository->setStatus($courseId, 'draft', $ownerId);
            $repository->setStatus($courseId, 'published', $ownerId);
            $republished = $repository->findById($courseId);
            self::assertSame($publishedAt, (string) $republished['published_at']);
            self::assertSame('approved', (string) $republished['publication_approval_status']);

            $repository->setApprovalStatus($courseId, 'pending', $ownerId);
            self::assertSame('pending', (string) $repository->findById($courseId)['publication_approval_status']);

            $items = $container->get(\CattoLearning\Course\CourseItemService::class);
            $records = $container->get(\CattoLearning\Course\CourseItemRepository::class);
            $assessmentId = $items->create(['item_key' => 'qa-assessment-' . $suffix, 'item_type' => 'assessment', 'title' => 'QA Assessment', 'pass_mark' => 50], $ownerId);
            $items->update($assessmentId, ['item_key' => 'qa-assessment-' . $suffix, 'item_type' => 'assessment', 'title' => 'QA Assessment Renamed', 'pass_mark' => 60], $ownerId);
            $assessmentNode = $items->addExisting($courseId, $assessmentId, ['assessment_role' => 'graded'], $ownerId);
            self::assertSame('QA Assessment Renamed', $items->item($assessmentId)['title']);
            self::assertSame(60, (int) $items->item($assessmentId)['pass_mark']);

            $records->replaceQuestions($assessmentId, [
                [
                    'question_html' => 'First question',
                    'points' => 2,
                    'options' => [
                        ['option_html' => 'Correct', 'is_correct' => true],
                        ['option_html' => 'Incorrect', 'is_correct' => false],
                    ],
                ],
                [
                    'question_html' => 'Second question',
                    'points' => 1,
                    'options' => [
                        ['option_html' => 'Only', 'is_correct' => true],
                    ],
                ],
            ]);
            $questions = $records->questions($assessmentId, true);
            self::assertCount(2, $questions);
            self::assertSame('First question', (string) $questions[0]['question_html']);
            self::assertCount(2, $questions[0]['options']);
            self::assertTrue($questions[0]['options'][0]['is_correct']);
            self::assertFalse($questions[0]['options'][1]['is_correct']);
            // Options belong to their own question: one query fetches them all, so a grouping
            // mistake would show up as the second question inheriting the first question's options.
            self::assertCount(1, $questions[1]['options']);
            self::assertSame('Only', (string) $questions[1]['options'][0]['option_html']);
            // Without includeCorrect the answer must not reach the caller at all.
            self::assertArrayNotHasKey('is_correct', $records->questions($assessmentId, false)[0]['options'][0]);

            $repository->replaceGradeBands($courseId, [
                ['grade_code' => 'A', 'grade_label' => 'Distinction', 'minimum_percentage' => 80, 'is_passing' => true],
                ['grade_code' => 'F', 'grade_label' => 'Fail', 'minimum_percentage' => 0, 'is_passing' => false],
            ]);
            $bands = $repository->gradeBands($courseId);
            self::assertCount(2, $bands);
            self::assertTrue($bands[0]['is_passing']);
            self::assertFalse($bands[1]['is_passing']);

            $repository->recordHistory($courseId, $ownerId, 'course.updated', 'course', $courseId, 'Checked.', ['checked' => true]);
            $history = $repository->history($courseId);
            self::assertNotEmpty($history);
            self::assertSame('course.updated', (string) $history[0]['event_key']);

            $firstVariantId = $repository->createPriceVariant($courseId, [
                'access_period_seconds' => 2592000,
                'price_minor_units' => 10000,
                'currency_code' => 'ZAR',
                'label' => 'One month',
                'position' => 1,
                'is_active' => true,
                'is_default' => true,
            ], $ownerId);
            $secondVariantId = $repository->createPriceVariant($courseId, [
                'access_period_seconds' => 5184000,
                'price_minor_units' => 15000,
                'currency_code' => 'ZAR',
                'label' => '',
                'position' => 2,
                'is_active' => true,
                'is_default' => false,
            ], $ownerId);
            self::assertCount(2, $repository->priceVariants($courseId));
            // An empty label is stored as NULL rather than an empty string.
            self::assertNull($repository->priceVariant($courseId, $secondVariantId)['label']);

            $repository->updatePriceVariant($courseId, $firstVariantId, [
                'access_period_seconds' => 2592000,
                'price_minor_units' => 20000,
                'currency_code' => 'ZAR',
                'label' => 'One month',
                'is_active' => true,
                'is_default' => true,
            ], $ownerId);
            self::assertSame(20000, (int) $repository->priceVariant($courseId, $firstVariantId)['price_minor_units']);

            $repository->swapPriceVariantPositions($courseId, $firstVariantId, $secondVariantId);
            self::assertSame(2, (int) $repository->priceVariant($courseId, $firstVariantId)['position']);
            self::assertSame(1, (int) $repository->priceVariant($courseId, $secondVariantId)['position']);

            $repository->deletePriceVariant($courseId, $secondVariantId);
            self::assertCount(1, $repository->priceVariants($courseId));

            $enrolmentId = $repository->grantCourse($ownerId, $courseId, 2592000, $ownerId);
            self::assertGreaterThan(0, $enrolmentId);

            $repository->startEnrolment($enrolmentId, $ownerId);
            $started = $repository->enrolmentByIdForUser($enrolmentId, $ownerId);
            self::assertNotNull($started);
            self::assertSame('active', (string) $started['status']);
            self::assertNotNull($started['expires_at']);

            // A certificate keeps the identity a learner may already have shared, so reissuing
            // updates the content and carries the public id and the number forward unchanged.
            $first = $repository->createCertificate(
                $enrolmentId, 'First Learner', 'QA Certificate', 'QA Authoring Course',
                'A', 91.5, 'classic', 'has successfully completed', '', '', ''
            );
            $second = $repository->createCertificate(
                $enrolmentId, 'Second Learner', 'QA Certificate', 'QA Authoring Course',
                'A', 91.5, 'classic', 'has successfully completed', '', '', ''
            );
            self::assertSame((string) $first['public_id'], (string) $second['public_id']);
            self::assertSame((string) $first['certificate_number'], (string) $second['certificate_number']);
            self::assertSame('Second Learner', (string) $second['learner_name']);
            self::assertStringContainsString('Second Learner', (string) $second['rendered_html']);
            $db->executeStatement('DELETE FROM certificates WHERE enrolment_id = :id', ['id' => $enrolmentId]);

            $repository->markEnrolmentExpired($enrolmentId);
            self::assertSame('expired', (string) $repository->enrolmentByIdForUser($enrolmentId, $ownerId)['status']);

            $repository->setCourseOwnership($courseId, $companyId, $ownerId, $ownerId);
            $owned = $repository->findById($courseId);
            self::assertSame($companyId, (int) $owned['owner_company_id']);
            self::assertSame($ownerId, (int) $owned['owner_user_id']);

            $items->removeFromCourse($courseId, $assessmentNode, $ownerId);
            $items->delete($assessmentId, $ownerId);
            self::assertNull($records->item($assessmentId));
        } finally {
            if ($courseId > 0) {
                $db->executeStatement('DELETE FROM course_enrolments WHERE course_id = :id', ['id' => $courseId]);
                $db->executeStatement('DELETE FROM courses WHERE id = :id', ['id' => $courseId]);
            }
            if ($categoryId > 0) {
                $db->executeStatement('DELETE FROM course_categories WHERE id = :id', ['id' => $categoryId]);
            }
            $fixture->cleanup();
        }
    }
}
