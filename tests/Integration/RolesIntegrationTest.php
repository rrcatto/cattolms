namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\RoleAdministrationService;
use CattoLearning\Auth\RoleCatalog;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Infrastructure\Persistence\RoleRepository;
use CattoLearning\Tests\Support\DevelopmentFixture;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoPHP\Access\Roles;
use Doctrine\DBAL\Exception as DatabaseError;
use PHPUnit\Framework\TestCase;
use RuntimeException;

final class RolesIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
        IntegrationContainer::get()->get(Roles::class)->refresh();
    }

    public function testTheBuiltInRolesKeepTheirPermissionsAndTheAdministratorHoldsEveryOne(): void
    {
        $roles = IntegrationContainer::get()->get(Roles::class);
        foreach (RoleCatalog::keys() as $key) self::assertArrayHasKey($key, $roles->all(), $key);
        self::assertContains('COMPANY.BILLING.MANAGE', $roles->get(RoleCatalog::COMPANY_ADMIN)->permissions);
        self::assertNotContains('COMPANY.BILLING.MANAGE', $roles->get(RoleCatalog::STUDENT)->permissions);
        self::assertSame(0, (int) $this->db->fetchOne("SELECT COUNT(*) FROM cattophp_role_permissions WHERE role_key = 'ADMIN' OR permission LIKE 'SYSTEM.%'"));

        $fixture = new DevelopmentFixture($this->db);
        $admin = $fixture->createUser('Roles administrator');
        IntegrationContainer::get()->get(RoleRepository::class)->assign($admin, RoleCatalog::ADMIN);
        self::assertSame([RoleCatalog::ADMIN, RoleCatalog::STUDENT], IntegrationContainer::get()->get(RoleRepository::class)->roles($admin), 'with the learner\'s baseline role');
        self::assertTrue($roles->may((string) $admin, 'SYSTEM.THEME.MANAGE'), 'every permission, SYSTEM ones too');
    }

    public function testARoleOfTheOwnersOwnFromMakingToDeleting(): void
    {
        $container = IntegrationContainer::get();
        $service = $container->get(RoleAdministrationService::class);
        $repository = $container->get(RoleRepository::class);
        $fixture = new DevelopmentFixture($this->db);
        $owner = $fixture->createUser('Roles owner');
        $holder = $fixture->createUser('Roles holder');

        $key = $service->create(['role_key' => 'qa_reviewer', 'role_name' => 'QaReviewer', 'role_description' => 'Reads the catalogue.'], $owner);
        self::assertSame('QA_REVIEWER', $key);
        $service->savePermissions($key, ['CATALOGUE.VIEW', 'SYSTEM.THEME.VIEW'], $owner);
        self::assertSame(['CATALOGUE.VIEW'], $repository->permissionKeysForRole($key), 'a SYSTEM permission is never offered to a role');
        try {
            $repository->replaceRolePermissions($key, ['SYSTEM.THEME.VIEW']);
            self::fail('A role took a SYSTEM permission.');
        } catch (RuntimeException) {
            self::assertSame(['CATALOGUE.VIEW'], $repository->permissionKeysForRole($key));
        }
        $this->db->executeStatement('SAVEPOINT system_guard');
        try {
            $this->db->executeStatement("INSERT INTO cattophp_role_permissions (role_key, permission) VALUES ('QA_REVIEWER', 'SYSTEM.THEME.VIEW')");
            self::fail('The database kept a SYSTEM permission for a role.');
        } catch (DatabaseError) {
            $this->db->executeStatement('ROLLBACK TO SAVEPOINT system_guard');
        }

        $repository->assign($holder, $key);
        self::assertContains('CATALOGUE.VIEW', $repository->permissionsForUser($holder));
        $renamed = $service->update($key, ['role_key' => 'QA_READER', 'role_name' => 'QaReader', 'role_description' => 'Reads it all.'], $owner);
        self::assertSame('QA_READER', $renamed);
        self::assertSame(['QA_READER', RoleCatalog::STUDENT], $repository->roles($holder), 'the holder follows the new key');
        self::assertSame(['role_key' => 'QA_READER', 'role_name' => 'QaReader', 'role_description' => 'Reads it all.', 'user_count' => 1], $repository->findByKey('qa_reader'));
        try {
            $service->delete($renamed, $owner);
            self::fail('A role someone holds was deleted.');
        } catch (RuntimeException $refused) {
            self::assertSame('Remove this role from all users before deleting it.', $refused->getMessage());
        }
        $repository->revoke($holder, $renamed);
        $service->delete($renamed, $owner);
        self::assertNull($repository->findByKey($renamed));

        $logged = $this->db->fetchAllAssociative("SELECT action, actor_id, details FROM cattophp_activity WHERE subject_type = 'role' AND subject_id IN ('QA_REVIEWER', 'QA_READER') ORDER BY id");
        self::assertSame(['access.role_made', 'access.role_changed', 'access.role_renamed', 'access.role_changed', 'access.role_deleted'], array_column($logged, 'action'));
        self::assertSame([(string) $owner], array_values(array_unique(array_column($logged, 'actor_id'))), 'each by the person who made the change');
        $permissions = json_decode((string) $logged[1]['details'], true);
        self::assertSame([[], ['CATALOGUE.VIEW']], [$permissions['old_permissions'], $permissions['permissions']]);
        $described = json_decode((string) $logged[3]['details'], true);
        self::assertSame(['Reads the catalogue.', 'Reads it all.', 'QaReviewer', 'QaReader'], [$described['old_description'], $described['description'], $described['old_name'], $described['name']]);
    }

    public function testAPersonDeletedLosesTheirRoles(): void
    {
        $person = (new DevelopmentFixture($this->db))->createUser('Roles leaver');
        IntegrationContainer::get()->get(RoleRepository::class)->assign($person, RoleCatalog::COMPANY_ADMIN);
        self::assertSame(2, (int) $this->db->fetchOne('SELECT COUNT(*) FROM cattophp_account_roles WHERE account_id = CAST(:id AS TEXT)', ['id' => $person]));
        $this->db->executeStatement('DELETE FROM users WHERE id = :id', ['id' => $person]);
        self::assertSame(0, (int) $this->db->fetchOne('SELECT COUNT(*) FROM cattophp_account_roles WHERE account_id = CAST(:id AS TEXT)', ['id' => $person]));
    }
}
