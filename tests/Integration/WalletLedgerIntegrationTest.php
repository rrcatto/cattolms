    public function testWalletCreditIsSpentOldestFirstAndGoesBackWithItsOwnExpiry(): void
    {
        $buyer = $this->buyer();
        $me = WalletOwner::person($buyer->id);
        $this->wallets->credit($me, 'overpayment_to_wallet', 30000, 'ZAR', 'eft');
        $this->clock->modify('+1 day');
        $this->wallets->credit($me, 'refund_to_wallet', 40000, 'ZAR', 'stitch');
        self::assertSame(70000, $this->wallets->balance($me));

        $this->orders->changeCart($buyer, $this->course['A']['variant']);
        $orderId = $this->buy($buyer, 'eft', true);
        self::assertSame('fulfilled', $this->records->order($orderId)['state'], 'The wallet paid the whole order, so it completed when placed.');
        self::assertSame(20000, $this->wallets->balance($me));
        self::assertSame([['2029-10-17', 0], ['2029-10-18', 20000]], $this->lots($me), 'The older credit was spent first.');
        $payments = $this->records->payments($orderId);
        self::assertSame([['wallet', 50000, 'paid']], array_map(static fn(array $p): array => [$p['gateway'], (int) $p['amount_minor'], $p['state']], $payments));
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM commerce_documents WHERE order_id=:o AND kind='receipt'", ['o' => $orderId]), 'The wallet payment has a receipt.');

        $this->clock->modify('+2 days');
        $refunds = $this->refunds();
        $item = $this->records->items($orderId)[0];
        $quote = $refunds->quote($this->records->order($orderId), $item, 50000, 'money_back');
        self::assertSame([50000, 0, [], 0], [$quote['wallet_part'], $quote['external'], $quote['deductions'], $quote['net']], 'What the wallet paid always goes back to the wallet, with nothing deducted.');
        $refunds->approve($this->admin(), $orderId, (int) $item['id'], Uuid::v4(), 'service_failure', 'The course could not be provided.', 1, 50000, 'Faulty course confirmed.', 'money_back');
        self::assertSame(70000, $this->wallets->balance($me));
        self::assertSame([['2029-10-17', 30000], ['2029-10-18', 40000]], $this->lots($me), 'Each credit came back with the expiry it had.');
        self::assertSame(0, (int) $this->db->fetchOne("SELECT COUNT(*) FROM commerce_ledger_entries WHERE order_id=:o AND kind='refund_owed'", ['o' => $orderId]), 'Nothing is owed as money back.');

        $page = InProcessPage::run($buyer, WalletController::class, 'mine')['body'];
        foreach (['Paid from wallet', 'Refund to wallet', 'Overpayment credited to wallet'] as $row) self::assertStringContainsString($row, $page, 'My Wallet lists ' . $row . '.');
    }

    public function testAnEftThatIsTooLittleWaitsAndOneThatIsTooMuchCreditsTheWallet(): void
    {
        $buyer = $this->buyer();
        $admin = $this->admin();
        $this->orders->changeCart($buyer, $this->course['A']['variant']);
        $orderId = $this->buy($buyer, 'eft');
        self::assertSame('awaiting_payment', $this->records->order($orderId)['state']);
        $page = InProcessPage::run($buyer, \CattoLearning\Commerce\Http\CommerceController::class, 'order', ['id' => (string) $orderId])['body'];
        $reference = AccountReference::format((string) $this->db->fetchOne('SELECT account_reference FROM users WHERE id=:id', ['id' => $buyer->id]));
        self::assertStringContainsString('Use your account reference as the payment reference: <strong>' . $reference . '</strong>', $page, 'The EFT instructions quote the account reference.');

        $bank = $this->bank();
        $bank->confirmBank($admin, $orderId, Uuid::v4(), 20000, $this->clock->now()->format(DATE_ATOM), 'FNB-0001', 'Seen in the bank account.');
        self::assertSame('awaiting_payment', $this->records->order($orderId)['state'], 'Too little: the order waits for the rest.');
        self::assertSame(30000, $this->records->dueAmount($orderId));
        $attention = $this->attention();
        $underpaid = $this->itemsFor($attention, $orderId);
        self::assertSame(['underpaid'], array_column($underpaid, 'kind'));
        self::assertStringContainsString('still due by', $underpaid[0]['summary']);

        $bank->confirmBank($admin, $orderId, Uuid::v4(), 40000, $this->clock->now()->format(DATE_ATOM), 'FNB-0002', 'The rest, and more.');
        self::assertSame('fulfilled', $this->records->order($orderId)['state'], 'Paid in full: the course starts.');
        self::assertSame(10000, $this->wallets->balance(WalletOwner::person($buyer->id)), 'R100 more than was due went to the wallet.');
        self::assertSame([['payment_received', 20000, 'eft'], ['payment_received', 40000, 'eft'], ['overpayment_to_wallet', 10000, 'eft']],
            array_map(static fn(array $r): array => [$r['kind'], (int) $r['amount_minor'], $r['method']], $this->db->fetchAllAssociative("SELECT kind, amount_minor, method FROM commerce_ledger_entries WHERE order_id=:o ORDER BY id", ['o' => $orderId])));
        $overpaid = $this->itemsFor($attention, $orderId);
        self::assertSame(['overpaid'], array_column($overpaid, 'kind'), 'The underpaid item is resolved and the overpayment needs attention.');

        $detail = $attention->detail('overpaid', $overpaid[0]['reference']);
        self::assertSame($reference, $detail['account_reference']);
        self::assertStringContainsString('went to your wallet', $detail['body']);
        $attention->email($admin, 'overpaid', $overpaid[0]['reference'], $detail['subject'], $detail['body']);
        self::assertSame('administrator_message', $this->mailer->messages[0]['type'] ?? null);
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM commerce_attention_emails WHERE kind='overpaid' AND reference=:r", ['r' => $overpaid[0]['reference']]), 'The email is kept with the item.');
        try {
            $attention->email($this->buyer(), 'overpaid', $overpaid[0]['reference'], 'Hello', 'Not allowed.');
            self::fail('Only ADMIN writes about a transaction.');
        } catch (RuntimeException $exception) {
            self::assertSame('You cannot act on transactions.', $exception->getMessage());
        }
        $attention->dismiss($admin, 'overpaid', $overpaid[0]['reference'], 'Emailed the learner.');
        self::assertSame([], $this->itemsFor($attention, $orderId));
    }

    public function testACancelledOrderGivesWhatWasPaidToTheWalletAndSoDoesALatePayment(): void
    {
        $buyer = $this->buyer();
        $me = WalletOwner::person($buyer->id);
        $this->wallets->credit($me, 'refund_to_wallet', 10000, 'ZAR', 'stitch');
        $this->orders->changeCart($buyer, $this->course['A']['variant']);
        $orderId = $this->buy($buyer, 'eft', true);
        self::assertSame(['awaiting_payment', 40000], [$this->records->order($orderId)['state'], $this->records->dueAmount($orderId)], 'The wallet paid R100 and R400 is left to pay by EFT.');
        self::assertSame(0, $this->wallets->balance($me));
        $bank = $this->bank();
        $bank->confirmBank($this->admin(), $orderId, Uuid::v4(), 15000, $this->clock->now()->format(DATE_ATOM), 'FNB-0003', 'Part of it.');

        $this->clock->modify('+8 days');
        self::assertTrue($this->orders->cancelDue($orderId));
        self::assertSame('cancelled', $this->records->order($orderId)['state']);
        self::assertSame(25000, $this->wallets->balance($me), 'The wallet part came back and the EFT became wallet credit.');
        self::assertSame([['2029-10-17', 10000], ['2029-10-25', 15000]], $this->lots($me), 'The returned credit keeps its expiry; the EFT is new credit.');
        self::assertSame(['cancelled_paid'], array_column($this->itemsFor($this->attention(), $orderId), 'kind'));

        $bank->confirmBank($this->admin(), $orderId, Uuid::v4(), 25000, $this->clock->now()->format(DATE_ATOM), 'FNB-0004', 'Arrived after the cancellation.');
        self::assertSame('cancelled', $this->records->order($orderId)['state'], 'A late payment does not revive the order');
        self::assertSame(50000, $this->wallets->balance($me), 'but becomes wallet credit.');
    }

    public function testCreditExpiresAfterTheSettingInForceAndIsRemindedAboutOnce(): void
    {
        $buyer = $this->buyer();
        $me = WalletOwner::person($buyer->id);
        $this->wallets->credit($me, 'refund_to_wallet', 10000, 'ZAR', 'stitch');
        $this->wallets->correct($me, -4000, 'ZAR', 'Spent at the front desk by agreement.', $this->admin()->id);
        self::assertSame(6000, $this->wallets->balance($me));
        $maintenance = new CommerceMaintenance($this->records, $this->orders, $this->access, IntegrationContainer::get()->get(FinancialDocuments::class), $this->mailer, new TransactionManager($this->db), $this->clock, $this->wallets);

        $this->clock->modify('+3 years -31 days');
        $maintenance->remindWallets();
        self::assertSame([], $this->remindersFor($buyer), 'Not yet: the reminder period is 30 days.');
        $this->clock->modify('+2 days');
        $maintenance->remindWallets();
        $sent = $this->remindersFor($buyer);
        self::assertCount(1, $sent);
        self::assertSame('17 October 2029', $sent[0]['lines'][0]['expires'], 'The reminder names the credit and its expiry date.');
        $maintenance->remindWallets();
        self::assertCount(1, $this->remindersFor($buyer), 'Each credit is reminded about once.');

        $this->clock->modify('+28 days');
        self::assertSame(6000, $this->wallets->spendable($me), 'Spendable until the moment it expires.');
        $this->clock->modify('+1 day');
        self::assertSame(0, $this->wallets->spendable($me));
        self::assertSame(1, $this->wallets->expireDue());
        self::assertSame(0, $this->wallets->expireDue(), 'Expired once.');
        self::assertSame(0, $this->wallets->balance($me));
        self::assertSame(6000, (int) $this->db->fetchOne("SELECT SUM(amount_minor) FROM commerce_ledger_entries WHERE owner_user_id=:u AND kind='credit_expired'", ['u' => $buyer->id]), 'Only what was left expired.');
    }

    public function testAWalletNeverGoesBelowNothingAndTheLedgerIsAppendOnly(): void
