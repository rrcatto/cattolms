    /** Places the buyer's cart, paying by the simulated card or choosing EFT, with or without the wallet. */
    private function buy(CurrentUser $buyer, string $method = 'dummy', bool $useWallet = false): int
    {
        $this->billing->saveOwn($buyer, BillingFixture::personFields('Wallet Buyer'));
        $_SESSION['checkout'][$buyer->id] = ['profile_confirmed' => true, 'payment_method' => $method, 'method_token' => $method === 'dummy' ? 'demo_success' : '', 'invoice_email' => false, 'payment_key' => Uuid::v4(), 'use_wallet' => $useWallet];
        $cart = $this->orders->cart($buyer);
        return (int) $this->checkout($buyer)->place($buyer, (int) $cart['id'], (string) $cart['quote'], true, true);
    }

    private function checkout(CurrentUser $buyer): CheckoutService
    {
        $auth = clone IntegrationContainer::get()->get(AuthService::class);
        (new \ReflectionProperty(AuthService::class, 'currentUser'))->setValue($auth, $buyer);
        return new CheckoutService($auth, $this->orders, $this->records, $this->payments, $this->fulfilment, new TransactionManager($this->db), $this->analytics(), $this->billing);
    }

