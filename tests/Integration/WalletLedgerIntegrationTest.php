    public function testWalletCreditIsSpentOldestFirstAndGoesBackWithItsOwnExpiry(): void
    {
        $buyer = $this->buyer();
        $me = WalletOwner::person($buyer->id);
        $this->wallets->credit($me, 'overpayment_to_wallet', 30000, 'ZAR', 'eft');
        // Credit with no order is not an order's overpayment: the dashboard does not list it, and its
        // page is not found rather than an error (owner, 2026-10-18: "500 Request failed").
        $orphan = (string) $this->db->fetchOne("SELECT MAX(id) FROM commerce_ledger_entries WHERE owner_user_id = :u AND kind = 'overpayment_to_wallet'", ['u' => $buyer->id]);
        self::assertSame([], array_values(array_filter($this->attention()->items(500), static fn(array $item): bool => $item['reference'] === $orphan && $item['kind'] === 'overpaid')));
        try {
            InProcessPage::run($this->admin(), AttentionController::class, 'show', ['kind' => 'overpaid', 'reference' => $orphan]);
            self::fail('A credit with no order opened as an attention item.');
        } catch (NotFoundHttpException $missing) {
            self::assertSame('That item does not exist.', $missing->getMessage());
        }
        $this->clock->modify('+1 day');
        $this->wallets->credit($me, 'refund_to_wallet', 40000, 'ZAR', 'stitch');
        self::assertSame(70000, $this->wallets->balance($me));

        $this->orders->changeCart($buyer, $this->course['A']['variant']);
        $orderId = $this->buy($buyer, 'eft', true);
        self::assertSame('fulfilled', $this->records->order($orderId)['state'], 'The wallet paid the whole order, so it completed when placed.');
        self::assertSame(20000, $this->wallets->balance($me));
        self::assertSame([['2029-10-17', 0], ['2029-10-18', 20000]], $this->lots($me), 'The older credit was spent first.');
        $payments = $this->records->payments($orderId);
        self::assertSame([['wallet', 50000, 'paid']], array_map(static fn(array $p): array => [$p['gateway'], (int) $p['amount_minor'], $p['state']], $payments));
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM commerce_documents WHERE order_id=:o AND kind='receipt'", ['o' => $orderId]), 'The wallet payment has a receipt.');

        $this->clock->modify('+2 days');
        $refunds = $this->refunds();
        $item = $this->records->items($orderId)[0];
        $quote = $refunds->quote($this->records->order($orderId), $item, 50000, 'money_back');
        self::assertSame([50000, 0, [], 0], [$quote['wallet_part'], $quote['external'], $quote['deductions'], $quote['net']], 'What the wallet paid always goes back to the wallet, with nothing deducted.');
