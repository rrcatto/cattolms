        $references[] = (string) $this->db->fetchOne('SELECT account_reference FROM companies WHERE id=:id', ['id' => $company]);
        self::assertCount(3, array_unique($references), 'Every person and company has their own reference.');
        foreach ($references as $reference) {
            self::assertMatchesRegularExpression('/^CL' . date('Ymd') . '\d{4,}[0-9A-Z]$/', $reference);
            self::assertSame($reference, AccountReference::parse(AccountReference::format($reference)), 'PHP accepts the database\'s check character.');
        }
        foreach (['CL202610170001', 'ZZ202901010042', 'A202612319999', 'CLM202611050317'] as $body) {
            self::assertSame(AccountReference::checkCharacter($body), $this->db->fetchOne('SELECT account_reference_check(:body)', ['body' => $body]), $body);
