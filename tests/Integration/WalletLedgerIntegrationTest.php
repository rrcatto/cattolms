    public function testAccountReferencesComeFromTheDatabaseWithTheCheckCharacterPhpComputes(): void
    {
        $users = [$this->fixture->createUser('Reference one'), $this->fixture->createUser('Reference two')];
        $company = $this->fixture->createCompany($users[0], 'Reference company ' . $this->fixture->suffix(), $this->fixture->suffix() . '.reference.example.test');
        $references = [];
        foreach ($users as $id) $references[] = (string) $this->db->fetchOne('SELECT account_reference FROM users WHERE id=:id', ['id' => $id]);
        $references[] = (string) $this->db->fetchOne('SELECT account_reference FROM companies WHERE id=:id', ['id' => $company]);
        self::assertCount(3, array_unique($references), 'Every person and company has their own reference.');
        foreach ($references as $reference) {
            self::assertMatchesRegularExpression('/^CL' . date('Ymd') . '\d{4,}[0-9A-Z]$/', $reference);
            self::assertSame($reference, AccountReference::parse(AccountReference::format($reference)), 'PHP accepts the database\'s check character.');
        }
        foreach (['CL202610170001', 'ZZ202901010042', 'A202612319999', 'CLM202611050317'] as $body) {
            self::assertSame(AccountReference::checkCharacter($body), $this->db->fetchOne('SELECT account_reference_check(:body)', ['body' => $body]), $body);
        }

        WalletFixture::settings($this->db)->saveSection('references', ['account_prefix' => 'ZZ'], $users[0]);
        $later = (string) $this->db->fetchOne('SELECT account_reference FROM users WHERE id=:id', ['id' => $this->fixture->createUser('Reference three')]);
        self::assertStringStartsWith('ZZ', $later, 'A new account takes the prefix in force.');
        self::assertTrue(AccountReference::isValid($later));
        self::assertSame($references[0], $this->db->fetchOne('SELECT account_reference FROM users WHERE id=:id', ['id' => $users[0]]), 'An existing reference never changes.');
        $this->db->executeStatement('SAVEPOINT reference_guard');
        try {
            $this->db->executeStatement('UPDATE users SET account_reference = :r WHERE id = :id', ['r' => $references[1], 'id' => $users[0]]);
            self::fail('Two accounts cannot share a reference.');
        } catch (\Doctrine\DBAL\Exception) {
            $this->db->executeStatement('ROLLBACK TO SAVEPOINT reference_guard');
        }
    }

    /** @return list<array{0:string,1:int}> each credit's expiry date and what it holds now, oldest first */
    private function lots(WalletOwner $owner): array
    {
        $rows = $this->db->fetchAllAssociative('SELECT l.expires_at, l.amount_minor - COALESCE((SELECT SUM(a.amount_minor) FROM commerce_wallet_allocations a WHERE a.lot_id = l.id), 0) AS remaining
            FROM commerce_wallet_lots l JOIN commerce_wallets w ON w.id = l.wallet_id WHERE w.owner_user_id = :u ORDER BY l.issued_at, l.id', ['u' => $owner->userId]);

        return array_map(static fn(array $row): array => [(new \DateTimeImmutable((string) $row['expires_at']))->setTimezone(new \DateTimeZone('Africa/Johannesburg'))->format('Y-m-d'), (int) $row['remaining']], $rows);
    }

    /**
     * @return list<array<string,mixed>>
     *
     * @phpstan-impure the reminders sent so far
     */
    private function remindersFor(CurrentUser $buyer): array
    {
        $email = (string) $this->db->fetchOne('SELECT email FROM user_emails WHERE user_id=:u AND is_primary', ['u' => $buyer->id]);

        $sent = [];
        foreach ($this->mailer->messages as $message) {
            if (($message['type'] ?? '') === 'wallet_expiry_reminder' && ($message['email'] ?? '') === $email) $sent[] = $message;
        }

        return $sent;
    }

    /** @return list<array<string,mixed>> */
    private function itemsFor(TransactionAttention $attention, int $orderId): array
    {
        return array_values(array_filter($attention->items(500), static fn(array $item): bool => str_contains($item['title'], sprintf('CL-%08d', $orderId))));
    }

