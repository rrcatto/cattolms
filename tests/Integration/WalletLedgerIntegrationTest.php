            'INSERT INTO commerce_wallet_allocations(lot_id, ledger_entry_id, amount_minor, created_at) VALUES (' . $lot . ', ' . $entry . ', -1, NOW())' => 'nor take back more than it gave.',
            'UPDATE commerce_ledger_entries SET amount_minor = 5 WHERE id = ' . $entry => 'Ledger rows are never changed',
            'DELETE FROM commerce_ledger_entries WHERE id = ' . $entry => 'or deleted.'] as $sql => $rule) {
            $this->db->executeStatement('SAVEPOINT wallet_guard');
            try {
                $this->db->executeStatement($sql);
                self::fail($rule);
            } catch (\Doctrine\DBAL\Exception) {
                $this->db->executeStatement('ROLLBACK TO SAVEPOINT wallet_guard');
                self::addToAssertionCount(1);
            }
        }
        self::assertSame(1000, $this->wallets->balance($me));
