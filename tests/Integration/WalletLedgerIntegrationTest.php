    /** @return list<array{0:string,1:int}> each credit's expiry date and what it holds now, oldest first */
    private function lots(WalletOwner $owner): array
    {
        $rows = $this->db->fetchAllAssociative('SELECT l.expires_at, l.amount_minor - COALESCE((SELECT SUM(a.amount_minor) FROM commerce_wallet_allocations a WHERE a.lot_id = l.id), 0) AS remaining
            FROM commerce_wallet_lots l JOIN commerce_wallets w ON w.id = l.wallet_id WHERE w.owner_user_id = :u ORDER BY l.issued_at, l.id', ['u' => $owner->userId]);

        return array_map(static fn(array $row): array => [(new \DateTimeImmutable((string) $row['expires_at']))->setTimezone(new \DateTimeZone('Africa/Johannesburg'))->format('Y-m-d'), (int) $row['remaining']], $rows);
    }

    /**
     * @return list<array<string,mixed>>
     *
     * @phpstan-impure the reminders sent so far
     */
    private function remindersFor(CurrentUser $buyer): array
    {
        $email = (string) $this->db->fetchOne('SELECT email FROM user_emails WHERE user_id=:u AND is_primary', ['u' => $buyer->id]);

        $sent = [];
        foreach ($this->mailer->messages as $message) {
            if (($message['type'] ?? '') === 'wallet_expiry_reminder' && ($message['email'] ?? '') === $email) $sent[] = $message;
        }

        return $sent;
    }

