    /** @return array<string,mixed> the commerce services, each keeping its messages through the real hook */
    private function services(string $mode = 'live'): array
    {
        $container = IntegrationContainer::get();
        $records = new CommerceRepository($this->db);
        $tx = new TransactionManager($this->db);
        $transitions = $container->get(TransitionService::class);
        $promotions = PromotionFixture::service($this->db, $this->clock);
        $documents = $container->get(FinancialDocuments::class);
        $orders = new OrderService($records, $tx, WalletFixture::settings($this->db), $transitions, $this->clock, $promotions, $documents, WalletFixture::wallets($this->db, $this->clock));
        $access = new AccessService($records, $tx, $transitions, $this->clock);
        $analytics = new AnalyticsEventRecorder(new AnalyticsEventRepository($this->db), $this->clock);
        $fulfilment = new FulfilmentService($records, $transitions, $access, $tx, $orders, $this->clock, new CompanyCreditFulfilment($records, $container->get(AdministrationRepository::class), $container->get(CourseRepository::class), $this->clock), $analytics, $promotions, $this->owners($mode));
        $payments = new PaymentService($records, $tx, $orders, new OmnipayPaymentGatewayAdapter(SiteMode::fixed('demo'), $this->clock), $fulfilment, $transitions, $this->clock, $documents, WalletFixture::wallets($this->db, $this->clock), WalletFixture::settings($this->db));
        $billing = BillingFixture::service($this->db, $this->clock);
        $checkout = function (CurrentUser $buyer) use ($orders, $records, $payments, $fulfilment, $analytics, $billing): CheckoutService {
            $auth = clone IntegrationContainer::get()->get(AuthService::class);
            (new \ReflectionProperty(AuthService::class, 'currentUser'))->setValue($auth, $buyer);

            return new CheckoutService($auth, $orders, $records, $payments, $fulfilment, new TransactionManager($this->db), $analytics, $billing);
        };

        return ['records' => $records, 'orders' => $orders, 'fulfilment' => $fulfilment, 'payments' => $payments, 'billing' => $billing, 'checkout' => $checkout];
    }

    /** @return array{0:int,1:array<string,mixed>} the order, paid with the simulated card, and the services */
    private function buy(CurrentUser $buyer, int $variant, string $mode = 'live'): array
    {
        $services = $this->services($mode);
        $services['orders']->changeCart($buyer, $variant);

        return [$this->pay($buyer, $services), $services];
    }

    /** @param array<string,mixed> $services */
    private function pay(CurrentUser $buyer, array $services): int
    {
        $services['billing']->saveOwn($buyer, BillingFixture::personFields('Sale Buyer'));
        $_SESSION['checkout'][$buyer->id] = ['profile_confirmed' => true, 'payment_method' => 'dummy', 'method_token' => 'demo_success', 'invoice_email' => false, 'payment_key' => Uuid::v4()];
        $cart = $services['orders']->cart($buyer);
        $order = (int) $services['checkout']($buyer)->place($buyer, (int) $cart['id'], (string) $cart['quote'], true, true);
        self::assertSame('fulfilled', $services['records']->order($order)['state']);

        return $order;
    }
