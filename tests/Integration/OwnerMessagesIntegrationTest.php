        self::assertSame([true, '4242', 'connected', 'Connected: @site_alerts_bot to @your_username', 'success'], [$setup->view()['connected'], $this->settings->saved()['chat_id'], $setup->view()['state'], $setup->view()['title'], $setup->view()['title_tone']]);
