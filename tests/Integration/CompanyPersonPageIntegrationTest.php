final class CompanyPersonPageIntegrationTest extends TestCase
{
    private Database $db;
    private IntegrationDataFixture $fixture;
    /** @var array<string,mixed> */
    private array $cookies = [];

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->fixture = new IntegrationDataFixture($this->db);
        $this->cookies = $_COOKIE;
        $_SESSION['csrf'] = str_repeat('c', 64);
    }

    protected function tearDown(): void
    {
        $_COOKIE = $this->cookies;
        $this->fixture->cleanup();
    }

    public function testACompanyAdministratorOpensTheirMembersPage(): void
    {
        $suffix = $this->fixture->suffix();
        $manager = $this->fixture->createUser('Company manager ' . $suffix, 'person-manager-' . $suffix . '@seed.test');
        $this->fixture->grantRole($manager, 'COMPANY_ADMIN');
        $company = $this->fixture->createCompany($manager, 'Person page ' . $suffix, 'person-page-' . $suffix . '.seed.test');
        $this->fixture->addCompanyMember($company, $manager, 'company_admin');
        $member = $this->fixture->createUser('Lerato Member' . $suffix, 'person-member-' . $suffix . '@seed.test');
        $this->fixture->addCompanyMember($company, $member);
        $outsider = $this->fixture->createUser('Not Here' . $suffix, 'person-outsider-' . $suffix . '@seed.test');
        $this->signIn($manager);

        $page = $this->send('/company/people/' . $member);
        self::assertSame(200, $page->getStatusCode(), substr(strip_tags((string) $page->getContent()), 0, 300));
        $html = (string) $page->getContent();
        $reference = AccountReference::format((string) $this->db->fetchOne('SELECT account_reference FROM users WHERE id = :id', ['id' => $member]));
        foreach (['Lerato Member' . $suffix, $reference, 'person-member-' . $suffix . '@seed.test', '>Courses<', '>Course requests<', 'Remove from the company'] as $text) {
            self::assertStringContainsString($text, $html);
        }
        self::assertStringNotContainsString('+02</dd>', $html, 'Dates are written out, not raw timestamps.');
        self::assertSame(404, $this->send('/company/people/' . $outsider)->getStatusCode(), 'A person outside the company is not found.');

        // Disabling them from their page comes back to their page.
        $back = $this->post('/company/people/' . $member . '/status', ['status' => 'disabled', 'return' => '/company/people/' . $member]);
        self::assertSame('/company/people/' . $member, $back->headers->get('Location'));
        self::assertSame('disabled', $this->db->fetchOne('SELECT status FROM users WHERE id = :id', ['id' => $member]));
        // The company's lists link the name to this page.
        self::assertStringContainsString('href="/company/people/' . $member . '"', (string) $this->send('/company/people')->getContent());
    }

    private function signIn(int $user): void
    {
        $token = Token::generate();
        IntegrationContainer::get()->get(AuthSessionRepository::class)->create($user, Token::hash($token), 3600, 'qa', 'PHPUnit');
        $_COOKIE = $this->cookies;
        $_COOKIE[Env::string('AUTH_SESSION_COOKIE', 'catto_learning_session')] = $token;
    }

    private function send(string $url): Response
    {
        $kernel = new Kernel('test', true, CliBootstrap::boot()['instance_root']);
        try {
            return $kernel->handle(Request::create($url, 'GET'));
        } finally {
            $kernel->shutdown();
        }
    }

    /** @param array<string,string> $fields */
    private function post(string $url, array $fields): Response
    {
        $_POST = ['csrf' => $_SESSION['csrf']] + $fields;
        $kernel = new Kernel('test', true, CliBootstrap::boot()['instance_root']);
        try {
            return $kernel->handle(Request::create($url, 'POST', $_POST));
        } finally {
            $kernel->shutdown();
            $_POST = [];
        }
    }
}
