    public function testAnOverridingPriceTakesTheDefaultsPlaceWhileItIsOnSale(): void
    {
        [$course, $owner] = $this->course();
        $default = (int) $this->db->fetchOne('SELECT id FROM course_price_variants WHERE course_id = :c AND is_default', ['c' => $course]);
        $promotion = $this->price($course, $owner, '1500', ['label' => 'December promotion', 'starts_at' => self::at('-1 hour'), 'ends_at' => self::at('+30 days'), 'overrides_default' => '1']);
        self::assertSame([['price' => 150000, 'was' => 250000, 'default' => true]], $this->onSale($course), 'The promotion replaces the default, the default struck through beside it.');
        $offers = IntegrationContainer::get()->get(CommerceRepository::class);
        self::assertFalse($offers->offer($default)['is_active'], 'The default it replaces cannot be bought meanwhile.');
        self::assertTrue($offers->offer($promotion)['is_active']);

        // To the minute, not the day: an hour from now is not yet, a minute ago has ended.
        $this->db->executeStatement('UPDATE course_price_variants SET starts_at = :s, ends_at = NULL WHERE id = :id', ['s' => self::stored('+1 hour'), 'id' => $promotion]);
        self::assertSame([['price' => 250000, 'was' => null, 'default' => true]], $this->onSale($course), 'Not started: the default is on sale.');
        self::assertFalse($offers->offer($promotion)['is_active'], 'A price not yet on sale cannot be bought.');
        $this->db->executeStatement('UPDATE course_price_variants SET starts_at = NULL, ends_at = :e WHERE id = :id', ['e' => self::stored('-1 minute'), 'id' => $promotion]);
        self::assertSame([['price' => 250000, 'was' => null, 'default' => true]], $this->onSale($course), 'Ended: the default is back.');
        $this->db->executeStatement('UPDATE course_price_variants SET starts_at = NULL, ends_at = :e WHERE id = :id', ['e' => self::stored('+2 hours'), 'id' => $promotion]);
        self::assertSame([['price' => 150000, 'was' => 250000, 'default' => true]], $this->onSale($course), 'Until later today: still on sale.');
        $this->db->executeStatement('UPDATE course_price_variants SET ends_at = :e WHERE id = :id', ['e' => self::stored('-1 minute'), 'id' => $promotion]);

        // A dated price that overrides nothing is another choice beside the default while it is on sale.
        $this->price($course, $owner, '900', ['access_period_value' => '6', 'label' => 'Six months this week', 'starts_at' => self::at('-1 minute'), 'ends_at' => self::at('+6 days')]);
        self::assertSame([['price' => 250000, 'was' => null, 'default' => true], ['price' => 90000, 'was' => null, 'default' => false]], $this->onSale($course));
    }

    public function testAnOverrideNeedsADefaultAndTheDatesMustMakeSense(): void
    {
        $tag = $this->fixture->suffix();
        $owner = $this->fixture->createUser('Price author', 'price-author-' . $tag . '@example.test');
        $company = $this->fixture->createCompany($owner, 'Pricing provider ' . $tag, $tag . '.pricing.example.test');
        $course = $this->fixture->createCourse($owner, $company, 'override-' . $tag, 'Override course', 'draft');
        foreach ([
            [['overrides_default' => '1'], 'There is no default price to override yet: make a price the default first.'],
            [['starts_at' => '2026-12-31T09:00', 'ends_at' => '2026-12-01T09:00'], 'The end of the sale must be after its start.'],
            [['starts_at' => '2026-12-01T09:00', 'ends_at' => '2026-12-01T09:00'], 'The end of the sale must be after its start.'],
            [['starts_at' => '2026-02-30T09:00'], 'Enter "On sale from" as a date and time, or leave it empty.'],
            [['ends_at' => '2026-12-01'], 'Enter "On sale until" as a date and time, or leave it empty.'],
            [['is_default' => '1', 'overrides_default' => '1'], 'A price cannot be the default and override the default: untick one of them.'],
        ] as [$more, $refusal]) {
            try {
                $this->price($course, $owner, '1000', $more);
                self::fail($refusal);
            } catch (InvalidArgumentException $refused) {
                self::assertSame($refusal, $refused->getMessage());
            }
        }
        $dated = $this->price($course, $owner, '1000', ['starts_at' => self::at('+10 days')]);
        self::assertFalse((bool) $this->db->fetchOne('SELECT is_default FROM course_price_variants WHERE id = :id', ['id' => $dated]), 'A dated price never becomes the default by itself.');
    }

