    public function testTheStatusDocumentIsServedByTheKernel(): void
    {
        $response = $this->kernelResponse(Request::create('/api/v1'));

        self::assertSame(200, $response->getStatusCode());
        self::assertSame('application/json; charset=utf-8', $response->headers->get('Content-Type'));

        $payload = json_decode((string) $response->getContent(), true, 512, JSON_THROW_ON_ERROR);
        self::assertSame('v1', $payload['data']['api_version'] ?? null);
        // The release is composer.json's, so this never needs editing when the version changes.
        $composer = json_decode((string) file_get_contents(dirname(__DIR__, 2) . '/composer.json'), true, 512, JSON_THROW_ON_ERROR);
        self::assertSame((string) $composer['version'], $payload['data']['application_version'] ?? null);
        self::assertSame('Bearer token', $payload['data']['authentication'] ?? null);
        self::assertNotSame('', (string) ($payload['data']['name'] ?? ''));
    }

    /** Every page names the full release that made it (owner, 2026-10-20: "I want the FULL FUCKING VERSION NUMBER ON EACH PAGE"). */
    public function testEveryPageNamesTheFullReleaseThatMadeIt(): void
    {
        $composer = json_decode((string) file_get_contents(dirname(__DIR__, 2) . '/composer.json'), true, 512, JSON_THROW_ON_ERROR);
        self::assertMatchesRegularExpression('/^[0-9]+\.[0-9]+\.[0-9]+/', (string) $composer['version']);
        self::assertSame((string) $composer['version'], \CattoLearning\Support\AppVersion::current());
        foreach (['/', '/courses', '/terms'] as $path) {
            $html = (string) $this->kernelResponse(Request::create($path))->getContent();
            self::assertStringContainsString(', CattoLMS v' . $composer['version'] . '">', $html, $path . ': the generator names the release in full.');
            self::assertMatchesRegularExpression('/<meta name="generator" content="CattoPHP [^",]+, CattoLMS v/', $html, $path);
        }
    }

    public function testEveryKernelResponseCarriesTheSecurityHeaders(): void
    {
        $headers = $this->kernelResponse(Request::create('/api/v1'))->headers;

        self::assertSame('SAMEORIGIN', $headers->get('X-Frame-Options'), 'the site frames its own previews');
        self::assertSame('nosniff', $headers->get('X-Content-Type-Options'));
        self::assertStringContainsString('no-store', (string) $headers->get('Cache-Control'));
        self::assertStringContainsString("frame-ancestors 'self'", (string) $headers->get('Content-Security-Policy'));
        self::assertStringContainsString('microphone=(self)', (string) $headers->get('Permissions-Policy'), 'narration is recorded on the site');
        self::assertFalse($headers->has('X-XSS-Protection'), 'retired: browsers no longer read it');
    }

    /** CattoPHP Phase 2, step 7c: a script runs only from the site's own files or with the page's nonce, and no tag has a handler. */
    public function testEveryScriptOnAPageCarriesItsNonceOrComesFromTheSite(): void
    {
        foreach (['/', '/courses', '/login', '/register', '/contact', '/help'] as $path) {
            $response = $this->kernelResponse(Request::create($path));
            $policy = (string) $response->headers->get('Content-Security-Policy');
            self::assertMatchesRegularExpression("/script-src 'self' 'nonce-[A-Za-z0-9_-]+';/", $policy, $path);
            self::assertStringNotContainsString('unsafe-eval', $policy, $path);
            preg_match("/'nonce-([A-Za-z0-9_-]+)'/", $policy, $nonce);
            $html = (string) $response->getContent();
            preg_match_all('/<script\b([^>]*)>/i', $html, $scripts);
            self::assertNotEmpty($scripts[1], $path);
            foreach ($scripts[1] as $attributes) {
                if (preg_match('/\ssrc="\//', $attributes) === 1 || str_contains($attributes, 'type="application/ld+json"')) continue;
                self::assertStringContainsString('nonce="' . $nonce[1] . '"', $attributes, $path . ': <script' . $attributes . '>');
            }
            self::assertSame(0, preg_match('/<[a-zA-Z][^>]*\son[a-z]+\s*=/', $html), $path . ': a tag with an event handler');
        }
    }

    /**
     * Every route the platform declares is matched by the kernel.
     *
     * This used to assert the opposite for most paths: while Fat-Free still owned them, a kernel
     * that quietly started matching one would have taken the request away from the controller that
     * served it. Fat-Free is gone, so the risk inverted - what would be wrong now is a declared
     * route the router cannot find, which is a 404 on a page that exists.
     */
    public function testEveryDeclaredRouteIsMatchable(): void
    {
        $router = self::kernel()->getContainer()->get('router');
        $collection = $router->getRouteCollection();

        $declared = RouteTable::all();
        self::assertGreaterThan(170, count($declared), 'The declared routes unexpectedly shrank.');

        foreach ($declared as $route) {
            self::assertNotNull(
                $collection->get($route['name']),
                $route['method'] . ' ' . $route['path'] . ' is declared but the router does not carry it.'
            );
        }
    }

    /**
     * Both connections must agree about the session timezone.
     *
     * There are two: the platform's own, built by ConnectionFactory, and DoctrineBundle's, built
     * from config/packages/doctrine.yaml. They are configured in different files and neither
     * mentions the other, so nothing but this stops one from being changed alone - and a
     * disagreement is invisible until a timestamp is read back an hour or two out.
     */
    public function testBothConnectionsShareTheSessionTimeZone(): void
    {
        $expected = Env::string('APP_TIMEZONE', 'Africa/Johannesburg');

        /** @var Database $platform */
        $platform = CliBootstrap::boot()['container']->get(Database::class);
        /** @var Database $kernel */
        $kernel = $this->kernel()->getContainer()->get('test.service_container')->get(Database::class);

        self::assertSame($expected, (string) $platform->fetchOne('SHOW TimeZone'));
        self::assertSame($expected, (string) $kernel->fetchOne('SHOW TimeZone'));
    }


    private function kernelResponse(Request $request): \Symfony\Component\HttpFoundation\Response
    {
        return $this->kernel()->handle($request);
    }

    private function kernel(): Kernel
    {
        $instanceRoot = (string) CliBootstrap::boot()['instance_root'];
        // Booted as 'test' so that config/services.yaml's when@test block makes services public;
        // it also keeps the compiled container out of the cache the running site uses.
        $kernel = new Kernel('test', true, $instanceRoot);
        $kernel->boot();

        return $kernel;
    }
