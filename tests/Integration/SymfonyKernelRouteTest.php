declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Kernel;
use CattoLearning\Support\Env;
use PHPUnit\Framework\TestCase;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\Routing\Exception\MethodNotAllowedException;
use Symfony\Component\Routing\Exception\ResourceNotFoundException;
use Symfony\Component\Routing\Matcher\RequestMatcherInterface;
use Symfony\Component\Routing\RouterInterface;

final class SymfonyKernelRouteTest extends TestCase
{
    public function testTheStatusDocumentIsServedByTheKernel(): void
    {
        $response = $this->kernelResponse(Request::create('/api/v1'));

        self::assertSame(200, $response->getStatusCode());
        self::assertSame('application/json; charset=utf-8', $response->headers->get('Content-Type'));

        $payload = json_decode((string) $response->getContent(), true, 512, JSON_THROW_ON_ERROR);
        self::assertSame('v1', $payload['data']['api_version'] ?? null);
        self::assertSame('0.5.8.2', $payload['data']['application_version'] ?? null);
        self::assertSame('Bearer token', $payload['data']['authentication'] ?? null);
        self::assertNotSame('', (string) ($payload['data']['name'] ?? ''));
    }

    public function testEveryKernelResponseCarriesThePlatformHeaders(): void
    {
        $headers = $this->kernelResponse(Request::create('/api/v1'))->headers;

        self::assertSame('SAMEORIGIN', $headers->get('X-Frame-Options'));
        self::assertSame('1; mode=block', $headers->get('X-XSS-Protection'));
        self::assertSame('nosniff', $headers->get('X-Content-Type-Options'));
        self::assertStringContainsString('no-store', (string) $headers->get('Cache-Control'));
    }

    /**
     * Paths Fat-Free still owns are declined, and a half-ported path is declined per method.
     *
     * The list is deliberately a sample of each shape the platform routes: a themed page, a page
     * with a placeholder, a form target, and two method mismatches - POST to a path Symfony owns
     * only for GET, and a verb no ported route declares at all.
     */
    public function testFatFreeRoutesAreNotMatched(): void
    {
        foreach ([['GET', '/'], ['GET', '/courses'], ['GET', '/courses/anything'],
                  ['GET', '/login'], ['POST', '/api/v1'], ['POST', '/contact'],
                  ['DELETE', '/api/v1/admin/courses/1']] as [$method, $path]) {
            self::assertFalse(
                $this->kernelMatches(Request::create($path, $method)),
                $method . ' ' . $path . ' must fall through to Fat-Free.'
            );
        }
    }

    /**
     * Both connections must agree about the session timezone.
     *
     * There are two: the platform's own, built by ConnectionFactory, and DoctrineBundle's, built
     * from config/packages/doctrine.yaml. They are configured in different files and neither
     * mentions the other, so nothing but this stops one from being changed alone - and a
     * disagreement is invisible until a timestamp is read back an hour or two out.
     */
    public function testBothConnectionsShareTheSessionTimeZone(): void
    {
        $expected = Env::string('APP_TIMEZONE', 'Africa/Johannesburg');

        /** @var Database $platform */
        $platform = CliBootstrap::boot()['container']->get(Database::class);
        /** @var Database $kernel */
        $kernel = $this->kernel()->getContainer()->get('test.service_container')->get(Database::class);

        self::assertSame($expected, (string) $platform->fetchOne('SHOW TimeZone'));
        self::assertSame($expected, (string) $kernel->fetchOne('SHOW TimeZone'));
    }

    private function kernelMatches(Request $request): bool
    {
        $kernel = $this->kernel();
        /** @var RouterInterface&RequestMatcherInterface $router */
        $router = $kernel->getContainer()->get('router');
        $router->getContext()->fromRequest($request);

        try {
            $router->matchRequest($request);
        } catch (ResourceNotFoundException | MethodNotAllowedException) {
            return false;
        }

        return true;
    }

    private function kernelResponse(Request $request): \Symfony\Component\HttpFoundation\Response
    {
        return $this->kernel()->handle($request);
    }

    private function kernel(): Kernel
    {
        $instanceRoot = (string) CliBootstrap::boot()['instance_root'];
        // Booted as 'test' so that config/services.yaml's when@test block makes services public;
        // it also keeps the compiled container out of the cache the running site uses.
        $kernel = new Kernel('test', true, $instanceRoot);
        $kernel->boot();

        return $kernel;
    }
}
