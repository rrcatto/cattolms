    public function testModulesAddedOrRemovedKeepTheStyling(): void
    {
        $course = $this->import(OriginalBuildExample::html(), 'grow.html');
        $package = $this->portability->exportCourse($course);
        $sections = array_values(array_filter($package['structure'], static fn(array $row): bool => $row['node_type'] === 'section' && !empty($row['numbered'])));
        $added = $package;
        $key = (string) $sections[1]['node_key'];
        $added['structure'][] = ['node_key' => 'added', 'title' => 'Harvest and storage', 'position' => (int) $sections[1]['position'] + 1] + $sections[1];
        foreach ($package['structure'] as $row) {
            if (($row['parent_node_key'] ?? null) === $key) { $added['structure'][] = ['parent_node_key' => 'added'] + $row; }
        }
        foreach ($added['structure'] as &$row) { if (($row['parent_node_key'] ?? null) === null && $row['node_type'] === 'item') { $row['position'] = (int) $row['position'] + 10; } }
        unset($row);
        $more = $this->files->render($added)['html'];
        self::assertStringContainsString('class="module acc-item" id="mod-m3"', $more, 'A new module, in the course\'s own panel.');
        self::assertStringContainsString('Harvest and storage', $more);
        self::assertMatchesRegularExpression('/ALL_IDS = \["m1", "m2", "m3", "final"\]/', $more, 'Counted by its script.');
        self::assertStringContainsString('<span class="eyebrow">Module 03</span>', $more);
        self::assertStringContainsString('<b>3</b> modules', $more);
        self::assertStringContainsString('function gradeQuiz(id)', $more);

        $fewer = $package;
        $fewer['structure'] = array_values(array_filter($package['structure'], static fn(array $row): bool => ($row['node_key'] ?? null) !== $key && ($row['parent_node_key'] ?? null) !== $key));
        $less = $this->files->render($fewer)['html'];
        self::assertStringNotContainsString('id="mod-m2"', $less);
        self::assertMatchesRegularExpression('/ALL_IDS = \["m1", "final"\]/', $less);
        self::assertStringContainsString('function gradeQuiz(id)', $less, 'The styling and the script stay.');
    }

