    private function withoutData(string $file): string
    {
        return (string) preg_replace('/<script\b.*?<\/script>/s', '', $file);
    }

    private function import(string $content, string $name, string $code = OriginalBuildExample::CODE, ?int $replace = null): int
    {
        $file = (string) tempnam(sys_get_temp_dir(), 'course-file');
        file_put_contents($file, $content);
        try {
            $analysis = $this->portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => $name, 'tmp_name' => $file], $this->admin);
            return $this->portability->commitImport((string) $analysis['import_key'], 0, $this->admin, $replace, $code);
        } finally {
            @unlink($file);
        }
    }
