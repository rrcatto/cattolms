        self::assertSame($files, (int) $this->db->fetchOne('SELECT count(*) FROM resources'), 'Its files are the site\'s, not copies.');
        self::assertSame('published', $this->courses->findByCode($code)['status']);
    }

    /**
     * Two courses imported, the first related to the second, both published, and the package that made them.
     *
     * @return array{0:string,1:string,2:string,3:array<string,mixed>,4:array<string,array<string,mixed>>}
     */
    private function pairOnTheSite(bool $relatedInFile = true): array
    {
        $a = 'CNA-' . $this->tail;
        $b = 'CNB-' . $this->tail;
        $catalogue = $this->catalogue([$a, $b]);
        $catalogue['categories'][0]['children'][] = ['name' => 'Cn elsewhere ' . $this->suffix, 'slug' => 'cn-elsewhere-' . $this->suffix, 'icon' => self::ICON];
        $catalogue['tags'][] = ['name' => 'Cn spare ' . $this->suffix, 'icon' => self::ICON];
        $courses = [$a => $this->course($a, 'cn-a-' . $this->suffix), $b => $this->course($b, 'cn-b-' . $this->suffix)];
        $courses[$b]['course']['title'] = 'Second canonical course ' . $this->suffix;
        if ($relatedInFile) {
            $courses[$a]['catalogue']['related'] = [$b];
            $courses[$b]['catalogue']['related'] = [$a];
        }
        $zip = $this->zip($catalogue, $courses, []);
        $this->import($zip);
        return [$a, $b, $zip, $catalogue, $courses];
    }

    /** The first course changed here in every way the file speaks of. */
    private function changeOnTheSite(int $aId, int $bId, ?int $third): void
    {
        $elsewhere = (int) $this->db->fetchOne('SELECT id FROM course_categories WHERE name = :n', ['n' => 'Cn elsewhere ' . $this->suffix]);
        $this->db->executeStatement('UPDATE courses SET category_id = :c, catalogue_position = 17, cover_svg = :cover WHERE id = :id', ['c' => $elsewhere, 'cover' => self::OTHER_COVER, 'id' => $aId]);
        $this->service->setCourseTagsByName($aId, ['Cn spare ' . $this->suffix], $this->admin);
        $this->db->executeStatement('UPDATE course_price_variants SET price_minor_units = 99900 WHERE course_id = :c', ['c' => $aId]);
        IntegrationContainer::get()->get(\CattoLearning\Course\CoursePageLayouts::class)->choose($aId, 'custom', null, null, $this->admin);
        $this->courses->replaceRelatedCourses($aId, $third === null ? [] : [$third]);
        $this->service->changeStatus($aId, 'draft', $this->admin);
        unset($bId);
    }

    /**
     * @param array<string,mixed> $plan
     * @return array<string,mixed>
     */
    private function row(array $plan, string $code): array
    {
        foreach ($plan['courses'] as $row) if ($row['code'] === $code) return $row;
        self::fail('The review has no ' . $code . '.');
    }

    /** @return list<string> */
    private function tagsOf(int $courseId): array
    {
        $names = array_map('strval', $this->db->fetchFirstColumn('SELECT t.name FROM course_tags ct JOIN tags t ON t.id = ct.tag_id WHERE ct.course_id = :c ORDER BY t.name', ['c' => $courseId]));
        return $names;
    }

