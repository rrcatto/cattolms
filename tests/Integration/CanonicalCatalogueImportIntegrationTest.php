    public function testAnImportOfAReviewTheSiteHasSinceChangedFromIsRefusedAndChangesNothing(): void
    {
        // The import does exactly what the review showed: a price set here after the review was drawn is a difference
        // nobody saw, so the import is refused and asks for the review again, rather than taking the price away.
        [$a, , $zip] = $this->pairOnTheSite();
        $aId = (int) $this->courses->findByCode($a)['id'];
        $plan = $this->package->plan($this->package->stageFile($zip, 'catalogue.zip', $this->admin));
        self::assertSame('unchanged', $this->row($plan, $a)['action']);
        $this->service->createPriceVariant($aId, ['access_period_value' => '2', 'access_period_unit' => 'years', 'price' => '1800.00', 'currency_code' => 'ZAR', 'is_active' => '1'], $this->admin);
        try {
            $this->package->apply($plan['key'], ['fingerprint' => $plan['fingerprint'] ?? 'not given'], $this->admin);
            self::fail('An import of a review the site has changed from is refused.');
        } catch (\InvalidArgumentException $refused) {
            self::assertStringContainsString('changed after the review', $refused->getMessage());
