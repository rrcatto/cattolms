        self::assertCount(2, $this->courses->priceVariants($aId, true), 'The price set after the review is still there.');
        $again = $this->package->plan($plan['key']);
        self::assertSame('Prices: R 950,00 (was R 1 250,00) for 1 year, R 1 800,00 for 2 years → R 950,00 (was R 1 250,00) for 1 year', self::plain(array_column($this->row($again, $a)['differences'], 'words', 'kind')['prices'] ?? ''),
            'The staged package is kept, and the review drawn again shows the difference.');
    }

    public function testThisSitesOwnCatalogueComesBackWithNoDifferenceAndChangesNothing(): void
    {
        // Every course and bundle on this site exported and reviewed at once, as the owner backs the catalogue up: the
        // review finds nothing to change, and importing it changes nothing.
        $export = $this->files[] = $this->package->export($this->admin);
        $plan = $this->package->plan($this->package->stageFile($export, 'catalogue.zip', $this->admin));
        $differing = [];
        foreach ($plan['courses'] as $row) if ($row['action'] !== 'unchanged') $differing[] = $row['code'] . ' ' . $row['action'] . ': ' . implode(' | ', $row['changes'] ?: [$row['reason']]);
        foreach ($plan['bundles'] as $row) if ($row['action'] !== 'unchanged') $differing[] = $row['code'] . ' ' . $row['action'] . ': ' . implode(' | ', $row['changes'] ?: [$row['reason']]);
        foreach ($plan['files'] as $file) if ($file['state'] !== 'same') $differing[] = $file['name'] . ' ' . $file['state'];
        self::assertSame([], $differing, 'The site\'s own catalogue is the site.');
        self::assertSame(count($plan['courses']), $plan['counts']['unchanged']);
        $codes = array_column($plan['courses'], 'code');
        $state = fn(): array => array_column($this->db->fetchAllAssociative('SELECT c.code, c.updated_at::text || \' \' || coalesce(c.category_id::text, \'\') || \' \' || c.status AS state FROM courses c WHERE c.code = ANY(CAST(:codes AS text[])) ORDER BY c.code',
            ['codes' => '{' . implode(',', $codes) . '}']), 'state', 'code');
        $before = $state();
        $report = $this->package->apply($plan['key'], [], $this->admin);
        self::assertSame([count($plan['courses']), 0, 0, 0, 0], [$report['counts']['unchanged'], $report['counts']['updated'], $report['counts']['replaced'], $report['counts']['failed'], $report['files_replaced']], json_encode(array_filter($report['courses'], static fn(array $c): bool => $c['outcome'] !== 'unchanged')) ?: '');
        self::assertSame($before, $state(), 'Not one course was touched.');
    }

    public function testARealCoursesContentReplacedFromItsOwnPackageComesBackTheSame(): void
    {
        // A course of this site with its files, which nobody has started: its own package, its lesson changed here, then
        // imported, gives the package's content back; the same package then finds no difference at all.
        $code = (string) $this->db->fetchOne("SELECT c.code FROM courses c WHERE c.status = 'published'
            AND EXISTS (SELECT 1 FROM course_item_placements p JOIN course_items ci ON ci.id = p.course_item_id WHERE p.course_id = c.id AND ci.resource_id IS NOT NULL)
            AND NOT EXISTS (SELECT 1 FROM course_enrolments e WHERE e.course_id = c.id AND e.started_at IS NOT NULL AND e.is_preview = FALSE)
            AND NOT EXISTS (SELECT 1 FROM course_item_placements p JOIN course_slide_narrations n ON n.course_item_id = p.course_item_id WHERE p.course_id = c.id)
            ORDER BY c.code LIMIT 1");
        if ($code === '') self::markTestSkipped('No published course with files that nobody has started.');
        $id = (int) $this->courses->findByCode($code)['id'];
        $export = $this->files[] = $this->package->export($this->admin, [$id]);
        $files = (int) $this->db->fetchOne('SELECT count(*) FROM resources');
        $lesson = $this->db->fetchAssociative("SELECT ci.id, ci.content_source FROM course_item_placements p JOIN course_items ci ON ci.id = p.course_item_id WHERE p.course_id = :c AND ci.item_type = 'html_lesson' ORDER BY ci.id LIMIT 1", ['c' => $id]);
        $this->db->executeStatement('UPDATE course_items SET content_source = :s WHERE id = :id', ['s' => '<p>Changed for the check.</p>', 'id' => (int) $lesson['id']]);
        $plan = $this->package->plan($this->package->stageFile($export, 'course.zip', $this->admin));
        self::assertSame(['content'], array_column($this->row($plan, $code)['differences'], 'kind'), implode(' | ', $this->row($plan, $code)['changes']));
        $report = $this->package->apply($plan['key'], [], $this->admin);
        self::assertSame(1, $report['counts']['replaced'], json_encode($report['courses']) ?: '');
        $again = $this->package->plan($this->package->stageFile($export, 'course.zip', $this->admin));
        self::assertSame([], $this->row($again, $code)['changes'], 'Its own package finds it as it was.');
