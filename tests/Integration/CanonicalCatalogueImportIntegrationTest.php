    public function testAFileOfTheSameNameIsReplacedInPlaceAndEveryCourseUsingItGetsIt(): void
    {
        $name = 'cn-workbook-' . $this->suffix . '.txt';
        $first = 'CNB-' . $this->tail;
        $second = 'CNC-' . $this->tail;
        $old = self::uuid();
        // A course on the site uses the workbook.
        $this->import($this->zip($this->catalogue([$first]), [$first => $this->course($first, 'cn-b-' . $this->suffix, $old, $name)], [$old => [$name, "The old workbook.\n"]]));
        $resources = IntegrationContainer::get()->get(ResourceLibraryService::class);
        $this->files[] = $resources->path(['filename' => $name]);
        $site = $this->db->fetchAssociative('SELECT id, public_id::text AS public_id FROM resources WHERE original_filename = :n', ['n' => $name]);
        self::assertIsArray($site);

        // Another course's package carries a newer workbook of the same name, under a public id of its own.
        $new = self::uuid();
        $zip = $this->zip($this->catalogue([$second]), [$second => $this->course($second, 'cn-c-' . $this->suffix, $new, $name)], [$new => [$name, "The new workbook, longer.\n"]]);
        $plan = $this->package->plan($this->package->stageFile($zip, 'catalogue.zip', $this->admin));
        $report = $this->package->apply($plan['key'], [], $this->admin);
        self::assertSame(0, $report['counts']['failed'], json_encode($report['courses']) ?: '');
        self::assertSame([(int) $site['id']], array_map('intval', $this->db->fetchFirstColumn('SELECT id FROM resources WHERE original_filename = :n', ['n' => $name])),
            'The record is kept: no second file of that name.');
        self::assertSame("The new workbook, longer.\n", file_get_contents($resources->path(['filename' => $name])), 'Its contents are the file\'s; the old ones are gone.');
        self::assertSame(strlen("The new workbook, longer.\n"), (int) $this->db->fetchOne('SELECT byte_size FROM resources WHERE id = :id', ['id' => (int) $site['id']]));
        foreach ([$first, $second] as $code) {
            self::assertSame((int) $site['id'], (int) $this->db->fetchOne(
                'SELECT ci.resource_id FROM course_item_placements p JOIN course_items ci ON ci.id = p.course_item_id JOIN courses c ON c.id = p.course_id WHERE c.code = :c AND ci.resource_id IS NOT NULL',
                ['c' => $code]), $code . ' uses the site\'s file.');
        }
        self::assertNull($this->db->fetchOne('SELECT id FROM resources WHERE public_id = :p', ['p' => $new]) ?: null, 'Nothing is kept under the package\'s public id.');
        $file = array_values(array_filter($plan['files'] ?? [], static fn(array $f): bool => $f['name'] === $name))[0] ?? null;
        self::assertSame('differs', $file['state'] ?? null, 'The review listed the file by its name, as different.');
        self::assertContains($name . ' differs and will be replaced (also used by ' . $first . ')', array_column($plan['courses'][0]['differences'] ?? [], 'words'), 'Said in words, with the courses that use it.');

        $again = $this->package->plan($this->package->stageFile($zip, 'catalogue.zip', $this->admin));
        self::assertSame('same', array_values(array_filter($again['files'] ?? [], static fn(array $f): bool => $f['name'] === $name))[0]['state'] ?? null, 'The same package again: the file is the same.');
        self::assertSame([], $again['courses'][0]['differences']);
    }

