    /** Fills the sections a new page leaves empty, so the page can be published. */
    private function complete(): void
    {
        $page = $this->landing->page($this->course);
        foreach ($page['sections'] as $section) {
            $input = match ($section['section_type']) {
                'hero' => ['headline' => 'Become a conveyancer', 'text' => 'Practical training.', 'image' => 'cover', 'secondary' => 'contents'],
                'audience' => ['items' => "Candidate attorneys\nConveyancing secretaries"],
                'outcomes' => ['items' => 'Draft a deed of transfer'],
                'benefits' => ['items' => [['title' => 'Practical', 'text' => 'Real precedents.']]],
                'faq' => ['items' => [['question' => 'How long do I have?', 'answer' => 'A year.']]],
                default => null,
            };
            if ($input !== null) {
                $this->landing->updateSection($this->course, $section['id'], $input, $this->owner);
            }
        }
    }

