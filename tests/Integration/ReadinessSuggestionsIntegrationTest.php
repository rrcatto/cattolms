    #[DataProvider('numbering')]
    public function testAVisitorIsShownTheSameModulesAndOpensWhatThePreviewShows(int $first): void
    {
        $this->importCourse($first);
        // The readiness check and the first module are in the public preview, as a course shows them before it is bought.
        $firstModule = $this->course['modules'][$first];
        $this->db->executeStatement('UPDATE course_item_placements SET public_preview = TRUE WHERE node_id = :node OR node_id IN (SELECT id FROM course_structure_nodes WHERE parent_node_id = :module)', ['node' => $this->course['diagnostic']['node'], 'module' => $firstModule]);
        $this->db->executeStatement('UPDATE course_sections SET public_preview = TRUE WHERE node_id = :module', ['module' => $firstModule]);
        $before = $this->counts();

        $container = IntegrationContainer::get();
        $attempts = $container->get(PublicAssessmentAttempts::class);
        $course = (array) $this->db->fetchAssociative('SELECT * FROM courses WHERE id = :id', ['id' => $this->course['id']]);
        $attempt = $attempts->session($attempts->start($course, $this->course['diagnostic']['node'], $this->course['diagnostic']['key'], 'diagnostic'));
        while ($attempt['status'] === 'in_progress') {
            $question = (int) $attempts->view($attempt)['question']['question_id'];
            $attempt = $attempts->respond($attempt, $question, $this->answer($question), false)['attempt'];
        }
        $result = $attempts->result($attempt, $container->get(CourseItemService::class)->availability($this->course['id'], null, true));

        $this->assertSuggestsBothModules($result['study_suggestions'] ?? null, $first, true);
        self::assertSame($before, $this->counts(), 'A visitor\'s attempt writes nothing.');

        $saved = $_SESSION ?? [];
        $_SESSION = ['public_assessment_attempts' => [(string) $attempt['public_id'] => $attempt]];
        try {
            $page = InProcessPage::run(null, CoursePresentationController::class, 'assessmentResult', ['slug' => $this->course['slug'], 'session' => (string) $attempt['public_id']]);
        } finally {
            $_SESSION = $saved;
        }
        self::assertSame(200, $page['status'], (string) $page['location']);
        $this->assertPageLinks($page['body'], $first, 'preview');
    }

    /**
     * Two suggestions in course order: the first module for the one wrong answer that names it, the second for the two
     * that name it; the reference to a module the course does not have, and the question answered correctly, add none.
     *
     * @param mixed $suggestions
     */
    private function assertSuggestsBothModules(mixed $suggestions, int $first, bool $publicPreview): void
    {
        self::assertIsArray($suggestions, 'The result says what to study.');
        self::assertSame([$first, $first + 1], array_column($suggestions, 'module'), 'Each module the wrong answers name, in course order, numbered as the course numbers them.');
        self::assertSame([1, 2], array_column($suggestions, 'questions'));
        self::assertSame(['Module ' . $first . ': Soil, compost and containers', 'Module ' . ($first + 1) . ': ' . self::SECOND], array_column($suggestions, 'heading'));
        self::assertSame(self::STUDY, array_column($suggestions[0]['parts'], 'label'), 'The parts a learner studies, never the practical work or the assessment.');
        foreach ($suggestions[0]['parts'] as $part) {
            self::assertSame($this->course['modules'][$first], (int) $part['row']['parent_node_id'], 'Each part is in the module it names.');
            self::assertFalse($part['locked']);
        }
        if ($publicPreview) {
            self::assertSame([], $suggestions[1]['parts'], 'A module the preview does not show opens nothing there.');
            self::assertTrue($suggestions[1]['elsewhere'], 'and is named as part of the full course.');
        } else {
            self::assertSame(self::STUDY, array_column($suggestions[1]['parts'], 'label'));
            self::assertFalse($suggestions[1]['elsewhere']);
        }
    }

    /** The result page lists the suggestions and links each part where the reader opens it. */
    private function assertPageLinks(string $html, int $first, string $where): void
    {
        $dom = new DOMDocument();
        @$dom->loadHTML($html);
        $xpath = new DOMXPath($dom);
        self::assertSame(1.0, $xpath->evaluate('count(//*[@data-study-suggestions]//h2[normalize-space()="What to study first"])'), 'The result says what to study first.');
        $shown = [];
        foreach ($xpath->query('//*[@data-study-suggestion]') ?: [] as $node) {
            if ($node instanceof \DOMElement) $shown[] = $node->getAttribute('data-study-module');
        }
        self::assertSame([(string) $first, (string) ($first + 1)], $shown);
        $structure = IntegrationContainer::get()->get(CourseItemService::class)->availability($this->course['id'], null, false);
        foreach ([$first, $first + 1] as $number) {
            $parts = array_values(array_filter($structure, fn(array $row): bool => (int) $row['parent_node_id'] === $this->course['modules'][$number] && in_array($row['part'], ['presentation', 'video', 'lesson', 'summary', 'flashcards'], true)));
            self::assertCount(count(self::STUDY), $parts);
            foreach ($parts as $row) {
                $href = $where === 'preview' ? CoursePartAddress::preview($this->course['slug'], $row) : CoursePartAddress::reader($this->course['slug'], $row);
                $linked = $xpath->evaluate('count(//*[@data-study-module="' . $number . '"]//a[@href="' . $href . '"])');
                self::assertSame($where === 'preview' && $number !== $first ? 0.0 : 1.0, $linked, 'Module ' . $number . ' ' . $row['part'] . ' at ' . $href);
            }
        }
        if ($where === 'preview') {
            self::assertSame('in the full course', trim((string) $xpath->evaluate('string(//*[@data-study-module="' . ($first + 1) . '"]//*[@data-study-elsewhere])')));
        }
    }

    /** Every question wrong but the one marked to be answered correctly. */
    private function answer(int $question): int
    {
        $right = str_contains((string) $this->db->fetchOne('SELECT question_html FROM assessment_questions WHERE id = :q', ['q' => $question]), 'drainage holes');
        return (int) $this->db->fetchOne('SELECT id FROM assessment_options WHERE question_id = :q AND is_correct = :right ORDER BY position LIMIT 1', ['q' => $question, 'right' => $right ? 'true' : 'false']);
    }

    /**
     * The course specification's example grown to two modules with a readiness check, imported as an administrator.
     */
    private function importCourse(int $first): void
    {
        $code = $first === 1 ? 'GDN-102' : 'GDN-103';
        if ((int) $this->db->fetchOne('SELECT count(*) FROM courses WHERE code = :code', ['code' => $code]) > 0) self::markTestSkipped($code . ' is on this site.');
        $html = self::twoModules(SpecificationExample::html(), $first, $code, $first === 1 ? 'Container Gardening Basics' : 'Container Gardening Workshop');
        $file = (string) tempnam(sys_get_temp_dir(), 'readiness');
        file_put_contents($file, $html);
        $portability = IntegrationContainer::get()->get(CoursePortabilityService::class);
        try {
            $analysis = $portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => 'readiness.html', 'tmp_name' => $file], $this->admin);
            $id = $portability->commitImport((string) $analysis['import_key'], 0, $this->admin);
        } finally {
            @unlink($file);
        }
        $this->db->executeStatement("UPDATE courses SET status = 'published' WHERE id = :id", ['id' => $id]);
        $row = (array) $this->db->fetchAssociative("SELECT p.node_id, ci.item_key FROM course_item_placements p JOIN course_items ci ON ci.id = p.course_item_id WHERE p.course_id = :c AND ci.item_type = 'diagnostic'", ['c' => $id]);
        self::assertNotSame([], $row, 'The readiness check was imported.');
        $modules = [];
        foreach (IntegrationContainer::get()->get(CourseItemService::class)->availability($id, null, false) as $node) {
            if ($node['section_number'] !== null) $modules[(int) $node['section_number']] = (int) $node['id'];
        }
        self::assertSame([$first, $first + 1], array_keys($modules), 'The course numbers its modules as its file does.');
        $this->course = ['id' => $id, 'slug' => (string) $this->db->fetchOne('SELECT slug FROM courses WHERE id = :id', ['id' => $id]), 'diagnostic' => ['node' => (int) $row['node_id'], 'key' => (string) $row['item_key']], 'modules' => $modules];
    }

    /**
     * The example with its module copied as a second one, both keyed from $first (mod-m0 and mod-m1, or mod-m1 and
     * mod-m2), and a readiness check before the modules whose questions name them as a course file does.
     */
    private static function twoModules(string $html, int $first, string $code, string $title): string
    {
        $start = strpos($html, '<section class="module" id="mod-m1"');
        $end = strpos($html, "\n    </section>\n  </div>", (int) $start);
        self::assertNotFalse($start, 'The example has its module.');
        self::assertNotFalse($end);
        $module = substr($html, $start, $end + strlen("\n    </section>") - $start);
        $keyed = static fn(string $source, int $number): string => str_replace(['id="mod-m1"', 'data-deck="m1"', 'data-cards="m1"', 'data-quiz="m1"', 'data-key="m1"', '<span class="num">01</span>', 'Module 01'], ['id="mod-m' . $number . '"', 'data-deck="m' . $number . '"', 'data-cards="m' . $number . '"', 'data-quiz="m' . $number . '"', 'data-key="m' . $number . '"', '<span class="num">' . sprintf('%02d', $number) . '</span>', 'Module ' . sprintf('%02d', $number)], $source);
        $second = str_replace('<span class="m-name">Soil, compost and containers</span>', '<span class="m-name">' . self::SECOND . '</span>', $keyed($module, $first + 1));
        $html = substr($html, 0, $start) . $keyed($module, $first) . "\n\n    " . $second . substr($html, $end + strlen("\n    </section>"));
        $diagnostic = <<<'HTML'
  <section class="diag" id="diagnostic">
    <details class="panel">
      <summary class="panel-head">
        <span class="node"><span class="num">D</span></span>
        <span class="m-titles"><span class="eyebrow">Diagnostic</span><span class="m-name">Readiness Check</span><small>Five questions on what this course assumes you know</small></span>
        <span class="chev">&#8250;</span>
      </summary>
      <div class="diag-inner">
        <p>This check is not scored and does not affect your grade. A wrong answer names the module to study first.</p>
        <div class="quiz" data-quiz="diag"></div>
      </div>
    </details>
  </section>


HTML;
        $html = str_replace('  <div class="modules">', $diagnostic . '  <div class="modules">', $html);
        $html = str_replace(['content="GDN-101"', 'Growing Vegetables in Small Spaces'], ['content="' . $code . '"', $title], $html);
        $one = 'm' . $first; $two = 'm' . ($first + 1);
        $diag = [
            ['q' => 'When does a watered bed lose the least water to the sun?', 'o' => ['At noon', 'Early in the morning', 'In the afternoon'], 'a' => 1, 'p' => 1, 'u' => [$two]],
            ['q' => 'Which soil drains fastest?', 'o' => ['Clay', 'Silt', 'Sand'], 'a' => 2, 'p' => 1, 'u' => [$one]],
            ['q' => 'How deep is a small seed sown?', 'o' => ['About twice its own width', 'A hand deep', 'On top of the soil, pressed down hard'], 'a' => 0, 'p' => 1, 'u' => [$two]],
            ['q' => 'Which crop needs the most sun?', 'o' => ['Lettuce', 'Tomatoes', 'Spinach'], 'a' => 1, 'p' => 1, 'u' => ['m9']],
            ['q' => 'Why does a pot need drainage holes?', 'o' => ['So that the roots get air', 'To let pests out', 'It does not need them'], 'a' => 0, 'p' => 1, 'u' => [$one]],
        ];
        return (string) preg_replace_callback('/^const (QUIZ|PRESENTATIONS|FLASHCARDS) = (\{.*?^\});$/ms', static function (array $match) use ($first, $diag): string {
            $data = json_decode($match[2], true, 512, JSON_THROW_ON_ERROR);
            $module = $data['m1'];
            unset($data['m1']);
            $data = ['m' . $first => $module, 'm' . ($first + 1) => $module] + $data;
            if ($match[1] === 'QUIZ') $data['diag'] = $diag;
            return 'const ' . $match[1] . ' = ' . json_encode($data, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT) . ';';
        }, $html);
    }

