    public function testConnectingKeepsTheKeyAndSecretAndNewsWaitsUntilTheDomainCanSendAndTheQuotaResets(): void
    {
        $settings = IntegrationContainer::get()->get(MailingSettings::class);
        $settings->forget(['cattomail_key', 'cattomail_secret', 'cattomail_secret_previous']);
        $this->db->executeStatement("DELETE FROM app_options WHERE option_key = 'mailing.cattomail_connection'");
        $settings->save(['from_address' => 'news@news.example.test'], null);
        $clock = new MockClock(new \DateTimeImmutable('2026-11-02 10:00:00', new \DateTimeZone('UTC')));
        [$connection, $transport] = $this->connection($settings, $clock);

        $connection->saveAddress('https://mail.example.test/v1', 1);
        $start = $connection->begin();
        parse_str((string) parse_url($start['url'], PHP_URL_QUERY), $query);
        self::assertStringStartsWith('https://mail.example.test/dashboard/connect?', $start['url']);
        self::assertSame(rtrim(strtr(base64_encode(hash('sha256', $start['verifier'], true)), '+/', '-_'), '='), $query['code_challenge'], 'S256 of the verifier.');
        self::assertSame(['S256', $start['state'], 'news.example.test'], [$query['code_challenge_method'], $query['state'], $query['sending_domain']]);
        self::assertStringEndsWith('/mailing/cattomail/callback', (string) $query['redirect_uri']);
        self::assertStringEndsWith('/webhooks/cattomail', (string) $query['webhook_url']);
        self::assertMatchesRegularExpression('/^[A-Za-z0-9._~-]{43,128}$/', $start['verifier']);

        $this->answers[] = new MockResponse((string) json_encode(['connection_id' => 'conn-1', 'application_name' => 'CattoLMS', 'client_name' => 'Example Learning',
            'api_base_url' => 'https://mail.example.test/v1', 'api_key' => 'shk_secretkey', 'webhook' => ['endpoint_id' => 'ep-1', 'url' => 'https://catto.test/webhooks/cattomail', 'signing_secret' => 'whsec_secret'],
            'sending_domains' => [['id' => 'd-1', 'domain' => 'news.example.test', 'status' => 'verified', 'dkim_status' => 'pending_dns', 'can_send' => false, 'setup_url' => 'https://mail.example.test/dashboard/c/1/sending-domains/1']]]), ['http_code' => 200]);
        $connection->finish('the-code', $start['verifier'], $start['redirect_uri'], 1, 'Thandi');
        self::assertSame(['code' => 'the-code', 'code_verifier' => $start['verifier'], 'redirect_uri' => $start['redirect_uri']], $this->requests[0]['body']);
        self::assertSame('', $this->requests[0]['auth'], 'The exchange carries no key.');
        self::assertSame('shk_secretkey', $settings->value('cattomail_key'));
        self::assertNotSame('shk_secretkey', (string) $this->db->fetchOne("SELECT option_value FROM app_options WHERE option_key = 'mailing.cattomail_key'"), 'Kept encrypted.');
        self::assertSame('whsec_secret', $settings->value('cattomail_secret'));
        self::assertSame('cattomail', $settings->transport(), 'News goes through catto-mail once connected (8A).');
        self::assertSame('Example Learning', $connection->state()['client_name']);
        self::assertFalse($connection->ready());
        self::assertSame(2, $connection->steps()['done']);

        $copy = ['delivery_id' => 1, 'token' => str_repeat('a', 32), 'to' => 'learner@example.test', 'subject' => 'News', 'html' => '<p>News</p>', 'text' => 'News', 'unsubscribe_url' => 'https://news.example.test/m/u/' . str_repeat('a', 32), 'list_id' => 1, 'list_name' => 'News and Updates'];
        try {
            $transport->send(['id' => 1], [$copy], ['email' => 'news@news.example.test', 'name' => 'News']);
            self::fail('Sent before the domain could send.');
        } catch (MailingTransportUnavailable $waits) {
            self::assertStringContainsString('cannot send from news.example.test yet', $waits->getMessage());
        }
        self::assertCount(1, $this->requests, 'Nothing was asked of catto-mail.');

        $this->answers[] = new MockResponse((string) json_encode(['data' => [['id' => 'd-1', 'domain' => 'news.example.test', 'status' => 'verified', 'dkim_status' => 'active', 'can_send' => true]]]), ['http_code' => 200]);
        $connection->checkDomains();
        self::assertTrue($connection->ready());
        self::assertSame('Bearer shk_secretkey', $this->requests[1]['auth']);

        $this->answers[] = new MockResponse((string) json_encode(['type' => 'https://mail.example.test/problems/quota-exceeded', 'title' => 'Quota exceeded', 'status' => 429, 'detail' => 'The daily quota is used up.',
            'quota' => ['metric' => 'send_recipients', 'period' => 'day', 'resets_at' => '2026-11-03T00:00:00.000000+02:00']]), ['http_code' => 429]);
        try {
            $transport->send(['id' => 1], [$copy], ['email' => 'news@news.example.test', 'name' => 'News']);
            self::fail('A quota refusal was not a wait.');
        } catch (MailingTransportUnavailable $waits) {
            self::assertStringContainsString('quota is used up until 3 November at 00:00', $waits->getMessage());
        }
        $asked = count($this->requests);
        try {
            $transport->send(['id' => 1], [$copy], ['email' => 'news@news.example.test', 'name' => 'News']);
            self::fail('Sent before the quota reset.');
        } catch (MailingTransportUnavailable) {
            self::assertCount($asked, $this->requests, 'Nothing is asked before the quota resets.');
        }
        $clock->modify('+15 hours');
        self::assertNull($connection->quotaUntil(), 'Once it resets, news goes on.');

        $this->answers[] = new MockResponse('', ['http_code' => 404]);
        $this->answers[] = new MockResponse((string) json_encode(['data' => [['id' => 'd-1', 'domain' => 'news.example.test', 'status' => 'verified', 'dkim_status' => 'active', 'can_send' => true]]]), ['http_code' => 200]);
        self::assertTrue($connection->check(), 'A job that cannot exist answers 404 to a key catto-mail accepts.');
        $this->answers[] = new MockResponse('', ['http_code' => 401]);
        self::assertFalse($connection->check());
        self::assertStringContainsString('does not accept the key', (string) $connection->state()['last_problem']);

        $this->answers[] = new MockResponse('', ['http_code' => 204]);
        $connection->disconnect(1);
        self::assertSame('DELETE', $this->requests[count($this->requests) - 1]['method']);
        self::assertStringEndsWith('/v1/connection', $this->requests[count($this->requests) - 1]['url']);
        self::assertFalse($connection->connected(), 'Forgotten here.');
    }

    public function testAnApprovalThatCannotBeUsedSaysSoAndChangesNothing(): void
    {
        $settings = IntegrationContainer::get()->get(MailingSettings::class);
        $settings->forget(['cattomail_key', 'cattomail_secret', 'cattomail_secret_previous']);
        [$connection] = $this->connection($settings, new MockClock());
        $connection->saveAddress('https://mail.example.test', 1);
        $this->answers[] = new MockResponse((string) json_encode(['type' => 'https://mail.example.test/problems/invalid-connect-code', 'title' => 'Invalid connect code', 'status' => 400]), ['http_code' => 400]);
        try {
            $connection->finish('used-code', str_repeat('v', 43), 'https://catto.test/mailing/cattomail/callback', 1, 'Thandi');
            self::fail('Connected with a used code.');
        } catch (MailingTransportRefused $refused) {
            self::assertStringStartsWith('That approval cannot be used', $refused->getMessage());
        }
        self::assertFalse($connection->connected());
    }

    /** @return array{0:CattomailConnection,1:CattomailTransport} */
    private function connection(MailingSettings $settings, MockClock $clock): array
    {
        $http = new MockHttpClient(function (string $method, string $url, array $options): MockResponse {
            $auth = '';
            foreach ((array) ($options['normalized_headers']['authorization'] ?? []) as $header) $auth = trim((string) substr((string) $header, strlen('Authorization:')));
            $this->requests[] = ['method' => $method, 'url' => $url, 'body' => json_decode((string) ($options['body'] ?? 'null'), true), 'auth' => $auth];

            return array_shift($this->answers) ?? new MockResponse('', ['http_code' => 500]);
        });
        $client = new CattomailClient($http, $settings);
        $connection = new CattomailConnection($settings, $client, IntegrationContainer::get()->get(OptionRepository::class), IntegrationContainer::get()->get(RuntimeSettings::class),
            IntegrationContainer::get()->get(AuditRepository::class), $clock);

        return [$connection, new CattomailTransport($client, $connection)];
    }
