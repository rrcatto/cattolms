declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Course\CourseRepository;
use CattoLearning\Course\CourseService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\{DevelopmentFixture, IntegrationContainer};
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class CourseRelationsIntegrationTest extends TestCase
{
    private Database $db;
    private CourseService $service;
    private CourseRepository $courses;
    private int $user;
    /** @var array<string,int> */
    private array $id = [];

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
        $this->service = IntegrationContainer::get()->get(CourseService::class);
        $this->courses = IntegrationContainer::get()->get(CourseRepository::class);
        $fixture = new DevelopmentFixture($this->db);
        $suffix = $fixture->suffix();
        $this->user = $fixture->createUser('Relations administrator ' . $suffix, 'relations-' . $suffix . '@example.test');
        $company = $fixture->createCompany($this->user, 'Relations Company ' . $suffix, 'relations-' . $suffix . '.example.test');
        foreach (['A' => 'published', 'B' => 'published', 'C' => 'published', 'D' => 'draft'] as $key => $status) {
            $this->id[$key] = $fixture->createCourse($this->user, $company, 'related-' . strtolower($key) . '-' . $suffix, 'Related ' . $key . ' ' . $suffix, $status);
        }
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testARelationMadeFromEitherCourseIsTheOthersToo(): void
    {
        $this->relate('A', ['B', 'C']);
        self::assertSame([$this->id['A']], $this->courses->relatedCourseIds($this->id['B']), 'B is related to A without being touched.');
        self::assertSame([$this->id['A']], $this->courses->relatedCourseIds($this->id['C']));
        self::assertTrue($this->checked('B', 'A'), "B's form shows A ticked.");
        // Removing it from the other course removes it from both.
        $this->relate('B', []);
        self::assertSame([$this->id['C']], $this->courses->relatedCourseIds($this->id['A']));
        self::assertSame([], $this->courses->relatedCourseIds($this->id['B']));
        // Relating again from the other side keeps one relation, not two.
        $this->relate('C', ['A']);
        self::assertSame(1, (int) $this->db->fetchOne('SELECT COUNT(*) FROM course_relations WHERE course_low_id = :low AND course_high_id = :high',
            ['low' => min($this->id['A'], $this->id['C']), 'high' => max($this->id['A'], $this->id['C'])]));
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM audit_log WHERE event_key = 'course.updated' AND user_id = :user AND metadata->'related_course_ids' IS NOT NULL AND metadata->>'course_id' = :course",
            ['user' => $this->user, 'course' => (string) $this->id['C']]));
    }

    public function testACourseIsNeverRelatedToItselfOrToACourseThatIsNotThere(): void
    {
        foreach ([[$this->id['A']], [999999999]] as $wanted) {
            try {
                $this->service->updateCourse($this->id['A'], ['related_shown' => '1', 'related_ids' => array_map('strval', $wanted)], $this->user);
                self::fail('Accepted ' . implode(',', $wanted));
            } catch (InvalidArgumentException $refused) {
                self::assertNotSame('', $refused->getMessage());
            }
        }
        $this->expectException(\Throwable::class);
        $this->db->executeStatement('INSERT INTO course_relations (course_low_id, course_high_id) VALUES (:high, :low)',
            ['high' => max($this->id['A'], $this->id['B']), 'low' => min($this->id['A'], $this->id['B'])]);
    }

    public function testTheCoursePageShowsThePublishedRelatedCoursesAndADeletedCourseLeavesNoRelation(): void
    {
        $this->relate('A', ['B', 'D']);
        $cards = $this->service->relatedCourseCards($this->id['A']);
        self::assertSame([$this->id['B']], array_map(static fn(array $card): int => (int) $card['id'], $cards), 'A draft is not shown on the public page.');
        $this->db->executeStatement('DELETE FROM courses WHERE id = :id', ['id' => $this->id['B']]);
        self::assertSame([$this->id['D']], $this->courses->relatedCourseIds($this->id['A']), 'A deleted course takes its relations with it.');
    }

    /** @param list<string> $others */
    private function relate(string $course, array $others): void
    {
        $existing = $this->courses->findById($this->id[$course]);
        self::assertNotNull($existing);
        $this->service->updateCourse($this->id[$course], ['related_shown' => '1', 'related_ids' => array_map(fn(string $key): string => (string) $this->id[$key], $others)], $this->user);
    }

    private function checked(string $course, string $other): bool
    {
        foreach ($this->service->relatedCourseOptions($this->id[$course]) as $option) {
            if ($option['id'] === $this->id[$other]) return $option['checked'];
        }
        return false;
    }
}
