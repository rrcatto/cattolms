final class CompanyRequestCreditRegressionTest extends TestCase
{
    public function testApprovalUsesOnlyExactMatchingCompanyCredit(): void
    {
        $container = CliBootstrap::boot()['container'];
        /** @var Database $db */
        $db = $container->get(Database::class);
        /** @var AdministrationRepository $administration */
        $administration = $container->get(AdministrationRepository::class);
        $fixture = new DevelopmentFixture($db);
        $suffix = $fixture->suffix();
        $mailer = new FakeMailer();

        try {
            $adminId = $fixture->createUser('QA company admin ' . $suffix, 'qa-admin-' . $suffix . '@example.test');
            $learnerEmail = 'qa-learner-' . $suffix . '@example.test';
            $learnerId = $fixture->createUser('QA company learner ' . $suffix, $learnerEmail);
            $companyId = $fixture->createCompany($adminId, 'QA Company ' . $suffix, 'qa-company-' . $suffix . '.example.test');
            $db->executeStatement(
                "INSERT INTO company_users (company_id,user_id,company_role,status) VALUES (:company_id,:user_id,'staff','active')",
                ['company_id' => $companyId, 'user_id' => $learnerId]
            );
            // The course belongs to somebody else. That is the whole premise of a credit: a company
            // buys access to a course it does not own. This fixture used to make the learner's own
            // company the owner, which since the 2026/09/07 ownership rule means the approval is
            // free and immediate and no credit is consulted at all - so the test would have passed
            // while proving nothing about credit matching.
            $providerAdminId = $fixture->createUser('QA provider admin ' . $suffix, 'qa-provider-' . $suffix . '@example.test');
            $providerId = $fixture->createCompany($providerAdminId, 'QA Provider ' . $suffix, 'qa-provider-' . $suffix . '.example.test');
            $courseId = $fixture->createCourse($providerAdminId, $providerId, 'qa-request-' . $suffix, 'QA Requested Course ' . $suffix, 'published');

            $wrongPeriodCredit = $administration->addCredit($companyId, null, $courseId, 31536000, 1, 'qa', 'wrong period', $adminId);
            $fixture->rememberCredit($wrongPeriodCredit);
            $requestId = $administration->createRequest($learnerId, $companyId, $courseId, 2592000, 'Please approve');
            $fixture->rememberRequest($requestId);

            $service = $this->service($container, $mailer);
            $service->decideRequest($requestId, true, 'Approved without matching credit', $adminId, $companyId);

            $request = $db->fetchAllAssociative('SELECT status,enrolment_id FROM course_requests WHERE id=:id', ['id' => $requestId])[0];
            self::assertSame('approved', (string) $request['status']);
            self::assertSame('', trim((string) ($request['enrolment_id'] ?? '')));
            $allocations = $db->fetchAllAssociative('SELECT COUNT(*)::int AS total FROM course_credit_allocations WHERE credit_id=:id', ['id' => $wrongPeriodCredit]);
            self::assertSame(0, (int) $allocations[0]['total']);

            $db->executeStatement("UPDATE course_requests SET status='cancelled' WHERE id=:id", ['id' => $requestId]);
            $matchingCredit = $administration->addCredit($companyId, null, $courseId, 2592000, 1, 'qa', 'matching', $adminId);
            $fixture->rememberCredit($matchingCredit);
            $requestId2 = $administration->createRequest($learnerId, $companyId, $courseId, 2592000, 'Please approve exactly');
            $fixture->rememberRequest($requestId2);

            $service->decideRequest($requestId2, true, 'Fulfilled with matching credit', $adminId, $companyId);
            $request2 = $db->fetchAllAssociative('SELECT status,enrolment_id FROM course_requests WHERE id=:id', ['id' => $requestId2])[0];
            self::assertSame('fulfilled', (string) $request2['status']);
            $enrolmentId = (int) $request2['enrolment_id'];
            self::assertGreaterThan(0, $enrolmentId);

            $allocation = $db->fetchAllAssociative(
                'SELECT status,enrolment_id FROM course_credit_allocations WHERE credit_id=:id',
                ['id' => $matchingCredit]
            );
            self::assertCount(1, $allocation);
            self::assertSame('assigned', (string) $allocation[0]['status']);
            self::assertSame($enrolmentId, (int) $allocation[0]['enrolment_id']);

            $enrolment = $db->fetchAllAssociative('SELECT status,started_at FROM course_enrolments WHERE id=:id', ['id' => $enrolmentId])[0];
            self::assertSame('assigned', (string) $enrolment['status']);
            self::assertSame('', trim((string) ($enrolment['started_at'] ?? '')));

            /** @var CourseRepository $courses */
            $courses = $container->get(CourseRepository::class);
            $courses->startEnrolment($enrolmentId, $learnerId);
            $allocationAfterStart = $db->fetchAllAssociative('SELECT status,consumed_at FROM course_credit_allocations WHERE credit_id=:id', ['id' => $matchingCredit])[0];
            self::assertSame('consumed', (string) $allocationAfterStart['status']);
            self::assertNotSame('', trim((string) ($allocationAfterStart['consumed_at'] ?? '')));

            self::assertCount(2, array_values(array_filter(
                $mailer->messages,
                static fn(array $message): bool => $message['type'] === 'course_request_decision'
            )));
        } finally {
            $fixture->cleanup();
        }
    }

