    public function testTheFrameIsTheFileJustImportedsOrNone(): void
    {
        $code = OriginalBuildExample::CODE;
        $id = $this->importNew(OriginalBuildExample::html(), 'html');
        $frames = IntegrationContainer::get()->get(CoursePortabilityRepository::class);
        self::assertNotNull($frames->fileFrame($id), 'A file in the original build gives its frame.');

        // Replaced from a course package that holds no frame: none is left.
        $package = $this->portability->exportCourse($id);
        $package['file_frame'] = null;
        $package['course']['title'] = 'Without its frame ' . $this->suffix;
        $this->commit($this->review($this->stage($package, 'json')));
        self::assertNull($frames->fileFrame($id), 'The frame of an earlier file is never left.');

        // Replaced from the original build again: its frame.
        $this->commit($this->review($this->stage(OriginalBuildExample::html(), 'html')));
        self::assertNotNull($frames->fileFrame($id), 'The file just imported, in the original build, gives its frame.');

        // Replaced from a file written to the specification: none.
        $spec = str_replace('content="GDN-101"', 'content="' . $code . '"', SpecificationExample::html());
        $this->commit($this->review($this->stage($spec, 'html')));
        self::assertNull($frames->fileFrame($id), 'A file without a frame leaves none.');
        self::assertSame($id, (int) $this->courses->findByCode($code)['id']);
    }

