/*
Generated by: Claude Code CLI

Date time: 2026/11/07 SAST

Version: 1.1.0

Description:
Administration > Courses > Import, one course from an HTML course file or a JSON course package, by the catalogue's
canonical rules (owner, 2026-11-06: "consider the import file to be canonical ... By default, what is in the import file
wins ... Do not retain or backup what is being replaced", "The identifier for a json course file is its course code not
its contents"), through the review page and its Import, inside a transaction:
- a course is matched by its code alone: another title and address still update the course with that code;
- for a course already here every difference the file states is listed with Use the file's (chosen) and Keep this
  site's, and the file's wins by default, nothing replaced kept (old tags, old prices, old parts);
- Keep this site's keeps that one;
- an HTML file states no prices, related courses, address, access period or certificate switch, so they stay, and the
  review lists no difference for them;
- a replace keeps each part's name (its address), a published course stays published, and what is open before buying
  stays open;
- an import whose review the site has changed since is refused and changes nothing;
- the course file's frame afterwards is the frame of the file just imported, or none, never one left from before;
- a file without a code whose content is a course already here is refused with how to update that course.

Changelog:
2026/11/07 SAST
- Created for the single-course import's canonical rules (stage 2).
*/

