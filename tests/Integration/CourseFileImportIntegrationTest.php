    public function testACourseIsMatchedByItsCodeAlone(): void
    {
        $code = 'CFI-' . $this->tail;
        $id = $this->importNew($this->package($code, 'cfi-first-' . $this->suffix, 'First title ' . $this->suffix));
        $again = $this->package($code, 'cfi-second-' . $this->suffix, 'Second title ' . $this->suffix);
        $review = $this->review($this->stage($again, 'json'));
        self::assertStringContainsString('Use the file', $review['body'], 'The difference is offered as the catalogue offers it.');
        self::assertStringNotContainsString('name="replace_course_id"', $review['body'], 'No course is chosen by hand: the code chooses it.');
        $this->commit($review);
        $course = $this->courses->findByCode($code);
        self::assertSame($id, (int) $course['id'], 'The course with the code was updated, not a second one made.');
        self::assertSame('Second title ' . $this->suffix, $course['title']);
        self::assertSame('cfi-second-' . $this->suffix, $course['slug'], 'A course package states its address, and the file\'s wins.');
        self::assertSame(1, (int) $this->db->fetchOne('SELECT COUNT(*) FROM courses WHERE code = :c', ['c' => $code]));
    }

    public function testWhatTheFileStatesWinsByDefaultAndNothingReplacedIsKept(): void
    {
        $code = 'CFW-' . $this->tail;
        $file = $this->package($code, 'cfw-' . $this->suffix, 'File title ' . $this->suffix);
        $id = $this->importNew($file);
        // The site changes everything the file speaks of.
        $this->db->executeStatement('UPDATE courses SET title = :t, cover_svg = :cover, catalogue_position = 17 WHERE id = :id', ['t' => 'Site title ' . $this->suffix, 'cover' => self::OTHER_COVER, 'id' => $id]);
        $this->service->setCourseTagsByName($id, ['Cf spare ' . $this->suffix], $this->admin);
        $this->db->executeStatement('UPDATE course_price_variants SET price_minor_units = 99900 WHERE course_id = :c', ['c' => $id]);
        $extra = $this->fixture->createAssessmentItem($id, $this->admin, 'content');
        unset($extra);

        $review = $this->review($this->stage($file, 'json'));
        foreach (['content', 'tags', 'prices', 'cover', 'position'] as $kind) self::assertArrayHasKey('choice[' . $kind . ']', $review['fields'], 'The review lists the ' . $kind . ' with Use the file\'s chosen.');
        foreach (['Content: the file', 'Tags: ', 'Price: ', 'Cover picture', 'Position in the catalogue: 17'] as $words) self::assertStringContainsString($words, $review['body'], 'In words: ' . $words);
        $this->commit($review);

        $course = $this->courses->findById($id);
        self::assertSame('File title ' . $this->suffix, $course['title']);
        self::assertSame(self::COVER, $course['cover_svg']);
        self::assertSame(4242, (int) $course['catalogue_position']);
        self::assertSame(['Cf tag ' . $this->suffix], $this->tagsOf($id), 'The file\'s tags exactly: the site\'s spare tag is not kept.');
        self::assertSame([95000], array_map('intval', $this->db->fetchFirstColumn("SELECT price_minor_units FROM course_price_variants WHERE course_id = :c AND is_active ORDER BY id", ['c' => $id])), 'The file\'s price is on sale and the site\'s is not.');
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM course_item_placements WHERE course_id = :c", ['c' => $id]), 'The part the site added is gone: the content is the file\'s.');
    }

