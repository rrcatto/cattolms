    /** @param array<string,mixed>|string $content */
    private function importNew(array|string $content, string $kind = 'json'): int
    {
        $review = $this->review($this->stage($content, $kind));
        $result = $this->commit($review);
        $code = is_array($content) ? (string) $content['course']['code'] : (string) (preg_match('/cattolms:course-code" content="([^"]+)"/', $content, $m) === 1 ? $m[1] : '');
        $course = $this->courses->findByCode($code) ?? self::fail('The course was not imported: ' . json_encode($_SESSION['flash'] ?? []) . ' ' . $result['location']);
        return (int) $course['id'];
    }

    /** @param array<string,mixed>|string $content */
    private function stage(array|string $content, string $kind): string
    {
        $file = (string) tempnam(sys_get_temp_dir(), 'course-file-import');
        file_put_contents($file, is_array($content) ? (string) json_encode($content) : $content);
        try {
            $key = (string) $this->portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => 'course.' . $kind, 'tmp_name' => $file], $this->admin)['import_key'];
        } finally {
            @unlink($file);
        }
        return $this->keys[] = $key;
    }

    /** @return array{key:string,body:string,fields:array<string,string>} */
    private function review(string $key): array
    {
        $page = InProcessPage::run($this->user, AdminCourseController::class, 'previewImport', [], null, ['key' => $key]);
        self::assertSame(200, $page['status'], 'The review opens: ' . json_encode($_SESSION['flash'] ?? []));
        $document = new \DOMDocument();
        @$document->loadHTML('<?xml encoding="UTF-8"><body>' . $page['body'] . '</body>');
        $xpath = new \DOMXPath($document);
        $fields = [];
        // What the Import form sends as it stands: its own fields and the choices tied to it.
        foreach ($xpath->query('//form[@action="/admin/courses/import/commit"]//input[@name] | //input[@form="course-import"][@name]') as $input) {
            if (!$input instanceof \DOMElement) continue;
            $type = $input->getAttribute('type');
            if (in_array($type, ['radio', 'checkbox'], true) && !$input->hasAttribute('checked')) continue;
            $fields[$input->getAttribute('name')] = $input->getAttribute('value');
        }
        foreach ($xpath->query('//form[@action="/admin/courses/import/commit"]//select[@name]') as $select) {
            if (!$select instanceof \DOMElement) continue;
            $chosen = $xpath->query('.//option[@selected]', $select)->item(0) ?? $xpath->query('.//option', $select)->item(0);
            $fields[$select->getAttribute('name')] = $chosen instanceof \DOMElement ? $chosen->getAttribute('value') : '';
        }
        return ['key' => $key, 'body' => $page['body'], 'fields' => $fields];
    }

    /**
     * @param array{key:string,body:string,fields:array<string,string>} $review
     * @param array<string,string> $change
     * @return array{status:int,location:?string}
     */
    private function commit(array $review, array $change = [], bool $succeeds = true): array
    {
        // Sent as a browser sends it: choice[tags] arrives as choice => [tags => …].
        parse_str(http_build_query(array_replace($review['fields'], ['csrf' => $_SESSION['csrf'], 'import_key' => $review['key']], $change)), $post);
        unset($_SESSION['flash']);
        $result = InProcessPage::run($this->user, AdminCourseController::class, 'commitImport', [], $post);
        if ($succeeds) self::assertStringStartsWith('/admin/courses/', (string) $result['location'], 'The import went through: ' . json_encode($_SESSION['flash'] ?? []));
        if ($succeeds) self::assertStringNotContainsString('/admin/courses/import', (string) $result['location'], 'The import went through: ' . json_encode($_SESSION['flash'] ?? []));
        return ['status' => $result['status'], 'location' => $result['location']];
    }

    /** @return list<string> */
    private function tagsOf(int $courseId): array
    {
        return array_map('strval', $this->db->fetchFirstColumn('SELECT t.name FROM course_tags ct JOIN tags t ON t.id = ct.tag_id WHERE ct.course_id = :c ORDER BY t.name', ['c' => $courseId]));
    }

    /** @return list<string> */
    private function partNames(int $courseId): array
    {
        $names = array_map('strval', $this->db->fetchFirstColumn('SELECT part_name FROM course_structure_nodes WHERE course_id = :c', ['c' => $courseId]));
        sort($names);
        return $names;
    }

    private function fileOf(int $courseId): string
    {
        return IntegrationContainer::get()->get(CourseFile::class)->fromCourse($courseId)['html'];
    }

    private function html(string $code): string
    {
        return str_replace('content="GDN-101"', 'content="' . $code . '"', SpecificationExample::html());
    }

    /** @return array<string,mixed> a course package (catto-learning-course 2.1) */
    private function package(string $code, string $slug, string $title): array
    {
        $lesson = 'cf-' . $this->suffix . '-' . substr(md5($code), 0, 6) . '-lesson';
        foreach (['tag', 'spare'] as $word) {
            $this->db->executeStatement("INSERT INTO tags (name, slug) VALUES (:n, :s) ON CONFLICT DO NOTHING", ['n' => 'Cf ' . $word . ' ' . $this->suffix, 's' => 'cf-' . $word . '-' . $this->suffix]);
        }
        return ['format' => 'catto-learning-course', 'schema_version' => '2.1',
            'course' => ['code' => $code, 'slug' => $slug, 'title' => $title, 'summary' => '', 'description_html' => '<p>About.</p>',
                'default_access_period_seconds' => 31536000, 'introduction_html' => '<p>Welcome.</p>', 'certificate_enabled' => true],
            'resources' => [],
            'course_items' => [['item_key' => $lesson, 'item_type' => 'html_lesson', 'title' => 'Lesson', 'description_html' => '', 'content_source' => '<p>Lesson.</p>', 'type_config' => [], 'resource_public_id' => null]],
            'structure' => [['node_key' => $lesson, 'parent_node_key' => null, 'position' => 1, 'node_type' => 'item', 'relative_delay_minutes' => 0, 'item_key' => $lesson, 'public_preview' => false, 'assessment_role' => 'content']],
            'grade_bands' => [],
            'catalogue' => ['tags' => ['Cf tag ' . $this->suffix], 'cover' => self::COVER, 'position' => 4242, 'related' => [], 'status' => 'draft', 'page_layout' => null,
                'prices' => [['period' => 12, 'unit' => 'months', 'price' => '950.00', 'was_price' => null, 'currency' => 'ZAR', 'label' => 'One year', 'active' => true, 'default' => true]]]];
    }
