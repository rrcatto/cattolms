    public function testAnHtmlFileLeavesWhatItDoesNotStateAndKeepsPublishedOpenPartsAndPartNames(): void
    {
        $html = $this->html('CFH-' . $this->tail);
        $id = $this->importNew($html, 'html');
        $code = 'CFH-' . $this->tail;
        // What only the site holds: a price, a related course, an access period, no certificate, its own address.
        $this->fixture->createPriceVariant($id, $this->admin, 31536000, 123400, true);
        $other = ['id' => $this->importNew($this->package('CFO-' . $this->tail, 'cfo-' . $this->suffix, 'Other course ' . $this->suffix))];
        $this->courses->replaceRelatedCourses($id, [(int) $other['id']]);
        $this->db->executeStatement('UPDATE courses SET default_access_period_seconds = 15552000, certificate_enabled = false, slug = :slug WHERE id = :id', ['slug' => 'cfh-own-address-' . $this->suffix, 'id' => $id]);
        $this->service->changeStatus($id, 'published', $this->admin, true);
        // What is open before buying, and a part with a name its place would not give it.
        $open = $this->db->fetchFirstColumn("SELECT part_name FROM course_structure_nodes n JOIN course_sections s ON s.node_id = n.id WHERE n.course_id = :c AND s.numbered ORDER BY n.position LIMIT 1", ['c' => $id]);
        self::assertNotSame([], $open);
        $this->db->executeStatement('UPDATE course_sections SET public_preview = true WHERE node_id = (SELECT id FROM course_structure_nodes WHERE course_id = :c AND part_name = :p)', ['c' => $id, 'p' => $open[0]]);
        $names = $this->partNames($id);

        // The file again, its title changed, so its content differs.
        $changed = str_replace('<title>', '<title>Renamed ', $this->fileOf($id));
        $changed = (string) preg_replace('/(<h1\b[^>]*>)/', '$1Renamed ', $changed, 1);
        $review = $this->review($this->stage($changed, 'html'));
        self::assertSame('file', $review['fields']['choice[content]'] ?? null, 'The content differs, and the file\'s is chosen.');
        foreach (['Price', 'Related courses', 'Status'] as $silent) self::assertStringNotContainsString('name="choice[' . strtolower(str_replace(' ', '_', $silent)) . ']"', $review['body'], 'An HTML file states no ' . $silent . ', so nothing is listed for it.');
        $this->commit($review);

        $course = $this->courses->findByCode($code);
        self::assertSame($id, (int) $course['id']);
        self::assertStringStartsWith('Renamed', (string) $course['title'], 'The file\'s content won.');
        self::assertSame('published', $course['status'], 'A published course stays published.');
        self::assertSame('cfh-own-address-' . $this->suffix, $course['slug'], 'The file states no address: the course keeps its own.');
        self::assertSame(15552000, (int) $course['default_access_period_seconds'], 'Nor an access period.');
        self::assertFalse((bool) $course['certificate_enabled'], 'Nor the certificate switch.');
        self::assertSame(1, (int) $this->db->fetchOne('SELECT COUNT(*) FROM course_price_variants WHERE course_id = :c AND is_active', ['c' => $id]), 'Its price stays.');
        self::assertSame([(int) $other['id']], array_map('intval', $this->courses->relatedCourseIds($id)), 'Its related course stays.');
        self::assertSame($names, $this->partNames($id), 'Every part keeps its name, so every address still works.');
        self::assertTrue((bool) $this->db->fetchOne('SELECT s.public_preview FROM course_structure_nodes n JOIN course_sections s ON s.node_id = n.id WHERE n.course_id = :c AND n.part_name = :p', ['c' => $id, 'p' => $open[0]]), 'What was open before buying stays open.');
    }

