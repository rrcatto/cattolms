    /**
     * A failure part-way through generation leaves nothing behind.
     *
     * The generator is driven directly here rather than through the service, because the service
     * writes its metadata only after the transaction commits - which is itself the behaviour
     * being relied on. Failing inside the transaction must roll back the business rows; failing
     * at all must leave no seed_data row to describe a set that does not exist.
     */
    public function testAFailedGenerationLeavesNoPartialGraph(): void
    {
        $doomed = $this->fixture->reserveToken();

        $before = [];
        foreach (['companies', 'users', 'courses', 'course_enrolments'] as $table) {
            $before[$table] = $this->rowCount('SELECT COUNT(*)::int AS total FROM ' . $table);
        }
        $setsBefore = $this->rowCount('SELECT COUNT(*)::int AS total FROM seed_data');
        $tablesBefore = $this->rowCount('SELECT COUNT(*)::int AS total FROM seed_data_tables');

        /** @var SeedGenerator $generator */
        $generator = $this->container->get(SeedGenerator::class);
        $plan = SeedGenerationPlan::forVolume(SeedGenerationPlan::MINIMUM_VOLUME);

        $this->db->beginTransaction();
        $failureMessage = null;
        try {
            $generator->generate($plan, $doomed);
            // The graph now exists inside this transaction. Abandoning it is the failure being
            // simulated: whatever goes wrong in production, the transaction is what unwinds it.
            throw new RuntimeException('simulated failure after the graph was built');
        } catch (RuntimeException $exception) {
            $failureMessage = $exception->getMessage();
            $this->db->rollBack();
        }

        self::assertSame(
            'simulated failure after the graph was built',
            $failureMessage,
            'The simulated failure must be the one that was raised.'
        );

        foreach ($before as $table => $count) {
            self::assertSame(
                $count,
                $this->rowCount('SELECT COUNT(*)::int AS total FROM ' . $table),
                $table . ' must be exactly as it was before the failed generation.'
            );
        }
        self::assertSame(
            0,
            $this->rowCount('SELECT COUNT(*)::int AS total FROM users WHERE seed_token = :token::uuid', ['token' => $doomed]),
            'No row of the abandoned set may survive.'
        );
        self::assertSame($setsBefore, $this->rowCount('SELECT COUNT(*)::int AS total FROM seed_data'), 'No metadata row may describe a set that does not exist.');
        self::assertSame($tablesBefore, $this->rowCount('SELECT COUNT(*)::int AS total FROM seed_data_tables'), 'No orphaned table breakdown may survive.');
    }

