declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\PlatformAdministrationService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Tests\Support\IntegrationDataFixture;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class AdministratorSelfLockoutIntegrationTest extends TestCase
{
    private Database $db;
    private PlatformAdministrationService $administration;
    private IntegrationDataFixture $fixture;
    private int $admin;
    private int $otherAdmin;
    private string $email;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
        /** @var PlatformAdministrationService $administration */
        $administration = IntegrationContainer::get()->get(PlatformAdministrationService::class);
        $this->administration = $administration;
        $this->fixture = new IntegrationDataFixture($this->db);
        $suffix = $this->fixture->suffix();
        $this->email = 'self-' . $suffix . '@example.test';
        $this->admin = $this->fixture->createUser('Self admin', $this->email);
        $this->otherAdmin = $this->fixture->createUser('Other admin', 'other-' . $suffix . '@example.test');
        foreach ([$this->admin, $this->otherAdmin] as $id) {
            $this->fixture->grantRole($id, 'ADMIN');
        }
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testAnAdministratorCannotDisableTheirOwnAccountButAnotherCan(): void
    {
        try {
            $this->administration->setPersonStatus($this->admin, 'disabled', $this->admin);
            self::fail('An administrator disabled their own account.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame(PlatformAdministrationService::OWN_ACCOUNT_DISABLE, $refused->getMessage());
        }
        self::assertSame('active', $this->accountStatus($this->admin), 'Nothing changed.');

        $this->administration->setPersonStatus($this->admin, 'disabled', $this->otherAdmin);
        self::assertSame('disabled', $this->accountStatus($this->admin), 'Another administrator can.');
        $this->administration->setPersonStatus($this->admin, 'active', $this->otherAdmin);
        self::assertSame('active', $this->accountStatus($this->admin));
    }

    public function testAnAdministratorCannotRemoveTheirOwnAdministratorRole(): void
    {
        try {
            $this->administration->updatePerson($this->admin, ['primary_email' => $this->email, 'roles' => ['STUDENT']], $this->admin);
            self::fail('An administrator removed their own administrator role.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame(PlatformAdministrationService::OWN_ADMIN_ROLE, $refused->getMessage());
        }
        self::assertContains('ADMIN', $this->roles($this->admin), 'The role stays.');
    }

    public function testThePersonPageOffersNoDisableButtonForTheReadersOwnAccount(): void
    {
        $page = (string) file_get_contents(dirname(__DIR__, 2) . '/resources/views/pages/admin-person-profile.html.twig');
        self::assertStringContainsString("{% elseif is_own_account and profile.status == 'active' %}", $page);
        self::assertStringContainsString('<input type="hidden" name="roles[]" value="ADMIN"><input type="checkbox" checked disabled', $page, 'The own ADMIN box is fixed, and the role still sent.');
    }

    private function accountStatus(int $userId): string
    {
        return (string) $this->db->fetchOne('SELECT status FROM users WHERE id = :id', ['id' => $userId]);
    }

    /** @return list<string> */
    private function roles(int $userId): array
    {
        return array_map('strval', $this->db->fetchFirstColumn('SELECT r.role_key FROM user_roles ur JOIN roles r ON r.id = ur.role_id WHERE ur.user_id = :id', ['id' => $userId]));
    }
}
