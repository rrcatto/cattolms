declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\ProfilePictures;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Infrastructure\Persistence\UserProfileRepository;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Tests\Support\IntegrationDataFixture;
use PHPUnit\Framework\TestCase;

final class ProfilePicturesIntegrationTest extends TestCase
{
    private Database $db;
    private ProfilePictures $pictures;
    private UserProfileRepository $profiles;
    private int $person;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
        /** @var ProfilePictures $pictures */
        $pictures = IntegrationContainer::get()->get(ProfilePictures::class);
        $this->pictures = $pictures;
        /** @var UserProfileRepository $profiles */
        $profiles = IntegrationContainer::get()->get(UserProfileRepository::class);
        $this->profiles = $profiles;
        $fixture = new IntegrationDataFixture($this->db);
        $this->person = $fixture->createUser('Pictured person', 'pictured-' . $fixture->suffix() . '@example.test');
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testAPersonWithoutAnUploadHasTheirDrawnAvatarAndNothingIsStored(): void
    {
        $picture = $this->pictures->picture($this->person);
        self::assertTrue($picture['drawn']);
        self::assertSame('image/svg+xml', $picture['mime_type']);
        self::assertStringStartsWith('<svg', $picture['bytes']);
        self::assertSame($picture['bytes'], $this->pictures->picture($this->person)['bytes'], 'Always the same one.');
        self::assertSame(0, (int) $this->db->fetchOne('SELECT COUNT(*) FROM user_profile_images WHERE user_id = :id', ['id' => $this->person]), 'Nothing stored.');
        self::assertSame(['drawn' => true, 'chosen' => false, 'version' => $picture['version']], $this->pictures->state($this->person));
    }

    public function testShowMeAnotherChangesThePictureAndItsAddressAndTheFirstComesBack(): void
    {
        $first = $this->pictures->picture($this->person);
        $this->pictures->showAnother($this->person);
        $another = $this->pictures->picture($this->person);
        self::assertNotSame($first['bytes'], $another['bytes']);
        self::assertNotSame($first['version'], $another['version'], 'A new address, so no browser keeps the old one.');
        self::assertTrue($this->pictures->state($this->person)['chosen'] ?? false);
        $this->pictures->firstAgain($this->person);
        self::assertSame($first['bytes'], $this->pictures->picture($this->person)['bytes'], 'Back to the first one.');
    }

    public function testAnUploadTakesThePlaceOfTheAvatarUntilItIsRemoved(): void
    {
        $png = (string) base64_decode('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGP4z8DwHwAFAAH/iZk9HQAAAABJRU5ErkJggg==');
        $this->profiles->storeImage($this->person, $png, 'image/png', 1, 1);
        $uploaded = $this->pictures->picture($this->person);
        self::assertFalse($uploaded['drawn']);
        self::assertSame('image/png', $uploaded['mime_type']);
        self::assertSame($png, $uploaded['bytes']);
        $this->profiles->removeImage($this->person);
        self::assertTrue($this->pictures->picture($this->person)['drawn'], 'Removed: the drawn avatar again.');
    }

    public function testAPageOfPeopleGetsTheirPictureAddressesInOneGo(): void
    {
        $rows = $this->pictures->withPictures([['id' => $this->person, 'name' => 'Pictured person'], ['id' => 999999999, 'name' => 'Gone']]);
        self::assertSame('/admin/people/' . $this->person . '/profile-image?v=' . $this->pictures->state($this->person)['version'], $rows[0]['picture_url']);
        self::assertTrue($rows[0]['picture_drawn']);
        self::assertSame('', $rows[1]['picture_url'], 'Nobody, no picture.');
        $this->pictures->showAnother($this->person);
        self::assertNotSame($rows[0]['picture_url'], $this->pictures->withPictures([['id' => $this->person]])[0]['picture_url'], 'Another picture, another address.');
    }

    public function testAnAccountThatDoesNotExistHasNoPicture(): void
    {
        self::assertNull($this->pictures->state(999999999));
        $this->expectException(\RuntimeException::class);
        $this->pictures->picture(999999999);
    }
}
