final class BundlePositionsIntegrationTest extends TestCase
{
    private const START = 1900000000;
    private const NEXT = 1950000000;

    private Database $db;
    private DevelopmentFixture $fixture;
    private BundleService $bundles;
    private BundleRepository $records;
    private BundlePositions $positions;
    private CurrentUser $admin;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
        $this->fixture = new DevelopmentFixture($this->db);
        $this->bundles = IntegrationContainer::get()->get(BundleService::class);
        $this->positions = IntegrationContainer::get()->get(BundlePositions::class);
        $this->records = new BundleRepository($this->db);
        $id = $this->fixture->createUser('Bundle order administrator', 'bundle-order-' . $this->fixture->suffix() . '@example.test');
        $this->admin = new CurrentUser($id, Uuid::v4(), 'bundle-order@example.test', 'Bundle order administrator', ['ADMIN'], (new PermissionCatalog())->keys(), Uuid::v4());
        $this->positions->save(['ZZT', 'ZZU'], [(string) self::START, (string) self::NEXT], $id);
        $_SESSION['csrf'] = str_repeat('c', 64);
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
        unset($_SESSION['csrf'], $_SESSION['flash'], $_SESSION['bundle_draft']);
    }

    public function testANewBundleTakesTheNextNumberInItsBandAndATypedOneIsKept(): void
    {
        $a = $this->bundle('ZZT-A');
        $b = $this->bundle('ZZT-B');
        $u = $this->bundle('ZZU-A');
        $typed = $this->bundle('ZZT-C', (string) (self::START + 50));
        self::assertSame([self::START, self::START + 100, self::NEXT, self::START + 50], [$this->position($a), $this->position($b), $this->position($u), $this->position($typed)]);
        self::assertSame('ZZT: ' . self::START . ' to ' . (self::NEXT - 1) . ', room for 500000', 'ZZT: ' . $this->positions->view()['rows'][0]['band']);
        // Typed on its form; emptied, it takes the next free number in its band.
        $this->bundles->updateDetails($this->admin, $a, $this->details($a, ['catalogue_position' => '42']));
        self::assertSame(42, $this->position($a));
        $this->bundles->updateDetails($this->admin, $a, $this->details($a, ['catalogue_position' => '']));
        self::assertSame(self::START + 200, $this->position($a), '100 after the highest in its band.');
        try {
            $this->bundles->updateDetails($this->admin, $a, $this->details($a, ['catalogue_position' => 'first']));
            self::fail('A position is a whole number.');
        } catch (RuntimeException $refused) {
            self::assertSame('Enter the bundle\'s position as a whole number from 1, such as 10100, or leave it empty.', $refused->getMessage());
        }
    }

    public function testADragOrTheMenuMovesABundleBetweenItsNeighbours(): void
    {
        [$a, $b, $c] = [$this->bundle('ZZT-A'), $this->bundle('ZZT-B'), $this->bundle('ZZT-C')];
        self::assertSame([$c => self::START + 50], $this->positions->arrange($c, $a, $this->admin->id), 'Halfway between its new neighbours.');
        self::assertSame([$a, $c, $b], $this->leading([$a, $b, $c]));
        $this->positions->move($b, 'up', $this->admin->id);
        self::assertSame([$a, $b, $c], $this->leading([$a, $b, $c]));
        $this->positions->move($a, 'down', $this->admin->id);
        self::assertSame([$b, $a, $c], $this->leading([$a, $b, $c]));
        try {
            $this->positions->arrange($a, $a, $this->admin->id);
            self::fail('A bundle cannot go after itself.');
        } catch (\InvalidArgumentException $refused) {
            self::assertSame('A bundle cannot go after itself.', $refused->getMessage());
        }
    }

    public function testRenumberPutsEveryBundleBackInItsBandInItsOrder(): void
    {
        [$a, $b, $u] = [$this->bundle('ZZT-A', (string) (self::START + 7)), $this->bundle('ZZT-B', (string) (self::START + 9)), $this->bundle('ZZU-A', (string) (self::START + 8))];
        $result = $this->positions->renumber($this->admin->id);
        self::assertSame([self::START, self::START + 100, self::NEXT], [$this->position($a), $this->position($b), $this->position($u)], 'Each in its band, in the order they were.');
        self::assertGreaterThanOrEqual(3, $result['changed']);
        self::assertNotContains('ZZT-A', $result['unbanded']);
        self::assertSame([], $this->positions->renumber($this->admin->id)['crowded']);
    }

    public function testASuggestedCodeTakesThePrefixItsCoursesShare(): void
    {
        $owner = $this->fixture->createUser('Bundle order owner');
        $company = $this->fixture->createCompany($owner, 'Bundle order provider ' . $this->fixture->suffix(), $this->fixture->suffix() . '.bundle-order.example.test');
        $id = $this->bundle('ZZT-WORDS');
        foreach (['101', '102'] as $n) {
            $course = $this->fixture->createCourse($owner, $company, 'bundle-order-' . $this->fixture->suffix() . '-' . $n, 'Order course ' . $n, 'published');
            $this->db->executeStatement('UPDATE courses SET code = :code WHERE id = :id', ['code' => 'ZZV-' . $n . strtoupper(substr($this->fixture->suffix(), 0, 4)), 'id' => $course]);
            $this->bundles->addCourse($this->admin, $id, $course);
        }
        $this->bundles->updateDetails($this->admin, $id, $this->details($id, ['code' => '']));
        self::assertStringStartsWith('ZZV-', (string) ($this->records->find($id)['code'] ?? ''), 'Left empty, the code starts with the prefix its courses share.');
    }

    public function testTheListIsDraggedInItsOrderAndCarriesRenumber(): void
    {
        $this->bundle('ZZT-A');
        $page = InProcessPage::run($this->admin, AdminBundleController::class, 'index');
        self::assertSame(200, $page['status']);
        self::assertStringContainsString('data-controller="list-order"', $page['body'], 'In its order, the list can be dragged.');
        self::assertStringContainsString('action="/admin/settings/bundle-positions/renumber"', $page['body']);
        self::assertStringContainsString('class="cl-row-handle"', $page['body']);
        $sorted = InProcessPage::run($this->admin, AdminBundleController::class, 'index', [], null, ['bundles_sort' => 'title', 'bundles_dir' => 'asc']);
        self::assertStringNotContainsString('data-controller="list-order"', $sorted['body'], 'Sorted by another column, it cannot be.');
    }

    public function testAPackageCarriesEachBundlesPosition(): void
    {
        $owner = $this->fixture->createUser('Bundle package owner');
        $company = $this->fixture->createCompany($owner, 'Bundle package provider ' . $this->fixture->suffix(), $this->fixture->suffix() . '.bundle-package.example.test');
        $id = $this->bundle('ZZT-PACK');
        $codes = [];
        foreach (['1', '2'] as $n) {
            $course = $this->fixture->createCourse($owner, $company, 'bundle-package-' . $this->fixture->suffix() . '-' . $n, 'Package course ' . $n, 'published');
            $this->bundles->addCourse($this->admin, $id, $course);
            $codes[] = (string) $this->db->fetchOne('SELECT code FROM courses WHERE id = :id', ['id' => $course]);
        }
        $exported = array_values(array_filter(IntegrationContainer::get()->get(BundleCatalogue::class)->export($codes), static fn(array $entry): bool => $entry['code'] === 'ZZT-PACK'));
        self::assertSame(self::START, $exported[0]['position'] ?? null);
    }

    public function testTheCatalogueIsRenumberedInItsBands(): void
    {
        $catalogue = IntegrationContainer::get()->get(CataloguePositions::class);
        $catalogue->save(['ZZC'], [(string) self::START], $this->admin->id);
        $owner = $this->fixture->createUser('Catalogue order owner');
        $company = $this->fixture->createCompany($owner, 'Catalogue order provider ' . $this->fixture->suffix(), $this->fixture->suffix() . '.catalogue-order.example.test');
        $ids = [];
        foreach (['1' => 20, '2' => 10] as $n => $position) {
            $ids[$n] = $this->fixture->createCourse($owner, $company, 'catalogue-order-' . $this->fixture->suffix() . '-' . $n, 'Catalogue order ' . $n);
            $this->db->executeStatement('UPDATE courses SET code = :code, catalogue_position = :p WHERE id = :id', ['code' => 'ZZC-' . $n . strtoupper(substr($this->fixture->suffix(), 0, 4)), 'p' => $position, 'id' => $ids[$n]]);
        }
        $before = (string) $this->db->fetchOne('SELECT updated_at FROM courses WHERE id = :id', ['id' => $ids['1']]);
        $result = $catalogue->renumber();
        self::assertSame([self::START + 100, self::START], [(int) $this->db->fetchOne('SELECT catalogue_position FROM courses WHERE id = :id', ['id' => $ids['1']]), (int) $this->db->fetchOne('SELECT catalogue_position FROM courses WHERE id = :id', ['id' => $ids['2']])], 'In the order they were: 2 (at 10) before 1 (at 20).');
        self::assertSame(2, $result['changed'], 'Only the banded courses move; the rest keep their numbers.');
        self::assertSame($before, (string) $this->db->fetchOne('SELECT updated_at FROM courses WHERE id = :id', ['id' => $ids['1']]), 'Its place moved, not the course.');
    }

    private function bundle(string $code, string $position = ''): int
    {
        return $this->bundles->create($this->admin, ['code' => $code, 'title' => 'Order ' . $code . ' ' . $this->fixture->suffix(), 'catalogue_position' => $position]);
    }

    private function position(int $id): ?int
    {
        $value = $this->records->find($id)['catalogue_position'] ?? null;
        return $value === null ? null : (int) $value;
    }

    /**
     * @param array<string,mixed> $changes
     * @return array<string,mixed> the bundle's form as it stands, with these changes
     */
    private function details(int $id, array $changes): array
    {
        $form = $this->bundles->form($this->records->find($id));
        return array_replace(['code' => $form['code'], 'title' => $form['title'], 'slug' => $form['slug'], 'short_description' => $form['short_description'],
            'description_html' => $form['description_html'], 'cover_svg' => $form['cover_svg'], 'available_from' => $form['available_from'], 'available_until' => $form['available_until']], $changes);
    }

    /**
     * The order these bundles are listed in among all the site's bundles.
     *
     * @param list<int> $ids
     * @return list<int>
     */
    private function leading(array $ids): array
    {
        return array_values(array_filter(array_column($this->records->orderForUpdate(), 'id'), static fn(int $id): bool => in_array($id, $ids, true)));
    }
}
