declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Infrastructure\Persistence\AuthSessionRepository;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Kernel;
use CattoLearning\Legal\LegalDocuments;
use CattoLearning\Support\Env;
use CattoLearning\Support\Token;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Tests\Support\IntegrationDataFixture;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\Response;

final class LegalPagesIntegrationTest extends TestCase
{
    private Database $db;
    private IntegrationDataFixture $fixture;
    private int $learner;
    /** @var array<string,mixed> */
    private array $cookies = [];

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->fixture = new IntegrationDataFixture($this->db);
        $suffix = $this->fixture->suffix();
        $this->learner = $this->fixture->createUser('Legal Reader ' . $suffix, 'legal-reader-' . $suffix . '@seed.test');
        $this->fixture->grantRole($this->learner, 'STUDENT');
        $this->cookies = $_COOKIE;
    }

    protected function tearDown(): void
    {
        $_COOKIE = $this->cookies;
        $this->fixture->cleanup();
    }

    /** @return iterable<string,array{string,string}> */
    public static function pages(): iterable
    {
        yield 'terms' => [LegalDocuments::TERMS, 'Terms and Conditions'];
        yield 'refunds' => [LegalDocuments::REFUNDS, 'Refund Policy'];
        yield 'privacy' => [LegalDocuments::PRIVACY, 'Privacy Policy'];
    }

    #[DataProvider('pages')]
    public function testEachPageAnswersASignedOutVisitorAndASignedInLearner(string $key, string $title): void
    {
        $document = IntegrationContainer::get()->get(LegalDocuments::class)->document($key);
        self::assertSame('/' . $key, $document['path']);

        $anonymous = $this->html($document['path']);
        $this->signIn($this->learner);
        $signedIn = $this->html($document['path']);
        self::assertStringContainsString('Legal Reader', $signedIn, 'The signed-in page is drawn for the learner.');
        self::assertStringNotContainsString('Legal Reader', $anonymous);

        foreach ([$anonymous, $signedIn] as $html) {
            self::assertMatchesRegularExpression('#<h1[^>]*>' . preg_quote($title, '#') . '</h1>#', $html);
            self::assertStringContainsString('data-legal-document="' . $key . '" data-legal-version="' . $document['version'] . '"', $html, 'The version the code references is on the page.');
            self::assertStringContainsString('<strong>Version ' . $document['version'] . '</strong> - last updated <time datetime="' . $document['updated'] . '">' . $document['updated_label'] . '</time>.', $html);
            foreach (['/terms' => 'Terms', '/refunds' => 'Refunds', '/privacy' => 'Privacy'] as $href => $label) {
                self::assertMatchesRegularExpression('#<footer.*<a href="' . $href . '">' . $label . '</a>.*</footer>#s', $html, 'The Core footer lists ' . $label . '.');
            }
            self::assertStringNotContainsString('OWNER DECISION', $html);
            self::assertDoesNotMatchRegularExpression('/\[[A-Z][A-Z ]+\]/', strip_tags($html), 'No placeholder is left in the text.');
        }
    }

    public function testTheSupplierBlockPrintsTheConfiguredEmailAddressAndDomain(): void
    {
        $email = strtolower(trim(Env::string('APP_ADMIN_EMAIL')));
        $domain = IntegrationContainer::get()->get(RuntimeSettings::class)->platformDomain();
        self::assertNotSame('', $email);
        self::assertNotSame('', $domain);

        $terms = $this->html('/terms');
        self::assertStringContainsString('1. Supplier information', $terms);
        foreach ([
            'Full name' => 'Example Person',
            'Legal status' => 'Sole proprietor. Not a registered company.',
            'Trading name' => 'Catto Learning',
            'Physical address' => '1 Example Street, Example Town, 0000, South Africa',
            'Telephone' => '+27 00 000 0000',
            'Email address' => $email,
            'Website' => $domain,
            'Information Officer' => 'Example Person',
        ] as $label => $value) {
            self::assertStringContainsString('<dt>' . $label . '</dt><dd>' . htmlspecialchars($value, ENT_QUOTES) . '</dd>', $terms, $label);
        }
        self::assertStringContainsString('href="mailto:' . $email . '"', $terms);

        $privacy = $this->html('/privacy');
        self::assertStringContainsString('<dt>Email address</dt><dd>' . $email . '</dd>', $privacy);
        self::assertStringContainsString('<dt>Website</dt><dd>' . $domain . '</dd>', $privacy);
        self::assertStringContainsString('<dt>Information Officer</dt><dd>Example Person</dd>', $privacy);
        self::assertStringContainsString('href="https://inforegulator.org.za"', $privacy);
        self::assertStringContainsString('href="mailto:' . $email . '"', $this->html('/refunds'), 'A refund is asked for at the configured address.');

        // Read when the page is drawn, not written into the code: another instance prints its own.
        $previous = [$_ENV['APP_ADMIN_EMAIL'] ?? null, $_ENV['APP_DOMAIN'] ?? null];
        $_ENV['APP_ADMIN_EMAIL'] = 'owner@other-instance.example';
        $_ENV['APP_DOMAIN'] = 'other-instance.example';
        try {
            $supplier = IntegrationContainer::get()->get(LegalDocuments::class)->supplier();
        } finally {
            foreach (['APP_ADMIN_EMAIL', 'APP_DOMAIN'] as $index => $name) {
                if ($previous[$index] === null) unset($_ENV[$name]); else $_ENV[$name] = $previous[$index];
            }
        }
        self::assertSame(['owner@other-instance.example', 'other-instance.example', 'https://other-instance.example/'], [$supplier['email'], $supplier['website'], $supplier['website_url']]);
    }

    public function testTheOldPrivacyPlaceholderIsGone(): void
    {
        $privacy = $this->html('/privacy');
        self::assertStringNotContainsString('product-design statement', $privacy);
        self::assertStringContainsString('Protection of Personal Information Act 4 of 2013', $privacy);
    }

    private function signIn(int $user): void
    {
        $token = Token::generate();
        IntegrationContainer::get()->get(AuthSessionRepository::class)->create($user, Token::hash($token), 3600, 'qa', 'PHPUnit');
        $_COOKIE = $this->cookies;
        $_COOKIE[Env::string('AUTH_SESSION_COOKIE', 'catto_learning_session')] = $token;
    }

    private function send(string $url): Response
    {
        $kernel = new Kernel('test', true, CliBootstrap::boot()['instance_root']);
        try {
            return $kernel->handle(Request::create($url, 'GET'));
        } finally {
            $kernel->shutdown();
        }
    }

    private function html(string $url): string
    {
        $response = $this->send($url);
        self::assertSame(200, $response->getStatusCode(), $url . ' must render: ' . substr(strip_tags((string) $response->getContent()), 0, 600));
        return (string) $response->getContent();
    }
}
