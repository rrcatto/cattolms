final class SitePresentationIntegrationTest extends TestCase
{
    private Database $db;
    private IntegrationDataFixture $fixture;
    private CourseItemService $items;
    private CourseItemRepository $repository;
    private int $admin;
    private int $item;
    /** @var array<string,mixed> */
    private array $cookies = [];

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->fixture = new IntegrationDataFixture($this->db);
        $this->items = IntegrationContainer::get()->get(CourseItemService::class);
        $this->repository = IntegrationContainer::get()->get(CourseItemRepository::class);
        $suffix = $this->fixture->suffix();
        $this->admin = $this->fixture->createUser('Presentation author ' . $suffix, 'presentation-author-' . $suffix . '@seed.test');
        $this->cookies = $_COOKIE;
        $this->item = $this->items->create(['item_key' => 'site-check-' . $suffix, 'item_type' => 'slide_deck', 'title' => 'About this site ' . $suffix, 'description_html' => 'An introduction', 'deck_kind' => 'site', 'deck_theme' => 'dark', 'slides' => [
            ['layout' => 'title', 'title' => 'Welcome', 'heading' => 'Welcome to this site'],
            ['layout' => 'cta', 'title' => 'Join us', 'heading' => 'Join us', 'text' => 'More is coming.', 'actions' => ['register', 'courses']],
            ['layout' => 'picture', 'title' => 'The emblem', 'picture' => '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10"></svg>', 'alt' => 'An emblem'],
        ]], $this->admin);
    }

    protected function tearDown(): void
    {
        $_COOKIE = $this->cookies;
        $this->db->executeStatement('DELETE FROM course_items WHERE id = :id', ['id' => $this->item]);
        $this->fixture->cleanup();
    }

    public function testTheFrontPageLinksToItAndItPlaysForAnyone(): void
    {
        self::assertSame($this->item, (int) $this->repository->sitePresentation()['id'], 'The most recently saved is the site\'s.');
        self::assertStringContainsString('href="/presentation#presentation"', $this->get('/'));
        $page = $this->get('/presentation');
        self::assertStringContainsString('<h1', $page);
        self::assertStringContainsString('class="cw-deck"', $page);
        self::assertStringContainsString('data-cw-kind="site"', $page);
        self::assertStringContainsString('href="/register">Register</a>', $page);
        self::assertStringContainsString('href="/courses">Browse the courses</a>', $page);

        $token = Token::generate();
        IntegrationContainer::get()->get(AuthSessionRepository::class)->create($this->admin, Token::hash($token), 3600, 'qa', 'PHPUnit');
        $_COOKIE[Env::string('AUTH_SESSION_COOKIE', 'catto_learning_session')] = $token;
        $signedIn = $this->get('/presentation');
        self::assertStringNotContainsString('href="/register">Register</a>', $signedIn, 'Someone signed in is not asked to register.');
        self::assertStringContainsString('href="/courses">Browse the courses</a>', $signedIn);
    }

    public function testAnAdministratorEditsItLikeAnyOtherPresentation(): void
    {
        $this->fixture->grantRole($this->admin, 'ADMIN');
        $token = Token::generate();
        IntegrationContainer::get()->get(AuthSessionRepository::class)->create($this->admin, Token::hash($token), 3600, 'qa', 'PHPUnit');
        $_COOKIE[Env::string('AUTH_SESSION_COOKIE', 'catto_learning_session')] = $token;
        $slide = (string) $this->items->item($this->item)['type_config']['slides'][0]['id'];
        // Each kind names its own icon and note on the details page, so a kind without them stops that page for every presentation.
        $details = $this->get('/admin/course-items/' . $this->item . '/details');
        self::assertStringContainsString('Introducing the site', $details);
        self::assertStringContainsString('Course trailer', $details);
        self::assertStringNotContainsString('Something went wrong', $this->get('/admin/course-items/' . $this->item));
        self::assertStringNotContainsString('Something went wrong', $this->get('/admin/course-items/' . $this->item . '/slides/' . $slide));
        $layouts = $this->get('/admin/course-items/' . $this->item . '/slides/add');
        self::assertStringContainsString('value="cta"', $layouts, 'Its call to action can be chosen.');
        self::assertStringNotContainsString('value="next"', $layouts, 'Up next hands back to a course, and it is in none.');
    }

    public function testACataloguePackageCarriesItAndLeavesASitesOwnAlone(): void
    {
        $package = IntegrationContainer::get()->get(CataloguePackage::class);
        $course = (int) $this->db->fetchOne('SELECT min(id) FROM courses WHERE code IS NOT NULL');
        if ($course < 1) { self::markTestSkipped('No course to export.'); }
        $path = $package->export($this->admin, [$course]);
        try {
            $zip = new ZipArchive();
            self::assertTrue($zip->open($path) === true);
            $carried = json_decode((string) $zip->getFromName(CataloguePackage::SITE_PRESENTATION), true);
            $zip->close();
            self::assertSame('site', $carried['deck']['kind']);
            self::assertCount(3, $carried['deck']['slides']);
            $key = $package->stageFile($path, 'catalogue.zip', $this->admin);
            self::assertSame('here', $package->plan($key)['site_presentation'], 'A site with its own keeps it.');
            $package->discard($key);
        } finally {
            @unlink($path);
        }
    }

    private function get(string $url): string
    {
        $kernel = new Kernel('test', true, CliBootstrap::boot()['instance_root']);
        $_GET = Request::create($url)->query->all();
        try {
            $response = $kernel->handle(Request::create($url, 'GET'));
            self::assertSame(200, $response->getStatusCode(), $url);
            return (string) $response->getContent();
        } finally {
            $kernel->shutdown();
            $_GET = [];
        }
    }
}
