declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Auth\AuthService;
use CattoLearning\Auth\CattolmsAccounts;
use CattoLearning\Auth\RoleCatalog;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Infrastructure\Persistence\RoleRepository;
use CattoLearning\Tests\Support\DevelopmentFixture;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoPHP\Settings\Settings;
use CattoPHP\SignIn\SignInAccounts;
use PHPUnit\Framework\TestCase;

final class CattolmsAccountsIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
        IntegrationContainer::get()->get(Settings::class)->refresh();
    }

    public function testAPersonIsFoundByAVerifiedAddressOrTheirNumberWhileActive(): void
    {
        $container = IntegrationContainer::get();
        $accounts = $container->get(CattolmsAccounts::class);
        self::assertInstanceOf(SignInAccounts::class, $accounts);
        $fixture = new DevelopmentFixture($this->db);
        $suffix = $fixture->suffix();
        $email = 'account-' . $suffix . '@example.test';
        $person = $fixture->createUser('Account Person', $email);
        $this->db->executeStatement("UPDATE users SET first_name = 'Nomsa', last_name = 'Dlamini' WHERE id = :id", ['id' => $person]);
        $this->db->executeStatement("INSERT INTO user_emails (user_id, email, is_primary, verified_at, created_at) VALUES (:id, :email, FALSE, NULL, NOW())",
            ['id' => $person, 'email' => 'unverified-' . $suffix . '@example.test']);

        $found = $accounts->forEmail(strtoupper($email));
        self::assertNotNull($found);
        self::assertSame([(string) $person, $email, 'Nomsa Dlamini', false], [$found->id, $found->email, $found->name, $found->administrator]);
        self::assertNull($accounts->forEmail('unverified-' . $suffix . '@example.test'), 'an address not yet verified signs nobody in');
        self::assertNull($accounts->forId('not-a-number'));

        $container->get(RoleRepository::class)->assign($person, RoleCatalog::ADMIN);
        self::assertTrue($accounts->forId((string) $person)?->administrator);

        $this->db->executeStatement("UPDATE users SET status = 'disabled' WHERE id = :id", ['id' => $person]);
        self::assertNull($accounts->forId((string) $person), 'a disabled account signs nobody in');
    }

    public function testTheSignInSettingsAreCattoPhpsAndTheSignInReadsThem(): void
    {
        $container = IntegrationContainer::get();
        $settings = $container->get(Settings::class);
        foreach (['AUTH_SIGNIN', 'AUTH_SIGNIN_ALLOWED_EMAILS', 'AUTH_TWO_STEP', 'AUTH_MAGIC_LINK_TTL', 'AUTH_SESSION_TTL', 'AUTH_REQUEST_LIMIT_EMAIL', 'AUTH_REQUEST_LIMIT_IP', 'AUTH_REQUEST_WINDOW'] as $name) {
            $settings->envValue($name);
        }
        $auth = $container->get(AuthService::class);
        $settings->set('AUTH_MAGIC_LINK_TTL', '10m');
        self::assertSame(600, $auth->linkLifetime(), 'the Settings page\'s override');
        $settings->reset('AUTH_MAGIC_LINK_TTL');
        self::assertSame($settings->duration('AUTH_MAGIC_LINK_TTL')->lengthInSeconds(), $auth->linkLifetime(), '.env again');
    }
}
