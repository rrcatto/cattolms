declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Auth\CurrentUser;
use CattoLearning\Commerce\Application\OrderService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Support\Uuid;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Tests\Support\IntegrationDataFixture;
use PHPUnit\Framework\TestCase;

final class CompanyOrdersIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testACompanysOrderOpensForEachOfItsAdministratorsOnly(): void
    {
        $fixture = new IntegrationDataFixture($this->db);
        $suffix = $fixture->suffix();
        $buyer = $fixture->createUser('Buying Admin', 'buyer@orders-' . $suffix . '.test');
        $founder = $fixture->createUser('Founder', 'founder@orders-' . $suffix . '.test');
        $member = $fixture->createUser('Member', 'member@orders-' . $suffix . '.test');
        $outsider = $fixture->createUser('Outsider', 'admin@other-' . $suffix . '.test');
        $company = $fixture->createCompany($founder, 'Orders Company', 'orders-' . $suffix . '.test');
        $other = $fixture->createCompany($outsider, 'Other Company', 'other-' . $suffix . '.test');
        $fixture->addCompanyMember($company, $buyer, 'administrator');
        $fixture->addCompanyMember($company, $founder, 'owner');
        $fixture->addCompanyMember($company, $member);
        $fixture->addCompanyMember($other, $outsider, 'administrator');
        /** @var OrderService $orders */
        $orders = IntegrationContainer::get()->get(OrderService::class);
        $companyOrder = ['purchaser_user_id' => $buyer, 'company_id' => $company];

        self::assertTrue($orders->mayOpen($this->actor($buyer), $companyOrder), 'Its buyer.');
        self::assertTrue($orders->mayOpen($this->actor($founder), $companyOrder), 'Another administrator of the company, its founder.');
        self::assertFalse($orders->mayOpen($this->actor($member), $companyOrder), 'Not a member who is not an administrator.');
        self::assertFalse($orders->mayOpen($this->actor($outsider), $companyOrder), 'Not another company\'s administrator.');
        self::assertFalse($orders->mayOpen($this->actor($founder), ['purchaser_user_id' => $buyer, 'company_id' => null]), 'A private order stays its buyer\'s.');
    }

    private function actor(int $id): CurrentUser
    {
        return new CurrentUser($id, Uuid::v4(), 'actor-' . $id . '@example.test', 'Actor', ['COMPANY_ADMIN'], ['COMMERCE.ORDER.VIEW', 'COMPANY.ORDER.VIEW'], Uuid::v4());
    }
}
