    /**
     * A failure after the deletion rolls the whole operation back.
     *
     * The bookkeeping - marking the set cleaned, writing the audit row - is inside the same
     * transaction as the deletion. Before that change the deletion committed first, so a failure
     * in either left the rows gone while `seed_data` still reported the set as live.
     *
     * The failure is injected by making the audit insert impossible for the duration of the
     * transaction: a deferred constraint the audit row cannot satisfy. The deletion has already
     * happened by then, which is exactly the window being tested.
     */
    public function testAFailureAfterDeletionRollsTheWholeOperationBack(): void
    {
        $rowsBefore = $this->rowCount(
            'SELECT COUNT(*)::int AS total FROM users WHERE seed_token = :token::uuid',
            [':token' => $this->setA['token']]
        );
        self::assertGreaterThan(0, $rowsBefore, 'The set must have identities for this to prove anything.');

        // A trigger that refuses every audit insert, for this test only.
        // Single-quoted on purpose. PostgreSQL dollar-quoting uses $tag$ ... $tag$, and in a
        // double-quoted PHP string PHP reads that as a variable and interpolates it away.
        $this->db->exec(
            'CREATE OR REPLACE FUNCTION catto_test_refuse_audit() RETURNS trigger AS $refuse$
             BEGIN RAISE EXCEPTION \'injected failure after deletion\'; END;
             $refuse$ LANGUAGE plpgsql'
        );
        $this->db->exec(
            'CREATE TRIGGER catto_test_refuse_audit_trigger
             BEFORE INSERT ON audit_log FOR EACH ROW EXECUTE FUNCTION catto_test_refuse_audit()'
        );

        $failed = false;
        try {
            $this->seeds->cleanup($this->setA['token'], $this->adminUserId);
        } catch (Throwable $exception) {
            $failed = true;
        } finally {
            $this->db->exec('DROP TRIGGER IF EXISTS catto_test_refuse_audit_trigger ON audit_log');
            $this->db->exec('DROP FUNCTION IF EXISTS catto_test_refuse_audit()');
        }

        self::assertTrue($failed, 'The injected failure must propagate rather than being swallowed.');

        // Everything is as it was.
        self::assertSame(
            $rowsBefore,
            $this->rowCount(
                'SELECT COUNT(*)::int AS total FROM users WHERE seed_token = :token::uuid',
                [':token' => $this->setA['token']]
            ),
            'The deletion must have been rolled back with the failed bookkeeping.'
        );
        self::assertTrue($this->exists('courses', $this->setA['course']), 'The target course must still exist.');
        self::assertTrue($this->exists('course_enrolments', $this->crossSetEnrolmentId), 'The collateral must still exist.');

        $set = $this->repository->findSet($this->setA['token']);
        self::assertNotNull($set);
        self::assertNull($set['cleaned_at'], 'The set must not be marked cleaned when the operation failed.');

        self::assertSame(
            0,
            $this->rowCount(
                "SELECT COUNT(*)::int AS total FROM audit_log WHERE event_key = 'seed.set_cleaned'
                 AND metadata->>'seed_token' = :token",
                [':token' => $this->setA['token']]
            ),
            'No completed-cleanup audit row may survive a rolled-back cleanup.'
        );

        // And the operation still works once the injected failure is gone.
        $this->seeds->cleanup($this->setA['token'], $this->adminUserId);
        self::assertFalse($this->exists('courses', $this->setA['course']));
    }

