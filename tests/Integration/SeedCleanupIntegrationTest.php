    private function createLoginToken(string $email, ?int $userId): string
    {
        $hash = hash('sha256', Token::generate() . $email . ($userId ?? 0));
        $this->fixture->rememberTokenEmail($email);
        $this->db->exec(
            "INSERT INTO auth_login_tokens (user_id,email,purpose,token_hash,context,expires_at,requested_ip_hash,created_at)
             VALUES (:user_id,:email,'login',:hash,'{}'::jsonb, NOW() + INTERVAL '15 minutes', :ip, NOW())",
            [':user_id' => $userId, ':email' => $email, ':hash' => $hash, ':ip' => hash('sha256', '127.0.0.1')]
        );

        return $hash;
    }

