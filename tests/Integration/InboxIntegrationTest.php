    public function testTheSettingsAreReadSavedAndReset(): void
    {
        $settings = IntegrationContainer::get()->get(InboxSettings::class);
        self::assertSame(['30 days', 60, 'html'], [$settings->trashKeptFor()->words(), $settings->spamLine(), $settings->replyFormat()]);
        $settings->saveAll(['inbox_trash_kept_for' => '2w', 'inbox_spam_line' => '70', 'inbox_reply_format' => 'plain', 'inbox_learn' => 'on', 'inbox_notify_email' => 'on', 'inbox_acknowledge' => 'on', 'inbox_hold_blocked_countries' => 'on', 'inbox_signature_text' => "Kind regards\nThe team"], null);
        try {
            self::assertSame(['2 weeks', 70, 'plain', false], [$settings->trashKeptFor()->words(), $settings->spamLine(), $settings->replyFormat(), $settings->notifiesByTelegram()], 'A tick left unticked is off.');
            self::assertSame("Kind regards\nThe team", $settings->signature('plain'));
        } finally {
            $settings->resetAll();
        }
        self::assertSame(['30 days', 60], [$settings->trashKeptFor()->words(), $settings->spamLine()]);
    }
