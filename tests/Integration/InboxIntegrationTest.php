    public function testMarkingTeachesTheFilterAndChangingTheVerdictTakesItBack(): void
    {
        $tag = $this->fixture->suffix();
        $admin = $this->fixture->createUser('Inbox administrator', 'inbox-admin-' . $tag . '@example.test');
        [, $id] = $this->send('Lerato Khumalo', 'lerato-' . $tag . '@example.test', 'Unbeatable zorbifuzz offer on quantumwidgets today', 120);
        $before = $this->inbox->trained();
        $this->inbox->markSpam([$id], $admin);
        self::assertSame('spam', $this->inbox->conversation($id)['folder'] ?? null);
        self::assertSame($before['spam'] + 1, $this->inbox->trained()['spam']);
        self::assertSame([1, 0], array_map('intval', array_values($this->db->fetchAssociative("SELECT spam_count, ham_count FROM cattophp_inbox_spam_tokens WHERE token = 'zorbifuzz'") ?: [])));
        $this->inbox->markSpam([$id], $admin);
        self::assertSame(1, (int) $this->db->fetchOne("SELECT spam_count FROM cattophp_inbox_spam_tokens WHERE token = 'zorbifuzz'"), 'Marked twice, learnt once.');

        $this->inbox->notSpam([$id], $admin);
        self::assertSame(['inbox', 'ham'], [$this->inbox->conversation($id)['folder'] ?? null, $this->inbox->conversation($id)['spam_verdict'] ?? null]);
        self::assertSame([0, 1], array_map('intval', array_values($this->db->fetchAssociative("SELECT spam_count, ham_count FROM cattophp_inbox_spam_tokens WHERE token = 'zorbifuzz'") ?: [])), 'The spam count is taken back.');
        self::assertSame($before['spam'], $this->inbox->trained()['spam']);

        $blocked = $this->inbox->blockSender($id, 'email', $admin);
        self::assertSame('lerato-' . $tag . '@example.test', $blocked);
        self::assertSame('spam', $this->inbox->conversation($id)['folder'] ?? null, 'Blocking the sender sends it to Spam.');
        [, $later] = $this->send('Lerato Khumalo', 'lerato-' . $tag . '@example.test', 'Hello again, a plain question about a course.', 120);
        self::assertSame('spam', $this->inbox->conversation($later)['folder'] ?? null, 'A blocked sender\'s later message goes straight to Spam.');
    }

    public function testDeleteRestoreAndDeleteForeverAndTheDailyCleanUp(): void
    {
        $tag = $this->fixture->suffix();
        $admin = $this->fixture->createUser('Inbox administrator', 'inbox-admin-' . $tag . '@example.test');
        [, $id] = $this->send('Sipho Nkosi', 'sipho-' . $tag . '@example.test', 'Test message, please delete.', 120);
        self::assertSame(1, $this->inbox->trash([$id], $admin));
        self::assertSame(['trash', 'Inbox'], [$this->inbox->conversation($id)['folder'] ?? null, $this->inbox->folder('trash', ['search' => $tag], 25, 0)['rows'][0]['from_folder'] === 'inbox' ? 'Inbox' : 'Spam']);
        self::assertSame(1, $this->inbox->deleteForever([$id], $admin));
        self::assertNull($this->inbox->conversation($id), 'Delete forever in the Trash removes it for good.');

        [, $kept] = $this->send('Ayesha Patel', 'ayesha-' . $tag . '@example.test', 'The video in Module 3 no longer plays.', 120);
        $this->inbox->trash([$kept], $admin);
        self::assertSame(1, $this->inbox->restore([$kept], $admin));
        self::assertSame('inbox', $this->inbox->conversation($kept)['folder'] ?? null, 'Restore puts it back where it was.');
        self::assertSame(0, $this->inbox->deleteForever([$kept], $admin), 'Delete forever never touches the Inbox.');

        $this->inbox->trash([$kept], $admin);
        $this->db->executeStatement("UPDATE cattophp_inbox_conversations SET trashed_at = now() - interval '31 days' WHERE id = :id", ['id' => $kept]);
        $gone = $this->engine->cleanUp();
        self::assertGreaterThanOrEqual(1, $gone['trash']);
        self::assertNull($this->inbox->conversation($kept), 'The daily clean-up empties the Trash after 30 days.');
    }

    public function testAReplyIsDraftedSentThreadedAndADiscardedDraftWaitsInTheTrash(): void
    {
        $tag = $this->fixture->suffix();
        $admin = $this->fixture->createUser('Inbox administrator', 'inbox-admin-' . $tag . '@example.test');
        [$reference, $id] = $this->send('Johan van Wyk', 'johan-' . $tag . '@example.test', 'I changed my email address and now my company says I left.', 120);
        $replies = $this->replies();
        $compose = $replies->compose($this->inbox->conversation($id) ?? []);
        self::assertSame('Re: Other [' . $reference . ']', $compose['subject'], 'The subject carries the reference an answer is matched by.');

        $file = tempnam(sys_get_temp_dir(), 'inbox');
        file_put_contents((string) $file, 'Steps to keep your account.');
        $upload = new \Symfony\Component\HttpFoundation\File\UploadedFile((string) $file, 'steps.txt', 'text/plain', null, true);
        $draft = $replies->save($id, ['format' => 'html', 'subject' => $compose['subject'], 'body_html' => '<h2>Good morning</h2><p>Your membership follows your <strong>primary</strong> address.</p><script>alert(1)</script>', 'mark_answered' => '1'], [$upload], (string) $admin, false);
        self::assertFalse($draft['sent']);
        self::assertSame($draft['item_id'], $replies->compose($this->inbox->conversation($id) ?? [])['draft_id'], 'It is the conversation\'s draft.');
        self::assertSame([], array_filter($this->mailer->messages, static fn(array $m): bool => $m['type'] === 'inbox_reply'), 'A draft sends nothing.');

        $sent = $replies->save($id, ['format' => 'html', 'subject' => $compose['subject'], 'body_html' => '<h2>Good morning</h2><p>Your membership follows your <strong>primary</strong> address.</p><script>alert(1)</script>', 'mark_answered' => '1'], [], (string) $admin, true);
        self::assertTrue($sent['sent'], $sent['error']);
        $mail = array_values(array_filter($this->mailer->messages, static fn(array $m): bool => $m['type'] === 'inbox_reply'))[0];
        self::assertSame('johan-' . $tag . '@example.test', $mail['email']);
        self::assertStringContainsString('<strong>primary</strong>', $mail['html']);
        self::assertStringNotContainsString('<script', $mail['html'], 'The reply keeps what the editor writes and nothing else.');
        self::assertStringContainsString('Good morning', $mail['text'], 'An HTML reply carries a plain text copy.');
        self::assertSame(['steps.txt'], $mail['attachments'], 'The draft\'s file goes with it.');
        self::assertMatchesRegularExpression('/^<inbox\.[0-9a-f-]{36}@[^>]+>$/', $mail['message_id']);
        $conversation = $this->inbox->conversation($id) ?? [];
        self::assertTrue($conversation['answered'], 'Sent with the tick, it marks the message answered.');
        self::assertSame(['Message received', 'Acknowledgement sent', 'Your reply'], array_column($conversation['items'], 'label'));
        self::assertSame($reference, $this->inbox->replies('sent', $tag, 25, 0)['rows'][0]['reference'] ?? null, 'It is in Sent.');
        self::assertSame($id, IntegrationContainer::get()->get(InboxStore::class)->conversationFor(trim($mail['message_id'], '<>'), 'Re: anything'), 'An answer naming it threads into the conversation.');
        self::assertSame($id, IntegrationContainer::get()->get(InboxStore::class)->conversationFor(null, 'RE: Re: Other [' . strtolower($reference) . ']'), 'Or by the reference in its subject.');

        $replies->save($id, ['format' => 'plain', 'subject' => 'A second thought', 'body_text' => 'One more thing.'], [], (string) $admin, false);
        self::assertTrue($replies->discard($id, (string) $admin));
        $trashed = array_filter($this->inbox->trashedDrafts(), static fn(array $d): bool => $d['reference'] === $reference);
        self::assertCount(1, $trashed, 'A discarded draft waits in the Trash.');
        self::assertSame(1, $this->inbox->restoreDrafts([(int) array_values($trashed)[0]['id']], $admin));
        self::assertSame('One more thing.', trim((string) ($replies->compose($this->inbox->conversation($id) ?? [])['body_text'])), 'Restored, it is the draft being written again.');
    }

    public function testAnAnswerFromTheMailboxIsFiledIntoItsConversationOnce(): void
    {
        $tag = $this->fixture->suffix();
        $admin = $this->fixture->createUser('Inbox administrator', 'inbox-admin-' . $tag . '@example.test');
        [$reference, $id] = $this->send('Pieter Joubert', 'pieter-' . $tag . '@example.test', 'Does the Basic Bookkeeping course cover VAT returns?', 120);
        $sent = $this->replies()->save($id, ['format' => 'plain', 'subject' => 'Re: Other [' . $reference . ']', 'body_text' => 'VAT returns come in a later course.', 'mark_answered' => '1'], [], (string) $admin, true);
        self::assertTrue($sent['sent']);
        $messageId = (string) $this->db->fetchOne('SELECT message_id FROM cattophp_inbox_items WHERE id = :id', ['id' => $sent['item_id']]);
        $this->inbox->trash([$id], $admin);
        $job = IntegrationContainer::get()->get(InboxMailbox::class);

        $answer = MimeMessage::parse("From: Pieter Joubert <pieter-{$tag}@example.test>\nSubject: Re: something else\nMessage-ID: <answer-{$tag}@example.test>\nIn-Reply-To: <{$messageId}>\n\nWhich course is it?");
        self::assertTrue($job->file($answer), 'Matched by the email it answers.');
        self::assertFalse($job->file($answer), 'Filed once.');
        $conversation = $this->inbox->conversation($id) ?? [];
        self::assertSame(['inbox', false], [$conversation['folder'] ?? null, $conversation['answered'] ?? null], 'Out of the Trash, and not answered until replied to.');
        self::assertSame('Answer received', $this->inbox->folder('inbox', ['search' => $tag], 25, 0)['rows'][0]['status']['label'] ?? null);
        self::assertSame('Which course is it?', end($conversation['items'])['body_text'] ?? null);

        self::assertTrue($job->file(MimeMessage::parse("From: pieter-{$tag}@example.test\nSubject: RE: Re: Other [{$reference}]\nMessage-ID: <second-{$tag}@example.test>\n\nThanks.")), 'Or by the reference in its subject.');
        self::assertFalse($job->file(MimeMessage::parse("From: pieter-{$tag}@example.test\nAuto-Submitted: auto-replied\nSubject: Re: Other [{$reference}]\n\nI am away.")), 'An automatic reply is left alone.');
        self::assertFalse($job->file(MimeMessage::parse("From: someone@example.test\nSubject: Newsletter\n\nHello.")), 'Mail answering no conversation is left alone.');
    }

    public function testEveryInboxPageIsDrawn(): void
    {
