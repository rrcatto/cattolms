    public function testANarrationIsKeptUnderItsSlideHeardOnlyByThoseWhoMaySeeItAndGoesWithItsSlide(): void
    {
        $item = $this->items->createAttached($this->course, ['item_key' => 'narrated-' . $this->suffix, 'item_type' => 'slide_deck', 'title' => 'Narrated'] + $this->deck(), $this->owner);
        $slides = $this->items->item($item)['type_config']['slides'];
        $clip = $this->narrations->save($item, (string) $slides[0]['id'], $this->wav(), 1.5, $this->owner);
        $clipPath = $this->narrations->path((string) $clip['public_id'], 'audio/wav');
        $this->files[] = $clipPath;
        self::assertFileExists($clipPath);
        self::assertSame('audio/wav', $clip['content_type']);
        self::assertSame([(string) $slides[0]['id'] => (string) $clip['public_id']], $this->narrations->forItem($item));
        self::assertNotNull($this->narrations->playable((string) $clip['public_id'], $this->owner, false), 'The course\'s author hears it.');
        self::assertNull($this->narrations->playable((string) $clip['public_id'], null, false), 'A visitor does not: the course is a draft and the item is not public.');
        try {
            $this->narrations->save($item, 'notaslide1', $this->wav(), null, $this->owner);
            self::fail('A slide that is not in the deck takes no narration.');
        } catch (InvalidArgumentException $exception) {
            self::assertStringContainsString('not in it yet', $exception->getMessage());
        }
        $input = $this->deck();
        $input['slides'] = array_slice($slides, 1);
        $this->items->update($item, $input + ['item_key' => 'narrated-' . $this->suffix, 'item_type' => 'slide_deck', 'title' => 'Narrated'], $this->owner);
        $this->narrations->keepOnly($item);
        self::assertSame([], $this->narrations->forItem($item), 'Removing the slide removed its narration.');
        self::assertFileDoesNotExist($clipPath);
    }

    /** A tenth of a second of silence, as a WAV file. */
    private function wav(): string
    {
        $samples = str_repeat("\x00\x00", 800);
        $wav = 'RIFF' . pack('V', 36 + strlen($samples)) . 'WAVEfmt ' . pack('VvvVVvv', 16, 1, 1, 8000, 16000, 2, 16) . 'data' . pack('V', strlen($samples)) . $samples;
        $file = tempnam(sys_get_temp_dir(), 'narration');
        file_put_contents($file, $wav);
        $this->files[] = $file;
        return $file;
    }
