declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Course\CourseFile;
use CattoLearning\Course\CourseItemService;
use CattoLearning\Course\CoursePortabilityService;
use CattoLearning\Course\CourseRepository;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\DevelopmentFixture;
use CattoLearning\Tests\Support\SpecificationExample;
use PHPUnit\Framework\TestCase;
use Psr\Container\ContainerInterface;

final class CourseFileIntegrationTest extends TestCase
{
    private ContainerInterface $container;
    private Database $db;
    private CoursePortabilityService $portability;
    private int $admin;

    protected function setUp(): void
    {
        $this->container = CliBootstrap::boot()['container'];
        $this->db = $this->container->get(Database::class);
        $this->portability = $this->container->get(CoursePortabilityService::class);
        $this->db->beginTransaction();
        $this->admin = (new DevelopmentFixture($this->db))->person('ADMIN')['id'];
        if ((int) $this->db->fetchOne("SELECT count(*) FROM courses WHERE code IN ('GDN-101', 'GDN-102')") > 0) self::markTestSkipped('A GDN course is on this site.');
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) { $this->db->rollBack(); }
    }

    public function testACourseComesBackFromItsFile(): void
    {
        $courseId = $this->import(SpecificationExample::html(), 'example.html');
        $file = $this->container->get(CourseFile::class)->fromCourse($courseId);
        self::assertSame([], $file['left_out'], 'The example has nothing a course file cannot hold.');
        self::assertSame('GDN-101-growing-vegetables-in-small-spaces.html', $file['filename']);
        $html = $file['html'];
        self::assertSame(0, preg_match('/<details\b[^>]*\bopen\b|class="[^"]*\bacc-/', $html), 'Every panel is a closed <details>, never a button panel.');
        self::assertSame(1 + 5 + 2 + 1, substr_count($html, '<details class="panel">') + substr_count($html, '<details class="sub ') + substr_count($html, '<details class="block '), 'The module, its five part panels, its two blocks and the final assessment.');

        $again = $this->import(str_replace(['content="GDN-101"', '<h1>Growing Vegetables in Small Spaces</h1>'], ['content="GDN-102"', '<h1>Growing Vegetables Again</h1>'], $html), 'again.html');
        self::assertSame($this->parts($courseId), $this->parts($again), 'The same parts with the same content, in the same order.');
        $courses = $this->container->get(CourseRepository::class);
        foreach (['subtitle', 'summary', 'level', 'cover_svg'] as $field) {
            self::assertSame((string) $courses->findById($courseId)[$field], (string) $courses->findById($again)[$field], $field);
        }
        self::assertSame(
            array_map(static fn(array $band): array => [$band['grade_label'], (float) $band['minimum_percentage']], $courses->gradeBands($courseId)),
            array_map(static fn(array $band): array => [$band['grade_label'], (float) $band['minimum_percentage']], $courses->gradeBands($again))
        );
    }

    public function testACourseThatStartsAtModuleZeroKeepsItsNumbering(): void
    {
        $html = str_replace(['id="mod-m1"', 'data-deck="m1"', 'data-cards="m1"', 'data-quiz="m1"', 'data-key="m1"', '"m1": [', '"m1": {'], ['id="mod-m0"', 'data-deck="m0"', 'data-cards="m0"', 'data-quiz="m0"', 'data-key="m0"', '"m0": [', '"m0": {'], SpecificationExample::html());
        $courseId = $this->import($html, 'zero.html');
        self::assertSame(0, (int) $this->container->get(CourseRepository::class)->findById($courseId)['first_module_number']);
        $file = $this->container->get(CourseFile::class)->fromCourse($courseId)['html'];
        self::assertStringContainsString('<section class="module" id="mod-m0"', $file);
        self::assertStringContainsString('<span class="num">00</span>', $file);
    }

    public function testTheFilesScriptIsTheSpecificationsExampleScript(): void
    {
        preg_match_all('/<script>\n(.*?)<\/script>/s', SpecificationExample::html(), $scripts);
        self::assertSame(file_get_contents(dirname(__DIR__, 2) . '/resources/course-file/course.js'), $scripts[1][1] ?? null, 'resources/course-file/course.js and the example in the specification are the same script.');
    }

    private function import(string $html, string $name): int
    {
        $file = (string) tempnam(sys_get_temp_dir(), 'course-file');
        file_put_contents($file, $html);
        try {
            $analysis = $this->portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => $name, 'tmp_name' => $file], $this->admin);
            self::assertSame([], array_values((array) $analysis['warnings']), $name . ' imports without a warning.');
            return $this->portability->commitImport((string) $analysis['import_key'], 0, $this->admin);
        } finally {
            @unlink($file);
        }
    }

    /** @return list<string> each section's title and each part's kind with its content, whitespace aside */
    private function parts(int $courseId): array
    {
        $items = $this->container->get(CourseItemService::class);
        $out = [];
        foreach ($items->availability($courseId, null, false) as $row) {
            if ($row['node_type'] === 'section') { $out[] = 'section ' . $row['section_title'] . ' ' . (string) $row['section_introduction_html']; continue; }
            $item = $items->item((int) $row['course_item_id']);
            $out[] = $row['part'] . ' ' . (string) preg_replace('/>\s+</', '><', trim((string) $item['content_source'] . json_encode($item['type_config']) . json_encode(array_map(static fn(array $q): array => [$q['question_html'], $q['points'], array_column($q['options'], 'is_correct')], $item['questions'] ?? []))));
        }
        return $out;
    }
}
