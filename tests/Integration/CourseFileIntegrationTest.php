    private function import(string $html, string $name): int
    {
        $file = (string) tempnam(sys_get_temp_dir(), 'course-file');
        file_put_contents($file, $html);
        try {
            $analysis = $this->portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => $name, 'tmp_name' => $file], $this->admin);
            self::assertSame([], array_values((array) $analysis['warnings']), $name . ' imports without a warning.');
            return $this->portability->commitImport((string) $analysis['import_key'], 0, $this->admin);
        } finally {
            @unlink($file);
        }
    }

    /** @return list<string> each section's title and each part's kind with its content, whitespace aside */
    private function parts(int $courseId): array
    {
        $items = $this->container->get(CourseItemService::class);
        $out = [];
        foreach ($items->availability($courseId, null, false) as $row) {
            if ($row['node_type'] === 'section') { $out[] = 'section ' . $row['section_title'] . ' ' . (string) $row['section_introduction_html']; continue; }
            $item = $items->item((int) $row['course_item_id']);
            $out[] = $row['part'] . ' ' . (string) preg_replace('/>\s+</', '><', trim((string) $item['content_source'] . json_encode($item['type_config']) . json_encode(array_map(static fn(array $q): array => [$q['question_html'], $q['points'], array_column($q['options'], 'is_correct')], $item['questions'] ?? []))));
        }
        return $out;
    }
