    public function testAnAddressChoosesTheCountryByNameAndASouthAfricanProvinceFromTheNine(): void
    {
        $html = RenderHarness::renderSource("{% include '@platform/partials/billing-fields.html.twig' %}", [
            'billing' => ['values' => ['country_code' => '', 'region' => '']], 'billing_fields' => BillingDetails::formFields(true), 'billing_prefix' => 'test',
        ]);
        $xpath = self::xpath($html);
        $country = $xpath->query('//select[@name="country_code"]')->item(0);
        self::assertNotNull($country, 'The country is a drop-down.');
        self::assertSame('South Africa', trim($xpath->evaluate('string(//select[@name="country_code"]/option[1])')), 'South Africa first.');
        self::assertSame('ZA', $xpath->evaluate('string(//select[@name="country_code"]/option[@selected]/@value)'), 'And chosen.');
        self::assertSame(Countries::options()[1]['name'], trim($xpath->evaluate('string(//select[@name="country_code"]/optgroup[@label="All countries"]/option[1])')));
        self::assertSame(count(Countries::CODES), (int) $xpath->evaluate('count(//select[@name="country_code"]//option)'), 'Every country.');
        foreach ($xpath->query('//select[@name="country_code"]//option') ?: [] as $option) {
            self::assertInstanceOf(\DOMElement::class, $option);
            self::assertNotSame($option->getAttribute('value'), trim($option->textContent), 'A country is shown by its name, never its code.');
        }
        self::assertSame(['Choose a province', ...Countries::SOUTH_AFRICAN_PROVINCES], array_map(static fn($o): string => trim($o->textContent), iterator_to_array($xpath->query('//select[@name="region"]/option'))));
        self::assertSame(1, (int) $xpath->evaluate('count(//input[@name="region_other"])'), 'And a text box for any other country.');

        $kenya = self::xpath(RenderHarness::renderSource("{% include '@platform/partials/billing-fields.html.twig' %}", [
            'billing' => ['values' => ['country_code' => 'KE', 'region' => 'Nairobi County']], 'billing_fields' => BillingDetails::formFields(true), 'billing_prefix' => 'test',
        ]));
        self::assertSame('KE', $kenya->evaluate('string(//select[@name="country_code"]//option[@selected]/@value)'));
        self::assertSame('Nairobi County', $kenya->evaluate('string(//input[@name="region_other"]/@value)'), 'Another country\'s province is in the text box.');
        self::assertSame('', $kenya->evaluate('string(//select[@name="region"]/option[@selected]/@value)'));
    }

    public function testTheRegisterPageAsksTheCountryTheyLiveInAndTheirIdNumberNotADateOfBirth(): void
    {
        $html = RenderHarness::render('pages/register', RenderHarness::hiveWith(['email' => '', 'return_path' => '/account', 'signup_opened' => '', 'hold_notice' => '',
            'draft' => ['first_name' => 'Lerato', 'country' => 'GB'], 'country' => 'GB', 'countries' => Countries::options()]));
        $xpath = self::xpath($html);
        self::assertSame('GB', $xpath->evaluate('string(//select[@name="country"]//option[@selected]/@value)'), 'Preset to the country their IP address showed, or what they chose.');
        self::assertGreaterThan(0, (int) $xpath->evaluate('count(//input[@name="id_number"][@inputmode="numeric"])'), 'The ID number field.');
        self::assertSame(0, (int) $xpath->evaluate('count(//input[@name="date_of_birth"])'), 'The date of birth comes from the ID number.');
        self::assertSame('Lerato', $xpath->evaluate('string(//input[@name="first_name"]/@value)'), 'What they typed comes back after a refusal.');
        self::assertSame('', $xpath->evaluate('string(//input[@name="id_number"]/@value)'), 'Never the ID number.');
    }

    public function testAnAccountWithoutAnIdNumberGivesItOnceAndAnotherAccountsIsRefused(): void
    {
        $fixture = new IntegrationDataFixture($this->db);
        $holder = $fixture->createUser('Holder', 'holder-' . $fixture->suffix() . '@seed.test');
        $heldNumber = CheckIdNumbers::give($this->db, $holder);
        $users = IntegrationContainer::get()->get(UserRepository::class);
        $person = $users->createManagedUser('step-' . $fixture->suffix() . '@seed.test');
        $actor = new CurrentUser((int) $person['id'], Uuid::v4(), 'step@seed.test', 'Step', ['STUDENT'], [], Uuid::v4(), '', 'id_number');
        $auth = IntegrationContainer::get()->get(AuthService::class);

        foreach ([[$heldNumber, IdNumbers::TAKEN], ['8001015009088', SouthAfricanIdNumber::INVALID], ['', SouthAfricanIdNumber::ENTER]] as [$typed, $words]) {
            try {
                $auth->giveIdNumber($actor, $typed);
                self::fail('Accepted: ' . $typed);
            } catch (\InvalidArgumentException $refused) {
                self::assertSame($words, $refused->getMessage());
            }
        }
        self::assertNull($this->db->fetchOne('SELECT id_number_hash FROM users WHERE id = :id', ['id' => $person['id']]), 'Nothing kept from a refusal.');

        $own = CheckIdNumbers::free($this->db, '1984-02-29');
        $auth->giveIdNumber($actor, $own);
        self::assertSame('1984-02-29', $this->db->fetchOne('SELECT birthdate::text FROM users WHERE id = :id', ['id' => $person['id']]), 'The date of birth comes from it.');
        self::assertSame(substr($own, 0, 6) . ' **** ***', IntegrationContainer::get()->get(IdNumbers::class)->shown((int) $person['id'])['masked']);
        self::assertSame(substr($own, 0, 6) . ' **** ***', $auth->profile((int) $person['id'])['id_number_masked'], 'The profile shows it masked.');
    }

    private static function xpath(string $html): DOMXPath
    {
        $dom = new DOMDocument();
        @$dom->loadHTML('<?xml encoding="utf-8"?>' . $html);

        return new DOMXPath($dom);
    }
