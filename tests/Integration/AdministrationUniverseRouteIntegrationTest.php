        self::assertSame(
            (int) $companies['companies_total'],
            $this->countRows('companies', $universe),
            'The companies total must describe the selected universe.'
        );

        // The fixture builds one set in each universe precisely so the two can be told apart.
        // Asserting each is visible where it belongs is what makes the totals above meaningful:
        // equal counts would also agree if both scopes were silently returning the same rows.
        $realIsVisible = $universe->includesReal();
        $seedIsVisible = $universe->includesSeed();

        self::assertSame(
            $realIsVisible,
            $this->companyIsListed($universe, $this->real['company']),
            'The genuine company must appear exactly when the selected universe includes REAL.'
        );
        self::assertSame(
            $seedIsVisible,
            $this->companyIsListed($universe, $this->seed['company']),
            'The generated company must appear exactly when the selected universe includes SEED.'
        );
    }

    /** Whether one company id appears in the Companies section for a universe. */
    private function companyIsListed(DataUniverse $universe, int $companyId): bool
    {
        $data = $this->administration->sectionData('companies', $this->adminUserId, $universe, [
            'companies_page_size' => 250,
        ], [], true);

        foreach ((array) ($data['companies'] ?? []) as $company) {
            if ((int) ($company['id'] ?? 0) === $companyId) {
                return true;
            }
        }

        return false;
    }

    private function countRows(string $table, DataUniverse $universe): int
    {
        $predicate = $universe->predicate('');
        $sql = 'SELECT COUNT(*)::int AS total FROM ' . $table . ($predicate === null ? '' : ' WHERE ' . $predicate);

        return (int) $this->db->exec($sql)[0]['total'];
    }

