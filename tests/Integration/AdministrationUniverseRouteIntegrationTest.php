    /**
     * Loading every section in every universe modifies no existing company membership.
     *
     * This is the assertion that would have caught the original defect, and its shape matters.
     * The defect deactivated a row rather than deleting one, so a row *count* would not have
     * moved; it is the values that must be compared.
     *
     * It asserts that no pre-existing row changed rather than that the table is byte-identical.
     * The difference is deliberate: the retained unassigned-user sweep may legitimately adopt a
     * company-less identity that already existed in the development database, which this test
     * neither created nor controls. Forbidding that would make the test fail on correct behaviour
     * and, worse, tempt someone to remove the invariant to make it pass. Modifying a row that
     * already existed is never legitimate, and that is what is checked.
     */
    public function testLoadingEverySectionInEveryUniverseModifiesNoExistingMembership(): void
    {
        // The whole table is compared, because the defect this covers changed a row nobody was
        // looking at. It is compared as a digest computed in the database rather than as an array
        // in PHP: `company_users` is one row per person, and materialising it twice exhausted the
        // 128MB limit outright once the v0.6 benchmark dataset put a hundred thousand people in it.
        // The rows are only ever fetched when the digest has already said something changed, which
        // is the one case where the memory is worth spending and the detail is needed.
        $beforeDigest = $this->membershipDigest();

        foreach (self::universes() as [$universe]) {
            foreach (self::scopedSections() as [$section, $capabilities]) {
                $this->administration->sectionData($section, $this->adminUserId, $universe, [], $capabilities, true);
            }
        }

        $afterDigest = $this->membershipDigest();
        if ($afterDigest === $beforeDigest) {
            self::assertSame($beforeDigest, $afterDigest, 'No company membership changed.');

            return;
        }

        $before = $this->membershipSnapshot();
        $after = [];
        foreach ($this->membershipSnapshot() as $row) {
            $after[$row['company_id'] . ':' . $row['user_id']] = $row;
        }

        $changed = [];
        $removed = [];
        foreach ($before as $row) {
            $key = $row['company_id'] . ':' . $row['user_id'];
            if (!isset($after[$key])) {
                $removed[] = $key;
                continue;
            }
            if ($after[$key] != $row) {
                $changed[] = $key . ' was ' . json_encode($row) . ', now ' . json_encode($after[$key]);
            }
        }

        self::assertSame([], $removed, 'A read must not delete a company membership.');
        self::assertSame(
            [],
            $changed,
            "A read must not re-role, deactivate or re-tag an existing company membership:\n  "
            . implode("\n  ", $changed)
        );
    }

    /**
     * Anything the sweep does add stays inside one universe.
     *
     * The invariant is allowed to adopt a company-less identity during a read. It is not allowed
     * to pair a REAL identity with a SEED company or the reverse, which is the failure the
     * database triggers exist to prevent and which this proves never even reaches them.
     */
    public function testAnyMembershipAddedByAReadIsSameUniverse(): void
    {
        $before = [];
        foreach ($this->membershipSnapshot() as $row) {
            $before[$row['company_id'] . ':' . $row['user_id']] = true;
        }

        foreach (self::universes() as [$universe]) {
            foreach (self::scopedSections() as [$section, $capabilities]) {
                $this->administration->sectionData($section, $this->adminUserId, $universe, [], $capabilities, true);
            }
        }

        $crossUniverse = [];
        foreach ($this->membershipSnapshot() as $row) {
            if (isset($before[$row['company_id'] . ':' . $row['user_id']])) {
                continue;
            }
            $mismatched = (int) $this->fixture->scalar(
                'SELECT COUNT(*)::int FROM company_users cu
                 JOIN companies c ON c.id = cu.company_id
                 JOIN users u ON u.id = cu.user_id
                 WHERE cu.company_id = :company_id AND cu.user_id = :user_id
                   AND ((c.seed_token IS NULL) <> (u.seed_token IS NULL))',
                [':company_id' => $row['company_id'], ':user_id' => $row['user_id']]
            );
            if ($mismatched > 0) {
                $crossUniverse[] = 'company ' . $row['company_id'] . ' / user ' . $row['user_id'];
            }
        }

        self::assertSame([], $crossUniverse, 'A read must never pair a REAL identity with a SEED company.');
    }

    /**
     * The administrator's own membership is untouched by viewing any universe.
     *
     * Stated separately from the table-wide check because it is the regression in one line: this
     * row is the one the original defect deactivated, and a failure here names the problem instead
     * of reporting a table inequality someone then has to interpret.
     */
    public function testTheAdministratorsOwnMembershipSurvivesEveryUniverse(): void
    {
        $before = $this->adminMemberships();
        self::assertCount(1, $before);

        foreach (self::universes() as [$universe]) {
            foreach (self::scopedSections() as [$section, $capabilities]) {
                $this->administration->sectionData($section, $this->adminUserId, $universe, [], $capabilities, true);
            }
        }

        $after = $this->adminMemberships();

        self::assertCount(1, $after, 'The administrator must still hold exactly one membership.');
        self::assertSame(
            (int) $before[0]['company_id'],
            (int) $after[0]['company_id'],
            'The company must not change merely because a different universe was viewed.'
        );
        self::assertSame((string) $before[0]['company_role'], (string) $after[0]['company_role'], 'The role must not change.');
        self::assertSame('active', (string) $after[0]['status'], 'The membership must remain active.');
        self::assertNull($after[0]['seed_token'], 'The administrator must remain in a REAL company.');
    }

