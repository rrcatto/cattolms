- Shared the Integration container so the suite opens one database connection instead of one per test method; the VPS run exhausted PostgreSQL connection slots.
2026/08/24 20:30 SAST
- Gave the administrator an explicit REAL System Company membership before any snapshot, and added assertions on that row directly. Without it the retained unassigned-user sweep legitimately adopted the administrator during the first read and the whole-table assertion failed against correct behaviour.
