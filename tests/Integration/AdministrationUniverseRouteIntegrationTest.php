Description:
Loads every Administration section in every universe a genuine ADMIN may select, and proves that
looking does not change anything.

This exists because `/admin/companies?universe=seed` returned 500 on the first VPS run. The cause
was that rendering the page performed a write: resolving the SEED System Company also tried to make
the genuine REAL administrator its owner, and the cross-universe guard refused. The refusal was
correct. The write was not.

The 500 was the visible half. The invisible half was worse - `assignUser()` deactivated the
administrator's existing active company membership *before* provenance was checked, so a GET
request left the account with no active company and only then failed.

So this test asserts two different things, and the second is the one that would have caught it:

  1. every section loads in real, seed and all;
  2. `company_users` is byte-for-byte unchanged afterwards.

It goes through PlatformAdministrationService rather than HTTP because that is where the defect
lived and where the universe is resolved; HttpRouteSmokeTest covers transport separately.

