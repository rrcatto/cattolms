    {
        $buyer = $this->buyers[$name] ??= $this->person($name, ['STUDENT'], self::PERMISSIONS);
        $this->orders->changeCart($buyer, $this->course[$course]['variant']);
        if ($code !== null) $this->promotions->apply($buyer, $code);
