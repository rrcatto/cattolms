Description:
Generating a larger set must not cost proportionally more memory.

Architectural boundary: integration test. It generates against the live development database, which
is disposable, and asserts nothing about the rows beyond the count.

Why this exists. Every phase of the generator used to build all of its rows before writing any of
them, so peak memory tracked the size of the request: 500,000 rows needed about 120 MB against the
128 MB the Dockerfile and the VPS both set, and /admin/seed/generate died with

    Allowed memory size of 134217728 bytes exhausted ... in PDO/Statement.php

The generator now streams - build a chunk, write it, keep the ids, discard the rows - so cost is set
by SeedGenerator::GENERATION_CHUNK rather than by the volume asked for.

What this asserts is the shape of the curve rather than an absolute figure. An absolute ceiling
would be a flaky test: peak usage depends on the allocator, on how much the kernel already holds and
on how many names the installation has accumulated. A ratio does not. Ten times the rows must not
cost ten times the memory, and if a phase goes back to accumulating, it will.

Changelog:
2026/09/10 20:41 SAST
- Created after the seed generator exhausted 128M on a large volume.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Seed\SeedGenerationPlan;
use CattoLearning\Seed\SeedGenerator;
use PHPUnit\Framework\Attributes\PreserveGlobalState;
use PHPUnit\Framework\Attributes\RunTestsInSeparateProcesses;
use PHPUnit\Framework\TestCase;

/**
 * Run in its own process, which a memory test has to be.
 *
 * Sharing the runner's process makes the measurement depend on every test that ran before it: the
 * suite already sits at about 112 MB of the 128 MB limit by the time the integration tests start,
 * so generating anything at all here killed the runner outright - and the reading would have been
 * about the suite rather than about the generator either way.
 */
#[RunTestsInSeparateProcesses]
#[PreserveGlobalState(false)]
final class SeedGeneratorMemoryTest extends TestCase
{
    /**
     * Small enough to run inside the whole suite, and ten times apart.
     *
     * The ratio is what this test reads, not the absolute figures, so the pair only has to be far
     * enough apart for an accumulating phase to show. Larger volumes were tried and are wrong
     * twice over: the suite already holds a great deal by the time this runs, so three large
     * generations exhausted the 128 MB limit and killed the runner outright; and every `composer
     * qa` would leave tens of thousands of rows behind in the development database, which nothing
     * removes now that generated rows are ordinary rows.
     */
    private const SMALL = 500;
    private const LARGE = 5000;

    private function generator(): SeedGenerator
    {
        $container = CliBootstrap::boot()['container'];
        $generator = $container->get(SeedGenerator::class);
        self::assertInstanceOf(SeedGenerator::class, $generator);

        return $generator;
    }

    /**
     * Peak memory added by one generation, in bytes.
     *
     * Measured against the peak already reached rather than from zero, so what the test harness and
     * the container hold before the call is excluded from the figure.
     */
    private function peakCostOf(int $volume, string $label): int
    {
        $generator = $this->generator();
        $before = memory_get_peak_usage(true);

        $counts = $generator->generate(SeedGenerationPlan::forVolume($volume), 'memtest-' . $label . '-' . bin2hex(random_bytes(8)));
        self::assertNotSame([], $counts, 'The generation wrote nothing, so the measurement is meaningless.');

        return max(0, memory_get_peak_usage(true) - $before);
    }

    public function testTenTimesTheRowsDoesNotCostTenTimesTheMemory(): void
    {
        // The small set runs first so the allocator has already grown to its working size; a cold
        // first call would otherwise charge the large set for growth the small one caused.
        $small = $this->peakCostOf(self::SMALL, 'small');
        $large = $this->peakCostOf(self::LARGE, 'large');

        $ratio = $small > 0 ? $large / $small : 0.0;

        self::assertLessThan(
            4.0,
            $ratio,
            sprintf(
                "Ten times the rows cost %.1f times the memory (%d bytes -> %d bytes).\n"
                . 'A generator that streams should be near flat; a ratio approaching ten means a '
                . 'phase is accumulating all of its rows before writing them again.',
                $ratio,
                $small,
                $large
            )
        );
    }

    /** The set must not stay in memory after it has been written. */
    public function testAGenerationReleasesWhatItBuilt(): void
    {
        $generator = $this->generator();

        // The real figure - memory_get_usage(true) - is the allocator's arena, and PHP does not
        // hand arenas back to the operating system, so it cannot fall and cannot show a release.
        // The unreal figure is what PHP considers in use, which is the question being asked.
        $before = memory_get_usage();

        $generator->generate(
            SeedGenerationPlan::forVolume(self::LARGE),
            'memtest-release-' . bin2hex(random_bytes(8))
        );

        $retained = memory_get_usage() - $before;

        // Some growth is legitimate and permanent: the name factory keeps a hash of every name it
        // has issued, which is what stops a later set repeating one. That is bounded by the set
        // size, not by the rows written, and 5,000 rows is roughly 375 people.
        self::assertLessThan(
            8 * 1024 * 1024,
            $retained,
            sprintf('%d bytes were still held after the generation finished.', $retained)
        );
    }
}
