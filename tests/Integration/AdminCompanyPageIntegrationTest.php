declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\PlatformAdministrationService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Tests\Support\IntegrationDataFixture;
use PHPUnit\Framework\TestCase;

final class AdminCompanyPageIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testACompanysPageHasItsFiguresAndItsPeople(): void
    {
        $fixture = new IntegrationDataFixture($this->db);
        $suffix = $fixture->suffix();
        $owner = $fixture->createUser('Page Owner', 'page-owner-' . $suffix . '@example.test');
        $member = $fixture->createUser('Page Member', 'page-member-' . $suffix . '@example.test');
        $company = $fixture->createCompany($owner, 'Page Company ' . $suffix, 'page-' . $suffix . '.test');
        $this->db->executeStatement("INSERT INTO company_users (company_id, user_id, company_role, status) VALUES (:c, :u, 'administrator', 'active') ON CONFLICT DO NOTHING", ['c' => $company, 'u' => $owner]);
        $this->db->executeStatement("INSERT INTO company_users (company_id, user_id, company_role, status) VALUES (:c, :u, 'student', 'active') ON CONFLICT DO NOTHING", ['c' => $company, 'u' => $member]);
        /** @var PlatformAdministrationService $service */
        $service = IntegrationContainer::get()->get(PlatformAdministrationService::class);

        $view = $service->adminCompanyView($company);
        self::assertNotNull($view);
        // Its founding Company Administrator (every company has one), the second administrator and the student.
        self::assertSame(['Page Company ' . $suffix, 'page-' . $suffix . '.test', 3, 'Client'],
            [$view['admin_company']['name'], $view['admin_company']['domain'], (int) $view['admin_company']['people_count'], $view['admin_company']['company_type_label']]);
        self::assertSame(3, $view['people_total']);
        $roles = array_column($view['people'], 'role', 'id');
        self::assertSame('Company Administrator', $roles[$owner], 'In the words the company\'s own person page uses.');
        self::assertSame('Student', $roles[$member]);
        self::assertNull($service->adminCompanyView(999999999), 'A company that does not exist has no page.');
    }
}
