    public function testEveryPublicPageHasItsOwnDescriptionCanonicalAddressAndShareCard(): void
    {
        $descriptions = [];
        foreach (PublicPages::PAGES as $key => [, $path]) {
            $meta = $this->meta($key, $path, ['title' => PublicPages::title($key)]);
            self::assertSame(self::SITE . $path, $meta['canonical'], $key);
            self::assertNotSame('', $meta['description'], $key);
            self::assertSame('', $meta['robots'], $key . ' may be indexed.');
            self::assertSame(self::SITE . $path, $meta['og']['url'] ?? '', $key);
            self::assertSame('en_ZA', $meta['og']['locale'] ?? '', $key);
            self::assertContains($meta['twitter_card'], ['summary', 'summary_large_image'], $key);
            $descriptions[] = $meta['description'];
        }
        self::assertSame($descriptions, array_values(array_unique($descriptions)), 'No two public pages share a description.');

        // A later page of a list is its own page, titled as such; the reader's view and page size are not pages.
        $model = $this->model('courses', '/courses', ['title' => 'Course catalogue'], ['page' => '3', 'catalogue_view' => 'list', 'page_size' => '48']);
        self::assertSame(self::SITE . '/courses?page=3', $model['meta']['canonical']);
        self::assertSame('Course catalogue, page 3', $model['page']['title']);
        self::assertSame(self::SITE . '/courses', $this->meta('courses', '/courses', ['title' => 'Course catalogue'], ['catalogue_view' => 'list'])['canonical']);
    }

