    public function testAdminsOwnWordsAreWhatSearchEnginesAreGiven(): void
    {
        $overrides = IntegrationContainer::get()->get(SearchOverrides::class);
        $admin = $this->admin();
        [$course, $slug] = $this->course('Garden Design');
        $overrides->saveCourse($course, ['title' => 'Garden design for <b>small</b> spaces', 'description' => "Plan a small garden,\n season by season.", 'hidden' => ''], $admin);
        self::assertSame(['title' => 'Garden design for small spaces', 'description' => 'Plan a small garden, season by season.', 'hidden' => false], $overrides->course($course), 'Plain text, one line.');
        $_SERVER['REQUEST_URI'] = '/courses/' . $slug;
        $html = InProcessPage::run(null, CourseController::class, 'detail', ['slug' => $slug])['body'];
        self::assertStringContainsString('<title>Garden design for small spaces · ', $html);
        self::assertStringContainsString('<meta name="description" content="Plan a small garden, season by season.">', $html);
        self::assertStringContainsString('<meta property="og:title" content="Garden design for small spaces">', $html);
        self::assertStringNotContainsString('name="robots"', $html, 'A live course page may be indexed.');

        $overrides->saveCourse($course, ['title' => '', 'description' => '', 'hidden' => '1'], $admin);
        $html = InProcessPage::run(null, CourseController::class, 'detail', ['slug' => $slug])['body'];
        self::assertStringContainsString('<meta name="robots" content="noindex, follow">', $html, 'Kept out of search engines.');
        self::assertStringContainsString('<title>Garden Design · ', $html, 'Its own title again.');
        self::assertStringNotContainsString('/courses/' . $slug . '<', $this->sitemap(), 'And out of the sitemap.');

        $category = IntegrationContainer::get()->get(CourseService::class)->createCategory(['name' => 'Garden Craft ' . $this->fixture->suffix()], $admin);
        $this->db->executeStatement('UPDATE courses SET category_id = :category WHERE id = :id', ['category' => (int) $category['id'], 'id' => $course]);
        $this->db->executeStatement('UPDATE courses SET search_hidden = FALSE WHERE id = :id', ['id' => $course]);
        $overrides->saveCategory((int) $category['id'], ['title' => 'Gardening courses', 'description' => 'Courses for people who grow things.'], $admin);
        $_SERVER['REQUEST_URI'] = '/courses/category/' . $category['slug'];
        $html = InProcessPage::run(null, CourseController::class, 'catalogue', ['slug' => (string) $category['slug']])['body'];
        self::assertStringContainsString('<title>Gardening courses · ', $html);
        self::assertStringContainsString('<meta name="description" content="Courses for people who grow things.">', $html);
        self::assertStringContainsString('<link rel="canonical" href="' . self::SITE . '/courses/category/' . $category['slug'] . '">', $html);

        $overrides->savePages(['pages' => ['help' => ['title' => 'How the courses work', 'description' => 'Buying, studying and being assessed, step by step.']]], $admin);
        $meta = $this->model('help', '/help', ['title' => 'Help']);
        self::assertSame('How the courses work', $meta['page']['title']);
        self::assertSame('Buying, studying and being assessed, step by step.', $meta['meta']['description']);
        self::assertSame('How the courses work', $meta['meta']['og']['title']);

        // The words travel in the course's catalogue block: exported, and taken back by an import that chooses them.
        $settings = IntegrationContainer::get()->get(\CattoLearning\Course\CourseCatalogueSettings::class);
        $overrides->saveCourse($course, ['title' => 'Small garden design', 'description' => 'Plan it season by season.', 'hidden' => ''], $admin);
        $block = $settings->export($course);
        self::assertSame(['title' => 'Small garden design', 'description' => 'Plan it season by season.', 'hidden' => false], $block['search']);
        $overrides->saveCourse($course, ['title' => '', 'description' => '', 'hidden' => '1'], $admin);
        $here = IntegrationContainer::get()->get(\CattoLearning\Course\CourseRepository::class)->findById($course) ?? [];
        self::assertContains('search', array_column($settings->differences($here, $block, [], []), 'kind'), 'An import names the difference.');
        $settings->applyChosen($course, $block, ['search'], $admin);
        self::assertSame(['title' => 'Small garden design', 'description' => 'Plan it season by season.', 'hidden' => false], $overrides->course($course), 'And takes the file\'s words.');

        try {
            $overrides->saveCourse($course, ['title' => str_repeat('a', SearchOverrides::TITLE_LIMIT + 1)], $admin);
            self::fail('A title too long was saved.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString('at most ' . SearchOverrides::TITLE_LIMIT . ' characters', $refused->getMessage());
        }
    }

    public function testTheSitemapListsThePublicPagesThenWhatThereIsToFindAndNeverADraft(): void
    {
        $service = IntegrationContainer::get()->get(CourseService::class);
        $admin = $this->admin();
        [$course, $slug] = $this->course('Pruning Fruit Trees');
        [, $draft] = $this->course('Orchard Planning', 'draft');
        $category = $service->createCategory(['name' => 'Orchards ' . $this->fixture->suffix()], $admin);
        $empty = $service->createCategory(['name' => 'Empty Shelf ' . $this->fixture->suffix()], $admin);
        $this->db->executeStatement('UPDATE courses SET category_id = :category WHERE id = :id', ['category' => (int) $category['id'], 'id' => $course]);
        $tag = $service->createTag(['name' => 'Pruning ' . $this->fixture->suffix()], $admin);
        $tagSlug = (string) $this->db->fetchOne('SELECT slug FROM tags WHERE id = :id', ['id' => (int) $tag['id']]);
        $this->db->executeStatement('INSERT INTO course_tags (course_id, tag_id) VALUES (:course, :tag)', ['course' => $course, 'tag' => (int) $tag['id']]);
        [$other] = $this->course('Grafting Basics');
        $bundle = BundleFixture::create($this->db, $admin, [$course, $other], 300000);

        $xml = $this->sitemap();
        $locations = [];
        preg_match_all('#<loc>([^<]+)</loc>#', $xml, $found);
        foreach ($found[1] as $location) $locations[] = substr($location, strlen(self::SITE));
        self::assertSame(array_map(static fn(string $key): string => PublicPages::path($key), Sitemap::PAGES), array_slice($locations, 0, count(Sitemap::PAGES)), 'The public pages come first.');
        foreach (['/courses/' . $slug, '/courses/category/' . $category['slug'], '/courses/tag/' . $tagSlug, '/bundles/' . $bundle['slug']] as $path) {
            self::assertContains($path, $locations, $path);
        }
        foreach (['/courses/' . $draft, '/courses/category/' . $empty['slug']] as $path) self::assertNotContains($path, $locations, $path);
        self::assertMatchesRegularExpression('#<loc>' . preg_quote(self::SITE, '#') . '/terms</loc><lastmod>[0-9T:+-]+</lastmod>#', $xml, 'A legal page has its own date.');
        self::assertStringContainsString('<loc>' . self::SITE . '/help</loc></url>', $xml, 'A page with no known date has none.');

        $robots = (new Sitemap(new SitemapRepository($this->db), SiteMode::fixed(SiteMode::LIVE), new ArrayAdapter(), Sitemap::LIMIT, SearchSettings::fixed(['ai_crawlers' => SearchSettings::ALLOW_ALL])))->robots();
        $groups = substr_count($robots, 'User-agent: ');
        foreach (['/mailing/', '/m/', '/admin/'] as $path) self::assertSame($groups, substr_count($robots, "Disallow: {$path}\n"), 'Every group keeps crawlers out of ' . $path);
    }

