    /**
     * The head a template drawn at an address has, as the site's renderer completes it.
     *
     * @param array<string,mixed> $data
     * @param array<string,string> $query
     * @return array<string,mixed>
     */
    private function meta(string $template, string $path, array $data, array $query = []): array
    {
        return $this->model($template, $path, $data, $query)['meta'];
    }

    /**
     * @param array<string,mixed> $data
     * @param array<string,string> $query
     * @return array<string,mixed>
     */
    private function model(string $template, string $path, array $data, array $query = []): array
    {
        $_SERVER['REQUEST_URI'] = $path . ($query === [] ? '' : '?' . http_build_query($query));
        $_GET = $query;
        return IntegrationContainer::get()->get(ThemeRenderer::class)->viewModel($template, $data, ThemeManager::DEFAULT_SLUG, false);
    }

    private function sitemap(): string
    {
        return (string) (new Sitemap(new SitemapRepository($this->db), SiteMode::fixed(SiteMode::LIVE), new ArrayAdapter(), Sitemap::LIMIT, null, IntegrationContainer::get()->get(LegalDocuments::class)))->document();
    }

