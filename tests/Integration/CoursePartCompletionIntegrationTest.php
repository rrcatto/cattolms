declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Course\AssessmentService;
use CattoLearning\Course\CoursePortabilityService;
use CattoLearning\Course\LearningService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\DevelopmentFixture;
use CattoLearning\Tests\Support\SpecificationExample;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;
use Psr\Container\ContainerInterface;

final class CoursePartCompletionIntegrationTest extends TestCase
{
    private ContainerInterface $container;
    private Database $db;
    private LearningService $learning;
    private DevelopmentFixture $fixture;
    private int $admin;
    private int $courseId;
    private string $slug;

    protected function setUp(): void
    {
        $this->container = CliBootstrap::boot()['container'];
        $this->db = $this->container->get(Database::class);
        $this->learning = $this->container->get(LearningService::class);
        $this->db->beginTransaction();
        $this->fixture = new DevelopmentFixture($this->db);
        $this->admin = $this->fixture->person('ADMIN')['id'];
        if ((int) $this->db->fetchOne("SELECT count(*) FROM courses WHERE code = 'GDN-101'") > 0) self::markTestSkipped('GDN-101 is on this site.');
        $portability = $this->container->get(CoursePortabilityService::class);
        $file = SpecificationExample::file();
        try {
            $analysis = $portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => 'example.html', 'tmp_name' => $file], $this->admin);
            $this->courseId = $portability->commitImport((string) $analysis['import_key'], 0, $this->admin);
        } finally {
            @unlink($file);
        }
        $this->db->executeStatement("UPDATE courses SET status = 'published' WHERE id = :id", ['id' => $this->courseId]);
        $this->slug = (string) $this->db->fetchOne('SELECT slug FROM courses WHERE id = :id', ['id' => $this->courseId]);
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) { $this->db->rollBack(); }
    }

    public function testALearnerTicksEachPartAndSeesTheirProgress(): void
    {
        $learner = $this->fixture->person('STUDENT')['id'];
        $this->fixture->createEnrolment($learner, $this->courseId, $this->admin);
        $this->learning->start($learner, $this->slug);
        $nodes = $this->nodes($learner);
        self::assertSame(['total' => 8, 'done' => 0, 'percentage' => 0], $this->learning->courseHome($learner, $this->slug)['progress'], 'Every part counts: seven in the module and the final assessment.');

        $this->learning->markPart($learner, $this->slug, $nodes['lesson'], true);
        $home = $this->learning->courseHome($learner, $this->slug);
        self::assertSame(['total' => 8, 'done' => 1, 'percentage' => 13], $home['progress']);
        self::assertTrue($this->row($home, $nodes['lesson'])['is_done'], 'The lesson carries its tick.');
        self::assertFalse($this->row($home, $nodes['section'])['is_done'], 'The module does not, until every part in it is done.');
        self::assertSame(13, $this->libraryPercentage($learner), 'My Courses shows the same figure.');

        $this->learning->markPart($learner, $this->slug, $nodes['lesson'], false);
        self::assertSame(0, $this->learning->courseHome($learner, $this->slug)['progress']['done'], 'Unticked, it no longer counts.');

        foreach (['assessment' => 'An assessment is complete once you submit it.', 'section' => 'A section is complete once every part in it is.'] as $kind => $refusal) {
            try {
                $this->learning->markPart($learner, $this->slug, $nodes[$kind], true);
                self::fail('The ' . $kind . ' was ticked by hand.');
            } catch (InvalidArgumentException $refused) {
                self::assertSame($refusal, $refused->getMessage());
            }
        }

        foreach (['presentation', 'video', 'lesson', 'summary', 'flashcards', 'practical'] as $part) {
            $this->learning->markPart($learner, $this->slug, $nodes[$part], true);
            $this->learning->markPart($learner, $this->slug, $nodes[$part], true);
        }
        self::assertFalse($this->row($this->learning->courseHome($learner, $this->slug), $nodes['section'])['is_done'], 'The assessment is not done yet.');
        $this->submit($learner, $nodes['assessment']);
        $home = $this->learning->courseHome($learner, $this->slug);
        self::assertTrue($this->row($home, $nodes['assessment'])['is_done'], 'The submitted assessment ticks itself.');
        self::assertTrue($this->row($home, $nodes['section'])['is_done'], 'Every part done, the module carries its tick.');
        self::assertSame(['total' => 8, 'done' => 7, 'percentage' => 88], $home['progress'], 'Ticking twice counts once.');
    }

    public function testAFinishedReadinessCheckTicksItself(): void
    {
        // The example has no readiness check: one is added as an author adds it, with two questions.
        $items = $this->container->get(\CattoLearning\Course\CourseItemService::class);
        $key = 'readiness-check-' . $this->fixture->suffix();
        $id = $items->create(['item_key' => $key, 'item_type' => 'diagnostic', 'title' => 'Readiness check'], $this->admin);
        $node = $items->addExisting($this->courseId, $id, [], $this->admin);
        $this->fixture->createQuestion($id);
        $this->fixture->createQuestion($id, 2);
        $learner = $this->fixture->person('STUDENT')['id'];
        $this->fixture->createEnrolment($learner, $this->courseId, $this->admin);
        $this->learning->start($learner, $this->slug);
        self::assertFalse($this->row($this->learning->courseHome($learner, $this->slug), $node)['is_done']);
        $this->submit($learner, $node, 'diagnostic');
        $home = $this->learning->courseHome($learner, $this->slug);
        self::assertTrue($this->row($home, $node)['is_done'], 'A finished readiness check ticks itself, though it writes no graded attempt.');
        self::assertSame(1, $home['progress']['done']);
    }

    public function testSomeoneWithoutTheCourseCannotTickAnything(): void
    {
        $owner = $this->fixture->person('STUDENT')['id'];
        $this->fixture->createEnrolment($owner, $this->courseId, $this->admin);
        $this->learning->start($owner, $this->slug);
        $lesson = $this->nodes($owner)['lesson'];
        $stranger = $this->fixture->person('STUDENT')['id'];
        $this->expectException(InvalidArgumentException::class);
        $this->learning->markPart($stranger, $this->slug, $lesson, true);
    }

    /** @return array<string,int> the module section's node and each of its parts' nodes, by part */
    private function nodes(int $learner): array
    {
        $nodes = [];
        foreach ($this->learning->courseHome($learner, $this->slug)['structure'] as $row) {
            if ($row['node_type'] === 'section') { $nodes['section'] = (int) $row['id']; continue; }
            $nodes[(string) $row['part']] = (int) $row['id'];
        }
        return $nodes;
    }

    /**
     * @param array<string,mixed> $home
     * @return array<string,mixed>
     */
    private function row(array $home, int $node): array
    {
        foreach ($home['structure'] as $row) { if ((int) $row['id'] === $node) return $row; }
        self::fail('No node ' . $node);
    }

    private function libraryPercentage(int $learner): int
    {
        foreach ($this->learning->library($learner) as $course) {
            if ((int) $course['course_id'] === $this->courseId) return (int) $course['progress_percentage'];
        }
        self::fail('The course is not in the learner\'s library.');
    }

    /** An assessment answered question by question, as a learner answers it. */
    private function submit(int $learner, int $node, string $mode = 'graded'): void
    {
        $assessments = $this->container->get(AssessmentService::class);
        $key = (string) $this->db->fetchOne('SELECT ci.item_key FROM course_item_placements p JOIN course_items ci ON ci.id = p.course_item_id WHERE p.node_id = :node', ['node' => $node]);
        $attempt = (string) $assessments->startAttempt($learner, $this->slug, $node, $key, $mode)['public_id'];
        $state = $assessments->session($learner, $attempt);
        for ($asked = 0; ($state['status'] ?? '') === 'in_progress' && $asked < 50; $asked++) {
            $question = (int) $state['question']['question_id'];
            $right = (int) $this->db->fetchOne('SELECT id FROM assessment_options WHERE question_id = :q AND is_correct LIMIT 1', ['q' => $question]);
            $state = $assessments->respond($learner, $attempt, $question, $right, false);
        }
        self::assertSame('submitted', (string) $state['status'], 'The assessment was submitted.');
    }
}
