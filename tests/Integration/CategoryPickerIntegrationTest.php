    public function testAnImportIsFiledInTheCategoryChosenAtAnyLevelOrNone(): void
    {
        $portability = IntegrationContainer::get()->get(CoursePortabilityService::class);
        foreach (['A' => $this->ids['A'], 'A1' => $this->ids['A1'], 'A1x' => $this->ids['A1x'], 'none' => 0] as $key => $categoryId) {
            $temporary = (string) tempnam(sys_get_temp_dir(), 'picker-import-');
            file_put_contents($temporary, json_encode(['course' => ['slug' => 'picker-import-' . strtolower($key) . '-' . $this->suffix, 'title' => 'Picker import ' . $key], 'modules' => [['title' => 'Only module', 'module_key' => 'm1', 'assessment_required' => false, 'content_html' => '<p>Hello</p>']]], JSON_THROW_ON_ERROR));
            try {
                $analysis = $portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($temporary), 'tmp_name' => $temporary, 'name' => 'picker.json'], $this->userId);
                $course = $portability->commitImport((string) $analysis['import_key'], $categoryId, $this->userId);
            } finally {
                @unlink($temporary);
            }
            $stored = $this->db->fetchOne('SELECT category_id FROM courses WHERE id = :id', ['id' => $course]);
            self::assertSame($categoryId === 0 ? null : $categoryId, $stored === null ? null : (int) $stored, 'Imported into ' . $key . '.');
        }
    }

