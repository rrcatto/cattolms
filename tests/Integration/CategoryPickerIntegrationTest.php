    public function testPlusNewCreatesAtTheChosenPlaceOrSaysWhyNot(): void
    {
        foreach ([[null, 1], ['A', 2], ['A1', 3]] as [$place, $level]) {
            $answer = $this->createInline('New ' . ($place ?? 'top'), $place === null ? '0' : (string) $this->ids[$place]);
            self::assertSame(201, $answer['status']);
            $category = json_decode($answer['body'], true)['category'];
            self::assertSame($level, $category['level']);
            $row = $this->db->fetchAssociative('SELECT parent_id, level, position FROM course_categories WHERE id = :id', ['id' => $category['id']]);
            self::assertNotFalse($row);
            self::assertSame($place === null ? null : $this->ids[$place], $row['parent_id'] === null ? null : (int) $row['parent_id']);
            $siblings = (int) $this->db->fetchOne('SELECT COUNT(*) FROM course_categories WHERE parent_id IS NOT DISTINCT FROM :p', ['p' => $row['parent_id']]);
            self::assertSame($siblings, (int) $row['position'], 'It goes last among its siblings.');
        }
        $deepest = json_decode($this->createInline('New A1', (string) $this->ids['A1'] . '')['body'] ?: '{}', true);
        self::assertStringContainsString('already uses the slug', (string) ($deepest['error'] ?? ''), 'A duplicate is refused with a sentence.');
        $path = json_decode($this->createInline('Leadership', (string) $this->ids['A1'])['body'], true)['category']['path'];
        self::assertSame($this->label('A') . ' › ' . $this->label('A1') . ' › ' . $this->label('Leadership'), $path, 'The answer carries the full path.');

        foreach ([[(string) $this->ids['A1x'], 'cannot hold subcategories'], ['999999999', 'no longer exists'], ['A1', 'Choose where the new category goes']] as [$parent, $message]) {
            $before = (int) $this->db->fetchOne('SELECT COUNT(*) FROM course_categories');
            $refused = $this->createInline('Refused ' . $message, $parent);
            self::assertSame(422, $refused['status']);
            self::assertStringContainsString($message, (string) json_decode($refused['body'], true)['error']);
            self::assertSame($before, (int) $this->db->fetchOne('SELECT COUNT(*) FROM course_categories'), 'Nothing is created, not even at the top level.');
        }
    }

