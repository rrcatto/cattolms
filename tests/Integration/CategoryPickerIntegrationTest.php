    public function testThePickerOffersUncategorisedThenTheTreeWithEveryLevelChoosable(): void
    {
        $picker = $this->service->courseCategoryPicker(null);
        self::assertSame('0', $picker['selected'], 'No category is Uncategorised, sent as 0.');
        self::assertSame(['value' => '0', 'label' => 'Uncategorised', 'depth' => 0, 'path' => 'Uncategorised'], $picker['items'][0]);
        $top = array_column($picker['items'], 'value');
        self::assertContains((string) $this->ids['A'], $top);
        self::assertNotContains((string) $this->ids['A1'], $top, 'Only main categories are at the top.');
        $a = self::find($picker['items'], $this->ids['A']);
        $a1 = self::find($a['children'] ?? [], $this->ids['A1']);
        $a1x = self::find($a1['children'] ?? [], $this->ids['A1x']);
        self::assertSame($this->label('A') . ' › ' . $this->label('A1') . ' › ' . $this->label('A1x'), $a1x['path']);
        self::assertArrayNotHasKey('children', $a1x);
        self::assertSame((string) $this->ids['A1x'], $this->service->courseCategoryPicker($this->ids['A1x'])['selected']);

        $places = $this->service->categoryLocationPicker();
        self::assertSame(['value' => '0', 'label' => 'Top level', 'depth' => 0, 'path' => 'Top level'], $places['items'][0]);
        $placeA = self::find($places['items'], $this->ids['A']);
        $placeA1 = self::find($placeA['children'] ?? [], $this->ids['A1']);
        self::assertArrayNotHasKey('children', $placeA1, 'A sub-subcategory is never offered as a place: nothing can go inside it.');
    }

