    /** @return array<string,mixed> */
    private function seedCompanyRow(): array
    {
        $row = $this->companies->systemCompany(DataUniverse::Seed);
        self::assertNotNull($row, 'The shared SEED System Company must never disappear.');

        return $row;
    }

    private function membershipCount(): int
    {
        return (int) $this->fixture->scalar(
            'SELECT COUNT(*)::int AS value FROM company_users WHERE company_id = :id',
            ['id' => (int) $this->seedCompanyBefore['id']]
        );
    }

    /** A domain nothing else on the platform uses. */
    private function freeDomain(string $label): string
    {
        return $label . '-' . $this->fixture->suffix() . '.stagec.test';
    }

    // --- the successful path -----------------------------------------------------------------

    /** A saved name and domain reach the company row, and the row stays infrastructure. */
    public function testSavingUpdatesTheCompanyRowWithoutChangingWhatItIs(): void
    {
        $domain = $this->freeDomain('saved');

        $this->administration->saveSeedSystemCompany([
            'seed_system_company_name' => 'Renamed SEED Host',
            'seed_system_company_domain' => $domain,
        ], $this->adminUserId);

        $after = $this->seedCompanyRow();

        self::assertSame('Renamed SEED Host', (string) $after['name']);
        self::assertSame($domain, (string) $after['domain']);
        self::assertSame(
            (string) $this->seedCompanyBefore['seed_token'],
            (string) $after['seed_token'],
            'The reserved infrastructure token must never be rewritten.'
        );
        self::assertSame(
            (int) $this->seedCompanyBefore['id'],
            (int) $after['id'],
            'The row must be edited in place, never replaced.'
        );
        self::assertTrue(
            in_array($after['is_system'], [true, 't', 1, '1'], true),
            'is_system must survive the edit, or the company stops being infrastructure.'
        );
    }

    /**
     * The saved domain is the domain seed mail is actually delivered to.
     *
     * This is the point of the whole stage. A router built after the save must agree with what
     * Administration displays; if it does not, the setting is decorative.
     */
    public function testTheSavedDomainBecomesTheEffectiveDeliveryDomain(): void
    {
        $domain = $this->freeDomain('delivery');

        $this->administration->saveSeedSystemCompany([
            'seed_system_company_name' => 'Delivery Host',
            'seed_system_company_domain' => $domain,
        ], $this->adminUserId);

        self::assertSame($domain, $this->settings->seedSystemCompanyDomain());
        self::assertSame('database', $this->settings->seedSystemCompanyDomainSource());

        $router = new SeedMailRouter($this->settings->seedSystemCompanyDomain());
        $generated = 'thabo.7.abc123@highveld-0-abc123' . SeedMailRouter::GENERATED_DOMAIN_SUFFIX;

        self::assertSame(
            'thabo.7.abc123@' . $domain,
            $router->deliveryAddress($generated),
            'The displayed domain and the delivery domain must be one value.'
        );
        self::assertSame(
            'someone@genuine.example',
            $router->deliveryAddress('someone@genuine.example'),
            'A genuine address must still never be rewritten.'
        );
    }

    /** Editing seed infrastructure never makes the administrator a member of it. */
    public function testSavingCreatesNoMembership(): void
    {
        $before = $this->membershipCount();

        $this->administration->saveSeedSystemCompany([
            'seed_system_company_name' => 'No Membership Host',
            'seed_system_company_domain' => $this->freeDomain('nomember'),
        ], $this->adminUserId);

        self::assertSame(
            $before,
            $this->membershipCount(),
            'A REAL administrator must not join a SEED company to administer it.'
        );
        self::assertSame(
            0,
            (int) $this->fixture->scalar(
                'SELECT COUNT(*)::int AS value FROM company_users WHERE company_id = :id AND user_id = :user',
                ['id' => (int) $this->seedCompanyBefore['id'], 'user' => $this->adminUserId]
            ),
            'The editing administrator specifically must hold no membership of the SEED company.'
        );
    }

    /** An empty domain is a deliberate choice: it disables the rewrite rather than failing. */
    public function testAnEmptyDomainDisablesTheRewriteAndKeepsTheCompanyDomain(): void
    {
        $existingDomain = (string) $this->seedCompanyRow()['domain'];

        $this->administration->saveSeedSystemCompany([
            'seed_system_company_name' => 'Undelivered Host',
            'seed_system_company_domain' => '',
        ], $this->adminUserId);

        self::assertSame('', $this->settings->seedSystemCompanyDomain());
        self::assertFalse((new SeedMailRouter($this->settings->seedSystemCompanyDomain()))->isConfigured());
        self::assertSame(
            $existingDomain,
            (string) $this->seedCompanyRow()['domain'],
            'Clearing the delivery domain must not blank companies.domain, which is NOT NULL and unique.'
        );
    }

    /** Reset returns both settings to their deployment defaults. */
    public function testResetReturnsBothSettingsToTheEnvironment(): void
    {
        $this->administration->saveSeedSystemCompany([
            'seed_system_company_name' => 'Temporary Host',
            'seed_system_company_domain' => $this->freeDomain('reset'),
        ], $this->adminUserId);
        self::assertTrue($this->settings->hasSeedSystemCompanyOverride());

        $this->administration->resetSeedSystemCompany($this->adminUserId);

        self::assertFalse($this->settings->hasSeedSystemCompanyOverride());
        self::assertSame('environment', $this->settings->seedSystemCompanyDomainSource());
        self::assertSame(
            RuntimeSettings::normaliseDomain(Env::string('SEED_SYSTEM_COMPANY_DOMAIN', '')),
            $this->settings->seedSystemCompanyDomain(),
            'After a reset the .env deployment default is the effective value again.'
        );
    }

    // --- the refusals, each proving nothing was written ----------------------------------------

    /**
     * @param array<string,mixed> $input
     * @return string the refusal message
     */
    private function refusalFor(array $input): string
    {
        $nameBefore = (string) $this->seedCompanyRow()['name'];
        $domainBefore = (string) $this->seedCompanyRow()['domain'];
        $overrideBefore = $this->settings->hasSeedSystemCompanyOverride();

        $message = null;
        try {
            $this->administration->saveSeedSystemCompany($input, $this->adminUserId);
        } catch (Throwable $exception) {
            $message = $exception->getMessage();
        }

        self::assertNotNull($message, 'This input must be refused.');

        // Validate before you mutate: a refusal must leave every byte as it was.
        self::assertSame($nameBefore, (string) $this->seedCompanyRow()['name'], 'A refused save wrote the name.');
        self::assertSame($domainBefore, (string) $this->seedCompanyRow()['domain'], 'A refused save wrote the domain.');
        self::assertSame(
            $overrideBefore,
            $this->settings->hasSeedSystemCompanyOverride(),
            'A refused save wrote an option row.'
        );

        return $message;
    }

    /** APP_DOMAIN belongs to the genuine System Company; companies.domain is unique platform-wide. */
    public function testTheSeedDomainMayNotEqualAppDomain(): void
    {
        $message = $this->refusalFor([
            'seed_system_company_name' => 'Colliding Host',
            'seed_system_company_domain' => Env::string('APP_DOMAIN', 'local'),
        ]);

        self::assertStringContainsString('must differ from APP_DOMAIN', $message);
    }

    /** A domain another company already holds cannot be taken. */
    public function testADomainAlreadyRegisteredIsRefused(): void
    {
        $taken = $this->freeDomain('taken');
        $this->fixture->createCompany($this->adminUserId, 'Occupier ' . $this->fixture->suffix(), $taken);

        $message = $this->refusalFor([
            'seed_system_company_name' => 'Squatting Host',
            'seed_system_company_domain' => $taken,
        ]);

        self::assertStringContainsString('already registered', $message);
    }

    /** The reserved generated suffix can never resolve, so it can never receive mail. */
    public function testAReservedGeneratedDomainIsRefused(): void
    {
        $message = $this->refusalFor([
            'seed_system_company_name' => 'Undeliverable Host',
            'seed_system_company_domain' => 'anything' . SeedMailRouter::GENERATED_DOMAIN_SUFFIX,
        ]);

        self::assertStringContainsString(SeedMailRouter::GENERATED_DOMAIN_SUFFIX, $message);
    }

    /** An address or a URL is not a domain. */
    public function testMalformedDomainsAreRefused(): void
    {
        foreach (['admin@example.com', 'https://example.com/x', 'not a domain'] as $malformed) {
            $this->refusalFor([
                'seed_system_company_name' => 'Malformed Host',
                'seed_system_company_domain' => $malformed,
            ]);
        }
    }

    /** The company must have a name. */
    public function testAnEmptyNameIsRefused(): void
    {
        $message = $this->refusalFor([
            'seed_system_company_name' => '   ',
            'seed_system_company_domain' => $this->freeDomain('noname'),
        ]);

        self::assertStringContainsString('Enter a name', $message);
    }

    /** Saving Settings is a read-then-write, and it must not disturb the genuine System Company. */
    public function testTheGenuineSystemCompanyIsUntouched(): void
    {
        $realBefore = $this->companies->systemCompany(DataUniverse::Real);
        self::assertNotNull($realBefore);

        $this->administration->saveSeedSystemCompany([
            'seed_system_company_name' => 'Isolated Host',
            'seed_system_company_domain' => $this->freeDomain('isolated'),
        ], $this->adminUserId);

        $realAfter = $this->companies->systemCompany(DataUniverse::Real);
        self::assertNotNull($realAfter);
        self::assertSame((int) $realBefore['id'], (int) $realAfter['id']);
        self::assertSame((string) $realBefore['name'], (string) $realAfter['name']);
        self::assertSame((string) $realBefore['domain'], (string) $realAfter['domain']);
        self::assertNull($realAfter['seed_token'], 'The genuine System Company must stay in the REAL universe.');
    }
