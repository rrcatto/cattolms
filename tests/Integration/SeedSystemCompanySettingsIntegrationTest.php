        );

        /** @var OptionRepository $options */
        $options = $this->container->get(OptionRepository::class);
        foreach (['seed_system_company_name' => 'name', 'seed_system_company_domain' => 'domain'] as $key => $slot) {
            $original = $this->optionsBefore[$slot];
            if ($original === null) {
