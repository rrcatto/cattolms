    public function testTheCodeTitleCategoryAndADefaultPriceAreSavedTogether(): void
    {
        $category = (int) $this->db->fetchOne('SELECT id FROM course_categories ORDER BY id LIMIT 1');
        $code = 'QE-' . strtoupper(substr(bin2hex(random_bytes(3)), 0, 5));
        $row = ['code' => $code, 'title' => 'Quick edit renamed', 'category_id' => (string) $category, 'price' => '1350', 'was_price' => '1600', 'access_period_value' => '6', 'access_period_unit' => 'months'];
        $this->quick->save($this->course, $row, $this->admin, true);
        $course = $this->courses->findById($this->course);
        self::assertSame([$code, 'Quick edit renamed', $this->slug], [$course['code'], $course['title'], $course['slug']], 'The course keeps its web address.');
        self::assertSame($category ?: null, $course['category_id'] === null ? null : (int) $course['category_id']);
        $variants = $this->courses->priceVariants($this->course);
        self::assertCount(1, $variants, 'A course without a price gets its default price option.');
        self::assertSame([135000, 160000, 180 * 86400, true], [(int) $variants[0]['price_minor_units'], (int) $variants[0]['was_price_minor_units'], (int) $variants[0]['access_period_seconds'], (bool) $variants[0]['is_default']]);

        // Its only price option is its default: it is changed, not added to.
        $this->quick->save($this->course, ['price' => '1400', 'was_price' => '', 'access_period_value' => '1', 'access_period_unit' => 'years'] + $row, $this->admin, true);
        $variants = $this->courses->priceVariants($this->course);
        self::assertSame([1, 140000, null, 365 * 86400], [count($variants), (int) $variants[0]['price_minor_units'], $variants[0]['was_price_minor_units'] === null ? null : (int) $variants[0]['was_price_minor_units'], (int) $variants[0]['access_period_seconds']]);
        // The position in the catalogue: saved, emptied, and refused when it is not a whole number from 1.
        $this->quick->save($this->course, ['catalogue_position' => '4300'] + $row, $this->admin, false);
        self::assertSame(4300, (int) $this->courses->findById($this->course)['catalogue_position']);
        $this->quick->save($this->course, ['catalogue_position' => ''] + $row, $this->admin, false);
        self::assertNull($this->courses->findById($this->course)['catalogue_position']);
        try {
            $this->quick->save($this->course, ['catalogue_position' => '0', 'title' => 'Never saved'] + $row, $this->admin, false);
            self::fail('A position of 0 was saved.');
        } catch (\InvalidArgumentException) {
            self::assertSame('Quick edit renamed', (string) $this->courses->findById($this->course)['title'], 'Nothing is saved with a refused position.');
        }
        // Without permission to manage prices, the price is left alone.
        $this->quick->save($this->course, ['price' => '9999'] + $row, $this->admin, false);
        self::assertSame(140000, (int) $this->courses->priceVariants($this->course)[0]['price_minor_units']);
    }

    public function testARefusalSavesNothing(): void
    {
        $before = $this->courses->findById($this->course);
        $row = ['code' => (string) $before['code'], 'title' => 'Never saved', 'category_id' => '0', 'price' => '2000', 'was_price' => '1500', 'access_period_value' => '12', 'access_period_unit' => 'months'];
        foreach ([$row, ['code' => ''] + $row, ['code' => 'not a code'] + $row, ['title' => ''] + $row] as $refused) {
            try {
                $this->quick->save($this->course, $refused, $this->admin, true);
                self::fail('Saved ' . json_encode($refused));
            } catch (\InvalidArgumentException) {
            }
        }
        self::assertSame((string) $before['title'], (string) $this->courses->findById($this->course)['title'], 'The title is not saved when the price is refused.');
        self::assertSame([], $this->courses->priceVariants($this->course));
    }

    public function testACourseWithOtherPriceOptionsIsPricedOnItsTab(): void
    {
        $service = IntegrationContainer::get()->get(CourseService::class);
        foreach ([['950.00', '1', '6'], ['1600.00', '', '12']] as [$price, $default, $months]) {
            $service->createPriceVariant($this->course, ['price' => $price, 'was_price' => '', 'access_period_value' => $months, 'access_period_unit' => 'months', 'currency_code' => 'ZAR', 'label' => '', 'is_active' => '1', 'is_default' => $default], $this->admin);
        }
        $row = IntegrationContainer::get()->get(\CattoLearning\Application\PlatformAdministrationService::class)->adminCourseRow($this->course);
        self::assertNotNull($row);
        self::assertSame([2, false, false], [$row['price_option_count'], CourseQuickEdit::priceEditable($row), $this->quick->form($row, true)['price']['editable']]);
        $this->expectExceptionMessage('other price options');
        $this->quick->save($this->course, ['code' => (string) $row['code'], 'title' => (string) $row['title'], 'category_id' => '0', 'price' => '100'], $this->admin, true);
    }

    public function testTheRowRouteAnswersHtmxWithTheRowAndTheListWithEditOpen(): void
    {
        $this->signIn($this->admin);
        $_SERVER['HTTP_HX_REQUEST'] = 'true';
        $form = $this->send('GET', '/admin/courses/' . $this->code . '/row?mode=edit&view=list');
        self::assertSame(200, $form->getStatusCode());
        $html = (string) $form->getContent();
        self::assertStringStartsWith('<tr id="course-' . $this->code . '" class="cl-course-quick"', trim((string) preg_replace('/^\s*(<!--.*?-->\s*)*/s', '', $html)));
        self::assertStringNotContainsString('<html', $html, 'Only the row is sent.');
        foreach (['name="catalogue_position"', 'name="code"', 'name="title"', 'name="price"', 'name="was_price"', 'name="access_period_value"', 'name="category_id"', 'form="course-quick-' . $this->course . '"'] as $part) {
            self::assertStringContainsString($part, $html);
        }
        $card = (string) $this->send('GET', '/admin/courses/' . $this->code . '/row?mode=edit&view=grid')->getContent();
        self::assertStringContainsString('<li class="cl-ui-card"', $card);

        $course = $this->courses->findById($this->course);
        $refused = $this->send('POST', '/admin/courses/' . $this->code . '/row', ['code' => (string) $course['code'], 'title' => 'Kept as typed', 'category_id' => '0', 'price' => '2000', 'was_price' => '1500', 'access_period_value' => '12', 'access_period_unit' => 'months', 'view' => 'list']);
        self::assertSame(422, $refused->getStatusCode());
        self::assertStringContainsString('cl-course-quick-error', (string) $refused->getContent());
        self::assertStringContainsString('value="Kept as typed"', (string) $refused->getContent());

        $saved = $this->send('POST', '/admin/courses/' . $this->code . '/row', ['code' => (string) $course['code'], 'title' => 'Saved in place', 'category_id' => '0', 'price' => '', 'was_price' => '', 'access_period_value' => '12', 'access_period_unit' => 'months', 'view' => 'list']);
        self::assertSame(200, $saved->getStatusCode());
        self::assertStringContainsString('data-course-saved', (string) $saved->getContent());
        self::assertStringContainsString('Saved in place', (string) $saved->getContent());
        self::assertSame('Saved in place', (string) $this->courses->findById($this->course)['title']);

        unset($_SERVER['HTTP_HX_REQUEST']);
        $plain = $this->send('GET', '/admin/courses/' . $this->code . '/row?mode=edit');
        self::assertSame(303, $plain->getStatusCode(), 'Without JavaScript the pencil opens the list.');
        $list = $this->send('GET', '/admin/courses?edit=' . $this->code . '&courses_q=' . rawurlencode('Saved in place'));
        self::assertStringContainsString('class="cl-course-quick"', (string) $list->getContent(), 'The list opens the row as its form.');
    }

    private function signIn(int $user): void
    {
        $token = Token::generate();
        IntegrationContainer::get()->get(AuthSessionRepository::class)->create($user, Token::hash($token), 3600, 'qa', 'PHPUnit');
        $_COOKIE = $this->cookies;
        $_COOKIE[Env::string('AUTH_SESSION_COOKIE', 'catto_learning_session')] = $token;
    }

    /** @param array<string,mixed> $fields */
    private function send(string $method, string $url, array $fields = []): Response
    {
        $kernel = new Kernel('test', true, CliBootstrap::boot()['instance_root']);
        $_POST = $method === 'POST' ? ['csrf' => $_SESSION['csrf']] + $fields : [];
        $_GET = Request::create($url)->query->all();
        try {
            return $kernel->handle(Request::create($url, $method, $_POST));
        } finally {
            $kernel->shutdown();
            $_POST = [];
            $_GET = [];
        }
    }
