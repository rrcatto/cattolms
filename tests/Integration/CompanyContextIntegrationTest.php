    /** @param list<string> $permissions */
    private function identity(int $userId, array $permissions, ?string $seedToken = null): CurrentUser
    {
        return new CurrentUser(
            $userId,
            Uuid::v4(),
            'identity-' . $userId . '@example.test',
            'Identity ' . $userId,
            [],
            $permissions,
            Uuid::v4(),
            $seedToken
        );
    }

    private function platformAdmin(): CurrentUser
    {
        return $this->identity($this->adminUserId, [
            SelectedCompanyContext::SELECTOR_PERMISSION,
            'COMPANY.DASHBOARD.VIEW',
            'PLATFORM.PERSON.MANAGE',
        ]);
    }

    private function companyAdmin(): CurrentUser
    {
        return $this->identity($this->companyAdminUserId, ['COMPANY.DASHBOARD.VIEW', 'COMPANY.PERSON.MANAGE']);
    }

    private function membershipCount(int $userId): int
    {
        return (int) $this->fixture->scalar(
            'SELECT COUNT(*)::int AS value FROM company_users WHERE user_id = :id',
            [':id' => $userId]
        );
    }

    /**
     * Loads every Company section under the current context and returns them by key.
     *
     * @return array<string,array<string,mixed>>
     */
    private function allSections(CurrentUser $user, DataUniverse $universe): array
    {
        $context = $this->context->resolve($user, $universe);
        $loaded = [];
        foreach (self::SECTIONS as $section) {
            $loaded[$section] = $this->administration->companySectionData(
                $section,
                $user->id,
                $universe,
                $context
            );
        }

        return $loaded;
    }

    // --- the platform administrator ------------------------------------------------------------

    /**
     * With nothing selected, a platform administrator administers the REAL System Company.
     *
     * The former default was a synthetic "All companies" row with id 0, which no mutation could
     * act on - so every write from that state fell back to the actor's own membership. The
     * workspace now always resolves one concrete company.
     */
    public function testTheRealSystemCompanyIsTheDefaultForAPlatformAdministrator(): void
    {
        $context = $this->context->resolve($this->platformAdmin(), DataUniverse::Real);

        self::assertSame('selected', $context['mode']);
        self::assertFalse($context['platform_wide']);
        self::assertGreaterThan(0, $context['company_id'], 'There must always be a concrete company to act on.');
        self::assertTrue(
            in_array($context['company']['is_system'] ?? false, [true, 1, '1', 't', 'true'], true),
            'The default must be the System Company.'
        );
        self::assertSame(DataUniverse::Real, $context['universe'], 'The default System Company is the REAL one.');
    }

    /** Selecting company A puts every section into company A. */
    public function testSelectingACompanyScopesEverySection(): void
    {
        $user = $this->platformAdmin();
        $this->context->select($user, $this->real['a'], DataUniverse::Real);

        $context = $this->context->resolve($user, DataUniverse::Real);
        self::assertSame('selected', $context['mode']);
        self::assertSame($this->real['a'], $context['company_id']);
        self::assertFalse($context['platform_wide']);

        foreach ($this->allSections($user, DataUniverse::Real) as $section => $data) {
            self::assertSame(
                $this->real['a'],
                (int) $data['company']['id'],
                $section . ' must describe the selected company.'
            );
            self::assertFalse((bool) $data['company_platform_wide'], $section . ' must not be platform-wide.');
        }
    }

    /** Switching from A to B changes what every section describes. */
    public function testSwitchingCompaniesChangesWhatIsShown(): void
    {
        $user = $this->platformAdmin();

        $this->context->select($user, $this->real['a'], DataUniverse::Real);
        $peopleA = $this->administration->companySectionData(
            'people',
            $user->id,
            DataUniverse::Real,
            $this->context->resolve($user, DataUniverse::Real)
        );

        $this->context->select($user, $this->real['b'], DataUniverse::Real);
        $peopleB = $this->administration->companySectionData(
            'people',
            $user->id,
            DataUniverse::Real,
            $this->context->resolve($user, DataUniverse::Real)
        );

        self::assertSame($this->real['a'], (int) $peopleA['company']['id']);
        self::assertSame($this->real['b'], (int) $peopleB['company']['id']);

        $idsA = array_map(static fn(array $row): int => (int) $row['id'], $peopleA['people']);
        $idsB = array_map(static fn(array $row): int => (int) $row['id'], $peopleB['people']);

        self::assertNotSame([], $idsA, 'Company A must have people, or this proves nothing.');
        self::assertNotSame([], $idsB, 'Company B must have people, or this proves nothing.');
        self::assertSame(
            [],
            array_values(array_intersect($idsA, $idsB)),
            'Two companies must not share a person list.'
        );
    }

    /** A platform administrator may deliberately administer a SEED company under a SEED scope. */
