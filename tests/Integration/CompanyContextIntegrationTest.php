    /** Switching from A to B changes what every section describes. */
    public function testSwitchingCompaniesChangesWhatIsShown(): void
    {
        $user = $this->platformAdmin();

        $this->context->select($user, $this->real['a']);
        $peopleA = $this->administration->companySectionData(
            'people',
            $user->id,
            $this->context->resolve($user)
        );

        $this->context->select($user, $this->real['b']);
        $peopleB = $this->administration->companySectionData(
            'people',
            $user->id,
            $this->context->resolve($user)
        );

        self::assertSame($this->real['a'], (int) $peopleA['company']['id']);
        self::assertSame($this->real['b'], (int) $peopleB['company']['id']);

        $idsA = array_map(static fn(array $row): int => (int) $row['id'], $peopleA['people']);
        $idsB = array_map(static fn(array $row): int => (int) $row['id'], $peopleB['people']);

        self::assertNotSame([], $idsA, 'Company A must have people, or this proves nothing.');
        self::assertNotSame([], $idsB, 'Company B must have people, or this proves nothing.');
        self::assertSame(
            [],
            array_values(array_intersect($idsA, $idsB)),
            'Two companies must not share a person list.'
        );
    }


