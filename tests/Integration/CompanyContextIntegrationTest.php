  REAL identity;

  an ordinary Company Administrator is offered no selector, is pinned to their own company, and
  cannot reach another company - or a SEED company - by supplying an id.

The membership assertions are the ones worth reading twice. Platform administration of a company
is a privileged context, not business membership, and the last time those two were conflated a GET
request deactivated a genuine administrator's real membership before failing.

