    // --- the corrected company courses rule ----------------------------------------------------

    /** Company Courses means owned-or-credited, and its count matches its rows. */
    public function testCompanyCoursesAreOwnedOrCreditedAndTheCountMatches(): void
    {
        /** @var CourseRepository $courses */
        $courses = $this->container->get(CourseRepository::class);

        // A course owned by REAL company A, and one owned by REAL company B.
        $suffix = $this->fixture->suffix();
        $ownedByA = $this->fixture->createCourse(
            $this->adminUserId,
            $this->real['a'],
            'owned-alpha-' . $suffix,
            'Owned by Alpha ' . $suffix
        );
        $this->fixture->createCourse(
            $this->adminUserId,
            $this->real['b'],
            'owned-beta-' . $suffix,
            'Owned by Beta ' . $suffix
        );

        $rows = $courses->companyCourses(DataUniverse::Real, $this->real['a'], 100, 0);
        $ids = array_map(static fn(array $row): int => (int) $row['id'], $rows);

        self::assertContains($ownedByA, $ids, 'A company must see the course it owns.');
        self::assertSame(
            $courses->companyCoursesCount(DataUniverse::Real, $this->real['a']),
            count($rows),
            'The count and the rows must describe the same population.'
        );

        // And it must not be the whole catalogue.
        $everything = $courses->allCoursesCount(DataUniverse::Real);
        self::assertLessThan(
            $everything,
            $courses->companyCoursesCount(DataUniverse::Real, $this->real['a']),
            'A company course list that equals the platform catalogue is the defect Stage D fixed.'
        );
    }

    /** The consolidated workspace preview uses the same rule as the standalone section. */
    public function testTheWorkspacePreviewAgreesWithTheStandaloneSection(): void
    {
        $user = $this->platformAdmin();
        $this->context->select($user, $this->real['a'], DataUniverse::Real);
        $context = $this->context->resolve($user, DataUniverse::Real);

        $workspace = $this->administration->companyControlCentre($user->id, DataUniverse::Real, $context);
        $section = $this->administration->companySectionData('courses', $user->id, DataUniverse::Real, $context);

        self::assertSame(
            (int) $section['courses_count'],
            (int) $workspace['courses_count'],
            'The preview and the section it links to must describe one population.'
        );
    }
