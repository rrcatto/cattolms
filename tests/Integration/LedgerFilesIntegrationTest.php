    public function testAStatementOpensWithWhatCameBeforeAndClosesWithTheBalanceAtItsEnd(): void
    {
        [$owner, $reference] = $this->wallet();
        $period = ['from' => '2025-03-05', 'to' => '2025-03-31'];

        $statement = $this->files->statement($owner, 'Thandi Mokoena', $reference, $period, 'xlsx');
        self::assertSame(50000, $statement['opening'], 'What the wallet held before the period.');
        self::assertSame([70000, 55000], array_column($statement['lines'], 'balance'), 'The balance after each movement in it, oldest first.');
        self::assertSame([20000, 15000, 55000], [$statement['added'], $statement['used'], $statement['closing']]);
        self::assertSame('5 March 2025 to 31 March 2025', $statement['period']);
        self::assertStringEndsWith('-2025-03-05-to-2025-03-31.xlsx', LedgerFiles::name($statement, 'xlsx'));

        $excel = $this->files->statementExcel($statement);
        $sheets = $this->readExcel($excel);
        self::assertSame(['Summary', 'Movements'], array_keys($sheets));
        self::assertSame(['When', 'What happened', 'Order', 'Document', 'Note', 'Credit added', 'Credit used', 'Balance'], $sheets['Movements'][0]);
        self::assertCount(3, $sheets['Movements'], 'A heading and the period\'s two movements.');
        self::assertInstanceOf(\DateTimeInterface::class, $sheets['Movements'][1][0], 'A date is a date.');
        self::assertSame(self::FORMULA_LIKE, $sheets['Movements'][1][4], 'A note that begins with = stays words.');
        self::assertEqualsWithDelta(200.0, $sheets['Movements'][1][5], 0.001, 'An amount is a number in rand.');
        self::assertEqualsWithDelta(550.0, $sheets['Movements'][2][7], 0.001);
        self::assertStringNotContainsString('<f>', $this->sheetXml($excel, 2), 'No cell is a formula.');

        self::assertStringStartsWith('%PDF', $this->files->statementPdf($this->files->statement($owner, 'Thandi Mokoena', $reference, $period, 'pdf')));

        $everything = $this->files->statement($owner, 'Thandi Mokoena', $reference, [], 'pdf');
        self::assertSame([0, 4, 65000], [$everything['opening'], count($everything['lines']), $everything['closing']], 'With no dates, every movement to now.');
    }

    public function testTheLedgersFileHoldsTheLinesItsFiltersMatchWithTheirTotals(): void
    {
        [, $reference] = $this->wallet();
        $query = ['q' => $reference];

        $ledger = $this->files->ledger($query, 'xlsx');
        $totals = $this->money->ledgerTotalsFor($query);
        self::assertSame(4, $totals['entries']);
        self::assertCount($totals['entries'], $ledger['lines'], 'Every line the filters match, as the page counts them.');
        self::assertSame([50000, 20000, -15000, 10000], array_column($ledger['lines'], 'wallet'), 'Oldest first.');
        self::assertSame(['Search: "' . $reference . '"'], $ledger['filters']);
        self::assertSame([80000, 15000], [$ledger['totals']['wallet_in'], $ledger['totals']['wallet_out']]);

        $sheets = $this->readExcel($this->files->ledgerExcel($ledger));
        self::assertSame(['Summary', 'Lines'], array_keys($sheets));
        self::assertCount(5, $sheets['Lines'], 'A heading and the four lines.');
        self::assertSame('Wallet credit', $sheets['Lines'][0][12]);
        self::assertEqualsWithDelta(-150.0, $sheets['Lines'][3][12], 0.001, 'Credit taken away is a negative amount.');

        self::assertStringStartsWith('%PDF', $this->files->ledgerPdf($this->files->ledger($query, 'pdf')));
    }

    public function testDatesTheWrongWayRoundAndAnyOtherFileAreRefused(): void
    {
        [$owner, $reference] = $this->wallet();
        try {
            $this->files->statement($owner, 'Thandi Mokoena', $reference, ['from' => '2025-03-31', 'to' => '2025-03-01'], 'pdf');
            self::fail('A statement that ends before it starts is refused.');
        } catch (RuntimeException $refused) {
            self::assertStringContainsString('comes before its first', $refused->getMessage());
        }
        try {
            $this->files->ledger([], 'csv');
            self::fail('Only a PDF or an Excel file is made.');
        } catch (RuntimeException $refused) {
            self::assertSame('Choose a PDF or an Excel file.', $refused->getMessage());
        }
    }

    /**
     * A person's wallet with four movements, each recorded by an administrator on its own day: R500 on 2 March 2025,
     * R200 on 10 March (its note looking like a formula), R150 taken back on 15 March and R100 on 1 April.
     *
     * @return array{0:WalletOwner,1:string}
     */
    private function wallet(): array
    {
        $person = $this->fixture->createUser('Thandi Mokoena', 'thandi-' . bin2hex(random_bytes(4)) . '@example.test');
        $admin = $this->fixture->createUser('Sipho Dlamini', 'sipho-' . bin2hex(random_bytes(4)) . '@example.test');
        $owner = WalletOwner::person($person);
        foreach ([['2025-03-02 09:00', 50000, 'Credit for the statement test.'], ['2025-03-10 10:00', 20000, self::FORMULA_LIKE],
            ['2025-03-15 11:00', -15000, 'Credit taken back for the test.'], ['2025-04-01 12:00', 10000, 'Credit after the period.']] as [$at, $amount, $why]) {
            $this->clock->modify($at);
            $this->wallets->correct($owner, $amount, 'ZAR', $why, $admin);
        }
        $this->clock->modify('2025-04-02 08:00');

        return [$owner, (string) $this->db->fetchOne('SELECT account_reference FROM users WHERE id = :id', ['id' => $person])];
    }

    /** @return array<string,list<list<mixed>>> */
    private function readExcel(string $bytes): array
    {
        $path = tempnam(sys_get_temp_dir(), 'ledger-files-test-');
        self::assertNotFalse($path);
        file_put_contents($path, $bytes);
        $reader = new Reader();
        $reader->open($path);
        $sheets = [];
        foreach ($reader->getSheetIterator() as $sheet) {
            $rows = [];
            foreach ($sheet->getRowIterator() as $row) $rows[] = $row->toArray();
            $sheets[$sheet->getName()] = $rows;
        }
        $reader->close();
        @unlink($path);

        return $sheets;
    }

    /** One worksheet's XML, to see how its cells were written. */
    private function sheetXml(string $bytes, int $sheet): string
    {
        $path = tempnam(sys_get_temp_dir(), 'ledger-files-zip-');
        self::assertNotFalse($path);
        file_put_contents($path, $bytes);
        $zip = new ZipArchive();
        self::assertTrue($zip->open($path) === true);
        $xml = (string) $zip->getFromName('xl/worksheets/sheet' . $sheet . '.xml');
        $zip->close();
        @unlink($path);

        return $xml;
    }
