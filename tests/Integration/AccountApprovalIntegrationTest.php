    public function testADemoSitesNewAccountWaitsForApprovalBeforeItCanSignIn(): void
    {
        $container = CliBootstrap::boot()['container'];
        $db = $container->get(Database::class);
        $fixture = new DevelopmentFixture($db);
        $email = 'approval-' . $fixture->suffix() . '@example.test';
        $mailer = new FakeMailer();
        $auth = $this->auth($container, $mailer, 'demo');
        try {
            $auth->requestRegistration(['account_type' => 'individual', 'first_name' => 'Waiting', 'middle_names' => '', 'last_name' => 'Person', 'email' => $email,
                'date_of_birth' => (new \DateTimeImmutable('-30 years'))->format('Y-m-d')]);
            parse_str((string) parse_url((string) self::sent($mailer)[0]['url'], PHP_URL_QUERY), $query);
            $mailer->messages = [];
            self::assertSame(AuthService::AWAITING_APPROVAL_PATH, $auth->consumeRegistration((string) $query['token']), 'Confirming the email shows the waiting page.');
            $userId = (int) $db->fetchOne('SELECT user_id FROM user_emails WHERE email = :email', ['email' => $email]);
            $fixture->rememberUser($userId);
            $fixture->rememberEmail($email);
            self::assertSame('awaiting_approval', $db->fetchOne('SELECT status FROM users WHERE id = :id', ['id' => $userId]));
            self::assertSame(0, (int) $db->fetchOne('SELECT COUNT(*) FROM auth_sessions WHERE user_id = :id', ['id' => $userId]), 'No session: it is not signed in.');
            self::assertSame(1, (int) $db->fetchOne("SELECT COUNT(*) FROM audit_log WHERE user_id = :id AND event_key = 'user.awaiting_approval'", ['id' => $userId]));
            $admin = trim((string) (getenv('APP_ADMIN_EMAIL') ?: ($_ENV['APP_ADMIN_EMAIL'] ?? '')));
            if ($admin !== '') {
                $toAdmin = array_values(array_filter(self::sent($mailer), static fn(array $m): bool => ($m['email'] ?? '') === $admin));
                self::assertCount(1, $toAdmin, 'ADMIN is told an account is waiting.');
                self::assertStringContainsString('/admin/people/' . $userId, (string) $toAdmin[0]['body']);
            }
            // Signing in is refused with the reason, and no link is sent; registering again says the same.
            $mailer->messages = [];
            foreach (['sign in' => fn() => $auth->requestLogin($email), 'register again' => fn() => $auth->requestRegistration(['email' => $email])] as $what => $try) {
                try {
                    $try();
                    self::fail('Accepted: ' . $what);
                } catch (RuntimeException $refused) {
                    self::assertSame(AuthService::AWAITING_APPROVAL_MESSAGE, $refused->getMessage(), $what);
                }
            }
            self::assertCount(0, self::sent($mailer), 'Nothing is sent to an account that is waiting.');
            // ADMIN approves it: it signs in from now on, and the person is told.
            $auth->approveAccount($userId, $userId);
            self::assertSame('active', $db->fetchOne('SELECT status FROM users WHERE id = :id', ['id' => $userId]));
            self::assertSame('Your account is approved', self::sent($mailer)[0]['subject'] ?? null);
            self::assertSame($email, self::sent($mailer)[0]['email'] ?? null);
            $auth->requestLogin($email);
            self::assertSame(['magic_link', $email], [self::sent($mailer)[1]['type'] ?? null, self::sent($mailer)[1]['email'] ?? null], 'An approved account is sent its sign-in link.');
            $this->expectException(RuntimeException::class);
            $auth->approveAccount($userId, $userId);
        } finally {
            unset($_COOKIE['catto_learning_session']);
            $fixture->cleanup();
        }
    }

