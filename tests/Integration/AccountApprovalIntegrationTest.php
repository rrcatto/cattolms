    private function auth(ContainerInterface $container, FakeMailer $mailer, string $mode, ?\CattoLearning\Auth\SignInRestriction $restriction = null): AuthService
    {
        return new AuthService(
            $container->get(TransactionManager::class),
            $container->get(UserRepository::class),
            $container->get(RoleRepository::class),
            $container->get(AclService::class),
            $container->get(LoginTokenRepository::class),
            $container->get(AuthSessionRepository::class),
            $container->get(AuditRepository::class),
            $mailer,
            $container->get(EventDispatcher::class),
            $container->get(UserProfileRepository::class),
            null,
            SiteMode::fixed($mode),
            $restriction
        );
    }
