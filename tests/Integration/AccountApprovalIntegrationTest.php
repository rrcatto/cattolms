    /**
     * Who can sign in (owner, 2026-10-21: "disallow all non-admin logins ... a whitelist of allowed emails"): while it is
     * limited, anyone not listed is refused at sign-in and registration, a listed friend registers without waiting for
     * approval even on a demo site, and the administrator always signs in.
     */
    public function testSignInCanBeLimitedToAdministratorsAndListedAddresses(): void
    {
        $container = CliBootstrap::boot()['container'];
        $db = $container->get(Database::class);
        $db->beginTransaction();
        $fixture = new DevelopmentFixture($db);
        $suffix = $fixture->suffix();
        $friend = 'friend-' . $suffix . '@example.test';
        $stranger = 'stranger-' . $suffix . '@example.test';
        $member = 'member-' . $suffix . '@example.test';
        $fixture->createUser('Existing member', $member);
        $mailer = new FakeMailer();
        $restriction = new \CattoLearning\Auth\SignInRestriction($container->get(\CattoLearning\Infrastructure\Persistence\OptionRepository::class));
        try {
            $restriction->save(true, $friend . "\n");
            $auth = $this->auth($container, $mailer, 'demo', $restriction);
            foreach (['sign in' => fn() => $auth->requestLogin($member), 'register' => fn() => $auth->requestRegistration(['account_type' => 'individual', 'first_name' => 'A', 'last_name' => 'Stranger', 'email' => $stranger,
                'date_of_birth' => (new \DateTimeImmutable('-30 years'))->format('Y-m-d')])] as $what => $try) {
                try {
                    $try();
                    self::fail('Allowed: ' . $what);
                } catch (RuntimeException $refused) {
                    self::assertSame(\CattoLearning\Auth\SignInRestriction::REFUSED, $refused->getMessage(), $what);
                }
            }
            self::assertCount(0, self::sent($mailer), 'Nothing is sent to someone kept out.');
            $auth->requestRegistration(['account_type' => 'individual', 'first_name' => 'A', 'middle_names' => '', 'last_name' => 'Friend', 'email' => $friend,
                'date_of_birth' => (new \DateTimeImmutable('-30 years'))->format('Y-m-d')], '/account/courses');
            parse_str((string) parse_url((string) self::sent($mailer)[0]['url'], PHP_URL_QUERY), $query);
            self::assertSame('/account/courses', $auth->consumeRegistration((string) $query['token']), 'A listed friend needs no approval, even on a demo site.');
            self::assertSame('active', $db->fetchOne('SELECT u.status FROM users u JOIN user_emails ue ON ue.user_id = u.id WHERE ue.email = :email', ['email' => $friend]));
            $admin = trim((string) (getenv('APP_ADMIN_EMAIL') ?: ($_ENV['APP_ADMIN_EMAIL'] ?? '')));
            if ($admin !== '') $auth->requestLogin($admin);
            self::assertTrue($restriction->allows('anyone@example.test', true), 'An administrator is never kept out.');
            $restriction->save(false, '');
            self::assertTrue($restriction->allows($stranger, false), 'Everyone again.');
            $this->expectException(\InvalidArgumentException::class);
            $restriction->save(true, 'not-an-address');
        } finally {
            unset($_COOKIE['catto_learning_session']);
            if ($db->isTransactionActive()) $db->rollBack();
        }
    }

    /**
     * What the fake mailer has sent, read through a call: PHPStan otherwise keeps the empty list it saw assigned.
