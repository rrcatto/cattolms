Date time: 2026/10/07 SAST

Version: 0.8.8.11

Description:
The category tree against the database and through its controller. Every move and creation goes
through CategoryHierarchyService, so these are the rules whichever way the request arrives:
reordering siblings at the top level and inside a category, moving a main category under another,
a subcategory back out to the top, a subcategory to another main category, a sub-subcategory
between subcategories and a whole subtree at once; refusing a fourth level, a subtree that would
end up below the third level, a category inside itself or one of its descendants, a position that
does not exist and a move decided on a tree that has since changed; and leaving the tree exactly as
it was when a move is refused. After every move positions are 1..n within each parent, the courses
filed in a category are untouched, and paths shown anywhere follow the new tree. New categories go
last among their siblings, under a parent taken from the address, never the form.

The page renders main categories with every branch closed, opens the branches asked for and those
above a category just created or moved, keeps Manage on every row, refreshes its counts with the
tree after a move, and answers a refused move from the tree's script with the stored tree and the
reason.

Test tree, appended after the shipped taxonomy:
  A > A1 > A1x, A > A2      B > B1      C      D > D1

Every test runs inside a transaction that is rolled back.

Changelog:
2026/10/07 SAST
- Created for the draggable category tree, replacing the parent picker test.
