    public function testReorderingSiblingsAtTheTopAndInsideACategory(): void
    {
        $this->move('C', null, $this->rootIndexOf('A'));
        self::assertSame(['C', 'A', 'B', 'D'], $this->roots(), 'C now sits before A; the order is explicit, not by name or id.');
        $this->move('A2', 'A', 0);
        self::assertSame(['A2', 'A1'], $this->children('A'));
        $this->move('A2', 'A', 1);
        self::assertSame(['A1', 'A2'], $this->children('A'));
        $this->assertCompact();
    }

    public function testMovingAcrossLevelsTakesTheWholeSubtreeAndRelevelsIt(): void
    {
        $this->move('C', 'B', null);
        self::assertSame([2, ['B1', 'C']], [$this->level('C'), $this->children('B')], 'A main category moved under another becomes its last subcategory.');
        $this->move('B1', null, null);
        self::assertSame([1, null], [$this->level('B1'), $this->parent('B1')], 'A subcategory moved out becomes a main category.');
        $this->move('A2', 'D', 0);
        self::assertSame([2, ['A2', 'D1']], [$this->level('A2'), $this->children('D')], 'A subcategory moves to another main category.');
        $this->move('A1x', 'D1', null);
        self::assertSame([3, $this->ids['D1']], [$this->level('A1x'), $this->parent('A1x')], 'A sub-subcategory moves between subcategories.');
        $this->move('A1x', 'A1', null);

        $this->move('A1', 'B', 0);
        self::assertSame([2, 3, $this->ids['A1']], [$this->level('A1'), $this->level('A1x'), $this->parent('A1x')], 'The subtree travels intact.');
        $this->move('A1', null, null);
        self::assertSame([1, 2], [$this->level('A1'), $this->level('A1x')], 'And back out, one level up, still intact.');
        $this->assertCompact();
    }

    public function testDepthCyclesBadPositionsAndStaleTreesAreRefusedAndNothingChanges(): void
    {
        $before = $this->snapshot();
        $this->assertRefused('C', 'A1x', null, 'three levels deep');
        $this->assertRefused('A1', 'B1', null, 'three levels deep', 'A1 holds a level below it: under a subcategory that would be a fourth level.');
        $this->assertRefused('A', 'B', null, 'three levels deep', 'A is three levels tall.');
        $this->assertRefused('A', 'A', null, 'into itself');
        $this->assertRefused('A', 'A1x', null, 'into itself');
        $this->assertRefused('A1', 'A1x', null, 'into itself');
        $this->assertRefused('B1', 'B', 7, 'valid position');
        try {
            $this->service->arrangeCategory($this->ids['A2'], $this->ids['B'], null, $this->userId, $this->ids['D'], true);
            self::fail('A move decided on a tree that has since changed is refused.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString('changed while you were moving', $refused->getMessage());
        }
        try {
            $this->service->moveCategory($this->ids['A'], 'out', $this->userId);
            self::fail('A main category cannot move out.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString('already a main category', $refused->getMessage());
        }
        self::assertSame($before, $this->snapshot(), 'A refused move leaves the tree exactly as it was.');
        $this->service->arrangeCategory($this->ids['A2'], $this->ids['B'], null, $this->userId, $this->ids['A'], true);
        self::assertSame($this->ids['B'], $this->parent('A2'), 'The same move from the tree as stored goes ahead.');
    }

    public function testMenuMovesKeepPositionsCompact(): void
    {
        // The main categories are shared with the shipped taxonomy, so D goes to the very top and
        // then one place down, past the first shipped category.
        $this->service->moveCategory($this->ids['D'], 'top', $this->userId);
        self::assertSame(1, $this->position('D'));
        $this->service->moveCategory($this->ids['D'], 'down', $this->userId);
        self::assertSame(2, $this->position('D'));
        $this->service->moveCategory($this->ids['A'], 'bottom', $this->userId);
        self::assertSame(['D', 'B', 'C', 'A'], $this->roots());
        self::assertSame((int) $this->db->fetchOne('SELECT COUNT(*) FROM course_categories WHERE parent_id IS NULL'), $this->position('A'));
        $this->service->moveCategory($this->ids['A1x'], 'out', $this->userId);
        self::assertSame([2, ['A1', 'A1x', 'A2']], [$this->level('A1x'), $this->children('A')], 'Out puts it just after its former parent.');
        $this->assertCompact();
        $audit = $this->db->fetchAssociative("SELECT metadata FROM audit_log WHERE event_key = 'course_category.moved' AND user_id = :user ORDER BY id DESC LIMIT 1", ['user' => $this->userId]);
        self::assertNotFalse($audit);
        self::assertSame($this->ids['A1x'], json_decode((string) $audit['metadata'], true)['category_id']);
    }

