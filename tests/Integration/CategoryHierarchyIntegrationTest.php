    private function move(string $key, ?string $parent, ?int $index): void
    {
        $this->service->arrangeCategory($this->ids[$key], $parent === null ? null : $this->ids[$parent], $index, $this->userId);
    }

    private function assertRefused(string $key, ?string $parent, ?int $index, string $message, string $why = ''): void
    {
        try {
            $this->move($key, $parent, $index);
            self::fail($key . ' was moved under ' . ($parent ?? 'the top') . '. ' . $why);
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString($message, $refused->getMessage(), $why);
        }
    }

    /** Where the given test root sits among the main categories other than C, which is the one moving. */
    private function rootIndexOf(string $key): int
    {
        $ids = array_map('intval', $this->db->fetchFirstColumn('SELECT id FROM course_categories WHERE parent_id IS NULL AND id <> :c ORDER BY position', ['c' => $this->ids['C']]));
        return (int) array_search($this->ids[$key], $ids, true);
    }

    /** @return list<string> the test categories among the main categories, in order */
    private function roots(): array
    {
        return $this->keysOf($this->db->fetchFirstColumn('SELECT id FROM course_categories WHERE parent_id IS NULL ORDER BY position'));
    }

    /** @return list<string> */
    private function children(string $key): array
    {
        return $this->keysOf($this->db->fetchFirstColumn('SELECT id FROM course_categories WHERE parent_id = :p ORDER BY position', ['p' => $this->ids[$key]]));
    }

    /**
     * @param list<mixed> $ids
     * @return list<string>
     */
    private function keysOf(array $ids): array
    {
        $keys = array_flip($this->ids);
        return array_values(array_map(static fn(mixed $id): string => $keys[(int) $id], array_filter($ids, static fn(mixed $id): bool => isset($keys[(int) $id]))));
    }

    private function level(string $key): int
    {
        return (int) $this->db->fetchOne('SELECT level FROM course_categories WHERE id = :id', ['id' => $this->ids[$key]]);
    }

    private function position(string $key): int
    {
        return (int) $this->db->fetchOne('SELECT position FROM course_categories WHERE id = :id', ['id' => $this->ids[$key]]);
    }

    private function parent(string $key): ?int
    {
        $parent = $this->db->fetchOne('SELECT parent_id FROM course_categories WHERE id = :id', ['id' => $this->ids[$key]]);
        return $parent === null ? null : (int) $parent;
    }

    /** @return list<array<string,mixed>> */
    private function snapshot(): array
    {
        return $this->db->fetchAllAssociative('SELECT id, parent_id, level, position FROM course_categories ORDER BY id');
    }

    /** Positions are 1..n within every parent, the whole taxonomy over. */
    private function assertCompact(): void
    {
        $broken = $this->db->fetchAllAssociative('SELECT parent_id, COUNT(*) AS n, MIN(position) AS lo, MAX(position) AS hi, COUNT(DISTINCT position) AS distinct_positions
            FROM course_categories GROUP BY parent_id HAVING MIN(position) <> 1 OR MAX(position) <> COUNT(*) OR COUNT(DISTINCT position) <> COUNT(*)');
        self::assertSame([], $broken, 'Sibling positions are 1..n.');
    }

    private function label(string $key): string
    {
        return 'Tree ' . $key . ' ' . $this->suffix;
    }

    private static function xpath(string $html): \DOMXPath
    {
        $document = new \DOMDocument();
        @$document->loadHTML('<?xml encoding="UTF-8">' . $html);
        return new \DOMXPath($document);
    }
