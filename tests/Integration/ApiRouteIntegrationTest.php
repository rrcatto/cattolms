    public function testTheCatalogueIsPagedAndCarriesItsMeta(): void
    {
        $payload = $this->json($this->call('GET', '/api/v1/courses?page=1&page_size=25'));

        self::assertIsArray($payload['data']);
        self::assertArrayHasKey('meta', $payload);
        self::assertSame(1, $payload['meta']['page']);
        self::assertSame(25, $payload['meta']['page_size']);
        self::assertGreaterThan(0, $payload['meta']['total']);
