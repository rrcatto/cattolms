    /** A key is read back exactly as the site stores it: the real bundles by their codes, and nothing for a near miss. */
    public function testAKeyIsReadBackExactly(): void
    {
        $db = IntegrationContainer::get()->get(Database::class);
        $keys = IntegrationContainer::get()->get(AddressKeyRepository::class);
        $db->beginTransaction();
        try {
            $bundle = $db->fetchAssociative('SELECT id, code FROM bundles ORDER BY id LIMIT 1');
            if ($bundle !== false) {
                self::assertSame((int) $bundle['id'], $keys->bundle((string) $bundle['code']));
                foreach ([strtolower((string) $bundle['code']), (string) $bundle['id'], $bundle['code'] . '-X', ' ' . $bundle['code']] as $miss) self::assertNull($keys->bundle($miss), $miss);
                self::assertSame((string) $bundle['code'], $keys->keyOf('bundle', (int) $bundle['id']));
            }
            $creator = (int) $db->fetchOne('SELECT id FROM users ORDER BY id LIMIT 1');
            $promotion = (int) $db->fetchOne("INSERT INTO promotions (code, name, discount_type, discount_value, active, course_scope, bundle_scope, created_by, updated_by)
                VALUES ('KEYTEST_2026', 'Key test', 'percentage', 1000, false, 'all', 'none', :u, :u) RETURNING id", ['u' => $creator]);
            self::assertSame($promotion, $keys->promotion('KEYTEST_2026'));
            foreach (['keytest_2026', (string) $promotion, 'KEYTEST-2026'] as $miss) self::assertNull($keys->promotion($miss), $miss);
            self::assertSame('KEYTEST_2026', $keys->keyOf('promotion', $promotion));

            $message = (int) $db->fetchOne("INSERT INTO contact_messages (reference, reason, sender_name, sender_email, message) VALUES ('MSG-987654321', 'other', 'Key Test', 'key@example.test', 'Hello.') RETURNING id");
            self::assertSame($message, $keys->message('MSG-987654321'));
            foreach (['msg-987654321', 'MSG-0987654321', (string) $message, 'MSG-98765432'] as $miss) self::assertNull($keys->message($miss), $miss);

            foreach (['CL-2026-000000000000', 'cl-2026-3f9a2c1b7d4e', '12'] as $miss) self::assertNull($keys->certificate($miss), $miss);
            try {
                $db->executeStatement("INSERT INTO promotions (code, name, discount_type, discount_value, active, course_scope, bundle_scope, created_by, updated_by)
                    VALUES ('20261107', 'Digits', 'percentage', 1000, false, 'all', 'none', :u, :u)", ['u' => $creator]);
                self::fail('The database refuses a promotion code of digits alone.');
            } catch (\Doctrine\DBAL\Exception\DriverException) {
                $this->addToAssertionCount(1);
            }
        } finally {
            if ($db->isTransactionActive()) $db->rollBack();
        }
    }

    private function match(string $method, string $path): ?string
    {
        try {
            $match = self::router()->matchRequest(Request::create($path, $method));
            return (string) ($match['_route'] ?? '');
        } catch (ResourceNotFoundException|MethodNotAllowedException) {
            return null;
        }
    }

    private static function router(): RequestMatcherInterface
    {
        if (self::$router === null) {
            $kernel = new Kernel('test', true, (string) CliBootstrap::boot()['instance_root']);
            $kernel->boot();
            $router = $kernel->getContainer()->get('router');
            self::assertInstanceOf(RequestMatcherInterface::class, $router);
            self::$router = $router;
        }
        return self::$router;
    }
