Description:
Proves what browsing the catalogue actually returns, through both facets: a category branch and a
tag.

Two separate claims, and both are easy to get wrong in ways nothing else notices:

  - Browsing a level includes every level beneath it. Given Root > Branch > Leaf, browsing Root must
    return the courses filed at all three, browsing Branch must return two of them, and browsing Leaf
    must return one. A query that only matched `category_id = :id` passes every smoke test, renders a
    perfectly good page, and quietly tells a reader that a branch holding forty courses holds three.

  - The count and the rows describe the same population. They are two separate statements sharing one
    predicate by construction, and a faceted count that disagrees with its own list is
    indistinguishable from missing data.

The universe is the third claim, and it is the one this platform has to be most careful about,
because a category carries no seed_token at all. The label is shared between the genuine catalogue
and every generated set; what is counted under it is not. So the same category browsed in REAL and
in SEED must report different totals, and the SEED total must exclude the genuine course sitting in
the same branch.

Changelog:
2026/09/08 19:52 SAST
- Reads and writes through the Database interface rather than F3's DB\SQL.
2026/09/07 00:40 SAST
- Renamed from CategoryBrowseIntegrationTest and extended to the tag facet, which shares one filter object with the category one, so both halves of the catalogue narrow through the same tested predicate.
2026/09/06 22:30 SAST
- Created with the v0.6 category browsing surfaces.
