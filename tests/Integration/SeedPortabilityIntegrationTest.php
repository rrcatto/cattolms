use PHPUnit\Framework\TestCase;
use Throwable;

final class SeedPortabilityIntegrationTest extends TestCase
{
    private Container $container;
    private SQL $db;
    private SeedIntegrationFixture $fixture;
    private CoursePortabilityService $portability;
    private CourseRepository $courses;

    /** @var array{token:null,company:int,owner:int,learner:int,category:int,course:int} */
    private array $real;
    /** @var array{token:string,company:int,owner:int,learner:int,category:int,course:int} */
    private array $seed;

    private int $adminUserId = 0;

    protected function setUp(): void
    {
        // One container for the whole run - see IntegrationContainer. Building one per test
        // method exhausted PostgreSQL's connection slots on the VPS.
        $this->container = IntegrationContainer::get();
        $this->db = IntegrationContainer::db();
        $this->fixture = new SeedIntegrationFixture($this->db);
        /** @var CoursePortabilityService $portability */
        $portability = $this->container->get(CoursePortabilityService::class);
        $this->portability = $portability;
        /** @var CourseRepository $courses */
        $courses = $this->container->get(CourseRepository::class);
        $this->courses = $courses;

        $this->real = $this->fixture->createRealSet('Portability real');
        $this->seed = $this->fixture->createSeedSet('Portability seed');

        $suffix = $this->fixture->suffix();
        $this->adminUserId = $this->fixture->createUser(
            'Portability administrator',
            'portability-' . $suffix . '@portability-' . $suffix . '.test'
        );
        $this->fixture->grantRole($this->adminUserId, 'ADMIN');

        // Both courses need a module, so an export has something to serialise.
        foreach ([$this->real['course'], $this->seed['course']] as $courseId) {
            $this->courses->createModule($courseId, [
                'module_key' => 'm1', 'position' => 1, 'title' => 'Module one',
                'subtitle' => '', 'content_html' => '<p>Body</p>', 'summary_html' => '',
                'learning_outcomes_html' => '', 'is_review' => false, 'assessment_required' => true,
            ]);
        }
    }

    protected function tearDown(): void
    {
        $this->fixture->cleanup();
    }

    /** Runs a call expected to be refused and returns the message, or null if it succeeded. */
    private function refusalFor(callable $operation): ?string
    {
        try {
            $operation();

            return null;
        } catch (Throwable $exception) {
            return $exception->getMessage();
        }
    }

    /** Genuine portability is unchanged. */
    public function testAGenuineCourseStillExports(): void
    {
        $export = $this->portability->exportCourse($this->real['course']);

        self::assertSame('catto-learning-course', $export['format']);
        self::assertNotSame('', (string) $export['course']['slug']);
        self::assertNotSame([], $export['modules'], 'The export must carry the course content.');

        $json = $this->portability->exportCourseJson($this->real['course']);
        $decoded = (array) json_decode($json, true);
        self::assertSame('catto-learning-course', $decoded['format'] ?? null, 'The JSON form must be valid and complete.');
    }

    /**
     * A generated course cannot be exported, and the refusal names the reason.
     *
     * This is the same call a genuine administrator's Export button makes. The identity is
     * irrelevant to the outcome, which is the decision working as intended.
     */
    public function testASeedCourseCannotBeExported(): void
    {
        $refusal = $this->refusalFor(fn(): array => $this->portability->exportCourse($this->seed['course']));

        self::assertNotNull($refusal, 'Exporting a generated course must be refused.');
        self::assertStringContainsString('seed set', strtolower($refusal), 'The refusal must say why.');
    }

    /** The JSON entry point refuses too, rather than emitting a package. */
    public function testTheJsonExportEntryPointRefusesASeedCourse(): void
    {
        $refusal = $this->refusalFor(fn(): string => $this->portability->exportCourseJson($this->seed['course']));

        self::assertNotNull($refusal, 'Every export path must reach the same refusal.');
    }

    /**
     * Cloning a revision is export followed by import, so it is refused as well.
     *
     * Without this, cloning would be the laundering path the decision exists to close: a
     * generated course in, a genuine revision out.
     */
    public function testCloningARevisionOfASeedCourseIsRefused(): void
    {
        $before = (int) $this->fixture->scalar('SELECT COUNT(*)::int FROM courses WHERE seed_token IS NULL');

        $refusal = $this->refusalFor(fn(): int => $this->portability->cloneRevision($this->seed['course'], $this->adminUserId));

        self::assertNotNull($refusal, 'A generated course must not be cloneable into a genuine revision.');
        self::assertSame(
            $before,
            (int) $this->fixture->scalar('SELECT COUNT(*)::int FROM courses WHERE seed_token IS NULL'),
            'No genuine course may appear as a side effect of the refused clone.'
        );
    }

    /** Cloning a genuine course still works, and the clone is genuine. */
    public function testCloningAGenuineCourseStillWorks(): void
    {
        $cloneId = $this->portability->cloneRevision($this->real['course'], $this->adminUserId);
        $this->fixture->rememberCourse($cloneId);

        self::assertGreaterThan(0, $cloneId);
        self::assertNull(
            $this->fixture->scalar('SELECT seed_token FROM courses WHERE id = :id', [':id' => $cloneId]),
            'A revision of a genuine course is genuine.'
        );
    }

    /** A seed identity cannot start an import, at either staging entry point or at commit. */
    public function testASeedIdentityCannotImport(): void
    {
        $seedOwner = $this->seed['owner'];

        $staged = $this->refusalFor(fn(): array => $this->portability->stageImport(
            ['error' => UPLOAD_ERR_OK, 'size' => 10, 'name' => 'course.json', 'tmp_name' => ''],
            $seedOwner
        ));
        self::assertNotNull($staged, 'A generated identity must not stage an import.');
        self::assertStringContainsString('seed identity', strtolower($staged));

        $bundled = $this->refusalFor(fn(): array => $this->portability->stageBundledImport('anything.json', $seedOwner));
        self::assertNotNull($bundled, 'A generated identity must not stage a bundled import either.');
        self::assertStringContainsString('seed identity', strtolower($bundled));

        $committed = $this->refusalFor(fn(): int => $this->portability->commitImport(
            str_repeat('a', 32),
            $this->real['category'],
            $seedOwner
        ));
        self::assertNotNull($committed, 'The commit must refuse independently of staging.');
        self::assertStringContainsString('seed identity', strtolower($committed));
    }

    /**
     * A genuine identity gets past the universe guard and fails on the ordinary rules instead.
     *
     * The distinction matters: it proves the guard is refusing seed identities specifically
     * rather than refusing everyone and passing this test by accident.
     */
    public function testAGenuineIdentityPassesTheUniverseGuard(): void
    {
        $refusal = $this->refusalFor(fn(): array => $this->portability->stageImport(
            ['error' => UPLOAD_ERR_NO_FILE, 'size' => 0, 'name' => '', 'tmp_name' => ''],
            $this->adminUserId
        ));

        self::assertNotNull($refusal, 'An empty upload is still refused, but for the ordinary reason.');
        self::assertStringNotContainsString(
            'seed identity',
            strtolower($refusal),
            'A genuine administrator must not be refused as a seed identity.'
        );
    }

    /** Replacing an existing course cannot target a generated one. */
    public function testAnImportCannotReplaceASeedCourse(): void
    {
        $refusal = $this->refusalFor(fn(): int => $this->portability->commitImport(
            str_repeat('b', 32),
            $this->real['category'],
            $this->adminUserId,
            $this->seed['course']
        ));

        self::assertNotNull($refusal, 'Replacing a generated course through import must be refused.');
    }

    /**
     * No portability path produced a genuine copy of generated content.
     *
     * The count is taken across the whole table rather than against the fixture's own rows,
     * because a laundering bug would create a course nothing in this test is holding a reference
     * to, and a narrower check would miss exactly that.
     */
    public function testNoRefusedOperationLaunderedSeedContentIntoTheGenuineUniverse(): void
    {
        $before = (int) $this->fixture->scalar('SELECT COUNT(*)::int FROM courses WHERE seed_token IS NULL');
        $seedTitle = (string) $this->fixture->scalar(
            'SELECT title FROM courses WHERE id = :id',
            [':id' => $this->seed['course']]
        );

        foreach ([
            fn(): array => $this->portability->exportCourse($this->seed['course']),
            fn(): string => $this->portability->exportCourseJson($this->seed['course']),
            fn(): int => $this->portability->cloneRevision($this->seed['course'], $this->adminUserId),
        ] as $operation) {
            self::assertNotNull($this->refusalFor($operation));
        }

        self::assertSame(
            $before,
            (int) $this->fixture->scalar('SELECT COUNT(*)::int FROM courses WHERE seed_token IS NULL'),
            'The genuine universe must contain exactly as many courses as before.'
        );
        self::assertSame(
            0,
            (int) $this->fixture->scalar(
                'SELECT COUNT(*)::int FROM courses WHERE seed_token IS NULL AND title LIKE :title',
                [':title' => $seedTitle . '%']
            ),
            'Generated content must not appear in the genuine universe under any name derived from it.'
        );
    }

    /** The refusal is on the course, not on the permission the actor happens to hold. */
    public function testTheRefusalIsAboutTheCourseRatherThanTheActor(): void
    {
        $asAdmin = $this->refusalFor(fn(): array => $this->portability->exportCourse($this->seed['course']));
        $asOwner = $this->refusalFor(fn(): array => $this->portability->exportCourse($this->seed['course']));

        self::assertNotNull($asAdmin);
        self::assertSame($asAdmin, $asOwner, 'Export takes no actor: the same course is refused identically however it is asked for.');

        self::assertInstanceOf(
            InvalidArgumentException::class,
            (static function (CoursePortabilityService $service, int $courseId): Throwable {
                try {
                    $service->exportCourse($courseId);
                } catch (Throwable $exception) {
                    return $exception;
                }

                return new \RuntimeException('no exception was raised');
            })($this->portability, $this->seed['course']),
            'The refusal is an ordinary input rejection the controller can turn into a flash message.'
        );
    }
