declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\PlatformAdministrationService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Support\Uuid;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Tests\Support\IntegrationDataFixture;
use PHPUnit\Framework\TestCase;
use RuntimeException;

final class CreditTakeBackIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testOnlyFreePlacesOfACreditGivenByHandAreTakenBack(): void
    {
        $fixture = new IntegrationDataFixture($this->db);
        $suffix = $fixture->suffix();
        $admin = $fixture->createUser('Credit Admin', 'credit-admin-' . $suffix . '@example.test');
        $learner = $fixture->createUser('Credit Learner', 'learner@credit-' . $suffix . '.test');
        $company = $fixture->createCompany($admin, 'Credit Company', 'credit-' . $suffix . '.test');
        $course = $fixture->createCourse($admin, $company, 'credit-take-back-' . $suffix, 'Credit course');
        $credit = (int) $this->db->fetchOne(
            "INSERT INTO course_credits (public_id, company_id, course_id, access_period_seconds, quantity, source_type, created_by_user_id) VALUES (:p, :c, :course, 31536000, 10, 'administrator', :a) RETURNING id",
            ['p' => Uuid::v4(), 'c' => $company, 'course' => $course, 'a' => $admin]
        );
        $this->db->executeStatement("INSERT INTO course_credit_allocations (credit_id, user_id, status) VALUES (:c, :u, 'assigned')", ['c' => $credit, 'u' => $learner]);
        /** @var PlatformAdministrationService $service */
        $service = IntegrationContainer::get()->get(PlatformAdministrationService::class);

        try {
            $service->takeBackCredit($credit, 10, 'Given by mistake.', $admin);
            self::fail('A place that is assigned is never taken back.');
        } catch (RuntimeException $refused) {
            self::assertSame('It has 9 free places to take back.', $refused->getMessage());
        }
        self::assertSame('Took back 9 places. The credit holds 1 now.', $service->takeBackCredit($credit, 9, 'Given by mistake.', $admin));
        self::assertSame(1, (int) $this->db->fetchOne('SELECT quantity FROM course_credits WHERE id = :c', ['c' => $credit]));
        self::assertStringContainsString('took back 9 places. Given by mistake.', (string) $this->db->fetchOne('SELECT note FROM course_credits WHERE id = :c', ['c' => $credit]), 'The reason stays on the credit.');
    }
}
