declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Course\AssessmentService;
use CattoLearning\Course\LearningService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\{DevelopmentFixture, IntegrationContainer};
use PHPUnit\Framework\TestCase;

final class DiagnosticAttemptIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testADiagnosticAsksEveryQuestionThoughNoneIsGradedEligible(): void
    {
        $fixture = new DevelopmentFixture($this->db);
        $suffix = $fixture->suffix();
        $admin = $fixture->createUser('Diagnostic admin ' . $suffix);
        $learner = $fixture->createUser('Diagnostic learner ' . $suffix, 'diagnostic-' . $suffix . '@example.test');
        $company = $fixture->createCompany($admin, 'Diagnostic Company ' . $suffix, 'diagnostic-' . $suffix . '.example.test');
        $slug = 'diagnostic-' . $suffix;
        $course = $fixture->createCourse($admin, $company, $slug, 'Diagnostic Course ' . $suffix, 'published');
        $diagnostic = $fixture->createAssessmentItem($course, $admin, 'content');
        // As both importers leave it: a diagnostic whose questions are all marked not graded-eligible.
        $this->db->executeStatement("UPDATE course_items SET item_type = 'diagnostic' WHERE id = :id", ['id' => $diagnostic['item_id']]);
        $this->db->executeStatement('UPDATE course_item_assessments SET graded_question_count = 3 WHERE course_item_id = :id', ['id' => $diagnostic['item_id']]);
        foreach ([1, 2, 3] as $position) $fixture->createQuestion($diagnostic['item_id'], $position);
        $this->db->executeStatement('UPDATE assessment_questions SET graded_eligible = FALSE WHERE course_item_id = :id', ['id' => $diagnostic['item_id']]);
        $fixture->createEnrolment($learner, $course, $admin);
        IntegrationContainer::get()->get(LearningService::class)->start($learner, $slug);

        $session = IntegrationContainer::get()->get(AssessmentService::class)->startAttempt($learner, $slug, $diagnostic['node_id'], $diagnostic['key'], 'diagnostic');
        self::assertSame('diagnostic', $session['attempt_mode']);
        self::assertSame(3, (int) $this->db->fetchOne('SELECT COUNT(*) FROM assessment_session_questions WHERE session_id = :id', ['id' => $session['id']]), 'Every question is asked.');
    }
}
