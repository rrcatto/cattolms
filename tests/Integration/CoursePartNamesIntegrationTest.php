declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Course\CourseFile;
use CattoLearning\Course\CourseItemRepository;
use CattoLearning\Course\CourseItemService;
use CattoLearning\Course\CoursePortabilityService;
use CattoLearning\Infrastructure\Persistence\AddressKeyRepository;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Support\Address\CoursePartAddress;
use CattoLearning\Tests\Support\DevelopmentFixture;
use CattoLearning\Tests\Support\SpecificationExample;
use PHPUnit\Framework\TestCase;
use Psr\Container\ContainerInterface;

final class CoursePartNamesIntegrationTest extends TestCase
{
    private ContainerInterface $container;
    private Database $db;
    private CoursePortabilityService $portability;
    private CourseItemService $items;
    private int $admin;

    protected function setUp(): void
    {
        $this->container = CliBootstrap::boot()['container'];
        $this->db = $this->container->get(Database::class);
        $this->portability = $this->container->get(CoursePortabilityService::class);
        $this->items = $this->container->get(CourseItemService::class);
        $this->db->beginTransaction();
        $this->admin = (new DevelopmentFixture($this->db))->person('ADMIN')['id'];
        if ((int) $this->db->fetchOne("SELECT count(*) FROM courses WHERE code = 'GDN-101'") > 0) self::markTestSkipped('A GDN course is on this site.');
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) { $this->db->rollBack(); }
    }

    public function testAPartIsNamedAfterItsPlace(): void
    {
        $courseId = $this->import(SpecificationExample::html());
        $names = $this->names($courseId);
        self::assertSame(array_values(array_unique($names)), $names, 'No two parts of a course share a name.');
        foreach ($names as $name) {
            self::assertMatchesRegularExpression('#^(?:' . CoursePartAddress::REQUIREMENT . ')$#', $name, 'Every name is a part name.');
            self::assertDoesNotMatchRegularExpression('/^part-[0-9a-f]{8}$/', $name, 'Every part was named after its place, none left waiting.');
        }
        foreach (['module-1', 'module-1-presentation', 'module-1-lesson', 'module-1-summary', 'module-1-flash-cards', 'module-1-assessment', 'integrated-final-assessment'] as $expected) {
            self::assertContains($expected, $names);
        }
        $keys = $this->container->get(AddressKeyRepository::class);
        self::assertSame($this->node($courseId, 'module-1-presentation'), $keys->part($courseId, 'module-1-presentation'), 'A name finds its part.');
        self::assertNull($keys->part($courseId, 'Module-1-Presentation'), 'Only exactly.');
    }

    public function testANameHoldsALetterIsNeverAFixedWordAndIsFreeInItsCourse(): void
    {
        $courseId = $this->import(SpecificationExample::html());
        self::assertSame('part-2024', $this->partOf($this->items->addSection($courseId, ['title' => '2024'], $this->admin)));
        self::assertSame('review-section', $this->partOf($this->items->addSection($courseId, ['title' => 'Review'], $this->admin)), 'Review is the reader\'s own page.');
        self::assertSame('review-section-2', $this->partOf($this->items->addSection($courseId, ['title' => 'Review'], $this->admin)));
        $quiz = $this->items->createAndPlace($courseId, ['item_key' => 'names-quiz-' . bin2hex(random_bytes(3)), 'item_type' => 'assessment', 'title' => 'Assessment'], $this->admin);
        self::assertSame('assessment-part', $this->partOf($quiz['node']), 'Assessment is a word beside a part name.');
        foreach (CoursePartAddress::RESERVED as $word) {
            self::assertDoesNotMatchRegularExpression('#^(?:' . CoursePartAddress::REQUIREMENT . ')$#', $word, $word . ' is never a part name.');
        }
        try {
            $this->db->executeStatement('SAVEPOINT fixed_word');
            $this->db->executeStatement('UPDATE course_structure_nodes SET part_name = :name WHERE id = :id', ['name' => 'start', 'id' => $quiz['node']]);
            self::fail('The database refuses a fixed word too.');
        } catch (\Doctrine\DBAL\Exception $refused) {
            $this->db->executeStatement('ROLLBACK TO SAVEPOINT fixed_word');
            self::assertStringContainsString('course_structure_nodes_part_name_check', $refused->getMessage());
        }
    }

    public function testAPartKeepsItsNameWhenItMoves(): void
    {
        $courseId = $this->import(SpecificationExample::html());
        $deck = $this->node($courseId, 'module-1-presentation');
        $module = $this->node($courseId, 'module-1');
        $this->items->arrange($courseId, [$deck], $module, 3, $this->admin);
        self::assertSame('module-1-presentation', $this->partOf($deck), 'Moved, it keeps its name and so its address.');
        $this->items->arrange($courseId, [$deck], null, 0, $this->admin);
        $this->items->nameParts($courseId);
        self::assertSame('module-1-presentation', $this->partOf($deck), 'Out of its module too, and naming the waiting parts leaves it alone.');
    }

    public function testANameTravelsThroughItsPackage(): void
    {
        $courseId = $this->import(SpecificationExample::html());
        $deck = $this->node($courseId, 'module-1-presentation');
        $this->items->arrange($courseId, [$deck], $this->node($courseId, 'module-1'), 3, $this->admin);
        $this->container->get(CourseItemRepository::class)->renamePart($courseId, $this->node($courseId, 'module-1'), 'getting-started');
        $before = $this->names($courseId);
        $package = json_decode((string) json_encode($this->portability->exportCourse($courseId)), true);
        self::assertContains('getting-started', array_column((array) $package['structure'], 'part_name'), 'The package carries each part\'s name.');
        $this->portability->importChecked($this->portability->analysePackage($package, 'names.json'), 0, $this->admin, $courseId);
        self::assertSame($before, $this->names($courseId), 'Replaced from its package, every part keeps its name.');
    }

    public function testANameTravelsThroughItsFile(): void
    {
        $courseId = $this->import(SpecificationExample::html());
        $records = $this->container->get(CourseItemRepository::class);
        $records->renamePart($courseId, $this->node($courseId, 'module-1'), 'getting-started');
        $records->renamePart($courseId, $this->node($courseId, 'module-1-presentation'), 'what-you-will-learn');
        $before = $this->names($courseId);
        $html = $this->container->get(CourseFile::class)->fromCourse($courseId)['html'];
        self::assertStringContainsString('<meta name="cattolms:part-names" content="module-1=getting-started module-1-presentation=what-you-will-learn">', $html, 'The file names the parts its places would name otherwise.');
        $this->import($html, $courseId);
        self::assertSame($before, $this->names($courseId), 'Replaced from its file, every part keeps its name.');
        self::assertStringNotContainsString('cattolms:part-names', $this->container->get(CourseFile::class)->fromCourse($this->import(str_replace(['content="GDN-101"', '<h1>Growing Vegetables in Small Spaces</h1>', ' module-1=getting-started module-1-presentation=what-you-will-learn'], ['content="GDN-102"', '<h1>Growing Vegetables Again</h1>', ''], preg_replace('/<meta name="cattolms:part-names"[^>]*>\n?/', '', $html) ?? $html)))['html'], 'A course whose parts all have their places\' names says nothing more.');
    }

    private function import(string $html, ?int $replace = null): int
    {
        $file = (string) tempnam(sys_get_temp_dir(), 'part-names');
        file_put_contents($file, $html);
        try {
            $analysis = $this->portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => 'names.html', 'tmp_name' => $file], $this->admin);
            return $this->portability->commitImport((string) $analysis['import_key'], 0, $this->admin, $replace);
        } finally {
            @unlink($file);
        }
    }

    /** @return list<string> every part's name, in course order */
    private function names(int $courseId): array
    {
        return array_map(static fn(array $row): string => (string) $row['part_name'], $this->items->availability($courseId, null, false));
    }

    private function partOf(int $node): string
    {
        return (string) $this->db->fetchOne('SELECT part_name FROM course_structure_nodes WHERE id = :id', ['id' => $node]);
    }

    private function node(int $courseId, string $name): int
    {
        return (int) $this->db->fetchOne('SELECT id FROM course_structure_nodes WHERE course_id = :course AND part_name = :name', ['course' => $courseId, 'name' => $name]);
    }
}
