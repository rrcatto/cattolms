Description:
Each part of a course has a short readable name, its address in the reader and the public preview (owner, 2026-11-06:
no row id in an address; the part name approved the same day, "yes, do it that way"), inside a transaction:
- a part is named after its place: a numbered module "module-1", an item its place without the course's code
  ("module-1-presentation", "integrated-final-assessment");
- a name is free in its course, holds a letter and is never a word beside it in an address;
- a part keeps its name when it moves;
- a name travels with the course, through its package and through its HTML file, so a course replaced keeps every part's
  address, a name its place would not give it included.

