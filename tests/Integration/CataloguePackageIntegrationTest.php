    /**
     * @param array<string,mixed> $catalogue
     * @param array<string,array<string,mixed>> $courses
     * @param array<string,array{0:string,1:string}> $resources
     * @param array<string,string> $extra
     */
    private function zip(array $catalogue, array $courses, array $resources, array $extra = []): string
    {
        $path = $this->files[] = (string) tempnam(sys_get_temp_dir(), 'pkg');
        $zip = new ZipArchive();
        $zip->open($path, ZipArchive::OVERWRITE);
        $zip->addFromString('catalogue.json', (string) json_encode($catalogue));
        foreach ($courses as $name => $course) $zip->addFromString('courses/' . $name . '.json', (string) json_encode($course));
        foreach ($resources as $publicId => [$filename, $bytes]) $zip->addFromString('resources/' . $publicId . '/' . $filename, $bytes);
        foreach ($extra as $name => $bytes) $zip->addFromString($name, $bytes);
        $zip->close();
        return $path;
    }

    private static function uuid(): string
    {
        $hex = bin2hex(random_bytes(16));
        return substr($hex, 0, 8) . '-' . substr($hex, 8, 4) . '-4' . substr($hex, 13, 3) . '-a' . substr($hex, 17, 3) . '-' . substr($hex, 20, 12);
    }
