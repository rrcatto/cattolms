    public function testANewCourseComesInWholeAndTheSamePackageAgainChangesNothing(): void
    {
        $code = 'PKG-' . strtoupper(substr($this->suffix, 0, 6));
        $resource = self::uuid();
        $zip = $this->zip($this->catalogue([$code]), [$code => $this->course($code, 'pkg-course-' . $this->suffix, $resource)], [$resource => ['guide-' . $this->suffix . '.txt', "A guide.\n"]]);

        $plan = $this->package->plan($this->package->stageFile($zip, 'catalogue.zip', $this->admin));
        self::assertSame(['new' => 1, 'update' => 0, 'unchanged' => 0, 'skip' => 0], $plan['counts'], 'The review finds one new course, its file brought by the package.');
        self::assertSame([2, 1, 1], [count($plan['catalogue']['categories_new']), count($plan['catalogue']['tags_new']), $plan['files_new']]);
        self::assertSame('Category: ' . $this->path(), $plan['courses'][0]['changes'][0]);

        $report = $this->package->apply($plan['key'], ['prices' => true, 'publish' => true], $this->admin);
        self::assertSame([1, 0, 1], [$report['counts']['imported'], $report['counts']['failed'], $report['files_installed']], json_encode($report['courses']) ?: '');
        $course = $this->courses->findByCode($code);
        self::assertNotNull($course, 'The course is known by its code.');
        $id = (int) $course['id'];
        self::assertSame(['pkg-course-' . $this->suffix, 'published', 4242, self::COVER], [$course['slug'], $course['status'], (int) $course['catalogue_position'], $course['cover_svg']],
            'It has its address, cover and position, and is published as it was where it came from.');
        self::assertSame('Pkg child ' . $this->suffix, $this->db->fetchOne('SELECT name FROM course_categories WHERE id = :id', ['id' => (int) $course['category_id']]));
        self::assertSame(['Pkg tag ' . $this->suffix], $this->db->fetchFirstColumn('SELECT t.name FROM course_tags ct JOIN tags t ON t.id = ct.tag_id WHERE ct.course_id = :c', ['c' => $id]));
        $price = $this->courses->priceVariants($id)[0];
        self::assertSame([95000, 125000, 31536000, true], [(int) $price['price_minor_units'], (int) $price['was_price_minor_units'], (int) $price['access_period_seconds'], (bool) $price['is_default']],
            'A new course takes the package\'s prices (owner, 2026-10-23: 4B).');
        self::assertSame($resource, $this->db->fetchOne('SELECT r.public_id::text FROM course_items ci JOIN resources r ON r.id = ci.resource_id WHERE ci.item_key = :k', ['k' => 'pkg-' . $this->suffix . '-guide']),
            'Its file is installed with the public id it had, and its item uses it.');

        $again = $this->package->plan($this->package->stageFile($zip, 'catalogue.zip', $this->admin));
        self::assertSame(['new' => 0, 'update' => 0, 'unchanged' => 1, 'skip' => 0], $again['counts'], 'The same package again finds nothing to change.');
        self::assertSame([[], [], 0], [$again['catalogue']['categories_new'], $again['catalogue']['tags_new'], $again['files_new']]);
        $twice = $this->package->apply($again['key'], [], $this->admin);
        self::assertSame([0, 1], [$twice['counts']['imported'], $twice['counts']['unchanged']]);
        self::assertCount(1, $this->courses->priceVariants($id), 'A course already here is never priced again.');

        // A tag removed and the price changed on this site: the package puts the tag back, never the price.
        IntegrationContainer::get()->get(CourseService::class)->setCourseTagsByName($id, [], $this->admin);
        $this->db->executeStatement('UPDATE course_price_variants SET price_minor_units = 99900 WHERE course_id = :c', ['c' => $id]);
        $changed = $this->package->plan($this->package->stageFile($zip, 'catalogue.zip', $this->admin));
        self::assertSame(['update', ['Tags: Pkg tag ' . $this->suffix]], [$changed['courses'][0]['action'], $changed['courses'][0]['changes']]);
        $this->package->apply($changed['key'], [], $this->admin);
        self::assertSame(99900, (int) $this->courses->priceVariants($id)[0]['price_minor_units']);

        // The site's own export holds the course with its code and settings, listed in catalogue.json.
        $export = $this->files[] = $this->package->export($this->admin);
        $archive = new ZipArchive();
        self::assertTrue($archive->open($export));
        $exported = json_decode((string) $archive->getFromName('courses/' . $code . '.json'), true);
        $catalogue = json_decode((string) $archive->getFromName('catalogue.json'), true);
        $file = $archive->getFromName('resources/' . $resource . '/guide-' . $this->suffix . '.txt');
        $archive->close();
        self::assertSame(['2.1', $code, $this->path(), ['Pkg tag ' . $this->suffix], self::COVER, 4242, '999.00', '1250.00', 'published'],
            [$exported['schema_version'], $exported['course']['code'], $exported['catalogue']['category'], $exported['catalogue']['tags'], $exported['catalogue']['cover'],
                $exported['catalogue']['position'], $exported['catalogue']['prices'][0]['price'], $exported['catalogue']['prices'][0]['was_price'], $exported['catalogue']['status']]);
        self::assertContains($code, $catalogue['courses']);
        self::assertSame("A guide.\n", $file, 'The files the courses use go in the package.');
    }

    public function testACourseThePackageCannotMatchIsLeftOutWithTheReason(): void
    {
        $owner = $this->fixture->createUser('Package course owner');
        $company = $this->fixture->createCompany($owner, 'Package provider ' . $this->suffix, $this->suffix . '.package.example.test');
        $taken = 'pkg-taken-' . $this->suffix;
        $this->fixture->createCourse($owner, $company, $taken, 'Already here', 'published');
        $code = 'PKN-' . strtoupper(substr($this->suffix, 0, 6));
        $courses = [
            'no-code' => array_replace_recursive($this->course('', 'pkg-nocode-' . $this->suffix), ['course' => ['code' => '']]),
            $code => $this->course($code, $taken),
        ];
        $plan = $this->package->plan($this->package->stageFile($this->zip($this->catalogue([]), $courses, []), 'catalogue.zip', $this->admin));
        self::assertSame(['skip', 'skip'], array_column($plan['courses'], 'action'));
        $reasons = array_column($plan['courses'], 'reason', 'file');
        self::assertStringStartsWith('It has no course code', $reasons['courses/no-code.json']);
        self::assertStringContainsString('The address /courses/' . $taken . ' is another course\'s here: “Already here”', $reasons['courses/' . $code . '.json']);
        self::assertStringContainsString('give it the code ' . $code . ' on its Details tab', $reasons['courses/' . $code . '.json']);
        $report = $this->package->apply($plan['key'], [], $this->admin);
        self::assertSame([0, 2], [$report['counts']['imported'], $report['counts']['skipped']]);
        self::assertNull($this->courses->findByCode($code), 'Nothing is made for a course left out.');
    }

    public function testAnExportHoldsOnlyTheTickedCoursesAndTheirCategoriesAndTags(): void
    {
        // Owner, 2026-10-23: "Unselected courses and categories and tags which do not apply to the select courses must not
        // be included in the export"; a link to an unselected related course is left out too.
        $first = 'PKA-' . strtoupper(substr($this->suffix, 0, 6));
        $second = 'PKB-' . strtoupper(substr($this->suffix, 0, 6));
        $other = 'Pkg other ' . $this->suffix;
        $catalogue = $this->catalogue([$first, $second]);
        $catalogue['categories'][] = ['name' => $other, 'slug' => 'pkg-other-' . $this->suffix, 'icon' => self::ICON];
        $catalogue['tags'][] = ['name' => 'Pkg other tag ' . $this->suffix, 'icon' => self::ICON];
        $courses = [
            $first => array_replace_recursive($this->course($first, 'pkg-first-' . $this->suffix), ['catalogue' => ['related' => [$second]]]),
            $second => array_replace($this->course($second, 'pkg-second-' . $this->suffix), ['catalogue' => array_replace($this->course($second, 'x')['catalogue'], ['category' => $other, 'tags' => ['Pkg other tag ' . $this->suffix]])]),
        ];
        $courses[$second]['course']['title'] = 'Second package course ' . $this->suffix;
        $plan = $this->package->plan($this->package->stageFile($this->zip($catalogue, $courses, []), 'catalogue.zip', $this->admin));
        $this->package->apply($plan['key'], ['prices' => true, 'publish' => false], $this->admin);
        $firstId = (int) $this->courses->findByCode($first)['id'];
        self::assertCount(1, $this->courses->relatedCourseIds($firstId), 'The two are related on the site.');

        $export = $this->files[] = $this->package->export($this->admin, [$firstId]);
        $archive = new ZipArchive();
        self::assertTrue($archive->open($export));
        $names = [];
        for ($i = 0; $i < $archive->numFiles; $i++) $names[] = (string) $archive->getNameIndex($i);
        $catalogueFile = json_decode((string) $archive->getFromName('catalogue.json'), true);
        $exported = json_decode((string) $archive->getFromName('courses/' . $first . '.json'), true);
        $archive->close();
        sort($names);
        self::assertSame(['catalogue.json', 'courses/' . $first . '.json'], $names, 'Only the ticked course is in the package.');
        self::assertSame([$first], $catalogueFile['courses']);
        self::assertSame([['Pkg root ' . $this->suffix, ['Pkg child ' . $this->suffix]]], array_map(static fn(array $node): array => [$node['name'], array_column($node['children'] ?? [], 'name')], $catalogueFile['categories']),
            'Only its category, with the category above it.');
        self::assertSame(['Pkg tag ' . $this->suffix], array_column($catalogueFile['tags'], 'name'), 'Only its tags.');
        self::assertSame([], $exported['catalogue']['related'], 'The related course that was not ticked is left out.');

        $taxonomy = json_decode($this->package->exportCategoriesAndTags($this->admin, [$firstId]), true);
        self::assertSame([['Pkg root ' . $this->suffix], ['Pkg tag ' . $this->suffix]], [array_column($taxonomy['categories'], 'name'), array_column($taxonomy['tags'], 'name')],
            'The categories and tags file follows the ticks.');
        $everything = json_decode($this->package->exportCategoriesAndTags($this->admin, []), true);
        self::assertContains($other, array_column($everything['categories'], 'name'), 'With none ticked it holds every category.');
        self::assertContains('Pkg other tag ' . $this->suffix, array_column($everything['tags'], 'name'));
        $this->expectExceptionMessage('Tick the courses to put in the catalogue package.');
        $this->package->export($this->admin, []);
    }

