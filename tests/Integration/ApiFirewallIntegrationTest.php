declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Api\ApiScope;
use CattoLearning\Application\CliBootstrap;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Kernel;
use CattoLearning\Tests\Support\DevelopmentFixture;
use PHPUnit\Framework\TestCase;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\Response;

final class ApiFirewallIntegrationTest extends TestCase
{
    private DevelopmentFixture $fixture;
    private Database $db;
    private int $userId = 0;
    /** @var list<string> */
    private array $tokenPublicIds = [];

    protected function setUp(): void
    {
        $container = CliBootstrap::boot()['container'];
        /** @var Database $db */
        $db = $container->get(Database::class);
        $this->db = $db;
        $this->fixture = new DevelopmentFixture($db);

        $suffix = $this->fixture->suffix();
        $this->userId = $this->fixture->createUser('QA api caller ' . $suffix, 'qa-api-' . $suffix . '@example.test');
        $this->db->executeStatement(
            "INSERT INTO cattophp_account_roles (account_id, role_key, granted_at) VALUES (CAST(:user_id AS TEXT), 'STUDENT', NOW())",
            ['user_id' => $this->userId]
        );
    }

    protected function tearDown(): void
    {
        foreach ($this->tokenPublicIds as $publicId) {
            $this->db->executeStatement('DELETE FROM cattophp_api_tokens WHERE CAST(public_id AS text) = :id', ['id' => $publicId]);
        }
        $this->db->executeStatement('DELETE FROM cattophp_account_roles WHERE account_id = CAST(:id AS TEXT)', ['id' => $this->userId]);
        $this->fixture->cleanup();
    }

    public function testAValidTokenReadsItsOwnProfile(): void
    {
        $response = $this->call($this->issue([ApiScope::PROFILE_READ]));

        self::assertSame(200, $response->getStatusCode());
        self::assertSame('application/json; charset=utf-8', $response->headers->get('Content-Type'));
        self::assertSame('no-store, private', $response->headers->get('Cache-Control'));

        $payload = json_decode((string) $response->getContent(), true, 512, JSON_THROW_ON_ERROR);
        self::assertSame('qa-api-' . $this->emailSuffix() . '@example.test', $payload['data']['primary_email'] ?? null);
        self::assertContains('STUDENT', $payload['data']['roles'] ?? []);
        self::assertSame([ApiScope::PROFILE_READ], $payload['data']['scopes'] ?? null);
        self::assertArrayHasKey('token_id', $payload['data']);
    }

    public function testNoTokenIsRefusedAsUnauthenticated(): void
    {
        $response = $this->call(null);

        self::assertSame(401, $response->getStatusCode());
        self::assertSame('Bearer', $response->headers->get('WWW-Authenticate'));
        self::assertSame(
            ['status' => 401, 'code' => 'unauthenticated', 'message' => 'A Bearer API token is required.'],
            $this->error($response)
        );
    }

    public function testAnUnknownTokenIsRefusedAsUnauthenticated(): void
    {
        $response = $this->call('not-a-real-token');

        self::assertSame(401, $response->getStatusCode());
        self::assertSame(
            ['status' => 401, 'code' => 'unauthenticated', 'message' => 'The API token is invalid, expired or revoked.'],
            $this->error($response)
        );
    }

    /** The account may view its profile, but this token was not issued to do it. */
    public function testATokenWithoutTheScopeIsForbidden(): void
    {
        $response = $this->call($this->issue([ApiScope::COURSES_READ]));

        self::assertSame(403, $response->getStatusCode());
        self::assertSame('forbidden', $this->error($response)['code']);
    }

    /** The token carries the scope, but the account behind it holds no permissions at all. */
    public function testATokenWhoseAccountLacksThePermissionIsForbidden(): void
    {
        $this->db->executeStatement('DELETE FROM cattophp_account_roles WHERE account_id = CAST(:id AS TEXT)', ['id' => $this->userId]);
        $response = $this->call($this->issue([ApiScope::PROFILE_READ]));

        self::assertSame(403, $response->getStatusCode());
        self::assertSame('forbidden', $this->error($response)['code']);
    }

    /** @param list<string> $scopes */
    private function issue(array $scopes): string
    {
        $container = CliBootstrap::boot()['container'];
        /** @var \CattoPHP\Api\ApiTokens $tokens */
        $tokens = $container->get(\CattoPHP\Api\ApiTokens::class);
        $made = $tokens->create((string) $this->userId, 'QA firewall token', $scopes, 3600);
        $this->tokenPublicIds[] = $made['public_id'];

        return $made['token'];
    }

    private function call(?string $rawToken): Response
    {
        $server = $rawToken === null ? [] : ['HTTP_AUTHORIZATION' => 'Bearer ' . $rawToken];
        $kernel = new Kernel('test', true, (string) CliBootstrap::boot()['instance_root']);
        $kernel->boot();

        return $kernel->handle(Request::create('/api/v1/me', 'GET', [], [], [], $server));
    }

    /** @return array<string,mixed> */
    private function error(Response $response): array
    {
        return json_decode((string) $response->getContent(), true, 512, JSON_THROW_ON_ERROR)['error'];
    }

    private function emailSuffix(): string
    {
        $email = (string) $this->db->fetchOne(
            'SELECT email FROM user_emails WHERE user_id = :id AND is_primary = TRUE',
            ['id' => $this->userId]
        );

        return substr($email, strlen('qa-api-'), -strlen('@example.test'));
    }
}
