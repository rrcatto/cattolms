The API firewall's contract: who is let in, who is refused, and in what document.

Architectural boundary: integration test. It issues real tokens against the development database
and drives the real kernel.

The three refusals matter as much as the success, and for different reasons. A missing token and a
bad token must be told apart from a token that is simply not allowed to do this - 401 against 403 -
because a client retries one and not the other. A token with the permission but not the scope, and a
token with the scope but not the permission, must both be refused: they are the two orthogonal
questions the platform insists on asking separately, and a firewall that answered only one of them
would let an API call do something the equivalent web operation refuses, or let a token act outside
what it was issued for.

