    private function place(CurrentUser $buyer, array $titles, ?string $code = null, array $bundleOffers = [], string $method = 'dummy', bool $email = false): int
    {
        foreach ($titles as $title) $this->orders->changeCart($buyer, $this->course[$title]['variant']);
        foreach ($bundleOffers as $offer) $this->orders->changeBundle($buyer, $offer);
        if ($code !== null) $this->promotions->apply($buyer, $code);
        $cart = $this->orders->cart($buyer);
        return $this->orders->place($buyer, (int) $cart['id'], (string) $cart['quote'], BillingFixture::person($buyer->displayName, '7 Original Street'), true, ['payment_method' => $method, 'invoice_email' => $email]);
    }

