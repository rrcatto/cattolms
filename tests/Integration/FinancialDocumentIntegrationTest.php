    public function testANewDesignDrawsDocumentsIssuedFromThenOnAndNeverOnesAlreadyIssued(): void
    {
        $before = $this->place($this->buyer('Early Buyer'), ['Conveyancing 1']);
        $old = $this->only($before, 'invoice');
        $oldPdf = $this->documents->pdf($old);
