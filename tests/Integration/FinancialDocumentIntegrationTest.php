    public function testEachRefundIssuesItsOwnCreditNoteAgainstTheInvoice(): void
    {
        $buyer = $this->buyer('Refunded Buyer');
        $orderId = $this->place($buyer, ['Conveyancing 1'], $this->promotion(1000));
        $this->payments->purchase($buyer, $orderId, Uuid::v4(), 'demo_success');
        $item = $this->records->items($orderId)[0];
        $refunds = new RefundAdministrationService($this->records, new TransactionManager($this->db), IntegrationContainer::get()->get(TransitionService::class), $this->clock,
            new AnalyticsEventRecorder(new AnalyticsEventRepository($this->db), $this->clock), $this->access, $this->documents);
        $first = $refunds->approve($this->admin(), $orderId, (int) $item['id'], Uuid::v4(), 'goodwill', 'A first goodwill amount.', 1, 30000);
        $firstNote = $this->db->fetchAssociative("SELECT * FROM commerce_documents WHERE source_key=:k", ['k' => 'refund:' . $first]) ?: [];
        $firstHtml = $this->documents->render($firstNote)->html;
        $refunds->approve($this->admin(), $orderId, (int) $item['id'], Uuid::v4(), 'service_failure', 'The rest of what was paid.', 1, 78000);

        $notes = array_values(array_filter($this->records->documents($orderId), static fn(array $d): bool => $d['kind'] === 'credit_note'));
        self::assertCount(2, $notes, 'One credit note per refund.');
        $invoice = $this->only($orderId, 'invoice');
        foreach ([[$notes[0], 30000, 'Goodwill'], [$notes[1], 78000, 'Service failure']] as [$note, $credited, $basis]) {
            $data = $this->data($note);
            self::assertSame([$credited, $credited, 108000, 12000, 120000, $basis, $invoice['number']],
                [$data['credit_note.amount']['minor'], $data['items'][0]['credited']['minor'], $data['items'][0]['paid']['minor'], $data['items'][0]['discount']['minor'],
                    $data['items'][0]['price']['minor'], $data['credit_note.basis'], $data['credit_note.invoice_number']]);
        }
        self::assertSame($firstHtml, $this->documents->render($notes[0])->html, 'A later refund does not change an earlier credit note.');
    }

    public function testTheDatabaseRefusesADocumentThatNamesAnotherKindOfTemplate(): void
    {
        $orderId = $this->place($this->buyer('Guarded Buyer'), ['Conveyancing 1']);
        $invoice = $this->only($orderId, 'invoice');
        $certificate = (int) $this->db->fetchOne("SELECT v.id FROM document_template_versions v JOIN document_templates t ON t.id=v.template_id WHERE t.document_type='certificate' LIMIT 1");
        foreach (['a certificate version' => [(int) $invoice['template_id'], $certificate, 1], 'the wrong number' => [(int) $invoice['template_id'], (int) $invoice['template_version_id'], 99]] as $case => [$template, $version, $number]) {
            $this->db->executeStatement('SAVEPOINT guard');
            try {
                $this->records->insertDocument($orderId, 'receipt', 'REC-TEST-' . bin2hex(random_bytes(3)), 'test:' . bin2hex(random_bytes(4)), [], ['x' => 1],
                    ['template_id' => $template, 'template_version_id' => $version, 'template_version_number' => $number], '2026-10-08T10:00:00+02:00');
                self::fail('The database accepts ' . $case);
            } catch (Throwable $refused) {
                self::assertStringContainsString('must name the published version', $refused->getMessage(), $case);
            } finally {
                $this->db->executeStatement('ROLLBACK TO SAVEPOINT guard');
            }
        }
    }

