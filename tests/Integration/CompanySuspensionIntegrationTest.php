declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\PlatformAdministrationService;
use CattoLearning\Auth\AuthService;
use CattoLearning\Infrastructure\Persistence\AuthSessionRepository;
use CattoLearning\Infrastructure\Persistence\CompanyRepository;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Infrastructure\Persistence\UserRepository;
use CattoLearning\Support\Token;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Tests\Support\IntegrationDataFixture;
use Psr\Container\ContainerInterface;
use PHPUnit\Framework\TestCase;
use RuntimeException;

final class CompanySuspensionIntegrationTest extends TestCase
{
    private ContainerInterface $container;
    private Database $db;
    private IntegrationDataFixture $fixture;
    private PlatformAdministrationService $administration;
    private AuthSessionRepository $sessions;
    private UserRepository $users;
    private CompanyRepository $companies;

    private int $adminUserId = 0;
    private int $learnerId = 0;
    private int $companyAdminId = 0;
    private int $otherLearnerId = 0;
    private int $companyId = 0;
    private int $otherCompanyId = 0;
    private string $suffix = '';

    protected function setUp(): void
    {
        $this->container = IntegrationContainer::get();
        $this->db = IntegrationContainer::db();
        $this->fixture = new IntegrationDataFixture($this->db);

        /** @var PlatformAdministrationService $administration */
        $administration = $this->container->get(PlatformAdministrationService::class);
        $this->administration = $administration;
        /** @var AuthSessionRepository $sessions */
        $sessions = $this->container->get(AuthSessionRepository::class);
        $this->sessions = $sessions;
        /** @var UserRepository $users */
        $users = $this->container->get(UserRepository::class);
        $this->users = $users;
        /** @var CompanyRepository $companies */
        $companies = $this->container->get(CompanyRepository::class);
        $this->companies = $companies;

        $_SESSION = [];
        $this->suffix = $this->fixture->suffix();

        $this->adminUserId = $this->fixture->createUser('Platform administrator', 'admin-' . $this->suffix . '@admin-' . $this->suffix . '.test');

        $this->companyId = $this->fixture->createCompany($this->adminUserId, 'Suspendable ' . $this->suffix, 'susp-' . $this->suffix . '.test');
        $this->otherCompanyId = $this->fixture->createCompany($this->adminUserId, 'Untouched ' . $this->suffix, 'untouched-' . $this->suffix . '.test');

        $this->learnerId = $this->fixture->createUser('Learner', 'learner-' . $this->suffix . '@susp-' . $this->suffix . '.test');
        $this->fixture->addCompanyMember($this->companyId, $this->learnerId);

        $this->companyAdminId = $this->fixture->createUser('Company administrator', 'coadmin-' . $this->suffix . '@susp-' . $this->suffix . '.test');
        $this->fixture->addCompanyMember($this->companyId, $this->companyAdminId, 'administrator');

        $this->otherLearnerId = $this->fixture->createUser('Other learner', 'other-' . $this->suffix . '@untouched-' . $this->suffix . '.test');
        $this->fixture->addCompanyMember($this->otherCompanyId, $this->otherLearnerId);

        // The platform administrator is a member of the suspendable company on purpose: the
        // exemption has to hold for somebody actually inside it, not merely for an outsider.
        $this->fixture->addCompanyMember($this->companyId, $this->adminUserId, 'administrator');
        $this->fixture->grantRole($this->adminUserId, 'ADMIN');
    }

    protected function tearDown(): void
    {
        // Leave the fixture's companies active so cleanup is never blocked by our own suspension.
        if ($this->companyId > 0) {
            $this->db->executeStatement("UPDATE companies SET status = 'active' WHERE id = :id", ['id' => $this->companyId]);
        }
        $_SESSION = [];
        $this->fixture->cleanup();
    }

    private function startSession(int $userId): string
    {
        $raw = 'session-' . $userId . '-' . $this->suffix;
        $this->sessions->create($userId, Token::hash($raw), 3600, 'ip', 'agent');

        return $raw;
    }

    private function liveSessions(int $userId): int
    {
        return (int) $this->fixture->scalar(
            'SELECT COUNT(*)::int AS value FROM auth_sessions WHERE user_id = :id AND revoked_at IS NULL',
            ['id' => $userId]
        );
    }

    private function suspend(): void
    {
        $this->administration->setCompanyStatus($this->companyId, 'disabled', $this->adminUserId);
    }

    private function reinstate(): void
    {
        $this->administration->setCompanyStatus($this->companyId, 'active', $this->adminUserId);
    }

    // --- the suspension itself ---------------------------------------------------------------------

    /** An active company's learner is unaffected: the baseline the other tests are measured against. */
    public function testAnActiveCompanysLearnerIsUnaffected(): void
    {
        $this->startSession($this->learnerId);

        self::assertFalse($this->users->hasSuspendedCompany($this->learnerId));
        self::assertSame(1, $this->liveSessions($this->learnerId));
    }

    /** Suspending ends the learner's live sessions immediately. */
    public function testSuspendingEndsExistingSessionsAtOnce(): void
    {
        $this->startSession($this->learnerId);
        $this->startSession($this->companyAdminId);

        $this->suspend();

        self::assertSame(0, $this->liveSessions($this->learnerId), 'A learner must not keep using an old session.');
        self::assertSame(0, $this->liveSessions($this->companyAdminId), 'Nor may the company administrator.');
    }

    /** Suspension is visible to the sign-in path for both the learner and the company administrator. */
    public function testSuspensionBlocksBothOrdinaryRoles(): void
    {
        $this->suspend();

        self::assertTrue($this->users->hasSuspendedCompany($this->learnerId));
        self::assertTrue($this->users->hasSuspendedCompany($this->companyAdminId));
    }

    /** The central request boundary refuses a session that outlived the sweep. */
    public function testASurvivingSessionIsRefusedAtTheRequestBoundary(): void
    {
        $this->suspend();

        // A session created after the sweep - the case a revoke-only design would miss entirely.
        $raw = $this->startSession($this->learnerId);
        self::assertSame(1, $this->liveSessions($this->learnerId), 'The fixture must start from a live session.');

        $session = $this->sessions->findActive(Token::hash($raw));
        self::assertNotNull($session, 'The row itself is still valid; policy is what refuses it.');
        self::assertTrue(
            in_array($session['company_suspended'] ?? false, [true, 1, '1', 't', 'true'], true),
            'The session lookup must report the suspension so AuthService can act on it.'
        );
    }

    // --- the platform administrator exemption -------------------------------------------------------

    /** A platform administrator inside the suspended company keeps their session. */
    public function testAPlatformAdministratorIsNotSignedOutBySuspension(): void
    {
        $this->startSession($this->adminUserId);

        $this->suspend();

        self::assertSame(
            1,
            $this->liveSessions($this->adminUserId),
            'Suspending a company must never be a way to lock the installation away from its owner.'
        );
    }

    /** And may still sign in while it is suspended. */
    public function testAPlatformAdministratorMaySignInDuringSuspension(): void
    {
        $this->suspend();

        // The fact is true of them - they are a member of a suspended company - but the policy
        // exempts them, which is why the two are kept apart.
        self::assertTrue($this->users->hasSuspendedCompany($this->adminUserId));
        self::assertContains('ADMIN', array_map('strtoupper', $this->container->get(\CattoLearning\Infrastructure\Persistence\RoleRepository::class)->roles($this->adminUserId)));
    }

    // --- blast radius --------------------------------------------------------------------------------

    /** Suspending one company leaves another company's members entirely alone. */
    public function testSuspendingOneCompanyDoesNotAffectAnother(): void
    {
        $this->startSession($this->otherLearnerId);

        $this->suspend();

        self::assertSame(1, $this->liveSessions($this->otherLearnerId));
        self::assertFalse($this->users->hasSuspendedCompany($this->otherLearnerId));
    }

    /** Nothing is deleted: memberships and the identity survive a suspension. */
    public function testSuspensionDeletesNothing(): void
    {
        $before = (int) $this->fixture->scalar(
            "SELECT COUNT(*)::int AS value FROM company_users WHERE company_id = :id AND status = 'active'",
            ['id' => $this->companyId]
        );

        $this->suspend();

        self::assertSame($before, (int) $this->fixture->scalar(
            "SELECT COUNT(*)::int AS value FROM company_users WHERE company_id = :id AND status = 'active'",
            ['id' => $this->companyId]
        ), 'Suspension is not removal.');
        self::assertSame('active', (string) $this->fixture->scalar('SELECT status AS value FROM users WHERE id = :id', ['id' => $this->learnerId]));
    }

    // --- reinstatement --------------------------------------------------------------------------------

    /** Re-enabling restores access with no repair step. */
    public function testReinstatingRestoresAccess(): void
    {
        $this->suspend();
        self::assertTrue($this->users->hasSuspendedCompany($this->learnerId));

        $this->reinstate();

        self::assertFalse($this->users->hasSuspendedCompany($this->learnerId), 'An eligible member signs in again.');
        self::assertFalse($this->companies->userCompanyIsSuspended($this->learnerId));
    }

    /** Somebody disabled in their own right stays disabled when the company returns. */
    public function testAnIndependentlyDisabledUserStaysDisabledAfterReinstatement(): void
    {
        $this->users->setStatus($this->learnerId, 'disabled');

        $this->suspend();
        $this->reinstate();

        self::assertSame(
            'disabled',
            (string) $this->fixture->scalar('SELECT status AS value FROM users WHERE id = :id', ['id' => $this->learnerId]),
            'Company status and account status are separate decisions.'
        );
    }

    // --- the System Company ---------------------------------------------------------------------------

    /** The System Company cannot be suspended, and the refusal is at repository level. */
    public function testTheSystemCompanyCannotBeSuspended(): void
    {
        $system = $this->companies->systemCompany();
        self::assertNotNull($system, 'The REAL System Company must exist.');

        $this->expectException(RuntimeException::class);
        $this->expectExceptionMessageMatches('/System Company cannot be disabled/i');
        $this->administration->setCompanyStatus((int) $system['id'], 'disabled', $this->adminUserId);
    }

    // --- the message ------------------------------------------------------------------------------------

    /** The suspended-company message explains the situation rather than blaming the account. */
    public function testTheSuspensionMessageIsAboutTheCompanyNotTheAccount(): void
    {
        $this->suspend();

        self::assertTrue($this->companies->userCompanyIsSuspended($this->learnerId));
        self::assertStringContainsString('suspended', AuthService::SUSPENDED_COMPANY_MESSAGE);
        self::assertStringNotContainsString(
            'not attached to an active company',
            AuthService::SUSPENDED_COMPANY_MESSAGE,
            'The old wording read as a fault in the reader\'s own account.'
        );
    }
