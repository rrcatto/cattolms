    /**
     * Sends a form the site refuses and returns the page the reader then sees: the page drawn again in answer (a 422), or
     * the one they are sent back to, drawn as their browser asks for it.
     *
     * @param array{0:class-string,1:string,2?:array<string,mixed>} $form the action the form is sent to, with its address's values
     * @param array<string,mixed> $typed
     * @param array{0:class-string,1:string,2?:array<string,mixed>,3?:array<string,mixed>}|null $back the page sent back to
     */
    private function refused(CurrentUser $user, array $form, array $typed, ?array $back, string $message): string
    {
        unset($_SESSION['flash']);
        $sent = InProcessPage::run($user, $form[0], $form[1], $form[2] ?? [], ['csrf' => $_SESSION['csrf']] + $typed);
        if ($sent['location'] === null) {
            self::assertSame(422, $sent['status'], 'A refused form drawn again says it was refused.');
            if ($message !== '') self::assertStringContainsString(htmlspecialchars($message, ENT_QUOTES), $sent['body']);
            return $sent['body'];
        }
        $this->sentTo = $sent['location'];
        $said = is_array($_SESSION['flash'] ?? null) ? (array) end($_SESSION['flash']) : [];
        self::assertSame('danger', $said['type'] ?? null, 'The form was refused: ' . json_encode($said));
        if ($message !== '') self::assertStringContainsString($message, (string) ($said['message'] ?? ''));
        self::assertNotNull($back, 'The form sent the reader to ' . $sent['location']);
        $page = InProcessPage::run($user, $back[0], $back[1], $back[2] ?? [], null, $back[3] ?? []);
        self::assertSame(200, $page['status']);
        return $page['body'];
    }

    /** The form sent to $action on the page, from its start tag to its end. */
    private function form(string $page, string $action): string
    {
        $at = strpos($page, 'action="' . $action . '" method="post"');
        self::assertNotFalse($at, 'The page has a form sent to ' . $action);
        $start = (int) strrpos(substr($page, 0, $at), '<form');
        $end = strpos($page, '</form>', $at);
        self::assertNotFalse($end);
        return substr($page, $start, $end - $start);
    }

    private static function assertField(string $form, string $name, string $value, string $why = ''): void
    {
        $value = htmlspecialchars($value, ENT_QUOTES);
        self::assertMatchesRegularExpression('/<input(?=[^>]*\sname="' . preg_quote($name, '/') . '")(?=[^>]*\svalue="' . preg_quote($value, '/') . '")[^>]*>/', $form, $why !== '' ? $why : $name . ' keeps "' . $value . '".');
    }

    private static function assertTextarea(string $form, string $name, string $value): void
    {
        self::assertMatchesRegularExpression('/<textarea[^>]*\sname="' . preg_quote($name, '/') . '"[^>]*>' . preg_quote(htmlspecialchars($value, ENT_QUOTES), '/') . '<\/textarea>/', $form, $name . ' keeps what was typed.');
    }

    private static function assertSelected(string $form, string $name, string $value, string $why = ''): void
    {
        self::assertMatchesRegularExpression('/<select[^>]*\sname="' . preg_quote($name, '/') . '"[^>]*>(?:(?!<\/select>).)*<option value="' . preg_quote($value, '/') . '"[^>]*\sselected/s', $form, $why !== '' ? $why : $name . ' keeps ' . $value . ' chosen.');
    }

    private static function assertTicked(string $form, string $name, string $value, string $why = ''): void
    {
        self::assertMatchesRegularExpression(self::tick($name, $value), $form, $why !== '' ? $why : $name . ' stays ticked at ' . $value . '.');
    }

    private static function assertNotTicked(string $form, string $name, string $value, string $why = ''): void
    {
        self::assertDoesNotMatchRegularExpression(self::tick($name, $value), $form, $why !== '' ? $why : $name . ' stays unticked at ' . $value . '.');
    }

    private static function tick(string $name, string $value): string
    {
        return '/<input(?=[^>]*\sname="' . preg_quote($name, '/') . '")(?=[^>]*\svalue="' . preg_quote($value, '/') . '")(?=[^>]*\schecked)[^>]*>/';
    }

    private static function assertWindowOpen(string $page, string $id): void
    {
        self::assertMatchesRegularExpression('/<div class="cl-ui-modal" id="' . preg_quote($id, '/') . '"[^>]*\sdata-modal-open/', $page, 'The window ' . $id . ' opens again, holding what was typed.');
    }

    /** A company with its founding Company Administrator, as every company has. */
    private function company(): int
    {
        return $this->company ??= $this->fixture->createCompany($this->admin->id, 'Typed Company ' . $this->suffix, 'typed-' . $this->suffix . '.example.test');
    }

    /** @return array{0:int,1:string} a published course sold for 12 months, and its code */
    private function pricedCourse(): array
    {
        $course = $this->fixture->createCourse($this->admin->id, $this->company(), 'typed-priced-' . $this->suffix, 'Typed Priced Course', 'published');
        $this->fixture->createPriceVariant($course, $this->admin->id, 31536000, 120000, true);
        return [$course, (string) $this->db->fetchOne('SELECT code FROM courses WHERE id = :id', ['id' => $course])];
    }
