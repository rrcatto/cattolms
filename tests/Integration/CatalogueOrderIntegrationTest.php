declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Course\CourseRepository;
use CattoLearning\Course\CourseService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\{DevelopmentFixture, IntegrationContainer};
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class CatalogueOrderIntegrationTest extends TestCase
{
    private Database $db;
    private CourseService $service;
    private CourseRepository $courses;
    private int $user;
    /** @var array<string,int> */
    private array $id = [];

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
        $this->service = IntegrationContainer::get()->get(CourseService::class);
        $this->courses = IntegrationContainer::get()->get(CourseRepository::class);
        $fixture = new DevelopmentFixture($this->db);
        $suffix = $fixture->suffix();
        $this->user = $fixture->createUser('Order administrator ' . $suffix, 'order-' . $suffix . '@example.test');
        $company = $fixture->createCompany($this->user, 'Order Company ' . $suffix, 'order-' . $suffix . '.example.test');
        // Numbered below every other course, so they lead the whole order.
        foreach (['A' => 10, 'B' => 20, 'C' => 30] as $key => $position) {
            $this->id[$key] = $fixture->createCourse($this->user, $company, 'order-' . strtolower($key) . '-' . $suffix, 'Order ' . $key);
            $this->courses->setCataloguePosition($this->id[$key], $position);
        }
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testACourseTakesTheMidpointBetweenItsNewNeighbours(): void
    {
        self::assertSame([$this->id['C'] => 15], $this->service->arrangeInCatalogue($this->id['C'], $this->id['A'], $this->user));
        self::assertSame(['A' => 10, 'C' => 15, 'B' => 20], $this->leading(3));
        self::assertSame([$this->id['B'] => 5], $this->service->arrangeInCatalogue($this->id['B'], null, $this->user), 'First: half the next one\'s number.');
        self::assertSame(['B' => 5, 'A' => 10, 'C' => 15], $this->leading(3));
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM audit_log WHERE event_key = 'course.catalogue_arranged' AND user_id = :user AND metadata->>'course_id' = :course",
            ['user' => $this->user, 'course' => (string) $this->id['B']]));
    }

    public function testWithNoNumberBetweenThemTheListIsNumberedAgainInHundreds(): void
    {
        $this->courses->setCataloguePosition($this->id['B'], 11);
        $changed = $this->service->arrangeInCatalogue($this->id['C'], $this->id['A'], $this->user);
        self::assertSame(['A' => 100, 'C' => 200, 'B' => 300], $this->leading(3), 'Numbered again from the top, every course still in order.');
        self::assertSame(100, $changed[$this->id['A']]);
        $order = $this->courses->catalogueOrderForUpdate();
        $numbers = array_values(array_filter(array_column($order, 'position'), static fn(?int $p): bool => $p !== null));
        $sorted = $numbers;
        sort($sorted);
        self::assertSame($sorted, $numbers, 'No course jumped ahead of another.');
        self::assertSame(count($numbers), count(array_unique($numbers)));
    }

    public function testTheMenuMovesUpDownAndToTheTop(): void
    {
        $this->service->moveInCatalogue($this->id['C'], 'up', $this->user);
        self::assertSame(['A' => 10, 'C' => 15, 'B' => 20], $this->leading(3));
        $this->service->moveInCatalogue($this->id['A'], 'down', $this->user);
        self::assertSame(['C' => 15, 'A' => 17, 'B' => 20], $this->leading(3));
        $this->service->moveInCatalogue($this->id['B'], 'top', $this->user);
        self::assertSame(['B' => 7, 'C' => 15, 'A' => 17], $this->leading(3));
        $this->expectException(InvalidArgumentException::class);
        $this->service->moveInCatalogue($this->id['B'], 'up', $this->user);
    }

    public function testAMoveNamesRealCourses(): void
    {
        $this->expectException(InvalidArgumentException::class);
        $this->service->arrangeInCatalogue($this->id['A'], 999999999, $this->user);
    }

    /** @return array<string,int|null> the first courses of the whole order, by their key here */
    private function leading(int $count): array
    {
        $keys = array_flip($this->id);
        $out = [];
        foreach (array_slice($this->courses->catalogueOrderForUpdate(), 0, $count) as $row) $out[$keys[$row['id']] ?? (string) $row['id']] = $row['position'];
        return $out;
    }
}
