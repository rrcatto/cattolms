declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Course\CourseItemService;
use CattoLearning\Course\CoursePortabilityService;
use CattoLearning\Course\CourseRepository;
use CattoLearning\Course\Package\CoursePackage;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\DevelopmentFixture;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;
use ZipArchive;

final class CoursePackageImportIntegrationTest extends TestCase
{
    private const EXAMPLE = __DIR__ . '/../Fixtures/course-package/GDN-101';

    private Database $db;
    private CoursePortabilityService $portability;
    private CourseItemService $items;
    private CourseRepository $courses;
    private int $admin;
    /** @var list<string> */
    private array $files = [];

    protected function setUp(): void
    {
        $container = CliBootstrap::boot()['container'];
        $this->db = $container->get(Database::class);
        $this->portability = $container->get(CoursePortabilityService::class);
        $this->items = $container->get(CourseItemService::class);
        $this->courses = $container->get(CourseRepository::class);
        $this->db->beginTransaction();
        $fixture = new DevelopmentFixture($this->db);
        $this->admin = $fixture->createUser('Package importer ' . $fixture->suffix());
        if ($this->db->fetchOne("SELECT id FROM courses WHERE code = 'GDN-101'") !== false) { self::markTestSkipped('A course GDN-101 is already on this site.'); }
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) { $this->db->rollBack(); }
        foreach ($this->files as $file) { if (is_file($file)) { unlink($file); } }
    }

    /** @param array<string,string|null> $changes files to replace (or, null, to leave out) */
    private function zip(array $changes = []): string
    {
        $path = (string) tempnam(sys_get_temp_dir(), 'package') . '.zip';
        $this->files[] = $path;
        $zip = new ZipArchive();
        $zip->open($path, ZipArchive::CREATE | ZipArchive::OVERWRITE);
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator(self::EXAMPLE, \FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            $relative = substr((string) $file, strlen(self::EXAMPLE) + 1);
            if (array_key_exists($relative, $changes)) { continue; }
            $zip->addFile((string) $file, 'GDN-101/' . $relative);
        }
        foreach ($changes as $relative => $content) { if ($content !== null) { $zip->addFromString('GDN-101/' . $relative, $content); } }
        $zip->close();
        return $path;
    }

    /** @return array<string,mixed> */
    private function stage(string $zip): array
    {
        return $this->portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($zip), 'name' => 'GDN-101.zip', 'tmp_name' => $zip], $this->admin);
    }

    public function testTheWorkedExampleBecomesACourseOfModuleSections(): void
    {
        self::assertTrue(CoursePackage::isPackage($this->zip()));
        $analysis = $this->stage($this->zip());
        self::assertSame('3.0', $analysis['package_version']);
        self::assertContains('modules/m1: the video is the example\'s placeholder', $analysis['warnings'], 'The specification\'s guidance reaches the review.');
        $courseId = $this->portability->commitImport((string) $analysis['import_key'], 0, $this->admin);
        $course = $this->courses->findById($courseId);
        self::assertSame('GDN-101', $course['code']);
        self::assertSame('Growing Vegetables in Small Spaces', $course['title']);
        self::assertStringContainsString('[grading-scale]', (string) $course['introduction_html']);

        $rows = $this->items->availability($courseId, null, false);
        $shape = array_map(static fn(array $row): string => str_repeat('  ', (int) $row['depth'] - 1) . ($row['node_type'] === 'section' ? 'section ' . ($row['section_number'] ?? '-') : $row['part']), $rows);
        self::assertSame(['slide_deck', 'section 1', '  presentation', '  video', '  lesson', '  summary', '  flashcards', '  practical', '  assessment', 'final'], array_map(static fn(string $line): string => $line === 'presentation' ? 'slide_deck' : $line, $shape));
        $byKey = [];
        foreach ($rows as $row) { if ($row['node_type'] === 'item') { $byKey[(string) $row['item_key']] = $row; } }
        self::assertTrue($byKey['gdn-101-trailer']['public_preview'], 'The trailer opens the public preview.');
        self::assertSame('trailer', $byKey['gdn-101-trailer']['type_config']['kind']);
        $deck = $byKey['gdn-101-m1-presentation']['type_config'];
        self::assertCount(7, $deck['slides']);
        self::assertStringStartsWith('<svg', $deck['slides'][4]['picture'], 'The picture slide keeps its drawing.');
        self::assertSame('EXAMPLE0001', $byKey['gdn-101-m1-video']['type_config']['youtube_id']);
        self::assertSame(8, $byKey['gdn-101-m1-video']['minutes']);
        self::assertSame('summary', $byKey['gdn-101-m1-summary']['type_config']['presentation_role']);
        self::assertCount(15, $byKey['gdn-101-m1-flashcards']['type_config']['cards']);
        self::assertStringContainsString('<section class="answer">', (string) $byKey['gdn-101-m1-practical']['type_config']['answer_html']);
        self::assertSame('graded', $byKey['gdn-101-m1-assessment']['assessment_role']);
        self::assertSame('final', $byKey['gdn-101-final']['assessment_role']);
        self::assertSame(15, (int) $this->db->fetchOne('SELECT COUNT(*) FROM assessment_questions WHERE course_item_id = :id', ['id' => $byKey['gdn-101-m1-assessment']['course_item_id']]));
        self::assertSame(4, (int) $this->db->fetchOne('SELECT COUNT(*) FROM course_grade_bands WHERE course_id = :id', ['id' => $courseId]));
        self::assertEqualsCanonicalizing(['Gardening', 'Food growing'], array_map('strval', $this->db->fetchFirstColumn('SELECT t.name FROM course_tags a JOIN tags t ON t.id = a.tag_id WHERE a.course_id = :id', ['id' => $courseId])));

        // Exported again, the course carries what makes it this structure.
        $export = $this->portability->exportCourse($courseId);
        $section = array_values(array_filter($export['structure'], static fn(array $node): bool => $node['node_type'] === 'section'))[0];
        self::assertTrue($section['numbered']);
        $exported = array_column($export['course_items'], null, 'item_key');
        self::assertSame(45, $exported['gdn-101-m1-lesson']['estimated_minutes']);
        self::assertSame($deck['slides'], $exported['gdn-101-m1-presentation']['type_config']['slides'], 'The slides travel as they are, ids and all.');
        self::assertSame([], $exported['gdn-101-m1-presentation']['narrations']);
    }

    public function testAPackageThatBreaksTheSpecificationIsRefusedWithItsErrors(): void
    {
        $module = (array) json_decode((string) file_get_contents(self::EXAMPLE . '/modules/m1/module.json'), true);
        $module['title'] = 'Module 1: Soil';
        $module['assessment']['questions'][0]['a'] = 5;
        $module['presentation']['slides'][0]['layout'] = 'banner';
        try {
            $this->stage($this->zip(['final.json' => null, 'modules/m1/module.json' => (string) json_encode($module), 'modules/m1/practical-answer.html' => '<section class="answer"><h3>Task 1</h3></section>']));
            self::fail('The broken package was accepted.');
        } catch (InvalidArgumentException $refused) {
            $message = $refused->getMessage();
            foreach (['final.json is missing', 'must not hold the module\'s number', 'layout "banner" is not one of', 'points at an option that is not there', 'one section class="answer" per task'] as $expected) {
                self::assertStringContainsString($expected, $message);
            }
        }
    }
}
