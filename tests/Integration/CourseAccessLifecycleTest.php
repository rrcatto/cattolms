    public function testAccessClockStartsOnlyOnceWhenLearnerStartsCourse(): void
    {
        $container = CliBootstrap::boot()['container'];
        /** @var SQL $db */
        $db = $container->get(SQL::class);
        /** @var LearningService $learning */
        $learning = $container->get(LearningService::class);
        $fixture = new DevelopmentFixture($db);
        $suffix = $fixture->suffix();

        try {
            $adminId = $fixture->createUser('QA access admin ' . $suffix);
            $learnerId = $fixture->createUser('QA access learner ' . $suffix);
            $companyId = $fixture->createCompany($adminId, 'QA Access ' . $suffix, 'qa-access-' . $suffix . '.example.test');
            $slug = 'qa-access-' . $suffix;
            $courseId = $fixture->createCourse($adminId, $companyId, $slug, 'QA Access Course ' . $suffix, 'published');
            $enrolmentId = $fixture->createEnrolment($learnerId, $courseId, $adminId, 2592000);

            $before = $db->exec('SELECT status,started_at,expires_at FROM course_enrolments WHERE id=:id', [':id' => $enrolmentId])[0];
            self::assertSame('assigned', (string) $before['status']);
            self::assertSame('', trim((string) ($before['started_at'] ?? '')));
            self::assertSame('', trim((string) ($before['expires_at'] ?? '')));

            $learning->start($learnerId, DataUniverse::Real, $slug);
            $started = $db->exec('SELECT status,started_at,expires_at FROM course_enrolments WHERE id=:id', [':id' => $enrolmentId])[0];
            self::assertSame('active', (string) $started['status']);
            $startedAt = (string) $started['started_at'];
            $expiresAt = (string) $started['expires_at'];
            self::assertNotSame('', trim($startedAt));
            self::assertNotSame('', trim($expiresAt));
            $delta = (strtotime($expiresAt) ?: 0) - (strtotime($startedAt) ?: 0);
            self::assertSame(2592000, $delta);

            $learning->start($learnerId, DataUniverse::Real, $slug);
            $again = $db->exec('SELECT started_at,expires_at FROM course_enrolments WHERE id=:id', [':id' => $enrolmentId])[0];
            self::assertSame($startedAt, (string) $again['started_at']);
            self::assertSame($expiresAt, (string) $again['expires_at']);
        } finally {
            $fixture->cleanup();
        }
    }

