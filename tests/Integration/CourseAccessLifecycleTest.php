    public function testExpiredAccessIsRejectedAndPersistedAsExpired(): void
    {
        $container = CliBootstrap::boot()['container'];
        /** @var SQL $db */
        $db = $container->get(SQL::class);
        /** @var LearningService $learning */
        $learning = $container->get(LearningService::class);
        $fixture = new DevelopmentFixture($db);
        $suffix = $fixture->suffix();

        try {
            $adminId = $fixture->createUser('QA expired admin ' . $suffix);
            $learnerId = $fixture->createUser('QA expired learner ' . $suffix);
            $companyId = $fixture->createCompany($adminId, 'QA Expired ' . $suffix, 'qa-expired-' . $suffix . '.example.test');
            $slug = 'qa-expired-' . $suffix;
            $courseId = $fixture->createCourse($adminId, $companyId, $slug, 'QA Expired Course ' . $suffix, 'published');
            $enrolmentId = $fixture->createEnrolment($learnerId, $courseId, $adminId, 86400, false, 'active');
            $db->exec(
                "UPDATE course_enrolments SET started_at=NOW()-INTERVAL '2 days',expires_at=NOW()-INTERVAL '1 day' WHERE id=:id",
                [':id' => $enrolmentId]
            );

            try {
                $learning->courseHome($learnerId, DataUniverse::Real, $slug);
                self::fail('Expected expired course access to be rejected.');
            } catch (InvalidArgumentException $e) {
                self::assertSame('Your access period for this course has expired.', $e->getMessage());
            }

            $row = $db->exec('SELECT status FROM course_enrolments WHERE id=:id', [':id' => $enrolmentId])[0];
            self::assertSame('expired', (string) $row['status']);
        } finally {
            $fixture->cleanup();
        }
    }
