        self::assertMatchesRegularExpression('/^The course started on [0-9]{1,2} [A-Z][a-z]+ [0-9]{4}\. A started course is not refunded\.$/', $refusals[0]);
        try {
            $refunds->approve($admin, $orderId, (int) $item['id'], Uuid::v4(), 'voluntary', 'Customer request', 1, 50000);
            self::fail('A started course is not refunded.');
        } catch (RuntimeException $exception) {
            self::assertStringStartsWith(self::REFUSED . ' The course started on ', $exception->getMessage());
            self::assertStringEndsWith('To approve it anyway, record an override reason.', $exception->getMessage());
        }
        try {
            $refunds->approve($admin, $orderId, (int) $item['id'], Uuid::v4(), 'voluntary', 'Customer request', 1, 50000, 'ok');
            self::fail('An override needs a written reason.');
        } catch (RuntimeException $exception) {
            self::assertSame('Record why the Refund Policy is overridden, in 5 to 2,000 characters.', $exception->getMessage());
        }
        self::assertSame(0, $this->records->refundedAmount($orderId), 'A refused refund writes nothing.');
        self::assertSame('fulfilled', $this->records->order($orderId)['state']);

        $refundId = $refunds->approve($admin, $orderId, (int) $item['id'], Uuid::v4(), 'service_failure', 'Customer request', 1, 50000, 'The course video would not play for this learner.');
