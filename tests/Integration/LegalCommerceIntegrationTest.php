    public function testAnOrderIsNotPlacedUntilTheTermsAndTheRefundPolicyAreAccepted(): void
    {
        $buyer = $this->buyer();
        $this->ready($buyer, 'eft');
        $this->orders->changeCart($buyer, $this->course['A']['variant']);
        $cart = $this->orders->cart($buyer);

        $review = InProcessPage::run($buyer, CommerceController::class, 'checkout', ['step' => 'review'])['body'];
        self::assertMatchesRegularExpression('/<input type="checkbox" name="accept_terms" value="yes" required>/', $review, 'The tick box is required.');
        self::assertStringContainsString('I have read and accept the <a href="/terms" target="_blank" rel="noopener">Terms and Conditions</a> and the <a href="/refunds" target="_blank" rel="noopener">Refund Policy</a>.', $review, 'Both documents are named and linked beside it.');

        $form = ['csrf' => $_SESSION['csrf'], 'cart_id' => (string) $cart['id'], 'quote' => (string) $cart['quote']];
        $refused = InProcessPage::run($buyer, CommerceController::class, 'place', [], $form);
        self::assertSame('/checkout/review', $refused['location']);
        self::assertSame(['type' => 'danger', 'message' => 'Accept the Terms and Conditions and the Refund Policy before placing your order.'], end($_SESSION['flash']));
        self::assertSame(0, $this->records->orderCount($buyer->id), 'Nothing is placed without acceptance.');

        foreach ([fn() => $this->checkout($buyer)->place($buyer, (int) $cart['id'], (string) $cart['quote'], false),
            fn() => $this->orders->place($buyer, (int) $cart['id'], (string) $cart['quote'], BillingFixture::person('Buyer'), false)] as $attempt) {
            try {
                $attempt();
                self::fail('The services refuse too, whatever the browser sends.');
            } catch (RuntimeException $exception) {
                self::assertSame('Accept the Terms and Conditions and the Refund Policy before placing your order.', $exception->getMessage());
            }
        }
        self::assertSame(0, $this->records->orderCount($buyer->id));

        $placed = InProcessPage::run($buyer, CommerceController::class, 'place', [], $form + ['accept_terms' => 'yes']);
        self::assertMatchesRegularExpression('#^/account/orders/[0-9]+$#', (string) $placed['location']);
        self::assertSame(1, $this->records->orderCount($buyer->id));
    }

