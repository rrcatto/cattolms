    public function testALearnerAsksForARefundOnTheOrderAndAdminDecides(): void
    {
        $buyer = $this->buyer();
        $this->orders->changeCart($buyer, $this->course['A']['variant']);
        $orderId = $this->buy($buyer);
        $item = $this->records->items($orderId)[0];
        $admin = $this->admin();
        $requests = $this->requests();

        $page = InProcessPage::run($buyer, CommerceController::class, 'order', ['id' => (string) $orderId])['body'];
        self::assertStringContainsString('Ask for a refund', $page, 'The order page offers the request');
        self::assertStringContainsString('The course started on ', $page, 'and says what the rule says');
        self::assertStringContainsString('If the course is faulty, is not as described or cannot be provided, tell us below', $page, 'and how to report a faulty course.');

        InProcessPage::run($buyer, CommerceController::class, 'refundRequest', ['id' => (string) $orderId], ['csrf' => $_SESSION['csrf'], 'item_id' => (string) $item['id'], 'reason' => 'The videos in module 2 do not play.', 'destination' => 'wallet']);
        self::assertSame('success', end($_SESSION['flash'])['type']);
        $request = $this->db->fetchAssociative('SELECT * FROM commerce_refund_requests WHERE order_id=:o', ['o' => $orderId]) ?: [];
        self::assertSame(['requested', 'wallet', 'The videos in module 2 do not play.'], [$request['status'], $request['destination'], $request['customer_reason']]);
        self::assertStringStartsWith('The course started on ', (string) $request['rule_refusals'], 'The rule\'s verdict when the learner asked is kept with the request.');
        try {
            $requests->requestForOwnOrder($buyer, $orderId, (int) $item['id'], 'wallet', 'Asking a second time.');
            self::fail('One open request per line.');
        } catch (RuntimeException $exception) {
            self::assertSame('A refund request for this line is already waiting for a decision.', $exception->getMessage());
        }
        try {
            $requests->requestForOwnOrder($this->buyer(), $orderId, (int) $item['id'], 'wallet', 'Not my order at all.');
            self::fail('Only the purchaser asks.');
        } catch (RuntimeException $exception) {
            self::assertSame('You can ask about refunds of your own orders only.', $exception->getMessage());
        }

        $queue = $requests->queue();
        self::assertSame([(int) $request['id']], array_map(static fn(array $row): int => (int) $row['id'], array_values(array_filter($queue, static fn(array $row): bool => (int) $row['order_id'] === $orderId))));
        $requests->refuse($admin, (int) $request['id'], 'The videos play: we checked them in three browsers.');
        self::assertSame('refused', $this->db->fetchOne('SELECT status FROM commerce_refund_requests WHERE id=:id', ['id' => $request['id']]));
        self::assertStringContainsString('Your refund request was refused on ', InProcessPage::run($buyer, CommerceController::class, 'order', ['id' => (string) $orderId])['body']);

        $second = $requests->requestForOwnOrder($buyer, $orderId, (int) $item['id'], 'wallet', 'Module 3 is missing entirely.');
        try {
            $requests->approve($admin, $second, 'service_failure', 'Module 3 was missing.');
            self::fail('The request is refused by the rule, so approving it is an override.');
        } catch (RuntimeException $exception) {
            self::assertStringStartsWith(self::REFUSED, $exception->getMessage());
        }
        $refundId = $requests->approve($admin, $second, 'service_failure', 'Module 3 was missing.', 'The course was not as described.');
        self::assertSame(['approved', $refundId], [$this->db->fetchOne('SELECT status FROM commerce_refund_requests WHERE id=:id', ['id' => $second]), (int) $this->db->fetchOne('SELECT id FROM commerce_refunds WHERE refund_request_id=:r', ['r' => $second])]);
        self::assertSame(50000, WalletFixture::wallets($this->db, $this->clock)->balance(WalletOwner::person($buyer->id), 'ZAR'), 'The refund went to the wallet the learner chose.');
        self::assertSame('refunded', $this->records->order($orderId)['state']);
    }

    private function buyer(): CurrentUser
    {
        $id = $this->fixture->createUser('Legal buyer', 'legal-buyer-' . bin2hex(random_bytes(5)) . '@example.test');
        return new CurrentUser($id, Uuid::v4(), 'buyer-' . $id . '@example.invalid', 'Buyer ' . $id, ['STUDENT'], self::PERMISSIONS, Uuid::v4());
    }

    private function admin(): CurrentUser
    {
        $id = $this->fixture->createUser('Legal administrator', 'legal-admin-' . bin2hex(random_bytes(5)) . '@example.test');
        return new CurrentUser($id, Uuid::v4(), 'admin-' . $id . '@example.invalid', 'Administrator', ['ADMIN'], (new PermissionCatalog())->keys(), Uuid::v4());
    }

    private function ready(CurrentUser $buyer, string $method = 'dummy'): void
    {
        $this->billing->saveOwn($buyer, BillingFixture::personFields('Legal Buyer'));
        $_SESSION['checkout'][$buyer->id] = ['profile_confirmed' => true, 'payment_method' => $method, 'method_token' => $method === 'dummy' ? 'demo_success' : '', 'invoice_email' => false, 'payment_key' => Uuid::v4()];
    }

    /** Places the buyer's cart and pays it with the simulated card. */
    private function buy(CurrentUser $buyer): int
    {
        $this->ready($buyer);
        $cart = $this->orders->cart($buyer);
        return (int) $this->checkout($buyer)->place($buyer, (int) $cart['id'], (string) $cart['quote'], true, true);
    }

    private function checkout(CurrentUser $buyer): CheckoutService
    {
        $auth = clone IntegrationContainer::get()->get(AuthService::class);
        (new \ReflectionProperty(AuthService::class, 'currentUser'))->setValue($auth, $buyer);
        return new CheckoutService($auth, $this->orders, $this->records, $this->payments, $this->fulfilment, new TransactionManager($this->db), $this->analytics(), $this->billing);
    }

    private function refunds(): RefundAdministrationService
    {
        $container = IntegrationContainer::get();
        return new RefundAdministrationService($this->records, new TransactionManager($this->db), $container->get(TransitionService::class), $this->clock, $this->analytics(), $this->access, $container->get(FinancialDocuments::class), WalletFixture::wallets($this->db, $this->clock), WalletFixture::settings($this->db));
    }

    private function requests(): RefundRequestService
    {
        return new RefundRequestService($this->records, $this->refunds(), new TransactionManager($this->db), $this->clock, IntegrationContainer::get()->get(AdministrationRepository::class));
    }

    private function analytics(): AnalyticsEventRecorder
    {
        return new AnalyticsEventRecorder(new AnalyticsEventRepository($this->db), $this->clock);
    }
