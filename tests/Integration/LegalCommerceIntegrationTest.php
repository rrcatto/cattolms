        self::assertSame('STITCH-RF-0001', ($this->records->refund($refundId) ?? [])['payout_reference']);
        self::assertSame(47900, (int) $this->db->fetchOne("SELECT SUM(amount_minor) FROM commerce_ledger_entries WHERE refund_id=:r AND kind='refund_paid'", ['r' => $refundId]));
