        $entitlement = $this->db->fetchAssociative('SELECT e.access_started_at, e.activation_deadline_at, ce.status, ce.started_at FROM commerce_entitlements e JOIN course_enrolments ce ON ce.id=e.enrolment_id WHERE e.order_item_id=:i', ['i' => $item['id']]) ?: [];
