    public function testARefundIsRefusedOnceTheLearnerHasStartedUnlessAdminOverridesWithAReason(): void
    {
        $buyer = $this->buyer();
        $this->orders->changeCart($buyer, $this->course['A']['variant']);
        $orderId = $this->buy($buyer);
        $item = $this->records->items($orderId)[0];
        $refunds = $this->refunds();
        $admin = $this->admin();
        self::assertSame([], $refunds->ruleRefusals($this->records->order($orderId), $item), 'Paid a moment ago and not started: the rule allows a refund.');

        $this->access->start($this->enrolment((int) $item['id']));
        $refusals = $refunds->ruleRefusals($this->records->order($orderId), $item);
        self::assertCount(1, $refusals);
        self::assertStringStartsWith('The learner started the course on ', $refusals[0]);
        try {
            $refunds->approve($admin, $orderId, (int) $item['id'], Uuid::v4(), 'voluntary', 'Customer request', 1, 50000);
            self::fail('A started course is not refunded.');
        } catch (RuntimeException $exception) {
            self::assertStringStartsWith(self::REFUSED . ' The learner started the course on ', $exception->getMessage());
            self::assertStringEndsWith('To approve it anyway, record an override reason.', $exception->getMessage());
        }
        try {
            $refunds->approve($admin, $orderId, (int) $item['id'], Uuid::v4(), 'voluntary', 'Customer request', 1, 50000, 'ok');
            self::fail('An override needs a written reason.');
        } catch (RuntimeException $exception) {
            self::assertSame('Record why the Refund Policy is overridden, in 5 to 2,000 characters.', $exception->getMessage());
        }
        self::assertSame(0, $this->records->refundedAmount($orderId), 'A refused refund writes nothing.');
        self::assertSame('fulfilled', $this->records->order($orderId)['state']);

        $refundId = $refunds->approve($admin, $orderId, (int) $item['id'], Uuid::v4(), 'goodwill', 'Customer request', 1, 50000, 'The course video would not play for this learner.');
        $refund = $this->db->fetchAssociative('SELECT * FROM commerce_refunds WHERE id=:id', ['id' => $refundId]) ?: [];
        self::assertSame($refusals[0], $refund['policy_refusal'], 'What the rule refused is kept with the refund');
        self::assertSame('The course video would not play for this learner.', $refund['override_reason'], 'with the written reason for overriding it.');
        $audit = CommerceRepository::decode((string) $this->db->fetchOne("SELECT payload FROM commerce_audit_events WHERE order_id=:o AND event='refund.approved'", ['o' => $orderId]));
        self::assertSame(['The course video would not play for this learner.', $refusals[0]], [$audit['override_reason'], $audit['policy_refusal']]);
        self::assertSame('refunded', $this->records->order($orderId)['state'], 'The refund itself works as any refund does.');
        self::assertSame('revoked', $this->db->fetchOne('SELECT state FROM commerce_entitlements WHERE order_item_id=:i', ['i' => $item['id']]));

        $page = InProcessPage::run($admin, PaymentAdministrationController::class, 'order', ['id' => (string) $orderId])['body'];
        self::assertStringContainsString('Refund Policy override', $page, 'The order page says an override was used');
        self::assertStringContainsString('Override reason: The course video would not play for this learner.', $page, 'and why.');
        self::assertStringContainsString(htmlspecialchars($refusals[0], ENT_QUOTES), $page);

        $this->db->executeStatement('SAVEPOINT refund_history');
        try {
            $this->db->executeStatement("UPDATE commerce_refunds SET override_reason='Changed afterwards.' WHERE id=:id", ['id' => $refundId]);
            self::fail('Refund records are append-only.');
        } catch (\Doctrine\DBAL\Exception) {
            $this->db->executeStatement('ROLLBACK TO SAVEPOINT refund_history');
        }
    }

    public function testARefundIsRefusedOnceSevenDaysHavePassedSinceThePurchase(): void
    {
        $buyer = $this->buyer();
        $this->orders->changeCart($buyer, $this->course['A']['variant']);
        $orderId = $this->buy($buyer);
        $item = $this->records->items($orderId)[0];
        $refunds = $this->refunds();
        $admin = $this->admin();

        $this->clock->modify('+7 days -1 second');
        $within = $refunds->approve($admin, $orderId, (int) $item['id'], Uuid::v4(), 'voluntary', 'Customer request', 1, 10000, 'A reason nobody needed.');
        self::assertSame([null, null], array_values($this->db->fetchAssociative('SELECT policy_refusal, override_reason FROM commerce_refunds WHERE id=:id', ['id' => $within]) ?: []), 'Inside the rule nothing is recorded as an override.');

        $this->clock->modify('+1 second');
        try {
            $refunds->approve($admin, $orderId, (int) $item['id'], Uuid::v4(), 'voluntary', 'Customer request', 1, 40000);
            self::fail('Seven days after the purchase there is no refund.');
        } catch (RuntimeException $exception) {
            self::assertStringStartsWith(self::REFUSED . ' 7 days have passed since the purchase on ', $exception->getMessage());
        }
        self::assertSame(10000, $this->records->refundedAmount($orderId));

        $late = $refunds->approve($admin, $orderId, (int) $item['id'], Uuid::v4(), 'voluntary', 'Customer request', 1, 40000, 'The request reached us on day six.');
        $refund = $this->db->fetchAssociative('SELECT policy_refusal, override_reason FROM commerce_refunds WHERE id=:id', ['id' => $late]) ?: [];
        self::assertStringStartsWith('7 days have passed since the purchase on ', (string) $refund['policy_refusal']);
        self::assertSame('The request reached us on day six.', $refund['override_reason']);
        self::assertSame('refunded', $this->records->order($orderId)['state']);
    }

    public function testStartingAnyCourseOfABundleEndsTheRefundForTheWholeBundle(): void
    {
        $bundle = BundleFixture::create($this->db, $this->owner, [$this->course['A']['id'], $this->course['B']['id'], $this->course['C']['id']], 120000);
        $refunds = $this->refunds();
        $admin = $this->admin();

        $starter = $this->buyer();
        $this->orders->changeBundle($starter, $bundle['offer']);
        $started = $this->buy($starter);
        $line = $this->records->items($started)[0];
        $this->access->start((int) $this->db->fetchOne('SELECT e.enrolment_id FROM commerce_entitlements e JOIN course_enrolments ce ON ce.id=e.enrolment_id WHERE e.order_item_id=:i AND ce.course_id=:c', ['i' => $line['id'], 'c' => $this->course['B']['id']]));
        try {
            $refunds->approve($admin, $started, (int) $line['id'], Uuid::v4(), 'voluntary', 'Customer request', 1, 120000);
            self::fail('One started course ends the refund for the whole bundle.');
        } catch (RuntimeException $exception) {
            self::assertStringStartsWith(self::REFUSED . ' The learner started Course B, a course in this bundle, on ', $exception->getMessage());
        }
        self::assertSame(0, $this->records->refundedAmount($started));
        $refunds->approve($admin, $started, (int) $line['id'], Uuid::v4(), 'goodwill', 'Customer request', 1, 120000, 'Agreed with the learner by telephone.');
        self::assertSame('refunded', $this->records->order($started)['state'], 'With an override the bundle is refunded whole, as before.');

        $waiter = $this->buyer();
        $this->orders->changeBundle($waiter, $bundle['offer']);
        $unstarted = $this->buy($waiter);
        $refundId = $refunds->approve($admin, $unstarted, (int) $this->records->items($unstarted)[0]['id'], Uuid::v4(), 'voluntary', 'Customer request', 1, 120000);
        self::assertNull($this->db->fetchOne('SELECT override_reason FROM commerce_refunds WHERE id=:id', ['id' => $refundId]), 'A bundle nobody started is refunded inside the rule.');
    }

