        // R500.00 paid by card: Stitch's fee is 2.9% (R14.50) plus R1.50, recorded when the payment arrived.
        self::assertSame(1600, (int) $this->db->fetchOne("SELECT SUM(amount_minor) FROM commerce_ledger_entries WHERE order_id=:o AND kind='processor_fee'", ['o' => $orderId]));
        $wallet = $refunds->quote($order, $item, 50000, 'wallet');
        self::assertSame([50000, 0, 50000, 'stitch', 48400], [$wallet['gross'], $wallet['wallet_part'], $wallet['external'], $wallet['method'], $wallet['net']]);
        self::assertSame([['kind' => 'stitch_transaction_fee', 'label' => 'Stitch transaction fee on this payment', 'amount_minor' => 1600]], $wallet['deductions'], 'Wallet credit: only the transaction fee is deducted.');
        $back = $refunds->quote($order, $item, 50000, 'money_back');
        self::assertSame(['stitch_transaction_fee' => 1600, 'stitch_refund_fee' => 500], array_column($back['deductions'], 'amount_minor', 'kind'), 'Money back: the refund fee as well.');
        self::assertSame(47900, $back['net']);

        $refundId = $refunds->approve($admin, $orderId, (int) $item['id'], Uuid::v4(), 'service_failure', 'Faulty course', 1, 50000, 'The course could not be provided.', 'money_back');
        $refund = $this->records->refund($refundId) ?? [];
        self::assertSame(['money_back', 'stitch', 47900, null], [$refund['destination'], $refund['method'], (int) $refund['net_minor'], $refund['paid_at']]);
