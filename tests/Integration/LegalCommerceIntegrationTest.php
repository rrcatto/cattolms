        }
    }

    public function testACardRefundIsWhatWasReceivedLessTheStitchFees(): void
    {
        $admin = $this->admin();
        WalletFixture::settings($this->db)->saveSection('fees', ['stitch_fee' => '2.9%+150', 'stitch_refund_fee' => '0%+500', 'eft_refund_fee' => '0:2000'], $admin->id);
