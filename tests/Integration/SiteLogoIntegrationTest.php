    public function testAnUploadedLogoIsPrintedByEveryDesignThatChoosesItAndServedByItsVersion(): void
    {
        $admin = $this->admin();
        $documents = $this->get(FinancialDocumentDesignService::class);
        // The documents choose the site logo, whatever the site had chosen.
        $documents->save(['logo_choice' => 'site'] + self::documentForm($documents), [], $admin);
        $before = $documents->summary()['versions'];

        $followed = $this->get(SiteLogoFollowers::class)->upload(self::png(400, 100), $admin);
        $logo = $this->get(SiteLogo::class);
        $image = $logo->image();
        self::assertNotNull($image, 'The logo is kept.');
        self::assertSame([400, 100], [$image->width, $image->height]);
        $version = (string) $logo->version();
        self::assertMatchesRegularExpression('/^[0-9a-f]{16}$/', $version);
        self::assertSame('https://site.example/site-logo/' . $version . '.png', $logo->url('https://site.example/'));
        self::assertStringStartsWith("\x89PNG", (string) ($logo->picture($version)['bytes'] ?? ''), 'It is served at its version.');
        self::assertNull($logo->picture('0123456789abcdef'), 'Nothing else is served there.');
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM cattophp_activity WHERE action = 'site_owner.logo_changed' AND actor_id = CAST(:admin AS TEXT) AND happened_at >= NOW() - INTERVAL '1 minute'", ['admin' => $admin]));

        self::assertSame(['invoice', 'receipt', 'credit_note'], $followed['documents'], 'All three documents print it from now on.');
        foreach ($documents->summary()['versions'] as $type => $number) {
            self::assertSame($before[$type] + 1, $number, $type . ' has a new version.');
            self::assertStringContainsString('asset:' . $image->sha, $this->publishedHtml($type), $type . ' prints the logo.');
        }
        $certificates = $this->get(CertificateDesignService::class);
        foreach ($certificates->designs() as $row) {
            $design = $row['design'];
            self::assertInstanceOf(CertificateDesign::class, $design);
            if ($design->logoChoice !== 'site') continue;
            $name = (string) $row['name'];
            self::assertTrue(in_array($name, $followed['certificates'], true) || in_array($name, $followed['kept'], true), $name . ' is given the logo, or named as keeping its look.');
            if (in_array($name, $followed['certificates'], true)) {
                self::assertStringContainsString('asset:' . $image->sha, $this->certificateHtml((int) $row['id']), $name . ' prints the logo.');
            }
        }

        $pdf = $logo->forPdf(45, 14);
        self::assertNotNull($pdf);
        self::assertStringStartsWith('data:image/png;base64,', $pdf['src']);
        self::assertEqualsWithDelta(45.0, $pdf['width_mm'], 0.11, 'A wide logo fills the box\'s width.');
        self::assertLessThanOrEqual(14.0, $pdf['height_mm']);

        // A new logo: the one before stays served, for the emails that show it.
        $this->get(SiteLogoFollowers::class)->upload(self::png(300, 300), $admin);
        self::assertNotSame($version, $logo->version());
        self::assertNotNull($logo->picture($version), 'An email already sent keeps its picture.');
        $documents->save(['logo_choice' => 'none'] + self::documentForm($documents), [], $admin);
        self::assertStringNotContainsString('asset:', $this->publishedHtml('invoice'), 'No logo is no logo.');

        $removed = $this->get(SiteLogoFollowers::class)->remove($admin);
        self::assertNotNull($removed);
        self::assertSame([], $removed['documents'], 'The documents chose no logo, so they are left as they are.');
        self::assertNull($logo->image());
        self::assertNull($logo->forPdf(45, 14));
        self::assertNull($this->get(SiteLogoFollowers::class)->remove($admin), 'There is nothing more to remove.');
    }

    public function testAnEmailShowsTheLogoItsTemplateChoosesAndAccountEmailsAreDrawnInTheirOwnTemplate(): void
    {
        $admin = $this->admin();
        $logo = $this->get(SiteLogo::class);
        $logo->upload(self::png(480, 120), $admin);
        $address = '/site-logo/' . $logo->version() . '.png';
        $templates = $this->get(MailingTemplates::class);
        $renderer = $this->get(EmailRenderer::class);
        $id = $templates->create('Account look', $admin);
        $design = static fn(string $source): array => ['name' => 'Account look', 'mode' => 'design', 'text_mode' => 'made', 'design' => ['logo_source' => $source, 'footer_words' => 'The Account look footer.']];

        $templates->save($id, $design('site'), $admin);
        self::assertSame('site', $templates->get($id)['design']['logo_source']);
        $words = '<p>Use the link below to sign in.</p><p><a href="https://site.example/login">Sign in securely</a></p>';
        $copy = $renderer->account('Your secure sign-in link', $words, 'Sign in: https://site.example/login', $templates->get($id));
        self::assertStringContainsString($address, $copy['html'], 'The site logo heads it.');
        self::assertStringContainsString('Sign in securely', $copy['html']);
        self::assertStringContainsString('The Account look footer.', $copy['html']);
        self::assertStringNotContainsString('Unsubscribe', $copy['html'], 'An account email is not news.');
        self::assertStringNotContainsString('View it in your browser', $copy['html']);
        self::assertStringContainsString('because of your account there', $copy['text']);

        $templates->save($id, $design('none'), $admin);
        self::assertStringNotContainsString('/site-logo/', $renderer->account('Subject', $words, 'Words', $templates->get($id))['html'], 'No logo is no logo.');
        $templates->save($id, $design('own'), $admin);
        self::assertStringNotContainsString('/site-logo/', $renderer->account('Subject', $words, 'Words', $templates->get($id))['html'], 'Its own logo, and it has none yet.');
        $news = $templates->create('News look', $admin);
        $templates->save($news, ['name' => 'News look', 'mode' => 'design', 'text_mode' => 'made', 'design' => ['logo_source' => 'site']], $admin);
        self::assertStringContainsString($address, $renderer->sample($templates->get($news), 'message', 'Lerato')['html'], 'A news email shows the site logo when its template chooses it.');

        // Account and order emails use the template chosen for them, which cannot be deleted.
        $templates->save($id, $design('site'), $admin);
        $templates->makeDefault($id, 'account', $admin);
        self::assertSame($id, (int) $templates->defaultFor('account')['id']);
        self::assertStringContainsString('The Account look footer.', $renderer->account('Subject', $words, 'Words')['html']);
        self::assertStringContainsString('Sign in securely', $renderer->sample($templates->get($id), 'account', 'Lerato')['html'], 'The template shows a sample account email.');
        try {
            $templates->delete($id, $admin);
            self::fail('The template for account and order emails was deleted.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString('account and order emails', $refused->getMessage());
        }

        // An HTML template places the site logo itself.
        $html = '<html><body><img src="{site_logo_url}" alt="">{content}<p>{site_owner_address}</p><a href="{unsubscribe_link}">Your subscriptions</a></body></html>';
        $templates->save($id, ['name' => 'Account look', 'mode' => 'html', 'html' => $html, 'text_mode' => 'made'], $admin);
        $page = $renderer->account('Subject', $words, 'Words')['html'];
        self::assertStringContainsString('src="' . rtrim(Env::string('APP_URL'), '/') . $address . '"', $page);
        self::assertStringContainsString('/account/subscriptions', $page, 'Its unsubscribe link is the person\'s subscriptions page.');
    }

    public function testAnSvgLogoIsDrawnAsPngAndAFileThatIsNotAPictureIsRefused(): void
    {
        $logo = $this->get(SiteLogo::class);
        try {
            $logo->upload('This is not a picture.', $this->admin());
            self::fail('A file that is not a picture was kept as the logo.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame('The logo must be a PNG, JPEG or SVG file of at most 12 MB.', $refused->getMessage());
        }
        if (SvgRaster::tool() === null) self::markTestSkipped('This server has no rsvg-convert to draw SVG.');
        $logo->upload('<?xml version="1.0"?><svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 50"><rect width="200" height="50" rx="8" fill="#9a3f12"/></svg>', $this->admin());
        $image = $logo->image();
        self::assertNotNull($image);
        self::assertSame([1200, 300], [$image->width, $image->height], 'Drawn as large as fits 1200 by 600, its shape kept.');
        self::assertStringStartsWith("\x89PNG", (string) ($logo->picture((string) $logo->version())['bytes'] ?? ''));
    }

    /** @return array<string,mixed> the financial document design's form as it stands */
    private static function documentForm(FinancialDocumentDesignService $documents): array
    {
        $design = $documents->design();
        $form = ['typeface' => $design->typeface, 'colour' => $design->colour, 'logo_asset' => $design->logo->sha ?? ''];
        foreach ($design->notes as $type => $note) $form['note_' . $type] = $note;
        return $form;
    }

    private function publishedHtml(string $type): string
    {
        return (string) $this->db->fetchOne("SELECT v.html FROM document_templates t JOIN document_template_versions v ON v.id = t.published_version_id WHERE t.document_type = :type AND t.is_current", ['type' => $type]);
    }

    private function certificateHtml(int $id): string
    {
        return (string) $this->db->fetchOne('SELECT v.html FROM document_templates t JOIN document_template_versions v ON v.id = t.published_version_id WHERE t.id = :id', ['id' => $id]);
    }

    /** A logo of the size given: a coloured band on a transparent ground. */
    private static function png(int $width, int $height): string
    {
        $image = imagecreatetruecolor($width, $height);
        imagesavealpha($image, true);
        imagefill($image, 0, 0, (int) imagecolorallocatealpha($image, 0, 0, 0, 127));
        imagefilledrectangle($image, (int) ($width / 10), (int) ($height / 4), (int) ($width * 9 / 10), (int) ($height * 3 / 4), (int) imagecolorallocate($image, 154, 63, 18));
        ob_start();
        imagepng($image);
        return (string) ob_get_clean();
    }

    /**
     * @template T of object
     * @param class-string<T> $class
     * @return T
     */
    private function get(string $class): object
    {
        return IntegrationContainer::get()->get($class);
    }

    private function admin(): int
    {
        return (int) $this->db->fetchOne("SELECT MIN(account_person(account_id)) FROM cattophp_account_roles WHERE role_key = 'ADMIN'");
    }
