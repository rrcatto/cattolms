    public function testAVisitorsTicksMarkTheirModuleAndCountOverWhatTheyAreShown(): void
    {
        $structure = $this->items->availability((int) $this->course['id'], null, true);
        $parts = array_values(array_filter($structure, static fn(array $row): bool => $row['node_type'] === 'item'));
        self::assertNotSame([], $parts);
        $done = array_fill_keys(array_map(static fn(array $row): int => (int) $row['id'], $parts), true);
        self::assertSame(['total' => count($parts), 'done' => count($parts), 'percentage' => 100], CourseNavigation::progress($structure, $done));
        $first = (int) $parts[0]['id'];
        $progress = CourseNavigation::progress($structure, [$first => true]);
        self::assertSame(1, $progress['done']);
        foreach (CourseNavigation::withDone($structure, [$first => true]) as $row) {
            if ((int) $row['id'] === $first) self::assertTrue($row['is_done']);
        }
    }

    private function right(int $question): int
    {
        return (int) $this->db->fetchOne('SELECT id FROM assessment_options WHERE question_id = :q AND is_correct LIMIT 1', ['q' => $question]);
    }

    /** @return array<string,int> */
    private function counts(): array
    {
        return ['sessions' => (int) $this->db->fetchOne('SELECT count(*) FROM assessment_sessions'), 'attempts' => (int) $this->db->fetchOne('SELECT count(*) FROM assessment_attempts'), 'enrolments' => (int) $this->db->fetchOne('SELECT count(*) FROM course_enrolments')];
    }
