    public function testAGradedAttemptRunsAsALearnersAndWritesNothing(): void
    {
        $before = $this->counts();
        ['node' => $node, 'key' => $key] = $this->nodes['module'];
        $overview = $this->attempts->overview($this->course, $node, $key);
        self::assertTrue($overview['can_start_graded']);
        self::assertTrue((bool) $overview['assessment']['practice_enabled'], 'The start page offers practice beside the graded attempt.');

        $attempt = $this->attempts->session($this->attempts->start($this->course, $node, $key, 'graded'));
        $total = count($attempt['questions']);
        self::assertGreaterThan(1, $total, 'The example asks more than one question.');
        $first = $this->attempts->view($attempt);
        self::assertSame(['total' => $total, 'answered' => 0], array_intersect_key($first['counts'], ['total' => 0, 'answered' => 0]));
        self::assertNotSame([], $first['question']['options'], 'One question is shown with its answers.');

        $skipped = (int) $first['question']['question_id'];
        $attempt = $this->attempts->respond($attempt, $skipped, null, true)['attempt'];
        self::assertNotSame($skipped, (int) $this->attempts->view($attempt)['question']['question_id'], 'A skipped question waits until the others are answered.');
        $asked = [];
        while ($attempt['status'] === 'in_progress') {
            $question = (int) $this->attempts->view($attempt)['question']['question_id'];
            $asked[] = $question;
            $answer = $this->attempts->respond($attempt, $question, $this->right($question), false);
            self::assertNull($answer['feedback'], 'A graded attempt gives no feedback until the end.');
            $attempt = $answer['attempt'];
        }
        self::assertSame($skipped, end($asked), 'The skipped question is asked again last.');
        self::assertSame('submitted', $attempt['status']);
        self::assertSame(100.0, (float) $attempt['percentage']);
        self::assertNotSame('', (string) $attempt['grade_code'], 'The result takes the course\'s grade band.');
        $result = $this->attempts->result($attempt, []);
        self::assertCount($total, $result['responses'], 'The question report lists every question.');
        self::assertSame($total, $result['counts']['correct']);
        self::assertTrue(PublicAssessmentAttempts::ticksItsPart($attempt), 'A finished graded attempt ticks its part.');
        self::assertSame($before, $this->counts(), 'Nothing is written to the database.');
    }

    public function testASkippedQuestionKeepsItsNumberForALearnerAndAVisitorAlike(): void
    {
        ['node' => $node, 'key' => $key] = $this->nodes['module'];
        $this->db->executeStatement('UPDATE course_item_assessments SET randomise_questions = FALSE WHERE course_item_id = (SELECT id FROM course_items WHERE item_key = :key)', ['key' => $key]);
        $fixture = new DevelopmentFixture($this->db);
        $learner = $fixture->person('STUDENT')['id'];
        $fixture->createEnrolment($learner, (int) $this->course['id'], $this->admin);
        $learning = $this->container->get(\CattoLearning\Course\LearningService::class);
        $assessments = $this->container->get(\CattoLearning\Course\AssessmentService::class);
        $learning->start($learner, (string) $this->course['slug']);
        $session = (string) $assessments->startAttempt($learner, (string) $this->course['slug'], $node, $key, 'graded')['public_id'];
        $learnerSeen = []; $state = $assessments->session($learner, $session);
        $visitorSeen = []; $attempt = $this->attempts->session($this->attempts->start($this->course, $node, $key, 'graded'));
        for ($turn = 0; $state['status'] === 'in_progress'; $turn++) {
            $question = (int) $state['question']['question_id'];
            $learnerSeen[] = (int) $state['question']['sequence'];
            $state = $assessments->respond($learner, $session, $question, $turn === 0 ? null : $this->right($question), $turn === 0);
        }
        for ($turn = 0; $attempt['status'] === 'in_progress'; $turn++) {
            $view = $this->attempts->view($attempt);
            $visitorSeen[] = (int) $view['question']['sequence'];
            $question = (int) $view['question']['question_id'];
            $attempt = $this->attempts->respond($attempt, $question, $turn === 0 ? null : $this->right($question), $turn === 0)['attempt'];
        }
        $count = count($attempt['questions']);
        self::assertSame([...range(1, $count), 1], $learnerSeen, 'The first question, skipped, comes back last as Question 1, never "Question 4 of 3".');
        self::assertSame($learnerSeen, $visitorSeen, 'A visitor is asked in the same way as a learner.');
    }

    public function testPracticeGivesFeedbackAndDoesNotTick(): void
    {
        ['node' => $node, 'key' => $key] = $this->nodes['module'];
        $attempt = $this->attempts->session($this->attempts->start($this->course, $node, $key, 'practice'));
        $question = (int) $this->attempts->view($attempt)['question']['question_id'];
        $wrong = (int) $this->db->fetchOne('SELECT id FROM assessment_options WHERE question_id = :q AND NOT is_correct LIMIT 1', ['q' => $question]);
        $answer = $this->attempts->respond($attempt, $question, $wrong, false);
        if ($answer['attempt']['status'] === 'in_progress') {
            self::assertFalse($answer['feedback']['is_correct'], 'Practice says the answer was not correct.');
            self::assertNotSame('', $answer['feedback']['correct_option_html'], 'and shows the correct answer.');
        }
        $finished = $this->attempts->finish($answer['attempt']);
        self::assertFalse(PublicAssessmentAttempts::ticksItsPart($finished), 'Practice on a graded assessment does not tick it.');
    }

    public function testFinishNowScoresTheRestAsUnanswered(): void
    {
        ['node' => $node, 'key' => $key] = $this->nodes['module'];
        $attempt = $this->attempts->session($this->attempts->start($this->course, $node, $key, 'graded'));
        $question = (int) $this->attempts->view($attempt)['question']['question_id'];
        $attempt = $this->attempts->respond($attempt, $question, $this->right($question), false)['attempt'];
        $finished = $this->attempts->finish($attempt);
        $result = $this->attempts->result($finished, []);
        self::assertSame(1, $result['counts']['correct']);
        self::assertSame(count($finished['questions']) - 1, $result['counts']['unanswered']);
        $points = (float) $this->db->fetchOne('SELECT points FROM assessment_questions WHERE id = :q', ['q' => $question]);
        self::assertSame($points, (float) $finished['earned_points'], 'Only the answered question scores.');
        self::assertSame(round($points / (float) $finished['maximum_points'] * 100, 2), (float) $finished['percentage']);
    }

    public function testAReadinessCheckIsReadyOrReviewAndTicksItsPart(): void
    {
        ['node' => $node, 'key' => $key] = $this->nodes['diagnostic'];
        try {
            $this->attempts->start($this->course, $node, $key, 'graded');
            self::fail('A readiness check took a graded attempt.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame('Select the assessment mode that matches this Course Item.', $refused->getMessage());
        }
        $attempt = $this->attempts->session($this->attempts->start($this->course, $node, $key, 'diagnostic'));
        while ($attempt['status'] === 'in_progress') {
            $question = (int) $this->attempts->view($attempt)['question']['question_id'];
            $attempt = $this->attempts->respond($attempt, $question, $this->right($question), false)['attempt'];
        }
        $result = $this->attempts->result($attempt, []);
        self::assertTrue($result['is_diagnostic']);
        self::assertTrue($result['diagnostic_passed']);
        self::assertSame('Ready', $attempt['grade_code']);
        self::assertTrue(PublicAssessmentAttempts::ticksItsPart($attempt));
    }

