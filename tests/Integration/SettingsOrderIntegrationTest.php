declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Configuration\SettingsOrder;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Infrastructure\Persistence\OptionRepository;
use CattoLearning\Tests\Support\IntegrationContainer;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class SettingsOrderIntegrationTest extends TestCase
{
    private Database $db;
    private SettingsOrder $order;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
        $this->order = IntegrationContainer::get()->get(SettingsOrder::class);
        // Whatever the site has saved, the test starts from the standard order; the rollback puts it back.
        $this->db->executeStatement('DELETE FROM app_options WHERE option_key = :key', ['key' => SettingsOrder::OPTION]);
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testASectionIsPlacedBeforeAnotherOrAtTheEndAndAStalePageIsRefused(): void
    {
        $admin = $this->admin();
        self::assertSame(SettingsOrder::STANDARD, $this->order->order());
        self::assertFalse($this->order->arranged());
        self::assertSame(array_keys(SettingsOrder::TITLES), SettingsOrder::STANDARD, 'Every section has its name.');

        $now = $this->order->place('maintenance', 'site-mode', SettingsOrder::STANDARD, $admin);
        self::assertSame(['maintenance', 'site-mode', 'site-notification'], array_slice($now, 0, 3));
        self::assertSame($now, $this->order->order(), 'It is saved.');
        self::assertTrue($this->order->arranged());
        $log = json_decode((string) $this->db->fetchOne("SELECT metadata FROM audit_log WHERE event_key = 'settings.order_changed' AND user_id = :admin ORDER BY id DESC LIMIT 1", ['admin' => $admin]), true);
        self::assertSame([SettingsOrder::STANDARD, $now], [$log['from'], $log['to']]);

        $end = $this->order->place('site-owner', '', $now, $admin);
        self::assertSame('site-owner', end($end), 'No section after it: the end.');
        foreach ([['site-owner', 'smtp', $now, 'The order changed since this page was opened. The saved order is shown.'], ['nonsense', '', $end, 'That section is not one of Settings.'],
            ['smtp', 'smtp', $end, 'A section cannot go before itself.']] as [$key, $before, $shown, $refusal]) {
            try {
                $this->order->place($key, $before, $shown, $admin);
                self::fail('Accepted ' . $key . ' before ' . $before);
            } catch (InvalidArgumentException $refused) {
                self::assertSame($refusal, $refused->getMessage());
            }
        }
        self::assertSame($end, $this->order->order(), 'A refused move changes nothing.');
    }

    public function testTheMenuMovesOneStepOrToAnEndAndResetGoesBackToTheStandardOrder(): void
    {
        $admin = $this->admin();
        self::assertSame(['site-mode', 'identity', 'site-notification'], array_slice($this->order->move('identity', 'up', $admin), 0, 3));
        self::assertSame('identity', $this->order->move('identity', 'top', $admin)[0]);
        self::assertSame('identity', $this->order->move('identity', 'up', $admin)[0], 'The top section stays at the top.');
        self::assertSame(['site-mode', 'identity'], array_slice($this->order->move('identity', 'down', $admin), 0, 2));
        $bottom = $this->order->move('identity', 'bottom', $admin);
        self::assertSame('identity', $bottom[count($bottom) - 1]);
        self::assertSame($bottom, $this->order->move('identity', 'down', $admin), 'The bottom section stays at the bottom.');
        try {
            $this->order->move('identity', 'sideways', $admin);
            self::fail('A direction that is not one was accepted.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame('Choose where the section goes.', $refused->getMessage());
        }
        $this->order->reset($admin);
        self::assertSame(SettingsOrder::STANDARD, $this->order->order());
        self::assertFalse($this->order->arranged());
        self::assertNull((new OptionRepository($this->db))->find(SettingsOrder::OPTION), 'Reset leaves nothing saved.');
    }

    public function testASectionTheSavedOrderDoesNotNameTakesItsStandardPlace(): void
    {
        // An order saved before Course positions and Maintenance existed, with a name no longer used.
        $saved = array_values(array_diff(array_reverse(SettingsOrder::STANDARD), ['course-positions', 'maintenance']));
        $saved[] = 'old-section';
        (new OptionRepository($this->db))->set(SettingsOrder::OPTION, (string) json_encode($saved), $this->admin());
        $order = $this->order->order();
        self::assertNotContains('old-section', $order);
        self::assertSame(count(SettingsOrder::STANDARD), count($order));
        $at = array_search('configuration', $order, true);
        self::assertSame(['configuration', 'course-positions', 'maintenance'], array_slice($order, (int) $at, 3), 'Each goes after the one before it in the standard order.');
    }

    private function admin(): int
    {
        return (int) $this->db->fetchOne("SELECT ur.user_id FROM user_roles ur JOIN roles r ON r.id = ur.role_id WHERE r.role_key = 'ADMIN' ORDER BY ur.user_id LIMIT 1");
    }
}
