    public function testAPreviewRunsForThePeriodABuyerGetsAndFollowsThePricesUntilItIsStarted(): void
    {
        $container = IntegrationContainer::get();
        $db = IntegrationContainer::db();
        $db->beginTransaction();
        try {
            $fixture = new DevelopmentFixture($db);
            $admin = $fixture->person('ADMIN');
            $provider = $fixture->company();
            $course = $fixture->course($provider['founder']['id'], $provider['id'], 'published');
            $short = $fixture->createPriceVariant($course['id'], $admin['id'], self::SIX_MONTHS, 90000, false);
            $db->executeStatement('UPDATE course_price_variants SET position = 2 WHERE id = :id', ['id' => $short]);
            $year = $fixture->createPriceVariant($course['id'], $admin['id'], self::YEAR, 120000, true);
            $previews = $container->get(CoursePortabilityService::class);
            $learning = $container->get(LearningService::class);
            $makeDefault = static function (int $variant) use ($db, $course): void {
                $db->executeStatement('UPDATE course_price_variants SET is_default = FALSE WHERE course_id = :course', ['course' => $course['id']]);
                $db->executeStatement('UPDATE course_price_variants SET is_default = TRUE WHERE id = :id', ['id' => $variant]);
            };
            $period = static fn(): int => (int) $previews->ensurePreview($admin['id'], $course['id'])['access_period_seconds'];

            self::assertSame(self::YEAR, $period(), 'The default price option\'s period, never ten years.');
            self::assertSame('1 year', $learning->courseHome($admin['id'], $course['slug'], true)['access_period_label'], 'The start page names it.');

            $makeDefault($short);
            self::assertSame(self::SIX_MONTHS, $period(), 'A preview not started follows the prices.');

            $learning->start($admin['id'], $course['slug'], true);
            $makeDefault($year);
            self::assertSame(self::SIX_MONTHS, $period(), 'A started preview keeps its period, as a learner\'s does.');

            $plain = $fixture->course($provider['founder']['id'], $provider['id'], 'published');
            $db->executeStatement('UPDATE courses SET default_access_period_seconds = 5184000 WHERE id = :id', ['id' => $plain['id']]);
            self::assertSame(5184000, (int) $previews->ensurePreview($admin['id'], $plain['id'])['access_period_seconds'], 'Without a price, the course\'s own default period.');
        } finally {
            if ($db->isTransactionActive()) { $db->rollBack(); }
        }
    }

    public function testTheStartPageNamesWhoseRefundStartingEnds(): void
    {
        // Owner, 2026-10-29: the learner's own refund for a course they bought, the company's for a place from its credit,
        // and none for a course given to test or an administrator's preview.
        $container = IntegrationContainer::get();
        $db = IntegrationContainer::db();
        $db->beginTransaction();
        try {
            $fixture = new DevelopmentFixture($db);
            $admin = $fixture->person('ADMIN');
            $provider = $fixture->company();
            $course = $fixture->course($provider['founder']['id'], $provider['id'], 'published');
            $learning = $container->get(LearningService::class);
            $refund = static fn(int $user, bool $preview = false): string => (string) $learning->courseHome($user, $course['slug'], $preview)['start_refund'];

            $given = $fixture->person('STUDENT');
            $fixture->createEnrolment($given['id'], $course['id'], $admin['id'], self::YEAR);
            self::assertSame('none', $refund($given['id']), 'A course given to test.');

            $buyer = $fixture->person('STUDENT');
            $bought = $fixture->createEnrolment($buyer['id'], $course['id'], $admin['id'], self::YEAR);
            $db->executeStatement("UPDATE course_enrolments SET source_type = 'paid_order' WHERE id = :id", ['id' => $bought]);
            self::assertSame('own', $refund($buyer['id']), 'A course the learner bought.');

            $staff = $fixture->staff($provider);
            $place = $fixture->createEnrolment($staff['id'], $course['id'], $admin['id'], self::YEAR);
            $administration = $container->get(\CattoLearning\Infrastructure\Persistence\AdministrationRepository::class);
            $credit = $administration->addCredit($provider['id'], null, $course['id'], self::YEAR, 1, 'qa', 'a place for the start page', $admin['id']);
            $administration->allocateCredit($credit, $staff['id'], $place, $provider['founder']['id']);
            self::assertSame('company', $refund($staff['id']), 'A place from the company\'s credit.');

            $container->get(CoursePortabilityService::class)->ensurePreview($admin['id'], $course['id']);
            self::assertSame('none', $refund($admin['id'], true), 'An administrator\'s preview.');
        } finally {
            if ($db->isTransactionActive()) { $db->rollBack(); }
        }
    }

