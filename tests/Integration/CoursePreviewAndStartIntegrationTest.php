    public function testStartCourseOpensTheFirstPartInOneClick(): void
    {
        $container = CliBootstrap::boot()['container'];
        $db = $container->get(Database::class);
        $fixture = new DevelopmentFixture($db);
        $cookies = $_COOKIE;
        try {
            $provider = $fixture->company();
            $course = $fixture->course($provider['founder']['id'], $provider['id'], 'published');
            $items = $container->get(CourseItemService::class);
            // A heading with nothing to show comes first: it is not a stop, so the lesson inside it is where Start leads.
            $section = $items->addSection($course['id'], ['title' => 'Getting started', 'numbered' => '1'], $provider['founder']['id']);
            $lesson = $items->createAndPlace($course['id'], ['item_key' => 'start-' . $fixture->suffix() . '-lesson', 'item_type' => 'html_lesson', 'title' => 'Welcome',
                'content_source' => '<p>Welcome to the course.</p>', 'parent_node_id' => (string) $section], $provider['founder']['id']);
            $learner = $fixture->person('STUDENT');
            $fixture->createEnrolment($learner['id'], $course['id'], $provider['founder']['id'], self::YEAR);

            $token = Token::generate();
            $container->get(AuthSessionRepository::class)->create($learner['id'], Token::hash($token), 3600, 'qa', 'PHPUnit');
            $_COOKIE[Env::string('AUTH_SESSION_COOKIE', 'catto_learning_session')] = $token;
            $before = (string) $this->send(Request::create('/learn/' . $course['slug']))->getContent();
            self::assertStringContainsString('I understand that starting begins my access period of 1 year, which then runs to its end.', $before, 'Given to test, the start page names no refund.');
            $_SESSION['csrf'] = str_repeat('c', 64);
            $_POST = ['csrf' => $_SESSION['csrf'], 'confirm_start' => 'yes'];
            $started = $this->send(Request::create('/learn/' . $course['slug'] . '/start', 'POST', $_POST));
            $_POST = [];
            self::assertSame('/learn/' . $course['slug'] . '/item/' . $lesson['node'] . '/content', $started->headers->get('Location'), 'Start course opens the first part.');
            self::assertNotNull($db->fetchOne('SELECT started_at FROM course_enrolments WHERE user_id = :u AND course_id = :c', ['u' => $learner['id'], 'c' => $course['id']]));
            $home = (string) $this->send(Request::create('/learn/' . $course['slug']))->getContent();
            self::assertStringNotContainsString('refund', $home, 'A course given to test names no refund on its page.');
            self::assertStringContainsString('href="/learn/' . $course['slug'] . '/item/' . $lesson['node'] . '/content"', $home, 'A learner coming back finds Begin course leading to the same part.');
        } finally {
            $_COOKIE = $cookies;
            $_POST = [];
            $fixture->cleanup();
        }
    }

