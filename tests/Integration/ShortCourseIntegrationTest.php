    public function testAShortCourseImportsPublishesAndRoundTrips(): void
    {
        $container = IntegrationContainer::get();
        $portability = $container->get(CoursePortabilityService::class);
        $file = ShortCourseExample::file();
        try {
            $analysis = $portability->stageImport(['error' => UPLOAD_ERR_OK, 'size' => filesize($file), 'name' => 'short.html', 'tmp_name' => $file], $this->admin);
        } finally {
            @unlink($file);
        }
        self::assertSame([], array_values((array) $analysis['warnings']), 'Nothing to warn about, and no "No final assessment was detected".');
        $courseId = $portability->commitImport((string) $analysis['import_key'], 0, $this->admin);
        $course = $container->get(CourseRepository::class)->findById($courseId);
        self::assertSame([ShortCourseExample::CODE, 'short', ShortCourseExample::MINUTES], [$course['code'], $course['course_type'], (int) $course['estimated_minutes']]);

        $items = $container->get(CourseItemService::class);
        $rows = $items->availability($courseId, null, false);
        $shape = array_map(static fn(array $row): string => str_repeat('  ', (int) $row['depth'] - 1) . ($row['node_type'] === 'section' ? ($row['label_number'] === null ? '' : 'Module ' . $row['label_number'] . ': ') . $row['section_title'] : (string) $row['part']), $rows);
        self::assertSame(['presentation', 'Soil, compost and containers', '  presentation', '  video', '  lesson', '  summary', '  flashcards', '  practical', '  assessment'], $shape, 'The preview, then the one module under its title alone (owner: "Title alone"), and no final.');
        self::assertTrue((bool) ($rows[0]['public_preview'] ?? false), 'The course preview is open to visitors from the start: nobody else ever sees it.');
        $section = array_values(array_filter($rows, static fn(array $row): bool => $row['node_type'] === 'section'))[0];
        self::assertSame(1, $section['section_number'], 'It keeps its number, and so its parts\' addresses.');
        self::assertSame([], $items->publicationValidation($courseId)['errors'], 'A short course publishes with its one assessment and no final.');

        // Its file: short, in minutes, no hours, no final time limit, no final, its module headed "Short course".
        $html = $container->get(CourseFile::class)->fromCourse($courseId)['html'];
        self::assertStringContainsString('<meta name="cattolms:course-type" content="short">', $html);
        self::assertStringContainsString('<meta name="cattolms:study-minutes" content="75">', $html);
        foreach (['cattolms:study-hours', 'cattolms:final-time-limit', 'class="final"', '"final":'] as $absent) self::assertStringNotContainsString($absent, $html, 'No ' . $absent . '.');
        self::assertStringContainsString('<span class="eyebrow">Short course</span>', $html);
        $back = (new LegacyHtmlCourseImporter())->analyse($html, 'exported.html');
        self::assertSame([], $back['warnings'], 'The exported file imports back without a warning.');
        self::assertSame(['short', 75, null], [$back['course']['course_type'], $back['course']['estimated_minutes'], $back['final_assessment']]);
        self::assertCount(6, $back['trailer']['type_config']['slides'] ?? []);

        // Its package carries the type.
        self::assertSame('short', $portability->exportCourse($courseId)['course']['course_type']);
    }

    public function testTheOneAssessmentCompletesTheCourseMakesTheMarkAndEarnsTheCertificate(): void
    {
        $container = IntegrationContainer::get();
        $suffix = $this->fixture->suffix();
        $companyId = $this->fixture->createCompany($this->admin, 'Short Course Academy ' . $suffix, 'short-' . $suffix . '.example.test');
        $slug = 'short-course-' . $suffix;
        $courseId = $this->fixture->createCourse($this->admin, $companyId, $slug, 'Make Compost in a Small Space', 'published');
        $this->db->executeStatement("UPDATE courses SET course_type = 'short', estimated_minutes = 75, certificate_enabled = TRUE WHERE id = :id", ['id' => $courseId]);
        $this->fixture->addGradeBands($courseId);
        $assessment = $this->fixture->createAssessmentItem($courseId, $this->admin, 'graded', 1);
        $right = $this->fixture->createQuestion($assessment['item_id']);
        $learnerId = $this->fixture->createUser('Short course learner', 'short-learner-' . $suffix . '@example.test');
        IdentityFixture::verify($learnerId, 'Lindiwe', 'Khumalo');
        $enrolmentId = $this->fixture->createEnrolment($learnerId, $courseId, $this->admin, 2592000);
        $container->get(LearningService::class)->start($learnerId, $slug);
        $assessments = $container->get(AssessmentService::class);
        $attempt = $assessments->startAttempt($learnerId, $slug, $assessment['node_id'], $assessment['key'], 'graded');
        // The assessment asks one question; answered right, the attempt is finished and scores 100%.
        $assessments->respond($learnerId, (string) $attempt['public_id'], $right['question_id'], $right['correct_option_id'], false);

        $saved = $this->db->fetchAssociative('SELECT module_percentage, final_percentage, overall_percentage FROM course_results WHERE enrolment_id = :id', ['id' => $enrolmentId]);
        self::assertNotFalse($saved, 'The short course\'s one assessment completes it: there is no final.');
        self::assertSame([100.0, 100.0, 100.0], [(float) $saved['module_percentage'], (float) $saved['final_percentage'], (float) $saved['overall_percentage']], 'Its score is the whole mark.');
        self::assertSame('completed', $this->db->fetchOne('SELECT status FROM course_enrolments WHERE id = :id', ['id' => $enrolmentId]));
        $page = $assessments->result($learnerId, (string) $attempt['public_id']);
        self::assertTrue($page['closes_course'], 'Its result page is the course\'s end.');
        self::assertSame(100.0, (float) ($page['course_result']['overall_percentage'] ?? 0));

        $certificates = $container->get(CertificateRepository::class);
        $certificate = $certificates->forEnrolment($enrolmentId);
        self::assertNotNull($certificate, 'A short course earns its certificate without a final.');
        $transcript = $certificates->transcriptForCertificate((int) $certificate['id']);
        self::assertNotNull($transcript);
        self::assertSame(['Short course', '100.00', null], [$transcript['document_data']['course.short_course'], $transcript['document_data']['result.overall'], $transcript['document_data']['result.module_average']]);
        self::assertSame('Assessment', $transcript['document_data']['assessments'][0]['kind'], 'Neither a module\'s assessment nor a final.');
    }
