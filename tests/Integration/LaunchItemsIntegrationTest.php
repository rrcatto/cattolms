    public function testTheSchedulerRecordsEachRunAndTheCleanUpDeletesOnlyWhatIsOlderThanFiveYears(): void
    {
        $person = $this->fixture->createUser('Retention person', 'retention-' . $this->fixture->suffix() . '@example.test');
        $old = (new \DateTimeImmutable('-5 years -2 days'))->format('Y-m-d H:i:sP');
        $recent = (new \DateTimeImmutable('-4 years'))->format('Y-m-d H:i:sP');
        foreach (['old' => $old, 'recent' => $recent] as $label => $at) {
            $this->db->executeStatement('INSERT INTO audit_log (user_id, event_key, metadata, created_at) VALUES (:user, :event, CAST(:meta AS JSONB), :at)', ['user' => $person, 'event' => 'qa.retention_' . $label, 'meta' => '{}', 'at' => $at]);
            $this->db->executeStatement("INSERT INTO analytics_events (event_type, source, occurred_at, user_id) VALUES ('qa_retention_" . $label . "', 'qa', :at, :user)", ['at' => $at, 'user' => $person]);
        }
        $results = IntegrationContainer::get()->get(Scheduler::class)->run([ScheduledJob::Cleanup]);
        self::assertTrue($results['cleanup']['ok']);
        self::assertStringContainsString('older than 5 years', $results['cleanup']['summary']);
        self::assertSame(0, (int) $this->db->fetchOne("SELECT COUNT(*) FROM audit_log WHERE event_key = 'qa.retention_old'"), 'An activity log entry older than 5 years is deleted.');
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM audit_log WHERE event_key = 'qa.retention_recent'"), 'A newer one is kept.');
        self::assertSame(0, (int) $this->db->fetchOne("SELECT COUNT(*) FROM analytics_events WHERE event_type = 'qa_retention_old'"));
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM analytics_events WHERE event_type = 'qa_retention_recent'"));
        $row = $this->db->fetchAssociative("SELECT * FROM scheduled_jobs WHERE job_key = 'cleanup'");
        self::assertNotFalse($row);
        self::assertNotNull($row['last_succeeded_at'], 'The run is recorded.');
        self::assertGreaterThan(0, (int) $row['run_count']);

        // The dashboard warns when the commerce job has not succeeded for five minutes.
        $status = IntegrationContainer::get()->get(ScheduledJobStatus::class);
        $this->db->executeStatement("INSERT INTO scheduled_jobs (job_key, last_started_at, last_succeeded_at) VALUES ('commerce', NOW() - INTERVAL '10 minutes', NOW() - INTERVAL '10 minutes')
            ON CONFLICT (job_key) DO UPDATE SET last_started_at = EXCLUDED.last_started_at, last_succeeded_at = EXCLUDED.last_succeeded_at");
        self::assertStringStartsWith('Order emails have not been sent since ', (string) $status->commerceWarning());
        $this->db->executeStatement("UPDATE scheduled_jobs SET last_succeeded_at = NOW() WHERE job_key = 'commerce'");
        self::assertNull($status->commerceWarning(), 'A running commerce job raises no warning.');
        self::assertSame(['commerce', 'popularity', 'cleanup', 'signup_lists', 'mailing', 'log_archive'], array_column($status->jobs(), 'key'));
    }

    public function testThePaymentMethodsSettingRefusesWhatCannotBeOfferedAndLogsAChange(): void
    {
        $admin = $this->fixture->createUser('Payments administrator', 'payments-' . $this->fixture->suffix() . '@example.test');
        $options = new OptionRepository($this->db);
        $options->delete(PaymentMethods::OPTION);
        $methods = new PaymentMethods(SiteMode::fixed(SiteMode::DEMO), $options, new AuditRepository($this->db));
        foreach ([[[], 'Tick at least one payment method'], [['card'], 'Card: paid on Stitch\'s secure page cannot be ticked']] as [$ticked, $refusal]) {
            try {
                $methods->save($ticked, $admin);
                self::fail('Refused: ' . $refusal);
            } catch (\InvalidArgumentException $refused) {
                self::assertStringStartsWith($refusal, $refused->getMessage());
            }
        }
        $methods->save(['eft'], $admin);
        self::assertSame(['eft'], $methods->offered());
        $logged = $this->db->fetchOne("SELECT metadata FROM audit_log WHERE event_key = 'settings.payment_methods_changed' AND user_id = :id", ['id' => $admin]);
        self::assertEquals(['before' => ['eft', 'dummy'], 'after' => ['eft']], json_decode((string) $logged, true));
        $live = new PaymentMethods(SiteMode::fixed(SiteMode::LIVE), $options);
        $options->set(PaymentMethods::OPTION, 'eft,dummy', $admin);
        self::assertSame(['eft'], $live->offered(), 'A saved simulated card is never offered on a live site.');
    }

