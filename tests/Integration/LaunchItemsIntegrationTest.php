    public function testTheSitemapListsPublishedCoursesAndLandingPagesAndADemoSiteHasNone(): void
    {
        $owner = $this->fixture->createUser('Sitemap owner', 'sitemap-' . $this->fixture->suffix() . '@example.test');
        $company = $this->fixture->createCompany($owner, 'Sitemap QA', 'sitemap-' . $this->fixture->suffix() . '.example.test');
        $suffix = $this->fixture->suffix();
        $published = $this->fixture->createCourse($owner, $company, 'qa-sitemap-on-' . $suffix, 'Sitemap On', 'published');
        $this->fixture->createCourse($owner, $company, 'qa-sitemap-draft-' . $suffix, 'Sitemap Draft', 'draft');
        $this->db->executeStatement("INSERT INTO course_landing_pages (course_id, slug, status, first_published_at, published_at) VALUES (:course, :slug, 'published', NOW(), NOW())", ['course' => $published, 'slug' => 'qa-landing-' . $suffix]);
        $hidden = $this->fixture->createCourse($owner, $company, 'qa-sitemap-hidden-' . $suffix, 'Sitemap Hidden', 'draft');
        $this->db->executeStatement("INSERT INTO course_landing_pages (course_id, slug, status, first_published_at, published_at) VALUES (:course, :slug, 'published', NOW(), NOW())", ['course' => $hidden, 'slug' => 'qa-landing-hidden-' . $suffix]);

        $previous = $_ENV['APP_URL'] ?? null;
        $_ENV['APP_URL'] = 'https://learning.example.test/';
        try {
            $repository = IntegrationContainer::get()->get(SitemapRepository::class);
            $live = new Sitemap($repository, SiteMode::fixed(SiteMode::LIVE), new ArrayAdapter());
            $xml = (string) $live->document();
            self::assertStringStartsWith('<?xml version="1.0" encoding="UTF-8"?>' . "\n" . '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">', $xml);
            self::assertStringContainsString('<loc>https://learning.example.test/courses/qa-sitemap-on-' . $suffix . '</loc><lastmod>', $xml);
            self::assertStringContainsString('<loc>https://learning.example.test/landing/qa-landing-' . $suffix . '</loc>', $xml);
            self::assertStringNotContainsString('qa-sitemap-draft-' . $suffix, $xml, 'A draft course is not listed.');
            self::assertStringNotContainsString('qa-landing-hidden-' . $suffix, $xml, 'A landing page of an unpublished course is not listed.');
            self::assertStringContainsString("Sitemap: https://learning.example.test/sitemap.xml\n", $live->robots());

            // Beyond its limit the sitemap is an index of numbered pages.
            $small = new Sitemap($repository, SiteMode::fixed(SiteMode::LIVE), new ArrayAdapter(), 1);
            self::assertGreaterThan(1, $small->pages());
            self::assertStringContainsString('<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">', (string) $small->document());
            self::assertStringContainsString('<loc>https://learning.example.test/sitemap-2.xml</loc>', (string) $small->document());
            self::assertSame(1, substr_count((string) $small->page(1), '<url>'));
            self::assertNull($small->page($small->pages() + 1));

            $demo = new Sitemap($repository, SiteMode::fixed(SiteMode::DEMO), new ArrayAdapter());
            self::assertNull($demo->document(), 'A demo site has no sitemap.');
            self::assertStringNotContainsString('Sitemap:', $demo->robots(), 'A demo site\'s robots.txt names no sitemap.');
            self::assertStringNotContainsString("Disallow: /\n", $demo->robots(), 'A demo site is never kept from search engines entirely: its pages say noindex.');
            self::assertStringContainsString('Disallow: /admin/', $demo->robots());
        } finally {
            if ($previous === null) unset($_ENV['APP_URL']); else $_ENV['APP_URL'] = $previous;
        }
    }

