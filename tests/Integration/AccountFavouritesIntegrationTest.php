declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Analytics\AnalyticsSource;
use CattoLearning\Application\AccountFavourites;
use CattoLearning\Bundle\BundleService;
use CattoLearning\Course\CourseFavouriteService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\{BundleFixture, DevelopmentFixture, IntegrationContainer};
use PHPUnit\Framework\TestCase;
use RuntimeException;

final class AccountFavouritesIntegrationTest extends TestCase
{
    private Database $db;
    private int $learner;
    /** @var array<string,int> */
    private array $courses = [];
    /** @var array<string,array{id:int,offer:int,slug:string,title:string}> */
    private array $bundles = [];

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
        $fixture = new DevelopmentFixture($this->db);
        $suffix = $fixture->suffix();
        $this->learner = $fixture->createUser('Favourites learner ' . $suffix, 'favourites-' . $suffix . '@example.test');
        $owner = $fixture->createUser('Favourites provider ' . $suffix, 'favourites-provider-' . $suffix . '@example.test');
        $company = $fixture->createCompany($owner, 'Favourites Company ' . $suffix, 'favourites-' . $suffix . '.example.test');
        foreach (['garden' => 'published', 'pottery' => 'published', 'weaving' => 'published', 'draft' => 'draft'] as $key => $status) {
            $this->courses[$key] = $fixture->createCourse($owner, $company, 'favourites-' . $key . '-' . $suffix, ucfirst($key) . ' course ' . $suffix, $status);
            $fixture->createPriceVariant($this->courses[$key], $owner, 31536000, 50000, true);
        }
        $two = [$this->courses['garden'], $this->courses['pottery']];
        $this->bundles['open'] = BundleFixture::create($this->db, $owner, $two, 90000, ['title' => 'Open bundle ' . $suffix]);
        $this->bundles['retired'] = BundleFixture::create($this->db, $owner, $two, 90000, ['title' => 'Retired bundle ' . $suffix, 'status' => 'retired']);
        $this->bundles['draft'] = BundleFixture::create($this->db, $owner, $two, 90000, ['title' => 'Draft bundle ' . $suffix, 'status' => 'draft']);
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testCoursesAndBundlesAreOneListNewestFirstWithACardForEachKind(): void
    {
        $this->star(['course:garden' => '2026-11-01 09:00', 'bundle:open' => '2026-11-03 09:00', 'course:pottery' => '2026-11-02 09:00', 'bundle:retired' => '2026-11-04 09:00', 'course:draft' => '2026-11-05 09:00']);
        $view = $this->view([]);
        self::assertSame('all', $view['favourites_kind']);
        self::assertSame(['all', 'courses', 'bundles'], array_column($view['favourites_kinds'], 'value'));
        self::assertSame(['4 courses and bundles', '2 courses', '2 bundles'], array_column($view['favourites_kinds'], 'note'), 'A draft course is not listed, as the catalogue does not show it.');
        self::assertSame([$this->bundles['retired']['title'], $this->bundles['open']['title'], $this->title('pottery'), $this->title('garden')], array_column($view['favourites_cards'], 'title'), 'Newest star first, courses and bundles together.');
        $bundle = $view['favourites_cards'][1];
        self::assertSame(['bundle', $this->bundles['open']['id'], true, '/bundles/' . $this->bundles['open']['slug']], [$bundle['kind'], $bundle['bundle_id'], $bundle['is_favourite'], $bundle['href']], 'A bundle\'s card: its star, filled, and its page.');
        $course = $view['favourites_cards'][2];
        self::assertSame(['course', $this->courses['pottery'], true], [$course['kind'], $course['id'], $course['is_favourite']], 'A course\'s card is the catalogue\'s.');
        self::assertTrue($view['can_favourite'], 'Every card carries its star, to unstar it in place.');
        self::assertSame('grid', $view['favourites_view'], 'Cards until the person chooses the list.');

        self::assertSame([$this->title('pottery'), $this->title('garden')], array_column($this->view(['kind' => 'courses'])['favourites_cards'], 'title'));
        self::assertSame([$this->bundles['retired']['title'], $this->bundles['open']['title']], array_column($this->view(['kind' => 'bundles'])['favourites_cards'], 'title'));
        self::assertFalse($view['favourites_searchable'], 'Four favourites: no search field.');
        try {
            $this->view(['kind' => 'everything']);
            self::fail('A kind that does not exist is refused.');
        } catch (\InvalidArgumentException $refused) {
            self::assertSame('There is no such list of favourites.', $refused->getMessage());
        }
    }

    public function testASearchAndAPageNarrowTheChosenKind(): void
    {
        $this->star(['course:garden' => '2026-11-01 09:00', 'course:pottery' => '2026-11-02 09:00', 'course:weaving' => '2026-11-03 09:00', 'bundle:open' => '2026-11-04 09:00', 'bundle:retired' => '2026-11-05 09:00']);
        $view = $this->view(['favourites_q' => 'Pottery']);
        self::assertSame([$this->title('pottery')], array_column($view['favourites_cards'], 'title'));
        self::assertTrue($view['favourites_searchable'], 'Five favourites, and a search narrowing them: the field stays.');
        self::assertSame('5 courses and bundles', $view['favourites_kinds'][0]['note'], 'A card counts its whole list.');
        $bundles = $this->view(['kind' => 'bundles', 'favourites_q' => 'Open bundle']);
        self::assertSame([$this->bundles['open']['title']], array_column($bundles['favourites_cards'], 'title'));
        self::assertSame('bundles', $bundles['favourites_pagination']['filters']['kind'] ?? null, 'Paging keeps the kind.');
        self::assertSame(24, $view['favourites_pagination']['page_size'] ?? null, 'Cards page in whole rows of four.');
        self::assertSame(25, $this->view(['favourites_view' => 'list'])['favourites_pagination']['page_size'] ?? null, 'A list pages as tables do.');
    }

    public function testABundleIsStarredOnceAndADraftCannotBe(): void
    {
        $bundles = IntegrationContainer::get()->get(BundleService::class);
        self::assertTrue($bundles->setFavourite($this->learner, $this->bundles['open']['id'], true));
        self::assertFalse($bundles->setFavourite($this->learner, $this->bundles['open']['id'], true), 'A repeated star changes nothing.');
        self::assertSame(1, (int) $this->db->fetchOne('SELECT COUNT(*) FROM audit_log WHERE user_id = :u AND event_key = :a', ['u' => $this->learner, 'a' => 'bundle.favourited']), 'Recorded once.');
        try {
            $bundles->setFavourite($this->learner, $this->bundles['draft']['id'], true);
            self::fail('A draft bundle is not in the catalogue, so it cannot be starred.');
        } catch (RuntimeException $refused) {
            self::assertSame('That bundle could not be added to your favourites.', $refused->getMessage());
        }
        $cards = $bundles->markFavourites($this->learner, $bundles->catalogue(200, 0));
        $mine = array_values(array_filter($cards, fn(array $card): bool => $card['bundle_id'] === $this->bundles['open']['id']));
        self::assertTrue($mine[0]['is_favourite'] ?? false, 'Its card on the Bundles page shows its star filled.');
        self::assertTrue($bundles->setFavourite($this->learner, $this->bundles['open']['id'], false));
        self::assertSame([], $this->view([])['favourites_cards'], 'Unstarred, it leaves Favourites.');
    }

    /** @param array<string,string> $stars kind:key => when it was starred */
    private function star(array $stars): void
    {
        $courseStars = IntegrationContainer::get()->get(CourseFavouriteService::class);
        $bundleStars = IntegrationContainer::get()->get(BundleService::class);
        foreach ($stars as $what => $when) {
            [$kind, $key] = explode(':', $what);
            if ($kind === 'course') {
                $courseStars->set($this->learner, $this->courses[$key], true, AnalyticsSource::Catalogue);
                $this->db->executeStatement('UPDATE course_favourites SET created_at = :at WHERE user_id = :u AND course_id = :c', ['at' => $when . '+02', 'u' => $this->learner, 'c' => $this->courses[$key]]);
            } else {
                $bundleStars->setFavourite($this->learner, $this->bundles[$key]['id'], true);
                $this->db->executeStatement('UPDATE bundle_favourites SET created_at = :at WHERE user_id = :u AND bundle_id = :b', ['at' => $when . '+02', 'u' => $this->learner, 'b' => $this->bundles[$key]['id']]);
            }
        }
    }

    private function title(string $key): string
    {
        return (string) $this->db->fetchOne('SELECT title FROM courses WHERE id = :id', ['id' => $this->courses[$key]]);
    }

    /**
     * @param array<string,string> $request
     * @return array<string,mixed>
     */
    private function view(array $request): array
    {
        return IntegrationContainer::get()->get(AccountFavourites::class)->view($this->learner, $request + ['kind' => null]);
    }
}
