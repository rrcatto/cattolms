use PHPUnit\Framework\TestCase;

final class PersonCompanyMembershipIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testTheCompanyFollowsTheAddress(): void
    {
        [$service, $admin, $person, $company, $domain] = $this->company();

        $page = $service->personForAdministration($person);
        self::assertSame($company, (int) ($page['selected_company']['id'] ?? 0), 'The page shows the company their address is at.');

        // Saving the page as it is sent back keeps the company, now with the role ticked.
        $service->updatePerson($person, ['first_name' => 'Membership', 'last_name' => 'Person', 'primary_email' => 'person@' . $domain, 'roles' => ['STUDENT', 'COMPANY_ADMIN']], $admin);
        self::assertSame(['administrator', 'active'], array_values($this->membership($person, $company)));
        // The founder hands the administration over, so the person is now its only Company Administrator.
        $founder = (int) $this->db->fetchOne("SELECT user_id FROM company_users WHERE company_id = :c AND company_role = 'owner'", ['c' => $company]);
        $service->setCompanyPersonRole($admin, $company, $founder, 'STUDENT');

        // The company's only Company Administrator cannot leave it, and nobody keeps the role at a private address.
        $private = ['first_name' => 'Membership', 'last_name' => 'Person', 'primary_email' => 'person-' . $domain . '@example.test', 'roles' => ['STUDENT', 'COMPANY_ADMIN']];
        foreach ([CompanyService::LAST_ADMINISTRATOR_MOVED, PlatformAdministrationService::COMPANY_ADMIN_NEEDS_COMPANY] as $why) {
            // A save has its own transaction, which a refusal rolls back; inside this test's, a savepoint stands in for it.
            $this->db->executeStatement('SAVEPOINT refused_save');
            try {
                $service->updatePerson($person, $private, $admin);
                self::fail('Refused: ' . $why);
            } catch (InvalidArgumentException $refused) {
                self::assertSame($why, $refused->getMessage());
            }
            $this->db->executeStatement('ROLLBACK TO SAVEPOINT refused_save');
            self::assertSame(['administrator', 'active'], array_values($this->membership($person, $company)), 'Nothing changed.');
            // A second Company Administrator, so the first may leave.
            if ($why === CompanyService::LAST_ADMINISTRATOR_MOVED) {
                $fixture = new IntegrationDataFixture($this->db);
                $fixture->addCompanyMember($company, $fixture->createUser('Second Admin', 'second@' . $domain), 'administrator');
            }
        }

        // A private address makes the account private, keeping its courses; the company's address again brings them back.
        $service->updatePerson($person, ['first_name' => 'Membership', 'last_name' => 'Person', 'primary_email' => 'person-' . $domain . '@example.test', 'roles' => ['STUDENT']], $admin);
        self::assertNull($service->personForAdministration($person)['selected_company'], 'Private now.');
        self::assertSame('inactive', $this->membership($person, $company)['status']);
        $service->updatePerson($person, ['first_name' => 'Membership', 'last_name' => 'Person', 'primary_email' => 'person@' . $domain, 'roles' => ['STUDENT']], $admin);
        self::assertSame(['student', 'active'], array_values($this->membership($person, $company)));

        // A disabled company's member is still its member.
        $this->db->executeStatement("UPDATE companies SET status = 'disabled' WHERE id = :c", ['c' => $company]);
        self::assertSame($company, (int) ($service->personForAdministration($person)['selected_company']['id'] ?? 0));
    }

    public function testAddPersonTakesTheCompanyFromTheAddressAndNeverTakesOverAnAccount(): void
    {
        [$service, $admin, $person, $company, $domain] = $this->company();

        $staff = $service->createPerson(['first_name' => 'New', 'last_name' => 'Staff', 'email' => 'new@' . $domain, 'role' => 'STUDENT'], $admin);
        self::assertSame(['student', 'active'], array_values($this->membership($staff, $company)), 'An address at the domain makes them its staff.');
        $private = $service->createPerson(['first_name' => 'New', 'last_name' => 'Private', 'email' => 'private-' . $domain . '@example.test', 'role' => 'STUDENT', 'company_id' => (string) $company], $admin);
        self::assertNull($service->personForAdministration($private)['selected_company'], 'Any other address makes a private account, whatever the form says.');

        try {
            $service->createPerson(['first_name' => 'Again', 'last_name' => 'Person', 'email' => 'person@' . $domain, 'role' => 'STUDENT'], $admin);
            self::fail('An address with an account is refused.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame(PlatformAdministrationService::ADDRESS_HAS_ACCOUNT, $refused->getMessage());
        }
    }

    public function testTheFounderIsACompanyAdministratorAndTheCompanyKeepsOne(): void
    {
        [$service, $admin, $person, $company] = $this->company(true);

        try {
            $service->setCompanyPersonRole($admin, $company, $person, 'STUDENT');
            self::fail('The only Company Administrator, the founder, is kept.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame(PlatformAdministrationService::LAST_COMPANY_ADMIN, $refused->getMessage());
        }
        // Saying they are a Company Administrator changes nothing: they are one.
        $service->setCompanyPersonRole($admin, $company, $person, 'COMPANY_ADMIN');
        self::assertSame('owner', $this->membership($person, $company)['company_role']);
    }

    public function testADomainChangeMovesEveryStaffAddressOnlyOnceConfirmed(): void
    {
        [$service, $admin, $person, $company, $domain] = $this->company(true);
        $new = 'renamed-' . $domain;

        $moves = $service->domainChangeMoves($company, $new);
        self::assertSame([['user_id' => $person, 'name' => 'Membership Person', 'from' => 'person@' . $domain, 'to' => 'person@' . $new, 'taken' => false]], $moves, 'The warning names each address and what it becomes.');
        try {
            $service->updateCompany($company, ['name' => 'Membership Company', 'domain' => $new], $admin);
            self::fail('Not without the confirmation.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString('warning page', $refused->getMessage());
        }
        $service->updateCompany($company, ['name' => 'Membership Company', 'domain' => $new, 'move_staff' => true], $admin);
        self::assertSame('person@' . $new, $this->db->fetchOne('SELECT email FROM user_emails WHERE user_id = :u AND is_primary', ['u' => $person]));
        self::assertSame($new, $this->db->fetchOne('SELECT domain FROM companies WHERE id = :c', ['c' => $company]));
        self::assertSame(['owner', 'active'], array_values($this->membership($person, $company)), 'Still its staff, at the new domain.');
    }

    public function testACompanysAddressIsOnlyForItsStaff(): void
    {
        [, , $person, , $domain] = $this->company();
        /** @var AuthService $auth */
        $auth = IntegrationContainer::get()->get(AuthService::class);

        try {
            $auth->requestRegistration(['email' => 'stranger@' . $domain, 'account_type' => 'individual', 'first_name' => 'A', 'last_name' => 'Stranger', 'country' => 'ZA', 'id_number' => \CattoLearning\Tests\Support\CheckIdNumbers::free($this->db), 'accept_terms' => '1']);
            self::fail('Registering with a company\'s address is refused.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString($domain, $refused->getMessage());
        }

        $fixture = new IntegrationDataFixture($this->db);
        $outsider = $fixture->createUser('Outsider', 'outsider-' . $fixture->suffix() . '@example.test');
        try {
            $auth->requestSecondaryEmail($outsider, 'second@' . $domain);
            self::fail('Another company\'s address is refused as a second address.');
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString($domain, $refused->getMessage());
        }
        self::assertGreaterThan(0, $person);
    }

    /**
     * A company and one of its people. Every company has its founding Company Administrator: the person themselves when
     * $personFounds, else someone the fixture makes, who hands the role over where a test needs the person to hold it alone.
     *
     * @return array{PlatformAdministrationService,int,int,int,string}
     */
    private function company(bool $personFounds = false): array
    {
        $fixture = new IntegrationDataFixture($this->db);
        $suffix = $fixture->suffix();
        $domain = 'membership-' . $suffix . '.test';
        $admin = $fixture->createUser('Membership Admin', 'membership-admin-' . $suffix . '@example.test');
        $this->db->executeStatement("INSERT INTO user_roles (user_id, role_id) SELECT :u, id FROM roles WHERE role_key = 'ADMIN'", ['u' => $admin]);
        $person = $fixture->createUser('Membership Person', 'person@' . $domain);
        $company = $fixture->createCompany($admin, 'Membership Company ' . $suffix, $domain, $personFounds ? $person : null);
        if (!$personFounds) $fixture->addCompanyMember($company, $person);
        /** @var PlatformAdministrationService $service */
        $service = IntegrationContainer::get()->get(PlatformAdministrationService::class);

        return [$service, $admin, $person, $company, $domain];
    }

    /** @return array{company_role:string,status:string} */
    private function membership(int $person, int $company): array
    {
        $row = $this->db->fetchAssociative('SELECT company_role, status FROM company_users WHERE user_id = :u AND company_id = :c', ['u' => $person, 'c' => $company]);
        self::assertIsArray($row);

        return ['company_role' => (string) $row['company_role'], 'status' => (string) $row['status']];
    }
