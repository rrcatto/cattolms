declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\DevelopmentFixture;
use CattoLearning\Tests\Support\IntegrationContainer;
use PHPUnit\Framework\TestCase;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\RequestStack;

final class ActivityLogIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testAnEntryNamesWhoActedFromWhereAndMasksSecrets(): void
    {
        $container = IntegrationContainer::get();
        $person = (new DevelopmentFixture($this->db))->createUser('Activity person');
        $requests = $container->get('request_stack');
        self::assertInstanceOf(RequestStack::class, $requests);
        $requests->push(Request::create('/admin/settings', 'POST', server: ['REMOTE_ADDR' => '203.0.113.7']));
        try {
            $container->get(AuditRepository::class)->record($person, 'qa.activity_checked', ['course_id' => 12, 'api_key' => 'never-kept']);
        } finally {
            $requests->pop();
        }
        $container->get(AuditRepository::class)->record(null, 'qa.activity_without_request', []);

        $entry = $this->db->fetchAssociative("SELECT actor_id, account_person(actor_id) AS person, action, details, ip_address, request_reference FROM cattophp_activity WHERE action = 'qa.activity_checked'");
        self::assertIsArray($entry);
        self::assertSame([(string) $person, $person, '203.0.113.7'], [$entry['actor_id'], (int) $entry['person'], $entry['ip_address']], 'the person, and the visitor\'s address as it came');
        self::assertSame(['api_key' => '••••', 'course_id' => 12], json_decode((string) $entry['details'], true), 'a secret is never kept');
        self::assertNotSame('', (string) $entry['request_reference'], 'with the request\'s reference for the log');
        $system = $this->db->fetchAssociative("SELECT actor_id, actor_name, ip_address FROM cattophp_activity WHERE action = 'qa.activity_without_request'");
        self::assertSame(['actor_id' => null, 'actor_name' => 'The system', 'ip_address' => null], $system, 'nobody is the system, and no request no address');

        $this->db->executeStatement('DELETE FROM users WHERE id = :id', ['id' => $person]);
        self::assertSame(['actor_id' => null, 'actor_name' => 'A deleted account'], $this->db->fetchAssociative("SELECT actor_id, actor_name FROM cattophp_activity WHERE action = 'qa.activity_checked'"),
            'a person deleted is forgotten, what happened kept');
    }

    public function testAnActorIsAPersonOnlyWhenItIsANumber(): void
    {
        self::assertSame([42, null, null, null], array_map(static fn(mixed $value): ?int => $value === null ? null : (int) $value, array_values((array) $this->db->fetchAssociative(
            "SELECT account_person('42') AS a, account_person('owner@example.org') AS b, account_person(NULL) AS c, account_person('99999999999999999999') AS d"))));
    }
}
