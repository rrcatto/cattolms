declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Seed\SeedSchema;
use CattoLearning\Seed\SeedTableCatalog;
use DB\SQL;
use PHPUnit\Framework\TestCase;

final class SeedSchemaIntegrationTest extends TestCase
{
    private static function db(): SQL
    {
        // The shared Integration connection. This class already memoised its own; using the common
        // one means the whole suite is bounded rather than this class alone.
        return IntegrationContainer::db();
    }

    /** Table names in the public schema that actually carry a seed_token column. */
    /** @return list<string> */
    private static function tablesWithSeedToken(): array
    {
        $rows = self::db()->exec(
            "SELECT table_name FROM information_schema.columns
             WHERE table_schema = 'public' AND column_name = 'seed_token'
             ORDER BY table_name"
        );

        return array_map(static fn(array $row): string => (string) $row['table_name'], (array) $rows);
    }

    public function testBothMetadataTablesExist(): void
    {
        $rows = self::db()->exec(
            "SELECT to_regclass('public.seed_data') AS sets, to_regclass('public.seed_data_tables') AS tables"
        );

        self::assertSame('seed_data', (string) ($rows[0]['sets'] ?? ''), 'seed_data is missing; the database predates the v0.5.8 baseline.');
        self::assertSame('seed_data_tables', (string) ($rows[0]['tables'] ?? ''), 'seed_data_tables is missing.');
    }

    /**
     * Exactly the catalogued tables carry the column - no more and no fewer.
     *
     * A missing column means writes in that table silently escape the universe rules. An extra
     * one means a table was made seed-aware without being added to the catalogue, so cleanup
     * would never remove its rows and they would accumulate as permanent orphans.
     */
    public function testExactlyTheCataloguedTablesAreSeedAware(): void
    {
        $expected = SeedTableCatalog::seedAwareTables();
        sort($expected);
        $actual = self::tablesWithSeedToken();
        // seed_data itself keys on seed_token as its own identifier rather than as provenance,
        // so it is not a seed-aware business table and is not in the catalogue.
        $actual = array_values(array_diff($actual, ['seed_data']));

        self::assertSame($expected, $actual, 'The installed seed-aware tables must match SeedTableCatalog exactly.');
        // Thirty since v0.6: course_categories left the policy when categories became
        // universe-free labels. The amendment to decision D3 is recorded in SeedTableCatalog.
        self::assertCount(30, $expected, 'The approved table policy is 30 seed-aware application tables.');
    }

    /** Decision D3, asserted against the database rather than against the catalogue. */
    public function testWebSessionsIsNotSeedAwareAndCourseMediaIs(): void
    {
        $installed = self::tablesWithSeedToken();

        self::assertNotContains('web_sessions', $installed, 'web_sessions is ephemeral session infrastructure (decision D3).');
        self::assertNotContains('auth_login_tokens', $installed, 'Login tokens are invalidated by identity, not tagged.');
        self::assertContains('course_media', $installed, 'Genuine media uploaded against a SEED course is SEED (decision D3).');
        self::assertContains('auth_sessions', $installed, 'A seed identity signs in, so its sessions belong to its set.');
    }

    /**
     * Every seed-aware table has its partial index.
     *
     * Partial because the genuine universe is the common case: every SEED read filters on
     * IS NOT NULL, so indexing the NULLs would cost storage for queries that do not exist.
     */
    public function testEverySeedAwareTableHasItsPartialIndex(): void
    {
        $rows = self::db()->exec(
            "SELECT tablename, indexname, indexdef FROM pg_indexes
             WHERE schemaname = 'public' AND indexname LIKE '%_seed_token_idx'"
        );
        $definitions = [];
        foreach ((array) $rows as $row) {
            $definitions[(string) $row['indexname']] = (string) $row['indexdef'];
        }

        $missing = [];
        $notPartial = [];
        foreach (SeedTableCatalog::seedAwareTables() as $table) {
            $name = $table . '_seed_token_idx';
            if (!isset($definitions[$name])) {
                $missing[] = $name;
                continue;
            }
            if (!str_contains($definitions[$name], 'seed_token IS NOT NULL')) {
                $notPartial[] = $name;
            }
        }

        self::assertSame([], $missing, 'Seed token indexes are missing.');
        self::assertSame([], $notPartial, 'Seed token indexes must be partial on IS NOT NULL.');
    }

    public function testTheUniverseTriggerFunctionExists(): void
    {
        $rows = self::db()->exec(
            'SELECT COUNT(*)::int AS total FROM pg_proc WHERE proname = :name',
            [':name' => SeedSchema::UNIVERSE_FUNCTION]
        );

        self::assertSame(1, (int) ($rows[0]['total'] ?? 0), SeedSchema::UNIVERSE_FUNCTION . '() must exist.');
    }

    /**
     * Every guarded reference has its constraint trigger installed and enabled.
     *
     * `tgenabled` is checked because a disabled trigger is invisible in every other way: the
     * object exists, the definition is right, and nothing is enforced.
     */
    public function testEveryGuardedReferenceHasAnEnabledTrigger(): void
    {
        $rows = self::db()->exec(
            "SELECT t.tgname, t.tgenabled FROM pg_trigger t
             WHERE NOT t.tgisinternal AND t.tgname LIKE :suffix",
            [':suffix' => '%' . SeedSchema::TRIGGER_SUFFIX]
        );
        $installed = [];
        foreach ((array) $rows as $row) {
            $installed[(string) $row['tgname']] = (string) $row['tgenabled'];
        }

        $missing = [];
        $disabled = [];
        foreach (array_keys(SeedTableCatalog::sameUniverseReferences()) as $table) {
            $name = SeedSchema::triggerName($table);
            if (!isset($installed[$name])) {
                $missing[] = $name;
                continue;
            }
            // 'O' is "origin", PostgreSQL's enabled default. 'D' is disabled.
            if ($installed[$name] === 'D') $disabled[] = $name;
        }

        self::assertSame([], $missing, 'Cross-universe triggers are missing.');
        self::assertSame([], $disabled, 'Cross-universe triggers must be enabled.');
    }

    /**
     * Both System Companies exist, one per universe, with different domains.
     *
     * The domains must differ because `companies.domain` is globally unique: giving the two the
     * same domain is not a cosmetic problem, it makes the migration itself fail.
     */
    public function testOneSystemCompanyExistsInEachUniverse(): void
    {
        $rows = self::db()->exec(
            'SELECT id, name, domain, is_system, seed_token FROM companies WHERE is_system = TRUE ORDER BY seed_token NULLS FIRST'
        );

        self::assertCount(2, (array) $rows, 'There must be exactly one REAL and one SEED System Company (decision D1).');

        $real = $rows[0];
        $seed = $rows[1];
        self::assertNull($real['seed_token'], 'The first System Company must be the genuine one.');
        self::assertSame(
            SeedTableCatalog::INFRASTRUCTURE_TOKEN,
            (string) $seed['seed_token'],
            'The SEED System Company is shared infrastructure and carries the reserved token, not a set token.'
        );
        self::assertTrue((bool) $real['is_system'] && (bool) $seed['is_system']);
        self::assertNotSame(
            strtolower((string) $real['domain']),
            strtolower((string) $seed['domain']),
            'companies.domain is globally unique, so the two System Companies must differ.'
        );
    }

    /**
     * The widened uniqueness rule permits exactly one System Company per universe.
     *
     * Asserted from the index definition rather than by attempting an insert, because the insert
     * would have to be rolled back and a failed rollback would leave a second System Company
     * behind in the development database.
     */
    public function testTheSystemCompanyUniquenessRuleIsPerUniverse(): void
    {
        $rows = self::db()->exec(
            "SELECT indexdef FROM pg_indexes WHERE schemaname='public' AND indexname='companies_one_system_uq'"
        );
        $definition = (string) ($rows[0]['indexdef'] ?? '');

        self::assertNotSame('', $definition, 'companies_one_system_uq must exist.');
        self::assertStringContainsString('is_system', $definition);
        self::assertStringContainsString('seed_token IS NULL', $definition, 'The rule must key on the universe, not only on is_system.');
        self::assertStringContainsString('UNIQUE', strtoupper($definition));
    }

    /**
     * The reserved infrastructure token is not a seed set.
     *
     * If it ever appeared in seed_data it would be listed as a removable set, and removing it
     * would take the shared SEED System Company with it.
     */
    public function testTheInfrastructureTokenIsNotRecordedAsASet(): void
    {
        $rows = self::db()->exec(
            'SELECT COUNT(*)::int AS total FROM seed_data WHERE seed_token = :token::uuid',
            [':token' => SeedTableCatalog::INFRASTRUCTURE_TOKEN]
        );

        self::assertSame(0, (int) ($rows[0]['total'] ?? -1), 'Shared SEED infrastructure must never be a removable set.');
    }
}
