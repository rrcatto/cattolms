declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CompanyLogos;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Tests\Support\IntegrationDataFixture;
use PHPUnit\Framework\TestCase;

final class CompanyLogosIntegrationTest extends TestCase
{
    private Database $db;
    private CompanyLogos $logos;
    private int $admin;
    private int $company;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
        /** @var CompanyLogos $logos */
        $logos = IntegrationContainer::get()->get(CompanyLogos::class);
        $this->logos = $logos;
        $fixture = new IntegrationDataFixture($this->db);
        $suffix = $fixture->suffix();
        $this->admin = $fixture->createUser('Logo admin', 'logo-admin-' . $suffix . '@example.test');
        $this->company = $fixture->createCompany($this->admin, 'Logo Company ' . $suffix, 'logo-' . $suffix . '.test');
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testACompanyWithoutALogoHasItsAnimatedDrawnPictureAndNothingIsStored(): void
    {
        $picture = $this->logos->picture($this->company);
        self::assertTrue($picture['drawn']);
        self::assertSame('image/svg+xml', $picture['mime_type']);
        self::assertStringContainsString('@keyframes', $picture['bytes']);
        self::assertSame($picture['bytes'], $this->logos->picture($this->company)['bytes'], 'Always the same one.');
        self::assertSame(0, (int) $this->db->fetchOne('SELECT COUNT(*) FROM company_logos WHERE company_id = :id', ['id' => $this->company]));
    }

    public function testAnUploadReplacesTheDrawnPictureAndRemovingItBringsItBack(): void
    {
        $drawn = $this->logos->state($this->company);
        $this->logos->upload($this->company, '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 4 4"><circle cx="2" cy="2" r="2" fill="#123456"/></svg>', $this->admin);
        $uploaded = $this->logos->state($this->company);
        self::assertNotNull($drawn);
        self::assertNotNull($uploaded);
        self::assertTrue($uploaded['uploaded']);
        self::assertNotSame($drawn['version'], $uploaded['version'], 'A new address.');
        $picture = $this->logos->picture($this->company);
        self::assertFalse($picture['drawn']);
        self::assertStringContainsString('#123456', $picture['bytes']);
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM audit_log WHERE event_key = 'company.logo_changed' AND user_id = :id", ['id' => $this->admin]), 'Logged.');

        $this->logos->remove($this->company, $this->admin);
        self::assertTrue($this->logos->picture($this->company)['drawn']);
        self::assertSame($drawn, $this->logos->state($this->company), 'The drawn picture, at its old address.');
    }

    public function testAPageOfCompanyRowsGetsTheirPictureAddresses(): void
    {
        $rows = $this->logos->withPictures([['id' => $this->company, 'name' => 'Logo Company'], ['id' => 999999999, 'name' => 'Gone']]);
        self::assertStringStartsWith('/admin/companies/' . $this->company . '/logo?v=s', (string) $rows[0]['logo_url']);
        self::assertFalse($rows[0]['logo_uploaded']);
        self::assertSame('', $rows[1]['logo_url'], 'A company that does not exist has none.');
    }

    public function testAnUploadForACompanyThatDoesNotExistIsRefused(): void
    {
        $this->expectException(\RuntimeException::class);
        $this->logos->upload(999999999, '<svg xmlns="http://www.w3.org/2000/svg"/>', $this->admin);
    }
}
