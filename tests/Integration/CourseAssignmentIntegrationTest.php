    private function enrolments(int $courseId): int
    {
        $rows = $this->db->fetchAllAssociative(
            'SELECT COUNT(*)::int AS total FROM course_enrolments WHERE course_id = :course_id AND user_id = :user_id',
            ['course_id' => $courseId, 'user_id' => $this->staffId]
        );

        return (int) $rows[0]['total'];
    }

    /** A company's own course costs it nothing and consumes no credit. */
    public function testAssigningAnOwnedCourseConsumesNoCredit(): void
    {
        // A stray credit exists and must be left alone: a company must not pay for what it made.
        $credit = $this->administration->addCredit($this->companyId, null, $this->ownedCourse, 31536000, 2, 'qa', 'untouched', $this->adminId);

        $result = $this->service->assignCourseToStaff($this->companyId, $this->ownedCourse, $this->staffId, 31536000, $this->adminId);

        self::assertSame('owned', $result['entitlement']);
        self::assertGreaterThan(0, $result['enrolment_id']);
        self::assertSame(1, $this->enrolments($this->ownedCourse));

        $used = $this->db->fetchAllAssociative(
            'SELECT COUNT(*)::int AS total FROM course_credit_allocations WHERE credit_id = :id',
            ['id' => $credit]
        );
        self::assertSame(0, (int) $used[0]['total'], 'Ownership is the entitlement; no seat is spent.');
    }

    /** A course the company does not own takes one seat. */
    public function testAssigningABoughtCourseTakesOneSeat(): void
    {
        $credit = $this->administration->addCredit($this->companyId, null, $this->boughtCourse, 31536000, 2, 'qa', 'seats', $this->adminId);

        $result = $this->service->assignCourseToStaff($this->companyId, $this->boughtCourse, $this->staffId, 31536000, $this->adminId);

        self::assertSame('credit', $result['entitlement']);
        self::assertSame(1, $this->enrolments($this->boughtCourse));

        $used = $this->db->fetchAllAssociative(
            "SELECT COUNT(*)::int AS total FROM course_credit_allocations
              WHERE credit_id = :id AND status IN ('assigned','consumed')",
            ['id' => $credit]
        );
        self::assertSame(1, (int) $used[0]['total'], 'Exactly one seat, not two and not none.');
    }

    /**
     * With no entitlement the assignment fails and leaves nothing behind.
     *
     * The important half is the second: a refusal that had already created the enrolment would be a
     * course somebody holds and nobody paid for.
     */
    public function testAssigningWithoutEntitlementIsRefusedAndEnrolsNobody(): void
    {
        try {
            $this->service->assignCourseToStaff($this->companyId, $this->boughtCourse, $this->staffId, 31536000, $this->adminId);
            self::fail('An assignment the company cannot cover must be refused.');
        } catch (RuntimeException $exception) {
            self::assertStringContainsString('no free seat', $exception->getMessage());
        }

        self::assertSame(0, $this->enrolments($this->boughtCourse));
    }

