    /** Every assignment tells the learner where to start. */
    public function testTheLearnerIsTold(): void
    {
        $this->service->assignCourseToStaff($this->companyId, $this->ownedCourse, $this->staffId, 31536000, $this->adminId);

        $notices = array_values(array_filter(
            $this->mailer->messages,
            static fn(array $message): bool => $message['type'] === 'course_enrolment_notice'
