Description:
A company administrator assigning a course to a staff member.

The owner's second workflow - buy credits, assign, tell the person outside the LMS - and the
counterpart to approving a request. Both end at the same place, so both obey the same two rules:

  owned      the company made the course, so training its own staff costs nothing and no credit is
             looked for or consumed;
  credited   the company holds a credit with a free seat, and the seat is taken.

Anything else is refused rather than recorded. Until Commerce exists there is nothing to pay with, so
an assignment the company cannot cover has to fail loudly - a silently recorded enrolment nobody paid
for is the state this platform has already shipped once, in "approved" requests that enrolled nobody.

The membership check is here because both ids arrive from a form. Without it a company administrator
could put anybody on the platform onto a course using their own company's entitlement, and nothing
about the request would look wrong.

