declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\CheckNames;
use CattoLearning\Tests\Support\IntegrationContainer;
use PHPUnit\Framework\TestCase;

final class CheckNamesIntegrationTest extends TestCase
{
    /** Enough draws to meet every free title many times over (40 titles at most). */
    private const DRAWS = 400;

    private Database $db;
    private string $file;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->file = (string) tempnam(sys_get_temp_dir(), 'held-names');
        CheckNames::keepHeldIn($this->file);
    }

    protected function tearDown(): void
    {
        CheckNames::keepHeldIn(null);
        @unlink($this->file);
    }

    public function testANameHeldForLaterIsNeverDrawnUntilItIsReleased(): void
    {
        $fixture = new CheckNames($this->db);
        $held = $fixture->course(true)['title'];
        self::assertSame(['course:' . strtolower($held)], $fixture->held(), 'The fixture keeps what it holds, for its clean-up.');

        $drawn = $this->draws();
        self::assertNotContains($held, $drawn, 'No other check is given the title while it is held.');
        self::assertGreaterThan(1, count(array_unique($drawn)), 'Titles drawn to be made at once are not held: they come again.');
        $other = new CheckNames($this->db);
        self::assertNotSame($held, $other->course(true)['title'], 'Nor is it held for another check.');
        CheckNames::release($other->held());

        CheckNames::release($fixture->held());
        self::assertContains($held, $this->draws(), 'Released, it is drawn again.');
    }

    /** @return list<string> course titles drawn one at a time, as fixtures draw the ones they make at once */
    private function draws(): array
    {
        $drawn = [];
        for ($i = 0; $i < self::DRAWS; $i++) $drawn[] = (new CheckNames($this->db))->course()['title'];

        return $drawn;
    }
}
