/*
Generated by: Claude Code CLI

Date time: 2026/09/10 03:05 SAST

Version: 0.7

Description:
The HTML this platform serves is indented so a human can read its structure.

The owner has asked for this more than once, and the failure it guards against is not a template
somebody wrote carelessly - the templates are tab-indented and stay that way. It is markup injected
into a finished page, which is written in PHP and has no template to keep it honest. The generator
meta tag was appended with a fixed single tab, so it sat at the wrong depth under every theme whose
head element is itself indented, which is all of them.

What this asserts, against pages actually rendered through the theme layer:

  the document opens on its own line and head is on its own line - not run onto the tag before it;
  every injected tag sits one step deeper than the element that contains it;
  no line runs several block-level tags together.

Inline SVG is deliberately exempt. An icon inside a link is one token to a reader and breaking it
across lines introduces rendered whitespace inside the link, so those stay on one line by design.

Changelog:
2026/09/10 03:05 SAST
- Created after the generator tag was found at the wrong indent depth in all five themes.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Kernel;
use PHPUnit\Framework\TestCase;
use Symfony\Component\HttpFoundation\Request;

final class ServedHtmlIndentationTest extends TestCase
{
    public function testTheDocumentHeadIsOnItsOwnLine(): void
    {
        foreach (self::pages() as $name => $html) {
            $lines = explode("\n", $html);

            $headLine = null;
            foreach ($lines as $index => $line) {
                if (str_contains($line, '<head')) {
                    $headLine = $index;
                    break;
                }
            }

            self::assertNotNull($headLine, $name . ' has no head element.');
            self::assertSame(
                '<head>',
                trim($lines[$headLine]),
                $name . ': the head tag shares its line with something else.'
            );
        }
    }

    public function testInjectedMarkupSitsOneStepInsideItsParent(): void
    {
        foreach (self::pages() as $name => $html) {
            $lines = explode("\n", $html);
            foreach ($lines as $index => $line) {
                if (!str_contains($line, '<head')) {
                    continue;
                }
                $headIndent = self::indentOf($line);
                $injected = $lines[$index + 1] ?? '';

                self::assertStringContainsString('name="generator"', $injected, $name . ': the generator tag is missing.');
                self::assertSame(
                    $headIndent . "\t",
                    self::indentOf($injected),
                    $name . ': the generator tag is not one step inside head.'
                );
                break;
            }
        }
    }

    public function testNoLineRunsSeveralBlockTagsTogether(): void
    {
        foreach (self::pages() as $name => $html) {
            foreach (explode("\n", $html) as $index => $line) {
                // Inline SVG is one token to a reader and must stay on one line: breaking it puts
                // rendered whitespace inside the link that holds it.
                if (str_contains($line, '<svg') || str_contains($line, '</svg>')) {
                    continue;
                }
                $blocks = preg_match_all('/<(?:div|section|nav|header|footer|main|article|aside|table|form|ul|ol)\b/', $line);
                self::assertLessThanOrEqual(
                    2,
                    $blocks,
                    sprintf('%s line %d runs %d block tags together: %s', $name, $index + 1, $blocks, trim(substr($line, 0, 120)))
                );
            }
        }
    }

    /**
     * Public pages, served by the kernel exactly as a browser receives them.
     *
     * Through the kernel rather than the renderer, because the tag this guards is injected after
     * the theme has finished - so rendering a template alone would never see it.
     *
     * @return array<string,string>
     */
    private static function pages(): array
    {
        $instanceRoot = (string) CliBootstrap::boot()['instance_root'];
        $kernel = new Kernel('test', true, $instanceRoot);
        $kernel->boot();

        $pages = [];
        foreach (['/' => 'home', '/about' => 'about', '/contact' => 'contact'] as $path => $name) {
            $response = $kernel->handle(Request::create($path));
            self::assertSame(200, $response->getStatusCode(), $path . ' did not render.');
            $pages[$name] = (string) $response->getContent();
        }

        return $pages;
    }

    private static function indentOf(string $line): string
    {
        preg_match('/^[ \t]*/', $line, $match);

        return $match[0];
    }
}
