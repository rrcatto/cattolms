        }
    }

    public function testATemplateIsCreatedEditedPreviewedAndPublishedAsTheOnlyCurrentOneOfItsType(): void
    {
        $id = $this->documents->create($this->admin, ['document_type' => 'invoice', 'name' => 'Branded invoice', 'description' => 'For the test']);
        $template = $this->templates->template($id);
        self::assertFalse((bool) $template['is_current'], 'A new template is not used until it is published.');
        $draft = $this->templates->draft($id);
        self::assertSame(1, (int) $draft['version_number']);
        self::assertSame(DocumentTemplateDefaults::for(DocumentType::Invoice)['html'], $draft['html'], 'It starts from the standard template.');

        $this->documents->saveDraft($this->admin, $id, $this->content('<h1>Marker-A {{ invoice.number }}</h1>', 'Saved A'));
        $preview = $this->documents->preview($id, $this->content('<h1>Marker-B {{ invoice.number }}</h1>'));
        self::assertStringContainsString('Marker-B INV-000412', $preview->body, 'Preview renders unsaved edits with sample data.');
        self::assertStringContainsString('Marker-A', $this->templates->draft($id)['html'], 'Previewing saves nothing.');
        self::assertStringContainsString('Marker-A INV-000412', $this->documents->previewVersion((int) $draft['id'])->body, 'The saved draft previews through the same renderer.');

        $published = $this->documents->publish($this->admin, $id);
        self::assertSame(1, $published['version_number']);
        self::assertTrue((bool) $this->templates->template($id)['is_current']);
        self::assertSame(1, (int) $this->db->fetchOne("SELECT COUNT(*) FROM document_templates WHERE document_type = 'invoice' AND is_current"), 'One current template per document type.');
        self::assertStringContainsString('Marker-A INV-000412', $this->renderer->renderCurrent(DocumentType::Invoice, DocumentSampleData::for(DocumentType::Invoice))->body);
        self::assertNull($this->templates->draft($id), 'Publishing uses up the draft.');

        $audit = $this->db->fetchAllAssociative("SELECT event_key, metadata::text AS metadata FROM audit_log WHERE user_id = :id AND event_key LIKE 'document_template.%' ORDER BY id", ['id' => $this->admin->id]);
        self::assertSame(['document_template.created', 'document_template.version_created', 'document_template.draft_edited', 'document_template.published'], array_column($audit, 'event_key'));
        foreach ($audit as $row) {
            self::assertStringNotContainsString('Marker-A', $row['metadata'], 'The audit refers to versions; it never stores the HTML.');
        }
        self::assertStringContainsString('"version_id"', $audit[3]['metadata']);
    }

    public function testAPublishedVersionNeverChangesAndStillRendersExactlyAsItWas(): void
    {
        $id = $this->documents->create($this->admin, ['document_type' => 'certificate', 'name' => 'Versioned certificate']);
        $this->documents->saveAndPublish($this->admin, $id, $this->content('<p>Edition-1 {{ learner.name }}</p>', null, 'certificate'));
        $first = (int) $this->templates->template($id)['published_version_id'];

        // Editing after publication starts a new draft; the published version is untouched.
        $this->documents->saveDraft($this->admin, $id, $this->content('<p>Edition-2 {{ learner.name }}</p>', 'Second edition', 'certificate'));
        $draft = $this->templates->draft($id);
        self::assertSame(2, (int) $draft['version_number']);
        self::assertSame($first, (int) $draft['based_on_version_id']);
        self::assertStringContainsString('Edition-1', $this->templates->version($first)['html']);
        $this->documents->publish($this->admin, $id);

        $sample = DocumentSampleData::for(DocumentType::Certificate);
        self::assertStringContainsString('Edition-1 Thandiwe Mokoena', $this->renderer->renderVersion($first, $sample)->body, 'An old document re-renders from its own version.');
        self::assertStringNotContainsString('Edition-2', $this->renderer->renderVersion($first, $sample)->body);
        self::assertStringContainsString('Edition-2', $this->renderer->renderCurrent('certificate', $sample)->body);

        foreach (["UPDATE document_template_versions SET html = '<p>changed</p>' WHERE id = :id", 'DELETE FROM document_template_versions WHERE id = :id',
            'UPDATE document_template_versions SET published_by_user_id = ' . $this->student->id . ' WHERE id = :id'] as $sql) {
            $this->db->executeStatement('SAVEPOINT guard');
            try {
                $this->db->executeStatement($sql, ['id' => $first]);
                self::fail('The database refuses: ' . $sql);
            } catch (Throwable $refused) {
                self::assertStringContainsString('published document template version cannot be changed', $refused->getMessage());
                $this->db->executeStatement('ROLLBACK TO SAVEPOINT guard');
            }
        }

        // Deleting the account that published it clears the author and nothing else.
        $before = $this->templates->version($first);
        $this->db->executeStatement('UPDATE document_template_versions SET published_by_user_id = NULL, created_by_user_id = NULL WHERE id = :id', ['id' => $first]);
        $after = $this->templates->version($first);
        foreach (['html', 'css', 'version_number', 'published_at', 'page_size'] as $field) {
            self::assertSame($before[$field], $after[$field], $field . ' is unchanged.');
        }
        self::assertNull($after['published_by_name']);
    }

    public function testInvalidContentIsReportedAndNothingIsSaved(): void
    {
        $id = $this->documents->create($this->admin, ['document_type' => 'invoice', 'name' => 'Careful invoice']);
        $before = $this->templates->draft($id)['html'];
        try {
            $this->documents->saveDraft($this->admin, $id, ['page_size' => 'A3'] + $this->content("<p>{{ invoice.nubmer }}</p>\n{{#each items}}<script>x</script>"));
            self::fail('An invalid template is refused.');
        } catch (TemplateValidationException $invalid) {
            $all = implode(' ', $invalid->errors);
            foreach (['Unknown placeholder {{ invoice.nubmer }}', 'is never closed with {{/each}}', '<script> elements', 'Unsupported page size "A3"'] as $expected) {
                self::assertStringContainsString($expected, $all);
            }
        }
        self::assertSame($before, $this->templates->draft($id)['html'], 'Nothing was saved.');

        $this->documents->publish($this->admin, $id);
        $this->expectException(RuntimeException::class);
        $this->expectExceptionMessage('There is no draft to publish');
        $this->documents->publish($this->admin, $id);
    }

    public function testAnEarlierVersionIsReusedThroughANewDraftAndHistoryIsNeverRewritten(): void
    {
        $id = $this->documents->create($this->admin, ['document_type' => 'receipt', 'name' => 'Receipt with history']);
        $this->documents->saveAndPublish($this->admin, $id, $this->content('<p>Old {{ receipt.number }}</p>', null, 'receipt'));
        $v1 = (int) $this->templates->template($id)['published_version_id'];
        $this->documents->saveAndPublish($this->admin, $id, $this->content('<p>New {{ receipt.number }}</p>', null, 'receipt'));

        $draftId = $this->documents->draftFromVersion($this->admin, $id, $v1);
        $draft = $this->templates->version($draftId);
        self::assertSame(3, (int) $draft['version_number']);
        self::assertSame('<p>Old {{ receipt.number }}</p>', $draft['html']);
        self::assertSame($v1, (int) $draft['based_on_version_id']);
        self::assertCount(3, $this->templates->versions($id));
        try {
            $this->documents->draftFromVersion($this->admin, $id, $v1);
            self::fail('A second draft is refused.');
        } catch (RuntimeException $refused) {
            self::assertStringContainsString('already has a draft', $refused->getMessage());
        }
        $this->documents->discardDraft($this->admin, $id);
        self::assertNull($this->templates->draft($id));
        self::assertCount(2, $this->templates->versions($id), 'Discarding a draft leaves the published versions.');

        try {
            $this->documents->setArchived($this->admin, $id, true);
            self::fail('The current template cannot be archived.');
        } catch (RuntimeException $refused) {
            self::assertStringContainsString('cannot be archived', $refused->getMessage());
        }
        $other = $this->documents->create($this->admin, ['document_type' => 'receipt', 'name' => 'Spare receipt']);
        $this->documents->setArchived($this->admin, $other, true);
        $this->expectExceptionMessage('archived');
        $this->documents->saveDraft($this->admin, $other, $this->content('<p>{{ receipt.number }}</p>', null, 'receipt'));
    }

    public function testThePagesListEditPreviewPublishAndShowHistory(): void
    {
        $id = $this->documents->create($this->admin, ['document_type' => 'credit_note', 'name' => 'Page credit note']);
        $list = InProcessPage::run($this->admin, DocumentTemplateController::class, 'index', [], null, ['type' => 'credit_note']);
        self::assertSame(200, $list['status']);
        foreach (['Page credit note', 'Standard credit note', 'Document templates'] as $text) self::assertStringContainsString($text, $list['body']);
        self::assertStringNotContainsString('Standard invoice', $list['body'], 'The type filter applies.');

        $editor = InProcessPage::run($this->admin, DocumentTemplateController::class, 'show', ['id' => $id]);
        self::assertSame(200, $editor['status']);
        foreach (['sandbox=""', 'srcdoc="', 'Version history', '{{ credit_note.number }}', 'Draft version 1', 'name="intent" value="publish"'] as $text) self::assertStringContainsString($text, $editor['body']);
        self::assertStringNotContainsString('<script>', explode('srcdoc="', $editor['body'])[1] ?? '', 'The preview is escaped into the frame.');

        $post = ['csrf' => $_SESSION['csrf'], 'intent' => 'preview'] + $this->content('<p>Page-Marker {{ credit_note.number }}</p>', null, 'credit_note');
        $preview = InProcessPage::run($this->admin, DocumentTemplateController::class, 'update', ['id' => $id], $post);
        self::assertSame(200, $preview['status']);
        self::assertStringContainsString('Page-Marker CN-000027', html_entity_decode($preview['body']), 'Preview shows the edits with sample data.');
        self::assertStringContainsString('unsaved changes', $preview['body']);

        $bad = InProcessPage::run($this->admin, DocumentTemplateController::class, 'update', ['id' => $id], array_replace($post, ['intent' => 'save', 'html' => '<p>{{ credit_note.numbr }}</p>']));
        self::assertStringEndsWith('#template-errors', (string) $bad['location']);
        $shown = InProcessPage::run($this->admin, DocumentTemplateController::class, 'show', ['id' => $id]);
        self::assertStringContainsString('did you mean {{ credit_note.number }}', html_entity_decode($shown['body']), 'The error is shown with the submitted content kept.');
        self::assertStringContainsString('credit_note.numbr', html_entity_decode($shown['body']));

        $published = InProcessPage::run($this->admin, DocumentTemplateController::class, 'update', ['id' => $id], ['intent' => 'publish'] + $post);
        self::assertSame('/admin/documents/templates/' . $id . '#template-preview', $published['location']);
        $version = (int) $this->templates->template($id)['published_version_id'];
        $page = InProcessPage::run($this->admin, DocumentTemplateController::class, 'version', ['id' => $id, 'version' => $version]);
        self::assertSame(200, $page['status']);
        self::assertStringContainsString('Page-Marker CN-000027', html_entity_decode($page['body']));
        $pdf = InProcessPage::run($this->admin, DocumentTemplateController::class, 'samplePdf', ['id' => $id, 'version' => $version]);
        self::assertSame(200, $pdf['status']);
        self::assertStringStartsWith('%PDF-', $pdf['body']);
    }

    public function testOnlyDocumentTemplatePermissionsOpenThePages(): void
    {
        foreach (['index' => [], 'show' => ['id' => (int) $this->templates->currentVersion(DocumentType::Invoice)['template_id']]] as $method => $attributes) {
