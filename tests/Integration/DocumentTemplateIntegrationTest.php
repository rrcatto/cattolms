    private Database $db;
    private DocumentTemplateRepository $templates;
    private DocumentTemplateRenderer $renderer;
    private CertificateDesignRepository $designs;
    private int $adminId;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
        $container = IntegrationContainer::get();
        $this->templates = $container->get(DocumentTemplateRepository::class);
        $this->renderer = $container->get(DocumentTemplateRenderer::class);
        $this->designs = $container->get(CertificateDesignRepository::class);
        $fixture = new DevelopmentFixture($this->db);
        $this->adminId = $fixture->createUser('Template administrator', 'template-admin-' . $fixture->suffix() . '@example.test');
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testEveryFinancialDocumentHasItsInstalledPublishedDefault(): void
    {
        foreach ([DocumentType::Invoice, DocumentType::Receipt, DocumentType::CreditNote] as $type) {
            $current = $this->templates->currentVersion($type);
            self::assertNotNull($current, $type->value . ' has a current template.');
            self::assertSame('published', $current['state']);
            self::assertSame(DocumentTemplateDefaults::for($type)['html'], $current['html'], 'The installed default is the source default.');
            $document = $this->renderer->renderCurrent($type->value, DocumentSampleData::for($type));
            self::assertSame((int) $current['id'], $document->reference()['template_version_id'], 'A rendered document names the exact version it came from.');
            self::assertSame($type->defaultSettings()->orientation, $document->settings->orientation);
        }
    }

    public function testTheSixLooksAreInstalledAsDesignsWithClassicTheDefault(): void
    {
        $designs = $this->designs->list();
        $byName = array_column($designs, null, 'name');
        $compiler = new CertificateDesignCompiler();
        foreach (CertificateLooks::installed() as $key => $look) {
            self::assertArrayHasKey($look->name, $byName, $look->name . ' is installed.');
            $installed = $byName[$look->name];
            self::assertSame($key, $installed['design']->look);
            $version = $this->templates->version((int) $installed['published_version_id']);
            self::assertSame($compiler->compile(CertificateDesign::starter($key))['html'], $version['html'], 'The installed design is its look’s starter, compiled.');
            self::assertSame(['A4', 'landscape', 0], [$version['page_size'], $version['page_orientation'], (int) $version['margin_top_mm']]);
            $document = $this->renderer->renderVersion((int) $version['id'], DocumentSampleData::for(DocumentType::Certificate));
            self::assertStringContainsString('Thandiwe Mokoena', $document->body);
            self::assertStringContainsString('src="data:image/png;base64,', $document->body, 'The stored background is embedded.');
        }
        self::assertSame((int) $byName['Classic']['id'], $this->designs->defaultId());
        self::assertTrue($byName['Classic']['is_current']);
    }

    public function testAPublishedVersionNeverChangesAndStillRendersExactlyAsItWas(): void
    {
        $compiled = (new CertificateDesignCompiler())->compile(CertificateDesign::starter('modern'));
        $id = $this->designs->create('Versioned design', '', CertificateDesign::starter('modern')->toArray(), $compiled['html'], $compiled['css'], $compiled['settings'], $this->adminId);
        $first = (int) $this->designs->find($id)['published_version_id'];
        $before = $this->renderer->renderVersion($first, DocumentSampleData::for(DocumentType::Certificate))->html;

        $edited = new CertificateDesign('modern', null, 'centre', 'serif', '#1F3A5F', null, '<p class="cert-name">' . \CattoLearning\Course\Certificate\CertificateWording::chip('learner.name') . '</p><p>Edition two</p>', '', '', null, '');
        $again = (new CertificateDesignCompiler())->compile($edited);
        $this->designs->save($id, 'Versioned design', $edited->toArray(), $again['html'], $again['css'], $again['settings'], $this->adminId);
        self::assertNotSame($first, (int) $this->designs->find($id)['published_version_id'], 'A save is a new version.');
        self::assertSame($before, $this->renderer->renderVersion($first, DocumentSampleData::for(DocumentType::Certificate))->html, 'The old version draws exactly as it did.');

        foreach (["UPDATE document_template_versions SET html = '<p>changed</p>' WHERE id = :id", 'DELETE FROM document_template_versions WHERE id = :id',
            'UPDATE document_template_versions SET published_by_user_id = NULL, design = NULL WHERE id = :id'] as $sql) {
            $this->db->executeStatement('SAVEPOINT guard');
            try {
                $this->db->executeStatement($sql, ['id' => $first]);
                self::fail('The database refuses: ' . $sql);
            } catch (Throwable $refused) {
                self::assertStringContainsString('published document template version cannot be changed', $refused->getMessage());
                $this->db->executeStatement('ROLLBACK TO SAVEPOINT guard');
            }
        }
        // Deleting the account that published it clears the author and nothing else.
        $this->db->executeStatement('UPDATE document_template_versions SET published_by_user_id = NULL, created_by_user_id = NULL, updated_by_user_id = NULL WHERE id = :id', ['id' => $first]);
        self::assertNull($this->templates->version($first)['published_by_name']);
    }

    public function testAStoredImageNeverChangesAndTheRendererEmbedsOnlyStoredImages(): void
    {
        $assets = IntegrationContainer::get()->get(DocumentAssetRepository::class);
        $png = (string) base64_decode('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==');
        $sha = $assets->store($png, 'image/png', 1, 1, $this->adminId);
        self::assertSame($sha, $assets->store($png, 'image/png', 1, 1, $this->adminId), 'The same picture is stored once.');
        self::assertSame(1, (int) $this->db->fetchOne('SELECT COUNT(*) FROM document_assets WHERE sha256 = :sha', ['sha' => $sha]));
        foreach (["UPDATE document_assets SET mime_type = 'image/jpeg' WHERE sha256 = :sha", 'DELETE FROM document_assets WHERE sha256 = :sha'] as $sql) {
            $this->db->executeStatement('SAVEPOINT guard');
            try {
                $this->db->executeStatement($sql, ['sha' => $sha]);
                self::fail('The database refuses: ' . $sql);
            } catch (Throwable $refused) {
                self::assertStringContainsString('stored document image cannot be changed', $refused->getMessage());
                $this->db->executeStatement('ROLLBACK TO SAVEPOINT guard');
            }
        }
        $this->db->executeStatement('UPDATE document_assets SET created_by_user_id = NULL WHERE sha256 = :sha', ['sha' => $sha]);

        $settings = DocumentType::Certificate->defaultSettings();
        $data = DocumentSampleData::for(DocumentType::Certificate);
        $document = $this->renderer->renderSource(DocumentType::Certificate, '<img src="asset:' . $sha . '" alt=""><p>{{ learner.name }}</p>', '.x{background:url(asset:' . $sha . ')}', $settings, $data);
        self::assertStringContainsString('src="data:image/png;base64,' . base64_encode($png) . '"', $document->body);
        self::assertStringContainsString('url("data:image/png;base64,', $document->html);
        $this->expectException(RuntimeException::class);
        $this->expectExceptionMessage('is not stored');
        $this->renderer->renderSource(DocumentType::Certificate, '<img src="asset:' . str_repeat('0', 64) . '" alt=""><p>{{ learner.name }}</p>', '', $settings, $data);
    }
