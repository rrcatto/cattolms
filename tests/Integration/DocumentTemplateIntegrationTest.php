        $viewer = new CurrentUser($this->student->id, Uuid::v4(), 'viewer@example.test', 'Viewer', ['STUDENT'], ['ACCOUNT.VIEW', 'DOCUMENT.TEMPLATE.VIEW'], Uuid::v4());
        $page = InProcessPage::run($viewer, DocumentTemplateController::class, 'show', ['id' => (int) $this->templates->currentVersion(DocumentType::Invoice)['template_id']]);
        self::assertSame(200, $page['status']);
        self::assertStringNotContainsString('name="intent"', $page['body'], 'Viewing does not offer editing.');
        $this->expectException(AccessDeniedHttpException::class);
        InProcessPage::run($viewer, DocumentTemplateController::class, 'store', [], ['csrf' => $_SESSION['csrf'], 'document_type' => 'invoice', 'name' => 'Not allowed']);
    }

    /** @return array<string,string> */
    private function content(string $html, ?string $note = null, string $type = 'invoice'): array
    {
        $settings = DocumentType::from($type)->defaultSettings()->toArray();
        return ['html' => $html, 'css' => 'p{margin:0}', 'change_note' => $note ?? ''] + array_map('strval', $settings);
    }
