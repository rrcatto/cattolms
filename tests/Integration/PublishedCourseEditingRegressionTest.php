declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Course\CourseRepository;
use CattoLearning\Course\CourseService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\DevelopmentFixture;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class PublishedCourseEditingRegressionTest extends TestCase
{
    public function testPublishedCourseRequiresPriceAndRemainsEditableInPlace(): void
    {
        $container = CliBootstrap::boot()['container'];
        /** @var Database $db */
        $db = $container->get(Database::class);
        /** @var CourseService $service */
        $service = $container->get(CourseService::class);
        /** @var CourseRepository $repository */
        $repository = $container->get(CourseRepository::class);
        $fixture = new DevelopmentFixture($db);
        $suffix = $fixture->suffix();

        try {
            $ownerId = $fixture->createUser('QA publisher ' . $suffix);
            $companyId = $fixture->createCompany($ownerId, 'QA Publisher ' . $suffix, 'qa-publish-' . $suffix . '.example.test');
            $slug = 'qa-publish-' . $suffix;
            $courseId = $fixture->createCourse($ownerId, $companyId, $slug, 'Original QA Course ' . $suffix, 'draft');

            try {
                $service->changeStatus($courseId, 'published', $ownerId);
                self::fail('Expected publishing without a price option to fail.');
            } catch (InvalidArgumentException $e) {
                self::assertStringContainsString('price', strtolower($e->getMessage()));
            }

            $fixture->createPriceVariant($courseId, $ownerId, 2592000, 12500, true);
            $service->changeStatus($courseId, 'published', $ownerId);

            $published = $repository->findById($courseId);
            self::assertNotNull($published);
            self::assertSame('published', (string) $published['status']);
            $publicId = (string) $published['public_id'];
            $revision = (int) $published['revision_number'];

            $service->updateCourse($courseId, [
                'title' => 'Updated QA Course ' . $suffix,
                'summary' => 'Updated while already published.',
                'description_html' => '<p>Updated published content.</p>',
            ], $ownerId);

            $updated = $repository->findById($courseId);
            self::assertNotNull($updated);
            self::assertSame($courseId, (int) $updated['id']);
            self::assertSame($publicId, (string) $updated['public_id']);
            self::assertSame($revision, (int) $updated['revision_number']);
            self::assertSame('published', (string) $updated['status']);
            self::assertSame('Updated QA Course ' . $suffix, (string) $updated['title']);
            self::assertSame('Updated while already published.', (string) $updated['summary']);

            $catalogue = $repository->findBySlug($slug);
            self::assertNotNull($catalogue);
            self::assertSame('Updated QA Course ' . $suffix, (string) $catalogue['title']);
        } finally {
            $fixture->cleanup();
        }
    }
}