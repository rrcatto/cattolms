    public function testABundleCreditIsBoughtOnlyAfterTheRuleIsTickedAndGivesOnePersonEveryCourse(): void
    {
        self::assertContains($this->bundle['offer'], array_map(static fn(array $offer): int => (int) $offer['id'], $this->purchases->bundleOffers()), 'The bundle is offered to the company.');
        $this->purchases->addBundle($this->buyer, $this->companyId, $this->bundle['offer'], 4);
        $review = $this->purchases->startCheckout($this->buyer, $this->companyId);
        self::assertTrue($review['has_bundles']);
        self::assertSame(['bundle_credit', 4, 1200000], [$review['items'][0]['fulfilment_type'], $review['items'][0]['quantity'], $review['items'][0]['line_total_minor']]);
        try {
            $this->purchases->place($this->buyer, $this->companyId, $review['purchase_key'], $review['quote'], BillingFixture::company(), 'dummy', 'demo_success', false, true);
            self::fail('The order is placed only once the rule is ticked.');
        } catch (RuntimeException $refused) {
            self::assertStringContainsString('Tick that each bundle credit is for one person', $refused->getMessage());
        }
        $orderId = $this->purchases->place($this->buyer, $this->companyId, $review['purchase_key'], $review['quote'], BillingFixture::company(), 'dummy', 'demo_success', false, true, false, true);
        $order = $this->db->fetchAssociative('SELECT state, snapshot::text AS snapshot FROM commerce_orders WHERE id = :id', ['id' => $orderId]);
        self::assertSame('fulfilled', $order['state']);
        self::assertSame(BundleCredits::ACCEPT, json_decode((string) $order['snapshot'], true)['consent']['bundle_use'], 'The order keeps what was ticked.');
        $invoice = (string) $this->db->fetchOne("SELECT document_data::text FROM commerce_documents WHERE order_id = :id AND kind = 'invoice'", ['id' => $orderId]);
        self::assertMatchesRegularExpression('/4 bundle credits at R\s3\s000,00 each, each for one person who gets every course in the bundle/u', $invoice);
        $credit = $this->credits->forCompany($this->companyId)[0];
        self::assertSame([4, 0, 4, ['Excel for Accountants', 'Basic Bookkeeping', 'Stock Control']], [$credit['held'], $credit['given'], $credit['left'], $credit['course_titles']]);
        $creditId = (int) $credit['id'];
        $administration = IntegrationContainer::get()->get(AdministrationRepository::class);
        $learning = IntegrationContainer::get()->get(LearningService::class);
        $slug = fn(int $course): string => (string) $this->db->fetchOne('SELECT slug FROM courses WHERE id = :id', ['id' => $course]);
        $open = fn(int $user): array => array_map('intval', $this->db->fetchFirstColumn("SELECT course_id FROM course_enrolments WHERE user_id = :user AND status IN ('assigned','active') ORDER BY course_id", ['user' => $user]));

        // Given to one person: every course, with the bundle's access period; removed before any start, all go and it comes back whole.
        $lindiwe = $this->staff('Lindiwe Khumalo', 'lindiwe');
        $given = $this->credits->assign($this->companyId, $creditId, $lindiwe, $this->buyer->id);
        self::assertSame($this->courses, $open($lindiwe));
        $administration->removeEnrolmentAccess($given['enrolment_ids'][0], $this->buyer->id, 'Given to the wrong person.');
        self::assertSame([], $open($lindiwe), 'All three courses go.');
        self::assertSame(0, $this->credits->forCompany($this->companyId)[0]['given'], 'The credit is back, whole.');

        // Given and started: the credit is used.
        $ayesha = $this->staff('Ayesha Patel', 'ayesha');
        $this->credits->assign($this->companyId, $creditId, $ayesha, $this->buyer->id);
        $learning->start($ayesha, $slug($this->courses[2]));
        self::assertSame('consumed', $this->db->fetchOne('SELECT status FROM bundle_credit_allocations WHERE user_id = :user', ['user' => $ayesha]), 'Starting any course of it uses the whole credit.');

        // Someone who already has a course not yet started: shown which, then given it anyway; their own period and the bundle's add up.
        $sipho = $this->staff('Sipho Nkosi', 'sipho');
        $held = IntegrationContainer::get()->get(CourseRepository::class)->grantCourse($sipho, $this->courses[1], 15552000, $this->buyer->id);
        self::assertSame(['Basic Bookkeeping'], array_column($this->credits->heldCourses($this->companyId, $creditId, $sipho), 'title'), 'The page names the course they have.');
        try {
            $this->credits->assign($this->companyId, $creditId, $sipho, $this->buyer->id);
            self::fail('Without the Company Administrator\'s say-so it is not given.');
        } catch (RuntimeException $refused) {
            self::assertStringContainsString('This person already has Basic Bookkeeping. Give the bundle anyway to extend their access to it', $refused->getMessage());
        }
        $this->credits->assign($this->companyId, $creditId, $sipho, $this->buyer->id, true);
        self::assertSame($this->courses, $open($sipho), 'The other courses are theirs too, and the one they had stays one enrolment.');
        self::assertSame(1, (int) $this->db->fetchOne('SELECT COUNT(*) FROM course_enrolments WHERE user_id = :user AND course_id = :course', ['user' => $sipho, 'course' => $this->courses[1]]));
        $sources = $this->db->fetchAllAssociative("SELECT source, state, access_period_seconds FROM commerce_entitlements WHERE enrolment_id = :e ORDER BY id", ['e' => $held]);
        self::assertSame([['origin', 'awaiting_activation', 15552000], ['bundle', 'awaiting_activation', 15552000 + 31536000]], array_map(static fn(array $r): array => [$r['source'], $r['state'], (int) $r['access_period_seconds']], $sources), 'Their own access stays its own; the bundle waits for their start with both periods.');
        $learning->start($sipho, $slug($this->courses[1]));
        $expires = new \DateTimeImmutable((string) $this->db->fetchOne('SELECT expires_at FROM course_enrolments WHERE id = :e', ['e' => $held]));
        self::assertEqualsWithDelta(time() + 15552000 + 31536000, $expires->getTimestamp(), 120, 'Starting, their access runs for their own period and the bundle\'s together.');
        self::assertSame('consumed', $this->db->fetchOne('SELECT status FROM bundle_credit_allocations WHERE user_id = :user', ['user' => $sipho]));

        // Someone part way through a course they have: its end moves out by the bundle's period, and the credit is used at once.
        $thabo = $this->staff('Thabo Molefe', 'thabo');
        $started = IntegrationContainer::get()->get(CourseRepository::class)->grantCourse($thabo, $this->courses[0], 15552000, $this->buyer->id);
        $learning->start($thabo, $slug($this->courses[0]));
        $before = new \DateTimeImmutable((string) $this->db->fetchOne('SELECT expires_at FROM course_enrolments WHERE id = :e', ['e' => $started]));
        $this->credits->assign($this->companyId, $creditId, $thabo, $this->buyer->id, true);
        $after = new \DateTimeImmutable((string) $this->db->fetchOne('SELECT expires_at FROM course_enrolments WHERE id = :e', ['e' => $started]));
        self::assertEqualsWithDelta($before->getTimestamp() + 31536000, $after->getTimestamp(), 5, 'Extended by the bundle\'s access period.');
        self::assertSame('consumed', $this->db->fetchOne('SELECT status FROM bundle_credit_allocations WHERE user_id = :user', ['user' => $thabo]));

        // Given anyway, then taken back before any start: the courses it gave go, the one they had stays, its extension is revoked.
        $naledi = $this->staff('Naledi Mahlangu', 'naledi');
        $own = IntegrationContainer::get()->get(CourseRepository::class)->grantCourse($naledi, $this->courses[2], 15552000, $this->buyer->id);
        $gift = $this->credits->assign($this->companyId, $creditId, $naledi, $this->buyer->id, true);
        $administration->removeEnrolmentAccess($gift['enrolment_ids'][0], $this->buyer->id, 'Not needed after all.');
        self::assertSame([$this->courses[2]], $open($naledi), 'Their own course stays.');
        self::assertSame('revoked', $this->db->fetchOne("SELECT state FROM commerce_entitlements WHERE enrolment_id = :e AND source = 'bundle'", ['e' => $own]));
        self::assertSame(3, $this->credits->forCompany($this->companyId)[0]['given'], 'And the credit is back.');

        // Only the credit not given is refunded.
        $item = (int) $this->db->fetchOne("SELECT id FROM commerce_order_items WHERE order_id = :id AND product_type = 'bundle_credit'", ['id' => $orderId]);
        $refunds = IntegrationContainer::get()->get(RefundAdministrationService::class);
        $admin = new CurrentUser($this->buyer->id, Uuid::v4(), 'admin@example.test', 'Administrator', ['ADMIN'], (new \CattoLearning\Auth\PermissionCatalog())->keys(), Uuid::v4());
        try {
            $refunds->approve($admin, $orderId, $item, Uuid::v4(), 'voluntary', 'Two staff left the company.', 2, 0, '', 'wallet');
            self::fail('A bundle credit given to someone is not refunded.');
        } catch (RuntimeException $refused) {
            self::assertStringContainsString('Only bundle credits not yet given to anyone can be refunded: 1 of this line.', $refused->getMessage());
        }
    }

