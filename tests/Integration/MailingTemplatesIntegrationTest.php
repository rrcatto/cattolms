    public function testADesignedTemplateDrawsTheEmailInItsLookAndRefusesWhatTheFormCouldNotSend(): void
    {
        $templates = $this->templates();
        $defaults = $templates->defaultFor('messages');
        self::assertTrue($defaults['default_for_messages'], 'There is always a default for messages.');
        self::assertNotEmpty($templates->defaultFor('digest'), 'And one for the digest.');

        $id = $templates->create('Course news', $this->admin());
        $templates->save($id, ['name' => 'Course news', 'mode' => 'design', 'text_mode' => 'made', 'design' => [
            'colours' => ['header' => '#1F5F6B', 'button' => '#1f5f6b', 'links' => '#1f5f6b'] + $defaults['design']['colours'],
            'heading_font' => 'cormorant', 'body_font' => 'georgia', 'text_size' => '17', 'width' => '640', 'corners' => 'rounded', 'spacing' => 'compact',
            'button_shape' => 'pill', 'logo_size' => 'small', 'align' => 'center', 'footer_words' => 'With every good wish from the team.',
            'social' => ['linkedin' => 'https://www.linkedin.com/company/example', 'x' => ''],
        ]], $this->admin());
        $template = $templates->get($id);
        self::assertSame('#1f5f6b', $template['design']['colours']['header'], 'Colours are kept in lower case.');
        $copy = $this->renderer()->sample($template, 'message', 'Lerato');
        foreach (['background:#1f5f6b', "'Cormorant Garamond',Georgia,serif", 'Georgia,', 'max-width:640px', 'border-radius:999px', 'With every good wish from the team.',
            'https://www.linkedin.com/company/example', 'fonts.googleapis.com/css2?family=Cormorant+Garamond', 'Show my subscriptions', 'Unsubscribe from News and Updates', 'Hello Lerato'] as $part) {
            self::assertStringContainsString($part, $copy['html'], $part);
        }
        self::assertStringNotContainsString('stop', strtolower(strip_tags($copy['html'])), 'It is always the unsubscribe link (owner, 2026-10-28).');

        foreach ([[['colours' => ['header' => 'teal']], 'Header background: write the colour as # and six hex digits, such as #9a3f12.'],
            [['heading_font' => 'comic sans'], "Choose the headings' font from the list."], [['width' => '900'], 'Choose the width from the list.'],
            [['social' => ['facebook' => 'http://facebook.com/x']], "Facebook: write your profile's full address, starting with https://."]] as [$design, $refusal]) {
            try {
                $templates->save($id, ['mode' => 'design', 'design' => $design], $this->admin());
                self::fail('Accepted: ' . json_encode($design));
            } catch (InvalidArgumentException $refused) {
                self::assertSame($refusal, $refused->getMessage());
            }
        }
        self::assertSame('#1f5f6b', $templates->get($id)['design']['colours']['header'], 'A refused change leaves the template as it was.');
    }

    public function testAnHtmlTemplateMustHoldItsRequiredPartsAndADemoSiteAlwaysSaysSo(): void
    {
        $templates = $this->templates();
        $id = $templates->create('Letter', $this->admin());
        $page = '<html><body><div class="letter">{content}</div><p>{why} <a href="{unsubscribe_link}">Unsubscribe</a> {site_owner_address}</p></body></html>';
        foreach ([[str_replace('{unsubscribe_link}', '#', $page), 'The HTML must hold {unsubscribe_link}'], ['<p>{content}</p>', 'The HTML must hold {unsubscribe_link}, {site_owner_address}'],
            [str_replace('</body>', '<script>alert(1)</script></body>', $page), 'Take out the script'], ['', "Write the template's HTML"]] as [$html, $refusal]) {
            try {
                $templates->save($id, ['mode' => 'html', 'html' => $html], $this->admin());
                self::fail('Accepted: ' . $html);
            } catch (InvalidArgumentException $refused) {
                self::assertStringStartsWith($refusal, $refused->getMessage());
            }
        }
        $templates->save($id, ['mode' => 'html', 'html' => $page, 'text_mode' => 'own', 'text_part' => "{content}\n\nUnsubscribe: {unsubscribe_link}"], $this->admin());
        $copy = $this->renderer()->sample($templates->get($id), 'message', 'Sipho');
        self::assertStringContainsString('<div class="letter">', $copy['html']);
        self::assertStringContainsString('Hello Sipho', $copy['html'], '{content} holds the message.');
        self::assertStringContainsString('Unsubscribe: ' . $copy['unsubscribe_url'], $copy['text'], 'The own plain-text copy is used.');
        if (IntegrationContainer::get()->get(SiteMode::class)->isDemo()) {
            self::assertStringContainsString(SiteMode::EMAIL_NOTICE, $copy['html'], 'A demo site says so even where the template has no place for it.');
            self::assertStringStartsWith(SiteMode::EMAIL_NOTICE, $copy['text']);
        }
        try {
            $templates->save($id, ['mode' => 'html', 'html' => $page, 'text_mode' => 'own', 'text_part' => 'Only words'], $this->admin());
            self::fail('Accepted a plain-text copy without the message.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame('Your own plain-text copy must hold {content} and {unsubscribe_link}.', $refused->getMessage());
        }
    }

    public function testADefaultCannotBeDeletedAndAMessageWhoseTemplateGoesUsesTheDefault(): void
    {
        $templates = $this->templates();
        $standard = $templates->defaultFor('messages');
        $id = $templates->create('Newsletter', $this->admin());
        $templates->makeDefault($id, 'messages', $this->admin());
        self::assertSame($id, $templates->defaultFor('messages')['id']);
        self::assertFalse($templates->get($standard['id'])['default_for_messages'], 'Only one default for messages.');
        try {
            $templates->delete($id, $this->admin());
            self::fail('Deleted the default for messages.');
        } catch (InvalidArgumentException $refused) {
            self::assertSame('It is the default for messages. Make another template the default for messages first.', $refused->getMessage());
        }
        $templates->makeDefault($standard['id'], 'messages', $this->admin());
        $campaigns = IntegrationContainer::get()->get(CampaignRepository::class);
        $message = $campaigns->create('message', 'Winter sale', $this->admin(), ['subject' => 'Our winter sale']);
        $this->db->executeStatement('UPDATE mailing_campaigns SET template_id = :t WHERE id = :id', ['t' => $id, 'id' => $message]);
        self::assertSame($id, $templates->forCampaign($campaigns->find($message))['id'], 'A message draws in the template it chose.');
        $templates->delete($id, $this->admin());
        self::assertSame($standard['id'], $templates->forCampaign($campaigns->find($message))['id'], 'Its template gone, it draws in the default for messages.');
    }

    public function testSixSampleDesignsStartATemplateOrGiveOneTheirLookKeepingItsOwnPictureAndWords(): void
    {
        self::assertCount(6, \CattoLearning\Mailing\TemplateDesign::SAMPLES, 'Six sample designs (owner, 2026-10-28).');
        $templates = $this->templates();
        foreach (array_keys(\CattoLearning\Mailing\TemplateDesign::SAMPLES) as $key) {
            $sample = \CattoLearning\Mailing\TemplateDesign::sample($key);
            self::assertNotNull($sample);
            self::assertSame($sample, \CattoLearning\Mailing\TemplateDesign::checked($sample, $sample), $key . ' is a design the form could have sent.');
            self::assertStringStartsWith('<svg', \CattoLearning\Mailing\TemplateDesign::thumbnail($sample, $key));
        }
        $id = $templates->create('', $this->admin(), 'noir');
        $made = $templates->get($id);
        self::assertSame('Gold on black', $made['name'], 'Without a name, the sample\'s.');
        self::assertSame('#d4af37', $made['design']['colours']['headings']);
        $templates->save($id, ['mode' => 'design', 'design' => ['footer_words' => 'With every good wish.', 'colours' => $made['design']['colours']]], $this->admin());
        $templates->applySample($id, 'fresh', $this->admin());
        $restyled = $templates->get($id);
        self::assertSame('#2f6b3f', $restyled['design']['colours']['header'], 'The sample\'s look.');
        self::assertSame('With every good wish.', $restyled['design']['footer_words'], 'Its own words stay.');
        self::assertSame('Gold on black', $restyled['name']);
    }

    private function templates(): MailingTemplates
    {
        return IntegrationContainer::get()->get(MailingTemplates::class);
    }

    private function renderer(): EmailRenderer
    {
        return IntegrationContainer::get()->get(EmailRenderer::class);
    }

    private function admin(): int
    {
        return (int) $this->db->fetchOne("SELECT ur.user_id FROM user_roles ur JOIN roles r ON r.id = ur.role_id WHERE r.role_key = 'ADMIN' ORDER BY ur.user_id LIMIT 1");
    }
