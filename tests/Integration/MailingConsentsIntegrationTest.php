declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Mailing\MailingConsents;
use CattoLearning\Mailing\MailingRepository;
use CattoLearning\Tests\Support\IntegrationContainer;
use CattoLearning\Tests\Support\IntegrationDataFixture;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class MailingConsentsIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testAnswersAreKeptWithWhereTheyWereGivenAndEveryChangeIsHistory(): void
    {
        $fixture = new IntegrationDataFixture($this->db);
        $suffix = $fixture->suffix();
        $person = $fixture->createUser('Mailing Person', 'mailing-' . $suffix . '@example.test');
        $owner = $fixture->createUser('Mailing Owner', 'mailing-owner-' . $suffix . '@example.test');
        $company = $fixture->createCompany($owner, 'Mailing Company', 'mailing-' . $suffix . '.test');
        $course = $fixture->createCourse($owner, $company, 'mailing-course-' . $suffix, 'Mailing course');
        /** @var MailingConsents $mailing */
        $mailing = IntegrationContainer::get()->get(MailingConsents::class);
        /** @var MailingRepository $lists */
        $lists = IntegrationContainer::get()->get(MailingRepository::class);

        $mailing->unsubscribe($person, 'course', $course, 'preferences');
        self::assertNull($lists->listId('course', $course, false), 'A no to a list nobody joined makes no list.');

        $mailing->subscribe($person, 'news', null, 'registration');
        $mailing->subscribe($person, 'course', $course, 'checkout');
        $mailing->subscribe($person, 'course', $course, 'follow_button');
        self::assertTrue($mailing->isSubscribed($person, 'news'));
        self::assertTrue($mailing->isSubscribed($person, 'course', $course));
        $courseList = (int) $lists->listId('course', $course, false);
        self::assertSame('checkout', $this->db->fetchOne('SELECT source FROM mailing_subscriptions WHERE list_id = :l AND user_id = :u', ['l' => $courseList, 'u' => $person]), 'The same yes again changes nothing.');

        $mailing->unsubscribe($person, 'course', $course, 'preferences');
        self::assertFalse($mailing->isSubscribed($person, 'course', $course));
        self::assertSame([['subscribed', 'checkout'], ['unsubscribed', 'preferences']], array_map(static fn(array $r): array => [$r['status'], $r['source']], $this->db->fetchAllAssociative('SELECT status, source FROM mailing_subscription_events WHERE list_id = :l AND user_id = :u ORDER BY id', ['l' => $courseList, 'u' => $person])), 'Every change is history.');

        $preferences = $mailing->preferences($person);
        self::assertTrue($preferences['news']);
        self::assertSame([], $preferences['follows'], 'Unfollowed, it is no longer listed.');
        $news = array_values(array_filter($lists->lists(), static fn(array $l): bool => $l['kind'] === 'news'))[0];
        self::assertGreaterThanOrEqual(1, $news['followers']);
        self::assertContains($person, array_map('intval', array_column($lists->followers($news['id'], 1000, 0), 'user_id')));

        $this->expectException(InvalidArgumentException::class);
        $mailing->subscribe($person, 'course', null, 'follow_button');
    }
}
