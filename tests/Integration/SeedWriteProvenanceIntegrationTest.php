     * puzzling constraint violation.
     */
    public function testTheResolverRefusesACrossUniversePairing(): void
    {
        /** @var SeedProvenance $provenance */
        $provenance = $this->container->get(SeedProvenance::class);

        $this->expectException(RuntimeException::class);
        $provenance->forPair('users', $this->real['learner'], 'courses', $this->seed['course']);
    }

    /** The universe an identity reads is the universe its rows are written into. */
    public function testIdentityUniverseMatchesStoredProvenance(): void
