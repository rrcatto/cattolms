    /** SeedProvenance reads the universe of a real row rather than guessing from an id. */
    public function testTheResolverReadsRealRows(): void
    {
        /** @var SeedProvenance $provenance */
        $provenance = $this->container->get(SeedProvenance::class);

        self::assertSame($this->seed['token'], $provenance->fromUser($this->seed['learner']));
        self::assertNull($provenance->fromUser($this->real['learner']));
        self::assertSame($this->seed['token'], $provenance->fromCourse($this->seed['course']));
        self::assertNull($provenance->fromCourse($this->real['course']));
        self::assertNull($provenance->fromUser(null), 'A null reference has no universe to inherit.');
    }

    /**
