    /**
     * The whole learning chain, each row inheriting the one above it.
     *
     * Enrolment, module progress, attempt and response are written by four different code paths
     * with four different provenance sources, and the chain is only correct if all four agree.
     */
    public function testTheLearningChainInheritsItsEnrolment(): void
    {
        $moduleId = $this->courses->createModule($this->seed['course'], [
            'module_key' => 'm1', 'position' => 1, 'title' => 'Module one',
            'subtitle' => '', 'content_html' => '<p>Body</p>', 'summary_html' => '',
            'learning_outcomes_html' => '', 'is_review' => false, 'assessment_required' => true,
        ]);
        $this->assertProvenance('module creation', 'course_modules', $moduleId, $this->seed['token']);

        $enrolmentId = $this->courses->grantCourse(
            $this->seed['learner'],
            $this->seed['course'],
            31536000,
            $this->adminUserId
        );
        $this->assertProvenance('enrolment', 'course_enrolments', $enrolmentId, $this->seed['token']);

        // Decision D4: a genuine administrator granted this, and stays attributable for it.
        self::assertSame(
            $this->adminUserId,
            (int) $this->fixture->scalar('SELECT assigned_by_user_id FROM course_enrolments WHERE id = :id', [':id' => $enrolmentId]),
            'An allowlisted actor column must keep naming the genuine administrator.'
        );

        $this->courses->startEnrolment($enrolmentId, $this->seed['learner']);
        $this->courses->touchModule($enrolmentId, $moduleId);
        self::assertSame(
            $this->seed['token'],
            (string) $this->fixture->scalar(
                'SELECT seed_token FROM module_progress WHERE enrolment_id = :e AND module_id = :m',
                [':e' => $enrolmentId, ':m' => $moduleId]
            ),
            'Module progress must inherit its enrolment.'
        );

        $assessmentId = $this->courses->createAssessment($this->seed['course'], $moduleId, [
            'assessment_type' => 'module', 'title' => 'Module one check', 'pass_mark' => 50,
        ]);
        $this->assertProvenance('assessment', 'course_assessments', $assessmentId, $this->seed['token']);

        $attemptId = $this->courses->saveAttempt($enrolmentId, $assessmentId, 1.0, 1.0, 100.0, 'A', true, []);
        $this->assertProvenance('assessment attempt', 'assessment_attempts', $attemptId, $this->seed['token']);
    }

