    public function testAuditRowsFollowTheActingIdentity(): void
    {
        /** @var AuditRepository $audit */
        $audit = $this->container->get(AuditRepository::class);

        $audit->record($this->adminUserId, 'seed.integration_probe', ['scope' => 'admin']);
        self::assertNull(
            $this->fixture->scalar(
                "SELECT seed_token FROM audit_log WHERE user_id = :id AND event_key = 'seed.integration_probe' ORDER BY id DESC LIMIT 1",
                [':id' => $this->adminUserId]
            ),
            'A genuine administrator writes a genuine audit row even when acting on generated data.'
        );

        $audit->record($this->seed['learner'], 'seed.integration_probe', ['scope' => 'seed']);
        self::assertSame(
            $this->seed['token'],
            (string) $this->fixture->scalar(
                "SELECT seed_token FROM audit_log WHERE user_id = :id AND event_key = 'seed.integration_probe' ORDER BY id DESC LIMIT 1",
                [':id' => $this->seed['learner']]
            ),
            'A generated identity writes a generated audit row, so cleanup removes it with the set.'
        );
    }

