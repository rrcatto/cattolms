declare(strict_types=1);

namespace CattoLearning\Tests\Integration;

use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Seed\SeedRun;
use CattoLearning\Tests\Support\DevelopmentFixture;
use CattoLearning\Tests\Support\IntegrationContainer;
use PHPUnit\Framework\TestCase;

final class SeedRunIntegrationTest extends TestCase
{
    private Database $db;

    protected function setUp(): void
    {
        $this->db = IntegrationContainer::db();
        $this->db->beginTransaction();
    }

    protected function tearDown(): void
    {
        if ($this->db->isTransactionActive()) $this->db->rollBack();
    }

    public function testARunFollowsTheWorkflowsWithRealNames(): void
    {
        $fixture = new DevelopmentFixture($this->db);
        $admin = $fixture->person('ADMIN');
        // A course on sale, with a graded assessment, so there is something to buy and to answer.
        $provider = $fixture->company();
        $course = $fixture->course($provider['founder']['id'], $provider['id'], 'published');
        $fixture->createPriceVariant($course['id'], $provider['founder']['id'], 31536000, 95000, true);
        $assessment = $fixture->createAssessmentItem($course['id'], $provider['founder']['id']);
        $fixture->createQuestion((int) $assessment['item_id']);
        $lastCompany = (int) $this->db->fetchOne('SELECT COALESCE(MAX(id), 0) FROM companies');
        $lastUser = (int) $this->db->fetchOne('SELECT COALESCE(MAX(id), 0) FROM users');
        $lastOrder = (int) $this->db->fetchOne('SELECT COALESCE(MAX(id), 0) FROM commerce_orders');
        $steps = [];

        $result = IntegrationContainer::get()->get(SeedRun::class)->run($admin['id'], 2, 4, static function (string $step) use (&$steps): void {
            $steps[] = $step;
        });

        self::assertSame(2, $result['made']['companies'] ?? 0, 'two companies: ' . implode('; ', $result['refused']));
        self::assertContains('Making company 1 of 2', $steps, 'each step is reported as it starts');
        $companies = $this->db->fetchAllAssociative('SELECT id, name, domain FROM companies WHERE id > :last', ['last' => $lastCompany]);
        self::assertCount(2, $companies);
        foreach ($companies as $company) {
            self::assertDoesNotMatchRegularExpression('/\d/', (string) $company['name'], 'no number in a company name');
            self::assertStringEndsWith('.invalid', (string) $company['domain'], 'an invented domain that never receives mail');
            self::assertGreaterThan(0, (int) $this->db->fetchOne("SELECT COUNT(*) FROM company_users WHERE company_id = :c AND status = 'active' AND company_role IN ('owner', 'administrator')", ['c' => $company['id']]), $company['name'] . ' has its Company Administrator');
            self::assertSame(0, (int) $this->db->fetchOne(
                "SELECT COUNT(*) FROM company_users cu JOIN user_emails ue ON ue.user_id = cu.user_id AND ue.is_primary WHERE cu.company_id = :c AND ue.email NOT LIKE :d",
                ['c' => $company['id'], 'd' => '%@' . $company['domain']]
            ), $company['name'] . '\'s people are at its domain');
        }
        $people = $this->db->fetchAllAssociative('SELECT first_name, last_name FROM users WHERE id > :last', ['last' => $lastUser]);
        self::assertNotEmpty($people);
        foreach ($people as $person) self::assertDoesNotMatchRegularExpression('/\d/', $person['first_name'] . ' ' . $person['last_name'], 'no number in a person\'s name');
        self::assertSame(0, (int) $this->db->fetchOne(
            "SELECT COUNT(*) FROM (SELECT lower(first_name), lower(last_name) FROM users WHERE first_name IS NOT NULL AND first_name <> '' GROUP BY 1, 2 HAVING COUNT(*) > 1) repeated"
        ), 'no two people share a name');
        self::assertGreaterThan(0, (int) $this->db->fetchOne('SELECT COUNT(*) FROM commerce_orders WHERE id > :last', ['last' => $lastOrder]), 'orders were placed at the checkouts');
        self::assertGreaterThan(0, $result['made']['emails held'] ?? 0, 'the mail the run\'s people would have received was held, not sent');
    }
}
