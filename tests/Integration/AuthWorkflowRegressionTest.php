    public function testMagicLinkConsumptionCreatesStudentAndActiveSession(): void
    {
        $container = CliBootstrap::boot()['container'];
        /** @var Database $db */
        $db = $container->get(Database::class);
        $fixture = new DevelopmentFixture($db);
        $suffix = $fixture->suffix();
        $email = 'qa-auth-' . $suffix . '@example.test';
        $fixture->rememberEmail($email);
        $mailer = new FakeMailer();

        try {
            $auth = $this->authService($container, $mailer);
            $auth->requestLogin($email, 'https://invalid.example/escape');

            self::assertCount(1, $mailer->messages);
            self::assertSame('magic_link', $mailer->messages[0]['type']);
            $url = (string) ($mailer->messages[0]['url'] ?? '');
            parse_str((string) parse_url($url, PHP_URL_QUERY), $query);
            $token = (string) ($query['token'] ?? '');
            self::assertNotSame('', $token);

            $returnPath = $auth->consumeLogin($token);
            self::assertSame('/account/library', $returnPath);

            $rows = $db->fetchAllAssociative(
                'SELECT u.id,u.created_at,u.last_login_at,ue.verified_at FROM users u JOIN user_emails ue ON ue.user_id=u.id WHERE ue.email=:email AND ue.is_primary=TRUE',
                ['email' => $email]
            );
            self::assertCount(1, $rows);
            $userId = (int) $rows[0]['id'];
            $fixture->rememberUser($userId);
            self::assertNotSame('', trim((string) ($rows[0]['verified_at'] ?? '')));
            self::assertNotSame('', trim((string) ($rows[0]['created_at'] ?? '')));
            self::assertNotSame('', trim((string) ($rows[0]['last_login_at'] ?? '')));

            $roles = $db->fetchAllAssociative(
                'SELECT r.role_key FROM user_roles ur JOIN roles r ON r.id=ur.role_id WHERE ur.user_id=:user_id',
                ['user_id' => $userId]
            );
            self::assertContains('STUDENT', array_map(static fn(array $row): string => (string) $row['role_key'], $roles));

            $sessions = $db->fetchAllAssociative(
                'SELECT revoked_at,expires_at FROM auth_sessions WHERE user_id=:user_id',
                ['user_id' => $userId]
            );
            self::assertCount(1, $sessions);
            self::assertSame('', trim((string) ($sessions[0]['revoked_at'] ?? '')));
            self::assertGreaterThan(time(), strtotime((string) $sessions[0]['expires_at']) ?: 0);
        } finally {
            unset($_COOKIE['catto_learning_session']);
            $fixture->cleanup();
        }
    }


