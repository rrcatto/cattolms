declare(strict_types=1);

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Course\CourseFile;
use CattoLearning\Course\CoursePortabilityService;
use CattoLearning\Infrastructure\Persistence\Database;
use CattoLearning\Tests\Support\CourseFileContents;

require dirname(__DIR__, 2) . '/vendor/autoload.php';

$container = CliBootstrap::boot()['container'];
$db = $container->get(Database::class);
$portability = $container->get(CoursePortabilityService::class);
$files = $container->get(CourseFile::class);
$codes = array_slice((array) ($_SERVER['argv'] ?? []), 1) ?: $db->fetchFirstColumn('SELECT code FROM courses ORDER BY code');
$lacking = 0;
$pieces = 0;
foreach ($codes as $code) {
    $package = $portability->exportCourse((int) $db->fetchOne('SELECT id FROM courses WHERE code = :code', ['code' => $code]));
    $file = $files->render($package);
    $missing = CourseFileContents::missing($package, $file['html']);
    $lacking += count($missing);
    $pieces += CourseFileContents::count($package);
    printf("%-10s %6d KB  missing %4d  left out %d\n", $code, (int) round(strlen($file['html']) / 1024), count($missing), count($file['left_out']));
    foreach (array_slice($missing, 0, 12) as $line) { echo '    ', $line, "\n"; }
    foreach ($file['left_out'] as $line) { echo '    left out: ', $line, "\n"; }
}
echo $lacking, ' of ', $pieces, " pieces missing in all.\n";
exit($lacking === 0 ? 0 : 1);
