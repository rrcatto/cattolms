    chmod($statePath, 0600);
    $items = $container->get(CourseItemService::class);
    $learning = $container->get(LearningService::class);
    $previews = $container->get(CoursePortabilityService::class);

    // Every layout on every background in both of the player's looks, each slide filled with its sample.
    $module = $items->addSection($own['id'], ['title' => 'Every layout', 'show_outline' => '1', 'numbered' => '1'], $admin['id']);
    $key = 'readable-' . $fixture->suffix();
    foreach (['light', 'dark'] as $look) {
        foreach (['base', 'alt', 'accent'] as $tone) {
            // A call to action belongs only at the end of a trailer, so it has a presentation of its own beside the rest.
            $slides = ['intro' => [], 'trailer' => []];
            foreach (SlideLayouts::SAMPLES as $layout => $sample) {
                $slide = ['layout' => $layout, 'tone' => $tone, 'chapter' => 'Every layout', 'narration' => 'Narration for ' . $layout . ' on ' . $tone . '.'] + $sample;
                foreach (['points', 'steps', 'options'] as $lines) { if (isset($slide[$lines])) { $slide[$lines] = implode("\n", $slide[$lines]); } }
                if (isset($slide['events'])) { $slide['events'] = implode("\n", array_map(static fn(array $event): string => $event['when'] . ' | ' . $event['what'], $slide['events'])); }
                $slides[$layout === 'cta' ? 'trailer' : 'intro'][] = $slide;
            }
            foreach ($slides as $kind => $deck) {
                $items->createAndPlace($own['id'], ['parent_node_id' => (string) $module, 'item_key' => $key . '-' . $look . '-' . $tone . '-' . $kind, 'item_type' => 'slide_deck', 'title' => 'Every layout, ' . $look . ', ' . $tone . ', ' . $kind, 'public_preview' => '1', 'deck_kind' => $kind, 'deck_theme' => $look, 'slides' => $deck], $admin['id']);
            }
        }
    }

    $decks = $db->fetchAllAssociative(
        "SELECT c.id AS course_id, c.code, c.title AS course, c.slug, n.id AS node, n.part_name AS part, ci.id AS item, ci.title, ci.type_config->>'kind' AS kind, ci.type_config->>'theme' AS look
