if ($action === 'create') {
    if (is_file($statePath)) { throw new RuntimeException('Clean up the previous presentation fixture first.'); }
    $admin = $fixture->person('ADMIN');
    $provider = $fixture->company();
    // A draft, opened through the ADMIN's preview: a course of a check's must never show in the site's catalogue, even
    // while the check runs (owner, 2026-11-02: "why did you created a Payroll Basics course?").
