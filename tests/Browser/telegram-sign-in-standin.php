declare(strict_types=1);

const TELEGRAM_SIGN_IN_KEY = '123456789:stand-in-key-for-checks-only';
const TELEGRAM_SIGN_IN_STATE = '/tmp/telegram-sign-in-standin.json';
$path = (string) parse_url((string) $_SERVER['REQUEST_URI'], PHP_URL_PATH);
$body = json_decode((string) file_get_contents('php://input'), true) ?: [];
header('Content-Type: application/json');
if (preg_match('#^/bot(.+)/(getMe|getUpdates|sendMessage)$#', $path, $match) !== 1 || $match[1] !== TELEGRAM_SIGN_IN_KEY) {
    http_response_code(401);
    echo '{"ok":false,"description":"Unauthorized"}';
    return;
}
$lock = fopen(TELEGRAM_SIGN_IN_STATE . '.lock', 'c');
flock($lock, LOCK_EX);
$state = json_decode((string) @file_get_contents(TELEGRAM_SIGN_IN_STATE), true) ?: ['updates' => [], 'sent' => [], 'blocked' => [], 'next' => 5000];
$answer = ['ok' => true, 'result' => []];
if ($match[2] === 'getMe') {
    $answer['result'] = ['username' => 'catto_check_bot'];
} elseif ($match[2] === 'getUpdates') {
    $offset = (int) ($body['offset'] ?? 0);
    if ($offset > 0) $state['updates'] = array_values(array_filter($state['updates'], static fn(array $one): bool => $one['update_id'] >= $offset));
    $answer['result'] = $state['updates'];
} else {
    $chat = (string) ($body['chat_id'] ?? '');
    if (in_array($chat, $state['blocked'], true)) {
        http_response_code(403);
        $answer = ['ok' => false, 'description' => 'Forbidden: bot was blocked by the user'];
    } else {
        $state['sent'][] = ['chat_id' => $chat, 'text' => (string) ($body['text'] ?? ''), 'link_preview_options' => $body['link_preview_options'] ?? null];
    }
}
file_put_contents(TELEGRAM_SIGN_IN_STATE, json_encode($state));
flock($lock, LOCK_UN);
echo json_encode($answer);
