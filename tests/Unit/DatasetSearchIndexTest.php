Description:
Ties the search predicates to the trigram indexes that make them fast.

The migration failed on the VPS for two reasons, both of which were knowable without a database and
neither of which any existing test could see:

  gin_trgm_ops is an operator class for `text`, and every indexed column is VARCHAR. Without an
  explicit cast PostgreSQL refuses the index, so the very first CREATE INDEX failed and the
  migration stopped having applied nothing.

  An index expression must be IMMUTABLE. `concat_ws()` is only STABLE, so the composed-name index
  was rejected outright.

There is a third failure mode that would not have failed loudly at all: an index expression that
does not match its query predicate character for character is simply never used, and the search
quietly returns to a sequential scan on every keystroke. That is worse than a failed migration,
because nothing announces it.

So this asserts all three properties against the two files, with no database:

  every indexed expression is text-typed;
  no index expression uses a non-immutable function;
  every search predicate has an index whose expression matches it exactly.

