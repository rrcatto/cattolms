declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;
use ReflectionClass;

final class DatasetSearchIndexTest extends TestCase
{
    private static function root(): string
    {
        return dirname(__DIR__, 2);
    }

    /**
     * The index definitions, read from the migration.
     *
     * @return array<string,string>
     */
    /**
     * The one canonical baseline.
     *
     * The trigram indexes lived in their own migration until v0.6 collapsed every migration into a
     * single baseline; the definitions moved unchanged, so this reads them from where they now
     * live rather than pinning a filename that no longer exists.
     */
    private static function baseline(): string
    {
        $matches = glob(self::root() . '/database/migrations/*_baseline.php') ?: [];
        self::assertCount(1, $matches, 'There must be exactly one baseline migration.');

        return (string) file_get_contents($matches[0]);
    }

    /** @return array<string,string> */
    private static function indexes(): array
    {
        $source = self::baseline();

        preg_match_all("/'([a-z_]+_trgm_idx)' => (?:'|\")(.+?)(?:'|\"),\n/", $source, $matches, PREG_SET_ORDER);
        $indexes = [];
        foreach ($matches as $match) {
            $indexes[$match[1]] = $match[2];
        }

        return $indexes;
    }

    /**
     * Every search predicate the repository uses, flattened.
     *
     * @return list<string>
     */
    private static function searchExpressions(): array
    {
        $reflection = new ReflectionClass(\CattoLearning\Infrastructure\Persistence\AdministrationRepository::class);
        $expressions = [];
        foreach ($reflection->getConstants() as $name => $value) {
            if (!str_ends_with((string) $name, '_SEARCH') || !is_array($value)) {
                continue;
            }
            foreach ($value as $expression) {
                $expressions[] = (string) $expression;
            }
        }

        return array_values(array_unique($expressions));
    }

    /** The migration declares indexes at all, and the reader above actually found them. */
    public function testTheMigrationDeclaresItsIndexes(): void
    {
        self::assertNotSame([], self::indexes(), 'The index declarations could not be read.');
        self::assertCount(6, self::indexes());
    }

    /**
     * Every indexed expression is text-typed.
     *
     * gin_trgm_ops does not accept `character varying`, and every column here is VARCHAR. This is
     * the error that stopped the migration before it applied anything.
     */
    public function testEveryIndexedExpressionIsTextTyped(): void
    {
        foreach (self::indexes() as $name => $definition) {
            self::assertTrue(
                str_contains($definition, '::text') || str_contains($definition, '||'),
                $name . ' indexes a VARCHAR column without casting to text; gin_trgm_ops will refuse it.'
            );
        }
    }

    /**
     * No index expression uses a function PostgreSQL will not accept as immutable.
     *
     * `concat_ws`, `concat` and `format` are STABLE, not IMMUTABLE, so an index expression using
     * one is rejected. Concatenation with the `||` operator is immutable and is the substitute.
     */
    public function testNoIndexExpressionUsesANonImmutableFunction(): void
    {
        foreach (self::indexes() as $name => $definition) {
            foreach (['concat_ws(', 'concat(', 'format(', 'now(', 'current_'] as $forbidden) {
                self::assertStringNotContainsString(
                    $forbidden,
                    $definition,
                    $name . ' uses ' . $forbidden . ', which is not IMMUTABLE and cannot be indexed.'
                );
            }
        }
    }

    /**
     * Every search predicate is backed by an index whose expression matches it.
     *
     * The quiet failure. A predicate that differs from its index by so much as a cast will not use
     * it, and nothing reports that - the search simply gets slow again as the data grows.
     *
     * Comparison strips the table alias from the predicate, because the query says `u.first_name`
     * and the index says `first_name` for the same column.
     */
    public function testEverySearchPredicateHasAMatchingIndex(): void
    {
        $indexes = implode(' ', self::indexes());

        foreach (self::searchExpressions() as $expression) {
            $unaliased = preg_replace('/\b[a-z]{1,3}\./', '', $expression) ?? $expression;
            self::assertStringContainsString(
                $unaliased,
                $indexes,
                'The search predicate ' . $expression . ' has no trigram index with a matching '
                . 'expression, so it will never use one.'
            );
        }
    }

    /**
     * Every query provides the tables its own search predicate references.
     *
     * A search expression naming an alias the query does not join is valid PHP, passes every
     * source-level check, and throws "missing FROM-clause entry" the first time somebody types in
     * that box - so it ships looking fine and fails only in use. `companyCredits()` did exactly
     * that: it searched on the holder company and person while joining neither.
     *
     * The pairing is checkable without a database, which is the point.
     */
    public function testEveryQueryJoinsTheTablesItsSearchReferences(): void
    {
        $source = (string) file_get_contents(
            self::root() . '/src/Infrastructure/Persistence/AdministrationRepository.php'
        );
        $reflection = new ReflectionClass(\CattoLearning\Infrastructure\Persistence\AdministrationRepository::class);
        $constants = $reflection->getConstants();

        // Each method is examined on its own. A pattern allowed to span method boundaries reports
        // the wrong method name and makes the failure unreadable.
        preg_match_all('/public function ([a-zA-Z]+)\(/', $source, $names);
        $checked = 0;

        foreach ($names[1] as $method) {
            $body = self::methodBody($source, $method);
            if (preg_match('/self::(?:andSearch|searchFilter)\([^;]*self::([A-Z_]+_SEARCH)\)/', $body, $used) !== 1) {
                continue;
            }
            $constant = $used[1];
            $checked++;

            // Aliases the query actually makes available.
            preg_match_all('/(?:FROM|JOIN)\s+[a-z_]+\s+([a-z]{1,3})\b/i', $body, $found);
            $available = array_unique($found[1]);

            foreach ((array) ($constants[$constant] ?? []) as $expression) {
                preg_match_all('/\b([a-z]{1,3})\.[a-z_]+/', (string) $expression, $used);
                foreach (array_unique($used[1]) as $alias) {
                    self::assertContains(
                        $alias,
                        $available,
                        $method . '() searches on "' . $alias . '." but never joins it; that is a '
                        . 'missing FROM-clause entry the moment somebody uses the search.'
                    );
                }
            }
        }

        self::assertGreaterThanOrEqual(
            14,
            $checked,
            'Far fewer searchable queries were found than exist; the detection is broken, not the code.'
        );
    }

    /**
     * One method body, from its signature to its closing brace at method indentation.
     *
     * Line endings are normalised first. This checked out with CRLF endings on Windows, where a
     * literal "\n    }\n" never matches, so every body came back empty, nothing was examined and
     * the guard reported success by examining nothing. The count assertion below is what caught
     * it - which is exactly why a detector should assert it found something.
     */
    private static function methodBody(string $source, string $method): string
    {
        $source = str_replace("\r\n", "\n", $source);
        $start = strpos($source, 'public function ' . $method . '(');
        if ($start === false) {
            return '';
        }
        $end = strpos($source, "\n    }\n", $start);

        return $end === false ? '' : substr($source, $start, $end - $start);
    }

    /**
     * The extension is created if absent and never dropped.
     *
     * Another schema on the same database may be using pg_trgm, and rolling this installation back
     * is not evidence that nothing else needs it. The additive check that used to sit here went
     * with the standalone migration: a baseline creates the schema, so forbidding CREATE TABLE in
     * it would be nonsense.
     */
    public function testTheExtensionIsCreatedButNeverDropped(): void
    {
        $source = self::baseline();

        self::assertStringContainsString('CREATE EXTENSION IF NOT EXISTS pg_trgm', $source);
        self::assertStringNotContainsString('DROP EXTENSION', $source);
    }
}
