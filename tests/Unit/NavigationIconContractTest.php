/*
Generated by: Claude Code CLI

Date time: 2026/08/31 03:50 SAST

Version: 0.5.8.3

Description:
The navigation icon contract: core owns the artwork, themes render one reference.

Icons used to be each theme's own problem. Core emitted a text glyph, Factory Reset rendered that
glyph, and Gilded Noir ignored it and built a reference into its own sprite from the navigation key.
So the same menu item looked different in different themes, and every time a navigation key was
added or renamed - Seed Database, then Learning becoming Enrolments - the item rendered as a blank
space until each theme was edited and given a new version number.

Core now ships one sprite and emits the symbol id. This asserts the three properties that keep that
true:

  every semantic key core can emit has a symbol in the core sprite;
  an unknown key resolves to the fallback rather than to nothing;
  every theme references the platform sprite rather than hard-coding artwork or a menu.

The last one is why a new menu item can never again be invisible in one theme and fine in another.

Changelog:
2026/08/31 03:50 SAST
- Created when navigation icons moved from the themes into the LMS.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\View\ThemeRenderer;
use PHPUnit\Framework\TestCase;

final class NavigationIconContractTest extends TestCase
{
    private static function root(): string
    {
        return dirname(__DIR__, 2);
    }

    private static function sprite(): string
    {
        return (string) file_get_contents(self::root() . '/public_html/img/nav-icons.svg');
    }

    /** The sprite exists and is well-formed XML, because a broken sprite renders nothing at all. */
    public function testTheSpriteIsWellFormed(): void
    {
        $sprite = self::sprite();

        self::assertNotSame('', $sprite, 'The platform icon sprite is missing.');
        self::assertNotFalse(simplexml_load_string($sprite), 'The platform icon sprite is not valid XML.');
    }

    /**
     * Every key core can emit has a symbol.
     *
     * This is the test that would have caught the missing Seed Database icon, and the Enrolments
     * icon that disappeared when the section was renamed.
     */
    public function testEveryNavigationKeyHasASymbol(): void
    {
        $sprite = self::sprite();

        foreach (ThemeRenderer::NAVIGATION_ICON_KEYS as $key) {
            self::assertStringContainsString(
                'id="nav-' . $key . '"',
                $sprite,
                'The navigation key "' . $key . '" has no symbol in the platform sprite, so it '
                . 'would render as a blank space in every theme.'
            );
        }
    }

    /** The fallback exists, so an unknown key still draws something. */
    public function testTheFallbackSymbolExists(): void
    {
        self::assertStringContainsString('id="' . ThemeRenderer::NAVIGATION_ICON_FALLBACK . '"', self::sprite());
        self::assertSame(ThemeRenderer::NAVIGATION_ICON_FALLBACK, ThemeRenderer::navigationIconId('no-such-key'));
    }

    /** A known key resolves to its own symbol, not the fallback. */
    public function testKnownKeysResolveToTheirOwnSymbol(): void
    {
        self::assertSame('nav-seed', ThemeRenderer::navigationIconId('seed'));
        self::assertSame('nav-enrolments', ThemeRenderer::navigationIconId('enrolments'));
        self::assertSame('nav-dashboard', ThemeRenderer::navigationIconId('dashboard'));
    }

    /**
     * The navigation builder passes semantic keys, never artwork.
     *
     * Passing a glyph is what made the icon a presentation decision taken in core and then ignored
     * by half the themes.
     */
    public function testTheNavigationBuilderPassesKeysNotGlyphs(): void
    {
        $renderer = (string) file_get_contents(self::root() . '/src/View/ThemeRenderer.php');
        $builder = substr(
            $renderer,
            (int) strpos($renderer, 'private function navigation('),
            (int) strpos($renderer, 'private function footerNavigation(') - (int) strpos($renderer, 'private function navigation(')
        );

        foreach (['⌂', '▦', '⚙', '♙', '↪', '◫', '✉'] as $glyph) {
            self::assertStringNotContainsString(
                "'" . $glyph . "'",
                $builder,
                'The navigation builder passes the glyph ' . $glyph . ' as an icon; it must pass a semantic key.'
            );
        }
        self::assertStringContainsString('icon_id', $builder, 'Every navigation item must carry its sprite symbol id.');
    }

    /** Core publishes the sprite URL, fingerprinted like every other platform asset. */
    public function testTheSpriteUrlIsPublishedToThemes(): void
    {
        $renderer = (string) file_get_contents(self::root() . '/src/View/ThemeRenderer.php');

        self::assertStringContainsString("'icon_sprite' => \$this->platformAsset('/img/nav-icons.svg')", $renderer);
    }

    /**
     * Every bundled theme renders the platform sprite, and none hard-codes the menu.
     *
     * Two themes hard-coded their own navigation links, so a menu item added in core never appeared
     * in them at all - an icon was the least of it. Themes style the navigation; they do not decide
     * what is in it.
     */
    public function testEveryBundledThemeUsesThePlatformSprite(): void
    {
        foreach (glob(self::root() . '/themes/*', GLOB_ONLYDIR) ?: [] as $theme) {
            $markup = '';
            foreach (glob($theme . '/*.html.twig') ?: [] as $file) {
                $markup .= (string) file_get_contents($file);
            }
            foreach (glob($theme . '/partials/*.html.twig') ?: [] as $file) {
                $markup .= (string) file_get_contents($file);
            }

            $name = basename($theme);
            self::assertStringContainsString(
                'platform.icon_sprite',
                $markup,
                $name . ' does not reference the platform icon sprite, so its icons will drift from every other theme.'
            );
            self::assertStringContainsString(
                'navigation',
                $markup,
                $name . ' does not render the core navigation array, so a menu item added in the LMS will not appear in it.'
            );
        }
    }
}
