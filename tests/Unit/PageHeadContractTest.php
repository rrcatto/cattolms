declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class PageHeadContractTest extends TestCase
{
    /**
     * Screens that deliberately carry no platform header.
     *
     * The home page is its own hero and a header above it would be a second title. The course
     * player and the assessment runner carry their own chrome - a course has its own name, progress
     * and navigation, and a platform header above that competes with the thing the reader came for.
     * The error page has no context to describe, and the catalogue and course detail are heroes in
     * their own right.
     *
     * @var array<string,string>
     */
    private const WITHOUT_HEADER = [
        'home.html.twig' => 'Its own hero; a header would be a second title.',
        'error.html.twig' => 'No context to describe.',
        'course-detail.html.twig' => 'The course is the hero.',
        'learn-module.html.twig' => 'Carries its own course toolbar, which is the compact header.',
        'assessment-question.html.twig' => 'One question, full width, nothing else on screen.',
    ];

    /**
     * Every page template.
     *
     * The emptiness check is not defensive noise. Three of the assertions below iterate this list
     * and pass trivially when it is empty, and an empty list is exactly what a wrong root produces -
     * so without this the whole class reports success while inspecting nothing.
     *
     * @return list<string>
     */
    private static function pages(): array
    {
        $paths = glob(dirname(__DIR__, 2) . '/resources/views/pages/*.html.twig') ?: [];
        self::assertNotSame([], $paths, 'No page templates were found, so these tests prove nothing.');

        return $paths;
    }

    public function testEveryPageCarriesTheSharedHeader(): void
    {
        $missing = [];

        foreach (self::pages() as $path) {
            $name = basename($path);
            $markup = (string) file_get_contents($path);
            $has = str_contains($markup, 'partials/page-head.html.twig');

            if (isset(self::WITHOUT_HEADER[$name])) {
                self::assertFalse(
                    $has,
                    $name . ' is listed as headerless but includes the header. Remove it from the list '
                    . 'rather than leaving the list wrong.'
                );
                continue;
            }
            if (!$has) {
                $missing[] = $name;
            }
        }

        self::assertSame(
            [],
            $missing,
            "These screens have no page header, so a reader arriving on one cannot tell where they "
            . "are:\n  " . implode("\n  ", $missing)
        );
    }

    /** No screen may hand-roll the header markup beside the shared one. */
    public function testNoPageWritesItsOwnHeaderMarkup(): void
    {
        $offenders = [];

        foreach (self::pages() as $path) {
            $markup = (string) file_get_contents($path);
            if (str_contains($markup, '<section class="cl-page-head"')) {
                $offenders[] = basename($path);
            }
        }

        self::assertSame([], $offenders, 'The header is a shared partial, not markup to copy.');
    }

    /**
     * No screen carries two headings for itself.
     *
     * Adding the shared header to pages that already had their own produced eleven screens with the
     * title twice - which is worse than the inconsistency it was meant to fix, because it reads as a
     * rendering fault rather than as a style. A page's own h1 is allowed only where the h1 belongs to
     * the artefact rather than to the page: a certificate, a module being previewed, a role name that
     * *is* the heading.
     */
    public function testNoPageCarriesTwoHeadings(): void
    {
        $offenders = [];

        foreach (self::pages() as $path) {
            $name = basename($path);
            $markup = (string) file_get_contents($path);
            if (!str_contains($markup, 'partials/page-head.html.twig')) {
                continue;
            }

            $own = preg_match_all('/<h1[\s>]/', $markup);
            if ($own === 0) {
                continue;
            }
            // The compact header exists precisely for a screen whose own artefact carries the title.
            if (str_contains($markup, 'set ph_compact')) {
                continue;
            }
            $offenders[] = $name;
        }

        self::assertSame(
            [],
            $offenders,
            "These screens print their title twice - once in the shared header and once in their own "
            . "markup:\n  " . implode("\n  ", $offenders)
        );
    }

}
