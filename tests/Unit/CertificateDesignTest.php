    public function testEveryPhaseIRuleStillHoldsForCertificateTemplates(): void
    {
        $validator = new TemplateValidator(new PlaceholderRegistry());
        foreach ([
            '<script>alert(1)</script><p>{{ learner.name }}</p>' => '<script>',
            '<img src="https://example.com/signature.png">' => 'embedded data: images',
            '<img src="asset:abc">' => 'embedded data: images',
            '<p onclick="x()">{{ learner.name }}</p>' => 'Event handler',
            '<p>{{ learner.name|raw }}</p>' => 'Filters',
            '{% include "base.html.twig" %}' => 'Twig tags',
            '<p>{{ learner.password }}</p>' => 'Unknown placeholder',
            '<p>{{ invoice.number }}</p>' => 'not a certificate placeholder',
            '<p>{{ certificate.title }}</p>' => 'Unknown placeholder',
        ] as $html => $message) {
            try {
                $validator->validate(DocumentType::Certificate, $html, '');
                self::fail('Refused: ' . $html);
            } catch (TemplateValidationException $refused) {
                self::assertStringContainsString($message, implode(' ', $refused->errors));
            }
        }
        $validator->validate(DocumentType::Certificate, '<img alt="" src="asset:' . str_repeat('b', 64) . '"><p>{{ course.accreditation }}</p>', '.x{background:url(asset:' . str_repeat('c', 64) . ')}');
        self::addToAssertionCount(1);
    }

    public function testUploadsArePreparedOrRefusedPlainly(): void
    {
        $background = self::png(3508, 2480);
        $prepared = CertificateImage::prepare($background, CertificateImage::BACKGROUND);
        self::assertSame([2480, 1754, 'image/png'], [$prepared['width'], $prepared['height'], $prepared['mime']], 'A Canva-sized background is scaled to the stored size.');
        self::assertSame(2, ord($prepared['bytes'][25]), 'A background is stored as opaque RGB.');
        $transparent = imagecreatetruecolor(2480, 1754);
        imagesavealpha($transparent, true);
        imagefill($transparent, 0, 0, (int) imagecolorallocatealpha($transparent, 0, 0, 0, 127));
        ob_start();
        imagepng($transparent);
        $flattened = CertificateImage::prepare((string) ob_get_clean(), CertificateImage::BACKGROUND);
        self::assertSame(2, ord($flattened['bytes'][25]), 'A transparent background already at the stored size is flattened too.');
        self::assertSame([255, 255, 255], array_values(array_slice((array) imagecolorsforindex($image = (imagecreatefromstring($flattened['bytes']) ?: imagecreatetruecolor(1, 1)), imagecolorat($image, 10, 10)), 0, 3)), 'onto white');
        $logo = CertificateImage::prepare(self::png(2400, 600), CertificateImage::LOGO);
        self::assertSame([1200, 300], [$logo['width'], $logo['height']], 'A logo is scaled down to fit its box.');
        self::assertSame(6, ord($logo['bytes'][25]), 'A logo keeps an alpha channel, so it sits cleanly on the background.');
        foreach ([[self::png(1000, 1000), CertificateImage::BACKGROUND, 'A4 landscape'], [self::png(800, 566), CertificateImage::BACKGROUND, 'too small'], ['GIF89a', CertificateImage::LOGO, 'PNG or JPEG']] as [$bytes, $kind, $message]) {
            try {
                CertificateImage::prepare($bytes, $kind);
                self::fail('Refused: ' . $message);
            } catch (\InvalidArgumentException $refused) {
                self::assertStringContainsString($message, $refused->getMessage());
            }
        }
    }

