    public function testWordingFromTheEditorIsKeptAndEverythingElseDropped(): void
    {
        $posted = '<p class="cert-title align-center unknown">Award</p>'
            . '<p>To <span class="cl-field" data-field="learner.name">anything</span> <span class="cl-field" data-field="user.password">x</span></p>'
            . '<h2>Heading</h2><ul><li>One</li></ul><p><b>Bold</b> and <i>it</i><script>alert(1)</script><a href="https://x.test" onclick="y()">link</a></p>'
            . '<p style="color:red">[Course title] and [no such field]</p><p>&nbsp;</p>';
        $normalized = CertificateWording::normalize($posted, 'wording');
        self::assertSame([], $normalized['errors']);
        $html = $normalized['html'];
        self::assertStringContainsString('<p class="cert-title align-center">Award</p>', $html);
        self::assertStringContainsString(CertificateWording::chip('learner.name'), $html, 'A field keeps its label, whatever text it arrived with.');
        self::assertStringNotContainsString('user.password', $html, 'An unknown field is dropped.');
        self::assertStringContainsString('<p>Heading</p><p>One</p>', $html);
        self::assertStringContainsString('<strong>Bold</strong> and <em>it</em>', $html);
        foreach (['<script', 'alert(1)', 'onclick', 'href', 'style=', 'unknown'] as $gone) {
            self::assertStringNotContainsString($gone, $html);
        }
        self::assertStringContainsString(CertificateWording::chip('course.title') . ' and [no such field]', $html, '[Label] is the field; other brackets stay text.');
        self::assertStringEndsWith('</p>', $html);
        self::assertStringNotContainsString('&nbsp;</p>', substr($html, -20), 'Trailing blank lines are dropped.');

        $typed = CertificateWording::normalize("This is to certify that\n[Learner name]", 'wording')['html'];
        self::assertSame('<p>This is to certify that</p><p>' . CertificateWording::chip('learner.name') . '</p>', $typed, 'Typed without the editor, each line is a paragraph.');
    }

    public function testWordingBecomesTemplateHtmlWithOptionalLinesAndNoTemplateSyntax(): void
