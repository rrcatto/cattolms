declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoPHP\Http\TypedForm;
use PHPUnit\Framework\TestCase;
use Symfony\Component\HttpFoundation\Request;

final class TypedFormTest extends TestCase
{
    protected function tearDown(): void
    {
        unset($_SESSION[TypedForm::SESSION]);
    }

    public function testWhatWasSentIsKeptWithoutTheFormsToken(): void
    {
        $kept = TypedForm::kept('/admin/courses', ['csrf' => 'secret-token', 'title' => 'Garden Design', 'list_ids' => ['3', '5'], 'width' => ['about' => 'half'], 7 => 'unnamed']);
        self::assertSame(['action' => '/admin/courses', 'values' => ['title' => 'Garden Design', 'list_ids' => ['3', '5'], 'width' => ['about' => 'half']]], $kept);
        self::assertSame('200000', (string) mb_strlen((string) TypedForm::kept('/x', ['body' => str_repeat('a', 200005)])['values']['body']), 'A very long value is cut short.');
        self::assertSame(['deep' => ['a' => ['b' => 'c']]], TypedForm::kept('/x', ['deep' => ['a' => ['b' => 'c', 'd' => ['too deep']]]])['values'], 'Two levels of lists are kept, no more.');
    }

    public function testOnlyTheFormSentToTheAddressReadsItFromThisSitesOwnSession(): void
    {
        $_SESSION ??= [];
        TypedForm::keep(Request::create('/admin/courses/GDN-101/pricing', 'POST', ['price' => 'lots', 'csrf' => 'secret-token']));
        self::assertSame(['action' => '/admin/courses/GDN-101/pricing', 'values' => ['price' => 'lots']], $_SESSION[TypedForm::SESSION], 'In this site\'s own PHP session.');

        $page = Request::create('/admin/courses/GDN-101');
        self::assertSame(['price' => 'lots'], TypedForm::peek($page, '/admin/courses/GDN-101/pricing?return=x#new'), 'The address is compared without its query or place.');
        self::assertSame([], TypedForm::take($page, '/admin/courses/GDN-102/pricing'), 'Another form reads nothing.');
        self::assertSame(['price' => 'lots'], TypedForm::take($page, '/admin/courses/GDN-101/pricing'));
        self::assertSame([], TypedForm::take(Request::create('/admin/courses/GDN-101'), '/admin/courses/GDN-101/pricing'), 'Once only.');
    }
}
