Date time: 2026/09/10 01:20 SAST

Version: 0.7

Description:
An HTML attribute is written as markup, never assembled as a Twig expression.

Twig autoescapes what an expression prints. An attribute built as a string - 'style="width:' ~ n ~
'%"' - therefore reaches the browser as style=&quot;width:26%&quot;, which is text inside the tag
rather than an attribute. Nothing errors, nothing is logged, and the markup looks right in the
template; the attribute simply is not there.

It has cost this platform twice. Every column width on every Administration table was inert, which
is why tables allocated space by header text rather than by the proportions declared beside the
labels. And all eight sections of the Company control centre carried an escaped hx-get, so none of
them ever fetched its own contents - the second cause of a "Loading forever" that had already been
diagnosed once as a trigger placement problem.

The rule is the fix: put the attribute in the template and interpolate only its value.

    wrong   {{ x ? 'style="width:' ~ x ~ '%"' : '' }}
    right   {% if x %}style="width:{{ x }}%"{% endif %}

Changelog:
2026/09/10 01:20 SAST
- Created after the same escaping bug was found in two templates on the same day.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class TemplateAttributeContractTest extends TestCase
{
    /** @return list<string> */
    private static function templates(): array
    {
        $found = [];
        $directory = new \RecursiveDirectoryIterator(dirname(__DIR__, 2) . '/resources/views');
        /** @var \SplFileInfo $file */
        foreach (new \RecursiveIteratorIterator($directory) as $file) {
            if ($file->isFile() && str_ends_with($file->getFilename(), '.twig')) {
                $found[] = $file->getPathname();
            }
        }
        sort($found);

        return $found;
    }

    public function testNoTemplateAssemblesAnAttributeAsAnExpression(): void
    {
        $offenders = [];
        foreach (self::templates() as $path) {
            // Comments are blanked in place rather than removed, so the reported line number is
            // the line the reader will open.
            $source = (string) preg_replace_callback(
                '/\{#.*?#\}/s',
                static fn(array $m): string => str_repeat("\n", substr_count($m[0], "\n")),
                (string) file_get_contents($path)
            );
            foreach (explode("\n", $source) as $number => $line) {
                // An attribute name, an equals sign and a quote, inside a printed expression.
                if (preg_match('/\{\{[^}]*[\'"][a-zA-Z-]+=\\\\?["\'][^}]*\}\}/', $line) === 1) {
                    $offenders[] = sprintf(
                        '%s:%d  %s',
                        basename($path),
                        $number + 1,
                        trim($line)
                    );
                }
            }
        }

        self::assertSame([], $offenders, sprintf(
            "These lines build an HTML attribute inside a Twig expression. Twig escapes the quotes, "
            . "so the browser receives the attribute as text and it does nothing at all - silently. "
            . "Write the attribute as markup and interpolate only its value:\n"
            . "  wrong   {{ x ? 'style=\"width:' ~ x ~ '%%\"' : '' }}\n"
            . "  right   {%% if x %%}style=\"width:{{ x }}%%\"{%% endif %%}\n\n  %s",
            implode("\n  ", $offenders)
        ));
    }

    /** A guard that finds nothing must fail, so prove the scan reads the templates. */
    public function testTheScanReadsTheTemplates(): void
    {
        self::assertGreaterThan(50, count(self::templates()), 'The template scan found almost nothing.');
    }
}
