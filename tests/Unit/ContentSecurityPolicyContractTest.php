declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;

final class ContentSecurityPolicyContractTest extends TestCase
{
    /** Templates that may hold a style, each with its reason. */
    private const STYLED = [
        'resources/views/layout/course-presentation.html.twig' => "the course's own CSS tab",
        'resources/views/partials/course-part-pdf.html.twig' => 'a PDF',
        'resources/views/partials/pdf-site-logo.html.twig' => 'a PDF',
        'resources/views/partials/wallet-statement-pdf.html.twig' => 'a PDF',
        'resources/views/partials/admin/money-report-pdf.html.twig' => 'a PDF',
        'resources/views/partials/admin/ledger-pdf.html.twig' => 'a PDF',
        'resources/views/partials/legal/document-pdf.html.twig' => 'a PDF',
    ];

    public function testNoTemplateRunsAScriptThePolicyWouldRefuse(): void
    {
        $faults = [];
        foreach ($this->templates() as $path => $source) {
            $markup = (string) preg_replace('/\{#.*?#\}/s', '', $source);
            if (preg_match_all('/<[a-zA-Z][^>]*?\son[a-z]+\s*=/', $markup, $handlers) > 0) {
                $faults[] = $path . ': an event handler (' . trim(substr($handlers[0][0], -30)) . ')';
            }
            if (stripos($markup, 'javascript:') !== false) $faults[] = $path . ': a javascript: address';
            preg_match_all('/<script\b([^>]*)>/i', $markup, $scripts);
            foreach ($scripts[1] as $attributes) {
                $fine = preg_match('/\ssrc=/', $attributes) === 1
                    || str_contains($attributes, 'application/ld+json')
                    || str_contains($attributes, 'nonce="{{ csp_nonce() }}"');
                if (!$fine) $faults[] = $path . ': <script' . $attributes . '> has no nonce';
            }
            if (str_contains($markup, 'importmap()')) $faults[] = $path . ": importmap() without the page's nonce";
        }
        self::assertSame([], $faults);
    }

    public function testNoTemplateOfTheSitesOwnHasAStyle(): void
    {
        $faults = [];
        foreach ($this->templates() as $path => $source) {
            if (isset(self::STYLED[$path])) continue;
            $markup = (string) preg_replace('/\{#.*?#\}/s', '', $source);
            if (preg_match('/\sstyle\s*=|<style\b/i', $markup) === 1) $faults[] = $path;
        }
        self::assertSame([], $faults, 'a style belongs in the stylesheet; a length from data is a share class (the Twig filter share)');
    }

    /** @return array<string,string> every template of the site's own and of its bundled theme, by its path from the code root */
    private function templates(): array
    {
        $root = dirname(__DIR__, 2);
        $found = [];
        foreach (['resources/views', 'themes/saharan-sunset'] as $folder) {
            foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root . '/' . $folder)) as $file) {
                if ($file->isFile() && str_ends_with($file->getFilename(), '.twig')) {
                    $found[substr($file->getPathname(), strlen($root) + 1)] = (string) file_get_contents($file->getPathname());
                }
            }
        }
        ksort($found);
        self::assertNotEmpty($found);

        return $found;
    }
}
