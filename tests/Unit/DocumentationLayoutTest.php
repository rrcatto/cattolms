namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class DocumentationLayoutTest extends TestCase
{
    public function testRepositoryRootContainsOnlyApprovedDocumentation(): void
    {
        $root = dirname(__DIR__, 2);
        $rootMarkdown = array_map('basename', glob($root . '/*.md') ?: []);
        sort($rootMarkdown);
        self::assertSame(['CHANGELOG.md', 'README.md'], $rootMarkdown);
        self::assertFileExists($root . '/LICENSE');

        $expected = [
            'COURSE-SPECIFICATION.md',
            'HANDOFF.md',
            'OPERATIONS.md',
            'PROJECT-INSTRUCTIONS.md',
            'ROADMAP.md',
            'THEME-SDK.md',
        ];
        $docs = array_map('basename', glob($root . '/docs/*.md') ?: []);
        sort($docs);
        self::assertSame($expected, $docs, 'docs/ must contain only the six canonical handoff documents.');
    }
}
