declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Application\App;
use PHPUnit\Framework\TestCase;
use ReflectionMethod;

final class ApplicationLoggingContractTest extends TestCase
{
    public function testBootstrapTargetsPersistentApplicationLogAndLogsRequests(): void
    {
        $source = (string) file_get_contents(dirname(__DIR__, 2) . '/src/Application/App.php');

        self::assertStringContainsString("ini_set('error_log', \$logRoot . '/application.log')", $source);
        self::assertStringContainsString('self::logRequest();', $source);
    }

    public function testRequestLogContainsPathButNotQueryString(): void
    {
        $logPath = tempnam(sys_get_temp_dir(), 'catto-application-log-');
        self::assertIsString($logPath);

        $oldErrorLog = (string) ini_get('error_log');
        $oldLogErrors = (string) ini_get('log_errors');
        $oldMethod = $_SERVER['REQUEST_METHOD'] ?? null;
        $oldUri = $_SERVER['REQUEST_URI'] ?? null;

        try {
            ini_set('log_errors', '1');
            ini_set('error_log', $logPath);
            $_SERVER['REQUEST_METHOD'] = 'GET';
            $_SERVER['REQUEST_URI'] = '/auth/consume?token=must-not-be-logged';

            $method = new ReflectionMethod(App::class, 'logRequest');
            $method->invoke(null);

            $log = (string) file_get_contents($logPath);
            self::assertStringContainsString('HTTP GET /auth/consume', $log);
            self::assertStringNotContainsString('must-not-be-logged', $log);
            self::assertStringNotContainsString('?token=', $log);
        } finally {
            ini_set('error_log', $oldErrorLog);
            ini_set('log_errors', $oldLogErrors);
            if ($oldMethod === null) {
                unset($_SERVER['REQUEST_METHOD']);
            } else {
                $_SERVER['REQUEST_METHOD'] = $oldMethod;
            }
            if ($oldUri === null) {
                unset($_SERVER['REQUEST_URI']);
            } else {
                $_SERVER['REQUEST_URI'] = $oldUri;
            }
            @unlink($logPath);
        }
    }
}
