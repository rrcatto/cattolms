`action.button` without an icon falls back to a tick or an arrow, which says nothing about Send, Revoke
or Export, and `action.link` without one draws none at all. So every `ui('action.button')` and
`ui('action.link')` call in Core's templates names its `icon`, every Actions menu names its trigger's,
every section registry action names one, and every name is a symbol in the platform sprite. The one
meaning to one symbol mapping is docs/UI-COMPONENTS.md, "Action icons".

A source contract over the templates rather than a render: the rule is about every call site, and a
render reaches only the pages a test happens to draw.

