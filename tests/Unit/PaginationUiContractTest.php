    /**
     * The Administration list partials are shared between the consolidated workspace and the
     * standalone routes, so they read the complete paginated view contract. A controller that
     * assembles its own payload leaves part of that contract unset, and F3 turns an undefined
     * template variable into a 500 for the whole page — which is exactly how /admin/courses
     * broke while its markup and its literal token checks stayed correct.
     */
    public function testEveryAdministrationSectionRenderTakesItsPayloadFromTheSectionLoader(): void
    {
        foreach (glob(self::root() . '/src/Http/Controller/*.php') ?: [] as $controller) {
            $source = (string) file_get_contents($controller);
            if (!str_contains($source, "'admin_section' =>") && !str_contains($source, "'admin_sections' =>")) continue;

            self::assertTrue(
                str_contains($source, 'sectionData(') || str_contains($source, 'workspacePreview('),
                basename($controller) . ' renders an Administration section, so it must take its data from the section loader.'
            );
        }
    }

    /**
     * The standalone Courses list goes through the same renderer as every other Administration
     * section.
     *
     * It used to be served by AdminCourseController with a request array written out by hand, and
     * that array listed the page and the page size only - so the search box on that one route sent
     * a term nothing read. This test previously asserted that hand-written array was present,
     * which pinned the defect in place: the check passed precisely because the broken line existed.
     *
     * What matters is that no Administration list assembles its own request. The shared renderer
     * reads the search declaration, so a route that uses it cannot drop a term.
     */
    public function testStandaloneCourseAdministrationUsesTheSharedSectionRenderer(): void
    {
        $admin = self::read('src/Http/Controller/AdminController.php');
        $courseController = self::read('src/Http/Controller/AdminCourseController.php');
        $routes = self::read('src/Application/App.php');

        self::assertStringContainsString(
            "\$routes->add('GET /admin/courses', AdminController::class, 'courses');",
            $routes,
            'The Courses list must be routed to the shared Administration controller.'
        );
        self::assertStringContainsString(
            "renderAdministrationSection('courses')",
            $admin,
            'AdminController::courses() must delegate to the shared section renderer.'
        );
        self::assertStringNotContainsString(
            "'courses_page' => \$_GET['courses_page']",
            $courseController,
            'A controller that hand-builds a dataset request will drop the search term, which is '
            . 'exactly how the Courses search shipped doing nothing.'
        );
        self::assertStringNotContainsString('$this->courses->adminCourses($user->id', $courseController);
    }

