    /**
     * Every paginated table offers sortable column headings.
     *
     * This is the check that was missing. Sorting was built, wired to Administration People, listed
     * as "extend it to the other lists" and then not extended - and nothing failed, because no test
     * asked whether a list that pages can also be sorted. A reader on Administration Companies found
     * a paginated table whose headings did nothing.
     *
     * Asserted from the templates rather than from the service, because the template is where the
     * reader's evidence is: a list that draws the shared pagination control is a paginated table, and
     * a paginated table must draw its headings from the shared sort model.
     */
    public function testEveryPaginatedTableOffersSortableHeadings(): void
    {
        $missing = [];

        foreach (self::listPartials() as $path) {
            $markup = (string) file_get_contents($path);

            // The dataset a partial pages on, taken from its own pagination include.
            preg_match_all('/pg: ([a-z_]+)_pagination/', $markup, $matches);
            foreach (array_unique($matches[1]) as $dataset) {
                if (!str_contains($markup, '@' . $dataset . '_sort_headers')) {
                    $missing[] = basename($path) . ' pages ' . $dataset . ' but draws no sortable headings';
                }
            }
        }

        self::assertSame(
            [],
            array_values(array_unique($missing)),
            "A paginated table must let the reader sort it:\n  " . implode("\n  ", $missing)
        );
    }

    /**
     * A sortable heading row is drawn entirely from the shared model.
     *
     * A hand-written cell beside generated ones is how a table ends up with one column that cannot
     * be sorted and no reason on the page for why.
     */
    public function testSortableHeadingRowsCarryNoHandWrittenCells(): void
    {
        $offenders = [];

        foreach (self::listPartials() as $path) {
            $markup = (string) file_get_contents($path);
            if (!str_contains($markup, '_sort_headers')) {
                continue;
            }

            foreach (preg_split('/(?=<tr>)/', $markup) ?: [] as $row) {
                if (!str_contains($row, '_sort_headers')) {
                    continue;
                }
                $head = substr($row, 0, strpos($row, '</tr>') ?: strlen($row));
                if (preg_match('/<th[ >]/', $head) === 1) {
                    $offenders[] = basename($path);
                }
            }
        }

        self::assertSame([], array_values(array_unique($offenders)));
    }

    /** @return list<string> */
    private static function listPartials(): array
    {
        $root = dirname(__DIR__, 2) . '/resources/views/partials';
        $paths = array_merge(
            glob($root . '/admin/*.html') ?: [],
            glob($root . '/company/*.html') ?: []
        );

        return array_values(array_filter(
            $paths,
            static fn(string $path): bool => str_contains((string) file_get_contents($path), 'partials/pagination.html.twig')
        ));
    }
