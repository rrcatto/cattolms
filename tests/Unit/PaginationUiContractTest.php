    /**
     * Every dataset that renders the shared control has the htmx swap region the control targets.
     *
     * The control derives `#<dataset>-region` and `#<dataset>-results` from the dataset prefix, by
     * the same convention the shared search uses, so a caller cannot point a control at another
     * table's rows. The cost of that convention is that a surface which includes the control
     * without declaring the region gets links that silently do nothing under htmx while working
     * perfectly with JavaScript disabled - the worst possible way for this to break, and invisible
     * to every other test here.
     *
     * The region is looked for across all views rather than in the same file, because two surfaces
     * legitimately split them: the Switch Company picker renders its rows in a fragment and its
     * region in the page that includes it.
     */
    public function testEveryPaginatedDatasetDeclaresItsHtmxRegion(): void
    {
        $views = self::root() . '/resources/views';
        $markup = '';
        $datasets = [];

        $directory = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($views));
        foreach ($directory as $file) {
            if ($file->isDir() || $file->getExtension() !== 'twig') continue;
            $contents = (string) file_get_contents($file->getPathname());
            $markup .= $contents;
            if (preg_match_all('/with \{pg: ([a-z_]+)_pagination\}/', $contents, $matches) > 0) {
                foreach ($matches[1] as $dataset) $datasets[$dataset] = true;
            }
        }

        self::assertGreaterThanOrEqual(10, count($datasets), 'The scan must actually be finding the paginated lists.');

        foreach (array_keys($datasets) as $dataset) {
            self::assertStringContainsString(
                'id="' . $dataset . '-region"',
                $markup,
                $dataset . ' renders the shared pagination control, so it must declare the region the control swaps.'
            );
            self::assertStringContainsString(
                'id="' . $dataset . '-results"',
                $markup,
                $dataset . ' must declare the results element the control replaces inside that region.'
            );
        }
    }

