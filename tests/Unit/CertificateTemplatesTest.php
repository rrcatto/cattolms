final class CertificateTemplatesTest extends TestCase
{
    private DocumentTemplateRenderer $renderer;

    protected function setUp(): void
    {
        $registry = new PlaceholderRegistry();
        $this->renderer = new DocumentTemplateRenderer(
            new DocumentTemplateRepository($this->createStub(Database::class)),
            $registry,
            new TemplateValidator($registry),
            new DocumentValueFormatter(new DateTimeZone('Africa/Johannesburg')),
        );
    }

    public function testThereAreClassicModernAndMinimalDesignsWithClassicAsTheDefault(): void
    {
        $presets = DocumentTemplateDefaults::presets(DocumentType::Certificate);
        self::assertSame(['Classic certificate', 'Modern certificate', 'Minimal certificate'], array_column($presets, 'name'));
        self::assertSame('Classic certificate', DocumentTemplateDefaults::for(DocumentType::Certificate)['name']);
        $settings = DocumentType::Certificate->defaultSettings();
        self::assertSame(['A4', 'landscape'], [$settings->size, $settings->orientation]);
    }

    /** @return iterable<string,array{string}> */
    public static function designs(): iterable
    {
        foreach (DocumentTemplateDefaults::presets(DocumentType::Certificate) as $preset) {
            yield $preset['name'] => [$preset['key']];
        }
    }

    #[DataProvider('designs')]
    public function testEachDesignRendersTheSampleCertificateOnOneLandscapePage(string $key): void
    {
        $document = $this->render($key, DocumentSampleData::for(DocumentType::Certificate));
        foreach (['Thandiwe Mokoena', 'Fire Safety for Workplace Supervisors', 'CL-CERT-2026-000184', 'Dr. Pieter van der Merwe', '86.50%', '29 September 2026'] as $text) {
            self::assertStringContainsString($text, $document->body);
        }
        self::assertStringNotContainsString('{{', $document->body);
        self::assertSame(1, self::pages((new DocumentPdfRenderer())->render($document)), $key . ' fits one page.');
    }

    #[DataProvider('designs')]
    public function testLongRealisticValuesStillFitOnePage(string $key): void
    {
        $data = DocumentSampleData::for(DocumentType::Certificate);
        $data['learner.name'] = 'Nomvula Thandeka Zanele Mahlangu-Van der Westhuizen';
        $data['course.title'] = 'Occupational Health and Safety Management Systems: Hazard Identification, Risk Assessment and Incident Investigation for Mining Supervisors';
        $data['course.provider'] = 'Southern African Institute for Mining and Metallurgical Safety Training (Pty) Ltd';
        $data['signatory.name'] = 'Professor Anneline Christina Bezuidenhout-Mokwena';
        $data['signatory.title'] = 'Executive Director: Accredited Learning Programmes and Quality Assurance';
        $data['certificate.footer'] = 'Accredited short course · 40 notional hours · NQF level 5 · SAQA ID 98765 · Valid for three years from the date of issue';
        $document = $this->render($key, $data);
        self::assertStringContainsString('Mahlangu-Van der Westhuizen', $document->body);
        self::assertSame(1, self::pages((new DocumentPdfRenderer())->render($document)), $key . ' keeps long values on one page.');
    }

    #[DataProvider('designs')]
    public function testAbsentResultGradeSignatoryAndFooterLeaveNoEmptyLabels(string $key): void
    {
        $data = DocumentSampleData::for(DocumentType::Certificate);
        foreach (['result.percentage', 'result.grade', 'signatory.name', 'signatory.title', 'certificate.footer', 'course.provider', 'certificate.verification_url'] as $optional) {
            $data[$optional] = null;
        }
        $body = $this->render($key, $data)->body;
        self::assertStringNotContainsString('%', strip_tags($body), 'No percentage, and no meaningless 0%.');
        foreach (['Grade', 'Result', 'Overall result', 'offered by', 'Verify at', 'signature-line'] as $label) {
            self::assertStringNotContainsString($label, $body, $key . ' prints no "' . $label . '" without its value.');
        }
        self::assertStringContainsString('Thandiwe Mokoena', $body);

        $data['result.grade'] = 'Pass';
        self::assertStringContainsString('Pass', $this->render($key, $data)->body, 'A grade without a percentage is shown on its own.');
    }

    public function testTheBuilderAssemblesRealValuesAndLeavesAbsentOnesNull(): void
    {
        $data = CertificateDocumentDataBuilder::assemble(
            ['business.name' => 'Catto Learning'],
            ['title' => 'Fire Safety', 'certificate_title' => '', 'certificate_body_text' => null, 'certificate_footer_text' => ' ', 'certificate_signatory_name' => 'Dr. A',
                'certificate_signatory_title' => '', 'overall_percentage' => '84.5', 'grade_code' => ''],
            'Lerato Dlamini', '', 'CL-2026-ABC', null, '2026-10-07T10:00:00+02:00', '2026-10-06T09:00:00+02:00'
        );
        self::assertSame(CertificateDocumentDataBuilder::DEFAULT_TITLE, $data['certificate.title']);
        self::assertSame(CertificateDocumentDataBuilder::DEFAULT_BODY, $data['certificate.body']);
        self::assertSame('84.50', $data['result.percentage']);
        foreach (['certificate.footer', 'signatory.title', 'result.grade', 'course.provider', 'certificate.verification_url'] as $absent) {
            self::assertNull($data[$absent], $absent);
        }
        self::assertSame('Dr. A', $data['signatory.name']);
        self::assertSame('Learner', CertificateDocumentDataBuilder::learnerName([]));
        self::assertSame('Thandi', CertificateDocumentDataBuilder::learnerName(['certificate_name' => ' ', 'display_name' => 'Thandi', 'email' => 't@example.test']));
        // The assembled data renders as it is: no placeholder is missing or unknown.
        $preset = DocumentTemplateDefaults::for(DocumentType::Certificate);
        self::assertStringContainsString('Lerato Dlamini', $this->renderer->renderSource(DocumentType::Certificate, $preset['html'], $preset['css'], DocumentType::Certificate->defaultSettings(), $data)->body);
    }

    public function testTheCertificateNumberKeepsTheExistingRule(): void
    {
        $publicId = '9141c30f-7167-4abc-8def-0123456789ab';
        self::assertSame('CL-2026-9141C30F7167', \CattoLearning\Course\Certificate\CertificateIssuer::number($publicId, new \DateTimeImmutable('2026-10-07 10:00', new DateTimeZone('Africa/Johannesburg'))));
        // The year is the UTC year, as before: half past midnight in Johannesburg on 1 January is still the old year in UTC.
        self::assertSame('CL-2025-9141C30F7167', \CattoLearning\Course\Certificate\CertificateIssuer::number($publicId, new \DateTimeImmutable('2026-01-01 00:30', new DateTimeZone('Africa/Johannesburg'))));
    }

    public function testEveryPhaseIRuleStillHoldsForCertificateTemplates(): void
    {
        $validator = new TemplateValidator(new PlaceholderRegistry());
        foreach ([
            '<script>alert(1)</script><p>{{ learner.name }}</p>' => '<script>',
            '<img src="https://example.com/signature.png">' => 'embedded data: images',
            '<p onclick="x()">{{ learner.name }}</p>' => 'Event handler',
            '<p>{{ learner.name|raw }}</p>' => 'Filters',
            '{% include "base.html.twig" %}' => 'Twig tags',
            '<p>{{ learner.password }}</p>' => 'Unknown placeholder',
            '<p>{{ invoice.number }}</p>' => 'not a certificate placeholder',
        ] as $html => $message) {
            try {
                $validator->validate(DocumentType::Certificate, $html, '');
                self::fail('Refused: ' . $html);
            } catch (TemplateValidationException $refused) {
                self::assertStringContainsString($message, implode(' ', $refused->errors));
            }
        }
        $signature = '<img alt="Signature" src="data:image/png;base64,iVBORw0KGgo=">';
        $validator->validate(DocumentType::Certificate, $signature . '<p>{{ signatory.name }}</p>', '');
        self::addToAssertionCount(1);
    }

    public function testTheOldCertificateRendererIsGone(): void
    {
        $root = dirname(__DIR__, 2);
        $sources = '';
        foreach (['src', 'resources/views', 'database/migrations'] as $directory) {
            foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($root . '/' . $directory, \FilesystemIterator::SKIP_DOTS)) as $file) {
                if (preg_match('/\.(php|twig)$/', (string) $file) === 1) {
                    $sources .= file_get_contents((string) $file);
                }
            }
        }
        foreach (['certificate_template_html', 'certificate_template_css', 'template_html_snapshot', "'{{' . \$key . '}}'", '{{student_name}}', 'previewCertificate', 'function createCertificate('] as $obsolete) {
            self::assertStringNotContainsString($obsolete, $sources, 'The old certificate renderer must not return: ' . $obsolete);
        }
    }

    /** @param array<string,mixed> $data */
    private function render(string $key, array $data): RenderedDocument
    {
        foreach (DocumentTemplateDefaults::presets(DocumentType::Certificate) as $preset) {
            if ($preset['key'] === $key) {
                return $this->renderer->renderSource(DocumentType::Certificate, $preset['html'], $preset['css'], DocumentType::Certificate->defaultSettings(), $data);
            }
        }
        self::fail('No design ' . $key);
    }

    /** Pages in a PDF: page objects, not the page tree. */
    private static function pages(string $pdf): int
    {
        return preg_match_all('#/Type\s*/Page(?![a-zA-Z])#', $pdf);
    }
