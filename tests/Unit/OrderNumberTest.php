declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Commerce\Application\BankPayments;
use CattoLearning\Commerce\Domain\OrderNumber;
use CattoLearning\Commerce\Http\AttentionController;
use CattoLearning\Commerce\Http\CommerceController;
use CattoLearning\Commerce\Http\PaymentAdministrationController;
use CattoLearning\Support\Address\OrderAddress;
use PHPUnit\Framework\TestCase;
use ReflectionClass;
use Symfony\Component\Routing\Attribute\Route;

final class OrderNumberTest extends TestCase
{
    public function testTheNumberIsMadeAndReadOneWayOnly(): void
    {
        self::assertSame('CL-00000689', OrderNumber::format(689));
        self::assertSame('CL-123456789', OrderNumber::format(123456789), 'An order past the eighth digit keeps every digit.');
        self::assertSame(689, OrderNumber::id('CL-00000689'));
        self::assertSame(123456789, OrderNumber::id('CL-123456789'));
        foreach (['689', 'CL-689', 'CL-000000689', 'cl-00000689', 'CL00000689', ' CL-00000689', 'CL-00000689 ', 'CL-00000000', 'CL-0000068A', 'INV-00000689', ''] as $near) {
            self::assertNull(OrderNumber::id($near), '"' . $near . '" names no order: an address names an order one way.');
        }
    }

    public function testAPayerWritingTheNumberLooselyStillFindsTheOrder(): void
    {
        self::assertSame(183, BankPayments::orderNumberIn('CL-00000183'));
        self::assertSame(183, BankPayments::orderNumberIn('Payment for cl00000183 thanks'), 'A payer often leaves the hyphen out, in either case.');
        self::assertSame(183, BankPayments::orderNumberIn('June fees, CL-00000183'));
        self::assertNull(BankPayments::orderNumberIn('CL-00000000'), 'There is no order nought.');
        self::assertNull(BankPayments::orderNumberIn('CL-183'), 'Only the eight digits the site writes.');
        self::assertNull(BankPayments::orderNumberIn('Payment 00000183'));
    }

    public function testTheAddressesAreMadeFromTheNumber(): void
    {
        self::assertSame('/account/orders/CL-00000689/pay', OrderAddress::buyer(689, '/pay'));
        self::assertSame('/admin/commerce/orders/CL-00000689', OrderAddress::admin('CL-00000689'));
        self::assertSame('/admin/commerce/orders/CL-00000689/documents/REC-00000042', OrderAddress::document('admin', 689, 'REC-00000042'));
        self::assertSame('order=CL-00000689', OrderAddress::query(689));
        self::assertSame('/admin/commerce/attention/underpaid/CL-00000689/email', OrderAddress::attention('underpaid', '689', '/email'));
        // An overpayment, or a payment after cancelling, is a ledger line: one order can have two, so each keeps its line's number.
        self::assertSame('/admin/commerce/attention/overpaid/41', OrderAddress::attention('overpaid', 41));
        self::assertSame('/admin/commerce/attention/refund_to_pay/5', OrderAddress::attention('refund_to_pay', 5));
    }

    /** Every route of an order and its documents takes the order's number and the document's, and refuses a row id. */
    public function testTheOrderRoutesTakeNumbersAndRefuseRowIds(): void
    {
        $checked = 0;
        foreach ([CommerceController::class, PaymentAdministrationController::class, AttentionController::class] as $class) {
            foreach ((new ReflectionClass($class))->getMethods() as $method) {
                foreach ($method->getAttributes(Route::class) as $attribute) {
                    $route = $attribute->newInstance();
                    $path = (string) $route->path;
                    if (preg_match('#^/(account/orders|admin/commerce/orders)/\{#', $path) !== 1 && !in_array('underpaid', explode('|', (string) ($route->requirements['kind'] ?? '')), true)) continue;
                    self::assertSame(OrderAddress::REQUIREMENT, $route->requirements['number'] ?? null, $path . ' names its order by its number.');
                    self::assertStringNotContainsString('{id}', $path, $path . ' carries no row id.');
                    foreach (['689', '12', 'CL-689', 'CL-000000689x'] as $near) self::assertDoesNotMatchRegularExpression('#^' . OrderAddress::REQUIREMENT . '$#', $near);
                    if (str_contains($path, '{document}')) {
                        self::assertSame(OrderAddress::DOCUMENT_REQUIREMENT, $route->requirements['document'] ?? null, $path . ' names its document by its number.');
                        foreach (['44', 'INV-44', 'REC-TEST-1'] as $near) self::assertDoesNotMatchRegularExpression('#^' . OrderAddress::DOCUMENT_REQUIREMENT . '$#', $near);
                    }
                    $checked++;
                }
            }
        }
        self::assertSame(11, $checked, 'The buyer\'s four order routes, Administration\'s five, and an underpaid order\'s two attention routes.');
    }
}
