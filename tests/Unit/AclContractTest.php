    /** @return list<string> */
    private function migrationPermissionKeys(string $migration): array
    {
        $start = strpos($migration, 'INSERT INTO permissions');
        $end = strpos($migration, 'CREATE TABLE role_permissions', $start === false ? 0 : $start);
        self::assertNotFalse($start);
        self::assertNotFalse($end);
        $block = substr($migration, (int) $start, (int) $end - (int) $start);
        preg_match_all("/\\('([A-Z]+(?:\\.[A-Z]+)+)'/", $block, $matches);
        return array_values(array_unique($matches[1]));
    }

