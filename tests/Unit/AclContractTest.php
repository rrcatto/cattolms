    private static function baselineMigration(): string
    {
        $matches = glob(dirname(__DIR__, 2) . '/database/migrations/*_baseline.php') ?: [];
        if (count($matches) !== 1) {
            throw new \RuntimeException('Expected exactly one baseline migration, found ' . count($matches) . '.');
        }

        return (string) file_get_contents($matches[0]);
    }

    public function testPermissionCatalogueAndBaselineSchemaStayAligned(): void
    {
        $root = dirname(__DIR__, 2);
        $migration = self::baselineMigration();
        $catalog = new PermissionCatalog();
        $keys = $catalog->keys();

        self::assertSame($keys, array_values(array_unique($keys)));
        self::assertCount(10, array_values(array_filter($keys, static fn(string $key): bool => str_starts_with($key, 'SYSTEM.'))));
        // 71 since v0.6: COURSE.TAG.MANAGE joined COURSE.CATEGORY.MANAGE when tags gained an
        // administration surface. Tags and categories are separate keys because they are separate
        // decisions - a tag is cross-cutting classification and a category is the catalogue's
        // structure - and an installation may well want one delegated and not the other.
        self::assertCount(71, $catalog->businessKeys());

        $actions = ['VIEW','CREATE','EDIT','MANAGE','DELETE','START','TAKE','REQUEST','FAVOURITE','PREVIEW','PUBLISH','IMPORT','EXPORT','PRUNE','TEST','RECONCILE'];
        foreach ($keys as $key) {
            self::assertMatchesRegularExpression('/^[A-Z]+(?:\.[A-Z]+)*$/', $key);
            self::assertContains(substr($key, (int) strrpos($key, '.') + 1), $actions, 'Permission action must be the final token: ' . $key);
            self::assertFalse(str_starts_with($key, 'REAL.'), 'REAL data visibility must not be encoded in permission keys.');
            self::assertFalse(str_starts_with($key, 'SEED.'), 'SEED data visibility must not be encoded in permission keys.');
            self::assertFalse(str_starts_with($key, 'API.'), 'API transport scopes must not be duplicated in the ACL catalogue.');
        }

        $migrationPermissions = $this->migrationPermissionKeys($migration);
        sort($keys);
        sort($migrationPermissions);
        self::assertSame($keys, $migrationPermissions, 'PermissionCatalog and the baseline migration must contain exactly the same permission keys.');
    }

