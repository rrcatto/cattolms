Description:
The slanted texture is a named platform element, defined once and available to every theme.

The owner's definition, 2026/09/10: "bands that slant at 45 degrees from top left to bottom right.
It has two bands rows each about 10px thick, alternating in colour, light grey with a darker grey."

It began as one theme's stage canvas. Named, it becomes core's, and the point of naming it is that
the next theme does not write its own gradient at its own angle and call it the same thing. So this
asserts the definition is still core's and still says what the owner said: the angle, the two bands,
the thickness, and the three custom properties a theme re-colours it through rather than replacing
it.

The properties matter as much as the gradient. A theme that needs a darker texture sets
--cl-texture-dark; a theme that writes `background: repeating-linear-gradient(...)` of its own has
forked the element, and the platform then has two textures wearing one name.

Architectural boundary: unit. It reads the core stylesheet and touches nothing else.

Changelog:
2026/09/10 02:25 SAST
- Created when the slanted texture became a named element.
