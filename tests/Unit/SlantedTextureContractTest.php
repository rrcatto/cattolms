declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class SlantedTextureContractTest extends TestCase
{
    private const CORE_CSS = __DIR__ . '/../../public_html/css/catto-platform.css';

    public function testCoreDefinesTheTextureTheOwnerDescribed(): void
    {
        $css = self::stylesheet();

        foreach ([
            '--cl-texture-light:' => 'the lighter of the two bands',
            '--cl-texture-dark:' => 'the darker of the two bands',
            '--cl-texture-band:10px' => 'bands about 10px thick',
            '--cl-texture-angle:45deg' => 'slanting at 45 degrees from top left to bottom right',
            '.cl-slanted-texture' => 'the named class itself',
        ] as $token => $what) {
            self::assertStringContainsString(
                $token,
                $css,
                'Core no longer states ' . $what . ' (' . $token . '), so the slanted texture is not defined.'
            );
        }

        // Two bands, alternating, drawn from the properties rather than from literals - which is
        // what makes it re-colourable by a theme instead of only re-writable.
        self::assertMatchesRegularExpression(
            '/repeating-linear-gradient\(var\(--cl-texture-angle\),\s*var\(--cl-texture-dark\)\s*0\s*var\(--cl-texture-band\),\s*var\(--cl-texture-light\)\s*var\(--cl-texture-band\)\s*calc\(var\(--cl-texture-band\)\s*\*\s*2\)\)/',
            $css,
            'The texture must be two alternating bands built from the custom properties.'
        );
    }

    public function testTheTextureIsAvailableWithoutATheme(): void
    {
        // Availability is the whole reason it moved into core: a theme should have to set three
        // colours at most, never redefine the element. If the class only existed in a theme
        // stylesheet, "available in all themes" would mean five copies to keep in step.
        $css = self::stylesheet();

        $bare = (int) preg_match('/(^|})\s*:root\s*\{[^}]*--cl-texture-angle/', $css);
        self::assertSame(
            1,
            $bare,
            'The texture properties must be declared on a bare :root, or a theme that sets none of '
            . 'them gets no texture at all.'
        );
    }

    private static function stylesheet(): string
    {
        // Comments are stripped first. A guard that matches its own explanatory comment passes
        // while the rule it protects is gone, which has happened in this codebase twice.
        $css = (string) file_get_contents(self::CORE_CSS);

        return (string) preg_replace('#/\*.*?\*/#s', '', $css);
    }
}
