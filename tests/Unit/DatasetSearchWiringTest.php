declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Application\PlatformAdministrationService;
use CattoLearning\Http\Controller\AdminController;
use CattoLearning\Http\Controller\CompanyController;
use PHPUnit\Framework\TestCase;
use ReflectionMethod;

final class DatasetSearchWiringTest extends TestCase
{
    /** @var array<string,mixed> */
    private array $originalGet = [];

    protected function setUp(): void
    {
        $this->originalGet = $_GET;
    }

    protected function tearDown(): void
    {
        $_GET = $this->originalGet;
    }

    /**
     * Invokes a controller's private request collector without constructing the controller.
     *
     * The collector reads superglobals and touches nothing else, so it can be exercised in
     * isolation. That matters: this is the exact layer the defect lived in, and a test that needed
     * a database to reach it would have been written as an Integration test and never run.
     *
     * @return array<string,mixed>
     */
    private static function collect(string $class, string ...$arguments): array
    {
        $method = new ReflectionMethod($class, 'sectionRequest');

        /** @var array<string,mixed> $collected */
        $collected = $method->invokeArgs(
            (new \ReflectionClass($class))->newInstanceWithoutConstructor(),
            $arguments
        );

        return $collected;
    }

    /**
     * A term typed into the Administration search reaches the collected request.
     *
     * This is the test that fails against the shipped defect.
     */
    public function testAdministrationCollectsTheSearchTermFromTheRequest(): void
    {
        $_GET = ['companies_q' => 'acme'];

        $collected = self::collect(AdminController::class, 'companies');

        self::assertArrayHasKey('companies_q', $collected, 'The term must be collected from the request.');
        self::assertSame('acme', PlatformAdministrationService::companySearchTerm($collected));
    }

    /** The Company workspace collects it too, on its own routes. */
    public function testCompanyCollectsTheSearchTermFromTheRequest(): void
    {
        $_GET = ['people_q' => 'ndlovu'];

        $collected = self::collect(CompanyController::class);

        self::assertArrayHasKey('people_q', $collected);
        self::assertSame('ndlovu', PlatformAdministrationService::searchTerm('people', $collected));
    }

    /**
     * Every dataset that declares a search has its parameter collected.
     *
     * The guard against this recurring. Adding search to a dataset without adding it to a
     * hardcoded list in the controller is exactly how it broke; the collector reads the
     * declaration, and this fails if the two ever come apart.
     */
    public function testEveryDeclaredSearchIsCollectedByBothControllers(): void
    {
        $_GET = [];
        foreach (array_keys(PlatformAdministrationService::SEARCHABLE_DATASETS) as $dataset) {
            $_GET[PlatformAdministrationService::searchParam($dataset)] = 'term-' . $dataset;
        }

        $admin = self::collect(AdminController::class, 'companies');
        $company = self::collect(CompanyController::class);

        foreach (array_keys(PlatformAdministrationService::SEARCHABLE_DATASETS) as $dataset) {
            $param = PlatformAdministrationService::searchParam($dataset);
            self::assertArrayHasKey($param, $admin, 'Administration must collect ' . $param);
            self::assertArrayHasKey($param, $company, 'Company must collect ' . $param);
        }
    }

    /**
     * A dataset that declares a search actually applies it.
     *
     * Courses shipped declared, collected from the request, given a search box in the template -
     * and never passed to a query. Every layer looked present and typing did nothing, which is the
     * hardest kind of gap to see: nothing is missing, one link is simply not connected.
     *
     * Asserted against the service, because that is where the term is read and handed on.
     */
    public function testEveryDeclaredSearchIsAppliedByTheService(): void
    {
        $service = (string) file_get_contents(
            dirname(__DIR__, 2) . '/src/Application/PlatformAdministrationService.php'
        );

        foreach (array_keys(PlatformAdministrationService::SEARCHABLE_DATASETS) as $dataset) {
            if ($dataset === 'seed') {
                // Declared for the Seed Database list, which is not built yet and is reported as
                // outstanding rather than quietly passing this check.
                continue;
            }
            self::assertStringContainsString(
                "searchTerm('" . $dataset . "'",
                $service,
                'The ' . $dataset . ' dataset declares a search that the service never reads, so '
                . 'its box will do nothing.'
            );
        }
    }

    /** An absent term collects as nothing rather than as a filter that matches nothing. */
    public function testAnAbsentTermIsEmptyNotNull(): void
    {
        $_GET = [];

        $collected = self::collect(AdminController::class, 'companies');

        self::assertSame('', PlatformAdministrationService::searchTerm('companies', $collected));
        self::assertSame('', PlatformAdministrationService::searchTerm('people', []));
    }

    /** A term is trimmed and capped, so an enormous paste is not handed to the database. */
    public function testTheTermIsTrimmedAndCapped(): void
    {
        self::assertSame('acme', PlatformAdministrationService::searchTerm('companies', ['companies_q' => "  acme \n"]));
        self::assertSame(120, mb_strlen(PlatformAdministrationService::searchTerm('companies', ['companies_q' => str_repeat('x', 400)])));
    }

    /**
     * The htmx fragment path supplies what a fragment's markup reads.
     *
     * The other half of the round's failure: a form inside a fragment needs a CSRF token, the
     * fragment renderer did not set one, and the render died mid-output. Asserted against the
     * renderer's source rather than a test hive on purpose - the test harness supplies a token,
     * which is precisely why every render test passed while the real path could not.
     */
    public function testTheFragmentRendererSuppliesTheFormEssentials(): void
    {
        $renderer = (string) file_get_contents(dirname(__DIR__, 2) . '/src/View/ThemeRenderer.php');
        $fragment = substr($renderer, strpos($renderer, 'public function renderFragment') ?: 0, 1600);

        self::assertStringContainsString("'csrf' => Csrf::token()", $fragment, 'A fragment containing a form needs a token.');
        self::assertStringContainsString("'app_name'", $fragment);
    }

    /**
     * A swap can never destroy the element it targets.
     *
     * One malformed response removed the id the next request needed, and the control was dead
     * until the page was reloaded. The target is now an outer wrapper that is never replaced.
     */
    public function testTheSearchSwapTargetsAWrapperItDoesNotReplace(): void
    {
        $control = (string) file_get_contents(dirname(__DIR__, 2) . '/resources/views/partials/dataset-search.html');

        self::assertStringContainsString('hx-target="#{{ @ds_name }}-region"', $control);
        self::assertStringContainsString('hx-select="#{{ @ds_name }}-results"', $control);
        self::assertStringContainsString('hx-swap="innerHTML"', $control, 'outerHTML on the target is what destroyed it.');
    }
}
