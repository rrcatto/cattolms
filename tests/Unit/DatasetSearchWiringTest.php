        }
    }

    /** An absent term collects as nothing rather than as a filter that matches nothing. */
    public function testAnAbsentTermIsEmptyNotNull(): void
    {
        $_GET = [];

        $collected = self::collect(AdminController::class, 'companies');

        self::assertSame('', PlatformAdministrationService::searchTerm('companies', $collected));
        self::assertSame('', PlatformAdministrationService::searchTerm('people', []));
    }

    /** A term is trimmed and capped, so an enormous paste is not handed to the database. */
    public function testTheTermIsTrimmedAndCapped(): void
    {
        self::assertSame('acme', PlatformAdministrationService::searchTerm('companies', ['companies_q' => "  acme \n"]));
        self::assertSame(120, mb_strlen(PlatformAdministrationService::searchTerm('companies', ['companies_q' => str_repeat('x', 400)])));
    }

    /**
     * The htmx fragment path supplies what a fragment's markup reads.
     *
     * The other half of the round's failure: a form inside a fragment needs a CSRF token, the
