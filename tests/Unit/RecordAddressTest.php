    public function testARowIdOrAWrongKeyIsRefused(): void
    {
        $refused = [
            static fn() => PersonAddress::admin('12'),
            static fn() => PersonAddress::admin(['id' => 12]),
            static fn() => PersonAddress::admin('cl2026011510423z'),
            static fn() => PersonAddress::admin('CL-20260115-10423-Z'),
            static fn() => CompanyAddress::admin('7'),
            static fn() => OrderAddress::admin('CL-689'),
            static fn() => OrderAddress::admin(0),
            static fn() => OrderAddress::document('buyer', 689, '44'),
            static fn() => CatalogueAddress::bundle('12'),
            static fn() => CatalogueAddress::promotion('2026'),
            static fn() => CatalogueAddress::category('12'),
            static fn() => CatalogueAddress::category('new'),
            static fn() => CatalogueAddress::tag('Raised-Beds'),
            static fn() => RecordAddress::certificate('admin', '12'),
            static fn() => RecordAddress::message('43'),
            static fn() => CourseItemAddress::admin('2026'),
            static fn() => CourseItemAddress::admin('New'),
            static fn() => CoursePartAddress::reader('growing-vegetables', '78466'),
            static fn() => CoursePartAddress::reader('growing-vegetables', 'review'),
        ];
        foreach ($refused as $at => $make) {
            try {
                $make();
                self::fail('Address ' . $at . ' was made from a row id or a wrong key.');
            } catch (InvalidArgumentException) {
                self::addToAssertionCount(1);
            }
        }
    }

    public function testAnOrderNumberIsReadExactly(): void
    {
        self::assertSame('CL-00000689', OrderNumber::format(689));
        self::assertSame(689, OrderNumber::id('CL-00000689'));
        self::assertSame(123456789, OrderNumber::id('CL-123456789'));
        foreach (['CL-689', 'CL-000000689', 'cl-00000689', 'CL00000689', 'CL-00000000', ' CL-00000689', '689'] as $near) {
            self::assertNull(OrderNumber::id($near), $near . ' names no order.');
        }
    }

    public function testAPartNameIsMadeFromWordsAndKeptFreeInItsCourse(): void
    {
        $taken = ['module-1-presentation' => true, 'summary' => true, 'summary-2' => true];
        $free = static fn(string $name): bool => isset($taken[$name]);
        self::assertSame('module-1-presentation-2', CoursePartAddress::make('Module 1 Presentation', false, $free));
        self::assertSame('summary-3', CoursePartAddress::make('Summary', false, $free));
        self::assertSame('thandis-planting-year', CoursePartAddress::make('Thandi’s Planting Year', true, $free));
        self::assertSame('review-section', CoursePartAddress::make('Review', true, $free));
        self::assertSame('assessment-part', CoursePartAddress::make('Assessment', false, $free));
        self::assertSame('part-2024', CoursePartAddress::make('2024', true, $free));
        self::assertSame('section', CoursePartAddress::make('???', true, $free));
        $long = CoursePartAddress::make(str_repeat('word ', 40), false, $free);
        self::assertLessThanOrEqual(CoursePartAddress::MAXIMUM - 8, strlen($long));
        self::assertMatchesRegularExpression('#^' . CoursePartAddress::REQUIREMENT . '$#', $long);
        self::assertMatchesRegularExpression('#^part-[0-9a-f]{8}$#', CoursePartAddress::provisional());
    }

    public function testACourseItemSlugIsTheDatabasesRule(): void
    {
        self::assertSame('gdn-101-module-1-presentation', CourseItemAddress::slug('GDN-101 Module 1 Presentation'));
        self::assertSame('greenhills-seed-catalogue-2026', CourseItemAddress::slug('Greenhill’s seed catalogue (2026)'));
        self::assertSame('caf-basics', CourseItemAddress::slug('Café basics'));
        self::assertFalse(CourseItemAddress::addressable('2026'));
        self::assertFalse(CourseItemAddress::addressable('New'));
        self::assertTrue(CourseItemAddress::addressable('New lesson'));
    }
