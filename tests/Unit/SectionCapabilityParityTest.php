declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class SectionCapabilityParityTest extends TestCase
{
    private const CONTROLLER = __DIR__ . '/../../src/Http/Controller/AdminController.php';

    /**
     * The methods every Administration screen passes through, so a flag set in one of them
     * reaches all of them.
     *
     * @var list<string>
     */
    private const SHARED_BUILDERS = [
        'withAdministrationPresentation',
        'sectionCapabilities',
        'administrationFilters',
    ];

    public function testNoCapabilityFlagIsSetInsideASingleRouteAction(): void
    {
        $methods = self::methodBodies();

        self::assertArrayHasKey(
            'withAdministrationPresentation',
            $methods,
            'The controller was not parsed into methods, so this test is examining nothing.'
        );

        $offenders = [];
        foreach ($methods as $name => $body) {
            if (in_array($name, self::SHARED_BUILDERS, true)) {
                continue;
            }
            if (preg_match_all("/\\\$data\[\'(can_[a-z_]+)\'\]\s*=/", $body, $matches) === 0) {
                continue;
            }
            foreach ($matches[1] as $flag) {
                $offenders[] = $name . '() sets ' . $flag;
            }
        }

        self::assertSame(
            [],
            $offenders,
            "A capability flag set inside one route action reaches that screen and no other, so the "
            . "same partial renders different controls on /admin and on the section's own page. Move "
            . "these into withAdministrationPresentation(), which every Administration route calls:\n - "
            . implode("\n - ", $offenders)
        );
    }

    public function testEveryCapabilityFlagASectionPartialReadsIsSetSomewhere(): void
    {
        // The three places a flag may legitimately be assigned, all of which every Administration
        // render passes through: the identity model BaseController builds, the section data the
        // service builds, and the controller's own shared presentation builder.
        $source = self::controllerSource();
        foreach (['/../../src/Http/Controller/BaseController.php', '/../../src/Application/PlatformAdministrationService.php'] as $file) {
            $source .= (string) file_get_contents(__DIR__ . $file);
        }

        $read = [];
        foreach (glob(__DIR__ . '/../../resources/views/partials/admin/*.twig') ?: [] as $file) {
            preg_match_all('/\b(can_[a-z_]+)\b/', (string) file_get_contents($file), $matches);
            foreach ($matches[1] as $flag) {
                $read[$flag] = basename($file);
            }
        }

        self::assertNotSame([], $read, 'No capability flags were found in the section partials.');

        $never = [];
        foreach ($read as $flag => $file) {
            if (!str_contains($source, "'" . $flag . "'")) {
                $never[] = $flag . ' (read by ' . $file . ')';
            }
        }

        self::assertSame(
            [],
            $never,
            "These flags decide whether a control is drawn and are never assigned, so under "
            . "strict_variables the control is simply never drawn:\n - " . implode("\n - ", $never)
        );
    }

    /**
     * Each method of the controller, keyed by name.
     *
     * @return array<string,string>
     */
    private static function methodBodies(): array
    {
        $source = self::controllerSource();
        preg_match_all('/\n    (?:private|protected|public)[^\n]*function (\w+)\(/', $source, $matches, PREG_OFFSET_CAPTURE);

        $bodies = [];
        $starts = $matches[0];
        foreach ($matches[1] as $index => [$name, $_]) {
            $from = (int) $starts[$index][1];
            $to = isset($starts[$index + 1]) ? (int) $starts[$index + 1][1] : strlen($source);
            $bodies[$name] = substr($source, $from, $to - $from);
        }

        return $bodies;
    }

    private static function controllerSource(): string
    {
        return str_replace("\r\n", "\n", (string) file_get_contents(self::CONTROLLER));
    }
}
