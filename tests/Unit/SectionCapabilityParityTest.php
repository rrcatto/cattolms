One table, rendered from one partial, must offer the same actions wherever it appears.

The owner opened the Companies accordion on /admin and found no Manage action, while the standalone
/admin/companies offered one. Both screens render `partials/admin/companies.html.twig`, and the
partial was correct: it draws Manage behind `can_select_company`, and only the section route set
that flag. The workspace route never did, so the same markup produced two different tables and
nothing failed.

That is the general shape of an inconsistent interface in this codebase, and it is worth stating as
a rule rather than fixing one instance of. A capability flag decides whether a control exists. If
one route sets it and another does not, the two screens disagree about what the reader may do, and
the disagreement is invisible in the template that draws the control.

So: no `can_*` flag may be assigned inside a route action of AdminController. Capability flags come
from `sectionCapabilities()`, from the service that builds the section data, or from
`withAdministrationPresentation()` - all three of which every route goes through. Assigned in an
action, a flag reaches that action's screen and no other.

Architectural boundary: unit. It reads controller source and touches nothing else.

