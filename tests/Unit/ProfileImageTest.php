namespace CattoLearning\Tests\Unit;

use CattoLearning\Support\ProfileImage;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use RuntimeException;

final class ProfileImageTest extends TestCase
{
    protected function setUp(): void
    {
        if (!extension_loaded('gd')) {
            self::markTestSkipped('GD is required to resize a profile image.');
        }
    }

    public function testALandscapeImageBecomesTheStoredSquare(): void
    {
        $image = ProfileImage::fromUpload(self::png(600, 400));

        self::assertSame(ProfileImage::SIZE, $image->width);
        self::assertSame(ProfileImage::SIZE, $image->height);
        self::assertSame('image/png', $image->mimeType, 'One format out means one decoder path back in.');

        $stored = getimagesizefromstring($image->bytes);
        self::assertNotFalse($stored);
        self::assertSame([ProfileImage::SIZE, ProfileImage::SIZE], [$stored[0], $stored[1]]);
    }

    public function testAPortraitIsCroppedRatherThanSquashed(): void
    {
        // A portrait squashed into a square is a worse answer than a portrait with its edges
        // trimmed, and every frame that shows a profile image is square or round.
        $image = ProfileImage::fromUpload(self::png(300, 900));

        self::assertSame(ProfileImage::SIZE, $image->width);
        self::assertSame(ProfileImage::SIZE, $image->height);
    }

    public function testAJpegIsAcceptedAndStoredAsPng(): void
    {
        $image = ProfileImage::fromUpload(self::jpeg(400, 400));

        self::assertSame('image/png', $image->mimeType);
        self::assertSame(IMAGETYPE_PNG, (int) (getimagesizefromstring($image->bytes)[2] ?? 0));
    }

    public function testAFileThatIsNotAnImageIsRefused(): void
    {
        $this->expectExceptionMessageMatches('/not a PNG, JPEG or WebP/');
        ProfileImage::fromUpload('GIF89a this is not really an image at all');
    }

    public function testAPhpFileWearingAnImageNameIsRefused(): void
    {
        // The name and the Content-Type are the client's to choose, so neither is evidence. This is
        // the same check as above stated as the case it exists for.
        $this->expectException(RuntimeException::class);
        ProfileImage::fromUpload("<?php echo 'hello'; ?>\n");
    }

    public function testAnEmptyUploadIsRefused(): void
    {
        $this->expectExceptionMessageMatches('/No image was received/');
        ProfileImage::fromUpload('');
    }

    public function testAnOversizedFileIsRefused(): void
    {
        $this->expectExceptionMessageMatches('/larger than 8 MB/');
        ProfileImage::fromUpload(str_repeat('x', ProfileImage::MAX_UPLOAD_BYTES + 1));
    }

    public function testAnImageWithTooManyPixelsIsRefusedBeforeItIsDecoded(): void
    {
        // A blank PNG of 9000 by 9000 compresses to a few hundred kilobytes and would want more
        // than 300MB to decode. The header states the dimensions, so it never reaches a decoder.
        $huge = self::blankPng(9000, 9000);
        self::assertLessThan(ProfileImage::MAX_UPLOAD_BYTES, strlen($huge), 'The point of this case is a small file with enormous dimensions.');

        $this->expectExceptionMessageMatches('/too many pixels/');
        ProfileImage::fromUpload($huge);
    }

    public function testAnEditedImageIsAcceptedAsAPngDataUrl(): void
    {
        $png = self::markedPng();
        $bytes = ProfileImage::decodeEditedImage('data:image/png;base64,' . base64_encode($png));

        self::assertSame($png, $bytes, 'What the editor posts back is what gets validated.');
    }

    public function testNoEditedImageMeansTheOrdinaryUploadPathTakesOver(): void
    {
        // Every one of these is "no edit", not an error. The file the reader chose is still in the
        // request, so the server takes its own centred square rather than refusing the upload.
        foreach ([
            '',
            'not a data url at all',
            'data:image/jpeg;base64,' . base64_encode('whatever'),
            'data:text/html;base64,' . base64_encode('<script>'),
            'data:image/png;base64,',
            'data:image/png;base64,!!!not-base64!!!',
        ] as $field) {
            self::assertNull(
                ProfileImage::decodeEditedImage($field),
                'This should fall back to the uploaded file: ' . substr($field, 0, 40)
            );
        }
    }

    public function testAnOversizedEditedFieldIsRefusedBeforeItIsDecoded(): void
    {
        // Checked on the encoded length. Decoding first to find out how large something is, is how
        // a size limit becomes the thing it was meant to prevent.
        $this->expectExceptionMessageMatches('/edited image was too large/');
        ProfileImage::decodeEditedImage('data:image/png;base64,' . str_repeat('A', ProfileImage::MAX_EDITED_FIELD_BYTES));
    }

    public function testAnEditedFieldIsStillValidatedAsAnImage(): void
    {
        // The field is a shortcut past the server's cropping, never past its validation. Bytes that
        // decode from base64 but are not an image still have to fail.
        $bytes = ProfileImage::decodeEditedImage('data:image/png;base64,' . base64_encode('<?php echo 1; ?>'));
        self::assertNotNull($bytes);

        $this->expectExceptionMessageMatches('/not a PNG, JPEG or WebP/');
        ProfileImage::fromUpload($bytes);
    }

    /**
     * @return list<array{int,string}>
     */
    public static function orientations(): array
    {
        // Where the marker - drawn on the LEFT of the stored bitmap - ends up once the EXIF
        // orientation has been applied. These are the eight values as the specification defines
        // them, not the three that are merely common.
        return [
            [1, 'left'],   // stored as displayed
            [2, 'right'],  // mirrored
            [3, 'right'],  // 180
            [4, 'left'],   // mirrored then 180 - back to the left, but flipped vertically
            [5, 'top'],    // transpose
            [6, 'top'],    // 90 clockwise
            [7, 'bottom'], // transverse
            [8, 'bottom'], // 270 clockwise
        ];
    }

    #[DataProvider('orientations')]
    public function testTheExifOrientationIsApplied(int $orientation, string $expectedEdge): void
    {
        // The defect the owner reported: two upright photographs imported lying on their side. A
        // camera stores the bitmap its sensor produced and records how it was held in EXIF;
        // imagecreatefromstring decodes the bitmap and ignores the tag.
        $image = ProfileImage::fromUpload(self::jpegWithOrientation($orientation));
        $decoded = imagecreatefromstring($image->bytes);
        self::assertNotFalse($decoded);

        self::assertSame(
            $expectedEdge,
            self::markedEdge($decoded),
            'EXIF orientation ' . $orientation . ' should place the marker on the ' . $expectedEdge . ' edge.'
        );
    }

    public function testAnImageWithNoExifIsLeftAlone(): void
    {
        // A PNG carries no EXIF at all, and exif_read_data warns rather than returning false when
        // handed one - so the orientation step has to decline to look at it.
        $image = ProfileImage::fromUpload(self::markedPng());
        $decoded = imagecreatefromstring($image->bytes);
        self::assertNotFalse($decoded);

        self::assertSame('left', self::markedEdge($decoded), 'Nothing should have been rotated.');
    }

    /** Which edge of a square image carries the red marker. */
    private static function markedEdge(\GdImage $image): string
    {
        $size = imagesx($image);
        $middle = intdiv($size, 2);
        $near = max(4, intdiv($size, 12));

        foreach ([
            'top' => [$middle, $near],
            'bottom' => [$middle, $size - $near],
            'left' => [$near, $middle],
            'right' => [$size - $near, $middle],
        ] as $edge => [$x, $y]) {
            $colour = imagecolorat($image, $x, $y);
            if ((($colour >> 16) & 255) > 180 && (($colour >> 8) & 255) < 80) {
                return $edge;
            }
        }

        return 'none';
    }

    /** A square image with a red bar down its left edge. */
    private static function markedCanvas(int $size): \GdImage
    {
        $image = imagecreatetruecolor($size, $size);
        imagefilledrectangle($image, 0, 0, $size, $size, imagecolorallocate($image, 240, 240, 240));
        imagefilledrectangle($image, 0, 0, intdiv($size, 4), $size, imagecolorallocate($image, 220, 20, 20));

        return $image;
    }

    private static function markedPng(): string
    {
        ob_start();
        imagepng(self::markedCanvas(200));

        return (string) ob_get_clean();
    }

    /**
     * A JPEG carrying a minimal but real EXIF block that declares one orientation.
     *
     * Built rather than shipped as a fixture, so what is asserted is what this environment's own
     * exif_read_data actually parses.
     */
    private static function jpegWithOrientation(int $orientation): string
    {
        ob_start();
        imagejpeg(self::markedCanvas(200), null, 92);
        $jpeg = (string) ob_get_clean();

        // A little-endian TIFF header, one IFD entry (0x0112 Orientation, type SHORT), no next IFD.
        $tiff = "II\x2a\x00" . pack('V', 8)
            . pack('v', 1)
            . pack('v', 0x0112) . pack('v', 3) . pack('V', 1) . pack('v', $orientation) . "\x00\x00"
            . pack('V', 0);
        $payload = "Exif\x00\x00" . $tiff;
        $app1 = "\xFF\xE1" . pack('n', strlen($payload) + 2) . $payload;

        // Immediately after the SOI marker, which is where a decoder looks for it.
        return substr($jpeg, 0, 2) . $app1 . substr($jpeg, 2);
    }

    private static function png(int $width, int $height): string
    {
        $image = imagecreatetruecolor($width, $height);
        imagefilledrectangle($image, 0, 0, $width, $height, imagecolorallocate($image, 40, 90, 160));
        imagefilledellipse($image, intdiv($width, 2), intdiv($height, 2), intdiv($width, 3), intdiv($height, 3), imagecolorallocate($image, 240, 200, 90));
        ob_start();
        imagepng($image);

        return (string) ob_get_clean();
    }

    private static function jpeg(int $width, int $height): string
    {
        $image = imagecreatetruecolor($width, $height);
        imagefilledrectangle($image, 0, 0, $width, $height, imagecolorallocate($image, 200, 60, 60));
        ob_start();
        imagejpeg($image, null, 80);

        return (string) ob_get_clean();
    }

    /**
     * A single-colour PNG, which compresses to almost nothing however large it is.
     *
     * The scanlines are deflated one at a time rather than concatenated first. Nine thousand rows
     * of nine thousand pixels is 243MB of raw bytes, and building that string to prove the subject
     * refuses to build it would be a test that fails for the reason it is testing.
     */
    private static function blankPng(int $width, int $height): string
    {
        $chunk = static fn(string $type, string $data): string =>
            pack('N', strlen($data)) . $type . $data . pack('N', crc32($type . $data));

        $scanline = "\x00" . str_repeat("\xff", $width * 3);
        $deflate = deflate_init(ZLIB_ENCODING_DEFLATE, ['level' => 9]);
        $compressed = '';
        for ($row = 0; $row < $height; $row++) {
            $compressed .= (string) deflate_add($deflate, $scanline, ZLIB_NO_FLUSH);
        }
        $compressed .= (string) deflate_add($deflate, '', ZLIB_FINISH);

        return "\x89PNG\r\n\x1a\n"
            . $chunk('IHDR', pack('NNCCCCC', $width, $height, 8, 2, 0, 0, 0))
            . $chunk('IDAT', $compressed)
            . $chunk('IEND', '');
    }
