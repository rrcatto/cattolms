Description:
An uploaded profile image is whatever the client sent, so every fact about it is checked here.

The three that matter, and why each is a real check rather than a formality:

- the type is read from the bytes. The browser sends a Content-Type and a filename and the client
  chooses both, so a .png that is not a PNG has to fail on its content;
- the pixel count is capped before any decoder sees the file. A decoded bitmap costs four bytes a
  pixel however small the file compressed to, so a highly compressible enormous image is the way to
  exhaust memory, and a byte cap alone does not stop it;
- the output is a square of a known size in a known format, so nothing downstream has to cope with
  a portrait, a 12-megapixel photograph or a format it cannot decode.

The tests build their own images with GD rather than shipping fixture files, so what is asserted is
what this environment actually produces.

