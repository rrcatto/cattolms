namespace CattoLearning\Tests\Unit;

use CattoLearning\Support\Token;
use PHPUnit\Framework\TestCase;

final class TokenTest extends TestCase
{
    public function testGeneratesUrlSafeUnpredictableTokens(): void
    {
        $first = Token::generate();
        $second = Token::generate();
        self::assertNotSame($first, $second);
        self::assertMatchesRegularExpression('/^[A-Za-z0-9_-]+$/', $first);
        self::assertSame(64, strlen(Token::hash($first)));
