declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class CoursePortabilityUniverseContractTest extends TestCase
{
    private static function service(): string
    {
        return (string) file_get_contents(dirname(__DIR__, 2) . '/src/Course/CoursePortabilityService.php');
    }

    /** @return array<string,string> method body, keyed by method name */
    private static function methods(): array
    {
        $source = self::service();
        preg_match_all(
            '/\n    (?:public|private) function (\w+)\([^)]*\)[^{]*\{(.*?)\n    \}/s',
            $source,
            $matches,
            PREG_SET_ORDER
        );
        $bodies = [];
        foreach ($matches as $match) {
            $bodies[$match[1]] = $match[2];
        }

        return $bodies;
    }

    /** Both guards exist and say what they are for. */
    public function testTheUniverseGuardsExist(): void
    {
        $source = self::service();
        self::assertStringContainsString('private function requireRealCourse(int $courseId): array', $source);
        self::assertStringContainsString('private function refuseSeedImporter(int $userId): void', $source);
        self::assertMatchesRegularExpression(
            "/requireRealCourse.*?seed_token.*?\] \?\? null\) !== null/s",
            $source,
            'requireRealCourse must refuse on the course\'s own token.'
        );
        self::assertMatchesRegularExpression(
            '/refuseSeedImporter.*?provenance->fromUser\(\$userId\) !== null/s',
            $source,
            'refuseSeedImporter must refuse on the importing identity\'s token.'
        );
    }

    /**
     * Export refuses a SEED course.
     *
     * exportCourseJson and cloneRevision both route through exportCourse, and the mandate's
     * concern is a genuine ADMIN exporting SEED content and re-importing it as REAL: the refusal
     * is about the course, not the actor's COURSE.EXPORT permission.
     */
    public function testEveryExportPathResolvesTheCourseThroughTheRealGuard(): void
    {
        $methods = self::methods();

        self::assertStringContainsString('$this->requireRealCourse($courseId)', $methods['exportCourse']);
        self::assertStringNotContainsString('$this->courses->findById', $methods['exportCourse']);

        self::assertStringContainsString('$this->requireRealCourse($courseId)', $methods['cloneRevision']);
        self::assertStringContainsString('$this->exportCourse($courseId)', $methods['exportCourseJson']);
    }

    /** Every way into an import refuses a seed identity. */
    public function testEveryImportEntryPointRefusesASeedIdentity(): void
    {
        $methods = self::methods();

        foreach (['stageImport', 'stageBundledImport', 'commitImport'] as $entryPoint) {
            self::assertStringContainsString(
                '$this->refuseSeedImporter($userId);',
                $methods[$entryPoint],
                $entryPoint . '() creates or stages a course and must refuse a seed identity.'
            );
        }
    }

    /**
     * An import always produces a REAL course.
     *
     * Passing the token explicitly rather than letting CourseRepository derive it from the owning
     * company is what makes this true by construction: whatever company an imported course lands
     * in, the course itself is genuine.
     */
    public function testImportCreatesAGenuineCourseExplicitly(): void
    {
        self::assertStringContainsString(
            '$this->courses->createCourse($data, $userId, null);',
            self::methods()['importAnalysis']
        );
    }

    /** Replacing an existing course rewrites it wholesale, so the target must be REAL too. */
    public function testReplacingACourseRequiresAGenuineTarget(): void
    {
        self::assertStringContainsString(
            '$this->requireRealCourse($replaceCourseId)',
            self::methods()['importAnalysis']
        );
    }

    /**
     * The refusal is serialised before the download headers are sent.
     *
     * Otherwise the operator receives an error page carrying a JSON content type and an
     * attachment filename, which the browser saves rather than shows.
     */
    public function testTheExportControllerFailsBeforeItCommitsToADownload(): void
    {
        $controller = (string) file_get_contents(
            dirname(__DIR__, 2) . '/src/Http/Controller/AdminCourseController.php'
        );
        preg_match('/\n    public function export\(\): void\s*\{(.*?)\n    \}/s', $controller, $match);
        self::assertNotEmpty($match, 'AdminCourseController::export() was not found.');

        $body = $match[1];
        $serialised = strpos($body, 'exportCourseJson');
        $header = strpos($body, "header('Content-Type");
        self::assertIsInt($serialised);
        self::assertIsInt($header);
        self::assertLessThan($header, $serialised, 'The export must be serialised before any header is emitted.');
        self::assertStringContainsString('catch (InvalidArgumentException', $body);
    }
}
