declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Infrastructure\Persistence\AuditRepository;
use CattoLearning\Infrastructure\Persistence\OptionRepository;
use CattoLearning\Infrastructure\Persistence\ThemeRegistryRepository;
use CattoLearning\View\ThemeManager;
use PHPUnit\Framework\TestCase;
use ReflectionClass;

final class ThemePaletteTest extends TestCase
{
    private string $root;

    protected function setUp(): void
    {
        parent::setUp();
        $this->root = sys_get_temp_dir() . '/catto-theme-palette-' . bin2hex(random_bytes(6));
        mkdir($this->root . '/instance/themes', 0775, true);
        mkdir($this->root . '/public/themes', 0775, true);
    }

    protected function tearDown(): void
    {
        $this->removeDirectory($this->root);
        parent::tearDown();
    }

    public function testDeclaredPaletteIsSortedDarkestToLightestAndPublished(): void
    {
        $key = 'fixture-v1.0.0';
        $this->writeTheme($key, [
            ['name' => 'One', 'colors' => ['#FFFFFF', '#000000', '#888888', '#222222', '#CCCCCC']],
            ['name' => 'Two', 'colors' => ['#EEEEEE', '#111111', '#AAAAAA', '#444444', '#777777']],
            ['name' => 'Three', 'colors' => ['#F5F5F5', '#101010', '#BBBBBB', '#555555', '#888888']],
            ['name' => 'Four', 'colors' => ['#FFFFFF', '#050505', '#999999', '#444444', '#DDDDDD']],
        ]);

        $manager = $this->manager();
        $configuration = $manager->paletteConfiguration($key);

        self::assertTrue($configuration['enabled']);
        self::assertTrue($configuration['switcher_visible']);
        self::assertSame(4, $configuration['palette_count']);
        self::assertSame(
            ['#000000', '#222222', '#888888', '#CCCCCC', '#FFFFFF'],
            $configuration['palettes'][0]['colors']
        );

        $manager->publish($key);
        $css = $this->root . '/public/themes/' . $key . '/catto-palette.css';
        self::assertFileExists($css);
        $contents = (string) file_get_contents($css);
        self::assertStringContainsString('--cl-darkest:var(--cl-color-1)', $contents);
        self::assertStringContainsString('--cl-page-bg:var(--cl-color-5)', $contents);
        self::assertStringContainsString('--cl-button-border:var(--cl-color-2)', $contents);
    }

    public function testSinglePaletteIsAutoAppliedWithoutSwitcher(): void
    {
        $key = 'single-v1.0.0';
        $this->writeTheme($key, [
            ['name' => 'Only', 'colors' => ['#FFFFFF', '#000000', '#888888', '#222222', '#CCCCCC']],
        ]);

        $manager = $this->manager();
        $configuration = $manager->paletteConfiguration($key);

        self::assertTrue($configuration['enabled']);
        self::assertFalse($configuration['switcher_visible']);
        self::assertSame(1, $configuration['palette_count']);

        $manager->publish($key);
        self::assertFileExists($this->root . '/public/themes/' . $key . '/catto-palette.css');
    }

    public function testThemeWithoutPalettesKeepsFullColourControl(): void
    {
        $key = 'manual-v1.0.0';
        $this->writeTheme($key, null);

        $manager = $this->manager();
        self::assertFalse($manager->paletteConfiguration($key)['enabled']);

        $manager->publish($key);
        self::assertFileDoesNotExist($this->root . '/public/themes/' . $key . '/catto-palette.css');
    }

    /** @param list<array{name:string,colors:list<string>}>|null $palettes */
    private function writeTheme(string $key, ?array $palettes): void
    {
        $dir = $this->root . '/instance/themes/' . $key;
        mkdir($dir . '/public/css', 0775, true);
        file_put_contents($dir . '/base.html', <<<'HTML'
<!doctype html><html><head><repeat group="{{ @platform.styles }}" value="{{ @style }}"><link rel="stylesheet" href="{{ @style }}"></repeat></head><body>{{ @content | raw }}<repeat group="{{ @platform.scripts }}" value="{{ @script }}"><script src="{{ @script }}"></script></repeat></body></html>
HTML);
        file_put_contents($dir . '/public/css/theme.css', 'body{font-family:sans-serif}');

        $manifest = [
            'format' => 'catto-learning-theme',
            'schema_version' => '3.0',
            'template_api' => '1.0',
            'theme' => [
                'name' => ucfirst(str_replace('-v1.0.0', '', $key)),
                'slug' => str_replace('-v1.0.0', '', $key),
                'version' => '1.0.0',
                'author' => 'Test',
                'description' => 'Palette test fixture',
                'created_at' => '2026-08-15T19:16:00+02:00',
            ],
            'parent' => null,
            'styles' => [],
            'scripts' => [],
            'external' => ['styles' => [], 'scripts' => []],
        ];
        if ($palettes !== null) {
            $manifest['palettes'] = $palettes;
        }
        file_put_contents($dir . '/theme.json', json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
    }

    private function manager(): ThemeManager
    {
        $projectRoot = dirname(__DIR__, 2);
        return new ThemeManager(
            $projectRoot,
            $this->root . '/instance',
            $this->root . '/public',
            (new ReflectionClass(OptionRepository::class))->newInstanceWithoutConstructor(),
            (new ReflectionClass(AuditRepository::class))->newInstanceWithoutConstructor(),
            (new ReflectionClass(ThemeRegistryRepository::class))->newInstanceWithoutConstructor()
        );
    }

    private function removeDirectory(string $dir): void
    {
        if (!is_dir($dir)) return;
        foreach (scandir($dir) ?: [] as $entry) {
            if ($entry === '.' || $entry === '..') continue;
            $path = $dir . '/' . $entry;
            if (is_dir($path)) $this->removeDirectory($path); else @unlink($path);
        }
        @rmdir($dir);
    }
