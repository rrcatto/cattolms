declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class PeopleListContractTest extends TestCase
{
    public function testThePeopleListHasNoBadgeBesideTheName(): void
    {
        $list = (string) file_get_contents(dirname(__DIR__, 2) . '/resources/views/partials/admin/people.html.twig');
        self::assertStringNotContainsString('class="avatar"', $list);
        self::assertStringNotContainsString('{{ person.email }}', $list, 'No email address in the list (owner, 2026-10-21): Last login needs the room.');
        self::assertStringContainsString("{{ person.last_login_at ?: 'Never' }}", $list);
        self::assertStringNotContainsString('initials', preg_replace('/\{#.*?#\}/s', '', $list) ?? '');
    }

    public function testAPersonsPageShowsTheirPictureOrAPlainPlaceholder(): void
    {
        $page = (string) file_get_contents(dirname(__DIR__, 2) . '/resources/views/pages/admin-person-profile.html.twig');
        self::assertStringContainsString('<img class="cl-person-photo" src="{{ profile_image_url }}"', $page);
        self::assertStringContainsString('aria-label="No profile picture"', $page);
        self::assertSame(0, preg_match('#class="avatar"[^>]*>\s*[A-Z]{1,2}\s*<|\|initials#', $page), 'No initials and no fixed letter.');
    }

    /** A role reads as words (owner, 2026-10-20: the role choices printed "CompanyAdministratorCOMPANY_ADMIN"). */
    public function testARoleReadsAsWords(): void
    {
        self::assertSame('Company Administrator', \CattoLearning\View\Twig\PlatformExtension::roleLabel('CompanyAdministrator', 'COMPANY_ADMIN'));
        self::assertSame('Course Editor', \CattoLearning\View\Twig\PlatformExtension::roleLabel('CourseEditor', 'COURSE_EDITOR'));
        self::assertSame('Administrator', \CattoLearning\View\Twig\PlatformExtension::roleLabel('Administrator', 'ADMIN'));
        self::assertSame('Company Admin', \CattoLearning\View\Twig\PlatformExtension::roleLabel('', 'COMPANY_ADMIN'));
        $list = (string) file_get_contents(dirname(__DIR__, 2) . '/resources/views/partials/admin/people.html.twig');
        self::assertStringContainsString("label: role|role_label", $list, 'A person row carries role names, shown in words.');
        $page = (string) file_get_contents(dirname(__DIR__, 2) . '/resources/views/pages/admin-person-profile.html.twig');
        self::assertStringNotContainsString('(roleOption.role_name) ~ (roleOption.role_key)', $page);
        foreach (['resources/views/pages/admin-person-profile.html.twig', 'resources/views/partials/admin/people.html.twig'] as $template) {
            $source = (string) file_get_contents(dirname(__DIR__, 2) . '/' . $template);
            self::assertSame(0, preg_match("#feedback\\.badge', \\{label: \\(role\\)#", $source), $template . ' prints a role key as it is.');
        }
    }
}
