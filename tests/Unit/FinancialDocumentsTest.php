        self::assertSame([['minor' => 487000, 'currency' => 'ZAR'], ['minor' => 48700, 'currency' => 'ZAR'], ['minor' => 438300, 'currency' => 'ZAR']],
            [$data['invoice.subtotal'], $data['invoice.discount'], $data['invoice.total']]);
        self::assertSame(['SPRING10', '10% off'], [$data['promotion.code'], $data['promotion.label']]);
        self::assertSame(['Lerato Dlamini', 'Dlamini & Associates', '4000000001', null, 'Lerato Dlamini', 'lerato@example.test'],
            [$data['customer.billing_name'], $data['customer.organisation'], $data['customer.tax_number'], $data['customer.company_name'], $data['customer.purchaser_name'], $data['customer.email']]);
        self::assertSame(['12 Kéré Street', 'Suite 4', 'Brooklyn', 'Pretoria 0181', 'Gauteng', 'South Africa'], $data['customer.billing_address']);
        self::assertSame(self::BANK, array_intersect_key($data, self::BANK), 'An invoice with something to pay says how to pay by EFT.');
        self::assertSame([
            'description' => 'Bundle: Workplace Safety Essentials',
            'detail' => 'Includes: First Aid Level 1, Incident Reporting, Fire Marshal Basics',
            'quantity' => 1, 'access_period' => '365 days',
            'price' => ['minor' => 179000, 'currency' => 'ZAR'], 'discount' => ['minor' => 17900, 'currency' => 'ZAR'], 'paid' => ['minor' => 161100, 'currency' => 'ZAR'],
        ], $data['items'][1], 'A bundle is the item bought, at its own price, with the courses it included when it was sold.');
        self::assertSame(['Fire Safety for Workplace Supervisors', null, '180 days'], [$data['items'][0]['description'], $data['items'][0]['detail'], $data['items'][2]['access_period']]);
    }

