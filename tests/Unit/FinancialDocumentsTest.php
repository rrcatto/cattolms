    public function testEverySampleDocumentOfTheStandardDesignIsValidAndBecomesAPdf(): void
    {
        $design = FinancialDocumentDesign::standard();
        $pdf = new DocumentPdfRenderer();
        foreach (array_keys(FinancialDocumentSamples::SAMPLES) as $sample) {
            foreach (FinancialDocumentSamples::documents($sample) as $type) {
                $compiled = $this->compiler->compile($design, $type);
                self::assertSame(['A4', 'portrait'], [$compiled['settings']->size, $compiled['settings']->orientation]);
                $document = $this->renderer->renderSource($type, $compiled['html'], $compiled['css'], $compiled['settings'], $this->data($sample, $type));
                self::assertStringNotContainsString('{{', $document->body, $sample . ' ' . $type->value);
                self::assertStringNotContainsString('[[', $document->html, 'No design slot reaches the document.');
                self::assertStringContainsString(FinancialDocumentDesign::STANDARD_NOTES[$type->value], $document->body);
                if ($sample === 'learner') {
                    self::assertStringStartsWith('%PDF-', $pdf->render($document));
                }
            }
        }
    }

    public function testTheDesignFillsOnlyItsSlotsAndANoteIsPlainText(): void
    {
        $logo = new CertificateImage(str_repeat('a', 64), 1200, 300);
        $design = new FinancialDocumentDesign($logo, 'plex-serif', '#7A1F2B', ['invoice' => "Pay within 7 days.\n<b>Thank you</b> {{ business.name }}", 'receipt' => '', 'credit_note' => 'Credited.']);
        self::assertSame([], $design->problems());
        $invoice = $this->compiler->compile($design, DocumentType::Invoice);
        self::assertStringContainsString('<p class="note">Pay within 7 days.<br>&lt;b&gt;Thank you&lt;/b&gt; &#123;&#123; business.name &#125;&#125;</p>', $invoice['html'],
            'A note is printed as typed: neither markup nor a placeholder.');
        self::assertStringContainsString('<img src="asset:' . str_repeat('a', 64) . '" alt="" style="width:60.0mm;height:15.0mm">', $invoice['html'], 'A wide logo is fitted to its width.');
        self::assertStringContainsString('font-family: "Plex Serif"', $invoice['css']);
        self::assertStringContainsString('color: #7A1F2B', $invoice['css']);
        self::assertStringNotContainsString('class="note"', $this->compiler->compile($design, DocumentType::Receipt)['html'], 'An empty note prints nothing.');
        self::assertStringContainsString('<p class="note">Credited.</p>', $this->compiler->compile($design, DocumentType::CreditNote)['html']);
        $tall = new FinancialDocumentDesign(new CertificateImage(str_repeat('b', 64), 200, 400), 'dejavu', '#000000', []);
        self::assertStringContainsString('style="width:8.0mm;height:16.0mm"', $this->compiler->compile($tall, DocumentType::Invoice)['html'], 'A tall logo is fitted to its height.');
        $validator = new TemplateValidator(new PlaceholderRegistry());
        foreach (FinancialDocumentDesign::types() as $type) {
            $compiled = $this->compiler->compile($design, $type);
            self::assertNotSame([], $validator->validate($type, $compiled['html'], $compiled['css']), $type->value . ' with a logo, a note and a colour is a valid template.');
        }
    }

