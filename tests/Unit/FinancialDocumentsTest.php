    public function testTheOldHardCodedFinancialRendererIsGone(): void
    {
        $root = dirname(__DIR__, 2);
        self::assertFileDoesNotExist($root . '/src/Commerce/Infrastructure/InvoicePdfRenderer.php');
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($root . '/src', \FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if (!$file->isFile() || $file->getExtension() !== 'php' || str_ends_with($file->getPathname(), '/src/Document/DocumentPdfRenderer.php')) {
                continue;
            }
            $source = (string) file_get_contents($file->getPathname());
            self::assertDoesNotMatchRegularExpression('/\bnew\s+\\\\?(?:Dompdf\\\\)?Dompdf\s*\(|use\s+Dompdf\\\\/', $source, $file->getPathname() . ' must draw PDFs through DocumentPdfRenderer.');
        }
        foreach (glob($root . '/src/Commerce/**/*.php') ?: [] as $path) {
            self::assertStringNotContainsString('<h2>Billed to</h2>', (string) file_get_contents($path), 'No financial document is written as HTML in code.');
        }
    }

    /** @return array<string,mixed> */
    private function data(string $sample, DocumentType $type): array
    {
        $example = FinancialDocumentSamples::for($sample, $type);
        return FinancialDocumentDataBuilder::assemble($type, $example['order'], $example['snapshot'], $example['number'], $example['issued_at'], $example['context'], self::BUSINESS, self::BANK);
    }

    /** @param array<string,mixed> $data */
    private function html(DocumentType $type, array $data): string
    {
        $compiled = $this->compiler->compile(FinancialDocumentDesign::standard(), $type);
        return $this->renderer->renderSource($type, $compiled['html'], $compiled['css'], $compiled['settings'], $data)->body;
    }
