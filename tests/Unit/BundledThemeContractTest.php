The themes this platform ships live in the code root, and a fresh install installs all of them.

Owner's instruction, 2026/09/10: the four themes that were instance-only are part of the codebase
now - versioned with the code, committed, and installed with the LMS. Factory Reset already was.

Three things have to stay true, and none of them is visible in a browser until an install has
already gone wrong:

- every directory under `themes/` is a valid theme package. An incomplete one is discovered as a
  theme, fails validation at runtime and is silently skipped, so the instance simply comes up with
  fewer themes than it shipped;
- every one of them has an installable package in `extras/themes/` at the same version. That is the
  other route onto an instance - Administration, Themes, Install a theme package - and a tree
  without a package can only reach a server that runs this checkout;
- `smoke:install` actually installs them. Shipping them and not installing them would leave a fresh
  instance exactly where it was before they were added.

The parent ordering is asserted because it is the one thing a directory scan gets wrong on its own:
`factory-reset-sidebar` sorts before `factory-reset`, and a child theme cannot install before the
parent it names.

Architectural boundary: unit. It reads the code root and touches no instance state.

