declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class BundledThemeContractTest extends TestCase
{
    private const ROOT = __DIR__ . '/../..';

    public function testEveryBundledThemeIsAValidPackage(): void
    {
        $themes = self::bundledThemes();

        self::assertGreaterThanOrEqual(
            5,
            count($themes),
            'The platform ships Factory Reset, Factory Reset Sidebar, Gilded Noir, Light Default and '
            . 'Radiant Learning. Fewer than five means one stopped being part of the codebase.'
        );

        foreach ($themes as $slug => $manifest) {
            $meta = (array) ($manifest['theme'] ?? []);
            self::assertSame(
                'catto-learning-theme',
                $manifest['format'] ?? null,
                $slug . ' does not declare the theme package format.'
            );
            self::assertSame(
                $slug,
                $meta['slug'] ?? null,
                'The directory name must be the theme slug, or the installer and the manifest disagree '
                . 'about what is being installed.'
            );
            self::assertMatchesRegularExpression(
                '/^\d+\.\d+\.\d+$/',
                (string) ($meta['version'] ?? ''),
                $slug . ' must declare a semantic version.'
            );
            // base.html.twig is what makes a directory a theme rather than a directory of assets.
            self::assertFileExists(self::ROOT . '/themes/' . $slug . '/base.html.twig');
        }
    }

    public function testEveryBundledThemeShipsAnInstallablePackageAtTheSameVersion(): void
    {
        foreach (self::bundledThemes() as $slug => $manifest) {
            $version = (string) ($manifest['theme']['version'] ?? '');
            $package = self::ROOT . '/extras/themes/' . $slug . '-v' . $version . '.zip';

            self::assertFileExists(
                $package,
                $slug . ' ships as a tree but not as a package, so it can only reach a server running '
                . 'this checkout. Run composer themes:package.'
            );
            self::assertGreaterThan(
                0,
                (int) filesize($package),
                $package . ' is empty. ZipArchive::close() fails silently when it cannot write beside '
                . 'the target, which produces exactly this.'
            );
        }
    }

    public function testAFreshInstallInstallsTheBundledThemes(): void
    {
        $composer = json_decode((string) file_get_contents(self::ROOT . '/composer.json'), true);
        $install = (array) ($composer['scripts']['smoke:install'] ?? []);

        self::assertContains(
            '@themes:install',
            $install,
            'smoke:install must install the bundled themes, or a fresh instance comes up with only '
            . 'the one theme discovery finds in the code root.'
        );

        $installIndex = array_search('@themes:install', $install, true);
        $syncIndex = array_search('@themes:sync', $install, true);
        self::assertIsInt($installIndex);
        self::assertIsInt($syncIndex);
        self::assertLessThan(
            $syncIndex,
            $installIndex,
            'The registry is rebuilt from the filesystem, so the themes have to be on the filesystem '
            . 'before it is rebuilt.'
        );
    }

    public function testAChildThemeNamesAParentThatIsAlsoBundled(): void
    {
        $themes = self::bundledThemes();
        $byName = [];
        foreach ($themes as $manifest) {
            $meta = (array) ($manifest['theme'] ?? []);
            $byName[(string) ($meta['name'] ?? '')] = (string) ($meta['version'] ?? '');
        }

        $children = 0;
        foreach ($themes as $slug => $manifest) {
            $parent = $manifest['parent'] ?? null;
            if (!is_array($parent)) {
                continue;
            }
            $children++;
            $name = (string) ($parent['name'] ?? '');
            self::assertArrayHasKey(
                $name,
                $byName,
                $slug . ' is a child of ' . $name . ', which is not bundled - so it can never install.'
            );
            self::assertSame(
                (string) ($parent['version'] ?? ''),
                $byName[$name],
                $slug . ' names ' . $name . ' ' . (string) ($parent['version'] ?? '') . ' as its parent, '
                . 'but the bundled ' . $name . ' is ' . $byName[$name] . '. A child installs against the '
                . 'exact version it names.'
            );
        }

        self::assertSame(1, $children, 'Factory Reset Sidebar is the one bundled child theme.');
    }

    /**
     * Every bundled theme's manifest, keyed by directory name.
     *
     * @return array<string,array<string,mixed>>
     */
    private static function bundledThemes(): array
    {
        $found = [];
        foreach (glob(self::ROOT . '/themes/*/theme.json') ?: [] as $path) {
            $manifest = json_decode((string) file_get_contents($path), true);
            if (is_array($manifest)) {
                $found[basename(dirname($path))] = $manifest;
            }
        }
        ksort($found);

        return $found;
    }
}
