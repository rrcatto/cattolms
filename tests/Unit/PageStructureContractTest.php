One construction for every page: what main holds, how wide a page is, and where a section's actions sit.

A page is built from a short sequence of rows in main - the page head (the only h1), the identity band,
then one or more page sections - and chooses its width once (ThemeRenderer::pageWidth, the cl-width-*
body class). Rows take their width and spacing from Core's variables, never from Bootstrap container
or spacing classes, so a section can no longer be wider or narrower than its page head, and a theme
draws every page the same way. Each section's content sits in a card that opens with its own heading
(UX rule 1.7, owner's choice of 2026-10-17); a layout.section-grid appears only around two or more
cards. A section's own actions come from its registry and sit in the page head when the section is the
page (owner's decision, 2026-10-16). Menu pages take their kicker from the menu and have no back link:
the breadcrumb is the way back. Group tab strips are gone: the menu leads to each page.

