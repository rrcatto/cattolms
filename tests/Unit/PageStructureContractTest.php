    public function testEveryPageHasOneKnownWidth(): void
    {
        self::assertSame('wide', ThemeRenderer::pageWidth('admin-section'));
        self::assertSame('wide', ThemeRenderer::pageWidth('commerce-orders'), 'My Orders is as wide as the other Account pages (owner, 2026-10-17).');
        self::assertSame('medium', ThemeRenderer::pageWidth('help'));
        self::assertSame('narrow', ThemeRenderer::pageWidth('login'));
        self::assertSame('full', ThemeRenderer::pageWidth('home'));
        self::assertSame('full', ThemeRenderer::pageWidth('landing-page'), 'Course landing pages run full width like Home (owner, 2026-10-17).');
        self::assertSame('medium', ThemeRenderer::pageWidth('admin-section', ['page_width' => 'medium']));
        foreach (array_keys((new \ReflectionClassConstant(ThemeRenderer::class, 'PAGE_WIDTHS'))->getValue()) as $page) {
            self::assertFileExists(self::views() . '/pages/' . $page . '.html.twig', 'PAGE_WIDTHS names ' . $page . ', which is not a page.');
        }
        $this->expectException(RuntimeException::class);
        ThemeRenderer::pageWidth('help', ['page_width' => 'enormous']);
    }

    public function testSectionActionsAreWellFormedAndOpenWindowsTheirSectionDraws(): void
    {
        $registries = [
            'admin' => new AdministrationSectionRegistry(),
            'account' => new AccountSectionRegistry(),
            'company' => new CompanySectionRegistry(),
        ];
        foreach ($registries as $family => $registry) {
            foreach ($registry->all() as $section) {
                $partial = (string) file_get_contents(self::views() . '/' . $section['template']);
                foreach ($registry->actions($section['key']) as $action) {
                    self::assertNotSame('', $action['label'], $family . '/' . $section['key']);
                    self::assertStringNotContainsString('＋', $action['label'], 'The add icon is the plus; the label does not carry another.');
                    self::assertTrue(($action['href'] === '') !== ($action['modal'] === ''), $family . '/' . $section['key'] . ': an action is a link or a button that opens a window, never both.');
                    self::assertContains($action['variant'], ['primary', 'secondary']);
                    if ($action['modal'] !== '') {
                        $drawn = str_contains($partial, "id: '" . $action['modal'] . "'") || str_contains($partial, "'partials/admin/company-modals.html.twig'") || str_contains($partial, '@platform/partials/admin/company-modals.html.twig');
                        self::assertTrue($drawn, $section['template'] . ' must draw the window ' . $action['modal'] . ' its action opens.');
                    }
                }
                if ($registry->actions($section['key']) !== []) {
                    self::assertStringContainsString("{% include '@platform/partials/section-actions.html.twig' with {actions: section_actions|default([])} %}", $partial, $section['template'] . ' shows its actions in its card head on the "All sections" page.');
                }
            }
        }
    }

