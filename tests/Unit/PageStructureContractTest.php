    /** @return array<string,string> relative path => source */
    private static function templates(): array
    {
        $found = [];
        foreach (new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator(self::views(), \FilesystemIterator::SKIP_DOTS)) as $file) {
            if ($file->isFile() && str_ends_with($file->getFilename(), '.twig')) {
                $found[substr($file->getPathname(), strlen(self::views()) + 1)] = (string) file_get_contents($file->getPathname());
            }
        }
        ksort($found);
        return $found;
    }

    public function testRowsCarryNoWidthOrSpacingClasses(): void
    {
        $faults = [];
        foreach (self::templates() as $path => $source) {
            preg_match_all('/<(?:section|div)\b[^>]*\bclass="([^"]*)"/', $source, $matches);
            foreach ($matches[1] as $classAttribute) {
                $classes = preg_split('/\s+/', trim((string) preg_replace('/\{\{.*?\}\}|\{%.*?%\}/s', ' ', $classAttribute))) ?: [];
                if (array_intersect($classes, ['cl-page-section', 'cl-page-head-inner', 'cl-identity-meta']) === []) continue;
                foreach ($classes as $class) {
                    if (preg_match(self::ROW_LAYOUT_CLASS, $class) === 1) $faults[] = $path . ': "' . $classAttribute . '"';
                }
            }
        }
        self::assertSame([], $faults, 'A row takes its width and spacing from the page width and Core\'s variables, never from these classes.');
    }

    public function testTheLegacyHeroAndTheGroupTabStripsAreGone(): void
    {
        foreach (self::templates() as $path => $source) {
            self::assertStringNotContainsString('class="hero"', $source, $path . ' draws the legacy hero: its heading duplicated the page head.');
            self::assertStringNotContainsString('group-nav.html.twig', $source, $path . ' draws a group tab strip; the menu leads to each page.');
