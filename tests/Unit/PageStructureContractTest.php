    }

    public function testASectionGridHoldsTwoOrMoreBlocks(): void
    {
        $single = [];
        foreach (self::templates() as $path => $source) {
            $offset = 0;
            while (preg_match("/\{%-?\s*embed\s+ui_template\('layout\.section-grid'\)[^%]*%\}/", $source, $open, PREG_OFFSET_CAPTURE, $offset) === 1) {
                $start = $open[0][1] + strlen($open[0][0]);
                $offset = $start;
                preg_match_all("/\{%-?\s*(embed|endembed|block|endblock|include|if|for)\b[^%]*%\}|\{\{-?\s*ui\(/", $source, $tokens, PREG_SET_ORDER | PREG_OFFSET_CAPTURE, $start);
                $depth = 0;
                $blocks = 0;
                $children = 0;
                foreach ($tokens as $token) {
                    $kind = $token[1][0] ?? 'ui';
                    if ($kind === 'embed') {
                        if ($depth === 0 && $blocks === 1) $children++;
                        $depth++;
                    } elseif ($kind === 'endembed') {
                        if ($depth === 0) break;
                        $depth--;
                    } elseif ($depth === 0 && $kind === 'block') {
                        $blocks++;
                    } elseif ($depth === 0 && $kind === 'endblock') {
                        $blocks--;
                    } elseif ($depth === 0 && $blocks === 1) {
                        // What remains is an include, a ui() call, an if or a for: each one child.
                        $children++;
                    }
                }
                if ($children === 1 && !str_contains($path, 'admin-theme-import-preview')) $single[] = $path;
            }
        }
        self::assertSame([], $single, 'A section grid around one card is a wrapper, not a layout: place the card in its section.');
    }

    public function testEverySectionAndAllSectionsPageRendersInsidePageSections(): void
    {
        $views = self::views() . '/pages/';
        foreach (['admin-section', 'account-section', 'company-section'] as $page) {
            $source = (string) file_get_contents($views . $page . '.html.twig');
            self::assertMatchesRegularExpression('/<section class="cl-page-section" data-(admin|account|company)-section=/', $source, $page);
            self::assertStringContainsString("{% set ph_actions %}{% include '@platform/partials/section-actions.html.twig'", $source, $page . ' puts the section\'s own actions in its page head.');
            self::assertStringNotContainsString('ph_action_href', $source, $page . ' has no "All … sections" button: the breadcrumb and the menu lead there.');
        }
        foreach (['admin-control-centre' => 'cl-admin-workspace', 'account-control-centre' => 'cl-account-workspace', 'company-control-centre' => 'cl-company-workspace'] as $page => $workspace) {
            $source = (string) file_get_contents($views . $page . '.html.twig');
            self::assertStringContainsString('<section class="cl-page-section ' . $workspace . '"', $source, $page);
            self::assertStringNotContainsString("eyebrow: 'All sections'", $source, $page . ' has no card that repeats the page head.');
        }
    }

