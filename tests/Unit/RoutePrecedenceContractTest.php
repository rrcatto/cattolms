Description:
A catch-all route must never be able to swallow a named one.

`/courses/{slug}` accepts any single word, so it also accepts `/courses/tags`. Symfony matches in
declaration order, and declaration order across two directories is decided by the filename: moving
CourseTagController from one controller directory to the other was enough to put `/courses/{slug}`
in front of `/courses/tags`, and the tag page started answering "The course could not be found".

Nothing failed loudly. The route matched, the controller ran, and the 404 it raised was a truthful
answer to the wrong question - which is the worst shape a routing bug can take, because it looks
like missing data rather than a missing route.

The rule this asserts is that ordering is never left to filenames: a route with a placeholder in a
position where some other route has a literal segment must declare a negative priority, which makes
Symfony match it last whatever order the files load in.

Architectural boundary: unit. It reads the route attributes and touches nothing else.

Changelog:
2026/09/10 02:25 SAST
- Created after /courses/tags was swallowed by /courses/{slug}.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Tests\Support\RouteTable;
use PHPUnit\Framework\TestCase;

final class RoutePrecedenceContractTest extends TestCase
{
    public function testEveryShadowingPlaceholderRouteIsMatchedLast(): void
    {
        $routes = RouteTable::all();
        self::assertNotSame([], $routes, 'No routes were parsed, so this test is examining nothing.');

        $requirements = self::requirements();

        // Two routes collide only when one's pattern matches the other's path outright, so each
        // placeholder route is compiled to a regex and tested against every literal path beside
        // it. Comparing one segment at a time is not enough: /admin/themes/{slug}/delete shares a
        // prefix with /admin/themes/resync and can never match it, because they are different
        // lengths.
        $unprioritised = [];
        foreach ($routes as $route) {
            if (!str_contains($route['path'], '{')) {
                continue;
            }
            $pattern = self::compile($route['path'], $requirements[$route['path']] ?? []);
            foreach ($routes as $other) {
                if ($other['method'] !== $route['method']
                    || str_contains($other['path'], '{')
                    || preg_match($pattern, $other['path']) !== 1
                    || self::declaresNegativePriority($route['path'])
                ) {
                    continue;
                }
                $unprioritised[$route['path'] . '|' . $other['path']] =
                    $route['path'] . ' also matches ' . $other['path'];
            }
        }

        self::assertSame(
            [],
            array_values($unprioritised),
            "These routes can swallow a literal route beside them and do not declare a negative priority, "
            . "so which one wins depends on the order the controller files happen to load:\n - "
            . implode("\n - ", $unprioritised)
        );
    }

    /**
     * One route path as the regex Symfony would match it with.
     *
     * @param array<string,string> $requirements
     */
    private static function compile(string $path, array $requirements): string
    {
        $pattern = (string) preg_replace_callback(
            '/\{(\w+)\}/',
            static fn(array $m): string => '(?:' . ($requirements[$m[1]] ?? '[^/]+') . ')',
            str_replace('#', '\#', $path)
        );

        return '#^' . $pattern . '$#';
    }

    /**
     * The requirement regex declared for each placeholder, keyed by route path then placeholder.
     *
     * @return array<string,array<string,string>>
     */
    private static function requirements(): array
    {
        $found = [];
        foreach (self::controllerSources() as $source) {
            preg_match_all(
                "/#\[Route\('(?P<path>[^']*)'(?P<rest>[^\n]*)\]/",
                $source,
                $matches,
                PREG_SET_ORDER
            );
            foreach ($matches as $match) {
                if (preg_match_all("/'(?P<name>\w+)'\s*=>\s*'(?P<pattern>[^']*)'/", (string) $match['rest'], $pairs, PREG_SET_ORDER) === 0) {
                    continue;
                }
                foreach ($pairs as $pair) {
                    $found[$match['path']][$pair['name']] = $pair['pattern'];
                }
            }
        }

        return $found;
    }

    /** True when the route attribute for this path states a negative priority. */
    private static function declaresNegativePriority(string $path): bool
    {
        foreach (self::controllerSources() as $source) {
            foreach (explode("\n", $source) as $line) {
                if (str_contains($line, "#[Route('" . $path . "'") && preg_match('/priority:\s*-\d+/', $line) === 1) {
                    return true;
                }
            }
        }

        return false;
    }

    /** @return list<string> */
    private static function controllerSources(): array
    {
        $sources = [];
        foreach (glob(__DIR__ . '/../../src/Http/{Controller,Symfony}/*.php', GLOB_BRACE) ?: [] as $file) {
            $sources[] = str_replace("\r\n", "\n", (string) file_get_contents($file));
        }

        return $sources;
    }
}
