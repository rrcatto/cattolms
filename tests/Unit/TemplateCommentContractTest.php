Template notes are written for the next developer and must not be served to the public.

Architectural boundary: contract test. It reads the templates; it renders nothing.

The rule has not changed but the mechanism has, and the new one is better. Under Fat-Free the notes
were HTML comments and the renderer stripped them from every response on the way out - which worked,
and cost a regular expression over the whole of every page, and would have served the lot verbatim
the day someone removed it. A Twig comment is not output at all: it does not survive compilation, so
there is nothing to strip and nothing to forget.

What this asserts is therefore the input rather than the output: no platform template and no bundled
theme template carries an HTML comment. Anything inside a script, style, pre or textarea is left
alone - a comment delimiter inside a script's own string is that script's business.

