declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;

final class TemplateCommentContractTest extends TestCase
{
    /** @return list<string> */
    private function templates(string $root): array
    {
        if (!is_dir($root)) {
            return [];
        }
        $found = [];
        foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root, \FilesystemIterator::SKIP_DOTS)) as $file) {
            if ($file->isFile() && str_ends_with($file->getFilename(), '.twig')) {
                $found[] = $file->getPathname();
            }
        }
        sort($found);

        return $found;
    }

    /** Everything a script, style, pre or textarea holds is that element's business, not ours. */
    private function outsideMarkupIslands(string $source): string
    {
        return (string) preg_replace('#<(script|style|pre|textarea)\b[^>]*>.*?</\1\s*>#is', '', $source);
    }

    public function testNoPlatformTemplateCarriesAnHtmlComment(): void
    {
        $root = dirname(__DIR__, 2) . '/resources/views';
        $templates = $this->templates($root);
        self::assertNotSame([], $templates, 'No platform templates were found to check.');

        foreach ($templates as $path) {
            self::assertStringNotContainsString(
                '<!--',
                $this->outsideMarkupIslands((string) file_get_contents($path)),
                basename($path) . ' carries an HTML comment; template notes go in a Twig comment, which is never served.'
            );
        }
    }

    public function testNoBundledThemeTemplateCarriesAnHtmlComment(): void
    {
        foreach ($this->templates(dirname(__DIR__, 2) . '/themes') as $path) {
            self::assertStringNotContainsString(
                '<!--',
                $this->outsideMarkupIslands((string) file_get_contents($path)),
                $path . ' carries an HTML comment.'
            );
        }
    }

    /** The notes themselves are still there - the point is where they go, not that they went. */
    public function testTheNotesSurvivedAsTwigComments(): void
    {
        $withNotes = 0;
        foreach ($this->templates(dirname(__DIR__, 2) . '/resources/views') as $path) {
            if (str_contains((string) file_get_contents($path), '{#')) {
                $withNotes++;
            }
        }

        self::assertGreaterThan(30, $withNotes, 'The template metadata headers should have survived the port.');
    }
}
