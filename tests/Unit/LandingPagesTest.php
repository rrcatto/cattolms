declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Analytics\AnalyticsEventType;
use CattoLearning\Analytics\CampaignAttribution;
use CattoLearning\Course\Landing\LandingCopy;
use CattoLearning\Course\Landing\LandingSectionType;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class LandingPagesTest extends TestCase
{
    private const ROOT = __DIR__ . '/../..';

    public function testEveryTypeHasAFriendlyLabelADescriptionAndDefaultsThatPassItsOwnSchema(): void
    {
        $labels = [];
        foreach (LandingSectionType::cases() as $type) {
            self::assertNotSame('', $type->label());
            self::assertStringNotContainsString('_', $type->label(), 'No implementation name is shown.');
            self::assertNotSame('', $type->description());
            self::assertSame($type->defaults(), $type->normalise($type->defaults()), $type->value . ' defaults are stored as they are.');
            $labels[] = $type->label();
        }
        self::assertSame(['Hero', 'Who this course is for', 'Learning outcomes', 'Course contents', 'Benefits', 'Instructor', 'Reviews', 'Pricing', 'FAQ', 'Call to action'], $labels);
    }

    public function testOnlyBenefitsQuestionsAndCallsToActionMayRepeat(): void
    {
        $repeatable = array_values(array_filter(LandingSectionType::cases(), static fn(LandingSectionType $type): bool => !$type->once()));
        self::assertSame([LandingSectionType::Benefits, LandingSectionType::Faq, LandingSectionType::Cta], $repeatable);
        $baseline = (string) file_get_contents(self::ROOT . '/database/migrations/20261006120000_create_v088_baseline.php');
        self::assertStringContainsString("WHERE section_type IN ('hero','audience','outcomes','contents','instructor','reviews','pricing')", $baseline, 'The database holds the same rule.');
    }

    public function testANewPageStartsWithTheRecommendedSectionsAndNoCopyWrittenForTheAuthor(): void
    {
        self::assertSame(
            ['hero', 'audience', 'outcomes', 'contents', 'benefits', 'reviews', 'pricing', 'faq', 'cta'],
            array_map(static fn(LandingSectionType $type): string => $type->value, LandingSectionType::starting())
        );
        foreach (LandingSectionType::starting() as $type) {
            $defaults = $type->defaults();
            foreach (['headline', 'text', 'heading'] as $copy) {
                if (array_key_exists($copy, $defaults)) {
                    self::assertSame('', $defaults[$copy], $type->value . ' starts without ' . $copy . '.');
                }
            }
            if (array_key_exists('items', $defaults)) {
                self::assertSame([], $defaults['items']);
            }
        }
    }

    public function testListsAreOneStatementALineAndRowsNeedBothTheirFields(): void
    {
        $audience = LandingSectionType::Audience->normalise(['heading' => '  Who  ', 'text' => "One\r\n\r\n\r\nTwo", 'items' => "Conveyancers\n\n  Candidate attorneys  \n"]);
        self::assertSame(['heading' => 'Who', 'text' => "One\n\nTwo", 'items' => ['Conveyancers', 'Candidate attorneys']], $audience);

        $faq = LandingSectionType::Faq->normalise(['items' => [1 => ['question' => 'How long?', 'answer' => 'A year.'], 2 => ['question' => '', 'answer' => '']]]);
        self::assertSame([['question' => 'How long?', 'answer' => 'A year.']], $faq['items'], 'An empty row is dropped.');

        $this->refuses(static fn() => LandingSectionType::Faq->normalise(['items' => [['question' => 'Half a row', 'answer' => '']]]), 'needs its answer');
        $this->refuses(static fn() => LandingSectionType::Benefits->normalise(['items' => [['title' => '', 'text' => 'No title']]]), 'needs its title');
        $this->refuses(static fn() => LandingSectionType::Audience->normalise(['items' => implode("\n", array_fill(0, 13, 'Someone'))]), 'at most 12');
        $this->refuses(static fn() => LandingSectionType::Hero->normalise(['headline' => str_repeat('x', 121)]), 'longer than 120');
        $this->refuses(static fn() => LandingSectionType::Reviews->normalise(['limit' => '13']), 'between 1 and 12');
        $this->refuses(static fn() => LandingSectionType::Reviews->normalise(['limit' => '3', 'when_empty' => 'maybe']), 'no reviews');
        $this->refuses(static fn() => LandingSectionType::Hero->normalise(['secondary' => 'https://example.com/buy']), 'second button');
        $this->refuses(static fn() => LandingSectionType::Hero->normalise(['image' => 'https://example.com/a.png']), 'hero picture');
        $this->refuses(static fn() => LandingSectionType::fromName('custom_html'), 'kind of section');
    }

    public function testCopyIsPlainTextThatStaysTextWhateverIsTyped(): void
    {
        $hero = LandingSectionType::Hero->normalise(['headline' => "<script>alert(1)</script>\x07 Title", 'text' => '<b onclick="x()">Bold</b>']);
        self::assertSame('<script>alert(1)</script> Title', $hero['headline'], 'Stored as typed, without control characters; the page escapes it.');
        self::assertSame([['<b onclick="x()">Bold</b>']], LandingCopy::paragraphs($hero['text']));
        $this->refuses(static fn() => LandingCopy::line("\xC3\x28", 10, 'The heading'), 'could not be read');
        self::assertSame([['First line', 'second line'], ['Next paragraph']], LandingCopy::paragraphs("First line\nsecond line\n\n\nNext paragraph"));
        self::assertSame('A lesson about…', LandingCopy::excerpt('<p>A lesson <strong>about</strong> deeds and transfers</p>', 20), 'Cut at a word, never inside one.');
    }

    public function testTheHeroRemembersAPictureOnlyWhenOneIsChosenAndAListMustHaveContentToBePublished(): void
    {
        self::assertNull(LandingSectionType::Hero->normalise(['image' => 'cover', 'image_resource_id' => '7'])['image_resource_id']);
        self::assertSame(7, LandingSectionType::Hero->normalise(['image' => 'resource', 'image_resource_id' => '7'])['image_resource_id']);
        self::assertSame(['The hero has no picture chosen.'], LandingSectionType::Hero->missing(LandingSectionType::Hero->normalise(['image' => 'resource'])));
        foreach ([LandingSectionType::Audience, LandingSectionType::Outcomes, LandingSectionType::Benefits, LandingSectionType::Faq] as $type) {
            self::assertCount(1, $type->missing($type->defaults()), $type->value . ' with nothing in it cannot be published.');
        }
        foreach ([LandingSectionType::Contents, LandingSectionType::Reviews, LandingSectionType::Pricing, LandingSectionType::Cta, LandingSectionType::Instructor] as $type) {
            self::assertSame([], $type->missing($type->defaults()), $type->value . ' shows live course data, so it is complete as it is.');
        }
        self::assertSame('3 questions', LandingSectionType::Faq->summary(['items' => [[], [], []]]));
        self::assertSame('Up to 1 approved review', LandingSectionType::Reviews->summary(['limit' => 1]));
    }

    public function testACampaignIsTheFiveUtmParametersCleanedAndNothingElse(): void
    {
        $campaign = CampaignAttribution::from([
            'utm_source' => '  newsletter ', 'utm_medium' => "email\x00", 'utm_campaign' => str_repeat('c', 80),
            'utm_content' => '', 'utm_term' => ['array'], 'gclid' => 'abc', 'fbclid' => 'def', 'ref' => 'x',
        ]);
        self::assertSame(['utm_source' => 'newsletter', 'utm_medium' => 'email', 'utm_campaign' => str_repeat('c', 64)], $campaign);
        foreach (CampaignAttribution::PARAMETERS as $name) {
            self::assertSame('string', AnalyticsEventType::LandingPageView->metadataSchema()[$name]);
            self::assertSame('string', AnalyticsEventType::LandingPageCtaClicked->metadataSchema()[$name]);
        }
        self::assertSame(['course_id'], AnalyticsEventType::LandingPageView->requiredReferences());
        self::assertFalse(AnalyticsEventType::LandingPageCtaClicked->requiresIdempotencyKey(), 'Every accepted press is recorded.');
    }

    public function testTheOutlineQueryReadsTitlesAndKindsAndNothingInsideTheCourse(): void
    {
        $source = (string) file_get_contents(self::ROOT . '/src/Course/Landing/LandingPageRepository.php');
        $outline = substr($source, (int) strpos($source, 'public function outline('), 2200);
        foreach (['content_source', 'type_config', 'resource_id', 'instructions_html', 'result_pass_html', 'assessment_questions', 'assessment_options', 'course_item_assessments', 'resources'] as $protected) {
            self::assertStringNotContainsString($protected, $outline, 'The landing page outline never reads ' . $protected . '.');
        }
    }

    public function testTheTemplatesDrawCopyAsTextAndShareThePurchaseBoxWithTheCoursePage(): void
    {
        $views = self::ROOT . '/resources/views';
        $landing = '';
        foreach (['pages/landing-page.html.twig', 'partials/landing/hero.html.twig', 'partials/landing/section.html.twig', 'partials/landing/paragraphs.html.twig'] as $file) {
            $landing .= (string) file_get_contents($views . '/' . $file);
        }
        self::assertSame(1, substr_count($landing, '|raw'), 'Only the course’s own generated cover artwork is drawn raw.');
        self::assertStringContainsString('landing.course.cover_svg|raw', $landing);
        self::assertStringNotContainsString('include \'@platform/partials/landing/section-\' ~', $landing, 'No template path is built from data.');
        self::assertStringContainsString("include '@platform/partials/course-purchase.html.twig'", $landing);
        self::assertStringContainsString("include '@platform/partials/course-purchase.html.twig'", (string) file_get_contents($views . '/pages/course-detail.html.twig'), 'The course page draws the same purchase box.');
        $purchase = (string) file_get_contents($views . '/partials/course-purchase.html.twig');
        self::assertStringContainsString('action="/cart/add"', $purchase, 'Purchases go through the platform’s cart, never a link written into the page.');
        foreach (['href="{{ section.', 'href="{{ item.'] as $authored) {
            self::assertStringNotContainsString($authored, $landing, 'Section copy never becomes a link.');
        }
    }

    public function testEveryThemeHeadDrawsTheCoreHeadMetadata(): void
    {
        foreach (glob(self::ROOT . '/themes/*/base.html.twig') ?: [] as $base) {
            $source = (string) file_get_contents($base);
            self::assertStringContainsString("{% include '@platform/partials/head-meta.html.twig' %}", $source, basename(dirname($base)));
            self::assertStringNotContainsString('<meta name="description"', $source, basename(dirname($base)) . ' leaves the description to core.');
        }
    }

    private function refuses(callable $call, string $message): void
    {
        try {
            $call();
            self::fail('Expected a refusal mentioning ' . $message);
        } catch (InvalidArgumentException $refused) {
            self::assertStringContainsString($message, $refused->getMessage());
        }
    }
}
