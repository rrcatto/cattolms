    public function testAdministrationThemeObjectAlwaysHasStablePluralAndSingularSectionKeys(): void
    {
        $f3 = Base::instance();
        $oldAdmin = $f3->get('admin');
        $renderer = (new ReflectionClass(ThemeRenderer::class))->newInstanceWithoutConstructor();
        (new ReflectionProperty(ThemeRenderer::class, 'f3'))->setValue($renderer, $f3);
        $method = new ReflectionMethod(ThemeRenderer::class, 'setPageFamilyObjects');

        try {
            $method->invoke($renderer, 'admin', [
                'admin_sections' => [['key' => 'dashboard']],
            ]);
            $admin = $f3->get('admin');
            self::assertIsArray($admin);
            self::assertArrayHasKey('sections', $admin);
            self::assertArrayHasKey('section', $admin);
            self::assertSame([['key' => 'dashboard']], $admin['sections']);
            self::assertSame([], $admin['section']);

            $method->invoke($renderer, 'admin', [
                'admin_section' => ['key' => 'themes'],
            ]);
            $admin = $f3->get('admin');
            self::assertIsArray($admin);
            self::assertArrayHasKey('sections', $admin);
            self::assertArrayHasKey('section', $admin);
            self::assertSame([], $admin['sections']);
            self::assertSame(['key' => 'themes'], $admin['section']);

            $method->invoke($renderer, 'admin', []);
            $admin = $f3->get('admin');
            self::assertIsArray($admin);
            self::assertSame([], $admin['sections']);
            self::assertSame([], $admin['section']);
        } finally {
            if ($oldAdmin === null) {
                $f3->clear('admin');
            } else {
                $f3->set('admin', $oldAdmin);
            }

            // Base::instance() installs F3's process-level handlers. PHPUnit 12
            // correctly marks a test risky if those handlers leak beyond the
            // test method, so restore the handlers that PHPUnit had installed.
            restore_error_handler();
            restore_exception_handler();
        }
    }

