A social profile link is an anchor other people click, so what goes in the field matters.

The owner's list, 2026/09/10, is twelve platforms. A field that accepted any URL would eventually
hold somebody else's, rendered from this platform's pages under this platform's name - so an address
must be https and must be on the platform it claims to be on.

The near-miss host is the case worth writing down: "notlinkedin.com" ends with "linkedin.com" as a
string and is a different company. Matching has to be the host itself or a subdomain of it, and this
asserts both halves.

Architectural boundary: unit. It exercises a value object and touches nothing else.

Changelog:
2026/09/10 02:25 SAST
- Created with the Profile submenu's social media page.
