    public function testGuidanceNeverBlocksASave(): void
    {
        $short = ['kind' => 'intro', 'slides' => [['layout' => 'title', 'title' => 'Hi', 'heading' => 'Hello']]];
        $deck = SlideDeck::validate($short);
        $warnings = SlideDeck::warnings($deck);
        self::assertContains('A module opening usually has 5 to 9 slides. This one has 1.', $warnings);
        self::assertContains('A module opening has at least one quick question.', $warnings);
        self::assertSame(1, SlideDeck::estimatedMinutes($deck));
        self::assertSame(['intro', 'review', 'overview', 'trailer'], array_keys(SlideLayouts::KINDS));
        self::assertCount(12, SlideLayouts::LAYOUTS, 'Twelve layouts, as the engine specification has.');
    }

    public function testTheMarkupIsTheEnginesContractWithEscapedTextLinksAndNarration(): void
    {
        $deck = SlideDeck::validate(self::deck() + ['theme' => 'dark']);
        $first = $deck['slides'][0]['id'];
        $html = (new DeckRenderer())->render($deck, 'gdn-101-m1-presentation', 'What you will learn', ['continue' => '/learn/gdn/item/7/content'], [$first => '/narrations/abc']);
        self::assertStringContainsString('<div class="cw-deck" tabindex="0" data-cw-key="gdn-101-m1-presentation" data-cw-kind="intro" data-cw-title="What you will learn" data-cw-version="1" data-cw-theme="dark"', $html);
        self::assertStringContainsString('data-cw-host-links="{&quot;continue&quot;:&quot;/learn/gdn/item/7/content&quot;}"', $html);
        self::assertSame(4, substr_count($html, '<section class="cw-slide"'));
        self::assertStringContainsString('data-cw-audio="/narrations/abc"', $html);
        self::assertStringContainsString('<aside class="cw-notes">We start underground.</aside>', $html);
        self::assertStringContainsString('<li class="cw-step">Test your soil</li>', $html);
        self::assertStringContainsString('<ol class="cw-options" data-cw-answer="1">', $html);
        self::assertStringContainsString('<details class="cw-explain"><summary>Show the answer</summary>', $html);
        self::assertStringContainsString('<a class="cw-action" data-cw-action="continue" href="/learn/gdn/item/7/content">Watch the video</a>', $html);
        $escaped = (new DeckRenderer())->render(['kind' => 'intro', 'slides' => [['id' => 'abcdef12', 'layout' => 'statement', 'title' => 'Q', 'text' => 'Tom & Jerry "quoted"']]], 'k', 'T');
        self::assertStringContainsString('Tom &amp; Jerry &quot;quoted&quot;', $escaped);
    }

    public function testFlashCardsAreAListThatWorksWithoutJavaScript(): void
    {
        $cards = FlashCards::validate([['front' => 'What is loam?', 'back' => 'A balanced mix.', 'hint' => 'Gardeners want it.'], ['front' => '', 'back' => '', 'hint' => '']]);
        self::assertCount(1, $cards, 'An empty card row is dropped.');
        $html = FlashCards::render($cards, 'gdn-101-m1-flashcards');
        self::assertStringContainsString('data-cl-flashcards="gdn-101-m1-flashcards"', $html);
        self::assertStringContainsString('<details class="cl-flashcard-back"><summary>Show the answer</summary><p>A balanced mix.</p></details>', $html);
        self::assertSame(['A module usually has 10 to 20 flash cards. This set has 1.'], FlashCards::warnings($cards));
        self::assertSame(['front' => 'Pasted', 'back' => 'Answer', 'hint' => 'Nudge'], CourseItemService::cardsInput(['cards_paste' => "Pasted | Answer | Nudge\n\n"])[0]);
        $this->expectExceptionMessage('the hint gives the answer away');
        FlashCards::validate([['front' => 'Q?', 'back' => 'Same', 'hint' => 'same']]);
    }

    public function testTheEditorsSlideActionsChangeOnlyTheDraft(): void
    {
        $input = ['deck_kind' => 'intro', 'deck_theme' => 'light', 'slides' => self::deck()['slides']];
        $added = CourseItemService::deckDraft($input + ['slide_action' => 'add:0', 'new_slide_layout' => [0 => 'number']]);
        self::assertSame(['title', 'number', 'points', 'check', 'next'], array_column($added['slides'], 'layout'));
        $end = CourseItemService::deckDraft($input + ['slide_action' => 'add:end', 'new_slide_layout' => ['end' => 'case']]);
        self::assertSame('case', end($end['slides'])['layout']);
        $moved = CourseItemService::deckDraft($input + ['slide_action' => 'down:0']);
        self::assertSame(['points', 'title', 'check', 'next'], array_column($moved['slides'], 'layout'));
        $removed = CourseItemService::deckDraft($input + ['slide_action' => 'remove:2']);
        self::assertSame(['title', 'points', 'next'], array_column($removed['slides'], 'layout'));
    }
