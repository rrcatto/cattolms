    public function testADeckIsShapedIntoItsLayoutsFieldsWithAnIdForEverySlide(): void
    {
        $deck = SlideDeck::validate(self::deck() + ['theme' => 'light']);
        self::assertSame('intro', $deck['kind']);
        self::assertCount(4, $deck['slides']);
        self::assertSame(['Test your soil', 'Make compost', 'Fill a container'], $deck['slides'][1]['points'], 'Lines are split and empty ones dropped.');
        self::assertTrue($deck['slides'][1]['build'], 'Points build one at a time unless told not to.');
        self::assertSame(1, $deck['slides'][2]['answer']);
        foreach ($deck['slides'] as $slide) { self::assertMatchesRegularExpression('/^[a-z0-9]{6,32}$/', $slide['id']); }
        $again = SlideDeck::validate($deck);
        self::assertSame(array_column($deck['slides'], 'id'), array_column($again['slides'], 'id'), 'A slide keeps its id, so its narration stays with it.');
        $shaped = SlideDeck::normaliseSlide(['layout' => 'number', 'title' => 'x', 'figure' => '5%', 'label' => 'y', 'heading' => 'not a number field']);
        self::assertArrayNotHasKey('heading', $shaped, 'Fields another layout has are dropped.');
    }

