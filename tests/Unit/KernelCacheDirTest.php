declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Kernel;
use PHPUnit\Framework\TestCase;

final class KernelCacheDirTest extends TestCase
{
    public function testTheCacheFolderIsTheReleasesOwn(): void
    {
        $kernel = new Kernel('production', false, '/srv/site');
        $key = Kernel::releaseCacheKey($kernel->getProjectDir());
        self::assertSame('/srv/site/storage/cache/symfony/' . $key . '/production', $kernel->getCacheDir());
        self::assertSame($kernel->getCacheDir(), $kernel->getBuildDir());
        self::assertSame('/srv/site/storage/cache/symfony/' . $key . '/development', (new Kernel('development', true, '/srv/site'))->getCacheDir(), 'Each environment in its own folder within it.');
    }

    public function testEachReleaseHasItsOwnKey(): void
    {
        $now = Kernel::releaseCacheKey('/home/site/cattolms/releases/0.9.10');
        $before = Kernel::releaseCacheKey('/home/site/cattolms/releases/0.9.9');
        self::assertMatchesRegularExpression('/^0\.9\.10-[0-9a-f]{8}$/', $now, 'The version, as the installers delete and prune it ("<version>-*").');
        self::assertNotSame($now, $before);
        self::assertSame($now, Kernel::releaseCacheKey('/home/site/cattolms/releases/0.9.10'), 'The same release always has the same folder.');
        self::assertNotSame(Kernel::releaseCacheKey('/usr/local/lib/php/cattolms/0.9.10'), $now, 'A folder of the same name elsewhere is another release.');
        self::assertMatchesRegularExpression('/^release-[0-9a-f]{8}$/', Kernel::releaseCacheKey('/srv/???'), 'A name of nothing but other characters.');
        self::assertMatchesRegularExpression('/^my-checkout-[0-9a-f]{8}$/', Kernel::releaseCacheKey('/srv/my checkout'));
    }
}
