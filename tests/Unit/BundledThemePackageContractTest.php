declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\View\ThemePackageValidator;
use PHPUnit\Framework\TestCase;

final class BundledThemePackageContractTest extends TestCase
{
    public function testEveryBundledThemePackagePassesTheRealValidator(): void
    {
        $packages = glob(__DIR__ . '/../../extras/themes/*.zip') ?: [];
        self::assertCount(1, $packages, 'Only the default Factory Reset theme package may be bundled in extras/themes.');
        self::assertSame('factory-reset-v1.0.1.zip', basename($packages[0]));
        $validator = new ThemePackageValidator();
        foreach ($packages as $package) {
            $result = $validator->inspect($package);
            self::assertSame('catto-learning-theme', $result['manifest']['format'] ?? null, basename($package));
        }
    }

    public function testMissingPlatformScriptsIsRejectedExplicitly(): void
    {
        if (!class_exists(\ZipArchive::class)) self::markTestSkipped('The PHP zip extension is not installed.');
        $path = tempnam(sys_get_temp_dir(), 'theme-no-platform-scripts-');
        self::assertNotFalse($path);
        @unlink($path);
        $path .= '.zip';
        $zip = new \ZipArchive();
        self::assertTrue($zip->open($path, \ZipArchive::CREATE | \ZipArchive::OVERWRITE) === true);
        $manifest = [
            'format'=>'catto-learning-theme','schema_version'=>'3.0','template_api'=>'1.0',
            'theme'=>['name'=>'Broken Scripts','slug'=>'broken-scripts','version'=>'1.0.0','author'=>'QA','description'=>'Broken base contract','created_at'=>'2026-08-17T04:00:00+02:00'],
            'parent'=>null,'styles'=>[],'scripts'=>[],'external'=>['styles'=>[],'scripts'=>[]],
        ];
        $zip->addFromString('theme.json', json_encode($manifest, JSON_THROW_ON_ERROR));
        $zip->addFromString('base.html', '<html><head><repeat group="{{ @platform.styles }}" value="{{ @url }}"></repeat></head><body>{{ @content | raw }}</body></html>');
        $zip->addFromString('public/css/theme.css', 'body{margin:0}');
        $zip->close();
        try {
            $this->expectException(\RuntimeException::class);
            $this->expectExceptionMessage('@platform.scripts');
            (new ThemePackageValidator())->inspect($path);
        } finally {
            @unlink($path);
        }
    }
}
