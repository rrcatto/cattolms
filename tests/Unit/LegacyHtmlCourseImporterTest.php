    public function testDomParsingCopyBlanksScriptAndStyleBodiesWithoutMovingLines(): void
    {
        $source = "<!doctype html>\n<html><head><style>\n.demo::after{content:'</span> &';}\n</style></head><body>\n"
            . "<script>\nconst card = \"<b>Bold</b><code>2>&1</code></li>\";\n</script>\n"
            . "<section class=\"module\" id=\"mod-m1\">Content</section>\n</body></html>";

        $importer = new LegacyHtmlCourseImporter();
        $method = new \ReflectionMethod($importer, 'htmlForDomParsing');
        $prepared = $method->invoke($importer, $source);

        self::assertIsString($prepared);
        self::assertSame(substr_count($source, "\n"), substr_count($prepared, "\n"));
        self::assertStringContainsString('<script>', $prepared);
        self::assertStringContainsString('</script>', $prepared);
        self::assertStringContainsString('<style>', $prepared);
        self::assertStringContainsString('</style>', $prepared);
        self::assertStringNotContainsString('<b>Bold</b>', $prepared);
        self::assertStringNotContainsString('2>&1', $prepared);
        self::assertStringNotContainsString('</span> &', $prepared);
        self::assertStringContainsString('<section class="module" id="mod-m1">Content</section>', $prepared);
    }

