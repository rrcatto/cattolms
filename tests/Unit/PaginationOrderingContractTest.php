Description:
Asserts that every ordering a paginated list pages on is a total order, and that no paginated read
orders by anything else.

Why this is a source contract rather than a database test.

The property is "PostgreSQL must never have a free choice about which of two rows comes first". A
test that pages a fixture and compares the sequence cannot establish that: given a tie, PostgreSQL
is *permitted* to return either order, and on a small dataset with one plan it will usually pick
the same one every time. Removing the tiebreaker from Administration People and Course Requests was
tried against exactly such a test and it passed - the query was free to lose rows and simply did
not happen to. A check that cannot fail when the thing it describes is broken is worse than no
check, because it is read as evidence.

What can be established, deterministically, is that the ordering *expression* ends in something
unique for its table. That is the definition of a total order over those rows, it is true or false
by inspection, and it is what these tests assert.

`PaginationDeterminismIntegrationTest` is the companion: it proves the pages of a real dataset
partition it and that the deferred join returns its key query's rows in its key query's order.
Between them, one covers the shape and the other the behaviour.

Changelog:
2026/09/04 21:00 SAST
- Created for the v0.6 Pagination 2.0 release.
*/

