    /**
     * The learner-scoped lists build their ORDER BY inline rather than from a constant, so they are
     * asserted on the clause itself.
     */
    public function testLearnerScopedListsCarryTheirOwnTiebreaker(): void
    {
        $source = self::read('src/Infrastructure/Persistence/AdministrationRepository.php');

        self::assertStringContainsString(
            "ORDER BY cf.created_at DESC, cf.course_id DESC",
            $source,
            'Favourites are keyed by learner and course, so the course is the tiebreaker.'
        );
        self::assertStringContainsString(
            "ORDER BY cr.requested_at DESC, cr.id DESC",
            $source,
            "A learner's own requests must not order by their timestamp alone."
        );
    }

    /**
     * Every paginated ordering is indexable.
     *
     * Scoped to the ordering constants on purpose. They are exactly the expressions a paginated
     * read sorts by, and they are the ones an index in the v0.6 migration mirrors; the same rule
     * applied to a whole file would also catch the bounded lists that are never paged and have
     * nothing to gain from an index.
     *
     * A CASE and a `concat_ws()` are the two specific shapes this release removed: the first cannot
     * use an index, and the second cannot even be indexed, because it is only STABLE.
     */
    public function testEveryPaginatedOrderingIsIndexable(): void
    {
        $constants = [];
        foreach ([
            'src/Infrastructure/Persistence/AdministrationRepository.php',
            'src/Course/CourseRepository.php',
        ] as $file) {
            preg_match_all(
                "/private const ([A-Z_]*ORDER) = '([^']*)';/",
                self::read($file),
                $matches,
                PREG_SET_ORDER
            );
            foreach ($matches as $match) {
                $constants[$file . '::' . $match[1]] = $match[2];
            }
        }

        self::assertGreaterThanOrEqual(
            12,
            count($constants),
            'Every paginated list must name its ordering, or this test silently stops covering it.'
        );

        foreach ($constants as $name => $expression) {
            self::assertDoesNotMatchRegularExpression(
                '/\bCASE\b/i',
                $expression,
                $name . ': a CASE cannot use an index; give it a generated sort key instead.'
            );
            self::assertStringNotContainsStringIgnoringCase(
                'concat_ws',
                $expression,
                $name . ': concat_ws() is only STABLE, so an ordering built from it can never be indexed.'
            );
        }
    }

    /**
     * The deferred-join composer states the ordering once and uses it in both halves.
     *
     * If the detail query were given an ORDER BY of its own it would be free to drift from the key
     * query's, and every page would hold the right rows in the wrong sequence.
     */
    public function testDeferredJoinUsesOneOrderingForBothQueries(): void
    {
        $source = self::read('src/Infrastructure/Persistence/PageQuery.php');

        self::assertStringContainsString(
            'public static function deferred(string $keys, string $detail, string $order, int $limit, int $offset): string',
            $source
        );
        // Once appended to the key query, once to the detail query, and nowhere else: a detail
        // query given an ORDER BY of its own would be free to drift from the keys that selected it.
        self::assertSame(
            2,
            substr_count($source, 'ORDER BY " . $order'),
            'The order expression must be applied exactly twice: to the key query and to the detail query.'
        );
    }

    /**
     * The one LIMIT/OFFSET clamp. Two copies of a bound is two places to raise it, and the page a
     * repository fetches must not be able to differ from the page the composer bounded.
     */
    public function testThereIsOneLimitOffsetClamp(): void
    {
        foreach ([
            'src/Infrastructure/Persistence/AdministrationRepository.php',
            'src/Course/CourseRepository.php',
        ] as $file) {
            self::assertStringNotContainsString(
                "' LIMIT ' . \$limit . ' OFFSET '",
                self::read($file),
                $file . ' must clamp through PageQuery::limitOffset() rather than interpolating its own.'
            );
        }

        self::assertStringContainsString(
            "return ' LIMIT ' . \$limit . ' OFFSET ' . max(0, \$offset);",
            self::read('src/Infrastructure/Persistence/PageQuery.php')
        );
    }
