<?php

/*
Generated by: Claude Code CLI

Date time: 2026/08/29 15:18 SAST

Version: 0.5.8.3

Description:
Contract tests for stripping HTML comments out of finished responses.

Every template carries a file metadata header, and several carry notes explaining why a control is
built the way it is. An HTML comment is served verbatim, so without stripping all of that prose is
readable in view source on every page. These tests assert it is gone.

The second half matters as much as the first. The stripper must not touch script, style, pre or
textarea content: imported course HTML reaches the page through a raw template token and can
legitimately contain a comment delimiter inside a script string, and a naive comment pattern would
cut such a script in half - turning a cosmetic concern into a broken course player. The cases below
therefore include exactly that shape.

Changelog:
2026/08/29 15:18 SAST
- Created when template metadata headers were stripped from rendered output.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\View\ThemeRenderer;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use ReflectionMethod;

final class RenderedCommentStrippingTest extends TestCase
{
    private static function strip(string $html): string
    {
        $method = new ReflectionMethod(ThemeRenderer::class, 'stripHtmlComments');

        return (string) $method->invoke(null, $html);
    }

    /**
     * The header block every template carries must not survive into the response.
     */
    public function testTemplateMetadataHeadersDoNotReachTheBrowser(): void
    {
        $html = "<!--\nGenerated by: Claude Code CLI\nDate time: 2026/08/29 15:18 SAST\n"
            . "Version: 0.5.8.3\nDescription:\n  Something internal.\nChangelog:\n"
            . "  2026/08/29 15:18 SAST\n  - Created.\n-->\n<div class=\"page\">Body</div>";

        $stripped = self::strip($html);

        self::assertStringNotContainsString('Generated by:', $stripped);
        self::assertStringNotContainsString('Changelog:', $stripped);
        self::assertStringNotContainsString('Something internal', $stripped);
        self::assertStringContainsString('<div class="page">Body</div>', $stripped);
    }

    /**
     * Developer notes written mid-template are internal reasoning too.
     */
    public function testExplanatoryCommentsAreAlsoRemoved(): void
    {
        $html = '<form><!-- Changing the page size returns to page 1. --><input name="page"></form>';

        $stripped = self::strip($html);

        self::assertStringNotContainsString('returns to page 1', $stripped);
        self::assertStringContainsString('<input name="page">', $stripped);
    }

    /**
     * The case that makes a naive pattern dangerous.
     *
     * Imported course HTML is injected raw. A script holding a comment delimiter inside a string,
     * anywhere after a real comment, would be cut in half by a plain non-greedy comment pattern.
     */
    public function testScriptContentSurvivesEvenWhenItHoldsCommentDelimiters(): void
    {
        $html = '<!-- header --><script>var a = "-->"; var b = 1 < 2;</script><p>after</p>';

        $stripped = self::strip($html);

        self::assertStringNotContainsString('header', $stripped);
        self::assertStringContainsString('var a = "-->";', $stripped);
        self::assertStringContainsString('var b = 1 < 2;', $stripped);
        self::assertStringContainsString('<p>after</p>', $stripped);
    }

    /**
     * Whitespace-significant and style content is not ours to rewrite either.
     *
     * @param string $html
     * @param string $expected
     */
    #[DataProvider('preservedBlocks')]
    public function testWhitespaceSignificantAndStyleBlocksArePreserved(string $html, string $expected): void
    {
        self::assertStringContainsString($expected, self::strip($html));
    }

    /** @return array<string,array{string,string}> */
    public static function preservedBlocks(): array
    {
        return [
            'pre' => ['<!-- x --><pre>line one
line two</pre>', "<pre>line one\nline two</pre>"],
            'textarea' => ['<!-- x --><textarea>  spaced  </textarea>', '<textarea>  spaced  </textarea>'],
            'style' => ['<!-- x --><style>.a{content:"-->"}</style>', '.a{content:"-->"}'],
        ];
    }

    /**
     * Stripping comments must not be allowed to become minification by accident: a rendering
     * difference should never be attributable to it.
     */
    public function testNothingButCommentsIsRemoved(): void
    {
        $html = "<div>\n\t<span>a</span> <span>b</span>\n</div>";

        self::assertSame($html, self::strip($html));
    }

    /**
     * A page with no comments at all must come back byte-identical.
     */
    public function testOutputWithoutCommentsIsUnchanged(): void
    {
        $html = '<!doctype html><html><body><p>Hello</p></body></html>';

        self::assertSame($html, self::strip($html));
    }
}
