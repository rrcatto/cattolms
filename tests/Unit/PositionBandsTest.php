declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Support\PositionBands;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class PositionBandsTest extends TestCase
{
    private const BANDS = ['FIN' => 10000, 'BUS' => 20000, 'SEC' => 80000];

    public function testABandRunsToTheNextStartAndTheLastRunsOn(): void
    {
        self::assertSame([10000, 20000], PositionBands::band(self::BANDS, 'FIN'));
        self::assertSame([80000, null], PositionBands::band(self::BANDS, 'SEC'));
        self::assertNull(PositionBands::band(self::BANDS, 'LAW'));
        self::assertSame('10000 to 19999, room for 100', PositionBands::words(self::BANDS, 'FIN'));
        self::assertSame('from 80000, without end', PositionBands::words(self::BANDS, 'SEC'));
        self::assertSame('FIN', PositionBands::prefixOf('fin-books'));
        self::assertSame('GDN', PositionBands::prefixOf('GDN'), 'A code without a hyphen is its own prefix.');
    }

    public function testSomethingNewTakesTheNextNumberInItsBand(): void
    {
        self::assertSame(10000, PositionBands::next(self::BANDS, 'FIN-101', [20000]));
        self::assertSame(10300, PositionBands::next(self::BANDS, 'FIN-104', [10000, 10100, 10200, 20000]));
        self::assertNull(PositionBands::next(self::BANDS, 'LAW-101', []), 'No band, no number.');
    }

    public function testAMoveTakesTheMidpointOrOneHundredAfterTheLast(): void
    {
        // Moved to index 1, between 10000 and 10100.
        self::assertSame([1 => 10050], PositionBands::place([10000, 999, 10100], 1));
        self::assertSame([0 => 5000], PositionBands::place([999, 10000, 10100], 0), 'First: half the next one\'s number.');
        self::assertSame([2 => 10200], PositionBands::place([10000, 10100, 999], 2), 'Last of the numbered: 100 after.');
    }

    /** With no whole number between its new neighbours, it and the crowded run below it are spread up to the next roomy number, never across a band. */
    public function testACrowdedMoveSpreadsItsNeighboursAndKeepsTheBands(): void
    {
        $numbers = [10000, 10001, null, 10002, 10003, 20000];
        $changes = PositionBands::place($numbers, 2);
        $after = $numbers;
        foreach ($changes as $index => $number) $after[$index] = $number;
        $sorted = $after;
        sort($sorted);
        self::assertSame($sorted, $after, 'Everything stays in order.');
        self::assertSame(count($after), count(array_unique($after)));
        self::assertSame(20000, $after[5], 'The next band\'s first is not touched.');
        self::assertSame([10000, 10001], array_slice($after, 0, 2), 'The numbers above it stay.');
        foreach (array_slice($after, 0, 5) as $number) self::assertTrue($number >= 10000 && $number < 20000, 'Nothing leaves its band: ' . $number);
        self::assertSame([2 => 12500, 3 => 14999, 4 => 17498], $changes, 'Spread evenly up to the next number with room.');
    }

    public function testAMoveAmongTheUnnumberedNumbersOnFromTheLast(): void
    {
        self::assertSame([1 => 10100, 2 => 10200], PositionBands::place([10000, null, 999, null], 2));
    }

    public function testRenumberPutsEachThingBackInItsBandInItsOrder(): void
    {
        $items = [
            ['key' => 'a', 'code' => 'FIN-101', 'position' => 100],
            ['key' => 'b', 'code' => 'SEC-101', 'position' => 150],
            ['key' => 'c', 'code' => 'FIN-102', 'position' => 200],
            ['key' => 'd', 'code' => 'LAW-101', 'position' => 300],
            ['key' => 'e', 'code' => 'FIN-103', 'position' => null],
        ];
        $plan = PositionBands::renumber(self::BANDS, $items);
        self::assertSame(['a' => 10000, 'c' => 10100, 'e' => 10200, 'b' => 80000], $plan['changes'], 'Each band from its start, 100 apart, in the order they were.');
        self::assertSame(['d'], $plan['unbanded'], 'No band: it keeps its number.');
        self::assertSame([], $plan['crowded']);
        $again = PositionBands::renumber(self::BANDS, [['key' => 'a', 'code' => 'FIN-101', 'position' => 10000], ['key' => 'c', 'code' => 'FIN-102', 'position' => 10100]]);
        self::assertSame([], $again['changes'], 'Renumbering again changes nothing.');
    }

    public function testABandFullerThanItsWidthIsNumberedCloser(): void
    {
        $items = [];
        for ($i = 0; $i < 4; $i++) $items[] = ['key' => $i, 'code' => 'GDN-' . $i, 'position' => null];
        $plan = PositionBands::renumber(['GDN' => 100, 'ART' => 400], $items);
        self::assertSame([0 => 100, 1 => 175, 2 => 250, 3 => 325], $plan['changes'], 'Four in a band of 300: 75 apart, all inside it.');
        $crowded = PositionBands::renumber(['GDN' => 100, 'ART' => 102], $items);
        self::assertSame(['GDN'], $crowded['crowded']);
        self::assertSame([], $crowded['changes'], 'Too narrow for a number each: left as it was.');
    }

    public function testATypedPositionIsAWholeNumberFromOne(): void
    {
        self::assertNull(PositionBands::typed('  ', 'x'));
        self::assertSame(10100, PositionBands::typed('10100', 'x'));
        foreach (['0', '-5', '1.5', 'ten', '3000000000'] as $wrong) {
            try {
                PositionBands::typed($wrong, 'Type a whole number.');
                self::fail('Accepted ' . $wrong);
            } catch (InvalidArgumentException $refused) {
                self::assertSame('Type a whole number.', $refused->getMessage());
            }
        }
    }

    public function testRenumberSaysWhatItDid(): void
    {
        self::assertSame('3 bundles were renumbered in their bands.', PositionBands::outcome(['changed' => 3, 'unbanded' => [], 'crowded' => []], 'bundle'));
        self::assertSame('Every course was already numbered in its band. No band for LAW-101, so it keeps its number: give their prefix a band in Settings to number them too.',
            PositionBands::outcome(['changed' => 0, 'unbanded' => ['LAW-101'], 'crowded' => []], 'course'));
    }
}
