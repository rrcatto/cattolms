namespace CattoLearning\Tests\Unit;

use CattoLearning\Course\LegacyHtmlCourseImporter;
use PHPUnit\Framework\TestCase;

final class LegacyHtmlGoldenFileTest extends TestCase
{
    public function testGoldenLegacyCoursePreservesCanonicalImportStructures(): void
    {
        if (!class_exists(\DOMDocument::class)) self::markTestSkipped('The DOM extension is not installed.');
        $htmlPath = __DIR__ . '/../Fixtures/legacy/golden-course.html';
        $expectedPath = __DIR__ . '/../Fixtures/legacy/golden-course.expected.json';
        $expected = json_decode((string) file_get_contents($expectedPath), true, 512, JSON_THROW_ON_ERROR);
        $analysis = (new LegacyHtmlCourseImporter())->analyse((string) file_get_contents($htmlPath), basename($htmlPath));

        foreach ($expected['course'] as $key => $value) {
            self::assertSame($value, $analysis['course'][$key] ?? null, 'Course field mismatch: ' . $key);
        }

        $module = $analysis['modules'][0];
        self::assertSame($expected['module']['module_key'], $module['module_key']);
        self::assertSame($expected['module']['title'], $module['title']);
        self::assertSame($expected['module']['subtitle'], $module['subtitle']);
        self::assertSame($expected['module']['assessment_required'], $module['assessment_required']);
        self::assertSame($expected['module']['question'], $module['assessment']['questions'][0]['question_html']);
        self::assertSame($expected['module']['question_points'], $module['assessment']['questions'][0]['points']);
        foreach ($expected['module']['content_markers'] as $marker) self::assertStringContainsString($marker, $module['content_html']);
        self::assertStringContainsString($expected['module']['learning_outcome_marker'], $module['learning_outcomes_html']);

        $review = $analysis['modules'][1];
        self::assertSame($expected['review']['module_key'], $review['module_key']);
        self::assertSame($expected['review']['title'], $review['title']);
        self::assertSame($expected['review']['subtitle'], $review['subtitle']);
        self::assertSame($expected['review']['is_review'], $review['is_review']);
        self::assertSame($expected['review']['assessment_required'], $review['assessment_required']);
        self::assertSame($expected['review']['question'], $review['assessment']['questions'][0]['question_html']);
        self::assertStringContainsString($expected['review']['content_marker'], $review['content_html']);

        self::assertSame($expected['final']['question'], $analysis['final_assessment']['questions'][0]['question_html']);
        self::assertSame($expected['final']['question_points'], $analysis['final_assessment']['questions'][0]['points']);
    }
