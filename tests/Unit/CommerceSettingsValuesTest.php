        foreach (['C' => true, 'CL' => true, 'CLM' => true, 'cl' => false, 'ABCD' => false, '' => false, 'C1' => false] as $prefix => $valid) {
            self::assertSame($valid, AccountReference::validPrefix((string) $prefix), '"' . $prefix . '"');
        }
    }

    public function testAProcessorFeeIsAPercentagePlusAFixedAmountRoundedHalfUp(): void
    {
        $stitch = ProcessorFee::fromText('2.9%+150');
        self::assertSame(1600, $stitch->on(50000), 'R500.00: 2.9% is R14.50, plus R1.50.');
        self::assertSame(0, $stitch->on(0), 'No fee on nothing.');
        self::assertSame('2.9%+150', $stitch->toText());
        $half = ProcessorFee::fromText('2.5%+0');
        self::assertSame([1, 1, 0], [$half->on(30), $half->on(20), $half->on(19)], '0.75 and 0.5 round up, 0.475 down.');
        self::assertSame('2.9% of the amount plus ' . Money::ofMinorUnits(150, 'ZAR')->format(), $stitch->words());
        self::assertSame(Money::ofMinorUnits(500, 'ZAR')->format(), ProcessorFee::fromText('0%+500')->words());
        self::assertSame('3% of the amount', ProcessorFee::fromText('3%+0')->words());
        self::assertSame('none at present', ProcessorFee::fromText('0%+0')->words());
        foreach (['3%', '60%+0', '2.999%+0', '2.9+150', '-1%+0'] as $wrong) {
            try {
                ProcessorFee::fromText($wrong);
                self::fail('"' . $wrong . '" is not a fee.');
            } catch (InvalidArgumentException) {
                self::addToAssertionCount(1);
            }
        }
    }

    public function testEftRefundFeeTiersPickTheFeeOfTheHighestTierReached(): void
    {
        $tiers = FeeTiers::fromText('1000000:10000, 0:2000');
        self::assertSame('0:2000,1000000:10000', $tiers->toText(), 'Tiers are kept in order.');
        self::assertSame([2000, 2000, 10000, 10000], [$tiers->feeFor(0), $tiers->feeFor(999999), $tiers->feeFor(1000000), $tiers->feeFor(5000000)]);
        $money = static fn(int $minor): string => Money::ofMinorUnits($minor, 'ZAR')->format();
        self::assertSame($money(2000) . ' on a refund under ' . $money(1000000) . ' and ' . $money(10000) . ' on ' . $money(1000000) . ' or more', $tiers->words());
        self::assertSame($money(2000), FeeTiers::fromText('0:2000')->words());
        self::assertSame('none at present', FeeTiers::fromText('0:0')->words());
        foreach (['500:100' => 'The first fee tier starts at R0.', '0:100,0:200' => 'Two fee tiers start at the same amount.', 'abc' => 'Fee tiers are written as amount:fee pairs in cents, such as 0:2000,1000000:10000.'] as $wrong => $message) {
            try {
                FeeTiers::fromText($wrong);
                self::fail('"' . $wrong . '" is refused.');
            } catch (InvalidArgumentException $exception) {
                self::assertSame($message, $exception->getMessage());
            }
        }
    }

    public function testEverySettingHasAWorkingDefaultAndExplainsAWrongValue(): void
    {
        foreach (CommerceSettings::SETTINGS as $key => [$section, $env, $default]) {
            self::assertContains($section, CommerceSettings::SECTIONS, $key);
            self::assertMatchesRegularExpression('/^COMMERCE_[A-Z_]+$/', $env);
            self::assertNull(CommerceSettings::check($key, $default), $key . ' has a valid built-in default.');
            self::assertNotSame($key, CommerceSettings::label($key), $key . ' has a label.');
        }
        self::assertSame('3y', CommerceSettings::SETTINGS['wallet_expiry'][2], 'Wallet credit lasts 3 years by default (CPA section 63).');
        self::assertSame('7d', CommerceSettings::SETTINGS['refund_window'][2]);
        self::assertSame('Use 1 to 3 capital letters, such as CL.', CommerceSettings::check('account_prefix', 'cl'));
        self::assertSame(\CattoLearning\Support\Duration::HOW, CommerceSettings::check('wallet_expiry', '3 years'));
        self::assertNotNull(CommerceSettings::check('stitch_fee', '3%'));
        $example = (string) file_get_contents(dirname(__DIR__, 2) . '/.env.example');
        foreach (CommerceSettings::SETTINGS as [, $env, $default]) {
            self::assertStringContainsString("\n" . $env . '=' . $default . "\n", $example, '.env.example names ' . $env . ' with its default.');
        }
        $this->expectException(InvalidArgumentException::class);
        CommerceSettings::check('cash_out_fee', '0:0');
    }

    public function testTheDashboardTimingSaysWhenACourseStartedAndWhenItsAccessEnds(): void
    {
        $now = new DateTimeImmutable('2026-10-17T12:00:00+02:00');
        $bought = CourseTiming::of(['status' => 'active', 'source_type' => 'paid_order', 'access_started_at' => '2026-10-01T10:00:00+02:00', 'started_at' => '2026-10-01T10:00:00+02:00', 'expires_at' => '2026-10-31T10:00:00+02:00'], $now);
        self::assertSame(['state' => 'started', 'lines' => ['Started on payment, 1 October 2026 10:00, 16 days ago.', 'Access ends 31 October 2026, in 14 days.']], $bought);
        $assigned = CourseTiming::of(['status' => 'assigned', 'source_type' => 'company', 'access_started_at' => null, 'started_at' => null, 'expires_at' => null], $now);
        self::assertSame(['state' => 'not_started', 'lines' => ['Assigned to you. Your access period starts when you press Start course.']], $assigned);
        $today = CourseTiming::of(['status' => 'active', 'source_type' => 'company', 'access_started_at' => '2026-10-17T08:00:00+02:00', 'expires_at' => '2026-10-17T20:00:00+02:00'], $now);
        self::assertSame(['Started 17 October 2026 08:00, today.', 'Access ends 17 October 2026, today.'], $today['lines']);
        $ended = CourseTiming::of(['status' => 'active', 'source_type' => 'paid_order', 'access_started_at' => '2026-09-01T10:00:00+02:00', 'expires_at' => '2026-10-01T10:00:00+02:00'], $now);
        self::assertSame(['state' => 'expired', 'lines' => ['Access ended 1 October 2026.']], $ended);
        $done = CourseTiming::of(['status' => 'completed', 'source_type' => 'bundle', 'access_started_at' => '2026-10-16T10:00:00+02:00', 'expires_at' => '2026-10-18T10:00:00+02:00'], $now);
        self::assertSame(['state' => 'completed', 'lines' => ['Started on payment, 16 October 2026 10:00, 1 day ago.', 'Access ends 18 October 2026, in 1 day.', 'Completed.']], $done);
    }
