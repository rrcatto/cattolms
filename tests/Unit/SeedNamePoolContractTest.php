Version: 0.6

Description:
Holds the v0.6 rule that generated names are real names, are unique, and are the operator's to edit.

Three separate promises are made here and each fails differently:

  1. The lists are large enough that combining them produces far more names than any seed set will
     ever need. This is asserted as a product rather than per list, because that is the number that
     matters and it is what lets uniqueness be a guarantee instead of a hope.
  2. No name carries a discriminator. Making a name unique by appending a number to it is a way of
     avoiding the requirement rather than meeting it, and it is invisible until somebody reads the
     data, at which point every company is called something like "Vaal Training Academy 47".
  3. The lists live in files an operator can edit, not in the code.

The randomness is asserted too. The generator's previous source took the low bits of a linear
congruential generator modulo the pool size, and the low bits of that generator alternate with a
period of two - so exactly half of every even-sized list was unreachable. It produced 17 of 34 first
names and 14 of 28 surnames, and no test noticed, because a test that asks "did I get a name" is
answered perfectly well by half a list.

Changelog:
2026/09/05 11:00 SAST
- Created for the v0.6 seed name pools.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Seed\SeedNameFactory;
use CattoLearning\Seed\SeedNamePools;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

final class SeedNamePoolContractTest extends TestCase
{
    private static function root(): string
    {
        return dirname(__DIR__, 2);
    }

    private static function pools(): SeedNamePools
    {
        // Read the bundled lists directly. The instance copy is whatever the operator has made of
        // it, and this test is about what the platform ships.
        return new SeedNamePools(self::root() . '/storage/seeds', self::root() . '/resources/seeds');
    }

    private static function factory(string $seed = 'contract-test'): SeedNameFactory
    {
        return new SeedNameFactory(self::pools(), $seed);
    }

    /** @return list<array{0:string}> */
    public static function poolNames(): array
    {
        return array_map(static fn(string $name): array => [$name], array_keys(SeedNamePools::POOLS));
    }

    #[DataProvider('poolNames')]
    public function testEveryDeclaredPoolShipsWithTheRelease(string $name): void
    {
        $path = self::root() . '/resources/seeds/' . $name . '.txt';

        self::assertFileExists($path, 'A declared pool with no bundled file leaves a fresh install unable to seed.');
        self::assertGreaterThanOrEqual(
            SeedNamePools::POOLS[$name],
            count(self::pools()->pool($name)),
            $name . ' holds fewer names than its own declared minimum.'
        );
    }

    /**
     * The combination counts, which are the numbers that actually matter.
     *
     * A pool of a thousand is not the goal in itself; a space far larger than anything drawn from
     * it is. Two of the nine word lists are deliberately smaller than the rest - there are about a
     * hundred real trading sectors and forty real course levels, and padding them would mean
     * inventing words that do not read as real.
     */
    public function testTheCombinedSpaceIsFarLargerThanAnySetWillNeed(): void
    {
        $capacity = self::factory()->capacity();

        self::assertGreaterThan(1_000_000_000, $capacity['people'], 'Person names must run to a billion combinations.');
        self::assertGreaterThan(100_000_000, $capacity['companies']);
        self::assertGreaterThan(1_000_000, $capacity['courses']);
    }

    /**
     * Uniqueness at the volume a real set is generated at.
     *
     * Twenty thousand is above the fifteen thousand people a 100,000 seed produces, so the margin
     * is tested rather than the exact case.
     */
    public function testTwentyThousandPeopleAreAllDistinct(): void
    {
        $factory = self::factory();
        $names = [];
        for ($index = 0; $index < 20000; $index++) {
            $names[] = $factory->person()['display'];
        }

        self::assertCount(20000, array_unique($names), 'Every generated person must have their own name.');
    }

    public function testCompaniesAndCourseTitlesAreDistinct(): void
    {
        $factory = self::factory();
        $companies = [];
        $courses = [];
        for ($index = 0; $index < 5000; $index++) {
            $companies[] = $factory->company();
            $courses[] = $factory->courseTitle();
        }

        self::assertCount(5000, array_unique($companies));
        self::assertCount(5000, array_unique($courses));
    }

    /**
     * A name already in the database is never issued again, so a second seed set cannot repeat a
     * person from the first.
     */
    public function testReservedNamesAreNeverIssued(): void
    {
        $first = self::factory('set-one');
        $taken = [];
        for ($index = 0; $index < 500; $index++) {
            $taken[] = $first->person()['display'];
        }

        // A different token, which is the real case: two seed sets never share one. Priming with
        // the same token as well would guarantee a collision on every single draw, and the redraw
        // ceiling would be reached long before five hundred names had been re-found - correctly,
        // because that is a request to generate a set that already exists rather than a new one.
        $second = self::factory('set-two');
        $second->reserve($taken, [], []);

        $issued = [];
        for ($index = 0; $index < 500; $index++) {
            $issued[] = $second->person()['display'];
        }

        self::assertSame([], array_intersect($taken, $issued), 'A second set repeated a name from the first.');
    }

    /**
     * No generated name carries a number, a code or a set suffix. This is the requirement the whole
     * design exists to meet: proper names made unique by there being enough of them, not by having
     * something appended to them.
     */
    public function testNoGeneratedNameCarriesADiscriminator(): void
    {
        $factory = self::factory();
        $names = [];
        for ($index = 0; $index < 400; $index++) {
            $person = $factory->person();
            $names[] = $person['display'];
            $names[] = $person['middle'];
            $names[] = $factory->company();
        }

        foreach (array_filter($names) as $name) {
            self::assertDoesNotMatchRegularExpression(
                '/\d/',
                $name,
                'A generated person or company name must contain no digits: ' . $name
            );
        }
    }

    /**
     * Every word in every list must be reachable.
     *
     * This is the regression test for the linear congruential generator. Drawing many times more
     * often than there are words, every word should appear; a source that can only reach half a
     * list fails immediately and unmistakably.
     */
    public function testEveryWordInAPoolCanActuallyBeDrawn(): void
    {
        $pools = self::pools();
        $factory = self::factory('reachability');

        $firstNames = $pools->pool('first-names');
        $seen = [];
        for ($index = 0; $index < count($firstNames) * 12; $index++) {
            $seen[$factory->person()['first']] = true;
        }

        // Twelve draws per word leaves a vanishing chance of missing one by luck; missing half of
        // them is the defect this covers.
        self::assertGreaterThan(
            (int) (count($firstNames) * 0.97),
            count($seen),
            'The random source cannot reach every name in the list.'
        );
    }

    /** The same seed token reproduces the same set, so a set can be regenerated identically. */
    public function testTheSameSeedProducesTheSameNames(): void
    {
        $one = self::factory('repeatable');
        $two = self::factory('repeatable');

        for ($index = 0; $index < 50; $index++) {
            self::assertSame($one->person()['display'], $two->person()['display']);
            self::assertSame($one->company(), $two->company());
        }
    }

    /** Different tokens produce different sets, or every seed batch would look identical. */
    public function testDifferentSeedsProduceDifferentNames(): void
    {
        $one = self::factory('token-one');
        $two = self::factory('token-two');

        $first = [];
        $second = [];
        for ($index = 0; $index < 100; $index++) {
            $first[] = $one->person()['display'];
            $second[] = $two->person()['display'];
        }

        self::assertLessThan(5, count(array_intersect($first, $second)));
    }

    /**
     * The names are data, not code, so an operator can add their own without a release.
     *
     * This fails until SeedGenerator is rewritten onto the pools, which is deliberate: the lists
     * existing in files means nothing while the generator still reads its own copies.
     */
    public function testTheNamesAreNotInTheCode(): void
    {
        $generator = (string) file_get_contents(self::root() . '/src/Seed/SeedGenerator.php');

        foreach (['FIRST_NAMES', 'LAST_NAMES', 'COMPANY_PREFIXES', 'COMPANY_SUFFIXES', 'COURSE_TOPICS', 'CATEGORY_NAMES'] as $constant) {
            self::assertStringNotContainsString(
                'const ' . $constant,
                $generator,
                'Name lists belong in storage/seeds, where they can be edited, not in the generator.'
            );
        }
    }

    /** The bundled lists are published to the instance rather than read from the release. */
    public function testTheListsArePublishedToTheInstance(): void
    {
        $composer = (string) file_get_contents(self::root() . '/composer.json');

        self::assertStringContainsString('"seeds:publish"', $composer);
        self::assertStringContainsString('"@seeds:publish"', $composer, 'A first install must publish the name lists.');
        self::assertFileExists(self::root() . '/tools/publish-seed-names.php');
    }
}
