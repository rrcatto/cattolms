declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Seed\SeedNamePools;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

final class SeedNamePoolContractTest extends TestCase
{
    private static function root(): string
    {
        return dirname(__DIR__, 2);
    }

    private static function pools(): SeedNamePools
    {
        // The bundled lists: the instance copy is whatever the operator has made of it.
        return new SeedNamePools(self::root() . '/storage/seeds-none', self::root() . '/resources/seeds');
    }

    /** @return list<array{0:string}> */
    public static function poolNames(): array
    {
        return array_map(static fn(string $name): array => [$name], array_keys(SeedNamePools::POOLS));
    }

    #[DataProvider('poolNames')]
    public function testEveryDeclaredPoolShipsWithTheRelease(string $name): void
    {
        self::assertFileExists(self::root() . '/resources/seeds/' . $name . '.txt', 'A declared pool with no bundled file leaves a fresh install unable to seed.');
        self::assertGreaterThanOrEqual(SeedNamePools::POOLS[$name], count(self::pools()->pool($name)), $name . ' holds fewer names than its own declared minimum.');
    }

    #[DataProvider('poolNames')]
    public function testNoEntryIsNumberedOrMadeUp(string $name): void
    {
        foreach (self::pools()->pool($name) as $word) {
            self::assertDoesNotMatchRegularExpression('/\d/', $word, $name . ': "' . $word . '" carries a number.');
            self::assertMatchesRegularExpression("/^[\\p{L}][\\p{L} '.-]*\$/u", $word, $name . ': "' . $word . '" is not a name.');
        }
        // A few of the words the old generated lists were made of.
        foreach (['Droiri', 'Tebturn', 'Perzass', 'Fapip', 'Wudufis', 'Droichunt', 'Bimedogh', 'Flamkono'] as $madeUp) {
            self::assertNotContains($madeUp, self::pools()->pool($name), $name . ' still holds a made-up word.');
        }
    }

    public function testNamesCombineToFarMoreThanARunNeeds(): void
    {
        $pools = self::pools();
        self::assertGreaterThan(100000, count($pools->pool('first-names')) * count($pools->pool('surnames')), 'People\'s names would repeat.');
        self::assertGreaterThan(5000, count($pools->pool('company-words')) * count($pools->pool('company-trades')), 'Company names would run out.');
    }

    public function testTheMadeUpListsAreGone(): void
    {
        foreach (['company-places', 'company-qualities', 'company-sectors', 'course-subjects', 'course-topics', 'course-levels', 'course-categories'] as $old) {
            self::assertFileDoesNotExist(self::root() . '/resources/seeds/' . $old . '.txt');
        }
    }

    public function testTheNamesAreNotInTheCode(): void
    {
        $source = (string) file_get_contents(self::root() . '/src/Seed/SeedNames.php');
        foreach (['Karoo', 'Umhlanga', 'Logistics', 'Dlamini'] as $word) {
            self::assertStringNotContainsString("'" . $word, $source, 'Names belong in the lists, which an operator can edit.');
        }
    }
}
