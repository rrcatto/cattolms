declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Course\LegacyHtmlCourseImporter;
use CattoLearning\Tests\Support\SpecificationExample;
use PHPUnit\Framework\TestCase;

final class CourseDriftWarningsTest extends TestCase
{
    public function testTheSpecificationsExampleGivesNoWarning(): void
    {
        self::assertSame([], (new LegacyHtmlCourseImporter())->analyse(SpecificationExample::html(), 'example.html')['warnings']);
    }

    public function testEachKindOfDriftIsNamed(): void
    {
        $html = SpecificationExample::html();
        $html = str_replace('<details class="block practical">', '<details class="block workshop">', $html);
        $html = str_replace('<p>A container must be big enough for its crop, drain freely and be filled with potting soil.</p>',
            '<p>A container must be big enough for its crop, drain freely and be filled with potting soil. Labour counts for 30% of the cost of a bed.</p>'
            . '<details class="block"><summary class="block-head">Practical Exercises <small>3 tasks</small></summary><div class="block-inner"><ol class="ex-list"><li><b class="ex-t">Measure</b><p>Measure a pot.</p><details class="ex-sol"><summary>Show worked solution</summary><p>Use a ruler.</p></details></li></ol></div></details>'
            . '<div class="box"><b>Month 1 Submission</b> Three items are submitted at the end of the month.</div>', $html);
        $html = str_replace('<p>Your module assessments count for half of your final mark and the final assessment for the other half.</p>',
            '<p>Your module assessments are weighted at 25% of your result. The capstone is submitted for assessment and carries 50%.</p>', $html);
        $warnings = implode("\n", (new LegacyHtmlCourseImporter())->analyse($html, 'drifted.html')['warnings']);
        foreach ([
            'Soil, compost and containers: a block called "workshop" is not a part CattoLMS reads',
            'Soil, compost and containers: a block headed "Practical Exercises',
            'Soil, compost and containers: worked solutions are hidden inside tasks',
            'Soil, compost and containers: model answers have no .practical tasks',
            'Soil, compost and containers says "Month 1 Submission"',
            'The introduction says "submitted for assessment"',
            'The introduction gives grading weights other than 50%',
        ] as $expected) {
            self::assertStringContainsString($expected, $warnings);
        }
        self::assertStringNotContainsString('Labour counts', $warnings, 'A figure in a lesson is not a grading weight.');
    }

    public function testATableOfExamWeightsIsNotGrading(): void
    {
        $html = str_replace('<h3>How you are graded</h3>',
            '<table><caption>The exam domains this course covers</caption><tr><th>Exam domain</th><th>Weight in the exam</th></tr><tr><td>System management</td><td>23%</td></tr><tr><td>Security</td><td>18%</td></tr></table><h3>How you are graded</h3>',
            SpecificationExample::html());
        self::assertSame([], (new LegacyHtmlCourseImporter())->analyse($html, 'exam-domains.html')['warnings'], 'An exam\'s weights in a table are course content, not the course\'s grading.');
    }
}
