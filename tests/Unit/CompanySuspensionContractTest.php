declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Auth\AuthService;
use PHPUnit\Framework\TestCase;

final class CompanySuspensionContractTest extends TestCase
{
    private static function source(string $relative): string
    {
        return (string) file_get_contents(dirname(__DIR__, 2) . '/' . $relative);
    }

    /** The suspension is decided on the identity path, which every authenticated request crosses. */
    public function testSuspensionIsEnforcedAtTheIdentityBoundary(): void
    {
        $auth = self::source('src/Auth/AuthService.php');

        self::assertStringContainsString("\$session['company_suspended']", $auth, 'currentUser() must consult the suspension.');
        self::assertStringContainsString('companySuspensionBlocks(', $auth, 'consumeLogin() must consult it too.');
    }

    /** Both halves exempt a platform administrator, and neither relies on the other to do it. */
    public function testThePlatformAdministratorExemptionIsExplicitInBothPaths(): void
    {
        $auth = self::source('src/Auth/AuthService.php');
        $sessions = self::source('src/Infrastructure/Persistence/AuthSessionRepository.php');

        // Asserted as the two distinct sites rather than by counting: AuthService also carries the
        // unrelated recovery-administrator block, and a count would silently track that instead.
        self::assertStringContainsString(
            "\$session['company_suspended'] ?? false) && !in_array('ADMIN', \$roles, true)",
            $auth,
            'The request path must exempt an administrator on its own.'
        );
        self::assertStringContainsString(
            "return !in_array('ADMIN', \$roles, true);",
            $auth,
            'The sign-in path must exempt an administrator on its own.'
        );
        self::assertStringContainsString("r.role_key = 'ADMIN'", $sessions, 'The revocation sweep must skip administrators.');
    }

    /**
     * The check is not copied into controllers.
     *
     * A scattered check is the failure mode the central boundary exists to prevent: it works until
     * somebody adds a route and does not know to add it there too.
     */
    public function testControllersDoNotCarryTheirOwnCompanyStatusChecks(): void
    {
        foreach (glob(dirname(__DIR__, 2) . '/src/Http/Controller/*.php') ?: [] as $file) {
            $source = (string) file_get_contents($file);
            self::assertStringNotContainsString(
                'hasSuspendedCompany(',
                $source,
                basename($file) . ' must not test company suspension for itself.'
            );
            self::assertStringNotContainsString(
                "c.status <> 'active'",
                $source,
                basename($file) . ' must not carry its own company-status SQL.'
            );
        }
    }

    /** Suspension revokes sessions in the same transaction as the status change. */
    public function testSuspensionAndRevocationAreOneOperation(): void
    {
        $service = self::source('src/Application/PlatformAdministrationService.php');

        self::assertStringContainsString('revokeCompanyMemberSessions(', $service);
        self::assertMatchesRegularExpression(
            '/setCompanyStatus\(.*?transactions->run/s',
            $service,
            'A status change that half-applied would leave live sessions on a suspended company.'
        );
    }

    /** Re-enabling revokes nothing: it is a status change and needs no repair step. */
    public function testReinstatementRevokesNothing(): void
    {
        $service = self::source('src/Application/PlatformAdministrationService.php');

        self::assertStringContainsString(
            "\$status === 'active' ? 0 : \$this->sessions->revokeCompanyMemberSessions(\$companyId)",
            $service
        );
    }

    /** The System Company invariant stays at repository level, not in a hidden button. */
    public function testTheSystemCompanyRefusalIsAtRepositoryLevel(): void
    {
        $repository = self::source('src/Infrastructure/Persistence/CompanyRepository.php');

        self::assertStringContainsString('The System Company cannot be disabled.', $repository);
    }

    /** The message names the company as the reason, and does not blame the reader's account. */
    public function testTheSuspensionMessageIsUsableByANonTechnicalReader(): void
    {
        $message = AuthService::SUSPENDED_COMPANY_MESSAGE;

        self::assertStringContainsString('suspended', $message);
        self::assertStringContainsString('safe', $message, 'A reader must be told nothing of theirs is lost.');
        self::assertStringNotContainsString('company_users', $message);
        self::assertStringNotContainsString('status', $message, 'No column names in a message for a learner.');
    }

    /** The workspace tells the two situations apart instead of blaming the account for both. */
    public function testTheWorkspaceDistinguishesSuspensionFromHavingNoCompany(): void
    {
        $context = self::source('src/Company/SelectedCompanyContext.php');

        self::assertStringContainsString('userCompanyIsSuspended(', $context);
        self::assertStringContainsString('not attached to a company yet', $context);
    }
}
