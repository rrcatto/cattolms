namespace CattoLearning\Tests\Unit;

use CattoLearning\Support\EmailAddress;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class EmailAddressTest extends TestCase
{
    public function testNormalizesEmail(): void
    {
        self::assertSame('person@example.co.za', EmailAddress::normalize(' Person@Example.CO.ZA '));
        self::assertSame('example.co.za', EmailAddress::domain('person@example.co.za'));
    }

    public function testRejectsInvalidEmail(): void
    {
        $this->expectException(InvalidArgumentException::class);
        EmailAddress::normalize('not-an-email');
    }
