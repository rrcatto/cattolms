declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Infrastructure\Persistence\RestrictViolationMiddleware;
use Doctrine\DBAL\Driver\AbstractException;
use Doctrine\DBAL\Driver\API\PostgreSQL\ExceptionConverter;
use Doctrine\DBAL\Exception\ForeignKeyConstraintViolationException;
use Doctrine\DBAL\Exception\UniqueConstraintViolationException;
use PHPUnit\Framework\TestCase;

final class RestrictViolationMiddlewareTest extends TestCase
{
    public function testARestrictRefusalIsAForeignKeyViolationOnEveryPostgreSql(): void
    {
        $converter = RestrictViolationMiddleware::converter(new ExceptionConverter());
        foreach ([['23001', 'PostgreSQL 18'], ['23503', 'PostgreSQL 16']] as [$state, $where]) {
            self::assertInstanceOf(ForeignKeyConstraintViolationException::class, $converter->convert(self::error($state), null), $where);
        }
        self::assertInstanceOf(UniqueConstraintViolationException::class, $converter->convert(self::error('23505'), null), 'Everything else as the driver converts it.');
    }

    private static function error(string $state): AbstractException
    {
        return new class ('refused', $state) extends AbstractException {
        };
    }
}
