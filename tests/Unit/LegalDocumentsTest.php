    public function testTheRefundRuleRefusesAStartedCourseAndAPurchaseOutsideTheWindow(): void
    {
        $paid = new DateTimeImmutable('2026-10-01T10:00:00+02:00');
        $week = Duration::parse('7d');
        self::assertSame('2026-10-08T10:00:00+02:00', RefundRule::windowEndsAt($paid, $week)->format(DATE_ATOM));
        self::assertSame([], RefundRule::refusals($paid, $paid->modify('+7 days -1 second'), $week, []), 'Not started and inside the window: the rule allows a refund.');
        self::assertSame(['The refund period of 7 days from the purchase on 1 October 2026 has ended.'], RefundRule::refusals($paid, $paid->modify('+7 days'), $week, []), 'At the end of the window it does not.');
        self::assertSame(['The course started on 1 October 2026. A started course is not refunded.'], RefundRule::refusals($paid, $paid->modify('+1 minute'), $week, [['title' => 'Course A', 'started_at' => '2026-10-01T10:00:00+02:00']]), 'A course started on payment is refused at once.');
        self::assertSame(
            ['Course B, a course in this bundle, started on 3 October 2026. A started course is not refunded.', 'The refund period of 7 days from the purchase on 1 October 2026 has ended.'],
            RefundRule::refusals($paid, $paid->modify('+30 days'), $week, [['title' => 'Course B', 'started_at' => '2026-10-03T08:00:00+02:00']], true),
            'One started course refuses the whole bundle, and both reasons are given.'
        );
        self::assertSame(['The refund period of 7 days from the credit purchase on 1 October 2026 has ended.'], RefundRule::refusals($paid, $paid->modify('+8 days'), $week, [], false, true));
        self::assertSame([], RefundRule::refusals($paid, $paid->modify('+10 days'), Duration::parse('2w'), []), 'The window is the setting in force, not a constant.');
    }

