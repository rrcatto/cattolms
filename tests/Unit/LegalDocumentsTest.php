    /** A page is dated by the later of its text and the last change to a Site Owner detail it prints. */
    public function testAPageIsDatedByTheLaterOfItsTextAndTheSiteOwner(): void
    {
        $documents = (new \ReflectionClassConstant(LegalDocuments::class, 'DOCUMENTS'))->getValue();
        $later = new LegalDocuments(SiteOwner::fixed(['trading_name' => 'P', 'legal_name' => 'P'], '2099-01-02T10:00:00+02:00'));
        self::assertSame(['2099-01-02', '2 January 2099'], [$later->document('terms')['updated'], $later->document('terms')['updated_label']]);
        $earlier = new LegalDocuments(SiteOwner::fixed(['trading_name' => 'P', 'legal_name' => 'P'], '2020-01-01T10:00:00+02:00'));
        self::assertSame($documents['refunds']['text_updated'], $earlier->document('refunds')['updated'], 'an older Site Owner change does not move the date back');
        $accepted = $later->acceptedDocuments();
        self::assertSame(['terms' => '2099-01-02', 'refunds' => '2099-01-02', 'privacy' => '2099-01-02'], $accepted['documents']);
        self::assertSame('P', $accepted['site_owner']['trading_name']);
    }
