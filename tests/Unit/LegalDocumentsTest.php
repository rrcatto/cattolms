            }
            self::assertStringNotContainsString('OWNER DECISION', $text);
            self::assertDoesNotMatchRegularExpression('/\[[A-Z][A-Z ]+\]/', $text, 'No [PLACEHOLDER] is left.');
            foreach (['organiz', 'recogniz', 'authoriz', 'color ', 'license ', 'program '] as $american) {
                self::assertStringNotContainsStringIgnoringCase($american, $text, 'British spelling: ' . $american);
            }
        }
    }

