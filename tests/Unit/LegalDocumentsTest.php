        self::assertStringContainsString('Analytics events store neither an IP address nor a user agent.', $privacy);
        self::assertStringContainsString('https://inforegulator.org.za', $privacy);
    }

    public function testTheRefundRuleRefusesAStartedCourseAndAPurchaseSevenDaysOld(): void
    {
        $paid = new DateTimeImmutable('2026-10-01T10:00:00+02:00');
        self::assertSame('2026-10-08T10:00:00+02:00', RefundRule::windowEndsAt($paid)->format(DATE_ATOM));
        self::assertSame([], RefundRule::refusals($paid, $paid->modify('+7 days -1 second'), []), 'Fewer than seven days and not started: a refund is given.');
        self::assertSame(['7 days have passed since the purchase on 1 October 2026.'], RefundRule::refusals($paid, $paid->modify('+7 days'), []), 'At seven days it is not.');
        self::assertSame(['The learner started the course on 2 October 2026.'], RefundRule::refusals($paid, $paid->modify('+2 days'), [['title' => 'Course A', 'started_at' => '2026-10-02T08:00:00+02:00']]));
        self::assertSame(
            ['The learner started Course B, a course in this bundle, on 3 October 2026.', '7 days have passed since the purchase on 1 October 2026.'],
            RefundRule::refusals($paid, $paid->modify('+30 days'), [['title' => 'Course B', 'started_at' => '2026-10-03T08:00:00+02:00']], true),
            'One started course refuses the whole bundle, and both reasons are given.'
        );
        self::assertSame(['7 days have passed since the credits were bought on 1 October 2026.'], RefundRule::refusals($paid, $paid->modify('+8 days'), [], false, true));
    }

