    /** @param array<string,mixed> $hive */
    private static function renderError(string $template, array $hive): ?string
    {
        $f3 = Base::instance();
        $temp = sys_get_temp_dir() . '/catto-seed-render/';
        if (!is_dir($temp)) {
            mkdir($temp, 0775, true);
        }

        $f3->set('UI', self::root() . '/resources/views/');
        $f3->set('TEMP', $temp);
        $f3->set('HALT', false);
        $f3->set('ONERROR', static function (): void {
        });
        $f3->clear('ERROR');

        foreach ($hive as $key => $value) {
            $f3->set($key, $value);
        }

        $captured = null;
        set_error_handler(static function (int $severity, string $message) use (&$captured): bool {
            $captured ??= $message;

            return true;
        });

        try {
            Template::instance()->render($template);
        } catch (\Throwable $exception) {
            $captured ??= $exception->getMessage();
        } finally {
            restore_error_handler();
        }

        $error = $f3->get('ERROR');
        if ($captured === null && is_array($error)) {
            $captured = (string) ($error['text'] ?? 'unknown template error');
        }

        return $captured;
    }
    /**
     * Cleanup invalidates a set's login tokens before it removes the identities they name.
     *
     * Order matters more than it looks. `auth_login_tokens.user_id` is nullable, so a token left
     * behind by a deleted user does not disappear with it - it becomes a live magic link for an
     * address nobody owns. Doing this first means the tokens are gone while the set's identities
     * are still there to be matched.
     */
    public function testSeedCleanupInvalidatesLoginTokensBeforeDeletingIdentities(): void
    {
        $service = self::read('src/Seed/SeedDatabaseService.php');

        $invalidate = strpos($service, '$this->seeds->invalidateLoginTokensForSet($token);');
        $delete = strpos($service, '$this->seeds->deleteSet($token);');
        self::assertIsInt($invalidate, "Cleanup must invalidate the outstanding login tokens of the set.");
        self::assertIsInt($delete);
        self::assertLessThan($delete, $invalidate, 'Tokens must be cleared while their identities still exist.');
    }

    /**
     * The invalidation is bounded by the set and matches both ways a token names an identity.
     *
     * A token raised for an existing account carries `user_id`; one raised before the account was
     * resolved carries only the address. Both are anchored on `seed_token = :token`, so a REAL
     * identity's token cannot be swept up by either branch.
     */
    public function testLoginTokenInvalidationIsScopedToTheSetAndCoversUnresolvedTokens(): void
    {
        $repository = self::read('src/Infrastructure/Persistence/SeedRepository.php');
        preg_match(
            '/public function invalidateLoginTokensForSet\(string \$token\): int\s*\{(.*?)
    \}/s',
            $repository,
            $match
        );
        self::assertNotEmpty($match, 'invalidateLoginTokensForSet() was not found.');

        $body = $match[1];
        self::assertStringContainsString('DELETE FROM auth_login_tokens', $body);
        self::assertStringContainsString('u.id = t.user_id', $body, 'A token naming a set user must be cleared.');
        self::assertStringContainsString('ue.email = t.email', $body, 'A token naming a set address must be cleared.');
        self::assertSame(
