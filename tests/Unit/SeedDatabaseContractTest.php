    /**
     * Two sets generated moments apart get different slugs.
     *
     * A regression for a defect that only appears under timing. The per-set suffix used to be the
     * first eight characters of the set token, and a UUIDv7 opens with a 48-bit millisecond
     * timestamp - so those eight characters are the *top 32 bits* of that counter and change once
     * every 2^16 ms, about every 65 seconds. Two seed sets generated inside the same minute
     * therefore produced identical category and course slugs, and PostgreSQL refused the second
     * with `course_categories_slug_key`.
     *
     * A hundred tokens in a tight loop reproduces the old failure reliably: all of them fall
     * inside one window.
     *
     * The key is read out of the generator itself rather than recomputed here. A test that
     * repeats the expression it is checking only proves the expression equals itself.
     */
    public function testTokensGeneratedInTheSameWindowProduceDifferentSuffixes(): void
    {
        $tokens = [];
        for ($i = 0; $i < 100; $i++) {
            $tokens[] = Uuid::v7();
        }

        // The old derivation, shown rather than described, so the collision is visible.
        $timestampPrefixes = [];
        foreach ($tokens as $token) {
            $timestampPrefixes[substr(str_replace('-', '', $token), 0, 8)] = true;
        }
        self::assertLessThan(
            count($tokens),
            count($timestampPrefixes),
            'If these stop colliding the tokens are no longer time-ordered, and this test has lost its point.'
        );

        $keys = [];
        foreach ($tokens as $token) {
            $keys[self::setUniqueKey($token)] = true;
        }
        self::assertCount(
            count($tokens),
            $keys,
            'Every seed set must get its own uniqueness key, whatever the interval between them.'
        );
    }

    /**
     * The key is a namespace, not a slice of the clock.
     *
     * A behavioural check rather than a reading of the source: two tokens that differ only in
     * their random half - the same millisecond, so byte-identical timestamps - must still produce
     * different keys. Any derivation taken from the leading timestamp fails this.
     */
    public function testTheKeyDependsOnTheWholeTokenAndNotItsTimestamp(): void
    {
        $prefix = substr(Uuid::v7(), 0, 14);

        $first = $prefix . '8123-456789abcdef';
        $second = $prefix . '8123-456789abcdee';

        self::assertSame(
            substr(str_replace('-', '', $first), 0, 8),
            substr(str_replace('-', '', $second), 0, 8),
            'These tokens must share a timestamp prefix, or the test is not testing anything.'
        );
        self::assertNotSame(
            self::setUniqueKey($first),
            self::setUniqueKey($second),
            'The key must depend on the whole token, including the random half.'
        );
    }

    /** The same token still rebuilds the same graph, which is what makes a defect reproducible. */
    public function testTheSuffixRemainsDeterministic(): void
    {
        $token = Uuid::v7();

        self::assertSame(
            self::setUniqueKey($token),
            self::setUniqueKey($token),
            'Reproducibility is why the key is hashed rather than randomised.'
        );
        self::assertSame(
            self::setUniqueKey(strtolower($token)),
            self::setUniqueKey(strtoupper($token)),
            'Two spellings of one UUID must not describe two different graphs.'
        );
    }

    /**
     * The key must fit every unique column it feeds, with room for the readable part in front.
     *
     * The generated address is the tightest of them, and it carries the key twice - once in the
     * local part and once in the generated domain.
     */
    public function testTheKeyIsShortEnoughForEveryColumnItFeeds(): void
    {
        $key = self::setUniqueKey(Uuid::v7());

        self::assertSame(16, strlen($key), 'A changed key length needs the column audit run again.');
        self::assertMatchesRegularExpression('/^[0-9a-f]+$/', $key, 'The key appears in slugs and domains.');
    }

    /** Calls the generator's own derivation, so these tests move when it does. */
    private static function setUniqueKey(string $token): string
    {
        $method = new ReflectionMethod(SeedGenerator::class, 'setUniqueKey');

        /** @var string $key */
        $key = $method->invoke(
            (new ReflectionClass(SeedGenerator::class))->newInstanceWithoutConstructor(),
            $token
        );

        return $key;
    }

