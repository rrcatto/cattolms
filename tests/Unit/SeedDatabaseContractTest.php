            substr_count($body, 'u.seed_token = :token::uuid'),
            'Both branches must be bounded by the set, so no REAL identity loses a token.'
        );
        self::assertStringNotContainsString(
            'seed.invalid',
            $body,
            'Deletion must follow the set, not the address shape: a generated domain is not proof of membership.'
        );
    }

