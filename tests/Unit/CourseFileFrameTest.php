declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Course\CourseFileFrame;
use CattoLearning\Tests\Support\OriginalBuildExample;
use PHPUnit\Framework\TestCase;

final class CourseFileFrameTest extends TestCase
{
    public function testTheFrameKeepsTheBuildAndCutsTheContent(): void
    {
        $frame = CourseFileFrame::capture(OriginalBuildExample::html());
        self::assertNotNull($frame);
        $template = $frame['template'];
        self::assertStringContainsString('<details', $template);
        self::assertStringContainsString('<summary class="acc-trigger module-trigger">', $template);
        self::assertStringNotContainsString('<button class="acc-trigger', $template, 'Every panel is a <details>.');
        self::assertStringContainsString('class="module acc-item" id="mod-m1"', $template, 'A panel keeps its classes and id, so its own rules still style it.');
        self::assertStringContainsString('<!--cl:stylesheet-->', $template, 'Where the styling goes: the styling itself is the course\'s CSS tab.');
        self::assertStringNotContainsString('<style', $template);
        self::assertStringContainsString('if(mod && pct < 101)', $template, 'Nor is a script.');
        self::assertStringContainsString(htmlspecialchars(OriginalBuildExample::FONTS, ENT_QUOTES), $template, 'The head stays, its fonts with it.');
        self::assertStringContainsString('<div class="progress-strip">', $template);
        self::assertStringContainsString('<h1>Growing <em>Vegetables</em></h1>', $template);
        self::assertStringContainsString('function gradeQuiz(id)', $template, 'The script stays.');
        self::assertStringContainsString('/*cl:QUIZ:const*/', $template, 'Its data goes.');
        self::assertStringNotContainsString('What does a jar test show?', $template);
        self::assertStringNotContainsString('Everything starts below the surface', $template, 'The lesson is the site\'s.');
        self::assertStringNotContainsString('Feed the soil', $template, 'So is the summary.');
        self::assertStringContainsString('The correct option and a short explanation', $template, 'A panel\'s own note stays.');
        self::assertStringContainsString('<details class="block practical">', $template, 'A practical in the module\'s body stays.');
        self::assertStringNotContainsString('Sow one row of radishes', $template, 'Its tasks are the site\'s.');
        self::assertStringContainsString('Reset all progress', $frame['reset']);
        self::assertStringContainsString('scale-list', $frame['scale']);
        self::assertStringNotContainsString('Work through the modules', $template, 'The introduction is the site\'s.');
        self::assertStringNotContainsString('course-cover', $template, 'So is the cover.');
    }

    public function testAFileWrittenToTheSpecificationHasNoFrame(): void
    {
        self::assertNull(CourseFileFrame::capture('<!doctype html><html><body><section class="module" id="mod-m1"><details class="panel"><summary class="panel-head">One</summary></details></section></body></html>'));
    }
}
