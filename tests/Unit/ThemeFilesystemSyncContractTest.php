    private function rewriteManifest(string $path, string $name, string $slug, string $version): void
    {
        $manifest = json_decode((string) file_get_contents($path), true, 512, JSON_THROW_ON_ERROR);
        self::assertIsArray($manifest);
        $manifest['theme']['name'] = $name;
        $manifest['theme']['slug'] = $slug;
        $manifest['theme']['version'] = $version;
        file_put_contents($path, json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
    }

    private function copyDirectory(string $source, string $target): void
    {
        mkdir($target, 0777, true);
        foreach (scandir($source) ?: [] as $entry) {
            if ($entry === '.' || $entry === '..') continue;
            $from = $source . '/' . $entry;
            $to = $target . '/' . $entry;
            if (is_dir($from)) $this->copyDirectory($from, $to); else copy($from, $to);
        }
    }

    private function removeDirectory(string $dir): void
    {
        if (!is_dir($dir)) return;
        foreach (scandir($dir) ?: [] as $entry) {
            if ($entry === '.' || $entry === '..') continue;
            $path = $dir . '/' . $entry;
            if (is_dir($path)) $this->removeDirectory($path); else @unlink($path);
        }
        @rmdir($dir);
    }
