Description:
Every table gives each column the space that column needs, and no table has a nameless column or a
row of buttons in a cell.

These are the three rules the tables kept breaking, each for its own reason, and each caught here
rather than on screen:

  1. Every column declares a width and the widths total one hundred. `table-layout: fixed` with no
     widths divides the table equally, so a five-column table gave a person's full name the same
     twenty per cent it gave a three-digit count. Every Company screen shipped like that. A set that
     does not total one hundred is not a proportion at all: the browser scales it, and the numbers
     stop describing what is rendered.
  2. Every column has a heading, the actions column included. A column with no heading is a column
     the reader has to work out from its contents.
  3. Two or more controls in one cell is a menu, not a row of buttons. Five buttons need about four
     hundred pixels; the menu is one control of a fixed width, and the difference goes to the column
     carrying the name the reader came to read. This is also what stopped the last button of the row
     being drawn half outside the table.

The width figures themselves are a judgement and this test does not police them. What it does police
is that the judgement was made: a count column takes six per cent because six is what four digits
need, and a title column takes what is left.

Changelog:
2026/09/07 22:10 SAST
- Created after the tables were reported as unusable: numeric columns hogging the width, actions
  columns with no heading, and button rows that did not fit.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class TableSpaceContractTest extends TestCase
{
    private static function root(): string
    {
        return dirname(__DIR__, 2);
    }

    /** @return list<string> */
    private static function views(): array
    {
        $files = [];
        $directory = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator(self::root() . '/resources/views'));
        foreach ($directory as $file) {
            if (!$file->isDir() && $file->getExtension() === 'html') {
                $files[] = $file->getPathname();
            }
        }
        sort($files);

        return $files;
    }

    /**
     * Every column model the service builds declares a width, and they total one hundred.
     *
     * The labels carry the share after a pipe, so this reads the models themselves rather than the
     * rendered page: a dataset whose widths were forgotten renders equal columns and looks merely
     * ugly rather than broken, which is how it survived.
     */
    public function testEveryDeclaredColumnModelTotalsOneHundred(): void
    {
        $service = (string) file_get_contents(self::root() . '/src/Application/PlatformAdministrationService.php');

        // A column model is an array literal whose entries are 'key' => 'Label|width'.
        preg_match_all("/\[[^\[\]]*?'[a-z_]+' => '[^']*\|\d+'[^\[\]]*?\]/s", $service, $models);
        self::assertNotSame([], $models[0], 'The scan found no column models, so it is proving nothing.');

        foreach ($models[0] as $model) {
            $entries = preg_match_all("/'[a-z_]+' => '([^']*)'/", $model, $labels);
            preg_match_all("/\|(\d+)'/", $model, $widths);

            self::assertCount(
                $entries,
                $widths[1],
                'Every column in a model must declare its width: ' . substr(preg_replace('/\s+/', ' ', $model) ?? '', 0, 120)
            );
            self::assertSame(
                100,
                array_sum(array_map(intval(...), $widths[1])),
                'Column widths are a proportion and must total 100: ' . substr(preg_replace('/\s+/', ' ', $model) ?? '', 0, 120)
            );
        }
    }

    /** A heading row written out in markup follows the same rule. */
    public function testEveryHandWrittenHeadingRowTotalsOneHundred(): void
    {
        $offenders = [];
        foreach (self::views() as $path) {
            $markup = (string) file_get_contents($path);
            foreach (preg_split('/<\/thead>/', $markup) ?: [] as $chunk) {
                $at = strrpos($chunk, '<thead>');
                if ($at === false) continue;
                $head = substr($chunk, $at);
                // Heading rows built from a model are covered by the test above.
                if (str_contains($head, 'sortable-header') || str_contains($head, 'repeat')) continue;

                $columns = preg_match_all('/<th\b[^>]*>/', $head, $cells);
                if ($columns === 0) continue;
                preg_match_all('/width:(\d+)%/', $head, $widths);
                if (count($widths[1]) !== $columns || array_sum(array_map(intval(...), $widths[1])) !== 100) {
                    $offenders[] = basename($path);
                }
            }
        }

        self::assertSame([], array_values(array_unique($offenders)));
    }

    /** No column is nameless, the actions column least of all. */
    public function testNoColumnIsNameless(): void
    {
        $service = (string) file_get_contents(self::root() . '/src/Application/PlatformAdministrationService.php');

        self::assertDoesNotMatchRegularExpression(
            "/'actions' => '\|/",
            $service,
            'The actions column must be headed "Actions", not left blank.'
        );
        $offenders = [];
        foreach (self::views() as $path) {
            $markup = (string) file_get_contents($path);
            if (preg_match('/<th\b[^>]*>\s*<\/th>/', $markup) === 1) {
                $offenders[] = basename($path);
            }
        }
        self::assertSame([], $offenders, 'An empty heading cell is a column the reader has to guess.');
    }

    /**
     * A cell with two or more controls uses the shared row menu.
     *
     * Counted on the cell rather than on the row: a row legitimately carries several cells that each
     * hold one control, and it is the cell that has to fit.
     */
    public function testACellWithSeveralControlsUsesTheSharedMenu(): void
    {
        $offenders = [];
        foreach (self::views() as $path) {
            $markup = (string) file_get_contents($path);
            // A cell may opt out, and must say why in the attribute itself. The Themes list is the
            // one that does: Activate is how an operator recovers from a theme that renders badly,
            // so it cannot be behind a menu that the same theme has to render correctly first.
            preg_match_all('/<td\b(?![^>]*data-no-row-menu)[^>]*>(.*?)<\/td>/s', $markup, $cells);

            foreach ($cells[1] as $cell) {
                if (str_contains($cell, 'row-menu')) continue;
                // Ordering arrows are one control in two halves, not two actions.
                if (str_contains($cell, "name=\"direction\"")) continue;
                // A check's two branches are exclusive, so only one of them is ever on screen.
                // Restore and Remove access are the same single button in two states.
                $rendered = (string) preg_replace('/<false>.*?<\/false>/s', '', $cell);
                $controls = preg_match_all('/<(?:button|a)\b[^>]*class="[^"]*\bbtn\b/', $rendered);
                if ($controls >= 2) {
                    $offenders[] = basename($path) . ': ' . $controls . ' controls in one cell';
                }
            }
        }

        self::assertSame([], array_values(array_unique($offenders)));
    }

    /**
     * An action in a table looks like a button.
     *
     * The Activity list used `btn-ghost`, which every theme draws as bare text, so the only way to
     * reach an event's details was to guess that the word was clickable. Consistency here is not
     * decoration: it is what makes a control recognisable as one.
     */
    public function testAnActionInATableLooksLikeAButton(): void
    {
        $offenders = [];
        foreach (self::views() as $path) {
            $markup = (string) file_get_contents($path);
            preg_match_all('/<td\b[^>]*>(.*?)<\/td>/s', $markup, $cells);
            foreach ($cells[1] as $cell) {
                if (str_contains($cell, 'btn-ghost')) {
                    $offenders[] = basename($path);
                }
            }
        }

        self::assertSame([], array_values(array_unique($offenders)));
    }
}
