declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class EnvWizardAppEnvTest extends TestCase
{
    /** @var list<string> */
    private array $files = [];

    protected function tearDown(): void
    {
        foreach ($this->files as $file) @unlink($file);
    }

    public function testAnExistingSiteKeepsDevelopment(): void
    {
        $existing = $this->file("APP_ENV=development\nAPP_DEBUG=true\n");
        self::assertSame(['development', null], $this->written($existing, []), 'Development kept; the retired APP_DEBUG dropped.');
    }

    public function testANewSiteStartsAsDevelopment(): void
    {
        self::assertSame(['development', null], $this->written(null, []), 'The example\'s value, never production.');
    }

    public function testProductionOnlyWhenItIsGiven(): void
    {
        $existing = $this->file("APP_ENV=development\n");
        self::assertSame(['production', null], $this->written($existing, ['APP_ENV' => 'production']), 'The owner\'s own answer.');
    }

    public function testAnythingElseIsRefused(): void
    {
        [$status, $output] = $this->wizard(null, ['APP_ENV' => 'prod']);
        self::assertNotSame(0, $status);
        self::assertStringContainsString('APP_ENV in the answers file: Enter development or production.', $output);
    }

    /**
     * The APP_ENV the wizard writes, and the APP_DEBUG line if it writes one.
     *
     * @param array<string,string> $answers
     * @return array{0:string,1:?string}
     */
    private function written(?string $existing, array $answers): array
    {
        [$status, $output, $written] = $this->wizard($existing, $answers);
        self::assertSame(0, $status, $output);
        preg_match('/^APP_ENV=(.*)$/m', $written, $env);
        $debug = preg_match('/^APP_DEBUG=(.*)$/m', $written, $line) === 1 ? trim($line[1], '"\'') : null;
        return [trim($env[1] ?? '', '"\''), $debug];
    }

    /**
     * Runs the wizard unattended: the settings it needs answered, stdin empty.
     *
     * @param array<string,string> $answers
     * @return array{0:int,1:string,2:string}
     */
    private function wizard(?string $existing, array $answers): array
    {
        $root = dirname(__DIR__, 2);
        $given = $answers + [
            'APP_NAME' => 'Wizard Test', 'APP_DOMAIN' => 'wizard.localdomain', 'APP_URL' => 'https://wizard.localdomain',
            'APP_ADMIN_EMAIL' => 'admin@wizard.localdomain', 'DB_HOST' => '127.0.0.1', 'DB_NAME' => 'wizard_test', 'DB_USER' => 'wizard_test',
            'DB_PASSWORD' => 'not-a-real-password', 'MAILER_DSN' => 'smtp://127.0.0.1:25',
            'SITE_OWNER_TRADING_NAME' => 'Wizard Test Learning', 'SITE_OWNER_LEGAL_NAME' => 'Wizard Test Learning (Pty) Ltd',
            'SITE_OWNER_LEGAL_FORM' => 'company', 'SITE_OWNER_ADDRESS' => '1 Test Street, Testville, 0001', 'SITE_OWNER_PHONE' => '012 345 6789',
            'SITE_OWNER_INFORMATION_OFFICER' => 'Test Officer',
        ];
        $answersFile = $this->file(implode("\n", array_map(static fn(string $k, string $v): string => $k . '=' . $v, array_keys($given), $given)) . "\n");
        $output = $this->file('');
        $command = [PHP_BINARY, $root . '/install/env-wizard.php', '--example=' . $root . '/.env.example', '--output=' . $output,
            '--codebase=' . $root, '--mode=demo', '--username=wizardtest', '--answers=' . $answersFile];
        if ($existing !== null) $command[] = '--existing=' . $existing;
        $process = proc_open($command, [0 => ['file', '/dev/null', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes);
        self::assertIsResource($process);
        $text = (string) stream_get_contents($pipes[1]) . (string) stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        $status = proc_close($process);
        return [$status, $text, (string) file_get_contents($output)];
    }

    private function file(string $content): string
    {
        $path = $this->files[] = (string) tempnam(sys_get_temp_dir(), 'wizard');
        file_put_contents($path, $content);
        return $path;
    }
}
