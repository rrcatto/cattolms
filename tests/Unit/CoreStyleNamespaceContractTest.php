<?php

/*
Generated by: Claude Code CLI

Date time: 2026/09/09 14:01 SAST

Version: 0.7

Description:
The cl- namespace contract: a class core emits is a class core has styled.

Core-owned page bodies emit their own cl- prefixed classes, and for a long time nothing checked that
anything defined them. The result was invisible: a page looked correct under whichever theme
happened to ship a rule for the class, and rendered unstyled under the ones that did not. Four of
these were found at once in v0.7 - .cl-narrow and .cl-medium had a width in only two of five themes,
so a sign-in form drew 1320px wide in the other three; .cl-page-head-row and .cl-filter-chip had a
rule in no theme at all, so the compact page header did not form a row and the selected status
filter was distinguishable only by aria-current.

None of that could fail a build, because the markup was valid and the class simply did nothing.

This asserts the property that makes it fail instead: every cl- class emitted by a core-owned view
is styled by core CSS or by the bundled Factory Reset theme. Factory Reset is the recovery theme and
ships inside the code root, so the pair is the floor below which no installation can fall - an
externally installed theme may restyle any of it, but nothing may be left to chance.

The exception list is for classes that deliberately carry no styling: htmx and JavaScript targets,
and wrapper hooks a theme may opt into. Adding to it is a decision to be stated, which is the point
of it being a literal list rather than a pattern.

Changelog:
2026/09/09 14:01 SAST
- Created after four core-owned classes were found unstyled in themes that never defined them.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class CoreStyleNamespaceContractTest extends TestCase
{
    /**
     * Classes that exist to be targeted, not painted.
     *
     * A behaviour hook is named by htmx, by JavaScript or by a theme that chooses to style it; it
     * has no appearance of its own and a core rule for it would be inventing one. Every other cl-
     * class is presentation and belongs in core CSS or the recovery theme.
     *
     * @var list<string>
     */
    private const BEHAVIOUR_HOOKS = [
        'cl-admin-standalone-section',
        'cl-company-picker',
        'cl-company-section',
        'cl-course-head',
        'cl-course-presentation',
        'cl-page-head-compact',
        'cl-rich-editor',
        'cl-section-body',
    ];

    private static function root(): string
    {
        return dirname(__DIR__, 2);
    }

    /** @return list<string> */
    private static function viewFiles(): array
    {
        $found = [];
        $directory = new \RecursiveDirectoryIterator(self::root() . '/resources/views');
        /** @var \SplFileInfo $file */
        foreach (new \RecursiveIteratorIterator($directory) as $file) {
            if ($file->isFile() && str_ends_with($file->getFilename(), '.twig')) {
                $found[] = $file->getPathname();
            }
        }
        sort($found);

        return $found;
    }

    /**
     * Every cl- class named in a class attribute of a core-owned view.
     *
     * Twig expressions inside the attribute are blanked rather than parsed: a class built from a
     * variable is a fragment such as "cl-status-" and naming a fragment would assert nothing.
     *
     * @return array<string,list<string>> class => views that emit it
     */
    private static function emittedClasses(): array
    {
        $emitted = [];
        foreach (self::viewFiles() as $path) {
            $source = (string) file_get_contents($path);
            $source = (string) preg_replace('/\{#.*?#\}/s', '', $source);
            preg_match_all('/class="([^"]*)"/', $source, $matches);
            foreach ($matches[1] as $attribute) {
                $attribute = (string) preg_replace('/\{\{.*?\}\}|\{%.*?%\}/', ' ', $attribute);
                foreach (preg_split('/\s+/', $attribute, -1, PREG_SPLIT_NO_EMPTY) ?: [] as $class) {
                    if (preg_match('/^cl-[a-z0-9-]*[a-z0-9]$/', $class) === 1) {
                        $emitted[$class][] = str_replace(self::root() . '/', '', $path);
                    }
                }
            }
        }
        ksort($emitted);

        return array_map(static fn (array $files): array => array_values(array_unique($files)), $emitted);
    }

    /** @return list<string> */
    private static function styledClasses(): array
    {
        $stylesheets = [
            self::root() . '/public_html/css/catto-platform.css',
            self::root() . '/themes/factory-reset/public/css/theme.css',
        ];
        $styled = [];
        foreach ($stylesheets as $stylesheet) {
            self::assertFileExists($stylesheet);
            // Comments are stripped first. The block explaining this contract names the very
            // classes it protects, so scanning the raw file let a deleted rule keep passing on the
            // strength of the prose describing it.
            $css = (string) preg_replace('#/\*.*?\*/#s', '', (string) file_get_contents($stylesheet));
            preg_match_all('/\.(cl-[a-z0-9-]+)/', $css, $matches);
            $styled = array_merge($styled, $matches[1]);
        }

        return array_values(array_unique($styled));
    }

    /** A guard that finds nothing must fail, so assert the scan actually read the views. */
    public function testTheScanFindsTheCoreOwnedViewsAndTheirClasses(): void
    {
        self::assertGreaterThan(50, count(self::viewFiles()), 'The view scan found almost no templates.');
        self::assertGreaterThan(50, count(self::emittedClasses()), 'The class scan found almost no cl- classes.');
        self::assertGreaterThan(50, count(self::styledClasses()), 'The stylesheet scan found almost no cl- rules.');
    }

    /** The contract itself: nothing core emits is left for an unknown theme to happen to define. */
    public function testEveryEmittedClassIsStyledByCoreOrTheRecoveryTheme(): void
    {
        $styled = self::styledClasses();
        $unstyled = [];
        foreach (self::emittedClasses() as $class => $views) {
            if (in_array($class, $styled, true) || in_array($class, self::BEHAVIOUR_HOOKS, true)) {
                continue;
            }
            $unstyled[] = sprintf('%s (in %s)', $class, implode(', ', $views));
        }

        self::assertSame([], $unstyled, sprintf(
            "These core-owned classes are styled by neither core CSS nor the bundled Factory Reset theme,\n"
            . "so they render as whatever the active theme happens to define and as nothing at all under a\n"
            . "theme that does not. Add a rule to public_html/css/catto-platform.css, or declare the class a\n"
            . "behaviour hook in BEHAVIOUR_HOOKS and say why:\n  %s",
            implode("\n  ", $unstyled)
        ));
    }

    /** An exception that no longer applies is a stale exception, and hides the next real gap. */
    public function testEveryDeclaredBehaviourHookIsStillEmittedAndStillUnstyled(): void
    {
        $emitted = self::emittedClasses();
        $styled = self::styledClasses();
        foreach (self::BEHAVIOUR_HOOKS as $hook) {
            self::assertArrayHasKey($hook, $emitted, sprintf(
                'BEHAVIOUR_HOOKS names %s, which no core view emits any more. Remove it.',
                $hook
            ));
            self::assertNotContains($hook, $styled, sprintf(
                'BEHAVIOUR_HOOKS names %s, but core or Factory Reset now styles it. Remove the exception.',
                $hook
            ));
        }
    }
}
