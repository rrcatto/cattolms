declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Auth\AdultAge;
use DateTimeImmutable;
use PHPUnit\Framework\TestCase;

final class AdultAgeTest extends TestCase
{
    public function testUnder18IsByTheDateOfBirthOnTheDay(): void
    {
        $today = new DateTimeImmutable('2026-10-19 15:00');
        self::assertTrue(AdultAge::under18('2008-10-20', $today), 'Turns 18 tomorrow.');
        self::assertFalse(AdultAge::under18('2008-10-19', $today), 'Turns 18 today.');
        self::assertFalse(AdultAge::under18('1990-01-01', $today));
        self::assertFalse(AdultAge::under18(null, $today), 'No date of birth is not under 18.');
    }
}
