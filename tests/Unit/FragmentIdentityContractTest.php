Description:
A fragment is rendered with the same identity and capability values as a page.

An htmx swap returns a fragment: the section body, not the whole document. It includes exactly the
same partials the page does, and those partials hide controls behind `can_*` flags. The fragment
path supplied four scalars - csrf, app_name, app_url and current_uri - and none of the flags, so
every swap of an Administration list died on "Undefined variable $can_manage_people", returned 500,
and htmx swapped the error page into the results region.

It survived everything:

  - HttpRouteSmokeTest issues ordinary GET requests, and paging by URL works, because that path
    renders a page.
  - The render smoke tests build their own hive through RenderHarness, which supplies the flags. The
    partial renders correctly there and fails in production, which is the worst kind of green.

So the contract is asserted where the defect was: both render paths pass their data through the same
method, and that method is the one that defines the flags.

Changelog:
2026/09/08 SAST
- Created after every htmx swap of a paginated Administration list was found returning 500.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class FragmentIdentityContractTest extends TestCase
{
    private static function source(): string
    {
        return (string) file_get_contents(dirname(__DIR__, 2) . '/src/Http/Controller/BaseController.php');
    }

    /** One method defines the identity and capability values, and both render paths call it. */
    public function testBothRenderPathsApplyTheSameIdentityBlock(): void
    {
        $source = self::source();

        self::assertStringContainsString(
            'protected function viewIdentity(array $data): array',
            $source,
            'The shared identity block must exist as one method.'
        );

        foreach ([
            'protected function render(string $page, array $data = [], int $status = 200): Response',
            'protected function renderFragment(string $template, array $data = [], int $status = 200): Response',
        ] as $signature) {
            $at = strpos($source, $signature);
            self::assertIsInt($at, $signature . ' must exist.');

            $body = substr($source, $at, 900);
            self::assertStringContainsString(
                '$data = $this->viewIdentity($data);',
                $body,
                'A fragment includes the same partials as a page, so it needs the same flags: '
                . $signature
            );
        }
    }

    /**
     * The capability flags are defined only inside that method.
     *
     * A flag assigned anywhere else in the controller would reach one path and not the other, which
     * is the shape of the original defect.
     */
    public function testCapabilityFlagsAreDefinedOnlyInTheSharedBlock(): void
    {
        $source = self::source();
        $at = strpos($source, 'protected function viewIdentity(array $data): array');
        self::assertIsInt($at);
        $end = strpos($source, 'protected function render(string $page', $at);
        self::assertIsInt($end);

        $shared = substr($source, $at, $end - $at);
        $elsewhere = substr($source, 0, $at) . substr($source, $end);

        self::assertGreaterThan(
            10,
            preg_match_all("/'can_[a-z_]+' =>/", $shared),
            'The shared block is where the capability flags live.'
        );
        self::assertSame(
            0,
            preg_match_all("/\\\$data\['can_[a-z_]+'\] =/", $elsewhere),
            'A capability flag assigned outside the shared block reaches one render path only.'
        );
    }
}
