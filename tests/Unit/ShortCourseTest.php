declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Course\AssessmentService;
use CattoLearning\Course\Catwalk\SlideDeck;
use CattoLearning\Course\Catwalk\SlideLayouts;
use CattoLearning\Course\LegacyHtmlCourseImporter;
use CattoLearning\Tests\Support\ShortCourseExample;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class ShortCourseTest extends TestCase
{
    public function testTheSlideLimitsDependOnTheCourseTypeInOnePlace(): void
    {
        self::assertSame([[8, 12], [5, 9], [5, 8], [4, 6]], [SlideLayouts::slides('trailer'), SlideLayouts::slides('intro'), SlideLayouts::slides('trailer', 'short'), SlideLayouts::slides('intro', 'short')]);
        self::assertSame([8, 15], SlideLayouts::slides('review', 'short'), 'Kinds a short course has no size of its own for keep a full course\'s.');
        $preview = SlideDeck::validate(['kind' => 'trailer'] + ShortCourseExample::TRAILER, 'short');
        self::assertSame([], array_values(array_filter(SlideDeck::warnings($preview, 'short'), static fn(string $warning): bool => str_contains($warning, 'slides'))), 'Six slides suit a short course\'s preview.');
        self::assertContains('A course trailer usually has 8 to 12 slides. This one has 6.', SlideDeck::warnings($preview), 'The same six are short for a full course\'s.');
        $opening = ['kind' => 'intro', 'slides' => [
            ['layout' => 'title', 'title' => 'Welcome', 'heading' => 'Start here'],
            ['layout' => 'points', 'title' => 'You will', 'heading' => 'Be able to', 'points' => ['One thing', 'Another']],
            ['layout' => 'check', 'title' => 'A question', 'question' => 'Ready?', 'options' => ['Yes', 'No'], 'answer' => 0, 'explanation' => 'Good.'],
            ['layout' => 'next', 'title' => 'Up next', 'heading' => 'The video', 'text' => 'Watch for the three steps.'],
        ]];
        $opening = SlideDeck::validate($opening, 'short');
        self::assertSame([], SlideDeck::warnings($opening, 'short'), 'Four slides suit a short course\'s module.');
        self::assertContains('A module opening usually has 5 to 9 slides. This one has 4.', SlideDeck::warnings($opening));
        self::assertContains('A module opening in a short course usually has 4 to 6 slides. This one has 9.', SlideDeck::warnings(['slides' => array_merge(array_fill(0, 8, $opening['slides'][1]), [$opening['slides'][3]])] + $opening, 'short'));
    }

    public function testAShortCoursesPreviewOffersGettingTheCourseAlone(): void
    {
        $deck = ShortCourseExample::TRAILER;
        $deck['slides'][5]['actions'] = ['enrol', 'preview'];
        self::assertSame(['enrol', 'preview'], SlideDeck::validate(['kind' => 'trailer'] + $deck)['slides'][5]['actions'], 'A full course\'s preview may also offer a look at a module.');
        $this->expectException(InvalidArgumentException::class);
        $this->expectExceptionMessage('a short course\'s preview offers getting the course alone, so its only button is Get this course.');
        SlideDeck::validate(['kind' => 'trailer'] + $deck, 'short');
    }

    public function testAShortCourseImportsWithItsTypeAndMinutesAndNoWarnings(): void
    {
        $analysis = (new LegacyHtmlCourseImporter())->analyse(ShortCourseExample::html(), 'short.html');
        self::assertSame([], $analysis['warnings'], 'A short course written to section 15 gives no warning, and no "No final assessment was detected".');
        self::assertSame(['short', 75, 1, null], [$analysis['course']['course_type'], $analysis['course']['estimated_minutes'], $analysis['course']['first_module_number'], $analysis['final_assessment']]);
        self::assertCount(1, $analysis['modules']);
        self::assertCount(6, $analysis['trailer']['type_config']['slides'] ?? []);
        $full = (new LegacyHtmlCourseImporter())->analyse(ShortCourseExample::html(['type' => 'full', 'minutes' => null, 'hours' => 2, 'keep_final' => true, 'grading' => 'Your module assessments count for half of your final mark and the final assessment for the other half.']), 'full.html');
        self::assertSame(['full', 120], [$full['course']['course_type'], $full['course']['estimated_minutes']], 'Written "full", it is a full course timed in hours.');
        self::assertNotNull($full['final_assessment']);
        $silent = (new LegacyHtmlCourseImporter())->analyse(ShortCourseExample::html(['type' => '', 'minutes' => null, 'keep_final' => true, 'grading' => 'Your module assessments count for half of your final mark and the final assessment for the other half.']), 'plain.html');
        self::assertSame('full', $silent['course']['course_type'], 'A course without the course-type line is a full course.');
    }

    public function testEverythingSection157ListsIsAWarning(): void
    {
        $warnings = (new LegacyHtmlCourseImporter())->analyse(ShortCourseExample::html(['keep_final' => true, 'hours' => 2, 'final_limit' => 60, 'minutes' => 150, 'trailer' => false, 'grading' => 'Your module assessments count for half of your final mark and the final assessment for the other half.']), 'drift.html')['warnings'];
        foreach ([
            'does not say how a short course is graded in the specification\'s words',
            'A short course\'s one assessment makes the whole mark',
            'It also has QUIZ.final',
            'never also has cattolms:study-hours',
            'it has no cattolms:final-time-limit',
            'cattolms:study-minutes says 150 minutes. A short course takes 60 to 120',
            'A short course must have a course preview',
        ] as $expected) {
            self::assertNotSame([], array_filter($warnings, static fn(string $warning): bool => str_contains($warning, $expected)), 'Warned: ' . $expected);
        }
        self::assertSame([], array_filter($warnings, static fn(string $warning): bool => str_contains($warning, 'No final assessment') || str_contains($warning, 'other than 50%')), 'Nothing a full course is told.');
        $missing = (new LegacyHtmlCourseImporter())->analyse(ShortCourseExample::html(['minutes' => null]), 'nominutes.html')['warnings'];
        self::assertContains('A short course states how long it takes in cattolms:study-minutes, 60 to 120 (specification, section 15.1).', $missing);
    }

    public function testAShortCoursesResultIsItsAssessmentsScore(): void
    {
        self::assertSame(['module' => 64.0, 'overall' => 64.0], AssessmentService::courseFigures([64.0], null));
        self::assertSame(['module' => 80.0, 'overall' => 70.0], AssessmentService::courseFigures([80.0], 60.0), 'A full course stays half and half.');
    }
}
