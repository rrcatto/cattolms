declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Course\CourseStyles;
use PHPUnit\Framework\TestCase;

final class CourseStylesTest extends TestCase
{
    private const G = CourseStyles::GUARD;

    public function testEverySelectorKeepsAwayFromThePlayer(): void
    {
        self::assertSame('.cl-course-presentation h3' . self::G . ' {color:red}', CourseStyles::forReader('.cl-course-presentation h3{color:red}'));
        self::assertSame('.cl-course-presentation' . self::G . ', .cl-course-presentation *' . self::G . ' {margin:0}', CourseStyles::forReader('.cl-course-presentation, .cl-course-presentation *{margin:0}'));
    }

    public function testTheGuardGoesBeforeAPseudoElement(): void
    {
        self::assertSame('.tip' . self::G . '::before', CourseStyles::guard('.tip::before'));
        self::assertSame('li' . self::G . ':after', CourseStyles::guard('li:after'));
        self::assertSame('a:hover' . self::G, CourseStyles::guard('a:hover'), 'A pseudo-class is part of the subject.');
        self::assertSame('p:first-child' . self::G . '::first-line', CourseStyles::guard('p:first-child::first-line'));
    }

    public function testCommasInBracketsAndStringsDoNotSplitASelector(): void
    {
        self::assertSame('p:not(.a, .b)' . self::G . ', [data-x="a,b"]' . self::G . ' {x:y}', CourseStyles::forReader('p:not(.a, .b), [data-x="a,b"]{x:y}'));
    }

    public function testGroupedRulesAreGuardedAndOtherAtRulesKept(): void
    {
        $css = "@import url(\"https://fonts.googleapis.com/css2?family=Inter:wght@400;700&display=swap\");\n"
            . "/* the frame */\n@font-face{font-family:X;src:url(x.woff2)}\n@keyframes fade{from{opacity:0}to{opacity:1}}\n"
            . "@media (max-width:600px){.cl-course-presentation table{font-size:.9rem}}\n@supports (display:grid){.grid{display:grid}}";
        $out = CourseStyles::forReader($css);
        self::assertStringContainsString('@import url("https://fonts.googleapis.com/css2?family=Inter:wght@400;700&display=swap");', $out);
        self::assertStringContainsString('/* the frame */', $out);
        self::assertStringContainsString('@font-face{font-family:X;src:url(x.woff2)}', $out);
        self::assertStringContainsString('@keyframes fade{from{opacity:0}to{opacity:1}}', $out, 'Keyframe steps are not selectors.');
        self::assertStringContainsString('@media (max-width:600px){.cl-course-presentation table' . self::G . ' {font-size:.9rem}}', $out);
        self::assertStringContainsString('@supports (display:grid){.grid' . self::G . ' {display:grid}}', $out);
        self::assertSame($out, CourseStyles::forReader($out), 'A stylesheet already guarded is left as it is.');
    }
}
