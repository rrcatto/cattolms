declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Course\CoursePageLayout;
use CattoLearning\Course\CoursePageLayouts;
use PHPUnit\Framework\TestCase;

final class CoursePageLayoutTest extends TestCase
{
    public function testTheStartingArrangementHoldsEveryBlockOnceAndShowsThemAll(): void
    {
        $starting = CoursePageLayout::starting();
        $ids = array_column($starting, 'id');
        sort($ids);
        $all = array_keys(CoursePageLayout::BLOCKS);
        sort($all);
        self::assertSame($all, $ids);
        self::assertSame($starting, CoursePageLayout::normalise($starting));
        self::assertNotContains(false, array_column($starting, 'shown'));
        // Every block that may be left out says why.
        self::assertSame([], array_diff(array_keys(CoursePageLayout::LEFT_OUT), array_keys(CoursePageLayout::BLOCKS)));
    }

    public function testALayoutIsMadeWhole(): void
    {
        $layout = CoursePageLayout::normalise([
            ['id' => 'access', 'width' => 'half', 'shown' => false],
            ['id' => 'about', 'width' => 'sideways', 'shown' => true],
            ['id' => 'about', 'width' => 'half', 'shown' => false],
            ['id' => 'banner', 'width' => 'full', 'shown' => true],
            'not a block',
            ['id' => 'reviews', 'width' => 'full', 'shown' => false],
        ]);
        // A missing block follows its neighbour in the default wherever that now is: Ready to start after Course access.
        self::assertSame(['access', 'start', 'related', 'about', 'how', 'modules', 'glance', 'get', 'reviews'], array_column($layout, 'id'));
        self::assertSame(['id' => 'access', 'width' => 'half', 'shown' => true], $layout[0], 'Course access is always shown.');
        self::assertSame(['id' => 'about', 'width' => 'full', 'shown' => true], $layout[3], 'The first of a repeated block counts, an unknown width is full.');
        self::assertSame(['id' => 'how', 'width' => 'half', 'shown' => true], $layout[4], 'A missing block comes with its default width, shown.');
        self::assertFalse($layout[8]['shown']);
        self::assertSame(CoursePageLayout::starting(), CoursePageLayout::normalise(null));
        self::assertSame(CoursePageLayout::starting(), CoursePageLayout::normalise('[]'));
    }

    public function testTheArrowsSkipHiddenBlocks(): void
    {
        $layout = CoursePageLayout::starting();
        $layout[5]['shown'] = false; // reviews
        $moved = CoursePageLayout::move($layout, 'access', 'up');
        self::assertSame(['about', 'how', 'modules', 'glance', 'access', 'get', 'reviews', 'start', 'related'], array_column($moved, 'id'));
        self::assertSame($layout, CoursePageLayout::move($layout, 'about', 'up'), 'The first block stays.');
        self::assertSame($layout, CoursePageLayout::move($layout, 'related', 'down'), 'The last block stays.');
        self::assertSame($layout, CoursePageLayout::move($layout, 'banner', 'down'));
    }

    public function testRowsPairHalfBlocksAndLeaveOutWhatHasNothingToShow(): void
    {
        $all = array_keys(CoursePageLayout::BLOCKS);
        $rows = CoursePageLayout::rows(CoursePageLayout::starting(), $all);
        self::assertSame([['about', 'how'], ['modules'], ['glance', 'get'], ['reviews'], ['access'], ['start'], ['related']],
            array_map(static fn(array $row): array => array_column($row, 'id'), $rows));

        // Without How each module works, About this course has half a row of its own; a hidden block is never drawn.
        $layout = CoursePageLayout::starting();
        $layout[3]['shown'] = false; // glance
        $rows = CoursePageLayout::rows($layout, array_values(array_diff($all, ['how', 'reviews'])));
        self::assertSame([['about'], ['modules'], ['get'], ['access'], ['start'], ['related']], array_map(static fn(array $row): array => array_column($row, 'id'), $rows));
        self::assertSame('half', $rows[0][0]['width']);

        // A half block after a full one starts a new row.
        $buyFirst = CoursePageLayout::normalise(array_map(static fn(array $block): array => ['id' => $block[0], 'width' => $block[1], 'shown' => true],
            [['access', 'full'], ['about', 'half'], ['glance', 'half'], ['modules', 'full'], ['how', 'half'], ['get', 'half'], ['reviews', 'full'], ['start', 'full'], ['related', 'full']]));
        $rows = CoursePageLayout::rows($buyFirst, $all);
        self::assertSame([['access'], ['about', 'glance'], ['modules'], ['how', 'get'], ['reviews'], ['start'], ['related']], array_map(static fn(array $row): array => array_column($row, 'id'), $rows));
    }

    public function testTheBuildersFormAsksForEachAction(): void
    {
        $form = ['order' => 'about,how,modules,glance,get,reviews,access,start,related', 'width' => ['about' => 'full', 'how' => 'half'], 'shown' => ['about' => '1', 'how' => '1', 'modules' => '1', 'reviews' => '0', 'access' => '0']];
        [$layout, $action] = CoursePageLayouts::fromForm($form);
        self::assertSame('save', $action);
        self::assertSame(['id' => 'about', 'width' => 'full', 'shown' => true], $layout[0]);
        self::assertFalse($layout[5]['shown'], 'Reviews unticked.');
        self::assertTrue($layout[6]['shown'], 'Course access shown whatever the form says.');
        self::assertSame('full', $layout[3]['width'], 'A width the form lacks is full.');

        self::assertSame([$layout, 'start:4'], CoursePageLayouts::fromForm($form + ['action' => 'start', 'start_from' => '4']), 'Start again from names the layout to copy in.');
        [$moved, $action] = CoursePageLayouts::fromForm($form + ['action' => 'move:how:up']);
        self::assertSame(['move', ['how', 'about']], [$action, array_slice(array_column($moved, 'id'), 0, 2)]);
        [$shown, $action] = CoursePageLayouts::fromForm($form + ['action' => 'show:reviews']);
        self::assertSame(['show', true], [$action, $shown[5]['shown']]);
        [$hidden, $action] = CoursePageLayouts::fromForm($form + ['action' => 'hide:access']);
        self::assertSame(['hide', true], [$action, $hidden[6]['shown']], 'Course access cannot be hidden.');
        self::assertSame('save', CoursePageLayouts::fromForm($form + ['action' => 'reset'])[1], 'Reset is gone: Start again from replaced it.');
        self::assertSame('save', CoursePageLayouts::fromForm($form + ['action' => 'anything'])[1]);
    }

    public function testTheBuilderAndTheSmallDrawing(): void
    {
        $layout = CoursePageLayout::starting();
        $layout[1]['shown'] = false; // how
        $builder = CoursePageLayouts::builder($layout);
        self::assertSame('about,how,modules,glance,get,reviews,access,start,related', $builder['order']);
        self::assertTrue($builder['blocks'][6]['required'], 'Course access is required.');
        self::assertSame('How each module works', $builder['blocks'][1]['name']);
        self::assertNotContains('how', array_column(CoursePageLayouts::cells($layout), 'id'), 'A layout drawn small shows only its shown blocks.');
    }

    public function testWhatACoursesPageLeavesOutAndWhy(): void
    {
        $everything = ['modules' => 6, 'figures' => 3, 'reviews' => 2, 'preview' => true, 'related' => 1];
        self::assertSame(array_keys(CoursePageLayout::BLOCKS), array_values(array_intersect(array_keys(CoursePageLayout::BLOCKS), CoursePageLayout::present($everything))));
        // A course with no review, no free preview and nothing related: those three are left out, in the layout's order.
        $bare = ['modules' => 6, 'figures' => 3, 'reviews' => 0, 'preview' => false, 'related' => 0];
        self::assertSame(['about', 'how', 'modules', 'glance', 'get', 'access'], CoursePageLayout::present($bare));
        self::assertSame([['id' => 'reviews', 'name' => 'Reviews', 'reason' => 'no approved review'], ['id' => 'start', 'name' => 'Ready to start', 'reason' => 'no free preview'], ['id' => 'related', 'name' => 'Related courses', 'reason' => 'no related course']],
            CoursePageLayout::leftOut(CoursePageLayout::starting(), $bare));
        // A block hidden in the layout is not left out: it was never on the page.
        $layout = CoursePageLayout::starting();
        $layout[7]['shown'] = false; // start
        self::assertSame(['reviews', 'related'], array_column(CoursePageLayout::leftOut($layout, $bare), 'id'));
        // Someone who owns the course is not offered its free preview again.
        self::assertNotContains('start', CoursePageLayout::present(['owned' => true] + $everything));
        // No modules: no How each module works; nothing counted: no What you get.
        self::assertSame(['how', 'get'], array_column(CoursePageLayout::leftOut(CoursePageLayout::starting(), ['modules' => 0, 'figures' => 0] + $everything), 'id'));
    }

    public function testTheSketchDrawsWhatTheCourseShows(): void
    {
        $layout = CoursePageLayout::starting();
        $layout[0]['shown'] = false; // about
        $sketch = CoursePageLayouts::sketch($layout, ['how', 'modules', 'glance', 'get', 'access', 'start', 'related']);
        self::assertSame(['how', 'modules', 'glance', 'get', 'access', 'start', 'related'], array_column(array_filter($sketch['cells'], static fn(array $cell): bool => $cell['drawn']), 'id'));
        self::assertSame(['reviews'], array_column($sketch['left_out'], 'id'), 'Only a shown block is left out: About this course is hidden in the layout.');
        self::assertSame('no approved review', $sketch['left_out'][0]['reason']);
        self::assertSame(array_keys(CoursePageLayout::BLOCKS), array_values(array_intersect(array_keys(CoursePageLayout::BLOCKS), array_column($sketch['cells'], 'id'))), 'Every block has a cell, to draw when it is shown.');
    }

    public function testBlockWordsHaveNoSemicolons(): void
    {
        foreach (CoursePageLayout::BLOCKS + CoursePageLayout::LEFT_OUT as $words) {
            foreach ((array) $words as $text) {
                self::assertStringNotContainsString(';', $text);
            }
        }
    }
