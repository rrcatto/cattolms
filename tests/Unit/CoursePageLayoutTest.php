declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Course\CoursePageLayout;
use CattoLearning\Course\CoursePageLayouts;
use PHPUnit\Framework\TestCase;

final class CoursePageLayoutTest extends TestCase
{
    public function testEveryTemplateHoldsEveryBlockOnceAndShowsThemAll(): void
    {
        foreach (array_keys(CoursePageLayout::TEMPLATES) as $name) {
            $template = CoursePageLayout::template($name);
            $ids = array_column($template, 'id');
            sort($ids);
            $all = array_keys(CoursePageLayout::BLOCKS);
            sort($all);
            self::assertSame($all, $ids, $name);
            self::assertSame($template, CoursePageLayout::normalise($template), $name);
            self::assertNotContains(false, array_column($template, 'shown'), $name);
            self::assertArrayHasKey($name, CoursePageLayout::TEMPLATE_NAMES);
            self::assertArrayHasKey($name, CoursePageLayout::TEMPLATE_NOTES);
        }
        // An unknown template is Course first.
        self::assertSame(CoursePageLayout::template('course'), CoursePageLayout::template('nothing'));
    }

    public function testALayoutIsMadeWhole(): void
    {
        $layout = CoursePageLayout::normalise([
            ['id' => 'access', 'width' => 'half', 'shown' => false],
            ['id' => 'about', 'width' => 'sideways', 'shown' => true],
            ['id' => 'about', 'width' => 'half', 'shown' => false],
            ['id' => 'banner', 'width' => 'full', 'shown' => true],
            'not a block',
            ['id' => 'reviews', 'width' => 'full', 'shown' => false],
        ]);
        // A missing block follows its neighbour in the default wherever that now is: Ready to start after Course access.
        self::assertSame(['access', 'start', 'related', 'about', 'how', 'modules', 'glance', 'get', 'reviews'], array_column($layout, 'id'));
        self::assertSame(['id' => 'access', 'width' => 'half', 'shown' => true], $layout[0], 'Course access is always shown.');
        self::assertSame(['id' => 'about', 'width' => 'full', 'shown' => true], $layout[3], 'The first of a repeated block counts, an unknown width is full.');
        self::assertSame(['id' => 'how', 'width' => 'half', 'shown' => true], $layout[4], 'A missing block comes with its default width, shown.');
        self::assertFalse($layout[8]['shown']);
        self::assertSame(CoursePageLayout::template('course'), CoursePageLayout::normalise(null));
        self::assertSame(CoursePageLayout::template('course'), CoursePageLayout::normalise('[]'));
    }

    public function testTheArrowsSkipHiddenBlocks(): void
    {
        $layout = CoursePageLayout::template('course');
        $layout[5]['shown'] = false; // reviews
        $moved = CoursePageLayout::move($layout, 'access', 'up');
        self::assertSame(['about', 'how', 'modules', 'glance', 'access', 'get', 'reviews', 'start', 'related'], array_column($moved, 'id'));
        self::assertSame($layout, CoursePageLayout::move($layout, 'about', 'up'), 'The first block stays.');
        self::assertSame($layout, CoursePageLayout::move($layout, 'related', 'down'), 'The last block stays.');
        self::assertSame($layout, CoursePageLayout::move($layout, 'banner', 'down'));
    }

    public function testRowsPairHalfBlocksAndLeaveOutWhatHasNothingToShow(): void
    {
        $all = array_keys(CoursePageLayout::BLOCKS);
        $rows = CoursePageLayout::rows(CoursePageLayout::template('course'), $all);
        self::assertSame([['about', 'how'], ['modules'], ['glance', 'get'], ['reviews'], ['access'], ['start'], ['related']],
            array_map(static fn(array $row): array => array_column($row, 'id'), $rows));

        // Without How each module works, About this course has half a row of its own; a hidden block is never drawn.
        $layout = CoursePageLayout::template('course');
        $layout[3]['shown'] = false; // glance
        $rows = CoursePageLayout::rows($layout, array_values(array_diff($all, ['how', 'reviews'])));
        self::assertSame([['about'], ['modules'], ['get'], ['access'], ['start'], ['related']], array_map(static fn(array $row): array => array_column($row, 'id'), $rows));
        self::assertSame('half', $rows[0][0]['width']);

        // A half block after a full one starts a new row.
        $rows = CoursePageLayout::rows(CoursePageLayout::template('buy'), $all);
        self::assertSame([['access'], ['about', 'glance'], ['modules'], ['how', 'get'], ['reviews'], ['start'], ['related']], array_map(static fn(array $row): array => array_column($row, 'id'), $rows));
    }

    public function testTheBuildersFormAsksForEachAction(): void
    {
        $form = ['order' => 'about,how,modules,glance,get,reviews,access,start,related', 'width' => ['about' => 'full', 'how' => 'half'], 'shown' => ['about' => '1', 'how' => '1', 'modules' => '1', 'reviews' => '0', 'access' => '0']];
        [$layout, $action] = CoursePageLayouts::fromForm($form);
        self::assertSame('save', $action);
        self::assertSame(['id' => 'about', 'width' => 'full', 'shown' => true], $layout[0]);
        self::assertFalse($layout[5]['shown'], 'Reviews unticked.');
        self::assertTrue($layout[6]['shown'], 'Course access shown whatever the form says.');
        self::assertSame('full', $layout[3]['width'], 'A width the form lacks is full.');

        self::assertSame([CoursePageLayout::template('reviews'), 'template'], CoursePageLayouts::fromForm($form + ['action' => 'template:reviews']));
        [$moved, $action] = CoursePageLayouts::fromForm($form + ['action' => 'move:how:up']);
        self::assertSame(['move', ['how', 'about']], [$action, array_slice(array_column($moved, 'id'), 0, 2)]);
        [$shown, $action] = CoursePageLayouts::fromForm($form + ['action' => 'show:reviews']);
        self::assertSame(['show', true], [$action, $shown[5]['shown']]);
        [$hidden, $action] = CoursePageLayouts::fromForm($form + ['action' => 'hide:access']);
        self::assertSame(['hide', true], [$action, $hidden[6]['shown']], 'Course access cannot be hidden.');
        self::assertSame('reset', CoursePageLayouts::fromForm($form + ['action' => 'reset'])[1]);
        self::assertSame('save', CoursePageLayouts::fromForm($form + ['action' => 'anything'])[1]);
    }

    public function testTheBuilderShowsWhichTemplateIsInUse(): void
    {
        $builder = CoursePageLayouts::builder(CoursePageLayout::template('buy'));
        self::assertSame(['course' => false, 'buy' => true, 'reviews' => false], array_column($builder['templates'], 'current', 'key'));
        self::assertSame('access,about,glance,modules,how,get,reviews,start,related', $builder['order']);
        self::assertTrue($builder['blocks'][0]['required']);
        self::assertSame(CoursePageLayout::template('reviews'), json_decode($builder['templates_json'], true)['reviews']);
    }

    public function testBlockWordsHaveNoSemicolons(): void
    {
        foreach (CoursePageLayout::BLOCKS + CoursePageLayout::TEMPLATE_NOTES as $words) {
            foreach ((array) $words as $text) {
                self::assertStringNotContainsString(';', $text);
            }
        }
    }
}
