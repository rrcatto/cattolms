    public function testWhereAPaymentStandsIsWhatStitchSays(): void
    {
        $attempt = ['id' => '0b6f6a1e-1111-4f3b-9c8d-7e6f5a4b3c2d', 'checkout_reference' => 'pl_7xQ2', 'amount_minor' => 120000, 'currency' => 'ZAR'];
        $site = $this->site([self::link('PAID', 'pay_9kL1'), self::link('PENDING'), self::link('EXPIRED'), self::link('CANCELLED'), [503, ['success' => false]]]);
        $stitch = $site->stitch();

        $paid = $stitch->check($attempt);
        self::assertNotNull($paid);
        self::assertSame('paid', $paid->state);
        self::assertSame('pay_9kL1', $paid->providerReference);
        self::assertSame(120000, $paid->amount->minorUnits);
        self::assertSame('https://express.stitch.money/api/v1/payment-links/pl_7xQ2', $this->sent[1]['url']);
        foreach (['pending' => 'Waiting for the payment.', 'failed' => 'The payment link expired before it was paid.', 'failed ' => 'The payment link was cancelled.'] as $state => $message) {
            $result = $stitch->check($attempt);
            self::assertNotNull($result);
            self::assertSame([trim($state), $message], [$result->state, $result->message]);
        }
        self::assertNull($stitch->check($attempt), 'Stitch not answering is asked again later.');
        self::assertNull($stitch->check(['checkout_reference' => ''] + $attempt), 'A payment with no link is not asked about.');
    }

    public function testAPaymentPaidWebhookIsReadOnlyWhenSignedByStitch(): void
    {
        $site = $this->site([], self::KEYS + ['STITCH_WEBHOOK_SECRET' => self::WEBHOOK_SECRET]);
        $body = '{"id":"pay_9kL1","status":"PAID","amount":120000,"type":"LINK","linkId":"pl_7xQ2","consentId":null,"subscriptionId":null,"terminalSessionId":null}';
        $site->requests->push($this->delivery($body, self::WEBHOOK_SECRET));
        self::assertSame(['link' => 'pl_7xQ2', 'payment' => 'pay_9kL1', 'amount' => 120000, 'delivery' => 'msg_2rTxwk'], $site->stitch()->notification());

        $site->requests->push($this->delivery(str_replace('"LINK","linkId":"pl_7xQ2"', '"TERMINAL","linkId":null,"x":"pl_7xQ2"', $body), self::WEBHOOK_SECRET));
        self::assertNull($site->stitch()->notification(), 'Only payment links are this site\'s.');

        $site->requests->push($this->delivery($body, 'whsec_' . base64_encode('someone else')));
        $this->expectException(InvalidRequestException::class);
        $site->stitch()->notification();
    }

