    private function delivery(string $body, string $secret): Request
    {
        $request = Request::create('https://learning.example.com/webhooks/stitch', 'POST', [], [], [], ['CONTENT_TYPE' => 'application/json'], $body);
        $request->headers->set('svix-id', 'msg_2rTxwk');
        $request->headers->set('svix-timestamp', (string) time());
        $request->headers->set('svix-signature', WebhookSignature::sign($secret, 'msg_2rTxwk', (string) time(), $body));

        return $request;
    }
