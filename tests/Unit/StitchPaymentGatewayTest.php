    public function testTheSettingsSectionSavesOverEnvKeepsTheWebhooksSecretAndResets(): void
    {
        $site = $this->site([
            [200, ['success' => true, 'data' => ['redirectUrls' => []]]],
            [200, ['success' => true, 'data' => ['secret' => self::WEBHOOK_SECRET]]],
        ], ['STITCH_CLIENT_ID' => 'test-from-env', 'STITCH_CLIENT_SECRET' => 'secret-from-env']);
        $audit = (new \ReflectionClass(AuditRepository::class))->newInstanceWithoutConstructor();
        $cards = new CardPaymentSettings($site->settings, $site->stitch(), SiteMode::fixed(SiteMode::DEMO), $audit);

        $view = $cards->view();
        self::assertSame('Test mode', $view['state']);
        self::assertSame(['client_id' => 'env', 'client_secret' => 'env', 'webhook_secret' => 'none'], $view['sources']);
        self::assertSame('https://learning.example.com/webhooks/stitch', $view['webhook_address']);

        self::assertNull($cards->save(['client_id' => 'test-typed-here', 'client_secret' => '', 'webhook_secret' => ''], 0), 'Stitch accepts them.');
        self::assertSame('test-typed-here', $site->settings->get('STITCH_CLIENT_ID'));
        self::assertSame('secret-from-env', $site->settings->get('STITCH_CLIENT_SECRET'), 'A secret left blank is kept.');
        self::assertSame('saved', $cards->view()['sources']['client_id']);

        $site->settings->set('STITCH_WEBHOOK_SECRET', self::WEBHOOK_SECRET);
        self::assertTrue($cards->view()['has_webhook_secret']);
        self::assertNotSame(self::WEBHOOK_SECRET, $site->store->all()['STITCH_WEBHOOK_SECRET']->value, 'Stored encrypted.');

        try {
            $cards->save(['webhook_secret' => 'not-a-secret'], 0);
            self::fail('A webhook secret without whsec_ was saved.');
        } catch (\RuntimeException $refused) {
            self::assertStringContainsString('starts with whsec_', $refused->getMessage());
        }

        $cards->reset(0);
        self::assertSame('test-from-env', $site->settings->get('STITCH_CLIENT_ID'), 'Reset goes back to .env.');
        self::assertFalse($cards->view()['has_webhook_secret']);
    }

