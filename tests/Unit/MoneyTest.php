declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Support\Money;
use PHPUnit\Framework\TestCase;

final class MoneyTest extends TestCase
{
    public function testAnAmountIsHeldInCents(): void
    {
        self::assertSame(123456, Money::ofMinorUnits(123456)->minorUnits);
        self::assertSame('1234.56', Money::ofMinorUnits(123456)->toMajorUnits());
        self::assertSame(123456, Money::ofMajorUnits('1234.56')->minorUnits);
    }

    /**
     * A typed price becomes the cents the person meant.
     *
     * `9.995` is the case that matters and the reason a string is parsed as digits rather than
     * converted to a float: in binary it lands very slightly below 9.995, so a float round gives
     * 999 cents instead of 1000. Nothing errors and the price is simply a cent light.
     */
    public function testATypedAmountBecomesTheCentsThatWereMeant(): void
    {
        self::assertSame(1999, Money::ofMajorUnits('19.99')->minorUnits);
        self::assertSame(1999, Money::ofMajorUnits(19.99)->minorUnits);
        self::assertSame(1000, Money::ofMajorUnits('9.995')->minorUnits, 'A half cent rounds up, not away.');
        self::assertSame(999, Money::ofMajorUnits('9.994')->minorUnits);
        self::assertSame(123456, Money::ofMajorUnits('1234,56')->minorUnits, 'A comma decimal is what a European types.');
        self::assertSame(500, Money::ofMajorUnits('5')->minorUnits);
        self::assertSame(0, Money::ofMajorUnits('0')->minorUnits);
        self::assertSame(0, Money::ofMajorUnits('-3.00')->minorUnits, 'A negative amount is not a price.');
    }

    public function testANegativeAmountIsNotAPrice(): void
    {
        self::assertSame(0, Money::ofMinorUnits(-500)->minorUnits);
        self::assertTrue(Money::ofMinorUnits(-500)->isFree());
    }

    /**
     * Formatting follows the locale, not a hardcoded symbol.
     *
     * Asserted on the parts rather than on the exact string: ICU changes its space characters
     * between versions, and a test that pins a non-breaking space is testing ICU rather than this
     * platform. What must be true is that each locale uses its own symbol and its own separators.
     */
    public function testFormattingFollowsTheLocaleAndTheCurrency(): void
    {
        if (!class_exists(\NumberFormatter::class)) {
            self::markTestSkipped('The intl extension is not loaded.');
        }

        $rand = Money::ofMinorUnits(123456, 'ZAR')->format('en_ZA');
        self::assertStringContainsString('R', $rand);
        self::assertStringContainsString(',56', $rand, 'South Africa separates decimals with a comma.');

        $pounds = Money::ofMinorUnits(123456, 'GBP')->format('en_GB');
        self::assertStringContainsString('£', $pounds);
        self::assertStringContainsString('.56', $pounds, 'The United Kingdom separates decimals with a point.');

        $euros = Money::ofMinorUnits(123456, 'EUR')->format('de_DE');
        self::assertStringContainsString('€', $euros);
        self::assertStringEndsWith('€', trim($euros), 'German puts the symbol last.');
    }

    /** An unusable currency code falls back rather than formatting against nonsense. */
    public function testAnInvalidCurrencyFallsBack(): void
    {
        foreach (['', 'Z', 'ZARR', '123', 'zar!'] as $bad) {
            self::assertSame('ZAR', Money::ofMinorUnits(100, $bad)->currency, $bad . ' is not a currency code.');
        }
        self::assertSame('ZAR', Money::ofMinorUnits(100, 'zar')->currency, 'Case is not part of a currency code.');
    }

    public function testAmountsAddAndMultiply(): void
    {
        $line = Money::ofMinorUnits(2500);
        self::assertSame(7500, $line->times(3)->minorUnits);
        self::assertSame(3000, $line->plus(Money::ofMinorUnits(500))->minorUnits);
        self::assertSame(0, $line->times(-2)->minorUnits, 'A negative quantity is not a quantity.');
    }
}
