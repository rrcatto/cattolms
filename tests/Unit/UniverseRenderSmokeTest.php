Description:
Render-level tests for the genuine-administrator data-universe control.

The disclosure rule for this control is a security rule wearing a user-interface costume: an
ordinary reader must never learn that a second population of records exists, and a seed identity
must never be shown a genuine one. Both halves are decided in PHP, so what is tested here is what
actually reaches the page in each of the five identity and scope combinations - the selector, the
record split, and the absence of both where they are not permitted.

Rendering is the only way to see the other half of it. A partial that reads a variable the
current code path never set is correct markup that still returns 500, which is exactly how
"Undefined variable $courses_pagination" reached the VPS. Every case below therefore renders the
real partial through F3 and fails on any undefined variable.

