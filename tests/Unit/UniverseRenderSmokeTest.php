declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Auth\DataUniverse;
use CattoLearning\Tests\Support\RenderHarness;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

final class UniverseRenderSmokeTest extends TestCase
{
    /**
     * The Administration list families that carry the control, with the dataset each counts.
     *
     * Reports is absent because it counts nothing: its figures are recomputed for the selected
     * universe rather than listed as rows, so it carries the selector alone and is exercised
     * separately below.
     *
     * @return array<string,array{0:string,1:string,2:string}>
     */
    public static function countedFamilies(): array
    {
        return [
            'people' => ['partials/admin/people.html', 'people', '/admin/people'],
            'companies' => ['partials/admin/companies.html', 'companies', '/admin/companies'],
            'courses' => ['partials/admin/courses.html', 'courses', '/admin/courses'],
            'credits' => ['partials/admin/credits.html', 'credits', '/admin/course/credits'],
            'activity' => ['partials/admin/activity.html', 'activity', '/admin/activity'],
            // Two screens with two routes since v0.6, not two tabs on one.
            'requests' => ['partials/admin/requests.html', 'requests', '/admin/course/requests'],
            'enrolments' => ['partials/admin/enrolments.html', 'enrolments', '/admin/course/enrolments'],
        ];
    }

    /**
     * The selector model exactly as PlatformAdministrationService::universeSwitch() builds it.
     *
     * @return array<string,mixed>
     */
    private static function selector(DataUniverse $selected, string $base): array
    {
        $options = [];
        foreach ([DataUniverse::All, DataUniverse::Real, DataUniverse::Seed] as $universe) {
            $options[] = [
                'value' => $universe->value,
                'label' => $universe->label(),
                'short_label' => $universe->shortLabel(),
                'href' => $base . '?universe=' . $universe->value,
                'active' => $universe === $selected,
            ];
        }

        return ['selected' => $selected->value, 'label' => $selected->label(), 'options' => $options];
    }

    /** @return array<string,mixed> */
    private static function counts(string $dataset): array
    {
        return [
            'label' => ucfirst($dataset),
            'total' => 1247, 'real' => 1031, 'seed' => 216,
            'total_display' => '1,247', 'real_display' => '1,031', 'seed_display' => '216',
        ];
    }

    /**
     * A hive for one identity looking at one universe.
     *
     * A genuine administrator receives the selector and the counts; nobody else receives either,
     * because the service builds neither for them. Passing null here is not a shortcut - it is
     * the real payload an ordinary or seed identity gets.
     *
     * @return array<string,mixed>
     */
    private static function hive(string $dataset, string $base, ?DataUniverse $selected): array
    {
        $hive = RenderHarness::baseHive();
        $hive[$dataset . '_pagination'] = RenderHarness::pagination($dataset, $base);
        if ($dataset === 'requests' || $dataset === 'enrolments') {
            $hive['requests_pagination'] = RenderHarness::pagination('requests', $base);
            $hive['enrolments_pagination'] = RenderHarness::pagination('enrolments', $base);
        }

        if ($selected === null) {
            return $hive;
        }

        $hive['universe'] = $selected->value;
        $hive['universe_query'] = '?universe=' . $selected->value;
        $hive['universe_switch'] = self::selector($selected, $base);
        $hive[$dataset . '_universe_counts'] = self::counts($dataset);

        return $hive;
    }

    // --- 1, 2 and 3: genuine ADMIN in Real, Seed and All -------------------------------------

    /** @return list<array{0:DataUniverse}> */
    public static function adminUniverses(): array
    {
        return [[DataUniverse::Real], [DataUniverse::Seed], [DataUniverse::All]];
    }

    /**
     * The selector renders for a genuine administrator, in every scope, on every family.
     */
    #[DataProvider('adminUniverses')]
    public function testGenuineAdminSeesTheSelectorOnEveryListFamily(DataUniverse $selected): void
    {
        foreach (self::countedFamilies() as $key => [$template, $dataset, $base]) {
            $hive = self::hive($dataset, $base, $selected);

            self::assertNull(
                RenderHarness::renderError($template, $hive),
                $template . ' failed to render for a genuine administrator in ' . $selected->value . '.'
            );

            $markup = RenderHarness::render($template, $hive);
            self::assertStringContainsString('class="universe-switch"', $markup, $key . ' must show the selector.');
            foreach (['All', 'Real', 'Seed'] as $choice) {
                self::assertStringContainsString(
                    '>' . $choice . '</a>',
                    $markup,
                    $key . ' must offer the ' . $choice . ' choice.'
                );
            }
        }
    }

    /** Exactly one choice is marked current, and it is the selected one. */
    #[DataProvider('adminUniverses')]
    public function testTheActiveChoiceIsTheSelectedUniverse(DataUniverse $selected): void
    {
        $markup = RenderHarness::render(
            'partials/admin/people.html',
            self::hive('people', '/admin/people', $selected)
        );

        self::assertSame(
            1,
            preg_match_all('/universe-switch-link active/', $markup),
            'Exactly one universe choice may be marked active.'
        );
        self::assertMatchesRegularExpression(
            '/universe-switch-link active[^<>]*universe=' . $selected->value . '"/s',
            $markup,
            'The active choice must be the selected universe.'
        );
        self::assertStringContainsString('aria-current="true"', $markup);
    }

    /** The record split renders, and renders the server's numbers rather than a page count. */
    public function testTheUniverseCountsRenderForAGenuineAdministrator(): void
    {
        foreach (self::countedFamilies() as $key => [$template, $dataset, $base]) {
            $markup = RenderHarness::render($template, self::hive($dataset, $base, DataUniverse::All));

            self::assertStringContainsString('universe-switch-summary', $markup, $key . ' must show the split.');
            foreach (['1,247', '1,031', '216'] as $figure) {
                self::assertStringContainsString($figure, $markup, $key . ' must show ' . $figure . '.');
            }
        }
    }

    /** Reports carries the selector but invents no records total. */
    public function testReportsCarriesTheSelectorWithoutARecordsStrip(): void
    {
        $hive = RenderHarness::baseHive();
        $hive['universe'] = 'seed';
        $hive['universe_query'] = '?universe=seed';
        $hive['universe_switch'] = self::selector(DataUniverse::Seed, '/admin/reports');
        $hive['report_summary'] = [
            'enrolments' => 0, 'assigned' => 0, 'active' => 0, 'completed' => 0, 'cancelled' => 0,
            'graded_assessments' => 0, 'assessment_average' => 0.0, 'assessment_pass_rate' => 0.0,
            'certificates' => 0,
        ];
        $hive['course_report'] = [];
        $hive['company_report'] = [];

        self::assertNull(RenderHarness::renderError('partials/admin/reports.html', $hive));

        $markup = RenderHarness::render('partials/admin/reports.html', $hive);
        self::assertStringContainsString('class="universe-switch"', $markup);
        self::assertStringNotContainsString('universe-switch-summary', $markup);
    }

    // --- 4 and 5: ordinary REAL identity, and a seed identity --------------------------------

    /**
     * An ordinary reader sees no control and no seed terminology.
     *
     * The word is searched for in the rendered page rather than in the selector alone, because
     * the leak that matters is any appearance of it at all - a count, a label, or a stray link
     * parameter left behind by a link the reader could follow.
     */
    public function testAnOrdinaryRealIdentitySeesNoControlAndNoSeedTerminology(): void
    {
        foreach (self::countedFamilies() as $key => [$template, $dataset, $base]) {
            $hive = self::hive($dataset, $base, null);

            self::assertNull(
                RenderHarness::renderError($template, $hive),
                $template . ' must render for an ordinary identity with no universe model at all.'
            );

            $markup = RenderHarness::render($template, $hive);
            self::assertStringNotContainsString('universe-switch', $markup, $key . ' must show no selector.');
            self::assertStringNotContainsString('universe=', $markup, $key . ' must expose no universe parameter.');
            self::assertStringNotContainsString('seed', strtolower($markup), $key . ' must not name seed data.');
        }
    }

    /**
     * A seed identity, including SEED_ADMIN, sees neither the control nor any genuine-universe
     * terminology.
     *
     * The service builds no model for a seed identity whatever arrives in the query string, so
     * the hive here is the same empty one an ordinary reader gets. That is the assertion: the
     * template has no path to a selector that does not start with a model the service refused
     * to build.
     */
    public function testASeedIdentitySeesNoControlAndNoRealTerminology(): void
    {
        foreach (self::countedFamilies() as $key => [$template, $dataset, $base]) {
            $markup = RenderHarness::render($template, self::hive($dataset, $base, null));

            self::assertStringNotContainsString('universe-switch', $markup, $key . ' must show no selector.');
            self::assertStringNotContainsString('Real data', $markup, $key . ' must not name the genuine universe.');
            self::assertStringNotContainsString('real</', $markup, $key . ' must not label a genuine record count.');
        }
    }

    /**
     * The consolidated workspace renders in every mode.
     *
     * It shows several bounded previews at once and applies the view defaults for the whole page,
     * so it is the surface where a missing default shows up as a 500 rather than as a blank
     * strip. Both the administrator and the ordinary reader are rendered here.
     */
    public function testTheConsolidatedWorkspaceRendersWithAndWithoutTheControl(): void
    {
        foreach ([DataUniverse::All, DataUniverse::Real, DataUniverse::Seed, null] as $selected) {
            foreach (self::countedFamilies() as [$template, $dataset, $base]) {
                $hive = RenderHarness::baseHive();
                $hive['is_preview'] = true;
                $hive[$dataset . '_preview_has_more'] = true;
                if ($selected !== null) {
                    $hive['universe'] = $selected->value;
                    $hive['universe_query'] = '?universe=' . $selected->value;
                    $hive['universe_switch'] = self::selector($selected, '/admin');
                    $hive[$dataset . '_universe_counts'] = self::counts($dataset);
                }

                self::assertNull(
                    RenderHarness::renderError($template, $hive),
                    $template . ' failed to render as a consolidated preview.'
                );
            }
        }
    }

    /**
     * Every view variable the control reads has a default.
     *
     * This is the undefined-variable guarantee stated as a contract rather than inferred from a
     * render that happened to set them: a section which never builds a universe model still
     * renders, because the service supplies a coherent empty state for all of them.
     */
    public function testTheServiceDefaultsCoverEveryUniverseVariable(): void
    {
        $defaults = RenderHarness::serviceDatasetDefaults();

        foreach (['universe', 'universe_switch', 'universe_query'] as $key) {
            self::assertArrayHasKey($key, $defaults, $key . ' must have a default.');
        }
        self::assertSame(DataUniverse::Real->value, $defaults['universe']);
        self::assertNull($defaults['universe_switch']);
        self::assertSame('', $defaults['universe_query']);
        foreach (RenderHarness::DATASETS as $dataset) {
            self::assertArrayHasKey($dataset . '_universe_counts', $defaults);
            self::assertNull($defaults[$dataset . '_universe_counts']);
        }
    }

    /**
     * A bounded preview's "View all" link keeps the reader in the universe they were looking at.
     */
    public function testPreviewViewAllLinksCarryTheSelectedUniverse(): void
    {
        $hive = RenderHarness::baseHive();
        $hive['is_preview'] = true;
        $hive['people_preview_has_more'] = true;
        $hive['universe'] = 'seed';
        $hive['universe_query'] = '?universe=seed';
        $hive['universe_switch'] = self::selector(DataUniverse::Seed, '/admin');

        $markup = RenderHarness::render('partials/admin/people.html', $hive);
        self::assertStringContainsString('href="/admin/people?universe=seed"', $markup);
    }

    /** The same link carries nothing at all for a reader who may not choose. */
    public function testPreviewViewAllLinksStayCleanForAnOrdinaryIdentity(): void
    {
        $hive = RenderHarness::baseHive();
        $hive['is_preview'] = true;
        $hive['people_preview_has_more'] = true;

        $markup = RenderHarness::render('partials/admin/people.html', $hive);
        self::assertStringContainsString('href="/admin/people"', $markup);
    }
