declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Mailing\CattomailSignature;
use CattoLearning\Mailing\EmailBlocks;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class EmailBlocksTest extends TestCase
{
    public function testABlockTakesOnlyItsOwnFieldsChecked(): void
    {
        $button = EmailBlocks::make('button');
        self::assertMatchesRegularExpression('/^b[0-9a-f]{10}$/', $button['id']);
        $saved = EmailBlocks::update($button, ['label' => 'Read more', 'href' => 'https://example.test/x', 'html' => '<script>']);
        self::assertSame(['id' => $button['id'], 'type' => 'button', 'label' => 'Read more', 'href' => 'https://example.test/x'], $saved);
        $this->expectException(InvalidArgumentException::class);
        EmailBlocks::update($button, ['label' => 'Read more', 'href' => 'javascript:alert(1)']);
    }

    public function testAStoredListKeepsOnlyKnownBlocksEachIdOnce(): void
    {
        $text = ['id' => 'b0123456789', 'type' => 'text', 'text' => 'Hello'];
        $blocks = EmailBlocks::normalise([$text, $text, ['id' => 'b9999999999', 'type' => 'script'], 'nonsense', ['id' => 'bad', 'type' => 'heading', 'text' => 'X']]);
        self::assertSame([$text], $blocks);
        self::assertSame('Text: Hello', EmailBlocks::summary($text));
        self::assertSame('HTML: Our own page', EmailBlocks::summary(['id' => 'b0000000001', 'type' => 'html', 'html' => '<p>Our <b>own</b> page</p>']));
    }

    public function testCattomailsSignatureIsCheckedWithEitherSecretWithinFiveMinutes(): void
    {
        $body = '{"id":"evt_1","type":"webhook.test"}';
        $now = 1_800_000_000;
        $header = 't=' . $now . ',v1=' . hash_hmac('sha256', $now . '.' . $body, 'old-secret');
        self::assertTrue(CattomailSignature::valid($header, $body, ['new-secret', 'old-secret'], $now + 10), 'The previous secret still works while it changes.');
        self::assertFalse(CattomailSignature::valid($header, $body, ['new-secret'], $now));
        self::assertFalse(CattomailSignature::valid($header, $body . ' ', ['old-secret'], $now), 'A changed body fails.');
        self::assertFalse(CattomailSignature::valid($header, $body, ['old-secret'], $now + 301), 'A stale one fails.');
        self::assertFalse(CattomailSignature::valid('v1=abc', $body, ['old-secret'], $now));
    }

    /** A text block written in the editor keeps only what an email can show (owner, 2026-10-28, decision 6A). */
    public function testATextBlockKeepsOnlyBoldItalicsLinksAndLists(): void
    {
        $clean = EmailBlocks::richText('<p class="x" style="color:red">Hello <strong>you</strong> and <em>all</em>, see <a href="https://example.test/courses" onclick="evil()">the courses</a>.</p>'
            . '<ul><li>One</li><li>Two</li></ul><script>alert(1)</script><style>p{}</style><h1>Big</h1><a href="javascript:alert(1)">bad link</a><img src="x" onerror="y">');
        self::assertSame('<p>Hello <strong>you</strong> and <em>all</em>, see <a href="https://example.test/courses">the courses</a>.</p><ul><li>One</li><li>Two</li></ul>Bigbad link', $clean);
        $block = EmailBlocks::update(EmailBlocks::make('text'), ['text' => '<p>Hi <b>[First name]</b></p><div>more</div>']);
        self::assertSame('<p>Hi <b>[First name]</b></p>more', $block['text']);
        self::assertSame('Text: Hi [First name] more', EmailBlocks::summary($block));
        self::assertSame("A plain paragraph.\n\nAnother.", EmailBlocks::update(EmailBlocks::make('text'), ['text' => "A plain paragraph.\n\nAnother."])['text'], 'Text typed without the editor stays as it was.');
    }
}
