    /**
     * Template comments are plain prose only. Three separate traps make anything else unsafe,
     * and none of them raises an error - the page simply renders wrongly:
     *
     *   - A comment opened inside a start tag is not a comment. The browser reads the opening
     *     characters as an attribute name and the closing bracket of the terminator ends the
     *     element, dropping every attribute after it. The entity lookup documented its value
     *     guard between the name and value attributes, which emptied the hidden field carrying
     *     the already-selected person, company or course and printed the attributes on screen.
     *   - A comment terminator inside a comment body ends that comment early, leaking the rest
     *     of the note onto the page as visible text.
     *   - F3 parses its own tags inside comments, so a template token becomes real markup.
     *
     * Forbidding angle brackets in a comment body covers the terminator case too, since the
     * terminator contains one.
     */
    public function testTemplateCommentsArePlainProseOnly(): void
    {
        $offenders = [];
        $directory = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator(self::root() . '/resources/views'));
        // Assembled rather than written out, so this test's own source cannot trip the rule it
        // describes if these constants are ever moved into a template.
        $open = '<' . '!--';
        $close = '--' . '>';

        foreach ($directory as $file) {
            if ($file->isDir() || $file->getExtension() !== 'html') continue;
            $markup = (string) file_get_contents($file->getPathname());
            $offset = 0;
            while (($commentAt = strpos($markup, $open, $offset)) !== false) {
                $before = substr($markup, 0, $commentAt);
                $openedAt = strrpos($before, '<');
                $closedAt = strrpos($before, '>');
                if ($openedAt !== false && ($closedAt === false || $closedAt < $openedAt)) {
                    $offenders[] = $file->getFilename() . ': comment opened inside a start tag';
                }

                $endsAt = strpos($markup, $close, $commentAt + 4);
                $body = $endsAt === false
                    ? substr($markup, $commentAt + 4)
                    : substr($markup, $commentAt + 4, $endsAt - $commentAt - 4);
                foreach (['<', '>', '{' . '{', '@'] as $forbidden) {
                    if (str_contains($body, $forbidden)) {
                        $offenders[] = $file->getFilename() . ': comment contains ' . $forbidden;
                    }
                }

                // Resume past this comment's own terminator, so the scan never re-reads a body.
                $offset = $endsAt === false ? $commentAt + 4 : $endsAt + 3;
            }
        }

        self::assertSame([], array_values(array_unique($offenders)));
    }

