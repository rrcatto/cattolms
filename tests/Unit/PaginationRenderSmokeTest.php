    /**
     * Renders one platform template and returns the first error it produced, or null.
     *
     * The capture is this suite's own error handler rather than F3's ERROR hive alone. Relying
     * on the hive meant relying on F3's global handler still being installed, which is exactly
     * what PHPUnit removes after flagging a risky test: from the second data set onward a
     * template reading an undefined variable produced a PHPUnit warning instead of a failure,
     * and the assertion below passed. The handler here is pushed and popped around the render,
     * so the stack is left exactly as it was found and the result does not depend on what else
     * has run first. F3 itself is constructed in tests/bootstrap.php, before any test runs, so
     * its own one-time handler installation is never charged to a test and never stripped.
     *
     * HALT is disabled and ONERROR silenced so a broken template reports itself instead of
     * terminating the whole test run, which is what F3 does by default.
     *
     * @param array<string,mixed> $hive
     */
    private static function renderError(string $template, array $hive): ?string
    {
        $f3 = Base::instance();
        $temp = sys_get_temp_dir() . '/catto-render-smoke/';
        if (!is_dir($temp)) mkdir($temp, 0775, true);

        $f3->set('UI', self::root() . '/resources/views/');
        $f3->set('TEMP', $temp);
        $f3->set('HALT', false);
        $f3->set('ONERROR', static function (): void {
            // Swallow F3's default error page; the captured message is the assertion subject.
        });
        $f3->clear('ERROR');

        foreach ($hive as $key => $value) $f3->set($key, $value);

        $captured = null;
        set_error_handler(static function (int $severity, string $message) use (&$captured): bool {
            $captured ??= $message;

            return true;
        });

        try {
            Template::instance()->render($template);
        } catch (\Throwable $exception) {
            $captured ??= $exception->getMessage();
        } finally {
            restore_error_handler();
        }

        // F3's own handler still wins while it is installed, in which case the message lands in
        // the hive instead. Both paths are read so the result is the same either way.
        $error = $f3->get('ERROR');
        if ($captured === null && is_array($error)) {
            $captured = (string) ($error['text'] ?? 'unknown template error');
        }

        return $captured;
    }

