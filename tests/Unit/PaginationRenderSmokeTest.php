    /**
     * F3 parses its own tags inside HTML comments. A usage example written out in a comment
     * becomes a real tag in the compiled template; in pagination.html a documented
     * self-referential include compiled into an infinite recursion that exhausted memory.
     */
    public function testNoTemplateWritesAnF3TagInsideAnHtmlComment(): void
    {
        $offenders = [];
        $directory = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator(self::root() . '/resources/views'));

        foreach ($directory as $file) {
            if ($file->isDir() || $file->getExtension() !== 'html') continue;
            $markup = (string) file_get_contents($file->getPathname());
            if (preg_match_all('/<!--(.*?)-->/s', $markup, $comments) === 0) continue;

            foreach ($comments[1] as $comment) {
                if (preg_match('/<\/?(include|check|repeat|loop|exclude|ignore|set|switch|case|true|false)\b/i', $comment) === 1) {
                    $offenders[] = $file->getFilename();
                }
            }
        }

        self::assertSame([], array_values(array_unique($offenders)));
    }

    /**
