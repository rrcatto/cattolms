namespace CattoLearning\Tests\Unit;

use CattoLearning\OwnerMessages\OwnerMessages;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

final class OwnerMessagesTest extends TestCase
{
    public function testAnAmountIsWrittenAsTheOwnerWritesIt(): void
    {
        self::assertSame('R2,500', OwnerMessages::amount(250000, 'ZAR'));
        self::assertSame('R2,500.50', OwnerMessages::amount(250050, 'ZAR'));
        self::assertSame('R0', OwnerMessages::amount(0, 'ZAR'));
        self::assertSame('USD 12', OwnerMessages::amount(1200, 'USD'));
    }

    /** @return iterable<array{string,bool}> */
    public static function addresses(): iterable
    {
        yield 'Seed Database' => ['thandi@greenhill.invalid', true];
        yield 'a check' => ['thandi.mokoena@inbox.test', true];
        yield 'a check company' => ['staff@greencompany.test', true];
        yield 'an example' => ['someone@example.com', true];
        yield 'a sub-domain of an example' => ['someone@mail.example.org', true];
        yield 'capitals' => ['SOMEONE@ACME.INVALID', true];
        yield 'a real address' => ['thandi@greenhillnursery.co.za', false];
        yield 'a domain that only looks like an example' => ['someone@myexample.com', false];
    }

    #[DataProvider('addresses')]
    public function testOnlyAnAddressNobodyRealHasIsInvented(string $email, bool $invented): void
    {
        self::assertSame($invented, OwnerMessages::invented($email));
    }
}
