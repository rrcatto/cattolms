namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class CreditHolderContractTest extends TestCase
{
    private static function read(string $path): string
    {
        return (string) file_get_contents(dirname(__DIR__, 2) . '/' . $path);
    }

    public function testGrantingACreditRequiresACompany(): void
    {
        $service = self::read('src/Application/PlatformAdministrationService.php');

        self::assertStringContainsString(
            "throw new InvalidArgumentException('Choose the company that holds the credit.');",
            $service,
            'A credit granted with no company must be refused.'
        );
        self::assertStringNotContainsString(
            'Choose either a company or one person as the credit holder.',
            $service,
            'The either-or holder rule is gone: a credit is a company seat.'
        );
    }

    public function testTheGrantFormOffersNoIndividualHolder(): void
    {
        $form = self::read('resources/views/partials/admin/credits.html');

        self::assertStringContainsString("lk_name='company_id'", $form);
        self::assertStringContainsString("lk_label='Company holding the credit',lk_empty='Search for the company',lk_selected=0,lk_required=1", $form);
        self::assertStringNotContainsString("lk_name='user_id'", $form, 'The individual holder control must not return.');
    }

    /**
     * The section is Credits, not "Credits & Orders".
     *
     * No order, invoice, payment or refund table exists. Naming the section after both made the
     * platform claim a purchase history it does not keep; an order is the record of a transaction
     * and a credit is what one leaves behind, and the two arrive together with commerce.
     */
    public function testTheSectionDoesNotClaimAnOrderHistoryThatDoesNotExist(): void
    {
        foreach (['src/Application/AdministrationSectionRegistry.php', 'src/View/ThemeRenderer.php'] as $file) {
            self::assertStringNotContainsString("'Credits & Orders'", self::read($file), $file . ' still advertises Orders.');
        }
