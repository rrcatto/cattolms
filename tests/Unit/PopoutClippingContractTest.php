/*
Generated by: Claude Code CLI

Date time: 2026/09/07 23:30 SAST

Version: 0.6

Description:
A core-owned popout is never clipped by a theme.

Two controls escape the box they are drawn in: the row actions menu escapes its table cell, and the
third navigation level escapes its menu panel. Both are absolutely positioned, and an absolutely
positioned element is clipped by any ancestor with an `overflow` other than `visible`. That failure
is completely silent - no error, no console message, nothing on screen. The control looks like a
button that does nothing.

It has now happened twice, in two different themes, for the same reason:

  - Gilded Noir declares `.cl-main .cl-ui-table { overflow: auto }`. Core's `.cl-ui-table` rule was
    not marked important and has lower specificity, and the theme stylesheet loads after core, so
    the theme won: the actions menu was drawn outside the wrapper and clipped away. It worked in
    the default theme, which made it look like a Gilded Noir bug rather than a core one.
  - Factory Reset's sidebar is `position: fixed` with `overflow-y: auto`. There is no such thing as
    a box that scrolls on one axis and overflows visibly on the other - the used value of the other
    axis becomes `auto` too - so the navigation flyout was clipped there. That one is not fixable by
    specificity, because the ancestor legitimately has to scroll; inside a sidebar the third level
    nests instead.

So this test checks the mechanism rather than the symptom: for every installed theme, core's
`overflow` declaration on the table wrapper must win the cascade.

Changelog:
2026/09/07 23:30 SAST
- Created after the row actions menu was invisible in Gilded Noir and the navigation flyout was
  invisible in the default theme.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class PopoutClippingContractTest extends TestCase
{
    private static function root(): string
    {
        return dirname(__DIR__, 2);
    }

    /**
     * The (ids, classes, elements) specificity of one selector.
     *
     * @return array{0:int,1:int,2:int}
     */
    private static function specificity(string $selector): array
    {
        $selector = (string) preg_replace('/::?[a-z-]+(\([^)]*\))?/', '', $selector);

        return [
            preg_match_all('/#[\w-]+/', $selector),
            preg_match_all('/\.[\w-]+/', $selector) + preg_match_all('/\[[^\]]+\]/', $selector),
            preg_match_all('/(?:^|[\s>+~])([a-z][\w-]*)/', $selector),
        ];
    }

    /**
     * Every declaration of one property on a selector mentioning $needle, in source order.
     *
     * @return list<array{selector:string,important:bool,specificity:array{0:int,1:int,2:int}}>
     */
    private static function declarations(string $css, string $property, string $needle): array
    {
        // Comments first: a property name inside prose is not a declaration.
        $css = (string) preg_replace('#/\*.*?\*/#s', '', $css);
        $found = [];

        preg_match_all('/([^{}]+)\{([^{}]*)\}/', $css, $blocks, PREG_SET_ORDER);
        foreach ($blocks as $block) {
            $declarations = array_filter(
                array_map(trim(...), explode(';', $block[2])),
                static fn(string $d): bool => str_starts_with($d, $property . ':')
            );
            if ($declarations === []) {
                continue;
            }
            $last = (string) end($declarations);

            foreach (explode(',', $block[1]) as $selector) {
                $selector = trim($selector);
                if ($selector === '' || !str_contains($selector, $needle)) {
                    continue;
                }
                $found[] = [
                    'selector' => $selector,
                    'important' => str_contains($last, '!important'),
                    'specificity' => self::specificity($selector),
                ];
            }
        }

        return $found;
    }

    /** @return list<string> Paths to every theme stylesheet that ships with the platform. */
    private static function themeStylesheets(): array
    {
        $sheets = [];
        foreach ([self::root() . '/themes', dirname(self::root(), 2) . '/runtime/themes'] as $base) {
            if (!is_dir($base)) {
                continue;
            }
            foreach ((array) glob($base . '/*/public/css/*.css') as $sheet) {
                $sheets[] = (string) $sheet;
            }
        }

        return $sheets;
    }

    /**
     * Core's overflow on the table wrapper beats every theme's.
     *
     * The wrapper must not clip, because the row actions menu is drawn outside the cell it belongs
     * to. Core loads first, so losing the cascade is the default outcome rather than an unlucky one.
     */
    public function testCoreKeepsTheTableWrapperFromClippingInEveryTheme(): void
    {
        $core = (string) file_get_contents(self::root() . '/public_html/css/catto-platform.css');
        $ours = self::declarations($core, 'overflow', '.cl-ui-table');

        $winner = null;
        foreach ($ours as $rule) {
            if ($rule['selector'] === '.cl-ui-table') {
                $winner = $rule;
            }
        }
        self::assertNotNull($winner, 'Core must declare the wrapper\'s overflow.');
        self::assertTrue(
            $winner['important'],
            'Core loads before every theme, so its wrapper rule must be marked important or a theme '
            . 'selector of higher specificity silently reinstates the clipping.'
        );

        $sheets = self::themeStylesheets();
        self::assertNotSame([], $sheets, 'No theme stylesheets were found, so this proves nothing.');

        foreach ($sheets as $sheet) {
            foreach (self::declarations((string) file_get_contents($sheet), 'overflow', '.cl-ui-table') as $rule) {
                self::assertFalse(
                    $rule['important'],
                    basename(dirname($sheet, 3)) . ' marks "' . $rule['selector'] . '" important, which '
                    . 'outranks core and clips the row actions menu.'
                );
            }
        }
    }

    /** The menu itself is restated by core, because themes style `details` as a bordered panel. */
    public function testCoreOwnsTheRowMenuOutrightRatherThanInheritingIt(): void
    {
        $core = (string) file_get_contents(self::root() . '/public_html/css/catto-platform.css');
        // Canonical theme geometry is forbidden by UiOwnershipAudit. These functional core
        // declarations therefore need no cascade escalation; keep checking their actual values.
        self::assertMatchesRegularExpression('/\.cl-ui-row-panel[^{}]*\{[^{}]*position:absolute(?:;|!important)/', $core);
        self::assertMatchesRegularExpression('/\.cl-ui-row-panel[^{}]*\{[^{}]*display:grid(?:;|!important)/', $core);


        foreach ([
            ['overflow', '.cl-ui-row-menu'],
            ['padding', '.cl-ui-row-panel'],
        ] as [$property, $needle]) {
            $rules = array_filter(
                self::declarations($core, $property, $needle),
                static fn(array $rule): bool => $rule['important']
            );
            self::assertNotSame(
                [],
                $rules,
                'Core must state ' . $property . ' on ' . $needle . ' with !important: a theme that '
                . 'styles every details element as an accordion panel would otherwise reshape it.'
            );
        }
    }

    /**
     * Inside a scrolling sidebar the third navigation level nests rather than flying out.
     *
     * A sidebar that scrolls cannot let an absolutely positioned child escape it, whatever the
     * specificity, so this one is a layout decision rather than a cascade fix.
     */
    public function testTheThirdNavigationLevelNestsInsideASidebar(): void
    {
        $core = (string) file_get_contents(self::root() . '/public_html/css/catto-platform.css');

        self::assertStringContainsString('.cl-sidebar .cl-nav-group>.cl-nav-subpanel', $core);
        self::assertNotSame(
            [],
            array_filter(
                self::declarations($core, 'position', '.cl-sidebar .cl-nav-group>.cl-nav-subpanel'),
                static fn(array $rule): bool => true
            ),
            'The sidebar sub-panel must take part in the flow, or it is clipped by the scroll container.'
        );
    }
}
