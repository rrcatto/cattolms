declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Seed\SeedTableCatalog;
use PHPUnit\Framework\TestCase;

final class SeedSchemaContractTest extends TestCase
{
    private static ?string $baseline = null;

    private static function baseline(): string
    {
        if (self::$baseline === null) {
            $matches = glob(dirname(__DIR__, 2) . '/database/migrations/*_create_*_baseline.php') ?: [];
            self::assertCount(1, $matches, 'There must be exactly one baseline migration.');
            self::$baseline = (string) file_get_contents($matches[0]);
        }

        return self::$baseline;
    }

    /** The body of one CREATE TABLE statement, or null when the table is absent. */
    private static function tableBody(string $table): ?string
    {
        $pattern = '/CREATE TABLE ' . preg_quote($table, '/') . ' \((.*?)\n\);/s';

        return preg_match($pattern, self::baseline(), $match) === 1 ? $match[1] : null;
    }

    /** @return list<string> the primary-key columns the baseline declares */
    private static function primaryKey(string $table): array
    {
        $body = self::tableBody($table);
        if ($body === null) {
            return [];
        }

        if (preg_match('/PRIMARY KEY \(([^)]+)\)/', $body, $match) === 1) {
            return array_map('trim', explode(',', $match[1]));
        }

        foreach (explode("\n", $body) as $line) {
            if (preg_match('/^\s*(\w+)\s+.*\bPRIMARY KEY\b/', $line, $match) === 1) {
                return [$match[1]];
            }
        }

        return [];
    }

    /**
     * Every foreign key the baseline declares on one table.
     *
     * @return list<array{column:string,parent:string,on_delete:string}>
     */
    private static function foreignKeys(string $table): array
    {
        $body = self::tableBody($table);
        if ($body === null) {
            return [];
        }

        $keys = [];
        foreach (explode("\n", $body) as $line) {
            if (preg_match('/^\s*(\w+)\s+.*REFERENCES\s+(\w+)\s*\(/', $line, $match) !== 1) {
                continue;
            }
            $onDelete = 'NO ACTION';
            if (stripos($line, 'ON DELETE CASCADE') !== false) {
                $onDelete = 'CASCADE';
            } elseif (stripos($line, 'ON DELETE SET NULL') !== false) {
                $onDelete = 'SET NULL';
            } elseif (stripos($line, 'ON DELETE RESTRICT') !== false) {
                $onDelete = 'RESTRICT';
            }
            $keys[] = ['column' => $match[1], 'parent' => $match[2], 'on_delete' => $onDelete];
        }

        return $keys;
    }

    // --- row identity ---------------------------------------------------------------------------

    /** Every seed-aware table has a declared cleanup row identity, and no other table does. */
    public function testEverySeedAwareTableHasADeclaredRowIdentity(): void
    {
        $seedAware = SeedTableCatalog::seedAwareTables();
        sort($seedAware);
        $declared = array_keys(SeedTableCatalog::rowIdentities());
        sort($declared);

        self::assertSame(
            $seedAware,
            $declared,
            'The cleanup planner names rows from this list, so it must cover exactly the seed-aware tables.'
        );
        self::assertCount(30, $declared);
    }

    /** Each declared identity is exactly the primary key the baseline declares. */
    public function testEachRowIdentityMatchesThePrimaryKey(): void
    {
        $mismatched = [];
        foreach (SeedTableCatalog::rowIdentities() as $table => $identity) {
            $primaryKey = self::primaryKey($table);
            if ($primaryKey === []) {
                $mismatched[] = $table . ': no primary key found in the baseline';
                continue;
            }
            if ($primaryKey !== $identity) {
                $mismatched[] = $table . ': declared (' . implode(', ', $identity)
                    . ') but the baseline says (' . implode(', ', $primaryKey) . ')';
            }
        }

        self::assertSame([], $mismatched, "Cleanup row identity disagrees with the schema:\n  " . implode("\n  ", $mismatched));
    }

    /**
     * The composite keys are still composite.
     *
     * Named individually because assuming `id` for any one of them is the defect this file exists
     * to prevent, and a regression would otherwise only show as a count.
     */
    public function testTheCompositeKeyTablesAreDeclaredComposite(): void
    {
        $expected = [
            'user_roles' => ['user_id', 'role_id'],
            'company_users' => ['company_id', 'user_id'],
            'course_editors' => ['course_id', 'user_id'],
            'module_progress' => ['enrolment_id', 'module_id'],
            'assessment_responses' => ['attempt_id', 'question_id'],
            'assessment_session_questions' => ['session_id', 'question_id'],
            'course_favourites' => ['user_id', 'course_id'],
            'course_results' => ['enrolment_id'],
        ];

        foreach ($expected as $table => $identity) {
            self::assertSame($identity, SeedTableCatalog::rowIdentity($table), $table . ' must keep its own key shape.');
            self::assertNotSame(['id'], SeedTableCatalog::rowIdentity($table), $table . ' has no id column.');
        }
    }

    /** No seed-aware table is silently assumed to have an `id`. */
    public function testNoTableIsAssumedToHaveAnIdColumn(): void
    {
        $wronglyAssumed = [];
        foreach (SeedTableCatalog::rowIdentities() as $table => $identity) {
            if ($identity !== ['id']) {
                continue;
            }
            $body = self::tableBody($table);
            if ($body === null || preg_match('/^\s*id\s+BIGSERIAL/m', $body) !== 1) {
                $wronglyAssumed[] = $table;
            }
        }

        self::assertSame([], $wronglyAssumed, 'These tables are declared as keyed by id but have no id column.');
    }

    // --- foreign keys ----------------------------------------------------------------------------

    /** Every foreign key between two seed-aware tables is classified exactly once. */
    public function testEveryInterSeedForeignKeyIsClassified(): void
    {
        $declared = [];
        foreach (SeedTableCatalog::interSeedReferences() as $reference) {
            $declared[$reference['child'] . '.' . $reference['column']] = $reference;
        }

        $missing = [];
        $wrongAction = [];
        $found = 0;

        foreach (SeedTableCatalog::seedAwareTables() as $table) {
            foreach (self::foreignKeys($table) as $key) {
                if (!SeedTableCatalog::isSeedAware($key['parent'])) {
                    continue;   // the parent is not seed-aware, so it is not a cleanup dependency
                }
                $found++;
                $name = $table . '.' . $key['column'];
                if (!isset($declared[$name])) {
                    $missing[] = $name . ' -> ' . $key['parent'] . ' (' . $key['on_delete'] . ')';
                    continue;
                }
                if ($declared[$name]['on_delete'] !== $key['on_delete']) {
                    $wrongAction[] = $name . ': declared ' . $declared[$name]['on_delete']
                        . ' but the baseline says ' . $key['on_delete'];
                }
                if ($declared[$name]['parent'] !== $key['parent']) {
                    $wrongAction[] = $name . ': declared parent ' . $declared[$name]['parent']
                        . ' but the baseline says ' . $key['parent'];
                }
                unset($declared[$name]);
            }
        }

        self::assertSame([], $missing, "Unclassified inter-seed foreign keys:\n  " . implode("\n  ", $missing));
        self::assertSame([], $wrongAction, "Misclassified foreign keys:\n  " . implode("\n  ", $wrongAction));
        self::assertSame([], array_keys($declared), 'These references are declared but do not exist in the baseline.');
        // Sixty-five since v0.6: courses.category_id stopped being a guarded cross-universe
        // reference when categories became universe-free labels.
        self::assertSame(65, $found, 'The inter-seed foreign-key count changed; reconcile the catalogue.');
    }

    /**
     * Collateral is every classification except SET NULL.
     *
     * SET NULL is the only action under which a child outlives its parent.
     */
    public function testCollateralIsEveryReferenceExceptSetNull(): void
    {
        $expected = 0;
        foreach (SeedTableCatalog::interSeedReferences() as $reference) {
            if ($reference['on_delete'] !== 'SET NULL') {
                $expected++;
            }
        }

        self::assertSame($expected, count(SeedTableCatalog::collateralReferences()));
        foreach (SeedTableCatalog::collateralReferences() as $reference) {
            self::assertNotSame('SET NULL', $reference['on_delete']);
        }
    }

    /**
     * Every foreign key targets its parent's single `id` column.
     *
     * The planner's closure joins a child column against the parent's planned key, which is only
     * valid while this holds. A reference to a composite key would need a different join and this
     * test is what would catch it.
     */
    public function testEveryForeignKeyTargetsASingleIdColumn(): void
    {
        preg_match_all('/REFERENCES\s+(\w+)\s*\(([^)]+)\)/', self::baseline(), $matches, PREG_SET_ORDER);
        self::assertNotSame([], $matches);

        $offenders = [];
        foreach ($matches as $match) {
            if (trim($match[2]) !== 'id') {
                $offenders[] = $match[1] . '(' . $match[2] . ')';
            }
        }

        self::assertSame([], array_unique($offenders), 'The cleanup closure assumes every foreign key targets id.');
    }

    // --- deletion order ---------------------------------------------------------------------------

    /**
     * Cleanup order deletes every child before its parent.
     *
     * `cleanupOrder()` is `array_reverse(SEED_AWARE)` - an order chosen for generation and reused
     * for deletion. That it happens to be dependency-safe is a property worth proving rather than
     * assuming, especially now the planner deletes generically from it.
     *
     * Self-references are excluded: a table cannot precede itself, and both of them
     * (`courses.parent_course_id`, `course_content_blocks.parent_block_id`) are handled by the
     * database - SET NULL and CASCADE respectively - rather than by table ordering.
     */
    public function testCleanupOrderDeletesChildrenBeforeParents(): void
    {
        $position = array_flip(SeedTableCatalog::cleanupOrder());

        $violations = [];
        foreach (SeedTableCatalog::collateralReferences() as $reference) {
            if ($reference['child'] === $reference['parent']) {
                continue;
            }
            $child = $position[$reference['child']] ?? null;
            $parent = $position[$reference['parent']] ?? null;
            self::assertIsInt($child, $reference['child'] . ' is missing from the cleanup order.');
            self::assertIsInt($parent, $reference['parent'] . ' is missing from the cleanup order.');

            if ($child > $parent) {
                $violations[] = $reference['child'] . ' (' . $child . ') is deleted after '
                    . $reference['parent'] . ' (' . $parent . '), via ' . $reference['column'];
            }
        }

        self::assertSame([], $violations, "Cleanup order would delete a parent before its child:\n  " . implode("\n  ", $violations));
    }

    /** The self-references are the two known ones, and neither is RESTRICT. */
    public function testSelfReferencesAreHandledByTheDatabase(): void
    {
        $selfReferences = [];
        foreach (SeedTableCatalog::interSeedReferences() as $reference) {
            if ($reference['child'] === $reference['parent']) {
                $selfReferences[$reference['child'] . '.' . $reference['column']] = $reference['on_delete'];
            }
        }

        self::assertSame(
            [
                'courses.parent_course_id' => 'SET NULL',
                'course_content_blocks.parent_block_id' => 'CASCADE',
            ],
            $selfReferences,
            'A RESTRICT self-reference could not be resolved by table-level ordering and would need its own handling.'
        );
    }

    /** The cleanup order covers every seed-aware table exactly once. */
    public function testCleanupOrderCoversEverySeedAwareTableOnce(): void
    {
        $order = SeedTableCatalog::cleanupOrder();
        $seedAware = SeedTableCatalog::seedAwareTables();

        self::assertCount(count($seedAware), $order);
        self::assertSame(count($order), count(array_unique($order)));

        sort($order);
        sort($seedAware);
        self::assertSame($seedAware, $order);
    }

    /**
     * The complete list of globally unique text columns the generator has to namespace.
     *
     * This is the audit that was missing when the first VPS run failed. The generator builds every
     * platform-wide unique value from one per-set key, and a collision in any of them stops a
     * generation dead. PostgreSQL reports only the first collision, so a second one hiding behind
     * it is invisible until the first is fixed - which is exactly what happened: the run stopped at
     * `course_categories_slug_key` and said nothing about the four columns behind it.
     *
     * `course_categories.slug` left this list in v0.6 along with the table: a universe-free label
     * is not generated per set, so it has nothing to namespace and nothing to collide with.
     *
     * Reading the list out of the baseline rather than trusting a written note means a sixth
     * column cannot be added without this failing and someone deciding, deliberately, whether it
     * needs the key too.
     *
     * Only single-column UNIQUE declarations on text columns qualify. A `public_id` is a random
     * UUID and namespaces itself; a unique BIGINT is a foreign key to a row the generator created;
     * and a composite or partial constraint is scoped to a parent row the generator owns, so two
     * sets can never meet inside one.
     */
    public function testEveryGloballyUniqueTextColumnIsKnownToTheGenerator(): void
    {
        // Each of these is built from the per-set uniqueness key in SeedGenerator::setUniqueKey().
        $namespaced = [
            'certificates.certificate_number',
            'companies.domain',
            'courses.slug',
            'user_emails.email',
        ];

        $found = [];
        foreach (SeedTableCatalog::generatorTables() as $table) {
            $body = self::tableBody($table);
            if ($body === null) {
                continue;
            }

            foreach (explode("\n", $body) as $line) {
                // A space rather than a word boundary after the type: `\b` between the closing
                // bracket of VARCHAR(n) and the following space is two non-word characters, and
                // never matches.
                if (preg_match('/^\s*(\w+)\s+(?:VARCHAR\(\d+\)|TEXT)\s[^,]*\bUNIQUE\b/i', $line, $match) === 1) {
                    $found[] = $table . '.' . $match[1];
                }
            }
        }

        sort($found);

        self::assertSame(
            $namespaced,
            $found,
            'A globally unique text column changed. Every one of these must be built from the '
            . 'per-set key, or two sets generated in the same window will collide on it.'
        );
    }
