Description:
Proves every assumption the cleanup planner makes about the schema, by parsing the baseline.

This exists because of a defect that reached the VPS twice. The cleanup planner generates SQL from
a catalogue, and the unit suite validated fragments of that catalogue - the exemption list, the
reference count - without ever checking the assumption the generated SQL actually rested on: that
every seed-aware table has an `id` column. Eight do not. The static tests passed and PostgreSQL
answered `column t.id does not exist` across fourteen tests.

The lesson is that generated SQL needs a contract against the real schema, not against another
piece of PHP. Everything here is checked against `database/migrations/*_baseline.php`, so a schema
change that adds a table, alters a primary key, adds a foreign key or changes an ON DELETE action
fails this test until the catalogue is reconciled.

Changelog:

2026/08/25 08:14 SAST

- Added the globally unique text column audit, read from the baseline, so a sixth such column cannot be introduced without a deliberate decision about namespacing it.
2026/08/25 05:10 SAST
- Created after the cleanup planner's universal `id` assumption reached PostgreSQL.
