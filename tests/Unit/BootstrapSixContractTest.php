    }

    /**
     * The safety net: Core and each theme give the body its text and background colours, links, the focus
     * outline and fields their colours in plain values. A theme custom property counts when its own
     * definition is plain; a Bootstrap token or light-dark() alone does not.
     */
    public function testCoreAndEveryThemeStateTheirColoursInPlainValues(): void
    {
        $sheets = ['core' => [self::root() . '/public_html/css/catto-platform.css']];
        foreach (self::bundledThemes() as $theme) {
            $manifest = json_decode((string) file_get_contents(self::root() . '/themes/' . $theme . '/theme.json'), true, 512, JSON_THROW_ON_ERROR);
            $own = [self::root() . '/themes/' . $theme . '/public/css/theme.css'];
            // A child theme draws on its parent's stylesheet too.
            $parent = is_array($manifest['parent'] ?? null) ? (string) $manifest['parent']['name'] : '';
            if ($parent !== '') $own[] = self::root() . '/themes/' . strtolower(str_replace(' ', '-', $parent)) . '/public/css/theme.css';
            $sheets[$theme] = $own;
        }
        $faults = [];
        foreach ($sheets as $name => $files) {
            $css = '';
            foreach ($files as $file) $css .= (string) preg_replace('~/\*.*?\*/~s', '', (string) file_get_contents($file));
            $definitions = [];
            preg_match_all('/(--[a-zA-Z0-9-]+)\s*:\s*([^;}]+)/', $css, $defs, PREG_SET_ORDER);
            foreach ($defs as $def) $definitions[$def[1]][] = trim($def[2]);
            $plain = static function (string $value) use ($definitions): bool {
                $value = trim(str_replace('!important', '', $value));
                if (str_contains($value, 'light-dark(') || str_contains($value, 'var(--bs-')) return false;
                if (preg_match('/^var\((--[a-zA-Z0-9-]+)\)$/', $value, $m) === 1) {
                    foreach ($definitions[$m[1]] ?? [] as $definition) {
                        if (!str_contains($definition, 'var(--bs-') && !str_contains($definition, 'light-dark(')) return true;
                    }
                    return false;
                }
                return $value !== '';
            };
            $wanted = [
                'body text' => ['/(^|,)\s*(html|body|:root|\.[a-z0-9-]+-(body|theme)|body\.[a-z0-9-]+)\s*(,|$)/', ['color']],
                'body background' => ['/(^|,)\s*(html|body|:root|\.[a-z0-9-]+-(body|theme)|body\.[a-z0-9-]+)\s*(,|$)/', ['background', 'background-color']],
                'link colour' => ['/(^|[\s,>)])a(:hover)?\s*(,|$)/', ['color']],
                'focus outline' => ['/:focus-visible/', ['outline', 'outline-color']],
                'field colours' => ['/\.cl-input\b|\binput\b/', ['color', 'background', 'background-color', 'border', 'border-color']],
            ];
            preg_match_all('/([^{}]+)\{([^{}]*)\}/', $css, $rules, PREG_SET_ORDER);
            foreach ($wanted as $label => [$selector, $properties]) {
                $found = false;
                foreach ($rules as $rule) {
                    if (preg_match($selector, trim(preg_replace('/\s+/', ' ', $rule[1]) ?? '')) !== 1) continue;
                    foreach (explode(';', $rule[2]) as $declaration) {
                        [$property, $value] = array_pad(explode(':', $declaration, 2), 2, '');
                        if (in_array(trim($property), $properties, true) && $plain($value)) { $found = true; break 2; }
                    }
                }
                if (!$found) $faults[] = $name . ': ' . $label;
            }
        }
        self::assertSame([], $faults, 'Each of these needs a plain colour, not only a Bootstrap token.');
    }
