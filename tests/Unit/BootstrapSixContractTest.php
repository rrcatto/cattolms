    public function testCoreMarkupUsesNoRetiredClassAndNoBootstrapBehaviour(): void
    {
        $faults = [];
        $files = [...(glob(self::root() . '/resources/views/{,*/,*/*/}*.twig', GLOB_BRACE) ?: []), ...(glob(self::root() . '/themes/*/{,*/}*.twig', GLOB_BRACE) ?: []), ...(glob(self::root() . '/src/{,*/,*/*/}*.php', GLOB_BRACE) ?: [])];
        foreach ($files as $file) {
            $source = (string) file_get_contents($file);
            // data-bs-theme is the colour scheme Core writes on <html>; any other data-bs- attribute is Bootstrap behaviour.
            if (preg_match('/data-bs-(?!theme\b)[a-z]/', $source) === 1) $faults[] = $file . ': Bootstrap data attribute';
            preg_match_all('/class=(["\'])(.*?)\1/', $source, $matches);
            foreach ($matches[2] as $value) {
                // String literals inside Twig expressions are class lists too.
                preg_match_all("/'([^']*)'/", implode(' ', preg_match_all('/\{\{.*?\}\}|\{%.*?%\}/', $value, $expressions) ? $expressions[0] : []), $literals);
                $tokens = preg_split('/\s+/', trim((string) preg_replace('/\{\{.*?\}\}|\{%.*?%\}/', ' ', $value) . ' ' . implode(' ', $literals[1]))) ?: [];
                foreach (array_intersect($tokens, self::RETIRED) as $token) $faults[] = $file . ': ' . $token;
                foreach ($tokens as $token) {
                    // A 5.3.8 responsive utility: 6.0 writes the breakpoint first (lg:col-8). py-lg-6 and its kind were
                    // never Bootstrap classes (5.3.8's spacing stops at 5); two themes use one as a hook.
                    if (preg_match('/^((col|offset|order)-(sm|md|lg|xl|xxl)-|(d|flex|text|align-items|justify-content|float)-(sm|md|lg|xl|xxl)-|[mp][tbsexy]?-(sm|md|lg|xl|xxl)-([0-5]|auto)$|(g|gx|gy|gap)-(sm|md|lg|xl|xxl)-[0-5]$)/', $token) === 1) {
                        $faults[] = $file . ': ' . $token . ' (6.0 writes the breakpoint first: lg:col-8)';
                    }
                }
            }
        }
        self::assertSame([], array_values(array_unique($faults)));
    }

    /**
     * Core's and the themes' markup was written for utilities that win, as 5.3.8's !important utilities did. Under 6.0
     * a utility sits in a layer and loses to every Core or theme rule, so Core states each utility this markup uses
     * as an !important rule of its own.
