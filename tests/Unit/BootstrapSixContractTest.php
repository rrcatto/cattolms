        foreach ([...(glob(self::root() . '/resources/views/{,*/,*/*/}*.twig', GLOB_BRACE) ?: []), ...(glob(self::root() . '/themes/*/{,*/}*.twig', GLOB_BRACE) ?: [])] as $file) {
