declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Auth\CurrentUser;
use CattoLearning\Auth\DataUniverse;
use CattoLearning\Support\Uuid;
use PHPUnit\Framework\TestCase;

final class DataUniverseTest extends TestCase
{
    /** @param list<string> $roles */
    private static function user(array $roles, ?string $seedToken): CurrentUser
    {
        return new CurrentUser(1, 'public', 'person@example.test', 'Person', $roles, [], 'session', $seedToken);
    }

    /** The universe follows the token, and only the token. */
    public function testIdentityUniverseIsDerivedFromTheTokenNotTheRoles(): void
    {
        self::assertSame(DataUniverse::Real, DataUniverse::forIdentity(null));
        self::assertSame(DataUniverse::Real, DataUniverse::forIdentity(''));
        self::assertSame(DataUniverse::Real, DataUniverse::forIdentity('   '));
        self::assertSame(DataUniverse::Seed, DataUniverse::forIdentity(Uuid::v7()));

        // A genuine account holding a seed-family role is still REAL: role names are mutable and
        // must never be able to move an identity across the data boundary.
        self::assertSame(DataUniverse::Real, self::user(['SEED_STUDENT'], null)->universe());

        // And a generated identity is SEED even if its roles were somehow mis-assigned.
        self::assertSame(DataUniverse::Seed, self::user(['STUDENT'], Uuid::v7())->universe());
    }

    /** Only a genuine ADMIN may deliberately widen scope. */
    public function testOnlyGenuineAdminMayCrossTheBoundary(): void
    {
        $admin = self::user(['ADMIN'], null);

        self::assertSame(DataUniverse::All, $admin->resolveUniverse('all'));
        self::assertSame(DataUniverse::Seed, $admin->resolveUniverse('seed'));
        self::assertSame(DataUniverse::Real, $admin->resolveUniverse('real'));
    }

    /**
     * An ordinary identity cannot widen its scope by asking, however it asks.
     *
     * This is the case that matters: the filter arrives from a query string, so every one of
     * these is a request an attacker can make for free.
     */
    public function testOrdinaryIdentityCannotWidenScopeByAsking(): void
    {
        $student = self::user(['STUDENT'], null);

        foreach (['all', 'seed', 'ALL', 'SEED', ' all ', 'both', '1', 'true', ''] as $attempt) {
            self::assertSame(
                DataUniverse::Real,
                $student->resolveUniverse($attempt),
                'An ordinary identity asking for "' . $attempt . '" must remain REAL-only.'
            );
        }
    }

    /** A seed identity is pinned to SEED and can never reach genuine data. */
    public function testSeedIdentityCannotReachRealData(): void
    {
        $seed = self::user(['SEED_STUDENT'], Uuid::v7());

        foreach (['all', 'real', 'REAL', null, 'nonsense'] as $attempt) {
            self::assertSame(
                DataUniverse::Seed,
                $seed->resolveUniverse($attempt),
                'A seed identity must remain SEED-only.'
            );
        }
    }

    /**
     * A seed identity holding SEED_ADMIN is a platform-style administrator *inside* seed data.
     * It is not the genuine ADMIN and receives no crossing privilege.
     */
    public function testSeedAdminIsNotTheGenuineAdmin(): void
    {
        $seedAdmin = self::user(['SEED_ADMIN'], Uuid::v7());

        self::assertTrue($seedAdmin->isSeedIdentity());
        self::assertSame(DataUniverse::Seed, $seedAdmin->resolveUniverse('all'));
    }

    /** An unrecognised value falls back rather than throwing or widening. */
    public function testUnrecognisedRequestValuesFallBack(): void
    {
        self::assertSame(DataUniverse::Real, DataUniverse::fromRequest('nonsense', DataUniverse::Real));
        self::assertSame(DataUniverse::Seed, DataUniverse::fromRequest(null, DataUniverse::Seed));
        self::assertSame(DataUniverse::Real, DataUniverse::fromRequest(['all'], DataUniverse::Real));
        self::assertSame(DataUniverse::All, DataUniverse::fromRequest(' ALL ', DataUniverse::Real));
    }

    /** The SQL fragment must express exactly the two-universe rule. */
    public function testPredicateExpressesTheTwoUniverseRule(): void
    {
        self::assertSame('u.seed_token IS NULL', DataUniverse::Real->predicate('u'));
        self::assertSame('u.seed_token IS NOT NULL', DataUniverse::Seed->predicate('u'));
        self::assertNull(DataUniverse::All->predicate('u'));

        self::assertSame('seed_token IS NULL', DataUniverse::Real->predicate());
        self::assertSame([], DataUniverse::All->conditions('u'));
        self::assertSame(['u.seed_token IS NOT NULL'], DataUniverse::Seed->conditions('u'));
    }

    public function testInclusionHelpers(): void
    {
        self::assertTrue(DataUniverse::Real->includesReal());
        self::assertFalse(DataUniverse::Real->includesSeed());
        self::assertFalse(DataUniverse::Seed->includesReal());
        self::assertTrue(DataUniverse::Seed->includesSeed());
        self::assertTrue(DataUniverse::All->includesReal());
        self::assertTrue(DataUniverse::All->includesSeed());
    }

    /** The enum values are the documented request vocabulary, with no translation layer. */
    public function testEnumValuesMatchTheDocumentedRequestVocabulary(): void
    {
        self::assertSame(['real', 'seed', 'all'], array_column(DataUniverse::cases(), 'value'));
    }
}
