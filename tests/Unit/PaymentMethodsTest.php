declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Commerce\Settings\PaymentMethods;
use CattoLearning\Configuration\SiteMode;
use PHPUnit\Framework\TestCase;

final class PaymentMethodsTest extends TestCase
{
    public function testADemoSiteOffersEftAndTheSimulatedCardAndALiveSiteOnlyEft(): void
    {
        $demo = new PaymentMethods(SiteMode::fixed(SiteMode::DEMO));
        $live = new PaymentMethods(SiteMode::fixed(SiteMode::LIVE));
        self::assertSame(['eft', 'dummy'], $demo->offered());
        self::assertSame(['eft'], $live->offered(), 'A live site never offers the simulated card.');
        self::assertSame(['eft', 'card'], $live->methods(), 'Settings on a live site lists EFT and card only.');
        self::assertSame('The simulated card exists only on a demo site.', $live->problem('dummy'));
        self::assertFalse($live->isOffered('wallet'), 'The wallet is not a payment method: it is always available to spend.');
    }

    public function testCardCannotBeTickedUntilItsKeysAreSetAndStitchIsConnected(): void
    {
        $methods = new PaymentMethods(SiteMode::fixed(SiteMode::LIVE));
        $previous = [$_ENV['STITCH_CLIENT_ID'] ?? null, $_ENV['STITCH_CLIENT_SECRET'] ?? null];
        try {
            $_ENV['STITCH_CLIENT_ID'] = ''; $_ENV['STITCH_CLIENT_SECRET'] = '';
            self::assertSame('Add STITCH_CLIENT_ID and STITCH_CLIENT_SECRET to .env first.', $methods->problem('card'));
            $_ENV['STITCH_CLIENT_ID'] = 'id'; $_ENV['STITCH_CLIENT_SECRET'] = 'secret';
            self::assertSame('Card payments through Stitch are not connected yet.', $methods->problem('card'));
            self::assertNotContains('card', $methods->offered());
        } finally {
            [$_ENV['STITCH_CLIENT_ID'], $_ENV['STITCH_CLIENT_SECRET']] = $previous;
            if ($previous[0] === null) unset($_ENV['STITCH_CLIENT_ID']);
            if ($previous[1] === null) unset($_ENV['STITCH_CLIENT_SECRET']);
        }
    }

    public function testCheckoutAndReceiptsNameTheMethodAndItsProvider(): void
    {
        self::assertSame([['key' => 'eft', 'label' => 'EFT: bank transfer to our bank account']], (new PaymentMethods(SiteMode::fixed(SiteMode::LIVE)))->checkoutOptions());
        self::assertSame('Card: paid on Stitch\'s secure page', PaymentMethods::label('card'));
        self::assertSame('Simulated card (demo site, no money is charged)', PaymentMethods::label('dummy'));
        self::assertSame('EFT (direct bank transfer)', PaymentMethods::receiptLabel('manual_bank'));
        self::assertSame('Card, through Stitch', PaymentMethods::receiptLabel('stitch'));
        self::assertSame('Wallet credit', PaymentMethods::receiptLabel('wallet'));
    }

    public function testNoTemplateCollectsCardDetails(): void
    {
        $root = dirname(__DIR__, 2);
        $files = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($root . '/resources/views', \FilesystemIterator::SKIP_DOTS));
        foreach ($files as $file) {
            if (!str_ends_with((string) $file, '.twig')) continue;
            $source = (string) file_get_contents((string) $file);
            self::assertDoesNotMatchRegularExpression('/autocomplete="cc-|name="(card_number|card|cvv|cvc|expiry|pan)"/i', $source, (string) $file . ' must not collect card details: a card is paid on the provider\'s page.');
        }
    }
}
