declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class SharedControlContractTest extends TestCase
{
    public function testThemesCannotGenerateTheirOwnDatasetControls(): void
    {
        $files = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator(dirname(__DIR__, 2) . '/themes'));
        foreach ($files as $file) {
            if (!$file->isFile() || $file->getExtension() !== 'js') continue;
            $source = (string) file_get_contents($file->getPathname());
            self::assertDoesNotMatchRegularExpression('/\.type\s*=\s*["\']search["\']/', $source, $file->getPathname());
            self::assertStringNotContainsString('gn-table-search', $source);
            self::assertDoesNotMatchRegularExpression('/createElement\(["\'](?:table|progress)["\']\)/', $source, $file->getPathname());
        }
    }

    /** The one search control. Everything else includes it. */
    private const SEARCH_CONTROL = 'resources/views/partials/dataset-search.html.twig';

    /**
     * The one legitimate other search input, and why.
     *
     * The entity lookup answers a different question: it picks a single record to put into a form
     * field, and returns a chosen value rather than filtering a table in place. It is itself a
     * shared control, used the same way everywhere it appears, so it is a second pattern for a
     * second job rather than a second pattern for this one.
     */
    private const ENTITY_LOOKUP = 'resources/views/partials/entity-lookup.html.twig';

    /**
     * No template builds its own search box.
     *
     * A search input outside the shared control is a second implementation by definition, and the
     * two then drift: the modal's copy triggered on the form instead of the input, so it needed
     * Enter while every other search filtered as you typed.
     */
    public function testTheOnlySearchInputLivesInTheSharedControl(): void
    {
        $offenders = [];

        foreach (self::templates() as $path => $source) {
            if ($path === self::SEARCH_CONTROL || $path === self::ENTITY_LOOKUP) {
                continue;
            }
            if (str_contains($source, 'type="search"')) {
                $offenders[] = $path;
            }
        }

        self::assertSame(
            [],
            $offenders,
            "These templates build their own search box instead of including "
            . self::SEARCH_CONTROL . ":\n  " . implode("\n  ", $offenders)
        );
    }

    /**
     * No template offers a data universe as a select element.
     *
     * The scope is chosen with the universe query parameter and the shared switch, so that one
     * mental model covers every list. The picker had a select naming All, Real and Seed, which is
     * both a second control and a second vocabulary for the same idea.
     */
    public function testAFilterIsNeverASelectElement(): void
    {
        $offenders = [];

        foreach (self::templates() as $path => $source) {
            if (preg_match('/<select[^>]*\bname="[^"]*universe[^"]*"/i', $source) === 1) {
                $offenders[] = $path;
            }
        }

        self::assertSame(
            [],
            $offenders,
            "The data universe is chosen through the universe query parameter and "
            . "partials/universe-switch.html.twig, never a select:\n  " . implode("\n  ", $offenders)
        );
    }

    /**
     * A search control and its results region agree on the dataset prefix.
     *
     * The control derives its htmx target and selector from the prefix by convention, so a caller
     * that names one dataset and wraps its rows in another's region gets a search that fires,
     * succeeds and swaps nothing.
     */
    public function testEverySearchControlHasAMatchingResultsRegion(): void
    {
        $offenders = [];

        $templates = self::templates();
        // The results element is often in an included partial, so the region is looked for in the
        // template that declares the search and the results element anywhere in the set.
        $everything = implode("\n", $templates);

        foreach ($templates as $path => $source) {
            if (preg_match_all("/dataset-search\.html.*?ds_name='([a-z_]+)'/s", $source, $matches) < 1) {
                continue;
            }
            foreach (array_unique($matches[1]) as $dataset) {
                if (!str_contains($source, 'id="' . $dataset . '-region"')) {
                    $offenders[] = $path . ' searches ' . $dataset . ' but declares no ' . $dataset . '-region';
                }
                if (!str_contains($everything, 'id="' . $dataset . '-results"')) {
                    $offenders[] = $path . ' searches ' . $dataset . ' but nothing declares ' . $dataset . '-results';
                }
            }
        }

        self::assertSame([], $offenders, implode("\n  ", $offenders));
    }

    /**
     * Every page and partial template, keyed by repository-relative path.
     *
     * @return array<string,string>
     */
    private static function templates(): array
    {
        $root = dirname(__DIR__, 2);
        $templates = [];

        foreach (['resources/views', 'themes'] as $directory) {
            $files = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($root . '/' . $directory));
            foreach ($files as $file) {
                if (!$file->isFile() || $file->getExtension() !== 'twig') {
                    continue;
                }
                $path = strtr($file->getPathname(), '\\', '/');
                $offset = strpos($path, 'resources/views');
                $templates[$offset === false ? $path : substr($path, $offset)] = (string) file_get_contents($path);
            }
        }

        ksort($templates);

        return $templates;
    }
}
