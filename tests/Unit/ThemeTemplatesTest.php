declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\View\Twig\ThemeTemplates;
use PHPUnit\Framework\TestCase;
use Twig\Loader\FilesystemLoader;

final class ThemeTemplatesTest extends TestCase
{
    private const FIXTURES = __DIR__ . '/../Support/fixtures/themes';

    public function testAChildTemplateIsFoundBeforeItsParent(): void
    {
        $loader = new FilesystemLoader();
        (new ThemeTemplates($loader))->use([
            self::FIXTURES . '/child-theme',
            self::FIXTURES . '/parent-theme',
        ]);

        // Shipped only by the child.
        self::assertTrue($loader->exists('@theme/partials/footer.html.twig'));
        // Shipped only by the parent, and reached by falling through.
        self::assertTrue($loader->exists('@theme/base.html.twig'));
        self::assertStringContainsString('parent-base', $loader->getSourceContext('@theme/base.html.twig')->getCode());
    }

    public function testAFamilyWithAWrapperUsesIt(): void
    {
        $templates = new ThemeTemplates(new FilesystemLoader());
        $templates->use([self::FIXTURES . '/parent-theme']);

        self::assertSame('@theme/pages/admin.html.twig', $templates->layoutFor('admin'));
    }

    public function testAFamilyWithoutAWrapperFallsBackToTheBase(): void
    {
        $templates = new ThemeTemplates(new FilesystemLoader());
        $templates->use([self::FIXTURES . '/parent-theme']);

        self::assertSame('@theme/base.html.twig', $templates->layoutFor('content'));
        self::assertSame('@theme/base.html.twig', $templates->layoutFor('catalogue'));
    }

    /** Selecting a theme replaces the namespace rather than adding to it. */
    public function testSwitchingThemeDoesNotLeaveTheOldOneSearchable(): void
    {
        $loader = new FilesystemLoader();
        $templates = new ThemeTemplates($loader);

        $templates->use([self::FIXTURES . '/parent-theme']);
        self::assertTrue($loader->exists('@theme/base.html.twig'));

        $templates->use([self::FIXTURES . '/child-theme']);
        self::assertFalse($loader->exists('@theme/base.html.twig'));
        self::assertTrue($loader->exists('@theme/partials/footer.html.twig'));
    }

    public function testAPlatformPageIsAddressedInItsOwnNamespace(): void
    {
        self::assertSame(
            '@platform/pages/privacy.html.twig',
            (new ThemeTemplates(new FilesystemLoader()))->pageTemplate('privacy')
        );
    }
}
