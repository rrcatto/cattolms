declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class FormActionRowContractTest extends TestCase
{
    public function testEverySaveFormEndsInTheSharedActionRow(): void
    {
        $forms = self::saveForms();

        self::assertGreaterThanOrEqual(
            12,
            count($forms),
            'No save forms were parsed, so this test is examining nothing.'
        );

        $missing = [];
        foreach ($forms as $where => $form) {
            if (!str_contains($form, "ui_template('form.actions')")) {
                $missing[] = $where;
            }
        }

        self::assertSame(
            [],
            $missing,
            "These forms have fields to fill in and a button to commit them, and no action row - so "
            . "'how do I save this' is answered somewhere different on each of them:\n - "
            . implode("\n - ", $missing)
        );
    }

    public function testCoreStatesWhatAnActionRowLooksLike(): void
    {
        // The rule is only worth asserting if the class does something. A separator above it and a
        // secondary slot pushed to the far end are what make Save findable and stop Remove sitting
        // beside it as an equal.
        $css = (string) preg_replace(
            '#/\*.*?\*/#s',
            '',
            (string) file_get_contents(__DIR__ . '/../../public_html/css/catto-platform.css')
        );

        self::assertMatchesRegularExpression('/\.cl-ui-form-actions\{[^}]*border-top:/', $css, 'An action row is separated from the fields.');
        self::assertMatchesRegularExpression('/\.cl-ui-form-actions\{[^}]*display:flex/', $css, 'An action row lays its actions out in a row.');
        self::assertStringContainsString('.cl-ui-form-actions-secondary{margin-left:auto}', $css, 'A destructive action is pushed away from the primary one.');
    }

    /**
     * Every form a reader fills in and saves, keyed by file and the label on its submit.
     *
     * @return array<string,string>
     */
    private static function saveForms(): array
    {
        $found = [];
        foreach (self::templates() as $path) {
            $source = (string) preg_replace('/\{#.*?#\}/s', '', (string) file_get_contents($path));
            foreach (self::matchForms($source) as $form) {
                if (!str_contains($form, "ui('action.button'")) {
                    continue;
                }
                // A form with nothing to fill in is a single-button action - a row menu entry, a
                // toggle, a sign-out - and has no fields for an action row to sit beneath.
                if (preg_match_all('/<(?:input|select|textarea)\b(?![^>]*type="hidden")/', $form) === 0) {
                    continue;
                }
                if (self::isControlRatherThanForm($form)) {
                    continue;
                }
                $label = preg_match('/type="submit"[^>]*>\s*([^<]{0,40})/', $form, $m) === 1 ? trim($m[1]) : '?';
                $found[basename($path) . ' :: ' . $label] = $form;
            }
        }

        return $found;
    }

    private static function isControlRatherThanForm(string $form): bool
    {
        // A modal states its actions in the footer the modal contract already gives it.
        if (str_contains($form, 'modal_actions') || str_contains($form, "ui_template('form.compact-action')")) {
            return true;
        }
        // A cl-ui-list control: pagination, search, a filter. It reads rather than writes.
        if (str_contains($form, 'method="get"') || preg_match('/class="[^"]*(pagination|dataset-search|cl-ui-toolbar)/', $form) === 1) {
            return true;
        }
        // A compact act control: one cl-ui-field with its button against it, no whitespace between.
        if (preg_match('#</(?:select|input)>?<button[^>]*type="submit"#', $form) === 1) {
            return true;
        }
        // An inline row control: the button is the last cell of a row of fields.
        $submit = strrpos($form, "type: 'submit'");

        return $submit !== false && preg_match('/class="col-[^"]*"[^>]*>\s*<button[^>]*$/', substr($form, 0, $submit)) === 1;
    }

    /** @return list<string> */
    private static function matchForms(string $source): array
    {
        preg_match_all('/<form\b.*?<\/form>/s', $source, $matches);

        return $matches[0];
    }

    /** @return list<string> */
    private static function templates(): array
    {
        $files = [];
        $walk = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator(__DIR__ . '/../../resources/views', \FilesystemIterator::SKIP_DOTS)
        );
        foreach ($walk as $entry) {
            if ($entry->isFile() && str_ends_with((string) $entry->getFilename(), '.twig')) {
                $files[] = (string) $entry->getPathname();
            }
        }
        sort($files);

        return $files;
    }
}
