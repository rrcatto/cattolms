declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Course\ReadinessSuggestions;
use PHPUnit\Framework\TestCase;

final class ReadinessSuggestionsTest extends TestCase
{
    public function testModulesAreNamedByTheirNumberAndListTheirStudyParts(): void
    {
        $outline = self::outline();
        $suggestions = ReadinessSuggestions::resolve($outline, [['m2'], ['M1', 'm2'], ['m7', 'nothing-here'], ['m02']]);
        self::assertSame([1, 2], array_column($suggestions, 'module'), 'In course order, each once.');
        self::assertSame([1, 3], array_column($suggestions, 'questions'), 'm02 and M2 name Module 2 too; a reference to nothing counts for nothing.');
        self::assertSame('Module 1: Getting started', $suggestions[0]['heading']);
        self::assertSame(['Presentation', 'Lesson', 'Summary'], array_column($suggestions[0]['parts'], 'label'), 'Never the practical work or the assessment.');
        self::assertSame(['Presentation (locked)', 'Lesson'], array_map(static fn(array $part): string => $part['label'] . ($part['locked'] ? ' (locked)' : ''), $suggestions[1]['parts']));
        self::assertSame('3 days', $suggestions[1]['parts'][0]['opens_in']);
        self::assertSame(11, $suggestions[0]['link']['id'] ?? null, 'A module with a page of its own links to it.');
        self::assertNull($suggestions[1]['link'], 'One without does not.');
    }

    public function testAModuleWinsOverACourseItemOfTheSameKeyAndAnItemKeySuggestsItsPart(): void
    {
        $outline = self::outline();
        $outline[] = ['id' => 40, 'parent_node_id' => null, 'node_type' => 'item', 'part' => 'lesson', 'item_key' => 'm1', 'item_title' => 'A lesson keyed m1', 'item_type' => 'html_lesson'];
        $suggestions = ReadinessSuggestions::resolve($outline, [['m1'], ['glossary-lesson']]);
        self::assertSame([1, null], array_column($suggestions, 'module'));
        self::assertSame('Lesson: Glossary', $suggestions[1]['heading']);
        self::assertSame(30, $suggestions[1]['link']['id'] ?? null);
        self::assertSame([], ReadinessSuggestions::resolve($outline, [['m9'], []]), 'Nothing to suggest.');
    }

    public function testThePublicPreviewOpensOnlyWhatItShows(): void
    {
        $suggestions = ReadinessSuggestions::resolve(self::outline(), [['m1'], ['m2'], ['glossary-lesson']], [11 => true, 12 => true, 13 => true]);
        self::assertSame(['Presentation', 'Lesson'], array_column($suggestions[0]['parts'], 'label'));
        self::assertFalse($suggestions[0]['elsewhere']);
        self::assertSame([], $suggestions[1]['parts']);
        self::assertTrue($suggestions[1]['elsewhere'], 'A module the preview does not show is in the full course.');
        self::assertNull($suggestions[2]['link']);
        self::assertTrue($suggestions[2]['elsewhere']);
    }

    /** @return list<array<string,mixed>> */
    private static function outline(): array
    {
        $item = static fn(int $id, ?int $parent, string $part, string $title, array $extra = []): array => $extra + ['id' => $id, 'parent_node_id' => $parent, 'node_type' => 'item', 'part' => $part, 'item_key' => 'key-' . $id, 'item_title' => $title, 'item_type' => 'html_lesson'];
        return [
            ['id' => 10, 'parent_node_id' => null, 'node_type' => 'item', 'part' => 'diagnostic', 'item_key' => 'readiness', 'item_title' => 'Readiness Check', 'item_type' => 'diagnostic'],
            ['id' => 11, 'parent_node_id' => null, 'node_type' => 'section', 'section_number' => 1, 'section_title' => 'Getting started', 'section_introduction_html' => '<p>What this module covers.</p>'],
            $item(12, 11, 'presentation', 'What you will learn', ['item_type' => 'slide_deck']),
            $item(13, 11, 'lesson', 'Getting started'),
            $item(14, 11, 'summary', 'Summary'),
            $item(15, 11, 'practical', 'Practical work', ['item_type' => 'practical']),
            $item(16, 11, 'assessment', 'Getting started assessment', ['item_type' => 'assessment']),
            ['id' => 20, 'parent_node_id' => null, 'node_type' => 'section', 'section_number' => 2, 'section_title' => 'Going further', 'section_introduction_html' => ''],
            $item(21, 20, 'presentation', 'What you will learn', ['item_type' => 'slide_deck', 'is_locked' => true, 'remaining_delay_label' => '3 days']),
            $item(22, 20, 'lesson', 'Going further'),
            $item(30, null, 'lesson', 'Glossary', ['item_key' => 'glossary-lesson']),
        ];
    }
}
