Protects the identity values every template may read, and the navigation bar's use of the display
name.

Two rules, and they are the same rule seen from either end. `viewIdentity()` answers for a signed-in
reader and for a signed-out one, and Twig runs with `strict_variables`: a key defined on one branch
and forgotten on the other is not a blank on the page, it is a 500 for exactly half the audience.
So the branches must agree on their key set, whatever that set grows to.

The other end is the navigation bar, which shows the *display name* - `JaneD` - rather than the
full name it is not an abbreviation of. Owner's instruction, 2026/09/12. A bar has one line to
spend, and `identity_name` spends it on middle names nobody asked this control to show.

A source contract rather than a render: no theme is installed in a unit test, and standing the whole
Gilded Noir layout up to read one chip would assert far more about the harness than about the rule.

