declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Http\Controller\BaseController;
use PHPUnit\Framework\TestCase;
use ReflectionMethod;

final class IdentityDisplayNameContractTest extends TestCase
{
    /**
     * The two branches of viewIdentity() must define the same identity keys.
     *
     * Read from the method's own source rather than from a rendered page, because proving it by
     * rendering would need both a signed-in and a signed-out request against a real AuthService -
     * which is final, so it cannot stand in for itself - and that is an integration test asking a
     * question the source already answers.
     */
    public function testBothIdentityBranchesDefineTheSameKeys(): void
    {
        [$signedIn, $signedOut] = $this->identityBranches();

        self::assertNotSame([], $signedIn, 'The signed-in branch defines no identity keys at all.');
        self::assertSame(
            $signedIn,
            $signedOut,
            'viewIdentity() must define every identity_* key on both branches. Twig runs with '
            . 'strict_variables, so a key defined only for a signed-in reader is a 500 for '
            . 'everybody else.'
        );
    }

    /** The display name is one of those keys, and is the reason this contract was written. */
    public function testTheDisplayNameIsOneOfThem(): void
    {
        [$signedIn] = $this->identityBranches();

        self::assertContains('identity_display_name', $signedIn);
    }

    /**
     * The navigation chip names the reader by display name, never by full name.
     *
     * The fallback is deliberate and is asserted with it: display_name is a nullable column, so a
     * reader who has never set one must still be named rather than left as an empty chip.
     */
    public function testGildedNoirNavigationChipUsesTheDisplayName(): void
    {
        foreach (['RichardC', ''] as $displayName) {
            $html = \CattoLearning\Tests\Support\RenderHarness::render('partials/account/identity-compact', [
                'identity_display_name' => $displayName, 'identity_name' => 'Richard Catto',
                'identity_email' => 'reader@example.test', 'user' => ['name' => 'Fallback'],
            ]);
            self::assertStringContainsString('<strong class="cl-identity-name">' . ($displayName ?: 'Richard Catto') . '</strong>', $html);
        }
    }

    /**
     * The identity keys assigned on each branch of viewIdentity(), sorted.
     *
     * @return array{0:list<string>,1:list<string>}
     */
    private function identityBranches(): array
    {
        $method = new ReflectionMethod(BaseController::class, 'viewIdentity');
        $file = (string) file_get_contents((string) $method->getFileName());
        $lines = explode("\n", $file);
        $body = implode("\n", array_slice(
            $lines,
            $method->getStartLine() - 1,
            $method->getEndLine() - $method->getStartLine() + 1
        ));

        $opening = strpos($body, 'if ($currentUser !== null) {');
        self::assertNotFalse($opening, 'viewIdentity() no longer branches on the current user.');
        $else = strpos($body, '} else {', $opening);
        self::assertNotFalse($else, 'viewIdentity() has no signed-out branch.');
        $closing = strpos($body, "\n        }\n", $else);
        self::assertNotFalse($closing, 'The signed-out branch is not closed where this scan expects.');

        return [
            $this->identityKeys(substr($body, $opening, $else - $opening)),
            $this->identityKeys(substr($body, $else, $closing - $else)),
        ];
    }

    /** @return list<string> */
    private function identityKeys(string $source): array
    {
        preg_match_all("/\\\$data\\['(identity_[a-z_]+)'\\]\\s*=/", $source, $matches);
        $keys = array_values(array_unique($matches[1]));
        sort($keys);

        return $keys;
    }

}
