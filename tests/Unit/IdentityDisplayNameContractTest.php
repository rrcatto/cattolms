declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Http\ViewIdentity;
use PHPUnit\Framework\TestCase;
use ReflectionMethod;

final class IdentityDisplayNameContractTest extends TestCase
{
    /**
     * The two branches of viewIdentity() must define the same identity keys.
     *
     * Read from the method's own source rather than from a rendered page, because proving it by
     * rendering would need both a signed-in and a signed-out request against a real AuthService -
     * which is final, so it cannot stand in for itself - and that is an integration test asking a
     * question the source already answers.
     */
    public function testBothIdentityBranchesDefineTheSameKeys(): void
    {
        [$signedIn, $signedOut] = $this->identityBranches();

        self::assertNotSame([], $signedIn, 'The signed-in branch defines no identity keys at all.');
        self::assertSame(
            $signedIn,
            $signedOut,
            'viewIdentity() must define every identity_* key on both branches. Twig runs with '
            . 'strict_variables, so a key defined only for a signed-in reader is a 500 for '
            . 'everybody else.'
        );
    }

    /** The display name is one of those keys, and is the reason this contract was written. */
    public function testTheDisplayNameIsOneOfThem(): void
    {
        [$signedIn] = $this->identityBranches();

        self::assertContains('identity_display_name', $signedIn);
    }

    /**
     * The navigation chip names the reader by display name, never by full name.
     *
     * The fallback is deliberate and is asserted with it: display_name is a nullable column, so a
     * reader who has never set one must still be named rather than left as an empty chip.
     */
    public function testGildedNoirNavigationChipUsesTheDisplayName(): void
    {
        foreach (['ThandiN', ''] as $displayName) {
            $html = \CattoLearning\Tests\Support\RenderHarness::render('partials/account/identity-compact', [
                'identity_display_name' => $displayName, 'identity_name' => 'Thandi Nkosi',
                'identity_email' => 'reader@example.test', 'user' => ['name' => 'Fallback'], 'identity_reference' => 'CL202601010001K',
                'identity_placement' => 'navigation',
            ]);
            // The name, then the reader's account reference under its label, opening their profile (owner, 2026-10-21).
            self::assertStringContainsString('<strong class="cl-identity-name">' . ($displayName ?: 'Thandi Nkosi') . '</strong> <span class="cl-identity-account"><span class="cl-identity-account-label">Account Reference:</span> <a class="cl-identity-reference" href="/account/profile"', $html);
            self::assertStringContainsString('>CL-20260101-0001-K</a>', $html);
        }
    }

    /** Where the identity band is on the page, the header chip leaves the account reference to it: once on a page. */
    public function testTheHeaderChipLeavesTheAccountReferenceToTheBand(): void
    {
        $html = \CattoLearning\Tests\Support\RenderHarness::render('partials/account/identity-compact', [
            'identity_display_name' => 'ThandiN', 'identity_name' => 'Thandi Nkosi', 'identity_email' => 'reader@example.test',
            'user' => ['name' => 'Fallback'], 'identity_reference' => 'CL202601010001K', 'identity_placement' => 'page',
        ]);
        self::assertStringContainsString('<strong class="cl-identity-name">ThandiN</strong>', $html);
        self::assertStringNotContainsString('cl-identity-account', $html);
        self::assertStringNotContainsString('CL-20260101-0001-K', $html);
    }

    /**
     * The identity band's account reference sits at its right edge under the label "Account Reference:" and opens the
     * person's profile (owner, 2026-10-21: "Without a label, people will not know what it is").
     */
    public function testTheIdentityBandLinksTheAccountReferenceToTheProfile(): void
    {
        $html = \CattoLearning\Tests\Support\RenderHarness::render('partials/account/identity-head', [
            'is_authenticated' => true, 'identity_name' => 'Thandi Nkosi', 'identity_email' => 'reader@example.test',
            'identity_reference' => 'CL202601010001K', 'identity_roles' => [], 'identity_status' => '', 'identity_image' => '',
        ]);
        self::assertMatchesRegularExpression('#<h2 class="cl-identity-name">\s*Thandi Nkosi\s*</h2>#', $html);
        self::assertMatchesRegularExpression('#<div class="cl-identity-account">\s*<span class="cl-identity-account-label">Account Reference:</span>\s*<a class="cl-identity-reference" href="/account/profile" title="Open your profile">CL-20260101-0001-K</a>\s*</div>#', $html);
    }

    /**
     * The identity keys assigned on each branch of viewIdentity(), sorted.
     *
     * @return array{0:list<string>,1:list<string>}
     */
    private function identityBranches(): array
    {
        $method = new ReflectionMethod(ViewIdentity::class, 'of');
        $file = (string) file_get_contents((string) $method->getFileName());
        $lines = explode("\n", $file);
        $body = implode("\n", array_slice(
            $lines,
            $method->getStartLine() - 1,
            $method->getEndLine() - $method->getStartLine() + 1
        ));

        $opening = strpos($body, 'if ($currentUser !== null) {');
        self::assertNotFalse($opening, 'ViewIdentity::of() no longer branches on the current user.');
        $else = strpos($body, '} else {', $opening);
        self::assertNotFalse($else, 'ViewIdentity::of() has no signed-out branch.');
        $closing = strpos($body, "\n        }\n", $else);
        self::assertNotFalse($closing, 'The signed-out branch is not closed where this scan expects.');

        return [
            $this->identityKeys(substr($body, $opening, $else - $opening)),
            $this->identityKeys(substr($body, $else, $closing - $else)),
        ];
    }

    /** @return list<string> */
    private function identityKeys(string $source): array
    {
        preg_match_all("/\\\$data\\['(identity_[a-z_]+)'\\]\\s*=/", $source, $matches);
        $keys = array_values(array_unique($matches[1]));
        sort($keys);

        return $keys;
    }

}
