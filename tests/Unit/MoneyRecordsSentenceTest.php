declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Commerce\Application\MoneyRecords;
use CattoLearning\Support\Money;
use PHPUnit\Framework\TestCase;

final class MoneyRecordsSentenceTest extends TestCase
{
    private static function r(int $minor): string
    {
        return Money::ofMinorUnits($minor, 'ZAR')->format();
    }

    /** @param array<string,mixed> $row */
    private static function line(string $kind, array $row = []): string
    {
        return MoneyRecords::ledgerSentence($row + ['kind' => $kind, 'account_name' => 'Thandi Nkosi', 'amount_minor' => 50000, 'currency' => 'ZAR',
            'order_id' => 183, 'method' => 'stitch', 'external_reference' => null, 'memo' => null]);
    }

    public function testEveryLedgerLineSaysWhoHowMuchHowAndForWhichOrder(): void
    {
        self::assertSame('Thandi Nkosi paid ' . self::r(50000) . ' by card for order CL-00000183.', self::line('payment_received', ['external_reference' => 'gateway-id']),
            'A card payment does not show the gateway’s own id.');
        self::assertSame('Thandi Nkosi paid ' . self::r(50000) . ' by EFT for order CL-00000183, reference FNB-123.', self::line('payment_received', ['method' => 'eft', 'external_reference' => 'FNB-123']));
        self::assertSame('Stitch charged ' . self::r(50000) . ' to process Thandi Nkosi\'s card payment for order CL-00000183.', self::line('processor_fee'));
        self::assertSame('Thandi Nkosi paid ' . self::r(50000) . ' from their wallet for order CL-00000183.', self::line('wallet_payment', ['method' => 'wallet']));
        self::assertSame('Thandi Nkosi was refunded ' . self::r(50000) . ' as wallet credit for order CL-00000183.', self::line('refund_to_wallet'));
        self::assertSame(self::r(50000) . ' was kept back from Thandi Nkosi\'s refund for order CL-00000183 to cover the EFT refund fee.', self::line('refund_deduction', ['memo' => 'EFT refund fee']));
        self::assertSame(self::r(50000) . ' was paid back to Thandi Nkosi by EFT, reference EFT-REFUND-1.', self::line('refund_paid', ['method' => 'eft', 'external_reference' => 'EFT-REFUND-1', 'order_id' => null]));
        self::assertSame(self::r(50000) . ' of Thandi Nkosi\'s wallet credit expired unused.', self::line('credit_expired', ['order_id' => null]));
        self::assertSame('The customer paid ' . self::r(50000) . ' by card for order CL-00000183.', self::line('payment_received', ['account_name' => '']), 'A line without an account still reads.');
    }

    public function testEveryPaymentStepSaysWhatBecameOfThePayment(): void
    {
        $step = static fn(string $gateway, string $state): string => MoneyRecords::paymentEventSentence(['account_name' => 'Thandi Nkosi', 'gateway' => $gateway,
            'amount_minor' => 50000, 'currency' => 'ZAR', 'order_id' => 183, 'state' => $state]);
        self::assertSame('Thandi Nkosi\'s card payment of ' . self::r(50000) . ' for order CL-00000183 went through: the money was received.', $step('dummy', 'paid'));
        self::assertSame('Thandi Nkosi\'s card payment of ' . self::r(50000) . ' for order CL-00000183 failed: no money was taken.', $step('dummy', 'failed'));
        self::assertSame('Thandi Nkosi\'s EFT payment of ' . self::r(50000) . ' for order CL-00000183 was received and recorded.', $step('manual_bank', 'paid'));
        self::assertSame('Thandi Nkosi\'s wallet payment of ' . self::r(50000) . ' for order CL-00000183 was taken from the wallet.', $step('wallet', 'paid'));
    }

    public function testEveryTrailEventIsASentence(): void
    {
        $event = static fn(string $name, array $payload, array $row = []): string => MoneyRecords::trailSentence($row + ['event' => $name, 'payload' => json_encode($payload),
            'actor_name' => 'Thandi Nkosi', 'account_name' => 'Thandi Nkosi', 'order_id' => 183, 'currency' => 'ZAR', 'order_total_minor' => 50000,
            'payment_amount_minor' => null, 'payment_gateway' => null, 'course_title' => 'Bookkeeping']);
        self::assertSame('Thandi Nkosi placed order CL-00000183 for ' . self::r(50000) . '.', $event('order.placed', ['total_minor' => 50000]));
        self::assertSame('Invoice INV-00000017 was issued for order CL-00000183.', $event('document.issued', ['kind' => 'invoice', 'number' => 'INV-00000017']));
        self::assertSame('The card payment of ' . self::r(50000) . ' for order CL-00000183 was confirmed.', $event('payment.confirmed', ['payment_id' => 'x'], ['payment_amount_minor' => 50000, 'payment_gateway' => 'dummy', 'actor_name' => null]));
        self::assertSame('Bookkeeping started.', $event('entitlement.learner_started', ['enrolment_id' => 9]));
        self::assertSame('Access to Bookkeeping was withdrawn because it was refunded.', $event('entitlement.revoked', ['reason' => 'refund:3']));
        self::assertSame('Thandi Nkosi approved a refund of ' . self::r(50000) . ' on Bookkeeping as money back, overriding the Refund Policy.',
            $event('refund.approved', ['amount_minor' => 50000, 'destination' => 'money_back', 'policy_refusal' => 'Started.']));
        self::assertSame('Order CL-00000183 was not paid by its due date, so it was cancelled.', $event('order.payment_deadline_elapsed', [], ['actor_name' => null]));
    }

    public function testAnOrdersStatusIsAWordWithANote(): void
    {
        $status = static fn(array $row): array => MoneyRecords::orderStatus($row + ['currency' => 'ZAR', 'total_minor' => 50000, 'paid_minor' => 0, 'refunded_minor' => 0,
            'payment_method' => 'eft', 'company_id' => null, 'bought' => 'Bookkeeping']);
        self::assertSame(['label' => 'Waiting for payment', 'note' => self::r(30000) . ' due by EFT', 'tone' => 'warning'], $status(['state' => 'awaiting_payment', 'paid_minor' => 20000]));
        self::assertSame(['label' => 'Paid', 'note' => 'Course open', 'tone' => 'success'], $status(['state' => 'fulfilled', 'paid_minor' => 50000]));
        self::assertSame(['label' => 'Paid', 'note' => 'Credits added', 'tone' => 'success'], $status(['state' => 'fulfilled', 'company_id' => 4]));
        self::assertSame(['label' => 'Needs your review', 'note' => 'Paid; release it to open access', 'tone' => 'warning'], $status(['state' => 'manual_review']));
        self::assertSame(['label' => 'Refunded', 'note' => self::r(50000) . ' refunded', 'tone' => 'neutral'], $status(['state' => 'refunded', 'refunded_minor' => 50000]));
    }
}
