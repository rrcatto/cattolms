    public function testDataMustFitTheRegistry(): void
    {
        $data = DocumentSampleData::for(DocumentType::Certificate);
        foreach ([
            'unknown key' => [['learner.password' => 'x'] + $data, 'learner.password is not a registered placeholder'],
            'missing required' => [array_diff_key($data, ['learner.name' => true]), 'learner.name is required'],
            'wrong kind' => [['course.completion_date' => 'soon'] + $data, 'course.completion_date must be a date'],
        ] as $case => [$values, $message]) {
            try {
                $this->renderer->renderSource(DocumentType::Certificate, '<p>{{ learner.name }}</p>', '', DocumentType::Certificate->defaultSettings(), $values);
                self::fail('Bad data is refused: ' . $case);
            } catch (DocumentDataException $bad) {
                self::assertStringContainsString($message, $bad->getMessage(), $case);
            }
        }
        $invoice = DocumentSampleData::for(DocumentType::Invoice);
        $invoice['items'][0]['colour'] = 'red';
        $this->expectException(DocumentDataException::class);
        $this->renderer->renderSource(DocumentType::Invoice, '<p>x</p>', '', DocumentType::Invoice->defaultSettings(), $invoice);
    }

    public function testRenderedDocumentCarriesThePageBoxAndItsTemplateReference(): void
    {
        $settings = new PageSettings('A5', 'portrait', 10, 10, 10, 10);
        $document = $this->renderer->renderSource(DocumentType::Certificate, '<p>{{ learner.name }}</p>', 'p{color:#111}', $settings, DocumentSampleData::for(DocumentType::Certificate), 7, 42, 3);
        self::assertStringStartsWith('<!DOCTYPE html>', $document->html);
        self::assertStringContainsString('@page{size:A5 portrait;margin:10mm 10mm 10mm 10mm}', $document->html);
        self::assertStringContainsString('<style>p{color:#111}</style>', $document->html);
        self::assertSame(['document_type' => 'certificate', 'template_id' => 7, 'template_version_id' => 42, 'template_version_number' => 3], $document->reference());
    }

    public function testEverySourceDefaultIsValidAndRendersItsSampleDocumentAsAPdf(): void
    {
        foreach (DocumentType::cases() as $type) {
            if ($type === DocumentType::Certificate) {
                continue; // Certificates are designs compiled from their looks: CertificateDesignTest.
            }
            $default = DocumentTemplateDefaults::for($type);
            $document = $this->renderer->renderSource($type, $default['html'], $default['css'], $type->defaultSettings(), DocumentSampleData::for($type));
            self::assertStringNotContainsString('{{', $document->body, $type->value . ' renders every placeholder.');
            $pdf = (new DocumentPdfRenderer())->render($document);
            self::assertStringStartsWith('%PDF-', $pdf, $type->value . ' becomes a PDF.');
            self::assertGreaterThan(1000, strlen($pdf));
        }
    }

    /** @return list<string> */
