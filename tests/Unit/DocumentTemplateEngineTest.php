declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Commerce\Document\FinancialDocumentDesign;
use CattoLearning\Commerce\Document\FinancialDocumentDesignCompiler;
use CattoPHP\Document\DocumentRenderer;
use CattoPHP\Document\DocumentDataException;
use CattoPHP\Document\PdfRenderer;
use CattoLearning\Document\DocumentSampleData;
use CattoLearning\Document\DocumentTemplateRenderer;
use CattoLearning\Document\DocumentTemplateRepository;
use CattoLearning\Document\DocumentType;
use CattoPHP\Document\PageSettings;
use CattoPHP\Document\ValueFormatter;
use CattoLearning\Document\Template\PlaceholderRegistry;
use CattoPHP\Document\TemplateValidator;
use CattoPHP\Document\TemplateValidationException;
use CattoLearning\Infrastructure\Persistence\Database;
use DateTimeZone;
use PHPUnit\Framework\TestCase;

final class DocumentTemplateEngineTest extends TestCase
{
    private DocumentTemplateRenderer $renderer;
    private TemplateValidator $validator;

    protected function setUp(): void
    {
        $registry = new PlaceholderRegistry();
        $this->validator = new TemplateValidator();
        $this->renderer = new DocumentTemplateRenderer(
            new DocumentTemplateRepository($this->createStub(Database::class)),
            $registry,
            new DocumentRenderer($this->validator, new ValueFormatter(new DateTimeZone('Africa/Johannesburg'))),
        );
    }

    public function testAnUnknownPlaceholderIsAnErrorWithASuggestionNeverABlank(): void
    {
        $errors = $this->errors(DocumentType::Invoice, "<p>x</p>\n<p>{{ invoice.nubmer }}</p>");
        self::assertCount(1, $errors);
        self::assertStringContainsString('Unknown placeholder {{ invoice.nubmer }} on line 2', $errors[0]);
        self::assertStringContainsString('did you mean {{ invoice.number }}', $errors[0]);

        // A placeholder of another document type is unknown here.
        self::assertStringContainsString('not a certificate placeholder', implode(' ', $this->errors(DocumentType::Certificate, '{{ invoice.number }}')));
        // Unregistered object traversal is refused too.
        self::assertNotSame([], $this->errors(DocumentType::Invoice, '{{ customer.user.password_hash }}'));
    }

    public function testRepeatingFieldsAreOnlyKnownInsideTheirBlockAndBlocksDoNotNest(): void
    {
        self::assertStringContainsString('only available inside {{#each items}}', implode(' ', $this->errors(DocumentType::Invoice, '{{ item.description }}')));
        self::assertStringContainsString('cannot be nested', implode(' ', $this->errors(DocumentType::Invoice, '{{#each items}}{{#each items}}{{/each}}{{/each}}')));
        self::assertStringContainsString('has no repeating data', implode(' ', $this->errors(DocumentType::Certificate, '{{#each items}}{{/each}}')));
        self::assertStringContainsString('Unknown condition', implode(' ', $this->errors(DocumentType::Invoice, '{{#if invoice.colour}}x{{/if}}')));
        self::assertSame([], $this->errors(DocumentType::Invoice, '{{#if items}}{{#each items}}{{ item.paid }}{{/each}}{{else}}None{{/if}}'));
    }

    public function testEachDocumentTypeHasItsDefaultPage(): void
    {
        self::assertSame(1123, DocumentType::Certificate->defaultSettings()->widthPx(), 'A certificate is A4 landscape by default.');
        self::assertSame('portrait', DocumentType::Invoice->defaultSettings()->orientation);
        self::assertStringStartsWith('@page{size:A4 portrait;margin:18mm 16mm 18mm 16mm}', DocumentType::Invoice->defaultSettings()->css());
    }

    public function testRepeatingAndConditionalContentRenders(): void
    {
        $html = '{{#each items}}[{{ item.description }}:{{ item.paid }}{{#if item.discount}} less {{ item.discount }}{{/if}}]{{/each}}'
            . '{{#if items}}{{else}}No lines{{/if}}|{{#if customer.tax_number}}VAT {{ customer.tax_number }}{{else}}no VAT{{/if}}';
        $data = DocumentSampleData::for(DocumentType::Invoice);
        $body = $this->renderer->renderSource(DocumentType::Invoice, $html, '', DocumentType::Invoice->defaultSettings(), $data)->body;
        self::assertSame(3, substr_count($body, '['), 'Every line renders.');
        self::assertStringContainsString('[Fire Safety for Workplace Supervisors:', $body);
        self::assertStringContainsString('|VAT 4000000001', $body);

        $data['items'] = [];
        $data['customer.tax_number'] = null;
        $body = $this->renderer->renderSource(DocumentType::Invoice, $html, '', DocumentType::Invoice->defaultSettings(), $data)->body;
        self::assertSame('No lines|no VAT', $body, 'Zero lines and an absent optional value are handled.');
    }

    public function testRenderedValuesCannotInjectMarkupOrTemplateSyntax(): void
    {
        $data = DocumentSampleData::for(DocumentType::Certificate);
        $data['learner.name'] = '<img src=x onerror=alert(1)> {{ business.name }} {% include "x" %}';
        $body = $this->renderer->renderSource(DocumentType::Certificate, '<h1>{{ learner.name }}</h1>', '', DocumentType::Certificate->defaultSettings(), $data)->body;
        self::assertSame('<h1>&lt;img src=x onerror=alert(1)&gt; {{ business.name }} {% include &quot;x&quot; %}</h1>', $body, 'A value is text: it is escaped and never parsed as a template.');
    }

    public function testDataMustFitTheRegistry(): void
    {
        $data = DocumentSampleData::for(DocumentType::Certificate);
        foreach ([
            'unknown key' => [['learner.password' => 'x'] + $data, 'learner.password is not a registered placeholder'],
            'missing required' => [array_diff_key($data, ['learner.name' => true]), 'learner.name is required'],
            'wrong kind' => [['course.completion_date' => 'soon'] + $data, 'course.completion_date must be a date'],
        ] as $case => [$values, $message]) {
            try {
                $this->renderer->renderSource(DocumentType::Certificate, '<p>{{ learner.name }}</p>', '', DocumentType::Certificate->defaultSettings(), $values);
                self::fail('Bad data is refused: ' . $case);
            } catch (DocumentDataException $bad) {
                self::assertStringContainsString($message, $bad->getMessage(), $case);
            }
        }
        $invoice = DocumentSampleData::for(DocumentType::Invoice);
        $invoice['items'][0]['colour'] = 'red';
        $this->expectException(DocumentDataException::class);
        $this->renderer->renderSource(DocumentType::Invoice, '<p>x</p>', '', DocumentType::Invoice->defaultSettings(), $invoice);
    }

    public function testRenderedDocumentCarriesThePageBoxAndItsTemplateReference(): void
    {
        $settings = new PageSettings('A5', 'portrait', 10, 10, 10, 10);
        $document = $this->renderer->renderSource(DocumentType::Certificate, '<p>{{ learner.name }}</p>', 'p{color:#111}', $settings, DocumentSampleData::for(DocumentType::Certificate), 7, 42, 3);
        self::assertStringStartsWith('<!DOCTYPE html>', $document->html);
        self::assertStringContainsString('@page{size:A5 portrait;margin:10mm 10mm 10mm 10mm}', $document->html);
        self::assertStringContainsString('<style>p{color:#111}</style>', $document->html);
        self::assertSame(['document_type' => 'certificate', 'template_id' => 7, 'template_version_id' => 42, 'template_version_number' => 3], $document->reference());
    }

    public function testTheStandardFinancialDesignIsValidAndRendersEachSampleDocumentAsAPdf(): void
    {
        // Certificates are designs compiled from their looks (CertificateDesignTest); financial
        // documents from the financial document design (FinancialDocumentsTest).
        foreach (FinancialDocumentDesign::types() as $type) {
            $default = (new FinancialDocumentDesignCompiler())->compile(FinancialDocumentDesign::standard(), $type);
            $document = $this->renderer->renderSource($type, $default['html'], $default['css'], $default['settings'], DocumentSampleData::for($type));
            self::assertStringNotContainsString('{{', $document->body, $type->value . ' renders every placeholder.');
            $pdf = (new PdfRenderer())->render($document);
            self::assertStringStartsWith('%PDF-', $pdf, $type->value . ' becomes a PDF.');
            self::assertGreaterThan(1000, strlen($pdf));
        }
    }

    /** @return list<string> */
    private function errors(DocumentType $type, string $html, string $css = ''): array
    {
        try {
            $this->validator->validate((new PlaceholderRegistry())->forType($type), $type->label(), $html, $css);
            return [];
        } catch (TemplateValidationException $invalid) {
            return $invalid->errors;
        }
    }
