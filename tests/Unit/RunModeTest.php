declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Configuration\RunMode;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

final class RunModeTest extends TestCase
{
    /** @var array{0:?string,1:?string,2:string|false} */
    private array $before;

    protected function setUp(): void
    {
        $this->before = [$_ENV['APP_ENV'] ?? null, $_SERVER['APP_ENV'] ?? null, getenv('APP_ENV')];
    }

    protected function tearDown(): void
    {
        [$env, $server, $getenv] = $this->before;
        if ($env === null) unset($_ENV['APP_ENV']); else $_ENV['APP_ENV'] = $env;
        if ($server === null) unset($_SERVER['APP_ENV']); else $_SERVER['APP_ENV'] = $server;
        putenv($getenv === false ? 'APP_ENV' : 'APP_ENV=' . $getenv);
    }

    /** @return iterable<string,array{0:?string,1:string,2:bool}> */
    public static function values(): iterable
    {
        yield 'production' => ['production', RunMode::PRODUCTION, false];
        yield 'Production' => ['Production', RunMode::PRODUCTION, false];
        yield 'PRODUCTION' => ['PRODUCTION', RunMode::PRODUCTION, false];
        yield 'development' => ['development', RunMode::DEVELOPMENT, true];
        yield 'prod, not production' => ['prod', RunMode::DEVELOPMENT, true];
        yield 'empty' => ['', RunMode::DEVELOPMENT, true];
        yield 'absent' => [null, RunMode::DEVELOPMENT, true];
    }

    #[DataProvider('values')]
    public function testProductionOnlyWhenAppEnvSaysSoAndDebuggingFollows(?string $value, string $environment, bool $debug): void
    {
        if ($value === null) {
            unset($_ENV['APP_ENV'], $_SERVER['APP_ENV']);
            putenv('APP_ENV');
        } else {
            $_ENV['APP_ENV'] = $_SERVER['APP_ENV'] = $value;
            putenv('APP_ENV=' . $value);
        }
        self::assertSame([$environment, $debug], [RunMode::environment(), RunMode::debug()]);
    }

    public function testNothingReadsAppDebug(): void
    {
        $root = dirname(__DIR__, 2);
        $readers = [];
        $files = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($root . '/src', \FilesystemIterator::SKIP_DOTS));
        foreach ([...iterator_to_array($files, false), new \SplFileInfo($root . '/bin/console'), new \SplFileInfo($root . '/phinx.php')] as $file) {
            if (!$file instanceof \SplFileInfo || !$file->isFile()) continue;
            if (preg_match('/[\'"]APP_DEBUG[\'"]/', (string) file_get_contents($file->getPathname())) === 1) $readers[] = substr($file->getPathname(), strlen($root) + 1);
        }
        self::assertSame([], $readers, 'Debugging follows APP_ENV (Configuration\RunMode); APP_DEBUG is read nowhere.');
        self::assertDoesNotMatchRegularExpression('/^APP_DEBUG=/m', (string) file_get_contents($root . '/.env.example'));
    }
}
