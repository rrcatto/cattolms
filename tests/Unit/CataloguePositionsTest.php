declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Course\CataloguePositions;
use PHPUnit\Framework\TestCase;

final class CataloguePositionsTest extends TestCase
{
    private const RANGES = ['GDN' => 1000, 'ART' => 2000, 'MUS' => 3000];

    public function testAnEmptyRangeStartsAtItsStart(): void
    {
        self::assertSame(1000, CataloguePositions::next(self::RANGES, 'GDN-101', []));
        self::assertSame(2000, CataloguePositions::next(self::RANGES, 'ART-101', [500, 1000, 1100, 3000]), 'Positions outside the range do not count.');
    }

    public function testAUsedRangeGoesOneHundredAfterItsHighest(): void
    {
        self::assertSame(1400, CataloguePositions::next(self::RANGES, 'GDN-103', [1000, 1100, 1300, 2000, 2100]));
        self::assertSame(3200, CataloguePositions::next(self::RANGES, 'MUS-301', [3000, 3100]), 'The last range runs on without end.');
        self::assertSame(1150, CataloguePositions::next(self::RANGES, 'GDN-2', [1050]));
    }

    public function testAFullRangeTakesTheMidpointThenNothing(): void
    {
        self::assertSame(1950, CataloguePositions::next(self::RANGES, 'GDN-111', [1000, 1900]));
        self::assertSame(1999, CataloguePositions::next(self::RANGES, 'GDN-112', [1998]));
        self::assertNull(CataloguePositions::next(self::RANGES, 'GDN-113', [1999]), 'No whole number left before the next range.');
    }

    public function testAPrefixWithoutARangeGetsNothing(): void
    {
        self::assertNull(CataloguePositions::next(self::RANGES, 'LIT-101', []));
        self::assertNull(CataloguePositions::next([], 'GDN-101', []));
        self::assertSame(1000, CataloguePositions::next(self::RANGES, 'gdn-101', []), 'The prefix is read in capitals.');
        self::assertSame(1000, CataloguePositions::next(self::RANGES, 'GDN', []), 'A code without a hyphen is its own prefix.');
    }
}
