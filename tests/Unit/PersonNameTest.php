declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Support\PersonName;
use PHPUnit\Framework\TestCase;

final class PersonNameTest extends TestCase
{
    public function testEveryNamePartIsUsedInOrder(): void
    {
        self::assertSame('Ada Marie Lovelace', PersonName::full([
            'first_name' => 'Ada', 'middle_names' => 'Marie', 'last_name' => 'Lovelace',
        ]));
    }

    /** A missing part is left out rather than leaving a double space behind it. */
    public function testAMissingPartLeavesNoGap(): void
    {
        self::assertSame('Ada Lovelace', PersonName::full([
            'first_name' => 'Ada', 'middle_names' => '', 'last_name' => 'Lovelace',
        ]));
        self::assertSame('Lovelace', PersonName::full(['last_name' => 'Lovelace']));
    }

    public function testDisplayNameIsUsedWhenNoPartsAreRecorded(): void
    {
        self::assertSame('Ada', PersonName::full(['display_name' => 'Ada', 'primary_email' => 'a@b.c']));
    }

    /**
     * The address is the last resort, under either name a row carries it by.
     *
     * A profile row joins it as primary_email; a listing row calls it email. This is the case that
     * rendered an empty heading.
     */
    public function testTheAddressIsUsedUnderEitherKey(): void
    {
        self::assertSame('a@b.c', PersonName::full(['primary_email' => 'a@b.c']));
        self::assertSame('a@b.c', PersonName::full(['email' => 'a@b.c']));
        self::assertSame('', PersonName::full([]));
    }
}
