Description:
A person is always addressable on screen, whatever their record holds.

The profile heading rendered empty for an account with no name parts. PersonName fell back to
display_name and then to `email`, and a profile row does not have an `email` key - it joins the
address as `primary_email`, because a person may hold several and only one is primary. Checking one
spelling and not the other produced a heading with nothing in it.

Changelog:
2026/09/08 SAST
- Created after an empty profile heading.
