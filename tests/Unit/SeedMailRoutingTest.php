declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Configuration\RuntimeSettings;
use CattoLearning\Seed\SeedMailRouter;
use PHPUnit\Framework\TestCase;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use SplFileInfo;

final class SeedMailRoutingTest extends TestCase
{
    private const DELIVERY = 'seed.prettythings.co.za';

    private static function router(string $domain = self::DELIVERY): SeedMailRouter
    {
        return new SeedMailRouter($domain);
    }

    /** Generated domains use the reserved TLD, so they can never resolve. */
    public function testGeneratedDomainsUseTheReservedInvalidTld(): void
    {
        $domain = SeedMailRouter::generatedDomain('highveld-mining', 0, '01a029f4');

        self::assertSame('highveld-mining-0-01a029f4.seed.invalid', $domain);
        self::assertStringEndsWith('.invalid', $domain);
        self::assertTrue(SeedMailRouter::isSeedAddress('someone@' . $domain));
    }

    /** A seed address is delivered to the configured inbox, keeping its local part. */
    public function testSeedAddressesAreRedirected(): void
    {
        $router = self::router();
        $stored = 'thabo-nkosi.7.01a029f4@highveld-mining-0-01a029f4.seed.invalid';

        self::assertSame('thabo-nkosi.7.01a029f4@' . self::DELIVERY, $router->deliveryAddress($stored));
    }

    /**
     * A genuine address is never touched.
     *
     * This is the half that matters: a rewrite that fired too widely would divert real mail.
     */
    public function testGenuineAddressesAreNeverRedirected(): void
    {
        $router = self::router();

        foreach ([
            'richard@prettythings.co.za',
            'learner@example.test',
            'someone@seed.prettythings.co.za',
            'someone@invalid.co.za',
            'someone@notseed.invalid.co.za',
        ] as $address) {
            self::assertSame($address, $router->deliveryAddress($address), $address . ' must be delivered unchanged.');
            self::assertFalse(SeedMailRouter::isSeedAddress($address));
        }
    }

    /**
     * With no delivery domain configured, nothing is rewritten.
     *
     * The address then stays on .seed.invalid and simply bounces, which is the safe outcome for
     * an installation that never signs in as a generated identity.
     */
    public function testWithoutConfigurationNothingIsRewritten(): void
    {
        $router = self::router('');
        $stored = 'thabo-nkosi.7.01a029f4@highveld-mining-0-01a029f4.seed.invalid';

        self::assertFalse($router->isConfigured());
        self::assertSame($stored, $router->deliveryAddress($stored));
    }

    /**
     * The property the whole scheme rests on.
     *
     * The rewrite discards the domain, so two identities that differ only by company would land
     * in the same inbox unless the local part is already unique. Generated local parts carry the
     * identity index and the set token suffix precisely so that cannot happen.
     */
    public function testLocalPartsStayUniqueOnceTheDomainIsDiscarded(): void
    {
        $router = self::router();
        $delivered = [];

        // Two sets, several companies each, the same person's name throughout: the worst case.
        foreach (['01a029f4', '02b13a05'] as $setSuffix) {
            for ($company = 0; $company < 5; $company++) {
                for ($person = 0; $person < 20; $person++) {
                    $index = $company * 20 + $person;
                    $address = SeedMailRouter::generatedLocalPart('thabo-nkosi', $index, $setSuffix)
                        . '@' . SeedMailRouter::generatedDomain('acme', $company, $setSuffix);

                    $delivered[] = $router->deliveryAddress($address);
                }
            }
        }

        self::assertCount(200, $delivered);
        self::assertCount(
            200,
            array_unique($delivered),
            'Two generated identities would share one real inbox once the domain is rewritten.'
        );
    }

    /** Malformed input is returned unchanged rather than mangled. */
    public function testMalformedAddressesAreLeftAlone(): void
    {
        $router = self::router();

        foreach (['', 'not-an-address', '@highveld.seed.invalid', 'trailing@'] as $value) {
            self::assertSame($value, $router->deliveryAddress($value));
        }
    }

    /** Case does not change whether an address is recognised as generated. */
    public function testRecognitionIsCaseInsensitive(): void
    {
        self::assertTrue(SeedMailRouter::isSeedAddress('Person@Acme-0-ABC.Seed.Invalid'));
    }

    /**
     * The decorator wraps the interface, so every send path inherits the rewrite.
     *
     * Asserted structurally: a new method on MailerInterface that the decorator forgets would
     * be a send path that quietly bypasses the redirect.
     */
    public function testEveryMailerMethodIsDecorated(): void
    {
        $interface = new \ReflectionClass(\CattoLearning\Infrastructure\Mail\MailerInterface::class);
        $decorator = new \ReflectionClass(\CattoLearning\Infrastructure\Mail\SeedAwareMailer::class);

        foreach ($interface->getMethods() as $method) {
            self::assertTrue(
                $decorator->hasMethod($method->getName()),
                'SeedAwareMailer must implement ' . $method->getName() . '().'
            );
        }

        $source = (string) file_get_contents(dirname(__DIR__, 2) . '/src/Infrastructure/Mail/SeedAwareMailer.php');
        self::assertSame(
            // Every method redirects except sendContactMessage, whose address is the sender.
            count($interface->getMethods()) - 1,
            substr_count($source, '$this->router->deliveryAddress($email)')
        );
    }

    // --- Stage C: the displayed domain and the delivery domain must be one value ----------------

    /**
     * The router is built from RuntimeSettings, not from the environment.
     *
     * Stage C lets an administrator save the SEED System Company domain. If the container went on
     * reading `.env` for the delivery domain, a saved domain would be displayed everywhere and
     * used nowhere - a divergence with no symptom at all until somebody waited for a message that
     * had quietly gone somewhere else. There is no runtime assertion that can catch that, so the
     * wiring itself is the thing under test.
     */
    public function testTheRouterIsBuiltFromRuntimeSettingsRatherThanTheEnvironment(): void
    {
        $source = self::source('src/Application/ContainerFactory.php');

        self::assertStringContainsString(
            'seedSystemCompanyDomain()',
            $source,
            'The container must take the delivery domain from RuntimeSettings.'
        );
        self::assertStringNotContainsString(
            "Env::string('SEED_SYSTEM_COMPANY_DOMAIN')",
            $source,
            'Reading .env here would ignore the administrator override that Stage C introduced.'
        );
    }

    /**
     * RuntimeSettings is the only place in `src/` that reads the seed domain from the environment.
     *
     * A second reader is how the two values drift apart. The migration is excluded deliberately:
     * it runs before `app_options` exists and must read `.env` directly.
     */
    public function testOnlyRuntimeSettingsReadsTheSeedDomainFromTheEnvironment(): void
    {
        $readers = [];
        foreach (self::phpFilesIn(dirname(__DIR__, 2) . '/src') as $file) {
            $source = (string) file_get_contents($file);
            if (str_contains($source, "Env::string('SEED_SYSTEM_COMPANY_DOMAIN'")) {
                $readers[] = basename($file);
            }
        }

        self::assertSame(
            ['RuntimeSettings.php'],
            $readers,
            'Exactly one class may resolve the seed delivery domain, or two of them will disagree.'
        );
    }

    /** Two spellings of one domain must not become two companies. */
    public function testDomainNormalisationCollapsesSpellings(): void
    {
        foreach ([' Seed.Example.CO.ZA ', '.seed.example.co.za', 'SEED.EXAMPLE.CO.ZA'] as $written) {
            self::assertSame(
                'seed.example.co.za',
                RuntimeSettings::normaliseDomain($written),
                'companies.domain is unique platform-wide, so spelling must not create a second row.'
            );
        }

        self::assertSame('', RuntimeSettings::normaliseDomain('   '), 'Blank stays blank: it disables the rewrite.');
    }

    private static function source(string $relative): string
    {
        return (string) file_get_contents(dirname(__DIR__, 2) . '/' . $relative);
    }

    /** @return list<string> */
    private static function phpFilesIn(string $directory): array
    {
        $files = [];
        $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($directory));
        foreach ($iterator as $file) {
            if ($file instanceof SplFileInfo && $file->isFile() && $file->getExtension() === 'php') {
                $files[] = $file->getPathname();
            }
        }
        sort($files);

        return $files;
    }
}
