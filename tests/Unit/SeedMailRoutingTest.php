Tests the seed mail rewrite: which addresses are redirected, which are left alone, and the
uniqueness property the whole scheme depends on.

The redirect exists because companies.domain is globally unique and nobody registers a hundred
domains for test data. The risk it introduces is that collapsing every generated domain onto one
real domain could make two distinct identities share an inbox, so the local part must be unique
on its own. That is asserted here rather than assumed.

