declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\View\Artwork\DrawnAvatar;
use PHPUnit\Framework\TestCase;

final class DrawnAvatarTest extends TestCase
{
    public function testAPersonAlwaysGetsTheSameLoreleiInSunsetFade(): void
    {
        $seed = '0f8e2d4c-1a3b-4c5d-8e9f-001122334455';
        $first = DrawnAvatar::person($seed);
        self::assertSame($first, DrawnAvatar::person($seed), 'The same seed, the same picture.');
        self::assertNotSame($first, DrawnAvatar::person('another-seed'), 'Another seed, another picture.');
        self::assertStringStartsWith('<svg', $first);
        foreach (['ff8a4c', 'b0468c', 'fff1e0'] as $colour) {
            self::assertStringContainsStringIgnoringCase($colour, $first, 'Sunset Fade: ' . $colour);
        }
        self::assertStringContainsString('Lorelei', $first, 'It names its style.');
        self::assertStringContainsString('CC0 1.0', $first, 'And its licence.');
        self::assertSafe($first);
    }

    public function testACompanyGetsAnimatedShapesThatStopForReducedMotion(): void
    {
        $svg = DrawnAvatar::company('7c2e9a10b4d35f68');
        self::assertSame($svg, DrawnAvatar::company('7c2e9a10b4d35f68'));
        self::assertStringContainsString('@keyframes', $svg, 'Animated.');
        self::assertStringContainsString('prefers-reduced-motion', $svg, 'Still for a reader who asks for less motion.');
        self::assertStringContainsString('CC0 1.0', $svg);
        self::assertSafe($svg);
    }

    public function testANewSeedIsRandomAndAVersionFollowsThePicture(): void
    {
        self::assertMatchesRegularExpression('/^[0-9a-f]{16}$/', DrawnAvatar::newSeed(), 'As users.avatar_seed accepts.');
        self::assertNotSame(DrawnAvatar::newSeed(), DrawnAvatar::newSeed());
        self::assertSame(DrawnAvatar::version('person', 'a'), DrawnAvatar::version('person', 'a'));
        self::assertNotSame(DrawnAvatar::version('person', 'a'), DrawnAvatar::version('person', 'b'));
    }

    private static function assertSafe(string $svg): void
    {
        self::assertDoesNotMatchRegularExpression('/<script|\son[a-z]+\s*=|<foreignObject|href\s*=\s*"(?!#)/i', $svg, 'Nothing that runs or loads anything.');
    }
}
