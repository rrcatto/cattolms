declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Course\CourseHtml;
use Dom\HTMLDocument;
use PHPUnit\Framework\TestCase;

final class CourseHtmlTest extends TestCase
{
    /** @return array<string,array{string}> */
    public static function fragments(): array
    {
        return [
            'line breaks, pictures and fields' => ['<p>Casey NO v The Master<br>1992 (4) SA 505 (N)</p><img src="p.png" alt=""><input type="checkbox" checked><hr>'],
            'scripts and styles' => ['<script>if (a < b && c > d) { x = "<br>"; }</script><style>a > b { content: "&"; }</style>'],
            'text, entities and attributes' => ['<p title="a &amp; b &quot;q&quot;">Tom &amp; Jerry &lt;tag&gt; &nbsp;x</p><textarea>a < b</textarea><!-- note -->'],
            'a template' => ['<template><p>t<br></p></template>'],
            'SVG' => ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10" role="img"><defs><linearGradient id="gA" gradientUnits="userSpaceOnUse"><stop offset="0"/></linearGradient></defs><use xlink:href="#gA" xmlns:xlink="http://www.w3.org/1999/xlink"/><foreignObject><p>in<br>svg</p></foreignObject><title>T</title><text>t &lt; 2</text></svg>'],
            'MathML, tables and details' => ['<math><mi>x</mi><mo>&lt;</mo></math><table><tr><td>a<br>b</td></tr></table><details class="block"><summary>S</summary><div>d</div></details>'],
        ];
    }

    #[\PHPUnit\Framework\Attributes\DataProvider('fragments')]
    public function testAFragmentIsWrittenBackAsANormalHtmlParseWritesIt(string $fragment): void
    {
        $html = '<!doctype html><html><body><div id="r">' . $fragment . '</div></body></html>';
        $normal = HTMLDocument::createFromString($html, LIBXML_NOERROR, 'UTF-8');
        $normalRoot = $normal->getElementsByTagName('div')->item(0);
        self::assertNotNull($normalRoot);
        $expected = '';
        foreach ($normalRoot->childNodes as $child) { $expected .= $normal->saveHtml($child); }
        $parsed = HTMLDocument::createFromString($html, \Dom\HTML_NO_DEFAULT_NS | LIBXML_NOERROR, 'UTF-8');
        $root = $parsed->getElementsByTagName('div')->item(0);
        self::assertNotNull($root);
        self::assertSame($expected, CourseHtml::innerHtml($root));
        self::assertDoesNotMatchRegularExpression('#</(br|img|hr|input)>#', CourseHtml::innerHtml($root));
    }
}
