Version: 0.6

Description:
A notice states its point as a leading bold label, never as a bold phrase inside a sentence.

This is a real constraint rather than a style preference. A theme is entitled to render the bold
part of a notice as its heading, and the active one does: Gilded Noir sets `.notice strong` to
`display:block` with a display font. A `strong` in the middle of a sentence then becomes its own
line, and the sentence around it breaks into orphaned fragments - "These are the courses this
company", then "owns", then the rest, with the full stop stranded on a line of its own. Nothing
errors; the page simply reads as broken prose, which is how it was reported.

Core cannot fix that in a theme it does not maintain, and overriding the theme would take the
heading treatment away from the thirteen notices that use it correctly. The markup convention is
the fix: the label comes first, the explanation follows it.

Changelog:
2026/09/07 20:00 SAST
- Created after /company/courses and /company/training rendered their notices as broken sentences.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class NoticeMarkupContractTest extends TestCase
{
    public function testANoticeUsesBoldOnlyAsItsLeadingLabel(): void
    {
        $offenders = [];
        $directory = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator(dirname(__DIR__, 2) . '/resources/views')
        );

        foreach ($directory as $file) {
            if ($file->isDir() || $file->getExtension() !== 'html') continue;
            $markup = (string) file_get_contents($file->getPathname());

            // The body of each notice: the div that follows the icon span.
            if (preg_match_all('/class="notice"(.*?)<\/div>\s*<\/div>/s', $markup, $notices) === 0) continue;

            foreach ($notices[1] as $notice) {
                // Only the text inside the notice's body div matters.
                if (preg_match('/<div[^>]*>(.*)$/s', $notice, $body) !== 1) continue;
                $text = trim($body[1]);
                $boldAt = strpos($text, '<strong>');
                if ($boldAt === false) continue;

                // Bold is the label, so it opens the body. Anything before it is a sentence the
                // theme is entitled to break in half.
                if ($boldAt !== 0) {
                    $offenders[] = $file->getFilename() . ': ' . substr(strip_tags(substr($text, 0, $boldAt)), 0, 60);
                }
            }
        }

        self::assertSame(
            [],
            array_values(array_unique($offenders)),
            'A notice must open with its bold label; a theme may render that bold as a block heading, '
            . 'which breaks any sentence wrapped around it.'
        );
    }
}
