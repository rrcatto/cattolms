        ], 'csrf-example');

        $administration = [];
        foreach ($items as $item) {
            if ((string) $item['key'] === 'administration') $administration = $item;
        }

        $groups = [];
        foreach ((array) ($administration['children'] ?? []) as $child) {
            if ((array) ($child['children'] ?? []) !== []) {
                $groups[(string) $child['key']] = array_column((array) $child['children'], 'key');
            }
        }

        self::assertSame(
            ['admin-group-catalogue', 'admin-group-directory', 'admin-group-commerce', 'admin-group-insights', 'admin-group-system'],
