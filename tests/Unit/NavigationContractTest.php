    /**
     * The third navigation level is a flyout, and it is reachable without a mouse.
     *
     * A menu child may itself hold children, and Factory Reset must render that level rather than
     * flattening it - a theme that ignores it shows twelve Administration sections as one
     * undifferentiated list, which is the problem the grouping exists to solve.
     *
     * The heading is a button rather than a span on purpose, and that is the part worth pinning.
     * The members are display:none until the group is hovered or holds focus, so unless something
     * inside the group can take focus first, Tab can never reach them and the whole level is
     * mouse-only. A span looks identical and renders identically; it just quietly removes keyboard
     * access.
     */
    public function testTheThirdNavigationLevelIsAFlyoutReachableWithoutAMouse(): void
    {
        $nav = (string) file_get_contents(dirname(__DIR__, 2) . '/resources/views/partials/navigation.html.twig');

        self::assertStringContainsString('child.children|length > 0', $nav, 'A menu child may hold children and the theme must render them.');
        self::assertStringContainsString('grandchild.href', $nav);
        // Asserted as a class rather than a whole attribute, for the reason given below about the
