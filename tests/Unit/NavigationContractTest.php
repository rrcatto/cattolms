            ['admin-courses', 'admin-course-categories', 'admin-course-tags', 'admin-requests', 'admin-enrolments'],
            $groups['admin-group-catalogue'],
            'The taxonomy and both enrolment queues belong with the catalogue they classify.'
        );
        self::assertContains('admin-seed', $groups['admin-group-system']);
    }

    /**
     * Every registered Administration section is reachable from the menu.
     *
     * A section belongs to exactly one navigation group, and a section that belongs to none is
     * silently dropped: the grouping loop only ever adds sections a group names, and nothing
     * afterwards notices the ones it did not. Company Enrolments shipped that way - registered,
     * routed, rendering, and absent from every menu on the platform.
     *
     * The reachability test above walks the same menu but checks a fixed list of destinations, so
     * it cannot notice a section the list has not been updated for. This reads the registry.
     */
    public function testEveryRegisteredSectionAppearsInTheAdministrationMenu(): void
    {
        $method = new ReflectionMethod(ThemeRenderer::class, 'navigation');
        $items = $method->invoke($this->renderer(), [
            'active_nav' => 'admin',
            'is_authenticated' => true,
            'is_platform_admin' => true,
            'permissions' => (new PermissionCatalog())->keys(),
        ], 'csrf-example');

        $administration = [];
        foreach ($items as $item) {
            if ((string) $item['key'] === 'administration') $administration = $item;
        }

        $routes = [];
        foreach ((array) ($administration['children'] ?? []) as $child) {
            $routes[] = (string) $child['href'];
            foreach ((array) ($child['children'] ?? []) as $grandchild) {
                $routes[] = (string) $grandchild['href'];
            }
        }

        foreach ((new AdministrationSectionRegistry())->all() as $section) {
            self::assertContains(
                (string) $section['route'],
                $routes,
                'The ' . $section['key'] . ' section is registered but belongs to no navigation group, '
                . 'so it appears in no menu.'
            );
        }
    }

