declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Application\PlatformAdministrationService;
use CattoLearning\Support\ListView;
use CattoLearning\Support\Pagination;
use PHPUnit\Framework\TestCase;

final class ListViewTest extends TestCase
{
    public function testTheAddressWinsThenTheRememberedChoiceThenTheListsDefault(): void
    {
        self::assertSame('list', ListView::chosen('people', [], []), 'Administration opens as a table.');
        self::assertSame('grid', ListView::chosen('catalogue', [], []), 'The catalogue opens as cards.');
        self::assertSame('grid', ListView::chosen('people', [], ['cl_view_people' => 'grid']), 'Remembered.');
        self::assertSame('list', ListView::chosen('people', ['people_view' => 'list'], ['cl_view_people' => 'grid']), 'Asked for now.');
        self::assertSame('list', ListView::chosen('people', ['people_view' => 'tiles'], ['cl_view_people' => '<x>']), 'Nothing else is a view.');
        self::assertSame('list', ListView::chosen('people', ['people_view' => ['grid']], []), 'Nor an array.');
        self::assertSame('list', ListView::chosen('courses', [], ['cl_view_people' => 'grid']), 'Each list remembers its own.');
    }

    public function testAGridPagesInWholeRows(): void
    {
        self::assertSame([30, 60, 90], ListView::pageSizes('people', 'grid'), '5 to a row.');
        self::assertSame([30, 60, 90], ListView::pageSizes('companies', 'grid'));
        self::assertSame([24, 48, 96], ListView::pageSizes('courses', 'grid'), '4 to a row.');
        self::assertSame(Pagination::PAGE_SIZES, ListView::pageSizes('people', 'list'), 'A table keeps the tables\' sizes.');
        // A company's own page shows the courses it provides 4 to a row (owner-approved mockup, 2026-10-27); Mailing's
        // Subscribers 5 to a row, like People (owner, 2026-10-28).
        self::assertSame(['people' => 5, 'companies' => 5, 'company_creators' => 5, 'courses' => 4, 'catalogue' => 4, 'company_people' => 5, 'company_courses' => 4, 'subscribers' => 5], ListView::COLUMNS);
        self::assertSame([30, 60, 90], ListView::pageSizes('subscribers', 'grid'));

        $page = Pagination::within('2', '60', 284, [30, 60, 90]);
        self::assertSame([2, 60, 60], [$page->page, $page->pageSize, $page->offset]);
        self::assertSame(30, Pagination::within(1, '25', 284, [30, 60, 90])->pageSize, 'A table\'s size is not a grid\'s: its first.');
        self::assertSame(30, Pagination::within(1, 'all', 284, [30, 60, 90])->pageSize);
        self::assertSame(10, Pagination::within('99', 30, 284, [30, 60, 90])->page, 'Past the end, the last page.');

        self::assertSame([30, 60, 90], PlatformAdministrationService::listSizes('people', ['people_view' => 'grid']));
        self::assertNull(PlatformAdministrationService::listSizes('people', ['people_view' => 'list']));
        self::assertNull(PlatformAdministrationService::listSizes('people', []), 'Administration\'s default is the table.');
        self::assertNull(PlatformAdministrationService::listSizes('requests', ['requests_view' => 'grid']), 'A list without a grid has none.');
    }

    public function testTheSwitchKeepsTheSearchAndSortAndReturnsToPageOne(): void
    {
        $switch = ListView::switcher('people', 'grid', '/admin/people', ['people_q' => 'Zulu', 'people_sort' => 'name', 'people_dir' => 'desc', 'empty' => '']);
        self::assertSame('grid', $switch['view']);
        self::assertSame(5, $switch['columns']);
        self::assertSame('/admin/people?people_q=Zulu&people_sort=name&people_dir=desc&people_view=list', $switch['list_href']);
        self::assertSame('/admin/people?people_q=Zulu&people_sort=name&people_dir=desc&people_view=grid', $switch['grid_href']);
        self::assertSame('/courses?catalogue_view=list', ListView::switcher('catalogue', 'grid', '/courses', ['catalogue_q' => ''])['list_href']);
    }
}
