declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Support\CompanyLogo;
use PHPUnit\Framework\TestCase;
use RuntimeException;

final class CompanyLogoTest extends TestCase
{
    public function testAnSvgLogoIsCleanedAndKeepsItsColours(): void
    {
        $logo = CompanyLogo::fromUpload('<?xml version="1.0"?><svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10"><!-- made in a design app --><rect width="10" height="10" fill="#c0392b"/></svg>');
        self::assertSame('image/svg+xml', $logo->mimeType);
        self::assertNull($logo->width);
        self::assertStringContainsString('#c0392b', $logo->bytes, 'Its own colour, not the theme\'s.');
        self::assertStringNotContainsString('made in a design app', $logo->bytes, 'Comments are dropped.');
    }

    public function testAnSvgThatCouldRunAnythingIsRefused(): void
    {
        $this->expectException(RuntimeException::class);
        $this->expectExceptionMessageMatches('/picture only/');
        CompanyLogo::fromUpload('<svg xmlns="http://www.w3.org/2000/svg"><script>alert(1)</script></svg>');
    }

    public function testARasterLogoIsFittedUncroppedIntoTheBox(): void
    {
        if (!function_exists('imagecreatetruecolor')) self::markTestSkipped('GD is not installed.');
        $wide = imagecreatetruecolor(1200, 300);
        self::assertNotFalse($wide);
        ob_start();
        imagepng($wide);
        $logo = CompanyLogo::fromUpload((string) ob_get_clean());
        self::assertSame('image/png', $logo->mimeType);
        self::assertSame([512, 128], [$logo->width, $logo->height], 'Fitted, its shape kept.');
        $small = imagecreatetruecolor(40, 20);
        self::assertNotFalse($small);
        ob_start();
        imagepng($small);
        self::assertSame([40, 20], [CompanyLogo::fromUpload((string) ob_get_clean())->width, 20], 'Never enlarged.');
    }

    public function testSomethingThatIsNoPictureIsRefused(): void
    {
        $this->expectException(RuntimeException::class);
        $this->expectExceptionMessage('That file is not an SVG, PNG, JPEG or WebP image.');
        CompanyLogo::fromUpload('%PDF-1.7 not a picture');
    }
}
