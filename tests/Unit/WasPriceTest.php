declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Commerce\Domain\OrderTotals;
use CattoLearning\Support\Money;
use CattoLearning\Support\WasPrice;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class WasPriceTest extends TestCase
{
    public function testAnEmptyWasPriceMeansNoMarkdown(): void
    {
        self::assertNull(WasPrice::fromInput('', 180000));
        self::assertNull(WasPrice::fromInput('  ', 180000));
        self::assertNull(WasPrice::fromInput(null, 180000));
        self::assertSame(['was_label' => null, 'saving_label' => null, 'saving_percent' => null], WasPrice::labels(180000, null, 'ZAR'));
        self::assertSame('', WasPrice::input(null));
    }

    public function testAWasPriceIsTypedAsAnAmountHigherThanThePrice(): void
    {
        self::assertSame(240000, WasPrice::fromInput('2 400', 180000));
        self::assertSame(240050, WasPrice::fromInput('2,400.50', 180000));
        self::assertSame('2400.50', WasPrice::input(240050));
        foreach (['1800', '1799.99'] as $notHigher) {
            try {
                WasPrice::fromInput($notHigher, 180000);
                self::fail($notHigher . ' is not higher than the price.');
            } catch (InvalidArgumentException $refused) {
                self::assertSame('The was price must be higher than the price, or left empty.', $refused->getMessage());
            }
        }
        $this->expectExceptionMessage('Enter the was price as an amount with no more than two decimal places, or leave it empty.');
        WasPrice::fromInput('2400.555', 180000);
    }

    public function testTheSavingIsShownAndItsPercentageRoundedDown(): void
    {
        $labels = WasPrice::labels(180000, 240000, 'ZAR');
        self::assertSame([Money::strictMinorUnits(240000, 'ZAR')->format(), Money::strictMinorUnits(60000, 'ZAR')->format() . ' (25%)', 25],
            [$labels['was_label'], $labels['saving_label'], $labels['saving_percent']]);
        self::assertSame(21, WasPrice::labels(250000, 320000, 'ZAR')['saving_percent'], '21.875% is shown as 21%, never 22%.');
        self::assertSame(Money::strictMinorUnits(50, 'ZAR')->format(), WasPrice::labels(1000000, 1000050, 'ZAR')['saving_label'], 'A saving under 1% shows no percentage.');
        self::assertNull(WasPrice::labels(180000, 180000, 'ZAR')['was_label'], 'A was price that is not higher is never shown.');
    }

    public function testAnAutomaticPromotionsTotalsLineSaysSo(): void
    {
        $rows = OrderTotals::rows(17345, 3469, 13876, 'ZAR', 'SPRING25', '20% off', true);
        self::assertSame('Promo SPRING25 (20% off, applied automatically)', $rows[1]['label']);
        self::assertSame('Promo SAVE10 (10% off)', OrderTotals::rows(17345, 1735, 15610, 'ZAR', 'SAVE10', '10% off')[1]['label']);
        self::assertSame('Promo SPRING25 (20% off, applied automatically)', OrderTotals::forSnapshot(['items' => [['line_total_minor' => 17345]], 'total_minor' => 13876, 'currency' => 'ZAR',
            'promotion' => ['code' => 'SPRING25', 'label' => '20% off', 'discount_minor' => 3469, 'automatic' => true]])[1]['label']);
    }
}
