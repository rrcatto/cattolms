Description:
Every table column declares how much of the table it takes, and the declarations total 100.

The owner's instruction, 2026/09/10, after finding the person column on /admin/people and the
company column on /admin/course/credits too narrow for what they hold: "go and check every single
table in every single page and ensure that the columns allocate space correctly. create a rule."

This is that rule, enforced rather than remembered. A column's share is declared beside its label as
"Label|NN" in the column model, because how much room a column needs is a fact about what it holds,
and the two belong in one place. `PlatformAdministrationService::sortViewFor()` splits them, and
`partials/sortable-header.html.twig` emits the width. Three things can go wrong and all three are
silent in a browser - the table simply looks wrong:

- a column with no share at all, which then takes an equal slice of whatever is left, and drags
  every other column's share away from what it was calculated to be;
- shares totalling less than 100, which leaves the table narrower than its container or hands the
  slack to the browser to distribute as it sees fit;
- shares totalling more than 100, which makes every declared width a lie because the browser scales
  them back proportionally.

The test reads the source rather than a rendered page on purpose. A rendered assertion would prove
one table on one screen; the column models all live in one file, so reading them proves every table
at once, including the ones no test renders.

Architectural boundary: unit. It parses source text and touches nothing else.

Changelog:
2026/09/10 02:25 SAST
- Created on the owner's instruction, as the permanent form of the column-width rule.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class TableColumnWidthContractTest extends TestCase
{
    private const SOURCE = __DIR__ . '/../../src/Application/PlatformAdministrationService.php';

    public function testEveryTableColumnDeclaresAShareAndTheSharesTotalOneHundred(): void
    {
        $tables = self::columnModels();

        // The guard that makes the rest of this test mean anything. A parser that finds nothing
        // passes every assertion below it, so the count is asserted before the shares are.
        self::assertGreaterThanOrEqual(
            18,
            count($tables),
            'No column models were parsed. The declaration shape changed and this test is now examining nothing.'
        );

        foreach ($tables as $line => $columns) {
            $total = 0;
            $undeclared = [];
            foreach ($columns as $key => $label) {
                [, $width] = array_pad(explode('|', $label, 2), 2, '');
                if ($width === '') {
                    $undeclared[] = $key;
                    continue;
                }
                self::assertMatchesRegularExpression(
                    '/^[1-9][0-9]?$|^100$/',
                    $width,
                    'Column "' . $key . '" near line ' . $line . ' states a share that is not a whole percentage.'
                );
                $total += (int) $width;
            }

            self::assertSame(
                [],
                $undeclared,
                'These columns near line ' . $line . ' state no width, so they take an equal slice of whatever '
                . 'is left and every other column on the table gets less than it was given: '
                . implode(', ', $undeclared)
            );

            self::assertSame(
                100,
                $total,
                'The column widths of the table near line ' . $line . ' total ' . $total . ', not 100. '
                . 'Under 100 leaves the table narrow; over 100 makes every declared width a lie, because the '
                . 'browser scales them back proportionally.'
            );
        }
    }

    public function testTheWidestColumnHoldsTheMostText(): void
    {
        // Space is allocated to need. The single widest column on any table must be one that holds
        // free text - a name, a title, a description - and never a count, a date or the action
        // menu, all of which have a known, small maximum size. Sizing them generously is precisely
        // how the person and company columns ended up too narrow.
        $fixed = ['actions', 'status', 'progress', 'created', 'updated', 'started', 'completed',
                  'last_login', 'courses', 'learners', 'people', 'enrolments', 'completion',
                  'available', 'assigned', 'consumed', 'total', 'period', 'ip', 'average'];

        foreach (self::columnModels() as $line => $columns) {
            $widest = '';
            $widestWidth = 0;
            foreach ($columns as $key => $label) {
                [, $width] = array_pad(explode('|', $label, 2), 2, '0');
                if ((int) $width > $widestWidth) {
                    $widestWidth = (int) $width;
                    $widest = $key;
                }
            }

            self::assertNotContains(
                $widest,
                $fixed,
                'On the table near line ' . $line . ' the widest column is "' . $widest . '", which holds a '
                . 'value of known, small size. The widest share belongs to the column holding the most text.'
            );
        }
    }

    public function testEveryHandWrittenTableHeaderRowAlsoTotalsOneHundred(): void
    {
        // Most tables take their widths from the service, but a handful of fixed lists - themes,
        // roles, the company picker - write their header row directly. The rule is the same for
        // them, and reading only the service would have declared those tables correct without
        // looking at them.
        $tables = self::templateHeaderRows();

        self::assertGreaterThanOrEqual(
            3,
            count($tables),
            'No hand-written header rows were parsed. The markup changed and this test is examining nothing.'
        );

        foreach ($tables as $where => $widths) {
            self::assertSame(
                100,
                array_sum($widths),
                'The hand-written column widths in ' . $where . ' total ' . array_sum($widths) . ', not 100.'
            );
        }
    }

    /**
     * Every header row in a template that states widths, keyed by file and the row's line.
     *
     * A header row that states no width at all is left alone: some tables are two fixed columns
     * where the browser's own sizing is right, and forcing a declaration on them would be noise.
     * What is not allowed is a partially declared row, which this reports as a total that misses.
     *
     * @return array<string,list<int>>
     */
    private static function templateHeaderRows(): array
    {
        $rows = [];
        foreach (self::templateFiles() as $file) {
            $source = str_replace("\r\n", "\n", (string) file_get_contents($file));
            preg_match_all('/<thead\b.*?<\/thead>/s', $source, $heads, PREG_OFFSET_CAPTURE);
            foreach ($heads[0] as [$head, $offset]) {
                preg_match_all('/<th\b[^>]*?style="width:(\d+)%"/s', $head, $found);
                if ($found[1] === []) {
                    continue;
                }
                $line = substr_count(substr($source, 0, $offset), "\n") + 1;
                $rows[basename($file) . ':' . $line] = array_map('intval', $found[1]);
            }
        }

        return $rows;
    }

    /** @return list<string> */
    private static function templateFiles(): array
    {
        $files = [];
        $root = __DIR__ . '/../../resources/views';
        $walk = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($root, \FilesystemIterator::SKIP_DOTS));
        foreach ($walk as $entry) {
            if ($entry->isFile() && str_ends_with((string) $entry->getFilename(), '.twig')) {
                $files[] = (string) $entry->getPathname();
            }
        }
        sort($files);

        return $files;
    }

    /**
     * Every column model declared in the service, keyed by the line it starts on.
     *
     * @return array<int,array<string,string>>
     */
    private static function columnModels(): array
    {
        $source = str_replace("\r\n", "\n", (string) file_get_contents(self::SOURCE));

        // An array literal holding no nested brackets and at least one 'Label|NN' entry. The
        // column models are flat maps of key to label, so that shape identifies them exactly.
        preg_match_all('/\[[^\[\]]*?\|\d+\'[^\[\]]*?\]/s', $source, $matches, PREG_OFFSET_CAPTURE);

        $tables = [];
        foreach ($matches[0] as [$literal, $offset]) {
            if (preg_match_all("/'([a-z_]+)'\s*=>\s*'([^']*)'/", $literal, $pairs, PREG_SET_ORDER) === 0) {
                continue;
            }
            $line = substr_count(substr($source, 0, $offset), "\n") + 1;
            $columns = [];
            foreach ($pairs as $pair) {
                $columns[$pair[1]] = $pair[2];
            }
            $tables[$line] = $columns;
        }

        return $tables;
    }
}
