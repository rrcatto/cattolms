/*
Generated by: Claude Code CLI

Date time: 2026/09/09 21:15 SAST

Version: 0.7

Description:
Mail to a domain the platform invented is delivered to the platform's own domain.

Generated identities need addresses that look like addresses, which means inventing domains. Those
domains do not exist, so the address is undeliverable by construction - it ends in `.invalid`, which
RFC 2606 reserves so it can never resolve - and the router rewrites the domain to APP_DOMAIN on the
way out, keeping the local part so the recipient is still recognisable in the inbox.

The half that matters is the half that does nothing: an address the platform did not invent is
returned untouched. Diverting a genuine address would be worse than any bounce, so that is asserted
first and in both directions.

Changelog:
2026/09/09 21:15 SAST
- Replaces SeedMailRoutingTest. Delivery is to APP_DOMAIN; there is no separate seed domain and nothing here refers to seed data.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Infrastructure\Mail\GeneratedDomainRouter;
use PHPUnit\Framework\TestCase;

final class GeneratedDomainRoutingTest extends TestCase
{
    public function testAnInventedDomainCanNeverResolve(): void
    {
        $domain = GeneratedDomainRouter::generatedDomain('highveld-mining', 3, 'a1b2c3d4');

        self::assertStringEndsWith('.invalid', $domain, 'An invented domain must be undeliverable by construction.');
        self::assertStringContainsString('highveld-mining', $domain, 'The company should still be recognisable.');
    }

    public function testAnInventedAddressIsDeliveredToThePlatformDomain(): void
    {
        $router = new GeneratedDomainRouter('catto.test');
        $address = 'jane.doe.7.a1b2c3d4@highveld-mining-3-a1b2c3d4.invalid';

        self::assertSame(
            'jane.doe.7.a1b2c3d4@catto.test',
            $router->deliveryAddress($address),
            'The local part is kept so the recipient is recognisable; only the domain is rewritten.'
        );
    }

    public function testAGenuineAddressIsNeverRewritten(): void
    {
        $router = new GeneratedDomainRouter('catto.test');

        foreach (['someone@example.com', 'admin@catto.test', 'a.person@a-real-company.co.za'] as $address) {
            self::assertSame($address, $router->deliveryAddress($address), $address . ' must be left alone.');
        }
    }

    public function testWithNoDeliveryDomainNothingIsRewritten(): void
    {
        $router = new GeneratedDomainRouter('');

        self::assertFalse($router->isConfigured());
        self::assertSame(
            'jane@company-1-abcd.invalid',
            $router->deliveryAddress('jane@company-1-abcd.invalid'),
            'Without a destination the address is left as it is rather than mangled.'
        );
    }

    public function testOnlyTheInventedSuffixIsRecognised(): void
    {
        self::assertTrue(GeneratedDomainRouter::isGeneratedAddress('x@thing-1-abcd.invalid'));
        self::assertFalse(GeneratedDomainRouter::isGeneratedAddress('x@invalid.example.com'));
        self::assertFalse(GeneratedDomainRouter::isGeneratedAddress(''));
    }
}
