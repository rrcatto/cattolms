    /**
     * The shared control searches as you type, and still works without JavaScript.
     *
     * The debounce, the abort-in-flight and the indicator are declared here rather than written
     * as bespoke JavaScript, so every dataset gets identical behaviour from one place.
     */
    public function testTheSharedSearchControlIsLiveAndDegrades(): void
    {
        $markup = self::source('resources/views/partials/dataset-search.html');

        self::assertStringContainsString('delay:300ms', $markup, 'Typing must not fire a request until the reader pauses.');
        self::assertStringContainsString('input changed', $markup, 'The input event catches typing, pasting and clearing; an unchanged value fires nothing.');
        self::assertStringContainsString('hx-sync="this:replace"', $markup, 'A newer search must abort the one in flight.');
        self::assertStringContainsString('hx-indicator', $markup, 'There must be a visible loading state.');
        self::assertStringContainsString('method="get"', $markup, 'It must work as an ordinary form without JavaScript.');
        self::assertStringContainsString('type="submit"', $markup, 'The no-JavaScript path needs a button.');
        self::assertStringNotContainsString('name="' . 'page', $markup, 'A new search must not carry a page number.');

        // The request attributes must sit on the input, which is the element that produces the
        // events. They were on the form, listening through a from selector, and the result was
        // that nothing happened until the reader pressed Enter - the form's submit was the only
        // trigger that fired. Asserted structurally because no source-level check caught it.
        $input = substr($markup, (int) strpos($markup, '<input type="search"'));
        $input = substr($input, 0, (int) strpos($input, '>') + 1);
        foreach (['hx-get', 'hx-trigger', 'hx-target', 'hx-select', 'hx-include'] as $attribute) {
            self::assertStringContainsString(
                $attribute,
                $input,
                $attribute . ' must be on the search input, not on the surrounding form.'
            );
        }
        self::assertStringContainsString('hx-include="closest form"', $input, 'The rest of the form must travel with the search.');
    }

