    /** The search term is bound, never interpolated. */
    public function testTheSearchTermIsBound(): void
    {
        $repository = self::source('src/Infrastructure/Persistence/AdministrationRepository.php');

        self::assertStringContainsString(':search_term', $repository);
        self::assertSame(
            2,
            substr_count($repository, "addcslashes(\$term, '%_"),
            'The bound value is escaped and built in the two shared builders and nowhere else.'
