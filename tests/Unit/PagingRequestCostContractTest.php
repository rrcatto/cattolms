declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\TestCase;

final class PagingRequestCostContractTest extends TestCase
{
    private static function read(string $relative): string
    {
        $path = dirname(__DIR__, 2) . '/' . $relative;
        self::assertFileExists($path);

        return (string) file_get_contents($path);
    }

    /**
     * The dataset being swapped is read from the header htmx sends, not guessed from the query.
     *
     * A reader who has both a search term and a page number in the URL is indistinguishable by
     * parameter sniffing, and guessing wrong means rebuilding the wrong list - which looks like the
     * page simply not responding.
     */
    public function testTheSwappedDatasetComesFromTheHtmxTargetHeader(): void
    {
        $base = self::read('src/Http/Controller/BaseController.php');

        self::assertStringContainsString('protected function htmxDataset(): ?string', $base);
        self::assertStringContainsString("\$_SERVER['HTTP_HX_TARGET']", $base);
        // The region id convention is what makes the header meaningful, so the pattern is pinned.
        self::assertStringContainsString("'/^([a-z][a-z_]*)-region\$/'", $base);
    }

    /** A swap returns the section body alone, and an ordinary navigation still returns the page. */
    public function testASwapReturnsOnlyTheSectionBody(): void
    {
        $admin = self::read('src/Http/Controller/AdminController.php');

        self::assertStringContainsString('$swapping = $this->htmxDataset();', $admin);
        self::assertStringContainsString('$this->renderFragment(', $admin);
        self::assertMatchesRegularExpression(
            '~preg_replace\(.*?\.html.*?\$definition\[.template.\]\)~',
            $admin,
            'The .html suffix must be stripped as a suffix, not as a set of characters.'
        );
        self::assertStringContainsString("\$this->render('admin-section'", $admin, 'A full navigation must still render the whole page.');

        // rtrim takes a set of characters rather than a suffix, so rtrim('form.html', '.html')
        // also strips the trailing m and asks for a template that does not exist.
        self::assertStringNotContainsString("rtrim(\$definition['template']", $admin);
    }

    /**
     * The universe counts are two COUNT(*) queries per dataset and they cannot change because a
     * reader moved to page 2. The strip that shows them is outside the swapped region.
     */
    public function testTheUniverseCountsAreNotRecomputedForASwap(): void
    {
        $service = self::read('src/Application/PlatformAdministrationService.php');
        $admin = self::read('src/Http/Controller/AdminController.php');

        self::assertStringContainsString('bool $withCounts = true', $service);
        self::assertStringContainsString('foreach ($withCounts ?', $service);
        self::assertStringContainsString('$swapping === null', $admin, 'The counts must be asked for only on a full load.');
    }

    /**
     * Enrolments sits under Requests and Reports holds two reports. Turning the page on one used to
     * run the queries for the other, and nothing on screen changed for it.
     */
    public function testOnlyTheSwappedDatasetIsLoaded(): void
    {
        $service = self::read('src/Application/PlatformAdministrationService.php');

        self::assertStringContainsString('private static function wants(?string $onlyDataset, string $dataset): bool', $service);

        // Only the datasets that still share a screen with something else. Requests and Enrolments
        // were on this list while they shared /admin/enrolments, and Company Enrolments while it
        // shared /admin/reports; each is now its own route, so a swap of one cannot reach the other
        // at all - a stronger guarantee than the guard, and the guard would now be dead code
        // claiming to prevent something that is already impossible. Course performance still shares
        // its screen with the report summary, which is nine aggregates and is not swapped.
        foreach (['course_report'] as $dataset) {
            self::assertStringContainsString(
                "self::wants(\$onlyDataset, '" . $dataset . "')",
                $service,
                'The ' . $dataset . ' table must not be built for a swap of another table.'
            );
        }
        // The report summary is nine aggregate sub-selects and is not swapped either.
        self::assertStringContainsString('$onlyDataset === null', $service);
    }

    /**
     * The restriction may never reach a decision about what the reader is allowed to see.
     *
     * It is derived from a request header, so it is untrusted input. It is legitimate for it to
     * decide how much work to do; it must never appear near a permission, a universe or a scope.
     */
    public function testTheSwapHintNeverInfluencesAuthorisation(): void
    {
        $admin = self::read('src/Http/Controller/AdminController.php');

        $position = strpos($admin, '$swapping = $this->htmxDataset();');
        self::assertIsInt($position);
        $before = substr($admin, 0, $position);

        // Permission and universe are both resolved before the hint is even read.
        self::assertStringContainsString('canAccessAdministrationSection($user, $key)', $before);
        self::assertStringContainsString('$crossUniverse = $this->canSelectUniverse($user);', $before);
    }
}
