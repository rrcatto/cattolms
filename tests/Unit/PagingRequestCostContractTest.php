Description:
Holds the v0.6 rule that turning a page builds the page being turned and nothing else.

A paginated screen replaces one table. Everything else on it - the heading, the navigation, the
data-universe strip and its counts, the report summary, and any second table - is already on the
reader's screen and is not being swapped. Building all of it anyway and then discarding it was, on
the Enrolments screen, roughly six sevenths of what a page turn cost: 465ms of server work to
deliver 78ms of table.

The three rules are asserted separately because each one fails silently and differently. Rebuilding
the whole page is invisible except as slowness. Recounting the universe is invisible except as
slowness. Loading the second table is invisible except as slowness. None of them breaks a page, so
nothing but a check like this notices when one comes back.

What this test does NOT cover is that the numbers stayed correct - that a page turn returns the same
rows a full load would. `PaginationDeterminismIntegrationTest` covers the rows and
`AdministrationUniverseRouteIntegrationTest` covers the sections loading at all.

Changelog:
2026/09/05 10:00 SAST
- Created for the v0.6 efficient paging path.
