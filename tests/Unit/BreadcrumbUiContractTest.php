declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Application\AdministrationSectionRegistry;
use CattoLearning\View\ThemeRenderer;
use PHPUnit\Framework\TestCase;
use ReflectionClass;
use ReflectionMethod;
use ReflectionProperty;

final class BreadcrumbUiContractTest extends TestCase
{
    public function testRouteAwareBreadcrumbsLinkAncestorsAndLeaveCurrentPageUnlinked(): void
    {
        $renderer = (new ReflectionClass(ThemeRenderer::class))->newInstanceWithoutConstructor();
        (new ReflectionProperty(ThemeRenderer::class, 'adminSections'))->setValue($renderer, new AdministrationSectionRegistry());
        $method = new ReflectionMethod(ThemeRenderer::class, 'breadcrumbs');
        $oldUri = $_SERVER['REQUEST_URI'] ?? null;
        $oldGet = $_GET;
        try {
            $_SERVER['REQUEST_URI'] = '/admin/courses/42';
            $_GET = [];
            $crumbs = $method->invoke($renderer, ['active_nav'=>'admin','page_title'=>'Edit course']);
            self::assertSame([
                ['label'=>'Home','href'=>'/','current'=>false],
                ['label'=>'Administration','href'=>'/admin','current'=>false],
                ['label'=>'Courses','href'=>'/admin/courses','current'=>false],
                ['label'=>'Edit course','href'=>'','current'=>true],
            ], $crumbs);

            $_SERVER['REQUEST_URI'] = '/admin/people';
            $people = $method->invoke($renderer, ['active_nav'=>'admin','page_title'=>'People']);
            self::assertSame([
                ['label'=>'Home','href'=>'/','current'=>false],
                ['label'=>'Administration','href'=>'/admin','current'=>false],
                ['label'=>'People','href'=>'','current'=>true],
            ], $people);

            $_SERVER['REQUEST_URI'] = '/';
            $home = $method->invoke($renderer, ['active_nav'=>'home','page_title'=>'Home']);
            self::assertSame([['label'=>'Home','href'=>'','current'=>true]], $home);
        } finally {
            $_GET = $oldGet;
            if ($oldUri === null) unset($_SERVER['REQUEST_URI']); else $_SERVER['REQUEST_URI'] = $oldUri;
        }
    }

