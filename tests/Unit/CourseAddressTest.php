declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Course\CourseAddress;
use CattoLearning\Course\CourseCode;
use InvalidArgumentException;
use PHPUnit\Framework\TestCase;

final class CourseAddressTest extends TestCase
{
    public function testACourseIsNamedByItsCode(): void
    {
        self::assertSame('/admin/courses/GDN-101', CourseAddress::admin('GDN-101'));
        self::assertSame('/admin/courses/GDN-101/content', CourseAddress::admin(['id' => 12, 'code' => 'GDN-101'], '/content'));
        self::assertSame('/admin/courses/GDN-101?tab=pricing', CourseAddress::admin(['course_id' => 12, 'course_code' => 'GDN-101', 'code' => 'BDL-X'], '?tab=pricing'));
        self::assertSame('course-GDN-101', CourseAddress::anchor(['code' => 'GDN-101']));
        self::assertSame('/admin/reports/popularity/GDN-201', CourseAddress::to('popularity', 'GDN-201'));
        self::assertSame('/company/favourites/GDN-201/toggle', CourseAddress::to('favourite', 'GDN-201'));
        self::assertSame('/follow/course/GDN-201', CourseAddress::to('follow', 'GDN-201'));
        self::assertSame('/api/v1/admin/courses/GDN-201', CourseAddress::to('api', 'GDN-201'));
    }

    public function testAnAddressIsNeverMadeFromARowId(): void
    {
        foreach ([['id' => 12], '12', 'gdn-101', ''] as $course) {
            try {
                CourseAddress::admin($course);
                self::fail('A course address was made without a code: ' . json_encode($course));
            } catch (InvalidArgumentException) {
                self::addToAssertionCount(1);
            }
        }
    }

    public function testACodeHoldsALetter(): void
    {
        foreach (['101', '12-34', '2026'] as $digits) self::assertFalse(CourseCode::isValid($digits), $digits . ' looks like a row id.');
        foreach (['GDN-101', 'A1', 'GDN-201', 'C-1A2B3C4D'] as $code) self::assertTrue(CourseCode::isValid($code), $code);
        self::assertMatchesRegularExpression('/[A-Z]/', CourseCode::suggest('101 2026', static fn(string $code): bool => false));
        self::assertMatchesRegularExpression('/[A-Z]/', CourseCode::generated());
    }
}
