            '',
            (string) file_get_contents(dirname(__DIR__, 2) . '/src/View/ThemeRenderer.php')
        );

        self::assertStringNotContainsString('http_response_code', $renderer);
        self::assertStringNotContainsString('$this->f3', $renderer);
    }

