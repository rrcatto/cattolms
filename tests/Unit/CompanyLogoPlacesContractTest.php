declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Application\CompanySectionRegistry;
use PHPUnit\Framework\TestCase;

final class CompanyLogoPlacesContractTest extends TestCase
{
    public function testTheLogoIsWhereTheCompanyIsAndNeverOnBilling(): void
    {
        $views = dirname(__DIR__, 2) . '/resources/views/';
        $read = static fn(string $path): string => (string) file_get_contents($views . $path);
        self::assertStringContainsString('company_context_logo', $read('partials/company-context.html.twig'), 'The band.');
        self::assertStringContainsString('company_logo', $read('partials/company/dashboard.html.twig'), 'The Dashboard.');
        self::assertStringContainsString('company.logo_url', $read('partials/company-picker-results.html.twig'), 'Switch company.');
        self::assertStringContainsString('partials/company-logo-manager.html.twig', $read('partials/company/profile.html.twig'), 'Managed on Company Profile.');
        self::assertStringContainsString('partials/company-logo-manager.html.twig', $read('pages/admin-company.html.twig'), 'And on the company\'s page in Administration.');
        self::assertStringNotContainsString('logo', strtolower($read('partials/company/billing.html.twig')), 'Billing Details holds only billing.');
        self::assertStringNotContainsString('type="file"', $read('partials/admin/company-modals.html.twig'), 'The Edit window sends the logo to the company\'s page.');
        foreach (['partials/admin/companies.html.twig', 'partials/admin/company-creators.html.twig'] as $list) {
            self::assertStringContainsString('<a href="/admin/companies/{{ company.id }}">{{ company.name }}</a>', $read($list), $list . ': the name opens the company\'s page.');
        }
        self::assertSame('profile', (new CompanySectionRegistry())->all()[1]['key'], 'Company Profile comes straight after the Dashboard.');
    }
}
