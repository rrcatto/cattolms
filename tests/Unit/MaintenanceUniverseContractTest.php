declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Seed\SeedTableCatalog;
use PHPUnit\Framework\TestCase;

final class MaintenanceUniverseContractTest extends TestCase
{
    private static function repository(): string
    {
        return (string) file_get_contents(
            dirname(__DIR__, 2) . '/src/Infrastructure/Persistence/MaintenanceRepository.php'
        );
    }

    /** The final table policy the prune workflow is being reconciled against. */
    public function testTheTablesItTouchesCarryTheExpectedPolicy(): void
    {
        self::assertTrue(
            SeedTableCatalog::isSeedAware('auth_sessions'),
            'auth_sessions is seed-aware, so a seed set owns the sessions of its own identities.'
        );
        self::assertFalse(
            SeedTableCatalog::isSeedAware('web_sessions'),
            'web_sessions is ephemeral session infrastructure and is deliberately not seed-aware (decision D3).'
        );
        self::assertFalse(
            SeedTableCatalog::isSeedAware('auth_login_tokens'),
            'auth_login_tokens is not seed-aware; seed cleanup invalidates tokens by user instead.'
        );
    }

    /**
     * The sweep is by cutoff alone.
     *
     * A `seed_token` predicate here would be a scope error whichever way it pointed, so the
     * absence of one is the contract.
     */
    public function testThePruneIsScopedByExpiryRatherThanByUniverse(): void
    {
        $source = self::repository();

        self::assertStringNotContainsString(
            'seed_token',
            $source,
            'The prune must not consult a seed token: expired rubbish is collected in both universes.'
        );
        self::assertStringNotContainsString('DataUniverse', $source);
        self::assertStringNotContainsString('SeedProvenance', $source);

        foreach (['auth_login_tokens', 'auth_sessions', 'web_sessions'] as $table) {
            self::assertMatchesRegularExpression(
                '/DELETE FROM ' . $table . ' WHERE \w+ < :cutoff/',
                $source,
                $table . ' must be pruned on a time cutoff only.'
            );
        }
    }

    /** It deletes expired authentication rows and nothing else. */
    public function testItNeverDeletesABusinessRow(): void
    {
        preg_match_all('/DELETE FROM (\w+)/', self::repository(), $matches);

        self::assertSame(
            ['auth_login_tokens', 'auth_sessions', 'web_sessions'],
            array_values(array_unique($matches[1])),
            'The prune is authentication garbage collection; a business table here would be a scope error.'
        );
    }

    /**
     * The counts are ADMIN-only.
     *
     * The query returns platform-wide totals that include SEED sessions, so disclosure is handled
     * by the section that reaches it rather than by the query: Administration Settings requires
     * SYSTEM.SETTING.VIEW, which no SEED role holds.
     */
    public function testTheCountsAreReachableOnlyThroughAnAdminOnlySection(): void
    {
        $controller = (string) file_get_contents(
            dirname(__DIR__, 2) . '/src/Http/Controller/AdminController.php'
        );

        self::assertStringContainsString("'settings' => 'SYSTEM.SETTING.VIEW',", $controller);
        $guarded = strpos($controller, "in_array('settings', \$sectionKeys, true)");
        $loaded = strpos($controller, "\$data['maintenance'] = \$this->maintenance->pending();");
        self::assertIsInt($guarded, 'The Settings section guard was not found.');
        self::assertIsInt($loaded, 'The pending-counts load was not found.');
        self::assertLessThan(
            $loaded,
            $guarded,
            'The pending counts must be loaded only when the Settings section is in scope.'
        );
        self::assertLessThan($guarded + 200, $loaded, 'The load must sit inside that guard.');
        self::assertStringContainsString("\$this->requirePermission('SYSTEM.DATABASE.PRUNE');", $controller);
    }
}
