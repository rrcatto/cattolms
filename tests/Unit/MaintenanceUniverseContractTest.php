Pins the database-prune workflow as deliberately universe-agnostic.

Expired sessions and spent login links are authentication infrastructure, not business records,
so the sweep collects rubbish from both universes and scopes neither. That is a decision rather
than an omission, and this test exists so it cannot drift silently in either direction: someone
adding a REAL/SEED filter here would leave seed sessions behind for cleanup to trip over, and
someone treating web_sessions as seed-aware would contradict decision D3.

