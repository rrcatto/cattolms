declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\View\ThemePackageValidator;
use PHPUnit\Framework\TestCase;
use RuntimeException;
use ZipArchive;

final class ThemePackageValidatorTest extends TestCase
{
    public function testMinimalThemePackageIsAccepted(): void
    {
        if (!class_exists(ZipArchive::class)) {
            self::markTestSkipped('The PHP zip extension is not installed.');
        }
        $path = $this->makePackage([
            'theme.json' => $this->manifest(),
            'templates/base.html' => '<!doctype html><html><head></head><body>{{ @page_content | raw }}</body></html>',
            'css/style.css' => 'body{margin:0}',
        ]);
        try {
            $result = (new ThemePackageValidator())->inspect($path);
            self::assertSame('Test Theme', $result['summary']['name']);
            self::assertSame(1, $result['summary']['stylesheets']);
        } finally {
            @unlink($path);
        }
    }

    public function testPhpFileIsRejected(): void
    {
        if (!class_exists(ZipArchive::class)) {
            self::markTestSkipped('The PHP zip extension is not installed.');
        }
        $path = $this->makePackage([
            'theme.json' => $this->manifest(),
            'templates/base.html' => '<!doctype html><html><head></head><body>{{ @page_content | raw }}</body></html>',
            'css/style.css' => 'body{margin:0}',
            'evil.php' => '<?php echo getenv("APP_KEY");',
        ]);
        try {
            $this->expectException(RuntimeException::class);
            $this->expectExceptionMessage('Unsupported theme package file type');
            (new ThemePackageValidator())->inspect($path);
        } finally {
            @unlink($path);
        }
    }

    public function testCssGradientsAreAccepted(): void
    {
        if (!class_exists(ZipArchive::class)) {
            self::markTestSkipped('The PHP zip extension is not installed.');
        }
        $path = $this->makePackage([
            'theme.json' => $this->manifest(),
            'templates/base.html' => '<!doctype html><html><head></head><body>{{ @page_content | raw }}</body></html>',
            'css/style.css' => 'body{background:linear-gradient(90deg,#100E09,#D9B44A)}',
        ]);
        try {
            $result = (new ThemePackageValidator())->inspect($path);
            self::assertSame(1, $result['summary']['stylesheets']);
        } finally {
            @unlink($path);
        }
    }

    /** @param array<string,string> $files */
    private function makePackage(array $files): string
    {
        $path = tempnam(sys_get_temp_dir(), 'catto-theme-');
        if ($path === false) {
            self::fail('Unable to create temporary file.');
        }
        @unlink($path);
        $path .= '.zip';
        $zip = new ZipArchive();
        self::assertTrue($zip->open($path, ZipArchive::CREATE | ZipArchive::OVERWRITE) === true);
        foreach ($files as $name => $content) {
            $zip->addFromString($name, $content);
        }
        $zip->close();
        return $path;
    }

    private function manifest(): string
    {
        return json_encode([
            'format' => 'catto-learning-theme',
            'schema_version' => '1.0',
            'theme' => ['name' => 'Test Theme', 'version' => '1.0.0', 'description' => 'Validator test theme.'],
            'templates' => ['base' => 'templates/base.html'],
            'stylesheets' => ['css/style.css'],
            'scripts' => [],
            'assets' => [],
            'external' => ['stylesheets' => [], 'scripts' => []],
        ], JSON_THROW_ON_ERROR);
    }
}
