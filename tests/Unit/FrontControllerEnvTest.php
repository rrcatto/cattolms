The front controller finds the code root from the instance .env before anything else is loaded, so
it cannot use Dotenv and reads APP_CODEBASE_PATH itself. It used parse_ini_file(), which is not a
.env reader: # lines are not comments to it, and a comment containing a bracket - line 66 of the
then .env.example - made the whole file fail, so every request answered "Application dependencies
are missing." although vendor/ was installed.

This proves the reader resolves exactly what phpdotenv resolves, by running both on the same files:
.env.example and the fixtures in tests/Fixtures/env (comments with ( ) [ ] { } ! " | & ~ ^, export,
quotes and Dotenv's escapes, inline comments, duplicates, a multi-line neighbour, a UTF-8 BOM, CRLF
and CR line endings). Values the reader refuses are refused for a stated reason. Each failure is
then requested over HTTP from PHP's built-in server: its own message, HTTP 500, plain text, no
server path in the body, and the detail with paths in the error log.

The reader is defined in public_html/index.php, which returns before handling a request when it
is not the script being run, so the test loads the real file and no other web-reachable file
exists for it.

Architectural boundary: unit. The HTTP cases run the front controller in a separate PHP process.

Changelog:
2026/10/06 SAST
