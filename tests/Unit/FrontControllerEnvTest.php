declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

final class FrontControllerEnvTest extends TestCase
{
    private string $scratch = '';

    protected function setUp(): void
    {
        $this->scratch = sys_get_temp_dir() . '/catto-front-controller-' . bin2hex(random_bytes(6));
        mkdir($this->scratch . '/instance/public_html', 0777, true);
        mkdir($this->scratch . '/code/vendor', 0777, true);
        copy(dirname(__DIR__, 2) . '/public_html/index.php', $this->scratch . '/instance/public_html/index.php');
        file_put_contents($this->scratch . '/code/vendor/autoload.php', "<?php echo 'AUTOLOAD-REACHED'; exit(0);\n");
    }

    protected function tearDown(): void
    {
        foreach (['instance/public_html/index.php', 'instance/.env', 'code/vendor/autoload.php'] as $file) {
            @unlink($this->scratch . '/' . $file);
        }
        foreach (['instance/public_html', 'instance', 'code/vendor', 'code', ''] as $directory) {
            @rmdir(rtrim($this->scratch . '/' . $directory, '/'));
        }
    }

    public function testTheShippedEnvExampleLeadsToTheCodeRoot(): void
    {
        $example = (string) file_get_contents(dirname(__DIR__, 2) . '/.env.example');
        $env = (string) preg_replace('/^APP_CODEBASE_PATH=.*$/m', 'APP_CODEBASE_PATH=' . $this->scratch . '/code', $example, 1, $count);
        self::assertSame(1, $count, '.env.example must define APP_CODEBASE_PATH.');

        self::assertSame('AUTOLOAD-REACHED', $this->serve($env));
    }

    /** @return iterable<string, array{string}> */
    public static function valueForms(): iterable
    {
        yield 'plain' => ['APP_CODEBASE_PATH=%s'];
        yield 'double quoted' => ['APP_CODEBASE_PATH="%s"'];
        yield 'single quoted' => ["APP_CODEBASE_PATH='%s'"];
        yield 'exported' => ['export APP_CODEBASE_PATH=%s'];
        yield 'inline comment' => ['APP_CODEBASE_PATH=%s # the deployed release (current)'];
        yield 'spaces around equals' => ['APP_CODEBASE_PATH = %s'];
    }

    #[DataProvider('valueForms')]
    public function testEveryEnvValueFormLeadsToTheCodeRoot(string $form): void
    {
        $env = "# Instance settings (comments may hold brackets, quotes and !)\n"
            . "APP_NAME=\"Catto Learning\"\n"
            . sprintf($form, $this->scratch . '/code') . "\n"
            . "APP_CODEBASE_PATH=/first/definition/wins\n";

        self::assertSame('AUTOLOAD-REACHED', $this->serve($env));
    }

    public function testAMissingCodeRootStillReportsMissingDependencies(): void
    {
        self::assertSame('Application dependencies are missing.', $this->serve("# no code root here\nAPP_NAME=x\n"));
    }

    private function serve(string $env): string
    {
        file_put_contents($this->scratch . '/instance/.env', $env);
        $command = escapeshellarg(PHP_BINARY) . ' ' . escapeshellarg($this->scratch . '/instance/public_html/index.php') . ' 2>&1';

        return trim((string) shell_exec($command));
    }
}
