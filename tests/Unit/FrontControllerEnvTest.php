The front controller finds the code root from the instance .env before anything else is loaded, so
it cannot use Dotenv and reads APP_CODEBASE_PATH itself. It used parse_ini_file(), which is not a
.env reader: # lines are not comments to it, and a comment containing a bracket - line 66 of the
shipped .env.example - made the whole file fail. The code root came back empty and every request
answered "Application dependencies are missing." although vendor/ was installed and the
deployment was correct.

Each case copies the real public_html/index.php into a scratch instance and runs it in a separate
PHP process against a code root whose vendor/autoload.php only reports that it was reached.

Architectural boundary: unit. It runs the front controller script in isolation; no kernel boots.

Changelog:
2026/10/06 SAST
- Created after a VPS installed from .env.example could not find its code root.
