    }

    public function testAnUnreadableEnvIsReportedAsSuch(): void
    {
        if (function_exists('posix_geteuid') && posix_geteuid() === 0) {
            self::markTestSkipped('root can read any file.');
        }
        file_put_contents($this->scratch . '/instance/.env', "APP_CODEBASE_PATH=/srv\n");
        chmod($this->scratch . '/instance/.env', 0000);
        $response = $this->request();
        self::assertSame(500, $response['status']);
        self::assertSame('The instance configuration file (.env) is missing or unreadable.', $response['body']);
    }

    /** @return array{status:int,body:string,type:string,log:string} */
    private function request(): array
    {
        $port = $this->freePort();
        $log = $this->scratch . '/server.log';
        $server = proc_open(
            [PHP_BINARY, '-S', '127.0.0.1:' . $port, '-t', $this->scratch . '/instance/public_html', $this->scratch . '/instance/public_html/index.php'],
            [0 => ['pipe', 'r'], 1 => ['file', $log, 'a'], 2 => ['file', $log, 'a']],
            $pipes
        );
        self::assertIsResource($server);
        try {
            $body = false;
            $headers = [];
            for ($attempt = 0; $attempt < 50 && $body === false; $attempt++) {
                usleep(100000);
                $body = @file_get_contents('http://127.0.0.1:' . $port . '/', false, stream_context_create(['http' => ['ignore_errors' => true, 'timeout' => 5]]));
                $headers = http_get_last_response_headers() ?? [];
            }
            self::assertNotFalse($body, 'The built-in server answered.');
            preg_match('#^HTTP/\S+ (\d{3})#', (string) ($headers[0] ?? ''), $status);
            $type = '';
            foreach ($headers as $header) {
                if (stripos($header, 'Content-Type:') === 0) $type = trim(substr($header, 13));
            }
            return ['status' => (int) ($status[1] ?? 0), 'body' => trim((string) $body), 'type' => $type, 'log' => (string) @file_get_contents($log)];
        } finally {
            proc_terminate($server);
            proc_close($server);
        }
    }

    private function freePort(): int
    {
        $socket = stream_socket_server('tcp://127.0.0.1:0');
        self::assertIsResource($socket);
        $name = (string) stream_socket_get_name($socket, false);
        fclose($socket);
        return (int) substr($name, strrpos($name, ':') + 1);
    }
