declare(strict_types=1);

namespace CattoLearning\Tests\Unit;

use CattoLearning\Support\Uuid;
use PHPUnit\Framework\TestCase;

final class UuidTest extends TestCase
{
    private const UUID_SHAPE = '/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/';

    public function testV7HasTheCorrectShapeVersionAndVariant(): void
    {
        for ($i = 0; $i < 50; $i++) {
            $uuid = Uuid::v7();

            self::assertMatchesRegularExpression(self::UUID_SHAPE, $uuid);
            self::assertSame('7', $uuid[14], 'The version nibble must be 7.');
            self::assertContains($uuid[19], ['8', '9', 'a', 'b'], 'The variant nibble must be RFC 9562.');
        }
    }

    public function testV4StillHasTheCorrectVersionAndVariant(): void
    {
        for ($i = 0; $i < 50; $i++) {
            $uuid = Uuid::v4();

            self::assertMatchesRegularExpression(self::UUID_SHAPE, $uuid);
            self::assertSame('4', $uuid[14]);
            self::assertContains($uuid[19], ['8', '9', 'a', 'b']);
        }
    }

    public function testV7IsUnique(): void
    {
        $tokens = [];
        for ($i = 0; $i < 500; $i++) {
            $tokens[] = Uuid::v7();
        }

        self::assertCount(500, array_unique($tokens));
    }

    /**
     * The whole point of v7: lexical order follows generation order.
     *
     * Sampled across a real millisecond boundary, because within one millisecond the timestamp
     * is identical and only the random tail differs, which does not sort.
     */
    public function testV7SortsByGenerationTime(): void
    {
        $earlier = Uuid::v7();
        usleep(3000);
        $later = Uuid::v7();

        self::assertLessThan(0, strcmp($earlier, $later), 'A later v7 must sort after an earlier one.');
    }

    /** The leading 48 bits must be the current Unix time in milliseconds. */
    public function testV7EmbedsTheCurrentTimestamp(): void
    {
        $before = (int) (microtime(true) * 1000);
        $uuid = Uuid::v7();
        $after = (int) (microtime(true) * 1000);

        $embedded = hexdec(str_replace('-', '', substr($uuid, 0, 13)));

        self::assertGreaterThanOrEqual($before - 1, $embedded);
        self::assertLessThanOrEqual($after + 1, $embedded);
    }
}
