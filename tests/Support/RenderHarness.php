    /**
     * A private directory for this process's compiled templates, created once per run.
     *
     * The previous fixed path - sys_get_temp_dir() . '/catto-render-smoke/' - was shared and
     * guessable. On Windows the system temp directory is per-user so it never collided; on the
     * Linux VPS it is /tmp, and a directory left there by another account is simply unwritable by
     * the test runner. F3 then wrote nothing and require()d a file that did not exist, which
