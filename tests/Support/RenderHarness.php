     *
     * mkdir() is checked rather than is_dir(), so an existing directory owned by someone else is
     * a failure here instead of a mystery later, and the random component means two users or two
     * concurrent runs cannot collide at all.
     *
     * @throws RuntimeException with a named diagnostic if the directory cannot be prepared
     */
    private static function compileDirectory(): string
    {
        if (self::$compileDirectory !== null) {
            return self::$compileDirectory;
        }

        $base = sys_get_temp_dir();
        if (!is_dir($base) || !is_writable($base)) {
            throw new RuntimeException(
                'RenderHarness cannot prepare compiled templates: the system temporary directory '
                . var_export($base, true) . ' is not writable by this process.'
            );
        }

        $directory = rtrim(strtr($base, '\\', '/'), '/')
            . '/catto-render-' . getmypid() . '-' . bin2hex(random_bytes(6));

        if (!@mkdir($directory, 0700) && !is_dir($directory)) {
            throw new RuntimeException(
                'RenderHarness could not create its compiled-template directory ' . $directory
                . '. This is a temporary-directory problem, not a template defect.'
            );
        }
        if (!is_writable($directory)) {
            throw new RuntimeException(
                'RenderHarness created ' . $directory . ' but cannot write to it. '
                . 'This is a temporary-directory problem, not a template defect.'
            );
        }

        self::$compileDirectory = $directory . '/';
        register_shutdown_function(static function (): void {
            self::removeCompileDirectory();
        });

        return self::$compileDirectory;
    }

    /** Removes this run's compiled templates. Best effort: a failure here must not fail a suite. */
    private static function removeCompileDirectory(): void
    {
        $directory = self::$compileDirectory;
        if ($directory === null || !is_dir($directory)) {
            return;
        }

        foreach (glob($directory . '*') ?: [] as $file) {
            if (is_file($file)) @unlink($file);
        }
        @rmdir($directory);
        self::$compileDirectory = null;
    }

