Version: 0.7

Description:
Every route the platform declares, read from the attributes that declare them.

Replaces the contract tests' habit of scanning App.php for a route table. There is no table: a route
is an attribute on the action it calls, which is the whole reason the table went - a list in one file
and sixteen controllers could drift apart, and an attribute cannot drift from the method it sits on.

Reading the attributes rather than booting the router keeps these tests in the Unit suite, where
they run without a database.

Changelog:
2026/09/10 01:45 SAST
- Created when the Fat-Free route table was replaced by route attributes.
*/

declare(strict_types=1);

namespace CattoLearning\Tests\Support;

final class RouteTable
{
    /**
     * Every declared route.
     *
     * @return list<array{method:string,path:string,name:string,class:string,action:string}>
     */
    public static function all(): array
    {
        $routes = [];
        foreach (self::controllerFiles() as $file) {
            $source = (string) file_get_contents($file);
            $class = self::classOf($source);
            if ($class === null) {
                continue;
            }
            preg_match_all(
                '/(?P<attrs>(?:^[ \t]*#\[Route\([^\n]*\)\]\n)+)[ \t]*public function (?P<action>\w+)\(/m',
                $source,
                $matches,
                PREG_SET_ORDER
            );
            foreach ($matches as $match) {
                preg_match_all(
                    "/#\[Route\('(?P<path>[^']*)'[^\n]*?name: '(?P<name>[^']*)'[^\n]*?methods: \['(?P<method>[A-Z]+)'\]/",
                    $match['attrs'],
                    $each,
                    PREG_SET_ORDER
                );
                foreach ($each as $route) {
                    $routes[] = [
                        'method' => $route['method'],
                        'path' => $route['path'],
                        'name' => $route['name'],
                        'class' => $class,
                        'action' => $match['action'],
                    ];
                }
            }
        }

        return $routes;
    }

    /** Every declared route as "METHOD /path", which is how the old table read. */
    public static function signatures(): string
    {
        return implode("\n", array_map(
            static fn(array $r): string => $r['method'] . ' ' . $r['path'],
            self::all()
        ));
    }

    public static function has(string $method, string $path): bool
    {
        foreach (self::all() as $route) {
            if ($route['method'] === $method && $route['path'] === $path) {
                return true;
            }
        }

        return false;
    }

    /** @return list<string> */
    private static function controllerFiles(): array
    {
        $root = dirname(__DIR__, 2) . '/src/Http';
        $found = [];
        $directory = new \RecursiveDirectoryIterator($root);
        /** @var \SplFileInfo $file */
        foreach (new \RecursiveIteratorIterator($directory) as $file) {
            if ($file->isFile() && str_ends_with($file->getFilename(), 'Controller.php')) {
                $found[] = $file->getPathname();
            }
        }
        sort($found);

        return $found;
    }

    private static function classOf(string $source): ?string
    {
        if (preg_match('/^namespace ([^;]+);/m', $source, $ns) !== 1) {
            return null;
        }
        if (preg_match('/^(?:final )?class (\w+)/m', $source, $cls) !== 1) {
            return null;
        }

        return $ns[1] . '\\' . $cls[1];
    }
}
