declare(strict_types=1);

namespace CattoLearning\Tests\Support;

use CattoLearning\Auth\SouthAfricanIdNumber;
use CattoLearning\Configuration\SecretCipher;
use CattoLearning\Infrastructure\Persistence\Database;
use DateTimeImmutable;

final class CheckIdNumbers
{
    /** A valid ID number for that date of birth that no account holds yet, as a person types it on the Register page. */
    public static function free(Database $db, string $birthdate = '1990-05-12'): string
    {
        for ($try = 0; $try < 50; $try++) {
            $digits = SouthAfricanIdNumber::make(new DateTimeImmutable($birthdate), random_int(0, 9999));
            $fingerprint = SouthAfricanIdNumber::fromInput($digits, new DateTimeImmutable())->fingerprint();
            if ($db->fetchOne('SELECT 1 FROM users WHERE id_number_hash = :h', ['h' => $fingerprint]) === false) return $digits;
        }

        throw new \RuntimeException('No free ID number for ' . $birthdate . '.');
    }

    /** Gives the person a valid ID number for their date of birth, one no other account holds. */
    public static function give(Database $db, int $userId, string $birthdate = '1990-05-12'): string
    {
        $born = new DateTimeImmutable($birthdate);
        for ($try = 0; $try < 50; $try++) {
            $digits = SouthAfricanIdNumber::make($born, random_int(0, 9999), random_int(0, 9) > 0);
            $fingerprint = SouthAfricanIdNumber::fromInput($digits, new DateTimeImmutable())->fingerprint();
            if ($db->fetchOne('SELECT 1 FROM users WHERE id_number_hash = :h', ['h' => $fingerprint]) !== false) continue;
            $db->executeStatement(
                "UPDATE users SET id_number_encrypted = :e, id_number_hash = :h, birthdate = CAST(:b AS DATE), residence_country = 'ZA' WHERE id = :id",
                ['e' => (new SecretCipher())->encrypt($digits), 'h' => $fingerprint, 'b' => $birthdate, 'id' => $userId]
            );

            return $digits;
        }

        throw new \RuntimeException('No free ID number for ' . $birthdate . '.');
    }
}
