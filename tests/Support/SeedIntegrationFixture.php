Fixture support for the Seed Database integration tests.

Two things make seed integration tests different from the rest of the Integration suite, and both
are handled here.

First, a test needs rows on *both* sides of the universe boundary to prove anything about it, and
a SEED row cannot simply be inserted the way DevelopmentFixture inserts a REAL one - it has to
carry a token, and every row it references has to be in the same universe or PostgreSQL rejects
it. createSeedSet() builds a small coherent SEED graph by hand for exactly that reason: it is
independent of SeedGenerator, so a generation defect cannot quietly make an isolation test pass.

