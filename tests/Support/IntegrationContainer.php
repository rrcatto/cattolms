declare(strict_types=1);

namespace CattoLearning\Tests\Support;

use CattoLearning\Application\CliBootstrap;
use CattoLearning\Infrastructure\Persistence\Database;
use DI\Container;

final class IntegrationContainer
{
    private static ?Container $container = null;

    /** The one container this process uses for Integration tests. */
    public static function get(): Container
    {
        if (self::$container === null) {
            /** @var Container $container */
            $container = CliBootstrap::boot()['container'];
            self::$container = $container;
        }

        return self::$container;
    }

    /** The one database connection, resolved from that container. */
    public static function db(): Database
    {
        /** @var Database $db */
        $db = self::get()->get(Database::class);

        return $db;
    }

    /**
     * Releases the container so the next call builds a fresh one.
     *
     * Not used by ordinary tests. It exists so a test that needs to prove something about
     * construction can reset the shared state rather than quietly leaving a second container
     * behind for everything after it.
     */
    public static function reset(): void
    {
        self::$container = null;
    }
}
