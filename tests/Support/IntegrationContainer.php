    FATAL: remaining connection slots are reserved for roles with the SUPERUSER attribute

`CliBootstrap::boot()` builds a fresh PHP-DI container each time it is called, and
`ConnectionFactory` gives that container a fresh connection - so a fresh PDO connection. Most
Integration tests call it from `setUp()`, which runs once per *test method* rather than once per
class. Counted against the current suite that is roughly 93 connections per run, against a default
`max_connections` of 100, and PHPUnit holds every test object alive for the duration so nothing is
released along the way.

Memoising the container bounds the suite to one connection. That is the correct shape regardless of
the limit: these tests all talk to the same development database, and building 93 identical
containers proves nothing that building one does not.

Deliberately test-only. Production builds one container per request and disposes of it with the
request, which was never the problem.

A test that genuinely needs an isolated container - one verifying container construction itself -
should keep calling `CliBootstrap::boot()` directly. This helper is for the majority that simply
want to talk to the database.

