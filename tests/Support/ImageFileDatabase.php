    public function fetchAssociative(string $sql, array $params = []): array|false
    {
        $path = $this->files[(string) ($params['sha'] ?? '')] ?? null;
        if ($path === null) {
            return false;
        }
        [$width, $height] = (array) getimagesize($path);
        return ['sha256' => $params['sha'], 'mime_type' => 'image/png', 'width' => $width, 'height' => $height,
            'byte_size' => filesize($path), 'encoded' => base64_encode((string) file_get_contents($path))];
    }

