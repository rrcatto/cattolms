        return $keys;
    }

    /** @return array<string,list<array{0:string,1:string}>> each table, and the rows of other tables that belong to its rows: [child table, column] */
    private function links(): array
    {
        $links = [];
        foreach ($this->db->fetchAllAssociative(
            "SELECT c.confrelid::regclass::text AS parent, c.conrelid::regclass::text AS child, a.attname AS col, c.confdeltype AS rule
             FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
             WHERE c.contype = 'f' AND array_length(c.conkey, 1) = 1 AND c.connamespace = 'public'::regnamespace"
        ) as $row) {
            $column = (string) $row['col'];
            if (in_array($column, self::POINTERS, true)) continue;
            if (in_array($row['child'] . '.' . $column, self::ACTS, true)) {
                $links[(string) $row['parent']][] = [(string) $row['child'], $column];
                continue;
            }
            // Who last touched a row (updated_by, approved_by, decided_by, recorded_by, an actor) never makes it the check's:
            // a check's administrator who saved one of the owner's courses must not take that course with them.
            if (preg_match('/_by(_user_id)?$|^actor_user_id$/', $column) === 1 && !in_array($column, ['created_by_user_id', 'created_by', 'requested_by_user_id'], true)) continue;
            // c cascade, r restrict, a no action: the row cannot outlive its parent. n set null: only ownership columns.
            if (!in_array($row['rule'], ['c', 'r', 'a'], true) && !in_array($column, self::OWNERSHIP, true)) continue;
            $links[(string) $row['parent']][] = [(string) $row['child'], $column];
        }

        return $links;
    }
}
