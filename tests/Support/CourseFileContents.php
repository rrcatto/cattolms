declare(strict_types=1);

namespace CattoLearning\Tests\Support;

final class CourseFileContents
{
    /** A slide's fields that are not words: its id, look and the buttons a site gives it. */
    private const NOT_WORDS = ['id', 'layout', 'tone', 'theme', 'answer', 'ordered', 'build', 'actions', 'picture', 'kind', 'youtube_id', 'presentation_role', 'duration_seconds', 'public_id', 'content_type', 'slide_id'];

    /** How the site stores a module's outcomes: the file heads them "Learning outcomes". */
    private const OUTCOMES_LEAD = 'In this module you will learn to:';

    /**
     * @param array<string,mixed> $package
     * @return list<string> each piece of the site's words the file lacks, with where it is on the site
     */
    public static function missing(array $package, string $html): array
    {
        $file = self::fileText($html);
        $missing = [];
        foreach (self::siteWords($package) as [$where, $words]) {
            foreach (self::pieces($words) as $piece) {
                if ($piece === self::OUTCOMES_LEAD) { continue; }
                if (!str_contains($file, self::squeezed($piece))) { $missing[] = $where . ': ' . mb_substr($piece, 0, 90); }
            }
        }
        return $missing;
    }

    /**
     * How many pieces of text the course holds, all of which missing() looks for.
     *
     * @param array<string,mixed> $package
     */
    public static function count(array $package): int
    {
        $count = 0;
        foreach (self::siteWords($package) as [, $words]) { $count += count(self::pieces($words)); }
        return $count;
    }

    /**
     * @param array<string,mixed> $package
     * @return list<array{0:string,1:string}>
     */
    private static function siteWords(array $package): array
    {
        $course = (array) ($package['course'] ?? []);
        $words = [];
        foreach (['title', 'subtitle', 'summary', 'introduction_html'] as $field) { $words[] = ['course ' . $field, str_replace('[grading-scale]', ' ', (string) ($course[$field] ?? ''))]; }
        // Where the introduction shows a scale. One that shows none has the standard grades, as a new import gives it.
        if (str_contains((string) ($course['introduction_html'] ?? ''), '[grading-scale]')) {
            foreach ((array) ($package['grade_bands'] ?? []) as $band) { $words[] = ['grade', (string) ($band['grade_label'] ?? '')]; }
        }
        foreach ((array) ($package['structure'] ?? []) as $row) {
            if (($row['node_type'] ?? '') === 'section') {
                $words[] = ['section title', (string) ($row['title'] ?? '')];
                $words[] = ['section "' . ($row['title'] ?? '') . '"', (string) ($row['introduction_html'] ?? '')];
            }
        }
        foreach ((array) ($package['course_items'] ?? []) as $item) {
            $where = (string) ($item['item_type'] ?? 'item') . ' "' . ($item['title'] ?? '') . '"';
            // An assessment's title is the name an import makes for it from its module, and a review's text is called the
            // Review Study Aid inside its section: neither shows anywhere but Course Content.
            $title = (string) ($item['title'] ?? '');
            if (!(($item['item_type'] ?? '') === 'assessment' && str_ends_with($title, ' assessment')) && $title !== 'Review Study Aid') { $words[] = [$where . ' title', $title]; }
            $words[] = [$where, (string) ($item['content_source'] ?? '')];
            self::collect((array) ($item['type_config'] ?? []), $where, $words);
            foreach ((array) ($item['questions'] ?? []) as $question) {
                $words[] = [$where . ' question', (string) ($question['question_html'] ?? '')];
                $words[] = [$where . ' explanation', (string) ($question['explanation_html'] ?? '')];
                foreach ((array) ($question['options'] ?? []) as $option) { $words[] = [$where . ' option', (string) ($option['option_html'] ?? '')]; }
            }
        }
        return $words;
    }

    /**
     * @param array<array-key,mixed> $values
     * @param list<array{0:string,1:string}> $words
     */
    private static function collect(array $values, string $where, array &$words): void
    {
        foreach ($values as $key => $value) {
            if (is_string($key) && in_array($key, self::NOT_WORDS, true)) { continue; }
            if (is_array($value)) { self::collect($value, $where, $words); }
            elseif (is_string($value)) { $words[] = [$where . (is_string($key) ? ' ' . $key : ''), $value]; }
        }
    }

    /**
     * The words between a value's tags, without its drawings' code.
     *
     * @return list<string>
     */
    private static function pieces(string $value): array
    {
        $value = (string) preg_replace('/<(style|script)\b.*?<\/\1>/si', ' ', $value);
        $pieces = [];
        foreach (preg_split('/<[^>]+>/', $value) ?: [] as $piece) {
            $piece = trim(html_entity_decode($piece, ENT_QUOTES | ENT_HTML5, 'UTF-8'));
            if ($piece !== '' && preg_match('/[\p{L}\p{N}]/u', $piece) === 1) { $pieces[] = $piece; }
        }
        return $pieces;
    }

    /** The file's page and the data it plays, as one run of text. */
    private static function fileText(string $html): string
    {
        $text = '';
        foreach (['QUIZ', 'REVIEW', 'PRESENTATIONS', 'FLASHCARDS'] as $name) {
            $start = strpos($html, 'const ' . $name . ' = ');
            if ($start === false) { continue; }
            $start += strlen('const ' . $name . ' = ');
            $end = str_starts_with(substr($html, $start, 3), '{};') ? $start + 2 : strpos($html, "\n};", $start);
            if ($end === false) { continue; }
            $decoded = json_decode(str_replace('<\/', '</', substr($html, $start, $end - $start + ($end === $start + 2 ? 0 : 2))), true);
            if (is_array($decoded)) { array_walk_recursive($decoded, static function (mixed $value) use (&$text): void { if (is_string($value)) { $text .= ' ' . self::words($value); } }); }
        }
        $page = (string) preg_replace('/<(style|script)\b.*?<\/\1>/si', ' ', $html);
        // A video's title is on its player.
        preg_match_all('/<iframe\b[^>]*\btitle="([^"]*)"/i', $page, $players);
        return self::squeezed(self::words($page) . ' ' . $text . ' ' . html_entity_decode(implode(' ', $players[1]), ENT_QUOTES | ENT_HTML5, 'UTF-8'));
    }

    private static function words(string $value): string
    {
        return html_entity_decode(implode(' ', preg_split('/<[^>]+>/', (string) preg_replace('/<(style|script)\b.*?<\/\1>/si', ' ', $value)) ?: []), ENT_QUOTES | ENT_HTML5, 'UTF-8');
    }

    private static function squeezed(string $text): string
    {
        return mb_strtolower((string) preg_replace('/[\s\x{00A0}\x{202F}]+/u', '', $text));
    }
}
