    public function rollBack(): void
    {
    }

    /** @param array<string,mixed> $params */
    private function record(string $sql, array $params): void
    {
        $this->statements[] = $sql;
        $this->bindings[] = $params;
    }

    /** Every statement recorded so far, as one string to assert against. */
    public function sql(): string
    {
        return implode(' ', $this->statements);
    }

    /**
     * Every binding value recorded so far.
     *
     * @return list<mixed>
     */
    public function boundValues(): array
    {
        $values = [];
        foreach ($this->bindings as $set) {
            foreach ($set as $value) {
                $values[] = $value;
            }
        }

        return $values;
    }

    /**
     * A repository of the given class wired to this recorder instead of a database.
     *
     * Constructed without its constructor because the collaborators it would otherwise require
     * are irrelevant to the SQL it builds.
     */
    public function inject(string $repositoryClass): object
    {
        return self::injectInto($repositoryClass, $this);
    }

    /**
     * Builds a repository with a recorder in place of its database.
     *
     * @return array{0:object,1:RecordingDatabase} The repository and its recorder.
     */
    public static function forRepository(string $repositoryClass): array
    {
        $recorder = new RecordingDatabase();

        return [self::injectInto($repositoryClass, $recorder), $recorder];
    }

    private static function injectInto(string $repositoryClass, object $recorder): object
    {
        $reflection = new ReflectionClass($repositoryClass);
        $repository = $reflection->newInstanceWithoutConstructor();

        foreach ($reflection->getProperties() as $property) {
            if ($property->getName() === 'db') {
                $property->setValue($repository, $recorder);
            }
        }

        return $repository;
    }
}
